#!/bin/bash
# 启动系统工程平台 HTTP 能力网关（对外核心底座）。
# 用法: ./MCP工具箱/启动能力网关.sh [端口] [地址]
# 默认端口 8866（能力搜索/契约），执行统一走运行核心 40007 /网关/调用。
set -euo pipefail
cd "$(dirname "$0")/.."
端口="${1:-8866}"
地址="${2:-127.0.0.1}"
mkdir -p 工程缓存
日志="工程缓存/能力网关_${端口}.log"
echo "启动 HTTP 能力网关: http://${地址}:${端口}"
echo "接口: GET /能力/搜索  GET /能力/契约/{能力id}（执行统一走 40007 /网关/调用）"
echo "日志: ${日志}"
exec python3.14 -m MCP工具箱.能力网关 --端口 "${端口}" --地址 "${地址}"
