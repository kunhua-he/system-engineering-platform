"""写入通道：多会话同仓开发时，改文件必须经此唯一入口并带「预期文件摘要」乐观锁。

直接改盘没有任何互斥保护：B 会话基于更早读到的旧内容去改，就把 A 的改动盖掉了。
本模块把写盘收敛到底座原子能力 `文件系统支持库.文本补丁.应用精确替换`：

- 精确替换、唯一匹配校验、摘要比对、临时文件 + os.replace 原子写、差异统计，
  全部由该能力负责，本模块**不重写**；
- 写前先查活跃文件租约：该文件被**别的开工id**占着就拒绝，不许硬闯（回到文件租约机制）；
- 「预期文件摘要」对不上磁盘当前内容即由能力拒绝，失败带上磁盘当前摘要供调用方重读。

不新增第二套机制：摘要算法与写盘都在底座能力里，本模块只做路径归一化、租约核对和结果整形。
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

错误_参数 = "参数无效"
错误_越界 = "路径越界"
错误_文件被占 = "FILE_LEASE_CONFLICT"
错误_文件不存在 = "文件不存在"

能力id_应用精确替换 = "文件系统支持库.文本补丁.应用精确替换"


def 解析仓库内路径(项目根: Path, 文件路径: Any) -> Path:
    """仓库相对路径 → 绝对路径；绝对路径也只允许落在项目根内，越界即拒绝。"""
    文本 = str(文件路径 or "").strip()
    if not 文本:
        raise ValueError("文件路径不能为空")
    根 = Path(项目根).resolve()
    候选 = Path(文本).expanduser()
    目标 = (候选 if 候选.is_absolute() else 根 / 候选).resolve()
    try:
        目标.relative_to(根)
    except ValueError as 错误:
        raise ValueError(f"路径越界：{文本} 不在项目根 {根} 内") from 错误
    return 目标


def _仓库相对路径(项目根: Path, 目标: Path) -> str:
    try:
        return 目标.relative_to(Path(项目根).resolve()).as_posix()
    except ValueError:
        return 目标.name


def _活跃占用人(存储目录: Path, 相对路径: str) -> dict[str, Any] | None:
    """查该文件当前的活跃租约持有者；没有就返回 None。"""
    from .文件租约 import 查询文件占用

    for 项 in 查询文件占用(存储目录, [相对路径]).get("占用", []):
        if str(项.get("文件路径", "")) == 相对路径:
            return 项
    return None


def 应用文件补丁(
    项目根: Path, 存储目录: Path, *,
    文件路径: Any, 旧文本: str, 新文本: str,
    预期文件摘要: str = "", 预期旧文本摘要: str = "",
    起始行: Any = None, 结束行: Any = None,
    写入: bool = True, 开工id: str = "",
) -> dict[str, Any]:
    """经底座能力应用一次精确替换；写前核对文件租约与「预期文件摘要」。

    返回 {成功, 错误码, 说明, 文件路径, 值, 详情, 证据链}。成功时 `值` 为底座能力
    的结果字典（含 差异/新文件摘要/行号）；失败时 `详情` 尽量带上磁盘当前摘要。
    """
    try:
        目标 = 解析仓库内路径(项目根, 文件路径)
    except ValueError as 错误:
        return {"成功": False, "错误码": 错误_越界, "说明": str(错误)}
    if not 目标.is_file():
        return {"成功": False, "错误码": 错误_文件不存在,
                "说明": f"文件不存在: {目标}", "文件路径": str(目标)}

    相对路径 = _仓库相对路径(项目根, 目标)
    if 写入:
        占用 = _活跃占用人(存储目录, 相对路径)
        if 占用:
            所有者 = str(占用.get("所有者", ""))
            if 所有者 and 所有者 != str(开工id or ""):
                return {
                    "成功": False, "错误码": 错误_文件被占, "文件路径": 相对路径,
                    "占用者": 所有者, "占用开始时间": 占用.get("心跳"),
                    "说明": f"{相对路径} 正被另一开工id占着，不许硬闯；换文件或等释放后再写",
                }

    from 开发工具.开发入口 import 真实调用能力

    调用 = 真实调用能力(
        能力id_应用精确替换,
        {
            "文件路径": str(目标), "旧文本": 旧文本, "新文本": 新文本,
            "根目录": str(Path(项目根).resolve()),
            "起始行": 起始行, "结束行": 结束行,
            "预期旧文本摘要": str(预期旧文本摘要 or ""),
            "预期文件摘要": str(预期文件摘要 or ""),
            "写入": bool(写入),
        },
        用户id=str(开工id or ""),
    )
    return {
        "成功": bool(调用.get("成功")),
        "错误码": str(调用.get("错误码", "")),
        "说明": str(调用.get("说明", "")),
        "文件路径": 相对路径,
        "值": 调用.get("值"),
        "详情": 调用.get("详情"),
        "证据链": 调用.get("证据链"),
    }
