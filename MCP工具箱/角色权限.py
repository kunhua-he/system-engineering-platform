class 越权拒绝(PermissionError):
    """越权阻断：携带明确错误码（权限不足 / 角色越权 / 未知角色 / 伪造令牌 / 越界路径），不静默放行。"""

    def __init__(self, 错误码: str, 消息: str) -> None:
        self.错误码 = 错误码
        self.消息 = 消息
        super().__init__(f"{错误码}: {消息}")

