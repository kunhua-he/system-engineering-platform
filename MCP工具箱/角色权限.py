_令牌异常字符 = re.compile(r"[\x00-\x20\x7f;|&<>`$'\"()]")
_令牌最大长度 = 16


def 校验角色令牌(令牌: str) -> None:
    """角色令牌必须精确匹配允许角色；空白/控制字符/注入字符/超长/未知值一律拒绝，不清洗、不默认放行。"""
    if not isinstance(令牌, str) or not 令牌:
        raise 越权拒绝("伪造令牌", "角色令牌缺失或不是字符串")
    if len(令牌) > _令牌最大长度:
        raise 越权拒绝("伪造令牌", f"角色令牌超长: {令牌[:6]}…")
    if _令牌异常字符.search(令牌):
        raise 越权拒绝("伪造令牌", "角色令牌包含空白、控制或注入字符")
    if 令牌 not in 允许角色:
        raise 越权拒绝("未知角色", f"未知 MCP 角色: {令牌}")


def 读取当前角色(令牌: str | None = None) -> str:
    """从进程配置读取角色；未知角色名与伪造令牌拒绝启动，不静默放行。

    环境变量未配置时保持历史默认（.mcp.json 的 8 个实例均显式配置角色，
    缺失只出现在测试/裸跑场景）；显式传入的令牌一律严格校验。
    """
    值 = 令牌 if 令牌 is not None else os.environ.get("SYSTEM_ENGINEERING_MCP_ROLE")
    if 值 is None or 值 == "":
        return 平台维护者
    校验角色令牌(值)
    return 值


def 可用工具(角色: str) -> set[str]:
    if 角色 not in 允许角色:
        return set()
    return set(角色工具表[角色])


def 门面分类(角色: str) -> str:
    """返回角色所属五类核心门面名称；专项角色返回其自身名；未知角色拒绝。"""
    for 门面名, 角色集 in 五类核心门面.items():
        if 角色 in 角色集:
            return 门面名
    if 角色 in 允许角色:
        return 角色
    raise 越权拒绝("未知角色", f"未知 MCP 角色: {角色}")


def 代码地图范围(角色: str) -> list[str]:
    """返回角色允许检索源码的目录副本；调用者没有源码范围，未知角色为空。"""
    if 角色 not in 允许角色:
        return []
    return list(角色边界表.get(角色, {}).get("允许目录", []))


def 校验工具权限(角色: str, 工具名: str) -> None:
    if 工具名 not in 可用工具(角色):
        raise 越权拒绝("权限不足", f"角色 {角色} 无权调用工具: {工具名}")


def _规范相对路径(路径: str) -> str:
    """统一斜杠并消解 . / ..；绝对路径、盘符、越过仓库根的穿越一律拒绝。"""
    文本 = str(路径).replace("\\", "/")
    if 文本.startswith("/") or (len(文本) >= 2 and 文本[1] == ":"):
        raise 越权拒绝("越界路径", f"绝对路径不允许: {路径}")
    规范 = posixpath.normpath(文本)
    if 规范 in {"", ".", ".."} or 规范.startswith("../"):
        raise 越权拒绝("越界路径", f"路径越出仓库根: {路径}")
    return 规范


def 校验修改路径(角色: str, 修改路径: list[str]) -> None:
    """修改路径必须落在角色允许目录内，防止借规划工具探测范围外代码。"""
    范围表 = [_规范相对路径(项) for 项 in 代码地图范围(角色)]
    for 路径 in 修改路径:
        规范路径 = _规范相对路径(路径)
        if not any(
            规范路径 == 范围 or 规范路径.startswith(f"{范围}/")
            for 范围 in 范围表
        ):
            raise 越权拒绝("角色越权", f"角色 {角色} 无权访问修改路径: {路径}")


def 允许测试范围(角色: str) -> list[str]:
    """角色允许运行的测试文件前缀；未配置测试目录的角色返回空表。"""
    范围表 = 代码地图范围(角色)
    if "测试中心" in 范围表:
        return ["测试中心"]
    return [范围 for 范围 in 范围表 if 范围.startswith("测试中心/")]


def _在范围内(路径: str, 范围表: list[str]) -> bool:
    try:
        规范路径 = _规范相对路径(路径)
    except 越权拒绝:
        return False
    return any(
        规范路径 == 范围 or 规范路径.startswith(f"{范围}/")
        for 范围 in 范围表
    )


def _提取测试文件(命令: list[str]) -> list[str]:
    """解析 --测试文件 后面的全部值（遇下一个选项或结束停止）。"""
    文件表: list[str] = []
    for 序号, 项 in enumerate(命令):
        if 项 != "--测试文件":
            continue
        for 值 in 命令[序号 + 1:]:
            if 值.startswith("--"):
                break
            文件表.append(值)
    return 文件表


def 获取角色指南(角色: str) -> dict[str, object]:
    步骤 = 角色指南表.get(角色)
    if 步骤 is None:
        raise 越权拒绝("角色越权", f"角色 {角色} 没有开发或维护指南")
    return {
        "角色": 角色, "步骤": 步骤,
        "允许目录": 代码地图范围(角色),
        "完成标准": "对应范围验证退出码为0，边界审计无违规，并提交结构化证据。",
    }


def _校验编译路径(角色: str, 文件表: list[str]) -> None:
    """py_compile 的文件参数必须落在角色允许目录内，防止借编译探测范围外源码。"""
    范围表 = [_规范相对路径(项) for 项 in 代码地图范围(角色)]
    for 文件 in 文件表:
        规范文件 = _规范相对路径(文件)  # 绝对路径/出根穿越直接抛 越界路径
        if not any(
            规范文件 == 范围 or 规范文件.startswith(f"{范围}/")
            for 范围 in 范围表
        ):
            raise 越权拒绝("角色越权", f"角色 {角色} 无权编译文件: {文件}")


def 校验验证命令(角色: str, 命令: list[str]) -> None:
    """验证工具只运行角色范围内的固定门禁入口，禁止退化成通用命令执行器。"""
    if 命令 == ["git", "diff", "--check"]:
        return
    if 命令[:2] == ["codegraph", "status"]:
        return
    if not 命令 or 命令[0] not in {"python3.14", "python3"}:
        raise 越权拒绝("权限不足", "验证命令只允许 Python、git diff --check 或 codegraph status")
    if "-c" in 命令:
        raise 越权拒绝("权限不足", "验证命令禁止 python -c")
    if 命令[1:3] == ["-m", "py_compile"]:
        if len(命令) < 4:
            raise 越权拒绝("权限不足", "py_compile 必须指定文件")
        _校验编译路径(角色, 命令[3:])
        return
    if len(命令) < 2:
        raise 越权拒绝("权限不足", "验证命令缺少固定入口")
    入口 = _规范相对路径(命令[1])
    if 入口.startswith("测试中心/"):
        测试范围表 = 允许测试范围(角色)
        if not 测试范围表:
            raise 越权拒绝("权限不足", f"角色 {角色} 不允许运行测试入口: {入口}")
        测试文件表 = _提取测试文件(命令)
        if 测试文件表:
            for 测试文件 in 测试文件表:
                if not _在范围内(测试文件, 测试范围表):
                    raise 越权拒绝("角色越权", f"角色 {角色} 无权运行测试文件: {测试文件}")
            return
        if "测试中心" in 测试范围表:
            return
        raise 越权拒绝("权限不足", f"角色 {角色} 必须用 --测试文件 限定测试范围: {入口}")
    if 入口 == "开发工具/发布门禁/运行发布门禁.py" and 角色 in {平台维护者, 发布者}:
        return
    raise 越权拒绝("权限不足", f"角色 {角色} 不允许执行验证入口: {入口}")


def 角色说明(角色: str) -> dict[str, object]:
    if 角色 not in 允许角色:
        raise 越权拒绝("未知角色", f"未知 MCP 角色: {角色}")
    校验工具权限(角色, "role_profile")
    边界 = 角色边界表.get(角色)
    if 边界 is None:
        raise 越权拒绝("未知角色", f"未知 MCP 角色: {角色}")
    return {
        "角色": 角色,
        "可用工具": sorted(可用工具(角色)),
        **边界,
        "权限模式": "服务端工具白名单",
        "边界": "调用者只能读取公开能力契约；开发角色仍须受目录边界和发布门禁约束。",
    }
