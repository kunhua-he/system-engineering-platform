"""OCR 模块包级中文入口。"""

from __future__ import annotations

from 模块库.OCR.实现.OCR import 可用性检查
from 模块库.OCR.实现.OCR import 识别图片文件
from 模块库.OCR.实现.OCR import 识别图片文字

__all__ = [
    "识别图片文字",
    "识别图片文件",
    "可用性检查",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("OCR.识别图片文字", 识别图片文字,
         ["图片路径", "图片字节", "语言", "词级数据", "超时秒", "取消事件", "输出上限字节"],
         "识别图片文字：路径/字节二选一，返回文本或词级数据"),
        ("OCR.识别图片文件", 识别图片文件,
         ["图片路径", "语言", "词级数据", "超时秒", "取消事件", "输出上限字节"],
         "按图片文件路径识别文字"),
        ("OCR.可用性检查", 可用性检查,
         ["超时秒"], "探测 tesseract 版本与语言包可用性"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.OCR",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明=说明,
            )
        )
