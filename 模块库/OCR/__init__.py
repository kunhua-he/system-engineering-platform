def _校验参数名序(参数契约表: dict[str, list[dict]],
                  注册参数名序: dict[str, list[str]]) -> None:
    """装配期闸门：注册参数名序必须逐字等于契约名序，否则本包装配失败。

    为什么要有它：注册处一旦漏一个参数（或顺序写反），网关的必填校验就与契约分叉
    ——那正是本包 2026-09-18 被修掉的缺陷形态。宁可装配期就 raise，也不静默漏参。
    """
    for 能力id, 契约参数 in 参数契约表.items():
        注册名序 = 注册参数名序.get(能力id)
        if 注册名序 is None:
            raise ValueError(f"能力 {能力id} 有契约但注册处未声明参数名序")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(注册名序):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(注册名序)} 与契约参数名序 {契约名序} "
                "不一致：参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），"
                "入口不得另立一份")


