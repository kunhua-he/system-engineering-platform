"""OCR 模块（基础模块）：只持能力 id 与契约版本，经 HTTP连接器调用统一网关。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
连接器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。

能力：
- 识别图片文字：图片路径/图片字节 二选一入口，输出 文本 或 词级数据；
- 识别图片文件：按图片文件路径识别文字，输出 文本 或 词级数据；
- 可用性检查：真实探测 tesseract 版本与语言包。
取消令牌id：文本语义（空字符串表示不取消；模块只透传令牌id，
支持库侧不传 callable 取消回调）。
支持库契约里的 取消事件 是 资源引用型（进程内 threading.Event）：JSON 表达不了
资源引用，所以本条 HTTP 调用路径**不发这个键**（省略即契约默认值 null＝不取消）。
错误码由支持库统一结构透传：参数不合法/文件不存在/工具缺失/语言包
缺失/识别失败/进程崩溃/超时/取消/超出限制/命令失败/版本不兼容/提供者不可用。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "OCR"
默认语言 = "eng"
识别图片能力id = "OCR识别支持库.OCR识别.识别图片"
语言包列表能力id = "OCR识别支持库.OCR识别.语言包列表"
版本探针能力id = "OCR识别支持库.OCR识别.版本探针"

_连接器 = None


def 设置HTTP连接器(连接器) -> None:
    """由项目适配层装配连接器；主要用于启动装配与隔离测试。"""
    global _连接器
    _连接器 = 连接器


def _获取连接器():
    return _连接器


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经 HTTP 连接器按能力 id 调用统一网关；失败统一转为 结果。"""
    try:
        连接器 = _获取连接器()
        if 连接器 is None:
            return 结果.失败(失败错误码, "HTTP 连接器未装配", 来源=来源)
        响应 = 连接器.调用能力(能力id, 参数)
        if isinstance(响应, 结果):
            return 响应
        if not isinstance(响应, dict):
            return 结果.失败("返回结果不符合契约", "网关返回不是对象", 来源=来源)
        if 响应.get("成功"):
            return 结果.成功结果(响应.get("值"))
        return 结果.失败(响应.get("错误码") or 失败错误码, 响应.get("错误说明") or "网关调用失败", 来源=来源)
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源=来源)
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源=来源)


def _识别请求(图片路径: str | None, 图片字节: bytes | None, 语言: str,
              词级数据: bool, 超时秒: float, 取消令牌id: str,
              输出上限字节: int | None, 命令路径: str) -> dict:
    """装配支持库识别请求：取消令牌id 语义下支持库侧不传 callable。

    网关按契约严格校验显式参数类型（文本型/双精度数型 拒绝 None）；值为 None 的
    可选参数剔除后由支持库取契约默认值。

    **取消事件 连键都不能出现**：契约里它的类型是 资源引用型（provider 侧收
    threading.Event），JSON 表达不了资源引用，显式 null 会被网关判「类型不符」
    （网关 fail-closed 类型校验：省略即不取消，写 null 就是错）。所以这里既不发
    None，也不发任何值——省略该键让契约默认值 null 生效，就是 取消令牌id 文本
    语义下的正确形态。
    """
    请求 = {
        "图片路径": 图片路径,
        "图片字节": 图片字节,
        "语言": 语言,
        "词级数据": 词级数据,
        "超时秒": 超时秒,
        "输出上限字节": 输出上限字节,
        "命令路径": 命令路径 or None,
    }
    return {键: 值 for 键, 值 in 请求.items() if 值 is not None}


def 识别图片文字(
    图片路径: str | None = None,
    图片字节: bytes | None = None,
    语言: str = 默认语言,
    词级数据: bool = False,
    超时秒: float = 60.0,
    取消令牌id: str = "",
    输出上限字节: int | None = None,
    命令路径: str = "",
) -> 结果:
    """识别图片文字：图片路径与图片字节二选一，返回 {文本} 或 词级数据 {词列表}。"""
    if (图片路径 is None) == (图片字节 is None):
        return 结果.失败("参数不合法", "图片路径与图片字节必须且只能提供一个", 来源=来源)
    return _调用支持库(识别图片能力id, _识别请求(
        图片路径, 图片字节, 语言, 词级数据, 超时秒, 取消令牌id, 输出上限字节, 命令路径))


def 识别图片文件(
    图片路径: str,
    语言: str = 默认语言,
    词级数据: bool = False,
    超时秒: float = 60.0,
    取消令牌id: str = "",
    输出上限字节: int | None = None,
    命令路径: str = "",
) -> 结果:
    """按图片文件路径识别文字：返回 {文本} 或 词级数据 {词列表}。"""
    if not isinstance(图片路径, str) or not 图片路径.strip():
        return 结果.失败("参数不合法", "图片路径必须为非空文本", 来源=来源)
    return _调用支持库(识别图片能力id, _识别请求(
        图片路径, None, 语言, 词级数据, 超时秒, 取消令牌id, 输出上限字节, 命令路径))


def 可用性检查(超时秒: float = 10.0, 命令路径: str = "") -> 结果:
    """可用性检查：真实探测 tesseract 版本与语言包。

    返回 {tesseract, 版本, 满足最低版本, 语言列表, 数据目录, 语言数量}；
    任一步失败如实透传（如 工具缺失）。
    """
    版本参数 = {"超时秒": 超时秒, "命令路径": 命令路径 or None}
    版本结果 = _调用支持库(版本探针能力id, {键: 值 for 键, 值 in 版本参数.items() if 值 is not None})
    if not 版本结果.成功:
        return 版本结果
    语言参数 = {"超时秒": 超时秒, "命令路径": 命令路径 or None}
    语言结果 = _调用支持库(语言包列表能力id, {键: 值 for 键, 值 in 语言参数.items() if 值 is not None})
    if not 语言结果.成功:
        return 语言结果
    return 结果.成功结果({
        "tesseract": 版本结果.值.get("tesseract"),
        "版本": 版本结果.值.get("版本"),
        "满足最低版本": 版本结果.值.get("满足最低版本"),
        "语言列表": 语言结果.值.get("语言列表"),
        "数据目录": 语言结果.值.get("数据目录"),
        "语言数量": 语言结果.值.get("数量"),
    })
