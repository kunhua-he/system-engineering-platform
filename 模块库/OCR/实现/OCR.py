"""OCR 模块（基础模块）：只经 获取能力调用器().调用能力 组合支持库公开能力。

调用边界：实现不得 import 支持库/提供者/第三方/运行核心；能力经
公共契约.能力契约.调用器.获取能力调用器 注入的唯一能力调用服务调用。
能力：
- 识别图片文字：图片路径/图片字节 二选一入口，输出 文本 或 词级数据；
- 识别图片文件：按图片文件路径识别文字，输出 文本 或 词级数据；
- 可用性检查：真实探测 tesseract 版本与语言包。
取消令牌id：文本语义（空字符串表示不取消；模块只透传令牌id，
支持库侧不传 callable 取消回调）。
错误码由支持库统一结构透传：参数不合法/文件不存在/工具缺失/语言包
缺失/识别失败/进程崩溃/超时/取消/超出限制/命令失败/版本不兼容/提供者不可用。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "OCR"
默认语言 = "eng"
识别图片能力id = "OCR识别.识别图片"
语言包列表能力id = "OCR识别.语言包列表"
版本探针能力id = "OCR识别.版本探针"


def _调用(能力id: str, 请求参数: dict) -> 结果:
    """经唯一能力调用服务调用支持库能力；调用器未装配时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器

    try:
        return 获取能力调用器().调用能力(能力id, 请求参数, 调用方=来源)
    except RuntimeError as 错误:
        return 结果.失败("提供者不可用", str(错误), 来源=来源)


def _识别请求(图片路径: str | None, 图片字节: bytes | None, 语言: str,
              词级数据: bool, 超时秒: float, 取消令牌id: str,
              输出上限字节: int | None, 命令路径: str) -> dict:
    """装配支持库识别请求：取消令牌id 语义下支持库侧不传 callable。"""
    return {
        "图片路径": 图片路径,
        "图片字节": 图片字节,
        "语言": 语言,
        "词级数据": 词级数据,
        "超时秒": 超时秒,
        "取消事件": None,  # 取消令牌id 语义：支持库侧不传 callable
        "输出上限字节": 输出上限字节,
        "命令路径": 命令路径 or None,
    }


def 识别图片文字(
    图片路径: str | None = None,
    图片字节: bytes | None = None,
    语言: str = 默认语言,
    词级数据: bool = False,
    超时秒: float = 60.0,
    取消令牌id: str = "",
    输出上限字节: int | None = None,
    命令路径: str = "",
) -> 结果:
    """识别图片文字：图片路径与图片字节二选一，返回 {文本} 或 词级数据 {词列表}。"""
    if (图片路径 is None) == (图片字节 is None):
        return 结果.失败("参数不合法", "图片路径与图片字节必须且只能提供一个", 来源=来源)
    return _调用(识别图片能力id, _识别请求(
        图片路径, 图片字节, 语言, 词级数据, 超时秒, 取消令牌id, 输出上限字节, 命令路径))


def 识别图片文件(
    图片路径: str,
    语言: str = 默认语言,
    词级数据: bool = False,
    超时秒: float = 60.0,
    取消令牌id: str = "",
    输出上限字节: int | None = None,
    命令路径: str = "",
) -> 结果:
    """按图片文件路径识别文字：返回 {文本} 或 词级数据 {词列表}。"""
    if not isinstance(图片路径, str) or not 图片路径.strip():
        return 结果.失败("参数不合法", "图片路径必须为非空文本", 来源=来源)
    return _调用(识别图片能力id, _识别请求(
        图片路径, None, 语言, 词级数据, 超时秒, 取消令牌id, 输出上限字节, 命令路径))


def 可用性检查(超时秒: float = 10.0, 命令路径: str = "") -> 结果:
    """可用性检查：真实探测 tesseract 版本与语言包。

    返回 {tesseract, 版本, 满足最低版本, 语言列表, 数据目录, 语言数量}；
    任一步失败如实透传（如 工具缺失）。
    """
    版本结果 = _调用(版本探针能力id, {"超时秒": 超时秒, "命令路径": 命令路径 or None})
    if not 版本结果.成功:
        return 版本结果
    语言结果 = _调用(语言包列表能力id, {"超时秒": 超时秒, "命令路径": 命令路径 or None})
    if not 语言结果.成功:
        return 语言结果
    return 结果.成功结果({
        "tesseract": 版本结果.值.get("tesseract"),
        "版本": 版本结果.值.get("版本"),
        "满足最低版本": 版本结果.值.get("满足最低版本"),
        "语言列表": 语言结果.值.get("语言列表"),
        "数据目录": 语言结果.值.get("数据目录"),
        "语言数量": 语言结果.值.get("数量"),
    })
