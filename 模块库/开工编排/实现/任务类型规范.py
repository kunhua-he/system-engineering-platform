"""任务类型规范：把「本次任务」文本映射到任务类型，取出该类强规范（只读投影）。

## 为什么需要它（华哥 2026-09-18：底座内部解决，Hermes 只是接入方）
开发规范此前靠**主代理记性**注入子代理的任务信 —— 实测夜间连派 6 路全部漏注入
（挂在任务记忆包上的通用开工纪律一次都没到达）。⇒ 规范注入不该依赖某个接入方的记性，
应由底座统一提供：任何 Agent（Hermes / 其他）调同一个入口即得同一份规范。

## 它怎么做（省 token 的关键）
- 只返回**命中的那几类**（默认上限 3 类），不返回全量规范；
- 匹配用**双字滑窗子串**（与 `查开工上下文` 同口径），纯 SQLite/字符串运算，
  **不调大模型、不做向量检索**；
- 未命中时如实返回空 + 提示去补字典，不捏造规范。

## 边界
零 I/O、零副作用（读字典文件除外）：不改库、不写文件、不推进任何状态机。
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

#: 字典文件相对项目根的路径（唯一数据源；改规范只改数据，不改代码）。
字典相对路径 = "开发文档/规范/任务类型规范.json"

#: 单类强规范返回上限：只回命中的几类，不把全量规范塞回去（省 token 的硬约束）。
默认返回类数 = 3


def 切词(文本: str) -> list[str]:
    """双字滑窗切词（与 `查开工上下文` 同口径）。

    为什么不用整句：整句会成为一个超长关键词，子串匹配必然 0 命中；
    也不分词库（那会引入第三方依赖与不一致口径）。
    """
    词表: list[str] = []
    净 = "".join(字 for 字 in str(文本 or "") if 字.strip())
    步 = 2
    for 起点 in range(0, max(0, len(净) - 步 + 1)):
        词表.append(净[起点:起点 + 步])
    return 词表


def _读字典(项目根: Path) -> tuple[dict[str, Any], str]:
    """读字典文件；返回（数据, 错误说明）。错误说明为空串表示成功。"""
    目标 = 项目根 / 字典相对路径
    if not 目标.is_file():
        return {}, f"任务类型字典不存在：{字典相对路径}（请先补该文件再取强规范）"
    try:
        数据 = json.loads(目标.read_text(encoding="utf-8"))
    except (OSError, ValueError) as 错误:
        return {}, f"任务类型字典不可读（{类型名(错误)}：{错误}）"
    if not isinstance(数据, dict):
        return {}, "任务类型字典不可读（顶层必须是 JSON 对象）"
    return 数据, ""


def 类型名(异常: BaseException) -> str:
    """异常类名（用于中文错误说明里标注来源，不吞异常语义）。"""
    return type(异常).__name__


def _打分(条目: dict[str, Any], 任务文本: str, 词表: set[str]) -> tuple[float, list[str]]:
    """按识别词命中情况打分。

    ★ 匹配方向（实测踩过）：必须是「识别词出现在本次任务文本里」，**不能反过来**
    用「任务文本的片段出现在识别词里」——后者会误命中（实测「修一个报错：门禁又红了」
    因文本片段「一个」出现在识别词「做一个能力」里而误命中「加新能力」）。
    两条判据：
    ① 识别词是任务文本的完整子串 → 最强信号（+20 与词长）；
    ② 否则取「识别词的双字片段」与「任务文本的双字片段」求交集，**交集 ≥ 2 才算命中**
       （只交 1 个片段太弱：任何含「能力」的任务都会命中所有含「能力」的识别词）。
    """
    命中词: list[str] = []
    分 = 0.0
    for 词 in (条目.get("识别词") or []):
        文本 = str(词 or "")
        if not 文本:
            continue
        if 文本 in 任务文本:
            命中词.append(文本)
            分 += 20.0 + len(文本)
            continue
        片段 = set(切词(文本))
        交集 = 片段 & 词表
        if len(片段) >= 2 and len(交集) >= 2:
            命中词.append(文本)
            分 += 10.0 * len(交集)
    return 分, 命中词


def 取任务类型规范(项目根: str, 本次任务: str, *,
                   返回类数: int = 默认返回类数) -> tuple[list[dict[str, Any]], str, bool]:
    """取「本次任务」命中的任务类型与强规范。

    返回 ``(命中列表, 错误说明, 是否截断)``：
    - 命中列表每项：``{任务类型, 强规范, 判据, 原文位置, 命中词, 相关度}``，
      按相关度降序、类型名升序稳定排序；
    - 错误说明为空串表示成功；字典缺失/损坏时明确给说明（**不静默返回空数组冒充「无规范」**）；
    - 是否截断：命中类数超过 ``返回类数`` 时为真（如实上报，不悄悄丢）。
    """
    上限 = 返回类数 if isinstance(返回类数, int) and 返回类数 > 0 else 默认返回类数
    路径 = Path(str(项目根 or "")).expanduser()
    数据, 错误 = _读字典(路径)
    if 错误:
        return [], 错误, False

    词表 = set(切词(本次任务))
    if not 词表:
        return [], "本次任务 为空，无法判定任务类型（请给一句「我正要做什么」）", False
    任务文本 = "".join(字 for 字 in str(本次任务 or "") if 字.strip())

    命中: list[dict[str, Any]] = []
    for 条目 in (数据.get("任务类型清单") or []):
        if not isinstance(条目, dict):
            continue
        分, 命中词 = _打分(条目, 任务文本, 词表)
        if 分 <= 0:
            continue
        命中.append({
            "任务类型": str(条目.get("任务类型") or ""),
            "强规范": list(条目.get("强规范") or []),
            "判据": str(条目.get("判据") or ""),
            "原文位置": str(条目.get("原文位置") or ""),
            "命中词": 命中词,
            "相关度": 分,
        })
    if not 命中:
        return [], "", False

    命中.sort(key=lambda 项: (-项["相关度"], 项["任务类型"]))
    截断 = len(命中) > 上限
    return 命中[:上限], "", 截断
