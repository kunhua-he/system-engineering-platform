"""开工编排 · 绑定文件认知（进程内纯函数，不对外暴露）。

## 为什么有这件东西（华哥 2026-09-22 裁决）

华哥原话：

> 「其次就是开工 ID 的那个，返回的内容，只要绑定的文件，就**后台顺手把它里面的一些传参、
> 自己有的函数等的，内容直接加入进去**。不需要说是要手动探索，被动的从代码地图也好，
> 或者其他的地方也好，抽出字段等内容，**最小化的让开工 id 返回的时候，知道这次的事项**，
> 而不是固定提示词，**固定提示词本质上就是缺陷**。」

**改前是什么样**：`开工准备` 的返回里，与「本次要改的文件」有关的内容只有路径清单
（`路径校验.通过清单`）与「下一步」里那句**对谁都一样**的
「用代码地图定位符号与调用链」。也就是说：开工返回的是**通用的、跟本次任务无关的**
劝告；至于「这个文件里到底有哪些函数、它们收什么参数」——得调用方自己再摸一轮。

**为什么那是缺陷（不是「不够贴心」）**：固定提示词对每份文件说一样的话，
价值恒等于零；而它占的 token 是恒定的。更糟的是它**看起来像已经告诉你了**，
于是调用方跳过探索直接动手 —— 实测教训：不摸清参数形状就写契约，反复踩
「超时秒传 12.0 报参数不合法」「命令表写成字典」这类坑。

**改后是什么样**：本模块把绑定文件的**真实符号与参数签名**抽出来随开工返回。
每一条都是现场从 `代码地图` 读的**事实**，文件不同则内容不同 —— 替换掉那句
对谁都一样的固定提示词。

## 数据来源只有一条腿

符号与签名一律经 `代码解析支持库.代码地图.查询节点`（唯一腿，不另建检索实现，
哲学 1.2/1.3）。地图不可用时**如实报「未抽取」并说明原因**，
绝不回落成一段固定文案（那就又回到了「固定提示词」）。

## 最小化（华哥原话「最小化的」）

不把整个文件的符号表搬回来。两道上限：`每文件条数` 与 `总条数`，
超出即截断并**如实标 `已截断`**；参数只留名字与类型标注，不留默认值以外的正文。
"""

from __future__ import annotations

from typing import Any, Callable

from 公共契约.基础类型.逻辑类型 import 真, 假

#: 只抽这四类节点：类、函数、方法、模块级变量。
#: `import`/`file` 节点对「知道这次要改什么」没有信息增量，不收。
关注节点种类 = ("class", "function", "method", "variable")

每文件条数默认 = 12
总条数默认 = 120

#: 不当成「参数」的形参名（方法第一个形参，不是调用方要传的东西）。
_隐式形参 = frozenset({"self", "cls"})


def _拆顶层逗号(文本: str) -> list[str]:
    """按**顶层**逗号切分（括号/引号内的逗号不算）—— 抽参数签名用。

    不引第三方、不用 ast：签名在这里是**文本**（来自代码地图的 `签名` 列），
    不是 Python 对象，只能做文本拆分。拆分失败只会少抽几个参数，不影响开工。
    """
    段表: list[str] = []
    缓冲: list[str] = []
    深度 = 0
    引号 = ""
    for 字符 in 文本:
        if 引号:
            缓冲.append(字符)
            if 字符 == 引号:
                引号 = ""
            continue
        if 字符 in "\"'":
            引号 = 字符
            缓冲.append(字符)
            continue
        if 字符 in "([{":
            深度 += 1
        elif 字符 in ")]}":
            深度 -= 1
        if 字符 == "," and 深度 == 0:
            段表.append("".join(缓冲))
            缓冲 = []
            continue
        缓冲.append(字符)
    if 缓冲:
        段表.append("".join(缓冲))
    return [段.strip() for 段 in 段表 if 段.strip()]


def 抽参数(签名: Any) -> list[dict[str, str]]:
    """从函数/方法签名文本里抽形参（名字 + 类型标注 + 默认值）。

    输入形如 `"(任务: str | None = None, 项目根: str | None = None) -> 结果"`，
    输出 `[{"参数名": "任务", "类型标注": "str | None", "默认值": "None"}, ...]`。

    抽不出来（签名空 / 没有括号 / 只有 self）一律返回空列表 ——
    **不猜、不造**。抽不出来本身也是有用的信息（说明该节点没有参数面）。
    """
    文本 = str(签名 or "").strip()
    if not 文本 or "(" not in 文本:
        return []
    起始 = 文本.index("(")
    深度 = 0
    结束 = -1
    for 下标 in range(起始, len(文本)):
        if 文本[下标] == "(":
            深度 += 1
        elif 文本[下标] == ")":
            深度 -= 1
            if 深度 == 0:
                结束 = 下标
                break
    if 结束 < 0:
        return []
    内层 = 文本[起始 + 1:结束].strip()
    if not 内层:
        return []
    参数表: list[dict[str, str]] = []
    for 段 in _拆顶层逗号(内层):
        去星 = 段.lstrip("*").strip()
        if not 去星 or 去星 in _隐式形参:
            continue
        默认值 = ""
        if "=" in 去星:
            左, _, 右 = 去星.partition("=")
            去星, 默认值 = 左.strip(), 右.strip()
        名字, 标注 = 去星, ""
        if ":" in 去星:
            名字, _, 标注 = 去星.partition(":")
            名字, 标注 = 名字.strip(), 标注.strip()
        if not 名字:
            continue
        参数表.append({"参数名": 名字, "类型标注": 标注, "默认值": 默认值})
    return 参数表


def _归一节点(节点: dict) -> dict[str, Any]:
    """把代码地图的一条节点压成开工返回需要的最小形状（**最小化原则**）。"""
    签名 = str(节点.get("签名") or "")
    return {
        "名称": str(节点.get("名称") or ""),
        "种类": str(节点.get("种类") or ""),
        "起始行": int(节点.get("起始行") or 0),
        "签名": 签名,
        "参数": 抽参数(签名),
    }


def 抽取绑定文件认知(代码地图路径: str, 文件清单: list[dict], 调用: Callable[[str, dict], Any],
                   每文件条数: int = 每文件条数默认, 总条数: int = 总条数默认) -> dict[str, Any]:
    """按绑定文件从代码地图抽真实符号与参数签名（**开工返回的“知道这次的事项”**）。

    参数：
        代码地图路径：`.codegraph/codegraph.db` 的**绝对**路径
        文件清单：`开工准备` 的 `通过清单`（逐条带 `路径`/`绝对路径`）
        调用：调用器函数 `(能力id, 参数) -> 结果`；由调用方注入（本模块不持调用器）
        每文件条数 / 总条数：两道最小化上限

    返回：
        ``{已抽取, 文件数, 符号总数, 截断文件数, 文件认知, 问题}``

    - `已抽取=假` 且 `问题` 非空：地图不可用或查询失败，**如实报因、不造固定文案**；
    - `文件认知`：逐文件 `{路径, 符号清单, 命中数, 已截断}`；
    - `问题` 汇总失败原因（取前几条，不静默吞）。
    """
    文件认知: list[dict[str, Any]] = []
    问题表: list[str] = []
    符号总数 = 0
    截断文件数 = 0
    已抽文件数 = 0

    for 条目 in (文件清单 or []):
        if not isinstance(条目, dict):
            continue
        路径 = str(条目.get("路径") or "").strip()
        if not 路径:
            continue
        if 符号总数 >= 总条数:
            问题表.append(f"已达总条数上限 {总条数}，其余文件未抽取")
            break
        可取数 = min(每文件条数, 总条数 - 符号总数)
        结果 = 调用("代码解析支持库.代码地图.查询节点", {
            "代码地图路径": 代码地图路径,
            "关键词": 路径,
            "模式": "路径子串",
            "节点种类": list(关注节点种类),
            "最大条数": 可取数,
        })
        if not (getattr(结果, "成功", False) and isinstance(getattr(结果, "值", None), dict)):
            问题表.append(f"{路径}: {getattr(结果, '错误码', '')} {getattr(结果, '错误说明', '')}".strip())
            文件认知.append({"路径": 路径, "符号清单": [], "命中数": 0,
                          "已截断": 假, "未抽取原因": "查询失败"})
            continue
        值 = 结果.值
        节点列表 = [节点 for 节点 in (值.get("节点列表") or []) if isinstance(节点, dict)]
        符号清单 = [_归一节点(节点) for 节点 in 节点列表][:可取数]
        符号总数 += len(符号清单)
        已抽文件数 += 1
        本文件截断 = bool(值.get("已截断"))
        if 本文件截断:
            截断文件数 += 1
        文件认知.append({"路径": 路径, "符号清单": 符号清单,
                      "命中数": int(值.get("命中数") or len(节点列表)),
                      "已截断": 本文件截断})

    return {
        "已抽取": 已抽文件数 > 0,
        "文件数": 已抽文件数,
        "符号总数": 符号总数,
        "截断文件数": 截断文件数,
        "文件认知": 文件认知,
        "问题": "；".join(问题表[:3]),
        "说明": ("逐条是从代码地图现场读的**真实符号与参数签名**（不是固定提示词）："
                "`名称`/`种类`/`起始行`/`签名`/`参数` 均来自被绑定文件本身，"
                "文件不同则内容不同。这是「动手前先知道这个文件里有什么」的最小情报，"
                "详情与调用链用 `代码解析支持库.代码地图.查询关系` 按需展开。"),
    }


__all__ = ["关注节点种类", "每文件条数默认", "总条数默认", "抽参数",
           "抽取绑定文件认知"]
