"""开工编排 · 返回体量分档投影（进程内纯函数，不对外暴露）。

**为什么单独成文件**（与 `项目文档支持库/实现/检索粒度.py` 同构）：
档位只影响**返回包含哪些字段**，不影响任何业务判定（路径校验、租约、证据、
规范命中全都照常算完）。把投影抽成纯函数有三个好处：
① 可单测（喂上下文 → 比字段集合，不碰 Git / 租约 / 账本）；
② `开工准备` 主流程只做「算完 → 调投影 → 组装」，不被字段判断污染；
③ 以后加档位只改本文件，业务逻辑一行不动。

**口径与全仓统一**（华哥 2026-09-21 裁决「返回体量分档统一」）：
参数名统一为 `细节级别`，与 `能力目录.搜索能力`（发现面主入口）同名同语义；
档位语义统一为「索引 / 摘要 / 完整」，与三档口径对齐。详见
`开发文档/方案/返回体量分档统一方案_20260921.md`。

**★ 默认档 = `摘要`（2026-09-22 二次裁决「所有注入提示词最高 2000 字符」）**：
改前默认是 `完整`；实测 `完整` 档 `通用纪律` **单段就 11,132 字符**，随每次开工灌进上下文。
现改默认 `摘要`：短且必需的操作纪律（`摘要保留全文段`）给全文，其余段落只给
「体积 + 展开指针」（**漂移值**），要正文显式传 `细节级别=完整`。

**★ 2026-09-23 收口（同一口径补到「随输入规模长的数据块」）**：上面那轮只把
`通用纪律` / `开发流程` 两块收窄，而**跟着输入规模长**的四块（`绑定文件认知` /
`工作区快照` / `最近成功验证` / `缺失原子能力`）在默认档**一块都没过 2000 字符闸**——
实测 3 个绑定文件时 `绑定文件认知` 单块 **5,454 字符**（随文件数线性长），
`开工准备` 默认档整次返回 **13,374 字符**。现四块一律过 `块上限字符` 闸：
≤上限原样、超出改「体积 + 展开指针」（列表型块仍回列表，不破契约类型断言）。
"""

from __future__ import annotations

import json
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真

细节级别表 = ("索引", "摘要", "完整")
#: 「不投影」档（原样返回 = 改前行为）。**与 `默认细节级别` 解耦**：
#: 直通判据必须认这个常量，否则改默认值会静默废掉该档的投影（见 `投影开工上下文`）。
完整档 = "完整"
默认细节级别 = "摘要"

#: 纪律段在索引／摘要档下的取法：每段只留「标题 + 体积标记」。
#: 哲学纪律另有专门处理 —— 它自带索引形态（`条款` 是一句话列表，
#: `说明`/`判据` 只在展开时看），故索引档只回 `条款`，不回解释段。
纪律段落名表 = (
    "哲学纪律", "命令环境", "工具姿势", "提交纪律", "改完必做", "效率达标线", "派活纪律",
)


def 收敛细节级别(值: Any) -> str | None:
    """收敛档位入参：未传 / 空串 → 默认档；不认识的值 → None（调用方判参数不合法）。

    **不做大小写或别名归一**：档位是契约取值，宽松匹配会让调用方写出平台不认的
    拼法却「碰巧能用」，等真改名时静默失效（与 `检索粒度.收敛细节级别` 同口径）。
    """
    if 值 is None:
        return 默认细节级别
    文本 = str(值).strip()
    if not 文本:
        return 默认细节级别
    return 文本 if 文本 in 细节级别表 else None


def _体积标记(值: Any) -> str:
    """给一段内容标体积，供调用方判断「要不要展开」。"""
    if isinstance(值, str):
        return f"{len(值)} 字符"
    if isinstance(值, list):
        return f"{len(值)} 条"
    if isinstance(值, dict):
        return f"{len(值)} 键"
    return "1 项"


def _索引纪律(纪律: dict) -> dict:
    """索引档纪律：每段只给「标题 + 体积标记」+ 展开入口，不回正文。

    哲学纪律例外：它本来就备好了索引形态（`条款` = 12 条一句话），
    故索引档**回条款全文**（那是「索引级」内容），只把 `说明`/`判据` 这类解释段挡掉。
    """
    出: dict[str, Any] = {}
    for 段 in 纪律段落名表:
        if 段 not in 纪律:
            continue
        原 = 纪律[段]
        if 段 == "哲学纪律" and isinstance(原, dict):
            项 = {}
            if 原.get("条款"):
                项["条款"] = list(原["条款"])
            if 原.get("原文位置"):
                项["原文位置"] = 原["原文位置"]
            项["展开"] = "项目文档支持库.查哲学条款(关键词=…)"
            出[段] = 项
        else:
            出[段] = {"体积": _体积标记(原), "展开": "传 细节级别=摘要 或 完整 取原文"}
    出["展开提示"] = ("本档只给段落清单与体积；要正文传 细节级别=摘要（关键段）"
                   "或 细节级别=完整（全部，等于改前行为）")
    return 出


#: 摘要档下**保留全文**的短段：都是「动手前必看、砍了当场犯错」的操作纪律，且本身很短
#: （命令环境 233 / 提交纪律 726 / 判据 235 字符）。其余段落一律收成漂移指针。
摘要保留全文段 = ("命令环境", "提交纪律", "判据")


def _摘要纪律(纪律: dict) -> dict:
    """摘要档纪律（= 默认档）：只有 `摘要保留全文段` 给正文，其余段落给「体积 + 展开指针」。

    为什么不再保留哲学纪律条款：那 12 条一句话本身约 1,100 字符，占了 2000 预算的一半，
    而它早就有**既有按需入口** `项目文档支持库.查哲学条款`（实测 0.45 毫秒），
    属于「要细则就显式要」的典型，故连条款也收成指针。
    """
    出: dict[str, Any] = {}
    for 段, 原 in 纪律.items():
        if 段 == "说明":
            continue
        if isinstance(原, str):
            出[段] = 原
        elif 段 in 摘要保留全文段:
            出[段] = list(原) if isinstance(原, list) else 原
        else:
            出[段] = {"体积": _体积标记(原), "展开": "传 细节级别=完整 取原文"}
    return 出


def _索引开发流程(流程: dict) -> dict:
    """索引档开发流程：只留标题与落点，正文按需展开。"""
    return {
        "强制项标题": "动手建任何包/能力之前，先用关键词搜一遍全仓已有承载",
        "四步": list(流程.get("完整开发流程（四步）") or [])[:4] and "搜承载 → 建包 → 编译体检 → 收口",
        "原文位置": 流程.get("原文位置", ""),
        "展开": "传 细节级别=完整 取全文（含每步判据与实测出处）",
    }


#: 单块字符上限（**同一口径**：2026-09-22 华哥裁决「所有注入提示词最高 2000 字符」）。
#: 一块内容序列化后超过它，就**不再随每次调用整块灌进上下文** —— 改成「漂移指针」
#: （只留体积 + 展开入口），原文一字未删，按 `展开` 给的入口显式取（`细节级别=完整`）。
#:
#: 为什么按「块」而不是按「整个返回」：整个返回按档位已分好粗细，真正会失控的是
#: **跟着输入规模长**的那几块 —— `绑定文件认知` 随绑定文件数线性长（实测 3 个文件
#: 5,454 字符、8 个文件到一万四，是「一次开工吃掉几万字符」的直接元凶）、
#: `工作区快照` 随未提交文件数长、`最近成功验证` 随账本记录长、
#: `缺失原子能力` 随缺口清单长。这四块此前在默认（摘要）档**一块都没过这道闸**。
块上限字符 = 2000

#: 收窄时保留的文件数梯度（从宽到严，取第一个能塞进上限的）。
_绑定文件梯度 = (8, 6, 4, 3, 2, 1)
#: 收窄时每文件保留的符号数梯度。
_绑定符号梯度 = (8, 6, 4, 3, 2, 1, 0)


def _块字符数(值: Any) -> int:
    """一块内容的字符数（口径 = 调用方看到的返回体：JSON 紧凑序列化）。"""
    return len(json.dumps(值, ensure_ascii=False))


def _展开指针(块名: str) -> str:
    """统一的展开入口文案：所有收窄块走同一句话（同一口径，不逐块各写一句）。"""
    return (f"本块已按单块 {块上限字符} 字符上限收窄（块：{块名}）；"
            f"原文传 细节级别=完整 取")


def _封顶块(值: Any, 指针: str) -> Any:
    """单块封顶：≤上限原样返回；超出改成「体积 + 展开指针」（只改形态、原文不丢）。

    **列表型块仍回列表**（`[{"条数": n, "体积": …, "展开": …}]`）—— 调用方按契约
    断言 `列表型`（如 `开工编排` 正向HTTP场景的 `最近成功验证`/`缺失原子能力`）时
    不会被形态变化误伤；字典型块回指针字典。
    """
    字符数 = _块字符数(值)
    if 字符数 <= 块上限字符:
        return 值
    指针项 = {"体积": f"{字符数} 字符（超单块 {块上限字符} 上限，已折叠）", "展开": 指针}
    if isinstance(值, list):
        return [{"条数": len(值), **指针项}]
    return 指针项


def _收窄绑定文件认知(值: Any, 指针: str) -> Any:
    """`绑定文件认知` 的专用收窄：先逐文件少留符号、再少留文件，直到塞进单块上限。

    为什么单独一件：它是**唯一随绑定文件数线性长**的块（3 个文件 5,454 字符），
    一刀切成指针就等于把「动手前先知道这个文件里有什么」这个能力在默认档废掉
    （与 2026-09-22 华哥裁决「固定提示词本质上就是缺陷」相悖）。故**逐级收窄**：
    保留 路径/名称/种类/起始行/签名，`参数` 与 `签名` 同源（参数就是从签名文本
    拆出来的）故收窄时略去；每级都把「砍到了什么」写进 `收窄` 字段，**不静默截断**。
    """
    if not isinstance(值, dict) or _块字符数(值) <= 块上限字符:
        return 值
    文件认知 = [项 for 项 in (值.get("文件认知") or []) if isinstance(项, dict)]
    for 文件数 in _绑定文件梯度:
        if 文件数 > len(文件认知):
            continue
        for 每文件 in _绑定符号梯度:
            候选 = dict(值)
            候选["文件认知"] = [
                {
                    "路径": str(项.get("路径") or ""),
                    "符号清单": [
                        {"名称": 符.get("名称", ""), "种类": 符.get("种类", ""),
                         "起始行": 符.get("起始行", 0), "签名": 符.get("签名", "")}
                        for 符 in (项.get("符号清单") or [])[:每文件]
                    ],
                    "命中数": int(项.get("命中数") or 0),
                    "已截断": (真 if len(项.get("符号清单") or []) > 每文件
                             else bool(项.get("已截断"))),
                }
                for 项 in 文件认知[:文件数]
            ]
            候选["收窄"] = (f"单块超 {块上限字符} 字符上限：保留 {文件数}/{len(文件认知)} 个文件、"
                          f"每文件前 {每文件} 个符号（只留 名称/种类/起始行/签名，"
                          f"`参数` 与 `签名` 同源已略）。{指针}")
            if _块字符数(候选) <= 块上限字符:
                return 候选
    return _封顶块(值, 指针)


#: 摘要档要过「单块 ≤2000 字符」闸的块（顺序即上下文里的出现顺序）。
摘要收窄块表 = ("工作区快照", "最近成功验证", "缺失原子能力", "绑定文件认知")
#: 索引档要过闸的块（`工作区快照`/`最近成功验证` 在索引档另有既有收窄形态，不重复列）。
索引收窄块表 = ("缺失原子能力", "绑定文件认知")


def _收窄注入块(出: dict, 上下文: dict, 块表: tuple) -> None:
    """按 `块表` 把各注入块收窄后写回 `出`；上下文里没有该键就不动（不凭空造键）。"""
    for 块名 in 块表:
        if 块名 not in 上下文:
            continue
        值 = 上下文[块名]
        if 块名 == "绑定文件认知":
            出[块名] = _收窄绑定文件认知(值, _展开指针(块名))
        else:
            出[块名] = _封顶块(值, _展开指针(块名))


def 投影开工上下文(上下文: dict, 档位: str) -> dict:
    """把开工上下文投影成指定档位（纯函数，不改入参）。

    参数：
        上下文：`开工准备` 组装好的完整上下文
        档位：三档之一（调用方须先过 `收敛细节级别`）

    完整档：原样返回（**等于改前行为，逐字段兼容**）。
    摘要档（**默认档**）：`摘要保留全文段` 给正文，其余段落给「体积 + 展开指针」；
            开发流程留标题。
    索引档：纪律只留段名 + 体积 + 展开入口；开发流程只留标题；快照只留计数。

    ★ 直通判据是 `完整档` 常量，**不是** `默认细节级别`（2026-09-22 修）：
    这里原写 `if 档位 == 默认细节级别: return 上下文`，于是把默认档改成 `摘要` 之后，
    「摘要」被当成「不投影」直通返回 —— **默认档看起来改了、实际一字未变**（实测：
    改完再跑，通用纪律仍是 11,132 字符）。档位语义与默认值必须解耦。
    """
    if 档位 == 完整档:
        return 上下文

    出 = dict(上下文)

    if 档位 == "摘要":
        纪律 = 上下文.get("通用纪律")
        if isinstance(纪律, dict):
            出["通用纪律"] = _摘要纪律(纪律)
        流程 = 上下文.get("开发流程")
        if isinstance(流程, dict):
            出["开发流程"] = _索引开发流程(流程)
        # ★ 2026-09-23 收口：随输入规模长的四块过「单块 ≤2000 字符」闸（同一口径）。
        #   此前只有纪律/开发流程收窄，`绑定文件认知`（3 文件 5,454 字符）等一块都没过闸。
        _收窄注入块(出, 上下文, 摘要收窄块表)
        return 出

    # 索引档
    纪律 = 上下文.get("通用纪律")
    出["通用纪律"] = _索引纪律(纪律) if isinstance(纪律, dict) else 纪律
    流程 = 上下文.get("开发流程")
    出["开发流程"] = _索引开发流程(流程) if isinstance(流程, dict) else 流程

    快照 = 上下文.get("工作区快照")
    if isinstance(快照, dict):
        出["工作区快照"] = {
            "当前分支": 快照.get("当前分支", ""),
            "未提交修改数": 快照.get("未提交修改数", 0),
            "最近提交": list(快照.get("最近提交") or [])[:3],
            "展开": "传 细节级别=完整 取完整变更清单",
        }
    验证 = 上下文.get("最近成功验证")
    if isinstance(验证, list):
        出["最近成功验证"] = {
            "条数": len(验证),
            "名称列表": [项.get("名称", "") for 项 in 验证 if isinstance(项, dict)],
            "展开": "传 细节级别=完整 取完整记录",
        }
    # ★ 2026-09-23：索引档同样给这两块过「单块 ≤2000 字符」闸（此前一块未过）。
    _收窄注入块(出, 上下文, 索引收窄块表)
    出["细节级别"] = "索引"
    出["细节级别提示"] = ("本档只给索引级内容（段名/条数/引导指针）；"
                     "要判断依据请传 细节级别=完整（等于改前行为）")
    return 出
