"""开工编排 · 返回体量分档投影（进程内纯函数，不对外暴露）。

**为什么单独成文件**（与 `项目文档支持库/实现/检索粒度.py` 同构）：
档位只影响**返回包含哪些字段**，不影响任何业务判定（路径校验、租约、证据、
规范命中全都照常算完）。把投影抽成纯函数有三个好处：
① 可单测（喂上下文 → 比字段集合，不碰 Git / 租约 / 账本）；
② `开工准备` 主流程只做「算完 → 调投影 → 组装」，不被字段判断污染；
③ 以后加档位只改本文件，业务逻辑一行不动。

**口径与全仓统一**（华哥 2026-09-21 裁决「返回体量分档统一」）：
参数名统一为 `细节级别`，与 `能力目录.搜索能力`（发现面主入口）同名同语义；
档位语义统一为「索引 / 摘要 / 完整」，与三档口径对齐。详见
`开发文档/方案/返回体量分档统一方案_20260921.md`。

**★ 默认档必须与改前逐字段兼容**：默认档取 `完整`（= 改前的返回）。
理由：开工上下文是**判断依据**（撞车清单、路径越界、纪律全文都靠它），
把它默认砍成索引档会让老调用方静默丢数据。要省 token 就**显式**传索引/摘要档
（与「要细则就该显式要」同一条口径，但方向相反：这里重型是默认，因为它是判据）。
"""

from __future__ import annotations

from typing import Any

细节级别表 = ("索引", "摘要", "完整")
默认细节级别 = "完整"

#: 纪律段在索引／摘要档下的取法：每段只留「标题 + 体积标记」。
#: 哲学纪律另有专门处理 —— 它自带索引形态（`条款` 是一句话列表，
#: `说明`/`判据` 只在展开时看），故索引档只回 `条款`，不回解释段。
纪律段落名表 = (
    "哲学纪律", "命令环境", "工具姿势", "提交纪律", "改完必做", "效率达标线", "派活纪律",
)


def 收敛细节级别(值: Any) -> str | None:
    """收敛档位入参：未传 / 空串 → 默认档；不认识的值 → None（调用方判参数不合法）。

    **不做大小写或别名归一**：档位是契约取值，宽松匹配会让调用方写出平台不认的
    拼法却「碰巧能用」，等真改名时静默失效（与 `检索粒度.收敛细节级别` 同口径）。
    """
    if 值 is None:
        return 默认细节级别
    文本 = str(值).strip()
    if not 文本:
        return 默认细节级别
    return 文本 if 文本 in 细节级别表 else None


def _体积标记(值: Any) -> str:
    """给一段内容标体积，供调用方判断「要不要展开」。"""
    if isinstance(值, str):
        return f"{len(值)} 字符"
    if isinstance(值, list):
        return f"{len(值)} 条"
    if isinstance(值, dict):
        return f"{len(值)} 键"
    return "1 项"


def _索引纪律(纪律: dict) -> dict:
    """索引档纪律：每段只给「标题 + 体积标记」+ 展开入口，不回正文。

    哲学纪律例外：它本来就备好了索引形态（`条款` = 12 条一句话），
    故索引档**回条款全文**（那是「索引级」内容），只把 `说明`/`判据` 这类解释段挡掉。
    """
    出: dict[str, Any] = {}
    for 段 in 纪律段落名表:
        if 段 not in 纪律:
            continue
        原 = 纪律[段]
        if 段 == "哲学纪律" and isinstance(原, dict):
            项 = {}
            if 原.get("条款"):
                项["条款"] = list(原["条款"])
            if 原.get("原文位置"):
                项["原文位置"] = 原["原文位置"]
            项["展开"] = "项目文档支持库.查哲学条款(关键词=…)"
            出[段] = 项
        else:
            出[段] = {"体积": _体积标记(原), "展开": "传 细节级别=摘要 或 完整 取原文"}
    出["展开提示"] = ("本档只给段落清单与体积；要正文传 细节级别=摘要（关键段）"
                   "或 细节级别=完整（全部，等于改前行为）")
    return 出


def _摘要纪律(纪律: dict) -> dict:
    """摘要档纪律：字符串段给全文（它们本就短），字典段给标题与体积。"""
    出: dict[str, Any] = {}
    for 段, 原 in 纪律.items():
        if 段 == "说明":
            continue
        if isinstance(原, str):
            出[段] = 原
        elif isinstance(原, dict):
            项 = {k: v for k, v in 原.items() if k in ("条款", "原文位置")}
            项["体积"] = _体积标记(原)
            项["展开"] = "传 细节级别=完整 取全部字段"
            出[段] = 项
        else:
            出[段] = {"体积": _体积标记(原), "展开": "传 细节级别=完整 取原文"}
    return 出


def _索引开发流程(流程: dict) -> dict:
    """索引档开发流程：只留标题与落点，正文按需展开。"""
    return {
        "强制项标题": "动手建任何包/能力之前，先用关键词搜一遍全仓已有承载",
        "四步": list(流程.get("完整开发流程（四步）") or [])[:4] and "搜承载 → 建包 → 编译体检 → 收口",
        "原文位置": 流程.get("原文位置", ""),
        "展开": "传 细节级别=完整 取全文（含每步判据与实测出处）",
    }


def 投影开工上下文(上下文: dict, 档位: str) -> dict:
    """把开工上下文投影成指定档位（纯函数，不改入参）。

    参数：
        上下文：`开工准备` 组装好的完整上下文
        档位：三档之一（调用方须先过 `收敛细节级别`）

    完整档：原样返回（**等于改前行为，逐字段兼容**）。
    摘要档：纪律字符串段保全文、字典段只留条款；开发流程留标题；
            作用域快照留计数与前若干条。
    索引档：纪律只留段名 + 体积 + 展开入口；开发流程只留标题；快照只留计数。
    """
    if 档位 == 默认细节级别:
        return 上下文

    出 = dict(上下文)

    if 档位 == "摘要":
        纪律 = 上下文.get("通用纪律")
        if isinstance(纪律, dict):
            出["通用纪律"] = _摘要纪律(纪律)
        流程 = 上下文.get("开发流程")
        if isinstance(流程, dict):
            出["开发流程"] = _索引开发流程(流程)
        return 出

    # 索引档
    纪律 = 上下文.get("通用纪律")
    出["通用纪律"] = _索引纪律(纪律) if isinstance(纪律, dict) else 纪律
    流程 = 上下文.get("开发流程")
    出["开发流程"] = _索引开发流程(流程) if isinstance(流程, dict) else 流程

    快照 = 上下文.get("工作区快照")
    if isinstance(快照, dict):
        出["工作区快照"] = {
            "当前分支": 快照.get("当前分支", ""),
            "未提交修改数": 快照.get("未提交修改数", 0),
            "最近提交": list(快照.get("最近提交") or [])[:3],
            "展开": "传 细节级别=完整 取完整变更清单",
        }
    验证 = 上下文.get("最近成功验证")
    if isinstance(验证, list):
        出["最近成功验证"] = {
            "条数": len(验证),
            "名称列表": [项.get("名称", "") for 项 in 验证 if isinstance(项, dict)],
            "展开": "传 细节级别=完整 取完整记录",
        }
    出["细节级别"] = "索引"
    出["细节级别提示"] = ("本档只给索引级内容（段名/条数/引导指针）；"
                     "要判断依据请传 细节级别=完整（等于改前行为）")
    return 出
