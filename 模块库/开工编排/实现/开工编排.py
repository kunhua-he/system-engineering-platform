def _归一化相对路径(原始: Any) -> str:
    """反斜杠转正斜杠、去前导 ./ 与首尾斜杠（与旧 文件租约.归一化路径 同口径）。

    ★ 2026-09-23（未完成事项 §四「路径边界有 5 份实现、口径互不一致」）：**本函数刻意不做 URL 解码**，理由是它的返回值会被
    **原样转发给下游的路径判定腿**（`_校验单条路径` 的 `归一` 既送 `系统核心支持库.路径安全.
    校验路径`，又经 `_提取路径认知` 进 `申请文件租约` → `租约路径.校验相对路径`），而下游那两条
    腿各自都会 unquote 一次。此处再解一次，等于把**已解码值**送进下游的 unquote ⇒ 真正的
    二次解码（**2026-09-23 S4 实测订正**：`%252e%252e/x` 本模块与直接调 `校验路径` **都放行** —— `归一` 送的是**未解码**的原始文本，下游各自只解一次，故不构成二次解码；原「本模块拒」的说法与实现不符）。
    ★ 2026-09-24（批H 裁-A）：本模块**不再自带解码**（原有那个私有解码函数已删）—— 边界判据已收口到
    唯一判据节点，解码那一次由该节点对**原始入参**自己做；本函数只收已过判据的原文。
    """
    文本 = str(原始).strip().replace("\\", "/")
    while 文本.startswith("./"):
        文本 = 文本[2:]
    return 文本.strip("/")


def _拆路径条目(原始: Any) -> tuple[Any, str]:
    """把一条 `修改路径` 条目拆成 (送边界校验的文本, 声明指纹·标准格式)。

    **为什么要拆（2026-09-19）**：`开工即占` 的乐观锁要声明「我认领时看到的内容指纹」。
    若允许字典直接进 `_校验单条路径`，会走 `str(dict)` 变成 `"{'路径': …}"` 这种脏文本，
    被边界校验判越界——那是把「调用方表达得更精确」错判成「越界」。所以先拆再校验。

    指纹格式归一（哲学第 8 条②「底子不同但格式一样 → 加模式变量」，同类问题 2026-09-19 实测）：
    底层 `文件租约存储.计算内容指纹` 的**唯一标准格式**是 `sha256:<64位小写十六进制>`。
    调用方常用 `hashlib.sha256(...).hexdigest()` 得到**裸 hex**，直接比对必然判「内容已变更」
    ——那是把「格式没对齐」错报成「文件被改过」，属误伤。因此这里**在入口归一**：
    裸 64 位十六进制自动补 `sha256:` 前缀；已是标准格式或底层常量（`不存在`/`目录`/`不可读:…`）
    一律原样透传，不做任何猜测性改写。

    返回：① 字符串条目 → 原样文本 + 空指纹（**旧行为逐字不变**）；
         ② `{"路径": …, "指纹": …}` → `路径` 文本 + 归一后指纹（缺失即空串）；
         ③ 其它类型 → 原样返回 + 空指纹，交给下游按原口径报「必须是相对路径」。
    """
    if isinstance(原始, dict):
        return 原始.get("路径"), _归一指纹(str(原始.get("指纹") or "").strip())
    return 原始, ""


def _归一指纹(原始指纹: str) -> str:
    """把声明指纹归一到底层标准格式 `sha256:<hex>`；其它形态原样透传（不做猜测改写）。

    只做一件有把握的事：**裸 64 位十六进制 → 补 `sha256:` 前缀**。
    `不存在` / `目录` / `不可读:<异常类型>` 是底层合法常量，原样保留；
    长度不对或含非十六进制字符的，说明调用方写错了，原样透传让比对如实判「不一致」，
    而不是替它猜一个「大概想写的是 sha256」。
    """
    候选 = str(原始指纹 or "").strip()
    if not 候选 or ":" in 候选:
        return 候选
    if len(候选) == 64 and all(字符 in "0123456789abcdefABCDEF" for 字符 in 候选):
        return f"sha256:{候选.lower()}"
    return 候选


def _解析基准根(项目根: str | None, 上下文根: str = "") -> str:
    """文件租约**现场指纹**的解析基准（绝对路径）：一律走全平台唯一那条解析腿。

    为什么必须有它（未完成事项 #134 ①，2026-09-23 修）：`申请文件租约` / `释放文件租约`
    / `查询文件租约` 的现场指纹读的是**仓库内真实文件**，相对路径按「`项目根` 实参 →
    环境变量 `系统平台_项目根` → 进程 cwd」三级解析。本模块此前**不转发 `项目根`**，
    租约层只能落到第三级 —— 网关跑激活制品时 cwd 就是制品根 ⇒ 实测本包认领 6 条路径时
    现场复现：`测试中心/…` 两条恒「不存在」（制品白名单不含测试中心），其余四条登记的是
    **制品副本**的 sha256（不是仓库那份）。于是「内容指纹」这一半的乐观锁形同虚设：
    想开门就得申报错那棵树的指纹。

    取值顺序：① 入参 `项目根`；② 入参为空/非路径时才用 `上下文根`（`开工准备` 上下文里
    那份已 `resolve()` 的根，同一份判据来源）。取到根即经 `平台适配.解析路径` 解析成绝对；
    **两处都取不到时返回空串** —— 那表示「本次没有可用的显式根」，调用方据此**不转发**
    该参数（让下游按它自己那条解析腿的三级口径走），而**不是**转发一个空串冒充根。

    ★ 2026-09-23（未完成事项 #134 兄弟收口）：本函数是**唯一一份**基准根取值实现。
    `_认领基准根`（认领腿）与 `收工释放`（解锁腿）都只是它的调用方 —— 同一件事只许
    一处实现，不许两处各写一遍取值顺序（「只修一处、兄弟漏改」在本仓已复发六次）。
    """
    根 = str(项目根 or "").strip() or str(上下文根 or "").strip()
    if not 根:
        return ""
    解析 = 解析路径(根)
    return (str(解析).strip() if isinstance(解析, Path) else "") or 根


