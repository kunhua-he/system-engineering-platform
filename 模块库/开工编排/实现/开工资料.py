"""开工资料 · 「一次调用拿到开工全部资料」的档位与硬预算投影（进程内纯函数，不对外暴露）。

## 为什么单独成文件（与 `返回体量分档.py` 同构）

华哥 2026-09-24（批R·R-16）原话：「我希望的就是纯用 mcp，然后尽量都功能后面变成，
1 次运行，能获取开工所有的资料。这是我的目标，但是控制住上下文不能撑爆」。

`开工准备` 新增 `资料` 段后，主流程会变成「算完 → 按档位与预算投影 → 组装」。把投影抽成
纯函数有三个好处（与 `返回体量分档.py` 同）：① 可单测（喂一份资料 → 比字符数与降级项，
不碰 Git / 租约 / 索引）；② 主流程不被预算判断污染；③ 以后加档位只改本文件。

## 边界：只做聚合与投影，**不做第二份事实源**

六项内容的事实源仍是各自节点（`文件租约` / `项目文档支持库.查询索引` / 能力定义与参数契约
与门禁基线原文 / `公共契约.能力契约.常用意图` / 通用纪律）。本件**不产生任何新事实**，
只决定「摆多少、超预算时先砍谁」，且**每一级降级都保留指针（文件 + 行区间）**，
保证砍掉的正文都能照指针取回。

## 预算口径（本批须华哥确认的一条，见交付单据 §须确认）

`资料预算` 约束的是**本次新增的 `资料` 段**（不是整个返回值）：改前既有各段的体积由
`细节级别` 管（索引 7,120 / 摘要 8,137 / 完整 26,386 字符，2026-09-24 实测），
按「不传新参数时行为与改前逐字节一致」的硬判据，新参数**不得**回头去缩既有段。
故 `资料.用量` 同时回带两个读数：`资料段字符数`（受本参数管辖）与
`总返回字符数`（读数，供调用方自己规划），判据落在前者。
"""

from __future__ import annotations

import copy
import json
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假

资料级别表 = ("指针", "摘要", "完整")
#: 默认档 = `指针`：只给指针与计数，不塞正文（「控制住上下文不能撑爆」的默认落点）。
默认资料级别 = "指针"
#: 默认预算（字符）：六项合计的上限。0 = 不限。
默认资料预算 = 8000
#: 「不投影」档（原样返回 = 把现有的都给全）。与 `默认资料级别` 解耦，判据必须认这个常量。
完整资料档 = "完整"


def 收敛资料级别(值: Any) -> str | None:
    """收敛档位入参：未传 → 默认档；不认识的值 → None（调用方判 参数不合法）。

    与 `返回体量分档.收敛细节级别` 同口径：**不做大小写或别名归一** ——
    档位是契约取值，宽松匹配会让调用方写出平台不认的拼法却「碰巧能用」。
    """
    if 值 is None:
        return 默认资料级别
    文本 = str(值).strip()
    if not 文本:
        return 默认资料级别
    return 文本 if 文本 in 资料级别表 else None


def 收敛资料预算(值: Any) -> int | None:
    """收敛预算入参：未传/空 → 默认预算；0 = 不限；负数与非整数 → None（判 参数不合法）。"""
    if 值 is None:
        return 默认资料预算
    if isinstance(值, bool) or not isinstance(值, int):
        return None
    return 值 if 值 >= 0 else None


def 资料字符数(资料: Any) -> int:
    """`资料` 段的字符数（口径与薄壳一致：`ensure_ascii=False` 的 JSON 字符数）。"""
    return len(json.dumps(资料, ensure_ascii=False))


# ── 降级阶梯（超预算时**按固定顺序**把正文换成指针；每级都保留指针）─────────────
#: 顺序即「先砍最不值钱的」：规范片段正文（可从索引重取）→ 纪律段正文（同一次调用
#: 顶层已有）→ 涉及路径明细（占用者/租约id 可再查）→ 契约逐能力明细（包级指针仍在）。

def _降规范片段正文(资料: dict) -> bool:
    """规范片段：去掉 `片段` 正文，只留 文档相对路径/标题/起始行/结束行 + 指针。"""
    改了 = 假
    for 项 in 资料.get("规范片段") or []:
        if isinstance(项, dict) and "片段" in 项:
            项.pop("片段", None)
            项["指针"] = f"{项.get('文档相对路径', '')}:{项.get('起始行', 0)}-{项.get('结束行', 0)}"
            项["展开"] = "传 资料级别=摘要（或按 指针 自行取原文）取片段正文"
            改了 = 真
    return 改了


def _降纪律段正文(资料: dict) -> bool:
    """纪律段：正文换成「体积 + 指向顶层 通用纪律 的键路径」。"""
    段 = 资料.get("纪律段")
    if not isinstance(段, dict):
        return 假
    段名表 = 段.get("段名")
    if not isinstance(段名表, list):
        return 假
    改了 = 假
    体积表 = 段.get("体积") or {}
    for 名 in 段名表:
        值 = 段.get(名)
        if isinstance(值, (str, list)):
            体积表[名] = (f"{len(值)} 字符" if isinstance(值, str) else f"{len(值)} 条")
            段[名] = {"体积": 体积表[名], "展开": f"顶层 通用纪律.{名}（本次同一次调用已无条件返回，不重复正文）"}
            改了 = 真
    if 改了:
        段["体积"] = 体积表
    return 改了


def _降涉及路径明细(资料: dict) -> bool:
    """涉及路径：去掉 占用者/租约id/存在，只留 路径/占用状态/指针。"""
    改了 = 假
    for 项 in 资料.get("涉及路径") or []:
        if not isinstance(项, dict):
            continue
        for 键 in ("占用者", "租约id", "存在"):
            if 键 in 项:
                项.pop(键, None)
                改了 = 真
        项.setdefault("指针", 项.get("路径", ""))
    return 改了


def _降契约指针明细(资料: dict) -> bool:
    """契约与判据指针：逐能力明细 → 只留包级三条指针（每类取第一条行区间）。"""
    改了 = 假
    for 包 in 资料.get("契约与判据指针") or []:
        if not isinstance(包, dict):
            continue
        能力表 = 包.get("能力")
        if not isinstance(能力表, list) or not 能力表:
            continue
        首条 = 能力表[0] if isinstance(能力表[0], dict) else {}
        for 类名 in ("能力定义", "参数契约", "门禁基线"):
            值 = 首条.get(类名)
            if isinstance(值, str) and 值:
                包.setdefault(类名, 值)
        包["能力"] = {"条数": len(能力表),
                  "能力id清单": [项.get("能力id", "") for 项 in 能力表 if isinstance(项, dict)],
                  "展开": "按 能力定义/参数契约/门禁基线 三指针取原文；逐能力行区间要更细请传 资料级别=完整"}
        改了 = 真
    return 改了


降级阶梯: tuple[tuple[str, Any], ...] = (
    ("规范片段正文→指针", _降规范片段正文),
    ("纪律段正文→指针", _降纪律段正文),
    ("涉及路径明细→指针", _降涉及路径明细),
    ("契约逐能力明细→指针", _降契约指针明细),
)


def 投影资料预算(资料: dict, 级别: str, 预算: int) -> dict:
    """按档位与预算投影 `资料`（纯函数，不改入参）。

    - `级别 == 完整` 或 `预算 == 0`：不投影（原样返回），只在 `用量` 里如实标注不受预算约束；
    - 其余：`资料` 段字符数超预算即按 `降级阶梯` 逐级降级（每级都保留指针），
      降到无法再降仍超 ⇒ `是否超预算=真` + `超预算原因`（**不静默**）。

    返回 `{"资料": …, "用量": …}`；`用量` 是本段的读数（不是判据之外的猜测）。
    """
    出 = copy.deepcopy(资料)
    用量: dict[str, Any] = {
        "资料级别": 级别,
        "资料预算": 预算,
        "资料段字符数": 资料字符数(出),
        "是否超预算": 假,
        "降级项": [],
    }
    if 级别 == 完整资料档 or not 预算:
        用量["预算管辖"] = "不受资料预算约束（完整档=不投影；或 资料预算=0 表示不限）"
        return {"资料": 出, "用量": 用量}

    用量["预算管辖"] = "只约束 资料 段（既有各段由 细节级别 管，见本文件 docstring）"
    for 名, 降级 in 降级阶梯:
        if 资料字符数(出) <= 预算:
            break
        if 降级(出):
            用量["降级项"].append(名)
    用量["资料段字符数"] = 资料字符数(出)
    if 用量["资料段字符数"] > 预算:
        用量["是否超预算"] = 真
        用量["超预算原因"] = (
            f"资料段已降到最低形态仍 {用量['资料段字符数']} 字符 > 预算 {预算}："
            f"六项指针本身占这么多。要更小请缩小 修改路径 条数（涉及路径/契约指针随之变少），"
            f"或传 资料级别=指针 且 资料预算=0 自行控量")
    return {"资料": 出, "用量": 用量}
