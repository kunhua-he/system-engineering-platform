"""逐字稿疑难标记（模块内部纯计算工具）：从多片分片转写结果里挑出需要复核的疑难段与死循环区间。

输入是已解析好的 03_分片转写 多片合成列表（list[dict]），输出纯 dict；不返回平台「结果」类型、不 import 支持库/
提供者/实现目录、不读写磁盘。判定口径（默认值见 默认阈值()，阈值可逐键覆盖）：低置信度 / 高压缩比 / 无语音概率高 / 空文本 /
数字可疑，外加「连续同文重复」「段内短语重复」两类死循环区间；死循环区间内分段不进疑难段，区间外照常判定；非列表输入返回带
错误码/错误说明 的空结果，缺字段按安全默认值处理，不抛裸异常。
"""

import re
from collections import Counter
from 公共契约.基础类型.逻辑类型 import 真, 假

短语最小长度, 短语最大长度 = 12, 48
阿拉伯数字正则 = re.compile(r"[0-9]")
空白正则 = re.compile(r"\s+")


def 默认阈值() -> dict:
    """返回默认阈值字典副本（调用方可在其基础上覆盖任意键）。"""
    return {"最小平均对数概率": -1.0, "最大压缩比": 2.4, "最大无语音概率": 0.6,
            "死循环连续次数": 15, "短语重复次数": 10}


def _合并阈值(阈值) -> dict:
    """默认阈值 + 调用方覆盖：只接受已知键的数值，非法键值忽略不报错。"""
    合并 = 默认阈值()
    for 键, 值 in (阈值 if isinstance(阈值, dict) else {}).items():
        if 键 in 合并 and isinstance(值, (int, float)) and not isinstance(值, bool):
            合并[键] = 值
    return 合并


def _数值(容器, 键: str) -> float:
    """安全取数：缺字段、非数值、布尔一律回落 0.0，绝不抛异常。"""
    值 = 容器.get(键) if isinstance(容器, dict) else None
    return 0.0 if isinstance(值, bool) or not isinstance(值, (int, float)) else float(值)


def _文本(容器, 键: str) -> str:
    """安全取文本：缺字段或非文本一律回落空串。"""
    值 = 容器.get(键) if isinstance(容器, dict) else None
    return 值 if isinstance(值, str) else ""


def _归一文本(分段: dict) -> str:
    """分段文本去掉全部空白，作为重复判定与长度判定的统一口径。"""
    return 空白正则.sub("", _文本(分段, "文本"))


def _窗口最多(文本: str, 窗口长: int) -> tuple[str, int]:
    """定长滑窗计数：返回出现次数最多的子串与次数（无命中返回空串和 0）。"""
    计数 = Counter(文本[起点:起点 + 窗口长] for 起点 in range(len(文本) - 窗口长 + 1))
    return 计数.most_common(1)[0] if 计数 else ("", 0)


def _最长重复短语(文本: str, 最少次数: int) -> tuple[str, int]:
    """段内重复短语检测：返回（最长的达标短语, 最大重复次数）。

    长度 >= 短语最小长度 的短语若重复 k 次，其前 短语最小长度 个字符也必然重复 >= k 次，所以先按 短语最小长度 滑一遍，
    计数不到 最少次数 即可判定不存在（提前返回，常规复杂度 O(n)）；达标后把窗口逐级加长，留下最长的达标短语当样例
    （更贴近真实循环话术），窗口超过 短语最大长度 或文本长度即停。
    """
    if len(文本) < 短语最小长度 * 2:
        return "", 0
    样例, 次数 = _窗口最多(文本, 短语最小长度)
    if 次数 < 最少次数:
        return "", 0
    for 窗口长 in range(短语最小长度 + 1, min(len(文本), 短语最大长度) + 1):
        候选短语, 候选次数 = _窗口最多(文本, 窗口长)
        if 候选次数 >= 最少次数:
            样例, 次数 = 候选短语, 候选次数
    return 样例, 次数


def _判定分段(分段: dict, 阈值表: dict) -> tuple[list[str], dict]:
    """按 5 条单段规则产出（原因列表, 指标快照）；一条不中即返回空原因。"""
    平均对数概率, 压缩比, 无语音概率 = (_数值(分段, "平均对数概率"),
                                       _数值(分段, "压缩比"), _数值(分段, "无语音概率"))
    原文 = _文本(分段, "文本")
    长度 = len(空白正则.sub("", 原文))
    命中表 = ((平均对数概率 < 阈值表["最小平均对数概率"], "低置信度"),
              (压缩比 > 阈值表["最大压缩比"], "高压缩比"),
              (无语音概率 > 阈值表["最大无语音概率"], "无语音概率高"),
              (长度 < 2, "空文本"),
              (长度 < 6 and bool(阿拉伯数字正则.search(原文)), "数字可疑"))
    指标 = {"平均对数概率": 平均对数概率, "压缩比": 压缩比, "无语音概率": 无语音概率, "去空白长度": 长度}
    return [名称 for 命中, 名称 in 命中表 if 命中], 指标


def _展平分段(分片转写列表: list) -> list[dict]:
    """把多片分片转写摊平成带归属信息的分段序列；缺字段按所在位置补 1 起的序号。"""
    序列: list[dict] = []
    for 分片下标, 分片 in enumerate(分片转写列表):
        分片 = 分片 if isinstance(分片, dict) else {}
        片序号, 分段列表 = 分片.get("分片序号"), 分片.get("分段")
        for 段下标, 段 in enumerate(分段列表 if isinstance(分段列表, list) else []):
            段 = 段 if isinstance(段, dict) else {}
            段序号 = 段.get("序号")
            序列.append({
                "分片序号": 分片下标 + 1 if isinstance(片序号, bool) or not isinstance(片序号, int) else 片序号,
                "序号": 段下标 + 1 if isinstance(段序号, bool) or not isinstance(段序号, int) else 段序号,
                "开始秒": _数值(段, "开始秒"), "结束秒": _数值(段, "结束秒"), "分段": 段,
            })
    return 序列


def _扫描死循环(序列: list[dict], 阈值表: dict) -> tuple[list[dict], set[int]]:
    """扫描两类死循环：返回（死循环区间列表, 命中分段在序列中的下标集合）。"""
    区间: list[dict] = []
    命中位置: set[int] = set()
    连续阈值, 短语阈值 = 阈值表["死循环连续次数"], 阈值表["短语重复次数"]
    下标 = 0
    while 下标 < len(序列):  # 其一：连续同文重复达到阈值的整段区间
        当前, 结尾 = _归一文本(序列[下标]["分段"]), 下标
        if 当前:
            while 结尾 + 1 < len(序列) and _归一文本(序列[结尾 + 1]["分段"]) == 当前:
                结尾 += 1
        if 当前 and 结尾 - 下标 + 1 >= 连续阈值:
            区间.append({"开始秒": 序列[下标]["开始秒"], "结束秒": 序列[结尾]["结束秒"], "重复次数": 结尾 - 下标 + 1, "样例文本": 当前})
            命中位置.update(range(下标, 结尾 + 1))
            下标 = 结尾 + 1
            continue
        下标 += 1
    for 位置, 项 in enumerate(序列):  # 其二：单个分段文本内部同一短语反复出现
        净文 = _归一文本(项["分段"])
        if 位置 in 命中位置 or len(净文) < 短语最小长度 * 2:
            continue
        短语, 次数 = _最长重复短语(净文, 短语阈值)
        if 次数 < 短语阈值:
            continue
        区间.append({"开始秒": 项["开始秒"], "结束秒": 项["结束秒"], "重复次数": 次数, "样例文本": 短语})
        命中位置.add(位置)
    return 区间, 命中位置


def _失败结果(错误码: str, 错误说明: str) -> dict:
    """失败返回结构：空数据 + 显式失败标志（成功=False / 状态=失败）+ 错误码/错误说明。

    调用方（全自动精校）只读 死循环区间 时，过去无法区分「真无疑难」与「内部炸了」：
    两种输入都返回 死循环区间=[]。失败返回一律带 成功=False，真无疑难返回**不含**该键，
    调用方按 成功 is False 或 错误码 非空判失败，即可阻断幻觉重复进正文。
    成功返回保持既有两键（疑难段/死循环区间）不变，不额外新增键。
    """
    return {"疑难段": [], "死循环区间": [], "状态": "失败", "成功": 假,
            "错误码": 错误码, "错误说明": 错误说明}


def 标记疑难(分片转写列表: list[dict], 阈值: dict | None = None) -> dict:
    """对多片分片转写结果做疑难标记，返回 {"疑难段": [...], "死循环区间": [...]}。

    疑难段保留输入的 分片序号/序号 便于回指原始分段；死循环区间内分段不进疑难段，区间外照常判定；非列表输入返回带
    错误码/错误说明 的空结果；其余意外同样被兜住，不抛裸异常。
    失败返回（参数不合法/内部异常）额外带 成功=False 与 状态=失败：与「真无疑难」的空结果可区分，调用方必须判它。
    """
    try:
        分片转写列表 = [] if 分片转写列表 is None else 分片转写列表
        if not isinstance(分片转写列表, list):
            return _失败结果("参数不合法", "分片转写列表必须为列表")
        阈值表 = _合并阈值(阈值)
        序列 = _展平分段(分片转写列表)
        死循环区间, 死循环位置 = _扫描死循环(序列, 阈值表)
        疑难段: list[dict] = []
        for 位置, 项 in enumerate(序列):
            if 位置 in 死循环位置:
                continue
            原因, 指标 = _判定分段(项["分段"], 阈值表)
            if not 原因:
                continue
            疑难段.append({"分片序号": 项["分片序号"], "序号": 项["序号"],
                           "开始秒": 项["开始秒"], "结束秒": 项["结束秒"],
                           "文本": _文本(项["分段"], "文本"), "原因": 原因, "指标": 指标})
        死循环区间.sort(key=lambda 项: (float(项.get("开始秒") or 0.0), float(项.get("结束秒") or 0.0)))
        return {"疑难段": 疑难段, "死循环区间": 死循环区间}
    except Exception as 错误:  # 兜底：任何意外都返回带失败标志的空结果，不把异常抛给调用方
        return _失败结果("内部异常", f"疑难标记失败: {错误}")
