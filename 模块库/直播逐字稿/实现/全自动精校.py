def _记账落盘(问题表: list[str], 名称: str, 成功: bool) -> bool:
    """登记一次落盘写入的返回值：失败即记进 问题表（绝不静默丢弃）。

    写指纹/写状态/写JSON 的返回值过去全部丢掉，缓存目录没建成也照样报「已完成」。
    这些产物是断点续跑依据与交付证据链，缺件必须可观测、必须影响结论。
    """
    if not 成功:
        问题表.append(f"{名称} 写入失败")
    return bool(成功)


def _汇总落盘(报告: dict, 落盘问题: list[str]) -> None:
    """把落盘问题汇总进报告并影响 通过（可重复调用，后一次覆盖上一次的汇总条目）。

    不直接失败（成品可能已落盘），但绝不静默：报告里留全量问题清单。
    """
    报告["落盘问题"] = 落盘问题
    if not 落盘问题:
        return
    报告["通过"] = 假
    原因 = 报告.setdefault("失败原因", [])
    原因[:] = [项 for 项 in 原因 if not str(项).startswith("落盘问题")]
    原因.append(f"落盘问题 {len(落盘问题)} 处：" + "；".join(落盘问题))


def _失败(缓存: dict | None, 错误码: str, 错误说明: str, 阶段: str = "",
        写状态=None) -> 结果:
    详情 = {}
    if 缓存:
        if callable(写状态):
            写状态(缓存, {"状态": "失败", "阶段": 阶段, "错误码": 错误码, "错误说明": 错误说明})
        详情["缓存目录"] = str(缓存["根"])
        详情["阶段"] = 阶段
    return 结果.失败(错误码, 错误说明, 来源=来源, 详情=详情)


泛化文件名 = {"合并视频", "输出", "output", "out", "录音", "音频", "video", "recording"}


def _场次标题(源文件: Path) -> str:
    """场次标题：泛化文件名（如 合并视频.mp4）改用所在目录名，避免整篇稿子的标题没信息量。"""
    主名 = 源文件.stem.strip()
    if 主名.lower() in 泛化文件名 or 主名 in 泛化文件名:
        return 源文件.parent.name.strip() or 主名
    return 主名


def _读已有裁决(裁决目录) -> dict:
    """读 08_裁决/窗口_*.json 里「状态=完成且精校文本非空」的窗口，供裁决阶段复用。

    为什么必须复用（2026-09-18 实测）：长场次 29 个窗口单轮要十几分钟且几乎必然有个别窗口
    遇瞬时超时/句柄失效；不复用时每次重跑都从第 1 窗重来，可能不断碰上新的瞬时失败而收不了口。

    ★ 文件读写一律经底座原子能力（`文件系统支持库.文件操作.列出目录` + `读取文件`，
    解析经 `数据操作支持库.数据交换.反序列化JSON`）：本文件是模块实现，不得直接触碰标准库
    I/O —— 原 `os.listdir` / 内置 `open` 是原子旁路（能力调用图审计判红，2026-09-19 修）。
    """
    表: dict = {}
    列 = _底座("文件系统支持库.文件操作.列出目录", {"目录路径": str(裁决目录)})
    if 列 is None or not getattr(列, "成功", 假):
        return 表
    文件们 = [str(名) for 名 in (getattr(列, "值", None) or [])]
    for 名 in sorted(文件们):
        if not (名.startswith("窗口_") and 名.endswith(".json")):
            continue
        读 = _底座("文件系统支持库.文件操作.读取文件",
                   {"文件路径": str(Path(裁决目录) / 名), "最大字符": 0, "编码": "utf-8"})
        if 读 is None or not getattr(读, "成功", 假) or not isinstance(getattr(读, "值", None), str):
            continue
        解析 = _底座("数据操作支持库.数据交换.反序列化JSON", {"文本": getattr(读, "值")})
        if 解析 is None or not getattr(解析, "成功", 假):
            continue
        数据 = getattr(解析, "值", None)
        if not isinstance(数据, dict) or 数据.get("状态") != "完成":
            continue
        if not str(数据.get("精校文本") or "").strip():
            continue
        # 键取「输入指纹」（提速方案 2a 口径）：指纹一致才复用，任一入参变即重算。
        # 旧产物没有该字段 → 跳过（自然重算一次并写入指纹，此后即可复用）。
        指纹 = str(数据.get("输入指纹") or "").strip()
        if not 指纹:
            continue
        表[指纹] = 数据
    return 表


def _有音轨(流表) -> bool:
    """源媒体是否有音频轨。流表来自 FFmpeg 提供者 探测媒体 的返回值「流」：
    每项是 {索引, 类型, 编码, 宽度, 高度, 采样率, 声道数}，类型为 audio 即音轨。

    非列表（含 None/缺失）一律判「无音轨」（fail-closed）：拿不到流表就不
    放行转写，否则「无音轨」硬门禁形同虚设。
    """
    if not isinstance(流表, list):
        return 假
    for 流 in 流表:
        if isinstance(流, dict) and str(流.get("类型") or "").strip().lower() == "audio":
            return 真
    return 假


def _写底稿行(缓存: dict, 分段列表: list[dict],
            开工ID: str | None = None) -> bool:
    """把逐句底稿写成 02_转录底稿/03_原始逐字稿.txt（[开始-结束] 文本）。开工ID 穿透见 _写文本。"""
    目标 = 缓存["根"] / "02_转录底稿" / "03_原始逐字稿.txt"
    行 = [f"[{段['开始秒']:06.1f}-{段['结束秒']:06.1f}] {段['文本']}" for 段 in 分段列表 if 段["文本"]]
    return _写文本(目标, "\n".join(行) + "\n", 开工ID)


def 全自动精校(源文件路径: str, 导出路径: str, 缓存目录: str, 模式: int,
                分片秒数: int = 300, 附加术语: str = "", 模型配置: dict | None = None,
                裁决模型配置: dict | None = None, 超时秒: float = 3600.0,
                输出结构: str = "", 附加要求: str = "",
                裁决模型句柄: int | None = None, 开工ID: str | None = None,
                *, 步骤: dict | None = None) -> 结果:
    """一次调用完成：视频/音频绝对路径 → 精校逐字稿（导出路径）。

    输出结构 / 附加要求 是消费者传进来的业务细节（分节结构、易错词校正、行业口径），
    底座只提供通用框架，不写死任何行业内容。

    裁决模型句柄 是消费者先调 `大语言模型支持库.模型连接器.连接LLM` 得到的句柄；
    传了它就不必再传 裁决模型配置，底座只借用、不释放（谁连接谁释放）。

    步骤 表由主文件注入全部兄弟子步骤（入参校验/缓存续跑/分片转写/疑难标记/复核/窗口/裁决/
    排版/质检/导出）；缺失任一步骤即如实失败，不静默降级。

    开工ID（2026-09-25）：写腿按「活跃写租约所有者 == 开工ID」判授权，本主流程把它逐跳
    绑进每一个**会写盘**的注入步骤（见下方 写盘步骤 绑定）；缺它时受管落点即 `越界`。
    """
    步骤 = dict(步骤 or {})
    缺失 = [名 for 名 in 必需步骤 if not callable(步骤.get(名))]
    if 缺失:
        return 结果.失败("装配缺失", "缺少步骤: " + "、".join(缺失), 来源=来源)

    # ── 开工ID 穿透（2026-09-25）────────────────────────────────────────────
    # 写腿按「活跃写租约所有者 == 开工ID」判授权（`公共契约/运行时/写入授权.py::校验写入授权`）。
    # 本主流程把 开工ID 逐跳绑进每一个**会写盘**的注入步骤：绑定只捕获本函数的形参
    # （**不用全局变量 / 环境变量 / 模块级状态**），等价于在每个调用点写 `开工ID=开工ID`；
    # 收在一处是因为 写状态 还要作为回调传给 _失败（不透明回调无法再透传形参）。
    写盘步骤 = ("校验入参", "准备缓存", "写指纹", "写状态", "写JSON",
              "分片转写", "跑复核", "原子写文本", "清理临时残留")
    for _名 in 写盘步骤:
        _原 = 步骤[_名]
        步骤[_名] = (
            lambda 原: lambda *位置参数, **关键字参数: 原(
                *位置参数, **关键字参数, 开工ID=开工ID)
        )(_原)

    注册表 = 步骤["读取模式注册表"]()
    参数 = {"源文件路径": 源文件路径, "导出路径": 导出路径, "缓存目录": 缓存目录, "模式": 模式,
            "分片秒数": 分片秒数, "附加术语": 附加术语, "模型配置": 模型配置, "超时秒": 超时秒,
            "输出结构": 输出结构, "附加要求": 附加要求}
    错误 = 步骤["校验入参"](参数, 注册表)
    if 错误:
        return 错误
    模式条目 = 步骤["取模式"](模式) or {}
    缓存 = 步骤["准备缓存"](缓存目录)
    源文件 = Path(源文件路径).expanduser().resolve()
    大小 = _底座("文件系统支持库.文件操作.获取大小", {"文件路径": str(源文件)})
    指纹 = {"源文件": str(源文件), "源文件大小字节": int(getattr(大小, "值", 0) or 0),
            "源文件摘要": 步骤["计算文件摘要"](str(源文件)), "模式": 模式, "分片秒数": 分片秒数,
            "附加术语": 附加术语, "输出结构": 输出结构, "附加要求": 附加要求,
            "模型名": str((模型配置 or {}).get("模型名") or ""),
            "创建时间": 步骤["现在文本"]()}
    已续跑 = 步骤["指纹一致"](步骤["读指纹"](缓存), 指纹)
    落盘问题: list[str] = []
    _记账落盘(落盘问题, "任务指纹（00_元数据/任务指纹.json）", 步骤["写指纹"](缓存, 指纹))
    _记账落盘(落盘问题, "项目状态（00_元数据/项目状态.json）",
             步骤["写状态"](缓存, {"状态": "处理中", "阶段": "原始转写", "源文件": str(源文件), "模式": 模式,
                            "模式名称": str(模式条目.get("名称") or ""), "续跑": 已续跑}))

    探测 = _调用(探测能力, {"文件路径": str(源文件), "超时秒": 60.0})
    if not 探测.成功:
        return _失败(缓存, 探测.错误码 or "媒体探测失败", 探测.错误说明 or "媒体探测失败", "原始转写",
                   写状态=步骤["写状态"])
    探测值 = 探测.值 or {}
    if not _有音轨(探测值.get("流")):
        return _失败(缓存, "无音轨", "源文件没有音频轨，无法转写", "原始转写", 写状态=步骤["写状态"])
    时长秒 = float(探测值.get("时长秒") or 0.0)

    分片结果 = 步骤["分片转写"](str(源文件), 缓存, 时长秒, 分片秒数, _调用,
                        模型配置=模型配置, 附加术语=附加术语,
                        超时秒=max(120.0, min(float(超时秒), 1800.0)), 续跑=已续跑)
    分片转写列表 = 分片结果["分片转写列表"]
    if not 分片转写列表:
        return _失败(缓存, "转写失败", 分片结果["错误说明"] or "所有分片转写失败", "原始转写",
                   写状态=步骤["写状态"])
    语言 = str(分片转写列表[0].get("语言") or "")
    分段列表 = 步骤["全部分段"](分片转写列表)
    if not 分段列表 and not any(str(项.get("文本") or "").strip() for 项 in 分片转写列表):
        return _失败(缓存, "转写失败", "转写未返回任何文本", "原始转写", 写状态=步骤["写状态"])
    if not _写底稿行(缓存, 分段列表, 开工ID):
        return _失败(缓存, "写入失败", "无法写原始逐字稿底稿", "原始转写", 写状态=步骤["写状态"])
    _记账落盘(落盘问题, "项目状态（疑难标记阶段）",
             步骤["写状态"](缓存, {"状态": "处理中", "阶段": "疑难标记", "源文件": str(源文件), "时长秒": 时长秒,
                            "模式": 模式, "模式名称": str(模式条目.get("名称") or ""),
                            "分片": f"{分片结果['已完成']}/{分片结果['分片总数']}（复用 {分片结果['复用']}）",
                            "转写状态": 分片结果["状态"]}))

    疑难 = 步骤["标记疑难"](分片转写列表)
    if 疑难.get("成功") is 假 or 疑难.get("错误码"):
        # 疑难标记内部异常时返回的是「空数据 + 成功=False + 错误码」；
        # 不判它等同于「真无疑难」——幻觉重复会直接进正文，不允许据此产出交付稿。
        # （γ 批跨路依赖点，2026-09-17 父会话合并）
        return _失败(缓存, "质检不通过",
                    "疑难标记未完成（" + str(疑难.get("错误码") or "未知") + "）："
                    + str(疑难.get("错误说明") or "")
                    + "——该失败等同于「零疑难」，不得据此产出交付稿",
                    "疑难标记", 写状态=步骤["写状态"])
    _记账落盘(落盘问题, "疑难清单（04_疑难清单.json）", 步骤["写JSON"](缓存["疑难清单"], 疑难))
    死循环区间 = 疑难.get("死循环区间") or []
    有效分段列表 = 步骤["清洗分段"](分段列表, 死循环区间)
    折叠数 = 0
    if 模式 != 7:  # 模式7 是 1:1 还原稿，必须原样保留重复
        有效分段列表, 折叠数 = 步骤["折叠循环话术"](有效分段列表)
    剔除信息 = 步骤["剔除摘要"](分段列表, 死循环区间, 有效分段列表)
    剔除信息["循环话术折叠"] = 折叠数
    有效底稿文本 = 步骤["有效文本"](有效分段列表)
    if not _写文本(缓存["根"] / "02_转录底稿" / "03_有效底稿.txt", 有效底稿文本 + "\n", 开工ID):
        return _失败(缓存, "写入失败", "无法写有效底稿", "疑难标记", 写状态=步骤["写状态"])
    区间表 = 步骤["聚类区间"](疑难.get("疑难段") or [])
    _记账落盘(落盘问题, "复核区间表（05_复核区间.json）", 步骤["写JSON"](缓存["复核区间"], 区间表))
    复核结果 = 步骤["跑复核"](str(源文件), 区间表, str(缓存["复核"]), _调用,
                        模型配置=模型配置, 超时秒=max(120.0, min(float(超时秒), 600.0)),
                        轮数=复核轮数, 复核区间函数=步骤["复核区间"])
    证据文本 = 步骤["证据包文本"](有效分段列表, 复核结果, 死循环区间, 附加术语,
                        生成证据包函数=步骤["生成证据包"])
    if not _写文本(缓存["证据包"] / "证据包.md", 证据文本, 开工ID):
        return _失败(缓存, "写入失败", "无法写证据包", "裁决", 写状态=步骤["写状态"])
    _记账落盘(落盘问题, "项目状态（裁决阶段）",
             步骤["写状态"](缓存, {"状态": "处理中", "阶段": "裁决", "源文件": str(源文件), "时长秒": 时长秒,
                            "模式": 模式, "模式名称": str(模式条目.get("名称") or ""),
                            "疑难段数": len(疑难.get("疑难段") or []),
                            "复核区间数": len(区间表.get("区间") or []),
                            "死循环剔除": 剔除信息, "复核": 步骤["复核摘要"](复核结果)}))

    窗口列表 = 步骤["合并短窗"](步骤["切窗口"](有效分段列表, 默认窗口秒))
    步骤["关联疑难"](窗口列表, 疑难.get("疑难段") or [])
    步骤["挂证据"](窗口列表, 复核结果.get("复核列表") or [])
    裁决结果 = 步骤["裁决窗口列表"](窗口列表, 步骤["取裁决提示词"](模式), _调用, 裁决模型配置, 附加术语,
                        重试次数=裁决重试次数, 前置提示词=步骤["取前置提示词"](模式),
                        输出结构=输出结构, 附加要求=附加要求, 外部句柄=裁决模型句柄,
                        已有窗口=_读已有裁决(缓存["裁决"]))
    段落列表 = 裁决结果.get("段落列表") or []
    if not 段落列表:
        return _失败(缓存, "裁决失败", 裁决结果.get("错误说明") or "裁决未产出任何段落", "裁决",
                   写状态=步骤["写状态"])
    for 段落 in 段落列表:
        窗口号 = int(段落.get("区间id") or 0)
        _记账落盘(落盘问题, f"裁决窗口产物（08_裁决/窗口_{窗口号:04d}.json）",
                 步骤["写JSON"](缓存["裁决"] / f"窗口_{窗口号:04d}.json",
                          {"区间id": 段落.get("区间id"), "开始秒": 段落.get("开始秒"), "结束秒": 段落.get("结束秒"),
                           "精校文本": 段落.get("精校文本"), "状态": 段落.get("状态"), "错误说明": 段落.get("错误说明"),
                           # 输入指纹：下次同输入直接复用（提速方案 2a）
                           "输入指纹": 段落.get("输入指纹") or ""}))

    元信息 = {"源文件": str(源文件), "标题": _场次标题(源文件), "模式": 模式,
            "模式名称": str(模式条目.get("名称") or ""),
            "时长秒": 时长秒, "语言": 语言,
            "生成时间": 步骤["现在文本"](), "死循环区间": 死循环区间, "已续跑": 已续跑}
    全文 = 步骤["压缩段内重复"](步骤["统一数字形式"](步骤["合成全文"](模式条目, 段落列表, 元信息)))
    if not _写文本(缓存["合成"] / "全文.md", 全文, 开工ID):
        return _失败(缓存, "写入失败", "无法写合成全文", "合成", 写状态=步骤["写状态"])

    底稿文本 = 有效底稿文本
    # 上游状态取值以实现为准（不猜）：
    #   分片结果["状态"]：完成 / 部分失败（实现/分片转写.py）
    #   复核结果["状态"]：完成 / 无需复核 / 部分失败 / 失败（实现/复核编排.py）
    分片状态 = str(分片结果.get("状态") or "")
    复核状态 = str(复核结果.get("状态") or "")
    报告 = 步骤["质检"](底稿文本, 全文, 模式条目)
    报告.update({"裁决窗口复用": {"复用": 裁决结果.get("复用窗口数"), "重跑": 裁决结果.get("重跑窗口数")},
                "模式": 步骤["模式摘要"](模式), "裁决模型": 裁决结果.get("模型") or "",
                "复核": 步骤["复核摘要"](复核结果), "死循环剔除": 剔除信息,
                "时间": 步骤["现在文本"]()})
    # ── 硬判据：交付门禁（只判「分片列表非空」会把整片丢失当完成交付）──
    报告["分片"] = {"状态": 分片状态, "已完成": 分片结果.get("已完成"), "分片总数": 分片结果.get("分片总数"),
                  "复用": 分片结果.get("复用"), "错误说明": str(分片结果.get("错误说明") or "")}
    报告["复核状态"] = 复核状态
    if 分片状态 != "完成":
        报告["通过"] = 假
        报告.setdefault("失败原因", []).append(
             f"分片转写未完成（状态「{分片状态}」，{分片结果.get('已完成')}/{分片结果.get('分片总数')} 片成功"
             f"{'，' + str(分片结果.get('错误说明')) if 分片结果.get('错误说明') else ''}）"
             "：内容整段缺失，不允许当交付稿")
    if 复核状态 not in ("完成", "无需复核"):
        报告["通过"] = 假
        报告.setdefault("失败原因", []).append(
             f"复核未完成（状态「{复核状态}」，{复核结果.get('完成数', 0)}/{复核结果.get('区间数', 0)} 个区间完成"
             f"{'，' + str(复核结果.get('错误说明')) if 复核结果.get('错误说明') else ''}）")
    _汇总落盘(报告, 落盘问题)
    失败窗口 = [段 for 段 in 段落列表 if str(段.get("状态") or "") != "完成"]
    报告["裁决失败窗口"] = len(失败窗口)
    if 失败窗口:
        报告["通过"] = 假
        报告.setdefault("失败原因", []).append(
             f"裁决失败 {len(失败窗口)} 个窗口（未精校内容不允许当交付稿）")
    _记账落盘(落盘问题, "质检报告（10_质检/质检报告.json）", 步骤["写JSON"](缓存["质检"] / "质检报告.json", 报告))
    _汇总落盘(报告, 落盘问题)   # 质检报告自身没落盘同样影响 通过

    if not 报告.get("通过"):
        步骤["写状态"](缓存, {"状态": "质检未通过（未导出）", "阶段": "质检", "源文件": str(源文件),
                      "时长秒": 时长秒, "模式": 模式, "模式名称": str(模式条目.get("名称") or ""),
                      "死循环剔除": 剔除信息, "复核": 步骤["复核摘要"](复核结果),
                      "落盘问题": 落盘问题,
                      "质检": {"通过": 假, "长度比": 报告.get("长度比"),
                             "数字保留率": 报告.get("数字保留率"),
                             "异常残句": 报告.get("异常残句")},
                      "导出": "未写入（质检不通过，导出路径不落半成品）"})
        return 结果.失败("质检不通过",
                        "；".join(报告.get("失败原因") or ["质检未通过"]),
                        来源=来源,
                        详情={"缓存目录": str(缓存["根"]), "质检": 报告,
                             "导出路径": "未写入（质检不通过）"})

    导出 = 步骤["原子写文本"](导出路径, 全文)
    if not 导出.成功:
        return _失败(缓存, 导出.错误码 or "写入失败", 导出.错误说明 or "导出失败", "导出",
                   写状态=步骤["写状态"])
    步骤["清理临时残留"](str(Path(导出路径).expanduser().parent))

    值 = {"精校稿路径": str((导出.值 or {}).get("导出路径") or 导出路径), "模式": 模式,
         "模式名称": str(模式条目.get("名称") or ""), "字数": len(全文), "时长秒": 时长秒,
         "质检": 报告, "缓存目录": str(缓存["根"]), "复核": 步骤["复核摘要"](复核结果),
         "状态": "已完成"}
    终态落盘 = 步骤["写状态"](缓存, {"状态": 值["状态"], "阶段": "导出", "源文件": str(源文件), "时长秒": 时长秒,
                  "模式": 模式, "模式名称": 值["模式名称"], "文本长度": len(全文),
                  "疑难段数": len(疑难.get("疑难段") or []), "复核区间数": len(区间表.get("区间") or []),
                  "死循环剔除": 剔除信息, "复核": 步骤["复核摘要"](复核结果),
                  "质检": {"通过": bool(报告.get("通过")), "长度比": 报告.get("长度比"),
                         "数字保留率": 报告.get("数字保留率")},
                  "精校稿路径": 值["精校稿路径"]})
    if not _记账落盘(落盘问题, "最终项目状态（00_元数据/项目状态.json）", 终态落盘):
        # 成品已落盘，但终态没写上：对外不得声称「已完成」（不伪造成功）
        值["状态"] = "已导出（项目状态落盘失败）"
    return 结果.成功结果(值)
