"""直播逐字稿全自动精校主流程（唯一对外能力的实现主体）。

输入：源文件绝对路径 + 导出路径 + 缓存目录 + 模式号（可选分片秒数/附加术语/模型配置/裁决模型配置）。
过程：入参校验 → 探测媒体 → 转写（带分段指标）→ 疑难标记 → 疑难聚类 → 窗口切分 →
      逐窗裁决（按模式提示词）→ 按模式排版合成 → 质检硬门禁 → 原子导出。
用户只看到 导出路径 那一个文件；中间产物全部落缓存目录，可断点续跑。
"""

from __future__ import annotations

from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 模块库.直播逐字稿.实现.入参校验 import 校验入参
from 模块库.直播逐字稿.实现.导出落盘 import 原子写文本, 清理临时残留
from 模块库.直播逐字稿.实现.排版合成 import 合成全文, 统一数字形式
from 模块库.直播逐字稿.实现.模式注册表 import 读取模式注册表, 取模式, 取裁决提示词, 模式摘要
from 模块库.直播逐字稿.实现.缓存与续跑 import (准备缓存, 写JSON, 写指纹, 写状态,
                                       指纹一致, 现在文本, 计算文件摘要, 读指纹)
from 模块库.直播逐字稿.实现.复核调度 import 聚类区间
from 模块库.直播逐字稿.实现.复核编排 import 挂证据, 复核摘要, 跑复核, 证据包文本
from 模块库.直播逐字稿.实现.质检门禁 import 质检
from 模块库.直播逐字稿.实现.疑难标记 import 标记疑难
from 模块库.直播逐字稿.实现.窗口切分 import 全部分段, 合并短窗, 切窗口, 关联疑难
from 模块库.直播逐字稿.实现.精校裁决 import 裁决窗口列表

来源 = "直播逐字稿"
探测能力 = "媒体处理支持库.FFmpeg媒体.探测媒体"
转写能力 = "转写支持库.转写.转写音频文件"
默认窗口秒 = 900
复核轮数 = 3


def _调用(能力id: str, 参数: dict) -> 结果:
    """经唯一能力调用服务调用底层能力；未装配或异常时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源)
    except Exception as 错误:
        return 结果.失败("提供者不可用", f"{能力id} 调用失败: {错误}", 来源=来源)


def _失败(缓存: dict | None, 错误码: str, 错误说明: str, 阶段: str = "") -> 结果:
    详情 = {}
    if 缓存:
        写状态(缓存, {"状态": "失败", "阶段": 阶段, "错误码": 错误码, "错误说明": 错误说明})
        详情["缓存目录"] = str(缓存["根"])
        详情["阶段"] = 阶段
    return 结果.失败(错误码, 错误说明, 来源=来源, 详情=详情)


def _有音轨(流列表) -> bool:
    if not isinstance(流列表, list):
        return True
    for 流 in 流列表:
        if isinstance(流, dict) and str(流.get("编码类型") or 流.get("codec_type") or "").lower() == "audio":
            return True
    return False


def _写底稿行(缓存: dict, 分段列表: list[dict]) -> None:
    """把逐句底稿写成 02_转录底稿/03_原始逐字稿.txt（[开始-结束] 文本）。"""
    目标 = 缓存["根"] / "02_转录底稿" / "03_原始逐字稿.txt"
    目标.parent.mkdir(parents=True, exist_ok=True)
    行 = [f"[{段['开始秒']:06.1f}-{段['结束秒']:06.1f}] {段['文本']}" for 段 in 分段列表 if 段["文本"]]
    目标.write_text("\n".join(行) + "\n", encoding="utf-8")


def 全自动精校(源文件路径: str, 导出路径: str, 缓存目录: str, 模式: int,
                分片秒数: int = 300, 附加术语: str = "", 模型配置: dict | None = None,
                裁决模型配置: dict | None = None, 超时秒: float = 3600.0) -> 结果:
    """一次调用完成：视频/音频绝对路径 → 精校逐字稿（导出路径）。"""
    注册表 = 读取模式注册表()
    参数 = {"源文件路径": 源文件路径, "导出路径": 导出路径, "缓存目录": 缓存目录, "模式": 模式,
            "分片秒数": 分片秒数, "附加术语": 附加术语, "模型配置": 模型配置, "超时秒": 超时秒}
    错误 = 校验入参(参数, 注册表)
    if 错误:
        return 错误
    模式条目 = 取模式(模式) or {}
    缓存 = 准备缓存(缓存目录)
    源文件 = Path(源文件路径).expanduser().resolve()
    指纹 = {"源文件": str(源文件), "源文件大小字节": 源文件.stat().st_size,
            "源文件摘要": 计算文件摘要(str(源文件)), "模式": 模式, "分片秒数": 分片秒数,
            "附加术语": 附加术语, "模型名": str((模型配置 or {}).get("模型名") or ""),
            "创建时间": 现在文本()}
    已续跑 = 指纹一致(读指纹(缓存), 指纹)
    写指纹(缓存, 指纹)
    写状态(缓存, {"状态": "处理中", "阶段": "原始转写", "源文件": str(源文件), "模式": 模式,
                  "模式名称": str(模式条目.get("名称") or ""), "续跑": 已续跑})

    探测 = _调用(探测能力, {"文件路径": str(源文件), "超时秒": 60.0})
    if not 探测.成功:
        return _失败(缓存, 探测.错误码 or "媒体探测失败", 探测.错误说明 or "媒体探测失败", "原始转写")
    探测值 = 探测.值 or {}
    if not _有音轨(探测值.get("流列表")):
        return _失败(缓存, "无音轨", "源文件没有音频轨，无法转写", "原始转写")
    时长秒 = float(探测值.get("时长秒") or 0.0)

    转写 = _调用(转写能力, {"文件路径": str(源文件), "超时秒": 超时秒, "配置": 模型配置,
                          "附加术语": 附加术语, "返回分段": True})
    if not 转写.成功:
        return _失败(缓存, 转写.错误码 or "转写失败", 转写.错误说明 or "转写失败", "原始转写")
    转写值 = 转写.值 or {}
    分段原始 = 转写值.get("分段") if isinstance(转写值.get("分段"), list) else []
    分片转写列表 = [{"分片序号": 1, "开始秒": 0.0, "结束秒": 时长秒,
                 "文本": str(转写值.get("文本") or ""), "分段": 分段原始}]
    if not 分片转写列表[0]["文本"].strip() and not 分段原始:
        return _失败(缓存, "转写失败", "转写未返回任何文本", "原始转写")
    写JSON(缓存["分片转写"] / "分片_0001.json", 分片转写列表[0])
    分段列表 = 全部分段(分片转写列表)
    _写底稿行(缓存, 分段列表)

    疑难 = 标记疑难(分片转写列表)
    写JSON(缓存["疑难清单"], 疑难)
    区间表 = 聚类区间(疑难.get("疑难段") or [])
    写JSON(缓存["复核区间"], 区间表)
    复核结果 = 跑复核(str(源文件), 区间表, str(缓存["复核"]), _调用,
                   模型配置=模型配置, 超时秒=max(120.0, min(float(超时秒), 600.0)),
                   轮数=复核轮数)
    (缓存["证据包"] / "证据包.md").write_text(
        证据包文本(分段列表, 复核结果, 疑难.get("死循环区间") or [], 附加术语), encoding="utf-8")
    写状态(缓存, {"状态": "处理中", "阶段": "裁决", "源文件": str(源文件), "时长秒": 时长秒,
                  "模式": 模式, "模式名称": str(模式条目.get("名称") or ""),
                  "疑难段数": len(疑难.get("疑难段") or []),
                  "复核区间数": len(区间表.get("区间") or []),
                  "复核": 复核摘要(复核结果)})

    窗口列表 = 合并短窗(切窗口(分段列表, 默认窗口秒))
    关联疑难(窗口列表, 疑难.get("疑难段") or [])
    挂证据(窗口列表, 复核结果.get("复核列表") or [])
    裁决结果 = 裁决窗口列表(窗口列表, 取裁决提示词(模式), _调用, 裁决模型配置, 附加术语)
    段落列表 = 裁决结果.get("段落列表") or []
    if not 段落列表:
        return _失败(缓存, "裁决失败", 裁决结果.get("错误说明") or "裁决未产出任何段落", "裁决")
    for 段落 in 段落列表:
        写JSON(缓存["裁决"] / f"窗口_{int(段落.get('区间id') or 0):04d}.json",
               {"区间id": 段落.get("区间id"), "开始秒": 段落.get("开始秒"), "结束秒": 段落.get("结束秒"),
                "精校文本": 段落.get("精校文本"), "状态": 段落.get("状态"), "错误说明": 段落.get("错误说明")})

    元信息 = {"源文件": str(源文件), "模式": 模式, "模式名称": str(模式条目.get("名称") or ""),
            "时长秒": 时长秒, "语言": str(转写值.get("语言") or ""),
            "生成时间": 现在文本(), "死循环区间": 疑难.get("死循环区间") or [], "已续跑": 已续跑}
    全文 = 统一数字形式(合成全文(模式条目, 段落列表, 元信息))
    (缓存["合成"] / "全文.md").write_text(全文, encoding="utf-8")

    底稿文本 = "".join(段["文本"] for 段 in 分段列表)
    报告 = 质检(底稿文本, 全文, 模式条目)
    报告.update({"模式": 模式摘要(模式), "裁决模型": 裁决结果.get("模型") or "",
                "复核": 复核摘要(复核结果), "时间": 现在文本()})
    写JSON(缓存["质检"] / "质检报告.json", 报告)

    导出 = 原子写文本(导出路径, 全文)
    if not 导出.成功:
        return _失败(缓存, 导出.错误码 or "写入失败", 导出.错误说明 or "导出失败", "导出")
    清理临时残留(str(Path(导出路径).expanduser().parent))

    值 = {"精校稿路径": str((导出.值 or {}).get("导出路径") or 导出路径), "模式": 模式,
         "模式名称": str(模式条目.get("名称") or ""), "字数": len(全文), "时长秒": 时长秒,
         "质检": 报告, "缓存目录": str(缓存["根"]), "复核": 复核摘要(复核结果),
         "状态": "已完成" if 报告.get("通过") else "已完成（质检未通过，见质检报告）"}
    写状态(缓存, {"状态": 值["状态"], "阶段": "导出", "源文件": str(源文件), "时长秒": 时长秒,
                  "模式": 模式, "模式名称": 值["模式名称"], "文本长度": len(全文),
                  "疑难段数": len(疑难.get("疑难段") or []), "复核区间数": len(区间表.get("区间") or []),
                  "复核": 复核摘要(复核结果),
                  "质检": {"通过": bool(报告.get("通过")), "长度比": 报告.get("长度比"),
                         "数字保留率": 报告.get("数字保留率")},
                  "精校稿路径": 值["精校稿路径"]})
    if not 报告.get("通过"):
        return 结果.失败("质检不通过",
                        "；".join(报告.get("失败原因") or ["质检未通过"]),
                        来源=来源, 详情=值)
    return 结果.成功结果(值)
