"""复核编排：对疑难区间跑多轮复核、生成证据包留档、把证据挂到裁决窗口。

复核只对疑难区间做（聚类后），既不重复整场转写，也不把证据整包塞进模型。
复核失败不静默降级：状态与错误说明如实回传，裁决阶段按可得证据继续并标注。
"""

from __future__ import annotations

默认轮数 = 3


def 底稿行(分段列表: list[dict]) -> list[str]:
    """把逐句底稿转成 [开始-结束] 文本 的行列表（供证据包引用）。"""
    return [f"[{段.get('开始秒'):06.1f}-{段.get('结束秒'):06.1f}] {段.get('文本')}"
            for 段 in (分段列表 or []) if str(段.get("文本") or "").strip()]


def _异常复核(区间, 错误: BaseException) -> dict:
    """单区间复核抛异常时的失败条目：与 复核调度.复核区间 的失败返回值同构。

    注入的 复核区间 实现（复核调度.复核区间）在参数与外层校验之外仍可能抛异常
    （实测：内部缺陷直接 RuntimeError）。异常必须被兜成「该区间状态=失败」的
    正常返回值，不能让整场复核裸崩，也不能把异常吞成「复核通过」。
    """
    区间表 = 区间 if isinstance(区间, dict) else {}
    区间id = 区间表.get("区间id")
    return {"区间id": 区间id if isinstance(区间id, int) and not isinstance(区间id, bool) else 0,
            "开始秒": 区间表.get("开始秒"), "结束秒": 区间表.get("结束秒"),
            "轮次": [], "状态": "失败", "错误码": "调用异常",
            "错误说明": f"复核区间 内部异常: {type(错误).__name__}: {错误}",
            "区间音频路径": "", "写入路径": ""}


def 跑复核(源文件路径: str, 区间表: dict, 复核目录: str, 调用能力,
           模型配置: dict | None = None, 超时秒: float = 600.0,
           轮数: int = 默认轮数, 续跑: bool = True, *, 复核区间函数=None) -> dict:
    """对每个区间跑复核（已落盘可复用）；返回 {复核列表, 状态, 错误说明, 区间数, 完成数}。

    单区间复核实现（复核调度.复核区间）由调用方注入，本文件不 import 兄弟模块。
    单区间抛异常不裸崩：该区间按 状态=失败 记账（错误码 调用异常），其余区间照跑。
    """
    区间列表 = (区间表 or {}).get("区间") if isinstance(区间表, dict) else []
    区间列表 = 区间列表 if isinstance(区间列表, list) else []
    if not 区间列表:
        return {"复核列表": [], "状态": "无需复核", "错误说明": "", "区间数": 0, "完成数": 0}
    if not callable(复核区间函数):
        return {"复核列表": [], "状态": "失败", "错误说明": "复核区间 未装配",
                "区间数": len(区间列表), "完成数": 0}
    复核列表: list[dict] = []
    说明表: list[str] = []
    for 区间 in 区间列表:
        try:
            复核 = 复核区间函数(源文件路径, 区间, 复核目录, 调用能力,
                            轮数=轮数, 模型配置=模型配置, 超时秒=超时秒, 续跑=续跑)
        except Exception as 错误:  # 单区间异常不得裸崩整场复核，其余区间继续
            复核 = _异常复核(区间, 错误)
        if not isinstance(复核, dict):  # 注入实现返回非字典同样按失败记账，不裸崩
            复核 = _异常复核(区间, TypeError(f"复核区间 返回非字典: {type(复核).__name__}"))
        复核列表.append(复核)
        if 复核.get("状态") != "完成":
            说明表.append(f"区间{复核.get('区间id')}: {复核.get('错误说明') or 复核.get('错误码')}")
    完成数 = len([项 for 项 in 复核列表 if 项.get("状态") == "完成"])
    return {"复核列表": 复核列表,
            "状态": "完成" if 完成数 == len(复核列表) else "部分失败",
            "错误说明": "；".join(说明表), "区间数": len(复核列表), "完成数": 完成数}


def 证据包文本(分段列表: list[dict], 复核结果: dict, 死循环区间: list[dict],
              附加术语: str, *, 生成证据包函数=None) -> str:
    """生成整包证据（留档给人工核对，不整包进模型）。

    证据包实现（证据包.生成证据包）由调用方注入；未装配时返回空串。
    """
    if not callable(生成证据包函数):
        return ""
    return 生成证据包函数(底稿行(分段列表), (复核结果 or {}).get("复核列表") or [],
                    死循环区间 or [], 附加术语)


def 挂证据(窗口列表: list[dict], 复核列表: list[dict], 每窗最长字符: int = 2500) -> None:
    """把落在各窗口时间范围内的复核轮次文本挂到窗口 证据文本（就地修改）。

    证据整包灌入会把单窗请求体撑到上万字（实测单窗 2575~10339 字，600 字输入约 39 秒），
    所以按窗口截断到 每窗最长字符；超出部分如实标注，不假装完整。
    """
    for 窗口 in 窗口列表 or []:
        片段: list[str] = []
        for 复核 in 复核列表 or []:
            try:
                开始 = float(复核.get("开始秒") or 0.0)
            except (TypeError, ValueError):
                continue
            if not (窗口.get("开始秒", 0.0) <= 开始 <= 窗口.get("结束秒", 0.0)):
                continue
            for 轮次 in 复核.get("轮次") or []:
                文本 = str(轮次.get("文本") or "").strip()
                片段.append(f"第{轮次.get('轮')}轮识别：{文本 or '（空）'}")
        全文 = "\n".join(片段)
        if 每窗最长字符 > 0 and len(全文) > 每窗最长字符:
            全文 = 全文[:每窗最长字符] + f"\n（证据过长，已截断至 {每窗最长字符} 字）"
        窗口["证据文本"] = 全文


def 复核摘要(复核结果: dict) -> str:
    """给状态/返回值用的简短复核摘要。"""
    if not 复核结果:
        return "未启用"
    状态 = str(复核结果.get("状态") or "")
    if 状态 == "无需复核":
        return "无需复核（无疑难段）"
    摘要 = f"{状态}（{复核结果.get('完成数', 0)}/{复核结果.get('区间数', 0)} 个区间完成）"
    if 复核结果.get("错误说明"):
        摘要 += f"：{复核结果['错误说明']}"
    return 摘要
