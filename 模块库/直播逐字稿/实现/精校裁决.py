"""精校裁决：持 LLM 句柄按模式提示词逐窗精校（大语言模型支持库是本模块唯一 LLM 入口）。

裁决规则来自模式注册表的 裁决提示词；无疑难窗直接精校，有疑难窗必须看复核证据；
不确定写【听不清】/【待确认】，禁止编造。未配置裁决模型时如实失败，不静默降级。
"""

from __future__ import annotations

import os
import re
import time
from concurrent.futures import ThreadPoolExecutor

from 公共契约.基础类型.结果类型 import 结果

来源 = "直播逐字稿"
连接能力 = "大语言模型支持库.模型连接器.连接LLM"
对话能力 = "大语言模型支持库.模型连接器.生成对话"
# 裁决模型必须关思考：开源推理模型（Qwen3.6-27B/gemma-4 实测）默认开思考，token 全被
# reasoning_content 吃掉、content 返回空串，底座会把它判成「模型调用失败」HTTP 500 ——
# 表现是「裁决失败 N 个窗口」而非报模型错误，极易误判成提示词问题。chat_completions
# 协议下传本参数即关闭；anthropic 协议不支持（会明确报错，不静默降级）。
关闭思考 = {"enable_thinking": False}
释放能力 = "大语言模型支持库.模型连接器.释放句柄"
默认上下文长度 = 32768
环境前缀 = "LLM裁决_"
默认裁决并发数 = 3  # 实测同一句柄可并发（3 路各自成功、总耗时约 1/3）；裁决是整链耗时大头


def _取模型配置(模型配置: dict | None) -> dict:
    """裁决模型配置：显式配置优先，其次读环境变量 LLM裁决_*；不读取任何硬编码密钥。"""
    配置 = dict(模型配置) if isinstance(模型配置, dict) else {}
    映射 = {
        "模型": "模型",
        "提供者": "提供者",
        "部署形态": "部署形态",
        "url": "url",
        "api_key": "api_key",
        "协议": "协议",
        "上下文长度": "上下文长度",
    }
    for 键, 环境键 in 映射.items():
        if not 配置.get(键):
            值 = os.environ.get(环境前缀 + 环境键, "").strip()
            if 值:
                配置[键] = int(值) if 环境键 == "上下文长度" and 值.isdigit() else 值
    return 配置


def 检查裁决配置(模型配置: dict | None) -> 结果 | None:
    """校验裁决模型配置齐全；缺项返回 结果.失败（未配置模型）。"""
    配置 = _取模型配置(模型配置)
    if not 配置.get("模型"):
        return 结果.失败("未配置模型", f"未提供裁决模型配置（参数 裁决模型配置 或环境变量 {环境前缀}模型）", 来源=来源)
    if not 配置.get("部署形态"):
        配置["部署形态"] = "云端" if 配置.get("url") else "本地"
    if 配置.get("部署形态") == "云端" and not (配置.get("url") and 配置.get("api_key")):
        return 结果.失败("未配置模型", "云端裁决模型必须提供 url 与 api_key", 来源=来源)
    return None


def 连接裁决模型(调用能力, 模型配置: dict | None) -> 结果:
    """连接裁决模型并返回句柄（值={句柄, 模型}）。"""
    错误 = 检查裁决配置(模型配置)
    if 错误:
        return 错误
    配置 = _取模型配置(模型配置)
    参数 = {
        "模型": 配置.get("模型"),
        "提供者": 配置.get("提供者") or "本地",
        "部署形态": 配置.get("部署形态"),
        "url": 配置.get("url"),
        "api_key": 配置.get("api_key"),
        "协议": 配置.get("协议") or "chat_completions",
        "上下文长度": int(配置.get("上下文长度") or 默认上下文长度),
        "超时秒": int(配置.get("超时秒") or 1800),
    }
    # 内存估算系数 必须能透传：内存守卫按「模型大小 × 系数」预估，系数偏保守时
    # 会把装得下的模型判成装不下（实测 19.8GB 模型按 1.15 估成 22.8GB，
    # 而真实 RSS 是 21.4GB）→ 整场精校在裁决阶段白跑。调用方可按实测值校准。
    for 可选 in ("本地路径", "启动器", "模型大小字节", "内存估算系数"):
        if 配置.get(可选):
            参数[可选] = 配置[可选]
    结果对象 = 调用能力(连接能力, 参数)
    if not 结果对象.成功:
        return 结果.失败("提供者不可用", f"裁决模型连接失败: {结果对象.错误说明}", 来源=来源)
    值 = 结果对象.值 or {}
    return 结果.成功结果({"句柄": 值.get("句柄"), "模型": 值.get("模型") or 配置.get("模型")})


def 释放裁决模型(调用能力, 句柄) -> None:
    """释放句柄（幂等；失败不影响主流程）。"""
    if 句柄 is None:
        return
    try:
        调用能力(释放能力, {"句柄": 句柄})
    except Exception:
        return


def 构造消息(窗口: dict, 术语表: str = "", 底稿文本: str | None = None,
             底稿标签: str = "原始识别") -> list[dict]:
    """把术语表、窗口底稿、疑难说明与复核证据拼成一条用户消息。

    术语表用强约束措辞（原样使用、禁止改写/同音替换），用于压制品牌词被模型顺手改写。
    两阶段总结时用 底稿文本/底稿标签 传入第一阶段已精校的文本。
    """
    片段: list[str] = []
    if str(术语表 or "").strip():
        片段 += ["【术语表·强制】以下词必须原样出现在稿件里，禁止改写、禁止同音替换、禁止翻译：",
               str(术语表).strip(), ""]
    文本 = 窗口.get("底稿文本") if 底稿文本 is None else 底稿文本
    片段 += [f"【时间范围】{窗口.get('开始秒')} - {窗口.get('结束秒')} 秒", "",
            f"【{底稿标签}】", str(文本 or "（空）")]
    if 窗口.get("疑难说明"):
        片段 += ["", "【需重点核对】", str(窗口["疑难说明"])]
    if 窗口.get("证据文本"):
        片段 += ["", "【多轮复核证据】", str(窗口["证据文本"])]
    return [{"role": "user", "content": "\n".join(片段)}]


def 渲染提示词(提示词: str, 输出结构: str = "", 附加要求: str = "") -> str:
    """把模式提示词里的 {输出结构} / {附加要求} 占位符换成调用方传入的内容。

    底座只提供通用框架（做什么、禁止什么）；业务细节——分节结构、易错词校正、
    行业口径——必须由消费者通过参数传进来，不写死在底座里。
    """
    文本 = str(提示词 or "")
    结构 = str(输出结构 or "").strip() or "按内容自然分节"
    文本 = 文本.replace("{输出结构}", 结构)
    要件 = str(附加要求 or "").strip()
    文本 = 文本.replace("{附加要求}", f"【调用方要求】{要件}" if 要件 else "")
    return re.sub(r"\n{3,}", "\n\n", 文本).strip()


def 裁决窗口(窗口: dict, 提示词: str, 句柄, 调用能力, 术语表: str = "",
             超时秒: float = 600.0, 前置提示词: str = "",
             输出结构: str = "", 附加要求: str = "") -> dict:
    """对单个窗口裁决；有前置提示词时先做一遍逐句精校，再按本模式提示词处理。

    两阶段用于总结类模式：直接在原始识别上总结会诱发同音替换（斑→班、美业→每夜），
    先精校再总结可显著降低改写错误。失败不伪造内容，状态置 待确认。
    """
    基础 = {"区间id": 窗口.get("窗口id"), "开始秒": 窗口.get("开始秒"),
            "结束秒": 窗口.get("结束秒"), "精校文本": "", "状态": "失败", "错误说明": ""}
    工作底稿 = 窗口.get("底稿文本") or ""
    底稿标签 = "原始识别"
    证据窗口 = 窗口
    if str(前置提示词 or "").strip():
        前置 = 调用能力(对话能力, {"句柄": 句柄, "消息列表": 构造消息(窗口, 术语表),
                                  "系统提示词": 前置提示词, "流式输出": False,
                                  "chat_template_kwargs": 关闭思考})
        前置文本 = str((前置.值 or {}).get("回复") or "").strip() if 前置.成功 else ""
        if not 前置文本:
            基础["错误说明"] = f"前置精校失败: {取错误说明(前置)}"
            基础["精校文本"] = f"【待确认】本段前置精校失败，保留原始识别：\n{工作底稿}"
            return 基础
        工作底稿 = 前置文本
        底稿标签 = "已精校文本（只做删减合并，禁止改词）"
        证据窗口 = {**窗口, "疑难说明": "", "证据文本": ""}
    结果对象 = 调用能力(对话能力, {
        "句柄": 句柄,
        "消息列表": 构造消息(证据窗口, 术语表, 底稿文本=工作底稿, 底稿标签=底稿标签),
        "系统提示词": 渲染提示词(提示词, 输出结构, 附加要求), "流式输出": False,
        "chat_template_kwargs": 关闭思考})
    if not 结果对象.成功:
        基础["错误说明"] = f"{结果对象.错误码}: {取错误说明(结果对象)}"
        基础["精校文本"] = f"【待确认】本段裁决失败，保留原始识别：\n{工作底稿}"
        return 基础
    文本 = str((结果对象.值 or {}).get("回复") or "").strip()
    if not 文本:
        基础["错误说明"] = "裁决返回空文本"
        基础["精校文本"] = f"【待确认】本段裁决返回空文本：\n{工作底稿}"
        return 基础
    基础["精校文本"] = 文本
    基础["状态"] = "完成"
    return 基础


def 取错误说明(结果对象) -> str:
    """统一取错误说明（无则给空串）。"""
    return str(getattr(结果对象, "错误说明", "") or "")


def 上游瞬时错误(段落: dict) -> bool:
    """该窗口失败是否属于上游瞬时错误（503/超时/限流/过载）——这类重试即可自愈。

    实测某长场次 69 个裁决窗口失败 18 个，全部是「模型 HTTP 返回 503」与
    「LLM HTTP调用失败: timed out」，都属于上游瞬时过载，退避重试即可恢复。
    """
    错误 = str((段落 or {}).get("错误说明") or "")
    return any(关键字 in 错误 for 关键字 in
             ("503", "502", "429", "timed out", "超时", "限流", "过载", "繁忙"))


def 句柄失效(段落: dict) -> bool:
    """该窗口失败是否由句柄失效引起（句柄被回收，或网关重启后句柄表变化）。

    句柄默认 30 分钟无人使用即被回收，长场次跑到一半失效会让整场白跑；
    识别出来后用 模型配置 重连一次、只补这些窗口。
    """
    错误 = str((段落 or {}).get("错误说明") or "")
    return "句柄不存在" in 错误 or "句柄失效" in 错误 or "无效句柄" in 错误


def 裁决窗口列表(窗口列表: list[dict], 提示词: str, 调用能力,
                 模型配置: dict | None = None, 术语表: str = "",
                 重试次数: int = 1, 前置提示词: str = "",
                 输出结构: str = "", 附加要求: str = "",
                 外部句柄: int | None = None, 并发数: int = 默认裁决并发数) -> dict:
    """连接一次模型，逐窗裁决（失败按 重试次数 重试），最后释放句柄。

    前置提示词 非空时走两阶段：先逐句精校，再按 提示词 总结/改写。
    输出结构 / 附加要求 是调用方传进来的业务细节（底座不写死）。

    外部句柄（消费者先调 连接LLM 拿到的句柄）优先于 模型配置：此时不再连接、
    也**不释放**该句柄——句柄生命周期归消费者（谁连接谁释放）。

    并发数 >1 时多窗并行送审（实测同一句柄并发 3 路各自成功、总耗时约为串行的 1/3）：
    裁决是整条链路的耗时大头（长场次 9~10 窗串行要十几分钟），并发后成倍缩短。
    """
    if not 提示词:
        return {"段落列表": [], "模型": "", "错误说明": "模式缺少裁决提示词"}
    借用 = 外部句柄 is not None
    if 借用:
        句柄 = 外部句柄
        模型名 = "消费者句柄"
    else:
        连接 = 连接裁决模型(调用能力, 模型配置)
        if not 连接.成功:
            return {"段落列表": [], "模型": "", "错误说明": f"{连接.错误码}: {连接.错误说明}"}
        句柄 = (连接.值 or {}).get("句柄")
        模型名 = str((连接.值 or {}).get("模型") or "")
    错误说明 = ""
    重试上限 = max(0, int(重试次数 or 0))
    句柄盒 = {"当前": 句柄}   # 可变引用：句柄被回收后可在中途换新

    def 跑一窗(窗口: dict) -> dict:
        段落 = 裁决窗口(窗口, 提示词, 句柄盒["当前"], 调用能力, 术语表, 前置提示词=前置提示词,
                      输出结构=输出结构, 附加要求=附加要求)
        for 试次 in range(重试上限):
            if 段落.get("状态") == "完成":
                break
            # 上游 503/超时多为瞬时过载：退避后再试，避免一口气打满上游
            退避秒 = min(8.0, 2.0 * (试次 + 1))
            time.sleep(退避秒 if 上游瞬时错误(段落) else 0.2)
            段落 = 裁决窗口(窗口, 提示词, 句柄盒["当前"], 调用能力, 术语表, 前置提示词=前置提示词,
                          输出结构=输出结构, 附加要求=附加要求)
        return 段落

    段落列表: list[dict] = []
    线程数 = max(1, int(并发数 or 1))
    try:
        if 线程数 > 1 and len(窗口列表) > 1:
            with ThreadPoolExecutor(max_workers=线程数) as 池:
                段落列表 = list(池.map(跑一窗, 窗口列表))
        else:
            段落列表 = [跑一窗(窗口) for 窗口 in 窗口列表]
        # 句柄失效兜底：句柄默认 30 分钟无人使用即被回收（消费者传进来的句柄同样会被回收），
        # 长场次跑到一半句柄失效会让整场白跑。这里用 模型配置 重连一次、只补失败的窗口。
        句柄出错 = [段 for 段 in 段落列表 if 句柄失效(段)]
        if 句柄出错 and 模型配置:
            重连 = 连接裁决模型(调用能力, 模型配置)
            if 重连.成功:
                句柄盒["当前"] = (重连.值 or {}).get("句柄")
                借用 = False  # 重连出来的句柄由底座负责释放
                重跑 = {id(段): 段 for 段 in 句柄出错}
                索引表 = [i for i, 段 in enumerate(段落列表) if id(段) in 重跑]
                for i in 索引表:
                    段落列表[i] = 跑一窗(窗口列表[i])
    finally:
        if not 借用:
            释放裁决模型(调用能力, 句柄盒["当前"])
    错误说明 = next((str(段.get("错误说明") or "") for 段 in 段落列表
                  if 段.get("状态") != "完成" and 段.get("错误说明")), "")
    return {"段落列表": 段落列表, "模型": 模型名, "错误说明": 错误说明, "借用句柄": 借用}
