"""逐字稿质检门禁（纯计算）：按模式 质检规则 判定精校稿是否放行。

冻结接口（开发文档/临时文档/41_逐字稿精校内部接口约定.md 第四节）：
- 质检(原始文本: str, 精校文本: str, 模式: dict) -> dict

返回结构与 10_质检/质检报告.json 一致：
{"通过","长度比","数字保留率","异常残句","待确认数","模式","模式附加","失败原因"}

本文件纯计算：只做字符串/正则统计，不调用能力、不联网、不写盘。
输入不合法、或底稿为空/过短（无法做长度比判定）时返回 通过=False 并在 失败原因 写明，
不向调用方抛裸异常——空底稿绝不放行。
"""

from __future__ import annotations

import re
from collections import Counter

数字正则 = re.compile(r"\d+(?:\.\d+)?")
重复片段正则 = re.compile(r"(.{1,15}?)\1{14,}")
纯标点正则 = re.compile(r"[\W_]+")
碎片正则 = re.compile(r"[.…?？!！]+")
待确认标记 = ("【待确认】", "【听不清】")
默认最小长度比 = 0.70
默认最小数字保留率 = 0.85
禁止删减阈值 = 0.95
丢失展示上限 = 8
# 底稿去空白后不足此字数时，长度比与数字保留率都不成立（分母太小、比值无意义）：
# 直接判不通过，绝不记满分——否则「底稿为空/极短」的场次会拿到 通过=True 的假成品稿。
# 可在 模式.质检规则.最小底稿字数 覆盖（下限 1，空底稿永远不通过）。
默认最小底稿字数 = 20
最小底稿字数下限 = 1


def _去空白(文本: str) -> str:
    """去掉全部空白字符（含换行），只留可见内容。"""
    return "".join((文本 or "").split())


def _取数(规则: dict, 键: str, 默认值: float) -> float:
    """从质检规则安全取数值阈值；非法或缺失用默认值。"""
    值 = 规则.get(键) if isinstance(规则, dict) else None
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        return 默认值
    return float(值)


def 统计异常残句(文本: str) -> int:
    """异常残句数：连续重复同一片段≥15 次、只有标点或单字符的行、纯省略号/问号碎片。"""
    if not isinstance(文本, str) or not 文本:
        return 0
    次数 = 0
    for 整行 in 文本.splitlines():
        行 = 整行.strip()
        if not 行:
            continue
        重复列表 = 重复片段正则.findall(行)
        if 重复列表:
            次数 += len(重复列表)
            continue
        if len(行) == 1 or 纯标点正则.fullmatch(行) or 碎片正则.fullmatch(行):
            次数 += 1
    return 次数


def 统计待确认(文本: str) -> int:
    """【待确认】与【听不清】标记出现次数之和。"""
    if not isinstance(文本, str) or not 文本:
        return 0
    return sum(文本.count(标记) for 标记 in 待确认标记)


def _统计数字保留(原始文本: str, 精校文本: str) -> tuple[float, list[str]]:
    """数字串保留率与丢失清单（按 原始出现次数 与 精校出现次数 取小计）。"""
    原始数字 = 数字正则.findall(原始文本 or "")
    if not 原始数字:
        return 1.0, []
    精校计数 = Counter(数字正则.findall(精校文本 or ""))
    保留数 = 0
    丢失: list[str] = []
    for 数字, 次数 in Counter(原始数字).items():
        实有 = 精校计数.get(数字, 0)
        保留数 += min(次数, 实有)
        丢失.extend([数字] * max(0, 次数 - 实有))
    比值 = round(保留数 / len(原始数字), 4)
    return 比值, 丢失


def _丢失展示(丢失: list[str]) -> str:
    """丢失数字的紧凑展示（最多 8 个）。"""
    展示 = "、".join(丢失[:丢失展示上限])
    if len(丢失) > 丢失展示上限:
        展示 += f" 等 {len(丢失)} 处"
    return 展示


def 质检(原始文本: str, 精校文本: str, 模式: dict) -> dict:
    """按模式的质检规则判定精校稿：底稿有效性、长度比、数字保留率、异常残句、模式附加项。

    任一项不达标即 通过=False，并在 失败原因 里逐条写明具体数值。
    底稿去空白后为空或过短（不足 最小底稿字数，默认 20 字）时，
    长度比与数字保留率都无从判定 —— 此时 长度比/数字保留率 记 0.0 并直接判不通过
    （绝不记 1.0：底稿为空却给满分，等于放行一份没有底稿依据的假成品稿）。
    底稿够长时，原始无数字记 数字保留率=1.0（没有数字可丢）。
    """
    失败原因: list[str] = []
    原始 = 原始文本 if isinstance(原始文本, str) else ""
    精校 = 精校文本 if isinstance(精校文本, str) else ""
    模式字典 = 模式 if isinstance(模式, dict) else {}
    规则 = 模式字典.get("质检规则")
    规则 = 规则 if isinstance(规则, dict) else {}

    最小长度比 = _取数(规则, "最小长度比", 默认最小长度比)
    最小数字保留率 = _取数(规则, "最小数字保留率", 默认最小数字保留率)
    最小底稿字数 = max(最小底稿字数下限, int(_取数(规则, "最小底稿字数", 默认最小底稿字数)))
    关键数字全保留 = bool(规则.get("关键数字全保留"))
    禁止删减 = bool(规则.get("禁止删减"))

    原始去空白 = _去空白(原始)
    精校去空白 = _去空白(精校)
    底稿过短 = len(原始去空白) < 最小底稿字数
    if 底稿过短:
        长度比 = 0.0
        数字保留率, 丢失 = 0.0, []
    else:
        长度比 = round(len(精校去空白) / len(原始去空白), 4)
        数字保留率, 丢失 = _统计数字保留(原始, 精校)
    异常残句 = 统计异常残句(精校)
    待确认数 = 统计待确认(精校)

    if not isinstance(模式, dict):
        失败原因.append("模式数据不合法（应为对象），已按默认阈值判定")
    if 底稿过短:
        失败原因.append(
            f"有效底稿为空/过短，无法做长度比判定"
            f"（底稿去空白 {len(原始去空白)} 字 < 最小底稿字数 {最小底稿字数} 字）")
    else:
        if 长度比 < 最小长度比:
            失败原因.append(f"长度比 {长度比:.4f} 低于模式最小长度比 {最小长度比:g}")
        if 数字保留率 < 最小数字保留率:
            补充 = f"（丢失 {_丢失展示(丢失)}）" if 丢失 else ""
            失败原因.append(f"数字保留率 {数字保留率:.4f} 低于模式最小数字保留率 {最小数字保留率:g}{补充}")
        if 关键数字全保留 and 丢失:
            失败原因.append(f"关键数字未全部保留：丢失 {_丢失展示(丢失)}，共 {len(丢失)} 处")
        if 禁止删减 and 长度比 < 禁止删减阈值:
            失败原因.append(f"禁止删减模式下长度比 {长度比:.4f} 低于阈值 {禁止删减阈值:g}")
    if 异常残句:
        失败原因.append(f"异常残句 {异常残句} 处，要求为 0")

    模式号 = 模式字典.get("模式")
    名称 = 模式字典.get("名称") or 模式字典.get("模式名称") or "未指定"
    模式文本 = f"{模式号 if 模式号 is not None else ''} {名称}".strip()
    模式附加 = {
        "模式名称": str(名称),
        "最小长度比": 最小长度比,
        "最小数字保留率": 最小数字保留率,
        "关键数字全保留": 关键数字全保留,
        "禁止删减": 禁止删减,
    }
    return {
        "通过": not 失败原因,
        "长度比": 长度比,
        "数字保留率": 数字保留率,
        "异常残句": 异常残句,
        "待确认数": 待确认数,
        "模式": 模式文本,
        "模式附加": 模式附加,
        "失败原因": 失败原因,
    }
