"""逐字稿排版合成（纯计算）：把精校段落按模式输出结构拼成 Markdown 全文。

冻结接口见 开发文档/临时文档/41_逐字稿精校内部接口约定.md 第四节（合成全文、统一数字形式）。
只做字符串/正则处理，不调用能力、不联网、不写盘；输入不合法返回安全结果，不抛裸异常。
"""

from __future__ import annotations

import os
import re

默认模式号, 每章秒数, 小标题上限 = 1, 600, 20
句正则 = re.compile(r"[^。！？!?；;\n]+[。！？!?；;]?")
数字片段正则 = re.compile(r"[零一二两三四五六七八九十百千万亿]+")
数字字符表 = dict(zip("零一二两三四五六七八九", (0, 1, 2, 2, 3, 4, 5, 6, 7, 8, 9)))
小单位表, 大单位表 = {"十": 10, "百": 100, "千": 1000}, {"万": 10000, "亿": 100000000}
单字后置量词 = set("个家人天年月日元年块件单次分秒点倍成号岁套盒瓶台位条张只支场轮批层度斤克米亩间名步遍杯页本门")

def _取字段(容器: dict, 键: str, 默认):
    """安全取字段；容器非字典、字段缺失返回默认值。"""
    值 = 容器.get(键) if isinstance(容器, dict) else None
    return 默认 if 值 is None else 值

def _数值(值, 默认: float = 0.0) -> float:
    """安全转数值；布尔、非数值返回默认值。"""
    return 默认 if isinstance(值, bool) or not isinstance(值, (int, float)) else float(值)

def _时间戳(秒: float, 带小数: bool = True) -> str:
    """秒 → mm:ss.d（带小数）或 mm:ss；负数按 0 处理。"""
    秒 = max(float(秒), 0.0)
    分钟 = int(秒) // 60
    余秒 = int((秒 - 分钟 * 60) * 10) / 10
    return f"{分钟:02d}:{余秒:04.1f}" if 带小数 else f"{分钟:02d}:{int(秒) % 60:02d}"

def _主名(路径: str) -> str:
    """路径 → 不含扩展名的主文件名。"""
    名称 = os.path.basename((路径 or "").replace("\\", "/")).strip()
    return os.path.splitext(名称)[0].strip() or 名称

def _切句(文本: str) -> list[str]:
    """按句末标点切句（保留标点），丢弃空句。"""
    return [片段.strip() for 片段 in 句正则.findall(文本 or "") if 片段.strip()]

def _小标题(文本: str) -> str:
    """精校文本首句 → 议题小标题（去空白与分隔符，超长截断）。"""
    首句 = (_切句(文本) or [文本 or ""])[0]
    首句 = re.sub(r"[\s#]+", "", 首句).strip("：:，,。")
    return (首句[:小标题上限] + "…" if len(首句) > 小标题上限 else 首句) or "未命名议题"

def _有效段落(段落列表) -> list[tuple[dict, str]]:
    """过滤非字典段落与空文本段落，返回有序对 (段落, 精校文本)。"""
    段落 = [段 for 段 in (段落列表 if isinstance(段落列表, list) else []) if isinstance(段, dict)]
    配对 = [(段, _取字段(段, "精校文本", "").strip()) for 段 in 段落]
    return [(段, 文本) for 段, 文本 in 配对 if isinstance(文本, str) and 文本]

def _头部行(模式: dict, 元: dict) -> list[str]:
    """头部两行：标题、模式/时长/生成时间（生成时间缺失写 未记录）。"""
    主名 = _主名(_取字段(元, "源文件", ""))
    名称 = _取字段(模式, "名称", "") or _取字段(元, "模式名称", "") or "未指定"
    时长 = _时间戳(_数值(_取字段(元, "时长秒", 0)), 带小数=False)
    生成时间 = _取字段(元, "生成时间", "") or "未记录"
    return [f"# {主名} 逐字稿" if 主名 else "# 逐字稿",
            f"> 模式：{名称}｜时长：{时长}｜生成时间：{生成时间}"]

def _正文块(模式号: int, 模式: dict, 段落列表, 元: dict) -> list[str]:
    """按模式号组织正文块：1 时间戳+前缀 / 2、3 议题 / 4 分章 / 5 原样 / 6 一句一行 / 7 逐句时间戳 / 8 问题卡。"""
    块: list[str] = []
    有效 = _有效段落(段落列表)
    if 模式号 == 1:
        前缀 = _取字段(模式, "段落前缀", "")
        for 段, 文本 in 有效:
            块.append(f"[{_时间戳(_数值(_取字段(段, '开始秒', 0)))}] {前缀}{文本}".rstrip())
    elif 模式号 in (2, 3, 4):
        上一标题 = ""
        for 段, 文本 in 有效:
            章号 = int(max(_数值(_取字段(段, "开始秒", 0)), 0.0) // 每章秒数) + 1
            标题 = f"第{章号}章" if 模式号 == 4 else (_取字段(段, "议题", "") or _小标题(文本))
            if 模式号 == 2 or 标题 != 上一标题:
                块.append(f"## {标题}")
                上一标题 = 标题
            块.append(文本)
    elif 模式号 == 6:
        for _段, 文本 in 有效:
            块.extend(_切句(文本))
    elif 模式号 == 7:
        for 段, 文本 in 有效:
            戳 = _时间戳(_数值(_取字段(段, "开始秒", 0)), 带小数=False)
            块.extend(f"[{戳}] {句}" for 句 in _切句(文本))
    elif 模式号 == 8:
        for 序号, (_段, 文本) in enumerate(有效, start=1):
            块.extend((f"## 问题{序号}", 文本))
    else:
        for _段, 文本 in 有效:
            块.append(文本)
    return 块

def _死循环行(元: dict) -> list[str]:
    """元信息里的死循环区间在文末逐条注明（直播间音乐/无声段已略过）。"""
    行: list[str] = []
    for 项 in (_取字段(元, "死循环区间", []) or []):
        if isinstance(项, dict):
            起止 = "-".join(_时间戳(_数值(_取字段(项, 键, 0)), 带小数=False) for 键 in ("开始秒", "结束秒"))
            行.append(f"> 注：{起止} 为直播间音乐/无声段（原识别为重复内容），已略过。")
    return 行

def 合成全文(模式: dict, 段落列表: list[dict], 元信息: dict) -> str:
    """把精校段落按模式拼成 Markdown 全文；模式非字典返回空串，段落之间空行分隔。"""
    if not isinstance(模式, dict):
        return ""
    元 = 元信息 if isinstance(元信息, dict) else {}
    模式号 = _取字段(模式, "模式", 默认模式号)
    模式号 = 模式号 if isinstance(模式号, int) and not isinstance(模式号, bool) else 默认模式号
    头部 = "\n".join(_头部行(模式, 元))
    块 = _正文块(模式号, 模式, 段落列表, 元) + _死循环行(元)
    return 头部 + "\n\n" + "\n\n".join(块) if 块 else 头部 + "\n"

def _解析中文数字(片段: str) -> int | None:
    """中文数字串 → 整数；无法解析返回 None。支持 十/百/千/万/亿 进位与口语尾数（三千八→3800）。"""
    总计 = 段值 = 当前 = 上一单位 = 0
    已见数字 = 已见零 = False
    for 字 in 片段:
        if 字 in 数字字符表:
            当前, 已见数字 = 数字字符表[字], True
            已见零 = 已见零 or 字 == "零"
        elif 字 in 小单位表:
            当前 = 当前 or (1 if 字 == "十" and not 已见数字 else 0)
            段值 += (当前 or 1) * 小单位表[字]
            上一单位, 当前, 已见零 = 小单位表[字], 0, False
        elif 字 in 大单位表:
            总计 += (段值 + 当前 or 1) * 大单位表[字]
            段值, 当前, 上一单位, 已见零 = 0, 0, 大单位表[字], False
        else:
            return None
    if 当前:
        段值 += 当前 if (已见零 or 上一单位 == 0) else 当前 * (上一单位 // 10)
    return 总计 + 段值

def 统一数字形式(文本: str) -> str:
    """把中文数字表达统一为阿拉伯数字，其它字符原样保留；非文本输入返回空串。

    覆盖：一/二/两/三/四/五/六/七/八/九/十 组成的数字串，含 十/百/千/万/亿 进位、口语尾数
    （三千八→3800、一万二→12000）、零位（一百零二→102）、范围（五十到一百→50到100）、
    带量词（一千家→1000家、十个人→10个人）。
    局限：单字数字（一~九/两/十）仅在后面紧跟常见量词时才转换，避免误伤「一起」「统一」「一直」；
    「俩」「廿」「卅」与小数点口语（一点五）不覆盖；不做上下文语义判断，纯字面替换。
    """
    if not isinstance(文本, str) or not 文本:
        return 文本 if isinstance(文本, str) else ""
    片段列表: list[str] = []
    位置 = 0
    for 匹配 in 数字片段正则.finditer(文本):
        片段 = 匹配.group()
        起, 止 = 匹配.span()
        值 = _解析中文数字(片段)
        保留原字 = len(片段) == 1 and 文本[止:止 + 1] not in 单字后置量词
        片段列表.append(文本[位置:起])
        片段列表.append(片段 if 值 is None or 保留原字 else str(值))
        位置 = 止
    片段列表.append(文本[位置:])
    return "".join(片段列表)
