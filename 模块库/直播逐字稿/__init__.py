def 全自动精校(源文件路径: str, 导出路径: str, 缓存目录: str, 模式: int,
                分片秒数: int = 300, 附加术语: str = "", 模型配置: dict | None = None,
                裁决模型配置: dict | None = None, 超时秒: float = 3600.0,
                输出结构: str = "", 附加要求: str = "",
                裁决模型句柄: int | None = None):
    """全自动精校（对外能力）：闭包注入步骤表后交 实现/全自动精校 主流程执行。"""
    return _精校实现(
        源文件路径=源文件路径, 导出路径=导出路径, 缓存目录=缓存目录, 模式=模式,
        分片秒数=分片秒数, 附加术语=附加术语, 模型配置=模型配置,
        裁决模型配置=裁决模型配置, 超时秒=超时秒, 输出结构=输出结构,
        附加要求=附加要求, 裁决模型句柄=裁决模型句柄, 步骤=步骤表,
    )


def 注册能力(注册表) -> None:
    """由模块加载器调用。参数类型按能力契约声明注册。"""
    from 公共契约.能力契约.契约 import 能力实现

    契约 = json.loads((Path(__file__).parent / "能力契约" / "参数契约.json").read_text(encoding="utf-8"))
    类型表 = {
        条目["能力id"]: {参数["名称"]: 参数.get("类型", "") for 参数 in 条目.get("参数", [])}
        for 条目 in 契约.get("能力契约", [])
    }

    for 能力id, 函数, 参数名, 返回类型, 说明 in [
        ("直播逐字稿.转写媒体文件", 转写媒体文件,
         ["文件路径", "输出目录", "分片秒数", "重叠秒数", "模型配置", "附加术语", "超时秒"],
         "结果型", "转写直播媒体文件为原始逐字稿（探测→转写→落盘）"),
        ("直播逐字稿.检查可用性", 检查可用性, ["超时秒", "配置"], "结果型",
         "检查直播逐字稿链路可用性（媒体探测/转写模型）"),
        ("直播逐字稿.读取项目状态", 读取项目状态, ["输出目录"], "结果型",
         "读取逐字稿项目状态（断点续跑查询）"),
        ("直播逐字稿.全自动精校", 全自动精校,
         ["源文件路径", "导出路径", "缓存目录", "模式", "分片秒数", "附加术语",
          "模型配置", "裁决模型配置", "超时秒", "输出结构", "附加要求", "裁决模型句柄"], "结果型",
         "全自动精校：传媒体绝对路径+导出路径+缓存目录+模式号，直接出精校逐字稿；"
         "行业细节由消费者传参（输出结构/附加要求/附加术语），模型可用 裁决模型句柄 借用"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.直播逐字稿",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": 类型表[能力id][名称]} for 名称 in 参数名],
                返回=返回类型,
                说明=说明,
            )
        )
