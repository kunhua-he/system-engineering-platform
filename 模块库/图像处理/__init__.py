def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名 in [
        ("图像处理.分析图像文件", 分析图像文件, ["文件路径"]),
        ("图像处理.生成占位图", 生成占位图,
         ["宽度", "高度", "占位类型", "背景颜色", "前景颜色", "文本"]),
        ("图像处理.识别图像格式", 识别图像格式, ["字节"]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.图像处理",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明="模块组合能力",
            )
        )
