def 缩放图像(字节: bytes, 宽度: int | None = None, 高度: int | None = None,
             超时秒: float = 60) -> 结果:
    """按指定宽高缩放（宽高可空=最长边按纵横比推算），经 图像处理支持库.图像解码.缩放图像。

    宽/高为空时不传该参数键（契约默认 null），避免 HTTP 网关把显式 null 判为类型不匹配。
    """
    超时秒数值 = _校验超时秒(超时秒)
    if isinstance(超时秒数值, 结果):
        return 超时秒数值
    参数 = {"字节": 字节, "超时秒": 超时秒数值}
    if 宽度 is not None:
        参数["宽度"] = 宽度
    if 高度 is not None:
        参数["高度"] = 高度
    return _调用支持库("图像处理支持库.图像解码.缩放图像", 参数)


