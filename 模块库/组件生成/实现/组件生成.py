"""组件生成模块：把「模块模板生成器」补成底座正规原子能力（第 32–36 条）。

分层选择（依据与对比见 说明/设计说明.md）：
- 路径边界校验、存在性与生成后文件清单，全部经底座支持库公开能力完成：
  系统核心支持库.路径安全.校验路径、文件系统支持库.文件操作.判断存在、
  文件系统支持库.文件操作.搜索文件；
- 脚手架内容不重写第二套模板实现（第 26 条）：只经唯一能力调用器调用
  `组件规范支持库.生成模块模板`（同一份模板口径；实现落点
  `支持库/后端/组件规范支持库/实现/模块模板生成器.py`，2026-09-16 由终端层下沉）；
- 写入只允许落在调用方声明的项目根内：`项目根/模块库/<模块名>/` 与
  `项目根/测试中心/模块库/测试_<模块名>.py`，越界一律返回 `路径逃逸`。

模块不 import 支持库/提供者/实现目录；只做参数校验、边界判定与结果组装。
"""

from __future__ import annotations

from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.基础类型.逻辑类型 import 真, 假

来源 = "组件生成"

_路径校验能力 = "系统核心支持库.路径安全.校验路径"
_判断存在能力 = "文件系统支持库.文件操作.判断存在"
_搜索文件能力 = "文件系统支持库.文件操作.搜索文件"

模块库目录名 = "模块库"
测试中心目录名 = "测试中心"
测试骨架目录名 = "模块库"

允许类型 = ("基础模块", "功能模块")


def _调用支持库(能力id: str, 参数: dict) -> 结果:
    """经唯一能力调用器调用底座支持库公开能力；未装配时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数)
    except Exception as 错误:
        return 结果.失败("提供者不可用", f"{能力id} 调用失败: {错误}", 来源=来源)


def _校验路径(项目根: str, 相对路径: str) -> tuple[str, 结果 | None]:
    """经 路径安全.校验路径 校验相对路径并解析绝对路径；越界返回 路径逃逸。"""
    校验结果 = _调用支持库(_路径校验能力, {"根目录": 项目根, "相对路径": 相对路径})
    if not 校验结果.成功:
        return "", 校验结果
    值 = 校验结果.值 if isinstance(校验结果.值, dict) else {}
    if not 值.get("通过"):
        return "", 结果.失败(
            "路径逃逸",
            f"目标路径越出项目根，拒绝写入: {相对路径}（{值.get('原因') or '路径不安全'}）",
            来源=来源,
        )
    return str(值.get("绝对路径") or ""), None


def _是否存在(路径: str) -> tuple[bool, 结果 | None]:
    """经 文件系统支持库.文件操作.判断存在 探测路径（只读）。"""
    存在结果 = _调用支持库(_判断存在能力, {"文件路径": 路径})
    if not 存在结果.成功:
        return 假, 存在结果
    值 = 存在结果.值
    if isinstance(值, dict):
        return bool(值.get("存在")), None
    return bool(值), None


def _相对文本(路径: str, 根: Path) -> str:
    """把生成文件绝对路径转成相对项目根的稳定文本路径。"""
    try:
        return Path(路径).resolve().relative_to(根.resolve()).as_posix()
    except (ValueError, OSError):
        return str(路径)


def 生成模块脚手架(项目根: str = None, 模块名: str = None, 类型: str = "基础模块",
                   能力清单: list = None, 依赖能力清单: list = None,
                   支持库扫描根: str = None) -> 结果:
    """按声明生成模块脚手架，只写调用方声明的项目根内。

    写入范围固定为二处：`项目根/模块库/<模块名>/`（整个模块包）与
    `项目根/测试中心/模块库/测试_<模块名>.py`（测试骨架）；目标已存在一律拒绝覆盖。
    返回 `结果(值={模块目录, 测试骨架, 目标相对目录, 文件清单, 文件数})`。
    """
    if not isinstance(项目根, str) or not 项目根.strip():
        return 结果.失败("参数不合法", "项目根必须为非空文本（生成只允许写在该根内）", 来源=来源)
    if not isinstance(模块名, str) or not 模块名.strip():
        return 结果.失败("参数不合法", "模块名必须为非空文本", 来源=来源)
    if not isinstance(类型, str) or not 类型.strip():
        return 结果.失败("参数不合法", f"类型必须为 {'/'.join(允许类型)} 之一", 来源=来源)
    if not isinstance(能力清单, list) or not 能力清单:
        return 结果.失败("参数不合法", "能力清单必须为非空列表", 来源=来源)
    if 依赖能力清单 is not None and not isinstance(依赖能力清单, list):
        return 结果.失败("参数不合法", "依赖能力清单必须为列表", 来源=来源)
    扫描根 = 支持库扫描根.strip() if isinstance(支持库扫描根, str) and 支持库扫描根.strip() else 项目根.strip()

    项目根路径 = Path(项目根.strip()).expanduser()
    目标相对目录 = f"{模块库目录名}/{模块名.strip()}"
    骨架相对路径 = f"{测试中心目录名}/{测试骨架目录名}/测试_{模块名.strip()}.py"

    # 1. 只读探测：项目根与支持库扫描根必须真实存在（不创建、不猜测）
    for 标签, 待查 in (("项目根", str(项目根路径)), ("支持库扫描根", 扫描根)):
        存在, 探测失败 = _是否存在(待查)
        if 探测失败 is not None:
            return 探测失败
        if not 存在:
            return 结果.失败("目录不存在", f"{标签} 不存在: {待查}", 来源=来源)

    # 2. 路径边界校验：写入目标必须落在项目根内的固定两处
    模块目录, 边界失败 = _校验路径(str(项目根路径), 目标相对目录)
    if 边界失败 is not None:
        return 边界失败
    骨架路径, 边界失败 = _校验路径(str(项目根路径), 骨架相对路径)
    if 边界失败 is not None:
        return 边界失败

    # 3. 经唯一能力调用器复用模板能力（不新建第二套模板、不直连实现目录）
    try:
        生成结果 = _调用支持库("组件规范支持库.生成模块模板", {
            "模块名": 模块名.strip(),
            "类型": 类型.strip(),
            "能力清单": 能力清单,
            "依赖能力清单": 依赖能力清单 or [],
            "系统根": 扫描根,
            "模块库根": str(项目根路径 / 模块库目录名),
            "测试中心根": str(项目根路径 / 测试中心目录名),
        })
    except Exception as 错误:
        return 结果.失败("生成失败", f"{type(错误).__name__}: {错误}", 来源=来源)
    if not 生成结果.成功:
        return 生成结果

    生成值 = 生成结果.值 if isinstance(生成结果.值, dict) else {}
    真实模块目录 = str(生成值.get("模块目录") or 模块目录)
    真实骨架路径 = str(生成值.get("测试骨架") or 骨架路径)

    # 4. 生成后读取真实文件清单（目录遍历经支持库能力，不自行遍历）
    清单结果 = _调用支持库(_搜索文件能力, {"目录": 真实模块目录, "通配符": "*", "递归": 真})
    if not 清单结果.成功:
        return 结果.失败(
            "清单读取失败",
            f"脚手架已生成但文件清单读取失败（模块目录={真实模块目录}）: {清单结果.错误说明}",
            来源=来源,
        )
    清单值 = 清单结果.值 if isinstance(清单结果.值, dict) else {}
    文件清单 = sorted(
        [_相对文本(str(条目), 项目根路径) for 条目 in (清单值.get("文件列表") or [])]
        + [骨架相对路径]
    )
    return 结果.成功结果({
        "模块目录": 真实模块目录,
        "测试骨架": 真实骨架路径,
        "目标相对目录": 目标相对目录,
        "文件清单": 文件清单,
        "文件数": len(文件清单),
    })
