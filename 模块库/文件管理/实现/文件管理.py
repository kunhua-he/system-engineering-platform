"""文件管理模块：只持能力 id 与契约版本，经 HTTP连接器调用统一网关。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
连接器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果


_连接器 = None


def 设置HTTP连接器(连接器) -> None:
    """由项目适配层装配连接器；主要用于启动装配与隔离测试。"""
    global _连接器
    _连接器 = 连接器


def _获取连接器():
    return _连接器


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经 HTTP 连接器按能力 id 调用统一网关；失败统一转为 结果。"""
    try:
        连接器 = _获取连接器()
        if 连接器 is None:
            return 结果.失败(失败错误码, "HTTP 连接器未装配", 来源="文件管理")
        响应 = 连接器.调用能力(能力id, 参数)
        if isinstance(响应, 结果):
            return 响应
        if not isinstance(响应, dict):
            return 结果.失败("返回结果不符合契约", "网关返回不是对象", 来源="文件管理")
        if 响应.get("成功"):
            return 结果.成功结果(响应.get("值"))
        return 结果.失败(响应.get("错误码") or 失败错误码, 响应.get("错误说明") or "网关调用失败", 来源="文件管理")
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源="文件管理")
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源="文件管理")


def 读取文件(文件路径: str) -> 结果:
    """读取文本文件（默认 utf-8），返回 结果[文本]。"""
    return _调用支持库("文件系统支持库.文件操作.读取文件", {"文件路径": 文件路径, "编码": "utf-8"})


def 写入文件(文件路径: str, 内容: str) -> 结果:
    """写入文本文件（默认 utf-8），返回 结果。"""
    return _调用支持库("文件系统支持库.文件操作.写入文件", {"文件路径": 文件路径, "内容": 内容, "编码": "utf-8"})


def 复制文件(源路径: str, 目标路径: str) -> 结果:
    """复制文件到目标路径（自动创建父目录），返回 结果。"""
    return _调用支持库("文件系统支持库.文件操作.复制文件", {"源路径": 源路径, "目标路径": 目标路径})


def 移动文件(源路径: str, 目标路径: str) -> 结果:
    """移动文件到目标路径（自动创建父目录），返回 结果。"""
    return _调用支持库("文件系统支持库.文件操作.移动文件", {"源路径": 源路径, "目标路径": 目标路径})


def 删除文件(文件路径: str) -> 结果:
    """删除文件（不存在视为成功，幂等），返回 结果。"""
    return _调用支持库("文件系统支持库.文件操作.删除文件", {"文件路径": 文件路径})


def 列出文件(目录路径: str) -> 结果:
    """列出目录下条目名称（排序），返回 结果[名称列表]。"""
    return _调用支持库("文件系统支持库.文件操作.列出目录", {"目录路径": 目录路径})


def 读取二进制文件(受控根目录: str, 相对路径: str, 最大字节数: int = 0) -> 结果:
    """在受控根目录内按相对路径读取二进制文件（路径越界拒绝、超限拒绝）。"""
    return _调用支持库(
        "文件系统支持库.文件操作.读取二进制文件",
        {"受控根目录": 受控根目录, "相对路径": 相对路径, "最大字节数": 最大字节数},
    )


def 读取文件头部字节(受控根目录: str, 相对路径: str, 字节数: int = 4096) -> 结果:
    """在受控根目录内按相对路径只读文件头部 N 字节（不加载全文件）。"""
    return _调用支持库(
        "文件系统支持库.文件操作.读取文件头部字节",
        {"受控根目录": 受控根目录, "相对路径": 相对路径, "字节数": 字节数},
    )


def 流式创建摘要(文件路径: str) -> 结果:
    """大文件分块流式创建内容摘要（sha256），失败返回统一错误结构。

    系统核心支持库.资源管理.创建内容摘要 成功返回摘要文本（非 结果），此处包装为 结果。
    """
    try:
        return _调用支持库("系统核心支持库.资源管理.创建内容摘要", {"文件路径": 文件路径}, 失败错误码="摘要失败")
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源="文件管理")
    except Exception as 错误:
        return 结果.失败("摘要失败", f"系统核心支持库.资源管理.创建内容摘要 调用失败: {错误}", 来源="文件管理")
