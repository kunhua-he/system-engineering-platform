"""文件管理模块：只经文件系统与资源管理支持库公开入口组合，不深入实现目录。"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.文件系统 import (
    删除文件 as _删除文件,
    复制文件 as _复制文件,
    读取文件 as _读取文件,
    读取二进制文件 as _读取二进制文件,
    读取文件头部字节 as _读取文件头部字节,
    列出目录 as _列出目录,
    移动文件 as _移动文件,
    写入文件 as _写入文件,
)
from 支持库.后端.资源管理 import 创建内容摘要 as _创建内容摘要


def 读取文件(文件路径: str) -> 结果:
    return _读取文件(文件路径)


def 写入文件(文件路径: str, 内容: str) -> 结果:
    return _写入文件(文件路径, 内容)


def 复制文件(源路径: str, 目标路径: str) -> 结果:
    return _复制文件(源路径, 目标路径)


def 移动文件(源路径: str, 目标路径: str) -> 结果:
    return _移动文件(源路径, 目标路径)


def 删除文件(文件路径: str) -> 结果:
    return _删除文件(文件路径)


def 列出文件(目录路径: str) -> 结果:
    return _列出目录(目录路径)


def 读取二进制文件(受控根目录: str, 相对路径: str, 最大字节数: int = 0) -> 结果:
    """在受控根目录内按相对路径读取二进制文件（路径越界拒绝、超限拒绝）。"""
    return _读取二进制文件(受控根目录, 相对路径, 最大字节数)


def 读取文件头部字节(受控根目录: str, 相对路径: str, 字节数: int = 4096) -> 结果:
    """在受控根目录内按相对路径只读文件头部 N 字节（不加载全文件）。"""
    return _读取文件头部字节(受控根目录, 相对路径, 字节数)


def 流式创建摘要(文件路径: str) -> 结果:
    """大文件分块流式创建内容摘要（sha256），失败返回统一错误结构。"""
    try:
        return 结果.成功结果(_创建内容摘要(文件路径))
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源="文件管理")
    except OSError as 错误:
        return 结果.失败("摘要失败", str(错误), 来源="文件管理")
