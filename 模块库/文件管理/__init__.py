"""文件管理模块包级中文入口。

对外能力经 公共契约.能力契约.调用器 的 获取能力调用器() 调用支持库，
不直接导入支持库/提供者实现。
"""

from __future__ import annotations

from 模块库.文件管理.实现.文件管理 import 读取文件
from 模块库.文件管理.实现.文件管理 import 写入文件
from 模块库.文件管理.实现.文件管理 import 复制文件
from 模块库.文件管理.实现.文件管理 import 移动文件
from 模块库.文件管理.实现.文件管理 import 删除文件
from 模块库.文件管理.实现.文件管理 import 列出文件
from 模块库.文件管理.实现.文件管理 import 读取二进制文件
from 模块库.文件管理.实现.文件管理 import 读取文件头部字节
from 模块库.文件管理.实现.文件管理 import 流式创建摘要

__all__ = [
    "读取文件",
    "写入文件",
    "复制文件",
    "移动文件",
    "删除文件",
    "列出文件",
    "读取二进制文件",
    "读取文件头部字节",
    "流式创建摘要",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用，向能力注册表注册本模块全部能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型, 说明 in [
        ("文件管理.读取文件", 读取文件, ['文件路径'], "结果", "读取文本文件（默认 utf-8），返回 结果[文本]"),
        ("文件管理.写入文件", 写入文件, ['文件路径', '内容'], "结果", "写入文本文件（默认 utf-8，自动创建父目录）"),
        ("文件管理.复制文件", 复制文件, ['源路径', '目标路径'], "结果", "复制文件到目标路径（自动创建父目录）"),
        ("文件管理.移动文件", 移动文件, ['源路径', '目标路径'], "结果", "移动文件到目标路径（自动创建父目录）"),
        ("文件管理.删除文件", 删除文件, ['文件路径'], "结果", "删除文件（不存在视为成功，幂等）"),
        ("文件管理.列出文件", 列出文件, ['目录路径'], "结果", "列出目录下条目名称（排序）"),
        ("文件管理.读取二进制文件", 读取二进制文件, ['受控根目录', '相对路径', '最大字节数'], "结果", "受控根内读取二进制文件（路径越界拒绝、超限拒绝）"),
        ("文件管理.读取文件头部字节", 读取文件头部字节, ['受控根目录', '相对路径', '字节数'], "结果", "受控根内只读文件头部 N 字节"),
        ("文件管理.流式创建摘要", 流式创建摘要, ['文件路径'], "结果", "大文件分块流式创建内容摘要（sha256）"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.文件管理",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": _参数类型(名称)} for 名称 in 参数名],
                返回=返回类型,
                说明=说明,
            )
        )


def _参数类型(名称: str) -> str:
    """注册参数类型与聚合契约对称：最大字节数/字节数 为整数，其余为文本。"""
    return "整数" if 名称 in ("最大字节数", "字节数") else "文本"
