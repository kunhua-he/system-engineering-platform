"""媒体转写模块（功能模块）：只经 获取能力调用器().调用能力 组合支持库能力。

- 检查可用性 / 获取模型版本：经 转写.检查可用性 / 转写.获取模型版本
- 转写音频文件 / 转写视频文件：经 转写.转写音频文件（MLX Whisper 受管子进程；
  视频文件由 mlx_whisper 内部经 ffmpeg 解码音轨，临时媒体/音频由支持库层管理）
未配置模型如实返回 未配置模型，绝不伪造转写成功。
禁止导入支持库/提供者/第三方/运行核心实现；公开参数全部可跨宿主序列化
（取消令牌id 为文本，禁止 callable）。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "媒体转写"
默认转写超时秒 = 300.0


def _调用(能力id: str, 请求参数: dict) -> 结果:
    """经唯一能力调用服务按 能力id 调用支持库能力；未装配时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 请求参数, 调用方=来源)
    except RuntimeError as 错误:
        return 结果.失败("提供者不可用", str(错误), 来源=来源)


def _校验基础(超时秒: float, 配置: dict | None) -> 结果 | None:
    """模块侧基础参数校验：超时秒 必须为正数，配置 必须为对象或空。"""
    if not isinstance(超时秒, (int, float)) or isinstance(超时秒, bool) or 超时秒 <= 0:
        return 结果.失败("参数不合法", "超时秒 必须为正数", 来源=来源)
    if 配置 is not None and not isinstance(配置, dict):
        return 结果.失败("参数不合法", "配置 必须为对象", 来源=来源)
    return None


def _校验文件输入(文件路径: str, 超时秒: float, 取消令牌id: str,
                  配置: dict | None) -> 结果 | None:
    """模块侧文件输入参数校验：路径/超时/令牌/配置 全量可序列化校验。"""
    if not isinstance(文件路径, str) or not 文件路径.strip():
        return 结果.失败("参数不合法", "文件路径必须为非空文本", 来源=来源)
    if not isinstance(取消令牌id, str):
        return 结果.失败("参数不合法", "取消令牌id 必须为文本", 来源=来源)
    return _校验基础(超时秒, 配置)


def 转写音频文件(文件路径: str, 超时秒: float = 默认转写超时秒,
                 取消令牌id: str = "", 配置: dict | None = None) -> 结果:
    """转写音频文件为文本；未配置模型如实返回 未配置模型。"""
    错误 = _校验文件输入(文件路径, 超时秒, 取消令牌id, 配置)
    if 错误:
        return 错误
    return _调用("转写.转写音频文件", {
        "文件路径": 文件路径, "超时秒": 超时秒, "配置": 配置})


def 检查可用性(超时秒: float = 默认转写超时秒,
              配置: dict | None = None) -> 结果:
    """检查 MLX Whisper 转写可用性；模型未配置如实返回 未配置模型。"""
    错误 = _校验基础(超时秒, 配置)
    if 错误:
        return 错误
    return _调用("转写.检查可用性", {"超时秒": 超时秒, "配置": 配置})


def 获取模型版本(超时秒: float = 默认转写超时秒,
                配置: dict | None = None) -> 结果:
    """获取 MLX Whisper 模型与库版本；未配置 → 未配置模型。"""
    错误 = _校验基础(超时秒, 配置)
    if 错误:
        return 错误
    return _调用("转写.获取模型版本", {"超时秒": 超时秒, "配置": 配置})


def 转写视频文件(文件路径: str, 转写超时秒: float = 默认转写超时秒,
                取消令牌id: str = "", 配置: dict | None = None) -> 结果:
    """视频转写：视频文件直接经 转写.转写音频文件 转写。

    mlx_whisper 内部经 ffmpeg 解码音轨；未配置模型如实返回 未配置模型；
    任一段失败按 转写 能力错误码透传。
    """
    错误 = _校验文件输入(文件路径, 转写超时秒, 取消令牌id, 配置)
    if 错误:
        return 错误
    return _调用("转写.转写音频文件", {
        "文件路径": 文件路径, "超时秒": 转写超时秒, "配置": 配置})
