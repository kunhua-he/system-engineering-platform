"""媒体转写模块包级中文入口（功能模块）：组合 MLX Whisper 支持库公开能力。

对外能力经项目适配层装配的 HTTP连接器调用统一网关，
不直接导入支持库/提供者实现。
"""

from __future__ import annotations

import json
from pathlib import Path

from 模块库.媒体转写.实现.媒体转写 import 检查可用性
from 模块库.媒体转写.实现.媒体转写 import 获取模型版本
from 模块库.媒体转写.实现.媒体转写 import 设置HTTP连接器
from 模块库.媒体转写.实现.媒体转写 import 转写音频文件
from 模块库.媒体转写.实现.媒体转写 import 转写视频文件

__all__ = [
    "设置HTTP连接器",
    "检查可用性",
    "获取模型版本",
    "转写音频文件",
    "转写视频文件",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    契约 = json.loads((Path(__file__).parent / "能力契约" / "参数契约.json").read_text(encoding="utf-8"))
    # 参数契约表：能力id → 契约里的**整条参数声明**（名称/类型/必填/默认值/说明）。
    # 不在此处手工重建参数项 —— 重建一次就丢一次字段（见下）。
    # 缺陷溯源（2026-09-18）：本表原先只抽「名称+类型」两个键，`必填` 被丢弃；而网关
    # 唯一校验点 `运行核心/统一网关/类型规格.py` 的判据是 `项.get("必填") is 真`
    # → `None is 真` = 假 → 必填校验静默失效：少传参数不再被拦在网关，直接落进实现体
    # 抛 TypeError，用户拿到 HTTP 500 而不是干净的 400「缺少必填参数 X」。
    # 契约是本包参数的唯一事实源（哲学 12.1）：入口只透传，不另立第二套事实。
    参数契约表 = {
        条目["能力id"]: [dict(参数) for 参数 in 条目.get("参数", [])]
        for 条目 in 契约.get("能力契约", [])
    }

    def _参数声明(能力id: str, 参数名: list[str]) -> list[dict]:
        """按契约整条透传参数声明；注册名序与契约名序不一致即失败（不静默漏参）。"""
        契约参数 = 参数契约表.get(能力id)
        if 契约参数 is None:
            raise ValueError(f"能力 {能力id} 不在 能力契约/参数契约.json 的能力契约里")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(参数名):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(参数名)} 与契约参数名序 {契约名序} 不一致："
                "参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），入口不得另立一份")
        return 契约参数

    for 能力id, 函数, 参数名, 说明 in [
        ("媒体转写.转写视频文件", 转写视频文件,
         ["文件路径", "转写超时秒", "取消令牌id", "配置"], "视频转写（经 转写支持库.转写.转写音频文件）"),
        ("媒体转写.转写音频文件", 转写音频文件,
         ["文件路径", "超时秒", "取消令牌id", "配置"], "转写音频文件"),
        ("媒体转写.检查可用性", 检查可用性, ["超时秒", "配置"], "检查 MLX Whisper 转写可用性"),
        ("媒体转写.获取模型版本", 获取模型版本, ["超时秒", "配置"], "获取模型与库版本"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.媒体转写",
                实现函数=函数,
                参数=_参数声明(能力id, 参数名),
                返回="结果型",
                说明=说明,
            )
        )
