"""媒体转写模块包级中文入口。"""

from __future__ import annotations

from 模块库.媒体转写.实现.媒体转写 import 检查转写可用性
from 模块库.媒体转写.实现.媒体转写 import 获取模型版本
from 模块库.媒体转写.实现.媒体转写 import 转写视频文件
from 模块库.媒体转写.实现.媒体转写 import 转写音频文件

__all__ = [
    "检查转写可用性",
    "获取模型版本",
    "转写视频文件",
    "转写音频文件",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("媒体转写.转写视频文件", 转写视频文件, ["文件路径", "输出格式", "提取超时秒", "转写超时秒", "取消判断", "配置"], "视频提取音频后转写"),
        ("媒体转写.转写音频文件", 转写音频文件, ["文件路径", "超时秒", "取消判断", "配置"], "转写音频文件"),
        ("媒体转写.检查可用性", 检查转写可用性, ["超时秒", "配置"], "检查 MLX Whisper 转写可用性"),
        ("媒体转写.获取模型版本", 获取模型版本, ["超时秒", "配置"], "获取模型与库版本"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.媒体转写",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明=说明,
            )
        )
