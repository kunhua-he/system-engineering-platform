"""仓库锁能力（自修复工具）：内核级只读封禁的 MCP 入口，一个 动作 参数带四个动作。

判据本体在 `公共契约/运行时/仓库只读锁.py`（扫描面、上锁、解锁、查询、兜底重锁全在那里），
本能力**只做翻译** —— 它与 `运维脚本/仓库锁.py` 是「**同一判据、不同入口**」：
一个给终端用，一个给 MCP 用；两者都不另写扫描面或上锁逻辑（另写一套就是同一件事的第二条腿）。

四个动作（华哥 2026-09-23 裁决「只有 mcp 才能解锁，禁止用其他方式解锁」的 MCP 侧落点）：

    上锁 → 上锁全仓(项目根)     收紧（安全方向，无门槛）
    查看 → 查询(项目根)         只读（无门槛）
    下锁 → 解锁全仓(项目根)     放宽（**只认网关凭证**，判据在 仓库只读锁._要求网关凭证）
    补齐 → 重锁一遍(项目根)     收紧（幂等兜底，无门槛）

`项目根` 按本仓「根目录是解析基准」口径解析：留空 = 本能力所在仓库根；相对写法按它拼接，
绝对写法原样用 —— 走 `平台适配.解析路径` 这条全平台唯一解析腿，本文件不自写 is_absolute 分支。
"""
from __future__ import annotations

from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果

from 公共契约.运行时 import 仓库只读锁 as 锁
from 公共契约.运行时.平台适配.路径解析 import 解析路径

来源 = "自修复工具"

#: 本能力所在仓库根（`模块库/自修复工具/实现/仓库锁.py` ⇒ 上三级）—— `项目根` 留空时的默认。
系统根 = Path(__file__).resolve().parents[3]

#: 动作 → (判据函数名, 一句话说明)。判据函数**只从 仓库只读锁 取**（`getattr(锁, 名)`），
#: 本表不复制任何上锁/扫描逻辑 —— 判据本体唯一，这里只登记「动作名 → 判据函数名」。
动作表: dict[str, tuple[str, str]] = {
    "上锁": ("上锁全仓", "给全仓受管文件与目录置内核不可变标志（收紧，安全方向）"),
    "查看": ("查询", "如实报受管条目数 / 已锁 / 未锁缺口（只读）"),
    "下锁": ("解锁全仓", "清掉全仓内核不可变标志（放宽；只认网关凭证，终端直跑被拒）"),
    "补齐": ("重锁一遍", "把「该锁却没锁」的条目补上（收紧，幂等兜底）"),
}


def _解析项目根(项目根: object) -> Path:
    """把 `项目根` 解析成绝对路径：留空 = 本仓库根；相对写法按本仓库根拼接。

    为什么默认是**本仓库根**而不是进程 cwd：网关跑激活制品时 cwd 是制品根，而本能力的
    判据面（`git ls-files` 的扫描面）针对的是**源码树**（华哥裁决「仅限这个项目」）。
    相对/绝对都走 `解析路径` 这条唯一解析腿，不在这里自写 `is_absolute()` 分支。
    """
    文本 = "" if 项目根 is None else str(项目根).strip()
    if not 文本:
        return 系统根
    return Path(解析路径(文本, str(系统根))).resolve()


def 仓库锁(动作: object = None, 项目根: object = "") -> 结果:
    """内核级只读封禁的四个动作：上锁 / 查看 / 下锁 / 补齐（判据在 公共契约/运行时/仓库只读锁.py）。

    入参：
      · `动作`（文本型，必填）：`上锁` / `查看` / `下锁` / `补齐`，其它值判 `参数不合法`；
      · `项目根`（文本型，默认空 = 本仓库根）：要作用的仓库根，相对/绝对都能用。

    返回（结果型，值结构见能力定义）：把 `仓库只读锁` 的判据 dict **原样带出**，另加
    `动作` / `说明` / `动作说明` / `项目根`。下锁在**没有网关凭证**时，判据本体抛
    `PermissionError`，本能力转成 `权限不足` 失败并原样带出判据的说明（不另写第二份门槛文本）。
    """
    文本动作 = "" if 动作 is None else str(动作).strip()
    if 文本动作 not in 动作表:
        return 结果.失败(
            "参数不合法",
            f"动作 必须是 {' / '.join(动作表)} 之一，收到：{动作!r}",
            来源=来源,
        )
    函数名, 动作说明 = 动作表[文本动作]
    根 = _解析项目根(项目根)
    判据 = getattr(锁, 函数名, None)
    if 判据 is None:
        # 判据本体被改名/缺失 ⇒ fail-closed 报出来，不静默当成成功（假绿防线）。
        return 结果.失败("提供者不可用",
                       f"仓库只读锁 缺少判据函数 {函数名}（本能力只做翻译，不代写判据）",
                       来源=来源)
    try:
        值 = 判据(根)
    except PermissionError as 错误:
        # 放宽动作（下锁）在没凭证时被判据本体拒绝：说明原文照带，本能力不另写门槛文本。
        return 结果.失败("权限不足", str(错误), 来源=来源)
    载荷 = dict(值) if isinstance(值, dict) else {"判据返回": 值}
    # `说明` 键恒在：判据自带说明（`查询` 有）**原样保留**，没有才补动作说明；
    # 动作说明另置 `动作说明`，两者都不丢。
    载荷.setdefault("说明", 动作说明)
    载荷["动作"] = 文本动作
    载荷["动作说明"] = 动作说明
    载荷["项目根"] = str(根)
    return 结果.成功结果(载荷)


__all__ = ["仓库锁"]
