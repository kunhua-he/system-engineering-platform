def _展开目录条目(相对路径: str, 根: Path) -> list[str]:
    """把一个**目录**形态的 `模块ID` 展开成它内部的全部 `.py`（仓库相对路径）。

    为什么必须展开（2026-09-23 复核实测的真缺口）：调用方很自然会传目录
    （`开发工具/MD文档生成`），而编译口的 `--文件` 只认文件 —— 传目录进去
    **步骤3 会报「变更集无 .py 文件、本轮无编译对象」并整体降为「未核验」**。
    实测（本轮）：一个代理改了 21 个 .py，按目录名传模块ID，拿到的结论是
    「变更集无 .py 文件」⇒ 调用方会以为「这个目录没什么要编的」，而真相是**它一个都没编**。
    这正是本仓反复定的口径：**扫描面为 0 不得记作通过**；但它更容易被误读成
    「干净」，故这里在能力面上就把目录展开成文件，让「传目录」得到与「传目录里每个文件」
    逐字相同的结论。

    展开口径：`遍历源码`（唯一遍历入口，进目录即剪枝生成式目录），只取 `.py`，
    排序稳定。非目录、或目录下没有 `.py` ⇒ 原样回传单条，交给编译口按它自己的
    判据报「未核验」（本函数不替它决定错误语义）。
    """
    from 公共契约.正式根 import 遍历源码
    目标 = 根 / 相对路径
    if not 目标.is_dir():
        return [相对路径]
    内部 = [路径.relative_to(根).as_posix()
            for 路径 in 遍历源码(目标, 层名表=(".",))
            if 路径.suffix == ".py"]
    return sorted(内部) if 内部 else [相对路径]


def _分派模块ID(条目: list[str], 根: Path | None = None) -> tuple[list[str], list[str], str]:
    """把 `模块ID` 逐条分派成 `(文件清单, 库 id 清单, 问题说明)`。

    判据：含 `/` ⇒ 仓库相对路径（送 `--文件`）；否则 ⇒ 包 id（送 `--库`）。
    返回的第三种形态（两者都有值）不合法 —— 编译口的 `--文件` 与 `--库` 互斥，
    一条命令只能走一种；混着传就是让调用方以为两边都编了（fail-closed 拦下）。

    `根` 给定时，路径形态的**目录条目**会先展开成它内部的 `.py`（见 `_展开目录条目`）——
    不展开的话「传目录」会静默编 0 个文件（本轮实测的真缺口）。
    """
    文件: list[str] = []
    库: list[str] = []
    for 条 in 条目:
        if "/" in 条 or 条.endswith(".py"):
            文件.extend(_展开目录条目(条, 根) if 根 is not None else [条])
        else:
            库.append(条)
    if 文件 and 库:
        return [], [], (f"同一次调用里既有路径形态（{文件[:2]}）又有包 id 形态（{库[:2]}）："
                    "编译口的 --文件 与 --库 互斥，请分两次调，别混着传")
    return 文件, 库, ""


def 静态编译(类型: object = None, 模块ID: object = None,
             超时秒: float = 600.0, 源码根: str = "") -> 结果:
    """静态编译：**不带实际数据**跑代码合规 + 契约 + 对应生成物，按库/模块分片。

    传参（哲学 7.1 的固定形制）：
      · `类型`（整数型）：`0` = 全仓；`1` = 指定库或模块；
      · `模块ID`（文本型路径）：`类型=0` 时可空（给了即判 `参数不合法`，不静默忽略）；
        `类型=1` 时必填，多条可换行分隔或传列表；每条接受**仓库相对路径**或**包 id**。
      · `超时秒` / `源码根`：与本包既有能力逐字同义（不新造口径）。

    返回（哲学 7.1 的固定形制）：
      · `成功数量` / `失败数量`；`逐条明细`（每条含 `模块ID或库ID`、`失败原因`、
        **`缺乏什么导致无法自动自愈`**、`能否自动自愈`）；
      · 另承接编译口既有结论：`五态结论` / `退出码` / `检查项表` / `失败门禁` /
        `未核验项` / `只报红项` / `缺失项表` / `结论原文` / `定向测试点名` / `命令` /
        `标准输出` / `标准错误` / `项目根`。

    **本能力不带实际数据跑测试**（与 `动态编译` 的唯一差别，逐字按华哥裁决）：
    组命令时固定加 `--不跑点名` —— 步骤5 **只点名、不执行**定向测试。
    要跑实测脚本请调 `动态编译`（它在同一套静态面之上**额外**执行那些脚本）。
    「不跑」不等于「不知道要跑谁」：点名的模块清单照样回带在 `定向测试点名` 里，
    调用方据此知道这一轮改了的东西该由哪些测试覆盖。
    """
    归一类型, 条目, 传参失败 = 归一传参(类型, 模块ID)
    if 传参失败 is not None:
        return 传参失败
    根, 说明 = _源码根(源码根)
    if 根 is None:
        return _失败("参数不合法", 说明)
    # 静态档：固定 --不跑点名（只点名不执行），这是与 动态编译 的**唯一**命令面差别。
    参数: list[str] = ["--不跑点名"]
    if 归一类型 == 类型全仓:
        参数.append("--全仓")
    else:
        文件, 库, 问题 = _分派模块ID(条目, 根)
        if 问题:
            return _失败("参数不合法", 问题)
        if 文件:
            参数 += ["--文件", *文件]
        else:
            参数 += ["--库", *库]
    命令 = [解释器, "-m", 编译口模块, *参数]
    调用 = _调用支持库("系统核心支持库.进程管理.执行命令", {
        "命令": " ".join(命令),
        "工作目录": str(根),
        "超时秒": float(超时秒),
    })
    if not 调用.成功:
        return _失败(调用.错误码 or "提供者不可用",
                     f"执行命令 调用失败（编译口未起）: {调用.错误说明}")
    值 = 调用.值 if isinstance(调用.值, dict) else {}
    退出码 = _取整数(值, ("退出码", "返回码"), -1)
    标准输出 = _取文本(值, ("标准输出", "输出", "stdout"))
    标准错误 = _取文本(值, ("标准错误", "错误输出", "stderr"))
    return 结果.成功结果(归并结论(
        标准输出, 标准错误, 退出码, " ".join(命令), 条目, str(根)))


