"""自修复开发工具模块实现：组合 Git 支持库、文件系统与定向验证。

模块只持能力 id 与契约版本，经 HTTP连接器调用统一网关；
不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
连接器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。
组合能力：Git操作（检查提供者/创建 工作区/关闭工作区/提交/回滚/挑拣合入/
当前状态/获取当前提交哈希）、文件系统（读取/写入/登记临时资源）、资源管理
（内容摘要/唯一运行目录）、本地进程（验证命令受管执行）。
错误码统一中文契约：路径逃逸/补丁多重匹配/验证失败/回滚失败/未提交修改/冲突。
"""

from __future__ import annotations

import os
import uuid
from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果

来源 = "自修复工具"

_连接器 = None


def 设置HTTP连接器(连接器) -> None:
    """由项目适配层装配连接器；主要用于启动装配与隔离测试。"""
    global _连接器
    _连接器 = 连接器


def _获取连接器():
    return _连接器


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经 HTTP 连接器按能力 id 调用统一网关；失败统一转为 结果。"""
    try:
        连接器 = _获取连接器()
        if 连接器 is None:
            return 结果.失败(失败错误码, "HTTP 连接器未装配", 来源=来源)
        响应 = 连接器.调用能力(能力id, 参数)
        if isinstance(响应, 结果):
            return 响应
        if not isinstance(响应, dict):
            return 结果.失败("返回结果不符合契约", "网关返回不是对象", 来源=来源)
        if 响应.get("成功"):
            return 结果.成功结果(响应.get("值"))
        return 结果.失败(响应.get("错误码") or 失败错误码, 响应.get("错误说明") or "网关调用失败", 来源=来源)
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源=来源)
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源=来源)


def _失败(错误码: str, 消息: str, **额外) -> 结果:
    return 结果.失败(错误码, 消息, 来源=来源, **额外)


def _补丁目标(工作区路径: str, 相对路径: object) -> 结果 | Path:
    """补丁文件必须为工作区内相对路径（绝对路径/.. 逃逸一律拒绝）。"""
    if not isinstance(相对路径, str) or not 相对路径.strip():
        return _失败("路径逃逸", "补丁文件必须为非空相对路径")
    if Path(相对路径).is_absolute():
        return _失败("路径逃逸", f"补丁文件禁止绝对路径: {相对路径}")
    根 = Path(工作区路径).resolve()
    目标 = (根 / 相对路径).resolve()
    try:
        if os.path.commonpath([str(根), str(目标)]) != str(根):
            return _失败("路径逃逸", f"补丁文件路径越出工作区: {相对路径}")
    except ValueError:
        return _失败("路径逃逸", f"补丁文件路径越出工作区: {相对路径}")
    return 目标


def _应用补丁(工作区路径: str, 补丁列表: object) -> 结果:
    """精确补丁应用：旧内容必须恰好匹配 1 次，多重匹配/未匹配拒绝。"""
    if not isinstance(补丁列表, list) or not 补丁列表:
        return _失败("参数不合法", "补丁列表必须为非空列表")
    for 补丁 in 补丁列表:
        if not isinstance(补丁, dict) or not all(
                键 in 补丁 for 键 in ("文件", "旧内容", "新内容")):
            return _失败("参数不合法", "补丁必须包含 文件/旧内容/新内容 字段")
        目标 = _补丁目标(工作区路径, 补丁["文件"])
        if isinstance(目标, 结果):
            return 目标
        读取 = _调用支持库("文件系统支持库.文件操作.读取文件",
                    {"文件路径": str(目标), "编码": "utf-8"})
        if not 读取.成功:
            return 读取
        次数 = 读取.值.count(补丁["旧内容"])
        if 次数 != 1:
            return _失败("补丁多重匹配",
                          f"旧内容必须恰好匹配 1 次，实际 {次数} 次: {补丁['文件']}")
        写入 = _调用支持库("文件系统支持库.文件操作.写入文件", {
            "文件路径": str(目标), "编码": "utf-8",
            "内容": 读取.值.replace(补丁["旧内容"], 补丁["新内容"]),
        })
        if not 写入.成功:
            return 写入
    return 结果.成功结果()


def _宿主目录() -> 结果 | Path:
    """宿主临时目录由支持库层管理：经网关创建唯一运行目录并登记。

    经 HTTP 网关时支持库能力只接受可 JSON 序列化的返回；创建唯一
    运行目录 返回 Path 对象无法跨网关传输，改为模块生成唯一目录名，
    经 文件系统支持库.文件操作.创建目录 真实创建并登记临时资源。
    """
    临时根 = os.environ.get("TMPDIR") or os.environ.get("TEMP") or "/tmp"
    宿主路径 = str(Path(临时根) / f"修复宿主_{uuid.uuid4().hex[:12]}")
    创建 = _调用支持库("文件系统支持库.文件操作.创建目录", {"目录路径": 宿主路径})
    if not 创建.成功:
        return 创建
    登记 = _调用支持库("文件系统支持库.文件操作.登记临时资源", {"路径": 宿主路径})
    if not 登记.成功:
        return 登记
    return Path(宿主路径)


def _关闭并登记(仓库路径: str, 工作区路径: str, 超时秒: float) -> 结果:
    """关闭工作区；未提交修改等拒绝时登记临时资源兜底清理。"""
    关闭 = _调用支持库("版本控制支持库.Git操作.关闭工作区", {
        "仓库路径": 仓库路径, "目标路径": 工作区路径, "超时秒": 超时秒,
    })
    if not 关闭.成功:
        _调用支持库("文件系统支持库.文件操作.登记临时资源", {"路径": 工作区路径})
    return 关闭


def 创建修复工作区(仓库路径: str, 补丁列表: list, 验证命令: list,
                   提交消息: str, 期望摘要: str = "", 检查文件: str = "",
                   分支名: str = "", 超时秒: float = 60.0) -> 结果:
    """Git worktree + 精确补丁 + 定向验证 + 可回滚提交组合流程。"""
    if not isinstance(提交消息, str) or not 提交消息.strip():
        return _失败("参数不合法", "提交消息必须为非空文本")
    提供者 = _调用支持库("版本控制支持库.Git操作.检查提供者", {})
    if not 提供者.成功:
        return 提供者
    宿主 = _宿主目录()
    if isinstance(宿主, 结果):
        return 宿主
    工作区路径 = str(宿主 / "修复工作区")
    创建参数 = {
        "仓库路径": 仓库路径, "新路径": 工作区路径, "超时秒": 超时秒,
    }
    if 分支名:
        创建参数["分支名"] = 分支名
    创建 = _调用支持库("版本控制支持库.Git操作.创建工作区", 创建参数)
    if not 创建.成功:
        _关闭并登记(仓库路径, 工作区路径, 超时秒)
        return 创建
    补丁结果 = _应用补丁(工作区路径, 补丁列表)
    if not 补丁结果.成功:
        _关闭并登记(仓库路径, 工作区路径, 超时秒)
        return 补丁结果
    验证结果 = 验证修复(工作区路径, 验证命令, 期望摘要, 检查文件, 超时秒)
    if not 验证结果.成功:
        _关闭并登记(仓库路径, 工作区路径, 超时秒)
        return 验证结果
    提交结果 = _调用支持库("版本控制支持库.Git操作.提交", {
        "仓库路径": 工作区路径, "路径列表": [工作区路径],
        "消息": 提交消息, "超时秒": 超时秒,
    })
    关闭结果 = _关闭并登记(仓库路径, 工作区路径, 超时秒)
    if not 提交结果.成功:
        return 提交结果
    return 结果.成功结果({
        "路径": 工作区路径,
        "分支": 创建.值["分支"],
        "提交": 提交结果.值["提交"],
        "摘要": 验证结果.值.get("摘要", ""),
        "工作区清理": 关闭结果.错误码 if not 关闭结果.成功 else "已关闭",
    })


def 验证修复(仓库路径: str, 验证命令: object, 期望摘要: str = "",
             检查文件: str = "", 超时秒: float = 60.0) -> 结果:
    """运行验证命令（受管进程）并检查内容摘要。"""
    if not isinstance(验证命令, list) or not 验证命令 or not all(
            isinstance(项, str) for 项 in 验证命令):
        return _失败("参数不合法", "验证命令必须为非空文本列表")
    执行 = _调用支持库("本地进程.执行命令受控", {
        "命令列表": 验证命令, "超时秒": 超时秒, "工作目录": 仓库路径,
    })
    if not 执行.成功:
        return _失败("验证失败", f"验证命令执行失败: {执行.错误说明}",
                      详情={"原始错误码": 执行.错误码})
    摘要 = ""
    if 检查文件 and 期望摘要:
        try:
            摘要结果 = _调用支持库("系统核心支持库.资源管理.创建内容摘要", {
                "文件路径": str(Path(仓库路径).resolve() / 检查文件),
            })
        except OSError:
            return _失败("验证失败", f"摘要检查文件不可读: {检查文件}")
        if not 摘要结果.成功 or not isinstance(摘要结果.值, str):
            return _失败("验证失败", f"摘要检查文件不可读: {检查文件}")
        摘要 = 摘要结果.值
        if 摘要 != 期望摘要:
            return _失败("验证失败", f"内容摘要不匹配: 期望 {期望摘要} 实际 {摘要}")
    return 结果.成功结果({
        "输出": 执行.值["输出"], "摘要": 摘要, "验证通过": True,
    })


def 回滚修复(仓库路径: str, 提交哈希: str, 操作: str = "回滚",
             超时秒: float = 60.0) -> 结果:
    """回滚修复：git revert（回滚）或 git cherry-pick（挑拣合入）。"""
    if 操作 not in ("回滚", "挑拣合入"):
        return _失败("参数不合法", "操作必须为 回滚 或 挑拣合入")
    状态 = _调用支持库("版本控制支持库.Git操作.当前状态", {"仓库路径": 仓库路径, "超时秒": 超时秒})
    if not 状态.成功:
        return 状态
    if 状态.值.get("未提交修改"):
        return _失败("未提交修改",
                      f"{操作}前必须提交或清理未提交修改",
                      详情={"未提交修改": 状态.值["未提交修改"]})
    执行 = _调用支持库("版本控制支持库.Git操作.回滚", {
        "仓库路径": 仓库路径, "提交哈希": 提交哈希, "超时秒": 超时秒,
    }) if 操作 == "回滚" else _调用支持库("版本控制支持库.Git操作.挑拣合入", {
        "仓库路径": 仓库路径, "提交哈希": 提交哈希, "超时秒": 超时秒,
    })
    if not 执行.成功:
        if 执行.错误码 == "冲突":
            return 执行
        return _失败("回滚失败", f"{操作}失败: {执行.错误说明}",
                      详情={"原始错误码": 执行.错误码})
    return 执行


def 获取当前提交哈希(仓库路径: str, 超时秒: float = 60.0) -> 结果:
    """获取仓库当前提交哈希与分支（经调用器 Git操作 能力）。"""
    return _调用支持库("版本控制支持库.Git操作.获取当前提交哈希", {
        "仓库路径": 仓库路径, "超时秒": 超时秒,
    })
