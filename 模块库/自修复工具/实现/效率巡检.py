"""效率巡检实现：把开发效率巡检收成原子能力（一条调用拿到结构化结论 + HTML 报告）。

背景（华哥 2026-09-21 口径）：「你这次的巡检，结果还要去探索，你要补充这个巡检的原子能力。
**下次一个 html 就能告诉我答案**。」

修前实测：全仓搜「巡检」「效率」「度量」**零命中** —— 要看效率必须自己敲
`python3.14 -m 开发工具.开发效率巡检`、再翻 `工程缓存/运行数据/开发效率巡检/*.json`、
再读实现才明白口径。本模块把它的产出**收成一条能力**：

  · **不新建第二套判据**：四类占比 / 黑洞计数 / 归因 / 判级全部由
    `开发工具/开发效率巡检.py` 给出；本模块只调它、读它写下的快照 json，
    把结论摆成字段（判据仍只有一处）。
  · **默认产 HTML**（该工具的 `--html` 已默认真，2026-09-21 同批改），并把
    **HTML 绝对路径**随结果返回 —— 调用方（或人）打开那一个文件即看全部答案：
    卡片（路数/调用/累计分钟/超时路/四类占比/黑洞/纪律未送达）+ 慢命令 Top20 +
    逐路明细 + 归因 + 趋势 + 优化方案（按判据）。
  · **fail-closed**：快照路径解析不出来、或快照读不到，一律如实报「未核验」，
    不把「跑过了但没读到结论」当成功。
  · **要巡检的树是显式参数**（`源码根`，债务 #217）：本模块不用「我住在哪」代替
    「要巡检哪棵树」——留空取本模块所在树（源码树里跑时行为不变），显式给出时按该树
    （制品里的本能力据此也能对着源码树巡检，见 `_源码根`）。

执行腿经唯一能力调用器调 `系统核心支持库.进程管理.执行命令`（argv 直启，不经 shell），
本模块不 import 开发工具、不 import 支持库实现、不开子进程。
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.基础类型.结果类型 import 结果

来源 = "自修复工具"
系统根 = Path(__file__).resolve().parents[3]
解释器 = "/opt/homebrew/bin/python3.14"
巡检模块 = "开发工具.开发效率巡检"
巡检文件 = "开发工具/开发效率巡检.py"

#: 该工具打印的产物路径行：`快照：/…/20260921_155006.json` / `HTML：/…/20260921_155006.html`
快照句式 = re.compile(r"快照：\s*(?P<路径>\S+)")
HTML句式 = re.compile(r"HTML：\s*(?P<路径>\S+)")
#: 归因行：`  ⛔ sleep 等后台 15 次 → …` / `  ⚠ 慢命令…` / `  ✓ …`
归因句式 = re.compile(r"^\s*(?P<级>[⛔⚠✓])\s*(?P<正文>.+)$", re.MULTILINE)
#: 判级行：`归因判级：⛔ 3 条 / ⚠ 3 条 / ✓ 0 条 → 退出码 2`
判级句式 = re.compile(r"归因判级：⛔\s*(?P<阻断>\d+)\s*条\s*/\s*⚠\s*(?P<告警>\d+)\s*条"
                    r"\s*/\s*✓\s*(?P<通过>\d+)\s*条\s*→\s*退出码\s*(?P<退出码>-?\d+)")


def _调用支持库(能力id: str, 参数: dict) -> 结果:
    """经唯一能力调用服务调用支持库公开能力；未装配或异常时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源)
    except Exception as 错误:
        return 结果.失败("提供者不可用", f"{能力id} 调用失败: {错误}", 来源=来源)


def _失败(错误码: str, 消息: str) -> 结果:
    return 结果.失败(错误码, 消息, 来源=来源)


def _源码根(源码根: object) -> tuple[Path | None, str]:
    """解析 `源码根` 参数：留空取本模块所在树；给定则 fail-closed 校验。

    为什么把源码树做成**显式参数**（2026-09-21，债务 #217）：本模块原先用
    `系统根 = Path(__file__).resolve().parents[3]` 隐式认定「要巡检的树就是我所在的
    那棵树」。这在源码树里跑没问题，但按单腿铁律 40007 常驻网关要跑**激活制品**，
    此时本模块住在制品里、`系统根` 就成了制品根 ⇒ 巡检对着制品跑，源码树的开发效率
    读数就取错了树。把源码根显式化之后，同一个能力在源码树里跑与在制品里跑**行为一致**。

    校验 fail-closed：给定路径必须是目录、且**含巡检本体**（`开发工具/开发效率巡检.py`），
    否则回 `参数不合法` 并指名缺什么（不猜、不代建、不静默回落）。
    """
    文本 = "" if 源码根 is None else str(源码根).strip()
    if not 文本:
        return 系统根, ""
    根 = Path(文本).expanduser().resolve()
    if not 根.is_dir():
        return None, f"源码根 不是目录: {文本}"
    if not (根 / 巡检文件).is_file():
        return None, f"源码根 里没有巡检本体 {巡检文件}: {根}"
    return 根, ""


def _取输出(调用结果: 结果) -> str:
    """从 `执行命令` 的结果里取标准输出（键名兼容两种形态）。"""
    if not 调用结果.成功:
        return ""
    值 = 调用结果.值
    if isinstance(值, dict):
        for 键 in ("标准输出", "输出", "stdout"):
            文本 = 值.get(键)
            if isinstance(文本, str):
                return 文本
    if isinstance(值, str):
        return 值
    return ""


def _取退出码(调用结果: 结果) -> int:
    if not 调用结果.成功 or not isinstance(调用结果.值, dict):
        return -1
    码 = 调用结果.值.get("退出码")
    return 码 if isinstance(码, int) and not isinstance(码, bool) else -1


def 效率巡检(日志根: object = "", 小时: object = 6.0, 超时秒: object = 120.0,
             源码根: object = "") -> 结果:
    """跑开发效率巡检并把结论结构化返回（含 HTML 报告绝对路径）。

    参数：
    - `日志根`：子代理 live 日志目录；留空用工具默认（`~/.hermes/cache/delegation/live`）。
    - `小时`：只看最近 N 小时有更新的日志，默认 6。
    - `超时秒`：单次执行上限，默认 120（该工具实测 0.3~0.5 秒，余量留给首次冷启动）。
    - `源码根`：要巡检的源码树根；留空取本模块所在树（见 `_源码根`，债务 #217）。

    返回 `结果[字典]`，键含：`子代理数` / `总调用` / `累计耗时秒` / `完成` / `超时` /
    `四类占比` / `黑洞` / `纪律` / `交付留痕` / `归因判级` / `退出码` / `快照` / `HTML` /
    `结论原文`（归因逐条）/ `优化方案`（HTML 里那一节的口径）。
    """
    try:
        小时数 = float(str(小时)) if 小时 not in (None, "") else 6.0
    except (TypeError, ValueError):
        return _失败("参数不合法", f"小时 必须是数（实收 {小时!r}）")
    if 小时数 <= 0:
        return _失败("参数不合法", f"小时 必须为正数（实收 {小时}）")
    try:
        上限 = float(str(超时秒)) if 超时秒 not in (None, "") else 120.0
    except (TypeError, ValueError):
        return _失败("参数不合法", f"超时秒 必须是数（实收 {超时秒!r}）")
    if 上限 <= 0:
        return _失败("参数不合法", f"超时秒 必须为正数（实收 {超时秒}）")
    根, 说明 = _源码根(源码根)
    if 根 is None:
        return _失败("参数不合法", 说明)

    命令 = f"{解释器} -m {巡检模块} --小时 {小时数:g} --html"
    if isinstance(日志根, str) and 日志根.strip():
        命令 += f" --目录 {日志根.strip()}"

    调用结果 = _调用支持库("系统核心支持库.进程管理.执行命令",
                      {"命令": 命令, "工作目录": str(根), "超时秒": 上限})
    if not 调用结果.成功:
        return _失败("执行命令不可用",
                    f"跑开发效率巡检失败：{调用结果.错误说明}")
    输出 = _取输出(调用结果)
    退出码 = _取退出码(调用结果)

    快照命中 = 快照句式.search(输出)
    if not 快照命中:
        return _失败("未核验",
                    "巡检跑完但输出里没有「快照：」行，读不到结构化结论 —— "
                    "按未核验处理（不把跑过当通过）。原始输出尾部："
                    + 输出.strip()[-300:])
    快照路径 = Path(快照命中.group("路径"))
    if not 快照路径.is_file():
        return _失败("未核验", f"巡检声称写了快照但文件不在：{快照路径}")
    try:
        快照数据 = json.loads(快照路径.read_text(encoding="utf-8"))
    except (OSError, ValueError) as 错误:
        return _失败("未核验", f"快照读不出来（{错误}）：{快照路径}")
    汇总 = 快照数据.get("汇总") if isinstance(快照数据, dict) else None
    if not isinstance(汇总, dict):
        return _失败("未核验", f"快照里没有「汇总」段：{快照路径}")

    HTML命中 = HTML句式.search(输出)
    HTML路径 = HTML命中.group("路径") if HTML命中 else ""
    判级命中 = 判级句式.search(输出)
    判级 = ({"阻断": int(判级命中.group("阻断")), "告警": int(判级命中.group("告警")),
             "通过": int(判级命中.group("通过"))} if 判级命中 else 快照数据.get("判级", {}))

    return 结果.成功结果({
        "子代理数": 汇总.get("子代理数", 0),
        "总调用": 汇总.get("总调用", 0),
        "累计耗时秒": 汇总.get("累计耗时秒", 0),
        "批次": 汇总.get("批次", 0),
        "完成": 汇总.get("完成", 0),
        "超时": 汇总.get("超时", 0),
        "四类占比": 汇总.get("占比", {}),
        "黑洞": 汇总.get("黑洞", {}),
        "工具分布": 汇总.get("工具", {}),
        "纪律": 汇总.get("纪律", {}),
        "交付留痕": 汇总.get("交付留痕", {}),
        "归因判级": 判级,
        "退出码": 退出码,
        "结论原文": [f"{m.group('级')} {m.group('正文')}" for m in 归因句式.finditer(输出)],
        "快照": str(快照路径),
        "HTML": HTML路径,
        "说明": ("一个 HTML 即全部答案：卡片（路数/调用/累计分钟/超时路/四类占比/黑洞/"
                 "纪律未送达）+ 慢命令 Top20 + 逐路明细 + 归因 + 趋势 + 优化方案（按判据）"),
    })
