"""动态编译能力（哲学 7.1 的两个公开编译能力之一，2026-09-23 华哥裁决）。

    ＝ **静态编译的全部内容 ＋ 实际测试脚本实测**

与 `静态编译` 的关系：**同构，且共用全部装配**（`编译公共` 的传参归一与结论归并、
`静态编译._分派模块ID` 的模块id 分派）—— 差别只有**命令面的一处**：

    · `静态编译`：`--不跑点名`（步骤5 只点名，不执行；不带实际数据）
    · `动态编译`：**不加** `--不跑点名`（步骤5 真跑那些定向测试模块；带实际数据）

华哥 2026-09-23 原话：「动态编译是带实际测试脚本去跑数据的（码合规+契约+对应生成物……
+ 实际脚本实测）」「测试需要超小型的，而且和静态编译一样，多线程 + 多线程嵌套 + 还能再
往下嵌套都行」——并行口径由编译口步骤5 与生成物联动**既有**的并行腿提供
（`系统核心支持库.进程管理.执行命令集`，**不自己起第二套线程池**）。

**「超小型」的落点是编译口既有的「定向」口径**，不是本模块另加的限制：步骤5 点名的
本就是「本轮受影响包对应的测试模块」（`_定向测试点名` + 非包文件传递覆盖闭包），
不是全量测试。故本模块**不加、也不该加**自己的选择逻辑 —— 加了就是第二套判据。

为什么不把两者合成一个带开关的能力：华哥的形制是**两个能力**（哲学 7.1），
且两者的**成本差一个量级**（静态秒级、动态要真跑测试），合成一个会让「只想静态查一遍」
的调用方不小心付动态的代价。共用装配保证了它们不会漂成两套实现。
"""
from __future__ import annotations

from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果

from 模块库.自修复工具.实现.编译公共 import (
    来源, 类型全仓,
    归一传参, 归并结论,
    归一明细级别, 投影明细级别, 明细级别合法值, 明细级别默认,
)
from 模块库.自修复工具.实现.静态编译 import _分派模块ID
from 模块库.自修复工具.实现.开发编译口自检 import (
    解释器, 编译口模块, _源码根, _调用支持库, _失败, _取文本, _取整数,
)


def 动态编译(类型: object = None, 模块ID: object = None,
             超时秒: float = 900.0, 源码根: str = "",
             明细级别: object = 明细级别默认) -> 结果:
    """动态编译：静态编译的全部内容 **＋ 实际测试脚本实测**。

    传参与返回形制与 `静态编译` **逐字一致**（哲学 7.1：两类共用同一形制）：
      · 传参 `类型`（`0`＝全仓 / `1`＝指定库或模块）＋ `模块ID`（路径，`类型=0` 时可空）；
      · 返回 `成功数量` / `失败数量` ＋ `逐条明细`（含「缺乏什么导致无法自动自愈」）。

    超时默认 **900 秒**（比静态档的 600 大）：动态档要真跑测试模块，实测是本仓最贵的一段
    （编译口步骤5 单模块超时 300 秒 × 8 路并行）；给 600 会让正常的一轮被判超时。

    **`明细级别`（2026-09-24 批R·R-12，只增参数）**：`计数` / `失败项`（**默认**）/ `全量`
    —— 形制与 `静态编译` **逐字一致**（共用 `编译公共.投影明细级别` 这一条腿）。
    默认只回**计数 ＋ 失败明细**；传 `全量` 回改前的全部键，**与改前逐字节等价**。
    ★ 默认档由「全量」改成「失败项」是**口径变更**，已在
    `开发文档/分析/批R单据_R12_账本与返回体积_20260924.md` 登记并标注**须华哥确认**。
    """
    档, 档问题 = 归一明细级别(明细级别)
    if 档问题:
        return _失败("参数不合法", 档问题)
    归一类型, 条目, 传参失败 = 归一传参(类型, 模块ID)
    if 传参失败 is not None:
        return 传参失败
    根, 说明 = _源码根(源码根)
    if 根 is None:
        return _失败("参数不合法", 说明)
    # 动态档：**不加** `--不跑点名` ⇒ 步骤5 真跑定向测试（这就是与静态档的唯一命令面差别）。
    参数: list[str] = []
    if 归一类型 == 类型全仓:
        参数.append("--全仓")
    else:
        文件, 库, 问题 = _分派模块ID(条目, 根)
        if 问题:
            return _失败("参数不合法", 问题)
        if 文件:
            参数 += ["--文件", *文件]
        else:
            参数 += ["--库", *库]
    命令 = [解释器, "-m", 编译口模块, *参数]
    调用 = _调用支持库("系统核心支持库.进程管理.执行命令", {
        "命令": " ".join(命令),
        "工作目录": str(根),
        "超时秒": float(超时秒),
    })
    if not 调用.成功:
        return _失败(调用.错误码 or "提供者不可用",
                     f"执行命令 调用失败（编译口未起）: {调用.错误说明}")
    值 = 调用.值 if isinstance(调用.值, dict) else {}
    退出码 = _取整数(值, ("退出码", "返回码"), -1)
    标准输出 = _取文本(值, ("标准输出", "输出", "stdout"))
    标准错误 = _取文本(值, ("标准错误", "错误输出", "stderr"))
    return 结果.成功结果(投影明细级别(
        归并结论(标准输出, 标准错误, 退出码, " ".join(命令), 条目, str(根)), 档))


__all__ = ["动态编译"]
