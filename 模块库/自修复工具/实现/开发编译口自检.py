"""开发编译口自检实现：把底座开发编译口收成结构化五态结论。

背景（华哥 2026-09-21 裁决「py 调用的腿全砍了」）：`开发工具/开发编译口/编译口.py`
已实现完整编排（影响面清单 → 生成物核对 → 静态规则全查 → 定向测试点名），
但它只有命令行入口，Agent 只能敲 `python3.14 -m 开发工具.开发编译口.编译口`
—— 那正是被砍掉的「py 腿」。本模块把它的结论**归并与结构化**：

  · **不新建第二套判据**：全部判据仍由编译口自身与它编排的现成检查器给出；
    本模块只调它、读它的输出、把「五态结论 + 逐项结论 + 失败详情」拆成字段。
  · **不改 CLI 判据**：退出码 0/1/2 与「五态结论」行原文照收，不做二次判红。
  · **假绿防线（与本模块自身相关）**：输出里找不到「五态结论」行时置
    `五态结论=未核验`（fail-closed）—— 结论解析不出来绝不当通过。
  · **参数先 fail-closed**：`变更文件` 里任一条不是项目根内的已存在文件，
    一律在起编译口之前回 `参数不合法` 并指名那一条（不起 40 秒的无效跑）。

执行腿经唯一能力调用器调 `系统核心支持库.进程管理.执行命令`（argv 直启，不经 shell），
本模块不 import 开发工具、不 import 支持库实现、不开子进程。
"""

from __future__ import annotations

import re
from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.基础类型.逻辑类型 import 真, 假

来源 = "自修复工具"
系统根 = Path(__file__).resolve().parents[3]
解释器 = "/opt/homebrew/bin/python3.14"
编译口模块 = "开发工具.开发编译口.编译口"

#: 逐项结论行：`  [阻断] 摘要闭合 退出码=0 耗时=1.23s：…` / `  [只报告] 测试伪装门禁 退出码=1 耗时=…s：…`
检查项句式 = re.compile(
    r"^\s*\[(?P<角色>阻断|只报告)\]\s*(?P<名字>\S+)\s+退出码=(?P<退出码>-?\d+)"
    r"(?:\s+耗时=(?P<耗时>[\d.]+)s)?"
)
#: 结论行：`五态结论：干净通过 —— …`
结论句式 = re.compile(r"五态结论：\s*(?P<结论>干净通过|债务冻结|只报告|未核验|失败)")
#: 定向测试点名行：`  python3.14 -m unittest 测试中心.…`
点名声式 = re.compile(r"^\s*(?:python3\S*\s+)?-m\s+unittest\s+(?P<模块>\S+)\s*$")
#: 存量冻结/基线字样（债务冻结信息位；不改五态，只供调用方看见）
存量句式 = re.compile(r"存量|基线")


def _调用支持库(能力id: str, 参数: dict) -> 结果:
    """经唯一能力调用服务调用支持库公开能力；未装配或异常时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源)
    except Exception as 错误:
        return 结果.失败("提供者不可用", f"{能力id} 调用失败: {错误}", 来源=来源)


def _失败(错误码: str, 消息: str) -> 结果:
    return 结果.失败(错误码, 消息, 来源=来源)


def _取文本(值: object, 键表: tuple[str, ...]) -> str:
    """从能力返回值里按候选键名取文本（不同形态键名不一致，逐个试）。"""
    if not isinstance(值, dict):
        return ""
    for 键 in 键表:
        候选 = 值.get(键)
        if isinstance(候选, str):
            return 候选
    return ""


def _取整数(值: object, 键表: tuple[str, ...], 缺省: int) -> int:
    if not isinstance(值, dict):
        return 缺省
    for 键 in 键表:
        候选 = 值.get(键)
        if isinstance(候选, bool):
            continue
        if isinstance(候选, int):
            return 候选
    return 缺省


def _校验变更文件(变更文件: object) -> 结果 | list[str]:
    """fail-closed 参数门：逐条必须是项目根内的已存在文件（不起无效的 40 秒跑）。"""
    if 变更文件 in (None, "", []):
        return []
    if not isinstance(变更文件, list):
        return _失败("参数不合法", "变更文件 必须是列表型（每项一个项目根相对路径）")
    归一: list[str] = []
    for 项 in 变更文件:
        if not isinstance(项, str) or not 项.strip():
            return _失败("参数不合法", "变更文件 的每一项必须是非空文本路径")
        文本 = 项.strip().replace("\\", "/")
        if 文本.startswith("/"):
            return _失败("参数不合法", f"变更文件 必须是项目根相对路径，不接受绝对路径: {文本}")
        绝对 = (系统根 / 文本).resolve()
        try:
            绝对.relative_to(系统根)
        except ValueError:
            return _失败("参数不合法", f"变更文件 路径越出项目根: {文本}")
        if not 绝对.is_file():
            return _失败("参数不合法", f"变更文件 不存在（项目根内没有这个文件）: {文本}")
        归一.append(文本)
    return 归一


def _组命令(变更文件: list[str], 全仓: bool, 自证: bool, 联动: bool) -> list[str]:
    """拼编译口命令行（argv 直启；显式点名优先，其次全仓/自证，都没有则默认 --变更）。"""
    参数: list[str] = []
    if 变更文件:
        参数 += ["--文件", *变更文件]
    elif 全仓:
        参数.append("--全仓")
    elif 自证:
        参数.append("--自证")
    else:
        参数.append("--变更")
    if 联动:
        参数.append("--联动")
    return [解释器, "-m", 编译口模块, *参数]


def _解析(输出: str) -> dict:
    """把编译口标准输出归并成结构化结论（只读解析，不另立判据）。"""
    检查项表: list[dict] = []
    点名单: list[str] = []
    结论行 = ""
    结论原文: list[str] = []
    已进结论 = 假
    for 行 in 输出.splitlines():
        命中 = 检查项句式.match(行)
        if 命中:
            退出码 = int(命中.group("退出码"))
            检查项表.append({
                "名字": 命中.group("名字"),
                "角色": 命中.group("角色"),
                "退出码": 退出码,
                "耗时秒": float(命中.group("耗时") or 0.0),
                "结论": ("未核验" if 退出码 == -1
                        else "通过" if 退出码 == 0
                        else "判红" if 命中.group("角色") == "阻断"
                        else "只报告判红"),
                "原文": 行.strip(),
            })
            continue
        if 行.strip() == "═══ 结论 ═══":
            已进结论 = 真
            continue
        if 已进结论:
            结论原文.append(行.strip())
            文本 = 结论句式.search(行)
            if 文本 and not 结论行:
                结论行 = 文本.group("结论")
            continue
        点名 = 点名声式.match(行)
        if 点名:
            点名单.append(点名.group("模块"))
    return {"检查项表": 检查项表, "结论": 结论行, "结论原文": 结论原文,
            "定向测试点名": 点名单}


def 运行开发编译口(变更文件: object = None, 全仓: bool = 假, 自证: bool = 假,
                   联动: bool = 假, 超时秒: float = 600.0) -> 结果:
    """跑开发编译口并回结构化五态结论（干净通过/债务冻结/只报告/未核验/失败）。

    入参：变更文件=显式点名（项目根相对路径列表，并行期首选）；全仓/自证=口径开关；
    联动=允许重算生成物（默认只读）。执行腿是唯一能力调用器 → 执行命令（argv 直启）。
    返回：五态结论 / 退出码 / 检查项表（逐项角色+退出码+结论）/ 失败门禁 / 未核验项 /
    只报红项 / 结论原文 / 定向测试点名 / 债务冻结（信息位）/ 命令 / 标准输出 / 标准错误。
    """
    归一 = _校验变更文件(变更文件)
    if isinstance(归一, 结果):
        return 归一
    命令 = _组命令(归一, bool(全仓), bool(自证), bool(联动))
    调用 = _调用支持库("系统核心支持库.进程管理.执行命令", {
        "命令": " ".join(命令),
        "工作目录": str(系统根),
        "超时秒": float(超时秒),
    })
    if not 调用.成功:
        return _失败(调用.错误码 or "提供者不可用",
                     f"执行命令 调用失败（编译口未起）: {调用.错误说明}")
    值 = 调用.值 if isinstance(调用.值, dict) else {}
    退出码 = _取整数(值, ("退出码", "返回码"), -1)
    标准输出 = _取文本(值, ("标准输出", "输出", "stdout"))
    标准错误 = _取文本(值, ("标准错误", "错误输出", "stderr"))
    解析 = _解析(标准输出)
    结论 = 解析["结论"]
    if not 结论:
        # 假绿防线：结论行解析不出来 → 未核验（绝不当通过）
        结论 = "未核验"
    检查项表 = 解析["检查项表"]
    失败门禁 = [项["原文"] for 项 in 检查项表 if 项["结论"] == "判红"]
    未核验项 = [项["原文"] for 项 in 检查项表 if 项["结论"] == "未核验"]
    只报红项 = [项["原文"] for 项 in 检查项表 if 项["结论"] == "只报告判红"]
    if not 检查项表 and 结论 != "未核验":
        结论 = "未核验"
        未核验项.append("逐项结论一行都没解析出来（结论不可核验）")
    return 结果.成功结果({
        "五态结论": 结论,
        "退出码": 退出码,
        "检查项表": 检查项表,
        "检查项数": len(检查项表),
        "失败门禁": 失败门禁,
        "失败门禁数": len(失败门禁),
        "未核验项": 未核验项,
        "未核验数": len(未核验项),
        "只报红项": 只报红项,
        "只报红数": len(只报红项),
        "债务冻结": bool(存量句式.search(标准输出)),
        "结论原文": 解析["结论原文"],
        "定向测试点名": 解析["定向测试点名"],
        "命令": " ".join(命令),
        "标准输出": 标准输出,
        "标准错误": 标准错误,
        "项目根": str(系统根),
    })
