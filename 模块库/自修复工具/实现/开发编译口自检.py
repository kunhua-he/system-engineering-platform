"""开发编译口自检实现：把底座开发编译口收成结构化五态结论。

背景（华哥 2026-09-21 裁决「py 调用的腿全砍了」）：`开发工具/开发编译口/编译口.py`
已实现完整编排（影响面清单 → 生成物核对 → 静态规则全查 → 定向测试点名），
但它只有命令行入口，Agent 只能敲 `python3.14 -m 开发工具.开发编译口.编译口`
—— 那正是被砍掉的「py 腿」。本模块把它的结论**归并与结构化**：

  · **不新建第二套判据**：全部判据仍由编译口自身与它编排的现成检查器给出；
    本模块只调它、读它的输出、把「五态结论 + 逐项结论 + 失败详情」拆成字段。
  · **不改 CLI 判据**：退出码 0/1/2 与「五态结论」行原文照收，不做二次判红。
  · **假绿防线（与本模块自身相关）**：输出里找不到「五态结论」行时置
    `五态结论=未核验`（fail-closed）—— 结论解析不出来绝不当通过。
  · **参数先 fail-closed**：`变更文件` 里任一条不是项目根内的已存在文件，
    一律在起编译口之前回 `参数不合法` 并指名那一条（不起 40 秒的无效跑）。
  · **要检查的树是显式参数**（`源码根`，债务 #217）：本模块不用「我住在哪」代替
    「要检查哪棵树」——留空取本模块所在树（源码树里跑时行为不变），显式给出时按该树
    （制品里的本能力据此也能对着源码树跑编译口，见 `_源码根`）。

执行腿经唯一能力调用器调 `系统核心支持库.进程管理.执行命令`（argv 直启，不经 shell），
本模块不 import 开发工具、不 import 支持库实现、不开子进程。
"""

from __future__ import annotations

import re
from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.基础类型.逻辑类型 import 真, 假

来源 = "自修复工具"
系统根 = Path(__file__).resolve().parents[3]
解释器 = "/opt/homebrew/bin/python3.14"
编译口模块 = "开发工具.开发编译口.编译口"
编译口文件 = "开发工具/开发编译口/编译口.py"

#: 逐项结论行：`  [阻断] 摘要闭合 退出码=0 耗时=1.23s：…` / `  [只报告] 测试伪装门禁 退出码=1 耗时=…s：…`
检查项句式 = re.compile(
    r"^\s*\[(?P<角色>阻断|只报告)\]\s*(?P<名字>\S+)\s+退出码=(?P<退出码>-?\d+)"
    r"(?:\s+耗时=(?P<耗时>[\d.]+)s)?"
)
#: 结论行：`五态结论：干净通过 —— …`
结论句式 = re.compile(r"五态结论：\s*(?P<结论>干净通过|债务冻结|只报告|未核验|失败)")
#: 定向测试点名行：`  python3.14 -m unittest 测试中心.…`
点名声式 = re.compile(r"^\s*(?:python3\S*\s+)?-m\s+unittest\s+(?P<模块>\S+)\s*$")
#: 存量冻结/基线字样（债务冻结信息位；不改五态，只供调用方看见）
存量句式 = re.compile(r"存量|基线")


def _调用支持库(能力id: str, 参数: dict) -> 结果:
    """经唯一能力调用服务调用支持库公开能力；未装配或异常时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源)
    except Exception as 错误:
        return 结果.失败("提供者不可用", f"{能力id} 调用失败: {错误}", 来源=来源)


def _失败(错误码: str, 消息: str) -> 结果:
    return 结果.失败(错误码, 消息, 来源=来源)


def _取文本(值: object, 键表: tuple[str, ...]) -> str:
    """从能力返回值里按候选键名取文本（不同形态键名不一致，逐个试）。"""
    if not isinstance(值, dict):
        return ""
    for 键 in 键表:
        候选 = 值.get(键)
        if isinstance(候选, str):
            return 候选
    return ""


def _取整数(值: object, 键表: tuple[str, ...], 缺省: int) -> int:
    if not isinstance(值, dict):
        return 缺省
    for 键 in 键表:
        候选 = 值.get(键)
        if isinstance(候选, bool):
            continue
        if isinstance(候选, int):
            return 候选
    return 缺省


def _是源码树(根: Path) -> bool:
    """判据：`AGENTS.md` 与 `开发文档/` 同时在 —— 源码树有、制品内镜像根两者都没有。

    实测 2026-09-22：制品内镜像根（`…/平台客户端环境/平台客户端/平台客户端`）两个都缺，
    且它下面没有 `平台客户端` 包可导入 —— 在那跑 `-m 开发工具…` 直接 `ModuleNotFoundError`。
    """
    return (根 / "AGENTS.md").is_file() and (根 / "开发文档").is_dir()


def _源码根(源码根: object) -> tuple[Path | None, str]:
    """解析 `源码根` 参数：留空取本模块所在树；给定则 fail-closed 校验。

    为什么把源码树做成**显式参数**（2026-09-21，债务 #217）：本模块原先用
    `系统根 = Path(__file__).resolve().parents[3]` 隐式认定「要检查的树就是我所在的
    那棵树」。这在源码树里跑没问题，但按单腿铁律 40007 常驻网关要跑**激活制品**，
    此时本模块住在制品里、`系统根` 就成了制品根，而 `AGENTS.md`／`开发文档/` 不在制品的
    `顶层包表` 里 ⇒ 源码树的文件一律被判「不存在」，**开发循环失去能力腿**（实测现场：
    `参数不合法：变更文件 不存在（项目根内没有这个文件）: AGENTS.md`）。把源码根显式化
    之后，同一个能力在源码树里跑与在制品里跑**行为一致**：制品里的本能力也能对着
    指定的源码树跑编译口（要检查哪棵树，本来就是这件事的真实输入）。

    校验 fail-closed：给定路径必须是目录、且**含编译口本体**（`开发工具/开发编译口/编译口.py`），
    否则回 `参数不合法` 并指名缺什么（不猜、不代建、不静默回落）。
    """
    文本 = "" if 源码根 is None else str(源码根).strip()
    if not 文本:
        # 留空取本模块所在树 —— 但**先判它是不是真源码树**：网关跑激活制品时本模块住在
        # 制品里，`系统根` 是制品内镜像根，它没有 `AGENTS.md`／`开发文档/`、也没有
        # `平台客户端` 包可导入 ⇒ 子进程一启动就 `ModuleNotFoundError`。
        # 实测 2026-09-22：这种裸 traceback 被上层当成「本轮无受影响包」报出去，
        # 看的人以为编译口跑过了、只是没变化。fail-closed：不是源码树就明确要 源码根。
        if not _是源码树(系统根):
            return None, (
                f"本模块不在源码树里（当前推出 {系统根}，缺 AGENTS.md 或 开发文档/）"
                " —— 网关跑激活制品时必须显式给 源码根=<源码树绝对路径>"
            )
        return 系统根, ""
    根 = Path(文本).expanduser().resolve()
    if not 根.is_dir():
        return None, f"源码根 不是目录: {文本}"
    if not (根 / 编译口文件).is_file():
        return None, f"源码根 里没有编译口本体 {编译口文件}: {根}"
    return 根, ""


def _校验变更文件(变更文件: object, 根: Path) -> 结果 | list[str]:
    """fail-closed 参数门：逐条必须是**给定源码根**内的已存在文件（不起无效的 40 秒跑）。"""
    if 变更文件 in (None, "", []):
        return []
    if not isinstance(变更文件, list):
        return _失败("参数不合法", "变更文件 必须是列表型（每项一个项目根相对路径）")
    归一: list[str] = []
    for 项 in 变更文件:
        if not isinstance(项, str) or not 项.strip():
            return _失败("参数不合法", "变更文件 的每一项必须是非空文本路径")
        文本 = 项.strip().replace("\\", "/")
        if 文本.startswith("/"):
            return _失败("参数不合法", f"变更文件 必须是项目根相对路径，不接受绝对路径: {文本}")
        绝对 = (根 / 文本).resolve()
        try:
            绝对.relative_to(根)
        except ValueError:
            return _失败("参数不合法", f"变更文件 路径越出项目根: {文本}")
        if not 绝对.is_file():
            return _失败("参数不合法", f"变更文件 不存在（项目根内没有这个文件）: {文本}")
        归一.append(文本)
    return 归一


def _校验库列表(库列表: object) -> 结果 | list[str]:
    """fail-closed 参数门：`库列表` 逐条必须是非空文本的包 id（形如 `模块库.自修复工具`）。

    只做**形状**校验，不在这里查包是否存在 —— 「这个包 id 在不在」的判据是编译口的
    `_影响面`（它本来就扫全仓 `包声明.json` 建包目录表），未知包由编译口 fail-closed
    退 2 并点名。在这里再扫一遍就是同一判据的第二条腿（哲学 1.2）。
    """
    if 库列表 in (None, "", []):
        return []
    if not isinstance(库列表, list):
        return _失败("参数不合法", "库列表 必须是列表型（每项一个包 id，如 模块库.自修复工具）")
    归一: list[str] = []
    for 项 in 库列表:
        if not isinstance(项, str) or not 项.strip():
            return _失败("参数不合法", "库列表 的每一项必须是非空文本的包 id")
        归一.append(项.strip())
    return 归一


def _组命令(变更文件: list[str], 库列表: list[str], 全仓: bool, 自证: bool,
           只读: bool) -> list[str]:
    """拼编译口命令行（argv 直启；显式点名优先，其次全仓/自证，都没有则默认 --变更）。

    点名优先级：`变更文件`（文件清单）→ `库列表`（包 id 清单）→ `--全仓` / `--自证`。
    `库列表` 是华哥 2026-09-22 定的口径：「改完代码，直接把库的 ID 传过去，然后就编译就行了」
    —— 调用方传的是**变量（库 id）**，不是路径、更不是命令。

    `只读=假`（默认）时**不加任何开关**：全自动是编译口的默认行为（华哥 2026-09-22
    「尽量不需要人工维护……就用全自动」），只有显式 `只读=真` 才加 `--只读` 降级。
    """
    参数: list[str] = []
    if 变更文件:
        参数 += ["--文件", *变更文件]
    elif 库列表:
        参数 += ["--库", *库列表]
    elif 全仓:
        参数.append("--全仓")
    elif 自证:
        参数.append("--自证")
    else:
        参数.append("--变更")
    if 只读:
        参数.append("--只读")
    return [解释器, "-m", 编译口模块, *参数]


def _解析(输出: str) -> dict:
    """把编译口标准输出归并成结构化结论（只读解析，不另立判据）。"""
    检查项表: list[dict] = []
    点名单: list[str] = []
    结论行 = ""
    结论原文: list[str] = []
    已进结论 = 假
    for 行 in 输出.splitlines():
        命中 = 检查项句式.match(行)
        if 命中:
            退出码 = int(命中.group("退出码"))
            检查项表.append({
                "名字": 命中.group("名字"),
                "角色": 命中.group("角色"),
                "退出码": 退出码,
                "耗时秒": float(命中.group("耗时") or 0.0),
                "结论": ("未核验" if 退出码 == -1
                        else "通过" if 退出码 == 0
                        else "判红" if 命中.group("角色") == "阻断"
                        else "只报告判红"),
                "原文": 行.strip(),
            })
            continue
        if 行.strip() == "═══ 结论 ═══":
            已进结论 = 真
            continue
        if 已进结论:
            结论原文.append(行.strip())
            文本 = 结论句式.search(行)
            if 文本 and not 结论行:
                结论行 = 文本.group("结论")
            continue
        点名 = 点名声式.match(行)
        if 点名:
            点名单.append(点名.group("模块"))
    return {"检查项表": 检查项表, "结论": 结论行, "结论原文": 结论原文,
            "定向测试点名": 点名单}


def _加建议上线(出: dict, *, 根: Path, 结论: str, 受影响包数: int,
             上线: bool, 超时秒: float) -> dict:
    """给编译口结论加上「建议上线」，并在 上线=真 时接上上线链。

    `建议上线` = 受影响包非空（本轮真改到了某个包）⇒ 制品里的能力面可能变了，
    必须重建 + 重启才在 MCP 上生效（热接入不重载已导入模块，见未完成事项 #195）。
    让**编译口自己说**要不要上线，调用方不必记得 —— 「要人记得」的开关本身就是漂移源。

    `建议上线` 是**三态**：编译口未跑成（未核验/失败）／有受影响包／真无受影响包。
    前两者不得混：实测 2026-09-22 混过一次 —— 制品里裸 traceback（未核验、受影响包 0）
    被报成「本轮无受影响包：没有包的能力面变化，不必重建」，看的人以为编译过了。
    """
    if 结论 in ("未核验", "失败"):
        建议 = False
        理由 = (f"编译口未跑成（结论={结论}）—— 这不是「没有变化」，是没验；"
                "先看 标准错误 修红，再谈上线")
    elif 受影响包数 > 0:
        建议 = True
        理由 = ("本轮有受影响包（能力面可能变了）：热接入不重载已导入模块，"
                "须重建制品 + 重启网关才在 MCP 上生效；传 上线=真 可一条走完")
    else:
        建议 = False
        理由 = "本轮无受影响包：没有包的能力面变化，不必重建"
    出["建议上线"] = 建议
    出["建议上线理由"] = 理由
    if 上线:
        if 结论 in ("未核验", "失败"):
            出["上线"] = {"已上线": False,
                        "原因": f"编译口结论={结论}，按「红的不上线」跳过（先修红再上线）"}
        else:
            出["上线"] = _上线(根, 超时秒)
    return 出


def _解析回执(值: dict) -> dict:
    """从 `执行命令` 的返回里取子进程回执 JSON。

    子进程（`重启网关.py`）把结论打成 JSON 写 **stdout**，`执行命令` 的返回里它是
    `标准输出` 字符串 —— **不是顶层键**。实测 2026-09-22：直接 `值.get("已触发")` 恒为假，
    于是「构建成功、重启也成功」被报成「重启未触发」，上线链实际断在最后一环（白干一轮）。
    """
    import json
    for 键 in ("标准输出", "输出", "stdout"):
        文本 = 值.get(键)
        if isinstance(文本, str) and 文本.strip():
            try:
                解析 = json.loads(文本.strip())
            except Exception:
                continue
            if isinstance(解析, dict):
                return 解析
    return {}


def _取受影响包数(标准输出: str, 归一库: list[str]) -> int:
    """受影响包数：优先取步骤1 报的「受影响包 N」（`--库`/`--变更` 两档都有）。

    此前直接用「定向测试点名」长度当受影响包数 —— `--库` 档下点名列表解析为空，
    于是恒报「本轮无受影响包：没有包的能力面变化，不必重建」（2026-09-22 实测）。
    """
    import re
    命中 = re.search(r"受影响包 (\d+)", 标准输出)
    if 命中:
        return int(命中.group(1))
    return len(归一库 or [])


def _上线(根: Path, 超时秒: float) -> dict:
    """上线链：构建并安装制品 → 触发网关重启（**一条调用替代固定 4 轮**）。

    华哥 2026-09-22「先把浪费时间的找出原理，然后修好浪费速度的问题」：改过能力实现后，
    「构建制品 → 入库 → 安装 → 重启 → 验收」原是一个**每次都一样**的固定序列，
    却要 4 轮 MCP 往返（实测墙钟 45 秒 + 3 轮）。固定序列就该组合成一步。

    为什么重启只**触发**不等待：重启会掉断本调用所在的进程组（`重启网关.py` 的 ★ 说明），
    同步等只会拿到「网关不可达」——重启成功了但拿不到结论。故触发后结论写
    `工程缓存/网关重启结果.json`，下一轮用 `重启网关.py --探活/--看结果` 取结论。
    ⇒ 上线把 4 轮收成 **2 轮**（本轮 编译+构建+触发重启；下一轮 验收）。

    为什么 `上线` 默认假（不替调用方拍板）：`决策记录 0008` 与 `重启网关.py` 都明写
    「重启会中断在途调用、打断句柄与租约，不要当成改完能力的默认动作」。默认假是尊重那条口径；
    但**返回值里带 `建议上线`**（受影响包非空 ⇒ 真），让调用方不必自己记得。
    """
    构建 = _调用支持库("自修复工具.构建平台客户端制品",
                     {"安装": 真, "源码根": str(根)})
    构建值 = 构建.值 if isinstance(构建.值, dict) else {}
    出: dict = {
        "已上线": False,
        "构建成功": bool(构建.成功 and 构建值.get("构建完成")),
        "制品摘要": str(构建值.get("制品摘要") or ""),
        "安装目标": str(构建值.get("安装目标") or ""),
        "入库消息": str(构建值.get("入库消息") or ""),
        "可重复构建校验通过": bool(构建值.get("可重复构建校验通过")),
        "构建错误": "" if 构建.成功 else f"{构建.错误码}：{构建.错误说明}",
        "重启已触发": False,
        "重启说明": "",
        "下一步": "构建未成功，未触发重启（制品没换就不该重启）",
    }
    if not 出["构建成功"]:
        return 出
    重启脚本 = 根 / "开发工具/能力网关/重启网关.py"
    重启 = _调用支持库("系统核心支持库.进程管理.执行命令", {
        "命令": f"python3.14 {重启脚本}",
        "工作目录": str(根),
        "超时秒": 60.0,
    })
    重启值 = 重启.值 if isinstance(重启.值, dict) else {}
    重启回执 = _解析回执(重启值)
    出["重启已触发"] = bool(重启.成功 and 重启回执.get("已触发"))
    if not 重启.成功:
        出["重启说明"] = f"{重启.错误码}：{重启.错误说明}"
    elif 重启回执:
        出["重启说明"] = str(重启回执.get("提示") or 重启回执.get("说明") or "")
    else:
        # 解析不出回执 = 不知道有没有触发 —— fail-closed 当没触发，并把原文带上（不静默）
        原文 = str(重启值.get("标准输出") or 重启值.get("标准错误") or "")
        出["重启说明"] = f"重启脚本回执解析不出来（原文）：{原文[:400]}"
    出["已上线"] = 出["重启已触发"]
    出["下一步"] = ("下一轮调 `重启网关.py --探活` 验收（argv/cwd/能力数/同根四项）；"
                   "验收过了才算本次能力改动真的在跑"
                   if 出["重启已触发"] else "重启未触发：查 重启说明")
    return 出


def 运行开发编译口(变更文件: object = None, 库列表: object = None, 全仓: bool = 假,
                   自证: bool = 假, 只读: bool = 假, 上线: bool = 假,
                   超时秒: float = 600.0, 源码根: str = "") -> 结果:
    """跑开发编译口并回结构化五态结论（干净通过/债务冻结/只报告/未核验/失败）。

    入参：变更文件=显式点名文件（项目根相对路径列表）；库列表=显式点名包（库）的 id 列表
    —— **华哥 2026-09-22 定的首选口径**「改完代码，直接把库的 ID 传过去，然后就编译就行了」
    （传的是**变量**，不是路径、更不是命令）；全仓/自证=口径开关；
    **只读=假（默认）即全自动**：编译口按 `开发文档/规范/生成物登记表.json` 自动生成全部
    派生凭据（华哥 2026-09-22「尽量不需要人工维护……就用全自动」）—— 人只需改代码；
    置真则只核验不生成（并行多写者同改一个仓库时降级）。源码根=要检查的源码树根，
    留空取本模块所在树（见 `_源码根`，债务 #217）。执行腿是唯一能力调用器 → 执行命令（argv 直启）。
    返回：五态结论 / 退出码 / 检查项表（逐项角色+退出码+结论）/ 失败门禁 / 未核验项 /
    只报红项 / 结论原文 / 定向测试点名 / 债务冻结（信息位）/ 命令 / 标准输出 / 标准错误。
    """
    根, 说明 = _源码根(源码根)
    if 根 is None:
        return _失败("参数不合法", 说明)
    归一 = _校验变更文件(变更文件, 根)
    if isinstance(归一, 结果):
        return 归一
    归一库 = _校验库列表(库列表)
    if isinstance(归一库, 结果):
        return 归一库
    命令 = _组命令(归一, 归一库, bool(全仓), bool(自证), bool(只读))
    调用 = _调用支持库("系统核心支持库.进程管理.执行命令", {
        "命令": " ".join(命令),
        "工作目录": str(根),
        "超时秒": float(超时秒),
    })
    if not 调用.成功:
        return _失败(调用.错误码 or "提供者不可用",
                     f"执行命令 调用失败（编译口未起）: {调用.错误说明}")
    值 = 调用.值 if isinstance(调用.值, dict) else {}
    退出码 = _取整数(值, ("退出码", "返回码"), -1)
    标准输出 = _取文本(值, ("标准输出", "输出", "stdout"))
    标准错误 = _取文本(值, ("标准错误", "错误输出", "stderr"))
    解析 = _解析(标准输出)
    结论 = 解析["结论"]
    if not 结论:
        # 假绿防线：结论行解析不出来 → 未核验（绝不当通过）
        结论 = "未核验"
    检查项表 = 解析["检查项表"]
    失败门禁 = [项["原文"] for 项 in 检查项表 if 项["结论"] == "判红"]
    未核验项 = [项["原文"] for 项 in 检查项表 if 项["结论"] == "未核验"]
    只报红项 = [项["原文"] for 项 in 检查项表 if 项["结论"] == "只报告判红"]
    if not 检查项表 and 结论 != "未核验":
        结论 = "未核验"
        未核验项.append("逐项结论一行都没解析出来（结论不可核验）")
    return 结果.成功结果(_加建议上线({
        "五态结论": 结论,
        "退出码": 退出码,
        "检查项表": 检查项表,
        "检查项数": len(检查项表),
        "失败门禁": 失败门禁,
        "失败门禁数": len(失败门禁),
        "未核验项": 未核验项,
        "未核验数": len(未核验项),
        "只报红项": 只报红项,
        "只报红数": len(只报红项),
        "债务冻结": bool(存量句式.search(标准输出)),
        "结论原文": 解析["结论原文"],
        "定向测试点名": 解析["定向测试点名"],
        "命令": " ".join(命令),
        "标准输出": 标准输出,
        "标准错误": 标准错误,
        "项目根": str(根),
    }, 根=根, 结论=结论, 受影响包数=_取受影响包数(标准输出, 归一库),
       上线=bool(上线), 超时秒=float(超时秒)))
