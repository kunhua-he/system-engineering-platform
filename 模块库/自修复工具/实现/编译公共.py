def _失败(错误码: str, 消息: str) -> 结果:
    return 结果.失败(错误码, 消息, 来源=来源)


def 归一传参(类型: object, 模块ID: object) -> tuple[int, list[str], 结果 | None]:
    """归一 `类型` / `模块ID`，返回 `(类型, 模块ID 清单, 失败结果 or None)`。

    `模块ID` 是**路径**（华哥给的形制），但它同时接受两种写法、按 `类型` 各自判：
      · `类型=1`（指定库/模块）⇒ 必须给，且每条须是**仓库根相对路径**
        （`支持库/后端/文档转换支持库/PDF生成`）或**包 id**（`模块库.自修复工具`）；
      · `类型=0`（全仓）⇒ 必须为空 —— **给了就判参数不合法**，不静默忽略：
        静默忽略会让「想编 A 结果编了全仓」这种误用变成一次白跑（哲学 3.1 一次命中）。
    """
    try:
        类型值 = int(类型)
    except (TypeError, ValueError):
        return 0, [], _失败("参数不合法",
                          f"类型 必须是整数型（0=全仓 / 1=指定库或模块），实得 {类型!r}")
    if 类型值 not in 类型取值域:
        return 0, [], _失败("参数不合法",
                          f"类型 只认 0（全仓）或 1（指定库或模块），实得 {类型值}")
    条目 = []
    if isinstance(模块ID, str):
        条目 = [段.strip() for 段 in 模块ID.splitlines() if 段.strip()]
    elif isinstance(模块ID, (list, tuple)):
        条目 = [str(段).strip() for 段 in 模块ID if str(段).strip()]
    elif 模块ID is not None:
        return 类型值, [], _失败("参数不合法",
                             f"模块ID 须是文本型路径（多条可换行或传列表），实得 {type(模块ID).__name__}")
    if 类型值 == 类型全仓:
        if 条目:
            return 类型值, [], _失败(
                "参数不合法",
                f"类型=0（全仓）时 模块ID 必须为空，实得 {len(条目)} 条 —— "
                "要编指定的库/模块请传 类型=1（不静默忽略：静默忽略会让你以为编了指定的那个）")
        return 类型值, [], None
    if not 条目:
        return 类型值, [], _失败("参数不合法", "类型=1（指定库或模块）时 模块ID 必填")
    return 类型值, 条目, None


def 解析输出(标准输出: str) -> dict:
    """把编译口的输出解析成分桶结论（结论 / 检查项表 / 点名 / 受影响包数）。

    结论解析不出来即 `未核验`（fail-closed，见本包既有 `运行开发编译口` 的同款防线）：
    解析不出 ≠ 通过。
    """
    结论 = ""
    结论原文 = ""
    检查项表: list[dict] = []
    点名: list[str] = []
    受影响包数 = 0
    for 行 in 标准输出.splitlines():
        命中结论 = 结论句式.search(行)
        if 命中结论 and not 结论:
            结论 = 命中结论.group("结论")
            结论原文 = 行.strip()
            continue
        命中检查 = 检查项句式.match(行)
        if 命中检查:
            检查项表.append({
                "角色": 命中检查.group("角色"),
                "名字": 命中检查.group("名字"),
                "退出码": int(命中检查.group("退出码")),
                "耗时秒": float(命中检查.group("耗时") or 0.0),
                "原文": 行.strip(),
            })
            continue
        命中点名 = 点名声式.match(行)
        if 命中点名:
            点名.append(命中点名.group("模块"))
            continue
        命中包 = 受影响包句式.search(行)
        if 命中包 and not 受影响包数:
            受影响包数 = int(命中包.group("包数"))
    for 项 in 检查项表:
        if 项["退出码"] == 0:
            项["结论"] = "通过"
        elif 项["角色"] == "只报告":
            项["结论"] = "只报告判红"
        else:
            项["结论"] = "判红"
    if not 结论:
        结论 = "未核验"
    return {"结论": 结论, "结论原文": 结论原文, "检查项表": 检查项表,
            "定向测试点名": 点名, "受影响包数": 受影响包数}


def 归因(文本: str) -> str:
    """按 `缺乏判据表` 给出「缺乏什么导致无法自动自愈」（匹配不上即如实说未归因）。"""
    for 关键词表, 说明 in 缺乏判据表:
        if any(词 in 文本 for 词 in 关键词表):
            return 说明
    return 缺乏_未归因


def 组逐条明细(检查项表: list[dict], 模块ID清单: list[str],
             结论: str, 标准输出: str) -> tuple[list[dict], int]:
    """逐条明细：`(明细表, 失败数量)`。

    **粒度取「检查项」而不是「包」**：编译口这一轮真正跑出来的是检查项（每项一行），
    包是检查项的**对象**。以包为粒度的话，「同一包被 3 项门禁同时点名」会被压成 1 条，
    调用方看不出到底是哪一项拦住的 —— 而修复动作恰恰按项而定。
    点名对象（库/模块）的**首选来源是入参 `模块ID清单`**：`类型=1` 时它只有一个条目，
    且那就是这一轮真正编的对象（权威来源，不用从文本里猜）；`类型=0`（全仓）时它为空，
    此时才从该项原文的**正文**（头段 `[角色] 名字 退出码=… 耗时=…s：` 之后）尽力取；
    两处都取不到就如实写空串（不编）。

    ★ 2026-09-24 修：此前**整行**都拿去搜模块名，且首段允许数字开头 ⇒ 头段 `耗时=0.97s`
    被当成模块名，全仓 19 条明细的 `模块ID或库ID` 全是耗时串（字段填错，等于没填）。
    """
    明细: list[dict] = []
    if 检查项表:
        for 项 in 检查项表:
            失败 = 项["结论"] in ("判红", "只报告判红", "未核验")
            对象 = 模块ID清单[0] if len(模块ID清单) == 1 else ""
            if not 对象:
                命中头 = 检查项句式.match(项["原文"])
                正文 = 项["原文"][命中头.end():] if 命中头 else 项["原文"]
                命中 = 模块名句式.search(正文)
                对象 = 命中.group(1) if 命中 else ""
            明细.append({
                "模块ID或库ID": 对象,
                "检查项": 项["名字"],
                "角色": 项["角色"],
                "退出码": 项["退出码"],
                "耗时秒": 项["耗时秒"],
                "结果": 项["结论"],
                "失败原因": 项["原文"] if 失败 else "",
                "缺乏什么导致无法自动自愈": 归因(项["原文"]) if 失败 else "",
                "能否自动自愈": (项["结论"] == "通过") or (归因(项["原文"]) == 缺乏_无 and 失败),
            })
        return 明细, len([项 for 项 in 明细 if 项["结果"] != "通过"])
    # 一项检查都没解析出来：按结论给单条（未核验时「缺乏什么」= 需人看一次输出，
    # 因为**解析面本身**没给出任何可归因的失败项，不许当 0 失败蒙过去）。
    if 结论 == "未核验":
        return [{
            "模块ID或库ID": "", "检查项": "", "角色": "", "退出码": -1, "耗时秒": 0.0,
            "结果": "未核验", "失败原因": "逐项结论一行都没解析出来（结论不可核验）",
            "缺乏什么导致无法自动自愈": 缺乏_未归因, "能否自动自愈": 假,
        }], 1
    return [], 0


def 归并结论(标准输出: str, 标准错误: str, 退出码: int, 命令: str,
           模块ID清单: list[str], 项目根: str) -> dict:
    """把一次编译口执行归并成**两个能力共用的返回体**（传参形制见模块 docstring）。

    返回键分两组，都必给、都不省略：
      · 华哥形制：`成功数量` / `失败数量` / `逐条明细`（每条含「缺乏什么导致无法自动自愈」）；
      · 承接既有：`五态结论` / `退出码` / `检查项表` / `失败门禁` / `未核验项` / `只报红项` /
        `结论原文` / `定向测试点名` / `命令` / `标准输出` / `标准错误` / `项目根`。
    """
    解析 = 解析输出(标准输出)
    结论 = 解析["结论"]
    明细, 失败数 = 组逐条明细(解析["检查项表"], 模块ID清单, 结论, 标准输出)
    检查项表 = 解析["检查项表"]
    成功数 = len([项 for 项 in 检查项表 if 项["结论"] == "通过"])
    if not 检查项表 and 结论 not in ("未核验",):
        # 有结论却没有逐项：如实降级为未核验（同上 fail-closed 口径）。
        结论 = "未核验"
        明细, 失败数 = 组逐条明细([], 模块ID清单, 结论, 标准输出)
    未核验明细 = [项["失败原因"] for 项 in 明细 if 项["结果"] == "未核验"]
    return {
        # ── 华哥形制 ──
        "成功数量": 成功数,
        "失败数量": 失败数,
        "逐条明细": 明细,
        # ── 承接既有 ──
        "五态结论": 结论,
        "退出码": 退出码,
        "检查项表": 检查项表,
        "检查项数": len(检查项表),
        "失败门禁": [项["失败原因"] for 项 in 明细 if 项["结果"] == "判红"],
        "未核验项": 未核验明细,
        "只报红项": [项["失败原因"] for 项 in 明细 if 项["结果"] == "只报告判红"],
        "缺失项表": [{"检查项": 项["检查项"],
                   "缺乏什么导致无法自动自愈": 项["缺乏什么导致无法自动自愈"]}
                  for 项 in 明细 if 项["结果"] != "通过" and not 项["能否自动自愈"]],
        "结论原文": 解析["结论原文"],
        "定向测试点名": 解析["定向测试点名"],
        "受影响包数": 解析["受影响包数"],
        "命令": 命令,
        "标准输出": 标准输出,
        "标准错误": 标准错误,
        "项目根": 项目根,
    }


def 归一明细级别(值: object) -> tuple[str, str]:
    """归一 `明细级别`：空 / None ⇒ 默认档；不在取值域内 ⇒ 回问题说明（**不静默取默认**）。

    返回 `(档, 问题说明)`；问题说明非空时调用方判 `参数不合法`（与 `_分派模块ID` 同形制）。
    为什么不静默回落：`明细级别` 决定调用方**看到多少明细** —— 参数写错却静默按默认档回，
    调用方会把「被裁掉的返回体」读成「本来就这么少」，正是本参数要治的那种误读。
    """
    文本 = str(值 or "").strip()
    if not 文本:
        return 明细级别默认, ""
    if 文本 not in 明细级别合法值:
        return "", f"明细级别 必须是 {'/'.join(明细级别合法值)} 之一，收到 {值!r}"
    return 文本, ""


def 投影明细级别(归并: dict, 明细级别: str) -> dict:
    """按 `明细级别` 投影归并结论（**唯一腿**，静态/动态共用）。

    判据来源（2026-09-24 批R·R-12 实测）：`自修复工具.静态编译` 当日 **55 次 / 3,574,456 字符**
    （单次最大 88,960、均值 ≈65 KB）、`动态编译` **19 次 / 1,085,088 字符**（单次最大 76,165）
    —— 每次都把 `标准输出`（实测占单次 61,412 字符里的 53,540 = 87%）与全量 `逐条明细` 回带，
    而调用方要的常常只是「几条红」。三档含义：

    · `计数`：只有计数与结论状态（成功/失败数量、检查项数、受影响包数、五态结论、退出码）；
    · `失败项`（默认）：计数 **＋** 失败明细（逐条明细只留非通过项、失败门禁、未核验项、
      只报红项、缺失项表、结论原文）—— 成功项与 `标准输出` 不回；
    · `全量`：**原样返回**（与改前逐字节一致，连键序都不动）。

    ★ 传 `全量` 时本函数**不做任何拷贝**（直接 `return 归并`），故「逐字节等价」是
      构造性成立的，不是靠比对碰巧相等。
    """
    if 明细级别 == 明细级别_全量:
        return 归并
    if 明细级别 == 明细级别_计数:
        return {键: 归并[键] for 键 in 计数档键 if 键 in 归并}
    投影 = {键: 归并[键] for 键 in 失败项档键 if 键 in 归并}
    投影["逐条明细"] = [项 for 项 in (归并.get("逐条明细") or [])
                    if isinstance(项, dict) and 项.get("结果") != "通过"]
    return 投影


