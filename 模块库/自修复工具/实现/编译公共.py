#: （字段填错，调用方读不出「哪一项对应哪个检查对象」）。首段改用 `[^\W\d]`（词字符且非数字）：
#: 库/模块名本就不可能以数字开头，故这是收窄到正确射程、不是放宽。
模块名句式 = re.compile(r"([^\W\d][\w\u4e00-\u9fff]*(?:\.[\w\u4e00-\u9fff]+)+)")

