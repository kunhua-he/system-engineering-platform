"""两个编译能力的公共装配：传参归一 + 结论归并（**唯一腿**，静态/动态共用）。

华哥 2026-09-23 裁决（哲学 7.1）：整个项目的编译/测试面**只有两个公开能力** ——
`静态编译`（不带实际数据）与 `动态编译`（静态编译全部内容 + 实际测试脚本实测）。
两者的**传参与返回形制完全一致**，故归一与归并只写一份（哲学 1.2：一类事情只有一条腿）；
两个能力各自只负责「命令怎么组」这一处差异。

## 传参标准（华哥给的形制，逐字落契约）

    · `类型`（整数型）：`0` = 全仓；`1` = 指定库/模块
    · `模块ID`（文本型，路径）：`类型=0` 时可空
    · 另有两个可选项（`超时秒` / `源码根`），语义与本包既有能力逐字一致，不新造口径

## 返回形制（华哥给的形制）

    · `成功数量` / `失败数量`
    · `逐条明细`：每条含 `模块ID或库ID`、`失败原因`、**`缺乏什么导致无法自动自愈`**

## 「缺乏什么导致无法自动自愈」的口径（本模块定义，此前无此概念）

判据是**这条失败要不要人来做一次判断/决定**，而不是「能不能重跑」：

    · 有明确修复动作、且动作不含人的取舍（改语法、补派生件、重跑生成器、对齐契约版本）
      ⇒ 能自愈，`能否自动自愈=真`，`缺乏什么` 为空；
    · 失败的根因在**本能力参数面之外**（缺测试模块、缺验证场景、制品里没有这个包、
      缺事实源、需要人来裁一个设计取舍）⇒ `能否自动自愈=假`，并把**缺的那一样具体东西**
      写进 `缺乏什么`（写"缺什么"，不写"失败了"）。

为什么要有这一栏：只回「失败 N 条」的话，调用方（人或 Agent）拿到的是**同质的 N 条噪声**，
还得自己逐条复现定性——那正是「每个红都要人复现」的代价（哲学 3.1 一次命中）。
"""
from __future__ import annotations

import re

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.基础类型.逻辑类型 import 真, 假

来源 = "自修复工具"

#: `类型` 的取值域（华哥给的形制：0=全仓 / 1=指定库或模块）。
类型全仓 = 0
类型指定 = 1
类型取值域 = (类型全仓, 类型指定)

#: 逐项结论行：`  [阻断] 摘要闭合 退出码=0 耗时=1.23s：…`
检查项句式 = re.compile(
    r"^\s*\[(?P<角色>阻断|只报告)\]\s*(?P<名字>\S+)\s+退出码=(?P<退出码>-?\d+)"
    r"(?:\s+耗时=(?P<耗时>[\d.]+)s)?")
#: 结论行：`五态结论：干净通过 —— …`
结论句式 = re.compile(r"五态结论：\s*(?P<结论>干净通过|债务冻结|只报告|未核验|失败)")
#: 定向测试点名行：`  python3.14 -m unittest 测试中心.…`
点名声式 = re.compile(r"^\s*(?:python3\S*\s+)?-m\s+unittest\s+(?P<模块>\S+)\s*$")
#: 检出「受影响包」的叙述行，取包数与包名（供逐条明细点名到库/模块）。
受影响包句式 = re.compile(r"受影响包\s*(?P<包数>\d+)")
#: 逐条明细里的库/模块名：`开发工具.契约编译.漂移检测` 这类模块路径。
模块名句式 = re.compile(r"([\w\u4e00-\u9fff]+(?:\.[\w\u4e00-\u9fff]+)+)")

#: 逐条明细的「缺乏什么」取值表（**可枚举**，调用方据此分流，不用读自然语言）。
缺乏_无 = ""
缺乏_测试模块 = "缺测试模块（该包没有对应的测试中心模块，或改的不是包内文件）"
缺乏_验证场景 = "缺验证场景（该包没有 验证场景引用.json / 验证场景）"
缺乏_制品包 = "制品里没有这个包（激活制品的基线缺该包，须先重建制品）"
缺乏_事实源 = "缺事实源（判据要读的文件/字段在现场不存在）"
缺乏_需人裁 = "需要人裁一个取舍（不是缺件，是两种做法都成立）"
缺乏_超时 = "执行超时（包本身没缺件，是这一轮没跑完）"
缺乏_未归因 = "未归因（失败原因没匹配到已知类别，须人看一次结论原文）"

#: 失败原因关键词 → 「缺乏什么」的**唯一映射**（一张表，静态/动态共用；不各处各判一套）。
#: 匹配顺序即优先级：越具体的排越前。
缺乏判据表 = (
    (("未找到测试", "无测试模块", "测试模块不存在", "ModuleNotFoundError"),
     缺乏_测试模块),
    (("验证场景引用", "验证场景", "场景缺失"), 缺乏_验证场景),
    (("制品里没有", "基线包缺失", "基线取证失败", "激活制品"), 缺乏_制品包),
    (("不存在", "没有这个文件", "缺字段", "读不到"), 缺乏_事实源),
    (("超时", "TimeoutExpired"), 缺乏_超时),
    (("需人工", "需裁决", "待裁决", "人工确认"), 缺乏_需人裁),
)


def _失败(错误码: str, 消息: str) -> 结果:
    return 结果.失败(错误码, 消息, 来源=来源)


def 归一传参(类型: object, 模块ID: object) -> tuple[int, list[str], 结果 | None]:
    """归一 `类型` / `模块ID`，返回 `(类型, 模块ID 清单, 失败结果 or None)`。

    `模块ID` 是**路径**（华哥给的形制），但它同时接受两种写法、按 `类型` 各自判：
      · `类型=1`（指定库/模块）⇒ 必须给，且每条须是**仓库根相对路径**
        （`支持库/后端/文档转换支持库/PDF生成`）或**包 id**（`模块库.自修复工具`）；
      · `类型=0`（全仓）⇒ 必须为空 —— **给了就判参数不合法**，不静默忽略：
        静默忽略会让「想编 A 结果编了全仓」这种误用变成一次白跑（哲学 3.1 一次命中）。
    """
    try:
        类型值 = int(类型)
    except (TypeError, ValueError):
        return 0, [], _失败("参数不合法",
                          f"类型 必须是整数型（0=全仓 / 1=指定库或模块），实得 {类型!r}")
    if 类型值 not in 类型取值域:
        return 0, [], _失败("参数不合法",
                          f"类型 只认 0（全仓）或 1（指定库或模块），实得 {类型值}")
    条目 = []
    if isinstance(模块ID, str):
        条目 = [段.strip() for 段 in 模块ID.splitlines() if 段.strip()]
    elif isinstance(模块ID, (list, tuple)):
        条目 = [str(段).strip() for 段 in 模块ID if str(段).strip()]
    elif 模块ID is not None:
        return 类型值, [], _失败("参数不合法",
                             f"模块ID 须是文本型路径（多条可换行或传列表），实得 {type(模块ID).__name__}")
    if 类型值 == 类型全仓:
        if 条目:
            return 类型值, [], _失败(
                "参数不合法",
                f"类型=0（全仓）时 模块ID 必须为空，实得 {len(条目)} 条 —— "
                "要编指定的库/模块请传 类型=1（不静默忽略：静默忽略会让你以为编了指定的那个）")
        return 类型值, [], None
    if not 条目:
        return 类型值, [], _失败("参数不合法", "类型=1（指定库或模块）时 模块ID 必填")
    return 类型值, 条目, None


def 解析输出(标准输出: str) -> dict:
    """把编译口的输出解析成分桶结论（结论 / 检查项表 / 点名 / 受影响包数）。

    结论解析不出来即 `未核验`（fail-closed，见本包既有 `运行开发编译口` 的同款防线）：
    解析不出 ≠ 通过。
    """
    结论 = ""
    结论原文 = ""
    检查项表: list[dict] = []
    点名: list[str] = []
    受影响包数 = 0
    for 行 in 标准输出.splitlines():
        命中结论 = 结论句式.search(行)
        if 命中结论 and not 结论:
            结论 = 命中结论.group("结论")
            结论原文 = 行.strip()
            continue
        命中检查 = 检查项句式.match(行)
        if 命中检查:
            检查项表.append({
                "角色": 命中检查.group("角色"),
                "名字": 命中检查.group("名字"),
                "退出码": int(命中检查.group("退出码")),
                "耗时秒": float(命中检查.group("耗时") or 0.0),
                "原文": 行.strip(),
            })
            continue
        命中点名 = 点名声式.match(行)
        if 命中点名:
            点名.append(命中点名.group("模块"))
            continue
        命中包 = 受影响包句式.search(行)
        if 命中包 and not 受影响包数:
            受影响包数 = int(命中包.group("包数"))
    for 项 in 检查项表:
        if 项["退出码"] == 0:
            项["结论"] = "通过"
        elif 项["角色"] == "只报告":
            项["结论"] = "只报告判红"
        else:
            项["结论"] = "判红"
    if not 结论:
        结论 = "未核验"
    return {"结论": 结论, "结论原文": 结论原文, "检查项表": 检查项表,
            "定向测试点名": 点名, "受影响包数": 受影响包数}


def 归因(文本: str) -> str:
    """按 `缺乏判据表` 给出「缺乏什么导致无法自动自愈」（匹配不上即如实说未归因）。"""
    for 关键词表, 说明 in 缺乏判据表:
        if any(词 in 文本 for 词 in 关键词表):
            return 说明
    return 缺乏_未归因


def 组逐条明细(检查项表: list[dict], 模块ID清单: list[str],
             结论: str, 标准输出: str) -> tuple[list[dict], int]:
    """逐条明细：`(明细表, 失败数量)`。

    **粒度取「检查项」而不是「包」**：编译口这一轮真正跑出来的是检查项（每项一行），
    包是检查项的**对象**。以包为粒度的话，「同一包被 3 项门禁同时点名」会被压成 1 条，
    调用方看不出到底是哪一项拦住的 —— 而修复动作恰恰按项而定。
    点名对象（库/模块）从该项原文里尽力取；取不到就如实写空串（不编）。
    """
    明细: list[dict] = []
    if 检查项表:
        for 项 in 检查项表:
            失败 = 项["结论"] in ("判红", "只报告判红", "未核验")
            命中 = 模块名句式.search(项["原文"])
            明细.append({
                "模块ID或库ID": 命中.group(1) if 命中 else "",
                "检查项": 项["名字"],
                "角色": 项["角色"],
                "退出码": 项["退出码"],
                "耗时秒": 项["耗时秒"],
                "结果": 项["结论"],
                "失败原因": 项["原文"] if 失败 else "",
                "缺乏什么导致无法自动自愈": 归因(项["原文"]) if 失败 else "",
                "能否自动自愈": (项["结论"] == "通过") or (归因(项["原文"]) == 缺乏_无 and 失败),
            })
        return 明细, len([项 for 项 in 明细 if 项["结果"] != "通过"])
    # 一项检查都没解析出来：按结论给单条（未核验时「缺乏什么」= 需人看一次输出，
    # 因为**解析面本身**没给出任何可归因的失败项，不许当 0 失败蒙过去）。
    if 结论 == "未核验":
        return [{
            "模块ID或库ID": "", "检查项": "", "角色": "", "退出码": -1, "耗时秒": 0.0,
            "结果": "未核验", "失败原因": "逐项结论一行都没解析出来（结论不可核验）",
            "缺乏什么导致无法自动自愈": 缺乏_未归因, "能否自动自愈": 假,
        }], 1
    return [], 0


def 归并结论(标准输出: str, 标准错误: str, 退出码: int, 命令: str,
           模块ID清单: list[str], 项目根: str) -> dict:
    """把一次编译口执行归并成**两个能力共用的返回体**（传参形制见模块 docstring）。

    返回键分两组，都必给、都不省略：
      · 华哥形制：`成功数量` / `失败数量` / `逐条明细`（每条含「缺乏什么导致无法自动自愈」）；
      · 承接既有：`五态结论` / `退出码` / `检查项表` / `失败门禁` / `未核验项` / `只报红项` /
        `结论原文` / `定向测试点名` / `命令` / `标准输出` / `标准错误` / `项目根`。
    """
    解析 = 解析输出(标准输出)
    结论 = 解析["结论"]
    明细, 失败数 = 组逐条明细(解析["检查项表"], 模块ID清单, 结论, 标准输出)
    检查项表 = 解析["检查项表"]
    成功数 = len([项 for 项 in 检查项表 if 项["结论"] == "通过"])
    if not 检查项表 and 结论 not in ("未核验",):
        # 有结论却没有逐项：如实降级为未核验（同上 fail-closed 口径）。
        结论 = "未核验"
        明细, 失败数 = 组逐条明细([], 模块ID清单, 结论, 标准输出)
    未核验明细 = [项["失败原因"] for 项 in 明细 if 项["结果"] == "未核验"]
    return {
        # ── 华哥形制 ──
        "成功数量": 成功数,
        "失败数量": 失败数,
        "逐条明细": 明细,
        # ── 承接既有 ──
        "五态结论": 结论,
        "退出码": 退出码,
        "检查项表": 检查项表,
        "检查项数": len(检查项表),
        "失败门禁": [项["失败原因"] for 项 in 明细 if 项["结果"] == "判红"],
        "未核验项": 未核验明细,
        "只报红项": [项["失败原因"] for 项 in 明细 if 项["结果"] == "只报告判红"],
        "缺失项表": [{"检查项": 项["检查项"],
                   "缺乏什么导致无法自动自愈": 项["缺乏什么导致无法自动自愈"]}
                  for 项 in 明细 if 项["结果"] != "通过" and not 项["能否自动自愈"]],
        "结论原文": 解析["结论原文"],
        "定向测试点名": 解析["定向测试点名"],
        "受影响包数": 解析["受影响包数"],
        "命令": 命令,
        "标准输出": 标准输出,
        "标准错误": 标准错误,
        "项目根": 项目根,
    }


