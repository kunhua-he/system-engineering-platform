"""客户端构建自检实现：把平台客户端构建脚本收成 HTTP 能力（债务 #213）。

背景（华哥 2026-09-21 裁决「py 调用的腿全砍了」）：`客户端/构建平台客户端.py`
已实现完整构建编排（源码树 → AST 导入重写 → 制品壳 → 可重复构建校验 → 入库/签名/安装/校验），
但它只有命令行入口，Agent 只能敲 `python3.14 客户端/构建平台客户端.py`
—— 那正是被砍掉的「py 腿」。本模块把它的结论**归并与结构化**（与 `开发编译口自检` 同范式）：

  · **不新建第二套判据**：全部判据仍由构建脚本自身给出（写盘后自校验 / 可重复构建校验 /
    稳定路径校验），本模块只调它、读它的输出、把结论拆成字段。
  · **不改 CLI 判据**：退出码与结论行原文照收，不做二次判红。
  · **假绿防线（两道，都经实测）**：① 输出里找不到「构建完成」行 ⇒ `构建结论=失败`，
    且全部派生字段（制品根/制品摘要/计数/安装结论）**清零**；② 输出里有「构建完成」行
    但进程**退出码非 0** ⇒ `构建结论=失败`（制品确实产出了，故 制品根/制品摘要 如实保留）。
    两道合起来的不变式：**`构建结论=成功` ⟺ 构建完成 且 退出码 0**。

**为什么落在这里而不是 `平台控制面.包仓库`**（2026-09-21 现场重测）：构建本体依赖
`开发工具.项目编译`（`客户端/制品生成与自校验.py` 的 `_生成HTML` / `_生成启动器` /
`_写入并编译Python` / `读取工作区字节指纹`），而实测 `允许依赖表["平台控制面"] =
{公共契约, 支持库, 运行核心}` —— 把构建实现搬进包仓库会产生全仓第 1 条越层违规，补表又
推翻裁决 H-6（`开发文档/方案/客户端构建能力化落地方案_20260917.md` §1.1 的否决理由，
本日重测仍逐条成立）。本模块不 import 开发工具、不 import 支持库实现、不开子进程，只经
唯一能力调用器调 `系统核心支持库.进程管理.执行命令` —— 与 `开发编译口自检` 同一条执行腿，
不新增第二腿。
"""

from __future__ import annotations

import re
from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.基础类型.逻辑类型 import 真, 假

来源 = "自修复工具"
系统根 = Path(__file__).resolve().parents[3]
解释器 = "/opt/homebrew/bin/python3.14"
构建脚本 = "客户端/构建平台客户端.py"

#: 构建完成行：`构建完成：/…/平台客户端-<摘要16>`
构建完成句式 = re.compile(r"^构建完成：(?P<制品根>.+)$")
#: 计数行：`改写导入数：123，重算包摘要：45，制品摘要：<摘要16>`
计数句式 = re.compile(
    r"^改写导入数：(?P<改写导入数>\d+)，重算包摘要：(?P<重算包摘要数>\d+)，"
    r"制品摘要：(?P<制品摘要>\S+)$"
)
#: 写盘后自校验行：`写盘后自校验通过：摘要对表一致（权威口径=目录名=制品摘要.json=…）`
自校验句式 = re.compile(r"^写盘后自校验通过：")
#: 可重复构建校验行：`可重复构建校验通过：正式文件 N 项（…）…`
可重复句式 = re.compile(r"^可重复构建校验通过：")
#: 安装激活行：`已经包仓库安装并激活：/…/平台客户端`
安装句式 = re.compile(r"^已经包仓库安装并激活：(?P<目标>.+)$")
#: 入库结论行：`入库：…`
入库句式 = re.compile(r"^入库：(?P<消息>.+)$")
#: 稳定路径校验行：`稳定路径校验：…`
稳定句式 = re.compile(r"^稳定路径校验：(?P<消息>.+)$")


def _调用支持库(能力id: str, 参数: dict) -> 结果:
    """经唯一能力调用服务调用支持库公开能力；未装配或异常时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源)
    except Exception as 错误:
        return 结果.失败("提供者不可用", f"{能力id} 调用失败: {错误}", 来源=来源)


def _失败(错误码: str, 消息: str) -> 结果:
    return 结果.失败(错误码, 消息, 来源=来源)


def _取文本(值: object, 键表: tuple[str, ...]) -> str:
    """从能力返回值里按候选键名取文本（不同形态键名不一致，逐个试）。"""
    if not isinstance(值, dict):
        return ""
    for 键 in 键表:
        候选 = 值.get(键)
        if isinstance(候选, str):
            return 候选
    return ""


def _取整数(值: object, 键表: tuple[str, ...], 缺省: int) -> int:
    if not isinstance(值, dict):
        return 缺省
    for 键 in 键表:
        候选 = 值.get(键)
        if isinstance(候选, bool):
            continue
        if isinstance(候选, int):
            return 候选
    return 缺省


def _组命令(安装: bool) -> list[str]:
    """拼构建命令行（argv 直启；与脚本自身文档用法逐字一致）。"""
    命令 = [解释器, 构建脚本]
    if 安装:
        命令.append("--安装")
    return 命令


def _解析(输出: str) -> dict:
    """把构建脚本标准输出归并成结构化结论（只读解析，不另立判据）。"""
    结论: dict = {
        "构建完成": 假, "构建结论": "失败", "制品根": "", "制品摘要": "",
        "改写导入数": -1, "重算包摘要数": -1,
        "写盘后自校验通过": 假, "可重复构建校验通过": 假,
        "安装目标": "", "入库消息": "", "稳定路径校验": "",
    }
    for 原始行 in 输出.splitlines():
        行 = 原始行.strip()
        if not 行:
            continue
        命中 = 构建完成句式.match(行)
        if 命中:
            结论["构建完成"] = 真
            结论["制品根"] = 命中.group("制品根").strip()
            continue
        命中 = 计数句式.match(行)
        if 命中:
            结论["改写导入数"] = int(命中.group("改写导入数"))
            结论["重算包摘要数"] = int(命中.group("重算包摘要数"))
            结论["制品摘要"] = 命中.group("制品摘要").strip()
            continue
        if 自校验句式.match(行):
            结论["写盘后自校验通过"] = 真
            continue
        if 可重复句式.match(行):
            结论["可重复构建校验通过"] = 真
            continue
        命中 = 安装句式.match(行)
        if 命中:
            结论["安装目标"] = 命中.group("目标").strip()
            continue
        命中 = 入库句式.match(行)
        if 命中:
            结论["入库消息"] = 命中.group("消息").strip()
            continue
        命中 = 稳定句式.match(行)
        if 命中:
            结论["稳定路径校验"] = 命中.group("消息").strip()
            continue
    return 结论


#: 构建未完成时必须清零的派生字段。理由（2026-09-21 反向验证实测）：计数行
#: `改写导入数：…，制品摘要：…` 与「构建完成：」是**两行独立解析**的，若只丢后者，
#: 失败构建的 `制品摘要` 仍会被读走 —— 调用方拿一个未完成构建的摘要去入库/比对，
#: 就是最坏那类假绿。清零后不变式为「制品摘要非空 ⟺ 构建完成」。
_派生字段 = ("制品根", "制品摘要", "改写导入数", "重算包摘要数",
           "安装目标", "入库消息", "稳定路径校验")


def _归并(输出: str, 退出码: int) -> dict:
    """解析 + fail-closed 收口：构建未完成 ⇒ 派生字段清零；退出码非 0 ⇒ 结论必为失败。

    **为什么结论必须同时看退出码（2026-09-21 端到端实测抓到的假绿）**：脚本在 `构建()`
    里**先**打印 `构建完成：<制品根>`、**之后**才调 `安装到环境`。于是 `安装=真` 且
    入库/安装失败时，输出里既有「构建完成」行、进程退出码又是 1 —— 只认输出行的判据
    会报「成功」，而实际制品没入库、环境没换。判据改成 **`构建完成` 且 `退出码 == 0`**
    才算成功，两处证据缺一不可（实测样本：构建成功 + 入库报「发布者公钥与既有信任记录
    不一致」+ 退出码 1）。

    清零只按「构建完成」判定：`构建完成=真` 但 `退出码!=0` 时，`制品根`/`制品摘要`
    是**真**的（制品确实产出了），照实保留，只让 `构建结论` 说失败。
    """
    结论 = _解析(输出)
    if not 结论["构建完成"]:
        for 键 in _派生字段:
            结论[键] = "" if isinstance(结论[键], str) else -1
        结论["写盘后自校验通过"] = 假
        结论["可重复构建校验通过"] = 假
    结论["构建结论"] = "成功" if (结论["构建完成"] and 退出码 == 0) else "失败"
    return 结论


def 构建平台客户端制品(安装: bool = 假, 超时秒: float = 1800.0) -> 结果:
    """跑平台客户端构建脚本并回结构化结论（#213：构建链的 HTTP 腿）。

    入参：安装=真 时构建后继续走 入库→签名→安装→激活稳定指针（等价 CLI `--安装`）；
    假 只产出制品目录与制品摘要（仍会改写制品根 `当前.json`，非纯只读）。
    执行腿是唯一能力调用器 → `系统核心支持库.进程管理.执行命令`（argv 直启，不经 shell）。
    返回：构建结论 / 构建完成 / 制品根 / 制品摘要 / 改写导入数 / 重算包摘要数 /
    写盘后自校验通过 / 可重复构建校验通过 / 安装目标 / 入库消息 / 稳定路径校验 /
    退出码 / 命令 / 标准输出 / 标准错误 / 项目根。

    **判成败只看 `构建结论`**（判据 = `构建完成` 且 `退出码 == 0`）：`安装=假` 时构建脚本
    不跑 `校验制品可重复`（它在 `安装到环境` 内），故 `可重复构建校验通过`、`安装目标`、
    `入库消息`、`稳定路径校验` 恒为假/空 —— 那是「该步未跑」，不是「该步失败」。
    `构建完成=真` 而 `构建结论=失败` 则表示**制品构建成功、后续步骤（入库/安装/校验）失败**，
    失败原因读 `标准错误`。
    """
    命令 = _组命令(bool(安装))
    调用 = _调用支持库("系统核心支持库.进程管理.执行命令", {
        "命令": " ".join(命令),
        "工作目录": str(系统根),
        "超时秒": float(超时秒),
    })
    if not 调用.成功:
        return _失败(调用.错误码 or "提供者不可用",
                     f"执行命令 调用失败（构建未起）: {调用.错误说明}")
    值 = 调用.值 if isinstance(调用.值, dict) else {}
    退出码 = _取整数(值, ("退出码", "返回码"), -1)
    标准输出 = _取文本(值, ("标准输出", "输出", "stdout"))
    标准错误 = _取文本(值, ("标准错误", "错误输出", "stderr"))
    解析 = _归并(标准输出, 退出码)
    return 结果.成功结果({
        **解析,
        "退出码": 退出码,
        "命令": " ".join(命令),
        "标准输出": 标准输出,
        "标准错误": 标准错误,
        "项目根": str(系统根),
    })
