"""自修复开发工具模块：Git worktree + 精确补丁 + 定向验证 + 可回滚提交。

组合 Git 支持库、文件系统（补丁/临时资源）、资源管理（摘要）与本地
进程适配器（受管验证命令），只经支持库公开入口调用。
"""

from __future__ import annotations

from 模块库.自修复工具.实现.自修复工具 import 创建修复工作区, 回滚修复, 验证修复

__all__ = ["创建修复工作区", "验证修复", "回滚修复"]


def 注册能力(注册表) -> None:
    """向能力注册表注册本模块公开能力（分组 自修复工具）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("自修复工具.创建修复工作区", 创建修复工作区,
         ["仓库路径", "补丁列表", "验证命令", "提交消息", "期望摘要", "检查文件", "分支名", "超时秒"],
         "Git worktree + 精确补丁 + 定向验证 + 可回滚提交组合流程"),
        ("自修复工具.验证修复", 验证修复,
         ["仓库路径", "验证命令", "期望摘要", "检查文件", "超时秒"],
         "运行验证命令并检查内容摘要"),
        ("自修复工具.回滚修复", 回滚修复,
         ["仓库路径", "提交哈希", "操作", "超时秒"],
         "git revert/cherry-pick 组合撤销或挑拣修复"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.自修复工具",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明=说明,
            )
        )
