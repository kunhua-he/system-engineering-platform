"""自修复开发工具模块：Git worktree + 精确补丁 + 定向验证 + 可回滚提交。

只经 获取能力调用器().调用能力 组合 Git 支持库、文件系统（补丁/临时
资源）、资源管理（摘要/唯一运行目录）与本地进程（受管验证命令），
模块不物理导入支持库/提供者实现。
"""

from __future__ import annotations

import json
from pathlib import Path

from 模块库.自修复工具.实现.自修复工具 import (
    创建修复工作区, 获取当前提交哈希, 回滚修复, 验证修复)

__all__ = ["创建修复工作区", "验证修复", "回滚修复", "获取当前提交哈希"]


def 注册能力(注册表) -> None:
    """向能力注册表注册本模块公开能力（分组 自修复工具）。"""
    from 公共契约.能力契约.契约 import 能力实现

    契约 = json.loads((Path(__file__).parent / "能力契约" / "参数契约.json").read_text(encoding="utf-8"))
    类型表 = {
        条目["能力id"]: {参数["名称"]: 参数.get("类型", "") for 参数 in 条目.get("参数", [])}
        for 条目 in 契约.get("能力契约", [])
    }

    for 能力id, 函数, 参数名, 说明 in [
        ("自修复工具.创建修复工作区", 创建修复工作区,
         ["仓库路径", "补丁列表", "验证命令", "提交消息", "期望摘要", "检查文件", "分支名", "超时秒"],
         "Git worktree + 精确补丁 + 定向验证 + 可回滚提交组合流程"),
        ("自修复工具.验证修复", 验证修复,
         ["仓库路径", "验证命令", "期望摘要", "检查文件", "超时秒"],
         "运行验证命令并检查内容摘要"),
        ("自修复工具.回滚修复", 回滚修复,
         ["仓库路径", "提交哈希", "操作", "超时秒"],
         "git revert/cherry-pick 组合撤销或挑拣修复"),
        ("自修复工具.获取当前提交哈希", 获取当前提交哈希,
         ["仓库路径", "超时秒"],
         "获取仓库当前提交哈希与分支"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.自修复工具",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": 类型表[能力id][名称]} for 名称 in 参数名],
                返回="结果型",
                说明=说明,
            )
        )
