"""简单窗口模块：只组合前端窗口描述支持库，不做真实浏览器渲染。"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果
from 支持库.前端.窗口描述 import (
    校验窗口定义 as _校验窗口定义,
    创建窗口定义 as _创建窗口定义,
)
from 支持库.前端.状态描述 import (
    创建窗口状态 as _创建窗口状态,
    状态流转校验 as _状态流转校验,
)

_窗口表: dict[str, dict] = {}
_状态表: dict[str, dict] = {}


def _获取状态(窗口id: str) -> 结果:
    状态 = _状态表.get(窗口id)
    if 状态 is None:
        return 结果.失败("窗口不存在", f"窗口 {窗口id} 不存在", 来源="简单窗口")
    return 结果.成功结果(状态)


def 创建窗口(窗口id: str, 标题: str, 宽度: int, 高度: int) -> 结果:
    定义结果 = _创建窗口定义(窗口id, 标题, 宽度, 高度)
    if not 定义结果.成功:
        return 定义结果
    校验结果 = _校验窗口定义(定义结果.值)
    if not 校验结果.成功:
        return 校验结果
    _窗口表[窗口id] = 定义结果.值
    _状态表[窗口id] = _创建窗口状态(窗口id).值
    return 结果.成功结果(定义结果.值)


def 打开窗口(窗口id: str) -> 结果:
    状态结果 = _获取状态(窗口id)
    if not 状态结果.成功:
        return 状态结果
    校验结果 = _状态流转校验(状态结果.值["状态"], "打开")
    if not 校验结果.成功:
        return 校验结果
    状态结果.值["状态"] = "打开"
    return 结果.成功结果(状态结果.值)


def 关闭窗口(窗口id: str) -> 结果:
    状态结果 = _获取状态(窗口id)
    if not 状态结果.成功:
        return 状态结果
    校验结果 = _状态流转校验(状态结果.值["状态"], "关闭")
    if not 校验结果.成功:
        return 校验结果
    状态结果.值["状态"] = "关闭"
    return 结果.成功结果(状态结果.值)


def 传递参数(窗口id: str, 参数: dict) -> 结果:
    状态结果 = _获取状态(窗口id)
    if not 状态结果.成功:
        return 状态结果
    状态结果.值["参数"] = dict(参数 or {})
    return 结果.成功结果(状态结果.值)


def 获取窗口描述(窗口id: str) -> 结果:
    窗口 = _窗口表.get(窗口id)
    if 窗口 is None:
        return 结果.失败("窗口不存在", f"窗口 {窗口id} 不存在", 来源="简单窗口")
    状态结果 = _获取状态(窗口id)
    描述 = dict(窗口)
    描述["状态"] = 状态结果.值["状态"] if 状态结果.成功 else "未知"
    描述["参数"] = 状态结果.值.get("参数") if 状态结果.成功 else None
    return 结果.成功结果(描述)
