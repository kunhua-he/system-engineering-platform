"""简单窗口基础模块：经能力调用器组合 窗口描述/状态描述 支持库能力。

调用边界：模块只持能力 id 与契约版本，经
公共契约.能力契约.调用器.获取能力调用器().调用能力 调用支持库能力；
禁止直接导入 支持库/提供者 实现。模块只做参数装配与结果组合，
对外中文能力语义不变（创建/打开/关闭窗口、传递参数、获取窗口描述）。
"""

from __future__ import annotations

import threading

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.能力契约.调用器 import 获取能力调用器

_窗口表: dict[str, dict] = {}
_状态表: dict[str, dict] = {}
_锁 = threading.Lock()


def _调用支持库能力(能力id: str, 参数: dict) -> 结果:
    """经唯一能力调用服务按能力 id 调用支持库能力（运行核心注入）。"""
    return 获取能力调用器().调用能力(能力id, 参数)


def _获取状态(窗口id: str) -> 结果:
    状态 = _状态表.get(窗口id)
    if 状态 is None:
        return 结果.失败("窗口不存在", f"窗口 {窗口id} 不存在", 来源="简单窗口")
    return 结果.成功结果(状态)


def 创建窗口(窗口id: str, 标题: str, 宽度: int, 高度: int) -> 结果:
    with _锁:
        定义结果 = _调用支持库能力(
            "窗口描述.创建窗口定义",
            {"窗口id": 窗口id, "标题": 标题, "宽度": 宽度, "高度": 高度},
        )
        if not 定义结果.成功:
            return 定义结果
        校验结果 = _调用支持库能力(
            "窗口描述.校验窗口定义", {"窗口定义": 定义结果.值}
        )
        if not 校验结果.成功:
            return 校验结果
        状态结果 = _调用支持库能力(
            "状态描述.创建窗口状态", {"窗口id": 窗口id, "初始状态": "关闭"}
        )
        if not 状态结果.成功:
            return 状态结果
        _窗口表[窗口id] = 定义结果.值
        _状态表[窗口id] = 状态结果.值
        return 结果.成功结果(定义结果.值)


def 打开窗口(窗口id: str) -> 结果:
    with _锁:
        状态结果 = _获取状态(窗口id)
        if not 状态结果.成功:
            return 状态结果
        校验结果 = _调用支持库能力(
            "状态描述.状态流转校验",
            {"当前状态": 状态结果.值["状态"], "目标状态": "打开"},
        )
        if not 校验结果.成功:
            return 校验结果
        状态结果.值["状态"] = "打开"
        return 结果.成功结果(状态结果.值)


def 关闭窗口(窗口id: str) -> 结果:
    with _锁:
        状态结果 = _获取状态(窗口id)
        if not 状态结果.成功:
            return 状态结果
        校验结果 = _调用支持库能力(
            "状态描述.状态流转校验",
            {"当前状态": 状态结果.值["状态"], "目标状态": "关闭"},
        )
        if not 校验结果.成功:
            return 校验结果
        状态结果.值["状态"] = "关闭"
        return 结果.成功结果(状态结果.值)


def 传递参数(窗口id: str, 参数: dict) -> 结果:
    with _锁:
        状态结果 = _获取状态(窗口id)
        if not 状态结果.成功:
            return 状态结果
        状态结果.值["参数"] = dict(参数 or {})
        return 结果.成功结果(状态结果.值)


def 获取窗口描述(窗口id: str) -> 结果:
    with _锁:
        窗口 = _窗口表.get(窗口id)
        if 窗口 is None:
            return 结果.失败("窗口不存在", f"窗口 {窗口id} 不存在", 来源="简单窗口")
        状态结果 = _获取状态(窗口id)
        描述 = dict(窗口)
        描述["状态"] = 状态结果.值["状态"] if 状态结果.成功 else "未知"
        描述["参数"] = 状态结果.值.get("参数") if 状态结果.成功 else None
        return 结果.成功结果(描述)
