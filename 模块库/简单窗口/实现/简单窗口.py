"""简单窗口模块：组合窗口能力，业务状态由网关受管句柄维护。"""
from __future__ import annotations

import uuid
from typing import Any

from 公共契约.基础类型.结果类型 import 结果

_连接器 = None
来源 = "简单窗口"


def 设置HTTP连接器(连接器) -> None:
    global _连接器
    _连接器 = 连接器


def _失败(错误码: str, 说明: str) -> 结果:
    return 结果.失败(错误码, 说明, 来源=来源)


def _转结果(响应: Any, 默认错误码: str = "提供者不可用") -> 结果:
    if isinstance(响应, 结果):
        return 响应
    if not isinstance(响应, dict):
        return _失败("返回结果不符合契约", "连接器返回不是对象")
    if 响应.get("成功") is True:
        return 结果.成功结果(响应.get("值"))
    return _失败(
        str(响应.get("错误码") or 默认错误码),
        str(响应.get("错误说明") or "网关调用失败"),
    )


def _调用支持库(能力id: str, 参数: dict) -> 结果:
    if _连接器 is None:
        return _失败("提供者不可用", "连接器未装配")
    try:
        return _转结果(_连接器.调用能力(能力id, 参数))
    except Exception as 错误:
        return _失败("提供者不可用", f"{能力id} 调用失败: {错误}")


def _读取状态(句柄: int) -> 结果:
    读取 = _调用支持库(
        "系统核心支持库.资源管理.读取受管状态", {"句柄": 句柄})
    if not 读取.成功 or not isinstance(读取.值, dict):
        return 读取 if not 读取.成功 else _失败("返回结果不符合契约", "受管状态读取值不是对象")
    业务状态 = 读取.值.get("状态")
    if not isinstance(业务状态, dict):
        return _失败("返回结果不符合契约", "句柄未绑定窗口状态")
    return 结果.成功结果({"信封": 读取.值, "业务状态": 业务状态})


def _更新状态(句柄: int, 信封: dict, 新状态: dict) -> 结果:
    return _调用支持库(
        "系统核心支持库.资源管理.更新受管状态",
        {"句柄": 句柄, "新状态": 新状态, "期望版本": str(信封.get("版本", ""))})


def 创建窗口(窗口id: str, 标题: str, 宽度: int, 高度: int) -> 结果:
    定义 = _调用支持库(
        "窗口描述.创建窗口定义",
        {"窗口id": 窗口id, "标题": 标题, "宽度": 宽度, "高度": 高度},
    )
    if not 定义.成功:
        return 定义
    校验 = _调用支持库("窗口描述.校验窗口定义", {"窗口定义": 定义.值})
    if not 校验.成功:
        return 校验
    状态 = _调用支持库(
        "状态描述.创建窗口状态", {"窗口id": 窗口id, "初始状态": "关闭"})
    if not 状态.成功 or not isinstance(状态.值, dict):
        return 状态 if not 状态.成功 else _失败("返回结果不符合契约", "窗口状态不是对象")
    初始状态 = {"窗口": 定义.值, "状态": 状态.值.get("状态", "关闭"), "参数": {}}
    创建 = _调用支持库(
        "系统核心支持库.资源管理.创建受管状态",
        {"资源id": f"简单窗口:{窗口id}:{uuid.uuid4().hex}", "初始状态": 初始状态})
    if not 创建.成功 or not isinstance(创建.值, dict):
        return 创建 if not 创建.成功 else _失败("返回结果不符合契约", "创建受管状态未返回信封")
    return 结果.成功结果({
        **dict(定义.值), "句柄": 创建.值.get("句柄"),
        "状态": 初始状态["状态"], "参数": {}, "版本": 创建.值.get("版本"),
    })


def _流转窗口(句柄: int, 目标状态: str) -> 结果:
    当前 = _读取状态(句柄)
    if not 当前.成功:
        return 当前
    信封, 业务 = 当前.值["信封"], dict(当前.值["业务状态"])
    校验 = _调用支持库(
        "状态描述.状态流转校验", {"当前状态": 业务["状态"], "目标状态": 目标状态})
    if not 校验.成功:
        return 校验
    业务["状态"] = 目标状态
    更新 = _更新状态(句柄, 信封, 业务)
    return 结果.成功结果(业务) if 更新.成功 else 更新


def 打开窗口(句柄: int) -> 结果:
    return _流转窗口(句柄, "打开")


def 关闭窗口(句柄: int) -> 结果:
    return _流转窗口(句柄, "关闭")


def 传递参数(句柄: int, 参数: dict) -> 结果:
    当前 = _读取状态(句柄)
    if not 当前.成功:
        return 当前
    信封, 业务 = 当前.值["信封"], dict(当前.值["业务状态"])
    业务["参数"] = dict(参数 or {})
    更新 = _更新状态(句柄, 信封, 业务)
    return 结果.成功结果(业务) if 更新.成功 else 更新


def 获取窗口描述(句柄: int) -> 结果:
    当前 = _读取状态(句柄)
    if not 当前.成功:
        return 当前
    业务 = 当前.值["业务状态"]
    窗口 = 业务.get("窗口")
    if not isinstance(窗口, dict):
        return _失败("返回结果不符合契约", "受管状态缺少窗口定义")
    return 结果.成功结果({**窗口, "状态": 业务.get("状态"), "参数": 业务.get("参数", {})})


def 释放窗口(句柄: int) -> 结果:
    释放 = _调用支持库(
        "系统核心支持库.资源管理.释放受管状态", {"句柄": 句柄})
    return 结果.成功结果({"句柄": 句柄, "状态": "已释放"}) if 释放.成功 else 释放
