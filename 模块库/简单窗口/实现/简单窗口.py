"""简单窗口基础模块：只持能力 id 与契约版本，经 HTTP连接器调用统一网关。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
连接器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。
"""

from __future__ import annotations

import threading

from 公共契约.基础类型.结果类型 import 结果


_连接器 = None
_窗口表: dict[str, dict] = {}
_状态表: dict[str, dict] = {}
_锁 = threading.Lock()


def 设置HTTP连接器(连接器) -> None:
    """由项目适配层装配连接器；主要用于启动装配与隔离测试。"""
    global _连接器
    _连接器 = 连接器


def _获取连接器():
    return _连接器


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经 HTTP 连接器按能力 id 调用统一网关；失败统一转为 结果。"""
    try:
        连接器 = _获取连接器()
        if 连接器 is None:
            return 结果.失败(失败错误码, "HTTP 连接器未装配", 来源="简单窗口")
        响应 = 连接器.调用能力(能力id, 参数)
        if isinstance(响应, 结果):
            return 响应
        if not isinstance(响应, dict):
            return 结果.失败("返回结果不符合契约", "网关返回不是对象", 来源="简单窗口")
        if 响应.get("成功"):
            return 结果.成功结果(响应.get("值"))
        return 结果.失败(响应.get("错误码") or 失败错误码, 响应.get("错误说明") or "网关调用失败", 来源="简单窗口")
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源="简单窗口")
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源="简单窗口")


def _获取状态(窗口id: str) -> 结果:
    状态 = _状态表.get(窗口id)
    if 状态 is None:
        return 结果.失败("窗口不存在", f"窗口 {窗口id} 不存在", 来源="简单窗口")
    return 结果.成功结果(状态)


def 创建窗口(窗口id: str, 标题: str, 宽度: int, 高度: int) -> 结果:
    with _锁:
        定义结果 = _调用支持库(
            "窗口描述.创建窗口定义",
            {"窗口id": 窗口id, "标题": 标题, "宽度": 宽度, "高度": 高度},
        )
        if not 定义结果.成功:
            return 定义结果
        校验结果 = _调用支持库(
            "窗口描述.校验窗口定义", {"窗口定义": 定义结果.值}
        )
        if not 校验结果.成功:
            return 校验结果
        状态结果 = _调用支持库(
            "状态描述.创建窗口状态", {"窗口id": 窗口id, "初始状态": "关闭"}
        )
        if not 状态结果.成功:
            return 状态结果
        _窗口表[窗口id] = 定义结果.值
        _状态表[窗口id] = 状态结果.值
        return 结果.成功结果(定义结果.值)


def 打开窗口(窗口id: str) -> 结果:
    with _锁:
        状态结果 = _获取状态(窗口id)
        if not 状态结果.成功:
            return 状态结果
        校验结果 = _调用支持库(
            "状态描述.状态流转校验",
            {"当前状态": 状态结果.值["状态"], "目标状态": "打开"},
        )
        if not 校验结果.成功:
            return 校验结果
        状态结果.值["状态"] = "打开"
        return 结果.成功结果(状态结果.值)


def 关闭窗口(窗口id: str) -> 结果:
    with _锁:
        状态结果 = _获取状态(窗口id)
        if not 状态结果.成功:
            return 状态结果
        校验结果 = _调用支持库(
            "状态描述.状态流转校验",
            {"当前状态": 状态结果.值["状态"], "目标状态": "关闭"},
        )
        if not 校验结果.成功:
            return 校验结果
        状态结果.值["状态"] = "关闭"
        return 结果.成功结果(状态结果.值)


def 传递参数(窗口id: str, 参数: dict) -> 结果:
    with _锁:
        状态结果 = _获取状态(窗口id)
        if not 状态结果.成功:
            return 状态结果
        状态结果.值["参数"] = dict(参数 or {})
        return 结果.成功结果(状态结果.值)


def 获取窗口描述(窗口id: str) -> 结果:
    with _锁:
        窗口 = _窗口表.get(窗口id)
        if 窗口 is None:
            return 结果.失败("窗口不存在", f"窗口 {窗口id} 不存在", 来源="简单窗口")
        状态结果 = _获取状态(窗口id)
        描述 = dict(窗口)
        描述["状态"] = 状态结果.值["状态"] if 状态结果.成功 else "未知"
        描述["参数"] = 状态结果.值.get("参数") if 状态结果.成功 else None
        return 结果.成功结果(描述)
