def 注册能力(注册表) -> None:
    """由模块加载器调用。参数类型按能力契约声明注册。"""
    from 公共契约.能力契约.契约 import 能力实现

    契约 = json.loads((Path(__file__).parent / "能力契约" / "参数契约.json").read_text(encoding="utf-8"))
    # 参数契约表：能力id → 契约里的**整条参数声明**（名称/类型/必填/默认值/说明）。
    # 缺陷溯源（2026-09-18）：本入口原先手工列举 (参数名, 类型) 二元组，`必填` 字段根本
    # 就不存在；网关唯一校验点 `运行核心/统一网关/类型规格.py` 的判据是
    # `项.get("必填") is 真` → `None is 真` = 假 → 必填校验静默失效：少传参数不再被拦在
    # 网关，直接落进实现体抛 TypeError，用户拿到 HTTP 500 而不是干净的 400。
    # 契约是本包参数的唯一事实源（哲学 12.1）：入口只透传，不另立第二套事实。
    参数契约表 = {
        条目["能力id"]: [dict(参数) for 参数 in 条目.get("参数", [])]
        for 条目 in 契约.get("能力契约", [])
    }

    def _参数声明(能力id: str, 参数名: list[str]) -> list[dict]:
        """按契约整条透传参数声明；注册名序与契约名序不一致即失败（不静默漏参）。"""
        契约参数 = 参数契约表.get(能力id)
        if 契约参数 is None:
            raise ValueError(f"能力 {能力id} 不在 能力契约/参数契约.json 的能力契约里")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(参数名):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(参数名)} 与契约参数名序 {契约名序} 不一致："
                "参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），入口不得另立一份")
        return 契约参数

    for 能力id, 函数, 参数名 in [
        ("简单窗口.创建窗口", 创建窗口, ["窗口id", "标题", "宽度", "高度"]),
        ("简单窗口.打开窗口", 打开窗口, ["句柄"]),
        ("简单窗口.关闭窗口", 关闭窗口, ["句柄"]),
        ("简单窗口.传递参数", 传递参数, ["句柄", "参数"]),
        ("简单窗口.获取窗口描述", 获取窗口描述, ["句柄"]),
        ("简单窗口.释放窗口", 释放窗口, ["句柄"]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.简单窗口",
                实现函数=函数,
                参数=_参数声明(能力id, 参数名),
                返回="结果型",
                说明=f"{能力id}",
            )
        )
