"""简单窗口基础模块包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：创建窗口/打开窗口/关闭窗口/传递参数/获取窗口描述，
全部经 HTTP 网关组合 窗口描述/状态描述 支持库能力。
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 模块库.简单窗口.实现.简单窗口 import 创建窗口
from 模块库.简单窗口.实现.简单窗口 import 打开窗口
from 模块库.简单窗口.实现.简单窗口 import 关闭窗口
from 模块库.简单窗口.实现.简单窗口 import 传递参数
from 模块库.简单窗口.实现.简单窗口 import 获取窗口描述
from 模块库.简单窗口.实现.简单窗口 import 释放窗口

__all__ = [
    '创建窗口',
    '打开窗口',
    '关闭窗口',
    '传递参数',
    '获取窗口描述',
    '释放窗口',
]


def 注册能力(注册表) -> None:
    """由模块加载器调用。注册参数与 能力契约/参数契约.json 逐条对应。"""
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 参数契约镜像（**函数内字面量**；本块由「丢参」缺陷修复注入，勿删）
    #
    # 缺陷溯源（2026-09-18）：本入口原先手工重建注册参数声明（只有 名称/类型），把
    # `必填` 丢掉；而网关唯一校验点 `运行核心/统一网关/协议/类型规格.py` 的判据是
    # `项.get("必填") is 真` → `None is 真` = 假 → 必填校验静默失效：少传参数不再被
    # 网关拦下，直接落进实现体抛 TypeError，用户拿到 HTTP 500 而不是干净的 400
    # 「缺少必填参数 X」。修法：参数声明从 `能力契约/参数契约.json` **整条透传**
    # （`参数=_参数契约表[能力id]`），入口不再另立第二套事实源（哲学 12.1）。
    #
    # 2026-09-18 第二轮（参数口径未解析 107 条里的最后一处本包形态）：本包原实现是
    # `_参数声明(能力id, 参数名)` **在函数内推导**参数表——推导过程对 AST 静态读取器
    # 不可判定，`读取注册口径` 抽不出参数项，包×能力全落「参数口径未解析」。改法是把
    # 契约逐条**镜像成 `注册能力` 函数体内的字面量赋值**，`参数=_参数契约表[能力id]`
    # 按下标取（不包一层函数：包一层 AST 一律判「不可静态判定」，等于拿门禁覆盖率换干净）。
    #
    # 为什么是**函数内字面量**：`开发工具/契约编译/漂移检测` 的 AST 读取器
    # （`_静态字面量` 的 `ast.Subscript` 分支）只收 `注册能力` 函数体内的赋值
    # （`_扫描注册语句`）——放模块顶层或包成函数都读不到，`必填`/`默认值` 就重新变瞎。
    # 「裸布尔」防回潮门禁**已把 `必填`/`默认值` 计入违规**（本文件已迁为 真/假），改回裸 True/False 即判红。
    # 表内布尔位写**中文 `真`／`假`**（正式口径，真源 `公共契约/基础类型/逻辑类型.py`）；
    # 本文件顶部已 import 真/假，漂移检测读取器（`_导入常量绑定`）能静态解析出参数表，
    # 键集与契约逐字对应（契约写了的键才留，没写的不补），不给漂移检测造出
    # 「注册声明了契约没声明的默认值」。契约名序/返回口径核验由装配期唯一闸门承担
    # （`运行核心/加载器/生命周期管理/管理器.装配系统` → 内核 `能力注册表.校验声明一致`），本入口不再另立第二份。
    _参数契约表 = {
        "简单窗口.创建窗口": [
            {"名称": "窗口id", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "标题", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "宽度", "类型": "整数型", "必填": 真, "默认值": None},
            {"名称": "高度", "类型": "整数型", "必填": 真, "默认值": None},
        ],
        "简单窗口.打开窗口": [
            {"名称": "句柄", "类型": "整数型", "必填": 真, "默认值": None},
        ],
        "简单窗口.关闭窗口": [
            {"名称": "句柄", "类型": "整数型", "必填": 真, "默认值": None},
        ],
        "简单窗口.传递参数": [
            {"名称": "句柄", "类型": "整数型", "必填": 真, "默认值": None},
            {"名称": "参数", "类型": "字典型", "必填": 真, "默认值": None},
        ],
        "简单窗口.获取窗口描述": [
            {"名称": "句柄", "类型": "整数型", "必填": 真, "默认值": None},
        ],
        "简单窗口.释放窗口": [
            {"名称": "句柄", "类型": "整数型", "必填": 真, "默认值": None},
        ],
    }
# ===== 参数声明透传 结束 =====
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数 in [
        ("简单窗口.创建窗口", 创建窗口),
        ("简单窗口.打开窗口", 打开窗口),
        ("简单窗口.关闭窗口", 关闭窗口),
        ("简单窗口.传递参数", 传递参数),
        ("简单窗口.获取窗口描述", 获取窗口描述),
        ("简单窗口.释放窗口", 释放窗口),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.简单窗口",
                实现函数=函数,
                参数=_参数契约表[能力id],
                返回="结果型",
                说明=f"{能力id}",
            )
        )
