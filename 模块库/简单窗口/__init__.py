"""简单窗口基础模块包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：创建窗口/打开窗口/关闭窗口/传递参数/获取窗口描述，
全部经 HTTP 网关组合 窗口描述/状态描述 支持库能力。
"""

from __future__ import annotations

from 模块库.简单窗口.实现.简单窗口 import 创建窗口
from 模块库.简单窗口.实现.简单窗口 import 打开窗口
from 模块库.简单窗口.实现.简单窗口 import 关闭窗口
from 模块库.简单窗口.实现.简单窗口 import 传递参数
from 模块库.简单窗口.实现.简单窗口 import 获取窗口描述
from 模块库.简单窗口.实现.简单窗口 import 设置HTTP连接器

__all__ = [
    "创建窗口",
    "打开窗口",
    "关闭窗口",
    "传递参数",
    "获取窗口描述",
    "设置HTTP连接器",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数类型表 in [
        (
            "简单窗口.创建窗口",
            创建窗口,
            [("窗口id", "文本"), ("标题", "文本"), ("宽度", "整数"), ("高度", "整数")],
        ),
        ("简单窗口.打开窗口", 打开窗口, [("窗口id", "文本")]),
        ("简单窗口.关闭窗口", 关闭窗口, [("窗口id", "文本")]),
        ("简单窗口.传递参数", 传递参数, [("窗口id", "文本"), ("参数", "字典")]),
        ("简单窗口.获取窗口描述", 获取窗口描述, [("窗口id", "文本")]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.简单窗口",
                实现函数=函数,
                参数=[
                    {"名称": 参数名, "类型": 类型}
                    for 参数名, 类型 in 参数类型表
                ],
                返回="结果型",
                说明=f"{能力id}",
            )
        )
