"""简单窗口模块包级中文入口。"""

from __future__ import annotations

from 模块库.简单窗口.实现.简单窗口 import 创建窗口
from 模块库.简单窗口.实现.简单窗口 import 打开窗口
from 模块库.简单窗口.实现.简单窗口 import 关闭窗口
from 模块库.简单窗口.实现.简单窗口 import 传递参数
from 模块库.简单窗口.实现.简单窗口 import 获取窗口描述

__all__ = [
    "创建窗口",
    "打开窗口",
    "关闭窗口",
    "传递参数",
    "获取窗口描述",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型 in [
        ("简单窗口.创建窗口", 创建窗口, ['窗口id', '标题', '宽度', '高度'], "结果"),
        ("简单窗口.打开窗口", 打开窗口, ['窗口id'], "结果"),
        ("简单窗口.关闭窗口", 关闭窗口, ['窗口id'], "结果"),
        ("简单窗口.传递参数", 传递参数, ['窗口id', '参数'], "结果"),
        ("简单窗口.获取窗口描述", 获取窗口描述, ['窗口id'], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.简单窗口",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回=返回类型,
                说明="模块组合能力",
            )
        )
