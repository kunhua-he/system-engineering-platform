"""测试资源 模块（功能模块）：只经 获取能力调用器().调用能力 组合支持库能力。

职责（与原 MCP 工具 test_resource 的真实职责一一对齐，只两条）：
- 申请资源：把一条测试临时资源（文件/目录/子进程/端口/线程/句柄）登记到底座临时资源注册表，
  并追加写进本次开工的清单（JSONL）；
- 回收资源：按清单回收未标记「保留」的资源——文件/目录走安全释放，子进程走进程句柄终止与释放；
  单项失败不抛异常，收集成失败表并保留结构化证据。

安全边界（保留原实现 S2/M2 口径，且不新增第二条腿）：
- 临时根必须位于某个 工程缓存/ 之下，且不能是 工程缓存 自身
  （经 文件系统支持库.文件操作.查找祖先目录 判定，判定链是能力不是本模块自算）；
- 文件/目录 资源必须落在临时根内（经 系统核心支持库.路径安全.校验路径 判定，含符号链接逃逸）；
- 子进程只接受「底座受管进程句柄」（系统核心支持库.进程管理.启动进程 返回），
  不再登记任意第三方 pid，也不再自行 ps/lsof/killpg：本模块内 0 subprocess、0 os.kill，
  「登记即校验、回收即终止」全部经统一调用腿（哲学第 7 条 4 项 统一调用接口铁律）。
"""

from __future__ import annotations

import json
import os
from typing import Any

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.基础类型.逻辑类型 import 真, 假

来源 = "测试资源"

_资源类型集合 = {"文件", "目录", "子进程", "端口", "线程", "句柄"}
_资源类型别名 = {"临时验证脚本": "文件"}
_工程缓存名 = "工程缓存"
# 这三类的回收在底座 538 个能力里无承载，只能如实报「待补能力」，不静默
# （缺什么补什么：清单见 说明/待补能力清单.md）。
_待补回收类型 = {"端口", "线程", "句柄"}


class _单项失败(Exception):
    """单项回收失败：携带真实原因，由 回收资源 收集进失败表。"""


def _调用(能力id: str, 请求参数: dict) -> 结果:
    """经唯一能力调用服务调用支持库能力；未装配时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 请求参数, 调用方="测试资源")
    except RuntimeError as 错误:
        return 结果.失败("提供者不可用", str(错误), 来源="测试资源")


def _文本(值: Any) -> str:
    """归一为非空文本（None/空值一律给了空串）。"""
    return str(值 if 值 is not None else "").strip()


def _规范资源类型(资源类型: Any) -> str:
    """统一资源类型；仅兼容已知历史别名，未知类型返回空串由调用方拒绝。"""
    文本 = _文本(资源类型)
    文本 = _资源类型别名.get(文本, 文本)
    return 文本 if 文本 in _资源类型集合 else ""


def _句柄值(值: Any) -> int | None:
    """归一进程句柄为 1 起的正整数；非法返回 None。"""
    if 值 is None or isinstance(值, bool):
        return None
    try:
        数值 = int(值)
    except (TypeError, ValueError):
        return None
    return 数值 if 数值 > 0 else None


def _冒号后(名称: str) -> str:
    """取「前缀:值」形式名称中冒号后的值。"""
    return 名称.rsplit(":", 1)[-1] if ":" in 名称 else 名称


def _二元(值: Any) -> tuple[bool, str]:
    """把「(成功标志, 消息) 二元组」归一为二元组；其它形状按成功标志解释。"""
    if isinstance(值, (tuple, list)) and len(值) >= 2:
        return bool(值[0]), str(值[1])
    return bool(值), ""


def _临时根校验(临时根目录: Any) -> 结果:
    """校验临时根位于 工程缓存/ 之下且不等于 工程缓存 自身（S2 边界）。

    判定事实来自 文件系统支持库.文件操作.查找祖先目录（向上找 工程缓存 标记），
    本模块只做「命中与否 / 是否等于锚点」的条件分支。
    """
    文本根 = _文本(临时根目录)
    if not 文本根:
        return 结果.失败("参数不合法", "临时根目录不能为空", 来源=来源)
    查询 = _调用(
        "文件系统支持库.文件操作.查找祖先目录",
        {"起点": 文本根, "标记": _工程缓存名, "匹配起点名": 真, "最大层数": 64},
    )
    if not 查询.成功:
        return 查询
    命中 = 查询.值 if isinstance(查询.值, dict) else {}
    if not 命中.get("命中"):
        return 结果.失败("临时根越界", f"临时根必须位于 工程缓存/ 之下: {文本根}", 来源=来源)
    锚点 = _文本(命中.get("命中路径"))
    if not 锚点:
        return 结果.失败("临时根越界", f"临时根必须位于 工程缓存/ 之下: {文本根}", 来源=来源)
    根 = os.path.realpath(文本根)
    缓存 = os.path.realpath(锚点)
    层级 = int(命中.get("层级") or 0)
    if os.path.basename(根) == _工程缓存名:
        return 结果.失败("临时根越界", f"临时根不能是 工程缓存 本身: {根}", 来源=来源)
    if 根 == 缓存 or 层级 == 0:
        # 命中发生在起点自身（起点内含有同名子目录，或起点即锚点）→ 锚点不可信，拒绝。
        return 结果.失败("临时根越界", f"临时根必须位于 工程缓存/ 之下: {根}", 来源=来源)
    if not 根.startswith(缓存 + os.sep):
        return 结果.失败("临时根越界", f"临时根必须位于 工程缓存/ 之下: {根}", 来源=来源)
    return 结果.成功结果({"临时根": 根, "工程缓存": 缓存})


def _资源在临时根内(资源路径: str, 临时根目录: str) -> 结果:
    """校验资源落在临时根内：相对化后交 系统核心支持库.路径安全.校验路径 判定。"""
    if not 资源路径:
        return 结果.失败("参数不合法", "资源路径不能为空", 来源=来源)
    try:
        相对路径 = os.path.relpath(资源路径, 临时根目录)
    except ValueError as 错误:
        return 结果.失败("资源越界", f"资源路径无法相对化到临时根: {错误}", 来源=来源)
    return _调用(
        "系统核心支持库.路径安全.校验路径",
        {"根目录": 临时根目录, "相对路径": 相对路径},
    )


def _清单目录准备(清单路径: str) -> 结果:
    """确保清单父目录存在（经 文件系统支持库.文件操作.创建目录）。"""
    目录 = os.path.dirname(清单路径) or "."
    创建 = _调用("文件系统支持库.文件操作.创建目录", {"目录路径": 目录, "递归": 真})
    if not 创建.成功:
        return 结果.失败("写入失败", f"清单目录不可用：{创建.错误说明}", 来源=来源)
    return 结果.成功结果(目录)


def _写失败证据(根: str, 证据目录: str, 开工id: str, 失败表: list[dict[str, str]],
              清理数: int, 保留数: int) -> str:
    """写清理失败证据：临时根/清理失败.json（合并追加）+ 证据目录/{开工id}.json（覆盖）。

    统一结构：运行id/时间/路径/失败原因/资源列表，与原实现及测试中心独立模块验证语义对齐。
    证据写盘失败不吞：追加进失败表（由调用方返回）。
    """
    import time
    写出路径 = ""
    临时根证据 = os.path.join(根, "清理失败.json")
    已有失败: list[dict[str, Any]] = []
    存在 = _调用("文件系统支持库.文件操作.判断存在", {"文件路径": 临时根证据})
    if 存在.成功 and bool(存在.值):
        读取 = _调用("文件系统支持库.文件操作.读取文件", {"文件路径": 临时根证据, "最大字符": 0, "编码": "utf-8"})
        if 读取.成功:
            try:
                已有内容 = json.loads(str(读取.值 or "{}"))
                已有失败 = list(已有内容.get("失败", []))
            except ValueError:
                已有失败 = []
    时间戳 = time.strftime("%Y-%m-%d %H:%M:%S")
    新条目 = [{"路径": 项.get("路径/标识", ""), "类型": 项.get("类型", ""),
               "原因": 项.get("原因", ""), "时间": 时间戳} for 项 in 失败表]
    写入 = _调用("系统核心支持库.资源管理.原子写入", {
        "目标路径": 临时根证据,
        "内容": json.dumps({"失败": 已有失败 + 新条目}, ensure_ascii=False, indent=2),
    })
    if 写入.成功:
        写出路径 = 临时根证据
    else:
        失败表.append({"路径/标识": 临时根证据, "类型": "证据",
                      "原因": f"写入临时根清理失败证据失败：{写入.错误说明}"})
    if 证据目录:
        统一证据 = {
            "运行id": 开工id,
            "时间": 时间戳,
            "路径": 根,
            "清理数": 清理数,
            "保留数": 保留数,
            "失败原因": f"资源清理失败，共 {len(失败表)} 项",
            "资源列表": [{"路径": 项.get("路径/标识", ""), "类型": 项.get("类型", ""),
                          "原因": 项.get("原因", "")} for 项 in 失败表],
        }
        统一路径 = os.path.join(证据目录, f"{开工id or '未开工'}.json")
        统一写入 = _调用("系统核心支持库.资源管理.原子写入", {
            "目标路径": 统一路径,
            "内容": json.dumps(统一证据, ensure_ascii=False, indent=2),
        })
        if 统一写入.成功:
            写出路径 = 统一路径
        else:
            失败表.append({"路径/标识": 统一路径, "类型": "证据",
                          "原因": f"写入统一清理失败证据失败：{统一写入.错误说明}"})
    return 写出路径


def _回收单项(记录: dict[str, Any], 临时根目录: str) -> None:
    """按登记类型回收单项；失败抛 _单项失败 由调用方收集。"""
    类型 = _规范资源类型(记录.get("类型") if 记录.get("类型") is not None else "文件")
    if not 类型:
        raise _单项失败(f"未知资源类型：{记录.get('类型')!r}")
    路径 = _文本(记录.get("路径"))
    if 类型 in ("文件", "目录"):
        越界 = _资源在临时根内(路径, 临时根目录)
        if not 越界.成功 or not bool((越界.值 or {}).get("通过")):
            return  # 越界记录跳过（安全边界，与原实现同口径）
        # 收口登记表：登记过的路径由 清理全部临时资源 释放（未登记返回 资源不存在，
        # 不构成回收失败）；真正删除与失败判据交给 安全释放（幂等）。
        _调用("文件系统支持库.文件操作.清理全部临时资源", {"路径前缀": 路径})
        释放 = _调用("系统核心支持库.资源管理.安全释放", {"路径": 路径})
        if not 释放.成功:
            raise _单项失败(f"安全释放失败：{释放.错误说明}")
        成功标志, 消息 = _二元(释放.值)
        if not 成功标志:
            raise _单项失败(f"安全释放失败：{消息 or '未给出原因'}")
        return
    if 类型 == "子进程":
        句柄 = _句柄值(记录.get("句柄")) or _句柄值(记录.get("标识"))
        if 句柄 is None:
            raise _单项失败("子进程登记缺少进程句柄（无法回收）")
        终止 = _调用("系统核心支持库.进程管理.终止进程", {"句柄": 句柄, "强制": 真})
        if not 终止.成功:
            raise _单项失败(f"终止进程失败：{终止.错误说明}")
        释放 = _调用("系统核心支持库.进程管理.释放句柄", {"句柄": 句柄})
        if not 释放.成功:
            raise _单项失败(f"释放进程句柄失败：{释放.错误说明}")
        return
    if 类型 in _待补回收类型:
        raise _单项失败(f"待补能力：底座缺少「{类型}」回收原子能力（见 说明/待补能力清单.md）")
    raise _单项失败(f"未知资源类型：{类型}")


def 申请资源(临时根目录: 文本, 清单路径: 文本, 资源路径: 文本, 资源类型: 文本 = None, 保留: 布尔 = None, 开工id: 文本 = None, 句柄: 整数 = None) -> 结果:
    """登记一条测试临时资源：写入开工清单 + 登记到底座临时资源注册表。。"""
    类型 = _规范资源类型(资源类型 if _文本(资源类型) else "文件")
    if not 类型:
        return 结果.失败("参数不合法", f"未知资源类型：{资源类型!r}", 来源=来源)
    文本清单 = _文本(清单路径)
    if not 文本清单:
        return 结果.失败("参数不合法", "清单路径不能为空", 来源=来源)
    文本资源 = _文本(资源路径)
    if not 文本资源:
        return 结果.失败("参数不合法", "资源路径不能为空", 来源=来源)
    根校验 = _临时根校验(临时根目录)
    if not 根校验.成功:
        return 根校验
    根 = _文本((根校验.值 or {}).get("临时根")) or os.path.realpath(_文本(临时根目录))
    标识 = ""
    进程句柄: int | None = None
    if 类型 in ("文件", "目录"):
        越界 = _资源在临时根内(文本资源, 根)
        if not 越界.成功:
            return 越界
        越界值 = 越界.值 if isinstance(越界.值, dict) else {}
        if not 越界值.get("通过"):
            return 结果.失败(
                "资源越界",
                f"只能登记临时根内的资源：{文本资源}（{越界值.get('原因') or '越界'}）",
                来源=来源,
            )
        登记 = _调用("文件系统支持库.文件操作.登记临时资源", {"路径": 文本资源})
        if not 登记.成功:
            return 结果.失败("登记失败", f"临时资源登记失败：{登记.错误说明}", 来源=来源)
    elif 类型 == "子进程":
        进程句柄 = _句柄值(句柄)
        if 进程句柄 is None:
            return 结果.失败(
                "参数不合法",
                "子进程资源必须传 句柄（系统核心支持库.进程管理.启动进程 的返回值）",
                来源=来源,
            )
        状态 = _调用("系统核心支持库.进程管理.查询进程状态", {"句柄": 进程句柄})
        if not 状态.成功:
            return 结果.失败(
                "句柄失效",
                f"进程句柄 {进程句柄} 不可用（未登记，避免留下无法回收的孤儿）：{状态.错误说明}",
                来源=来源,
            )
        标识 = str(进程句柄)
    else:
        标识 = _冒号后(文本资源)
    记录: dict[str, Any] = {"路径": 文本资源, "类型": 类型, "保留": bool(保留), "标识": 标识}
    if 开工id is not None and _文本(开工id):
        记录["work_id"] = _文本(开工id)
    if 类型 == "子进程":
        记录["句柄"] = 进程句柄
    目录结果 = _清单目录准备(文本清单)
    if not 目录结果.成功:
        return 目录结果
    写入 = _调用("文件系统支持库.文件操作.追加写入", {
        "路径": 文本清单,
        "内容": json.dumps(记录, ensure_ascii=False) + "\n",
    })
    if not 写入.成功:
        return 结果.失败("写入失败", f"清单写入失败：{写入.错误说明}", 来源=来源)
    return 结果.成功结果({"成功": 真, **记录})


def 回收资源(临时根目录: 文本, 清单路径: 文本, 证据目录: 文本 = None, 开工id: 文本 = None) -> 结果:
    """回收清单中未标记保留的测试临时资源，失败留证据并如实返回失败。。"""
    文本清单 = _文本(清单路径)
    if not 文本清单:
        return 结果.失败("参数不合法", "清单路径不能为空", 来源=来源)
    根校验 = _临时根校验(临时根目录)
    if not 根校验.成功:
        return 根校验
    根 = _文本((根校验.值 or {}).get("临时根")) or os.path.realpath(_文本(临时根目录))
    存在 = _调用("文件系统支持库.文件操作.判断存在", {"文件路径": 文本清单})
    if not 存在.成功:
        return 存在
    清单存在 = bool(存在.值)
    行表: list[str] = []
    if 清单存在:
        读取 = _调用("文件系统支持库.文件操作.读取文件", {"文件路径": 文本清单, "最大字符": 0, "编码": "utf-8"})
        if not 读取.成功:
            return 结果.失败("读取失败", f"清单读取失败：{读取.错误说明}", 来源=来源)
        行表 = str(读取.值 or "").splitlines()
    清理数 = 0
    保留数 = 0
    失败表: list[dict[str, str]] = []
    for 行 in 行表:
        文本行 = 行.strip()
        if not 文本行:
            continue
        try:
            记录 = json.loads(文本行)
        except ValueError:
            continue
        if not isinstance(记录, dict):
            continue
        if 记录.get("保留"):
            保留数 += 1
            continue
        try:
            _回收单项(记录, 根)
            清理数 += 1
        except _单项失败 as 错误:
            失败表.append({
                "路径/标识": _文本(记录.get("路径")) or _文本(记录.get("标识")),
                "类型": _文本(记录.get("类型")),
                "原因": str(错误),
            })
    if 清单存在:
        删除 = _调用("文件系统支持库.文件操作.删除文件", {"文件路径": 文本清单})
        if not 删除.成功:
            失败表.append({"路径/标识": 文本清单, "类型": "清单",
                          "原因": f"清单删除失败：{删除.错误说明}"})
    证据路径 = ""
    if 失败表:
        证据路径 = _写失败证据(
            根, _文本(证据目录), _文本(开工id) or "未开工", 失败表, 清理数, 保留数)
        return 结果.失败(
            "资源清理失败",
            f"资源清理失败，共 {len(失败表)} 项",
            来源=来源,
            详情={"清理数": 清理数, "保留数": 保留数,
                  "失败表": 失败表, "证据路径": 证据路径},
        )
    return 结果.成功结果({"成功": 真, "清理数": 清理数, "保留数": 保留数,
                         "失败表": [], "证据路径": ""})
