"""知识检索模块：组合嵌入缓存/重排服务/文件系统/数据集合完成知识检索流程。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
调用器未装配或支持库不可用时返回统一失败，不向调用方抛异常。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.结果类型 import 结果


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数)
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源="知识检索")


def 检索知识(查询: str = None, 知识库: str = None, 模型名: str = None, 提供者: str = None, 顶部数量: int = None) -> 结果:
    """检索知识：先查嵌入缓存，再走文件/数据集合，最后重排。

    流程：
    1. 查询嵌入缓存（大语言模型支持库.嵌入缓存.查询嵌入）
    2. 若命中缓存直接取向量，否则加载文档（文件系统支持库.文件操作.读取文件 + 数据集合）
    3. 重排候选文档（大语言模型支持库.重排服务.重排）
    返回 {来源, 相关文档, 重排结果, 缓存命中}
    """
    if not isinstance(查询, str) or not 查询.strip():
        return 结果.失败("参数不合法", "查询必须是非空字符串", 来源="知识检索")
    模型 = 模型名 or "bge-m3"
    提供者标识 = 提供者 or "本地"
    顶数 = 顶部数量 or 5

    # 1. 查询嵌入缓存
    r1 = _调用支持库("大语言模型支持库.嵌入缓存.查询嵌入", {"文本": 查询, "模型名": 模型, "提供者": 提供者标识})
    缓存命中 = r1.成功 and r1.值.get("命中") if r1.值 else False

    # 2. 从知识库加载文档（文件系统 + 数据集合）
    if not 知识库:
        return 结果.失败("参数不合法", "知识库路径不能为空", 来源="知识检索")
    文档列表 = []
    r2 = _调用支持库("文件系统支持库.文件操作.列出目录", {"目录路径": 知识库})
    if r2.成功 and r2.值:
        for 条目 in (r2.值.get("项目") or r2.值.get("列表") or r2.值 if isinstance(r2.值, list) else []):
            路径 = 条目 if isinstance(条目, str) else (条目.get("路径") or 条目.get("名称") or "")
            if 路径:
                r3 = _调用支持库("文件系统支持库.文件操作.读取文件", {"文件路径": 路径, "编码": "utf-8"})
                if r3.成功 and r3.值:
                    文档列表.append({"路径": 路径, "文本": r3.值.get("值") or str(r3.值)})

    # 3. 重排
    if not 文档列表:
        return 结果.成功结果({"来源": 知识库, "相关文档": [], "重排结果": [], "缓存命中": 缓存命中, "总数": 0})
    r4 = _调用支持库("大语言模型支持库.重排服务.重排", {"查询": 查询, "文档列表": 文档列表, "顶部数量": 顶数})
    重排结果 = r4.值.get("重排结果") if r4.成功 else []

    return 结果.成功结果({
        "来源": 知识库,
        "相关文档": 文档列表,
        "重排结果": 重排结果,
        "缓存命中": 缓存命中,
        "总数": len(文档列表),
    })


def 检查可用性(知识库: str = None) -> 结果:
    """检查知识检索模块是否可用（依赖的支持库是否就绪）。"""
    依赖 = [("大语言模型支持库.嵌入缓存.查询嵌入", "嵌入缓存"), ("大语言模型支持库.重排服务.重排", "重排服务")]
    缺失 = []
    for 能力id, 名称 in 依赖:
        r = _调用支持库(能力id, {"文本": "探针", "模型名": "探针", "提供者": "探针"})
        if not r.成功:
            缺失.append(名称)
    return 结果.成功结果({"可用": len(缺失) == 0, "缺失支持库": 缺失, "知识库": 知识库 or "未指定"})