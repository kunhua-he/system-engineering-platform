"""能力目录 模块包级中文入口（功能模块）。

参数类型不在本文件手写：一律从本包的 `能力契约/参数契约.json`（由
`能力定义.json` 编译产出的唯一事实源）读取。历史教训（2026-09-15 实测）：
这里曾写成 `参数=[{"名称": 名称, "类型": "文本型"} for 名称 in 参数名]`，
把 `限制` 这类整数参数也注册成文本型，与能力定义漂移，网关按文本型校验 →
调用方传整数被拒（`参数不合法：能力 能力目录.搜索能力 的参数 限制 必须是 文本型`），
本包两个能力在 HTML 黑盒上全红。注册口径只允许有一个来源。
"""

from __future__ import annotations

import json
from pathlib import Path

from 模块库.能力目录.实现.能力目录 import 搜索能力
from 模块库.能力目录.实现.能力目录 import 读取能力
from 模块库.能力目录.实现.能力目录 import 常用参数组合

__all__ = ['搜索能力', '读取能力', '常用参数组合']

契约文件名 = "能力契约/参数契约.json"


def _契约参数(能力id: str) -> list:
    """从本包参数契约读该能力的参数声明（唯一事实源；缺条目即明确失败）。"""
    契约路径 = Path(__file__).resolve().parent / 契约文件名
    数据 = json.loads(契约路径.read_text(encoding="utf-8"))
    for 条目 in 数据.get("能力契约", []):
        if isinstance(条目, dict) and 条目.get("能力id") == 能力id:
            return [dict(项) for 项 in (条目.get("参数") or [])]
    raise RuntimeError(f"能力契约缺少 能力id: {能力id}（{契约路径}）")


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 说明 in [
        ("能力目录.搜索能力", 搜索能力, "只读检索支持库与模块库公开能力：关键词命中 能力id/名称/说明/包id，返回覆盖 14 字段的能力记录列表；含常用参数=真 时每条命中多带该能力历史上最常怎么传参的前 5 组"),
        ("能力目录.读取能力", 读取能力, "只读读取单个能力的契约：参数/必填/默认值/返回结构/错误码/调用示例/权限/依赖/版本/最近成功验证"),
        ("能力目录.常用参数组合", 常用参数组合, "按能力 id 返回历史上最常用的几组入参（含真实样例，默认 5 组），供调用方照抄免试错；数据源是调用参数账（按 (能力id, 入参形状) 计数、读时按次数倒序）"),
    ]:
        注册表.注册(能力实现(能力id=能力id, 包id="模块库.能力目录", 实现函数=函数,
                         参数=_契约参数(能力id),
                         返回="结果", 说明=说明))
