def _收敛限制(限制: Any) -> int | None:
    """限制：缺省用默认值；非整数或布尔 → None（参数不合法）；超界按边界收敛。"""
    if 限制 is None:
        return 默认限制
    if isinstance(限制, bool) or not isinstance(限制, int):
        return None
    return max(1, min(限制, 最大限制))


def _归一文本(值: Any) -> str | None:
    """可选文本参数归一：None 视为未传（空字符串）；非文本 → None 表示不合法。"""
    if 值 is None:
        return ""
    if not isinstance(值, str):
        return None
    return 值


def _收敛细节级别(细节级别: Any) -> str | None:
    """细节级别：未传/空 → 默认档；不认识的值 → None（参数不合法）。

    **不接受「不认识的档位就降级到默认档」**：静默降级会让调用方以为拿到了完整
    契约、实际只拿到指针，属「看起来对其实不对」。判据挂在产出点，直接拒绝。
    """
    文本 = _归一文本(细节级别)
    if 文本 is None:
        return None
    if not 文本:
        return 默认细节级别
    return 文本 if 文本 in 细节级别表 else None


def 切检索词(文本: str) -> list[str]:
    """把自然语言检索词切成双字滑窗词（与 `查开工上下文`/`查哲学条款` 同口径）。

    中文双字滑窗、英文数字整词（长度 ≥2），纯字符串运算，不调大模型、不分词库。
    为什么不用整句：整句会成为一个超长关键词，子串匹配必然 0 命中（2026-09-18 实测）。
    """
    净 = str(文本 or "")
    词表: list[str] = []
    已见: set[str] = set()
    for 串 in re.findall(r"[\u4e00-\u9fa5]{2,}", 净):
        for 起点 in range(len(串) - 1):
            词 = 串[起点:起点 + 2]
            if 词 not in 已见:
                已见.add(词)
                词表.append(词)
    for 词 in re.findall(r"[A-Za-z0-9_]{2,}", 净):
        小 = 词.lower()
        if 小 not in 已见:
            已见.add(小)
            词表.append(小)
    return 词表


#: 检索全文派生表缓存：键 = (id(记录表), 条数, 首条能力id, 末条能力id)。
#: 用 `id()` 作主键的前提是「同一份索引返回同一个列表对象」（`构建能力索引` 命中
#: 缓存时确实如此）；另两位校验位防 `id()` 被回收后复用顶替。
#: 有界：索引本身按项目根缓存，这里只需留住最近几份。
_检索全文缓存: dict[tuple, list[str]] = {}
_检索全文缓存上限 = 8


def _检索全文表(记录表: list[dict]) -> list[str]:
    """把每条记录预序列化成小写检索全文（**与记录下标一一对应**）。

    为什么必须有（2026-09-21 华哥「一点并发都扛不住」的第二个根因）：
    整串匹配与双字滑窗打分**各自**都在循环里现做 `json.dumps(记录)`，542 条记录
    单次序列化实测 **13.5ms**。两处都在每次能力调用的链路上，而 `json.dumps` 是
    纯 CPU、持 GIL ⇒ 并发时被完全串行化（实测吞吐恒为 ~73 req/s，加线程无效）。

    预序列化一次 13.6ms、复用 20 次只要 15.5ms（单次 **0.77ms**，快 17 倍）；
    索引自带「指纹 + 有效期」缓存，故这份派生表随索引一起被复用。
    """
    指纹 = (id(记录表), len(记录表),
            记录表[0].get("能力id") if 记录表 else "",
            记录表[-1].get("能力id") if 记录表 else "")
    已有 = _检索全文缓存.get(指纹)
    if 已有 is not None and len(已有) == len(记录表):
        return 已有
    全文表 = [json.dumps(记录, ensure_ascii=False).lower() for 记录 in 记录表]
    if len(_检索全文缓存) >= _检索全文缓存上限:
        _检索全文缓存.clear()
    _检索全文缓存[指纹] = 全文表
    return 全文表


def _滑窗打分表(记录表: list[dict], 关键词: str) -> list[tuple[int, dict]]:
    """双字滑窗**打分表**：`(命中词数, 记录)`，按 分降序、同分按 能力id 稳定排序（0 分不进表）。

    **只在「整串子串匹配 0 命中」的兜底链路上被调用** —— 命中时老行为逐字不变（对外只增不改）。

    分工：本函数**只打分**；相关度下限与占比上限两条护栏在 `_兜底检索`。
    打分只此一份产出点，护栏只此一条消费链路（哲学 1.1：同一件事不留两条腿）。
    """
    词表 = 切检索词(关键词)
    if not 词表:
        return []
    全文表 = _检索全文表(记录表)
    打分表: list[tuple[int, dict]] = []
    for 记录, 全文 in zip(记录表, 全文表):
        分 = sum(1 for 词 in 词表 if 词 in 全文)
        if 分 > 0:
            打分表.append((分, 记录))
    打分表.sort(key=lambda 项: (-项[0], 项[1]["能力id"]))
    return 打分表


def _兜底相关度下限(词表长度: int) -> int:
    """兜底候选的命中词数下限：`max(2, ceil(词表长度 × 0.25))`（阈值口径只有这一份）。

    词表为空时退到绝对下限；该分支实际不会被走到（`切检索词` 为空时打分表本就为空），
    留它只为让本函数**对任何入参都有定义的返回值**，不靠调用方替它兜空。
    """
    if 词表长度 <= 0:
        return 兜底相关度绝对下限
    return max(兜底相关度绝对下限, math.ceil(词表长度 * 兜底相关度下限系数))


def _兜底检索(记录表: list[dict], 关键词: str) -> tuple[list[dict], dict]:
    """**零命中兜底**：双字滑窗打分 + 两条护栏（相关度下限、命中占比上限）。

    只在「整串子串匹配 0 命中」时才走这里；命中时老行为逐字不变（对外只增不改）。
    为什么需要它（2026-09-20 实测）：整串匹配下 12 个自然语言词 **11 个零命中（91%）**，
    Agent 描述「我要干什么」基本搜不到，被迫改用 `rg` 枚举源码找能力 id ⇒ 违反
    「Agent 只记两个动作：搜索能力 → 调用能力」。双字滑窗后同批词 **10/12 有命中**，
    且排序正确（如「把视频转成音频」最高分命中 `媒体转写.转写视频文件`，命中词 视频/频转/音频）。

    **两条护栏缺一不可**（2026-09-21 补，未完成事项 #183/#196⑧）：滑窗打分只排序、**不筛除** ——
    实测「文档生成 编译口 收工释放 文件租约」打分后 **546 条全表都在**（每条至少命中「文件」这类
    高频二字词），返回全表等于没有过滤，比如实报零命中更有害。故补齐：
    ① **相关度下限**：命中词数 < `_兜底相关度下限(词表长度)` 的记录不进候选；
    ② **占比上限**：候选数 / 全表 > `兜底占比上限` ⇒ 判**无效兜底**，返回空候选（如实报零命中）。
    两条都只作用在兜底路径上：精确命中的查询一行都不受它影响。

    返回 `(候选记录, 判据字典)`。判据字典是「怎么判的」的唯一载体（阈值、命中数、占比、
    是否无效都在里面），由调用方原样回带给使用者对账 —— 本函数不拼人读文案、不写返回字段。

    与扩词表的分工：**本条是「无需预登记的兜底」**（任何自然语言都能拿到候选）；
    `项目文档支持库` 的「未命中词 → 建议词」表是**可沉淀的精确映射**，两者互补不冲突。
    """
    词表 = 切检索词(关键词)
    打分表 = _滑窗打分表(记录表, 关键词)
    全表条数 = len(记录表)
    下限 = _兜底相关度下限(len(词表))
    候选 = [记录 for 分, 记录 in 打分表 if 分 >= 下限]
    占比 = (len(候选) / 全表条数) if 全表条数 else 0.0
    判据 = {
        "词表长度": len(词表),
        "相关度下限": 下限,
        "打分命中数": len(打分表),
        "候选命中数": len(候选),
        "全表条数": 全表条数,
        "命中占比": round(占比, 4),
        "占比上限": 兜底占比上限,
        "是否无效": 占比 > 兜底占比上限,
    }
    if 判据["是否无效"]:
        return [], 判据
    return 候选, 判据


def _游标校验(关键词: str, 上一条id: str) -> str:
    """游标校验位：绑定 游标版本 + 关键词 + 排序键，任一处被改都算构造。"""
    原料 = f"{游标版本}\x00{关键词}\x00{上一条id}".encode("utf-8")
    return hashlib.sha256(原料).hexdigest()[:游标校验位长度]


def 编码游标(关键词: str, 上一条id: str) -> str:
    """按排序键产出不透明游标（base64url(JSON) + 校验位）。

    不透明是**有意的**：调用方拿到的那串东西不该被解析或自己拼装——一旦允许拼装，
    就等于把分页正确性的责任推给每个调用方。校验位保证「自己拼的」会被拒。
    """
    载荷 = {"版本": 游标版本, "关键词": 关键词, "上一条id": 上一条id,
            "校验": _游标校验(关键词, 上一条id)}
    return base64.urlsafe_b64encode(
        json.dumps(载荷, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    ).decode("ascii").rstrip("=")


def 解码游标(游标: str) -> tuple[str, str] | None:
    """解游标；返回 (关键词, 上一条id)。任何异常形态一律返回 None（由调用方报参数不合法）。

    fail-closed：不认识的版本、缺键、校验位不匹配、base64/JSON 坏掉——全部当非法，
    绝**不**退回「从头开始」或「按偏移近似」——那会把调用方的错变成静默漏项。
    """
    原文 = 游标.strip()
    if not 原文:
        return None
    补齐 = "=" * (-len(原文) % 4)
    try:
        载荷 = json.loads(base64.urlsafe_b64decode(原文 + 补齐).decode("utf-8"))
    except (binascii.Error, UnicodeDecodeError, ValueError, json.JSONDecodeError):
        return None
    if not isinstance(载荷, dict):
        return None
    if 载荷.get("版本") != 游标版本:
        return None
    关键词 = 载荷.get("关键词")
    上一条id = 载荷.get("上一条id")
    if not isinstance(关键词, str) or not isinstance(上一条id, str) or not 上一条id:
        return None
    if 载荷.get("校验") != _游标校验(关键词, 上一条id):
        return None
    return 关键词, 上一条id


def _投影(记录: dict, 细节级别: str) -> dict:
    """按档位裁剪一条记录：只保留该档允许的键，**顺序与档位表一致**（便于人读对账）。"""
    if 细节级别 == 细节级别表[-1]:
        return 记录
    允许 = 说明字段表 if 细节级别 == 细节级别表[1] else 精简字段表
    return {键: 记录[键] for 键 in 允许 if 键 in 记录}


def _索引(项目根: Path) -> tuple[list[dict], 结果 | None]:
    """构建只读能力索引；返回 (记录列表, 失败结果或 None)。

    数据根缺失或索引为空时给出明确失败（绝不返回空列表冒充「平台没有能力」）；
    失败时记录列表为空列表，由调用方按 失败 结果返回。
    """
    from 模块库.能力目录.实现.能力索引 import 定位数据根, 构建能力索引

    if not 定位数据根(项目根):
        return [], _失败("文件不存在",
                        f"项目根 {项目根.as_posix()} 下缺少 支持库/模块库/技能库 目录，无法检索能力")
    记录表, 问题列表 = 构建能力索引(项目根)
    if not 记录表:
        return [], _失败("内部错误",
                        "能力索引为空：包声明可读但未解析到任何公开能力"
                        + (f"；扫描问题: {'; '.join(问题列表[:3])}" if 问题列表 else ""))
    return 记录表, None


def _常用参数表(能力id表: list[str], 上限: int) -> dict[str, list[dict]]:
    """取这批能力的历史常用参数组合；返回 `{能力id: 组合列表}`。

    数据源是 `公共契约.诊断.调用账本` 的**调用参数账**（SQLite，主键
    `(能力id, 入参形状)`，网关每调一次自增 1）。写方在网关、读方在这里，
    两边都不许各写一份口径，故账本读写只在那个模块实现一次。

    为什么一次只查一个能力：账本的排序索引是 `(能力id, 调用次数 DESC)`，
    带上 `能力id` 才是**索引内取前 N**；一条 SQL 跨能力取再在内存里分组会退化成全表扫。
    """
    from 公共契约.诊断.调用账本 import 调用参数账

    账 = 调用参数账()
    结果表: dict[str, list[dict]] = {}
    for 标识 in 能力id表:
        结果表[标识] = 账.查常用参数(标识, 上限)["常用参数组合"]
    return 结果表


def 搜索能力(关键词: str = "", 限制: int = 默认限制, 游标: str = "",
           细节级别: str = 默认细节级别, 含常用参数: bool = 假) -> 结果:
    """按关键词只读检索公开能力，支持游标分页与三档细节级别（对外只增不改）。

    - `关键词`：空字符串表示不过滤；大小写不敏感，命中**整条记录**任一字段即算匹配
      （与 能力搜索器.搜索公开能力、公开能力.搜索公开能力 同为整条记录子串匹配）。
    - `限制`：**每页大小**（1~100）。旧调用形状（只传 关键词/限制）语义不变——
      本来也只取前 N 条；差别只在「能接着往下翻了」。
    - `游标`：空 = 第一页；否则原样回传上一次的 `下一条游标`。游标绑定关键词，
      同一轮翻页传了不同 关键词 一律拒绝（否则等于换了过滤条件还接着老位置取）。
    - `细节级别`：默认「名称」只回精简字段（指针），重字段必须显式要「完整契约」。
    - `含常用参数`：**默认假**。为真时每条命中多带一个 `常用参数`（该能力历史上最常
      怎么传参的前 5 组，含真实样例）——「契约只声明类型、不声明一组能跑通的取值」，
      调用方靠它免掉试错。**默认关的理由**：每条挂 5 组会把返回体量放大数倍，正是
      「调用几次打爆上下文」的成因；要细则就该显式要（与 细节级别 同一取舍）。

    返回键在原有 7 个（关键词/限制/总数/返回数/是否截断/能力列表/项目根）之上
    追加 5 个：`游标`（本次用的入参原值）、`下一条游标`（空 = 没有更多）、
    `细节级别`（本次实际生效的档位）、`兜底说明`（人读文案：本次兜底是怎么判的、
    判无效时为什么如实报零命中）、`兜底判据`（机器可对账的阈值与命中占比；
    本次没走兜底时为空字典 —— 空字典 ≠ 兜底命中 0 条，后者是「走了兜底但被判无效」）。
    """
    关键词文本 = _归一文本(关键词)
    if 关键词文本 is None:
        return _失败("参数不合法", f"关键词 必须是文本，收到 {type(关键词).__name__}")
    条数上限 = _收敛限制(限制)
    if 条数上限 is None:
        return _失败("参数不合法", f"限制 必须是整数，收到 {限制!r}")
    游标文本 = _归一文本(游标)
    if 游标文本 is None:
        return _失败("参数不合法", f"游标 必须是文本，收到 {type(游标).__name__}")
    生效档 = _收敛细节级别(细节级别)
    if 生效档 is None:
        return _失败("参数不合法",
                   f"细节级别 必须是 {'/'.join(细节级别表)} 之一，收到 {细节级别!r}")
    if type(含常用参数) is not bool:
        return _失败("参数不合法", f"含常用参数 必须是逻辑值（真/假），收到 {含常用参数!r}")

    项目根 = 定位项目根()
    记录表, 错误 = _索引(项目根)
    if 错误 is not None:
        return 错误
    模式 = 关键词文本.strip().lower()
    # 预序列化全文表与记录下标一一对应（见 `_检索全文表`：这里是每次调用的热路径，
    # 现做 json.dumps 会让并发被 GIL 串行化）。
    if 模式:
        全文表 = _检索全文表(记录表)
        命中表 = [记录 for 记录, 全文 in zip(记录表, 全文表) if 模式 in 全文]
    else:
        命中表 = list(记录表)
    兜底扩词 = False
    兜底判据: dict = {}
    兜底说明 = ""
    if 模式 and not 命中表:
        # 零命中兜底：自然语言整串匹配不到时，改用双字滑窗打分 + 两条护栏（见 _兜底检索）。
        命中表, 兜底判据 = _兜底检索(记录表, 关键词文本)
        兜底扩词 = bool(命中表)
        if 兜底扩词:
            兜底说明 = ("兜底命中非精确匹配（整串关键词 0 命中，改用双字滑窗按命中词数打分），"
                       f"已按相关度排序；本页命中 {兜底判据['候选命中数']}/{兜底判据['全表条数']} 条"
                       f"（占比 {兜底判据['命中占比']:.0%}，上限 {兜底判据['占比上限']:.0%}），"
                       f"相关度下限 = 命中词数 ≥ {兜底判据['相关度下限']}"
                       f"（词表 {兜底判据['词表长度']} 个双字词）")
        elif 兜底判据["是否无效"]:
            兜底说明 = (f"兜底命中占比过高（{兜底判据['候选命中数']}/{兜底判据['全表条数']} = "
                       f"{兜底判据['命中占比']:.0%} > 上限 {兜底判据['占比上限']:.0%}），"
                       "判无效兜底，已如实报零命中 —— 请改用更具体的关键词"
                       "（能力名/能力id 的实词，如「文档生成」而不是「生成 文件 文档」）")
        else:
            兜底说明 = ("兜底命中为空：双字滑窗相关度不足（无记录达到命中词数下限 "
                       f"{兜底判据['相关度下限']}），已如实报零命中"
                       " —— 平台可能确无此类能力，请改用更具体的关键词")
    # 排序键唯一且稳定：能力id（索引按 能力id 去重，故不重复）——游标就锚在它上面。
    # 兜底路径已按分数排好序（分数优先），此处**不再重排**，否则会把相关度打散。
    if not 兜底扩词:
        命中表.sort(key=lambda 记录: 记录["能力id"])
    编号表 = [记录["能力id"] for 记录 in 命中表]
    总数 = len(命中表)

    # 起点：无游标 = 0；有游标 = 第一个**严格大于**锚点 能力id 的位置（二分，不用偏移）。
    # 这样即便上一页之后有能力的增删，续取位置仍由排序键决定，不会漏项/重项。
    起点 = 0
    if 游标文本.strip():
        解出 = 解码游标(游标文本)
        if 解出 is None:
            return _失败("参数不合法",
                       "游标 非法：不是本能力签发的游标（不透明、不可自行构造或改写）")
        游标关键词, 锚点id = 解出
        if 游标关键词 != 关键词文本:
            return _失败("参数不合法",
                       f"游标 与 关键词 不匹配：游标签发于 关键词={游标关键词!r}，"
                       f"本次传入 关键词={关键词文本!r}（同一轮翻页必须传相同关键词，"
                       "否则会漏项或重项）")
        起点 = bisect_right(编号表, 锚点id)
        if 兜底扩词 and 锚点id in 编号表:
            # 兜底路径按相关度排序（非能力id 序），二分结果不适用；改用锚点定位。
            起点 = 编号表.index(锚点id) + 1
    当页 = 命中表[起点:起点 + 条数上限]
    还有更多 = (起点 + len(当页)) < 总数

    能力列表 = [_投影(记录, 生效档) for 记录 in 当页]
    if 含常用参数 and 能力列表:
        常用参数表 = _常用参数表([记录["能力id"] for 记录 in 当页], 默认常用参数组数)
        for 条目 in 能力列表:
            条目["常用参数"] = 常用参数表.get(条目.get("能力id", ""), [])

    return 结果.成功结果({
        "关键词": 关键词文本,
        "限制": 条数上限,
        "总数": 总数,
        "返回数": len(当页),
        "是否截断": 还有更多,
        "能力列表": 能力列表,
        "项目根": 项目根.as_posix(),
        "游标": 游标文本,
        "下一条游标": (编码游标(关键词文本, 当页[-1]["能力id"]) if 还有更多 and 当页 else ""),
        "细节级别": 生效档,
        "是否扩词": 兜底扩词,
        "含常用参数": 含常用参数,
        "兜底说明": 兜底说明,
        "兜底判据": 兜底判据,
    })


def 常用参数组合(能力id: str = "", 上限: int = 默认常用参数组数) -> 结果:
    """按能力 id 返回**历史上最常用的几组入参**（含真实样例），供调用方照抄。

    华哥 2026-09-21 口径：「在查询这个技能的时候，给他历史调用组合参数，返回最常用的
    5 组，这样子是否会更加不容易犯错？毕竟都返回了最常用的 5 组了，那格式都算明朗了。」
    本条就是那个「查」的入口；`搜索能力(含常用参数=真)` 是它的批量形态（一次给一页命中）。

    数据源是 `公共契约.诊断.调用账本` 的**调用参数账**（SQLite，主键
    `(能力id, 入参形状)`，网关每调一次自增 1、读时按次数倒序取前 N）——
    华哥 2026-09-21 口径：「参数组合是唯一值，每一次访问同一个参数自 +1，
    然后返回的时候直接排序返回」。账本读写只在那个模块实现一次，这里不重复口径。

    口径必须说清（否则是拿局部冒充全局）：
    - 计数覆盖**账本建立以来的全部调用**（不是「最近 N 条窗口」的近似值）；
    - `能力id` 为空 → 汇总全部能力，每段各取前 `上限` 组；
    - 本能力上线前的历史调用没有入参记录，**一律不补**（编一个样例出来就是假证据）；
    - 一个组合都没有（能力从没被调用过）→ `常用参数组合` 为空列表，
      **这是如实结论不是错误**，调用方此时应以 `读取能力` 的 `调用示例` 为准；
    - 账本读不出来 → 同样回空列表，但 `问题` 字段非空，调用方据此区分两种情况。
    """
    归一id = _归一文本(能力id)
    if 归一id is None:
        return _失败("参数不合法", f"能力id 必须是文本，收到 {type(能力id).__name__}")
    组数 = _收敛限制(上限)
    if 组数 is None:
        return _失败("参数不合法", f"上限 必须是整数，收到 {上限!r}")

    from 公共契约.诊断.调用账本 import 调用参数账

    查得 = 调用参数账().查常用参数(归一id, 组数)
    return 结果.成功结果({
        "能力id": 归一id,
        "上限": 组数,
        "命中能力数": 查得["命中能力数"],
        "组合数": 查得["组合数"],
        "常用参数组合": 查得["常用参数组合"],
        "问题": 查得["问题"],
        "说明": ("来自调用参数账（按 (能力id, 入参形状) 计数、读时按次数倒序）；"
               "`样例` 是最近一次的真实入参（长文本已折叠），只作展示、不作校验依据；"
               "一组都没有时以 读取能力 的 `调用示例` 为准"),
    })


def 读取能力(能力id: str) -> 结果:
    """按能力id只读读取单条完整契约（参数/必填/默认值/返回/错误码/调用示例等）。"""
    if not isinstance(能力id, str) or not 能力id.strip():
        return _失败("参数不合法", f"能力id 必须是非空文本，收到 {能力id!r}")
    项目根 = 定位项目根()
    记录表, 错误 = _索引(项目根)
    if 错误 is not None:
        return 错误
    目标 = 能力id.strip()
    for 记录 in 记录表:
        if 记录["能力id"] == 目标:
            return 结果.成功结果(记录)
    return _失败("能力不存在",
               f"公开能力不存在: {目标}（可先用 能力目录.搜索能力 按关键词定位）")
