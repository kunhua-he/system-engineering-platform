"""能力目录 模块（功能模块）：把「平台有哪些能力」收敛成两个只读能力。

- 能力目录.搜索能力（关键词/限制/游标/细节级别 → 能力记录列表）
- 能力目录.读取能力（能力id → 单条完整契约）

两个能力都只读对方的公开声明（包声明/参数契约/能力定义/权限契约/资源预算/
验证历史），不加载任何能力实现、不 import 支持库/提供者/第三方；
数据边界与旧两道检索实现同口径：支持库.适配层.* 与 内部层 包不对外暴露。
失败一律返回统一结果（成功/值/错误码/错误说明），不向调用方抛异常。

分层披露（P-9 第 1 条「清单聚合、细节按需」）与游标分页（P-9 第 6 条「成本递减的
修补顺序」）在本文件内的落点：

- **检索口径不变**：关键词仍按**整条记录**做大小写不敏感子串匹配（与旧两道实现
  同口径，不因返回变精简而丢掉「按参数说明找到能力」的召回）；
- **投影只影响返回**：`细节级别` 决定每条记录回多少字段，默认档「名称」把
  `参数`/`行为`/`返回`/`资源预算` 这类重字段挡在返回之外（保住 prompt 前缀缓存）；
- **游标基于排序键**：游标里带的是「上一页最后一条的 能力id」这个**排序键**，
  不是偏移量——翻页时按排序键二分定位续取，中间新增/删除能力也不会漏项或重项。
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import json
from bisect import bisect_right
from pathlib import Path
from typing import Any

from 公共契约.基础类型.结果类型 import 结果

来源 = "能力目录"
默认限制 = 5
最大限制 = 100
错误码表 = ("参数不合法", "能力不存在", "文件不存在", "内部错误")

#: 返回明细三档（**顺序即粗细**：索引 0 最精简，末位最完整）。
细节级别表 = ("名称", "名称+说明", "完整契约")
#: 默认档 = 「名称」。选择理由见 `能力定义.json` 该能力 `说明` 字段与
#: `说明/设计说明.md`「默认档为什么选『名称』」一节（一句话：默认档是给 Agent
#: 做**发现**用的，重字段每一轮都进上下文会把前缀缓存打掉；要细则就该显式要）。
默认细节级别 = 细节级别表[0]

#: 精简档：只是**指针**（我是谁、在哪、干什么用），不含任何契约细则。
#: `内部层` 也在精简档：它是**取舍标记**（该能力属内部层包，可调但非常规推荐），
#: 属「我是谁」的一部分；2026-09-20 起内部层能力进发现面，必须让调用方一眼看到该标记。
精简字段表 = ("能力id", "名称", "中文名", "中文名称", "一句话说明", "包id", "内部层")
#: 中间档：追加「一段话看懂这个能力」所需的归属性与版本字段，仍不含重字段。
说明字段表 = 精简字段表 + (
    "说明", "包名称", "提供方", "提供者", "类型", "版本", "包版本",
)
#: 重字段（**默认档与中间档都不得出现**）：参数/返回/错误码/行为/资源预算/验证/权限。
#: 这张表同时是反向验证的判据——测试断言精简档与这些键**互斥**，而不是只断言
#: 「有几个键」；只数键数的断言挡不住重字段偷偷回流。
重字段表 = (
    "参数", "参数类型", "参数列表", "参数名", "必填", "必填参数", "可选参数", "默认值",
    "返回", "返回结构", "错误码", "调用示例", "调用示例文本", "权限",
    "资源预算", "资源预算声明", "依赖", "依赖能力", "最近成功验证", "验证状态", "行为",
)

#: 游标载荷版本：格式一变就 +1，旧游标自然失效（fail-closed 报参数不合法，
#: 绝不按新格式硬解出个错位置）。
游标版本 = 1
游标校验位长度 = 12


def 定位项目根() -> Path:
    """项目根：从本文件向上找到同时含 支持库 与 模块库 的目录。

    不使用固定长度的 parents[N]（目录迁移会让它失效），找不到时退回
    实现/→包→模块库→项目根 的四级位置。
    """
    起始 = Path(__file__).resolve()
    for 祖先 in 起始.parents:
        if (祖先 / "支持库").is_dir() and (祖先 / "模块库").is_dir():
            return 祖先
    return 起始.parents[3]


def _失败(错误码: str, 说明: str) -> 结果:
    return 结果.失败(错误码, 说明, 来源=来源)


def _收敛限制(限制: Any) -> int | None:
    """限制：缺省用默认值；非整数或布尔 → None（参数不合法）；超界按边界收敛。"""
    if 限制 is None:
        return 默认限制
    if isinstance(限制, bool) or not isinstance(限制, int):
        return None
    return max(1, min(限制, 最大限制))


def _归一文本(值: Any) -> str | None:
    """可选文本参数归一：None 视为未传（空字符串）；非文本 → None 表示不合法。"""
    if 值 is None:
        return ""
    if not isinstance(值, str):
        return None
    return 值


def _收敛细节级别(细节级别: Any) -> str | None:
    """细节级别：未传/空 → 默认档；不认识的值 → None（参数不合法）。

    **不接受「不认识的档位就降级到默认档」**：静默降级会让调用方以为拿到了完整
    契约、实际只拿到指针，属「看起来对其实不对」。判据挂在产出点，直接拒绝。
    """
    文本 = _归一文本(细节级别)
    if 文本 is None:
        return None
    if not 文本:
        return 默认细节级别
    return 文本 if 文本 in 细节级别表 else None


def _游标校验(关键词: str, 上一条id: str) -> str:
    """游标校验位：绑定 游标版本 + 关键词 + 排序键，任一处被改都算构造。"""
    原料 = f"{游标版本}\x00{关键词}\x00{上一条id}".encode("utf-8")
    return hashlib.sha256(原料).hexdigest()[:游标校验位长度]


def 编码游标(关键词: str, 上一条id: str) -> str:
    """按排序键产出不透明游标（base64url(JSON) + 校验位）。

    不透明是**有意的**：调用方拿到的那串东西不该被解析或自己拼装——一旦允许拼装，
    就等于把分页正确性的责任推给每个调用方。校验位保证「自己拼的」会被拒。
    """
    载荷 = {"版本": 游标版本, "关键词": 关键词, "上一条id": 上一条id,
            "校验": _游标校验(关键词, 上一条id)}
    return base64.urlsafe_b64encode(
        json.dumps(载荷, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    ).decode("ascii").rstrip("=")


def 解码游标(游标: str) -> tuple[str, str] | None:
    """解游标；返回 (关键词, 上一条id)。任何异常形态一律返回 None（由调用方报参数不合法）。

    fail-closed：不认识的版本、缺键、校验位不匹配、base64/JSON 坏掉——全部当非法，
    绝**不**退回「从头开始」或「按偏移近似」——那会把调用方的错变成静默漏项。
    """
    原文 = 游标.strip()
    if not 原文:
        return None
    补齐 = "=" * (-len(原文) % 4)
    try:
        载荷 = json.loads(base64.urlsafe_b64decode(原文 + 补齐).decode("utf-8"))
    except (binascii.Error, UnicodeDecodeError, ValueError, json.JSONDecodeError):
        return None
    if not isinstance(载荷, dict):
        return None
    if 载荷.get("版本") != 游标版本:
        return None
    关键词 = 载荷.get("关键词")
    上一条id = 载荷.get("上一条id")
    if not isinstance(关键词, str) or not isinstance(上一条id, str) or not 上一条id:
        return None
    if 载荷.get("校验") != _游标校验(关键词, 上一条id):
        return None
    return 关键词, 上一条id


def _投影(记录: dict, 细节级别: str) -> dict:
    """按档位裁剪一条记录：只保留该档允许的键，**顺序与档位表一致**（便于人读对账）。"""
    if 细节级别 == 细节级别表[-1]:
        return 记录
    允许 = 说明字段表 if 细节级别 == 细节级别表[1] else 精简字段表
    return {键: 记录[键] for 键 in 允许 if 键 in 记录}


def _索引(项目根: Path) -> tuple[list[dict], 结果 | None]:
    """构建只读能力索引；返回 (记录列表, 失败结果或 None)。

    数据根缺失或索引为空时给出明确失败（绝不返回空列表冒充「平台没有能力」）；
    失败时记录列表为空列表，由调用方按 失败 结果返回。
    """
    from 模块库.能力目录.实现.能力索引 import 定位数据根, 构建能力索引

    if not 定位数据根(项目根):
        return [], _失败("文件不存在",
                        f"项目根 {项目根.as_posix()} 下缺少 支持库/模块库 目录，无法检索能力")
    记录表, 问题列表 = 构建能力索引(项目根)
    if not 记录表:
        return [], _失败("内部错误",
                        "能力索引为空：包声明可读但未解析到任何公开能力"
                        + (f"；扫描问题: {'; '.join(问题列表[:3])}" if 问题列表 else ""))
    return 记录表, None


def 搜索能力(关键词: str = "", 限制: int = 默认限制, 游标: str = "",
           细节级别: str = 默认细节级别) -> 结果:
    """按关键词只读检索公开能力，支持游标分页与三档细节级别（对外只增不改）。

    - `关键词`：空字符串表示不过滤；大小写不敏感，命中**整条记录**任一字段即算匹配
      （与 能力搜索器.搜索公开能力、公开能力.搜索公开能力 同为整条记录子串匹配）。
    - `限制`：**每页大小**（1~100）。旧调用形状（只传 关键词/限制）语义不变——
      本来也只取前 N 条；差别只在「能接着往下翻了」。
    - `游标`：空 = 第一页；否则原样回传上一次的 `下一条游标`。游标绑定关键词，
      同一轮翻页传了不同 关键词 一律拒绝（否则等于换了过滤条件还接着老位置取）。
    - `细节级别`：默认「名称」只回精简字段（指针），重字段必须显式要「完整契约」。

    返回键在原有 7 个（关键词/限制/总数/返回数/是否截断/能力列表/项目根）之上
    追加 3 个：`游标`（本次用的入参原值）、`下一条游标`（空 = 没有更多）、
    `细节级别`（本次实际生效的档位）。
    """
    关键词文本 = _归一文本(关键词)
    if 关键词文本 is None:
        return _失败("参数不合法", f"关键词 必须是文本，收到 {type(关键词).__name__}")
    条数上限 = _收敛限制(限制)
    if 条数上限 is None:
        return _失败("参数不合法", f"限制 必须是整数，收到 {限制!r}")
    游标文本 = _归一文本(游标)
    if 游标文本 is None:
        return _失败("参数不合法", f"游标 必须是文本，收到 {type(游标).__name__}")
    生效档 = _收敛细节级别(细节级别)
    if 生效档 is None:
        return _失败("参数不合法",
                   f"细节级别 必须是 {'/'.join(细节级别表)} 之一，收到 {细节级别!r}")

    项目根 = 定位项目根()
    记录表, 错误 = _索引(项目根)
    if 错误 is not None:
        return 错误
    模式 = 关键词文本.strip().lower()
    命中表 = [记录 for 记录 in 记录表
             if not 模式 or 模式 in json.dumps(记录, ensure_ascii=False).lower()]
    # 排序键唯一且稳定：能力id（索引按 能力id 去重，故不重复）——游标就锚在它上面。
    命中表.sort(key=lambda 记录: 记录["能力id"])
    编号表 = [记录["能力id"] for 记录 in 命中表]
    总数 = len(命中表)

    # 起点：无游标 = 0；有游标 = 第一个**严格大于**锚点 能力id 的位置（二分，不用偏移）。
    # 这样即便上一页之后有能力的增删，续取位置仍由排序键决定，不会漏项/重项。
    起点 = 0
    if 游标文本.strip():
        解出 = 解码游标(游标文本)
        if 解出 is None:
            return _失败("参数不合法",
                       "游标 非法：不是本能力签发的游标（不透明、不可自行构造或改写）")
        游标关键词, 锚点id = 解出
        if 游标关键词 != 关键词文本:
            return _失败("参数不合法",
                       f"游标 与 关键词 不匹配：游标签发于 关键词={游标关键词!r}，"
                       f"本次传入 关键词={关键词文本!r}（同一轮翻页必须传相同关键词，"
                       "否则会漏项或重项）")
        起点 = bisect_right(编号表, 锚点id)
    当页 = 命中表[起点:起点 + 条数上限]
    还有更多 = (起点 + len(当页)) < 总数

    return 结果.成功结果({
        "关键词": 关键词文本,
        "限制": 条数上限,
        "总数": 总数,
        "返回数": len(当页),
        "是否截断": 还有更多,
        "能力列表": [_投影(记录, 生效档) for 记录 in 当页],
        "项目根": 项目根.as_posix(),
        "游标": 游标文本,
        "下一条游标": (编码游标(关键词文本, 当页[-1]["能力id"]) if 还有更多 and 当页 else ""),
        "细节级别": 生效档,
    })


def 读取能力(能力id: str) -> 结果:
    """按能力id只读读取单条完整契约（参数/必填/默认值/返回/错误码/调用示例等）。"""
    if not isinstance(能力id, str) or not 能力id.strip():
        return _失败("参数不合法", f"能力id 必须是非空文本，收到 {能力id!r}")
    项目根 = 定位项目根()
    记录表, 错误 = _索引(项目根)
    if 错误 is not None:
        return 错误
    目标 = 能力id.strip()
    for 记录 in 记录表:
        if 记录["能力id"] == 目标:
            return 结果.成功结果(记录)
    return _失败("能力不存在",
               f"公开能力不存在: {目标}（可先用 能力目录.搜索能力 按关键词定位）")
