"""能力目录 模块（功能模块）：把「平台有哪些能力」收敛成两个只读能力。

- 能力目录.搜索能力（关键词/限制 → 能力记录列表）
- 能力目录.读取能力（能力id → 单条完整契约）

两个能力都只读对方的公开声明（包声明/参数契约/能力定义/权限契约/资源预算/
验证历史），不加载任何能力实现、不 import 支持库/提供者/第三方；
数据边界与旧两道检索实现同口径：支持库.适配层.* 与 内部层 包不对外暴露。
失败一律返回统一结果（成功/值/错误码/错误说明），不向调用方抛异常。
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from 公共契约.基础类型.结果类型 import 结果

来源 = "能力目录"
默认限制 = 5
最大限制 = 100
错误码表 = ("参数不合法", "能力不存在", "文件不存在", "内部错误")


def 定位项目根() -> Path:
    """项目根：从本文件向上找到同时含 支持库 与 模块库 的目录。

    不使用固定长度的 parents[N]（目录迁移会让它失效），找不到时退回
    实现/→包→模块库→项目根 的四级位置。
    """
    起始 = Path(__file__).resolve()
    for 祖先 in 起始.parents:
        if (祖先 / "支持库").is_dir() and (祖先 / "模块库").is_dir():
            return 祖先
    return 起始.parents[3]


def _失败(错误码: str, 说明: str) -> 结果:
    return 结果.失败(错误码, 说明, 来源=来源)


def _收敛限制(限制: Any) -> int | None:
    """限制：缺省用默认值；非整数或布尔 → None（参数不合法）；超界按边界收敛。"""
    if 限制 is None:
        return 默认限制
    if isinstance(限制, bool) or not isinstance(限制, int):
        return None
    return max(1, min(限制, 最大限制))


def _索引(项目根: Path) -> tuple[list[dict], 结果 | None]:
    """构建只读能力索引；返回 (记录列表, 失败结果或 None)。

    数据根缺失或索引为空时给出明确失败（绝不返回空列表冒充「平台没有能力」）；
    失败时记录列表为空列表，由调用方按 失败 结果返回。
    """
    from 模块库.能力目录.实现.能力索引 import 定位数据根, 构建能力索引

    if not 定位数据根(项目根):
        return [], _失败("文件不存在",
                        f"项目根 {项目根.as_posix()} 下缺少 支持库/模块库 目录，无法检索能力")
    记录表, 问题列表 = 构建能力索引(项目根)
    if not 记录表:
        return [], _失败("内部错误",
                        "能力索引为空：包声明可读但未解析到任何公开能力"
                        + (f"；扫描问题: {'; '.join(问题列表[:3])}" if 问题列表 else ""))
    return 记录表, None


def 搜索能力(关键词: str = "", 限制: int = 默认限制) -> 结果:
    """按关键词只读检索公开能力，返回 14 字段（可覆盖旧两道实现的键名）记录列表。

    关键词空字符串表示不过滤；大小写不敏感，命中任一字段即算匹配
    （与 能力搜索器.搜索公开能力、公开能力.搜索公开能力 同为整条记录子串匹配）。
    """
    if 关键词 is None:
        关键词 = ""
    if not isinstance(关键词, str):
        return _失败("参数不合法", f"关键词 必须是文本，收到 {type(关键词).__name__}")
    条数上限 = _收敛限制(限制)
    if 条数上限 is None:
        return _失败("参数不合法", f"限制 必须是整数，收到 {限制!r}")
    项目根 = 定位项目根()
    记录表, 错误 = _索引(项目根)
    if 错误 is not None:
        return 错误
    模式 = 关键词.strip().lower()
    命中表 = [记录 for 记录 in 记录表
             if not 模式 or 模式 in json.dumps(记录, ensure_ascii=False).lower()]
    当页 = 命中表[:条数上限]
    return 结果.成功结果({
        "关键词": 关键词,
        "限制": 条数上限,
        "总数": len(命中表),
        "返回数": len(当页),
        "是否截断": len(命中表) > len(当页),
        "能力列表": 当页,
        "项目根": 项目根.as_posix(),
    })


def 读取能力(能力id: str) -> 结果:
    """按能力id只读读取单条完整契约（参数/必填/默认值/返回/错误码/调用示例等）。"""
    if not isinstance(能力id, str) or not 能力id.strip():
        return _失败("参数不合法", f"能力id 必须是非空文本，收到 {能力id!r}")
    项目根 = 定位项目根()
    记录表, 错误 = _索引(项目根)
    if 错误 is not None:
        return 错误
    目标 = 能力id.strip()
    for 记录 in 记录表:
        if 记录["能力id"] == 目标:
            return 结果.成功结果(记录)
    return _失败("能力不存在",
               f"公开能力不存在: {目标}（可先用 能力目录.搜索能力 按关键词定位）")
