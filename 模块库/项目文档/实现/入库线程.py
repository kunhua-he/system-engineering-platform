"""项目文档 模块 · 入库后台线程（进程内实现，不对外暴露）。

口径（华哥明确要求「后台单独拉一个线程去处理入库」）：

- **有界**：非守护线程、单次执行、硬超时（默认 30 秒），完成即退出；
  不做常驻线程池、不用跨调用存活的队列。
- **不阻塞落盘**：`写文档` 的文件已落盘即返回成功，入库在后台上做；
  线程内异常**只记录不抛给调用方**，并登记待补入库清单。
- **文件是权威、索引是派生**：入库失败不回滚文件（索引丢了可从文件重建）。
- **待补清单落运行库（运行态一律入库）**：失败记录写底座运行库 `作业` 域，
  不再落临时目录下的 jsonl 文件。

为什么把待补清单从「临时目录 jsonl 文件」改成「运行库 `作业` 域」（本次修复）：

1. **口径**。华哥 2026-09-15 定盘「**运行态一律入库**，库文件统一
   `工程缓存/运行数据/`」（唯一解析器 `公共契约/运行时/运行缓存.py::解析运行数据根`）。
   原实现落在 `<系统临时目录>/项目文档入库/项目文档待补入库.jsonl` ——
   临时目录**随系统清理**，待补记录会静默消失，重建索引时无从补做；
   而入库失败本身正是最该留痕的运行态。
2. **合规**。原实现直连 `tempfile.gettempdir()` / `os.makedirs` / `open` / `os.remove`，
   等于把 `文件系统支持库` 的原子实现又抄了一份，违反本包门面
   `模块库/项目文档/实现/调用.py` 写死的一句话：「**本模块 0 直连第三方、
   0 直接文件 IO、0 直接 os 调用**」。现在本文件**唯一**的出入口是本包门面
   `调用(能力id, 参数)`（哲学第 7 条 4 项：统一调用接口铁律）。

**线程模型与能力调用不冲突（故不需要回退到本地文件方案）**：能力调用器是
进程内**全局注入**的，后台线程里直接可取用；且门面 `调用` 在未装配时
**如实返回失败结果、不抛**，故「登记待补」在无调用器的进程里也只是如实
不写入，不会把异常泄漏进后台线程。原方案要落临时文件的原因只是
「不想碰项目目录」，与「能力调用器需装配上下文」无关。

`作业` 域字段（`支持库/后端/数据库连接支持库/SQLite数据库/实现/提供者.py::运行库表定义`）：
`作业id / 工具 / 开工id / 错误码 / 错误说明 / 开始时间 / 完成时间 / 取消标记 / 结果已截断`；
项目名、文档相对路径等附加事实随 `写入运行态` 的 `载荷` 完整保留，读回时逐字还原。
"""

from __future__ import annotations

import threading
from pathlib import Path
from typing import Any, Callable

from 公共契约.运行时.运行缓存 import 解析运行数据根
from 模块库.项目文档.实现.调用 import 调用, 取值, 文本
from 公共契约.基础类型.逻辑类型 import 真, 假

# 待补入库清单 = 运行库 `作业` 域里「工具 = 本值」且「状态 = 待补」的行。
作业域 = "作业"
作业工具名 = "项目文档入库"
待补状态 = "待补"
已补状态 = "已补做"
幂等前缀 = "doc-pending"
入库超时秒 = 30
默认查询限制 = 200
最大查询限制 = 1000
运行库环境变量 = "系统库运行库"
运行库文件名 = "底座运行.db"

SQLite = "数据库连接支持库.SQLite数据库"


def 项目根() -> Path:
    """本包所在系统根：`<系统根>/模块库/项目文档/实现/入库线程.py` 上溯三级。"""
    return Path(__file__).resolve().parents[3]


def 运行库路径() -> str:
    """底座运行库路径：环境变量 `系统库运行库` 优先，否则经唯一解析器落运行数据根。

    与 `平台控制面/能力反馈/开工id校验.py::默认运行库路径` 同口径（运行态唯一落点）。
    环境变量也**不直读 `os.environ`**（门面口径：0 直接 os 调用），走
    `系统核心支持库.环境变量.获取环境变量`；该能力不可用时回落唯一解析器的默认路径，
    不拿假路径蒙（读不到环境变量 ≠ 没有运行库）。
    """
    环境结果 = 调用(
        "系统核心支持库.环境变量.获取环境变量",
        {"名称": 运行库环境变量, "包含敏感值": 真},
    )
    if 环境结果.成功:
        值 = 取值(环境结果)
        if 值.get("存在") and 文本(值.get("值")):
            return 文本(值.get("值"))
    return str(解析运行数据根(项目根()) / 运行库文件名)


def _现在() -> str:
    """当前时间文本（含时区偏移）：经唯一能力取，不直连 `time`/`datetime`。"""
    结果对象 = 调用("数据操作支持库.时间日期.获取当前时间", {"时区": "Asia/Shanghai"})
    if not 结果对象.成功:
        return ""
    值 = 结果对象.值
    return 文本(值) if isinstance(值, (str, int, float)) else ""


def _收敛限制(限制: Any) -> int:
    """返回条数收敛到 1..`最大查询限制`；非整数（含布尔）回落默认值。"""
    if isinstance(限制, bool) or not isinstance(限制, int):
        return 默认查询限制
    return max(1, min(限制, 最大查询限制))


def _作业记录(记录: dict[str, Any], 失败原因: str, 开始时间: str) -> dict[str, Any]:
    """把一条入库失败事实装配成 `作业` 域记录（含 `写入运行态` 要求的非空 id）。

    幂等 id = `幂等消息.生成id(会话id=项目名|文档相对路径, 内容=失败原因)`：
    同一份文档的同一个失败原因重复登记，落到同一 id 上（upsert 更新），
    清单不堆重复行；失败原因变了则换 id，如实留新痕迹（不覆盖成「一种失败」）。
    """
    项目名 = 文本(记录.get("项目名"))
    文档相对路径 = 文本(记录.get("文档相对路径"))
    id结果 = 调用(
        "系统核心支持库.幂等消息.生成id",
        {"会话id": f"{项目名}|{文档相对路径}" or 作业工具名,
         "内容": 失败原因 or 作业工具名, "前缀": 幂等前缀},
    )
    if not id结果.成功:
        return {}
    作业id = 文本(取值(id结果).get("幂等id"))
    if not 作业id:
        return {}
    return {
        "id": 作业id,
        "作业id": 作业id,
        "工具": 作业工具名,
        "开工id": 文本(记录.get("开工id")),
        "错误码": 文本(记录.get("错误码")) or "索引库不可用",
        "错误说明": 失败原因,
        "开始时间": 开始时间,
        "完成时间": _现在(),
        "状态": 待补状态,
        # 以下为附加事实：`写入运行态` 把整条记录写进 `载荷`，读回时可逐字还原。
        "项目名": 项目名,
        "文档相对路径": 文档相对路径,
        "库文件": 文本(记录.get("库文件")),
        # 与原 jsonl 清单的字段名逐字兼容：`失败原因` 是清单读回侧的历史字段名。
        "失败原因": 失败原因,
    }


def 登记待补(记录: dict[str, Any]) -> bool:
    """把一条入库失败记录写进运行库待补清单；写清单本身失败也不抛（不反向影响主流程）。

    返回：真=已入库（可被 `读待补清单` 读回）；假=未入库。调用方按需要处置，
    **不把「没写进去」改判成「写进去了」**（静默丢是这条链路最危险的行为）。
    """
    失败原因 = 文本(记录.get("失败原因"))
    装配 = _作业记录(记录, 失败原因, 文本(记录.get("开始时间")) or _现在())
    if not 装配:
        return 假
    写入结果 = 调用(
        f"{SQLite}.写入运行态",
        {"数据库路径": 运行库路径(), "域": 作业域, "记录": 装配},
    )
    if not 写入结果.成功:
        return 假
    return bool(取值(写入结果).get("已写入"))


def _行转记录(行: dict[str, Any]) -> dict[str, Any]:
    """运行库行 → 待补记录：`载荷` 是写入时的完整原始记录，反序列化后合并回顶层。

    列上有的字段以列为准（列是索引出来的高频字段，与载荷同源）；载荷解不出时
    退回纯列记录，**不假装字段存在**（缺字段由调用方按缺值处理）。
    """
    记录: dict[str, Any] = {}
    载荷 = 文本(行.get("载荷"))
    if 载荷:
        解析 = 调用("数据操作支持库.数据交换.反序列化JSON", {"文本": 载荷})
        if 解析.成功 and isinstance(解析.值, dict):
            记录 = dict(解析.值)
    for 字段 in ("作业id", "状态", "错误码", "错误说明", "开始时间", "完成时间"):
        值 = 行.get(字段)
        if 值 is not None and 值 != "":
            记录[字段] = 值
    return 记录


def 读待补清单(限制: Any = 默认查询限制) -> list[dict[str, Any]]:
    """读待补清单：查运行库 `作业` 域 `工具=项目文档入库` + `状态=待补`。

    返回记录与原 jsonl 清单的字段逐字同义（项目名/文档相对路径/库文件/失败原因
    都从 `载荷` 还原），供重建索引时补做。运行库读不到时返回空列表（调用方以
    `登记待补` 的返回值判断写入侧是否可用，不用「空清单」冒充「没有待补」）。
    """
    结果对象 = 调用(
        f"{SQLite}.查询运行态",
        {"数据库路径": 运行库路径(), "域": 作业域,
         "条件": {"工具": 作业工具名, "状态": 待补状态},
         "限制": _收敛限制(限制)},
    )
    if not 结果对象.成功:
        return []
    行列表 = 取值(结果对象).get("行列表") or []
    return [_行转记录(行) for 行 in 行列表 if isinstance(行, dict)]


def 清空待补清单() -> int:
    """把待补记录收口为「已补做」（**软清空**，不物理删），返回成功收口的条数。

    为什么软清空：①「运行态一律入库」的口径下，清单是库里的行，改 `状态` 即从
    待补清单消失；② 底座未提供「按域删除运行态」的原子能力，拼 SQL 删除等于在本
    文件里再实现一遍存储动作（且会连失败证据一起毁掉，事后无从追溯补做过什么）。
    """
    条数 = 0
    for 记录 in 读待补清单():
        作业id = 文本(记录.get("作业id") or 记录.get("id"))
        if not 作业id:
            continue
        记录["id"] = 作业id
        记录["作业id"] = 作业id
        记录["工具"] = 作业工具名
        记录["状态"] = 已补状态
        写入结果 = 调用(
            f"{SQLite}.写入运行态",
            {"数据库路径": 运行库路径(), "域": 作业域, "记录": 记录},
        )
        if 写入结果.成功 and 取值(写入结果).get("已写入"):
            条数 += 1
    return 条数


def 起入库线程(任务: Callable[[], Any], 记录: dict[str, Any]) -> dict[str, Any]:
    """起一个**非守护、单次执行、带硬超时**的入库线程，立刻返回受理信息。

    `任务` 内部异常与超时都只登记进待补清单，**不向调用方抛**——
    调用方此时已拿到落盘成功的文件，不该因为派生数据失败被判失败。
    """
    异常盒: list[str] = []
    开始时间 = _现在()

    def 包一层() -> None:
        try:
            任务()
        except BaseException as 错误:  # noqa: BLE001 — 后台线程不向外抛，全部落待补
            异常盒.append(f"{type(错误).__name__}: {错误}")
            登记待补({**记录, "失败原因": 异常盒[-1], "开始时间": 开始时间})

    线程 = threading.Thread(target=包一层, name="项目文档入库", daemon=False)
    线程.start()
    线程.join(入库超时秒)
    if 线程.is_alive():
        登记待补({**记录, "失败原因": f"入库超时（>{入库超时秒} 秒）", "开始时间": 开始时间})
        return {"已受理": 真, "是否完成": 假, "说明": f"入库超过 {入库超时秒} 秒，已登记待补"}
    if 异常盒:
        return {"已受理": 真, "是否完成": 假, "说明": f"入库失败已登记待补：{异常盒[0]}"}
    return {"已受理": 真, "是否完成": 真, "说明": "入库完成"}


