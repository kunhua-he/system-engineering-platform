"""项目文档 模块 · 写文档（进程内实现，不对外暴露）。

公开能力二：`项目文档.写文档`（华哥明确要求：**符合规范的就落盘，不符合的单独返回不合规范的方式**）

两段式（见设计说明「文件是权威、索引是派生」）：

1. **校验规范（阻断）**：先按判据文件逐条校验正文；有阻断级条目 → **不落盘**，
   直接把违规范清单返给调用方。判据文件缺失 → 明确失败（无判据的「通过」是假绿）。
2. **落盘（同步、必须成功）**：经 系统核心支持库.资源管理.原子写入 写入 md。
3. **入库（后台线程，失败可重跑）**：起非守护单次线程做切块 + 写索引；
   线程失败只登记待补清单，**不回滚已落盘文件**。

路径安全：目标路径必须落在该项目文档根内（经 系统核心支持库.路径安全.校验路径 判定），
越界返回 路径越界；目标已存在且未声明覆盖时返回 已存在（不静默覆盖别人的文档）。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.结果类型 import 结果
from 模块库.项目文档.实现.调用 import 失败, 取值, 文本, 调用
from 模块库.项目文档.实现.项目边界 import (
    判据文件路径,
    文档根绝对路径,
    目标在根内,
    组合路径,
    目录存在,
    读项目,
    校验资源路径,
)
from 模块库.项目文档.实现.入库线程 import 起入库线程

来源 = "项目文档"
支持库 = "项目文档支持库"


def _校验(正文: str, 判据: str, 是否权威文档: bool) -> 结果:
    """跑规范校验；判据文件缺失或校验能力失败都如实返回（不吞成通过）。"""
    if not 目录存在(判据):
        return 失败("判据文件不存在", f"规范判据文件不存在，无法校验: {判据}")
    return 调用(
        f"{支持库}.校验规范",
        {"正文": 正文, "判据文件": 判据, "是否权威文档": bool(是否权威文档)},
    )


def _违规范说明(条目列表: list) -> str:
    """把违规范条目压成一句可读说明（调用方一眼知道违反的是哪几条）。"""
    片段 = []
    for 条目 in 条目列表[:8]:
        if isinstance(条目, dict):
            片段.append(f"{条目.get('判据id', '')}@{条目.get('行号', 0)}")
    return "；".join(片段) + ("…" if len(条目列表) > 8 else "")


def _入库(项目名: str, 文档相对路径: str, 正文: str, 库文件: str, 修改时间: float) -> dict[str, Any]:
    """入库任务体：切块 → 写索引（在后台线程里跑，失败只登记待补）。"""
    切块结果 = 调用(f"{支持库}.切块", {"正文": 正文})
    if not 切块结果.成功:
        raise RuntimeError(f"切块失败：{切块结果.错误码} {切块结果.错误说明}")
    写入结果 = 调用(
        f"{支持库}.写入索引",
        {"项目名": 项目名, "文档相对路径": 文档相对路径,
         "块列表": 取值(切块结果).get("块列表") or [],
         "文件修改时间": 修改时间, "库文件": 库文件},
    )
    if not 写入结果.成功:
        raise RuntimeError(f"写入索引失败：{写入结果.错误码} {写入结果.错误说明}")
    return 取值(写入结果)


def 写文档(项目名: str = None, 文档相对路径: str = None, 正文: str = None,
          判据文件: str = "", 是否权威文档: bool = False, 覆盖: bool = False,
          库文件: str = None, 等待入库完成: bool = False) -> 结果:
    """按规范校验正文，合规才落盘成 md 并后台入库；不合规**不落盘**并返回违规范清单。

    参数：项目名 / 文档相对路径（相对文档根）/ 正文 / 判据文件（留空按约定推导）/
         是否权威文档 / 覆盖（真=允许覆盖已存在文件）/ 库文件 / 等待入库完成
    返回：``{文档绝对路径, 文档相对路径, 项目名, 入库}``
    """
    名称 = 文本(项目名)
    相对 = 文本(文档相对路径).strip("/")
    文 = 正文 if isinstance(正文, str) else ""
    if not 名称:
        return 失败("参数不合法", "项目名必须是非空文本")
    if not 相对:
        return 失败("参数不合法", "文档相对路径必须是非空文本")
    if not 文.strip():
        return 失败("参数不合法", "正文必须是非空文本")

    档案结果 = 读项目(名称, 库文件)
    if not 档案结果.成功:
        return 档案结果
    档案 = 取值(档案结果)
    文档根 = 文档根绝对路径(档案)
    if not 目录存在(文档根):
        return 失败("目录不存在", f"文档根不存在: {文档根}")

    安全 = 校验资源路径(文档根, 相对)
    if not 安全.成功:
        return 安全
    目标 = 取值(安全).get("绝对路径") or 组合路径(文档根, 相对)
    # 双保险：无论上游判定怎么写，落盘前自己再核一次目标确实在文档根内。
    if not 目标在根内(文档根, 目标):
        return 失败("路径越界", f"落盘目标越出文档根: {目标}")

    if 目录存在(目标) and not 覆盖:
        return 失败("已存在", f"目标文件已存在，未声明覆盖: {目标}")

    判据 = 判据文件路径(档案, 判据文件)
    校验结果 = _校验(文, 判据, bool(是否权威文档))
    if not 校验结果.成功:
        return 校验结果
    校验值 = 取值(校验结果)
    if not 校验值.get("通过"):
        条目 = 校验值.get("违规范条目") or []
        return 结果.失败(
            "参数不合法",
            f"正文不符合文档规范，已拒绝落盘（违反：{_违规范说明(条目)}）",
            来源=来源,
            详情={"违规范条目": 条目, "驳回项数": 校验值.get("驳回项数", 0),
                      "唯一真源": 校验值.get("唯一真源", ""), "是否落盘": False},
        )

    写入结果 = 调用(
        "系统核心支持库.资源管理.原子写入",
        {"目标路径": 目标, "内容": 文},
    )
    if not 写入结果.成功:
        return 写入结果
    if not 目录存在(目标):
        return 失败("内部错误", f"原子写入返回成功但目标不存在: {目标}")

    记录 = {"项目名": 名称, "文档相对路径": 相对, "库文件": 库文件 or ""}
    入库任务 = lambda: _入库(名称, 相对, 文, 库文件, 0.0)  # noqa: E731
    if 等待入库完成:
        try:
            入库任务()
            入库 = {"已受理": True, "是否完成": True, "说明": "入库完成（同步）"}
        except BaseException as 错误:  # noqa: BLE001 — 入库失败不回滚文件，如实回报
            入库 = {"已受理": True, "是否完成": False, "说明": f"入库失败：{错误}"}
    else:
        入库 = 起入库线程(入库任务, 记录)

    return 结果.成功结果({
        "项目名": 名称, "文档相对路径": 相对, "文档绝对路径": 目标,
        "判据文件": 判据, "入库": 入库,
    })
