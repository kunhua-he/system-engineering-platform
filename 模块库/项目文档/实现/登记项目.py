"""项目文档 模块 · 写文档（登记项目）（进程内实现，不对外暴露）。

公开能力一：`项目文档.登记项目`
    校验项目根与文档根真实存在 → 规范文件就位 → 写登记表（幂等：同项目名覆盖更新）。

**边界校验在模块层**：支持库的 `登记项目` 是纯存储动作、不校验目录存在性，
所以「这个项目能不能用」在这里判死：项目根不存在、文档根不存在、规范文件缺失，
一律明确失败，不把不合法的项目写进登记表（写进去会让后续查文档全查空）。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.结果类型 import 结果
from 模块库.项目文档.实现.调用 import 失败, 取值, 文本, 调用
from 模块库.项目文档.实现.项目边界 import (
    判据文件相对文档根,
    判据文件路径,
    文档根绝对路径,
    组合路径,
    目录存在,
    读项目,
)
from 公共契约.运行时.平台适配 import 解析路径

来源 = "项目文档"


def 登记项目(项目名: str = None, 项目根目录: str = None, 文档根相对路径: str = "开发文档",
            规范文件: str = "", 库文件: str = None, 开工ID: str | None = None) -> 结果:
    """登记一个项目：校验真实存在后写入登记表（同项目名覆盖更新，幂等）。

    参数：项目名 / 项目根目录（绝对路径）/ 文档根相对路径 / 规范文件 / 库文件
    返回：``{项目名, 项目根目录, 文档根相对路径, 规范文件, 是否新增}``
    """
    名称 = 文本(项目名)
    根 = 文本(项目根目录).rstrip("/")
    文档根相对 = 文本(文档根相对路径) or "开发文档"
    规范 = 文本(规范文件)
    if not 名称:
        return 失败("参数不合法", "项目名必须是非空文本")
    if not 根:
        return 失败("参数不合法", "项目根目录必须是非空绝对路径")
    if not 根.startswith("/"):
        return 失败("参数不合法", f"项目根目录必须是绝对路径: {根}")
    if not 目录存在(根):
        return 失败("目录不存在", f"项目根目录不存在: {根}")
    文档根 = 组合路径(根, 文档根相对)
    if not 目录存在(文档根):
        return 失败("目录不存在", f"文档根不存在: {文档根}")

    # 规范文件与判据文件就位检查：缺判据＝后续校验无法执行，登记时就要拦住。
    # 给了 规范 就用 规范 本身（登记时登记的判据路径，相对项目根，经唯一解析腿拼绝对）；
    # 没给才回落到 <文档根>/规范/… 的约定。旧写法在「给了 规范」时仍按 文档根 推导，
    # 登记了真实判据路径却报「判据未就位」—— 债务清单 147 就是这个口径不一致。
    判据 = (str(解析路径(规范, 根)) if 规范
            else str(解析路径(组合路径(文档根, 判据文件相对文档根), 根)))
    判据存在 = 目录存在(判据)
    临时档案 = {"项目根目录": 根, "文档根相对路径": 文档根相对}

    写入结果 = 调用(
        "项目文档支持库.登记项目",
        {"项目名": 名称, "项目根目录": 根, "文档根相对路径": 文档根相对,
         "规范文件": 规范, "库文件": 库文件},
    )
    if not 写入结果.成功:
        return 写入结果
    值 = 取值(写入结果)
    return 结果.成功结果({
        "项目名": 值.get("项目名", 名称),
        "项目根目录": 值.get("项目根目录", 根),
        "文档根相对路径": 值.get("文档根相对路径", 文档根相对),
        "规范文件": 值.get("规范文件", 规范),
        "是否新增": bool(值.get("是否新增")),
        "文档根绝对路径": 文档根,
        "判据文件": 判据,
        "判据文件就位": 判据存在,
    })


def 查项目或拒(项目名: str, 库文件: str = None) -> 结果:
    """按项目名取档案；未登记即明确失败（供其它能力复用，避免各写一遍）。"""
    名称 = 文本(项目名)
    if not 名称:
        return 失败("参数不合法", "项目名必须是非空文本")
    return 读项目(名称, 库文件)
