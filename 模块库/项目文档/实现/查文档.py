"""项目文档 模块 · 查文档 与 查记忆（进程内实现，不对外暴露）。

公开能力三：`项目文档.查文档` —— 按项目 + 关键词快查索引，返回可回溯的
「文件路径 + 行号 + 片段」；索引空或未命中时**回退到真实搜索**（不返回假空）。

公开能力四：`项目文档.查记忆` —— 委托 `记忆支持库.搜索记忆`（带项目过滤），
**不重造记忆能力**（记忆支持库已有 9 个能力且带项目维度，重造＝第二事实源）。
按华哥口径默认 仅关键词=真：结构化查询不付 LLM 代价。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.结果类型 import 结果
from 模块库.项目文档.实现.调用 import 失败, 取值, 文本, 调用
from 模块库.项目文档.实现.项目边界 import 文档根绝对路径, 目录存在, 读项目
from 公共契约.基础类型.逻辑类型 import 真, 假

来源 = "项目文档"
支持库 = "项目文档支持库"


def _回溯核对(文档根: str, 命中列表: list) -> list:
    """给每条命中补 可回溯 标记：索引记录的文件必须真实存在，否则剔除（不返回假命中）。"""
    保留 = []
    for 命中 in 命中列表:
        if not isinstance(命中, dict):
            continue
        路径 = 文本(命中.get("文档相对路径"))
        绝对 = f"{文档根.rstrip('/')}/{路径}" if 路径 else ""
        可回溯 = bool(绝对) and 目录存在(绝对)
        条目 = {**命中, "文档绝对路径": 绝对, "可回溯": 可回溯}
        保留.append(条目)
    return 保留


def 查文档(项目名: str = None, 关键词: str = None, 返回条数: int = 20,
          库文件: str = None) -> 结果:
    """按项目 + 关键词查文档索引，返回文件路径/行号/片段（每条带可回溯标记）。

    参数：项目名 / 关键词（空白分隔多词，全命中优先）/ 返回条数 / 库文件
    返回：``{项目名, 关键词, 命中列表, 命中数, 是否截断, 数据来源, 文档根绝对路径}``
    """
    名称 = 文本(项目名)
    词 = 文本(关键词)
    if not 名称:
        return 失败("参数不合法", "项目名必须是非空文本")
    if not 词:
        return 失败("参数不合法", "关键词必须是非空文本")

    档案结果 = 读项目(名称, 库文件)
    if not 档案结果.成功:
        return 档案结果
    档案 = 取值(档案结果)
    文档根 = 文档根绝对路径(档案)

    查询结果 = 调用(
        f"{支持库}.查询索引",
        {"项目名": 名称, "关键词": 词, "返回条数": max(1, int(返回条数 or 20)),
         "库文件": 库文件},
    )
    if not 查询结果.成功:
        return 查询结果
    查询值 = 取值(查询结果)
    命中列表 = _回溯核对(文档根, 查询值.get("命中列表") or [])
    if 命中列表:
        return 结果.成功结果({
            "项目名": 名称, "关键词": 词, "命中列表": 命中列表,
            "命中数": len(命中列表), "是否截断": bool(查询值.get("是否截断")),
            "数据来源": "索引", "文档根绝对路径": 文档根,
        })

    # 索引没命中：回退到真实搜索（扫文档根内的 md 正文），不返回假空。
    回退结果 = 调用(
        "文件系统支持库.内容检索.正则搜索",
        {"根目录": 文档根, "模式": 词.split()[0], "文件模式": "*.md",
         "最大匹配数": max(1, int(返回条数 or 20)), "忽略大小写": 真},
    )
    if not 回退结果.成功:
        # 回退也失败时如实返回「索引未命中 + 回退不可用」，不伪装成「查无此项」。
        return 结果.成功结果({
            "项目名": 名称, "关键词": 词, "命中列表": [], "命中数": 0,
            "是否截断": 假, "数据来源": "索引与回退均无结果",
            "文档根绝对路径": 文档根,
            "回退说明": f"{回退结果.错误码} {回退结果.错误说明}",
        })
    匹配列表 = 取值(回退结果).get("匹配列表") or []
    条目列表 = [
        {"文档相对路径": _相对化(文档根, 文本(项.get("文件"))),
         "文档绝对路径": 文本(项.get("文件")), "起始行": 项.get("行号"),
         "结束行": 项.get("行号"), "块类型": "回退搜索", "命中词数": 1,
         "命中次数": 1, "片段": 文本(项.get("文本"))[:180],
         "可回溯": 目录存在(文本(项.get("文件")))}
        for 项 in 匹配列表 if isinstance(项, dict)
    ]
    return 结果.成功结果({
        "项目名": 名称, "关键词": 词, "命中列表": 条目列表,
        "命中数": len(条目列表), "是否截断": bool(取值(回退结果).get("已达上限")),
        "数据来源": "回退搜索（索引未命中）", "文档根绝对路径": 文档根,
    })


def _相对化(文档根: str, 绝对路径: str) -> str:
    """把绝对路径转成相对文档根的路径；不在根内时原样返回（不硬裁）。"""
    根 = 文档根.rstrip("/") + "/"
    return 绝对路径[len(根):] if 绝对路径.startswith(根) else 绝对路径


def 查记忆(项目名: str = None, 关键词: str = None, 返回条数: int = 5,
          仅关键词: bool = 真) -> 结果:
    """查该项目的历史记忆：委托 记忆支持库.搜索记忆（带项目过滤），不重造记忆。

    参数：项目名（作为记忆的项目过滤键）/ 关键词 / 返回条数 / 仅关键词（默认真，不调大模型）
    返回：``{项目名, 关键词, 记忆列表, 命中数, 来源}``
    """
    名称 = 文本(项目名)
    词 = 文本(关键词)
    if not 名称:
        return 失败("参数不合法", "项目名必须是非空文本")
    if not 词:
        return 失败("参数不合法", "关键词必须是非空文本")
    结果对象 = 调用(
        "记忆支持库.搜索记忆",
        {"查询": 词, "返回条数": max(1, int(返回条数 or 5)),
         "项目": 名称, "仅关键词": bool(仅关键词)},
    )
    if not 结果对象.成功:
        return 结果对象
    值 = 取值(结果对象)
    for 键 in ("记忆", "记忆列表", "结果列表"):
        if isinstance(值.get(键), list):
            列表 = 值[键]
            break
    else:
        列表 = []
    return 结果.成功结果({
        "项目名": 名称, "关键词": 词, "记忆列表": 列表, "命中数": len(列表),
        "来源": "记忆支持库.搜索记忆",
    })
