"""项目文档 模块 · 唯一调用腿与公共小件（进程内实现，不对外暴露）。

**本模块 0 直连第三方、0 直接文件 IO、0 直接 os 调用**：所有原子动作一律经
`公共契约.能力契约.调用器.获取能力调用器().调用能力(能力id, 参数)` 走统一网关
（哲学第 7 条 4 项：统一调用接口铁律）。本文件只放「所有子能力共用」的两件事：
唯一调用腿、参数归一。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.结果类型 import 结果

来源 = "项目文档"


def 调用(能力id: str, 参数: dict[str, Any]) -> 结果:
    """经唯一能力调用服务调用支持库能力；未装配时如实返回失败（不静默降级）。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器

    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源)
    except RuntimeError as 错误:
        return 结果.失败("提供者不可用", str(错误), 来源=来源)


def 文本(值: Any) -> str:
    """归一为非空文本：None 与纯空白一律给空串，由调用方按必填判定拒绝。"""
    return str(值 if 值 is not None else "").strip()


def 取值(结果对象: 结果) -> dict[str, Any]:
    """取统一结果里的 值；非字典型一律给空字典（不把意外形状泄漏给上层）。"""
    值 = 结果对象.值
    return 值 if isinstance(值, dict) else {}


def 失败(错误码: str, 错误说明: str) -> 结果:
    """本模块的失败构造捷径（错误码一律用网关已登记中文码）。"""
    return 结果.失败(错误码, 错误说明, 来源=来源)
