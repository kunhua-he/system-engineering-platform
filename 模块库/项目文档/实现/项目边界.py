"""项目文档 模块 · 项目边界解析（进程内实现，不对外暴露）。

模块层与支持库层的分工：**边界校验是模块层的活**。
支持库的 `登记项目` 是纯存储动作、不校验目录存在性；本文件负责把「这个项目到底
能不能用」判清楚：项目根在不在、文档根在不在、登记表里有没有它、判据文件在哪。

判据文件推导规则（唯一权威）：登记时未给判据文件 → 按
`<项目根>/<文档根>/规范/Markdown 文档体例判据.json` 推导；该文件不存在即明确失败，
**不静默跳过规范校验**（跳过校验＝放不合规文档落盘，比报错危险得多）。
"""

from __future__ import annotations

import posixpath
from typing import Any

from 公共契约.基础类型.结果类型 import 结果
from 模块库.项目文档.实现.调用 import 失败, 取值, 文本, 调用

支持库包 = "项目文档支持库"
判据文件相对文档根 = "规范/Markdown 文档体例判据.json"


def 目录存在(路径: str) -> bool:
    """经 文件系统支持库.文件操作.判断存在 判定路径存在（本模块不自算文件系统事实）。"""
    结果对象 = 调用("文件系统支持库.文件操作.判断存在", {"文件路径": 路径})
    if not 结果对象.成功:
        return False
    值 = 结果对象.值
    if isinstance(值, dict):
        return bool(值.get("存在"))
    return bool(值)


def 读项目(项目名: str, 库文件: str = None) -> 结果:
    """查登记表拿项目档案；未登记或档案字段缺失一律明确失败（不猜默认值）。"""
    结果对象 = 调用(f"{支持库包}.查询项目", {"项目名": 项目名, "库文件": 库文件})
    if not 结果对象.成功:
        return 结果对象
    项目表 = 取值(结果对象).get("项目表") or []
    if not 项目表:
        return 失败("项目未登记", f"项目未登记，请先调用 项目文档.登记项目: {项目名}")
    档案 = 项目表[0]
    if not 文本(档案.get("项目根目录")):
        return 失败("项目未登记", f"登记档案缺少项目根目录: {项目名}")
    return 结果.成功结果(档案)


def 组合路径(*段: str) -> str:
    """拼接绝对路径：只做「去尾斜杠拼接」，不做文件系统判定（判定交给支持库能力）。"""
    干净段 = [文本(段[0]).rstrip("/")] + [文本(x).strip("/") for x in 段[1:]]
    return "/".join(x for x in 干净段 if x != "")


def 文档根绝对路径(档案: dict[str, Any]) -> str:
    """项目档案 → 文档根绝对路径（文档根相对路径留空时按约定取 开发文档）。"""
    文档根 = 文本(档案.get("文档根相对路径")) or "开发文档"
    return 组合路径(文本(档案.get("项目根目录")), 文档根)


def 判据文件路径(档案: dict[str, Any], 判据文件: str = "") -> str:
    """解析判据文件绝对路径：调用方给值优先，否则按唯一约定推导。"""
    给定 = 文本(判据文件)
    if 给定:
        return 给定
    return 组合路径(文档根绝对路径(档案), 判据文件相对文档根)


def 目标在根内(根目录: str, 目标: str) -> bool:
    """落盘前自核：目标必须落在根内（等于根或在根下一层以上）。

    **这是越界写的最后一道闸**：不依赖上游路径安全能力的判定写法。两条硬要求：

    1. **先做 POSIX 路径归一化**，否则 `/根/../逃逸.md` 这种串在纯前缀比较下会被放行
       （2026-09-17 单测实测：不归一化时该串被判为「在根内」）。
    2. **按「根 + 斜杠」比较**，否则 `/a/根备份/x` 这种同前缀兄弟目录会被误判成根内。

    路径一律按 POSIX 语义算（用 posixpath，不随宿主平台变），因为调用方给的是绝对
    POSIX 路径，平台差异不该在这里出现。
    """
    根 = posixpath.normpath(文本(根目录).rstrip("/")) if 文本(根目录).strip() else ""
    路径 = posixpath.normpath(文本(目标)) if 文本(目标).strip() else ""
    if not 根 or not 路径 or not 根.startswith("/") or not 路径.startswith("/"):
        return False
    return 路径 == 根 or 路径.startswith(根 + "/")


def 校验资源路径(根目录: str, 相对路径: str) -> 结果:
    """经 系统核心支持库.路径安全.校验路径 校验相对路径不逃逸出根（含符号链接逃逸）。

    **口径提醒（踩坑记录）**：该能力的拒绝表达是「成功结果 + 值.通过=假」，
    不是失败结果。调用方**必须**读 `值.通过`，只看 结果.成功 会把拒绝读成允许
    （2026-09-17 实测：造成越界写到文档根之外）。本函数把口径归一成
    「拒绝即失败结果」返回，调用方只需判 成功 与 错误码。
    """
    结果对象 = 调用(
        "系统核心支持库.路径安全.校验路径",
        {"根目录": 根目录, "相对路径": 相对路径},
    )
    if not 结果对象.成功:
        return 结果对象
    值 = 取值(结果对象)
    if not 值.get("通过"):
        return 失败("路径越界", f"路径未通过安全校验: {相对路径}（{文本(值.get('原因'))}）")
    return 结果.成功结果({"绝对路径": 文本(值.get("绝对路径")), "原因": 文本(值.get("原因"))})
