"""项目文档 模块 · 文档生成器动作（进程内实现，不对外暴露）。

把平台唯一 md 生成器 `开发工具.MD文档生成` 的四个**此前只能敲命令行**的动作收成公开能力：

| 动作 | 命令行形态 | 本模块公开能力 |
|---|---|---|
| 列类型 | `--列出` | `项目文档.列文档类型` |
| 校验生成区 | `--类型 X --校验` | `项目文档.校验文档生成区` |
| 写盘生成区 | `--类型 X --写盘` | `项目文档.写文档生成区` |
| 人工改正文 | `--人工改 --文件 <目标> --正文文件 <草稿>` | `项目文档.人工改文档` |

## 为什么经 `执行命令` 调生成器，而不在本模块重写一份逻辑

生成器是本仓 md 写入的**唯一腿**（华哥 2026-09-20 口径「全部 md 文件，都需要通过生成器去写」）。
在本模块里另写一份「类型枚举 / 生成区比对 / 印记插入」就是**第二条腿**：两份判据迟早漂移，
而漂移的那一份正好是没被门禁盯住的那份。故本模块只做三件事 —— 参数归一、命令拼装、
退出码与输出收口；跑的还是同一个入口、同一条命令，**行为与命令行逐字一致**。

## 为什么不能直接 import 生成器

`开发工具.MD文档生成` 在 `开发工具` 层；`模块库` 的允许依赖只有 `公共契约`/`支持库`
（`运行核心/依赖防火墙.py::允许依赖表`）。跨层静态导入会被依赖审计判红，故一律经统一网关的
能力调用腿触达 `系统核心支持库.进程管理.执行命令` —— 与本包既有口径（0 直连第三方、
0 直接文件 IO）一致。

## 错误口径（fail-closed，且错误说明自解释）

- 生成器**跑不起来**（超时/危险命令/执行失败）→ 直接透传 `执行命令` 的错误码与说明，不吞；
- 生成器**跑起来了但退出码非 0**（校验不合规、生成区被人工改动、路径不在任何类型判据下…）
  → 返回**成功结果**但 `通过=假`，并把生成器自己的输出行**原样**回带。
  为什么不把这一支做成失败：生成器的输出本就是「一份清单/一份差异」——`校验` 的语义就是
  「报出违规范清单」，把它压成一句错误说明反而丢信息。`通过=假` 已足以让调用方 fail-closed，
  且 `退出码`/`输出行` 里带着「哪一份、哪个生成区、归谁管」的全部原文。
"""

from __future__ import annotations

import re
from typing import Any

from 公共契约.基础类型.逻辑类型 import 假, 真
from 公共契约.基础类型.结果类型 import 结果
from 模块库.项目文档.实现.调用 import 失败, 调用, 取值, 文本

来源 = "项目文档"

#: 生成器模块（`python3.14 -m 开发工具.MD文档生成`）
生成器模块 = "开发工具.MD文档生成"
#: 通用执行腿（本模块唯一的原子动作来源）
执行命令能力 = "系统核心支持库.进程管理.执行命令"
#: 生成器单次调用的默认超时（秒）：债务清单整类重算最慢，实测远低于此值
默认超时秒 = 300.0
#: 首选解释器与兜底解释器（兜底只在首选「找不到」时启用，不做无差别重试）
首选解释器 = "python3.14"
兜底解释器 = "python3"
#: 命令拼装里被拒的路径片段（相对路径不许逃出项目根，fail-closed）
逃逸片段 = ("..",)

#: `--列出` 输出行 → 类型条目（序号 / 类型名 / 现存份数 / 处置）
类型行模式 = re.compile(r"^\s*(\d+)\s+(\S+)\s+现存\s*(\d+)\s*份\s*(.*)$")


def 自举项目根() -> str:
    """从本文件位置向上找含 `开发文档/` 的目录（与生成器自己的 `找项目根` 同判据）。

    找不到返回空串，由调用方按 `参数不合法` 拒绝 —— 不猜、不回落当前工作目录。
    """
    from pathlib import Path

    根 = Path(__file__).resolve()
    while 根.name:
        if (根 / "开发文档").is_dir():
            return str(根)
        根 = 根.parent
    return ""


def _引号化(值: str) -> str:
    """命令文本里的单个参数：含空白时按 posix 规则加单引号。

    `执行命令` 按 `平台适配.拆分命令文本` 直启（不经 shell），含空白的路径不加引号会被拆成
    两个参数。单引号内除单引号自身外全部字面保留，是这里最省心的一种引法。
    """
    文 = str(值)
    if not 文 or not any(字.isspace() for 字 in 文):
        return 文
    return "'" + 文.replace("'", "'\\''") + "'"


def _定项目根(项目根: str) -> tuple[str, 结果 | None]:
    """归一项目根：留空即自举；自举不到返回 fail-closed 失败（可自解释）。"""
    根 = 文本(项目根)
    if not 根:
        根 = 自举项目根()
    if not 根:
        return "", 失败(
            "参数不合法",
            "项目根未给且自举失败：向上找不到含 `开发文档/` 的目录，请显式传 项目根（绝对路径）",
        )
    return 根, None


def _查逃逸(项目根: str, *相对表: str) -> 结果 | None:
    """相对路径不许含 `..`（逃出项目根即拒绝）；越界返回 路径越界，否则返回 None。"""
    for 相对 in 相对表:
        文 = 文本(相对)
        if any(片段 in 文.split("/") for 片段 in 逃逸片段):
            return 失败("路径越界", f"相对路径含 `..`，逃出项目根，拒绝执行: {文}")
    return None


def _命令文本(参数表: list[str], 解释器: str) -> str:
    return " ".join([解释器, "-m", 生成器模块, *[_引号化(项) for 项 in 参数表]])


def _跑生成器(项目根: str, 参数表: list[str]) -> tuple[dict[str, Any], str, str]:
    """经唯一网关跑一次生成器。

    返回 ``(执行值, 命令文本, 错误说明)``：执行值取 `执行命令` 的 `值`（含 退出码/标准输出/
    错误输出）；跑不起来时执行值为空字典且错误说明非空。
    """
    解释器 = 首选解释器
    命令 = _命令文本(参数表, 解释器)
    执行 = 调用(执行命令能力, {"命令": 命令, "超时秒": 默认超时秒, "工作目录": 项目根})
    if 执行.成功:
        return 取值(执行), 命令, ""
    # 首选解释器不存在时用兜底解释器再试一次（只在「找不到可执行文件」这一支生效，
    # 不做无差别重试 —— 重试会掩盖真实失败原因）。
    说明 = f"{执行.错误码} {执行.错误说明}".strip()
    if 解释器 == 首选解释器 and ("not found" in 说明.lower()
                              or "no such file" in 说明.lower()):
        命令 = _命令文本(参数表, 兜底解释器)
        执行 = 调用(执行命令能力, {"命令": 命令, "超时秒": 默认超时秒, "工作目录": 项目根})
        if 执行.成功:
            return 取值(执行), 命令, ""
        说明 = f"{执行.错误码} {执行.错误说明}".strip()
    return {}, 命令, 说明 or "执行命令返回失败且无说明"


def _输出行(执行值: dict[str, Any]) -> list[str]:
    """标准输出按行拆开（去尾空行）；执行值形状不符时如实给空表。"""
    文 = 执行值.get("标准输出")
    if not isinstance(文, str):
        return []
    行表 = 文.splitlines()
    while 行表 and not 行表[-1].strip():
        行表.pop()
    return 行表


def _退出码(执行值: dict[str, Any]) -> int:
    """取生成器退出码；形状不符（没跑起来）一律 -1（绝不冒充 0）。"""
    退出码 = 执行值.get("退出码")
    return int(退出码) if isinstance(退出码, (int, float)) else -1


def _收口(执行值: dict[str, Any], 附加: dict[str, Any]) -> 结果:
    """把一次生成器执行收成统一结果：`通过 = 退出码为 0`，输出行原样回带。"""
    码 = _退出码(执行值)
    return 结果.成功结果({
        **附加,
        "退出码": 码,
        "通过": 码 == 0,
        "输出行": _输出行(执行值),
        "错误输出": 执行值.get("错误输出") if isinstance(执行值.get("错误输出"), str) else "",
    })


def _解析类型行(行表: list[str]) -> list[dict[str, Any]]:
    """从 `--列出` 输出里解析类型条目（解析不到的行忽略；原样输出行另在 输出行 里回带）。"""
    条目: list[dict[str, Any]] = []
    for 行 in 行表:
        命中 = 类型行模式.match(行)
        if not 命中:
            continue
        条目.append({
            "序号": int(命中.group(1)),
            "类型": 命中.group(2),
            "现存份数": int(命中.group(3)),
            "处置": 命中.group(4).strip(),
        })
    return 条目


def _选类型参数(类型名: str, 序号: int) -> tuple[list[str], 结果 | None]:
    """按「类型名 优先、其次 序号」拼出定位参数；两者都没给即 fail-closed。"""
    名 = 文本(类型名)
    if 名:
        return ["--类型", 名], None
    try:
        号 = int(序号) if 序号 is not None else 0
    except (TypeError, ValueError):
        return [], 失败("参数不合法", f"序号 必须是整数（收到 {序号!r}）")
    if 号:
        return ["--序号", str(号)], None
    return [], 失败(
        "参数不合法",
        "必须给 类型名 或 序号（用 项目文档.列文档类型 查已登记的文档类型）",
    )


def 列文档类型(项目根: str = "") -> 结果:
    """列出全部文档类型与处置方式（等价 `--列出`）。

    参数：项目根（留空自举）
    返回：``{项目根, 命令, 退出码, 通过, 类型列表, 类型数, 输出行, 错误输出}``
    """
    根, 错 = _定项目根(项目根)
    if 错 is not None:
        return 错
    执行值, 命令, 问题 = _跑生成器(根, ["--列出"])
    if 问题:
        return 失败("提供者不可用", f"生成器未跑起来（{命令}）：{问题}")
    行表 = _输出行(执行值)
    条目 = _解析类型行(行表)
    return _收口(执行值, {
        "项目根": 根, "命令": 命令,
        "类型列表": 条目, "类型数": len(条目),
    })


def 校验文档生成区(项目根: str = "", 类型名: str = "", 序号: int = 0,
                  文件: str = "") -> 结果:
    """核验某类（或某一份）文档的生成区是否为生成器算出来的那份（等价 `--类型 X --校验`）。

    参数：项目根（留空自举）/ 类型名（优先）/ 序号 / 文件（可选，只核这一份）
    返回：``{项目根, 类型名, 文件, 命令, 退出码, 通过, 输出行, 错误输出}``；
    退出码 0=合规、1=有违规（输出行即违规范清单）、2=拒绝执行（生成区边界缺失等）
    """
    根, 错 = _定项目根(项目根)
    if 错 is not None:
        return 错
    定位, 错 = _选类型参数(类型名, 序号)
    if 错 is not None:
        return 错
    单文件 = 文本(文件)
    错 = _查逃逸(根, 单文件) if 单文件 else None
    if 错 is not None:
        return 错
    参数表 = [*定位, "--校验"]
    if 单文件:
        参数表 += ["--文件", 单文件]
    执行值, 命令, 问题 = _跑生成器(根, 参数表)
    if 问题:
        return 失败("提供者不可用", f"生成器未跑起来（{命令}）：{问题}")
    return _收口(执行值, {
        "项目根": 根, "类型名": 文本(类型名), "文件": 单文件, "命令": 命令,
    })


def 写文档生成区(项目根: str = "", 类型名: str = "", 序号: int = 0,
                文件: str = "", 补头: bool = 假) -> 结果:
    """刷新某类（或某一份）文档的生成区并补机器印记（等价 `--类型 X --写盘`）。

    参数：项目根（留空自举）/ 类型名（优先）/ 序号 / 文件（可选）/ 补头（真=允许给缺元信息头的件补头）
    返回：``{项目根, 类型名, 文件, 命令, 退出码, 通过, 输出行, 错误输出}``
    """
    根, 错 = _定项目根(项目根)
    if 错 is not None:
        return 错
    定位, 错 = _选类型参数(类型名, 序号)
    if 错 is not None:
        return 错
    单文件 = 文本(文件)
    错 = _查逃逸(根, 单文件) if 单文件 else None
    if 错 is not None:
        return 错
    参数表 = [*定位, "--写盘"]
    if 单文件:
        参数表 += ["--文件", 单文件]
    if bool(补头):
        参数表 += ["--补头"]
    执行值, 命令, 问题 = _跑生成器(根, 参数表)
    if 问题:
        return 失败("提供者不可用", f"生成器未跑起来（{命令}）：{问题}")
    return _收口(执行值, {
        "项目根": 根, "类型名": 文本(类型名), "文件": 单文件, "命令": 命令,
    })


def 人工改文档(项目根: str = "", 目标文件: str = "", 草稿文件: str = "",
              写盘: bool = 假) -> 结果:
    """人工改正文的唯一落盘通道（等价 `--人工改 --文件 <目标> --正文文件 <草稿>`）。

    生成器负责「类型判据校验 → 生成区保护 → 加机器印记 → 落盘」四步；缺 `写盘=真` 时
    **只干跑**并报结论。生成区被人工改动时**被拒绝**，输出行里指明该生成区归谁管。

    参数：项目根（留空自举）/ 目标文件（相对项目根）/ 草稿文件（相对项目根或绝对路径）/ 写盘
    返回：``{项目根, 目标文件, 草稿文件, 是否落盘, 命令, 退出码, 通过, 输出行, 错误输出}``
    """
    根, 错 = _定项目根(项目根)
    if 错 is not None:
        return 错
    目标 = 文本(目标文件)
    草稿 = 文本(草稿文件)
    if not 目标:
        return 失败("参数不合法", "目标文件 必须是非空文本（相对项目根的路径，如 开发文档/xxx.md）")
    if not 草稿:
        return 失败("参数不合法", "草稿文件 必须是非空文本（人先写草稿，不直接写目标）")
    错 = _查逃逸(根, 目标, 草稿)
    if 错 is not None:
        return 错
    真写 = bool(写盘)
    参数表 = ["--人工改", "--文件", 目标, "--正文文件", 草稿] + (["--写盘"] if 真写 else [])
    执行值, 命令, 问题 = _跑生成器(根, 参数表)
    if 问题:
        return 失败("提供者不可用", f"生成器未跑起来（{命令}）：{问题}")
    # 是否落盘 = 声明要写 且 生成器退出码为 0（被拒绝时绝不报已落盘）
    return _收口(执行值, {
        "项目根": 根, "目标文件": 目标, "草稿文件": 草稿, "命令": 命令,
        "是否落盘": bool(真写 and _退出码(执行值) == 0),
    })
