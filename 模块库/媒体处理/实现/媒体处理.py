"""媒体处理模块（基础模块）：只经 获取能力调用器().调用能力 组合 FFmpeg 支持库能力。

能力：检查提供者 / 探测媒体 / 提取音频 / 转码 / 抽取帧；
错误码（损坏媒体/无音轨/超长媒体/超时/取消/进程崩溃/提供者不可用/
参数不合法/文件不存在/超出限制）由 唯一能力调用服务 按能力契约透传。
禁止导入支持库/提供者/第三方/运行核心实现；临时媒体由 FFmpeg 支持库自管。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "媒体处理"
默认超时秒 = 60.0
默认最大输出字节 = 200 * 1024 * 1024
默认最大时长秒 = 7200.0
探针默认超时秒 = 30.0


def _调用(能力id: str, 请求参数: dict) -> 结果:
    """经唯一能力调用服务按 能力id 调用支持库能力；未装配时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 请求参数, 调用方=来源)
    except RuntimeError as 错误:
        return 结果.失败("提供者不可用", str(错误), 来源=来源)


def 检查提供者(超时秒: float = 探针默认超时秒) -> 结果:
    """检查 ffmpeg/ffprobe 可用性并返回版本；缺失 → 提供者不可用。

    超时秒 为版本探针超时预留参数（当前版本经支持库默认探针执行）。
    """
    if not isinstance(超时秒, (int, float)) or isinstance(超时秒, bool) or 超时秒 <= 0:
        return 结果.失败("参数不合法", "超时秒 必须为正数", 来源=来源)
    return _调用("FFmpeg媒体.检查提供者", {})


def 探测媒体(文件路径: str, 超时秒: float = 默认超时秒) -> 结果:
    """探测媒体文件：{时长秒, 流, 格式, 大小字节, 比特率}；错误码透传。"""
    return _调用("FFmpeg媒体.探测媒体", {"文件路径": 文件路径, "超时秒": 超时秒})


def 提取音频(
    文件路径: str,
    输出格式: str = "wav",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> 结果:
    """从视频提取首个音频轨（wav/mp3/aac/m4a/ogg/flac），字节经 b64 返回。

    成功值 {字节b64, 格式, 字节数}；无音轨/超长媒体/损坏媒体等错误码透传。
    """
    return _调用("FFmpeg媒体.提取音频", {
        "文件路径": 文件路径, "输出格式": 输出格式, "输出路径": 输出路径,
        "超时秒": 超时秒, "最大输出字节": 最大输出字节, "最大时长秒": 最大时长秒})


def 转码(
    文件路径: str,
    输出格式: str = "mp4",
    编码选项: dict | None = None,
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> 结果:
    """ffmpeg 转码（mp4/mkv/webm/mov/avi），编码选项白名单透传。

    编码选项支持：分辨率/视频码率/音频码率/帧率；
    成功值 {字节b64, 格式, 字节数}；错误码透传。
    """
    return _调用("FFmpeg媒体.转码", {
        "文件路径": 文件路径, "输出格式": 输出格式, "编码选项": 编码选项,
        "输出路径": 输出路径, "超时秒": 超时秒, "最大输出字节": 最大输出字节,
        "最大时长秒": 最大时长秒})


def 抽取帧(
    文件路径: str,
    时间点秒: float,
    输出格式: str = "jpg",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> 结果:
    """ffmpeg 抽帧（jpg/png，时间点秒），字节经 b64 返回。

    成功值 {字节b64, 格式, 宽度, 高度}；错误码透传。
    """
    return _调用("FFmpeg媒体.抽取帧", {
        "文件路径": 文件路径, "时间点秒": 时间点秒, "输出格式": 输出格式,
        "输出路径": 输出路径, "超时秒": 超时秒, "最大输出字节": 最大输出字节,
        "最大时长秒": 最大时长秒})
