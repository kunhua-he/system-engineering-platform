"""媒体处理模块：只经 FFmpeg 支持库公开入口组合，不深入实现目录。

能力：检查提供者 / 探测媒体 / 提取音频 / 转码 / 抽取帧；
错误码（损坏媒体/无音轨/超长媒体/超时/取消/进程崩溃/提供者不可用/
参数不合法/文件不存在/超出限制）原样透传 FFmpeg 提供者。
"""

from __future__ import annotations

from 支持库.适配层.FFmpeg提供者 import (
    检查提供者 as _检查提供者,
    探测媒体 as _探测媒体,
    提取音频 as _提取音频,
    转码 as _转码,
    抽取帧 as _抽取帧,
)

默认超时秒 = 60.0
默认最大输出字节 = 200 * 1024 * 1024
默认最大时长秒 = 7200.0


def 检查提供者() -> dict:
    """检查 ffmpeg/ffprobe 可用性并返回版本；缺失 → 提供者不可用。"""
    return _检查提供者()


def 探测媒体(文件路径: str, 超时秒: float = 默认超时秒) -> dict:
    """探测媒体文件：{时长秒, 流, 格式, 大小字节, 比特率}；错误码透传。"""
    return _探测媒体(文件路径, 超时秒)


def 提取音频(
    文件路径: str,
    输出格式: str = "wav",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> dict:
    """从视频提取首个音频轨（wav/mp3/aac/m4a/ogg/flac），字节经 b64 返回。

    成功值 {字节b64, 格式, 字节数}；无音轨/超长媒体/损坏媒体等错误码透传。
    """
    return _提取音频(文件路径, 输出格式, 输出路径, 超时秒, 最大输出字节, 最大时长秒)


def 转码(
    文件路径: str,
    输出格式: str = "mp4",
    编码选项: dict | None = None,
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> dict:
    """ffmpeg 转码（mp4/mkv/webm/mov/avi），编码选项白名单透传。

    编码选项支持：分辨率/视频码率/音频码率/帧率；
    成功值 {字节b64, 格式, 字节数}；错误码透传。
    """
    return _转码(文件路径, 输出格式, 编码选项, 输出路径, 超时秒, 最大输出字节, 最大时长秒)


def 抽取帧(
    文件路径: str,
    时间点秒: float,
    输出格式: str = "jpg",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> dict:
    """ffmpeg 抽帧（jpg/png，时间点秒），字节经 b64 返回。

    成功值 {字节b64, 格式, 宽度, 高度}；错误码透传。
    """
    return _抽取帧(文件路径, 时间点秒, 输出格式, 输出路径, 超时秒, 最大输出字节, 最大时长秒)
