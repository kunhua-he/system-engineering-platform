"""媒体处理模块（基础模块）：只持能力 id 与契约版本，经 HTTP连接器调用统一网关。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
连接器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。

能力：检查提供者 / 探测媒体 / 提取音频 / 转码 / 抽取帧；
错误码（损坏媒体/无音轨/超长媒体/超时/取消/进程崩溃/提供者不可用/
参数不合法/文件不存在/超出限制）由 统一网关 按能力契约透传。
临时媒体由 FFmpeg 支持库自管。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "媒体处理"
默认超时秒 = 60.0
默认最大输出字节 = 200 * 1024 * 1024
默认最大时长秒 = 7200.0
探针默认超时秒 = 30.0

_连接器 = None


def 设置HTTP连接器(连接器) -> None:
    """由项目适配层装配连接器；主要用于启动装配与隔离测试。"""
    global _连接器
    _连接器 = 连接器


def _获取连接器():
    return _连接器


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经 HTTP 连接器按能力 id 调用统一网关；失败统一转为 结果。"""
    try:
        连接器 = _获取连接器()
        if 连接器 is None:
            return 结果.失败(失败错误码, "HTTP 连接器未装配", 来源=来源)
        # 网关按能力契约对显式参数做严格类型校验；省略 None 等价于
        # 进程内调用时支持库签名默认值（如 输出路径=None → 临时文件）。
        参数 = {键: 值 for 键, 值 in (参数 or {}).items() if 值 is not None}
        响应 = 连接器.调用能力(能力id, 参数)
        if isinstance(响应, 结果):
            return 响应
        if not isinstance(响应, dict):
            return 结果.失败("返回结果不符合契约", "网关返回不是对象", 来源=来源)
        if 响应.get("成功"):
            return 结果.成功结果(响应.get("值"))
        return 结果.失败(响应.get("错误码") or 失败错误码, 响应.get("错误说明") or "网关调用失败", 来源=来源)
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源=来源)
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源=来源)


def 检查提供者(超时秒: float = 探针默认超时秒) -> 结果:
    """检查 ffmpeg/ffprobe 可用性并返回版本；缺失 → 提供者不可用。

    超时秒 为版本探针超时预留参数（当前版本经支持库默认探针执行）。
    """
    if not isinstance(超时秒, (int, float)) or isinstance(超时秒, bool) or 超时秒 <= 0:
        return 结果.失败("参数不合法", "超时秒 必须为正数", 来源=来源)
    return _调用支持库("媒体处理支持库.FFmpeg媒体.检查提供者", {})


def 探测媒体(文件路径: str, 超时秒: float = 默认超时秒) -> 结果:
    """探测媒体文件：{时长秒, 流, 格式, 大小字节, 比特率}；错误码透传。"""
    return _调用支持库("媒体处理支持库.FFmpeg媒体.探测媒体", {"文件路径": 文件路径, "超时秒": 超时秒})


def 提取音频(
    文件路径: str,
    输出格式: str = "wav",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> 结果:
    """从视频提取首个音频轨（wav/mp3/aac/m4a/ogg/flac），字节经 b64 返回。

    成功值 {字节b64, 格式, 字节数}；无音轨/超长媒体/损坏媒体等错误码透传。
    """
    return _调用支持库("媒体处理支持库.FFmpeg媒体.提取音频", {
        "文件路径": 文件路径, "输出格式": 输出格式, "输出路径": 输出路径,
        "超时秒": 超时秒, "最大输出字节": 最大输出字节, "最大时长秒": 最大时长秒})


def 转码(
    文件路径: str,
    输出格式: str = "mp4",
    编码选项: dict | None = None,
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
    返回字节: bool = True,
) -> 结果:
    """ffmpeg 转码（mp4/mkv/webm/mov/avi），编码选项白名单透传。

    编码选项支持：分辨率/视频码率/音频码率/帧率/视频编码器/音频编码器/
    码率上限/缓冲/视频标签/预设。
    高效压缩推荐组合（Apple Silicon 硬编，实测比软编快 20 倍以上）：
      视频编码器=hevc_videotoolbox、视频码率=900k、码率上限=1100k、
      缓冲=2200k、帧率=15、视频标签=hvc1、音频编码器=copy。
    成功值 {格式, 字节数, 输出路径, 字节b64}；返回字节=否 时省略 字节b64
    （已落盘的大文件不必再走 base64，避免 4/3 倍放大与内存占用）。错误码透传。
    """
    return _调用支持库("媒体处理支持库.FFmpeg媒体.转码", {
        "文件路径": 文件路径, "输出格式": 输出格式, "编码选项": 编码选项,
        "输出路径": 输出路径, "超时秒": 超时秒, "最大输出字节": 最大输出字节,
        "最大时长秒": 最大时长秒, "返回字节": 返回字节})


def 抽取帧(
    文件路径: str,
    时间点秒: float,
    输出格式: str = "jpg",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> 结果:
    """ffmpeg 抽帧（jpg/png，时间点秒），字节经 b64 返回。

    成功值 {字节b64, 格式, 宽度, 高度}；错误码透传。
    """
    return _调用支持库("媒体处理支持库.FFmpeg媒体.抽取帧", {
        "文件路径": 文件路径, "时间点秒": 时间点秒, "输出格式": 输出格式,
        "输出路径": 输出路径, "超时秒": 超时秒, "最大输出字节": 最大输出字节,
        "最大时长秒": 最大时长秒})
