"""媒体处理模块（基础模块）：只持能力 id 与契约版本，经唯一能力调用器调用统一网关。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
能力调用器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。

能力：检查提供者 / 探测媒体 / 提取音频 / 转码 / 抽取帧；
错误码（损坏媒体/无音轨/超长媒体/超时/取消/进程崩溃/提供者不可用/
参数不合法/文件不存在/超出限制）由 统一网关 按能力契约透传。
临时媒体由 FFmpeg 支持库自管。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.基础类型.逻辑类型 import 真, 假

来源 = "媒体处理"
默认超时秒 = 60.0
默认最大输出字节 = 200 * 1024 * 1024
默认最大时长秒 = 7200.0
探针默认超时秒 = 30.0


def _校验必填文本(名称: str, 值) -> 结果 | None:
    """必填文本参数边界校验：None/非文本/空白 → 参数不合法；通过返回 None。

    为什么必填项必须在模块边界先拒（2026-09-23，开工-20260923-030635-b562）：
    `_调用支持库` 会把值为 None 的入参**整条剔除**（见该函数说明：HTTP 腿的契约
    类型校验不接受 None，省略 None 等价于支持库签名默认值）。对**非必填**参数这是
    对的；对**必填**参数则把「显式传了非法 None」静默改写成「没传这个参数」——
    HTTP 腿有网关必填校验兜住（回 参数不合法），**进程内腿没有必填校验**，于是直接
    落成支持库实现体的 `TypeError: missing 1 required positional argument`，再被
    `运行核心/能力调用/唯一能力调用_调用错误码.py::_公开错误码` 归为「内部错误」：
    可预期的入参错误伪装成服务故障（哲学第 3 条 2 项：失败必须明确）。

    故必填项按**本模块自己的契约**（`能力契约/参数契约.json` 声明的 必填=真、
    类型=文本型）在进 `_调用支持库` 之前拒掉，不依赖下游兜底——与同包
    `拼接媒体`（`文件列表` 必填边界校验）、兄弟模块 `模块库/图像处理`（受控根目录/
    相对路径 边界校验）同一姿势。
    """
    if not isinstance(值, str) or not 值.strip():
        return 结果.失败("参数不合法", f"{名称} 必须是非空文本", 来源=来源)
    return None


def _校验必填数值(名称: str, 值) -> 结果 | None:
    """必填数值参数边界校验：None/非数值（布尔不算）→ 参数不合法；通过返回 None。

    理由同 `_校验必填文本`：None 会被 `_调用支持库` 的 None 过滤剔除，把必填项
    变成缺参。数值判据不另立第二套口径——类型判据与支持库侧
    `FFmpeg提供者/实现/处理.py::抽取帧` 同源（`isinstance(值, (int, float))` 且
    排除 bool），越界值（如负数）仍由支持库实现体按同一错误码拒绝。
    """
    if 值 is None or isinstance(值, bool) or not isinstance(值, (int, float)):
        return 结果.失败("参数不合法", f"{名称} 必须是数值（不得为 None）", 来源=来源)
    return None


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经唯一能力调用服务调用支持库公开能力；未装配或异常时如实返回失败。

    统一调用接口铁律（哲学第 7 条 4 项）：模块只经
    `获取能力调用器().调用能力(能力id, 参数)` 组合公开能力；HTTP / 进程内 /
    本地 / 远程的差异只存在于装配层 —— 模块不持有连接器、不导出第二入口。
    调用层时限沿用决策 0023：能力参数「超时秒」就是调用方对本次操作的时限意图。
    """
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        # 网关按能力契约对显式参数做严格类型校验；省略 None 等价于
        # 进程内调用时支持库签名默认值（如 输出路径=None → 临时文件）。
        参数 = {键: 值 for 键, 值 in (参数 or {}).items() if 值 is not None}
        调用时限 = 参数.get("超时秒")
        if isinstance(调用时限, bool) or not isinstance(调用时限, (int, float)) or 调用时限 <= 0:
            调用时限 = None
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源, 超时秒=调用时限)
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源=来源)
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源=来源)


def 检查提供者(超时秒: float = 探针默认超时秒) -> 结果:
    """检查 ffmpeg/ffprobe 可用性并返回版本；缺失 → 提供者不可用。

    超时秒 为版本探针超时预留参数（当前版本经支持库默认探针执行）。
    """
    if not isinstance(超时秒, (int, float)) or isinstance(超时秒, bool) or 超时秒 <= 0:
        return 结果.失败("参数不合法", "超时秒 必须为正数", 来源=来源)
    return _调用支持库("媒体处理支持库.FFmpeg媒体.检查提供者", {})


def 探测媒体(文件路径: str, 超时秒: float = 默认超时秒) -> 结果:
    """探测媒体文件：{时长秒, 流, 格式, 大小字节, 比特率}；错误码透传。"""
    错误 = _校验必填文本("文件路径", 文件路径)
    if 错误:
        return 错误
    return _调用支持库("媒体处理支持库.FFmpeg媒体.探测媒体", {"文件路径": 文件路径, "超时秒": 超时秒})


def 提取音频(
    文件路径: str,
    输出格式: str = "wav",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> 结果:
    """从视频提取首个音频轨（wav/mp3/aac/m4a/ogg/flac），字节经 b64 返回。

    成功值 {字节b64, 格式, 字节数}；无音轨/超长媒体/损坏媒体等错误码透传。
    """
    错误 = _校验必填文本("文件路径", 文件路径)
    if 错误:
        return 错误
    return _调用支持库("媒体处理支持库.FFmpeg媒体.提取音频", {
        "文件路径": 文件路径, "输出格式": 输出格式, "输出路径": 输出路径,
        "超时秒": 超时秒, "最大输出字节": 最大输出字节, "最大时长秒": 最大时长秒})


def 转码(
    文件路径: str,
    输出格式: str = "mp4",
    编码选项: dict | None = None,
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
    返回字节: bool = 真,
) -> 结果:
    """ffmpeg 转码（mp4/mkv/webm/mov/avi），编码选项白名单透传。

    编码选项支持：分辨率/视频码率/音频码率/帧率/视频编码器/音频编码器/
    码率上限/缓冲/视频标签/预设。
    高效压缩推荐组合（Apple Silicon 硬编，实测比软编快 20 倍以上）：
      视频编码器=hevc_videotoolbox、视频码率=900k、码率上限=1100k、
      缓冲=2200k、帧率=15、视频标签=hvc1、音频编码器=copy。
    成功值 {格式, 字节数, 输出路径, 字节b64}；返回字节=否 时省略 字节b64
    （已落盘的大文件不必再走 base64，避免 4/3 倍放大与内存占用）。错误码透传。
    """
    错误 = _校验必填文本("文件路径", 文件路径)
    if 错误:
        return 错误
    return _调用支持库("媒体处理支持库.FFmpeg媒体.转码", {
        "文件路径": 文件路径, "输出格式": 输出格式, "编码选项": 编码选项,
        "输出路径": 输出路径, "超时秒": 超时秒, "最大输出字节": 最大输出字节,
        "最大时长秒": 最大时长秒, "返回字节": 返回字节})


def 拼接媒体(
    文件列表: list,
    输出格式: str = "mp4",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    返回字节: bool = 假,
) -> 结果:
    """按顺序无损拼接多个同源分片（concat demuxer + -c copy，不重编码）。

    成功值 {格式, 字节数, 输出路径}；分片编码参数不一致 → 进程崩溃；错误码透传。
    """
    if not isinstance(文件列表, (list, tuple)) or len(文件列表) < 2:
        return 结果.失败("参数不合法", "文件列表 至少 2 项", 来源=来源)
    return _调用支持库("媒体处理支持库.FFmpeg媒体.拼接媒体", {
        "文件列表": list(文件列表), "输出格式": 输出格式, "输出路径": 输出路径,
        "超时秒": 超时秒, "最大输出字节": 最大输出字节, "返回字节": 返回字节})


def 抽取帧(
    文件路径: str,
    时间点秒: float,
    输出格式: str = "jpg",
    输出路径: str | None = None,
    超时秒: float = 默认超时秒,
    最大输出字节: int = 默认最大输出字节,
    最大时长秒: float | None = 默认最大时长秒,
) -> 结果:
    """ffmpeg 抽帧（jpg/png，时间点秒），字节经 b64 返回。

    成功值 {字节b64, 格式, 宽度, 高度}；错误码透传。
    """
    错误 = _校验必填文本("文件路径", 文件路径)
    if 错误:
        return 错误
    错误 = _校验必填数值("时间点秒", 时间点秒)
    if 错误:
        return 错误
    return _调用支持库("媒体处理支持库.FFmpeg媒体.抽取帧", {
        "文件路径": 文件路径, "时间点秒": 时间点秒, "输出格式": 输出格式,
        "输出路径": 输出路径, "超时秒": 超时秒, "最大输出字节": 最大输出字节,
        "最大时长秒": 最大时长秒})
