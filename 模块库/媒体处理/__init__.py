"""媒体处理模块包级中文入口（基础模块）：组合 FFmpeg 支持库公开能力。"""

from __future__ import annotations

from 模块库.媒体处理.实现.媒体处理 import 检查提供者
from 模块库.媒体处理.实现.媒体处理 import 探测媒体
from 模块库.媒体处理.实现.媒体处理 import 提取音频
from 模块库.媒体处理.实现.媒体处理 import 转码
from 模块库.媒体处理.实现.媒体处理 import 抽取帧

__all__ = [
    "检查提供者",
    "探测媒体",
    "提取音频",
    "转码",
    "抽取帧",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用，向能力注册表注册本模块能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名 in [
        ("媒体处理.检查提供者", 检查提供者, ["超时秒"]),
        ("媒体处理.探测媒体", 探测媒体, ["文件路径", "超时秒"]),
        ("媒体处理.提取音频", 提取音频,
         ["文件路径", "输出格式", "输出路径", "超时秒", "最大输出字节", "最大时长秒"]),
        ("媒体处理.转码", 转码,
         ["文件路径", "输出格式", "编码选项", "输出路径", "超时秒", "最大输出字节", "最大时长秒"]),
        ("媒体处理.抽取帧", 抽取帧,
         ["文件路径", "时间点秒", "输出格式", "输出路径", "超时秒", "最大输出字节", "最大时长秒"]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.媒体处理",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明="模块组合能力",
            )
        )
