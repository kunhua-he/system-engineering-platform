"""媒体处理模块包级中文入口（基础模块）：组合 FFmpeg 支持库公开能力。"""

from __future__ import annotations

import json
from pathlib import Path

from 模块库.媒体处理.实现.媒体处理 import 检查提供者
from 模块库.媒体处理.实现.媒体处理 import 设置HTTP连接器
from 模块库.媒体处理.实现.媒体处理 import 探测媒体
from 模块库.媒体处理.实现.媒体处理 import 提取音频
from 模块库.媒体处理.实现.媒体处理 import 转码
from 模块库.媒体处理.实现.媒体处理 import 拼接媒体
from 模块库.媒体处理.实现.媒体处理 import 抽取帧

__all__ = [
    "检查提供者",
    "设置HTTP连接器",
    "探测媒体",
    "提取音频",
    "转码",
    "拼接媒体",
    "抽取帧",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用，向能力注册表注册本模块能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    契约 = json.loads((Path(__file__).parent / "能力契约" / "参数契约.json").read_text(encoding="utf-8"))
    类型表 = {
        条目["能力id"]: {参数["名称"]: 参数.get("类型", "") for 参数 in 条目.get("参数", [])}
        for 条目 in 契约.get("能力契约", [])
    }

    for 能力id, 函数, 参数名 in [
        ("媒体处理.检查提供者", 检查提供者, ["超时秒"]),
        ("媒体处理.探测媒体", 探测媒体, ["文件路径", "超时秒"]),
        ("媒体处理.提取音频", 提取音频,
         ["文件路径", "输出格式", "输出路径", "超时秒", "最大输出字节", "最大时长秒"]),
        ("媒体处理.拼接媒体", 拼接媒体,
         ["文件列表", "输出格式", "输出路径", "超时秒", "最大输出字节", "返回字节"]),
        ("媒体处理.转码", 转码,
         ["文件路径", "输出格式", "编码选项", "输出路径", "超时秒", "最大输出字节", "最大时长秒", "返回字节"]),
        ("媒体处理.抽取帧", 抽取帧,
         ["文件路径", "时间点秒", "输出格式", "输出路径", "超时秒", "最大输出字节", "最大时长秒"]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.媒体处理",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": 类型表[能力id][名称]} for 名称 in 参数名],
                返回="结果型",
                说明="模块组合能力",
            )
        )
