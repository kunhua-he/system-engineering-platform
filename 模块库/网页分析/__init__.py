"""网页分析模块包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：提取网页信息(网页内容, 最大长度) → 结果{标题, 正文}。
"""

from __future__ import annotations

from 模块库.网页分析.实现.网页分析 import 提取网页信息

__all__ = ["提取网页信息"]


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(
        能力实现(
            能力id="网页分析.提取网页信息",
            包id="模块库.网页分析",
            实现函数=提取网页信息,
            参数=[{"名称": "网页内容", "类型": "文本"}, {"名称": "最大长度", "类型": "整数"}],
            返回="结果",
            说明="组合提取网页标题与正文（正文剔除 script/style，空白归一化，截断到最大长度）",
        )
    )
