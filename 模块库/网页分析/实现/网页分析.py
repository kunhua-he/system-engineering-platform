"""网页分析模块：只持能力 id 与契约版本，经唯一能力调用器调用统一网关。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
能力调用器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。
能力：
- 提取网页信息：组合 网络通信支持库.网页解析.提取网页标题 + 提取网页正文，一次返回
  {标题, 正文}；正文剔除 script/style，空白归一化，截断到 最大长度。
参数不合法 为本模块兜底；其余错误码透传支持库（提供者不可用 等）。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "网页分析"
_提取网页标题 = "网络通信支持库.网页解析.提取网页标题"
_提取网页正文 = "网络通信支持库.网页解析.提取网页正文"


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经唯一能力调用服务调用支持库公开能力；未装配或异常时如实返回失败。

    统一调用接口铁律（哲学第 7 条 4 项）：模块只经
    `获取能力调用器().调用能力(能力id, 参数)` 组合公开能力；HTTP / 进程内 /
    本地 / 远程的差异只存在于装配层 —— 模块不持有连接器、不导出第二入口。
    """
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源)
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源=来源)
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源=来源)


def 提取网页信息(网页内容: str, 最大长度: int = 20000) -> 结果:
    """组合提取网页标题与正文；返回 结果(值={"标题": ..., "正文": ...})。"""
    if not isinstance(网页内容, str):
        return 结果.失败("参数不合法", "网页内容必须为字符串", 来源=来源)
    if not isinstance(最大长度, int):
        return 结果.失败("参数不合法", "最大长度必须为整数", 来源=来源)
    标题结果 = _调用支持库(_提取网页标题, {"网页内容": 网页内容})
    if not 标题结果.成功:
        return 标题结果
    正文结果 = _调用支持库(_提取网页正文, {"网页内容": 网页内容, "最大长度": 最大长度})
    if not 正文结果.成功:
        return 正文结果
    return 结果.成功结果({"标题": 标题结果.值, "正文": 正文结果.值})
