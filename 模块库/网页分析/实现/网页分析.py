"""网页分析模块：只经 获取能力调用器().调用能力 组合网页解析支持库能力。

禁止 import 支持库/提供者实现；调用边界唯一通道为能力调用器。能力：
- 提取网页信息：组合 网页解析.提取网页标题 + 提取网页正文，一次返回
  {标题, 正文}；正文剔除 script/style，空白归一化，截断到 最大长度。
参数不合法 为本模块兜底；其余错误码透传支持库（提供者不可用 等）。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "网页分析"
_提取网页标题 = "网页解析.提取网页标题"
_提取网页正文 = "网页解析.提取网页正文"


def _调用(能力id: str, 请求参数: dict) -> 结果:
    """经唯一能力调用服务调用支持库能力；未装配时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器

    try:
        return 获取能力调用器().调用能力(能力id, 请求参数, 调用方=来源)
    except RuntimeError as 错误:
        return 结果.失败("提供者不可用", str(错误), 来源=来源)


def 提取网页信息(网页内容: str, 最大长度: int = 20000) -> 结果:
    """组合提取网页标题与正文；返回 结果(值={"标题": ..., "正文": ...})。"""
    if not isinstance(网页内容, str):
        return 结果.失败("参数不合法", "网页内容必须为字符串", 来源=来源)
    if not isinstance(最大长度, int):
        return 结果.失败("参数不合法", "最大长度必须为整数", 来源=来源)
    标题结果 = _调用(_提取网页标题, {"网页内容": 网页内容})
    if not 标题结果.成功:
        return 标题结果
    正文结果 = _调用(_提取网页正文, {"网页内容": 网页内容, "最大长度": 最大长度})
    if not 正文结果.成功:
        return 正文结果
    return 结果.成功结果({"标题": 标题结果.值, "正文": 正文结果.值})
