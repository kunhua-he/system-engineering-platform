"""网页分析模块：只经网页解析支持库公开入口组合，不深入实现目录。"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.网页解析 import 提取网页标题 as _提取网页标题
from 支持库.后端.网页解析 import 提取网页正文 as _提取网页正文


def 提取网页信息(网页内容: str, 最大长度: int = 20000) -> 结果:
    """组合提取网页标题与正文；返回 结果(值={"标题": ..., "正文": ...})。"""
    if not isinstance(网页内容, str):
        return 结果.失败("参数不合法", "网页内容必须为字符串", 来源="网页分析")
    标题结果 = _提取网页标题(网页内容)
    if not 标题结果.成功:
        return 标题结果
    正文结果 = _提取网页正文(网页内容, 最大长度)
    if not 正文结果.成功:
        return 正文结果
    return 结果.成功结果({"标题": 标题结果.值, "正文": 正文结果.值})
