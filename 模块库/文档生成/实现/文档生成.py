"""文档生成模块：只持能力 id 与契约版本，经唯一能力调用器调用统一网关。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
能力调用器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。

能力签名：生成文档(格式, 内容参数) → 结果[生成产物]。
- 格式非法（非 docx/xlsx/pptx/pdf）→ 错误码“参数不合法”
- 支持库缺库 → 错误码“提供者不可用”（透传）
- 生成字节为空 → 错误码“生成失败”
"""

from __future__ import annotations

import base64

from 公共契约.基础类型.文档结构 import 生成产物
from 公共契约.基础类型.结果类型 import 结果

# 模块只调用文档生成支持库公开能力；Provider 内部能力 id 不得跨边界泄漏。
格式到能力id = {
    "docx": "办公文档支持库.文档生成.生成DOCX",
    "xlsx": "办公文档支持库.文档生成.生成XLSX",
    "pptx": "办公文档支持库.文档生成.生成PPTX",
    "pdf": "办公文档支持库.文档生成.生成PDF",
}
可生成格式 = set(格式到能力id)


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经唯一能力调用服务调用支持库公开能力；未装配或异常时如实返回失败。

    统一调用接口铁律（哲学第 7 条 4 项）：模块只经
    `获取能力调用器().调用能力(能力id, 参数)` 组合公开能力；HTTP / 进程内 /
    本地 / 远程的差异只存在于装配层 —— 模块不持有连接器、不导出第二入口。
    """
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方="文档生成")
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源="文档生成")
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源="文档生成")


def _归一化格式(格式: str) -> str:
    """格式统一为小写无点前缀；非法格式原样返回（由调用方判参数不合法）。"""
    from 公共契约.基础类型.文档结构 import 归一化格式

    try:
        return 归一化格式(格式)
    except ValueError:
        return str(格式 or "").lower().lstrip(".")


# 兼容别名：历史调用方/测试 mock 生成函数表；值均为经 _调用支持库 的包装
生成函数表 = {格式: (lambda 内容, 能力id=能力id: _调用支持库(能力id, {"参数": 内容}))
                for 格式, 能力id in 格式到能力id.items()}


def _失败(错误码: str, 错误说明: str):
    return 结果.失败(错误码, 错误说明, 来源="文档生成")


def 生成文档(格式: str, 内容参数: dict):
    """按格式生成文档，返回 结果[生成产物]。"""
    from 公共契约.基础类型.文档结构 import 归一化格式

    标准格式 = _归一化格式(格式)
    if 标准格式 not in 可生成格式:
        return _失败(
            "参数不合法",
            f"暂不支持生成格式 '{标准格式}'，仅支持 {sorted(可生成格式)}",
        )
    if not isinstance(内容参数, dict):
        return _失败("参数不合法", "内容参数必须是字典")

    try:
        支持库结果 = 生成函数表[标准格式](内容参数)
    except Exception as 错误:
        return _失败("生成失败", f"{标准格式} 生成器异常: {错误}")
    if not 支持库结果.成功:
        return 支持库结果  # 透传：提供者不可用 / 参数不合法 / 生成失败
    值 = 支持库结果.值
    if isinstance(值, 生成产物):
        产物 = 值
    elif isinstance(值, dict) and isinstance(值.get("字节"), (bytes, bytearray)):
        # HTTP 网关路径：dataclass 经 asdict 展开后，字节字段按 字节集型 还原为 bytes
        产物 = 生成产物(
            格式=标准格式,
            字节=bytes(值["字节"]),
            媒体类型=值.get("媒体类型", ""),
            摘要=值.get("摘要", ""),
            诊断=值.get("诊断", []),
            附加=值.get("附加", {}),
        )
    elif isinstance(值, dict) and 值.get("字节b64"):
        # 兼容：提供者直接返回 base64 文本
        字节 = base64.b64decode(值["字节b64"])
        产物 = 生成产物(
            格式=标准格式,
            字节=字节,
            媒体类型=值.get("媒体类型", ""),
            摘要=值.get("摘要", ""),
            诊断=值.get("诊断", []),
            附加=值.get("附加", {}),
        )
    else:
        return _失败("生成失败", f"{标准格式} 提供者未产出生成产物（生成产物为空）")

    if not 产物.字节:
        return _失败("生成失败", f"{标准格式} 生成字节为空")
    return _成功结果(产物)


def _成功结果(产物: 生成产物):
    return 结果.成功结果(产物)
