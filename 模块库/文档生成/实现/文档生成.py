"""文档生成模块：按格式组合文档生成支持库能力，返回统一 生成产物。

模块只保存能力 id 与契约版本；提供者选择与调用由运行核心注入的
唯一能力调用服务完成（禁止直接 import 支持库/提供者实现）。

能力签名：生成文档(格式, 内容参数) → 结果[生成产物]。
- 格式非法（非 docx/xlsx/pptx/pdf）→ 错误码“参数不合法”
- 支持库缺库 → 错误码“提供者不可用”（透传）
- 生成字节为空 → 错误码“生成失败”
"""

from __future__ import annotations

import base64

from 公共契约.基础类型.文档结构 import 生成产物

# 格式 → 能力 id（一格式一权威能力，提供者选择由唯一能力调用服务完成）
格式到能力id = {
    "docx": "文字文档.生成文字文档",
    "xlsx": "表格文档.生成表格文档",
    "pptx": "演示文稿.生成演示文稿",
    "pdf": "PDF生成.生成PDF",
}
可生成格式 = set(格式到能力id)


def _归一化格式(格式: str) -> str:
    """格式统一为小写无点前缀；非法格式原样返回（由调用方判参数不合法）。"""
    from 公共契约.基础类型.文档结构 import 归一化格式

    try:
        return 归一化格式(格式)
    except ValueError:
        return str(格式 or "").lower().lstrip(".")


def _经唯一服务调用(能力id: str, 内容参数: dict):
    """经运行核心注入的唯一能力调用服务按能力 id 调用支持库能力。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器
    return 获取能力调用器().调用能力(能力id, 内容参数)


# 兼容别名：历史调用方/测试 mock 生成函数表；值均为经唯一能力调用服务的包装
生成函数表 = {格式: (lambda 内容, 能力id=能力id: _经唯一服务调用(能力id, 内容))
                for 格式, 能力id in 格式到能力id.items()}


def _失败(错误码: str, 错误说明: str):
    from 公共契约.基础类型.结果类型 import 结果
    return 结果.失败(错误码, 错误说明, 来源="文档生成")


def 生成文档(格式: str, 内容参数: dict):
    """按格式生成文档，返回 结果[生成产物]。"""
    from 公共契约.基础类型.文档结构 import 归一化格式

    标准格式 = _归一化格式(格式)
    if 标准格式 not in 可生成格式:
        return _失败(
            "参数不合法",
            f"暂不支持生成格式 '{标准格式}'，仅支持 {sorted(可生成格式)}",
        )
    if not isinstance(内容参数, dict):
        return _失败("参数不合法", "内容参数必须是字典")

    try:
        支持库结果 = 生成函数表[标准格式](内容参数)
    except Exception as 错误:
        return _失败("生成失败", f"{标准格式} 生成器异常: {错误}")
    if not 支持库结果.成功:
        return 支持库结果  # 透传：提供者不可用 / 参数不合法 / 生成失败
    值 = 支持库结果.值
    if isinstance(值, 生成产物):
        产物 = 值
    elif isinstance(值, dict) and 值.get("字节b64"):
        字节 = base64.b64decode(值["字节b64"])
        产物 = 生成产物(
            格式=标准格式,
            字节=字节,
            媒体类型=值.get("媒体类型", ""),
            摘要=值.get("摘要", ""),
            诊断=值.get("诊断", []),
            附加=值.get("附加", {}),
        )
    else:
        return _失败("生成失败", f"{标准格式} 提供者未产出生成产物（生成产物为空）")

    if not 产物.字节:
        return _失败("生成失败", f"{标准格式} 生成字节为空")
    return _成功结果(产物)


def _成功结果(产物: 生成产物):
    from 公共契约.基础类型.结果类型 import 结果
    return 结果.成功结果(产物)
