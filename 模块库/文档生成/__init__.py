"""文档生成模块包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：文档生成.生成文档(格式, 内容参数) → 结果[生成产物]。

**能力 id 用模块自己的前缀**（`文档生成.`，规矩同 `模块库.能力目录` →
`能力目录.搜索能力`）：模块只**组合**支持库，不顶着支持库包名
（`办公文档支持库.文档生成.*`）注册自己的能力。`办公文档支持库.文档生成.生成DOCX`
等是**被依赖的支持库真实能力 id**，只出现在 实现/ 的调用表与 包声明 的依赖里。

参数声明不在本文件手写：一律从本包 `能力契约/参数契约.json`（唯一事实源）读取，
避免注册口径与契约漂移（历史教训：手写参数表漏掉必填/默认值，注册口径判为
「漏声明」；同 `模块库/能力目录/__init__.py` 的既有做法）。
"""

from __future__ import annotations

import json
from pathlib import Path

from 模块库.文档生成.实现.文档生成 import 生成文档, 设置HTTP连接器

__all__ = ["生成文档", "设置HTTP连接器"]

本模块能力id = "文档生成.生成文档"
契约文件名 = "能力契约/参数契约.json"


def _契约参数(能力id: str) -> list[dict]:
    """从本包参数契约读该能力的参数声明（唯一事实源；缺条目即明确失败）。"""
    契约路径 = Path(__file__).resolve().parent / 契约文件名
    数据 = json.loads(契约路径.read_text(encoding="utf-8"))
    for 条目 in 数据.get("能力契约", []):
        if isinstance(条目, dict) and 条目.get("能力id") == 能力id:
            return [dict(项) for 项 in (条目.get("参数") or [])]
    raise RuntimeError(f"能力契约缺少 能力id: {能力id}（{契约路径}）")


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(
        能力实现(
            能力id=本模块能力id,
            包id="模块库.文档生成",
            实现函数=生成文档,
            参数=_契约参数(本模块能力id),
            返回="结果型",
            说明="按格式组合文档生成支持库，返回统一 生成产物",
        )
    )
