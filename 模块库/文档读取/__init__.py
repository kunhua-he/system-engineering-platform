"""文档读取模块包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：读取正文/提取标题/计算段落数/结构化读取，返回统一 结果。
"""

from __future__ import annotations

from 模块库.文档读取.实现.文档读取 import 读取正文
from 模块库.文档读取.实现.文档读取 import 提取标题
from 模块库.文档读取.实现.文档读取 import 计算段落数
from 模块库.文档读取.实现.文档读取 import 结构化读取

__all__ = [
    "读取正文",
    "提取标题",
    "计算段落数",
    "结构化读取",
]


def 注册能力(注册表) -> None:
    """由模块加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型, 说明 in [
        ("文档读取.读取正文", 读取正文, ['文件路径'], "结果",
         "读取文档正文文本"),
        ("文档读取.提取标题", 提取标题, ['文件路径'], "结果",
         "提取文档标题（首个非空行）"),
        ("文档读取.计算段落数", 计算段落数, ['文件路径'], "结果",
         "统计非空段落数"),
        ("文档读取.结构化读取", 结构化读取, ['文件路径'], "结果",
         "返回结构化结果（正文/标题/段落数/序列化文本）"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="模块库.文档读取",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "文本型"} for 名称 in 参数名],
                返回=返回类型,
                说明=说明,
            )
        )
