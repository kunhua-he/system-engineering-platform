"""文档读取模块：组合文件系统、文本处理与数据交换支持库。"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.错误结构 import 错误结构
from 支持库.后端.文件系统 import 读取文件 as _读取文件
from 支持库.后端.数据交换 import 序列化JSON as _序列化JSON
from 支持库.后端.文本处理 import 去空白 as _去空白, 按行分割 as _按行分割, 统计长度 as _统计长度


def _读取全部行(文件路径: str) -> 结果:
    读取结果 = _读取文件(文件路径)
    if not 读取结果.成功:
        return 读取结果
    文本 = 读取结果.值 or ""
    行列表结果 = _按行分割(文本)
    return 行列表结果


def 读取正文(文件路径: str) -> 结果:
    结果对象 = _读取文件(文件路径)
    if not 结果对象.成功:
        return 结果.失败(结果对象.错误.错误码, 结果对象.错误.消息, 来源="文档读取")
    return 结果.成功结果(结果对象.值)


def 提取标题(文件路径: str) -> 结果:
    行结果 = _读取全部行(文件路径)
    if not 行结果.成功:
        return 行结果
    for 行 in 行结果.值:
        标题 = _去空白(行).值
        if 标题:
            return 结果.成功结果(标题)
    return 结果.成功结果("")


def 计算段落数(文件路径: str) -> 结果:
    行结果 = _读取全部行(文件路径)
    if not 行结果.成功:
        return 行结果
    段落数 = sum(1 for 行 in 行结果.值 if _去空白(行).值)
    return 结果.成功结果(段落数)


def 结构化读取(文件路径: str) -> 结果:
    正文结果 = 读取正文(文件路径)
    if not 正文结果.成功:
        return 正文结果
    标题结果 = 提取标题(文件路径)
    段落结果 = 计算段落数(文件路径)
    结构 = {
        "正文": 正文结果.值,
        "标题": 标题结果.值 if 标题结果.成功 else "",
        "段落数": 段落结果.值 if 段落结果.成功 else 0,
        "错误": None,
    }
    序列化 = _序列化JSON(结构)
    if not 序列化.成功:
        return 结果.失败("序列化失败", 序列化.错误.消息, 来源="文档读取")
    结构["序列化文本"] = 序列化.值
    return 结果.成功结果(结构)
