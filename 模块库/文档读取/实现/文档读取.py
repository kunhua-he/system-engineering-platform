"""文档读取模块：只持能力 id 与契约版本，经唯一能力调用器调用统一网关。

模块不 import 支持库/提供者/实现目录；只做参数装配、条件分支与结果组合。
能力调用器未装配或支持库不可用时返回统一失败（提供者不可用），不向调用方抛异常。
能力：
- 读取正文：读取文档文本；
- 提取标题：首个非空行；
- 计算段落数：非空行计数；
- 结构化读取：正文/标题/段落数。
参数不合法 为本模块兜底；其余错误码透传支持库（文件不存在/提供者不可用）。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "文档读取"
_文件系统读取文件 = "文件系统支持库.文件操作.读取文件"
_文本处理按行分割 = "数据操作支持库.文本处理.按行分割"
_文本处理去空白 = "数据操作支持库.文本处理.去空白"
_数据交换序列化JSON = "数据操作支持库.数据交换.序列化JSON"


def _调用支持库(能力id: str, 参数: dict, *, 失败错误码: str = "提供者不可用") -> 结果:
    """经唯一能力调用服务调用支持库公开能力；未装配或异常时如实返回失败。

    统一调用接口铁律（哲学第 7 条 4 项）：模块只经
    `获取能力调用器().调用能力(能力id, 参数)` 组合公开能力；HTTP / 进程内 /
    本地 / 远程的差异只存在于装配层 —— 模块不持有连接器、不导出第二入口。
    """
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        return 获取能力调用器().调用能力(能力id, 参数, 调用方=来源)
    except FileNotFoundError as 错误:
        return 结果.失败("文件不存在", str(错误), 来源=来源)
    except Exception as 错误:
        return 结果.失败(失败错误码, f"{能力id} 调用失败: {错误}", 来源=来源)


def _校验文件路径(文件路径) -> 结果 | None:
    """文件路径必须为非空文本；非法返回 参数不合法。"""
    if not isinstance(文件路径, str) or not 文件路径.strip():
        return 结果.失败("参数不合法", "文件路径必须为非空文本", 来源=来源)
    return None


def _读取全部行(文件路径: str) -> 结果:
    """读取文件文本并按行分割；任一步失败透传。

    `最大字符: 0` = 不限长、不精炼：本处结果要按行分割后**逐行统计/取标题**，
    用 `读取文件` 默认档（精炼 + 2000 字符上限）会把大文档截断 ⇒ 段落数少算、
    正文残缺（同 §四 #65 的「读了又解析」同类点）。
    """
    读取结果 = _调用支持库(_文件系统读取文件, {"文件路径": 文件路径, "最大字符": 0})
    if not 读取结果.成功:
        return 读取结果
    文本 = 读取结果.值 or ""
    return _调用支持库(_文本处理按行分割, {"文本": 文本})


def 读取正文(文件路径: str) -> 结果:
    """读取文档正文文本：返回 结果(值=文本)。

    `最大字符: 0` = 不限长、不精炼：正文是**完整内容**语义，用默认档会把
    >2000 字符的文档静默截断（同 §四 #65 的「读了又解析」同类点）。
    """
    校验 = _校验文件路径(文件路径)
    if 校验 is not None:
        return 校验
    return _调用支持库(_文件系统读取文件, {"文件路径": 文件路径, "最大字符": 0})


def 提取标题(文件路径: str) -> 结果:
    """提取文档标题（首个非空行）；无标题返回空字符串。"""
    校验 = _校验文件路径(文件路径)
    if 校验 is not None:
        return 校验
    行结果 = _读取全部行(文件路径)
    if not 行结果.成功:
        return 行结果
    for 行 in 行结果.值 or []:
        去空白结果 = _调用支持库(_文本处理去空白, {"文本": 行})
        if not 去空白结果.成功:
            return 去空白结果
        标题 = 去空白结果.值
        if 标题:
            return 结果.成功结果(标题)
    return 结果.成功结果("")


def 计算段落数(文件路径: str) -> 结果:
    """统计非空段落数。"""
    校验 = _校验文件路径(文件路径)
    if 校验 is not None:
        return 校验
    行结果 = _读取全部行(文件路径)
    if not 行结果.成功:
        return 行结果
    段落数 = 0
    for 行 in 行结果.值 or []:
        去空白结果 = _调用支持库(_文本处理去空白, {"文本": 行})
        if not 去空白结果.成功:
            return 去空白结果
        if 去空白结果.值:
            段落数 += 1
    return 结果.成功结果(段落数)


def 结构化读取(文件路径: str) -> 结果:
    """结构化读取：返回 {正文/标题/段落数/错误}。"""
    校验 = _校验文件路径(文件路径)
    if 校验 is not None:
        return 校验
    正文结果 = 读取正文(文件路径)
    if not 正文结果.成功:
        return 正文结果
    标题结果 = 提取标题(文件路径)
    if not 标题结果.成功:
        return 标题结果
    段落结果 = 计算段落数(文件路径)
    if not 段落结果.成功:
        return 段落结果
    # 2026-09-21（华哥裁决「不保留旧腿」+ 返回体量分档统一）：
    # 原实现额外返回 `序列化文本` —— 它是**整个结构体的 JSON 转义副本**，
    # 与 `正文` 是同一份内容的两遍，实测让读一个 24,695 字节的 md 返回 50,611 字符
    # （膨胀 2.05 倍，等于同一份文字花两遍 token）。该字段全仓仅一处测试引用，
    # 无业务调用方 ⇒ 按口径直接删除，不留兼容字段、不留同义新名。
    结构 = {
        "正文": 正文结果.值,
        "标题": 标题结果.值,
        "段落数": 段落结果.值,
        "错误": None,
    }
    return 结果.成功结果(结构)
