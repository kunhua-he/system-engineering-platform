"""文档读取模块：只经 获取能力调用器().调用能力 组合支持库能力。

禁止 import 支持库/提供者实现；调用边界唯一通道为能力调用器。能力：
- 读取正文：读取文档文本；
- 提取标题：首个非空行；
- 计算段落数：非空行计数；
- 结构化读取：正文/标题/段落数 + JSON 序列化文本。
参数不合法 为本模块兜底；其余错误码透传支持库（文件不存在/提供者不可用）。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果

来源 = "文档读取"
_文件系统读取文件 = "文件系统支持库.文件操作.读取文件"
_文本处理按行分割 = "数据操作支持库.文本处理.按行分割"
_文本处理去空白 = "数据操作支持库.文本处理.去空白"
_数据交换序列化JSON = "数据操作支持库.数据交换.序列化JSON"


def _调用(能力id: str, 请求参数: dict) -> 结果:
    """经唯一能力调用服务调用支持库能力；未装配时如实返回失败。"""
    from 公共契约.能力契约.调用器 import 获取能力调用器

    try:
        return 获取能力调用器().调用能力(能力id, 请求参数, 调用方=来源)
    except RuntimeError as 错误:
        return 结果.失败("提供者不可用", str(错误), 来源=来源)


def _校验文件路径(文件路径) -> 结果 | None:
    """文件路径必须为非空文本；非法返回 参数不合法。"""
    if not isinstance(文件路径, str) or not 文件路径.strip():
        return 结果.失败("参数不合法", "文件路径必须为非空文本", 来源=来源)
    return None


def _读取全部行(文件路径: str) -> 结果:
    """读取文件文本并按行分割；任一步失败透传。"""
    读取结果 = _调用(_文件系统读取文件, {"文件路径": 文件路径})
    if not 读取结果.成功:
        return 读取结果
    文本 = 读取结果.值 or ""
    return _调用(_文本处理按行分割, {"文本": 文本})


def 读取正文(文件路径: str) -> 结果:
    """读取文档正文文本：返回 结果(值=文本)。"""
    校验 = _校验文件路径(文件路径)
    if 校验 is not None:
        return 校验
    return _调用(_文件系统读取文件, {"文件路径": 文件路径})


def 提取标题(文件路径: str) -> 结果:
    """提取文档标题（首个非空行）；无标题返回空字符串。"""
    校验 = _校验文件路径(文件路径)
    if 校验 is not None:
        return 校验
    行结果 = _读取全部行(文件路径)
    if not 行结果.成功:
        return 行结果
    for 行 in 行结果.值 or []:
        去空白结果 = _调用(_文本处理去空白, {"文本": 行})
        if not 去空白结果.成功:
            return 去空白结果
        标题 = 去空白结果.值
        if 标题:
            return 结果.成功结果(标题)
    return 结果.成功结果("")


def 计算段落数(文件路径: str) -> 结果:
    """统计非空段落数。"""
    校验 = _校验文件路径(文件路径)
    if 校验 is not None:
        return 校验
    行结果 = _读取全部行(文件路径)
    if not 行结果.成功:
        return 行结果
    段落数 = 0
    for 行 in 行结果.值 or []:
        去空白结果 = _调用(_文本处理去空白, {"文本": 行})
        if not 去空白结果.成功:
            return 去空白结果
        if 去空白结果.值:
            段落数 += 1
    return 结果.成功结果(段落数)


def 结构化读取(文件路径: str) -> 结果:
    """结构化读取：返回 {正文/标题/段落数/错误/序列化文本}。"""
    校验 = _校验文件路径(文件路径)
    if 校验 is not None:
        return 校验
    正文结果 = 读取正文(文件路径)
    if not 正文结果.成功:
        return 正文结果
    标题结果 = 提取标题(文件路径)
    if not 标题结果.成功:
        return 标题结果
    段落结果 = 计算段落数(文件路径)
    if not 段落结果.成功:
        return 段落结果
    结构 = {
        "正文": 正文结果.值,
        "标题": 标题结果.值,
        "段落数": 段落结果.值,
        "错误": None,
    }
    序列化 = _调用(_数据交换序列化JSON, {"数据": 结构})
    if not 序列化.成功:
        return 结果.失败("序列化失败", 序列化.错误.消息, 来源=来源)
    结构["序列化文本"] = 序列化.值
    return 结果.成功结果(结构)
