def 首选能力(意图: str) -> str:
    """按 意图名 查 `常见意图首选能力`；查不到回空串（**不猜、不发明**）。"""
    名 = str(意图 or "").strip()
    for 意图名, 能力id, _限定 in 常见意图首选能力:
        if 意图名 == 名:
            return 能力id
    return ""


def 速办条目(意图: str) -> dict[str, Any] | None:
    """速办意图 → 派生条目 `{意图, 常用意图, 首选能力, 短参数}`；未知意图回 None。

    `首选能力` 是**现查**出来的（口径见 速办意图表 上方）；表里缺那一条时为空串，
    调用方据此如实报错 —— 本件不在这里补一个 id（发明数据比缺字段更坏）。
    """
    名 = str(意图 or "").strip()
    for 速办名, 常用意图名, 短参数 in 速办意图表:
        if 速办名 == 名:
            return {"意图": 速办名, "常用意图": 常用意图名,
                    "首选能力": 首选能力(常用意图名), "短参数": 短参数}
    return None


def 速办意图清单() -> list[str]:
    """速办支持的意图名（顺序即表序）。"""
    return [速办名 for 速办名, _常用, _短 in 速办意图表]


def 渲染速办短表() -> str:
    """一句短话的短参数表（工具描述与失败回执共用**同一处渲染**，不手抄第二份）。

    形如：`看文件=路径[+区间]；查文件=模式+范围[+文件模式]；…`
    """
    段表 = []
    for 速办名, _常用, 短参数 in 速办意图表:
        必填 = [短名 for 短名, _真名, 必填位, _缺省, _说明 in 短参数 if 必填位]
        可选 = [短名 for 短名, _真名, 必填位, _缺省, _说明 in 短参数 if not 必填位]
        段 = 速办名 + "=" + "+".join(必填)
        if 可选:
            段 += "[+" + "+".join(可选) + "]"
        段表.append(段)
    return "；".join(段表) + "。"
