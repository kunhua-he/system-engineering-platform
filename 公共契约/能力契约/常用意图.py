"""常用意图 → 首选能力：全平台**唯一一份**映射（薄壳工具描述与 开工准备.资料 段同源）。

## 为什么单独成件（华哥 2026-09-24 批R·R-16）

华哥原话：「我希望的就是纯用 mcp，然后尽量都功能后面变成，1 次运行，能获取开工所有的
资料。这是我的目标，但是控制住上下文不能撑爆」。

「读文件 / 内容检索 / 跑命令 / 找能力」这四个高频意图该调哪个能力，此前只以**散文字面量**
写在 `开发工具/薄壳/工具清单.py` 的 `capability_call` 描述里（批R·R-13 补）。开工资料段
要把同一份映射随开工上下文回带，于是有两条错路：

- 在模块里再抄一份 ⇒ 哲学第 1 条「同一件事两套实现即缺陷」，两处必然漂移；
- 让模块 import 薄壳 ⇒ 逆向依赖（分层是 `公共契约 → 支持库 → 模块库`，
  `模块库` 不许依赖 `开发工具`，那会把支持库拖进模块的导入图）。

故把映射收到**两边都能依赖的最底层**（`公共契约`）：薄壳与模块都只读本件，不各持一份。

## 只增不改（哲学第 5 条 2 项）

条目只增；已发布条目**不得**改能力 id、不得删（会让照它写好的调用方静默失效）。
要换落点就新增条目并把旧条目标 `已废弃`（本件目前无废弃条目）。
"""

from __future__ import annotations

from typing import Any

#: 高频意图 →（意图名, 首选能力 id, 一句话限定）。**唯一事实源**：改这里，
#: 薄壳描述（`开发工具/薄壳/工具清单.py`）与开工资料段（`开工编排.开工准备`）同时变。
常见意图首选能力: tuple[tuple[str, str, str], ...] = (
    ("读文件", "文件系统支持库.文件操作.读取文件", ""),
    ("内容检索", "文件系统支持库.内容检索.正则搜索", "≈一条 rg：文件模式/上下文/最大匹配数"),
    ("跑命令", "系统核心支持库.进程管理.执行命令", ""),
    ("找能力", "能力目录.搜索能力", ""),
)

#: 薄壳描述里那一句的固定前缀（`渲染映射文本` 的默认值；两处口径同一个字面量）。
映射文本前缀 = "★ 常见意图→首选能力："

#: 本件在仓库里的位置（指针用；随返回回带给调用方，便于「这份映射住哪」可追溯）。
口径源 = "公共契约/能力契约/常用意图.py"


def 渲染映射文本(前缀: str = 映射文本前缀) -> str:
    """渲染成薄壳工具描述里那一句（**逐字节**：薄壳描述由本函数生成，不手抄）。

    形如：`★ 常见意图→首选能力：读文件=\\`…\\`；内容检索=\\`…\\`（≈一条 rg：…）；…。`
    """
    段表 = []
    for 意图, 能力id, 限定 in 常见意图首选能力:
        项 = f"{意图}=`{能力id}`"
        if 限定:
            项 += f"（{限定}）"
        段表.append(项)
    return 前缀 + "；".join(段表) + "。"


def 映射表() -> list[dict[str, Any]]:
    """结构形态（供 `开工编排.开工准备` 的 `资料.能力映射` 回带）。

    返回的是**新建列表**：调用方改自己的那份不会污染本件（本件是只读事实源）。
    """
    return [
        {"意图": 意图, "首选能力": 能力id, "说明": 限定, "口径源": 口径源}
        for 意图, 能力id, 限定 in 常见意图首选能力
    ]
