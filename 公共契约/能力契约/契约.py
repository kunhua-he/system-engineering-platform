"""能力契约：支持库与模块之间唯一的公开调用边界。

模块不得导入支持库实现，只能按能力契约调用；契约校验保证调用方
声明的参数与提供方实现一致，防止同名不同义。
"""

from __future__ import annotations

import ast
from dataclasses import dataclass, field
from typing import Any, Callable

from 公共契约.包声明 import 能力声明
from 公共契约.基础类型.逻辑类型 import 真, 假


def _参数名(参数: Any) -> str:
    """参数表项取参数名：兼容 dict（{名称,类型}）与字符串参数名两种形态。

    声明一致 与 调用 必须用同一口径取名，否则字符串形态下 声明一致 读到空名、
    把不一致的声明判成一致（判据③ 非期望类型静默通过）。
    """
    if isinstance(参数, dict):
        return str(参数.get("名称", ""))
    return str(参数)


# 注册口径别名表：历史注册写法 → 正式契约类型名。
# 只登记「同一语义、仅写法不同」的项（`结果` 与 `结果型` 是同一种统一结果，
# 不是两种返回结构）；语义确实不同的历史短名（布尔/文本/字典/数值…）**不进本表**，
# 它们属批次4「注册元数据-类型名非正式」的治理范围，混进来会把真问题淹掉。
# 背景（落点清单_03 重要-10）：注册写 `结果`、契约写 `结果型`，全仓首报约 300 条
# 噪声；归一后只剩真实口径差异。
注册口径别名表 = {"结果": "结果型"}


def _取返回类型位(名称: Any) -> str:
    """取「返回声明」的类型位，兼容三种形态（唯一实现，归一注册口径 专用）。

    为什么需要三种形态（2026-09-17 主会话实测定位）：

    1. **对象形态** `{"类型": "结果型", "值结构": {...}}`：`包声明.json` 原文如此。
    2. **字符串化对象形态** `"{'类型': '结果型', '值结构': {...}}"`：
       `公共契约/包声明/声明.py:101` 用 `返回=str(条目.get("返回", ""))` 把对象
       **str 化**了（`能力声明.返回` 声明为 `str`），结构信息在这里被丢弃 ——
       所以真实传给归一函数的是这一种，而不是 1。**这是「判据打架」的真根因**。
    3. **纯字符串形态** `"结果型"` / `"结果"`：注册侧与 `__init__.py` 用这种。

    形态 2 用 `ast.literal_eval` 安全解析（标准库；不用 `eval`，不执行任意代码）；
    解析不出来就按原文本处理，不抛异常、不静默改语义。
    """
    if isinstance(名称, dict):
        return str(名称.get("类型", ""))
    文本 = str(名称 or "").strip()
    if 文本.startswith("{") and "类型" in 文本:
        try:
            解析 = ast.literal_eval(文本)
        except (ValueError, SyntaxError):
            return 文本
        if isinstance(解析, dict):
            return str(解析.get("类型", ""))
    return 文本


def 归一注册口径(名称: Any) -> str:
    """把注册/声明里的写法归一为正式口径名（当前仅 `结果` → `结果型`）。

    返回声明的三种形态由 `_取返回类型位` 统一收敛到「类型位」后再比对；
    `值结构` 是文档性描述，**不属口径**，不参与判定（否则值结构里任意一个
    说明文字改动都会变成「口径不一致」）。

    修前（2026-09-17 前）本函数直接 `str(名称)`，于是 `包声明.json` 的对象形态
    （经加载器 str 化）变成一整串字面量、与注册侧 `"结果型"` **永不相等** ——
    `校验声明一致` 因此对全平台约 **519 条能力**恒报「声明参数/返回与实现不一致」，
    而权威编译期判据 `漂移检测.检测注册口径漂移` 对同一个包返回 `[]`。
    这正是本函数下游 `返回口径一致` 的 docstring 承诺要避免的
    「门禁过了、运行期判不一致」的第二套判据。

    放宽只针对**形态**，不放松**语义**：取到类型位后仍走同一张别名表归一，
    `{"类型": "结果型"}`、`"{'类型': '结果型'}"`、`"结果型"`、`"结果"` 判一致；
    而 `"文本型"` 与 `"结果型"` 照旧判不一致（配反向验证，见测试）。
    """
    类型位 = _取返回类型位(名称)
    return 注册口径别名表.get(类型位, 类型位)


def 返回口径一致(声明返回: str, 实现返回: str) -> bool:
    """返回口径比较：两边归一后相等即视为一致。

    `声明一致`（:45）与 `校验声明一致`（:113）共用本函数；开发工具.契约编译.
    漂移检测 的「注册口径」子检测也用它，保证运行期校验与编译期门禁同口径，
    否则会出现「门禁过了、运行期判不一致」的第二套判据。
    """
    return 归一注册口径(声明返回) == 归一注册口径(实现返回)


class 未知参数错误(TypeError):
    """契约层收到**未声明参数**：参数名与声明不符，拒绝调用。

    ## 口径（刻意不同，不是缺陷）

    进程内腿（`唯一能力调用` / 契约层）对**未声明键是拒绝的**；网关边界对未知字段
    是**忽略**（在边界剔除，且信封回带 `被忽略参数`）——**两层口径不同，别混**。
    出处：`开发文档/当前流程图.md` 传参铁律 + `开发文档/规范/网关调用最小示例.md`
    「调用方只需记住的四条兼容口径」规则 1（2026-09-21 现场核实并改正）。

    注意：**不要**把这条口径记成「哲学第 5 条 2 项」——5.2 原文讲的是「**版本**不对齐
    默认不失败，只有强制参数才失败」，与未知参数无关（`开发文档/方案/MCP接入面瘦身与
    网关协议对齐方案_20260921.md` 第二节已纠正这处引证错误）。

    ## 为什么继承 TypeError 而不是另立 ValueError

    「多传关键字参数」在 CPython 里就是 `TypeError`（`能力实现.调用` 的语义与之同源），
    继承 TypeError 保持 Python 语义：既有 `except TypeError` 的调用方行为不变
    （`测试中心/公共契约/测试_能力契约.py::test_未知参数拒绝` 断言 `assertRaises(TypeError)`
    **无需改动**）。同时它是**可精确识别的子类**：`唯一能力调用_调用错误码._异常错误码表`
    据此把这一条映射为公开码 `参数不合法`（改前是裸 `TypeError` → 落 `内部错误`，
    把**可预期的入参错误**当成**未预期异常**上报，违哲学第 3 条 2 项「失败必须明确」）。
    实现体内其它 `TypeError`（真故障）不受影响，仍归 `内部错误`。
    """


@dataclass(frozen=True)
class 能力实现:
    """能力提供方注册的实现句柄。

    元数据字段（版本/提供者id/提供者版本/制品摘要）供调用证据采集：
    由生产装配注册方提供，缺省为空串；不得伪造，未知即空。
    """

    能力id: str
    包id: str
    实现函数: Callable[..., Any]
    参数: list[dict[str, str]] = field(default_factory=list)
    返回: str = ""
    说明: str = ""
    版本: str = ""
    提供者id: str = ""
    提供者版本: str = ""
    制品摘要: str = ""
    #: **可选**执行形态声明（默认空串 = 未声明，由调用侧按执行单元保守推断）。
    #: 取值是 `运行核心/能力调用/超时执行.执行形态表` 里的形态名
    #: （即时纯计算 / 阻塞IO / 长耗时 / 常驻有状态）。为什么用字符串而不在这里
    #: import 那张表：`公共契约` 是最底层、谁都能依赖的一层，不得反向依赖运行核心。
    #: 空串语义 = 「未知」——与 制品摘要 等同一条仓库口径：不得伪造，未知即空。
    执行形态: str = ""
    #: **可选**提供者级执行形态声明（默认空串 = 未声明）。给「同一提供者的全部能力
    #: 同一形态」的注册方用，优先级低于 `执行形态`；空串时同样交给保守推断。
    提供者执行形态: str = ""

    def 声明一致(self, 声明: 能力声明) -> bool:
        """实现句柄与声明的参数/返回是否一致（取名口径与 调用 相同）。

        返回按 `返回口径一致` 归一后比较：注册写 `结果`、契约写 `结果型` 属同一
        口径，不能判成不一致（否则全仓约 300 条噪声）。
        """
        声明参数名 = [_参数名(参数) for 参数 in 声明.参数]
        实现参数名 = [_参数名(参数) for 参数 in self.参数]
        return 声明参数名 == 实现参数名 and 返回口径一致(声明.返回, self.返回)

    def 调用(self, *参数值: Any, **关键字值: Any) -> Any:
        """按契约调用实现；参数名与声明不符时拒绝调用。

        参数表兼容两种形态：dict 列表（{名称,类型}）与字符串参数名列表。
        未声明键抛 `未知参数错误`（TypeError 子类，可精确映射公开码，见该类说明）。
        """
        声明参数名 = {_参数名(参数) for 参数 in self.参数}
        未知关键字 = set(关键字值) - 声明参数名
        if 未知关键字:
            raise 未知参数错误(f"能力 {self.能力id} 收到未知参数: {sorted(未知关键字)}")
        return self.实现函数(*参数值, **关键字值)


class 能力注册表:
    """包级能力注册表：同一能力 id 只允许一个提供方。"""

    def __init__(self) -> None:
        self._实现表: dict[str, 能力实现] = {}

    @property
    def 能力id列表(self) -> list[str]:
        return sorted(self._实现表)

    def 注册(self, 实现: 能力实现) -> None:
        已有 = self._实现表.get(实现.能力id)
        if 已有 is not None and 已有.包id != 实现.包id:
            raise ValueError(
                f"能力 {实现.能力id} 已被 {已有.包id} 注册，禁止 {实现.包id} 重复注册"
            )
        self._实现表[实现.能力id] = 实现

    def 移除(self, 能力id: str, 包id: str = "") -> bool:
        """移除指定能力（热接入回滚/删除场景）。

        传 包id 时只允许移除该包已注册的能力（跨包保护）；
        能力不存在返回 False。
        """
        已有 = self._实现表.get(能力id)
        if 已有 is None:
            return 假
        if 包id and 已有.包id != 包id:
            return 假
        del self._实现表[能力id]
        return 真

    def 获取(self, 能力id: str) -> 能力实现 | None:
        return self._实现表.get(能力id)

    def 清空(self) -> None:
        """卸载时清空全部注册能力（卸载后不得残留提供者）。"""
        self._实现表.clear()

    def 搜索(self, *, 关键词: str = "", 返回类型: str = "") -> list[能力实现]:
        """按关键词与返回类型搜索能力实现。"""
        结果列表 = []
        for 实现 in self._实现表.values():
            # #164（2026-09-20）：原为 `实现.返回 != 返回类型` 直比，**未走本文件
            # `返回口径一致`（:87）** —— 而 `声明一致`（:45）与 `校验声明一致`（:113）
            # 都已归一（口径别名表：如「结果」↔「结果型」）。同一文件三种比较两种口径，
            # 搜索传「结果」就会漏掉注册为「结果型」的实现（假失败）。
            # 按「同口径」纪律：搜索也必须走 返回口径一致。
            if 返回类型 and not 返回口径一致(返回类型, 实现.返回):
                continue
            if 关键词 and 关键词 not in 实现.能力id and 关键词 not in 实现.说明:
                continue
            结果列表.append(实现)
        return 结果列表

    def 校验声明一致(self, 包id: str, 声明列表: list[能力声明]) -> list[str]:
        """校验某包声明的能力与注册实现是否一致，返回不一致清单。

        返回口径经 `返回口径一致` 归一后比较（注册 `结果` ≡ 契约 `结果型`），
        与 `声明一致` 同口径；不一致时把两侧口径与参数名一并回带，便于直接定位。
        """
        问题列表: list[str] = []
        for 声明 in 声明列表:
            实现 = self._实现表.get(声明.能力id)
            if 实现 is None:
                问题列表.append(f"{声明.能力id}: 声明了但未注册实现")
            elif 实现.包id != 包id:
                问题列表.append(f"{声明.能力id}: 声明方 {包id} 与实现方 {实现.包id} 不一致")
            elif not 实现.声明一致(声明):
                问题列表.append(
                    f"{声明.能力id}: 声明参数/返回与实现不一致"
                    f"（返回 声明={归一注册口径(声明.返回)} 实现={归一注册口径(实现.返回)}；"
                    f"参数 声明={[_参数名(参数) for 参数 in 声明.参数]}"
                    f" 实现={[_参数名(参数) for 参数 in 实现.参数]}）"
                )
        for 实现 in self._实现表.values():
            if 实现.包id == 包id and not any(声明.能力id == 实现.能力id for 声明 in 声明列表):
                问题列表.append(f"{实现.能力id}: 已注册实现但未在声明中列出")
        return 问题列表
