"""能力调用器契约：模块按能力 id 调用支持库的唯一通道。

模块不 import 支持库/提供者/运行核心实现；只经本契约文件声明的
调用器接口获取"按能力 id 调用"的注入调用器。运行核心装配时调用
注册注入；未装配时第一次获取触发惰性装配（保证任意入口可用）。

装配状态机（唯一事实源，本文件内全局原子状态）：
- 未装配：未注入调用器（进程冷启动默认）；获取 → E未装配（或触发惰性装配）。
- 装配中：装配进行中；获取 → E装配中（禁止并发重复装配）。
- 已装配：注入完成；获取直接返回；重复装配幂等（装配次数递增）。
- 装配失败：上次装配失败；获取 → E装配失败，必须重新装配才能恢复。
每个状态都有明确 状态/错误码/错误说明，经 查询装配状态() 可观测。
"""

from __future__ import annotations

import threading
import time
from typing import Any, Protocol


class 能力调用器(Protocol):
    """能力调用器协议：按能力 id 调用、查询历史、失败诊断。"""

    def 调用能力(self, 能力id: str, 参数: dict[str, Any] | None = None, *,
                 调用方: str = "", 项目id: str = "", 超时秒: float | None = None) -> Any: ...

    def 幂等重放(self, 能力id: str, 参数: dict[str, Any]) -> bool: ...

    def 查询调用历史(self, 上限: int = 50) -> list[dict[str, Any]]: ...

    def 最近失败(self, 上限: int = 10) -> list[dict[str, Any]]: ...

    def 回答九问(self, 能力id: str, 错误码: str) -> dict[str, str]: ...


# ── 装配状态机 ──────────────────────────────────────────────────

装配状态表 = ("未装配", "装配中", "已装配", "装配失败")

错误码未装配 = "E未装配"
错误码装配中 = "E装配中"
错误码装配失败 = "E装配失败"


class 能力调用器状态异常(RuntimeError):
    """获取能力调用器时的装配状态异常：携带 状态/错误码/错误说明。

    兼容旧 RuntimeError 语义（模块实现 catch RuntimeError 转统一失败结果），
    同时暴露结构化字段供上层诊断与测试断言。
    """

    def __init__(self, *, 状态: str, 错误码: str, 错误说明: str) -> None:
        self.状态 = 状态
        self.错误码 = 错误码
        self.错误说明 = 错误说明
        super().__init__(f"[{错误码}] 能力调用器状态={状态}: {错误说明}")


_全局调用器: 能力调用器 | None = None
_全局锁 = threading.Lock()
_惰性装配函数: Any = None
# 装配状态唯一事实（与 _全局调用器 同锁保护）
_装配状态 = "未装配"
_装配错误码 = ""
_装配错误说明 = ""
_装配次数 = 0
_装配最近时间 = ""


def _写装配状态(状态: str, *, 错误码: str = "", 错误说明: str = "") -> None:
    """写装配状态（必须在 _全局锁 内调用）。"""
    global _装配状态, _装配错误码, _装配错误说明, _装配最近时间, _装配次数
    _装配状态 = 状态
    _装配错误码 = 错误码
    _装配错误说明 = 错误说明
    _装配最近时间 = time.strftime("%Y-%m-%d %H:%M:%S")
    if 状态 == "已装配":
        _装配次数 += 1


def 标记装配中() -> None:
    """装配开始：未装配/装配失败 → 装配中。"""
    with _全局锁:
        _写装配状态("装配中")


def 标记装配完成() -> None:
    """装配成功：任意状态 → 已装配（重复装配幂等，次数递增）。"""
    with _全局锁:
        _写装配状态("已装配")


def 标记装配失败(错误码: str = 错误码装配失败, 错误说明: str = "") -> None:
    """装配失败：回滚为 装配失败 并记录错误码/错误说明（不留半状态）。"""
    with _全局锁:
        _写装配状态("装配失败", 错误码=错误码, 错误说明=错误说明)


def 标记销毁() -> None:
    """销毁对称：卸载调用器后回到 未装配（测试间不得残留能力）。"""
    with _全局锁:
        _写装配状态("未装配")


def 查询装配状态() -> dict[str, str | int]:
    """查询装配状态：状态/错误码/错误说明/装配次数/最近时间。"""
    with _全局锁:
        return {
            "状态": _装配状态,
            "错误码": _装配错误码,
            "错误说明": _装配错误说明,
            "装配次数": _装配次数,
            "最近时间": _装配最近时间,
        }


# ── 注册与获取 ──────────────────────────────────────────────────


def 注册能力调用器(调用器: 能力调用器 | None) -> None:
    """运行核心装配后注册/卸载全局调用器（None 表示卸载）。

    注册 → 已装配（重复注册幂等）；卸载 → 未装配（销毁对称）。
    """
    global _全局调用器
    with _全局锁:
        _全局调用器 = 调用器
    if 调用器 is None:
        标记销毁()
    else:
        标记装配完成()


def 设置惰性装配函数(函数) -> None:
    """运行核心注册惰性装配钩子：首次获取调用器且未装配时调用。"""
    global _惰性装配函数
    with _全局锁:
        _惰性装配函数 = 函数


def 获取能力调用器() -> 能力调用器:
    """模块实现内获取注入的能力调用器。

    状态语义：
    - 已装配：直接返回注入调用器（权威注册表，禁止绕过）。
    - 装配中：抛 能力调用器状态异常（错误码 E装配中），禁止并发重复装配。
    - 装配失败：抛 能力调用器状态异常（错误码 E装配失败 + 失败原因），
      必须重新装配（装配系统/创建并绑定）才能恢复。
    - 未装配：存在惰性装配钩子则触发一次惰性装配；无钩子抛
      能力调用器状态异常（错误码 E未装配）。
    进程重启后为全新 未装配 状态，重新装配即可恢复。
    """
    with _全局锁:
        状态 = _装配状态
        调用器 = _全局调用器
    if 调用器 is not None and 状态 == "已装配":
        return 调用器
    if 状态 == "装配中":
        raise 能力调用器状态异常(
            状态="装配中", 错误码=错误码装配中,
            错误说明="装配正在进行中，禁止并发获取（等待装配完成后重试）",
        )
    if 状态 == "装配失败":
        raise 能力调用器状态异常(
            状态="装配失败", 错误码=_装配错误码 or 错误码装配失败,
            错误说明=_装配错误说明 or "上次装配失败，必须重新装配后恢复",
        )
    with _全局锁:
        惰性装配 = _惰性装配函数
    if 惰性装配 is None:
        raise 能力调用器状态异常(
            状态="未装配", 错误码=错误码未装配,
            错误说明="能力调用器未注入且无惰性装配钩子：模块必须由加载器装配后调用，"
                      "禁止直接导入支持库/提供者绕过能力调用服务",
        )
    标记装配中()
    try:
        惰性装配()
    except Exception as 错误:
        失败说明 = f"{type(错误).__name__}: {错误}"
        标记装配失败(错误码装配失败, 失败说明)
        raise 能力调用器状态异常(
            状态="装配失败", 错误码=错误码装配失败, 错误说明=失败说明,
        ) from 错误
    with _全局锁:
        if _全局调用器 is not None:
            return _全局调用器
    标记装配失败(错误码装配失败, "惰性装配结束但调用器仍未注入")
    raise 能力调用器状态异常(
        状态="装配失败", 错误码=错误码装配失败,
        错误说明="惰性装配结束但调用器仍未注入",
    )
