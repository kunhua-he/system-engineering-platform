def _监听枚举工具() -> str | None:
    """返回端口占用进程枚举工具（``lsof``）的绝对路径；本机没有则返回 ``None``。

    **B-11 收口点**：端口回收要靠 ``lsof`` 把「监听某端口的进程」枚举出来，再与句柄
    登记的归属 PID 比对，只杀本句柄归属的进程（第 9 条 5 项：回收必须自证归属）。
    该工具**不是全平台必备**（精简 Linux 容器、部分 Windows 环境都没有）——修前是
    直接 ``subprocess.run(["lsof", ...])``，工具缺失时抛 ``FileNotFoundError`` 被就地
    吞掉，回收结论含糊、调用方只能反复重试。

    这里把「工具在不在」显式化：探测结果缓存（进程生命周期内工具不会凭空出现），
    缺失时调用点**明确报告本平台无此能力**，不猜杀、不自造第二套枚举实现。

    收口层复用说明：同仓 ``公共契约/运行时/平台适配/`` 只提供平台判定、虚拟环境
    解释器、``句柄枚举目录表``、``内存峰值原始单位``、``子进程组启动标志`` 与
    ``要求POSIX能力``；``进程终止.py`` 只收口「探活 / 终止（组/树）/ 等待消失 /
    强制结束子进程」。**两者都没有「端口 → 占用进程」的跨平台枚举**，仓内也没有
    第二处端口归属实现（``发布门禁`` 自带一份仅供门禁自用的 ``lsof`` 快照）。
    故本轮不做跨平台收口（不在本文件自创第二套实现），只把缺失态显式化并如实报告。
    """
    global _监听枚举路径
    if _监听枚举路径 is _未探测:
        try:
            _监听枚举路径 = shutil.which(_监听枚举工具名)
        except Exception as 错误:  # 允许忽略，但留痕（哲学第 3 条 2 项）
            记录忽略('句柄体系._监听枚举工具', 错误)
            _监听枚举路径 = None
    return _监听枚举路径 or None


def 是合法句柄id(句柄id: str | int) -> bool:
    """公共对外句柄格式：固定六位数字字符串（兼容历史整数调用）。"""
    if isinstance(句柄id, str):
        return len(句柄id) == 句柄位数 and 句柄id.isascii() and 句柄id.isdecimal()
    return isinstance(句柄id, int) and not isinstance(句柄id, bool) and 1 <= 句柄id <= 999999


def 校验句柄型(值: Any) -> bool:
    """`句柄型` 的**唯一强度判定**（B-2 收口）——本函数是全平台判「什么算句柄型」的唯一一处。

    合法形态只有两种：
    1. 合法句柄 id：六位数字文本（``"123456"``）或 1..999999 的整数（``123456``），
       判定全部委托 `是合法句柄id`，本函数不复制位数/范围口径；
    2. 进程内可调用句柄（回调函数）：JSON 表达不了，只可能来自进程内直调。

    明确判**不是**句柄型：任意文本（``"abc"``）、五位数字、越界整数、布尔（``True`` 是
    ``int`` 子类）、空值、对象。修前网关侧写 ``isinstance(值, (int, str, callable))``、
    契约侧另有六位口径，两套强度——任意字符串都能当句柄穿过边界（实证见
    `测试中心/运行核心/测试_网关类型收口.py::test_句柄型与公共六位口径同强度`）。
    调用方一律经本函数或 `确保句柄型`，不得自造第二套判定。
    """
    if callable(值):
        return 真
    return 是合法句柄id(值)


def 确保句柄型(值: Any) -> Any:
    """校验并返回 `句柄型`；不符合时抛稳定的 ``TypeError``（与 `确保数值类型` 同口径）。"""
    if not 校验句柄型(值):
        raise TypeError(f"值不符合句柄型契约：{值!r}（合法形态只有 六位数字句柄 或 进程内可调用句柄）")
    return 值


def 生成句柄id() -> int:
    """生成 1 到 999999 的整数句柄；资源表负责校验活动句柄冲突。"""
    return secrets.randbelow(999999) + 1

@dataclass
class 句柄:
    句柄id: int = 0
    句柄类型: str = 句柄类型_资源
    资源id: str = ""
    项目id: str = ""
    所有者: str = ""
    状态: str = 状态_已创建
    创建时间: str = ""
    失效时间: str = ""
    失效原因: str = ""
    版本: str = ""
    元数据: dict[str, Any] = field(default_factory=dict)
    绑定资源: list[dict[str, Any]] = field(default_factory=list)   # 句柄绑定的资源清单

    def 转字典(self) -> dict[str, Any]:
        return {"句柄id": self.句柄id, "句柄类型": self.句柄类型, "资源id": self.资源id,
                "项目id": self.项目id, "所有者": self.所有者, "状态": self.状态,
                "创建时间": self.创建时间, "失效时间": self.失效时间,
                "失效原因": self.失效原因, "版本": self.版本,
                "绑定资源数": len(self.绑定资源)}


class 句柄体系:
    def __init__(self) -> None:
        # 键 = 规范 id（整数或六位串）或**请求键别名**（旧整数客户端/六位串客户端命中同一账本对象）；
        # 访问一律经 查询句柄() / 别名句柄() 持 `_锁`，类外禁止直接触碰本表。
        self.句柄表: dict[int | str, 句柄] = {}
        self.回收证据表: deque[dict[str, Any]] = deque(maxlen=回收证据上限)
        self.失效id留痕: deque[int | str] = deque(maxlen=失效id留痕上限)   # 已淘汰句柄的 id（幂等判定）
        self.已淘汰句柄数: int = 0                                    # 累计真正删除的已失效行数（可观测）
        # **B-06 修**：内部短临界区可重入（RLock）。评估见 `_锁类型说明`：
        # 回收动作已全部移出锁外，两段式本身不需要可重入；改 RLock 是防御性的——
        # 「清理函数」是调用方注入的外部回调，一旦将来有路径在持锁时回调本体系，
        # 普通 Lock 会**永久自锁死**，RLock 至少能推进。锁内禁止阻塞 I/O 与外部回调
        # 的硬约束不因锁类型放松。
        self._锁类型说明 = "RLock：短临界区可重入，防外部回调同线程重入时永久自锁死"
        self._锁 = threading.RLock()
        # 同一句柄的「失效回收方」登记表：句柄id → 收口事件。保证同一句柄同时只有一个
        # 线程跑回收 I/O，其余失效调用等它收口后按**真实终态**重新判定（事件驱动，不轮询）。
        self._失效进行中: dict[int, threading.Event] = {}

    def 创建句柄(self, *, 句柄类型: str, 资源id: str, 项目id: str = "", 所有者: str = "", 版本: str = "") -> 句柄:
        with self._锁:
            for _ in range(100):
                句柄id = 生成句柄id()
                if 句柄id not in self.句柄表:
                    对象 = 句柄(句柄id, 句柄类型, 资源id, 项目id, 所有者, 状态_有效,
                                time.strftime("%Y-%m-%d %H:%M:%S"), 版本=版本)
                    self.句柄表[句柄id] = 对象
                    return 对象
        raise RuntimeError("六位句柄已耗尽")

    def 恢复句柄(self, 对象: 句柄) -> 句柄:
        """从权威账本恢复句柄；禁止覆盖本进程已存在的不同对象。"""
        if not 是合法句柄id(对象.句柄id):
            raise ValueError("恢复句柄id不合法")
        if 对象.状态 not in (状态_已创建, 状态_有效, 状态_已失效):
            raise ValueError("恢复句柄状态不合法")
        with self._锁:
            已有 = self.句柄表.get(对象.句柄id)
            if 已有 is not None:
                if 已有.资源id != 对象.资源id or 已有.项目id != 对象.项目id or 已有.所有者 != 对象.所有者:
                    raise RuntimeError("句柄账本与内存对象冲突")
                return 已有
            self.句柄表[对象.句柄id] = 对象
            return 对象

    # ── 句柄表访问收口（真竞态修）────────────────────────────────
    # `句柄表` 是跨线程共享的可变字典：`创建句柄` / `恢复句柄` / `失效` / `_淘汰失效句柄`
    # 都在 `_锁` 内改它。锁外任何直接读写都会让「锁内全表遍历」
    # （`_淘汰失效句柄`，由 `失效()` 调用）与「锁外写」并发，遍历方抛
    # `RuntimeError: dictionary changed size during iteration`，
    # 把一次**合法的句柄关闭/失效调用**打成 500（修前实证：运行核心/资源协调/句柄服务.py:96-99
    # 直接 `句柄表[句柄id] = 对象`；200 轮并发探针 66 轮命中，异常全部从合法 `关闭()` 调用逃出）。
    # 故类外一律经下面两个方法，禁止直接触碰 `句柄表`。

    def 查询句柄(self, 句柄id: int | str) -> 句柄 | None:
        """按句柄 id 定位对象（唯一加锁读入口）。

        与直接 `句柄表.get` 逐字节等价（不存在返回 ``None``），差别只是持 `_锁`：
        读共享可变容器同样要收口——锁内全表遍历期间读到的中间态不可信。
        """
        with self._锁:
            return self.句柄表.get(句柄id)

    def 别名句柄(self, 句柄id: int | str, 对象: 句柄) -> 句柄:
        """登记「请求键 → 账本对象」的别名行（唯一加锁写入口）。

        场景：账本行以整数落库（SQLite TEXT 亲和性读回为字符串 ``'123'``），内存对象按
        六位零填充规范为 ``'000123'``，两者不等；为使旧整数客户端与六位串客户端命中
        **同一个账本对象**，`句柄服务._加载句柄` 需要补登记请求键这一行。

        与 `恢复句柄` 的分工：`恢复句柄` 建立**规范 id** 的行并拒绝覆盖冲突对象；
        本方法只补别名行，语义与修前那句直接赋值逐字一致（不新增可拒绝分支，
        避免把既有可答路径变成硬失败）。
        """
        with self._锁:
            self.句柄表[句柄id] = 对象
            return 对象

    def 校验(self, 句柄id: int, *, 项目id: str = "", 所有者: str = "") -> tuple[bool, str]:
        对象 = self.查询句柄(句柄id)
        if 对象 is None: return 假, f"句柄不存在: {句柄id}"
        if 对象.状态 != 状态_有效: return 假, f"句柄已失效（{对象.失效原因}），不能自动复活"
        if 对象.项目id and 对象.项目id != 项目id: return 假, f"跨项目复用被拒绝: 句柄属 {对象.项目id}，请求 {项目id or '未提供'}"
        if 对象.所有者 and 对象.所有者 != 所有者: return 假, f"跨所有者复用被拒绝: 句柄属 {对象.所有者}，请求 {所有者 or '未提供'}"
        return 真, "句柄有效"

    # ── 资源登记（状态机内置，华哥口径）────────────────

    def 登记资源(self, 句柄id: int, *, 资源类型: str, PID: int = None, 端口: int = None,
                 资源路径: str = None, 清理函数: Any = None) -> tuple[bool, str]:
        """把资源绑定到句柄，由状态机统一监控/回收。资源类型：进程/端口/连接/临时文件。"""
        with self._锁:
            对象 = self.句柄表.get(句柄id)
            if 对象 is None: return 假, f"句柄不存在: {句柄id}"
            if 对象.状态 != 状态_有效: return 假, f"句柄已失效，不能登记资源: {句柄id}"
            if len(对象.绑定资源) >= 句柄绑定资源上限:
                return 假, f"句柄绑定资源超过上限 {句柄绑定资源上限}"
            对象.绑定资源.append({
                "资源类型": 资源类型, "PID": PID, "端口": 端口, "资源路径": 资源路径,
                "清理函数": 清理函数, "已回收": 假, "回收说明": "",
            })
            return 真, "资源已绑定句柄"

    def 查询资源(self, 句柄id: int) -> list[dict[str, Any]]:
        """查询句柄绑定的资源（审计）。"""
        with self._锁:
            对象 = self.句柄表.get(句柄id)
            if 对象 is None: return []
            return [{"资源类型": r["资源类型"], "PID": r["PID"], "端口": r["端口"],
                     "资源路径": r["资源路径"], "已回收": r["已回收"], "回收说明": r["回收说明"]}
                    for r in 对象.绑定资源]

    def _检查进程存活(self, pid: int) -> bool:
        """检查 PID 是否存活（排除 zombie）。

        存活探测走跨平台收口层：Windows 上对非控制台信号发 0 号信号等于
        ``TerminateProcess``，裸调会把目标进程**真杀掉**——故本处一律经
        ``进程终止.进程存活``，由收口层按平台选 WinAPI 或 POSIX 探活。
        """
        if not isinstance(pid, int) or pid <= 0:
            return 假
        if not 进程终止.进程存活(pid):
            return 假
        try:
            r = subprocess.run(["ps", "-o", "state=", "-p", str(pid)], capture_output=True, text=True, timeout=3)
            if r.stdout.strip() and r.stdout.strip()[0] in ("Z", "X"):
                return 假
        except Exception as 错误:  # 允许忽略，但留痕（哲学第 3 条 2 项）
            记录忽略('句柄体系._检查进程存活', 错误)
        return 真

    def _端口被占用(self, 端口: int) -> bool:
        """检查本机端口是否仍被监听占用（与 进程 分支的存活复查对称）。"""
        if not isinstance(端口, int) or 端口 <= 0:
            return 假
        import socket
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
                s.settimeout(1)
                return s.connect_ex(("127.0.0.1", 端口)) == 0
        except Exception:
            return 假

    def _端口归属PID(self, 端口资源: dict, 同句柄资源: list[dict] | None = None) -> set[int]:
        """端口归属判定（第 9 条 5 项：回收必须自证归属，不猜、不误杀）。

        归属来源只有两处，都在登记时写入状态机：① 该端口资源自身登记的 PID；
        ② 同一句柄下、端口相同的那条「进程」资源登记的 PID。
        两处都取不到 → 返回空集，回收方只能报告、不得按 lsof 枚举结果强杀。
        """
        候选: set[int] = set()
        自己 = 端口资源.get("PID")
        if isinstance(自己, int) and 自己 > 0:
            候选.add(自己)
        端口 = 端口资源.get("端口")
        for 其他 in (同句柄资源 or []):
            if 其他 is 端口资源:
                continue
            if 其他.get("资源类型") == "进程" and 其他.get("端口") == 端口:
                pid = 其他.get("PID")
                if isinstance(pid, int) and pid > 0:
                    候选.add(pid)
        return 候选

    def _回收单个资源(self, 资源: dict, 同句柄资源: list[dict] | None = None) -> tuple[bool, str, str]:
        """核查单个资源：存活→回收；否则标记已回收（幂等）。

        **调用约定（B-06 修）**：本函数含阻塞 I/O（终止、等待死透、``ps`` 探活、
        ``lsof`` 枚举，单资源最坏 7–10 秒），**只允许在 `_锁` 之外调用**——它由
        `核查回收` 的第二段（锁外段）调用，内部一律不碰 `self._锁`。

        **判据口径（P1-6 收口）**：返回 ``(已回收, 回收结论, 说明)``。成败由**各回收分支
        显式给枚举**（`回收结论_已回收` / `回收结论_未回收`），布尔由枚举推出；
        `说明` 只作人读文案，**不参与任何判定**。

        修前是「先拼说明、再用 ``"无泄露"/"已删除"/"已释放"/"已清理"/"已终止"/"已调用清理函数"
        in 说明`` 反推成败」——改一句中文文案（例如「无泄露」→「无泄漏」）就**静默翻转回收结论**，
        未收敛的资源被 `失效` 判成已收敛（真缺陷；本条已配改文案反向验证）。
        """
        类型 = 资源["资源类型"]
        结论 = 回收结论_未回收
        说明 = ""
        try:
            if 类型 == "进程":
                pid = 资源["PID"]
                if pid and self._检查进程存活(pid):
                    try:
                        # 组长判定与「整组 / 单进程」的选择全部由收口层负责，调用点不判平台
                        进程终止.终止进程组(pid, 信号="终止")
                    except Exception as 错误:  # 允许忽略，但留痕（哲学第 3 条 2 项）
                        记录忽略('句柄体系._回收单个资源', 错误)
                    # 等待死透走收口层的事件式等待（进程一消失立即返回，最多等 _回收等待秒）：
                    # 上限与修前固定 `time.sleep(1)` 相同，进程立刻退出时不再白等满 1 秒。
                    进程终止.等待进程消失(pid, 超时秒=_回收等待秒)
                    try:
                        if self._检查进程存活(pid):
                            进程终止.终止进程组(pid, 信号="强杀")
                    except Exception as 错误:  # 允许忽略，但留痕（哲学第 3 条 2 项）
                        记录忽略('句柄体系._回收单个资源', 错误)
                    仍存活 = self._检查进程存活(pid)   # 回收后复查：只认探活结果，不认文案
                    结论 = 回收结论_未回收 if 仍存活 else 回收结论_已回收
                    说明 = "进程仍存活（回收失败）" if 仍存活 else "已终止进程（含进程组）"
                else:
                    # 进程不在（含 zombie 已死）→ 补杀一次确保回收干净
                    try:
                        # 非整数 PID 由收口层按「参数错误」明确拒绝（不静默跳过）
                        进程终止.终止进程组(pid, 信号="强杀")
                    except Exception as 错误:  # 允许忽略，但留痕（哲学第 3 条 2 项）
                        记录忽略('句柄体系._回收单个资源', 错误)
                    结论 = 回收结论_已回收
                    说明 = "进程已不存在（无泄露）"
            elif 类型 == "端口":
                端口 = 资源["端口"]
                归属表 = self._端口归属PID(资源, 同句柄资源)
                if not isinstance(端口, int) or 端口 <= 0:
                    结论 = 回收结论_已回收
                    说明 = "无端口（无泄露）"  # 与 进程 分支「进程已不存在（无泄露）」对称
                elif not self._端口被占用(端口):
                    结论 = 回收结论_已回收
                    说明 = "端口已释放（无泄露）"
                elif not 归属表:
                    说明 = (f"端口 {端口} 仍被占用，但本句柄未登记归属进程"
                           f"（第 9 条 5 项：只报告、不按 lsof 猜杀无关进程）")
                else:
                    # B-11：枚举工具先探测再调用。缺失时**明确报告本平台无此能力**，
                    # 结论如实为「未回收」，由调用方拿到确定的失败，而不是含糊的成功或重试循环。
                    枚举工具 = _监听枚举工具()
                    if 枚举工具 is None:
                        说明 = (f"端口 {端口} 仍被占用，且本机无 {_监听枚举工具名} 无法枚举占用进程"
                               f"（第 9 条 5 项：只报告、不自造第二套枚举实现）")
                    else:
                        try:
                            r = subprocess.run([枚举工具, "-nP", "-iTCP:%d" % 端口, "-sTCP:LISTEN", "-t"],
                                               capture_output=True, text=True, timeout=5)
                        except Exception as 错误:
                            说明 = f"端口 {端口} 仍被占用，且无法枚举占用进程: {错误}"
                        else:
                            占用进程 = [int(文本) for 文本 in r.stdout.strip().split()
                                        if 文本.strip().isdigit()]
                            if not 占用进程:
                                说明 = f"端口 {端口} 仍被占用（未枚举到可清理进程）"
                            else:
                                越权 = [pid for pid in 占用进程 if pid not in 归属表]
                                if 越权:
                                    记录忽略('句柄体系.回收端口占用进程', f"端口 {端口} 存在非本句柄归属进程 {越权}，跳过")
                                归属内 = [pid for pid in 占用进程 if pid in 归属表]
                                for pid in 归属内:
                                    try: 进程终止.终止进程组(pid, 信号="强杀")
                                    except (ProcessLookupError, PermissionError) as 错误:
                                        # 允许忽略，但留痕（哲学第 3 条 2 项）：进程刚退出 / 无权限杀，
                                        # 后果由紧随其后的端口复查兜住。
                                        记录忽略('句柄体系.回收端口占用进程', 错误)
                                # 等死透（事件式等待，总预算 _回收等待秒，与修前固定 sleep(1) 同上限）
                                截止 = time.monotonic() + _回收等待秒
                                for pid in 归属内:
                                    进程终止.等待进程消失(pid, 超时秒=max(0.0, 截止 - time.monotonic()))
                                # 回收后必须复查端口是否真的释放；kill 被吞掉、权限不足或
                                # 进程忽略 SIGKILL 时不得谎报「已清理」（原实现无条件宣告
                                # 已清理，与 进程 分支的存活复查口径不一致）。
                                仍被占用 = self._端口被占用(端口)   # 只认复查结果，不认文案
                                结论 = 回收结论_未回收 if 仍被占用 else 回收结论_已回收
                                说明 = (f"端口 {端口} 仍被占用（回收失败）" if 仍被占用
                                       else f"端口 {端口} 占用进程已清理")
            elif 类型 == "临时文件":
                路径 = 资源["资源路径"]
                if 路径 and os.path.isfile(路径):
                    try:
                        os.remove(路径)
                    except Exception as 错误:
                        说明 = f"临时文件删除失败: {错误}"
                    else:
                        结论 = 回收结论_已回收
                        说明 = f"临时文件 {路径} 已删除"
                else:
                    结论 = 回收结论_已回收
                    说明 = "临时文件本就不存在（无泄露）"
            else:
                # 连接等资源：由清理函数回收
                清理函数 = 资源["清理函数"]
                if callable(清理函数):
                    # #155（2026-09-20）：原实现**无条件**判「已回收」—— 清理函数返回
                    # `False`/`None`（明确表示没清掉）时报告仍称已回收，属静默降级，
                    # 与同函数里进程/临时文件分支的复查口径不一致（那两支都会核对现场）。
                    # 现按返回值判定：显式 `False` 记为未回收；其余（None/True/无返回）
                    # 视为「已调用成功」，因为多数清理函数按惯例不返回值，
                    # 若把 None 也判未回收会把全部既有正常路径误报成泄漏。
                    清理结果 = 清理函数()
                    if 清理结果 is False:
                        结论 = 回收结论_未回收
                        说明 = "清理函数显式返回 False（自述未回收）"
                    else:
                        结论 = 回收结论_已回收
                        说明 = "已调用清理函数回收"
                else:
                    说明 = f"连接资源需清理函数回收（无）"
        except Exception as 错误:
            结论 = 回收结论_未回收
            说明 = f"回收异常: {错误}"
        return 结论 == 回收结论_已回收, 结论, 说明

    def 核查回收(self, 句柄id: int) -> dict[str, Any]:
        """句柄失效时核查所有绑定资源，未回收的补回收一趟（幂等）。状态机统一维护。

        **两段式（B-06 修）**：修前本方法在整个回收过程里持 ``self._锁``——而回收内部
        有 ``时间.sleep(1)``、``ps``（timeout=3）、``lsof``（timeout=5），单条进程资源
        最坏 7–10 秒；同一把锁又是 ``创建句柄``（网关「获取句柄=True」热路径）、
        ``登记资源``、``失效`` 的必经之路，于是**一次回收即让全平台停摆数秒**。
        现在拆成三段，锁内零阻塞 I/O：

        1. **锁内**：定位句柄 + 取资源清单 + 给待回收资源打「回收中」标记；
        2. **锁外**：真正的回收动作（终止 / 等死透 / 探活 / 枚举占用进程）；
        3. **锁内**：把本轮结果写回资源行（``已回收`` / ``回收说明`` / 清「回收中」）并组信封。

        「回收中」标记保证同一资源不会被两个回收方重复 kill；本轮没拿到标记的资源
        **如实报告未收口**，不冒充成功（否则 ``失效`` 会把未回收的句柄判成已收敛）。
        对外返回信封（键、顺序、说明文案）与修前一致；`:301-308` 的 id 语义不变。
        """
        # ── 第一段（锁内）：定位 + 取清单 + 打「回收中」标记，零阻塞 I/O ──
        with self._锁:
            对象 = self.句柄表.get(句柄id)
            if 对象 is None:
                return {"句柄": 句柄id, "已回收数": 0, "资源总数": 0, "回收清单": []}
            资源快照 = list(对象.绑定资源)
            待回收 = [资源 for 资源 in 资源快照
                      if not 资源["已回收"] and not 资源.get("回收中")]
            for 资源 in 待回收:
                资源["回收中"] = 真

        # ── 第二段（锁外）：回收动作全在这里，锁已释放，热路径不受影响 ──
        本轮结果: dict[int, tuple[bool, str, str]] = {}
        for 资源 in 待回收:
            本轮结果[id(资源)] = self._回收单个资源(资源, 资源快照)

        # ── 第三段（锁内）：写回终态 + 组信封（对外形状与修前逐字一致）──
        with self._锁:
            现有对象 = self.句柄表.get(句柄id)
            回收清单 = []
            已回收数 = 0
            for 资源 in 资源快照:
                本轮 = 本轮结果.get(id(资源))
                if 本轮 is not None:
                    已回收, 结论, 说明 = 本轮
                    资源["已回收"] = 已回收
                    资源["回收说明"] = 说明
                    资源["回收中"] = 假
                elif 资源["已回收"]:
                    已回收, 结论, 说明 = 真, 回收结论_已回收, "已在先前回收（幂等）"
                else:
                    # 并发回收方仍持「回收中」标记：本轮如实报告进行中，不冒充成功。
                    已回收, 结论, 说明 = 假, 回收结论_未回收, "回收进行中（并发回收方持有）"
                回收清单.append({"资源类型": 资源["资源类型"], "已回收": 已回收, "说明": 说明})
                已回收数 += 1 if 已回收 else 0
            资源总数 = len(现有对象.绑定资源) if 现有对象 is not None else len(资源快照)
            return {"句柄": 句柄id, "已回收数": 已回收数, "资源总数": 资源总数,
                    "回收清单": 回收清单}

    def _登记失效回收方(self) -> threading.Event:
        """新建一个「本句柄回收中」的收口事件（调用方必须已持 `_锁`）。"""
        return threading.Event()

    def _释放失效回收方(self, 句柄id: int, 事件: threading.Event) -> None:
        """撤销回收方登记并唤醒等待者（调用方必须已持 `_锁`）。"""
        if self._失效进行中.get(句柄id) is 事件:
            self._失效进行中.pop(句柄id, None)
        事件.set()

    def 失效(self, 句柄id: int, 原因: str) -> tuple[bool, str]:
        """把句柄推到终态「已失效」，并在**锁外**完成绑定资源回收。

        **并发收口（B-06 修）**：修前本方法全程无锁——线程 A 把状态改成「已失效」后
        去跑数秒的回收，线程 B 读到「已失效」便直接回「幂等成功」，而线程 A 随后可能
        因资源未收敛把状态**回滚成有效**：B 的调用方被告知「已失效」，共享状态却是「有效」
        （实证见交付记录「并发失效落错终态 = 真」）。现在同一句柄只允许一个回收方：
        锁内登记事件，其余线程**事件驱动**等它收口后按真实终态重新判定。

        锁内只做状态迁移与登记（零阻塞 I/O），回收 I/O 在锁外，热路径不再被停摆。
        """
        while True:
            with self._锁:
                对象 = self.句柄表.get(句柄id)
                if 对象 is None:
                    # 行可能已被淘汰（已失效行超过保留窗口后被真删）：已淘汰的 id 仍按
                    # 「已失效（幂等）」答复，使 组件控件.释放句柄 / 浏览器自动化.关闭会话 等
                    # 依赖「重复释放返回成功」的调用方不因淘汰而变成硬失败。
                    # 注意：这里能到「行不存在」分支，说明该 id 当前未被复用为有效句柄（复用则 对象 非空）。
                    if 句柄id in self.失效id留痕:
                        return 真, "句柄已失效（已淘汰，幂等）"
                    return 假, f"句柄不存在: {句柄id}"
                回收方 = self._失效进行中.get(句柄id)
                if 回收方 is None:
                    if 对象.状态 == 状态_已失效:
                        return 真, "句柄已失效（幂等）"
                    # 成为本句柄唯一的回收方：登记事件 → 锁内完成状态迁移 → 出锁做 I/O
                    回收事件 = self._登记失效回收方()
                    self._失效进行中[句柄id] = 回收事件
                    原状态, 原失效时间, 原失效原因 = 对象.状态, 对象.失效时间, 对象.失效原因
                    对象.状态 = 状态_已失效; 对象.失效时间 = time.strftime("%Y-%m-%d %H:%M:%S"); 对象.失效原因 = 原因
                    break
            # 另一个线程正在回收本句柄：等它收口（事件驱动，不轮询、不占锁），再按真实终态重判
            if not 回收方.wait(_失效回收等待上限秒):
                return 假, f"句柄失效等待回收收口超时（{_失效回收等待上限秒:g} 秒），可重试"

        回收结果 = None
        异常说明 = ""
        try:
            回收结果 = self.核查回收(句柄id)
        except Exception as 错误:
            异常说明 = f"句柄未失效且资源回收异常: {type(错误).__name__}"

        with self._锁:
            try:
                if 回收结果 is None:
                    回滚 = 真
                    结论 = (假, 异常说明)
                elif 回收结果["已回收数"] != 回收结果["资源总数"]:
                    回滚 = 真
                    结论 = (假, f"资源未收敛（{回收结果['已回收数']}/{回收结果['资源总数']}）")
                else:
                    回滚 = 假
                    self.回收证据表.append({"句柄id": 句柄id, "资源id": 对象.资源id, "类型": 对象.句柄类型,
                                          "失效原因": 原因, "时间": 对象.失效时间, "版本": 对象.版本})
                    self._淘汰失效句柄(time.time())
                    结论 = (真, f"句柄已失效（{原因}）")
                # 回滚只在「该行仍是本回收方置的失效态」时执行：并发/淘汰改过状态就不覆盖它
                if 回滚 and 对象.状态 == 状态_已失效:
                    对象.状态, 对象.失效时间, 对象.失效原因 = 原状态, 原失效时间, 原失效原因
            finally:
                # 无论成败都要撤销回收方登记并唤醒等待者，否则等待方会白等到超时
                self._释放失效回收方(句柄id, 回收事件)
        return 结论

    def _淘汰失效句柄(self, 当前时间: float) -> int:
        """真正删除超保留期的「已失效」行，让句柄表有界（哲学：有界即正确）。

        双限收敛，只留少量审计必要信息：
        - 时长：`失效时间` 早于 `当前时间 - 失效句柄保留秒` 的行立即删除；
        - 条数：仍在时长窗口内的已失效行最多保留 `失效句柄保留数` 条，多余的按
          失效时间从旧到新删除（时间字符串定宽零填充，可直接字典序比较，无需解析）。
        被删行的 id 记入有界 `失效id留痕`，保证 `失效` 的重复调用仍是幂等成功。
        调用方必须在 `_锁` 内调用（本函数直接改动 `句柄表`）。
        """
        截止文本 = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(当前时间 - 失效句柄保留秒))
        超期行: list[int | str] = []
        窗内行: list[tuple[str, int | str]] = []
        for 句柄id, 对象 in self.句柄表.items():
            if 对象.状态 != 状态_已失效:
                continue
            if 对象.失效时间 and 对象.失效时间 < 截止文本:
                超期行.append(句柄id)
            else:
                窗内行.append((对象.失效时间, 句柄id))
        淘汰清单 = list(超期行)
        超额 = len(窗内行) - 失效句柄保留数
        if 超额 > 0:
            窗内行.sort(key=lambda 项: 项[0])   # 稳定排序：同一秒内按插入先后淘汰
            淘汰清单.extend(句柄id for _, 句柄id in 窗内行[:超额])
        for 句柄id in 淘汰清单:
            self.句柄表.pop(句柄id, None)
            self.失效id留痕.append(句柄id)
        self.已淘汰句柄数 += len(淘汰清单)
        return len(淘汰清单)

    def 查询回收证据(self, *, 资源id: str = "") -> list[dict[str, Any]]:
        with self._锁:
            return [x for x in self.回收证据表 if not 资源id or x["资源id"] == 资源id]

    def 活跃句柄数(self) -> int:
        # 持锁读：修前无锁遍历 `句柄表`，与 `创建句柄`/`失效`/`_淘汰失效句柄` 的写
        # 并发时可能抛 "dictionary changed size during iteration"（读共享状态同样要收口）。
        with self._锁:
            return sum(x.状态 == 状态_有效 for x in self.句柄表.values())

    def 状态快照(self) -> dict[str, Any]:
        with self._锁:
            return {"句柄总数": len(self.句柄表), "活跃句柄数": self.活跃句柄数(),
                    "回收证据数": len(self.回收证据表)}

