"""唯一原子写腿：单文件「解锁窗口 → 临时件 → fsync → os.replace → 收口锁态」（唯一实现）。

## 为什么它必须住在 `公共契约/运行时/`（2026-09-25 核心批·写腿下沉）

写腿原先住在 `支持库/后端/文件系统支持库/文件操作/实现/文件系统.py`（`写入文件` + 私有
`_原子写`），而 `运行核心/依赖防火墙.py` 的 `允许依赖表` 明文写着：

    公共契约: []                        ← 连自己都够不到写腿
    技能库:   [公共契约]
    项目适配层: [公共契约, 运行核心]
    前端核心 / 后端核心: [公共契约, 运行核心]

⇒ 这 5 层**物理上够不到**住在 `支持库` 的写腿。现场代价是**三份逐字同形的骨架副本**，
且每份的注释都写着同一句「本层**不能**转调 `写入文件`（唯一分层方案）」：

    · `项目适配层/项目声明/项目声明.py`    「解锁 → 临时件 + replace → 收口锁态」
    · `项目适配层/依赖锁定/依赖锁定.py`    同上
    · `技能库/后端/技能库/实现/技能库.py`  同上

再加上 `运行核心`（它**有权**依赖 `支持库`，却仍各处裸写 `write_text`）与 `公共契约` 自己
（`诊断/写入流水.py` 自开窗口追加）—— 同一个动作在核心面上有 **5 套实现**，判据只能靠
「扫重复」兜住，而不是靠结构保证（哲学 1.2：一类事情只有一条腿）。

★ 关键事实：这条骨架**本来就没有 `支持库` 依赖** —— 它只用 `os` / `tempfile` 与
`公共契约.运行时.仓库只读锁` 的 `临时解锁` / `写腿收口锁态`。所以本模块是**逐字搬迁**，
不是重写：搬迁后唯一腿落在依赖表的最底层（`公共契约` 依赖=空），**每一层都够得到**。

## 与 `支持库.文件系统支持库.文件操作.写入文件` 的分工（不是两条腿）

`写入文件` 仍是**对外能力的唯一入口**（能力 id / 参数 / 返回 / 错误码一字不变），它保留
三项**能力面**的判据与护栏，然后把落盘动作转调本模块：

    ① 身份准入 `平台适配.MCP身份准入()`（公共契约）
    ② 租约授权 `写入授权.授权拒绝结果()`（公共契约）
    ③ 危险路径护栏（`实现/危险路径.py`，支持库本地）
    ④ **落盘骨架 = 本模块**
    ⑤ md 写入凭据登记 `诊断.写入流水`（公共契约）

即：`写入文件` 是「能力面组装」，本模块是「落盘骨架」。**骨架只有一份**，组装口可以有多个
（`原子写入` / `追加写入` / `文本补丁` 各自组装），但都必须转调本模块，不得自建骨架。

## 边界（如实声明）

- 只做**单文件**原子写；目录树搬移 / 目录换位（`os.replace(目录, 目录)`）不在本原语射程
  —— 那是 `平台适配/删除树.py`、`移动并可删` 一族的事。
- **不做**身份准入、**不做**租约授权、**不做**危险路径护栏、**不登记** md 凭据：那四项是
  「能力面」的判断，本模块只管「把字节安全地放上去」。谁组装谁负责判据（同 `平台适配/复制.py`
  的口径：原语不替调用方拍板）。
- 权限位**恒按「目标已存在则保持原权限位」恢复**：临时件默认 `0o600`，直接 `replace` 会把
  只读的 `0444` 静默降成 `0600` ⇒ 锁自己开了（2026-09-21 `文本补丁` 实测）。新建文件的权限位
  由临时件决定（`0600`），不随 umask。
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path

# 骨架只用这两条既有腿，两条都在 `公共契约/运行时/` 内部 ⇒ 本模块无跨层依赖。
from 公共契约.运行时.仓库只读锁 import 临时解锁, 写腿收口锁态
# 平台差异的**收口层门**（判据唯一在收口层）：本模块不自己写平台判断
# （`重复腿与旁路·平台判断越界` 铁律；样板 = `平台控制面/包仓库/平台客户端制品.py::_加固密钥权限`）。
from 公共契约.运行时.平台适配 import 支持chmod


def 原子写文件(目标: str | Path, 内容: str, 编码: str = "utf-8",
               开工ID: str = "") -> None:
    """把 `内容` 原子写到 `目标`（同目录唯一临时名 + `fsync` + `os.replace`）。

    **内核只读锁的解锁窗口**（华哥 2026-09-23 裁决「纯粹电脑硬件权限管控」）：
    整仓受管文件可能置了 macOS 不可变标志（`chflags uchg`）—— 那时 `os.replace` 会被
    内核以 `Operation not permitted` 拒绝（实测）。故整个落盘动作包在 `临时解锁()` 里：

        解锁（目标文件 + 其父目录）→ 临时件 → replace → 按原状态重锁

    为什么父目录也要解锁：`os.replace` 是「在父目录里换名」、新建文件是「在父目录里
    加条目」，父目录锁着时两者都被拒。**建父目录必须也在窗口内**：目标在新建的多层目录里时
    `mkdir(parents=True)` 是在「已锁的祖父目录」里加条目，放窗口外会在这一步就被内核拒
    （实测 2026-09-23）。

    **窗口退出后的收口**（`finally` 里、窗口**外**）：

    · 必须在窗口外：窗口内父目录是临时解锁态，`_上下文锁态` 读到的上下文是假的（会得出
      「上下文没锁 ⇒ 目标也解开」的错误结论）；
    · 必须在 `finally`：写失败时 `mkdir(parents=True)` 可能已在窗口内建出新目录，那些新目录
      同样要按上下文收口，否则会永久留在未锁态；
    · 调的是**写腿专用**那一层 `写腿收口锁态()`（只收口「窗口退出后仍未锁」的那一档）——
      写前就锁着的文件由 `临时解锁` 自己按写前状态复原，无条件对齐会把它解锁掉。

    **`开工ID`**：落盘窗口本身也过授权判据（`仓库只读锁._要求写入授权` 调
    `校验写入授权`）⇒ 开窗必须带调用方的开工ID，否则窗口自己就把落盘拒掉
    （受管路径 + 空开工ID ⇒ `PermissionError`）。故由公开函数一路穿透进来，缺省空串。

    **异常口径**：`LookupError`（未知编码）/ `OSError`（落盘失败）**原样逸出**，本模块不吞、
    不包装、不改文案 —— 与搬迁前逐字相同，调用方的 `except` 分支不变。
    """
    目标 = Path(目标)
    权限 = None
    try:
        if 目标.is_file():
            权限 = 目标.stat().st_mode & 0o777
    except OSError:
        权限 = None
    try:
        with 临时解锁(目标, 开工ID=开工ID):
            目标.parent.mkdir(parents=True, exist_ok=True)
            句柄 = tempfile.NamedTemporaryFile(
                "w", encoding=编码, dir=str(目标.parent) if 目标.parent.is_dir() else None,
                delete=False, prefix=".__写入_", suffix=".tmp")
            try:
                句柄.write(内容)
                句柄.flush()
                os.fsync(句柄.fileno())
            finally:
                句柄.close()
            try:
                if 权限 is not None and 支持chmod():
                    # 平台差异收口在 `平台适配.支持chmod()`（判据唯一在收口层）：
                    # Windows 无 POSIX 权限位语义 ⇒ 如实跳过「恢复原权限位」这一动作
                    # （写本身照常完成）；POSIX 平台上 `chmod` 失败是**真错误**
                    # （非属主 / 文件系统不支持），按「不静默降级」原样逸出。
                    os.chmod(句柄.name, 权限)
                os.replace(句柄.name, 目标)
            except OSError:
                try:
                    os.unlink(句柄.name)
                except OSError:
                    pass
                raise
    finally:
        写腿收口锁态(目标)


__all__ = ["原子写文件"]
