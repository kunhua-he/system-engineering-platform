"""执行耗时账本：把**每一次代码执行的耗时**落盘，供事后优化取数（华哥 2026-09-23）。

## 开关（唯一口径）

环境变量 ``系统平台_执行耗时日志``：``真`` / ``1`` / ``on``（不分大小写）= 开；其余（含未设）= 关。

**关掉时一个字节都不写盘** —— 函数第一行就返回，不做「先算耗时再判要不要写」那种
隐性开销（华哥口径：「如果是关了日志功能，直接丢了就行……反正内存传参直接丢，不用硬盘 IO」）。

## 为什么要有它

优化要有数据。此前「哪个脚本慢」只能靠临时计时：本会话实测编译口定向测试 **274.5 秒**、
长杆 `测试_注册口径漂移` **234 秒** —— 这个数还是子代理临时测出来的，测完就没了。
落一张表就能按「来源 × 命令」聚合出真耗时分布，不必每次现测。
（华哥：「我需要每一个代码执行的时间，要落盘到数据库里面……主要是方便用于优化。」）

## 落点与保留

* 落点 = 底座运行库：环境变量 ``系统库运行库`` 覆盖优先，否则
  `公共契约.运行时.运行缓存.解析运行数据根` 下的 ``底座运行.db``
  —— 与 `运行核心/任务调度/任务系统.py`、`运行核心/加载器/提供者隔离/独立进程_账本.py`
  **同一口径，不另立第二套定位**。
* 每次读写各开一条**短连接**、用完即关（同 `独立进程_账本` 口径）：
  跨线程/跨进程共用一个 `sqlite3.Connection` 会静默串事务。
* 保留 ``保留天数`` 天，写入时**按概率**顺手清理（不是每次都全表扫 ——
  日志不该把自己变成负担）。

## 失败即静默（**刻意的**，与仓内多数判据相反）

本账本是**观测设施，不是判据**：写不进去（磁盘满/库被锁/权限）**绝不影响被测的那次执行**，
故一律吞掉异常、只记 `最后一次错误` 供自检读取。
★ 这条与「fail-closed」相反是**有意的**：判据取不到证据必须判红，而观测取不到数据
不能把生产执行判死。要查它通不通，调 `自检()`，不要指望它在执行路径上报错。
"""

from __future__ import annotations

import os
import random
import sqlite3
import time
from pathlib import Path

from 公共契约.运行时.环境开关 import 环境开关
from 公共契约.运行时.数据库连接 import 打开, 打开可写

#: 开关的环境变量名（唯一口径；改这里即改全平台）。
开关环境变量 = "系统平台_执行耗时日志"
#: 本开关的历史接受面（显式传给 `环境开关`；**不得改用并集** `真值词表`：并集多出的
#: `yes` / `是` 会把「关」静默改成「开」＝放宽接受面，而同义收口不得改变任何一处判定结果）。
开关词表 = frozenset({"真", "1", "on", "true"})
#: 库路径覆盖环境变量（与 任务系统 / 独立进程账本 同一口径）。
库环境变量 = "系统库运行库"
#: 表名与列口径的唯一定义处（读写共用，不各写一遍）。
表名 = "执行耗时"
列 = ("时刻", "来源", "命令", "工作目录", "退出码", "耗时秒", "输出字节")
#: 保留天数（华哥：「保留 3 天也行，7 天也行」）。
保留天数 = 7
#: 写入时顺手清理的概率（避免每次执行都全表扫）。
清理概率 = 0.02
#: 命令列的截断长度（账本是索引，不是全文库；要全文另存回执）。
命令上限 = 300

#: 最近一次写入失败的原因（供 `自检()` 读；正常为 空串）。
最后一次错误 = ""


def 开关() -> bool:
    """日志开关当前是否打开（未设/无法解析一律按**关**处理）。

    判定逻辑统一走 `公共契约/运行时/环境开关.py`（env→bool 唯一实现）；本处不再自带一份。

    **接受面逐字保持（显式传 `开关词表`）**：旧实现认 `真/1/on/true`，并集 `真值词表`
    多出的 `yes` / `是` **故意不认** —— 传并集会把这两个值从「关」判成「开」＝放宽
    本开关接受面（观测开关会突然开始写盘），违反「同义收口不得改变任何一处判定结果」。
    """
    return 环境开关(开关环境变量, 词表=开关词表)


def 库路径() -> Path:
    """底座运行库路径：环境变量覆盖优先，否则经唯一解析器落运行数据根。"""
    显式 = str(os.environ.get(库环境变量, "") or "").strip()
    if 显式:
        return Path(显式)
    from 公共契约.运行时.运行缓存 import 解析运行数据根
    from 公共契约.运行时.导入前缀 import 取系统根

    return 解析运行数据根(取系统根(__file__)) / "底座运行.db"


def _连接() -> sqlite3.Connection:
    # 本处转调 `公共契约/运行时/数据库连接.py`，原参数 timeout=5.0 + 手写 `PRAGMA journal_mode=WAL` → 档 打开可写（超时 5.0 + WAL，逐字等价）。
    连接 = 打开可写(库路径(), 5.0)
    连接.execute(
        f"CREATE TABLE IF NOT EXISTS {表名}("
        f"{列[0]} TEXT, {列[1]} TEXT, {列[2]} TEXT, {列[3]} TEXT, "
        f"{列[4]} INTEGER, {列[5]} REAL, {列[6]} INTEGER)")
    连接.execute(f"CREATE INDEX IF NOT EXISTS idx_{表名}_时刻 ON {表名}({列[0]})")
    return 连接


def 记一笔(来源: str, 命令: str, 耗时秒: float, 退出码: int | None = None,
         工作目录: str = "", 输出字节: int | None = None) -> None:
    """把一次执行记进账本。**开关关着时立即返回，不碰盘、不抛异常。**

    `来源` = 谁发起的（能力id / 工具名，如 `系统核心支持库.进程管理.执行命令`）；
    `命令` = 被执行的东西（超长按 `命令上限` 截断，账本是索引不是全文库）。
    """
    if not 开关():
        return
    global 最后一次错误
    try:
        连接 = _连接()
        try:
            连接.execute(
                f"INSERT INTO {表名}({', '.join(列)}) VALUES(?,?,?,?,?,?,?)",
                (time.strftime("%Y-%m-%d %H:%M:%S"), 来源, 命令[:命令上限], 工作目录,
                 None if 退出码 is None else int(退出码),
                 None if 耗时秒 is None else float(耗时秒),
                 None if 输出字节 is None else int(输出字节)))
            if random.random() < 清理概率:
                连接.execute(f"DELETE FROM {表名} WHERE {列[0]} < ?",
                            (time.strftime("%Y-%m-%d %H:%M:%S",
                                           time.localtime(time.time() - 保留天数 * 86400)),))
            连接.commit()
        finally:
            连接.close()
        最后一次错误 = ""
    except Exception as 异常:      # noqa: BLE001 —— 观测设施绝不把被测执行判死（见模块 docstring）
        最后一次错误 = f"{type(异常).__name__}: {异常}"


def 自检() -> dict:
    """账本自检：开关状态、库路径、表内行数、最近一次写入错误。

    为什么要有它：本模块**刻意**静默失败（见 docstring），故「它到底通没通」必须能
    单独问出来，否则坏了也没人知道 —— 那就成了假绿。
    """
    开 = 开关()
    路径 = 库路径()
    行数: int | None = None
    错误 = 最后一次错误
    if 路径.is_file():
        try:
            # 本处转调 `公共契约/运行时/数据库连接.py`，原参数 timeout=5.0（纯读 SELECT、无 PRAGMA、前置 `路径.is_file()` 门）→ 档 打开（读路径：超时 5.0；不建目录、不切 WAL，原语义逐字保留）。
            连接 = 打开(路径, 5.0)
            try:
                行数 = int(连接.execute(f"SELECT COUNT(*) FROM {表名}").fetchone()[0])
            finally:
                连接.close()
        except Exception as 异常:  # noqa: BLE001
            错误 = 错误 or f"{type(异常).__name__}: {异常}"
    return {"开关": 开, "开关环境变量": 开关环境变量, "库路径": str(路径),
            "库存在": 路径.is_file(), "表": 表名, "行数": 行数,
            "保留天数": 保留天数, "最近写入错误": 错误}
