"""唯一目录项 fsync 腿：打开目录 fd → `fsync` → 关闭（唯一实现）。

## 为什么它必须住在 `公共契约/运行时/`（2026-09-26 目录项 fsync 下沉）

`运行核心/依赖防火墙.py` 的 `允许依赖表` 明文写着：

    公共契约:   []                                ← 连自己都够不到目录项 fsync
    支持库:     [公共契约]
    平台控制面: [公共契约, 支持库, 运行核心]

⇒ `支持库` 与 `平台控制面` **互不可达**。同一件事（`os.replace` / `os.rename` 之后，
把「改名」这一项也刷到盘上）原先在三个层各有一份**就地实现**，各自都够不到别人：

    · `平台控制面/能力目录/单文件互斥存储.py::同步目录`
    · `支持库/后端/文件系统支持库/文本补丁/实现/文本补丁.py::_同步目录`
      （它的 docstring 自己就写着「跨层依赖：支持库不得依赖平台控制面，故按同口径就地实现」）
    · `运行核心/运行环境管理器/远程镜像.py::_同步目录项`

★ 关键事实：这条腿**本来就没有跨层依赖** —— 它只用 `os`，以及同层的
`公共契约.诊断.忽略记录`（且只在调用方要求留痕时才用）。所以本模块是**逐字搬迁**，
不是重写：搬迁后唯一腿落在依赖表的最底层（`公共契约` 依赖=空），**每一层都够得到**。

## 唯一实现是谁

`同步目录项` 是**本轮收口**的「目录项 fsync」唯一实现（best-effort 档）。已转调
（函数名一律保留，调用点不动）：`单文件互斥存储.同步目录`、`文本补丁._同步目录`、
`远程镜像._同步目录项`；`平台控制面/包仓库/服务.py::落盘同步目录` 的**目录项那一段**
也转调本原语（它整函数是「整树落盘屏障」，是另一件事，见下）。

**如实声明未收口面**（2026-09-26 全仓 `os.open(…, O_RDONLY)` 复扫，本轮不在写集内，
未动）：`平台控制面/包仓库/可信仓库元数据.py:78`（best-effort 静默，同本原语默认档）、
`平台控制面/包仓库/激活指针.py:111` 与 `平台控制面/包仓库/平台客户端制品.py:419,434`
（三处**无守卫硬失败档**，与 `运行核心/资源协调/服务.py::_同步目录` 同族）、
`开发工具/环境自检/自检_POSIX专有.py:27`（dir_fd 能力探针，非同一件事）。

## 边界（如实声明）

- 只 fsync **单个目录项**：`os.replace` / `os.rename` 只保证「改名这个动作」原子，
  不保证改名后的**目录项**已落盘；本原语补的就是这一项。
- **不做**「整棵树的落盘屏障」（逐文件 fsync + 递归目录）：那是
  `平台控制面/包仓库/服务.py::落盘同步目录`（它转调本原语只覆盖目录那一段）。
- **不做**硬失败档：本原语是 **best-effort** —— 平台不支持目录 fsync / 拿不到句柄时
  默认**静默**（与 `单文件互斥存储.同步目录`、`文本补丁._同步目录` 现状逐字一致）；
  调用方要留痕就显式传 `留痕位置=`（`远程镜像._同步目录项` 即此）。要「失败必须显式
  报错」的调用方（`运行核心/资源协调/服务.py::_同步目录` 的发布事务耐久性承诺）
  **不用本原语**：那是另一档语义（硬失败），不在本原语射程。
- 不做权限位、不做原子写：那是 `公共契约/运行时/写文件.py::原子写文件` 的事。
"""

from __future__ import annotations

import os
from pathlib import Path

from 公共契约.诊断.忽略记录 import 记录忽略


def 同步目录项(目录: str | Path, *, 留痕位置: str = "") -> None:
    """best-effort fsync 单个目录项；平台不支持时**不升级为落盘失败**。

    做法与既有各份逐字一致：`os.open(目录, os.O_RDONLY)` → `os.fsync(fd)` → `os.close(fd)`。

    **为什么吞而不是抛**：`os.open(目录, os.O_RDONLY)` 在 Windows 上**必然**失败 ——
    CPython 的 `os.open()` 对目录走 `CreateFileW` 且不带 `FILE_FLAG_BACKUP_SEMANTICS`，
    抛 `PermissionError: [Errno 13] Permission denied: '<目录>'`；这**不是权限不足**，
    是「Windows 不允许把目录当文件打开」，POSIX 上同一调用合法（本机实测成功）。
    此时**数据本身已经写出**（内容 fsync 由写腿负责），本原语只是「改名后的可见性」
    加固 ⇒ 不能把「目录 fsync 不可用」升级成「落盘失败」把发布/装配带偏。

    **异常口径**：只吞 `OSError`（平台守卫，含 Windows 的 `PermissionError`）与
    `AttributeError`（极简运行时没有 `os.open`/`os.fsync`）；其余异常不吞、不包装。

    **`留痕位置`**（可选，缺省空 = **静默**，与 `单文件互斥存储`/`文本补丁` 现状逐字一致）：
    给出「模块.动作」即把拿不到句柄 / fsync 失败 / 关闭失败三处按 `记录忽略` **如实留痕**
    （设计哲学第 3 条 2 项「失败要明确」）—— `远程镜像._同步目录项` 传它的原口径
    `"远程镜像.同步落盘.目录"`，保住
    `测试中心/运行核心/测试_清只读删除与落盘跨平台.py` 里「目录打不开要留痕」那条断言。
    """
    位置 = str(留痕位置).strip()
    句柄 = -1
    try:
        句柄 = os.open(str(目录), os.O_RDONLY)
        os.fsync(句柄)
    except (OSError, AttributeError) as 错误:
        if 位置:
            记录忽略(位置, 错误)
    finally:
        if 句柄 >= 0:
            try:
                os.close(句柄)
            except OSError as 错误:
                if 位置:
                    记录忽略(位置, 错误)


__all__ = ["同步目录项"]
