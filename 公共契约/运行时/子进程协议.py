"""子进程请求/响应协议：读一行 JSON 请求 → 执行 → 写一行 JSON 响应（唯一实现）。

背景（2026-09-24 批R·R-6，审计 R3）：这段协议此前在 **10 处各写一份** —— 6 个提供者
子进程入口（PyMuPDF / Pillow / reportlab / MLXWhisper / 代码地图 / PDF隔离）各写一份
「空请求 / 非法 JSON / 未知操作 / 异常」四类收口，2 个工作器（任务工作器 / 进程工作器）
各写一份多请求主循环，组件规范支持库的模板再把这套形状复制给新提供者。同一件事多份
实现即缺陷：实测已漂移（同一个崩溃场景，MLXWhisper 腿回「进程崩溃」、其余腿回「提供者
崩溃」，两边都自称稳定错误码）。本模块把协议收成唯一实现，调用点只提供**操作表**
（单发）或**处理请求**（多请求）。

**响应信封（唯一形状）**

``{"成功": 逻辑型, "值": 任意可 JSON 化值, "错误码": 文本, "错误说明": 文本}``
成功时 ``错误码`` / ``错误说明`` 为空串；失败时 ``值`` 尽量保留（部分腿回带部分结果）。

**单发协议**（一次性子进程：读一条、写一条、退出）

``单发主循环(操作表, ...)`` 一次调用做完「前置 → 读请求 → 查操作表 → 执行 → 写响应」：

1. 空请求 / 非法 JSON → ``参数不合法``；
2. 未知操作 → ``参数不合法``（附未知操作名）；
3. 处理函数抛异常 → ``崩溃错误码``（默认 ``提供者崩溃``，按腿传参）；
4. 处理函数返回值：``结果`` 对象按其成功/失败转信封；含 ``成功`` 键的字典按信封转；
   含非空 ``错误码`` 的字典按失败转（保留 ``值``）；其余按成功转信封。

**多请求协议**（常驻工作器：就绪标记 → 逐行处理 → 停止类型即结束）

``多请求主循环(处理请求, ...)``：空行跳过、非法 JSON 跳过、每条请求都交处理函数并写一行
响应；``请求["类型"] == 停止类型`` 的那条**也写响应**（停止确认），写完才结束循环 ——
对端拿到确认后才看到 EOF。

**诚实标注**：密码签名提供者的子进程入口**不接入本模块**（判据见该文件：它完全自包含、
不向 ``sys.path`` 注入平台根，只以同级模块方式导入 ``密码操作.py``），它的四类收口仍是
本地一份 —— 这是本批唯一保留的协议副本，已登记在批R·R-6 单据里。
"""

from __future__ import annotations

import json
import os
import sys
import time
from typing import Any, Callable

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.运行时.环境开关 import 严格真值词表

来源 = "子进程协议"

错误码_参数不合法 = "参数不合法"
错误码_提供者崩溃 = "提供者崩溃"
错误码_提供者不可用 = "提供者不可用"

#: 常驻工作器的默认就绪标记与停止类型
默认就绪标记 = "READY"
默认停止类型 = "停止"


def _标准输出(行: str) -> None:
    """写一行到 stdout 并 flush（子进程协议的唯一出口；flush 保证对端立刻读到）。"""
    print(行, flush=True)


def _环境已置位(变量名: str) -> bool:
    """跨进程布尔开关：**只认 `"1"`**（词表＝`环境开关.严格真值词表`）。

    **为什么不转调 `环境开关.环境开关`**：本函数的唯一调用方是「父进程经环境变量给
    子进程传布尔」（`单发主循环` 的 `测试超时环境变量`，父子读同一个变量）——
    跨进程开关是**窄契约**。并集词表会把 `on` / `true` / `真` / `yes` / `是` 也放行，
    那就是**放宽接受面**（同义收口不得改变任何一处的判定结果），故此处**就地保留
    严格口径**，只共用词表常量；比较的仍是**环境变量原文**，不加 strip / lower
    （那同样是放宽：`" 1"` / `"1 "` 不该被认）。
    """
    return os.environ.get(变量名) in 严格真值词表


def 响应行(成功: bool, 值: Any = None, 错误码: str = "", 错误说明: str = "") -> str:
    """组装一行响应（唯一信封形状）；不抛异常。"""
    return json.dumps(
        {
            "成功": bool(成功),
            "值": 值,
            "错误码": str(错误码 or ""),
            "错误说明": str(错误说明 or ""),
        },
        ensure_ascii=False,
    )


def 读一行请求(流=None) -> 结果[dict[str, Any]]:
    """从 ``流``（默认 stdin）读一行并解析 JSON。

    失败一律是 ``参数不合法``（空请求 / 非法 JSON / 非对象），**不抛异常** —— 子进程边界
    必须回结构化失败，否则上层只能看到「崩溃」，真实原因被掩盖。
    """
    if 流 is None:
        流 = sys.stdin
    try:
        行 = 流.readline()
    except (OSError, ValueError) as 错误:
        return 结果.失败(错误码_参数不合法, f"读取请求失败: {错误}", 来源=来源)
    if not 行 or not 行.strip():
        return 结果.失败(错误码_参数不合法, "空请求", 来源=来源)
    try:
        请求 = json.loads(行)
    except json.JSONDecodeError as 错误:
        return 结果.失败(错误码_参数不合法, f"请求不是合法 JSON: {错误}", 来源=来源)
    if not isinstance(请求, dict):
        return 结果.失败(
            错误码_参数不合法, f"请求必须是 JSON 对象，收到 {type(请求).__name__}", 来源=来源
        )
    return 结果.成功结果(请求)


def 组装应答(处理结果: Any) -> str:
    """把处理函数返回值转成一行响应（四条判据：结果对象 / 信封字典 / 含错误码字典 / 其余）。

    这是「同一件事多种形状」的唯一转换处：各腿处理函数的返回形状历史上并不一致
    （``结果`` 对象、含 ``成功`` 键的信封字典、含 ``错误码`` 的结果字典、裸值），
    本函数按判据统一收口，调用点不再各写一份 ``_输出`` / ``_响应``。
    """
    if isinstance(处理结果, 结果):
        if 处理结果.成功:
            return 响应行(True, 值=处理结果.值)
        return 响应行(False, 错误码=处理结果.错误码, 错误说明=处理结果.错误说明)
    if isinstance(处理结果, dict) and "成功" in 处理结果:
        # 信封字典：本腿实现自己就返回 ``{"成功": ..., "值": ..., "错误码": ...}``（如代码地图腿）
        if 处理结果.get("成功"):
            return 响应行(True, 值=处理结果.get("值"))
        return 响应行(
            False,
            值=处理结果.get("值"),
            错误码=str(处理结果.get("错误码") or 错误码_提供者崩溃),
            错误说明=str(处理结果.get("错误说明") or "子进程执行失败"),
        )
    if isinstance(处理结果, dict) and 处理结果.get("错误码"):
        return 响应行(
            False,
            值=处理结果.get("值"),
            错误码=str(处理结果.get("错误码")),
            错误说明=str(处理结果.get("错误说明") or "子进程执行失败"),
        )
    return 响应行(True, 值=处理结果)


def 单发主循环(
    操作表: dict[str, Callable[[dict], Any]],
    *,
    入口名: str = "子进程入口",
    前置: Callable[[], str | None] | None = None,
    崩溃错误码: str = 错误码_提供者崩溃,
    崩溃说明前缀: str = "子进程执行异常",
    测试超时环境变量: str = "",
    测试超时秒: float = 5.0,
    流=None,
    输出: Callable[[str], None] | None = None,
) -> int:
    """单发协议主循环，返回进程退出码（正常路径恒 0）。

    ``操作表``：``操作名 → 处理函数(请求 dict)``；处理函数抛异常即按 ``崩溃错误码`` 回失败。
    ``前置``：可选初始化 / 路径注入；返回非空字符串即视为失败（回 ``提供者不可用`` 并结束）。
    ``测试超时环境变量``：置 ``"1"`` 时在**操作校验之后**故意睡眠 ``测试超时秒``
    （供上层超时路径的真实用例使用；不需要就别传）。
    """
    if 输出 is None:
        输出 = _标准输出
    if 前置 is not None:
        try:
            前置错误 = 前置()
        except Exception as 错误:  # noqa: BLE001 - 边界必须回结构化失败
            输出(响应行(False, 错误码=错误码_提供者不可用,
                        错误说明=f"{入口名} 初始化异常: {type(错误).__name__}: {错误}"))
            return 0
        if 前置错误:
            输出(响应行(False, 错误码=错误码_提供者不可用, 错误说明=str(前置错误)))
            return 0
    读结果 = 读一行请求(流)
    if not 读结果.成功:
        输出(响应行(False, 错误码=读结果.错误码, 错误说明=读结果.错误说明))
        return 0
    请求 = 读结果.值
    操作 = str(请求.get("操作") or "")
    处理函数 = 操作表.get(操作)
    if 处理函数 is None:
        输出(响应行(False, 错误码=错误码_参数不合法, 错误说明=f"未知操作 '{操作}'"))
        return 0
    if 测试超时环境变量 and _环境已置位(测试超时环境变量):
        time.sleep(测试超时秒)
    try:
        输出(组装应答(处理函数(请求)))
    except Exception as 错误:  # noqa: BLE001 - 任何未预期异常都转稳定响应，不把栈打给调用方
        说明 = f"{崩溃说明前缀}: {错误}" if 崩溃说明前缀 else str(错误)
        输出(响应行(False, 错误码=崩溃错误码, 错误说明=说明))
    return 0


def 多请求主循环(
    处理请求: Callable[[dict], Any],
    *,
    就绪标记: str = 默认就绪标记,
    停止类型: str = 默认停止类型,
    流=None,
    输出: Callable[[str], None] | None = None,
) -> int:
    """多请求协议主循环（常驻工作器），返回退出码（正常路径恒 0）。

    语义（任务工作器 / 进程工作器共用一份）：

    - 先写就绪标记（父进程据此判断启动完成）；
    - 空行与非法 JSON / 非对象一律**跳过**（常驻进程不能因一行噪声退出）；
    - 每条请求都交 ``处理请求`` 并写一行响应，含 ``类型 == 停止类型`` 的那条（回停止确认）；
    - 响应写完再判停止，保证对端拿到确认后才看到 EOF。
    """
    if 输出 is None:
        输出 = _标准输出
    if 就绪标记:
        输出(就绪标记)
    if 流 is None:
        流 = sys.stdin
    for 行 in 流:
        if not 行.strip():
            continue
        try:
            请求 = json.loads(行)
        except json.JSONDecodeError:
            continue
        if not isinstance(请求, dict):
            continue
        应答 = 处理请求(请求)
        输出(应答 if isinstance(应答, str) else json.dumps(应答, ensure_ascii=False))
        if 请求.get("类型") == 停止类型:
            break
    return 0


