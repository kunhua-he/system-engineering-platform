"""SQLite 只读连接 URI 的**唯一构造口径**：百分号编码的 file URI + 查询参数。

**为什么必须新建本文件（不是重复造件）**：`只读库URI` 原住 `运行核心/权威状态.py`
（2026-09-18 由 P2-13③ 建立）。依赖防火墙的 `允许依赖表`（真实审计输出）里
`支持库 -> ["公共契约"]`——**支持库层不得依赖 运行核心**，而本仓的同类裸拼调用方
横跨 `公共契约`/`支持库`/`模块库`/`技能库`/`运行核心`/`平台控制面`/`项目适配层`/`开发工具`
八个层（见各处调用点），其中 `支持库/后端/代码解析支持库` 与 `模块库` 都够不到 运行核心。
把口径留在高层会让低层调用方无法复用、只能各写一份裸拼——正是本文件要消灭的
「同一写法两把尺子」。

按 `允许依赖表`：`公共契约 -> []`、`支持库 -> ["公共契约"]`、
`模块库 -> ["公共契约","支持库"]`、`技能库 -> ["公共契约"]`、
`运行核心 -> ["公共契约","支持库"]`、`平台控制面 -> ["公共契约","支持库","运行核心"]`、
`开发工具 -> ["公共契约",…,"运行核心",…]`。**`公共契约` 是唯一能被上述全部层导入的层**，
故本口径落在这里——与同层的 `平台适配.py`/`有界IO.py` 一致：都是「跨层共用的底层原语」。

为什么不复用 `运行核心/运行状态监督/实现/只读状态库.py:只读连接()`：它在 `实现/` 下
（依赖防火墙强制拒绝导入任何 `实现/` 目录，且按能力契约不是公开件），且把参数写死
`mode=ro`、不带 `timeout`，覆盖不了本文件要收口的两种参数形态。

为什么连 `连接真实库路径` 一并下移：它与 `只读库URI` 是**一对验真原语**——
`只读库URI` 构造「我打算读哪个库」，`连接真实库路径` 回答「我实际连到了哪个库」。
空库的 `PRAGMA integrity_check` 恒返 `ok`，只看前者永远发现不了 URI 被截断连错库；
低层调用方要自证「没连错库」就得两个都有。留一份在 运行核心 会让 支持库 调用方
要么绕路要么自己再写一份比对——又回到两把尺子。

代价实测（2026-09-18，导入 `运行核心.权威状态`）：拖入 **86 个模块、27.6 ms**，
且连带 `运行核心.进程身份`——低层调用方为拼一个字符串去背这个依赖不划算，
口径下移到本文件后各层只背标准库 `pathlib`。

**本口径的缺陷背景（P2-13③，2026-09-18 现场实测）**：裸拼 `f"file:{路径}?mode=ro"`
在 `file:` URI 里 `#` 起 fragment、`?` 起 query，路径含这两个字符时被**静默截断到前缀**
——`#` 那支把后面拼的 `?mode=ro` 整体算进 fragment，`?` 那支把路径尾部连同 `?mode=ro`
一起吞掉（URI 里再无任何查询参数 ⇒ **只读彻底失效**，实测该连接 `CREATE TABLE` 落盘成功）；
截断出来的前缀名还会被 SQLite **现场新建**成一个空库，而空库的 `PRAGMA integrity_check`
返回 `ok` ⇒ **真实损坏被掩盖**。三层后果全不报错。

为什么用 `as_uri()` 而不是 `urllib.parse.quote()`：`Path.as_uri()` 是标准库里
「路径 → file URI」的现成能力，除 `#`/`?`/空格/百分号外还管 `.`/`..` 规范化与
`quote` 的 `safe` 字符（早前报告建议的 `quote(str(路径))` 默认 `safe='/'`，在 Windows
反斜杠与冒号上会走偏）。`as_uri()` 要求绝对路径，故先 `resolve()`。

**两个参数形态各留具名常量，禁止调用方再手写参数字面量**：参数里写错一个字符同样是
静默失效（`mode=rw` 会写入、`mode=ro&immutable=1` 在 WAL 活库上读不到正在追加的内容），
所以参数本身也必须收口。
"""
from __future__ import annotations

from pathlib import Path

只读参数 = "mode=ro"
只读不可变参数 = "mode=ro&immutable=1"


def 只读库URI(数据库路径: Path | str, 参数: str = 只读参数) -> str:
    """SQLite 只读连接 URI：百分号编码的 file URI + 查询参数。

    默认参数 `mode=ro`：只读校验连接不得改写任何库。**不要**默认加 `immutable=1`——
    该选项断言「文件不会变」，而权威状态库是 WAL 活库，正在追加的 WAL 在 immutable
    连接下读不到（会把活跃内容误判成缺失）。

    什么时候才该显式传 `只读不可变参数`：目标是**别人的只读外部索引**、且连 `mode=ro`
    都不许在其目录里留下 side 文件（实测量：`mode=ro` 会在索引目录生成
    `xxx.db-shm`/`xxx.db-wal`，等于向别人的目录写盘）。这种库不会在连接期间被追加，
    `immutable=1` 的前提才成立。
    """
    return Path(数据库路径).resolve().as_uri() + "?" + 参数


def 只读库URI实参(数据库路径: Path | str) -> str:
    """`mode=ro` + `immutable=1` 形态：**只读外部索引**专用（判据见 `只读库URI` 末段）。

    与 `只读库URI(路径)` 分成两个具名入口，是为了让调用点一眼看出「我开的是活动库」
    还是「我开的是外部索引」——两者的可用选项不同，写混了不报错、只出错结果。
    """
    return 只读库URI(数据库路径, 只读不可变参数)


def 连接真实库路径(连接) -> str:
    """取连接实际打开的 main 库路径（`PRAGMA database_list` 的设备路径列）。

    用途：区别「我连到的是我要的那个库」与「连到了另一个（空）库」——空库的
    `integrity_check` 照样 `ok`，只有比对真实路径才能拆穿这种掩盖。
    空库、内存库（`''`）都如实返回空串，交给调用方判不等。
    """
    行 = 连接.execute("PRAGMA database_list").fetchone()
    return "" if 行 is None else str(行[2] or "")
