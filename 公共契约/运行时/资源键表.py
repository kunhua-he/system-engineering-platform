"""有界 LRU 资源键表：把「资源键 → 池成员索引」映射收敛成唯一实现。

**为什么必须有本文件（同一缺陷在本仓已出现三次）**：`提供者进程池._分配成员` 与
`本地进程提供者._分配成员` 曾各自持有一份**同构且都错**的实现 —— 普通 dict 单调增长，
满 `最大资源键数`（默认 4096）后 `return None`，调用侧永久拿「资源繁忙」。后果是
**软性自我 DoS**：长驻服务上每见过一个新键就占一格，用过的键越多、可用键越少，
且**永不恢复**。两次独立修复（`43c7ce07` 与主会话本次）证明「同一写法两处维护」
必然漂移，故按哲学 1.2 抽成本件，两边只调本件。

**为什么淘汰不需要释放池内资源**（这是本设计成立的关键，也是曾被质疑的点）：
本表是「键 → 成员索引」的**等价绑定**，成员索引由 `sha256(键) % 池大小` 纯函数决定，
池成员是**共享的**（不是「一键一成员」），成员生命周期归池自己的 `关闭()` 管理。
淘汰只丢一行缓存记录；被淘汰的键再次到来时，按同一哈希必然绑回**同一个成员对象**
（`is` 同一性已实测通过）。

**为什么放 `公共契约/运行时/`**：按依赖防火墙的 `允许依赖表`，本表的调用方横跨
`运行核心`（提供者进程池）与 `平台控制面`（本地进程提供者），而 `公共契约` 是
**唯一能被这两层都导入**的层（`公共契约 -> []`）。放高层会让低层调用方够不到、
只能各写一份裸拼 —— 正是本文件要消灭的「同一写法两把尺子」。与同层
`平台适配.py` / `有界IO.py` / `数据库URI.py` 定位一致：都是跨层共用的底层原语。

**本件不是第二执行腿**：它是**同一个唯一实现**，两边调用它是收口，不是并存。
"""

from __future__ import annotations

import hashlib
from collections import OrderedDict
from typing import Any


def 绑定的成员索引(资源键: str, *, 池大小: int) -> int:
    """资源键 → 池成员索引的**唯一判据**（纯函数，无状态，可单测）。

    用 `sha256` 前 8 字节取模，而不是 `hash()`：`hash()` 对 str 带进程级随机盐，
    同一键在不同进程会绑到不同成员 —— 而「被淘汰的键重进必须绑回同一成员」是
    本表的核心不变量，必须跨进程稳定。
    """
    摘要 = hashlib.sha256(str(资源键).encode("utf-8")).digest()
    return int.from_bytes(摘要[:8], "big") % int(池大小)


def 取成员索引(
    表: "OrderedDict[str, int]",
    锁: Any,
    资源键: str,
    *,
    池大小: int,
    最大资源键数: int,
) -> int:
    """在**有界 LRU** 表里取（或建立）资源键的成员索引；**永不拒绝新键**。

    语义（两边调用方共用同一套，不得各自改写）：

    1. 命中 → `move_to_end` 刷「最近使用」，返回既有索引；
    2. 未命中 → 先 `popitem(last=False)` 淘汰最久未用，直到表长 < 上限，再按
       `绑定的成员索引()` 建立新行并返回。

    **为什么必须 `move_to_end`**：少了它退化成 FIFO，会把仍活跃的键淘汰掉
    （同构缺陷修复时的反向验证拍2 专测这条：去掉后 2 条断言必红）。

    参数 `锁` 由调用方持有（本件不加锁、不建锁）—— 池的并发粒度归池自己定，
    本件只保证「表操作本身」是原子的、语义唯一。调用方必须已持锁进入。
    """
    索引 = 表.get(资源键)
    if 索引 is not None:
        表.move_to_end(资源键)
        return 索引
    上限 = int(最大资源键数)
    while len(表) >= 上限:
        表.popitem(last=False)
    索引 = 绑定的成员索引(资源键, 池大小=池大小)
    表[资源键] = 索引
    return 索引


def 表快照(表: "OrderedDict[str, int]") -> dict[str, int]:
    """只读快照（供状态快照/诊断用，不进热路径）。

    `OrderedDict` 的迭代顺序就是 LRU 顺序（队首最久未用、队尾最近使用），
    转普通 dict 保留该顺序 —— 调用方据此可判「谁将先被淘汰」。
    """
    return dict(表)
