"""环境开关：环境变量「真值词表」与 env→bool 判定的唯一实现。

2026-09-26 之前仓内有三套各写一份的 env→bool：`子进程协议._环境已置位` 只认 `"1"`、
`执行耗时账本.开关` 认 真/1/on/true、`后端核心_包指纹面.启用包指纹校验` 认 1/true/yes/是。
**判定逻辑**（取原文 → 归一化 → 查表 → 空值退默认）收成本模块唯一一份；
**同义词数据**也全部在本模块具名，调用方不再各写一份字面量。

**本模块统管「判定」与「词表定义处」，不强行统管「各站点的接受面」**（这是它的边界）：

- `真值词表`（六同义词并集）= 默认词表，供**新**开关使用；
- `严格真值词表`（只认 `"1"`）= **跨进程传布尔**的窄契约：父子两进程读同一变量，
  宽松匹配会把别的值也当「开」放进去（见 `子进程协议._环境已置位` 的理由注释）；
- 历史两处（观测开关 / 门禁开关）各有自己的接受面，与本模块并集**逐例实测不同**
  （差集：执行耗时账本少 `yes`/`是`，包指纹面少 `真`/`on`）。同义收口**不得改变
  任何一处的判定结果**，故这两处**显式传入各自的词表**（在调用方本地具名 + 写明
  理由），而不是改用并集 —— 那会把 `yes` / `是` / `真` / `on` 从「关」变成「开」，
  即静默放宽接受面（观测开关会突然开始写盘、门禁会突然开始拦人）。

**归一化口径**：取 `os.environ` 原文 → 去两端空白 → 小写 → 查表；
未设 / 空串 → 返回 `默认`；表外值 → **假**（不给「非空即真」那种兜底）。
"""

from __future__ import annotations

import os
from typing import Iterable


__all__ = ["真值同义词", "真值词表", "严格真值词表", "环境变量文本", "环境开关"]

#: 六个真值同义词（全仓唯一具名处；各站点只从这些词里取子集）。
真值同义词 = frozenset({"1", "true", "yes", "on", "是", "真"})
#: 默认词表 = 六同义词并集（**新**开关一律用它）。
真值词表 = 真值同义词
#: 跨进程传布尔的窄词表：只认 `"1"`，不放宽。
严格真值词表 = frozenset({"1"})


def 环境变量文本(名: str) -> str:
    """取环境变量原文并归一化（strip + lower）；未设即空串。"""
    return str(os.environ.get(名, "") or "").strip().lower()


def 环境开关(名: str, 默认: bool = False, *, 词表: Iterable[str] | None = None) -> bool:
    """按 `词表`（默认 `真值词表` 六同义词并集）判定开关。

    未设 / 空串 → `默认`；表外值 → 假。**要保留历史接受面的调用点必须显式传 `词表`**
    （`词表` 关键字参数就是为「同一实现、各自接受面」留的口子，见模块 docstring）。
    """
    原文 = 环境变量文本(名)
    if not 原文:
        return bool(默认)
    return 原文 in (真值词表 if 词表 is None else 词表)
