"""空闲端口：向系统借一个当前空闲的回环端口（唯一实现）。

**为什么住 `公共契约/运行时/`**：调用方横跨互不依赖的两条腿 —— `平台控制面/提供者/
进程组管理.py`（进程树自检要一个真端口）与 `开发工具/组件合规/参数探测.py`（组件合规
按参数契约给「端口」类参数造最小真实输入）。两处此前各写一份、逐字同义：
`socket.socket()` → `bind(("127.0.0.1", 0))` → `getsockname()[1]` → close。
本件只依赖标准库 `socket`，而 `公共契约` 的依赖=空、每一层（平台控制面 / 开发工具）
都够得到它，故放这里：既不给任何一层引入新的依赖方向，也不让这两条腿互相 import。

**语义（只是借号，不是占号）**：bind 到 0 由系统分配，读出实际端口后立即 close；
close 之后该端口就回到可用池，别的进程可随时抢走 —— 所以「取到端口」与
「等下真的绑得上」之间没有保证。要真占住，请调用方自己 bind 并保持不关。
"""

from __future__ import annotations

import socket


__all__ = ["取空闲端口"]


def 取空闲端口(主机: str = "127.0.0.1") -> int:
    """借用系统分配取一个当前空闲端口（bind 0 → 读实际端口 → close）。"""
    with socket.socket() as 套接字:
        套接字.bind((主机, 0))
        return int(套接字.getsockname()[1])
