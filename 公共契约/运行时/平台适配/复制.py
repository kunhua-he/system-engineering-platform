"""跨平台复制原语：复制文件时**不传播内核不可变标志**（唯一实现）。

## 治什么病（2026-09-25 实测）

`shutil.copy2` = `shutil.copy` + `copystat`，而 `copystat` 会把源的 `st_flags` 一并复制
（`os.chflags`）。本仓整仓置了内核只读锁（macOS `chflags uchg`，见
`公共契约/运行时/仓库只读锁.py`）⇒ **被跟踪文件全都带 `uchg`** ⇒ 用 `copy2` 把它复制到
任何地方，副本也带 `uchg`。

副本一旦带 `uchg`，两件事同时坏：

- **改不动**：`write_text` / `os.replace` 被内核以 `Operation not permitted` 拒；
- **删不掉**：`平台适配.清只读后删除树` 只清 `os.chmod` 权限位，而 `uchg` 存在时
  **`os.chmod` 本身就被内核拒**（见 `删除树.py::_清内核只读标志`）⇒ 清理必然失败、留下
  删不掉的残留。实测影响面：HTML 验证腿 **36 个场景 / 73 处夹具复制** 各留一个受管临时根，
  把「验证腿自己没打扫干净」长期伪装成场景失败；`开发工具/统一验证/验证工作区.py`
  的工作区快照同族。

## 为什么不是「复制后复用 `仓库只读锁.对齐目标锁态(目标)`」

该腿是「新建/搬入条目继承上下文锁态」的唯一实现，但它**对落在仓库内豁免区
（`工程缓存/`）的副本不生效** —— 实测 `对齐目标锁态(副本)` 回「改动 0 条」、副本仍
`uchg`：`_上下文锁态` 的规则①「目标自身已锁 ⇒ 参照锁着=真」**先于**规则③「遇豁免前缀
即停并返回假」命中，而副本恰恰带着源的标志；且其递归候选被 `_在豁免区` 过滤。该腿的
既有用法全部落 `tempfile` 临时区（仓库外，规则①不适用）才成立。

⇒ 正确落点是**从源头不传播标志**：`shutil.copy`（`copyfile` + `copymode`，只 `chmod`
权限位、不碰 `st_flags`），**不是 `copy2`**。本模块是该动作的全仓唯一落点，调用点
（`开发工具/HTML验证/动态值.py::夹具文件复制`、`开发工具/统一验证/验证工作区.py::复制输入快照`）
一律调它，不各自再写一遍复制原语。

## 边界（如实声明）

- **不保留源的 mtime / atime**（那是 `copystat` 带的）。需要保留元数据的复制**不能**用它
  —— 那种场景若副本落仓库外，走「复制后 `仓库只读锁.对齐目标锁态()`」仍成立。
- 只做**单文件**复制（与 `shutil.copy` 同形）；目录树复制不在本原语射程。
"""

from __future__ import annotations

import shutil
from pathlib import Path


def 复制文件不传标志(来源: str | Path, 目标: str | Path) -> str:
    """把 `来源` 复制到 `目标`，**不复制源的 `st_flags`**（内核不可变标志不随之传播）。

    判据、理由与边界见模块 docstring。返回目标路径文本（与 `shutil.copy` 的返回值同形）。
    异常口径与 `shutil.copy` **逐字相同**：`OSError` 原样逸出，不吞、不包装、不改文案
    —— 本函数只换复制原语，不新造失败语义。
    """
    shutil.copy(来源, 目标)
    return str(目标)
