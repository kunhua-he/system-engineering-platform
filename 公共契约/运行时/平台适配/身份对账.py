"""MCP 身份对账：识别符号、对账原语、修 MCP 白名单，以及「要求经 MCP」的脚本入口准入门。"""

from __future__ import annotations

import os
import sys

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.运行时.平台适配.准入 import 脚本入口准入


#: 识别符号：**经 MCP 来的**（MCP 腿经 40007 网关，网关进程带它；终端直跑不带）。
#: 不新造符号 —— 这就是既有的网关凭证变量名，网关 plist 的 `EnvironmentVariables` 里就有它。
MCP识别符号 = "系统库网关凭证"


def 对账MCP身份() -> tuple[bool, str]:
    """对账「是不是经 MCP 来的」：`(通过, 说明)`。**毫秒级**（只读环境变量，不碰磁盘）。

    判据（一层，穷尽）：
      · 环境变量 `系统库网关凭证` 存在且非空 ⇒ 通过（MCP 腿经网关注入，终端直跑没有）；
      · 不存在 ⇒ 不通过，说明里给出**可直接照抄的替代命令**（华哥 2026-09-23：
        「没对上账直接报错。返回错误提示词。请使用***来运行。类似于这样子的形式」）。

    为什么只按环境变量、不另读磁盘对账本（原设计有两层，实测后收成一层）：
    读「凭证指纹文件」比读环境变量**没有任何增量强度** —— 改环境变量的人同样能改那个文件，
    两层的强度都等于「一层 + 一次 IO」。对账的价值在于**给走对路的人秒级放行、
    给走错路的人一句正确的替代命令**，不在于制造幻觉式的深度。
    """
    值 = os.environ.get(MCP识别符号, "").strip()
    if 值:
        return 真, ""
    return 假, (
        "拒绝执行：本项目的代码只能经 MCP 运行（终端直跑不带识别符号 "
        f"`{MCP识别符号}`）。\n"
        "请使用：\n"
        '  capability_call(能力id="自修复工具.静态编译", '
        '参数={"类型": 1, "模块ID": "<你改的库或模块>"})   # 不带实际数据，只查合规/契约/生成物\n'
        '  capability_call(能力id="自修复工具.动态编译", '
        '参数={"类型": 1, "模块ID": "<你改的库或模块>"})   # 再加实际测试脚本实测\n'
        "  （`类型=0` 为全仓口径，此时 `模块ID` 必须留空。）\n"
        "若你确实在修 MCP 自身（哲学 7.1 明文允许终端腿）：由白名单入口放行，见 脚本入口准入 的 要求经MCP 参数。"
    )


def 脚本入口准入MCP(用途: str) -> None:
    """**要求经 MCP** 的脚本入口准入：对账不过即打印替代命令并退出码 1。

    与 `脚本入口准入` 的关系（**不是两条腿**）：本函数先做同样的平台校验，再多做一步
    MCP 身份对账；故内部**转调** `脚本入口准入`，不重复任何平台判断。

    **转调 `MCP身份准入()`，不是 `对账MCP身份()`**（2026-09-23 复核实测的缺陷修复）：
    修 MCP 白名单（`修MCP自身`）是华哥裁决「修 mcp 可以用终端」的**唯一放行口**；
    本函数原先直接调 `对账MCP身份()`（只看识别符号、不认白名单），与写入腿/站点层用的
    `MCP身份准入()` **对同一问题给出相反答案** —— 实测：设了白名单后写入腿与
    `sitecustomize` 都放行，而接了本函数的编译口/生成物联动**照旧拒启**
    ⇒ 「修 MCP 自身」在入口这条腿上其实走不通（同一件事两套判据，哲学第 1.2 条）。
    现统一到 `MCP身份准入()` 这一条腿：白名单 → 放行；否则转 `对账MCP身份()` 取说明。

    **默认不接**（要显式调它才生效）：这是加在开发循环上的新门槛，接错了会把编译口、
    提交钩子、生成器一起打死（本仓反复栽的「判据太宽＝假红」）。接法见各入口的注释。
    """
    脚本入口准入(用途)
    通过, 说明 = MCP身份准入()
    if not 通过:
        # flush 的理由同 脚本入口准入：入口常被外部限时拉起，不 flush 会丢这句唯一线索。
        print(说明, flush=True)
        sys.exit(1)


#: 「修 MCP 自身」的终端白名单环境变量名（**唯一放行口**，2026-09-23）。
#:
#: 华哥 2026-09-23 裁决原文：「mcp 除外，等于说**修 mcp 可以用终端**，但是除了 mcp
#: 以外的，都必须要用 mcp 的工具。否则全部拒绝落盘。」—— 这条白名单就是那句话的
#: 机器落点：设了它（非空即算）`MCP身份准入()` 直接放行，不必经网关。
#:
#: 命名沿用本仓既有环境变量前缀口径（实测既有：`系统库网关凭证` / `系统底座_网关端口` /
#: `系统平台_项目根` / `系统工程平台_决策模型权重目录`）。
修MCP白名单变量名 = "系统平台_修MCP自身"


def MCP身份准入() -> tuple[bool, str]:
    """MCP 身份准入（**写入腿与站点层的唯一放行判据**）：`(通过, 说明)`。

    两层，穷尽（与 `对账MCP身份()` 一样是毫秒级，只读环境变量）：

      1. **修 MCP 白名单**（环境变量 `修MCP白名单变量名`）非空 ⇒ 通过。
         这是华哥 2026-09-23「修 mcp 可以用终端」的**唯一放行口**，显式、可审计；
      2. 否则转调 `对账MCP身份()` —— **拒绝文本的唯一来源就是它**（本函数不另写
         第二份说明；同一条腿两处实现即缺陷，哲学第 1.2 条）。

    为什么单独有这个原语、而不是把白名单塞进 `对账MCP身份()`：那三个原语
    （`MCP识别符号` / `对账MCP身份` / `脚本入口准入MCP`）是**别的批次已在用**的既有
    契约，签名与语义已冻结（2026-09-23 派活方明文要求不许动）；本函数是它们的
    **加法包装** —— 一个字节都不改它们。

    调用方（2026-09-23 接线的两处）：
      · 仓库根 `sitecustomize.py`：本项目目录内的解释器启动时对账，不过即拒绝启动；
      · `支持库/后端/文件系统支持库/文件操作/实现/文件系统.py::写入文件` 与
        `支持库/后端/文件系统支持库/文本补丁/实现/文本补丁.py` 的两条落盘腿：
        不过即 `结果.失败`，不落盘。
    """
    if os.environ.get(修MCP白名单变量名, "").strip():
        return 真, ""
    return 对账MCP身份()
