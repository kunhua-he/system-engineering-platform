"""路径解析（相对路径按生效根解析成绝对路径，**全平台唯一一份口径**，2026-09-23）。"""

from __future__ import annotations

import contextvars
import os
from pathlib import Path
from typing import Any


# ── 路径解析（**全平台唯一一份口径**，2026-09-23）────────────────────
#
# 起因（华哥 2026-09-22 原话）：「mcp 应该有一个默认配置项，是锁定根目录的，然后用户
# 无论输入绝对路径，还是相对路径（复用根目录配置），只要文件存在，就可以使用的兼容性
# 才对，这纯粹是 bug 了」。实测代价：给 MCP 传相对路径时，网关跑的是**制品**（不是
# 源码树），相对路径落到制品根，回「文件不存在」；调用方只能靠猜该给绝对路径。
#
# 根因是**同一件事被多处各自实现、根由本地 `parents[N]` 推出**（样本：
# `平台控制面/提供者/实现/能力入口.py` 自己写 `路径 if 路径.is_absolute() else
# (系统根目录 / 路径)`，根在制品态就是制品根）。按哲学第 8 条唯一性判定②，
# 「相对路径按根解析」必须收成**同一份实现**：本函数是唯一那一份，调用点（网关派发前）
# 只调它，不许自带 `is_absolute()` 分支。

#: 项目根环境变量名（**平台级默认配置项**，2026-09-23 新增）。
#:
#: 来源说明：本仓既有环境变量用 `系统底座_*` / `系统库*` 前缀（实测：`系统底座_网关端口`、
#: `系统库运行库`、`系统库网关凭证`…），**实现时全仓没有与本名同名的既有约定**
#: （已 grep 核实），故按本工作包指定名 `系统平台_项目根` 立为新约定：
#: 它承载「锁定的项目根」，供 `解析路径` 在**没有显式根**时兜底。
#: 设置它 → 相对路径一律按它解析；不设置 → 退到进程当前工作目录（fail-open 到既有行为，
#: 不改变任何「本来就传绝对路径」的调用）。
项目根环境变量名 = "系统平台_项目根"

#: 本次调用的解析基准（**调用方 `项目根`**，2026-09-24 批R R-32 新增）。
#:
#: 为什么需要它（本批修的就是这个洞）：平台自己写的口径是「普通路径参数一律
#: **项目根相对**」（`AGENTS.md` 项目硬规则 ＋ `字段名册.取路径写法口径`），而本函数在
#: **没有显式根**时只能退到「环境变量 → 进程 cwd」—— 网关进程跑在**制品**里（实测：
#: 进程命令行 `平台客户端/运行核心/启动运行核心网关.py`，cwd ＝ 制品内层根），于是漏传
#: `根目录` 的相对路径被解析到**制品镜像根**（`工程缓存/制品仓库/…`）。实测代价：
#: R-21 债务 #8 与 R-27 债务 #1 **各因此白跑一轮**；本批复现同一形态 ——
#: `批量应用精确替换(编辑列表=[{文件路径:'开发文档/项目说明.md', …}])` 不传 `根目录`
#: ⇒ `文件不存在: …/工程缓存/制品仓库/平台客户端环境/平台客户端/开发文档/项目说明.md`。
#:
#: 为什么是 **ContextVar** 而不是环境变量：网关是**多请求并发**的同一进程，把「本次调用的
#: 根」写进 `os.environ` 会让并发请求互相踩（A 的根被 B 覆盖）。ContextVar 随调用线程/
#: 任务隔离，天然是「本次调用」语义。
#:
#: 谁写它：网关派发前那一处（`运行核心/统一网关/核心处理/网关执行面.py::执行面._执行`
#: 入口）—— 那是全平台**唯一**「已经拿到顶层 `项目根`、且还没派发」的时刻（薄壳对每次
#: 「调用能力」都自动补位顶层 `项目根`）。调用方**不得**另写一份。
本次调用基准变量: contextvars.ContextVar = contextvars.ContextVar(
    "本次调用基准", default=None)


def 设置本次调用基准(根: Any) -> None:
    """把**本次调用**的解析基准交给唯一解析腿；传空 = **清空**（不残留上一次的值）。

    清空这一半同样是判据：网关进程长期存活，若只设不清，一次带 `项目根` 的调用会把基准
    **粘**给后面所有不带 `项目根` 的调用 —— 那是「基准漂移」，比退回 cwd 更难查（调用方
    看到的是一个自己没给过的根）。故网关每次都**无条件**调本函数（有根设根、无根清空），
    而不是「有根才设」。

    只收文本与 `Path`：其余类型（``None`` / 数字 / 列表…）一律按「清空」处置 —— 本函数
    不猜语义、不抛异常（与 `解析路径` 对非文本入参的处置同一条）。
    """
    if isinstance(根, Path):
        本次调用基准变量.set(根)
        return
    if isinstance(根, str) and 根.strip():
        本次调用基准变量.set(根)
        return
    本次调用基准变量.set(None)


def 解析路径(路径: Any, 根: str | Path | None = None) -> Any:
    """把路径解析成**绝对** ``Path``：绝对原样、相对按「生效根」拼接。

    这是全平台**唯一一份**「相对路径按根解析」实现（哲学第 8 条唯一性判定②）：
    调用点不得自带 ``is_absolute()`` 分支、不得自己用 ``parents[N]`` 推根。

    语义（**只拼根，不查存在性**）：

    - 绝对路径 → 原样返回 ``Path``（**不查存在性**：存在性是调用方的判据，不是本函数的）；
    - 相对路径 → 以「生效根」为基准拼接，返回**绝对** ``Path``；
    - 空值 / 非文本（``None`` / ``""`` / 数字 / 列表…）→ **原样返回**，
      **绝不抛异常** —— 调用方的参数本来就可能不是路径（参数名同形但语义不同是常态），
      本函数只对「确实是路径文本」的输入动手。

    生效根优先级（**四级，取第一个可用者**）：

    1. 显式 ``根`` 实参（非空文本或 ``Path``）—— 调用方现场已知的基准；
    2. **本次调用基准**（`本次调用基准变量`，＝调用方顶层 `项目根`；网关派发前写入，
       见 `设置本次调用基准`）—— 2026-09-24 批R R-32 新增这一级；
    3. 环境变量 ``项目根环境变量名``（``系统平台_项目根``，**锁定的项目根**默认配置项）；
    4. 进程当前工作目录 ``Path.cwd()``（前三级都取不到时的既有行为兜底）。

    **为什么第 2 级必须存在**：平台口径是「普通路径参数写项目根相对路径」，而实现层里
    **嵌套在列表型参数内的相对路径**（样本：`编辑列表[].文件路径`）到不了网关的顶层标量
    改写（`_归一化路径族参数` 只改顶层）—— 它们只剩本函数的兜底可用，改前那个兜底是
    进程 cwd（网关跑制品 ⇒ 制品镜像根）⇒ 漏传 `根目录` 恒判「文件不存在」。
    **不设第 2 级时行为与改动前逐字一致**（退回环境变量 → cwd），本函数仍是纯增量。

    **为什么把「环境变量」放在「cwd」之前**：平台跑在制品态时 cwd 往往是制品根，
    而调用方心里想的是源码树；「锁定的项目根」正是为跨过制品/源码差异而设的默认项，
    故它优先于 cwd。**不设置环境变量时行为与改动前逐字一致**（相对路径落 cwd），
    即本函数是**纯增量**：只让「配了根」的场景变好，不改变「没配根」的既有语义。

    **不做** ``resolve()`` / ``exists()`` / ``expanduser`` 之外的处理：不解析符号链接、
    不规范化 ``..`` 之外的写法（``expanduser`` 只把 ``~`` 展开成家目录 —— 展开后若成绝对
    路径即按绝对路径原样返回，与 ``Path.expanduser`` 的既有语义一致）。
    """
    if not isinstance(路径, str):
        return 路径
    if not 路径.strip():
        return 路径
    目标 = Path(路径).expanduser()
    if 目标.is_absolute():
        return 目标
    生效根 = 根
    if 生效根 is None or (isinstance(生效根, str) and not 生效根.strip()):
        生效根 = 本次调用基准变量.get()
    if 生效根 is None or (isinstance(生效根, str) and not 生效根.strip()):
        生效根 = os.environ.get(项目根环境变量名, "").strip() or None
    if 生效根 is None:
        生效根 = Path.cwd()
    return Path(生效根).expanduser() / 目标
