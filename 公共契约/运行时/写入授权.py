def _取读取器() -> tuple[Callable[[], tuple[dict[str, str] | None, str]] | None, str]:
    """取写租约事实源；未注册时**懒加载**平台控制面那一侧（它载入即自注册）。

    ★ **为什么这里允许一条跨层边**（`运行核心/依赖防火墙.py::文件级豁免表` 对本文件有
    显式登记，且**只放行本文件、不开放整层**）：判据本体必须住 `公共契约`（写入腿只能
    依赖这一层），而租约事实住 `平台控制面` —— 两者之间没有别的合法走法。

    没有它会怎样（**2026-09-23 现场活体回归**）：`项目文档.人工改文档` 是本仓「人工改正文
    的唯一合法落盘通道」，而它经 `系统核心支持库.进程管理.执行命令` **起子进程**跑生成器
    （`模块库/项目文档/实现/文档生成器.py:116::_跑生成器`）；子进程只 import `开发工具` +
    `支持库`，从不载入租约能力面 ⇒ 事实源恒为空 ⇒ **结构性永远过不了这道门**。
    实测：前 3 份 md 落盘成功，之后 4 份全部退出码 1（`越界：… 拿不到写租约事实源`），
    并且把调用方逼去用 `文本补丁.应用精确替换` 落 md —— 那正是绕过生成器的旁路。

    **懒加载而不是模块级 import**：① 不需要本判据的进程不付导入代价；
    ② 避免与 `平台控制面.能力目录` 形成模块载入环（本模块被 `文件租约存储` 反向 import）。
    懒加载失败**不抛**，如实回问题让调用方 fail-closed（证不出授权就拒写）。
    """
    global 写租约事实源
    if 写租约事实源 is not None:
        return 写租约事实源, ""
    try:
        import 平台控制面.能力目录  # noqa: F401 —— 载入即触发 `文件租约存储` 自注册
    except ImportError as 错误:
        return None, f"`平台控制面.能力目录` 不可导入（{错误}）"
    return 写租约事实源, ""


def 校验写入授权(绝对路径: Any, 开工ID: str = "") -> tuple[bool, str]:
    """这条路径**此刻能不能写**：`(通过, 说明)`。

    四条出口，穷尽（fail-closed 在每一条上）：

      1. **非受管** ⇒ 通过（仓库外 / 豁免前缀 / 平台自管生成物 / 平台自管临时资源 /
         平台自己的编译机：本判据没有话说）；
      2. 受管但算不出相对路径（异常形态）⇒ 拒绝；
      3. 受管 且 `开工ID` 为空 ⇒ **拒绝**；
      4. 受管 且 `开工ID` 非空 ⇒ 问写租约事实源：
         · 事实源**未注册** ⇒ 拒绝（「证不出被授权」不等于「可以写」）；
         · 事实源**不可用** ⇒ 拒绝（存储读失败同样证不出）；
         · 该路径的活跃租约 **`所有者` == 开工ID** ⇒ 通过；
         · 否则（该路径无租约，或租约属**别人**）⇒ 拒绝。

    **为什么必须比 `所有者`，而不是只问「有没有人占」**（2026-09-25 底座权限面收口）：
    改前第 4 条只问 `相对 in 活跃集`，而活跃集**全平台一本、跨会话共享** ⇒ 那个判据是
    **路径级**的：甲认领了 X，乙（任一并发会话、任一持网关凭证的进程）写 X 照样通过。
    `所有者` 就是认领方的**开工ID**，故这一比等于问「这条路径的写窗口是不是**你**开的」。

    **为什么 `开工ID` 为空也要拒**（而不是退回旧的路径级判据）：退回＝保留一条
    「不传凭证也能写」的旧腿，而那正是本次要收掉的洞（华哥「不保留旧腿」）。
    纯读能力不走本判据（它不写盘）；平台自身写腿**分两类** —— 编译口及其子进程走第 1 条
    「写者是平台编译机」出口，**其余在 agent 请求时刻落盘的平台写腿照样走本判据**
    （典型：`开发工具/MD文档生成` 那条「人工改文档」链）⇒ 它们必须把 `开工ID` 一路传到
    写腿，否则结构性永远过不了这道门。

    为什么事实源不可用也算拒绝而不是放行：本判据存在的理由就是「不能靠 agent 自觉」
    （同 `仓库只读锁` 的判据哲学）。证不出授权时放行，等于把判据退化成「有租约时更严」
    的反向激励 —— 把事实源删掉就没人拦了。
    """
    受管, 相对, 说明 = 受管相对路径(绝对路径)
    if not 受管:
        return 真, ""
    if not 相对:
        return 假, (f"越界：{绝对路径!r} 落在仓库受管面内却算不出项目根相对路径"
                    f"（{说明}）⇒ 无法证明授权，按 fail-closed 拒绝。")
    凭证 = str(开工ID or "").strip()
    if not 凭证:
        return 假, (f"越界：{相对} 的写入**没有开工ID 凭证** —— 本判据要问「这条路径的活跃租约"
                    "是不是你认领的」，没凭证就无从比对（判据是**调用方级**的，不再只看路径）。\n"
                    + 照抄认领调用(相对))
    读取器, 取问题 = _取读取器()
    if 读取器 is None:
        return 假, (f"越界：{相对} 无法证明被授权 —— 拿不到写租约事实源（{取问题}）"
                    "⇒ fail-closed 拒绝。\n"
                    "  说明：本判据要求**同进程可载入的事实源**（`平台控制面/能力目录`）。"
                    "若你在生成器/子进程里落盘，请确认该子进程能 import 平台控制面"
                    "（同仓库源码树 / 制品内都应有它），否则改走同进程能力。\n"
                    + 照抄认领调用(相对))
    所有者表, 问题 = 读取器()
    if 所有者表 is None:
        return 假, (f"越界：{相对} 无法证明被授权 —— 租约事实源不可用（{问题}）"
                    "⇒ fail-closed 拒绝。\n" + 照抄认领调用(相对))
    所有者 = 所有者表.get(相对)
    if 所有者 == 凭证:
        return 真, ""
    if 所有者:
        return 假, (f"越界：{相对} 的活跃写租约属**别的凭证**（所有者 {所有者}），不是你传的 "
                    f"{凭证} —— 活跃租约是全平台一本、跨会话共享的，只有**认领它的那条凭证**"
                    "能写（写入腿只判「是不是经 MCP」，本判据补的就是「是不是**你**认领的」这一半）。\n"
                    + 照抄认领调用(相对))
    return 假, (f"越界：{相对} 没有任何**活跃写租约**覆盖（写入腿只判「是不是经 MCP」，"
                "不判路径授权；本判据补的就是这一半）。\n" + 照抄认领调用(相对))


def 授权拒绝结果(绝对路径: Any, 来源: str, 开工ID: str = ""):
    """写入腿共用的收口：不过即 `结果.失败("越界", 说明)`；过则返回 `None`。

    与各写入腿既有的 `_身份拒绝()` 逐字同形（同一道口的两道判据各自一个收口），
    这样每条腿只多两行，不把授权语义抄进 6 个文件（哲学 1.2）。

    `开工ID` 由写入腿从自己的入参原样透传（**写入腿自己的能力契约里都有它**，见各包
    `能力定义.json`）—— 缺它即拒绝（判据是调用方级的，见 `校验写入授权`）。
    ★ 但**调用写入腿的上层能力**不一定有它（典型：`开发工具/MD文档生成` 的人工改文档链）
    —— 那是「调用链断」的破口，判据只能如实报 `越界`，修在调用方那一侧。
    """
    from 公共契约.基础类型.结果类型 import 结果

    通过, 说明 = 校验写入授权(绝对路径, 开工ID)
    if 通过:
        return None
    return 结果.失败("越界", 说明, 来源=来源)
