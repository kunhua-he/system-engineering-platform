# ── 租约**回收器**注册（2026-09-24 批P：过期租约留真缺口）────────────────
#
# 缺陷本体（现场实测）：一条写租约的**到期是时间的函数、不是事件** ——
# `申请文件租约` 认领成功即 `仓库只读锁.解锁供写入(目标 + 父链)` 开窗，而回锁只在
# **下一次认领的懒回收**里发生。于是「租约已过期、窗口还开着、没人来收」这段里，
# `仓库只读锁.活跃租约开窗集()` 的 `是活跃`（状态活跃 **且** 未过期）把这几条判成
# 「既不是开窗、也不是写腿被杀留下的缺口」⇒ 落进 `缺口数` ⇒ `pre-commit` 拒提交。
#
# 修法是**判据不动**：把已有的回收腿（`回收过期文件租约`）挂到调用方**本来就有的唤醒点**
# （只读查询、周期维护循环）上，接入既有统一机制，不新建第二条腿、不改占用判定。
#
# 为什么与 `写租约事实源` **并排住本文件**：本文件已经是「公共契约 侧唯一的注入宿主」
# （跨层边在 `运行核心/依赖防火墙.py::文件级豁免表` 有显式登记，只放行本文件）；
# 回收器是同一份事实的**第二个出口**，另开文件就要多一份「谁 import 它」的接线。
#
# ★ 两个注册口**形状逐字同形**（`None` 即注销、模块级全局、平台控制面侧载入时注册），
#   但**语义刻意相反**，这不是「同一件事两套实现」：
#
#     写租约事实源 = **判据**（怎么问同层的写入授权） ⇒ 未注册即 fail-closed（拒写）；
#     租约回收器   = **顺手清理**（把已过期的写窗口收回来） ⇒ 未注册即**静默跳过**。
#
#   第二句的理由：清理失败绝不能把只读查询（`查询()` / `查看`）打死 —— 那是把
#   「顺手帮忙」升级成新的假红来源，方向上正好与本判据要治的病相反。
租约回收器: Callable[[Any], tuple[int, str]] | None = None


