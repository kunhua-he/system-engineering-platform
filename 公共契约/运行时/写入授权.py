#: 平台自己的**编译机**（`开发编译口`）身份判据的两件事实（**唯一一份定义**）：
#: 环境标记名 + 单写者锁相对路径。`开发工具/开发编译口/编译口.py` **引用**它们，
#: 不另写第二份（哲学 1.2：同一件事两套实现即缺陷）。
#:
#: 两层判据是**有意为之**：第一层（环境标记）是快筛；第二层（进程祖先链）才是强度所在 ——
#: 环境变量可伪造（`执行命令` 的 `环境变量` 入参是**追加**语义），而**进程祖先关系伪造不了**：
#: 调用方无法让「自己的父进程」变成那个编译口。
