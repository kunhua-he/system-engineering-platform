"""写入授权：本路径是否被一条**活跃写租约**覆盖（判据本体，唯一一处）。

## 为什么要有它（2026-09-23 现场取证）

写入腿此前只判「是不是经 MCP 来的」（`公共契约.运行时.平台适配.MCP身份准入`），
**不判路径有没有被授权**：调用方只要带上网关凭证，任何路径都能写。于是「只读子代理」
在平台上**根本不存在** —— 2026-09-23 一次四路只读子代理全部越界落盘/占租约，
落点就是这道缺口。本模块补的是**第二判据**：

    身份对账管「谁在写」；本判据管「这条路径此刻能不能写」。

## 判据口径（一条，穷尽）

    受管路径（在仓库内、且不落豁免区） ⇒ 必须被一条活跃写租约覆盖，否则拒绝（fail-closed）
    非受管路径                         ⇒ 不受本判据约束

「受管」与 `公共契约/运行时/仓库只读锁.py` **同一覆盖范围**（同一份 `豁免前缀`）：
内核锁不锁的路径，本判据也不判 —— 否则平台自己的运行期数据（`工程缓存/`）、
临时区（`/tmp`）、制品树会被整片判红，那是「判据太宽＝假红」，本仓反复栽过。

## 为什么判据住公共契约、事实源住平台控制面

分层是硬判据（`运行核心/依赖防火墙.py::允许依赖表`）：`公共契约` 的允许依赖 = **空**。
故本模块**不 import 平台控制面**：租约事实由平台控制面侧**注册**进来
（`设写租约事实源`），本模块只做判据与「受管」判定。事实源本体复用
`平台控制面/能力目录/文件租约存储.py` 既有的租约读取与 `是活跃` 占用判定
（**不另写一套租约读取**：同一件事两套实现即缺陷）。

## 三个调用面（同一处判据，不另立一套）

    · 写入腿：`文件系统支持库.文件操作.写入文件/删除文件/复制文件/移动文件`、
      `文件系统支持库.文件操作.文件系统补充.追加写入/删除目录`、
      `文件系统支持库.文本补丁.应用精确替换/批量应用精确替换`；
    · 文档写入腿：`开发工具.MD文档生成.人工编辑`（它经 `写入文件` 落盘，传递覆盖）；
    · 内核锁窗口：`仓库只读锁.临时解锁/临时解锁树` —— 它们此前明写「不受门槛约束」，
      而 `写入文件` 正是用它们包住落盘 ⇒ 不纳入同一判据，写入腿的第一判据就形同虚设。

## 失败语义（fail-closed，且必须可自救）

任何一条走不通都回 `(假, 说明)`，说明里**必带可照抄的 `开工即占` 调用** ——
否则调用方只看到「越界」却不知道该怎么合规，判据就变成拦路石而不是门。
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Callable

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.运行时.平台适配 import 解析路径

#: 写租约事实源：`() -> (活跃写租约的项目根相对路径集, 问题说明)`。
#: 由 `平台控制面/能力目录/文件租约存储.py` 在模块载入时注册（那一侧能 import 本模块，
#: 反向不成立 —— 公共契约的允许依赖为空）。未注册即 fail-closed。
写租约事实源: Callable[[], tuple[frozenset[str] | None, str]] | None = None

#: 平台自管的**生成物**：它们由平台的装配/证据机器写入，不是 agent 的事实源文件，
#: 故与 `工程缓存/` 等豁免前缀同一性质 —— 不受本判据约束（否则每一次 md 落盘的
#: 凭据登记、每一次装配的声明/锁定写盘都会被判红，那是假红）。
#:
#: 五条都是**固定名**、由平台自己的写腿生成：
#:   · `开发文档/项目证据/MD写入流水.jsonl` ← `公共契约/诊断/写入流水.py`
#:   · `项目声明.json` / `项目声明.tmp`    ← `项目适配层/项目声明/项目声明.py`
#:   · `依赖锁定.json` / `依赖锁定.tmp`    ← `项目适配层/依赖锁定/依赖锁定.py`
#: （`.tmp` 两条是那两腿的**同目录临时件**：`os.replace` 前要先写它，
#:   只豁免正式名会让装配写盘在临时件那一步被判红。）
平台生成物: tuple[str, ...] = (
    "开发文档/项目证据/MD写入流水.jsonl",
    "项目声明.json",
    "项目声明.tmp",
    "依赖锁定.json",
    "依赖锁定.tmp",
)


def 设写租约事实源(读取器: Callable[[], tuple[frozenset[str] | None, str]] | None) -> None:
    """注册写租约事实源（**平台控制面侧唯一的注册入口**）。

    为什么用注册而不是直接 import：本模块住 `公共契约`，那一层的允许依赖是**空**
    （`运行核心/依赖防火墙.py::允许依赖表`）；而租约事实住 `平台控制面`。
    向上 import 会同时踩两条硬判据（越层 + 导 `实现/` 目录），故事实从下往上**注入**：
    平台控制面侧载入时调本函数，本模块只持有「怎么问」而不持有「问谁」。

    `读取器` 传 `None` 即注销（测试用：验证「没注册就 fail-closed」那条判据）。
    """
    global 写租约事实源
    写租约事实源 = 读取器


def 受管相对路径(绝对路径: Any) -> tuple[bool, str, str]:
    """`(是否受管, 项目根相对路径, 说明)`；不受管时相对路径为空串。

    受管 = **在仓库内** 且 **不命中豁免前缀** 且 **不是平台自管生成物**。
    三条判据都只问既有唯一实现，不在这里另抄一份：

      · 「在哪个仓库内」→ `仓库只读锁.推断仓库根`（与 `回锁`/`_在豁免区` 同源）；
      · 「是否豁免」    → `仓库只读锁.是豁免相对路径`（`豁免前缀` 的唯一一份口径）；
      · 「相对路径按谁解析」→ `平台适配.解析路径`（全平台唯一那条相对路径解析腿）。

    非受管**不是**「放行」，而是「本判据没有话说」：仓库外与豁免区本来就没有租约
    可言（租约只能认领项目根相对路径，`校验相对路径` 会把仓库外判成路径越界）。
    """
    if not isinstance(绝对路径, str) or not 绝对路径.strip():
        return 假, "", "路径为空"
    目标 = 解析路径(绝对路径)
    if not isinstance(目标, Path):
        return 假, "", "路径不可解析（非文本）"
    try:
        目标 = 目标.resolve()
    except OSError:
        pass
    from 公共契约.运行时.仓库只读锁 import 是豁免相对路径, 推断仓库根

    仓库根 = 推断仓库根(目标)
    if 仓库根 is None:
        return 假, "", "不在任何仓库内（仓库外无受管面）"
    try:
        相对 = 目标.relative_to(仓库根).as_posix()
    except ValueError:
        return 假, "", "不在仓库内"
    if not 相对:
        return 假, "", "仓库根自身"
    if 是豁免相对路径(相对):
        return 假, "", "命中豁免前缀（内核锁同样不锁它）"
    if 相对 in 平台生成物:
        return 假, "", "平台自管生成物"
    return 真, 相对, ""


def 照抄认领调用(相对路径: str, 仓库根: str = "") -> str:
    """可照抄的合规动作（**失败说明里必带**）：判据要指路，不能只拦路。"""
    根 = 仓库根 or "<本仓库绝对路径>"
    return (
        "处置：先用 MCP 认领这条路径，再写 ——\n"
        '  capability_call(能力id="开工编排.开工即占", 参数={'
        f'"项目根": "{根}", "任务": "<你要做什么>", '
        f'"修改路径": ["{相对路径}"], "所有者": "<你的会话名>"}})\n'
        '  收工释放：capability_call(能力id="开工编排.收工释放", '
        '参数={"租约id清单": [<开工即占 返回的 租约id清单>]})'
    )


def _取读取器() -> tuple[Callable[[], tuple[frozenset[str] | None, str]] | None, str]:
    """取写租约事实源；未注册时**懒加载**平台控制面那一侧（它载入即自注册）。

    ★ **为什么这里允许一条跨层边**（`运行核心/依赖防火墙.py::文件级豁免表` 对本文件有
    显式登记，且**只放行本文件、不开放整层**）：判据本体必须住 `公共契约`（写入腿只能
    依赖这一层），而租约事实住 `平台控制面` —— 两者之间没有别的合法走法。

    没有它会怎样（**2026-09-23 现场活体回归**）：`项目文档.人工改文档` 是本仓「人工改正文
    的唯一合法落盘通道」，而它经 `系统核心支持库.进程管理.执行命令` **起子进程**跑生成器
    （`模块库/项目文档/实现/文档生成器.py:116::_跑生成器`）；子进程只 import `开发工具` +
    `支持库`，从不载入租约能力面 ⇒ 事实源恒为空 ⇒ **结构性永远过不了这道门**。
    实测：前 3 份 md 落盘成功，之后 4 份全部退出码 1（`越界：… 拿不到写租约事实源`），
    并且把调用方逼去用 `文本补丁.应用精确替换` 落 md —— 那正是绕过生成器的旁路。

    **懒加载而不是模块级 import**：① 不需要本判据的进程不付导入代价；
    ② 避免与 `平台控制面.能力目录` 形成模块载入环（本模块被 `文件租约存储` 反向 import）。
    懒加载失败**不抛**，如实回问题让调用方 fail-closed（证不出授权就拒写）。
    """
    global 写租约事实源
    if 写租约事实源 is not None:
        return 写租约事实源, ""
    try:
        import 平台控制面.能力目录  # noqa: F401 —— 载入即触发 `文件租约存储` 自注册
    except ImportError as 错误:
        return None, f"`平台控制面.能力目录` 不可导入（{错误}）"
    return 写租约事实源, ""


def 校验写入授权(绝对路径: Any) -> tuple[bool, str]:
    """这条路径**此刻能不能写**：`(通过, 说明)`。

    三条出口，穷尽（fail-closed 在每一条上）：

      1. **非受管** ⇒ 通过（仓库外 / 豁免前缀 / 平台自管生成物：本判据没有话说）；
      2. **受管** ⇒ 问写租约事实源：
         · 事实源**未注册** ⇒ 拒绝（「证不出被授权」不等于「可以写」）；
         · 事实源**不可用** ⇒ 拒绝（存储读失败同样证不出）；
         · 相对路径**命中活跃租约** ⇒ 通过；
         · 否则 ⇒ 拒绝。
      3. 受管但算不出相对路径（异常形态）⇒ 拒绝。

    为什么事实源不可用也算拒绝而不是放行：本判据存在的理由就是「不能靠 agent 自觉」
    （同 `仓库只读锁` 的判据哲学）。证不出授权时放行，等于把判据退化成「有租约时更严」
    的反向激励 —— 把事实源删掉就没人拦了。
    """
    受管, 相对, 说明 = 受管相对路径(绝对路径)
    if not 受管:
        return 真, ""
    if not 相对:
        return 假, (f"越界：{绝对路径!r} 落在仓库受管面内却算不出项目根相对路径"
                    f"（{说明}）⇒ 无法证明授权，按 fail-closed 拒绝。")
    读取器, 取问题 = _取读取器()
    if 读取器 is None:
        return 假, (f"越界：{相对} 无法证明被授权 —— 拿不到写租约事实源（{取问题}）"
                    "⇒ fail-closed 拒绝。\n"
                    "  说明：本判据要求**同进程可载入的事实源**（`平台控制面/能力目录`）。"
                    "若你在生成器/子进程里落盘，请确认该子进程能 import 平台控制面"
                    "（同仓库源码树 / 制品内都应有它），否则改走同进程能力。\n"
                    + 照抄认领调用(相对))
    活跃集, 问题 = 读取器()
    if 活跃集 is None:
        return 假, (f"越界：{相对} 无法证明被授权 —— 租约事实源不可用（{问题}）"
                    "⇒ fail-closed 拒绝。\n" + 照抄认领调用(相对))
    if 相对 in 活跃集:
        return 真, ""
    return 假, (f"越界：{相对} 没有任何**活跃写租约**覆盖（写入腿只判「是不是经 MCP」，"
                "不判路径授权；本判据补的就是这一半）。\n" + 照抄认领调用(相对))


def 授权拒绝结果(绝对路径: Any, 来源: str):
    """写入腿共用的收口：不过即 `结果.失败("越界", 说明)`；过则返回 `None`。

    与各写入腿既有的 `_身份拒绝()` 逐字同形（同一道口的两道判据各自一个收口），
    这样每条腿只多两行，不把授权语义抄进 6 个文件（哲学 1.2）。
    """
    from 公共契约.基础类型.结果类型 import 结果

    通过, 说明 = 校验写入授权(绝对路径)
    if 通过:
        return None
    return 结果.失败("越界", 说明, 来源=来源)
