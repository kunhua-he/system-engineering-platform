def 是自管临时资源(绝对路径: Any) -> bool:
    """该绝对路径（已 `resolve()`）是否在**平台自管临时资源**登记表里。

    未注册读取器 / 读取器抛错一律回 `假` —— 本函数只做「减法」（给出豁免），
    证不出就照常走租约判据，绝不把「问不到」当成「可以写」。
    """
    if 自管临时资源读取器 is None:
        return 假
    try:
        集合 = 自管临时资源读取器()
    except Exception:  # 读取器是外部注入件，抛错不能把写入腿打死
        return 假
    return 真 if str(绝对路径) in (集合 or frozenset()) else 假


