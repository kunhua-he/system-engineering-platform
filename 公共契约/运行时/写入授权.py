编译机锁相对路径 = "工程缓存/编译口单写者锁.json"


def _祖先PID链(上限: int = 8) -> list[int]:
    """本进程的祖先 PID 链（含自身，从近到远，去环）。

    `os.getppid()` 恒可用（第一跳就覆盖本仓真实拓扑：`生成物联动.跑命令` 与
    `进程管理` 都是 **argv 直启、不经 shell** ⇒ 生成器是编译口的**直接子进程**）；
    更远的跳用 `ps` 尽力而为，取不到就停 —— 不把「取不到」变成新的假红来源。
    """
    链 = [os.getpid()]
    当前 = os.getppid()
    while 当前 and 当前 > 1 and len(链) <= 上限 and 当前 not in 链:
        链.append(当前)
        try:
            完成 = subprocess.run(
                ["ps", "-o", "ppid=", "-p", str(当前)],
                capture_output=True, text=True, timeout=5)
        except (OSError, subprocess.SubprocessError):
            break
        try:
            当前 = int((完成.stdout or "").strip().split()[0])
        except (IndexError, ValueError):
            break
    return 链


def 写者是平台编译机(仓库根: Any) -> tuple[bool, str]:
    """本进程是不是**平台自己的编译机**（编译口）的进程树成员：`(是, 说明)`。

    判据两层（穷尽）：① 环境标记非空且等于**单写者锁里记的 pid**；② 该 pid 在本进程的
    祖先链里。**任何一步证不出即回 `(假, "")`** —— 证不出不等于放行：调用方随后照常走
    租约判据，fail-closed 的语义一个字都不变（本函数只做「减法」，不做「加法」）。
    """
    标记 = os.environ.get(编译机PID环境变量名, "").strip()
    if not 标记:
        return 假, ""
    try:
        锁 = json.loads((Path(仓库根) / 编译机锁相对路径).read_text(encoding="utf-8"))
        锁pid = int(锁.get("pid"))
    except (OSError, ValueError, TypeError, AttributeError):
        return 假, ""
    if 标记 != str(锁pid):
        return 假, ""
    # 第二层分两档：**直接父进程**是常见形态（生成器是编译口的直接子进程，实测拓扑），
    # 一次 `getppid()` 就够、不必起 `ps`；只有更远的祖先（生成器又起了子进程）才走 `ps` 链。
    是本人 = 锁pid in (os.getpid(), os.getppid())
    if not 是本人 and 锁pid not in _祖先PID链():
        return 假, ""
    return 真, (f"平台自己的编译机在写（编译口 PID {锁pid}，持 `{编译机锁相对路径}`）"
                "⇒ 派生件写盘不受本判据约束")


