"""整机资源水位：**整机内存水位的唯一采样、缓存与判定**（运行时闸门的公共判据）。

**为什么单独立件**（华哥 2026-09-21 裁决「内存最高容量是 80%；超过的话没有做限制吗？」）：

1. **判据要有唯一来源**。水位判据原先只活在 `平台控制面/资源监督.py`（阈值 0.8 + 私有采样），
   而真正需要它的是**每一次能力调用的准入**（`运行核心/能力调用/超时执行/准入闸门.py` 那一层）
   —— 运行核心**不得依赖平台控制面**（层向规则）。判据下沉到 `公共契约/运行时/`（谁都能依赖），
   两处才可能用同一份判据，而不是各写一套 0.8。
2. **采样口径要有唯一来源**。真实采样唯一实现在 `平台适配.内存容量信息()`（macOS 走
   `sysctlbyname` + `host_statistics64` 纯系统调用；Linux 走 `/proc/meminfo`；失败回退原子进程）。
   本模块**只做水位换算、缓存与判定**，不另采一次、不复制口径。

**为什么是「定时采样 + 读缓存」而不是「每次请求都采」**（华哥 2026-09-21 当场纠正）：

> 其实访问内存的这个快照，你可以做一个计时器，大概 30 秒采样一次。然后这个监控器就直接
> 读文本就行了。不然一直请求内存，也是个麻烦事。

即：**采样是定时器的事，判据只读快照**。系统调用再快（实测约 1.2 微秒）也没必要挂在每次调用上
—— 闸门是高频路径，采样是低频事实，两者解耦后闸门侧只有一次字典读取。
采样周期 `采样周期秒` = 30 秒；快照陈旧阈值 `快照陈旧阈值秒` = 90 秒（3 个周期，容一次抖动）。

**口径（与 `平台适配` 一致，不产生第二套）**：``可用 = 物理 − 占用``，
``占用率 = 占用 / 物理``；物理 ≤ 0、可用为负、可用大于物理等异常一律按「采样未知」处理。

**采不到 / 快照陈旧时都不判超限**（哨兵 `内存采样未知`，比较恒为假）：把「没数据」当成
「没超限」是有意的 —— 闸门误杀会让平台在最需要诊断时失去全部能力；同时**不许静默**：
`整机内存水位超限` 的说明会如实写「不可判定/快照陈旧（xx 秒）」，快照里带 `快照年龄秒`
与 `采样失败次数`，调用方照抄进留痕即可（哲学第 3 条 2 项：失败必须明确）。

**有界**：常驻的只有**一条**采样线程 + **一份**快照；线程可显式停止（`停止采样定时器`），
重复启动幂等；线程是普通 `threading.Thread`（daemon），**不引入任何外部不可回收执行器**
（对齐 `运行核心/依赖防火墙.py` 的「外部不可回收后台执行器」禁引）。
"""

from __future__ import annotations

import threading
import time
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.运行时 import 平台适配

#: 整机内存水位阈值（占物理内存比例）：超过即判整机内存水位超限。
#: 与 `运行核心/自适应选型/档位表.py::模型内存安全比例`（0.8）**同值不同义**：
#: 那个是「选型时这台机器能塞下多大模型」的安全线，本常量是「运行时准入」的水位线。
#: 两者同值属口径对齐，**不是同一件事**，不合并为一个常量（合并会让「调选型线」误改运行时闸门）。
整机内存水位阈值 = 0.8

#: 整机内存采样不可用时的哨兵。**不用 0 冒充**：0 会被判成「内存占用为零」而放行。
内存采样未知 = -1.0

#: 采样周期（秒）：定时器多久采一次（华哥 2026-09-21 定的 30 秒）。
采样周期秒 = 30.0

#: 快照陈旧阈值（秒）：超过即判「数据不新鲜」，判据退回「不可判定」而不是拿旧数据下结论。
#: 取 3 个采样周期：容一次采样失败或调度抖动，又不会让陈旧快照长期冒充实时事实。
快照陈旧阈值秒 = 90.0

#: 采样线程名（诊断用；同一进程只应存在一条）。
采样线程名 = "整机内存水位采样"


def _取数(值: Any) -> float:
    """把采样字段归一成浮点数；非数值/缺失一律返回 0（由调用方按「口径异常」收口）。"""
    try:
        return float(值)
    except (TypeError, ValueError):
        return 0.0


def _空快照(原因: str, 依据: str = "") -> dict[str, Any]:
    return {
        "支持": 假, "物理字节": 0, "已用字节": 0, "可用字节": 0,
        "占用率": 内存采样未知, "依据": 依据, "原因": str(原因)[:200],
    }


def _采一次() -> dict[str, Any]:
    """真正采一次整机内存（唯一采样口径；只在定时器与冷启动首采里调用）。"""
    try:
        信息 = 平台适配.内存容量信息()
    except Exception as 错误:  # noqa: BLE001 - 采样失败必须收成明确结果，不许穿透
        return _空快照(f"内存采样异常 {type(错误).__name__}: {错误}")
    if not isinstance(信息, dict) or not 信息.get("支持"):
        return _空快照(
            str(信息.get("原因", "")) if isinstance(信息, dict) else "采样返回非字典",
            str(信息.get("依据", "")) if isinstance(信息, dict) else "")
    物理 = _取数(信息.get("物理字节"))
    可用 = _取数(信息.get("可用字节"))
    if 物理 <= 0 or 可用 < 0 or 可用 > 物理:
        return _空快照(f"采样口径异常：物理 {物理:g} 可用 {可用:g}", str(信息.get("依据", "")))
    已用 = 物理 - 可用
    return {
        "支持": 真, "物理字节": int(物理), "已用字节": int(已用), "可用字节": int(可用),
        "占用率": 已用 / 物理, "依据": str(信息.get("依据", "")), "原因": "",
    }


_锁 = threading.Lock()
_最新快照: dict[str, Any] | None = None
_采样时刻: float = 0.0          # 单调时钟；与 快照年龄秒 同源，不受墙钟跳变影响
_采样次数 = 0
_采样失败次数 = 0
_定时器线程: threading.Thread | None = None
_停止事件 = threading.Event()


def _写快照(快照: dict[str, Any]) -> dict[str, Any]:
    """把一次采样结果写进缓存（唯一写入点），并回带带元信息的那一份。"""
    global _最新快照, _采样时刻, _采样次数, _采样失败次数
    with _锁:
        _最新快照 = dict(快照)
        _采样时刻 = time.monotonic()
        _采样次数 += 1
        if not 快照.get("支持"):
            _采样失败次数 += 1
        return dict(_最新快照)


def _采样循环(周期秒: float) -> None:
    """定时采样循环：采一次 → 等一个周期（可被停止事件即时打断）。"""
    while not _停止事件.is_set():
        _写快照(_采一次())
        _停止事件.wait(max(1.0, float(周期秒)))


def 启动采样定时器(周期秒: float = 采样周期秒) -> bool:
    """启动整机内存水位采样定时器；**幂等**（已在跑返回假，不重复起线程）。"""
    global _定时器线程
    with _锁:
        在跑 = _定时器线程 is not None and _定时器线程.is_alive()
        if not 在跑:
            _停止事件.clear()
            _定时器线程 = threading.Thread(
                target=_采样循环, args=(周期秒,), name=采样线程名, daemon=True)
            _定时器线程.start()
            return 真
    return 假


def 停止采样定时器() -> bool:
    """停止采样定时器（幂等）：置停止事件并等线程退出；返回是否真的停掉了一条。"""
    global _定时器线程
    with _锁:
        线程 = _定时器线程
        _定时器线程 = None
    if 线程 is None:
        return 假
    _停止事件.set()
    线程.join(timeout=max(1.0, 采样周期秒))
    return 真


def 读取整机内存水位(*, 自动启动定时器: bool = 真) -> dict[str, Any]:
    """**读缓存快照**（闸门与监控器的唯一读入口；不做系统调用）。

    快照为空（进程刚起、定时器还没跑第一轮）时**同步首采一次**并顺手启动定时器
    —— 冷启动阶段不能出现「无水位数据」的空窗期（那会让闸门在头 30 秒无判据）。
    返回 ``{支持, 物理字节, 已用字节, 可用字节, 占用率, 依据, 原因,
    快照年龄秒, 快照陈旧, 采样次数, 采样失败次数, 采样周期秒, 快照陈旧阈值秒}``。
    """
    global _最新快照
    with _锁:
        快照 = dict(_最新快照) if _最新快照 is not None else None
        时刻 = _采样时刻
    if 快照 is None:
        if 自动启动定时器:
            启动采样定时器()
        快照 = _写快照(_采一次())
        with _锁:
            时刻 = _采样时刻
    年龄 = max(0.0, time.monotonic() - 时刻) if 时刻 > 0 else float("inf")
    with _锁:
        return {**快照, "快照年龄秒": round(年龄, 3),
                "快照陈旧": 年龄 > 快照陈旧阈值秒,
                "采样次数": _采样次数, "采样失败次数": _采样失败次数,
                "采样周期秒": 采样周期秒, "快照陈旧阈值秒": 快照陈旧阈值秒}


def 采样整机内存() -> dict[str, Any]:
    """**立即采一次**并更新缓存（诊断/验收用；高频路径请用 `读取整机内存水位`）。"""
    return _写快照(_采一次())


def 整机内存水位超限(阈值: float = 整机内存水位阈值) -> tuple[bool, str, dict[str, Any]]:
    """整机内存水位判定：**读缓存快照**（不采样），返回 ``(是否超限, 说明, 快照)``。

    - 快照新鲜且 ``占用率 > 阈值`` → ``(真, 说明, 快照)``，说明带**实测占用率、阈值与快照年龄**；
    - 快照新鲜且未超 → ``(假, "整机内存水位正常（…）", 快照)``；
    - 快照不可用 / 陈旧 → ``(假, "…不可判定（…）", 快照)``，**不判超限**
      （理由见模块说明；说明里如实带原因与年龄，调用方照抄进留痕，不许静默）。
    """
    快照 = 读取整机内存水位()
    if not 快照.get("支持"):
        return 假, (f"整机内存水位不可判定（采样不可用：{快照.get('原因') or '未知原因'}；"
                    f"采样失败 {快照.get('采样失败次数')} 次）"), 快照
    if 快照.get("快照陈旧"):
        return 假, (f"整机内存水位不可判定（快照陈旧：{快照.get('快照年龄秒')} 秒前 > "
                    f"{快照.get('快照陈旧阈值秒')} 秒，采样线程可能已停）"), 快照
    占用率 = float(快照["占用率"])
    年龄 = 快照.get("快照年龄秒")
    if 占用率 > float(阈值):
        return 真, (f"整机内存水位超限（{占用率:.1%} > {float(阈值):.0%}）："
                    f"占用 {快照['已用字节'] / 1024 / 1024:.0f} MB / 物理 "
                    f"{快照['物理字节'] / 1024 / 1024:.0f} MB（快照 {年龄} 秒前）"), 快照
    return 假, f"整机内存水位正常（{占用率:.1%} ≤ {float(阈值):.0%}，快照 {年龄} 秒前）", 快照


