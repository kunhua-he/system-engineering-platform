"""导入前缀与源码树根的唯一推导（「唯一实现」垫片共用一处，债务 #218）。

**为什么要有它**：`支持库/后端/*/*/实现/` 下有 30 份「唯一实现」垫片，每份都自带两段
推导 —— 「我该认哪个模块名」（`唯一实现名`）与「我该操作哪棵树」（`系统根`）。
两段都是**靠 `__file__`／`__name__` 猜自己在哪**的隐式推断，复制 30 遍意味着改一次口径
要改 30 处、漏一处即静默分叉。实证：`#216②`（模块名不随前缀改写）与 `#217`
（源码树根由模块位置推出）就是同一根因在两条不同链上**各修一遍**的实例。
本模块把两段推导收成一处，垫片只调用、不再各自持有实现。

**两处都必须前缀感知**（理由见 #216②）：制品构建的 `复制并重写` 只改 import **语句**，
改不到字符串字面量，而制品的公开入口把实现注册成 `平台客户端.支持库.…`：

| 形态 | 垫片模块的 `__name__` | `取根前缀` | `取系统根` |
|---|---|---|---|
| 源码树 | `支持库.后端.X.Y.实现.Z` | `""` | 仓库根 |
| 制品 | `平台客户端.支持库.后端.X.Y.实现.Z` | `"平台客户端."` | 制品内层根（同样含 `支持库/`、`模块库/`） |

`取系统根` 的判据是**锚目录**，不是「文件在第几层」：层数写法（`parents[N]`）在目录结构
一动就静默指错树 —— 30 份垫片改前正是「25 份用 `next(祖先…)`、5 份用 `parents[5]`」
两种写法并存。锚目录只认「这棵树长什么样」。
"""
from __future__ import annotations

from pathlib import Path

from 公共契约.正式根 import 正式根名表, 源码层名表

#: 系统根判据的锚目录：一个目录**同时**含这两者才算「本仓的包根」。
#: 只取垫片实际需要的两个（垫片要拼的是 `支持库/适配层/…` 与 `模块库/…`）；目录名表另有一份
#: 更全的 `公共契约/正式根.正式根名表`，但**锚取得越多越严**，与「我要的只是这棵树的包根」
#: 并不等价（少一个正式根就找不到根了），故只声明本判据真正依赖的那部分。
#: 自举段的内联块逐字用同一对字面量，由 `测试中心/开发工具/测试_导入前缀.py` 钉住。
根锚目录表 = ("支持库", "模块库")


def 取根前缀(模块名: str) -> str:
    """本模块所在树的导入前缀：`__name__` 里**第一个正式根段**之前的那一段。

    源码树里 `__name__` 以正式根开头 ⇒ 返回空串（行为与改前逐字相同）；
    制品里 `__name__` 形如 `平台客户端.支持库.…` ⇒ 返回 `平台客户端.`。

    **为什么不再写 `find("支持库.")`**（改前写法，已被 `测试_导入前缀` 逮到）：包根
    有三个（`支持库`／`模块库`／`技能库`，真源 `公共契约/正式根.正式根名表`），只认
    `支持库.` 会让 `平台客户端.模块库.…` **静默回空串** —— 前缀凭空消失、兜底分支被误进，
    症状正是 #216② 那一种「同一份实现在制品里被加载成第二个模块对象」。

    两道判据缺一不可：① 首个正式根段必须在**第 0 段之后**（在第 0 段就是源码树，回空串）；
    ② 它之前的段不得含本仓源码层名（拦 `测试中心.支持库.…` 这类**形状相似但非制品**的
    模块名 —— 它们的前缀不是制品前缀，回空串才是对的）。两表都取自 `公共契约/正式根`，
    不在此复写一份。
    """
    段表 = str(模块名 or "").split(".")
    for 序, 段 in enumerate(段表):
        if 段 not in 正式根名表:
            continue
        if 序 == 0 or any(名 in 源码层名表 for 名 in 段表[:序]):
            return ""
        return ".".join(段表[:序]) + "."
    return ""


def 取系统根(模块文件: str | Path) -> Path:
    """含 `根锚目录表` 全部锚目录的**最近祖先**（源码树与制品同判据）。

    找不到即 `ImportError`（fail-closed）：绝不返回一个猜出来的根 —— 猜错的根会让
    垫片去错误的位置按文件路径加载实现，症状是「整包装配失败」而不是「一个清晰的错」。
    """
    起点 = Path(模块文件).resolve()
    for 祖先 in 起点.parents:
        if all((祖先 / 名).is_dir() for 名 in 根锚目录表):
            return 祖先
    raise ImportError(
        f"找不到同时含 {'、'.join(根锚目录表)} 的祖先目录（模块文件: {模块文件}）")


__all__ = ["根锚目录表", "取根前缀", "取系统根"]
