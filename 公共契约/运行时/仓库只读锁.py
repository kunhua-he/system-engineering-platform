#:   跟踪的事实源，必须上锁**。这条是本模块自己漏过一轮、复核时用探针抓出来的。
豁免前缀: tuple[str, ...] = (".git/", "工程缓存/", ".venv/", "node_modules/")


def _命中豁免(相对路径: str) -> bool:
    """相对路径（正斜杠、无前导 `./`）是否落在豁免前缀内。

    **按路径段比，不按裸字符串前缀比**：判据是「该项本身」或「以该项 + `/` 打头的子孙」，
    两个条件都用**带尾斜杠**的形式 —— 于是 `.github` 不匹配 `.git/`

    （`".github/workflows/".startswith(".git/")` 为假：第 4 个字符是 `h` 不是 `/`）。

    `相对路径` 传空串（仓库根）恒返回假 —— 根目录**要上锁**，它正是「凭空新建顶层文件」
    那条漏径的落点。
    """
    归一 = 相对路径.strip("/")
    if not 归一:
        return 假
    带斜杠 = 归一 + "/"
    return 真 if any(带斜杠.startswith(x) for x in 豁免前缀) else 假


def 支持内核锁() -> bool:
    """本平台能否做内核级只读锁（macOS 真）。"""
    return 真 if (_是MACOS and 不可变标志 != 0) else 假


def _取标志(路径: Path) -> int:
    """读文件的 `st_flags`；读不到返回 0（当作「没锁」，由后续动作如实报错）。"""
    try:
        return int(os.stat(路径).st_flags)
    except (OSError, AttributeError):
        return 0


def 是锁着的(路径: str | Path) -> bool:
    """该路径当前是否置了不可变标志。"""
    return 真 if (_取标志(Path(路径)) & 不可变标志) else 假


def 上锁(路径: str | Path) -> bool:
    """给文件**或目录**置不可变标志。已锁则幂等；路径不存在返回 ``假``；失败抛 ``OSError``。

    **文件锁与目录锁各挡不同的东西，两者都要**（2026-09-23 实测，缺一不可）：

        · 文件锁 → 挡「改内容 / 删 / 改名 / chmod」（11 条写入路径全被内核拒）；
        · 目录锁 → 挡「**在该目录里新建条目**」。

    为什么必须补目录锁（实测缺口，**是本模块自己的测试抓出来的**）：只锁文件时
    `touch 开发文档/新文件.md` **照样成功** —— 「凭空新增一个文件」这条最典型的漂移路径
    没被挡住。锁住目录后同一动作被内核以 `Operation not permitted` 拒。

    不吞错：锁不上必须让调用方知道 —— 否则「整仓已锁」是一句假话。
    """
    目标 = Path(路径)
    if not 目标.exists():
        return 假
    标志 = _取标志(目标)
    if 标志 & 不可变标志:
        return 真
    os.chflags(目标, 标志 | 不可变标志)
    return 真


def _清标志(路径: str | Path) -> None:
    """裸原语：清掉不可变标志（**不做任何身份门槛**）。

    写腿的瞬时窗口（`临时解锁` / `临时解锁树`）与内部循环用它 —— 它们本来就在
    「显式解锁的那一刻」，再问一次身份只会把平台自己的落盘腿一起锁死。
    """
    目标 = Path(路径)
    标志 = _取标志(目标)
    if not (标志 & 不可变标志):
        return
    try:
        os.chflags(目标, 标志 & ~不可变标志)
    except OSError:
        return


