def 解锁供写入(路径: str | Path) -> None:
    """**租约用**：解锁一条路径，并把它的**父链**一路放开到第一个已未锁的祖先。

    为什么要连父链（与 `临时解锁()` 同根，2026-09-23 实测）：认领的路径常常**还不存在**
    （开工即占的「待建清单」），而「新建文件」是在父目录里加条目 —— 父目录锁着时
    `mkdir` / `open(..., "w")` 都被内核以 `Operation not permitted` 拒。只解目标本身
    会得到「认领了却写不进」。

    只认网关凭证（同 `解锁()`）—— 它是一条**放宽**动作，不是写腿的瞬时窗口。
    """
    _要求网关凭证("解锁供写入")
    目标 = Path(路径)
    _清标志(目标)
    # ★ 循环条件**不能**是「当前还锁着」：待建路径的父目录往往**也不存在**，
    #   `_取标志` 对不存在的路径回 0 ⇒ 第一步就退出、一个祖先都没放开 ⇒
    #   `mkdir(parents=True)` 照旧被内核拒（本函数初版就这么错，被探针当场抓住）。
    #   正确判据 = 「一路放开到**第一个已存在的祖先**」（与 `临时解锁()` 同一口径）。
    当前 = 目标.parent
    while True:
        _清标志(当前)
        if 当前.exists():
            break
        上 = 当前.parent
        if 上 == 当前:
            break
        当前 = 上


def 回锁(路径: str | Path, *, 连父链: bool = 假) -> None:
    """**租约用**：把一条路径锁回去（释放 / 过期回收时调；幂等，不存在则静默返回）。

    **不加身份门槛** —— 上锁是**安全方向**（同 `上锁()`）：门槛只该拦「放宽」，
    不该拦「收紧」。若给回锁也设门槛，一旦凭证对不上，租约释放就会静默留下一个洞。

    `连父链=真` 时**把认领时放开的那条链整条收回**：从目标一路向上，把仍开着的
    祖先逐个锁回去，到**第一个本来就锁着的祖先**为止。

    为什么不能只锁直接父目录（本函数初版就是那么写的，被探针实测抓住）：`解锁供写入`
    放开的是「目标 + 一路到第一个**已存在**祖先」整条链，而这条链的**长度会随新建而变化**
    —— 认领 `a/新目录/新文件.md` 时只放开到 `a`（`新目录` 当时不存在），建完之后
    `新目录` 也存在了，只锁直接父目录就会把 `a` 永久留开（实测 `未锁数=1`）。
    「第一个本来就锁着的祖先」正好是当初放开的**边界**（链的终点），故拿它收口。

    ★ **收链的边界**：一路向上收到**第一个本来就锁着的祖先**为止；若一路都开着，就收到
    **仓库根（含）** 为止，**绝不出仓库**。仓库外（`_推断仓库根` 回 `None`）不走链 ——
    不然会把任人目录锁掉。
    """
    目标 = Path(路径)
    if 目标.exists():
        try:
            os.chflags(目标, _取标志(目标) | 不可变标志)
        except OSError:
            pass
    if not 连父链:
        return
    仓库根 = _推断仓库根(目标)
    if 仓库根 is None:
        return
    当前 = 目标.parent
    while True:
        if _取标志(当前) & 不可变标志:
            break
        try:
            os.chflags(当前, _取标志(当前) | 不可变标志)
        except OSError:
            break
        if 当前 == 仓库根:
            break
        上 = 当前.parent
        if 上 == 当前:
            break
        当前 = 上


@contextmanager
def 临时解锁(*路径表: str | Path):
    """落盘用的上下文管理器：**解锁（含父目录）→ 让调用方写 → 恢复写前状态**。

    **为什么父目录也要解锁**：`os.replace(临时件, 目标)` 是「在父目录里换名」，
    以及「新建文件」是「在父目录里加条目」—— 父目录置了 `uchg` 时两者都被内核拒绝。
    只解锁目标文件会在 `replace`/新建那一步失败（实测）。

    ## 恢复规则（两类，**这是本函数唯一容易写错的地方**）

        · 写前**已存在**的路径 → 按它写前的 flags 恢复（锁着就重锁，没锁就保持没锁）；
        · 写前**不存在**的路径（本次新建）→ **继承父目录写前的锁状态**。

    第二条修的是一个实测漏锁（2026-09-23，MCP 端到端验收时发现）：初版只按「写前状态」
    恢复，于是**新建文件永远是未锁的** —— 平台每写一个新文件，整仓锁就多一个洞；
    `查询()` 的未锁数会从 0 变 1 并永久留着（实测：经 MCP 写一个 `.md` 后，该文件
    `flags` 为空、终端仍能改它）。

    为什么用「继承父目录」而不是「一律锁上」：一律锁上会让**未上锁期间的正常开发**
    也开始扩散锁（每写一个新文件就多一把锁），锁范围从「`上锁全仓()` 决定的集合」
    漂移成「所有被碰过的文件」，不可预测。按父目录继承则两边都对：

        · 父目录锁着（整仓已锁）⇒ 新文件也锁 ⇒ 未锁数维持 0，没有洞；
        · 父目录没锁（正常开发）⇒ 新文件也不锁 ⇒ 不扩散。

    异常路径也按同样规则恢复（`finally`）：写入失败不该留下解锁缺口。
    多条路径按「浅→深」解锁、「深→浅」恢复。
    """
    # 收集「路径本身 + 其父目录链」，去重后按路径深度升序解锁（父目录先）。
    # ★ 必须一路走到**第一个已存在的祖先**（含）：目标在**新建的多层目录**里时，
    #   `mkdir(parents=True)` 要逐层建，而每一层都是在它自己的父目录里加条目 ——
    #   只解锁「目标 + 它的直接父目录」不够（实测 2026-09-23：向已锁树里
    #   `写入文件('已锁目录/新目录/新文件.md')` 报 `Operation not permitted`，
    #   因为 `新目录` 的父目录 `已锁目录` 没被解锁）。
    待处理: dict[str, Path] = {}
    for 一项 in 路径表:
        目标 = Path(一项)
        候选链: list[Path] = [目标]
        当前 = 目标.parent
        while True:
            候选链.append(当前)
            if 当前.exists() or 当前 == 当前.parent:
                break
            当前 = 当前.parent
        for 候选 in 候选链:
            try:
                键 = str(候选.resolve())
            except OSError:
                键 = str(候选)
            待处理[键] = 候选
    顺序 = sorted(待处理.values(), key=lambda p: len(p.parts))

    #: 路径 → (写前是否锁着, 写前是否存在)。两个事实都要记：存在性决定「是不是新建」，
    #: 而「新建」那一类要改判成「继承父目录」，不能按自身（它写前根本不存在）。
    写前: dict[str, tuple[bool, bool]] = {}
    for 路径 in 顺序:
        标志 = _取标志(路径)
        写前[str(路径)] = (bool(标志 & 不可变标志), 路径.exists())
        if 标志 & 不可变标志:
            try:
                os.chflags(路径, 标志 & ~不可变标志)
            except OSError:
                pass
    try:
        yield
    finally:
        def _继承锁态(路径: Path) -> bool:
            """新建路径的锁态 = **最近一个「写前就已存在」的祖先**的写前锁态。

            为什么不是「直接父目录」：父目录可能**也是本次新建的**
            （多层新建 `已锁目录/新目录/新文件.md` 里 `新目录` 就是新的）——
            而新目录自己的写前记录是「不存在 ⇒ 未锁」，拿它当依据会把锁判成
            「不用锁」，于是**多层新建在锁树里留下一片未锁区域**（同族漏径）。
            故必须一路向上找到第一个写前就存在的祖先，用它的锁态。
            """
            当前 = 路径.parent
            while True:
                记录 = 写前.get(str(当前))
                if 记录 is not None and 记录[1]:
                    return 记录[0]
                上 = 当前.parent
                if 上 == 当前:
                    return 假
                当前 = 上

        # 深→浅恢复；**只在路径仍存在时**动 —— 删除类写入之后目标已经没了。
        for 路径 in reversed(顺序):
            键 = str(路径)
            原就锁着, 原就存在 = 写前.get(键, (假, 假))
            if not 路径.exists():
                continue
            要锁 = 原就锁着 if 原就存在 else _继承锁态(路径)
            try:
                if 要锁:
                    os.chflags(路径, _取标志(路径) | 不可变标志)
            except OSError:
                pass


def _推断仓库根(路径: Path) -> Path | None:
    """从路径往上找第一个带 `.git` 的目录（找不到返回 `None`，表示不在任何仓库里）。

    为什么需要它：`_上下文锁态()` 必须能分辨「祖先链上的锁属于本仓库」还是
    「属于仓库外（如 `/tmp`）」—— 仓库外没有受管面，也不存在豁免前缀。
    """
    当前 = 路径 if 路径.is_dir() else 路径.parent
    while True:
        if (当前 / ".git").exists():
            return 当前
        上 = 当前.parent
        if 上 == 当前:
            return None
        当前 = 上


def _在豁免区(路径: Path, 仓库根: Path | None) -> bool:
    """该路径是否落在豁免前缀内（仓库外恒为假）。

    为什么 `对齐目标锁态` 的递归候选也要过滤：目标可能是**仓库根**（三条调用都能传它），
    那时 `rglob("*")` 会把 `.git/` 与 `工程缓存/` 整棵包进来；参照锁态又是真 ⇒
    一次调用就把 `.git` 与制品树全部上锁 —— **git 写不了 index、构建写不了制品**。
    """
    if 仓库根 is None:
        return 假
    try:
        相对 = 路径.relative_to(仓库根).as_posix()
    except ValueError:
        return 假
    return _命中豁免(相对)


def _上下文锁态(路径: Path) -> bool:
    """**目标所在上下文的锁态**（不是「它父亲的状态」）——对齐的参照值。

    取值规则（顺序敏感）：

      1. 目标**自身**已锁 ⇒ 真。这一条最关键：目标本身是既有目录（仓库根、既有
         目标目录）时，它**就是**上下文，不能再往上看它的父目录（那是仓库外）。
         只看直接父目录会漏掉一类致命场景（2026-09-23 复核实测）：目标为既有目录
         时父目录在受管面外、恒判未锁 ⇒ 整棵子树里**原有的锁被逐条剥掉**。
         实测：假仓库 4 条全锁，一次 `对齐目标锁态(根)` 后未锁 4/4；
         现行仓库上同一调用会把 5671 条锁全解。三条调用可触发：
         `复制文件/移动文件(源, 目标路径=<既有目录>)`、
         `解压文件(源包, 目标目录=<既有目录>)`。
      2. 否则沿祖辈链找**最近一个锁着的祖先** —— 多层新建（`已锁/新目录/新文件`）
         时，中间新建的目录自己没锁，但它所处的上下文锁着。
      3. **遇到豁免前缀即停并返回假**：`工程缓存/` 这类豁免区不是受管面，
         它的祖辈（仓库根）锁着也不能把锁带进去（否则制品树被锁、网关与构建双双瘫痪）。
      4. 走到文件系统根还没找到 ⇒ 假（仓库外：副本自然是未锁的，不把锁带出仓库）。
    """
    仓库根 = _推断仓库根(路径)
    # ★ 「自身锁着 ⇒ 真」这条**只在本仓库内成立**（否则会把「复制出仓库」判反）：
    #   `copy2` 会把源的 flags 一起带出来，仓库外的副本天生是锁着的 —— 而仓库外
    #   没有受管面，副本应当是未锁的（否则「复制到临时区再改」全被内核拒）。
    #   实测 2026-09-23：不限定在仓库内时，本模块自己那两条「复制出仓库」用例当场红。
    #   仓库外则退化为「看直接父目录」的口径（单元判据本来就是这个语义）。
    if 仓库根 is not None and (_取标志(路径) & 不可变标志):
        return 真
    当前 = 路径.parent
    while True:
        if 仓库根 is not None:
            try:
                相对 = 当前.relative_to(仓库根).as_posix()
            except ValueError:
                return 假
            if _命中豁免(相对):
                return 假
        if _取标志(当前) & 不可变标志:
            return 真
        上 = 当前.parent
        if 上 == 当前:
            return 假
        当前 = 上


def 对齐目标锁态(目标: str | Path) -> int:
    """把「本次新建/搬入的路径」的锁态对齐到**其所在上下文的当前锁态**（递归；返回改动条数）。

    **规则只有一条，与写腿同源**：新条目**继承所在上下文的锁态** ——

        上下文锁着 ⇒ 目标也锁上（锁树里不留洞）；
        上下文没锁 ⇒ 目标也解开（不把锁带出仓库、不在开窗期扩散）。

    **为什么不能「按源文件恢复」**（洞 ④，2026-09-23 实测）：源文件的 flags 描述的是
    **它原来待的地方**，搬到新地方就该服从新地方的规矩。反例（修前真跑）：
    经 MCP `复制文件` 把 `/tmp` 的未锁文件复制进已锁的 `公共契约/运行时/`，
    副本 `flags` 为空、终端仍能改它 ⇒ **锁树里凭空多一个洞**（`查询()` 未锁数 0→1）。

    这条规则**写腿早已落地**（`临时解锁()` 的「本次新建继承父目录写前锁态」），
    但复制/移动/解压这些**同样会「新建条目」的腿漏了** —— 典型「同一根因只修一处、
    兄弟漏改」。故把规则提到这里做**唯一实现**，各腿调用，不再各写一遍（哲学 1.2）。

    顺带修掉反方向：把仓库里的**已锁**文件复制/移动到仓库外（如临时区）时，
    按源 flags 恢复会带出一把**解不开的锁**（实测 `shutil.copy2` 会连 `st_flags` 一起
    复制，导致「复制到临时区再改」的既有流程全部 `Operation not permitted`）——
    按目标父目录对齐则副本在仓库外自然是未锁的。
    """
    路径 = Path(目标)
    仓库根 = _推断仓库根(路径)
    参照锁着 = _上下文锁态(路径)
    # ★ 目标**不存在也要往下走**（2026-09-23 第三形态，子代理真跑抓出）：
    #   `mkdir(parents=True)` 建出中间层之后、落点本身还没写出来时中途抛错，
    #   早退 `return 0` 会让那几层**刚建的中间目录**永久留在未锁态。
    #   目标不存在时 `_上下文锁态` 自动退化为「沿祖辈链找最近一个锁着的祖先」，
    #   下面的祖辈链循环会把它们补进候选。
    候选: list[Path] = []
    if 路径.exists():
        候选.append(路径)
        if 路径.is_dir():
            # ★ 递归候选必须**排掉豁免区**（2026-09-23 复核补）：目标可能是仓库根
            #   （三条调用都能传它），`rglob("*")` 会把 `.git/` 与 `工程缓存/` 整棵
            #   包进来，而参照锁态是真 ⇒ 一次调用就把 `.git` 与制品树全上锁 ——
            #   **git 写不了 index、构建写不了制品**。
            候选.extend(项 for 项 in 路径.rglob("*") if not _在豁免区(项, 仓库根))
    # ★ 祖辈链也要进候选（2026-09-23 复核补，与 `_上下文锁态` 同源）：多层新建
    #   （`已锁/新目录/新文件`）时，**中间新建的目录也是「本次新建的条目」**，
    #   同样要继承上下文锁态；只对齐目标本身会让中间那层永久留在未锁态。
    #   停在「已锁的祖先」或「豁免前缀」上（两者都说明再往上不是本目标的上下文）。
    当前 = 路径.parent
    while True:
        if 仓库根 is not None:
            try:
                当前.relative_to(仓库根)
            except ValueError:
                break   # 走到仓库外了：再往上不是本目标的上下文
        if _在豁免区(当前, 仓库根) or (_取标志(当前) & 不可变标志):
            break
        候选.append(当前)
        上 = 当前.parent
        if 上 == 当前:
            break
        当前 = 上
    # 上锁走**浅→深**（父目录先锁，子条目仍能 chflags）；解锁走**深→浅**。
    候选.sort(key=lambda p: len(p.parts), reverse=not 参照锁着)
    改动 = 0
    for 条目 in 候选:
        try:
            标志 = _取标志(条目)
        except OSError:
            continue
        当前锁着 = bool(标志 & 不可变标志)
        if 参照锁着 and not 当前锁着:
            try:
                os.chflags(条目, 标志 | 不可变标志)
                改动 += 1
            except OSError:
                pass
        elif not 参照锁着 and 当前锁着:
            try:
                os.chflags(条目, 标志 & ~不可变标志)
                改动 += 1
            except OSError:
                pass
    return 改动


@contextmanager
def 临时解锁树(根: str | Path):
    """递归落盘用的上下文管理器：**整棵树的文件与目录都解锁 → 写 → 按原状态重锁**。

    与 `临时解锁()` 的分工：那一个是「单文件（含其父目录）」的细粒度窗口，
    本函数是「**子树批量动作**」（递归删除、压缩、解压、整树搬移）用的 ——
    那些动作要动的条目事先数不清，逐条传参不现实（哲学 1.2：一条腿覆盖一类）。

    **只记录并重锁「进入时确实锁着的」条目**（同 `临时解锁()` 的口径）：
    本来没锁的文件写完之后保持没锁，锁范围不因谁碰过它而扩散。

    **祖辈链一路补到第一个已存在祖先**（与 `临时解锁()` 同口径，2026-09-23 复核补）：
    只补直接父目录时，「目标不存在且上层目录还没建」的整树动作（`mkdir(parents=True)`、
    多层搬入）会在**祖父目录**处被内核拒 —— 实测
    `临时解锁树(已锁/新目录/新文件.txt)` 里 `mkdir(parents=True)` 抛 `PermissionError`，
    而同场景 `临时解锁` 成功（就是这处口径不一致）。
    """
    根路径 = Path(根).resolve()
    原状态: list[Path] = []
    # 先收集（此时还没解锁，能正常遍历），再解锁 —— 顺序反了会在遍历中途踩到未解锁的目录。
    候选: list[Path] = []
    if 根路径.is_dir():
        候选.append(根路径)
        候选.extend(根路径.rglob("*"))
    elif 根路径.exists():
        候选.append(根路径)
    当前 = 根路径
    while True:
        上级 = 当前.parent
        候选.append(上级)
        if 上级.exists() or 上级 == 上级.parent:
            break
        当前 = 上级
    for 路径 in 候选:
        if _取标志(路径) & 不可变标志:
            原状态.append(路径)
    # 浅→深解锁（父目录先，否则子条目的 chflags 会被父目录的锁挡住）。
    for 路径 in sorted(原状态, key=lambda p: len(p.parts)):
        try:
            os.chflags(路径, _取标志(路径) & ~不可变标志)
        except OSError:
            pass
    try:
        yield
    finally:
        # 深→浅重锁；**仍存在的才重锁**（删除类动作之后目标没了）。
        for 路径 in sorted(原状态, key=lambda p: len(p.parts), reverse=True):
            if 路径.exists():
                try:
                    os.chflags(路径, _取标志(路径) | 不可变标志)
                except OSError:
                    pass


def _受管条目(仓库根: Path) -> list[Path]:
    """本锁的**扫描面**：tracked + 未跟踪未忽略的**文件**，外加它们所在的**目录**。

    为什么目录也要进扫描面：只锁文件挡不住「在该目录里新建条目」（实测 `touch` 照样成功），
    而「凭空新增一个文件」正是最典型的漂移路径。目录锁与文件锁各挡一半，缺一不可。

    为什么用 `git ls-files` 而不是 `rglob("*")`（两个理由各自独立）：
    ① 它天然排除 `.gitignore` 里的东西（`工程缓存/`、`__pycache__/`、`.venv/` 等），
       不必在本模块再抄一份忽略表（抄一份必然与 `.gitignore` 漂移）；
    ② 它给出的正是「**这个项目的事实源文件**」，即华哥说的「仅限这个项目」。

    ★ **三条漏径都在本函数里修过一次**（2026-09-23 复核用探针逐条实测出来的，
    不是先验推断）—— 三者的共同形状是「扫描面不全，于是锁有洞而 `查询()` 还报全绿」：

    1. **仓库根目录本身**：早先的父目录链循环把 `相对目录 in ("", ".")` 当终止条件、
       在**加入字典之前**就 `break`，于是根从来没被锁。实测后果：`touch 顶层探针.txt`
       在根下**成功**（顶层凭空新建），而 `查询()` 报「未锁数 0 · 全部上锁」。
    2. **豁免前缀按裸串比**：父目录链那一步用的是 `startswith(x.rstrip("/"))`，
       于是 `.github/` 命中 `.git` 被豁免 —— 连同 `.gitattributes` / `.gitignore`。
       实测后果：`.github/workflows/探针.yml` 能凭空新建（而那是跟踪的事实源）。
       已改为统一走 `_命中豁免()`（按**路径段 + 带尾斜杠**比）。
    3. **未跟踪的空目录**：`git ls-files` 只列文件，空目录不出现 ——
       实测 `开发工具/说明书生成/`、`底座浏览器会话/`、`测试中心/慢速层/` 等
       里面**都能凭空新建**（这些正是「本轮新建但还没落文件」的目录，恰是最该锁的）。
       本函数补一次 `--directory` 扫描（git 会把整包未跟踪目录折叠成 `路径/`）。

    ★ 注意 `--directory` 与逐文件扫描**不可互相替代**：前者把「整包未跟踪目录」折叠成一行，
    于是 `工程缓存/` 之外的整树未跟踪目录（如 `开发文档/分析/` 若整包未跟踪）只有前者能报；
    后者给出每个文件的父目录链。两者都跑，取并集。
    """
    文件: dict[str, Path] = {}
    目录: dict[str, Path] = {}
    二分 = "/Library/Developer/CommandLineTools/usr/bin/git"
    if not Path(二分).exists():
        二分 = "git"

    def _收目录(路径: Path) -> None:
        """把「该路径及其父目录链（到仓库根为止）」全部登记进 `目录`。

        终止条件是「已到仓库根」—— **不是**「相对目录为空」：
        根目录自己必须进 `目录`（漏径 1 的修复点）。

        **不再逐步判豁免**：调用方进来之前已经用 `_命中豁免()` 判过「这条路径本身」，
        而豁免是**前缀关系**（`工程缓存/` 的一切子孙都豁免）——
        故一个不豁免的路径，它的祖先必然也不豁免，无需在链上再判一次
        （链上再判一次正是漏径 2 那个裸串 bug 的藏身处，去掉它等于去掉一处复发点）。
        """
        当前 = 路径
        while True:
            try:
                相对目录 = 当前.relative_to(仓库根).as_posix()
            except ValueError:
                break
            目录[相对目录] = 当前
            if 当前 == 仓库根:
                break
            当前 = 当前.parent

    # ① tracked + 未跟踪未忽略的**文件**；② `--directory` 补**空目录**与折叠的未跟踪树。
    for 参数 in (["ls-files"],
                 ["ls-files", "--others", "--exclude-standard"],
                 ["ls-files", "--others", "--exclude-standard", "--directory"]):
        try:
            输出 = subprocess.run([二分, *参数], cwd=仓库根, capture_output=True,
                                text=True, timeout=120, check=False)
        except (OSError, subprocess.SubprocessError):
            continue
        if 输出.returncode != 0:
            continue
        for 行 in 输出.stdout.splitlines():
            相对 = 行.strip().rstrip("/")
            if not 相对 or _命中豁免(相对):
                continue
            路径 = 仓库根 / 相对
            if 路径.is_file():
                文件[相对] = 路径
                _收目录(路径.parent)
            elif 路径.is_dir():
                # 空目录 / `--directory` 折叠出来的未跟踪目录：它自己 + 父目录链都要锁。
                _收目录(路径)
    # 仓库根：任何一条已登记路径的父目录链都能走到根，故有内容时根必已登记；
    # 这里只是把「有受管条目 ⇒ 根确已进表」写成显式断言性动作（空仓时不锁根，
    # 否则连第一个文件都建不出来）。
    if 文件 or 目录:
        _收目录(仓库根)
    return list(文件.values()) + list(目录.values())


def _受管文件(仓库根: Path) -> list[Path]:
    """只返回受管**文件**（不含目录）。供需要「文件计数」口径的调用方使用。"""
    return [p for p in _受管条目(仓库根) if p.is_file()]


def 上锁全仓(仓库根: str | Path) -> dict:
    """给全仓受管**文件与目录**置不可变标志。返回
    ``{支持, 文件数, 目录数, 已锁数, 新锁数, 失败表}``。"""
    根 = Path(仓库根).resolve()
    if not 支持内核锁():
        return {"支持": 假, "文件数": 0, "目录数": 0, "已锁数": 0, "新锁数": 0,
                "失败表": [["", "本平台不支持内核级只读锁（仅 macOS 的 chflags）"]]}
    已锁 = 新锁 = 0
    失败: list[list[str]] = []
    条目表 = _受管条目(根)
    # **浅→深**上锁：父目录先锁上之后，子条目仍能 chflags（在同一进程里属主可改），
    # 但顺序统一有利于「中途被杀」时留下的是「父锁子未锁」这种可被 重锁一遍 补齐的状态。
    for 路径 in sorted(条目表, key=lambda p: len(p.parts)):
        try:
            if 是锁着的(路径):
                已锁 += 1
                continue
            上锁(路径)
            新锁 += 1
        except OSError as 错误:
            失败.append([路径.relative_to(根).as_posix(), str(错误)])
    文件数 = sum(1 for p in 条目表 if p.is_file())
    return {"支持": 真, "文件数": 文件数, "目录数": len(条目表) - 文件数,
            "已锁数": 已锁, "新锁数": 新锁, "失败表": 失败}


def 解锁全仓(仓库根: str | Path) -> dict:
    """清掉全仓受管文件与目录的不可变标志（**改代码前的显式动作**）。

    ★ **只认网关凭证**（同 `解锁()`）：不经 MCP 即抛 `PermissionError`。
    这就是「`--下锁` 一行命令无门槛解全仓」那个缺口的收口点（2026-09-23 实测：
    终端跑 `python3.14 运维脚本/仓库锁.py --下锁` 退出码 0、解开 5672 项）。

    解锁顺序**深→浅**：先放开子条目再放开父目录 —— 反过来会在父目录已解锁、
    子条目仍锁着时留下「半开」状态（不影响正确性，但读数更难看）。
    """
    _要求网关凭证("解锁全仓")
    根 = Path(仓库根).resolve()
    if not 支持内核锁():
        return {"支持": 假, "文件数": 0, "解锁数": 0, "失败表": []}
    解锁数 = 0
    失败: list[list[str]] = []
    条目表 = _受管条目(根)
    for 路径 in sorted(条目表, key=lambda p: len(p.parts), reverse=True):
        try:
            if 是锁着的(路径):
                _清标志(路径)
                解锁数 += 1
        except OSError as 错误:
            失败.append([路径.relative_to(根).as_posix(), str(错误)])
    return {"支持": 真, "文件数": sum(1 for p in 条目表 if p.is_file()),
            "解锁数": 解锁数, "失败表": 失败}


def 重锁一遍(仓库根: str | Path) -> dict:
    """兜底：把「该锁却没锁」的文件补上（幂等，可反复跑）。

    为什么需要它：写腿的「解锁→写→重锁」若在中间被杀（SIGKILL、断电），文件会停在
    解锁态 —— 一把锁出现缺口。本函数把缺口补回来。
    """
    return 上锁全仓(仓库根)


def 查询(仓库根: str | Path, *, 取前: int = 20) -> dict:
    """如实报锁的状态：受管条目数（文件 + 目录）/ 已锁 / **未锁（缺口）** / 样本 / 是否支持。

    「未锁数」是本方案唯一需要的度量 —— 锁的强度不靠感觉，靠这个数是不是 0。
    **目录与文件一起算**：只锁文件挡不住「在目录里新增条目」（实测 `touch` 照样成功），
    所以「未锁数=0」必须同时覆盖两者，否则这个读数会给出虚假的安全感。
    """
    根 = Path(仓库根).resolve()
    if not 支持内核锁():
        return {"支持": 假, "文件数": 0, "目录数": 0, "已锁数": 0, "未锁数": 0,
                "未锁样本": [], "说明": "本平台不支持内核级只读锁"}
    未锁: list[str] = []
    已锁数 = 0
    条目表 = _受管条目(根)
    for 路径 in 条目表:
        相对 = 路径.relative_to(根).as_posix()
        if 是锁着的(路径):
            已锁数 += 1
        else:
            未锁.append(相对)
    文件数 = sum(1 for p in 条目表 if p.is_file())
    return {
        "支持": 真,
        "文件数": 文件数,
        "目录数": len(条目表) - 文件数,
        "已锁数": 已锁数,
        "未锁数": len(未锁),
        "未锁样本": sorted(未锁)[:取前],
        "说明": ("全部上锁" if not 未锁
              else f"{len(未锁)} 个受管条目未上锁"
                   "（写腿中途被杀会留下缺口，可跑 重锁一遍 补齐）"),
    }
