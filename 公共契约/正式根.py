全仓口径 = 扫描口径(根名=正式根名表, 含聚合视图包=True)


def 是保留目录(包目录: Path, 根目录: Path) -> bool:
    """`包目录` 相对 `根目录` 的路径里是否出现保留段（`_`/`.` 开头或语义非生产名）。

    **判据必须相对根**（2026-09-15 实测教训）：`模块库/能力目录` 原用绝对路径
    逐段判断 `"工程缓存" in 声明路径.parts`，而制品整个落在
    `<仓>/工程缓存/制品仓库/…` 之下 → **制品运行时会把自己的全部包都排除掉**，
    索引恒为空。相对根判断后：根内确实存在的缓存/保留目录照旧被排除，
    根外的宿主目录不再误伤。
    """
    try:
        相对 = (根目录 if 包目录 == 根目录 else 包目录.relative_to(根目录))
    except ValueError:
        # 不在根下：口径无法判定，按保留处理（fail-closed，不白送收录）。
        return 真
    return any(段.startswith(保留目录前缀) or 段 in 保留目录段名 for 段 in 相对.parts)


def 是非生产声明(声明: object, 包id: str = "") -> bool:
    """包声明是否**自己**表明「非生产」（模板/样板/仅供复制/仅供开发/已废弃）。

    与 `是保留目录`（物理判据）配对成「双重判断」：模板改名后仅靠目录名会漏进
    生产索引，仅靠字段则改名的模板包不会主动声明。此前这条判据只住在
    `开发工具/项目编译/正式包索引.py`（`_是非生产包`），其余扫描器不认 ——
    债务 #38 的分叉之一；现上移本处作唯一源。

    `包id` 的 `模块库._模板*` 前缀判据也在此（原 `_是非生产包` 的第二条）：
    目录被改名但 包id 仍自称模板的那些包，靠这条兜住。
    """
    if 包id.startswith("模块库._模板"):
        return 真
    if not isinstance(声明, dict):
        return 假
    for 字段 in 非生产声明字段:
        值 = 声明.get(字段)
        if isinstance(值, bool) and 值:
            return 真
        if isinstance(值, str) and 值.strip().lower() in 非生产真值:
            return 真
    状态 = str(声明.get("状态", "")).strip().lower()
    return 状态 in 非生产状态值


def 子包声明表(包目录: Path) -> list[Path]:
    """包目录下**子包**（不含自身）的 `包声明.json`，跳过保留段。

    递归到孙子包（不只看直接子目录）：只认直接子目录会给「隔一层才放子包」
    留同样的判定后门。**不设上限**：截断会让「有没有子包」的判定随子包数量
    翻转（超过上限就把聚合视图包误判成真包），那是把口径变成隐性开关。
    """
    路径表: list[Path] = []
    for 声明路径 in sorted(包目录.rglob(声明文件名)):
        if 声明路径.parent == 包目录:
            continue
        try:
            相对 = 声明路径.parent.relative_to(包目录)
        except ValueError:
            continue
        if any(段.startswith(保留目录前缀) for 段 in 相对.parts):
            continue
        路径表.append(声明路径)
    return 路径表


def 是聚合视图包(包目录: Path) -> bool:
    """聚合视图父包：**无 `能力定义.json` 且含子包声明**（自己不拥有任何能力）。

    自带 `能力定义.json` 的包即便含子包（如 `代码解析支持库` 含 `语法索引`）
    仍是真实能力 owner，**必须收录**。判据此前在 7 处各写一份（发现器用
    「6 聚合库名表」、正式包索引用「聚合库名表 + 无能力定义」、门禁用三条），
    本函数是唯一一份。
    """
    if (包目录 / "能力定义.json").is_file():
        return 假
    return bool(子包声明表(包目录))


def 枚举包目录(系统根, 口径: 扫描口径) -> list[Path]:
    """按 `口径` 枚举包目录，按「相对系统根的 posix 路径」排序。

    这是「正式根下有哪些包」的**唯一实现**。任何调用方要一份包清单都必须走它，
    不许再写 `rglob("包声明.json")` + 自定过滤（哲学 12.1）。
    """
    系统根 = Path(系统根)
    出: list[Path] = []
    for 根目录名 in 口径.根名:
        根目录 = 系统根 / 根目录名
        if not 根目录.is_dir():
            continue
        for 声明路径 in 根目录.rglob(声明文件名):
            if 是保留目录(声明路径.parent, 根目录):
                continue
            包目录 = 声明路径.parent
            if not 口径.含聚合视图包 and 是聚合视图包(包目录):
                continue
            出.append(包目录)
    return sorted(出, key=lambda 路径: 路径.relative_to(系统根).as_posix())



def 枚举包声明路径(系统根, 口径: 扫描口径) -> list[Path]:
    """同 `枚举包目录`，返回 `包声明.json` 路径（调用方要自己读声明时用）。"""
    return [包目录 / 声明文件名 for 包目录 in 枚举包目录(系统根, 口径)]

