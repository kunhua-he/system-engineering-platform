"""正式根清单：平台「哪些顶层目录是正式包根」的唯一事实源。

依据：华哥设计哲学第 10 条（缺什么补什么：治理类能力要补进对应的那个库）
与决策记录 `0012_装配根声明式化与平台治理能力面.md`。

为什么必须有这个文件：把正式根写成三根（支持库/模块库/技能库）硬编码在
发现器、正式包索引、完整性摘要、依赖锁定等多处，本身就是「用特例绕过」——
新增一个正式层（`平台控制面`、`运行核心` 的治理能力面）要同时改 N 处，
改漏一处就出现「有的地方认、有的地方不认」的第二事实源。

口径：
- **根目录里含 `包声明.json` 才参与发现/统计**（空根自动跳过，行为与原来一致）；
- 除 `模块库` 按「模块」识别外，其余正式根按「支持库」识别——`技能库`
  已有先例：单独成根只是让它在目录上与支持库/模块库平级，包类型同口径；
- 新增正式层只改本文件的 `正式根名表`，调用方一律读这里。

**包目录口径也住本文件**（`扫描口径` / `枚举包目录`）：见下方「包目录口径」一节，
那里是「正式根下哪些目录算包声明面」的唯一事实源。
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

# 唯一清单：顶层正式包根（顺序＝发现/统计顺序）
正式根名表: tuple[str, ...] = ("支持库", "模块库", "技能库", "平台控制面", "运行核心", "启动监督器")

# 包类型映射：不在表内的根按「支持库」口径识别
包类型映射: dict[str, str] = {"模块库": "模块"}

声明文件名 = "包声明.json"


def 包类型(根目录名: str) -> str:
    """正式根目录名 → 包类型（模块库=模块，其余=支持库）。"""
    return 包类型映射.get(根目录名, "支持库")


def 存在根名(系统根) -> list[str]:
    """系统根下实际存在的正式根名（只判目录存在，不判是否含包）。"""
    系统根 = Path(系统根)
    出: list[str] = []
    for 根目录名 in 正式根名表:
        if (系统根 / 根目录名).is_dir():
            出.append(根目录名)
    return 出


def 枚举正式根(系统根) -> list[tuple[Path, str]]:
    """参与发现/装配的正式根：(目录, 包类型)。

    只有**含 `包声明.json`** 的正式根才返回——空根（如尚未补能力面的
    `平台控制面`）参与进来只会制造无意义扫描和「根不在装配里」的误判。
    """
    系统根 = Path(系统根)
    出: list[tuple[Path, str]] = []
    for 根目录名 in 正式根名表:
        根目录 = 系统根 / 根目录名
        if not 根目录.is_dir():
            continue
        if not any(根目录.rglob(声明文件名)):
            continue
        出.append((根目录, 包类型(根目录名)))
    return 出


# ═══════════════════════════════════════════════════════════════════
# 包目录口径（唯一事实源）
# ═══════════════════════════════════════════════════════════════════
#
# **为什么口径必须住这里**（2026-09-18 债务 #38 收口）：
# 此前「正式根下哪些目录算包声明面」有 7 处各写一份 `rglob("包声明.json")`
# 加各自自定的过滤规则，同一系统根能得出 4 个不同的包数（现场实测
# **136 / 142 / 124 / 119**）：
#
# | 扫描器 | 扫描范围 | 过滤规则 | 产出 |
# |---|---|---|---|
# | `运行核心/加载器/包发现/发现器.py::扫描目录` | 逐根传入 | `_`/`.` 前缀段 + 6 聚合库名表子域 | 136（全根） |
# | `开发工具/项目编译/正式包索引.py::_扫描包` | 全根 | 非生产路径片段 + 非生产字段 + 状态字段 + 聚合父包 | 136 |
# | `支持库/后端/组件规范支持库/实现/完整性摘要.py::扫描正式包` | 全根 | 无（`__pycache__` 由 rglob 之外决定） | 142 |
# | `开发工具/契约编译/生成物一致性检查.py::枚举正式包` | 仓根 `os.walk` | 跳过 `工程缓存/.git/__pycache__/node_modules/示例项目` | 142 |
# | `平台控制面/能力目录/消费者登记判定.py::枚举正式包` | 全根 | `__pycache__` | 142 |
# | `开发工具/公开调用完整性门禁.py::找全部包目录` | 全根 | `_`/`.` 前缀段 + 系统适配器名录 | 142 |
# | `模块库/能力目录/实现/能力索引.py::扫描包目录` | 支持库+模块库 | 相对根的 `工程缓存`/`__pycache__` | 124 |
# | `开发工具/契约编译/漂移检测.py::_全仓注册口径扫描` | 三根硬编码 | 只收 `能力契约/参数契约.json` | 119 |
#
# 差异**不是「范围不同」**（范围本就该由调用方按用途声明），而是**同一件事
# 各写一份规则**：`_模板` 目录在发现器被跳过、在能力索引被收；`状态=非生产`
# 的包在正式包索引被排除、在完整性摘要被收——这些是哲学 12.1（唯一事实源）
# 与 1.2（不保留旧腿）下的真缺陷，不是可容忍的口径差。
#
# 故：**过滤规则只有下面这一份**；调用方只能传两个**显式**范围参数
# （扫哪些正式根 / 收不收聚合视图父包），不许再自定任何跳过逻辑。

#: 保留目录前缀：`_`/`.` 开头的段＝模板、草稿、隐藏目录，不是正式包。
保留目录前缀 = ("_", ".")

#: 保留目录段名：不带前缀但语义明确非生产的目录名（模板/样板/开发样例）。
#: 与 `保留目录前缀` 合并成唯一一份「哪些目录不是正式包」的判据
#: —— 原「非生产路径片段」住在 `正式包索引` 一家，别的扫描器不认，
#: 属债务 #38 要消灭的那类分叉。
保留目录段名 = frozenset({"模板", "样板", "非生产", "开发样例"})

#: 非生产声明字段：包自己声明「我是模板/仅供复制/仅供开发」时，一票排除。
#: **双重判断**（物理目录 + 显式声明）是刻意的：模板改名后仅靠目录名会漏进
#: 生产索引，仅靠字段则改名的模板包不会主动声明。判据只有这一份。
非生产声明字段 = ("非生产", "仅供复制", "仅供开发", "模板", "样板")

#: `非生产声明字段` 里被认定为「真」的字符串写法（大小写/中文都收）。
非生产真值 = frozenset({"是", "true", "1", "非生产"})

#: `状态` 字段里被认定为非生产的取值。
非生产状态值 = frozenset({"非生产", "草稿", "模板", "样板", "deprecated", "废弃"})


@dataclass(frozen=True)
class 扫描口径:
    """包发现口径：扫描范围**显式声明**，过滤规则只有一份。

    两个字段都不是「开关」，而是调用方按用途必须挑明的事实：

    - `根名`：扫哪些正式根（必须取自 `正式根名表`；空元组＝不扫，判红由调用方负责）；
    - `含聚合视图包`：聚合视图父包（无 `能力定义.json` 且含子包声明）只作目录视图，
      自身不注册能力。**完整性摘要 / 说明书 / 生成物对账必须含它**（每个包声明目录
      都有这两类文件）；**装配 / 能力 owner / 漂移门禁必须不含它**（它不是 owner）。
    """

    根名: tuple[str, ...]
    含聚合视图包: bool = False


#: 装配口径：全正式根、不含聚合视图父包（对应 `后端核心` 装配注册表包集合）。
装配口径 = 扫描口径(根名=正式根名表, 含聚合视图包=False)

#: 全仓口径：全正式根、含聚合视图父包（对应「有 `包声明.json` 的目录」全集）。
全仓口径 = 扫描口径(根名=正式根名表, 含聚合视图包=True)


def 是保留目录(包目录: Path, 根目录: Path) -> bool:
    """`包目录` 相对 `根目录` 的路径里是否出现保留段（`_`/`.` 开头或语义非生产名）。

    **判据必须相对根**（2026-09-15 实测教训）：`模块库/能力目录` 原用绝对路径
    逐段判断 `"工程缓存" in 声明路径.parts`，而制品整个落在
    `<仓>/工程缓存/制品仓库/…` 之下 → **制品运行时会把自己的全部包都排除掉**，
    索引恒为空。相对根判断后：根内确实存在的缓存/保留目录照旧被排除，
    根外的宿主目录不再误伤。
    """
    try:
        相对 = (根目录 if 包目录 == 根目录 else 包目录.relative_to(根目录))
    except ValueError:
        # 不在根下：口径无法判定，按保留处理（fail-closed，不白送收录）。
        return True
    return any(段.startswith(保留目录前缀) or 段 in 保留目录段名 for 段 in 相对.parts)


def 是非生产声明(声明: object, 包id: str = "") -> bool:
    """包声明是否**自己**表明「非生产」（模板/样板/仅供复制/仅供开发/已废弃）。

    与 `是保留目录`（物理判据）配对成「双重判断」：模板改名后仅靠目录名会漏进
    生产索引，仅靠字段则改名的模板包不会主动声明。此前这条判据只住在
    `开发工具/项目编译/正式包索引.py`（`_是非生产包`），其余扫描器不认 ——
    债务 #38 的分叉之一；现上移本处作唯一源。

    `包id` 的 `模块库._模板*` 前缀判据也在此（原 `_是非生产包` 的第二条）：
    目录被改名但 包id 仍自称模板的那些包，靠这条兜住。
    """
    if 包id.startswith("模块库._模板"):
        return True
    if not isinstance(声明, dict):
        return False
    for 字段 in 非生产声明字段:
        值 = 声明.get(字段)
        if isinstance(值, bool) and 值:
            return True
        if isinstance(值, str) and 值.strip().lower() in 非生产真值:
            return True
    状态 = str(声明.get("状态", "")).strip().lower()
    return 状态 in 非生产状态值


def 子包声明表(包目录: Path) -> list[Path]:
    """包目录下**子包**（不含自身）的 `包声明.json`，跳过保留段。

    递归到孙子包（不只看直接子目录）：只认直接子目录会给「隔一层才放子包」
    留同样的判定后门。**不设上限**：截断会让「有没有子包」的判定随子包数量
    翻转（超过上限就把聚合视图包误判成真包），那是把口径变成隐性开关。
    """
    路径表: list[Path] = []
    for 声明路径 in sorted(包目录.rglob(声明文件名)):
        if 声明路径.parent == 包目录:
            continue
        try:
            相对 = 声明路径.parent.relative_to(包目录)
        except ValueError:
            continue
        if any(段.startswith(保留目录前缀) for 段 in 相对.parts):
            continue
        路径表.append(声明路径)
    return 路径表


def 是聚合视图包(包目录: Path) -> bool:
    """聚合视图父包：**无 `能力定义.json` 且含子包声明**（自己不拥有任何能力）。

    自带 `能力定义.json` 的包即便含子包（如 `代码解析支持库` 含 `语法索引`）
    仍是真实能力 owner，**必须收录**。判据此前在 7 处各写一份（发现器用
    「6 聚合库名表」、正式包索引用「聚合库名表 + 无能力定义」、门禁用三条），
    本函数是唯一一份。
    """
    if (包目录 / "能力定义.json").is_file():
        return False
    return bool(子包声明表(包目录))


def 是装配包(包目录: Path, 根目录: Path, 声明: object = None) -> bool:
    """装配口径的**唯一收录判据**：保留目录 / 聚合视图父包 / 非生产声明，三者皆非。

    `声明` 已由调用方读好时传进来（避免重复读盘）；为 `None` 时本函数自行读
    `包目录/包声明.json`，**读不成即判「不是装配包」**（fail-closed：宁可漏收
    并让上层报缺口，也绝不因为一次读取故障白送一张收录票）。

    此前这套判据分裂成两份互不相同的实现：`发现器.扫描目录`（`_`/`.` 前缀 +
    6 聚合库名表）与 `正式包索引._扫描包`（非生产路径片段 + 非生产字段 + 状态
    字段 + 聚合父包）。两份对同一目录可以给出相反结论 —— 见本模块头「包目录口径」。
    """
    if 是保留目录(包目录, 根目录):
        return False
    if 是聚合视图包(包目录):
        return False
    if 声明 is None:
        import json
        try:
            声明 = json.loads((包目录 / 声明文件名).read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, ValueError):
            return False
    包id = str(声明.get("包id", "")) if isinstance(声明, dict) else ""
    return not 是非生产声明(声明, 包id)


def 枚举包目录(系统根, 口径: 扫描口径) -> list[Path]:
    """按 `口径` 枚举包目录，按「相对系统根的 posix 路径」排序。

    这是「正式根下有哪些包」的**唯一实现**。任何调用方要一份包清单都必须走它，
    不许再写 `rglob("包声明.json")` + 自定过滤（哲学 12.1）。
    """
    系统根 = Path(系统根)
    出: list[Path] = []
    for 根目录名 in 口径.根名:
        根目录 = 系统根 / 根目录名
        if not 根目录.is_dir():
            continue
        for 声明路径 in 根目录.rglob(声明文件名):
            if 是保留目录(声明路径.parent, 根目录):
                continue
            包目录 = 声明路径.parent
            if not 口径.含聚合视图包 and 是聚合视图包(包目录):
                continue
            出.append(包目录)
    return sorted(出, key=lambda 路径: 路径.relative_to(系统根).as_posix())



def 枚举包声明路径(系统根, 口径: 扫描口径) -> list[Path]:
    """同 `枚举包目录`，返回 `包声明.json` 路径（调用方要自己读声明时用）。"""
    return [包目录 / 声明文件名 for 包目录 in 枚举包目录(系统根, 口径)]

