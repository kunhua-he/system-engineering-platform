"""正式根清单：平台「哪些顶层目录是正式包根」的唯一事实源。

依据：华哥设计哲学第 10 条（缺什么补什么：治理类能力要补进对应的那个库）
与决策记录 `0012_装配根声明式化与平台治理能力面.md`。

为什么必须有这个文件：把正式根写成三根（支持库/模块库/技能库）硬编码在
发现器、正式包索引、完整性摘要、依赖锁定等多处，本身就是「用特例绕过」——
新增一个正式层（`平台控制面`、`运行核心` 的治理能力面）要同时改 N 处，
改漏一处就出现「有的地方认、有的地方不认」的第二事实源。

口径：
- **根目录里含 `包声明.json` 才参与发现/统计**（空根自动跳过，行为与原来一致）；
- 除 `模块库` 按「模块」识别外，其余正式根按「支持库」识别——`技能库`
  已有先例：单独成根只是让它在目录上与支持库/模块库平级，包类型同口径；
- 新增正式层只改本文件的 `正式根名表`，调用方一律读这里。
"""

from __future__ import annotations

from pathlib import Path

# 唯一清单：顶层正式包根（顺序＝发现/统计顺序）
正式根名表: tuple[str, ...] = ("支持库", "模块库", "技能库", "平台控制面", "运行核心", "启动监督器")

# 包类型映射：不在表内的根按「支持库」口径识别
包类型映射: dict[str, str] = {"模块库": "模块"}

声明文件名 = "包声明.json"


def 包类型(根目录名: str) -> str:
    """正式根目录名 → 包类型（模块库=模块，其余=支持库）。"""
    return 包类型映射.get(根目录名, "支持库")


def 存在根名(系统根) -> list[str]:
    """系统根下实际存在的正式根名（只判目录存在，不判是否含包）。"""
    系统根 = Path(系统根)
    出: list[str] = []
    for 根目录名 in 正式根名表:
        if (系统根 / 根目录名).is_dir():
            出.append(根目录名)
    return 出


def 枚举正式根(系统根) -> list[tuple[Path, str]]:
    """参与发现/装配的正式根：(目录, 包类型)。

    只有**含 `包声明.json`** 的正式根才返回——空根（如尚未补能力面的
    `平台控制面`）参与进来只会制造无意义扫描和「根不在装配里」的误判。
    """
    系统根 = Path(系统根)
    出: list[tuple[Path, str]] = []
    for 根目录名 in 正式根名表:
        根目录 = 系统根 / 根目录名
        if not 根目录.is_dir():
            continue
        if not any(根目录.rglob(声明文件名)):
            continue
        出.append((根目录, 包类型(根目录名)))
    return 出
