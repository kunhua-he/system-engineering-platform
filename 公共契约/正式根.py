def 是核心面路径(相对路径) -> bool:
    """相对路径（项目根相对、posix）是否落在**核心面或核心支撑面**内。

    「核心 0 债务」的量化与常驻扫描一律走本函数，不许各自拼路径前缀
    （各拼一份＝同一事实两把尺子）。`开发工具` 按 `核心支撑面表` 的子目录
    **精确相等**匹配，不做前缀模糊 —— 否则 `开发工具/验证门禁备份/` 之类会被误算进核心。
    """
    段串 = str(相对路径).replace("\\", "/").strip("/")
    if not 段串:
        return 假
    段 = 段串.split("/")
    顶层 = 段[0]
    if 顶层 in 核心面层表:
        return 真
    for 层名, 子目录 in 核心支撑面表:
        if 顶层 != 层名:
            continue
        if not 子目录:
            return 真
        if len(段) > 1 and 段[1] == 子目录:
            return 真
    return 假


def 是生成式路径(路径: Path) -> bool:
    """路径（文件或目录）是否落在生成式目录内 —— 按**段名精确相等**判定。

    子串命中会误剪真实源码文件（`工程缓存回收.py` 含「工程缓存」但它不是生成式的），
    这是 `依赖防火墙.排除片段表` 已经踩过的语义修正，此处沿用同一把尺子。
    """
    return any(段 in 生成式目录表 for 段 in Path(路径).parts)


def 遍历源码(
    根,
    *,
    后缀: tuple[str, ...] = (".py",),
    层名表: tuple[str, ...] | None = None,
    剪枝: bool = 真,
) -> list[Path]:
    """递归收集源码文件，**进入目录时就剪枝**生成式目录（唯一遍历入口）。

    与「rglob 全量产出再过滤」的区别只在代价，不在结果：实测两者文件集合完全一致，
    但全仓 rglob 枚举 32 万条 / 167 秒，本函数只走 8 千条 / 数秒。

    参数：
    - `后缀`：只收这些后缀（默认 `.py`）。
    - `层名表`：只在这些顶层目录下走（默认 `源码层名表`，即各正式根＋工具/契约层）。
      传 `None` 且 `根` 本身就是某个包/子目录时，用 `层名表=(".",)` 走整棵 `根`。
    - `剪枝`：`假` 时不剪枝（**只给确需扫缓存的那几处用**：工程缓存回收、提供者环境回收、
      制品校验类；这些地方扫的就是生成式目录本身）。
    """
    根 = Path(根)
    出: list[Path] = []
    起点表 = 层名表 if 层名表 is not None else 源码层名表
    for 层名 in 起点表:
        层目录 = (根 / 层名) if 层名 != "." else 根
        if not 层目录.is_dir():
            continue
        if 剪枝 and 是生成式路径(层目录):
            continue
        for 当前根, 子目录名表, 文件名表 in os.walk(层目录):
            if 剪枝:
                子目录名表[:] = [名 for 名 in 子目录名表 if 名 not in 生成式目录表]
            出 += [
                Path(当前根) / 名
                for 名 in 文件名表
                if any(名.endswith(尾) for 尾 in 后缀)
                and not (剪枝 and 名 in 生成式目录表)
            ]
    return sorted(set(出))


