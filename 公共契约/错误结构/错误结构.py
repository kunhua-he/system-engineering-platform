"""错误结构：跨包统一错误模型。

错误必须携带错误码、消息、来源、可恢复性与可重试性，禁止用裸字符串
当错误。外部适配失败必须能区分：未安装、不可访问、参数错误、版本
不兼容、协议错误、超时、内部错误。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class 错误结构:
    """统一错误结构。"""

    错误码: str
    消息: str
    来源: str = ""
    可恢复: bool = False
    可重试: bool = False
    详情: dict[str, Any] = field(default_factory=dict)

    def 转字典(self) -> dict[str, Any]:
        return {
            "错误码": self.错误码,
            "消息": self.消息,
            "来源": self.来源,
            "可恢复": self.可恢复,
            "可重试": self.可重试,
            "详情": self.详情,
        }


