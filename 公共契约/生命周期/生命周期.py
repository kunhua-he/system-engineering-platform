"""生命周期：包状态机与状态流转约束。

状态链：未发现 → 已发现 → 已校验 → 已锁定 → 已装配 → 可运行 → 已停止 → 已卸载。
要求：非法状态跳转必须失败；重复装配必须幂等；重复停止必须幂等；
装配失败必须可回滚；记录包含 包id/版本/当前状态/操作名称/成功或失败/
错误码/错误说明；不允许吞掉异常。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from 公共契约.基础类型.逻辑类型 import 真, 假

状态链 = ["未发现", "已发现", "已校验", "已锁定", "已装配", "可运行", "已停止", "已卸载"]

# 幂等操作：目标状态等于当前状态时允许（重复装配/重复停止）
幂等操作表 = {"已装配": "装配", "已停止": "停止"}


@dataclass
class 生命周期记录:
    """一次状态流转的记录。"""

    包id: str
    版本: str
    当前状态: str
    操作名称: str
    成功: bool
    错误码: str = ""
    错误说明: str = ""

    def 转字典(self) -> dict:
        return {
            "包id": self.包id,
            "版本": self.版本,
            "当前状态": self.当前状态,
            "操作名称": self.操作名称,
            "成功": self.成功,
            "错误码": self.错误码,
            "错误说明": self.错误说明,
        }


class 生命周期管理器:
    """单个包的生命周期状态机。"""

    def __init__(self, 包id: str, 版本: str = "", 初始状态: str = "未发现") -> None:
        self.包id = 包id
        self.版本 = 版本
        self.状态 = 初始状态
        self.记录列表: list[生命周期记录] = []

    def _状态索引(self, 状态: str) -> int:
        if 状态 not in 状态链:
            raise ValueError(f"未知状态: {状态}")
        return 状态链.index(状态)

    def 流转(
        self,
        目标状态: str,
        *,
        操作名称: str = "",
        版本: str | None = None,
        错误码: str = "",
        错误说明: str = "",
    ) -> 生命周期记录:
        """尝试流转到目标状态；非法跳转记录失败并返回失败记录（不抛异常）。

        返回记录本身；调用方可通过 记录.成功 判断。不允许吞掉异常：
        未知状态仍抛 ValueError。
        """
        操作名称 = 操作名称 or f"流转到{目标状态}"
        版本 = 版本 or self.版本
        当前索引 = self._状态索引(self.状态)
        目标索引 = self._状态索引(目标状态)

        # 非法跳转：目标必须恰好前进一步，或属于幂等操作，或回滚到上一状态
        合法前进 = 目标索引 == 当前索引 + 1
        幂等 = 目标状态 == self.状态 and 目标状态 in 幂等操作表
        回滚 = 目标索引 == 当前索引 - 1
        if not (合法前进 or 幂等 or 回滚):
            记录 = 生命周期记录(
                包id=self.包id, 版本=版本, 当前状态=self.状态,
                操作名称=操作名称, 成功=假,
                错误码=错误码 or "状态跳转非法",
                错误说明=错误说明 or f"不允许从 {self.状态} 跳转到 {目标状态}",
            )
            self.记录列表.append(记录)
            return 记录

        self.状态 = 目标状态
        记录 = 生命周期记录(
            包id=self.包id, 版本=版本, 当前状态=目标状态,
            操作名称=操作名称, 成功=真,
        )
        self.记录列表.append(记录)
        return 记录

    def 回滚(self, 错误码: str = "", 错误说明: str = "") -> None:
        """装配失败回滚：记录失败并回到上一稳定状态（不得停留在半成品状态）。"""
        当前索引 = self._状态索引(self.状态)
        上一状态 = 状态链[max(当前索引 - 1, 0)]
        self.状态 = 上一状态
        self.记录列表.append(
            生命周期记录(
                包id=self.包id, 版本=self.版本, 当前状态=上一状态,
                操作名称="回滚", 成功=假,
                错误码=错误码 or "装配失败",
                错误说明=错误说明 or f"从 {状态链[当前索引]} 回滚到 {上一状态}",
            )
        )

    def 检查记录(self, 操作名称: str, 成功: bool = 真) -> bool:
        """按操作名+成功标志检查最近记录是否存在（供测试断言）。"""
        return any(
            记录.操作名称 == 操作名称 and 记录.成功 == 成功
            for 记录 in self.记录列表
        )


def 流转链(管理器: 生命周期管理器, 状态列表: list[str]) -> list[生命周期记录]:
    """按状态列表依次流转；返回全部记录。"""
    记录列表: list[生命周期记录] = []
    for 状态 in 状态列表:
        记录列表.append(管理器.流转(状态))
    return 记录列表
