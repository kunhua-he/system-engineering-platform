"""`字节型` / `字节集型` 的冻结契约与严格校验（**类型判定的唯一真源**）。

**为什么需要本模块**：两者收口前都只有网关侧判定（`字节型` 是内联 lambda，
`字节集型` 是网关私有 `_是字节集值`），没有公共可复用层。现场实测（2026-09-19）：
`字节型` 参数位声明 **0** 处（属「有名无实」档），`字节集型` **34** 处。

**`字节型` 口径（与 `类型目录.md` 逐条一致）**：

- 合法值只有 `int` 且 `0 <= 值 <= 255`（单个无符号字节）；
- 布尔**不是**字节型——`True` 是 `int` 子类，不等于 `1`，必须显式排除；
- `bytes`／`str`（如 `"0x41"`）**不是**字节型——不做隐式转换。

**`字节集型` 口径（HTTP 边界只能传文本，故有三种合法形态）**：

1. 真正的二进制对象：`bytes`／`bytearray`／`memoryview`；
2. `str`：base64 文本表示（HTTP 边界上 JSON 表达不了二进制，本地网关与实现层
   都按 base64 文本约定收发）；
3. 冻结的显式结构：`{"类型": "字节集型", "base64": <str>}`。

整数／浮点／布尔／列表／字典（非上述结构）一律**不是**字节集型。

**相对安全（哲学第 9 条 9.5，必须如实写明）**：第 2 种形态**不校验 base64 合法性**
——任意文本都放行。这是**刻意的相对安全**：实现层（图像解码、文本解析等）既接受
真二进制也接受 base64 文本，若在这里强制 base64 解码，会把「内容格式错误」提前
判成「类型不符」，改掉既有 34 处参数位的可答路径。真正的解码失败由实现层按
`参数不合法`／`文件损坏` 明确报告。**本函数不是「绝对安全的二进制边界」**，
不得被这样包装或依赖。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假

__all__ = ["校验字节类型", "确保字节类型", "校验字节集类型", "确保字节集类型"]

字节最小值 = 0
字节最大值 = 255


def 校验字节类型(值: Any) -> bool:
    """严格校验值是否为 `字节型`：`int` 且 0~255，且不是布尔。"""
    if isinstance(值, bool):
        return 假
    return isinstance(值, int) and 字节最小值 <= 值 <= 字节最大值


def 确保字节类型(值: Any) -> int:
    """校验并返回 `字节型`；不符合时抛稳定的 ``TypeError``。"""
    if not 校验字节类型(值):
        raise TypeError(
            f"值不符合字节型契约：{值!r}"
            f"（字节型只接受 {字节最小值}~{字节最大值} 的整数，布尔不算）"
        )
    return 值


def 校验字节集类型(值: Any) -> bool:
    """校验值是否为 `字节集型`（三种合法形态见模块 docstring）。"""
    if isinstance(值, (bytes, bytearray, memoryview)):
        return 真
    if isinstance(值, str):
        return 真
    return (isinstance(值, dict)
            and 值.get("类型") == "字节集型"
            and isinstance(值.get("base64"), str))


def 确保字节集类型(值: Any) -> Any:
    """校验并返回 `字节集型`；不符合时抛稳定的 ``TypeError``。"""
    if not 校验字节集类型(值):
        raise TypeError(
            f"值不符合字节集型契约：{值!r}"
            "（合法形态：bytes/bytearray/memoryview、base64 文本、"
            '{"类型":"字节集型","base64":…} 结构）'
        )
    return 值
