"""`资源引用型` 的冻结契约与严格校验（**类型判定的唯一真源**）。

**为什么需要本模块**：`资源引用型` 收口前只有网关私有 `_是资源引用值`，没有公共
可复用层。现场实测（2026-09-19）：参数位声明 **2** 处。

**口径（与 `公共契约/基础类型/类型目录.md` 逐条一致）**：

- `资源引用型` 是**平台托管制品引用**（文件、图片、模型、音频），由运行核心签发，
  **不传裸路径／指针**，引用里包含摘要与大小；
- JSON 表达不了资源引用对象 ⇒ **任何 JSON 值都不是资源引用型**（含 `空值`、
  含看起来像路径的文本 `"/tmp/a.png"`）。走 HTTP 传这个参数本身就是类型不符，
  只有进程内直调才可能合法。因此合法形态 = **非 JSON 标量／容器的对象**
  （如 `资源引用` 数据类实例、句柄承载的资源对象）；
- 显式 `空值` 也**不等于**「未提供」：要省略就不传这个键（与 `空值类型.py`
  的「省略键才是未提供」同一口径）。

**相对安全（哲学第 9 条 9.5，必须如实写明）**：本函数只保证「不是一个 JSON 值」，
**不**校验引用里是否真有摘要与大小、**不**校验引用是否由运行核心签发。若某个
自定义对象没有摘要／大小就冒充资源引用，本函数放行——这是**刻意的相对安全**：
把「有摘要有大小」写进类型校验器，等于在类型层复刻签发层的口径（两套强度），
签发可信性由运行核心的签发路径负责。**本函数不是「绝对可信的资源引用边界」**，
不得被这样包装或依赖。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假

__all__ = ["校验资源引用类型", "确保资源引用类型"]


def 校验资源引用类型(值: Any) -> bool:
    """校验值是否为 `资源引用型`：进程内资源对象；任何 JSON 值（含 `空值`）都不是。"""
    return 值 is not None and not isinstance(值, (bool, int, float, str, list, dict))


def 确保资源引用类型(值: Any) -> Any:
    """校验并返回 `资源引用型`；不符合时抛稳定的 ``TypeError``。"""
    if not 校验资源引用类型(值):
        raise TypeError(
            f"值不符合资源引用型契约：{值!r}"
            "（资源引用型只能由运行核心签发，任何 JSON 值都不是；"
            "JSON 表达不了资源引用，走 HTTP 传这个参数本身就是类型不符）"
        )
    return 值
