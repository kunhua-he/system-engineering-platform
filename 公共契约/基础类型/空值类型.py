"""`空值型` 的冻结契约与严格校验，并提供公共常量 `空值`。

**为什么需要本模块**：收口前 `空值型` 是**双重有名无实**——

1. 契约要求「只能写 `空值`」，但 `空值` 这个名字**全仓 0 定义点**（只在一处注释里
   被提及）；说明书让人写一个代码里不存在的名字，等于没有可写的合法值；
2. 判定只有网关 `类型匹配表` 的内联 lambda（`值 is None`），没有公共可复用层。

现场实测（2026-09-19）：`空值型` 参数位声明 **1** 处。

**口径（与 `公共契约/基础类型/类型目录.md` 逐条一致）**：

- `空值型` 的合法值**只有一个**：`空值`（即 Python `None`）；
- **不能用空文本冒充**：`""` 否定；`0`／`假`／`[]`／`{}` 同样否定——
  「明确没有值」与「值是空的容器」是两件事，后者有自己的正式类型；
- 与「参数未提供」的区别：**省略键**才是「未提供」（网关口径：未知／多余字段忽略）；
  显式传 `空值` 是「提供了，值是空」——两者不得混同。要允许省略，契约里把该参数
  声明为非必填；**不要**用 `空值` 冒充「未提供」。

**相对安全（哲学第 9 条 9.5）**：本函数只判定「是不是 `空值`」，不判定
「此处**应不应该**允许空值」——那是契约面（必填位）的决定。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假

__all__ = ["空值", "校验空值类型", "确保空值类型"]

#: `空值型` 的唯一合法值（公共契约唯一真源）。正式代码一律从这里取，
#: 不要散写 Python 字面量 ``None`` ——与 `逻辑类型.真／假` 是同一套做法：
#: 中文口径收口一次，业务代码只写中文。
空值 = None


def 校验空值类型(值: Any) -> bool:
    """严格校验值是否为 `空值型`：只接受 `空值`。

    空文本 `""`、`0`、`假`、空列表、空字典一律判为**不符合**
    （不得用空文本或空容器冒充「明确没有值」）。
    """
    return 值 is 空值


def 确保空值类型(值: Any) -> Any:
    """校验并返回 `空值型`；不符合时抛稳定的 ``TypeError``。"""
    if 值 is not 空值:
        raise TypeError(
            f"值不符合空值型契约：{值!r}（空值型的唯一合法值是 空值，"
            "不得用空文本／空容器冒充）"
        )
    return 值
