"""`日期时间型` 的冻结契约与严格校验（**类型判定的唯一真源**）。

**为什么需要本模块**：`日期时间型` 收口前只有网关私有 `_是日期时间值`，而它的判据是
`isinstance(值, datetime) or isinstance(值, str)`——**任意文本都放行**，等于「声明了
日期时间型却谁都没校验」，正是哲学第 7 条点名的**假绿**：`"下周三"`、`"abc"`、
`"2026/09/19"`（斜杠式）全都能穿过网关边界。现场实测（2026-09-19）：该类型契约
参数位声明 **0** 处 ⇒ 收紧判定**零存量消费方**，不会打破任何在跑的能力。

**口径（与 `公共契约/基础类型/类型目录.md` 逐条一致）**：

- 合法值只有两种形态：
  1. 真正的 `datetime` 对象（进程内直调）；
  2. **ISO-8601 文本**（JSON 只能表达文本）。必须真的能按 ISO-8601 解析：
     `"2026-09-19"`、`"2026-09-19T13:05:00"`、`"2026-09-19T13:05:00+08:00"`、
     `"2026-09-19T13:05:00Z"` 合法；`"下周三"`、`"abc"`、`"2026/09/19"` 否定。
- **不强制带时区**：`类型目录.md` 的口径是「ISO-8601；**默认 Asia/Shanghai**」，
  即不带偏移的文本按上海时区解读，故无偏移的 ISO 文本合法。时区默认值由消费方
  按该口径解读，不由本函数补写（补写等于在校验器里做隐式转换）。
- 日期（`date`）本身**不是**日期时间型——只接受 `datetime`，避免「有日期无时刻」
  的含糊值穿过带时刻的契约位。

**相对安全（哲学第 9 条 9.5）**：本函数只保证「形状与格式对」，**不**保证该时刻
在业务上合理（未来时间、超出保留期、与上游时钟一致）。业务时间边界由调用方负责。
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假

__all__ = ["校验日期时间类型", "确保日期时间类型"]


def 校验日期时间类型(值: Any) -> bool:
    """严格校验值是否为 `日期时间型`：`datetime` 对象，或**可解析的 ISO-8601 文本**。"""
    if isinstance(值, datetime):
        return 真
    if not isinstance(值, str):
        return 假
    try:
        datetime.fromisoformat(值)
    except ValueError:
        return 假
    return 真


def 确保日期时间类型(值: Any) -> Any:
    """校验并返回 `日期时间型`；不符合时抛稳定的 ``TypeError``。"""
    if not 校验日期时间类型(值):
        raise TypeError(
            f"值不符合日期时间型契约：{值!r}"
            "（合法形态：datetime 对象，或可解析的 ISO-8601 文本，如 2026-09-19T13:05:00+08:00）"
        )
    return 值
