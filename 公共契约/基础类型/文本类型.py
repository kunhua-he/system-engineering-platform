"""`文本型` 的冻结契约与严格校验（**类型判定的唯一真源**）。

**为什么需要本模块**：`文本型` 是全平台最高频的正式类型（2026-09-19 现场实测：
能力契约参数位 **1156** 处，占全部类型声明的一半以上），但收口前它**没有可复用的
公共校验层**——唯一判定写在网关 `运行核心/统一网关/协议/类型规格.py:类型匹配表`
的私有 lambda 里（`isinstance(值, str)`）。后果是任何调用方想校验文本型，只能
① 自己再写一遍 `isinstance`，或 ② 绕到网关内部去拿那张表。两条路都是「第二套判定」，
正是哲学第 5 条（口径唯一）要杀掉的裂缝：**最高频的类型反而最没有公共校验层**。

**口径（与 `公共契约/基础类型/类型目录.md` 逐条一致）**：

- 合法值只有 Python `str`（Unicode 文本，UTF-8 传输）；
- `0`／`1`／`真`／`假`／`空值` 一律**不是**文本型——不做任何隐式转换；
- 空文本 `""` **是**合法文本型值。契约要拒绝空文本，就在契约里声明必填或加长度
  下限，**类型校验器不替业务做这个决定**（`空值型` 的「不能用空文本冒充」是
  `空值型` 自己的口径，见 `空值类型.py`，不是文本型的口径）；
- 长度／大小上限是**契约面声明**（`类型目录.md` 校验规则 4），由契约里的上限字段
  表达，**不在本函数按固定阈值硬判**——硬判会把契约口径搬进代码，两处又要分叉。

**相对安全（哲学第 9 条 9.5）**：本函数只保证「值是文本型」，**不**保证长度有界、
**不**保证内容合法（编码、格式、越权、注入）。内容层边界由调用方或能力自身负责，
本函数不越权替它们把关，也不得被包装成「绝对安全的文本边界」。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假

__all__ = ["校验文本类型", "确保文本类型"]


def 校验文本类型(值: Any) -> bool:
    """严格校验值是否为 `文本型`：只接受 `str`。

    `1`／`0`／`真`／`假`／`空值`／`b"..."`／`["a"]` 一律判为**不符合**
    （不做隐式转换：数字转文本、布尔转文本都必须显式走
    `类型转换.数值转文本` / `类型转换.逻辑转文本`）。
    空文本 `""` 判为符合（理由见模块 docstring）。
    """
    return isinstance(值, str)


def 确保文本类型(值: Any) -> str:
    """校验并返回 `文本型`；不符合时抛稳定的 ``TypeError``（与 `确保数值类型` 同口径）。"""
    if not isinstance(值, str):
        raise TypeError(f"值不符合文本型契约：{值!r}（文本型只接受 str，不做隐式转换）")
    return 值
