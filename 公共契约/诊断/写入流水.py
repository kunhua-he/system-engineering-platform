"""MD 写入流水：**「这份 md 的这次改动是不是经工具做的」的唯一凭据**（2026-09-23 华哥裁决）。

为什么住公共契约（同 `公共契约/诊断/调用账本.py` 的分层理由）：**写方跨两层** ——
`开发工具.MD文档生成`（生成器写盘时记一条）与 `支持库.后端.文件系统支持库.文本补丁`
（受管写入口记一条）；`开发工具` 按依赖防火墙不得 import `支持库` 实现、反之亦然，
两边都能依赖的只有 `公共契约`。各写一份的话，「什么算同一次写入」的算法规格必然走偏，
判据就会变成两拨对不上的结论。

## 为什么要有它（现场取证）

华哥 2026-09-23 口径：

> 「说明书的那个，是否可以固定规范？人工也要使用 mcp 工具才行。不能直接手写？否则编译的时候，直接报错。」

现场取证（本模块建立时实测）：`模块库/自修复工具/说明/使用说明书.md` 里**有**机器印记
（第 2 行 `<!-- 机器管理｜类型：仓库内其他文档｜生成器：开发工具.MD文档生成 -->`），
而它当时刚被**直接写文件**改过（绕开生成器），`--拒绝手写校验` 照样报「通过」。

⇒ **旧判据是「有没有印记」，不是「这次改动有没有经工具」**。印记是**文件级、加一次就永久有效**，
所以「曾经被生成器写过」的 md 之后**永远可被人直接编辑而不被拦** —— 这比「无印记手写」更隐蔽
（那种好歹会被拦下）。

## 本模块给什么

一条**只增不改**的流水 `开发文档/项目证据/MD写入流水.jsonl`（一行一 JSON）：

    {"相对路径": "模块库/…/使用说明.md", "内容sha256": "…", "时刻": "2026-09-23 15:00:00",
     "工具": "开发工具.MD文档生成", "类型名": "包级说明-使用说明"}

判据：**本轮改动的 md，现场内容指纹必须命中流水**。
  · 命中 ⇒ 这份文件的**当前内容**是某次工具写入的产物 ⇒ 通过；
  · 不命中 ⇒ 内容对不上任何一次工具写入（人直接改的、或工具写完又被人改了）⇒ **判红**。

## 与「机器印记」的分工（不是两条腿）

  · `机器印记`：回答「**这份文件归不归生成器管**」（类型归属；文件级、持久）；
  · `本模块`：回答「**这份文件现在这个内容是谁写的**」（写入凭据；内容级、每次写一条）。

两者是**两个不同的问题**，故不是重复实现。判据的合成在 `__main__._拒绝手写校验` 一处。

## 唯一登记节点与登记失败留痕（2026-09-24 裁决）

`登记md写入凭据(目标, 文本, 工具)` 是**全平台唯一的 md 写入凭据登记节点**（含**唯一一份根推断**
`推断仓库根`）：两条写腿（`文件操作.写入文件` / `文本补丁.应用精确替换`）与生成器都经它。
此前两条腿各自就地写一份「推断根 + 记一次写入」，两份判据必然走偏 —— 同一条腿两处实现即缺陷。

**凭据登记不许静默失败**：旧形状下 `记一次写入` 若打不开流水（内核锁 / 权限 / 磁盘），
两条腿各自 `except Exception: return` ⇒ 工具写的 md 没有凭据，编译口判它「手写」，
而**没有任何地方能回答「为什么没凭据」**（2026-09-23 实测事故：`开发文档/未完成事项.md`
内容对不上任何一次登记，真身是流水写不进去）。现在失败被写成**机器可判**的一行
（`原因` 是原因码，不是散文），落 `<运行数据根>/写入凭据登记失败.jsonl` ——
`工程缓存/` 是仓库既有豁免前缀（不受整仓内核只读锁管辖），故这条留痕**比它记录的东西更皮实**：
不需要也不许再开 `临时解锁` 窗口。门禁 `__main__._拒绝手写校验` 单列「凭据登记失败」一档读它。
"""
from __future__ import annotations

import hashlib
import json
import time
from pathlib import Path

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.诊断.忽略记录 import 记录忽略
from 公共契约.运行时.运行缓存 import 解析运行数据根

流水相对路径 = Path("开发文档") / "项目证据" / "MD写入流水.jsonl"
工具名 = "开发工具.MD文档生成"
#: 登记失败留痕文件名（落 `<运行数据根>/`，见 `登记失败落点`）。
登记失败文件名 = "写入凭据登记失败.jsonl"
#: 仓库根判据的两项标记：同层**同时**含这两项才算根。
根标记文件 = "AGENTS.md"
根标记目录 = "开发文档"
#: 往上找根的最大层数；找不到即失败（**不猜**）。
最大上溯层数 = 12


def 流水路径(项目根: Path) -> Path:
    """流水文件位置（相对仓库根实时解析，便于测试注入临时根）。"""
    return Path(项目根) / 流水相对路径


def 内容指纹(文本: str) -> str:
    """内容 sha256（十六进制全长）——**与换行风格无关**不成立，故按原始字节算。

    为什么按原始字节：判据要区分「工具写的内容」与「人改过一版的内容」，
    任何归一化（如行尾归一）都会让「人只改了行尾」不被发现。
    """
    return hashlib.sha256(文本.encode("utf-8")).hexdigest()


def 记一次写入(项目根: Path, 相对: str, 文本: str, *,
              类型名: str = "", 工具: str = 工具名, 时刻: str | None = None,
              开工ID: str = "") -> str:
    """把一次工具写入记进流水（**只增不改**），返回本次内容指纹。

    为什么只增不改：这条流水是判据的**证据链**，改一条就等于把「有人直接改过」的痕迹抹掉。
    同日同文件多次写入就是多条记录（各自对应一个内容版本）——判据只问「现场内容是否命中任一条」。

    **`开工ID` = 这次改动属于哪个工作项**（2026-09-25 底座权限面收口）：改前流水只记
    「哪个工具写的、写的什么内容」，答不出「**谁授权**的这次改动」—— 于是提交强制点只能
    regex 猜消息里的开工ID（**声明级**），拿它去核流水就核不出东西。补上这一维之后，
    「本次提交的每条路径是否都出自某个真实开工ID 的授权」才成为**可实证**的判据。
    留空即空串（不编造凭证：记不出来就如实空着，由消费侧 fail-closed 判）。
    """
    指纹 = 内容指纹(文本)
    路径 = 流水路径(项目根)
    # ★ 流水文件本身是**受管条目**（整仓内核锁会给它置 `uchg`）⇒ 不在这条腿里开解锁
    #   窗口的话，`mkdir` 与 `open("a")` 都被内核以 `Operation not permitted` 拒；
    #   而两个调用方（`文件系统.写入文件`、`文本补丁.应用精确替换`）都用
    #   `except Exception` 静默兜底 ⇒ **凭据一声不响地不落盘**，编译口随即把
    #   「工具刚写的 md」判成「手写」。实测 2026-09-23：`开发文档/未完成事项.md`
    #   内容对不上任何一次登记（真身在此，不是谁手改的）。
    #   窗口用 `临时解锁`（不是 `临时解锁树`）：流水是**单文件追加**，不需要递归。
    from 公共契约.运行时.仓库只读锁 import 临时解锁
    # ★ 窗口本身也要带凭证（2026-09-25 底座权限面收口）：`临时解锁` 内部同样过
    #   `校验写入授权`（它是落盘动作的唯一通道，见 `仓库只读锁.py:204-207`），
    #   不传开工ID 会被窗口自己拒掉（实测文案：「临时解锁被拒（写入未授权）：… 没有开工ID 凭证」）。
    凭证 = str(开工ID or "").strip()
    with 临时解锁(路径, 开工ID=凭证):
        路径.parent.mkdir(parents=True, exist_ok=True)
        条目 = {
            "相对路径": str(相对).replace("\\", "/"),
            "内容sha256": 指纹,
            "时刻": 时刻 or time.strftime("%Y-%m-%d %H:%M:%S"),
            "工具": 工具,
            "类型名": 类型名,
            "开工ID": str(开工ID or "").strip(),
        }
        with 路径.open("a", encoding="utf-8") as 文件:
            文件.write(json.dumps(条目, ensure_ascii=False) + "\n")
    return 指纹


def 读过全部流水(项目根: Path) -> set[str]:
    """全部已登记的 (相对路径, 内容sha256) 组合；流水缺失/坏行即**跳过该行**并继续。

    为什么坏行跳过而不是整份判不可用：流水是**只增**的证据链，写入是逐行追加，
    进程被杀可能留半行；把半行当「整份不可信」会让**所有**历史凭据一起失效
    （那会把「有凭据」误判成「没凭据」= 假红）。半行丢掉的只是它自己那一次记录。
    """
    路径 = 流水路径(项目根)
    结果: set[str] = set()
    if not 路径.is_file():
        return 结果
    try:
        内容 = 路径.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return 结果
    for 行 in 内容.splitlines():
        行 = 行.strip()
        if not 行:
            continue
        try:
            条目 = json.loads(行)
        except json.JSONDecodeError:
            continue
        if not isinstance(条目, dict):
            continue
        相对 = str(条目.get("相对路径") or "").replace("\\", "/")
        指纹 = str(条目.get("内容sha256") or "")
        if 相对 and 指纹:
            结果.add(f"{相对}|{指纹}")
    return 结果


def 有写入凭据(项目根: Path, 相对: str, 文本: str) -> bool:
    """这份文件的**当前内容**是不是某一次工具写入的产物。"""
    return f"{str(相对).replace(chr(92), '/')}|{内容指纹(文本)}" in 读过全部流水(项目根)


def 推断仓库根(路径: Path) -> Path | None:
    """从目标路径往上找仓库根（同层**同时**含 `AGENTS.md` 与 `开发文档/` 的那一层）。

    **本平台唯一一份「平台仓库根」判据**（2026-09-24 裁决）：`文件操作.写入文件` 与
    `文本补丁` 此前各自就地实现了一份私有根推断（现已删除），两处判据必然走偏 —— 现在只住这里。
    ★ 与 `仓库只读锁.推断仓库根` **不是同一件事**（那个判「第一个含 `.git` 的目录」，服务于
    「锁态上下文属不属于本仓库」）：本判据要的是「这份 md 该记进哪个仓库的流水」，
    故按 `AGENTS.md` + `开发文档/` 同层来认，两者都不改对方的语义。

    为什么不用环境变量/固定层级：写入腿既可能被源码树里的调用方用（`__file__` 在仓库内），
    也可能被制品里的调用方用（`__file__` 在制品内，往上找不到源码树）——
    沿**目标路径本身**往上找是唯一与调用方无关的定位法。找不到返回 `None`（不登记，不猜）。
    """
    当前 = Path(路径).resolve().parent
    for _ in range(最大上溯层数):
        if (当前 / 根标记文件).is_file() and (当前 / 根标记目录).is_dir():
            return 当前
        if 当前.parent == 当前:
            break
        当前 = 当前.parent
    return None


def 登记失败落点(项目根: Path) -> Path:
    """登记失败留痕的落点：`<运行数据根>/写入凭据登记失败.jsonl`（源码态 = `工程缓存/运行数据/`）。

    为什么**不**与 `MD写入流水.jsonl` 同级落 `开发文档/项目证据/`：那条腿的文件受整仓内核
    只读锁管辖（写它要开 `临时解锁` 窗口），而登记失败的现场恰恰可能包含「解锁窗口自己出问题」
    ⇒ 往同一个受管面写等于让留痕与被留痕的东西**一起**失败。留痕必须比它记录的东西更皮实。
    `工程缓存/` 是仓库既有**豁免前缀**（`仓库只读锁.豁免前缀`：运行期数据不是受管事实源），
    故这里**不开**（也不许开）任何解锁窗口。
    """
    return 解析运行数据根(Path(项目根)) / 登记失败文件名


def _记一条登记失败(项目根: Path | None, 目标: Path, 工具: str, 原因: str,
                异常: str = "") -> None:
    """把一次「凭据没登记上」写进留痕（**机器可判字段，不是散文**）；自身绝不抛。

    字段与 `MD写入流水.jsonl` 同风格（一行一 JSON），另有三个判据字段：
      · `原因`：原因码（`根未找到` / `登记异常`），读方按码判档，不解析散文；
      · `目标`：绝对路径 —— `相对路径` 为空（根都没找着）时，读方靠它对上文件；
      · `异常`：原始异常文本（截断），供人看细节。
    """
    条目 = {
        "时刻": time.strftime("%Y-%m-%d %H:%M:%S"),
        "原因": 原因,
        "工具": 工具,
        "目标": str(目标),
        "项目根": "" if 项目根 is None else str(项目根),
        "相对路径": "",
        "异常": 异常[:300],
    }
    if 项目根 is not None:
        try:
            条目["相对路径"] = Path(目标).resolve().relative_to(
                Path(项目根).resolve()).as_posix()
        except ValueError:
            pass
    try:
        # 根没找着时退到**平台自己的**运行数据根（`<本模块>/../../..`，与
        # `调用账本.参数账路径` 同一取法）—— 这是「平台自身运行数据目录」，
        # 不是替调用方猜它的仓库根（那件事在 `推断仓库根` 里已如实返回失败）。
        落点根 = Path(项目根) if 项目根 is not None else Path(__file__).resolve().parents[2]
        落点 = 登记失败落点(落点根)
        落点.parent.mkdir(parents=True, exist_ok=True)
        with 落点.open("a", encoding="utf-8") as 文件:
            文件.write(json.dumps(条目, ensure_ascii=False) + "\n")
    except Exception as 错:
        # 连留痕落点都写不进去：退到既有内存忽略记录（有界、可查），**仍不静默**。
        记录忽略("写入流水.登记md写入凭据", 错)


def 登记md写入凭据(目标: Path, 文本: str, 工具: str, 开工ID: str = "") -> dict:
    """**md 写入凭据的唯一登记节点**（两条写腿 + 生成器都经这里；2026-09-24 裁决）。

    按序做四件事，任一步失败都**如实返回 + 留痕**（不静默、不抛）：

      1. 目标后缀不是 `.md` ⇒ 返回「不适用」（判据只管 md，别的不记：白噪声 + 白一次 IO）；
      2. 从目标路径往上找仓库根（`推断仓库根`，**全平台唯一一份根推断**）——找不到即失败，不猜；
      3. 调既有的 `记一次写入`（它**自己**用 `临时解锁` 开窗，本节点不重复开窗、不改它的窗口）；
      4. 失败落 `登记失败落点`（`工程缓存/运行数据/`，不受整仓只读锁管辖）。

    `开工ID` 原样透传给 `记一次写入`（这次改动属于哪个工作项；留空即空串）。

    返回值**机器可判**（调用方与门禁都读它，不解析散文）：
      `适用` 逻辑 / `成功` 逻辑 / `原因` 原因码（`不适用` / `根未找到` / `登记异常` / 空）
      / `项目根` / `相对路径` / `内容sha256` / `说明`。
    """
    结果 = {"适用": 假, "成功": 假, "原因": "", "项目根": "", "相对路径": "",
            "内容sha256": "", "说明": ""}
    目标路径 = Path(目标)
    if 目标路径.suffix.lower() != ".md":
        结果["原因"] = "不适用"
        结果["说明"] = "判据只管 .md，非 md 不留痕（避免白噪声与白一次 IO）"
        return 结果
    结果["适用"] = 真
    项目根 = 推断仓库根(目标路径)
    if 项目根 is None:
        结果["原因"] = "根未找到"
        结果["说明"] = (f"从 {目标路径} 上溯 {最大上溯层数} 层未找到同时含 "
                    f"{根标记文件} 与 {根标记目录}/ 的仓库根（不猜，故不登记）")
        _记一条登记失败(None, 目标路径, 工具, "根未找到", 结果["说明"])
        return 结果
    结果["项目根"] = str(项目根)
    try:
        相对 = 目标路径.resolve().relative_to(项目根).as_posix()
        结果["相对路径"] = 相对
        结果["内容sha256"] = 记一次写入(项目根, 相对, 文本, 工具=工具, 开工ID=开工ID)
    except Exception as 错:
        结果["原因"] = "登记异常"
        结果["说明"] = f"{type(错).__name__}: {错}"
        _记一条登记失败(项目根, 目标路径, 工具, "登记异常", 结果["说明"])
        return 结果
    结果["成功"] = 真
    return 结果


def 读过登记失败(项目根: Path) -> dict[str, list[str]]:
    """登记失败留痕：`{目标键: [原因码, ...]}`（只增不改，一行一 JSON）。

    目标键 = **项目根相对路径**（根推断成功时）或**绝对路径**（`根未找到` 时）。
    留痕缺失 / 坏行按 `读过全部流水` 同口径**跳过该行继续**（半行只丢它自己那一次）。
    """
    表: dict[str, list[str]] = {}
    try:
        路径 = 登记失败落点(项目根)
    except Exception:
        # 连留痕落点都解析不出来（如制品态缓存根非法）⇒ 当作「没有失败留痕」：
        # 这是**诊断面**，绝不能把门禁变成新的故障点（fail-soft，与 `_记一条登记失败` 同向）。
        return 表
    if not 路径.is_file():
        return 表
    try:
        内容 = 路径.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return 表
    for 行 in 内容.splitlines():
        行 = 行.strip()
        if not 行:
            continue
        try:
            条目 = json.loads(行)
        except json.JSONDecodeError:
            continue
        if not isinstance(条目, dict):
            continue
        键 = str(条目.get("相对路径") or "").replace("\\", "/") or str(条目.get("目标") or "")
        if not 键:
            continue
        表.setdefault(键, []).append(str(条目.get("原因") or ""))
    return 表


def 取登记失败(项目根: Path, 相对: str) -> list[str]:
    """该文件（项目根相对路径）的登记失败原因码；没有则空表。

    门禁「凭据登记失败」档（`__main__._拒绝手写校验`）的**唯一数据源** ——
    同一条留痕两处各读一份，档位与原因码迟早对不上。
    """
    表 = 读过登记失败(项目根)
    归一 = str(相对).replace("\\", "/")
    if 归一 in 表:
        return 表[归一]
    try:
        绝对 = str((Path(项目根) / 归一).resolve())
    except OSError:
        return []
    return 表.get(绝对, [])


