"""MD 写入流水：**「这份 md 的这次改动是不是经工具做的」的唯一凭据**（2026-09-23 华哥裁决）。

为什么住公共契约（同 `公共契约/诊断/调用账本.py` 的分层理由）：**写方跨两层** ——
`开发工具.MD文档生成`（生成器写盘时记一条）与 `支持库.后端.文件系统支持库.文本补丁`
（受管写入口记一条）；`开发工具` 按依赖防火墙不得 import `支持库` 实现、反之亦然，
两边都能依赖的只有 `公共契约`。各写一份的话，「什么算同一次写入」的算法规格必然走偏，
判据就会变成两拨对不上的结论。

## 为什么要有它（现场取证）

华哥 2026-09-23 口径：

> 「说明书的那个，是否可以固定规范？人工也要使用 mcp 工具才行。不能直接手写？否则编译的时候，直接报错。」

现场取证（本模块建立时实测）：`模块库/自修复工具/说明/使用说明书.md` 里**有**机器印记
（第 2 行 `<!-- 机器管理｜类型：仓库内其他文档｜生成器：开发工具.MD文档生成 -->`），
而它当时刚被**直接写文件**改过（绕开生成器），`--拒绝手写校验` 照样报「通过」。

⇒ **旧判据是「有没有印记」，不是「这次改动有没有经工具」**。印记是**文件级、加一次就永久有效**，
所以「曾经被生成器写过」的 md 之后**永远可被人直接编辑而不被拦** —— 这比「无印记手写」更隐蔽
（那种好歹会被拦下）。

## 本模块给什么

一条**只增不改**的流水 `开发文档/项目证据/MD写入流水.jsonl`（一行一 JSON）：

    {"相对路径": "模块库/…/使用说明.md", "内容sha256": "…", "时刻": "2026-09-23 15:00:00",
     "工具": "开发工具.MD文档生成", "类型名": "包级说明-使用说明"}

判据：**本轮改动的 md，现场内容指纹必须命中流水**。
  · 命中 ⇒ 这份文件的**当前内容**是某次工具写入的产物 ⇒ 通过；
  · 不命中 ⇒ 内容对不上任何一次工具写入（人直接改的、或工具写完又被人改了）⇒ **判红**。

## 与「机器印记」的分工（不是两条腿）

  · `机器印记`：回答「**这份文件归不归生成器管**」（类型归属；文件级、持久）；
  · `本模块`：回答「**这份文件现在这个内容是谁写的**」（写入凭据；内容级、每次写一条）。

两者是**两个不同的问题**，故不是重复实现。判据的合成在 `__main__._拒绝手写校验` 一处。
"""
from __future__ import annotations

import hashlib
import json
import time
from pathlib import Path

流水相对路径 = Path("开发文档") / "项目证据" / "MD写入流水.jsonl"
工具名 = "开发工具.MD文档生成"


def 流水路径(项目根: Path) -> Path:
    """流水文件位置（相对仓库根实时解析，便于测试注入临时根）。"""
    return Path(项目根) / 流水相对路径


def 内容指纹(文本: str) -> str:
    """内容 sha256（十六进制全长）——**与换行风格无关**不成立，故按原始字节算。

    为什么按原始字节：判据要区分「工具写的内容」与「人改过一版的内容」，
    任何归一化（如行尾归一）都会让「人只改了行尾」不被发现。
    """
    return hashlib.sha256(文本.encode("utf-8")).hexdigest()


def 记一次写入(项目根: Path, 相对: str, 文本: str, *,
              类型名: str = "", 工具: str = 工具名, 时刻: str | None = None) -> str:
    """把一次工具写入记进流水（**只增不改**），返回本次内容指纹。

    为什么只增不改：这条流水是判据的**证据链**，改一条就等于把「有人直接改过」的痕迹抹掉。
    同日同文件多次写入就是多条记录（各自对应一个内容版本）——判据只问「现场内容是否命中任一条」。
    """
    指纹 = 内容指纹(文本)
    路径 = 流水路径(项目根)
    # ★ 流水文件本身是**受管条目**（整仓内核锁会给它置 `uchg`）⇒ 不在这条腿里开解锁
    #   窗口的话，`mkdir` 与 `open("a")` 都被内核以 `Operation not permitted` 拒；
    #   而两个调用方（`文件系统.写入文件`、`文本补丁.应用精确替换`）都用
    #   `except Exception` 静默兜底 ⇒ **凭据一声不响地不落盘**，编译口随即把
    #   「工具刚写的 md」判成「手写」。实测 2026-09-23：`开发文档/未完成事项.md`
    #   内容对不上任何一次登记（真身在此，不是谁手改的）。
    #   窗口用 `临时解锁`（不是 `临时解锁树`）：流水是**单文件追加**，不需要递归。
    from 公共契约.运行时.仓库只读锁 import 临时解锁
    with 临时解锁(路径):
        路径.parent.mkdir(parents=True, exist_ok=True)
        条目 = {
            "相对路径": str(相对).replace("\\", "/"),
            "内容sha256": 指纹,
            "时刻": 时刻 or time.strftime("%Y-%m-%d %H:%M:%S"),
            "工具": 工具,
            "类型名": 类型名,
        }
        with 路径.open("a", encoding="utf-8") as 文件:
            文件.write(json.dumps(条目, ensure_ascii=False) + "\n")
    return 指纹


def 读过全部流水(项目根: Path) -> set[str]:
    """全部已登记的 (相对路径, 内容sha256) 组合；流水缺失/坏行即**跳过该行**并继续。

    为什么坏行跳过而不是整份判不可用：流水是**只增**的证据链，写入是逐行追加，
    进程被杀可能留半行；把半行当「整份不可信」会让**所有**历史凭据一起失效
    （那会把「有凭据」误判成「没凭据」= 假红）。半行丢掉的只是它自己那一次记录。
    """
    路径 = 流水路径(项目根)
    结果: set[str] = set()
    if not 路径.is_file():
        return 结果
    try:
        内容 = 路径.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return 结果
    for 行 in 内容.splitlines():
        行 = 行.strip()
        if not 行:
            continue
        try:
            条目 = json.loads(行)
        except json.JSONDecodeError:
            continue
        if not isinstance(条目, dict):
            continue
        相对 = str(条目.get("相对路径") or "").replace("\\", "/")
        指纹 = str(条目.get("内容sha256") or "")
        if 相对 and 指纹:
            结果.add(f"{相对}|{指纹}")
    return 结果


def 有写入凭据(项目根: Path, 相对: str, 文本: str) -> bool:
    """这份文件的**当前内容**是不是某一次工具写入的产物。"""
    return f"{str(相对).replace(chr(92), '/')}|{内容指纹(文本)}" in 读过全部流水(项目根)


