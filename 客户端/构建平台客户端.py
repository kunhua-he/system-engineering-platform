def _异常行号(错误: BaseException, 树: ast.AST | None = None) -> int:
    """为 AST 解析/反解析失败提供稳定、非零的源码行号。"""
    行号 = getattr(错误, "lineno", None)
    if isinstance(行号, int) and 行号 > 0:
        return 行号
    if 树 is not None:
        for 节点 in ast.walk(树):
            节点行号 = getattr(节点, "lineno", None)
            if isinstance(节点行号, int) and 节点行号 > 0:
                return 节点行号
    return 1


def 复制并重写(源根: Path, 目标根: Path) -> int:
    """安全复制 Python 源码并重写导入；任一 AST 失败立即阻断。"""
    源根 = Path(源根)
    目标根 = Path(目标根)
    _拒绝符号链接(源根, "复制前源码检查")
    真实源根 = _解析源码根(源根)
    真实目标根 = _准备目标根(目标根)
    源描述符 = _打开根目录(源根, "Python源码")
    目标描述符 = _打开根目录(目标根, "Python目标")
    总数 = 0
    try:
        for 文件 in sorted(源根.rglob("*.py")):
            相对 = 文件.relative_to(源根)
            if "__pycache__" in 相对.parts:
                continue
            _解析受控源文件(文件, 源根, 真实源根)
            _受控目标路径(目标根, 真实目标根, 相对)
            原始字节, 权限位 = _读取受控文件(源描述符, 源根, 相对)
            内容 = 原始字节.decode("utf-8")
            try:
                树 = ast.parse(内容, filename=str(文件))
            except Exception as 错误:
                行号 = _异常行号(错误)
                详情 = 错误.msg if isinstance(错误, SyntaxError) else str(错误)
                raise 客户端构建错误(
                    f"Python AST解析失败: {文件}:{行号}: {详情}") from 错误
            重写器 = 导入重写器(顶层包表, 客户端前缀)
            新树 = 重写器.visit(树)
            总数 += 重写器.改写数
            try:
                新内容 = ast.unparse(新树)
            except Exception as 错误:
                行号 = _异常行号(错误, 新树)
                raise 客户端构建错误(
                    f"Python AST反解析失败: {文件}:{行号}: {错误}") from 错误
            _写入受控目标(
                目标描述符, 目标根, 相对, 新内容.encode("utf-8"), 权限位)
    finally:
        os.close(源描述符)
        os.close(目标描述符)
    _拒绝符号链接(源根, "复制后源码检查")
    _拒绝符号链接(目标根, "复制后目标检查")
    return 总数


def 复制非Py文件(源根: Path, 目标根: Path) -> None:
    """安全复制非 Python 资源；逐文件校验源码根与目标边界。"""
    源根 = Path(源根)
    目标根 = Path(目标根)
    _拒绝符号链接(源根, "复制前资源检查")
    真实源根 = _解析源码根(源根)
    真实目标根 = _准备目标根(目标根)
    源描述符 = _打开根目录(源根, "资源源码")
    目标描述符 = _打开根目录(目标根, "资源目标")
    try:
        for 文件 in sorted(源根.rglob("*")):
            if 文件.is_symlink():
                raise 客户端构建错误(f"源资源是符号链接: {文件}")
            if 文件.is_dir():
                continue
            相对 = 文件.relative_to(源根)
            if "__pycache__" in 相对.parts:
                continue
            if "工程缓存" in 相对.parts:
                continue
            if 相对.suffix == ".py":
                continue
            是夹具 = any(部分 in {"夹具", "验证夹具"} for 部分 in 相对.parts)
            if 相对.suffix.lower() in {".db", ".sqlite", ".sqlite3"} and not 是夹具:
                continue
            if 相对.suffix.lower() in {".log", ".tmp", ".pyc"}:
                continue
            _解析受控源文件(文件, 源根, 真实源根)
            _受控目标路径(目标根, 真实目标根, 相对)
            数据, 权限位 = _读取受控文件(源描述符, 源根, 相对)
            _写入受控目标(目标描述符, 目标根, 相对, 数据, 权限位)
    finally:
        os.close(源描述符)
        os.close(目标描述符)
    _拒绝符号链接(源根, "复制后资源检查")
    _拒绝符号链接(目标根, "复制后目标检查")


def 构建(安装: bool = False) -> Path:
    """构建平台客户端制品目录；构建前后都拒绝任何符号链接。"""
    源根列表: list[tuple[str, Path]] = []
    for 顶层 in 顶层包表:
        源 = 系统根 / 顶层
        if not 源.exists():
            continue
        if 源.is_symlink() or not 源.is_dir():
            raise 客户端构建错误(f"正式源码根非法: {源}")
        _拒绝符号链接(源, "构建前源码检查")
        源根列表.append((顶层, 源))
    _拒绝符号链接(构建目录, "构建前旧构建目录检查")
    _拒绝符号链接(制品目录, "构建前制品目录检查")
    if 安装:
        _拒绝符号链接(环境目录, "构建前安装环境检查")
    if 构建目录.exists():
        shutil.rmtree(构建目录)
    客户端根 = 构建目录 / 客户端前缀
    客户端根.mkdir(parents=True)
    改写数 = 0
    for 顶层, 源 in 源根列表:
        改写数 += 复制并重写(源, 客户端根 / 顶层)
        复制非Py文件(源, 客户端根 / 顶层)
    # 插入点：AST 重写已完成（包内 .py 字节已变）、制品身份摘要尚未计算（见 计算制品摘要）。
    # 这一步只改构建副本，故身份摘要会如实反映重算后的字节；不改源码树。
    重算包摘要数 = 重算包内完整性摘要(客户端根)
    生成入口(客户端根)
    _拒绝符号链接(客户端根, "构建副本完成检查")
    # 制品根含 平台客户端 包层（激活指针→不可变制品→制品内 平台客户端 包可导入）
    制品根 = 制品目录 / f"{客户端前缀}-临时"
    _拒绝符号链接(制品根, "临时制品覆盖前检查")
    if 制品根.exists():
        shutil.rmtree(制品根)
    制品根.mkdir(parents=True)
    _安全复制目录树(客户端根, 制品根 / 客户端前缀)
    生成可运行制品壳(制品根)
    _拒绝符号链接(制品根, "临时制品复制后检查")
    # 摘要口径=唯一权威口径（平台控制面/包仓库/平台客户端制品.py::计算目录摘要16）；
    # 该口径按文件名排除构建期生成的元数据（制品摘要.json 内含自身摘要，纳入即自指），
    # 因此「此刻目录里还没有元数据」与「写完元数据之后再算」结果相同 —— 见 写盘后自校验。
    摘要 = 计算制品摘要(制品根)
    _拒绝符号链接(制品根, "正式摘要后检查")
    摘要制品根 = 制品目录 / f"{客户端前缀}-{摘要}"
    _拒绝符号链接(摘要制品根, "摘要制品覆盖前检查")
    if 摘要制品根.exists():
        shutil.rmtree(摘要制品根)
    _安全复制目录树(制品根, 摘要制品根)
    _拒绝符号链接(摘要制品根, "摘要制品复制后检查")
    shutil.rmtree(制品根)
    制品根 = 摘要制品根
    摘要内容 = json.dumps({
        "客户端": 客户端前缀,
        "摘要sha256": 摘要,
        "顶层包": 顶层包表,
        "生成时间": "",
    }, ensure_ascii=False).encode("utf-8")
    制品根描述符 = _打开根目录(制品根, "制品摘要目标")
    try:
        _写入受控目标(
            制品根描述符, 制品根, Path("制品摘要.json"), 摘要内容)
    finally:
        os.close(制品根描述符)
    生成来源元数据(制品根)
    _拒绝符号链接(制品根, "构建完成检查")
    # 写盘后自校验（fail-closed）：全部文件已落盘才验；不过就异常退出，绝不写稳定指针。
    校验 = 写盘后自校验(制品根, 客户端根, 摘要)
    print(f"写盘后自校验通过：摘要对表一致（权威口径=目录名=制品摘要.json={摘要}）"
          f"耗时 {校验['摘要耗时']:.2f}s；"
          f"PY 重解析 {校验['py文件数']} 个 {校验['py耗时']:.2f}s；"
          f"回读全树字节 {校验['回读文件数']} 个/{校验['回读兆字节']:.1f}MB {校验['回读耗时']:.2f}s "
          f"（全树内容 sha256={校验['回读sha256']}）")
    # 稳定指针：最新制品
    指针 = 制品目录 / "当前.json"
    if 指针.is_symlink():
        raise 客户端构建错误(f"稳定指针是符号链接: {指针}")
    真实制品目录 = _准备目标根(制品目录)
    _受控目标路径(制品目录, 真实制品目录, Path("当前.json"))
    制品目录描述符 = _打开根目录(制品目录, "稳定指针目标")
    try:
        _写入受控目标(
            制品目录描述符,
            制品目录,
            Path("当前.json"),
            f'{{"摘要sha256": "{摘要}", "路径": "{制品根.name}"}}'.encode("utf-8"),
        )
    finally:
        os.close(制品目录描述符)
    _拒绝符号链接(制品目录, "构建后制品目录检查")
    print(f"构建完成：{制品根}")
    print(f"改写导入数：{改写数}，重算包摘要：{重算包摘要数}，制品摘要：{摘要}")
    if 安装:
        安装到环境(制品根)
        _拒绝符号链接(环境目录, "正式安装后环境检查")
    return 制品根


