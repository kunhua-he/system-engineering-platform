def 清理过期制品(仓库根: Path, 当前摘要: str, 当前身份: str) -> None:
    """只留当前制品：过期就删（内容寻址目录/身份目录/信任链历史各留一份）。

    为什么放进构建脚本：每次重编都会落一份新制品（约 30MB），不自动清理会越堆越多；
    源码与历史都在 git，删错可取回，因此不需要本地保留历史副本。
    """
    删目录数 = 0
    释放 = 0
    for 目录 in 仓库根.iterdir():
        if not 目录.is_dir():
            continue
        是内容寻址 = len(目录.name) == 32 and all(c in '0123456789abcdef' for c in 目录.name)
        是身份目录 = 目录.name.startswith(f"{客户端前缀}-")
        if not (是内容寻址 or 是身份目录):
            continue
        # 当前件的三种合法写法都要认：摘要本体、客户端前缀-摘要（实际目录名形态）、
        # 客户端前缀-版本（身份目录形态）。只比对前两种会把手上的当前件一并删掉
        # （2026-09-15 沙箱实测：原判定漏了「前缀-摘要」→ 当前件被删）。
        是当前 = 目录.name in (
            当前摘要, f"{客户端前缀}-{当前摘要}", f"{客户端前缀}-{当前身份}")
        if 是当前:
            continue
        大小 = sum(p.stat().st_size for p in 目录.rglob('*') if p.is_file())
        shutil.rmtree(目录)
        删目录数 += 1
        释放 += 大小
    # 信任链：快照/目标/签名制品包各留最新一份
    信任根 = 仓库根 / "平台客户端信任"
    for 目录, 模式 in ((信任根 / "元数据", "快照_*.json"), (信任根 / "元数据", "目标_*.json"),
                     (信任根 / "制品", "*.bin")):
        if not 目录.is_dir():
            continue
        文件 = sorted(目录.glob(模式), key=lambda p: p.stat().st_mtime)
        for 过期 in 文件[:-1]:
            释放 += 过期.stat().st_size
            过期.unlink()
            删目录数 += 1
    print(f"过期制品清理：删 {删目录数} 项，释放 {释放 / 1024 / 1024:.1f} MB")


def 构建(安装: bool = False) -> Path:
    """构建平台客户端制品目录；构建前后都拒绝任何符号链接。"""
    源根列表: list[tuple[str, Path]] = []
    for 顶层 in 顶层包表:
        源 = 系统根 / 顶层
        if not 源.exists():
            continue
        if 源.is_symlink() or not 源.is_dir():
            raise 客户端构建错误(f"正式源码根非法: {源}")
        _拒绝符号链接(源, "构建前源码检查")
        源根列表.append((顶层, 源))
    _拒绝符号链接(构建目录, "构建前旧构建目录检查")
    _拒绝符号链接(制品目录, "构建前制品目录检查")
    if 安装:
        _拒绝符号链接(环境目录, "构建前安装环境检查")
    if 构建目录.exists():
        shutil.rmtree(构建目录)
    客户端根 = 构建目录 / 客户端前缀
    客户端根.mkdir(parents=True)
    改写数 = 0
    for 顶层, 源 in 源根列表:
        改写数 += 复制并重写(源, 客户端根 / 顶层)
        复制非Py文件(源, 客户端根 / 顶层)
    # 插入点：AST 重写已完成（包内 .py 字节已变）、制品身份摘要尚未计算（见 计算制品摘要）。
    # 这一步只改构建副本，故身份摘要会如实反映重算后的字节；不改源码树。
    重算包摘要数 = 重算包内完整性摘要(客户端根)
    生成入口(客户端根)
    _拒绝符号链接(客户端根, "构建副本完成检查")
    # 制品根含 平台客户端 包层（激活指针→不可变制品→制品内 平台客户端 包可导入）
    制品根 = 制品目录 / f"{客户端前缀}-临时"
    _拒绝符号链接(制品根, "临时制品覆盖前检查")
    if 制品根.exists():
        shutil.rmtree(制品根)
    制品根.mkdir(parents=True)
    _安全复制目录树(客户端根, 制品根 / 客户端前缀)
    生成可运行制品壳(制品根)
    _拒绝符号链接(制品根, "临时制品复制后检查")
    # 摘要口径=唯一权威口径（平台控制面/包仓库/平台客户端制品.py::计算目录摘要16）；
    # 该口径按文件名排除构建期生成的元数据（制品摘要.json 内含自身摘要，纳入即自指），
    # 因此「此刻目录里还没有元数据」与「写完元数据之后再算」结果相同 —— 见 写盘后自校验。
    摘要 = 计算制品摘要(制品根)
    _拒绝符号链接(制品根, "正式摘要后检查")
    摘要制品根 = 制品目录 / f"{客户端前缀}-{摘要}"
    _拒绝符号链接(摘要制品根, "摘要制品覆盖前检查")
    if 摘要制品根.exists():
        shutil.rmtree(摘要制品根)
    _安全复制目录树(制品根, 摘要制品根)
    _拒绝符号链接(摘要制品根, "摘要制品复制后检查")
    shutil.rmtree(制品根)
    制品根 = 摘要制品根
    摘要内容 = json.dumps({
        "客户端": 客户端前缀,
        "摘要sha256": 摘要,
        "顶层包": 顶层包表,
        "生成时间": "",
    }, ensure_ascii=False).encode("utf-8")
    制品根描述符 = _打开根目录(制品根, "制品摘要目标")
    try:
        _写入受控目标(
            制品根描述符, 制品根, Path("制品摘要.json"), 摘要内容)
    finally:
        os.close(制品根描述符)
    生成来源元数据(制品根)
    _拒绝符号链接(制品根, "构建完成检查")
    # 写盘后自校验（fail-closed）：全部文件已落盘才验；不过就异常退出，绝不写稳定指针。
    校验 = 写盘后自校验(制品根, 客户端根, 摘要)
    print(f"写盘后自校验通过：摘要对表一致（权威口径=目录名=制品摘要.json={摘要}）"
          f"耗时 {校验['摘要耗时']:.2f}s；"
          f"PY 重解析 {校验['py文件数']} 个 {校验['py耗时']:.2f}s；"
          f"回读全树字节 {校验['回读文件数']} 个/{校验['回读兆字节']:.1f}MB {校验['回读耗时']:.2f}s "
          f"（全树内容 sha256={校验['回读sha256']}）")
    # 稳定指针：最新制品
    指针 = 制品目录 / "当前.json"
    if 指针.is_symlink():
        raise 客户端构建错误(f"稳定指针是符号链接: {指针}")
    真实制品目录 = _准备目标根(制品目录)
    _受控目标路径(制品目录, 真实制品目录, Path("当前.json"))
    制品目录描述符 = _打开根目录(制品目录, "稳定指针目标")
    try:
        _写入受控目标(
            制品目录描述符,
            制品目录,
            Path("当前.json"),
            f'{{"摘要sha256": "{摘要}", "路径": "{制品根.name}"}}'.encode("utf-8"),
        )
    finally:
        os.close(制品目录描述符)
    _拒绝符号链接(制品目录, "构建后制品目录检查")
    print(f"构建完成：{制品根}")
    print(f"改写导入数：{改写数}，重算包摘要：{重算包摘要数}，制品摘要：{摘要}")
    if 安装:
        安装到环境(制品根)
        _拒绝符号链接(环境目录, "正式安装后环境检查")
    return 制品根


def _取唯一能力调用器():
    """取平台唯一能力调用入口（对外动作一律从这里走，不直持有实现对象）。

    为什么必须有这一步（第 36 项「构建链调用面未收口」）：本脚本此前直接持有
    `平台客户端制品接入` 对象并调它的实现方法与属性 —— 那是「同一件事的第二个
    调用面」，实现方法一旦改名/改语义，构建脚本会静默走偏（没有任何一层能拦）。

    取法（**必须走完整装配**，实测依据）：
    - `公共契约.能力契约.调用器.获取能力调用器()` 的惰性装配只装支持库，
      实测 **515** 条能力、`平台控制面.*` **0 条** —— 包仓库与平台状态的能力面
      一条都不在，调用会直接判「能力不存在」；
    - `后端核心()` + `启动()` 走 发现→校验→锁定→装配 全链，实测 **679** 条能力、
      其中 `平台控制面.*` **90 条**（含 查询制品布局 / 校验平台客户端稳定路径 /
      平台状态.读取记录），且冷启动一次装配后进程内复用模板（实测二次 0.5s）。
    本脚本属 `其他` 层，`允许依赖表["其他"]` 显式放行 后端核心（同一层用法先例：
    `开发工具/发布门禁/运行发布门禁.py`），构不成越层。
    """
    from 后端核心.后端核心 import 后端核心

    后端 = 后端核心(系统根)
    启动 = 后端.启动()
    if not 启动.成功:
        raise RuntimeError(f"后端核心装配失败，无法按能力 id 调用：{启动.错误说明}")
    return 后端


def 调用能力(后端, 能力id: str, 参数: dict) -> Any:
    """按能力 id 调用并 **fail-closed**：失败即抛，绝不降级为警告或默默继续。

    这是本脚本唯一的对外动作通道。硬要求：能力被从注册表移除（缺件，错误码
    `能力不存在`）时必须**当场报错**，不许绕过平台入口继续跑；其余错误码
    （参数不合法 / 提供者不可用 / 内部错误）同样不许吞掉。报错文本里带能力 id
    与错误码，调用方（人/Agent）能直接读出是哪条能力缺了、缺在哪。
    """
    结果 = 后端.调用(能力id, 参数)
    if not 结果.成功:
        raise RuntimeError(
            f"能力调用失败（{结果.错误码 or '未知错误码'}）：{能力id}：{结果.错误说明}")
    return 结果.值


def 目录口径(后端) -> dict[str, Path]:
    """制品仓库目录口径 —— 经能力 id `平台控制面.包仓库.查询制品布局` 取。

    第 36 项命中的重叠结论之一（`查询制品布局` 真重复）就在这：调用方原来直取
    `接入.制品根目录` / `接入.客户端制品目录` 拼路径，正是该能力暴露的口径。
    传空 `制品根目录` 让实现层给**权威默认根**（源码态 = `<系统根>/工程缓存/制品仓库`，
    实测同值），调用方不再自己拼 `工程缓存`（制品态裸拼会把运行态写进不可变制品）。
    """
    布局 = 调用能力(后端, "平台控制面.包仓库.查询制品布局", {})
    return {
        "制品根目录": Path(布局["制品根目录"]),
        "客户端制品目录": Path(布局["客户端制品目录"]),
    }


def 安装到环境(制品根: Path) -> Path:
    """把制品经正式包仓库机制安装到 平台客户端环境/（不 bypass）。

    调用面收口（第 36 项）：目录口径与结论核查**一律经能力 id**走平台唯一调用入口，
    不再直取实现属性拼路径、不再直调实现方法取结论：

        查询制品布局            → 制品根目录 / 客户端制品目录（口径唯一事实源）
        校验平台客户端稳定路径   → 有效 / 消息 / 激活路径
        平台状态.读取记录        → 制品记录（清理时判「哪一份是当前件」）

    环境目录契约不变：
        工程缓存/制品仓库/平台客户端环境/平台客户端/  ← 固定包名的已安装制品
        工程缓存/制品仓库/平台客户端环境/当前.json    ← 激活指针（摘要/制品目录）

    仍有 3 处是「实现调用」：它们对应的语义在 679 条能力里 **0 覆盖**，
    按第 36 项口径「不要自己新开能力」原地保留，并逐处标注缺口能力名，
    待主会话裁决后补能力面（见每处 `缺口` 注释与交付回传）。
    """
    from 平台控制面.包仓库.平台客户端制品 import 平台客户端制品接入

    后端 = _取唯一能力调用器()
    口径 = 目录口径(后端)
    制品根目录 = 口径["制品根目录"]          # = 缓存根（内容寻址目录所在）
    客户端制品目录 = 口径["客户端制品目录"]   # = 缓存根/平台客户端制品（身份目录所在）
    # 状态目录/信任目录不是 查询制品布局 的参数面（能力契约只暴露制品根与客户端制品目录）：
    # 两者与实现层默认目录同名同源（`_制品仓库缓存根()` 同根），且都只是构造接入对象的
    # 定位参数、不产生任何对外动作；密钥与信任元数据的落点仍由实现层决定。
    状态目录 = 制品根目录 / "平台客户端状态"
    信任目录 = 制品根目录 / "平台客户端信任"
    接入 = 平台客户端制品接入(
        状态目录=状态目录, 制品根目录=制品根目录,
        客户端制品目录=客户端制品目录, 环境目录=环境目录, 信任目录=信任目录)
    try:
        # ⚠️ 缺口①（待裁决，勿新开能力）：密钥「落盘 + 复用」无能力面。
        #    唯一沾边的 `密码签名.生成密钥对` 是**纯计算**（实测契约：无路径参数、
        #    副作用「纯计算」），改调它 → 每次构建都换新钥，公钥与既有信任记录不符，
        #    入库直接判「发布者公钥与既有信任记录不一致」；不是等价替换，故不改。
        #    建议缺口能力名：`平台控制面.包仓库.读取或生成客户端签名密钥`。
        私钥, 公钥 = 平台客户端制品接入.生成或读取密钥(制品根目录 / "平台客户端密钥")
        # ⚠️ 缺口②（待裁决，勿新开能力）：入库编排无能力面。它内部三件套
        #    （`构建制品` / `登记发布者` / `签名制品`）**都已有能力 id**（重叠结论：
        #    构建制品真重复 → 勿再开同名能力），但入库还含「制品目录命名与摘要校验 →
        #    读取制品文件表 → 落盘生成元数据 → 登记磁盘信任元数据 → 入库自检」五步，
        #    这些没有能力面；在客户端复现它们等于把实现搬成第二套，故不做。
        #    建议缺口能力名：`平台控制面.包仓库.入库客户端制品`（内部转调上述三条能力）。
        入库成功, 入库消息, 制品摘要 = 接入.入库(
            制品目录=制品根, 构建输入={"来源": "客户端构建", "命令": " ".join(sys.argv)},
            私钥PEM=私钥, 公钥PEM=公钥)
        if not 入库成功:
            raise RuntimeError(f"入库失败: {入库消息}")
        # ⚠️ 缺口③（待裁决）：安装到环境（临时目录 + fsync + 原子替换 + 发布管理 CAS
        #    激活指针 + 同步 当前.json）无同名能力面。`平台控制面.包仓库.安装制品`
        #    语义**重叠但不等价**（它只按 目标目录 复制，不做发布管理激活、不写 当前.json），
        #    直接换过去会把激活指针契约悄悄改掉 —— 正是第 36 项「安装制品语义重复待裁」。
        #    建议缺口能力名：`平台控制面.包仓库.安装平台客户端制品`（落点是新能力还是扩
        #    安装制品的参数面，须裁决，本脚本不自行选）。
        安装成功, 安装消息, 目标 = 接入.安装到环境(制品摘要)
        if not 安装成功 or 目标 is None:
            raise RuntimeError(f"安装失败: {安装消息 or '未返回安装目标'}")
        # ── 以下两处原为直调实现，现已改为能力 id ──
        # 结论核查：原 `接入.校验稳定路径()` → 能力 `平台控制面.包仓库.校验平台客户端稳定路径`
        校验 = 调用能力(后端, "平台控制面.包仓库.校验平台客户端稳定路径", {
            "状态目录": str(状态目录),
            "制品根目录": str(制品根目录),
            "客户端制品目录": str(客户端制品目录),
            "环境目录": str(环境目录),
            "信任目录": str(信任目录),
        })
        if not 校验["有效"]:
            raise RuntimeError(f"稳定路径校验失败: {校验['消息']}")
        # 记录回读：原 `接入.状态.读取记录(...)` → 能力 `平台控制面.平台状态.读取记录`
        记录值 = 调用能力(后端, "平台控制面.平台状态.读取记录", {
            "存储目录": str(状态目录), "表": "制品",
            "主键列": "制品摘要", "主键值": 制品摘要})
        记录 = 记录值["记录"] if 记录值.get("是否命中") else None
        # 两个根都要清：制品根目录=内容寻址目录，客户端制品目录=每次构建落的
        # 平台客户端-<摘要16> 目录；只清前者会让后者无限堆积（2026-09-15 实测：29 份 / 467MB 从未被清）。
        清理过期制品(制品根目录, 制品摘要, (记录 or {}).get("版本", ""))
        清理过期制品(客户端制品目录, 制品摘要, (记录 or {}).get("版本", ""))
        print(f"已经包仓库安装并激活：{目标}")
        print(f"入库：{入库消息}")
        print(f"稳定路径校验：{校验['消息']}")
        return 目标
    finally:
        接入.关闭()


