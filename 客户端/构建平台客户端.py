def 构建链未收口缺口() -> list[dict[str, str]]:
    """构建链未收口缺口的**只读视图**（唯一事实源 = 上方 `_未收口能力缺口`）。

    给验证场景与人工核查用：拿到的是逐条 (调用点, 建议能力id, 实测阻塞原因)，
    不复制判定、不读盘。
    """
    return [dict(条) for 条 in _未收口能力缺口]


def _声明仍落在源码里(调用点: str, 语法树: ast.AST) -> bool:
    """`调用点` 是否仍是**真实的调用表达式**（AST 判据，不是字符串包含）。

    为什么必须走 AST：字符串包含法会被本模块自己的声明与注释骗过 ——
    声明行 `"调用点": "接入.入库",` 里就带着这个串，注释与 docstring 里也到处在提
    函数名，于是「调用点已搬走、只留声明」这种半吊子迁移照样判「还在」，
    守卫就成了恒绿（2026-09-19 反向验证实测：把调用点改成不存在的名字，守卫仍放行）。
    AST 只看真实的 `调用点(...)` 调用表达式，声明、注释、docstring 一概不算。
    """
    部分 = 调用点.split(".")
    if len(部分) != 2:
        raise ValueError(f"调用点 必须是 <对象>.<方法> 形式: {调用点!r}")
    对象名, 方法名 = 部分
    for 节点 in ast.walk(语法树):
        if not isinstance(节点, ast.Call):
            continue
        函数 = 节点.func
        if (isinstance(函数, ast.Attribute) and 函数.attr == 方法名
                and isinstance(函数.value, ast.Name) and 函数.value.id == 对象名):
            return True
    return False


def _核对未收口缺口(后端) -> None:
    """**fail-closed 守卫**：未收口清单必须与现场事实一致，不一致即当场报错。

    为什么要这个守卫（第 36 项「构建链调用面未收口」的收口判据）：清单里三条都是
    「等主会话裁决后开能力面」的**临时**例外。例外最大的风险不是它存在，而是
    **它悄悄过期** —— 能力面开通了没人回来切、调用点搬走了清单还留着，两种都会让
    「客户端层不直接 import 平台控制面实现」这条纪律退化成一句没人执行的注释。
    故此处把两个方向都做成判据：

    - **缺口被填**（`建议能力id` 已注册）→ 报红：能力面已就位，必须改走能力 id
      并删掉这条清单项，不许继续直调实现；
    - **声明已过期**（`调用点` 已不再是源码里的真实调用）→ 报红：调用点已搬走/
      改名，清单必须同步删除，不许留一条指向空气的缺口。

    判据来源全部是**本地事实**，不依赖任何目录或状态库存在：
    `后端.能力详情(能力id)` 实测「已注册 → 字典 / 未注册 → None」，
    调用点现场由本文件 AST 解析得到。故纯代码库/单测环境下同样可判。
    """
    语法树 = ast.parse(Path(__file__).read_text(encoding="utf-8"), filename=__file__)
    问题: list[str] = []
    for 条 in _未收口能力缺口:
        调用点, 能力id = 条["调用点"], 条["建议能力id"]
        if 后端.能力详情(能力id) is not None:
            问题.append(
                f"缺口已填：能力 `{能力id}` 已注册，但 `{调用点}` 仍在直调实现 —— "
                f"改走 `调用能力(后端, \"{能力id}\", …)` 并删除 `_未收口能力缺口` 里这条")
        if not _声明仍落在源码里(调用点, 语法树):
            问题.append(
                f"声明过期：`{调用点}` 已不是本文件里的真实调用（已搬走/改名），"
                f"删除 `_未收口能力缺口` 里这条（建议能力id `{能力id}`）")
    if 问题:
        raise RuntimeError(
            "构建链未收口清单与现场事实不一致（fail-closed，不静默降级）：\n  - "
            + "\n  - ".join(问题))


def _取唯一能力调用器():
    """取平台唯一能力调用入口（对外动作一律从这里走，不直持有实现对象）。

    为什么必须有这一步（第 36 项「构建链调用面未收口」）：本脚本此前直接持有
    `平台客户端制品接入` 对象并调它的实现方法与属性 —— 那是「同一件事的第二个
    调用面」，实现方法一旦改名/改语义，构建脚本会静默走偏（没有任何一层能拦）。

    取法（**必须走完整装配**，实测依据）：
    - `公共契约.能力契约.调用器.获取能力调用器()` 的惰性装配只装支持库，
      实测 **515** 条能力、`平台控制面.*` **0 条** —— 包仓库与平台状态的能力面
      一条都不在，调用会直接判「能力不存在」；
    - `后端核心()` + `启动()` 走 发现→校验→锁定→装配 全链，实测 **679** 条能力、
      其中 `平台控制面.*` **90 条**（含 查询制品布局 / 校验平台客户端稳定路径 /
      平台状态.读取记录），且冷启动一次装配后进程内复用模板（实测二次 0.5s）。
    本脚本属 `其他` 层，`允许依赖表["其他"]` 显式放行 后端核心（同一层用法先例：
    `开发工具/发布门禁/运行发布门禁.py`），构不成越层。
    """
    from 后端核心.后端核心 import 后端核心

    后端 = 后端核心(系统根)
    启动 = 后端.启动()
    if not 启动.成功:
        raise RuntimeError(f"后端核心装配失败，无法按能力 id 调用：{启动.错误说明}")
    return 后端


def 调用能力(后端, 能力id: str, 参数: dict) -> Any:
    """按能力 id 调用并 **fail-closed**：失败即抛，绝不降级为警告或默默继续。

    这是本脚本唯一的对外动作通道。硬要求：能力被从注册表移除（缺件，错误码
    `能力不存在`）时必须**当场报错**，不许绕过平台入口继续跑；其余错误码
    （参数不合法 / 提供者不可用 / 内部错误）同样不许吞掉。报错文本里带能力 id
    与错误码，调用方（人/Agent）能直接读出是哪条能力缺了、缺在哪。
    """
    结果 = 后端.调用(能力id, 参数)
    if not 结果.成功:
        raise RuntimeError(
            f"能力调用失败（{结果.错误码 or '未知错误码'}）：{能力id}：{结果.错误说明}")
    return 结果.值


def 目录口径(后端) -> dict[str, Path]:
    """制品仓库目录口径 —— 经能力 id `平台控制面.包仓库.查询制品布局` 取。

    第 36 项命中的重叠结论之一（`查询制品布局` 真重复）就在这：调用方原来直取
    `接入.制品根目录` / `接入.客户端制品目录` 拼路径，正是该能力暴露的口径。
    传空 `制品根目录` 让实现层给**权威默认根**（源码态 = `<系统根>/工程缓存/制品仓库`，
    实测同值），调用方不再自己拼 `工程缓存`（制品态裸拼会把运行态写进不可变制品）。
    """
    布局 = 调用能力(后端, "平台控制面.包仓库.查询制品布局", {})
    return {
        "制品根目录": Path(布局["制品根目录"]),
        "客户端制品目录": Path(布局["客户端制品目录"]),
    }


def 安装到环境(制品根: Path) -> Path:
    """把制品经正式包仓库机制安装到 平台客户端环境/（不 bypass）。

    调用面收口（第 36 项）：目录口径与结论核查**一律经能力 id**走平台唯一调用入口，
    不再直取实现属性拼路径、不再直调实现方法取结论：

        查询制品布局            → 制品根目录 / 客户端制品目录（口径唯一事实源）
        校验平台客户端稳定路径   → 有效 / 消息 / 激活路径
        平台状态.读取记录        → 制品记录（清理时判「哪一份是当前件」）

    环境目录契约不变：
        工程缓存/制品仓库/平台客户端环境/平台客户端/  ← 固定包名的已安装制品
        工程缓存/制品仓库/平台客户端环境/当前.json    ← 激活指针（摘要/制品目录）

    仍有 3 处是「实现调用」：它们对应的语义在 679 条能力里 **0 覆盖**，
    按第 36 项口径「不要自己新开能力」原地保留，并逐处标注缺口能力名，
    待主会话裁决后补能力面。三处的**唯一事实源**是模块级 `_未收口能力缺口`
    （本函数内三处调用点只写「指向清单的简短标记」，不复制原因，避免两处口径分叉）；
    进入安装链前先经 `_核对未收口缺口` 校验清单未过期（fail-closed）。
    """
    from 平台控制面.包仓库.平台客户端制品 import 平台客户端制品接入

    后端 = _取唯一能力调用器()
    _核对未收口缺口(后端)
    口径 = 目录口径(后端)
    制品根目录 = 口径["制品根目录"]          # = 缓存根（内容寻址目录所在）
    客户端制品目录 = 口径["客户端制品目录"]   # = 缓存根/平台客户端制品（身份目录所在）
    # 状态目录/信任目录不是 查询制品布局 的参数面（能力契约只暴露制品根与客户端制品目录）：
    # 两者与实现层默认目录同名同源（`_制品仓库缓存根()` 同根，实测三处目录逐项同值），
    # 且都只是构造接入对象的定位参数、不产生任何对外动作；密钥与信任元数据的落点仍由实现层决定。
    状态目录 = 制品根目录 / "平台客户端状态"
    信任目录 = 制品根目录 / "平台客户端信任"
    接入 = 平台客户端制品接入(
        状态目录=状态目录, 制品根目录=制品根目录,
        客户端制品目录=客户端制品目录, 环境目录=环境目录, 信任目录=信任目录)
    try:
        # ⚠️ 缺口①（待裁决，勿新开能力）：见模块级 `_未收口能力缺口` 第 3 条
        #    （建议能力名 `平台控制面.包仓库.读取或生成客户端签名密钥`）。
        私钥, 公钥 = 平台客户端制品接入.生成或读取密钥(制品根目录 / "平台客户端密钥")
        # ⚠️ 缺口②（待裁决，勿新开能力）：见模块级 `_未收口能力缺口` 第 1 条
        #    （建议能力名 `平台控制面.包仓库.入库客户端制品`）。
        入库成功, 入库消息, 制品摘要 = 接入.入库(
            制品目录=制品根, 构建输入={"来源": "客户端构建", "命令": " ".join(sys.argv)},
            私钥PEM=私钥, 公钥PEM=公钥)
        if not 入库成功:
            raise RuntimeError(f"入库失败: {入库消息}")
        # ⚠️ 缺口③（待裁决）：见模块级 `_未收口能力缺口` 第 2 条
        #    （建议能力名 `平台控制面.包仓库.安装平台客户端制品`；落点是新能力还是扩
        #    `安装制品` 的参数面，须裁决，本脚本不自行选）。
        安装成功, 安装消息, 目标 = 接入.安装到环境(制品摘要)
        if not 安装成功 or 目标 is None:
            raise RuntimeError(f"安装失败: {安装消息 or '未返回安装目标'}")
        # ── 以下两处原为直调实现，现已改为能力 id ──
        # 结论核查：原 `接入.校验稳定路径()` → 能力 `平台控制面.包仓库.校验平台客户端稳定路径`
        校验 = 调用能力(后端, "平台控制面.包仓库.校验平台客户端稳定路径", {
            "状态目录": str(状态目录),
            "制品根目录": str(制品根目录),
            "客户端制品目录": str(客户端制品目录),
            "环境目录": str(环境目录),
            "信任目录": str(信任目录),
        })
        if not 校验["有效"]:
            raise RuntimeError(f"稳定路径校验失败: {校验['消息']}")
        # 回收不在这里做：唯一回收实现是 `平台控制面/包仓库/制品保留.py`，由
        # `平台客户端制品接入` 的必经路径（诊断激活指针 / 安装到环境）自动调用，
        # 且带保底保留下限。此处曾另写一套无保底的清理（2026-09-19 实测把
        # `平台客户端制品/` 清成 0 份，安装链随即在「制品目录缺失」上被拒）。
        print(f"已经包仓库安装并激活：{目标}")
        print(f"入库：{入库消息}")
        print(f"稳定路径校验：{校验['消息']}")
        return 目标
    finally:
        接入.关闭()


