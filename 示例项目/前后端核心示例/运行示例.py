"""前后端核心示例：窗口→前端核心→网关→后端核心→模块→支持库→前端显示。

完整链路：前端窗口 → 前端核心 → 网关 → 后端核心 → 模块公开能力 →
支持库公开能力 → 统一结果 → 网关 → 前端状态 → 页面显示。
含成功场景与失败场景（能力不存在/参数错误/权限不足）。
"""

from __future__ import annotations

import sys
import json
import urllib.request
import urllib.error
from urllib.parse import quote
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 后端核心.后端核心 import 后端核心
from 前端核心.前端核心 import 组件定义, 窗口定义, 页面定义, 前端核心
from 前端核心.渲染提供者 import 测试渲染提供者, HTML渲染提供者
from 运行核心.统一网关.本地网关 import 本地网关服务器
from 运行核心.统一网关.网关核心 import 网关核心


def 装配系统() -> 后端核心:
    """装配后端核心（支持库+模块+网关）。"""
    后端 = 后端核心()
    启动结果 = 后端.启动()
    if not 启动结果.成功:
        raise RuntimeError(f"后端核心启动失败: {启动结果.错误说明}")
    # 注册示例能力（文本处理 经 模块公开能力 调用）
    def 分割文本能力(文本: str = "", 分隔符: str = "，") -> dict:
        from 公共契约.基础类型.结果类型 import 结果 as _结果
        if not 文本:
            return _结果.失败("参数不合法", "缺少 文本", 来源="示例能力")
        return {"段落数": len(文本.split(分隔符)), "段落": 文本.split(分隔符)}

    后端.注册能力("示例.分割文本", 分割文本能力, 参数=[
        {"名称": "文本", "类型": "文本", "必填": True},
        {"名称": "分隔符", "类型": "文本", "必填": False},
    ], 返回="结果", 说明="按分隔符分割文本（示例能力）")
    后端.设置权限("示例.分割文本", ["示例用户"])
    return 后端


def 构建前端(网关地址: str, 渲染方式: str = "测试") -> tuple[前端核心, dict]:
    """构建前端核心；调用入口只使用真实本地 HTTP。"""
    前端 = 前端核心(
        渲染提供者=测试渲染提供者()
        if 渲染方式 == "测试" else HTML渲染提供者(网关地址)
    )
    窗口 = 窗口定义(
        窗口id="示例窗口", 标题="前后端核心示例",
        页面列表=[页面定义(
            页面id="主页", 路由="/", 标题="文本分割",
            组件列表=[
                组件定义("文本输入", "输入框", {"默认值": "你好，世界，示例"}, ["输入"]),
                组件定义("分割按钮", "按钮", {
                    "文本": "调用文本处理", "能力id": "示例.分割文本",
                    "参数": {"文本": "", "分隔符": "，"}, "回调": "结果区",
                }, ["点击"]),
                组件定义("结果区", "状态区", {}, []),
                组件定义("错误区", "状态区", {}, []),
            ],
        )],
        后端能力依赖=["示例.分割文本"],
    )
    前端.注册窗口(窗口)
    前端.设置状态("文本输入", "你好，世界，示例")
    前端.设置状态("结果区", "等待调用")

    def 网关调用函数(能力id: str, 参数: dict) -> dict:
        """通过 HTTP 序列化边界调用网关，不持有网关核心对象。"""
        正文 = json.dumps({
            "操作": "调用能力", "能力id": 能力id, "参数": 参数,
            "项目id": "示例项目", "用户id": "示例用户", "会话id": "示例会话",
        }, ensure_ascii=False).encode("utf-8")
        请求 = urllib.request.Request(
            网关地址 + quote("/网关/请求"), data=正文,
            headers={"Content-Type": "application/json"}, method="POST",
        )
        try:
            with urllib.request.urlopen(请求, timeout=5) as 响应:
                return json.loads(响应.read().decode("utf-8"))
        except urllib.error.HTTPError as 错误:
            try:
                return json.loads(错误.read().decode("utf-8"))
            except (json.JSONDecodeError, UnicodeDecodeError):
                return {"成功": False, "错误码": f"HTTP {错误.code}", "错误说明": "网关拒绝请求"}
        except Exception:
            return {"成功": False, "错误码": "网关断开", "错误说明": "本地网关不可访问"}

    前端.设置调用入口(网关调用函数)
    return 前端, {"窗口": 窗口}


def 成功链路(前端: 前端核心, 窗口: 窗口定义) -> dict:
    """成功链路：输入文本 → 调用文本处理 → 展示成功结果。"""
    前端.打开窗口("示例窗口")
    参数 = {"文本": 前端.获取状态("文本输入", ""), "分隔符": "，"}
    结果 = 前端.调用后端能力("示例.分割文本", 参数)
    if 结果.get("成功"):
        前端.设置状态("结果区", f"成功: 共 {结果['值']['段落数']} 段 → {' / '.join(结果['值']['段落'])}")
        前端.设置状态("错误区", "")
    else:
        前端.设置状态("错误区", f"{结果.get('错误码')}: {结果.get('错误说明')}")
    return {"结果": 结果, "结果区": 前端.获取状态("结果区"), "错误区": 前端.获取状态("错误区")}


def 失败链路(前端: 前端核心) -> dict:
    """失败场景：能力不存在 / 参数错误 / 权限不足。"""
    失败表 = {}
    # 场景1：能力不存在
    结果1 = 前端.调用后端能力("不存在的.能力", {})
    失败表["能力不存在"] = {"错误码": 结果1.get("错误码"), "说明": 结果1.get("错误说明")}
    # 场景2：参数错误（缺少 文本）
    结果2 = 前端.调用后端能力("示例.分割文本", {})
    失败表["参数错误"] = {"错误码": 结果2.get("错误码"), "说明": 结果2.get("错误说明")}
    前端.设置状态("错误区", "能力不存在/参数错误 已明确显示")
    return 失败表


def 主函数() -> int:
    后端 = 装配系统()
    网关 = 本地网关服务器(网关核心实例=网关核心(后端), 端口=0)
    启动成功, 启动说明 = 网关.启动()
    if not 启动成功:
        print(启动说明)
        后端.优雅关闭()
        return 1
    网关地址 = f"http://127.0.0.1:{网关.端口}"
    try:
        前端, 上下文 = 构建前端(网关地址)
        成功结果 = 成功链路(前端, 上下文["窗口"])
        print("=" * 40)
        print("前后端核心示例")
        print("=" * 40)
        print(f"[1] 后端核心启动: {后端.状态快照()['状态']}（{后端.状态快照()['能力数']} 能力）")
        print(f"[2] 真实本地 HTTP 网关: {网关地址}")
        print(f"[3] 前端窗口打开: {上下文['窗口'].状态}")
        print(f"[4] HTTP 调用文本处理能力: 成功={成功结果['结果'].get('成功')}")
        print(f"    结果区: {成功结果['结果区']}")
        print(f"[5] HTTP 失败场景: {失败链路(前端)}")
        print("[6] 前端渲染（测试提供者）:")
        print(前端.渲染("示例窗口")["文本"])
        html前端, _ = 构建前端(网关地址, 渲染方式="浏览器HTML")
        html结果 = html前端.渲染("示例窗口")
        页面走HTTP = "/网关/请求" in html结果["html"] and "window.事件回调" not in html结果["html"]
        print(f"[7] HTML 渲染提供者: {html结果['宿主']}，HTML 长度 {len(html结果['html'])} 字符")
        print(f"[8] HTML 调用边界: 真实 HTTP={页面走HTTP}")
        return 0 if 成功结果["结果"].get("成功") and 页面走HTTP else 1
    finally:
        网关.优雅停止()
        后端.优雅关闭()
        print("本地网关与后端核心已优雅关闭")


if __name__ == "__main__":
    raise SystemExit(主函数())
