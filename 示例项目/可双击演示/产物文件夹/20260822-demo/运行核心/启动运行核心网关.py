"""启动运行核心网关（含后端核心装配、能力执行）。端口 40007，统一执行入口为 /网关/调用。"""
import sys
sys.path.insert(0, ".")
from 后端核心.后端核心 import 后端核心
from 运行核心.统一网关.网关核心 import 网关核心
from 运行核心.统一网关.本地网关 import 本地网关服务器

后端 = 后端核心()
启动 = 后端.启动()
if not 启动.成功:
    print(f"后端核心装配失败: {启动.错误说明}")
    sys.exit(1)
print(f"后端核心装配成功: {启动.值}")

网关 = 本地网关服务器(
    网关核心实例=网关核心(后端), 端口=40007, 地址="127.0.0.1",
    # 正式固定端口不得以匿名模式启动；凭证只从受控环境变量加载。
    配置={
        "请求超时秒": 1800,
        "要求凭证": True,
        "凭证环境变量": "系统库网关凭证",
        "禁止客户端身份": True,
    },
)
成功, 说明 = 网关.启动()
if not 成功:
    print(f"运行核心网关启动失败: {说明}")
    sys.exit(1)
print(f"运行核心网关已启动: http://127.0.0.1:40007")
print(f"接口: POST /网关/调用  GET /健康（调用需凭证）")
import time
while True:
    time.sleep(3600)
