"""启动运行核心网关（含后端核心装配、能力执行）。端口 8867，与能力网关(8866 搜索/契约)互补。"""
import sys
sys.path.insert(0, ".")
from 后端核心.后端核心 import 后端核心
from 运行核心.统一网关.网关核心 import 网关核心
from 运行核心.统一网关.本地网关 import 本地网关服务器

后端 = 后端核心()
启动 = 后端.启动()
if not 启动.成功:
    print(f"后端核心装配失败: {启动.错误说明}")
    sys.exit(1)
print(f"后端核心装配成功: {启动.值}")

网关 = 本地网关服务器(
    网关核心实例=网关核心(后端), 端口=40007, 地址="127.0.0.1",
    配置={"请求超时秒": 1800},
)
成功, 说明 = 网关.启动()
if not 成功:
    print(f"运行核心网关启动失败: {说明}")
    sys.exit(1)
print(f"运行核心网关已启动: http://127.0.0.1:8867")
print(f"接口: POST /网关/请求  POST /网关/调用  POST /网关/流式  GET /健康")
import time
while True:
    time.sleep(3600)