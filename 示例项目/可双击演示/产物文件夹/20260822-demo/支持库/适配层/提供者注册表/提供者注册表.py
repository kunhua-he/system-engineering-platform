"""提供者注册表：外部提供者注册、唯一选择与路由权威化。

规则：同一适配能力只能选择一个提供者；提供者必须声明名称、版本、
能力和配置需求；提供者不可用时返回明确错误；提供者初始化失败必须
回滚；提供者停止后必须释放运行时状态。

路由权威化（第三十阶段C3）：提供者注册表、实际进程与依赖锁必须对齐。
登记路由 把能力绑定到 提供者名称+提供者目录+依赖锁路径+运行方式；
同一能力已登记不同目录必须失败（禁止目录有记录、运行时却选另一实现）；
对齐核对 检查 登记路由 与 目录/依赖锁 的一致性。生命周期本身（启动/
健康/调用/超时/取消/停止/崩溃重启/资源回收）由 运行核心/运行环境管理器/
提供者生命周期 统一管理，本注册表只承载路由事实点。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable

from 公共契约.基础类型.结果类型 import 结果
from 支持库.适配层.配置契约.提供者配置契约 import 提供者配置需求


@dataclass
class 提供者路由信息:
    """能力级提供者路由：能力 → 提供者 → 目录/依赖锁/运行方式。

    三方对齐事实点：注册表登记的能力路由必须与 提供者目录 和 依赖锁
    实际存在一致；运行时不得选择登记之外的实现。
    """

    能力id: str
    提供者名称: str
    提供者目录: str = ""
    依赖锁路径: str = ""
    运行方式: str = "独立进程"  # 独立进程（第三方隔离）| 系统解释器（无第三方锁）
    进程名称: str = ""


@dataclass
class 提供者声明:
    """一份提供者注册声明。"""

    名称: str
    版本: str
    能力列表: list[str]
    配置需求: list[提供者配置需求] = field(default_factory=list)
    创建函数: Callable[..., Any] | None = None  # 接收配置字典，返回适配器实例


class 提供者注册表:
    """提供者注册表：注册、唯一选择、初始化（含回滚）、停止（含释放）。"""

    def __init__(self) -> None:
        self.注册表: dict[str, 提供者声明] = {}  # 提供者名称 → 声明
        self.能力映射: dict[str, str] = {}  # 能力id → 提供者名称
        self.活动实例: dict[str, Any] = {}  # 能力id → 运行中适配器实例
        self.状态表: dict[str, str] = {}  # 能力id → 运行状态
        self.路由表: dict[str, 提供者路由信息] = {}  # 能力id → 路由信息

    def 注册提供者(self, 声明: 提供者声明) -> 结果:
        """注册提供者；重名或同能力多提供者必须失败。"""
        if 声明.名称 in self.注册表:
            return 结果.失败("提供者冲突", f"提供者已注册: {声明.名称}", 来源="提供者注册表")
        for 能力id in 声明.能力列表:
            if 能力id in self.能力映射:
                return 结果.失败(
                    "提供者冲突",
                    f"能力 {能力id} 已有提供者 {self.能力映射[能力id]}，同一能力只能选择一个提供者",
                    来源="提供者注册表",
                )
        self.注册表[声明.名称] = 声明
        for 能力id in 声明.能力列表:
            self.能力映射[能力id] = 声明.名称
        return 结果.成功结果(声明.名称)

    def 选择提供者(self, 能力id: str) -> 结果:
        """按能力选择唯一提供者；无提供者返回明确错误。"""
        提供者名称 = self.能力映射.get(能力id)
        if 提供者名称 is None:
            return 结果.失败(
                "外部未安装", f"能力 {能力id} 无可用提供者", 来源="提供者注册表", 可重试=True
            )
        return 结果.成功结果(self.注册表[提供者名称])

    def 初始化提供者(self, 能力id: str, 配置: dict[str, Any] | None = None) -> 结果:
        """初始化提供者（创建实例+建立连接）；失败回滚并释放。"""
        配置 = 配置 or {}
        选择结果 = self.选择提供者(能力id)
        if not 选择结果.成功:
            return 选择结果
        声明 = 选择结果.值
        if 能力id in self.活动实例:
            return 结果.失败("提供者冲突", f"能力 {能力id} 已初始化", 来源="提供者注册表")
        try:
            实例 = 声明.创建函数(配置) if 声明.创建函数 else None
            if 实例 is None:
                return 结果.失败("内部错误", f"提供者 {声明.名称} 创建失败", 来源="提供者注册表")
            检查结果 = 实例.检查可用()
            if not 检查结果.成功:
                return 检查结果
            连接结果 = 实例.建立连接()
            if not 连接结果.成功:
                return 连接结果
            self.活动实例[能力id] = 实例
            self.状态表[能力id] = "已连接"
            return 结果.成功结果(实例)
        except Exception as 错误:
            self.活动实例.pop(能力id, None)
            self.状态表.pop(能力id, None)
            return 结果.失败("内部错误", f"提供者初始化失败已回滚: {错误}", 来源="提供者注册表")

    def 调用提供者(self, 能力id: str, 参数: dict | None = None) -> 结果:
        """调用已初始化提供者的最小操作；未初始化返回明确错误。"""
        实例 = self.活动实例.get(能力id)
        if 实例 is None:
            return 结果.失败(
                "外部不可访问", f"能力 {能力id} 提供者未初始化", 来源="提供者注册表"
            )
        try:
            return 实例.执行最小操作(参数)
        except Exception as 错误:
            return 结果.失败("内部错误", f"提供者调用异常: {错误}", 来源="提供者注册表")

    def 停止提供者(self, 能力id: str) -> 结果:
        """停止提供者（关闭+释放运行时状态）；重复停止幂等。"""
        实例 = self.活动实例.get(能力id)
        if 实例 is None:
            return 结果.成功结果("已停止")  # 重复停止幂等
        try:
            关闭结果 = 实例.关闭连接()
            if not 关闭结果.成功:
                return 关闭结果
        finally:
            self.活动实例.pop(能力id, None)
            self.状态表.pop(能力id, None)
        return 结果.成功结果("已停止并释放")

    def 已初始化(self, 能力id: str) -> bool:
        return 能力id in self.活动实例

    def 登记路由(self, 路由: 提供者路由信息) -> 结果:
        """登记能力路由；同一能力已登记不同目录/提供者必须冲突失败。

        目录有记录、运行时却选另一实现属于禁止行为：同一能力只能有
        一条路由，重复登记同一目录视为幂等成功。
        """
        已有 = self.路由表.get(路由.能力id)
        if 已有 is not None:
            if (已有.提供者名称 == 路由.提供者名称
                    and 已有.提供者目录 == 路由.提供者目录):
                return 结果.成功结果(路由.能力id)  # 幂等：同目录重复登记
            return 结果.失败(
                "提供者冲突",
                f"能力 {路由.能力id} 已登记提供者 {已有.提供者名称}（{已有.提供者目录}），"
                f"禁止登记另一实现 {路由.提供者名称}（{路由.提供者目录}）",
                来源="提供者注册表",
            )
        if not 路由.提供者目录:
            return 结果.失败("参数不合法", f"能力 {路由.能力id} 路由缺提供者目录",
                              来源="提供者注册表")
        self.路由表[路由.能力id] = 路由
        return 结果.成功结果(路由.能力id)

    def 获取路由(self, 能力id: str) -> 结果:
        """按能力获取登记路由；无路由返回明确错误。"""
        路由 = self.路由表.get(能力id)
        if 路由 is None:
            return 结果.失败(
                "外部未安装", f"能力 {能力id} 无登记路由", 来源="提供者注册表", 可重试=True
            )
        return 结果.成功结果(路由)

    def 移除路由(self, 能力id: str) -> 结果:
        """移除能力路由；重复移除幂等。"""
        if 能力id in self.路由表:
            del self.路由表[能力id]
            return 结果.成功结果("已移除路由")
        return 结果.成功结果("无路由（幂等）")

    def 对齐核对(self) -> list[str]:
        """登记路由 ↔ 提供者目录/依赖锁 对齐核对（fail-closed 报告）。

        检查：登记路由的 提供者目录 必须存在；登记了 依赖锁路径 的必须
        是 提供者目录/依赖锁.json 且文件存在；目录含 依赖锁.json 但登记
        为无锁 → 不一致。目录扫描级别的对齐（含锁目录未登记）由运行核心
        提供者生命周期管理器 核对（其持有提供者根目录事实点）。
        """
        问题列表: list[str] = []
        for 能力id, 路由 in self.路由表.items():
            if not 路由.提供者目录:
                问题列表.append(f"能力 {能力id} 路由缺提供者目录")
                continue
            目录 = Path(路由.提供者目录)
            if not 目录.is_dir():
                问题列表.append(f"能力 {能力id} 提供者目录不存在: {目录}")
                continue
            实际锁 = 目录 / "依赖锁.json"
            if 路由.依赖锁路径:
                锁文件 = Path(路由.依赖锁路径)
                if not 锁文件.is_file():
                    问题列表.append(f"能力 {能力id} 依赖锁文件缺失: {锁文件}")
                elif str(锁文件.resolve()) != str(实际锁.resolve()):
                    问题列表.append(
                        f"能力 {能力id} 依赖锁路径与目录不一致: {锁文件} vs {实际锁}")
            elif 实际锁.is_file():
                问题列表.append(f"能力 {能力id} 登记为无锁但目录含依赖锁（不一致）")
        return 问题列表
