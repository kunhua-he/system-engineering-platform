"""支持库适配层包：第三方库、系统接口与外部协议的中文边界。

包含：密码签名（经 密码签名提供者 隔离子进程）、密钥提供者（环境变量/
钥匙串）、配置安全、外部适配契约、数据库/HTTP/本地进程/动态库适配器与
提供者注册表。

密码签名能力经 密码签名提供者（cryptography 隔离子进程）执行：
- 生成密钥对/签名/验证签名/内容摘要 保持本公开入口历史语义：
  数据参数为原始字节，签名返回十六进制字符串，验证返回布尔；
  失败时 生成密钥对/签名/内容摘要 抛 RuntimeError（等价旧 密码适配 的
  cryptography 异常语义），验证签名 不抛异常。
- 内容摘要 保持历史语义：sha256 前 32 位（密码签名提供者契约返回完整
  64 位 sha256，此处截断兼容）。
"""

from __future__ import annotations

import base64

from 支持库.适配层.密码签名提供者 import (
    内容摘要 as _提供者内容摘要,
    生成密钥对 as _提供者生成密钥对,
    签名 as _提供者签名,
    验证签名 as _提供者验证签名,
)
from 支持库.适配层.适配契约 import 外部适配器, 资源状态_未连接, 资源状态_已连接, 资源状态_已关闭
from 支持库.适配层.数据库适配器.数据库适配器 import 数据库适配器
from 支持库.适配层.HTTP服务适配器.http服务适配器 import HTTP服务适配器
from 支持库.适配层.本地进程适配器.本地进程适配器 import 本地进程适配器
from 支持库.适配层.动态库适配器.动态库适配器 import 动态库适配器
from 支持库.适配层.提供者注册表.提供者注册表 import 提供者声明, 提供者注册表
from 支持库.适配层.提供者注册表.标准提供者 import 注册全部标准提供者


def _编码数据(数据: bytes) -> str:
    """原始字节 → base64 文本（密码签名提供者数据参数）。"""
    return base64.b64encode(数据).decode("ascii")


def 生成密钥对() -> tuple[str, str]:
    """生成 Ed25519 密钥对；返回 (私钥PEM, 公钥PEM)。"""
    结果 = _提供者生成密钥对()
    if not 结果.成功:
        raise RuntimeError(f"生成密钥对失败: {结果.错误说明}")
    return 结果.值["私钥PEM"], 结果.值["公钥PEM"]


def 签名(私钥PEM: str, 数据: bytes) -> str:
    """Ed25519 签名；返回十六进制签名。"""
    结果 = _提供者签名(私钥PEM, _编码数据(数据))
    if not 结果.成功:
        raise RuntimeError(f"签名失败: {结果.错误说明}")
    return 结果.值


def 验证签名(公钥PEM: str, 数据: bytes, 签名hex: str) -> bool:
    """验证 Ed25519 签名；签名不合法返回 False（不抛异常）。"""
    结果 = _提供者验证签名(公钥PEM, _编码数据(数据), 签名hex)
    return bool(结果.成功 and 结果.值 is True)


def 内容摘要(数据: bytes) -> str:
    """内容寻址摘要（sha256 前 32 位，历史语义）。"""
    结果 = _提供者内容摘要(_编码数据(数据))
    if not 结果.成功:
        raise RuntimeError(f"内容摘要失败: {结果.错误说明}")
    return 结果.值[:32]


