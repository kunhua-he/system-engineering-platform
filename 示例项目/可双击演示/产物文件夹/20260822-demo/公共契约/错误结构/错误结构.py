"""错误结构：跨包统一错误模型。

错误必须携带错误码、消息、来源、可恢复性与可重试性，禁止用裸字符串
当错误。外部适配失败必须能区分：未安装、不可访问、参数错误、版本
不兼容、协议错误、超时、内部错误。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class 错误结构:
    """统一错误结构。"""

    错误码: str
    消息: str
    来源: str = ""
    可恢复: bool = False
    可重试: bool = False
    详情: dict[str, Any] = field(default_factory=dict)

    def 转字典(self) -> dict[str, Any]:
        return {
            "错误码": self.错误码,
            "消息": self.消息,
            "来源": self.来源,
            "可恢复": self.可恢复,
            "可重试": self.可重试,
            "详情": self.详情,
        }


# 系统级错误码约定
错误码_参数不合法 = "参数不合法"
错误码_文件不存在 = "文件不存在"
错误码_文件不可写 = "文件不可写"
错误码_依赖缺失 = "依赖缺失"
错误码_版本冲突 = "版本冲突"
错误码_循环依赖 = "循环依赖"
错误码_能力重复 = "能力重复"
错误码_提供者冲突 = "提供者冲突"
错误码_未实现 = "未实现"
错误码_资源未清理 = "资源未清理"
错误码_状态跳转非法 = "状态跳转非法"

# 外部适配错误码（适配层统一使用）
错误码_外部未安装 = "外部未安装"
错误码_外部不可访问 = "外部不可访问"
错误码_参数错误 = "参数错误"
