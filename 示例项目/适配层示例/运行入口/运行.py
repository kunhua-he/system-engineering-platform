"""适配层示例：项目公开入口全链路运行样板。

链路：初始化项目 → 绑定支持库 → 绑定模块 → 生成依赖锁 → 装配系统
→ 搜索能力 → 调用模块 → 返回统一结果 → 运行项目验证。
全程不出现任何业务项目名称、数据库名或业务字段。
"""

from __future__ import annotations

import sys
from pathlib import Path

系统根 = Path(__file__).resolve().parents[3]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

项目根 = Path(__file__).resolve().parent.parent

from 公共契约.能力契约.契约 import 能力注册表
from 运行核心.加载器.生命周期管理.管理器 import 装配系统
from 项目适配层.能力适配.能力适配 import 从项目声明构建映射
from 项目适配层.依赖锁定.依赖锁定 import 生成依赖锁定
from 项目适配层.运行入口.项目入口 import 项目入口
from 项目适配层.支持库绑定.支持库绑定 import 校验绑定 as 校验支持库
from 项目适配层.模块绑定.模块绑定 import 校验绑定 as 校验模块


def 主程序() -> int:
    步骤 = [
        "[1] 绑定支持库: 文件系统、文本处理",
        "[2] 绑定模块: 文件管理",
        "[3] 生成依赖锁",
        "[4] 装配系统",
        "[5] 搜索能力",
        "[6] 经项目入口调用",
        "[7] 返回统一结果校验",
        "[8] 运行项目验证",
    ]
    print("适配层示例运行开始")

    # 1. 绑定校验（只读声明）
    for 支持库id in ("支持库.后端.文件系统", "支持库.后端.文本处理"):
        结果 = 校验支持库(支持库id, ">=1.0.0", 系统根 / "支持库")
        if not 结果.成功:
            print(f"[1] 绑定支持库失败: {结果.问题列表}")
            return 1
    print("[1] 绑定支持库: 文件系统、文本处理 ✓")

    # 2. 绑定模块
    模块结果 = 校验模块("模块库.文件管理", ">=1.0.0", 系统根)
    if not 模块结果.成功:
        print(f"[2] 绑定模块失败: {模块结果.问题列表}")
        return 1
    print("[2] 绑定模块: 文件管理 ✓")

    # 3. 依赖锁定（可重复生成）
    锁定结果 = 生成依赖锁定(项目根, 系统根)
    if not 锁定结果.成功:
        print(f"[3] 依赖锁定失败: {锁定结果.问题列表}")
        return 1
    锁定1 = (项目根 / "依赖锁定.json").read_text(encoding="utf-8")
    锁定结果2 = 生成依赖锁定(项目根, 系统根)
    锁定2 = (项目根 / "依赖锁定.json").read_text(encoding="utf-8")
    if 锁定1 != 锁定2:
        print("[3] 依赖锁定不可重复：两次生成结果不一致")
        return 1
    print(f"[3] 生成依赖锁: {锁定结果.包数量} 个包，可重复生成 ✓")

    # 4. 装配系统（支持库+模块全部装配）
    注册表 = 能力注册表()
    装配 = 装配系统(系统根 / "支持库", 系统根 / "模块库", 注册表)
    if not 装配.成功:
        print(f"[4] 装配失败: {装配.问题列表}")
        return 1
    print(f"[4] 装配系统: {装配.已注册能力数} 个能力 ✓")

    # 5. 搜索能力
    搜索列表 = 注册表.搜索(关键词="读取文件")
    if not 搜索列表:
        print("[5] 搜索 读取文件 失败")
        return 1
    print(f"[5] 搜索 读取文件: {[实现.能力id for 实现 in 搜索列表]} ✓")

    # 6. 经项目入口调用（项目代码唯一入口）
    import json as _json
    项目数据 = _json.loads((项目根 / "项目声明.json").read_text(encoding="utf-8"))
    发现 = __import__("运行核心.加载器.包发现.发现器", fromlist=["发现全部"]).发现全部(系统根 / "支持库", 系统根 / "模块库")
    映射 = 从项目声明构建映射(项目数据, 发现.声明列表)
    入口 = 项目入口(注册表, 映射)

    临时文件 = str(项目根 / "项目资源" / "示例输出.txt")
    写入结果 = 入口.调用("写入文件", {"文件路径": 临时文件, "内容": "适配层示例内容"})
    if not 写入结果.成功:
        print(f"[6] 入口调用写入失败: {写入结果.错误}")
        return 1
    读取结果 = 入口.调用("读取文件", {"文件路径": 临时文件})
    if not 读取结果.成功 or "适配层示例内容" not in (读取结果.值 or ""):
        print("[6] 入口调用读取失败")
        return 1
    分割结果 = 入口.调用("分割文本", {"文本": "甲,乙,丙", "分隔符": ","})
    if not 分割结果.成功 or 分割结果.值 != ["甲", "乙", "丙"]:
        print("[6] 入口调用分割失败")
        return 1
    print("[6] 经项目入口调用: 写入文件/读取文件/分割文本 ✓")

    # 7. 统一结果结构校验（成功/值/错误/错误码/说明）
    for 调用 in (写入结果, 读取结果, 分割结果):
        if not hasattr(调用, "成功") or not hasattr(调用, "值") or not hasattr(调用, "错误"):
            print("[7] 返回结果不符合统一结构")
            return 1
    print("[7] 返回统一结果结构: 成功/值/错误/错误码 ✓")

    # 8. 项目验证（项目适配范围）
    from 开发工具.统一验证.统一验证器 import 验证执行
    报告 = 验证执行(目标="适配层示例", 范围="项目适配")
    print(f"[8] 项目适配验证: {'通过' if 报告.门禁通过 else '失败'}（通过 {报告.通过数} / 失败 {报告.失败数}）")
    if not 报告.门禁通过:
        for 问题 in 报告.问题清单:
            print("    ✗", 问题)
        return 1

    print("适配层示例运行成功")
    return 0


if __name__ == "__main__":
    raise SystemExit(主程序())
