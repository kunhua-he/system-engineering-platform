"""适配层示例：项目公开入口的最小真实运行样板。"""
from __future__ import annotations

import json
import sys
from pathlib import Path

系统根 = Path(__file__).resolve().parents[3]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))
项目根 = Path(__file__).resolve().parent.parent

from 公共契约.能力契约.契约 import 能力注册表
from 后端核心.后端核心 import 后端核心
from 运行核心.加载器.生命周期管理.管理器 import 装配系统
from 运行核心.统一网关.网关核心 import 网关核心
from 运行核心.统一网关.本地网关 import 本地网关服务器
from 运行核心.能力调用.HTTP连接器 import HTTP连接器
from 项目适配层.能力适配.能力适配 import 从项目声明构建映射
from 项目适配层.依赖锁定.依赖锁定 import 生成依赖锁定
from 项目适配层.运行入口.项目入口 import 项目入口
from 项目适配层.支持库绑定.支持库绑定 import 校验绑定 as 校验支持库
from 项目适配层.模块绑定.模块绑定 import 校验绑定 as 校验模块


def 主程序() -> int:
    print("适配层示例运行开始")
    # 真实可装配子域：父包只是目录分组，不是绑定目标
    for 支持库id in (
        "支持库.后端.文件系统支持库.文件操作",
        "支持库.后端.数据操作支持库.文本处理",
        "支持库.后端.系统核心支持库.资源管理",
    ):
        if not 校验支持库(支持库id, ">=1.0.0", 系统根 / "支持库").成功:
            return 1
    print("[1] 绑定支持库: 文件系统、文本处理 ✓")
    if not 校验模块("模块库.文件管理", ">=1.0.0", 系统根).成功:
        return 1
    print("[2] 绑定模块: 文件管理 ✓")
    锁定 = 生成依赖锁定(项目根, 系统根)
    if not 锁定.成功:
        print(f"[3] 依赖锁定失败: {锁定.问题列表}")
        return 1
    print(f"[3] 生成依赖锁: {锁定.包数量} 个包 ✓")
    后端 = 后端核心(系统根)
    启动结果 = 后端.启动()
    if not 启动结果.成功:
        print(f"[4] 后端核心启动失败: {启动结果.错误说明}")
        return 1
    print(f"[4] 装配系统: {后端.状态.能力数} 个能力 ✓")
    # 模块调用面与支持库提供者调用面使用不同的本地 HTTP 端口，
    # 防止模块通过连接器回指自身网关形成递归。
    提供者网关 = 本地网关服务器(网关核心实例=网关核心(后端), 地址="127.0.0.1", 端口=0)
    提供者启动, 提供者说明 = 提供者网关.启动()
    if not 提供者启动:
        后端.强制关闭()
        print(f"[5] 提供者网关启动失败: {提供者说明}")
        return 1
    网关 = 本地网关服务器(网关核心实例=网关核心(后端), 地址="127.0.0.1", 端口=0)
    网关启动, 网关说明 = 网关.启动()
    if not 网关启动:
        提供者网关.优雅停止()
        后端.强制关闭()
        print(f"[5] 模块网关启动失败: {网关说明}")
        return 1
    连接器 = HTTP连接器(网关地址="127.0.0.1", 网关端口=提供者网关.端口)
    项目连接器 = HTTP连接器(网关地址="127.0.0.1", 网关端口=网关.端口)
    from 模块库.文件管理 import 设置HTTP连接器
    设置HTTP连接器(连接器)
    项目数据 = json.loads((项目根 / "项目声明.json").read_text(encoding="utf-8"))
    from 运行核心.加载器.包发现.发现器 import 发现全部
    映射 = 从项目声明构建映射(项目数据, 发现全部(系统根 / "支持库", 系统根 / "模块库").声明列表)
    入口 = 项目入口(后端.注册表, 映射, 项目连接器)
    资源 = 项目根 / "项目资源"
    资源.mkdir(parents=True, exist_ok=True)
    路径 = str(资源 / "示例输出.txt")
    写入 = 入口.调用("写入文件", {"文件路径": 路径, "内容": "适配层示例内容"})
    读取 = 入口.调用("读取文件", {"文件路径": 路径})
    分割 = 入口.调用("分割文本", {"文本": "苹果,香蕉,橙子", "分隔符": ","})
    try:
        if not (写入.成功 and 读取.成功 and 分割.成功 and 分割.值 == ["苹果", "香蕉", "橙子"]):
            def 错误摘要(结果):
                错误 = getattr(结果, "错误", None)
                return "成功" if 错误 is None else f"{错误.错误码} {错误.消息}"
            print(f"[6] 调用失败: 写入={错误摘要(写入)}; 读取={错误摘要(读取)}; 分割={错误摘要(分割)}")
            return 1
        print("[6] 经项目入口调用: 写入文件/读取文件/分割文本 ✓")
        print("[7] 返回统一结果结构: 成功/值/错误 ✓")
        print("[8] 项目适配验证: 通过 ✓")
        print("适配层示例运行成功")
        return 0
    finally:
        网关.优雅停止()
        提供者网关.优雅停止()
        后端.优雅关闭()


if __name__ == "__main__":
    raise SystemExit(主程序())
