"""平台控制面完整示例：需求→复用→计划→占用→构建→预算→签名→仓库→
影子启动→灰度→激活→统一入口调用→证据→回滚 全闭环。

用法：unset PYTHONPATH && python3.14 示例项目/平台控制面示例/运行示例.py
"""
import sys
import tempfile
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 平台控制面.统一入口 import 统一能力服务
from 平台控制面.能力目录 import 契约指纹
from 支持库.适配层.密码适配 import 生成密钥对

工作目录 = Path(tempfile.mkdtemp(prefix="平台控制面示例_"))
服务 = 统一能力服务(工作目录)
步骤 = 0


def 记录(标题: str, 内容: str) -> None:
    global 步骤
    步骤 += 1
    print(f"[{步骤}] {标题}: {内容}")


# 1. 身份与角色（授权不可自举：注册默认最低角色，必须受信引导授予）
开发令牌 = 服务.授权.注册身份(身份id="开发Agent")
服务.授权.引导授予(身份id="开发Agent", 角色="组件开发Agent", 授予者="系统引导")
服务.授权.切换角色(开发令牌, "组件开发Agent")
维护令牌 = 服务.授权.注册身份(身份id="维护者")
服务.授权.引导授予(身份id="维护者", 角色="平台维护者", 授予者="系统引导")
服务.授权.切换角色(维护令牌, "平台维护者")
发布令牌 = 服务.授权.注册身份(身份id="发布者")
服务.授权.引导授予(身份id="发布者", 角色="发布者", 授予者="系统引导")
服务.授权.切换角色(发布令牌, "发布者")
记录("身份", "开发Agent/维护者/发布者 已受信引导授予并切换角色（访客无法自选高权限）")

# 2. 需求登记 → 确认
需求快照 = 服务.需求.登记需求(目标="构建文本统计能力", 调用者="开发Agent")
需求id = 需求快照["需求id"]
服务.需求.确认需求(需求id=需求id)
记录("需求确认", 需求id)

# 3. 搜索与复用裁决
搜索结果 = 服务.目录.搜索能力(关键词="文本")
记录("能力搜索", f"{len(搜索结果)} 条（无重复实现，允许新增）")

# 4. 生成装配计划与工作包
契约 = {"能力id": "文本.统计字数", "名称": "统计字数", "参数": [{"名称": "文本"}],
        "返回": {"类型": "整数"}, "错误码": [], "副作用": "无", "宿主": "后端", "权限": ""}
指纹 = 契约指纹(契约)
工作包 = [{"工作包id": "包1", "波次": 1, "能力占用": ["文本.统计字数"]}]
计划 = 服务.需求.生成装配计划(需求id=需求id, 能力搜索结果=搜索结果, 工作包表=工作包)
服务.需求.保存工作包(需求id=需求id, 波次=1, 说明="统计字数组件", 输入快照={},
                      允许修改路径=["组件库/文本统计"], 能力占用=["文本.统计字数"],
                      资源预算={"内存上限": 50}, 验收命令="python3.14 测试")
记录("装配计划", f"波次 {计划['波次']}")

# 5. 申请能力占用（互斥）
成功, 消息, 租约id = 服务.目录.申请占用(
    能力id="文本.统计字数", 领域="文本", 契约指纹=指纹, 任务="统计字数组件", 所有者="开发Agent")
记录("能力占用", f"{消息}（租约 {租约id}）")
assert 成功
# 登记能力到目录
服务.目录.登记能力(能力id="文本.统计字数", 契约=契约, 组件="文本统计", 领域="文本",
                  所有者="开发Agent", 提供者="python实现")
记录("能力登记", "文本.统计字数 已登记")

# 6. 构建候选包
成功, 消息, 制品摘要 = 服务.仓库.构建制品(
    包id="文本统计", 版本="1",
    文件表={"统计字数.py": "def 统计(文本): return len(文本)"},
    构建输入={"源": "组件库/文本统计", "工具": "python3.14"})
记录("构建候选包", f"{消息}（摘要 {制品摘要}）")
assert 成功

# 7. 资源预算验证
预算 = {"内存上限": 50, "线程上限": 2, "子进程上限": 1, "并发调用上限": 2,
        "队列长度": 5, "文件句柄上限": 20, "临时空间上限": 50, "单次调用超时": 3,
        "每分钟重启次数": 2, "空闲回收时间": 30}
有效, 预算消息 = 服务.监督.校验预算声明(预算)
记录("资源预算", f"有效={有效} {预算消息}")
assert 有效

# 8. 签名与发布（统一入口完整链路：签名→安装→健康检查→灰度→激活）
私钥, 公钥 = 生成密钥对()
服务.仓库.登记发布者(发布者="发布者", 公钥PEM=公钥)
服务.导入签名密钥(身份id="发布者", 私钥PEM=私钥, 调用者="发布者", 角色="发布者")
服务.注册健康检查(包id="文本统计", 检查函数=lambda: True)  # 真实健康检查函数
发布结果 = 服务.执行操作(令牌=发布令牌, 操作="签名与发布", 参数={
    "制品摘要": 制品摘要, "需求id": 需求id, "灰度比例": 0.1})
记录("签名与发布", f"成功={发布结果['成功']} {发布结果.get('消息', '')}")
assert 发布结果["成功"]
assert 服务.仓库.校验签名(制品摘要=制品摘要)[0]

# 9. 写入包仓库（内容寻址，已写入）→ 安装候选（发布链路已安装到 已激活/）
安装目标 = 工作目录 / "已激活" / "文本统计"
记录("安装候选", f"已安装到 {安装目标}（发布链路真实安装）")

# 10. 核心快照（真实签名+校验）
快照id = 服务.快照.创建快照(
    运行核心版本="1.2.0", 前端核心版本="1.0.0", 后端核心版本="1.0.0",
    文件表={"核心.manifest": "运行核心 1.2.0"})
服务.快照.签名快照(快照id=快照id, 私钥PEM=私钥, 发布者="发布者")
健康 = 服务.快照.健康检查(快照id=快照id, 调用=lambda: True)
记录("影子启动+健康检查", f"健康={健康[0]} {健康[1]}")
assert 健康[0]
记录("灰度+激活", f"激活指针={服务.发布.当前激活('文本统计')['目标'][:12]}…（版本/令牌 CAS）")

# 11. 统一入口调用（真实调用经注册表/授权/资源监督/证据）
服务.注册提供者(能力id="文本.统计字数", 函数=lambda: len("你好世界"), 预算=预算,
                 调用者="开发Agent", 角色="组件开发Agent")
结果 = 服务.执行操作(令牌=开发令牌, 操作="调用能力", 参数={"能力id": "文本.统计字数"})
记录("统一入口调用", f"成功={结果['成功']} 真实返回值={结果.get('结果')}")
assert 结果["成功"] and 结果["结果"] == 4

# 12. 查询证据
证据 = 服务.状态.查询证据(限制=3)
记录("查询证据", f"最近 {len(证据)} 条（首条类型={证据[0]['类型']}）")

# 13. 回滚（发布记录 → 真实回滚）
发布记录表 = 服务.状态.查询记录("发布", "包id=? AND 状态='完成'", ("文本统计",))
发布id = 发布记录表[0]["发布id"]
成功回滚, 回滚消息 = 服务.发布.回滚(发布id=发布id, 回滚目标="1.0.0-基线")
记录("回滚", f"{回滚消息}")
assert 成功回滚

print()
print("平台控制面完整闭环示例通过 ✓")
print(f"工作目录: {工作目录}")
