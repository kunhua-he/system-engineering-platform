"""稳定平台完整示例：从自然语言需求草案到证据查询的一条真实链路。

全部步骤调用生产实现（统一能力服务、需求登记、能力目录、包仓库、
发布管理、提供者注册表、密码适配），禁止桩实现；每个阶段把真实执行
结果追加为主题=包id 的证据，证据链在 状态.查询证据(主题=包id) 下
完整可追溯（登记/确认/搜索/装配/工作包/构建/签名/安装/调用/升级/回滚）。
"""
from __future__ import annotations

import tempfile
from pathlib import Path
from typing import Any

from 平台控制面.统一入口 import 统一能力服务
from 平台控制面.授权 import 发布者
from 支持库.适配层.密码适配 import 生成密钥对

包id = "示例_文本统计包"
能力id = "文本.统计"
需求目标 = "需要统计中文文本的字数与行数，并验证制品的构建、签名、安装、升级与回滚。"


class 稳定平台完整示例:
    """真实链路执行器：一次执行覆盖全部阶段，返回各阶段真实结果。"""

    def __init__(self, 存储目录: Path | None = None) -> None:
        self.目录 = Path(存储目录 or tempfile.mkdtemp(prefix="工作包20_"))
        self.服务 = 统一能力服务(self.目录)
        self.身份id = "示例发布者"
        self.令牌 = self.服务.授权.注册身份(身份id=self.身份id)
        成功, 消息 = self.服务.授权.引导授予(身份id=self.身份id, 角色=发布者, 授予者="系统引导")
        if not 成功:
            raise RuntimeError(f"引导授予失败: {消息}")
        成功, 消息 = self.服务.授权.切换角色(self.令牌, 发布者)
        if not 成功:
            raise RuntimeError(f"切换角色失败: {消息}")
        self.私钥, self.公钥 = 生成密钥对()
        self.服务.仓库.登记发布者(发布者=self.身份id, 公钥PEM=self.公钥)
        self.服务.导入签名密钥(身份id=self.身份id, 私钥PEM=self.私钥)

    def _证据(self, 类型: str, 内容: dict[str, Any]) -> str:
        """把阶段真实结果追加为主题=包id 的证据（生产证据账本）。"""
        return self.服务.状态.追加证据(类型=类型, 主题=包id, 内容=内容,
                                      调用者=self.身份id, 角色=发布者, 结果="成功")

    @staticmethod
    def 统计文本(*, 文本: str) -> dict[str, Any]:
        """真实统计实现：字数=非空白字符数，行数=换行分段数。"""
        行数 = len(文本.splitlines()) or 1
        字数 = sum(1 for 字符 in 文本 if not 字符.isspace())
        return {"字数": 字数, "行数": 行数}

    @staticmethod
    def _预算() -> dict[str, Any]:
        return {键: 10 for 键 in ("内存上限", "线程上限", "子进程上限", "并发调用上限",
                                "队列长度", "文件句柄上限", "临时空间上限",
                                "每分钟重启次数", "空闲回收时间")} | {"单次调用超时": 5}

    def 执行(self) -> dict[str, Any]:
        服务 = self.服务
        # 1. 登记需求（自然语言草案 → 不可变需求快照）
        快照 = 服务.需求.登记需求(目标=需求目标, 调用者=self.身份id, 角色=发布者)
        需求id = 快照["需求id"]
        self._证据("登记", {"需求id": 需求id, "目标": 需求目标})
        # 2. 确认需求
        成功, 消息 = 服务.需求.确认需求(需求id=需求id, 调用者=self.身份id, 角色=发布者)
        if not 成功:
            raise RuntimeError(f"确认需求失败: {消息}")
        self._证据("确认", {"需求id": 需求id})
        # 能力登记 + 提供者注册（调用阶段真实执行）
        成功, 消息 = 服务.目录.登记能力(
            能力id=能力id, 契约={"能力id": 能力id, "名称": "文本统计", "参数": ["文本"],
                                  "返回": {"字数": "int", "行数": "int"}},
            组件="文本工具", 领域="文本处理", 成熟度="稳定", 所有者=self.身份id)
        if not 成功:
            raise RuntimeError(f"登记能力失败: {消息}")
        成功, 消息 = 服务.注册提供者(能力id=能力id, 函数=self.统计文本, 预算=self._预算())
        if not 成功:
            raise RuntimeError(f"注册提供者失败: {消息}")
        # 3. 搜索能力
        搜索 = 服务.执行操作(令牌=self.令牌, 操作="搜索能力", 参数={"关键词": "文本"})
        if not 搜索["成功"]:
            raise RuntimeError(f"搜索失败: {搜索}")
        self._证据("搜索", {"关键词": "文本", "数量": 搜索["数量"]})
        # 4. 生成装配计划
        计划结果 = 服务.执行操作(令牌=self.令牌, 操作="生成装配计划", 参数={"需求id": 需求id, "关键词": "文本"})
        if not 计划结果["成功"]:
            raise RuntimeError(f"装配计划失败: {计划结果}")
        计划 = 计划结果["计划"]
        self._证据("装配", {"工作包数": len(计划["工作包表"])})
        # 5. 并行工作包：把计划中的能力条目拆为工作包（真实落库）
        工作包表 = []
        for 包 in 计划["工作包表"]:
            记录 = 服务.需求.保存工作包(
                需求id=需求id, 波次=包["波次"], 说明=包["说明"],
                输入快照={"目标": 需求目标}, 允许修改路径=["示例_输出"],
                能力占用=包["能力占用"], 资源预算=self._预算(), 验收命令="python3.14 主.py")
            工作包表.append(记录["工作包id"])
        self._证据("工作包", {"数量": len(工作包表)})
        # 6. 构建 v1（真实文件表 → 内容寻址制品落盘）
        成功, 消息, v1摘要 = 服务.仓库.构建制品(
            包id=包id, 版本="1", 文件表={"主.py": "def 统计():\n    return 1\n"},
            构建输入={"源码": "文本统计组件", "构建命令": "python3.14 主.py"})
        if not 成功:
            raise RuntimeError(f"构建失败: {消息}")
        self._证据("构建", {"版本": "1", "制品摘要": v1摘要})
        # 7. 签名 v1（真实 Ed25519，密钥来自密码适配）
        成功, 消息 = 服务.仓库.签名制品(制品摘要=v1摘要, 私钥PEM=self.私钥, 发布者=self.身份id)
        if not 成功:
            raise RuntimeError(f"签名失败: {消息}")
        self._证据("签名", {"版本": "1", "发布者": self.身份id})
        # 8. 安装 v1（临时目录 + 原子替换，安装前后真实校验）
        成功, 消息 = 服务.仓库.安装制品(制品摘要=v1摘要, 目标目录=self.目录 / "已激活" / 包id)
        if not 成功:
            raise RuntimeError(f"安装失败: {消息}")
        self._证据("安装", {"版本": "1", "目标": "已激活"})
        发布id1 = 服务.发布.登记期望版本(包id=包id, 期望版本="1", 调用者=self.身份id)
        成功, 消息 = 服务.发布.开始灰度(发布id=发布id1, 候选版本="1", 比例=0.1)
        if not 成功:
            raise RuntimeError(f"灰度失败: {消息}")
        成功, 消息 = 服务.发布.激活(发布id=发布id1, 目标=v1摘要)
        if not 成功:
            raise RuntimeError(f"激活v1失败: {消息}")
        # 9. 调用能力（注册表 + 资源监督真实执行提供者）
        调用 = 服务.执行操作(令牌=self.令牌, 操作="调用能力",
                            参数={"能力id": 能力id, "参数": {"文本": "你好世界\n第二行"}})
        if not 调用["成功"]:
            raise RuntimeError(f"调用失败: {调用}")
        self._证据("调用", {"能力id": 能力id, "结果": 调用["结果"]})
        # 10. 升级 v2：构建新版本（版本+1、内容变化）→ 重新签名 → 登记期望版本 → 激活
        成功, 消息, v2摘要 = 服务.仓库.构建制品(
            包id=包id, 版本="2", 文件表={"主.py": "def 统计():\n    return 2\n"},
            构建输入={"源码": "文本统计组件v2", "构建命令": "python3.14 主.py"})
        if not 成功:
            raise RuntimeError(f"构建v2失败: {消息}")
        成功, 消息 = 服务.仓库.签名制品(制品摘要=v2摘要, 私钥PEM=self.私钥, 发布者=self.身份id)
        if not 成功:
            raise RuntimeError(f"签名v2失败: {消息}")
        发布id2 = 服务.发布.登记期望版本(包id=包id, 期望版本="2", 调用者=self.身份id)
        成功, 消息 = 服务.发布.开始灰度(发布id=发布id2, 候选版本="2", 比例=0.1)
        if not 成功:
            raise RuntimeError(f"灰度失败: {消息}")
        成功, 消息 = 服务.发布.激活(发布id=发布id2, 目标=v2摘要)
        if not 成功:
            raise RuntimeError(f"激活v2失败: {消息}")
        升级后指针 = 服务.发布.当前激活(包id)
        self._证据("升级", {"版本": "2", "制品摘要": v2摘要, "指针": 升级后指针["目标"]})
        # 11. 回滚到 v1（真实 CAS 指针切换）
        成功, 消息 = 服务.发布.回滚(发布id=发布id2, 回滚目标=v1摘要, 调用者=self.身份id)
        if not 成功:
            raise RuntimeError(f"回滚失败: {消息}")
        回滚后指针 = 服务.发布.当前激活(包id)
        self._证据("回滚", {"版本": "1", "指针": 回滚后指针["目标"]})
        # 12. 证据查询（主题=包id 完整证据链）
        证据 = 服务.状态.查询证据(主题=包id, 限制=100)
        return {"包id": 包id, "需求id": 需求id, "能力id": 能力id,
                "v1摘要": v1摘要, "v2摘要": v2摘要, "计划": 计划,
                "工作包表": 工作包表, "调用结果": 调用["结果"],
                "升级后指针": 升级后指针, "回滚后指针": 回滚后指针,
                "证据": 证据}
