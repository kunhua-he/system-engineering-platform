"""真实浏览器交互示例：浏览器页面 → 前端核心 → HTTP 网关 → 后端核心 → 能力。

页面：文本输入 → 点击分割按钮 → 调用网关 → 后端执行文本处理能力 →
返回结果 → 浏览器结果区显示（含 等待/加载中/成功/错误 状态）。
启动 HTTP 网关，输出浏览器页面 HTML 并验证交互链路真实可用。
"""

