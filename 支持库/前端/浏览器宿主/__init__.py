"""浏览器宿主支持库：静态页面与统一 HTTP 网关转发。"""
from 支持库.前端.浏览器宿主.实现.浏览器宿主 import 启动网页服务
from 公共契约.能力契约.契约 import 能力实现
from 公共契约.基础类型.结果类型 import 结果

__all__ = ["启动网页服务"]


def 注册能力(注册表) -> None:
    注册表.注册(能力实现(
        能力id="浏览器宿主.启动网页服务", 包id="支持库.前端.浏览器宿主",
        实现函数=_启动网页服务统一结果,
        参数=[{"名称": "标题", "类型": "文本型", "必填": False, "默认值": "底座网页服务"},
              {"名称": "页面说明", "类型": "文本型", "必填": False, "默认值": ""},
              {"名称": "网关地址", "类型": "文本型", "必填": False, "默认值": ""},
              {"名称": "能力id", "类型": "文本型", "必填": False, "默认值": ""},
              # 端口默认值必须与 能力契约/参数契约.json（对调用方的唯一承诺）和实现签名三方一致。
              # 注册侧原写 0：0 是「让操作系统分配随机端口」，与「固定应用端口 45080」的设计意图相冲
              # ——实现层在端口被占用时明确拒绝改绑随机端口（见 实现/浏览器宿主.py 的 OSError 分支），
              # 调用方照注册表公布的默认值传 0 拿到的就是一个随机端口，声明与真实行为不符。
              {"名称": "端口", "类型": "整数型", "必填": False, "默认值": 45080},
              {"名称": "自动打开", "类型": "逻辑型", "必填": False, "默认值": False},
              {"名称": "受管验证", "类型": "逻辑型", "必填": False, "默认值": False},
              {"名称": "状态目录", "类型": "文本型", "必填": False, "默认值": ""}],
        返回="结果型", 说明="启动静态网页宿主，能力执行统一转发到网关"))


def _启动网页服务统一结果(**参数):
    """把宿主原子实现的受管回收值封装为统一结果。"""
    try:
        return 结果.成功结果(启动网页服务(**参数))
    except (OSError, ValueError) as 错误:
        return 结果.失败("参数不合法", str(错误), 来源="浏览器宿主")
