"""前端组件控件原子能力：句柄层级、属性校验、事件绑定与释放。"""
from __future__ import annotations

from typing import Any
from 公共契约.句柄体系 import 句柄体系, 句柄类型_资源
from 公共契约.基础类型.结果类型 import 结果

_句柄体系 = 句柄体系()
_资源: dict[str, dict[str, Any]] = {}
_组件属性 = {
    "文本": "文本", "占位文本": "文本", "左": "整数", "上": "整数",
    "宽度": "整数", "高度": "整数", "可见": "逻辑", "禁用": "逻辑",
    "只读": "逻辑", "能力id": "文本", "参数模板": "字典",
}
_组件类型 = {"标签", "文本", "编辑框", "输入框", "按钮", "标签框", "状态区", "列表框", "容器"}


def _失败(码: str, 说明: str) -> 结果:
    return 结果.失败(码, 说明, 来源="组件控件支持库")


def _校验(句柄id: int, 类型: str) -> tuple[bool, str]:
    句柄 = _句柄体系.句柄表.get(句柄id)
    if 句柄 is None or 句柄.状态 != "有效": return False, "句柄不存在或已失效"
    if 句柄.元数据.get("层级") != 类型: return False, f"需要{类型}句柄"
    return True, ""


def 创建窗口(窗口id: str, 标题: str, 宽度: int = 800, 高度: int = 600,
             项目id: str = "", 所有者: str = "") -> 结果:
    if not isinstance(窗口id, str) or not 窗口id: return _失败("参数不合法", "窗口id不能为空")
    if not isinstance(标题, str) or not 标题: return _失败("参数不合法", "标题不能为空")
    if not isinstance(宽度, int) or 宽度 <= 0 or not isinstance(高度, int) or 高度 <= 0:
        return _失败("参数不合法", "宽度和高度必须为正整数")
    句柄 = _句柄体系.创建句柄(句柄类型=句柄类型_资源, 资源id=f"窗口:{窗口id}", 项目id=项目id, 所有者=所有者)
    句柄.元数据["层级"] = "窗口"; _资源[句柄.句柄id] = {"窗口id":窗口id,"标题":标题,"宽度":宽度,"高度":高度,"页面":[]}
    return 结果.成功结果({"句柄id":句柄.句柄id,"句柄类型":"窗口句柄","窗口id":窗口id})


def 创建页面(窗口句柄: int, 页面id: str, 路由: str = "/", 标题: str = "") -> 结果:
    通过, 说明 = _校验(窗口句柄, "窗口")
    if not 通过: return _失败("句柄不合法", 说明)
    if not isinstance(页面id, str) or not 页面id: return _失败("参数不合法", "页面id不能为空")
    父 = _资源[窗口句柄]; 句柄 = _句柄体系.创建句柄(句柄类型=句柄类型_资源, 资源id=f"页面:{页面id}")
    句柄.元数据.update({"层级":"页面","窗口句柄":窗口句柄}); _资源[句柄.句柄id] = {"页面id":页面id,"路由":路由,"标题":标题 or 页面id,"窗口句柄":窗口句柄,"组件":[]}; 父["页面"].append(句柄.句柄id)
    return 结果.成功结果({"句柄id":句柄.句柄id,"句柄类型":"页面句柄","页面id":页面id,"窗口句柄":窗口句柄})


def 创建组件(页面句柄: int, 组件id: str, 组件类型: str, 属性: dict | None = None) -> 结果:
    通过, 说明 = _校验(页面句柄, "页面")
    if not 通过: return _失败("句柄不合法", 说明)
    if not isinstance(组件id, str) or not 组件id or 组件类型 not in _组件类型: return _失败("参数不合法", "组件id不能为空或组件类型不受支持")
    属性 = dict(属性 or {})
    for 名称, 值 in 属性.items():
        if 名称 not in _组件属性: return _失败("属性不支持", f"组件属性不支持: {名称}")
        if _组件属性[名称] == "整数" and (not isinstance(值, int) or isinstance(值, bool)): return _失败("参数不合法", f"属性 {名称} 必须为整数")
    句柄 = _句柄体系.创建句柄(句柄类型=句柄类型_资源, 资源id=f"组件:{组件id}")
    句柄.元数据.update({"层级":"组件","页面句柄":页面句柄}); _资源[句柄.句柄id] = {"组件id":组件id,"组件类型":组件类型,"属性":属性,"事件":[],"页面句柄":页面句柄}; _资源[页面句柄]["组件"].append(句柄.句柄id)
    return 结果.成功结果({"句柄id":句柄.句柄id,"句柄类型":"组件句柄","组件id":组件id,"页面句柄":页面句柄})


def 设置组件属性(组件句柄: int, 属性名: str, 属性值: Any) -> 结果:
    通过, 说明 = _校验(组件句柄, "组件")
    if not 通过: return _失败("句柄不合法", 说明)
    if 属性名 not in _组件属性: return _失败("属性不支持", f"组件属性不支持: {属性名}")
    if _组件属性[属性名] == "整数" and (not isinstance(属性值, int) or isinstance(属性值, bool)): return _失败("参数不合法", f"属性 {属性名} 必须为整数")
    _资源[组件句柄]["属性"][属性名] = 属性值
    return 结果.成功结果({"句柄id":组件句柄,"属性名":属性名,"属性值":属性值})


def 绑定组件事件(组件句柄: int, 事件名称: str, 能力id: str, 参数模板: dict | None = None) -> 结果:
    通过, 说明 = _校验(组件句柄, "组件")
    if not 通过: return _失败("句柄不合法", 说明)
    if not 事件名称 or not 能力id: return _失败("参数不合法", "事件名称和能力id不能为空")
    事件 = {"名称":事件名称,"能力id":能力id,"参数模板":dict(参数模板 or {})}; 当前 = _资源[组件句柄]["事件"]; 当前[:] = [x for x in 当前 if x["名称"] != 事件名称]; 当前.append(事件)
    return 结果.成功结果(事件)


def 释放句柄(句柄: int = None) -> 结果:
    """释放句柄（幂等）。不存在或已失效一律成功（`状态=未找到且已幂等`）。"""
    if isinstance(句柄, bool) or not isinstance(句柄, int) or not 1 <= 句柄 <= 999999:
        return _失败("参数不合法", "句柄必须是1到999999的整数")
    成功, _说明 = _句柄体系.失效(句柄, "前端组件释放")
    if not 成功:
        return 结果.成功结果({"句柄":句柄,"状态":"未找到且已幂等","已释放":True})
    return 结果.成功结果({"句柄":句柄,"状态":"已释放","已释放":True})
