"""前端组件控件支持库：窗口/页面/组件句柄与属性事件契约。"""
from 支持库.前端.组件控件.实现.组件控件 import (
    创建窗口, 创建页面, 创建组件, 设置组件属性, 绑定组件事件, 释放句柄,
)
from 公共契约.能力契约.契约 import 能力实现

__all__ = ["创建窗口", "创建页面", "创建组件", "设置组件属性", "绑定组件事件", "释放句柄", "注册能力"]


def 注册能力(注册表) -> None:
    """向唯一能力注册表注册组件控件支持库的原子能力。"""
    契约表 = [
        ("组件控件.创建窗口", 创建窗口, [("窗口id", "文本"), ("标题", "文本"), ("宽度", "整数"), ("高度", "整数")]),
        ("组件控件.创建页面", 创建页面, [("窗口句柄", "句柄"), ("页面id", "文本"), ("路由", "文本")]),
        ("组件控件.创建组件", 创建组件, [("页面句柄", "句柄"), ("组件id", "文本"), ("组件类型", "文本"), ("属性", "字典")]),
        ("组件控件.设置组件属性", 设置组件属性, [("组件句柄", "句柄"), ("属性名", "文本"), ("属性值", "任意")]),
        ("组件控件.绑定组件事件", 绑定组件事件, [("组件句柄", "句柄"), ("事件名称", "文本"), ("能力id", "文本"), ("参数模板", "字典")]),
        ("组件控件.释放句柄", 释放句柄, [("句柄id", "整数型")]),
    ]
    返回表 = {
        "组件控件.创建窗口": "结果型<窗口句柄型>",
        "组件控件.创建页面": "结果型<页面句柄型>",
        "组件控件.创建组件": "结果型<组件句柄型>",
        "组件控件.设置组件属性": "结果型",
        "组件控件.绑定组件事件": "结果型<事件定义型>",
        "组件控件.释放句柄": "结果型",
    }
    for 能力id, 函数, 参数表 in 契约表:
        注册表.注册(能力实现(
            能力id=能力id,
            包id="支持库.前端.组件控件",
            实现函数=函数,
            参数=[{"名称": 名称, "类型": 类型} for 名称, 类型 in 参数表],
            返回=返回表[能力id],
            说明="前端组件控件原子能力",
        ))
