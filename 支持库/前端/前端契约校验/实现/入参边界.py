"""能力边界上的入参判定与结论文案（与 能力定义.json 的 空值 / 输入上限 逐条对应）。

判定只有两类，互不混淆：

- **调用方传错**（不是 JSON 对象、含无法序列化的值、超过 256 KB）→ 统一结果失败，
  错误码 `参数不合法`（网关侧同一码 → HTTP 400，见 运行核心/统一网关/本地网关.py
  的 公开错误码状态映射）；
- **描述写错**（对象结构不合 前端核心 口径）→ 不是失败：走 提供者.py 的成功结果
  + `值.有效=假` + `值.问题列表`（结构不合法是校验结论，不是异常；用失败码顶替会让
  调用方分不清「我参数传错了」和「我的页面描述写错了」）。
"""

from __future__ import annotations

import json
from typing import Any

from 公共契约.基础类型.结果类型 import 结果
from 支持库.前端.前端契约校验.实现.结构校验 import 类型名

来源名称 = "前端契约校验"
参数总量上限字节 = 256 * 1024


def 判定入参(名称: str, 值: Any) -> 结果 | None:
    """入参边界判定：可用返回 None，否则返回可直接回带的失败结果。"""
    if not isinstance(值, dict):
        return 结果.失败("参数不合法",
                        f"{名称} 必须是 JSON 对象（字典型），当前是 {类型名(值)}",
                        来源=来源名称)
    try:
        字节数 = len(json.dumps(值, ensure_ascii=False).encode("utf-8"))
    except (TypeError, ValueError) as 错误:
        return 结果.失败("参数不合法", f"{名称} 含无法序列化为 JSON 的值：{错误}",
                        来源=来源名称)
    if 字节数 > 参数总量上限字节:
        return 结果.失败("参数不合法",
                        f"{名称} 共 {字节数} 字节，超过输入上限 {参数总量上限字节} 字节",
                        来源=来源名称)
    return None


def 结论(契约名: str, 问题列表: list[str], 附注: str = "") -> str:
    """校验结论原文（给人读的一句），与 问题列表 同源、不另算一遍。"""
    if 问题列表:
        return f"{契约名}结构不合法：共 {len(问题列表)} 处问题（逐条见 问题列表）"
    return f"{契约名}结构合法：字段、类型与枚举取值均符合 前端核心 口径{附注}"
