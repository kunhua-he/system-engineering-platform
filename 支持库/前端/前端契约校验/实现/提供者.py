"""前端契约校验包的实现层：四条公开能力的唯一实现（边界校验 + 结果归一）。

能力：校验页面定义 / 校验渲染请求 / 校验执行单元声明 / 查询前端契约清单。
调用方（发布门禁、前端宿主、轻代码编辑器、Agent）只经唯一能力调用入口按能力 id
调用，不得 import 本模块；包级中文入口（同包 `__init__.py`）的 `注册能力(注册表)`
从这里取实现函数。

分工（本包不复制 前端核心 的判定逻辑）：
- `契约口径.py`：字段与枚举口径表（语义来源 `前端核心/前端核心.py` 的五个数据类）；
- `结构校验.py`：逐字段结构校验，出「字段路径 + 原因」问题列表；
- `入参边界.py`：入参类型/体积判定与结论文案；
- 本模块：四条能力的边界串接与统一结果归一。

四条能力均为纯计算、幂等、不写盘、不依赖调用顺序（并发的线程与进程安全）。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.基础类型.结果类型 import 结果
from 支持库.前端.前端契约校验.实现.契约口径 import (
    宿主类型取值, 渲染方式取值, 组件类型取值, 契约必填表, 契约字段表, 契约名表, 窗口状态取值,
)
from 支持库.前端.前端契约校验.实现.结构校验 import 计数列表, 校验结构
from 支持库.前端.前端契约校验.实现.入参边界 import 判定入参, 结论


def 校验页面定义(页面定义: Any = None) -> 结果:
    """校验页面定义字典（页面id/路由/标题/组件列表与组件字段）；问题逐条回带。"""
    失败 = 判定入参("页面定义", 页面定义)
    if 失败 is not None:
        return 失败
    问题列表 = 校验结构("页面定义", 页面定义)
    组件数 = 计数列表(页面定义.get("组件列表"))
    return 结果.成功结果({
        "有效": 假 if 问题列表 else 真,
        "说明": 结论("页面定义", 问题列表, f"，组件 {组件数} 条"),
        "问题列表": 问题列表,
        "组件数": 组件数,
    })


def 校验渲染请求(渲染请求: Any = None) -> 结果:
    """校验渲染请求字典（窗口id/标题/状态表/宿主类型）；不启动任何渲染。"""
    失败 = 判定入参("渲染请求", 渲染请求)
    if 失败 is not None:
        return 失败
    问题列表 = 校验结构("渲染请求", 渲染请求)
    return 结果.成功结果({
        "有效": 假 if 问题列表 else 真,
        "说明": 结论("渲染请求", 问题列表),
        "问题列表": 问题列表,
    })


def 校验执行单元声明(执行单元声明: Any = None) -> 结果:
    """校验执行单元声明（执行单元id/宿主类型/渲染方式/四类资源与依赖列表）。"""
    失败 = 判定入参("执行单元声明", 执行单元声明)
    if 失败 is not None:
        return 失败
    问题列表 = 校验结构("执行单元声明", 执行单元声明)
    return 结果.成功结果({
        "有效": 假 if 问题列表 else 真,
        "说明": 结论("执行单元声明", 问题列表),
        "问题列表": 问题列表,
    })


def 查询前端契约清单() -> 结果:
    """查询前端核心契约清单（只读）：契约字段表与四张枚举取值表，供调用方自检。"""
    契约清单 = [
        {
            "契约名": 契约名,
            "必填字段": list(契约必填表[契约名]),
            "可选字段": [字段 for 字段, _形态, _枚举 in 契约字段表[契约名]
                     if 字段 not in 契约必填表[契约名]],
        }
        for 契约名 in 契约名表
    ]
    return 结果.成功结果({
        "契约清单": 契约清单,
        "枚举表": {
            "组件类型": list(组件类型取值),
            "宿主类型": list(宿主类型取值),
            "渲染方式": list(渲染方式取值),
            "窗口状态": list(窗口状态取值),
        },
        "数量": len(契约清单),
    })
