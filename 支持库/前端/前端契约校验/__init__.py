def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本包的公开能力。

    参数名与顺序与 `能力定义.json` / `能力契约/参数契约.json` 逐条一致
    （`公共契约/能力契约/契约.py` 的 `声明一致` 与 `开发工具/契约编译/漂移检测.py`
    的注册口径子检测都按同一口径比对）。
    """
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数表, 说明 in [
        (
            "支持库.前端.前端契约校验.校验页面定义",
            校验页面定义,
            [{"名称": "页面定义", "类型": "字典型", "必填": 真}],
            "校验页面定义字典的结构合法性（页面id/路由/标题/组件列表与组件字段）。",
        ),
        (
            "支持库.前端.前端契约校验.校验渲染请求",
            校验渲染请求,
            [{"名称": "渲染请求", "类型": "字典型", "必填": 真}],
            "校验渲染请求字典的结构合法性（窗口id/标题/状态表/宿主类型）。",
        ),
        (
            "支持库.前端.前端契约校验.校验执行单元声明",
            校验执行单元声明,
            [{"名称": "执行单元声明", "类型": "字典型", "必填": 真}],
            "校验前端执行单元声明的结构合法性（执行单元id/宿主类型/渲染方式/四类资源与依赖列表）。",
        ),
        (
            "支持库.前端.前端契约校验.查询前端契约清单",
            查询前端契约清单,
            [],
            "查询前端核心契约清单（只读）：五个契约的必填字段与枚举取值表。",
        ),
    ]:
        注册表.注册(能力实现(
            能力id=能力id,
            包id=包id,
            实现函数=函数,
            参数=参数表,
            返回="结果",
            说明=说明,
            版本=版本,
            提供者id=包id,
            提供者版本=版本,
        ))
