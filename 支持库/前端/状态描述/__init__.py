"""状态描述支持库包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：创建窗口状态/状态流转校验。
"""

from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现
from 支持库.前端.状态描述.实现.状态描述 import 创建窗口状态
from 支持库.前端.状态描述.实现.状态描述 import 状态流转校验

__all__ = [
    "创建窗口状态",
    "状态流转校验",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库全部能力。"""
    契约表 = [
        ("状态描述.创建窗口状态", 创建窗口状态,
         [("窗口id", "文本"), ("初始状态", "文本")]),
        ("状态描述.状态流转校验", 状态流转校验,
         [("当前状态", "文本"), ("目标状态", "文本")]),
    ]
    for 能力id, 函数, 参数类型表 in 契约表:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.前端.状态描述",
                实现函数=函数,
                参数=[
                    {"名称": 参数名, "类型": 类型}
                    for 参数名, 类型 in 参数类型表
                ],
                返回="结果",
                说明="前端描述模型能力",
            )
        )
