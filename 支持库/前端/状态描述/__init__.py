"""状态描述支持库包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：创建窗口状态/状态流转校验。
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 公共契约.能力契约.契约 import 能力实现
from 支持库.前端.状态描述.实现.状态描述 import 创建窗口状态
from 支持库.前端.状态描述.实现.状态描述 import 状态流转校验

__all__ = [
    "创建窗口状态",
    "状态流转校验",
]

def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库全部能力。"""
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 参数契约镜像（**函数内字面量**；本块由「丢参」缺陷修复注入，勿删）
    #
    # 缺陷溯源（2026-09-18）：本入口原先手工重建注册参数声明（只写 名称/类型），把
    # `必填` 丢掉；而网关唯一校验点 `运行核心/统一网关/协议/类型规格.py` 的判据是
    # `项.get("必填") is 真` → `None is 真` = 假 → 必填校验静默失效：少传参数不再被
    # 网关拦下，直接落进实现体抛 TypeError，用户拿到 HTTP 500 而不是干净的 400
    # 「缺少必填参数 X」。修法：参数声明从 `能力契约/参数契约.json` **整条透传**
    # （`参数=_参数契约表[能力id]`），入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：
    #  ① `_参数契约表` 是字面量、键是常量，`开发工具/契约编译/漂移检测` 的 AST 读取器
    #     （`_静态字面量` 的 `ast.Subscript` 分支）能解析出**整条参数含 `必填`** ——
    #     改前那处「参数口径未解析」不因本次修复恶化，反而把读不到的 `必填` 读到了。
    #     放在函数内是因为该读取器只收 `注册能力` 函数体内的赋值（`_扫描注册语句`）。
    #  ② 「裸布尔」防回潮门禁**已把 `必填`/`默认值` 计入违规**（本文件已迁为 真/假），改回裸 True/False 即判红。
    # 表内布尔位写**中文 `真`／`假`**（正式口径，真源 `公共契约/基础类型/逻辑类型.py`）；
    # 本文件顶部已 import 真/假，漂移检测读取器（`_导入常量绑定`）能静态解析出参数表，
    # （契约写了的键才留，没写的不补），不给漂移检测造出「注册声明了契约没声明的默认值」。
    # 为什么按下标取而不是包一层 `_参数声明(能力id)`：包一层会让 AST 一律判「不可静态
    # 判定」，等于拿门禁覆盖率换干净（不可接受）。契约名序/返回口径核验由装配期唯一闸门承担
    # （`运行核心/加载器/生命周期管理/管理器.装配系统` → 内核 `能力注册表.校验声明一致`），本入口不再另立第二份。
    _参数契约表 = {
        "状态描述.创建窗口状态": [
            {"名称": "窗口id", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "初始状态", "类型": "文本型", "必填": 真, "默认值": None},
        ],
        "状态描述.状态流转校验": [
            {"名称": "当前状态", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "目标状态", "类型": "文本型", "必填": 真, "默认值": None},
        ],
    }
# ===== 参数声明透传 结束 =====
    契约表 = [
        ("状态描述.创建窗口状态", 创建窗口状态),
        ("状态描述.状态流转校验", 状态流转校验),
    ]
    for 能力id, 函数 in 契约表:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.前端.状态描述",
                实现函数=函数,
                参数=_参数契约表[能力id],
                返回="结果型",
                说明="前端描述模型能力",
            )
        )
