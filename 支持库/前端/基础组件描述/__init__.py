"""基础组件描述包级中文入口。"""

from __future__ import annotations

from 支持库.前端.基础组件描述.实现.基础组件描述 import 创建组件定义
from 支持库.前端.基础组件描述.实现.基础组件描述 import 校验组件属性
from 支持库.前端.基础组件描述.实现.基础组件描述 import 声明事件

__all__ = [
    "创建组件定义",
    "校验组件属性",
    "声明事件",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型 in [
        ("基础组件描述.创建组件定义", 创建组件定义, ['组件id', '组件类型', '属性'], "结果"),
        ("基础组件描述.校验组件属性", 校验组件属性, ['组件定义'], "结果"),
        ("基础组件描述.声明事件", 声明事件, ['组件定义', '事件名称'], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.前端.基础组件描述",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回=返回类型,
                说明="前端描述模型能力",
            )
        )
