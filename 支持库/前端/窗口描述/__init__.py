# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
# 缺陷溯源（2026-09-18）：本入口原先手工重建注册参数表（只写 名称/类型），把 `必填`
# 丢掉；而网关唯一校验点 `运行核心/统一网关/类型规格.py` 的判据是 `项.get("必填") is 真`
# → `None is 真` = 假 → 必填校验静默失效：少传参数不再被网关拦下，直接落进实现体抛
# TypeError，用户拿到 HTTP 500 而不是干净的 400「缺少必填参数 X」。修法：参数声明从
# `能力契约/参数契约.json` **整条透传**，入口不再另立第二套事实源（哲学 12.1）。
#
# 为什么用**模块级字面量**而不是「运行时读 JSON」：字面量让 开发工具/契约编译/漂移检测
# 的 AST 读取器与「裸布尔」防回潮门禁都能看见 `必填`（改前那处「参数口径未解析」不因
# 本次修复恶化）；并让 真/假 落在入口文件里，运行期口径仍只有一处。表内 True/False 是
# 契约 JSON 的原值镜像（JSON 无 真/假 字面量），`_参数声明` 交给注册表前按
# 公共契约.基础类型.逻辑类型 归一。
from 公共契约.基础类型.逻辑类型 import 真, 假
_参数契约表: dict[str, list[dict]] = {
    "窗口描述.创建窗口定义": [
        {"名称": "窗口id", "类型": "文本型", "必填": True, "默认值": None, "说明": "窗口唯一标识"},
        {"名称": "标题", "类型": "文本型", "必填": True, "默认值": None, "说明": "窗口标题"},
        {"名称": "宽度", "类型": "整数型", "必填": True, "默认值": None, "说明": "窗口宽度像素（正整数）"},
        {"名称": "高度", "类型": "整数型", "必填": True, "默认值": None, "说明": "窗口高度像素（正整数）"},
    ],
    "窗口描述.反序列化窗口定义": [
        {"名称": "文本", "类型": "文本型", "必填": True, "默认值": None, "说明": "窗口定义的 JSON 文本"},
    ],
    "窗口描述.序列化窗口定义": [
        {"名称": "窗口定义", "类型": "字典型", "必填": True, "默认值": None, "说明": "待序列化的窗口定义字典"},
    ],
    "窗口描述.校验窗口定义": [
        {"名称": "窗口定义", "类型": "字典型", "必填": True, "默认值": None, "说明": "待校验的窗口定义字典"},
    ],
}
_参数名序表: dict[str, list[str]] = {
    "窗口描述.创建窗口定义": ["窗口id", "标题", "宽度", "高度"],
    "窗口描述.反序列化窗口定义": ["文本"],
    "窗口描述.序列化窗口定义": ["窗口定义"],
    "窗口描述.校验窗口定义": ["窗口定义"],
}

_参数声明缓存: dict[str, list[dict]] = {}


def _参数声明(能力id: str, 参数名序: list[str] | None = None) -> list[dict]:
    """按契约整条透传参数声明（名称/类型/必填/默认值/说明）；给名序时同时守名序。"""
    契约参数 = _参数契约表.get(能力id)
    if 契约参数 is None:
        raise ValueError(f"能力 {能力id} 不在 能力契约/参数契约.json 的能力契约里")
    if 参数名序 is None:
        参数名序 = _参数名序表[能力id]
    if [参数.get("名称") for 参数 in 契约参数] != list(参数名序):
        raise ValueError(
            f"能力 {能力id} 注册参数名序 {list(参数名序)} 与契约参数名序 "
            f"{[参数.get('名称') for 参数 in 契约参数]} 不一致：参数事实源只有 "
            "能力契约/参数契约.json 一处（哲学 12.1），入口不得另立一份")
    缓存 = _参数声明缓存.get(能力id)
    if 缓存 is None:
        缓存 = []
        for 参数 in 契约参数:
            项 = dict(参数)
            if "必填" in 项:
                项["必填"] = 真 if 项["必填"] else 假
            缓存.append(项)
        _参数声明缓存[能力id] = 缓存
    return 缓存

# ===== 参数声明透传 结束 =====

def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库全部能力。"""
    契约表 = [
        ("窗口描述.创建窗口定义", 创建窗口定义),
        ("窗口描述.校验窗口定义", 校验窗口定义),
        ("窗口描述.序列化窗口定义", 序列化窗口定义),
        ("窗口描述.反序列化窗口定义", 反序列化窗口定义),
    ]
    for 能力id, 函数 in 契约表:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.前端.窗口描述",
                实现函数=函数,
                参数=_参数声明(能力id),
                返回="结果型",
                说明="前端描述模型能力",
            )
        )
