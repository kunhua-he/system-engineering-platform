from __future__ import annotations

from 支持库.前端.窗口描述.实现.窗口描述 import 创建窗口定义
from 支持库.前端.窗口描述.实现.窗口描述 import 校验窗口定义
from 支持库.前端.窗口描述.实现.窗口描述 import 序列化窗口定义
from 支持库.前端.窗口描述.实现.窗口描述 import 反序列化窗口定义

__all__ = [
    "创建窗口定义",
    "校验窗口定义",
    "序列化窗口定义",
    "反序列化窗口定义",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型 in [
        ("窗口描述.创建窗口定义", 创建窗口定义, ['窗口id', '标题', '宽度', '高度'], "结果"),
        ("窗口描述.校验窗口定义", 校验窗口定义, ['窗口定义'], "结果"),
        ("窗口描述.序列化窗口定义", 序列化窗口定义, ['窗口定义'], "结果"),
        ("窗口描述.反序列化窗口定义", 反序列化窗口定义, ['文本'], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.前端.窗口描述",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回=返回类型,
                说明="前端描述模型能力",
            )
        )
