"""文件选择描述包级中文入口。"""

from __future__ import annotations

from 支持库.前端.文件选择描述.实现.文件选择描述 import 创建文件选择描述
from 支持库.前端.文件选择描述.实现.文件选择描述 import 校验文件选择描述

__all__ = [
    "创建文件选择描述",
    "校验文件选择描述",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型 in [
        ("文件选择描述.创建文件选择描述", 创建文件选择描述, ['允许扩展名列表', '多选'], "结果"),
        ("文件选择描述.校验文件选择描述", 校验文件选择描述, ['文件选择描述'], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.前端.文件选择描述",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回=返回类型,
                说明="前端描述模型能力",
            )
        )
