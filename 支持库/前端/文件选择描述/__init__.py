"""文件选择描述支持库包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：创建文件选择描述/校验文件选择描述。
"""

from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现
from 支持库.前端.文件选择描述.实现.文件选择描述 import 创建文件选择描述
from 支持库.前端.文件选择描述.实现.文件选择描述 import 校验文件选择描述

__all__ = [
    "创建文件选择描述",
    "校验文件选择描述",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库全部能力。"""
    契约表 = [
        ("文件选择描述.创建文件选择描述", 创建文件选择描述,
         [("允许扩展名列表", "列表"), ("多选", "布尔")]),
        ("文件选择描述.校验文件选择描述", 校验文件选择描述,
         [("文件选择描述", "字典")]),
    ]
    for 能力id, 函数, 参数类型表 in 契约表:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.前端.文件选择描述",
                实现函数=函数,
                参数=[
                    {"名称": 参数名, "类型": 类型}
                    for 参数名, 类型 in 参数类型表
                ],
                返回="结果",
                说明="前端描述模型能力",
            )
        )
