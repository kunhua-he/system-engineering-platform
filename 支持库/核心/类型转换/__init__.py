"""易语言式基础类型转换原子能力。"""

from 公共契约.能力契约.契约 import 能力实现
from 支持库.核心.类型转换.实现.类型转换 import (
    文本转整数, 文本转长整数, 整数转文本, 长整数转文本,
    文本转单精度数, 文本转双精度数, 数值转文本, 逻辑转文本,
    文本转逻辑, 校验类型,
)

def 注册能力(注册表) -> None:
    能力表 = (
        ("类型转换.文本转整数", 文本转整数, [("文本", "文本型"), ("进制", "整数型")]),
        ("类型转换.文本转长整数", 文本转长整数, [("文本", "文本型"), ("进制", "整数型")]),
        ("类型转换.整数转文本", 整数转文本, [("整数", "整数型")]),
        ("类型转换.长整数转文本", 长整数转文本, [("长整数", "长整数型")]),
        ("类型转换.文本转单精度数", 文本转单精度数, [("文本", "文本型")]),
        ("类型转换.文本转双精度数", 文本转双精度数, [("文本", "文本型")]),
        ("类型转换.数值转文本", 数值转文本, [("数值", "双精度数型"), ("小数位数", "整数型")]),
        ("类型转换.逻辑转文本", 逻辑转文本, [("逻辑值", "逻辑型")]),
        ("类型转换.文本转逻辑", 文本转逻辑, [("文本", "文本型")]),
        ("类型转换.校验类型", 校验类型, [("值", "字典型"), ("目标类型", "文本型")]),
    )
    for 能力id, 函数, 参数 in 能力表:
        注册表.注册(能力实现(
            能力id=能力id, 包id="支持库.核心.类型转换",
            实现函数=函数,
            参数=[{"名称": 名称, "类型": 类型} for 名称, 类型 in 参数],
            返回="结果型", 说明="核心类型转换原子能力",
        ))

__all__ = ["注册能力", "文本转整数", "文本转长整数", "整数转文本", "长整数转文本",
           "文本转单精度数", "文本转双精度数", "数值转文本", "逻辑转文本", "文本转逻辑", "校验类型"]
