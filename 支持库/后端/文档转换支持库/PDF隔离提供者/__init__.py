from 支持库.后端.文档转换支持库.PDF隔离提供者.实现.隔离提供者 import 检查提供者版本

__all__ = [
    "解析PDF隔离",
    "校验PDF隔离",
    "检查提供者版本",
    "注册能力",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数, 说明 in [
        ("文档转换支持库.PDF隔离提供者.解析PDF", 解析PDF隔离,
         [{"名称": "文件路径", "类型": "文本型", "必填": True, "默认值": None},
          {"名称": "最大页数", "类型": "整数型", "必填": False, "默认值": 500},
          {"名称": "最大字节数", "类型": "整数型", "必填": False, "默认值": 0},
          {"名称": "超时秒", "类型": "双精度数型", "必填": False, "默认值": 90}],
         "隔离解析 PDF 为通用文档字典（块列表/资源列表/标题/警告）"),
        ("文档转换支持库.PDF隔离提供者.校验PDF", 校验PDF隔离,
         [{"名称": "字节", "类型": "字节集型", "必填": True, "默认值": None},
          {"名称": "超时秒", "类型": "双精度数型", "必填": False, "默认值": 30}],
         "隔离重新打开 PDF 返回页数（生成签名校验用）"),
        ("文档转换支持库.PDF隔离提供者.检查提供者", 检查提供者版本,
         [{"名称": "超时秒", "类型": "双精度数型", "必填": False, "默认值": 30}],
         "隔离探测 pdfplumber/fitz 版本与可用性"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文档转换支持库.PDF隔离提供者",
                实现函数=函数,
                参数=参数,
                返回="结果型",
                说明=说明,
            )
        )
