"""python_docx提供者 包级中文入口（主进程直接加载 python-docx）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 文字文档）：
- 解析文字文档 → DOCX → 通用文档字典（段落/表格/图像）；OOXML 不可信 ZIP 校验
- 生成文字文档 → 内容参数 → DOCX 字节（生成产物字典）
python-docx 为纯 Python 库，主进程 import，不启用子进程隔离。
"""

from __future__ import annotations

from 支持库.后端.文档转换支持库.python_docx提供者.实现.文字文档 import 解析文字文档
from 支持库.后端.文档转换支持库.python_docx提供者.实现.文字文档 import 生成文字文档

__all__ = ["解析文字文档", "生成文字文档", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 文字文档）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        # Provider 仅注册内部实现能力；公开 owner 在 支持库/后端/文字文档。
        ("内部.文字文档.解析", 解析文字文档,
         [{"名称": "文件路径", "类型": "文本型", "必填": True},
          {"名称": "格式", "类型": "文本型", "必填": False, "默认值": "docx"},
          {"名称": "最大字节数", "类型": "整数型", "必填": False, "默认值": 209715200},
          {"名称": "超时秒", "类型": "双精度数型", "必填": False, "默认值": 60}],
         "python-docx 内部 DOCX 解析实现，仅供文字文档后端调用"),
        ("内部.文字文档.生成", 生成文字文档,
         [{"名称": "内容参数", "类型": "字典型", "必填": True, "默认值": None}],
         "python-docx 内部 DOCX 生成实现，仅供文档生成后端调用"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文档转换支持库.python_docx提供者",
                实现函数=函数,
                参数=参数名,
                返回="结果型",
                说明=说明,
            )
        )
