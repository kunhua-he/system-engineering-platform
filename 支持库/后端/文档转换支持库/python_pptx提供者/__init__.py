"""python-pptx 提供者包级中文入口（目录名含连字符，实现按文件路径加载）。

调用者只从此入口导入 解析演示文稿 / 生成演示文稿；禁止深入 实现/ 目录。
公开能力（分组 演示文稿）：
- 解析演示文稿 → pptx → 结果[通用文档]（幻灯片块/备注/图像资源）
- 生成演示文稿 → 幻灯片列表 → 结果[生成产物字典]（字节b64/媒体类型/摘要）
python-pptx 纯 Python，主进程 import；OOXML 按不可信 ZIP 处理。
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

_实现路径 = Path(__file__).resolve().parent / "实现" / "演示文稿.py"
_规格 = importlib.util.spec_from_file_location("python_pptx提供者_实现", _实现路径)
_实现 = importlib.util.module_from_spec(_规格)
_规格.loader.exec_module(_实现)

解析演示文稿 = _实现.解析演示文稿
生成演示文稿 = _实现.生成演示文稿

__all__ = ["解析演示文稿", "生成演示文稿", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 演示文稿）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        # Provider 仅注册内部实现能力；公开 owner 在后端支持库。
        ("内部.演示文稿.解析", 解析演示文稿,
         [{"名称": "文件路径", "类型": "文本型", "必填": True},
          {"名称": "格式", "类型": "文本型", "必填": False, "默认值": ""},
          {"名称": "最大幻灯片数", "类型": "整数型", "必填": False, "默认值": 200},
          {"名称": "最大字节数", "类型": "整数型", "必填": False, "默认值": 209715200},
          {"名称": "超时秒", "类型": "双精度数型", "必填": False, "默认值": 60}],
         "python-pptx 内部 PPTX 解析实现，仅供演示文稿后端调用"),
        ("内部.演示文稿.生成", 生成演示文稿,
         [{"名称": "内容参数", "类型": "字典型", "必填": True, "默认值": None}],
         "python-pptx 内部 PPTX 生成实现，仅供文档生成后端调用"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文档转换支持库.python_pptx提供者",
                实现函数=函数,
                参数=参数名,
                返回="结果型",
                说明=说明,
            )
        )
