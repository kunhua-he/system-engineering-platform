"""openpyxl 独立提供者包级中文入口（主进程直接 import openpyxl，纯 Python）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 表格文档）：
- 解析表格文档 → XLSX → 通用文档字典（工作表块/表格数据）；OOXML 不可信 ZIP 校验
- 生成表格文档 → 内容参数 → XLSX 字节（生成产物字典：字节b64/媒体类型/摘要）
openpyxl 代码全部收拢在本提供者目录，支持库后端不再直接触碰 openpyxl。
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.后端.文档转换支持库.openpyxl提供者.实现.表格文档 import 解析表格文档
from 支持库.后端.文档转换支持库.openpyxl提供者.实现.表格文档生成 import 生成表格文档

__all__ = ["解析表格文档", "生成表格文档", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 表格文档）。"""
    from 公共契约.能力契约.契约 import 能力实现
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 缺陷溯源：本入口原先手工重建注册参数声明（`参数=...` 手写字面量），只写 名称/类型/必填，
    # `默认值` 整批缺声明（2026-09-24 实测：本包 6 条契约参数中 3 条漏声明，
    # 全仓 93 条）。后果：网关按入口契约表判参时拿不到默认值 —— 「≥10 秒须走异步腿」的守卫
    # 对 超时秒≥10 的能力**不传参即被绕过**（实测 执行命令/沙箱执行命令/发送请求 等 9 条）；
    # 其余能力的默认值同样在网关侧不可见。
    # 手工表一旦漏一个参数，新参数还会被网关**静默丢弃**（同族现场见未完成事项 #197）。
    # 修法：参数声明从 `能力契约/参数契约.json` **整条透传**，入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：漂移检测的 AST 读取器
    # （`_静态字面量` 的 `ast.Subscript` 分支）只收 `注册能力` 函数体内的赋值，
    # 包一层 `_参数声明(能力id)` 会让 AST 一律判「不可静态判定」，等于拿门禁覆盖率换干净。
    # 表内布尔位写中文 真/假（真源 公共契约/基础类型/逻辑类型.py）。
    # 契约名序/返回口径核验由装配期唯一闸门承担（`运行核心/加载器/生命周期管理/管理器.装配系统`
    # → 内核 `能力注册表.校验声明一致`），本入口不再另立第二份。
    _参数契约表 = {
        "内部.表格文档.解析": [
            {"名称": "文件路径", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "数据模式", "类型": "逻辑型", "必填": 假, "默认值": 真},
            {"名称": "最大工作表数", "类型": "整数型", "必填": 假, "默认值": 50},
            {"名称": "最大行数", "类型": "整数型", "必填": 假, "默认值": 200000},
            {"名称": "最大字节数", "类型": "整数型", "必填": 假, "默认值": 209715200},
        ],
        "办公文档支持库.表格文档.生成表格文档": [
            {"名称": "内容参数", "类型": "字典型", "必填": 真, "默认值": None},
        ],
    }
# ===== 参数声明透传 结束 =====

    for 能力id, 函数, 说明 in [
        # 解析实现是后端公开能力的受管内部 owner；使用内部 id 避免
        # Provider 重新声明“办公文档支持库.表格文档.解析表格文档”造成公开 owner 冲突。
        ("内部.表格文档.解析", 解析表格文档, "内部 XLSX 解析实现；仅供支持库后端调用，不是公开能力 owner"),
        ("办公文档支持库.表格文档.生成表格文档", 生成表格文档, "按 内容参数（工作表列表：表名/行列表）生成 xlsx，返回 结果[生成产物字典]（字节b64/媒体类型/摘要）"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文档转换支持库.openpyxl提供者",
                实现函数=函数,
                参数=_参数契约表[能力id],
                返回="结果型",
                说明=说明,
            )
        )
