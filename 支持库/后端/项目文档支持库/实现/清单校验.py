"""项目文档支持库 · 清单校验原子能力（进程内实现，不对外暴露）。

只读校验 markdown 表格清单的结构与唯一性，返回真实问题清单。
**不修不改**：报出问题即职责结束，修复由维护者决定（能力不替人拍板）。

问题 id 一览（与治理方案 11.2 的措辞对齐）：

| 问题id | 含义 |
|---|---|
| 非表格正文 | 没找到「表头行 + 分隔行」，不是清单 |
| 缺列 | 某行的列数与表头不一致 |
| 编号列缺失 | 表头里没有指定编号列，退化为第一列也找不到 |
| 编号为空 | 编号单元格为空 |
| 编号格式不符 | 编号不满足调用方给的 编号模式（不给则不判格式，只判空与重复） |
| 编号重复 | 同一编号出现两次以上（编号不复用） |
| 必填列为空 | 指定必填列的单元格为空 |
"""

from __future__ import annotations

from typing import Any

import re

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.项目文档支持库.实现.清单 import _拆列, _结构, 编号列序


def _问题(问题id: str, 说明: str, 行号: int = 0) -> dict[str, Any]:
    return {"问题id": 问题id, "严重级": "违规", "说明": 说明, "行号": 行号}


def _编号问题(表头: list[str], 数据行: list[tuple[int, list[str]]], 编号列: str,
          编号模式: str) -> list[dict]:
    """编号列定位 / 空 / 格式（给了模式才判）/ 唯一性（编号不复用）。

    格式判据**不硬编在代码里**：体例规范第七节的「四位递增」只约束决策记录，
    其他文档的清单编号形态各不相同（实测 未完成事项.md 用「1/2/3/—」），
    硬编四位会对着合法清单误报——故格式口径由调用方以 编号模式 传入。
    """
    问题列表: list[dict] = []
    if 编号列 and 编号列 in 表头:
        序 = 表头.index(编号列)
    elif 编号列:
        问题列表.append(_问题("编号列缺失", f"表头中没有编号列「{编号列}」，退化为第一列判定"))
        序 = 编号列序
    else:
        序 = 编号列序
    见过: dict[str, int] = {}
    for 行号, 格们 in 数据行:
        值 = 格们[序].strip() if 序 < len(格们) else ""
        if not 值:
            问题列表.append(_问题("编号为空", "编号单元格为空", 行号))
            continue
        if 编号模式 and not re.match(编号模式, 值):
            问题列表.append(_问题("编号格式不符", f"编号「{值}」不匹配模式 {编号模式}", 行号))
        if 值 in 见过:
            问题列表.append(_问题("编号重复", f"编号「{值}」与第 {见过[值]} 行重复（编号不复用）", 行号))
        else:
            见过[值] = 行号
    return 问题列表


def 校验清单(正文: str = None, 必填列=None, 编号列: str = "编号",
            编号模式: str = "") -> 结果:
    """校验 markdown 表格清单：编号唯一性 / 编号格式 / 必填列非空 / 表格结构完整。

    参数：正文（清单文本）；必填列（列名列表或逗号分隔列名，缺省为空）；
    编号列（编号所在列名，默认「编号」；表头无此列时退化为第一列并报「编号列缺失」）；
    编号模式（可选的编号正则，给了才判格式——口径由调用方给，不硬编四位）。
    返回：``{通过, 问题列表, 条目数, 表头}``；**非表格文本如实报告**：
    报「非表格正文」并把 通过 置假，不假装通过。
    """
    if not isinstance(正文, str) or not 正文.strip():
        return 结果.失败("参数不合法", "正文必须是非空文本", 来源="项目文档支持库")
    if isinstance(必填列, str):
        必填列表 = [列.strip() for 列 in 必填列.split(",") if 列.strip()]
    elif isinstance(必填列, (list, tuple)):
        必填列表 = [str(列).strip() for 列 in 必填列 if str(列).strip()]
    elif 必填列 is None:
        必填列表 = []
    else:
        return 结果.失败("参数不合法", "必填列必须是列名列表或逗号分隔文本",
                     来源="项目文档支持库")
    编号列名 = 编号列 if isinstance(编号列, str) else "编号"
    模式 = 编号模式 if isinstance(编号模式, str) else ""
    if 模式:
        try:
            re.compile(模式)
        except re.error as 异常:
            return 结果.失败("参数不合法", f"编号模式不是合法正则: {异常}",
                         来源="项目文档支持库")

    结构 = _结构(正文)
    if 结构 is None:
        return 结果.成功结果({
            "通过": False,
            "问题列表": [_问题("非表格正文", "未识别到 Markdown 表格清单（需表头行 + 分隔行）")],
            "条目数": 0,
            "表头": [],
        })
    行们, 表头, _, 数据行序 = 结构
    数据行 = [(行号, _拆列(行们[行号 - 1])) for 行号 in 数据行序]
    问题列表 = _编号问题(表头, 数据行, 编号列名, 模式)

    for 行号, 格们 in 数据行:
        if len(格们) != len(表头):
            问题列表.append(_问题("缺列",
                            f"该行 {len(格们)} 列，表头 {len(表头)} 列", 行号))
    for 列名 in 必填列表:
        if 列名 not in 表头:
            问题列表.append(_问题("缺列", f"必填列「{列名}」不在表头中"))
            continue
        序 = 表头.index(列名)
        for 行号, 格们 in 数据行:
            if 序 >= len(格们) or not 格们[序].strip():
                问题列表.append(_问题("必填列为空", f"必填列「{列名}」为空", 行号))

    问题列表.sort(key=lambda 项: (项["行号"], 项["问题id"]))
    return 结果.成功结果({
        "通过": not 问题列表,
        "问题列表": 问题列表,
        "条目数": len(数据行),
        "表头": 表头,
    })
