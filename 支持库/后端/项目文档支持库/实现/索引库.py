def 建索引库(库文件: str = None) -> 结果:
    """初始化项目文档索引库（三表 + 两个高频索引），重复调用保持幂等。

    参数：库文件（绝对路径；留空取运行数据根/项目文档库.db）
    返回：``{库文件, 已初始化, 表清单}``
    """
    try:
        with _连接(库文件) as 连接:
            表清单 = [行[0] for 行 in 连接.execute(
                "SELECT name FROM sqlite_master WHERE type='table' ORDER BY name")]
        return 结果.成功结果({"库文件": str(_库路径(库文件)), "已初始化": True, "表清单": 表清单})
    except ValueError as 错误:
        return 结果.失败("参数不合法", str(错误), 来源="项目文档支持库")
    except sqlite3.Error as 错误:
        return 结果.失败("索引库不可用", f"初始化失败: {错误}", 来源="项目文档支持库")


def 写入索引(项目名: str = None, 文档相对路径: str = None, 块列表: list = None,
            文件修改时间: float = 0, 库文件: str = None) -> 结果:
    """写入或更新一个文档的索引（文档级 + 块级），同项目同路径覆盖更新。

    参数：项目名 / 文档相对路径 / 块列表（切块结果）/ 文件修改时间 / 库文件
    返回：``{项目名, 文档相对路径, 块数, 标题, 段数}``
    """
    if not isinstance(项目名, str) or not 项目名.strip():
        return 结果.失败("参数不合法", "项目名必须是非空文本", 来源="项目文档支持库")
    if not isinstance(文档相对路径, str) or not 文档相对路径.strip():
        return 结果.失败("参数不合法", "文档相对路径必须是非空文本", 来源="项目文档支持库")
    if not isinstance(块列表, list):
        return 结果.失败("参数不合法", "块列表必须是列表", 来源="项目文档支持库")
    规范块 = []
    for 块 in 块列表:
        if not isinstance(块, dict):
            return 结果.失败("参数不合法", "块列表每项必须是对象", 来源="项目文档支持库")
        规范块.append((
            int(块.get("起始行") or 0), int(块.get("结束行") or 0),
            str(块.get("块类型") or "段落"), str(块.get("块文本") or "")))
    标题 = next((t[3].split("\n")[0].lstrip("# ").strip() for t in 规范块 if t[2] == "标题"), "")
    正文块 = [t for t in 规范块 if t[2] not in ("空行",)]
    段数 = len(正文块)
    字节数 = sum(len(t[3].encode("utf-8")) for t in 规范块)
    摘要 = " ".join(t[3].replace("\n", " ") for t in 正文块)[:400]

    try:
        import time
        with _连接(库文件) as 连接:
            连接.execute("DELETE FROM 块索引 WHERE 项目名=? AND 文档相对路径=?", (项目名, 文档相对路径))
            连接.executemany(
                "INSERT INTO 块索引(项目名,文档相对路径,起始行,结束行,块类型,块文本) VALUES(?,?,?,?,?,?)",
                [(项目名, 文档相对路径, s, e, k, t) for s, e, k, t in 规范块])
            连接.execute(
                """INSERT OR REPLACE INTO 文档索引
                   (项目名,文档相对路径,标题,文档类型,内容摘要,段数,字节数,文件修改时间,入库时间)
                   VALUES(?,?,?,?,?,?,?,?,?)""",
                (项目名, 文档相对路径, 标题, "md", 摘要, 段数, 字节数,
                 float(文件修改时间 or 0), time.time()))
            连接.commit()
        return 结果.成功结果({"项目名": 项目名, "文档相对路径": 文档相对路径,
                            "块数": len(规范块), "标题": 标题, "段数": 段数})
    except ValueError as 错误:
        return 结果.失败("参数不合法", str(错误), 来源="项目文档支持库")
    except sqlite3.Error as 错误:
        return 结果.失败("索引库不可用", f"写入失败: {错误}", 来源="项目文档支持库")


def 查询索引(项目名: str = None, 关键词: str = None, 返回条数: int = 20,
            库文件: str = None, 返回粒度: str = None, 搜索词: list = None,
            截断上限: int = 0) -> 结果:
    """按项目名与关键词查询块索引（大小写不敏感子串匹配）。

    **多词两组口径（并存，只增不改）**：
    - `关键词`（老参数）：空白分隔多词，**同一条查询里 AND 式匹配**，全命中优先；
    - `搜索词`（新参数）：**一组一组的候选**，如 `[["开通","流程"],["签约","步骤"]]`，
      每组独立检索打分，**只返回评分最高的那一组**。
    传了 `搜索词` 时 `关键词` 只原样带回、不参与检索；两个都不传则报参数不合法。

    **返回粒度四档**（`返回粒度`）：标题 / 简介（默认）/ 内容 / 完整。
    默认档与改前返回**逐字段兼容**（老调用零行为变化）。

    **未命中词扩词**：某组词零命中时，读该项目的「未命中词」表取建议词重查
    （只读，不写库）；只对零命中的那一组生效，不做全局替换。

    参数：项目名 / 关键词 / 返回条数 / 库文件 / 返回粒度 / 搜索词 / 截断上限
    **未建索引不冒充「真缺口」**：`命中数=0` 有两种含义，用 `项目已建索引` 区分 ——
    真=该项目已建索引（0 命中＝确实没有，可判真缺口）；假=尚未建索引/未登记
    （0 命中**不代表没有承载**，须先 `建全仓索引`）。`判别说明` 给出可执行提示，
    `已索引文档数` 是该项目当前索引的文档数。这是 fail-open 防护：不让调用方
    把「不知道」当成「没有」（哲学）。

    **索引可能是旧的**：索引建好之后文档又被改过，就是旧索引 —— 拿它当权威会得出
    与磁盘不符的结论（实测踩过：当天新写的内容没重建索引时搜不到，看着像「真缺口」）。
    用 `索引新鲜度` 区分：`新鲜` / `部分过期` / `空索引` / `未核验`；
    `过期文档数` 给出几份已变（实测 stat 全部已索引文档仅 0.002 秒，几乎免费）。
    `未核验` 表示项目根不可用或文档是虚拟渲染的（如包能力清单，无磁盘文件），
    **如实报「未核验」而不是默认当新鲜**。

    返回：``{项目名, 关键词, 命中列表, 命中数, 是否截断, 返回粒度,
            生效搜索词, 搜索词组数, 扩词记录,
            项目已建索引, 已索引文档数, 判别说明,
            索引新鲜度, 过期文档数, 新鲜度说明}``
    """
    if not isinstance(项目名, str) or not 项目名.strip():
        return 结果.失败("参数不合法", "项目名必须是非空文本", 来源="项目文档支持库")
    档 = 收敛返回粒度(返回粒度)
    if 档 is None:
        return 结果.失败("参数不合法",
                         f"返回粒度 必须是 {'/'.join(返回粒度表)} 之一，收到 {返回粒度!r}",
                         来源="项目文档支持库")

    词组表 = _归一词组(关键词, 搜索词)
    if 词组表 is None:
        return 结果.失败("参数不合法",
                         "关键词与搜索词至少给一个非空值；搜索词须是非空列表，每项是一组词",
                         来源="项目文档支持库")
    上限 = max(1, int(返回条数 or 20))
    try:
        with _连接(库文件) as 连接:
            # 项目登记判别：区分「该项目根本没建索引」与「建了但确实没这条」。
            # 两种情况的命中数都是 0，不给判别字段调用方就会把「没建索引」
            # 误读成「真缺口」并直接新建包（fail-open，哲学明令禁止
            # 「把『不知道』说成『没有』」）。此处只读登记表，不猜、不兜底。
            已建 = 连接.execute("SELECT 1 FROM 项目登记 WHERE 项目名=?",
                            (项目名,)).fetchone() is not None
            已索文档数 = 连接.execute(
                "SELECT COUNT(*) FROM 文档索引 WHERE 项目名=?", (项目名,)).fetchone()[0]
            行表 = 连接.execute(
                "SELECT 文档相对路径,起始行,结束行,块类型,块文本 FROM 块索引 WHERE 项目名=?",
                (项目名,)).fetchall()
            # 新鲜度判别的原料（**只读**）：文档入库时间 + 项目根目录。
            # 为什么在查询里顺带取：实测 stat 全部已索引文档只要 0.002 秒（647 份），
            # 比新建一条「查索引新鲜度」能力更直接 —— 调用方要搜之前本来就该知道
            # 索引是不是旧的，漏了这一步就会拿旧索引当权威（fail-open 的另一面）。
            文件行表 = 连接.execute(
                "SELECT 文档相对路径,入库时间 FROM 文档索引 WHERE 项目名=?",
                (项目名,)).fetchall()
            根行 = 连接.execute("SELECT 项目根目录 FROM 项目登记 WHERE 项目名=?",
                             (项目名,)).fetchone()
            标题表 = {行[0]: 行[1] for 行 in 连接.execute(
                "SELECT 文档相对路径,标题 FROM 文档索引 WHERE 项目名=?", (项目名,)).fetchall()}
    except ValueError as 错误:
        return 结果.失败("参数不合法", str(错误), 来源="项目文档支持库")
    except sqlite3.Error as 错误:
        return 结果.失败("索引库不可用", f"查询失败: {错误}", 来源="项目文档支持库")

    # 索引新鲜度：索引建好之后文档又被改过，就是「旧索引」——
    # 拿它当权威会得出与磁盘不符的结论（本轮实测踩过：索引 22:00 建，
    # 未重建时搜不到当天新写的内容，看起来像「真缺口」）。
    新鲜度 = _算新鲜度(文件行表, 根行[0] if 根行 else "")

    # 未建索引不冒充「真缺口」：如实回带判别字段与可执行提示。
    判别说明 = ""
    if not 已建:
        判别说明 = (f"该项目（{项目名}）尚未建索引或未登记 —— 本次 0 命中"
                 f"**不代表「没有既有承载」**。请先调 `建全仓索引`"
                 f"（项目名={项目名}, 根目录=<工程根>）建好索引再搜。")
    elif 已索文档数 == 0:
        判别说明 = (f"该项目已登记但索引为空（0 份文档）—— 本次 0 命中"
                 f"**不代表「没有既有承载」**。请先调 `建全仓索引` 灌入文档。")

    # 逐组检索并按评分定序；同时记录「零命中」的组（供扩词）
    组结果 = []
    零命中组 = []
    for 组词 in 词组表:
        命中 = _扫一组(行表, 标题表, 组词)
        if 命中:
            组结果.append((组词, 命中))
        else:
            零命中组.append(组词)

    # 扩词：只对零命中的组生效，读未命中词表取建议词重查（只读，不写库）
    扩词记录 = []
    if 零命中组:
        建议表 = 取建议词(项目名, [w for 组词 in 零命中组 for w in 组词], 库文件)
        for 组词 in 零命中组:
            命中, 来源 = _扫扩词组(行表, 标题表, 组词, 建议表)
            if 命中:
                组结果.append((组词, 命中))
                扩词记录.append({"原始词": 组词, "扩词来源": 来源})

    if not 组结果:
        return 结果.成功结果({
            "项目名": 项目名, "关键词": 关键词 or "", "命中列表": [], "命中数": 0,
            "是否截断": 假, "返回粒度": 档, "生效搜索词": [], "搜索词组数": len(词组表),
            "扩词记录": 扩词记录,
            "项目已建索引": 已建, "已索引文档数": 已索文档数, "判别说明": 判别说明,
            "索引新鲜度": 新鲜度["档"], "过期文档数": 新鲜度["过期文档数"],
            "新鲜度说明": 新鲜度["说明"],
        })

    # 择优：先比最优块评分，再比命中块数，再取组序（稳定，不随机）
    组词, 命中 = max(组结果, key=lambda x: (x[1][0]["覆盖率"], x[1][0]["命中词数"],
                                            x[1][0]["命中次数"], len(x[1])))
    扩词来源 = next((r["扩词来源"] for r in 扩词记录 if r["原始词"] == 组词), "")

    # 按文档聚合（标题档要「命中块数」，且避免同一文档刷屏）
    聚合: dict[str, dict] = {}
    for 记录 in 命中:
        if 扩词来源:
            记录 = {**记录, "扩词来源": 扩词来源}
        键 = 记录["文档相对路径"]
        if 键 not in 聚合:
            聚合[键] = {**记录, "命中块数": 1}
        else:
            聚合[键]["命中块数"] += 1
    条目表 = sorted(聚合.values(),
                    key=lambda x: (-x["覆盖率"], -x["命中词数"], -x["命中次数"],
                                   x["文档相对路径"], x["起始行"]))
    投影 = [投影记录(记录, 档, 截断上限=int(截断上限 or 0)) for 记录 in 条目表[:上限]]
    return 结果.成功结果({
        "项目名": 项目名, "关键词": 关键词 or "", "命中列表": 投影,
        "命中数": len(条目表), "是否截断": len(条目表) > 上限, "返回粒度": 档,
        "生效搜索词": 组词, "搜索词组数": len(词组表), "扩词记录": 扩词记录,
        "项目已建索引": 已建, "已索引文档数": 已索文档数, "判别说明": 判别说明,
        "索引新鲜度": 新鲜度["档"], "过期文档数": 新鲜度["过期文档数"],
        "新鲜度说明": 新鲜度["说明"],
    })


def _归一词组(关键词: str, 搜索词: list) -> list[list[str]] | None:
    """把两种入参归一到「一组一组的词」；都不合法返回 None。

    - `搜索词` 给了：必须是列表，每项是非空字符串或字符串列表（空组剔除）；
    - `搜索词` 没给：`关键词` 按空白切成**唯一一组**（老行为逐字保留）。
    """
    if 搜索词 is not None:
        if not isinstance(搜索词, list) or not 搜索词:
            return None
        组表: list[list[str]] = []
        for 项 in 搜索词:
            词 = [w for w in re.split(r"\s+", 项.strip()) if w] if isinstance(项, str) \
                else [str(w).strip() for w in 项 if str(w).strip()] if isinstance(项, list) else []
            if 词:
                组表.append(词)
        return 组表 or None
    if not isinstance(关键词, str) or not 关键词.strip():
        return None
    return [[w for w in re.split(r"\s+", 关键词.strip()) if w]]


def _算新鲜度(文件行表: list, 项目根: str) -> dict[str, Any]:
    """算索引新鲜度：索引里有几份文档在磁盘上已改过（或已不存在）。

    为什么值得做（实测）：索引 22:00 建、当天新写的内容不重建就搜不到，
    调用方会把「索引旧了」误读成「真缺口」—— 又与 fail-open 同理。
    口径必须可判定（哲学第 13 条）：
      - 已索引文档逐个 stat：mtime 比入库时间新 → 该份过期；文件不存在 → 也算过期；
      - **虚拟渲染文档**（如包能力清单，磁盘无此文件）单独归一类，不算过期也不算核验，
        但会拉低可核验比例 → 没有磁盘文件可比的场合如实报 `未核验`。
    返回 ``{档, 过期文档数, 可核验数, 说明}``。
    """
    档表 = {"新鲜": "新鲜", "部分过期": "部分过期", "空索引": "空索引", "未核验": "未核验"}
    if not 文件行表:
        return {"档": 档表["空索引"], "过期文档数": 0, "可核验数": 0,
                "说明": "该项目索引里没有任何文档。"}
    根 = Path(项目根) if 项目根 else None
    if 根 is None or not 根.is_dir():
        return {"档": 档表["未核验"], "过期文档数": 0, "可核验数": 0,
                "说明": f"项目根目录（{项目根 or '未登记'}）不可用，无法比对文档是否已变；"
                      "如实报「未核验」，不默认当新鲜。"}
    过期 = 可核验 = 0
    for 路径, 入库时间 in 文件行表:
        文件 = 根 / str(路径)
        try:
            stat = 文件.stat()
        except OSError:
            # 磁盘没有这份文件：可能是虚拟渲染文档（能力清单），也可能是文件被删。
            # 无法区分，故不计入过期、也不计入可核验 —— 只由比例决定是否报「未核验」。
            continue
        可核验 += 1
        if stat.st_mtime > float(入库时间 or 0) + 1.0:
            过期 += 1
    总数 = len(文件行表)
    if 可核验 == 0:
        return {"档": 档表["未核验"], "过期文档数": 0, "可核验数": 0,
                "说明": f"索引里 {总数} 份文档在磁盘上都无同名文件（多为包能力清单等"
                      f"虚拟渲染文档），无从比对修改时间；如实报「未核验」。"}
    if 过期 == 0:
        return {"档": 档表["新鲜"], "过期文档数": 0, "可核验数": 可核验,
                "说明": f"已核验 {可核验} 份，均未晚于入库时间。"}
    return {"档": 档表["部分过期"], "过期文档数": 过期, "可核验数": 可核验,
            "说明": f"已核验 {可核验} 份中有 {过期} 份在磁盘上已改，索引是旧的 —— "
                  f"请先调 `建全仓索引` 重建再据结果下结论。"}


def _扫一组(行表: list, 标题表: dict, 组词: list[str]) -> list[dict]:
    """扫全表命中某一组词，返回带评分字段的命中列表（不改行表）。"""
    命中 = []
    for 路径, 起始行, 结束行, 块类型, 块文本 in 行表:
        小写 = 块文本.lower()
        命中词 = [w for w in 组词 if w.lower() in 小写]
        if not 命中词:
            continue
        命中.append({
            "文档相对路径": 路径, "标题": 标题表.get(路径, ""),
            "起始行": 起始行, "结束行": 结束行, "块类型": 块类型,
            "块文本": 块文本, "命中词": 命中词, "命中词数": len(命中词),
            "命中次数": sum(小写.count(w.lower()) for w in 命中词),
            "覆盖率": len(命中词) / len(组词) if 组词 else 0.0,
        })
    命中.sort(key=lambda x: (-x["覆盖率"], -x["命中词数"], -x["命中次数"],
                             x["文档相对路径"], x["起始行"]))
    return 命中


def _扫扩词组(行表: list, 标题表: dict, 组词: list[str],
             建议表: dict[str, str]) -> tuple[list[dict], str]:
    """对零命中组用建议词重查：返回（命中列表, 扩词来源文案）。

    只有当该组**全部词**都能取到建议词时才扩（部分扩会让评分口径混乱）；
    否则原样返回空，如实承认这组确实搜不到。
    """
    新词 = [建议表.get(w, "") for w in 组词]
    if not all(新词):
        return [], ""
    命中 = _扫一组(行表, 标题表, 新词)
    if not 命中:
        return [], ""
    来源 = " → ".join(f"{旧}→{新}" for 旧, 新 in zip(组词, 新词))
    return 命中, 来源
