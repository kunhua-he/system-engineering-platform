"""项目文档支持库 · 清单条目原子能力（进程内实现，不对外暴露）。

Markdown 表格清单的解析 / 增删改 / 校验：纯文本变换，不留状态（哲学 1.1）。

明确不做（项目文档治理方案 11.3）：

* 不自动排序 —— 清单的业务顺序是人工判断（优先级/分组语义），机器排序会打乱编排；
* 不自动生成编号 —— 体例规范第七节「编号四位递增且不复用、缺号即从未存在过」，
  新增必须由调用方给编号，能力只拒绝缺编号与重复编号；
* 不新建包、不保存清单副本 —— 属既有域补齐，正文一律由调用方传入。

约定：改清单条目以**第一列**为编号列（清单体例），据此判「编号不复用」。
"""

from __future__ import annotations

import re
from typing import Any

from 公共契约.基础类型.结果类型 import 结果

分隔单元格模式 = re.compile(r"^:?-{3,}:?$")
表格行模式 = re.compile(r"^\s*\|")

编号列序 = 0


def _切行(正文: str) -> list[str]:
    """按行切开并丢掉末尾换行造成的幽灵空行（与切块同口径）。"""
    行们 = 正文.split("\n")
    if len(行们) > 1 and 行们[-1] == "":
        行们 = 行们[:-1]
    return 行们


def _拆列(行: str) -> list[str]:
    """按竖线拆单元格，去掉首尾空壳并逐格去空白。"""
    内容 = 行.strip()
    if 内容.startswith("|"):
        内容 = 内容[1:]
    if 内容.endswith("|"):
        内容 = 内容[:-1]
    return [格.strip() for 格 in 内容.split("|")]


def _是表格行(行: str) -> bool:
    return bool(表格行模式.match(行))


def _是分隔行(行: str) -> bool:
    """分隔行 = 每格都是 `---` 一类的对齐标记；没有它就不是 Markdown 表格。"""
    格们 = _拆列(行)
    return bool(格们) and all(分隔单元格模式.match(格) for 格 in 格们)


def _定位表格(行们: list[str]) -> tuple[int, int, list[int]] | None:
    """找第一个 Markdown 表格：返回 (表头行号, 分隔行号, 数据行号列表)。"""
    for 序 in range(1, len(行们)):
        if _是表格行(行们[序 - 1]) and _是分隔行(行们[序]):
            数据行序: list[int] = []
            末 = 序 + 2
            while 末 <= len(行们) and _是表格行(行们[末 - 1]):
                数据行序.append(末)
                末 += 1
            return 序, 序 + 1, 数据行序
    return None


def _结构(正文: str) -> tuple[list[str], list[str], int, list[int]] | None:
    """正文 → (行们, 表头, 分隔行号, 数据行号列表)；非表格正文返回 None。"""
    行们 = _切行(正文)
    位置 = _定位表格(行们)
    if 位置 is None:
        return None
    表头序, 分隔行号, 数据行序 = 位置
    return 行们, _拆列(行们[表头序 - 1]), 分隔行号, 数据行序


def _列值(行们: list[str], 行号: int) -> list[str]:
    return _拆列(行们[行号 - 1])


def _成行(列值: list[str]) -> str:
    return "| " + " | ".join(列值) + " |"


def _收尾(正文: str, 行们: list[str]) -> str:
    """保持原文末尾是否有换行，不擅自改动。"""
    return "\n".join(行们) + ("\n" if 正文.endswith("\n") else "")


def 解析清单(正文: str = None) -> 结果:
    """把 markdown 表格清单解析成结构化条目。

    参数：正文（非空文本，含表头行与分隔行的 markdown 表格）
    返回：``{表头, 条目列表, 条目数, 提示}``；每条目含 行号 / 列值 / 原始行，
    行号自 1 起（全文行号）。**非表格文本如实报告**：表头与条目列表为空、
    条目数为 0、提示说明原因，不假装解析出条目。
    """
    if not isinstance(正文, str) or not 正文.strip():
        return 结果.失败("参数不合法", "正文必须是非空文本", 来源="项目文档支持库")
    结构 = _结构(正文)
    if 结构 is None:
        return 结果.成功结果({
            "表头": [],
            "条目列表": [],
            "条目数": 0,
            "提示": "未识别到 Markdown 表格清单（需表头行 + 分隔行）",
        })
    行们, 表头, _, 数据行序 = 结构
    条目列表 = [
        {"行号": 行号, "列值": _列值(行们, 行号), "原始行": 行们[行号 - 1]}
        for 行号 in 数据行序
    ]
    return 结果.成功结果({
        "表头": 表头,
        "条目列表": 条目列表,
        "条目数": len(条目列表),
        "提示": "",
    })
