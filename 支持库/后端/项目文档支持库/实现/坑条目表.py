"""项目文档支持库 · 坑条目表定义（进程内实现，不对外暴露）。

只放**表结构与状态机常量**，供 `坑条目`（写入侧）与 `开工上下文`（读取侧）共用。
同一口径只写一遍（哲学 1.2 单腿）：表的列名、状态取值、条目主键算法都只在本文件定义。

**状态机（每条坑的生命周期）**：

    草稿 ──命中≥1──> 已用 ──命中≥3 且有判据──> 已固化 ──> 已封存
      └───────────────── 前提失效 ─────────────────> 已失效（检索不再返回）

- `草稿`：刚记下，还没被检索命中过；
- `已用`：被 `查开工上下文` 命中过（有人靠它查过）；
- `已固化`：命中 ≥3 次（这个坑已稳定，可考虑升级为门禁）；
- `已封存`：已升级为判据 / 门禁，条目只留索引（防回潮）；
- `已失效`：前提已不成立（如相关能力已删除），**不再返回**，避免误导旧结论。

库文件与 `索引库` **同一个库**（`<运行数据根>/项目文档库.db`），不新建第二套。
"""

from __future__ import annotations

import hashlib

状态表 = ("草稿", "已用", "已固化", "已封存", "已失效")
可检索状态 = ("草稿", "已用", "已固化")
固化阈值 = 3

五键 = ("场景id", "症状", "根因", "判据", "原文位置")

建表语句 = (
    """CREATE TABLE IF NOT EXISTS 坑条目(
       条目id TEXT PRIMARY KEY, 项目名 TEXT NOT NULL, 场景id TEXT NOT NULL,
       症状 TEXT NOT NULL, 根因 TEXT NOT NULL, 判据 TEXT NOT NULL, 原文位置 TEXT NOT NULL,
       状态 TEXT NOT NULL, 命中次数 INTEGER NOT NULL, 首次命中时间 REAL NOT NULL,
       最近命中时间 REAL NOT NULL, 创建时间 REAL NOT NULL, 更新时间 REAL NOT NULL);""",
    "CREATE INDEX IF NOT EXISTS 坑条目_项目_状态 ON 坑条目(项目名, 状态);",
)


def 确保表(连接) -> None:
    """建表（幂等）——表不存在时自动初始化，调用方不必先调 `建索引库`。"""
    for 语句 in 建表语句:
        连接.execute(语句)


def 条目id(项目名: str, 场景id: str, 症状: str) -> str:
    """条目主键：项目名 + 场景id + 症状 的稳定短哈希（同项目同坑覆盖更新，不重复累积）。"""
    原料 = f"{项目名}|{场景id}|{症状}".encode("utf-8")
    return hashlib.sha256(原料).hexdigest()[:16]


def 校验五键(条目: dict, 序: int = 0) -> str:
    """返回缺失字段说明；五键齐全返回空串（**五键齐全是硬要求**，缺一即拒收）。"""
    缺 = [键 for 键 in 五键 if not str(条目.get(键) or "").strip()]
    if not 缺:
        return ""
    前缀 = f"第 {序} 条" if 序 else "条目"
    return f"{前缀}缺字段: {'/'.join(缺)}（五键齐全是硬要求：{'/'.join(五键)}）"
