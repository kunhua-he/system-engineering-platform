"""项目文档支持库 · 检索粒度投影（进程内纯函数，不对外暴露）。

**为什么单独成文件**：粒度只影响**返回什么字段**，不影响检索与排序。
把投影抽成纯函数有三个好处：① 可单测（喂记录 → 比字段集合，不碰数据库）；
② `查询索引` 只做「拿记录 → 调投影 → 组装」，主流程不被字段判断污染；
③ 以后加档位只改本文件，检索逻辑一行不动。

**档位口径与 `模块库.能力目录.搜索能力` 的三档一致**（那边是平台能力的标杆）：
只增不改、默认档最省 token、要重字段必须显式声明。

四档（按返回量升序）：

| 档位 | 回什么 | 典型用途 |
|---|---|---|
| 标题 | 文档相对路径 / 标题 / 命中块数 | 先看有哪些文档相关，最省 token |
| 简介（默认） | 上档 + 起始行 / 结束行 / 块类型 / 命中词数 / 命中次数 / 片段 | 判断值不值得深入 |
| 内容 | 上档 + 完整块文本（截断上限由参数给） | 直接拿正文，省一次读文件 |
| 完整 | 上档 + 命中词 / 覆盖率 / 扩词来源 | 排查为什么排这个序 |

**★ 兼容铁律：默认档 `简介` 的字段必须是改前返回字段的超集。**
改前 `查询索引` 每条命中回的是：文档相对路径 / 起始行 / 结束行 / 块类型 /
命中词数 / 命中次数 / 片段 —— 这 7 个字段在 `简介` 档里**一个都不能少**，
新增字段只能往后加。任何"顺手精简掉老字段"的写法都会让老调用静默丢数据
（本项目已踩过同类坑：假降级、字段漂移）。

**本文件管两处投影**（同一个「档位只影响返回什么字段」的口径，不另起第二个文件）：

- `查询索引` 的四档领域说法：标题 / 简介（默认）/ 内容 / 完整 —— `投影记录`；
- `查开工上下文` 的三档通用说法：索引（默认）/ 摘要 / 完整 —— `投影坑条目` + `投影坑结果`。

参数名全仓只有一个 `细节级别`；「四档」与「三档」是同一语义在两处的领域叫法，
不是两套参数名（口径见 `开发文档/方案/返回体量分档统一方案_20260921.md`）。
"""

from __future__ import annotations

import re
from typing import Any

粒度_标题 = "标题"
粒度_简介 = "简介"
粒度_内容 = "内容"
粒度_完整 = "完整"

细节级别表 = (粒度_标题, 粒度_简介, 粒度_内容, 粒度_完整)
默认细节级别 = 粒度_简介

#: 简介档片段长度（与改前 `块文本[:180]` 一致，不得改，否则老调用摘要会变）
片段长度 = 180


def 收敛细节级别(值: Any) -> str | None:
    """细节级别：未传 / 空串 → 默认档；不认识的值 → None（调用方判参数不合法）。

    **不做大小写或别名归一**：档位是契约取值，宽松匹配会让调用方写出平台不认的
    拼法却"碰巧能用"，等真改名时静默失效（本项目已立此口径）。
    """
    if 值 is None:
        return 默认细节级别
    文本 = str(值).strip()
    if not 文本:
        return 默认细节级别
    return 文本 if 文本 in 细节级别表 else None


def 投影记录(记录: dict, 粒度: str, *, 截断上限: int = 0) -> dict:
    """把一条命中记录投影成指定粒度的返回项（纯函数，不改输入）。

    参数：
        记录：含 文档相对路径 / 标题 / 起始行 / 结束行 / 块类型 / 块文本 /
              命中词数 / 命中次数（完整档还需 命中词 / 覆盖率 / 扩词来源）
        粒度：四档之一（调用方须先过 `收敛细节级别`）
        截断上限：`内容` 档下块文本的最大字符数；0 或负 = 不截断

    返回：按档位裁剪后的新字典（不改入参）。
    """
    片段 = str(记录.get("块文本") or "").strip().replace("\n", " ")
    标题 = 记录.get("标题", "")
    路径 = 记录.get("文档相对路径", "")

    if 粒度 == 粒度_标题:
        return {
            "文档相对路径": 路径,
            "标题": 标题,
            "命中块数": int(记录.get("命中块数") or 0),
        }

    # 简介档：**改前 7 字段全保留**（文档相对路径/起始行/结束行/块类型/命中词数/命中次数/片段）
    # 只新增「标题」。顺序按「先定位、再看量、最后给内容」排，便于人读。
    基础 = {
        "文档相对路径": 路径,
        "标题": 标题,
        "起始行": int(记录.get("起始行") or 0),
        "结束行": int(记录.get("结束行") or 0),
        "块类型": 记录.get("块类型", ""),
        "命中词数": int(记录.get("命中词数") or 0),
        "命中次数": int(记录.get("命中次数") or 0),
        "片段": 片段[:片段长度],
    }
    if 粒度 == 粒度_简介:
        return 基础

    全文 = 片段 if 截断上限 <= 0 else 片段[:截断上限]
    基础["块文本"] = 全文
    if 粒度 == 粒度_内容:
        return 基础

    # 完整档：追加判序依据，供排查「为什么排这个序」
    基础["命中词"] = list(记录.get("命中词") or [])
    基础["覆盖率"] = float(记录.get("覆盖率") or 0.0)
    if 记录.get("扩词来源"):
        基础["扩词来源"] = 记录.get("扩词来源")
    return 基础


# ══════════════════════════════════════════════════════════════════════════════
# 坑条目（`查开工上下文`）的三档：索引 / 摘要 / 完整
# ══════════════════════════════════════════════════════════════════════════════
#
# 华哥 2026-09-22 定「所有注入提示词最高 2000 字符」后补的收窄面。口径与
# `模块库.开工编排/实现/返回体量分档.py` **完全一致**（参数名 `细节级别`、
# 三档 索引/摘要/完整、`完整` = 改前行为），只是投影对象换成「坑条目」——
# 与上面 `查询索引` 的四档领域说法（标题/简介/内容/完整）**并存不冲突**：
# 两者是同一语义在两处的领域叫法，参数名只有 `细节级别` 一个，不是两套。
#
# **默认档 = `索引`**（实测改前一次默认调用回 5 条、整条回执 3,363 字符）：
# `根因` / `命中词` / `相关度` / `命中次数` / `检索词` 全是「判断这条坑跟我要做的
# 事有没有关系」用不到的重字段，一律收进按需展开；`症状`/`判据`/`原文位置`
# 是判断面本体，**留但截断**（`原文位置` 是漂移值，上限给得最宽）。
#
# ★ 判据不动：本档位只改「回哪些字段 / 正文多长」。命中判定、失效条目上报、
#   状态机推进全在 `开工上下文.py` 里**算完之后**才调本投影 —— 投影是纯函数。

坑细节级别表 = ("索引", "摘要", "完整")
#: 「不投影」档：原样返回 = 改前行为。**与 `坑默认细节级别` 解耦** ——
#: 直通判据必须认这个常量，否则改默认值会静默废掉该档的投影
#: （`开工编排/实现/返回体量分档.py:137-140` 已因这个写法实测踩过一次）。
坑完整档 = "完整"
坑默认细节级别 = "索引"

#: 索引档各字段的硬上限（字符）。超限截断并补 `…`，原文按 `原文位置` 取回。
坑症状上限 = 32
坑判据上限 = 64
#: `原文位置` 是**漂移值**（唯一的取回指针），上限给最宽：真实「路径#锚点」远短于它，
#: 被截掉的只会是路径后面那截散文说明。
坑原文位置上限 = 96

#: 索引/摘要档的展开入口提示。默认档只多花 40 字符，换来调用方「知道怎么要全文」——
#: 与 `开工准备` 的 `细节级别提示` 同形制（一处一个，不自造第二套）。
坑展开提示 = "要根因/全文传 细节级别=摘要；要逐字段（等于改前）传 细节级别=完整"


def 收敛坑细节级别(值: Any) -> str | None:
    """坑条目档位：未传 / 空串 → 默认档；不认识的值 → None（调用方判参数不合法）。

    **不做大小写或别名归一**（与 `收敛细节级别` 同口径）：档位是契约取值，
    宽松匹配会让调用方写出平台不认的拼法却「碰巧能用」，等真改名时静默失效。
    """
    if 值 is None:
        return 坑默认细节级别
    文本 = str(值).strip()
    if not 文本:
        return 坑默认细节级别
    return 文本 if 文本 in 坑细节级别表 else None


def _一句话(文本: Any, 上限: int) -> str:
    """取「一句话」：先按句末标点切第一句，再按 `上限` 硬截（超限补 `…`）。

    只用于**索引档**的 `症状`/`判据`/`原文位置` —— 默认档要的是「一眼判断相关性」，
    不是原文；原文按 `原文位置` 取回。先折空白再截，避免换行把 `…` 顶到下一行。
    """
    文本 = " ".join(str(文本 or "").split())
    if not 文本:
        return ""
    句 = re.split(r"(?<=[。！？；])", 文本)[0]
    return 句 if len(句) <= 上限 else 句[:上限] + "…"


def 投影坑条目(条目: dict, 档位: str) -> dict:
    """把一条坑条目投影成指定档位（纯函数，不改入参）。

    参数：
        条目：`查开工上下文` 组装好的单条命中（条目id/场景id/症状/根因/判据/
              原文位置/状态/命中次数/相关度/提示）
        档位：三档之一（调用方须先过 `收敛坑细节级别`）

    索引档（**默认**）：标识（条目id/场景id/状态）+ 一句话症状 + 判据 + 原文位置
            + 提示 —— 够判断「跟我要做的事有没有关系」，也够照着判据动手。
    摘要档：索引档 + `根因`（说明段）+ 排序依据（命中次数/相关度），
            且 症状/判据/原文位置 **给全文**。
    完整档：原样返回（等于改前行为，逐字段兼容）。
    """
    if 档位 == 坑完整档:
        return dict(条目)

    出 = {
        "条目id": 条目.get("条目id", ""),
        "场景id": 条目.get("场景id", ""),
        "状态": 条目.get("状态", ""),
        "症状": 条目.get("症状", ""),
        "根因": 条目.get("根因", ""),
        "判据": 条目.get("判据", ""),
        "原文位置": 条目.get("原文位置", ""),
        "命中次数": int(条目.get("命中次数") or 0),
        "相关度": float(条目.get("相关度") or 0.0),
        "提示": 条目.get("提示", ""),
    }
    if 档位 == "索引":
        出["症状"] = _一句话(出["症状"], 坑症状上限)
        出["判据"] = _一句话(出["判据"], 坑判据上限)
        出["原文位置"] = _一句话(出["原文位置"], 坑原文位置上限)
        for 键 in ("根因", "命中次数", "相关度"):
            出.pop(键, None)
    return 出


def 投影坑结果(值: dict, 档位: str) -> dict:
    """把 `查开工上下文` 的整个返回值投影成指定档位（纯函数，不改入参）。

    索引/摘要档额外做两件事：
    ① 去掉顶层 `检索词`（切词明细，属「排查为什么排这个序」= 完整档内容）；
    ② 追加 `细节级别`（标注实际生效档位）与 `展开提示`（漂移值）。

    **不动**的字段：`项目名` / `本次任务` / `命中数` / `已失效条数` / `是否截断`
    —— 命中判定与失效上报的口径一律不变，只改「回哪些字段 / 正文多长」。

    三档都回 `细节级别`（新增字段，不改任何既有字段）：与同库 `查询索引` 同形制。
    """
    出 = dict(值)
    出["细节级别"] = 档位
    if 档位 == 坑完整档:
        return 出

    出.pop("检索词", None)
    出["坑列表"] = [投影坑条目(条, 档位) for 条 in 值.get("坑列表") or []]
    出["展开提示"] = 坑展开提示
    return 出
