"""项目文档支持库 · 切块原子能力（进程内实现，不对外暴露）。

把项目文档正文按 Markdown 结构切成有序块，每块带起始行/结束行（行号自 1 起）。
代码块内的井号不算标题 —— 这是体例规范第一节的前提，切块必须与它同口径。

「哪些行是标题」不在这里手写正则判定：一律转调唯一腿
`办公文档支持库.轻量文本解析.解析Markdown块`（它按 `属性.章节` 给出行号），
本件只按行号分类，不另立第二条标题语法腿。
"""

from __future__ import annotations

import re
from typing import Any

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.办公文档支持库.轻量文本解析 import 解析Markdown块

围栏模式 = re.compile(r"^\s*```")
表格模式 = re.compile(r"^\s*\|")
列表模式 = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s")
引用模式 = re.compile(r"^\s*>")
分隔线模式 = re.compile(r"^\s*(?:-{3,}|\*{3,}|_{3,})\s*$")
链接模式 = re.compile(r"\[([^\]]*)\]\(([^)\s]+)\)")


def _标题行集(正文: str) -> set[int]:
    """转调唯一腿取「哪些行是标题」（行号自 1 起）；标题语法只此一条腿。"""
    解析结果 = 解析Markdown块(文本=正文, 语法集="完整")
    if not 解析结果.成功:
        raise RuntimeError(f"解析Markdown块 失败：{解析结果.错误码} {解析结果.错误说明}")
    行集: set[int] = set()
    for 块 in 解析结果.值.get("块列表") or []:
        if (块.get("属性") or {}).get("章节") == "heading" and 块.get("行起"):
            行集.add(块["行起"])
    return 行集


def _行类型(行: str) -> str:
    """判定单行的块类型；空行单独一类，供状态机断块。标题不在本函数判定。"""
    if not 行.strip():
        return "空行"
    if 围栏模式.match(行):
        return "围栏"
    if 分隔线模式.match(行):
        return "分隔线"
    if 表格模式.match(行):
        return "表格"
    if 列表模式.match(行):
        return "列表"
    if 引用模式.match(行):
        return "引用"
    return "段落"


def _断块(块列表: list[dict[str, Any]], 行们: list[str], 开始: int, 结束: int) -> None:
    """把 [开始, 结束] 区间收成一个块；空区间不产生块。"""
    if 结束 < 开始:
        return
    文本 = "\n".join(行们[开始 - 1:结束])
    if not 文本.strip():
        return
    块列表.append({
        "起始行": 开始,
        "结束行": 结束,
        "块类型": _行类型(行们[开始 - 1]) if 开始 == 结束 or _行类型(行们[开始 - 1]) != "空行" else "段落",
        "块文本": 文本,
    })


def _切(正文: str) -> list[dict[str, Any]]:
    """状态机切块：围栏内一律归代码块，围栏外按行类型聚合。"""
    行们 = 正文.split("\n")
    # 末尾换行会切出一个幽灵空行（"a\n" → ['a','']）。它不是文档的一行，
    # 留着会让未闭合围栏的结束行多报一行、行号对不上真实文件。
    if len(行们) > 1 and 行们[-1] == "":
        行们 = 行们[:-1]
    标题行集 = _标题行集(正文)
    块列表: list[dict[str, Any]] = []
    当前类型 = ""
    开始行 = 1
    在围栏内 = False

    for 序号, 行 in enumerate(行们, start=1):
        类型 = "标题" if 序号 in 标题行集 else _行类型(行)

        if 在围栏内:
            if 类型 == "围栏":  # 闭合围栏：与开围栏同属一个代码块
                在围栏内 = False
                _断块(块列表, 行们, 开始行, 序号)
                块列表[-1]["块类型"] = "代码"
                当前类型 = ""
            continue

        if 类型 == "围栏":  # 开围栏
            在围栏内 = True
            当前类型 = "代码"
            开始行 = 序号
            continue

        if 类型 == "空行":
            if 当前类型:
                _断块(块列表, 行们, 开始行, 序号 - 1)
                当前类型 = ""
            continue

        # 标题与分隔线天然独立成块：先断旧块，再自成一块
        if 类型 in ("标题", "分隔线"):
            if 当前类型:
                _断块(块列表, 行们, 开始行, 序号 - 1)
                当前类型 = ""
            _断块(块列表, 行们, 序号, 序号)
            块列表[-1]["块类型"] = 类型
            continue

        if 类型 != 当前类型:
            if 当前类型:
                _断块(块列表, 行们, 开始行, 序号 - 1)
            当前类型 = 类型
            开始行 = 序号

    if 当前类型 and not 在围栏内:
        _断块(块列表, 行们, 开始行, len(行们))
    elif 在围栏内:  # 未闭合围栏：把剩余全部收成代码块（不吞掉，如实产出供校验判红）
        _断块(块列表, 行们, 开始行, len(行们))
        块列表[-1]["块类型"] = "代码"

    return 块列表


def 切块(正文: str = None) -> 结果:
    """把项目文档正文按 Markdown 结构切成有序块。

    参数：正文（非空文本）
    返回：``{块列表, 块数}``；每块含 起始行 / 结束行 / 块类型 / 块文本。
    """
    if not isinstance(正文, str) or not 正文.strip():
        return 结果.失败("参数不合法", "正文必须是非空文本", 来源="项目文档支持库")
    try:
        块列表 = _切(正文)
    except Exception as 异常:  # 切块是纯计算，异常只可能是实现缺陷，不吞
        return 结果.失败("参数不合法", f"切块失败: {异常}", 来源="项目文档支持库")
    return 结果.成功结果({"块列表": 块列表, "块数": len(块列表)})
