def 切词(文本: str) -> list[str]:
    """把「我正要做什么」切成检索词（中文双字滑窗，与 `查开工上下文` 同口径）。

    为什么不用整句：整句会成为一个超长关键词，子串匹配必然 0 命中（2026-09-18 实测）。
    """
    文本 = str(文本 or "").strip()
    if not 文本:
        return []
    词表: list[str] = []
    已见: set[str] = set()
    for 串 in re.findall(r"[\u4e00-\u9fa5]{2,}", 文本):
        for i in range(len(串) - 1):
            词 = 串[i:i + 2]
            if 词 not in 已见:
                已见.add(词)
                词表.append(词)
    for 词 in re.findall(r"[A-Za-z0-9_]{2,}", 文本):
        小 = 词.lower()
        if 小 not in 已见:
            已见.add(小)
            词表.append(小)
    return 词表[:60]


def _全角窄化(文本: str) -> str:
    """全角/半角与大小写归一（判据里常混用）。"""
    return unicodedata.normalize("NFKC", str(文本 or "")).lower()


def _打一分(条款: tuple[str, str, str, str, str], 词表: list[str]) -> tuple[int, list[str]]:
    """按双字词命中数打分；返回（分数, 命中词）。"""
    全文 = _全角窄化(" ".join(条款))
    命中 = [词 for 词 in 词表 if _全角窄化(词) in 全文]
    return len(命中), 命中


def 查哲学条款(本次任务: str = "", 主条号: str = "", 返回条数: int = 5) -> 结果:
    """按「我正要做什么」检索设计哲学条款，返回命中的几条第 1 句结论（不全量载入）。

    参数：本次任务（自然语言描述）/ 主条号（如 "12"，留空＝全部）/ 返回条数
    返回：``{本次任务, 主条号, 条款列表, 命中数, 条款总数, 是否截断, 口径}``

    条款列表每项：``{主条号, 主条名, 结论, 判据, 原文位置, 命中词, 分数}``
    """
    号 = str(主条号 or "").strip()
    池 = 条款数据
    if 号:
        合法 = {条[0] for 条 in 条款数据}
        if 号 not in 合法:
            return 结果.失败(
                "参数不合法",
                f"主条号 非法：{号}（合法值 {'/'.join(sorted(合法, key=int))}）",
                来源="项目文档支持库")
        池 = tuple(条 for 条 in 条款数据 if 条[0] == 号)

    上限 = max(1, int(返回条数 or 5))
    词表 = 切词(本次任务)
    全部 = bool(str(本次任务 or "").strip()) is False  # 没给任务描述＝列该类全部

    if 全部:
        命中表 = [(条, 0, []) for 条 in 池][:上限]
    else:
        打分 = []
        for 条 in 池:
            分, 命中词 = _打一分(条, 词表)
            if 分 > 0:
                打分.append((条, 分, 命中词))
        # 分数降序；同分保持原顺序（条款本身按主条号、语义聚簇排布）
        打分.sort(key=lambda x: -x[1])
        命中表 = 打分[:上限]

    列表 = [
        {
            "主条号": 条[0],
            "主条名": 条[1],
            "结论": 条[2],
            "判据": 条[3],
            "原文位置": 条[4],
            "命中词": 词,
            "分数": 分,
        }
        for 条, 分, 词 in 命中表
    ]
    return 结果.成功结果({
        "本次任务": str(本次任务 or ""),
        "主条号": 号,
        "条款列表": 列表,
        "命中数": len(列表),
        "条款总数": len(条款数据),
        "是否截断": len(命中表) < len(池) and not 全部,
        "口径": ("只返回命中的几条第 1 句结论 + 判据 + 原文位置，不载入 1065 行哲学全文；"
                 "细节按 原文位置 跳转（开发文档/项目说明.md 的设计哲学节）"),
    })
