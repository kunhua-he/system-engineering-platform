"""一趟索引：扫一批文档 + 各包能力清单，逐份切块并写入索引库（只索引、不改文档）。

## 为什么需要它（2026-09-20 华哥裁决）
华哥原话：「你就不能类似于代码地图这样子，构建一套东西么？那么复杂干啥？
**所有 md 都能直接跑一趟索引。然后全部记录入库，然后关键词搜词不就完事了？**」

现状缺口：底座已有 `扫描文档集合`（扫）、`切块`（切）、`写入索引`（写）三条原子能力，
但**没有「一趟把它们串起来」的入口** —— 调用方要自己写循环、自己处理单份失败、
自己算耗时，实测每次都要重写一遍（本会话就重写了三次）。
本能力只做**机械串联**：扫描 → 切块 → 写入，不复制任何一条既有规则。

## 边界（严格照现有分层）
- **只索引，不改文档**：不写任何被索引的文件，只写索引库（与 `写入索引` 同口径）。
- **单份失败不静默**：失败的那份如实记入 `跳过清单`（带错误码与说明），
  不冒充成功、不整体失败（一份坏文档不该让整趟白跑）。
- **不自带语义判断**：检索归 `查询索引`，判断归调用方 —— 本能力不猜「算不算同一件事」。
- **复用既有原子**：扫描用 `扫描文档集合`、切块用 `切块`、写库用 `写入索引`，
  本文件不重复实现其中任何一条。
"""

from __future__ import annotations

import time
from pathlib import Path
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.基础类型.结果类型 import 结果

from .集合扫描 import 扫描文档集合
from .索引库 import 写入索引
from .切块 import 切块

#: 单个包渲染出的能力清单文件名（与普通文档同库同入口，便于统一检索）。
能力清单文件名 = "能力清单.md"

#: 包声明文件名：判断一个目录是否为正式包。
包声明文件名 = "包声明.json"


def _渲染包能力清单(包目录: Path, 项目根: Path) -> tuple[str, str]:
    """把一个包的 `能力定义.json` 渲染成 Markdown 正文；返回（相对路径, 正文）。

    为什么渲染成 md：索引库的块表按行号定位，md 切块才有标题/列表结构，
    检索命中后能给调用方「哪个包、哪条能力、说明是什么」的片段。
    """
    import json

    能力文件 = 包目录 / "能力定义.json"
    数据 = json.loads(能力文件.read_text(encoding="utf-8"))
    包id = 数据.get("包id") or 包目录.relative_to(项目根).as_posix()
    相对 = 包目录.relative_to(项目根).as_posix()
    层 = 包目录.relative_to(项目根).parts
    行 = [
        f"# {包id}",
        f"- 所属库：{层[1] if len(层) > 1 else 包id}",
        f"- 包路径：{相对}",
        "",
    ]
    for 能力 in 数据.get("能力列表") or []:
        参数名 = " ".join(str(项.get("名称")) for 项 in (能力.get("参数") or []))
        行 += [
            f"## {能力.get('能力id')}",
            f"- 所属包：{包id}",
            f"- 中文名称：{能力.get('中文名称') or 能力.get('名称') or ''}",
            f"- 说明：{str(能力.get('说明') or '')}",
            f"- 参数：{参数名}",
            "",
        ]
    return f"{相对}/{能力清单文件名}", "\n".join(行)


def 建全仓索引(项目名: str = None, 根目录: str = None, 文件名模式: str = "*.md",
              豁免目录=None, 是否含包能力: bool = 真, 库文件: str = None) -> 结果:
    """一趟索引：扫描 → 逐份切块 → 逐份写入索引库。重复调用按路径覆盖更新（幂等）。

    参数：
      项目名（非空文本）/ 根目录（绝对路径）/ 文件名模式（默认 ``*.md``）/
      豁免目录（片段列表，如 ``["工程缓存", ".git"]``）/ 是否含包能力（默认真）/
      库文件（留空取默认）
    返回：``{项目名, 文档数, 来源md, 来源包, 块数, 跳过清单, 仅库目录, 耗时秒}``；
      `跳过清单` 每项含 ``文档相对路径 / 错误码 / 错误说明`` —— **失败逐份如实登记**；
      `仅库目录` 是「有包声明但没有 能力定义.json」的库级目录（能力在子包里）——
      **这是正常结构、不是失败**，单独列出以免与真失败混在一起。
    """
    if not isinstance(项目名, str) or not 项目名.strip():
        return 结果.失败("参数不合法", "项目名必须是非空文本", 来源="项目文档支持库")
    if not isinstance(根目录, str) or not 根目录.strip():
        return 结果.失败("参数不合法", "根目录必须是非空文本（绝对路径）", 来源="项目文档支持库")
    根 = Path(根目录.strip())
    if not 根.is_dir():
        return 结果.失败("根目录不存在", f"根目录不是已存在的目录: {根}", 来源="项目文档支持库")

    T0 = time.time()
    跳过清单: list[dict[str, Any]] = []
    仅库目录: list[str] = []          # 有包声明但能力在子包里的库级目录（正常结构）
    文档数 = 块数 = 来源md = 来源包 = 0

    # ① 文档部分：交给既有 `扫描文档集合`（不自己 rglob，避免第二套扫描口径）
    出 = 扫描文档集合(根目录=str(根), 文件名模式=文件名模式,
                  豁免目录=豁免目录, 是否读正文=真)
    if not 出.成功:
        return 结果.失败(出.错误码 or "扫描失败", 出.错误说明 or "扫描文档集合失败",
                       来源="项目文档支持库")
    扫描值 = 出.值 or {}
    for 文档 in 扫描值.get("文档列表") or []:
        相对 = 文档.get("相对路径") or ""
        正文 = 文档.get("正文") or ""
        if not 相对 or not 正文.strip():
            跳过清单.append({"文档相对路径": 相对 or "（未命名）",
                        "错误码": "内容为空", "错误说明": "该文档无正文，不入索引"})
            continue
        结果项 = _入一份(项目名.strip(), 相对, 正文, float(文档.get("修改时间") or 0), 库文件)
        if 结果项.get("成功"):
            文档数 += 1; 块数 += 结果项["块数"]; 来源md += 1
        else:
            跳过清单.append({"文档相对路径": 相对, "错误码": 结果项.get("错误码") or "写入失败",
                        "错误说明": 结果项.get("错误说明") or ""})

    # ② 包能力部分：正式三层下的每个包渲染成能力清单后入索引
    if 是否含包能力:
        for 层名 in ("支持库", "模块库", "技能库"):
            层目录 = 根 / 层名
            if not 层目录.is_dir():
                continue
            for 声明 in sorted(层目录.rglob(包声明文件名)):
                if "__pycache__" in 声明.as_posix():
                    continue
                包目录 = 声明.parent
                if not (包目录 / "能力定义.json").is_file():
                    # 库级目录（能力在子包里）是**正常结构**，不是失败：静默计一笔，
                    # 不进 跳过清单（否则每个多子包的库都刷成一条假失败，实测 6 条）。
                    仅库目录.append(包目录.relative_to(根).as_posix())
                    continue
                try:
                    相对, 正文 = _渲染包能力清单(包目录, 根)
                except Exception as 异常:      # 读不了单个包不拖垮整趟
                    跳过清单.append({"文档相对路径": 包目录.relative_to(根).as_posix(),
                                "错误码": "渲染失败", "错误说明": f"{type(异常).__name__}: {异常}"})
                    continue
                结果项 = _入一份(项目名.strip(), 相对, 正文,
                            (包目录 / "能力定义.json").stat().st_mtime, 库文件)
                if 结果项.get("成功"):
                    文档数 += 1; 块数 += 结果项["块数"]; 来源包 += 1
                else:
                    跳过清单.append({"文档相对路径": 相对,
                                "错误码": 结果项.get("错误码") or "写入失败",
                                "错误说明": 结果项.get("错误说明") or ""})

    return 结果.成功结果({
        "项目名": 项目名.strip(),
        "文档数": 文档数,
        "来源md": 来源md,
        "来源包": 来源包,
        "块数": 块数,
        "跳过清单": 跳过清单,
        "仅库目录": 仅库目录,
        "耗时秒": round(time.time() - T0, 2),
    })


def _入一份(项目名: str, 相对路径: str, 正文: str, 修改时间: float,
            库文件: str = None) -> dict[str, Any]:
    """单份：切块 → 写入索引；返回 ``{成功, 块数, 错误码, 错误说明}``（异常也转成结果）。"""
    切 = 切块(正文=正文)
    if not 切.成功:
        return {"成功": 假, "错误码": 切.错误码 or "切块失败", "错误说明": 切.错误说明 or ""}
    块列表 = (切.值 or {}).get("块列表") or []
    if not 块列表:
        return {"成功": 假, "错误码": "切块为空", "错误说明": "正文切不出任何块"}
    写 = 写入索引(项目名=项目名, 文档相对路径=相对路径, 块列表=块列表,
                文件修改时间=修改时间, 库文件=库文件)
    if not 写.成功:
        return {"成功": 假, "错误码": 写.错误码 or "写入失败", "错误说明": 写.错误说明 or ""}
    return {"成功": 真, "块数": len(块列表)}
