"""项目文档支持库 · 清单条目改写原子能力（进程内实现，不对外暴露）。

增 / 删 / 改**一条**清单条目，纯文本变换：正文进、新正文出，不留状态。

不自动排序、不自动生成编号（项目文档治理方案 11.3）：
编号必须由调用方给，能力只拒绝缺编号、重编号与找不到定位。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.项目文档支持库.实现.清单 import (
    _成行, _拆列, _收尾, _结构, 编号列序,
)

操作集 = ("增", "删", "改")


def _编号序(表头: list[str], 编号列: str) -> int | None:
    """编号列序：优先按表头列名，退化为第一列（清单体例）。"""
    if 编号列 and 编号列 in 表头:
        return 表头.index(编号列)
    return 编号列序 if 表头 else None


def _首格(行: str) -> str:
    格们 = _拆列(行)
    return 格们[0] if 格们 else ""


def _拆条目(条目) -> list[str] | None:
    """条目可以是字符串（按竖线拆）或列值列表；结构不符返回 None。"""
    if isinstance(条目, str):
        return [格.strip() for 格 in 条目.strip().strip("|").split("|")]
    if isinstance(条目, (list, tuple)) and 条目:
        return [str(格).strip() for 格 in 条目]
    return None


def _追加点(数据行序: list[int], 插入位置: str, 现有编号: dict) -> tuple[int, str] | str:
    """尾部追加或某编号之后插入；返回 (插入行号, 变更说明) 或错误说明。"""
    if 插入位置 == "尾部":
        return (数据行序[-1] + 1) if 数据行序 else 3, "在尾部追加"
    if 插入位置 not in 现有编号:
        return f"插入位置 {插入位置} 在清单中找不到"
    return 现有编号[插入位置] + 1, f"在编号 {插入位置} 之后插入"


def 改清单条目(正文: str = None, 操作: str = None, 定位: str = None,
            条目=None, 插入位置: str = "尾部") -> 结果:
    """对 markdown 表格清单增 / 删 / 改一条条目，返回新正文。

    参数：正文（含表头行与分隔行的清单）；操作（增/删/改）；定位（删/改＝目标编号，
    增＝某编号之后）；条目（增/改的新条目：字符串或列值列表，须自带编号）；
    插入位置（增：``尾部`` 或 某编号）。
    返回：``{新正文, 变更说明, 条目数}``。**不自动生成编号**：条目缺编号、
    编号已存在（不复用）、定位或插入位置找不到编号，一律明确失败，不猜不补。
    """
    if not isinstance(正文, str) or not 正文.strip():
        return 结果.失败("参数不合法", "正文必须是非空文本", 来源="项目文档支持库")
    if 操作 not in 操作集:
        return 结果.失败("参数不合法", f"操作必须是 增/删/改 之一，收到 {操作!r}",
                     来源="项目文档支持库")
    结构 = _结构(正文)
    if 结构 is None:
        return 结果.失败("参数不合法", "未识别到 Markdown 表格清单（需表头行 + 分隔行）",
                     来源="项目文档支持库")
    行们, 表头, _, 数据行序 = 结构
    if _编号序(表头, "") is None:
        return 结果.失败("参数不合法", "表头为空，无法判定编号列", 来源="项目文档支持库")
    现有编号 = {_首格(行们[行号 - 1]): 行号 for 行号 in 数据行序}
    列值 = _拆条目(条目)

    if 操作 == "增":
        if 列值 is None or not 列值[0]:
            return 结果.失败("参数不合法", "增条目必须自带编号（编号不自动生成）",
                         来源="项目文档支持库")
        if 列值[0] in 现有编号:
            return 结果.失败("参数不合法", f"编号 {列值[0]} 已存在（编号不复用）",
                         来源="项目文档支持库")
        点位 = _追加点(数据行序, str(插入位置 or "尾部"), 现有编号)
        if isinstance(点位, str):
            return 结果.失败("参数不合法", 点位, 来源="项目文档支持库")
        行们.insert(点位[0] - 1, _成行(列值))
        变更 = f"{点位[1]}编号 {列值[0]}"

    elif 操作 == "删":
        if str(定位) not in 现有编号:
            return 结果.失败("参数不合法", f"定位编号 {定位} 在清单中找不到",
                         来源="项目文档支持库")
        del 行们[现有编号[str(定位)] - 1]
        变更 = f"删除编号 {定位}"

    else:  # 改
        if 列值 is None or not 列值[0]:
            return 结果.失败("参数不合法", "改条目必须自带编号（编号不自动生成）",
                         来源="项目文档支持库")
        if str(定位) not in 现有编号:
            return 结果.失败("参数不合法", f"定位编号 {定位} 在清单中找不到",
                         来源="项目文档支持库")
        if 列值[0] != str(定位) and 列值[0] in 现有编号:
            return 结果.失败("参数不合法", f"新编号 {列值[0]} 已存在（编号不复用）",
                         来源="项目文档支持库")
        行们[现有编号[str(定位)] - 1] = _成行(列值)
        变更 = f"改写编号 {定位}（新编号 {列值[0]}）"

    新正文 = _收尾(正文, 行们)
    新结构 = _结构(新正文)
    return 结果.成功结果({
        "新正文": 新正文,
        "变更说明": 变更,
        "条目数": len(新结构[3]) if 新结构 else 0,
    })
