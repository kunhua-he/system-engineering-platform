"""项目文档支持库 · 未命中词闭环（进程内实现，不对外暴露）。

**这个文件解决什么**（华哥 2026-09-18 原话：「你一开始搜到时候没搜到的词……
这样子越用就越好用了。本质上是一个不断的完善的过程。」）

现状是**检索失败的教训完全不沉淀**：搜不到 → 得到空列表 → 换个词再试 →
下次会话、下个子代理遇到同一个词**再撞一次**。检索的代价是「一次往返 + 一轮思考」，
同一个词重复撞墙纯属浪费（哲学 14.3：反复犯错的开发要补底层）。

**设计口径**：

1. **只登记「原始词 → 建议词」的实测映射，不做同义词表**。
   同义词表要人预先维护全且永远不全；实测映射是**按需长出来**的，
   而且能直接审计「哪些词我们一直搜不到」。
2. **写动作只能由调用方显式发起**（`登记未命中词` 能力）。
   `查询索引` 是只读能力，**不得**在检索失败时偷偷写库 ——
   那等于让「副作用：只读」的契约面对外撒谎。
3. **扩词只对零命中的那一组生效**，不做全局替换：把本来命中的组也换个词
   会把对的改坏（这条在方案里列为被否决做法）。
4. **命中次数由显式登记累加**，平台不自作主张记账。

表结构与 `索引库.py` 同库（`项目文档库.db`），不新建库文件。
"""

from __future__ import annotations

import sqlite3
import time
from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果

from .库连接 import _连接, _库路径

def 确保表(库文件: str = None) -> None:
    """惰性建表（幂等）：`未命中词` 表随第一次使用出现，不需调用方先初始化。

    建表语句统一放在 `库连接.py`（与其余三表同一份定义），
    本文件**不再自带一份** —— 两份定义迟早会漂移。
    """
    with _连接(库文件):
        pass


def 登记未命中词(项目名: str = None, 原始词: str = None, 建议词: str = None,
                 库文件: str = None) -> 结果:
    """登记「搜不到的词 → 该搜什么」的实测映射（UPSERT，幂等）。

    `建议词` 是**必填**：只登记「没搜到」没有意义，必须同时带上「那该搜什么」，
    否则这张表只会长成一张抱怨清单，无法用于自动扩词。
    """
    if not isinstance(项目名, str) or not 项目名.strip():
        return 结果.失败("参数不合法", "项目名必须是非空文本", 来源="项目文档支持库")
    词 = str(原始词 or "").strip()
    建 = str(建议词 or "").strip()
    if not 词:
        return 结果.失败("参数不合法", "原始词必须是非空文本", 来源="项目文档支持库")
    if not 建:
        return 结果.失败("参数不合法", "建议词必须是非空文本（只登记「没搜到」无法用于扩词）",
                        来源="项目文档支持库")
    if 词 == 建:
        return 结果.失败("参数不合法", f"建议词不得等于原始词（{词}），否则扩词无意义",
                        来源="项目文档支持库")
    现在 = time.time()
    try:
        确保表(库文件)
        with _连接(库文件) as 连接:
            连接.execute(
                "INSERT INTO 未命中词(项目名,原始词,建议词,命中次数,登记时间,更新时间) "
                "VALUES(?,?,?,0,?,?) "
                "ON CONFLICT(项目名,原始词) DO UPDATE SET 建议词=excluded.建议词, 更新时间=excluded.更新时间",
                (项目名, 词, 建, 现在, 现在))
    except ValueError as 错误:
        return 结果.失败("参数不合法", str(错误), 来源="项目文档支持库")
    except sqlite3.Error as 错误:
        return 结果.失败("索引库不可用", f"登记未命中词失败: {错误}", 来源="项目文档支持库")
    return 结果.成功结果({"项目名": 项目名, "原始词": 词, "建议词": 建, "操作": "已登记"})


def 列出未命中词(项目名: str = None, 库文件: str = None) -> 结果:
    """列出该项目的未命中词（按命中次数降序、原始词升序，稳定排序）。

    供 Agent 一次补齐建议词 —— 不用逐个词重新摸索。
    """
    if not isinstance(项目名, str) or not 项目名.strip():
        return 结果.失败("参数不合法", "项目名必须是非空文本", 来源="项目文档支持库")
    try:
        确保表(库文件)
        with _连接(库文件) as 连接:
            行表 = 连接.execute(
                "SELECT 原始词,建议词,命中次数,登记时间 FROM 未命中词 WHERE 项目名=? "
                "ORDER BY 命中次数 DESC, 原始词 ASC", (项目名,)).fetchall()
    except ValueError as 错误:
        return 结果.失败("参数不合法", str(错误), 来源="项目文档支持库")
    except sqlite3.Error as 错误:
        return 结果.失败("索引库不可用", f"查询未命中词失败: {错误}", 来源="项目文档支持库")
    词表 = [{"原始词": 原, "建议词": 建, "命中次数": int(次 or 0), "登记时间": float(时 or 0.0)}
            for 原, 建, 次, 时 in 行表]
    return 结果.成功结果({"项目名": 项目名, "未命中词列表": 词表, "条数": len(词表)})


def 取建议词(项目名: str, 词表: list[str], 库文件: str = None) -> dict[str, str]:
    """批量取建议词（**只读**，供 `查询索引` 做零命中扩词）。

    返回 `{原始词: 建议词}`，只含**在表里存在**的词 —— 没有记录的词不进返回，
    调用方据此判断"这一组该不该扩"。

    **失败不抛异常、不阻断检索**：扩词是增强，读不到表就当作没有建议词
    （返回空字典），让主检索照常返回原始结果。这里**不写库**。
    """
    if not 词表:
        return {}
    try:
        确保表(库文件)
        with _连接(库文件) as 连接:
            问号 = ",".join("?" * len(词表))
            行表 = 连接.execute(
                f"SELECT 原始词,建议词 FROM 未命中词 WHERE 项目名=? AND 原始词 IN ({问号})",
                (项目名, *词表)).fetchall()
    except (ValueError, sqlite3.Error):
        return {}
    return {原: 建 for 原, 建 in 行表}


def 累加命中次数(项目名: str, 原始词: str, 库文件: str = None) -> None:
    """把某条未命中词的「被扩词救回」次数 +1（**由登记路径调用，不在检索里写**）。

    为什么单独一个函数：`查询索引` 只读，扩词命中后**不写库**；
    若调用方希望记账，走显式登记。本函数保留给未来"扩词命中自动记账"的显式入口，
    当前无生产调用点（如实标注，不假装已接通）。
    """
    if not 项目名 or not 原始词:
        return
    try:
        with _连接(库文件) as 连接:
            连接.execute("UPDATE 未命中词 SET 命中次数=命中次数+1, 更新时间=? "
                         "WHERE 项目名=? AND 原始词=?", (time.time(), 项目名, 原始词))
    except (ValueError, sqlite3.Error):
        return


def 库文件路径(库文件: str = None) -> Path:
    """对外暴露库路径解析（测试与诊断用；口径与索引库一致，不另立一套）。"""
    return _库路径(库文件)
