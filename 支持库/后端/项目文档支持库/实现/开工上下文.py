"""项目文档支持库 · 开工上下文检索（取用端，进程内实现，不对外暴露）。

华哥 2026-09-18 定调：「类似于豆包的那种，先弄开工上下文。等于说你现在做什么，
你就先 HTML 请求一下，看看有没有历史的坑，搜一下。**而不是全量载入**。」

调用形态：给一句「我正要做什么」→ 返回 3–5 条相关坑（默认档：症状 + 判据 + 原文位置），
**不把 126KB 项目说明、1065 行哲学正文载入上下文**。

排序＝命中分 × 状态权重（`已固化` 靠前，因为它附带「已由判据强制」的结论，最省时间）。
`已失效` 态**不返回**（避免旧结论误导），但会在 `已失效条数` 里如实上报。

**返回体量分三档**（`细节级别`：索引 / 摘要 / 完整，2026-09-22 增）：
华哥定「所有注入提示词最高 2000 字符」后，改前默认一次调用回 5 条、整条回执 **3,363 字符**
（`根因`/`命中词`/`相关度`/`命中次数`/`检索词` 这些重字段全在里面）。
现默认 `索引` 档：每条只给「标识 + 一句话症状 + 判据 + 原文位置（漂移值）+ 提示」，
要 `根因`/全文传 `细节级别=摘要`，要逐字段（等于改前行为）传 `细节级别=完整`。
投影是**算完之后**的纯函数（`实现/检索粒度.py:投影坑结果`）——
命中判定、失效上报、状态机推进这些判据一个字不动，只改「回哪些字段 / 正文多长」。
"""

