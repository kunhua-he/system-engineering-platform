"""网页解析支持库包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
"""

from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现

from 支持库.后端.网络通信支持库.网页解析.实现.网页解析 import 提取网页标题
from 支持库.后端.网络通信支持库.网页解析.实现.网页解析 import 提取网页正文

__all__ = ["提取网页标题", "提取网页正文", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
    注册表.注册(
        能力实现(
            能力id="网络通信支持库.网页解析.提取网页标题",
            包id="支持库.后端.网络通信支持库.网页解析",
            实现函数=提取网页标题,
            参数=[{"名称": "网页内容", "类型": "文本型", "必填": True}],
            返回="结果型",
            说明="从 HTML 内容中提取 <title> 标签文本并去除首尾空白；无标题时返回空字符串",
        )
    )
    注册表.注册(
        能力实现(
            能力id="网络通信支持库.网页解析.提取网页正文",
            包id="支持库.后端.网络通信支持库.网页解析",
            实现函数=提取网页正文,
            参数=[{"名称": "网页内容", "类型": "文本型", "必填": True},
                  {"名称": "最大长度", "类型": "整数型", "必填": False}],
            返回="结果型",
            说明="从 HTML 内容中提取 body 文本：剔除 script/style 标签内容，空白归一化，截断到 最大长度",
        )
    )
