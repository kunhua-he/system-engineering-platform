"""融合排名：RRF 倒数排名融合 + 截断。

公式（Cormack/Clarke/Buettcher 2009，工业界默认融合算法）：
    得分(条) = Σ_路 权重_路 / (k + 该条在本路的最好名次)

为什么用排名不用分数：各路分数量纲不同（能力层命中数、符号层无分、文本层行号），
直接相加必须归一化，而归一化对异常值很脆。排名天然可比，所以不需要调参。

为什么 k=60：k 小则各路的第 1 名霸榜（单路第 1 就能压过多路共识），
k 大则拉平（低排名条目几乎与头部等价）。60 是原论文经验值。

★ 同一路内同一身份只计**最好名次一次**（RRF 原文口径）：
  文本层是逐行匹配，同一文件命中多行会产生多条同身份候选；
  若每条都累加，该文件会凭空拿到数倍得分、挤掉真正该出的答案
  （2026-09-21 实测缺陷：某文件拿到 0.0567 ≈ 3.5×1/61，能力层一条都没进前 3）。

★ 截断就是精确率控制：精确率 = 命中题数 / 全部返回条数，
  所以 期望条数 是硬参数——返回 10 条里只中 1 条就是 10%。

身份带路前缀（`能力层·xxx`），因为各路指向的东西不同粒度：
能力层指向能力、符号/文本层指向代码位置，不加前缀会被误当成同一条合并。
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

默认K = 60.0


def 融合排名(候选: list[dict], 各路明细: dict, 期望条数: int = 1,
             路权重: dict | None = None) -> dict:
    """把多路候选按 RRF 合成一个有序列表，只返回 期望条数 条。

    返回 结果型：命中列表/命中数/已截断/期望条数/k常数/路权重/各路明细。
    命中列表 每项带 身份/指向/得分/命中路数/各路排名——让调用方看得出
    「为什么它排第一」（在多路里都靠前），而不是只拿到一个名字。
    """
    权重表 = dict(路权重 or {})

    # 第一遍：按 (身份, 路) 去重，只留最好名次；同时收摘要。
    最好名次: dict[str, dict[str, int]] = {}
    元信息: dict[str, dict] = {}
    for 条 in 候选:
        路 = str(条.get("路", ""))
        序 = int(条.get("排名") or 0)
        身份 = str(条.get("身份", ""))
        if not 路 or 序 <= 0 or not 身份:
            continue
        路表 = 最好名次.setdefault(身份, {})
        旧序 = 路表.get(路)
        if 旧序 is None or 序 < 旧序:
            路表[路] = 序
        记录 = 元信息.setdefault(身份, {"身份": 身份,
                                       "指向": str(条.get("指向", "")),
                                       "摘要": str(条.get("摘要", ""))})
        if not 记录["摘要"] and 条.get("摘要"):
            记录["摘要"] = str(条["摘要"])
        if not 记录["指向"] and 条.get("指向"):
            记录["指向"] = str(条["指向"])

    # 第二遍：算分（每条路只计一次）
    得分表: dict[str, float] = {}
    for 身份, 路表 in 最好名次.items():
        for 路, 序 in 路表.items():
            权重 = float(权重表.get(路, 1.0))
            if 权重 <= 0:
                continue
            得分表[身份] = 得分表.get(身份, 0.0) + 权重 / (默认K + 序)

    排序 = sorted(得分表.items(), key=lambda 项: (-项[1], 项[0]))
    命中列表 = []
    for 身份, 得分 in 排序[:max(1, int(期望条数))]:
        记录 = dict(元信息[身份])
        记录["得分"] = round(得分, 8)
        记录["命中路数"] = len(最好名次[身份])
        记录["各路排名"] = dict(sorted(最好名次[身份].items()))
        命中列表.append(记录)

    return {
        "命中列表": 命中列表,
        "命中数": len(得分表),
        "已截断": len(得分表) > len(命中列表),
        "期望条数": int(期望条数),
        "k常数": 默认K,
        "路权重": {路: float(权重表.get(路, 1.0)) for 路 in 各路明细},
        "各路明细": 各路明细,
        "各路候选数": {路: int(明细.get("候选数") or 0) for 路, 明细 in 各路明细.items()},
    }
