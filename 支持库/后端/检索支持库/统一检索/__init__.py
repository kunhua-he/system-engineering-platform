"""统一检索：RRF 倒数排名融合，把多路检索合成一个入口。

为什么要有它（2026-09-21 华哥「搜索我觉得反而是最好是更加准确为主」）：
单路各有毛病——实测符号层「爱给多」（期望 1 条精确率 0.8，放到 10 条掉到 0.45）、
文本层「克制但漏」（召回仅 0.6）。RRF 只看排名不看分数，把「在多路里都排前面」
的条目顶上来，正好是你要的那一个。

公式（Cormack 2009，Elasticsearch/Qdrant/Vespa/OpenSearch 同款默认）：
    得分(条) = Σ_路 权重_路 / (k + 该条在本路的排名)

为什么 k=60：k 小则各路的第 1 名霸榜，k 大则拉平；60 是原论文经验值，工业界照抄至今。
为什么不用模型：纯算术、可复现、不生成文字就不会漂移；各路分数尺度不同也不用归一化。

★ 只返回 期望条数 条：精确率 = 命中题数 / 全部返回条数，
  返回 10 条里只中 1 条就是 10%——所以「给几条」是硬参数，不是越大越好。

调用方只从此入口导入，禁止深入 实现/ 目录；正式调用一律经 40007 网关。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.后端.检索支持库.统一检索.实现.融合 import 融合排名
from 支持库.后端.检索支持库.统一检索.实现.召回 import 多路召回, 默认路权重, 默认目标, 目标路表

__all__ = ["统一检索"]

包id = "支持库.后端.检索支持库.统一检索"


def _校验参数名序(参数契约表: dict[str, list[dict]],
                  注册参数名序: dict[str, list[str]]) -> None:
    """装配期闸门：注册参数名序必须逐字等于契约名序，否则本包装配失败。

    为什么要有它：入口原先手工重建参数表，将来契约加一个参数而入口漏加，网关就按
    入口的参数表传参——新参数被静默丢弃（本仓 2026-09-18 的「丢参」缺陷形态）。
    名序护盾让这种「漏参」在装配期就 raise，不再静默（参数事实源只有
    能力契约/参数契约.json 一处，哲学 12.1）。
    """
    for 能力id, 契约参数 in 参数契约表.items():
        注册名序 = 注册参数名序.get(能力id)
        if 注册名序 is None:
            raise ValueError(f"能力 {能力id} 有契约但注册处未声明参数名序")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(注册名序):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(注册名序)} 与契约参数名序 {契约名序} "
                "不一致：参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），"
                "入口不得另立一份")


def 注册能力(注册表) -> None:
    """由支持库加载器调用：注册统一检索原子能力。"""

# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 参数契约镜像（**函数内字面量**；本块由「丢参」缺陷修复注入，勿删）
    #
    # 缺陷溯源（2026-09-18 注入；2026-09-22 按 #204 铺开到剩余旧入口）：本入口原先手工
    # 重建注册参数声明，`默认值`/`说明` 全靠手抄，抄漏即静默丢参——网关按**入口注册表**
    # 过滤入参（`运行核心/统一网关/协议/类型规格.py` 的必填判据是 `项.get("必填") is 真`），
    # 入口表漏一个参数，新参数就传了没反应（#197 实测：`文件系统支持库.文件操作.目录树`
    # 漏了 `忽略模式`，两次验收都拿到旧行为）。修法：参数声明从 `能力契约/参数契约.json`
    # **整条透传**（`参数=_参数契约表[能力id]`），入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：
    #  ① `_参数契约表` 是字面量、键是常量，`开发工具/契约编译/漂移检测` 的 AST 读取器
    #     （`_静态字面量` 的 `ast.Subscript` 分支）能解析出**整条参数含 `必填`/`默认值`**；
    #     放在函数内是因为该读取器只收 `注册能力` 函数体内的赋值（`_扫描注册语句`）。
    #  ② 表内布尔位写**中文 `真`／`假`**（正式口径，真源 `公共契约/基础类型/逻辑类型.py`）；
    #     本文件顶部已 import 真/假，漂移检测读取器（`_导入常量绑定`）能静态解析出参数表。
    # 为什么按下标取而不是包一层 `_参数声明(能力id)`：包一层会让 AST 一律判「不可静态
    # 判定」，等于拿门禁覆盖率换干净（不可接受）。名序护盾由 `_注册参数名序` +
    # `_校验参数名序()` 承担，装配期逐条对契约核名序，不一致即 raise。
    from 公共契约.能力契约.契约 import 能力实现

    def _统一检索(关键词, 目标="能力", 期望条数=1, 候选深度=50, 路权重=None, 项目根="",
                 代码地图路径="", 网关地址="", 凭证=""):
        """薄包装：校验→召回→融合；必填与范围在实现内校验（进程内与 HTTP 同口径）。"""
        检索词 = str(关键词 or "").strip()
        if not 检索词:
            return 结果.失败("参数不合法", "关键词不能为空")
        检索目标 = str(目标 or 默认目标).strip()
        if 检索目标 not in 目标路表:
            return 结果.失败("参数不合法",
                            f"目标必须是 {'/'.join(目标路表)} 之一，收到 {检索目标!r}")
        try:
            条数 = int(期望条数)
            深度 = int(候选深度)
        except (TypeError, ValueError):
            return 结果.失败("参数不合法", "期望条数 / 候选深度 必须是整数型")
        if not 1 <= 条数 <= 50:
            return 结果.失败("参数不合法", f"期望条数必须在 1~50，收到 {条数}")
        if not 1 <= 深度 <= 200:
            return 结果.失败("参数不合法", f"候选深度必须在 1~200，收到 {深度}")
        if 路权重 is not None and not isinstance(路权重, dict):
            return 结果.失败("参数不合法", "路权重必须是字典型（如 {文本层: 0.3}）")

        候选, 各路明细 = 多路召回(关键词=检索词, 候选深度=深度, 目标=检索目标,
                                      项目根=项目根, 代码地图路径=代码地图路径,
                                      网关地址=网关地址, 凭证=凭证)
        # ★ 权重必须真生效（2026-09-21 实测缺陷）：RRF 只看排名，单路第 1 名 = 1/61，
        # 而质量差的路第 2 名 = 1/62 ≈ 同一量级 —— 不压权重，噪音就会挤掉正确答案。
        # 文本层实测召回仅 0.6、又爱把源码行当命中，故默认压到 0.6。
        生效权重 = dict(默认路权重)
        for 键, 值 in (路权重 or {}).items():
            try:
                生效权重[str(键)] = float(值)
            except (TypeError, ValueError):
                return 结果.失败("参数不合法", f"路权重.{键} 必须是数值型")
        return 结果.成功结果(融合排名(候选=候选, 各路明细=各路明细,
                                      期望条数=条数, 路权重=生效权重))

    _参数契约表 = {
        "检索支持库.统一检索.统一检索": [
            {"名称": "关键词", "类型": "文本型", "必填": 真, "默认值": None, "说明": "检索词；能力层按一句话说明匹配、符号层按名称子串、文本层按正则"},
            {"名称": "目标", "类型": "文本型", "必填": 假, "默认值": "能力", "说明": "选路目标：能力（默认，只走能力层，实测精确率 1.0）／代码（符号层+文本层）／全部（三路混排，实测精确率反而降到 0.875，因为三路指向的粒度不同：能力/代码位置/文本行）"},
            {"名称": "期望条数", "类型": "整数型", "必填": 假, "默认值": 1, "说明": "调用方本来想要几条（1~50）；精确率=命中数/返回条数，给多了就稀释，所以默认 1"},
            {"名称": "候选深度", "类型": "整数型", "必填": 假, "默认值": 50, "说明": "每路取多少候选再融合（1~200）；越大召回越全但越慢"},
            {"名称": "路权重", "类型": "字典型", "必填": 假, "默认值": None, "说明": "覆盖各路权重，如 {能力层:1.0,符号层:1.0,文本层:0.6}；不传用默认表"},
            {"名称": "项目根", "类型": "文本型", "必填": 假, "默认值": "", "说明": "项目根绝对路径；不传按本包位置推断"},
            {"名称": "代码地图路径", "类型": "文本型", "必填": 假, "默认值": "", "说明": "代码地图 SQLite 绝对路径；不传用 项目根/.codegraph/codegraph.db"},
            {"名称": "网关地址", "类型": "文本型", "必填": 假, "默认值": "", "说明": "唯一网关调用地址；不传用默认 40007"},
            {"名称": "凭证", "类型": "文本型", "必填": 假, "默认值": "", "说明": "网关凭证；不传从网关 launchd 配置读"},
        ],
    }
    _注册参数名序 = {
        "检索支持库.统一检索.统一检索": ["关键词", "目标", "期望条数", "候选深度", "路权重", "项目根", "代码地图路径", "网关地址", "凭证"],
    }
    _校验参数名序(_参数契约表, _注册参数名序)
# ===== 参数声明透传 结束 =====
    契约表 = [
        ("检索支持库.统一检索.统一检索", _统一检索,
         "RRF 倒数排名融合多路检索（能力层/符号层/文本层），只返回期望条数条；主指标精确率"),
    ]
    for 能力id, 函数, 说明 in 契约表:
        注册表.注册(能力实现(
            能力id=能力id, 包id=包id, 实现函数=函数,
            参数=_参数契约表[能力id], 返回="结果", 说明=说明))
