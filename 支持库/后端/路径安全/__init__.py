def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现
    for 能力id, 函数, 参数表 in [
        ("路径安全.校验路径", 校验路径, [{"名称": "根目录", "类型": "文本型", "必填": True, "默认值": None, "说明": "受控根目录"}, {"名称": "相对路径", "类型": "文本型", "必填": True, "默认值": None, "说明": "要校验的相对路径"}]),
        ("路径安全.校验文件名", 校验文件名, [{"名称": "文件名", "类型": "文本型", "必填": True, "默认值": None, "说明": "文件名"}]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.路径安全",
                实现函数=函数,
                参数=参数表,
                返回="结果",
                说明="路径安全支持库",
            )
        )
