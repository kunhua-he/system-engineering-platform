def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 缺陷溯源：本入口原先手工重建注册参数声明（`参数=...` 手写字面量），只写 名称/类型/必填，
    # `默认值` 整批缺声明（2026-09-24 实测：本包 15 条契约参数中 4 条漏声明，
    # 全仓 93 条）。后果：网关按入口契约表判参时拿不到默认值 —— 「≥10 秒须走异步腿」的守卫
    # 对 超时秒≥10 的能力**不传参即被绕过**（实测 执行命令/沙箱执行命令/发送请求 等 9 条）；
    # 其余能力的默认值同样在网关侧不可见。
    # 手工表一旦漏一个参数，新参数还会被网关**静默丢弃**（同族现场见未完成事项 #197）。
    # 修法：参数声明从 `能力契约/参数契约.json` **整条透传**，入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：漂移检测的 AST 读取器
    # （`_静态字面量` 的 `ast.Subscript` 分支）只收 `注册能力` 函数体内的赋值，
    # 包一层 `_参数声明(能力id)` 会让 AST 一律判「不可静态判定」，等于拿门禁覆盖率换干净。
    # 表内布尔位写中文 真/假（真源 公共契约/基础类型/逻辑类型.py）。
    # 契约名序/返回口径核验由装配期唯一闸门承担（`运行核心/加载器/生命周期管理/管理器.装配系统`
    # → 内核 `能力注册表.校验声明一致`），本入口不再另立第二份。
    _参数契约表 = {
        "数据操作支持库.数据交换.序列化JSON": [
            {"名称": "数据", "类型": "字典型", "必填": 真, "默认值": None},
        ],
        "数据操作支持库.数据交换.反序列化JSON": [
            {"名称": "文本", "类型": "文本型", "必填": 真, "默认值": None},
        ],
        "数据操作支持库.数据交换.序列化CSV": [
            {"名称": "行列表", "类型": "列表型", "必填": 真, "默认值": None},
        ],
        "数据操作支持库.数据交换.反序列化CSV": [
            {"名称": "文本", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "分隔符", "类型": "文本型", "必填": 假, "默认值": ""},
            {"名称": "严格模式", "类型": "逻辑型", "必填": 假, "默认值": 假},
        ],
        "数据操作支持库.数据交换.深合并": [
            {"名称": "基础", "类型": "字典型", "必填": 真, "默认值": None},
            {"名称": "覆盖", "类型": "字典型", "必填": 真, "默认值": None},
        ],
        "数据操作支持库.数据交换.解析YAML": [
            {"名称": "文本", "类型": "文本型", "必填": 真, "默认值": None},
        ],
        "数据操作支持库.数据交换.序列化YAML": [
            {"名称": "数据", "类型": "JSON值型", "必填": 假, "默认值": None},
        ],
        "数据操作支持库.数据交换.提取带前缀JSON": [
            {"名称": "文本", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "前缀", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "从末尾查找", "类型": "逻辑型", "必填": 假, "默认值": 真},
        ],
        "数据操作支持库.数据交换.压缩描述字段": [
            {"名称": "数据", "类型": "字典型", "必填": 真, "默认值": None},
            {"名称": "字段名", "类型": "文本型", "必填": 假, "默认值": "description"},
        ],
    }
# ===== 参数声明透传 结束 =====

    for 能力id, 函数, 返回类型 in [
        ("数据操作支持库.数据交换.序列化JSON", 序列化JSON, "结果"),
        ("数据操作支持库.数据交换.反序列化JSON", 反序列化JSON, "结果"),
        ("数据操作支持库.数据交换.序列化CSV", 序列化CSV, "结果"),
        ("数据操作支持库.数据交换.反序列化CSV", 反序列化CSV, "结果"),
        ("数据操作支持库.数据交换.解析YAML", 解析YAML, "结果"),
        ("数据操作支持库.数据交换.序列化YAML", 序列化YAML, "结果"),
        ("数据操作支持库.数据交换.深合并", 深合并, "结果"),
        ("数据操作支持库.数据交换.提取带前缀JSON", 提取带前缀JSON, "结果"),
        ("数据操作支持库.数据交换.压缩描述字段", 压缩描述字段, "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.数据操作支持库.数据交换",
                实现函数=函数,
                参数=_参数契约表[能力id],
                返回=返回类型,
                说明="数据交换原子能力",
            )
        )
