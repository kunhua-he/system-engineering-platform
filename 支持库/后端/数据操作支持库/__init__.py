def 注册能力(注册表) -> None:
    """聚合注册：收集所有子库的能力注册。"""
    import importlib
    for 子库名 in ['数据交换', '数据集合', '文本处理', '时间日期', '类型转换']:
        try:
            入口 = importlib.import_module("支持库.后端.数据操作支持库." + 子库名)
            注册函数 = getattr(入口, "注册能力", None)
            if callable(注册函数):
                注册函数(注册表)
        except Exception as 错误:
            raise RuntimeError(f"聚合子库 {子库名} 注册失败: {错误}") from 错误
