def 判定耗时超标(实测秒: Any, 阈值秒: Any = None, 名称: str = "") -> 结果:
    """判定一次工具调用的实测耗时是否超过阈值；超了就给出该走哪些加速方向。

    哲学 11.2（2026-09-19 华哥裁决）：「工具调用如果超过 5 秒的，就要考虑是哪里可以优化了」
    —— 本能力把这句裁决做成**可被门禁/工具链自动调用**的原子件，不靠人记得住。

    返回 {超标, 实测秒, 阈值秒, 倍率, 名称, 加速方向, 说明}；`加速方向` 是
    `加速方式表` 的机器可读子集（按适用面从宽到窄给，供调用方继续判断，**不替调用方拍板**）。
    """
    阈值 = 默认判定阈值秒 if 阈值秒 is None else _秒值(阈值秒)
    if 阈值 is None or 阈值 <= 0:
        return 结果.失败("参数不合法", "阈值秒 必须是正数", 来源=来源标记)
    秒 = _秒值(实测秒)
    if 秒 is None:
        return 结果.失败("参数不合法", "实测秒 必须是数值", 来源=来源标记)

    超标 = 秒 > 阈值
    倍率 = round(秒 / 阈值, 2)
    说明 = (
        f"耗时 {秒} 秒 > 阈值 {阈值} 秒（{倍率}×）：按哲学 11.2 停下判断原理，"
        "从加速方式表逐项排除，并给出「改前实测 / 改后实测」两列数字。"
        if 超标 else
        f"耗时 {秒} 秒 ≤ 阈值 {阈值} 秒：无需按 11.2 判定。"
    )
    return 结果.成功结果({
        "超标": 超标,
        "实测秒": 秒,
        "阈值秒": 阈值,
        "倍率": 倍率 if 超标 else 0.0,
        "名称": _文本值(名称),
        "加速方向": [dict(项) for 项 in 加速方式表] if 超标 else [],
        "说明": 说明,
    })


