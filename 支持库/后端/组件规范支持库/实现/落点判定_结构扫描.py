"""落点判定：把「要做的能力」判到「新库 / 新子包 / 补既有能力」三选一。

## 为什么需要它（华哥 2026-09-20 裁决，纯 bug 修复）
开新库还是补原子能力，此前**没有机器判据**——`新建支持库与模块指南.md` 第一节那张表
只写到 `支持库/后端/<某支持库>/<包名>`，**没说「<某支持库> 该怎么定」、也没有
「先查有没有既有库能承接」这一步**。结果是执行者只能靠猜：实测按源项目模块名
直接派了 6 个新库，其中「协议转换/请求审计/模型资源池」与既有 `大语言模型支持库`
（已有 `模型连接器` 25 个能力、明确支持三协议）大面积重叠 —— 正是哲学第 1 条
「不保留旧腿：同一件事两套实现即缺陷」要防的。

## 判据来源（全部来自本仓真实结构，不是发明）
1. **库名后缀定「大类型」**（实测 65 个库）：`*支持库`（26 领域）/`*描述`（5 只描述）/
   `*宿主`（2 承载运行）/`*提供者`·`*适配器`（24 第三方翻译）。
2. **库可以直接承载能力，也可以建子包**（实测：51 个库库根直接有 `能力定义.json`，
   14 个库建子包；子包最多的 `系统核心支持库` 14 个）。→ 所以「新库」不是唯一出路。
3. **库 = 领域，子包 = 子域**（如 `大语言模型支持库` → `模型连接器/流式推理/会话存储/…`）。

## 判定顺序（先窄后宽，先复用后新建）
① 先按关键词在**全仓既有能力**里找承担者 → 命中即 `补既有能力`（给出确切能力id）；
② 再按关键词在**既有子包名**里找同域 → 命中即 `补既有子包`；
③ 再按关键词在**既有库名**里找同领域 → 命中即 `新建子包`（落在该库下）；
④ 三条都不命中才 `新建库`，并给出按后缀规律推定的库名。

## 边界
只读：不写盘、不建包、不改任何文件。判定结论一律走返回值，附「依据」与「候选清单」，
使调用方能自行复核——不替调用方做业务取舍。
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假

#: 后端支持库根（相对项目根）；只扫法定正式根，不扫工程缓存与编译产物。
支持库根相对 = "支持库/后端"
前端根相对 = "支持库/前端"
适配层根相对 = "支持库/适配层"
模块库根相对 = "模块库"

#: 扫描时要跳过的目录名（缓存/产物/非常规）。
跳过目录 = frozenset(("__pycache__", "工程缓存", "说明", "能力数据", "验证场景",
                    "验证夹具", "夹具", "实现"))

#: 落点类型枚举（机器可判的四值）。
落点_补既有能力 = "补既有能力"
落点_补既有子包 = "补既有子包"
落点_新建子包 = "新建子包"
落点_新建库 = "新建库"

#: 库名后缀 → 大类型（实测 65 个库归纳；判据写在这里，不散落到各调用点）。
后缀大类型 = (
    ("支持库", "领域支持库（原子能力域）"),
    ("描述", "前端描述类（只描述不执行）"),
    ("宿主", "宿主类（承载运行/服务）"),
    ("提供者", "适配层提供者（第三方翻译）"),
    ("适配器", "适配层适配器（第三方翻译）"),
)


def 取项目根(项目根: Any) -> Path:
    """取项目根；空值即用本文件往上推四级（实现/包/库/支持库 → 项目根）。"""
    文本 = str(项目根 or "").strip()
    if 文本:
        return Path(文本).expanduser()
    return Path(__file__).resolve().parents[4]


def _读能力定义(包目录: Path) -> dict[str, Any] | None:
    """读一个包的 能力定义.json；读不到/坏 JSON 一律返回 None（不抛，交给上层汇总）。"""
    文件 = 包目录 / "能力定义.json"
    if not 文件.is_file():
        return None
    try:
        数据 = json.loads(文件.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return 数据 if isinstance(数据, dict) else None


def 扫描既有结构(项目根: Path) -> dict[str, Any]:
    """扫全仓既有「库 / 子包 / 能力」三层结构（只读）。

    返回 ``{"库": [...], "子包": [...], "能力": [...]}``：
    - 库：``{名称, 层, 路径相对, 后缀大类型, 库根直接承载, 子包清单}``
    - 子包：``{子包名, 包id, 所属库, 路径相对, 能力数}``
    - 能力：``{能力id, 中文名称, 说明, 包id, 库名, 子包名}``
    """
    库表: list[dict[str, Any]] = []
    子包表: list[dict[str, Any]] = []
    能力表: list[dict[str, Any]] = []

    for 层相对 in (支持库根相对, 前端根相对, 适配层根相对, 模块库根相对):
        层路径 = 项目根 / 层相对
        if not 层路径.is_dir():
            continue
        层名 = 层相对.split("/")[-1]
        for 库名 in sorted(os.listdir(层路径)):
            库路径 = 层路径 / 库名
            if not 库路径.is_dir() or 库名.startswith((".", "__")):
                continue
            大类型 = ""
            for 后缀, 说明 in 后缀大类型:
                if 库名.endswith(后缀):
                    大类型 = 说明
                    break
            子包名称表: list[str] = []
            # ① 库根直接承载能力（实测 51 个库如此）
            库根定义 = _读能力定义(库路径)
            if 库根定义:
                for 能力 in (库根定义.get("能力列表") or []):
                    能力表.append({
                        "能力id": str(能力.get("能力id") or ""),
                        "中文名称": str(能力.get("中文名称") or 能力.get("名称") or ""),
                        "说明": str(能力.get("说明") or ""),
                        "包id": str(库根定义.get("包id") or ""),
                        "库名": 库名, "子包名": "",
                    })
            # ② 库下子包
            for 子 in sorted(os.listdir(库路径)):
                子路径 = 库路径 / 子
                if not 子路径.is_dir() or 子.startswith((".", "__")) or 子 in 跳过目录:
                    continue
                子定义 = _读能力定义(子路径)
                if not 子定义:
                    continue
                子包名称表.append(子)
                子包表.append({
                    "子包名": 子, "包id": str(子定义.get("包id") or ""),
                    "所属库": 库名, "层": 层名,
                    "路径相对": f"{层相对}/{库名}/{子}",
                    "能力数": len(子定义.get("能力列表") or []),
                })
                for 能力 in (子定义.get("能力列表") or []):
                    能力表.append({
                        "能力id": str(能力.get("能力id") or ""),
                        "中文名称": str(能力.get("中文名称") or 能力.get("名称") or ""),
                        "说明": str(能力.get("说明") or ""),
                        "包id": str(子定义.get("包id") or ""),
                        "库名": 库名, "子包名": 子,
                    })
            库表.append({
                "库名": 库名, "层": 层名, "路径相对": f"{层相对}/{库名}",
                "后缀大类型": 大类型, "库根直接承载": bool(库根定义),
                "子包清单": 子包名称表,
            })
    return {"库": 库表, "子包": 子包表, "能力": 能力表}
