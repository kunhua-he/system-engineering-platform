                + "\n".join(f"from {包id}.实现.{模块名} import {e['名称']}" for e in 能力清单)
                + f'\n\n__all__ = {[e["名称"] for e in 能力清单]!r}\n\n\n'
                "def 注册能力(注册表) -> None:\n    \"\"\"由模块加载器调用。\"\"\"\n"
                "    from 公共契约.能力契约.契约 import 能力实现\n\n"
                "    for 能力id, 函数, 参数名, 返回类型, 说明 in [\n" + 注册行 + "\n    ]:"
