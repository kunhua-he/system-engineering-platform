def 读取数据源(包目录: Path) -> dict:
    """读取包目录下五个数据源；缺失文件返回空结构，不因单文件缺失中断。"""
    def 读取(相对路径: str) -> object:
        文件 = 包目录 / 相对路径
        return json.loads(文件.read_text(encoding="utf-8")) if 文件.is_file() else {}
    return {
        "能力定义": 读取("能力定义.json"),
        "参数契约": 读取("能力契约/参数契约.json"),
        "搜索数据": 读取("能力数据/能力搜索数据.json"),
        "验证引用": 读取("验证场景引用.json"),
        "包声明": 读取("包声明.json"),
    }


def 收集能力(数据: dict) -> list[dict]:
    """合并能力列表：能力定义优先，缺失时回退参数契约；参数表以参数契约为准。"""
    定义 = 数据["能力定义"]
    能力列表 = 定义.get("能力列表", []) if isinstance(定义, dict) else []
    契约数据 = 数据["参数契约"]
    契约列表 = 契约数据.get("能力契约", []) if isinstance(契约数据, dict) else []
    契约按id = {条目.get("能力id"): 条目 for 条目 in 契约列表}
    if not 能力列表:
        能力列表 = [{**条目, "中文名称": 条目.get("能力id", "").rsplit(".", 1)[-1]} for 条目 in 契约列表]
    结果列表 = []
    for 能力 in 能力列表:
        能力id = 能力.get("能力id", "")
        契约 = 契约按id.get(能力id)
        结果列表.append({
            "能力id": 能力id,
            "中文名称": 能力.get("中文名称", 能力id.rsplit(".", 1)[-1]),
            "版本": 能力.get("版本", ""),
            "说明": 能力.get("说明", ""),
            "参数": (契约 or 能力).get("参数", []),
            "返回": 能力.get("返回", ""),
            "错误码": 能力.get("错误码", []),
        })
    return 结果列表


def 生成调用示例(能力: dict, 搜索数据: list) -> tuple[str, bool]:
    """返回 (示例代码, 是否骨架)：优先能力搜索数据已有示例，否则按参数生成。"""
    for 条目 in 搜索数据:
        if 条目.get("能力id") != 能力["能力id"]:
            continue
        示例 = 条目.get("调用示例") or 条目.get("示例")
        if 示例:
            return str(示例).strip(), False
        break
    占位 = ", ".join(f"{参数.get('名称', '参数')}=值" for 参数 in 能力["参数"])
    return f"{能力['能力id']}({占位})", True


def 生成验证状态(数据: dict) -> str:
    """验证状态：按本包 `验证场景引用.json` 的**真实登记形态**渲染。

    全仓实测三种登记形态（2026-09-20 开工-20260920-182332-7166；136 份现场统计）：
      ① 条目含 `场景`（内嵌完整场景对象，92 条）：取 `场景.场景id` 与 `场景.目标步骤` 步数；
      ② 条目含 `场景id` + `场景文件` + `范围`（10 条）：直接取 `场景id`（`范围` 可能为空串）；
      ③ 条目只有 `场景文件`（88 条）：无场景名可渲染，**如实写文件名**并标注未登记场景id。

    原实现只读 `条目['场景id']` / `条目['场景范围']`，对 ①②③ 全部取到 None，
    渲染成 `已纳入验证场景：None（None）` —— 那是**垃圾行**（G2 血统的旧缺陷），
    经合并工具会真的写进说明书。本函数改为「有引用即取真值、无引用如实标未纳入」，
    **任何分支都不渲染 None**；三条正向 + 一条反向样本见 `验证场景/` 同名场景。
    """
    引用数据 = 数据.get("验证引用")
    引用列表 = 引用数据.get("验证场景引用", []) if isinstance(引用数据, dict) else []
    if not isinstance(引用列表, list):
        引用列表 = []
    描述列表: list[str] = []
    for 条目 in 引用列表:
        if not isinstance(条目, dict):
            continue
        内嵌场景 = 条目.get("场景")
        if isinstance(内嵌场景, dict) and 内嵌场景.get("场景id"):
            步数 = len(内嵌场景.get("目标步骤") or [])
            描述列表.append(f"{内嵌场景['场景id']}（本包 验证场景引用.json，{步数} 步）")
            continue
        if 条目.get("场景id"):
            范围 = 条目.get("范围") or ""
            来源 = 条目.get("场景文件") or "本包 验证场景引用.json"
            描述列表.append(f"{条目['场景id']}（{来源}{'，' + 范围 if 范围 else ''}）")
            continue
        if 条目.get("场景文件"):
            描述列表.append(f"{条目['场景文件']}（未登记场景id）")
            continue
    if not 描述列表:
        return "未纳入验证场景（暂无验证场景引用）"
    return "已纳入验证场景：" + "、".join(描述列表)


def 生成依赖段(数据: dict) -> list[str]:
    """`## 依赖能力` 段：取 `包声明.json` 的 `依赖`（唯一真源），有则渲染、无则不产该段。

    原实现只读 `能力定义.json.依赖`，而该文件**恒无此键**（实测：`支持库/后端/系统核心支持库/进程管理`
    包声明有 1 条依赖而能力定义无该键）⇒ G2 血统说明书**永远不产依赖段**，
    与 G1 血统「每能力一行 `- 依赖能力：…`」口径分叉，且真依赖同步不进说明书
    （实测 3 个包的真依赖未写进说明书）。本段与 G1 的 `## 依赖能力` 段同形态。
    """
    声明 = 数据.get("包声明")
    依赖列表 = 声明.get("依赖", []) if isinstance(声明, dict) else []
    if not isinstance(依赖列表, list) or not 依赖列表:
        return []
    行列表 = ["", "## 依赖能力"]
    for 依赖 in 依赖列表:
        if isinstance(依赖, dict):
            行列表.append(f"- 能力 `{依赖.get('能力', '')}` 版本约束 `{依赖.get('版本', '')}`")
    return 行列表 if len(行列表) > 2 else []



def 生成说明书文本(包目录: Path) -> str:
    """从包目录数据源生成 Agent 可读使用说明书全文。"""
    数据 = 读取数据源(包目录)
    定义 = 数据["能力定义"] if isinstance(数据["能力定义"], dict) else {}
    搜索数据 = 数据["搜索数据"] if isinstance(数据["搜索数据"], list) else []
    能力列表 = 收集能力(数据)
    行列表 = [
        f"# {包目录.name} 使用说明", "",
        f"- 包id：{定义.get('包id', '')}", f"- 版本：{定义.get('版本', '')}", "",
    ]
    行列表.extend(生成依赖段(数据))
    行列表.extend([
        "", "## 能力清单", "",
        "| 能力id | 名称 | 版本 | 返回 | 说明 |", "| --- | --- | --- | --- | --- |",
    ])
    for 能力 in 能力列表:
        行列表.append(f"| {能力['能力id']} | {能力['中文名称']} | {能力['版本']} | {能力['返回']} | {能力['说明']} |")
    for 能力 in 能力列表:
        行列表.extend([
            "", f"## {能力['能力id']}（{能力['中文名称']}）", "",
            f"**说明**：{能力['说明'] or '（无）'}", "",
            "**参数表**：", "", "| 参数 | 类型 | 必填 | 默认值 | 说明 |", "| --- | --- | --- | --- | --- |",
        ])
        if 能力["参数"]:
            for 参数 in 能力["参数"]:
                行列表.append(
                    f"| {参数.get('名称', '')} | {参数.get('类型', '')} | "
                    f"{'是' if 参数.get('必填', False) else '否'} | "
                    f"{参数.get('默认值', '')} | {参数.get('说明', '')} |"
                )
        else:
            行列表.append("| （无参数） | | | | |")
        行列表.extend([
            "", f"**返回结构**：{能力['返回']}（统一结果：成功/值/错误）", "",
            "**错误码表**：", "", "| 错误码 |", "| --- |",
        ])
        for 错误码 in 能力["错误码"]:
            行列表.append(f"| {错误码} |")
        示例, 是否骨架 = 生成调用示例(能力, 搜索数据)
        行列表.extend(["", "**调用示例**：", "", "```python", 示例, "```"])
        if 是否骨架:
            行列表.append("> 示例为骨架需验证：能力搜索数据无现成示例，按参数自动生成。")
        行列表.extend(["", f"**验证状态**：{生成验证状态(数据)}"])
    行列表.append("")
    return "\n".join(行列表)


def 校验输出目标(包目录: Path, 输出根目录: Path, *, 允许重建骨架: bool = False) -> Path:
    """校验并返回输出目标路径：默认拒绝覆盖；**骨架态**可显式重建；拒绝路径逃逸。

    ★ 骨架态重建（2026-09-18 补，归因见 `开发文档/分析/新建支持库回填链路归因_20260918.md`）：
    新建包刚生成时，说明书是**模板骨架**（含「骨架占位」等占位字样）。此时若不许可重建，
    作者改完真实实现后说明书写不回去 —— 回填链在此断裂，实测一个包因此卡住 40 分钟。
    许可条件**双重收紧**，只放行"确定没被人工改过"的骨架：
      ① 调用方显式传 `允许重建骨架=True`（不给默认放行）；
      ② 目标文件**确实命中骨架标记**（有骨架标记才可能被重建）。
    人工改过的说明书（无骨架标记）即便传了许可也**照样拒绝** —— 人工权威不被有损覆盖。
    """
    包目录 = Path(包目录).resolve()
    输出根目录 = Path(输出根目录).resolve()
    if not 包目录.is_dir():
        raise ValueError(f"包目录不存在: {包目录}")
    if not 输出根目录.is_dir():
        raise ValueError(f"输出根目录不是目录: {输出根目录}")
    说明目录 = 输出根目录 / "说明"
    目标路径 = 说明目录 / 说明书文件名
    for 路径 in (说明目录, 目标路径):
        if 路径.is_symlink():
            raise ValueError(f"路径逃逸拒绝: {路径}")
    if 说明目录.exists() and 说明目录.resolve() != 说明目录:
        raise ValueError(f"路径逃逸拒绝: {说明目录}")
    if 目标路径.exists():
        文本 = ""
        try:
            文本 = 目标路径.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            pass
        是骨架 = any(标记 in 文本 for 标记 in 骨架标记表)
        if not (允许重建骨架 and 是骨架):
            raise FileExistsError(f"拒绝覆盖已有说明书: {目标路径}")
    return 目标路径


def 生成说明书(包目录: Path, 输出根目录: Path, *, 允许重建骨架: bool = False,
            开工ID: str | None = None) -> Path:
    """生成 输出根目录/说明/使用说明.md 并返回写入路径。

    `允许重建骨架=True` 时，仅当目标仍是模板骨架态才覆盖（见 校验输出目标 的双重收紧）。

    `开工ID`（2026-09-25 开工-20260925-161955-849f）：本次改动的开工ID，逐跳透传到
    `模板公共件.写产物` → `写入文件`，供写腿第二判据核对活跃写租约所有者；受管路径缺它
    即写腿回 `越界`（经 `写入被拒` 原样上抛）。**只走形参**，不用全局变量/环境变量/模块级状态。
    """
    目标路径 = 校验输出目标(包目录, 输出根目录, 允许重建骨架=允许重建骨架)
    # P-10 接线：说明书是**入制品的产物**，故与模板产物走同一条腿、同一处判据
    # （`模板公共件.写产物`），不另起第二处强制点。
    from 支持库.后端.组件规范支持库.实现.模板公共件 import 写产物
    写产物(目标路径, 生成说明书文本(包目录), 系统根, 开工ID)
    return 目标路径
