"""落点判定：把「要做的能力」判到四值之一，并给出确切落点与依据。

判定顺序（先窄后宽，先复用后新建）：
① 既有能力命中 → 补既有能力；② 既有子包同域 → 补既有子包；
③ 既有库同领域 → 新建子包；④ 全部落空 → 新建库。

匹配口径：**双字滑窗 + 中文名/说明/能力id 三处命中加权**（与底座既有
`模块库/开工编排/实现/任务类型规范.切词` 同口径，不引入分词库、不调大模型）。

为什么不用模糊搜索定重复：实测 `能力目录.搜索能力` 是**相关度检索**，
「请求日志记录」会命中 OCR 能力、「代码签名」会命中代码地图查询关系 ——
拿它当判据会得出「全是重复」的假结论。故本判定**只认名字里真的含有
关键片段**，并把命中清单原样回带，让调用方能自行复核。
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假
from 支持库.后端.组件规范支持库.实现.落点判定_结构扫描 import (
    落点_新建库, 落点_新建子包, 落点_补既有子包, 落点_补既有能力,
    取项目根, 扫描既有结构,
)
from 支持库.后端.组件规范支持库.实现.落点判定_相关度 import (
    主干段表, 算相关度, 泛化词, 阈值_同域,
)

#: 单次返回的候选上限（防把全仓命中塞回调用方）。
候选上限 = 8


#: 机械推库名时要剥掉的首尾单字：这三类字本身不构成领域名，
#: 只说明「对谁做/在哪做/怎么做」，留着会得到 `把请求挂到本支持库` 这类废名。
_首尾废字 = "把在并做成对的了和与及为于将用让给从到就都也还很非常个些"


def 判落点(要做的能力: Any = None, 关键片段清单: Any = None,
           项目根: Any = None) -> Any:
    """把「要做的能力」判到落点；返回统一结果信封。

    参数：
    - ``要做的能力``：中文描述（如「三协议请求体互转」）。必填。
    - ``关键片段清单``：可选，调用方指定的关键片段（如 ``["协议","互转","载荷"]``）；
      不传则由 ``要做的能力`` 自动双字切词。
    - ``项目根``：可选，缺省由本文件位置上推。

    返回 ``结果.成功结果({落点类型, 建议落点, 依据, 候选能力, 候选子包, 候选库,
    后续动作})``；``要做的能力`` 为空时按 ``参数不合法`` 明确拒绝（不静默给默认落点）。
    """
    from 公共契约.基础类型.结果类型 import 结果

    描述 = str(要做的能力 or "").strip()
    if not 描述:
        return 结果.失败("参数不合法", "要做的能力 不能为空（请给一句「我要做什么能力」）")
    根 = 取项目根(项目根)
    if not 根.is_dir():
        return 结果.失败("参数不合法", f"项目根不存在: {根}")

    结构 = 扫描既有结构(根)

    def _评(候选: dict[str, Any], 目标文本: str) -> dict[str, Any]:
        """给一条候选算相关度（读数原样回带，可自行复核）。"""
        结果 = 算相关度(描述, 目标文本)
        return {**候选, **结果}

    # ── ① 既有能力命中 → 补既有能力 ──
    # 判据用「中文名称 + 能力id + 说明」三处（说明里常带协议/技术专名，
    # 实测「三协议请求体互转」与 归一化对话响应 的同域关系只在说明里体现）
    命中能力: list[dict[str, Any]] = []
    for 能力 in 结构["能力"]:
        评 = _评(能力, f"{能力['中文名称']}{能力['能力id']}{能力['说明']}")
        if 评["是否同域"]:
            命中能力.append(评)
    # ── ② 既有子包同域 → 补既有子包 ──
    命中子包: list[dict[str, Any]] = []
    for 子包 in 结构["子包"]:
        评 = _评(子包, f"{子包['子包名']}{子包['包id']}")
        if 评["是否同域"]:
            命中子包.append(评)
    # ── ③ 既有库同领域 → 新建子包 ──
    命中库: list[dict[str, Any]] = []
    for 库 in 结构["库"]:
        评 = _评(库, f"{库['库名']}{''.join(库['子包清单'])}")
        if 评["是否同域"]:
            命中库.append(评)

    命中能力.sort(key=lambda x: (-x["分数"], x["能力id"]))
    命中子包.sort(key=lambda x: (-x["分数"], x["子包名"]))
    命中库.sort(key=lambda x: (-x["分数"], x["库名"]))

    # ── ④ 定论（先窄后宽）──
    if 命中能力:
        首 = 命中能力[0]
        落点类型 = 落点_补既有能力
        建议落点 = 首["能力id"]
        依据 = (f"既有能力「{首['能力id']}」与本次描述同域（相关度 {首['分数']:.0f}；"
               f"主干命中 {首['主干命中']}／专名命中 {首['专名命中']}／"
               f"覆盖度 {首.get('覆盖度')}）—— "
               f"按哲学第 1 条「同一件事两套实现即缺陷」，"
               f"应扩展该能力或在其所属包内补能力，不新建第二个同类包")
    elif 命中子包:
        首 = 命中子包[0]
        落点类型 = 落点_补既有子包
        建议落点 = 首["路径相对"]
        依据 = (f"既有子包「{首['子包名']}」（属 {首['所属库']}，已有 {首['能力数']} 个能力）"
               f"与本次描述同域（相关度 {首['分数']:.0f}）—— 应把新能力补进该子包")
    elif 命中库:
        首 = 命中库[0]
        落点类型 = 落点_新建子包
        建议落点 = f"{首['路径相对']}/<新子包名>"
        依据 = (f"既有库「{首['库名']}」（{首['后缀大类型'] or '未归后缀'}，"
               f"现有子包 {len(首['子包清单'])} 个：{首['子包清单'][:6]}）与本次描述同领域 —— "
               f"库是领域、子包是子域，应在该库下新建子包，而不是新开一个库")
    else:
        落点类型 = 落点_新建库
        # 库名是**业务取舍，工具不替调用方拍**。这里只给一个机械参考名，并如实标注。
        # 实测踩坑：先前用「主干词滑窗最长候选」会产出 `源码编译成支持库`（5 字窗口
        # 截到动词中间）、`请求挂到本支持库`（截断在半个词上）这种废名。
        # 改为三步：① 取最长连续中文段（整段是完整词意，不会截在词中间）
        #           ② 剥掉首尾的介词/动词/助词单字（把/在/并/做/成/的/了…）
        #           ③ 限长 6 字，超了截断并标注
        中文段 = [段 for 段 in 主干段表(描述) if 段 not in 泛化词]
        领域名 = max(中文段, key=len) if 中文段 else ""
        领域名 = 领域名.strip(_首尾废字)
        if len(领域名) > 6:
            领域名 = 领域名[:6]
        候选名 = f"{领域名}支持库" if 领域名 else "新领域支持库"
        建议落点 = f"支持库/后端/{候选名}"
        依据 = ("全仓既有能力/子包/库三层均无同域命中 —— 属真缺口，可新建库；"
               "库名按实测后缀规律取「领域名+支持库」（后端领域）/「+描述」（前端只描述）"
               "/「+宿主」（承载运行）/「+提供者」（第三方翻译）。"
               f"★ 本建议名由主干词「{领域名 or '（未取到）'}」机械推得，**命名请自行定夺**："
               "库名是业务取舍，工具只保证后缀大类型对得上。")

    后续动作 = {
        落点_补既有能力: ["按 建议落点 的能力id 读其所属包 能力定义.json（唯一手编源）",
                      "在该包 能力定义.json 的 能力列表 内新增/扩展能力条目",
                      "重跑契约编译器与包体检，再重算摘要"],
        落点_补既有子包: ["按 建议落点 读该子包 能力定义.json",
                      "在 能力列表 内新增能力，不改包id（包id 不变即对外无破坏）",
                      "重跑契约编译器与包体检，再重算摘要"],
        落点_新建子包: ["用 生成支持库模板 建新子包，输出目录落在 既有库/新子包 下",
                      "包id 按「支持库.<层>.<库>.<子包>」三段式（照该库既有子包命名）",
                      "编译→体检→摘要→补验证场景"],
        落点_新建库: ["确认确无承接者后，用 生成支持库模板 建库",
                    "库根可直接承载能力（实测 51 个库如此），也可另建子包层（14 个库如此）",
                    "编译→体检→摘要→补验证场景"],
    }[落点类型]

    return 结果.成功结果({
        "落点类型": 落点类型,
        "建议落点": 建议落点,
        "依据": 依据,
        "后续动作": 后续动作,
        "候选能力": [{k: v for k, v in x.items() if k != "说明"} for x in 命中能力[:候选上限]],
        "候选子包": 命中子包[:候选上限],
        "候选库": [{k: v for k, v in x.items()} for x in 命中库[:候选上限]],
        "扫描规模": {"库": len(结构["库"]), "子包": len(结构["子包"]),
                  "能力": len(结构["能力"])},
        "判定说明": ("先窄后宽：先查既有能力→再查既有子包→再查既有库→全空才新建库。"
                  f"判决阈值为 {阈值_同域:.0f} 分：专名命中（协议/技术专名）与 3 字以上"
                  "主干词命中是主信号，泛化词（转换/校验/构建…)一律不计分 —— "
                  "它们出现在几十个能力名里，拿它们判「同一件事」必然误命中。"
                  "命中清单与各级命中项已原样回带，可自行复核，不替你下业务取舍。"),
    })
