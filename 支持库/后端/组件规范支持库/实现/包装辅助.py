"""组件规范支持库 能力包装层公共辅助：参数归一 + 统一失败码映射。

包装层只做两件事（不复制任何第二套算法，算法一律在 实现/*.py 里）：
1. **参数归一**：把网关/进程内传来的值归一成内部实现期望的形状；
2. **统一失败码映射**：把内部实现自带的失败码收敛到网关已登记的错误码。

错误码硬约束：包装层返回的码必须已存在于
`运行核心/统一网关/本地网关.py::公开错误码状态映射`，否则网关回落 500
（六环门禁「能力定义声明码 ⊆ 状态映射码」会红）。内部实现里那几个
**未登记**的历史码在 `统一失败码表` 里做等义收敛，不新增网关码。
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from 公共契约.基础类型.结果类型 import 结果

来源 = "组件规范支持库"

# 包装层唯一可对外的码字面量（**显式登记**，与
# `运行核心/统一网关/本地网关.py::公开错误码状态映射` 同名同字）：
# 包装层只认这一集合，集合外一律收敛，绝不把未登记的内部码透给调用方
# （缺键在网关侧回落 500，等于让调用方拿到「没有原因的失败」）。
已登记码字面量 = frozenset({
    "参数不合法", "参数类型不合法", "类型不合法", "能力重复", "路径逃逸",
    "无提供者", "包目录不存在", "包无正式文件", "能力不存在", "已存在",
    "写入失败", "摘要生成失败", "内部错误",
})

# 内部实现自带码 → 网关已登记等义码（语义相同的收口，不发明新码）。
# 内部实现是历史产物（如 核心快照模板 的 `参数无效`、技能模板生成器 的
# `已存在文件`），它们的码字面量不进 能力定义.json，故必须在包装层收敛；
# 表里每一条都必须落在 已登记码字面量 内（本文件自校验，见 __init__ 说明）。
统一失败码表 = {
    "同名能力": "能力重复",
    "文件已存在": "已存在",
    "已存在文件": "已存在",
    "参数无效": "参数不合法",
    "快照损坏": "写入失败",
    "未实现": "能力不存在",
}

# 可重试码：只读类瞬时故障可安全重试；参数/冲突类不可重试。
可重试码表 = {"写入失败", "摘要生成失败"}


def 路径参数(值: Any) -> Path | None:
    """归一路径类参数：空/非文本返回 None（由调用方如实报 参数不合法）。"""
    if isinstance(值, Path):
        return 值
    if isinstance(值, str) and 值.strip():
        return Path(值)
    return None


def 文本参数(值: Any, 默认: str = "") -> str:
    """归一文本类参数：非文本或空文本回落到默认值。"""
    if isinstance(值, str) and 值.strip():
        return 值
    return 默认


def 列表参数(值: Any) -> list | None:
    """归一列表类参数：非列表返回 None（由调用方如实报 参数不合法）。"""
    return 值 if isinstance(值, list) else None


def 包声明取值(包目录: Path, 键名: str) -> str:
    """从 包声明.json 读取指定键；不可读或缺失返回空串（由调用方如实报错）。"""
    声明路径 = 包目录 / "包声明.json"
    if not 声明路径.is_file():
        return ""
    try:
        声明 = json.loads(声明路径.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError, UnicodeDecodeError):
        return ""
    if not isinstance(声明, dict):
        return ""
    值 = 声明.get(键名)
    return 值 if isinstance(值, str) else ""


def 归一失败码(码: Any, *, 缺省: str = "内部错误") -> str:
    """把内部实现返回的失败码收敛到网关已登记码字面量。

    三段判定，顺序固定：内部历史码查 `统一失败码表` 等义收敛 → 本包已登记
    字面量原样透出 → 其余一律回落 `内部错误`（**绝不把未登记码透给调用方**）。
    """
    文本 = str(码 or "").strip()
    if 文本 in 统一失败码表:
        return 统一失败码表[文本]
    if 文本 in 已登记码字面量:
        return 文本
    return 缺省


def 失败(码: Any, 说明: str, *, 详情: dict | None = None) -> 结果:
    """统一失败返回：码经收敛，说明原样（不吞异常、不伪造成功）。"""
    最终码 = 归一失败码(码)
    return 结果.失败(最终码, 说明, 来源=来源,
                    可重试=最终码 in 可重试码表, 详情=详情)
