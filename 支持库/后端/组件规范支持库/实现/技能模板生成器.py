"""技能包模板生成器：一次生成技能包六件套 + 受控执行桥接脚本骨架 + 索引登记。

产出（严格对齐 `技能库.技能包.校验技能包` 的必需清单）：
    <技能根目录>/<技能目录名>/
        SKILL.md           Agent 读的提示词（YAML 头 + 说明）
        契约.json           参数契约（Agent 据此组参，执行器据此校验）
        工作流.json         步骤（只给执行器，不返回给 Agent）
        依赖.json           标准库 / 第三方 / 项目模块
        验证声明.json       用例（必须至少一条真实正向用例，禁空转）
        scripts/<入口脚本>   桥接脚本（stdin JSON 进，stdout JSON 出）
生成后调用 `技能库.技能索引.生成索引` 写回 `索引.json`——索引只由技能库能力派生，
本生成器不重复实现索引逻辑（结果唯一即收口）。

防御：目标技能目录已存在文件即拒绝覆盖（返回已存在清单）；技能目录名与入口脚本名
含 `../`、反斜杠、绝对路径一律拒绝（路径逃逸）；能力标识/名称/参数/验证用例缺失拒绝；
没有验证用例直接拒绝（空转即杀：没有结果的东西不需要存在）。

用法（Python 函数调用，无命令行参数）：

    unset PYTHONPATH
    python3.14 -c "
    import sys; sys.path.insert(0, '.')
    from 支持库.后端.组件规范支持库.实现.技能模板生成器 import 生成技能模板
    结果 = 生成技能模板(
        技能根目录='技能根示例', 技能目录名='示例技能',
        能力标识='示例.文本统计', 名称='文本统计', 分类='文本',
        说明='给一段中文文本，返回字符数。',
        参数=[{'名称': '文本', '类型': '文本型', '必填': 真, '默认值': None, '说明': '待统计文本'}],
        验证用例=[{'说明': '中文短句', '参数': {'文本': '华世王镞 护肤'}, '预期': {'字符数': 7}}],
    )
    print(结果.成功, 结果.错误码, 结果.错误说明)
    "
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

def _定位项目根() -> Path:
    """向上定位项目根：判据本体在 `公共契约/运行时/导入前缀.取系统根`（唯一实现）。

    本函数在**自举段**被调用（推导本身就是让下面 `from 公共契约…` 能成立的前置），
    故内联同一套锚目录判据；形状由测试逐字钉住。
    """
# 自举前只能用标准库：本文件可能被当脚本跑（`sys.path[0]` 是 `实现/`），平台模块此刻
# **不可导入** ⇒ 不能调 `公共契约/运行时/导入前缀`（循环依赖）。判据仍是**同一套锚目录**
# （不是 `parents[N]` 那种一改目录结构就静默指错树的层数写法），与共享模块逐字同判；
# 形状由 `测试中心/开发工具/测试_导入前缀.py` 的 `自举段形状` 钉住，改这里必须同批改它。
    系统根 = next(
        祖先 for 祖先 in Path(__file__).resolve().parents
        if (祖先 / "支持库").is_dir() and (祖先 / "模块库").is_dir()
    )
    return 系统根


# 项目根入 sys.path 必须在任何项目内导入之前（直接执行时项目根不在 path）。
_项目根 = _定位项目根()
if str(_项目根) not in sys.path:
    sys.path.insert(0, str(_项目根))

from 公共契约.基础类型.结果类型 import 结果

来源标识 = "技能模板生成器"
默认步骤 = [
    {"步骤": "读取 stdin 的 JSON 载荷", "说明": "参数在 参数 字段下"},
    {"步骤": "执行技能主体逻辑", "说明": "占位：替换为真实实现，禁止空转"},
    {"步骤": "向 stdout 打印 JSON 结果", "说明": "执行器解析 stdout 作为技能返回值"},
]
桥接脚本骨架 = '''# -*- coding: utf-8 -*-
"""{名称}：技能桥接脚本（stdin JSON 进，stdout JSON 出）。

契约：{能力标识}

参数经 stdin 传入，形如 {{"参数": {{...}}}}；本脚本只依赖 依赖.json 里声明的模块。
输出必须是单个 JSON 对象；失败时输出 {{"成功": false, "错误码": "...", "错误说明": "..."}}。
"""

import json
import sys


def 主流程(参数: dict) -> dict:
    """占位实现：原样回执参数键。**必须替换为真实逻辑后再交付。**"""
    return {{
        "技能标识": "{能力标识}",
        "收到参数键": sorted(参数.keys()),
        "参数个数": len(参数),
    }}


def 主函数() -> int:
    原文 = sys.stdin.read()
    try:
        载荷 = json.loads(原文) if 原文.strip() else {{}}
    except json.JSONDecodeError as 错误:
        print(json.dumps({{"成功": False, "错误码": "参数不合法",
                          "错误说明": f"stdin 不是合法 JSON: {{错误}}"}}, ensure_ascii=False))
        return 0
    参数 = 载荷.get("参数") or {{}}
    if not isinstance(参数, dict):
        print(json.dumps({{"成功": False, "错误码": "参数不合法",
                          "错误说明": "参数必须是 JSON 对象"}}, ensure_ascii=False))
        return 0
    try:
        值 = 主流程(参数)
    except Exception as 错误:  # 失败要明确，不吞
        print(json.dumps({{"成功": False, "错误码": "脚本执行失败",
                          "错误说明": f"{{type(错误).__name__}}: {{错误}}"}}, ensure_ascii=False))
        return 0
    print(json.dumps({{"成功": True, "值": 值}}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(主函数())
'''


def _写(路径: Path, 内容: str) -> None:
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(内容, encoding="utf-8")


def _转JSON文本(数据: Any) -> str:
    return json.dumps(数据, ensure_ascii=False, indent=2) + "\n"


def _名称安全(名: str, 字段: str) -> str:
    """路径逃逸与非法命名检查；返回错误说明，空串表示通过。"""
    文本 = str(名 or "").strip()
    if not 文本:
        return f"{字段} 必填"
    if 文本 in (".", "..") or ".." in 文本 or "/" in 文本 or "\\" in 文本 or 文本.startswith("~"):
        return f"{字段} 非法（不允许路径分隔与上级引用）: {文本}"
    if Path(文本).is_absolute():
        return f"{字段} 不允许绝对路径: {文本}"
    return ""


def _规范参数(参数: list) -> tuple[list, str]:
    规范 = []
    for 项 in 参数 or []:
        if not isinstance(项, dict) or not 项.get("名称"):
            return [], "每个参数必须含 名称"
        类型 = str(项.get("类型") or "文本型")
        if 类型 not in ("文本型", "整数型", "双精度数型", "逻辑型", "字典型", "列表型"):
            return [], f"参数 {项['名称']} 的类型不是正式类型名: {类型}"
        规范.append({"名称": str(项["名称"]), "类型": 类型,
                     "必填": bool(项.get("必填", False)),
                     "默认值": 项.get("默认值"), "说明": str(项.get("说明") or "")})
    return 规范, ""


def _规范用例(用例: list) -> tuple[list, str]:
    if not 用例:
        return [], "验证用例至少 1 条（空转即杀：没有结果的东西不需要存在）"
    规范 = []
    for 项 in 用例:
        if not isinstance(项, dict) or not 项.get("说明"):
            return [], "每条用例必须含 说明"
        if "预期" not in 项:
            return [], f"用例「{项.get('说明')}」必须给出 预期"
        规范.append({"说明": str(项["说明"]), "参数": 项.get("参数") or {}, "预期": 项["预期"]})
    return 规范, ""


def 生成技能模板(
    技能根目录: str | None = None,
    技能目录名: str | None = None,
    能力标识: str | None = None,
    名称: str | None = None,
    分类: str = "通用",
    说明: str = "",
    参数: list | None = None,
    返回: str = "字典型",
    入口脚本: str | None = None,
    步骤: list | None = None,
    依赖: dict | None = None,
    验证用例: list | None = None,
) -> 结果:
    """生成技能包六件套；索引由 `技能库.技能索引.生成索引` 统一派生，本函数不写索引。"""
    for 字段, 值 in (("技能根目录", 技能根目录), ("技能目录名", 技能目录名),
                    ("能力标识", 能力标识), ("名称", 名称)):
        if not 值:
            return 结果.失败("参数不合法", f"{字段} 必填", 来源=来源标识)
    for 字段, 值 in (("技能目录名", 技能目录名), ("入口脚本", 入口脚本 or 名称 + ".py")):
        问题 = _名称安全(值, 字段)
        if 问题:
            return 结果.失败("参数不合法", 问题, 来源=来源标识)
    if 返回 not in ("文本型", "整数型", "双精度数型", "逻辑型", "字典型", "列表型"):
        return 结果.失败("参数不合法", f"返回类型不是正式类型名: {返回}", 来源=来源标识)

    参数规范, 参数问题 = _规范参数(参数 or [])
    if 参数问题:
        return 结果.失败("参数不合法", 参数问题, 来源=来源标识)
    用例规范, 用例问题 = _规范用例(验证用例 or [])
    if 用例问题:
        return 结果.失败("参数不合法", 用例问题, 来源=来源标识)

    根 = Path(技能根目录).expanduser().resolve()
    技能目录 = 根 / str(技能目录名)
    入口名 = str(入口脚本 or f"{名称}.py")
    待写 = {
        "SKILL.md": None, "契约.json": None, "工作流.json": None, "依赖.json": None,
        "验证声明.json": None, f"scripts/{入口名}": None,
    }
    已存在 = [名 for 名 in 待写 if (技能目录 / 名).is_file() or (技能目录 / 名).is_dir()]
    if 已存在:
        # 码字面量必须落在网关 `公开错误码状态映射` 内（本包能力定义声明的是 已存在）：
        # 这里原写 `已存在文件` 是内部自造码，网关缺键回落 500，也让实现侧产生码
        # 判据（公开调用完整性门禁）长期报未登记；语义等价，故直接用登记字面量。
        return 结果.失败("已存在", f"目标技能包已存在文件，拒绝覆盖: {已存在}",
                        来源=来源标识, 详情={"技能目录": str(技能目录), "已存在": 已存在})

    依赖规范 = {"解释器": "固定解释器",
              "标准库": list((依赖 or {}).get("标准库") or ["json", "sys"]),
              "第三方": list((依赖 or {}).get("第三方") or []),
              "项目模块": list((依赖 or {}).get("项目模块") or [])}
    契约 = {"能力标识": str(能力标识), "名称": str(名称), "分类": str(分类),
           "版本": "1.0.0", "执行入口": "脚本执行器", "路径": str(技能目录名),
           "参数": 参数规范, "返回": 返回}
    工作流 = {"入口脚本": 入口名, "步骤": list(步骤 or 默认步骤)}
    验证声明 = {"契约版本": "技能验证/v1", "用例": 用例规范}
    _写(技能目录 / "契约.json", _转JSON文本(契约))
    _写(技能目录 / "工作流.json", _转JSON文本(工作流))
    _写(技能目录 / "依赖.json", _转JSON文本(依赖规范))
    _写(技能目录 / "验证声明.json", _转JSON文本(验证声明))
    _写(技能目录 / "SKILL.md", _技能说明(名称, 能力标识, 说明, 参数规范, 用例规范))
    _写(技能目录 / "scripts" / 入口名, 桥接脚本骨架.format(名称=名称, 能力标识=能力标识))

    值 = {"技能目录": str(技能目录), "能力标识": str(能力标识), "六件套": sorted(待写),
         "参数个数": len(参数规范), "用例条数": len(用例规范),
         "下一步": ["替换 scripts/%s 的占位实现" % 入口名,
                  "核对验证声明.json 的预期与真实返回一致",
                  "调用 技能库.技能包.校验技能包（技能根目录 + 技能标识或路径）",
                  "调用 技能库.受控执行.运行技能包（技能根目录 + 能力标识 + 参数）做真实验收"]}
    # 索引只由 `技能库.技能索引.生成索引` 从各技能 契约.json 派生（结果唯一即收口）：
    # 本生成器是纯文件工具（与 支持库/模块 模板生成器 一致，不调能力、不重复实现索引逻辑）。
    # 批量生成/变更技能包后统一调用一次该能力，避免每生成一个技能就扫描一遍技能根。
    值["索引提示"] = {"能力id": "技能库.技能索引.生成索引",
                   "参数": {"技能根目录": str(根), "写回索引": True},
                   "说明": "生成或变更技能包后调用一次，写回 索引.json"}
    值["下一步"].append("调用 技能库.技能索引.生成索引（技能根目录=%s，写回索引=true）写回索引" % 根)
    return 结果.成功结果(值)


def _技能说明(名称: str, 能力标识: str, 说明: str, 参数: list, 用例: list) -> str:
    参数行 = "\n".join(
        f"- `{p['名称']}`（{p['类型']}，{'必填' if p['必填'] else '选填'}）：{p['说明']}"
        for p in 参数) or "- 无参数"
    用例行 = "\n".join(f"- {c['说明']}" for c in 用例)
    return f"""# {名称}

{说明 or '（待补充：一句话说清这个技能做什么。）'}

## 参数

{参数行}

## 用法

调用 `技能库.受控执行.运行技能包`，`技能根目录` 传本技能所在根目录，
`能力标识` 传 `{能力标识}`，参数放在 `参数` 里。

## 验证用例

{用例行}

> 本文件由 `支持库/后端/组件规范支持库/实现/技能模板生成器.py` 生成，计入技能包指纹；任何改动都要升技能版本。
"""


