from 支持库.后端.文件系统支持库.文件操作 import 写入文件
# 落盘腿拒绝的**原样错误码载体**（`越界` 等真码不许被中间层收敛掉，2026-09-25）：
# 类型定义在生成器族唯一落盘腿所在的 `模板公共件`，本模块只 import 类型供上抛用。
from 支持库.后端.组件规范支持库.实现.模板公共件 import 写入被拒

组件类型表 = {"支持库", "基础模块", "功能模块", "项目代码"}
九要素 = ("包声明", "能力契约", "依赖契约", "配置契约", "权限契约",
          "执行单元", "验证场景", "说明书", "完整性摘要")


@dataclass
class 规范校验结果:
    """组件规范校验结果。"""

    组件id: str = ""
    问题列表: list[str] = field(default_factory=list)

    @property
    def 成功(self) -> bool:
        return not self.问题列表


def 校验组件规范(组件目录: Path) -> 规范校验结果:
    """校验组件目录符合统一九要素规范。"""
    结果 = 规范校验结果(组件id=组件目录.name)
    声明路径 = 组件目录 / "包声明.json"
    if not 声明路径.is_file():
        结果.问题列表.append("缺少 包声明.json")
        return 结果
    try:
        声明 = json.loads(声明路径.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        结果.问题列表.append("包声明.json 不是合法 JSON")
        return 结果
    if 声明.get("类型") not in 组件类型表:
        结果.问题列表.append(f"类型不合法: {声明.get('类型')}（应为 {组件类型表}）")
    if not 声明.get("包id"):
        结果.问题列表.append("缺少 包id")
    if not 声明.get("版本"):
        结果.问题列表.append("缺少 版本")
    # 能力契约目录
    能力契约目录 = 组件目录 / "能力契约"
    if not 能力契约目录.is_dir() or not any(能力契约目录.glob("*.json")):
        结果.问题列表.append("缺少 能力契约/（至少一个契约 JSON）")
    # 依赖契约：可选 —— 无目录 = 无内部依赖（2026-09-15 定：空白声明删掉，不留占位目录；
    # 与组件合规「依赖」判据同源：声明缺失即独立组件）
    # 配置契约（支持库/模块应有）
    if not (组件目录 / "配置契约").is_dir():
        结果.问题列表.append("缺少 配置契约/")
    # 权限契约
    if not (组件目录 / "权限契约").is_dir():
        结果.问题列表.append("缺少 权限契约/")
    # 执行单元
    if not (组件目录 / "实现").is_dir() and not (组件目录 / "执行单元").is_dir():
        结果.问题列表.append("缺少 实现/ 或 执行单元/")
    # 验证场景
    if not (组件目录 / "验证场景").is_dir() and not (组件目录 / "验证场景引用.json").is_file():
        结果.问题列表.append("缺少 验证场景/ 或 验证场景引用.json")
    # 说明书
    if not (组件目录 / "说明").is_dir() and not (组件目录 / "说明书.md").is_file():
        结果.问题列表.append("缺少 说明/ 或 说明书.md")
    # 完整性摘要（委托唯一校验器：文件清单格式唯一权威，旧格式一律拒绝）
    if not (组件目录 / "完整性摘要.json").is_file():
        结果.问题列表.append("缺少 完整性摘要.json")
    else:
        from 支持库.后端.组件规范支持库.实现.完整性摘要 import 校验完整性摘要
        通过, 问题列表 = 校验完整性摘要(组件目录)
        结果.问题列表.extend(问题列表)
    return 结果


def 生成完整性摘要(组件目录: Path, *, 开工ID: str | None = None) -> dict[str, Any]:
    """生成并写入 完整性摘要.json（委托唯一生成器，文件清单唯一权威格式）。

    包id/版本取自 包声明.json（缺省时用 组件目录名/1.0.0），
    不复制任何第二套摘要算法。

    `开工ID`（2026-09-25 开工-20260925-161955-849f）：本次改动的开工ID，**原样透传**给
    `写入文件`，由写腿第二判据（`公共契约/运行时/写入授权.py::校验写入授权`）核对活跃写租约
    所有者；受管路径缺它即写腿回 `越界`，本函数经 `写入被拒` **原样上抛该码**（不收敛）。
    """
    # 序列化一律转调**唯一权威**（`开发工具.全量重算摘要.完整性摘要文本`），本处不再自写
    # `json.dumps` 公式 —— 2026-09-24 批R R-31 收口 O-12 第三腿（前两腿 `重建依赖锁`／
    # `完整性摘要生成器` 已于批O O-5 转调）。写下去的字节与返回的字典**同源**：返回的就是
    # 权威文本 `json.loads` 出来的那一份，同一产物不可能再分叉。
    #   以前为什么改不动、现在为什么能改（层向硬约束，实测非推测）：`运行核心/依赖防火墙.py`
    #   的 `允许依赖表["支持库"]` 只有 `公共契约`，权威节点住 `开发工具` 层 ⇒ 本文件静态
    #   导入它会被判「越层依赖（支持库 不允许依赖 开发工具）」。华哥 2026-09-24 裁决＝
    #   **改防火墙把这条依赖登记进去**；本批落在 `文件级豁免表`（`允许依赖表` 的**文件限定**
    #   补充）：**只放行本文件**→`开发工具`，与 2026-09-23 `公共契约/运行时/写入授权.py` 的
    #   先例逐字同形 —— 不把「支持库 可依赖 开发工具」推广成整层边（那是扩大授权）。
    from 开发工具.全量重算摘要 import 完整性摘要文本
    声明路径 = 组件目录 / "包声明.json"
    try:
        声明 = json.loads(声明路径.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        声明 = {}
    文本 = 完整性摘要文本(
        组件目录, 包id=声明.get("包id", 组件目录.name),
        版本=声明.get("版本", "1.0.0"))
    落盘 = 写入文件(str(组件目录 / "完整性摘要.json"), 文本, 开工ID=str(开工ID or ""))
    if not 落盘.成功:
        raise 写入被拒(落盘.错误码, 落盘.错误说明)
    return json.loads(文本)
