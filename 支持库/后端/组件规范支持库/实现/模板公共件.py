"""模板公共件：两个包模板生成器（支持库 / 模块）共用的**同口径常量与小件**。

**为什么有这个文件（2026-09-18 修根）**：两个模板生成器是同类产物生成器，此前各自
持有一份「资源预算十项键名」，靠 docstring 互相指向保持同源 —— 那是**真实的漂移风险点**：
键名一旦在 `平台控制面/资源监督.py::资源监督器.必需预算键` 改名，两侧得同时记得改，
漏一侧就会产出「过不了组件合规」的模板产物（S0 缺项阻断）。

**抽取边界（刻意只抽这些）**：

| 抽 | 不抽 |
|---|---|
| `资源预算必需键` 十项键名元组 | **取值档位**：支持库是一次性子进程档、模块是组合层档，本来就该不同，合并会引入「同一函数按包类型分支」的隐藏耦合 |
| `渲染`（`@@键@@` 占位替换） | **设计说明正文**：支持库讲子进程协议/第三方边界，模块讲编排口径/依赖边界，差异大 |
| `复用决策骨架` 的「待填写」文案常量 | **复用决策全文**：两侧的「搜索词建议」来源不同（支持库取能力名、模块取编排对象） |

即：**只抽「口径必须一致」的公共件；口径本就不同的（取值、正文）留在各自生成器**。
"""

from __future__ import annotations

from typing import Any

#: 资源预算的十项必需键（顺序即产物体例顺序）。
#: 判据来源：`平台控制面/资源监督.py::资源监督器.必需预算键`（十项），
#: 与 `开发工具/组件合规/合规测试包.py::资源预算必需键` 同源。
#: **本元组是模板侧的唯一声明处** —— 两个模板生成器都从这里取键名组装预算 dict，
#: 不再各自手写一份（消除漂移；取值仍由各自决定）。
资源预算必需键 = (
    "内存上限", "线程上限", "子进程上限", "并发调用上限", "队列长度",
    "文件句柄上限", "临时空间上限", "单次调用超时", "每分钟重启次数", "空闲回收时间",
)

#: `复用决策.json` 的「待填写」占位文案（两个模板共用同一句，避免同一件事两种说法）。
#: **语义**：`复用决策.json` 是「新建包之前先查有没有可复用能力」的**结论记录**。
#: `开发工具/组件合规/合规测试包.py::_场景结构` 要求 `搜索词` 与 `候选能力id` 都非空
#: （S0 缺项阻断）——那只有**真做过能力搜索**才成立。模板**不替作者造这个结论**：
#: 两个字段留空列表 + 本占位说明。
复用决策待填写 = [
    "**待填写**：新建包前必须先跑能力搜索，把真实搜索词与候选能力 id 填进这两个字段。",
    "留空即代表「尚未做复用决策」，组件合规会以 S0 缺项阻断——这是刻意的，不是漏做。",
]


def 渲染(模板: str, **替换: Any) -> str:
    """模板占位替换：把 `@@键@@` 换成对应值（两个模板生成器共用同一口径）。"""
    for 键, 值 in 替换.items():
        模板 = 模板.replace(f"@@{键}@@", str(值))
    return 模板


def 组装资源预算(取值: dict[str, Any]) -> dict[str, Any]:
    """按 `资源预算必需键` 的顺序，用给定取值组装预算 dict（键集与顺序由本模块保证）。

    `取值` 必须**恰好**覆盖十项键名：多给或漏给都抛 `ValueError` —— 与其产出
    「过不了组件合规」的模板产物，不如在生成期当场失败（哲学 14.2 判据挂在产出点）。
    """
    漏 = [键 for 键 in 资源预算必需键 if 键 not in 取值]
    多 = [键 for 键 in 取值 if 键 not in 资源预算必需键]
    if 漏 or 多:
        raise ValueError(f"资源预算取值与必需键不一致：漏 {漏}／多 {多}")
    return {键: 取值[键] for 键 in 资源预算必需键}
