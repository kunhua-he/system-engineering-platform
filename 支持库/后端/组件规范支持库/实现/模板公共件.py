"""模板公共件：两个包模板生成器（支持库 / 模块）共用的**同口径常量与小件**。

**为什么有这个文件（2026-09-18 修根）**：两个模板生成器是同类产物生成器，此前各自
持有一份「资源预算十项键名」，靠 docstring 互相指向保持同源 —— 那是**真实的漂移风险点**：
键名一旦在 `平台控制面/资源监督.py::资源监督器.必需预算键` 改名，两侧得同时记得改，
漏一侧就会产出「过不了组件合规」的模板产物（S0 缺项阻断）。

**抽取边界（刻意只抽这些）**：

| 抽 | 不抽 |
|---|---|
| `资源预算必需键` 十项键名元组 | **取值档位**：支持库是一次性子进程档、模块是组合层档，本来就该不同，合并会引入「同一函数按包类型分支」的隐藏耦合 |
| `渲染`（`@@键@@` 占位替换） | **设计说明正文**：支持库讲子进程协议/第三方边界，模块讲编排口径/依赖边界，差异大 |
| `复用决策骨架` 的「待填写」文案常量 | **复用决策全文**：两侧的「搜索词建议」来源不同（支持库取能力名、模块取编排对象） |

即：**只抽「口径必须一致」的公共件；口径本就不同的（取值、正文）留在各自生成器**。
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

#: 资源预算的十项必需键（顺序即产物体例顺序）。
#: 判据来源：`平台控制面/资源监督.py::资源监督器.必需预算键`（十项），
#: 与 `开发工具/组件合规/合规测试包.py::资源预算必需键` 同源。
#: **本元组是模板侧的唯一声明处** —— 两个模板生成器都从这里取键名组装预算 dict，
#: 不再各自手写一份（消除漂移；取值仍由各自决定）。
资源预算必需键 = (
    "内存上限", "线程上限", "子进程上限", "并发调用上限", "队列长度",
    "文件句柄上限", "临时空间上限", "单次调用超时", "每分钟重启次数", "空闲回收时间",
)

#: `复用决策.json` 的「待填写」占位文案（两个模板共用同一句，避免同一件事两种说法）。
#: **语义**：`复用决策.json` 是「新建包之前先查有没有可复用能力」的**结论记录**。
#: `开发工具/组件合规/合规测试包.py::_场景结构` 要求 `搜索词` 与 `候选能力id` 都非空
#: （S0 缺项阻断）——那只有**真做过能力搜索**才成立。模板**不替作者造这个结论**：
#: 两个字段留空列表 + 本占位说明。
复用决策待填写 = [
    "**待填写**：新建包前必须先跑能力搜索，把真实搜索词与候选能力 id 填进这两个字段。",
    "留空即代表「尚未做复用决策」，组件合规会以 S0 缺项阻断——这是刻意的，不是漏做。",
]


def 渲染(模板: str, **替换: Any) -> str:
    """模板占位替换：把 `@@键@@` 换成对应值（两个模板生成器共用同一口径）。"""
    for 键, 值 in 替换.items():
        模板 = 模板.replace(f"@@{键}@@", str(值))
    return 模板


def 组装资源预算(取值: dict[str, Any]) -> dict[str, Any]:
    """按 `资源预算必需键` 的顺序，用给定取值组装预算 dict（键集与顺序由本模块保证）。

    `取值` 必须**恰好**覆盖十项键名：多给或漏给都抛 `ValueError` —— 与其产出
    「过不了组件合规」的模板产物，不如在生成期当场失败（哲学 14.2 判据挂在产出点）。
    """
    漏 = [键 for 键 in 资源预算必需键 if 键 not in 取值]
    多 = [键 for 键 in 取值 if 键 not in 资源预算必需键]
    if 漏 or 多:
        raise ValueError(f"资源预算取值与必需键不一致：漏 {漏}／多 {多}")
    return {键: 取值[键] for 键 in 资源预算必需键}


def 产物路径文本(路径: str | Path, 系统根: str | Path) -> str:
    """把要**写进产物**的路径值收成「项目根相对路径」（写进产物前先相对化）。

    唯一权威是 `系统核心支持库.路径安全.显示相对路径` —— 相对化这件事全平台只有这一条腿
    （P-10 实测：接线前它**零消费方**），本函数只转调，**不手写** `os.path.relpath`。
    不在项目根内时按该节点自身口径**原样返回绝对路径**：那是调用方指定的输出位置
    （如夹具临时目录、仓外输出目录），不是「生成期机器根」，不在本判据射程内。
    """
    from 支持库.后端.系统核心支持库.路径安全 import 显示相对路径
    判定 = 显示相对路径(str(路径), str(系统根))
    判定值 = 判定.值 if isinstance(判定.值, dict) else {}
    return str(判定值.get("显示路径") or 路径)


def 产物文本收口(文本: str, 系统根: str | Path) -> str:
    """「写进产物前」的**唯一收口点**：产物文本里不得含生成期机器根（源码树绝对路径）。

    **为什么必须有**（2026-09-24 批P P-9／P-10，华哥口径「有统一节点就接入」）：
    生成器把**生成期**源码树绝对路径渲染进产物（`@@系统根@@` 那类注入），产物随包入
    制品、并计入 `完整性摘要.json` 指纹 ⇒ **换机即指纹漂移**；跑制品时还会把源码树
    插进 `sys.path`（制品不自足，O-1）。而相对化节点
    `系统核心支持库.路径安全.显示相对路径` 此前**零消费方** ⇒ 这条规则没有任何强制点。

    **本函数就是那个强制点**（哲学 13.3 四环链的 ④门禁、14.2 判据挂在产出点）：
    生成器族把**全部产物文本**在落盘前过这里，命中即抛 `ValueError` ——
    与同文件 `组装资源预算` 同形制：与其产出过不了门禁的产物，不如在生成期当场失败。

    **判据射程**（不放大）：只认**生成期机器根**（`系统根` 的绝对路径字面量）。
    夹具临时目录、调用方指定的仓外输出目录不算机器根。

    **修法指引**（命中时给）：路径值走 `产物路径文本`（转调唯一相对化节点）；
    需要**运行期**取根的代码写**自举段**（锚目录判据，与
    `公共契约/运行时/导入前缀.取系统根` 同判，形状由
    `测试中心/开发工具/测试_导入前缀.py` 逐字钉住）—— 不要写 `parents[N]` 那种层数写法。
    """
    机器根 = str(系统根).rstrip("/\\")
    if 机器根 and 机器根 in 文本:
        raise ValueError(
            f"产物文本里出现生成期机器根绝对路径（{机器根}）：写进产物前必须先相对化 —— "
            "路径值走 `模板公共件.产物路径文本`（转调 `系统核心支持库.路径安全.显示相对路径`）；"
            "需要运行期取根的代码写自举段（锚目录判据），不要写 parents[N]")
    return 文本


def 写产物(路径: str | Path, 内容: str, 系统根: str | Path) -> None:
    """生成器族**唯一**的产物落盘腿 —— P-10 的强制点就挂在这里（判据挂在产出点，哲学 14.2）。

    **为什么是这一处**（2026-09-24 批P P-9／P-10，华哥口径「有统一节点就接入」）：
    本包落盘**产物**的腿原先在每个生成器里各写一份（`支持库模板生成器._写` 与
    `技能模板生成器._写` 逐字相同，`模块模板生成器` 自己内联一行）——同一件事多份实现
    正是「写进产物前先相对化」**没有任何强制点**的成因：接在哪一份上，另一份就漏。
    故落盘腿收成这里**一处**，`产物文本收口` 挂在它上面 ⇒ 必经且唯一：
    本包任何产物文本落盘都过同一处判据，**且没有第二处**。

    **射程**（不放大，见 `产物文本收口`）：只拒**生成期机器根**字面量。派生件
    （`完整性摘要.json`）与运行态指针（`核心快照模板` → `工程缓存/`）里的绝对路径是
    合法运行态事实，**不接线**，接上去当场假红。

    `路径` 为文件系统路径（绝对合法，不参与逃逸检查）；父目录不存在即就地建。
    """
    from 支持库.后端.文件系统支持库.文件操作 import 写入文件
    目标 = Path(路径)
    目标.parent.mkdir(parents=True, exist_ok=True)
    写入文件(str(目标), 产物文本收口(内容, 系统根)).确保成功()
