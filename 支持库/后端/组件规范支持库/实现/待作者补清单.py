骨架填充项 = (
    ("说明/设计说明.md", "15 处左右 `**待填写**`：本包是什么／不是什么／管什么／不管什么／"
                    "为什么这样切／失败如何表达／被否决的做法（写成空话等于没有设计权威）"),
    ("复用决策.json", "`待填写` 对象里的三个字段说明"),
    ("实现/提供者.py", "各公开函数的真实逻辑（模板产的是占位实现）"),
    ("实现/子进程入口.py", "真实子进程协议实现（模板产的是占位）"),
    ("验证场景引用.json", "场景正文（模板产的是空引用列表，空列表过不了门禁）"),
)


def 生成待作者补清单(*, 包目录: str, 名称: str, 能力清单: list[dict] | None = None,
                    第三方说明: list[dict] | None = None) -> str:
    """产出「待作者补.md」正文（纯文本，不写盘）。"""
    能力表 = 能力清单 or []
    行 = [
        f"# {名称} · 待作者补清单",
        "",
        "> 本文件由模板生成器产出，**是提示不是事实源**（不参与运行时、不进门禁）。",
        "> 目的：新建包后**一次性看清要补哪几件、合法值是什么、怎么验**——",
        "> 不必逐个文件读、逐个试错。补完可删本文件。",
        "",
        "## 一、必须补的内容（骨架→真实）",
        "",
        "| 文件 | 要补什么 |",
        "|---|---|",
    ]
    for 文件, 说明 in 骨架填充项:
        行.append(f"| `{文件}` | {说明} |")
    if 能力表:
        行 += ["", "本包能力（每个都要有成功目标步骤 + 权限声明）：", ""]
        for c in 能力表:
            行.append(f"- `{c.get('能力id', '')}` —— {c.get('说明', '')}")
    行 += [
        "",
        "## 二、★ 隐性硬约束（**撞一次就浪费一轮，先看这里**）",
        "",
        "| 要补什么 | 合法值 / 硬约束 | 怎么验 | 真源 |",
        "|---|---|---|---|",
    ]
    for 项, 约束, 判据, 真源 in 隐性规则:
        行.append(f"| {项} | {约束} | `{判据}` | `{真源}` |")
    行 += [
        "",
        "## 三、补完的自检顺序（照这个顺序跑，别跳）",
        "",
        "```bash",
        "unset PYTHONPATH",
        "# ① 一次报全缺项（不装配、不编译、不写盘）",
        f"python3.14 开发工具/包体检.py {包目录}",
        "# ② 场景体检（含状态码逐条对表）",
        "python3.14 开发工具/验证场景体检.py",
        "# ③ 重编译（能力定义.json 是源，改源必编译）",
        "#    见 开发文档/规范/新建支持库与模块指南.md 步骤 2",
        "# ④ 重算摘要（排除自身与 __pycache__）",
        "python3.14 -m 开发工具.全量重算摘要",
        "# ⑤ 组件合规 13 项（这才是最终验收）",
        "python3.14 -c \"import sys;sys.path.insert(0,'.');"
        "from 开发工具.组件合规.合规测试包 import 组件合规;"
        f"from pathlib import Path;print(组件合规(Path('{包目录}')).执行().通过数)\"",
        "```",
        "",
        "## 四、第三方依赖说明",
        "",
    ]
    if 第三方说明:
        行.append("本包声明了第三方/外部依赖：**必须同时产 `依赖锁.json`**（锁存在 ⟺ 有第三方依赖）。")
        for d in 第三方说明:
            行.append(f"- {d.get('名称', '')} {d.get('版本', '')}（{d.get('接入方式', '外部工具')}）")
    else:
        行.append("无第三方依赖：**不要建空壳 `依赖锁.json`**（空锁会被判 `依赖锁为空` 并整包禁止装配）。")
    行.append("")
    return "\n".join(行)
