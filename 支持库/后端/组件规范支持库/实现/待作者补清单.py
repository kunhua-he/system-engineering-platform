"""待作者补清单：新建包后**一次性告诉作者要补哪几件、合法值是什么、补完怎么验**。

**为什么必须有**（2026-09-18 归因，见 `开发文档/分析/新建支持库回填链路归因_20260918.md`）：
模板生成器把「待填写」占位写在**各文件正文里**，却没有**汇总清单**告诉作者全集 ——
作者只能逐个文件读、逐个猜，且不知道「一共几件」。实测后果：一个新建包耗时 40+ 分钟，
隐性规则（`def 注册能力` 豁免、`$动态` 六类、失败用例要 `返回断言`、说明书默认拒绝覆盖、
权限要逐能力声明）**全是撞出来才知道的**。

本模块把这些判据**前移到生成期**，产出一份 `<包目录>/待作者补.md`，是**只读提示**，
不参与运行时、不进门禁（进门禁就变成新的事实源，违反单腿原则）。
"""

