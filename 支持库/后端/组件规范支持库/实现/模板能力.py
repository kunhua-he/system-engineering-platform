"""模板类能力包装：支持库/技能/快照模板生成与快照校验（统一结果信封）。

包装层只做参数归一 + 失败码映射；算法一律在被包装的 实现/ 模块里：
- `支持库模板生成器.py` / `技能模板生成器.py` / `核心快照模板.py`。

失败码收敛（错误码硬约束）：内部实现自带的 `同名能力`/`文件已存在`/`参数无效`/
`快照损坏` 等**未登记**历史码一律经 `包装辅助.归一失败码` 收敛成网关已登记码
（技能模板生成器的 `已存在文件` 已直接改为登记字面量 `已存在`），
不新增网关码、也不把未登记码透出给调用方（集合外一律回落 `内部错误`）。
"""

