来源 = "组件规范支持库"


def 生成支持库模板(输出目录: Any = None, 包id: Any = None, 名称: Any = None,
                  能力清单: Any = None, 说明: Any = "", 第三方说明: Any = None,
                  测试文件路径: Any = None, 开工ID: Any = None) -> 结果:
    """按能力清单生成九要素支持库包骨架与定向测试骨架（已存在一律拒绝覆盖）。"""
    目录 = 路径参数(输出目录)
    清单 = 列表参数(能力清单)
    if 目录 is None:
        return 结果.失败("参数不合法", f"输出目录 必须是非空路径文本: {输出目录!r}", 来源=来源)
    if not 文本参数(包id):
        return 结果.失败("参数不合法", f"包id 必填: {包id!r}", 来源=来源)
    if not 文本参数(名称):
        return 结果.失败("参数不合法", f"名称 必填: {名称!r}", 来源=来源)
    if 清单 is None or not 清单:
        return 结果.失败("参数不合法", "能力清单 必须是非空列表", 来源=来源)
    if 目录.exists() and any(目录.rglob("*")):
        return 结果.失败("已存在", f"目标目录已存在文件，拒绝覆盖: {目录}", 来源=来源)
    测试路径 = 路径参数(测试文件路径)
    if 测试路径 is not None and 测试路径.is_file():
        return 结果.失败("已存在", f"测试文件已存在，拒绝覆盖: {测试路径}", 来源=来源)
    try:
        返回值 = _生成支持库模板(
            输出目录=目录, 包id=文本参数(包id), 名称=文本参数(名称),
            能力清单=清单, 说明=文本参数(说明),
            第三方说明=第三方说明 if isinstance(第三方说明, list) else [],
            测试文件路径=测试路径, 开工ID=文本参数(开工ID))
    except 写入被拒 as 错误:
        # 写腿第二判据（写入授权）的拒绝：**原样透出真码**（`越界`），不进 `归一失败码`。
        return 结果.失败(错误.错误码, 错误.错误说明, 来源=来源)
    except (TypeError, ValueError, OSError) as 错误:
        return 结果.失败("参数不合法", f"模板生成输入不可用: {type(错误).__name__}: {错误}", 来源=来源)
    if not 返回值.成功:
        return 失败(返回值.错误码, 返回值.错误说明, 详情=dict(返回值.详细信息 or {}))
    return 结果.成功结果(返回值.值)


def 生成技能模板(技能根目录: Any = None, 技能目录名: Any = None, 能力标识: Any = None,
                名称: Any = None, 分类: Any = "通用", 说明: Any = "",
                参数: Any = None, 返回: Any = "字典型", 入口脚本: Any = None,
                步骤: Any = None, 依赖: Any = None, 验证用例: Any = None,
                开工ID: Any = None) -> 结果:
    """生成技能包六件套 + 受控执行桥接脚本骨架（索引由技能库能力统一派生）。"""
    for 字段, 值 in (("技能根目录", 技能根目录), ("技能目录名", 技能目录名),
                    ("能力标识", 能力标识), ("名称", 名称)):
        if not 文本参数(值):
            return 结果.失败("参数不合法", f"{字段} 必填: {值!r}", 来源=来源)
    if 列表参数(验证用例) is None or not 验证用例:
        return 结果.失败("参数不合法", "验证用例至少 1 条（空转即杀：没有结果的东西不需要存在）", 来源=来源)
    技能目录 = 路径参数(技能根目录).expanduser() / str(技能目录名)
    if 技能目录.is_dir() and any(技能目录.iterdir()):
        return 结果.失败("已存在", f"目标技能包已存在文件，拒绝覆盖: {技能目录}", 来源=来源)
    try:
        返回值 = _生成技能模板(
            技能根目录=技能根目录, 技能目录名=技能目录名, 能力标识=能力标识,
            名称=名称, 分类=文本参数(分类, "通用"), 说明=文本参数(说明),
            参数=列表参数(参数) or [], 返回=文本参数(返回, "字典型"),
            入口脚本=入口脚本 if isinstance(入口脚本, str) and 入口脚本 else None,
            步骤=列表参数(步骤), 依赖=依赖 if isinstance(依赖, dict) else None,
            验证用例=验证用例, 开工ID=文本参数(开工ID))
    except 写入被拒 as 错误:
        # 写腿第二判据（写入授权）的拒绝：**原样透出真码**（`越界`）。
        return 结果.失败(错误.错误码, 错误.错误说明, 来源=来源)
    except (TypeError, ValueError, OSError) as 错误:
        return 结果.失败("参数不合法", f"技能模板输入不可用: {type(错误).__name__}: {错误}", 来源=来源)
    if not 返回值.成功:
        return 失败(返回值.错误码, 返回值.错误说明, 详情=dict(返回值.详细信息 or {}))
    return 结果.成功结果(返回值.值)


def 生成快照清单模板(目标目录: Any = None, 范围目录表: Any = None,
                    工作目录: Any = None, 版本: Any = "1.0.0",
                    栅栏令牌: Any = "", 开工ID: Any = None) -> 结果:
    """生成核心快照结构骨架（清单/摘要/激活指针）；已存在或路径逃逸一律拒绝。"""
    目标 = 路径参数(目标目录)
    范围 = 列表参数(范围目录表)
    if 目标 is None:
        return 结果.失败("参数不合法", f"目标目录 必须是非空路径文本: {目标目录!r}", 来源=来源)
    if 范围 is None or not 范围:
        return 结果.失败("参数不合法", "范围目录表 必须是非空列表", 来源=来源)
    if 目标.exists() and any(目标.iterdir()):
        return 结果.失败("已存在", f"快照目录已存在，拒绝覆盖: {目标}", 来源=来源)
    try:
        返回值 = _生成快照清单模板(
            目标, 范围, 工作目录=路径参数(工作目录),
            版本=文本参数(版本, "1.0.0"), 栅栏令牌=文本参数(栅栏令牌),
            开工ID=文本参数(开工ID))
    except 写入被拒 as 错误:
        return 结果.失败(错误.错误码, 错误.错误说明, 来源=来源)
    except (TypeError, ValueError, OSError) as 错误:
        return 结果.失败("参数不合法", f"快照模板输入不可用: {type(错误).__name__}: {错误}", 来源=来源)
    码 = str(返回值.get("错误码") or "")
    if 返回值.get("成功") and not 码:
        return 结果.成功结果({键: 值 for 键, 值 in 返回值.items()
                           if 键 not in ("成功", "错误码")})
    if 码 == 写入授权码:
        # 写腿第二判据的拒绝：**原样透出**（不走 `归一失败码` —— 收敛成 `内部错误` 会把
        # 「没开工ID / 租约属别的凭证」这个唯一真因洗掉，调用方也就无法按解决办法自救）。
        return 结果.失败(写入授权码, str(返回值.get("消息") or "快照模板生成失败"), 来源=来源)
    return 失败(码 or "写入失败", str(返回值.get("消息") or "快照模板生成失败"))


def 校验快照模板(快照目录: Any = None) -> 结果:
    """校验快照结构：三文件存在 / 清单与磁盘一致 / 聚合摘要匹配。"""
    目录 = 路径参数(快照目录)
    if 目录 is None:
        return 结果.失败("参数不合法", f"快照目录 必须是非空路径文本: {快照目录!r}", 来源=来源)
    try:
        通过, 消息 = _校验快照模板(目录)
    except (TypeError, ValueError, OSError) as 错误:
        return 结果.失败("参数不合法", f"快照目录不可读: {type(错误).__name__}: {错误}", 来源=来源)
    return 结果.成功结果({"通过": bool(通过), "说明": str(消息)})
