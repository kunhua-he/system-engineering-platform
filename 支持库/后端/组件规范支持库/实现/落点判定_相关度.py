"""相关度计算：落点判定的唯一判据口径（独立成件，便于定向验证与反向验证）。

## 为什么单独一件（实测教训）
第一版把判据与判定流程写在同一个文件里，回归时只能整包跑、看不出是哪一环错。
独立后可以只对判据做定向验证：给一组「应当命中 / 应当不命中」样本，逐条看判据给什么。

## 判据演进（两版，第二版取代第一版，旧口径不留）
**第一版（已废弃）**：中文双字滑窗交集 ≥2 即命中。实测误命中严重——
「Swift 源码编译成 .app 并签名」判到 `PDF隔离提供者.校验PDF`（交集来自「编译」二字
之外的杂散片段），「HTTP 服务宿主」判到 `会话存储.连接会话存储`。**根因**：
双字交集只证明「有两个字碰巧相邻出现过」，不证明「说的是同一件事」。

**第二版（现行）**：三级信号，**必须命中语义级才算相关**，词汇级只作候选补充：
1. **主干词命中**（最强）：把描述里的 2–4 字连续中文名词（主干词）与目标名比对，
   主干词**整体**出现在目标名里 → 逐字计分（2 字 20 分、3 字 30 分、4 字 40 分）；
2. **词元命中**（次强）：描述切出的词元里，**长度 ≥3 的中文词元或 ≥4 的英文词元**
   整体出现在目标名里 → 每个 12 分（滤掉「转换/校验」这类泛化词的高频噪声靠第 3 条）；
3. **泛化词降权**：维护一份**泛化词表**（转换/校验/构建/查询/读取/创建/生成/检查/分析 等），
   命中泛化词**不加分**，只记入「泛化命中」供调用方参考——它们出现在几百个能力名里，
   拿它当判据必然误命中。

判据只做**相关度评分**，不下结论；结论由 `落点判定.判落点` 按阈值定夺。
"""

from __future__ import annotations

#: 泛化词表：出现在大量能力名里、**不能**作为「同一件事」的证据。
#: 实测「转换」「校验」「构建」各出现在 20+ 个能力名中 —— 拿它们判重复必然误命中。
泛化词 = frozenset((
    "转换", "校验", "检查", "构建", "创建", "生成", "读取", "写入", "查询",
    "分析", "解析", "处理", "计算", "执行", "关闭", "连接", "释放", "获取",
    "设置", "更新", "删除", "添加", "开始", "结束", "开启", "停止", "启动",
    "内容", "数据", "文件", "文本", "信息", "状态", "参数", "结果", "结构",
    "请求", "响应", "能力", "支持", "服务", "系统", "平台", "底座", "通用",
))

#: 中文词元最短长度（≥3 才作次强信号；2 字词太泛）。
中文词元最短 = 3
#: 英文词元最短长度。
英文词元最短 = 4
#: 主干词长度区间：**最短 3 字**（实测 2 字主干词全是噪声——「模型」「资源」「签名」
#: 各出现在 30+ 个能力名里，拿它们判「同一件事」必然误命中：实测「模型资源池号池粘性选择」
#: 因「模型」+「资源」两个 2 字词凑够 40 分，被判成与 `资源快照` 同域）。
主干词最短 = 3
主干词最长 = 5

#: 各级信号分值（可判定、可复核；不随调用变化）。
分_主干每字 = 10.0
分_词元 = 12.0
#: 专名命中（协议名/技术专名：anthropic、responses、swift、http 等）—— 这类词一旦同时
#: 出现在描述与目标里，几乎必然是同一件事（实测：描述「三协议请求体互转 chat responses
#: anthropic」与能力 `归一化对话响应` 的中文主干词零命中，但它们共享 chat/responses/
#: anthropic 三个专名，同域关系明确）。故给高权重，且**不受泛化词降权影响**。
分_专名 = 30.0
#: **覆盖度阈值**：没有专名命中时，主干词命中的字数必须占到描述中文部分的这一比例，
#: 才算「同一件事」。实测缺陷：描述「把模型调用关系画成请求图并做环检测」（18 个中文字）
#: 只与 `记录模型调用` 共有 4 字「模型调用」，却因 4×10=40 分越过阈值 26，
#: 把真缺口（请求图）误判成「补既有能力」。只靠分数看不出「只有一小截撞上」。
覆盖度_同域 = 0.34
#: 专名词表：底座里反复出现的协议/技术专名（不随调用变化，改这里即改判据）。
专名词表 = frozenset((
    # ★ 只收「**一出现就几乎锁定同一件事**」的专名。实测剔除 http/https/llm/token/json
    # 这类泛协议词：它们出现在几十个能力名里（「HTTP 服务宿主」曾因 `http` 命中被判到
    # `浏览器自动化.导航页面`），拿它们当专名必然误命中 —— 与泛化词同理，只是形态是英文。
    "anthropic", "responses", "swift", "swiftc", "codesign", "notarytool",
    "psycopg", "sqlite", "postgres", "mysql", "ffmpeg", "whisper", "tesseract",
    "libreoffice", "pymupdf", "pdfplumber", "reportlab", "tree-sitter", "treesitter",
    "docx", "xlsx", "pptx", "sse",
))
#: 判定阈值：达到它才算「同域/同一件事」，否则视为无承接者。
阈值_同域 = 26.0


def 是汉字(字: str) -> bool:
    """是否 CJK 汉字（中文分段的唯一判据）。

    ★ 不能只判「非 ASCII 即中文」——实测标点（：，。、（）「」）也非 ASCII，
    会被算进中文段，于是主干词变成「服务宿主：」这种带标点的废词，
    整段主干命中全废（「HTTP 服务宿主」因此判不出任何主干词、落到错误落点）。
    """
    return "\u4e00" <= 字 <= "\u9fff"


def 切词(文本: str) -> list[str]:
    """切词：中文连续段按双字滑窗，ASCII 连续段整体成词（长度 ≥2 才收）。

    只服务于「候选补充」，不做结论。中文双字片段噪声大，故结论性判定一律走
    `主干词表` 与 `词元表`，不直接拿双字片段当判据。
    """
    词表: list[str] = []
    净 = "".join(字 for 字 in str(文本 or "") if 字.strip())
    中文段 = ""
    英文段 = ""

    def _收中文() -> None:
        nonlocal 中文段
        for 起点 in range(0, max(0, len(中文段) - 1)):
            词表.append(中文段[起点:起点 + 2])
        中文段 = ""

    def _收英文() -> None:
        nonlocal 英文段
        if len(英文段) >= 2:
            词表.append(英文段.lower())
        英文段 = ""

    for 字 in 净:
        if 字.isascii() and (字.isalnum() or 字 in "_-."):
            if 中文段:
                _收中文()
            英文段 += 字
        elif 是汉字(字):
            if 英文段:
                _收英文()
            中文段 += 字
        else:
            # 标点/符号：**既不是中文也不是英文**，只作分段边界，不进任何段
            if 中文段:
                _收中文()
            if 英文段:
                _收英文()
    if 中文段:
        _收中文()
    if 英文段:
        _收英文()
    return 词表


def 主干段表(描述: str) -> list[str]:
    """取描述里的**连续中文段**（标点/英文/数字一律作边界）。

    主干词只从纯中文段里取：这样「服务宿主：把请求…」不会被冒号污染成
    「服务宿主：」这种带标点的废词（实测缺陷）。
    """
    净 = "".join(字 for 字 in str(描述 or "") if 字.strip())
    段表: list[str] = []
    当前 = ""
    for 字 in 净:
        if 是汉字(字):
            当前 += 字
        else:
            # 标点/英文/数字：一律作分段边界（主干词只取纯中文段）
            if 当前:
                段表.append(当前)
                当前 = ""
    if 当前:
        段表.append(当前)
    return 段表


def 主干词表(描述: str) -> list[str]:
    """从描述里的连续中文段生成 3–5 字主干词候选（长的在前，判据更严）。

    ⚠ 本函数返回的是**滑窗全排列**，相邻词互相重叠（如「记录模型调用」会产出
    「记录模型调用」「记录模型调」「录模型调用」…）。**不能逐个命中就累加计分**——
    那会让同一段文字贡献多份分（实测把真缺口误判成「补既有能力」）。
    计分请用 `算相关度` 里的**不重叠最长匹配**；本函数仅供需要候选清单的场景。
    """
    词表: list[str] = []
    for 段 in 主干段表(描述):
        for 长 in range(主干词最长, 主干词最短 - 1, -1):
            for 起点 in range(0, max(0, len(段) - 长 + 1)):
                词 = 段[起点:起点 + 长]
                if 词 not in 泛化词:
                    词表.append(词)
    # 长的在前：判定时优先用长主干词（更具体）
    return 词表


def 词元表(描述: str) -> list[str]:
    """取长度达标的词元（中文 ≥3、英文 ≥4），滤掉泛化词。"""
    表: list[str] = []
    for 词 in 切词(描述):
        if 词 in 泛化词:
            continue
        if 词.isascii():
            if len(词) >= 英文词元最短:
                表.append(词)
        elif len(词) >= 中文词元最短:
            表.append(词)
    return 表


def 算相关度(描述: str, 目标文本: str) -> dict[str, object]:
    """算描述与目标名的相关度；返回 ``{分数, 主干命中, 词元命中, 泛化命中}``。

    只给读数，不下结论；结论由调用方按 `阈值_同域` 定夺。
    """
    目标 = "".join(字 for 字 in str(目标文本 or "") if 字.strip())
    目标小写 = 目标.lower()
    分 = 0.0
    主干命中: list[str] = []
    词元命中: list[str] = []
    泛化命中: list[str] = []
    专名命中: list[str] = []

    # ① 专名命中（最强：协议/技术专名同时出现在描述与目标里 → 几乎必然同一件事）
    描述小写 = "".join(字 for 字 in str(描述 or "") if 字.strip()).lower()
    for 专名 in 专名词表:
        if 专名 in 描述小写 and (专名 in 目标小写 or 专名 in 目标):
            专名命中.append(专名)
            分 += 分_专名

    # ② 主干词命中（**不重叠、最长优先**）。
    #     实测缺陷：主干词表是滑窗全排列（「记录模型调用」会产出「模型调用」「模型调」
    #     「型调用」等 3 个重叠窗口），若逐个命中就各计一次分 ——
    #     描述「把模型调用关系画成请求图并做环检测」误命中 `记录模型调用` 得 100 分，
    #     抢过了真缺口（应为新建库）。故此处按描述逐字扫描：
    #     每个位置先试最长窗口，命中即**消费该区间**（已消费区间不再出词），
    #     保证同一段文字只贡献一个主干词、分数不虚高。
    已计主干: set[str] = set()

    for 段 in 主干段表(描述):
        # 每段独立算区间：段内坐标只在本段内有意义，跨段共用会误判重叠
        已用区间: list[tuple[int, int]] = []

        def _区间可用(起: int, 止: int, _已用=已用区间) -> bool:
            return all(止 <= 左 or 起 >= 右 for 左, 右 in _已用)

        for 长 in range(主干词最长, 主干词最短 - 1, -1):
            for 起点 in range(0, max(0, len(段) - 长 + 1)):
                词 = 段[起点:起点 + 长]
                if 词 in 泛化词 or 词 in 已计主干:
                    continue
                if not _区间可用(起点, 起点 + 长):
                    continue
                if 词 in 目标:
                    已用区间.append((起点, 起点 + 长))
                    已计主干.add(词)
                    主干命中.append(词)
                    分 += 分_主干每字 * len(词)
                    break

    # ② 词元命中
    for 词 in 词元表(描述):
        if 词.isascii():
            hit = 词 in 目标小写
        else:
            hit = 词 in 目标
        if hit:
            词元命中.append(词)
            分 += 分_词元

    # ③ 泛化词命中：**不计分**，只如实记录（它们不能作为「同一件事」的证据）
    for 词 in 泛化词:
        if 词 in 描述 and 词 in 目标:
            泛化命中.append(词)

    # ④ 覆盖度：主干命中字数 ÷ 描述的中文总字数。
    #     无专名命中时靠它防「只有一小截撞上」被当同域（见 覆盖度_同域 注释）。
    总中文字 = sum(len(段) for 段 in 主干段表(描述))
    覆盖度 = (sum(len(词) for 词 in 主干命中) / 总中文字) if 总中文字 else 0.0
    是否同域 = (分 >= 阈值_同域) and (bool(专名命中) or 覆盖度 >= 覆盖度_同域)

    return {"分数": 分, "主干命中": 主干命中, "词元命中": 词元命中,
            "专名命中": 专名命中, "泛化命中": 泛化命中,
            "覆盖度": round(覆盖度, 3), "是否同域": 是否同域}
