"""说明书生成能力包装：由包内数据源生成 说明/使用说明.md（统一结果信封）。

算法在被包装的 `实现/说明书生成器.py`；本层只做参数归一与失败码映射
（内部 `校验输出目标` 的三类 ValueError：包目录不存在/输出根不是目录/路径逃逸，
前两类在本层先判，故剩余 ValueError 一律按路径逃逸如实回带）。

写盘能力：写到 `<输出根目录>/说明/使用说明.md`，**默认拒绝覆盖**；
调用方显式传 `允许重建骨架=True` 时，仅当目标仍是**模板骨架态**才允许覆盖
（人工改过的一律拒绝，见 `实现/说明书生成器.py` 的双重收紧）。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.组件规范支持库.实现.包装辅助 import 失败, 路径参数
from 支持库.后端.组件规范支持库.实现.说明书生成器 import (
    生成说明书 as _生成说明书,
)


def 生成说明书(包目录: Any = None, 输出根目录: Any = None, 允许重建骨架: Any = False) -> 结果:
    """生成 `<输出根目录>/说明/使用说明.md`；默认拒绝覆盖，骨架态可显式重建。"""
    源目录 = 路径参数(包目录)
    输出根 = 路径参数(输出根目录)
    if 源目录 is None:
        return 失败("参数不合法", f"包目录 必须是非空路径文本: {包目录!r}")
    if 输出根 is None:
        return 失败("参数不合法", f"输出根目录 必须是非空路径文本: {输出根目录!r}")
    if not isinstance(允许重建骨架, bool):
        return 失败("参数不合法", f"允许重建骨架 必须是逻辑型: {允许重建骨架!r}")
    if not 源目录.is_dir():
        return 失败("包目录不存在", f"包目录不是目录: {源目录}")
    if not 输出根.is_dir():
        return 失败("参数不合法", f"输出根目录不是目录: {输出根}")
    try:
        目标 = _生成说明书(源目录, 输出根, 允许重建骨架=允许重建骨架)
    except FileExistsError as 错误:
        return 失败("已存在", str(错误))
    except ValueError as 错误:
        return 失败("路径逃逸", str(错误))
    except OSError as 错误:
        return 失败("写入失败", f"说明书写入失败: {错误}")
    return 结果.成功结果({"说明书": str(目标), "已生成": True,
                       "重建骨架": 允许重建骨架,
                       "提示": "与人工维护内容 diff 后再纳入包目录（生成器默认拒绝覆盖）"})
