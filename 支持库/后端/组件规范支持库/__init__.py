def 注册能力(注册表) -> None:
    """由支持库加载器调用：注册组件包工程原子能力（实现取能力包装层，返回统一结果）。"""
    from 公共契约.能力契约.契约 import 能力实现

    契约表 = [
        ("组件规范支持库.生成完整性摘要", 生成完整性摘要能力,
         "按唯一生成器口径计算正式包的文件清单 sha256 摘要数据（只计算不写盘）"),
        ("组件规范支持库.校验完整性摘要", 校验完整性摘要能力,
         "校验包内 完整性摘要.json 与真实文件是否闭合"),
        ("组件规范支持库.生成模块模板", 生成模块模板能力,
         "按模块名/类型/能力清单生成模块包骨架与定向测试骨架"),
        ("组件规范支持库.校验组件规范", 校验组件规范能力,
         "只读校验组件目录是否符合统一九要素规范，问题列表为空即通过"),
        ("组件规范支持库.生成支持库模板", 生成支持库模板能力,
         "按能力清单生成九要素支持库包骨架与定向测试骨架"),
        ("组件规范支持库.生成技能模板", 生成技能模板能力,
         "按技能标识与验证用例生成技能包六件套与桥接脚本骨架"),
        ("组件规范支持库.生成快照清单模板", 生成快照清单模板能力,
         "生成核心快照结构骨架（清单/摘要/激活指针三件套）"),
        ("组件规范支持库.校验快照模板", 校验快照模板能力,
         "只读校验快照结构：三件套齐全、清单与磁盘一致、聚合摘要匹配"),
        ("组件规范支持库.生成并写入完整性摘要", 生成并写入完整性摘要能力,
         "生成并写入包内 完整性摘要.json（生成完整性摘要 的写盘配对）"),
        ("组件规范支持库.生成说明书", 生成说明书能力,
         "由包内数据源生成 <输出根目录>/说明/使用说明.md；默认拒绝覆盖，骨架态可显式重建"),
    ]
    for 能力id, 函数, 说明 in 契约表:
        注册表.注册(能力实现(
            能力id=能力id, 包id=包id, 实现函数=函数,
            参数=能力参数表[能力id], 返回="结果", 说明=说明))
