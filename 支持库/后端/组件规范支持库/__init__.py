def 注册能力(注册表) -> None:
    """由支持库加载器调用：注册组件包工程原子能力（实现取能力包装层，返回统一结果）。"""
    from 公共契约.能力契约.契约 import 能力实现

    契约表 = [
        ("组件规范支持库.生成完整性摘要", 生成完整性摘要能力,
         "按唯一生成器口径计算正式包的文件清单 sha256 摘要数据（只计算不写盘）"),
        ("组件规范支持库.校验完整性摘要", 校验完整性摘要能力,
         "校验包内 完整性摘要.json 与真实文件是否闭合"),
        ("组件规范支持库.生成模块模板", 生成模块模板能力,
         "按模块名/类型/能力清单生成模块包骨架与定向测试骨架"),
    ]
    for 能力id, 函数, 说明 in 契约表:
        注册表.注册(能力实现(
            能力id=能力id, 包id=包id, 实现函数=函数,
            参数=能力参数表[能力id], 返回="结果", 说明=说明))
