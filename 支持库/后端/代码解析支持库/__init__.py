"""代码解析支持库包级中文入口。

调用者只能经 40007 网关调用能力，禁止直接 import 实现目录。
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.后端.代码解析支持库.实现.代码解析 import 解析器基类, 扫描类属性

# 公开调用导出：能力短名映射到实现（实际调用一律经 40007 网关，此处供加载器发现与文档生成）
解析代码字节 = 解析器基类.解析代码字节
解析代码文件 = 解析器基类.解析代码文件
按规则切块 = 解析器基类.按规则切块
解码文本 = 解析器基类.解码文本
加载切块规则 = 解析器基类.加载切块规则

__version__ = "1.0.0"
__all__ = [
    "解析代码字节",
    "解析代码文件",
    "按规则切块",
    "解码文本",
    "加载切块规则",
    "扫描类属性",
    "注册能力",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用：注册代码解析原子能力。"""
    from 公共契约.能力契约.契约 import 能力实现
    from 公共契约.基础类型.结果类型 import 结果
    from 支持库.后端.代码解析支持库.实现.代码解析 import (
        扫描类属性, 解析器基类, 代码解析错误,
    )

    def _新建解析器(规则文件路径=None, 支持扩展名=None, 当前格式=None):
        from pathlib import Path
        解析器 = 解析器基类(Path(规则文件路径) if 规则文件路径 else None)
        if 支持扩展名 is not None:
            解析器.支持扩展名 = set(支持扩展名)
        elif 当前格式:
            # 缺省放行当前格式（白名单校验由调用方决定）
            解析器.支持扩展名 = {当前格式.lower().lstrip(".")}
        return 解析器

    def _包装解析代码字节(*, 原始字节, 文件id, 文件格式, 规则=None, 规则文件路径=None, 支持扩展名=None):
        try:
            解析器 = _新建解析器(规则文件路径, 支持扩展名, 文件格式)
            结果值 = 解析器.解析代码字节(文件id, 原始字节, 文件格式, 规则=规则)
            return 结果.成功结果(结果值)
        except 代码解析错误 as e:
            return 结果.失败("代码解析失败", str(e))
        except Exception as e:
            return 结果.失败("解析异常", str(e))

    def _包装解析代码文件(*, 文件id, 路径, 扩展名, 规则文件路径=None, 支持扩展名=None):
        try:
            from pathlib import Path
            解析器 = _新建解析器(规则文件路径, 支持扩展名, 扩展名)
            结果值 = 解析器.解析代码文件(文件id, Path(路径), 扩展名)
            return 结果.成功结果(结果值)
        except 代码解析错误 as e:
            return 结果.失败("代码解析失败", str(e))
        except Exception as e:
            return 结果.失败("解析异常", str(e))

    def _包装按规则切块(*, 内容, 文件id, 文件格式, 规则):
        try:
            解析器 = 解析器基类()
            结果值 = 解析器.按规则切块(内容, 文件id, 文件格式, 规则)
            return 结果.成功结果(结果值)
        except 代码解析错误 as e:
            return 结果.失败("代码解析失败", str(e))
        except Exception as e:
            return 结果.失败("解析异常", str(e))

    def _包装解码文本(*, 原始字节):
        try:
            文本, 编码 = 解析器基类.解码文本(原始字节)
            return 结果.成功结果({"文本": 文本, "编码": 编码})
        except 代码解析错误 as e:
            return 结果.失败("代码解析失败", str(e))
        except Exception as e:
            return 结果.失败("解析异常", str(e))

    def _包装加载切块规则(*, 规则文件路径, 强制重载=False):
        try:
            from pathlib import Path
            解析器 = 解析器基类(Path(规则文件路径))
            结果值 = 解析器.加载切块规则(强制重载)
            return 结果.成功结果(结果值)
        except 代码解析错误 as e:
            return 结果.失败("代码解析失败", str(e))
        except Exception as e:
            return 结果.失败("解析异常", str(e))

    for 能力id, 函数, 参数表, 说明 in [
        ("代码解析支持库.解析代码字节", _包装解析代码字节,
         [{"名称": "原始字节", "类型": "字节集型", "必填": 真},
          {"名称": "文件id", "类型": "整数型", "必填": 真},
          {"名称": "文件格式", "类型": "文本型", "必填": 真},
          {"名称": "规则", "类型": "字典型", "必填": 假},
          {"名称": "规则文件路径", "类型": "文本型", "必填": 假},
          {"名称": "支持扩展名", "类型": "列表型", "必填": 假}], "解析代码字节为块列表"),
        ("代码解析支持库.解析代码文件", _包装解析代码文件,
         [{"名称": "文件id", "类型": "整数型", "必填": 真},
          {"名称": "路径", "类型": "文本型", "必填": 真},
          {"名称": "扩展名", "类型": "文本型", "必填": 真},
          {"名称": "规则文件路径", "类型": "文本型", "必填": 真},
          {"名称": "支持扩展名", "类型": "列表型", "必填": 假}], "解析代码文件为块列表"),
        ("代码解析支持库.按规则切块", _包装按规则切块,
         [{"名称": "内容", "类型": "文本型", "必填": 真},
          {"名称": "文件id", "类型": "整数型", "必填": 真},
          {"名称": "文件格式", "类型": "文本型", "必填": 真},
          {"名称": "规则", "类型": "字典型", "必填": 真}], "按规则切分块"),
        ("代码解析支持库.解码文本", _包装解码文本,
         [{"名称": "原始字节", "类型": "字节集型", "必填": 真}], "解码文本"),
        ("代码解析支持库.加载切块规则", _包装加载切块规则,
         [{"名称": "规则文件路径", "类型": "文本型", "必填": 真},
          {"名称": "强制重载", "类型": "逻辑型", "必填": 假}], "加载切块规则"),
        ("代码解析支持库.扫描类属性", 扫描类属性,
         [{"名称": "目录", "类型": "文本型", "必填": 真},
          {"名称": "属性名", "类型": "文本型", "必填": 真},
          {"名称": "递归", "类型": "逻辑型", "必填": 假},
          {"名称": "排除关键字", "类型": "列表型", "必填": 假},
          {"名称": "最大文件数", "类型": "整数型", "必填": 假}], "AST 扫描类属性字符串赋值，产出去重值清单"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.代码解析支持库",
                实现函数=函数,
                参数=参数表,
                返回="结果",
                说明=说明,
            )
        )
