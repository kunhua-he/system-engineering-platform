"""嵌入句柄生命周期 + 嵌入缓存复用：本包不自己调模型、不自己建缓存。

为什么这样切（两句可验证的事实）：
- 嵌入只能经 `大语言模型支持库.模型连接器.连接向量模型 / 生成嵌入 / 释放句柄`；
  本包直接 import 模型连接器的 `实现/` 会被依赖防火墙拒（实测过同类违规）。
- 缓存只能经 `大语言模型支持库.嵌入缓存.查询嵌入 / 存储嵌入`；本包不建第二套缓存表。

句柄生命周期（**用完必释放**）：
- `取句柄` 内部会尝试本地模型拉起（`连接向量模型` 收 本地路径 时转调 `启动本地模型`，
  由底座起 llama-server 并把进程绑到句柄）；
- `释放句柄` 在 finally 里调，即使中途抛异常也不遗留进程与句柄（本地句柄释放会终止进程）；
- 句柄超时由包声明申报（默认 30 分钟），一直用持续重置。
"""
from __future__ import annotations

import re
from pathlib import Path

提供者标识 = "本地"
启动器名 = "llama-server"
句柄超时秒 = 1800
模型根候选 = (Path.home() / "Documents" / "AI模型", Path.home() / "AI模型")
向量目录关键字 = ("embedding", "向量", "bge", "embed")


def _调用能力(能力id: str, 参数: dict):
    from 公共契约.能力契约.调用器 import 获取能力调用器
    return 获取能力调用器().调用能力(能力id, 参数, 调用方="语义索引")


def _归一(文本: str) -> str:
    return re.sub(r"[^0-9a-z一-鿿]", "", 文本.lower())


def 解析本地模型路径(模型名: str) -> str:
    """按模型名在受管模型根下找 GGUF 权重；找不到返回空串（不猜、不造路径）。

    优先向量目录，其次任意目录；同目录多命中取文件名最短的（即主权重而非分片）。
    """
    目标 = _归一(模型名)
    if not 目标:
        return ""
    命中列表: list[tuple[int, int, str]] = []
    for 根 in 模型根候选:
        if not 根.is_dir():
            continue
        for 路径 in 根.rglob("*.gguf"):
            名称 = _归一(路径.stem)
            if 目标 not in 名称:
                continue
            在向量目录 = int(any(关键字 in _归一(str(路径.parent)) for 关键字 in 向量目录关键字))
            命中列表.append((-在向量目录, len(路径.name), str(路径)))
    if not 命中列表:
        return ""
    命中列表.sort()
    return 命中列表[0][2]


def 取句柄(模型名: str) -> tuple[int | None, str]:
    """取向量模型句柄；返回（句柄, 说明）。失败时句柄为 None、说明写清原因。"""
    本地路径 = 解析本地模型路径(模型名)
    参数 = {"模型": 模型名, "提供者": 提供者标识, "部署形态": "本地",
            "启动器": 启动器名, "超时秒": 句柄超时秒}
    if 本地路径:
        参数["本地路径"] = 本地路径
    结果 = _调用能力("大语言模型支持库.模型连接器.连接向量模型", 参数)
    if 结果.成功 and isinstance(结果.值, dict):
        句柄 = 结果.值.get("句柄")
        if isinstance(句柄, int) and not isinstance(句柄, bool):
            return 句柄, (f"已连接（本地权重 {本地路径}）" if 本地路径 else "已连接（未指定本地权重，按环境配置）")
        return None, "连接向量模型未返回有效句柄"
    说明 = f"{结果.错误码}: {结果.错误说明}" if not 结果.成功 else "连接向量模型返回值不是字典"
    if 本地路径:
        return None, f"{说明}（本地权重 {本地路径}）"
    return None, f"{说明}；且未在受管模型根下找到名为 {模型名} 的 GGUF 权重"


def 释放句柄(句柄: int) -> bool:
    """释放句柄（幂等）；返回是否释放成功。异常一律吞下（不遮主流程的错）。"""
    try:
        结果 = _调用能力("大语言模型支持库.模型连接器.释放句柄", {"句柄": 句柄})
        return bool(结果.成功)
    except Exception:
        return False


def 嵌入一条(句柄: int, 模型名: str, 文本: str) -> dict:
    """先查嵌入缓存，命中不重算；未命中才调模型并回写缓存。

    返回 {向量, 命中缓存, 错误说明}；向量为空表示本次失败，由调用方决定是跳过还是报错。
    """
    查询结果 = _调用能力("大语言模型支持库.嵌入缓存.查询嵌入",
                     {"文本": 文本, "模型名": 模型名, "提供者": 提供者标识})
    if 查询结果.成功 and isinstance(查询结果.值, dict) and 查询结果.值.get("命中"):
        向量 = 查询结果.值.get("向量")
        if isinstance(向量, list) and 向量:
            return {"向量": 向量, "命中缓存": True, "错误说明": ""}
    生成结果 = _调用能力("大语言模型支持库.模型连接器.生成嵌入", {"句柄": 句柄, "文本": 文本})
    if not 生成结果.成功 or not isinstance(生成结果.值, dict):
        return {"向量": [], "命中缓存": False,
                "错误说明": f"{生成结果.错误码}: {生成结果.错误说明}"}
    向量 = 生成结果.值.get("向量") or 生成结果.值.get("嵌入")
    if not isinstance(向量, list) or not 向量:
        return {"向量": [], "命中缓存": False, "错误说明": "生成嵌入未返回向量"}
    _调用能力("大语言模型支持库.嵌入缓存.存储嵌入",
            {"文本": 文本, "向量": 向量, "模型名": 模型名, "提供者": 提供者标识})
    return {"向量": 向量, "命中缓存": False, "错误说明": ""}


def 嵌入查询(模型名: str, 查询: str) -> tuple[list, str]:
    """查代码块用：临时取句柄 → 嵌入查询 → 必释放；返回（向量, 错误说明）。"""
    句柄, 说明 = 取句柄(模型名)
    if 句柄 is None:
        return [], 说明
    try:
        结果 = 嵌入一条(句柄, 模型名, 查询)
    finally:
        释放句柄(句柄)
    if 结果["错误说明"]:
        return [], 结果["错误说明"]
    return 结果["向量"], ""


