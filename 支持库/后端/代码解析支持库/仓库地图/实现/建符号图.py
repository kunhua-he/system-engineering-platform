"""仓库地图 · 建符号图：抽定义/引用建加权有向图并落 SQLite。

解析一律**复用** `代码解析支持库.语法索引` 的既有能力（批量解析语法），
本包不自写解析器；单文件失败隔离进 `跳过清单`，不让整批挂掉。
跨包只走对方**包级公开入口**（依赖防火墙：支持库仅限包级公开入口）。
"""

from __future__ import annotations

import time
from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.代码解析支持库.仓库地图.实现.参数口径 import (
    参数错误, 取文本, 取文本列表, 取枚举列表,
)
from 支持库.后端.代码解析支持库.仓库地图.实现.仓库扫描 import 扫描
from 支持库.后端.代码解析支持库.仓库地图.实现.图构建 import 建图
from 支持库.后端.代码解析支持库.仓库地图.实现.图库 import 关闭, 建库, 落点, 写入, 来源

语言表 = ("python", "typescript", "vue")
#: 单次入参文件数上限：一次把整仓代码文本塞进一次能力调用会把入参顶爆。
批量上限 = 200


def 建符号图(*, 仓库根: str = "", 排除目录: list | None = None,
             语言集: list | None = None, 库文件: str = "") -> 结果:
    """抽定义/引用建加权有向图并落 SQLite（必填参数在实现内校验：与 HTTP 同口径）。"""
    起点 = time.perf_counter()
    try:
        根 = Path(取文本("仓库根", 仓库根, 必填=True)).expanduser()
        排除 = 取文本列表("排除目录", 排除目录)
        收窄 = 取枚举列表("语言集", 语言集, 允许值=语言表)
        落点参数 = 取文本("库文件", 库文件, 必填=False)
    except 参数错误 as 错误:
        return 结果.失败(错误.错误码, 错误.说明, 来源=来源)
    if not 根.is_dir():
        return 结果.失败("目录不存在", f"仓库根不是目录: {根}", 来源=来源)
    文件表, 跳过清单 = 扫描(根.resolve(), 排除, 收窄)
    if not 文件表:
        return 结果.失败("解析失败", f"仓库根下没有可建图的源码文件: {根}", 来源=来源)
    事实表, 失败清单 = _批量解析(文件表)
    跳过清单.extend(失败清单)
    if not 事实表:
        return 结果.失败("解析失败", "全部源码文件均解析失败，未建图", 来源=来源)
    节点表, 边表 = 建图(文件表, 事实表)
    连接结果 = 建库(落点(str(根.resolve()), 落点参数))
    if not 连接结果.成功:
        return 连接结果
    连接 = 连接结果.值
    try:
        写结果 = 写入(连接, 节点表, 边表)
    finally:
        关闭(连接)
    if not 写结果.成功:
        return 写结果
    return 结果.成功结果({
        "节点数": len(节点表),
        "边数": len(边表),
        "文件数": len(事实表),
        "耗时秒": round(time.perf_counter() - 起点, 4),
        "跳过清单": 跳过清单,
    })


def _批量解析(文件表: list[dict]) -> tuple[list[dict], list[dict]]:
    """复用 语法索引.批量解析语法 抽事实；按批切分，失败清单原样转 跳过清单。"""
    from 支持库.后端.代码解析支持库.语法索引 import 批量解析语法

    索引 = {项["相对路径"]: 项 for 项 in 文件表}
    事实表: list[dict] = []
    失败清单: list[dict] = []
    for 起 in range(0, len(文件表), 批量上限):
        批次 = 文件表[起:起 + 批量上限]
        入参 = [{"路径": 项["相对路径"], "代码文本": 项["代码文本"],
                "语法集": 项["语法集"]} for 项 in 批次]
        结果值 = 批量解析语法(文件列表=入参)
        if not getattr(结果值, "成功", False):
            说明 = getattr(结果值, "错误说明", "") or "批量解析失败"
            失败清单.extend({"路径": 项["相对路径"], "原因": 说明} for 项 in 批次)
            continue
        值 = 结果值.值 or {}
        for 事实 in 值.get("结果列表") or []:
            原文 = 索引.get(str(事实.get("路径") or ""))
            if 原文 is not None:
                事实表.append(_补文件信息(事实, 原文))
        for 失败 in 值.get("失败列表") or []:
            失败清单.append({
                "路径": str(失败.get("路径") or ""),
                "原因": str(失败.get("错误说明") or 失败.get("错误码") or "解析失败"),
            })
    return 事实表, 失败清单


def _补文件信息(事实: dict, 原文: dict) -> dict:
    """把单文件事实集补上文件级信息与行表（建图与签名抽取都要用）。"""
    补充 = dict(事实)
    补充["相对路径"] = 原文["相对路径"]
    补充["语言"] = 原文["语言"]
    补充["语法集"] = 原文["语法集"]
    补充["代码行表"] = 原文["代码文本"].splitlines()
    return 补充
