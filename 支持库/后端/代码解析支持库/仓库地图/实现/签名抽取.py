"""符号签名抽取：从定义行裁出「def 名(参数) / class 名」形态，不输出函数体。

语法事实（`符号列表`）只给名称/类别/行号/结束行号，**不带签名文本**；
签名必须从源码行现取——这是「地图里带签名」与「地图里只有名字」的分界。
"""

from __future__ import annotations

#: 单条签名长度上限：超长签名（一行写死的长参数表）截断，不拿它去吃 token 预算。
最大签名长度 = 160
行尾噪声字符 = ":{};"


def 取签名(代码行表: list[str], 起始行: int, 类别: str, 名称: str) -> str:
    """按定义行裁剪签名：去掉行尾冒号/花括号与多余空白；取不到时退化为「类别 名称」。"""
    退化值 = f"{类别} {名称}"
    if 起始行 < 1 or 起始行 > len(代码行表):
        return 退化值
    签名 = (代码行表[起始行 - 1] or "").strip()
    if not 签名:
        return 退化值
    while 签名 and 签名[-1] in 行尾噪声字符:
        签名 = 签名[:-1].rstrip()
    if len(签名) > 最大签名长度:
        签名 = 签名[:最大签名长度].rstrip() + "…"
    return 签名 or 退化值
