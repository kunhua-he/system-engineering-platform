"""地图渲染：把排名后的「渲染单元」序列渲染成紧凑文本，并给出 token 估算口径。

渲染单元（unit）是二分的粒度：一个文件头是一单元，一条符号签名也是一单元。
为什么粒度是**符号**而不是文件（对齐 aider repo map 的关键做法）：
按文件二分时，只要排名第一的文件放不下就整张地图空掉（实测 200 token 预算下
收录文件数=0）；按符号二分能得到「最大可容纳前缀」，预算小也能给出可用的头几条。
「不是截断字符串」的判据仍然成立：任何被收录的单元都是**完整的一行**。
"""

from __future__ import annotations

每token字符数 = 3
地图首行 = "仓库地图（文件 + 符号签名；token 口径 = 字符数/3）"
文件单元 = "文件"
符号单元 = "符号"


def 估算token(文本: str) -> int:
    """token 估算：字符数/3 向上取整（中文场景保守口径）。"""
    return -(-len(文本) // 每token字符数)


def 展开单元(文件块表: list[dict]) -> list[dict]:
    """把「文件块表」展平成有序渲染单元序列：文件头在前，其符号随后。"""
    单元表: list[dict] = []
    for 文件 in 文件块表:
        单元表.append({"类型": 文件单元, "文件": 文件["路径"],
                     "文本": f"{文件['路径']}:"})
        for 符号 in 文件["符号列表"]:
            单元表.append({"类型": 符号单元, "文件": 文件["路径"],
                         "文本": "  " + (符号["签名"] or f"{符号['类别']} {符号['名称']}")})
    return 单元表


def 渲染(单元表: list[dict]) -> str:
    """渲染地图文本：首行 + 空行 + 全部单元（每个单元独占一行）。"""
    行表 = [地图首行, ""]
    行表.extend(单元["文本"] for 单元 in 单元表)
    return "\n".join(行表)


def 统计(单元表: list[dict]) -> tuple[int, int]:
    """统计 (收录文件数, 收录符号数)；文件数按实际出现的文件头单元计。"""
    文件数 = sum(1 for 单元 in 单元表 if 单元["类型"] == 文件单元)
    符号数 = sum(1 for 单元 in 单元表 if 单元["类型"] == 符号单元)
    return 文件数, 符号数
