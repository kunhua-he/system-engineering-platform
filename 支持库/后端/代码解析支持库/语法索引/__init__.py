"""代码解析支持库.语法索引 包级中文入口。"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.后端.代码解析支持库.语法索引.实现.语法索引 import (
    批量解析语法, 解析Python语法, 解析脚本语法,
)

__all__ = ["解析Python语法", "解析脚本语法", "批量解析语法"]

包id = "支持库.后端.代码解析支持库.语法索引"


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 参数契约镜像（**函数内字面量**；本块由「丢参」缺陷修复注入，勿删）
    #
    # 缺陷溯源（2026-09-18 注入；2026-09-22 按 #204 铺开到剩余旧入口）：本入口原先手工
    # 重建注册参数声明，`默认值`/`说明` 全靠手抄，抄漏即静默丢参——网关按**入口注册表**
    # 过滤入参（`运行核心/统一网关/协议/类型规格.py` 的必填判据是 `项.get("必填") is 真`），
    # 入口表漏一个参数，新参数就传了没反应（#197 实测：`文件系统支持库.文件操作.目录树`
    # 漏了 `忽略模式`，两次验收都拿到旧行为）。修法：参数声明从 `能力契约/参数契约.json`
    # **整条透传**（`参数=_参数契约表[能力id]`），入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：
    #  ① `_参数契约表` 是字面量、键是常量，`开发工具/契约编译/漂移检测` 的 AST 读取器
    #     （`_静态字面量` 的 `ast.Subscript` 分支）能解析出**整条参数含 `必填`/`默认值`**；
    #     放在函数内是因为该读取器只收 `注册能力` 函数体内的赋值（`_扫描注册语句`）。
    #  ② 表内布尔位写**中文 `真`／`假`**（正式口径，真源 `公共契约/基础类型/逻辑类型.py`）；
    #     本文件顶部已 import 真/假，漂移检测读取器（`_导入常量绑定`）能静态解析出参数表。
    # 为什么按下标取而不是包一层 `_参数声明(能力id)`：包一层会让 AST 一律判「不可静态
    # 判定」，等于拿门禁覆盖率换干净（不可接受）。契约名序/返回口径核验由装配期唯一闸门承担
    # （`运行核心/加载器/生命周期管理/管理器.装配系统` → 内核 `能力注册表.校验声明一致`），本入口不再另立第二份。
    _参数契约表 = {
        "代码解析支持库.语法索引.解析Python语法": [
            {"名称": "代码文本", "类型": "文本型", "必填": 真, "默认值": None, "说明": "Python 源码文本"},
        ],
        "代码解析支持库.语法索引.解析脚本语法": [
            {"名称": "代码文本", "类型": "文本型", "必填": 真, "默认值": None, "说明": "TypeScript 或 Vue 源码文本"},
            {"名称": "语法集", "类型": "文本型", "必填": 假, "默认值": "typescript", "说明": "typescript 或 vue"},
        ],
        "代码解析支持库.语法索引.批量解析语法": [
            {"名称": "文件列表", "类型": "列表型", "必填": 真, "默认值": None, "说明": "元素为 {路径, 代码文本, 语法集(选填)}；语法集缺省按 python"},
        ],
    }
# ===== 参数声明透传 结束 =====
    契约表 = [
        ("代码解析支持库.语法索引.解析Python语法", 解析Python语法,
         "ast 解析 Python 源码，产出导入/符号/调用/字符串型类属性四类有序语法事实"),
        ("代码解析支持库.语法索引.解析脚本语法", 解析脚本语法,
         "tree-sitter 解析 TypeScript/Vue 源码（不可用时正则降级），产出导入/符号/调用/字符串四类有序语法事实"),
        ("代码解析支持库.语法索引.批量解析语法", 批量解析语法,
         "按语法集分派批量解析，结果严格保序，单文件失败隔离进失败列表"),
    ]
    for 能力id, 函数, 说明 in 契约表:
        注册表.注册(能力实现(
            能力id=能力id, 包id=包id, 实现函数=函数,
            参数=_参数契约表[能力id], 返回="结果", 说明=说明))
