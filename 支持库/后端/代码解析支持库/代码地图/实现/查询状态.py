"""代码地图 · 查询状态：只读报告索引可用性与覆盖率，替代「目录存在性」弱判据。

**为什么要这个能力（2026-09-22，批F F1）**：`开工编排.开工准备` 原先只能给
「`.codegraph` 目录存在」这种**弱判据** —— 目录在、但库是空的 / 缺表 / 落后源码，
调用方一样收到「可用」。本能力直读 SQLite 报真实状态，并在传了 `项目根` 时给出
**覆盖率**：仓库里有多少 `.py` 还没进索引（这是 F1 要求的覆盖率键）。

**不跑外部 CLI**：`codegraph status` 是子进程、实测 45 秒超时（见
`模块库/开工编排/说明/待补能力清单.md:32`），把它放进开工路径会拖垮开工。
本能力只读 SQLite + 扫仓库文件名，秒级完成 —— 先稳（不引长阻塞）后快（一次给足信息）。
"""

from __future__ import annotations

import os
from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.代码解析支持库.代码地图.实现.参数口径 import 参数错误, 取文本
from 支持库.后端.代码解析支持库.代码地图.实现.只读连接 import (
    关闭代码地图, 打开代码地图, 来源,
)

#: 覆盖率扫描时跳过的目录（与 `运行发布门禁_逐包合规._扫描工程缓存Python源码` 同口径：
#: 这几棵子树可能含数 GB 文件，且它们本身有独立门禁，不该算进「源码覆盖率」）。
跳过目录表 = frozenset({
    "__pycache__", ".git", "工程缓存", "node_modules",
    ".venv", "提供者运行环境", "编译缓存", "制品仓库",
})

状态_可用 = "可用"
状态_需同步 = "需同步"
状态_不存在 = "不存在"
状态_缺表 = "缺表"
状态_打不开 = "打不开"


def 查询状态(*, 代码地图路径: str = "", 项目根: str = "") -> 结果:
    """只读报告代码地图状态（必填参数在实现内校验：进程内调用与 HTTP 同口径）。

    - `代码地图路径`：`.codegraph/codegraph.db` 的路径（必填）。
    - `项目根`：传了才算覆盖率（可选；不传时 `覆盖率` 为 `{}`）。

    返回值（统一结果信封）：`{可用, 状态, 详情, 节点数, 边数, 已索引文件数, 覆盖率}`。
    `状态` 取值：`可用` / `需同步` / `不存在` / `缺表` / `打不开`。
    **状态不是错误**：`不存在`/`缺表`/`打不开` 仍按成功返回（调用方要的是「现在能不能用」，
    不是一个异常），只有参数不合法才失败。
    """
    try:
        地图路径 = 取文本("代码地图路径", 代码地图路径, 必填=True)
        根路径 = 取文本("项目根", 项目根, 必填=False)
    except 参数错误 as 错误:
        return 结果.失败(错误.错误码, 错误.说明, 来源=来源)

    路径 = Path(str(地图路径))
    if not 路径.is_file():
        return 结果.成功结果({
            "可用": False, "状态": 状态_不存在,
            "详情": f"代码地图文件不存在: {路径}（先跑代码地图索引器生成）",
            "节点数": 0, "边数": 0, "已索引文件数": 0, "覆盖率": {},
        })

    连接结果 = 打开代码地图(地图路径)
    if not 连接结果.成功:
        # `打开代码地图` 已区分「缺表」与「打不开」，但只给错误码；这里按详情分档。
        详情文本 = str(连接结果.错误说明)
        档位 = 状态_缺表 if "缺少表" in 详情文本 else 状态_打不开
        return 结果.成功结果({
            "可用": False, "状态": 档位, "详情": 详情文本,
            "节点数": 0, "边数": 0, "已索引文件数": 0, "覆盖率": {},
        })

    连接 = 连接结果.值
    try:
        节点数 = 连接.execute("SELECT COUNT(*) FROM nodes").fetchone()[0]
        边数 = 连接.execute("SELECT COUNT(*) FROM edges").fetchone()[0]
        已索引文件数 = 连接.execute(
            "SELECT COUNT(DISTINCT file_path) FROM nodes").fetchone()[0]
    except Exception as 错误:  # 统一结果铁律：实现不外抛，真实原因原样回带
        return 结果.成功结果({
            "可用": False, "状态": 状态_打不开,
            "详情": f"读取统计失败: {type(错误).__name__}: {错误}",
            "节点数": 0, "边数": 0, "已索引文件数": 0, "覆盖率": {},
        })
    finally:
        关闭代码地图(连接)

    覆盖率 = _算覆盖率(根路径, 已索引文件数) if 根路径 else {}
    需同步原因 = _判需同步(节点数, 覆盖率)
    可用 = not 需同步原因
    return 结果.成功结果({
        "可用": 可用,
        "状态": 状态_可用 if 可用 else 状态_需同步,
        "详情": (f"索引可用：{节点数} 个节点 / {边数} 条边 / {已索引文件数} 个文件"
                 if 可用 else f"索引需同步：{需同步原因}"),
        "节点数": 节点数,
        "边数": 边数,
        "已索引文件数": 已索引文件数,
        "覆盖率": 覆盖率,
    })


def _算覆盖率(项目根: str, 已索引文件数: int) -> dict:
    """扫 `项目根` 下的 `.py` 数量，报「已索引 / 未索引 / 覆盖率」。

    为什么用「文件数比」而不是逐个比对路径：索引器写进 `nodes.file_path` 的形态
    （相对/绝对、是否带 `./`）由外部 CLI 决定，本能力不猜它的口径；文件数比是
    **口径无关**的保守判据，够回答「索引是不是落后了」。
    """
    根 = Path(str(项目根))
    if not 根.is_dir():
        return {"说明": f"项目根不存在或不是目录: {根}"}
    仓库文件数 = 0
    try:
        for 当前根, 目录名表, 文件名表 in os.walk(根):
            目录名表[:] = [名称 for 名称 in 目录名表 if 名称 not in 跳过目录表]
            仓库文件数 += sum(1 for 名称 in 文件名表 if 名称.endswith(".py"))
    except OSError as 错误:
        return {"说明": f"扫描项目根失败: {错误}"}
    未索引数 = max(0, 仓库文件数 - 已索引文件数)
    比例 = (已索引文件数 / 仓库文件数) if 仓库文件数 else 0.0
    return {
        "仓库py文件数": 仓库文件数,
        "已索引py文件数": 已索引文件数,
        "未索引py文件数": 未索引数,
        "覆盖率": round(比例, 4),
    }


def _判需同步(节点数: int, 覆盖率: dict) -> str:
    """返回「需同步」的原因；空串表示可用。"""
    if 节点数 <= 0:
        return "索引里 0 个节点（库在但没内容）"
    未索引 = 覆盖率.get("未索引py文件数")
    if isinstance(未索引, int) and 未索引 > 0:
        比例 = 覆盖率.get("覆盖率", 0.0)
        return f"仓库有 {未索引} 个 .py 未进索引（覆盖率 {比例}）"
    return ""
