"""数据结构原子能力实现（不对外暴露，只经包级中文入口调用）。

职责：栈/队列 数据结构（参考易语言数据结构支持库，保持原子）。
每个结构实例用六位句柄登记（状态机统一生命周期）。
纯标准库，不做业务逻辑。
"""

from __future__ import annotations

import threading
from collections import deque

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.句柄体系 import 句柄体系, 句柄类型_资源

句柄系统 = 句柄体系()
结构表: dict[int, dict] = {}   # 句柄 → {类型, 容器}
锁 = threading.Lock()


def _创建结构(类型: str) -> 结果:
    with 锁:
        对象 = 句柄系统.创建句柄(句柄类型=句柄类型_资源, 资源id=f"数据结构-{类型}", 所有者="")
        结构表[对象.句柄id] = {"类型": 类型, "容器": deque() if 类型 == "队列" else []}
    return 结果.成功结果({"句柄": 对象.句柄id, "类型": 类型,
                            "说明": f"{类型}已创建，持句柄操作；默认30分钟超时可续约"})

def _取结构(句柄: int) -> tuple[dict | None, str]:
    有效, 原因 = 句柄系统.校验(句柄id=句柄)
    if not 有效:
        return None, 原因
    结构 = 结构表.get(句柄)
    if 结构 is None:
        return None, f"结构 {句柄} 不存在（可能已超时释放）"
    return 结构, ""


def 创建栈() -> 结果:
    """创建栈（后进先出）。返回句柄。句柄超时按本包 `包声明.json` 的 `句柄超时秒`（历史上收过未使用的 `超时秒` 形参，2026-09-22 已删）。"""
    return _创建结构("栈")


def 创建队列() -> 结果:
    """创建队列（先进先出）。返回句柄。句柄超时按本包 `包声明.json` 的 `句柄超时秒`（历史上收过未使用的 `超时秒` 形参，2026-09-22 已删）。"""
    return _创建结构("队列")


def 压栈(句柄: int = None, 值: object = None) -> 结果:
    """入栈。返回 {大小}。"""
    结构, 原因 = _取结构(句柄)
    if 结构 is None:
        return 结果.失败("句柄失效", 原因, 来源="数据结构")
    if 结构["类型"] != "栈":
        return 结果.失败("参数不合法", "句柄不是栈", 来源="数据结构")
    结构["容器"].append(值)
    return 结果.成功结果({"大小": len(结构["容器"])})


def 出栈(句柄: int = None) -> 结果:
    """出栈。返回 {值, 大小}。"""
    结构, 原因 = _取结构(句柄)
    if 结构 is None:
        return 结果.失败("句柄失效", 原因, 来源="数据结构")
    if 结构["类型"] != "栈":
        return 结果.失败("参数不合法", "句柄不是栈", 来源="数据结构")
    if not 结构["容器"]:
        return 结果.失败("栈为空", "无法出栈", 来源="数据结构")
    值 = 结构["容器"].pop()
    return 结果.成功结果({"值": 值, "大小": len(结构["容器"])})


def 入队(句柄: int = None, 值: object = None) -> 结果:
    """入队。返回 {大小}。"""
    结构, 原因 = _取结构(句柄)
    if 结构 is None:
        return 结果.失败("句柄失效", 原因, 来源="数据结构")
    if 结构["类型"] != "队列":
        return 结果.失败("参数不合法", "句柄不是队列", 来源="数据结构")
    结构["容器"].append(值)
    return 结果.成功结果({"大小": len(结构["容器"])})


def 出队(句柄: int = None) -> 结果:
    """出队。返回 {值, 大小}。"""
    结构, 原因 = _取结构(句柄)
    if 结构 is None:
        return 结果.失败("句柄失效", 原因, 来源="数据结构")
    if 结构["类型"] != "队列":
        return 结果.失败("参数不合法", "句柄不是队列", 来源="数据结构")
    if not 结构["容器"]:
        return 结果.失败("队列为空", "无法出队", 来源="数据结构")
    值 = 结构["容器"].popleft()
    return 结果.成功结果({"值": 值, "大小": len(结构["容器"])})


def 释放句柄(句柄: int = None) -> 结果:
    """释放结构句柄（幂等）。"""
    if isinstance(句柄, bool) or not isinstance(句柄, int) or not 1 <= 句柄 <= 999999:
        return 结果.失败("参数不合法", "句柄必须是1到999999的整数", 来源="数据结构")
    with 锁:
        结构表.pop(句柄, None)
        句柄系统.失效(句柄, "释放")
    return 结果.成功结果({"句柄": 句柄, "状态": "已释放", "已释放": True})
