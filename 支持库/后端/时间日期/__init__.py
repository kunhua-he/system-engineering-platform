"""时间日期支持库包级中文入口。"""

from __future__ import annotations

from 支持库.后端.时间日期.实现.时间日期 import 获取当前时间
from 支持库.后端.时间日期.实现.时间日期 import 格式化为文本
from 支持库.后端.时间日期.实现.时间日期 import 解析文本时间
from 支持库.后端.时间日期.实现.时间日期 import 时间戳转换
from 支持库.后端.时间日期.实现.时间日期 import 计算间隔
from 支持库.后端.时间日期.实现.时间日期 import 注入时钟, 恢复默认时钟

__all__ = [
    "获取当前时间",
    "格式化为文本",
    "解析文本时间",
    "时间戳转换",
    "计算间隔",
    "注入时钟", "恢复默认时钟",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型 in [
        ("时间日期.获取当前时间", 获取当前时间, [], "结果"),
        ("时间日期.格式化为文本", 格式化为文本, ['时间戳', '格式'], "结果"),
        ("时间日期.解析文本时间", 解析文本时间, ['文本', '格式'], "结果"),
        ("时间日期.时间戳转换", 时间戳转换, ['时间戳'], "结果"),
        ("时间日期.计算间隔", 计算间隔, ['起始时间戳', '结束时间戳'], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.时间日期",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回=返回类型,
                说明="原子能力",
            )
        )
