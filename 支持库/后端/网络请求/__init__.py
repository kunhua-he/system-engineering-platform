"""网络请求支持库包级中文入口（外部协议边界）。

调用者只从此入口导入，禁止深入 实现/ 目录。
安全默认：SSRF 防护（拒绝回环/内网/私有地址）、响应大小上限、凭证不泄漏。
"""

from __future__ import annotations

from 支持库.后端.网络请求.实现.网络请求 import 发送请求
from 支持库.后端.网络请求.实现.网络请求 import 构建查询串

__all__ = [
    "发送请求",
    "构建查询串",
]


def 注册能力(注册表) -> None:
    """由适配层加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型 in [
        ("网络请求.发送请求", 发送请求,
         ['地址', '方法', '请求参数', '超时秒', '最大字节数', '允许回环', '取消标记'], "结果"),
        ("网络请求.构建查询串", 构建查询串, ['参数'], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.网络请求",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回=返回类型,
                说明="HTTP 客户端原子能力（外部协议边界）",
            )
        )
