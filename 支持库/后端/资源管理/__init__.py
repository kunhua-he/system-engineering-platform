"""资源管理支持库包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
"""

from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现
from 支持库.后端.资源管理.实现.资源管理 import (
    创建内容摘要,
    创建不可变快照,
    创建唯一运行目录,
    原子写入,
    原子替换,
    比较并交换,
    资源短锁,
    安全释放资源,
)

__all__ = [
    "创建内容摘要", "创建不可变快照", "创建唯一运行目录",
    "原子写入", "原子替换", "比较并交换", "资源短锁", "安全释放资源",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库全部能力。"""
    契约表 = [
        ("资源管理.创建内容摘要", 创建内容摘要, ["文件路径"], "结果"),
        ("资源管理.创建不可变快照", 创建不可变快照, ["来源目录", "快照目录"], "结果"),
        ("资源管理.创建唯一运行目录", 创建唯一运行目录, ["基础目录"], "结果"),
        ("资源管理.原子写入", 原子写入, ["目标路径", "内容"], "结果"),
        ("资源管理.原子替换", 原子替换, ["目标路径", "新内容", "期望版本"], "结果"),
        ("资源管理.比较并交换", 比较并交换, ["目标路径", "期望值", "新值"], "结果"),
        ("资源管理.资源短锁", 资源短锁, ["锁目录", "资源id", "持有者"], "结果"),
        ("资源管理.安全释放", 安全释放资源, ["路径"], "结果"),
    ]
    for 能力id, 函数, 参数名, 返回类型 in 契约表:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.资源管理",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "文本"} for 名称 in 参数名],
                返回=返回类型,
                说明="资源管理原子能力",
            )
        )
