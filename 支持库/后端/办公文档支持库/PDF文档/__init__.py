"""PDF文档支持库包级中文入口（经调用器调用受管提供者 PDF隔离提供者）。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：解析PDF(文件路径, 最大页数, 最大字节数, 超时秒) → 结果[通用文档]
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 公共契约.能力契约.契约 import 能力实现
from 支持库.后端.办公文档支持库.PDF文档.实现.PDF文档 import 解析PDF

__all__ = ["解析PDF"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 缺陷溯源：本入口原先手工重建注册参数声明（`参数=[...]`），只写 名称/类型/必填，
    # `默认值` 整批缺声明（2026-09-24 实测本包 3 条、全仓 93 条）。后果：网关按入口
    # 契约表判参时拿不到默认值 —— 「≥10 秒须走异步腿」的守卫**不传参即被绕过**
    # （解析PDF 契约 超时秒 默认 60，实测不传参成功=true）。
    # 手工表一旦漏一个参数，新参数还会被网关**静默丢弃**（同族现场见未完成事项 #197）。
    # 修法：参数声明从 `能力契约/参数契约.json` **整条透传**，入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：漂移检测的 AST 读取器
    # （`_静态字面量` 的 `ast.Subscript` 分支）只收 `注册能力` 函数体内的赋值，
    # 包一层 `_参数声明(能力id)` 会让 AST 一律判「不可静态判定」，等于拿门禁覆盖率换干净。
    # 表内布尔位写中文 真/假（真源 公共契约/基础类型/逻辑类型.py）。
    # 契约名序/返回口径核验由装配期唯一闸门承担（`运行核心/加载器/生命周期管理/管理器.装配系统`
    # → 内核 `能力注册表.校验声明一致`），本入口不再另立第二份。
    _参数契约表 = {
        "办公文档支持库.PDF文档.解析PDF": [
            {"名称": "文件路径", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "最大页数", "类型": "整数型", "必填": 假, "默认值": 500},
            {"名称": "最大字节数", "类型": "整数型", "必填": 假, "默认值": 209715200},
            {"名称": "超时秒", "类型": "双精度数型", "必填": 假, "默认值": 60},
        ],
    }
# ===== 参数声明透传 结束 =====
    注册表.注册(
        能力实现(
            能力id="办公文档支持库.PDF文档.解析PDF",
            包id="支持库.后端.办公文档支持库.PDF文档",
            实现函数=解析PDF,
            参数=_参数契约表["办公文档支持库.PDF文档.解析PDF"],
            返回="结果型",
            说明="解析 PDF 为平台通用文档（经 PDF隔离提供者 隔离子进程解析）",
        )
    )
