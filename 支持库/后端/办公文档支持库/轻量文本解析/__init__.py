"""办公文档支持库.轻量文本解析 包级中文入口。"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.后端.办公文档支持库.轻量文本解析.实现.轻量文本解析 import (
    解析Markdown块, 解析纯文本块,
)

__all__ = ["解析Markdown块", "解析纯文本块"]

包id = "支持库.后端.办公文档支持库.轻量文本解析"


def _校验参数名序(参数契约表: dict[str, list[dict]],
                  注册参数名序: dict[str, list[str]]) -> None:
    """装配期闸门：注册参数名序必须逐字等于契约名序，否则本包装配失败。

    为什么要有它：入口原先手工重建参数表，将来契约加一个参数而入口漏加，
    网关就按入口的参数表传参——新参数被静默丢弃。名序护盾让这种「漏参」在
    装配期就 raise，不再静默（参数事实源只有 能力契约/参数契约.json 一处，哲学 12.1）。
    """
    for 能力id, 契约参数 in 参数契约表.items():
        注册名序 = 注册参数名序.get(能力id)
        if 注册名序 is None:
            raise ValueError(f"能力 {能力id} 有契约但注册处未声明参数名序")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(注册名序):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(注册名序)} 与契约参数名序 {契约名序} "
                "不一致：参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），"
                "入口不得另立一份")


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现
    _参数契约表 = {
        "办公文档支持库.轻量文本解析.解析Markdown块": [
            {"名称": "文本", "类型": "文本型", "必填": 真, "默认值": None, "说明": "Markdown 文本，内部归一化 CRLF/CR"},
            {"名称": "语法集", "类型": "文本型", "必填": 假, "默认值": "完整", "说明": "完整=8 类块；简化=3 类块（标题判定也更宽松）"},
        ],
        "办公文档支持库.轻量文本解析.解析纯文本块": [
            {"名称": "文本", "类型": "文本型", "必填": 真, "默认值": None, "说明": "纯文本，内部归一化 CRLF/CR"},
        ],
    }
    _注册参数名序 = {
        "办公文档支持库.轻量文本解析.解析Markdown块": ["语法集", "文本"],
        "办公文档支持库.轻量文本解析.解析纯文本块": ["文本"],
    }
    _校验参数名序(_参数契约表, _注册参数名序)
    契约表 = [
        ("办公文档支持库.轻量文本解析.解析Markdown块", 解析Markdown块,
         "把 Markdown 文本切成中间块列表（完整 8 类 / 简化 3 类）"),
        ("办公文档支持库.轻量文本解析.解析纯文本块", 解析纯文本块,
         "把纯文本按空行切成段落中间块列表"),
    ]
    for 能力id, 函数, 说明 in 契约表:
        注册表.注册(能力实现(
            能力id=能力id, 包id=包id, 实现函数=函数, 参数=_参数契约表[能力id],
            返回="结果", 说明=说明))

