def 登记临时资源(路径: str = None, 开工ID: str | None = None) -> 结果:
    """登记一个临时资源（文件或目录），由 清理全部临时资源 统一释放。

    ★ 2026-09-24（批R R-31）：登记表同时是「平台自管临时资源」这一豁免的事实源
    （`公共契约/运行时/写入授权.设自管临时资源读取器`），故**登记腿必须自带授权闸**
    —— 否则「先登记任意受管路径、再让清理腿删掉」就是一条绕过写入/删除判据的越权口子。
    两道闸与 `删除文件` / `清理全部临时资源` 逐字同序（先认人、再认路径）。
    非受管路径（运行期临时区、`工程缓存/`）照旧直接放行，既有调用方行为不变。
    """
    if not isinstance(路径, str) or not 路径.strip():
        return 结果.失败("参数不合法", "路径必须为非空文本", 来源="文件系统")
    拒绝 = _身份拒绝()
    if 拒绝 is not None:
        return 拒绝
    授权 = 授权拒绝结果(路径, "文件系统", 开工ID)
    if 授权 is not None:
        return 授权
    with _临时资源锁:
        _临时资源登记表.add(路径)
        return 结果.成功结果(len(_临时资源登记表))


def 清理全部临时资源(路径前缀: str = "", 允许危险路径: bool = 假,
                     开工ID: str | None = None) -> 结果:
    """清理已登记临时资源（文件删除/目录递归删除，不存在视为幂等成功）。

    路径前缀 非空时只清理以此前缀开头的登记资源；无匹配登记资源时返回
    资源不存在（避免静默什么都不做）。登记表变更全部在锁内完成。

    危险路径护栏：清理=删除动作，逐条登记资源默认拒绝命中危险路径判据的目标
    （护栏在任何删除发生之前完成判定，命中即整批不改动）；允许危险路径=真 显式放行并如实标注。
    """
    if 路径前缀 is None or not isinstance(路径前缀, str):
        return 结果.失败("参数不合法", "路径前缀必须为文本", 来源="文件系统")
    拒绝 = _身份拒绝()
    if 拒绝 is not None:
        return 拒绝
    with _临时资源锁:
        # 前缀匹配必须按**路径段边界**（缺陷 #151，2026-09-20）：
        # 裸 `startswith` 是字符串级匹配，前缀 `工程缓存/tmp/abc` 会连
        # `工程缓存/tmp/abcxxx`（相邻但不同的登记项）一起匹配并 `rmtree` —— 误删。
        # 加 `os.sep` 边界后只匹配「就是它本身」或「它在某段之下」。
        待清理 = _临时资源登记表 if not 路径前缀 else {
            路径 for 路径 in _临时资源登记表
            if 路径 == 路径前缀 or 路径.startswith(路径前缀 + os.sep)
        }
        if 路径前缀 and not 待清理:
            return 结果.失败("资源不存在", f"无匹配前缀 {路径前缀} 的登记资源", 来源="文件系统")
        for 路径 in sorted(待清理):
            # ★ 2026-09-25 补挂（本批开工-20260925-161955-849f）：清理 = 删除动作，与
            #   `删除文件` / `删除目录` 同族，此前只有 `_身份拒绝` 一道闸。补第二判据；
            #   登记表里的条目是「平台自管临时资源」（`写入授权` 已豁免），故对既有调用方
            #   行为一字不变，只把「换一个能力调就绕过去」的第二扇门关掉。
            授权 = 授权拒绝结果(路径, "文件系统", 开工ID)
            if 授权 is not None:
                return 授权
            拦截 = 拦截危险路径(路径, 允许危险路径, "清理全部临时资源")
            if 拦截 is not None:
                return 拦截
        清理失败表 = []
        清理数量 = 0
        # ★ 清理腿也要开解锁窗口（2026-09-23 复核补）：登记资源可能落在**已锁的**
        #   事实源目录里，不开窗口时 `unlink`/`清只读后删除树` 必被内核拒、全部进
        #   `清理失败表`（fail-closed、如实报错，不留洞，但这条腿在锁态下等于不可用）。
        from 公共契约.运行时.仓库只读锁 import 临时解锁
        with 临时解锁(*[Path(项) for 项 in 待清理], 开工ID=str(开工ID or "").strip()):
            for 路径 in list(待清理):
                try:
                    目标 = Path(路径)
                    if 目标.is_dir():
                        清只读后删除树(目标)
                    else:
                        目标.unlink(missing_ok=True)
                    清理数量 += 1
                    _临时资源登记表.discard(路径)
                except OSError as 错误:
                    清理失败表.append(f"{路径}: {错误}")
        清理标注 = 汇总放行标注(sorted(待清理))
    if 清理失败表:
        return 结果.失败("清理失败", "；".join(清理失败表), 来源="文件系统")
    if 清理标注:
        return 结果.成功结果({"清理数量": 清理数量, "危险路径放行": 清理标注})
    return 结果.成功结果(清理数量)
