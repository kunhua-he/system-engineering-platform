def _窗口落盘(目标: Path, 写动作: Callable[[], None],
             窗口表: tuple[Path, ...], 开工ID: str = "") -> None:
    """在 `临时解锁树` 窗口里执行 `写动作`，**成功与失败两条路都把落点对齐到上下文锁态**。

    为什么要有这一个函数（哲学 1.2「同一件事只有一处实现」）：`复制文件` / `移动文件`
    是**同一族**腿（骨架都是「在解锁窗口里新建或覆盖一个落点，出来把落点对齐到
    它所在上下文的锁态」）—— 骨架与对齐必须**两腿共用一份**，各写一遍就会像本轮之前
    那样「成功路径对齐了、失败路径漏了」（同一根因只修一处）。

    **失败路径为什么也必须对齐（本轮修的洞 ⑤，2026-09-23）**：`shutil.copy2` / 移动腿
    在窗口内**写半截后抛错**（ENOSPC / EINTR）时，落点**已经存在**，但它**进入窗口时
    不存在** ⇒ 不在 `临时解锁树` 的「原状态」表里 ⇒ 窗口 `finally` 只重锁「进入时确实
    锁着的」条目，半截落点不在其中 ⇒ **锁树里留下一个未锁的半截文件**
    （可在其中凭空新建/改写内容，`查询()` 的未锁数由 0 变 1）。
    故对齐动作从「成功路径上的一行」提成「`try/finally` 里的一条腿」：`finally` 覆盖
    成功、`OSError`、以及 `KeyboardInterrupt` 这类非 `OSError` 的中断 —— **只有一处实现**，
    不靠在 `except` 里再补一遍（那是同一件事的第二套实现）。

    **为什么对齐仍在解锁窗口之外调**：窗口内父目录是**临时解锁态**，那时读上下文锁态
    得到的是「未锁」，对齐会得出错误答案（既有实测：窗口内对齐后副本仍 `flags` 为空）。
    `finally` 里窗口已经退出（`with` 的 `__exit__` 在栈展开中先跑），故读到的是真锁态。

    **为什么用 `ExitStack` 而不是把窗口开在调用方**：移动腿要同时开**源与目标**两个窗口
    （源处删 + 目标处写），复制腿只开目标一个；窗口表由调用方给，`ExitStack` 让
    「一个到两个窗口」共用同一段代码，两腿的 `with` 嵌套不必各写一份。

    分工：窗口的开启、`mkdir(parents=True)` 与失败路径的对齐都归本函数（两腿共同的骨架），
    调用方只描述「窗口开在哪、真正动磁盘的那一句是什么」。

    `开工ID`（2026-09-25 本批）：开窗本身也过授权判据（`仓库只读锁._要求写入授权`）⇒
    由调用方（`复制文件` / `移动文件`）穿透进来，本函数原样交给 `临时解锁树`。
    """
    from 公共契约.运行时.仓库只读锁 import 临时解锁树, 对齐目标锁态
    try:
        with contextlib.ExitStack() as 栈:
            for 项 in 窗口表:
                栈.enter_context(临时解锁树(项, 开工ID=开工ID))
            目标.parent.mkdir(parents=True, exist_ok=True)
            写动作()
    finally:
        对齐目标锁态(目标)


def 复制文件(源路径: str = None, 目标路径: str = None,
             允许危险路径: bool = 假, 开工ID: str | None = None) -> 结果:
    """复制文件到目标路径（自动创建父目录）。

    危险路径护栏只判**目标路径**（源路径只读，不构成系统性破坏）；
    允许危险路径=真 显式放行并如实标注。
    """
    拒绝 = _身份拒绝()
    if 拒绝 is not None:
        return 拒绝
    if 源路径 is None or not isinstance(源路径, str) or not 源路径.strip():
        return 结果.失败("参数不合法", "源路径必须为非空文本", 来源="文件系统")
    if 目标路径 is None or not isinstance(目标路径, str) or not 目标路径.strip():
        return 结果.失败("参数不合法", "目标路径必须为非空文本", 来源="文件系统")
    源 = Path(源路径)
    if not 源.is_file():
        return 结果.失败("文件不存在", f"源文件不存在: {源路径}", 来源="文件系统")
