"""危险路径护栏（相对安全的底线，不是工作区牢笼）。

哲学依据：《系统哲学》第 9 条 5 项「相对安全，不做绝对安全」（华哥 2026-09-16 裁定）
- 底座面向**本地私有部署**，安全是**相对安全**；追求绝对安全会让能力萎缩、失去全通用性；
- **全通用的标准是用户拥有绝对自主权**；
- 但**底线护栏（防止「系统性破坏」）属于必须项，优先级高于用户自主权**；
- 需要更严边界时由调用方**传参选择**；**不许把相对安全包装成绝对边界**。

本模块只做一件事：判定一个**目标路径**是否命中「危险路径判据」。
- 只拦**会改变系统状态**的动作（写入/追加/删除/移动/复制/建目录/解压落盘/清理登记资源），默认拒绝；
- 调用方传 `允许危险路径=真` 时**显式放行**并如实标注，用户绝对自主权不被剥夺；
- **不是**工作区沙箱：不设「工作区根目录」，不限制普通路径——未命中判据的路径一律照常执行，
  能力不萎缩、保持全通用性（这就是「护栏式」而非「牢笼式」的分界）。

判据来源：华哥 2026-09-16 裁定 + 第三份外部审计 P0-03
（`实现/文件系统.py` 原有 读取文件/写入文件/删除文件 只做 Path 转换、无任何危险路径拦截，
可被覆盖 ~/.zshrc、~/.ssh/authorized_keys、/etc/hosts，属「系统性破坏」范畴）。

=====================================================================
危险路径判据全文（命中任意一条即视为危险路径）
=====================================================================
一、系统目录（目录本身及其全部子路径）—— **表本身不在本模块**（#174 收口，2026-09-21）
    平台差异的唯一落点是 `公共契约/运行时/平台适配`：本模块只调 `平台适配.系统位置表()`
    拿当前平台的表并逐条比对，**不写 `是Windows()` 分支**（写了即「取值后自行分叉」，
    会被 `开发工具/验证门禁/平台判断越界检测.py` 规则二判红）。

    POSIX（macOS / Linux，见 `平台适配.POSIX系统位置表`）：
    /etc、/System、/usr、/bin、/sbin、/var/db、
    /Library/LaunchDaemons、/Library/LaunchAgents、
    /dev、/boot，
    以及 macOS 上解析软链接后的真实位置别名：/private/etc、/private/var/db、/private/System。

    Windows（见 `平台适配.Windows系统位置表`，#174 补）：
    C:\\Windows、C:\\Windows\\System32（含 drivers\\etc、config、WindowsPowerShell）、
    C:\\Program Files、C:\\Program Files (x86)、
    C:\\ProgramData\\Microsoft\\Windows\\Start Menu（含其下 Programs\\StartUp 启动文件夹）。

    **为什么修前 Windows 上等于没拦**：`Path("/etc")` 在 Windows 上解析成**当前盘根下的
    `\\etc`**，与真正该拦的 `C:\\Windows\\System32\\drivers\\etc\\hosts` 毫无关系。

二、用户凭据与启动配置（家目录内）—— 表同样收口在 `平台适配.家目录敏感位置表()`
    1. 凭据目录整棵：`~/.ssh/**`（含 `~/.ssh` 本目录，两平台同名）；
    2. 钥匙串目录整棵：`~/Library/Keychains/**`（含目录本身，POSIX）；
    3. PowerShell 配置目录整棵（Windows）：`~/Documents/PowerShell/**`、
       `~/Documents/WindowsPowerShell/**`；
    4. 用户启动文件夹整棵（Windows）：
       `~/AppData/Roaming/Microsoft/Windows/Start Menu/Programs/Startup/**`；
    5. shell 启动配置单文件（精确文件名，大小写不敏感）：
       `~/.zshrc`、`~/.zprofile`、`~/.zshenv`、`~/.zlogin`、`~/.zlogout`、
       `~/.bashrc`、`~/.bash_profile`、`~/.bash_login`、`~/.bash_logout`、
       `~/.profile`、`~/.cshrc`、`~/.tcshrc`、`~/.inputrc`；
    6. `~/.config/` 下的 shell 配置：
       整棵目录 `~/.config/fish/**`、`~/.config/zsh/**`、`~/.config/bash/**`（含目录本身）；
       以及 `~/.config/` 直接子文件中的 shell 配置单文件（同名集合同第 5 条）。

三、任何指向上述位置的软链接父路径
    判定同时用「未解析的绝对路径」与「resolve() 后的真实路径」两份候选：
    目标本身是软链接、或任一祖先目录是指向上述位置的软链接，都会在解析后命中，
    防止用 `ln -s /etc XXX && 写入文件(XXX/hosts)` 这类软链接绕过。

四、明确**不在**护栏范围（护栏只防系统性破坏，不做沙箱）
    - 家目录下的普通文件与目录（如 `~/Documents/...`、`~/Desktop/...`、`~/下载/...`）；
    - 项目目录、`/tmp`、`/var/tmp`、用户自建的任意工作目录；
    - `~/Library/Application Support/**` 等应用数据目录；
    - 只读动作（读取文件、列出目录、判断存在、获取大小、获取修改时间、获取文件权限、
      读取二进制文件、读取文件头部字节、搜索文件、查找祖先目录、登记临时资源）——
      读不改系统状态，不属系统性破坏，**默认不拦**（边缘个例见父会话裁决清单）。

五、实现口径
    - 命中即返回**明确失败**（错误码 `危险路径`，说明含「目标路径命中危险路径护栏：<命中哪一条>；
      如确需操作，请显式传 允许危险路径=真」）；
    - `允许危险路径=真` 时跳过护栏、照常执行，并在返回结果里如实标注
      「已按调用方显式放行危险路径」（透明、不隐瞒）；
    - `允许危险路径` 非逻辑型 → 参数不合法（不静默按假处理）；
    - 判据本身不随包配置改写：要更严边界由调用方在更上层传参选择，不在本层偷偷收紧。
"""

from __future__ import annotations

from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.运行时.平台适配 import 家目录敏感位置表, 系统位置表

# ---------------------------------------------------------------------------
# 判据数据（单一事实源：判据全文由本模块导出，文档与代码注释均引用此处口径）
# ---------------------------------------------------------------------------

#: 系统位置表与家目录敏感位置表**都不在本模块**（#174 收口，2026-09-21）：
#: 平台差异（POSIX 位置 vs Windows 位置）的唯一落点是 `公共契约/运行时/平台适配`，
#: 本模块只调它的**取值型原语**拿当前平台的表，绝不写 `是Windows()` 分支
#: （「取值后自行分叉」会被 开发工具/验证门禁/平台判断越界检测.py 规则二判红）。
#: 表内容见 `平台适配.POSIX系统位置表` / `Windows系统位置表` / `家目录敏感位置表`。

#: 家目录敏感位置的命中说明（**只影响返回文案**，不影响判据；键是相对家目录的路径，
#: 与 `平台适配.Windows家目录敏感位置表` 的写法逐字一致）
家目录敏感位置说明: dict[str, str] = {
    ".ssh": "用户凭据目录 ~/.ssh（含其子路径）",
    "Library/Keychains": "用户钥匙串目录 ~/Library/Keychains（含其子路径）",
    "Documents\\PowerShell": "用户 PowerShell 配置目录 ~/Documents/PowerShell（含其子路径）",
    "Documents\\WindowsPowerShell":
        "用户 PowerShell 配置目录 ~/Documents/WindowsPowerShell（含其子路径）",
    "AppData\\Roaming\\Microsoft\\Windows\\Start Menu\\Programs\\Startup":
        "用户启动文件夹（含其子路径）",
}

shell启动配置文件名: tuple[str, ...] = (
    ".zshrc", ".zprofile", ".zshenv", ".zlogin", ".zlogout",
    ".bashrc", ".bash_profile", ".bash_login", ".bash_logout",
    ".profile", ".cshrc", ".tcshrc", ".inputrc",
)

用户配置目录名 = ".config"
用户配置内shell配置目录: tuple[str, ...] = ("fish", "zsh", "bash")

错误码 = "危险路径"


def _是同一路径或子路径(路径: Path, 目标: Path) -> bool:
    """路径是否等于目标或位于目标之下（按路径部件比较，杜绝 /etcx 这类字符串前缀绕过）。"""
    return 路径 == 目标 or 目标 in 路径.parents


def _文件名命中(路径: Path, 名称集合: tuple[str, ...]) -> bool:
    """文件名是否命中集合（大小写不敏感：macOS 文件系统默认大小写不敏感）。"""
    return 路径.name.lower() in {名称.lower() for 名称 in 名称集合}


def _命中系统目录(路径: Path) -> str:
    for 目录 in 系统位置表():
        if _是同一路径或子路径(路径, Path(目录)):
            return f"系统目录 {目录}（含其子路径）"
    return ""


def _命中家目录凭据(路径: Path) -> str:
    家目录 = Path.home()
    for 相对 in 家目录敏感位置表():
        根 = 家目录 / 相对
        if _是同一路径或子路径(路径, 根):
            return 家目录敏感位置说明.get(相对, f"用户敏感目录 ~/{相对}（含其子路径）")
    if _是同一路径或子路径(路径, 家目录) and 路径.parent == 家目录 \
            and _文件名命中(路径, shell启动配置文件名):
        return f"用户 shell 启动配置 ~/{路径.name}"
    配置根 = 家目录 / 用户配置目录名
    if _是同一路径或子路径(路径, 配置根):
        相对部件 = 路径.relative_to(配置根).parts
        if 相对部件 and 相对部件[0].lower() in {名.lower() for 名 in 用户配置内shell配置目录}:
            return f"用户 ~/.config 内 shell 配置目录 ~/.config/{相对部件[0]}（含其子路径）"
        if len(相对部件) == 1 and _文件名命中(路径, shell启动配置文件名):
            return f"用户 ~/.config 内 shell 配置 ~/.config/{路径.name}"
    return ""


判据表 = (
    ("系统目录", _命中系统目录),
    ("用户凭据与启动配置", _命中家目录凭据),
)


# ---------------------------------------------------------------------------
# 判定与护栏（供 实现/文件系统.py、实现/文件系统补充.py 调用）
# ---------------------------------------------------------------------------

def 命中的危险路径判据(路径文本: str) -> str:
    """返回命中的判据说明；空文本表示未命中（不属于系统性破坏范畴，照常执行）。

    候选路径两份：未解析的绝对路径 + resolve() 后的真实路径。
    第二份用于覆盖「目标或父路径是指向危险位置的软链接」这一规避形态。
    """
    if not isinstance(路径文本, str) or not 路径文本.strip():
        return ""
    候选列表 = [Path(路径文本).expanduser().absolute()]
    try:
        真实路径 = Path(路径文本).expanduser().resolve()
    except OSError:
        真实路径 = None
    if 真实路径 is not None and 真实路径 not in 候选列表:
        候选列表.append(真实路径)
    for 候选 in 候选列表:
        for _, 判定 in 判据表:
            命中 = 判定(候选)
            if 命中:
                return 命中
    return ""


def 拦截危险路径(路径文本: str, 允许危险路径: bool,
                  动作: str) -> 结果 | None:
    """护栏入口：命中且未显式放行时返回失败结果；否则返回 None（调用方照常执行）。

    - 允许危险路径 非逻辑型 → 参数不合法（不静默按假处理，也不静默按真放行）；
    - 未命中判据 → None（护栏不介入，普通路径能力不萎缩）；
    - 命中且 允许危险路径=假 → 明确失败（错误码 危险路径，说明含命中哪一条与放行方式）；
    - 命中且 允许危险路径=真 → None（显式放行，透明标注由 放行标注 提供）。
    """
    if not isinstance(允许危险路径, bool):
        return 结果.失败("参数不合法", "允许危险路径必须是逻辑型（真/假）",
                        来源="文件系统")
    命中 = 命中的危险路径判据(路径文本)
    if not 命中 or 允许危险路径:
        return None
    return 结果.失败(
        错误码,
        f"{动作}目标路径命中危险路径护栏：{命中}；"
        f"如确需操作，请显式传 允许危险路径=真（路径: {路径文本}）",
        来源="文件系统",
    )


def 放行标注(路径文本: str) -> str:
    """调用方显式放行时的透明标注文案（随成功结果一并返回，不隐瞒）。"""
    命中 = 命中的危险路径判据(路径文本)
    if not 命中:
        return ""
    return f"已按调用方显式放行危险路径：{命中}（路径: {路径文本}）"


def 汇总放行标注(路径列表: list[str]) -> str:
    """多路径能力（如移动/清理）的放行标注汇总；无命中返回空文本。"""
    命中列表 = [放行标注(路径) for 路径 in 路径列表]
    命中列表 = [项 for 项 in 命中列表 if 项]
    return "；".join(命中列表)
