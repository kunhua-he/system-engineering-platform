from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现
from 支持库.后端.文件系统.实现.文件系统 import (
    创建目录,
    复制文件,
    读取二进制文件,
    读取文件,
    读取文件头部字节,
    登记临时资源,
    清理全部临时资源,
    判断存在,
    删除文件,
    获取大小,
    获取修改时间,
    列出目录,
    移动文件,
    写入文件,
)

__all__ = [
    "读取文件", "读取二进制文件", "读取文件头部字节", "写入文件", "判断存在", "列出目录",
    "删除文件", "复制文件", "移动文件", "获取大小", "获取修改时间", "创建目录",
    "登记临时资源", "清理全部临时资源",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库全部能力。"""
    契约表 = [
        ("文件系统.读取文件", 读取文件, ["文件路径", "编码"], "结果"),
        ("文件系统.读取二进制文件", 读取二进制文件, ["受控根目录", "相对路径", "最大字节数"], "结果"),
        ("文件系统.读取文件头部字节", 读取文件头部字节, ["受控根目录", "相对路径", "字节数"], "结果"),
        ("文件系统.写入文件", 写入文件, ["文件路径", "内容", "编码"], "结果"),
        ("文件系统.判断存在", 判断存在, ["文件路径"], "布尔"),
        ("文件系统.列出目录", 列出目录, ["目录路径"], "结果"),
        ("文件系统.删除文件", 删除文件, ["文件路径"], "结果"),
        ("文件系统.复制文件", 复制文件, ["源路径", "目标路径"], "结果"),
        ("文件系统.移动文件", 移动文件, ["源路径", "目标路径"], "结果"),
        ("文件系统.获取大小", 获取大小, ["文件路径"], "结果"),
        ("文件系统.获取修改时间", 获取修改时间, ["文件路径"], "结果"),
        ("文件系统.创建目录", 创建目录, ["目录路径"], "结果"),
        ("文件系统.登记临时资源", 登记临时资源, ["路径"], "结果"),
        ("文件系统.清理全部临时资源", 清理全部临时资源, [], "结果"),
    ]
    for 能力id, 函数, 参数名, 返回类型 in 契约表:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文件系统",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "文本"} for 名称 in 参数名],
                返回=返回类型,
                说明="文件系统原子能力",
            )
        )
