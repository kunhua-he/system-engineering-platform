"""并发控制事件与管道：事件总线 / 流管道（内部实现，不对外）。

本模块由 `实现/并发控制.py` 按职责簇**原样搬出**（对外符号零变化：`并发控制.py`
逐名再导出，全仓调用方与 `__init__.py` 的 `from ….实现.并发控制 import X` 照旧成立）。

两簇都是「有界队列 + 双语义/生产消费」形态，句柄助手 `_创建` / `_取` / `_句柄键`
的落点见 `实现/并发句柄核心.py`（共享底座，本模块只引用不复制）：
- **事件总线**：通知 vs 决策双语义 —— 通知类广播给全部订阅者，决策类按订阅顺序
  逐个询问、显式 `继续` 才走下一个（DeepSeek 事件总线模式化落地）；
- **流管道**：生产者写入 / 消费者读取的有界 FIFO 队列，调用方立即返回再读取
  （Coze 流管道模式化落地）。
"""

from __future__ import annotations

import threading

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.并发控制支持库.实现.并发句柄核心 import _创建, _句柄键, _取

# ═══════════════════════════════════════════════════════════════════
# 事件总线（DeepSeek 事件总线模式化：通知 vs 决策双语义，waterfall 显式 next）
# 通知类 = 广播给所有订阅者；决策类 = 按订阅顺序逐个询问，显式 next 才继续。
# ═══════════════════════════════════════════════════════════════════
_事件总线表: dict[int, dict] = {}
_事件总线锁 = threading.Lock()
_事件总线序号 = 0


def 创建事件总线(*, 名称: str = None, 队列上限: int = None) -> 结果:
    """创建事件总线。返回句柄。通知/决策双语义，订阅者队列有界。"""
    global _事件总线序号
    try:
        总线名 = str(名称 or "").strip()
        if not 总线名:
            return 结果.失败("参数不合法", "名称不能为空", 来源="并发控制")
        上限 = 队列上限 if isinstance(队列上限, int) and 队列上限 > 0 else 1000
        with _事件总线锁:
            _事件总线序号 += 1
            总线 = {
                "名称": 总线名, "队列上限": 上限,
                "订阅者": [],  # [{序号, 事件名, 模式(通知/决策), 说明}]
                "通知次数": 0, "决策次数": 0,
                "创建时间": __import__("time").time(),
            }
            结果对象 = _创建("事件总线", 总线, f"事件总线已创建（{总线名}）")
            if 结果对象.成功:
                _事件总线表[_句柄键(结果对象.值["句柄"])] = 总线
            return 结果对象
    except Exception as 异常:
        return 结果.失败("创建事件总线失败", str(异常), 来源="并发控制")


def 订阅事件(*, 句柄: int = None, 事件名: str = None, 模式: str = None,
             订阅者名: str = None) -> 结果:
    """订阅事件。模式=通知（广播）或 决策（按序询问，显式 next 才继续）。"""
    try:
        总线对象, 原因 = _取(句柄, "事件总线")
        if 总线对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        事件 = str(事件名 or "").strip()
        if not 事件:
            return 结果.失败("参数不合法", "事件名不能为空", 来源="并发控制")
        模式值 = str(模式 or "通知").strip()
        if 模式值 not in ("通知", "决策"):
            return 结果.失败("参数不合法", f"模式必须为 通知/决策（当前 {模式值}）", 来源="并发控制")
        with _事件总线锁:
            if len(总线对象["订阅者"]) >= 总线对象["队列上限"]:
                return 结果.失败("队列已满", "订阅者数量超过队列上限", 来源="并发控制")
            序号 = len(总线对象["订阅者"]) + 1
            总线对象["订阅者"].append({
                "序号": 序号, "事件名": 事件, "模式": 模式值,
                "订阅者名": str(订阅者名 or f"订阅者{序号}"),
            })
        return 结果.成功结果({"序号": 序号, "事件名": 事件, "模式": 模式值})
    except Exception as 异常:
        return 结果.失败("订阅失败", str(异常), 来源="并发控制")


def 取消订阅(*, 句柄: int = None, 序号: int = None) -> 结果:
    """取消订阅。按订阅序号移除。"""
    try:
        总线对象, 原因 = _取(句柄, "事件总线")
        if 总线对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        with _事件总线锁:
            旧表 = 总线对象["订阅者"]
            目标 = [s for s in 旧表 if s["序号"] == int(序号 or -1)]
            if not 目标:
                return 结果.失败("订阅不存在", f"序号 {序号} 未订阅", 来源="并发控制")
            总线对象["订阅者"] = [s for s in 旧表 if s["序号"] != int(序号)]
        return 结果.成功结果({"已取消": True, "序号": int(序号), "订阅者名": 目标[0]["订阅者名"]})
    except Exception as 异常:
        return 结果.失败("取消订阅失败", str(异常), 来源="并发控制")


def 发布通知(*, 句柄: int = None, 事件名: str = None, 负载: dict = None) -> 结果:
    """发布通知类事件（广播）。返回收到通知的订阅者列表。"""
    try:
        总线对象, 原因 = _取(句柄, "事件总线")
        if 总线对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        事件 = str(事件名 or "").strip()
        if not 事件:
            return 结果.失败("参数不合法", "事件名不能为空", 来源="并发控制")
        with _事件总线锁:
            接收者 = [s for s in 总线对象["订阅者"]
                      if s["事件名"] == 事件 and s["模式"] == "通知"]
            for s in 接收者:
                s.setdefault("历史", []).append(负载 or {})
            if len(接收者) > 0:
                总线对象["通知次数"] += 1
        return 结果.成功结果({
            "已通知": len(接收者),
            "订阅者": [s["订阅者名"] for s in 接收者],
            "事件名": 事件,
        })
    except Exception as 异常:
        return 结果.失败("发布通知失败", str(异常), 来源="并发控制")


def 发布决策(*, 句柄: int = None, 事件名: str = None, 负载: dict = None,
             继续: bool = None) -> 结果:
    """发布决策类事件（waterfall：按订阅顺序逐个询问，显式 next 才继续）。
    返回首个订阅者处理结果；后续订阅者需 继续=true 才会被询问。"""
    try:
        总线对象, 原因 = _取(句柄, "事件总线")
        if 总线对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        事件 = str(事件名 or "").strip()
        if not 事件:
            return 结果.失败("参数不合法", "事件名不能为空", 来源="并发控制")
        with _事件总线锁:
            决策者 = [s for s in 总线对象["订阅者"]
                       if s["事件名"] == 事件 and s["模式"] == "决策"]
            if not 决策者:
                return 结果.成功结果({"已处理": False, "原因": "无决策订阅者", "事件名": 事件})
            询问数 = 0
            for s in 决策者:
                询问数 += 1
                s.setdefault("决策历史", []).append({"负载": 负载 or {}, "已处理": True})
                if not s.get("显式继续", False) and 继续 is not True:
                    # 首个订阅者处理即停（默认 waterfall）
                    s["显式继续"] = False
                    总线对象["决策次数"] += 1
                    return 结果.成功结果({
                        "已处理": True, "事件名": 事件,
                        "处理者": s["订阅者名"], "询问数": 询问数,
                        "负载": 负载 or {},
                    })
            s["显式继续"] = False
            总线对象["决策次数"] += 1
            return 结果.成功结果({
                "已处理": True, "事件名": 事件,
                "处理者": "末位订阅者", "询问数": 询问数,
                "负载": 负载 or {}, "已走完": True,
            })
    except Exception as 异常:
        return 结果.失败("发布决策失败", str(异常), 来源="并发控制")


def 查询事件总线(*, 句柄: int = None) -> 结果:
    """查询事件总线状态（订阅者/通知次数/决策次数）。句柄空=列全部。"""
    try:
        if 句柄 is None:
            with _事件总线锁:
                return 结果.成功结果({"事件总线列表": [
                    {"句柄": k, "名称": v["名称"], "订阅者数": len(v["订阅者"]),
                     "通知次数": v["通知次数"], "决策次数": v["决策次数"]}
                    for k, v in _事件总线表.items()
                ]})
        总线对象, 原因 = _取(句柄, "事件总线")
        if 总线对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        with _事件总线锁:
            return 结果.成功结果({
                "名称": 总线对象["名称"], "队列上限": 总线对象["队列上限"],
                "订阅者": [{"序号": s["序号"], "事件名": s["事件名"], "模式": s["模式"],
                             "订阅者名": s["订阅者名"]} for s in 总线对象["订阅者"]],
                "通知次数": 总线对象["通知次数"], "决策次数": 总线对象["决策次数"],
            })
    except Exception as 异常:
        return 结果.失败("查询失败", str(异常), 来源="并发控制")


# ═══════════════════════════════════════════════════════════════════
# 流管道运行器（Coze 流管道模式化：管道+任务序列+事件名，调用方立即返回读取）
# ═══════════════════════════════════════════════════════════════════
_流管道表: dict[int, dict] = {}
_流管道锁 = threading.Lock()
_流管道序号 = 0


def 创建流管道(*, 名称: str = None, 容量上限: int = None) -> 结果:
    """创建流管道（生产者写入/消费者读取，有界队列）。返回句柄。"""
    global _流管道序号
    try:
        管道名 = str(名称 or "").strip()
        if not 管道名:
            return 结果.失败("参数不合法", "名称不能为空", 来源="并发控制")
        上限 = 容量上限 if isinstance(容量上限, int) and 容量上限 > 0 else 1000
        with _流管道锁:
            _流管道序号 += 1
            管道 = {
                "名称": 管道名, "容量上限": 上限,
                "队列": [],  # [{事件名, 负载, 序号}]
                "已写入": 0, "已读取": 0,
                "创建时间": __import__("time").time(),
            }
            结果对象 = _创建("流管道", 管道, f"流管道已创建（{管道名}）")
            if 结果对象.成功:
                _流管道表[_句柄键(结果对象.值["句柄"])] = 管道
            return 结果对象
    except Exception as 异常:
        return 结果.失败("创建流管道失败", str(异常), 来源="并发控制")


def 管道写入(*, 句柄: int = None, 事件名: str = None, 负载: dict = None) -> 结果:
    """向流管道写入一条事件（生产者）。队列满返回 队列已满。"""
    try:
        管道对象, 原因 = _取(句柄, "流管道")
        if 管道对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        事件 = str(事件名 or "").strip()
        if not 事件:
            return 结果.失败("参数不合法", "事件名不能为空", 来源="并发控制")
        with _流管道锁:
            if len(管道对象["队列"]) >= 管道对象["容量上限"]:
                return 结果.失败("队列已满", f"流管道 {管道对象['名称']} 队列已满", 来源="并发控制")
            管道对象["已写入"] += 1
            管道对象["队列"].append({"事件名": 事件, "负载": 负载 or {}, "序号": 管道对象["已写入"]})
        return 结果.成功结果({"已写入": True, "序号": 管道对象["已写入"]})
    except Exception as 异常:
        return 结果.失败("管道写入失败", str(异常), 来源="并发控制")


def 管道读取(*, 句柄: int = None, 数量: int = None) -> 结果:
    """从流管道读取事件（消费者；FIFO 出队）。返回 {条目数, 条目列表}。"""
    try:
        管道对象, 原因 = _取(句柄, "流管道")
        if 管道对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        请求数 = 数量 if isinstance(数量, int) and 数量 > 0 else 1
        with _流管道锁:
            取出 = 管道对象["队列"][:请求数]
            del 管道对象["队列"][:请求数]
            管道对象["已读取"] += len(取出)
        return 结果.成功结果({
            "条目数": len(取出), "剩余": len(管道对象["队列"]),
            "条目列表": 取出,
        })
    except Exception as 异常:
        return 结果.失败("管道读取失败", str(异常), 来源="并发控制")


def 查询流管道(*, 句柄: int = None) -> 结果:
    """查询流管道状态。句柄空=列全部。"""
    try:
        if 句柄 is None:
            with _流管道锁:
                return 结果.成功结果({"流管道列表": [
                    {"句柄": k, "名称": v["名称"], "队列中": len(v["队列"]),
                     "已写入": v["已写入"], "已读取": v["已读取"]}
                    for k, v in _流管道表.items()
                ]})
        管道对象, 原因 = _取(句柄, "流管道")
        if 管道对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        with _流管道锁:
            return 结果.成功结果({
                "名称": 管道对象["名称"], "容量上限": 管道对象["容量上限"],
                "队列中": len(管道对象["队列"]), "已写入": 管道对象["已写入"],
                "已读取": 管道对象["已读取"],
            })
    except Exception as 异常:
        return 结果.失败("查询失败", str(异常), 来源="并发控制")


