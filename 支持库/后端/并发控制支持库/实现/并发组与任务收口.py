"""并发控制并发组与任务收口：并发组 / 结构化任务结果（内部实现，不对外）。

本模块由 `实现/并发控制.py` 按职责簇**原样搬出**（对外符号零变化：`并发控制.py`
逐名再导出，全仓调用方与 `__init__.py` 的 `from ….实现.并发控制 import X` 照旧成立）。

两簇同为「任务汇聚 → 终态收口」语义：
- **并发组**：一组任务并发跑、等待全部结束，失败即停 / 收口不打断双语义
  （Coze errgroup 模式化落地）；
- **结构化任务结果**：把成功值/取消/异常统一收敛为结构化终态，严格 / 收口双模式，
  异常不外抛。

句柄助手 `_创建` / `_取` / `_句柄键` 的落点见 `实现/并发句柄核心.py`（共享底座，
本模块只引用不复制）。
"""

from __future__ import annotations

import threading

from 公共契约.基础类型.结果类型 import 结果
from 支持库.后端.并发控制支持库.实现.并发句柄核心 import _创建, _句柄键, _取

# ═══════════════════════════════════════════════════════════════════
# 并发组（Coze errgroup 模式化：一组任务并发跑，等待全部结束，可设失败即停/收口双语义）
# ═══════════════════════════════════════════════════════════════════
_并发组表: dict[int, dict] = {}
_并发组锁 = threading.Lock()
_并发组序号 = 0


def 创建并发组(*, 名称: str = None, 并发上限: int = None, 失败模式: str = None) -> 结果:
    """创建并发组。失败模式=失败即停（一任务失败即中止等待）/ 收口不打断（全部跑完再汇总）。"""
    global _并发组序号
    try:
        组名 = str(名称 or "").strip()
        if not 组名:
            return 结果.失败("参数不合法", "名称不能为空", 来源="并发控制")
        上限 = 并发上限 if isinstance(并发上限, int) and 并发上限 > 0 else 8
        模式 = str(失败模式 or "收口不打断").strip()
        if 模式 not in ("失败即停", "收口不打断"):
            return 结果.失败("参数不合法", f"失败模式必须为 失败即停/收口不打断（当前 {模式}）", 来源="并发控制")
        with _并发组锁:
            _并发组序号 += 1
            组 = {
                "名称": 组名, "并发上限": 上限, "失败模式": 模式,
                "任务": {},  # 任务名 -> {状态: 排队/执行/结束, 成功, 结果, 错误}
                "顺序": [], "结束数": 0, "失败数": 0,
                "创建时间": __import__("time").time(),
            }
            结果对象 = _创建("并发组", 组, f"并发组已创建（{组名}，{模式}）")
            if 结果对象.成功:
                _并发组表[_句柄键(结果对象.值["句柄"])] = 组
            return 结果对象
    except Exception as 异常:
        return 结果.失败("创建并发组失败", str(异常), 来源="并发控制")


def 组内提交(*, 句柄: int = None, 任务名: str = None, 负载: dict = None) -> 结果:
    """向并发组提交一个任务（排队）。任务名重复返回 已存在。"""
    try:
        组对象, 原因 = _取(句柄, "并发组")
        if 组对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        任务 = str(任务名 or "").strip()
        if not 任务:
            return 结果.失败("参数不合法", "任务名不能为空", 来源="并发控制")
        with _并发组锁:
            if 任务 in 组对象["任务"]:
                return 结果.失败("任务已存在", f"任务 {任务} 已提交", 来源="并发控制")
            组对象["任务"][任务] = {"状态": "排队", "成功": None, "结果": None, "错误": None,
                                     "负载": 负载 or {}}
            组对象["顺序"].append(任务)
        return 结果.成功结果({"任务名": 任务, "状态": "排队", "组名": 组对象["名称"]})
    except Exception as 异常:
        return 结果.失败("组内提交失败", str(异常), 来源="并发控制")


def 组内领取(*, 句柄: int = None, 数量: int = None) -> 结果:
    """从并发组领取可执行任务（排队→执行，受限并发上限）。失败即停模式下组已失败则拒绝领取。"""
    try:
        组对象, 原因 = _取(句柄, "并发组")
        if 组对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        请求数 = 数量 if isinstance(数量, int) and 数量 > 0 else 组对象["并发上限"]
        with _并发组锁:
            if 组对象["失败模式"] == "失败即停" and 组对象["失败数"] > 0:
                return 结果.成功结果({"领取数": 0, "任务列表": [], "已停": True,
                                        "原因": "组已有失败，失败即停模式中止"})
            执行中 = sum(1 for t in 组对象["任务"].values() if t["状态"] == "执行")
            可领 = max(0, 组对象["并发上限"] - 执行中)
            领取数 = min(请求数, 可领)
            领取列表 = []
            for 任务 in 组对象["顺序"]:
                if len(领取列表) >= 领取数:
                    break
                if 组对象["任务"][任务]["状态"] == "排队":
                    组对象["任务"][任务]["状态"] = "执行"
                    领取列表.append(任务)
            if 领取数 == 0 and 执行中 == 0:
                return 结果.成功结果({"领取数": 0, "任务列表": [], "已停": True,
                                        "原因": "无排队任务"})
            return 结果.成功结果({"领取数": len(领取列表), "任务列表": 领取列表,
                                    "组名": 组对象["名称"]})
    except Exception as 异常:
        return 结果.失败("组内领取失败", str(异常), 来源="并发控制")


def 组内完成(*, 句柄: int = None, 任务名: str = None, 成功: bool = None,
             结果值: dict = None, 错误: str = None) -> 结果:
    """上报任务完成（执行→结束）。返回组累计统计。"""
    try:
        组对象, 原因 = _取(句柄, "并发组")
        if 组对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        任务 = str(任务名 or "").strip()
        if not 任务:
            return 结果.失败("参数不合法", "任务名不能为空", 来源="并发控制")
        with _并发组锁:
            if 任务 not in 组对象["任务"]:
                return 结果.失败("任务不存在", f"任务 {任务} 不在组内", 来源="并发控制")
            旧态 = 组对象["任务"][任务]["状态"]
            if 旧态 != "执行":
                return 结果.成功结果({"上报": False, "原因": f"当前状态={旧态}（仅执行中可上报）",
                                        "组名": 组对象["名称"]})
            组对象["任务"][任务]["状态"] = "结束"
            组对象["任务"][任务]["成功"] = bool(成功)
            组对象["任务"][任务]["结果"] = 结果值 or {}
            组对象["任务"][任务]["错误"] = 错误 or ""
            组对象["结束数"] += 1
            if not 成功:
                组对象["失败数"] += 1
        return 结果.成功结果({
            "任务名": 任务, "状态": "结束", "成功": bool(成功),
            "结束数": 组对象["结束数"], "失败数": 组对象["失败数"],
            "总数": len(组对象["顺序"]), "组名": 组对象["名称"],
        })
    except Exception as 异常:
        return 结果.失败("组内完成失败", str(异常), 来源="并发控制")


def 组内等待(*, 句柄: int = None, 超时秒: float = None) -> 结果:
    """等待并发组全部结束（轮询语义，非阻塞返回当前快照；超时返回仍在执行）。"""
    try:
        组对象, 原因 = _取(句柄, "并发组")
        if 组对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        时间 = __import__("time")
        等待秒 = 超时秒 if isinstance(超时秒, (int, float)) and 超时秒 > 0 else 10
        启动 = 时间.time()
        with _并发组锁:
            执行中 = sum(1 for t in 组对象["任务"].values() if t["状态"] == "执行")
            排队中 = sum(1 for t in 组对象["任务"].values() if t["状态"] == "排队")
        while (执行中 > 0 or 排队中 > 0) and 时间.time() - 启动 < 等待秒:
            时间.sleep(0.2)
            with _并发组锁:
                执行中 = sum(1 for t in 组对象["任务"].values() if t["状态"] == "执行")
                排队中 = sum(1 for t in 组对象["任务"].values() if t["状态"] == "排队")
        with _并发组锁:
            return 结果.成功结果({
                "已结束": 组对象["结束数"], "总数": len(组对象["顺序"]),
                "失败数": 组对象["失败数"], "执行中": 执行中, "排队中": 排队中,
                "全部结束": 组对象["结束数"] == len(组对象["顺序"]) and len(组对象["顺序"]) > 0,
                "失败模式": 组对象["失败模式"], "组名": 组对象["名称"],
            })
    except Exception as 异常:
        return 结果.失败("组内等待失败", str(异常), 来源="并发控制")


def 查询并发组(*, 句柄: int = None) -> 结果:
    """查询并发组状态。句柄空=列全部。"""
    try:
        if 句柄 is None:
            with _并发组锁:
                return 结果.成功结果({"并发组列表": [
                    {"句柄": k, "名称": v["名称"], "任务数": len(v["顺序"]),
                     "结束数": v["结束数"], "失败数": v["失败数"], "失败模式": v["失败模式"]}
                    for k, v in _并发组表.items()
                ]})
        组对象, 原因 = _取(句柄, "并发组")
        if 组对象 is None:
            return 结果.失败("句柄失效", 原因, 来源="并发控制")
        with _并发组锁:
            return 结果.成功结果({
                "名称": 组对象["名称"], "并发上限": 组对象["并发上限"],
                "失败模式": 组对象["失败模式"], "总数": len(组对象["顺序"]),
                "结束数": 组对象["结束数"], "失败数": 组对象["失败数"],
                "任务": [{"任务名": t, "状态": 组对象["任务"][t]["状态"],
                           "成功": 组对象["任务"][t]["成功"]} for t in 组对象["顺序"]],
            })
    except Exception as 异常:
        return 结果.失败("查询失败", str(异常), 来源="并发控制")


# ═══════════════════════════════════════════════════════════════════
# 结构化任务结果（异步任务结果收口语义：严格/收口双模式，异常不外抛）
# 收口模式：成功值/取消/异常说明一律收敛为结构化终态；
# 严格模式：只校验并结构化，参数明显非法返回统一失败（参数不合法）。
# ═══════════════════════════════════════════════════════════════════
def 结构化任务结果(*, 结果模式: str = None, 任务标识: str = None,
                    结果值=None, 异常说明: str = None) -> 结果:
    """异步任务结果收口：把成功值/取消/异常统一收敛为结构化终态。

    参数:
        结果模式: "1"=严格（参数明显非法返回 参数不合法）/ "2"=收口（一律返回结构化终态）
        任务标识: 可选任务标识，仅用于错误说明定位，不改变终态判定
        结果值: 任务产出的值（JSON 值；空值视为未产出）
        异常说明: 异常说明文本（非空即终态=异常、成功=假）
    返回 {成功: 逻辑型, 终态: 成功/取消/异常, 值: JSON值型, 错误说明: 文本型}。
    收口模式下既无结果值也无异常说明时按取消收口（终态=取消、成功=假）。
    """
    try:
        模式 = str(结果模式).strip() if 结果模式 is not None else ""
        if 模式 not in ("1", "2"):
            return 结果.失败("参数不合法",
                           f"结果模式必须为 1(严格)/2(收口)（当前 {模式 or '空'}）",
                           来源="并发控制")
        说明 = str(异常说明).strip() if 异常说明 is not None else ""
        标识 = str(任务标识).strip() if 任务标识 is not None else ""
        前缀 = f"任务 {标识}: " if 标识 else ""
        if 说明:
            # 异常说明非空即终态=异常、成功=假（严格/收口语义一致）
            return 结果.成功结果({"成功": False, "终态": "异常",
                                  "值": 结果值, "错误说明": f"{前缀}{说明}"})
        if 结果值 is not None:
            return 结果.成功结果({"成功": True, "终态": "成功",
                                  "值": 结果值, "错误说明": ""})
        if 模式 == "2":
            # 收口模式：既无结果值也无异常说明 → 取消收口，不向调用方抛异常
            return 结果.成功结果({"成功": False, "终态": "取消", "值": None,
                                  "错误说明": f"{前缀}未产出结果且无异常说明，按取消收口"})
        return 结果.失败("参数不合法", f"{前缀}严格模式要求提供结果值或异常说明",
                        来源="并发控制")
    except Exception as 异常:
        return 结果.失败("收口失败", f"结果结构化收口失败: {异常}", 来源="并发控制")

