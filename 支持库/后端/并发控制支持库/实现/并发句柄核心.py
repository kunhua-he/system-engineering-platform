"""并发控制句柄核心：句柄账本与资源表的唯一落点（内部实现，不对外）。

本模块由 `实现/并发控制.py` 按职责簇**原样搬出**（对外符号零变化：`并发控制.py`
逐名再导出，全仓调用方与 `__init__.py` 的 `from ….实现.并发控制 import X` 照旧成立）。

为什么必须下沉成独立模块：事件总线 / 流管道 / 并发组三个簇与主模块**同时依赖**
`_句柄键` / `_创建` / `_取` 这三个助手 —— 留在主模块就会构成循环导入
（三簇 → 主模块 → 三簇）。故按「被双方依赖的符号下沉」把共享底座搬到这里。

判据唯一事实源：句柄生命周期由 `公共契约.句柄体系` 持有，本模块不复制其算法，
只持有实例（`句柄系统`）与资源表（`资源表`）与全局锁（`锁`）。
"""

from __future__ import annotations

import threading

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.句柄体系 import 句柄体系, 句柄类型_资源

句柄系统 = 句柄体系()
资源表: dict[int, dict] = {}
锁 = threading.Lock()


def _句柄键(句柄: int | int) -> int:
    """资源表与公开网关统一使用整数句柄。"""
    return int(句柄)


def _创建(类型: str, 对象: object, 说明: str) -> 结果:
    with 锁:
        句柄 = 句柄系统.创建句柄(句柄类型=句柄类型_资源, 资源id=f"并发-{类型}", 所有者="")
        句柄键 = _句柄键(句柄.句柄id)
        资源表[句柄键] = {"类型": 类型, "对象": 对象, "状态": "有效"}
    return 结果.成功结果({"句柄": 句柄键, "类型": 类型, "说明": 说明})


def _取(句柄: int, 类型: str) -> tuple[object | None, str]:
    键 = _句柄键(句柄)
    try:
        状态机id = int(键)
    except ValueError:
        return None, f"句柄格式不合法: {句柄}"
    有效, 原因 = 句柄系统.校验(句柄id=状态机id)
    if not 有效:
        return None, 原因
    资源 = 资源表.get(键)
    if 资源 is None or 资源["类型"] != 类型:
        return None, f"{类型}句柄不存在"
    if 资源.get("状态", "有效") != "有效":
        return None, f"{类型}句柄正在释放或释放失败"
    return 资源["对象"], ""
