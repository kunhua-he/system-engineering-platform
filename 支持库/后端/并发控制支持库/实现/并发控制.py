# ═══════════════════════════════════════════════════════════════════
# 结构化任务结果（异步任务结果收口语义：严格/收口双模式，异常不外抛）
# 收口模式：成功值/取消/异常说明一律收敛为结构化终态；
# 严格模式：只校验并结构化，参数明显非法返回统一失败（参数不合法）。
# ═══════════════════════════════════════════════════════════════════
def 结构化任务结果(*, 结果模式: str = None, 任务标识: str = None,
                    结果值=None, 异常说明: str = None) -> 结果:
    """异步任务结果收口：把成功值/取消/异常统一收敛为结构化终态。

    参数:
        结果模式: "1"=严格（参数明显非法返回 参数不合法）/ "2"=收口（一律返回结构化终态）
        任务标识: 可选任务标识，仅用于错误说明定位，不改变终态判定
        结果值: 任务产出的值（JSON 值；空值视为未产出）
        异常说明: 异常说明文本（非空即终态=异常、成功=假）
    返回 {成功: 逻辑型, 终态: 成功/取消/异常, 值: JSON值型, 错误说明: 文本型}。
    收口模式下既无结果值也无异常说明时按取消收口（终态=取消、成功=假）。
    """
    try:
        模式 = str(结果模式).strip() if 结果模式 is not None else ""
        if 模式 not in ("1", "2"):
            return 结果.失败("参数不合法",
                           f"结果模式必须为 1(严格)/2(收口)（当前 {模式 or '空'}）",
                           来源="并发控制")
        说明 = str(异常说明).strip() if 异常说明 is not None else ""
        标识 = str(任务标识).strip() if 任务标识 is not None else ""
        前缀 = f"任务 {标识}: " if 标识 else ""
        if 说明:
            # 异常说明非空即终态=异常、成功=假（严格/收口语义一致）
            return 结果.成功结果({"成功": False, "终态": "异常",
                                  "值": 结果值, "错误说明": f"{前缀}{说明}"})
        if 结果值 is not None:
            return 结果.成功结果({"成功": True, "终态": "成功",
                                  "值": 结果值, "错误说明": ""})
        if 模式 == "2":
            # 收口模式：既无结果值也无异常说明 → 取消收口，不向调用方抛异常
            return 结果.成功结果({"成功": False, "终态": "取消", "值": None,
                                  "错误说明": f"{前缀}未产出结果且无异常说明，按取消收口"})
        return 结果.失败("参数不合法", f"{前缀}严格模式要求提供结果值或异常说明",
                        来源="并发控制")
    except Exception as 异常:
        return 结果.失败("收口失败", f"结果结构化收口失败: {异常}", 来源="并发控制")

