        if not 名:
            return 结果.失败("参数不合法", "lane 名称不能为空", 来源="并发控制")
        完成 = max(1, int(数量 or 1))
        失败 = max(0, int(失败数 or 0))
        import time as _时间
        with _lane锁:
            if 名 not in _lane表:
                return 结果.失败("lane不存在", f"lane {名} 未创建", 来源="并发控制")
