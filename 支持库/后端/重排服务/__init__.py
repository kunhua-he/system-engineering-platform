def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数表 in [
        ("重排服务.重排", 重排, [{"名称": "查询", "类型": "文本型", "必填": True, "默认值": None, "说明": "查询文本"}, {"名称": "文档列表", "类型": "列表型", "必填": True, "默认值": None, "说明": "候选文档（字符串或含 文本/内容 字段的字典）"}, {"名称": "模型配置", "类型": "字典型", "必填": False, "默认值": None, "说明": "预留：{模型名, 提供者}，当前忽略"}, {"名称": "顶部数量", "类型": "整数型", "必填": False, "默认值": None, "说明": "限制返回条数（默认全部）"}]),
        ("重排服务.检查可用性", 检查可用性, [{"名称": "模型配置", "类型": "字典型", "必填": False, "默认值": None, "说明": "预留模型配置"}]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.重排服务",
                实现函数=函数,
                参数=参数表,
                返回="结果",
                说明="返回当前实现可用性（默认标准库始终可用，模型配置仅作声明）。",
            )
        )
