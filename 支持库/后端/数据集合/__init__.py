def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型 in [
        ("数据集合.列表添加", 列表添加, ['列表', '条目'], "结果"),
        ("数据集合.列表移除", 列表移除, ['列表', '条目'], "结果"),
        ("数据集合.列表排序", 列表排序, ['列表', '倒序'], "结果"),
        ("数据集合.列表查找", 列表查找, ['列表', '目标'], "结果"),
        ("数据集合.字典设置", 字典设置, ['字典', '键', '值'], "结果"),
        ("数据集合.字典获取", 字典获取, ['字典', '键', '默认值'], "结果"),
        ("数据集合.集合取并集", 集合取并集, ['集合甲', '集合乙'], "结果"),
        ("数据集合.集合取交集", 集合取交集, ['集合甲', '集合乙'], "结果"),
        ("数据集合.统计数量", 统计数量, ['列表'], "结果"),
        ("数据集合.按字段查找", 按字段查找, ['列表', '字段名', '匹配值', '直接匹配'], "结果"),
        ("数据集合.过滤", 过滤, ['列表', '字段名', '等于值', '直接匹配'], "结果"),
        ("数据集合.映射转换", 映射转换, ['列表', '字段映射'], "结果"),
        ("数据集合.按字段排序", 按字段排序, ['列表', '字段名', '升序', '直接匹配'], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.数据集合",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回=返回类型,
                说明="原子能力",
            )
        )
