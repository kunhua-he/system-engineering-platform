def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 Git操作）。"""
    from 公共契约.能力契约.契约 import 能力实现
    from 公共契约.基础类型.结果类型 import 结果

    def 校验分支名能力(分支名: str | None = None):
        """能力边界：缺参明确失败；其余直接透传实现结果（值 = {是否安全, 原因}）。

        历史缺陷（2026-09-15）：原先把 实现.校验分支名 直接注册成公开能力，它**缺参时返回
        「成功 + 是否安全=False」**，让「缺必填参数必须明确失败」这条门禁失效。缺口只补在缺参分支：
        - 缺参/非文本 → 结果.失败("参数不合法")；
        - 其余**透传实现结果**（实现本来就返回合规的统一结果：安全 → 是否安全 True，不安全 → False）。
        ⚠️ 不要再把实现结果重新包一层——实测那样会把「安全=True」翻成「False」（回归）。
        """
        if not isinstance(分支名, str) or not 分支名.strip():
            return 结果.失败("参数不合法", "分支名必须为非空文本", 来源="Git操作")
        return 校验分支名(分支名)

    for 能力id, 函数, 说明 in [
        ("版本控制支持库.Git操作.检查提供者", 检查提供者, "git --version 真实探针：返回 {git: 可用, 版本}；缺失/超时 → 提供者不可用"),
        ("版本控制支持库.Git操作.创建工作区", 创建工作区, "git worktree add 新建独立工作区"),
        ("版本控制支持库.Git操作.查询工作区", 查询工作区, "git worktree list 返回全部工作区清单"),
        ("版本控制支持库.Git操作.关闭工作区", 关闭工作区, "git worktree remove 非强制关闭（未提交修改拒绝）"),
        ("版本控制支持库.Git操作.提交", 提交, "git add 指定路径 + commit 最小原子提交"),
        ("版本控制支持库.Git操作.回滚", 回滚, "git revert 撤销指定提交（冲突自动中止）"),
        ("版本控制支持库.Git操作.挑拣合入", 挑拣合入, "git cherry-pick 挑拣提交（冲突自动中止）"),
        ("版本控制支持库.Git操作.当前状态", 当前状态, "status/log 摘要：分支、未提交修改、最近提交"),
        ("版本控制支持库.Git操作.获取当前提交哈希", 获取当前提交哈希, "git rev-parse HEAD 与分支：返回当前提交哈希与分支（detached 为 HEAD）"),
        ("版本控制支持库.Git操作.校验分支名", 校验分支名能力, "校验分支名是否安全（git check-ref-format 常用子集）：返回 {是否安全, 原因}"),
        ("版本控制支持库.Git操作.建议分支名", 建议分支名, "按前缀与时间戳生成建议分支名（前缀非法时回退默认）"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.版本控制支持库.Git操作",
                实现函数=函数,
                参数=_能力参数表[能力id],
                返回="结果型",
                说明=说明,
            )
        )
