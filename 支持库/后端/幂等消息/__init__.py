def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数表 in [
        ("幂等消息.生成id", 生成id, [{"名称": "会话id", "类型": "文本型", "必填": True, "默认值": None, "说明": "会话标识"}, {"名称": "内容", "类型": "文本型", "必填": True, "默认值": None, "说明": "消息内容"}, {"名称": "前缀", "类型": "文本型", "必填": False, "默认值": None, "说明": "可选前缀（字母数字下划线，截断16位）"}]),
        ("幂等消息.校验id", 校验id, [{"名称": "幂等id", "类型": "文本型", "必填": True, "默认值": None, "说明": "要校验的幂等id"}]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.幂等消息",
                实现函数=函数,
                参数=参数表,
                返回="结果",
                说明="校验幂等 id 格式（24位十六进制 或 前缀-24位）。",
            )
        )
