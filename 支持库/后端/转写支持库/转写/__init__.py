"""跨平台语音转写提供者包级中文入口（转写库隔离子进程边界；**一份实现 + 按平台选后端**）。

后端由 `公共契约/运行时/平台适配.转写后端()` 唯一判定：Apple Silicon → mlx_whisper；
Windows / Linux → faster_whisper。后端差异在 `实现/子进程解析.py` 内部吸收，
本入口与调用方的能力/参数/返回结构逐字不变。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 转写）：
- 检查可用性 → {可用, 模型名, 模型版本}（未配置模型如实返回 未配置模型）
- 转写音频文件 → {文本, 语言, 模型名}（受管子进程：超时/取消/进程组回收/输出上限）
  返回分段=真 时额外带 分段 指标：[{序号, 开始秒, 结束秒, 文本, 平均对数概率, 压缩比, 无语音概率}]
- 获取模型版本 → {模型名, 模型版本}
主进程绝不 import 任何转写库；模型路径/模型名来自配置（环境变量或配置对象）。
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.后端.转写支持库.转写.实现.提供者 import 检查转写可用性
from 支持库.后端.转写支持库.转写.实现.提供者 import 获取模型版本
from 支持库.后端.转写支持库.转写.实现.提供者 import 转写音频文件

__all__ = ["检查转写可用性", "获取模型版本", "转写音频文件", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 转写）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("转写支持库.转写.检查可用性", 检查转写可用性,
         [{"名称": "超时秒", "类型": "双精度数型", "必填": 假, "默认值": 300},
          {"名称": "配置", "类型": "字典型", "必填": 假, "默认值": None}],
         "检查语音转写可用性（按平台选后端；模型是否配置）"),
        ("转写支持库.转写.转写音频文件", 转写音频文件,
         [{"名称": "文件路径", "类型": "文本型", "必填": 真, "默认值": None},
          {"名称": "超时秒", "类型": "双精度数型", "必填": 假, "默认值": 300},
          {"名称": "配置", "类型": "字典型", "必填": 假, "默认值": None},
          {"名称": "附加术语", "类型": "文本型", "必填": 假, "默认值": ""},
          {"名称": "返回分段", "类型": "逻辑型", "必填": 假, "默认值": 假}],
         "转写音频文件为文本（受管子进程；返回分段=真时附置信度指标）"),
        ("转写支持库.转写.获取模型版本", 获取模型版本,
         [{"名称": "超时秒", "类型": "双精度数型", "必填": 假, "默认值": 300},
          {"名称": "配置", "类型": "字典型", "必填": 假, "默认值": None}],
         "获取语音转写模型与库版本（按平台对应的后端库）"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.转写支持库.转写",
                实现函数=函数,
                参数=参数名,
                返回="结果型",
                说明=说明,
            )
        )
