"""额度控制原子能力实现（不对外暴露，只经包级中文入口调用）。

额度原则（华哥口径）：默认不限制；调用时可配置额度。
- 未配置的额度项 → 不限制（检查永远通过）。
- 配置额度值 0 → 表示不限制。
- 检查额度：已用值 > 额度值（且额度值 > 0）→ 超限。
"""

from __future__ import annotations

import threading

from 公共契约.基础类型.结果类型 import 结果

额度表: dict[str, dict[str, int]] = {}   # 额度键 → {额度项: 额度值}
锁 = threading.Lock()


def 配置额度(额度键: str = None, 额度项: str = None, 额度值: int = None) -> 结果:
    """按 额度键+额度项 配置额度值（0=不限制）。返回 {额度键, 额度项, 额度值}。"""
    if not isinstance(额度键, str) or not 额度键.strip():
        return 结果.失败("参数不合法", "额度键必须是非空字符串", 来源="额度控制")
    if not isinstance(额度项, str) or not 额度项.strip():
        return 结果.失败("参数不合法", "额度项必须是非空字符串", 来源="额度控制")
    if not isinstance(额度值, int) or 额度值 < 0:
        return 结果.失败("参数不合法", f"额度值必须是非负整数（0=不限制）: {额度值}", 来源="额度控制")
    with 锁:
        额度表.setdefault(额度键, {})[额度项] = 额度值
    return 结果.成功结果({"额度键": 额度键, "额度项": 额度项, "额度值": 额度值})


def 查询额度(额度键: str = None) -> 结果:
    """查询额度键下全部额度配置。返回 {额度键, 额度配置}。"""
    if not isinstance(额度键, str) or not 额度键.strip():
        return 结果.失败("参数不合法", "额度键必须是非空字符串", 来源="额度控制")
    with 锁:
        配置 = dict(额度表.get(额度键, {}))
    return 结果.成功结果({"额度键": 额度键, "额度配置": 配置, "说明": "未配置项=不限制"})


def 检查额度(额度键: str = None, 额度项: str = None, 已用值: int = None) -> 结果:
    """复核额度：检查是否超限。超限不是拒绝，是触发复核（压缩/降级）的信号。

    返回 {通过, 是否超限, 超出量, 建议动作, 原因}：
    - 未配置或额度值 0 → 通过，建议动作=继续（不限制）。
    - 额度内 → 通过，建议动作=继续。
    - 超限 → 通过=False，建议动作=压缩复核（调用方应压缩历史后重试，而非丢弃请求）。
    """
    if not isinstance(额度键, str) or not 额度键.strip():
        return 结果.失败("参数不合法", "额度键必须是非空字符串", 来源="额度控制")
    if not isinstance(额度项, str) or not 额度项.strip():
        return 结果.失败("参数不合法", "额度项必须是非空字符串", 来源="额度控制")
    if not isinstance(已用值, int) or 已用值 < 0:
        return 结果.失败("参数不合法", "已用值必须是非负整数", 来源="额度控制")
    with 锁:
        额度值 = 额度表.get(额度键, {}).get(额度项, 0)
    if 额度值 <= 0:
        return 结果.成功结果({"通过": True, "是否超限": False, "超出量": 0,
                                "建议动作": "继续", "原因": "未配置额度（不限制）", "额度值": 0, "已用值": 已用值})
    超出量 = 已用值 - 额度值
    if 超出量 <= 0:
        return 结果.成功结果({"通过": True, "是否超限": False, "超出量": 0,
                                "建议动作": "继续", "原因": "额度内", "额度值": 额度值, "已用值": 已用值})
    return 结果.成功结果({
        "通过": False, "是否超限": True, "超出量": 超出量,
        "建议动作": "压缩复核", "原因": f"超限：已用 {已用值} / 额度 {额度值}，应压缩历史后复核，而非拒绝",
        "额度值": 额度值, "已用值": 已用值,
    })
