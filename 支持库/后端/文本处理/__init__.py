def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 返回类型 in [
        ("文本处理.分割文本", 分割文本, ['文本', '分隔符'], "结果"),
        ("文本处理.合并文本", 合并文本, ['片段列表', '分隔符'], "结果"),
        ("文本处理.替换文本", 替换文本, ['文本', '旧文本', '新文本'], "结果"),
        ("文本处理.查找文本", 查找文本, ['文本', '目标'], "结果"),
        ("文本处理.去空白", 去空白, ['文本'], "结果"),
        ("文本处理.转大写", 转大写, ['文本'], "结果"),
        ("文本处理.转小写", 转小写, ['文本'], "结果"),
        ("文本处理.统计长度", 统计长度, ['文本'], "结果"),
        ("文本处理.按行分割", 按行分割, ['文本'], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文本处理",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回=返回类型,
                说明="原子能力",
            )
        )
