"""PDF文档原子能力实现：经 PDF 隔离提供者 在独立子进程中解析。

架构（PyMuPDF SWIG 崩溃隔离）：
- 本模块（主进程）绝不 import pdfplumber/fitz；
- 实际解析/加密检测/图像渲染/版本探测全部由 支持库.适配层.PDF隔离提供者
  在隔离子进程内完成，崩溃只返回 提供者崩溃，不影响主进程/测试器/后端。
安全覆盖（统一返回稳定错误码）：
- 损坏→文件损坏；加密→文件加密；超页数/超大小→超出限制；
- 提供者缺失/崩溃→提供者不可用/提供者崩溃；超时→超时（可重试）。
"""

from __future__ import annotations

import time
from pathlib import Path
from typing import Any

from 公共契约.基础类型.文档结构 import (
    文档块, 文档资源, 来源位置, 通用文档,
)
from 公共契约.基础类型.结果类型 import 结果
from 支持库.适配层.PDF隔离提供者 import 解析PDF隔离 as _解析PDF隔离

默认最大页数 = 500
默认最大字节数 = 200 * 1024 * 1024
默认超时秒 = 60.0


def _失败(错误码: str, 消息: str, *, 可重试: bool = False, 详情: dict[str, Any] | None = None) -> 结果:
    return 结果.失败(错误码, 消息, 来源="PDF文档", 可重试=可重试, 详情=详情 or {})


def _转通用文档(字典: dict[str, Any]) -> 通用文档:
    """把隔离子进程返回的通用文档字典重建为 dataclass。"""
    块列表 = [
        文档块(
            类型=块.get("类型", "段落"),
            文本=块.get("文本", ""),
            来源位置=来源位置(**{k: v for k, v in (块.get("来源位置") or {}).items() if v is not None}),
            资源引用=块.get("资源引用"),
            表格数据=块.get("表格数据"),
            附加=块.get("附加", {}),
        )
        for 块 in 字典.get("块列表", [])
    ]
    资源列表 = [
        文档资源(
            类型=资源.get("类型", "图像"),
            媒体类型=资源.get("媒体类型", ""),
            文件名=资源.get("文件名", ""),
            描述=资源.get("描述", ""),
            字节数据b64=资源.get("字节数据b64", ""),
            附加={k: v for k, v in 资源.items() if k not in ("类型", "媒体类型", "文件名", "描述", "字节数据b64")},
        )
        for 资源 in 字典.get("资源列表", [])
    ]
    return 通用文档(
        文档类型=字典.get("文档类型", "PDF"),
        格式=字典.get("格式", "pdf"),
        标题=字典.get("标题", ""),
        块列表=块列表,
        资源列表=资源列表,
        保真级别=字典.get("保真级别", "高"),
        解析方式=字典.get("解析方式", "隔离提供者"),
        警告=字典.get("警告", []),
        诊断=字典.get("诊断", []),
        耗时秒=字典.get("耗时秒", 0.0),
        提供者版本=字典.get("提供者版本", {}),
        原始文件摘要=字典.get("原始文件摘要", ""),
        附加=字典.get("附加", {}),
    )


def 解析PDF(
    文件路径: str,
    最大页数: int = 默认最大页数,
    最大字节数: int = 默认最大字节数,
    超时秒: float = 默认超时秒,
) -> 结果:
    """解析 PDF 为平台通用文档（结果[通用文档]）。

    全部第三方逻辑在隔离子进程执行；本函数只做参数校验与结果转换。
    """
    开始时刻 = time.monotonic()
    if not isinstance(文件路径, str) or not 文件路径.strip():
        return _失败("参数不合法", "文件路径必须为非空文本")
    路径 = Path(文件路径)
    if not 路径.is_file():
        return _失败("文件不存在", f"文件不存在: {文件路径}")
    大小 = 路径.stat().st_size
    if 最大字节数 > 0 and 大小 > 最大字节数:
        return _失败("超出限制", f"文件 {大小} 字节超过上限 {最大字节数} 字节")

    结果 = _解析PDF隔离(str(路径), 最大页数=最大页数, 最大字节数=最大字节数, 超时秒=超时秒)
    if not 结果.成功:
        return 结果
    字典 = 结果.值
    if not isinstance(字典, dict) or "错误码" in 字典:
        错误码 = str(字典.get("错误码") or "文件损坏") if isinstance(字典, dict) else "文件损坏"
        消息 = str(字典.get("错误说明") or "PDF 解析失败") if isinstance(字典, dict) else "PDF 解析失败"
        return _失败(错误码, 消息, 可重试=错误码 in ("提供者不可用", "提供者崩溃", "超时"), 详情={"耗时秒": round(time.monotonic() - 开始时刻, 3)})
    文档 = _转通用文档(字典)
    return 结果.成功结果(文档)
