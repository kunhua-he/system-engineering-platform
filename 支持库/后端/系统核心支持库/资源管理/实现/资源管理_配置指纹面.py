"""资源管理·配置指纹面：配置快照指纹的登记/对比/查询（**资源管理包 的能力簇**）。

2026-09-19 从同目录 `资源管理.py` 原样搬出（对外零变化）：本模块只承载「配置变更
指纹」这一簇，成员名一个不改；全部符号仍由 `资源管理.py` 回托（re-export）成模块级
属性，故包级入口、能力注册表与全部调用方都无感。

职责边界（**不要在这里加第二套实现**）：指纹账本 `_配置指纹账本`、锁 `_配置指纹锁`
与稳定序列化口径 `_配置指纹` 随本簇一并搬来，全仓只此一处实现。原文与注释一字未改。
"""

from __future__ import annotations

import hashlib
import json
import threading

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.错误结构 import 错误码_参数不合法
from 公共契约.基础类型.逻辑类型 import 真
from 公共契约.基础类型.逻辑类型 import 假


# ═══════════════════════════════════════════════
# 配置变更指纹：OpenClaw config-journal-snapshot 模式化落地
# 改前快照指纹 + 改后对比；记录 谁/何时/改了什么/前后指纹（0加密，脱敏业务端自理）。
# ═══════════════════════════════════════════════
_配置指纹账本: dict[str, dict] = {}
_配置指纹锁 = threading.Lock()


def _配置指纹(配置: dict) -> str:
    """配置快照指纹：稳定序列化 + sha256。"""
    try:
        规范化 = json.dumps(配置, ensure_ascii=False, sort_keys=True, default=str)
        return hashlib.sha256(规范化.encode("utf-8")).hexdigest()[:16]
    except Exception:
        return "无法指纹"


def 登记配置快照(*, 配置名: str = None, 配置: dict = None, 操作人: str = None) -> 结果:
    """登记配置当前快照指纹（改前调用：记录基线）。"""
    try:
        名 = str(配置名 or "").strip()
        if not 名:
            return 结果.失败(错误码_参数不合法, "配置名不能为空", 来源="资源管理")
        if not isinstance(配置, dict):
            return 结果.失败(错误码_参数不合法, "配置必须是字典", 来源="资源管理")
        import time as _时间
        指纹 = _配置指纹(配置)
        with _配置指纹锁:
            _配置指纹账本[名] = {
                "指纹": 指纹,
                "改前指纹": None,
                "操作人": str(操作人 or ""),
                "时间": _时间.strftime("%Y-%m-%d %H:%M:%S", _时间.localtime()),
                "变更记录": [],
            }
            return 结果.成功结果({"配置名": 名, "指纹": 指纹, "基线": 真})
    except Exception as 异常:
        return 结果.失败("登记失败", str(异常), 来源="资源管理")


def 对比配置指纹(*, 配置名: str = None, 新配置: dict = None, 操作人: str = None) -> 结果:
    """对比新配置与基线指纹。变则记 journal（改前指纹/新指纹/操作人），不变返回一致。"""
    try:
        名 = str(配置名 or "").strip()
        if not 名:
            return 结果.失败(错误码_参数不合法, "配置名不能为空", 来源="资源管理")
        if not isinstance(新配置, dict):
            return 结果.失败(错误码_参数不合法, "新配置必须是字典", 来源="资源管理")
        import time as _时间
        新指纹 = _配置指纹(新配置)
        with _配置指纹锁:
            if 名 not in _配置指纹账本:
                # 无基线：直接登记为新基线（幂等首登）
                _配置指纹账本[名] = {
                    "指纹": 新指纹, "改前指纹": None,
                    "操作人": str(操作人 or ""),
                    "时间": _时间.strftime("%Y-%m-%d %H:%M:%S", _时间.localtime()),
                    "变更记录": [],
                }
                return 结果.成功结果({"配置名": 名, "变更": 假, "首登基线": 真, "指纹": 新指纹})
            条目 = _配置指纹账本[名]
            if 条目["指纹"] == 新指纹:
                return 结果.成功结果({"配置名": 名, "变更": 假, "指纹": 新指纹})
            # 有变更：记 journal
            条目["变更记录"].append({
                "改前指纹": 条目["指纹"],
                "新指纹": 新指纹,
                "操作人": str(操作人 or "未知"),
                "时间": _时间.strftime("%Y-%m-%d %H:%M:%S", _时间.localtime()),
            })
            条目["改前指纹"] = 条目["指纹"]
            条目["指纹"] = 新指纹
            条目["操作人"] = str(操作人 or "")
            条目["时间"] = _时间.strftime("%Y-%m-%d %H:%M:%S", _时间.localtime())
            return 结果.成功结果({
                "配置名": 名, "变更": 真,
                "改前指纹": 条目["改前指纹"], "新指纹": 新指纹,
                "操作人": str(操作人 or "未知"),
                "变更序号": len(条目["变更记录"]),
            })
    except Exception as 异常:
        return 结果.失败("对比失败", str(异常), 来源="资源管理")


def 查配置指纹(*, 配置名: str = None) -> 结果:
    """查询配置指纹与变更记录。"""
    try:
        名 = str(配置名 or "").strip()
        if not 名:
            return 结果.失败(错误码_参数不合法, "配置名不能为空", 来源="资源管理")
        with _配置指纹锁:
            if 名 not in _配置指纹账本:
                return 结果.失败("配置不存在", f"配置指纹 {名} 未登记", 来源="资源管理")
            条目 = _配置指纹账本[名]
            return 结果.成功结果({
                "配置名": 名, "当前指纹": 条目["指纹"],
                "改前指纹": 条目["改前指纹"],
                "当前操作人": 条目["操作人"], "当前时间": 条目["时间"],
                "变更次数": len(条目["变更记录"]),
                "变更记录": list(reversed(条目["变更记录"])),
            })
    except Exception as 异常:
        return 结果.失败("查询失败", str(异常), 来源="资源管理")
