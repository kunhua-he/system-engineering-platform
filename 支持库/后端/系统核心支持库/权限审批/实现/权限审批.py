"""权限审批原子能力实现（不对外暴露，只经包级中文入口调用）。

职责：操作审批门禁（借鉴 Claude Code PermissionGate + OpenHands 人工确认流，保持原子）。
规则表判定 → 动作是否放行；可登记白名单规则（按 动作类型+目标 精确匹配）。
只做判定，不执行业务；审批结果由调用方执行。
"""

from __future__ import annotations

from typing import Any

from 公共契约.基础类型.结果类型 import 结果

# 规则表：动作类型 → 策略（允许/拒绝/询问）
规则表: dict[str, str] = {
    "读取": "允许",
    "写入": "允许",
    "执行命令": "询问",
    "删除": "询问",
    "网络请求": "允许",
    "模型调用": "允许",
    # 全量验收（发布门禁 --测试真跑 / 跨平台部署验证 / 全量 unittest）：
    # 哲学 11.2（2026-09-19 华哥裁决）「默认无授权禁止跑全量，强制需要弹窗授权才可启动」
    # ⇒ 默认「询问」＝入口直接拒绝，必须先由华哥授权后经 登记规则 置为「允许」
    "全量验收": "询问",
}


def 校验动作(动作类型: str = None, 目标: str = None) -> 结果:
    """校验动作是否放行。策略 ∈ 允许/拒绝/询问。返回 {通过, 策略, 原因}。"""
    if not isinstance(动作类型, str) or not 动作类型.strip():
        return 结果.失败("参数不合法", "动作类型必须是非空字符串", 来源="权限审批")
    策略 = 规则表.get(动作类型)
    if 策略 is None:
        return 结果.失败("未知动作", f"动作类型 {动作类型} 未登记规则", 来源="权限审批")
    通过 = 策略 == "允许"
    return 结果.成功结果({
        "通过": 通过,
        "策略": 策略,
        "原因": "允许" if 通过 else ("需要人工确认" if 策略 == "询问" else "拒绝"),
        "动作类型": 动作类型, "目标": 目标 or "",
    })


def 登记规则(动作类型: str = None, 策略: str = None) -> 结果:
    """登记/更新动作规则。策略 ∈ 允许/拒绝/询问。"""
    if not isinstance(动作类型, str) or not 动作类型.strip():
        return 结果.失败("参数不合法", "动作类型必须是非空字符串", 来源="权限审批")
    if 策略 not in ("允许", "拒绝", "询问"):
        return 结果.失败("参数不合法", f"策略必须是 允许/拒绝/询问: {策略}", 来源="权限审批")
    规则表[动作类型] = 策略
    return 结果.成功结果({"动作类型": 动作类型, "策略": 策略, "已登记": True})


def 查询规则表() -> 结果:
    """返回当前全部动作规则。"""
    return 结果.成功结果({"规则表": dict(规则表)})
