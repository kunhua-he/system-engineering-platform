"""限流与请求上下文原子能力实现（不对外暴露，只经包级中文入口调用）。

迁移自 V3（薄壳化 1-8）：
- `后端服务/应用层/中间件/限流中间件.py`（134 行，令牌桶 + 来源桶映射 + 闲置回收）
- `后端服务/应用层/中间件/请求ID标注.py`（请求编号生成）
- `后端服务/应用层/服务/基础设施/认证服务.py`（登录失败限速判定）

设计取舍：底座能力保持**无状态、一进一出**，只做判定与计算；
「按来源维护桶映射」「失败计数存储」等状态由调用方（V3）持有 ——
这样同一能力对任何调用方语义一致，且不引入进程级全局副作用。
"""

from __future__ import annotations

import uuid

from 公共契约.基础类型.结果类型 import 结果

来源标识 = "限流"


def 令牌桶判定(
    桶容量: int = None,
    每秒补充: float = None,
    当前令牌数: float = None,
    上次补充时间: float = None,
    现在: float = None,
    取用数量: int = 1,
) -> 结果:
    """令牌桶惰性补充 + 取用判定。返回 {放行, 当前令牌数, 上次补充时间}。

    语义与 V3 令牌桶一致：按流逝时间补充（不超过容量），够取则放行并扣减。
    `现在` 省略时由能力内部取当前单调时钟；调用方也可显式传入以复用同一时间基准。
    """
    if not isinstance(桶容量, int) or 桶容量 <= 0:
        return 结果.失败("参数不合法", "桶容量必须是正整数", 来源=来源标识)
    if not isinstance(每秒补充, (int, float)) or 每秒补充 < 0:
        return 结果.失败("参数不合法", "每秒补充必须是非负数", 来源=来源标识)
    if not isinstance(当前令牌数, (int, float)) or 当前令牌数 < 0:
        return 结果.失败("参数不合法", "当前令牌数必须是非负数", 来源=来源标识)
    if not isinstance(上次补充时间, (int, float)):
        return 结果.失败("参数不合法", "上次补充时间必须是数值", 来源=来源标识)
    if not isinstance(取用数量, int) or 取用数量 <= 0:
        return 结果.失败("参数不合法", "取用数量必须是正整数", 来源=来源标识)

    import time as _time
    当前时间 = float(现在) if isinstance(现在, (int, float)) else _time.monotonic()
    已流逝 = max(0.0, 当前时间 - float(上次补充时间))
    补充后令牌数 = min(float(桶容量), float(当前令牌数) + 已流逝 * float(每秒补充))

    if 补充后令牌数 >= 取用数量:
        剩余令牌数 = 补充后令牌数 - 取用数量
        放行 = True
    else:
        剩余令牌数 = 补充后令牌数
        放行 = False

    return 结果.成功结果({
        "放行": 放行,
        "当前令牌数": 剩余令牌数,
        "上次补充时间": 当前时间,
    })


def 生成请求编号(长度: int = 8) -> 结果:
    """生成唯一的请求编号（十六进制片段，可贯穿日志与响应头）。返回 {请求编号}。"""
    if not isinstance(长度, int) or 长度 <= 0:
        return 结果.失败("参数不合法", "长度必须是正整数", 来源=来源标识)
    if 长度 > 32:
        return 结果.失败("参数不合法", "长度上限 32", 来源=来源标识)
    编号 = uuid.uuid4().hex
    片段 = 编号 if 长度 >= 32 else 编号[:长度]
    return 结果.成功结果({"请求编号": 片段})


def 登录限速判定(
    当前失败次数: int = None,
    最大失败次数: int = None,
    锁定剩余秒: float = 0.0,
) -> 结果:
    """登录失败限速判定。返回 {锁定, 原因, 剩余可尝试次数}。

    语义与 V3 认证服务一致：累计失败达到上限即锁定；
    `锁定剩余秒` 由调用方按锁定窗口计算并传入（>0 表示仍在锁定窗口内）。
    """
    if not isinstance(当前失败次数, int) or 当前失败次数 < 0:
        return 结果.失败("参数不合法", "当前失败次数必须是非负整数", 来源=来源标识)
    if not isinstance(最大失败次数, int) or 最大失败次数 <= 0:
        return 结果.失败("参数不合法", "最大失败次数必须是正整数", 来源=来源标识)
    if not isinstance(锁定剩余秒, (int, float)) or 锁定剩余秒 < 0:
        return 结果.失败("参数不合法", "锁定剩余秒必须是非负数", 来源=来源标识)

    if float(锁定剩余秒) > 0:
        return 结果.成功结果({
            "锁定": True,
            "原因": f"登录失败次数过多，请在 {int(float(锁定剩余秒))} 秒后重试",
            "剩余可尝试次数": 0,
        })
    if int(当前失败次数) >= int(最大失败次数):
        return 结果.成功结果({
            "锁定": True,
            "原因": "登录失败次数已达上限",
            "剩余可尝试次数": 0,
        })
    return 结果.成功结果({
        "锁定": False,
        "原因": "",
        "剩余可尝试次数": int(最大失败次数) - int(当前失败次数),
    })
