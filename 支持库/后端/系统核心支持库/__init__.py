def 注册能力(注册表) -> None:
    """聚合注册：收集所有子库的能力注册。"""
    import importlib
    for 子库名 in ['删除守卫', '协议白名单', '工具执行', '幂等消息', '权限审批', '检查点恢复', '环境变量', '系统信息', '资源管理', '路径安全', '进程管理', '额度控制']:
        try:
            入口 = importlib.import_module("支持库.后端.系统核心支持库." + 子库名)
            注册函数 = getattr(入口, "注册能力", None)
            if callable(注册函数):
                注册函数(注册表)
        except Exception as 错误:
            raise RuntimeError(f"聚合子库 {子库名} 注册失败: {错误}") from 错误
