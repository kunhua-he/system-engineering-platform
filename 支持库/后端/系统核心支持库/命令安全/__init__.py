"""支持库.命令安全 包级中文入口。"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.后端.系统核心支持库.命令安全.实现.命令安全 import 检测危险命令

__all__ = [
    "检测危险命令",
]


def _校验参数名序(参数契约表: dict[str, list[dict]],
                  注册参数名序: dict[str, list[str]]) -> None:
    """装配期闸门：注册参数名序必须逐字等于契约名序，否则本包装配失败。

    为什么要有它：注册处一旦漏一个参数（或顺序写反），网关的必填校验就与契约分叉
    ——那正是「手工重建参数声明」缺陷的形态。宁可装配期就 raise，也不静默漏参。
    """
    for 能力id, 契约参数 in 参数契约表.items():
        注册名序 = 注册参数名序.get(能力id)
        if 注册名序 is None:
            raise ValueError(f"能力 {能力id} 有契约但注册处未声明参数名序")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(注册名序):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(注册名序)} 与契约参数名序 {契约名序} "
                "不一致：参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），"
                "入口不得另立一份")


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 缺陷溯源：本入口原先手工重建注册参数声明（`for 能力id, 函数, 参数表 in [...]`），
    # 手工表一旦漏一个参数，网关按入口契约表传参时会把新参数**静默丢弃**（同族现场见
    # 未完成事项 #197：文件操作 手工表漏了 起始行/结束行）。修法：参数声明从
    # `能力契约/参数契约.json` **整条透传**，入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：漂移检测的 AST 读取器
    # （`_静态字面量`）只收 `注册能力` 函数体内的赋值，且能解析出整条参数含 `必填`；
    # 包一层 `_参数声明(能力id)` 会让 AST 一律判「不可静态判定」，等于拿门禁覆盖率换干净。
    # 表内布尔位写中文 真/假（真源 公共契约/基础类型/逻辑类型.py）。
    # 名序护盾由 `_注册参数名序` + `_校验参数名序()` 承担，装配期逐条对契约核名序。
    _参数契约表 = {
        "系统核心支持库.命令安全.检测危险命令": [
            {"名称": "命令", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "最大长度", "类型": "整数型", "必填": 假, "默认值": None},
        ],
    }
    _注册参数名序 = {
        "系统核心支持库.命令安全.检测危险命令": ["命令", "最大长度"],
    }
    _校验参数名序(_参数契约表, _注册参数名序)
# ===== 参数声明透传 结束 =====
    注册表.注册(
        能力实现(
            能力id="系统核心支持库.命令安全.检测危险命令",
            包id="支持库.后端.系统核心支持库.命令安全",
            实现函数=检测危险命令,
            参数=_参数契约表["系统核心支持库.命令安全.检测危险命令"],
            返回="结果",
            说明="命令安全支持库",
        )
    )
