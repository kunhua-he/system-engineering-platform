#: `校验相对路径文本` 拒绝时的**结构化判据码**（哲学 14.4：文案给人看，错误码给机器判）。
#: **冻结集合**：`绝对写法`（POSIX 绝对 + Windows 盘符两种字面同属一条判据）／`家目录写法`／
#: `段跳转`／`当前目录`／`点段`。判据码与 `原因` 文案一一对应，但**机器判据只许读判据码** ——
#: 2026-09-24 批H 收口时，调用方（`开发工具/HTML验证/路径安全.py` 的静态守卫）是按 `原因`
#: **文案串**做 `in (...)` 比对的：文案一改，判据就静默失效（正是 14.4 要消灭的形状）。
#: 故本节点同时给出两条读数：`原因` 给人看、`判据` 给机器判；判据码集合只增不改不删。
判据码_绝对写法 = "绝对写法"
判据码_家目录写法 = "家目录写法"
判据码_段跳转 = "段跳转"
判据码_当前目录 = "当前目录"
判据码_点段 = "点段"
判据码集合 = frozenset({判据码_绝对写法, 判据码_家目录写法, 判据码_段跳转, 判据码_当前目录, 判据码_点段})


def _绝对写法原因(归一: str) -> str | None:
    """「绝对写法」判据的**唯一内部实现**：Windows 盘符 + POSIX 绝对，一次判定。

    命中返回原因文本（对外契约的原文，逐字不变），未命中返回 `None`。

    ★ 2026-09-24（批H 裁-A 收口）：此前「Windows 盘符判据」与 POSIX 绝对判定是**两条各自
    独立的判据** —— 同一件事两套实现，且 `C:foo` 只被前一条认出（后一条在 POSIX 上不认）
    ⇒ 同一份文本随宿主平台得出两个结论。现收成这一份：**判据集合、判定顺序与对外原因文本
    逐字不变**（盘符 → 「相对路径不能是 Windows 盘符路径」；其余绝对写法 → 「相对路径不能是
    绝对路径」），只加严、不放宽，也不新增/删除任何判据。

    `归一` 已由调用方把反斜杠归成 `/`（故「POSIX 绝对」即「以 `/` 开头」，与 POSIX 绝对判定
    在归一后文本上的判定等价）；盘符那一支已在本函数里先判。
    """
    if len(归一) > 1 and 归一[1] == ":" and 归一[0].isalpha():
        return "相对路径不能是 Windows 盘符路径"
    if 归一.startswith("/"):
        return "相对路径不能是绝对路径"
    return None


def 像路径写法文本(文本: str = None) -> 结果:
    """**射程判定**：这段字面是不是在写一个路径？返回 {是路径写法, 原因}。

    **它回答的问题与 `校验相对路径文本` 不同**（两个问题、同一个节点模块，不是两条腿）：
    · 本函数问「**要不要**按路径规范判」—— 调用方拿它决定是否送写法判据；
    · `校验相对路径文本` 问「是不是绝对写法／`..` 逃逸写法」—— 那才是**边界判据**。

    **为什么必须有射程（2026-09-24 批H-H5 实测）**：写法判据按**路径规范**判（判据前把反斜杠
    归一成 `/`），把**非路径字面**送进去会得到与路径无关的结论 —— 同一份验证场景里
    `表达式="\\d+"`（正则）被读成绝对路径 `/d+` 而判拒，`表达式="(\\d+)"` 却放行；
    空串/空白串则被回 `失败("参数不合法")`。调用方若把这些当「越界写法」，全仓负向用例
    （「空参数被拒」这类）会整包报红（实测 24 个包）。

    射程判据（三条，任一命中即**是**路径写法）：原文含正斜杠、原文含连续两点、盘符写法
    （字母加冒号后跟正斜杠或反斜杠）。口径与 2026-09-24 批H 之前的场景守卫自写判据**等价**
    （那时对空串、空白串、正则 `\\d+`、单前导反斜杠的 `\\etc\\passwd` 一律放行），
    **只加严不放宽**：`a\\..\\b` 这类「反斜杠归一后才成 `..` 段」的写法由写法判据判 `段跳转`。

    **为什么它必须住本模块**（而不是住在调用方）：`开发工具/验证门禁/同动作双路径检测.py`
    的规则七把「名字含路径 + 段里含 `..`」的模块级函数一律算「同职责路径边界判定的第二份实现」
    —— 射程判定若写在调用方，会被正确判红（实测 `开发工具/HTML验证/路径安全.py` 命中一条）。
    它是路径判定这件事的一部分，故与写法判据同住唯一腿 `支持库.后端.系统核心支持库.路径安全`。
    """
    if not isinstance(文本, str):
        return 结果.失败("参数不合法", "文本必须是字符串", 来源="路径安全")
    是 = ("/" in 文本) or (".." in 文本) or (re.match(r"^[A-Za-z]:[\\/]", 文本) is not None)
    return 结果.成功结果({
        "是路径写法": 是,
        "原因": "含正斜杠或连续两点或盘符写法" if 是 else "不含正斜杠、连续两点与盘符，非路径字面",
    })


def 校验相对路径文本(相对路径: str = None) -> 结果:
    """**全平台路径边界判定的唯一节点**：只判**相对路径文本**，不碰文件系统、不需要根目录。

    返回 {通过, 判据, 原因, 归一化相对路径}：通过时给出去空段、按 `/` 切的归一化相对路径。
    **拒绝时多给一条结构化读数 `判据`**（见本模块 `判据码_*` 常量，哲学 14.4）：`原因` 给人看、
    `判据` 给机器判 —— 调用方要按判据类别分支（如「绝对写法/段跳转 要拒、家目录写法/点段 要放行」）
    一律读 `判据`，**不得比对 `原因` 文案串**（2026-09-24 批H 实测：按文案比对的守卫在文案一改时静默失效）。
    `校验路径` = 本节点 + 根内绝对化 + realpath 符号链接逃逸判；三处调用方
    （包仓库/租约路径/HTML验证 各自的路径模块）一律转调本节点 ⇒ 同一职责只有这一份判据。

    判据顺序（**只加严、不放宽**）：
    ① URL 解码一次 → ② 反斜杠归一 → ③ Windows 盘符 → ④ `~` 家目录写法 →
    ⑤ POSIX 绝对路径 → ⑥ `..` 目录段 → ⑦ 整串 `.`/`./` → ⑧ 段内 `.`。

    ★ 2026-09-24（批H 裁-A 收口）：③ 与 ⑤ 同属「绝对写法」，由 `_绝对写法原因` **一份内部实现**
    判定（此前是两条各自独立的判据：盘符那条认 `C:foo`、POSIX 绝对判定那条不认 ⇒
    同一件事两套实现）。**判据集合与对外原因文本逐字不变**，只加严不放宽。
    """
    if not isinstance(相对路径, str) or not 相对路径.strip():
        return 结果.失败("参数不合法", "相对路径必须是非空字符串", 来源="路径安全")
    # URL 解码归一化（未完成事项 §四「路径边界有 5 份实现、口径互不一致」，2026-09-23）：**所有判据之前**先 unquote，且只解一次。
    # 为什么必须在判据之前：`..%2fetc` / `%2e%2e/x` / `a/..%2f/b` 字面既不含 `..` 段、
    # POSIX 绝对判定也不认，会被整段当成普通目录名放行；而消费方拿到的是**解码后**的
    # 路径 ⇒ 编码穿越可整体绕过本能力。
    # 为什么只解一次：对**已解码结果**再解一次会让 `%252e%252e` 这类双重编码钻过去
    # （二次解码本身就是漏洞），故此处只对原始入参调用一次 unquote。
    归一 = unquote(相对路径).replace("\\", "/")
    # 加严（2026-09-23 S4·T3「路径安全 8 处实现、实测 6 处分歧」）：下面几条把唯一腿缺的判据补齐，
    # 使分歧归零。**只加严、不放宽**任何既有判据（既有判据的切分口径是这里的子集）。
    # ① 反斜杠归一后再判 —— 此前 POSIX 上 `a\\..\\b` 整段被当普通目录名，`..` 段判据看不见它。
    # ②③ 绝对写法（Windows 盘符 `C:foo` / `C:/foo` + POSIX 绝对）：都不是「项目根内相对路径」，
    #    而 POSIX 绝对判定对盘符两者都不认 ⇒ 此前整体放行。2026-09-24 收成一份内部实现
    #    （`_绝对写法原因`）：原因文本与判据集合逐字不变。
    绝对写法 = _绝对写法原因(归一)
    if 绝对写法:
        return 结果.成功结果({"通过": False, "判据": 判据码_绝对写法, "原因": 绝对写法, "归一化相对路径": ""})
    # ④ `~` 家目录写法：`expanduser` 只作用于 根目录，相对路径里的 `~` 会被当成普通目录名放行。
    if 归一.startswith("~"):
        return 结果.成功结果({"通过": False, "判据": 判据码_家目录写法, "原因": "相对路径不能是 ~ 家目录写法", "归一化相对路径": ""})
    # 段判据统一按 `/` 切（`归一` 已把反斜杠转正斜杠 ⇒ 是原口径的超集，不会放宽）。
    段 = [项 for 项 in 归一.split("/") if 项]
    if ".." in 段:
        return 结果.成功结果({"通过": False, "判据": 判据码_段跳转, "原因": "相对路径不能包含 .. 目录跳转", "归一化相对路径": ""})
    if 归一 in (".", "./"):
        return 结果.成功结果({"通过": False, "判据": 判据码_当前目录, "原因": "相对路径不能是当前目录", "归一化相对路径": ""})
    # ④ 段内 `.`（如 `a/./b`）此前整体放行（实测：包仓库拒、唯一腿通过）⇒ 一并拒，收成一致。
    if "." in 段:
        return 结果.成功结果({"通过": False, "判据": 判据码_点段, "原因": "相对路径不能包含 . 目录段", "归一化相对路径": ""})
    return 结果.成功结果({"通过": True, "原因": "允许", "归一化相对路径": "/".join(段)})


def 校验路径(根目录: str = None, 相对路径: str = None) -> 结果:
    """校验 相对路径 是否安全落在 根目录 内。返回 {通过, 绝对路径}。

    判定**转调** `校验相对路径文本`（唯一节点）；本函数只多做「根内绝对化 + realpath 符号链接逃逸」。
    """
    if not isinstance(根目录, str) or not 根目录.strip():
        return 结果.失败("参数不合法", "根目录必须是非空字符串", 来源="路径安全")
    文本判定 = 校验相对路径文本(相对路径)
    if not 文本判定.成功:
        return 文本判定
    判定值 = 文本判定.值 if isinstance(文本判定.值, dict) else {}
    if not 判定值.get("通过"):
        return 结果.成功结果({"通过": False, "原因": 判定值.get("原因") or "相对路径不合法", "绝对路径": ""})
    归一 = 判定值.get("归一化相对路径") or ""
    根 = os.path.abspath(os.path.expanduser(根目录))
    # 判据已收口到 校验相对路径文本（唯一节点）；本函数只保留根内绝对化 + realpath 符号链接逃逸判。
    # 「相对 → 绝对」转调 `公共契约.运行时.平台适配.解析路径`（全平台唯一那条腿），生效根取
    # 调用方给的 `根`；`归一` 已由唯一节点去掉空段与 `.`/`..` 段，故无需再 normpath。
    # **本函数不自带绝对写法分支、不自己拼根**（绝对写法判据只住 `_绝对写法原因` 一处）。
    绝对路径 = str(解析路径(归一, 根))
    # 防符号链接逃逸：解析后必须仍在根内
    try:
        真实根 = os.path.realpath(根)
        真实路径 = os.path.realpath(绝对路径)
    except OSError:
        return 结果.失败("路径解析失败", "realpath 解析异常", 来源="路径安全")
    if not (真实路径 == 真实根 or 真实路径.startswith(真实根 + os.sep)):
        return 结果.成功结果({"通过": False, "原因": "路径越出根目录（符号链接逃逸）", "绝对路径": ""})
    return 结果.成功结果({"通过": True, "原因": "允许", "绝对路径": 绝对路径})


def 校验文件名(文件名: str = None) -> 结果:
    """校验文件名安全：非空、不含路径分隔符、不含 .. 、不以 . 开头（防隐藏文件）。"""
    if not isinstance(文件名, str) or not 文件名.strip():
        return 结果.失败("参数不合法", "文件名必须是非空字符串", 来源="路径安全")
    if "/" in 文件名 or "\\" in 文件名:
        return 结果.成功结果({"通过": False, "原因": "文件名不能包含路径分隔符", "安全文件名": ""})
    if 文件名 in (".", "..") or 文件名.startswith("."):
        return 结果.成功结果({"通过": False, "原因": "文件名不能是 . / .. 或以点开头", "安全文件名": ""})
    return 结果.成功结果({"通过": True, "原因": "允许", "安全文件名": 文件名})

def 显示相对路径(目标路径: str = None, 基准目录: str = None, 备选基准: str = None) -> 结果:
    """把绝对路径显示为相对某基准目录的字符串（用于日志/UI 展示）。

    依次尝试 基准目录 → 备选基准，都不在则原样返回绝对路径。
    不抛异常：任何异常都回退为原样返回，保证展示路径永不中断调用方。
    """
    from pathlib import Path as _Path

    if not isinstance(目标路径, str) or not 目标路径.strip():
        return 结果.失败("参数不合法", "目标路径必须是非空字符串", 来源="路径安全")
    路径 = _Path(目标路径)
    for 候选 in (基准目录, 备选基准):
        if isinstance(候选, str) and 候选.strip():
            try:
                return 结果.成功结果({"显示路径": str(路径.relative_to(_Path(候选))), "相对": True})
            except ValueError:
                continue
    return 结果.成功结果({"显示路径": str(路径), "相对": False})
