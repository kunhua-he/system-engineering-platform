"""数据交换支持库包级中文入口。

调用者只能从此入口导入，禁止深入 实现/ 目录。
"""

from __future__ import annotations

from 支持库.后端.数据交换.实现.数据交换 import 序列化JSON
from 支持库.后端.数据交换.实现.数据交换 import 反序列化JSON
from 支持库.后端.数据交换.实现.数据交换 import 序列化CSV
from 支持库.后端.数据交换.实现.数据交换 import 反序列化CSV

__all__ = [
    "序列化JSON",
    "反序列化JSON",
    "序列化CSV",
    "反序列化CSV",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数表, 返回类型 in [
        ("数据交换.序列化JSON", 序列化JSON, [{"名称": "数据", "类型": "字典", "必填": True}], "结果"),
        ("数据交换.反序列化JSON", 反序列化JSON, [{"名称": "文本", "类型": "文本", "必填": True}], "结果"),
        ("数据交换.序列化CSV", 序列化CSV, [{"名称": "行列表", "类型": "列表", "必填": True}], "结果"),
        ("数据交换.反序列化CSV", 反序列化CSV, [{"名称": "文本", "类型": "文本", "必填": True}], "结果"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.数据交换",
                实现函数=函数,
                参数=参数表,
                返回=返回类型,
                说明="数据交换原子能力",
            )
        )
