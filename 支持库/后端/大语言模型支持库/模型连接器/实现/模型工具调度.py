"""模型工具调度：循环软护栏、工具并行调度、取消结果合成、重试调度、工具清单门控。

2026-09-19 从 `实现/模型连接器.py` 原样搬出（对外零变化，成员名一个不改）。

**纯计算簇**：不发起任何模型、网络或工具调用，只产出计划与判定，可被任意层复用：

- `循环软护栏`：同工具连续调用达阈值档位时给提醒文本（不硬杀、不静默，纠错权交模型）；
- `调度工具调用` / `合成取消结果`：独占调用成串行屏障、并行调用进有界池（默认 10），
  结果严格按输入顺序提交；取消结果错误码一律中文（`派发前已取消`）；
- `重试调度`：按错误码白名单/兜底模式判定是否重试，给出带抖动的指数退避计划
  （第 i 次 = 退避基数秒 × 2^i × (1 + 抖动比例)，单次上限 300 秒）；可选入参
  `实际错误码` 传入时按「实际错误码 ∈ 白名单」判定命中，不传保持旧行为；
- `组装可用工具清单`：按门控模式过滤/排序调用方传入的清单，不内嵌任何业务角色判断。

三张别名/键表（`重试模式别名` / `门控模式别名` / `工具名键表`）是各自归一化的唯一事实源。

**依存方向**：只依赖公共契约与 `模型连接基元` 的 `_失败`，无反向引用。
"""
