def 注册能力(注册表) -> None:
    """聚合注册：收集所有子库的能力注册。"""
    import importlib
    for 子库名 in ['上下文压缩', '会话存储', '嵌入缓存', '模型连接器', '流式推理', '重排服务']:
        try:
            入口 = importlib.import_module("支持库.后端.大语言模型支持库." + 子库名)
            注册函数 = getattr(入口, "注册能力", None)
            if callable(注册函数):
                注册函数(注册表)
        except Exception as 错误:
            raise RuntimeError(f"聚合子库 {子库名} 注册失败: {错误}") from 错误
