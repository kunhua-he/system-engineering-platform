"""文档转换支持库包级中文入口（经调用器调用受管提供者能力）。

调用者只从此入口导入，禁止深入 实现/ 目录。
安全默认：外部进程边界由受管提供者（textutil/LibreOffice）承担。
"""

from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现
from 支持库.后端.文档转换.实现.文档转换 import 检查提供者
from 支持库.后端.文档转换.实现.文档转换 import 转换文本文件
from 支持库.后端.文档转换.实现.文档转换 import 转换办公文件

__all__ = [
    "检查提供者",
    "转换文本文件",
    "转换办公文件",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
    for 能力id, 函数, 参数表 in [
        ("文档转换.检查提供者", 检查提供者, [{"名称": "提供者名", "类型": "文本型", "必填": True}]),
        ("文档转换.转换文本文件", 转换文本文件, [
            {"名称": "源路径", "类型": "文本型", "必填": True},
            {"名称": "目标格式", "类型": "文本型", "必填": False},
            {"名称": "输出目录", "类型": "文本型", "必填": False},
            {"名称": "超时秒", "类型": "双精度数型", "必填": False},
            {"名称": "最大输出字节", "类型": "整数型", "必填": False},
        ]),
        ("文档转换.转换办公文件", 转换办公文件, [
            {"名称": "源路径", "类型": "文本型", "必填": True},
            {"名称": "目标格式", "类型": "文本型", "必填": True},
            {"名称": "输出目录", "类型": "文本型", "必填": False},
            {"名称": "超时秒", "类型": "双精度数型", "必填": False},
            {"名称": "最大输出字节", "类型": "整数型", "必填": False},
        ]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文档转换",
                实现函数=函数,
                参数=参数表,
                返回="结果型",
                说明="文档转换原子能力",
            )
        )
