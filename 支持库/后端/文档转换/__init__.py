"""文档转换支持库包级中文入口（外部进程边界）。

调用者只从此入口导入，禁止深入 实现/ 目录。
安全默认：结构化参数、独立进程组、超时、输出上限、临时目录隔离、强制终止。
"""

from __future__ import annotations

from 支持库.后端.文档转换.实现.文档转换 import 检查提供者
from 支持库.后端.文档转换.实现.文档转换 import 转换文本文件
from 支持库.后端.文档转换.实现.文档转换 import 转换办公文件

__all__ = [
    "检查提供者",
    "转换文本文件",
    "转换办公文件",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名 in [
        ("文档转换.检查提供者", 检查提供者, ["提供者名"]),
        ("文档转换.转换文本文件", 转换文本文件, ["源路径", "目标格式", "输出目录", "超时秒", "最大输出字节"]),
        ("文档转换.转换办公文件", 转换办公文件, ["源路径", "目标格式", "输出目录", "超时秒", "最大输出字节"]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文档转换",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明="文档转换原子能力",
            )
        )
