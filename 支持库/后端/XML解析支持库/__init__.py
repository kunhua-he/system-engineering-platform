"""支持库.XML解析支持库 包级中文入口。"""

from __future__ import annotations

from 支持库.后端.XML解析支持库.实现.XML解析 import 解析XML
from 支持库.后端.XML解析支持库.实现.XML解析 import 生成XML
from 支持库.后端.XML解析支持库.实现.XML解析 import 查询节点

__all__ = [
    "解析XML",
    "生成XML",
    "查询节点",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现
    for 能力id, 函数, 参数表 in [
        ("XML解析支持库.解析XML", 解析XML, [{"名称": "XML文本", "类型": "文本型", "必填": True, "默认值": None, "说明": "XML 文本"}]),
        ("XML解析支持库.生成XML", 生成XML, [{"名称": "根节点名", "类型": "文本型", "必填": True, "默认值": None, "说明": "根节点名称"}, {"名称": "子节点", "类型": "列表型", "必填": False, "默认值": None, "说明": "子节点列表 [{名称, 文本, 属性}]"}]),
        ("XML解析支持库.查询节点", 查询节点, [{"名称": "XML文本", "类型": "文本型", "必填": True, "默认值": None, "说明": "XML 文本"}, {"名称": "XPath", "类型": "文本型", "必填": True, "默认值": None, "说明": "XPath 表达式"}]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.XML解析支持库",
                实现函数=函数,
                参数=参数表,
                返回="结果",
                说明="XML 解析/生成/查询节点（参考易语言 XML解析支持库）",
            )
        )
