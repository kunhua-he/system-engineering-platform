"""文档生成支持库包级中文入口（经调用器调用受管提供者能力）。

调用者只能从此入口导入，禁止深入 实现/ 目录。
公开能力：生成DOCX / 生成XLSX / 生成PPTX / 生成PDF / 校验签名。
"""

from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现
from 支持库.后端.文档生成.实现.文档生成 import 生成DOCX
from 支持库.后端.文档生成.实现.文档生成 import 生成PDF
from 支持库.后端.文档生成.实现.文档生成 import 生成PPTX
from 支持库.后端.文档生成.实现.文档生成 import 生成XLSX
from 支持库.后端.文档生成.实现.签名校验 import 校验签名

__all__ = ["生成DOCX", "生成XLSX", "生成PPTX", "生成PDF", "校验签名"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库全部能力。"""
    契约表 = [
        ("文档生成.生成DOCX", 生成DOCX, [{"名称": "参数", "类型": "字典", "必填": True}], "生成DOCX"),
        ("文档生成.生成XLSX", 生成XLSX, [{"名称": "参数", "类型": "字典", "必填": True}], "生成XLSX"),
        ("文档生成.生成PPTX", 生成PPTX, [{"名称": "参数", "类型": "字典", "必填": True}], "生成PPTX"),
        ("文档生成.生成PDF", 生成PDF, [{"名称": "参数", "类型": "字典", "必填": True}], "生成PDF"),
        ("文档生成.校验签名", 校验签名, [{"名称": "格式", "类型": "文本", "必填": True}, {"名称": "字节", "类型": "字节", "必填": True}], "校验签名"),
    ]
    for 能力id, 函数, 参数表, 说明 in 契约表:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.后端.文档生成",
                实现函数=函数,
                参数=参数表,
                返回="结果",
                说明=f"文档生成原子能力：{说明}",
            )
        )
