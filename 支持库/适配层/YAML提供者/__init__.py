"""YAML 提供者包级中文入口（第三方 PyYAML 边界）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 数据交换）：
- 解析YAML → 解析后的数据
- 序列化YAML → YAML 文本
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.适配层.YAML提供者.实现.提供者 import 解析YAML
from 支持库.适配层.YAML提供者.实现.提供者 import 序列化YAML
from 支持库.适配层.YAML提供者.实现.提供者 import 检查可用性
from 支持库.适配层.YAML提供者.实现.提供者 import YAML解析错误
from 支持库.适配层.YAML提供者.实现.提供者 import YAML依赖不可用

__all__ = ["解析YAML", "序列化YAML", "检查可用性", "YAML解析错误", "YAML依赖不可用", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本提供者能力。"""
    from 公共契约.能力契约.契约 import 能力实现
    from 公共契约.基础类型.结果类型 import 结果

    def 解析YAML能力(文本: str):
        """能力边界：按契约返回结果型；裸 dict 会被统一结果契约判违约，故在此收口。

        依赖缺失（PyYAML 未装）与解析失败分两码：前者 依赖不可用（可重试，装好即可恢复），
        后者 解析失败（属输入问题，重试同样失败）。两者都不静默降级。
        """
        try:
            return 结果.成功结果(解析YAML(文本))
        except YAML依赖不可用 as 错误:
            return 结果.失败("依赖不可用", f"PyYAML 不可用: {错误}",
                             来源="YAML提供者", 可重试=真)
        except YAML解析错误 as 错误:
            return 结果.失败("解析失败", f"YAML 解析失败: {错误}", 来源="YAML提供者")
        except Exception as 错误:
            return 结果.失败("解析失败", f"YAML 解析异常: {错误}", 来源="YAML提供者")

    def 序列化YAML能力(数据):
        """能力边界：依赖缺失报 依赖不可用（可重试），序列化异常报 序列化失败。"""
        try:
            return 结果.成功结果(序列化YAML(数据))
        except YAML依赖不可用 as 错误:
            return 结果.失败("依赖不可用", f"PyYAML 不可用: {错误}",
                             来源="YAML提供者", 可重试=真)
        except Exception as 错误:
            return 结果.失败("序列化失败", f"YAML 序列化异常: {错误}", 来源="YAML提供者")

    def 检查可用性能力():
        """探针能力：依赖不可用时明确失败（不静默降级）。

        口径说明（2026-09-19）：提供者层的 检查可用性() 本身**不抛**（缺依赖时如实
        返回 可用=假），把「可用=假」翻成中文错误码 依赖不可用 的收口落在本能力边界。
        探针的「不可用」是探针的**正常判定结果**，不得被当作异常吞成看不清的原因文本。
        """
        try:
            探针值 = 检查可用性()
        except Exception as 错误:
            return 结果.失败("依赖不可用", f"PyYAML 探针异常: {错误}", 来源="YAML提供者")
        if not 探针值.get("可用"):
            return 结果.失败("依赖不可用", str(探针值.get("说明") or "PyYAML 不可用"),
                             来源="YAML提供者", 可重试=真)
        return 结果.成功结果(探针值)

    for 能力id, 函数, 参数表, 说明 in [
        ("适配层.YAML提供者.解析YAML", 解析YAML能力,
         [{"名称": "文本", "类型": "文本型", "必填": 真}], "把 YAML 文本解析为数据"),
        ("适配层.YAML提供者.序列化YAML", 序列化YAML能力,
         [{"名称": "数据", "类型": "JSON值型", "必填": 真}], "把数据序列化为 YAML 文本"),
        ("适配层.YAML提供者.检查可用性", 检查可用性能力,
         [], "探针：报告 PyYAML 依赖可用性与版本"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.YAML提供者",
                实现函数=函数,
                参数=参数表,
                返回="结果",
                说明=说明,
            )
        )
