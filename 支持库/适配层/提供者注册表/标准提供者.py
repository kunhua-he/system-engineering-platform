"""标准提供者注册：把四类外部适配器注册为提供者。

每个提供者声明：名称、版本、能力、配置需求；创建函数接收配置
返回适配器实例。真实第三方库实现未来放提供者适配层，这里只注册
模拟提供者。
"""

from __future__ import annotations

from typing import Any

from 支持库.适配层.配置契约.提供者配置契约 import 提供者配置需求
from 支持库.适配层.数据库适配器.数据库适配器 import 数据库适配器
from 支持库.适配层.动态库适配器.动态库适配器 import 动态库适配器
from 支持库.适配层.HTTP服务适配器.http服务适配器 import HTTP服务适配器
from 支持库.适配层.本地进程适配器.本地进程适配器 import 本地进程适配器
from 支持库.适配层.提供者注册表.提供者注册表 import 提供者声明, 提供者注册表


def _创建数据库(配置: dict[str, Any]) -> 数据库适配器:
    return 数据库适配器(驱动可用=配置.get("驱动可用", True), 版本=配置.get("版本", "模拟1.0.0"))


def _创建HTTP(配置: dict[str, Any]) -> HTTP服务适配器:
    return HTTP服务适配器(服务可用=配置.get("服务可用", True), 版本=配置.get("版本", "模拟1.0.0"))


def _创建进程(配置: dict[str, Any]) -> 本地进程适配器:
    return 本地进程适配器(程序可用=配置.get("程序可用", True), 版本=配置.get("版本", "模拟1.0.0"))


def _创建动态库(配置: dict[str, Any]) -> 动态库适配器:
    return 动态库适配器(库可用=配置.get("库可用", True), 版本=配置.get("版本", "模拟1.0.0"))


def 注册全部标准提供者(注册表: 提供者注册表) -> list[str]:
    """注册四类标准提供者；返回已注册提供者名称列表。"""
    提供者表 = [
        提供者声明(
            名称="标准数据库提供者", 版本="1.0.0",
            能力列表=["数据库.执行查询"],
            配置需求=[
                提供者配置需求("驱动可用", "布尔", False, True, False, "模拟驱动是否可用"),
                提供者配置需求("版本", "文本", False, "模拟1.0.0", False, "提供者版本"),
            ],
            创建函数=_创建数据库,
        ),
        提供者声明(
            名称="标准HTTP提供者", 版本="1.0.0",
            能力列表=["HTTP.请求"],
            配置需求=[
                提供者配置需求("服务可用", "布尔", False, True, False, "模拟服务是否可用"),
                provide_HTTP版本需求(),
            ],
            创建函数=_创建HTTP,
        ),
        提供者声明(
            名称="标准进程提供者", 版本="1.0.0",
            能力列表=["进程.执行"],
            配置需求=[
                提供者配置需求("程序可用", "布尔", False, True, False, "模拟程序是否可用"),
            ],
            创建函数=_创建进程,
        ),
        提供者声明(
            名称="标准动态库提供者", 版本="1.0.0",
            能力列表=["动态库.调用"],
            配置需求=[
                提供者配置需求("库可用", "布尔", False, True, False, "模拟库是否可用"),
            ],
            创建函数=_创建动态库,
        ),
    ]
    已注册: list[str] = []
    for 提供者 in 提供者表:
        结果 = 注册表.注册提供者(提供者)
        if 结果.成功:
            已注册.append(提供者.名称)
    return 已注册


def provide_HTTP版本需求() -> 提供者配置需求:
    """HTTP 提供者版本配置需求（独立函数保持行内简洁）。"""
    return 提供者配置需求("版本", "文本", False, "模拟1.0.0", False, "提供者版本")
