"""浏览器自动化受管 Provider 包级入口。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 浏览器自动化）：
- 检查可用 → {命令}（browser-use/uvx 未安装返回 提供者不可用）
会话级原子能力（创建/导航/读取/操作/截图/关闭）由浏览器自动化支持库持有，
Provider 作为其内部受管边界被直接引用，不重复占用会话能力 owner。
"""

from __future__ import annotations

from 支持库.适配层.浏览器自动化提供者.实现.提供者 import 浏览器自动化提供者

__all__ = ["浏览器自动化提供者", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    提供者 = 浏览器自动化提供者()

    def 检查可用() -> dict:
        return 提供者.检查可用()

    注册表.注册(
        能力实现(
            能力id="浏览器自动化.检查可用",
            包id="支持库.适配层.浏览器自动化提供者",
            实现函数=检查可用,
            参数=[],
            返回="结果型",
            说明="检查 Browser Use/agent-browser 命令是否可用并返回发现命令",
        )
    )
