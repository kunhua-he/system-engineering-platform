"""Git 提供者包级中文入口（git 外部命令受管执行边界）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 Git操作）：
- 检查提供者 → {git, 版本}
- 创建工作区 → {路径, 分支}
- 查询工作区 → {工作区列表}
- 关闭工作区 → {已关闭}
- 提交 → {提交, 消息, 路径列表}
- 回滚 → {回滚, 新提交}
- 挑拣合入 → {挑拣合入, 新提交}
- 当前状态 → {分支, 未提交修改, 最近提交}
安全：分支名/路径/提交哈希 参数白名单，全部 git 调用为参数列表（禁 shell）。
"""

from __future__ import annotations

from 支持库.适配层.Git提供者.实现.Git提供者 import 检查提供者
from 支持库.适配层.Git提供者.实现.Git提供者 import 创建工作区
from 支持库.适配层.Git提供者.实现.Git提供者 import 查询工作区
from 支持库.适配层.Git提供者.实现.Git提供者 import 关闭工作区
from 支持库.适配层.Git提供者.实现.Git提供者 import 当前状态
from 支持库.适配层.Git提供者.实现.提交回滚 import 提交
from 支持库.适配层.Git提供者.实现.提交回滚 import 回滚
from 支持库.适配层.Git提供者.实现.提交回滚 import 挑拣合入

__all__ = [
    "检查提供者", "创建工作区", "查询工作区", "关闭工作区",
    "提交", "回滚", "挑拣合入", "当前状态",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 Git操作）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("Git操作.检查提供者", 检查提供者, [], "检查 git 是否可用并返回版本"),
        ("Git操作.创建工作区", 创建工作区, ["仓库路径", "新路径", "分支名", "起始点", "超时秒"],
         "git worktree add 新建独立工作区"),
        ("Git操作.查询工作区", 查询工作区, ["仓库路径", "超时秒"],
         "git worktree list 返回全部工作区清单"),
        ("Git操作.关闭工作区", 关闭工作区, ["仓库路径", "目标路径", "超时秒"],
         "git worktree remove 非强制关闭（未提交修改拒绝）"),
        ("Git操作.提交", 提交, ["仓库路径", "路径列表", "消息", "超时秒"],
         "git add 指定路径 + commit 最小原子提交"),
        ("Git操作.回滚", 回滚, ["仓库路径", "提交哈希", "超时秒"],
         "git revert 撤销指定提交（冲突自动中止）"),
        ("Git操作.挑拣合入", 挑拣合入, ["仓库路径", "提交哈希", "超时秒"],
         "git cherry-pick 挑拣提交（冲突自动中止）"),
        ("Git操作.当前状态", 当前状态, ["仓库路径", "超时秒"],
         "status/log 摘要：分支、未提交修改、最近提交"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.Git提供者",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明=说明,
            )
        )
