"""Git 提供者分支命令：切换分支（switch）、合并分支（merge）。

`挑拣合入` 是 cherry-pick、`回滚` 是 revert，二者都**不能冒充合并/切换**，
故这里是 git 分支动作的唯一原子能力落点（MCP `workspace` 工具的「合并」在
底座原先无落点，本模块补齐）。

安全边界（与 提交 同口径，来源 `工作区管理.py:73-77` 的高危漏洞修复）：
1. 仓库根必须先过 仓库根白名单（实现/仓库根白名单.py）→ 白名单外一律 路径越界，
   禁止对任意 Git 仓执行 switch/merge；
2. 分支名先过参数白名单（实现/白名单.py：拒 空格/换行/;|&`$ 等 shell 元字符），
   再过 git check-ref-format 常用子集（实现/分支名安全.py：拒 `..`、`/.`、尾 `/`、
   尾 `.lock`、`-` 开头等），任一不过 → 参数不合法；
3. 合并冲突自动 `git merge --abort` 恢复干净状态（与 回滚/挑拣合入 同一口径），
   非零退出且无 conflict 标记时按 命令失败 返回，不吞异常。
"""

from __future__ import annotations

from 公共契约.基础类型.结果类型 import 结果
from 支持库.适配层.Git提供者.实现.白名单 import (
    失败结果, 校验分支名, 校验仓库路径, 校验超时,
)
from 支持库.适配层.Git提供者.实现.分支名安全 import 校验分支名 as 校验分支名规则
from 支持库.适配层.Git提供者.实现.仓库根白名单 import 校验提交根
from 支持库.适配层.Git提供者.实现.受管执行 import 默认超时秒, 执行git, 命令结果

_冲突标记 = "conflict"


def 校验分支名安全(分支名: object) -> 结果 | None:
    """新能力统一的分支名校验：参数白名单 + git check-ref-format 常用子集。

    两道校验都过才返回 None。返回的错误码固定 参数不合法，原因写明是哪一道不过，
    便于调用方定位（不暴露底层异常）。
    """
    白名单错误 = 校验分支名(分支名)
    if 白名单错误:
        return 白名单错误
    规则结果 = 校验分支名规则(分支名)
    if not 规则结果.成功 or not (规则结果.值 or {}).get("是否安全"):
        原因 = (规则结果.值 or {}).get("原因") or "分支名不满足 git 引用格式"
        return 失败结果("参数不合法", f"分支名不安全: {分支名!r}（{原因}）")
    return None


def _当前分支(仓库路径: str, 超时秒: float) -> 结果:
    """真实探针：当前分支名（detached HEAD 时为 HEAD）。"""
    执行 = 命令结果(执行git(仓库路径, ["rev-parse", "--abbrev-ref", "HEAD"], 超时秒))
    if not 执行.成功:
        return 执行
    return 结果.成功结果(执行.值["标准输出"].strip() or "HEAD")


def _切换(仓库路径: str, 分支名: str, 超时秒: float) -> 结果:
    """git switch 分支名 并按真实探针确认已切过去（不只信退出码）。"""
    前 = _当前分支(仓库路径, 超时秒)
    if not 前.成功:
        return 前
    切换 = 命令结果(执行git(仓库路径, ["switch", 分支名], 超时秒))
    if not 切换.成功:
        return 切换
    后 = _当前分支(仓库路径, 超时秒)
    if not 后.成功:
        return 后
    if 后.值 != 分支名:
        return 失败结果("命令失败", f"切换后当前分支为 {后.值}，不是 {分支名}")
    return 结果.成功结果({"分支": 分支名, "切换前分支": 前.值})


def 切换分支(仓库路径: str, 分支名: str, 超时秒: float = 默认超时秒) -> 结果:
    """git switch 分支名：切换到已存在的本地分支（不新建、不强制、不丢弃修改）。

    值：{分支, 切换前分支}；分支不存在/被其他工作区占用 → 命令失败；
    分支名含 shell 元字符或不符合 git 引用格式 → 参数不合法；
    仓库根不在白名单内 → 路径越界。
    """
    校验 = (校验仓库路径(仓库路径) or 校验提交根(仓库路径)
            or 校验分支名安全(分支名) or 校验超时(超时秒))
    if 校验:
        return 校验
    return _切换(仓库路径, 分支名, 超时秒)


def 合并分支(仓库路径: str, 来源分支: str, 目标分支: str | None = None,
            超时秒: float = 默认超时秒) -> 结果:
    """git merge 来源分支：把来源分支合并进目标分支（缺省 = 当前分支）。

    指定 目标分支 且与当前分支不同时，先切换再合并（等价 MCP `workspace` 的
    「switch + merge」一步到位口径）；合并冲突自动中止并返回 冲突，工作区恢复干净。
    值：{合并分支, 目标分支, 提交}（提交 = 合并后的 HEAD）。
    """
    校验 = (校验仓库路径(仓库路径) or 校验提交根(仓库路径)
            or 校验分支名安全(来源分支) or 校验超时(超时秒))
    if 校验:
        return 校验
    if 目标分支 is not None:
        校验 = 校验分支名安全(目标分支)
        if 校验:
            return 校验
    当前 = _当前分支(仓库路径, 超时秒)
    if not 当前.成功:
        return 当前
    if 目标分支 is None:
        操作分支 = 当前.值
    else:
        操作分支 = 目标分支
        if 当前.值 != 操作分支:
            切换 = _切换(仓库路径, 操作分支, 超时秒)
            if not 切换.成功:
                return 切换
    执行 = 执行git(仓库路径, ["merge", "--no-edit", 来源分支], 超时秒)
    if not 执行.成功:
        return 执行
    if 执行.值["退出码"] == 0:
        完成 = 命令结果(执行git(仓库路径, ["rev-parse", "HEAD"], 超时秒))
        if not 完成.成功:
            return 完成
        return 结果.成功结果({
            "合并分支": 来源分支, "目标分支": 操作分支,
            "提交": 完成.值["标准输出"].strip(),
        })
    输出 = (执行.值["标准输出"] + 执行.值["标准错误"]).lower()
    if _冲突标记 not in 输出:
        return 命令结果(执行)
    中止 = 命令结果(执行git(仓库路径, ["merge", "--abort"], 超时秒))
    return 失败结果("冲突", f"合并分支 发生冲突，已自动中止", 详情={
        "中止成功": 中止.成功, "git输出": 执行.值["标准错误"].strip()[-300:],
    })
