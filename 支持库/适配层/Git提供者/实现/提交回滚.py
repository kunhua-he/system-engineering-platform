#: 推送缺省远端（与 git 自身缺省一致；显式参数优先）。
默认远端 = "origin"

# ── 提交强制点（第 2 层，2026-09-23）─────────────────────────────────────────
#:
#: 第 1 层是 `开发工具/git钩子/commit-msg`，它挡的是**终端 git 腿**（任何进程都能敲 git，
#: 拦不住，只能钩）。它有一个**可达上限**：`core.hooksPath` 是仓库本地配置，
#: 一条 `git config --unset core.hooksPath` 就把它**静默关掉** —— 此后提交再无拦截，
#: 且没有任何东西会报出来（本仓反复吃亏的「假绿」形态）。
#:
#: 本层把**同一条规则**直接判在提交腿上，两处各自独立生效：钩子被关掉，本腿照样拦。
#: 而 `git commit --no-verify` 这条 git 内建绕过通道，**本腿的签名里没有它**
#: （2026-09-23 实测确认）⇒ 对 MCP 腿是严格强制。
提交开工ID句式 = re.compile(r"开工-\d{8}-\d{6}-[0-9a-f]{4,}")
#: git 自身的流程消息（合并/回退/自动 fixup）不是「一次开发改动」，不要求开工ID。
#: ★ 与钩子逐字同口径（`开发工具/git钩子/commit-msg:43`）—— 两处判据必须同批改，否则两腿分叉。
提交豁免前缀 = re.compile(r"^(Merge |Revert |fixup! |squash! )")
#: 强制点的安装位置与 git 侧应指向的配置值（两处是同一件事的两个落点，故并排写）。
强制点相对目录 = ("开发工具", "git钩子")
强制点hooksPath = "开发工具/git钩子"


def 强制点校验(仓库路径: str, 消息: str, 超时秒: float) -> 结果 | None:
    """提交强制点第 2 层：钩子在不在、接着线没、消息里有没有开工ID。全通过返回 None。

    钩子文件不存在时返回 None —— 别的仓库（或本仓尚未装钩子时）没有这道强制点，
    在此处判它是**误报**，而误报会挡死与本题无关的仓库。
    """
    根 = Path(仓库路径).resolve()
    钩子 = 根.joinpath(*强制点相对目录) / "commit-msg"
    if not 钩子.is_file():
        return None
    文本 = 消息 or ""
    首行 = 文本.splitlines()[0] if 文本.strip() else ""
    if not 提交豁免前缀.match(首行) and not 提交开工ID句式.search(文本):
        return 失败结果(
            "提交被拒",
            "提交消息里没有开工ID —— 本仓一切改动从 `开工编排.开工即占` 进："
            "它发开工ID，同时原子认领 `修改路径`（互斥门）；没有开工ID 的改动不合规。"
            "修法：把开工ID 写进消息开头，形如 "
            "`开工-20260923-131126-78e8 <改了什么、怎么验的>`。",
            详情={"判据": "消息必须匹配 " + 提交开工ID句式.pattern,
                  "豁免": "首行为 Merge / Revert / fixup! / squash! 时豁免（git 自身流程消息）",
                  "本层为什么存在": "钩子可被 `git config --unset core.hooksPath` 静默关掉；"
                              "本腿判同一条规则，关掉钩子也拦得住"},
        )
    执行 = 执行git(str(根), ["config", "--get", "core.hooksPath"], 超时秒)
    if not 执行.成功:
        return 执行
    值 = (执行.值.get("标准输出") or "").strip()   # 退出码 1 = 该项未设置（git 正常回执）
    if 值 != 强制点hooksPath:
        return 失败结果(
            "强制点未接线",
            f"core.hooksPath = {值 or '（未设置）'}，应为 '{强制点hooksPath}' —— "
            f"钩子文件在（{钩子}），但 git 不会调用它：终端腿的提交将无人拦。"
            f"修法：git config core.hooksPath {强制点hooksPath}",
            详情={"钩子文件": str(钩子), "现场值": 值,
                  "修复命令": f"git config core.hooksPath {强制点hooksPath}"},
        )
    return None


def _已暂存路径(仓库路径: str, 超时秒: float) -> 结果 | list[str]:
    """读**共享索引**当前已暂存的仓库相对路径（`git diff --cached --name-only -z`）。

    为什么要读索引（2026-09-23）：本能力的提交腿是 `git add -- 我的路径` + `git commit -m`
    —— 第二条命令**不带 pathspec**，提交的是**整个索引**，而索引是**全仓一份、跨会话共享**
    的。别人（另一路并行会话）已暂存的文件会被一并卷进本次提交，这正是「只提交自己的」
    这条防线被穿透的形态（本仓 2026-09-23 已实测复发）。故提交前必须先看清索引里有什么。

    fail-closed：读不出来（git 起不来/超时/输出超限）一律回失败结果，由调用方拒绝提交
    —— 判据取不到就放行，等于又回到「看不见就当没有」。
    """
    执行 = 执行git(仓库路径, ["diff", "--cached", "--name-only", "-z"], 超时秒)
    if not 执行.成功:
        return 执行
    if 执行.值["退出码"] != 0:
        return 失败结果("命令失败",
                        f"读共享索引失败（git diff --cached 退出码 {执行.值['退出码']}）: "
                        f"{执行.值['标准错误'].strip()[-300:]}")
    return [项 for 项 in 执行.值["标准输出"].split("\0") if 项]


def _被本次覆盖(暂存路径: str, 相对列表: list[str]) -> bool:
    """该暂存路径是否属于本次 路径列表（路径列表 条目可能是文件，也可能是目录）。"""
    规范 = 暂存路径.replace("\\", "/").strip("/")
    for 项 in 相对列表:
        候选 = 项.replace("\\", "/").strip("/")
        if 规范 == 候选 or 规范.startswith(候选 + "/"):
            return 真
    return 假


def 提交(仓库路径: str, 路径列表: list[str] | None = None, 消息: str | None = None,
        超时秒: float = 默认超时秒) -> 结果:
    """git add（指定路径 或 全量 -A）+ git commit 原子提交，并回带**本次提交的文件清单**。

    路径语义（与 MCP `工作区管理.py:_工作区提交` 同口径）：
    - 路径列表 为空/未给（None 或 []）→ `git add -A` 全量暂存（新增/修改/删除全部纳入），
      返回值 全量暂存=真、路径列表=[]；
    - 路径列表 非空 → 逐条过 路径在仓库内 校验（越界 → 路径越界）后 `git add -- 路径...`。
    安全边界：仓库根先过 仓库根白名单（实现/仓库根白名单.py，M1 高危漏洞修复口径），
    白名单外一律 路径越界——禁止对任意 Git 仓执行越界提交。

    **回带 提交文件/文件数**（2026-09-21）：提交纪律要求「提交后核对文件数，防把别人的
    半成品一起带进来」，此前只能回终端 `git show --stat HEAD` 核对 —— 这条腿现在收进返回值：
    `git show --name-only --pretty=format: HEAD` 的逐行输出就是本次真正落进 commit 的文件
    （路径转义已在 执行git 层统一关掉，中文文件名按原样回带），调用方拿 文件数 与自己的
    改动数对一下即可，不必再开终端。

    **夹带判据（2026-09-23，fail-closed）**：本腿**分两层**防夹带，两层各挡一个不同的洞，
    别指望任一层单独解决（2026-09-23 主会话现场确证）：

    第一层 —— **别人的「文件」被卷进本次提交**（已复发两次的真机制）：本腿原先是
    `git add -- 我的路径` + `git commit -m 消息`（**不带 pathspec**），第二条命令提交的是
    **整个索引**，而索引全仓一份、跨会话共享 ⇒ 两个会话交错 `git add` 时，谁的 `commit`
    先跑谁就把对方**已暂存的文件**一起提交走。纪律（`开发工具/任务记忆/任务记忆.py`
    「commit 也必须带 pathspec」）写了、能力没实现。现修：`commit` 也带 pathspec
    （`["commit", "-m", 消息, "--"] + 相对列表`），**全量暂存（路径列表 为空）分支保持原样**
    —— 那一档本来就该全量，不误加。**并在提交前硬判共享索引**：索引里出现不属于本次
    `路径列表` 的路径一律 `未提交修改` 拒绝（fail-closed，见下方 `_已暂存路径`）——
    pathspec 会把它们静默留在索引里（对它们的作者无害），但**静默**正是本仓反复吃亏的形态，
    故选择显式拒绝；要提交先让那些改动各自提交/复位（`git restore --staged <路径>`）。

    第二层 —— **同一个文件上别人的「hunk」被卷进本次提交**：`git commit -- <路径>` 是
    **`--only` 语义**，取该路径**工作树的整份内容**（忽略索引里那一段的边界）⇒ 我改 F 的
    A 段、别人也改过 F 的 B 段（未提交），pathspec 照样把 B 段带上；`git add -p` 只暂存
    A 段也一样挡不住。**这一层本能力判不出来**（没有「哪几段是谁的」这个事实），只能靠
    **租约**（`开工即占` 的 `校验指纹=真` / 收工前 `查询文件租约(含现场指纹=真)` 核对
    `内容是否变更`）在**开工面**挡住 —— 即：同一文件的并行改动必须由互斥门串行化，
    提交腿不替它兜底。此处如实写清，不假装 pathspec 一次解决。
    """
    校验 = (校验仓库路径(仓库路径) or 校验提交根(仓库路径)
            or 校验提交消息(消息) or 校验超时(超时秒))
    if 校验:
        return 校验
    # ── 提交强制点第 2 层（2026-09-23）：见 强制点校验 的 docstring ──
    校验 = 强制点校验(仓库路径, 消息, 超时秒)
    if 校验:
        return 校验
    相对列表: list[str] = []
    全量暂存 = 路径列表 is None or (isinstance(路径列表, list) and not 路径列表)
    if 全量暂存:
        暂存参数 = ["add", "-A"]
        提交参数 = ["commit", "-m", 消息]
    elif isinstance(路径列表, list):
        for 路径 in 路径列表:
            # 「项目根相对路径（绝对兼容）→ 仓库内相对路径」的归一**只有 白名单.归一化仓库内路径 一处**
            # （口径出处 `公共契约/基础类型/字段名册.py::路径写法口径_普通`）；本腿不再自己解析。
            归一 = 归一化仓库内路径(仓库路径, 路径)
            if isinstance(归一, 结果):
                return 归一
            相对列表.append(归一)
        # ── 第一层夹带判据：共享索引里不属于本次 路径列表 的暂存路径 = 别人的改动 ──
        暂存路径表 = _已暂存路径(仓库路径, 超时秒)
        if isinstance(暂存路径表, 结果):
            return 暂存路径表
        外来暂存 = [路径 for 路径 in 暂存路径表 if not _被本次覆盖(路径, 相对列表)]
        if 外来暂存:
            return 失败结果(
                "未提交修改",
                f"拒绝提交：共享索引里有不属于本次提交的已暂存改动 {len(外来暂存)} 条"
                f"（{ '、'.join(sorted(外来暂存)[:5]) }{' 等' if len(外来暂存) > 5 else ''}）"
                f" —— 索引全仓一份、跨会话共享，提交腿据此判定存在夹带风险。"
                f"先把它们各自提交或复位（`git restore --staged <路径>`），再重跑本次提交。",
                详情={"外来暂存": sorted(外来暂存), "本次路径列表": 相对列表,
                      "修法": "对每条外来暂存路径先 `git restore --staged <路径>`（不改工作树）"
                              "或由它的作者先提交，再重跑本能力",
                      "第二层提示": "同一文件上他人的未提交改动本腿判不出来，"
                                "靠 开工即占/查询文件租约 的租约互斥挡"},
            )
        暂存参数 = ["add", "--"] + 相对列表
        # 第一层修法：commit 也带 pathspec（纪律口径），全量档不加。
        提交参数 = ["commit", "-m", 消息, "--", *相对列表]
    else:
        return 失败结果("参数不合法", "路径列表必须是列表（空列表=全量暂存）")
    命令列表 = [暂存参数, 提交参数, ["rev-parse", "HEAD"],
                ["show", "--name-only", "--pretty=format:", "HEAD"]]
    执行列表: list[结果] = []
    for 参数 in 命令列表:
        执行 = 命令结果(执行git(仓库路径, 参数, 超时秒))
        if not 执行.成功:
            return 执行
        执行列表.append(执行)
    提交文件 = [行.strip() for 行 in 执行列表[3].值["标准输出"].splitlines() if 行.strip()]
    return 结果.成功结果({
        "提交": 执行列表[2].值["标准输出"].strip(), "消息": 消息, "路径列表": 相对列表,
        "全量暂存": 全量暂存, "提交文件": 提交文件, "文件数": len(提交文件),
        "强制点": {"钩子": "开发工具/git钩子/commit-msg", "hooksPath": 强制点hooksPath,
                 "本腿": "已按同一判据放行（开工ID 在消息里）"},
    })


def _撤销式命令(仓库路径: str, 子命令: str, 操作名: str, 提交哈希: str,
               超时秒: float) -> 结果:
    """回滚/挑拣合入共用：哈希白名单 → 执行 → 冲突自动中止恢复。"""
    校验 = 校验仓库路径(仓库路径) or 校验提交哈希(提交哈希) or 校验超时(超时秒)
    if 校验:
        return 校验
    参数 = [子命令, 提交哈希]
    if 子命令 == "revert":
        参数.insert(1, "--no-edit")
    执行 = 执行git(仓库路径, 参数, 超时秒)
    if not 执行.成功:
        return 执行
    if 执行.值["退出码"] == 0:
        完成 = 命令结果(执行git(仓库路径, ["rev-parse", "HEAD"], 超时秒))
        if 完成.成功:
            return 结果.成功结果({
                操作名: 提交哈希, "新提交": 完成.值["标准输出"].strip(),
            })
        return 完成
    输出 = (执行.值["标准输出"] + 执行.值["标准错误"]).lower()
    if "conflict" not in 输出:
        return 命令结果(执行)
    中止 = 命令结果(执行git(仓库路径, [子命令, "--abort"], 超时秒))
    return 失败结果("冲突", f"{操作名} 发生冲突，已自动中止", 详情={
        "中止成功": 中止.成功, "git输出": 执行.值["标准错误"].strip()[-300:],
    })


def 回滚(仓库路径: str, 提交哈希: str, 超时秒: float = 默认超时秒) -> 结果:
    """git revert --no-edit 撤销指定提交；冲突自动中止。"""
    return _撤销式命令(仓库路径, "revert", "回滚", 提交哈希, 超时秒)


def 挑拣合入(仓库路径: str, 提交哈希: str, 超时秒: float = 默认超时秒) -> 结果:
    """git cherry-pick 挑拣指定提交到当前分支；冲突自动中止。"""
    return _撤销式命令(仓库路径, "cherry-pick", "挑拣合入", 提交哈希, 超时秒)


def 推送(仓库路径: str, 远端: str | None = None, 分支: str | None = None,
        超时秒: float = 默认超时秒) -> 结果:
    """git push：把本地提交推到远端（远端缺省 `origin`，分支缺省当前分支）。

    为什么补这个能力（华哥 2026-09-21：「原则上来说，你每次调用一次终端，都可以理解成
    是能力的缺失」）：本库此前只做到 `提交`（本地 add + commit），**推送没有对应能力**，
    于是「提交到 GitHub」的第二步永远只能回终端 —— 一半在能力里、一半在终端外，
    正是最典型的半截子封装。补上后整条链路（改文件→提交→推送）都留在能力面内。

    安全：仓库根过 提交根白名单（与 提交/合并/切换分支 同一口径，防越界推送到别的仓）；
    `远端`/`分支` 走白名单并**拒绝 `-` 开头**（`-` 开头的值会被 git 当选项解析，
    如 `--upload-pack=…` 可挂任意命令，属参数注入面）；全部走参数列表，禁 shell。
    detached HEAD 且未显式给 `分支` → 参数不合法（不猜要推哪条分支）。
    """
    校验 = (校验仓库路径(仓库路径) or 校验提交根(仓库路径)
            or 校验远端名(远端) or 校验超时(超时秒))
    if 校验:
        return 校验
    远端名 = (远端 or 默认远端).strip()
    分支名 = (分支 or "").strip()
    if not 分支名:
        查询 = 命令结果(执行git(仓库路径, ["rev-parse", "--abbrev-ref", "HEAD"], 超时秒))
        if not 查询.成功:
            return 查询
        分支名 = 查询.值["标准输出"].strip()
        if 分支名 in ("", "HEAD"):
            return 失败结果("参数不合法", "detached HEAD 下无法推断分支，必须显式给 分支")
    校验分支 = 校验分支名(分支名)
    if 校验分支:
        return 校验分支
