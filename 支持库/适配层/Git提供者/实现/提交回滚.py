def 推送(仓库路径: str, 远端: str | None = None, 分支: str | None = None,
        超时秒: float = 默认超时秒) -> 结果:
    """git push：把本地提交推到远端（远端缺省 `origin`，分支缺省当前分支）。

    为什么补这个能力（华哥 2026-09-21：「原则上来说，你每次调用一次终端，都可以理解成
    是能力的缺失」）：本库此前只做到 `提交`（本地 add + commit），**推送没有对应能力**，
    于是「提交到 GitHub」的第二步永远只能回终端 —— 一半在能力里、一半在终端外，
    正是最典型的半截子封装。补上后整条链路（改文件→提交→推送）都留在能力面内。

    安全：仓库根过 提交根白名单（与 提交/合并/切换分支 同一口径，防越界推送到别的仓）；
    `远端`/`分支` 走白名单并**拒绝 `-` 开头**（`-` 开头的值会被 git 当选项解析，
    如 `--upload-pack=…` 可挂任意命令，属参数注入面）；全部走参数列表，禁 shell。
    detached HEAD 且未显式给 `分支` → 参数不合法（不猜要推哪条分支）。
    """
    校验 = (校验仓库路径(仓库路径) or 校验提交根(仓库路径)
            or 校验远端名(远端) or 校验超时(超时秒))
    if 校验:
        return 校验
    远端名 = (远端 or 默认远端).strip()
    分支名 = (分支 or "").strip()
    if not 分支名:
        查询 = 命令结果(执行git(仓库路径, ["rev-parse", "--abbrev-ref", "HEAD"], 超时秒))
        if not 查询.成功:
            return 查询
        分支名 = 查询.值["标准输出"].strip()
        if 分支名 in ("", "HEAD"):
            return 失败结果("参数不合法", "detached HEAD 下无法推断分支，必须显式给 分支")
    校验分支 = 校验分支名(分支名)
    if 校验分支:
        return 校验分支
    执行 = 命令结果(执行git(仓库路径, ["push", 远端名, 分支名], 超时秒))
    if not 执行.成功:
        return 执行
    哈希 = 命令结果(执行git(仓库路径, ["rev-parse", "HEAD"], 超时秒))
    return 结果.成功结果({
        "远端": 远端名,
        "分支": 分支名,
        "提交哈希": 哈希.值["标准输出"].strip() if 哈希.成功 else "",
        "输出": 执行.值["标准输出"].strip()[-500:],
        "标准错误": 执行.值["标准错误"].strip()[-500:],
    })
