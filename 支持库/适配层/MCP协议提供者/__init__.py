def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本提供者能力。"""
    from 公共契约.能力契约.契约 import 能力实现
    from 公共契约.基础类型.结果类型 import 结果

    def 检查可用性能力():
        """探针能力：依赖不可用时明确失败（不静默降级）。"""
        try:
            return 结果.成功结果(检查可用性())
        except Exception as 错误:
            return 结果.失败("依赖不可用", f"mcp SDK 不可用: {错误}", 来源="MCP协议提供者")

    注册表.注册(
        能力实现(
            能力id="适配层.MCP协议提供者.检查可用性",
            包id="支持库.适配层.MCP协议提供者",
            实现函数=检查可用性能力,
            参数=[],
            返回="结果",
            说明="探针：报告 mcp SDK 依赖可用性与版本",
        )
    )
