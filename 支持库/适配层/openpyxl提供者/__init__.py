"""openpyxl 独立提供者包级中文入口（主进程直接 import openpyxl，纯 Python）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（注册 id 用 openpyxl提供者.* 前缀，领域契约名 表格文档.解析/
生成表格文档 为后端组合层委托入口）：解析表格文档(文件路径, 数据模式=True)
→ 通用文档字典；生成表格文档(内容参数dict) → 生成产物字典（字节b64/媒体
类型/摘要）。openpyxl 代码全部收拢在本提供者目录，支持库后端不再直接
触碰 openpyxl。
"""

from __future__ import annotations

from 支持库.适配层.openpyxl提供者.实现.表格文档 import 解析表格文档
from 支持库.适配层.openpyxl提供者.实现.表格文档生成 import 生成表格文档

__all__ = ["解析表格文档", "生成表格文档"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本提供者能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名 in [
        ("表格文档.解析表格文档", 解析表格文档, ["文件路径", "数据模式", "最大工作表数", "最大行数", "最大字节数"]),
        ("表格文档.生成表格文档", 生成表格文档, ["内容参数"]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.openpyxl提供者",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明="openpyxl 表格文档解析/生成提供者能力",
            )
        )
