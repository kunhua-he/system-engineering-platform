"""psycopg 数据库独立提供者包级中文入口。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力：psycopg数据库.连接/查询/事务执行/关闭。
每次调用自包含连接生命周期，连接对象与游标调用后关闭，绝不泄漏；
驱动缺失或目标库不可达时返回统一失败结果，绝不假装连接成功。
"""

from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现

from 支持库.适配层.psycopg提供者.实现.提供者 import 关闭
from 支持库.适配层.psycopg提供者.实现.提供者 import 连接
from 支持库.适配层.psycopg提供者.实现.提供者 import 查询
from 支持库.适配层.psycopg提供者.实现.提供者 import 事务执行

__all__ = ["连接", "查询", "事务执行", "关闭", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
    for 能力id, 函数, 参数表, 返回, 说明 in [
        ("psycopg数据库.连接", 连接,
         [{"名称": "连接串", "类型": "文本"}, {"名称": "超时秒", "类型": "数字"}],
         "结果", "psycopg 连接测试：成功返回 {已连接: true, 提供者版本}"),
        ("psycopg数据库.查询", 查询,
         [{"名称": "连接串", "类型": "文本"}, {"名称": "SQL", "类型": "文本"},
          {"名称": "参数", "类型": "列表"}, {"名称": "超时秒", "类型": "数字"}],
         "结果", "查询：返回 {行列表: [{列名: 值}...]}"),
        ("psycopg数据库.事务执行", 事务执行,
         [{"名称": "连接串", "类型": "文本"}, {"名称": "SQL列表", "类型": "列表"},
          {"名称": "超时秒", "类型": "数字"}],
         "结果", "事务执行：全部成功提交；任一失败回滚"),
        ("psycopg数据库.关闭", 关闭,
         [{"名称": "连接串", "类型": "文本"}, {"名称": "超时秒", "类型": "数字"}],
         "结果", "关闭：本提供者每次调用自包含连接，关闭为空操作"),
    ]:
        注册表.注册(能力实现(
            能力id=能力id,
            包id="支持库.适配层.psycopg提供者",
            实现函数=函数,
            参数=参数表,
            返回=返回,
            说明=说明,
        ))
