"""代码地图提供者包级中文入口（外部命令 codegraph 受管边界）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 代码地图提供者）：
- 检查提供者 → {可执行路径, 版本, 退出码}；未配置 → 提供者不可用
- 查询项目地图状态 → {地图路径, 索引时间, 文件数, 节点数, 边数, 待同步变更}
- 重建项目地图索引 → {重建方式, 耗时秒, 之前规模, 之后规模, 是否刷新}

**传项目根目录即可**：支持对任意项目建/查索引，不写死本仓。
外部命令经独立进程组受管执行：超时强制结束子进程、输出上限截断、异常不伪装成功。
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.适配层.代码地图提供者.实现.提供者 import 检查提供者
from 支持库.适配层.代码地图提供者.实现.提供者 import 查询项目地图状态
from 支持库.适配层.代码地图提供者.实现.提供者 import 重建项目地图索引

__all__ = [
    "检查提供者",
    "查询项目地图状态",
    "重建项目地图索引",
    "注册能力",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 代码地图提供者）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数表, 说明 in [
        ("代码地图提供者.检查提供者", 检查提供者,
         [{"名称": "超时秒", "类型": "双精度数型", "必填": 假, "默认值": 30}],
         "检查 codegraph 外部命令是否可用（真实版本探针），返回版本；缺失 → 提供者不可用"),
        ("代码地图提供者.查询项目地图状态", 查询项目地图状态,
         [{"名称": "项目根目录", "类型": "文本型", "必填": 真, "默认值": None},
          {"名称": "超时秒", "类型": "双精度数型", "必填": 假, "默认值": 120}],
         "只读查询某项目的代码地图索引状态：是否存在、文件/节点/边数量、索引时间、待同步变更数"),
        ("代码地图提供者.重建项目地图索引", 重建项目地图索引,
         [{"名称": "项目根目录", "类型": "文本型", "必填": 真, "默认值": None},
          {"名称": "重建方式", "类型": "文本型", "必填": 假, "默认值": "同步"},
          {"名称": "超时秒", "类型": "双精度数型", "必填": 假, "默认值": 1800}],
         "对指定项目重建/同步代码地图索引（传项目根目录即可），返回同步前后规模，供调用方核实是否真刷新"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.代码地图提供者",
                实现函数=函数,
                参数=参数表,
                返回="结果型",
                说明=说明,
            )
        )
