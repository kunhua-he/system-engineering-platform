__all__ = [
    "检查提供者",
    "探测媒体",
    "提取音频",
    "转码",
    "抽取帧",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 FFmpeg媒体）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("FFmpeg媒体.检查提供者", 检查提供者, [], "检查 ffmpeg/ffprobe 可用性并返回版本"),
        ("FFmpeg媒体.探测媒体", 探测媒体, ["文件路径", "超时秒"], "ffprobe 探测媒体：时长/流/格式"),
        ("FFmpeg媒体.提取音频", 提取音频, ["文件路径", "输出格式", "输出路径", "超时秒", "最大输出字节", "最大时长秒"], "提取首个音频轨（wav/mp3/aac/m4a/ogg/flac）"),
        ("FFmpeg媒体.转码", 转码, ["文件路径", "输出格式", "编码选项", "输出路径", "超时秒", "最大输出字节", "最大时长秒"], "ffmpeg 转码（mp4/mkv/webm/mov/avi）"),
        ("FFmpeg媒体.抽取帧", 抽取帧, ["文件路径", "时间点秒", "输出格式", "输出路径", "超时秒", "最大输出字节", "最大时长秒"], "ffmpeg 抽帧（jpg/png）"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.FFmpeg提供者",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明=说明,
            )
        )
