"""提供者配置读取：读取外部提供者配置，按能力 id 取配置段（提供者层）。

职责边界（2026-09-18 配置双入口收口定性）：提供者配置数据只存
`支持库/适配层/提供者配置/提供者配置.json`（供 `提供者注册表` 路由与
初始化时读取）；本包只负责**把这份外部协议配置读进来、按能力 id 取段**。

它**不**承担全仓统一配置加载：不做多层级合并（支持库默认→项目默认→
环境→提供者→显式覆盖）、不做结构校验与未知项报告、不做来源追踪 ——
那些是**项目门面层** `项目适配层/配置适配/` 的职责。两者是
「提供者层（读第三方/外部协议配置）」与「项目门面层（项目配置加载与
合并）」的分工，不是同一件事的两套实现。
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from 支持库.适配层.提供者配置读取.配置读取工具 import 读取JSON配置


def 读取提供者配置(配置目录: Path | None = None) -> dict[str, Any]:
    """读取提供者配置目录（默认 `支持库/适配层/提供者配置/`）。

    目录或文件缺失返回空字典（不抛异常）：提供者配置是**可选**输入，
    调用方按能力 id 取段，取不到即由调用方走默认/降级，不在此处伪造。
    """
    配置目录 = 配置目录 or Path(__file__).resolve().parents[1] / "提供者配置"
    配置文件 = 配置目录 / "提供者配置.json"
    if not 配置文件.is_file():
        return {}
    return 读取JSON配置(配置文件)


def 获取能力配置(配置: dict[str, Any], 能力id: str) -> dict[str, Any]:
    """获取某能力对应的提供者配置段（无该段返回空字典，返回副本）。"""
    return dict(配置.get(能力id, {}))
