"""Tesseract 提供者包级中文入口（外部命令 tesseract 受管执行）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 OCR识别）：
- 识别图片 → {文本} 或 {词列表}（词级数据，路径/字节二选一）
- 语言包列表 → {语言列表, 数据目录, 数量}
- 版本探针 → {tesseract, 版本, 满足最低版本}
所有 tesseract 调用一律走 受管进程（独立进程组 + 超时/取消/上限/零残留）。
"""

from __future__ import annotations

from 支持库.适配层.Tesseract提供者.实现.提供者 import 识别图片
from 支持库.适配层.Tesseract提供者.实现.提供者 import 语言包列表
from 支持库.适配层.Tesseract提供者.实现.提供者 import 版本探针

__all__ = [
    "识别图片",
    "语言包列表",
    "版本探针",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 OCR识别）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("OCR识别.识别图片", 识别图片,
         ["图片路径", "图片字节", "语言", "词级数据", "超时秒", "取消事件", "输出上限字节"],
         "图片 OCR 识别为文本或词级数据"),
        ("OCR识别.语言包列表", 语言包列表, ["超时秒"], "列出 tesseract 已安装语言包"),
        ("OCR识别.版本探针", 版本探针, ["超时秒"], "探测 tesseract 版本与可用性"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.Tesseract提供者",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明=说明,
            )
        )
