"""PyMuPDF 提供者包级中文入口（fitz 独立子进程边界）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 PDF渲染）：
- 检测加密页数 → {已加密, 页数}
- 渲染整页 → PNG 图像字节（base64）
- 提取图像 → [{xref, 字节b64, 尺寸}]
- 校验PDF → {页数}
主进程绝不 import fitz；fitz 只在 实现/子进程入口.py 的独立子进程中加载。
"""

from __future__ import annotations

from 支持库.适配层.PyMuPDF提供者.实现.提供者 import 检测加密页数
from 支持库.适配层.PyMuPDF提供者.实现.提供者 import 渲染整页
from 支持库.适配层.PyMuPDF提供者.实现.提供者 import 提取图像
from 支持库.适配层.PyMuPDF提供者.实现.提供者 import 校验PDF

__all__ = [
    "检测加密页数",
    "渲染整页",
    "提取图像",
    "校验PDF",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 PDF渲染）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("PDF渲染.检测加密页数", 检测加密页数, ["文件路径", "超时秒"], "检测 PDF 是否加密并返回页数"),
        ("PDF渲染.渲染整页", 渲染整页, ["文件路径", "页序号", "超时秒"], "整页渲染为 PNG 图像字节（base64）"),
        ("PDF渲染.提取图像", 提取图像, ["文件路径", "页序号", "超时秒"], "提取页内嵌入图像列表（xref/字节b64/尺寸）"),
        ("PDF渲染.校验PDF", 校验PDF, ["字节", "超时秒"], "在隔离子进程中重新打开 PDF 返回页数"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.PyMuPDF提供者",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明=说明,
            )
        )
