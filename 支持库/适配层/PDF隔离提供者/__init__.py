"""PDF 隔离提供者包级中文入口（第三方库子进程边界）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力：解析PDF隔离 / 校验PDF隔离 / 检查提供者版本。
主进程不加载 pdfplumber/fitz；第三方库只在隔离子进程中加载。
"""

from __future__ import annotations

from 支持库.适配层.PDF隔离提供者.实现.隔离提供者 import 解析PDF隔离
from 支持库.适配层.PDF隔离提供者.实现.隔离提供者 import 校验PDF隔离
from 支持库.适配层.PDF隔离提供者.实现.隔离提供者 import 检查提供者版本

__all__ = [
    "解析PDF隔离",
    "校验PDF隔离",
    "检查提供者版本",
]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名 in [
        ("PDF隔离提供者.解析PDF", 解析PDF隔离, ["文件路径", "最大页数", "最大字节数", "超时秒"]),
        ("PDF隔离提供者.校验PDF", 校验PDF隔离, ["字节", "超时秒"]),
        ("PDF隔离提供者.检查提供者", 检查提供者版本, ["超时秒"]),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.PDF隔离提供者",
                实现函数=函数,
                参数=[{"名称": 名称, "类型": "任意"} for 名称 in 参数名],
                返回="结果",
                说明="PDF 隔离子进程提供者能力",
            )
        )
