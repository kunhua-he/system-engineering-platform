"""能力调用：密码签名提供者公开能力的主进程侧包装。

七个注册能力都从这里导出（经包级 __init__.py 对外）。生成密钥对/签名/
验证签名/公钥指纹/对称加密/对称解密 通过 提供者管理器.执行任务 走隔离子
进程（cryptography 只在子进程内加载）；内容摘要 纯标准库 hashlib，留在
主进程。本模块绝不 import cryptography。

统一返回 结果（成功=值 / 失败=错误码+错误说明）。各函数可直接调用，
也可传可选关键字 超时秒 覆盖默认 30 秒（注册能力契约不含该参数，
经注册表调用时不传）。
"""

from __future__ import annotations

import base64
import hashlib

from 公共契约.基础类型.结果类型 import 结果
from 支持库.适配层.密码签名提供者.实现 import 提供者管理器


def 生成密钥对(超时秒: float = 提供者管理器.默认超时秒) -> 结果:
    return 提供者管理器.执行任务({"操作": "生成密钥对"}, 超时秒=超时秒)


def 签名(私钥PEM: str, 数据b64: str, 超时秒: float = 提供者管理器.默认超时秒) -> 结果:
    return 提供者管理器.执行任务(
        {"操作": "签名", "私钥PEM": 私钥PEM, "数据b64": 数据b64}, 超时秒=超时秒
    )


def 验证签名(公钥PEM: str, 数据b64: str, 签名hex: str, 超时秒: float = 提供者管理器.默认超时秒) -> 结果:
    return 提供者管理器.执行任务(
        {"操作": "验证签名", "公钥PEM": 公钥PEM, "数据b64": 数据b64, "签名hex": 签名hex},
        超时秒=超时秒,
    )


def 公钥指纹(公钥PEM: str, 超时秒: float = 提供者管理器.默认超时秒) -> 结果:
    """公钥指纹（sha256 前 16 位）；走隔离子进程保持提供者语义一致。"""
    return 提供者管理器.执行任务({"操作": "公钥指纹", "公钥PEM": 公钥PEM}, 超时秒=超时秒)


def 内容摘要(数据b64: str) -> 结果:
    """内容摘要（sha256 完整 hex）；纯标准库 hashlib，留在主进程。"""
    if not isinstance(数据b64, str) or not 数据b64:
        return 提供者管理器._失败("参数不合法", "数据b64 必须是非空文本")
    try:
        数据 = base64.b64decode(数据b64, validate=True)
    except Exception as 错误:
        return 提供者管理器._失败("参数不合法", f"数据b64 不是合法 base64: {错误}")
    return 结果.成功结果(hashlib.sha256(数据).hexdigest())


def 对称加密(明文b64: str, 密钥b64: str, 模式: str = "AES-GCM",
           初始向量b64: str = "", 附加数据b64: str = "",
           超时秒: float = 提供者管理器.默认超时秒) -> 结果:
    """AES 对称加密（GCM 默认 / CBC 可选）；走隔离子进程，主进程零加载 cryptography。"""
    return 提供者管理器.执行任务(
        {
            "操作": "对称加密",
            "明文b64": 明文b64,
            "密钥b64": 密钥b64,
            "模式": 模式,
            "初始向量b64": 初始向量b64,
            "附加数据b64": 附加数据b64,
        },
        超时秒=超时秒,
    )


def 对称解密(密文b64: str, 密钥b64: str, 模式: str = "AES-GCM",
           初始向量b64: str = "", 附加数据b64: str = "",
           超时秒: float = 提供者管理器.默认超时秒) -> 结果:
    """AES 对称解密（GCM 默认 / CBC 可选）；走隔离子进程，主进程零加载 cryptography。"""
    return 提供者管理器.执行任务(
        {
            "操作": "对称解密",
            "密文b64": 密文b64,
            "密钥b64": 密钥b64,
            "模式": 模式,
            "初始向量b64": 初始向量b64,
            "附加数据b64": 附加数据b64,
        },
        超时秒=超时秒,
    )
