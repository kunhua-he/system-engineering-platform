"""模型服务提供者 公开入口（**手写**：注册能力 + 轻导入 + 延迟导出）。

## #96 包化说明

真实实现已从 `支持库/适配层/模型服务.py` 搬到本包 `实现/`；根下平铺件
`支持库/适配层/模型服务.py` 保留为**自举 + 等价再导出**腿 —— `模型连接器` 的
本地启动链按**路径**取用它（`取系统根(__file__) / 支持库/适配层/模型服务.py`），
路径、命令行参数（`--model-path/--model-type/--port/--host`）与对外行为逐字不变。

## 公开面

- 公开能力**只有 1 个**：`模型服务.检查提供者`（本地模型服务运行栈可用性探针，
  只定位不导入，不启动服务、不加载权重）。
- `模型服务` / `创建应用` / `停止服务` / `主程序` 是**内部件**（服务进程入口与
  生命周期函数），**不登记为公开能力**（调用方无法经能力调用入口把 `模型路径`
  传进来，见 说明/设计说明.md）。它们经**模块级 `__getattr__` 延迟导出** ——
  这是刻意的：`实现/模型服务.py` 在模块级 import torch 等原生扩展，
  若在本入口包级 import 它，**任何** `import 支持库.适配层.模型服务提供者` 都会
  把原生扩展拖进主进程，直接推翻「原生扩展不在主进程加载」的既有结论。
  延迟导出让「只查能力」的调用方零代价，让「要起服务」的调用方按需付出代价。

本入口**手写**（含 `def 注册能力`）：能力定义编译器对含注册能力的手写入口
原样保留，不做覆盖（见 `开发工具/契约编译/能力定义编译器.py:_写产物`）。
"""

from __future__ import annotations

from 公共契约.能力契约.契约 import 能力实现

from 支持库.适配层.模型服务提供者.实现.提供者 import 检查提供者

#: 延迟导出的内部件名（都在 `实现/模型服务.py`，该模块 import torch）。
_延迟导出名 = ("模型服务", "创建应用", "停止服务", "主程序")

__all__ = [
    "检查提供者",
    "模型服务",
    "创建应用",
    "停止服务",
    "主程序",
    "注册能力",
]


def __getattr__(名称: str):
    """按需从 `实现/模型服务.py` 取内部件（PEP 562 模块级延迟导出）。"""
    if 名称 in _延迟导出名:
        from 支持库.适配层.模型服务提供者.实现 import 模型服务 as _实现

        return getattr(_实现, 名称)
    raise AttributeError(f"module {__name__!r} has no attribute {名称!r}")


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力。"""
    注册表.注册(
        能力实现(
            能力id="模型服务.检查提供者",
            包id="支持库.适配层.模型服务提供者",
            实现函数=检查提供者,
            参数=[],
            返回="结果型",
            说明="检查本机本地模型服务运行栈（torch/transformers/fastapi/uvicorn）是否齐备（真实探针：只定位不导入）；缺件 → 提供者不可用",
        )
    )
