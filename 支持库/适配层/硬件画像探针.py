def _读取磁盘可用() -> int:
    """磁盘可用字节：锚点目录的可用空间。

    锚点是**本文件所在系统根的上一级**（`....parents[…]`），不是 `os.getcwd()` ——
    工作目录会被调用方进程改变（网关从别的 cwd 起来是常态），拿 cwd 当锚点会让
    「磁盘可用」随调用方漂移，测出来的不是系统盘。取不到一律 0（未知）。
    """
    from pathlib import Path

    锚点 = Path(__file__).resolve().parents[3]  # 支持库/适配层/本文件 → 系统根（parents[2]）的上一级
    if not 锚点.is_dir():
        锚点 = Path(__file__).resolve().parent
    try:
        return int(shutil.disk_usage(str(锚点)).free)
    except OSError:
        return 0


