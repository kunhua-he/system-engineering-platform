"""TreeSitter提供者 包级中文入口（第三方 tree-sitter 边界）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 代码语法）：
- 解析语法树 → 底座中性语法树（根节点）
- 检查可用性 → 依赖可用性探针
"""

from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真, 假

from 支持库.适配层.TreeSitter提供者.实现.提供者 import 解析语法树
from 支持库.适配层.TreeSitter提供者.实现.提供者 import 检查可用性
from 支持库.适配层.TreeSitter提供者.实现.提供者 import TreeSitter解析错误
from 支持库.适配层.TreeSitter提供者.实现.提供者 import 停止

__all__ = ["解析语法树", "检查可用性", "TreeSitter解析错误", "停止", "注册能力"]

支持的语言集 = ("typescript", "tsx")


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本提供者能力。"""
    from 公共契约.能力契约.契约 import 能力实现
    from 公共契约.基础类型.结果类型 import 结果

    def 解析语法树能力(代码文本: str, 语言: str = "typescript"):
        """能力边界：按契约返回结果型；依赖不可用/解析失败如实报错，不静默降级。"""
        if not isinstance(代码文本, str):
            return 结果.失败("参数不合法", "代码文本 必须是字符串", 来源="TreeSitter提供者")
        if 语言 not in 支持的语言集:
            return 结果.失败(
                "参数不合法", f"语言 必须是 {' 或 '.join(支持的语言集)}，收到 {语言!r}",
                来源="TreeSitter提供者")
        try:
            return 结果.成功结果(解析语法树(代码文本, 语言))
        except TreeSitter解析错误 as 错误:
            return 结果.失败("提供者不可用", f"tree-sitter 不可用: {错误}", 来源="TreeSitter提供者")
        except Exception as 错误:
            return 结果.失败(
                "解析失败", f"tree-sitter 解析异常: {type(错误).__name__}: {错误}",
                来源="TreeSitter提供者")

    def 检查可用性能力():
        """探针能力：依赖不可用时如实报告（不伪装可用）。"""
        try:
            return 结果.成功结果(检查可用性())
        except Exception as 错误:
            return 结果.失败("依赖不可用", f"tree-sitter 探针异常: {错误}", 来源="TreeSitter提供者")
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 缺陷溯源：本入口原先手工重建注册参数声明（`参数=...` 手写字面量），只写 名称/类型/必填，
    # `默认值` 整批缺声明（2026-09-24 实测：本包 2 条契约参数中 1 条漏声明，
    # 全仓 93 条）。后果：网关按入口契约表判参时拿不到默认值 —— 「≥10 秒须走异步腿」的守卫
    # 对 超时秒≥10 的能力**不传参即被绕过**（实测 执行命令/沙箱执行命令/发送请求 等 9 条）；
    # 其余能力的默认值同样在网关侧不可见。
    # 手工表一旦漏一个参数，新参数还会被网关**静默丢弃**（同族现场见未完成事项 #197）。
    # 修法：参数声明从 `能力契约/参数契约.json` **整条透传**，入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：漂移检测的 AST 读取器
    # （`_静态字面量` 的 `ast.Subscript` 分支）只收 `注册能力` 函数体内的赋值，
    # 包一层 `_参数声明(能力id)` 会让 AST 一律判「不可静态判定」，等于拿门禁覆盖率换干净。
    # 表内布尔位写中文 真/假（真源 公共契约/基础类型/逻辑类型.py）。
    # 契约名序/返回口径核验由装配期唯一闸门承担（`运行核心/加载器/生命周期管理/管理器.装配系统`
    # → 内核 `能力注册表.校验声明一致`），本入口不再另立第二份。
    _参数契约表 = {
        "适配层.TreeSitter提供者.解析语法树": [
            {"名称": "代码文本", "类型": "文本型", "必填": 真, "默认值": None},
            {"名称": "语言", "类型": "文本型", "必填": 假, "默认值": "typescript"},
        ],
        "适配层.TreeSitter提供者.检查可用性": [
        ],
    }
# ===== 参数声明透传 结束 =====

    for 能力id, 函数, 说明 in [
        ("适配层.TreeSitter提供者.解析语法树", 解析语法树能力, "把 TypeScript/TSX 源码解析为底座中性语法树（中文种类与中文字段名）"),
        ("适配层.TreeSitter提供者.检查可用性", 检查可用性能力, "探针：报告 tree-sitter 依赖可用性与版本"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.TreeSitter提供者",
                实现函数=函数,
                参数=_参数契约表[能力id],
                返回="结果",
                说明=说明,
            )
        )
