"""系统探针提供者 的能力实现：`系统探针.检查提供者`（提供者自身可用性真实探针）。

**探针口径（真实探针，不是常量冒充）**：

1. psutil 是本提供者的**唯一**第三方依赖（系统内存读取），落 依赖锁.json；
2. 探针**真读一次** `psutil.virtual_memory()` —— 只「import 成功」不算可用：
   import 成但取用失败时 `读取系统内存` 会返回 可用=假，此处如实判不可用；
3. 不可用 → 结果.失败("提供者不可用")，不伪造版本、不返回桩值（fail-closed）。

**为什么不把 `检查系统工具`（外部工具独立进程探针）并入本能力**：它不依赖任何
第三方（只起子进程），被探工具自身的可用性由**被探工具的提供者**负责 ——
`LibreOffice提供者` / `textutil提供者` 的生命周期契约里各自有真实探针。
把两者并成一个能力，会让「系统探针提供者挂了」与「soffice 没装」两个不同
事实共用一个错误码。
"""

from __future__ import annotations

import importlib.metadata as _发行包元数据

from 公共契约.基础类型.逻辑类型 import 真
from 公共契约.基础类型.结果类型 import 结果

from 支持库.适配层.系统探针提供者.实现.系统探针 import 读取系统内存

#: 可重试错误码：提供者不可用（psutil 缺失/取用失败）属环境态，可重试。
可重试错误码 = ("提供者不可用",)


def _失败(错误码: str, 消息: str) -> 结果:
    """统一失败信封（错误码必须是网关公开错误码状态映射里的码）。"""
    return 结果.失败(错误码, 消息, 来源="系统探针提供者",
                    可重试=错误码 in 可重试错误码)


def 检查提供者() -> 结果:
    """检查系统探针提供者是否可用（真实探针：真读一次系统内存）。

    返回：结果型；成功时 值 = {可用, 探针, 版本, 内存总量字节, 内存可用字节,
    内存占用率}；psutil 缺失或取用失败 → 失败("提供者不可用") + 真实原因。
    """
    快照 = 读取系统内存()
    if not 快照.可用:
        return _失败("提供者不可用", 快照.不可用原因 or "psutil 不可用，无法读取系统内存")
    try:
        版本 = _发行包元数据.version("psutil")
    except Exception:  # 发行包元数据读不到不影响「可用」判定，如实留空
        版本 = ""
    return 结果.成功结果({
        "可用": 真,
        "探针": "psutil 系统内存读取",
        "版本": 版本,
        "内存总量字节": 快照.总量字节,
        "内存可用字节": 快照.可用字节,
        "内存占用率": 快照.占用率,
        "说明": 快照.说明,
    })
