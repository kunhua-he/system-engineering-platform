"""系统级提供者健康探针原语：独立子进程检查外部应用/系统工具 + 系统内存汉化原子能力。

**落点（#96 包化后）**：本件是 `支持库/适配层/系统探针提供者/` 的实现载体。
对外入口仍是 `支持库.适配层.系统探针`（根下平铺件保留，做自举 + 等价再导出），
调用方**不需要**改一行 import；能力 id 与函数签名与包化前逐字一致。

LibreOffice（soffice）与 textutil（macOS 系统工具）不是 pip 包，
没有独立 venv 可做 import 校验；健康检查必须真实启动独立子进程
执行版本/帮助参数，带回 退出码/版本信息/标准错误摘要/耗时。

探针四要素：超时、退出码、版本信息、标准错误摘要。
隔离性：探针在独立子进程（新会话）运行，超时 terminate→kill 强杀；
任何失败都收敛为 探针结果 返回，绝不向调用方抛异常拖垮主进程。
不可用语义：工具缺失/探针超时/退出码非0 → 成功=假 + 明确错误码；
提供者入口统一映射为「外部提供者不可用」。

系统内存（`读取系统内存`）：psutil 是**唯一**系统内存读取实现，且只在适配层
出现（支持库经本能力的汉化返回值取真值，不得直连第三方）。本函数仍是本提供者的
**内部原语**——它不单独登记为公开能力（公开能力只有 `系统探针.检查提供者` 一个，
见 能力定义.json），只由 模型连接器 / 硬件画像探针 经 支持库.适配层.系统探针 取用。

第三方依赖：psutil 一项，落 `依赖锁.json`（第三方库），并进依赖生命周期审计。
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.运行时.有界IO import 受限通信, 默认子进程输出上限字节
from 公共契约.运行时 import 平台适配, 进程终止

try:
    import psutil
except Exception:  # pragma: no cover - 环境无 psutil 时降级为「探针不可用」
    psutil = None


版本行最大长度 = 200
标准错误摘要最大长度 = 300
终止宽限秒 = 1.0

#: 探针**内部信封码**（不跨唯一网关，故不在公开错误码状态映射里）。
#: 为什么写成模块常量而不是散写字面量：`探针超时`/`退出码非零` 是适配层内部码，
#: 网关的 `公开错误码状态映射` 只登记 HTTP 面的码（362 个），把这两个塞进去
#: 等于把内部码污染成对外可调用结果；而调用方（健康监督 / 环境指纹 / 文档转换）
#: 只消费 `探针结果.错误码` 这个**值字段**，不拿它当状态码。
#: 与 `密钥提供者/密钥提供者.py` 的 `错误码_钥匙串不可用` 同形制：常量表达 +
#: 说明书如实写明（见 说明/设计说明.md「内部信封码」一节）。
错误码_探针超时 = "探针超时"
错误码_退出码非零 = "退出码非零"


@dataclass(frozen=True)
class 探针结果:
    """系统工具独立进程探针结果（成功=假 时不抛异常，只返回结果）。

    统一字段：成功/错误码/退出码/版本/标准错误摘要/耗时秒/诊断/
    错误摘要/可重试；失败不伪造版本，错误码 工具缺失/探针超时/退出码非零 明确。
    """

    成功: bool
    错误码: str = ""           # 参数不合法/工具缺失/探针超时/退出码非零
    退出码: int | None = None  # 子进程退出码（成功为 0；超时/缺失为 None）
    版本: str = ""             # 版本信息（成功时取输出首行的版本号）
    标准错误摘要: str = ""     # 标准错误截断摘要
    耗时秒: float = 0.0
    诊断: str = ""
    可重试: bool = 假          # 探针超时等暂态失败 → 可重试
    错误摘要: str = ""         # 统一错误摘要（失败时=诊断 or 标准错误摘要；成功为空）

    def __post_init__(self) -> None:
        # 成功时错误摘要恒为空；失败未显式提供时由 诊断/标准错误摘要 派生
        if self.成功:
            object.__setattr__(self, "错误摘要", "")
        elif not self.错误摘要:
            object.__setattr__(self, "错误摘要", self.诊断 or self.标准错误摘要)


def 检查系统工具(名称: str, 命令列表: list[str], *, 超时秒: float = 5.0,
               版本参数: str = "--version") -> 探针结果:
    """独立子进程健康探针：执行 命令列表+版本参数，返回 探针结果。

    参数：
        名称：工具显示名（用于诊断信息）。
        命令列表：可执行文件路径与前置参数（可执行文件缺省由 PATH 解析）。
        超时秒：探针最大耗时（正数，超时 terminate→kill）。
        版本参数：版本探测参数（默认 --version，可传 -help 等）。
    返回：探针结果（成功/退出码/版本/标准错误摘要/耗时秒/诊断）；
    失败不抛异常，主进程不受影响。
    """
    if not isinstance(名称, str) or not 名称.strip():
        return 探针结果(假, 错误码="参数不合法", 诊断="名称必须是非空文本")
    if (not isinstance(命令列表, list) or not 命令列表
            or not all(isinstance(项, str) and 项.strip() for 项 in 命令列表)):
        return 探针结果(假, 错误码="参数不合法", 诊断="命令列表必须是非空文本列表")
    if (not isinstance(超时秒, (int, float)) or isinstance(超时秒, bool) or 超时秒 <= 0):
        return 探针结果(假, 错误码="参数不合法", 诊断="超时秒必须是正数")
    if not isinstance(版本参数, str) or not 版本参数.strip():
        return 探针结果(假, 错误码="参数不合法", 诊断="版本参数必须是非空文本")
    可执行 = 命令列表[0]
    可执行路径 = _解析可执行(可执行)
    if not 可执行路径:
        return 探针结果(假, 错误码="工具缺失",
                         诊断=f"未找到 {名称}（{可执行} 不在 PATH 或路径不存在）")
    开始 = time.monotonic()
    try:
        进程 = subprocess.Popen(
            list(命令列表) + [版本参数],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            **平台适配.子进程组启动标志(),
        )
    except OSError as 错误:
        return 探针结果(假, 错误码="工具缺失",
                         诊断=f"无法启动 {名称}: {错误}")
    try:
        标准输出, 标准错误, 已超时, 已超限 = 受限通信(
            进程, 超时秒=超时秒, 输出上限字节=默认子进程输出上限字节,
            终止回调=lambda: 进程终止.结束并留痕(
                进程, 位置="系统探针提供者.检查系统工具", 宽限秒=终止宽限秒,
                等待秒=终止宽限秒),
        )
        if 已超时:
            return 探针结果(
                假, 错误码=错误码_探针超时, 耗时秒=time.monotonic() - 开始,
                诊断=f"{名称} 探针超时（> {超时秒} 秒），已强制终止",
                可重试=真,
            )
        退出码 = 进程.returncode
        耗时秒 = time.monotonic() - 开始
        错误摘要 = _标准错误摘要(标准错误)
        if 退出码 != 0:
            return 探针结果(
                假, 错误码=错误码_退出码非零, 退出码=退出码,
                标准错误摘要=错误摘要, 耗时秒=耗时秒,
                诊断=f"{名称} 退出码 {退出码}",
            )
        输出文本 = _解码(标准输出) or _解码(标准错误)
        return 探针结果(
            真, 退出码=0, 版本=_提取版本(输出文本),
            标准错误摘要=错误摘要, 耗时秒=耗时秒,
            诊断=f"{名称} 探针成功",
        )
    finally:
        if 进程.poll() is None:
            进程终止.结束并留痕(
                进程, 位置="系统探针提供者.检查系统工具", 宽限秒=终止宽限秒,
                等待秒=终止宽限秒)


# ── 系统内存（汉化原子能力）─────────────────────────────

内存探针不可用原因 = "psutil 不可用，无法读取系统内存"


@dataclass(frozen=True)
class 系统内存快照:
    """系统内存快照（汉化原子返回；字段按类型目录正式类型的 Python 载体）。

    可用=逻辑型；总量字节/可用字节/已用字节=长整数型；占用率=双精度数型；
    说明/不可用原因=文本型。探针不可用时 可用=假 + 不可用原因 说明原因，
    不伪造内存数字（失败不冒充成功）。
    """

    可用: bool
    总量字节: int = 0
    可用字节: int = 0
    已用字节: int = 0
    占用率: float = 0.0
    说明: str = ""
    不可用原因: str = ""


def 读取系统内存() -> 系统内存快照:
    """读取系统真实内存：总量/可用/已用/占用率（汉化原子能力）。

    psutil 是唯一实现细节，只在适配层出现；支持库经本能力的返回值取真值，
    不得直接 import 第三方。探针不可用（未安装/取用异常）时返回 可用=假 的
    快照 + 不可用原因，由调用方决定降级策略，本能力不抛异常。
    """
    if psutil is None:
        return 系统内存快照(可用=假, 不可用原因=内存探针不可用原因)
    try:
        内存 = psutil.virtual_memory()
        总量字节 = int(内存.total)
        可用字节 = int(内存.available)
        已用字节 = int(内存.used)
    except Exception as 错误:  # 平台取用失败一律降级为「探针不可用」，不抛给调用方
        return 系统内存快照(可用=假, 不可用原因=f"psutil 读取系统内存失败: {错误}")
    return 系统内存快照(
        可用=真, 总量字节=总量字节, 可用字节=可用字节, 已用字节=已用字节,
        占用率=round(float(内存.percent), 1),
        说明=(f"总 {总量字节/1024**3:.1f}GB / 可用 {可用字节/1024**3:.1f}GB"
              f" / 占用 {内存.percent:.0f}%"),
    )


def _解析可执行(可执行: str) -> str | None:
    """可执行路径解析：含路径分隔符按文件校验，否则按 PATH 查找。"""
    if os.path.sep in 可执行 or 可执行.startswith("~"):
        路径 = Path(可执行).expanduser()
        return str(路径) if 路径.is_file() else None
    return shutil.which(可执行)


def _解码(字节: bytes | None) -> str:
    """字节转文本（替换非法序列，去首尾空白）。"""
    if not 字节:
        return ""
    return 字节.decode("utf-8", errors="replace").strip()


def _提取版本(文本: str) -> str:
    """从输出首行提取版本信息：优先数字点序列（如 26.2.2.2），
    无版本号时返回首行清洗文本（textutil -help 类输出）。"""
    if not 文本:
        return ""
    首行 = next((行 for 行 in 文本.splitlines() if 行.strip()), "").strip()
    匹配 = re.search(r"\d+(?:\.\d+)+", 首行)
    return (匹配.group(0) if 匹配 else 首行)[:版本行最大长度]


def _标准错误摘要(标准错误: bytes | None) -> str:
    """标准错误截断摘要（单行化，超长截断）。"""
    if not 标准错误:
        return ""
    文本 = 标准错误.decode("utf-8", errors="replace").strip()
    return " | ".join(行.strip() for 行 in 文本.splitlines() if 行.strip())[
        :标准错误摘要最大长度
    ]
