"""pdfplumber 独立提供者实现：PDF → 平台通用文档字典（文本块/表格块）。

pdfplumber 为纯 Python 库，主进程直接 import（缺库 → 提供者不可用）；
解析超时通过工作线程 join 强约束（超时 → 超时，可重试）；稳定错误码：
文件不存在/参数不合法/提供者不可用/文件损坏/文件加密/超出限制/超时。

资源口径（三处一律有界，且都有读取方）：

1. **超时值必须真校验**：`超时秒` 必须是**大于 0 的有限数字**（`math.isfinite`），
   且**不得超过 `threading.TIMEOUT_MAX`**（标准库 join/wait 的硬上限），
   否则按 参数不合法 明确失败。旧写法只判类型，实测三种穿透：`0` 与负数被
   `max(超时秒, 0.0)` 抹平后静默返回「超时」（把调用方的无效配置说成任务超时），
   `float("inf")` 直接让 `Thread.join()` 抛 `OverflowError` 穿透错误边界。
   补 `isfinite` 后仍有**两类非静默即泄漏的穿透**（2026-09-18 现场实测）：
   `1e300` / `1e10` 是有限正数、过得了 `isfinite`，但都大于 `TIMEOUT_MAX`，
   `join()` 抛 `OverflowError` —— **且此时工作线程已经起来了**：异常穿透
   错误边界，线程在下无超时记录、无错误结果地继续跑（最坏形态的静默泄漏）；
   `10**400` 这种超大整数在 `float()` 转换那一步就抛 `OverflowError`。
   故本函数把「转浮点」「isfinite」「> 0」「≤ `TIMEOUT_MAX`」四处判据一并做足，
   任一不满足一律返回 None（调用方判 参数不合法），不放异常穿透。
2. **超时后不留无界线程**：join 到点即发出**协作式取消**（`threading.Event`，
   经 `_取消登记表` 按线程名绑定），解析在**页边界**检测取消并提前退出，随后只在
   **有界**的 `线程收尾等待秒` 内等待收敛。终态如实登记进有界的 `_超时线程记录`，
   并经 超时 结果的 `结果.详细信息["线程"]` 返回调用方。Python 不能强杀线程，
   故「收尾等待内仍未退出」的极端情形**如实记录、不假装回收**（口径同
   `运行核心/能力调用/超时执行.py`：注册一个杀不掉线程的回收器才是撒谎）。
   并发解析线程数由 `取消登记上限` 硬约束，超出即 超出限制 拒绝开工；
   **槽位只在「线程真退出」时归还**——旧写法见取消事件置位就回收槽位，
   而置位只代表「已请求取消」，不能强杀的线程照样活着：实测 9 条并发挂起的
   解析线程都拿到了槽位，`取消登记上限` 形同虚设、活线程依旧无界增长。
   改按 `threading.enumerate()` 核「该线程名是否真还活着」后，硬上限约束的是
   **活着的**线程数（线程退出时在 `_提取工作` 的 finally 里自己注销）。
3. **关闭失败登记有界且接上读取方**：`_关闭失败记录` 是
   `deque(maxlen=关闭失败记录上限)`；本次调用的关闭失败**同时追加进本次解析结果的
   `诊断` 字段**——该字段由 `模块库/文档解析`（`诊断=值.get("诊断") or []`）与
   `支持库/后端/办公文档支持库/PDF文档`（`诊断=字典.get("诊断", [])`）实际读取，
   是现行真读取方；另有只读 `关闭失败摘要()` 供诊断与测试。旧写法是**无界 list
   且全仓 0 读取方**（只写不读的死登记）。
4. **「线程有界」必须按进程真线程数取证，不能只看自己的登记表**（2026-09-18 实测补齐）：
   上面第 2 条的 `取消登记上限` 约束的是**本包登记过的**工作线程，而
   `threading.enumerate()` 里还存在**不由本包登记**的线程——解析库自身在解析期间
   起的线程就是典型。实测（替换库为会在解析中起线程的替身，连续 20 次「超时」调用）：
   进程线程数 1 → 21 逐轮增长、20 条库内部线程全部仍活着，而 `取消登记摘要()` 的
   `存活条数` **始终为 0** —— 也就是说，这类残留**既不受上限约束，也不被任何只读
   视图暴露**，「线程无界」在这条路径上依然成立。故本模块补 `真线程快照()`
   （进程真线程视图，含 `超预算` 判据，上限取自本包 `资源预算.json` 声明的
   `线程上限`），并把它写进 超时 结果的 `结果.详细信息` 与有界的 `_超时线程记录`，
   让「超时后线程数回到基线」这条例据**可由包自身单次调用取证**，不必外部 `ps`。
   本包不假装能强杀库内部线程（同第 2 条口径：如实登记、不假装回收）。
"""

