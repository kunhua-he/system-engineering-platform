# 关闭失败登记：有界 + 接上读取方（旧写法无界且 0 读取方）
# ═══════════════════════════════════════════════════════════════════
def _记录关闭失败(关闭错误: Exception) -> str:
    """有界登记一次关闭失败，返回本次记录文本（调用方接进结果 诊断 = 真读取方）。"""
    global _关闭失败总数
    文本 = str(关闭错误) or type(关闭错误).__name__
    with _关闭失败锁:
        _关闭失败记录.append(文本)
        _关闭失败总数 += 1
    return 文本

def 关闭失败摘要() -> dict[str, Any]:
    """关闭失败登记的有界只读视图（供诊断/测试；不注册为能力，故不进 `__all__`）。"""
    with _关闭失败锁:
        return {
            "在册条数": len(_关闭失败记录),
            "上限": 关闭失败记录上限,
            "累计条数": _关闭失败总数,
            "最近记录": list(_关闭失败记录),
        }

# ═══════════════════════════════════════════════════════════════════
# 协作式取消登记：线程名 → 取消事件（有界准入 + 线程自身注销）
# ═══════════════════════════════════════════════════════════════════
def _线程仍存活(线程名: str) -> bool:
    """该线程名对应的线程是否**真的还活着**（按 OS 线程状态判，不按取消事件判）。

    尚未 `start()` 的登记（`已启动=False`）视为存活 —— 否则并发调用会在
    「已登记、还没起来」的几微秒窗口里把它当死线程回收，槽位就又管不住了。
    """
    登记 = _取消登记表.get(线程名)
    if 登记 is None:
        return False
    if not 登记["已启动"]:
        return True
    return bool(登记["线程"].is_alive())

def _清理已结束取消() -> None:
    """回收**线程已确实退出**的登记腾位。

    判据必须是「线程真死了」，不是「取消事件已置位」：置位只代表调用方已请求取消，
    而 Python 不能强杀线程，挂住的线程照样在跑。旧写法按置位回收，等于「已请求取消」
    就让出并发槽位 —— `取消登记上限` 于是管不住**活着的**线程数（见模块 docstring
    第 2 条实测：9 条并发挂起的解析线程全部拿到槽位）。
    调用方须已持 `_取消登记锁`。
    """
    for 名 in [名 for 名 in list(_取消登记表) if not _线程仍存活(名)]:
        _取消登记表.pop(名, None)

def _登记取消(线程名: str, 事件: threading.Event) -> bool:
    """登记取消事件（`已启动=False`，待 `_标记线程已启动()` 转真）。

    返回 False＝**仍存活**的并发解析线程已达硬上限（拒绝开工）。
    """
    with _取消登记锁:
        if len(_取消登记表) >= 取消登记上限:
            _清理已结束取消()
        if len(_取消登记表) >= 取消登记上限:
            return False
        _取消登记表[线程名] = {"事件": 事件, "线程": None, "已启动": False}
        return True

def _标记线程已启动(线程名: str, 工作线程: threading.Thread) -> None:
    """`Thread.start()` 成功后把线程句柄接进登记，此后本条目按真实存活状态参与清理。"""
    with _取消登记锁:
        登记 = _取消登记表.get(线程名)
        if 登记 is not None:
            登记["线程"] = 工作线程
            登记["已启动"] = True

def _注销取消(线程名: str) -> None:
    with _取消登记锁:
        _取消登记表.pop(线程名, None)

def _取消已请求() -> bool:
    """当前工作线程是否已被调用方请求取消（页边界检测点）。"""
    线程名 = threading.current_thread().name
    with _取消登记锁:
        登记 = _取消登记表.get(线程名)
        事件 = 登记["事件"] if 登记 is not None else None
    return bool(事件 is not None and 事件.is_set())

def _下一个解析序号() -> int:
    global _解析序号
    with _序号锁:
        _解析序号 += 1
        return _解析序号

# ═══════════════════════════════════════════════════════════════════
# 超时线程终态：有界登记 + 随超时结果返回（超时后线程终态的取证方式）
# ═══════════════════════════════════════════════════════════════════
def _登记超时线程(线程名: str, 仍在运行: bool, 超时秒: float, 开始时刻: float,
                  真线程: dict[str, Any] | None = None) -> dict[str, Any]:
    """登记一次超时后的线程终态（有界），返回该条记录供结果详情携带。

    `真线程` 是超时时点的进程真线程快照（含未登记线程），一并入册 ——
    只记本包线程名会让「线程有界」取证看不到库内部线程留下的残留。
    """
    global _超时线程总数
    记录 = {
        "线程名": 线程名,
        "超时秒": 超时秒,
        "已运行秒": round(max(0.0, time.monotonic() - 开始时刻), 3),
        "取消信号": "已发出",
        "协同收尾秒": 线程收尾等待秒,
        "仍在运行": 仍在运行,
        "终态": "仍在运行（不可强杀，如实登记，不假装回收）" if 仍在运行 else "已退出（协作取消在收尾等待内收敛）",
        "真线程": 真线程 or {},
    }
    with _超时线程锁:
        _超时线程记录.append(记录)
        _超时线程总数 += 1
    return 记录

def 超时线程摘要() -> dict[str, Any]:
    """超时线程终态登记的有界只读视图（供诊断/测试）。"""
    with _超时线程锁:
        return {
            "在册条数": len(_超时线程记录),
            "上限": 超时线程记录上限,
            "累计条数": _超时线程总数,
            "最近记录": list(_超时线程记录),
        }

def 取消登记摘要() -> dict[str, Any]:
    """协作取消登记表的有界只读视图。

    「在册线程名」= 本包当前**仍活着**的解析线程（含已请求取消、但不可强杀而
    尚未退出的），是并发闸门实际约束的对象；`存活条数` 与之等值，`在册条数`
    另报未清理的历史条目数（二者不等说明有待下一次准入时清理）。
    """
    with _取消登记锁:
        存活 = [名 for 名 in _取消登记表 if _线程仍存活(名)]
        return {"在册条数": len(_取消登记表), "存活条数": len(存活), "上限": 取消登记上限,
                "在册线程名": sorted(_取消登记表), "存活线程名": sorted(存活)}

# ═══════════════════════════════════════════════════════════════════
# 进程真线程视图：把「线程数是否回到基线」变成包内可取证的事实
# ═══════════════════════════════════════════════════════════════════
def 真线程快照() -> dict[str, Any]:
    """当前进程的**真线程**只读视图（`threading.enumerate()`），含超预算判据。

    为什么必须有它：`取消登记摘要()` 只看得见**本包登记过**的工作线程，而
    `threading.enumerate()` 里还有不由本包登记的线程（解析库自身在解析期间起的线程
    即典型）。实测（2026-09-18，替身库在解析中起线程，连续 20 次超时调用）：

    - 进程线程数 1 → 21 逐轮增长、20 条替身库内部线程全部仍活着；
    - 而 `取消登记摘要()['存活条数']` **始终为 0**。

    即：那类残留**既不受 `取消登记上限` 约束，也不被任何只读视图暴露** ——
    只看自己的登记表会把「线程无界」谎报成「线程有界」。本视图把判据放回进程真状态，
    上限取本包 `资源预算.json` 声明的 `线程上限`（与 `取消登记上限` 同源，不自定新数）。

    `判定口径` 字段如实区分两种情形：**执行期间**进程存在本包登记的工作线程，此时
    `超预算` 判的是「登记线程 ≤ 上限」；**空闲期间**（无在册登记线程）`超预算` 判的是
    「进程线程数 ≤ 上限」，也就是把「超时后回到基线」这条例据直接变成可读事实。
    本视图**只读不清理**：Python 不能强杀线程，如实报数、不假装回收。
    """
    全部 = threading.enumerate()
    with _取消登记锁:
        登记名 = set(_取消登记表)
    登记线程 = [线程 for 线程 in 全部 if 线程.name in 登记名]
    未登记 = [线程 for 线程 in 全部 if 线程.name not in 登记名]
    在册 = len(登记线程)
    if 在册:
        超预算 = 在册 > 取消登记上限
        口径 = f"执行期间：本包在册解析线程 {在册} 对上上限 {取消登记上限}"
    else:
        超预算 = len(全部) > 取消登记上限
        口径 = f"空闲期间：进程真线程 {len(全部)} 对上上限 {取消登记上限}"
    return {
        "进程线程数": len(全部),
        "在册解析线程数": 在册,
        "未登记线程数": len(未登记),
        "未登记线程名": sorted(线程.name for 线程 in 未登记),
        "上限": 取消登记上限,
        "超预算": 超预算,
        "判定口径": 口径,
        "视图": "threading.enumerate()（进程真线程，含不由本包登记的线程）",
    }

