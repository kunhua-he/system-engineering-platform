"""pdfplumber 提供者包级中文入口（纯 Python 主进程导入）。

调用者只从此入口导入，禁止深入 实现/ 目录。
公开能力（分组 PDF文本表格）：
- 解析PDF → 通用文档字典（文本块/表格块）
- 提取表格 → 指定页表格数据（二维数组）
pdfplumber 为纯 Python 库，主进程直接导入；缺库 → 提供者不可用。
"""

from __future__ import annotations

from 支持库.适配层.pdfplumber提供者.实现.PDF文本表格 import 解析PDF
from 支持库.适配层.pdfplumber提供者.实现.PDF文本表格 import 提取表格

__all__ = ["解析PDF", "提取表格", "注册能力"]


def 注册能力(注册表) -> None:
    """由支持库加载器调用，向能力注册表注册本库能力（分组 PDF文本表格）。"""
    from 公共契约.能力契约.契约 import 能力实现

    for 能力id, 函数, 参数名, 说明 in [
        ("PDF文本表格.解析PDF", 解析PDF,
         [{"名称": "文件路径", "类型": "文本", "必填": True, "默认值": None},
          {"名称": "最大页数", "类型": "整数", "必填": False, "默认值": 500},
          {"名称": "最大字节数", "类型": "整数", "必填": False, "默认值": 209715200},
          {"名称": "超时秒", "类型": "数字", "必填": False, "默认值": 60}],
         "pdfplumber 解析 PDF：文本块/表格块 → 通用文档字典；加密检测/页数大小上限"),
        ("PDF文本表格.提取表格", 提取表格,
         [{"名称": "文件路径", "类型": "文本", "必填": True, "默认值": None},
          {"名称": "页序号", "类型": "整数", "必填": True, "默认值": None}],
         "提取指定页表格数据（二维数组）"),
    ]:
        注册表.注册(
            能力实现(
                能力id=能力id,
                包id="支持库.适配层.pdfplumber提供者",
                实现函数=函数,
                参数=参数名,
                返回="结果",
                说明=说明,
            )
        )
