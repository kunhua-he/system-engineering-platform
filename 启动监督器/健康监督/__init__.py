def __getattr__(名称: str):
    """回落到同名平铺模块 `启动监督器/健康监督.py`（惰性，不预加载）。

    包目录与同名平铺文件并存时**包优先**，那个文件是「系统提供者周期探针 + 读取
    健康监督配置」的唯一语义实现；这里只把它的公开名字透出来，保住既有调用方与
    测试的导入，不复制它的逻辑（装载细节见 实现/兼容平铺模块.py）。
    """
    if 名称.startswith("__"):
        raise AttributeError(名称)
    from 启动监督器.健康监督.实现.兼容平铺模块 import 取平铺模块

    模块 = 取平铺模块()
    try:
        return getattr(模块, 名称)
    except AttributeError:
        raise AttributeError(f"模块 {__name__} 没有属性 {名称}") from None



def _校验参数名序(参数契约表: dict[str, list[dict]],
                  注册参数名序: dict[str, list[str]]) -> None:
    """装配期闸门：注册参数名序必须逐字等于契约名序，否则本包装配失败。

    为什么要有它：注册处一旦漏一个参数（或顺序写反），网关的必填校验就与契约分叉
    ——那正是本包 2026-09-18 被修掉的缺陷形态。宁可装配期就 raise，也不静默漏参。
    """
    for 能力id, 契约参数 in 参数契约表.items():
        注册名序 = 注册参数名序.get(能力id)
        if 注册名序 is None:
            raise ValueError(f"能力 {能力id} 有契约但注册处未声明参数名序")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(注册名序):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(注册名序)} 与契约参数名序 {契约名序} "
                "不一致：参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），"
                "入口不得另立一份")

def 注册能力(注册表) -> None:
    """由加载器调用，注册本包公开能力（能力数：2；参数口径：执行健康监督(基线、临时目录), 查询健康检查项()）。"""
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 参数契约镜像（**函数内字面量**；本块由「丢参」缺陷修复注入，勿删）
    #
    # 缺陷溯源（2026-09-18）：本入口原先手工重建注册参数声明（只写 名称/类型），把
    # `必填` 丢掉；而网关唯一校验点 `运行核心/统一网关/类型规格.py` 的判据是
    # `项.get("必填") is 真` → `None is 真` = 假 → 必填校验静默失效：少传参数不再被
    # 网关拦下，直接落进实现体抛 TypeError，用户拿到 HTTP 500 而不是干净的 400
    # 「缺少必填参数 X」。修法：参数声明从 `能力契约/参数契约.json` **整条透传**
    # （`参数=_参数契约表[能力id]`），入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：
    #  ① `_参数契约表` 是字面量、键是常量，`开发工具/契约编译/漂移检测` 的 AST 读取器
    #     （`_静态字面量` 的 `ast.Subscript` 分支）能解析出**整条参数含 `必填`** ——
    #     改前那处「参数口径未解析」不因本次修复恶化，反而把读不到的 `必填` 读到了。
    #     放在函数内是因为该读取器只收 `注册能力` 函数体内的赋值（`_扫描注册语句`）。
    #  ② 「裸布尔」防回潮门禁**已把 `必填`/`默认值` 计入违规**（本文件已迁为 真/假），改回裸 True/False 即判红。
    # 表内布尔位写**中文 `真`／`假`**（正式口径，真源 `公共契约/基础类型/逻辑类型.py`）；
    # 本文件顶部已 import 真/假，漂移检测读取器（`_导入常量绑定`）能静态解析出参数表，
    # （契约写了的键才留，没写的不补），不给漂移检测造出「注册声明了契约没声明的默认值」。
    # 为什么按下标取而不是包一层 `_参数声明(能力id)`：包一层会让 AST 一律判「不可静态
    # 判定」，等于拿门禁覆盖率换干净（不可接受）。名序护盾由 `_注册参数名序` +
    # `_校验参数名序()` 承担，装配期逐条对契约核名序，不一致即 raise。
    _参数契约表 = {
        "启动监督器.健康监督.执行健康监督": [
            {"名称": "基线", "类型": "字典型", "必填": 真, "默认值": None},
            {"名称": "临时目录", "类型": "文本型", "必填": 假, "默认值": ""},
        ],
        "启动监督器.健康监督.查询健康检查项": [
        ],
    }
    _注册参数名序 = {
        "启动监督器.健康监督.执行健康监督": ["基线", "临时目录"],
        "启动监督器.健康监督.查询健康检查项": [],
    }
    _校验参数名序(_参数契约表, _注册参数名序)
# ===== 参数声明透传 结束 =====
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="启动监督器.健康监督.执行健康监督",
        包id=包id,
        实现函数=执行健康监督,
        参数=_参数契约表["启动监督器.健康监督.执行健康监督"],
        返回="结果",
        说明="真跑一次健康监督：按调用方声明的容量基线做一次真实采样并比对，返回健康结论、超限项与采样快照（只读判定，不写证据、不触发超限处理链）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="启动监督器.健康监督.查询健康检查项",
        包id=包id,
        实现函数=查询健康检查项,
        参数=_参数契约表["启动监督器.健康监督.查询健康检查项"],
        返回="结果",
        说明="列出本监督面已注册的检查项：阈值项取自 容量基线.必需基线字段（唯一事实源），实测项来自一次真实采样，并给出各类条数。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
