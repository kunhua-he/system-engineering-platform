"""健康监督能力实现（只读/判定）：资源判定的唯一实现在 `启动监督器/容量基线.py`。

分工（第 2 条 1 项 分层与归属固定）：
- `启动监督器/容量基线.py`：声明基线→实测采样→对比超限 的**唯一语义实现**
  （必需基线字段、对照表、采样口径、证据与熔断全在那里）；
- `启动监督器/健康监督/核心.py`：系统提供者周期探针的唯一语义实现；
- 本模块：能力边界参数校验、实例取用与结果归一，**不复制任何判定分支**。

为什么只切只读/判定：`超限处理`（停止接收→拒绝排队→排空→优雅释放→熔断→证据）
是执行类与写类动作，会真改运行态并落盘证据，不在本轮能力面。`执行健康监督`
只跑 声明基线 + 实测采样 + 对比基线，不写证据、不改实例状态、不启动线程。
"""
from __future__ import annotations

from typing import Any

from 启动监督器.容量基线 import 必需基线字段, 容量基线

来源名称 = "健康监督"


def _失败(错误码: str, 说明: str):
    from 公共契约.基础类型.结果类型 import 结果

    return 结果.失败(错误码, 说明, 来源=来源名称)


def _成功(值: dict[str, Any]):
    from 公共契约.基础类型.结果类型 import 结果

    return 结果.成功结果(值)


def 执行健康监督(基线: dict, 临时目录: str = ""):
    """真跑一次健康监督：真实采样 + 按容量基线判定，返回结论与超限项。"""
    if not isinstance(基线, dict):
        return _失败("参数不合法",
                     f"基线必须是字典，实际 {type(基线).__name__}")
    目录 = str(临时目录 or "").strip() or None
    实例 = 容量基线(临时目录=目录)
    通过, 说明 = 实例.声明基线(基线)
    if not 通过:
        return _失败("参数不合法", 说明)
    采样 = 实例.实测采样()
    超限项 = 实例.对比基线()
    健康 = not 超限项
    if 健康:
        结论 = (f"健康：{len(必需基线字段)} 项基线全部在限内，"
                f"采样失败 0 项")
    else:
        明细 = "；".join(
            f"{项['字段']} 实测{项['实测值']} 对 声明{项['声明值']}"
            + ("（采样失败）" if 项.get("采样失败") else "")
            for 项 in 超限项)
        结论 = f"不健康：{len(超限项)} 项超限或采样失败 —— {明细}"
    return _成功({
        "健康": 健康,
        "超限项": 超限项,
        "采样": 采样,
        "结论": 结论,
        "检查项数": len(必需基线字段),
    })


def 查询健康检查项():
    """列出已注册的检查项：阈值项取 容量基线.必需基线字段，实测项来自真实采样。"""
    采样 = 容量基线().实测采样()
    if not 采样.get("成功"):
        return _失败("采样失败",
                     f"实测采样未通过：{采样.get('错误说明') or 采样.get('错误码')}")
    实测项 = [{"名称": 键, "实测值": 值, "来源": "容量基线.实测采样"}
              for 键, 值 in 采样.items()
              if isinstance(值, (int, float)) and not isinstance(值, bool)]
    阈值项 = [{"名称": 名称, "来源": "容量基线.必需基线字段"}
              for 名称 in 必需基线字段]
    检查项 = ([{**项, "类型": "阈值项"} for 项 in 阈值项]
              + [{**项, "类型": "实测项"} for 项 in 实测项])
    return _成功({
        "检查项": 检查项,
        "阈值项数": len(阈值项),
        "实测项数": len(实测项),
        "数量": len(检查项),
    })
