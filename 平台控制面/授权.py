"""五类角色统一授权：所有入口（命令行/Python/MCP/维护）调用同一授权服务。

授权不可自举：注册身份默认只能获得最低角色（普通用户）；高权限角色必须
来自持久化信任目录（角色授予表）的显式授予；角色切换只能在该身份已被
授予的角色集合内进行；会话重启后从权威状态恢复；过期、撤销、跨项目、
伪造所有者全部拒绝。CLI 不得把参数当可信角色。

受信引导的凭证（B-04 修复，唯一一处判定在本文件 `引导授予`）：
- 引导是**一次性**动作，凭证是**一次性引导令牌文件**（无长期密钥）：
  由 `发放引导令牌` 写入（0600，路径见 `引导令牌文件`），`引导授予` 校验
  令牌匹配后**立即删除**（存在即用、用完即删）；文件在 → 任何入口缺令牌
  一律拒绝；令牌不符 → 拒绝；无令牌文件而携带令牌 → 拒绝。
- `发放引导令牌` 自身有门槛：平台已初始化（存在有效 平台维护者/发布者 授予）
  时禁止再发放，令牌文件已存在时禁止重复发放 → 已上线平台无法再"凭空铸造"
  引导凭证，本机任意进程不能靠引导自我提权。
- 兼容边界：未配置令牌文件、且未携带令牌、且 授予者=系统引导 的**进程内直调**
  仍按原契约放行（既有夹具/门禁/示例的受信引导路径）。这是本地私有部署下的
  已知相对边界，不是新的后门：部署时发放一次性令牌即可关闭该路径。
"""
from __future__ import annotations

import os
import secrets
import time
import uuid
from pathlib import Path
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假

# 五类角色（固定）
普通用户 = "普通用户"
调用Agent = "调用Agent"
组件开发Agent = "组件开发Agent"
平台维护者 = "平台维护者"
发布者 = "发布者"

角色表 = [普通用户, 调用Agent, 组件开发Agent, 平台维护者, 发布者]
可授予角色表 = [调用Agent, 组件开发Agent, 平台维护者, 发布者]

# 角色等级（用于最小角色判定）
角色等级 = {普通用户: 1, 调用Agent: 2, 组件开发Agent: 3, 平台维护者: 4, 发布者: 5}

# 操作 → 最小角色等级
操作最小角色 = {
    "确认需求": 2, "搜索能力": 1, "查看能力": 1, "生成装配计划": 2,
    "申请能力占用": 3, "创建组件": 3, "验证组件": 3, "调用能力": 2,
    "查看诊断": 4, "提交候选包": 3, "签名与发布": 5, "回滚": 5,
    "登记需求": 3, "复用裁决": 4, "管理信任": 5, "监督资源": 4,
}

# 稳定错误码：错误语义 → **对外**稳定错误码。键与值同词是刻意的（决策 0003
# 「对外错误只走中文」，2026-09-17 B-16 收口）：值即对外返回的错误码文本，
# 中文短词与 平台控制面/统一入口.py（「越权操作/会话过期/未知角色/角色未授予」只透传）
# 和 开发工具/契约编译/消费者契约.py 的 全局错误码 三侧同词表。
# 保留字典型形态（能力面 查询角色模型 的「稳定错误码」字段按 错误语义 → 码 返回）。
稳定错误码 = {
    "未知角色": "未知角色", "越权操作": "越权操作",
    "越权资源": "越权资源", "跨项目": "跨项目",
    "伪造所有者": "伪造所有者", "会话过期": "会话过期",
    "角色未授予": "角色未授予", "引导受限": "引导受限",
}


class 授权服务:
    """统一授权服务：注册（最低角色）、授予（信任目录）、切换、鉴权。"""

    def __init__(self, 状态) -> None:
        self.状态 = 状态
        self._会话表: dict[str, dict[str, Any]] = {}

    # ---- 注册与引导 ----
    def 注册身份(self, *, 身份id: str, 所有者: str = "") -> str:
        """注册身份：默认只能获得最低角色（普通用户），不能自选高权限。"""
        令牌 = uuid.uuid4().hex[:20]
        self._会话表[令牌] = {
            "身份id": 身份id, "所有者": 所有者 or 身份id,
            "角色": 普通用户, "创建时间": time.time(), "过期时间": time.time() + 3600,
        }
        # 首次注册自动落一条普通用户授予记录（最低角色，无需授予者）
        if not self.状态.查询记录("角色授予", "身份id=? AND 角色=?", (身份id, 普通用户)):
            self.状态.写入记录("角色授予", {
                "授予id": uuid.uuid4().hex[:16], "身份id": 身份id,
                "所有者": 所有者 or 身份id, "项目范围": "", "角色": 普通用户,
                "授予者": "系统", "有效期": time.time() + 86400 * 365,
                "撤销状态": "有效", "证据": "注册自动授予最低角色",
            })
        return 令牌

    # ---- 受信引导凭证（一次性引导令牌文件，B-04）----
    def 引导令牌文件(self, 令牌文件: Path | str | None = None) -> Path:
        """一次性引导令牌文件路径：显式参数 → 环境变量 → 存储目录 → 平台默认目录。"""
        if 令牌文件 is not None and str(令牌文件).strip():
            return Path(令牌文件)
        环境 = os.environ.get("系统工程平台_引导令牌文件", "").strip()
        if 环境:
            return Path(环境)
        存储目录 = getattr(self.状态, "存储目录", None)
        if 存储目录:
            return Path(存储目录) / "引导令牌.txt"
        # 兜底缺省经唯一解析器（禁止 cwd 依赖的裸相对 `工程缓存`）：制品进程 cwd 是制品目录，
        # 裸相对值会把一次性引导令牌写进不可变制品；源码态回落 `<系统根>/工程缓存/平台控制面`。
        from 公共契约.运行时.运行缓存 import 解析运行缓存根

        return 解析运行缓存根(Path(__file__).resolve().parents[1]) / "平台控制面" / "引导令牌.txt"

    def 平台已初始化(self) -> bool:
        """是否已有有效高权限授予（平台维护者/发布者）：引导只在初始化前有意义。"""
        for 角色 in (平台维护者, 发布者):
            if self.状态.查询记录("角色授予", "角色=? AND 撤销状态='有效'", (角色,)):
                return 真
        return 假

    def 发放引导令牌(self, *, 令牌文件: Path | str | None = None) -> tuple[bool, str, str]:
        """发放一次性引导令牌：返回 (成功, 消息, 令牌明文)。

        门槛（缺一不可）：令牌文件不存在（一次性，不重复发放）+ 平台未初始化
        （已有有效 平台维护者/发布者 授予即拒绝）。令牌只写文件（0600）与返回值，
        不进证据/日志；证据只记路径。
        """
        文件 = self.引导令牌文件(令牌文件)
        if 文件.exists():
            return 假, f"引导令牌已存在（一次性，使用后即焚）: {文件}", ""
        if self.平台已初始化():
            return 假, "平台已初始化（已有 平台维护者/发布者 授予），禁止再发放引导令牌", ""
        令牌 = secrets.token_hex(16)
        文件.parent.mkdir(parents=True, exist_ok=True)
        文件.write_text(令牌, encoding="utf-8")
        os.chmod(文件, 0o600)
        self.状态.追加证据(类型="授权", 主题="发放引导令牌",
                          内容={"令牌文件": str(文件)}, 调用者="系统引导",
                          角色=平台维护者, 结果="发放")
        return 真, f"已发放一次性引导令牌: {文件}", 令牌

    def 引导授予(self, *, 身份id: str, 角色: str, 授予者: str,
                引导令牌: str = "", 令牌文件: Path | str | None = None) -> tuple[bool, str]:
        """受信引导：仅允许授予者=系统引导 且 目标角色为高权限角色，并校验一次性引导令牌。

        这是唯一受信提权路径（生产由平台管理员发放一次性令牌后使用），写证据，
        不是注册后门：令牌文件存在即必须匹配并被删除；缺令牌/令牌不符一律拒绝。
        """
        if 角色 not in 可授予角色表:
            return 假, f"角色不可授予: {角色}"
        if 授予者 != "系统引导":
            return 假, "引导授予必须显式指定 授予者=系统引导（受信引导，非注册后门）"
        文件 = self.引导令牌文件(令牌文件)
        提供令牌 = str(引导令牌 or "")
        if 文件.is_file():
            try:
                应匹配 = 文件.read_text(encoding="utf-8").strip()
            except OSError as 错误:
                return 假, f"引导令牌文件不可读: {错误}"
            if not 提供令牌:
                return 假, f"引导授予需要一次性引导令牌（先经 发放引导令牌 取得）: {文件}"
            # 按字节比较（compare_digest 不接受含非 ASCII 的 str：中文令牌会直接抛异常）
            if not secrets.compare_digest(提供令牌.encode("utf-8"), 应匹配.encode("utf-8")):
                return 假, "引导令牌不匹配：引导授予被拒"
            文件.unlink(missing_ok=True)   # 一次性：用后即焚
            凭证 = "一次性引导令牌"
        elif 提供令牌:
            return 假, f"引导令牌文件不存在，无法校验令牌: {文件}"
        else:
            凭证 = "进程内受信直调（未配置引导令牌文件）"
        self._授予(身份id=身份id, 角色=角色, 项目范围="", 授予者=授予者,
                   有效期=time.time() + 86400 * 30)
        self.状态.追加证据(类型="授权", 主题=f"引导:{身份id}",
                          内容={"角色": 角色, "凭证": 凭证}, 调用者=身份id,
                          角色=角色, 结果="引导授予")
        return 真, f"引导授予: {身份id} → {角色}（凭证: {凭证}）"

    def 授予角色(self, *, 授予者令牌: str, 身份id: str, 角色: str,
                项目范围: str = "", 有效期秒: float = 86400) -> tuple[bool, str]:
        """授予角色：授予者必须是 平台维护者（角色等级≥4），写信任目录+证据。"""
        会话 = self._会话表.get(授予者令牌)
        if 会话 is None:
            return 假, "授予者会话不存在"
        if 会话["过期时间"] < time.time():
            return 假, 稳定错误码["会话过期"]
        if 角色 not in 可授予角色表:
            return 假, f"角色不可授予: {角色}"
        if 会话["角色"] not in (平台维护者, 发布者):
            return 假, 稳定错误码["越权操作"]
        self._授予(身份id=身份id, 角色=角色, 项目范围=项目范围,
                   授予者=会话["身份id"], 有效期=time.time() + 有效期秒)
        self.状态.追加证据(类型="授权", 主题=f"授予:{身份id}", 内容={"角色": 角色, "项目范围": 项目范围},
                          调用者=会话["身份id"], 角色=会话["角色"], 结果="授予")
        return 真, f"已授予 {身份id} → {角色}"

    def _授予(self, *, 身份id: str, 角色: str, 项目范围: str,
              授予者: str, 有效期: float) -> None:
        self.状态.写入记录("角色授予", {
            "授予id": uuid.uuid4().hex[:16], "身份id": 身份id,
            "所有者": 身份id, "项目范围": 项目范围, "角色": 角色,
            "授予者": 授予者, "有效期": 有效期, "撤销状态": "有效",
            "证据": f"授予者 {授予者} 于 {time.strftime('%Y-%m-%d %H:%M:%S')}",
        })

    def 撤销角色(self, *, 授予者令牌: str, 身份id: str, 角色: str) -> tuple[bool, str]:
        """撤销角色：旧令牌立即失效；写证据。"""
        会话 = self._会话表.get(授予者令牌)
        if 会话 is None or 会话["角色"] != 平台维护者:
            return 假, 稳定错误码["越权操作"]
        成功 = self.状态.条件更新(
            "角色授予", {"撤销状态": "已撤销"},
            "身份id=? AND 角色=? AND 撤销状态='有效'", (身份id, 角色))
        if not 成功:
            return 假, "无有效授予可撤销"
        self.状态.追加证据(类型="授权", 主题=f"撤销:{身份id}", 内容={"角色": 角色},
                          调用者=会话["身份id"], 角色=会话["角色"], 结果="撤销")
        # 撤销后强制会话降级为最低角色（旧会话立即失败）
        for 会话值 in self._会话表.values():
            if 会话值["身份id"] == 身份id and 会话值["角色"] == 角色:
                会话值["角色"] = 普通用户
        return 真, f"已撤销 {身份id} 的 {角色}"

    def 已授予角色(self, 身份id: str, 项目范围: str = "") -> list[str]:
        """该身份当前有效授予的角色集合（未撤销+未过期+项目范围匹配）。"""
        结果表 = []
        for 授予 in self.状态.查询记录("角色授予", "身份id=? AND 撤销状态='有效'", (身份id,)):
            if 授予["有效期"] < time.time():
                continue
            if 项目范围 and 授予["项目范围"] and 授予["项目范围"] != 项目范围:
                continue
            结果表.append(授予["角色"])
        return 结果表

    # ---- 会话与鉴权 ----
    def 切换角色(self, 令牌: str, 角色: str, 项目范围: str = "") -> tuple[bool, str]:
        """切换角色：只能切换到该身份已授予的角色集合内；写证据。"""
        会话 = self._会话表.get(令牌)
        if 会话 is None:
            return 假, "会话不存在"
        if 会话["过期时间"] < time.time():
            return 假, 稳定错误码["会话过期"]
        if 角色 not in 角色表:
            return 假, f"未知角色: {角色}"
        已授予 = self.已授予角色(会话["身份id"], 项目范围)
        if 角色 not in 已授予:
            self.状态.追加证据(类型="授权拒绝", 主题=f"切换角色:{角色}",
                              内容={"身份": 会话["身份id"], "已授予": 已授予},
                              调用者=会话["身份id"], 角色=会话["角色"],
                              结果="拒绝", 错误码=稳定错误码["角色未授予"])
            return 假, f"角色未授予: {角色}（已授予: {已授予 or '仅普通用户'}）"
        会话["角色"] = 角色
        self.状态.追加证据(类型="授权", 主题="切换角色",
                          内容={"身份": 会话["身份id"], "角色": 角色},
                          调用者=会话["身份id"], 角色=角色, 结果="成功")
        return 真, f"已切换为 {角色}"

    def 校验操作(self, *, 令牌: str, 操作: str, 资源范围: str = "",
                 项目范围: str = "") -> tuple[bool, str, dict[str, Any]]:
        """校验操作权限；默认拒绝；返回 (允许, 错误码, 会话)。"""
        会话 = self._会话表.get(令牌)
        if 会话 is None:
            return 假, "会话不存在", {}
        if 会话["过期时间"] < time.time():
            return 假, 稳定错误码["会话过期"], {}
        角色 = 会话["角色"]
        if 角色 not in 角色表:
            return 假, 稳定错误码["未知角色"], {}
        # 会话角色必须仍在有效授予集合内（撤销后旧令牌立即失败）
        已授予 = self.已授予角色(会话["身份id"], 项目范围)
        if 角色 not in 已授予 and 角色 != 普通用户:
            return 假, 稳定错误码["角色未授予"], {}
        需要等级 = 操作最小角色.get(操作, 99)
        if 角色等级[角色] < 需要等级:
            self.状态.追加证据(类型="授权拒绝", 主题=操作,
                              内容={"身份": 会话["身份id"], "角色": 角色, "需要等级": 需要等级},
                              调用者=会话["身份id"], 角色=角色, 结果="拒绝",
                              错误码=稳定错误码["越权操作"])
            return 假, 稳定错误码["越权操作"], {}
        return 真, "", 会话

    def 刷新会话(self, 令牌: str) -> bool:
        会话 = self._会话表.get(令牌)
        if 会话 is None:
            return 假
        会话["过期时间"] = time.time() + 3600
        return 真
