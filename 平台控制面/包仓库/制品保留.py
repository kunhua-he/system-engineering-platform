"""制品保留与回收：内容寻址目录 / 身份目录 / 镜像目录 的**唯一回收实现**。

为什么要有这个模块（2026-09-18 现场：`平台客户端制品/` 下积压 17 份身份目录，351MB）：

回收逻辑原本长在**构建脚本** `客户端/构建平台客户端.py::清理过期制品` 里，且只被
`安装到环境` 的**成功路径**调用一次 —— 也就是「回收点挂在了某条成功路径上」：

- 不走 `--安装` 就永远不回收；
- 入库/安装中途失败（正是最容易留下垃圾的路径）反而不回收；
- 任何**别的**清点方（门禁、诊断、人工核查）拿不到同一个回收能力，只能自己再写一遍
  `rmtree` —— 那就是「同一件事两种表达」的第二套回收实现。

本模块把回收收成**一处实现**（本文件），由 `平台客户端制品接入` 两个必经方法
（`诊断激活指针` / `安装到环境`）自动调用。**2026-09-19 补齐最后一处**：构建脚本里
残留的那套旧实现（无本文件的保底保留，退化成「不是当前件就删」）已**整块删除**，
构建成功路径不再自行回收 —— 至此全仓只剩本文件一处回收实现。
「必经路径」的判据不是「谁调用得多」，而是：**任何一次入库/安装/清点动作都会经过
同一个回收入口**，且回收**有上限**（`回收上限份数`），不会一次删光无法诊断。

`清理过期制品`（能力 `平台控制面.包仓库.清理过期制品`）对外给的是同一条实现 +
一次「预期存量」判定，供门禁断言「清理干净了」。

回收不仅有**上限**，还有**下限**：**无任何实际保留件时，每个根至少保底留一份**
（`保底保留份数`）。依据（2026-09-18 实测）：`重置激活指针` 把指针清回「未安装态」后，
环境指针为空 ⇒ `_标识集合` 得到**空集** ⇒ 判据退化成「不是当前件就删」⇒ 下一次必经路径
（诊断/清点）把两个制品根**整根清空**；首次安装随即在「制品目录缺失（半成品）」上被拒 ——
半成品判定本身正确，错的是回收把「未安装」当成了「仓库为空」。
判据在**一处**收口，所以下限也落在同一处（`_扫描核心`），`扫描/回收/清点` 三者结论恒一致。
"""
from __future__ import annotations

import shutil
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假

# 内容寻址摘要长度（sha256 前 32 位）= 内容寻址目录名形态
内容寻址名长度 = 32
_十六进制字符 = frozenset("0123456789abcdef")
# 身份目录前缀（`平台客户端-<摘要16>`）
身份目录前缀 = "平台客户端-"
# 镜像目录后缀（预留：与内容寻址目录成套的镜像目录命名）
镜像目录后缀 = ".镜像"

# 与 `客户端/构建平台客户端.py::清理过期制品` 的历史口径**逐字一致**的信任链保留模式：
# 快照/目标/签名制品包各留最新一份。信任链历史不是「制品积压」，但同属「过期就删」的
# 回收动作，收在同一处避免两条回收路径各删各的。
信任链保留模式表 = (
    ("元数据", "快照_*.json"),
    ("元数据", "目标_*.json"),
    ("制品", "*.bin"),
)

# 缺省回收上限：一次回收最多删掉的项数。设上限的理由是「回收不该变成不可诊断的批量删除」——
# 现场积压 17 份时一轮删完，但如果某个根被外部写坏成上千份，无限删会让一次安装调用
# 静默变成破坏性操作；有上限时超出的部分留到下一次必经路径继续收，且 `达到上限` 会如实回报。
回收上限份数 = 256

# 保底保留份数：**当该根没有任何实际保留件时**，至少留几份可用件（每个根各算）。
#
# 为什么清理必须有下限（2026-09-18 实测，`重置激活指针` → 首次安装被拒）：
# 保留判据的唯一来源是激活指针与里程碑；指针一旦被合法清空（重置回「未安装态」），
# 保留标识就成了空集，判据退化成「不是当前件就删」——下一次必经路径（诊断/清点）
# 把两个制品根整根清空，安装链的输入（内容寻址目录）与重装源（身份目录）一起没了，
# 首次安装只能报「制品目录缺失（半成品）」。半成品判定本身是对的（装机输入确实没了），
# 错的是回收把「未安装」读成了「仓库为空」。
# 下限只管「至少留一份可用件」，不放行任何半成品/篡改：真正的完整性判定仍由
# 安装链的 校验制品（签名 + 磁盘逐一摘要）拦，保底件本身不合格同样装不上。
保底保留份数 = 1


@dataclass
class 回收结果:
    """一次回收的真实结果（供调用方断言，不做任何「假成功」包装）。"""

    扫描项: int = 0
    删除项: int = 0
    保留项: int = 0
    失败项: list[str] = field(default_factory=list)
    释放字节: int = 0
    删除明细: list[str] = field(default_factory=list)
    达到上限: bool = 假
    保底保留明细: list[str] = field(default_factory=list)
    未扫描根: list[str] = field(default_factory=list)

    @property
    def 成功(self) -> bool:
        return not self.失败项

    @property
    def 释放兆字节(self) -> float:
        return self.释放字节 / 1024 / 1024

    def 摘要文本(self) -> str:
        """一行可读结论（供构建脚本 print 与能力返回复用，不各写一套文案）。"""
        文本 = (f"过期制品清理：扫描 {self.扫描项} 项，删 {self.删除项} 项，"
                f"留 {self.保留项} 项，释放 {self.释放兆字节:.1f} MB")
        if self.达到上限:
            文本 += f"（已达单次上限 {回收上限份数}，下次必经路径继续回收）"
        if self.保底保留明细:
            文本 += (f"（无实际保留件，按保底各留 {保底保留份数} 份："
                     f"{self.保底保留明细}）")
        if self.失败项:
            文本 += f"；删除失败 {len(self.失败项)} 项：{self.失败项[:3]}"
        if self.未扫描根:
            文本 += f"；根不存在跳过：{self.未扫描根}"
        return 文本


def _是内容寻址目录(名称: str) -> bool:
    """内容寻址目录名形态：32 位十六进制（不得由 镜像目录后缀 干扰）。"""
    return len(名称) == 内容寻址名长度 and all(字符 in _十六进制字符 for 字符 in 名称)


def _是身份目录(名称: str) -> bool:
    """身份目录名形态：`平台客户端-<摘要16>`（可带镜像后缀）。"""
    值 = 名称[: -len(镜像目录后缀)] if 名称.endswith(镜像目录后缀) else 名称
    return 值.startswith(身份目录前缀) and len(值) > len(身份目录前缀)


def 是受管制品目录(名称: str) -> bool:
    """名称是否是**受管制品目录**（内容寻址 / 身份 / 镜像三类之一）。

    非受管制品的目录（`平台客户端信任`、`平台客户端状态`、`平台客户端环境`、
    `平台客户端密钥`、`可信仓库校验探测` …）一律不在回收范围内：它们是活数据，
    不是「过期制品」。回收判据必须**白名单形态**，不能是「不是当前件就删」。
    """
    return _是内容寻址目录(名称) or _是身份目录(名称)


def _标识集合(当前摘要: str, 当前身份: str, 里程碑摘要表: tuple[str, ...] | list[str]) -> set[str]:
    """当前件与里程碑件的**全部合法写法**。

    历史踩坑（2026-09-15 沙箱实测）：原判定只比对「摘要本体」与「前缀-摘要」，
    漏了「前缀-身份」，把手上的当前件一并删掉。现按四种写法枚举：
    摘要本体、`前缀-摘要`、`前缀-身份`、各自的镜像后缀形态。
    """
    标识: set[str] = set()
    for 值 in (当前摘要, 当前身份, *里程碑摘要表):
        值 = str(值 or "").strip()
        if not 值:
            continue
        for 形态 in (值, f"{身份目录前缀}{值}"):
            标识.add(形态)
            标识.add(f"{形态}{镜像目录后缀}")
    return 标识


def _扫描核心(根: Path | str, *, 当前摘要: str = "", 当前身份: str = "",
              里程碑摘要表: tuple[str, ...] | list[str] = (),
              保留最近份数: int = 0,
              保底保留: int = 保底保留份数) -> tuple[list[Path], list[str]]:
    """受管判据 + 保留判据的**唯一实现**：返回 `(应回收目录, 保底保留目录名)`。

    `扫描过期制品` / `清理过期制品` / `回收报告` 都从这里取结论，所以
    「清点说该收」「回收真的收」「保底留了谁」不可能变成三套说法。

    保底（`保底保留`，缺省 `保底保留份数`）只在**该根没有任何实际保留件**时生效：
    既没命中保留标识（指针为空 + 无里程碑），`保留最近份数` 也没留下任何一份 ——
    此时按 mtime 从新到旧留 `保底保留` 份，其余照常回收。有实际保留件时保底不生效，
    「过期就删（只留当前件与里程碑）」的历史口径逐字不变。
    留最新的一份而非最旧的：无当前件时，最新的一份才是重装/回滚最可能用得上的。
    """
    根 = Path(根)
    if not 根.is_dir():
        return [], []
    保留标识 = _标识集合(当前摘要, 当前身份, 里程碑摘要表)
    候选 = [目录 for 目录 in sorted(根.iterdir())
            if 目录.is_dir() and 是受管制品目录(目录.name)]
    过期 = [目录 for 目录 in 候选 if 目录.name not in 保留标识]
    实际保留 = [目录 for 目录 in 候选 if 目录.name in 保留标识]
    if 保留最近份数 > 0 and 过期:
        过期.sort(key=lambda 目录: 目录.stat().st_mtime, reverse=True)
        实际保留 += 过期[:保留最近份数]
        过期 = 过期[保留最近份数:]
    保底件: list[Path] = []
    if not 实际保留 and 过期 and int(保底保留) > 0:
        过期.sort(key=lambda 目录: 目录.stat().st_mtime, reverse=True)
        保底件 = 过期[:int(保底保留)]
        过期 = 过期[int(保底保留):]
    return 过期, [目录.name for 目录 in 保底件]


def 扫描过期制品(根: Path | str, *, 当前摘要: str = "", 当前身份: str = "",
                 里程碑摘要表: tuple[str, ...] | list[str] = (),
                 保留最近份数: int = 0,
                 保底保留: int = 保底保留份数) -> list[Path]:
    """列出该根下**应回收**的受管制品目录（只读，不删）。

    `保留最近份数>0` 时，除当前件/里程碑件外再按 mtime 保留最近 N 份
    （用于「先清点再决定」的场景）。`保底保留` 见 `_扫描核心`：无任何实际保留件时
    至少留 N 份，避免「指针被合法清空 → 整根清空」。
    """
    return _扫描核心(根, 当前摘要=当前摘要, 当前身份=当前身份,
                     里程碑摘要表=里程碑摘要表, 保留最近份数=保留最近份数,
                     保底保留=保底保留)[0]


def _目录字节数(目录: Path) -> int:
    """目录内全部普通文件字节数（用于回报释放量；失败该项按 0 计，不影响删除）。"""
    try:
        return sum(文件.stat().st_size for 文件 in 目录.rglob("*") if 文件.is_file())
    except OSError:
        return 0


def 清理过期制品(根: Path | str, *, 当前摘要: str = "", 当前身份: str = "",
                 里程碑摘要表: tuple[str, ...] | list[str] = (),
                 保留最近份数: int = 0, 上限份数: int = 回收上限份数) -> 回收结果:
    """回收该根下的过期制品目录：**唯一回收实现**（受管制品目录 + 信任链历史）。

    - 只删**受管制品目录**（见 `是受管制品目录`）：白名单形态，不是「不是当前件就删」；
    - 当前件与里程碑件的四种写法都保留（见 `_标识集合`）；无任何实际保留件时按
      `保底保留份数` **每个根至少留一份可用件**（见 `_扫描核心`：这是「重置回未安装态
      后整根被清空、首次安装报半成品」的根因收口）；
    - `上限份数` 封顶（缺省 `回收上限份数`）：达到上限即停并置 `达到上限`，
      剩下的留给下一次必经路径，回收不变成不可诊断的批量删除；
    - 信任链历史（快照/目标/签名制品包）各留最新一份，模式与历史口径逐字一致；
    - 删除失败**如实计入 `失败项`**，不吞异常、不静默续跑。
    """
    根 = Path(根)
    结果 = 回收结果()
    if not 根.is_dir():
        结果.未扫描根.append(str(根))
        return 结果
    过期, 保底件 = _扫描核心(根, 当前摘要=当前摘要, 当前身份=当前身份,
                            里程碑摘要表=里程碑摘要表, 保留最近份数=保留最近份数)
    结果.保底保留明细 = 保底件
    受管总数 = sum(1 for 目录 in 根.iterdir()
                   if 目录.is_dir() and 是受管制品目录(目录.name))
    结果.扫描项 = 受管总数
    结果.保留项 = 受管总数 - len(过期)
    for 目录 in 过期:
        if 结果.删除项 >= max(0, int(上限份数)):
            结果.达到上限 = 真
            break
        大小 = _目录字节数(目录)
        try:
            shutil.rmtree(目录)
        except OSError as 错误:
            结果.失败项.append(f"{目录.name}（{错误}）")
            continue
        结果.删除项 += 1
        结果.释放字节 += 大小
        结果.删除明细.append(目录.name)
    # 信任链历史：快照/目标/签名制品包各留最新一份（与历史口径逐字一致）
    for 子目录名, 模式 in 信任链保留模式表:
        目录 = 根 / 子目录名
        if not 目录.is_dir():
            continue
        文件表 = sorted(目录.glob(模式), key=lambda 路径: 路径.stat().st_mtime)
        for 过期文件 in 文件表[:-1]:
            if 结果.删除项 >= max(0, int(上限份数)):
                结果.达到上限 = 真
                break
            try:
                大小 = 过期文件.stat().st_size
                过期文件.unlink()
            except OSError as 错误:
                结果.失败项.append(f"{过期文件.name}（{错误}）")
                continue
            结果.删除项 += 1
            结果.释放字节 += 大小
            结果.删除明细.append(过期文件.name)
    return 结果


def 合并回收结果(结果表: list[回收结果]) -> 回收结果:
    """把同一轮里多个根的回收结果合成一份（回报口径统一，调用方不必自己累加）。"""
    合并 = 回收结果()
    for 结果 in 结果表:
        合并.扫描项 += 结果.扫描项
        合并.删除项 += 结果.删除项
        合并.保留项 += 结果.保留项
        合并.释放字节 += 结果.释放字节
        合并.删除明细.extend(结果.删除明细)
        合并.失败项.extend(结果.失败项)
        合并.保底保留明细.extend(结果.保底保留明细)
        合并.未扫描根.extend(结果.未扫描根)
        合并.达到上限 = 合并.达到上限 or 结果.达到上限
    return 合并


def 记录回收证据(状态, *, 结果: 回收结果, 触发点: str, 当前摘要: str = "",
                 里程碑摘要表: tuple[str, ...] | list[str] = ()) -> str:
    """把一轮回收写进平台状态证据链（可追溯「谁在什么时候收了什么」）。

    为什么必须有留痕：回收是**破坏性动作**，只靠 print 无法回答「这份制品什么时候
    被谁收走的」。证据写失败不抛（回收已经真实发生，不能因为证据写不进去反过来
    谎报回收失败），返回空串表示证据未落。
    """
    try:
        return 状态.追加证据(
            类型="制品回收", 主题=str(触发点),
            内容={"触发点": str(触发点), "当前摘要": str(当前摘要),
                  "里程碑摘要": list(里程碑摘要表),
                  "扫描项": 结果.扫描项, "删除项": 结果.删除项,
                  "保留项": 结果.保留项, "释放字节": 结果.释放字节,
                  "达到上限": 结果.达到上限, "失败项": 结果.失败项[:10],
                  "保底保留": list(结果.保底保留明细),
                  "删除明细": 结果.删除明细[:50],
                  "时间": time.strftime("%Y-%m-%d %H:%M:%S")},
            调用者="平台控制面.包仓库.制品保留",
            角色="回收", 结果="已回收" if 结果.删除项 else "无需回收",
            错误码="" if 结果.成功 else "回收部分失败")
    except Exception:  # 证据链是旁路：写不进去不得改变回收的真实结论
        return ""


def 回收报告(根: Path | str, *, 当前摘要: str = "", 当前身份: str = "",
             里程碑摘要表: tuple[str, ...] | list[str] = (),
             保留最近份数: int = 0,
             保底保留: int = 保底保留份数) -> dict[str, Any]:
    """只读清点：`{根, 存在, 受管份数, 过期份数, 过期明细, 保留明细, 过期字节}`。

    给门禁/诊断用：**不删任何东西**，但和 `清理过期制品` 共用同一套受管判据与保留判据
    （同一 `_扫描核心`，含保底保留），因此「清点说该收」与「回收真的收」不可能两套结论
    （这正是原来回收脚本自己 iterdir 判形态、门禁自己另判一次的隐患）。
    另返回 `保底保留明细`：本次无实际保留件、靠保底留下的那份（空 = 保底未生效）。
    """
    根 = Path(根)
    存在 = 根.is_dir()
    受管 = ([目录 for 目录 in sorted(根.iterdir())
             if 目录.is_dir() and 是受管制品目录(目录.name)] if 存在 else [])
    过期, 保底件 = (_扫描核心(根, 当前摘要=当前摘要, 当前身份=当前身份,
                            里程碑摘要表=里程碑摘要表, 保留最近份数=保留最近份数,
                            保底保留=保底保留) if 存在 else ([], []))
    过期名集 = {目录.name for 目录 in 过期}
    return {
        "根": str(根), "存在": 存在,
        "受管份数": len(受管), "过期份数": len(过期),
        "过期明细": sorted(过期名集),
        "保留明细": sorted(目录.name for 目录 in 受管 if 目录.name not in 过期名集),
        "保底保留明细": 保底件,
        "过期字节": sum(_目录字节数(目录) for 目录 in 过期),
    }


