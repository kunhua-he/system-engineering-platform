def _文本(值: Any) -> str:
    """目录/摘要类参数归一：None 视为空串，其余转文本并去首尾空白。"""
    return "" if 值 is None else str(值).strip()


def _目录参数(键名: str, 值: Any) -> tuple[str, str]:
    """校验一个目录参数：非空且已存在时必须是目录（是文件即 参数不合法）。

    返回值 = (规范化文本, 错误说明)；错误说明为空表示通过。
    目录不存在是合法输入（实现层按「未安装/从未发布」正确处理），
    不在这里代为创建，也不静默改写调用方给的路径。
    """
    文本 = _文本(值)
    if not 文本:
        return "", ""
    路径 = Path(文本)
    if 路径.exists() and not 路径.is_dir():
        return "", f"{键名} 已存在但不是目录: {文本}"
    return 文本, ""


def _目录字典(参数: dict[str, Any], 键名列表: tuple[str, ...]) -> tuple[dict[str, str], str]:
    """批量校验目录参数，返回 (只含非空项的参数字典, 错误说明)。"""
    结果: dict[str, str] = {}
    for 键名 in 键名列表:
        文本, 说明 = _目录参数(键名, 参数.get(键名))
        if 说明:
            return {}, 说明
        if 文本:
            结果[键名] = 文本
    return 结果, ""


def _制品接入(参数: dict[str, Any]):
    """按参数构造 平台客户端制品接入；目录项为空即取实现层默认值。

    `客户端制品目录` 不是公开参数：它由 制品根目录 派生（与调用方原口径
    `制品根目录/平台客户端制品` 完全一致），避免同一事有两套口径。
    """
    from 平台控制面.包仓库.平台客户端制品 import 平台客户端制品接入

    实参: dict[str, Any] = {}
    for 键名 in ("状态目录", "制品根目录", "环境目录", "信任目录"):
        文本 = _文本(参数.get(键名))
        if 文本:
            实参[键名] = Path(文本)
    if "制品根目录" in 实参:
        实参["客户端制品目录"] = 实参["制品根目录"] / "平台客户端制品"
    return 平台客户端制品接入(**实参)


def 校验平台客户端制品(制品摘要: str = "", 状态目录: str = "", 制品根目录: str = "",
                      环境目录: str = "", 信任目录: str = "") -> Any:
    """校验平台客户端制品：Ed25519 签名 + 磁盘逐一摘要 + 信任元数据目标校验。

    返回 `{通过, 消息}`；`通过=False` 是**校验结论**（不是调用失败），
    消息逐字沿用实现层原文，调用方据此映射自己的错误码。
    """
    from 公共契约.基础类型.结果类型 import 结果

    摘要 = _文本(制品摘要)
    if not 摘要:
        return 结果.失败(错误_参数不合法, "制品摘要不能为空", 来源="包仓库")
    目录参数, 说明 = _目录字典(
        {"状态目录": 状态目录, "制品根目录": 制品根目录,
         "环境目录": 环境目录, "信任目录": 信任目录},
        ("状态目录", "制品根目录", "环境目录", "信任目录"))
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    接入 = _制品接入(目录参数)
    try:
        通过, 消息 = 接入.校验制品(摘要)
    finally:
        接入.关闭()
    return 结果.成功结果({"通过": bool(通过), "消息": str(消息)})


def 校验平台客户端稳定路径(状态目录: str = "", 制品根目录: str = "",
                          环境目录: str = "", 信任目录: str = "",
                          客户端制品目录: str = "") -> Any:
    """校验平台客户端稳定路径：指针可读 → 已安装目录存在 → 摘要一致 → 制品目录一致。

    返回 `{有效, 消息, 激活路径}`；`激活路径` 为文本型（未通过时为空串），
    调用方可直接 `Path(激活路径).resolve()`。
    """
    from 公共契约.基础类型.结果类型 import 结果

    目录参数, 说明 = _目录字典(
        {"状态目录": 状态目录, "制品根目录": 制品根目录, "环境目录": 环境目录,
         "信任目录": 信任目录, "客户端制品目录": 客户端制品目录},
        ("状态目录", "制品根目录", "环境目录", "信任目录", "客户端制品目录"))
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    接入 = _制品接入(目录参数)
    try:
        有效, 消息, 激活路径 = 接入.校验稳定路径()
    finally:
        接入.关闭()
    return 结果.成功结果({
        "有效": bool(有效), "消息": str(消息),
        "激活路径": str(激活路径) if 激活路径 is not None else "",
    })


def 安装候选包(仓库根目录: str = "", 包目录: str = "") -> Any:
    """安装候选包到不可变版本目录，返回 `{安装路径,包id,版本,完整性摘要}`。

    同包同版本不可覆盖、包结构不全即失败——判定全部由 版本仓库 实现层负责，
    本能力只做参数校验与结果收口；安装失败返回 `候选包安装失败` + 实现层原文说明。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.版本仓库 import 包仓库

    仓库文本, 说明 = _目录参数("仓库根目录", 仓库根目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    if not 仓库文本:
        return 结果.失败(错误_参数不合法, "仓库根目录不能为空", 来源="包仓库")
    源文本, 说明 = _目录参数("包目录", 包目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    if not 源文本:
        return 结果.失败(错误_参数不合法, "包目录不能为空", 来源="包仓库")
    仓库 = 包仓库(Path(仓库文本))
    成功, 结果值 = 仓库.安装(Path(源文本))
    if not 成功 or isinstance(结果值, str):
        return 结果.失败("候选包安装失败", str(结果值), 来源="包仓库")
    return 结果.成功结果({
        "安装路径": str(结果值.安装路径),
        "包id": str(结果值.包id),
        "版本": str(结果值.版本),
        "完整性摘要": str(结果值.完整性摘要),
    })


def 校验已安装包完整性(仓库根目录: str = "", 包id: str = "", 版本: str = "",
                      期望摘要: str = "") -> Any:
    """校验已安装版本的完整性摘要，返回 `{校验成功,证据}`。

    `校验成功=False` 是**校验结论**（摘要漂移/未安装），证据逐字沿用实现层原文；
    调用方据此判定「篡改后必须被拒绝」这类反向场景。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.版本仓库 import 包仓库

    仓库文本, 说明 = _目录参数("仓库根目录", 仓库根目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    if not 仓库文本:
        return 结果.失败(错误_参数不合法, "仓库根目录不能为空", 来源="包仓库")
    包id文本, 版本文本 = _文本(包id), _文本(版本)
    if not 包id文本 or not 版本文本:
        return 结果.失败(错误_参数不合法, "包id 与 版本 不能为空", 来源="包仓库")
    仓库 = 包仓库(Path(仓库文本))
