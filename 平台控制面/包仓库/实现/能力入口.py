"""包仓库包的实现层：治理面制品/仓库动作的唯一执行入口（能力实现）。

本模块是 `平台控制面.包仓库` 正式包的能力实现层，包级中文入口
（同包 `__init__.py`）的 `注册能力(注册表)` 从这里取实现函数。

分工（第 2 条 1 项「分层与归属固定」）：
- 同目录 `平台客户端制品.py` / `版本仓库.py` / `可复现构建器.py` /
  `可信仓库元数据.py` / `生命周期.py`：仓库与制品的**唯一语义实现**；
- 本模块：把上述实现的公开方法收成**统一结果契约**的能力实现，负责能力
  边界上的参数校验、目录缺省与「调用方场景」编排（收口，不复制语义）。

为什么要有这一层：
- `开发工具` 下的门禁/审计脚本是**进程外**调用方，不得 import 本包实现，
  只能经唯一能力调用入口按能力 id 调用；本层是它们唯一可达的公开面。
- 每条能力对应调用方原来直接调实现时做的**同一件事**，返回值把它需要的
  事实一次给全，错误码与说明逐字沿用实现层原文。
"""
from __future__ import annotations

import tempfile
import shutil
from pathlib import Path
from typing import Any

错误_参数不合法 = "参数不合法"

# 能力 存放目录 缺省值：运行态一律入库 `工程缓存`（哲学：运行态一律入库）。
_包内系统根 = Path(__file__).resolve().parents[3]
_默认可信仓库目录 = _包内系统根 / "工程缓存" / "制品仓库" / "可信仓库校验探测"


def _文本(值: Any) -> str:
    """目录/摘要类参数归一：None 视为空串，其余转文本并去首尾空白。"""
    return "" if 值 is None else str(值).strip()


def _目录参数(键名: str, 值: Any) -> tuple[str, str]:
    """校验一个目录参数：非空且已存在时必须是目录（是文件即 参数不合法）。

    返回值 = (规范化文本, 错误说明)；错误说明为空表示通过。
    目录不存在是合法输入（实现层按「未安装/从未发布」正确处理），
    不在这里代为创建，也不静默改写调用方给的路径。
    """
    文本 = _文本(值)
    if not 文本:
        return "", ""
    路径 = Path(文本)
    if 路径.exists() and not 路径.is_dir():
        return "", f"{键名} 已存在但不是目录: {文本}"
    return 文本, ""


def _目录字典(参数: dict[str, Any], 键名列表: tuple[str, ...]) -> tuple[dict[str, str], str]:
    """批量校验目录参数，返回 (只含非空项的参数字典, 错误说明)。"""
    结果: dict[str, str] = {}
    for 键名 in 键名列表:
        文本, 说明 = _目录参数(键名, 参数.get(键名))
        if 说明:
            return {}, 说明
        if 文本:
            结果[键名] = 文本
    return 结果, ""


def _制品接入(参数: dict[str, Any]):
    """按参数构造 平台客户端制品接入；目录项为空即取实现层默认值。

    `客户端制品目录` 不是公开参数：它由 制品根目录 派生（与调用方原口径
    `制品根目录/平台客户端制品` 完全一致），避免同一事有两套口径。
    """
    from 平台控制面.包仓库.平台客户端制品 import 平台客户端制品接入

    实参: dict[str, Any] = {}
    for 键名 in ("状态目录", "制品根目录", "环境目录", "信任目录"):
        文本 = _文本(参数.get(键名))
        if 文本:
            实参[键名] = Path(文本)
    if "制品根目录" in 实参:
        实参["客户端制品目录"] = 实参["制品根目录"] / "平台客户端制品"
    return 平台客户端制品接入(**实参)


def 校验平台客户端制品(制品摘要: str = "", 状态目录: str = "", 制品根目录: str = "",
                      环境目录: str = "", 信任目录: str = "") -> Any:
    """校验平台客户端制品：Ed25519 签名 + 磁盘逐一摘要 + 信任元数据目标校验。

    返回 `{通过, 消息}`；`通过=False` 是**校验结论**（不是调用失败），
    消息逐字沿用实现层原文，调用方据此映射自己的错误码。
    """
    from 公共契约.基础类型.结果类型 import 结果

    摘要 = _文本(制品摘要)
    if not 摘要:
        return 结果.失败(错误_参数不合法, "制品摘要不能为空", 来源="包仓库")
    目录参数, 说明 = _目录字典(
        {"状态目录": 状态目录, "制品根目录": 制品根目录,
         "环境目录": 环境目录, "信任目录": 信任目录},
        ("状态目录", "制品根目录", "环境目录", "信任目录"))
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    接入 = _制品接入(目录参数)
    try:
        通过, 消息 = 接入.校验制品(摘要)
    finally:
        接入.关闭()
    return 结果.成功结果({"通过": bool(通过), "消息": str(消息)})


def 校验平台客户端稳定路径(状态目录: str = "", 制品根目录: str = "",
                          环境目录: str = "", 信任目录: str = "",
                          客户端制品目录: str = "") -> Any:
    """校验平台客户端稳定路径：指针可读 → 已安装目录存在 → 摘要一致 → 制品目录一致。

    返回 `{有效, 消息, 激活路径}`；`激活路径` 为文本型（未通过时为空串），
    调用方可直接 `Path(激活路径).resolve()`。
    """
    from 公共契约.基础类型.结果类型 import 结果

    目录参数, 说明 = _目录字典(
        {"状态目录": 状态目录, "制品根目录": 制品根目录, "环境目录": 环境目录,
         "信任目录": 信任目录, "客户端制品目录": 客户端制品目录},
        ("状态目录", "制品根目录", "环境目录", "信任目录", "客户端制品目录"))
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    接入 = _制品接入(目录参数)
    try:
        有效, 消息, 激活路径 = 接入.校验稳定路径()
    finally:
        接入.关闭()
    return 结果.成功结果({
        "有效": bool(有效), "消息": str(消息),
        "激活路径": str(激活路径) if 激活路径 is not None else "",
    })


def 安装候选包(仓库根目录: str = "", 包目录: str = "") -> Any:
    """安装候选包到不可变版本目录，返回 `{安装路径,包id,版本,完整性摘要}`。

    同包同版本不可覆盖、包结构不全即失败——判定全部由 版本仓库 实现层负责，
    本能力只做参数校验与结果收口；安装失败返回 `候选包安装失败` + 实现层原文说明。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.版本仓库 import 包仓库

    仓库文本, 说明 = _目录参数("仓库根目录", 仓库根目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    if not 仓库文本:
        return 结果.失败(错误_参数不合法, "仓库根目录不能为空", 来源="包仓库")
    源文本, 说明 = _目录参数("包目录", 包目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    if not 源文本:
        return 结果.失败(错误_参数不合法, "包目录不能为空", 来源="包仓库")
    仓库 = 包仓库(Path(仓库文本))
    成功, 结果值 = 仓库.安装(Path(源文本))
    if not 成功 or isinstance(结果值, str):
        return 结果.失败("候选包安装失败", str(结果值), 来源="包仓库")
    return 结果.成功结果({
        "安装路径": str(结果值.安装路径),
        "包id": str(结果值.包id),
        "版本": str(结果值.版本),
        "完整性摘要": str(结果值.完整性摘要),
    })


def 校验已安装包完整性(仓库根目录: str = "", 包id: str = "", 版本: str = "",
                      期望摘要: str = "") -> Any:
    """校验已安装版本的完整性摘要，返回 `{校验成功,证据}`。

    `校验成功=False` 是**校验结论**（摘要漂移/未安装），证据逐字沿用实现层原文；
    调用方据此判定「篡改后必须被拒绝」这类反向场景。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.版本仓库 import 包仓库

    仓库文本, 说明 = _目录参数("仓库根目录", 仓库根目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    if not 仓库文本:
        return 结果.失败(错误_参数不合法, "仓库根目录不能为空", 来源="包仓库")
    包id文本, 版本文本 = _文本(包id), _文本(版本)
    if not 包id文本 or not 版本文本:
        return 结果.失败(错误_参数不合法, "包id 与 版本 不能为空", 来源="包仓库")
    仓库 = 包仓库(Path(仓库文本))
    校验成功, 证据 = 仓库.校验完整性(包id文本, 版本文本, _文本(期望摘要))
    return 结果.成功结果({"校验成功": bool(校验成功), "证据": str(证据)})


def 校验可重复构建(冻结输入: dict | None = None, 变化输入: dict | None = None,
                  工作区根目录: str = "") -> Any:
    """校验可重复构建：同输入双工作区摘要一致 + 输入变化摘要必须变化。

    返回 `{双工作区一致,基线摘要,变化摘要,消息}`。
    `基线摘要` = 冻结输入在两处全新工作区构建出的文件摘要表（一致时两者相同）；
    `变化摘要` = 变化输入在同一构建器下构建出的文件摘要表。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.可复现构建器 import 可复现构建器

    if not isinstance(冻结输入, dict):
        return 结果.失败(错误_参数不合法, "冻结输入 必须是对象", 来源="包仓库")
    if not isinstance(变化输入, dict):
        return 结果.失败(错误_参数不合法, "变化输入 必须是对象", 来源="包仓库")
    for 名称, 输入 in (("冻结输入", 冻结输入), ("变化输入", 变化输入)):
        说明 = _构建输入问题(名称, 输入)
        if 说明:
            return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    工作区文本, 说明 = _目录参数("工作区根目录", 工作区根目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    构建器 = 可复现构建器()
    一致, 基线摘要, _, 消息 = 构建器.双工作区验证(冻结输入)
    临时根: Path | None = None
    try:
        if 工作区文本:
            工作区 = Path(工作区文本)
            工作区.mkdir(parents=True, exist_ok=True)
        else:
            临时根 = Path(tempfile.mkdtemp(prefix="可重复构建校验_"))
            工作区 = 临时根
        变化摘要 = 构建器.构建摘要(构建器.构建(变化输入, 工作区)[0])
    finally:
        if 临时根 is not None:
            shutil.rmtree(临时根, ignore_errors=True)
    return 结果.成功结果({
        "双工作区一致": bool(一致), "基线摘要": 基线摘要,
        "变化摘要": 变化摘要, "消息": str(消息),
    })


def _构建输入问题(名称: str, 输入: Any) -> str:
    """校验一份构建输入：必须是含非空文件表的对象，且文件内容必须都是文本。"""
    if not isinstance(输入, dict):
        return f"{名称} 必须是对象"
    文件表 = 输入.get("文件表")
    if not isinstance(文件表, dict) or not 文件表:
        return f"{名称} 必须包含非空 文件表"
    for 路径, 内容 in 文件表.items():
        if not isinstance(路径, str) or not isinstance(内容, str):
            return f"{名称} 文件表的路径与内容都必须是文本"
    return ""


def 校验可信仓库元数据(存储目录: str = "") -> Any:
    """校验可信仓库元数据：根信任/目标/快照三类真实签名校验 + 替换攻击必须阻断。

    返回 `{根信任通过,目标通过,快照通过,替换攻击阻断,原因}`。
    在给定存储目录内真实初始化根信任、发布目标制品、生成快照，再用**被替换**
    的目标摘要做一次反向校验——`替换攻击阻断=True` 表示反向校验确实失败。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.可信仓库元数据 import 可信仓库元数据
    from 支持库.适配层 import 内容摘要

    目录文本, 说明 = _目录参数("存储目录", 存储目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    目录 = Path(目录文本) if 目录文本 else _默认可信仓库目录
    仓库 = 可信仓库元数据(目录)
    根信任 = 仓库.初始化()
    内容 = "可信仓库元数据校验探测内容".encode("utf-8")
    目标 = 仓库.发布目标("探测包", "1.0.0", 内容摘要(内容), 制品内容=内容)
    快照 = 仓库.生成快照()
    根信任通过, 根信任原因 = 仓库.校验元数据("根信任", 根信任)
    目标通过, 目标原因 = 仓库.校验元数据("目标", 目标)
    快照通过, 快照原因 = 仓库.校验元数据("快照", 快照)
    篡改 = dict(目标)
    篡改["制品摘要"] = 内容摘要("被替换的制品内容".encode("utf-8"))
    反向通过, 反向原因 = 仓库.校验元数据("目标", 篡改)
    原因表 = [名称 for 名称, 通过 in (("根信任", 根信任通过), ("目标", 目标通过),
                                      ("快照", 快照通过)) if not 通过]
    if 原因表:
        细节 = "；".join((根信任原因, 目标原因, 快照原因))
        原因 = f"{'、'.join(原因表)} 校验未通过：{细节}"
    else:
        原因 = ""
    return 结果.成功结果({
        "根信任通过": bool(根信任通过), "目标通过": bool(目标通过),
        "快照通过": bool(快照通过), "替换攻击阻断": bool(not 反向通过),
        "原因": 原因 or (f"替换攻击阻断原因：{反向原因}" if not 反向通过 else ""),
    })


def 校验包生命周期(包id: str = "", 版本: str = "1.0.0") -> Any:
    """校验包生命周期状态机：合法流转/非法流转/重复操作/故障回滚全部真实执行。

    返回 `{问题列表}`；列表为空表示状态机全部判定符合契约。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.生命周期 import 包生命周期

    包id文本 = _文本(包id)
    if not 包id文本:
        return 结果.失败(错误_参数不合法, "包id 不能为空", 来源="包仓库")
    状态机 = 包生命周期(包id文本, _文本(版本) or "1.0.0")
    问题: list[str] = []
    for 目标 in ("安装中", "已安装", "校验中", "已校验", "已解析", "启动中", "已就绪"):
        记录 = 状态机.流转(目标)
        if not 记录.成功:
            问题.append(f"合法流转失败: {目标}（{记录.错误码}）")
    非法记录 = 状态机.流转("安装中")
    if 非法记录.成功:
        问题.append("非法流转未被拒绝: 已就绪→安装中")
    状态机.流转("已激活")
    重复记录 = 状态机.流转("已激活")
    if not 重复记录.成功:
        问题.append("重复操作非幂等")
    故障记录 = 状态机.流转("故障")
    if not 故障记录.成功:
        问题.append("故障流转失败")
    状态机.回滚("包生命周期校验探测")
    if 状态机.状态 == "回滚中":
        问题.append("失败回滚未恢复")
    return 结果.成功结果({"问题列表": 问题})


