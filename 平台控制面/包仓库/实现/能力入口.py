def _文本(值: Any) -> str:
    """目录/摘要类参数归一：None 视为空串，其余转文本并去首尾空白。"""
    return "" if 值 is None else str(值).strip()


def _PEM文本(值: Any) -> str:
    """PEM 参数**逐字透传**：只把 None 视为空串，**不做任何去空白**。

    为什么不能用 `_文本()`（2026-09-21 实测根因，债务 #190）：`_文本` 自述是
    「目录/摘要类参数归一」，会 `.strip()`；而 PEM 是**逐字比较**的凭据 ——
    信任记录里的 `公钥` 存的是**带尾部换行**的 113 字节（`生成或读取密钥` 从
    `发布者公钥.pem` 原样读出），调用方（构建脚本）也原样传进来。一旦在能力
    包装层 strip 成 112 字节，`平台客户端制品.py` 的
    `elif 信任记录["公钥"] != 公钥PEM` 就必然成立 ⇒ 每次 `入库客户端制品`
    都报「发布者公钥与既有信任记录不一致」，而磁盘上两侧**逐字相同**
    （实测：能力返回／库内记录／盘上文件三方均 113 字节且相等，却仍报不一致）。

    修法是**停止改写调用方给的值**，不是把比较改成宽松匹配 —— 后者会把
    fail-closed 变成假绿，并掩盖真因。
    """
    return "" if 值 is None else str(值)


def _目录参数(键名: str, 值: Any) -> tuple[str, str]:
    """校验一个目录参数：非空且已存在时必须是目录（是文件即 参数不合法）。

    返回值 = (规范化文本, 错误说明)；错误说明为空表示通过。
    目录不存在是合法输入（实现层按「未安装/从未发布」正确处理），
    不在这里代为创建，也不静默改写调用方给的路径。
    """
    文本 = _文本(值)
    if not 文本:
        return "", ""
    路径 = Path(文本)
    if 路径.exists() and not 路径.is_dir():
        return "", f"{键名} 已存在但不是目录: {文本}"
    return 文本, ""


def _目录字典(参数: dict[str, Any], 键名列表: tuple[str, ...]) -> tuple[dict[str, str], str]:
    """批量校验目录参数，返回 (只含非空项的参数字典, 错误说明)。"""
    结果: dict[str, str] = {}
    for 键名 in 键名列表:
        文本, 说明 = _目录参数(键名, 参数.get(键名))
        if 说明:
            return {}, 说明
        if 文本:
            结果[键名] = 文本
    return 结果, ""


def _制品接入(参数: dict[str, Any]):
    """按参数构造 平台客户端制品接入；目录项为空即取实现层默认值。

    `客户端制品目录` 不是公开参数：它由 制品根目录 派生（与调用方原口径
    `制品根目录/平台客户端制品` 完全一致），避免同一事有两套口径。
    """
    from 平台控制面.包仓库.平台客户端制品 import 平台客户端制品接入

    实参: dict[str, Any] = {}
    for 键名 in ("状态目录", "制品根目录", "环境目录", "信任目录"):
        文本 = _文本(参数.get(键名))
        if 文本:
            实参[键名] = Path(文本)
    if "制品根目录" in 实参:
        实参["客户端制品目录"] = 实参["制品根目录"] / "平台客户端制品"
    return 平台客户端制品接入(**实参)


def 校验平台客户端制品(制品摘要: str = "", 状态目录: str = "", 制品根目录: str = "",
                      环境目录: str = "", 信任目录: str = "") -> Any:
    """校验平台客户端制品：Ed25519 签名 + 磁盘逐一摘要 + 信任元数据目标校验。

    返回 `{通过, 消息}`；`通过=False` 是**校验结论**（不是调用失败），
    消息逐字沿用实现层原文，调用方据此映射自己的错误码。
    """
    from 公共契约.基础类型.结果类型 import 结果

    摘要 = _文本(制品摘要)
    if not 摘要:
        return 结果.失败(错误_参数不合法, "制品摘要不能为空", 来源="包仓库")
    目录参数, 说明 = _目录字典(
        {"状态目录": 状态目录, "制品根目录": 制品根目录,
         "环境目录": 环境目录, "信任目录": 信任目录},
        ("状态目录", "制品根目录", "环境目录", "信任目录"))
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    接入 = _制品接入(目录参数)
    try:
        通过, 消息 = 接入.校验制品(摘要)
    finally:
        接入.关闭()
    return 结果.成功结果({"通过": bool(通过), "消息": str(消息)})


