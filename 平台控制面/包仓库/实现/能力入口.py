def 校验可重复构建(冻结输入: dict | None = None, 变化输入: dict | None = None,
                  工作区根目录: str = "", 开工ID: str | None = None) -> Any:
    """校验可重复构建：同输入双工作区摘要一致 + 输入变化摘要必须变化。

    返回 `{双工作区一致,基线摘要,变化摘要,消息}`。
    `基线摘要` = 冻结输入在两处全新工作区构建出的文件摘要表（一致时两者相同）；
    `变化摘要` = 变化输入在同一构建器下构建出的文件摘要表。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.可复现构建器 import 可复现构建器

    if not isinstance(冻结输入, dict):
        return 结果.失败(错误_参数不合法, "冻结输入 必须是对象", 来源="包仓库")
    if not isinstance(变化输入, dict):
        return 结果.失败(错误_参数不合法, "变化输入 必须是对象", 来源="包仓库")
    for 名称, 输入 in (("冻结输入", 冻结输入), ("变化输入", 变化输入)):
        说明 = _构建输入问题(名称, 输入)
        if 说明:
            return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    工作区文本, 说明 = _目录参数("工作区根目录", 工作区根目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    构建器 = 可复现构建器()
    一致, 基线摘要, _, 消息 = 构建器.双工作区验证(冻结输入)
    临时根: Path | None = None
    try:
        if 工作区文本:
            工作区 = Path(工作区文本)
            工作区.mkdir(parents=True, exist_ok=True)
        else:
            临时根 = Path(tempfile.mkdtemp(prefix="可重复构建校验_"))
            工作区 = 临时根
        变化摘要 = 构建器.构建摘要(构建器.构建(变化输入, 工作区)[0])
    finally:
        if 临时根 is not None:
            shutil.rmtree(临时根, ignore_errors=True)
    return 结果.成功结果({
        "双工作区一致": bool(一致), "基线摘要": 基线摘要,
        "变化摘要": 变化摘要, "消息": str(消息),
    })


def _构建输入问题(名称: str, 输入: Any) -> str:
    """校验一份构建输入：必须是含非空文件表的对象，且文件内容必须都是文本。"""
    if not isinstance(输入, dict):
        return f"{名称} 必须是对象"
    文件表 = 输入.get("文件表")
    if not isinstance(文件表, dict) or not 文件表:
        return f"{名称} 必须包含非空 文件表"
    for 路径, 内容 in 文件表.items():
        if not isinstance(路径, str) or not isinstance(内容, str):
            return f"{名称} 文件表的路径与内容都必须是文本"
    return ""


def 校验可信仓库元数据(存储目录: str = "", 开工ID: str | None = None) -> Any:
    """校验可信仓库元数据：根信任/目标/快照三类真实签名校验 + 替换攻击必须阻断。

    返回 `{根信任通过,目标通过,快照通过,替换攻击阻断,原因}`。
    在给定存储目录内真实初始化根信任、发布目标制品、生成快照，再用**被替换**
    的目标摘要做一次反向校验——`替换攻击阻断=True` 表示反向校验确实失败。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.可信仓库元数据 import 可信仓库元数据
    from 支持库.适配层 import 内容摘要

    目录文本, 说明 = _目录参数("存储目录", 存储目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    目录 = Path(目录文本) if 目录文本 else _默认可信仓库目录
    仓库 = 可信仓库元数据(目录)
    根信任 = 仓库.初始化()
    内容 = "可信仓库元数据校验探测内容".encode("utf-8")
    目标 = 仓库.发布目标("探测包", "1.0.0", 内容摘要(内容), 制品内容=内容)
    快照 = 仓库.生成快照()
    根信任通过, 根信任原因 = 仓库.校验元数据("根信任", 根信任)
    目标通过, 目标原因 = 仓库.校验元数据("目标", 目标)
    快照通过, 快照原因 = 仓库.校验元数据("快照", 快照)
    篡改 = dict(目标)
    篡改["制品摘要"] = 内容摘要("被替换的制品内容".encode("utf-8"))
    反向通过, 反向原因 = 仓库.校验元数据("目标", 篡改)
    原因表 = [名称 for 名称, 通过 in (("根信任", 根信任通过), ("目标", 目标通过),
                                      ("快照", 快照通过)) if not 通过]
    if 原因表:
        细节 = "；".join((根信任原因, 目标原因, 快照原因))
        原因 = f"{'、'.join(原因表)} 校验未通过：{细节}"
    else:
        原因 = ""
    return 结果.成功结果({
        "根信任通过": bool(根信任通过), "目标通过": bool(目标通过),
        "快照通过": bool(快照通过), "替换攻击阻断": bool(not 反向通过),
        "原因": 原因 or (f"替换攻击阻断原因：{反向原因}" if not 反向通过 else ""),
    })


def 校验包生命周期(包id: str = "", 版本: str = "1.0.0") -> Any:
    """校验包生命周期状态机：合法流转/非法流转/重复操作/故障回滚全部真实执行。

    返回 `{问题列表}`；列表为空表示状态机全部判定符合契约。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.生命周期 import 包生命周期

    包id文本 = _文本(包id)
    if not 包id文本:
        return 结果.失败(错误_参数不合法, "包id 不能为空", 来源="包仓库")
    状态机 = 包生命周期(包id文本, _文本(版本) or "1.0.0")
    问题: list[str] = []
    for 目标 in ("安装中", "已安装", "校验中", "已校验", "已解析", "启动中", "已就绪"):
        记录 = 状态机.流转(目标)
        if not 记录.成功:
            问题.append(f"合法流转失败: {目标}（{记录.错误码}）")
    非法记录 = 状态机.流转("安装中")
    if 非法记录.成功:
        问题.append("非法流转未被拒绝: 已就绪→安装中")
    状态机.流转("已激活")
    重复记录 = 状态机.流转("已激活")
    if not 重复记录.成功:
        问题.append("重复操作非幂等")
    故障记录 = 状态机.流转("故障")
    if not 故障记录.成功:
        问题.append("故障流转失败")
    状态机.回滚("包生命周期校验探测")
    if 状态机.状态 == "回滚中":
        问题.append("失败回滚未恢复")
    return 结果.成功结果({"问题列表": 问题})


