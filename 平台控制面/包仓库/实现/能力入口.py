def _数值(值: Any) -> float | None:
    """把数值参数归一为浮点数；不可解析返回 None（由调用点判 参数不合法）。"""
    try:
        return float(值)
    except (TypeError, ValueError):
        return None


def _公钥问题(公钥文本: str) -> str:
    """公钥 PEM 结构校验：必须是公钥块，且明确拒绝把私钥当公钥登记。"""
    if not 公钥文本:
        return "公钥PEM 不能为空"
    if "PRIVATE KEY" in 公钥文本:
        return "公钥PEM 是私钥（私钥不得登记为发布者公钥）"
    if not 公钥文本.startswith("-----BEGIN PUBLIC KEY-----") \
            or not 公钥文本.rstrip().endswith("-----END PUBLIC KEY-----"):
        return "公钥PEM 不是合法的 SubjectPublicKeyInfo 公钥块（缺 BEGIN/END PUBLIC KEY 边界）"
    return ""


def _私钥问题(私钥文本: str) -> str:
    """私钥 PEM 结构校验：必须是私钥块（私钥只经参数进出，不落盘、不进返回）。"""
    if not 私钥文本:
        return "私钥PEM 不能为空"
    if "PRIVATE KEY" not in 私钥文本:
        return "私钥PEM 不是合法的私钥块（缺 PRIVATE KEY 边界）"
    return ""


def _生产目录(参数: dict[str, Any]) -> tuple[dict[str, str], str]:
    """校验生产链两个目录参数（状态目录/制品根目录），返回 (参数字典, 错误说明)。"""
    return _目录字典({"状态目录": 参数.get("状态目录"), "制品根目录": 参数.get("制品根目录")},
                     ("状态目录", "制品根目录"))


def _生产仓库(目录参数: dict[str, str]):
    """按目录参数构造 服务.包仓库 与其平台状态；返回 (仓库, 状态)，状态由调用方关闭。"""
    from 平台控制面.平台状态 import 平台状态
    from 平台控制面.包仓库.服务 import 包仓库

    状态 = 平台状态(Path(目录参数.get("状态目录") or _默认状态目录), 项目id="平台控制面")
    仓库 = 包仓库(状态, 制品根目录=Path(目录参数.get("制品根目录") or _默认制品根目录))
    return 仓库, 状态


def 登记发布者(发布者: str = "", 公钥PEM: str = "", 有效期秒: float = 31536000.0,
               维护者: str = "", 状态目录: str = "", 制品根目录: str = "") -> Any:
    """登记发布者：把发布者身份与公钥写入信任目录（复用 签名能力.登记发布者）。

    返回 `{发布者,状态,过期时间,公钥指纹}`；四个事实全部取自**登记后重读**的信任记录——
    实现层 登记发布者 无返回值，调用方要的结论靠重读拿到，不靠猜、不靠传入参数回显。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 支持库.适配层 import 内容摘要

    发布者文本, 公钥文本 = _文本(发布者), _文本(公钥PEM)
    if not 发布者文本:
        return 结果.失败(错误_参数不合法, "发布者不能为空", 来源="包仓库")
    说明 = _公钥问题(公钥文本)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    秒数 = _数值(有效期秒)
    if 秒数 is None or 秒数 <= 0:
        return 结果.失败(错误_参数不合法, f"有效期秒 必须是正数（实收 {有效期秒!r}）", 来源="包仓库")
    目录参数, 说明 = _生产目录({"状态目录": 状态目录, "制品根目录": 制品根目录})
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    仓库, 状态 = _生产仓库(目录参数)
    try:
        仓库.登记发布者(发布者=发布者文本, 公钥PEM=公钥文本, 有效期秒=秒数,
                        维护者=_文本(维护者))
        记录 = 状态.读取记录("信任", "发布者", 发布者文本)
    finally:
        状态.关闭()
    if not 记录:
        return 结果.失败(错误_发布者登记未落盘, f"登记后信任目录没有该发布者记录: {发布者文本}",
                         来源="包仓库")
    return 结果.成功结果({
        "发布者": 发布者文本,
        "状态": str(记录.get("状态", "")),
        "过期时间": str(记录.get("过期时间", "")),
        "公钥指纹": 内容摘要(公钥文本.encode("utf-8"))[:16],
    })


def 撤销发布者(发布者: str = "", 维护者: str = "", 状态目录: str = "",
               制品根目录: str = "") -> Any:
    """撤销发布者：把信任记录状态置为已撤销（复用 签名能力.撤销发布者）。

    先读信任目录确认发布者存在，再执行撤销——「从未登记」与「已撤销」是两件事，
    返回 `{已撤销,状态,消息}` 区分：未登记判 发布者不存在，已撤销为 幂等无操作。
    """
    from 公共契约.基础类型.结果类型 import 结果

    发布者文本 = _文本(发布者)
    if not 发布者文本:
        return 结果.失败(错误_参数不合法, "发布者不能为空", 来源="包仓库")
    目录参数, 说明 = _生产目录({"状态目录": 状态目录, "制品根目录": 制品根目录})
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    仓库, 状态 = _生产仓库(目录参数)
    try:
        记录 = 状态.读取记录("信任", "发布者", 发布者文本)
        if 记录 is None:
            return 结果.失败(错误_发布者不存在, f"信任目录没有该发布者记录: {发布者文本}",
                             来源="包仓库")
        已撤销 = 仓库.撤销发布者(发布者=发布者文本, 维护者=_文本(维护者))
        撤销后 = 状态.读取记录("信任", "发布者", 发布者文本)
    finally:
        状态.关闭()
    状态文本 = str((撤销后 or 记录).get("状态", ""))
    if not 已撤销:
        return 结果.成功结果({
            "已撤销": False, "状态": 状态文本,
            "消息": f"无可撤销的有效信任记录（当前状态 {状态文本}）: {发布者文本}",
        })
    return 结果.成功结果({
        "已撤销": True, "状态": 状态文本,
        "消息": f"发布者已撤销（重读状态 {状态文本}）: {发布者文本}",
    })


def 构建制品(包id: str = "", 版本: str = "", 文件表: dict | None = None,
             构建输入: dict | None = None, 状态目录: str = "", 制品根目录: str = "") -> Any:
    """构建制品：冻结输入经内容寻址落盘（复用 服务.包仓库.构建制品）。

    临时目录构建 → 路径安全校验 → 摘要 → 原子发布，全部由实现层负责；
    返回 `{制品摘要,包id,版本,消息}`，制品摘要即内容寻址目录名。
    """
    from 公共契约.基础类型.结果类型 import 结果

    包id文本, 版本文本 = _文本(包id), _文本(版本)
    if not 包id文本:
        return 结果.失败(错误_参数不合法, "包id 不能为空", 来源="包仓库")
    if not 版本文本:
        return 结果.失败(错误_参数不合法, "版本 不能为空", 来源="包仓库")
    if not isinstance(文件表, dict) or not 文件表:
        return 结果.失败(错误_参数不合法, "文件表 必须是非空对象（相对路径 → 文件内容）",
                         来源="包仓库")
    for 路径, 内容 in 文件表.items():
        if not isinstance(路径, str) or not isinstance(内容, str):
            return 结果.失败(错误_参数不合法, "文件表的路径与内容都必须是文本", 来源="包仓库")
    if not isinstance(构建输入, dict):
        return 结果.失败(错误_参数不合法, "构建输入 必须是对象（构建来源证据）", 来源="包仓库")
    目录参数, 说明 = _生产目录({"状态目录": 状态目录, "制品根目录": 制品根目录})
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    仓库, 状态 = _生产仓库(目录参数)
    try:
        成功, 消息, 制品摘要 = 仓库.构建制品(
            包id=包id文本, 版本=版本文本, 文件表=文件表, 构建输入=构建输入)
    finally:
        状态.关闭()
    if not 成功:
        return 结果.失败(错误_制品构建失败, str(消息), 来源="包仓库")
    return 结果.成功结果({
        "制品摘要": str(制品摘要), "包id": 包id文本, "版本": 版本文本, "消息": str(消息),
    })


