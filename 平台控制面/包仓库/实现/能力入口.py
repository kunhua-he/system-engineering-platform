def 查询制品布局(制品根目录: str = "", 制品摘要: str = "") -> Any:
    """查询制品布局（只读）：把实现层的制品目录口径变成能力，调用方不再直取属性拼路径。

    返回 `{制品根目录,客户端制品目录,制品路径,根目录存在}`：
    目录项留空取实现层默认根目录（工程缓存/制品仓库，与 平台客户端制品接入 同口径，
    且为绝对路径，不受调用方工作目录影响）；给 制品摘要 时 制品路径 = 制品根目录/制品摘要，
    即内容寻址目录（`制品根目录` 属性直取 `仓库.制品根目录 / 制品摘要` 的等价合法路径）。
    **只读**：只做路径推导与存在性判断，不创建任何目录、不写任何仓库事实。
    """
    from 公共契约.基础类型.结果类型 import 结果

    根文本, 说明 = _目录参数("制品根目录", 制品根目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    根 = Path(根文本) if 根文本 else _默认制品根目录
    摘要 = _文本(制品摘要)
    if 摘要 and len(摘要) != 32:
        return 结果.失败(错误_参数不合法,
                         f"制品摘要 必须是内容寻址摘要（sha256 前 32 位），实收 {len(摘要)} 位",
                         来源="包仓库")
    return 结果.成功结果({
        "制品根目录": str(根),
        "客户端制品目录": str(根 / "平台客户端制品"),
        "制品路径": str(根 / 摘要) if 摘要 else "",
        "根目录存在": 根.is_dir(),
    })


