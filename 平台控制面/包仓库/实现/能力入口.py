# （`开发文档/方案/客户端构建能力化落地方案_20260917.md` §1.1 实测）。而三条激活指针与
# 入库/安装编排所需的一切（内容寻址、签名、信任元数据、发布管理 CAS、当前.json 唯一
# 落盘点）**全部已在本包内**：本层只做参数校验、目录缺省与结果收口，语义仍落在
# `平台客户端制品.py` / `激活指针面.py` 的既有实现里（本模块头承诺的收口口径，不复制语义）。
#
# 【调用面】`客户端/构建平台客户端.py` 的构建链编排经能力 id 调用本层三条；
# `参数不合法`/`目标不存在`/`摘要不符`/`验证失败`/`制品安装失败`/`写入失败` 六个码
# 全部取自已登记状态映射（`运行核心/统一网关/本地网关.py:公开错误码状态映射`），
# 不新造码 —— 新造码会被 `开发工具/公开调用完整性门禁.py::检查错误码登记` 判红。
# ============================================================================

错误_目标不存在 = "目标不存在"
错误_文件读取失败 = "文件读取失败"
错误_验证失败 = "验证失败"
错误_写入失败 = "写入失败"

#: 客户端链四个目录参数（六条能力共用同一口径：留空取实现层默认目录）。
#: `客户端制品目录` 不是公开参数：由 制品根目录 派生（与调用方原口径
#: `<制品根目录>/平台客户端制品` 逐字一致），避免同一事两套口径。
_客户端链目录键 = ("状态目录", "制品根目录", "环境目录", "信任目录")


def _客户端接入(参数: dict[str, Any]) -> tuple[Any, str]:
    """按参数构造 `平台客户端制品接入`；返回 `(接入对象, 错误说明)`。

    错误说明非空 = 某个目录参数已存在但不是目录（判 `参数不合法`），此时不构造对象。
    目录不存在是**合法输入**（实现层按「从未安装/从未构建」正确处理），此处不代为创建。
    """
    from 平台控制面.包仓库.平台客户端制品 import 平台客户端制品接入

    目录参数, 说明 = _目录字典(参数, _客户端链目录键)
    if 说明:
        return None, 说明
    实参: dict[str, Any] = {键名: Path(值) for 键名, 值 in 目录参数.items()}
    if "制品根目录" in 实参:
        实参["客户端制品目录"] = 实参["制品根目录"] / "平台客户端制品"
    return 平台客户端制品接入(**实参), ""


def 诊断平台客户端激活指针(状态目录: str = "", 制品根目录: str = "",
                           环境目录: str = "", 信任目录: str = "",
                           自动收尾: bool = 真, 开工ID: str | None = None) -> Any:
    """诊断平台客户端激活指针（D-17 ① 的可诊断出口）：源与已安装**双边**判定陈旧。

    返回 `{陈旧,可继续,原因,陈旧级别,源符合,已安装符合,摘要16,制品名,制品摘要,必经路径}`，
    十项全部逐字沿用实现层 `激活指针面.诊断激活指针` 的结论：`陈旧` 只在源制品目录与
    已安装副本**都对不上**时报真（单边不符只记 `陈旧级别` 且 `可继续=真`）。

    `自动收尾`（缺省真）= 实现层的「必经路径收尾」：归一到制品根 `当前.json` 的唯一 schema
    并按上限回收过期制品；置 `假` 得到**纯只读**结论（隔离断言用）。
    """
    from 公共契约.基础类型.结果类型 import 结果

    接入, 说明 = _客户端接入({"状态目录": 状态目录, "制品根目录": 制品根目录,
                               "环境目录": 环境目录, "信任目录": 信任目录})
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    try:
        结论 = 接入.诊断激活指针(自动收尾=bool(自动收尾))
    finally:
        接入.关闭()
    return 结果.成功结果({
        "陈旧": bool(结论["陈旧"]), "可继续": bool(结论["可继续"]),
        "原因": str(结论["原因"]), "陈旧级别": str(结论["陈旧级别"]),
        "源符合": bool(结论["源符合"]), "已安装符合": bool(结论["已安装符合"]),
        "摘要16": str(结论["摘要16"]), "制品名": str(结论["制品名"]),
        "制品摘要": str(结论["制品摘要"]),
        "必经路径": dict(结论.get("必经路径") or {}),
    })


def 重建平台客户端激活指针(状态目录: str = "", 制品根目录: str = "",
                           环境目录: str = "", 信任目录: str = "",
                           开工ID: str | None = None) -> Any:
    """按**已安装副本**重建激活指针（D-17 ① 的修复出口）：不重复安装、不碰制品仓库。

    只把 `环境目录/当前.json` 的摘要字段改回已安装副本的实算摘要（内容寻址字段不变），
    使稳定路径立刻恢复可读。返回 `{已重建,消息,原摘要,新摘要,已安装路径}`。

    错误码映射（实现层结论原文 → 已登记码，逐条在下方判据里写死，不按文案猜）：
    已安装副本不存在 → `目标不存在`（须先安装或重置）；已安装副本摘要不合法或指针不可读
    → `文件读取失败`（须人工确认后重置）。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.制品布局 import 计算目录摘要16, 摘要前缀长度

    接入, 说明 = _客户端接入({"状态目录": 状态目录, "制品根目录": 制品根目录,
                               "环境目录": 环境目录, "信任目录": 信任目录})
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    try:
        已安装 = 接入.环境目录 / "平台客户端"
        原摘要 = ""
        try:
            from 平台控制面.包仓库.激活指针 import 读取激活指针, 指针文件名
            原指针 = 读取激活指针(接入.环境目录 / 指针文件名)
            原摘要 = str((原指针 or {}).get("摘要sha256", ""))
        except (OSError, ValueError):
            原摘要 = ""
        成功, 消息 = 接入.重建激活指针()
        新摘要 = 计算目录摘要16(已安装) if 已安装.is_dir() else ""
    finally:
        接入.关闭()
    if not 成功:
        # 实现层只有两条失败出口，逐条对应已登记码（不按文案猜，也不用摘要长度兜底）：
        # ① 已安装副本不存在 → 目标不存在（须先安装或重置）；
        # ② 已安装副本在但指针不可读 → 文件读取失败（须人工确认后重置）。
        码 = 错误_目标不存在 if not 已安装.is_dir() else 错误_文件读取失败
        return 结果.失败(码, str(消息), 来源="包仓库")
    return 结果.成功结果({
        "已重建": 真, "消息": str(消息), "原摘要": 原摘要,
        "新摘要": 新摘要, "已安装路径": str(已安装),
    })


def 重置平台客户端激活指针(状态目录: str = "", 制品根目录: str = "",
                           环境目录: str = "", 信任目录: str = "",
                           开工ID: str | None = None) -> Any:
    """清掉激活指针回到「从未安装」（D-17 ① 的修复出口）。

    只动 `环境目录/当前.json`：改名保存为 `当前.json.陈旧指针备份_<时间戳>`（**不删除**，
    留痕可回溯），不碰制品仓库、不碰已安装副本；发布管理的激活指针同批清空，避免留下
    「文件说没装、账本说已激活」的第二事实源。返回
    `{已重置,消息,备份路径,发布指针已清空}`。
    """
    from 公共契约.基础类型.结果类型 import 结果

    接入, 说明 = _客户端接入({"状态目录": 状态目录, "制品根目录": 制品根目录,
                               "环境目录": 环境目录, "信任目录": 信任目录})
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    指针文件 = 接入.环境目录 / "当前.json"
    已存在 = 指针文件.is_file()
    激活 = None
    try:
        try:
            激活 = 接入.发布.当前激活(接入.包id)
        except Exception:
            激活 = None
        try:
            成功, 消息 = 接入.重置激活指针()
        except OSError as 错误:
            return 结果.失败(错误_写入失败, f"重置激活指针写盘失败: {错误}", 来源="包仓库")
    finally:
        接入.关闭()
    if not 成功:
        return 结果.失败(错误_写入失败, str(消息), 来源="包仓库")
    备份 = ""
    for 项 in str(消息).split("；"):
        if 项.startswith("指针已备份:"):
            备份 = 项.split(":", 1)[1].strip()
    return 结果.成功结果({
        "已重置": 真, "消息": str(消息), "备份路径": 备份,
        "发布指针已清空": bool(已存在 and 激活),
    })


def 读取或生成客户端签名密钥(密钥目录: str = "", 开工ID: str | None = None) -> Any:
    """读取或生成客户端签名密钥（**落盘 + 复用**，非纯计算）。

    已有 `发布者私钥.pem` / `发布者公钥.pem` 即**原样复用**（这是与 `密码签名.生成密钥对`
    的本质差别：纯计算能力每次调用都换新钥，公钥会与既有信任记录不符，入库必判
    `发布者公钥与既有信任记录不一致`）；缺失才生成并落盘，权限加固为目录 700 /
    私钥 600 / 公钥 644。返回 `{私钥PEM,公钥PEM,已复用,密钥目录}`。

    密钥目录留空时取实现层默认目录（运行态根下的 `平台客户端密钥`）。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.包仓库.平台客户端制品 import 平台客户端制品接入

    目录文本, 说明 = _目录参数("密钥目录", 密钥目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    from 平台控制面.包仓库.制品布局 import 制品仓库缓存根
    from 平台控制面.包仓库.平台客户端制品 import 平台客户端制品接入

    目录 = Path(目录文本) if 目录文本 else None
    目标目录 = 目录 if 目录 is not None else 制品仓库缓存根() / "平台客户端密钥"
    try:
        已有 = bool((目标目录 / "发布者私钥.pem").is_file()
                    and (目标目录 / "发布者公钥.pem").is_file())
        私钥, 公钥 = 平台客户端制品接入.生成或读取密钥(目标目录)
    except OSError as 错误:
        return 结果.失败(错误_写入失败, f"客户端签名密钥落盘失败: {错误}", 来源="包仓库")
    return 结果.成功结果({
        "私钥PEM": str(私钥), "公钥PEM": str(公钥),
        "已复用": 已有, "密钥目录": str(目标目录),
    })


def 入库客户端制品(制品目录: str = "", 构建输入: dict | None = None,
                   私钥PEM: str = "", 公钥PEM: str = "",
                   状态目录: str = "", 制品根目录: str = "",
                   环境目录: str = "", 信任目录: str = "",
                   开工ID: str | None = None) -> Any:
    """入库客户端制品：把已构建的客户端制品登记到正式包仓库体系。

    一条能力覆盖「内容寻址登记 → 生成元数据落盘 → Ed25519 签名 → 磁盘信任元数据
    （根信任/目标/快照）→ 入库自检」五步编排（复用 `平台客户端制品.入库` 的**唯一实现**，
    本能力只做边界校验与结果收口）。同内容重复入库幂等；入库自检不过即判失败，
    拒报「假成功」。返回 `{制品摘要,制品名,消息}`。

    `制品目录` 必须是已构建的 `平台客户端-<摘要16>` 目录（目录名摘要与实算摘要必须一致）。
    副作用：写制品仓库（内容寻址目录 + 状态记录）、写信任目录（签名与信任元数据），
    并走实现层的必修路径收尾（归一指针 schema + 按上限回收过期制品）。
    """
    from 公共契约.基础类型.结果类型 import 结果

    目录文本, 说明 = _目录参数("制品目录", 制品目录)
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    if not 目录文本 or not Path(目录文本).is_dir():
        return 结果.失败(错误_目标不存在,
                         f"制品目录不存在（须先构建）: {目录文本 or '<空>'}", 来源="包仓库")
    if not isinstance(构建输入, dict) or not 构建输入:
        return 结果.失败(错误_参数不合法, "构建输入 必须是非空对象（构建来源证据）",
                         来源="包仓库")
    for 名称, 值 in (("私钥PEM", 私钥PEM), ("公钥PEM", 公钥PEM)):
        说明 = _私钥问题(_PEM文本(值)) if 名称 == "私钥PEM" else _公钥问题(_PEM文本(值))
        if 说明:
            return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    接入, 说明 = _客户端接入({"状态目录": 状态目录, "制品根目录": 制品根目录,
                               "环境目录": 环境目录, "信任目录": 信任目录})
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    try:
        成功, 消息, 制品摘要 = 接入.入库(
            制品目录=Path(目录文本), 构建输入=构建输入,
            私钥PEM=_PEM文本(私钥PEM), 公钥PEM=_PEM文本(公钥PEM))
    finally:
        接入.关闭()
    if not 成功:
        # 实现层把「目录名/摘要不符、签名失败、发布者公钥不一致、自检不过」等全部结论
        # 收在与 制品目录 相关的同一条失败回路上；码统一取已登记的 `验证失败`，
        # 原因逐字沿用实现层原文（不按文案猜码，也不新造码）。
        return 结果.失败(错误_验证失败, str(消息), 来源="包仓库")
    return 结果.成功结果({
        "制品摘要": str(制品摘要), "制品名": Path(目录文本).name, "消息": str(消息),
    })


def 安装平台客户端制品(制品摘要: str = "", 制品名: str = "",
                       状态目录: str = "", 制品根目录: str = "",
                       环境目录: str = "", 信任目录: str = "",
                       开工ID: str | None = None) -> Any:
    """安装平台客户端制品到环境：原子替换 + 发布管理 CAS 激活 + 同步 当前.json。

    与 `安装制品` 的**语义差别**（第 36 项已裁的「语义重复但不等价」，两条并存不合并）：
    `安装制品` 按调用方给的 `目标目录` 复制（受控根判定），**不做**发布管理激活、
    **不写** `环境目录/当前.json`；本能力固定装到 `<环境目录>/平台客户端`，并把
    「临时目录 + 逐文件 fsync + os.replace 原子替换 + 发布管理 CAS 激活指针 +
    同步 当前.json」做成一条必经路径（复用 `平台客户端制品.安装到环境` 的唯一实现）。

    返回 `{安装路径,制品名,复用,消息}`；已安装同摘要且指针一致时**幂等复用**不重复复制
    （`复用=真`）。陈旧指针、半成品（制品缺失/物料清单缺失）、被篡改制品一律在复制前被拒。
    """
    from 公共契约.基础类型.结果类型 import 结果

    摘要 = _文本(制品摘要)
    if len(摘要) != 32:
        return 结果.失败(错误_参数不合法,
                         f"制品摘要 必须是内容寻址摘要（sha256 前 32 位），实收 {len(摘要)} 位",
                         来源="包仓库")
    接入, 说明 = _客户端接入({"状态目录": 状态目录, "制品根目录": 制品根目录,
                               "环境目录": 环境目录, "信任目录": 信任目录})
    if 说明:
        return 结果.失败(错误_参数不合法, 说明, 来源="包仓库")
    try:
        成功, 消息, 目标 = 接入.安装到环境(摘要, _文本(制品名) or None)
    finally:
        接入.关闭()
    if not 成功 or 目标 is None:
        return 结果.失败(错误_制品安装失败, str(消息) or "未返回安装目标", 来源="包仓库")
    return 结果.成功结果({
        "安装路径": str(目标), "制品名": _文本(制品名),
        "复用": bool("幂等" in str(消息)), "消息": str(消息),
    })


