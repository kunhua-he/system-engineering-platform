"""路径安全：制品内相对路径校验与规范化（包仓库共用）。"""

from __future__ import annotations

import os
from pathlib import Path
from urllib.parse import unquote


def 安全迭代文件(根目录: str | Path, *, 跳过符号链接: bool = True) -> list[Path]:
    """递归列出根目录下的**真实文件**，跳过符号链接与目录（#159，2026-09-20）。

    **为什么需要**：全仓有五处「`rglob("*")` 后直接 `is_file()` / `read_bytes()`」
    （`签名能力.py:45`、`制品布局.py:60,99`、`安装能力.py:185`、`核心快照.py:96`）。
    `Path.rglob` **不解析符号链接但会把它列出来**，而 `Path.is_file()` 对符号链接
    **跟随目标判定** —— 于是制品目录里一个指向 `/etc/passwd`（或任何受控根之外文件）
    的软链会被判成「普通文件」，随后 `read_bytes()` 就把**根外文件内容**读进
    制品摘要 / 物料清单 / 签名清单：既有信息泄露，也让「制品摘要」可被根外内容影响
    （篡改面）。安装侧更直接：`安装能力.py` 会把它复制进受控根，等于把根外文件搬进来。

    **口径**：默认**跳过符号链接**（不跟随）。制品/快照/安装源里的软链一律不算正式文件，
    与既有 `__pycache__` / 排除文件名同属「不是正式内容」的处理；发现软链时按
    `记录忽略` 留痕（调用点自决是否留痕，本函数只返回清单）。

    返回：**已排序**的真实文件路径列表（排序保证摘要稳定可复现）。
    """
    根 = Path(根目录)
    结果: list[Path] = []
    for 路径 in 根.rglob("*"):
        if 跳过符号链接 and 路径.is_symlink():
            continue          # 不跟随软链：既防根外读取，也防指向目录的软链造成遍历逃逸
        if not 路径.is_file():
            continue
        结果.append(路径)
    return sorted(结果)


def 规范化相对路径(路径: str) -> str:
    """校验并规范化制品内相对路径；非法路径抛 ValueError。

    **本函数是包仓库内「制品/清单内相对路径校验」的唯一实现**（#165，2026-09-20）。
    原 `可复现构建器.py:26` 与 `物料清单.py:19` 各带一份同名副本，三份规则**并不等价**：
      · 本处 / 可复现构建器版：拒空/根、拒绝对（含 Windows 盘符 `C:`）、按正反斜杠
        双分隔符判 `..`/`.` 逃逸、再拒反斜杠 —— 归纳为先归一再看逃逸，覆盖最全；
      · 物料清单版：**不查盘符**（`C:foo` 会被放行成合法相对路径）、且用 `路径.split("/")`
        直接判逃逸（两段点加反斜杠的写法因整段不等于 `..` 而不匹配，可绕过）—— 规则更弱。
    收敛后三处行为一致（取并集中最严的那份），并保证「同一件事只有一套实现」。

    ★ 2026-09-23（未完成事项 §四「路径边界有 5 份实现、口径互不一致」）：判据前先 `unquote`（**只解一次**）—— 此前
    `..%2fetc` / `%2e%2e/x` / `a/..%2f/b` 三种 URL 编码穿越**全放行**（字面量里没有 `..` 段）。
    """
    if 路径 is None:
        raise ValueError("路径不能为空")
    路径 = str(路径)
    # URL 解码归一化（未完成事项 §四「路径边界有 5 份实现、口径互不一致」，2026-09-23）：**所有判据之前**先 unquote，且只解一次。
    # 为什么必须在判据之前：`..%2fetc` / `%2e%2e/x` / `a/..%2f/b` 的字面量里既没有 `..` 段、
    # 也不是绝对路径，直接进下面那几条判据会被整段当成普通目录名放行；而真正消费这条路径的
    # 解包/落盘代码看到的是**解码后**的名字 ⇒ 编码穿越可整体绕过本函数。
    # 为什么只解一次：对**已解码结果**再解一次会让 `%252e%252e` 这类双重编码钻过去
    # （二次解码本身就是漏洞），故此处只对原始入参调用一次 unquote。
    路径 = unquote(路径)
    if not 路径 or 路径 in (".", "/", "\\"):
        raise ValueError(f"空或根路径不允许: {路径!r}")
    if 路径.startswith("/") or 路径.startswith("\\") or 路径[1:2] == ":":
        raise ValueError(f"绝对路径不允许: {路径!r}")
    if any(段 in ("..", ".") for 段 in 路径.replace("\\", "/").split("/")):
        raise ValueError(f"路径逃逸不允许: {路径!r}")
    if "\\" in 路径:
        raise ValueError(f"反斜杠分隔符不允许: {路径!r}")
    return 路径
