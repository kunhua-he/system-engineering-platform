"""环境回收面：两个制品根的回收接线、指针收尾与只读清点（**平台客户端制品接入 的能力簇**）。

2026-09-18 从 `平台客户端制品.py` 原样搬出（对外零变化），本模块以混入类挂到入口类：

    class 平台客户端制品接入(环境回收面, 激活指针面): ...

职责边界（**先看清归属，不要制造第二份实现**）：

- `制品保留.py` 是**回收的判据与唯一实现**（内容寻址 / 身份 / 镜像三类受管目录、
  保留标识四种写法、单次上限、未安装态保底、信任链历史、证据留痕）。
  本模块**不复制任何回收判据**，只做两件事：把两个根交给它、把结论收成回报；
- `激活指针.py` 是 `当前.json` 的唯一 schema 与读写落点；本模块只读它取「谁是当前件」；
- `激活指针面.py` 提供 `规范化指针文件`（收尾里的 schema 归一那一半）；
- `制品布局.py` 提供摘要→身份目录名换算（本模块的 `_身份目录名表` 是它的薄委托）。

**为什么「收尾」必须存在（哲学 14.1：回收点要接在必经路径上）**：
回收原来只被构建脚本 `--安装` 的**成功路径**调用一次，于是「不走安装」「安装失败」
「别人来清点」三种情况都不回收 —— 现场 17 份身份目录 / 351MB 就是这么积起来的。
判据不是「谁调用得多」，而是**任何一次入库/安装/清点动作都会经过同一个回收入口，且有上限**。
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from 平台控制面.包仓库.激活指针 import 读取激活指针, 指针文件名
from 平台控制面.包仓库.制品保留 import (
    回收报告,
    回收结果,
    合并回收结果,
    记录回收证据,
    清理过期制品 as 回收制品目录,
)
from 平台控制面.包仓库.制品布局 import 计算身份目录名
from 公共契约.基础类型.逻辑类型 import 假, 真


class 环境回收面:
    """环境回收接线：当前件判据、过期回收、只读清点、必经路径收尾（混入 `平台客户端制品接入`）。

    本面**不自建**目录口径与指针落点，只用宿主类提供的依赖（注解即契约，宿主缺一即
    属性错误当场暴露，不会静默退回各自拼路径）：

    - `状态目录`：平台状态库位置（仅用于就地构造，供注解与诊断可见）；
    - `制品根目录`：内容寻址目录所在根；
    - `客户端制品目录`：身份目录（`平台客户端-<摘要16>`）所在根；
    - `环境目录`：已安装副本与 `当前.json` 所在根；
    - `包id`：身份目录名前缀（唯一来源，本面不再抄一份字面量）；
    - `状态`：平台状态（读制品记录、写回收证据）；
    - `里程碑摘要表` / `回收上限` / `自动回收`：保留策略与开关；
    - `规范化指针文件`：由 `激活指针面` 提供（收尾里的 schema 归一）。
    """

    状态目录: Path
    制品根目录: Path
    客户端制品目录: Path
    环境目录: Path
    包id: str
    状态: Any
    里程碑摘要表: tuple[str, ...]
    回收上限: int
    自动回收: bool
    规范化指针文件: Any
    规范化制品根指针: Any
    _制品根指针文件: Any
    指针目标: Any

    # ---- 当前件判据（唯一来源：环境激活指针） ----
    def 当前制品摘要(self) -> str:
        """环境激活指针指向的制品摘要（内容寻址摘要，32 位）；未安装返回空串。

        回收的「当前件」判据**必须**走这里（读环境指针），不能只看内存参数：
        回收发生在安装链路上，靠调用方传进来的摘要会把「谁是当前件」变成调用方责任，
        传漏一次就把手上在用的制品删掉。
        """
        指针 = 读取激活指针(self.环境目录 / 指针文件名)
        return str((指针 or {}).get("制品摘要", "")) if 指针 else ""

    def 当前制品身份(self) -> str:
        """环境激活指针指向的制品目录名（`平台客户端-<摘要16>`）；未安装返回空串。"""
        指针 = 读取激活指针(self.环境目录 / 指针文件名)
        return str((指针 or {}).get("制品目录", "")) if 指针 else ""

    def _身份目录名表(self, 摘要表: tuple[str, ...] | list[str]) -> list[str]:
        """把制品摘要逐项换算成身份目录名（换算规则唯一事实源 = `制品布局.计算身份目录名`）。

        回收保护必须**两种名称形态都展开**：内容寻址目录名是 32 位摘要，身份目录名是
        16 位身份摘要（制品记录的 `版本` 字段）。只保护摘要本体，身份目录照样被回收删掉，
        表现为「安装成功但紧接着 `指向的制品目录不存在` / `制品目录缺失（半成品）`」
        （2026-09-18 实测）。查不到记录的摘要（如伪造摘要）不产出名字：不掩盖，也不瞎猜。
        """
        return [名称 for 名称 in
                (计算身份目录名(self.状态, self.包id, 摘要) for 摘要 in 摘要表) if 名称]

    # ---- 保留判据（唯一装配点） ----
    def _保留判据(self, *, 额外保留摘要表: tuple[str, ...] | list[str] = (),
                  额外保留目录名表: tuple[str, ...] | list[str] = (),
                  ) -> tuple[str, str, tuple[str, ...]]:
        """保留判据的**唯一装配点**：返回 `(当前摘要, 当前身份, 保留标识表)`。

        `回收过期制品`（真删）与 `回收报告`（只读清点）都从这里取判据 —— 否则
        「清点说该收」与「回收真的收」会给出两套结论，那正是本模块要防的形态。

        四路并集（每路都要按两种名称形态展开，缺一路就会删掉手上的件）：

        1. 环境激活指针的当前件（`当前制品摘要` / `当前制品身份`）；
        2. `里程碑摘要表`（回滚目标）；
        3. `额外保留摘要表` / `额外保留目录名表` —— 本次正在操作的件；
        4. **制品根指针的目标**（`客户端制品目录/当前.json`，债务 #214）—— 它与环境
           激活指针**不是同一件事**（一个是「最近构建出来的」、一个是「当前装着的」），
           但同样是**活引用**：只看环境指针，它的目标就会被当「非当前件」回收掉，
           留下**悬空指针**（2026-09-21 实测：连续三次构建的产物全被回收，
           `平台客户端制品/当前.json` 指向一个已不存在的目录）。

        第 1、4 路的摘要都要经 `_身份目录名表` 换算：指针的 `制品目录` 字段一旦被写错
        （现场测试与真实故障都会发生），身份目录就失去唯一的名字来源，只剩摘要可追 ——
        不换算等于「只要指针坏过一次，制品就被回收吃掉」。
        """
        当前摘要 = self.当前制品摘要()
        当前身份 = self.当前制品身份()
        制品根摘要, 制品根身份 = self.指针目标(self._制品根指针文件())
        保留摘要表 = list(dict.fromkeys(
            [str(值) for 值 in self.里程碑摘要表 if str(值 or "").strip()]
            + [str(值) for 值 in 额外保留摘要表 if str(值 or "").strip()]
            + ([制品根摘要] if 制品根摘要 else [])))
        保留目录名表 = [str(值) for 值 in 额外保留目录名表 if str(值 or "").strip()]
        if 制品根身份:
            保留目录名表.append(制品根身份)
        保留目录名表.extend(self._身份目录名表(
            tuple(保留摘要表 + ([当前摘要] if 当前摘要 else []))))
        保留标识表 = tuple(dict.fromkeys(保留摘要表 + 保留目录名表))
        return 当前摘要, 当前身份, 保留标识表

    # ---- 回收（唯一判据在 制品保留.py；本面是「必经路径」的接线点） ----
    def 回收过期制品(self, *, 触发点: str = "手动", 写证据: bool = 真,
                     额外保留摘要表: tuple[str, ...] | list[str] = (),
                     额外保留目录名表: tuple[str, ...] | list[str] = ()) -> 回收结果:
        """按当前激活指针回收两个制品根（**任何一次调用都经这里**）。

        为什么接在 `入库` / `安装到环境` / `诊断激活指针` 上（而不是只挂 `--安装` 成功路径）：
        原来只靠构建脚本 `--安装` 成功那一刻调一次 `清理过期制品`，于是
        「不走安装」「安装失败」「别人来清点」三种情况都不回收 —— 现场 17 份
        身份目录 / 351MB 就是这么积起来的。判据不是「谁调用得多」，而是
        **任何一次入库/安装/清点动作都会经过同一个回收入口，且有上限**（`回收上限`）。

        两个根都收：`制品根目录`（内容寻址目录）与 `客户端制品目录`（身份目录）。
        只清前者会让后者无限堆积（2026-09-15 实测：29 份 / 467MB 从未被清）。

        保留项怎么算（**四路并集**，装配点只有 `_保留判据` 一处，每路都要按两种名称形态
        展开，缺一路就会删掉手上的件）：

        1. 环境激活指针的当前件（`当前制品摘要` / `当前制品身份`）；
        2. `里程碑摘要表`（回滚目标）；
        3. `额外保留摘要表` / `额外保留目录名表` —— 本次正在操作的件。它此刻还**不是**
           当前件（指针未切），只按当前件保留就会把它的身份目录先删掉；
        4. **制品根指针的目标**（`客户端制品目录/当前.json`，债务 #214）—— 与第 1 路
           **不是同一件事**（一个是「最近构建出来的」、一个是「当前装着的」），但同样是
           **活引用**：只看环境指针，它的目标就会被当「非当前件」回收掉，留下**悬空指针**
           （2026-09-21 实测：连续三次构建的产物全被回收，
           `平台客户端制品/当前.json` 指向一个已不存在的目录）。

        第 1、4 路的摘要都要经 `_身份目录名表` 换算：指针的 `制品目录` 字段一旦被写错
        （现场测试与真实故障都会发生），身份目录就失去唯一的名字来源，只剩摘要可追 ——
        不换算等于「只要指针坏过一次，制品就被回收吃掉」。

        **未安装态（指针为空）有一条保底**（2026-09-18 实测根因，见 `制品保留.保底保留份数`）：
        `重置激活指针` 之后指针为空 ⇒ 保留标识是空集 ⇒ 若不保底，下一次必经路径会把
        两个根**整根清空**，而 `安装到环境` 正是要从内容寻址目录取件 —— 于是「重置 →
        重装」这条恢复路径被自己的回收掐死，报的是 `制品目录缺失（半成品）`
        （半成品判定没错，是回收把「未安装」读成了「仓库为空」）。
        每个根至少留一份可用件；半成品/篡改照旧由安装链的 `校验制品` 拦，不放行任何脏件。
        """
        当前摘要, 当前身份, 保留标识表 = self._保留判据(
            额外保留摘要表=额外保留摘要表, 额外保留目录名表=额外保留目录名表)
        结果表: list[回收结果] = []
        for 根 in (self.制品根目录, self.客户端制品目录):
            结果表.append(回收制品目录(
                根, 当前摘要=当前摘要, 当前身份=当前身份,
                里程碑摘要表=保留标识表, 上限份数=self.回收上限))
        合并 = 合并回收结果(结果表)
        if 写证据 and (合并.删除项 or 合并.失败项):
            记录回收证据(self.状态, 结果=合并, 触发点=触发点, 当前摘要=当前摘要,
                         里程碑摘要表=保留标识表)
        return 合并

    def 回收报告(self) -> dict[str, Any]:
        """只读清点两个根（不删任何东西）：与 `回收过期制品` 共用同一套判据。

        判据必须走同一个 `_保留判据`（含制品根指针目标）—— 否则「清点说该收」与
        「回收真的收」会给出两套结论，那正是本模块要防的形态（见模块头）。
        """
        当前摘要, 当前身份, 保留标识表 = self._保留判据()
        报告 = {}
        for 名称, 根 in (("制品根目录", self.制品根目录),
                        ("客户端制品目录", self.客户端制品目录)):
            报告[名称] = 回收报告(根, 当前摘要=当前摘要, 当前身份=当前身份,
                                 里程碑摘要表=保留标识表)
        return 报告

    def _收尾必经路径(self, *, 触发点: str, 正在操作摘要: str = "") -> dict[str, Any]:
        """**必经路径收尾**：指针 schema 归一 + 过期制品回收（唯一接线点）。

        为什么必须存在这一层：回收原来只被构建脚本 `--安装` 的**成功路径**调用一次 ——
        回收点没接在必经路径上（哲学 14.1）。本函数把「两件事」绑到同一个收尾动作上，
        由 `入库`（成败都走）/ `安装到环境`（成败都走）/ `诊断激活指针`（任何清点都走）
        分别调用，于是「入库失败」「不安装」「别人来清点」三条路径都会回收。

        本函数是**收尾**，不是主链路：任何异常都**不得**把已经成功的入库/安装
        反过来改成失败（那会造出「装好了但报失败」的假失败）。故异常在此收敛进
        返回报告的 `回收` / `制品根指针归一` 字段，如实回报而不抛出。

        `正在操作摘要` = 本次入库/安装正在处理的那份制品：它此刻还不是当前件，
        必须显式保护，否则回收会先把它删掉。
        """
        报告: dict[str, Any] = {"触发点": 触发点}
        try:
            归一成功, 归一消息 = self.规范化制品根指针(触发点=触发点)
            报告["制品根指针归一"] = 归一消息
            报告["制品根指针已归一"] = bool(归一成功)
        except Exception as 错误:  # 指针归一失败是真问题，但不得反向污染主链路结论
            报告["制品根指针归一"] = f"指针归一异常（未改写任何文件）: {错误}"
            报告["制品根指针已归一"] = 假
        if self.自动回收:
            try:
                回收 = self.回收过期制品(
                    触发点=触发点,
                    额外保留摘要表=(正在操作摘要,) if 正在操作摘要 else ())
                报告["回收"] = 回收.摘要文本()
                报告["回收删除项"] = 回收.删除项
                报告["回收保留项"] = 回收.保留项
            except Exception as 错误:
                报告["回收"] = f"回收异常（未中断主链路）: {错误}"
                报告["回收删除项"] = 0
        else:
            报告["回收"] = "自动回收已关闭（自动回收=False，仅供隔离测试）"
        return 报告


__all__ = ["环境回收面"]
