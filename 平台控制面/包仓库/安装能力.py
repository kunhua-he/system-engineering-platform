"""安装能力：制品安装（受控根判定 + 临时目录 + 备份/替换/失败还原三段式，安装前后双重校验）。

边界（2026-09-17 B-04 安全修复，两条都收在本文件）：
- 安装目标必须是**受控根下的单层合法目录名**（包id）：先经同仓已有工具
  `支持库.后端.系统核心支持库.路径安全.校验文件名` 判定（拒绝路径分隔符、
  `..`、点开头、空名），再断言 `目标目录.resolve().parent == 受控根.resolve()`。
  `包id = "x/../../../evil"` 这类构造在拼路径后立刻被拒，不可能逃出受控根。
  这是**唯一一处**安装目标判定（`校验安装目标目录`），发布链与安装实现共用，
  不再各拼各判。
- 受控根口径（B-04 之二）：`安装制品` 增加 `受控目录` 参数。
  **显式传入**时按其精确父目录判定（发布链 `统一入口.签名与发布` 传 `存储目录/已激活`）；
  **缺省**时取平台存储目录下的 `已激活`（`默认受控目录`，与发布链同一落点）。
  旧实现缺省时把「目标目录自己的父目录」当受控根，等于放行**任意已存在目录**——
  实测后果：`含 重要数据.txt 的 /tmp 目标目录` 被整体改名备份后 `rmtree` 删除（数据丢失），
  旧代码里 `校验安装目标目录(无受控目录) = (True, '')` 正是这条放行。
- **禁止自动造父目录**：受控根缺失时最多**单层**创建（其父目录必须已存在），受控根之外
  任何父目录都不创建；受控根就是目标目录的父目录，因此目标目录的父目录必须已存在。
  旧实现的 `临时目标.mkdir(parents=True)` 会把目标目录的整条父链一并造出来。
- 同一受控根下的安装按目标名 `flock` **串行化**（`_安装串行锁`）：并发安装同一目标时
  互斥，避免两笔安装交错做「改名备份 → 就位 → 删备份」。
- 替换不再是「先删后改」：旧目标先 `os.rename` 成备份（改名不丢数据）→ 新目录
  就位 → 第二步失败即把备份改名还原旧版；只有替换成功后才丢弃备份。
  照搬同仓 平台客户端制品._原子写入安装目录（:419-428）的同款三段式，
  不自创第二套实现。
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import uuid
from contextlib import contextmanager
from pathlib import Path

from 支持库.后端.系统核心支持库.路径安全 import 校验文件名

# 缺省受控根名：平台存储目录下的 `已激活`（与发布链 统一入口.签名与发布 的安装落点同一形态）
默认受控目录名 = "已激活"
# 受控根内的安装期临时物（临时目录/备份目录/串行锁）前缀：统一点开头，便于调用方识别
临时目录前缀 = ".安装临时_"
备份目录前缀 = ".安装备份_"
串行锁前缀 = ".安装串行锁_"


def 校验安装目标目录(目标目录, 受控目录=None) -> tuple[bool, str]:
    """判定安装目标是否为受控父目录下的单层合法目录（包id）。

    唯一判定入口：安装实现（安装制品）与发布链（统一入口.签名与发布）
    共用这一处，避免同一事两套口径。判定不看文件系统权限、只判形态：
    ①目录名必须是合法单层名（无分隔符/无 `..`/非点开头/非空）；
    ②路径**任何一段**都不得是 `..` 或 `.`——只比"解析后是否父目录子项"是挡不住的：
       `已激活/x/../../../evil` 的父路径本身就被 `..` 抬到了存储目录之外，
       解析后它照样是（那个已经跑偏的）父目录的直接子项（2026-09-17 实测踩坑）；
    ③解析后必须仍是父目录的直接子项（挡符号链接归位异常）；
    ④给了 `受控目录` 时，解析后的父目录必须**等于**该受控目录（拼路径处用）。
    注意：本函数**不**判定受控根是什么、也不创建任何目录；「缺省受控根」由
    `安装制品` 按 `默认受控目录` 解析后传入（见本模块顶部边界说明）。
    """
    路径 = Path(目标目录)
    名字结果 = 校验文件名(路径.name)
    if not 名字结果.成功:
        return False, f"包id 非法: {名字结果.错误说明}"
    if not 名字结果.值.get("通过"):
        return False, f"包id 非法: {名字结果.值.get('原因', '')}"
    段表 = 路径.parts[1:] if 路径.is_absolute() else 路径.parts
    for 段 in 段表:
        if 段 in ("..", "."):
            return False, f"安装目标含目录跳转段（. / ..）: {路径}"
    父目录 = 路径.parent.resolve()
    实际目录 = 路径.resolve()
    if 实际目录.parent != 父目录:
        return False, f"安装目标未归位到父目录直接子项: {路径}"
    if 受控目录 is not None:
        根目录 = Path(受控目录).resolve()
        if 实际目录.parent != 根目录:
            return False, f"安装目标越出受控目录 {根目录}: {实际目录}"
    return True, ""


class 安装能力:
    """安装能力：安装制品到受控根下的目标目录，全程防篡改。"""

    def 默认受控目录(self) -> Path:
        """缺省受控根：平台存储目录下的 `已激活`（与发布链安装落点同一形态）。

        唯一解析点：调用方不传 `受控目录` 时，安装目标只能落在
        `<平台状态存储目录>/已激活/<包名>`，不再接受「任意已存在目录」当目标。
        """
        return Path(self.状态.存储目录) / 默认受控目录名

    @staticmethod
    @contextmanager
    def _安装串行锁(受控根: Path, 目标名: str):
        """同一受控根下同一目标名的安装互斥（`flock`）；取不到锁设施时退化为不锁（不报错）。

        为什么需要：改名备份 → 新目录就位 → 删备份 是三段非原子操作，两笔安装交错会把
        对方的备份当成自己的旧版（甚至删掉刚就位的新目录）。锁粒度取「受控根 + 目标名」，
        不同目标之间不互相阻塞。
        """
        try:
            import fcntl
        except ImportError:  # 非 POSIX（Windows 类）：无 flock，退化为不锁
            yield
            return
        锁路径 = 受控根 / f"{串行锁前缀}{目标名}"
        try:
            句柄 = open(锁路径, "a+")
        except OSError:
            yield
            return
        try:
            fcntl.flock(句柄.fileno(), fcntl.LOCK_EX)
            yield
        finally:
            try:
                fcntl.flock(句柄.fileno(), fcntl.LOCK_UN)
            finally:
                句柄.close()

    def 安装制品(self, *, 制品摘要: str, 目标目录: Path,
                 受控目录: Path | str | None = None) -> tuple[bool, str]:
        """安装候选：临时目录复制 → 安装前后都校验 → 备份/替换/失败还原。

        不能把被篡改内容复制出去：安装前校验失败立即中止。
        替换失败必须还原旧版：旧版先改名备份，绝不先删。
        受控根见 `默认受控目录`：`受控目录` 给出时按精确父目录判定，缺省时按
        `<平台状态存储目录>/已激活` 判定——两条都不接受任意已存在目录当目标。
        """
        制品 = self.状态.读取记录("制品", "制品摘要", 制品摘要)
        if 制品 is None:
            return False, "制品不存在"
        目标目录 = Path(目标目录)
        受控根 = Path(受控目录) if 受控目录 is not None else self.默认受控目录()
        # 路径形态判定（唯一一处）：拼路径之后立刻挡目录逃逸/越出受控根。
        # 判定结果**先算出、不立刻返回**：拒绝原因在签名判定之后统一决定（见下）。
        目标通过, 目标原因 = 校验安装目标目录(目标目录, 受控目录=受控根)
        if 目标通过 and 目标目录.resolve() == 受控根.resolve():
            # 兜底断言：上面的形态判定已要求「解析后的父目录 == 受控根」，因此目标不可能
            # 等于受控根（受控根是父目录，不是子项）；这里再断言一次，防将来放宽形态判定时
            # 静默放开「整体替换受控根」这条路（实测该分支当前不可达，属纵深防御）。
            目标通过, 目标原因 = False, f"安装目标不得是受控根本身（会整体替换受控根）: {受控根}"
        # 安装前校验（签名 + 磁盘一致性）
        有效, 消息 = self.校验签名(制品摘要=制品摘要)
        if not 有效:
            # 签名原因优先于路径原因：目标非法与制品不可信同时成立时报**制品**原因。
            # 否则一个错传的路径会把「未签名/被篡改」这类直接指向制品的拒绝原因
            # 遮蔽成「路径非法」，既不可诊断，也让篡改检测看起来是「路径问题」。
            return False, f"安装被拒: {消息}"
        if not 目标通过:
            return False, f"安装被拒: {目标原因}"
        # 受控根：缺省场景下可能尚不存在（首次安装），只允许**单层**创建，
        # 其父目录必须已存在 —— 绝不自动补齐父目录链（否则等于把安装目标造到任意位置）。
        if not 受控根.is_dir():
            if not 受控根.parent.is_dir():
                return False, (f"安装被拒: 受控目录的父目录不存在（禁止自动造父目录）: "
                               f"{受控根.parent}")
            try:
                受控根.mkdir()
            except OSError as 错误:
                return False, f"安装被拒: 受控目录不可创建: {受控根}（{错误}）"
        with self._安装串行锁(受控根, 目标目录.name):
            return self._安装到受控根(制品, 制品摘要, 目标目录, 受控根)

    def _安装到受控根(self, 制品: dict, 制品摘要: str, 目标目录: Path,
                      受控根: Path) -> tuple[bool, str]:
        """受控根内的安装主体：临时目录写入 → 安装后校验 → 三段式原子替换。

        调用者保证：`目标目录.resolve().parent == 受控根.resolve()`、受控根已存在、
        安装前校验已通过、同目标名的串行锁已持有。
        临时目录与备份都建在**受控根内**（不是「目标目录自己的父目录」），
        因此整个替换过程不可能触碰受控根之外的任何路径。
        """
        源目录 = self.制品根目录 / 制品摘要
        临时目标 = 受控根 / f"{临时目录前缀}{uuid.uuid4().hex[:8]}"
        备份 = 受控根 / f"{备份目录前缀}{uuid.uuid4().hex[:8]}"
        # 备份只作旧版还原依据：仅当旧目标改名为备份后才会存在
        已备份 = False
        # 受控根已由调用方保证存在：**不加 parents**，不自动造父目录
        临时目标.mkdir()
        try:
            for 文件 in 源目录.rglob("*"):
                if 文件.is_file() and 文件.name != "物料清单.json":
                    相对 = 文件.relative_to(源目录)
                    目标文件 = 临时目标 / 相对
                    目标文件.parent.mkdir(parents=True, exist_ok=True)
                    目标文件.write_bytes(文件.read_bytes())
                    模式 = json.loads(制品["文件清单"]).get(str(相对), {}).get("模式")
                    if 模式 is not None:
                        目标文件.chmod(int(模式) & 0o7777)
            # 安装后再次校验磁盘摘要（防复制过程篡改）
            for 路径, 摘要信息 in json.loads(制品["文件清单"]).items():
                实际 = hashlib.sha256((临时目标 / 路径).read_bytes()).hexdigest()
                if 实际 != 摘要信息["sha256"]:
                    raise RuntimeError(f"安装后校验失败: {路径}")
            # 原子替换三段式（照搬同仓 平台客户端制品._原子写入安装目录:419-428）：
            # 旧目录先改名备份 → 新目录就位 → 失败即把备份改名还原。
            # 禁止先 rmtree：rmtree 与 rename 之间中断会让 <受控根>/<包id> 彻底消失。
            if 目标目录.exists():
                os.rename(目标目录, 备份)
                已备份 = True
            try:
                os.rename(临时目标, 目标目录)
            except OSError:
                if 备份.exists() and not 目标目录.exists():
                    os.rename(备份, 目标目录)
                    已备份 = False
                raise
        except Exception as 错误:
            shutil.rmtree(临时目标, ignore_errors=True)
            # 还原未完成时保留备份目录：旧版仍可人工恢复，不让旧版彻底消失
            return False, f"安装失败: {错误}" + (f"（旧版已备份于 {备份}）" if 已备份 else "")
        # 新目录已就位：旧版备份不再是回滚依据（回滚走 发布管理.回滚），丢弃
        if 已备份 and 备份.exists():
            shutil.rmtree(备份, ignore_errors=True)
        self.状态.条件更新("制品", {"状态": "已安装"}, "制品摘要=?", (制品摘要,))
        return True, f"已安装到 {目标目录}"
