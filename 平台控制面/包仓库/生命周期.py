"""包生命周期：包状态机（16 态）。

状态：未安装/安装中/已安装/校验中/已校验/已解析/启动中/已就绪/灰度中/
已激活/已弃用/排空中/已停止/卸载中/已卸载/故障/回滚中。
要求：非法跳转拒绝；重复操作幂等；安装/启动/热切换失败回滚；
卸载失败保留故障状态；每次状态变化写入事件；状态恢复后不丢失历史。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假

状态链 = [
    "未安装", "安装中", "已安装", "校验中", "已校验", "已解析",
    "启动中", "已就绪", "灰度中", "已激活", "已弃用", "排空中",
    "已停止", "卸载中", "已卸载", "故障", "回滚中",
]

# 允许流转表（目标状态集合）
允许流转表 = {
    "未安装": {"安装中", "故障"},
    "安装中": {"已安装", "故障", "回滚中", "未安装"},
    "已安装": {"校验中", "故障", "回滚中"},
    "校验中": {"已校验", "故障", "回滚中"},
    "已校验": {"已解析", "故障", "回滚中", "卸载中"},
    "已解析": {"启动中", "故障", "回滚中", "卸载中"},
    "启动中": {"已就绪", "故障", "回滚中"},
    "已就绪": {"灰度中", "已激活", "已停止", "故障", "排空中"},
    "灰度中": {"已激活", "故障", "回滚中", "已停止"},
    "已激活": {"已弃用", "灰度中", "故障", "排空中", "已停止"},
    "已弃用": {"排空中", "已停止", "卸载中", "故障"},
    "排空中": {"已停止", "故障"},
    "已停止": {"启动中", "卸载中", "故障", "已弃用"},
    "卸载中": {"已卸载", "故障", "回滚中"},
    "已卸载": set(),
    "故障": {"回滚中", "卸载中", "已停止"},
    "回滚中": {"已停止", "已就绪", "已激活", "故障"},
}

幂等操作表 = {"已停止", "已卸载", "已激活"}  # 重复操作幂等


@dataclass
class 状态记录:
    """一次状态变化记录。"""

    包id: str
    版本: str
    从状态: str
    到状态: str
    操作名称: str = ""
    成功: bool = 真
    错误码: str = ""
    错误说明: str = ""

    def 转字典(self) -> dict:
        return {
            "包id": self.包id, "版本": self.版本, "从状态": self.从状态,
            "到状态": self.到状态, "操作名称": self.操作名称, "成功": self.成功,
            "错误码": self.错误码, "错误说明": self.错误说明,
        }


class 包生命周期:
    """单个包的生命周期状态机（事件写入可选）。"""

    def __init__(self, 包id: str, 版本: str = "", 初始状态: str = "未安装",
                 事件日志: Any = None) -> None:
        self.包id = 包id
        self.版本 = 版本
        self.状态 = 初始状态
        self.历史记录: list[状态记录] = []
        self.事件日志 = 事件日志

    def 流转(self, 目标状态: str, *, 操作名称: str = "", 成功: bool = 真,
             错误码: str = "", 错误说明: str = "") -> 状态记录:
        """流转到目标状态；非法跳转拒绝；重复操作幂等。"""
        从状态 = self.状态
        操作名称 = 操作名称 or f"流转到{目标状态}"
        if 目标状态 not in 状态链:
            raise ValueError(f"未知状态: {目标状态}")
        if 目标状态 == 从状态 and 从状态 in 幂等操作表:
            记录 = 状态记录(self.包id, self.版本, 从状态, 目标状态, 操作名称, 真)
            self.历史记录.append(记录)
            return 记录
        if 目标状态 not in 允许流转表.get(从状态, set()):
            记录 = 状态记录(self.包id, self.版本, 从状态, 从状态, 操作名称, 假,
                          错误码 or "状态跳转非法", 错误说明 or f"不允许从 {从状态} 跳转到 {目标状态}")
            self.历史记录.append(记录)
            return 记录
        self.状态 = 目标状态
        记录 = 状态记录(self.包id, self.版本, 从状态, 目标状态, 操作名称, 成功, 错误码, 错误说明)
        self.历史记录.append(记录)
        if self.事件日志 is not None:
            from 运行核心.运行诊断.运行事件.事件模型 import 生成事件
            self.事件日志.写入(生成事件(
                "生命周期变化", 成功=成功, 错误码=错误码, 错误说明=错误说明,
                包id=self.包id, 版本=self.版本, 生命周期状态=目标状态,
                操作名称=操作名称,
            ))
        return 记录

    def 回滚(self, 错误码: str = "", 错误说明: str = "") -> None:
        """失败回滚：进入 回滚中 再回到失败前的稳定状态。"""
        上一状态 = self.历史记录[-1].从状态 if self.历史记录 else "未安装"
        self.流转("回滚中", 操作名称="失败回滚", 成功=假, 错误码=错误码, 错误说明=错误说明)
        if 上一状态 != "回滚中" and 上一状态 in 允许流转表.get("回滚中", set()):
            self.流转(上一状态, 操作名称="回滚恢复", 成功=真)

    def 检查历史(self, 操作名称: str) -> bool:
        return any(记录.操作名称 == 操作名称 for 记录 in self.历史记录)

    def 历史转列表(self) -> list[dict]:
        return [记录.转字典() for 记录 in self.历史记录]
