"""激活指针面：陈旧指针的诊断、重建与重置（**平台客户端制品接入 的能力簇**）。

2026-09-18 从 `平台客户端制品.py` 原样搬出（对外零变化），本模块只承载「激活指针
怎么算陈旧、怎么修」这一簇；入口类仍是 `平台客户端制品接入`，本模块以混入类
（mixin）形式挂上去，因此**没有任何成员被改名**——

    class 平台客户端制品接入(环境回收面, 激活指针面): ...

职责边界（**不要在这里加第二套实现**）：

- `激活指针.py`：`当前.json` 的**唯一 schema 与读写落点**
  （`指针键表` / `归一激活指针` / `读取激活指针` / `写激活指针` / `指针形态`）。
  本模块是它的**调用方**，不复制键名、不自己拼 `json.dumps` 落盘。
- 本模块：**指针新鲜度的判据与修复出口**（诊断 / 重建 / 重置 + 历史写法归一）。
  全仓只有这一处实现；`检查激活指针` 是 `诊断激活指针` 的真陈旧投影（同一判据两种问法）。
- `制品保留.py`：回收判据；本模块的诊断只读主体绝不删文件，回收走
  `环境回收面._收尾必经路径`（唯一接线点）。
- `发布管理`：账本侧的激活指针（`当前激活` / `激活` / `切换激活指针`）；
  重置时两边同批清空，避免「文件说没装、账本说已激活」的第二事实源。

D-17 ① 的两半在这里齐备：陈旧**可诊断**（`诊断激活指针` 给出 `陈旧级别` 与原因）
且**可修复**（`重建激活指针` / `重置激活指针` 两个出口），不再只有「永久拒绝」。
"""
from __future__ import annotations

import json
import os
import shutil
import time
from pathlib import Path
from typing import Any

from 平台控制面.包仓库.激活指针 import (
    归一激活指针,
    指针文件名,
    指针形态,
    写激活指针,
    读取激活指针,
)
from 平台控制面.包仓库.制品布局 import 计算目录摘要16, 摘要前缀长度
from 公共契约.基础类型.逻辑类型 import 假, 真


class 激活指针面:
    """陈旧指针诊断 + 修复出口（重建 / 重置）+ 历史写法归一（混入 `平台客户端制品接入`）。

    本面**不自建**目录口径与收尾接线，只用宿主类提供的依赖（注解即契约，宿主缺一即
    属性错误当场暴露，不会静默退回各自拼路径）：

    - `环境目录` / `客户端制品目录`：两个根的位置（由宿主 `__init__` 解析，
      与 `制品布局.制品仓库缓存根` 同源）；
    - `包id`：身份目录名前缀与发布账本主键（唯一来源，本面不再抄一份字面量）；
    - `状态`：平台状态（读制品记录、写发布账本）；
    - `发布`：发布管理（账本侧激活指针）；
    - `_收尾必经路径`：由 `环境回收面` 提供（归一 + 回收的唯一接线点）。
    """

    环境目录: Path
    客户端制品目录: Path
    包id: str
    状态: Any
    发布: Any
    _收尾必经路径: Any

    # ---- 指针路径（唯一解析点） ----
    def _指针文件路径(self) -> Path:
        """环境侧 `当前.json` 的路径（= `环境目录 / 指针文件名`）。

        唯一解析点：诊断 / 重建 / 重置 / 归一 / 稳定路径校验共用它，避免五处各拼一遍
        `self.环境目录 / 指针文件名`（文件名本身仍是 `激活指针.指针文件名` 的唯一事实源）。
        """
        return self.环境目录 / 指针文件名

    def _制品根指针文件(self) -> Path:
        """制品根（`平台客户端制品`）那份同名 `当前.json` 的路径。

        第二处 `当前.json` 就在这个根下 —— 它与 `环境目录/当前.json` 同名同概念，
        历史写法是 `{摘要sha256, 路径}`（见 `激活指针` 模块头）。
        """
        return self.客户端制品目录 / 指针文件名

    def 指针目标(self, 指针文件: Path) -> tuple[str, str]:
        """读一份 `当前.json` 的 `(制品摘要, 制品目录)`；不存在/不可读/空指针返回空串对。

        为什么要有它（债务 #214）：回收的保留判据要的是**两份**指针的目标 ——
        环境激活指针（「现在装着谁」）与制品根指针（「最近构建出来的是谁」）。
        两处必须是同一段读取代码，否则「按文件名猜 schema」的旧病会从写入侧搬到读取侧
        （schema 归一本就在 `激活指针.读取激活指针` 里做，这里只是它的调用方，
        不复制键名、不自己 `json.loads`）。
        """
        指针 = 读取激活指针(指针文件)
        if not 指针:
            return "", ""
        return (str(指针.get("制品摘要", "") or ""),
                str(指针.get("制品目录", "") or ""))

    # ---- 历史写法归一（制品根那份 `当前.json`） ----
    def 规范化制品根指针(self, 触发点: str = "手动") -> tuple[bool, str]:
        """把制品根的历史写法 `当前.json` 原位归一到唯一 schema（幂等）。

        必须归一的理由：这份指针是**制品根自己的激活指针**，写得用 `路径`、
        环境指针写得用 `制品目录` —— 同一个概念两种表达，读的人只能按文件名猜。
        归一后两份文件键集相同，且仍可由读取侧兼容旧写法（`激活指针.归一激活指针`）。
        """
        return self.规范化指针文件(self._制品根指针文件(), 触发点=触发点)

    def 规范化指针文件(self, 指针文件: Path, 触发点: str = "手动") -> tuple[bool, str]:
        """把一份历史写法的 `当前.json` 原位归一为唯一 schema（幂等）。

        返回 `(是否已归一, 消息)`；已是统一 schema 时为无操作（返回 True + 说明），
        **不重写文件、不备份**（避免每次必经路径都产生一份无用备份）。
        历史写法归一前留 `当前.json.统一schema前_<时间戳>` 备份（不删除，可回溯），
        备份失败即如实报错并**不改动原文件**（不留「改了但没法回退」的中间态）。
        """
        形态 = 指针形态(指针文件)
        if not 形态["存在"]:
            return 假, f"指针文件不存在（无历史写法可归一）: {指针文件}"
        if not 形态["可读"]:
            return 假, f"指针文件不可读，拒绝覆盖（请人工确认）: {指针文件}"
        if 形态["已统一"]:
            return 真, f"指针已是统一 schema（无需归一）: {指针文件}"
        原始 = json.loads(指针文件.read_text(encoding="utf-8"))
        备份 = 指针文件.with_name(
            f"{指针文件.name}.统一schema前_{time.strftime('%Y%m%d%H%M%S')}")
        try:
            shutil.copy2(指针文件, 备份)
        except OSError as 错误:
            return 假, f"归一前备份失败，已放弃改写（原文件未动）: {错误}"
        try:
            写激活指针(指针文件, 原始)
        except OSError as 错误:
            return 假, f"归一写入失败（备份留在 {备份}）: {错误}"
        归一 = 归一激活指针(原始)
        return 真, (f"指针已归一到统一 schema（触发点 {触发点}）："
                     f"原键 {形态['原始键']} → 统一键 {形态['归一键集']}"
                     f"（历史写法 {形态['历史写法']}）；原文件已备份 {备份.name}；"
                     f"制品目录={归一['制品目录'] or '<空>'}")

    def _写指针文件原始(self, 指针: dict[str, Any]) -> None:
        """按**唯一 schema** 原子写 `环境目录/当前.json`（本面唯一落盘点）。

        落盘不再自己拼 `json.dumps`：统一委托 `激活指针.写激活指针`（唯一写入点，
        只写 `指针键表` 的键）。这样「环境指针」与「制品根指针」两份同名文件
        不可能再写出两种表达 —— 两份 schema 能各活一半，正是因为原来有两处各写各的。
        """
        写激活指针(self._指针文件路径(), 指针)

    # ---- 诊断（可诊断的陈旧判定） ----
    def 诊断激活指针(self, *, 自动收尾: bool = 真) -> dict[str, Any]:
        """可诊断的陈旧指针判定（D-17 ①）：本函数自身不改任何文件。

        判定**源制品目录**与**已安装副本**两处，`陈旧` 只在两处都对不上时报真：
        - `源符合`：制品仓库里的源制品目录（`工程缓存/制品仓库/平台客户端制品/<名>`）
          的实算摘要与指针一致。源目录是二次构建的中间产物，会被制品进程写脏，
          **不该单独决定安装是否被拒**（这是 2026-09-16 实测踩到的设计缺陷）。
        - `已安装符合`：已安装副本（`环境目录/平台客户端`）的实算摘要与指针一致；
          外部调用方真正读到的是它，它才是指针许诺的落点。
        - `陈旧`：源与已安装**都不符合**或指针本身不可读/指向不存在 → 真陈旧，必须重置；
          单边不符只记 `陈旧级别`（`源目录被写脏（已安装副本正常）` / `已安装副本被改`）并可继续安装修复。
        返回键：`陈旧/可继续/原因/陈旧级别/源符合/已安装符合/摘要16/制品名/制品摘要`，
        另含 `必经路径`（收尾报告：指针 schema 归一 + 过期制品回收）。

        `自动收尾`（缺省开）：任何一次诊断/清点都顺带回收过期制品 —— 这就是「回收点
        接在必经路径上」的那条必经路径，因为任何安装/校验/门禁动作都会先诊断指针。
        设 False 可拿到纯只读结论（隔离断言用）。
        """
        结论 = self._诊断激活指针只读()
        if 自动收尾:
            结论["必经路径"] = self._收尾必经路径(触发点="诊断激活指针")
        return 结论

    def _诊断激活指针只读(self) -> dict[str, Any]:
        """陈旧指针判定的**纯只读**主体（不写任何文件、不触发回收）。"""
        指针文件 = self._指针文件路径()
        结论: dict[str, Any] = {
            "陈旧": 假, "可继续": 真, "原因": "", "陈旧级别": "无",
            "源符合": 假, "已安装符合": 假,
            "摘要16": "", "制品名": "", "制品摘要": "",
        }
        if not 指针文件.is_file():
            结论["原因"] = "从未安装（无 当前.json），无指针可查"
            return 结论
        try:
            原始 = json.loads(指针文件.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as 错误:
            结论.update({"陈旧": 真, "可继续": 假,
                         "陈旧级别": "指针文件不可读", "原因": f"激活指针文件不可读: {错误}"})
            return 结论
        # 键取值一律经唯一 schema 归一（历史写法 `路径` 在读取侧归一为 `制品目录`）；
        # 本函数不按原始键各自 .get，避免又变成「按文件猜 schema」。
        指针 = 归一激活指针(原始 if isinstance(原始, dict) else {})
        摘要16 = 指针["摘要sha256"]
        制品名 = 指针["制品目录"]
        制品摘要 = 指针["制品摘要"]
        结论.update({"摘要16": 摘要16, "制品名": 制品名, "制品摘要": 制品摘要})
        源目录 = self.客户端制品目录 / 制品名 if 制品名 else None
        源存在 = bool(源目录 is not None and 源目录.is_dir())
        已安装 = self.环境目录 / "平台客户端"
        已安装存在 = 已安装.is_dir()
        摘要合法 = len(摘要16) == 摘要前缀长度
        结论["源符合"] = bool(源存在 and 摘要合法 and 计算目录摘要16(源目录) == 摘要16)
        结论["已安装符合"] = bool(已安装存在 and 摘要合法 and 计算目录摘要16(已安装) == 摘要16)
        if 结论["源符合"] or 结论["已安装符合"]:
            if not 结论["源符合"]:
                结论["陈旧级别"] = "源目录被写脏（已安装副本正常）"
                结论["原因"] = (f"源制品目录 {制品名 or '<空>'} 与指针摘要不符，已安装副本正常；"
                               f"按已安装副本判定，可继续安装（安装会重建源制品目录）")
            elif not 结论["已安装符合"]:
                结论["陈旧级别"] = "已安装副本被改（源制品正常）"
                结论["原因"] = ("已安装副本摘要与指针不符（源制品正常）；重装同摘要可修复，"
                               "或重置激活指针回「从未安装」")
            elif not 摘要合法:
                结论["陈旧级别"] = "指针摘要字段不合法"
                结论["原因"] = f"激活指针摘要字段不合法: {摘要16!r}"
            if 制品摘要:
                记录 = self.状态.读取记录("制品", "制品摘要", 制品摘要)
                if 记录 is None:
                    结论["陈旧级别"] = "指向制品未入库（摘要缺失）"
                    结论["原因"] = f"激活指针指向的制品未入库: {制品摘要[:16]}…"
            return 结论
        if not 源存在 and not 已安装存在:
            结论.update({"陈旧": 真, "可继续": 假,
                         "陈旧级别": "指向制品目录不存在",
                         "原因": f"激活指针指向的制品目录不存在: {制品名 or '<空>'}"})
            return 结论
        if not 摘要合法:
            结论.update({"陈旧": 真, "可继续": 假,
                         "陈旧级别": "指针摘要字段不合法",
                         "原因": f"激活指针摘要字段不合法: {摘要16!r}"})
            return 结论
        结论.update({"陈旧": 真, "可继续": 假, "陈旧级别": "源与已安装摘要均不符",
                     "原因": (f"源制品目录与已安装副本摘要都与指针不符: {制品名}"
                             f"（期望 {摘要16}）")})
        return 结论

    def 检查激活指针(self) -> str | None:
        """陈旧指针检查：**真陈旧**（源与已安装都不可信）→ 返回可诊断原因；否则 None。

        D-17 ①：口径按 `诊断激活指针` 判定，源制品目录单边被写脏**不再**永久拒绝安装
        （源目录是二次构建中间产物，已安装副本才是对外落点）。真陈旧时的修复出口是
        `重建激活指针`（按已安装副本重建）或 `重置激活指针`（清回「从未安装」）。
        """
        结论 = self.诊断激活指针()
        return None if 结论["可继续"] else str(结论["原因"])

    # ---- 修复出口（D-17 ① 的另一半：陈旧必须可修，不能只有「永久拒绝」） ----
    def 重建激活指针(self) -> tuple[bool, str]:
        """按**已安装副本**重建激活指针（D-17 ① 修复出口，不重复安装、不碰制品仓库）。

        适用：源制品目录被写脏/已被清理，而 `环境目录/平台客户端` 完好——
        只把指针的摘要字段改回已安装副本的实算摘要（内容寻址字段不变），
        使稳定路径立刻恢复可读。
        拒绝：已安装副本不存在或摘要非 16 位十六进制（半安装态不可信 → 走 `重置激活指针`）。
        """
        指针文件 = self._指针文件路径()
        已安装 = self.环境目录 / "平台客户端"
        if not 已安装.is_dir():
            return 假, f"已安装副本不存在，无法重建指针（请先安装或重置）: {已安装}"
        摘要16 = 计算目录摘要16(已安装)
        if len(摘要16) != 摘要前缀长度:
            return 假, f"已安装副本摘要不合法，拒绝写入指针: {摘要16!r}"
        try:
            指针 = 归一激活指针(
                json.loads(指针文件.read_text(encoding="utf-8")) if 指针文件.is_file() else {})
        except (OSError, json.JSONDecodeError) as 错误:
            return 假, f"激活指针不可读，拒绝覆盖（请人工确认后重置）: {错误}"
        原摘要 = 指针["摘要sha256"]
        指针["摘要sha256"] = 摘要16
        if not 指针["制品目录"]:
            指针["制品目录"] = 已安装.name
        self._写指针文件原始(指针)
        return 真, (f"激活指针已按已安装副本重建：{原摘要 or '<空>'} → {摘要16}"
                     f"（已安装副本 {已安装}）")

    def 重置激活指针(self) -> tuple[bool, str]:
        """清掉激活指针，回到「从未安装」状态（D-17 ① 修复出口）。

        只动 `环境目录/当前.json`：改名保存为 `当前.json.陈旧指针备份_<时间戳>`（**不删除**，
        留痕可回溯），不碰制品仓库、不碰已安装副本。发布管理的激活指针同批清空，
        避免留下「文件说没装、账本说已激活」的第二事实源。
        """
        指针文件 = self._指针文件路径()
        步骤: list[str] = []
        if 指针文件.is_file():
            # 文件名里的 `当前.json` 与 指针文件名 同源，不另抄一份字面量
            备份 = 指针文件.with_name(f"{指针文件名}.陈旧指针备份_{time.strftime('%Y%m%d%H%M%S')}")
            os.replace(指针文件, 备份)
            步骤.append(f"指针已备份: {备份}")
        else:
            步骤.append(f"无 {指针文件名}（已是未安装态）")
        激活 = self.发布.当前激活(self.包id)
        if 激活:
            self.状态.写入记录("激活指针", {
                "指针id": self.包id, "目标": "", "版本": int(激活.get("版本", 0)) + 1,
                "栅栏令牌": int(激活.get("栅栏令牌", 0)) + 1, "状态": "已清空"})
            步骤.append("发布管理激活指针已清空（版本+1、栅栏令牌+1，防陈旧写者覆盖）")
        else:
            步骤.append("发布管理侧无激活记录")
        步骤.append("当前状态：从未安装（下次安装走首次安装分支）")
        return 真, "；".join(步骤)


