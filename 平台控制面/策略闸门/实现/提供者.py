"""策略闸门能力实现（判定/只读）：把 策略中心 的只读判定语义包成统一结果契约。

分工（第 2 条 1 项 分层与归属固定）：
- `平台控制面/策略中心.py`：策略判定的**唯一语义实现**（复用/依赖/签名/发布/资源）；
- 本模块：能力边界上的参数校验、判定器取用与结果归一，不复制任何判定分支。

为什么判定走 `策略中心._执行判定` 而不走 `策略中心.判定`：
`判定()` 会向平台证据账本追加证据（写类动作），本轮只补「只读/判定」能力面，
写证据留到写类能力轮次；`_执行判定` 是同一判定器的纯判定入口，零副作用。

为什么要有这个包：`统一入口` 只经唯一能力调用入口按能力 id 调用；策略闸门把
「创建组件 / 提交候选包 / 签名与发布」三条主链要用的策略自查能力暴露成网关能力，
调用方（网关、薄壳、其他模块）不必 import 策略中心 实现，也不必在进程内自查。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

from 平台控制面.平台状态.状态存储 import 平台状态
from 平台控制面.策略中心 import 策略中心
from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.运行时.运行缓存 import 解析运行缓存根

# 存储目录缺省值：经唯一解析器取运行态存储根（源码态 = `<系统根>/工程缓存/平台控制面`，
# 与旧的裸相对值同义；制品态 = 平台受管缓存）。裸相对路径在制品态会把运行态写进制品。
默认存储目录 = str(解析运行缓存根(Path(__file__).resolve().parents[3]) / "平台控制面")
来源名称 = "策略闸门"

# 策略类型 → 该类型判定需要的键（与 策略中心._执行判定 的分支一一对应）
判定键表: dict[str, list[str]] = {
    "复用": ["能力id"],
    "依赖": ["包id", "依赖"],
    "签名": ["包id", "已签名", "签名失效", "签名者"],
    "发布": ["包id", "需求id", "候选版本"],
    "资源": ["包id", "资源预算"],
}
策略类型表 = tuple(判定键表)

# 判定器 → 按 (目录, 项目id) 复用，避免每次调用重建状态库连接。
_判定器表: dict[tuple[str, str], 策略中心] = {}


def _失败(错误码: str, 说明: str):
    from 公共契约.基础类型.结果类型 import 结果

    return 结果.失败(错误码, 说明, 来源=来源名称)


def _取判定器(存储目录: str, 项目id: str):
    """按存储目录取判定器（内建平台状态实例）；目录不可用即明确失败。"""
    from 公共契约.基础类型.结果类型 import 结果

    目录 = str(存储目录 or 默认存储目录).strip()
    if not 目录:
        return None, 结果.失败("参数不合法", "存储目录不能为空", 来源=来源名称)
    键 = (目录, str(项目id))
    判定器 = _判定器表.get(键)
    if 判定器 is not None:
        return 判定器, None
    try:
        状态 = 平台状态(Path(目录), 项目id=str(项目id))
    except (OSError, ValueError, sqlite3.Error) as 错误:
        return None, 结果.失败("存储目录不可用", f"无法打开平台权威状态库：{错误}",
                              来源=来源名称)
    判定器 = 策略中心(状态)
    _判定器表[键] = 判定器
    return 判定器, None


def _纯判定器() -> 策略中心:
    """无需状态库的判定器（资源判定不读任何表）。"""
    return 策略中心(None)


def _决定(策略类型: str, 决定: dict[str, Any]):
    from 公共契约.基础类型.结果类型 import 结果

    return 结果.成功结果({
        "策略类型": 策略类型,
        "允许": bool(决定.get("允许")),
        "理由": str(决定.get("理由") or ""),
        "错误码": str(决定.get("错误码") or ""),
    })


def 查询策略类型():
    """查询策略中心支持的策略类型与判定键（只读，不落证据）。"""
    from 公共契约.基础类型.结果类型 import 结果

    return 结果.成功结果({
        "策略类型表": list(策略类型表),
        "数量": len(策略类型表),
        "判定键表": {类型: list(键表) for 类型, 键表 in 判定键表.items()},
        "证据写入": "判定类能力不写结论证据（证据写入属写类动作，不在本轮能力面）",
    })


def 判定复用策略(能力id: str, 存储目录: str = "", 项目id: str = ""):
    """复用策略判定（只读）；拒绝也在 成功=True 的信封里，按 允许 判定。"""
    标识 = str(能力id or "").strip()
    if not 标识:
        return _失败("参数不合法", "能力id不能为空")
    判定器, 失败 = _取判定器(存储目录, 项目id)
    if 判定器 is None:
        return 失败
    try:
        决定 = 判定器._执行判定("复用", 标识, {})
    except sqlite3.Error as 错误:
        return _失败("查询记录失败", f"复用判定查询能力条目失败：{错误}")
    return _决定("复用", 决定)


def 判定依赖策略(包id: str, 依赖: list, 存储目录: str = "", 项目id: str = ""):
    """依赖策略判定（只读）：声明依赖能力是否全部已登记。"""
    标识 = str(包id or "").strip()
    if not 标识:
        return _失败("参数不合法", "包id不能为空")
    if not isinstance(依赖, (list, tuple)) or not 依赖:
        return _失败("参数不合法", "依赖必须是非空列表，每项含 能力id")
    for 项 in 依赖:
        if not isinstance(项, dict) or not str(项.get("能力id") or "").strip():
            return _失败("参数不合法", "依赖项必须是含 能力id 的字典")
    判定器, 失败 = _取判定器(存储目录, 项目id)
    if 判定器 is None:
        return 失败
    try:
        决定 = 判定器._执行判定("依赖", 标识, {"依赖": list(依赖)})
    except sqlite3.Error as 错误:
        return _失败("查询记录失败", f"依赖判定查询能力条目失败：{错误}")
    return _决定("依赖", 决定)


def 判定签名策略(包id: str, 已签名: bool, 签名失效: bool = 假, 签名者: str = "",
                存储目录: str = "", 项目id: str = ""):
    """签名策略判定（只读）：未签名/失效/发布者不受信一律拒绝。"""
    标识 = str(包id or "").strip()
    if not 标识:
        return _失败("参数不合法", "包id不能为空")
    if not isinstance(已签名, bool) or not isinstance(签名失效, bool):
        return _失败("参数不合法", "已签名与签名失效必须是逻辑型")
    判定器, 失败 = _取判定器(存储目录, 项目id)
    if 判定器 is None:
        return 失败
    try:
        决定 = 判定器._执行判定("签名", 标识, {
            "已签名": 已签名, "签名失效": 签名失效, "签名者": str(签名者 or "")})
    except sqlite3.Error as 错误:
        return _失败("查询记录失败", f"签名判定查询信任目录失败：{错误}")
    return _决定("签名", 决定)


def 判定发布策略(包id: str, 候选版本: str = "", 需求id: str = "",
                存储目录: str = "", 项目id: str = ""):
    """发布策略判定（只读）：未确认需求、候选版本已发布即拒绝。"""
    标识 = str(包id or "").strip()
    if not 标识:
        return _失败("参数不合法", "包id不能为空")
    判定器, 失败 = _取判定器(存储目录, 项目id)
    if 判定器 is None:
        return 失败
    try:
        决定 = 判定器._执行判定("发布", 标识, {
            "候选版本": str(候选版本 or ""), "需求id": str(需求id or "")})
    except sqlite3.Error as 错误:
        return _失败("查询记录失败", f"发布判定查询需求/发布表失败：{错误}")
    return _决定("发布", 决定)


def 判定资源策略(包id: str, 资源预算: dict):
    """资源策略判定（纯计算）：预算缺策略中心要求的必需项即拒绝，不建库不落盘。"""
    标识 = str(包id or "").strip()
    if not 标识:
        return _失败("参数不合法", "包id不能为空")
    if not isinstance(资源预算, dict):
        return _失败("参数不合法", "资源预算必须是字典型")
    return _决定("资源", _纯判定器()._执行判定("资源", 标识, {"资源预算": dict(资源预算)}))
