"""统一入口包实现层：统一能力入口两条能力的唯一执行入口（能力实现）。

分工：
- `平台控制面/统一入口.py`：12 个稳定操作与统一结果结构的唯一实现
  （授权 → 执行 → 证据、命令白名单、进程组终止、输出上限）。
- 本模块：把该实现的公开方法包成**统一结果契约**的能力实现，只做能力边界上的
  参数校验与错误映射，不复制任何操作语义。

为什么只切两条能力（宁少勿滥）：本面对外的动作只有「按稳定操作名执行」与
「读稳定操作表」两个——12 个稳定操作是同一条 `执行操作(操作, 参数)` 分派入口的
取值，不是 12 个独立对外动作；把它们各切一条只会把同一分派逻辑复制 12 份契约
面，不增加任何能力。视图/门禁需要的操作清单由 `查询稳定操作表` 提供。

调用方（开发工具/视图/模块/薄壳）不得 import 本模块，只能经唯一能力调用入口
按能力 id 调用；存储目录由调用方按部署配置传入（缺省取工程缓存下的平台控制面
目录），本层不硬编码任何调用方的缓存根。
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from 平台控制面.授权 import 取共享授权服务
from 平台控制面.统一入口 import 统一能力服务, 稳定操作表
from 公共契约.运行时.运行缓存 import 解析运行缓存根

# 存储目录缺省值：经唯一解析器取运行态存储根（源码态 = `<系统根>/工程缓存/平台控制面`，
# 与旧的裸相对值同义；制品态 = 平台受管缓存）。裸相对路径在制品态会把运行态写进制品。
默认存储目录 = str(解析运行缓存根(Path(__file__).resolve().parents[3]) / "平台控制面")

# 存储目录 → 统一能力服务（同目录复用同一实例，避免每次调用重建状态库连接）。
_服务表: dict[str, 统一能力服务] = {}


def _取服务(存储目录: str) -> 统一能力服务:
    """按存储目录取统一能力服务；目录为空即抛错（由能力实现转 参数不合法）。"""
    目录 = str(存储目录 or 默认存储目录).strip()
    if not 目录:
        raise ValueError("存储目录不能为空")
    服务 = _服务表.get(目录)
    if 服务 is None:
        服务 = 统一能力服务(目录)
        # 与本层授权面共用同一会话表：授权面签发的令牌在本能力里同样有效
        # （会话表是进程内事实，两侧各持一份会让令牌跨面失效）。
        服务.授权 = 取共享授权服务(目录)
        _服务表[目录] = 服务
    return 服务


def 执行稳定操作(操作: str, 参数: dict[str, Any] | None = None, 令牌: str = "",
                 存储目录: str = "") -> Any:
    """按稳定操作名执行真实操作（授权 → 执行 → 证据），返回统一结果。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not str(操作 or "").strip():
        return 结果.失败("参数不合法", "操作不能为空", 来源="统一入口")
    if not str(令牌 or "").strip():
        return 结果.失败("参数不合法", "令牌不能为空（先经 平台控制面.授权.注册身份 取得令牌）",
                         来源="统一入口")
    if 参数 is not None and not isinstance(参数, dict):
        return 结果.失败("参数不合法", "参数必须是 JSON 对象", 来源="统一入口")
    值 = _取服务(存储目录).执行操作(令牌=令牌, 操作=操作, 参数=参数 or {})
    if not 值.get("成功"):
        # 内层错误码是调用方做错误分支的唯一依据，必须**结构化**外传：
        # 折叠进人读文本（原实现 `f"{错误码} {消息}"`）会让调用方只能做字符串
        # 搜索，错误码级断言随之失守（发布门禁实测受影响）。
        # 冻结口径（键名与类型自此不变，仅文本型）：
        #   外层 错误码 = 本能力契约声明的稳定码（参数不合法 / 操作失败）；
        #   内层码与内层消息进 详情（结果型标准字段），键名 内层错误码 / 内层消息。
        # 内层码为空时 详情 里该键仍存在（空串），调用方无需判键存在性。
        内层错误码 = str(值.get("错误码", "") or "")
        内层消息 = str(值.get("消息", "") or "")
        return 结果.失败("操作失败",
                         内层消息 or "操作未成功",
                         来源="统一入口",
                         详情={"内层错误码": 内层错误码, "内层消息": 内层消息})
    return 结果.成功结果({"操作": 值.get("操作", 操作),
                         "调用者": 值.get("调用者", ""),
                         "结果": 值})


def 查询稳定操作表() -> Any:
    """查询统一入口的稳定操作表（唯一权威列表）。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not 稳定操作表:
        return 结果.失败("稳定操作表为空", "统一入口未持有任何稳定操作", 来源="统一入口")
    return 结果.成功结果({"操作表": list(稳定操作表), "数量": len(稳定操作表)})
