"""平台控制面统一入口面公开入口（正式包包级中文入口）。

本目录是 `平台控制面` 正式根下的**统一能力入口治理面**正式包：把「用户与 Agent
统一能力入口」的对外动作收成本包的公开能力——按稳定操作名真实执行、查询稳定
操作表。授权 → 执行 → 证据的完整链路仍在同层唯一实现里，本包只做能力边界上的
参数校验与结果归一。

边界（决策记录 0012「波2：给治理层功能面补正规包」）：
- 调用方（开发工具/视图/模块/薄壳）**只经唯一能力调用入口**按能力 id 调用，
  不得 import `实现/` 目录；
- 本入口的 `注册能力(注册表)` 由加载器装配时调用，机器可读定义见同目录
  `能力定义.json`，实现见 `实现/能力入口.py`。

与既有 `平台控制面/统一入口.py` 的关系（不复制、不双写）：
`统一入口.py` 是 12 个稳定操作的**唯一实现**（授权→执行→证据、统一结果结构、
CLI 适配器）。本正式包目录与它同名，按 Python 导入规则包目录优先——若本入口不
显式接续，平台内所有 `from 平台控制面.统一入口 import 统一能力服务` 会全部失联。
因此本入口按**文件路径**显式载入该唯一实现并原样再导出（同一模块对象，不产生
第二份实现、不改行为、不静默降级）。
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

_唯一实现文件 = Path(__file__).resolve().parent.parent / "统一入口.py"
_唯一实现名 = "平台控制面._统一入口唯一实现"

if _唯一实现名 not in sys.modules:
    _规格 = importlib.util.spec_from_file_location(_唯一实现名, _唯一实现文件)
    _模块 = importlib.util.module_from_spec(_规格)
    sys.modules[_唯一实现名] = _模块
    _规格.loader.exec_module(_模块)
_唯一实现 = sys.modules[_唯一实现名]

统一能力服务 = _唯一实现.统一能力服务
命令行入口 = _唯一实现.命令行入口
稳定操作表 = _唯一实现.稳定操作表

包id = "平台控制面.统一入口"

from 平台控制面.统一入口.实现.能力入口 import (  # noqa: E402 —— 入口末尾导入实现，避免环
    执行稳定操作,
    查询稳定操作表,
)

__all__ = [
    "统一能力服务",
    "命令行入口",
    "稳定操作表",
    "包id",
    "执行稳定操作",
    "查询稳定操作表",
    "注册能力",
]


def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本治理面的公开能力。

    注册参数与 `能力定义.json` 逐条对应（参数名与顺序一致）；
    能力实现只做边界校验与结果归一，稳定操作语义仍在同层唯一实现 `统一入口.py` 里。
    """
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.统一入口.执行稳定操作",
        包id=包id,
        实现函数=执行稳定操作,
        参数=[{"名称": "操作", "类型": "文本型"},
              {"名称": "参数", "类型": "字典型"},
              {"名称": "令牌", "类型": "文本型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="按稳定操作名执行真实操作：授权 → 执行 → 证据，返回统一结果。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.统一入口.查询稳定操作表",
        包id=包id,
        实现函数=查询稳定操作表,
        参数=[],
        返回="结果",
        说明="查询统一入口的 12 个稳定操作名（唯一权威列表）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
