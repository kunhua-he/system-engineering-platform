"""平台控制面.资源预算监督 包级中文入口（正式包包级中文入口）。

平台控制面资源预算监督面：把 资源监督器 的预算声明判定语义切成可经网关调用的只读/判定原子能力（必需项清单、预算完整性、阈值有效性）。必需项与预算判定唯一实现在 平台控制面/资源监督.py，本包只做边界校验与结果归一；写类动作（注册执行单元/提交任务/排空/优雅停止）与运行中采样依赖进程内实例状态，不在本轮能力面。

本入口只做两件事：把同包实现里的公开函数重新导出，以及向加载器暴露
`注册能力(注册表)`。能力注册的参数名与顺序**逐条对应** `能力定义.json`
（`公共契约.能力契约.契约.能力实现.声明一致` 会逐项比对，写错即报不一致）。

正式包边界：调用方只经唯一能力调用入口按能力 id 调用，不得 import 实现，
也不得深入 `实现/` 目录。
"""

from __future__ import annotations

from 平台控制面.资源预算监督.实现.提供者 import 查询必需预算项
from 平台控制面.资源预算监督.实现.提供者 import 校验预算声明
from 平台控制面.资源预算监督.实现.提供者 import 校验预算阈值

__all__ = [
    "查询必需预算项",
    "校验预算声明",
    "校验预算阈值",
    "注册能力",
]

包id = "平台控制面.资源预算监督"



def _校验参数名序(参数契约表: dict[str, list[dict]],
                  注册参数名序: dict[str, list[str]]) -> None:
    """装配期闸门：注册参数名序必须逐字等于契约名序，否则本包装配失败。

    为什么要有它：注册处一旦漏一个参数（或顺序写反），网关的必填校验就与契约分叉
    ——那正是本包 2026-09-18 被修掉的缺陷形态。宁可装配期就 raise，也不静默漏参。
    """
    for 能力id, 契约参数 in 参数契约表.items():
        注册名序 = 注册参数名序.get(能力id)
        if 注册名序 is None:
            raise ValueError(f"能力 {能力id} 有契约但注册处未声明参数名序")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(注册名序):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(注册名序)} 与契约参数名序 {契约名序} "
                "不一致：参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），"
                "入口不得另立一份")

def 注册能力(注册表) -> None:
    """由加载器调用，注册本包公开能力（能力数：3；参数口径：查询必需预算项(无参数), 校验预算声明(资源预算), 校验预算阈值(资源预算)）。"""
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 参数契约镜像（**函数内字面量**；本块由「丢参」缺陷修复注入，勿删）
    #
    # 缺陷溯源（2026-09-18）：本入口原先手工重建注册参数声明（只写 名称/类型），把
    # `必填` 丢掉；而网关唯一校验点 `运行核心/统一网关/类型规格.py` 的判据是
    # `项.get("必填") is 真` → `None is 真` = 假 → 必填校验静默失效：少传参数不再被
    # 网关拦下，直接落进实现体抛 TypeError，用户拿到 HTTP 500 而不是干净的 400
    # 「缺少必填参数 X」。修法：参数声明从 `能力契约/参数契约.json` **整条透传**
    # （`参数=_参数契约表[能力id]`），入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：
    #  ① `_参数契约表` 是字面量、键是常量，`开发工具/契约编译/漂移检测` 的 AST 读取器
    #     （`_静态字面量` 的 `ast.Subscript` 分支）能解析出**整条参数含 `必填`** ——
    #     改前那处「参数口径未解析」不因本次修复恶化，反而把读不到的 `必填` 读到了。
    #     放在函数内是因为该读取器只收 `注册能力` 函数体内的赋值（`_扫描注册语句`）。
    #  ② 「裸布尔」防回潮门禁是全文件 AST 扫描，但只对三类判违规（`Return` 裸布尔 / 信封键 `成功`·`可重试` / `结果(裸布尔)`）；`必填` **不在**违规集里 —— 即字面量里的 `必填: True` 「看得见但不计违规」（实测命中 0 条）。
    # 表内 True/False 是**契约 JSON 的原值镜像**（JSON 无 真/假 字面量；`公共契约/基础类型/
    # 逻辑类型.py` 自己就写着 `真 = True`，JSON 契约侧同理），键集与契约逐字对应
    # （契约写了的键才留，没写的不补），不给漂移检测造出「注册声明了契约没声明的默认值」。
    # 为什么按下标取而不是包一层 `_参数声明(能力id)`：包一层会让 AST 一律判「不可静态
    # 判定」，等于拿门禁覆盖率换干净（不可接受）。名序护盾由 `_注册参数名序` +
    # `_校验参数名序()` 承担，装配期逐条对契约核名序，不一致即 raise。
    _参数契约表 = {
        "平台控制面.资源预算监督.查询必需预算项": [
        ],
        "平台控制面.资源预算监督.校验预算声明": [
            {"名称": "资源预算", "类型": "字典型", "必填": True, "默认值": None},
        ],
        "平台控制面.资源预算监督.校验预算阈值": [
            {"名称": "资源预算", "类型": "字典型", "必填": True, "默认值": None},
        ],
    }
    _注册参数名序 = {
        "平台控制面.资源预算监督.查询必需预算项": [],
        "平台控制面.资源预算监督.校验预算声明": ["资源预算"],
        "平台控制面.资源预算监督.校验预算阈值": ["资源预算"],
    }
    _校验参数名序(_参数契约表, _注册参数名序)
# ===== 参数声明透传 结束 =====
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.资源预算监督.查询必需预算项",
        包id=包id,
        实现函数=查询必需预算项,
        参数=_参数契约表["平台控制面.资源预算监督.查询必需预算项"],
        返回="结果",
        说明="查询资源监督器要求的全部必需预算项（只读）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.资源预算监督.校验预算声明",
        包id=包id,
        实现函数=校验预算声明,
        参数=_参数契约表["平台控制面.资源预算监督.校验预算声明"],
        返回="结果",
        说明="校验资源预算声明是否含资源监督器要求的全部必需项（判定，返回缺失项清单）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.资源预算监督.校验预算阈值",
        包id=包id,
        实现函数=校验预算阈值,
        参数=_参数契约表["平台控制面.资源预算监督.校验预算阈值"],
        返回="结果",
        说明="校验预算项取值本身是否有效（线程/并发/队列/句柄/重启次数为正整数、超时为正数、内存与临时空间可解析量纲），逐项给非法原因。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
