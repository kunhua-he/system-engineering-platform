def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本治理面的十类能力。

    ① 消费者契约五条：注册参数与 `能力定义.json` 逐条对应（参数名与顺序一致）；
    ② 文件租约五条：注册参数**读自** `能力契约/参数契约.json`（唯一事实源）。
    能力实现只做边界校验与结果收口，契约语义仍在同目录实现里。
    """
    from pathlib import Path

    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.登记消费者契约",
        包id=包id,
        实现函数=登记消费者契约,
        参数=[{"名称": "消费者id", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"},
              {"名称": "契约", "类型": "字典型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="登记消费者对能力的契约并落盘：契约结构不合法即判 契约非法。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.查询消费者契约",
        包id=包id,
        实现函数=查询消费者契约,
        参数=[{"名称": "能力id", "类型": "文本型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="查询能力下全部消费者契约（只读），返回公开记录表与数量。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.删除消费者契约",
        包id=包id,
        实现函数=删除消费者契约,
        参数=[{"名称": "消费者id", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="删除消费者与能力的契约绑定；未登记返回 未登记（失败即失败）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.判定契约漂移",
        包id=包id,
        实现函数=判定契约漂移,
        参数=[{"名称": "能力id", "类型": "文本型"},
              {"名称": "当前契约", "类型": "字典型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="逐项对比登记契约与当前契约，返回漂移列表与漂移数（只读）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.判定契约门禁",
        包id=包id,
        实现函数=判定契约门禁,
        参数=[{"名称": "能力id", "类型": "文本型"},
              {"名称": "当前契约", "类型": "字典型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="门禁判定：存在任一漂移即判阻断，返回是否阻断与漂移列表（只读）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    _注册文件租约能力(注册表)


def _注册文件租约能力(注册表) -> None:
    """注册文件租约五条能力：参数**读自** `能力契约/参数契约.json`（唯一事实源）。

    读不到契约即**不注册**（fail-closed）：宁可让门禁如实报「声明了但未注册实现」，
    也不许按记忆手写一份参数表冒充契约——那正是「同一事实两套」的起点。
    """
    from pathlib import Path

    from 公共契约.能力契约.契约 import 能力实现
    from 平台控制面.能力目录.实现.注册文件租约 import 读契约表, 注册参数

    包目录 = Path(__file__).resolve().parent
    契约表 = 读契约表(包目录)
    for 能力id, 实现函数 in 文件租约能力表:
        契约条目 = 契约表.get(能力id)
        if not 契约条目:
            continue
        注册表.注册(能力实现(
            能力id=能力id,
            包id=包id,
            实现函数=实现函数,
            参数=注册参数(契约条目),
            返回="结果",
            说明=str(契约条目.get("说明") or ""),
            版本=str(契约条目.get("版本") or "1.0.0"),
            提供者id=包id,
            提供者版本="1.0.0",
        ))
