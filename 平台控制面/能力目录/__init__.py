def _读真契约名序(包目录) -> dict[str, list[str]]:
    """读**真契约**（`能力契约/参数契约.json`）的参数名序。

    唯一读腿：转调 `实现/注册文件租约.读契约表`（本包读聚合契约的唯一入口），
    本函数只把契约条目的 `参数` 投影成 `{能力id: [参数名…]}`，**不另起一份 JSON 解析**
    （哲学 12.1）。读不到 / 结构不合法时 `读契约表` 返回空表，由 `_校验参数名序`
    如实判「真契约里没有该能力」并在装配期 raise（fail-closed：宁可装配失败，
    也不静默放过——静默放过正是本条漂移的形态）。
    """
    from 平台控制面.能力目录.实现.注册文件租约 import 读契约表
    return {
        能力id: [str(参数.get("名称") or "") for 参数 in (条目.get("参数") or [])]
        for 能力id, 条目 in 读契约表(包目录).items()
    }


def _校验参数名序(参数契约表: dict[str, list[dict]],
                  注册参数名序: dict[str, list[str]],
                  真契约名序: dict[str, list[str]]) -> None:
    """装配期闸门：注册镜像与注册名序必须逐字等于**真契约**名序，否则本包装配失败。

    为什么要有它：注册处一旦漏一个参数（或顺序写反），网关的必填校验就与契约分叉
    ——那正是本包 2026-09-18 被修掉的缺陷形态。宁可装配期就 raise，也不静默漏参。

    ★ 2026-09-23 修静默漂移：判据原先是「镜像 vs 名序」两份**都在本文件里**的自比
    （旧 `契约名序` 是从 `参数契约表` 现取的，与 `注册参数名序` 同源、同文件），两份
    一起写错即互证「一致」，**从不与真契约（`能力契约/参数契约.json`）比** ⇒
    `释放文件租约` 的真契约名序 `[租约id清单, 原因, 项目根, 存储目录]` 与本文件
    镜像/名序 `[租约id清单, 原因, 存储目录, 项目根]` 的顺序差异被静默放过
    （按关键字传参无害，按位置传参即把 项目根 与 存储目录 对调）。现改为：真契约名序
    由唯一读腿 `_读真契约名序` 读入，镜像与名序**各自**与真契约逐字核，任一处不一致
    即 raise（不接受放宽、不接受豁免登记）。
    """
    for 能力id, 镜像参数 in 参数契约表.items():
        契约名序 = 真契约名序.get(能力id)
        if 契约名序 is None:
            raise ValueError(
                f"能力 {能力id} 在注册镜像里，但真契约（能力契约/参数契约.json）里没有它："
                "注册声明不得先于契约存在，参数事实源只有契约一处（哲学 12.1）")
        镜像名序 = [参数.get("名称") for 参数 in 镜像参数]
        if 镜像名序 != list(契约名序):
            raise ValueError(
                f"能力 {能力id} 注册镜像参数名序 {镜像名序} 与真契约参数名序 "
                f"{list(契约名序)} 不一致：参数事实源只有 能力契约/参数契约.json 一处"
                "（哲学 12.1），入口不得另立一份")
        注册名序 = 注册参数名序.get(能力id)
        if 注册名序 is None:
            raise ValueError(f"能力 {能力id} 有契约但注册处未声明参数名序")
        if list(注册名序) != list(契约名序):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(注册名序)} 与真契约参数名序 "
                f"{list(契约名序)} 不一致：参数事实源只有 能力契约/参数契约.json 一处"
                "（哲学 12.1），入口不得另立一份")

