def _注册文件租约能力(注册表, 参数契约表: dict[str, list[dict]]) -> None:
    """注册文件租约五条能力：参数走 `参数契约表` 整条透传自 `能力契约/参数契约.json`。

    读不到契约条目即**不注册**（fail-closed）：宁可让门禁如实报「声明了但未注册实现」，
    也不许按记忆手写一份参数表冒充契约——那正是「同一事实两套」的起点。
    """
    from pathlib import Path

    from 公共契约.能力契约.契约 import 能力实现
    from 平台控制面.能力目录.实现.注册文件租约 import 读契约表

    包目录 = Path(__file__).resolve().parent
    契约表 = 读契约表(包目录)
    for 能力id, 实现函数 in 文件租约能力表:
        契约条目 = 契约表.get(能力id)
        if not 契约条目:
            continue
        注册表.注册(能力实现(
            能力id=能力id,
            包id=包id,
            实现函数=实现函数,
            # 参数声明唯一事实源 = 契约；本包模块级 `_参数契约表` 已整条镜像契约
            # （见文件首部注册块），这里按下标取即可，无需另传局部表。
            参数=参数契约表[能力id],
            返回="结果",
            说明=str(契约条目.get("说明") or ""),
            版本=str(契约条目.get("版本") or "1.0.0"),
            提供者id=包id,
            提供者版本="1.0.0",
        ))
