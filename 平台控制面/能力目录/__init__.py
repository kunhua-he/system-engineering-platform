"""能力目录包：中文公开入口（正式包包级入口）。

公开导出：能力目录（服务类）、契约指纹（指纹工具）、消费者契约注册表
（消费者契约登记/查询/删除/漂移/门禁的唯一语义实现），以及五条公开能力的
实现函数。

正式包边界（本目录是 `平台控制面` 正式根下的治理能力面）：
- 调用方（开发工具门禁、运行核心/统一网关、薄壳）**只经唯一能力调用入口**
  按能力 id 调用，不得 import 实现，也不得深入 `实现/` 目录；
- 本入口的 `注册能力(注册表)` 由加载器装配时调用，注册五条消费者契约能力：
  `登记消费者契约` / `查询消费者契约` / `删除消费者契约` / `判定契约漂移` /
  `判定契约门禁`（机器可读定义见同目录 `能力定义.json`，
  实现见 `实现/能力入口.py`）。
"""

from 平台控制面.能力目录.服务 import 能力目录, 契约指纹
from 平台控制面.能力目录.消费者契约注册表 import 消费者契约注册表, 统一返回
from 平台控制面.能力目录.实现.能力入口 import (
    登记消费者契约,
    查询消费者契约,
    删除消费者契约,
    判定契约漂移,
    判定契约门禁,
    默认存储目录,
)

__all__ = [
    "能力目录", "契约指纹", "消费者契约注册表", "统一返回",
    "登记消费者契约", "查询消费者契约", "删除消费者契约",
    "判定契约漂移", "判定契约门禁", "默认存储目录",
    "注册能力",
]

包id = "平台控制面.能力目录"


def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本治理面的五条能力。

    注册参数与 `能力定义.json` 逐条对应（参数名与顺序一致）；
    能力实现只做边界校验与结果收口，契约语义仍在同目录实现里。
    """
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.登记消费者契约",
        包id=包id,
        实现函数=登记消费者契约,
        参数=[{"名称": "消费者id", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"},
              {"名称": "契约", "类型": "字典型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="登记消费者对能力的契约并落盘：契约结构不合法即判 契约非法。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.查询消费者契约",
        包id=包id,
        实现函数=查询消费者契约,
        参数=[{"名称": "能力id", "类型": "文本型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="查询能力下全部消费者契约（只读），返回公开记录表与数量。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.删除消费者契约",
        包id=包id,
        实现函数=删除消费者契约,
        参数=[{"名称": "消费者id", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="删除消费者与能力的契约绑定；未登记返回 未登记（失败即失败）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.判定契约漂移",
        包id=包id,
        实现函数=判定契约漂移,
        参数=[{"名称": "能力id", "类型": "文本型"},
              {"名称": "当前契约", "类型": "字典型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="逐项对比登记契约与当前契约，返回漂移列表与漂移数（只读）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力目录.判定契约门禁",
        包id=包id,
        实现函数=判定契约门禁,
        参数=[{"名称": "能力id", "类型": "文本型"},
              {"名称": "当前契约", "类型": "字典型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="门禁判定：存在任一漂移即判阻断，返回是否阻断与漂移列表（只读）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
