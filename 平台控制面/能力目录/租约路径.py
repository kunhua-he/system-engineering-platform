"""文件租约路径边界：项目根相对路径的归一与边界校验（唯一实现）。

为什么单独一个文件：路径边界是**旧实现被记录的缺陷**——旧 `MCP工具箱/文件租约.py`
的 `申请文件租约` 只做归一化、不做项目根边界校验，`../` 之类越界相对路径也能进租约。
本模块把边界校验补成**硬失败**（第 1 条 2 项「不保留旧腿」：不继承旧口径），
并让 `模块库/开工编排` 的入参校验与租约申请落到同一套判据上。

判据（任一命中即拒绝，绝不静默归一后照收）：
① 非文本 / 空白；② 绝对路径（POSIX `/…` 与 Windows `C:\…`，**必须在归一化之前判**，
   否则归一化会抹掉前导斜杠，把 `/etc/passwd` 伪装成项目根内的相对路径）；
③ `~` 家目录写法；④ 归一化后含 `..` 段；⑤ 归一化后为空。
★ 2026-09-23（未完成事项 #106）：以上判据一律在 **URL 解码一次之后**做 —— 此前
   `..%2fetc` / `%2e%2e/x` / `a/..%2f/b` 三种编码穿越全放行（字面量里没有 `..` 段，
   判据看不见）。**只解一次**：二次解码本身是漏洞（见 `_解码URL一次`）。
"""
from __future__ import annotations

from typing import Any
from urllib.parse import unquote

拒绝_非文本 = "非文本或空白"
拒绝_绝对路径 = "绝对路径"
拒绝_家目录 = "~ 家目录写法"
拒绝_越界 = "含 .. 越界段"
拒绝_空 = "归一化后为空"
拒绝_盘符 = "Windows 盘符绝对路径"


def _解码URL一次(文本: str) -> str:
    """URL 解码归一化（未完成事项 #106，2026-09-23）：**只解一次，绝不解两遍**。

    二次解码本身就是漏洞：`%252e%252e` 解一次得 `%2e%2e`、再解一次就是 `..`。故本函数
    只接受**原始入参**；任何调用点都不得把已解码结果再送进来。
    """
    return unquote(文本)


def 归一化相对路径(原始: Any) -> str:
    """反斜杠转正斜杠、去前导 `./` 与首尾斜杠（与旧 文件租约.归一化路径 同口径）。

    ★ 2026-09-23（未完成事项 #106）：**入参必须是已 URL 解码的文本** —— 本层只在
    `校验相对路径` 里对**原始入参**解一次（`_解码URL一次`），本函数不再解码：
    同一条路径在一层里解两遍就是「二次解码」漏洞的温床（`%252e%252e` 解一次得
    `%2e%2e`、再解一次就是 `..`）。唯一调用点 `校验相对路径` 传的正是那次解码结果。
    """
    文本 = str(原始).strip().replace("\\", "/")
    while 文本.startswith("./"):
        文本 = 文本[2:]
    return 文本.strip("/")


def _是绝对路径(原文: str) -> bool:
    盘符 = len(原文) > 1 and 原文[1] == ":" and 原文[0].isalpha()
    return 原文.startswith("/") or 盘符


def 校验相对路径(原始: Any) -> tuple[str, str]:
    """校验一条项目根相对路径；返回 (归一化路径, 问题说明)，问题非空即拒绝。

    **顺序是判据的一部分**：绝对性/家目录必须在归一化之前判（见模块头注释 ②）。
    """
    if not isinstance(原始, str) or not 原始.strip():
        return "", f"修改路径必须是非空文本: {原始!r}"
    # URL 解码归一化（未完成事项 #106，2026-09-23）：绝对性/家目录判据必须看**解码后**的文本
    # —— `%2fetc/passwd` 解码后是 `/etc/passwd`，若不解码就会被归一化抹掉前导斜杠、伪装成
    # 项目根内的相对路径（正是模块头注释 ② 要防的那件事）。
    # **本层只解这一次**（吃的是原始入参），下面把同一个解码结果交给 归一化相对路径 复用，
    # 不再解第二遍 —— 对已解码值再解一次正是「二次解码」漏洞。
    解码文本 = _解码URL一次(原始.strip())
    原文 = 解码文本.replace("\\", "/")
    if _是绝对路径(原文):
        原因 = 拒绝_盘符 if not 原文.startswith("/") else 拒绝_绝对路径
        return "", f"只接受项目根内的仓库相对路径，拒绝{原因}: {原始!r}"
    if 原文.startswith("~"):
        return "", f"只接受项目根内的仓库相对路径，拒绝{拒绝_家目录}: {原始!r}"
    归一 = 归一化相对路径(解码文本)  # 复用本层唯一那次解码结果，不再解码
    if not 归一:
        return "", f"修改路径{拒绝_空}: {原始!r}"
    if 归一 == ".." or 归一.startswith("../") or "/../" in 归一 or 归一.endswith("/.."):
        return 归一, f"只接受项目根内的仓库相对路径，拒绝{拒绝_越界}: {原始!r}"
    if _是绝对路径(归一):
        return 归一, f"只接受项目根内的仓库相对路径，拒绝{拒绝_绝对路径}: {原始!r}"
    return 归一, ""
