def 盘上活跃(记录: object) -> bool:
    """盘上 `状态` 字段是否写着「活跃」—— **不看过期时间**。

    这是「占用判定」与「清理判定」两个不同问题的**前半个问题**，必须与 `是活跃`
    分开命名（2026-09-23 实测的病根就是两者混用）：

    - **占用判定**（`申请文件租约` / `续租` / `留言` / `查询.只要活跃`）问的是
      「这条记录现在还算不算占着路径」—— 已过期的租约**不再挡路径**，
      故用 `是活跃`（状态活跃 **且** 未过期）；
    - **清理判定**（`回收过期文件租约`）要收的恰恰是「盘上状态仍写着活跃、
      但已过点」那一批 —— 拿 `是活跃` 当入口门，目标集合会被自身判据滤空。
      实测 2026-09-23：存储 714 条里 397 条「状态活跃且已过期」，
      `回收过期文件租约(心跳超时秒=300)` 两次都回 `回收数 0`（默认/显式存储目录
      都试过）—— 回收是**结构性空转**，一条也收不走，僵尸记录在盘上永久冒充活跃。

    一句话：`是活跃` = `盘上活跃` 且 未过期；清理侧只能看 `盘上活跃`。
    """
    return isinstance(记录, dict) and 记录.get("状态") == 活跃状态


def 是活跃(记录: object, *, 现在: float | None = None) -> bool:
    """记录是否活跃（非活跃 = 可被同一路径重新认领）。

    **活跃 = 状态为活跃 且 未过期**（两条件同时成立）。修前只判 `状态` 字段，
    不看 `过期时间` —— 于是**过期租约仍是活跃**，僵尸租约把同一路径永久挡死：
    实测 2026-09-20 一条 21:13:59 到期的租约在 21:35 仍判活跃，其所有者
    （就是当时正在开工的会话自己）连"跳过占用"都拿不到路径，
    `开工编排.开工即占` 直接失败 —— 与同包 `文件租约维护.续租` 注释里
    写的「过期租约只能重新申请」自相矛盾（那句注释描述了本函数的应有语义，
    但实现从未接线）。

    `过期时间` 缺键/非数值时按「不判过期」处理（老记录容忍：不新造事实）；
    过期但 `状态` 仍为活跃的记录由调用方按需改判 `状态_已过期`（本函数只判不写）。

    实现只由 `盘上活跃` + 过期两半组成（**不再各自判 `状态` 字面量**）：
    「盘上状态是活跃」这件事全仓只有 `盘上活跃` 一处定义，避免第二个判据漂移。
    """
    if not 盘上活跃(记录):
        return 假
    如果 = 现在 if 现在 is not None else time.time()
    try:
        截止 = float(记录.get("过期时间"))  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return 真   # 缺键/坏值：无从判过期，按活跃处理（不因数据缺失误放行）
    return 如果 < 截止


