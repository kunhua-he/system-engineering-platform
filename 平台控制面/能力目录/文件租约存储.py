"""文件租约存储：单 JSON 存储的原子读写与竞争互斥（唯一写入口）。

归属：文件租约是**多会话并发写同一文件**的平台级互斥，属平台治理面，落
`平台控制面.能力目录`。事实唯一落 `存储目录/文件租约.json`，与同包
`消费者契约注册表.py` 同一种做法（单 JSON 存储、按存储目录实例化，
**不建新表、不改任何既有存储结构**）。

并发机制**不再由本文件自带**，一律走同包 `单文件互斥存储.py` 的唯一底座
（类级实例缓存 `取实例` + RLock + 跨进程 flock + 锁内重读 + 唯一临时名 + fsync +
`os.replace`）：同包两条单 JSON 存储（文件租约、消费者契约）共用同一套锁，
不重复实现第二套；本文件只留租约自己的数据语义（认领判据、租约字段、回收口径）。

**互斥保证（应用级唯一判定）**：认领 = 「独占区内以磁盘最新内容重读 → 判定活跃占用 →
唯一临时文件 + `os.replace` 原子替换」。三个条件缺一不可（详见基座模块头注释）：

1. **同目录同实例**（`取实例`）：锁随实例创建，`取存储` 每次 new 一把新锁时，两个调用方
   各持一把互不相干的锁，"check-then-act" 就没有闸门——这是实测到并发双认领的病根；
2. **跨进程锁**（锁文件 `<存储目录>/.文件租约.lock` + `fcntl.flock(LOCK_EX)`）：进程内锁
   对另一个进程无效，跨进程只能靠 OS 级文件锁。锁文件被破坏（如被目录占位）时**如实报
   「锁不可用」并拒绝读写**，绝不假装拿到锁继续；
3. **锁内重读磁盘**：临界区里先 `读取()` 拿磁盘现状，再判、再写；`os.replace` 原子，读者
   永远看不到半写状态。

**写原子性**：临时文件名唯一化（`.<存储文件名>.tmp-<pid>-<uuid8>`）并 `fsync` 后才
`os.replace`。`os.replace` 失败时**重读磁盘判定**（写入其实已生效即算成功；另有他因则
如实报写失败并回带磁盘实况），不回落成笼统的「存储目录不可用」。

**残余风险（缺 DB 唯一索引）**：`平台控制面/平台状态/状态存储.py` 不在本批允许域，且该库
既有部分唯一索引 `索引_占用活跃` 是按**单列 能力id** 建的 —— 文件键写回那张表会让
「同一能力 id 只有一条活跃租约」的单列唯一语义失效，故本批不写回该表；跨进程互斥由上面
这三条应用级判定承担，不依赖数据库级唯一约束。
"""
from __future__ import annotations

import hashlib
import json
import time
import uuid
from pathlib import Path
from typing import Any

from 平台控制面.能力目录.单文件互斥存储 import 单文件互斥存储

存储文件名 = "文件租约.json"
锁文件名 = ".文件租约.lock"
活跃状态 = "活跃"
状态_已释放 = "已释放"
状态_已过期 = "已过期"
默认持有秒 = 300.0
最长持有秒 = 86400.0
# —— 内容指纹（乐观锁的「内容」那一半）——
# 只锁路径挡不住「A 认领后把文件改了、B 拿着旧认知接着改」：路径没变、内容已变，
# 两侧都以为自己是第一个改的。指纹登记的就是认领那一刻的内容事实。
# 算法统一 sha256（与平台其余指纹口径同一算法，不引入第二套；不做 MD5）。
内容指纹算法 = "sha256"
指纹_不存在 = "不存在"
指纹_目录 = "目录"
# 留言长度上限（防把存储撑爆；留言是审计链，不是数据通道）。
留言上限字 = 2000
留言条数上限 = 200
# 跨进程锁最长等待秒：等不到即如实报「锁不可用」硬失败，绝不无锁继续（宁可失败也不双认领）。
最长等锁秒 = 120.0
等锁重试间隔秒 = 0.005
# 实例缓存上限：只淘汰「当前没被任何线程持有」的实例，淘汰一个正被持有的实例会让同一目录
# 出现两把线程锁（互斥会再次失效），所以持有中的实例一律留驻。
实例上限 = 256


def 文件键(路径: str) -> str:
    """文件租约键：`文件::<项目根相对路径>`（与 平台状态.占用租约 表 能力id 列同形）。"""
    return f"文件::{路径}"


def 时间文本(时间戳: object) -> str:
    """时间戳 → 人读文本（本地时区 `%Y-%m-%d %H:%M:%S`，平台统一口径）。"""
    try:
        return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(float(时间戳)))  # type: ignore[arg-type]
    except (TypeError, ValueError, OSError):
        return ""


def 是活跃(记录: object) -> bool:
    """记录是否活跃（非活跃 = 可被同一路径重新认领）。"""
    return isinstance(记录, dict) and 记录.get("状态") == 活跃状态


def _文件指纹字节流(文件: Path) -> str:
    """按块算 sha256（大文件不吃内存）；读失败即抛 `OSError` 交调用方判定。"""
    摘要 = hashlib.sha256()
    with 文件.open("rb") as 句柄:
        while True:
            块 = 句柄.read(1 << 20)
            if not 块:
                break
            摘要.update(块)
    return 摘要.hexdigest()


def 计算内容指纹(项目根: Path | str, 相对路径: str) -> tuple[str, str]:
    """算一条项目根相对路径的**内容指纹**；返回 (指纹, 问题)，问题非空即算不出来。

    口径（三种「算不出来」必须可区分，不许都压成空串）：
    - 文件在场 → `sha256:<64位小写十六进制>`；
    - 文件不在场（新建/刚被删）→ 常量 `不存在`（**不是错误**：新建也是合法认领）；
    - 路径是目录 / 读不动（权限、IO 错）→ 常量 `目录` 或 `不可读:<异常类型>`。

    为什么不是「算不出来就算了、留空串」：空串会让「没登记指纹」与「文件不存在」
    在读数上完全一样，调用方据此无法判断是「本就没锁内容」还是「文件已被删」——
    这正是 14.4「状态要能被机器判」的要求。算法统一 sha256（不做第二套摘要）。
    """
    路径 = Path(项目根) / 相对路径
    try:
        if 路径.is_dir():
            return 指纹_目录, ""
        if not 路径.exists():
            return 指纹_不存在, ""
        摘要 = _文件指纹字节流(路径)
    except OSError as 错误:
        return f"不可读:{type(错误).__name__}", f"内容指纹算不出来（{相对路径}）: {错误}"
    except ValueError as 错误:
        return f"不可读:{type(错误).__name__}", f"内容指纹算不出来（{相对路径}）: {错误}"
    return f"{内容指纹算法}:{摘要}", ""


def 指纹是否一致(声明: object, 现在: object) -> bool:
    """声明指纹与现场指纹是否一致（空/缺声明一律视为「无可比」→ 不一致）。"""
    声明值 = str(声明 or "").strip()
    现场值 = str(现在 or "").strip()
    return bool(声明值) and bool(现场值) and 声明值 == 现场值


def 留言条目(作者: str, 正文: str, 现在: float | None = None) -> dict:
    """构造一条留言（句柄内的备注；只增不改，构成审计链）。"""
    时刻 = time.time() if 现在 is None else 现在
    return {"作者": 作者, "留言": 正文, "时间": 时间文本(时刻), "时刻": 时刻}


def _规范化(数据: object) -> str:
    """内容可比文本（判「磁盘上的就是本次要写的」用）；不可序列化即空串。"""
    try:
        return json.dumps(数据, ensure_ascii=False, sort_keys=True)
    except (TypeError, ValueError):
        return ""


class 文件租约存储(单文件互斥存储):
    """文件租约存储；心跳单位为秒（浮点），键为 `文件::<路径>`。

    实例一律经 `取实例` 取（同目录同实例）；实例缓存/线程锁/跨进程锁/原子落盘一律
    由 `单文件互斥存储` 唯一承载（同包不再有第二套并发机制）。
    """

    存储标签 = "文件租约存储"
    # 文件名与上限沿用模块常量（唯一事实源：不在类里再抄一份字面量）
    存储文件名 = 存储文件名
    锁文件名 = 锁文件名
    最长等锁秒 = 最长等锁秒
    等锁重试间隔秒 = 等锁重试间隔秒
    实例上限 = 实例上限

    # ── 存储基础 ──────────────────────────────────────────────
    def 读取(self) -> tuple[dict, str]:
        """读取存储；文件缺失视为空库；**损坏即报错**（不按空库继续，避免静默丢租约）。

        本方法在 `独占()` 内调用即等于「锁内以磁盘最新内容重读」。锁没拿到（锁文件被破坏、
        等锁超时）时一律如实报「锁不可用」，不假装读到空库、也不继续判占用。
        """
        锁问题 = self.锁问题()
        if 锁问题:
            return {}, 锁问题
        if not self.存储文件.is_file():
            return {}, ""
        try:
            正文 = self.存储文件.read_text(encoding="utf-8")
        except OSError as 错误:
            return {}, f"文件租约存储不可读: {错误}"
        except UnicodeDecodeError as 错误:
            return {}, f"文件租约存储编码损坏: {错误}"
        try:
            数据 = json.loads(正文)
        except json.JSONDecodeError as 错误:
            return {}, f"文件租约存储损坏（拒绝按空库继续）: {错误}"
        return (数据 if isinstance(数据, dict) else {}), ""

    def 写入(self, 数据: dict) -> str:
        """临时文件（唯一名、fsync）+ `os.replace` 原子替换；返回问题说明（成功为空串）。

        `os.replace` 失败时**重读磁盘判定**：磁盘上已是本次要写的内容 → 视为写入生效；
        磁盘另有实况 → 如实报「原子替换失败」并回带磁盘实况。不回落成笼统的
        「存储目录不可用」，也不静默成功。
        """
        锁问题 = self.锁问题()
        if 锁问题:
            return 锁问题
        正文 = json.dumps(数据, ensure_ascii=False, indent=2, sort_keys=True)
        try:
            # 落盘一律走基座单一口径（唯一临时名 + fsync + os.replace + 目录 fsync + 失败清临时）
            self.原子写文本(正文, 权限=0o644)
        except OSError as 错误:
            现有, 读问题 = self.读取()
            if 读问题:
                return f"文件租约存储原子替换失败（重读磁盘判定：{读问题}）: {错误}"
            if _规范化(现有) == _规范化(数据):
                return ""
            return (f"文件租约存储原子替换失败（已重读磁盘判定：磁盘内容与本次写入不一致，"
                    f"磁盘实有 {len(现有)} 条记录）: {错误}")
        return ""

    @staticmethod
    def 按租约id找键(存储: dict, 租约id: str) -> str:
        for 键, 记录 in 存储.items():
            if isinstance(记录, dict) and str(记录.get("租约id") or "") == 租约id:
                return 键
        return ""

    @staticmethod
    def 新租约(路径: str, 所有者: str, 任务: str, 持有秒: float,
               存储标签: str, 现在: float | None = None,
               内容指纹: str = "", 已声明指纹: str = "") -> dict:
        """构造一条活跃租约记录（字段与 平台状态.占用租约 表列族同名同义）。

        新增两键（乐观锁的「内容」那一半；老调用不传即空串，行为与旧口径一致）：
        - `内容指纹`：认领那一刻**现场算得**的指纹（事实）；
        - `已声明指纹`：调用方**自己声明**的指纹（期望）。两者可以不同 —— 不同正是
          「A 认领后文件已被改」的机器可判信号，登记下来而不是当场拒绝（认领是
          「我先站住」，不是「内容必须与我的认知一致」）。
        `留言` 初始为空表（留言只增不改，构成审计链）。
        """
        时刻 = time.time() if 现在 is None else 现在
        return {
            "租约id": uuid.uuid4().hex[:16], "键": 文件键(路径), "路径": 路径,
            "所有者": 所有者, "任务": 任务, "存储标签": 存储标签,
            "心跳": 时刻, "申请时间": 时间文本(时刻),
            "过期时间": 时刻 + 持有秒, "状态": 活跃状态,
            "释放时间": "", "释放原因": "",
            "内容指纹": str(内容指纹 or ""), "已声明指纹": str(已声明指纹 or ""),
            "留言": [],
        }

    @staticmethod
    def 对外记录(记录: dict) -> dict:
        """对外读数：浮点心跳照给，另附人读时间字段（不改变内部字段名）。

        三处补读数（都是**读数**、不新造事实）：`指纹一致` 是可判的机器结论
        （声明与现场是否一致，缺声明即假）、`留言数` 让调用方一眼看出有没有备注、
        `留言` 缺键补空表（老记录没有这一列，不许让调用方拿到 None 再自己猜）。
        """
        对外 = dict(记录)
        对外["心跳时间"] = 时间文本(记录.get("心跳"))
        对外["过期时间读数"] = 时间文本(记录.get("过期时间"))
        对外["留言"] = list(记录.get("留言") or [])
        对外["留言数"] = len(对外["留言"])
        对外["指纹一致"] = 指纹是否一致(记录.get("已声明指纹"), 记录.get("内容指纹"))
        return 对外
