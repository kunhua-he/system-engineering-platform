#: 心跳停摆兜底阈值（秒）：模块级唯一事实源，类属性与 `回收过期占用` 缺省值都引用它。
默认心跳超时秒 = 300.0


def 已失效(记录: object, *, 现在: float | None = None,
           心跳超时秒: float = 默认心跳超时秒) -> bool:
    """**清理判定的动作判据**（唯一具名定义）：这条盘上活跃的租约是否已失效、该回收。

    两个回收动作共用本判据 —— `回收能力过期租约`（范围收窄到某能力）与
    `回收过期占用`（全表）**判据一处、范围不同**，不是两套实现。三条任一命中即失效：

    - **到点**：`过期时间` 可判（数值）且 <= 现在；
    - **停摆**：`心跳` 可判（数值）且 <= 现在 - `心跳超时秒`；
    - **无存活证据**：`过期时间` 与 `心跳` **都不可判**（缺键 / 坏值）⇒ 判失效。
      没有这一支，一条盘上写着「活跃」的行既收不走、也续不成，会**永久占着**
      `索引_占用活跃` 的唯一槽位 —— 同一能力此后谁都申请不到（永久锁死，正是
      `申请占用` 的内联 CAS 回收要治的那件事）。

    与**占用判定** `是活跃` 的分工（两个问题，故意不同口径，不许混用）：
    `是活跃` 问「这条租约现在**还挡不挡路**」——数据缺失时**保守判占用**（不误放行），
    故 `过期时间` 缺/坏**不**判过期；本判据问「这条盘上活跃的租约**该不该清掉**」——
    数据缺失到没有任何存活证据时判**失效**（不永久锁死），但只有「两个时间戳都不可判」
    才走这一支：只要心跳还在跳，这条行就仍算活着，不许抢（`过期时间` 坏 + 心跳新鲜
    的行由「停摆」支在其心跳停摆后回收，不在此刻抢走）。
    """
    如果 = time.time() if 现在 is None else 现在
    过期 = 记录.get("过期时间") if isinstance(记录, dict) else None
    心跳 = 记录.get("心跳") if isinstance(记录, dict) else None
    # 可判 = 数值且非 bool（bool 是 int 子类，必须排除）。
    过期可判 = isinstance(过期, (int, float)) and not isinstance(过期, bool)
    心跳可判 = isinstance(心跳, (int, float)) and not isinstance(心跳, bool)
    if not 过期可判 and not 心跳可判:
        return 真                                   # 无存活证据
    if 过期可判 and float(过期) <= 如果:
        return 真                                   # 到点
    return 心跳可判 and float(心跳) <= 如果 - 心跳超时秒   # 停摆


class 能力目录:
    """能力目录服务（唯一写入口：平台状态.能力条目/占用租约）。"""

    # 「相同契约指纹阻断重复实现」的既有失败文案：顺序调用与并发冲突共用同一句，
    # 不新造错误码（本服务对外只回 (成功, 消息)，无独立错误码字段）。
    重复实现文案 = "相同契约指纹已存在: {占用者}（必须复用或声明新提供者）"

    def __init__(self, 状态) -> None:
        self.状态 = 状态

    def _重复实现(self, 占用者: str) -> tuple[bool, str]:
        return 假, self.重复实现文案.format(占用者=占用者)

    def 登记能力(self, *, 能力id: str, 契约: dict[str, Any], 组件: str, 领域: str,
                成熟度: str = "实验", 所有者: str = "", 提供者: str = "",
                资源: dict[str, Any] | None = None) -> tuple[bool, str]:
        """登记能力；相同契约指纹直接阻断重复实现。

        并发下的重复实现门禁（唯一边界在此）：
        - 快路径：先按指纹查一次（顺序调用时给出占用者能力 id，文案逐字不变）；
        - **原子边界**：写侧走 `平台状态.写入记录或唯一冲突` + `能力条目(契约指纹)`
          部分唯一索引（结构 1.5.0，见 `平台状态.状态存储._迁移到150`）。两个进程/
          线程同时登记同一指纹的**两个不同能力 id** 时，索引只放行一条，另一条的写
          以唯一冲突返回，这里按指纹回读占用者后回**同一句既有失败文案**。
          修复前这条路径没有闸门（实测 8 路并发 8/8 落库、跨进程 6 路 6/6 落库）：
          同指纹条目双双进目录，之后「重复实现门禁」按指纹只查得到一条，等于漏判。
        - 这里**不许**用 `写入记录`：它的 `INSERT OR REPLACE` 遇到唯一索引冲突会先
          删掉对方那行再插入自己（SQLite REPLACE 语义，本地实测过），并发下会静默
          删掉先落库那条、自己还报成功——比双双落库更糟。
        """
        指纹 = 契约指纹(契约)
        已有 = self.状态.查询记录("能力条目", "契约指纹=?", (指纹,))
        if 已有 and 已有[0]["能力id"] != 能力id:
            return self._重复实现(已有[0]["能力id"])
        成功, 占用者 = self.状态.写入记录或唯一冲突("能力条目", {
            "能力id": 能力id, "契约指纹": 指纹, "组件": 组件, "领域": 领域,
            "成熟度": 成熟度, "所有者": 所有者, "替代能力": "", "复用裁决": "",
            "裁决状态": "已登记", "提供者": 提供者,
            "资源": json.dumps(资源 or {}, ensure_ascii=False), "版本": "1",
        }, "能力id", "契约指纹")
        if not 成功:
            return self._重复实现(占用者)
        return 真, "能力已登记"

    def 搜索能力(self, 关键词: str = "", 限制: int = 20) -> list[dict[str, Any]]:
        结果表 = []
        for 记录 in self.状态.查询记录("能力条目"):
            if 关键词 and 关键词 not in 记录["能力id"] and 关键词 not in 记录["组件"]:
                continue
            结果表.append({键: 记录[键] for 键 in
                          ("能力id", "组件", "领域", "成熟度", "所有者", "裁决状态")})
            if len(结果表) >= 限制:
                break
        return 结果表

    def 待裁决(self) -> list[dict[str, Any]]:
        return [记录 for 记录 in self.状态.查询记录("能力条目")
                if 记录["裁决状态"] == "待裁决"]

    def 裁决(self, *, 能力id: str, 决定: str, 替代能力: str = "",
             维护者: str = "") -> tuple[bool, str]:
        """维护者裁决：复用/合并/允许并存/拒绝；裁决写入能力目录供后续继承。"""
        if 决定 not in ("复用", "合并", "允许并存", "拒绝"):
            return 假, f"未知裁决: {决定}"
        更新 = {"复用裁决": 决定, "裁决状态": "已裁决"}
        if 替代能力:
            更新["替代能力"] = 替代能力
        self.状态.条件更新("能力条目", 更新, "能力id=?", (能力id,))
        self.状态.追加证据(类型="能力目录", 主题=能力id, 内容={"裁决": 决定, "替代": 替代能力},
                          调用者=维护者, 角色="平台维护者", 结果="裁决")
        return 真, f"裁决完成: {决定}"

    # ---- 能力占用租约 ----
    # 类属性引用模块常量（唯一事实源在模块级，类里不再抄一份 300.0 字面量）。
    默认心跳超时秒 = 默认心跳超时秒

    def 申请占用(self, *, 能力id: str, 领域: str, 契约指纹: str, 任务: str,
                所有者: str, 心跳秒: float = 60.0) -> tuple[bool, str, str]:
        """申请能力占用；唯一部分索引（活跃租约同能力唯一）原子保证互斥。

        申请失败不是立刻判「被占用」：先内联 CAS 回收该能力下**已失效**的活跃租约再重试一次
        （判据 = `已失效`：到点 / 停摆 / 无存活证据）。
        为什么必须自愈：占用者崩溃（Agent 中断）后租约还挂在部分唯一索引上，
        没人回收就永远「活跃」，这个能力此后谁都申请不到——同一能力被永久锁死。
        """
        租约id = uuid.uuid4().hex[:16]
        现在 = time.time()
        记录 = {
            "租约id": 租约id, "能力id": 能力id, "领域": 领域, "契约指纹": 契约指纹,
            "任务": 任务, "所有者": 所有者, "心跳": 现在,
            "过期时间": 现在 + 心跳秒 * 10, "释放证据": "", "状态": 占用租约状态_活跃,
        }
        成功 = self.状态.原子插入("占用租约", 记录)
        if not 成功:
            if self.回收能力过期租约(能力id):
                成功 = self.状态.原子插入("占用租约", 记录)
        if not 成功:
            # 占用者读数走**占用判定** `是活跃`（状态活跃 **且** 未过期），不是「盘上状态是活跃」：
            # 已过点/已失效的僵尸租约不该被报成占用者（2026-09-23 收口）。此前按
            # `状态='活跃'` 取，只要回收腿没把它收走，就会指名一个其实已经过期的占用者。
            占用者 = "未知"
            for 租约 in self.状态.查询记录(
                    "占用租约", f"{占用租约盘上活跃条件} AND 能力id=?", (能力id,)):
                if 是活跃(租约, 现在=现在):
                    占用者 = str(租约.get("所有者") or "未知")
                    break
            return 假, f"能力已被占用: {占用者}", ""
        return 真, "占用成功", 租约id

    def 回收能力过期租约(self, 能力id: str) -> list[str]:
        """CAS 回收某能力下**已失效**的盘上活跃租约；幂等。

        入口门 = `盘上活跃`（SQL 形态 `占用租约盘上活跃条件`：只看盘上 `状态`，
        **不看过期时间**）——本函数要收的恰恰是「盘上状态仍写着活跃、但已失效」那一批；
        拿 `是活跃` 当门会把目标集合自身整批滤空（2026-09-23 已实测的病根：`到点` 分支永不可达）。
        失效判据 = `已失效`（唯一具名定义，与 `回收过期占用` 同一判据，只是范围收窄到本能力）。
        """
        现在 = time.time()
        已回收 = []
        for 租约 in self.状态.查询记录(
                "占用租约", f"{占用租约盘上活跃条件} AND 能力id=?", (能力id,)):
            if not 已失效(租约, 现在=现在):
                continue
            if self.状态.条件更新("占用租约", {"状态": "已过期"},
                                  f"租约id=? AND {占用租约盘上活跃条件}", (租约["租约id"],)):
                已回收.append(租约["租约id"])
        return 已回收

    def 续租(self, 租约id: str) -> bool:
        """续租（**占用判定**）：过期即拒 —— 与 `续租文件租约` 同一口径（过期只能重新申请）。

        2026-09-23 收口：此前判据是 `记录["状态"] != "活跃"`（只看盘上状态、**不看过期时间**），
        于是「状态活跃但已过期」的占用租约可以被续租**复活**，与同包 `续租文件租约`
        （入口门 `是活跃`：过期即进失败清单、不能复活）口径相反 —— 同一件事两套判据。
        现在两处都转调唯一那条 `是活跃`。
        """
        记录 = self.状态.读取记录("占用租约", "租约id", 租约id)
        if not 是活跃(记录):
            return 假
        # 续租必须连 过期时间 一起顺延：租期 = 申请时写入的 过期时间 - 心跳。
        # 只推 心跳 不推 截止时间，活着的租约会在原截止点被 回收过期租约 判死，
        # 能力被别的 Agent 接管——这比不回收更危险。
        时刻 = time.time()
        租期 = float(记录.get("过期时间") or 0) - float(记录.get("心跳") or 0)
        if 租期 <= 0:
            租期 = self.默认心跳超时秒 * 2
        return self.状态.条件更新("占用租约", {"心跳": 时刻, "过期时间": 时刻 + 租期},
                                  f"租约id=? AND {占用租约盘上活跃条件}", (租约id,))

    def 释放占用(self, 租约id: str, 证据: str = "") -> bool:
        """显式释放（**清理判定**的终结动作）：入口门 = `盘上活跃`（只看盘上状态），
        **过期与否不影响能不能终结** —— 与 `释放文件租约` 同一入口门；不能复活的只有 `续租`。
        """
        return self.状态.条件更新("占用租约", {"状态": "已释放", "释放证据": 证据},
                                  f"租约id=? AND {占用租约盘上活跃条件}", (租约id,))

    def 回收过期占用(self, 心跳超时秒: float = 默认心跳超时秒) -> list[str]:
        """Agent 中断后占用自动过期（心跳停止）；幂等。

        入口门 = `盘上活跃`（只看盘上状态），失效判据 = `已失效`（**唯一具名定义**，
        与 `回收能力过期租约` 同一判据，本动作范围 = 全表）：
        - `过期时间` 已到点（权威判据，续租会顺延）；
        - 或 `心跳` 停摆超过 `心跳超时秒`（兜底，覆盖没有有效截止时间的历史行）；
        - 或 `过期时间` 与 `心跳` 都不可判（无存活证据 ⇒ 判失效，否则这条盘上活跃的行
          永久占着 `索引_占用活跃` 的唯一槽位）。
        逐行 CAS，只有状态仍是「活跃」才改。
        """
        现在 = time.time()
        过期列表 = []
        for 租约 in self.状态.查询记录("占用租约", 占用租约盘上活跃条件):
            if not 已失效(租约, 现在=现在, 心跳超时秒=心跳超时秒):
                continue
            if self.状态.条件更新("占用租约", {"状态": "已过期"},
                                  f"租约id=? AND {占用租约盘上活跃条件}", (租约["租约id"],)):
                过期列表.append(租约["租约id"])
        return 过期列表
