"""能力目录：组件/能力/契约/资源/提供者/所有者/成熟度/替代能力/复用裁决。

转调契约指纹（**唯一实现**在 `公共契约/能力契约/契约指纹.py`，本文件只再导出，见下方 import 注释）、
复用决策强制、能力占用租约（心跳/过期/释放证据）、
维护者裁决（复用/合并/允许并存/拒绝）；相同契约指纹直接阻断重复实现，
高度重叠进入待裁决；Agent 中断后占用自动过期（申请失败路径内联 CAS 回收 + 周期回收）。

并发边界（两条事实各有自己的原子防线，都不靠应用层「读→判→写」）：
- 能力条目：`能力条目(契约指纹)` 部分唯一索引（结构 1.5.0，见
  `平台控制面/平台状态/状态存储.py._迁移到150`）+ `写入记录或唯一冲突`——
  并发登记同一指纹的两个不同能力 id 时只有一条落库，另一条回既有失败文案；
- 占用租约：`索引_占用活跃` 部分唯一索引 + `原子插入`（申请失败先内联 CAS 回收）。
"""
from __future__ import annotations

import json
import time
import uuid
from typing import Any

# 唯一事实源（2026-09-17 下移）：契约指纹的**唯一实现**在 `公共契约/能力契约/契约指纹.py`
# （纯计算、契约语义，归最底层；下移前曾在本文件内实现，属治理层持有契约语义的层错位）。
# 这里只做再导出，不再保有任何算指纹的代码：全仓
# `rg -n 'sha256' 平台控制面/能力目录/ 公共契约/` 只剩公共契约那一处。
# 公开导出名 `平台控制面.能力目录.契约指纹`（经本包 __init__ 与 平台控制面/__init__ 再导出）
# 保持不变，既有消费方零改动；两边拿到的是**同一个函数对象**，不构成第二套实现。
from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.能力契约.契约指纹 import 契约指纹


class 能力目录:
    """能力目录服务（唯一写入口：平台状态.能力条目/占用租约）。"""

    # 「相同契约指纹阻断重复实现」的既有失败文案：顺序调用与并发冲突共用同一句，
    # 不新造错误码（本服务对外只回 (成功, 消息)，无独立错误码字段）。
    重复实现文案 = "相同契约指纹已存在: {占用者}（必须复用或声明新提供者）"

    def __init__(self, 状态) -> None:
        self.状态 = 状态

    def _重复实现(self, 占用者: str) -> tuple[bool, str]:
        return 假, self.重复实现文案.format(占用者=占用者)

    def 登记能力(self, *, 能力id: str, 契约: dict[str, Any], 组件: str, 领域: str,
                成熟度: str = "实验", 所有者: str = "", 提供者: str = "",
                资源: dict[str, Any] | None = None) -> tuple[bool, str]:
        """登记能力；相同契约指纹直接阻断重复实现。

        并发下的重复实现门禁（唯一边界在此）：
        - 快路径：先按指纹查一次（顺序调用时给出占用者能力 id，文案逐字不变）；
        - **原子边界**：写侧走 `平台状态.写入记录或唯一冲突` + `能力条目(契约指纹)`
          部分唯一索引（结构 1.5.0，见 `平台状态.状态存储._迁移到150`）。两个进程/
          线程同时登记同一指纹的**两个不同能力 id** 时，索引只放行一条，另一条的写
          以唯一冲突返回，这里按指纹回读占用者后回**同一句既有失败文案**。
          修复前这条路径没有闸门（实测 8 路并发 8/8 落库、跨进程 6 路 6/6 落库）：
          同指纹条目双双进目录，之后「重复实现门禁」按指纹只查得到一条，等于漏判。
        - 这里**不许**用 `写入记录`：它的 `INSERT OR REPLACE` 遇到唯一索引冲突会先
          删掉对方那行再插入自己（SQLite REPLACE 语义，本地实测过），并发下会静默
          删掉先落库那条、自己还报成功——比双双落库更糟。
        """
        指纹 = 契约指纹(契约)
        已有 = self.状态.查询记录("能力条目", "契约指纹=?", (指纹,))
        if 已有 and 已有[0]["能力id"] != 能力id:
            return self._重复实现(已有[0]["能力id"])
        成功, 占用者 = self.状态.写入记录或唯一冲突("能力条目", {
            "能力id": 能力id, "契约指纹": 指纹, "组件": 组件, "领域": 领域,
            "成熟度": 成熟度, "所有者": 所有者, "替代能力": "", "复用裁决": "",
            "裁决状态": "已登记", "提供者": 提供者,
            "资源": json.dumps(资源 or {}, ensure_ascii=False), "版本": "1",
        }, "能力id", "契约指纹")
        if not 成功:
            return self._重复实现(占用者)
        return 真, "能力已登记"

    def 搜索能力(self, 关键词: str = "", 限制: int = 20) -> list[dict[str, Any]]:
        结果表 = []
        for 记录 in self.状态.查询记录("能力条目"):
            if 关键词 and 关键词 not in 记录["能力id"] and 关键词 not in 记录["组件"]:
                continue
            结果表.append({键: 记录[键] for 键 in
                          ("能力id", "组件", "领域", "成熟度", "所有者", "裁决状态")})
            if len(结果表) >= 限制:
                break
        return 结果表

    def 待裁决(self) -> list[dict[str, Any]]:
        return [记录 for 记录 in self.状态.查询记录("能力条目")
                if 记录["裁决状态"] == "待裁决"]

    def 裁决(self, *, 能力id: str, 决定: str, 替代能力: str = "",
             维护者: str = "") -> tuple[bool, str]:
        """维护者裁决：复用/合并/允许并存/拒绝；裁决写入能力目录供后续继承。"""
        if 决定 not in ("复用", "合并", "允许并存", "拒绝"):
            return 假, f"未知裁决: {决定}"
        更新 = {"复用裁决": 决定, "裁决状态": "已裁决"}
        if 替代能力:
            更新["替代能力"] = 替代能力
        self.状态.条件更新("能力条目", 更新, "能力id=?", (能力id,))
        self.状态.追加证据(类型="能力目录", 主题=能力id, 内容={"裁决": 决定, "替代": 替代能力},
                          调用者=维护者, 角色="平台维护者", 结果="裁决")
        return 真, f"裁决完成: {决定}"

    # ---- 能力占用租约 ----
    默认心跳超时秒 = 300.0

    def 申请占用(self, *, 能力id: str, 领域: str, 契约指纹: str, 任务: str,
                所有者: str, 心跳秒: float = 60.0) -> tuple[bool, str, str]:
        """申请能力占用；唯一部分索引（活跃租约同能力唯一）原子保证互斥。

        申请失败不是立刻判「被占用」：先内联 CAS 回收该能力下已过期的活跃租约再重试一次。
        为什么必须自愈：占用者崩溃（Agent 中断）后租约还挂在部分唯一索引上，
        没人回收就永远「活跃」，这个能力此后谁都申请不到——同一能力被永久锁死。
        """
        租约id = uuid.uuid4().hex[:16]
        现在 = time.time()
        记录 = {
            "租约id": 租约id, "能力id": 能力id, "领域": 领域, "契约指纹": 契约指纹,
            "任务": 任务, "所有者": 所有者, "心跳": 现在,
            "过期时间": 现在 + 心跳秒 * 10, "释放证据": "", "状态": "活跃",
        }
        成功 = self.状态.原子插入("占用租约", 记录)
        if not 成功:
            if self.回收能力过期租约(能力id):
                成功 = self.状态.原子插入("占用租约", 记录)
        if not 成功:
            活跃 = [租约 for 租约 in self.状态.查询记录("占用租约", "状态='活跃' AND 能力id=?", (能力id,))]
            占用者 = 活跃[0]["所有者"] if 活跃 else "未知"
            return 假, f"能力已被占用: {占用者}", ""
        return 真, "占用成功", 租约id

    def 回收能力过期租约(self, 能力id: str) -> list[str]:
        """CAS 回收某能力下「已过该租约自己的截止时间」的活跃租约；幂等。

        只按 过期时间 判：申请失败路径上不能顺手回收活着的租约，
        否则会把别人的能力抢走（那比锁死更糟）。
        """
        现在 = time.time()
        候选 = self.状态.查询记录(
            "占用租约", "状态='活跃' AND 能力id=? AND 过期时间 <= ?", (能力id, 现在))
        已回收 = []
        for 租约 in 候选:
            if self.状态.条件更新("占用租约", {"状态": "已过期"},
                                  "租约id=? AND 状态='活跃'", (租约["租约id"],)):
                已回收.append(租约["租约id"])
        return 已回收

    def 续租(self, 租约id: str) -> bool:
        记录 = self.状态.读取记录("占用租约", "租约id", 租约id)
        if 记录 is None or 记录["状态"] != "活跃":
            return 假
        # 续租必须连 过期时间 一起顺延：租期 = 申请时写入的 过期时间 - 心跳。
        # 只推 心跳 不推 截止时间，活着的租约会在原截止点被 回收过期租约 判死，
        # 能力被别的 Agent 接管——这比不回收更危险。
        时刻 = time.time()
        租期 = float(记录.get("过期时间") or 0) - float(记录.get("心跳") or 0)
        if 租期 <= 0:
            租期 = self.默认心跳超时秒 * 2
        return self.状态.条件更新("占用租约", {"心跳": 时刻, "过期时间": 时刻 + 租期},
                                  "租约id=? AND 状态='活跃'", (租约id,))

    def 释放占用(self, 租约id: str, 证据: str = "") -> bool:
        return self.状态.条件更新("占用租约", {"状态": "已释放", "释放证据": 证据},
                                  "租约id=? AND 状态='活跃'", (租约id,))

    def 回收过期占用(self, 心跳超时秒: float = 300.0) -> list[str]:
        """Agent 中断后占用自动过期（心跳停止）；幂等。

        判据两条，任一命中即回收（逐行 CAS，只有状态仍是「活跃」才改）：
        - `过期时间 <= 现在`：租约自带的截止时间，权威判据，续租会顺延；
        - `心跳 <= 现在 - 心跳超时秒`：心跳停摆兜底，覆盖没有有效截止时间的历史行。
        """
        现在 = time.time()
        截止 = 现在 - 心跳超时秒
        过期列表 = []
        for 租约 in self.状态.查询记录(
                "占用租约", "状态='活跃' AND (过期时间 <= ? OR 心跳 <= ?)", (现在, 截止)):
            if self.状态.条件更新("占用租约", {"状态": "已过期"},
                                  "租约id=? AND 状态='活跃'", (租约["租约id"],)):
                过期列表.append(租约["租约id"])
        return 过期列表
