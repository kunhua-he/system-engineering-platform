def _准备(租约id清单: Any, 持有秒: Any) -> tuple[list[str], float, Any, Any]:
    """续租参数归一：返回 (ids, 秒, 失败结果, 存储)。"""
    ids, 问题 = 文本清单(租约id清单, "租约id清单")
    if 问题:
        return [], 0.0, 失败结果("参数不合法", 问题), None
    if not ids:
        return [], 0.0, 失败结果("参数不合法", "租约id清单 不能为空"), None
    秒, 秒问题 = 正秒(持有秒, 默认持有秒, 最长持有秒)
    if 秒问题:
        return [], 0.0, 失败结果("参数不合法", f"持有秒 {秒问题}"), None
    return ids, 秒, None, None


def 续租文件租约(租约id清单: Any = None, 持有秒: Any = None, 存储目录: Any = "") -> Any:
    """按租约id**续租**（幂等）：活跃租约心跳与过期时间前推；不能续租的如实进失败清单。"""
    ids, 秒, 归一失败, _ = _准备(租约id清单, 持有秒)
    if 归一失败 is not None:
        return 归一失败
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    时刻 = time.time()
    with 存储.独占():
        快照, 读问题 = 存储.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        快照 = dict(快照)
        续租清单, 失败清单 = [], []
        for 租约id in ids:
            键 = 存储.按租约id找键(快照, 租约id)
            记录 = 快照.get(键) if 键 else None
            if not 键 or not 是活跃(记录):
                失败清单.append({"租约id": 租约id,
                              "说明": "租约不存在或已非活跃，不能复活（过期租约只能重新申请）"})
                continue
            记录 = dict(记录)
            记录["心跳"] = 时刻
            记录["过期时间"] = 时刻 + 秒
            快照[键] = 记录
            续租清单.append(记录)
        if not 续租清单:
            return 失败结果("租约不存在",
                          f"全部 {len(失败清单)} 条租约未能续租：{失败清单[0]['说明']}")
        写问题 = 存储.写入(快照)
    if 写问题:
        return 失败结果("存储目录不可用", 写问题)
    return 成功结果({
        "续租清单": [存储.对外记录(记录) for 记录 in 续租清单],
        "失败清单": 失败清单, "续租数": len(续租清单),
        "说明": "续租幂等：同一租约重复续租只前推心跳与过期时间，不新建租约",
    })


def 释放文件租约(租约id清单: Any = None, 原因: Any = "", 项目根: Any = "",
                存储目录: Any = "") -> Any:
    """按租约id**释放**（幂等）：释放后同一路径必须能立即再次申请成功。

    `项目根` 是解锁事件里**现场重算内容指纹**的路径解析基准（走全平台唯一那条
    `平台适配.解析路径` 腿；留空落 环境变量 `系统平台_项目根` → 进程 cwd）。

    ★ 2026-09-23 签名名序对齐真契约：本函数形参名序此前为
    `(租约id清单, 原因, 存储目录, 项目根)`，与真契约
    `能力契约/参数契约.json` 的 `[租约id清单, 原因, 项目根, 存储目录]` **相反**。
    运行期一律关键字调用故无功能影响，但按位置调用会把 `项目根` 与 `存储目录` 对调。
    参数事实源只有契约一处（哲学 12.1），实现签名名序必须与契约逐字逐序一致。
    """
    ids, 问题 = 文本清单(租约id清单, "租约id清单")
    if 问题:
        return 失败结果("参数不合法", 问题)
    if not ids:
        return 失败结果("参数不合法", "租约id清单 不能为空")
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    时刻 = time.time()
    with 存储.独占():
        快照, 读问题 = 存储.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        快照 = dict(快照)
        释放清单, 幂等清单 = [], []
        过期未清 = 0
        for 租约id in ids:
            键 = 存储.按租约id找键(快照, 租约id)
            记录 = 快照.get(键) if 键 else None
            if 记录 is None:
                幂等清单.append({"租约id": 租约id, "结果": "未找到且已幂等"})
                continue
            if not 是活跃(记录):
                # 非活跃有两种：真已释放（盘上状态就是已释放）与**过期但盘上状态仍写着「活跃」**。
                # 后者照原样回带，调用方看到的就是「已结束且已释放 + 状态：活跃」的自相矛盾（#196 ⑦）。
                # 故与查询侧 `_改判过期` 用同一判据如实回带，并单独计数（只动读数，不改盘上数据）。
                改判 = _改判过期(记录, 时刻)
                已过期 = 改判.get("状态") == 状态_已过期
                if 已过期:
                    过期未清 += 1
                幂等清单.append({"租约id": 租约id,
                              "结果": "已过期且已释放" if 已过期 else "已结束且已释放",
                              "状态": str(改判.get("状态") or "")})
                continue
            记录 = dict(记录)
            记录["状态"] = "已释放"
            记录["释放时间"] = 时间文本(时刻)
            记录["释放原因"] = 文本(原因) or "调用方显式释放"
            快照[键] = 记录
            释放清单.append(记录)
        写问题 = 存储.写入(快照)
    if 写问题:
        return 失败结果("存储目录不可用", 写问题)
    # ★ 解锁 = 「改完了」的那一刻：事件里的内容指纹必须**现场重算**，
    # 不能沿用租约创建时的快照（否则后手用新指纹拉流水会找不到终点，
    # 起点也会错位到解锁那一条 —— 实测踩过）。
    解锁记录 = []
    for 记录 in 释放清单:
        条目 = 存储.对外记录(记录)
        解锁指纹, 指纹问题 = 现场指纹(str(记录.get("路径") or ""), 项目根)
        条目["内容指纹"] = 解锁指纹 or (条目.get("内容指纹") or "")
        条目["已声明指纹"] = ""   # 解锁是事实不是声明；留着会让指纹锚点错位
        条目["现场指纹不可用"] = 指纹问题 or ""
        解锁记录.append(条目)
    流水问题 = 写流水(存储目录, 事件_解锁,
                    解锁记录,
                    [str(记录.get("路径") or "") for 记录 in 释放清单],
                    str((释放清单[0].get("所有者") if 释放清单 else "") or ""),
                    str((释放清单[0].get("任务") if 释放清单 else "") or ""),
                    时刻, 详情=文本(原因) or "调用方显式释放")
    return 成功结果({
        "释放清单": [存储.对外记录(记录) for 记录 in 释放清单],
        "幂等清单": 幂等清单, "释放数": len(释放清单),
        "过期未清数": 过期未清,
        "流水问题": 流水问题,
        "说明": "释放后同一路径可立即再次申请；重复释放/回收已结束租约一律回「已结束且已释放」",
    })


def _是数(值: Any) -> bool:
    """是否为可用作时间戳的实数（bool 是 int 子类，必须排除）。"""
    return isinstance(值, (int, float)) and not isinstance(值, bool)


def 回收过期文件租约(心跳超时秒: Any = None, 存储目录: Any = "") -> Any:
    """**回收过期**租约（幂等）：`过期时间` 已到 **或** 心跳停摆超过阈值即置为已过期。

    两个判据都必须看：只看心跳时，一条「心跳很新但 `过期时间` 早已到点」的租约会被永久
    当成活跃占用（申请时给了短持有秒、之后一直不续租的情形），占用既不释放也不回收。
    「到期」与「心跳停摆」是两件事，判据取并集，且回带是哪一条触发的。
    """
    阈值, 问题 = 正秒(心跳超时秒, 默认持有秒, 最长持有秒)
    if 问题:
        return 失败结果("参数不合法", f"心跳超时秒 {问题}")
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    时刻 = time.time()
    截止 = 时刻 - 阈值
    with 存储.独占():
        快照, 读问题 = 存储.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        快照 = dict(快照)
        回收清单 = []
        for 键 in sorted(快照):
            记录 = 快照[键]
            if not 是活跃(记录):
                continue
            心跳 = 记录.get("心跳")
            过期 = 记录.get("过期时间")
            停摆 = _是数(心跳) and float(心跳) <= 截止  # type: ignore[arg-type]
            到点 = _是数(过期) and float(过期) <= 时刻  # type: ignore[arg-type]
            if not (停摆 or 到点):
                continue
            原因 = []
            if 到点:
                原因.append(f"过期时间 {时间文本(过期)} 已到")
            if 停摆:
                原因.append(f"心跳停摆超过 {阈值} 秒未续租")
            记录 = dict(记录)
            记录["状态"] = "已过期"
            记录["释放时间"] = 时间文本(时刻)
            记录["释放原因"] = "自动回收：" + "；".join(原因)
            快照[键] = 记录
            回收清单.append(记录)
        写问题 = 存储.写入(快照)
    if 写问题:
        return 失败结果("存储目录不可用", 写问题)
    流水问题 = 写流水(存储目录, 事件_过期回收,
                    [存储.对外记录(记录) for 记录 in 回收清单],
                    [str(记录.get("路径") or "") for 记录 in 回收清单],
                    "", "", 时刻, 详情=f"心跳超时秒={阈值}；自动回收")
    return 成功结果({
        "回收清单": [存储.对外记录(记录) for 记录 in 回收清单],
        "流水问题": 流水问题,
        "回收租约id清单": [str(记录.get("租约id") or "") for 记录 in 回收清单],
        "回收数": len(回收清单), "心跳超时秒": 阈值,
    })


def _查询记录(存储, 修改路径: Any) -> tuple[list[dict], Any]:
    """按路径清单取记录（留空取全部）；越界即整体失败。返回 (记录表, 失败结果)。"""
    原始清单, 问题 = 文本清单(修改路径, "修改路径")
    if 问题:
        return [], 失败结果("参数不合法", 问题)
    键集 = set()
    for 原始 in 原始清单:
        归一, 边界问题 = 校验相对路径(原始)
        if 边界问题:
            return [], 失败结果("路径越界", f"修改路径越出项目根边界：{原始!r} → {边界问题}")
        键集.add(文件键(归一))
    快照, 读问题 = 存储.读取()
    if 读问题:
        return [], 失败结果("存储目录不可用", 读问题)
    记录表 = [快照[键] for 键 in sorted(快照)]
    if 键集:
        记录表 = [记录 for 记录 in 记录表 if 记录.get("键") in 键集]
    # 查得到的事实 ≠ 还活着的事实：过期租约的 `状态` 字段仍是「活跃」（写入时定的），
    # 若照原样返回，调用方按 `状态` 判定就会把僵尸租约当成占用者 —— 实测 2026-09-20
    # 一条 21:13:59 到期的租约在 21:35 仍被判活跃，把同一路径的新开工整体挡死。
    # 这里只补一个**读数**（不改盘上数据，本函数是只读查询）：过期即改判 `状态_已过期`。
    记录表 = [_改判过期(记录, time.time()) for 记录 in 记录表]
    return 记录表, None


def _改判过期(记录: dict, 现在: float) -> dict:
    """只读查询用的过期改判：状态仍是活跃但已过期 → 返回状态改判为「已过期」的副本。

    只动 `状态` 一个读数，不改盘上数据（查询是只读能力，不产生写副作用）；
    真正的落盘改判由 `过期回收` 负责（那是写能力，有它自己的调用时机）。
    """
    if not isinstance(记录, dict) or 记录.get("状态") != 活跃状态:
        return 记录
    try:
        截止 = float(记录.get("过期时间"))  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return 记录
    if 现在 < 截止:
        return 记录
    副本 = dict(记录)
    副本["状态"] = 状态_已过期
    return 副本


def _摘要记录(对外: dict) -> dict:
    """摘要形态：只留定位与判定必需字段，去掉留言全文与指纹（控返回体量）。

    为什么有它：全量查询实测 412 条 / 250697 字符，直接打爆调用方上下文（#196 ⑥）。
    保留的字段够调用方做「谁占着、还能不能动、什么时候到期」三件判断；
    要看留言时间线或做指纹核对，再对单条传 摘要=假。
    """
    保留键 = ("租约id", "路径", "所有者", "开工id", "任务", "状态",
              "过期时间", "心跳", "释放时间", "释放原因")
    摘要 = {键: 值 for 键, 值 in 对外.items() if 键 in 保留键}
    留言 = 对外.get("留言")
    摘要["留言数"] = len(留言) if isinstance(留言, list) else 0
    return 摘要


def 查询文件租约(修改路径: Any = None, 存储目录: Any = "", 只要活跃: Any = 假,
                摘要: Any = 假, 含现场指纹: Any = 假, 项目根: Any = "") -> Any:
    """查询项目根相对路径上的租约事实（只读）；留空表示取全部记录。

    ★ 2026-09-23 签名名序对齐真契约：本函数形参名序此前为
    `(…, 含现场指纹, 只要活跃, 摘要, …)`，与真契约 `能力契约/参数契约.json` 的
    `[…, 只要活跃, 摘要, 含现场指纹, 项目根]` 不一致。运行期一律关键字调用故无功能
    影响；参数事实源只有契约一处（哲学 12.1），实现签名名序必须与契约逐字逐序一致。

    **含现场指纹=真 时**：每条记录补一组**此刻现场算得**的读数（`现场指纹` /
    `现场指纹一致` / `内容是否变更` / `指纹核验`）——这是华哥 2026-09-18 口述的那个动作：
    「B 会话发现指纹没对上，就查一下之前登记的和现在的差分」。四个读数的含义：

    - `现场指纹`：**现在**这个文件的内容指纹（认领时的旧指纹在 `内容指纹` 键里）；
    - `现场指纹一致`：认领那一刻的指纹与现在是否还一致（假 = 认领后被改过）；
    - `内容是否变更`：`已声明指纹`（调用方认知）与**现场**是否一致 —— 这才是
      「该不该按旧认知动手」的判据，与上一条不同：上一条比的是「认领时的现场」，
      这一条比的是「调用方拿着的认知」；
    - `指纹核验`：`已核验` / `未核验` —— **现场指纹读不出来时 `内容是否变更` 一律为
      假并在此标 `未核验`**，不再把「读不到」冒充成「已变更」（债务清单 134 ②：
      两个指纹都是「不存在」却判「已变更」，这条纪律就恒报红、失去分辨力）。

    **解析基准（`项目根`）**：现场指纹读的是**仓库内真实文件**，相对路径必须按
    项目根解析。此前一律用 `租约边界.项目根()`（= `Path(__file__).parents[3]`），
    网关跑**激活制品**时那是制品根（制品里没有 `开发文档/`）⇒ 现场指纹恒「不存在」、
    `内容是否变更` 恒真（债务清单 134 的病根）。现在改走
    `公共契约.运行时.平台适配.解析路径`（全平台唯一那条相对路径解析腿）：
    生效根 = 本参数 `项目根`（网关/薄壳每次调用都会补位顶层项目根，路径族字段故被
    归一成绝对）→ 环境变量 `系统平台_项目根` → 进程 cwd。**本模块不自带 is_absolute() 分支。**

    现场读不到（文件被删/目录/不可读）时如实给 `现场指纹` 的字面量，不算失败。

    **只要活跃=真 时**：只回 `状态` 仍活跃的记录（查询侧已把过期租约改判为
    `已过期`，故该判据可信）。**摘要=真 时**：每条只留定位与判定必需字段
    （去掉留言全文与指纹，改回 `留言数`）。两条都是为「全量取数打爆调用方上下文」
    而加：实测全量 412 条 / 250697 字符（#196 ⑥）。
    """
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    记录表, 失败 = _查询记录(存储, 修改路径)
    if 失败 is not None:
        return 失败
    活跃数 = sum(1 for 记录 in 记录表 if 是活跃(记录))
    if 只要活跃 is 真:
        记录表 = [记录 for 记录 in 记录表 if 是活跃(记录)]
    对外表 = [存储.对外记录(记录) for 记录 in 记录表]
    if 摘要 is 真:
        对外表 = [_摘要记录(对外) for 对外 in 对外表]
    未核验数 = 0
    指纹基准 = ""
    if 含现场指纹 is 真:
        for 对外 in 对外表:
            现场, _问题, 基准根 = 现场指纹与基准(str(对外.get("路径") or ""), 项目根)
            指纹基准 = str(基准根)
            已核验 = 指纹已核验(现场)
            对外["现场指纹"] = 现场
            对外["现场指纹一致"] = 指纹是否一致(对外.get("内容指纹"), 现场)
            对外["指纹核验"] = "已核验" if 已核验 else "未核验"
            对外["内容是否变更"] = (
                (not 指纹是否一致(对外.get("已声明指纹"), 现场)) if 已核验 else 假
            )
            if not 已核验:
                未核验数 += 1
    返回值: dict[str, Any] = {
        "记录表": 对外表, "数量": len(对外表), "活跃数": 活跃数,
        "说明": "只要活跃=真 只回活跃记录；摘要=真 只回定位与判定字段（去留言全文与指纹）",
    }
    if 含现场指纹 is 真:
        # ★ 2026-09-23（未完成事项 #134 ③）：与 `申请文件租约` 同一口径 —— 回带实际使用的
        #   解析基准根与未核验条数，让「指纹读的是哪棵树 / 有几条根本没核验」机器可判，
        #   而不是把「读不到」冒充成「不存在」或「已变更」。
        返回值["未核验数"] = 未核验数
        返回值["指纹基准"] = 指纹基准
    return 成功结果(返回值)


def 文件租约留言(租约id: Any = "", 作者: Any = "", 留言: Any = "",
                 存储目录: Any = "", 项目根: Any = "") -> Any:
    """在租约句柄里**留一条备注**（只增不改，构成审计链）。

    `项目根` 是留言事件里**现场重算内容指纹**的路径解析基准（走全平台唯一那条
    `平台适配.解析路径` 腿；留空落 环境变量 `系统平台_项目根` → 进程 cwd）。

    华哥 2026-09-18 口述的「改完之后解锁，并且在开工 ID 句柄里面留一个留言，
    说我改了什么」——这就是那条留言。三条硬口径：

    - **只增不改**：不允许编辑/删除既有留言（审计链一旦可改就不可信）；
    - **留言前必须持有活跃租约**：非活跃（已释放/已过期/不存在）一律拒绝，
      不然留言会挂到一条已经结束的句柄上，时间线错位；
    - **上限**：单条留言 `留言上限字` 字、单租约 `留言条数上限` 条，超限如实拒绝
      （留言是审计链，不是数据通道）。
    """
    id文本 = 文本(租约id)
    if not id文本:
        return 失败结果("参数不合法", "租约id 不能为空")
    写作者 = 文本(作者)
    if not 写作者:
        return 失败结果("参数不合法", "作者 不能为空（留言必须可追溯到人/会话）")
    正文 = str(留言 if 留言 is not None else "").strip()
    if not 正文:
        return 失败结果("参数不合法", "留言 不能为空")
    if len(正文) > 留言上限字:
        return 失败结果("参数不合法",
                      f"留言 超过 {留言上限字} 字上限（收到 {len(正文)} 字；留言是审计链，不是数据通道）")
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    时刻 = time.time()
    写问题 = ""
    记录: dict = {}
    with 存储.独占():
        快照, 读问题 = 存储.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        快照 = dict(快照)
        键 = 存储.按租约id找键(快照, id文本)
        命中 = 快照.get(键) if 键 else None
        if 命中 is None:
            return 失败结果("租约不存在", f"租约id={id文本} 未找到，留言必须挂在真实租约上")
        if not 是活跃(命中):
            return 失败结果("租约不存在", (
                f"租约id={id文本} 已非活跃（状态={命中.get('状态')}），"
                f"留言只允许挂在活跃租约上（留言是「我改了什么」的在场记录）"))
        记录 = dict(命中)
        现有 = list(记录.get("留言") or [])
        if len(现有) >= 留言条数上限:
            return 失败结果("参数不合法",
                          f"该租约留言已达 {留言条数上限} 条上限")
        现有.append(留言条目(写作者, 正文, 时刻))
        记录["留言"] = 现有
        快照[键] = 记录
        写问题 = 存储.写入(快照)
    if 写问题:
        return 失败结果("存储目录不可用", 写问题)
    # ★ 留言也是「动作发生那一刻」：事件里的内容指纹要现场重算，
    # 并把 已声明指纹 清空（声明值是调用方期望，不是事实，留着会让指纹锚点错位）。
    留言流水条目 = 存储.对外记录(记录)
    留言现场指纹, _留言指纹问题 = 现场指纹(str(记录.get("路径") or ""), 项目根)
    留言流水条目["内容指纹"] = 留言现场指纹 or (留言流水条目.get("内容指纹") or "")
    留言流水条目["已声明指纹"] = ""
    流水问题 = 写流水(存储目录, 事件_留言, [留言流水条目],
                    [str(记录.get("路径") or "")],
                    写作者, str(记录.get("任务") or ""), 时刻, 详情=正文)
    return 成功结果({
        "租约id": id文本, "作者": 写作者, "留言": 正文,
        "流水问题": 流水问题,
        "留言数": len(记录["留言"]), "时间": 时间文本(时刻),
        "租约记录": 存储.对外记录(记录),
        "说明": "留言只增不改；查询文件租约 可读取该句柄的完整留言时间线",
    })
