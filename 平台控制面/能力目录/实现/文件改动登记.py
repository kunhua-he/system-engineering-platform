"""文件改动登记与历史查询：乐观登记 + 两个指纹拉中途流水（唯一实现）。

华哥 2026-09-18 口述的两条语义，住这个文件：

1. **登记 = 乐观，不冻结**：「申请开工 ID 时把他可能要改的文件全写上（顺手 + 个 MD5），
   等于上了个乐观锁」——10 个会话可以同时登记同一个文件，各自的事实是
   「我也想改，我当时看到的是 md5=X」。登记**不上锁、不互斥、不阻塞任何人**；
   真正的互斥点只有「改」（见 `文件租约申请.申请文件租约` 的 `校验指纹`）。

2. **两个指纹 → 中途流水**：「后手只需要输入他登记时的 md5 以及现在文件的 md5，
   请求一下，后端直接算这个 md5 的时间 − 最新 md5 的时间，中途的所有日志」——
   `查询改动历史` 拿声明指纹与现场指纹，去流水里找这两条各属哪个时刻（**指纹就是时间锚点**），
   返回区间内的**全部事件**；两个锚点都找不到时如实报「无从定位」，不编造区间。

为什么不另建一套「乐观锁」：登记只是**写一条意图事实**，能力面完全走既有的
`文件租约存储`（状态）+ `文件改动日志存储`（事件）两存储，不新造锁（哲学 1.2）。
"""
