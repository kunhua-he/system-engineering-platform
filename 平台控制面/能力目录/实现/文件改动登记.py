def 取日志(存储目录: str):
    """按存储目录取改动日志存储（同目录同实例；缺省与租约同一目录口径）。

    为什么与租约**同目录**：登记、上锁、解锁、留言是同一件事的四个动作，流水要能被
    「按同一次开工」整段拉出来；两个存储分目录会让「同一个工作区的流水」分裂成两处。
    """
    from pathlib import Path

    from 平台控制面.能力目录.实现.租约边界 import 默认存储目录

    目录 = 文本(存储目录) or 默认存储目录
    if not 目录:
        return None
    return 文件改动日志存储.取实例(Path(目录))


def 登记改动意图(修改路径: Any = None, 所有者: Any = "", 任务: Any = "",
                 备注: Any = "", 存储目录: Any = "") -> Any:
    """**乐观登记**拟改文件（不互斥、不冻结）：同路径可被多人同时登记。

    返回 `{登记清单, 登记数, 撞车清单, 说明}`：

    - `登记清单`：本次登记的事实（路径 / 声明指纹 / 现场指纹 / 指纹一致）；
    - `撞车清单`：**这些路径上已有别的会话的在改租约**（活跃占用）——即华哥口述的
      「B 会话申请时返回有几个绝对路径的文件撞车了」。撞车**不阻止登记**（登记是乐观的），
      只如实告知：谁在改、什么时候开始的、留言多少条；
    - 每条登记都追加一条 `登记` 事件进流水（供后续用两个指纹拉中途日志）。

    与 `申请文件租约` 的分工：**登记是「我也要改」的意向，上锁是「我正在改」的事实**。
    """
    持有人 = 文本(所有者)
    if not 持有人:
        return 失败结果("参数不合法", "所有者 不能为空（登记必须可追溯到人/会话）")
    承载任务 = 文本(任务)
    if not 承载任务:
        return 失败结果("参数不合法", "任务 不能为空（登记必须能追到哪次开工）")
    路径表, 问题 = 路径与指纹清单(修改路径, "修改路径")
    if 问题:
        return 失败结果("参数不合法", 问题)
    if not 路径表:
        return 失败结果("参数不合法", "修改路径 不能为空（登记必须给出文件）")
    归一表: list[tuple[str, str]] = []
    越界: list[dict] = []
    for 原始, 声明 in 路径表:
        归一, 边界问题 = 校验相对路径(原始)
        if 边界问题:
            越界.append({"输入": 原始, "归一化": 归一, "说明": 边界问题})
            continue
        归一表.append((归一, 声明))
    if 越界:
        首条 = 越界[0]
        return 失败结果("路径越界", (
            f"修改路径越出项目根边界：{首条['输入']!r} → {首条['说明']}；"
            f"一律按项目根相对路径给，绝对路径 / `..` / `~` 写法一致拒绝。"
            f"越界 {len(越界)}/{len(路径表)} 条。"))
    路径名表 = [p for p, _ in 归一表]
    if len(set(路径名表)) != len(路径名表):
        return 失败结果("参数不合法", "修改路径 存在重复路径（同一次登记里同一文件只允许一条）")
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    日志 = 取日志(存储目录)
    if 日志 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    根 = 项目根()
    现场表: list[str] = []
    for 相对路径, _声明 in 归一表:
        现场, 指纹问题 = 计算内容指纹(根, 相对路径)
        if 指纹问题:
            return 失败结果("内容指纹不可用", 指纹问题)
        现场表.append(现场)
    时刻 = time.time()
    备注文本 = 文本(备注)
    登记清单: list[dict] = []
    撞车清单: list[dict] = []
    写问题 = ""
    with 存储.独占():
        快照, 读问题 = 存储.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        for 序号, (路径, 声明) in enumerate(归一表):
            记录 = (快照 or {}).get(文件键(路径)) or {}
            if 是活跃(记录):
                撞车清单.append({
                    "路径": 路径, "占用者": str(记录.get("所有者") or ""),
                    "任务": str(记录.get("任务") or ""),
                    "占用开始时间": str(记录.get("申请时间") or ""),
                    "过期时间读数": 时间文本(记录.get("过期时间")),
                    "留言数": len(list(记录.get("留言") or [])),
                })
            登记清单.append({
                "路径": 路径, "所有者": 持有人, "任务": 承载任务,
                "声明指纹": 声明, "现场指纹": 现场表[序号],
                "指纹一致": 指纹是否一致(声明, 现场表[序号]),
                "备注": 备注文本, "登记时间": 时间文本(时刻),
            })
    with 日志.独占():
        流水, 读问题 = 日志.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        流水 = dict(流水 or {})
        for 条目 in 登记清单:
            事件 = 文件改动日志存储.新事件(
                事件_登记, str(条目["路径"]), 持有人, 承载任务,
                内容指纹=str(条目["现场指纹"]),
                已声明指纹=str(条目["声明指纹"]),
                详情=备注文本, 现在=时刻)
            文件改动日志存储.追加(流水, 事件)
        写问题 = 日志.写入(流水)
    if 写问题:
        return 失败结果("存储目录不可用", 写问题)
    return 成功结果({
        "登记清单": 登记清单, "登记数": len(登记清单),
        "撞车清单": 撞车清单,
        "说明": ("登记是乐观的：不冻结、不互斥，同路径可被多人同时登记；"
                "撞车清单只是如实告知谁正在改。要动手改之前，用 申请文件租约"
                "（修改路径 每条带 {\"路径\", \"指纹\"} + 校验指纹=真）上锁，"
                "改完 释放文件租约 解锁并在 文件租约留言 记下改了什么。"),
    })


def _定位锚点(事件表: list[dict], 指纹: str) -> dict | None:
    """在事件表里找**该指纹最早出现**的那条 = 「这份内容是什么时候被看到的」的时刻锚点。

    两处口径都是实测踩出来的：
    - ★ 只认 `内容指纹`（**事件发生那一刻现场算出来的事实**），绝不认 `已声明指纹`
      （那是调用方当时的期望值，会一路带着旧值漂到后面的事件里）。认了它会让旧指纹
      锚点错位到「解锁」那条，区间被压成一条，后手反而看不到中途流水。
    - ★ 取**最早**而不是最晚：同一份内容在被改之前会被多次观测到（登记→上锁→留言
      都记着同一指纹）。若取最晚，区间起点会滑到「留言」，把最关键的「上锁」甩出区间。
      取最早 = 「这份内容最早是哪一刻被看到的」，区间才覆盖完整改动窗（旧内容→新内容）。
    """
    目标 = str(指纹 or "").strip()
    if not 目标:
        return None
    命中 = [e for e in 事件表 if 目标 == str(e.get("内容指纹") or "").strip()]
    return 命中[0] if 命中 else None


def _现场核对现在指纹(项目根目录, 相对路径: str, 现在指纹: Any) -> dict:
    """现场算一次当前指纹，与调用方给的「现在指纹」比对（只读，不改状态）。

    为什么必须现场核：华哥的原话是「**现在文件的 md5**」——那是调用方在自己那边算的，
    不可能出现在流水里。光靠流水找它会永远「找不到终点」。现场核一次后：
    - 一致 → 区间终点 = 此刻（流水里最后一条事件之后），语义正确；
    - 不一致 → 说明调用方手里的指纹是过期的（文件在它算完之后又变了），
      如实报出来，比默默给个错区间强。
    """
    目标 = str(现在指纹 or "").strip()
    if not 目标:
        return {"一致": False, "现场指纹": "", "说明": "未提供 现在指纹"}
    现场, 问题 = 计算内容指纹(项目根目录, 相对路径)
    if 问题:
        return {"一致": False, "现场指纹": "", "说明": f"现场指纹算不出来：{问题}"}
    if 现场 == 目标:
        return {"一致": True, "现场指纹": 现场, "说明": "现在指纹与现场一致"}
    return {"一致": False, "现场指纹": 现场,
            "说明": f"现在指纹 {目标} 与现场 {现场} 不一致（你拿到指纹之后文件又变过）"}


def 查询改动历史(修改路径: Any = None, 声明指纹: Any = "", 现在指纹: Any = "",
                 存储目录: Any = "", 最多条数: Any = None) -> Any:
    """用**两个指纹**拉出中途全部流水（华哥口述的「后手」用法）。

    `声明指纹` = 你登记时看到的那个指纹；`现在指纹` = 此刻文件的指纹。
    本能力在流水里分别定位这两条各属哪个时刻（**指纹即时间锚点**），返回区间内的
    全部事件（按时间升序），并给出区间总结：谁在什么时候干了什么。

    三种定位结果必须可区分（14.4：状态要能被机器判）：
    - 两个锚点都找到 → 返回区间事件 + `区间起点/终点` + `中间事件数`；
    - 只找到「声明指纹」→ 说明**该指纹之后再没出现过**（没人改过或改动未留指纹），
      返回从它到最新的全部事件并如实标注「现在指纹未在流水中出现」；
    - 都找不到 → 如实报「无从定位」（不返回一份空清单冒充「没改过」）。

    参数 `最多条数` 缺省取 `单路径上限`（与存储上限同口径，不给调用方留假上限）。
    """
    路径表, 问题 = 文本清单(修改路径, "修改路径")
    if 问题:
        return 失败结果("参数不合法", 问题)
    归一表: list[str] = []
    for 原始 in 路径表:
        归一, 边界问题 = 校验相对路径(原始)
        if 边界问题:
            return 失败结果("路径越界", f"修改路径越出项目根边界：{原始!r} → {边界问题}")
        归一表.append(归一)
    上限, 秒问题 = 正秒(最多条数, float(单路径上限), float(单路径上限))
    if 秒问题:
        return 失败结果("参数不合法", f"最多条数 {秒问题}")
    条数上限 = int(上限)
    日志 = 取日志(存储目录)
    if 日志 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    流水, 读问题 = 日志.读取()
    if 读问题:
        return 失败结果("存储目录不可用", 读问题)
    流水 = dict(流水 or {})
    目标路径表 = 归一表 or sorted(流水)
    结果表: list[dict] = []
    for 路径 in 目标路径表:
        事件表 = [dict(e) for e in (流水.get(路径) or []) if isinstance(e, dict)]
        事件表.sort(key=lambda e: float(e.get("时刻") or 0))
        起点 = _定位锚点(事件表, 声明指纹)
        终点 = _定位锚点(事件表, 现在指纹)
        # 「现在指纹」按华哥的原话是**此刻文件的指纹**，它天然多半不在流水里
        # （流水只在登记/上锁/解锁时留指纹）。因此终点补一条：现场算一次当前指纹，
        # 与调用方给的「现在指纹」比对——对得上就把区间终点定在「此刻」（最后一条事件之后）。
        现场核对 = _现场核对现在指纹(项目根(), 路径, 现在指纹)
        现场终锚 = bool(现场核对.get("一致")) and not 终点
        终点时刻 = (float(终点.get("时刻") or 0) if 终点
                    else (time.time() if 现场终锚 else 0.0))
        能定位 = bool(起点) and bool(终点 or 现场终锚)
        区间: list[dict]
        定位说明: str
        if 起点 and (终点 or 现场终锚):
            起始时刻 = float(起点.get("时刻") or 0)
            区间 = [e for e in 事件表
                   if 起始时刻 <= float(e.get("时刻") or 0) <= 终点时刻]
            终点描述 = (f"现在指纹属 {终点.get('时间')}（{终点.get('类型')} by {终点.get('所有者')}）"
                      if 终点 else f"现在指纹经现场核对一致（现场 {现场核对.get('现场指纹')}）")
            定位说明 = (f"已定位：声明指纹属 {起点.get('时间')}（{起点.get('类型')} by "
                      f"{起点.get('所有者')}），{终点描述}")
        elif 起点:
            起始时刻 = float(起点.get("时刻") or 0)
            区间 = [e for e in 事件表 if float(e.get("时刻") or 0) >= 起始时刻]
            定位说明 = (f"只定位到声明指纹（{起点.get('时间')}，{起点.get('类型')} by "
                      f"{起点.get('所有者')}）；现在指纹未在流水中出现"
                      f"且与现场不一致（{现场核对.get('说明')}）——区间取到最新事件")
        elif 终点 or 现场终锚:
            区间 = 事件表
            定位说明 = ("声明指纹未在流水中出现（可能：还没人登记过 / 该指纹不是本平台算的）；"
                      f"区间取全部 {len(事件表)} 条事件")
        else:
            区间 = []
            定位说明 = ("两个指纹都没在流水中出现，且现在指纹与现场不一致"
                      f"（{现场核对.get('说明')}）—— 无从定位区间："
                      "该路径可能还没人登记过，或你给的指纹不是本平台算出来的")
        结果表.append({
            "路径": 路径, "事件总数": len(事件表),
            "区间事件": 区间[-条数上限:] if 条数上限 else 区间,
            "区间事件数": len(区间),
            "定位说明": 定位说明,
            "能否定位": 能定位,
            "区间起点": (起点.get("时间") if 起点 else ""),
            "区间终点": (终点.get("时间") if 终点 else
                       (时间文本(终点时刻) if 现场终锚 else "")),
            "现在指纹与现场一致": bool(现场核对.get("一致")),
            "现场指纹": 现场核对.get("现场指纹") or "",
        })
    return 成功结果({
        "结果表": 结果表, "路径数": len(结果表),
        "说明": ("两个指纹即时间锚点：返回的是它们之间的**全部流水**"
                "（登记 / 上锁 / 解锁 / 留言 / 过期回收），按时间升序。"
                "本能力只读，不改任何状态、不占用。"),
    })
