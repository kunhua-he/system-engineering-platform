"""申请文件租约：按项目根相对路径批量原子认领（唯一实现）。

认领语义（第 10 条 2 项：补成原子能力，不补成特例）：
- 先对**全部**路径做项目根边界校验，任一条越界即整体 `路径越界` 硬失败（不留半批）；
- 再在存储独占区内**重读**最新事实并判定活跃占用，任一条被占用即整体 `文件已被占用`，
  并回带**占用者 / 占用开始时间 / 租约id**；被占用的文件**不许静默跳过**；
- 全部通过才一次性原子落盘（临时文件 + `os.replace`）。
"""
from __future__ import annotations

import time
from typing import Any

from 平台控制面.能力目录.实现.租约边界 import (
    失败结果,
    成功结果,
    取存储,
    文本,
    文本清单,
    正秒,
    项目根,
    路径与指纹清单,
)
from 平台控制面.能力目录.租约路径 import 校验相对路径
from 平台控制面.能力目录.文件租约存储 import (
    文件租约存储,
    默认持有秒,
    最长持有秒,
    是活跃,
    文件键,
    计算内容指纹,
    指纹是否一致,
)
from 公共契约.基础类型.逻辑类型 import 真, 假

__all__ = ["申请文件租约", "存储冲突条目"]


def _校验路径清单(修改路径: Any) -> tuple[list[tuple[str, str]], Any]:
    """批量路径边界校验：返回 (通过清单[(路径, 声明指纹)], 失败结果)；失败非 None 即整体拒绝。"""
    原始清单, 问题 = 路径与指纹清单(修改路径, "修改路径")
    if 问题:
        return [], 失败结果("参数不合法", 问题)
    if not 原始清单:
        return [], 失败结果("参数不合法", "修改路径 不能为空（批量原子认领必须给出路径）")
    通过清单, 越界清单 = [], []
    for 原始, 声明指纹 in 原始清单:
        归一, 边界问题 = 校验相对路径(原始)
        if 边界问题:
            越界清单.append({"输入": 原始, "归一化": 归一, "说明": 边界问题})
            continue
        通过清单.append((归一, 声明指纹))
    if 越界清单:
        首条 = 越界清单[0]
        return [], 失败结果("路径越界", (
            f"修改路径越出项目根边界：{首条['输入']!r} → {首条['说明']}；"
            f"路径一律按项目根相对路径给，绝对路径 / `..` / `~` 写法一致拒绝"
            f"（旧 文件租约 只归一化、不做边界校验，本能力改判硬失败）。"
            f"越界 {len(越界清单)}/{len(原始清单)} 条。"))
    路径表 = [条目[0] for 条目 in 通过清单]
    if len(set(路径表)) != len(路径表):
        return [], 失败结果("参数不合法", "修改路径 存在重复路径（同一次认领里同一文件只允许一条）")
    return 通过清单, None


def 存储冲突条目(路径: str, 存储快照: dict) -> dict:
    """被占用路径的冲突读数：占用者与占用开始时间必须在场（不许只说「失败」）。

    对外字段一律经 `文件租约存储.对外记录` 生成（心跳时间 / 过期时间读数），
    与 `查询文件租约` 的记录表同一口径——冲突读数也是对外读数，不许少字段。
    """
    记录 = 存储快照.get(文件键(路径)) or {}
    对外 = 文件租约存储.对外记录(dict(记录))
    对外["路径"] = 路径
    对外["占用者"] = str(记录.get("所有者") or "未知")
    对外["占用开始时间"] = str(记录.get("申请时间") or "")
    return 对外


def 申请文件租约(修改路径: Any = None, 所有者: Any = "", 任务: Any = "",
                 持有秒: Any = None, 存储标签: Any = "", 存储目录: Any = "",
                 校验指纹: Any = 假) -> Any:
    """按项目根相对路径**批量原子认领**文件租约（多会话并发写同一文件的平台级互斥）。

    返回 `{租约清单, 租约id清单, 申请数, 认领数, 冲突清单}`；同一路径已被活跃租约占用时
    整体失败（`文件已被占用`）并回带该路径的占用者与占用开始时间，绝不静默成功。

    **内容指纹（乐观锁的「内容」那一半，2026-09-18 新增）**：
    - 每条认领都**现场算**内容指纹并随租约登记（`内容指纹`）；调用方若用
      `{"路径": …, "指纹": …}` 写法，声明值一并登记（`已声明指纹`）；
    - 认领本身**不因指纹不符而拒绝** —— 认领语义是「我先站住这个文件」，不是
      「内容必须与我的认知一致」（那属于改的时机，见下）；
    - `校验指纹=真` 时，若**声明指纹与现场指纹不一致**（含只给路径没声明指纹的情形），
      整体失败 `内容已变更` 并回带两侧指纹与当前占用者 —— 这是「A 认领后文件被改，
      B 拿着旧认知要接着改」的机器可判闸门（华哥 2026-09-18 口述的乐观锁语义）。
    """
    持有人 = 文本(所有者)
    if not 持有人:
        return 失败结果("参数不合法", "所有者 不能为空（谁持有租约必须可识别）")
    承载任务 = 文本(任务)
    if not 承载任务:
        return 失败结果("参数不合法", "任务 不能为空（租约必须能追到哪次开工）")
    秒, 问题 = 正秒(持有秒, 默认持有秒, 最长持有秒)
    if 问题:
        return 失败结果("参数不合法", f"持有秒 {问题}")
    要校验指纹 = 校验指纹 is 真
    路径清单, 边界失败 = _校验路径清单(修改路径)
    if 边界失败 is not None:
        return 边界失败
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    根 = 项目根()
    # 现场指纹一律在**进独占区之前**算（对仓库文件的 IO 不该占着存储锁）；
    # 存在「算不出来」的路径即整体拒绝（如实报是哪条、为什么）。
    指纹表: list[str] = []
    for 相对路径, _声明 in 路径清单:
        指纹, 指纹问题 = 计算内容指纹(根, 相对路径)
        if 指纹问题:
            return 失败结果("内容指纹不可用", 指纹问题)
        指纹表.append(指纹)
    with 存储.独占():
        快照, 读问题 = 存储.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        快照 = dict(快照)
        冲突清单 = [存储冲突条目(路径, 快照) for 路径, _声明 in 路径清单
                    if 是活跃(快照.get(文件键(路径)))]
        冲突清单 = [条目 for 条目 in 冲突清单 if 条目]
        if 冲突清单:
            首条 = 冲突清单[0]
            return 失败结果("文件已被占用", (
                f"文件已被占用（{len(冲突清单)} 条）：{首条['路径']} 的活跃租约属 "
                f"{首条['占用者']}（租约id={首条['租约id']}），占用开始时间 "
                f"{首条['占用开始时间']}、过期时间 {首条['过期时间读数']}；"
                f"拒绝认领：批量认领必须整体成功，被占用文件不许静默跳过；"
                f"冲突路径清单 {[条目['路径'] for 条目 in 冲突清单]}。"))
        if 要校验指纹:
            不符 = [
                {"路径": 路径, "声明指纹": 声明, "现场指纹": 指纹表[序号],
                 "占用者": str((快照.get(文件键(路径)) or {}).get("所有者") or "")}
                for 序号, (路径, 声明) in enumerate(路径清单)
                if not 指纹是否一致(声明, 指纹表[序号])
            ]
            if 不符:
                首条 = 不符[0]
                return 失败结果("内容已变更", (
                    f"内容已变更（{len(不符)} 条）：{首条['路径']} 的声明指纹 "
                    f"{首条['声明指纹'] or '（未声明）'} 与现场指纹 "
                    f"{首条['现场指纹']} 不一致；拒绝按旧认知认领，"
                    f"请先 查询文件租约 看该文件的占用者与留言时间线，"
                    f"确认现状后再改。不符路径 {[条目['路径'] for 条目 in 不符]}。"))
        时刻 = time.time()
        租约清单 = [
            存储.新租约(路径, 持有人, 承载任务, 秒, 文本(存储标签), 时刻,
                        内容指纹=指纹表[序号], 已声明指纹=声明)
            for 序号, (路径, 声明) in enumerate(路径清单)
        ]
        快照.update({条目["键"]: 条目 for 条目 in 租约清单})
        写问题 = 存储.写入(快照)
    if 写问题:
        return 失败结果("存储目录不可用", 写问题)
    return 成功结果({
        "租约清单": [存储.对外记录(条目) for 条目 in 租约清单],
        "租约id清单": [条目["租约id"] for 条目 in 租约清单],
        "申请数": len(路径清单), "认领数": len(租约清单), "冲突清单": [],
    })
