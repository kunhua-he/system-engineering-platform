def 写流水(存储目录: str, 类型: str, 条目表: list[dict], 路径表: list[str],
           所有者: str, 任务: str, 时刻: float, 详情: str = "") -> str:
    """把若干条事件追加进改动流水；返回问题说明（成功为空串）。

    流水是**审计面**：写不进去**不回滚业务动作**（锁已经上了就是上了），但必须如实
    回报问题让调用方知道「这次动作没留下流水」——绝不静默。
    """
    from 平台控制面.能力目录.实现.文件改动登记 import 取日志

    日志 = 取日志(存储目录)
    if 日志 is None:
        return "存储目录 为空，改动流水未记录"
    with 日志.独占():
        流水, 读问题 = 日志.读取()
        if 读问题:
            return 读问题
        流水 = dict(流水 or {})
        for 序号, 路径 in enumerate(路径表):
            指纹 = ""
            声明 = ""
            if 序号 < len(条目表) and isinstance(条目表[序号], dict):
                指纹 = str(条目表[序号].get("内容指纹") or 条目表[序号].get("现场指纹") or "")
                声明 = str(条目表[序号].get("已声明指纹") or "")
            事件 = 文件改动日志存储.新事件(
                类型, 路径, 所有者, 任务, 内容指纹=指纹, 已声明指纹=声明,
                详情=详情, 现在=时刻)
            文件改动日志存储.追加(流水, 事件)
        return 日志.写入(流水)


def _校验路径清单(修改路径: Any) -> tuple[list[tuple[str, str]], Any]:
    """批量路径边界校验：返回 (通过清单[(路径, 声明指纹)], 失败结果)；失败非 None 即整体拒绝。"""
    原始清单, 问题 = 路径与指纹清单(修改路径, "修改路径")
    if 问题:
        return [], 失败结果("参数不合法", 问题)
    if not 原始清单:
        return [], 失败结果("参数不合法", "修改路径 不能为空（批量原子认领必须给出路径）")
    通过清单, 越界清单 = [], []
    for 原始, 声明指纹 in 原始清单:
        归一, 边界问题 = 校验相对路径(原始)
        if 边界问题:
            越界清单.append({"输入": 原始, "归一化": 归一, "说明": 边界问题})
            continue
        通过清单.append((归一, 声明指纹))
    if 越界清单:
        首条 = 越界清单[0]
        return [], 失败结果("路径越界", (
            f"修改路径越出项目根边界：{首条['输入']!r} → {首条['说明']}；"
            f"路径一律按项目根相对路径给，绝对路径 / `..` / `~` 写法一致拒绝"
            f"（旧 文件租约 只归一化、不做边界校验，本能力改判硬失败）。"
            f"越界 {len(越界清单)}/{len(原始清单)} 条。"))
    路径表 = [条目[0] for 条目 in 通过清单]
    if len(set(路径表)) != len(路径表):
        return [], 失败结果("参数不合法", "修改路径 存在重复路径（同一次认领里同一文件只允许一条）")
    return 通过清单, None


def 存储冲突条目(路径: str, 存储快照: dict) -> dict:
    """被占用路径的冲突读数：占用者与占用开始时间必须在场（不许只说「失败」）。

    对外字段一律经 `文件租约存储.对外记录` 生成（心跳时间 / 过期时间读数），
    与 `查询文件租约` 的记录表同一口径——冲突读数也是对外读数，不许少字段。
    """
    记录 = 存储快照.get(文件键(路径)) or {}
    对外 = 文件租约存储.对外记录(dict(记录))
    对外["路径"] = 路径
    对外["占用者"] = str(记录.get("所有者") or "未知")
    对外["占用开始时间"] = str(记录.get("申请时间") or "")
    return 对外


