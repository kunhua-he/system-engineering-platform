def 解锁认领路径(路径表: list[str], 项目根: Any) -> tuple[str, int, list[dict]]:
    """逐条 `解锁供写入`；返回 `(锁问题, 已解锁条数, 未解锁清单)`。

    **不把解锁失败升级成整批失败**：调到这里时租约**已经落盘**，此时再回一个「失败」
    只会让盘上事实与调用方认知相反；故按审计面口径处置（同 `流水问题`）——动作照旧，
    但如实回报「写入窗口没打开」，绝不静默。

    ★ 2026-09-24（未完成事项 §四 · 批H-H4）：**读数必须让「写窗口开没开」机器可判**。
    改前只回一个 `锁问题` 文本，调用方要自己从「14 条里几条没解开」里数；实测症状是
    上层 `开工即占` 回 `成功=true`、14 条租约已认领，而 `ls -lO` 显示 14 个文件仍是
    `uchg`、写进去 `EPERM` —— 回执里看不出窗口没开。故把这条腿的读数**逐条**回带：
    `已解锁条数` + `未解锁清单`（每条带路径与错误类型），与 `锁问题` 是同一份事实的
    两种载体，**不是第二份判据**。

    捕获范围是 `Exception`（口径同 `模块库/开工编排/实现/开工编排.py::_调用` 与本仓
    `运行核心/运行环境管理器/提供者生命周期.py:309` 那处 `noqa: BLE001`）：解锁这条腿
    除 `OSError`（含网关凭证不通过抛的 `PermissionError`）外还可能抛别的异常，而它发生在
    **租约落盘之后** —— 漏一种异常就等于「租约已落盘、调用方却只拿到一个裸异常、
    连一句 `锁问题` 都没有」，比如实回报一条锁问题更坏。错误类型进清单，不吞异常信息。
    """
    未解锁清单: list[dict] = []
    for 相对路径 in 路径表:
        try:
            解锁供写入(锁绝对路径(相对路径, 项目根))
        except Exception as 错误:  # noqa: BLE001 —— 解锁腿失败必须可见，绝不静默
            未解锁清单.append({"路径": 相对路径,
                            "错误类型": type(错误).__name__,
                            "错误说明": str(错误)})
    if not 未解锁清单:
        return "", len(路径表), []
    问题表 = [f"{条目['路径']}（{条目['错误类型']}: {条目['错误说明']}）"
             for 条目 in 未解锁清单]
    锁问题 = (f"解锁失败 {len(未解锁清单)}/{len(路径表)} 条：{'；'.join(问题表)}"
             "（租约已落盘，但这些路径的写入窗口没打开：仍被内核只读锁挡着）")
    return 锁问题, len(路径表) - len(未解锁清单), 未解锁清单


