"""申请文件租约：按项目根相对路径批量原子认领（唯一实现）。

认领语义（第 10 条 2 项：补成原子能力，不补成特例）：
- 先对**全部**路径做项目根边界校验，任一条越界即整体 `路径越界` 硬失败（不留半批）；
- 再在存储独占区内**重读**最新事实并判定活跃占用，任一条被占用即整体 `文件已被占用`，
  并回带**占用者 / 占用开始时间 / 租约id**；被占用的文件**不许静默跳过**；
- 全部通过才一次性原子落盘（临时文件 + `os.replace`）。
"""
