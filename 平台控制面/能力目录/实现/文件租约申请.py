# 冲突策略（只增参数，缺省保持老行为逐字不变）。
策略_整体拒绝 = "整体拒绝"
策略_跳过占用 = "跳过占用"
允许冲突策略 = (策略_整体拒绝, 策略_跳过占用)


def 写流水(存储目录: str, 类型: str, 条目表: list[dict], 路径表: list[str],
           所有者: str, 任务: str, 时刻: float, 详情: str = "") -> str:
    """把若干条事件追加进改动流水；返回问题说明（成功为空串）。

    流水是**审计面**：写不进去**不回滚业务动作**（锁已经上了就是上了），但必须如实
    回报问题让调用方知道「这次动作没留下流水」——绝不静默。
    """
    from 平台控制面.能力目录.实现.文件改动登记 import 取日志

    日志 = 取日志(存储目录)
    if 日志 is None:
        return "存储目录 为空，改动流水未记录"
    with 日志.独占():
        流水, 读问题 = 日志.读取()
        if 读问题:
            return 读问题
        流水 = dict(流水 or {})
        for 序号, 路径 in enumerate(路径表):
            指纹 = ""
            声明 = ""
            if 序号 < len(条目表) and isinstance(条目表[序号], dict):
                指纹 = str(条目表[序号].get("内容指纹") or 条目表[序号].get("现场指纹") or "")
                声明 = str(条目表[序号].get("已声明指纹") or "")
            事件 = 文件改动日志存储.新事件(
                类型, 路径, 所有者, 任务, 内容指纹=指纹, 已声明指纹=声明,
                详情=详情, 现在=时刻)
            文件改动日志存储.追加(流水, 事件)
        return 日志.写入(流水)


def _校验路径清单(修改路径: Any) -> tuple[list[tuple[str, str]], Any]:
    """批量路径边界校验：返回 (通过清单[(路径, 声明指纹)], 失败结果)；失败非 None 即整体拒绝。"""
    原始清单, 问题 = 路径与指纹清单(修改路径, "修改路径")
    if 问题:
        return [], 失败结果("参数不合法", 问题)
    if not 原始清单:
        return [], 失败结果("参数不合法", "修改路径 不能为空（批量原子认领必须给出路径）")
    通过清单, 越界清单 = [], []
    for 原始, 声明指纹 in 原始清单:
        归一, 边界问题 = 校验相对路径(原始)
        if 边界问题:
            越界清单.append({"输入": 原始, "归一化": 归一, "说明": 边界问题})
            continue
        通过清单.append((归一, 声明指纹))
    if 越界清单:
        首条 = 越界清单[0]
        return [], 失败结果("路径越界", (
            f"修改路径越出项目根边界：{首条['输入']!r} → {首条['说明']}；"
            f"路径一律按项目根相对路径给，绝对路径 / `..` / `~` 写法一致拒绝"
            f"（旧 文件租约 只归一化、不做边界校验，本能力改判硬失败）。"
            f"越界 {len(越界清单)}/{len(原始清单)} 条。"))
    路径表 = [条目[0] for 条目 in 通过清单]
    if len(set(路径表)) != len(路径表):
        return [], 失败结果("参数不合法", "修改路径 存在重复路径（同一次认领里同一文件只允许一条）")
    return 通过清单, None


def 存储冲突条目(路径: str, 存储快照: dict) -> dict:
    """被占用路径的冲突读数：占用者与占用开始时间必须在场（不许只说「失败」）。

    对外字段一律经 `文件租约存储.对外记录` 生成（心跳时间 / 过期时间读数），
    与 `查询文件租约` 的记录表同一口径——冲突读数也是对外读数，不许少字段。
    """
    记录 = 存储快照.get(文件键(路径)) or {}
    对外 = 文件租约存储.对外记录(dict(记录))
    对外["路径"] = 路径
    对外["占用者"] = str(记录.get("所有者") or "未知")
    对外["占用开始时间"] = str(记录.get("申请时间") or "")
    return 对外


def 申请文件租约(修改路径: Any = None, 所有者: Any = "", 任务: Any = "",
                 持有秒: Any = None, 存储标签: Any = "", 存储目录: Any = "",
                 校验指纹: Any = 假, 冲突策略: Any = "") -> Any:
    """按项目根相对路径**认领**文件租约（多会话并发写同一文件的平台级互斥＝上锁）。

    返回 `{租约清单, 租约id清单, 申请数, 认领数, 冲突清单}`；同一路径已被活跃租约占用时
    整体失败（`文件已被占用`）并回带该路径的占用者与占用开始时间，绝不静默成功。

    **内容指纹（乐观锁的「内容」那一半）**：
    - 每条认领都**现场算**内容指纹并随租约登记（`内容指纹`）；调用方若用
      `{"路径": …, "指纹": …}` 写法，声明值一并登记（`已声明指纹`）；
    - 认领本身**不因指纹不符而拒绝** —— 认领语义是「我先站住这个文件」，不是
      「内容必须与我的认知一致」（那属于改的时机，见下）；
    - `校验指纹=真` 时，若**声明指纹与现场指纹不一致**（含只给路径没声明指纹的情形），
      整体失败 `内容已变更` 并回带两侧指纹与当前占用者 —— 这是「A 认领后文件被改，
      B 拿着旧认知要接着改」的机器可判闸门。

    **冲突策略（缺省保持老行为）**：
    - 缺省 / `整体拒绝`：任一条被占用即整批失败（老行为逐字不变）；
    - `跳过占用`：能拿的拿到、被占的进 `冲突清单`（华哥口述「改哪一个冻结哪一个，
      不是全部冻结」）——**跳过的是被占的那些，其余照常上锁**，且被跳过的不写流水。
    """
    持有人 = 文本(所有者)
    if not 持有人:
        return 失败结果("参数不合法", "所有者 不能为空（谁持有租约必须可识别）")
    承载任务 = 文本(任务)
    if not 承载任务:
        return 失败结果("参数不合法", "任务 不能为空（租约必须能追到哪次开工）")
    策略 = 文本(冲突策略) or 策略_整体拒绝
    if 策略 not in 允许冲突策略:
        return 失败结果("参数不合法",
                      f"冲突策略 只能是 {允许冲突策略} 之一: {冲突策略!r}")
    跳过占用 = 策略 == 策略_跳过占用
    秒, 问题 = 正秒(持有秒, 默认持有秒, 最长持有秒)
    if 问题:
        return 失败结果("参数不合法", f"持有秒 {问题}")
    要校验指纹 = 校验指纹 is 真
    路径清单, 边界失败 = _校验路径清单(修改路径)
    if 边界失败 is not None:
        return 边界失败
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    根 = 项目根()
    # 现场指纹一律在**进独占区之前**算（对仓库文件的 IO 不该占着存储锁）；
    # 存在「算不出来」的路径即整体拒绝（如实报是哪条、为什么）。
    指纹表: list[str] = []
    for 相对路径, _声明 in 路径清单:
        指纹, 指纹问题 = 计算内容指纹(根, 相对路径)
        if 指纹问题:
            return 失败结果("内容指纹不可用", 指纹问题)
        指纹表.append(指纹)
    流水问题 = ""
    租约清单: list[dict] = []
    冲突清单: list[dict] = []
    时刻 = time.time()
    with 存储.独占():
        快照, 读问题 = 存储.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        快照 = dict(快照)
        冲突清单 = [存储冲突条目(路径, 快照) for 路径, _声明 in 路径清单
                    if 是活跃(快照.get(文件键(路径)))]
        冲突清单 = [条目 for 条目 in 冲突清单 if 条目]
        if 冲突清单 and not 跳过占用:
            首条 = 冲突清单[0]
            return 失败结果("文件已被占用", (
                f"文件已被占用（{len(冲突清单)} 条）：{首条['路径']} 的活跃租约属 "
                f"{首条['占用者']}（租约id={首条['租约id']}），占用开始时间 "
                f"{首条['占用开始时间']}、过期时间 {首条['过期时间读数']}；"
                f"拒绝认领：批量认领必须整体成功，被占用文件不许静默跳过；"
                f"冲突路径清单 {[条目['路径'] for 条目 in 冲突清单]}。"
                f"（要「改哪个锁哪个」就传 冲突策略={策略_跳过占用!r}："
                f"能拿的拿到、被占的进 冲突清单。）"))
        被占路径 = {str(条目.get("路径") or "") for 条目 in 冲突清单}
        可认领 = [(序号, 路径, 声明) for 序号, (路径, 声明) in enumerate(路径清单)
                 if 路径 not in 被占路径]
        if 要校验指纹:
            不符 = [
                {"路径": 路径, "声明指纹": 声明, "现场指纹": 指纹表[序号],
                 "占用者": str((快照.get(文件键(路径)) or {}).get("所有者") or "")}
                for 序号, 路径, 声明 in 可认领
                if not 指纹是否一致(声明, 指纹表[序号])
            ]
            if 不符:
                首条 = 不符[0]
                return 失败结果("内容已变更", (
                    f"内容已变更（{len(不符)} 条）：{首条['路径']} 的声明指纹 "
                    f"{首条['声明指纹'] or '（未声明）'} 与现场指纹 "
                    f"{首条['现场指纹']} 不一致；拒绝按旧认知认领，"
                    f"请先 查询文件租约 看该文件的占用者与留言时间线，"
                    f"确认现状后再改。不符路径 {[条目['路径'] for 条目 in 不符]}。"))
        租约清单 = [
            存储.新租约(路径, 持有人, 承载任务, 秒, 文本(存储标签), 时刻,
                        内容指纹=指纹表[序号], 已声明指纹=声明)
            for 序号, 路径, 声明 in 可认领
        ]
        if not 租约清单:
            # 全被占（跳过占用策略下可能发生）：不算成功，如实回带冲突清单。
            return 失败结果("文件已被占用", (
                f"全部 {len(冲突清单)} 条路径均被占用，本次没有认领到任何文件"
                f"（冲突策略={策略}）；冲突路径 "
                f"{[条目['路径'] for 条目 in 冲突清单]}。"))
        快照.update({条目["键"]: 条目 for 条目 in 租约清单})
        写问题 = 存储.写入(快照)
    if 写问题:
        return 失败结果("存储目录不可用", 写问题)
    # 上锁事件写流水（审计面；写不进去不回滚锁，但如实回报）。
    流水问题 = 写流水(存储目录, 事件_上锁,
                    [存储.对外记录(条目) for 条目 in 租约清单],
                    [str(条目.get("路径") or "") for 条目 in 租约清单],
                    持有人, 承载任务, 时刻,
                    详情=f"冲突策略={策略}；本次认领 {len(租约清单)} 条")
    return 成功结果({
        "租约清单": [存储.对外记录(条目) for 条目 in 租约清单],
        "租约id清单": [条目["租约id"] for 条目 in 租约清单],
        "申请数": len(路径清单), "认领数": len(租约清单),
        "冲突清单": 冲突清单,
        "流水问题": 流水问题,
    })
