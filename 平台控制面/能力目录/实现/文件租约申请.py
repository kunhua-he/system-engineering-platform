def 申请文件租约(修改路径: Any = None, 所有者: Any = "", 任务: Any = "",
                 持有秒: Any = None, 存储标签: Any = "", 存储目录: Any = "",
                 校验指纹: Any = 假, 冲突策略: Any = "", 项目根: Any = "") -> Any:
    """按项目根相对路径**认领**文件租约（多会话并发写同一文件的平台级互斥＝上锁）。

    返回 `{租约清单, 租约id清单, 申请数, 认领数, 冲突清单}`；同一路径已被活跃租约占用时
    整体失败（`文件已被占用`）并回带该路径的占用者与占用开始时间，绝不静默成功。

    **内容指纹（乐观锁的「内容」那一半）**：
    - 每条认领都**现场算**内容指纹并随租约登记（`内容指纹`）；调用方若用
      `{"路径": …, "指纹": …}` 写法，声明值一并登记（`已声明指纹`）；
    - 认领本身**不因指纹不符而拒绝** —— 认领语义是「我先站住这个文件」，不是
      「内容必须与我的认知一致」（那属于改的时机，见下）；
    - `校验指纹=真` 时，若**声明指纹与现场指纹不一致**（含只给路径没声明指纹的情形），
      整体失败 `内容已变更` 并回带两侧指纹与当前占用者 —— 这是「A 认领后文件被改，
      B 拿着旧认知要接着改」的机器可判闸门。

    **解析基准（`项目根`）**：现场指纹读的是**仓库内真实文件**，相对路径必须按项目根解析。
    走全平台唯一那条腿 `公共契约.运行时.平台适配.解析路径`：生效根 = 本参数 `项目根`
    （网关/薄壳每次调用都会补位顶层项目根）→ 环境变量 `系统平台_项目根`。
    ★ 2026-09-24：**两者都取不到时拒绝（`参数不合法`，fail-closed）**，不再兜底到进程
    cwd —— 网关跑激活制品时 cwd = 制品根（制品里没有 `测试中心/`）⇒ 登记的内容指纹来自
    制品副本、未随制品打包的路径恒「不存在」，乐观锁的「内容」那一半就此静默失效
    （未完成事项 #134）。返回值里 `指纹基准` 回带实际使用的基准根、
    `未核验指纹` 列出读不到真指纹的路径（每条 `租约清单` 条目另带 `指纹核验` =
    `已核验`/`未核验`），让「读的是哪棵树」成为机器可判的事实，而不是一个看起来正常的
    `不存在`。

    **冲突策略（缺省保持老行为）**：
    - 缺省 / `整体拒绝`：任一条被占用即整批失败（老行为逐字不变）；
    - `跳过占用`：能拿的拿到、被占的进 `冲突清单`（华哥口述「改哪一个冻结哪一个，
      不是全部冻结」）——**跳过的是被占的那些，其余照常上锁**，且被跳过的不写流水。

    **内核只读锁联动（2026-09-23 华哥裁决「开工 ID 登记的时候解锁」）**：认领成功 =
    开工窗口打开的那一刻 ⇒ 本批路径逐条 `解锁供写入`（连父链一路放开到第一个已存在的
    祖先，好让「待建路径」真能建出来）。**解锁发生在租约落盘之后**：锁跟着租约走，
    先解锁后认领一旦失败就会留下「路径已解锁、却没有租约」的半开窗口；
    失败 / 被占分支**一条锁都不碰**。解锁这条腿只认网关凭证（判据在
    `公共契约/运行时/仓库只读锁.py`），解锁失败按审计面口径记在 `锁问题` 里，
    不把已经落盘的认领改判成失败。

    **写窗口的读数（2026-09-24 批H-H4，只增字段）**：`锁问题`（散文）+ `已解锁条数` +
    `未解锁清单`（逐条：路径 / 错误类型 / 错误说明）三条同源读数一起回带，让「本批路径的
    写窗口到底开没开」**机器可判**，不必从散文里数条数。★ 口径：**读数不得误导** ——
    调用方（如 `开工编排.开工即占`）判「已开工」时必须与这三条绑定，写窗口没开就不得
    报「已开工」。本能力只保证**读数如实**（不把解锁失败升级成整批失败的理由见上），
    不代替上层做那个判定。

    **懒回收**：认领之前顺手调一次同包的 `回收过期文件租约`（挂在「有人要动文件」这个
    本来就有的唤醒点上，**不新造周期调度器**）—— 过期租约挡路径、还留着未锁的目录，
    都是后来者最该先清掉的东西；被回收的路径同时回锁。回收条数记在 `懒回收数`。
    """
    持有人 = 文本(所有者)
    if not 持有人:
        return 失败结果("参数不合法", "所有者 不能为空（谁持有租约必须可识别）")
    承载任务 = 文本(任务)
    if not 承载任务:
        return 失败结果("参数不合法", "任务 不能为空（租约必须能追到哪次开工）")
    策略 = 文本(冲突策略) or 策略_整体拒绝
    if 策略 not in 允许冲突策略:
        return 失败结果("参数不合法",
                      f"冲突策略 只能是 {允许冲突策略} 之一: {冲突策略!r}")
    跳过占用 = 策略 == 策略_跳过占用
    秒, 问题 = 正秒(持有秒, 默认持有秒, 最长持有秒)
    if 问题:
        return 失败结果("参数不合法", f"持有秒 {问题}")
    要校验指纹 = 校验指纹 is 真
    路径清单, 边界失败 = _校验路径清单(修改路径)
    if 边界失败 is not None:
        return 边界失败
    # ★ 2026-09-24（修「租约腿生效根静默落回进程 cwd」）：**fail-closed 门**放在所有
    #   写盘动作之前 —— 生效根没有显式来源（`项目根` 参数与环境变量 `系统平台_项目根`
    #   都取不到）时直接回 `参数不合法`，不再由 `解析路径` 兜底到进程 cwd（网关跑激活
    #   制品时 cwd = 制品根，登记的内容指纹会静默读错那棵树）。判据只此一处，走
    #   `文件租约存储.基准根问题`（同一份口径，本模块不自写第二套）。
    根问题 = 基准根问题(项目根)
    if 根问题:
        return 失败结果("参数不合法", 根问题)
    存储 = 取存储(存储目录)
    if 存储 is None:
        return 失败结果("参数不合法", "存储目录 不能为空")
    # 现场指纹一律在**进独占区之前**算（对仓库文件的 IO 不该占着存储锁）；
    # 存在「算不出来」的路径即整体拒绝（如实报是哪条、为什么）。
    # 解析基准走 `项目根`（唯一解析腿 `平台适配.解析路径`；两个显式来源都取不到时**拒绝**，
    # 已在上面过 `基准根问题`，不落 cwd）：
    # 此前用 `租约边界.项目根()`（= `Path(__file__).parents[3]`），网关跑激活制品时
    # 那是**制品根**（制品里没有 `开发文档/`）⇒ 认领时登记的内容指纹恒「不存在」，
    # 之后每次现场核对都判「不一致」（债务清单 134）。
    指纹表: list[str] = []
    基准根: Any = None
    for 相对路径, _声明 in 路径清单:
        指纹, 指纹问题, 本次基准根 = 现场指纹与基准(相对路径, 项目根)
        if 指纹问题:
            return 失败结果("内容指纹不可用", 指纹问题)
        指纹表.append(指纹)
        基准根 = 本次基准根
    流水问题 = ""
    租约清单: list[dict] = []
    冲突清单: list[dict] = []
    时刻 = time.time()
    # ★ 懒回收：挂在「认领」这个本来就有的唤醒点上（**不新造周期调度器**）。
    #   必须在本次认领**之前**：过期租约挡路径、还留着未锁的目录，正是后来者最该先
    #   清掉的东西；清掉的路径会同时被回锁（见 `文件租约维护.回收过期文件租约`）。
    #   它自带 `独占()`，故只能放在本段独占区**之外**（同线程虽可重入，但没必要）。
    懒回收数, 懒回收问题 = 懒回收过期租约(存储目录, 项目根)
    with 存储.独占():
        快照, 读问题 = 存储.读取()
        if 读问题:
            return 失败结果("存储目录不可用", 读问题)
        快照 = dict(快照)
        冲突清单 = [存储冲突条目(路径, 快照) for 路径, _声明 in 路径清单
                    if 是活跃(快照.get(文件键(路径)))]
        冲突清单 = [条目 for 条目 in 冲突清单 if 条目]
        if 冲突清单 and not 跳过占用:
            首条 = 冲突清单[0]
            return 失败结果("文件已被占用", (
                f"文件已被占用（{len(冲突清单)} 条）：{首条['路径']} 的活跃租约属 "
                f"{首条['占用者']}（租约id={首条['租约id']}），占用开始时间 "
                f"{首条['占用开始时间']}、过期时间 {首条['过期时间读数']}；"
                f"拒绝认领：批量认领必须整体成功，被占用文件不许静默跳过；"
                f"冲突路径清单 {[条目['路径'] for 条目 in 冲突清单]}。"
                f"（要「改哪个锁哪个」就传 **本能力**（申请文件租约）的 "
                f"冲突策略={策略_跳过占用!r}：能拿的拿到、被占的进 冲突清单。"
                f"★ 该参数**只属于本能力**，上层能力（如 开工编排.开工即占）"
                f"**不转发**它，照抄到上层即被网关当未知参数剔除、静默无效。）"))
        被占路径 = {str(条目.get("路径") or "") for 条目 in 冲突清单}
        可认领 = [(序号, 路径, 声明) for 序号, (路径, 声明) in enumerate(路径清单)
                 if 路径 not in 被占路径]
        if 要校验指纹:
            不符 = [
                {"路径": 路径, "声明指纹": 声明, "现场指纹": 指纹表[序号],
                 "占用者": str((快照.get(文件键(路径)) or {}).get("所有者") or "")}
                for 序号, 路径, 声明 in 可认领
                if not 指纹是否一致(声明, 指纹表[序号])
            ]
            if 不符:
                首条 = 不符[0]
                return 失败结果("内容已变更", (
                    f"内容已变更（{len(不符)} 条）：{首条['路径']} 的声明指纹 "
                    f"{首条['声明指纹'] or '（未声明）'} 与现场指纹 "
                    f"{首条['现场指纹']} 不一致；拒绝按旧认知认领，"
                    f"请先 查询文件租约 看该文件的占用者与留言时间线，"
                    f"确认现状后再改。不符路径 {[条目['路径'] for 条目 in 不符]}。"))
        租约清单 = [
            存储.新租约(路径, 持有人, 承载任务, 秒, 文本(存储标签), 时刻,
                        内容指纹=指纹表[序号], 已声明指纹=声明)
            for 序号, 路径, 声明 in 可认领
        ]
        if not 租约清单:
            # 全被占（跳过占用策略下可能发生）：不算成功，如实回带冲突清单。
            return 失败结果("文件已被占用", (
                f"全部 {len(冲突清单)} 条路径均被占用，本次没有认领到任何文件"
                f"（冲突策略={策略}）；冲突路径 "
                f"{[条目['路径'] for 条目 in 冲突清单]}。"))
        快照.update({条目["键"]: 条目 for 条目 in 租约清单})
        写问题 = 存储.写入(快照)
    if 写问题:
        return 失败结果("存储目录不可用", 写问题)
    # ★ 认领成功 ⇒ 逐条 `解锁供写入`（华哥裁决：「开工 ID 登记的时候解锁」）。
    #   **为什么必须在租约落盘之后、且在所有失败分支之后**：
    #   ① 锁是**跟着租约走**的 —— 没有租约就没有写窗口。若在认领之前解锁，后面任何一条
    #      失败（越界 / 被占用 / 内容已变更 / 存储写失败）都会留下「路径已解锁、
    #      却没有任何租约」的半开窗口，而那正是这条裁决要堵的口子；
    #   ② 上面每一个 `return 失败结果` 都在本行之前 ⇒ **失败 / 被占分支一条锁都不碰**，
    #      整体拒绝就是整体拒绝，不留半开。
    #   路径解析基准 = 本参数 `项目根`（与现场指纹同一条 `解析路径` 腿）。
    #   解锁会连父链一路放开到第一个已存在的祖先，好让「待建路径」真能建出来。
    锁问题, 已解锁条数, 未解锁清单 = 解锁认领路径(
        [str(条目.get("路径") or "") for 条目 in 租约清单], 项目根)
    # 上锁事件写流水（审计面；写不进去不回滚锁，但如实回报）。
    流水问题 = 写流水(存储目录, 事件_上锁,
                    [存储.对外记录(条目) for 条目 in 租约清单],
                    [str(条目.get("路径") or "") for 条目 in 租约清单],
                    持有人, 承载任务, 时刻,
                    详情=f"冲突策略={策略}；本次认领 {len(租约清单)} 条")
    # ★ 2026-09-23（未完成事项 #134 ③）：把「这次指纹读的是哪棵树、哪些路径根本没核验」
    #   如实回带。此前读不到就静默回一个 `不存在`（与「文件真的是新建的」在读数上一模一样），
    #   基准根一旦落错树（制品根 / cwd）调用方无从分辨 ⇒ 乐观锁的「内容」那一半失效。
    #   只增字段（哲学第 5 条 2 项）：老键语义逐字不变。
    对外清单: list[dict] = []
    for 条目 in 租约清单:
        对外 = 存储.对外记录(条目)
        对外["指纹核验"] = "已核验" if 指纹已核验(对外.get("内容指纹")) else "未核验"
        对外清单.append(对外)
    未核验指纹 = [{"路径": str(条目.get("路径") or ""),
                "内容指纹": str(条目.get("内容指纹") or ""),
                "说明": "该路径按本次基准根读不到真实文件（新建/被删/基准根落错树），"
                      "此读数不能作为「内容一致」的证据"}
               for 条目 in 对外清单 if 条目.get("指纹核验") == "未核验"]
    return 成功结果({
        "租约清单": 对外清单,
        "租约id清单": [条目["租约id"] for 条目 in 租约清单],
        "申请数": len(路径清单), "认领数": len(租约清单),
        "冲突清单": 冲突清单,
        # 指纹基准 = 现场指纹**实际使用**的解析基准根（绝对）；未核验指纹 = 读不到真指纹的路径。
        # 两者合起来让「错树」变成机器可判：基准根不是仓库根 / 未核验非空即要警觉。
        "指纹基准": str(基准根) if 基准根 is not None else "",
        "未核验指纹": 未核验指纹,
        "流水问题": 流水问题,
        # 内核只读锁联动的读数（2026-09-23 起，只增字段）：`锁问题` 非空 = 租约已落盘但
        # 写入窗口没打开（该路径仍被内核锁挡着）；`懒回收数` = 本次认领前顺手回收掉的
        # 过期租约条数（回收时已把它们的路径回锁）；`懒回收问题` = 那一步没跑成的原因。
        # ★ 2026-09-24 批H-H4 补两条同源读数（只增字段，老键语义不变）：`已解锁条数` 与
        # `未解锁清单`（每条带 路径/错误类型/错误说明）—— 「写窗口开没开」由此**逐条**可判，
        # 调用方不必再从 `锁问题` 的散文里数条数；`锁问题` 非空 ⇔ `未解锁清单` 非空。
        "锁问题": 锁问题,
        "已解锁条数": 已解锁条数,
        "未解锁清单": 未解锁清单,
        "懒回收数": 懒回收数,
        "懒回收问题": 懒回收问题,
    })
