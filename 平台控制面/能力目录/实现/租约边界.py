def 文本(值: Any) -> str:
    """文本参数归一：None 视为空串，其余转文本并去首尾空白。"""
    return "" if 值 is None else str(值).strip()


def 正秒(值: Any, 缺省: float, 上限: float) -> tuple[float, str]:
    """秒数参数归一：缺省取 缺省，非法或越界返回问题说明（不静默截断）。"""
    if 值 is None or 值 == "":
        return 缺省, ""
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        return 0.0, f"必须是非负秒数（数），收到 {type(值).__name__}: {值!r}"
    if 值 < 0 or 值 > 上限:
        return 0.0, f"必须在 0 到 {上限} 秒之间，收到 {值!r}"
    return float(值), ""


def 文本清单(值: Any, 名称: str) -> tuple[list[str], str]:
    """文本列表参数归一：None 视为空表；含非文本项即如实报问题（不静默丢弃）。"""
    if 值 is None:
        return [], ""
    if not isinstance(值, list):
        return [], f"{名称} 必须是列表型，收到 {type(值).__name__}"
    清单 = []
    for 序号, 项 in enumerate(值):
        if not isinstance(项, str) or not 项.strip():
            return [], f"{名称} 第 {序号} 项必须是非空文本: {项!r}"
        清单.append(项.strip())
    return 清单, ""


def 路径与指纹清单(值: Any, 名称: str = "修改路径") -> tuple[list[tuple[str, str]], str]:
    """路径与声明指纹的参数归一：返回 `[(路径, 声明指纹), …]`，问题非空即整体拒绝。

    **两种写法都收**（老调用逐字兼容，新调用可带指纹）：
    - 纯文本项 `"模块库/开工编排/实现/开工编排.py"` → 声明指纹为空（只锁路径，旧口径）；
    - 字典项 `{"路径": …, "指纹": …}` → 同时登记声明指纹（乐观锁的「内容」那一半）。
    字典项缺 `路径` 即如实报问题（不静默当空路径丢掉）；`指纹` 缺省为空串。
    顺序即入参顺序（存储与读数都按它稳定排序，不许靠字典序漂移）。
    """
    if 值 is None:
        return [], ""
    if not isinstance(值, list):
        return [], f"{名称} 必须是列表型，收到 {type(值).__name__}"
    清单: list[tuple[str, str]] = []
    for 序号, 项 in enumerate(值):
        if isinstance(项, str) and 项.strip():
            清单.append((项.strip(), ""))
            continue
        if isinstance(项, dict):
            路径 = str(项.get("路径") or "").strip()
            if not 路径:
                return [], f"{名称} 第 {序号} 项是字典但缺 `路径`: {项!r}"
            清单.append((路径, str(项.get("指纹") or "").strip()))
            continue
        return [], f"{名称} 第 {序号} 项必须是文本或 `{{路径, 指纹}}` 字典: {项!r}"
    return 清单, ""


