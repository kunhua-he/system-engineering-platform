"""能力目录包的实现层：消费者契约注册表动作的唯一执行入口（能力实现）。

本模块是 `平台控制面.能力目录` 正式包的能力实现层，包级中文入口
（同包 `__init__.py`）的 `注册能力(注册表)` 从这里取实现函数。

分工（第 2 条 1 项「分层与归属固定」）：
- 同目录 `消费者契约注册表.py`：消费者契约的登记/查询/删除/漂移判定/门禁判定
  的**唯一语义实现**，事实落 `存储目录/消费者契约.json`；
- 同目录 `服务.py`：能力目录服务（契约指纹/复用裁决/占用租约）的唯一语义实现，
  本批**不**为它开能力——它只有同层调用方（`平台控制面/统一入口.py`、
  `平台控制面/__init__.py`），属合法的同层分层，没有越层调用方；
- 本模块：把 `消费者契约注册表` 的公开方法收成**统一结果契约**的能力实现，
  只做能力边界上的存储目录缺省与结果收口，不复制任何契约语义。

为什么要有这一层：`开发工具` 下的发布门禁是**进程外**调用方，不得 import 本包
实现，只能经唯一能力调用入口按能力 id 调用；本层是它唯一可达的公开面。
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

错误_参数不合法 = "参数不合法"

# 存储目录缺省值：取包内系统根下的 工程缓存/平台控制面（绝对路径，
# 不随调用方工作目录漂移；运行态一律入库 工程缓存）。
_包内系统根 = Path(__file__).resolve().parents[3]
默认存储目录 = str(_包内系统根 / "工程缓存" / "平台控制面")


def _文本(值: Any) -> str:
    """文本参数归一：None 视为空串，其余转文本并去首尾空白。"""
    return "" if 值 is None else str(值).strip()


def _取注册表(存储目录: str):
    """按存储目录构造 消费者契约注册表；目录为空即取平台默认目录。"""
    from 平台控制面.能力目录.消费者契约注册表 import 消费者契约注册表

    目录 = _文本(存储目录) or 默认存储目录
    return 消费者契约注册表(Path(目录))


def _收口(返回: dict, 成功值: dict[str, Any]) -> Any:
    """把 消费者契约注册表 的统一返回映射为能力的统一结果。

    - 注册表 `成功=True` → **成功结果**，值 = 成功值（逐键取自注册表数据，
      不复制判定语义）；
    - 注册表 `成功=False` → **失败结果**，错误码与消息逐字沿用注册表原文
      （`消费者必填` / `能力必填` / `契约非法` / `未登记`），调用方据此映射
      自己的错误码，口径逐字保持。
    """
    from 公共契约.基础类型.结果类型 import 结果

    if not 返回["成功"]:
        return 结果.失败(str(返回["错误码"]), str(返回["消息"]), 来源="能力目录")
    return 结果.成功结果(成功值)


def _能力id守卫(能力id: str) -> Any:
    """查询/判定类能力的边界守卫：能力id 必填（fail-closed）。

    为什么必填不是「多此一举」：`消费者契约注册表.查询契约("")` 与
    `门禁判定("")` 都会返回**空结果**——而空门禁结果会被发布门禁读成
    「不阻断」（放行）。空 id 必须明确失败，绝不能放行。
    """
    from 公共契约.基础类型.结果类型 import 结果

    if not _文本(能力id):
        return 结果.失败(错误_参数不合法, "能力id 不能为空", 来源="能力目录")
    return None


def 登记消费者契约(消费者id: str = "", 能力id: str = "", 契约: dict | None = None,
                  存储目录: str = "") -> Any:
    """登记消费者对能力的契约（请求/响应约束/错误码/超时/释放要求）并落盘。

    返回 `{消费者id, 能力id, 消息, 记录}`；契约结构不合法由注册表判
    `契约非法` 并给出问题原文（失败即失败，不补默认值、不静默降级）。
    """
    返回 = _取注册表(存储目录).登记契约(
        _文本(消费者id), _文本(能力id), 契约 if isinstance(契约, dict) else {})
    return _收口(返回, {
        "消费者id": _文本(消费者id), "能力id": _文本(能力id),
        "消息": str(返回["消息"]), "记录": 返回["数据"],
    })


def 查询消费者契约(能力id: str = "", 存储目录: str = "") -> Any:
    """查询能力下全部消费者契约（只读）；返回 `{记录表, 数量}`。

    能力id 必填：空 id 会命中「未登记能力」的空表，读起来像「该能力没有消费者
    契约」，那是**假空**，必须明确失败。
    """
    守卫 = _能力id守卫(能力id)
    if 守卫 is not None:
        return 守卫
    返回 = _取注册表(存储目录).查询契约(_文本(能力id))
    记录表 = 返回["数据"] or []
    return _收口(返回, {"记录表": list(记录表), "数量": len(记录表)})


def 删除消费者契约(消费者id: str = "", 能力id: str = "", 存储目录: str = "") -> Any:
    """删除消费者与能力的契约绑定；未登记返回 `未登记`（失败即失败）。"""
    返回 = _取注册表(存储目录).删除契约(_文本(消费者id), _文本(能力id))
    return _收口(返回, {
        "消费者id": _文本(消费者id), "能力id": _文本(能力id),
        "消息": str(返回["消息"]),
    })


def 判定契约漂移(能力id: str = "", 当前契约: dict | None = None,
                存储目录: str = "") -> Any:
    """当前能力契约与全部登记消费者契约逐项对比（只读）。

    返回 `{漂移列表, 漂移数}`；漂移列表逐项含 消费者id/期望值/实际值/漂移类型，
    供发布门禁做证据展示。对比项 = 参数/返回键/错误码/超时/释放要求。
    能力id 必填（空 id 的空漂移列表是假证据）。
    """
    守卫 = _能力id守卫(能力id)
    if 守卫 is not None:
        return 守卫
    返回 = _取注册表(存储目录).漂移判定(
        _文本(能力id), 当前契约 if isinstance(当前契约, dict) else {})
    漂移列表 = 返回["数据"] or []
    return _收口(返回, {"漂移列表": list(漂移列表), "漂移数": len(漂移列表)})


def 判定契约门禁(能力id: str = "", 当前契约: dict | None = None,
                存储目录: str = "") -> Any:
    """门禁判定：存在任一漂移即判阻断（只读）。

    返回 `{是否阻断, 漂移列表, 漂移数}`——`是否阻断=True` 是**判定结论**（正常答复），
    不是调用失败；发布门禁据此阻断发布。**能力id 必填**——空 id 会得到
    「不阻断」的假放行，属 fail-open，必须明确失败。
    """
    守卫 = _能力id守卫(能力id)
    if 守卫 is not None:
        return 守卫
    返回 = _取注册表(存储目录).门禁判定(
        _文本(能力id), 当前契约 if isinstance(当前契约, dict) else {})
    数据 = 返回["数据"] or {}
    漂移列表 = list(数据.get("漂移列表") or [])
    return _收口(返回, {
        "是否阻断": bool(数据.get("是否阻断")),
        "漂移列表": 漂移列表, "漂移数": len(漂移列表),
    })


