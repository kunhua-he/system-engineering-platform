"""消费者契约登记判定：现场认「消费者关系」，为漂移门禁补上「公开能力必须有登记」的反向断言。

为什么必须有这个模块（哲学 14.1 归因② 架构错位）：

消费者契约注册表（同目录 `消费者契约注册表.py`）本身是**齐备**的——登记/查询/删除/
漂移判定/门禁判定五条能力都有真实实现、真实落盘与真实测试。缺的不是机制，而是
**「公开能力必须有登记」这条反向断言没有接线**：漂移门禁只问「已登记的契约有没有漂移」，
**没有登记的能力根本不参与对比**，于是「登记表为 0 份」时门禁对全部真实包**恒放行**。
现场实测（2026-09-18）：`find . -name "消费者契约*.json" -not -path './工程缓存/*' | wc -l`
= **0 份**，而全仓跨包消费者关系真实存在（依赖声明 119 条 + 验证场景调用 1064 步）。
见 `开发文档/未完成事项.md` 第 30 条。

本模块把该断言做成**可被门禁与验证器直接调用的真实判据**：
- `枚举消费者关系`：现场枚举真实存在的跨包消费者关系（证据见下）；
- `取能力契约`：把提供包声明面上的真实字段投影成漂移比对用的「当前契约」；
- `判定登记完整性`：逐条关系核对「有没有登记」，任何一条缺登记即如实列出（fail-closed）；
- `判定全部漂移`：对全部有关系的公开能力真实跑一遍漂移判定（不是空表恒绿）。

## 消费者关系的判定口径（**现场实测**，不许凭空造）

一条**跨包消费者关系**必须同时具备两份来自正式包声明面的证据，缺一不算：

1. **消费者方证据**：消费者包在 `包声明.json` 的 `依赖` 里**逐条声明**了被消费的能力 id
   （平台既有的声明面依赖口径；实测 119 条，且 100% 能在 `能力定义.json` 里解析到提供者）。
2. **提供者方证据**：该能力 id 在**提供包**的 `能力定义.json` 能力列表里真实存在
   （`能力定义.json` 是平台唯一的能力声明面，owner 判据与 `开发工具/项目编译/正式包索引` 同源）。

同一能力 id 出现在两侧、或「消费者包就是提供包」（包内自消费）**不算**消费者契约要管的关系：
契约要管的是**跨边界**的承诺。实测口径见回传：跨包关系按「依赖声明」为 119 条 /
按「依赖声明 ∪ 验证场景调用」为 348 条；本模块以**依赖声明**为主证据（可机器判定、
且是平台既有声明面），验证场景调用只作交叉核对，不单独构成登记义务（场景里的调用步
多数是包内自测编排，把它当契约义务会把「测试怎么调」升格成「对外承诺」）。

## 「当前契约」字段全部逐字取自声明面（不造值）

| 契约字段 | 取值来源（逐字） | 取不到时的行为 |
|---|---|---|
| 请求.参数列表 | `能力定义.json` 的 `参数[].名称` | 空表 → 该能力**计入缺登记**（判不出 ≠ 通过） |
| 请求.示例 | `能力契约/参数契约.json` 的 `调用示例` | 缺失 → 计入缺登记 |
| 响应约束.返回键 | `能力定义.json` 的 `返回.值结构` 键集合 | 空 → 计入缺登记 |
| 响应约束.结构 | `能力定义.json` 的 `返回.类型` | 空 → 计入缺登记 |
| 错误码集 | `能力定义.json` 的 `错误码` 列表 | 必须是列表（空列表是合法值：声明「无错误码」） |
| 超时 | 提供包 `资源预算.json` 的 `单次调用超时`（秒） | 缺失 → 计入缺登记 |
| 释放要求 | `能力定义.json` 的 `行为.资源释放` 原文；原文为「无外部资源/无」→ 空表 | 缺失 → 计入缺登记 |

**为什么超时取包级 `资源预算.json` 而不是能力级**：能力声明面**没有**能力级超时字段
（实测 675 能力里 0 个有），凭一个不存在的字段造值就是假证据；包级 `单次调用超时`
是平台对「本包任一能力单次调用」的既有承诺口径，逐字取用并在 `超时来源` 字段里标注。

**为什么「返回.值结构 缺失」计入缺登记而不是跳过**：实测 675 个能力里 292 个
（43%）没有 `返回.值结构`，那类能力**无法**形成「响应约束」这一项的期望值——没有期望值
就没有可比对的契约，登记它等于给漂移门禁塞一张空头支票。本模块的处理是
**如实列入缺登记清单**（带缺项原因），不静默跳过、也不替它编造返回键。

判断口径（一句话）：**判不出的能力一律按「没有登记」处理**——反向断言的方向必须是
宁可报红也不许假绿（fail-open 正是本条要消灭的东西）。
"""
from __future__ import annotations

import ast
import json
from pathlib import Path

# 包级声明面的固定文件名（正式根下按包目录读取，口径与 正式包索引 一致）
包声明名 = "包声明.json"
能力定义名 = "能力定义.json"
参数契约相对路径 = ("能力契约", "参数契约.json")
资源预算名 = "资源预算.json"
# 正式根清单的**唯一事实源**（顶层正式包根）：不硬编码三根，见 决策记录 0012
正式根事实源 = ("公共契约", "正式根.py")
正式根名表变量 = "正式根名表"

# 「无外部资源」类释放要求的既有写法（逐字枚举，不靠子串猜测）
无释放写法 = frozenset({"", "无", "无外部资源", "不涉及", "无（失败即不落盘，不留半份状态）"})

# 缺登记清单的返回上限：清单是给人和门禁看证据用的，报满 100 条已足够定位；
# 全量条数由 `未登记关系数` 如实给出（截断绝不改变判定结果）。
清单上限 = 100


def _读JSON(路径: Path):
    """读 JSON；不可读返回 None（调用方按「判不出」处理，不静默当空表）。"""
    try:
        return json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return None


def 正式根名表(系统根: Path) -> tuple[str, ...]:
    """读正式根清单（AST 取字面量，不 import：直跑与包式调用同一结果）。

    读不成即抛错——**不退回硬编码三根**：那正是「正式包面有 37 个圈外却恒绿」的老病根
    （见 `开发工具/公开调用完整性门禁.py` 的 E-2 段）。判不出扫描面就必须判红，
    绝不用一份可能漏掉整个正式根的名表继续算。
    """
    路径 = Path(系统根).joinpath(*正式根事实源)
    try:
        树 = ast.parse(路径.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, SyntaxError) as 错误:
        raise RuntimeError(f"正式根清单不可读，扫描面未知: {路径}（{错误.__class__.__name__}）") from 错误
    for 节点 in 树.body:
        # 既支持 `正式根名表 = (...)`，也支持带类型标注的 `正式根名表: tuple[str, ...] = (...)`
        if isinstance(节点, ast.AnnAssign):
            目标列表 = [节点.target]
            值节点 = 节点.value
        elif isinstance(节点, ast.Assign):
            目标列表 = list(节点.targets)
            值节点 = 节点.value
        else:
            continue
        if 值节点 is None:
            continue
        if any(isinstance(目标, ast.Name) and 目标.id == 正式根名表变量 for 目标 in 目标列表):
            return tuple(ast.literal_eval(值节点))
    raise RuntimeError(f"正式根清单缺少 {正式根名表变量}: {路径}")


def 枚举正式包(系统根: Path) -> dict[str, dict]:
    """枚举正式包声明面：{包目录相对路径 → {包id, 包目录, 能力列表, 依赖}}。

    只收录**自持 `能力定义.json`** 的包为「公开能力包」（聚合父包是子包的对外视图，
    能力 owner 在子包，判据与 `正式包索引` 的 owner 规则一致）；无 `能力定义.json`
    的包仍收录（它的 `依赖` 是消费者方证据的来源，例如 `模块库/开工编排`）。
    """
    系统根 = Path(系统根)
    出: dict[str, dict] = {}
    for 根名 in 正式根名表(系统根):
        基 = 系统根 / 根名
        if not 基.is_dir():
            continue
        for 声明路径 in sorted(基.rglob(包声明名)):
            if "__pycache__" in 声明路径.parts:
                continue
            声明 = _读JSON(声明路径)
            if not isinstance(声明, dict):
                continue
            包目录 = 声明路径.parent
            相对 = 包目录.relative_to(系统根).as_posix()
            能力列表 = []
            定义 = _读JSON(包目录 / 能力定义名)
            if isinstance(定义, dict) and isinstance(定义.get("能力列表"), list):
                能力列表 = [条 for 条 in 定义["能力列表"] if isinstance(条, dict) and 条.get("能力id")]
            出[相对] = {
                "包id": str(声明.get("包id") or 相对),
                "包目录": 包目录,
                "相对路径": 相对,
                "声明": 声明,
                "能力列表": 能力列表,
                "依赖": [条 for 条 in (声明.get("依赖") or []) if isinstance(条, dict)],
            }
    return 出


def _提供者索引(包表: dict[str, dict]) -> dict[str, list[str]]:
    """能力 id → 提供它的包相对路径列表（能力定义.json 是 owner 面）。"""
    索引: dict[str, list[str]] = {}
    for 相对, 信息 in 包表.items():
        for 条 in 信息["能力列表"]:
            索引.setdefault(str(条["能力id"]), []).append(相对)
    return 索引


def 枚举消费者关系(系统根: Path, 包表: dict[str, dict] | None = None) -> list[dict]:
    """枚举跨包消费者关系的唯一入口（主证据 = 包声明.依赖）。

    返回每条关系：{消费者id, 消费者包, 能力id, 提供包, 版本要求, 证据}。
    未在 `能力定义.json` 里解析到提供者的依赖条目**照样列出**（`提供包` 记空串）：
    那类「依赖了不存在的能力」是平台的依赖闭包缺口，属于本判据该报红的事，
    不能因为解析不到就悄悄略过。
    """
    包表 = 包表 if 包表 is not None else 枚举正式包(系统根)
    提供者 = _提供者索引(包表)
    出: list[dict] = []
    for 相对, 信息 in sorted(包表.items()):
        for 依赖 in 信息["依赖"]:
            能力id = str(依赖.get("能力") or "").strip()
            if not 能力id:
                continue
            提供包 = next((项 for 项 in 提供者.get(能力id, []) if 项 != 相对), "")
            出.append({
                "消费者id": 信息["包id"],
                "消费者包": 相对,
                "能力id": 能力id,
                "提供包": 提供包,
                "版本要求": str(依赖.get("版本") or ""),
                "证据": "包声明.依赖",
            })
    return 出


def 取能力契约(包表: dict[str, dict], 能力id: str) -> dict:
    """把提供包声明面上的真实字段投影成漂移比对用的「当前契约」。

    返回 {当前契约, 缺项, 提供包, 超时来源}；`缺项` 非空即「判不出」——
    调用方（本模块的判定与外部门禁）一律按**没有登记**处理，不许当通过。
    """
    提供包 = ""
    for 相对, 信息 in 包表.items():
        if any(str(条["能力id"]) == 能力id for 条 in 信息["能力列表"]):
            提供包 = 相对
            break
    if not 提供包:
        return {"当前契约": {}, "缺项": ["提供包内无此能力的能力定义"],
                "提供包": "", "超时来源": ""}
    信息 = 包表[提供包]
    条目 = next(条 for 条 in 信息["能力列表"] if str(条["能力id"]) == 能力id)
    参数列表 = [str(参数["名称"]) for 参数 in (条目.get("参数") or [])
               if isinstance(参数, dict) and 参数.get("名称")]
    返回 = 条目.get("返回") if isinstance(条目.get("返回"), dict) else {}
    值结构原始 = 返回.get("值结构") if isinstance(返回, dict) else None
    值结构: dict = 值结构原始 if isinstance(值结构原始, dict) else {}
    返回键 = list(值结构)
    结构 = 返回.get("类型") if isinstance(返回.get("类型"), str) else ""
    错误码 = 条目.get("错误码")
    释放原文 = (条目.get("行为") or {}).get("资源释放")
    释放要求 = [释放原文] if 释放原文 not in 无释放写法 and isinstance(释放原文, str) else []
    契约文件 = 信息["包目录"].joinpath(*参数契约相对路径)
    契约数据 = _读JSON(契约文件)
    示例 = {}
    if isinstance(契约数据, dict) and isinstance(契约数据.get("能力契约"), list):
        for 契约条目 in 契约数据["能力契约"]:
            if isinstance(契约条目, dict) and 契约条目.get("能力id") == 能力id:
                示例 = 契约条目.get("调用示例") if isinstance(契约条目.get("调用示例"), dict) else {}
                break
    预算 = _读JSON(信息["包目录"] / 资源预算名)
    超时 = 预算.get("单次调用超时") if isinstance(预算, dict) else None
    缺项: list[str] = []
    if not 参数列表:
        缺项.append("请求参数列表")
    if not 示例:
        缺项.append("请求示例")
    if not 返回键:
        缺项.append("响应约束返回键")
    if not 结构:
        缺项.append("响应约束结构")
    if not isinstance(错误码, list):
        缺项.append("错误码集")
    if not isinstance(超时, (int, float)) or isinstance(超时, bool):
        缺项.append("超时")
    if not isinstance(释放原文, str) or not 释放原文:
        缺项.append("释放要求")
    当前契约 = {
        "请求": {"参数列表": 参数列表, "示例": dict(示例)},
        "响应约束": {"返回键": 返回键, "结构": 结构},
        "错误码集": list(错误码) if isinstance(错误码, list) else [],
        "超时": 超时 if isinstance(超时, (int, float)) and not isinstance(超时, bool) else None,
        "释放要求": 释放要求,
    }
    return {"当前契约": 当前契约, "缺项": 缺项, "提供包": 提供包,
            "超时来源": f"{提供包}/{资源预算名}.单次调用超时"}


def 消费者id(消费者包id: str) -> str:
    """登记用的消费者标识 = 消费者包id。

    为什么不另编码：注册表的键是「能力id + 消费者id」，能力 id 全仓唯一
    （公开调用完整性门禁的硬约束），所以「消费者包id」这一层就够用，且
    与包声明面**逐字同名**——门禁报红时能直接定位到哪个包欠了登记。
    """
    return 消费者包id


def 判定登记完整性(系统根: Path, *, 注册表=None, 存储目录: str = "",
                  包表: dict[str, dict] | None = None) -> dict:
    """反向断言本体：每条真实跨包消费者关系都必须有登记，缺一条即如实报出。

    `注册表` 取「查询消费者契约」的返回：`注册表.查询契约(能力id)` 的
    `{"成功":…, "数据":[…]}`。默认自行构造注册表（目录缺省走同一份默认口径）。
    读存储失败（半截 JSON / 锁不可用）**按缺登记处理**：判不出就是判不出，
    绝不当成「有登记」放行。
    """
    包表 = 包表 if 包表 is not None else 枚举正式包(系统根)
    关系 = 枚举消费者关系(系统根, 包表)
    if 注册表 is None:
        from 平台控制面.能力目录.消费者契约注册表 import 消费者契约注册表
        from 平台控制面.能力目录.实现.能力入口 import 默认存储目录

        目录 = 存储目录 or 默认存储目录
        注册表 = 消费者契约注册表.取实例(Path(目录))
    已登记关系数 = 0
    未登记: list[dict] = []
    覆盖提供包: set[str] = set()
    缺字段能力: dict[str, list[str]] = {}
    存储问题: list[str] = []
    for 项 in 关系:
        查询 = 注册表.查询契约(项["能力id"])
        记录表 = list(查询.get("数据") or []) if 查询.get("成功") else []
        if not 查询.get("成功"):
            存储问题.append(f"{项['能力id']}: {查询.get('消息') or 查询.get('错误码')}")
        if 记录表:
            已登记关系数 += 1
            if 项["提供包"]:
                覆盖提供包.add(项["提供包"])
            continue
        鉴定 = 取能力契约(包表, 项["能力id"])
        if 鉴定["缺项"]:
            缺字段能力[项["能力id"]] = list(鉴定["缺项"])
        未登记.append({**项, "缺项": 鉴定["缺项"], "提供包": 鉴定["提供包"] or 项["提供包"]})
    公开能力包 = sorted({项["提供包"] for 项 in 关系 if 项["提供包"]})
    总包数 = len(包表)
    问题表: list[str] = []
    if 未登记:
        问题表.append(
            f"{len(未登记)}/{len(关系)} 条真实跨包消费者关系没有登记消费者契约"
            f"（涉及 {len({项['能力id'] for 项 in 未登记})} 个公开能力、"
            f"{len({项['提供包'] for 项 in 未登记 if 项['提供包']})} 个公开能力包）")
    if 存储问题:
        问题表.append(f"消费者契约存储不可读 {len(存储问题)} 处，已按缺登记处理: {存储问题[:3]}")
    判定说明 = "；".join(问题表) if 问题表 else "全部真实跨包消费者关系均有登记，断言通过"
    return {
        "通过": not 问题表,
        "总包数": 总包数,
        "公开能力包数": len(公开能力包),
        "公开能力数": len({项["能力id"] for 项 in 关系}),
        "总关系数": len(关系),
        "已登记关系数": 已登记关系数,
        "未登记关系数": len(未登记),
        "未登记清单": 未登记[:清单上限],
        "清单已截断": len(未登记) > 清单上限,
        "覆盖提供包清单": sorted(覆盖提供包),
        "未覆盖提供包清单": sorted(set(公开能力包) - 覆盖提供包),
        "缺字段能力": 缺字段能力,
        "判定说明": 判定说明,
    }


def 判定全部漂移(系统根: Path, *, 注册表=None, 存储目录: str = "",
                包表: dict[str, dict] | None = None) -> dict:
    """对全部「有跨包消费者关系」的公开能力真实跑一遍漂移判定。

    为什么要有它：`判定契约漂移` 是逐能力调用的能力，**没有任何调用点会自动跑全仓**——
    登记表空着的时候，「跑一遍漂移」与「不跑」得到的是同一个空结论。本函数把
    「全仓真实包逐能力跑」这件事收成一个可被门禁直接调用的判据，顺带把
    「当前契约取不到完整字段」的能力也如实列出（那类能力连参与比对的资格都没有）。
    """
    包表 = 包表 if 包表 is not None else 枚举正式包(系统根)
    if 注册表 is None:
        from 平台控制面.能力目录.消费者契约注册表 import 消费者契约注册表
        from 平台控制面.能力目录.实现.能力入口 import 默认存储目录

        注册表 = 消费者契约注册表.取实例(Path(存储目录 or 默认存储目录))
    漂移列表: list[dict] = []
    已判定能力数 = 0
    判不出: list[dict] = []
    for 能力id in sorted({项["能力id"] for 项 in 枚举消费者关系(系统根, 包表)}):
        鉴定 = 取能力契约(包表, 能力id)
        if 鉴定["缺项"]:
            判不出.append({"能力id": 能力id, "提供包": 鉴定["提供包"], "缺项": 鉴定["缺项"]})
            continue
        结果 = 注册表.漂移判定(能力id, 鉴定["当前契约"])
        if not 结果.get("成功"):
            判不出.append({"能力id": 能力id, "提供包": 鉴定["提供包"],
                          "缺项": [f"漂移判定不可用: {结果.get('消息') or 结果.get('错误码')}"]})
            continue
        已判定能力数 += 1
        for 项 in (结果.get("数据") or []):
            漂移列表.append({"能力id": 能力id, "提供包": 鉴定["提供包"], **项})
    return {
        "漂移数": len(漂移列表),
        "漂移列表": 漂移列表[:清单上限],
        "清单已截断": len(漂移列表) > 清单上限,
        "已判定能力数": 已判定能力数,
        "判不出能力数": len(判不出),
        "判不出清单": 判不出[:清单上限],
        "是否阻断": bool(漂移列表) or bool(判不出),
    }


# ---- 跨包消费者关系基线（「只增不报」的存量口径，与公开调用完整性门禁同一套路）----
#
# 为什么需要基线：C1 的反向断言要求「每条真实跨包消费者关系都必须有登记」。而现场
# 实测 119 条关系里，39 个提供包、90 个公开能力的**响应约束（返回键/结构）在能力声
# 明面就没有**（675 个能力里 292 个缺 `返回.值结构`，43%）——对它们只能登记出半份
# 契约（无响应约束），登记了也拦不住漂移，等于制造假证据。把这类一口气判红，会把
# 门禁做成「永远红」，与「先把判据接上线、再逐包补声明面」的施工顺序冲突。
#
# 口径（与 `公开调用完整性门禁存量基线.json` 逐条同规矩）：
# - **基线内 = 存量**：字段齐备的关系即便暂未登记，也只报不拦（本批已全部登记，桶内
#   计数为 0，属「已清空的历史桶」）；
# - **基线外 = 新增**：新增关系或新增能力包，一出现就必须有登记，否则判红；
# - 基线文件缺失/读不成 → **全量判红**（fail-closed，不静默放过）。
基线文件名 = "消费者关系基线.json"


def 载入基线(包目录: Path) -> dict:
    """读跨包消费者关系基线；读不成返回空基线 + 问题说明（调用方据此全量判红）。"""
    路径 = Path(包目录) / 基线文件名
    数据 = _读JSON(路径)
    if not isinstance(数据, dict) or not isinstance(数据.get("关系基线"), list):
        return {"关系基线": [], "提供包基线": [], "来源": str(路径),
                "问题": f"基线不可读或结构不合法: {路径}"}
    关系基线 = [x for x in 数据["关系基线"] if isinstance(x, str) and x]
    提供包基线 = [x for x in 数据.get("提供包基线", []) if isinstance(x, str) and x]
    return {"关系基线": 关系基线, "提供包基线": 提供包基线, "来源": str(路径), "问题": ""}


def 关系键(项: dict) -> str:
    """基线键口径：`能力id <- 消费者包`（两侧都在声明面逐字可取）。"""
    return f"{项['能力id']} <- {项['消费者包']}"


def 判定登记完整性带基线(系统根: Path, *, 参考目录: Path | None = None,
                        注册表=None, 存储目录: str = "",
                        包表: dict[str, dict] | None = None) -> dict:
    """C1 门禁判据：基线外关系缺登记即判红；基线内只报。

    与 `判定登记完整性` 的分工：那支是**全量事实**（给人和验证器看现状），
    这支是**门禁判据**（只对新增判红）。两支共用同一枚举与登记查询，不复制语义。
    """
    包表 = 包表 if 包表 is not None else 枚举正式包(系统根)
    基线 = 载入基线(参考目录 if 参考目录 is not None else Path(系统根))
    事实 = 判定登记完整性(系统根, 注册表=注册表, 存储目录=存储目录, 包表=包表)
    缺登记键 = [关系键(项) for 项 in 事实["未登记清单"]]
    基线集 = set(基线["关系基线"])
    提供包集 = set(基线["提供包基线"])
    现提供包 = {项["提供包"] for 项 in 枚举消费者关系(系统根, 包表) if 项["提供包"]}
    新增提供包 = sorted(现提供包 - 提供包集)
    新增缺登记 = [键 for 键 in 缺登记键 if 键 not in 基线集]
    基线内缺登记数 = len(缺登记键) - len(新增缺登记)
    问题表: list[str] = []
    if 基线["问题"]:
        问题表.append(f"{基线['问题']}（基线未生效，按全量判红）")
    if 新增提供包:
        问题表.append(f"新增公开能力包未进基线 {len(新增提供包)} 个: {新增提供包[:5]}")
    if 新增缺登记:
        问题表.append(
            f"基线外真实跨包消费者关系缺登记 {len(新增缺登记)} 条"
            f"（新增即必须登记，不许静默放进注册表空白区）: {新增缺登记[:5]}")
    通过 = not 问题表
    return {
        "通过": 通过,
        "基线来源": 基线["来源"],
        "基线关系数": len(基线集),
        "基线提供包数": len(提供包集),
        "现存关系数": 事实["总关系数"],
        "现存提供包数": len(现提供包),
        "缺登记总数": len(缺登记键),
        "基线内缺登记数": 基线内缺登记数,
        "新增缺登记数": len(新增缺登记),
        "新增缺登记清单": 新增缺登记[:清单上限],
        "新增提供包清单": 新增提供包[:清单上限],
        "判定说明": "；".join(问题表) if 问题表 else
                  f"无新增缺登记（现存 {事实['总关系数']} 条关系，"
                  f"存量缺登记 {基线内缺登记数} 条只报不拦）",
        "事实": {k: v for k, v in 事实.items() if k not in ("未登记清单", "缺字段能力")},
    }


def 生成基线(系统根: Path, *, 注册表=None, 存储目录: str = "",
            包表: dict[str, dict] | None = None) -> dict:
    """按现场事实生成基线（**已登记的关系不进基线**：基线只承载存量债务）。"""
    包表 = 包表 if 包表 is not None else 枚举正式包(系统根)
    事实 = 判定登记完整性(系统根, 注册表=注册表, 存储目录=存储目录, 包表=包表)
    关系 = 枚举消费者关系(系统根, 包表)
    return {
        "契约版本": "消费者关系基线/v1",
        "说明": ("跨包消费者关系存量基线（只减不增）：基线内缺登记只报不拦，"
               "基线外关系缺登记及新增公开能力包一律判红。"
               "重新生成会覆盖本文件，生成前须确认现场登记已完。" ),
        "计数": {
            "现存关系数": 事实["总关系数"],
            "已登记关系数": 事实["已登记关系数"],
            "缺登记关系数": 事实["未登记关系数"],
            "提供包数": len({项["提供包"] for 项 in 关系 if 项["提供包"]}),
        },
        "关系基线": sorted(关系键(项) for 项 in 事实["未登记清单"]),
        "提供包基线": sorted({项["提供包"] for 项 in 关系 if 项["提供包"]}),
    }


def 登记消费者契约集(系统根: Path, *, 注册表=None, 存储目录: str = "",
                    包表: dict[str, dict] | None = None,
                    只报: bool = False) -> dict:
    """按现场枚举把**字段齐备**的跨包消费者关系批量登记成消费者契约（幂等）。

    为什么收进包内而不是留一个一次性脚本：填表是这条判据的**正规落地动作**，
    按 1.6「临时脚本不留库」不能留在正式目录里当散件；收成本模块的一个函数，
    测试与门禁都能直接调用同一条实现，不会出现「脚本版」与「能力版」两套行为。

    口径：
    - 只登记 `取能力契约` 判为齐备的关系；字段取不到的关系**跳过**（登记半份契约
      等于给漂移门禁塞假证据），跳过清单如实返回；
    - 已登记的不重复写（注册表侧同一消费者同一能力本就是覆盖写，先查后写只省一次写）；
    - `只报=True` 时不写盘，只回带将要登记/跳过的清单。
    """
    from 平台控制面.能力目录.消费者契约注册表 import 消费者契约注册表

    包表 = 包表 if 包表 is not None else 枚举正式包(系统根)
    if 注册表 is None:
        from 平台控制面.能力目录.实现.能力入口 import 默认存储目录

        注册表 = 消费者契约注册表.取实例(Path(存储目录 or 默认存储目录))
    已登记 = 0
    新登记 = 0
    失败: list[str] = []
    跳过: list[dict] = []
    for 项 in 枚举消费者关系(系统根, 包表):
        鉴定 = 取能力契约(包表, 项["能力id"])
        if 鉴定["缺项"]:
            跳过.append({"能力id": 项["能力id"], "消费者包": 项["消费者包"],
                       "缺项": list(鉴定["缺项"])})
            continue
        现有 = 注册表.查询契约(项["能力id"])
        记录表 = list(现有.get("数据") or []) if 现有.get("成功") else []
        标识 = 消费者id(项["消费者id"])
        if any(记录.get("消费者id") == 标识 for 记录 in 记录表):
            已登记 += 1
            continue
        if 只报:
            新登记 += 1
            continue
        结果 = 注册表.登记契约(标识, 项["能力id"], 鉴定["当前契约"])
        if 结果.get("成功"):
            新登记 += 1
        else:
            失败.append(f"{项['能力id']} <- {项['消费者包']}: "
                      f"{结果.get('消息') or 结果.get('错误码')}")
    return {"已在册": 已登记, "新登记": 新登记, "失败": 失败, "跳过清单": 跳过,
            "跳过数": len(跳过), "只报": bool(只报)}


