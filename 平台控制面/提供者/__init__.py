包id = "平台控制面.提供者"


def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本提供者面的公开能力。

    注册参数与 `能力定义.json` 逐条对应（参数名与顺序一致）；实现层只做边界校验
    与结果归一，真实语义仍在同包提供者本体里。
    """
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.提供者.采样资源",
        包id=包id,
        实现函数=采样资源,
        参数=[{"名称": "临时目录", "类型": "文本型"}],
        返回="结果",
        说明="真实采样当前进程资源（内存峰值/文件句柄/临时空间）并合并资源监督执行单元峰值。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.提供者.审计平台控制面",
        包id=包id,
        实现函数=审计平台控制面,
        参数=[{"名称": "目标目录", "类型": "文本型"}],
        返回="结果",
        说明="治理面专属依赖防火墙静态审计：动态导入/反射导入/深入实现目录/直连外部服务四类规则。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.提供者.只读激活指针",
        包id=包id,
        实现函数=只读激活指针,
        参数=[{"名称": "存储目录", "类型": "文本型"},
              {"名称": "指针id", "类型": "文本型"}],
        返回="结果",
        说明="控制面不可用时的调用面只读视图：只读打开权威状态库取激活指针，未命中如实返回。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
