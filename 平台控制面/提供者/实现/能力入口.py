"""平台控制面·提供者能力实现（能力边界层）。

本模块是 `平台控制面.提供者` 正式包的能力实现层：把同包提供者本体
（`采样器.py` / `防火墙审计.py` / `控制面对账.py`）的对外动作包成**统一结果契约**
的公开能力，本层只做参数校验与结果归一，真实语义仍在提供者本体里。

对外三条能力（机器可读定义见同目录上级 `能力定义.json`）：

- `采样资源`：真实采样内存峰值 / 文件句柄 / 临时空间，并合并资源监督执行单元峰值。
- `审计平台控制面`：治理面专属依赖防火墙（动态导入 / 反射导入 / 深入实现目录 /
  直连外部服务四类规则）静态审计。
- `只读激活指针`：控制面不可用时的调用面只读视图（只读打开权威状态库，
  不启动统一能力服务、不执行结构迁移）。

边界口径（不做的承诺）：
- 不做默认值兜底、不做静默降级：参数形态不符、目录不可用一律明确失败；
- 不重复登记子包能力：动态库与提供者注册表由子包 `动态库提供者` / `注册表`
  各自的声明与注册函数承担，本模块不越权代管。
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from 公共契约.运行时.运行缓存 import 解析运行缓存根

来源名称 = "提供者"
# 存储目录缺省值：经唯一解析器取运行态存储根（源码态 = `<系统根>/工程缓存/平台控制面`，
# 与旧的裸相对值同义；制品态 = 平台受管缓存）。裸相对路径在制品态会把运行态写进制品。
默认存储目录 = str(解析运行缓存根(Path(__file__).resolve().parents[3]) / "平台控制面")
本包目录 = Path(__file__).resolve().parents[1]
系统根目录 = 本包目录.parents[1]
平台控制面目录 = 本包目录.parent


def 默认审计目录() -> Path:
    """治理面审计默认目标：平台控制面目录（本面唯一的治理对象）。"""
    return 平台控制面目录


def 解析存储目录(存储目录: str) -> Path:
    """存储目录归一：留空取平台默认目录，相对路径按平台根解析（不随进程工作目录漂移）。"""
    文本 = str(存储目录 or "").strip() or 默认存储目录
    路径 = Path(文本)
    return 路径 if 路径.is_absolute() else (系统根目录 / 路径)


def 采样资源(临时目录: str = "") -> Any:
    """真实采样当前进程资源（内存峰值/文件句柄/临时空间），并合并监督单元峰值。"""
    from 公共契约.基础类型.结果类型 import 结果

    目录文本 = str(临时目录 or "").strip()
    if 目录文本 and not Path(目录文本).is_dir():
        return 结果.失败("参数不合法", f"临时目录不存在或不可读: {目录文本}",
                        来源=来源名称)
    from 平台控制面.提供者.采样器 import 组合报告

    报告 = 组合报告(None, 目录文本 or None)
    if not 报告.get("成功"):
        return 结果.失败("采样失败", str(报告.get("错误说明") or "资源采样失败"),
                        来源=来源名称)
    return 结果.成功结果({
        "内存峰值MB": 报告["内存峰值MB"],
        "文件句柄数": 报告["文件句柄数"],
        "临时空间字节": 报告["临时空间字节"],
        "线程峰值": 报告["线程峰值"],
        "并发峰值": 报告["并发峰值"],
        "队列峰值": 报告["队列峰值"],
        "采样时间": 报告["采样时间"],
    })


def 审计平台控制面(目标目录: str = "") -> Any:
    """治理面专属依赖防火墙：静态审计目标目录下全部 .py（只读，不改被审计文件）。"""
    from 公共契约.基础类型.结果类型 import 结果

    目录文本 = str(目标目录 or "").strip()
    目录 = Path(目录文本) if 目录文本 else 默认审计目录()
    if not 目录.is_dir():
        return 结果.失败("目录不可用", f"审计目标目录不存在或不可读: {目录}",
                        来源=来源名称)
    from 运行核心.依赖防火墙 import 审计结果转清单
    from 平台控制面.提供者.防火墙审计 import 审计平台控制面 as 执行治理面审计

    审计 = 执行治理面审计(目录)
    清单 = 审计结果转清单(审计)
    if not 审计.审计文件数:
        # 恒真面收口（2026-09-16）：目录存在但一个 .py 都没有时，`无违规=true` 是
        # **空集恒真**——什么都没审就发绿，任何只断言 `无违规=true` 的调用方都会被骗。
        # 空树不构成证据，按契约既有错误码 目录不可用 明确失败（不做默认值兜底、
        # 不静默降级）。
        return 结果.失败("目录不可用", f"审计目标目录不含可审计 .py 文件: {目录}",
                        来源=来源名称)
    return 结果.成功结果({
        "审计文件数": int(审计.审计文件数),
        "违规数": len(审计.违规列表),
        "违规清单": 清单,
        "无违规": not 审计.违规列表,
    })


def 只读激活指针(存储目录: str = "", 指针id: str = "") -> Any:
    """控制面不可用时的调用面只读视图：只读打开权威状态库取激活指针。"""
    from 公共契约.基础类型.结果类型 import 结果

    标识 = str(指针id or "").strip()
    if not 标识:
        return 结果.失败("参数不合法", "指针id不能为空", 来源=来源名称)
    目录 = 解析存储目录(存储目录)
    from 平台控制面.提供者.控制面对账 import 只读激活指针 as 只读激活指针本体

    import sqlite3
    try:
        指针 = 只读激活指针本体(目录, 标识)
    except (OSError, sqlite3.Error) as 错误:
        return 结果.失败("存储目录不可用", f"只读打开权威状态库失败：{错误}",
                        来源=来源名称)
    if 指针 is None:
        return 结果.成功结果({"指针": None, "是否命中": False})
    return 结果.成功结果({"指针": 指针, "是否命中": True})
