def 默认审计目录() -> Path:
    """治理面审计默认目标：平台控制面目录（本面唯一的治理对象）。"""
    return 平台控制面目录


def 解析存储目录(存储目录: str) -> Path:
    """存储目录归一：留空取平台默认目录，相对路径按平台根解析（不随进程工作目录漂移）。

    「相对 → 绝对」一律转调 `公共契约.运行时.平台适配.解析路径`（全平台唯一那条腿），
    生效根取本模块唯一推导的 `系统根目录` —— **本函数不自带 `is_absolute()` 分支。**
    """
    文本 = str(存储目录 or "").strip() or 默认存储目录
    return Path(解析路径(文本, 系统根目录))


def 采样资源(临时目录: str = "") -> Any:
    """真实采样当前进程资源（内存峰值/文件句柄/临时空间），并合并监督单元峰值。"""
    from 公共契约.基础类型.结果类型 import 结果

    目录文本 = str(临时目录 or "").strip()
    if 目录文本 and not Path(目录文本).is_dir():
        return 结果.失败("参数不合法", f"临时目录不存在或不可读: {目录文本}",
                        来源=来源名称)
    from 平台控制面.提供者.采样器 import 组合报告

    报告 = 组合报告(None, 目录文本 or None)
    if not 报告.get("成功"):
        return 结果.失败("采样失败", str(报告.get("错误说明") or "资源采样失败"),
                        来源=来源名称)
    return 结果.成功结果({
        "内存峰值MB": 报告["内存峰值MB"],
        "文件句柄数": 报告["文件句柄数"],
        "临时空间字节": 报告["临时空间字节"],
        "线程峰值": 报告["线程峰值"],
        "并发峰值": 报告["并发峰值"],
        "队列峰值": 报告["队列峰值"],
        "采样时间": 报告["采样时间"],
    })


def 采样整机内存() -> Any:
    """读本机（整机）物理内存占用：物理总量/已用/可用/使用率。

    **为什么单列一条能力（2026-09-21）**：`采样资源` 把内存/句柄/临时空间捆在一起，
    实测 291 毫秒（临时空间遍历 2.18 GB）—— 资源闸门与 HTML 黑盒验收要的是
    **原子的**、微秒级的整机水位读数，捆在一起就没法用。本能力只做一件事，
    实测 14.2 微秒（纯系统调用，无子进程）。

    口径与 `采样资源` 里的内存项**不是同一个东西**，两者不混用：
    本能力是**整机**（物理总量减可用），`采样资源.内存峰值MB` 是**本进程** getrusage 峰值。
    """
    from 公共契约.基础类型.结果类型 import 结果

    from 平台控制面.提供者.采样器 import 采样整机内存 as 采样整机内存本体

    采样 = 采样整机内存本体()
    if not 采样.get("成功"):
        return 结果.失败(str(采样.get("错误码") or "采样失败"),
                        str(采样.get("错误说明") or "整机内存采样失败"),
                        来源=来源名称)
    return 结果.成功结果({
        "物理字节": 采样["物理字节"],
        "已用字节": 采样["已用字节"],
        "可用字节": 采样["可用字节"],
        "使用率": 采样["使用率"],
    })


def 读取整机内存水位() -> Any:
    """**读整机内存水位快照**（定时器 30 秒采一次；本能力只读缓存，零系统调用）。

    **为什么与 `采样整机内存` 分成两条能力**（华哥 2026-09-21 裁决）：
    > 其实访问内存的这个快照，你可以做一个计时器，大概 30 秒采样一次。然后这个监控器
    > 就直接读文本就行了。不然一直请求内存，也是个麻烦事。

    采样是**低频事实**（一条 30 秒周期的定时线程负责），判据/监控是**高频读**（只读快照）。
    两条能力各司其职：`采样整机内存` = 立即采一次（诊断/验收用），
    本能力 = 读现成快照（监控器、闸门、HTML 面板用）。
    快照里带 `快照年龄秒` 与 `快照陈旧`，读的人自己知道数据新不新鲜（不许拿旧数据冒充实时）。

    快照不可用（采样失败且从未成功过）时**明确失败** `内存读数不可用`，不返回一堆 0。
    """
    from 公共契约.基础类型.结果类型 import 结果

    from 公共契约.运行时.资源水位 import 读取整机内存水位 as 读水位快照

    快照 = 读水位快照()
    if not 快照.get("支持"):
        return 结果.失败("内存读数不可用",
                        f"整机内存水位快照不可用：{快照.get('原因') or '未知原因'}"
                        f"（已采样 {快照.get('采样次数')} 次，失败 {快照.get('采样失败次数')} 次）",
                        来源=来源名称)
    return 结果.成功结果({
        "支持": 快照["支持"],
        "物理字节": int(快照["物理字节"]),
        "已用字节": int(快照["已用字节"]),
        "可用字节": int(快照["可用字节"]),
        "占用率": round(float(快照["占用率"]), 4),
        "快照年龄秒": 快照["快照年龄秒"],
        "快照陈旧": 快照["快照陈旧"],
        "采样次数": int(快照["采样次数"]),
        "采样失败次数": int(快照["采样失败次数"]),
        "采样周期秒": 快照["采样周期秒"],
        "快照陈旧阈值秒": 快照["快照陈旧阈值秒"],
        "依据": 快照["依据"],
        "原因": 快照["原因"],
    })


def 整机内存水位超限(阈值: Any = None) -> Any:
    """**整机内存水位判定**（读缓存快照，不采样）：返回是否超限、说明与快照事实。

    **这是 80% 闸门的公开判据入口**（华哥 2026-09-21：「我不是有个资源控制吗？就是内存
    最高容量是 80%；超过的话没有做限制吗？」）：能力调用准入（`运行核心/能力调用/超时执行`）
    与监控器用的是**同一份**判定（唯一实现 `公共契约.运行时.资源水位`），本能力只是把
    它开放给 HTML/调用方，让「闸门为什么拦我」可以被直接问出来。

    参数 `阈值` 留空取平台默认 `整机内存水位阈值`（0.8）；给出时必须落在 0 到 1 之间
    （开区间）—— 越界或非数值一律 `参数不合法`，不做静默夹取。
    快照不可用或陈旧时**不判超限**（返回失败 `内存读数不可用` 并写明原因），
    既不把「没数据」伪装成超限，也不伪装成正常。
    """
    from 公共契约.基础类型.结果类型 import 结果

    from 公共契约.运行时.资源水位 import 整机内存水位超限 as 判水位, 整机内存水位阈值

    if 阈值 is None:
        用阈值 = float(整机内存水位阈值)
    elif isinstance(阈值, bool) or not isinstance(阈值, (int, float)):
        return 结果.失败("参数不合法", "阈值必须是 0 到 1 之间的数值（双精度数型）",
                        来源=来源名称)
    else:
        用阈值 = float(阈值)
        if not 0.0 < 用阈值 < 1.0:
            return 结果.失败("参数不合法",
                            f"阈值必须在 0 到 1 之间（开区间），收到 {阈值!r}", 来源=来源名称)
    超限, 说明, 快照 = 判水位(用阈值)
    if not 快照.get("支持") or 快照.get("快照陈旧"):
        return 结果.失败("内存读数不可用", 说明, 来源=来源名称)
    return 结果.成功结果({
        "超限": 超限,
        "说明": 说明,
        "阈值": 用阈值,
        "占用率": round(float(快照["占用率"]), 4),
        "物理字节": int(快照["物理字节"]),
        "已用字节": int(快照["已用字节"]),
        "可用字节": int(快照["可用字节"]),
        "快照年龄秒": 快照["快照年龄秒"],
        "采样周期秒": 快照["采样周期秒"],
    })


def 水位采样定时器(动作: Any = None, 周期秒: Any = None) -> Any:
    """**整机内存水位采样定时器**：启动 / 停止 / 查状态（有界：全局只允许一条采样线程）。

    为什么要把它开放成能力（华哥 2026-09-21「都封装成 html 可以调用的 py 脚本」）：
    采样线程是常驻资源，它「在不在跑、周期多少、采了多少次、失败几次、快照多新」
    必须能被平台外部的监控面板（HTML）直接问到并控制，而不是只能靠终端里的 Python 进程内调用。

    `动作` 取值 `启动` / `停止` / `状态`（留空按 `状态`，只读不改变任何东西）；
    非法动作 `参数不合法`。`周期秒` 只在 `启动` 时生效，留空取 `采样周期秒`（30 秒），
    必须大于 0。
    """
    from 公共契约.基础类型.结果类型 import 结果

    from 公共契约.运行时.资源水位 import (
        停止采样定时器, 启动采样定时器, 读取整机内存水位, 采样周期秒,
    )

    动作值 = str(动作 or "").strip() or "状态"
    if 动作值 not in ("启动", "停止", "状态"):
        return 结果.失败("参数不合法",
                        f"动作必须是 启动 / 停止 / 状态 之一，收到 {动作!r}", 来源=来源名称)
    用周期 = float(采样周期秒)
    if 周期秒 is not None:
        if isinstance(周期秒, bool) or not isinstance(周期秒, (int, float)) or float(周期秒) <= 0:
            return 结果.失败("参数不合法", f"周期秒必须大于 0，收到 {周期秒!r}", 来源=来源名称)
        用周期 = float(周期秒)
    本次启动 = 假
    本次停止 = 假
    if 动作值 == "启动":
        本次启动 = 启动采样定时器(用周期)
    elif 动作值 == "停止":
        本次停止 = 停止采样定时器()
    快照 = 读取整机内存水位(自动启动定时器=(动作值 == "状态"))
    return 结果.成功结果({
        "动作": 动作值,
        "本次启动": 本次启动,
        "本次停止": 本次停止,
        "周期秒": 用周期,
        "采样次数": int(快照.get("采样次数", 0)),
        "采样失败次数": int(快照.get("采样失败次数", 0)),
        "快照年龄秒": 快照.get("快照年龄秒"),
        "快照陈旧": 快照.get("快照陈旧"),
        "支持": 快照.get("支持"),
    })


def 取消登记快照() -> Any:
    """**调用取消登记快照**：在册调用与取消留痕的有界只读视图（断连即回收的可观测面）。

    为什么要有（华哥 2026-09-21「整条链路弄干净」）：网关在连接断开时置取消令牌、
    正在跑的原子能力（如 `执行命令`）在 ≤50 毫秒内整组回收子进程 —— 这件事必须可被
    平台外部看到证据：`在册` 是当前还没结束的调用，`留痕` 是历史取消记录（有界 200 条）。
    验收「断连即回收」时，HTML 面板据本能力核对留痕条数与原因，而不是只看一句成功。
    """
    from 公共契约.基础类型.结果类型 import 结果

    try:
        from 公共契约.运行时.取消登记 import 在册快照, 留痕快照

        在册 = 在册快照()
        留痕 = 留痕快照()
    except Exception as 错误:  # noqa: BLE001 - 快照构造失败必须明确失败，不许返回空表冒充「无取消」
        return 结果.失败("内部错误", f"取消登记快照构造失败 {type(错误).__name__}: {错误}",
                        来源=来源名称)
    return 结果.成功结果({
        "在册条数": int(在册.get("在册条数", 0)),
        "在册上限": int(在册.get("上限", 0)),
        "在册": 在册.get("条目", []),
        "留痕条数": len(留痕),
        "留痕": 留痕,
    })


def 审计平台控制面(目标目录: str = "") -> Any:
    """治理面专属依赖防火墙：静态审计目标目录下全部 .py（只读，不改被审计文件）。"""
    from 公共契约.基础类型.结果类型 import 结果

    目录文本 = str(目标目录 or "").strip()
    目录 = Path(目录文本) if 目录文本 else 默认审计目录()
    if not 目录.is_dir():
        return 结果.失败("目录不可用", f"审计目标目录不存在或不可读: {目录}",
                        来源=来源名称)
    from 运行核心.依赖防火墙 import 审计结果转清单
    from 平台控制面.提供者.防火墙审计 import 审计平台控制面 as 执行治理面审计

    审计 = 执行治理面审计(目录)
    清单 = 审计结果转清单(审计)
    if not 审计.审计文件数:
        # 恒真面收口（2026-09-16）：目录存在但一个 .py 都没有时，`无违规=true` 是
        # **空集恒真**——什么都没审就发绿，任何只断言 `无违规=true` 的调用方都会被骗。
        # 空树不构成证据，按契约既有错误码 目录不可用 明确失败（不做默认值兜底、
        # 不静默降级）。
        return 结果.失败("目录不可用", f"审计目标目录不含可审计 .py 文件: {目录}",
                        来源=来源名称)
    return 结果.成功结果({
        "审计文件数": int(审计.审计文件数),
        "违规数": len(审计.违规列表),
        "违规清单": 清单,
        "无违规": not 审计.违规列表,
    })


def 只读激活指针(存储目录: str = "", 指针id: str = "") -> Any:
    """控制面不可用时的调用面只读视图：只读打开权威状态库取激活指针。"""
    from 公共契约.基础类型.结果类型 import 结果

    标识 = str(指针id or "").strip()
    if not 标识:
        return 结果.失败("参数不合法", "指针id不能为空", 来源=来源名称)
    目录 = 解析存储目录(存储目录)
    from 平台控制面.提供者.控制面对账 import 只读激活指针 as 只读激活指针本体

    import sqlite3
    try:
        指针 = 只读激活指针本体(目录, 标识)
    except (OSError, sqlite3.Error) as 错误:
        return 结果.失败("存储目录不可用", f"只读打开权威状态库失败：{错误}",
                        来源=来源名称)
    if 指针 is None:
        return 结果.成功结果({"指针": None, "是否命中": 假})
    return 结果.成功结果({"指针": 指针, "是否命中": 真})
