"""授权会话重启恢复辅助：重启后按持久化角色授予策略恢复会话。

会话表是内存态（实例重启即失）；角色授予表是持久化权威事实
（身份/所有者/项目范围/角色/授予者/有效期/撤销状态/证据）。

恢复策略：重新注册身份（默认最低角色）→ 读取持久化已授予角色
集合 → 切换到其中最高等级角色；无任何有效授予则保持普通用户。
切换失败（已撤销/过期/范围不匹配）只降级为普通用户，会话仍可用。
恢复出的会话与普通注册无差异，后续鉴权走同一 校验操作 路径。
"""
from __future__ import annotations

from 平台控制面.授权 import 普通用户, 角色等级


def 恢复会话(授权服务, 身份id: str, 项目范围: str = "") -> tuple[bool, str, str, str]:
    """重启后恢复会话：返回 (成功, 消息, 令牌, 角色)。

    按策略恢复：重新注册 → 从持久化角色授予表取已授予集合 →
    切换到最高等级角色（引导授予/正式授予都走同一持久化表）。
    """
    令牌 = 授权服务.注册身份(身份id=身份id)
    已授予 = 授权服务.已授予角色(身份id, 项目范围)
    目标角色 = max(已授予, key=lambda 角色: 角色等级.get(角色, 1)) if 已授予 else 普通用户
    if 目标角色 != 普通用户:
        成功, 消息 = 授权服务.切换角色(令牌, 目标角色, 项目范围)
        if 成功:
            return True, f"会话已恢复（角色:{目标角色}，来源:持久化角色授予表）", 令牌, 目标角色
        return True, f"会话已恢复（降级:{普通用户}，{目标角色} 不可用:{消息}）", 令牌, 普通用户
    return True, "会话已恢复（仅普通用户，无持久化授予）", 令牌, 普通用户
