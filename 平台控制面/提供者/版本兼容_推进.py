"""核心双版本状态兼容·推进（双读/切换）。由 版本兼容 组合使用。"""
from __future__ import annotations

import time
from typing import Any, Callable

from 平台控制面.提供者.版本兼容_版本 import 版本在范围内
from 平台控制面.核心快照 import 核心快照管理


class 版本兼容推进:
    def 双读(self, *, 迁移id: str, 新状态版本: str,
             旧核心实例: 核心快照管理 | None = None,
             新核心实例: 核心快照管理 | None = None) -> dict:
        """双读：旧/新核心双实例读同一状态存储，读到同一份新快照记录。

        旧核心兼容窗口：旧核心快照声明的状态兼容范围必须覆盖新状态版本，
        否则旧核心无法读取新状态，双读阶段失败且不推进。
        """
        迁移 = self._读迁移(迁移id)
        if 迁移 is None:
            return {"成功": False, "错误": "迁移不存在"}
        if 迁移["阶段"] != "扩展":
            return {"成功": False,
                    "错误": f"阶段不允许: 当前 {迁移['阶段']}，双读 只能从 扩展 推进"}
        旧快照 = self.读取快照(迁移["旧快照id"])
        if 旧快照 is None:
            return {"成功": False, "错误": "旧快照不存在"}
        # 旧核心兼容窗口：旧快照状态兼容范围必须覆盖新状态版本
        旧范围 = 旧快照["状态兼容"]
        if not 版本在范围内(新状态版本, 旧范围):
            return {"成功": False, "阶段": "扩展", "兼容窗口": False,
                    "错误": f"旧核心不在兼容窗口: 旧快照状态兼容 {旧范围} 不含 新状态版本 {新状态版本}"}
        # 双实例读同一存储：两个独立状态实例指向同一权威状态库 + 同一快照根目录
        from 平台控制面.平台状态 import 平台状态
        内部创建 = 旧核心实例 is None and 新核心实例 is None
        旧实例 = 旧核心实例 or 核心快照管理(
            平台状态(self.状态.存储目录, 项目id=self.状态.项目id),
            快照根目录=self.快照.快照根目录)
        新实例 = 新核心实例 or 核心快照管理(
            平台状态(self.状态.存储目录, 项目id=self.状态.项目id),
            快照根目录=self.快照.快照根目录)
        try:
            同一存储 = (旧实例.状态.数据库路径 == 新实例.状态.数据库路径
                       == self.状态.数据库路径)
            旧读新快照 = 旧实例.状态.读取记录("核心快照", "快照id", 迁移["新快照id"])
            新读新快照 = 新实例.状态.读取记录("核心快照", "快照id", 迁移["新快照id"])
            一致 = (旧读新快照 is not None and 旧读新快照 == 新读新快照)
            if not (同一存储 and 一致):
                return {"成功": False, "阶段": "扩展",
                        "错误": "双实例未读到同一份状态记录（同一存储要求不满足）"}
        finally:
            if 内部创建:
                旧实例.状态.关闭()
                新实例.状态.关闭()
        迁移["阶段"] = "双读"
        迁移["新状态版本"] = 新状态版本
        self._写迁移(迁移)
        证据id = self._证据(迁移, {"新状态版本": 新状态版本, "同一存储": 同一存储,
                                 "旧快照状态兼容": 旧范围}, "双读")
        return {"成功": True, "迁移id": 迁移id, "阶段": "双读",
                "同一存储": 同一存储, "兼容窗口": True,
                "旧核心读取": {"快照id": 旧读新快照["快照id"]},
                "新核心读取": {"快照id": 新读新快照["快照id"]},
                "状态": 迁移, "证据id": 证据id}

    def 切换(self, *, 迁移id: str, 健康检查: Callable[[], bool]) -> dict:
        """切换：新快照真实校验 + 状态兼容范围匹配 + 健康检查 + CAS 指针切换。

        失败路径：兼容范围不匹配阻止切换；健康检查失败切换中止并回退旧指针。
        """
        迁移 = self._读迁移(迁移id)
        if 迁移 is None:
            return {"成功": False, "错误": "迁移不存在"}
        if 迁移["阶段"] != "双读":
            return {"成功": False,
                    "错误": f"阶段不允许: 当前 {迁移['阶段']}，切换 只能从 双读 推进"}
        新快照 = self.读取快照(迁移["新快照id"])
        if 新快照 is None:
            return {"成功": False, "错误": "新快照不存在"}
        # 1. 新快照真实校验（Ed25519 签名 + 磁盘摘要，防伪造/篡改）
        有效, 消息 = self.快照.校验快照(快照id=迁移["新快照id"])
        if not 有效:
            return {"成功": False, "错误": f"新快照校验失败: {消息}", "阶段": "双读"}
        # 2. 状态兼容范围匹配：新快照兼容范围必须覆盖当前平台状态结构版本
        当前状态版本 = self.状态.目标版本
        if not 版本在范围内(当前状态版本, 新快照["状态兼容"]):
            证据id = self._证据(迁移, {"阻止切换": True, "当前状态版本": 当前状态版本,
                                     "新快照状态兼容": 新快照["状态兼容"]}, "切换被拒")
            return {"成功": False, "阶段": "双读", "阻止切换": True,
                    "证据id": 证据id,
                    "错误": f"状态兼容范围不匹配: 新快照 {新快照['状态兼容']} 不含 当前状态 {当前状态版本}"}
        # 3. 健康检查（真实调用）；失败 → 回退旧指针
        try:
            健康 = bool(健康检查())
        except Exception:
            健康 = False
        if not 健康:
            return self._回退(迁移, "健康检查失败")
        # 4. CAS 切换激活指针（栅栏令牌防陈旧覆盖；幂等复用）
        指针 = self.状态.读取记录("激活指针", "指针id", self.指针id)
        if 指针 is None:
            return {"成功": False, "错误": "无激活指针", "阶段": "双读"}
        幂等 = 指针["目标"] == 迁移["新快照id"]
        if not 幂等:
            成功, 消息 = self.发布.切换激活指针(
                指针id=self.指针id, 目标=迁移["新快照id"],
                期望版本=int(指针["版本"]), 期望令牌=int(指针["栅栏令牌"]))
            if not 成功:
                return {"成功": False, "错误": f"切换被拒: {消息}", "阶段": "双读"}
        新指针 = self.状态.读取记录("激活指针", "指针id", self.指针id)
        迁移["阶段"] = "切换"
        迁移["指针"] = {"目标": 新指针["目标"], "版本": int(新指针["版本"]),
                       "栅栏令牌": int(新指针["栅栏令牌"])}
        self._写迁移(迁移)
        证据id = self._证据(迁移, {"当前状态版本": 当前状态版本,
                                 "健康检查": 健康, "幂等": 幂等}, "切换")
        return {"成功": True, "迁移id": 迁移id, "阶段": "切换",
                "指针": 迁移["指针"], "状态": 迁移, "证据id": 证据id}
