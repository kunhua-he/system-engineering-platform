"""控制面停止与恢复对账：停机期间调用面只读激活指针继续；恢复后对账修复期望状态。

总补修边界：
- 控制面（统一能力服务/状态存储服务）不可用时，已激活调用面不依赖控制面
  进程，直接从持久化状态存储只读激活指针确定当前激活目标（数据库只读打开，
  不启动统一能力服务、不执行结构迁移、不注册进程）。
- 控制面恢复后对账：对比期望状态（发布记录）与实际状态（激活指针），
  以实际激活指针为准修复期望状态（发布记录），不反向改写实际指针。
- 恢复证据走证据账本追加写（INSERT 新记录），停机期间原始失败证据保留
  不被覆盖；恢复证据可选引用原始证据 id 构成可审计证据链。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

from 公共契约.运行时.数据库连接 import 打开只读


def 只读激活指针(存储目录: Path | str, 指针id: str) -> dict[str, Any] | None:
    """控制面不可用时的调用面读取：只读持久化激活指针，不依赖控制面服务。

    权威状态.db 以只读模式（mode=ro）打开，仅执行 SELECT；不启动统一能力
    服务、不执行结构迁移、不注册进程。控制面停机期间已激活调用面据此继续工作。
    """
    数据库路径 = Path(存储目录) / "权威状态.db"
    if not 数据库路径.exists():
        return None
    # 本处转调 `公共契约/运行时/数据库连接.py`，原参数 `只读库URI(数据库路径), uri=True`（**未传 timeout**）
    # → 档 打开只读（缺省超时 5.0）：原写法未显式传 timeout 时 stdlib 默认即 5.0，故逐字等价；
    # `uri=True` 与 `mode=ro` 由该档写死，不在此另拼 URI。
    连接 = 打开只读(数据库路径)
    try:
        行 = 连接.execute(
            "SELECT 指针id, 目标, 版本, 栅栏令牌, 状态 FROM 激活指针 WHERE 指针id=?",
            (指针id,)).fetchone()
    except sqlite3.OperationalError as 错误:
        # 库文件在、但「激活指针」表不存在 = 控制面从未初始化过这张表。
        # 按本能力语义（「控制面不可用时的调用面只读视图」「未命中如实返回」），
        # 这属**未命中**，不属「存储目录不可用」：后者留给真正的 IO/权限/库损坏。
        # 2026-09-17 实测：黑盒场景用受管临时根（那里只有最小库），旧实现抛
        # SQLite OperationalError 被上层包成 503，而场景期望 200 + 是否命中=false。
        if "no such table" in str(错误).lower():
            return None
        raise
    finally:
        连接.close()
    if 行 is None:
        return None
    return {"指针id": 行[0], "目标": 行[1], "版本": 行[2],
            "栅栏令牌": 行[3], "状态": 行[4]}


def 对账并记录恢复证据(状态, 发布, *, 调用者: str = "控制面恢复",
                     角色: str = "平台维护者",
                     原始证据id: str = "") -> tuple[list[str], str]:
    """控制面恢复对账：以实际激活指针为准修复期望状态，并追加恢复证据。

    对账表由 发布管理.对账() 真实计算（期望状态 vs 实际激活指针逐项核对，
    不一致以实际为准修正发布记录）；恢复证据以追加写方式记入证据账本，
    与停机期间原始失败证据共存，绝不覆盖旧记录；传入 原始证据id 时写入
    关联引用构成证据链。
    """
    对账表 = 发布.对账()
    内容 = {"对账表": 对账表,
            "修正项": [项 for 项 in 对账表 if 项.startswith("修正:")]}
    if 原始证据id:
        内容["关联原始证据"] = 原始证据id
    证据id = 状态.追加证据(类型="恢复对账", 主题="控制面", 内容=内容,
                        调用者=调用者, 角色=角色, 结果="已对账")
    return 对账表, 证据id
