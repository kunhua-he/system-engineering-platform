"""真实资源采样器提供者：内存/文件句柄/临时空间，全部来自真实系统状态。

- 采样内存(): resource.getrusage(RUSAGE_SELF).ru_maxrss 实际峰值
  （原始单位与换算系数由 平台适配.内存峰值原始单位() 给出：macOS 字节 / Linux KB，
  统一换算为 MB；不在此处自带平台判断）
- 采样文件句柄(): 枚举当前进程句柄目录实际句柄数（候选目录表由
  平台适配.句柄枚举目录表() 给出；本平台无句柄目录时明确报不支持）
- 采样临时空间(目录): os.path.getsize 对目录内全部文件求和（真实磁盘占用）
- 组合报告(监督器报告, 临时目录): 真实采样 + 资源监督器峰值（线程/并发/队列），
  供资源监督器对外报告使用。任何采样失败都如实标注，不伪装数值。

统一结果固定包含：成功、值、错误码、错误说明。
"""
from __future__ import annotations

import os
import tempfile
import time

from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.运行时 import 平台适配


def 采样内存() -> dict:
    """真实内存峰值：getrusage RU_MAXRSS 换算为 MB（原始单位见 平台适配）。

    ``resource`` 是 POSIX 专有模块（Windows 上根本不存在，顶层导入会让 import 本模块即崩），
    因此在真正取用它的本函数内惰性导入；非 POSIX 平台**显式报不支持**（抛 平台不支持错误），
    不静默返回假数值、也不静默跳过采样。原始值单位与换算系数由
    ``平台适配.内存峰值原始单位()`` 给出（macOS/BSD 字节、Linux KB）——本函数不自带
    平台判断，遇到单位无权威定义的平台由收口层抛 平台不支持错误。
    """
    平台适配.要求POSIX能力("resource 内存峰值采样（getrusage）")
    单位名, 换算除数 = 平台适配.内存峰值原始单位()
    from resource import RUSAGE_SELF, getrusage  # 惰性导入：POSIX 专有
    原始值 = getrusage(RUSAGE_SELF).ru_maxrss
    峰值MB = 原始值 / 换算除数 / 1024
    return {"成功": 真, "值": round(峰值MB, 2), "原始值": 原始值,
            "原始单位": 单位名, "错误码": "", "错误说明": ""}


def 采样文件句柄() -> dict:
    """真实文件句柄数：枚举当前进程句柄目录（候选表由 平台适配 按平台给出）。

    本平台没有句柄目录（如 Windows）时**明确报不支持**（错误码「平台不支持」），
    不报 0 冒充真实值、也不静默跳过采样。
    """
    目录表 = 平台适配.句柄枚举目录表()
    if not 目录表:
        return {"成功": 假, "值": -1, "来源": "", "错误码": "平台不支持",
                "错误说明": f"当前平台（{平台适配.当前平台()}）无进程句柄目录，不支持文件句柄采样"}
    for 目录 in 目录表:
        try:
            return {"成功": 真, "值": len(os.listdir(目录)), "来源": 目录,
                    "错误码": "", "错误说明": ""}
        except OSError:
            continue
    return {"成功": 假, "值": -1, "来源": "", "错误码": "句柄枚举失败",
            "错误说明": "无法枚举文件句柄：" + " 与 ".join(目录表) + " 均不可用"}


#: 临时空间采样的**文件数上限**（有界采样的硬闸，与
#: `启动监督器/容量基线.py::临时采样文件上限` 同口径）。
#:
#: **为什么必须有界（2026-09-18 实测的性能缺陷）**：本函数原实现对整棵目录树
#: **无界递归求和**，而调用方 `组合报告` 默认 `临时目录 = tempfile.gettempdir()`，
#: macOS 的系统临时目录是**全机共享**的。实测 `/var/folders/<…>/T`
#: **324860 个文件 / 11.2 GB**，本函数耗时 **18.9 秒**
#: ⇒ 能力 `平台控制面.提供者.采样资源` **16.78 秒**，**超过网关 20 秒转发上限**，
#: 在 HTML 黑盒验证里报成「统一返回缺字段」（现象与真因相差很远）。
#:
#: 处置与 `容量基线` 完全一致：**有界采样 + 如实标注截断**，
#: 不把有界值冒充完整占用。资源监督要的是「有没有逼近阈值」，不是「精确到字节」。
临时采样文件上限 = 20000


def 采样临时空间(目录, *, 文件上限: int | None = None) -> dict:
    """真实临时空间占用：**有界**遍历求和（字节），到上限即止并如实标注截断。

    参数：目录（临时目录路径）；文件上限（缺省取 `临时采样文件上限`）。
    返回：``{成功, 值, 文件数, 已截断, 错误码, 错误说明}``。
    ``已截断=True`` 表示「到上限就停了，真实占用 ≥ 值」，**不冒充完整值**。
    """
    上限 = int(文件上限) if 文件上限 is not None else 临时采样文件上限
    根 = os.fspath(目录)
    if not os.path.isdir(根):
        return {"成功": 假, "值": 0, "文件数": 0, "已截断": 假, "错误码": "目录不可用",
                "错误说明": f"目录不存在或不可读: {根}"}
    总字节, 文件数, 截断 = 0, 0, 假
    for 当前目录, 子目录表, 文件表 in os.walk(根):
        # 剪枝：`__pycache__` 这类派生目录不计（不是「临时空间占用」的有效信号，且数量最多）
        子目录表[:] = [名 for 名 in 子目录表 if 名 != "__pycache__"]
        for 文件名 in 文件表:
            路径 = os.path.join(当前目录, 文件名)
            try:
                总字节 += os.path.getsize(路径)
                文件数 += 1
            except OSError:
                continue  # 枚举后被删除等竞态：跳过，不伪装
            if 文件数 >= 上限:
                截断 = 真
                break
        if 截断:
            break
    return {"成功": 真, "值": 总字节, "文件数": 文件数, "已截断": 截断,
            "错误码": "", "错误说明": ""}


def 采样整机内存() -> dict:
    """整机内存占用（微秒级、单一职责）：不遍历目录、不读句柄。**立即采一次**。

    **为什么单独一个函数（2026-09-21）**：`组合报告` 把内存/句柄/临时空间捆在一起，
    实测 **291 毫秒**（临时空间遍历工程缓存 2.18 GB）—— 资源闸门与 HTML 黑盒验收
    要的是**原子的**、微秒级的整机水位读数，捆在一起就没法用。本函数只做一件事。

    **口径唯一实现在 `公共契约.运行时.资源水位`**（2026-09-21 收口）：采样与换算
    原先在本文件与 `资源监督.py` 各写一份，属「同一件事两套实现」；现在两处都只调
    `资源水位`，本函数只把快照转成历史调用方认的旧形状（成功/使用率/错误码），
    **不再自己采、不再自己算**。高频路径（每次调用都判的水位闸门）请读
    `资源水位.读取整机内存水位()`（定时器 30 秒采一次，读缓存，零系统调用）。

    返回 ``{成功, 物理字节, 已用字节, 可用字节, 使用率, 错误码, 错误说明}``。
    """
    from 公共契约.运行时.资源水位 import 采样整机内存 as 采样水位快照

    快照 = 采样水位快照()
    if not 快照.get("支持"):
        return {"成功": 假, "物理字节": int(快照.get("物理字节") or 0),
                "已用字节": 0, "可用字节": int(快照.get("可用字节") or 0), "使用率": 0.0,
                "错误码": "内存读数不可用",
                "错误说明": str(快照.get("原因") or "整机内存读数不可用")}
    物理 = int(快照["物理字节"])
    可用 = int(快照["可用字节"])
    已用 = int(快照["已用字节"])
    if 物理 <= 0 or 可用 <= 0 or 可用 > 物理:
        return {"成功": 假, "物理字节": 物理, "已用字节": 0, "可用字节": 可用, "使用率": 0.0,
                "错误码": "内存读数不可用",
                "错误说明": str(快照.get("原因") or f"物理={物理} 可用={可用}，不足以算使用率")}
    return {"成功": 真, "物理字节": 物理, "已用字节": 已用, "可用字节": 可用,
            "使用率": round(已用 / 物理, 4), "错误码": "", "错误说明": ""}


报告键表 = ("成功", "内存峰值MB", "整机内存占用MB", "整机内存占用率",
           "文件句柄数", "临时空间字节",
           "线程峰值", "并发峰值", "队列峰值", "单元表", "采样时间", "错误说明")


def 组合报告(监督器报告=None, 临时目录=None) -> dict:
    """组合资源监督器报告：真实采样（内存/句柄/临时空间）+ 监督器峰值。

    监督器报告 为 资源监督.状态报告() 的输出（单元id → 单元报告）；
    线程/并发/队列峰值取全部执行单元的最大值，内存峰值与真实采样取大。
    """
    内存 = 采样内存()
    整机 = 采样整机内存()
    句柄 = 采样文件句柄()
    临时 = 采样临时空间(临时目录 if 临时目录 is not None else tempfile.gettempdir())
    单元表 = dict(监督器报告 or {})
    if 单元表 and not all(isinstance(项, dict) for 项 in 单元表.values()):
        单元表 = {"": 单元表}  # 兼容直接传入单个执行单元报告
    峰值表 = {"线程峰值": 0, "并发峰值": 0, "队列峰值": 0, "内存峰值": 0.0}
    for 单元报告 in 单元表.values():
        for 键 in 峰值表:
            try:
                峰值表[键] = max(峰值表[键], float(单元报告.get(键, 0)))
            except (TypeError, ValueError):
                continue
    失败表 = [项["错误说明"] for 项 in (内存, 整机, 句柄, 临时) if not 项["成功"]]
    return {
        "成功": not 失败表,
        "内存峰值MB": round(max(内存["值"], 峰值表["内存峰值"]), 2),
        "整机内存占用MB": round(整机["已用字节"] / 1024 / 1024, 2),
        "整机内存占用率": 整机["使用率"],
        "文件句柄数": 句柄["值"],
        "临时空间字节": 临时["值"],
        "线程峰值": int(峰值表["线程峰值"]),
        "并发峰值": int(峰值表["并发峰值"]),
        "队列峰值": int(峰值表["队列峰值"]),
        "单元表": 单元表,
        "采样时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        "错误说明": "；".join(失败表),
    }
