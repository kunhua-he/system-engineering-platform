"""核心双版本状态兼容：迁移四步编排器（中文契约）。

开始迁移() → 扩展() → 双读() → 切换() → 清理()

每步真实推进状态机并返回四步状态证据（阶段/旧新快照/兼容范围/指针/证据id），
证据追加到权威状态证据账本（类型=版本迁移）；迁移记录持久化在 元信息 表
（键=版本迁移:{迁移id}，重启可恢复）。唯一写入口：平台状态.元信息/核心快照/激活指针。

总补修边界：
- 旧核心兼容窗口：旧核心快照声明的状态兼容范围必须覆盖新状态版本，
  双读阶段由旧/新两个核心快照管理实例读同一状态存储，读到同一份快照记录，
  旧核心在窗口内可读取新状态。
- 状态兼容范围不匹配阻止切换：新核心快照声明的状态兼容范围必须覆盖当前
  平台状态结构版本，否则拒绝切换，激活指针保持旧快照。
- 新核心失败回退旧指针：健康检查真实调用失败时切换中止，
  激活指针保持/回退到旧快照（CAS 栅栏令牌防陈旧覆盖）。
- 引用未归零禁止删除快照：清理阶段校验引用计数表，计数>0 拒绝删除，
  归零后才真实删除旧快照目录。
"""
from __future__ import annotations

import json
import shutil
import time
import uuid
from pathlib import Path
from typing import Any, Callable

from 平台控制面.核心快照 import 核心快照管理
from 平台控制面.提供者.版本兼容_版本 import 解析兼容范围, 版本在范围内
from 平台控制面.提供者.版本兼容_推进 import 版本兼容推进
from 平台控制面.提供者.版本兼容_回退 import 版本兼容回退
from 公共契约.基础类型.逻辑类型 import 真, 假


class 版本兼容(版本兼容推进, 版本兼容回退):
    """核心双版本状态兼容编排器（唯一写入口：平台状态.元信息/核心快照/激活指针）。"""

    指针id = "核心"

    def __init__(self, 状态, 快照管理: 核心快照管理, 发布管理) -> None:
        self.状态 = 状态
        self.快照 = 快照管理
        self.发布 = 发布管理

    # ---- 迁移记录（持久化在 元信息 表，重启可恢复） ----
    def _迁移键(self, 迁移id: str) -> str:
        return f"版本迁移:{迁移id}"

    def _读迁移(self, 迁移id: str) -> dict[str, Any] | None:
        记录 = self.状态.读取记录("元信息", "键", self._迁移键(迁移id))
        return json.loads(记录["值"]) if 记录 else None

    def _写迁移(self, 迁移: dict[str, Any]) -> None:
        self.状态.写入记录("元信息", {"键": self._迁移键(迁移["迁移id"]),
                                     "值": json.dumps(迁移, ensure_ascii=False)}, "键")

    def _证据(self, 迁移: dict[str, Any], 内容: dict[str, Any], 结果: str) -> str:
        return self.状态.追加证据(
            类型="版本迁移", 主题=迁移["迁移id"],
            内容={**{"迁移id": 迁移["迁移id"], "阶段": 迁移["阶段"],
                     "旧快照id": 迁移["旧快照id"], "新快照id": 迁移["新快照id"]}, **内容},
            结果=结果)

    # ---- 公开查询 ----
    def 读取快照(self, 快照id: str) -> dict[str, Any] | None:
        """读取核心快照记录（兼容窗口内旧核心同样可读新快照记录）。"""
        return self.状态.读取记录("核心快照", "快照id", 快照id)

    def 查询迁移(self, 迁移id: str) -> dict[str, Any] | None:
        """查询迁移当前状态（四步状态机进度）。"""
        return self._读迁移(迁移id)

    def 迁移证据(self, 迁移id: str) -> list[dict[str, Any]]:
        """四步状态证据：证据账本中该迁移的全部阶段证据。"""
        return self.状态.查询证据(主题=迁移id, 类型="版本迁移")

    # ---- 四步状态机：开始迁移 → 扩展 → 双读 → 切换 → 清理 ----
    def 开始迁移(self, *, 旧快照id: str, 目标版本: str,
                 状态兼容范围: str, 调用者: str = "") -> dict:
        """开始迁移：校验旧快照已签名、激活指针指向旧快照，记录迁移状态机。"""
        旧快照 = self.读取快照(旧快照id)
        if 旧快照 is None:
            return {"成功": 假, "错误": "旧快照不存在"}
        if not 旧快照["签名"]:
            return {"成功": 假, "错误": "旧快照未签名，不允许迁移"}
        指针 = self.状态.读取记录("激活指针", "指针id", self.指针id)
        if 指针 is None:
            self.状态.写入记录("激活指针", {"指针id": self.指针id, "目标": 旧快照id,
                                        "版本": 1, "栅栏令牌": 1, "状态": "激活"})
            指针 = {"指针id": self.指针id, "目标": 旧快照id, "版本": 1,
                    "栅栏令牌": 1, "状态": "激活"}
        elif 指针["目标"] != 旧快照id:
            return {"成功": 假, "错误": "激活指针目标与旧快照不一致，迁移前提不满足"}
        迁移id = uuid.uuid4().hex[:16]
        迁移 = {"迁移id": 迁移id, "阶段": "开始", "旧快照id": 旧快照id,
                "新快照id": "", "目标版本": 目标版本, "状态兼容范围": 状态兼容范围,
                "指针": {"目标": 指针["目标"], "版本": int(指针["版本"]),
                         "栅栏令牌": int(指针["栅栏令牌"])},
                "开始时间": time.strftime("%Y-%m-%d %H:%M:%S")}
        self._写迁移(迁移)
        证据id = self._证据(迁移, {"目标版本": 目标版本, "状态兼容范围": 状态兼容范围}, "开始")
        return {"成功": 真, "迁移id": 迁移id, "阶段": "开始",
                "状态": 迁移, "指针": 迁移["指针"], "证据id": 证据id}

    def 扩展(self, *, 迁移id: str, 运行核心版本: str, 前端核心版本: str,
             后端核心版本: str, 状态兼容范围: str | None = None, 回滚许可: bool = 真,
             迁移方式: str = "双读", 文件表: dict[str, str] | None = None,
             私钥PEM: str = "", 发布者: str = "") -> dict:
        """扩展：真实创建新核心快照（文件表内容与旧快照不同）并签名；双快照磁盘并存。"""
        迁移 = self._读迁移(迁移id)
        if 迁移 is None:
            return {"成功": 假, "错误": "迁移不存在"}
        if 迁移["阶段"] != "开始":
            return {"成功": 假,
                    "错误": f"阶段不允许: 当前 {迁移['阶段']}，扩展 只能从 开始 推进"}
        范围 = 状态兼容范围 or 迁移["状态兼容范围"]
        新快照id = self.快照.创建快照(
            运行核心版本=运行核心版本, 前端核心版本=前端核心版本,
            后端核心版本=后端核心版本, 状态兼容范围=范围,
            回滚许可=回滚许可, 迁移方式=迁移方式, 文件表=文件表)
        if 私钥PEM and 发布者:
            成功, 消息 = self.快照.签名快照(快照id=新快照id, 私钥PEM=私钥PEM, 发布者=发布者)
            if not 成功:
                return {"成功": 假, "错误": f"新快照签名失败: {消息}"}
        迁移["阶段"] = "扩展"
        迁移["新快照id"] = 新快照id
        迁移["扩展时间"] = time.strftime("%Y-%m-%d %H:%M:%S")
        self._写迁移(迁移)
        证据id = self._证据(迁移, {"新快照id": 新快照id, "运行核心版本": 运行核心版本,
                                 "状态兼容范围": 范围}, "扩展")
        双快照并存 = ((self.快照.快照根目录 / 迁移["旧快照id"]).is_dir()
                    and (self.快照.快照根目录 / 新快照id).is_dir())
        return {"成功": 真, "迁移id": 迁移id, "阶段": "扩展",
                "新快照id": 新快照id, "旧快照id": 迁移["旧快照id"],
                "双快照并存": 双快照并存, "状态": 迁移, "证据id": 证据id}

