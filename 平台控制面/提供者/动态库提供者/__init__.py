def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本提供者的公开能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.提供者.动态库提供者.调用动态库",
        包id=包id,
        实现函数=调用动态库,
        参数=[{"名称": "库名", "类型": "文本型"},
              {"名称": "函数名", "类型": "文本型"},
              {"名称": "参数表", "类型": "列表型"}],
        返回="结果",
        说明="真实加载动态库并调用已登记签名的函数；未登记签名或宿主不支持一律明确失败。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.提供者.动态库提供者.可用库列表",
        包id=包id,
        实现函数=能力可用库列表,
        参数=[],
        返回="结果",
        说明="真实探测已知系统库（sqlite3/c/system），返回库名、真实路径与可用状态。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.提供者.动态库提供者.宿主可用性",
        包id=包id,
        实现函数=能力宿主可用性,
        参数=[],
        返回="结果",
        说明="探测当前宿主能否真实提供动态库调用；不可用时状态为 HOST_UNAVAILABLE。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
