"""动态库提供者的能力实现层（能力边界，统一结果契约）。"""
from __future__ import annotations

from typing import Any

from 平台控制面.提供者.动态库提供者.动态库实现 import (
    调用 as 动态库调用,
    可用库列表 as 探测可用库表,
    宿主可用性 as 探测宿主可用性,
)

来源名称 = "动态库提供者"


def 调用动态库(库名: str = "", 函数名: str = "", 参数表: list | None = None) -> Any:
    """真实加载动态库并真实调用函数；失败按 宿主不可用 等稳定错误码透传，不伪装成功。

    成功返回**必须**包成契约声明的 `{值}` 值结构（`能力契约/参数契约.json` 值结构
    `{"值": "按登记返回类型真实转换的值"}`）；旧写法把裸标量直接当 值 返回，
    与契约声明的字典型值结构不符（2026-09-16 HTML 黑盒实测：期望 字典型/字段 值 文本型，
    实际拿到裸文本 "3.51.0"）。本层只做能力边界归一，不复制提供者本体语义。
    """
    from 公共契约.基础类型.结果类型 import 结果

    if not 库名 or not 函数名:
        return 结果.失败("参数不合法", "库名与函数名必须给齐", 来源=来源名称)
    if 参数表 is None:
        参数表 = []
    if not isinstance(参数表, (list, tuple)):
        return 结果.失败("参数不合法", "参数表必须是列表", 来源=来源名称)
    调用结果 = 动态库调用(库名, 函数名, list(参数表))
    if not 调用结果.成功:
        return 调用结果
    return 结果.成功结果({"值": 调用结果.值})


def 可用库列表() -> Any:
    """真实探测已知系统库：返回库名/真实路径/可用状态；不可用状态为 宿主不可用。"""
    from 公共契约.基础类型.结果类型 import 结果

    return 结果.成功结果({"库表": 探测可用库表()})


def 宿主可用性() -> Any:
    """探测当前宿主能否真实提供动态库调用；不可用时状态为 宿主不可用。"""
    from 公共契约.基础类型.结果类型 import 结果

    return 结果.成功结果(探测宿主可用性())
