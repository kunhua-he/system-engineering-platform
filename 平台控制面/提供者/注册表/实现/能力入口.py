"""提供者注册表的能力实现层（能力边界，统一结果契约）。

代理语义（本层唯一新增机制，理由见 说明/设计说明.md）：
调用函数是进程内可调用对象，跨能力边界无法表达；故本包把「提供者」表达为
**对目标能力的委托**——登记时给出目标能力id，委托函数经唯一能力调用入口
按能力 id 调用，真实执行仍经 资源监督器 的有界执行单元（超时/信号量/证据）。
调用入口不可用时**明确失败**（`调用入口不可用`），绝不静默降级或伪造成功。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

from 平台控制面.平台状态.状态存储 import 平台状态
from 平台控制面.资源监督 import 资源监督器
from 平台控制面.提供者.注册表.注册表实现 import 注册表
from 公共契约.运行时.运行缓存 import 解析运行缓存根

# 存储目录缺省值：经唯一解析器取运行态存储根（源码态 = `<系统根>/工程缓存/平台控制面`，
# 与旧的裸相对值同义；制品态 = 平台受管缓存）。裸相对路径在制品态会把运行态写进制品。
# 本文件为 `<系统根>/平台控制面/提供者/注册表/实现/`，故系统根 = parents[4]。
默认存储目录 = str(解析运行缓存根(Path(__file__).resolve().parents[4]) / "平台控制面")
来源名称 = "提供者注册表"

# 存储目录 → (状态, 监督器, 注册表)：同目录复用，避免每次调用重建状态库连接。
_注册表表: dict[str, tuple[平台状态, 资源监督器, 注册表]] = {}


def _取注册表(存储目录: str):
    """按存储目录取提供者注册表；目录为空即明确失败（不隐式兜底）。"""
    from 公共契约.基础类型.结果类型 import 结果

    目录 = str(存储目录 or 默认存储目录).strip()
    if not 目录:
        return None, 结果.失败("参数不合法", "存储目录不能为空", 来源=来源名称)
    条目 = _注册表表.get(目录)
    if 条目 is not None:
        return 条目[2], None
    try:
        状态 = 平台状态(Path(目录), 项目id="平台控制面")
        监督器 = 资源监督器(状态)
        实例 = 注册表(状态, 监督器)
    except (OSError, ValueError, sqlite3.Error) as 错误:
        return None, 结果.失败("存储目录不可用", f"无法打开平台权威状态库：{错误}",
                              来源=来源名称)
    _注册表表[目录] = (状态, 监督器, 实例)
    return 实例, None


def _委托函数(目标能力id: str, 调用方: str):
    """构造委托调用函数：真实执行经唯一能力调用入口按能力 id 调用目标能力。"""

    def 委托(**参数: Any) -> Any:
        from 公共契约.能力契约.调用器 import 获取能力调用器

        调用器 = 获取能力调用器()
        return 调用器.调用能力(目标能力id, 参数, 调用方=调用方)

    return 委托


def 登记提供者(存储目录: str = "", 能力id: str = "", 目标能力id: str = "",
              预算: dict | None = None) -> Any:
    """登记一个提供者（委托到目标能力）：校验预算声明并建立有界执行单元。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not 能力id or not 目标能力id or not isinstance(预算, dict):
        return 结果.失败("参数不合法", "能力id/目标能力id/预算必须给齐，预算必须是 JSON 对象",
                        来源=来源名称)
    实例, 失败 = _取注册表(存储目录)
    if 实例 is None:
        return 失败
    已登记, 消息 = 实例.注册(能力id=能力id, 调用函数=_委托函数(目标能力id, 来源名称),
                             预算=预算)
    if not 已登记:
        return 结果.失败("注册被拒绝", 消息, 来源=来源名称)
    return 结果.成功结果({"能力id": 能力id, "目标能力id": 目标能力id, "已登记": True,
                        "消息": 消息})


def 调用提供者(存储目录: str = "", 能力id: str = "", 参数: dict | None = None,
              超时秒: float = 0.0) -> Any:
    """经资源监督有界执行调用已登记提供者；目标能力失败即透传失败，不伪绿。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not 能力id:
        return 结果.失败("参数不合法", "能力id 不能为空", 来源=来源名称)
    if 参数 is not None and not isinstance(参数, dict):
        return 结果.失败("参数不合法", "参数必须是 JSON 对象", 来源=来源名称)
    实例, 失败 = _取注册表(存储目录)
    if 实例 is None:
        return 失败
    调用结果 = 实例.调用(能力id=能力id, 参数=参数 or {}, 超时秒=超时秒)
    if not 调用结果.get("成功"):
        # 注册表未登记能力返回中文码 `能力不存在`（决策 0003）：此前此处比英文码，
        # 判等恒假 → 「提供者未登记」分支从未生效，未登记一律被误报为「调用失败」。
        if str(调用结果.get("错误码")) == "能力不存在":
            return 结果.失败("提供者未登记", str(调用结果.get("消息")), 来源=来源名称)
        return 结果.失败("调用失败", str(调用结果.get("消息")), 来源=来源名称)
    值 = 调用结果.get("结果")
    # 返回形态**只有一种**（能力契约 值结构 `{能力id, 值}`）：目标能力包成 结果 时取它的 值，
    # 目标能力直接给出值时就地使用；两条路径都必须包成同一形状。
    # 旧写法在 结果 分支直接返回裸值，同一能力因目标能力形态不同而返回两种形状
    # （2026-09-16 HTML 黑盒实测：`值` 少一层 能力id 外壳，契约字段 能力id 恒缺）。
    if isinstance(值, 结果):
        if not 值.成功:
            return 结果.失败(str(值.错误码 or "调用失败"), str(值.错误说明), 来源=来源名称)
        值 = 值.值
    return 结果.成功结果({"能力id": 能力id, "值": 值})


def 查询提供者(存储目录: str = "", 能力id: str = "") -> Any:
    """查询提供者是否已登记（只读）。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not 能力id:
        return 结果.失败("参数不合法", "能力id 不能为空", 来源=来源名称)
    实例, 失败 = _取注册表(存储目录)
    if 实例 is None:
        return 失败
    return 结果.成功结果({"能力id": 能力id, "已登记": bool(实例.已注册(能力id))})


def 卸载提供者(存储目录: str = "", 能力id: str = "") -> Any:
    """卸载提供者并优雅停止其执行单元；未登记即明确失败（不伪装成功）。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not 能力id:
        return 结果.失败("参数不合法", "能力id 不能为空", 来源=来源名称)
    实例, 失败 = _取注册表(存储目录)
    if 实例 is None:
        return 失败
    if not 实例.卸载(能力id):
        return 结果.失败("提供者未登记", f"能力未登记: {能力id}", 来源=来源名称)
    return 结果.成功结果({"能力id": 能力id, "已卸载": True})
