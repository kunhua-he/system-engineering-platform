"""提供者注册表公开入口（正式包包级中文入口）。

`注册表实现.py` 是第十三阶段产出的提供者注册表本体：注册 → 授权 → 资源监督 →
真实执行 → 证据（统一结果 `{成功, 结果, 错误码, 消息, 可重试}`）。
本入口把它包成四条公开能力：`登记提供者` / `调用提供者` / `查询提供者` / `卸载提供者`。

能力化口径：调用函数是进程内可调用对象，跨能力边界不可表达；因此提供者在能力面上
表达为**对目标能力的委托**（登记时给目标能力id，执行经唯一能力调用入口），
真实执行仍经 资源监督器 的有界执行单元（信号量/超时/释放/证据）。
调用入口不可用时明确失败，绝不静默降级。

正式包边界：调用方只经唯一能力调用入口按能力 id 调用，不得深入 `实现/` 目录。
"""
from 平台控制面.提供者.注册表.注册表实现 import 注册表
from 平台控制面.提供者.注册表.实现.能力入口 import (
    登记提供者,
    调用提供者,
    查询提供者,
    卸载提供者,
    默认存储目录,
)

__all__ = [
    "注册表",
    "登记提供者",
    "调用提供者",
    "查询提供者",
    "卸载提供者",
    "默认存储目录",
    "注册能力",
]

包id = "平台控制面.提供者.注册表"


def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本提供者的公开能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.提供者.注册表.登记提供者",
        包id=包id,
        实现函数=登记提供者,
        参数=[{"名称": "存储目录", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"},
              {"名称": "目标能力id", "类型": "文本型"},
              {"名称": "预算", "类型": "字典型"}],
        返回="结果",
        说明="登记一个提供者（委托到目标能力）：校验预算声明并建立资源监督执行单元。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.提供者.注册表.调用提供者",
        包id=包id,
        实现函数=调用提供者,
        参数=[{"名称": "存储目录", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"},
              {"名称": "参数", "类型": "字典型"},
              {"名称": "超时秒", "类型": "双精度数型"}],
        返回="结果",
        说明="经资源监督有界执行调用已登记提供者；未登记或目标能力失败一律明确失败。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.提供者.注册表.查询提供者",
        包id=包id,
        实现函数=查询提供者,
        参数=[{"名称": "存储目录", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"}],
        返回="结果",
        说明="查询提供者是否已登记（只读）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.提供者.注册表.卸载提供者",
        包id=包id,
        实现函数=卸载提供者,
        参数=[{"名称": "存储目录", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"}],
        返回="结果",
        说明="卸载提供者并优雅停止其执行单元；未登记即明确失败。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
