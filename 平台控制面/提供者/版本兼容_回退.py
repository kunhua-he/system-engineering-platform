"""核心双版本状态兼容·回退与清理。由 版本兼容 组合使用。"""
from __future__ import annotations

import time
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.运行时.平台适配 import 清只读后删除树


class 版本兼容回退:
    def 回退(self, *, 迁移id: str, 原因: str = "主动回退") -> dict:
        """显式回退：激活指针 CAS 切回旧快照（新核心失败兜底，可重复调用）。"""
        迁移 = self._读迁移(迁移id)
        if 迁移 is None:
            return {"成功": 假, "错误": "迁移不存在"}
        指针 = self.状态.读取记录("激活指针", "指针id", self.指针id)
        if 指针 is None:
            return {"成功": 假, "错误": "无激活指针"}
        保持旧指针 = 指针["目标"] == 迁移["旧快照id"]
        if not 保持旧指针:
            成功, 消息 = self.发布.切换激活指针(
                指针id=self.指针id, 目标=迁移["旧快照id"],
                期望版本=int(指针["版本"]), 期望令牌=int(指针["栅栏令牌"]))
            if not 成功:
                return {"成功": 假, "错误": f"回退被拒: {消息}"}
        指针 = self.状态.读取记录("激活指针", "指针id", self.指针id)
        迁移["回退"] = {"原因": 原因, "时间": time.strftime("%Y-%m-%d %H:%M:%S")}
        self._写迁移(迁移)
        证据id = self._证据(迁移, {"回退原因": 原因, "指针目标": 指针["目标"]}, "回退")
        return {"成功": 真, "迁移id": 迁移id, "回退": 真, "指针保持旧快照": 保持旧指针,
                "指针": {"目标": 指针["目标"], "版本": int(指针["版本"]),
                         "栅栏令牌": int(指针["栅栏令牌"])}, "证据id": 证据id}

    def _回退(self, 迁移: dict[str, Any], 原因: str) -> dict:
        """切换内部失败路径：激活指针保持/切回旧快照，阶段不推进，写回退证据。"""
        指针 = self.状态.读取记录("激活指针", "指针id", self.指针id)
        if 指针 is not None and 指针["目标"] != 迁移["旧快照id"]:
            self.发布.切换激活指针(指针id=self.指针id, 目标=迁移["旧快照id"],
                                   期望版本=int(指针["版本"]), 期望令牌=int(指针["栅栏令牌"]))
        指针 = self.状态.读取记录("激活指针", "指针id", self.指针id)
        迁移["回退"] = {"原因": 原因, "时间": time.strftime("%Y-%m-%d %H:%M:%S")}
        self._写迁移(迁移)
        证据id = self._证据(迁移, {"回退原因": 原因, "指针目标": 指针["目标"]}, "回退")
        return {"成功": 假, "迁移id": 迁移["迁移id"], "阶段": 迁移["阶段"],
                "错误": f"切换失败并回退: {原因}", "回退": 真,
                "指针": {"目标": 指针["目标"], "版本": int(指针["版本"]),
                         "栅栏令牌": int(指针["栅栏令牌"])},
                "状态": 迁移, "证据id": 证据id}

    def 清理(self, *, 迁移id: str) -> dict:
        """清理：引用未归零禁止删除旧快照；归零后真实删除旧快照目录。"""
        迁移 = self._读迁移(迁移id)
        if 迁移 is None:
            return {"成功": 假, "错误": "迁移不存在"}
        if 迁移["阶段"] != "切换":
            return {"成功": 假,
                    "错误": f"阶段不允许: 当前 {迁移['阶段']}，清理 只能从 切换 推进"}
        # 引用计数检查：引用未归零禁止删除快照（拒绝同样写证据留痕）
        # 口径说明：引用计数表按「资源id@版本」记账（读取句柄生命周期，权威状态.增加引用），
        # 而核心快照记录只有快照id/核心版本、没有包清单，无法与快照逐包对齐，
        # 因此这里按全局口径判定：账本里存在任意 计数>0 即视为引用未归零，拒绝删除。
        活跃引用 = self.状态.查询记录("引用计数", "计数>0", ())
        if 活跃引用:
            引用键表 = [str(行.get("引用键") or 行.get("包id")) for 行 in 活跃引用][:10]
            证据id = self._证据(迁移, {"禁止删除": 真,
                                     "旧快照id": 迁移["旧快照id"],
                                     "活跃引用数": len(活跃引用),
                                     "活跃引用键": 引用键表}, "清理被拒")
            return {"成功": 假, "阶段": "切换", "禁止删除": 真,
                    "证据id": 证据id,
                    "错误": f"引用未归零禁止删除: {迁移['旧快照id']} 仍有 {len(活跃引用)} 条活跃引用"}
        旧目录 = self.快照.快照根目录 / 迁移["旧快照id"]
        if 旧目录.is_dir():
            # 快照目录来自制品/运行态，可能含只读条目：删除走唯一实现，失败原样抛 OSError。
            清只读后删除树(旧目录)
        已删除 = not 旧目录.exists()
        迁移["阶段"] = "清理"
        迁移["完成时间"] = time.strftime("%Y-%m-%d %H:%M:%S")
        self._写迁移(迁移)
        证据id = self._证据(迁移, {"已删除旧快照": 已删除}, "清理")
        return {"成功": 真, "迁移id": 迁移id, "阶段": "清理", "完成": 真,
                "已删除旧快照": 已删除, "状态": 迁移, "证据id": 证据id}
