"""快照校验能力实现（只读/判定）：签名验证与磁盘摘要比对的唯一实现在 核心快照管理。

分工（第 2 条 1 项 分层与归属固定）：
- `平台控制面/核心快照.py`：快照创建/签名/校验/健康检查的**唯一语义实现**；
- 本模块：能力边界参数校验、存储与快照目录取用、结果归一，不复制校验分支。

为什么只切只读/判定：`创建快照`/`签名快照` 是写类动作（落状态库 + 落快照文件），
`健康检查` 要执行调用方给的函数（影子启动）——两者都不在本轮能力面。
`校验核心快照` 会比对快照目录的实际文件摘要，**先判目录存在再构造管理器**，
避免为了「只读校验」凭空创建快照根目录。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

from 平台控制面.核心快照 import 核心快照管理
from 平台控制面.平台状态.状态存储 import 平台状态
from 运行核心.权威状态 import 版本元组
from 公共契约.运行时.运行缓存 import 解析运行缓存根

# 存储目录缺省值：经唯一解析器取运行态存储根（源码态 = `<系统根>/工程缓存/平台控制面`，
# 与旧的裸相对值同义；制品态 = 平台受管缓存）。裸相对路径在制品态会写进制品。
默认存储目录 = str(解析运行缓存根(Path(__file__).resolve().parents[3]) / "平台控制面")
默认快照根目录 = str(解析运行缓存根(Path(__file__).resolve().parents[3]) / "核心快照")
来源名称 = "快照校验"

_状态表: dict[tuple[str, str], 平台状态] = {}


def _失败(错误码: str, 说明: str):
    from 公共契约.基础类型.结果类型 import 结果

    return 结果.失败(错误码, 说明, 来源=来源名称)


def _取状态(存储目录: str, 项目id: str):
    from 公共契约.基础类型.结果类型 import 结果

    目录 = str(存储目录 or 默认存储目录).strip()
    if not 目录:
        return None, 结果.失败("参数不合法", "存储目录不能为空", 来源=来源名称)
    键 = (目录, str(项目id))
    状态 = _状态表.get(键)
    if 状态 is not None:
        return 状态, None
    try:
        状态 = 平台状态(Path(目录), 项目id=str(项目id))
    except (OSError, ValueError, sqlite3.Error) as 错误:
        return None, 结果.失败("存储目录不可用", f"无法打开平台权威状态库：{错误}",
                              来源=来源名称)
    _状态表[键] = 状态
    return 状态, None


def _读快照记录(快照id: str, 存储目录: str, 项目id: str):
    """取快照记录；返回 (记录, 错误)，记录为 None 表示未命中。"""
    状态, 失败 = _取状态(存储目录, 项目id)
    if 状态 is None:
        return None, 失败
    try:
        return 状态.读取记录("核心快照", "快照id", str(快照id)), None
    except sqlite3.Error as 错误:
        return None, _失败("读取记录失败", f"读取核心快照失败：{错误}")


def _版本在范围(目标: str, 范围文本: str) -> tuple[bool, str]:
    """判定目标版本是否落在 '下限-上限' 范围内；范围非法即明确失败。"""
    文本 = str(范围文本 or "").strip()
    if "-" not in 文本:
        return False, f"状态兼容范围格式非法（应为 下限-上限）：{文本}"
    下限文本, 上限文本 = 文本.split("-", 1)
    下限, 上限 = 下限文本.strip(), 上限文本.strip()
    if not 下限 or not 上限:
        return False, f"状态兼容范围格式非法（应为 下限-上限）：{文本}"
    目标元组 = 版本元组(目标)
    return (版本元组(下限) <= 目标元组 <= 版本元组(上限),
            f"目标版本 {目标} 不在兼容范围 {文本} 内")


def 查询核心快照(快照id: str, 存储目录: str = "", 项目id: str = ""):
    """查询一条核心快照记录（只读）：未命中返回 是否命中=False，不伪造记录。"""
    from 公共契约.基础类型.结果类型 import 结果

    标识 = str(快照id or "").strip()
    if not 标识:
        return _失败("参数不合法", "快照id不能为空")
    记录, 错误 = _读快照记录(标识, 存储目录, 项目id)
    if 错误 is not None:
        return 错误
    if 记录 is None:
        return 结果.成功结果({"记录": None, "是否命中": False})
    return 结果.成功结果({"记录": 记录, "是否命中": True})


def 校验核心快照(快照id: str, 存储目录: str = "", 快照根目录: str = "",
                项目id: str = ""):
    """校验核心快照（判定）：签名正文 + 磁盘文件摘要 + 发布者信任；只读不落盘。"""
    from 公共契约.基础类型.结果类型 import 结果

    标识 = str(快照id or "").strip()
    if not 标识:
        return _失败("参数不合法", "快照id不能为空")
    状态, 失败 = _取状态(存储目录, 项目id)
    if 状态 is None:
        return 失败
    根目录 = Path(str(快照根目录 or 默认快照根目录).strip() or 默认快照根目录)
    目录 = 根目录 / 标识
    if not 目录.is_dir():
        return 结果.成功结果({"有效": False, "说明": f"快照目录不存在: {目录}",
                              "快照目录": str(目录)})
    try:
        有效, 说明 = 核心快照管理(状态, 根目录).校验快照(快照id=标识)
    except sqlite3.Error as 错误:
        return _失败("读取记录失败", f"校验快照失败：{错误}")
    return 结果.成功结果({"有效": bool(有效), "说明": str(说明), "快照目录": str(目录)})


def 校验状态兼容范围(快照id: str, 存储目录: str = "", 目标状态结构版本: str = "",
                    项目id: str = ""):
    """校验快照的状态兼容范围与回滚许可是否覆盖目标版本（判定，不执行回滚）。"""
    from 公共契约.基础类型.结果类型 import 结果

    标识 = str(快照id or "").strip()
    if not 标识:
        return _失败("参数不合法", "快照id不能为空")
    记录, 错误 = _读快照记录(标识, 存储目录, 项目id)
    if 错误 is not None:
        return 错误
    目标 = str(目标状态结构版本 or "").strip() or 平台状态.目标版本
    if 记录 is None:
        # 「没命中不是失败」（见本包 `说明/设计说明.md` 失败如何表达一节：未命中必须与
        # 「读取失败」严格区分，否则「内部故障与被测缺陷不可区分」）。快照不存在时，对
        # 「目标版本能否回滚」的**真实回答就是否定的**，故按同包兄弟能力
        # （查询核心快照 → 是否命中=false、校验核心快照 → 有效=false）的同一口径结构化返回；
        # `读取记录失败` 只留给真正的库读错误（即上方 _读快照记录 返回的 错误）。
        return 结果.成功结果({
            "允许回滚": False,
            "说明": f"核心快照不存在: {标识}",
            "快照状态兼容范围": "",
            "目标状态结构版本": 目标,
            "回滚许可": False,
            "迁移方式": "",
        })
    兼容文本 = str(记录.get("状态兼容") or "")
    回滚许可 = str(记录.get("回滚许可") or "").strip().lower() in ("true", "1", "是")
    在范围, 原因 = _版本在范围(目标, 兼容文本)
    允许回滚 = bool(回滚许可 and 在范围)
    if not 回滚许可:
        说明 = "快照未开放回滚许可"
    elif not 在范围:
        说明 = 原因
    else:
        说明 = f"允许回滚：目标版本 {目标} 落在兼容范围 {兼容文本} 内"
    return 结果.成功结果({
        "允许回滚": 允许回滚,
        "说明": 说明,
        "快照状态兼容范围": 兼容文本,
        "目标状态结构版本": 目标,
        "回滚许可": 回滚许可,
        "迁移方式": str(记录.get("迁移方式") or ""),
    })


def 查询快照清单(限制: int = 50, 存储目录: str = "", 项目id: str = ""):
    """查询核心快照清单（只读）：按限制返回记录表与条数。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not isinstance(限制, int) or isinstance(限制, bool) or not 1 <= 限制 <= 500:
        return _失败("参数不合法", "限制必须是 1 到 500 的整数")
    状态, 失败 = _取状态(存储目录, 项目id)
    if 状态 is None:
        return 失败
    try:
        记录表 = 状态.查询记录("核心快照")
    except sqlite3.Error as 错误:
        return _失败("查询记录失败", f"查询核心快照清单失败：{错误}")
    结果表 = list(记录表)[:限制]
    return 结果.成功结果({"快照表": 结果表, "数量": len(结果表)})
