def 校验操作(令牌: str, 操作: str, 资源范围: str = "", 项目范围: str = "",
             存储目录: str = "") -> Any:
    """校验某令牌能否执行某操作：返回判定结论（默认拒绝写在 允许=False）。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not str(令牌 or "").strip():
        return 结果.失败("参数不合法", "令牌不能为空", 来源="授权")
    if not str(操作 or "").strip():
        return 结果.失败("参数不合法", "操作不能为空", 来源="授权")
    允许, 拒绝码, 会话 = 取共享授权服务(存储目录).校验操作(
        令牌=令牌, 操作=操作, 资源范围=资源范围, 项目范围=项目范围)
    return 结果.成功结果({
        "允许": 允许,
        "身份id": str(会话.get("身份id", "")) if 允许 else "",
        "角色": str(会话.get("角色", "")) if 允许 else "",
        "需要等级": int(操作最小角色.get(操作, 99)),
        # 拒绝码兜底：授权实现（平台控制面/授权.py 校验操作）已按决策 0003
        # 「对外错误只走中文」返回中文短词（会话不存在/会话过期/未知角色/角色未授予/
        # 越权操作），此处只做透传 + 缺省兜底，兜底值必须同为中文，禁止对外吐英文。
        # 「拒绝但无拒绝码」的唯一中文归属 = 越权操作（授权.py 越权拒绝分支同码）。
        "拒绝码": "" if 允许 else (稳定错误码.get(拒绝码, 拒绝码) or 稳定错误码["越权操作"]),
    })


