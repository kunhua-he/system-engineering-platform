def 注册身份(身份id: str, 所有者: str = "", 存储目录: str = "") -> Any:
    """注册一个身份（默认最低角色 普通用户），返回会话令牌。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not str(身份id or "").strip():
        return 结果.失败("参数不合法", "身份id不能为空", 来源="授权")
    令牌 = 取共享授权服务(存储目录).注册身份(身份id=身份id, 所有者=所有者)
    return 结果.成功结果({"令牌": 令牌, "身份id": 身份id, "角色": 普通用户})


def 引导授予(身份id: str, 角色: str, 授予者: str = "", 存储目录: str = "") -> Any:
    """受信引导授予：唯一受信提权路径（授予者必须是 系统引导）。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not str(身份id or "").strip():
        return 结果.失败("参数不合法", "身份id不能为空", 来源="授权")
    if not str(角色 or "").strip():
        return 结果.失败("参数不合法", "角色不能为空", 来源="授权")
    if str(授予者 or "").strip() != "系统引导":
        return 结果.失败("引导授予被拒",
                         "引导授予必须显式指定 授予者=系统引导（受信引导，非注册后门）",
                         来源="授权")
    成功, 消息 = 取共享授权服务(存储目录).引导授予(
        身份id=身份id, 角色=角色, 授予者=授予者)
    if not 成功:
        return 结果.失败("角色不可授予", 消息, 来源="授权")
    return 结果.成功结果({"身份id": 身份id, "角色": 角色})


def 授予角色(授予者令牌: str, 身份id: str, 角色: str, 项目范围: str = "",
             有效期秒: float = 86400, 存储目录: str = "") -> Any:
    """授予角色：授予者令牌须属 平台维护者/发布者。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not str(授予者令牌 or "").strip():
        return 结果.失败("参数不合法", "授予者令牌不能为空", 来源="授权")
    if not str(身份id or "").strip():
        return 结果.失败("参数不合法", "身份id不能为空", 来源="授权")
    if str(角色 or "").strip() not in 可授予角色表:
        return 结果.失败("角色不可授予", f"角色不可授予: {角色}", 来源="授权")
    成功, 消息 = 取共享授权服务(存储目录).授予角色(
        授予者令牌=授予者令牌, 身份id=身份id, 角色=角色,
        项目范围=项目范围, 有效期秒=float(有效期秒))
    if not 成功:
        return 结果.失败("越权操作", 消息, 来源="授权")
    return 结果.成功结果({"身份id": 身份id, "角色": 角色})


