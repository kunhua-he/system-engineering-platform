def 切换角色(令牌: str, 角色: str, 项目范围: str = "", 存储目录: str = "") -> Any:
    """切换会话角色：只能在该身份已授予的角色集合内切换。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not str(令牌 or "").strip():
        return 结果.失败("参数不合法", "令牌不能为空", 来源="授权")
    if str(角色 or "").strip() not in 角色表:
        return 结果.失败("未知角色", f"未知角色: {角色}", 来源="授权")
    服务 = 取共享授权服务(存储目录)
    成功, 消息 = 服务.切换角色(令牌, 角色, 项目范围)
    if not 成功:
        return 结果.失败("角色未授予", 消息, 来源="授权")
    身份id = ""
    for 令牌值, 会话 in 服务._会话表.items():
        if 令牌值 == 令牌:
            身份id = str(会话.get("身份id", ""))
            break
    return 结果.成功结果({"身份id": 身份id, "角色": 角色,
                         "已授予": 服务.已授予角色(身份id, 项目范围)})


