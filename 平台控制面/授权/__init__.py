def 规范化存储目录(存储目录: str = "") -> str:
    """存储目录归一：空值取平台默认目录；归一后为空即抛错（不静默兜底）。"""
    目录 = str(存储目录 or 默认存储目录).strip()
    if not 目录:
        raise ValueError("存储目录不能为空")
    return 目录


def 取共享平台状态(存储目录: str = "") -> 平台状态:
    """按存储目录取进程级共享状态库句柄（同目录复用同一实例）。"""
    目录 = 规范化存储目录(存储目录)
    状态 = _共享状态表.get(目录)
    if 状态 is None:
        状态 = 平台状态(Path(目录), 项目id="平台控制面")
        _共享状态表[目录] = 状态
    return 状态


def 取共享授权服务(存储目录: str = "") -> 授权服务:
    """按存储目录取进程级共享授权服务（会话表跨治理面共用，令牌跨面有效）。"""
    目录 = 规范化存储目录(存储目录)
    服务 = _共享授权表.get(目录)
    if 服务 is None:
        服务 = 授权服务(取共享平台状态(目录))
        _共享授权表[目录] = 服务
    return 服务


