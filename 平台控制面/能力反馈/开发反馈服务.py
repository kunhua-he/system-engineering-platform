def _去重键(开工id: str, 字段值: dict[str, str]) -> str:
    """去重键：开工id + 五字段**原文**（脱敏前），保证同一内容判为同一反馈。"""
    原文 = "\n".join([开工id] + [字段值.get(字段, "") for 字段 in 五字段])
    return hashlib.sha256(原文.encode("utf-8")).hexdigest()[:20]


def _候选摘要(开工id: str, 来源反馈id: str, 类别: str) -> str:
    原文 = f"{开工id}\n{来源反馈id}\n{类别}"
    return hashlib.sha256(原文.encode("utf-8")).hexdigest()[:20]


def _字段(请求: dict[str, Any], 名称: str) -> str:
    """按中文名或旧英文别名取字段（旧 MCP 字段名兼容，批次 D 接线不破）。"""
    if 名称 in 请求:
        return str(请求[名称]).strip()
    for 别名, 中文 in 字段别名.items():
        if 中文 == 名称 and 别名 in 请求:
            return str(请求[别名]).strip()
    return ""


class 开发反馈服务:
    """开发反馈事实服务（唯一写入口：平台状态 证据账本 + 需求表）。

    构造：`开发反馈服务(存储目录, 开工id有效=None, *, 状态=None, 需求服务=None,
    回退文件=<默认 JSONL>|None, 校验器=None)`
    - `开工id有效`：可调用对象，入参开工id，返回是否有效（可传 `默认校验器().校验`
      那样的三门版）；不传则用 `默认校验器()`（格式 + 运行库协作状态域）。
    - `回退文件`：历史 JSONL **只读**回退源；传 None 关闭。
    - 本类不执行反馈内容、不改变能力契约或 Provider 配置（与 反馈服务 同边界）。
    """

    def __init__(self, 存储目录: str, 开工id有效: Callable[[str], bool] | None = None, *,
                 状态: 平台状态 | None = None,
                 需求服务: 需求登记 | None = None,
                 回退文件: str | Path | None = 默认回退文件,
                 校验器: 开工id校验器 | None = None) -> None:
        self.状态 = 状态 or 平台状态(Path(存储目录), 项目id="平台控制面")
        if 校验器 is not None:
            self.校验器 = 校验器
        elif 开工id有效 is not None:
            self.校验器 = 开工id校验器(开工id有效)
        else:
            # 默认 fail-closed：格式门 + 运行库协作状态域登记门。
            self.校验器 = 默认校验器()
        self.需求服务 = 需求服务 if 需求服务 is not None else 需求登记(self.状态)
        self.回退文件 = Path(回退文件) if 回退文件 else None

    # ---------- 能力 1：登记开发反馈 ----------
    def 登记(self, 请求: dict[str, Any]) -> tuple[bool, str, dict[str, Any]]:
        try:
            if not isinstance(请求, dict):
                raise ValueError("请求必须是 JSON 对象")
            有效, 错误码, 说明 = self.校验器.校验(请求.get("开工id") or 请求.get("work_id"))
            if not 有效:
                return 假, 错误码, {"错误说明": 说明}
            开工id = 归一化(请求.get("开工id") or 请求.get("work_id"))
            原文表: dict[str, str] = {}
            for 名称 in 五字段:
                值 = _字段(请求, 名称)
                if not 值:
                    raise ValueError(f"{名称}必须填写；没有问题时明确填写「无」")
                if len(值) > 字段上限:
                    raise ValueError(f"{名称}超过 {字段上限} 字上限")
                原文表[名称] = 值
            任务 = 键值脱敏(str(脱敏(文本(请求["任务"], "任务", 文本上限)))) if 请求.get("任务") else ""
            角色 = 键值脱敏(str(脱敏(文本(请求["角色"], "角色", 文本上限)))) if 请求.get("角色") else ""
            记录表 = {名称: 键值脱敏(str(脱敏(值))) for 名称, 值 in 原文表.items()}
            键 = _去重键(开工id, 原文表)
            已有 = self._按去重键找(开工id, 键)
            if 已有 is not None:
                return 真, 错误_成功, {"反馈id": 已有.get("反馈id", ""),
                                        "开工id": 开工id, "门禁": "已满足",
                                        "是否重复": 真, "时间": 已有.get("时间", "")}
            时间 = time.strftime("%Y-%m-%d %H:%M:%S")
            记录 = {"反馈id": uuid.uuid4().hex[:20], "开工id": 开工id, "任务": 任务,
                    "角色": 角色, "时间": 时间, "去重键": 键, "来源": "账本", **记录表}
            证据id = self.状态.追加证据(
                类型=证据类型_开发反馈, 主题=开工id, 内容=记录,
                操作id=记录["反馈id"], 调用者=角色, 结果="已登记")
            if not 证据id:
                return 假, 错误_写入失败, {}
            return 真, 错误_成功, {"反馈id": 记录["反馈id"], "证据id": 证据id,
                                    "开工id": 开工id, "门禁": "已满足",
                                    "是否重复": 假, "时间": 时间}
        except (OSError, TypeError, ValueError, KeyError, json.JSONDecodeError):
            return 假, 错误_参数不合法, {}

    # ---------- 能力 2：查询开发反馈状态 ----------
    def 查询状态(self, 开工id: str) -> tuple[bool, str, dict[str, Any]]:
        有效, 错误码, 说明 = self.校验器.校验(开工id)
        if not 有效:
            return 假, 错误码, {"错误说明": 说明}
        标识 = 归一化(开工id)
        try:
            记录表 = self._合并记录(标识, 限制上限)
        except (OSError, ValueError, json.JSONDecodeError):
            return 假, 错误_查询失败, {}
        if not 记录表:
            return 真, 错误_成功, {"已反馈": 假, "开工id": 标识, "反馈": {},
                                    "数量": 0, "来源": ""}
        return 真, 错误_成功, {"已反馈": 真, "开工id": 标识, "反馈": 记录表[0],
                                "数量": len(记录表), "来源": 记录表[0].get("来源", "")}

    # ---------- 能力 3：复核开发反馈 ----------
    def 复核(self, 请求: dict[str, Any]) -> tuple[bool, str, dict[str, Any]]:
        try:
            if not isinstance(请求, dict):
                raise ValueError("请求必须是 JSON 对象")
            候选表 = [请求.get("开工id")] if 请求.get("开工id") else []
            多值 = 请求.get("开工id表")
            if 多值 is not None:
                if not isinstance(多值, list):
                    raise ValueError("开工id表必须是数组")
                候选表.extend(多值)
            标识表: list[str] = []
            for 候选 in 候选表:
                有效, 错误码, 说明 = self.校验器.校验(候选)
                if not 有效:
                    return 假, 错误码, {"错误说明": 说明}
                标识 = 归一化(候选)
                if 标识 not in 标识表:
                    标识表.append(标识)
            if not 标识表:
                raise ValueError("必须给出开工id或开工id表（禁止全量读取）")
            限制 = 请求.get("限制", 默认限制)
            if isinstance(限制, bool) or not isinstance(限制, int) or not 1 <= 限制 <= 限制上限:
                raise ValueError(f"限制必须是 1 到 {限制上限} 的整数")
            任务 = str(请求.get("任务", "")).strip()
            反馈表: list[dict[str, Any]] = []
            截断 = 假
            for 标识 in 标识表:
                命中, 该截断 = self._合并记录带截断(标识, 限制)
                截断 = 截断 or 该截断
                反馈表.extend(项 for 项 in 命中
                            if not 任务 or 任务 in str(项.get("任务", "")))
            反馈表.sort(key=lambda 项: str(项.get("时间", "")), reverse=True)
            升级候选 = self._聚合候选(反馈表)
            return 真, 错误_成功, {"数量": len(反馈表), "反馈列表": 反馈表,
                                    "升级候选": 升级候选, "查询是否截断": 截断}
        except (OSError, TypeError, ValueError, KeyError, json.JSONDecodeError):
            return 假, 错误_参数不合法, {}

    # ---------- 能力 4：登记升级候选（缺口②通道） ----------
    def 登记升级候选(self, 请求: dict[str, Any]) -> tuple[bool, str, dict[str, Any]]:
        try:
            if not isinstance(请求, dict):
                raise ValueError("请求必须是 JSON 对象")
            有效, 错误码, 说明 = self.校验器.校验(请求.get("开工id") or 请求.get("work_id"))
            if not 有效:
                return 假, 错误码, {"错误说明": 说明}
            开工id = 归一化(请求.get("开工id") or 请求.get("work_id"))
            来源反馈id = 文本(请求.get("来源反馈id"), "来源反馈id")
            类别 = 字段别名.get(str(请求.get("类别", "")).strip(), "")
            if 类别 not in 升级候选类别:
                raise ValueError("类别必须是不满意、多余、缺失或升级建议")
            来源记录 = next((项 for 项 in self._合并记录(开工id, 限制上限)
                          if 项.get("反馈id") == 来源反馈id), None)
            if 来源记录 is None:
                return 假, 错误_不存在, {}
            内容 = str(来源记录.get(类别, "")).strip()
            if not 内容 or 内容 == "无":
                return 假, 错误_参数不合法, {"错误说明": f"{类别}为「无」，不构成升级候选"}
            摘要 = _候选摘要(开工id, 来源反馈id, 类别)
            已有 = next((项 for 项 in self._证据记录(开工id, 证据类型_升级候选)
                       if 项.get("候选摘要") == 摘要), None)
            if 已有 is not None:
                return 真, 错误_成功, {"需求id": 已有.get("需求id", ""),
                                        "需求状态": 已有.get("需求状态", "待确认"),
                                        "开工id": 开工id, "来源反馈id": 来源反馈id,
                                        "类别": 类别, "是否重复": 真}
            目标 = str(请求.get("目标", "")).strip()[:说明上限] or (
                f"开发反馈升级：{类别}｜{内容[:180]}")
            需求 = self.需求服务.登记需求(
                目标=目标, 非目标=str(请求.get("非目标", "")).strip()[:说明上限],
                输入={"来源": "开发反馈", "开工id": 开工id, "来源反馈id": 来源反馈id,
                     "类别": 类别, "内容": 内容[:字段上限], "候选摘要": 摘要},
                调用者=str(来源记录.get("角色", ""))[:文本上限], 角色="开发反馈")
            需求id = str(需求.get("需求id", ""))
            if not 需求id:
                return 假, 错误_升级登记失败, {}
            记录 = {"需求id": 需求id, "需求状态": "待确认", "来源反馈id": 来源反馈id,
                    "类别": 类别, "候选摘要": 摘要, "开工id": 开工id,
                    "时间": time.strftime("%Y-%m-%d %H:%M:%S")}
            self.状态.追加证据(类型=证据类型_升级候选, 主题=开工id, 内容=记录,
                              操作id=需求id, 调用者=str(来源记录.get("角色", "")),
                              结果="已登记")
            return 真, 错误_成功, {"需求id": 需求id, "需求状态": "待确认",
                                    "开工id": 开工id, "来源反馈id": 来源反馈id,
                                    "类别": 类别, "是否重复": 假}
        except (OSError, TypeError, ValueError, KeyError, json.JSONDecodeError):
            return 假, 错误_参数不合法, {}

    # ---------- 账本与回退源 ----------
    def _证据记录(self, 开工id: str, 类型: str) -> list[dict[str, Any]]:
        """读证据账本（本服务的唯一事实源）；库不可用抛出 OSError 交给上层转错误码。"""
        行表 = self.状态.查询证据(主题=开工id, 类型=类型, 限制=限制上限)
        记录表: list[dict[str, Any]] = []
        for 行 in 行表:
            内容 = 行.get("内容")
            if isinstance(内容, dict):
                记录表.append({**内容, "证据id": 行.get("证据id", ""),
                             "来源": "账本", "时间": 内容.get("时间") or 行.get("时间", "")})
        return 记录表

    def _回退记录(self, 开工id: str, 限制: int) -> tuple[list[dict[str, Any]], bool]:
        """历史 JSONL **只读**回退（迁移期口径，与 协作状态.py 的「库优先＋旧文件只读」一致）。"""
        if self.回退文件 is None or not self.回退文件.is_file():
            return [], 假
        try:
            from 公共契约.运行时.有界IO import (
                读取JSONL,
                默认JSONL读取上限字节,
                默认JSONL读取上限记录,
            )
        except ImportError:
            return [], 假
        源表, 截断 = 读取JSONL(self.回退文件, 最大字节数=默认JSONL读取上限字节,
                            最大记录数=默认JSONL读取上限记录)
        记录表: list[dict[str, Any]] = []
        for 记录 in reversed(源表):
            if 归一化(记录.get("开工id")) != 开工id:
                continue
            归一 = {"反馈id": "", "开工id": 开工id, "任务": str(记录.get("任务", "")),
                   "角色": str(记录.get("角色", "")), "时间": str(记录.get("时间", "")),
                   "去重键": _去重键(开工id, {字段: str(记录.get(字段, "")) for 字段 in 五字段}),
                   "来源": "回退文件",
                   **{字段: str(记录.get(字段, "")) for 字段 in 五字段}}
            记录表.append(归一)
            if len(记录表) >= 限制:
                break
        return 记录表, 截断

    def _合并记录带截断(self, 开工id: str, 限制: int) -> tuple[list[dict[str, Any]], bool]:
        """账本优先 + 回退补齐；同一去重键只留账本那条（不重复计数）。"""
        库表 = self._证据记录(开工id, 证据类型_开发反馈)
        键集 = {项.get("去重键") for 项 in 库表}
        回退表, 截断 = self._回退记录(开工id, 限制)
        回退表 = [项 for 项 in 回退表 if 项.get("去重键") not in 键集]
        合并 = (库表 + 回退表)[:限制]
        合并.sort(key=lambda 项: str(项.get("时间", "")), reverse=True)
        return 合并, 截断

    def _合并记录(self, 开工id: str, 限制: int) -> list[dict[str, Any]]:
        return self._合并记录带截断(开工id, 限制)[0]

    def _按去重键找(self, 开工id: str, 键: str) -> dict[str, Any] | None:
        for 项 in self._合并记录(开工id, 限制上限):
            if 项.get("去重键") == 键:
                return 项
        return None

    @staticmethod
    def _聚合候选(反馈表: list[dict[str, Any]]) -> list[dict[str, Any]]:
        """四字段非「无」→ 升级候选（与旧 `使用反馈.读取反馈列表` 同口径，另加候选摘要）。"""
        候选表: list[dict[str, Any]] = []
        for 记录 in 反馈表:
            for 类别 in 升级候选类别:
                内容 = str(记录.get(类别, "")).strip()
                if not 内容 or 内容 == "无":
                    continue
                候选表.append({
                    "开工id": 记录.get("开工id", ""),
                    "任务": 记录.get("任务", ""), "角色": 记录.get("角色", ""),
                    "时间": 记录.get("时间", ""), "类别": 类别, "内容": 内容,
                    "来源反馈id": 记录.get("反馈id", ""),
                    "来源": 记录.get("来源", ""),
                    "候选摘要": _候选摘要(str(记录.get("开工id", "")),
                                      str(记录.get("反馈id", "")), 类别),
                })
        return 候选表


def 调用能力(能力id: str, 参数: dict[str, Any], *, 服务: 开发反馈服务) -> dict[str, Any]:
    """按能力id调用（薄壳「调用能力」转发用的统一信封）；未知能力id → 能力不存在。"""
    分发 = {
        "平台控制面.能力反馈.登记开发反馈": lambda: 服务.登记(参数),
        "平台控制面.能力反馈.查询开发反馈": lambda: 服务.查询状态(
            str(参数.get("开工id") or 参数.get("work_id") or "")),
        "平台控制面.能力反馈.复核开发反馈": lambda: 服务.复核(参数),
        "平台控制面.能力反馈.登记升级候选": lambda: 服务.登记升级候选(参数),
    }
    执行 = 分发.get(str(能力id))
    if 执行 is None:
        return {"成功": 假, "错误码": "能力不存在", "错误说明": "", "值": {}}
    成功, 错误码, 值 = 执行()
    return {"成功": 成功, "值": 值, "错误码": 错误码,
            "错误说明": 值.get("错误说明", "") if isinstance(值, dict) else "",
            "稳定错误码": 稳定错误码映射.get(错误码, 错误码)}
