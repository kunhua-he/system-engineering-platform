包id = "平台控制面.能力反馈"


def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本治理面的公开能力。

    注册参数与 `能力定义.json` 逐条对应（参数名与顺序一致）；
    能力实现只做边界校验与结果归一，反馈语义仍在同目录反馈服务里。
    """
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.能力反馈.登记能力反馈",
        包id=包id,
        实现函数=登记能力反馈,
        参数=[{"名称": "请求", "类型": "字典型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="登记一条能力反馈（运行时诊断）：校验必填字段与能力存在，按去重键幂等落一条事实。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力反馈.查询能力反馈",
        包id=包id,
        实现函数=查询能力反馈,
        参数=[{"名称": "反馈id", "类型": "文本型"},
              {"名称": "状态", "类型": "文本型"},
              {"名称": "能力id", "类型": "文本型"},
              {"名称": "限制", "类型": "整数型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="查询能力反馈记录（只读）：按反馈id/状态/能力id 过滤，返回公开字段记录表。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.能力反馈.迁移能力反馈状态",
        包id=包id,
        实现函数=迁移能力反馈状态,
        参数=[{"名称": "反馈id", "类型": "文本型"},
              {"名称": "请求", "类型": "字典型"},
              {"名称": "存储目录", "类型": "文本型"}],
        返回="结果",
        说明="迁移一条能力反馈的状态（8 态状态机）：校验迁移合法性并追加状态证据。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
