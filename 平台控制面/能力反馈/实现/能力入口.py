"""能力反馈包的实现层：治理面反馈动作的唯一执行入口（能力实现）。

本模块是 `平台控制面.能力反馈` 正式包的能力实现层，包级中文入口
（同包 `__init__.py`）的 `注册能力(注册表)` 从这里取实现函数。

分工：
- `反馈服务.py` / `开发反馈服务.py`：反馈语义与状态机（唯一实现）。
- 本模块：把反馈服务的公开方法包成**统一结果契约**的能力实现，
  并负责能力边界上的参数校验、存储目录缺省与能力存在判定装配。

为什么要有这一层（第 2 条 1 项分层与归属固定）：
- 反馈事实属**平台控制面证据域**，写入口只有本包的反馈服务；
- 调用方（运行核心/统一网关、模块、薄壳）**不得 import 实现**，只能经
  唯一能力调用入口按能力 id 调用，实现与本层之间由包级中文入口隔离。
- 存储目录由调用方按部署配置传入（缺省取工程缓存下的平台控制面目录），
  本层不硬编码任何调用方的缓存根。
"""
from __future__ import annotations

from typing import Any, Callable

from 平台控制面.能力反馈.反馈服务 import 能力反馈服务

默认存储目录 = "工程缓存/平台控制面"

错误_参数不合法 = "参数不合法"
错误_能力校验不可用 = "能力校验不可用"

# 存储目录 → 反馈服务（同目录复用同一实例，避免每次调用重建状态库连接）。
_服务表: dict[str, 能力反馈服务] = {}
_能力存在判定: Callable[[str], bool] | None = None


def 设置能力存在判定(判定: Callable[[str], bool] | None) -> None:
    """注入能力存在判定（唯一注入点，供装配与验证场景使用）。

    `None` 表示回到默认判定（经唯一能力调用入口取注册表）。
    """
    global _能力存在判定
    _能力存在判定 = 判定


def _默认能力存在判定() -> tuple[Callable[[str], bool] | None, str]:
    """默认能力存在判定：注册关系取唯一能力调用入口的注册表（fail-closed）。

    未装配 / 调用入口不可用时返回 `(None, 原因)`，由能力实现转成明确失败，
    **绝不**默认放行（放行等于让任意能力 id 都能写反馈）。
    """
    try:
        from 运行核心.能力调用.唯一能力调用 import 获取唯一调用服务
        注册表 = 获取唯一调用服务().注册表
    except Exception as 错误:  # noqa: BLE001 —— 调用入口不可用必须转明确失败，不静默放行
        return None, f"唯一能力调用入口不可用：{错误}"
    if 注册表 is None:
        return None, "唯一能力调用入口未装配注册表"
    return (lambda 能力id: 能力id in 注册表.能力id列表), ""


def _取服务(存储目录: str, 能力存在: Callable[[str], bool]) -> 能力反馈服务:
    """按存储目录取反馈服务；目录为空即抛错（由能力实现转 参数不合法）。"""
    目录 = str(存储目录 or 默认存储目录).strip()
    if not 目录:
        raise ValueError("存储目录不能为空")
    服务 = _服务表.get(目录)
    if 服务 is None:
        服务 = 能力反馈服务(目录, 能力存在)
        _服务表[目录] = 服务
    return 服务


def _失败说明(值: Any) -> str:
    """从反馈服务返回值里取错误说明（无则空串）。"""
    return str(值.get("错误说明", "")) if isinstance(值, dict) else ""


def 登记能力反馈(请求: dict[str, Any], 存储目录: str = "") -> Any:
    """登记一条能力反馈（运行时诊断反馈的唯一写入口）。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not isinstance(请求, dict):
        return 结果.失败(错误_参数不合法, "请求必须是 JSON 对象", 来源="能力反馈")
    能力存在 = _能力存在判定
    说明 = ""
    if 能力存在 is None:
        能力存在, 说明 = _默认能力存在判定()
        if 能力存在 is None:
            return 结果.失败(错误_能力校验不可用, 说明, 来源="能力反馈")
    try:
        服务 = _取服务(存储目录, 能力存在)
    except (TypeError, ValueError, OSError) as 错误:
        return 结果.失败(错误_参数不合法, f"存储目录不合法：{错误}", 来源="能力反馈")
    成功, 错误码, 值 = 服务.登记(请求)
    if not 成功:
        return 结果.失败(错误码 or 错误_参数不合法, _失败说明(值) or 错误码,
                        来源="能力反馈")
    return 结果.成功结果(值)


def 查询能力反馈(反馈id: str = "", 状态: str = "", 能力id: str = "", 限制: int = 50,
                存储目录: str = "") -> Any:
    """查询能力反馈记录（只读；不改变任何反馈事实）。"""
    from 公共契约.基础类型.结果类型 import 结果

    try:
        服务 = _取服务(存储目录, _查询用判定())
    except (TypeError, ValueError, OSError) as 错误:
        return 结果.失败(错误_参数不合法, f"存储目录不合法：{错误}", 来源="能力反馈")
    成功, 错误码, 记录表 = 服务.查询(反馈id, 状态, 能力id, 限制)
    if not 成功:
        # 查询的失败原因属调用方输入问题：错误码统一为 参数不合法，
        # 具体原因（限制范围/状态取值）走错误说明，逐字保持收敛前口径。
        码 = 错误_参数不合法 if 错误码 != "反馈查询失败" else "反馈查询失败"
        return 结果.失败(码, 错误码, 来源="能力反馈")
    return 结果.成功结果({"记录表": 记录表, "数量": len(记录表)})


def 迁移能力反馈状态(反馈id: str, 请求: dict[str, Any], 存储目录: str = "") -> Any:
    """迁移一条能力反馈的状态（按 8 态状态机校验，非法迁移即失败）。"""
    from 公共契约.基础类型.结果类型 import 结果

    if not isinstance(请求, dict):
        return 结果.失败(错误_参数不合法, "请求必须是 JSON 对象", 来源="能力反馈")
    try:
        服务 = _取服务(存储目录, _查询用判定())
    except (TypeError, ValueError, OSError) as 错误:
        return 结果.失败(错误_参数不合法, f"存储目录不合法：{错误}", 来源="能力反馈")
    成功, 错误码, 值 = 服务.迁移状态(反馈id, 请求)
    if not 成功:
        return 结果.失败(错误码 or 错误_参数不合法, _失败说明(值) or 错误码,
                        来源="能力反馈")
    return 结果.成功结果(值)


def _查询用判定() -> Callable[[str], bool]:
    """查询/迁移路径的能力存在判定：只用已注入判定，不触达注册表。

    查询与状态迁移不校验「能力存在」（与收敛前的服务实现一致），
    这里给一个恒真的占位判定，保证构造服务时不会误触达装配。
    """
    return _能力存在判定 or (lambda 能力id: True)
