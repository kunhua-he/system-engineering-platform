"""备份恢复包的实现层：备份契约治理动作的唯一执行入口（能力实现）。

本模块是 `平台控制面.备份恢复` 正式包的能力实现层，包级中文入口
（同包 `__init__.py`）的 `注册能力(注册表)` 从这里取实现函数。

分工（第 2 条 1 项「分层与归属固定」）：
- 同目录 `备份契约.py`：三类权威数据（权威状态/包仓库/证据账本）的
  恢复点、恢复时限、保留周期、恢复顺序与真实校验方法**唯一语义实现**；
- 同目录 `备份执行.py` / `恢复执行.py`：备份写入与按序恢复的能力 mixin；
- 同目录 `校验函数.py`：三类数据真实校验函数；
- 同目录 `恢复编排器.py` / `恢复工具.py`：新机器恢复编排（P1-10），
  本批**不**为它开能力（尚无跨层调用方，其调用方是测试中心）；
- 本模块：把 `权威数据备份契约` 的公开方法收成**统一结果契约**的能力实现，
  只做能力边界上的存储根目录缺省、前置校验与结果收口，不复制任何备份语义。

为什么要有这一层：`开发工具` 下的发布门禁是**进程外**调用方，不得 import
本包实现，只能经唯一能力调用入口按能力 id 调用；本层是它唯一可达的公开面。

**存储根目录缺省口径（2026-09-20 修 #63）**：缺省不再取 `解析运行数据根()`
（= `<运行缓存根>/运行数据`）—— 实测三类权威数据**不共用那一个根**，于是真实
生产数据上 `校验备份` 恒判 `通过=False`（包仓库报缺失、证据账本空）。
缺省改为**空串**：留空即逐类回落各自的权威宿主，唯一实现在同包
`类根解析.解析类根()`（状态/证据/锁 → `平台控制面/平台状态` 的默认存储目录；
包仓库 → 包仓库包自己的 `制品仓库缓存根()`）。显式传根仍是合法用法，语义不变。
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真, 假
# 错误码唯一源 = `公共契约/错误结构/错误结构.py`（B-9 收口）：平台同义码只导入，不复制字面量。
from 公共契约.错误结构 import 错误码_参数不合法

# 本包自有码（不在平台规范集内）。
错误码_备份不存在 = "备份不存在"

#: 存储根目录缺省值＝空串＝**逐类回落各自的权威宿主**（见模块头注释）。
#: 不再给一个「看似具体」的默认路径：旧默认根指向 `运行数据`，而三类数据都不住在
#: 那里（状态/证据/锁 在 `平台控制面/`、包仓库在 `制品仓库/`），那个默认值只会让
#: 调用方以为「不传参也能备全」，实际是备错源或备空（修 #63 的根因）。
默认存储根目录 = ""

_备份清单文件名 = "备份清单.json"
_快照前缀 = "快照_"


def _文本(值: Any) -> str:
    """文本参数归一：None 视为空串，其余转文本并去首尾空白。"""
    return "" if 值 is None else str(值).strip()


def _取契约(存储根目录: str):
    """按存储根目录构造 权威数据备份契约；目录为空即**逐类回落各自的权威宿主**。

    ⚠️ 空串**必须原样透传**，不得先包成 `Path("")` —— `Path("")` 求值为 `Path(".")`，
    那是一个**非空相对路径**，会让「留空＝逐类回落」静默退化成「拿当前工作目录当根」
    （修 #63 时实测到：备份只写出 4096 字节的空状态库，三类依旧全撞缺失）。
    归一与判空只有一份实现，在 类根解析.解析类根()。
    """
    from 平台控制面.备份恢复.备份契约 import 权威数据备份契约

    return 权威数据备份契约(_文本(存储根目录) or 默认存储根目录)


def _有备份(备份根: Path) -> bool:
    """能力边界前置校验：备份目录内是否有**已认证**的可用备份。

    认证判据 = `备份清单.json`（实现层写它的顺序是最后一步，清单缺失即该快照
    未被认证）。只按「有 `快照_*` 目录」判会把**半份快照**当备份：紧接着去读清单
    会抛 `FileNotFoundError`，被 `运行核心/统一网关/网关核心.py` 收口成公开码
    `文件不存在` = **HTTP 404**——调用方看到的是「路由不存在」，而不是本能力声明的
    `备份不存在`（2026-09-16 HTML 黑盒实测：备份恢复.备份与校验 两步双双 404）。

    缺失即返回明确的 `备份不存在` 失败，绝不静默降级、绝不回退到别的备份。
    """
    if (备份根 / _备份清单文件名).is_file():
        return 真
    if not 备份根.is_dir():
        return 假
    return any((子目录 / _备份清单文件名).is_file()
               for 子目录 in 备份根.glob(_快照前缀 + "*"))


def 声明备份契约(覆盖表: dict | None = None, 存储根目录: str = "") -> Any:
    """声明三类权威数据的备份契约（只读，不触碰磁盘）。

    返回 `{契约表, 类数}`；契约表按类给出 恢复点/恢复时限秒/保留周期/恢复顺序，
    盖写字段由 `覆盖表` 提供。**校验方法转成方法名 `校验方法名`**（函数对象
    不是可序列化值，能力的返回值必须可 JSON 化）。
    """
    from 公共契约.基础类型.结果类型 import 结果

    if 覆盖表 is not None and not isinstance(覆盖表, dict):
        return 结果.失败(错误码_参数不合法, "覆盖表 必须是对象", 来源="备份恢复")
    契约 = _取契约(存储根目录).声明契约(覆盖表)
    契约表: dict[str, Any] = {}
    for 类名, 项 in 契约.items():
        公开项 = {键: 值 for 键, 值 in 项.items() if 键 != "校验方法"}
        公开项["校验方法名"] = str(getattr(项.get("校验方法"), "__name__", ""))
        契约表[类名] = 公开项
    return 结果.成功结果({"契约表": 契约表, "类数": len(契约表)})


def 执行备份(备份目录: str = "", 存储根目录: str = "") -> Any:
    """真实备份三类权威数据到时间戳快照子目录，返回 `{清单}`。

    备份源 = `存储根目录`（缺省取平台运行数据根）；快照目录与 `备份清单.json`
    由实现层真实落盘。数据源缺失的类在清单里**如实标记缺失**，
    `校验备份` 会据此判失败——不伪造、不补默认值。
    """
    from 公共契约.基础类型.结果类型 import 结果

    备份文本 = _文本(备份目录)
    if not 备份文本:
        return 结果.失败(错误码_参数不合法, "备份目录不能为空", 来源="备份恢复")
    清单 = _取契约(存储根目录).执行备份(Path(备份文本))
    return 结果.成功结果({"清单": 清单})


def 校验备份(备份目录: str = "", 存储根目录: str = "") -> Any:
    """校验备份：定位清单 → 摘要核对 → 逐类真实校验方法。

    返回 `{通过, 原因}`；`通过=False` 是**校验结论**（正常答复，不是调用失败），
    原因逐字沿用实现层原文（如「权威状态: 内容摘要不符」）。备份目录内无任何
    备份时返回失败码 `备份不存在`（缺失不可被当作「校验通过」）。
    """
    from 公共契约.基础类型.结果类型 import 结果

    备份文本 = _文本(备份目录)
    if not 备份文本:
        return 结果.失败(错误码_参数不合法, "备份目录不能为空", 来源="备份恢复")
    备份根 = Path(备份文本)
    if not _有备份(备份根):
        return 结果.失败(错误码_备份不存在, f"备份目录无任何备份: {备份根}",
                        来源="备份恢复")
    通过, 原因 = _取契约(存储根目录).校验备份(备份根)
    return 结果.成功结果({"通过": bool(通过), "原因": str(原因)})


def 恢复备份(备份目录: str = "", 目标目录: str = "", 存储根目录: str = "") -> Any:
    """按契约恢复顺序恢复三类数据到目标目录，恢复后逐类真实校验。

    返回 `{成功, 恢复顺序, 结果, 目标目录, 回退警告}`。`回退警告` 非空表示
    目标目录现有权威状态比本备份更新（旧快照重放），调用方必须看到该标记；
    备份目录内无任何备份时返回失败码 `备份不存在`。
    """
    from 公共契约.基础类型.结果类型 import 结果

    备份文本 = _文本(备份目录)
    目标文本 = _文本(目标目录)
    if not 备份文本:
        return 结果.失败(错误码_参数不合法, "备份目录不能为空", 来源="备份恢复")
    if not 目标文本:
        return 结果.失败(错误码_参数不合法, "目标目录不能为空", 来源="备份恢复")
    备份根 = Path(备份文本)
    if not _有备份(备份根):
        return 结果.失败(错误码_备份不存在, f"备份目录无任何备份: {备份根}",
                        来源="备份恢复")
    恢复结果 = _取契约(存储根目录).恢复(备份根, Path(目标文本))
    return 结果.成功结果({
        "成功": bool(恢复结果.get("成功")),
        "恢复顺序": list(恢复结果.get("恢复顺序") or []),
        "结果": list(恢复结果.get("结果") or []),
        "目标目录": str(恢复结果.get("目标目录", "")),
        "回退警告": str(恢复结果.get("回退警告", "")),
    })


def 查询备份源根(存储根目录: str = "") -> Any:
    """查询备份源根（只读自省）：逐类回报生效的源根、是否存在、由谁声明。

    为什么要有这条能力（2026-09-20 修 #63）：「三类数据各住哪」这一事实此前只存在
    于实现里，调用方与门禁都无法从外部核实 —— 于是错口径长期没人发现（真实生产数据上
    `校验备份` 恒判 `通过=False` 也不曾被当成缺陷）。做成能力后，根口径可查、可测、
    可回归：门禁与演练可直接比对「生效根」与「该类应有宿主」，漂移当场暴露。
    """
    from 公共契约.基础类型.结果类型 import 结果
    from 平台控制面.备份恢复.类根解析 import 类根清单

    表 = 类根清单(_文本(存储根目录) or 默认存储根目录)
    return 结果.成功结果({"类根表": 表, "类数": len(表)})


