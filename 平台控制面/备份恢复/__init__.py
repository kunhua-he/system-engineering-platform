包id = "平台控制面.备份恢复"


def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本治理面的四条备份契约能力。

    注册参数与 `能力定义.json` 逐条对应（参数名与顺序一致）；
    能力实现只做边界校验与结果收口，备份语义仍在同目录实现里。
    """
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="平台控制面.备份恢复.声明备份契约",
        包id=包id,
        实现函数=声明备份契约,
        参数=[{"名称": "覆盖表", "类型": "字典型"},
              {"名称": "存储根目录", "类型": "文本型"}],
        返回="结果",
        说明="声明四类权威数据的备份契约（只读），校验方法以方法名对外。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.备份恢复.执行备份",
        包id=包id,
        实现函数=执行备份,
        参数=[{"名称": "备份目录", "类型": "文本型"},
              {"名称": "存储根目录", "类型": "文本型"}],
        返回="结果",
        说明="真实备份四类权威数据到时间戳快照子目录，数据源缺失如实标记。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.备份恢复.校验备份",
        包id=包id,
        实现函数=校验备份,
        参数=[{"名称": "备份目录", "类型": "文本型"},
              {"名称": "存储根目录", "类型": "文本型"}],
        返回="结果",
        说明="校验备份：清单定位、摘要核对与逐类真实校验方法。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="平台控制面.备份恢复.恢复备份",
        包id=包id,
        实现函数=恢复备份,
        参数=[{"名称": "备份目录", "类型": "文本型"},
              {"名称": "目标目录", "类型": "文本型"},
              {"名称": "存储根目录", "类型": "文本型"}],
        返回="结果",
        说明="按契约顺序恢复四类数据并逐类真实校验，旧快照重放带回退警告。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
