"""四类权威数据的**根解析**：逐类取各自唯一解析器（本包唯一实现）。

为什么要有这个模块（2026-09-20 修 #63 实测）：备份契约原先假设「四类数据共用一个
根」，在真实生产数据上**四类挂三类**——

- `权威状态` / `证据账本` 的真实宿主是 `平台控制面/平台状态` 的默认存储目录
  （`<运行缓存根>/平台控制面`；8 个平台控制面包里 7 个都用它）；而旧默认根取的是
  `解析运行数据根()` = `<运行缓存根>/运行数据`，那里只剩一份**停更副本**
  （证据 0 条、结构版本落后）⇒ 备到了、但备的是错的那一份；
- `包仓库` 的真实宿主是 `工程缓存/制品仓库`（与 `运行数据` **平级**），已有唯一
  解析器 `平台控制面.包仓库.制品布局.制品仓库缓存根()`（该模块明写「禁止裸拼
  `工程缓存`」），契约却按 `<存储根>/制品` 硬拼 ⇒ 永远找不到。

**只转调、不复制**：本模块对 `平台状态` 与 `包仓库` 各自的默认值只做**转调**，
不在这里重算路径。重算就是第二份口径——那两个包改了根，这里不会跟着改，
缺陷会以同样的形态复发（哲学第 1 条「不保留旧腿」、第 2 条「分层与依赖归属」）。

**显式传根优先**：调用方显式传了根（发布门禁与演练在临时目录里自建四类数据、
测试构造自足数据根）就一律用它，本模块不改写 —— 那是合法用法，不是缺陷。

**「根」指该类数据的源目录本身**，不是它的父目录：包仓库在显式传根的夹具形态下
位于 `<根>/制品`（发布门禁与测试都这么建），而真实形态的制品仓库根下**没有**
`制品/` 这一层（子目录直接是 `平台客户端制品/`、`平台客户端状态/` 等）。两种形态
由本模块**一次抹平**，调用方拿到的 `源根` 就是「装着该类数据的那个目录」。
"""

from __future__ import annotations

from pathlib import Path

#: 各类数据的权威宿主由谁声明（本表只作可读性索引，取用一律在 解析类根() 内转调）。
类根来源表 = {
    "权威状态": "平台控制面.平台状态.默认存储目录",
    "证据账本": "平台控制面.平台状态.默认存储目录",
    "项目锁": "平台控制面.平台状态.默认存储目录",
    "包仓库": "平台控制面.包仓库.制品布局.制品仓库缓存根",
}


def _文本路径(存储根目录: object) -> Path | None:
    """把入参归一成 `Path`；空值（None / "" / 纯空白）归一成 `None`＝「未显式传根」。"""
    文本 = "" if 存储根目录 is None else str(存储根目录).strip()
    return Path(文本) if 文本 else None


def 解析类根(存储根目录: object, 类名: str) -> Path:
    """取某一类数据的**源目录**（装着该类数据的那个目录）；显式传根时由该根推出。"""
    显式 = _文本路径(存储根目录)
    if 类名 == "包仓库":
        # 显式传根的夹具形态：制品在 `<根>/制品` 下（发布门禁与测试的既有建法，逐字不变）。
        if 显式 is not None:
            return 显式 / "制品"
        # 真实形态：包仓库自己的唯一解析器（源码态 = `<系统根>/工程缓存/制品仓库`，
        # 制品态落制品外）。它返回的就是制品仓库根本身，其下没有 `制品/` 层。
        from 平台控制面.包仓库.制品布局 import 制品仓库缓存根

        return Path(制品仓库缓存根())
    if 显式 is not None:
        return 显式
    # 状态库 / 证据账本 / 项目锁 三类同宿：平台状态包自己的默认存储目录。
    from 平台控制面.平台状态 import 默认存储目录

    return Path(默认存储目录)


def 类根清单(存储根目录: object = "") -> list[dict]:
    """逐类回报**生效的根**：`[{类, 根目录, 存在, 来自}]`（只读自省，不建目录、不写盘）。

    为什么要有它：修 #63 时，「四类各住哪」这个事实只存在于实现里，调用方与
    门禁都无法从外部核实 —— 于是同一份错口径长期没人发现（`校验备份` 恒判
    `通过=False` 也没人当成缺陷）。有了本自省能力，根口径**可见、可测、可回归**：
    门禁与演练直接比对「生效根」与「该类应有宿主」，漂移当场暴露。
    """
    清单 = []
    for 类名 in ("权威状态", "证据账本", "包仓库", "项目锁"):
        根 = 解析类根(存储根目录, 类名)
        清单.append({
            "类": 类名,
            "根目录": str(根),
            "存在": bool(根.is_dir()),
            "来自": "调用方显式传入" if _文本路径(存储根目录) is not None else 类根来源表[类名],
        })
    return 清单


__all__ = ["解析类根", "类根清单", "类根来源表"]
