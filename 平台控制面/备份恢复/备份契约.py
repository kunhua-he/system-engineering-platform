"""权威数据备份契约：权威状态/包仓库/证据账本三类数据的恢复点、
恢复时限、保留周期、恢复顺序与真实校验方法（第十四阶段工作包 P1-09）。

公开类型与编排入口：声明契约、执行备份（备份执行能力）、校验备份、
恢复（恢复执行能力）；真实校验函数见 校验函数.py。仅标准库；中文命名。

**三类数据的根不是同一个目录**（2026-09-20 修 #63 实测）：
原先三类共用 `存储根目录` 一个根，实测在真实生产数据上**多类都挂**——
① 权威状态与证据账本的真实宿主是 `平台控制面/平台状态` 的默认存储目录
（`<运行缓存根>/平台控制面`，8 个平台控制面包里 7 个都用它），而契约默认根
取的是 `解析运行数据根()` = `<运行缓存根>/运行数据`，那里只剩一份**停更副本**
（证据 0 条、结构版本落后）⇒ 备到了、但备的是错的那一份；
② 包仓库真实宿主是 `工程缓存/制品仓库`（与 `运行数据` **平级**），已有唯一
解析器 `平台控制面.包仓库.制品布局.制品仓库缓存根()`（该模块明写「禁止裸拼
`工程缓存`」），契约却按 `<存储根>/制品` 硬拼 ⇒ 永远找不到；
③ 证据账本从 `<默认根>/权威状态.db` 的 `证据` 表读，随 ① 一起读错库。

因此本契约改为**逐类取各自唯一解析器**：不再假设「三类共用一个根」。
`存储根目录` 入参保留原语义——**显式传入时**仍作为三类的共同根（夹具/演练/
测试要构造自足数据根，这是合法用法）；只有**未显式传入**时才逐类回落到各自的
真实宿主。判据：真实生产数据上 `校验备份` 必须能通过，而不是恒判 `通过=False`。
"""
from __future__ import annotations

import time
from pathlib import Path
from typing import Any

from 平台控制面.备份恢复.校验函数 import (内容摘要, 校验权威状态, 校验证据账本,
                                            校验包仓库)
from 平台控制面.备份恢复.类根解析 import 解析类根
from 平台控制面.备份恢复.备份执行 import 备份执行能力
from 平台控制面.备份恢复.恢复执行 import 恢复执行能力
from 公共契约.基础类型.逻辑类型 import 真, 假

三类数据表 = ("权威状态", "包仓库", "证据账本")


class 权威数据备份契约(备份执行能力, 恢复执行能力):
    """权威数据备份契约：声明契约、执行备份、校验备份、按序恢复。"""

    校验方法表 = {"权威状态": (1, 校验权威状态), "证据账本": (2, 校验证据账本),
                "包仓库": (3, 校验包仓库)}
    文件名表 = {"权威状态": "权威状态.db", "证据账本": "证据账本.json",
                "包仓库": "制品"}

    def __init__(self, 存储根目录: Path | str) -> None:
        # 存原样入参（可能是 None / ""）：显式传根=三类共用该根；空=逐类回落权威宿主。
        # 归一与逐类解析的唯一实现在 类根解析.解析类根()，本类不复制第二份口径。
        self.存储根目录 = 存储根目录

    def _类根(self, 类名: str) -> Path:
        """取某一类数据的权威宿主目录（转调本包唯一实现 `类根解析.解析类根`）。"""
        return 解析类根(self.存储根目录, 类名)

    def 声明契约(self, 覆盖表: dict | None = None) -> dict[str, Any]:
        """三类数据契约字典；恢复点/时限/周期/顺序/校验方法可配置。"""
        覆盖表 = dict(覆盖表 or {})
        默认值 = {"恢复点": time.strftime("%Y-%m-%d %H:%M:%S"),
                  "恢复时限秒": 60, "保留周期": 7}
        return {类: {"恢复点": 覆盖表.get("恢复点", 默认值["恢复点"]),
                     "恢复时限秒": 覆盖表.get("恢复时限秒", 默认值["恢复时限秒"]),
                     "保留周期": 覆盖表.get("保留周期", 默认值["保留周期"]),
                     "恢复顺序": 顺序, "校验方法": 校验,
                     **(覆盖表[类] if isinstance(覆盖表.get(类), dict) else {})}
                for 类, (顺序, 校验) in self.校验方法表.items()}

    def 校验备份(self, 备份目录: Path | str) -> tuple[bool, str]:
        """校验备份：定位清单 → 摘要核对 → 逐类真实校验方法。"""
        清单 = self._定位清单(备份目录)
        快照目录 = Path(清单["快照目录"])
        契约表 = self.声明契约(清单["契约"])
        失败表 = []
        for 类名 in 三类数据表:
            备份项 = 清单["文件"].get(类名, {})
            if 备份项.get("缺失"):
                失败表.append(f"{类名}: 备份缺失")
                continue
            if 类名 != "包仓库":
                文件 = 快照目录 / 备份项["文件"]
                if not 文件.is_file() or 内容摘要(文件.read_bytes()) != 备份项.get("摘要", ""):
                    失败表.append(f"{类名}: 内容摘要不符")
                    continue
            成功, 原因 = 契约表[类名]["校验方法"](快照目录 / ("制品" if 类名 == "包仓库" else ""), 备份项)
            if not 成功:
                失败表.append(f"{类名}: {原因}")
        return (真, "三类数据校验全部通过") if not 失败表 else (假, "；".join(失败表))


__all__ = ["权威数据备份契约", "内容摘要"]
