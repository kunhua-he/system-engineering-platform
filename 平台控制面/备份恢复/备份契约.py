"""权威数据备份契约：权威状态/包仓库/证据账本/项目锁四类数据的恢复点、
恢复时限、保留周期、恢复顺序与真实校验方法（第十四阶段工作包 P1-09）。

公开类型与编排入口：声明契约、执行备份（备份执行能力）、校验备份、
恢复（恢复执行能力）；真实校验函数见 校验函数.py。仅标准库；中文命名。
"""
from __future__ import annotations

import sqlite3
import time
from pathlib import Path
from typing import Any

from 平台控制面.备份恢复.校验函数 import (内容摘要, 校验权威状态, 校验证据账本,
                                            校验包仓库, 校验项目锁)
from 平台控制面.备份恢复.备份执行 import 备份执行能力
from 平台控制面.备份恢复.恢复执行 import 恢复执行能力
from 公共契约.基础类型.逻辑类型 import 真, 假

四类数据表 = ("权威状态", "包仓库", "证据账本", "项目锁")


class 权威数据备份契约(备份执行能力, 恢复执行能力):
    """权威数据备份契约：声明契约、执行备份、校验备份、按序恢复。"""

    校验方法表 = {"权威状态": (1, 校验权威状态), "证据账本": (2, 校验证据账本),
                "包仓库": (3, 校验包仓库), "项目锁": (4, 校验项目锁)}
    文件名表 = {"权威状态": "权威状态.db", "证据账本": "证据账本.json",
                "项目锁": "项目锁.json", "包仓库": "制品"}

    def __init__(self, 存储根目录: Path | str) -> None:
        self.存储根目录 = Path(存储根目录)

    def 声明契约(self, 覆盖表: dict | None = None) -> dict[str, Any]:
        """四类数据契约字典；恢复点/时限/周期/顺序/校验方法可配置。"""
        覆盖表 = dict(覆盖表 or {})
        默认值 = {"恢复点": time.strftime("%Y-%m-%d %H:%M:%S"),
                  "恢复时限秒": 60, "保留周期": 7}
        return {类: {"恢复点": 覆盖表.get("恢复点", 默认值["恢复点"]),
                     "恢复时限秒": 覆盖表.get("恢复时限秒", 默认值["恢复时限秒"]),
                     "保留周期": 覆盖表.get("保留周期", 默认值["保留周期"]),
                     "恢复顺序": 顺序, "校验方法": 校验,
                     **(覆盖表[类] if isinstance(覆盖表.get(类), dict) else {})}
                for 类, (顺序, 校验) in self.校验方法表.items()}

    def 校验备份(self, 备份目录: Path | str) -> tuple[bool, str]:
        """校验备份：定位清单 → 摘要核对 → 逐类真实校验方法。"""
        清单 = self._定位清单(备份目录)
        快照目录 = Path(清单["快照目录"])
        契约表 = self.声明契约(清单["契约"])
        失败表 = []
        for 类名 in 四类数据表:
            备份项 = 清单["文件"].get(类名, {})
            if 备份项.get("缺失"):
                失败表.append(f"{类名}: 备份缺失")
                continue
            if 类名 != "包仓库":
                文件 = 快照目录 / 备份项["文件"]
                if not 文件.is_file() or 内容摘要(文件.read_bytes()) != 备份项.get("摘要", ""):
                    失败表.append(f"{类名}: 内容摘要不符")
                    continue
            成功, 原因 = 契约表[类名]["校验方法"](快照目录 / ("制品" if 类名 == "包仓库" else ""), 备份项)
            if not 成功:
                失败表.append(f"{类名}: {原因}")
        return (真, "四类数据校验全部通过") if not 失败表 else (假, "；".join(失败表))


__all__ = ["权威数据备份契约", "内容摘要"]
