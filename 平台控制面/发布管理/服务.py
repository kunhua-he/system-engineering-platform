"""发布管理：期望版本、候选版本、灰度、激活指针、排空、撤销和回滚事务。

总补修边界：
- 发布事务状态机：准备 → 提交（提交中）→ 完成（激活）；重启后恢复未完成发布，
  只能落在明确旧版或新版，不允许半激活。
- 控制面对账：对比期望状态（发布记录）与实际状态（激活指针），分歧时以**实际
  激活指针**为准回退期望记录，并追加 `对账告警` 证据（唯一口径，见 对账 方法说明）。
- 激活指针使用单调版本 + 栅栏令牌 + CAS：陈旧监督器不能覆盖新指针。
"""
from __future__ import annotations

import json
import time
import uuid
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假


class 发布管理:
    """发布管理服务（唯一写入口：平台状态.发布/激活指针）。"""

    def __init__(self, 状态) -> None:
        self.状态 = 状态

    def 登记期望版本(self, *, 包id: str, 期望版本: str, 调用者: str = "") -> str:
        发布id = uuid.uuid4().hex[:16]
        self.状态.写入记录("发布", {
            "发布id": 发布id, "包id": 包id, "期望版本": 期望版本, "候选版本": "",
            "灰度比例": 0.0, "激活指针": "", "状态": "期望", "回滚事务": "",
            "时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        })
        return 发布id

    def 开始灰度(self, *, 发布id: str, 候选版本: str, 比例: float) -> tuple[bool, str]:
        记录 = self.状态.读取记录("发布", "发布id", 发布id)
        if 记录 is None:
            return 假, "发布不存在"
        self.状态.条件更新("发布", {"候选版本": 候选版本, "灰度比例": 比例, "状态": "灰度"},
                          "发布id=?", (发布id,))
        return 真, "灰度开始"

    def 激活(self, *, 发布id: str, 目标: str) -> tuple[bool, str]:
        """激活（事务状态机）：准备 → 提交 → 完成；任一步可恢复。"""
        记录 = self.状态.读取记录("发布", "发布id", 发布id)
        if 记录 is None:
            return 假, "发布不存在"
        包id = 记录["包id"]
        # 准备：同时落下本事务的目标，使强杀后可判别指针是否已切
        # （只写 状态=准备 会让 恢复未完成发布 读到空目标，「指针已切→完成」
        #  分支恒不可达，CAS 与「完成」之间强杀即留下半激活）
        # 返回值必须检查（B-23 ①）：原先把结果丢掉，条件不满足时 UPDATE 影响 0 行、
        # 「准备」根本没落地，流程照样往下走 —— 已回滚（状态=已回滚）的发布会被
        # 原地「复活」成完成态，越过了回滚终态。
        准备成功 = self.状态.条件更新(
            "发布", {"状态": "准备", "激活指针": 目标},
            "发布id=? AND 状态 IN ('期望','灰度','准备','完成')", (发布id,))
        if not 准备成功:
            return 假, (f"发布状态不允许激活（当前 {记录['状态']}，已回滚的发布"
                           f"不得原地复活）: {发布id}")
        # 提交：CAS 切换激活指针（幂等：目标一致视为已完成）
        指针 = self.状态.读取记录("激活指针", "指针id", 包id)
        if 指针 is not None and 指针["目标"] == 目标 and 指针["状态"] == "激活":
            if not self.状态.条件更新("发布", {"激活指针": 目标, "状态": "完成"},
                                      "发布id=? AND 状态 IN ('准备','完成')", (发布id,)):
                return 假, f"发布已回滚，拒绝幂等激活复活: {发布id}"
            return 真, "已激活（幂等复用）"
        if 指针 is None:
            # #161（2026-09-20）：首次激活原为无条件 `写入记录`（UPSERT）—— 两个并发首次激活
            # 会「后写覆盖先写」且**都报成功**（无 CAS 的经典竞态，首建版本号/栅栏令牌也会被
            # 对方抹掉）。改用状态层 `原子插入`（`INSERT OR IGNORE`）：只有仍不存在时才建立指针，
            # 「判存在 + 写入」由唯一约束在单事务内原子完成。
            if not self.状态.原子插入("激活指针", {"指针id": 包id, "目标": 目标,
                                                "版本": 1, "栅栏令牌": 1, "状态": "激活"}):
                # 已被并发抢先建立 → 读回核对（不覆盖对方的指针）
                指针 = self.状态.读取记录("激活指针", "指针id", 包id)
                if 指针 is None or 指针["目标"] != 目标:
                    对方 = 指针["目标"][:12] if 指针 else "未知"
                    return 假, f"首次激活竞态：指针已被并发建立为 {对方}…，拒绝覆盖"
                # 目标一致 → 与上方幂等分支同口径
                if not self.状态.条件更新("发布", {"激活指针": 目标, "状态": "完成"},
                                          "发布id=? AND 状态 IN ('准备','完成')", (发布id,)):
                    return 假, f"发布已回滚，拒绝幂等激活复活: {发布id}"
                return 真, "已激活（并发幂等复用）"
        else:
            新版本 = int(指针["版本"]) + 1
            新令牌 = int(指针["栅栏令牌"]) + 1
            成功 = self.状态.条件更新(
                "激活指针", {"目标": 目标, "版本": 新版本, "栅栏令牌": 新令牌, "状态": "激活"},
                "指针id=? AND 版本=? AND 栅栏令牌=?", (包id, 指针["版本"], 指针["栅栏令牌"]))
            if not 成功:
                return 假, "激活指针 CAS 失败（陈旧监督器被拒）"
        # 完成：必须带状态护栏（B-23 ②）。无护栏时，与并发 回滚 交错会把
        # 「已回滚」改写成「完成」，产生互斥终态同时成立；护栏保证只有仍处于
        # 「准备」的本事务能落完成，交错时如实返回失败（由 对账/恢复 收口）。
        完成成功 = self.状态.条件更新("发布", {"激活指针": 目标, "状态": "完成"},
                                      "发布id=? AND 状态='准备'", (发布id,))
        if not 完成成功:
            return 假, (f"发布状态在激活过程中被并发修改（如回滚），未落完成态: {发布id}")
        return 真, "已激活"

    def 切换激活指针(self, *, 指针id: str, 目标: str, 期望版本: int,
                     期望令牌: int) -> tuple[bool, str]:
        """通用激活指针切换（核心快照/组件通用）：陈旧令牌被拒。"""
        成功 = self.状态.条件更新(
            "激活指针", {"目标": 目标, "版本": 期望版本 + 1, "栅栏令牌": 期望令牌 + 1, "状态": "激活"},
            "指针id=? AND 版本=? AND 栅栏令牌=?", (指针id, 期望版本, 期望令牌))
        if not 成功:
            return 假, "陈旧栅栏令牌切换被拒"
        return 真, "指针已切换"

    def 当前激活(self, 指针id: str) -> dict[str, Any] | None:
        return self.状态.读取记录("激活指针", "指针id", 指针id)

    # ---- 恢复与对账（强杀后重启继续） ----
    def 恢复未完成发布(self) -> list[str]:
        """重启恢复：状态=准备/灰度的发布 → 幂等完成或回滚到明确版本。

        强杀在激活前后注入：指针要么已切（新版完成）、要么未切（旧版回滚），
        不存在半激活（指针切换是单条原子 UPDATE）。
        """
        恢复表 = []
        for 记录 in self.状态.查询记录("发布", "状态 IN ('准备','灰度')"):
            包id = 记录["包id"]
            指针 = self.状态.读取记录("激活指针", "指针id", 包id)
            目标 = 记录["激活指针"]
            if 指针 is not None and 目标 and 指针["目标"] == 目标:
                # 指针已切到新目标 → 完成
                # #160（2026-09-20）：原 `WHERE 发布id=?` 无状态护栏，与上方激活路径
                # （`AND 状态 IN ('准备','完成')`）口径不一致 —— 并发交错时会把别的流程
                # 已推进到「已回滚/其他终态」的发布**覆盖**成「完成」。补同一口径护栏：
                # 只有仍处于恢复可触及的中间态才允许改，否则如实回报未改动。
                if not self.状态.条件更新("发布", {"状态": "完成"},
                                          "发布id=? AND 状态 IN ('准备','灰度')", (记录["发布id"],)):
                    恢复表.append(f"{记录['发布id']}:跳过（状态已非准备/灰度，未覆盖）")
                else:
                    恢复表.append(f"{记录['发布id']}:完成({目标[:12]}…)")
            else:
                # 指针未切 → 回滚为期望（明确旧版）
                if not self.状态.条件更新("发布", {"状态": "已回滚",
                                                "回滚事务": json.dumps({"恢复回滚": 真})},
                                        "发布id=? AND 状态 IN ('准备','灰度')", (记录["发布id"],)):
                    恢复表.append(f"{记录['发布id']}:跳过（状态已非准备/灰度，未覆盖）")
                else:
                    恢复表.append(f"{记录['发布id']}:回滚")
        return 恢复表

    def _留对账告警(self, *, 主题: str, 内容: dict) -> None:
        """对账分歧必须留**告警证据**（B-23 ③）：越权切换指针不再无声合法化。

        证据走唯一证据账本入口追加写（不可覆盖）。状态实现没有证据能力时退化为
        无操作，但**对账表**照旧报告分歧 —— 不因留证能力缺失而隐瞒分歧。
        """
        追加 = getattr(self.状态, "追加证据", None)
        if callable(追加):
            追加(类型="对账告警", 主题=主题, 内容=内容,
                 调用者="发布管理.对账", 角色="控制面", 结果="按实际修复期望")

    def 对账(self) -> list[str]:
        """控制面恢复对账：期望状态（发布记录）vs 实际状态（激活指针）逐项核对。

        **语义唯一口径（B-23 ③）**：分歧时以**实际激活指针**为准回写期望记录，
        同时对每次分歧追加 `对账告警` 证据。取这个方向的原因：激活指针是数据面
        **正在服务**的真实状态（单调版本 + 栅栏令牌 CAS），控制面停机期间数据面
        可以合法前进；反向把实际指针改回期望，等于让对账去热切换运行中的系统。
        原实现的错不在方向，而在「注释写以期望为准、代码以实际为准」且**不落任何
        告警**：越权切换指针被静默洗白。现在语义与注释一致，且分歧必留证据。
        若要改成「以期望为准回写激活指针」，必须同步改
        `平台控制面/提供者/控制面对账.py`（按 `修正:` 前缀统计修正项）与
        `测试中心/平台控制面/测试_补修阻断.py::test_控制面对账修复不一致`，
        超出本包边界，另行立项。
        """
        对账表 = []
        for 记录 in self.状态.查询记录("发布", "状态='完成'"):
            包id = 记录["包id"]
            指针 = self.状态.读取记录("激活指针", "指针id", 包id)
            if 指针 is None:
                对账表.append(f"缺指针:{包id}")
                self._留对账告警(主题=包id, 内容={"分歧": "缺激活指针",
                                                 "期望": 记录["激活指针"], "实际": ""})
                continue
            if 记录["激活指针"] and 指针["目标"] != 记录["激活指针"]:
                # 实际与期望不一致：先留告警证据，再以实际为准修复期望记录
                self._留对账告警(主题=包id, 内容={"分歧": "激活指针与期望不一致",
                                                 "期望": 记录["激活指针"],
                                                 "实际": 指针["目标"],
                                                 "指针版本": 指针["版本"],
                                                 "栅栏令牌": 指针["栅栏令牌"]})
                成功 = self.状态.条件更新("发布", {"激活指针": 指针["目标"]},
                                        "发布id=? AND 状态='完成'", (记录["发布id"],))
                if not 成功:
                    对账表.append(f"修正失败（记录已被并发修改）:{包id}")
                    continue
                对账表.append(f"修正:{包id}:{指针['目标'][:12]}…")
        # 清理无主激活指针（无对应发布记录）
        for 指针 in self.状态.查询记录("激活指针"):
            有发布 = self.状态.查询记录("发布", "包id=? AND 状态='完成'", (指针["指针id"],))
            if not 有发布 and 指针["状态"] == "回滚":
                对账表.append(f"保留回滚指针:{指针['指针id']}")
        return 对账表

    def 回滚(self, *, 发布id: str, 回滚目标: str, 调用者: str = "") -> tuple[bool, str]:
        """回滚：切换指针到回滚目标，保留历史发布记录（证据不删）。"""
        记录 = self.状态.读取记录("发布", "发布id", 发布id)
        if 记录 is None:
            return 假, "发布不存在"
        指针 = self.状态.读取记录("激活指针", "指针id", 记录["包id"])
        if 指针 is None:
            return 假, "无激活指针可回滚"
        成功 = self.状态.条件更新(
            "激活指针", {"目标": 回滚目标, "版本": int(指针["版本"]) + 1,
                        "栅栏令牌": int(指针["栅栏令牌"]) + 1, "状态": "回滚"},
            "指针id=? AND 版本=? AND 栅栏令牌=?", (记录["包id"], 指针["版本"], 指针["栅栏令牌"]))
        if not 成功:
            return 假, "回滚 CAS 失败"
        self.状态.条件更新("发布", {"回滚事务": json.dumps({"回滚到": 回滚目标, "时间": time.strftime("%Y-%m-%d %H:%M:%S")}),
                                  "状态": "已回滚"}, "发布id=?", (发布id,))
        return 真, f"已回滚到 {回滚目标}"
