"""二阶恢复校验：恢复进程自身被强杀后的幂等恢复校验（生产校验模块）。

背景：一阶强杀（发布激活中途被杀）由 发布管理.恢复未完成发布() 恢复；
本模块补二阶场景——恢复未完成发布 执行过程中（恢复动作提交后、恢复
证据写入前）恢复进程自身被 kill -9。再次启动恢复必须幂等：
- 落点唯一：指针明确旧版或新版，发布状态明确完成或已回滚（无半激活）；
- 证据不覆盖：证据表中原有证据记录 内容/哈希 逐字节不变，只是新增恢复证据。

恢复动作一律调用 发布管理.恢复未完成发布()（正式入口，禁止复制简化实现）。
"""
from __future__ import annotations

import sys
import time
from pathlib import Path
from typing import Any

_系统根 = Path(__file__).resolve()
for _祖先 in _系统根.parents:
    if (_祖先 / "平台控制面").is_dir():
        _系统根 = _祖先
        break
if str(_系统根) not in sys.path:
    sys.path.insert(0, str(_系统根))

from 平台控制面.发布管理 import 发布管理


def 写入恢复证据(状态, *, 发布id: str, 恢复动作: str, 调用者: str = "二阶恢复校验") -> str:
    """恢复证据追加写：证据表只追加，永不覆盖已有记录。"""
    return 状态.追加证据(
        类型="恢复", 主题=发布id,
        内容={"恢复动作": 恢复动作, "时间": time.strftime("%Y-%m-%d %H:%M:%S")},
        操作id=发布id, 调用者=调用者, 来源快照="二阶恢复强杀", 结果=恢复动作)


def 幂等恢复校验(状态, 发布id: str, 期望版本: str, *, 调用者: str = "") -> dict[str, Any]:
    """重复调用 恢复未完成发布() 完成恢复并校验；不满足断言即抛 AssertionError。"""
    服务 = 发布管理(状态)
    记录 = 状态.读取记录("发布", "发布id", 发布id)
    if 记录 is None:
        raise ValueError(f"发布不存在: {发布id}")
    包id = 记录["包id"]
    前快照 = {行["证据id"]: (行["内容"], 行["哈希"]) for 行 in 状态.查询证据(限制=1000)}
    # 第一轮：正式恢复入口（真实提交 完成/回滚）
    恢复表一 = 服务.恢复未完成发布()
    记录一 = 状态.读取记录("发布", "发布id", 发布id)
    if 记录一 is None or 记录一["状态"] not in ("完成", "已回滚"):
        raise AssertionError(f"恢复后发布状态不明确: {记录一}")
    # 恢复动作提交后写入恢复证据（只新增，不覆盖）
    恢复动作 = "完成" if 记录一["状态"] == "完成" else "回滚"
    写入恢复证据(状态, 发布id=发布id, 恢复动作=恢复动作, 调用者=调用者)
    # 第二轮与第三轮：幂等（恢复结果稳定、状态逐字段不变）
    指针一 = 状态.读取记录("激活指针", "指针id", 包id)
    发布一 = 状态.查询记录("发布")
    恢复表二 = 服务.恢复未完成发布()
    指针二 = 状态.读取记录("激活指针", "指针id", 包id)
    发布二 = 状态.查询记录("发布")
    恢复表三 = 服务.恢复未完成发布()
    if 恢复表二 or 恢复表三 or 指针一 != 指针二 or 发布一 != 发布二:
        raise AssertionError(f"重复恢复结果不稳定: {恢复表二} {恢复表三}")
    # 指针必须落在明确版本（旧版或新版），无半激活
    指针 = 指针二
    if 指针 is None or 指针["状态"] != "激活" or not 指针["目标"]:
        raise AssertionError(f"指针未落在明确激活版本: {指针}")
    目标 = 指针["目标"]
    if not [r for r in 发布二 if r["状态"] == "完成" and r["激活指针"] == 目标]:
        raise AssertionError(f"半激活: 指针 {目标} 无对应完成记录")
    if any(r["状态"] == "已回滚" and r["激活指针"] == 目标 for r in 发布二):
        raise AssertionError(f"半激活: 已回滚记录指向激活指针 {目标}")
    # 证据链不覆盖：原有证据逐字节不变，只新增恢复证据
    后快照 = {行["证据id"]: (行["内容"], 行["哈希"]) for 行 in 状态.查询证据(限制=1000)}
    新增数 = 0
    for 证据id, 签名 in 后快照.items():
        if 证据id in 前快照:
            if 签名 != 前快照[证据id]:
                raise AssertionError(f"证据被覆盖: {证据id}")
        else:
            新增数 += 1
    if 新增数 == 0:
        raise AssertionError("恢复证据未新增")
    新证据表 = [行 for 行 in 状态.查询证据(限制=1000) if 行["证据id"] not in 前快照]
    if any(行["类型"] != "恢复" for 行 in 新证据表):
        raise AssertionError("新增证据不是恢复证据")
    return {"恢复表一": 恢复表一, "恢复动作": 恢复动作, "幂等": True,
            "发布状态": 记录一["状态"], "指针目标": 目标,
            "指针版本": 指针["版本"], "栅栏令牌": 指针["栅栏令牌"],
            "原有证据未覆盖": True, "新增恢复证据数": 新增数,
            "期望版本": 期望版本, "指针符合期望": 目标 == 期望版本}
