def 标题行表(文本: str) -> dict[int, str]:
    """markdown **二至四级标题**的「行号（自 1 起）→ 标题文本」表 —— 转调唯一腿。

    **为什么转调**（哲学 1.2「一类事情只有一条腿」）：markdown 标题语法（`#{1,6}` 前缀）
    只该有一处实现。本模块原先自持 `标题行 = re.compile(r"^(#{2,4})\\s+(.*)$")`，被
    `开发工具.验证门禁.同动作双路径检测` 规则六判为「与 `办公文档支持库.轻量文本解析`
    重复的实现面第二条腿」（存量基线内）。收口口径同
    `开发工具/MD文档生成/说明书/合并重生成.py::_二级标题文本`（2026-09-23）与
    `开发工具/MD文档生成/文档类型_债务清单.py`（2026-09-22）：标题识别一律转调该原子能力，
    本模块只保留**业务判据**（「二至四级标题 = 能力段边界」这条层级选择是说明书体例约定，
    不是 markdown 语法）。

    **判据不变**：旧正则的 `#{2,4}` 就是层级 2..4；唯一腿用 `属性.level` 给层级、`文本`
    给标题，故过滤条件取 `2 <= level <= 4`，与旧口径逐字对应。

    **fail-closed**：能力调用失败即 raise，不退回手写正则、不静默判「无标题」——
    判不出标题会把整份说明书判成「缺能力段」，正是本门禁要堵的静默路径。
    """
    from 支持库.后端.办公文档支持库.轻量文本解析 import 解析Markdown块

    结果 = 解析Markdown块(文本, "完整")
    if not 结果.成功:
        raise RuntimeError(
            f"轻量文本解析.解析Markdown块 调用失败：{结果.错误码}：{结果.错误说明}")
    出: dict[int, str] = {}
    for 块 in ((结果.值 or {}).get("块列表") or []):
        属性 = 块.get("属性") or {}
        if 属性.get("章节") != "heading":
            continue
        层级 = 属性.get("level")
        if isinstance(层级, int) and 2 <= 层级 <= 4:
            出[int(块.get("行起") or 0)] = str(块.get("文本") or "")
    return 出


def _表格行(行: str) -> list[str] | None:
    """markdown 表行 → 单元格列表；非表行返回 None。"""
    匹配 = 表头行.match(行)
    if 匹配 is None:
        return None
    格 = [单元.strip() for 单元 in 匹配.group(1).split("|")]
    if 格 and all(set(单元) <= {"-", ":"} and 单元 for 单元 in 格):
        return None  # 分隔行
    return 格


def _清单形(格: list[str]) -> bool:
    """该表行是否是「能力清单」行（首格是能力 id）。"""
    return bool(格) and bool(能力id形.fullmatch(格[0])) and "." in 格[0]


def _是表头行(格: list[str]) -> bool:
    """markdown 表头行判定：首格是列名族、第二格是它的**元信息列名**。

    为什么必须两格一起判：``错误码`` 既可能是列名（``| 错误码 | 触发条件 |``），
    也可能是**参数名**（``平台控制面.平台状态.追加证据`` 的参数里就有 ``错误码``：
    ``| 错误码 | 文本型 | 否 | … |``）。只看首格会把参数行当表头，整张参数表就丢了；
    只看第二格会把任何以「类型」结尾的中文列当表头。两格同时命中的集合才是表头。

    单列表头（``| 错误码 |`` + 下方逐行码，见 ``平台控制面/平台状态`` 与
    ``平台控制面/包仓库`` 的既有体例）也认：那种表只有一列，第二格不存在。
    """
    列名族 = {"参数", "入参", "错误码", "字段", "值字段", "返回", "返回结构"}
    if len(格) == 1:
        return 格[0] in 列名族
    return (len(格) >= 2 and 格[0] in 列名族
            and 格[1] in {"类型", "说明", "含义", "默认值", "触发条件"})


def _解析参数散文(文本: str) -> dict[str, tuple[str | None, bool | None]]:
    """把散文式参数描述解析成 ``{名称: (类型, 必填)}``（两种既有写法）。

    - A支/清单表写法：``身份id:文本型（必填），所有者:文本型``
    - 金标记法：``临时根目录(文本型,必填)、清单路径(文本型,必填)``
    解析不出的片段**不猜**（不计入），解析结果只用于「名称集合/类型/必填」三类比对；
    名称集合这一档对本函数是可判的，类型与必填在写法缺失时为 ``None``（不比）。
    """
    出: dict[str, tuple[str | None, bool | None]] = {}
    for 片段 in re.split(r"[，,、;；]", 文本 or ""):
        片段 = 片段.strip().strip("`")
        if not 片段 or 片段 in {"无", "（无）", "(无)"}:
            continue
        冒号 = re.match(r"^([^:：()（）]+)[:：]\s*(.*)$", 片段)
        if 冒号:
            名称 = 冒号.group(1).strip()
            尾 = 冒号.group(2).strip()
            必填 = None
            if 尾.endswith(("（必填）", "(必填)")):
                必填 = True
                尾 = 尾[: -len("（必填）")].strip() if 尾.endswith("（必填）") else 尾[: -len("(必填)")].strip()
            elif 尾.endswith(("（可选）", "(可选)")) or "默认" in 尾:
                必填 = False
            类型 = 尾.split("，")[0].split(",")[0].strip()
            if 名称:
                出.setdefault(名称, (类型 or None, 必填))
            continue
        括号 = re.match(r"^([^()（）、]+)[（(]([^()）]+)[)）]\s*$", 片段)
        if 括号:
            名称 = 括号.group(1).strip()
            内 = 括号.group(2)
            件 = [项.strip() for 项 in re.split(r"[，,]", 内)]
            类型 = 件[0] or None
            必填 = None
            if any(项 == "必填" for 项 in 件[1:]):
                必填 = True
            elif any(项 in {"可选", "非必填"} for 项 in 件[1:]):
                必填 = False
            if 名称:
                出.setdefault(名称, (类型, 必填))
            continue
    return 出


def _说明书包级版本(头部行: list[str], 全文行: list[str]) -> str | None:
    """包级版本：首个 ``- 版本：X``（在第一个标题之前）或包级表 ``| 版本 | X |``。"""
    for 行 in 头部行:
        匹配 = 版本行.match(行)
        if 匹配:
            return 匹配.group(1)
    for 行 in 全文行:
        格 = _表格行(行)
        if 格 and len(格) >= 2 and 格[0] in {"版本", "包版本"}:
            return 格[1]
    return None


def _段内载位(行列表: list[str]) -> dict:
    """一个能力段落内的字段载位：版本/参数/必填/错误码/返回。

    ``错误码原文`` 是错误码载体的**逐字文本**（既有体例里码后面常跟一句说明，
    如 ``参数不合法（命令不是列表…）``，甚至把码写在句子里）。逐字文本只在**该能力段内**
    参与「码是否出现」判定，不扩到整份文档——那是原来的子串后门。
    """
    载位 = {"版本": None, "参数": {}, "必填": {}, "默认值": {}, "错误码": set(),
            "错误码原文": [], "返回": set(), "参数载体": False}
    表头: list[str] = []
    for 行 in 行列表:
        匹配 = 版本行.match(行)
        if 匹配 and 载位["版本"] is None:
            载位["版本"] = 匹配.group(1)
            continue
        匹配 = 参数列表行.match(行)
        if 匹配:
            载位["参数载体"] = True
            for 名称, (类型, 必填) in _解析参数散文(匹配.group(1)).items():
                载位["参数"].setdefault(名称, 类型)
                if 必填 is not None:
                    载位["必填"].setdefault(名称, 必填)
            continue
        匹配 = 必填参数行.match(行)
        if 匹配:
            载位["参数载体"] = True
            for 名称 in 匹配.group(1).split(", "):
                名称 = 名称.strip()
                if 名称 and 名称 != "无":
                    载位["必填"][名称] = True
            continue
        匹配 = 错误码行.match(行)
        if 匹配:
            原文 = 匹配.group(1)
            载位["错误码原文"].append(原文)
            for 名称 in 错误码分隔.split(原文):
                名称 = 名称.strip().split("（")[0].split("(")[0].strip()
                if 名称 and 名称 not in {"无", "（无）"}:
                    载位["错误码"].add(名称)
            continue
        for 正则, 键 in ((返回结构行, "返回"), (返回结构粗体行, "返回")):
            匹配 = 正则.match(行)
            if 匹配:
                载位["返回"].update(_返回类型名(匹配.group(1)))
                break
        格 = _表格行(行)
        if 格 is None:
            continue
        if _是表头行(格):
            表头 = 格
            continue
        if 表头 and 表头[0] == "参数" and len(格) >= 3:
            载位["参数载体"] = True
            载位["参数"].setdefault(格[0], 格[1] or None)
            if 格[2] in {"是", "否"}:
                载位["必填"].setdefault(格[0], 格[2] == "是")
            # #126（2026-09-23）：参数表**有「默认值」列**时把该格也记成载位。
            # 此前逐参数只比名称/类型/必填，参数表默认值写错门禁恒绿（实测事故见债务行 126）。
            # 列位按**表头列名**定位（不钉第 4 列）：既有体例有 4 列
            # （参数|类型|必填|说明）与 5 列（参数|类型|必填|默认值|说明）两种。
            if "默认值" in 表头:
                位置 = 表头.index("默认值")
                if 位置 < len(格):
                    载位["默认值"].setdefault(格[0], 格[位置])
            continue
        if 表头 and 表头[0] == "错误码":
            名称 = 格[0].strip().split("（")[0].strip()
            if 名称 and 名称 != "无":
                载位["错误码"].add(名称)
            载位["错误码原文"].append(" ".join(格))
            continue
    return 载位


