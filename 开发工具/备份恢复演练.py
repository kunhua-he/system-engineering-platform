def _调用(能力id: str, 参数: dict) -> Any:
    """经唯一能力调用入口调用平台控制面公开能力；不成功即抛错（不静默降级）。"""
    global _后端
    if _后端 is None:
        from 后端核心.后端核心 import 后端核心

        _后端 = 后端核心(系统根目录=系统根)
        if not _后端.启动().成功:
            raise RuntimeError("后端核心装配失败，演练无法开始")
    结果 = _后端.调用(能力id, 参数)
    if not 结果.成功:
        raise RuntimeError(f"{能力id} 调用失败：{结果.错误码} {结果.错误说明}")
    return 结果.值


def _只读一处(库: Path, SQL: str, 参数: tuple) -> list:
    """只读一次并立即关闭连接：留在打开态会挡住恢复能力的 `BEGIN EXCLUSIVE` 独占锁。"""
    with contextlib.closing(sqlite3.connect(只读库URI(库), uri=True, timeout=10)) as 连接:
        return 连接.execute(SQL, 参数).fetchall()


def _灌注(源根: Path, 规模: int) -> float:
    """按规模经真实能力把 句柄 + 证据 灌进源副本，返回秒数；规模=0 即零耗时空转。"""
    起 = time.perf_counter()
    for 序号 in range(规模):
        时刻 = time.strftime("%Y-%m-%d %H:%M:%S")
        _调用("平台控制面.平台状态.写入记录", {
            "存储目录": str(源根), "表": "句柄", "主键": "句柄id",
            "记录": {"句柄id": f"演练句柄{序号:06d}", "句柄类型": "资源", "资源id": f"资源{序号:06d}",
                     "项目id": "演练", "所有者": "小马仔", "状态": "有效", "版本": "1",
                     "创建时间": 时刻, "失效时间": "", "失效原因": "", "进程身份键": ""}})
        _调用("平台控制面.平台状态.追加证据", {"存储目录": str(源根), "类型": "备份恢复演练",
                                           "主题": "规模灌注", "内容": {"序号": 序号, "时刻": 时刻}})
    return round(time.perf_counter() - 起, 4)


def _合并生产根(合并目录: Path) -> Path:
    """把三类数据的**各自权威宿主**汇到一处，返回合并后的生产根（供 建源副本 逐类取用）。

    为什么需要合并（2026-09-20 修 #63）：三类数据本来就不共用一个目录 —— 权威状态/证据账本
    住 `平台控制面/平台状态` 的默认存储目录，包仓库住 `工程缓存/制品仓库`（与前者**平级**）。
    旧版把 `解析运行数据根()` 当成「三类共用的生产数据根」，两处都不在那儿，于是报告里
    常年写着「缺 `制品/`」—— 那是**取错根**的症状，不是生产不产出。

    **怎么取**：经唯一能力调用入口调 `平台控制面.备份恢复.查询备份源根`（只读自省），
    拿「该发哪个根」的权威答复 —— 不在本文件里复制第二份根口径（哲学第 1 条）；`开发工具`
    层也不得 import `平台控制面`，只能按能力 id 调。

    **怎么合并**：状态库与制品用**符号链接**指过去（不搬 877M 制品、不复制大库），
    证据账本同理；链接目标不可用（跨卷等）时退回真实复制。合并目录落受管临时根内，
    退出即清理，不污染生产。
    """
    根表 = _调用("平台控制面.备份恢复.查询备份源根", {"存储根目录": ""})["类根表"]
    来源根 = {项["类"]: Path(项["根目录"]) for 项 in 根表}
    print(f"生产侧逐类根：{json.dumps({k: str(v) for k, v in 来源根.items()}, ensure_ascii=False)}")
    合并目录.mkdir(parents=True, exist_ok=True)

    def _链或复制(源: Path, 目标: Path) -> bool:
        """优先软链（省时省盘），失败即真实复制。返回是否链成功。"""
        if 目标.exists() or 目标.is_symlink():
            return 目标.is_symlink()
        try:
            目标.symlink_to(源, target_is_directory=源.is_dir())
            return 真
        except OSError:
            if 源.is_file():
                shutil.copy2(源, 目标)
            elif 源.is_dir():
                shutil.copytree(源, 目标, dirs_exist_ok=True, symlinks=True)
            return 假

    _链或复制(来源根["权威状态"] / "权威状态.db", 合并目录 / "权威状态.db")
    _链或复制(来源根["包仓库"], 合并目录 / "制品")
    return 合并目录


def 演练(是否反向验证: bool = False, 规模: int = 0, 生产根: Path | None = None) -> dict:
    """一键演练主流程：副本 →（可选按规模灌注）→ 备份 → 校验 → 恢复 → 逐类核对 → 实测 RPO/RTO。"""
    临时 = Path(tempfile.mkdtemp(prefix="备份恢复演练_"))
    临时根表.add(临时)
    源根, 恢复根, 备份根 = 临时 / "源副本", 临时 / "恢复副本", 临时 / "备份"
    生产根 = Path(生产根) if 生产根 else _合并生产根(临时 / "生产侧")
    来源 = 建源副本(生产根, 源根, 系统根 / 制品夹具相对路径)
    存储 = {"存储根目录": str(源根)}
    灌注秒 = _灌注(源根, 规模)
    写入 = _调用("平台控制面.平台状态.追加证据",
               {"存储目录": str(源根), "类型": "备份恢复演练", "主题": "B7演练",
                "内容": {"动作": "演练写入", "时刻": time.strftime("%Y-%m-%d %H:%M:%S")}})
    起 = time.perf_counter()
    备份清单 = _调用("平台控制面.备份恢复.执行备份", {"备份目录": str(备份根), **存储})["清单"]
    备份秒 = round(time.perf_counter() - 起, 4)
    起 = time.perf_counter()
    校验 = _调用("平台控制面.备份恢复.校验备份", {"备份目录": str(备份根), **存储})
    校验秒 = round(time.perf_counter() - 起, 4)
    起 = time.perf_counter()
    恢复 = _调用("平台控制面.备份恢复.恢复备份", {"备份目录": str(备份根), "目标目录": str(恢复根), **存储})
    RTO = round(time.perf_counter() - 起, 4)
    恢复时刻 = time.time()
    起 = time.perf_counter()
    核对 = 核对一致性(源根, 恢复根)
    核对秒 = round(time.perf_counter() - 起, 4)
    回到副本 = bool(_只读一处(恢复根 / "权威状态.db", "select 证据id from 证据 where 证据id=?",
                            (写入["证据id"],)))
    恢复点 = 备份清单["备份时间"]
    结果 = {"生产数据根": str(生产根), "受管临时根": str(临时), "逐类来源": 来源, "备份清单": 备份清单,
            "校验": 校验, "校验耗时秒": 校验秒, "恢复成功": bool(恢复["成功"]), "恢复结果": 恢复["结果"],
            "恢复状态": str(恢复.get("状态", "")), "恢复未核验": bool(恢复.get("是否未核验")),
            "恢复状态说明": str(恢复.get("状态说明", "")),
            "恢复回退警告": 恢复.get("回退警告", ""), "契约恢复时限秒": 备份清单["契约"]["权威状态"]["恢复时限秒"],
            "实测RTO秒": RTO, "恢复加核对秒": round(RTO + 核对秒, 4), "核对耗时秒": 核对秒,
            "实测RPO秒": round(恢复时刻 - time.mktime(time.strptime(恢复点, "%Y-%m-%d %H:%M:%S")), 4),
            "恢复点解析度秒": 1, "规模": 规模, "灌注耗时秒": 灌注秒, "备份耗时秒": 备份秒,
            "备份字节": 备份清单["文件"]["权威状态"]["大小"], "演练写入证据id": 写入["证据id"],
            "演练写入证据已恢复到副本": 回到副本, "一致性核对": 核对}
    结果["一致"] = 核对["一致"] and 结果["恢复成功"] and 校验["通过"] and 回到副本
    结果["结论"] = "一致（三类数据逐类核对全绿，演练写入的证据已回到恢复副本）" if 结果["一致"] \
        else "不一致（存在差异或恢复/校验未全绿，逐条见差异列表）"
    if 是否反向验证:
        结果["反向验证"] = 跑反向验证(源根, 恢复根, 备份根, 存储,
                               lambda 参数: _调用("平台控制面.备份恢复.恢复备份", 参数))
        if not 结果["反向验证"]["符合预期"]:
            结果["一致"], 结果["结论"] = False, "不一致（反向验证未按预期变红/变绿）"
    return 结果


def 打印(结果: dict) -> None:
    """人读输出：实测数字在前，逐类核对结论随后。"""
    print(f"生产数据根 {结果['生产数据根']} → 受管临时根 {结果['受管临时根']}")
    print(f"逐类来源 {json.dumps(结果['逐类来源'], ensure_ascii=False)}")
    print(f"规模 {结果['规模']} 条（灌注 {结果['灌注耗时秒']}s）｜备份 {结果['备份耗时秒']}s"
          f"／{结果['备份字节']} 字节｜恢复点 {结果['备份清单']['备份时间']}")
    print(f"校验通过={结果['校验']['通过']}（{结果['校验']['原因']}，{结果['校验耗时秒']}s）"
          f"｜恢复成功={结果['恢复成功']}（状态：{结果['恢复状态']}"
          f"{'｜' + 结果['恢复状态说明'] if 结果['恢复未核验'] else ''}；"
          f"回退警告：{结果['恢复回退警告'] or '无'}）")
    print(f"★ 实测 RTO {结果['实测RTO秒']}s（含逐类真实校验；契约恢复时限 {结果['契约恢复时限秒']}s）"
          f"；恢复+核对 {结果['恢复加核对秒']}s")
    print(f"★ 实测 RPO {结果['实测RPO秒']}s（恢复时刻 − 备份恢复点；解析度仅 "
          f"{结果['恢复点解析度秒']}s；零数据损失的判据是下面三类全绿 + 写入证据已回到副本）")
    print(f"演练写入证据 {结果['演练写入证据id']} 已回到恢复副本：{结果['演练写入证据已恢复到副本']}")
    for 项 in 结果["一致性核对"]["类结果"]:
        print(f"  [{'绿' if 项['一致'] else '红'}] {项['类']}（{项['件数']} 行/条/文件）"
              f"{'；' + '；'.join(项['差异']) if 项['差异'] else ''}")
    if "反向验证" in 结果:
        反 = 结果["反向验证"]
        print(f"反向验证：弄坏后一致={反['破坏后一致']}（应 False，{len(反['破坏后差异'])} 条差异："
              f"{'；'.join(反['破坏后差异'][:3])}）→ 重新恢复成功={反['还原恢复成功']}"
              f" → 还原后一致={反['还原后一致']}（应 True）→ 符合预期={反['符合预期']}")
    print(f"结论：{结果['结论']}")


def _解析参数(参数: list[str]) -> tuple[dict, int]:
    """解析 `--规模 N / --反向验证 / --json`；未知开关与非法规模一律拒绝（返回码 2）。"""
    表: dict[str, Any] = {"反向验证": False, "json": False, "规模": 0}
    余 = list(参数)
    while 余:
        项 = 余.pop(0)
        if 项 == "--反向验证":
            表["反向验证"] = True
        elif 项 == "--json":
            表["json"] = True
        elif 项 == "--规模" and 余 and 余[0].isdigit():
            表["规模"] = int(余.pop(0))
        else:
            print(f"未知/非法参数：{项}；只支持 --规模 N / --反向验证 / --json，其余一律拒绝。")
            return 表, 2
    return 表, 0


def 入口() -> int:
    取值表, 码 = _解析参数(sys.argv[1:])
    if 码:
        return 码
    try:
        结果 = 演练(是否反向验证=取值表["反向验证"], 规模=取值表["规模"])
    except RuntimeError as 错误:
        print(f"演练无法开始：{错误}")
        return 4
    if 取值表["json"]:
        print(json.dumps(结果, ensure_ascii=False, indent=2))
    else:
        打印(结果)
    return 0 if 结果["一致"] else 3


if __name__ == "__main__":
    sys.exit(入口())
