"""备份恢复演练主入口（B7）：受管临时目录内一键「建副本 → 备份 → 校验 → 恢复到另一副本 → 逐类核对」，报实测 RPO/RTO。

现状（2026-09-18 二次审计 B7）：平台已有备份与恢复能力，但**没有一键演练、没有定期跑、
没有 RPO/RTO 实测数据**——「有备份」不等于「能恢复」。本入口补的就是这一环，全程只碰副本。

1. 受管临时根（`mkdtemp`，退出即清理）建**源副本**：**逐类从各自的权威宿主**取
   （状态/证据/锁 → `平台控制面.平台状态` 的默认存储目录；包仓库 → 包仓库包的
   `制品仓库缓存根()`，即 `工程缓存/制品仓库`），权威状态经只读 `VACUUM INTO` 一致性快照，
   其余三类真实复制或软链；某类确实没有时补**真实文件夹具**并逐类标注来源
   （见 `备份恢复演练核对.建源副本`）。

   ⚠️ **2026-09-20 修 #63**：旧版把 `解析运行数据根()`（= `工程缓存/运行数据`）当成
   「三类共用的生产数据根」，于是报告里长期写着「生产数据根缺 `制品/`」——
   实测那句话是**取错根**的症状，不是生产不产出：真实制品仓库有 15633 个文件、
   活状态库有 54 条证据，两处都不在 `运行数据` 下。取正确根之后，演练报告才反映真实保全能力。
2. 经**唯一能力调用入口**按能力 id 调 `平台控制面.备份恢复.执行备份` / `校验备份`。
3. 调 `恢复备份` 恢复到**另一个副本目录**，墙钟秒数 = 实测 **RTO**（该能力语义已含逐类真实校验）。
4. 三类数据逐类核对（行数 + 关键字段指纹），并断言「演练刚写入的证据确实回到恢复副本」。
5. 实测 **RPO** = 恢复时刻 − 备份恢复点（即「能恢复到最近多久前的状态」）。恢复点由备份清单写入，
   是**秒级字符串**，故 RPO 的解析度只有 1 秒；**数据损失量**另由「源/恢复副本逐表全行指纹一致 +
   演练写入那条证据逐字段存在」实测，缺一条即判红——两条一起看才是完整的「丢了多少」。
   `--规模 N`：先灌 N 条句柄 + N 条证据再演练，否则量出来的 RTO 只代表空库（生产权威状态库
   实测 22 张表、仅 2 行非空）。`--反向验证`：弄坏副本 → 必须变红；重新恢复 → 必须变绿。
   退出码：0 全绿／3 不一致／2 参数错／4 装配失败。

分工：本文件**只调度与输出**；核对算法与副本构建在 `开发工具/备份恢复演练核对.py`。
`开发工具` 层不允许 import `平台控制面`（`运行核心/依赖防火墙.py:允许依赖表`），故一律按能力 id 调用。
"""
