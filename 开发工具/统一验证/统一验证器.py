def _结构验证(报告: 验证报告) -> None:
    """结构验证：包声明 JSON 合法、目录七件套齐备（声明列表驱动）。"""
    from 运行核心.加载器.包发现.发现器 import 发现全部

    发现 = 发现全部(支持库根目录, 模块根目录)
    声明列表 = 发现.声明列表
    if not 声明列表:
        报告.记录未执行("结构验证", "未发现任何包")
        return
    for 声明 in 声明列表:
        包目录 = Path(声明.来源路径).parent
        for 必备 in ("实现", "说明", "能力契约", "验证场景引用.json", "完整性摘要.json", "__init__.py"):
            if not (包目录 / 必备).exists():
                报告.记录失败(f"{声明.包id} 缺少 {必备}")
        报告.记录通过(f"结构: {声明.包id}")
    for 问题 in 发现.问题列表:
        报告.记录失败(f"发现问题: {问题}")


def _契约验证(报告: 验证报告) -> None:
    """契约验证：能力声明与参数契约一致（声明列表驱动）。"""
    from 运行核心.加载器.包发现.发现器 import 发现全部

    声明列表 = 发现全部(支持库根目录, 模块根目录).声明列表
    for 声明 in 声明列表:
        包目录 = Path(声明.来源路径).parent
        契约路径 = 包目录 / "能力契约" / "参数契约.json"
        try:
            声明数据 = json.loads((包目录 / "包声明.json").read_text(encoding="utf-8"))
            契约 = json.loads(契约路径.read_text(encoding="utf-8")) if 契约路径.is_file() else {"能力契约": []}
        except (json.JSONDecodeError, OSError) as 错误:
            报告.记录失败(f"{声明.包id} 契约读取失败", str(错误))
            continue
        声明能力 = {能力["能力id"]: 能力 for 能力 in 声明数据.get("能力", [])}
        契约能力 = {条目["能力id"]: 条目 for 条目 in 契约.get("能力契约", [])}
        for 能力id in 声明能力:
            声明参数 = [参数.get("名称") for 参数 in 声明能力[能力id].get("参数", [])]
            契约参数 = [参数.get("名称") for 参数 in 契约能力.get(能力id, {}).get("参数", [])]
            if 声明参数 != 契约参数:
                报告.记录失败(f"{声明.包id}.{能力id}", f"声明参数 {声明参数} 与契约 {契约参数} 不一致")
            if 能力id not in 契约能力:
                报告.记录失败(f"{声明.包id}.{能力id}", "声明存在但契约缺失")
        if 声明能力:
            报告.记录通过(f"契约: {声明.包id}")


