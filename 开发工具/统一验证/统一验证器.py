def 验证执行(*, 目标: str, 范围: str) -> 验证报告:
    """执行一次验证，返回统一报告。"""
    报告 = 验证报告(目标=目标, 验证范围=范围)
    if 范围 == "结构":
        _结构验证(报告)
    elif 范围 == "契约":
        _契约验证(报告)
    elif 范围 == "资产":
        _资产验证(报告)
    elif 范围 == "装配":
        _装配验证(报告)
    elif 范围 == "加载器":
        _加载器验证(报告)
    elif 范围 == "示例项目":
        _示例项目验证(报告)
    elif 范围 == "项目适配":
        _项目适配验证(报告)
    else:
        报告.记录未执行("未知范围", f"范围 {范围} 不在 {范围列表}")
    return 报告


def _解析参数(argv: list[str] | None = None) -> argparse.Namespace:
    解析器 = argparse.ArgumentParser(description="系统级统一验证器")
    解析器.add_argument("--目标", default="项目", help="验证目标（第一版固定为 项目）")
    解析器.add_argument("--范围", required=True, choices=范围列表, help="验证范围")
    return 解析器.parse_args(argv)


def 主函数(argv: list[str] | None = None) -> int:
    参数 = _解析参数(argv)
    报告 = 验证执行(目标=参数.目标, 范围=参数.范围)
    print(报告.打印())
    return 0 if 报告.门禁通过 else 1


