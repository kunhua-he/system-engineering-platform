def _示例项目验证(报告: 验证报告) -> None:
    """示例项目验证：最小运行样板真实执行。"""
    import subprocess

    脚本路径 = 示例项目目录 / "示例项目.py"
    if not 脚本路径.is_file():
        报告.记录未执行("示例项目", "缺少 示例项目/示例项目.py")
        return
    进程 = subprocess.run(
        [sys.executable, str(脚本路径)],
        cwd=str(系统根), capture_output=True, text=True, timeout=120,
    )
    if 进程.returncode == 0 and "示例项目运行成功" in 进程.stdout:
        报告.记录通过("示例项目.运行")
    else:
        报告.记录失败("示例项目.运行", (进程.stderr or 进程.stdout)[-500:])


