#!/bin/bash
# 启动系统工程平台 HTTP 能力网关（只读能力发现，对外 40006）。
# 用法: ./开发工具/能力网关/启动能力网关.sh [端口] [地址]
# 接口: GET /能力/搜索  GET /能力/契约/{能力id}
# 注意: 执行统一走运行核心 40007 /网关/调用 —— 本网关**只读**，不是第二条执行腿。
# 变量名一律 ASCII（bash 不支持中文变量名；原脚本用 端口= 这类中文名，
# 直接 `bash 脚本` 会在第 7 行报 `端口=40006: command not found`，所以从没跑通过）。
set -euo pipefail
cd "$(dirname "$0")/../.."
PORT="${1:-40006}"
ADDR="${2:-127.0.0.1}"
mkdir -p 工程缓存
LOG="工程缓存/能力网关_${PORT}.log"
echo "启动 HTTP 能力网关: http://${ADDR}:${PORT}"
echo "接口: GET /能力/搜索  GET /能力/契约/{能力id}（执行统一走 40007 /网关/调用）"
echo "日志: ${LOG}"
exec python3.14 -m 开发工具.能力网关.能力网关 --端口 "${PORT}" --地址 "${ADDR}"
