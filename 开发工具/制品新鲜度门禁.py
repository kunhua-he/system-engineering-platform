#!/usr/bin/env python3.14
"""制品新鲜度门禁：**激活制品是不是由当前源码构建的**（开发循环里的可见性判据）。

为什么必须有这一项（2026-09-24 实测，批J）：
本仓的「运行」面按单腿铁律走**激活制品**（`工程缓存/制品仓库/平台客户端环境/`），
源码树的改动**不会自动进网关**。实测踩到的形态：批F 已把「任务表有界历史 + 释放句柄」
修进源码，但制品仍停在 `7dd1f57b`（**落后 HEAD 10 个提交**）⇒ 网关继续跑旧装配，
`任务表` 仍只写不删、fd 继续攒 —— 表现为「同一个 bug 修了两次」，
而**所有读数都是绿的**（健康 200 / 能力数对 / 装配告警空 / 编译口全绿），
比判红更危险。此前这条腿**只在发布门禁里**（`校验制品来源绑定` + `校验制品落后提交数`），
开发循环（`开发编译口`）看不见它 ⇒「源码已修、运行态未修」可以静默穿过每一次收工。

判据**一处不复制**（哲学 1.2「一类事情只有一条腿」）：本模块只做
「定位激活制品 + 转调发布门禁既有唯一腿 + 打印结论」，不新写任何比对逻辑：

- 制品定位 → `开发工具.发布门禁.运行发布门禁_制品验证.选择待验证制品`；
- 落后提交数 → 同模块 `计算制品落后提交数`（阈值同源 `制品落后提交阈值`，不另写数字）；
- 来源字节指纹 → 同模块 `校验制品来源绑定`。

为什么本项在 `开发编译口` 里是**只报告**而不是阻断（判据边界，如实留档）：
`校验制品来源绑定` 要求「制品来源提交 = 当前 HEAD」，而**提交这个动作本身就会移动 HEAD**
—— 制品只能在提交之后重建。故开发循环里「阻断」在结构上不可能自洽
（要提交就得先有制品，要有制品就得先提交）。阻断留在**发布门禁**（提交 → 重建 → 再发，
那条链是闭合的）；开发循环只负责把「落后几个提交」**说清楚**，不让它静默。

用法::

    python3.14 -m 开发工具.制品新鲜度门禁                 # 跑判据，打印 JSON，退出码 0/1
    python3.14 -m 开发工具.制品新鲜度门禁 --制品 <目录>    # 显式点名制品（反向验证用）

退出码：0 = 新鲜（落后不超阈值 且 来源字节指纹一致）；1 = 判红；2 = 用法错误。
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

仓库根 = Path(__file__).resolve().parents[1]


def 判定(制品目录: Path | None = None) -> dict:
    """结构化结论：激活制品是否由**当前源码**构建（全部判据转调发布门禁唯一腿）。"""
    from 开发工具.发布门禁.运行发布门禁_制品验证 import (
        制品落后提交阈值,
        校验制品来源绑定,
        校验制品落后提交数,
        选择待验证制品,
    )

    结论: dict = {"制品路径": "", "制品来源": "", "制品来源提交": "",
                  "落后提交数": None, "落后阈值": int(制品落后提交阈值),
                  "来源绑定通过": False, "来源绑定详情": "", "通过": False, "说明": ""}
    try:
        制品, 来源 = 选择待验证制品(制品目录)
    except Exception as 错误:  # noqa: BLE001 —— 定位不到即判红（fail-closed），不吞成「无对象可查」
        结论["说明"] = f"定位激活制品失败（{错误}）—— 判据取不到即判红（fail-closed）"
        return 结论
    结论["制品路径"] = str(制品)
    结论["制品来源"] = str(来源)

    通过, 详情 = 校验制品落后提交数(制品, 仓库根)
    结论["落后提交数"] = _落后数(制品)
    结论["制品来源提交"] = _来源提交(制品)
    绑定通过, 绑定详情, _身份 = 校验制品来源绑定(制品)
    结论["来源绑定通过"] = bool(绑定通过)
    结论["来源绑定详情"] = str(绑定详情)

    if not 通过:
        结论["说明"] = (f"{详情} ⇒ 网关跑的是旧装配：源码已改而运行态未改，"
                       "须「重建制品 + 重启网关」后再复验读数")
        return 结论
    if not 绑定通过:
        结论["说明"] = (f"制品落后提交数达标，但来源字节指纹与当前工作区不一致：{绑定详情}"
                       " ⇒ 运行态不是当前源码构建的")
        return 结论
    结论["通过"] = True
    结论["说明"] = f"制品新鲜：{详情}；来源字节指纹与当前工作区一致（{制品}）"
    return 结论


def _来源提交(制品目录: Path) -> str:
    """读 `制品来源.json` 的 `提交`（只回显，判据仍在发布门禁，不参与判定）。"""
    try:
        来源 = json.loads((Path(制品目录) / "制品来源.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return ""
    return str(来源.get("提交") or "") if isinstance(来源, dict) else ""


def _落后数(制品目录: Path) -> int | None:
    """落后提交数（只回显；判据本体在 `校验制品落后提交数`，本函数不另算一遍）。"""
    from 开发工具.发布门禁.运行发布门禁_制品验证 import 计算制品落后提交数
    数, _说明 = 计算制品落后提交数(Path(制品目录), 仓库根)
    return 数


def main(argv: list[str]) -> int:
    制品目录 = None
    if "--制品" in argv:
        下标 = argv.index("--制品")
        if 下标 + 1 >= len(argv):
            print(json.dumps({"成功": False, "错误说明": "--制品 需要跟一个目录"},
                             ensure_ascii=False))
            return 2
        制品目录 = Path(argv[下标 + 1])
    elif len(argv) > 0:
        print(json.dumps({"成功": False, "错误说明": f"未知参数：{' '.join(argv)}"},
                         ensure_ascii=False))
        return 2
    结论 = 判定(制品目录)
    结论["成功"] = bool(结论["通过"])
    print(json.dumps(结论, ensure_ascii=False))
    return 0 if 结论["通过"] else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
