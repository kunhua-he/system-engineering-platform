"""一次性落地脚本：把现场枚举到的真实跨包消费者关系登记成消费者契约，并生成基线。

用法（工程根下，`unset PYTHONPATH`）：
    python3.14 工程缓存/消费者登记落地.py            # 登记 + 生成基线 + 上报
    python3.14 工程缓存/消费者登记落地.py --只报      # 只报现场事实，不写盘

为什么放在 工程缓存（运行态目录，不入正式包摘要）：这是**一次性的落地工具**，
不是平台能力——按 1.6「临时脚本不留库」不留在正式目录里。登记动作本身走的是
包内唯一公开能力 `登记消费者契约`（登记契约的真实实现），脚本只做批量编排。

口径：
- 只登记**字段齐备**的关系（请求参数/示例、响应约束返回键/结构、错误码集、超时、
  释放要求 全部在声明面取得到）；字段取不到的关系**不登记**（登记半份契约等于
  给漂移门禁塞假证据），它们的清单由 判定消费者登记完整性 的 缺字段能力 如实给出。
- 已登记的关系不重复写（幂等；注册表侧同一消费者同一能力本就是覆盖写）。
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

工程根 = Path(__file__).resolve().parents[1]
if str(工程根) not in sys.path:
    sys.path.insert(0, str(工程根))

from 平台控制面.能力目录.实现.能力入口 import 登记消费者契约, 默认存储目录   # noqa: E402
from 平台控制面.能力目录.消费者契约注册表 import 消费者契约注册表          # noqa: E402
from 平台控制面.能力目录.消费者登记判定 import (                          # noqa: E402
    枚举正式包, 枚举消费者关系, 取能力契约, 消费者id, 判定登记完整性, 生成基线, 基线文件名,
)


def 主函数() -> int:
    解析器 = argparse.ArgumentParser(description="消费者契约登记落地（现场枚举 → 登记 → 基线）")
    解析器.add_argument("--只报", action="store_true", help="只报现场事实，不写盘")
    参数 = 解析器.parse_args()

    根 = 工程根
    包表 = 枚举正式包(根)
    关系 = 枚举消费者关系(根, 包表)
    注册表 = 消费者契约注册表.取实例(Path(默认存储目录))
    print(f"[现场] 正式包 {len(包表)} 个；跨包消费者关系 {len(关系)} 条；"
          f"涉及公开能力 {len({x['能力id'] for x in 关系})} 个、提供包 "
          f"{len({x['提供包'] for x in 关系 if x['提供包']})} 个")

    登记成功 = 0
    登记失败: list[str] = []
    跳过缺字段: list[dict] = []
    for 项 in 关系:
        鉴定 = 取能力契约(包表, 项["能力id"])
        if 鉴定["缺项"]:
            跳过缺字段.append({"能力id": 项["能力id"], "消费者包": 项["消费者包"],
                            "缺项": 鉴定["缺项"]})
            continue
        已有 = 注册表.查询契约(项["能力id"])
        记录表 = list(已有.get("数据") or []) if 已有.get("成功") else []
        if any(记录.get("消费者id") == 消费者id(项["消费者id"]) for 记录 in 记录表):
            登记成功 += 1
            continue
        if 参数.只报:
            登记成功 += 1
            continue
        结果 = 登记消费者契约(
            消费者id=消费者id(项["消费者id"]), 能力id=项["能力id"],
            契约=鉴定["当前契约"], 存储目录=默认存储目录)
        if 结果.成功:
            登记成功 += 1
        else:
            登记失败.append(f"{项['能力id']} <- {项['消费者包']}: {结果.错误说明}")
    print(f"[登记] 成功/已在册 {登记成功} 条；失败 {len(登记失败)} 条；"
          f"跳过（声明面字段取不到）{len(跳过缺字段)} 条")
    for 行 in 登记失败[:5]:
        print("   失败:", 行)

    if 参数.只报:
        print("[只报] 未写盘。")
        return 0

    事实 = 判定登记完整性(根, 注册表=注册表, 存储目录=默认存储目录, 包表=包表)
    print(f"[复核] 总关系 {事实['总关系数']}；已登记 {事实['已登记关系数']}；"
          f"缺登记 {事实['未登记关系数']}")
    print(f"[复核] 判定说明: {事实['判定说明']}")

    基线 = 生成基线(根, 注册表=注册表, 存储目录=默认存储目录, 包表=包表)
    基线路径 = 工程根 / "平台控制面" / "能力目录" / 基线文件名
    基线路径.write_text(json.dumps(基线, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[基线] 已写出 {基线路径}；计数 {json.dumps(基线['计数'], ensure_ascii=False)}；"
          f"基线内缺登记 {len(基线['关系基线'])} 条")
    return 0


if __name__ == "__main__":
    raise SystemExit(主函数())
