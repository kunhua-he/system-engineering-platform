def 读任务类型规范(根: Path | None = None) -> dict:
    """读任务类型规范字典；读不成即返回空（由生成器如实报「未命中」，不编造规范）。"""
    基 = Path(根) if 根 else 系统根
    try:
        return json.loads((基 / 任务类型规范路径).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, UnicodeDecodeError):
        return {}


def 匹配任务类型(任务文本: str, 规范: dict | None = None) -> list[dict]:
    """按「识别词出现在本次任务文本里」命中任务类型（方向不能反）。

    只回命中的类，不返回全量规范（省 token：实测命中类强规范 89–155 字符）。
    匹配方向**必须是「识别词在任务文本里」**：反过来（任务文本片段出现在识别词里）
    会误命中（实测「修一个报错」误命中「加新能力」）。
    """
    数据 = 规范 if 规范 is not None else 读任务类型规范()
    文本 = str(任务文本 or "")
    命中: list[dict] = []
    for 条目 in 数据.get("任务类型清单") or []:
        if not isinstance(条目, dict):
            continue
        词表 = [w for w in (条目.get("识别词") or []) if isinstance(w, str) and w]
        if not 词表:
            continue
        命中词 = [w for w in 词表 if w in 文本]
        if 命中词:
            命中.append({"任务类型": str(条目.get("任务类型") or ""),
                        "命中词": 命中词,
                        "强规范": list(条目.get("强规范") or []),
                        "判据": str(条目.get("判据") or ""),
                        "原文位置": str(条目.get("原文位置") or "")})
    命中.sort(key=lambda x: -len(x["命中词"]))
    return 命中


def 生成任务信(标题: str, 任务正文: str, 允许修改: list[str] | None = None,
              禁止修改: list[str] | None = None, 开工ID: str = "",
              记忆包路径: str = "", 根: Path | None = None) -> dict:
    """拼一封完整任务信；返回 `{任务信文本, 命中任务类型, 缺项, 字符数}`。

    `缺项` 非空即**这封信不合格**——调用方必须先补齐再派发（fail-closed：宁可不派，
    也不用一封缺纪律的信去烧一轮）。判据与检查项固定：
    ① 标题/正文非空；② 允许修改非空（否则子代理不知道该动什么）；③ 至少命中 1 类任务类型
    （没命中说明任务描述太含糊，要么写具体，要么去字典补该类，不编造）。
    """
    缺项: list[str] = []
    if not str(标题 or "").strip():
        缺项.append("标题为空")
    if not str(任务正文 or "").strip():
        缺项.append("任务正文为空")
    允许 = [str(x).strip() for x in (允许修改 or []) if str(x).strip()]
    # 「只读任务」是**合法任务类型**（核验/审计/盘点），显式写「只读」即认；
    # 空清单才判不合格（那才是「子代理不知道能改什么」的真歧义）。
    只读任务 = 允许 == ["只读"]
    if not 允许:
        缺项.append("允许修改清单为空（子代理无从知道该动什么；只读任务请显式写「只读」）")
    命中 = 匹配任务类型(f"{标题}\n{任务正文}", 读任务类型规范(根))
    if not 命中:
        缺项.append("未命中任何任务类型（任务描述太含糊，或该类型未登记在字典里）")

    段: list[str] = [f"# 任务：{str(标题).strip()}", ""]
    # 纪律标志放在最前（2026-09-19 修根因）：此前固定条款排在「任务正文」之后，
    # 长任务信里落在 8KB 处 —— 子代理最先读到的几百字里**看不到任何纪律**，
    # 而派活转录只记 kickoff 首行约 600 字符，连巡检判据也看不到 ⇒ 一份合格的信
    # 仍被判「纪律未送达」。放一行指针在最前，两件事一起解决：
    # ① 子代理第一眼就知道纪律在哪、有几段；② 巡检判据在首行即可命中标志串。
    段 += ["**本次任务固定纪律**：命令环境 / 工具姿势 / **文件租约（先认领再改）** / 提交纪律 / pathspec / 禁区 / "
          "落盘回传 / 自证如实 / 改完必做 / 收工返回 —— 全文见本信末「固定条款」各段，**逐条照做**。", ""]
    if 开工ID:
        段 += [f"**开工ID**：`{开工ID}`", ""]
    if 记忆包路径:
        段 += [f"**开工第一步**：读任务记忆包 `{记忆包路径}`（已核实事实包，先读它再动手）", ""]
    段 += ["## 任务正文", "", str(任务正文).rstrip(), ""]
    段 += ["## 允许修改（域白名单）", ""]
    if 只读任务:
        段 += ["- **本任务只读**：禁止修改任何仓库文件，禁止 `git add` / `git commit`；",
               "  结论只在最终回答里给出（不落盘、不新建文件）。"]
    else:
        段 += [f"- `{p}`" for p in 允许] or ["- （未给：本封信不合格，不要派发）"]
    禁止 = [str(x).strip() for x in (禁止修改 or []) if str(x).strip()]
    if 禁止:
        段 += ["", "## 禁止修改（在途/他人域）", ""]
        段 += [f"- `{p}`" for p in 禁止]
    段 += [""]
    if 命中:
        段 += ["## 本次任务强规范（按任务类型自动注入，细节按 原文位置 跳转）", ""]
        for 一 in 命中:
            段 += [f"### 任务类型：{一['任务类型']}（命中词：{'、'.join(一['命中词'])}）", ""]
            段 += [f"- {r}" for r in 一["强规范"]]
            if 一["判据"]:
                段 += ["", f"**判据**：{一['判据']}"]
            段 += [""]
    if 只读任务:
        # 只读任务不带「提交纪律 / 改完必做 / 落盘回传」三段 —— 那三段都要求写动作，
        # 与「禁止改任何文件」直接矛盾（实测子代理为此反复推敲，白耗一轮）。
        # 「收工与返回」照带：它只要求「跑完核对命令就写最终回答」，不要求任何写动作，
        # 而「做完了却不返回」对只读任务同样是超时首因。
        段 += [条款_命令环境, 条款_工具姿势, 条款_只读禁区, 条款_自证, 条款_收工返回]
    else:
        段 += list(固定条款段)
    文本 = "\n".join(段).rstrip() + "\n"
    return {"任务信文本": 文本, "命中任务类型": [x["任务类型"] for x in 命中],
            "命中任务类型明细": 命中, "缺项": 缺项, "字符数": len(文本)}


def 生成派发载荷(标题: str, 任务正文: str, 允许修改: list[str] | None = None,
                 禁止修改: list[str] | None = None, 开工ID: str = "",
                 记忆包路径: str = "", 根: Path | None = None) -> dict:
    """生成 **`delegate_task` 可直接投递**的 `{goal, context}`（华哥要的「省流程」）。

    为什么需要它（2026-09-18 实测根因）：生成器做出来了，但派活时手写 context 更快，
    结果整批 8 路 kickoff 里「工具姿势/提交纪律/pathspec/命令环境」命中 **全 0**；
    而**没有任何检查会因此报红**。判据挂在产出点 = 让「用生成器」比「手写」更省事：
    这里直接把固定条款 + 强规范拼进 `context`，调用方 `goal` 抄第一行、`context` 整段抄走即可。

    `goal` 用一句话（判据：子代理只看这一句也知道要交出什么）；`context` 是完整任务信。
    """
    信 = 生成任务信(标题=标题, 任务正文=任务正文, 允许修改=允许修改,
                  禁止修改=禁止修改, 开工ID=开工ID, 记忆包路径=记忆包路径, 根=根)
    return {
        "goal": str(标题).strip(),
        "context": 信["任务信文本"],
        "缺项": 信["缺项"],
        "命中任务类型": 信["命中任务类型"],
        "字符数": 信["字符数"],
        "可用": not 信["缺项"],
    }


def 自检任务信(文本: str) -> list[str]:
    """检查一封已写好的任务信缺哪些固定条款（给「手写信」用同一套判据）。

    **只读任务走另一套判据**：它合法地不带「提交纪律 / 改完必做 / 落盘回传」三段
    （那三段都要求写动作，与「禁止改任何文件」矛盾）。判据按任务性质分流，不是放宽。
    """
    缺: list[str] = []
    只读 = "**本任务只读**" in 文本
    if 只读:
        for 标题, 标志 in (
            ("命令环境", "python3.14"),
            ("命令环境", "单命令硬上限 15 秒"),
            ("命令环境", "不许 sleep"),
            ("工具姿势", "read_file"),
            ("只读禁区", "禁止修改任何仓库文件"),
            ("自证与如实", "真实命令输出"),
            ("收工与返回", "收工与返回"),
        ):
            if 标志 not in 文本:
                缺.append(f"缺固定条款段：{标题}（标志串 {标志!r} 未出现）")
        # 反向判据：只读信**不得**出现写入类条款（否则自相矛盾，子代理会反复推敲）。
        # ★ 判据口径修正（2026-09-19）：原先用「标志串」（pathspec / 全量重算摘要），
        # 但 `条款_收工返回` 的表一里**也会出现**这两个串（它讲「改过包要重算摘要」），
        # 而只读信**合法地带 收工与返回 段** ⇒ 整批只读信假红。改用**段标题**判定：
        # 段标题只会出现在该段自己里，不会串段。
        不该有 = (("提交纪律", "## 提交纪律（固定条款"),
                 ("改完必做", "## 改完必做（固定条款"),
                 ("落盘与回传", "## 落盘与回传（固定条款"),
                 ("文件租约", "## 文件租约（固定条款"))
        for 标题, 标志 in 不该有:
            if 标志 in 文本:
                缺.append(f"只读信混入写入类条款：{标题}（标志串 {标志!r} 出现）"
                          "—— 与「禁止修改任何文件」矛盾，必须剔除")
        return 缺
    for 标题, 标志 in (
        ("命令环境", "python3.14"),
        ("命令环境", "单命令硬上限 15 秒"),
        ("命令环境", "不许 sleep"),
        ("工具姿势", "read_file"),
        ("文件租约", "开工即占"),
        ("文件租约", "失败原因"),   # 反向判据：租约段必须讲清「判据是 已开工/失败原因，不是 冲突清单」
        ("文件租约", "不是 `路径`"),  # 反向判据：查询文件租约 的入参名是 修改路径（写 路径 会静默返回全表）
        ("提交纪律", "pathspec"),
        ("禁区", "pkill"),
        ("禁区", "严禁任何 `git stash` 动作"),
        ("落盘与回传", "增量落盘"),
        ("自证与如实", "提交哈希"),
        ("改完必做", "全量重算摘要"),
        ("收工与返回", "收工与返回"),
        ("收工与返回", "不许交「计划」当交付"),
    ):
        if 标志 not in 文本:
            缺.append(f"缺固定条款段：{标题}（标志串 {标志!r} 未出现）")
    return 缺


def 主函数(argv: list[str] | None = None) -> int:
    """命令行入口：`python3.14 开发工具/任务记忆/派活任务信.py --自检 <文件>`。"""
    参数 = list(sys.argv[1:] if argv is None else argv)
    if 参数 and 参数[0] == "--自检":
        if len(参数) < 2:
            print("用法：--自检 <任务信文件>")
            return 2
        文本 = Path(参数[1]).read_text(encoding="utf-8")
        缺 = 自检任务信(文本)
        if 缺:
            print(f"不合格，缺 {len(缺)} 项：")
            for x in 缺:
                print("  ✗", x)
            return 1
        print(f"合格：{len(固定条款段)} 段固定条款齐备")
        return 0
    if 参数 and 参数[0] == "--生成派发":
        # 用法：--生成派发 <标题> <任务正文文件> <允许修改路径1> [路径2 …]
        if len(参数) < 4:
            print("用法：--生成派发 <标题> <任务正文文件> <允许修改路径1> [路径2 …]")
            return 2
        标题, 正文文件, *允许 = 参数[1:]
        正文 = Path(正文文件).read_text(encoding="utf-8")
        载 = 生成派发载荷(标题=标题, 任务正文=正文, 允许修改=允许)
        if not 载["可用"]:
            print("不合格，不能派发：")
            for x in 载["缺项"]:
                print("  ✗", x)
            return 1
        print("【goal】")
