"""派活任务信生成器：把「固定条款 + 任务类型强规范 + 命令环境」自动拼进每封任务信。

为什么要有它（哲学 14.3：反复犯错的开发要补底层）：
实测子代理 kickoff 里**只有 goal + context**，项目 `AGENTS.md` 的工具姿势纪律一次都到不了
（2026-09-18 亲验：任务转录里「工具姿势」0 次命中）。根因不是子代理不看——是**主会话靠记性写**，
漏一次就整批漏。本生成器把「每封信都必须带的条款」从主会话语境里搬到底座，写完任务信
先自检缺项，缺了就报错，不靠人记。

分工（第 2 条 1 项）：
- 固定条款（命令环境 / 提交纪律 / 工具姿势 / 禁区 / 落盘）住本模块 —— 它们是**派活这件事**的
  共性，与具体任务类型无关；
- 任务类型强规范住 `开发文档/规范/任务类型规范.json` —— **不在本模块再抄一份**（第 5 条 1 项：
  同一事实只有一处；本模块只读它、拼装它）；
- 任务正文（目标 / 落点 / 验收命令 / 允许修改）由调用方给 —— 那是一次性的，不沉淀。
"""
