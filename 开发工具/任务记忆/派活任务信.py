def 主函数(argv: list[str] | None = None) -> int:
    """命令行入口：`python3.14 开发工具/任务记忆/派活任务信.py --自检 <文件>`。"""
    参数 = list(sys.argv[1:] if argv is None else argv)
    if 参数 and 参数[0] == "--自检":
        if len(参数) < 2:
            print("用法：--自检 <任务信文件>")
            return 2
        文本 = Path(参数[1]).read_text(encoding="utf-8")
        缺 = 自检任务信(文本)
        if 缺:
            print(f"不合格，缺 {len(缺)} 项：")
            for x in 缺:
                print("  ✗", x)
            return 1
        print(f"合格：{len(固定条款段)} 段固定条款齐备")
        return 0
    if 参数 and 参数[0] == "--生成派发":
        # 用法：--生成派发 <标题> <任务正文文件> <允许修改路径1> [路径2 …]
        if len(参数) < 4:
            print("用法：--生成派发 <标题> <任务正文文件> <允许修改路径1> [路径2 …]")
            return 2
        标题, 正文文件, *允许 = 参数[1:]
        正文 = Path(正文文件).read_text(encoding="utf-8")
        载 = 生成派发载荷(标题=标题, 任务正文=正文, 允许修改=允许)
        if not 载["可用"]:
            print("不合格，不能派发：")
            for x in 载["缺项"]:
                print("  ✗", x)
            return 1
        print("【goal】")
        print(载["goal"])
        print()
        print("【context】（整段抄进 delegate_task 的 context）")
        print(载["context"])
        print()
        print(f"【自检】命中任务类型 {载['命中任务类型']}；{载['字符数']} 字符；"
              f"固定条款齐备 = {not 自检任务信(载['context'])}")
        return 0
    if 参数 and 参数[0] == "--列任务类型":
        数据 = 读任务类型规范()
        for 条目 in 数据.get("任务类型清单") or []:
            print(f"- {条目.get('任务类型')}：{'、'.join(条目.get('识别词') or [])}")
        return 0
    print("用法：--自检 <任务信文件> | --列任务类型 | --生成派发 <标题> <正文文件> <允许路径…>")
    return 2


if __name__ == "__main__":
    raise SystemExit(主函数())
