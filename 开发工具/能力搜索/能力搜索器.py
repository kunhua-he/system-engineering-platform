"""能力检索转调入口：唯一实现腿是 `模块库.能力目录` 的两个公开能力。

唯一实现腿：`模块库/能力目录/实现/能力索引.py`（声明扫描 + 14 字段格式化），
对外只经已注册能力 `能力目录.搜索能力` / `能力目录.读取能力` 暴露。
本文件**不解析任何声明文件**——同一目的不保留第二套实现（哲学 1.3「结果唯一即收口」）；
检索一律按统一调用接口铁律（哲学 7.4）走唯一调用链：`后端核心(项目根).启动()`
→ `后端核心.调用(能力id, 参数)`。本文件只做参数适配、结果解包与命令行输出。

失败不静默：能力腿返回失败时抛 `检索失败`（带能力侧错误码与说明），
不返回空列表冒充「平台没有能力」；只支持 关键词/限制 两个入参，其余过滤条件
（返回类型/提供方/类型）明确拒绝，不做「收下不用」。

命令行：python3.14 开发工具/能力搜索/能力搜索器.py --能力 读取文件
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

系统根 = Path(__file__).resolve().parents[1]
for _祖先 in 系统根.parents:
    if (_祖先 / "支持库").is_dir() and (_祖先 / "模块库").is_dir():
        系统根 = _祖先
        break
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

搜索能力id = "能力目录.搜索能力"
读取能力id = "能力目录.读取能力"

_后端缓存: Any = None
_后端项目根: Path | None = None


class 检索失败(RuntimeError):
    """能力检索失败：携带唯一能力腿返回的错误码与错误说明。"""

    def __init__(self, 错误码: str, 错误说明: str) -> None:
        super().__init__(f"{错误码}: {错误说明}")
        self.错误码 = 错误码
        self.错误说明 = 错误说明


def _取后端(项目根: Path | None = None) -> Any:
    """惰性装配唯一调用链；同一进程内复用一次装配，不每次重装。"""
    global _后端缓存, _后端项目根
    根 = Path(项目根) if 项目根 else 系统根
    if _后端缓存 is not None and _后端项目根 == 根:
        return _后端缓存
    from 后端核心.后端核心 import 后端核心

    后端 = 后端核心(根)
    启动结果 = 后端.启动()
    if not 启动结果.成功:
        raise 检索失败("装配失败", f"后端核心装配失败: {启动结果.错误码} {启动结果.错误说明}")
    _后端缓存, _后端项目根 = 后端, 根
    return 后端


def 调用唯一检索能力(项目根: Path | None = None, *, 关键词: str = "",
                     限制: int = 20) -> dict[str, Any]:
    """经唯一调用链调 `能力目录.搜索能力`，返回其值（关键词/限制/总数/返回数/是否截断/能力列表/项目根）。"""
    调用结果 = _取后端(项目根).调用(搜索能力id, {"关键词": 关键词, "限制": 限制})
    if not 调用结果.成功:
        raise 检索失败(调用结果.错误码 or "检索失败", 调用结果.错误说明 or "能力检索失败")
    值 = 调用结果.值
    if not isinstance(值, dict):
        raise 检索失败("返回结果不符合契约", f"{搜索能力id} 未返回值对象")
    return 值


def 搜索公开能力(项目根: Path | None = None, 关键词: str = "",
                 限制: int = 20) -> list[dict[str, Any]]:
    """按关键词检索公开能力（记录列表形状，兼容历史调用方）。

    记录字段口径、适配层/内部层过滤、限制收敛全部由唯一能力腿决定，
    本文件不复制任何检索规则。
    """
    值 = 调用唯一检索能力(项目根, 关键词=关键词, 限制=限制)
    记录表 = 值.get("能力列表")
    if not isinstance(记录表, list):
        raise 检索失败("返回结果不符合契约", f"{搜索能力id} 的能力列表不是列表")
    return 记录表


def 搜索带原因(项目根: Path | None = None, *, 关键词: str = "", 返回类型: str = "",
               提供方: str = "", 类型: str = "") -> tuple[list[dict[str, Any]], str]:
    """检索并返回 (记录列表, 失败原因)；能力侧失败一并转成原因文本，不抛异常。

    空关键词表示不过滤（返回候选，与唯一能力腿同口径），不再报「缺少搜索条件」。
    """
    if 返回类型 or 提供方 or 类型:
        return [], (
            "参数错误: 唯一检索能力 能力目录.搜索能力 只支持 关键词/限制；"
            f"不支持 返回类型/提供方/类型 过滤（收到 返回类型={返回类型!r}、"
            f"提供方={提供方!r}、类型={类型!r}）"
        )
    try:
        记录表 = 搜索公开能力(项目根, 关键词=关键词)
    except 检索失败 as 错误:
        return [], f"{错误.错误码}: {错误.错误说明}"
    if not 记录表:
        return [], f"未找到匹配能力: {关键词 or '（无关键词）'}"
    return 记录表, ""


def 主函数(argv: list[str] | None = None) -> int:
    """命令行入口：python3.14 开发工具/能力搜索/能力搜索器.py --能力 读取文件"""
    import argparse

    解析器 = argparse.ArgumentParser(description="系统级能力搜索（转调 能力目录.搜索能力）")
    解析器.add_argument("--能力", required=True, help="搜索关键词（能力id/名称/说明）")
    解析器.add_argument("--类型", default="", help="过滤类型：支持库/模块（唯一能力腿不提供该过滤）")
    参数 = 解析器.parse_args(argv)

    记录列表, 原因 = 搜索带原因(关键词=参数.能力, 类型=参数.类型)
    if 原因:
        print(f"检索失败: {原因}")
        return 1
    print(f"找到 {len(记录列表)} 个能力实现：")
    for 记录 in 记录列表:
        参数描述 = ", ".join(
            f"{条目.get('名称', '?')}:{条目.get('类型', '')}" for 条目 in 记录["参数类型"]
        ) or "无"
        print(f"  - 能力id: {记录['能力id']}")
        print(f"    名称: {记录['中文名']}")
        print(f"    提供方: {记录['提供方']}（{记录['类型']} {记录['版本']}）")
        print(f"    参数: {参数描述}")
        print(f"    返回: {记录['返回结构']}")
        print(f"    说明: {记录['说明']}")
        print(f"    调用示例: {记录['调用示例']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(主函数())
