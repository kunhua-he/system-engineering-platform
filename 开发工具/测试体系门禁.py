# ---------------------------------------------------------------- 真跑（B1）
def _真跑环境() -> dict[str, str]:
    """真跑子进程环境：清空 PYTHONPATH、禁止写字节码（不污染仓库现场）。"""
    环境 = {键: 值 for 键, 值 in os.environ.items() if 键 != 真跑环境遮蔽变量}
    环境["PYTHONDONTWRITEBYTECODE"] = "1"
    return 环境


def _真跑末行(输出: str) -> str:
    行 = [行.strip() for 行 in (输出 or "").strip().splitlines() if 行.strip()]
    关键 = [行 for 行 in 行 if 行.startswith(("FAILED", "OK", "ERROR:", "Ran "))]
    return "  ".join((关键 or 行)[-2:])[-300:]


def _跑一个模块(根: Path, 模块名: str, *, 解释器: str, 超时秒: int,
              环境: dict[str, str]) -> dict:
    """真实执行 `python3.14 -m unittest <模块>`；rc≠0／超时／起不来都算不通过。"""
    记录 = {"模块": 模块名, "退出码": None, "通过": False, "异常类型": "",
            "末行": "", "耗时秒": 0.0}
    开始 = time.perf_counter()
    try:
        完成 = subprocess.run([解释器, "-m", "unittest", 模块名],
                            capture_output=True, text=True, timeout=超时秒,
                            env=环境, cwd=str(根))
    except subprocess.TimeoutExpired:
        记录["异常类型"] = "超时"
        记录["末行"] = f"实跑超过 {超时秒} 秒未结束（子进程已被回收）"
    except OSError as 错误:
        记录["异常类型"] = "无法启动"
        记录["末行"] = str(错误)[:300]
    else:
        记录["退出码"] = 完成.returncode
        记录["通过"] = 完成.returncode == 0
        记录["末行"] = _真跑末行((完成.stderr or "") + (完成.stdout or ""))
        if not 记录["通过"]:
            记录["异常类型"] = "实跑不通过"
    记录["耗时秒"] = round(time.perf_counter() - 开始, 2)
    return 记录


def 真跑检查(根: Path, 模块列表: list[str], *, 并发: int = 真跑默认并发,
           超时秒: int = 真跑默认超时秒, 解释器: str | None = None) -> list[dict]:
    """逐模块真实执行；返回按模块名排序的明细（每项都带初筛与复核两段证据）。

    **两段式判定是刻意的**：先按 `并发` 并行初筛，再把初筛不通过的模块**串行
    复跑一次**，判定以串行复跑为准。实测 `测试中心.开发工具.测试_公开调用完整性门禁`
    与 `测试中心.开发工具.测试_核心快照模板` 只在并发（共享临时目录/端口）下红、
    串行复跑即绿——把这种抖动写成真红会让基线不可复现，把串行红写成绿才是真缺陷。
    """
    待跑 = list(模块列表)
    if not 待跑:
        return []
    解释器 = 解释器 or sys.executable
    环境 = _真跑环境()
    线程数 = max(1, min(int(并发), len(待跑)))

    def _初筛(模块名: str) -> dict:
        return _跑一个模块(根, 模块名, 解释器=解释器, 超时秒=超时秒, 环境=环境)

    with concurrent.futures.ThreadPoolExecutor(max_workers=线程数) as 线程池:
        初筛结果 = list(线程池.map(_初筛, 待跑))
    初筛结果.sort(key=lambda 项: 项["模块"])
    for 项 in 初筛结果:
        项["初筛通过"] = 项["通过"]
        项["初筛退出码"] = 项["退出码"]
        项["初筛末行"] = 项["末行"]
        项["复核救回"] = False
        if 项["通过"]:
            项["串行复核"] = "未触发（初筛即通过）"
            continue
        复核 = _跑一个模块(根, 项["模块"], 解释器=解释器, 超时秒=超时秒, 环境=环境)
        项["复核救回"] = bool(复核["通过"])
        项["串行复核"] = 复核["末行"]
        项["通过"] = 复核["通过"]
        项["退出码"] = 复核["退出码"]
        项["异常类型"] = 复核["异常类型"]
        项["末行"] = 复核["末行"]
        项["耗时秒"] = round(项["耗时秒"] + 复核["耗时秒"], 2)
    return 初筛结果


def 真跑归类(真跑结果: list[dict],
           存量: tuple[str, ...] = 存量真跑红) -> dict[str, list]:
    """把真跑结果分成「存量红（只报告）／新增红（判违规）／基线失效（点名）」三桶。"""
    跑过的模块 = {项["模块"] for 项 in 真跑结果}
    红模块名 = {项["模块"] for 项 in 真跑结果 if not 项["通过"]}
    存量集 = set(存量)
    红 = [项 for 项 in 真跑结果 if not 项["通过"]]
    基线失效 = []
    for 模块 in 存量:
        if 模块 in 红模块名:
            continue
        原因 = ("本次真跑通过，基线已过时，必须从 存量真跑红 删除"
               if 模块 in 跑过的模块
               else "模块不在本次发现的测试资产里（改名/删除？），必须同步维护清单")
        基线失效.append({"模块": 模块, "原因": 原因})
    return {
        "红": 红,
        "存量红": [项 for 项 in 红 if 项["模块"] in 存量集],
        "新增红": [项 for 项 in 红 if 项["模块"] not in 存量集],
        "基线失效": 基线失效,
    }


def 运行检查(根: Path, *, 并发: int = 默认并发, 超时秒: int = 默认超时秒,
             连字符即失败: bool = False, 解释器: str | None = None,
             真跑并发: int = 真跑默认并发, 真跑超时秒: int = 真跑默认超时秒,
             存量: tuple[str, ...] = 存量真跑红) -> dict:
    """执行四项检查并汇总：只返回结果，不打印、不退出。"""
    根 = Path(根).resolve()
    开始 = time.perf_counter()
    资产列表 = 发现.发现测试文件(根)
    探测结果 = 可导入性检查.检查可导入性(
        根, 资产列表, 并发=并发, 超时秒=超时秒, 解释器=解释器,
    )
    跳过项 = [
        {"文件": 资产.相对路径, "细节": 资产.跳过原因}
        for 资产 in 资产列表 if 资产.跳过原因
    ]
    违规: list[dict] = []
    违规.extend(可导入性检查.导入失败违规(探测结果))
    违规.extend(零测试检查.零测试违规(探测结果, 资产列表))
    违规.extend(跳过检查.未解释跳过违规(资产列表))
    if 连字符即失败:
        违规.extend(
            {"类型": "跳过资产未守护", "文件": 条["文件"], "行号": None,
             "细节": f"{条['细节']}（--连字符即失败 已升级为违规）"}
            for 条 in 跳过项
        )

    # ④ 真跑：只导入不执行会把实跑即红的模块记成绿，所以逐模块真跑一遍。
    # 存量红走显式基线（只报告），基线外的红一律判违规（fail-closed）。
    可跑资产 = [资产 for 资产 in 资产列表 if not 资产.跳过原因]
    模块到路径 = {资产.模块名: 资产.相对路径 for 资产 in 可跑资产}
    真跑结果 = 真跑检查(根, [资产.模块名 for 资产 in 可跑资产],
                     并发=真跑并发, 超时秒=真跑超时秒, 解释器=解释器)
    归类 = 真跑归类(真跑结果, 存量)
    for 项 in 归类["新增红"]:
        违规.append({
            "类型": "真跑新增红",
            "文件": 模块到路径.get(项["模块"], 项["模块"]),
            "行号": None,
            "细节": (f"实跑 `{解释器 or sys.executable} -m unittest {项['模块']}` "
                    f"退出码 {项['退出码']}（{项['异常类型']}）：{项['末行']}"
                    f"；不在 存量真跑红 基线内，按 fail-closed 判违规"),
        })
    return {
        "相对根": str(根),
        "测试文件数": len(资产列表),
        "参与数": len(可跑资产),
        "导入成功数": sum(1 for 项 in 探测结果 if 项["导入成功"]),
        # 口径必须分开：收集到的用例一个都没跑，真跑才是真执行。
        "用例总数": sum(int(项["用例数"] or 0) for 项 in 探测结果 if 项["导入成功"]),
        "收集用例数_未执行": sum(int(项["用例数"] or 0)
                              for 项 in 探测结果 if 项["导入成功"]),
        "真跑模块数": len(真跑结果),
        "真跑通过数": sum(1 for 项 in 真跑结果 if 项["通过"]),
        "真跑红数": len(归类["红"]),
        "存量真跑红命中数": len(归类["存量红"]),
        "新增真跑红数": len(归类["新增红"]),
        "复核救回数": sum(1 for 项 in 真跑结果 if 项["复核救回"]),
        "存量真跑红基线": list(存量),
        "真跑基线失效": 归类["基线失效"],
        "真跑明细": 真跑结果,
        "跳过数": len(跳过项),
        "跳过": 跳过项,
        "违规": 违规,
        "耗时秒": time.perf_counter() - 开始,
    }


def 运行门禁(根: Path, *, 并发: int = 默认并发, 超时秒: int = 默认超时秒,
             连字符即失败: bool = False, 真跑并发: int = 真跑默认并发,
             真跑超时秒: int = 真跑默认超时秒,
             存量: tuple[str, ...] = 存量真跑红) -> list[dict]:
    """门禁入口（供发布门禁调用）：返回违规清单，空列表即通过；不打印。"""
    return 运行检查(根, 并发=并发, 超时秒=超时秒, 连字符即失败=连字符即失败,
                   真跑并发=真跑并发, 真跑超时秒=真跑超时秒, 存量=存量)["违规"]


# ---------------------------------------------------------------- 报告（本文件）
def _违规摘要(违规: list[dict]) -> str:
    计数 = 报告.分组计数(违规)
    return "、".join(f"{名称} {计数[名称]}" for 名称 in sorted(计数)) or "无"


def 生成文本报告(结果: dict) -> str:
    行 = [
        f"测试体系门禁：{结果['相对根']}",
        f"  测试文件 {结果['测试文件数']} 个｜参与可导入性 {结果['参与数']} 个｜"
        f"导入成功 {结果['导入成功数']} 个｜跳过 {结果['跳过数']} 个",
        "  口径（两个字段必须分开读，不得混读）："
        f"收集用例数（未执行）= {结果['收集用例数_未执行']}  ｜  "
        f"真跑通过模块数 = {结果['真跑通过数']}/{结果['真跑模块数']}",
        f"  真跑：红 {结果['真跑红数']} 个（存量基线内 {结果['存量真跑红命中数']}／"
        f"新增 {结果['新增真跑红数']}）；并发初筛后被串行复核救回 "
        f"{结果['复核救回数']} 个（并发抖动，不算真红）",
        f"  耗时 {结果['耗时秒']:.1f} 秒（含真跑）",
    ]
    if 结果["跳过"]:
        行.append(f"跳过（不纳入可导入性与真跑，共 {len(结果['跳过'])} 项）：")
        行.extend(f"  [跳过] {条['文件']} — {条['细节']}" for 条 in 结果["跳过"])
    if 结果["真跑红数"]:
        存量集 = set(结果["存量真跑红基线"])
        行.append(f"真跑红的模块（{结果['真跑红数']} 个；存量只报告、新增判违规）：")
        for 项 in 结果["真跑明细"]:
            if 项["通过"]:
                continue
            桶 = "存量基线" if 项["模块"] in 存量集 else "新增违规"
            行.append(f"  [红·{桶}] {项['模块']} — 退出码 {项['退出码']}"
                      f"（{项['异常类型']}）{项['末行']}")
    if 结果["真跑基线失效"]:
        行.append(f"存量真跑红基线失效 {len(结果['真跑基线失效'])} 项"
                  "（必须同步维护 存量真跑红 清单，只减不增）：")
        行.extend(f"  [基线失效] {条['模块']} — {条['原因']}"
                  for 条 in 结果["真跑基线失效"])
    if not 结果["违规"]:
        行.append("测试体系门禁通过：全部测试文件可导入、无零测试、无未解释跳过、"
                  "真跑无新增红（存量红见上，不代表已清零）")
        return "\n".join(行)
    行.append(f"测试体系门禁失败：共 {len(结果['违规'])} 项违规（{_违规摘要(结果['违规'])}）")
    for 条 in 结果["违规"]:
        位置 = f"{条['文件']}:{条['行号']}" if 条.get("行号") else 条["文件"]
        行.append(f"  [{条['类型']}] {位置} — {条['细节']}")
    return "\n".join(行)


def 生成json报告(结果: dict) -> str:
    import json
    return json.dumps(结果, ensure_ascii=False, indent=2)


def 主程序(参数: list[str] | None = None) -> int:
    解析 = 构造解析器().parse_args(参数)
    根 = Path(解析.根).resolve()
    if not (根 / 发现.测试中心目录名).is_dir():
        print(f"环境错误：{根} 下不存在 {发现.测试中心目录名}/ 目录", file=sys.stderr)
        return 2
    结果 = 运行检查(
        根, 并发=max(1, 解析.并发), 超时秒=max(1, 解析.超时秒),
        连字符即失败=解析.连字符即失败,
        真跑并发=max(1, 解析.真跑并发), 真跑超时秒=max(1, 解析.真跑超时秒),
    )
    print(生成json报告(结果) if 解析.json输出 else 生成文本报告(结果))
    if not 结果["违规"]:
        return 0
    if 解析.只报告:
        print(f"（--只报告：本次 {len(结果['违规'])} 项违规按约定不阻断，退出码 0）")
        return 0
    return 1


if __name__ == "__main__":
    raise SystemExit(主程序())
