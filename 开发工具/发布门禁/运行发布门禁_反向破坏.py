"""反向破坏项（哲学 1.4「空转即杀」的反向证明）。

内容：`反向破坏预算秒`、`校验反向破坏`。判据本体在 `开发工具/复用审计/反向破坏/破坏验证.py`，
本文件只做接线与判定，不复制任何破坏场景。

**本文件由 `开发工具/发布门禁/运行发布门禁.py` 按检查项簇**逐字搬移**（成员名一个不改、
判据一处不复制）。依赖方向**单向**：本文件只依赖底座/同族子模块，**不得 import 主文件**
（主文件 import 本文件；反向 import 会成循环）。主文件仍 re-export 本文件全部对外符号，
故 `from 开发工具.发布门禁.运行发布门禁 import <名>` 照旧可用。
"""

from __future__ import annotations

import time
from 公共契约.基础类型.逻辑类型 import 真, 假

反向破坏预算秒 = 120.0


def 校验反向破坏(*, 预算秒: float | None = None) -> tuple[bool | None, str]:
    """卡点 B 接线第 2 条「反向破坏」：把哲学 1.4（空转即杀）的判据接进**必经路径**。

    **为什么接（哲学总账 1.4 实测）**：``开发工具/复用审计/反向破坏/破坏验证.py``
    是哲学 1.4 的反向证明工具，**有实现、有单测，但发布门禁不调用** —— 门禁里
    「反向破坏」此前只作为**包名清单字符串**出现在「旧过渡目录不存在」那一行的枚举里
    （字面 ≠ 调用）。按 13.1「判据在、门禁不调即纸面规则」，它此前是半个强制。
    本函数只做**接线 + 判定**，判据**不在这里第二遍实现**：13 类破坏场景与结论一律取
    ``破坏验证.破坏验证器().执行()`` 的返回值（该判据自带场景表、恒真真对照与
    ``报告.成功`` 判据），本函数不复刻任何场景、不自建第二份场景表。

    **判定唯一入口 = ``报告.成功``**：其定义是
    ``通过数 == 证据数 and 证据数 == len(破坏场景表) and 恒真检查``。
    不得自己数证据条数判绿 —— 那样会漏掉「恒真检查」这一项，而一个恒真的验证器
    同样能「13 项全检出」，正是本项要防的恒真/空转。

    **耗时取舍（真实实测，2026-09-18，macOS 本机 python3.14）**：

      · 判据模块 import 一次性 **0.026 秒**。
      · 门禁项单次耗时 **0.34–0.38 秒**（装配已暖；5 次实测
        4.084／0.379／0.344／0.345／0.373 秒 —— 首次 4.08 秒含「激活路由指向不存在
        版本」场景惰性装配 平台控制面 的一次性成本，其后 ≈0.37 秒）。
      · 全量 13 场景**独立冷跑**（进程内还没有装配）= **2.6–3.1 秒**。
        逐场景实测：依赖锁篡改 0.225／摘要篡改 0.008／参数类型 0.008／错误码 0.001／
        实现删除 0.001／重复能力 0.000／循环依赖 0.000／提供者崩溃 0.079／任务超时
        0.012／资源泄漏 0.017／热切换回滚 0.085／客户端断开 0.014／激活路由 2.202／
        恒真对照 0.001 秒。
      · 整轮发布门禁实测 **111–132 秒**（109 项强制项）；**门禁自身抖动量级
        22.9 秒**（同一份空跑路径连测 3 次：77.79／83.34／100.66 秒）。
      · 整轮 A/B（同一进程、把本项换成空转壳）= **−3.33 秒**，是**负的** ——
        即本项增量已被门禁自身抖动完全淹没（差两个数量级）。

      ⇒ 结论分两句，不合并：
        ① 本项增量 ≈ **0.37 秒**（装配已暖），相对整轮 **0.3%**；
        ② 「整轮 A/B 差不出正数」**不是**本项不花钱的证据，只说明整轮耗时这个读数
           分辨率不够，**不得**用它冒充「零成本」。故本项取 **全量常驻（不抽样、
           不删项）**。
        抽样/清单制是给「全量太慢」准备的降级手段，实测不慢就不该用它；按硬约束
        「不得为了提速而删掉验证项」，此处**不引入抽样档**。
      · 耗时控制改用**预算警戒线**：``预算秒``（默认 ``反向破坏预算秒``＝120 秒，
        约 300 倍余量）只作回归警戒 —— 实测耗时超预算即判红并报出耗时，让人看见
        「判据变慢了」。本函数**不**用线程/子进程强杀超时判据：强杀等于「无证据也
        出结论」，那是「跳过却报绿」的反面；挂死的兜底属于调用方/CI 的整体超时职责。
      · 将来若仓库规模把这一项推到分钟级，再按「登记清单 + 抽样」降级；**那时必须
        先有实测数字**，不得凭感觉抽样。

    **工作树安全（实测，不是推测）**：本判据的破坏全部落在 ``tempfile`` 临时目录或
    进程内对象上，**不写脏仓库**。取证：对 122 份被验对象（依赖锁定／运行核心／
    组件规范支持库／能力契约／契约编译）连跑 3 次本判据前后取字节，逐字相同。
    故无需 `git worktree` 洁净树（旧方案里的「只能在洁净树里跑」是基于推测的顾虑，
    实测不成立；真正需要洁净树的是会改工程内文件的判据）。

    **fail-closed**：判据导入失败／执行抛异常 → 一律判红（不静默降级）；报告里
    证据列表为空 → 判红（什么破坏都没验的「验证器」正是空转本尊）；场景数少于
    ``破坏场景表`` 登记数 → 判红（判据被削弱）。``检出方式=执行异常`` 的场景在
    破坏验证内部已记 ``验证结果=假``（异常 ≠ 检出），本函数照它的结论判，不自行
    解释异常。

    阻断口径见 ``防回潮阻断配置["反向破坏"]``（13.2：是否阻断必须显式配置）。
    """
    预算 = 反向破坏预算秒 if 预算秒 is None else float(预算秒)
    from 开发工具.复用审计.反向破坏.破坏验证 import 破坏场景表, 破坏验证器

    开始 = time.monotonic()
    报告 = 破坏验证器().执行()
    耗时 = time.monotonic() - 开始

    场景数 = len(报告.证据列表)
    规范 = (f"判据=复用 开发工具/复用审计/反向破坏/破坏验证.破坏验证器"
            f"（本项不另立第二份实现）；破坏场景 {场景数}/{len(破坏场景表)}；"
            f"通过 {报告.通过数}；恒真检查={报告.恒真检查}；"
            f"耗时实测 {耗时:.2f} 秒（预算 {预算:.2f} 秒）")
    if 场景数 == 0:
        return 假, f"{规范}；**一项破坏都没产生证据**：验证器空转，判红"
    if 场景数 < len(破坏场景表):
        return 假, (f"{规范}；**场景表登记 {len(破坏场景表)} 类，实际只跑出 {场景数} 类**"
                    f"（少 {len(破坏场景表) - 场景数} 类 = 判据被削弱），判红")
    if 耗时 > 预算:
        return 假, (f"{规范}；**耗时超预算 {耗时 - 预算:.2f} 秒**（判据出现性能回归，"
                    f"先查明再谈放宽预算）")
    if not 报告.成功:
        失败场景 = [
            f"{证据.场景名}（{证据.破坏方式}／检出方式={证据.检出方式}）: {证据.详情 or '无详情'}"
            for 证据 in 报告.证据列表 if not 证据.验证结果
        ]
        if 失败场景:
            return 假, (f"{规范}；**应当检出却未拦住 {len(失败场景)} 条**："
                        f"{'；'.join(失败场景[:5])}")
        # 12 类全检出、报告仍不成功 ⇒ 只可能是 `报告.成功` 的另一半没过：恒真检查。
        # 这条必须与「未拦住」分开报，否则红出来的文案是「未拦住 0 条」= 自相矛盾，
        # 让人以为门禁在乱报（本项要防的正是「判据错误说成被测缺陷」的反面）。
        return 假, (f"{规范}；**判据恒真**：{场景数} 类全部「检出」，但同一批检测器对"
                    f"未破坏输入也报检出（真对照未通过），故全体检出不作数："
                    f"{'；'.join(报告.恒真详情) or '恒真详情缺失'}")
    return 真, (f"{规范}；{场景数} 类破坏均被生产接口真实拒绝，且恒真真对照通过"
                f"（同一批检测器对未破坏输入一条都不报 = 判据非恒真）")
