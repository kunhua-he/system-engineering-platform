def _项5_双迁移互斥(系统根: Path) -> tuple[str, bool, str]:
    """迁移互斥：同存储连续迁移后者必须复用；并发两个不同任务必须只有一个推进。"""
    import threading
    from 平台控制面.发布管理.迁移互斥编排器 import 迁移互斥编排器
    目录 = Path(tempfile.mkdtemp(prefix="门禁_迁移互斥_"))
    编排器1 = 迁移互斥编排器(目录)
    编排器2 = 迁移互斥编排器(目录)
    结果1, 状态1 = 编排器1.执行迁移("迁移任务A")
    结果2, 状态2 = 编排器2.执行迁移("迁移任务B")
    # 正确语义：编排器1推进完成，编排器2复用（不重复迁移）
    正向通过 = 结果1 == "推进" and 状态1 == "已完成" and 结果2 == "复用"
    # 反向：同一存储上真实并发两个不同任务，必须恰好一个推进，另一个复用或明确冲突。
    # 原实现只在全新空目录跑单次迁移并断言首次成功，与正向编排器1是同一条路径，等于零证据。
    并发目录 = Path(tempfile.mkdtemp(prefix="门禁_迁移互斥2_"))
    结果表: list[str] = []
    结果锁 = threading.Lock()

    def _并发迁移(任务id: str) -> None:
        结果 = "异常:未执行"
        try:
            编排 = 迁移互斥编排器(并发目录)
            编排.步骤延迟秒 = 0.25  # 拉长写锁窗口，让两个线程真实重叠
            结果, _ = 编排.执行迁移(任务id)
            try:
                编排.清理()
            except Exception as 错误:  # 允许忽略，但留痕（哲学第 15 条）
                记录忽略('第十四阶段门禁._并发迁移', 错误)
        except Exception as 错误:
            结果 = f"异常:{错误}"
        with 结果锁:
            结果表.append(结果)

    线程1 = threading.Thread(target=_并发迁移, args=("并发任务1",))
    线程2 = threading.Thread(target=_并发迁移, args=("并发任务2",))
    线程1.start()
    线程2.start()
    线程1.join(timeout=30)
    线程2.join(timeout=30)
    推进数 = 结果表.count("推进")
    反向通过 = (
        len(结果表) == 2 and 推进数 == 1
        and all(项 in ("推进", "复用", "冲突") for 项 in 结果表)
    )
    通过 = 正向通过 and 反向通过
    详情 = f"编排器1:{结果1}({状态1}) 编排器2:{结果2}({状态2}) 并发:{结果表}(推进{推进数})"
    return "第十四阶段-同存储双迁移互斥", 通过, 详情


