def _工程根目录() -> Path:
    """向上定位工程根（同时含 平台控制面 与 开发工具 双目录的祖先）。"""
    候选 = Path(__file__).resolve()
    for 祖先 in 候选.parents:
        if (祖先 / "平台控制面").is_dir() and (祖先 / "开发工具").is_dir():
            return 祖先
    return 候选.parents[1]


def _调用治理能力(能力id: str, 参数: dict[str, Any]) -> Any:
    """经完整装配调用 平台控制面 正式包的公开能力（唯一能力调用入口）。

    `开发工具` 是进程外调用方：惰性装配钩子只装 支持库/模块库，取不到
    `平台控制面` 的能力，故这里自建完整装配并按**惰性单例**复用（约 1.5 秒，
    不塞进 import 期）。返回统一结果信封（成功/值/错误），不做任何兜底降级。
    """
    global _治理后端
    if _治理后端 is None:
        from 后端核心.后端核心 import 后端核心
        实例 = 后端核心(_工程根目录())
        启动结果 = 实例.启动()
        if not 启动结果.成功:
            raise RuntimeError(
                f"平台控制面 能力装配失败: {启动结果.错误说明}")
        _治理后端 = 实例
    return _治理后端.调用(能力id, 参数)


