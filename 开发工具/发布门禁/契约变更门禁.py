"""发布门禁·契约口径两项：哲学 5.3（对外契约变更需判定）+ 哲学 5.1（契约版本唯一）。

**卡点 B 接线第 3 条**（2026-09-18）。本模块只做**接线与判定**，两条判据都不在这里出生。

## 为什么接（哲学总账第一节实测）

`开发文档/哲学总账.md` 实测：5.3 的判据 `开发工具/契约编译/对外契约变更判定.py`
「**有实现、有单测，但发布门禁不调用**」；5.1 的判据只存在于单测
单测 `测试_契约版本唯一`（测试侧）。按 13.1「判据在、门禁不调即纸面规则」，
两条此前都是**半个强制** —— 而对外契约内容变了却不升版本，是全仓最贵的破坏之一
（能力 id 的「只增不改」已接线，但「契约内容变了要不要升版本」这一层没人拦）。

## 判据不从本模块出生（不建第二份实现）

- **5.3**：逐包调 `开发工具/契约编译/对外契约变更判定.判定对外契约变更`。该模块内部
  只用**同一个** `契约指纹()`（唯一实现 `公共契约/能力契约/契约指纹.py`）与
  `检查契约兼容()` 产结论；本模块**不复写指纹、不复写兼容、不重排判据**，
  只在它之上做「逐包汇总 + 五态表态 + 人读证据」。
- **5.1**：唯一事实源 = `公共契约/版本规则/契约版本.py`（本模块直接 import 它，
  **不另立常量**）。口径与测试侧逐字同源；差别在扫描面：测试侧只扫
  支持库/模块库/技能库 三根，本模块按门禁源码边界扫全平台
  （否则 `平台控制面` 15 包 / `运行核心` 1 包 / `启动监督器` 1 包 无人在守）。

## 对比基准（现成可得，不新建存储）

**基准 = 当前激活制品内的同名包**：`工程缓存/制品仓库/平台客户端制品/当前.json`
→ 制品目录 → 制品内 `平台客户端/<包相对路径>` 的 `能力定义.json` /
`能力契约/参数契约.json`；源码侧为「新版」。

- 这正是 `判定对外契约变更` 的缺省基准，本模块**不另造基线、不落任何缓存、不写盘**。
- 另一条现成基准**不适用**并已排除：`项目编译器` 写的 `候选.json` 是**单个项目**的
  编译候选指针，不承载全平台契约面，拿它当 133+ 包的对比基准是错配。
- **基准过期与判据边界（关键口径）**：制品绑定的固定提交/工作区字节指纹由门禁既有项
  「正式制品来源与字节指纹」单独核验；本项**不比字节**，只比**对外契约面**。
  因此「制品比工作区旧」这件事**本身不会**把本项打成假红 —— 只有「某能力契约面确实变了
  且源码侧版本号没有递增」才判红，而那正是 5.3 要拦的东西。
- **制品滞后期的判红是本职、不是误报**：激活制品天然滞后于工作树（制品由
  `客户端/构建平台客户端.py` 重建后才更新 `当前.json`）。于是在「本轮改了契约」到
  「重建并激活制品」之间，本项**会**判红 —— 这是设计意图：5.3 要求的是**先递增版本**，
  一旦该包版本号递增，本项即刻转绿（**不必等制品重建**），这就是它要形成的强制力。
  唯二能转绿的路径是「递增版本」或「把改动撤回」，不存在「等制品追上」这条绕路。
  反向验证实测：本轮并行期真实抓到 3 个包改了契约面（新增错误码）却没升版本
  （`支持库/后端/媒体处理支持库/FFmpeg媒体`、`支持库/适配层/FFmpeg提供者`、
  `模块库/项目文档`），门禁逐包点名判红 —— 判据在真数据上确实拦得住。
- 基线侧的读数只取制品内的**契约 JSON（数据）**，**不 import 制品内实现**
  （避免「两份实现并存、当前实现是哪一份」的歧义，与判定模块 0020 裁决二同口径）。

## 口径（13.2 门禁五态：**干净通过**，零容忍）

逐包判定结果分四类：

| 判定 | 含义 | 门禁表态 |
|---|---|---|
| 契约面指纹逐字相同（或仅文档性变化：`参数.说明` / `返回.值结构`） | 纯内部优化 | 通过 |
| 契约面变化 + **版本已递增** | 变更已由版本递增承载 | 通过，但**必须报到**（详情写清「上一版是什么、本版变了什么」） |
| 契约面变化 + **版本未递增 / 版本回退** | 5.3 要拦的破坏 | **判红**，点名包、能力、字段级差异 |
| 基线取证失败 | 判不出 | **判红**（fail-closed） |

**fail-closed 清单**（`判定对外契约变更` 的错误信封**原样外传**，本模块不把它降级成
「无变化」）：基线指针缺失 / 基线制品目录缺失 / 基线内无同名包（含新包尚未进制品） /
契约文件缺失或不可读 / 契约结构非法。**扫描面为 0**（一个包都枚举不到）→ 返回
`None` = **未核验**（不占通过位，也不冒充失败证据；空集不是通过）。

## 用法

    python3.14 -c "from 开发工具.发布门禁.契约变更门禁 import 校验对外契约变更; print(校验对外契约变更())"
    python3.14 -c "from 开发工具.发布门禁.契约变更门禁 import 校验契约版本唯一; print(校验契约版本唯一())"

接线点：`开发工具/发布门禁/运行发布门禁.py` 的「对外契约变更需判定」「契约版本唯一」
两个门禁项；阻断口径显式登记在 `防回潮阻断配置`（13.2：不靠「未新增即放行」隐含）。
"""

