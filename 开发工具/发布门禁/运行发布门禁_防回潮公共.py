def _读分桶基线(路径: Path, 项名: str) -> dict[str, int] | None:
    """读分桶基线里某一项的「文件 → 上限」；文件缺失/损坏一律返回 None（调用方回退总数模式）。"""
    try:
        if not 路径.is_file():
            return None
        数据 = json.loads(路径.read_text(encoding="utf-8"))
        条目 = ((数据.get("项") or {}).get(项名) or {}).get("条目")
        if not isinstance(条目, dict):
            return None
        return {str(k): int(v) for k, v in 条目.items()}
    except (OSError, ValueError, TypeError, AttributeError):
        return None


def _按文件分组(命中: list[str], 显示根: Path) -> dict[str, list[str]]:
    """把命中行按**文件相对路径**分组（命中行格式 `<文件>:<行号>: <说明>`）。"""
    分组: dict[str, list[str]] = {}
    for 行 in 命中:
        部分 = 行.rsplit(":", 2)
        键 = 部分[0] if len(部分) == 3 else 行
        try:
            键 = str(Path(键).relative_to(显示根))
        except ValueError:
            pass
        分组.setdefault(键, []).append(行)
    return 分组


def _分桶判定(分组: dict[str, list[str]], 分桶: dict[str, int]) -> tuple[bool, list[str], list[str]]:
    """按分桶基线判定：返回 `(是否新增, 新增明细, 超基线最多的文件样本)`。

    **口径**：只有「某文件命中数 > 该文件基线值」才算新增（新增项＝该文件超出上限的那几条）；
    基线里有、本次未出现的文件＝**收敛**（正向信号，不计红）；基线里没有的新文件＝整份都算新增。
    """
    新增明细: list[str] = []
    for 文件 in sorted(分组):
        本文件 = 分组[文件]
        上限 = int(分桶.get(文件, 0) or 0)
        if len(本文件) > 上限:
            新增明细.extend(本文件[上限:])
    超基线 = sorted(((len(v) - int(分桶.get(k, 0) or 0), k) for k, v in 分组.items()),
                  reverse=True)
    样本 = [f"{k}（{len(分组[k])} 条，基线 {int(分桶.get(k, 0) or 0)}）" for _, k in 超基线[:5]]
    return bool(新增明细), 新增明细, 样本
