def _读模块字面量(源路径: Path, 变量名: str) -> Any:
    """AST 读模块级字面量赋值（两种形态都认），并剥掉 ``frozenset(...)`` 外壳。

    为什么不能直接复用 ``开发工具.公开调用完整性门禁.读取模块字面量字典``：
    它对 ``正式类型表 = frozenset({…})`` 这种**调用外壳**读不出（返回 None）——
    实测 ``正式类型名集()`` 在真仓库上返回**空集**，「拿唯一真源判类型名」于是
    要么全判红要么静默放行。本函数是同一真源（同一路径 + 同一变量名）的读取器，
    不是第二份类型清单：类型名只有一个真源 ``公共契约/基础类型/类型表.py:正式类型表``。
    """
    try:
        树 = ast.parse(源路径.read_text(encoding="utf-8"))
    except (OSError, SyntaxError, UnicodeDecodeError):
        return None
    for 节点 in 树.body:
        值 = None
        if isinstance(节点, ast.Assign) and any(
                getattr(目标, "id", None) == 变量名 for 目标 in 节点.targets):
            值 = 节点.value
        elif isinstance(节点, ast.AnnAssign) and isinstance(节点.target, ast.Name) \
                and 节点.target.id == 变量名 and 节点.value is not None:
            值 = 节点.value
        if 值 is None:
            continue
        if isinstance(值, ast.Call) and 值.args:  # frozenset({…}) / set([…])
            值 = 值.args[0]
        try:
            return ast.literal_eval(值)
        except (ValueError, SyntaxError):
            return None
    return None
