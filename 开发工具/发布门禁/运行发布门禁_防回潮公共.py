def _防回潮分桶判定(项名: str, 命中: list[str], 计数: int, 配置: dict[str, Any],
                    规范: str, *, 样本上限: int = 3) -> tuple[bool | None, str] | None:
    """分桶优先的存量判定。**返回 None 表示「本项不走分桶、由调用方按总数判定」**。

    为什么抽成公用件：三个防回潮项（裸布尔/非正式类型名/英文错误码）此前各自写一遍
    「计数 > 基线 → 报新增」，**三处都会展示 `违规[:N]`（前 N 条）而不是真正新增的那几条**，
    且都用硬编码总数（多路并行期数字漂移必然误报）。统一到这里，一处口径、三处受益。
    """
    分桶 = _读分桶基线(防回潮存量基线路径, 项名)
    if 分桶 is None:
        return None
    分组 = _按文件分组(命中, 系统根)
    有新增, 新增明细, 超基线样本 = _分桶判定(分组, 分桶)
    if 有新增:
        return 假, (f"{规范}｜**按文件分桶判定**（存量冻结口径：每个文件不得比基线更差）；"
                    f"**新增 {len(新增明细)} 条**（硬限制不得增加）："
                    f"{'；'.join(新增明细[:样本上限])}")
    收敛文件 = [k for k in 分桶 if k not in 分组]
    return 真, (f"{规范}｜**按文件分桶判定**；未新增（无文件超基线）；"
                f"超基线最多的文件：{'；'.join(超基线样本) or '无'}；"
                f"（基线内已收敛 {len(收敛文件)} 个文件）")
