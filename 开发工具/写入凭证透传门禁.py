def _方法名(节点: ast.AST) -> str:
    """被调名：`ast.Attribute.attr` 或 `ast.Name.id`；取不到回空串。"""
    if isinstance(节点, ast.Attribute):
        return 节点.attr
    if isinstance(节点, ast.Name):
        return 节点.id
    return ""


def _模块限定(节点: ast.AST) -> str:
    """`os.replace` ⇒ `"os"`；`shutil.rmtree` ⇒ `"shutil"`；`self.服务.x` ⇒ `"self.服务"`。"""
    if not isinstance(节点, ast.Attribute):
        return ""
    左 = 节点.value
    if isinstance(左, ast.Name):
        return 左.id
    if isinstance(左, ast.Attribute) and isinstance(左.value, ast.Name):
        return f"{左.value.id}.{左.attr}"
    return ""


def _常量串(节点: ast.AST | None) -> str:
    """从表达式抽第一个字符串字面量（含 f-string 常量段）；抽不到回空串。"""
    if 节点 is None:
        return ""
    for 子 in ast.walk(节点):
        if isinstance(子, ast.Constant) and isinstance(子.value, str):
            return 子.value
        if isinstance(子, ast.JoinedStr):
            for 段 in 子.values:
                if isinstance(段, ast.Constant) and isinstance(段.value, str):
                    return 段.value
    return ""


def _路径证据(节点: ast.AST | None) -> bool:
    """接收者/首参表达式是否带路径证据（路径词标识符、路径分隔符或源码后缀字面量）。"""
    if 节点 is None:
        return False
    文本 = _常量串(节点)
    if 文本 and ("/" in 文本 or "\\" in 文本
                or 文本.endswith((".py", ".json", ".db", ".txt", ".md", ".yaml", ".toml"))):
        return True
    for 子 in ast.walk(节点):
        if isinstance(子, ast.Name) and 子.id.lower() in 路径证据标记:
            return True
    return False


def _open是写(节点: ast.Call) -> bool:
    """`open(路径, "w"/"a"/"x"/"+")` ⇒ 写；缺模式（默认 `r`）⇒ 读，**不算写盘**。"""
    模式 = ""
    if len(节点.args) >= 2 and isinstance(节点.args[1], ast.Constant) \
            and isinstance(节点.args[1].value, str):
        模式 = 节点.args[1].value
    for 关键词 in 节点.keywords:
        if 关键词.arg == "mode" and isinstance(关键词.value, ast.Constant) \
                and isinstance(关键词.value.value, str):
            模式 = 关键词.value.value
    return any(符 in 模式 for 符 in ("w", "a", "x", "+")) if 模式 else False


def _是SQL写(节点: ast.Call) -> bool:
    """`连接.execute("INSERT …")` ⇒ 写；语句是变量 ⇒ 证不出只读，按写算（fail-closed）。"""
    if _方法名(节点.func) not in ("execute", "executemany", "executescript"):
        return False
    语句 = _常量串(节点).strip().upper()
    return True if not 语句 else 语句.startswith(SQL写动词)


def _写盘命中(节点: ast.Call) -> str:
    """一次调用是不是写盘动作：`平台:<名>` / `临时落点:<名>` / `裸写:<名>` / 空串（不是）。"""
    名 = _方法名(节点.func)
    if not 名:
        return ""
    if 名 in 平台写腿名:
        return f"平台:{名}"
    if 名 in 临时落点构造器名:
        return f"临时落点:{名}"
    接收者 = 节点.func.value if isinstance(节点.func, ast.Attribute) else None
    首参 = 节点.args[0] if 节点.args else None
    if 名 == "open":
        if _open是写(节点) and (_模块限定(节点.func) in 文件系统模块名 or _路径证据(首参)):
            return "裸写:open"
        return ""
    if 名 in 路径专属写名:
        return f"裸写:{名}"
    if 名 in 歧义写名:
        # 同名不同义（`str.replace`/`list.remove`/`socket.write`/容器 `copy`）⇒ **必须模块限定**
        # （`os.replace`/`shutil.copy`）。**不再退回「接收者带路径证据」**：实测该退路仍把
        # `口径.replace("/", "_")` 这类**文本归一化**误判成写盘（~10 条假红，见 docstring 假红类 2）。
        # 代价是 `Path变量.replace(...)` 这类不带模块限定的路径方法会**漏报**（如实声明：漏报 > 假红）。
        限定 = _模块限定(节点.func)
        return f"裸写:{限定}.{名}" if 限定 in 文件系统模块名 else ""
    if 名 in 写盘名 and (_模块限定(节点.func) in 文件系统模块名
                      or _路径证据(接收者) or _路径证据(首参)):
        return f"裸写:{名}"
    if _是SQL写(节点):
        return "裸写:execute(SQL)"
    return ""


def _包内源码面(包目录: Path) -> tuple[dict, dict, list]:
    """一次遍历包内 `.py`（唯一遍历腿 `遍历源码`），回 `(函数定义表, 注册映射, 不可解析)`。"""
    定义表: dict[str, dict] = {}
    注册: dict[str, str] = {}
    不可解析: list[str] = []
    for 文件 in 遍历源码(包目录, 层名表=(".",)):
        try:
            源码 = 文件.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as 错误:
            不可解析.append(f"{文件.name}（{type(错误).__name__}）")
            continue
        try:
            树 = ast.parse(源码)
        except SyntaxError as 错误:
            不可解析.append(f"{文件.name}（SyntaxError@{错误.lineno}）")
            continue
        for 编号, 函数名 in 提取注册映射(源码).items():
            注册.setdefault(编号, 函数名)
        for 节点 in ast.walk(树):
            if isinstance(节点, (ast.FunctionDef, ast.AsyncFunctionDef)):
                定义表.setdefault(节点.name, {"节点": 节点, "文件": 文件})
    return 定义表, 注册, 不可解析


def _可达函数体(入口名: str, 定义表: dict) -> list[dict]:
    """从入口函数起，**同包内按名字**收集可达函数体（BFS，深度 ≤ `闭包深度上限`）。"""
    if 入口名 not in 定义表:
        return []
    出 = [定义表[入口名]]
    已见 = {入口名}
    当前 = [入口名]
    for _ in range(闭包深度上限):
        下轮: list[str] = []
        for 名 in 当前:
            for 子 in ast.walk(定义表[名]["节点"]):
                if not isinstance(子, ast.Call) or _模块限定(子.func):
                    continue
                被调 = _方法名(子.func)
                if 被调 in 定义表 and 被调 not in 已见:
                    已见.add(被调)
                    出.append(定义表[被调])
                    下轮.append(被调)
        当前 = 下轮
        if not 当前:
            break
    return 出


def _写盘面(能力列表: list, 定义表: dict, 注册: dict) -> dict[str, dict]:
    """`能力id -> {"实现函数","平台写腿","裸写","临时落点"}`（每类给 `文件:行 名` 去重清单）。"""
    面: dict[str, dict] = {}
    for 能力 in 能力列表:
        if not isinstance(能力, dict):
            continue
        编号 = str(能力.get("能力id") or "")
        函数名 = 注册.get(编号, "")
        条 = {"实现函数": 函数名, "平台写腿": [], "裸写": [], "临时落点": []}
        面[编号] = 条
        if not 函数名:
            continue
        桶: dict[str, set] = {"平台": set(), "裸写": set(), "临时落点": set()}
        for 函数 in _可达函数体(函数名, 定义表):
            for 子 in ast.walk(函数["节点"]):
                if not isinstance(子, ast.Call):
                    continue
                命中 = _写盘命中(子)
                if 命中:
                    类别, _, 名 = 命中.partition(":")
                    桶[类别].add(f"{函数['文件'].name}:{子.lineno} {名}")
        if 桶["临时落点"]:
            # **自造临时目录 ⇒ 本能力的写盘动作按「临时落点」算**（`mkdtemp`/`mkstemp`/
            # `TemporaryDirectory`，落点＝系统临时目录＝仓库外）。
            # 这一条压制**同时**给判据 B 与 C 用 —— B/C 只认 `裸写` 与 `平台写腿`，
            # 此处整簇挪进 `临时落点`，两边**同时**生效，**不为 C 另写一份**（同一套机器）。
            # 实测假红：`办公文档支持库.解析文字/演示/表格文档` 的 `mkdtemp+rmtree`、
            # `技能库.受控执行.运行技能包` 的 `write_text`（写的是它自己 `mkdtemp` 出来的目录）。
            # 代价（如实声明）：**自造临时目录又同时写受管文件**的能力会被漏报
            # （见模块 docstring「判据边界」第 2 条）。
            桶["临时落点"] |= 桶["裸写"]
            桶["裸写"] = set()
        条["平台写腿"] = sorted(桶["平台"])
        条["裸写"] = sorted(桶["裸写"])
        条["临时落点"] = sorted(桶["临时落点"])
    return 面


def 判定记录(记录: dict, 豁免映射: dict[str, tuple[str, str]]) -> dict:
    """单条能力的判定：返回带「组 / 判定 / 缺什么 / 缺乏什么导致无法自动自愈」的结果。"""
    编号 = 记录["能力id"]
    出 = {
        "能力id": 编号,
        "包路径": 记录["包路径"],
        "内部层": 记录["内部层"],
        "副作用": 记录["副作用"],
        "只读": 记录["只读"],
        "有凭证": 记录["有凭证"],
        "组": "",
        "判定": "通过",
        "缺什么": "",
        "缺乏什么导致无法自动自愈": "",
        "能否自动自愈": 真,
        "豁免出口": "",
        "豁免理由": "",
    }
    出["实现函数"] = 记录.get("实现函数", "")
    出["平台写腿"] = tuple(记录.get("平台写腿", ()))
    出["裸写"] = tuple(记录.get("裸写", ()))
    出["临时落点"] = tuple(记录.get("临时落点", ()))
    副作用 = 记录["副作用"]
    if not isinstance(副作用, str) or not 副作用.strip():
        出["组"] = 缺口_副作用缺失
        出["判定"] = "判红"
        出["缺什么"] = "行为.副作用 缺失或为空（证不出「只读」）"
        出["能否自动自愈"] = 假
        出["缺乏什么导致无法自动自愈"] = (
            "缺：能力契约里 `行为.副作用` 的值（当前缺失/空）"
            " → 修法：在 能力定义.json 该能力补 `行为.副作用`（只读类写 `只读`；"
            "有写入面写清写什么），或按闭集出口登记豁免")
        return 出

    # ── 判据 B：`副作用` 可证只读，而**可达函数体**有写盘 ⇒ 声明与实现不符 ─────────
    # 只算「裸写 + 平台写腿」；**临时落点单列归 `仓库外`**（`mkdtemp`/`mkstemp` 落系统临时
    # 目录），不计入本判据（否则 `办公文档支持库.解析文字/演示/表格文档` 是假红）。
    if 记录["只读"]:
        真写 = tuple(记录.get("裸写", ())) + tuple(记录.get("平台写腿", ()))
        if 真写:
            出["组"] = 缺口_只读声明不符
            出["判定"] = "判红"
            出["缺什么"] = (f"`行为.副作用` 声明可证只读，但实现面有写盘动作"
                          f"（{len(真写)} 处，首处 {真写[0]}）")
            出["能否自动自愈"] = 假
            出["缺乏什么导致无法自动自愈"] = (
                f"缺：`行为.副作用` 与实现一致的**其中一方**（实现函数 `{出['实现函数']}`）"
                " → 修法：真写盘就把 `行为.副作用` 改成非只读并补 `开工ID`（走平台写腿）；"
                "确不写受管面就改实现、或按闭集出口登记豁免。"
                "★ 本判据是 AST 调用名匹配、不是数据流（见模块 docstring「判据边界」第 2 条）")
        return 出

    豁免 = 豁免映射.get(编号)
    if 豁免:
        出["豁免出口"], 出["豁免理由"] = 豁免
        return 出
    # ── 判据 A 的**触发面**（2026-09-25 第三轮收窄）：非只读 **且 写盘面可见** 才要求凭证。
    # 「可见」＝可达函数体内有 `裸写` 或 `平台写腿`（`临时落点` **不算**：落系统临时目录＝仓库外）。
    # ★ **不可证不可见时退回 fail-closed**：实现函数没映射到、或实现面腿不可用 ⇒ 仍按原判据要求
    # 凭证，**绝不因为「扫不到」就静默放过**（否则复用腿一坏，全仓非只读项集体转绿＝假绿）。
    面已知 = bool(记录.get("实现函数")) and not _实现面腿问题
    写盘面可见 = bool(记录.get("裸写") or 记录.get("平台写腿"))
    需凭证 = (not 面已知) or 写盘面可见
    if 记录["有凭证"]:
        # ── 判据 C：有 `开工ID` 但**无写腿消费点** ⇒ 装饰性合规（盲区二）────────────
        # 判据：可达函数体有**裸写**，且**一个平台写腿调用都没有** ⇒ 凭证根本没机会被消费。
        裸写 = tuple(记录.get("裸写", ()))
        if 裸写 and not 记录.get("平台写腿"):
            出["组"] = 缺口_凭证无消费点
            出["判定"] = "判红"
            出["缺什么"] = (f"参数表有 `{凭证参数名}` 但实现面**零平台写腿调用**，"
                          f"落盘走实现层直写（{len(裸写)} 处，首处 {裸写[0]}）")
            出["能否自动自愈"] = 假
            出["缺乏什么导致无法自动自愈"] = (
                f"缺：实现 `{出['实现函数']}` 里对 `{凭证参数名}` 的**消费点**"
                " → 修法：把裸写改成经平台写腿（`写入文件`/`原子写入`/`应用精确替换` 等）"
                f"并把 `{凭证参数名}` 一路透传进去；**只加参数不接写腿＝装饰性合规**，"
                "受管路径写入照样恒拒（或更糟：绕过 `校验写入授权` 直写）")
        return 出
    if not 需凭证:
        # ── 留痕组（**不判红**）：非只读，但实现面**看不到任何写盘动作** ─────────────────
        # 这正是本门禁的已知盲区（进程外写盘 / 跨包写腿，见 docstring「判据边界」第 3/4 条）：
        # 判据看不见它的写盘，也就无从要求凭证。**静默放过＝假绿** ⇒ 单列一组如实留痕，
        # 让「判据看不见」这件事本身可被复核。它不是「通过」，也不是「豁免」。
        出["组"] = 缺口_写盘面不可见
        出["判定"] = "留痕"
        出["缺什么"] = ("非只读，但实现面**看不到写盘动作**（进程外 / 跨包）"
                      "⇒ 不要求 `开工ID`（不判红，留痕待复核）")
        出["能否自动自愈"] = 假
        出["缺乏什么导致无法自动自愈"] = (
            "缺：对该能力**真实写盘动作**的可见性（本门禁只看同包 AST 调用名，"
            "看不到子进程写盘与跨包写腿）"
            " → 修法：人核它的真实落点 —— 落受管面就补 `开工ID` 并改走平台写腿；"
            "落非受管面就按闭集出口登记豁免；确属外部程序写盘而四条出口一条都不贴时，"
            "**需先裁决是否新增出口**，不得随手扩出口闭集")
        return 出
    出["组"] = 缺口_非只读缺凭证
    出["判定"] = "判红"
    出["缺什么"] = f"非只读能力的参数表缺 `{凭证参数名}`"
    出["能否自动自愈"] = 假
    出["缺乏什么导致无法自动自愈"] = (
        f"缺：该能力 `参数` 里的 `{凭证参数名}`（文本型、必填）"
        " → 修法：在 能力定义.json 补参数并让实现**一路透传**到写腿（否则受管路径写入恒拒）；"
        "若它本就不写受管面，则按闭集出口（仓库外/豁免前缀/自管临时资源/写者是平台编译机）"
        "登记进豁免表")
    return 出


def 运行门禁(系统根: Path | None = None, *, 豁免映射: dict[str, tuple[str, str]] | None = None) -> dict:
    """跑一遍全仓：返回 `{"公开层", "内部层", "副作用字段缺失", "只读声明不符",
    "凭证无消费点", "统计", "豁免命中", "问题"}`。"""
    系统根 = Path(系统根 or 仓库根).resolve()
    豁免映射 = 豁免索引() if 豁免映射 is None else 豁免映射
    取证 = 扫描(系统根)
    判定列表 = [判定记录(项, 豁免映射) for 项 in 取证["记录"]]
    红 = [项 for 项 in 判定列表 if 项["判定"] == "判红"]
    公开层 = [项 for 项 in 红 if 项["组"] == 缺口_非只读缺凭证 and not 项["内部层"]]
    内部层 = [项 for 项 in 红 if 项["组"] == 缺口_非只读缺凭证 and 项["内部层"]]
    副作用缺失 = [项 for 项 in 红 if 项["组"] == 缺口_副作用缺失]
    只读声明不符 = [项 for 项 in 红 if 项["组"] == 缺口_只读声明不符]
    凭证无消费点 = [项 for 项 in 红 if 项["组"] == 缺口_凭证无消费点]
    写盘面不可见 = [项 for 项 in 判定列表 if 项["组"] == 缺口_写盘面不可见]
    命中 = [项 for 项 in 判定列表 if 项["豁免出口"]]
    统计 = {
        "包数": 取证["包数"],
        "无能力定义包数": 取证["无能力定义包数"],
        "空能力面包数": 取证["空能力面包数"],
        "能力总数": len(判定列表),
        "只读": sum(1 for 项 in 判定列表 if 项["只读"]),
        "非只读": sum(1 for 项 in 判定列表 if not 项["只读"]),
        "非只读且有凭证": sum(1 for 项 in 判定列表 if not 项["只读"] and 项["有凭证"]),
        "豁免命中": len(命中),
        "红项": len(红),
        "公开层红": len(公开层),
        "内部层红": len(内部层),
        "副作用字段缺失红": len(副作用缺失),
        "只读声明不符红": len(只读声明不符),
        "凭证无消费点红": len(凭证无消费点),
        "写盘面不可见留痕": len(写盘面不可见),
        "扫描问题": len(取证["问题"]),
    }
    return {"公开层": 公开层, "内部层": 内部层, "副作用字段缺失": 副作用缺失,
            "只读声明不符": 只读声明不符, "凭证无消费点": 凭证无消费点,
            "写盘面不可见": 写盘面不可见,
            "统计": 统计, "豁免命中": 命中, "问题": 取证["问题"]}


def 生成文本报告(结果: dict, 明细上限: int = 默认明细上限) -> str:
    """人读报告：三组红项逐条给「能力id / 包路径 / 缺什么」+「缺乏什么导致无法自动自愈」。"""
    行: list[str] = []
    统计 = 结果["统计"]
    行.append("写入凭证透传门禁：非只读能力必须声明 `开工ID`（判据口径见模块 docstring）")
    行.append(
        f"  包 {统计['包数']}（无 能力定义.json 的聚合视图包 {统计['无能力定义包数']}，跳过；"
        f"显式空能力面包 {统计['空能力面包数']}）"
        f"；能力 {统计['能力总数']}（只读 {统计['只读']} / 非只读 {统计['非只读']}）；"
        f"非只读且有凭证 {统计['非只读且有凭证']}；豁免命中 {统计['豁免命中']}")
    行.append(
        f"  红项 {统计['红项']}：公开层 {统计['公开层红']} / 内部层 {统计['内部层红']}"
        f" / 副作用字段缺失 {统计['副作用字段缺失红']}"
        f" / 只读声明不符 {统计['只读声明不符红']}"
        f" / 凭证无消费点 {统计['凭证无消费点红']}"
        f"；留痕（写盘面不可见）{统计['写盘面不可见留痕']}；扫描问题 {统计['扫描问题']}")
    if 结果["问题"]:
        行.append("")
        行.append("【扫描问题】（fail-closed，逐条判红）")
        for 项 in 结果["问题"]:
            行.append(f"  [{项['缺口类型']}] {项['路径']}：{项['详情']}")
    for 组名, 键 in (("公开层", "公开层"), ("内部层", "内部层"), ("副作用字段缺失", "副作用字段缺失"),
                    ("只读声明与实现不符（判据 B）", "只读声明不符"),
                    ("凭证无消费点 / 实现层直写（判据 C）", "凭证无消费点"),
                    ("非只读-写盘面不可见（留痕，不判红）", "写盘面不可见")):
        条 = 结果[键]
        行.append("")
        行.append(f"【{组名}】红项 {len(条)} 条")
        if not 条:
            行.append("  （空）")
            continue
        for 项 in 条[:max(0, 明细上限)]:
            行.append(f"  · {项['能力id']} | 包={项['包路径']} | 缺什么={项['缺什么']}")
            行.append(f"      缺乏什么导致无法自动自愈：{项['缺乏什么导致无法自动自愈']}")
        if len(条) > 明细上限:
            行.append(f"  …（余 {len(条) - 明细上限} 条省略，--明细上限 调大或 --json 取全量）")
    if 结果["豁免命中"]:
        行.append("")
        行.append(f"【已豁免】（豁免表初稿命中 {len(结果['豁免命中'])} 条，按出口分组）")
        分组: dict[str, int] = {}
        for 项 in 结果["豁免命中"]:
            分组[项["豁免出口"]] = 分组.get(项["豁免出口"], 0) + 1
        for 出口, 数 in sorted(分组.items()):
            行.append(f"  · 出口={出口}：{数} 条")
    return "\n".join(行)


def 生成json报告(结果: dict) -> str:
    return json.dumps(结果, ensure_ascii=False, indent=2)


def 反向验证三拍(系统根: Path | None = None) -> tuple[int, str]:
    """反向验证（**内存注入，不改任何文件**）：`(退出码, 报告文本)`。

    ① 取一条**已合规**的真实能力（非只读 + 有 `开工ID`），在内存记录里把「有凭证」置假
       ⇒ 必须判红；还原 ⇒ 必须通过。
    ② 取一条**已登记豁免**的真实能力，判定必须通过；把豁免索引里该 id 删掉 ⇒ 必须判红。
    ③ 取一条真实能力，把 `副作用` 置空 ⇒ 必须判红，且落进「副作用字段缺失」组。
    ④（判据 B）取一条**可证只读**的真实能力，在内存记录里塞一条裸写 ⇒ 必须判红，且落进
       「只读声明与实现不符」组；清空 ⇒ 必须通过。
    ⑤（判据 C）取一条「非只读 + 有 `开工ID` + 有裸写 + 零平台写腿」的真实能力 ⇒ 必须判红，
       且落进「凭证无消费点」组；补一条平台写腿 ⇒ 必须通过。
    ⑥（判据 A 的**新触发面**）取一条「非只读 + 无凭证 + **写盘面不可见** + 未豁免」的真实能力
       ⇒ 必须**留痕**（不判红）；注入一条裸写 ⇒ 必须判红（证明触发面确实由写盘面把关）。
    ⑦（临时落点压制对 B/C **同一套**生效）取一条带 `临时落点` 的真实能力，断言其 `裸写` 为空、
       且判定不落进 B/C 两组（**真实数据断言**，非内存注入）。

    本函数名保留「三拍」（外部按此名调用），实际已扩到**七拍**（A 三拍 + B/C 各一拍
    + 新触发面一拍 + 临时落点压制一拍）。
    """
    系统根 = Path(系统根 or 仓库根).resolve()
    取证 = 扫描(系统根)
    映射 = 豁免索引()
    行: list[str] = ["反向验证三拍（内存注入，不落盘；每拍都贴真实判定字段）"]
    失败: list[str] = []

    合规 = next((项 for 项 in 取证["记录"]
                if not 项["只读"] and 项["有凭证"] and 项["能力id"] == "文件系统支持库.文件操作.写入文件"), None)
    if 合规 is None:
        合规 = next((项 for 项 in 取证["记录"] if not 项["只读"] and 项["有凭证"]), None)
    行.append("")
    行.append("① 已合规能力临时去掉 `开工ID` ⇒ 必须判红；还原 ⇒ 必须通过")
    if 合规 is None:
        行.append("  未核验：全仓找不到「非只读且含 开工ID」的能力，本拍无法取证")
        失败.append("①")
    else:
        坏 = dict(合规)
        坏["有凭证"] = 假
        判坏 = 判定记录(坏, 映射)
        判好 = 判定记录(合规, 映射)
        行.append(f"  取样：{合规['能力id']}（副作用={合规['副作用']!r}）")
        行.append(f"  去掉 开工ID ⇒ 判定={判坏['判定']} 组={判坏['组']} 缺什么={判坏['缺什么']}")
        行.append(f"  还原       ⇒ 判定={判好['判定']} 组={判好['组'] or '（无）'} 有凭证={判好['有凭证']}")
        if 判坏["判定"] != "判红" or 判好["判定"] != "通过":
            失败.append("①")

    行.append("")
    行.append("② 已登记豁免项临时去掉豁免 ⇒ 必须判红（证明豁免表真在用，不是死数据）")
    # ★ 取样必须带**可见写盘面**：判据 A 的触发面收窄后，写盘面不可见的豁免项**去掉豁免只会落
    # 「留痕」**（不判红）—— 拿它做本拍会**假失败**（实测：`平台控制面.发布管理.登记发布期望`，
    # 它的写腿在别的包）。本拍要证的是「豁免表真在用」，故只取写盘面可见的样本。
    豁免样本 = next((项 for 项 in 取证["记录"]
                 if 项["能力id"] in 映射 and (项["裸写"] or 项["平台写腿"])), None)
    if 豁免样本 is None:
        行.append("  未核验：豁免表里没有「写盘面可见」的能力id 命中（豁免表与全仓脱节，"
                 "或全表都是写盘面不可见项）")
        失败.append("②")
    else:
        判豁免 = 判定记录(豁免样本, 映射)
        无豁免映射 = {k: v for k, v in 映射.items() if k != 豁免样本["能力id"]}
        判无豁免 = 判定记录(豁免样本, 无豁免映射)
        行.append(f"  取样：{豁免样本['能力id']}（出口={判豁免['豁免出口']}，副作用={豁免样本['副作用']!r}）")
        行.append(f"  带豁免 ⇒ 判定={判豁免['判定']} 组={判豁免['组'] or '（无）'}")
        行.append(f"  去豁免 ⇒ 判定={判无豁免['判定']} 组={判无豁免['组']} 缺什么={判无豁免['缺什么']}")
        if 判豁免["判定"] != "通过" or 判无豁免["判定"] != "判红":
            失败.append("②")

    行.append("")
    行.append("③ 副作用字段缺失 ⇒ 必须判红（fail-closed：证不出「只读」就不放过）")
    样本 = next((项 for 项 in 取证["记录"] if 项["只读"]), None)
    if 样本 is None:
        行.append("  未核验：找不到只读能力做取样")
        失败.append("③")
    else:
        坏 = dict(样本)
        坏["副作用"] = ""
        坏["只读"] = 是否只读("")
        判坏 = 判定记录(坏, 映射)
        行.append(f"  取样：{样本['能力id']}（原副作用={样本['副作用']!r}）")
        行.append(f"  置空副作用 ⇒ 判定={判坏['判定']} 组={判坏['组']} 缺什么={判坏['缺什么']}")
        行.append(f"      缺乏什么导致无法自动自愈：{判坏['缺乏什么导致无法自动自愈']}")
        if 判坏["判定"] != "判红" or 判坏["组"] != 缺口_副作用缺失:
            失败.append("③")

    行.append("")
    行.append("④ 判据 B：可证只读的能力被塞进一条写盘动作 ⇒ 必须判红（声明与实现不符）")
    只读样本 = next((项 for 项 in 取证["记录"] if 项["只读"]), None)
    if 只读样本 is None:
        行.append("  未核验：找不到只读能力做取样")
        失败.append("④")
    else:
        坏 = dict(只读样本)
        坏["裸写"] = ("反向验证注入:1 write_text",)
        判坏 = 判定记录(坏, 映射)
        判好 = 判定记录(只读样本, 映射)
        行.append(f"  取样：{只读样本['能力id']}（副作用={只读样本['副作用']!r}）")
        行.append(f"  注入裸写 ⇒ 判定={判坏['判定']} 组={判坏['组']} 缺什么={判坏['缺什么']}")
        行.append(f"  还原     ⇒ 判定={判好['判定']} 组={判好['组'] or '（无）'}")
        if 判坏["判定"] != "判红" or 判坏["组"] != 缺口_只读声明不符 or 判好["判定"] != "通过":
            失败.append("④")

    行.append("")
    行.append("⑤ 判据 C：有 `开工ID` 而实现面零平台写腿 ⇒ 必须判红（装饰性合规）")
    面样本 = next((项 for 项 in 取证["记录"] if 项["有凭证"] and 项["裸写"]
                 and not 项["平台写腿"] and 项["能力id"] not in 映射), None)
    if 面样本 is None:
        行.append("  未核验：全仓找不到「有凭证 + 有裸写 + 零平台写腿 + 未豁免」的能力（判据 C 面为空）")
        失败.append("⑤")
    else:
        判坏 = 判定记录(面样本, 映射)
        补 = dict(面样本)
        补["平台写腿"] = ("反向验证注入:1 写入文件",)
        判好 = 判定记录(补, 映射)
        行.append(f"  取样：{面样本['能力id']}（实现函数={面样本['实现函数']}，裸写 {len(面样本['裸写'])} 处）")
        行.append(f"  零平台写腿   ⇒ 判定={判坏['判定']} 组={判坏['组']} 缺什么={判坏['缺什么']}")
        行.append(f"  补平台写腿   ⇒ 判定={判好['判定']} 组={判好['组'] or '（无）'}")
        if 判坏["判定"] != "判红" or 判坏["组"] != 缺口_凭证无消费点 or 判好["判定"] != "通过":
            失败.append("⑤")

    行.append("")
    行.append("⑥ 判据 A 新触发面：非只读 + 无凭证 + 写盘面不可见 ⇒ 留痕（不判红）；注入裸写 ⇒ 判红")
    无面样本 = next((项 for 项 in 取证["记录"] if not 项["只读"] and not 项["有凭证"]
                  and not 项["裸写"] and not 项["平台写腿"] and 项["实现函数"]
                  and 项["能力id"] not in 映射), None)
    if 无面样本 is None:
        行.append("  未核验：全仓找不到「非只读 + 无凭证 + 写盘面不可见 + 未豁免」的能力")
        失败.append("⑥")
    else:
        判留痕 = 判定记录(无面样本, 映射)
        注入 = dict(无面样本)
        注入["裸写"] = ("反向验证注入:1 write_text",)
        判注入 = 判定记录(注入, 映射)
        行.append(f"  取样：{无面样本['能力id']}（实现函数={无面样本['实现函数']}）")
        行.append(f"  写盘面不可见 ⇒ 判定={判留痕['判定']} 组={判留痕['组']} 缺什么={判留痕['缺什么']}")
        行.append(f"  注入裸写     ⇒ 判定={判注入['判定']} 组={判注入['组']}")
        if 判留痕["判定"] != "留痕" or 判留痕["组"] != 缺口_写盘面不可见 \
                or 判注入["判定"] != "判红" or 判注入["组"] != 缺口_非只读缺凭证:
            失败.append("⑥")

    行.append("")
    行.append("⑦ 临时落点压制对 B/C 同一套生效（真实数据断言）")
    临时样本 = next((项 for 项 in 取证["记录"] if 项["临时落点"]), None)
    if 临时样本 is None:
        行.append("  未核验：全仓找不到带 `临时落点` 的能力（压制规则无从取证）")
        失败.append("⑦")
    else:
        判临 = 判定记录(临时样本, 映射)
        行.append(f"  取样：{临时样本['能力id']}（临时落点 {len(临时样本['临时落点'])} 处，"
                 f"裸写 {len(临时样本['裸写'])} 处，平台写腿 {len(临时样本['平台写腿'])} 处）")
        行.append(f"  判定={判临['判定']} 组={判临['组'] or '（无）'}"
                 "；压制生效判据＝裸写必须为 0（否则 B/C 仍把它当真写）")
        if 临时样本["裸写"] or 判临["组"] in (缺口_只读声明不符, 缺口_凭证无消费点):
            失败.append("⑦")

    行.append("")
    if 失败:
        行.append(f"反向验证未全过：拍 {('、'.join(失败))} 未达预期 ⇒ 判红")
        return 1, "\n".join(行)
    行.append("反向验证七拍全部达预期：① 去凭证判红/还原通过；② 去豁免判红；③ 副作用缺失判红；"
             "④ 只读+写盘判红/还原通过（判据 B）；⑤ 有凭证+零平台写腿判红/补写腿通过（判据 C）；"
             "⑥ 写盘面不可见留痕/注入裸写判红（判据 A 新触发面）；⑦ 临时落点压制对 B/C 同一套生效。")
    return 0, "\n".join(行)


def 构造解析器() -> argparse.ArgumentParser:
    解析器 = argparse.ArgumentParser(
        prog="写入凭证透传门禁.py",
        description="非只读能力必须声明 `开工ID` 参数；否则须登记在带理由的豁免表里。",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    解析器.add_argument("--根", default=str(仓库根), help="仓库根（默认本文件所在仓库根）")
    解析器.add_argument("--json", dest="json输出", action="store_true", help="以 JSON 输出全量结果")
    解析器.add_argument("--只报告", dest="只报告", action="store_true", help="有红也返回 0（接入编译口前的默认档）")
    解析器.add_argument("--自测", dest="自测", action="store_true", help="反向验证三拍（内存注入，不改文件）")
    解析器.add_argument("--明细上限", dest="明细上限", type=int, default=默认明细上限,
                        help=f"文本报告每组明细上限（默认 {默认明细上限}）")
    return 解析器


def 主程序(argv: list[str] | None = None) -> int:
    参数 = 构造解析器().parse_args(argv)
    根 = Path(参数.根).resolve()
    if not 根.is_dir():
        print(f"环境错误：根目录不存在 {根}", file=sys.stderr)
        return 2
    if not (根 / "公共契约" / "正式根.py").is_file():
        print(f"环境错误：{根} 下找不到 公共契约/正式根.py（唯一事实源）", file=sys.stderr)
        return 2

    if 参数.自测:
        码, 文本 = 反向验证三拍(根)
        print(文本)
        return 码

    结果 = 运行门禁(根)
    if 参数.json输出:
        print(生成json报告(结果))
    else:
        print(生成文本报告(结果, 明细上限=max(0, 参数.明细上限)))

    # 空集闸（哲学 1.4「空集 ≠ 通过」）：扫不到能力与「能力都合规」的返回形状一样，
    # 不在此拦一道，门禁会拿「没扫到任何能力」当「没有违规」照样退 0 —— 空集假绿通道。
    if 结果["统计"]["能力总数"] == 0:
        print("（写入凭证透传门禁未核验：能力总数=0，空集不等于通过（哲学 1.4））", file=sys.stderr)
        return 2
    红数 = 结果["统计"]["红项"] + 结果["统计"]["扫描问题"]
    if 参数.只报告:
        print(f"（--只报告：本次红项 {红数} 条按约定不阻断，退出码 0）", file=sys.stderr)
        return 0
    if 红数:
        print(f"（写入凭证透传门禁判红：红项 {红数} 条）", file=sys.stderr)
        return 1
    print("（写入凭证透传门禁通过：非只读能力均已声明 `开工ID` 或已按闭集出口登记豁免）", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(主程序())
