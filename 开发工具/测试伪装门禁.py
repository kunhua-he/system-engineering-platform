    for 项 in 解析失败:
        违规.append({
            "规则": "规则1", "类型": "解析失败（fail-closed）", "文件": 项["相对路径"],
            "行号": None, "子类型": "", "细节": 项["细节"],
            "建议": "修复文件可读性/语法后复跑（无法解析即无法证明桩与断言合规）",
        })
    统计1, 统计2, 统计3 = 空规则1统计(), 空规则2统计(), 空规则3统计()
    形式分布: dict[str, int] = {}
    桩总数 = 0
    for 资产 in 资产列表:
        if not 资产.可用:
            continue
        调用点列表 = 桩检测.收集桩调用点(资产, 根)
        桩总数 += len(调用点列表)
        统计2["自动规格调用"] += 桩检测.收集自动规格数(资产)
        for 点 in 调用点列表:
            形式分布[点.形式] = 形式分布.get(点.形式, 0) + 1
            判定1 = 桩检测.判定规则1(点, 豁免表)
            if 判定1:
                if "类型" in 判定1:
                    统计1["违规"] += 1
                    统计1["P1" if 判定1["层级"].startswith("P1") else "P2"] += 1
                    键 = {"本体成员": "本体成员", "依赖边界": "依赖边界"}.get(点.成员分类, "未知成员")
                    统计1[键] += 1
                    违规.append(_成条(点, 判定1, "规则1"))
                elif 判定1["层级"].startswith("豁免"):
                    if 判定1["层级"] == "豁免·清单":
                        统计1["清单豁免"] += 1
                    else:
                        统计1["wraps豁免"] += 1
                    已豁免.append({"规则": "规则1", "文件": 点.相对路径, "行号": 点.行号,
                                 "细节": f"{判定1['层级']}：{判定1['依据']}"})
                else:
                    统计1["观察"] += 1
                    观察.append({"相对路径": 点.相对路径, "行号": 点.行号,
                               "细节": f"规则1 {判定1['层级']}：{判定1['依据']}（{点.目标}）"})
            判定2 = 桩检测.判定规则2(点, 豁免表)
            if 判定2:
                if "类型" in 判定2:
                    统计2["违规"] += 1
                    违规.append(_成条(点, 判定2, "规则2"))
                elif 判定2["层级"].startswith("合规"):
                    统计2["合规"] += 1
                elif 判定2["层级"].startswith("豁免"):
                    if 判定2["层级"] == "豁免·清单":
                        统计2["清单豁免"] += 1
                    else:
                        统计2["wraps豁免"] += 1
                    已豁免.append({"规则": "规则2", "文件": 点.相对路径, "行号": 点.行号,
                                 "细节": f"{判定2['层级']}：{判定2['依据']}"})
                else:
                    统计2["不适用"] += 1
        for 用例 in 断言检测.收集用例(资产):
            统计3["用例总数"] += 1
            三违规, 三观察 = 断言检测.判定规则3(用例, 豁免表)
