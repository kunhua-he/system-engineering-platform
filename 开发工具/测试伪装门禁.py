def 运行门禁(根: Path, *, 豁免路径: Path | None = None) -> list[dict]:
    """门禁入口（供发布门禁调用）：返回违规清单，空列表即通过；不打印。"""
    路径 = Path(豁免路径) if 豁免路径 else 默认豁免路径
    豁免表, 清单错误 = 豁免.读取豁免清单(路径)
    if 清单错误:
        raise ValueError("；".join(清单错误))
    return 运行检查(根, 豁免表=豁免表, 豁免路径=路径)["违规"]


def 运行门禁并摘要(根: Path, *, 强制: bool = False,
                   豁免路径: Path | None = None) -> tuple[list[dict], str]:
    """发布门禁接线用：`(违规清单, 一行摘要)`。

    `强制=False`（默认）即首发「只报不拦」：清单照给，是否阻断由调用方按
    `强制` 决定；后续收紧只需把接线处改成 `强制=True`。
    """
    路径 = Path(豁免路径) if 豁免路径 else 默认豁免路径
    豁免表, 清单错误 = 豁免.读取豁免清单(路径)
    if 清单错误:
        raise ValueError("；".join(清单错误))
    结果 = 运行检查(根, 豁免表=豁免表, 豁免路径=路径)
    return 结果["违规"], 报告.生成摘要行(结果)


def 判定(计数: int, 上限: int | None = None) -> tuple[bool, str]:
    """**本门禁唯一的判绿口径**（发布门禁接线与 `主程序()` 共用这一处实现）。

    `计数 = 违规数 + 清单豁免数`；`上限` 缺省取 `存量违约上限`。

    - 通过 ⇔ `计数 <= 上限`（存量未清零也算通过，但说明里写明「只表示没比基线更差」）；
    - `计数 > 上限` ⇒ 不通过，并写明新增条数（fail-closed，新增违规不可能被放过）。

    改前是**两处口径**：本文件按「违规非空即退 1」自判（存量 259 恒红），发布门禁按
    「计数 ≤ 上限」判绿 ⇒ 同一件事一处红一处绿。现两侧都调本函数，口径只剩一处。
    """
    顶 = int(存量违约上限) if 上限 is None else int(上限)
    计数 = int(计数)
    if 计数 > 顶:
        return 假, (f"计数 {计数} > 存量违约上限 {顶}；**新增 {计数 - 顶} 项**"
                       f"（硬限制不得增加）")
    return 真, (f"计数 {计数} <= 存量违约上限 {顶}；未新增（存量未清零，"
                  f"通过只表示「没比基线更差」，不代表测试桩已合规）")


def 接入报告(根: Path, *, 豁免路径: Path | None = None) -> dict:
    """发布门禁接线用：一次给出 `违规数／清单豁免数／计数／摘要`。

    **为什么把「清单豁免数」单独返回并计入 `计数`**：接入口径是「硬限制不得增加」，
    如果只按 `违规数` 判，那么把违约登记进豁免清单就能把计数压到上限以下，
    等于「用豁免清单把违约清空」。`计数 = 违规数 + 清单豁免数` 堵掉这条路：
    被清单豁免的条目照样计入，登记豁免不能让门禁变绿，只能改代码。

    豁免清单无效时 `ValueError`（fail-closed，由调用方判红，不静默降级）。
    """
    路径 = Path(豁免路径) if 豁免路径 else 默认豁免路径
    豁免表, 清单错误 = 豁免.读取豁免清单(路径)
    if 清单错误:
        raise ValueError("；".join(清单错误))
    结果 = 运行检查(根, 豁免表=豁免表, 豁免路径=路径)
    违规数 = len(结果["违规"])
    清单豁免数 = int(结果["豁免清单"]["命中数"])
    计数 = 违规数 + 清单豁免数
    通过, 判定说明 = 判定(计数)
    return {
        "相对根": 结果["相对根"],
        "违规数": 违规数,
        "清单豁免数": 清单豁免数,
        "计数": 计数,
        "存量违约上限": 存量违约上限,
        "判定": {"通过": 通过, "说明": 判定说明},
        "摘要": 报告.生成摘要行(结果),
        "豁免清单": 结果["豁免清单"],
        "违规": 结果["违规"],
        "观察数": len(结果["观察"]),
    }


def 主程序(参数: list[str] | None = None) -> int:
    解析 = 构造解析器().parse_args(参数)
    根 = Path(解析.根).resolve()
    if not 根.is_dir():
        print(f"环境错误：根目录不存在 {根}", file=sys.stderr)
        return 2
    if not (根 / 发现.测试中心目录名).is_dir():
        print(f"环境错误：{根} 下不存在 {发现.测试中心目录名}/ 目录", file=sys.stderr)
        return 2
    豁免路径 = Path(解析.豁免).resolve() if 解析.豁免 else 默认豁免路径
    豁免表, 清单错误 = 豁免.读取豁免清单(豁免路径)
    if 清单错误:
        print(f"用法错误：豁免清单无效（fail-closed，不静默降级）：{豁免路径}", file=sys.stderr)
        for 错误 in 清单错误:
            print(f"  - {错误}", file=sys.stderr)
        return 2
    结果 = 运行检查(根, 豁免表=豁免表, 豁免路径=豁免路径)
    # 空集闸（哲学 1.4「空集 ≠ 通过」，债务 #61）：
    # 「零测试文件」与「测试都合规」的返回结构完全一样（都是 `违规=[]`），
    # 若不在此拦一道，门禁会拿「没扫到任何测试」当「没有违规」照样退 0 ——
    # 这正是本项要修的空集假绿通道。按未核验处理（退 2），不占通过位。
    # ⚠️ 必须在打印报告之前判：报告尾部会写「测试伪装门禁通过」，
    #    先打印就等于先宣布通过、再退回未核验，文案与退出码自相矛盾（反向验证实测）。
    if 结果["测试文件数"] == 0:
        if 解析.json输出:
            结果["结论"] = "未核验"
            结果["结论说明"] = "测试文件数=0，空集不等于通过（哲学 1.4）"
            print(报告.生成json报告(结果))
        else:
            print(f"测试伪装门禁未核验：{根} 下未扫到任何测试文件（测试文件数=0）。")
            print("空集不等于通过（哲学 1.4）—— 没有可扫的测试，本门禁无法据此判定合规，"
                  "按未核验处理（退出码 2），不占通过位。")
        return 2
    if 解析.json输出:
        print(报告.生成json报告(结果))
    else:
        print(报告.生成文本报告(结果, 明细上限=max(0, 解析.明细上限)))
    计数 = len(结果["违规"]) + int(结果["豁免清单"]["命中数"])
    通过, 判定说明 = 判定(计数)
    if 解析.只报告:
        print(f"（--只报告：本次计数 {计数} 项按约定不阻断，退出码 0）", file=sys.stderr)
        return 0
    if 通过:
        print(f"（测试伪装门禁通过：{判定说明}）", file=sys.stderr)
        return 0
    print(f"（测试伪装门禁判红：{判定说明}）", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(主程序())
