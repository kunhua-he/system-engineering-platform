"""包体检：给一个支持库/模块包目录，一次性报「还差哪几件、差哪条、合法值、怎么修」。

**为什么要它**（2026-09-18 归因，见 `开发文档/分析/新建支持库回填链路归因_20260918.md`）：
新建包的隐性规则散落在各处抛出点（编译器、场景加载、路径安全、组件合规），
作者只能「补一件跑一次」才暴露下一条 —— 即「挤牙膏」，实测一个包耗 40+ 分钟。

本入口把这些判据**汇总到一处、一次报全**，且**不装配、不编译、不写盘**（纯只读），
可在开工第一步就跑，把「要补什么」在动手前说清。

用法：``python3.14 开发工具/包体检.py <包目录>``（退出码 0=无缺项，1=有缺项）
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

系统根 = Path(__file__).resolve().parent.parent
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

# 场景 $动态 允许类型与精确字段集（真源 开发工具/HTML验证/路径安全.py）
动态允许表 = {
    "制品根": {"$动态", "相对路径"},
    "受管临时目录": {"$动态", "相对路径"},
    "受管临时路径": {"$动态", "相对路径"},
    "夹具文件复制": {"$动态", "来源", "目标"},
    "步骤返回": {"$动态", "步骤id", "JSON路径"},
    "环境变量": {"$动态", "名称"},
}
生成标记 = "本文件由契约编译器自动生成，禁止手工修改"
九要素目录 = ("实现", "能力契约", "权限契约", "配置契约", "说明")
# 占位/骨架态标记：出现即说明还是模板产物，作者必须补真实内容
骨架标记表 = ("**待填写**", "待填写：", "骨架占位", "（骨架，返回未实现/占位值）")


def _缺(项: str, 说明: str, 怎么修: str) -> dict:
    return {"项": 项, "说明": 说明, "怎么修": 怎么修}


def _读JSON(路径: Path):
    try:
        return json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def 体检目录(包目录: Path) -> list[dict]:
    """九要素目录与必备文件是否齐全。"""
    缺项 = []
    for 子 in 九要素目录:
        if not (包目录 / 子).is_dir():
            缺项.append(_缺(f"目录 {子}/", "九要素目录缺失", "用 生成支持库模板 重新生成，或手工补齐该目录"))
    for 名, 描述 in (("能力定义.json", "唯一可编辑事实源"), ("包声明.json", "包元数据"),
                    ("依赖锁.json", "有第三方/外部依赖时必须存在（无依赖不要建）"),
                    ("复用决策.json", "设计期决策记录"), ("资源预算.json", "资源预算十项必需键")):
        if not (包目录 / 名).is_file():
            缺项.append(_缺(名, f"{描述}：文件缺失", "模板生成器会产它；缺则重跑生成器或手工补"))
    return 缺项


def 体检入口注册(包目录: Path) -> list[dict]:
    """__init__.py 是否含 `def 注册能力`（编译器对此有豁免特判）。"""
    入口 = 包目录 / "__init__.py"
    if not 入口.is_file():
        return [_缺("__init__.py", "包级中文入口缺失", "模板生成器会产它")]
    文本 = 入口.read_text(encoding="utf-8")
    缺项 = []
    if 生成标记 not in 文本 and "def 注册能力" not in 文本:
        缺项.append(_缺(
            "__init__.py 的 def 注册能力",
            "入口不是生成物、又不含 `def 注册能力` → 编译器会判「生成文件被手工修改」并拒绝编译",
            "在 __init__.py 里**直接定义** def 注册能力(注册表)（不是从别处 import），"
            "或让编译器重新生成该入口"))
    return 缺项


def 体检复用决策(包目录: Path) -> list[dict]:
    """复用决策：搜索词/候选能力id 必须非空（真跑过搜索）。"""
    数据 = _读JSON(包目录 / "复用决策.json")
    if 数据 is None:
        return [_缺("复用决策.json", "缺失或不是合法 JSON", "重跑生成器")]
    缺项 = []
    for 键, 说明 in (("搜索词", "必须填你真实用过的能力搜索词（至少一个）"),
                    ("候选能力id", "必须填能力搜索真实命中的候选 id；查无命中也要写明「未命中」")):
        值 = 数据.get(键)
        if not 值:
            缺项.append(_缺(f"复用决策.{键}", f"为空 → 组件合规「结构」场景判红（S0 缺项阻断）。{说明}",
                          "真跑一次能力搜索（开发工具/开发能力搜索）后据实填写"))
    return 缺项


def 体检权限契约(包目录: Path) -> list[dict]:
    """权限契约必须逐能力声明（组件合规「权限」项按能力遍历）。"""
    路径 = 包目录 / "权限契约" / "权限契约.json"
    if not 路径.is_file():
        return [_缺("权限契约/权限契约.json", "缺失 → 组件合规「权限」项阻断", "按能力 id 逐条声明 允许用户")]
    声明 = _读JSON(路径) or {}
    定义 = _读JSON(包目录 / "能力定义.json") or {}
    缺项 = []
    for 能力 in 定义.get("能力列表") or []:
        能力id = 能力.get("能力id")
        if 能力id and 能力id not in 声明:
            缺项.append(_缺(f"权限声明 {能力id}", "该能力没有权限声明",
                          f'在 权限契约.json 里加 "{能力id}": {{"允许用户": ["*"]}}'))
    return 缺项


def _解析包内场景(包目录: Path) -> list:
    """解析包内的验证场景引用（**复用官方唯一解析器**，不自己再写一套）。

    ★ 为什么改成复用（2026-09-18 实测修根）：
      原实现只读 `验证场景引用.json` 里的**内联场景**（`{"场景": {...}}`），
      完全忽略**外部场景文件**形态（`{"场景文件": "验证场景/x.json"}`）——
      而后者是全仓主流（实测：外部引用 71 处 / 内联 43 处）。
      后果：凡是把场景写在 `验证场景/*.json` 里的包，体检一律误报
      「该公开能力没有成功目标步骤」，即使场景里明明有成功步骤
      （实证：`支持库/前端/桌面宿主`、`支持库/后端/OCR识别支持库/OCR识别` 均被误报）。
      官方 `开发工具/HTML验证/场景加载._解析场景引用` 本就把两种形态都支持，
      故此处直接复用它 —— 同一件事不维护两套实现（哲学 1.2）。
    """
    from 开发工具.HTML验证.场景加载 import _解析场景引用
    try:
        return [场景 for 场景, _ in _解析场景引用(包目录)]
    except Exception:   # noqa: BLE001 —— 解析失败要按缺项如实上报，不静默
        raise


def 体检验证场景(包目录: Path) -> list[dict]:
    """验证场景：引用非空 + $动态 合法 + 失败用例带返回断言 + 有成功目标步骤。"""
    引用文件 = 包目录 / "验证场景引用.json"
    缺项 = []
    if not 引用文件.is_file():
        return [_缺("验证场景引用.json", "缺失 → 验证证据为空，组件合规「结构」项阻断", "写场景引用")]
    数据 = _读JSON(引用文件) or {}
    引用 = 数据.get("验证场景引用") or []
    if not 引用:
        return [_缺("验证场景引用.验证场景引用", "列表为空 → 验证证据为空（S0 阻断）",
                    "至少写一个场景，含成功目标步骤")]
    场景表 = _解析包内场景(包目录)
    目标能力 = set()
    for 场景 in 场景表:
        if not isinstance(场景, dict):
            continue
        for 步 in 场景.get("目标步骤") or []:
            if 步.get("预期", {}).get("成功") is True:
                目标能力.add(步.get("能力id"))
    for 能力 in (_读JSON(包目录 / "能力定义.json") or {}).get("能力列表") or []:
        if 能力.get("能力id") not in 目标能力:
            缺项.append(_缺(f"成功目标步骤 {能力.get('能力id')}",
                          "该公开能力没有成功目标步骤（只有失败用例不算覆盖）",
                          "补一个预期 成功=true 的步骤"))
    for 场景 in 场景表:
        if not isinstance(场景, dict):
            continue
        for 步 in 场景.get("目标步骤") or []:
            预期 = 步.get("预期") or {}
            if 预期.get("成功") is False and "返回断言" not in 预期:
                缺项.append(_缺(f"失败用例 {步.get('步骤id')}",
                              "失败用例必须声明 返回断言（错误码写进断言里，不是并列键）",
                              '预期写成 {"成功": false, "状态码": <真源映射>, "返回断言": {"错误码": "..."}}'))
            for 值 in (步.get("参数") or {}).values():
                if isinstance(值, dict) and "$动态" in 值:
                    类型 = 值.get("$动态")
                    if 类型 not in 动态允许表 or set(值) != 动态允许表.get(类型, set()):
                        合法 = "、".join(sorted(动态允许表))
                        缺项.append(_缺(f"$动态 {类型!r}",
                                      f"动态值声明不合法（字段集必须精确匹配）。允许类型：{合法}",
                                      f"改为 {合法} 之一，并按该型的字段集写全"))
    return 缺项


def 体检骨架残留(包目录: Path) -> list[dict]:
    """说明/设计类文件是否还是模板骨架（占位未填）。"""
    缺项 = []
    for 路径 in sorted(包目录.rglob("*")):
        if 路径.is_dir() or 路径.suffix not in (".md", ".json") or "__pycache__" in 路径.parts:
            continue
        try:
            文本 = 路径.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        命中 = [m for m in 骨架标记表 if m in 文本]
        if 命中:
            缺项.append(_缺(f"骨架残留 {路径.relative_to(包目录)}",
                          f"仍是模板骨架态（命中 {命中[:2]}），作者必须填真实内容",
                          "按同目录同类真实包对照补齐；说明类填完需重算摘要"))
    return 缺项


def 体检摘要一致(包目录: Path) -> list[dict]:
    """完整性摘要是否与磁盘一致（改完内容必须重算）。

    判据对齐真源（`组件规范支持库/实现/完整性摘要.py:30-42`）：
    摘要**排除自身（完整性摘要.json）与 __pycache__ / .DS_Store / .pyc/.pyo**，
    因此这里的「实际」必须用同一套排除规则，否则会把「包不自哈希」误报成不一致
    （本工具首版就踩了这个假绿，2026-09-18 实测修正）。
    """
    摘要文件 = 包目录 / "完整性摘要.json"
    if not 摘要文件.is_file():
        return [_缺("完整性摘要.json", "缺失", "跑 python3.14 -m 开发工具.全量重算摘要")]
    摘要 = _读JSON(摘要文件) or {}
    登记 = 摘要.get("文件清单") or []
    排除目录名 = {"__pycache__", "工程缓存"}
    排除文件名 = {"完整性摘要.json", ".DS_Store"}
    实际 = [p for p in 包目录.rglob("*")
            if p.is_file() and p.name not in 排除文件名
            and not any(部分 in 排除目录名 for 部分 in p.relative_to(包目录).parts)
            and p.suffix not in {".pyc", ".pyo"}]
    if 登记 and len(登记) != len(实际):
        return [_缺("完整性摘要.json", f"文件清单登记 {len(登记)} 个、磁盘（同口径排除后）{len(实际)} 个 → 不一致",
                    "跑 python3.14 -m 开发工具.全量重算摘要")]
    return []


体检项表 = (
    ("九要素与必备文件", 体检目录),
    ("入口注册能力", 体检入口注册),
    ("复用决策", 体检复用决策),
    ("权限契约", 体检权限契约),
    ("验证场景", 体检验证场景),
    ("骨架残留", 体检骨架残留),
    ("完整性摘要", 体检摘要一致),
)


def 体检(包目录: Path) -> dict:
    """跑全部体检项，返回 {包目录, 缺项列表, 项数}。"""
    缺项 = []
    for 名称, 函数 in 体检项表:
        try:
            命中 = 函数(包目录)
        except Exception as 错误:  # 体检自身不许因单项崩掉整轮
            命中 = [_缺(f"体检项 {名称} 自身异常", f"{type(错误).__name__}: {错误}", "先修体检项实现")]
        for 项 in 命中:
            项["体检项"] = 名称
        缺项.extend(命中)
    return {"包目录": str(包目录), "缺项": 缺项, "缺项数": len(缺项)}


def main() -> int:
    if len(sys.argv) < 2:
        print("用法: python3.14 开发工具/包体检.py <包目录> [<包目录> ...]")
        return 2
    总缺 = 0
    for 参数 in sys.argv[1:]:
        包目录 = Path(参数)
        if not 包目录.is_dir():
            print(f"✗ 不是目录: {包目录}")
            总缺 += 1
            continue
        报告 = 体检(包目录)
        print(f"=== {报告['包目录']} ===")
        if not 报告["缺项"]:
            print("  ✅ 无缺项（可进入编译与组件合规）")
            continue
        for 项 in 报告["缺项"]:
            print(f"  ✗ [{项['体检项']}] {项['项']}")
            print(f"      说明: {项['说明']}")
            print(f"      怎么修: {项['怎么修']}")
        总缺 += 报告["缺项数"]
    print(f"\n合计缺项 {总缺} 项")
    return 1 if 总缺 else 0


if __name__ == "__main__":
    raise SystemExit(main())
