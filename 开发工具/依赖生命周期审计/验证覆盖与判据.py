"""验证覆盖与判据：把 F-5（契约释放策略文案与实现不符）那次的审计覆盖缺口钉成可复跑的自检。

用法：
    /opt/homebrew/bin/python3.14 开发工具/依赖生命周期审计/验证覆盖与判据.py

退出码：0 全部断言通过；1 有断言失败（打印失败项）。
只读真实仓库：所有篡改都在 tempfile 临时目录里做，不动被审计文件。
"""

from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

本文件目录 = Path(__file__).resolve().parent
系统根 = 本文件目录.parents[1]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 开发工具.依赖生命周期审计.审计核心 import 审计单个提供者, 审计全部

后端契约提供者 = (
    "支持库/后端/图像处理支持库/图像解码",
    "支持库/后端/数据库连接支持库/psycopg数据库",
    "支持库/后端/文档转换支持库/PDF文本表格",
    "支持库/后端/文档转换支持库/PDF渲染",
    "支持库/后端/文档转换支持库/PDF生成",
    "支持库/后端/文档转换支持库/openpyxl提供者",
    "支持库/后端/文档转换支持库/python_docx提供者",
    "支持库/后端/文档转换支持库/python_pptx提供者",
)
适配层提供者数 = 17
旧文案 = "关闭连接、游标、工作簿或文件句柄。"


def 复制到临时目录(相对路径: str) -> Path:
    """把真实包整目录复制到临时目录（篡改只发生在副本上）。"""
    临时根 = Path(tempfile.mkdtemp(prefix="依赖审计自检_"))
    目标 = 临时根 / Path(相对路径).name
    shutil.copytree(系统根 / 相对路径, 目标)
    return 目标


def 改契约(目录: Path, 改动: dict) -> None:
    契约路径 = 目录 / "生命周期契约.json"
    数据 = json.loads(契约路径.read_text(encoding="utf-8"))
    数据.update(改动)
    契约路径.write_text(json.dumps(数据, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def 主入口() -> int:
    失败项: list[str] = []

    # 断言一：覆盖到 支持库/后端 的提供者（旧版只 glob 适配层，后端一个都审不到）
    结果列表, _跳过列表 = 审计全部(系统根)
    被测路径 = {str(结果.目录.relative_to(系统根)) for 结果 in 结果列表}
    漏掉 = [路径 for 路径 in 后端契约提供者 if 路径 not in 被测路径]
    if 漏掉:
        失败项.append(f"覆盖缺口未补上，后端提供者未被审计: {漏掉}")
    适配层数 = sum(1 for 路径 in 被测路径 if 路径.startswith("支持库/适配层/"))
    if 适配层数 != 适配层提供者数:
        失败项.append(f"适配层提供者数由 {适配层提供者数} 变为 {适配层数}（既有覆盖被改动）")
    for 结果 in 结果列表:
        if str(结果.目录.relative_to(系统根)) in 后端契约提供者 and not 结果.是否通过:
            失败项.append(f"[{结果.提供者名}] 后端提供者不应违规: {结果.违规列表}")

    # 断言二：把释放策略改回旧文案（声称关闭连接/游标/工作簿/文件句柄），必须真报出来
    目标 = "支持库/后端/文档转换支持库/python_docx提供者"
    副本 = 复制到临时目录(目标)
    改契约(副本, {"释放策略": 旧文案})
    结果 = 审计单个提供者(副本)
    命中 = [违规 for 违规 in 结果.违规列表 if 违规.startswith("释放策略不符")]
    if not 命中:
        失败项.append(f"旧文案（声称关闭连接等）没有被报出来，实际违规: {结果.违规列表}")
    # 改回真实文案后必须回到零违规（证明判据不是「有文案就报」的一刀切）
    改契约(副本, {"释放策略": json.loads((系统根 / 目标 / "生命周期契约.json")
                                     .read_text(encoding="utf-8"))["释放策略"]})
    恢复后 = 审计单个提供者(副本)
    if not 恢复后.是否通过:
        失败项.append(f"文案改回真实内容后仍违规（判据过宽/误报）: {恢复后.违规列表}")

    # 断言三：如实声明「不持有该资源」不能被误判成假话
    副本2 = 复制到临时目录(目标)
    改契约(副本2, {"释放策略": "不涉及数据库连接、游标与工作簿；调用内完成，"
                              "异常路径由 finally 保证清理，不保留跨调用状态"})
    否定结果 = 审计单个提供者(副本2)
    if any(违规.startswith("释放策略不符") for 违规 in 否定结果.违规列表):
        失败项.append(f"否定语境被误报为释放策略不符: {否定结果.违规列表}")

    # 断言四：身份判据仍拦得住「抄别的提供者id」（扩覆盖后没有把身份判据放宽）
    副本3 = 复制到临时目录(目标)
    改契约(副本3, {"提供者id": "支持库.适配层.Pillow提供者", "健康探针": {
        "方式": "依赖导入探针", "入口": "__init__.py", "成功条件": "可导入", "失败码": "不可用"}})
    身份结果 = 审计单个提供者(副本3)
    if not any(违规.startswith("缺健康探针") for 违规 in 身份结果.违规列表):
        失败项.append(f"抄来的提供者id 没有被拦住: {身份结果.违规列表}")

    print(f"覆盖：后端提供者 {len(后端契约提供者)} 个全部纳入；适配层 {适配层数} 个结论不变")
    print(f"判据：旧文案被报出 {len(命中)} 条；真实文案零违规；否定语境零误报；抄id 被拦住")
    if 失败项:
        print("自检失败：")
        for 项 in 失败项:
            print(f"  - {项}")
        return 1
    print("自检通过：覆盖缺口已补、文案与实现不符能真报错、无放宽判据")
    return 0


if __name__ == "__main__":
    sys.exit(主入口())
