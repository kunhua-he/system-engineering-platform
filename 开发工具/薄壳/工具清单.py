#: 动态段最多展示几组常用传参。
#:
#: 改前是 3 组 —— 华哥 2026-09-22 二次裁决「所有注入提示词最高 2000 字符，超出的只能使用漂移值」：
#: 工具面是**每个请求都要重发**的注入面，多一组就多付一轮；1 组已够「照抄就完事」，
#: 要更多样例走 `能力目录.常用参数组合`（按需取，不常驻）。
动态常用传参数 = 1


def 常用传参段(能力id: str = "", 库路径=None) -> str:
    """从**调用参数账**取该能力最常用的几组入参形状，拼成描述里那段动态文本。

    华哥 2026-09-22 原话：「每一个工具的调用，应该提示词都不一样才对吧？」
    「调用工具，只需要告诉别人 POST(****路径) 参数 json:{A 参数：B 参数：C 参数：}」
    —— 所以这里给的是**真实历史上跑通过的具体参数形状与样例**，不是规则散文。

    数据源是唯一的（`公共契约.诊断.调用账本`，写方在网关、读方在能力目录），
    本函数**只读不写、不新建统计设施**（哲学 1.2/1.3）。

    失败口径（三档必须分得开，不能合并成一句「没有」）：
      - 账本里没这个能力 → 如实说「尚无历史调用」（不编造样例）；
      - 账本读不出来 → 如实说「账本不可读」+ 原因（不是「没有记录」）；
      - 能力id 为空 → 回全平台最高频的前 N 组（**全局取**，不按能力分段；给「不知道调
        什么」的人一个起点）。注意账本那侧的口径是「按能力分段、每段前 N 组」，
        所以全局前 N 必须在本函数内重排截断，不能直接把账本结果铺进描述。
    """
    try:
        if 库路径 is None:
            库路径 = 参数账路径()
        账 = 调用参数账(库路径)
        出 = 账.查常用参数(能力id=能力id, 上限=动态常用传参数)
    except Exception as 错误:  # noqa: BLE001 —— 动态段绝不能反噬工具面（出事就退回静态描述）
        return f"\n（常用传参暂不可用：{type(错误).__name__}）"
    问题 = str(出.get("问题") or "")
    组合 = list(出.get("常用参数组合") or [])
    if 问题:
        return f"\n（常用传参不可用：{问题}）"
    if not 组合:
        return ("\n（该能力尚无历史调用，无可照抄的传参；按上面 json 形状自拟，"
                "先探参数名与类型）")
    if not 能力id:
        # 全平台分支要的是**全局前 N 组**；账本 `查常用参数(能力id="")` 的既定语义是
        # 「按能力分段、每段前 N 组」（`能力目录.常用参数组合` 依赖它，属公共契约，不动）。
        # 不在这里重排截断，675 个能力 × N 组会把描述灌成十万字 —— 2026-09-22 实测：
        # 三个工具描述合计 302,070 字符，随每个请求的工具面发出，是上下文被频繁压缩的真凶。
        组合 = sorted(组合, key=lambda 条: -int(条.get("调用次数") or 0))[:动态常用传参数]
    行表 = []
    for 条 in 组合:
        行表.append("  %s\n     样例 %s\n     （历史 %d 次）" % (
            条.get("入参形状") or "", 条.get("样例") or "{}", int(条.get("调用次数") or 0)))
    # 表头写短（预算内多留给样例）：两个分支各留最短的自释文本，不加客套语。
    标题 = "常用传参（照抄即可）：" if 能力id else "全平台最高频传参："
    return "\n" + 标题 + "\n" + "\n".join(行表)


#: 动态段字符上限。
#:
#: 为什么必须有硬上限：动态段是**从账本现算**的，长度随「该能力最常用那组入参有多长」漂移。
#: 实测同一份代码、同一个调用，详情面（`tools/list` 带 能力id）在两个进程里量到 1,176 与 2,464 ——
#: 差的就是账本里那组样例的长短。注入面是**每个请求都要重发**的，长度必须由构造保证有界，
#: 不能靠「账本里恰好没有超长样例」这种运气。超限按「保留前缀 + 漂移指针」截断。
#: 预算怎么定出来的（**构造保证**，不是估计）：注入预算 2000，静态部分固定
#: = 三个模板（去掉占位符）555 + 三个 schema 1,229 = 1,784；
#: 动态段最多 2 处（capability_search 与 capability_call，tool_catalog 不注入）
#: ⇒ 每处上限 ≤ (2000 - 1784) / 2 = 108。取 105 留 6 字符余量。
#: 2026-09-24 批R·R-13 重算：本轮补「常见意图→首选能力」映射，并同步收紧三处 schema
#: 与目录模板文案 —— 改前 1,903 + 2×110 = 2,123 已超 2000（存量红），一并收回到 1,994。
#: 改静态文案或 schema 时，本条要跟着重算（`注入面预算测试` 会当场报红）。
#: 2026-09-24 批R·R-16：描述里的「常见意图→首选能力」映射**不再手写字面量** —— 唯一
#: 事实源移到 `公共契约/能力契约/常用意图.py`（`开工编排.开工准备` 的 `资料.能力映射`
#: 与 本描述同源，两处不再各持一份）。渲染结果与改前逐字节一致 ⇒ 静态部分字符数不变。
动态段字符上限 = 105
动态段截断后缀 = "\n…（已截断；完整样例调 能力目录.常用参数组合）"


def 截断动态段(文本: str) -> str:
    """把动态段压到 `动态段字符上限` 以内；尽量断在行边界，尾接漂移指针（不静默丢）。"""
    if len(文本) <= 动态段字符上限:
        return 文本
    头 = 文本[:动态段字符上限 - len(动态段截断后缀)]
    切点 = 头.rfind("\n")
    if 切点 > 0:
        头 = 头[:切点]
    return 头 + 动态段截断后缀


def 注入动态段(描述: str, 动态文本: str) -> str:
    """把占位符换成动态文本；没有占位符就原样返回（描述模板可静态可动态）。"""
    return (描述.replace(动态段占位, 截断动态段(动态文本))
            if 动态段占位 in 描述 else 描述)


