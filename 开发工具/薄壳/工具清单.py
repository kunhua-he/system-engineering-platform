def 常用传参段(能力id: str = "", 库路径=None) -> str:
    """从**调用参数账**取该能力最常用的几组入参形状，拼成描述里那段动态文本。

    华哥 2026-09-22 原话：「每一个工具的调用，应该提示词都不一样才对吧？」
    「调用工具，只需要告诉别人 POST(****路径) 参数 json:{A 参数：B 参数：C 参数：}」
    —— 所以这里给的是**真实历史上跑通过的具体参数形状与样例**，不是规则散文。

    数据源是唯一的（`公共契约.诊断.调用账本`，写方在网关、读方在能力目录），
    本函数**只读不写、不新建统计设施**（哲学 1.2/1.3）。

    失败口径（三档必须分得开，不能合并成一句「没有」）：
      - 账本里没这个能力 → 如实说「尚无历史调用」（不编造样例）；
      - 账本读不出来 → 如实说「账本不可读」+ 原因（不是「没有记录」）；
      - 能力id 为空 → 回全平台最高频的一组（给「不知道调什么」的人一个起点）。
    """
    try:
        if 库路径 is None:
            库路径 = 参数账路径()
        账 = 调用参数账(库路径)
        出 = 账.查常用参数(能力id=能力id, 上限=动态常用传参数)
    except Exception as 错误:  # noqa: BLE001 —— 动态段绝不能反噬工具面（出事就退回静态描述）
        return f"\n（常用传参暂不可用：{type(错误).__name__}）"
    问题 = str(出.get("问题") or "")
    组合 = list(出.get("常用参数组合") or [])
    if 问题:
        return f"\n（常用传参不可用：{问题}）"
    if not 组合:
        return ("\n（该能力尚无历史调用，无可照抄的传参；按上面 json 形状自拟，"
                "先探参数名与类型）")
    行表 = []
    for 条 in 组合:
        行表.append("  %s\n     样例 %s\n     （历史 %d 次）" % (
            条.get("入参形状") or "", 条.get("样例") or "{}", int(条.get("调用次数") or 0)))
    标题 = ("本能力历史常用传参（照抄即可）：" if 能力id
            else "全平台历史最高频传参（挑一个能力后调 capability_search 拿它的）：")
    return "\n" + 标题 + "\n" + "\n".join(行表)


def 注入动态段(描述: str, 动态文本: str) -> str:
    """把占位符换成动态文本；没有占位符就原样返回（描述模板可静态可动态）。"""
    return 描述.replace(动态段占位, 动态文本) if 动态段占位 in 描述 else 描述


def 组装工具面(能力id: str = "", 库路径=None) -> tuple:
    """按当前上下文组装三个工具（**每次 tools/list 现算**）。

    为什么单独成函数：`list_tools` 是回调（薄壳服务.py），动态化只需在那一刻
    把真实数据注进去；`三个工具定义` 仍是模块级静态模板（保住工具面指纹
    只反映代码版本，不因账本变化而漂移）。
    """
    动态 = 常用传参段(能力id=能力id, 库路径=库路径)
    return tuple(
        构造工具定义(工具.name,
                  注入动态段(工具.description or "", 动态),
                  工具.inputSchema)
        for 工具 in 三个工具定义
    )


# ── 薄壳工具面指纹（唯一口径）────────────────────────────────────────────────
# 为什么要有：薄壳是 MCP 客户端在**会话启动时拉起的常驻进程**。改了本文件（工具描述 /
# 入参 / 工具面）之后，运行中的旧壳照旧回旧元数据，调用方**无从知道自己手里的是不是
# 旧壳**。唯一能判的只有「进程里跑的那份代码」与「盘上现在那份代码」的字节比对：
#   进程内指纹 = 本进程导入本模块时（＝薄壳进程启动时）读到的字节 sha256，进程内不再变；
#   盘上指纹   = 调用时**现读盘**算出的同一对 sha256，随时反映最新代码。
薄壳源文件 = ("工具清单.py", "薄壳服务.py")
指纹口径 = "sha256(文件字节) × (工具清单.py, 薄壳服务.py)"
不一致提示 = ("薄壳为会话启动时的旧进程，盘上代码已更新；请重启 MCP 客户端后再调"
              "（薄壳不自重启，也不尝试重启）")


def 源文件路径(文件名: str) -> _Path:
    """薄壳源文件的绝对路径：以本模块所在目录为锚，不猜路径、不扫仓库。"""
    return _Path(__file__).resolve().parent / 文件名


def 算文件指纹(路径: _Path) -> str:
    """文件字节的 sha256 十六进制串；读不到返回空串（空串＝没取到，绝不当成「一致」）。"""
    try:
        return hashlib.sha256(路径.read_bytes()).hexdigest()
    except OSError:
        return ""


def 采集源文件指纹() -> dict[str, str]:
    """采集这一对薄壳源文件的字节指纹 —— **全仓唯一口径**，进程内快照与盘上现读都用它。"""
    return {文件名: 算文件指纹(源文件路径(文件名)) for 文件名 in 薄壳源文件}


#: 进程内指纹兜底值：本模块被导入时（薄壳进程启动时）的快照，进程内恒定不变。
#: 正常路径由入口 薄壳服务.py 在进程启动时显式采集并传入（锚在「本进程启动」那一刻）；
#: 本兜底值保证不经入口的调用方（如直接 import 本模块自测）也拿得到有意义的值。
_导入时指纹: dict[str, str] = 采集源文件指纹()


def 构建指纹段(进程内指纹: dict[str, str] | None = None) -> dict[str, Any]:
    """三组键（进程内指纹 / 盘上指纹 / 是否一致）+ 提示：一眼判断手里这个壳是不是盘上那一版。"""
    进程内 = dict(进程内指纹) if 进程内指纹 else dict(_导入时指纹)
    盘上 = 采集源文件指纹()
    未取到 = sorted(名 for 名, 值 in 盘上.items() if not 值)
    不一致文件 = sorted(名 for 名 in 盘上 if 进程内.get(名) != 盘上.get(名))
    是否一致 = bool(盘上) and not 未取到 and not 不一致文件
    指纹段: dict[str, Any] = {
        "进程内指纹": 进程内,
        "盘上指纹": 盘上,
        "是否一致": 真 if 是否一致 else 假,
        "指纹口径": 指纹口径,
        "判据": ("进程内指纹（进程启动时快照）逐文件等于盘上指纹（调用时现读盘）"
                 "→ 一致；任一不等或读不到 → 不一致"),
        "提示": "" if 是否一致 else 不一致提示,
    }
    if 未取到:
        指纹段["读取失败文件"] = 未取到
    if 不一致文件:
        指纹段["不一致文件"] = 不一致文件
    return 指纹段


def 构建工具目录(进程内指纹: dict[str, str] | None = None,
             进程启动时刻: str = "",
             进程号: int | None = None) -> dict[str, Any]:
    """薄壳自身工具清单（只读元数据，不触碰仓库其它文件）。

    只增不改：老键（成功 / 错误码 / 错误说明 / 薄壳工具数 / 工具 / 传输 / 唯一转发通道）
    语义不变；新增 进程内指纹 / 盘上指纹 / 是否一致 / 提示（+ 指纹口径 / 判据 /
    进程启动时刻 / 进程号），让调用方能判断手里这个壳是不是盘上当前那一版。
    """
    清单 = [
        {
            "协议名": 工具.name,
            "中文名": 协议名到中文名.get(工具.name, 工具.name),
            "入参": 工具.inputSchema,
            "描述": 工具.description,
            "转发目标": {
                "capability_search": f"{调用能力操作} → {搜索能力目标}",
                "capability_call": f"{调用能力操作} → 入参指定能力id",
                "tool_catalog": "不转发（薄壳本地元数据）",
            }.get(工具.name, ""),
        }
        for 工具 in 三个工具定义
    ]
    目录: dict[str, Any] = {
        "成功": True,
        "错误码": "",
        "错误说明": "",
        "薄壳工具数": len(清单),
        "工具": 清单,
        "传输": "stdio（不监听任何端口）",
        "唯一转发通道": "HTTP POST http://127.0.0.1:40007/网关/调用",
    }
    目录.update(构建指纹段(进程内指纹))
    if 进程启动时刻:
        目录["进程启动时刻"] = 进程启动时刻
    if 进程号 is not None:
        目录["进程号"] = 进程号
    return 目录
