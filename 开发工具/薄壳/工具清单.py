# ── 薄壳工具面指纹（唯一口径）────────────────────────────────────────────────
# 为什么要有：薄壳是 MCP 客户端在**会话启动时拉起的常驻进程**。改了本文件（工具描述 /
# 入参 / 工具面）之后，运行中的旧壳照旧回旧元数据，调用方**无从知道自己手里的是不是
# 旧壳**。唯一能判的只有「进程里跑的那份代码」与「盘上现在那份代码」的字节比对：
#   进程内指纹 = 本进程导入本模块时（＝薄壳进程启动时）读到的字节 sha256，进程内不再变；
#   盘上指纹   = 调用时**现读盘**算出的同一对 sha256，随时反映最新代码。
薄壳源文件 = ("工具清单.py", "薄壳服务.py")
指纹口径 = "sha256(文件字节) × (工具清单.py, 薄壳服务.py)"
不一致提示 = ("薄壳为会话启动时的旧进程，盘上代码已更新；下一次请求前会自换新壳"
              "（无需重启 MCP 客户端；换不成的原因见 `自换新壳` 键）")


def 源文件路径(文件名: str) -> _Path:
    """薄壳源文件的绝对路径：以本模块所在目录为锚，不猜路径、不扫仓库。"""
    return _Path(__file__).resolve().parent / 文件名


def 算文件指纹(路径: _Path) -> str:
    """文件字节的 sha256 十六进制串；读不到返回空串（空串＝没取到，绝不当成「一致」）。"""
    try:
        return hashlib.sha256(路径.read_bytes()).hexdigest()
    except OSError:
        return ""


def 采集源文件指纹(目录: _Path | None = None) -> dict[str, str]:
    """采集这一对薄壳源文件的字节指纹 —— **全仓唯一口径**，进程内快照与盘上现读都用它。

    `目录` 只给测试注入（默认＝本模块所在目录）：判据要能对着**假源文件**验，
    否则「盘上编译不过 ⇒ 拒绝换壳」这条反向保护永远测不到（真去改坏真源码再改回来，
    等于用污染工作区的方式换一次判据）。
    """
    if 目录 is not None:
        锚 = _Path(目录)
        return {文件名: 算文件指纹(锚 / 文件名) for 文件名 in 薄壳源文件}
    return {文件名: 算文件指纹(源文件路径(文件名)) for 文件名 in 薄壳源文件}


#: 进程内指纹兜底值：本模块被导入时（薄壳进程启动时）的快照，进程内恒定不变。
#: 正常路径由入口 薄壳服务.py 在进程启动时显式采集并传入（锚在「本进程启动」那一刻）；
#: 本兜底值保证不经入口的调用方（如直接 import 本模块自测）也拿得到有意义的值。
_导入时指纹: dict[str, str] = 采集源文件指纹()


def 构建指纹段(进程内指纹: dict[str, str] | None = None) -> dict[str, Any]:
    """三组键（进程内指纹 / 盘上指纹 / 是否一致）+ 提示：一眼判断手里这个壳是不是盘上那一版。"""
    进程内 = dict(进程内指纹) if 进程内指纹 else dict(_导入时指纹)
    盘上 = 采集源文件指纹()
    未取到 = sorted(名 for 名, 值 in 盘上.items() if not 值)
    不一致文件 = sorted(名 for 名 in 盘上 if 进程内.get(名) != 盘上.get(名))
    是否一致 = bool(盘上) and not 未取到 and not 不一致文件
    指纹段: dict[str, Any] = {
        "进程内指纹": 进程内,
        "盘上指纹": 盘上,
        "是否一致": 真 if 是否一致 else 假,
        "指纹口径": 指纹口径,
        "判据": ("进程内指纹（进程启动时快照）逐文件等于盘上指纹（调用时现读盘）"
                 "→ 一致；任一不等或读不到 → 不一致"),
        "提示": "" if 是否一致 else 不一致提示,
    }
    if 未取到:
        指纹段["读取失败文件"] = 未取到
    if 不一致文件:
        指纹段["不一致文件"] = 不一致文件
    # 自换新壳（2026-09-22）：把「会不会换、换不成为什么」摆在指纹旁边 ——
    # 调用方不用去猜「这个旧壳还要不要人来管」。
    需换, 换壳原因 = 需换新壳(进程内)
    指纹段["自换新壳"] = (f"下一次请求前自动换新壳（{换壳原因}）；无需重启 MCP 客户端"
                       if 需换 else 换壳原因)
    指纹段["本进程已换壳"] = 真 if os.environ.get(换壳目标指纹环境变量) else 假
    return 指纹段


# ── 自换新壳（2026-09-22 华哥口径「工具内部的事，不该是使用者的事」）──────────────
# 为什么要有：薄壳是 MCP 客户端在会话启动时拉起的**常驻进程**，改了源码旧壳照旧跑。
# 实测代价（2026-09-22）：回执库（落盘 + 回指针 + 7 天 TTL）/ 注入面收窄 / 工具面瘦身
# 三批改动全部落地并提交之后，会话里那个旧壳仍在走老路径 —— 真实调用照样回
# 还在走原地裁切（等于还在丢内容），`tool_catalog` 实测 `是否一致=假`、
# `进程启动时刻 21:46:37`，而人必须自己记得「重启 MCP 客户端」。
# 判据只有一条：**盘上这一版比本进程新**（与 `是否一致` 同一份指纹，不另立一套）。
# 换不成必须能解释（两种情况：盘上编译不过 / 本进程已换到盘上这一版），且继续用旧壳。
换壳强制环境变量 = "系统平台_薄壳强制换壳"
#: 上一代进程换壳时**换到的目标指纹**（`指纹串(盘上)` 的取值），随环境传给新壳。
#: 守卫按它比对，**不按「换过一次」这个布尔**（2026-09-23 改）：布尔在语义上过宽 ——
#: 它把「又一次真改了源码」也一起挡掉，于是「改了源码自换新壳」每个客户端会话**只能用一次**
#: （第二次编辑被静默忽略，正是本条要治的「改了不生效」），且换过壳的进程再也换不动
#: ⇒ 壳一旦出问题就只能靠杀进程或重启客户端。按指纹比对则：同版本不重复换（防套娃照旧），
#: 版本再变就再换一次；连带把「换壳后出问题」变成可自愈的（下一次编辑即恢复）。
换壳目标指纹环境变量 = "系统平台_薄壳换壳目标"


def 指纹串(指纹: dict[str, str]) -> str:
    """指纹的**稳定串形**（跨进程传参与守卫比对都用它，只此一处口径，不另写一套）。"""
    return ";".join(f"{名}={指纹.get(名, '')}" for 名 in sorted(指纹))


def 新壳可加载(目录: _Path | None = None) -> tuple[bool, str]:
    """盘上薄壳源码能否编译成新壳 —— 换上一个起不来的壳比继续用旧壳更糟（整个 MCP 当场失联）。

    只编译、不导入：导入会执行模块级代码（真起一套服务），那是换壳那一刻才该发生的事。
    """
    锚 = _Path(目录) if 目录 is not None else _Path(__file__).resolve().parent
    for 文件名 in 薄壳源文件:
        路径 = 锚 / 文件名
        try:
            源码 = 路径.read_bytes()
        except OSError as 错误:
            return 假, f"{文件名} 读不到（{type(错误).__name__}）"
        try:
            compile(源码, str(路径), "exec")
        except SyntaxError as 错误:
            return 假, f"{文件名}:{错误.lineno} 语法错误（{错误.msg}）"
    return 真, ""


#: 金丝雀标记：`新壳能起` 拉起的那个子进程带它 ⇒ 它自己不再换壳（防套娃）。
金丝雀环境变量 = "系统平台_薄壳金丝雀"
#: 金丝雀启动超时（秒）：正常启动实测 0.3 秒级，20 秒是给冷文件系统与首次导入的余量。
金丝雀超时秒 = 20.0
#: 能起判据的缓存（键＝盘上指纹串）：同一个盘上版本只起一次金丝雀。
_能起缓存: dict[str, tuple[bool, str]] = {}


def 新壳能起(目录: _Path | None = None, 可执行: str | None = None,
           超时秒: float | None = None) -> tuple[bool, str]:
    """盘上薄壳能不能**真起来**：起一次金丝雀子进程（`stdin=/dev/null`）看它干净退出。

    为什么编译过还不够（2026-09-25 现场实测）：换壳走 `os.execve`，**不可回退** —— 盘上那一版
    能编译、但 import 期就崩（少一个模块、模块级抛错）时，旧壳已经被换掉，新壳当场死，
    客户端只看到 `Transport closed`，**整个 MCP 面失联、只能重启客户端**（本次现场：
    改 薄壳服务.py 的中途被周期巡检巡到，换上一个起不来的壳）。
    编译（`新壳可加载`）只回答「语法对不对」；本函数回答「这一版到底能不能服务」，判据是**真起一次**。

    金丝雀与真壳只差两条：`stdin` 接 `/dev/null`（进程立即干净退出）、带 `金丝雀环境变量`
    （它自己不再换壳）。`stdout`/`stderr` 全被 `subprocess` 接管，**绝不碰客户端那三条 fd**
    （否则金丝雀会往 MCP 流里写）。`PYTHONPATH` 沿用现有值（副本场景由调用方给），
    真壳场景不设 —— 真壳的导入靠 `薄壳服务.py` 自己把项目根插进 `sys.path`，金丝雀照抄同一环境。
    """
    if not 可执行:
        可执行 = _sys.executable or "python3.14"
    锚 = _Path(目录) if 目录 is not None else _Path(__file__).resolve().parent
    键 = 指纹串(采集源文件指纹(目录))
    缓存 = _能起缓存.get(键)
    if 缓存 is not None:
        return 缓存
    环境 = dict(os.environ)
    环境[金丝雀环境变量] = "1"
    if 目录 is not None and not 环境.get("PYTHONPATH"):
        # 副本场景（判据自测注入的目录）自己找不到平台包，补上它上一层的项目根。
        环境["PYTHONPATH"] = str(锚.parent.parent)
    try:
        完成 = subprocess.run(
            [可执行, str(锚 / "薄壳服务.py")],
            stdin=subprocess.DEVNULL,
            capture_output=True,
            timeout=超时秒 or 金丝雀超时秒,
            env=环境,
        )
    except subprocess.TimeoutExpired:
        结论 = (假, f"金丝雀 {超时秒 or 金丝雀超时秒:.0f} 秒未退出（起不来或卡住）")
    except OSError as 错误:  # noqa: BLE001 —— 起不来就是起不来，不把异常抛给巡检
        结论 = (假, f"金丝雀起不来（{type(错误).__name__}）")
    else:
        错文 = 完成.stderr.decode("utf-8", "replace")
        if 完成.returncode == 0 and "Traceback" not in 错文:
            结论 = (真, "")
        else:
            末行 = [行 for 行 in 错文.strip().splitlines() if 行.strip()]
            结论 = (假, f"金丝雀退出码 {完成.returncode}：{末行[-1][:120] if 末行 else '无 stderr'}")
    _能起缓存[键] = 结论
    return 结论


def 需换新壳(进程内指纹: dict[str, str] | None = None, 目录: _Path | None = None,
           环境: dict | None = None) -> tuple[bool, str]:
    """要不要自换新壳：返回 `(需换, 原因)` —— **不换时原因也必须说得出话**。

    三条不换的情形（都是「宁可继续用旧壳」）：
      ① 盘上源码编译不过、或编译得过却**起不来**（`新壳可加载` ＋ `新壳能起`）——
         换壳是 `os.execve`、不可回退，换上一个起不来的壳就是整个 MCP 面失联；
      ② 本进程**已经换到盘上这一版**（`换壳目标指纹环境变量` 记的就是上一代换到的目标指纹）
         —— 换完还认为自己是旧壳就会无限套娃；而盘上**又变了**时必须允许再换，
         否则「改了源码自换新壳」每会话只能用一次（2026-09-23 实测踩到）。
      ③ 本进程是金丝雀（`金丝雀环境变量`）—— 金丝雀只负责证明「新壳起得来」，不换壳。
    指纹读不到也算不换：**读不到 ≠ 有新版**（拿空指纹当「不一致」会换上一个未知版本）。
    `换壳强制环境变量` 只给端到端测试用（真去改盘上源码再改回来会污染工作区）。
    """
    环境 = os.environ if 环境 is None else 环境
    if 环境.get(金丝雀环境变量):
        return 假, "金丝雀进程不换壳（它只证明新壳起得来）"
    进程内 = dict(进程内指纹) if 进程内指纹 else dict(_导入时指纹)
    盘上 = 采集源文件指纹(目录)
    不一致 = sorted(名 for 名 in 盘上 if 进程内.get(名) != 盘上.get(名))
    if not (bool(环境.get(换壳强制环境变量)) or 不一致):
        return 假, "本壳即盘上当前版本"
    未取到 = sorted(名 for 名, 值 in 盘上.items() if not 值)
    if 未取到:
        return 假, f"盘上指纹读不到（{'、'.join(未取到)}），不换"
    已换到 = str(环境.get(换壳目标指纹环境变量, "") or "").strip()
    if 已换到 and 已换到 == 指纹串(盘上):
        return 假, "本进程已换到盘上这一版，不重复换（防套娃）"
    可加载, 原因 = 新壳可加载(目录)
    if not 可加载:
        return 假, f"盘上源码编译不过，拒绝换壳（{原因}）；修好后自动换"
    能起, 起因 = 新壳能起(目录)
    if not 能起:
        return 假, f"盘上源码起不来，拒绝换壳（{起因}）；修好后自动换"
    return 真, "盘上代码已更新（" + "、".join(不一致 or ["强制自测"]) + "）"


def 构建工具目录(进程内指纹: dict[str, str] | None = None,
             进程启动时刻: str = "",
             进程号: int | None = None) -> dict[str, Any]:
    """薄壳自身工具清单（只读元数据，不触碰仓库其它文件）。

    只增不改：老键（成功 / 错误码 / 错误说明 / 薄壳工具数 / 工具 / 传输 / 唯一转发通道）
    语义不变；新增 进程内指纹 / 盘上指纹 / 是否一致 / 提示（+ 指纹口径 / 判据 /
    进程启动时刻 / 进程号），让调用方能判断手里这个壳是不是盘上当前那一版。
    """
    清单 = [
        {
            "协议名": 工具.name,
            "中文名": 协议名到中文名.get(工具.name, 工具.name),
            "入参": 工具.inputSchema,
            "描述": 工具.description,
            "转发目标": {
                "capability_search": f"{调用能力操作} → {搜索能力目标}",
                "capability_call": f"{调用能力操作} → 入参 能力id 指定",
                "code_map_search": "调用能力 → 代码解析支持库.代码地图.查询节点",
                "run_command": "调用能力 → 系统核心支持库.进程管理.执行命令",
                "tool_catalog": "不转发（薄壳本地元数据；已从工具面撤，仅供自检/测试）",
            }.get(工具.name, ""),
        }
        for 工具 in 工具定义
    ]
    目录: dict[str, Any] = {
        "成功": 真,
        "错误码": "",
        "错误说明": "",
        "薄壳工具数": len(清单),
        "工具": 清单,
        "传输": "stdio（不监听任何端口）",
        "唯一转发通道": "HTTP POST http://127.0.0.1:40007/网关/调用",
    }
    目录.update(构建指纹段(进程内指纹))
    if 进程启动时刻:
        目录["进程启动时刻"] = 进程启动时刻
    if 进程号 is not None:
        目录["进程号"] = 进程号
    return 目录
