def 候选能力id条(能力id: str) -> list[str]:
    """按**唯一检索腿**（`搜索能力目标`）给「你是不是想调 X」的候选 id；失败一律回空表。

    **为什么要有**（实测 2026-09-24，华哥：「失败回执要能自证真名」）：
    `能力id=静态编译` ⇒ `能力不存在 / 能力未注册: 静态编译`，真名是 `自修复工具.静态编译`；
    `能力id=开工编排.查询文件租约` ⇒ 真名 `平台控制面.能力目录.查询文件租约`。
    回执对「真名是什么」**零信息** ⇒ agent 只能猜包前缀（子代理日志里
    `文件管理.读取文件` 猜了 126 次，真名 `文件系统支持库.文件操作.读取文件`）。
    网关对**参数名**早有 `difflib` 近似名机制，对**能力 id** 一直没有 —— 本条补这个缺口。
    更糟的是既有那段「常用传参」提示取自**调用方自己的历史**（含失败调用），
    会把错误猜测强化成「看起来有据」的样例。

    **为什么落在这里**（而不是逐处改网关）：`能力不存在` 在网关侧有 7+ 处构造点
    （`网关执行面` / `网关处理面` / `唯一能力调用` / `任务工作器` …），但它们**全部**
    经本壳回给 agent ⇒ 只在回执出口补一次，既不漏一处、也不会各写一套判据。

    **候选来源只有一条腿**：本壳既有的检索转发（`搜索能力目标` = `能力目录.搜索能力`，
    与 `capability_search` 同一条腿）；**不扫目录、不自建索引**（薄壳零业务语义）。

    **查什么**：只查请求串的**末段（能力名）**，不查整串 —— 本条要治的恰恰是「记得住
    能力名、记不住包前缀」（实测 `开工编排.查询文件租约` 整串 0 精确命中，去掉包前缀
    `查询文件租约` 精确命中 3 条且真名在其中）。末段归一只是入参整形，不是业务判据。

    **只认精确命中**：搜索腿走了零命中兜底（`是否扩词=真`，双字滑窗按相关度打分）时
    一律回空表 —— 实测 `不存在的包.不存在的名` ⇒ 兜底回 201 条候选，头 5 条是
    `读取文件` / `切换分支` / `识别图片文件` 这类毫不相干的记录。那不是「你是不是想调 X」，
    是噪声，**比空表更坏**（会把 agent 带偏去调一个错的能力）。

    附加信息绝不反噬主错误：搜不通 / 读不到 / 结构不符一律回空表，
    主调用的 `错误码` 与 `错误说明` 原样保留。
    """
    末段 = 能力id.rsplit(".", 1)[-1].strip()
    if not 末段 or 能力id == 搜索能力目标:
        # 检索腿自己没注册时不再递归去搜自己（那只是多一次注定失败的往返）；
        # 末段为空（请求串以点号结尾）时没有可查的词，直接回空表。
        return []
    try:
        结果 = 转发({"操作": 默认操作, "能力id": 搜索能力目标,
                    "参数": {"关键词": 末段, "限制": 候选检索条数,
                            "细节级别": 细节级别合法值[0]}})
        信封 = 结果.get("信封") or {}
        if not 信封.get("成功"):
            return []
        值 = 信封.get("值") or {}
        if not isinstance(值, dict) or 值.get("是否扩词"):
            return []
        记录表 = 值.get("能力列表")
        if not isinstance(记录表, list):
            return []
        候选表: list[str] = []
        for 记录 in 记录表:
            if not isinstance(记录, dict):
                continue
            候选 = str(记录.get("能力id", "") or "").strip()
            if 候选 and 候选 != 能力id and 候选 not in 候选表:
                候选表.append(候选)
        # 末段名与请求末段**完全相等**的排前（真名与被猜的短名通常就差一个包前缀）；
        # 排序稳定，同键保持检索腿的 能力id 序 —— 不另起一套相关度打分。
        候选表.sort(key=lambda 项: 0 if 项.rsplit(".", 1)[-1] == 末段 else 1)
        return 候选表[:候选能力上限]
    except Exception:  # noqa: BLE001 —— 候选是附加信息，绝不反噬主错误
        return []


def _解析项目根(参数: dict) -> tuple[str, str]:
    """解析本次调用该用哪个项目根，返回 `(根, 来源)`。

    **唯一一处解析**：`_项目根检查`（校验）与 `_调用能力`（`参数` 补位）都必须走这里。
    分成两处各算一个根就会分叉 —— 实测形态：校验按下面那条裁决回落到薄壳自身位置，
    补位却直接读 `参数.get("项目根","")`，调用方**省略**顶层 `项目根` 时（工具描述
    推荐的用法）补位值是**空串**，能力侧拿到 `项目根: ""` 而不是薄壳绑定的那个根。
    """
    传入 = str(参数.get("项目根", "") or "").strip()
    if 传入:
        return 传入, "调用方显式传入"
    return str(_项目根), "薄壳默认绑定（shell 自身位置）"


def _项目根检查(参数: dict) -> tuple[bool, str]:
    """判断「这次调用是不是系统工程平台的」——不是就**不载入任何平台上下文**。

    华哥 2026-09-19 裁决：「如果是这个项目的就载入提示词；如果不是这个项目的，
    就直接不载入更多上下文就好了」「控制好最小体量的 token 限制」。

    判据只看一条：`项目根` 必须是**真实存在的目录**，且其下有本平台的锚文件
    （`AGENTS.md` **且** `开发文档/项目说明.md`）——两件都在才算本仓库，
    避免一个同名目录或随手传的路径把平台规则灌进无关会话。
    不存在/缺锚文件 → 一律按「不是本项目」处理（fail-closed）。

    **不传 `项目根` 时默认用薄壳自身位置**（2026-09-22 华哥裁决「理论上 mcp 是默认
    绑定根目录的」）：薄壳由 MCP 客户端按**本仓库内的绝对路径**拉起，「我在哪个仓库」
    在**进程启动时**就由客户端配置定死（`_项目根 = _薄壳目录.parents[1]`），
    不随调用方入参变化。此前要求每次调用手抄同一个常量 —— 实测一轮开工手抄 50+ 次，
    那是拿调用方的记性去补一个进程已知的事实，是缺陷不是纪律。

    **默认不等于免检**：默认值照样过同一套锚文件判据，薄壳自身位置不是平台仓库时
    一样拒绝；调用方显式传了就以传入值为准（传错照样拒，**不静默替换成默认值**）。
    拒绝说明一律带上「项目根来自哪」——不这样写，调用方分不清是自己传错了
    还是薄壳绑定位置不对。
    """
    传入, 来源 = _解析项目根(参数)
    根 = Path(传入).expanduser()
    if not 根.is_dir():
        return 假, (f"项目根不是目录：{传入}（来自：{来源}）。"
                       "本工具只服务系统工程平台仓库，已拒绝（未载入任何平台上下文）。")
    if not ((根 / "AGENTS.md").is_file() and (根 / "开发文档" / "项目说明.md").is_file()):
        return 假, (f"项目根缺少平台锚文件（AGENTS.md 与 开发文档/项目说明.md）：{根}"
                       f"（来自：{来源}）。"
                       "本工具只服务系统工程平台仓库，已拒绝（未载入任何平台上下文）。")
    return 真, ""


def _查询能力(参数: dict) -> dict[str, Any]:
    """转发到唯一网关调用 搜索能力目标；未注册则报 能力未注册 并登记缺口。"""
    通过, 原因 = _项目根检查(参数)
    if not 通过:
        return {"成功": 假, "错误码": "非本平台项目根", "错误说明": 原因}
    关键词 = str(参数.get("关键词", "") or "").strip()
    if not 关键词:
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "关键词必填"}
    try:
        限制 = int(参数.get("限制", 默认检索条数))
    except (TypeError, ValueError):
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "限制必须是整数"}
    # 精准检索三件套：条数 / 详略档 / 翻页游标 —— 都**原样透传**给能力，薄壳不解释语义。
    # 未传的不塞默认值（能力自己知道默认是什么），避免薄壳悄悄改写调用语义。
    入参: dict[str, Any] = {"关键词": 关键词, "限制": 限制}
    细节级别 = str(参数.get("细节级别", "") or "").strip()
    if 细节级别:
        if 细节级别 not in 细节级别合法值:
            return {"成功": 假, "错误码": "参数不合法",
                    "错误说明": f"细节级别必须是 {'/'.join(细节级别合法值)} 之一，收到 {细节级别!r}"}
        入参["细节级别"] = 细节级别
    游标 = str(参数.get("游标", "") or "").strip()
    if 游标:
        入参["游标"] = 游标
    结果 = 转发({"操作": "调用能力", "能力id": 搜索能力目标, "参数": 入参})
    数据 = _包装(搜索能力目标, 结果, 参数)
    # 回包瘦身（2026-09-23）后 `错误码` / `错误说明` 只在非空时出现，故一律 `.get`
    # —— 直取会 KeyError（实测：搜索能力注册正常时 3 条测试当场报错）。
    错误码 = str(数据.get("错误码", "") or "")
    错误说明 = str(数据.get("错误说明", "") or "")
    未注册 = 错误码 in 未注册标志 or "能力未注册" in 错误说明
    if not 数据["成功"] and 未注册:
        登记 = 登记待补能力(搜索能力目标, "capability_search", 错误说明)
        数据["错误码"] = "能力未注册"
        数据["错误说明"] = f"网关未注册能力 {搜索能力目标}；薄壳不自实现搜索逻辑"
        数据["待补能力清单"] = 登记
    return 数据


def _调用能力(参数: dict) -> dict[str, Any]:
    """薄壳主体：按 `操作` 转发唯一网关（先校验项目根是本平台仓库）。

    `操作` 白名单见 `薄壳允许操作`（默认 `调用能力`）：
    - `调用能力`：`能力id` + `参数` 转发；返回侧只做体积控制，**不解释、不改写、不重排**。
    - `热接入` / `健康检查`：网关操作，**不接受 `参数`、不需要 `能力id`**（网关侧
      允许字段表把它们声明为 `set()`）。`热接入` = 新增/变更包增量装配免重启，
      改完能力调它即生效（决策记录 0008：**不重启网关**）。
    - `任务提交`：`能力id` + `参数`，**立即**回 `{任务id, 状态}`；`任务查询`（`参数`
      带 `任务id`）/ `任务取消`：**不需要 `能力id`，但必须带 `参数`**。
      这三条是「长命令异步腿」的 MCP 面入口（2026-09-23 接入）：结果落
      `工程缓存/运行数据/底座运行.db` 的 `任务` 表，所以**查询是秒返回、不依赖调用方
      保持连接**；`释放句柄` 会**杀掉**在跑的子进程，故要拿结果就该走这条腿而不是句柄腿。
      ★ 任务腿输出上限 **256 KiB**（`公共契约/运行时/有界IO.py:18`），超了硬失败 ⇒
      长输出命令必须**自己重定向到文件**再取。

    入参侧唯一一处动刀：`项目根` 自动补位（见下），其余原样转发。
    """
    通过, 原因 = _项目根检查(参数)
    if not 通过:
        return {"成功": 假, "错误码": "非本平台项目根", "错误说明": 原因}
    操作 = str(参数.get("操作", "") or "").strip() or 默认操作
    if 操作 not in 薄壳允许操作:
        return {"成功": 假, "错误码": "参数不合法",
                "错误说明": (f"操作必须是 {' / '.join(薄壳允许操作)} 之一，收到 {操作!r}；"
                          "薄壳按白名单 fail-closed，不转发未登记的操作")}
    try:
        上限字符 = int(参数.get("返回上限字符", 默认返回上限字符))
    except (TypeError, ValueError):
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "返回上限字符必须是整数"}
    if 操作 in 无能力id操作 or 操作 in 无能力id但接受参数操作:
        # 网关操作：网关侧 允许字段表 声明为 set() 的那两个，多带字段虽被网关忽略
        # （协议只增不删），但静默丢弃会让调用方以为参数生效了 —— 故薄壳在边界上直接拒绝，
        # 不装作接受。任务查询 / 任务取消 是**另一类**：不认 `能力id`，但 `参数` 必带
        # （里面装 任务id），一律拒参数会把整条任务腿堵死。
        if 操作 in 无能力id操作 and 参数.get("参数"):
            return {"成功": 假, "错误码": "参数不合法",
                    "错误说明": (f"操作 {操作} 不接受 参数（网关侧 允许字段表 为 set()）；"
                              "请留空或删掉 参数 键")}
        转发体: dict[str, Any] = {"操作": 操作}
        if 操作 in 无能力id但接受参数操作:
            入参 = 参数.get("参数")
            if 入参 is None:
                入参 = {}
            if not isinstance(入参, dict):
                return {"成功": 假, "错误码": "参数不合法", "错误说明": "参数必须是对象"}
            转发体["参数"] = 入参
        结果 = 转发(转发体)
        数据 = _包装(操作, 结果, 参数, 操作=操作)
        裁剪后, 裁剪说明 = _裁剪值(数据.get("值"), 上限字符, 参数.get("值字段"),
                                  _信封耗时毫秒(结果))
        if 裁剪后 is not None:
            数据["值"] = 裁剪后
        if 裁剪说明 is not None:
            数据[值裁剪键] = 裁剪说明
        return 数据
    能力id = str(参数.get("能力id", "") or "").strip()
    if not 能力id:
        return {"成功": 假, "错误码": "参数不合法",
                "错误说明": "能力id必填（只有 热接入 / 健康检查 / 任务查询 / 任务取消 这四个网关操作不需要能力id）"}
    入参 = 参数.get("参数")
    if 入参 is None:
        入参 = {}
    if not isinstance(入参, dict):
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "参数必须是对象"}
    # ★ `项目根` 自动补位（2026-09-21 华哥裁决「不要再同一个坑摔倒 2 次」）：
    # 顶层 `项目根` 是**本工具自己的**平台身份校验参数，能力自己的同名入参在 `参数` 里，
    # 两者同名不同层。此前必须手抄第二遍，实测「连传 4 次错才开通工」（工具描述里至今
    # 留着这条警告）——这就是典型的「本该一次成功的调用被迫多次探索」。现由薄壳补位：
    # `参数` 里没给 `项目根` 就填上**校验时用的那个根**（走 `_解析项目根`，与 `_项目根检查`
    # 同一条腿）。★ 这里曾经直接读 `参数.get("项目根","")`：调用方省略顶层 `项目根` 时
    # （工具描述推荐的用法），校验回落到薄壳自身位置、补位却注入**空串**，
    # 同一个根被算成两个值 —— 正是「同一件事两处解析」的典型形态。
    # 安全前提两条，均已核实：① 平台把 `项目根` 一律定义为「仓库根绝对路径」，与顶层同义
    # （4 个声明它为必填的能力说明全一致）；② 网关对**未知参数一律忽略**
    # （运行核心/统一网关/协议/类型规格.py 的协议兼容口径），故对未声明它的能力注入也无害。
    # 调用方显式给了就以调用方的为准（不覆盖）。
    if 操作 == 默认操作 and "项目根" not in 入参:
        # 只对「调用能力」补位：`能力详情` 是网关操作（允许字段表 = {"能力id"}），
        # 没有能力契约、也不认 `项目根`，塞进去只是噪声，还会误导读者以为它接受该参数。
        入参 = dict(入参)
        入参["项目根"] = _解析项目根(参数)[0]
    结果 = 转发({"操作": 操作, "能力id": 能力id, "参数": 入参})
    数据 = _包装(能力id, 结果, 参数, 操作=操作)
    # ★ `能力不存在` 时回带候选能力 id（2026-09-24 华哥裁决「失败回执要能自证真名」）：
    #   只增字段（哲学第 5 条 2 项）—— 成功回执与既有失败字段一字不改；
    #   候选为空时**不出现该键**（空表零信息量，出现只是白占字符）。
    #   判据复用既有常量 `未注册标志`（`能力不存在` / `能力未注册` 同一件事的唯一一处定义），
    #   不再手抄第二个字面量。来源与理由见 `候选能力id条` 的 docstring。
    if not 数据.get("成功") and str(数据.get("错误码", "") or "") in 未注册标志:
        候选 = 候选能力id条(能力id)
        if 候选:
            数据["候选能力id"] = 候选
    # ★ 回执默认带该能力的常用传参（2026-09-22 华哥裁决「调用的时候，默认给他返回调用的传参」）。
    #   为什么自带而不叫人另调 `能力目录.常用参数组合`：实测那条路要么爆上下文
    #   （全量 79198 字符）要么拿不到（裁到 2500 后只剩 47 字符、连主键都被丢了）。
    #   而“怎么调”恰是失败重试时最需要的东西，放在回执里零额外往返。
    #   **只增字段（哲学第 5 条 2 项）**：老调用方看不到这个键也不受影响。
    #   失败/无记录时如实给原因，不编造样例；且它**不占值预算**（在 `值` 之外）。
    # 只在**失败时**回带常用传参（2026-09-22 二次裁决「返回内容尽量精简字符数减少」）：
    # 成功时调用方手里那组参数就是最佳样例，再回带一份纯属重复；失败时「怎么调」才是重试
    # 最需要的东西。要无条件回带时显式读 开发文档/规范/任务类型规范.json 或调
    # `能力目录.常用参数组合`。
    if not 数据.get("成功"):
        数据["常用传参"] = 常用传参条(能力id)
    裁剪后, 裁剪说明 = _裁剪值(数据.get("值"), 上限字符, 参数.get("值字段"),
                              _信封耗时毫秒(结果))
    if 裁剪后 is not None:
        数据["值"] = 裁剪后
    if 裁剪说明 is not None:
        数据[值裁剪键] = 裁剪说明
    return 数据


