@服务.call_tool()
async def 调用工具(名称: str, 参数: dict[str, Any]):
    协议名 = 中文名到协议名.get(str(名称), str(名称))
    处理 = 分发表.get(协议名)
    if 处理 is None:
        数据: dict[str, Any] = {"成功": 假, "错误码": "未知工具",
                              "错误说明": f"薄壳只有 3 个工具，未注册：{协议名}"}
    else:
        try:
            数据 = await asyncio.to_thread(处理, dict(参数 or {}))
        except Exception as 异常:  # 薄壳不吞异常细节以外的信息，凭证不入错误文本
            数据 = {"成功": 假, "错误码": "薄壳内部错误",
                    "错误说明": f"{type(异常).__name__}: {str(异常)[:200]}"}
    # `isError` 如实置（2026-09-21 批 2 · L10）：业务失败必须让客户端与模型**看得见**。
    # 此前只回 list[TextContent]，而 SDK 对「返回 list」的正常路径固定 isError=False
    # ⇒ `参数不合法` 这类失败在 MCP 链路上完全不可见，模型于是反复重试同一错误
    # （SEP-1303：输入校验失败必须走 Tool Execution Error，不许走 Protocol Error）。
    # ── agent 面向空值省略（2026-09-24 华哥裁决「空值不显示（动态省略）」）─────
    # 本行是薄壳把结果交给 agent 的**唯一出口**（三个工具都走这里），故只在这一层
    # 做一次递归省略 —— 不在任何能力里各加一遍判断（见 `去空值` 上方那段口径）。
    # `失败` 仍从**省略后**的 `数据` 取：`成功` 在 `空值豁免键` 里，`假` 不会被省掉。
    数据 = 去空值(数据)
    return 构造工具结果(json.dumps(数据, ensure_ascii=False, indent=2),
                    失败=not bool(数据.get("成功")))


async def 主程序() -> None:
    """stdio 传输：不绑定端口、不启 HTTP 服务。"""
    async with 标准输入输出上下文() as (读取流, 写入流):
        # `stateless=True` 是自换新壳的**必要条件**，不是可选项：`os.execve` 换掉进程镜像的
        # 同时也换掉了 SDK 会话里那份「已握手」状态，而握手只能由客户端发起、客户端不会重发
        # ⇒ 新壳停在 NotInitialized，此后**每一次**调用都被 SDK 判成
        # `RuntimeError: Received request before initialization was complete`，再被会话循环
        # 兜成一句 `Invalid request parameters`。实测 2026-09-23：编辑薄壳源码后的第一次调用起，
        # MCP 面整条被打死 —— 连无参的 `tool_catalog` 都调不动。
        # （当时还**不可自愈**：守卫是「换过一次」的布尔，换过壳的进程再也换不动。守卫已改为
        #  按目标指纹比对 ⇒ 再改一次源码就能把被打死的壳换回新壳，见 `工具清单.需换新壳`。）
        # 薄壳不持有任何会话态（每次调用独立转发给网关），故「无握手也服务」语义正确；
        # 客户端正常握手那条路不受影响（`initialize` 分支照旧应答）。
        #
        # 换壳**必须在读路径之外**做（见 `自换新壳读取流.换壳周期任务`）：读路径是「请求刚读进、
        # 回包还没写」的那一刻，那里的换壳点永远不安全。故这里另起一个周期任务，读流/写流各包一层
        # 记账（读进一条带 id 的请求记上、写出它的响应划掉）⇒ 换壳只在「需换 且 无在途请求
        # 且 读取流空」三条同时成立时发生。
        账本 = 在途请求账本()
        壳读取流 = 自换新壳读取流(读取流, 进程内指纹, 账本)
        壳写入流 = 记账写入流(写入流, 账本)
        换壳巡检 = asyncio.create_task(壳读取流.换壳周期任务())
        try:
            await 服务.run(壳读取流, 壳写入流,
                         构造初始化选项(服务名, 服务版本), stateless=True)
        finally:
            换壳巡检.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await 换壳巡检


if __name__ == "__main__":
    asyncio.run(主程序())
