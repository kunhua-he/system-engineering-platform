def 渲染键值(键: str, 项: Any, 缩进: int = 0) -> str:
    """渲染一行 `键：值`；值是容器就换行缩进铺开（**唯一一处**决定这个写法）。

    抽出来是为了让 `渲染值` 的字典分支与 `渲染文本回执` 的附注分支**共用同一处判断** ——
    否则两处各写一遍「标量内联／容器换行」，改一处漏一处（实测：附注里的列表曾被内联成
    `候选能力id：- x.y` 这种读不出结构的形状）。
    """
    空白 = " " * 缩进
    if isinstance(项, (dict, list, tuple)):
        return f"{空白}{键}：\n{渲染值(项, 缩进 + 2)}"
    return f"{空白}{键}：{渲染值(项).lstrip()}"


def 渲染值(值: Any, 缩进: int = 0) -> str:
    """把一个值渲染成给人读的文本（**不 JSON 化**）。

    标量原样（布尔按平台口径写 `真`／`假`）；字典每键一行 `键：值`；列表每项一行 `- `；
    嵌套逐层缩进 2 空格。**键名与值都逐字保留** —— 本函数只换写法，不丢信息。
    """
    空白 = " " * 缩进
    if isinstance(值, bool):
        return 空白 + ("真" if 值 else "假")
    if 值 is None:
        return 空白 + "空"
    if isinstance(值, str):
        return "\n".join(空白 + 行 for 行 in 值.split("\n"))
    if isinstance(值, (int, float)):
        return 空白 + str(值)
    if isinstance(值, (list, tuple)):
        行表 = []
        for 项 in 值:
            if isinstance(项, (dict, list, tuple)):
                行表.append(f"{空白}- \n{渲染值(项, 缩进 + 2)}")
            else:
                行表.append(f"{空白}- {渲染值(项).lstrip()}")
        return "\n".join(行表)
    if isinstance(值, dict):
        return "\n".join(渲染键值(键, 项, 缩进) for 键, 项 in 值.items())
    return 空白 + str(值)


def 渲染文本回执(数据: dict[str, Any]) -> str:
    """把薄壳回执渲染成**文本口径**（`调用工具` 的唯一出口格式）。

    形状（固定三段，逐字可判）：
      · 成功且无值 → 首行 `1`；
      · 成功且有值 → 首行就是**值的内容**（文本原样铺开，不加包装）；
      · 失败       → 首行 `-1`；
      · 其后：除 `成功`／`值` 外的每个非空键一行 `键：值`（嵌套逐层缩进）。
        `错误码`／`错误说明`／`值裁剪`／`句柄`／`任务id`／`被忽略参数`／`慢调用提示`／
        `候选能力id`／`常用传参`／`详情`／`请检查`／`待补能力清单`／`状态`／`日志` … 一律保留。
    """
    行表: list[str] = []
    if not bool(数据.get("成功")):
        行表.append("-1")
    elif 数据.get("值") is None:
        行表.append("1")
    else:
        行表.append(渲染值(数据["值"]))
    行表.extend(渲染键值(键, 项)
               for 键, 项 in 数据.items() if 键 not in 正文键)
    # 失败必带解决办法（2026-09-25 华哥裁定）：调用方拿到失败时**顺手就有下一步动作**，
    # 不必先复现再自己定性。成功不补（不制造噪声）；数据里已自带 `解决办法` 的不重复补。
    if not bool(数据.get("成功")) and "解决办法" not in 数据:
        行表.append(f"解决办法：{解决办法(数据)}")
    return "\n".join(行表)


def _裁剪值(值: Any, 上限字符: int,
           耗时毫秒: float | None = None) -> tuple[Any, dict | None]:
    """超过 `上限字符` ⇒ **整包换指针**（全量回执），不做任何原地裁切。

    ★ 2026-09-25 华哥裁决「裁切没意义」（实测依据见上方 `值裁剪键` 段注释）：
    限内**原样回**（一字不动）；超限**只回指针**，全量由 `回执` + `取回` 指得住。
    落盘不成（回执库不可写）⇒ **原样回** ＋ 如实说明「全量没落盘」，同样**不裁** ——
    宁可让调用方看到「这次没裁、内容可能很大」，也不给它一个被啃过的值。

    返回 `(值, 值裁剪说明或 None)`；说明非空即表示「值这次不是原样」。未超限时返回 None，不留噪声。
    """
    if 上限字符 <= 0 or _字符数(值) <= 上限字符:
        return 值, None
    指针 = _落全量回执(值, 耗时毫秒)
    if 指针:
        return 指针, None
    return 值, {"全量回执未落盘": "落盘不可用，本次按原值回带（未裁切）"}


# ── 全量回执库（2026-09-22 华哥裁决）─────────────────────────────────────
# 「丢弃干啥？直接全部收录到一个 db 里面啊，然后用指针便宜可以查询。这个 db，7 天删一次就完事了。」
# 口径：**不再丢内容、也不再裁切**。超过上限时按序做两件事：
#   ① 把**未裁剪的原始值**整份落盘成一份全量回执（一行一个 JSON）；
#   ② 回执外只回**指针**（路径 + 行号 + 字符数 + sha256 前十位 + 过期日期）。
#      （2026-09-25 华哥裁决「裁切没意义」：曾补过一条「指针 + 缩影」；实测小上限下缩影会被裁到
#       15 字符并标 `未能压到限内` ⇒ 既没内容、也没能用的缩影。整条缩影腿已下线。）
# 为什么不落 sqlite：仓库里 17 处 sqlite3 全是**平台内部**用（权威状态/幂等/快照），MCP 侧
# **没有取回腿** —— 落进去就是第二个「原体量照样进不了上下文」的黑洞。一行一 JSON 则
# 取回腿就是现成的 `文件管理.读取文件` 的 起始行/结束行，不新增能力、不多一条腿。
# 为什么带 TTL 仍必须按行区间取回：一行一副本、行号只增不改，过期只按文件日期判（不做压缩重排），
# 否则「回执路径 + 行区间」的指针会在下一次裁剪时整体错位 —— 指针必须永远指得住。
回执库相对路径 = Path("工程缓存") / "运行数据" / "MCP全量回执"
回执保留天数 = 7
回执时钟环境变量 = "系统底座_MCP回执时钟"
#: 本次进程内已落盘过的「内容摘要 → (起始行, 结束行)」：
#: 同一内容在同一进程里反复调不重复占盘；**盘上不去重**（跨进程重复落 = 自己的一份副本，可接受）——
#: 去重要读全文件找标记行，那是幂等又添一次 IO，而 TTL 7 天本就会清。
进程内回执行: dict[str, tuple[int, int]] = {}


def 回执库() -> Path:
    """回执库目录（相对仓库根）—— 落盘前实时解析，便于测试注入（不缓存模块级路径）。"""
    return _项目根 / 回执库相对路径


def _回执时刻() -> datetime:
    """回执的「现在」。可用环境变量注入固定时刻 —— 只为让 TTL 修剪**可被反向验证**。

    没这个口子就只能「真等 8 天」才能证明过期会删，而「证明不了」的判据等于没有判据。
    """
    固定 = os.environ.get(回执时钟环境变量, "")
    if 固定:
        try:
            return datetime.fromisoformat(固定)
        except ValueError:
            pass
    return datetime.now()


def _修剪过期回执() -> int:
    """删掉超过保留天数的**整个**回执文件；返回删掉的个数（0 = 没有过期项）。

    为什么以文件为粒度而不是删行：行号是「指针」的一部分，删行会让同库其它行的行号整体前移，
    已经给出去的指针当场指错。文件名带日期，本身就是天然的过期单位 —— 删整文件，旧指针只是
    「文件已过期被清理」（可判、可解释），而不是「指到别人的内容」（不可判、最危险）。
    """
    截止 = (_回执时刻() - timedelta(days=回执保留天数)).date()
    删掉 = 0
    for 文件 in sorted(回执库().glob("*.jsonl")):
        try:
            哪天 = datetime.strptime(文件.stem.split("_")[0], "%Y%m%d").date()
        except ValueError:
            continue  # 名字不合规的件不碰（宁可留着，也不删来路不明的件）
        if 哪天 < 截止:
            try:
                文件.unlink()
                删掉 += 1
            except OSError:
                pass
    return 删掉


def _落全量回执(值: Any, 耗时毫秒: float | None = None) -> dict[str, Any] | None:
    """把**未裁剪**的值整份写进当日回执库；返回指针字典；写不成返回 None（绝不因此弄坏调用）。

    ★ 有意为之：本函数**不看调用方有没有要**。落盘 = 事实源可回溯，是「不丢」的实现；要不要取回是
    调用方的事。实测教训（2026-09-22）：把落盘做成按需开关，等于把「能不能取回」押在调用方记性上。
    ★ 为什么记录要 **indent 成多行**（而不是一行一条）：取回腿 `文件系统支持库.文件操作.读取文件`
    的定位单位是**行**（`起始行/结束行`，1 起闭区间，显式分段时不精炼不限长）。一条记录若压成一行，
    超大值就只能「全量读回」（上下文当场爆）或「读前 2000 字符」（等于又丢了）—— 两种都不是
    「便宜可以查询」。多行 JSON 让指针能逐段翻页，指针才真的便宜。
    """
    try:
        正文 = json.dumps({"时刻": _回执时刻().isoformat(timespec="seconds"), "值": 值},
                          ensure_ascii=False, indent=1, default=str)
    except (TypeError, ValueError):
        return None
    摘要 = hashlib.sha256(正文.encode("utf-8")).hexdigest()
    # 耗时（2026-09-24 批R·R-12，**只增字段**）：`耗时毫秒` 由网关在
    # `运行核心/统一网关/核心处理/网关处理面.py` 的 finally 里**只产生一次**，
    # 经 `网关信封.转字典` 随回包回来 ⇒ 薄壳只**搬运**，不自己再量一遍
    # （同一件事两套计时即缺陷，哲学 1.2）。
    # 为什么必须落盘：客户端那句 `Wall time: N seconds` 只在调用方屏幕上
    # （实测 2026-09-24：回执库 `grep -c "Wall time"` = 0 ⇒ 盘上答不了「哪个慢」）。
    # ★ 摘要的哈希输入仍是 `时刻 + 值`（与改前逐字相同）：摘要是**内容去重键**，
    #   把耗时并进去会让同一份内容因耗时不同而重复落盘。
    耗时键 = ""
    try:
        耗时键 = f'"耗时毫秒": {round(float(耗时毫秒), 2)}, '
    except (TypeError, ValueError):
        耗时键 = ""
    记录 = '{"摘要": "' + 摘要 + '",' + 耗时键 + 正文[1:]  # 正文[1:] 起于换行 ⇒ 拼出合法 JSON 的多行记录
    if not 记录.endswith("\n"):
        记录 += "\n"
    库 = 回执库()
    try:
        库.mkdir(parents=True, exist_ok=True)
    except OSError:
        return None
    已清理 = _修剪过期回执()
    件 = 库 / f"{_回执时刻():%Y%m%d}_全量回执.jsonl"
    缓存 = 进程内回执行.get(摘要)
    if 缓存 is None:
        try:
            已有行数 = len(件.read_text(encoding="utf-8").splitlines()) if 件.exists() else 0
        except OSError:
            已有行数 = 0
        起始行 = 已有行数 + 1
        try:
            with 件.open("a", encoding="utf-8") as 句柄:
                句柄.write(记录)
        except OSError:
            return None
        结束行 = 起始行 + 记录.count("\n") - 1
        进程内回执行[摘要] = (起始行, 结束行)
    else:
        起始行, 结束行 = 缓存
    指针: dict[str, Any] = {
        "回执": str(件),
        "起始行": 起始行,
        "结束行": 结束行,
        # ★ 取回腿必须自带「不限」：实测缺口（2026-09-22）—— 薄壳对**任何**返回值都会再裁一次，
        #   照指针原样调，5500 字符的值当场被裁到 300，**等于又丢了一遍**。
        # ★ 2026-09-25：形状必须与 4 腿工具面**同形** —— 旧写法 `参数={...}, 返回上限字符=0` 在
        #   schema 层就被拒（顶层 additionalProperties=false ⇒ 那两个都是表外键），等于指针指向一条
        #   「走得到、拿不回」的腿；裁切下线后指针是超限时的唯一出口，这条腿更不能断。
        "取回": (f"capability_call{{能力id=文件系统支持库.文件操作.读取文件, "
                f"数组=['{件}', '', {起始行}, {结束行}, 0], 返回字符数=0}}"
                "（数组位＝文件路径/编码/起始行/结束行/最大字符；0=不限；去掉它会被再裁一次）"),
        "原字符数": _字符数(值),
        "sha256前10": 摘要[:10],
        "保留天数": 回执保留天数,
        "过期日期": (_回执时刻() + timedelta(days=回执保留天数)).date().isoformat(),
        "说明": "上面「取回」拿到的就是本次全量原文；本区段只增不改，指针不会失效",
    }
    if 已清理:
        指针["已清理过期回执"] = 已清理
    return 指针


def _包装(能力id: str, 结果: dict, 参数: dict, 操作: str = "调用能力") -> dict[str, Any]:
    """把网关返回统一成薄壳回执：**只回必要字段**。

    口径（2026-09-23 华哥三次点名：「返回的时候只需要返回必要参数，而不是一堆空值都需要返回」
    「这种复述就没用」「时间是后台记录的，不需要显示」「易语言的返回本质上是很精准的返回，
    不会有一大堆无用的东西返回……一大堆东西本质上是不复用的，结果就是造成了上下文的浪费」）：

    - **恒在**：`成功`（唯一一个无条件出现的键 —— 调用方最先要的就是这一位）；
    - **非空才出现**：`值`（null 不出现）、`错误码` / `错误说明`（成功时为空）、
      `详情` / `句柄` / `慢调用提示` / `被忽略参数` / `请检查`；
    - **不再出现**：`HTTP状态码` / `转发` / `能力id`（**纯复述请求**）、`耗时毫秒`（后台已记录）。

    为什么敢删 `HTTP状态码`：失败原因已被 `错误码` 全覆盖 —— 网关侧失败（网关超时 / 网关不可达 /
    网关响应非JSON / 网关响应非对象）在 `结果["错误码"]`，能力侧失败在信封 `错误码`，本函数取二者之一。
    `网关转发.py` 仍保留该键，那是**内部腿**的判据（"绝不吞掉 HTTP 状态码"），与回包无关。
    `耗时毫秒` 同理：它由网关在后台记录，回包里只留**超阈值时的** `慢调用提示` 这一条人读信号。

    判据出处：`开发文档/项目说明.md` 12.4①「裁决来源链的最后一环 = 易语言口径」。
    """
    信封 = 结果.get("信封") or {}
    成功 = bool(信封.get("成功"))
    数据: dict[str, Any] = {"成功": 成功}
    if 信封.get("值") is not None:
        数据["值"] = 信封.get("值")
    错误码 = str(信封.get("错误码", "") or 结果.get("错误码", "") or "")
    错误说明 = str(信封.get("错误说明", "") or 结果.get("错误说明", "") or "")
    if 错误码:
        数据["错误码"] = 错误码
    if 错误说明:
        数据["错误说明"] = 错误说明
    # 能力侧结构化错误明细（#203）：失败时调用方靠它定位，非空才出现。
    if 信封.get("详情"):
        数据["详情"] = 信封["详情"]
    # 句柄：句柄型能力的产物，调用方靠它续租/查状态/释放 —— 有才出现（华哥：句柄是需要返回的）。
    if 信封.get("句柄") is not None:
        数据["句柄"] = 信封["句柄"]
    # 慢调用提示（2026-09-21）：读/搜索超 15 秒时网关才带出，空即无信号。
    慢调用提示 = str(信封.get("慢调用提示", "") or "").strip()
    if 慢调用提示:
        数据["慢调用提示"] = 慢调用提示
    # 被网关剔除的入参：调用方参数名写错时唯一可见的信号（实测给 `查询文件租约` 传 `路径`
    # 被剔除后过滤器变成「取全部」，一次拿回 470KB 全表），空即无信号。
    if 信封.get("被忽略参数"):
        数据["被忽略参数"] = 信封["被忽略参数"]
    if not 信封:
        数据["成功"] = False
        数据["请检查"] = f"网关凭证来自环境变量，地址 {网关调用地址}"
    return 数据


