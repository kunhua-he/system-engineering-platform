def 是空值(项: Any) -> bool:
    """`null` / `""` / `[]` / `{}` ⇒ 空；`假` / `真` / `0` / `0.0` **都不算空**。

    ★ 布尔 `假` 不再算空（2026-09-24 批R·R-14 口径修正）：原先按「`false` 也没有信息」一并
    省略，实测省掉的是**判定位** —— `指纹一致=false`（「核验过、且不一致」）与「没核验」
    （缺键）在 agent 眼里变成同一个样子，读法被迫变成「缺键＝假」。
    华哥口径「空值直接就不显示」里 `假` 不是空值 ⇒ 一律保留。
    （`0` / `0.0` 同理不算空：计数 0 是读数，「0 条失败」与「没这个字段」是两件事。）
    """
    return 项 is None or 项 == "" or 项 == [] or 项 == {}


def 去空值(值: Any) -> Any:
    """递归省略空值键 / 空元素，返回**新对象**（不改入参）。

    字典：先递归子树、再丢「自己为空」的键（`空值豁免键` 除外）；
    列表：丢递归后仍为空的元素。**非空字段一个不少、值逐字节等价** —— 本函数只删键，
    不碰任何非空值（也不改键序：字典推导保序）。
    """
    if isinstance(值, dict):
        子树 = {键: 去空值(项) for 键, 项 in 值.items()}
        return {键: 项 for 键, 项 in 子树.items()
                if 键 in 空值豁免键 or not 是空值(项)}
    if isinstance(值, list):
        结果表: list[Any] = []
        for 项 in 值:
            新项 = 去空值(项)
            if not 是空值(新项):
                结果表.append(新项)
        return 结果表
    return 值


