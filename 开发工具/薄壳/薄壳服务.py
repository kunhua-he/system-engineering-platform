def _任务终态回执(任务: dict[str, Any]) -> dict[str, Any]:
    """任务终态 → 薄壳回执：成功 ⇒ `值` ＝ 任务结果；失败 ⇒ 错误码 ＋ **结果明细**。

    只回必要字段（空值省略的出口在 `调用工具`）：`任务id`／`状态`／`耗时秒`／`轮询次数`
    这类过程量一律不回 —— 答案到手时它们没有信息量（华哥「时间是后台记录的，不需要显示」）。

    ★ 2026-09-25 补（MCP 现场实测抓到的缺口）：能力任务失败时，任务自己的 `错误码`／
    `错误说明` 字段**常常是空的** —— `自修复工具.静态编译` 的 `状态=失败` 是由
    `结果.五态结论` 校准来的（`任务系统.转字典`），结论原文、逐条明细、失败门禁全在 `结果` 里。
    只回一句「错误码：失败」＝ 把唯一有信息量的东西丢掉，调用方拿不到任何可定位信息
    （实测原文：`-1 / 错误码：失败`，而任务账本里躺着 18 成功 2 失败与两条红项原因）。
    处置与网关同步腿既有口径同源（`网关执行面` 的 #203「能力侧的结构化错误明细如实带出」）：
    失败也把 `结果` 带回 —— **只增字段**，成功/失败判据不变。
    """
    状态 = str(任务.get("状态", "") or "")
    if 状态 == "成功":
        回执: dict[str, Any] = {"成功": 真}
        if 任务.get("结果") is not None:
            回执["值"] = 任务["结果"]
        return 回执
    回执 = {"成功": 假, "错误码": str(任务.get("错误码", "") or "") or 状态}
    if 任务.get("错误说明"):
        回执["错误说明"] = str(任务["错误说明"])
    if 任务.get("结果") is not None:
        回执["结果"] = 任务["结果"]
    日志 = 任务.get("日志") or []
    if 日志:
        回执["日志"] = list(日志)[-5:]
    return 回执


# ── 句柄账（薄壳本地，唯一一处「同一次调用记住了哪个任务」）──────────────────────
# 为什么记在薄壳：底层（网关任务账本）按 任务id 存任务，**没有**「按调用查最近一次任务」的
# 入口；而「提交秒返回 ＋ 同参续查 ＋ 该文件历史最高/平均」三件事都要按**同一次调用**累积
# ⇒ 唯一节点放薄壳本地账（不新建库、不新增能力、不改内核，华哥「不要做多条腿」）。
# 账结构：`{键: {能力id, 任务id, 提交时刻, 耗时秒:[…]}}`；键＝能力id ＋ 入参指纹（`_账键`）。
# 终态收尾时把该次耗时（完成时间 − 创建时间）追加进 `耗时秒` —— 历史最高/平均的唯一数据源。
# 账只是**加速器**：读不到/写不进都不许挡住真实调用（坏账当空账）。
def 句柄账文件() -> Path:
    """句柄账落盘位置：与全量回执库同目录（`工程缓存/运行数据/`）。"""
    return 回执库().parent / "薄壳句柄账.json"


def _账键(能力id: str, 入参: Any) -> str:
    """句柄账的键：能力id ＋ 入参指纹（同一次调用的判据；同参再调即命中）。"""
    正文 = json.dumps({"能力id": 能力id, "入参": 入参}, ensure_ascii=False,
                      sort_keys=True, default=str)
    return hashlib.sha256(正文.encode("utf-8")).hexdigest()[:16]


def _读句柄账() -> dict[str, Any]:
    """读句柄账；不存在/坏 JSON 一律当空账（账是加速器，不是事实源）。"""
    try:
        账 = json.loads(句柄账文件().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return 账 if isinstance(账, dict) else {}


def _写句柄账(账: dict[str, Any]) -> None:
    """写句柄账（先写临时文件再原子替换：读侧永远看不到半截 JSON）。落盘失败不报错。"""
    路径 = 句柄账文件()
    try:
        路径.parent.mkdir(parents=True, exist_ok=True)
        临时 = 路径.with_name(路径.name + ".tmp")
        临时.write_text(json.dumps(账, ensure_ascii=False), encoding="utf-8")
        临时.replace(路径)
    except OSError:
        pass


def _耗时秒(任务: dict[str, Any]) -> float | None:
    """任务耗时（秒）＝ `完成时间 − 创建时间`（内核账本既有字段，薄壳只做差，不另立一套）。"""
    try:
        起 = datetime.fromisoformat(str(任务.get("创建时间") or ""))
        止 = datetime.fromisoformat(str(任务.get("完成时间") or ""))
    except (TypeError, ValueError):
        return None
    差 = (止 - 起).total_seconds()
    return 差 if 差 >= 0 else None


def _历史耗时串(耗时表: Any) -> str:
    """历史耗时一句话：**运行次数**／时间最高值／平均值（无记录时如实说「暂无」，不编数）。

    ★ 2026-09-25 华哥口径：必须带「运行次数」—— 只有最高/平均时，调用方分不清这两个数
    是「一次跑出来」还是「十次跑出来的」，「平均」有没有代表性也就无从判断。
    """
    秒表 = [float(项) for 项 in (耗时表 or []) if isinstance(项, (int, float))]
    if not 秒表:
        return "该文件暂无历史运行时间记录。"
    return (f"该文件历史中运行次数为：{len(秒表)} 次，"
            f"时间最高值为：{max(秒表):.1f} s，"
            f"平均值为：{sum(秒表) / len(秒表):.1f} s。")


def _句柄找键(句柄: Any) -> str:
    """「直接传句柄」也接上（华哥口径③「查询异步的时候，传参是句柄」）：句柄 → 账键。"""
    文本 = str(句柄 or "").strip()
    if not 文本:
        return ""
    for 键, 项 in _读句柄账().items():
        if isinstance(项, dict) and str(项.get("任务id") or "") == 文本:
            return str(键)
    return ""


def 提交回执文案(能力id: str, 任务id: str, 项: dict[str, Any]) -> str:
    """提交**秒返回**的正文：句柄 ＋ 两档 ＋ 下一步动作（不把「怎么查」留给调用方猜）。"""
    return (f"任务已提交（句柄={任务id}）。\n"
            f"默认一直跑到 {异步腿首档秒:g} 秒；{异步腿首档秒:g} 秒没跑完会自动升到"
            f" {异步腿次档秒:g} 秒。\n"
            f"你可以先做其他事情，后续再过来查询：把**同一次调用原样再发一遍**"
            f"（{能力id} 与入参都不改）即可，薄壳会回该任务的最新进度或结果。\n"
            f"{_历史耗时串(项.get('耗时秒'))}")


def 进行中文案(任务id: str, 项: dict[str, Any], 状态: str) -> str:
    """未终态续查的正文：正在执行 ＋ 已跑秒数 ＋ 两档说明 ＋ 历史最高/平均 ＋ 下一步。"""
    try:
        已跑 = max(0.0, time.time() - float(项.get("提交时刻") or 0))
    except (TypeError, ValueError):
        已跑 = 0.0
    段 = [f"任务仍在执行（句柄={任务id}，状态={状态 or '进行中'}，已跑 {已跑:.0f} s）。"]
    if 已跑 < 异步腿首档秒:
        段.append(f"默认跑到 {异步腿首档秒:g} 秒；没跑完会自动升到 {异步腿次档秒:g} 秒。")
    elif 已跑 < 异步腿次档秒:
        段.append(f"已超过 {异步腿首档秒:g} 秒，自动升到 {异步腿次档秒:g} 秒。")
    else:
        段.append(f"该任务跑了 {异步腿次档秒:g} s，仍然没跑完，"
                  "请检查代码是否有泄露，优化代码速度。")
    段.append(_历史耗时串(项.get("耗时秒")))
    段.append("你可以先做其他事情，后续再过来查询（同一次调用原样再发一遍）。")
    return "".join(段)


def _续查(账键: str, 上限字符: int) -> dict[str, Any] | None:
    """同参再调 ⇒ 先看句柄账：账里有在跑的任务就查它（**秒返回**）。

    返回 `None` ＝「账里没有这个调用」或「该任务已不可查」⇒ 调用方按正常调用继续走。
    账只是加速器，**绝不因为账的问题挡住真实调用**（任务不存在就销账放行）。
    """
    账 = _读句柄账()
    项 = 账.get(账键)
    if not isinstance(项, dict) or not 项.get("任务id"):
        return None
    任务id = str(项["任务id"])
    查询 = _原始转发(任务查询操作, {"参数": {"任务id": 任务id}}, 0)
    if not 查询.get("成功"):
        if str(查询.get("错误码", "") or "") == "任务不存在":
            账.pop(账键, None)
            _写句柄账(账)
        return None
    任务 = 查询.get("值") or {}
    状态 = str(任务.get("状态", "") or "")
    if 状态 in 任务终态:
        耗时 = _耗时秒(任务)
        if 耗时 is not None:
            项.setdefault("耗时秒", []).append(耗时)
        项.pop("任务id", None)
        项.pop("提交时刻", None)
        账[账键] = 项
        _写句柄账(账)
        return _任务终态回执(任务)
    return {"成功": 真, "值": 进行中文案(任务id, 项, 状态)}


def _走异步腿(能力id: str, 转发参数: dict[str, Any], 上限字符: int,
             账键: str = "") -> dict[str, Any]:
    """走异步腿：**提交 → 秒返回句柄**（2026-09-25 华哥新口径 ①②）。

    改前是「提交 ＋ 有界等待 100 秒」：窗口内跑完才一次往返拿答案，超时回一句「薄壳不再等」
    —— 把「换腿／等待」抛回调用方，且没给下一步动作。现口径：提交完立刻把 `句柄`（任务id）
    交回，并**明确下一步动作**（同一次调用原样再发一遍＝续查）。任务一直跑（第一档 300 秒、
    第二档 600 秒），薄壳不再替调用方等。
    """
    提交 = _原始转发(任务提交操作, {"能力id": 能力id, "参数": dict(转发参数)}, 上限字符)
    if not 提交.get("成功"):
        提交["错误说明"] = f"任务提交未成功；{提交.get('错误说明', '')}"
        return 提交
    任务id = str((提交.get("值") or {}).get("任务id", "") or "")
    if not 任务id:
        return {"成功": 假, "错误码": "任务提交异常",
                "错误说明": f"任务提交没回任务id：{str(提交.get('值'))[:200]}"}
    键 = 账键 or _账键(能力id, 转发参数)
    账 = _读句柄账()
    项 = 账.get(键)
    if not isinstance(项, dict):
        项 = {"能力id": 能力id, "耗时秒": []}
    项["能力id"] = 能力id
    项["任务id"] = 任务id
    项["提交时刻"] = time.time()
    项.setdefault("耗时秒", [])
    账[键] = 项
    _写句柄账(账)
    return {"成功": 真, "值": 提交回执文案(能力id, 任务id, 项)}


