def _节点可信(块: str, 节点: dict) -> bool:
    """③ 的**只读**保鲜判据：块里首个 `def`/`class` 行是否就是该节点的定义行。

    为什么不比文件内容哈希（§十二 记的那条更硬的判据）：哈希要直读 `.codegraph/codegraph.db`
    的 `files.content_hash` —— 那是 `代码解析支持库.代码地图` 的活，薄壳直读业务库就是在
    薄壳里立第二套实现（哲学 1.2）。这里用**自证**判据：索引给的 `起始行` 若还指着那个符号，
    块里第一行定义语句的名字必须与索引的 `名称` 逐字相同（方法取 `类.方法` 的末段）。
    行号漂了 ⇒ 名字对不上 ⇒ 判未验证。硬哈希口径的落点已登记（§13.6 B-5）。
    非 python 或 `file`/`variable` 类节点退化为「名称出现在块里」—— 弱判据也不冒充强判据。
    """
    名称 = str(节点.get("名称", "") or "")
    种类 = str(节点.get("种类", "") or "")
    语言 = str(节点.get("语言", "") or "")
    if not 名称 or not 块:
        return False
    if 种类 == "file":
        return True
    末段 = 名称.rsplit(".", 1)[-1]
    if 语言 == "python" and 种类 in ("function", "method", "class"):
        for 行 in 块.splitlines():
            去空白 = 行.strip()
            if not (去空白.startswith("def ") or 去空白.startswith("async def ")
                    or 去空白.startswith("class ")):
                continue
            声明 = 去空白.split("(", 1)[0].rstrip(":").strip()
            词表 = 声明.split()
            if not 词表:
                return False
            词 = 词表[-1].split("[", 1)[0].strip()
            return 词 == 末段
        return False
    return 名称 in 块 or 末段 in 块


def _渲染地图节点(根: str, 节点列表: list) -> tuple[list[str], list[dict]]:
    """把节点表渲染成回包文本；返回 `(文本段, 未验证节点表)`。

    每条形如：`<绝对路径>:<起>-<止>  #已验证` 紧跟一段缩进 4 空格的代码块（≤60 行）。
    """
    段: list[str] = []
    未验: list[dict] = []
    for 节点 in 节点列表:
        if not isinstance(节点, dict):
            continue
        文件 = str(节点.get("文件路径", "") or "")
        起, 止 = 节点.get("起始行"), 节点.get("结束行")
        块 = _取代码块(根, 文件, 起, 止)
        标记 = "#已验证" if _节点可信(块, 节点) else "#未验证"
        if 标记 == "#未验证":
            未验.append(节点)
        段.append(f"{根.rstrip('/')}/{文件}:{起}-{止}  {标记}")
        if 块:
            段.append("\n".join("    " + 行 for 行 in 块.splitlines()))
    return 段, 未验


def _代码地图搜索(参数: dict) -> dict[str, Any]:
    """腿③：按符号名查代码地图；回 `<绝对路径>:<起>-<止>  #已验证` ＋ 代码块（缩进 4 空格）。

    三条硬口径：
    · **每条都带保鲜标记**：验过 ⇒ `#已验证`；验不过 ⇒ 先触发一次增量同步（唯一同步腿＝
      `代码地图提供者.重建项目地图索引`）再查再验，仍不过就如实回 `#未验证` —— **绝不冒充已验证**。
    · 单条代码块上限 60 行（超出标 `…（余 N 行）`，见 `_取代码块`）—— 实测 11,847 节点：
      中位 10 行／P90 41／P95 67，60 行盖住绝大多数又不至于撑爆上下文。
    · 一次给全：定位行 ＋ 代码块一次回带，调用方不用再取第二次。
    """
    关键词 = str(参数.get("关键词", "") or "").strip()
    if not 关键词:
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "关键词必填"}
    try:
        最大条数 = int(参数.get("最大条数") or 默认地图条数)
    except (TypeError, ValueError):
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "最大条数必须是整数"}
    最大条数 = max(1, min(最大条数, 地图条数上限))
    根 = _解析项目根(参数)[0]
    节点列表, 错误 = _查地图节点(根, 关键词, 最大条数)
    if 错误 is not None:
        return 错误
    if not 节点列表:
        return {"成功": 真, "值": f"（代码地图无命中：{关键词}）"}
    段, 未验 = _渲染地图节点(根, 节点列表)
    if 未验 and _同步代码地图(根):
        重查, 重查错误 = _查地图节点(根, 关键词, 最大条数)
        if 重查错误 is None and 重查:
            段, 未验 = _渲染地图节点(根, 重查)
    if 未验:
        段.append(f"（{len(未验)} 条索引未验证：索引行号与源文件对不上；已触发同步仍对不上）")
    return {"成功": 真, "值": "\n".join(段)}


def _命令回执(数据: dict[str, Any]) -> dict[str, Any]:
    """④ 回包：成功 ⇒ `值` ＝ 标准输出；失败 ⇒ 错误码 ＋ 错误输出（**二选一，不同时回**）。

    口径（华哥 2026-09-25「返回值本质上就只需要返回成功的文本；如果失败了，就返回错误码和
    错误输出；这个是二选一的返回」）：成功那一路不看 `错误输出`（很多工具往 stderr 打进度，
    成功时它是噪声），失败那一路才把 `错误输出 ＋ 标准输出` 一起给（诊断要全）。
    """
    if not 数据.get("成功"):
        return 数据
    值 = 数据.get("值")
    if not isinstance(值, dict):
        return 数据
    退出码 = 值.get("退出码")
    if str(退出码) in ("0", "None"):
        数据["值"] = 值.get("标准输出") or ""
        return 数据
    数据["成功"] = 假
    数据["错误码"] = "命令失败"
    数据["错误说明"] = f"退出码 {退出码}"
    数据["值"] = ((值.get("错误输出") or "") + (值.get("标准输出") or "")).strip()
    return 数据


def _终端运行(参数: dict) -> dict[str, Any]:
    """腿④：执行单条命令。成功回标准输出；失败回错误码与错误输出。

    - `执行方式`：1=直启（argv 直启；管道/重定向/`&&` 一律拒）；2=shell（默认，POSIX sh -c）。
    - `是否异步`：留空=**真**。真 ⇒ 走**异步腿**（任务提交）＋ 薄壳**有界等待**
      （`命令等待上限秒`＝100 秒）：窗口内跑完就一次往返把结果拿回来，超时才回 `任务id`
      ＋ 查法；假 ⇒ 走**同步腿**（`超时秒` 固定 9 秒 < 网关同步腿守卫阈值 10 秒），
      若网关仍回 `须走异步腿` 则**自动改走异步腿**（一次调用把答案拿回来，不把换腿的事
      抛回给调用方）。
    - `工作目录` 由薄壳补位**仓库根**（本工具只服务本仓库，不猜路径）。
    """
    命令 = str(参数.get("命令", "") or "")
    if not 命令.strip():
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "命令必填"}
    执行方式 = 参数.get("执行方式")
    if 执行方式 in (None, ""):
        执行方式 = 2
    if not isinstance(执行方式, int) or isinstance(执行方式, bool) or 执行方式 not in (1, 2):
        return {"成功": 假, "错误码": "参数不合法",
                "错误说明": "执行方式只认整数 1=直启／2=shell，留空=2"}
    是否异步 = 参数.get("是否异步")
    if 是否异步 in (None, ""):
        是否异步 = 真
    if not isinstance(是否异步, bool):
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "是否异步只认逻辑值（真/假）"}
    根 = _解析项目根(参数)[0]
    能力id = "系统核心支持库.进程管理.执行命令"
    上限字符 = int(参数.get("返回字符数", 默认返回上限字符))
    具名 = {"命令": 命令, "经shell": 执行方式 == 2, "工作目录": 根}
    # 续查（口径③）：同一条命令再发一遍 ⇒ 查上一次那个任务；直接传句柄也认。
    账键 = _句柄找键(命令) or _账键(能力id, {"命令": 命令, "执行方式": 执行方式})
    续查 = _续查(账键, 上限字符)
    if 续查 is not None:
        return _命令回执(续查)
    if 是否异步:
        数据 = _走异步腿(能力id, {**具名, "超时秒": 异步腿命令超时秒}, 上限字符, 账键)
    else:
        数据 = _转发能力(能力id, {**具名, "超时秒": 同步腿命令超时秒}, 上限字符)
        if not 数据.get("成功") and str(数据.get("错误码", "") or "") == 须走异步腿错误码:
            数据 = _走异步腿(能力id, {**具名, "超时秒": 异步腿命令超时秒}, 上限字符, 账键)
    return _命令回执(数据)


