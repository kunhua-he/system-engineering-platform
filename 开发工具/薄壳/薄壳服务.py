def _字符数(值: Any) -> int:
    """值的 JSON 字符数（不可序列化时退回 str 长度，不抛异常）。"""
    try:
        return len(json.dumps(值, ensure_ascii=False))
    except (TypeError, ValueError):
        return len(str(值))


def _裁剪值(值: Any, 上限字符: int, 值字段: Any) -> tuple[Any, dict | None]:
    """按 `值字段` 投影、再按 `上限字符` 结构化裁剪；返回 `(值, 裁剪说明或 None)`。

    顺序有意为之：**先投影后裁剪** —— 只要了 2 个字段的调用方，不该因为「没要的字段太大」
    而丢掉自己要的东西。未发生投影与裁剪时返回 None，不留噪声。
    """
    说明: dict[str, Any] = {}
    原字符数 = _字符数(值)

    if 值字段:
        if not isinstance(值字段, list) or not all(isinstance(项, str) for 项 in 值字段):
            说明["值字段未生效"] = "值字段必须是字符串数组"
        elif not isinstance(值, dict):
            说明["值字段未生效"] = f"值不是对象（{type(值).__name__}），无法按字段投影"
        else:
            保留 = [键 for 键 in 值字段 if 键 in 值]
            缺失 = [键 for 键 in 值字段 if 键 not in 值]
            值 = {键: 值[键] for 键 in 保留}
            说明["保留字段"] = 保留
            if 缺失:
                说明["字段不存在"] = 缺失

    if 上限字符 <= 0 or _字符数(值) <= 上限字符:
        if not 说明:
            return 值, None
        说明["原字符数"] = 原字符数
        说明["裁剪后字符数"] = _字符数(值)
        return 值, 说明

    # 结构化裁剪：按结构丢，而不是把 JSON 字符串拦腰切断（切一半的 JSON 调用方没法用）。
    if isinstance(值, dict):
        保留项: dict[str, Any] = {}
        丢弃: list[str] = []
        for 键, 项值 in 值.items():
            候选 = dict(保留项)
            候选[键] = 项值
            if _字符数(候选) > 上限字符:
                # 单个值就超限时**也丢**（不搞「至少留一个」的例外）：上限是硬承诺，
                # 留一个 20KB 的字段等于没保护。丢了什么会在下面如实列出。
                丢弃.append(键)
            else:
                保留项[键] = 项值
        值 = 保留项
        if 丢弃:
            说明["丢弃字段"] = 丢弃
        if not 保留项:
            说明["全部丢弃"] = "每个字段单独都超过上限，已全部丢弃；请提高 返回上限字符 或改用 值字段"
    elif isinstance(值, list):
        保留列表: list[Any] = []
        for 项 in 值:
            if _字符数(保留列表 + [项]) > 上限字符:
                break
            保留列表.append(项)
        说明["列表截断"] = f"{len(值)} → {len(保留列表)}"
        值 = 保留列表
    elif isinstance(值, str):
        值 = 值[:上限字符]
        说明["文本截断"] = f"截到 {上限字符} 字"
    else:
        值 = f"<{type(值).__name__} 值超过 {上限字符} 字符，已省略>"
        说明["值已省略"] = 真

    说明.update({
        "已裁剪": 真,
        "原字符数": 原字符数,
        "上限字符": 上限字符,
        "裁剪后字符数": _字符数(值),
        "提示": "提高 返回上限字符、或用 值字段 精确取字段；确实要全量时把 返回上限字符 设为 0",
    })
    return 值, 说明


def _包装(能力id: str, 结果: dict, 参数: dict, 操作: str = "调用能力") -> dict[str, Any]:
    """把网关返回统一成薄壳回执：保留 HTTP 状态码、信封关键字段与转发路径。"""
    信封 = 结果.get("信封") or {}
    数据: dict[str, Any] = {
        "HTTP状态码": 结果.get("HTTP状态码"),
        "转发": f"POST {网关调用地址}（操作={操作}）",
        "能力id": 能力id,
        "成功": bool(信封.get("成功")),
        "错误码": str(信封.get("错误码", "") or 结果.get("错误码", "")),
        "错误说明": str(信封.get("错误说明", "") or 结果.get("错误说明", "")),
        "值": 信封.get("值"),
        # 能力侧结构化错误明细（#203）：网关信封已经带出 `详情`（源：`结果.详情`），薄壳此前
        # 只挑固定字段，把它整块丢掉 —— 失败时调用方依旧只能二分试。只增字段
        # （哲学第 5 条 2 项），老调用方不受影响。
        "详情": 信封.get("详情") or {},
        "句柄": 信封.get("句柄"),
        "耗时毫秒": 信封.get("耗时毫秒"),
        # 慢调用提示（只增字段，2026-09-21 华哥要求）：读/搜索超 15 秒时网关会带出该提示，
        # 薄壳同样不能把它丢掉，否则「赶紧去看哪里卡住了」在 MCP 链路上失效。
        "慢调用提示": str(信封.get("慢调用提示", "") or ""),
    }
    if not 信封:
        数据["成功"] = False
        数据["请检查"] = f"网关凭证来自环境变量，地址 {网关调用地址}"
    return 数据


def _项目根检查(参数: dict) -> tuple[bool, str]:
    """判断「这次调用是不是系统工程平台的」——不是就**不载入任何平台上下文**。

    华哥 2026-09-19 裁决：「如果是这个项目的就载入提示词；如果不是这个项目的，
    就直接不载入更多上下文就好了」「控制好最小体量的 token 限制」。

    判据只看一条：`项目根` 必须是**真实存在的目录**，且其下有本平台的锚文件
    （`AGENTS.md` **且** `开发文档/项目说明.md`）——两件都在才算本仓库，
    避免一个同名目录或随手传的路径把平台规则灌进无关会话。
    传空/不存在/缺锚文件 → 一律按「不是本项目」处理（fail-closed）。
    """
    传入 = str(参数.get("项目根", "") or "").strip()
    if not 传入:
        return 假, ("未传 项目根：本工具只服务系统工程平台仓库。"
                       "请传仓库绝对路径（含 AGENTS.md 与 开发文档/项目说明.md）后再调用；"
                       "非本仓库会话不要调用本工具，也不要据此载入平台上下文。")
    根 = Path(传入).expanduser()
    if not 根.is_dir():
        return 假, f"项目根不是目录：{传入}。本工具只服务系统工程平台仓库，已拒绝（未载入任何平台上下文）。"
    if not ((根 / "AGENTS.md").is_file() and (根 / "开发文档" / "项目说明.md").is_file()):
        return 假, (f"项目根缺少平台锚文件（AGENTS.md 与 开发文档/项目说明.md）：{根}。"
                       "本工具只服务系统工程平台仓库，已拒绝（未载入任何平台上下文）。")
    return 真, ""


def _查询能力(参数: dict) -> dict[str, Any]:
    """转发到唯一网关调用 搜索能力目标；未注册则报 能力未注册 并登记缺口。"""
    通过, 原因 = _项目根检查(参数)
    if not 通过:
        return {"成功": 假, "错误码": "非本平台项目根", "错误说明": 原因}
    关键词 = str(参数.get("关键词", "") or "").strip()
    if not 关键词:
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "关键词必填"}
    try:
        限制 = int(参数.get("限制", 默认检索条数))
    except (TypeError, ValueError):
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "限制必须是整数"}
    # 精准检索三件套：条数 / 详略档 / 翻页游标 —— 都**原样透传**给能力，薄壳不解释语义。
    # 未传的不塞默认值（能力自己知道默认是什么），避免薄壳悄悄改写调用语义。
    入参: dict[str, Any] = {"关键词": 关键词, "限制": 限制}
    细节级别 = str(参数.get("细节级别", "") or "").strip()
    if 细节级别:
        if 细节级别 not in 细节级别合法值:
            return {"成功": 假, "错误码": "参数不合法",
                    "错误说明": f"细节级别必须是 {'/'.join(细节级别合法值)} 之一，收到 {细节级别!r}"}
        入参["细节级别"] = 细节级别
    游标 = str(参数.get("游标", "") or "").strip()
    if 游标:
        入参["游标"] = 游标
    结果 = 转发({"操作": "调用能力", "能力id": 搜索能力目标, "参数": 入参})
    数据 = _包装(搜索能力目标, 结果, 参数)
    未注册 = 数据["错误码"] in 未注册标志 or "能力未注册" in 数据["错误说明"]
    if not 数据["成功"] and 未注册:
        登记 = 登记待补能力(搜索能力目标, "capability_search", 数据["错误说明"])
        数据["错误码"] = "能力未注册"
        数据["错误说明"] = f"网关未注册能力 {搜索能力目标}；薄壳不自实现搜索逻辑"
        数据["待补能力清单"] = 登记
    return 数据


def _调用能力(参数: dict) -> dict[str, Any]:
    """薄壳主体：按 `操作` 转发唯一网关（先校验项目根是本平台仓库）。

    `操作` 白名单见 `薄壳允许操作`（默认 `调用能力`）：
    - `调用能力`：`能力id` + `参数` 转发；返回侧只做体积控制，**不解释、不改写、不重排**。
    - `热接入` / `健康检查`：网关操作，**不接受 `参数`、不需要 `能力id`**（网关侧
      允许字段表把它们声明为 `set()`）。`热接入` = 新增/变更包增量装配免重启，
      改完能力调它即生效（决策记录 0008：**不重启网关**）。

    入参侧唯一一处动刀：`项目根` 自动补位（见下），其余原样转发。
    """
    通过, 原因 = _项目根检查(参数)
    if not 通过:
        return {"成功": 假, "错误码": "非本平台项目根", "错误说明": 原因}
    操作 = str(参数.get("操作", "") or "").strip() or 默认操作
    if 操作 not in 薄壳允许操作:
        return {"成功": 假, "错误码": "参数不合法",
                "错误说明": (f"操作必须是 {' / '.join(薄壳允许操作)} 之一，收到 {操作!r}；"
                          "薄壳按白名单 fail-closed，不转发未登记的操作")}
    try:
        上限字符 = int(参数.get("返回上限字符", 默认返回上限字符))
    except (TypeError, ValueError):
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "返回上限字符必须是整数"}
    if 操作 in 无能力id操作:
        # 网关操作：网关侧 允许字段表 声明为 set()，多带字段虽被网关忽略（协议只增不删），
        # 但静默丢弃会让调用方以为参数生效了 —— 故薄壳在边界上直接拒绝，不装作接受。
        if 参数.get("参数"):
            return {"成功": 假, "错误码": "参数不合法",
                    "错误说明": (f"操作 {操作} 不接受 参数（网关侧 允许字段表 为 set()）；"
                              "请留空或删掉 参数 键")}
        数据 = _包装(操作, 转发({"操作": 操作}), 参数, 操作=操作)
        裁剪后, 裁剪说明 = _裁剪值(数据.get("值"), 上限字符, 参数.get("值字段"))
        数据["值"] = 裁剪后
        if 裁剪说明 is not None:
            数据[值裁剪键] = 裁剪说明
        return 数据
    能力id = str(参数.get("能力id", "") or "").strip()
    if not 能力id:
        return {"成功": 假, "错误码": "参数不合法",
                "错误说明": "能力id必填（只有 热接入 / 健康检查 这两个网关操作不需要能力id）"}
    入参 = 参数.get("参数")
    if 入参 is None:
        入参 = {}
    if not isinstance(入参, dict):
        return {"成功": 假, "错误码": "参数不合法", "错误说明": "参数必须是对象"}
    # ★ `项目根` 自动补位（2026-09-21 华哥裁决「不要再同一个坑摔倒 2 次」）：
    # 顶层 `项目根` 是**本工具自己的**平台身份校验参数，能力自己的同名入参在 `参数` 里，
    # 两者同名不同层。此前必须手抄第二遍，实测「连传 4 次错才开通工」（工具描述里至今
    # 留着这条警告）——这就是典型的「本该一次成功的调用被迫多次探索」。现由薄壳补位：
    # `参数` 里没给 `项目根` 就填上顶层那个（顶层已通过校验，故此处必有值）。
    # 安全前提两条，均已核实：① 平台把 `项目根` 一律定义为「仓库根绝对路径」，与顶层同义
    # （4 个声明它为必填的能力说明全一致）；② 网关对**未知参数一律忽略**
    # （运行核心/统一网关/协议/类型规格.py 的协议兼容口径），故对未声明它的能力注入也无害。
    # 调用方显式给了就以调用方的为准（不覆盖）。
    if "项目根" not in 入参:
        入参 = dict(入参)
        入参["项目根"] = str(参数.get("项目根", "") or "").strip()
    数据 = _包装(能力id, 转发({"操作": 操作, "能力id": 能力id, "参数": 入参}), 参数, 操作=操作)
    裁剪后, 裁剪说明 = _裁剪值(数据.get("值"), 上限字符, 参数.get("值字段"))
    数据["值"] = 裁剪后
    if 裁剪说明 is not None:
        数据[值裁剪键] = 裁剪说明
    return 数据


