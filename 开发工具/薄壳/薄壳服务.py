    if not 读.get("成功"):
        return ""
    值 = 读.get("值")
    if isinstance(值, str):
        return 值
    if isinstance(值, dict):
        for 键 in ("内容", "文本", "文本内容", "值"):
            if isinstance(值.get(键), str):
                return 值[键]
    return ""


