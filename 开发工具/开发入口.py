def 查看契约(能力id: str) -> dict[str, Any]:
    """查看契约与参数返回：转调唯一能力腿 `能力目录.读取能力`（不自建契约读取腿）。

    为什么改转调（2026-09-20，待办 #83）：原实现自建 `rglob("能力契约/*.json")`
    扫 `支持库`/`模块库` 两子树找条目 —— 那是**第二套契约读取实现**（哲学 1.2/1.3），
    且只扫两个顶层，`平台控制面`/`技能库`/`运行核心` 的契约天然查不到，
    与唯一腿 `读取能力`（扫全仓 713 条公开能力）**结果不一致**。
    唯一腿已是注册能力，返回字段覆盖本函数原输出（参数/必填/默认值/返回结构/
    错误码/调用示例/权限/资源预算/依赖/版本/最近成功验证），故直接转调、
    删掉 rglob 分支。字段名对齐唯一腿口径：`版本` 用其 `版本`、`返回结构` 用其
    `返回结构`；`结构问题` 由契约编译器在本函数内对**唯一腿返回的参数面**复核。

    **「能力不存在」不算腿故障（2026-09-23 修）**：唯一腿把「按能力id 找不到公开能力」
    作为错误码表内的公开结论返回（`能力不存在`），转调层按「失败一律抛」的契约把它抛成
    `检索失败`。本函数把它翻译回业务结论 `找到=False`（唯一腿的**真故障**仍照抛），
    否则调用方（HTTP 网关）会把 404 谎报成 500「网关内部错误」。
    """
    from 开发工具.能力搜索.能力搜索器 import 读取公开能力契约, 检索失败
    from 开发工具.契约编译.契约编译器 import 校验契约结构
    结果: dict[str, Any] = {"能力id": 能力id, "找到": False}
    try:
        条目 = 读取公开能力契约(系统根, 能力id)
    except 检索失败 as 错误:
        # 「能力不存在」是唯一腿**错误码表内的公开结论**（`模块库/能力目录/说明/设计说明.md`
        # 「失败如何表达」表：按能力id 找不到公开能力 → `能力不存在` / HTTP 404），**不是腿故障**。
        # 转调层按「失败一律抛 `检索失败`」的契约把它抛上来，本层负责把它翻译回业务结论：
        # 落 `找到=False`，由调用方（网关）按 404 处理。不翻译则网关的兜底 `except Exception`
        # 会把 404 谎报成 500「网关内部错误」—— 2026-09-23 实测（当时承载该路由的 40006 腿
        # 已于 2026-09-24 批R·R-7 删除；本翻译按契约对任何调用方仍一律生效）。
        if 错误.错误码 != "能力不存在":
            raise RuntimeError(f"读取能力失败: {错误}") from 错误
        条目 = {}
    except Exception as 错误:  # 唯一腿失败如实抛出，不用「找不到」冒充
        raise RuntimeError(f"读取能力失败: {错误}") from 错误
    if not 条目:
        结果["说明"] = f"公开能力不存在: {能力id}（可先用 搜索能力 按关键词定位）"
        return 结果
    问题 = 校验契约结构({"能力id": 条目.get("能力id", 能力id),
                        "版本": 条目.get("版本", ""),
                        "参数": 条目.get("参数", []),
                        "返回": 条目.get("返回结构", "")})
    结果.update({"找到": True, "版本": 条目.get("版本", ""),
                "参数": 条目.get("参数", []), "返回": 条目.get("返回结构", ""),
                "错误码": 条目.get("错误码", []), "结构问题": 问题,
                "包id": 条目.get("包id", ""), "提供方": 条目.get("提供方", ""),
                "来源": "能力目录.读取能力"})
    return 结果


