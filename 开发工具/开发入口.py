def 创建支持库模板(名称: str, 目录: Path | None = None, 开工ID: str | None = None) -> str:
    """创建支持库模板（九要素）。

    落盘一律走**唯一写腿**（`文件系统支持库.文件操作.创建目录` / `写入文件`）：它们自带
    「内核只读锁的解锁窗口 + 原子替换 + 保留权限位」，裸 `mkdir`/`write_text` 会在整仓
    上锁后被内核以 `Operation not permitted` 拒（2026-09-23 实测）。

    开工ID 穿透（2026-09-25）：唯一写腿按「活跃写租约所有者 == 开工ID」判授权
    （`公共契约/运行时/写入授权.py::校验写入授权`），本能力落点 `系统根/支持库/后端/<名称>`
    明确受管，故必须把调用方的 开工ID 原样透传给每一次 创建目录/写入文件 —— 缺它即 `越界`。
    本能力不是 MCP 能力（无 能力定义.json，只在 命令行入口 暴露），凭证经 `--开工ID` 收。
    """
    from 支持库.后端.文件系统支持库.文件操作 import 写入文件, 创建目录
    目录 = 目录 or 系统根 / "支持库" / "后端" / 名称
    创建目录(str(目录), 开工ID=开工ID).确保成功()
    for 子目录 in ("实现", "能力契约", "依赖契约", "配置契约", "权限契约", "说明", "验证场景", "默认配置"):
        创建目录(str(目录 / 子目录), 开工ID=开工ID).确保成功()
    写入文件(str(目录 / "包声明.json"), json.dumps({
        "包id": f"支持库.后端.{名称}", "名称": 名称, "类型": "支持库",
        "版本": "1.0.0", "说明": f"{名称} 支持库", "入口": "__init__.py", "依赖": [],
        "能力": [{"能力id": f"{名称}.示例能力", "名称": "示例能力",
                  "参数": [{"名称": "输入", "类型": "文本型"}], "说明": "示例能力"}],
    }, ensure_ascii=False, indent=2), 开工ID=开工ID).确保成功()
    写入文件(str(目录 / "__init__.py"),
        f'"""支持库.{名称} 包级中文入口。"""\n\nfrom 公共契约.能力契约.契约 import 能力实现\n\n\ndef 注册能力(注册表) -> None:\n    """由支持库加载器调用。"""\n    注册表.注册(能力实现(\n        能力id="{名称}.示例能力", 包id="支持库.后端.{名称}",\n        实现函数=示例能力, 参数=[{{"名称": "输入", "类型": "文本型"}}],\n        返回="结果型", 说明="示例能力",\n    ))\n\n\ndef 示例能力(输入: str) -> dict:\n    if not 输入:\n        return {{"成功": False, "错误码": "参数不合法"}}\n    return {{"成功": True, "值": {{"长度": len(输入)}}}}\n', 开工ID=开工ID).确保成功()
    写入文件(str(目录 / "能力契约" / "参数契约.json"), json.dumps({
        "能力契约": [{"能力id": f"{名称}.示例能力", "参数": [{"名称": "输入", "类型": "文本型"}], "返回": "结果型"}],
    }, ensure_ascii=False, indent=2), 开工ID=开工ID).确保成功()
    写入文件(str(目录 / "说明" / f"{名称}说明.md"), f"# {名称} 支持库\n\n示例能力：输入文本，返回长度。\n", 开工ID=开工ID).确保成功()
    写入文件(str(目录 / "验证场景引用.json"), json.dumps({
        f"{名称}.示例能力": {"能力": "示例能力", "验证场景": ["组件合规"]},
    }, ensure_ascii=False, indent=2), 开工ID=开工ID).确保成功()
    return f"支持库模板已创建: {目录}"


