        事件已清空 = 通道.事件队列 == []
        通道已移除 = 通道.请求id not in 管理器.通道表
        验证失败 = 事件已清空 and 通道已移除
        return 破坏证据("客户端断开", "流式客户端断开", 验证失败,
                      资源释放=验证失败, 详情=f"事件清空:{事件已清空} 通道移除:{通道已移除}")

