        注册表.注册版本("破坏.能力", "1.0.0", 声明字典={"包id": "破坏.能力", "版本": "1.0.0"})
        注册表.注册版本("破坏.能力", "1.1.0", 声明字典={"包id": "破坏.能力", "版本": "1.1.0"})
        切换 = 热切换管理器(注册表)
