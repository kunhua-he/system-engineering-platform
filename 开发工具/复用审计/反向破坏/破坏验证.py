@dataclass
class 破坏证据:
    """一份破坏验证证据。"""

    场景名: str
    破坏方式: str
    验证结果: bool  # 验证器是否失败（预期 True）
    发布阻断: bool = False
    旧版本恢复: bool = False
    证据保留: bool = False
    资源释放: bool = False
    详情: str = ""
    # 检出方式：断言=场景在生产接口上真跑出「破坏被拒」；执行异常=场景函数自身
    # 抛异常（被测系统拒绝 与 测试自身故障 在异常里无法区分），后者一律记
    # 验证结果=False 并显式标出，避免异常被当成检出成功。
    检出方式: str = "断言"


@dataclass
class 破坏验证报告:
    """反向破坏验证报告。"""

    证据列表: list[破坏证据] = field(default_factory=list)
    # 恒真检查：真对照结论——同一批验证器对「未破坏输入」必须**不**报检出。
    # True = 已用正向对照证明本验证器不是恒真（不是「13 项全检出」的同义反复）。
    恒真检查: bool = False
    # 恒真事实清单：空 = 无恒真；非空逐条给出「哪个检测器对未破坏输入也报检出」。
    恒真详情: list[str] = field(default_factory=list)

    @property
    def 通过数(self) -> int:
        return sum(1 for 证据 in self.证据列表 if 证据.验证结果)

    @property
    def 成功(self) -> bool:
        return self.通过数 == len(self.证据列表) and len(self.证据列表) == len(破坏场景表) and self.恒真检查


def _临时组件() -> Path:
    """构造一个可破坏的临时组件（能力契约 + 实现）。"""
    目录 = Path(tempfile.mkdtemp(prefix="反向破坏_"))
    (目录 / "能力契约").mkdir()
    (目录 / "实现").mkdir()
    (目录 / "能力契约" / "示例契约.json").write_text(json.dumps({
        "能力id": "示例.能力", "版本": "1.0.0", "说明": "反向破坏测试",
        "参数": [{"名称": "文本", "类型": "文本型", "必填": 真}],
        "返回": "普通返回", "错误码": ["参数不合法", "内部错误"],
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    (目录 / "实现" / "能力.py").write_text(
        '"""示例实现"""\n\ndef 能力(文本: str) -> dict:\n    if not 文本:\n        return {"成功": False, "错误码": "参数不合法"}\n    return {"成功": True, "值": {"长度": len(文本)}}\n',
        encoding="utf-8")
    return 目录


