    def _破坏客户端断开(self) -> 破坏证据:
        from 运行核心.统一网关.传输.流式HTTP import HTTP流式管理器
        管理器 = HTTP流式管理器()
        # 使用可停止的长生成器，确保断开动作发生在生产线程仍存活时；
        # 单元素生成器可能在断开调用前已完成并被管理器正常移除，导致
        # 测试把合法的终态清理误判为客户端断开未释放。
        def 生成(停止事件):
            while not 停止事件.wait(0.01):
                yield {"x": 1}

        通道 = 管理器.开始(能力id="破坏.流式", 事件生成函数=生成)
        管理器.断开(通道.请求id)
        # 修复恒真：真实检查资源释放（事件清空 + 通道移除），未释放必须真实失败
        事件已清空 = 通道.事件队列 == []
        通道已移除 = 通道.请求id not in 管理器.通道表
        验证失败 = 事件已清空 and 通道已移除
        return 破坏证据("客户端断开", "流式客户端断开", 验证失败,
                      资源释放=验证失败, 详情=f"事件清空:{事件已清空} 通道移除:{通道已移除}")

