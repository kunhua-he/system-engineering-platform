    def _破坏循环依赖(self) -> 破坏证据:
        """破坏：包1 与包2 互相依赖对方提供的能力，构造真实依赖环。

        生产接口 `解析依赖(声明列表, 能力提供者)` 先按「有无提供者」判定，
        不给提供者时只会报「缺失能力」、循环检测不触发；故必须同时给出能力
        提供者（元组语义 = (提供包id, 提供版本)），依赖项的键是「能力」。
        `解析结果` 的字段是 顺序列表/缺失能力/版本冲突/循环（无 问题列表）。
        断言同样分两步：无环对照必须解析成功（检测器不是恒红），有环输入必须
        报出环且解析失败（检测器不是恒绿）。
        """
        from 运行核心.加载器.依赖解析.解析器 import 解析依赖
