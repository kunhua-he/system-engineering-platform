class 破坏验证器:
    """反向破坏验证器：执行全部 13 种破坏并收集证据。"""

    def __init__(self) -> None:
        self.报告 = 破坏验证报告()

    def 执行(self) -> 破坏验证报告:
        """执行全部破坏场景。"""
        场景函数表 = [
            ("依赖锁篡改", self._破坏依赖锁篡改),
            ("完整性摘要篡改", self._破坏摘要篡改),
            ("参数类型修改", self._破坏参数类型),
            ("错误码删除", self._破坏错误码),
            ("实现文件删除", self._破坏实现删除),
            ("重复能力", self._破坏重复能力),
            ("循环依赖", self._破坏循环依赖),
            ("提供者崩溃", self._破坏提供者崩溃),
            ("任务超时", self._破坏任务超时),
            ("资源泄漏", self._破坏资源泄漏),
            ("新版本健康失败", self._破坏健康失败),
            ("客户端断开", self._破坏客户端断开),
            ("激活路由指向不存在版本", self._破坏路由不存在),
        ]
        for 名称, 函数 in 场景函数表:
            try:
                证据 = 函数()
            except Exception as 错误:
                # 异常 ≠ 检出。异常可能来自「被测系统拒绝了破坏」，也可能来自
                # 测试自身故障（函数名已改名、字段不存在），二者在异常对象里
                # 无法区分；把异常记成 True 等于用「跑没跑通」冒充「检出成功」，
                # 实测 13/13 里有 2 条正是这么蒙过去的。故这里一律记 验证结果
                # =False（报告立即变红），并保留 破坏方式/详情/检出方式 让它显眼。
                证据 = 破坏证据(场景名=名称, 破坏方式="执行异常", 验证结果=False,
                              详情=f"{type(错误).__name__}: {错误}", 检出方式="执行异常")
            self.报告.证据列表.append(证据)
        # 恒真检查（真对照）：13 项「全检出」不构成非恒真证据——一个恒真的
        # 验证器同样能全检出。必须拿**未破坏输入**再跑一遍同一批检测器：
        # 未破坏输入若也被报成检出，说明检测器恒真，相关场景的检出全是假的。
        self.报告.恒真详情 = self._恒真对照()
        self.报告.恒真检查 = not self.报告.恒真详情
        return self.报告

    def _恒真对照(self) -> list[str]:
        """正向对照：对「未破坏」输入跑同一批检测器，必须一条检出都不报。

        覆盖两个「检测器产出即结论」的场景（参数类型修改 / 错误码删除）；
        依赖锁篡改与循环依赖场景自带场景内对照组（控制组通过 / 无环对照通过）。
        边界如实说明：其余 9 个场景是「对被测系统施加一次性副作用后断言其响应」，
        本对照组不覆盖其断言恒真风险——不假装覆盖，只报真正验过的那部分。
        返回恒真事实清单：空 = 无恒真。
        """
        from 开发工具.契约编译.漂移检测 import 检测参数漂移, 检测错误码漂移

        目录 = _临时组件()
        入口 = 目录 / "能力契约" / "_入口.py"
        入口.write_text('def 能力(文本: str) -> dict:\n    return {}\n', encoding="utf-8")
        契约 = json.loads((目录 / "能力契约" / "示例契约.json").read_text(encoding="utf-8"))
        问题列表: list[str] = []
        参数漂移 = 检测参数漂移(契约, 入口)
        if 参数漂移 is not None:
            问题列表.append(f"参数漂移检测器对未破坏输入也报漂移（该场景检出恒真）: {参数漂移}")
        错误码漂移 = 检测错误码漂移(契约, 目录 / "实现" / "能力.py")
        if 错误码漂移:
            问题列表.append(f"错误码漂移检测器对未破坏输入也报漂移（该场景检出恒真）: {错误码漂移}")
        return 问题列表

    def _破坏依赖锁篡改(self) -> 破坏证据:
        """破坏：把真实依赖锁里某个包的版本改成 9.9.9，确认锁定校验真实检出。

        调用生产接口 `校验锁定文件(项目根目录, 系统根目录)`（原调的 `校验锁定`
        已不存在）。断言分两步，防止「校验器恒失败」也冒充检出：
          1. 控制组：按真实包声明生成的锁必须校验通过（校验器不是恒红）；
          2. 破坏组：只把该条目的版本改成 9.9.9，必须报出该包的版本漂移。
        """
        from 项目适配层.依赖锁定.锁定校验 import 校验锁定文件
        from 项目适配层.依赖锁定.依赖锁定 import (
            计算完整性摘要, 契约版本常量, 能力版本常量, 锁定版本常量,
        )
        from 运行核心.加载器.包发现.发现器 import 发现全部
        系统根目录 = _工程根目录()
        发现 = 发现全部(系统根目录 / "支持库", 系统根目录 / "模块库")
        if not 发现.成功:
            raise RuntimeError(f"包发现失败，无法基于真实系统构造依赖锁: {发现.问题列表}")
        无依赖声明 = sorted(
            (声明 for 声明 in 发现.声明列表 if not 声明.依赖),
            key=lambda 声明: 声明.包id,
        )
        if not 无依赖声明:
            raise RuntimeError("系统根目录下没有无依赖包，无法构造可校验的真实依赖锁")
        声明 = 无依赖声明[0]
        锁定条目 = {
            "包id": 声明.包id,
            "版本": 声明.版本,
            "类型": 声明.类型,
            "契约版本": 契约版本常量,
            "能力版本": 能力版本常量,
            "完整性摘要": 计算完整性摘要(声明),
            "依赖顺序": 0,
        }
        项目根目录 = Path(tempfile.mkdtemp(prefix="破坏依赖锁_"))
        锁路径 = 项目根目录 / "依赖锁定.json"

        def 写锁(条目: dict[str, Any]) -> None:
            锁路径.write_text(json.dumps({
                "锁定版本": 锁定版本常量, "项目id": "反向破坏验证",
                "生成时间": "", "包列表": [条目],
            }, ensure_ascii=False, indent=2), encoding="utf-8")

        写锁(锁定条目)
        控制结果 = 校验锁定文件(项目根目录, 系统根目录)
        写锁({**锁定条目, "版本": "9.9.9"})
        破坏结果 = 校验锁定文件(项目根目录, 系统根目录)
        漂移命中 = any(漂移.startswith(f"版本漂移: {声明.包id} ") for 漂移 in 破坏结果.漂移列表)
        验证失败 = 控制结果.成功 and not 破坏结果.成功 and 漂移命中
        return 破坏证据("依赖锁篡改", f"依赖锁定.json 把 {声明.包id} 版本改为 9.9.9",
                      验证失败, 发布阻断=not 破坏结果.成功, 证据保留=True,
                      详情=f"控制组(真实锁)通过:{控制结果.成功}；"
                          f"破坏组漂移:{'；'.join(破坏结果.漂移列表) or '未检出'}")

