def _合并基线键表(汇总: dict[str, Any]) -> dict[str, set[str]]:
    """把扫描结果里各维度的键表合并成 包相对路径 → {`维度|条目键`}（生成/收缩共用）。

    两个来源的键形态**同构**（都带 `维度|` 前缀，见 `_记漏声明` 与 `_全仓注册口径扫描`
    的实现默认值分支），故此处只做集合合并；`维度|条目键` 的拆分只在消费端做一次。
    """
    合并: dict[str, set[str]] = {}
    for 来源 in (汇总["漏声明键表"], 汇总["实现默认值键表"]):
        for 包相对路径, 键集 in 来源.items():
            合并.setdefault(包相对路径, set()).update(键集)
    return 合并
def 生成存量基线(系统根: Path) -> dict[str, Any]:
    """按当前仓库实测**重建**基线（仅用于首次初始化；日常只允许 收缩存量基线）。

    登记 `基线维度表` 的全部维度：两个漏声明维度 + 实现默认值差异（2026-09-23 升格为
    债务冻结）。默认值/必填**硬不一致**实测存量 0，故不设豁免——一旦出现就应直接判红，
    登记进基线等于给自己发免死牌。
    """
    汇总 = _全仓注册口径扫描(系统根, None, 含实现默认值=True)
    维度: dict[str, dict[str, list[str]]] = {名: {} for 名 in 基线维度表}
    for 包相对路径, 键集 in sorted(_合并基线键表(汇总).items()):
        for 键 in sorted(键集):
            维度名, _, 条目键 = 键.partition("|")
            if 维度名 in 维度:
                维度[维度名].setdefault(包相对路径, []).append(条目键)
    return {
        "版本": 存量基线版本,
        "说明": ("注册口径存量基线（只减不增）：基线命中=存量（只报）；基线外=新增（判红）；"
                 "无基线时新判据整批降级为只报。默认值/必填**硬不一致不设基线**（实测存量 0）。"
                 "`实现默认值差异` 维度（2026-09-23 加）同为债务冻结：存量只报、新增判红。"),
        "生成口径": "包×能力×参数 条目数；条目键 = 能力id#参数名",
        "条目数": {名: sum(len(列表) for 列表 in 维度[名].values()) for 名 in 基线维度表},
        "维度": 维度,
    }
def _键去值指纹(键: str) -> str:
    """把「实现默认值差异」维度的键降为 `包|维度|能力id#参数名`（其余维度的键原样返回）。

    用途：区分「**同一对参数的默认值变了**」与「新出现一对参数不一致」——两者都拒绝纳入，
    但给人工的措辞与后续动作不同（前者是「有人改了已公布的默认值，来看一眼」，后者是
    「冒出一处新的不一致」）。只有实现默认值维度的键带值指纹，故只对它降级。
    """
    包, 分隔, 剩余 = 键.partition("|")
    维度名, 分隔2, 条目键 = 剩余.partition("|")
    if 分隔2 and 维度名 == 实现默认值维度:
        段 = 条目键.split("#", 2)
        if len(段) == 3:
            条目键 = f"{段[0]}#{段[1]}"
    return f"{包}|{维度名}|{条目键}" if 分隔2 else 键
def 收缩存量基线(系统根: Path, 基线文件: Path, *, 写盘: bool = False) -> dict[str, Any]:
    """基线**只减不增**：删掉已消解的项，并**拒绝**把新出现的不一致纳入基线。

    返回 {新基线, 已删除, 拒绝纳入, 值变更, 写盘}。`拒绝纳入` 非空即说明仓库里出现了新的
    不一致（那本该判红）——不能靠「重建基线」一键洗白，要洗白必须先在源码里改对。
    `值变更` 是 `拒绝纳入` 的子集：键的「能力id#参数名」与基线里某条相同、只是两侧默认值
    变了（指纹含值，见 检测实现默认值差异）——它同样是拒绝纳入，只是人工该看的重点不同。
    """
    旧 = 读取存量基线(基线文件)
    汇总 = _全仓注册口径扫描(系统根, None, 含实现默认值=True)
    实测 = _合并基线键表(汇总)
    旧维度 = (旧 or {}).get("维度", {}) or {}
    新维度: dict[str, dict[str, list[str]]] = {名: {} for 名 in 基线维度表}
    已删除: list[str] = []
    for 维度名 in 基线维度表:
        for 包相对路径, 条目列表 in sorted((旧维度.get(维度名, {}) or {}).items()):
            实测键 = 实测.get(包相对路径, set())
            for 键 in 条目列表:
                if f"{维度名}|{键}" in 实测键:
                    新维度[维度名].setdefault(包相对路径, []).append(键)
                else:
                    已删除.append(f"{包相对路径}: {维度名} {键}")
    旧键全 = {f"{包}|{维度名}|{条目键}" for 维度名 in 基线维度表
             for 包, 列表 in (旧维度.get(维度名, {}) or {}).items() for 条目键 in 列表}
    实测键全 = {f"{包}|{键}" for 包, 键集 in 实测.items() for 键 in 键集}
    基线包数 = len({包 for 维度名 in 基线维度表
                 for 包 in (旧维度.get(维度名, {}) or {})})
    # 防呆：基线覆盖的是「全仓」，对局部树（包数少于基线登记的包数）不许写盘——
    # 否则对某个局部系统根跑一次收缩，就会把「本根里没有的包」整片判成已消解而删光基线。
    拒绝写盘 = ""
    if 写盘 and 汇总["包数"] < 基线包数:
        拒绝写盘 = (f"系统根只扫到 {汇总['包数']} 个包 < 基线登记的 {基线包数} 个包，"
                  "疑似局部树：拒绝写盘（仅返回收缩结果供人工核对）")
    新基线 = {
        "版本": 存量基线版本,
        "说明": 旧.get("说明", "") if 旧 else "注册口径存量基线（只减不增）",
        "生成口径": 旧.get("生成口径", "包×能力×参数 条目数；条目键 = 能力id#参数名") if 旧 else
                    "包×能力×参数 条目数；条目键 = 能力id#参数名",
        "条目数": {名: sum(len(列表) for 列表 in 新维度[名].values()) for 名 in 基线维度表},
        "维度": 新维度,
    }
    if 写盘 and not 拒绝写盘:
        写入存量基线(基线文件, 新基线)
    拒绝纳入 = sorted(实测键全 - 旧键全)
    旧参数对 = {_键去值指纹(键) for 键 in 旧键全}
    return {"新基线": 新基线, "已删除": sorted(已删除),
            "拒绝纳入": 拒绝纳入,
            "值变更": [键 for 键 in 拒绝纳入 if _键去值指纹(键) in 旧参数对],
            "拒绝写盘": 拒绝写盘, "写盘": bool(写盘 and not 拒绝写盘)}
