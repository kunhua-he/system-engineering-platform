def _制品指针(制品仓库根: Path) -> tuple[str, Path]:
    """读 当前.json，返回 (摘要, 激活制品目录)。"""
    指针文件 = 制品仓库根 / 制品指针文件名
    if not 指针文件.is_file():
        raise 判定错误(错误码_基线制品指针缺失,
                     f"激活制品指针不存在：{指针文件}（fail-closed：不得当无变化放行）")
    指针 = _读JSON(指针文件)
    制品名 = str(指针.get("路径", "") or "")
    if not 制品名:
        摘要 = str(指针.get("摘要sha256", "") or "")
        if 摘要:
            制品名 = f"平台客户端-{摘要}"
        else:
            raise 判定错误(错误码_基线制品指针缺失, f"激活制品指针缺 路径：{指针文件}")
    制品目录 = 制品仓库根 / 制品名
    if not 制品目录.is_dir():
        raise 判定错误(错误码_基线制品目录缺失, f"激活制品目录不存在：{制品目录}")
    return str(指针.get("摘要sha256", "") or ""), 制品目录


def _定位基线包(包目录: Path, 项目根: Path, 制品仓库根: Path,
                基线包目录: Path | None) -> tuple[Path, str]:
    """定位基线包（当前激活制品内同名包，或显式基线目录），返回 (基线包目录, 基线来源)。"""
    if 基线包目录 is not None:
        基线包目录 = Path(基线包目录)
        if (基线包目录 / 能力定义文件名).is_file() or (基线包目录 / 参数契约相对路径).is_file():
            return 基线包目录, f"显式基线包目录 {基线包目录}"
        # 兼容「传制品目录」的写法：制品目录/平台客户端/<包相对路径>
        try:
            相对路径 = 包目录.resolve().relative_to(项目根.resolve())
        except ValueError:
            raise 判定错误(错误码_基线包缺失,
                         f"基线包目录既不是包目录（缺 {能力定义文件名} 与 {参数契约相对路径}），"
                         f"又无法从 {包目录} 推导包相对路径：{基线包目录}") from None
        候选 = 基线包目录 / 制品内源码根名 / 相对路径
        if 候选.is_dir():
            return 候选, f"显式基线制品目录 {基线包目录} 内同名包 {相对路径}"
        raise 判定错误(错误码_基线包缺失,
                     f"基线包不存在：{候选}（fail-closed：不得当无变化放行）")

    try:
        相对路径 = 包目录.resolve().relative_to(项目根.resolve())
    except ValueError:
        raise 判定错误(
            错误码_基线包缺失,
            f"包目录不在项目根内，无法推导激活制品内同名包：{包目录}（请显式传 基线包目录）",
        ) from None
    摘要, 制品目录 = _制品指针(制品仓库根)
    候选 = 制品目录 / 制品内源码根名 / 相对路径
    if not 候选.is_dir():
        raise 判定错误(错误码_基线包缺失,
                     f"激活制品 {制品目录.name} 内无同名包：{相对路径}（fail-closed：不得当无变化放行）")
    return 候选, (f"激活制品 {制品目录.name}（当前.json 摘要 {摘要}）内同名包 {相对路径}")


