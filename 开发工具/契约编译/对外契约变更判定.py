# ---------------- 规范化（同一指纹函数 + 规范化输入；绝不另写第二套算法）----------------


def _是文档形态(值: Any) -> bool:
    """值是否「纯文档形态」：文本 / 空 / 纯文本映射（字典且所有叶子都是文档形态）。

    硬保守的第二道闸：即便键在文档键表里，**值不是文档形态就保留**——宁可把变化算严
    （判契约变化），也不把结构性取值当文案剔除掉。列表 / 数字 / 布尔一律不是文档形态
    （`返回.值结构` 里出现过 bool 叶子，这类条目会整条留在契约面内）。
    """
    if 值 is None or isinstance(值, str):
        return 真
    if isinstance(值, dict):
        return all(_是文档形态(子值) for 子值 in 值.values())
    return 假


def 规范化契约面(契约: dict[str, Any]) -> dict[str, Any]:
    """把归一化契约里的**纯文档字段**剔除，得到「对外契约面」——喂给**同一个** `契约指纹()`。

    剔除范围（硬保守，见 `文档键_参数条目` / `文档键_返回`）：参数条目的 `说明`、返回的 `值结构`。
    其余一律保留（`上限` 是约束、`副作用`/`资源类型`/`宿主`/`权限` 是 0020 的对外契约维度）。
    不修改入参（浅拷贝 + 重建 参数/返回 两个容器）。
    """
    面 = dict(契约)
    参数表 = 面.get("参数")
    if isinstance(参数表, list):
        面["参数"] = [
            {键: 值 for 键, 值 in 项.items()
             if not (键 in 文档键_参数条目 and _是文档形态(值))} if isinstance(项, dict) else 项
            for 项 in 参数表
        ]
    返回表 = 面.get("返回")
    if isinstance(返回表, dict):
        面["返回"] = {键: 值 for 键, 值 in 返回表.items()
                    if not (键 in 文档键_返回 and _是文档形态(值))}
    return 面


