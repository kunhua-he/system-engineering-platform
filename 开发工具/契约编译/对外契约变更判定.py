class 判定错误(Exception):
    """判定链路上不可继续的错误（一律 fail-closed，不静默放行）。"""

    def __init__(self, 错误码: str, 错误说明: str) -> None:
        super().__init__(错误说明)
        self.错误码 = 错误码
        self.错误说明 = 错误说明


@dataclass
class 包契约读数:
    """一侧（源码侧或基线侧）的对外契约读数。"""

    包目录: Path
    契约文件: Path
    包版本: str
    说明: str
    能力表: dict[str, dict[str, Any]] = field(default_factory=dict)   # 能力id → 归一化对外契约
    能力版本表: dict[str, str] = field(default_factory=dict)          # 能力id → 该能力版本号

    def 指纹表(self) -> dict[str, str]:
        """逐能力对外契约指纹（唯一事实源 契约指纹() 产出）。"""
        return {能力id: 契约指纹(契约) for 能力id, 契约 in sorted(self.能力表.items())}


# ---------------- 统一结果信封 ----------------


def 错误信封(错误码: str, 错误说明: str) -> dict[str, Any]:
    """统一结果信封（错误路径）：成功/值/错误码/错误说明。"""
    return {"成功": False, "值": None, "错误码": 错误码, "错误说明": 错误说明}


def 是失败结果(结果: dict[str, Any]) -> bool:
    """结果是否为错误信封（供门禁判红）。"""
    return 结果.get("成功") is False and "变更类别" not in 结果


def 判定并包装(结果: dict[str, Any]) -> dict[str, Any]:
    """把固定结构结果包成统一信封：成功 → 值为固定结构；失败原样返回。"""
    if 是失败结果(结果):
        return 结果
    return {"成功": True, "值": 结果, "错误码": "", "错误说明": ""}


# ---------------- 读取与归一化 ----------------


def _读JSON(路径: Path) -> dict[str, Any]:
    try:
        数据 = json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError) as 异常:
        raise 判定错误(错误码_契约文件不可读, f"契约文件读不到：{路径}（{异常}）") from 异常
    except json.JSONDecodeError as 异常:
        raise 判定错误(错误码_契约结构非法, f"契约文件不是合法 JSON：{路径}（{异常}）") from 异常
    if not isinstance(数据, dict):
        raise 判定错误(错误码_契约结构非法, f"契约文件顶层不是对象：{路径}")
    return 数据


def 归一化能力契约(原始能力: dict[str, Any], 权限表: dict[str, Any]) -> dict[str, Any]:
    """把 能力定义.json / 能力契约/参数契约.json 的能力条目归一化成 `契约指纹()` 的入参形状。

    只取 0020 列明的对外契约维度：参数 / 返回 / 错误码 / 副作用 / 资源类型 / 宿主 / 权限（含能力对外名）。
    副作用在能力条目里位于 `行为.副作用`；权限取自 `权限契约/权限契约.json` 的 `允许用户`。
    （包级 `只读` / `写路径` 不属于 0020 的七维，不入指纹。）
    """
    能力id = str(原始能力.get("能力id") or "")
    行为 = 原始能力.get("行为") or {}
    if not isinstance(行为, dict):
        行为 = {}
    权限项 = 权限表.get(能力id) or {}
    if not isinstance(权限项, dict):
        权限项 = {}
    return {
        "能力id": 能力id,
        # 对外名：能力定义.json 用 中文名称；参数契约.json 两种写法都有
        "名称": 原始能力.get("中文名称") or 原始能力.get("名称") or "",
        "参数": 原始能力.get("参数", []),
        "返回": 原始能力.get("返回", {}),
        "错误码": 原始能力.get("错误码", []),
        "副作用": 原始能力.get("副作用", "") or 行为.get("副作用", ""),
        "资源类型": 原始能力.get("资源类型", ""),
        "宿主": 原始能力.get("宿主", ""),
        "权限": 权限项.get("允许用户", ""),
    }


def 读取包契约(包目录: Path) -> 包契约读数:
    """读一侧包的对外契约；两端任一读不到即 fail-closed（抛 判定错误）。"""
    包目录 = Path(包目录)
    if not 包目录.is_dir():
        raise 判定错误(错误码_新包目录不存在, f"包目录不存在：{包目录}")
    定义文件 = 包目录 / 能力定义文件名
    契约文件 = 包目录 / 参数契约相对路径
    if 定义文件.is_file():
        源文件 = 定义文件
        数据 = _读JSON(源文件)
        原始能力表 = 数据.get("能力列表")
        包版本 = str(数据.get("版本", "") or "")
        说明 = str(数据.get("说明", "") or "")
        能力列表键 = "能力列表"
    elif 契约文件.is_file():
        源文件 = 契约文件
        数据 = _读JSON(源文件)
        原始能力表 = 数据.get("能力契约")
        包版本 = str(数据.get("包版本", "") or "")
        说明 = str(数据.get("说明", "") or "")
        能力列表键 = "能力契约"
    else:
        raise 判定错误(
            错误码_契约文件缺失,
            f"两端都读不到契约：{包目录}（既无 {能力定义文件名} 也无 {参数契约相对路径}）"
            "——fail-closed，不得当无变化放行",
        )
    if not isinstance(原始能力表, list):
        raise 判定错误(错误码_契约结构非法, f"{源文件} 缺 {能力列表键} 表或不是列表")

    权限契约文件 = 包目录 / 权限契约相对路径
    权限表: dict[str, Any] = {}
    if 权限契约文件.is_file():
        权限数据 = _读JSON(权限契约文件)
        for 键, 值 in 权限数据.items():
            if isinstance(值, dict) and "允许用户" in 值:
                权限表[键] = 值

    能力表: dict[str, dict[str, Any]] = {}
    能力版本表: dict[str, str] = {}
    for 项 in 原始能力表:
        if not isinstance(项, dict):
            raise 判定错误(错误码_契约结构非法, f"{源文件} 能力条目不是对象")
        能力id = str(项.get("能力id") or "")
        if not 能力id:
            raise 判定错误(错误码_契约结构非法, f"{源文件} 存在缺 能力id 的能力条目")
        if 能力id in 能力表:
            raise 判定错误(错误码_契约结构非法, f"{源文件} 能力id 重复：{能力id}")
        能力表[能力id] = 归一化能力契约(项, 权限表)
        能力版本表[能力id] = str(项.get("版本", "") or "")
    return 包契约读数(包目录=包目录, 契约文件=源文件, 包版本=包版本, 说明=说明,
                     能力表=能力表, 能力版本表=能力版本表)


def 包级兼容契约(读数: 包契约读数, 能力id: str | None = None) -> dict[str, Any]:
    """组装 `检查契约兼容()` 的入参：{"能力": [{能力id, 参数, 返回}], "错误码": [...], "说明": ...}。

    包级＝包内全部能力集合（含新增/删除能力）；能力级＝单个能力。
    """
    if 能力id is None:
        条目表 = [读数.能力表[键] for 键 in sorted(读数.能力表)]
    else:
        条目表 = [读数.能力表[能力id]] if 能力id in 读数.能力表 else []
    错误码 = sorted({str(码) for 契约 in 条目表 for 码 in 契约.get("错误码", [])})
    return {
        "能力": [{"能力id": 契约["能力id"], "参数": 契约["参数"], "返回": 契约["返回"]}
                 for 契约 in 条目表],
        "错误码": 错误码,
        "说明": 读数.说明 if 能力id is None else "",
    }


# ---------------- 变化明细（人读证据，不参与判据） ----------------


def _短(值: Any, 上限: int = 120) -> str:
    文本 = 值 if isinstance(值, str) else json.dumps(值, ensure_ascii=False, default=str)
    return 文本 if len(文本) <= 上限 else 文本[:上限] + "…"


def 逐项变化明细(能力id: str, 旧契约: dict[str, Any], 新契约: dict[str, Any]) -> list[str]:
    """逐字段列出某一能力的对外契约差异（仅供人读；判据是 契约指纹() 与 检查契约兼容()）。"""
    明细: list[str] = []

    if 旧契约.get("名称") != 新契约.get("名称"):
        明细.append(f"对外名称变化（能力 {能力id}）：{_短(旧契约.get('名称'))} → {_短(新契约.get('名称'))}")

    旧参表 = {p.get("名称"): p for p in 旧契约.get("参数", []) if isinstance(p, dict)}
    新参表 = {p.get("名称"): p for p in 新契约.get("参数", []) if isinstance(p, dict)}
    for 参数名 in 旧参表:
        if 参数名 not in 新参表:
            明细.append(f"删除参数（能力 {能力id}）：{参数名}")
    for 参数名 in 新参表:
        if 参数名 not in 旧参表:
            明细.append(f"新增参数（能力 {能力id}）：{参数名}")
    for 参数名 in 旧参表:
        if 参数名 not in 新参表:
            continue
        旧参, 新参 = 旧参表[参数名], 新参表[参数名]
        for 字段 in 参数字段表:
            if 旧参.get(字段) != 新参.get(字段):
                明细.append(f"参数{字段}变化（能力 {能力id}·{参数名}）："
                           f"{_短(旧参.get(字段))} → {_短(新参.get(字段))}")

    if 旧契约.get("返回") != 新契约.get("返回"):
        明细.append(f"返回结构变化（能力 {能力id}）："
                   f"{_短(旧契约.get('返回'))} → {_短(新契约.get('返回'))}")

    旧码集, 新码集 = set(旧契约.get("错误码", [])), set(新契约.get("错误码", []))
    for 码 in sorted(旧码集 - 新码集):
        明细.append(f"删除错误码（能力 {能力id}）：{码}")
    for 码 in sorted(新码集 - 旧码集):
        明细.append(f"新增错误码（能力 {能力id}）：{码}")

    for 字段 in ("副作用", "资源类型", "宿主", "权限"):
        if 旧契约.get(字段) != 新契约.get(字段):
            明细.append(f"{字段}变化（能力 {能力id}）："
                       f"{_短(旧契约.get(字段))} → {_短(新契约.get(字段))}")
    return 明细


# ---------------- 版本判定 ----------------


def _版本元组(版本: str) -> tuple[int, ...] | None:
    数字表 = re.findall(r"\d+", str(版本))
    if not 数字表:
        return None
    数字表 = 数字表[:3]
    while len(数字表) < 3:
        数字表.append("0")
    return tuple(int(数字) for 数字 in 数字表)


def 判定版本递增(基线版本: str, 新版本: str) -> tuple[bool, str]:
    """版本是否已合法递增：返回 (是否递增, 版本判定说明)。"""
    if not 基线版本 or not 新版本:
        return False, "版本号缺失"
    旧元, 新元 = _版本元组(基线版本), _版本元组(新版本)
    if 旧元 is None or 新元 is None:
        return False, "版本号格式非法"
    if 新元 > 旧元:
        return True, "版本已递增"
    if 新元 == 旧元:
        return False, "版本未递增"
    return False, "版本回退"


