def 判定对外契约变更(包目录: str | Path, *, 基线包目录: str | Path | None = None,
                制品仓库根: str | Path | None = None, 项目根: str | Path | None = None,
                能力id: str | None = None) -> dict[str, Any]:
    """包级（能力id=None）或能力级（能力id 非空）对外契约变更判定。

    参数：
    - 包目录：新侧（源码包或 /tmp 副本）包目录；相对路径按 项目根 解析。
    - 基线包目录：显式基线包目录（或制品目录）；缺省＝当前激活制品内同名包。
    - 制品仓库根：缺省 项目根/工程缓存/制品仓库/平台客户端制品。
    - 项目根：缺省本文件上溯两级。
    - 能力id：给了就做能力级判定（单个能力对外契约指纹对比），不给就做包级判定
      （包内全部能力集合对比，新增/删除能力也算契约变化）。

    返回：成功＝固定结构（恰好 5 键）；失败＝统一结果信封（中文错误码）。
    """
    项目根 = Path(项目根) if 项目根 is not None else 默认项目根
    制品仓库根 = Path(制品仓库根) if 制品仓库根 is not None else 项目根 / 制品仓库相对路径
    包目录 = Path(包目录) if Path(包目录).is_absolute() else 项目根 / 包目录

    try:
        if 能力id is not None and not str(能力id).strip():
            raise 判定错误(错误码_参数不合法, "能力id 为空：能力级判定必须给具体能力id")
        新读数 = 读取包契约(包目录)
        基线定位, 来源说明 = _定位基线包(包目录, 项目根, 制品仓库根,
                                       None if 基线包目录 is None else Path(基线包目录))
        基线读数 = 读取包契约(基线定位)
    except 判定错误 as 错误:
        return 错误信封(错误.错误码, 错误.错误说明)

    if 能力id is None:
        结果 = _判定包级(基线读数, 新读数, _基线来源全称(来源说明, 基线读数))
    else:
        结果 = _判定能力级(基线读数, 新读数, str(能力id), _基线来源全称(来源说明, 基线读数))
    if isinstance(结果, dict) and 是失败结果(结果):
        return 结果
    return 结果


def 判定能力对外契约变更(包目录: str | Path, 能力id: str, **选项: Any) -> dict[str, Any]:
    """能力级判定（单个能力对外契约指纹对比）的显式入口。"""
    return 判定对外契约变更(包目录, 能力id=能力id, **选项)


def _分类变化(共有能力: list[str], 基线原始指纹表: dict[str, str], 新原始指纹表: dict[str, str],
           基线契约面指纹表: dict[str, str], 新契约面指纹表: dict[str, str],
           ) -> tuple[list[str], list[str], list[str]]:
    """共有能力分三类（唯一分类口径，判据只有「契约面指纹是否变化」一处）：

    - 原始指纹变化能力：`契约指纹(参数对象整体)` 变了（保留给人看，说明文案变化也命中）；
    - 契约面变化能力：`契约指纹(规范化契约面)` 变了 —— **要求递增版本只看这一张**；
    - 文档性变化能力：原始变了但契约面没变 ⇒ 只动了被剔除的纯文档字段（参数说明 / 返回值结构）。
    """
    原始变化 = [能力 for 能力 in 共有能力 if 基线原始指纹表[能力] != 新原始指纹表[能力]]
    契约面变化 = [能力 for 能力 in 共有能力 if 基线契约面指纹表[能力] != 新契约面指纹表[能力]]
    文档性变化 = [能力 for 能力 in 原始变化 if 能力 not in set(契约面变化)]
    return 原始变化, 契约面变化, 文档性变化


def _判定包级(基线读数: 包契约读数, 新读数: 包契约读数, 来源说明: str) -> dict[str, Any]:
    基线原始指纹表 = 基线读数.指纹表()
    新原始指纹表 = 新读数.指纹表()
    基线契约面指纹表 = 基线读数.契约面指纹表()
    新契约面指纹表 = 新读数.契约面指纹表()
    新增能力 = sorted(set(新原始指纹表) - set(基线原始指纹表))
    删除能力 = sorted(set(基线原始指纹表) - set(新原始指纹表))
    共有能力 = sorted(set(基线原始指纹表) & set(新原始指纹表))
    原始指纹变化能力, 契约面变化能力, 文档性变化能力 = _分类变化(
        共有能力, 基线原始指纹表, 新原始指纹表, 基线契约面指纹表, 新契约面指纹表)

    明细: list[str] = []
    for 能力 in 新增能力:
        明细.append(f"新增能力（新增对外面，能力 {能力}）：基线无此能力，"
                   f"新契约面指纹 {新契约面指纹表[能力]}（原始指纹 {新原始指纹表[能力]}）")
    for 能力 in 删除能力:
        明细.append(f"删除能力（能力 {能力}）：基线契约面指纹 {基线契约面指纹表[能力]}"
                   f"（原始指纹 {基线原始指纹表[能力]}），新侧已无此能力")
    for 能力 in 契约面变化能力:
        明细.append(f"契约面变化（要求递增，能力 {能力}）：原始指纹 {基线原始指纹表[能力]} → "
                   f"{新原始指纹表[能力]}；契约面指纹 {基线契约面指纹表[能力]} → {新契约面指纹表[能力]}")
        明细.extend(逐项变化明细(能力, 规范化契约面(基线读数.能力表[能力]),
                              规范化契约面(新读数.能力表[能力])))
    for 能力 in 文档性变化能力:
        明细.append(f"文档性变化（不要求递增，能力 {能力}）：原始指纹 {基线原始指纹表[能力]} → "
                   f"{新原始指纹表[能力]}，但契约面指纹 {基线契约面指纹表[能力]} 未变"
                   f"（剔除字段：{'、'.join(文档字段清单)}）")
        明细.extend(文档字段变化明细(能力, 基线读数.能力表[能力], 新读数.能力表[能力]))

    契约面变化 = bool(新增能力 or 删除能力 or 契约面变化能力)
    兼容结果 = 检查契约兼容(包级兼容契约(基线读数), 包级兼容契约(新读数)).转字典()
    变更类别 = (变更类别_契约变化 if (契约面变化 or 兼容结果["结论"] != "兼容")
              else 变更类别_内部优化)

    明细, 要求递增, 版本块 = _版本收口(变更类别, 基线读数.包版本, 新读数.包版本, 明细,
                                   包级=True, 仅文档性变化=bool(文档性变化能力))
    return _组装(变更类别, 明细, 要求递增, 兼容结果, 版本块, 来源说明,
                基线原始指纹表, 新原始指纹表, 基线契约面指纹表, 新契约面指纹表,
                原始指纹变化能力, 契约面变化能力, 文档性变化能力,
                新增能力, 删除能力, 对比能力数=len(共有能力))


def _判定能力级(基线读数: 包契约读数, 新读数: 包契约读数, 能力id: str,
             来源说明: str) -> dict[str, Any]:
    基线表, 新表 = 基线读数.能力表, 新读数.能力表
    if 能力id not in 基线表:
        return 错误信封(错误码_基线能力不存在,
                     f"基线包内无此能力：{能力id}（{基线读数.契约文件}）"
                     "——fail-closed：不得当无变化放行（新增能力请走包级判定）")
    明细: list[str] = []
    基线指纹 = 契约指纹(基线表[能力id])
    基线契约面指纹 = 契约面指纹(基线表[能力id])
    新侧存在 = 能力id in 新表
    新指纹 = 契约指纹(新表[能力id]) if 新侧存在 else None
    新契约面指纹 = 契约面指纹(新表[能力id]) if 新侧存在 else None
    原始指纹变化 = 基线指纹 != 新指纹
    契约面变化 = 基线契约面指纹 != 新契约面指纹
    文档性变化 = 原始指纹变化 and not 契约面变化
    if 新侧存在 and 契约面变化:
        明细.append(f"契约面变化（要求递增，能力 {能力id}）：原始指纹 {基线指纹} → {新指纹}；"
                   f"契约面指纹 {基线契约面指纹} → {新契约面指纹}")
        明细.extend(逐项变化明细(能力id, 规范化契约面(基线表[能力id]),
                              规范化契约面(新表[能力id])))
    elif 新侧存在 and 文档性变化:
        明细.append(f"文档性变化（不要求递增，能力 {能力id}）：原始指纹 {基线指纹} → {新指纹}，"
                   f"但契约面指纹 {基线契约面指纹} 未变（剔除字段：{'、'.join(文档字段清单)}）")
        明细.extend(文档字段变化明细(能力id, 基线表[能力id], 新表[能力id]))
    elif not 新侧存在:
        明细.append(f"删除能力（能力 {能力id}）：基线契约面指纹 {基线契约面指纹}"
                   f"（原始指纹 {基线指纹}），新侧已无此能力")

    基线版本 = 基线读数.能力版本表.get(能力id, "") or 基线读数.包版本
    新版本 = (新读数.能力版本表.get(能力id, "") or 新读数.包版本) if 新侧存在 else ""
    兼容结果 = 检查契约兼容(包级兼容契约(基线读数, 能力id),
                         包级兼容契约(新读数, 能力id)).转字典()
    变更类别 = (变更类别_契约变化 if (契约面变化 or 兼容结果["结论"] != "兼容")
              else 变更类别_内部优化)

    明细, 要求递增, 版本块 = _版本收口(变更类别, 基线版本, 新版本, 明细,
                                   包级=False, 仅文档性变化=文档性变化)
    return _组装(变更类别, 明细, 要求递增, 兼容结果, 版本块, 来源说明,
                {能力id: 基线指纹}, {能力id: 新指纹} if 新侧存在 else {},
                {能力id: 基线契约面指纹},
                {能力id: 新契约面指纹} if 新侧存在 else {},
                [能力id] if 原始指纹变化 else [], [能力id] if 契约面变化 else [],
                [能力id] if 文档性变化 else [],
                [], [] if 新侧存在 else [能力id], 对比能力数=1)


def _版本收口(变更类别: str, 基线版本: str, 新版本: str, 明细: list[str],
           包级: bool, *, 仅文档性变化: bool = False) -> tuple[list[str], bool, dict[str, Any]]:
    """把「变更类别 + 版本号」收口成 是否要求版本递增（0020 的唯一口径）。"""
    是否递增, 版本判定 = 判定版本递增(基线版本, 新版本)
    if 变更类别 == 变更类别_契约变化:
        要求递增 = not 是否递增
        if 是否递增:
            明细.append(f"版本已递增合法：{基线版本} → {新版本}"
                       f"（{'包级' if 包级 else '能力级'}契约变化已由版本递增承载，放行）")
        else:
            明细.append(f"契约变化但{版本判定}：{基线版本 or '（缺）'} → {新版本 or '（缺）'}"
                       f"（必须递增版本；旧版本按 版本注册表 引用保护保留，无引用才允许清理）")
    else:
        要求递增 = False
        版本说明 = f"版本 {基线版本} → {新版本}" if 基线版本 or 新版本 else "无版本号"
        仅文档 = ("仅文档性字段（" + "、".join(文档字段清单) + "）变化，"
                 if 仅文档性变化 else "")
        明细.append("对外契约面（参数名称/类型/必填/默认值＋返回类型＋错误码集合＋"
                   f"副作用/资源类型/宿主/权限）指纹逐字相同：{仅文档}纯内部优化，"
                   f"允许直接更新，不要求版本递增（{版本说明}，"
                   "也不要求说明书版本行同步）")
    版本块 = {"基线版本": 基线版本, "新增版本": 新版本,
            "版本判定": 版本判定, "是否递增": 是否递增}
    return 明细, 要求递增, 版本块


def _组装(变更类别: str, 明细: list[str], 要求递增: bool, 兼容结果: dict[str, Any],
        版本块: dict[str, Any], 来源说明: str, 基线原始指纹表: dict[str, Any],
        新原始指纹表: dict[str, Any], 基线契约面指纹表: dict[str, Any],
        新契约面指纹表: dict[str, Any], 原始指纹变化能力: list[str],
        契约面变化能力: list[str], 文档性变化能力: list[str], 新增能力: list[str],
        删除能力: list[str], *, 对比能力数: int) -> dict[str, Any]:
    """组装固定输出结构（恰好 5 键，供门禁直接消费；原始指纹与契约面指纹两个值都在里面）。"""
    兼容判定 = {
        "结论": 兼容结果["结论"],
        "原因": 兼容结果["原因"],
        "需要适配器": 兼容结果["需要适配器"],
        "必须升主版本": 兼容结果["必须升主版本"],
        # 判据＝契约面指纹是否变化；原始指纹只作对照与「文档性变化」识别
        "指纹是否变化": bool(契约面变化能力 or 新增能力 or 删除能力),
        "原始指纹是否变化": bool(原始指纹变化能力 or 新增能力 or 删除能力),
        "基线指纹": 基线原始指纹表,
        "新增指纹": 新原始指纹表,
        "基线契约面指纹": 基线契约面指纹表,
        "新增契约面指纹": 新契约面指纹表,
        "指纹变化能力": 原始指纹变化能力,
        "契约面变化能力": 契约面变化能力,
        "文档性变化能力": 文档性变化能力,
        "新增能力": 新增能力,
        "删除能力": 删除能力,
        "对比能力数": 对比能力数,
        "版本": 版本块,
        "判据来源": dict(判据来源),
        "指纹口径": 指纹口径说明(),
    }
    return {
        "变更类别": 变更类别,
        "变化明细": 明细,
        "是否要求版本递增": bool(要求递增),
        "兼容判定": 兼容判定,
        "基线来源": 来源说明,
    }
