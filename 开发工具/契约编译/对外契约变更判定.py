"""对外契约变更判定：版本递增判据＝对外契约指纹变化（设计哲学第 5 条 5.3 / 决策记录 0020）。

本模块是「版本递增判据＝对外契约指纹变化」的**唯一可调用判定模块**（新增文件，不改任何既有文件）。
门禁、说明书版本行对账、发布前核对一律调本模块，不得各自复写判据、不得人工判断。

## 判定规则（逐字遵循决策记录 0020，不自创第二套口径）

```
算本包（或本能力）的对外契约：参数 / 返回 / 错误码集合 / 副作用 / 资源类型 / 宿主 / 权限
        ↓ 用 契约指纹() 算指纹，并用 检查契约兼容() 判兼容
指纹不变（完全兼容） → 纯内部优化 / 性能 / 重构 / 改名（对外名不变）
                       → 允许直接更新，**不要求版本号递增**，也不要求说明书版本行同步
指纹变化（不兼容或有新增对外面） → **必须递增版本**（能力级 / 包级按实际变化范围）
                       → 旧版本按 版本注册表 引用保护保留；无引用才允许清理
```

## 唯一事实源（不另写第二套指纹算法）

- 指纹：`from 平台控制面.能力目录 import 契约指纹`（实现 `平台控制面/能力目录/服务.py:22 契约指纹()`，
  维度＝参数/返回/错误码/副作用/资源类型/宿主/权限 → sha256 前 16 位）；
- 兼容：`from 运行核心.加载器.版本系统.契约兼容 import 检查契约兼容`
  （实现同名文件 `:34`，返回 `兼容检查结果`）。
- 本模块**不重写**上述任一算法：指纹逐个由 `契约指纹()` 产出、兼容结论逐字取 `检查契约兼容().转字典()`。
  `变化明细` 只是逐字段的**人读证据**，不参与判据；判据只有「指纹是否变化」与「兼容结论」两处。
- 导入路径（实测最短可用路径）：
  - **源码布局（本模块运行所在）**：把项目根加入 `sys.path` 后
    `from 平台控制面.能力目录 import 契约指纹`、`from 运行核心.加载器.版本系统.契约兼容 import 检查契约兼容`；
  - **制品布局（实测）**：制品内 `平台客户端/平台控制面/__init__.py` 按 `平台客户端.平台控制面.…`
    自引用，须以**制品根**入 `sys.path` 才能导入（即 `制品根/平台客户端/...` 带 `平台客户端` 前缀）。
    本模块**不使用**该路径：基线侧只读制品内的契约 JSON（数据），不 import 制品内实现，
    以免出现「两份实现并存、当前实现是哪一份」的歧义（0020 裁决二）。

## 基线来源（不新建存储）

基线＝**当前激活制品**内的同名包：`工程缓存/制品仓库/平台客户端制品/当前.json` → 制品目录 →
制品内 `平台客户端/<包相对路径>` 的 `能力定义.json` / `能力契约/参数契约.json`；源码侧为「新」。
两端任一读不到即 **fail-closed 报错**（中文错误码），绝不当「无变化」放行。

## 输出（给后续门禁直接消费）

- 成功：固定结构 `{变更类别, 变化明细, 是否要求版本递增, 兼容判定, 基线来源}`
  （恰好这 5 个键；`变更类别` ∈ {内部优化, 契约变化}）；
- 失败：统一结果信封 `{成功: False, 值: None, 错误码, 错误说明}`（错误码全中文）。
  （信封键名按 0020 落地口径固定，与 `消费者契约注册表.统一返回` 的 {成功, 错误码, 消息, 数据}
  不是同一套装；本模块不改既有文件，故不覆盖那边。）
- 需要「永远信封」的调用方用 `判定并包装(结果)`：成功 → `{成功: True, 值: 固定结构, ...}`；
  失败原样返回。失败识别用 `是失败结果(结果)`。
"""

