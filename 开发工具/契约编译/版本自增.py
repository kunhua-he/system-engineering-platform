def _下一版本(版本: str, *, 升主: bool) -> tuple[str, str]:
    """算出下一版本：返回（新版本, 口径说明）。版本号不可解析时抛 ValueError（fail-closed）。"""
    组: list[int] = []
    for 段 in (版本 or "").split("."):
        段 = 段.strip()
        if not 段.isdigit():
            raise ValueError(f"版本号不可解析：{版本!r}（本模块只处理纯数字点分版本）")
        组.append(int(段))
    if not 组:
        raise ValueError(f"版本号为空：{版本!r}")
    while len(组) < 3:
        组.append(0)
    if 升主:
        return f"{组[0] + 1}.0.0", f"不兼容变化（判据要求升主版本）：{版本} → {组[0] + 1}.0.0"
    return f"{组[0]}.{组[1]}.{组[2] + 1}", f"默认自增 1（补丁位）：{版本} → {组[0]}.{组[1]}.{组[2] + 1}"


def _替换顶层版本(定义路径: Path, 旧版本: str, 新版本: str) -> str:
    """算出替换后的文本（只替换文件里**第一处** `"版本": "<旧版本>"`，即顶层版本）。

    为什么用文本替换而不是 `json.dumps` 整份重写：整份重写会把文件里所有格式细节
    （缩进风格、键序以外的空白）一起刷掉，产生与本次改动无关的巨大 diff。
    第一处出现即顶层 —— `能力列表` 在它之后（实测全仓 142 份包定义同形制）；
    且 `"契约版本": "X"` 不含子串 `"版本": "X"`（`版本` 前是 `约` 不是 `"`），不会误伤。
    万一第一处不在顶层，`json.loads` 复核会当场发现并拒绝写盘（不猜）。
    """
    import json

    文本 = 定义路径.read_text(encoding="utf-8")
    旧串 = f'"版本": "{旧版本}"'
    if 文本.count(旧串) < 1:
        raise ValueError(f"文件里找不到 `{旧串}`（顶层版本载位缺失，不猜）")
    新文本 = 文本.replace(旧串, f'"版本": "{新版本}"', 1)
    复核 = json.loads(新文本)
    if str(复核.get("版本") or "") != 新版本:
        raise ValueError(f"替换后顶层版本复核不一致：期望 {新版本}，实得 {复核.get('版本')!r}")
    return 新文本


def 处理一个包(包目录: Path, *, 写盘: bool) -> dict:
    """判一个包要不要递增版本；写盘口径下就地递增。返回结构化结论。"""
    from 开发工具.契约编译.对外契约变更判定 import 判定对外契约变更

    出: dict = {"包目录": 包目录.as_posix(), "基线版本": "", "当前版本": "",
               "新版本": "", "口径": "", "动作": "", "问题": ""}
    try:
        结果 = 判定对外契约变更(包目录)
    except Exception as 错误:  # noqa: BLE001 —— fail-closed：判不出来绝不猜
        出["问题"] = f"契约变更判定失败（{type(错误).__name__}: {错误}）"
        出["动作"] = "未核验"
        return 出
    兼容 = 结果.get("兼容判定") or {}
    版本块 = 兼容.get("版本") or {}
    出["基线版本"] = str(版本块.get("基线版本") or "")
    出["当前版本"] = str(版本块.get("新增版本") or "")
    if not 结果.get("是否要求版本递增"):
        出["动作"] = "无需递增"
        return 出
    try:
        新版本, 口径 = _下一版本(出["当前版本"], 升主=bool(兼容.get("必须升主版本")))
    except ValueError as 错误:
        出["问题"] = str(错误)
        出["动作"] = "未核验"
        return 出
    出["新版本"], 出["口径"] = 新版本, 口径
    if not 写盘:
        出["动作"] = "待递增"
        return 出
    定义路径 = 包目录 / "能力定义.json"
    try:
        新文本 = _替换顶层版本(定义路径, 出["当前版本"], 新版本)
    except (OSError, ValueError) as 错误:
        出["问题"] = f"算出新文本失败（{type(错误).__name__}: {错误}）"
        出["动作"] = "未核验"
        return 出
    try:
        写入文件(str(定义路径), 新文本).确保成功()
    except (OSError, ValueError) as 错误:
        出["问题"] = f"写盘失败（{type(错误).__name__}: {错误}）"
        出["动作"] = "未核验"
        return 出
    出["动作"] = "已递增"
    return 出


def 主流程(包目录表: list[Path], *, 写盘: bool) -> tuple[int, list[str]]:
    """对给定包逐个判/递增。

    退出码（**「修」的语义：修完就不再是红**）：

    - 写盘口径：0 = 无需递增的都已一致、该递增的都已递增；2 = 有真问题（判不出/写失败/空范围）。
    - 只读口径：0 = 无待递增；1 = 有待递增；2 同上。
    """
    if not 包目录表:
        return 2, ["没有给任何包目录（扫描面为 0 不是通过）"]
    行表: list[str] = []
    码 = 0
    待增 = 0
    for 包目录 in 包目录表:
        结果 = 处理一个包(包目录, 写盘=写盘)
        if 结果["问题"]:
            码 = max(码, 2)
            行表.append(f"  [未核验] {结果['包目录']}：{结果['问题']}")
            continue
        if 结果["动作"] == "无需递增":
            行表.append(f"  [一致] {结果['包目录']}（契约面未变化，不要求递增；"
                      f"版本 {结果['当前版本']}）")
            continue
        待增 += 1
        if not 写盘:
            码 = max(码, 1)
        行表.append(f"  [{'已递增' if 写盘 else '待递增'}] {结果['包目录']}：{结果['口径']}")
    行表.append(f"共 {len(包目录表)} 个包；{'已递增' if 写盘 else '待递增'} {待增} 个")
    return 码, 行表


def 主函数(argv: list[str] | None = None) -> int:
    """命令行入口：`--写盘`（递增并写回）/ `--校验`（只报不改）+ 包目录列表。"""
    参 = list(sys.argv[1:] if argv is None else argv)
    写盘 = "--写盘" in 参
    未知 = [项 for 项 in 参 if 项.startswith("--") and 项 not in ("--写盘", "--校验")]
    if 未知:
        print(f"未知参数：{' '.join(未知)}；本入口只支持 `--写盘` 或 `--校验` + 包目录列表。")
        return 2
    包目录表 = [Path(项) for 项 in 参 if not 项.startswith("--")]
    print(f"═══ 契约版本自增（{'写盘' if 写盘 else '校验'}口径；口径 = 默认补丁位自增 1）═══")
    码, 行表 = 主流程(包目录表, 写盘=写盘)
    for 行 in 行表:
        print(行)
    return 码


