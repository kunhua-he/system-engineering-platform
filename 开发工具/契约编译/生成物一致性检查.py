"""生成物一致性检查（**只读**）：输入包目录，输出「哪些生成物与按当前源重算的结果不一致」。

定位
    契约编译器的产物有 6 类、说明书有 2 支生成器、依赖锁有 1 个正式入口 —— 改一条源文件后，
    到底有几份生成物要跟着变、哪一份已经落后，此前没有任何**单一入口**能一次说清。
    本入口就是那个入口：**按当前源现场重算，与磁盘逐项比对，只报差异**。

只读保证（硬约束，代码级强制）
    ① 本入口不写盘、不自动修、不落缓存；
    ② 运行期对 ``pathlib.Path`` 的 ``write_text/write_bytes/mkdir/replace/unlink/rmdir``
       与 ``builtins.open`` 的写模式**打桩拦截**，任何被调用到的生成器若试图写盘会当场抛错
       并把包名记进报告，而不是静默改动仓库；
    ③ ``sys.dont_write_bytecode = True``，导入不产生 ``__pycache__``。
    这三条合起来使得「拿本入口当重算器用」在物理上不可能 —— 它没有写的能力。

比对口径（每一类都取**该生成物自己的权威生成器**，不另写第二份算式）
    | 生成物 | 权威生成器 | 比对粒度 |
    |---|---|---|
    | 能力契约/参数契约.json | 开发工具.契约编译.能力定义编译器.生成能力契约（传入既有契约，非破坏性口径） | 解析后逐键 |
    | 包声明.json | 同文件.生成包声明（保留既有额外顶层字段） | 解析后逐键 |
    | 能力数据/能力搜索数据.json | 同文件.生成搜索数据 | 解析后逐键 |
    | 能力数据/Agent查询数据.json | 同文件.生成Agent数据 | 解析后逐键 |
    | __init__.py | 同文件.生成注册入口（仅对**带生成标记**的入口） | 全文逐字 |
    | 完整性摘要.json | 支持库.后端.组件规范支持库.生成完整性摘要（唯一生成器） | 解析后逐键 |
    | 说明/使用说明.md | **无单一权威**：G1=开发工具.说明书生成.说明书生成器；G2=组件规范支持库.实现.说明书生成器；人工类见 开发文档/项目证据/说明书白名单.json | 逐字 / 形态 |
    | 依赖锁.json | 开发工具.重建依赖锁（**只比 环境 块**：只刷新平台指纹，不改依赖集合） | 解析后取 环境 |
    | 权限契约/配置契约/依赖契约/资源预算/复用决策/生命周期契约/默认配置/验证场景引用 | **无生成器**（模板生成器只产骨架、不随源刷新） | 只登记「机器不可重算」 |

    说明书一项的口径说明（不许含糊）：``说明/使用说明.md`` **不是**任一生成器的无条件产物 ——
    G1 产出的是 ``工程缓存/说明书/<包id>.md``（不落包内），G2 明确拒绝覆盖已有文件。故本入口
    对说明书给三档判定：``G1逐字相同`` / ``G2逐字相同`` / ``形态漂移`` / ``白名单人工类（不可重算）``。
    ``形态漂移`` 只表示「与 G2 生成器现产出不同」，**不等于缺陷** —— 见白名单铁律「禁止对全部说明书批量重生成」。

用法
    python3.14 开发工具/契约编译/生成物一致性检查.py 模块库/开工编排
    python3.14 开发工具/契约编译/生成物一致性检查.py 模块库/开工编排 支持库/后端/组件规范支持库
    python3.14 开发工具/契约编译/生成物一致性检查.py --全部
    python3.14 开发工具/契约编译/生成物一致性检查.py --全部 --json

退出码
    0 = 全部一致（或只有「机器不可重算」登记项）；1 = 存在真实不一致；2 = 用法错误。
    本入口**不**接入任何门禁（接线是下一步，见 `开发文档/方案/项目总纲重写方案_20260917.md` §五）。
"""

