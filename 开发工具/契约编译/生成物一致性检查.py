def 相对(路径: Path) -> str:
    try:
        return 路径.relative_to(仓库根).as_posix()
    except ValueError:
        return str(路径)


def 读JSON(路径: Path):
    """读 JSON；不存在或不可读返回 (None, 原因)。"""
    if not 路径.is_file():
        return None, "文件不存在"
    try:
        return json.loads(路径.read_text(encoding="utf-8")), ""
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as 错误:
        return None, f"不可读: {错误}"


def 差异行(左, 右) -> tuple[int, int]:
    """两份文本的行集合差（生成器多出的行数 / 现行多出的行数）。"""
    import difflib
    差 = difflib.unified_diff(左.splitlines(), 右.splitlines(), lineterm="", n=0)
    加 = 减 = 0
    for 行 in 差:
        if 行.startswith("+") and not 行.startswith("+++"):
            加 += 1
        elif 行.startswith("-") and not 行.startswith("---"):
            减 += 1
    return 加, 减


