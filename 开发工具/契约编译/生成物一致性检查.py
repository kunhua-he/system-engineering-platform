不一致状态 = ("不一致", "不一致（形态漂移）", "缺失")


def 汇总(全部结论: list[检查项]) -> dict:
    from collections import Counter
    计数 = Counter(条.状态 for 条 in 全部结论)
    分类 = Counter(条.生成物 for 条 in 全部结论 if 条.状态 in 不一致状态)
    return {
        "检查项总数": len(全部结论),
        "按状态": dict(计数),
        "不一致总数": sum(分类.values()),
        "按生成物类型的不一致数": dict(sorted(分类.items(), key=lambda 项: -项[1])),
    }


def 打印包报告(包目录: Path, 结论: list[检查项]) -> None:
    print(f"\n═══ {相对(包目录)} ═══")
    for 条 in 结论:
        标记 = {"一致": "✔", "不一致": "✗", "不一致（形态漂移）": "△", "缺失": "✗ 缺",
                "手工维护": "○ 人工", "不可重算": "－ 不可重算", "跳过": "· 跳过"}.get(条.状态, "?")
        print(f"  {标记:12s} {条.生成物:26s} ← {条.生成器}")
        if 条.详情:
            print(f"      {'':12s} {条.详情}")


def 入口() -> int:
    解析 = argparse.ArgumentParser(
        prog="python3.14 开发工具/契约编译/生成物一致性检查.py",
        description="生成物一致性检查（只读）：按当前源现场重算，报出与磁盘不一致的生成物。")
    解析.add_argument("包", nargs="*", help="包相对路径（可多个）；与 --全部 二选一")
    解析.add_argument("--全部", action="store_true", help="检查全部正式包")
    解析.add_argument("--json", action="store_true", help="以 JSON 输出")
    解析.add_argument("--只看不一致", action="store_true", help="只打印不一致/缺失项")
    参数 = 解析.parse_args()

    if not 参数.包 and not 参数.全部:
        print("用法错误：给出至少一个包相对路径，或用 --全部。本入口只读，不会写盘。")
        return 2
    if 参数.包 and 参数.全部:
        print("用法错误：--全部 与 逐个包 不能同时给。")
        return 2

    白名单 = 说明书白名单()
    全部包 = 枚举正式包()
    目标: list[Path] = []
    未命中: list[str] = []
    if 参数.全部:
        根名表 = ("支持库", "模块库", "技能库", "平台控制面", "运行核心",
                "开发工具", "客户端", "启动监督器", "项目适配层", "公共契约")
        目标 = [p for p in 全部包
               if p.relative_to(仓库根).parts[0] in 根名表]
    else:
        候选表 = {p.relative_to(仓库根).as_posix(): p for p in 全部包}
        按名 = {}
        for p in 全部包:
            按名.setdefault(p.name, []).append(p)
        for 选择 in 参数.包:
            规范化 = 选择.strip().rstrip("/")
            if 规范化 in 候选表:
                目标.append(候选表[规范化])
                continue
            路径 = (仓库根 / 规范化) if not Path(规范化).is_absolute() else Path(规范化)
            if (路径 / "包声明.json").is_file():
                目标.append(路径.resolve())
                continue
            if 按名.get(Path(规范化).name, []) and len(按名[Path(规范化).name]) == 1:
                目标.append(按名[Path(规范化).name][0])
                continue
            未命中.append(选择)

    if 未命中:
        print(f"未命中或歧义的包：{', '.join(未命中)}", file=sys.stderr)
        if not 目标:
            return 2
    目标 = sorted(set(目标), key=lambda p: p.relative_to(仓库根).as_posix())

    全部结论: list[检查项] = []
    包结论表: list[tuple[str, list[检查项]]] = []
    for 包目录 in 目标:
        结论 = 检查一个包(包目录, 白名单)
        全部结论.extend(结论)
        包结论表.append((相对(包目录), 结论))

    if 参数.json:
        print(json.dumps({
            "只读": True,
            "写盘尝试": _写盘尝试,
            "包数": len(目标),
            "汇总": 汇总(全部结论),
            "包": [{"包": 包名, "条目": [条.转字典() for 条 in 结论]} for 包名, 结论 in 包结论表],
        }, ensure_ascii=False, indent=2))
    else:
        for 包名, 结论 in 包结论表:
            要打 = [条 for 条 in 结论 if 条.状态 in 不一致状态] if 参数.只看不一致 else 结论
            if 参数.只看不一致 and not 要打:
                continue
            print(f"\n═══ {包名} ═══")
            for 条 in 要打:
                标记 = {"一致": "✔", "不一致": "✗", "不一致（形态漂移）": "△", "缺失": "✗ 缺",
                        "手工维护": "○ 人工", "不可重算": "－ 不可重算", "跳过": "· 跳过"}.get(条.状态, "?")
                print(f"  {标记:12s} {条.生成物:26s} ← {条.生成器}")
                if 条.详情:
                    print(f"      {'':12s} {条.详情}")
        统计 = 汇总(全部结论)
        print(f"\n═══ 汇总（{len(目标)} 包） ═══")
        for 名, 数 in 统计["按状态"].items():
            print(f"  {数:5d}  {名}")
        print(f"  ── 不一致合计 {统计['不一致总数']} 项")
        for 名, 数 in 统计["按生成物类型的不一致数"].items():
            print(f"     {数:5d}  {名}")
        if _写盘尝试:
            print(f"\n⚠ 只读护栏触发 {len(_写盘尝试)} 次（生成器曾试图写盘，已拦下，仓库未被改动）：")
            for 项 in _写盘尝试[:10]:
                print(f"    {项}")

    return 1 if 汇总(全部结论)["不一致总数"] else 0


if __name__ == "__main__":
    raise SystemExit(入口())
