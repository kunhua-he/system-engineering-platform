class 检查项:
    """一条生成物检查结论。"""

    def __init__(self, 生成物: str, 相对路径: str, 生成器: str, 依据源: str,
                 状态: str, 详情: str = ""):
        self.生成物 = 生成物
        self.相对路径 = 相对路径
        self.生成器 = 生成器
        self.依据源 = 依据源
        self.状态 = 状态          # 一致 / 不一致 / 缺失 / 手工维护 / 不可重算 / 跳过
        self.详情 = 详情

    def 转字典(self) -> dict:
        return {"生成物": self.生成物, "路径": self.相对路径, "生成器": self.生成器,
                "依据源": self.依据源, "状态": self.状态, "详情": self.详情}


def 检查一个包(包目录: Path, 白名单: dict[str, dict]) -> list[检查项]:
    """检查一个包的**全部生成物**；返回逐项结论。"""
    结果: list[检查项] = []
    相对包 = 相对(包目录)

    # ── 0. 无生成器的生成物：只登记「机器不可重算」，不判红 ──────────────
    for 相对文件 in 无生成器生成物:
        if (包目录 / 相对文件).is_file():
            结果.append(检查项(Path(相对文件).name, f"{相对包}/{相对文件}",
                            "（无）", "（无）", "不可重算",
                            "全仓无生成器：模板生成器只产一次骨架，之后人工维护"))

    # ── 1. 依赖锁：唯一正式入口是 开发工具/重建依赖锁，只比 环境 块 ──────
    锁路径 = 包目录 / "依赖锁.json"
    if 锁路径.is_file():
        锁数据, 原因 = 读JSON(锁路径)
        if 锁数据 is None:
            结果.append(检查项("依赖锁.json", f"{相对包}/依赖锁.json", "重建依赖锁",
                            "包自身 + 当前平台指纹", "不一致", 原因))
        else:
            try:
                from 开发工具.重建依赖锁 import 采样环境
                当前 = 采样环境()
            except Exception as 错误:
                当前 = None
                结果.append(检查项("依赖锁.json", f"{相对包}/依赖锁.json", "重建依赖锁",
                                "当前平台指纹", "跳过", f"平台指纹采样失败（不判红）: {错误}"))
            if 当前 is not None:
                锁内 = 锁数据.get("环境") if isinstance(锁数据.get("环境"), dict) else {}
                差异 = [f"{键}: {锁内.get(键)!r} → {当前[键]!r}"
                       for 键 in ("Python", "操作系统", "CPU") if 锁内.get(键) != 当前.get(键)]
                if 差异:
                    结果.append(检查项("依赖锁.json", f"{相对包}/依赖锁.json", "重建依赖锁",
                                    "当前平台指纹", "不一致", "；".join(差异)))
                else:
                    结果.append(检查项("依赖锁.json", f"{相对包}/依赖锁.json", "重建依赖锁",
                                    "当前平台指纹", "一致", "环境块与当前平台一致（幂等，无需重建）"))

    # ── 2. 说明书：三档判定，白名单优先 ────────────────────────────────
    说明路径 = 包目录 / "说明" / "使用说明.md"
    if 说明路径.is_file():
        现说明 = 说明路径.read_text(encoding="utf-8").strip()
        白名单条 = 白名单.get(f"{相对包}/说明/使用说明.md")
        G1账号 = None
        try:
            from 公共契约.包声明.声明 import 从字典构建 as _从字典构建
            from 开发工具.说明书生成.说明书生成器 import 生成单包说明书
            声明对象, 声明原因 = 读JSON(包目录 / "包声明.json")
            if 声明对象 is not None:
                G1账号 = 生成单包说明书(_从字典构建(
                    声明对象, 来源路径=str(包目录 / "包声明.json"))).strip()
        except Exception:
            G1账号 = None
        G2账号 = None
        try:
            # 走**包级公开面**（`__init__.py` 的 __all__ 已导出 生成说明书文本）。
            # 直接 import 包内 `实现/` 会被依赖防火墙判「跨包禁止导入 实现/ 目录」——
            # 那是**真违规**，不是误报（2026-09-18 主会话按 1.3「结果唯一即收口」改正）。
            from 支持库.后端.组件规范支持库 import 生成说明书文本
            G2账号 = 生成说明书文本(包目录).strip()
        except Exception:
            G2账号 = None
        if G1账号 is not None and 现说明 == G1账号:
            结果.append(检查项("说明/使用说明.md", f"{相对包}/说明/使用说明.md",
                            "开发工具/说明书生成/说明书生成器（G1）", "包声明.json + 能力契约/参数契约.json",
                            "一致", "与 G1 生成器逐字相同"))
        elif G2账号 is not None and 现说明 == G2账号:
            结果.append(检查项("说明/使用说明.md", f"{相对包}/说明/使用说明.md",
                            "组件规范支持库/实现/说明书生成器（G2）",
                            "能力定义.json + 参数契约.json + 能力搜索数据.json + 验证场景引用.json",
                            "一致", "与 G2 生成器逐字相同"))
        elif 白名单条 is not None:
            结果.append(检查项("说明/使用说明.md", f"{相对包}/说明/使用说明.md",
                            f"（人工类·{白名单条.get('血统细分', '未细分')}）", "（人工）",
                            "手工维护",
                            f"白名单类别 {白名单条.get('类别')}：生成器不得覆盖"))
        elif G2账号 is not None:
            加, 减 = 差异行(现说明, G2账号)
            结果.append(检查项("说明/使用说明.md", f"{相对包}/说明/使用说明.md",
                            "组件规范支持库/实现/说明书生成器（G2）", "见生成器",
                            "不一致（形态漂移）",
                            f"G2 生成器多 {加} 行／现行多 {减} 行。★ 形态漂移≠缺陷："
                            f"该生成器拒绝覆盖已有文件，批量重生成会抹掉人工内容（见说明书白名单铁律）"))
        else:
            结果.append(检查项("说明/使用说明.md", f"{相对包}/说明/使用说明.md", "（不可判定）",
                            "（不可判定）", "跳过", "两支生成器均无法实跑比对"))

    # ── 3. 依赖能力定义的三类派生物（编译器的唯一事实源口径）───────────
    定义文件 = 包目录 / "能力定义.json"
    if not 定义文件.is_file():
        子包 = [子 for 子 in sorted(包目录.iterdir())
               if 子.is_dir() and (子 / "包声明.json").is_file()]
        if 子包 and not (包目录 / "实现").is_dir():
            结果.append(检查项("（整包）", 相对包, "能力定义编译器", "（聚合父包）", "跳过",
                            f"聚合父包：自身不注册能力，能力在 {len(子包)} 个子包里，无能力定义即无派生物"))
        else:
            结果.append(检查项("（整包）", 相对包, "能力定义编译器", "能力定义.json", "跳过",
                            "缺 能力定义.json 且不构成聚合父包：无派生物可比"))
        return 结果

    try:
        from 开发工具.契约编译.能力定义编译器 import (
            生成Agent数据, 生成包声明, 生成能力契约, 生成注册入口, 生成搜索数据,
            校验能力定义, 从包推导编译参数, 读取能力定义,
        )
        from 开发工具.契约编译.聚合契约解析 import 读取原始
    except Exception as 错误:
        return [*结果, 检查项("（全部）", 相对包, "能力定义编译器", "能力定义.json", "跳过",
                         f"编译器导入失败: {错误}")]

    定义, 定义原因 = 读JSON(定义文件)
    if 定义 is None:
        return [*结果, 检查项("（全部）", 相对包, "能力定义编译器", "能力定义.json", "不一致", 定义原因)]
    结构问题 = 校验能力定义(定义)
    if 结构问题:
        return [*结果, 检查项("（全部）", 相对包, "能力定义编译器", "能力定义.json", "不一致",
                         f"能力定义结构不合法: {'; '.join(结构问题[:3])}")]
    编译参数, 推导问题 = 从包推导编译参数(包目录)
    if 推导问题:
        return [*结果, 检查项("（全部）", 相对包, "能力定义编译器", "能力定义.json", "跳过",
                         f"编译参数无法推导（不判红，先修推导前提）: {'; '.join(推导问题[:2])}")]

    def 比JSON(生成物名: str, 相对文件: str, 期望对象, 生成器名: str, 依据源: str) -> None:
        路径 = 包目录 / 相对文件
        实际, 原因 = 读JSON(路径)
        if 实际 is None and not 路径.is_file():
            结果.append(检查项(生成物名, f"{相对包}/{相对文件}", 生成器名, 依据源, "缺失", 原因))
            return
        if 实际 is None:
            结果.append(检查项(生成物名, f"{相对包}/{相对文件}", 生成器名, 依据源, "不一致", 原因))
            return
        if 实际 == 期望对象:
            结果.append(检查项(生成物名, f"{相对包}/{相对文件}", 生成器名, 依据源, "一致", ""))
            return
        差异键 = sorted({*实际, *期望对象} if isinstance(实际, dict) and isinstance(期望对象, dict)
                     else [])
        差异明细 = [键 for 键 in 差异键 if 实际.get(键) != 期望对象.get(键)] or ["（非对象或结构不同）"]
        结果.append(检查项(生成物名, f"{相对包}/{相对文件}", 生成器名, 依据源, "不一致",
                        f"与按当前源重算不同，差异键 {差异明细[:4]}"))

    # 3.1 能力契约/参数契约.json —— 非破坏性口径：必须把既有契约传进生成器
    契约路径 = 包目录 / "能力契约" / "参数契约.json"
    期望契约 = json.loads(生成能力契约(定义, 读取原始(契约路径) if 契约路径.is_file() else None))
    比JSON("能力契约/参数契约.json", "能力契约/参数契约.json", 期望契约,
         "能力定义编译器.生成能力契约", "能力定义.json（+既有契约保留手写键）")

    # 3.2 包声明.json —— 保留既有额外顶层字段
    声明路径 = 包目录 / "包声明.json"
    既有声明, _ = 读JSON(声明路径)
    期望声明 = json.loads(生成包声明(定义, 编译参数["包id"], 编译参数["包名称"],
                              编译参数["包类型"], 编译参数["依赖"]))
    if isinstance(既有声明, dict):
        期望声明.update({键: 值 for 键, 值 in 既有声明.items() if 键 not in 期望声明})
    比JSON("包声明.json", "包声明.json", 期望声明,
         "能力定义编译器.生成包声明", "能力定义.json + 既有声明的额外顶层字段")

    # 3.3 能力数据两份
    比JSON("能力数据/能力搜索数据.json", "能力数据/能力搜索数据.json",
         json.loads(生成搜索数据(定义)), "能力定义编译器.生成搜索数据", "能力定义.json")
    比JSON("能力数据/Agent查询数据.json", "能力数据/Agent查询数据.json",
         json.loads(生成Agent数据(定义, 编译参数["包id"])),
         "能力定义编译器.生成Agent数据", "能力定义.json + 包id")

    # 3.4 __init__.py —— 只对带生成标记的入口判红；手写入口含 注册能力 是合法形态
    入口路径 = 包目录 / "__init__.py"
    if not 入口路径.is_file():
        结果.append(检查项("__init__.py", f"{相对包}/__init__.py", "能力定义编译器.生成注册入口",
                        "能力定义.json + 实现模块", "缺失", "入口文件不存在"))
    else:
        入口文本 = 入口路径.read_text(encoding="utf-8")
        if 契约编译器生成标记 in 入口文本:
            期望入口 = 生成注册入口(定义, 编译参数["包id"], 编译参数["实现模块"])
            if 入口文本 == 期望入口:
                结果.append(检查项("__init__.py", f"{相对包}/__init__.py",
                                "能力定义编译器.生成注册入口", "能力定义.json + 实现模块",
                                "一致", "带生成标记且与重生成逐字相同"))
            else:
                加, 减 = 差异行(入口文本, 期望入口)
                结果.append(检查项("__init__.py", f"{相对包}/__init__.py",
                                "能力定义编译器.生成注册入口", "能力定义.json + 实现模块",
                                "不一致", f"带生成标记却与重生成不同：重生成多 {加} 行／现行多 {减} 行"))
        elif "def 注册能力" in 入口文本:
            结果.append(检查项("__init__.py", f"{相对包}/__init__.py",
                            "（手工入口：含 注册能力，编译器按规则不覆盖）", "（人工）",
                            "手工维护", "无生成标记但有 注册能力 函数 → 编译器承认的合法手写入口"))
        else:
            结果.append(检查项("__init__.py", f"{相对包}/__init__.py", "能力定义编译器.生成注册入口",
                            "能力定义.json + 实现模块", "不一致",
                            "既无生成标记、又无 注册能力 函数 → 编译器不会承认的入口"))

    # 3.5 完整性摘要.json —— 唯一生成器口径（含能力派生字段回读对账）
    try:
        from 支持库.后端.组件规范支持库 import 生成完整性摘要, 校验完整性摘要
        摘要路径 = 包目录 / "完整性摘要.json"
        实际摘要, 摘要原因 = 读JSON(摘要路径)
        期望摘要 = 生成完整性摘要(包目录, 包id=编译参数["包id"], 版本=str(定义.get("版本") or "1.0.0"))
        if 实际摘要 is None:
            结果.append(检查项("完整性摘要.json", f"{相对包}/完整性摘要.json",
                            "组件规范支持库.生成完整性摘要", "包内全部文件 + 能力定义.json",
                            "缺失" if not 摘要路径.is_file() else "不一致", 摘要原因))
        elif 实际摘要 == 期望摘要:
            通过, 回读问题 = 校验完整性摘要(包目录)
            结果.append(检查项("完整性摘要.json", f"{相对包}/完整性摘要.json",
                            "组件规范支持库.生成完整性摘要", "包内全部文件 + 能力定义.json",
                            "一致", "" if 通过 else f"重算相等但回读校验报: {回读问题[:2]}"))
        else:
            差异键 = sorted({*实际摘要, *期望摘要})
            不同 = [键 for 键 in 差异键 if 实际摘要.get(键) != 期望摘要.get(键)]
            结果.append(检查项("完整性摘要.json", f"{相对包}/完整性摘要.json",
                            "组件规范支持库.生成完整性摘要", "包内全部文件 + 能力定义.json",
                            "不一致", f"与按当前源重算不同，差异键 {不同[:4]}"))
    except Exception as 错误:
        结果.append(检查项("完整性摘要.json", f"{相对包}/完整性摘要.json",
                        "组件规范支持库.生成完整性摘要", "包内全部文件 + 能力定义.json",
                        "跳过", f"重算失败（不判红）: {type(错误).__name__}: {错误}"))

    return 结果


