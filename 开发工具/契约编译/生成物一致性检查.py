def _装只读护栏() -> None:
    """把 Path 的写方法与 open 的写模式全部替换成「抛错并记账」。

    为什么连 ``mkdir`` 都要拦：生成器普遍先 ``mkdir(parents=True, exist_ok=True)``
    再写文件；只拦写不拦建目录，仍会让「拿检查器当生成器跑」在仓库里留下空目录。
    """
    def _拒绝(方法名: str):
        原 = getattr(Path, 方法名)

        def 包装(self, *参数, **关键字):
            原样 = "".join(参数[:1]) if 参数 else ""
            _写盘尝试.append(f"Path.{方法名}({self}{('/' + str(原样)) if 原样 else ''})")
            raise RuntimeError(
                f"只读保证：生成物一致性检查不得写盘（已拦下 Path.{方法名} → {self}）。"
                f"要真正重算请用对应生成器的正式入口。")
        return 包装

    for 名 in ("write_text", "write_bytes", "mkdir", "replace", "unlink", "rmdir", "rename", "touch"):
        if hasattr(Path, 名):
            _路径方法原名[名] = getattr(Path, 名)
            setattr(Path, 名, _拒绝(名))

    _原生open = builtins.open

    def 包装open(文件, 模式="r", *参数, **关键字):
        if isinstance(模式, str) and any(标志 in 模式 for 标志 in ("w", "a", "x", "+")):
            _写盘尝试.append(f"open({文件}, {模式!r})")
            raise RuntimeError(
                f"只读保证：生成物一致性检查不得写盘（已拦下 open({文件}, {模式!r})）。")
        return _原生open(文件, 模式, *参数, **关键字)

    builtins.open = 包装open


