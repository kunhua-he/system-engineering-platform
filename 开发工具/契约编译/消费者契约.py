def 校验契约() -> tuple[bool, list[str]]:
    """契约自检：12 操作齐备、角色合法、错误码全集闭合、消费者关键输出非空。"""
    问题表: list[str] = []
    if len(稳定操作表) != 12:
        问题表.append(f"稳定操作表应为 12 项，实际 {len(稳定操作表)}")
    if set(操作契约) != set(稳定操作表):
        问题表.append("操作契约与稳定操作表不一致")
    for 操作, 项 in 操作契约.items():
        if 项["最小角色"] not in 角色等级表:
            问题表.append(f"{操作} 最小角色非法: {项['最小角色']}")
        for 码 in 项["错误码"]:
            if 码 not in 错误码全集:
                问题表.append(f"{操作} 错误码 {码} 不在全集")
        if not 项["超时"] or not 项["资源释放"]:
            问题表.append(f"{操作} 缺少 超时/资源释放 声明")
    for 消费者 in 消费者契约:
        if not 消费者["关键输出"]:
            问题表.append(f"{消费者['消费者']} 关键输出不能为空")
    return not 问题表, 问题表
