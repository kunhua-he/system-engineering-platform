"""唯一聚合契约解析器：契约编译器/能力搜索器/说明书生成器共用的唯一解析入口。

S0 唯一聚合格式：{契约版本, 能力契约:[{能力id,版本,说明,参数,返回,错误码,调用示例}]}。
本模块是唯一的契约解析实现：禁止各自解析与兼容双写；类型"任意"由本解析器
统一拒绝（严格模式）或归一为"未约束"（读取模式），搜索与说明书只消费本模块输出。
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from 公共契约.基础类型.类型表 import 正式类型表

任意类型 = "任意"
未约束类型 = "未约束"


def 读取原始(来源: Path | str | dict) -> dict[str, Any] | None:
    """读取聚合契约 JSON（文件/文本/字典）；非法或非对象返回 None。"""
    if isinstance(来源, dict):
        return 来源
    try:
        文本 = 来源.read_text(encoding="utf-8") if isinstance(来源, Path) else 来源
        数据 = json.loads(文本)
    except (OSError, json.JSONDecodeError):
        return None
    return 数据 if isinstance(数据, dict) else None


#: 必填参数在示例里的占位值（按正式类型名给；搜到即可照抄改）。
#: 为什么需要：原实现只取「默认值非 None」的参数，**无默认值的必填参数一律不进示例** ⇒
#: 生成的示例结构上必然跑不通（实测 491/713 个能力的示例缺必填，照抄即报「缺少必填参数」）。
示例占位值: dict[str, Any] = {
    "文本型": "<必填>",
    "整数型": 0,
    "长整数型": 0,
    "双精度数型": 0.0,
    "单精度数型": 0.0,
    "逻辑型": False,
    "列表型": [],
    "字典型": {},
    "JSON值型": {},
    "字节型": "<字节>",
    "字节集型": "<字节集>",
    "日期时间型": "<日期时间>",
    "句柄型": "<句柄：由产生它的能力返回>",
    "资源引用型": "<资源引用>",
    "空值型": None,
    "结果型": {},
    "任意": "<必填>",
    "未约束": "<必填>",
}


def 示例值(参数: dict) -> Any:
    """取一个参数在调用示例里的值：有默认值用默认值，必填无默认值给类型占位值。

    不可填的可选参数（无默认值、非必填）不进示例 —— 可选参数缺失本就合法，
    填上去反而把示例变复杂（省 token 口径：示例只写到「能跑」为止）。
    """
    默认 = 参数.get("默认值")
    if 默认 is not None:
        return 默认
    if not 参数.get("必填", True):
        return None
    return 示例占位值.get(str(参数.get("类型", "")), "<必填>")


def 生成调用示例(能力id: str, 参数表: list[dict]) -> dict:
    """由参数默认值生成可执行调用示例（必填而无默认值的参数给类型占位值）。

    **「可执行」的判据是「照抄不报缺少必填参数」**，不是「参数对象非空」——
    原实现只收默认值非 None 的参数，导致必填参数整体缺失、示例必然跑不通（见 示例值 注释）。
    """
    示例参数: dict[str, Any] = {}
    for 参数 in 参数表:
        值 = 示例值(参数)
        if 值 is not None:
            示例参数[参数["名称"]] = 值
    return {"能力id": 能力id, "参数": 示例参数}


def _参数可用性检查(能力id: str, 参数: dict, 名称: str) -> list[str]:
    """参数可用性判据：让「搜到即会用」。

    **为什么不塞进 `校验能力条目(严格=True)`**：严格模式被 `运行发布门禁_制品验证`
    使用，而这两条判据在存量契约上有 **131 + 84 条**违规——塞进去会让发布门禁直接判红
    （违反「存量冻结、只减不增」）。故本函数**独立导出**，由编译口以「只报告」口径调用，
    新增违规才阻断；存量按基线治理。

    **两条判据的来由**（2026-09-20 审计，华哥口述「搜到即会用、不再反复探索」）：

    ① **必填参数说明不得为空、不得等于参数名**：全仓实测 **131 条**必填参数的说明为空
       或与名称完全相同（如 `{"名称":"消息列表","说明":"消息列表"}`），Agent 只能靠猜形状。
       判据＝说明非空且不等于名称（好样板：`代码地图路径` →「代码地图 SQLite 文件绝对路径
       （如 `<项目根>/.codegraph/codegraph.db`）」）。

    ② **句柄类参数必须写明产地能力**：全仓实测提到「句柄」的参数 **92 条**，写了产地
       （「由 X 返回」）的仅 **8 条**，**84 条只说「网关返回的句柄」不说哪个能力产生它**。
       判据＝句柄参数说明里必须出现「由 … 返回」或「产地」这类指向能力的表述，
       否则 Agent 拿到句柄参数也不知道该先调哪个能力。
    """
    问题: list[str] = []
    说明 = str(参数.get("说明", "") or "").strip()
    if 参数.get("必填", True):
        if not 说明:
            问题.append(f"能力 {能力id or '?'}: 必填参数 {名称} 缺少 说明（使用者无法知道该传什么形状）")
        elif 说明 == 名称:
            问题.append(f"能力 {能力id or '?'}: 必填参数 {名称} 的 说明 与参数名相同（无信息量，"
                     "请给出可照抄的取值形状或来源）")
    # 句柄参数判据：只认**参数名或类型**含「句柄」（说明里提到「句柄」多半是在解释用法，
    # 如 `超时秒` 的说明里引用了句柄；把这类也算句柄参数会误报——2026-09-20 实测踩过）。
    # 产地写法宽容：`由 X 返回` / `由 X / Y / Z 返回` / 显式写「产地」都算写明；
    # 也接受**明确声明无产地**（如「由调用方提供」的回调函数——它不由任何能力产生，
    # 硬要求写产地只会逼出假话）。判据要的是「写清楚」，不是「非得有产地」。
    名或型 = f"{名称}{参数.get('类型','')}"
    if "句柄" in 名或型 and not re.search(
            r"由\s*[^。；\n]{1,80}?返回|产地|调用方提供|无产地", 说明):
        问题.append(f"能力 {能力id or '?'}: 句柄参数 {名称} 未写明产地能力"
                 "（请写成「…（由 某能力 返回）」，或明确声明「由调用方提供」）")
    return 问题


def 检查参数可用性(契约数据: dict[str, Any]) -> tuple[list[str], int]:
    """全量检查一份聚合契约的参数可用性，返回（问题列表, 参数总数）。

    供编译口以「只报告」口径调用：存量按基线治理，新增违规才拦（存量冻结原则）。
    """
    问题表: list[str] = []
    参数总数 = 0
    for 条目 in 契约数据.get("能力契约") or []:
        if not isinstance(条目, dict):
            continue
        能力id = str(条目.get("能力id", ""))
        for 参数 in 条目.get("参数") or []:
            if not isinstance(参数, dict) or not 参数.get("名称"):
                continue
            参数总数 += 1
            问题表.extend(_参数可用性检查(能力id, 参数, str(参数["名称"])))
    return 问题表, 参数总数


def 校验能力条目(条目: dict[str, Any], *, 严格: bool = False) -> list[str]:
    """校验一条能力契约；严格模式按 S0 全量（说明/错误码非空/调用示例/类型门禁）。"""
    问题列表 = []
    能力id = 条目.get("能力id", "")
    if not 能力id:
        问题列表.append("缺少 能力id")
    if not 条目.get("版本"):
        问题列表.append(f"能力 {能力id or '?'}: 缺少 版本")
    参数表 = 条目.get("参数")
    if not isinstance(参数表, list):
        问题列表.append(f"能力 {能力id or '?'}: 缺少 参数 列表")
    else:
        for 参数 in 参数表:
            名称 = 参数.get("名称", "")
            if not 名称:
                问题列表.append(f"能力 {能力id or '?'}: 存在缺少 名称 的参数")
                continue
            类型 = 参数.get("类型", "")
            if not 类型:
                问题列表.append(f"能力 {能力id or '?'}: 参数 {名称} 缺少 类型")
            elif 类型 == 任意类型:
                if 严格:
                    问题列表.append(f"能力 {能力id or '?'}: 参数 {名称} 类型为 任意（禁止）")
            elif 严格 and 类型 not in 正式类型表:
                问题列表.append(f"能力 {能力id or '?'}: 参数 {名称} 类型 {类型} 不在正式类型表")
    if not 条目.get("返回"):
        问题列表.append(f"能力 {能力id or '?'}: 缺少 返回")
    if "错误码" not in 条目:
        问题列表.append(f"能力 {能力id or '?'}: 缺少 错误码")
    elif 严格 and (not isinstance(条目["错误码"], list) or not 条目["错误码"]):
        问题列表.append(f"能力 {能力id or '?'}: 错误码 必须为非空列表")
    if 严格:
        if not 条目.get("说明"):
            问题列表.append(f"能力 {能力id or '?'}: 缺少 说明")
        if not 条目.get("调用示例"):
            问题列表.append(f"能力 {能力id or '?'}: 缺少 调用示例")
    return 问题列表


def 标准化条目(条目: dict[str, Any]) -> dict[str, Any]:
    """归一化一条能力条目：参数补默认字段；任意类型归一为未约束；缺调用示例生成。"""
    能力id = str(条目.get("能力id", ""))
    参数表 = []
    for 参数 in 条目.get("参数", []):
        if not isinstance(参数, dict) or not 参数.get("名称"):
            continue
        类型 = 参数.get("类型", "")
        参数表.append({
            "名称": 参数["名称"],
            "类型": 未约束类型 if 类型 == 任意类型 else 类型,
            "必填": 参数.get("必填", True),
            "默认值": 参数.get("默认值"),
            "说明": 参数.get("说明", ""),
        })
    调用示例 = 条目.get("调用示例")
    if not isinstance(调用示例, dict):
        调用示例 = 生成调用示例(能力id, 参数表)
    错误码 = 条目.get("错误码", [])
    return {
        "能力id": 能力id,
        "版本": 条目.get("版本", ""),
        "说明": 条目.get("说明", ""),
        "参数": 参数表,
        "返回": 条目.get("返回", ""),
        "错误码": 错误码 if isinstance(错误码, list) else [],
        "调用示例": 调用示例,
        "行为": 条目.get("行为", {}),
        "提供者": 条目.get("提供者", {}),
    }


def 包声明显式零能力(包目录: Path | None) -> bool:
    """同包 `包声明.json` 是否**显式声明**零能力（`能力` 键存在且为空数组）。

    「有实现、无能力面」形态的**唯一判据节点**（2026-09-24 批R 收尾）。

    为什么住本模块（而不是 `能力定义编译器`）：本模块是编译器的**下层** ——
    `能力定义编译器.py` 反向 import 本模块，判据若住上层、本模块再 import 它即**成环**。
    故判据下沉到本模块，两侧都转调它：
      · 定义侧 = `能力定义编译器.校验能力定义`（`能力列表` 为空时）；
      · 契约侧 = 本模块 `解析聚合契约`（`严格` 且 `能力契约` 为空时），
        服务 `开发工具.发布门禁.运行发布门禁_制品验证.校验制品来源绑定`。

    批R·R-28 裁决①（华哥 2026-09-24「删适配层孪生能力面、保留后端腿 id」）：
    5 个适配层提供者包删掉孪生能力面后成为「有实现、无能力面」形态 —— 该形态
    必须**两侧同时**声明（`能力定义.json` 能力列表 空 ＋ `包声明.json` 能力 空），
    单侧清空一律照旧判红（防静默丢能力）。
    fail-closed：包目录为空 / 读不成 / 不是对象 / 无 `能力` 键 / `能力` 非空 ⇒ 假。
    """
    if 包目录 is None:
        return False
    声明路径 = Path(包目录) / "包声明.json"
    if not 声明路径.is_file():
        return False
    try:
        声明 = json.loads(声明路径.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return False
    return isinstance(声明, dict) and 声明.get("能力") == []


def _契约文件所在包目录(来源: Any) -> Path | None:
    """契约文件路径 → 所在包目录（`…/包名/能力契约/参数契约.json` ⇒ `…/包名`）。

    定位不到包（不是 `Path`、或不在 `能力契约` 目录下）就回 `None`
    ⇒ `解析聚合契约` 退回旧口径（空列表照旧判红），**不静默放宽**。
    """
    if not isinstance(来源, Path):
        return None
    目录 = 来源.parent
    if 目录.name != "能力契约":
        return None
    return 目录.parent


def 解析聚合契约(来源: Any, *, 严格: bool = False) -> tuple[dict, list[str]]:
    """解析并归一化聚合契约；返回 (标准数据, 问题列表)。"""
    原始 = 读取原始(来源)
    if 原始 is None:
        return {"契约版本": "", "能力契约": []}, ["聚合契约 JSON 非法或缺失"]
    问题列表 = []
    契约版本 = 原始.get("契约版本")
    if 严格 and not 契约版本:
        问题列表.append("缺少 契约版本")
    能力契约 = 原始.get("能力契约")
    if not isinstance(能力契约, list):
        问题列表.append("能力契约 必须是列表")
        return {"契约版本": 契约版本 or "", "能力契约": []}, 问题列表
    # 「有实现、无能力面」包的空契约合法（判据唯一节点，两侧同源）——
    # 见 `包声明显式零能力` 上方那段：单侧清空仍照旧判红。
    if 严格 and not 能力契约 and not 包声明显式零能力(_契约文件所在包目录(来源)):
        问题列表.append("能力契约 不能为空列表")
    条目表 = []
    for 条目 in 能力契约:
        if not isinstance(条目, dict):
            问题列表.append("能力契约 存在非对象条目")
            continue
        问题列表.extend(校验能力条目(条目, 严格=严格))
        if 条目.get("能力id"):
            条目表.append(标准化条目(条目))
    return {"契约版本": 契约版本 or "", "能力契约": 条目表}, 问题列表


def 提取能力表(聚合数据: dict[str, Any]) -> list[dict[str, Any]]:
    """从聚合契约数据提取能力条目表。"""
    if not isinstance(聚合数据, dict):
        return []
    return 聚合数据.get("能力契约", [])
