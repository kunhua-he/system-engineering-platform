#: 产地句式与并列切分（与 `模块库/能力目录/实现/能力索引.py` 同口径）。
#: 为什么在这里各自实现一份而不是 import 模块库：本入口属 `开发工具/契约编译/`，
#: 让「契约编译判据」反向依赖「模块库实现」会把依赖方向倒过来（契约编译在模块库
#: 之下）。两边判据都从同一份 `说明` 文本派生，口径由本节注释与两条测试共同锁死。
产地句式 = re.compile(r"由\s*([^（）。；\n]{1,80}?)\s*返回")
产地名分隔符句式 = re.compile(r"\s*[/、和及]\s*")
无产地句式 = re.compile(r"调用方提供|无产地|不由任何能力")

#: 「只有类型名、没有说明」的判定：整串就是 16 个正式类型名之一的形态（如 `整数型`、`双精度数型`）。
#: **用 `fullmatch` 判**（见 `只有类型名`）：只要带了说明（哪怕是 `整数型，句柄超时秒`）就不算 ——
#: 判据只管「有没有说明」，不管说明写得好不好（后者是 13.1 的活，不是本口）。
裸类型名句式 = re.compile(r"[^\s，,：:]{1,8}型")


def 只有类型名(声明: object) -> bool:
    """该值结构声明是否「只有类型名、没有说明」。"""
    return (isinstance(声明, str)
            and 裸类型名句式.fullmatch(声明.strip()) is not None)


def 空值结构(值结构: object) -> bool:
    """`返回.值结构` 是否「空对象」——一个载荷字段说明都没给出。

    两态（2026-09-23 补盲区，见 `值结构存量基线` 注释）：

    - `{}` 空字典：旧实现 `for 字段, 声明 in 值结构.items()` 迭代**零项**，
      于是「空对象」在判据 5 里**一条都不报**——这就是 151 条空对象悄悄累积的盲区；
    - `{"类型": <裸类型名>}`：只放了 `类型` 一个键、且值就是裸类型名（无说明），
      等于把 `返回.类型` 误填进了 值结构，同样读不出形状。

    **判定要精确到「无说明」**：`类型` 本身也是合法载荷字段名（实测全仓如此），
    故 `{"类型": "文本型，这条记录的类型"}`（带说明的单字段）**不算**空对象。
    """
    if not isinstance(值结构, dict):
        return False
    if not 值结构:
        return True
    return set(值结构) == {"类型"} and 只有类型名(值结构["类型"])


def 建全仓能力名库(契约文件表: list[Path]) -> tuple[set[str], dict[str, int]]:
    """扫一遍已收集的契约文件，返回（全限定能力id 集, 末段名 → 出现次数）。"""
    全id集: set[str] = set()
    名计数: dict[str, int] = {}
    for 文件 in 契约文件表:
        try:
            数据 = json.loads(文件.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for 条目 in 数据.get("能力契约") or []:
            if not isinstance(条目, dict) or not 条目.get("能力id"):
                continue
            能力id = str(条目["能力id"])
            全id集.add(能力id)
            名 = 能力id.rsplit(".", 1)[-1]
            名计数[名] = 名计数.get(名, 0) + 1
    return 全id集, 名计数


def 产地可解析(产地名: str, 本能力id: str, 全id集: set[str],
              名计数: dict[str, int]) -> bool:
    """产地名能否解析成全仓真实能力 id（与 能力索引.解析产地 同三级判据）。

    歧义（末段名对应多条能力）**算通过**：那不证明写错了，只证明不够精确——
    真判红会逼作者瞎猜一个，属「宁缺勿假」的反面。
    """
    净 = 产地名.strip().strip("的").strip()
    if not 净:
        return 假
    if "." in 净:
        return 净 in 全id集
    同包 = f"{本能力id.rsplit('.', 1)[0]}.{净}"
    if 同包 in 全id集:
        return 真
    return 名计数.get(净, 0) >= 1


def 检查产地可解析(契约文件表: list[Path]) -> list[str]:
    """判据 3：句柄参数的产地名必须能解析到真实能力。"""
    全id集, 名计数 = 建全仓能力名库(契约文件表)
    问题表: list[str] = []
    for 文件 in 契约文件表:
        try:
            数据 = json.loads(文件.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for 条目 in 数据.get("能力契约") or []:
            if not isinstance(条目, dict) or not 条目.get("能力id"):
                continue
            能力id = str(条目["能力id"])
            for 参数 in 条目.get("参数") or []:
                if not isinstance(参数, dict):
                    continue
                名或型 = f"{参数.get('名称', '')}{参数.get('类型', '')}"
                if "句柄" not in 名或型:
                    continue
                说明 = str(参数.get("说明", "") or "")
                if 无产地句式.search(说明):
                    continue
                名表 = [段.strip().strip("的").strip()
                       for 匹配 in 产地句式.finditer(说明)
                       for 段 in 产地名分隔符句式.split(匹配.group(1))
                       if 段.strip().strip("的").strip()]
                if any(not 产地可解析(名, 能力id, 全id集, 名计数) for 名 in 名表):
                    坏 = [名 for 名 in 名表
                         if not 产地可解析(名, 能力id, 全id集, 名计数)]
                    问题表.append(
                        f"能力 {能力id}: 句柄参数 {参数.get('名称', '?')} 的产地 "
                        f"{'、'.join(坏)} 解析不到真实能力"
                        "（写明全限定能力 id，或改成「由调用方提供」）")
    return 问题表


def 检查值结构可用性(数据: dict) -> list[str]:
    """判据 4/5：`返回` 不得退化成裸文本；`返回.值结构` 不得为空对象、字段值不得只有类型名。

    判据出处是平台自己（`公共契约/基础类型/字段名册.py` 的 `返回` 条目原文），
    本函数只把它接成机器可跑的检查，不新增口径。
    """
    问题表: list[str] = []
    for 条目 in 数据.get("能力契约") or []:
        if not isinstance(条目, dict) or not 条目.get("能力id"):
            continue
        能力id = str(条目["能力id"])
        返回声明 = 条目.get("返回")
        if isinstance(返回声明, str):
            问题表.append(
                f"能力 {能力id}: 返回 退化成裸文本 {返回声明!r}"
                "（应为 {类型, 值结构}；字段名册的 返回 条目明写不得退化成裸文本）")
            continue
        if not isinstance(返回声明, dict):
            continue
        值结构 = 返回声明.get("值结构")
        if not isinstance(值结构, dict):
            continue
        if 空值结构(值结构):
            # 空对象：旧实现迭代零项、一条不报（判据 5 的盲区）。这里单独判、只报一条，
            # 不落进下面的逐字段循环（没有字段可循环）。
            问题表.append(
                f"能力 {能力id}: 返回.值结构 是空对象 {值结构!r}，未声明任何载荷字段"
                "（读 实现/ 取真实字段口径后写成 {字段名: '类型，说明'}）")
            continue
        for 字段, 声明 in 值结构.items():
            if 只有类型名(声明):
                问题表.append(
                    f"能力 {能力id}: 返回.值结构.{字段} 只有类型名 {声明!r}，没有字段说明"
                    "（读 实现/ 取真实字段口径后写成「类型，说明」）")
    return 问题表


def 体检(项目根: Path | None = None) -> tuple[list[str], int, int, int]:
    """扫全部包的聚合契约，返回（问题列表, 参数总数, 参数违规数, 值结构违规数）。"""
    根 = 项目根 or 系统根
    契约文件表 = [文件 for 文件 in sorted(根.rglob("能力契约/参数契约.json"))
              if "工程缓存" not in 文件.as_posix()]
    问题表: list[str] = []
    参数总数 = 0
    for 契约文件 in 契约文件表:
        try:
            数据 = json.loads(契约文件.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        问题, 数 = 检查参数可用性(数据)
        相对 = 契约文件.relative_to(根).as_posix()
        问题表.extend(f"{相对}: {项}" for 项 in 问题)
        参数总数 += 数
    问题表.extend(f"产地可解析: {项}" for 项 in 检查产地可解析(契约文件表))
    参数违规数 = len(问题表)
    值结构问题: list[str] = []
    for 契约文件 in 契约文件表:
        try:
            数据 = json.loads(契约文件.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        相对 = 契约文件.relative_to(根).as_posix()
        值结构问题.extend(f"{相对}: {项}" for 项 in 检查值结构可用性(数据))
    问题表.extend(f"值结构: {项}" for 项 in 值结构问题)
    return 问题表, 参数总数, 参数违规数, len(值结构问题)


def 主函数() -> int:
    问题表, 参数总数, 违规数, 值结构违规数 = 体检()
    参数类问题 = [项 for 项 in 问题表 if not 项.startswith("值结构: ")]
    for 问题 in 参数类问题[:40]:
        print(f"  [违规] {问题}")
    if 违规数 > 40:
        print(f"  …（另有 {违规数 - 40} 条，见完整清单请去掉本口截断）")
    print(f"参数可用性体检：扫描参数 {参数总数} 个，违规 {违规数} 条；存量基线 {存量基线}")
    值结构问题 = [项 for 项 in 问题表 if 项.startswith("值结构: ")]
    for 问题 in 值结构问题[:20]:
        print(f"  [违规] {问题}")
    if 值结构违规数 > 20:
        print(f"  …（另有 {值结构违规数 - 20} 条裸返回/空值结构/裸值结构，见完整清单请去掉本口截断）")
    print(f"返回字段形状：裸返回 + 空值结构 + 裸值结构 {值结构违规数} 条；存量基线 {值结构存量基线}")
    退出码 = 0
    if 违规数 > 存量基线:
        print(f"⇒ 新增参数违规 {违规数 - 存量基线} 条（超出基线，判红）")
        退出码 = 1
    if 值结构违规数 > 值结构存量基线:
        print(f"⇒ 新增返回字段形状违规 {值结构违规数 - 值结构存量基线} 条（超出基线，判红）")
        退出码 = 1
    if 退出码 == 0:
        print("⇒ 两类均未超存量基线（存量冻结，只减不增）")
    return 退出码


