"""第 1／2 项：解释器与版本、平台与架构。

两项都只回答「本机能不能采出依赖锁『环境』字段要的三元组」——采不出来就建不了锁、
换平台后装配会被逐条拒绝；它们**不判「是否在支持范围内」**（准入判定归 校验支持范围）。"""

from __future__ import annotations

import sys
import platform as 平台模块

from 开发工具.环境自检.基础 import 结论_不支持, 结论_通过, 自检项, 期望Python主次版本


def 自检_解释器与版本() -> 自检项:
    主次 = (sys.version_info.major, sys.version_info.minor)
    版本 = f"{主次[0]}.{主次[1]}.{sys.version_info.micro}"
    在虚拟环境 = sys.prefix != sys.base_prefix
    详情 = {
        "版本": 版本, "主次版本": list(主次), "期望主次版本": list(期望Python主次版本),
        "解释器": sys.executable, "实现": sys.implementation.name,
        "在虚拟环境内": 在虚拟环境,
    }
    为什么 = ("运行核心.运行环境管理器.强制校验 规则 5 只比 Python 主次版本：3.14.x 与 3.14.y 算一致，"
              "3.13 与 3.14 直接判『环境指纹不符』。解释器不对，后面每一项都没意义。")
    if 主次 != 期望Python主次版本:
        return 自检项(
            "1", "解释器与版本", 结论_不支持,
            f"当前解释器是 Python {版本}（{sys.executable}），不是 3.14",
            为什么,
            "低于 3.14 会让装配 fail-closed：依赖锁『环境.Python』= 3.14.x，"
            "强制校验 直接拒绝，报错为『环境指纹不符：锁内 Python …  ≠ 当前 …』。"
            "请改用 3.14 解释器跑本入口与 README 的全部命令（如 python3.14 / 绝对路径解释器）。",
            详情,
        )
    return 自检项(
        "1", "解释器与版本", 结论_通过,
        f"Python {版本}（{sys.executable}）是 3.14，与依赖锁口径一致",
        为什么, "", 详情,
    )


def 自检_平台与架构() -> 自检项:
    from 公共契约.运行时 import 平台适配
    from 运行核心.环境指纹 import 计算环境指纹

    原始标志 = 平台适配.原始平台标志()
    平台名 = 平台适配.当前平台()
    指纹 = 计算环境指纹(含外部应用=False).详细信息
    架构 = str(指纹.get("架构", "")).strip()
    机器 = 平台模块.machine()
    为什么 = ("依赖锁的『环境』字段是 Python / 操作系统 / CPU 三元组（操作系统只比系统大类、"
              "CPU 架构要求精确一致）。这三个值全部由 平台适配 + 环境指纹 采样，本项就是看"
              "本机能不能把这三个值采出来——采不出来就建不了锁，也就没法在换平台后重跑。")
    详情 = {
        "sys.platform": 原始标志, "平台": 平台名, "架构": 架构,
        "platform.machine()": 机器, "平台表": list(平台适配.平台表),
        "是Windows": 平台适配.是Windows(), "是macOS": 平台适配.是macOS(),
        "是Linux": 平台适配.是Linux(), "是POSIX": 平台适配.是POSIX(),
    }
    问题表: list[str] = []
    if 平台名 == "未知":
        问题表.append(
            f"平台名判定为『未知』（sys.platform={原始标志!r}）：依赖锁的『环境.操作系统』"
            f"采不出可写锁的值（开发工具.重建依赖锁.采样环境 会拒绝写锁）")
    if not 架构:
        问题表.append("环境指纹的『架构』为空：依赖锁 CPU 字段要求精确一致，采不到就没法重建锁")
    if 架构 and 机器 and 架构 != 机器:
        问题表.append(f"架构自相矛盾：环境指纹 {架构!r} ≠ platform.machine() {机器!r}")
    if 问题表:
        return 自检项("2", "平台与架构", 结论_不支持, "；".join(问题表), 为什么,
                    "依赖锁无法按本机重建 → 换平台后装配会被 强制校验 逐条拒绝（fail-closed）。",
                    详情)
    return 自检项(
        "2", "平台与架构", 结论_通过,
        f"平台 {平台名}（sys.platform={原始标志}）／CPU {架构}；"
        f"这就是依赖锁『环境』字段要写进去的三元组里的两个",
        为什么, "", 详情,
    )
