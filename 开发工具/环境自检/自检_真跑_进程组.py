"""第 5.1 项：真跑一次独立进程组全链（起组→探活→按组号终止→回收→死透）。

「接口在、语义对」不等于「整链在本机跑得通」；跨平台分支最容易错的就是这里，
所以本项真起子进程、真探活、真强杀、真确认回收。"""

from __future__ import annotations

import subprocess
import sys

from 开发工具.环境自检.基础 import 结论_不支持, 结论_通过, 自检项, _进程组启动参数


def 自检_进程组真跑() -> 自检项:
    from 公共契约.运行时 import 平台适配, 进程终止

    为什么 = ("上面 4.x 只验了语义；这一项**真起一个子进程组、真探活、真按组号终止、真确认回收**。"
              "『接口在、语义对』不等于『整链在本机跑得通』——跨平台分支最容易错的就是这里。")
    步骤: list[str] = []
    子: subprocess.Popen | None = None
    try:
        子 = subprocess.Popen(
            [sys.executable, "-c", "import time; time.sleep(600)"],
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            **_进程组启动参数())
        步骤.append(f"1) 用 平台适配.子进程组启动标志() 起了子进程组：PID={子.pid}")
        组号 = 进程终止.进程组号(子)
        if 组号 is None:
            return 自检项("5.1", "收口层真跑：起组→探活→终止→回收", 结论_不支持,
                        f"平台 {平台适配.当前平台()} 拿不到进程组号 → 按组号整链不可用",
                        为什么, "Windows 上只能走 taskkill 整树终止（未真机验证），本项在真机验证过前不能算通过。",
                        {"步骤": 步骤})
        if 组号 != 子.pid:
            return 自检项("5.1", "收口层真跑：起组→探活→终止→回收", 结论_不支持,
                        f"子进程没有独占进程组：组号 {组号} ≠ 子进程号 {子.pid}，"
                        f"终止范围会波及父进程组",
                        为什么, "组没独立 → 按组号终止会连带杀掉自己/同组进程（危险）。",
                        {"步骤": 步骤})
        步骤.append(f"2) 进程组号={组号}（== 组长 PID：独立进程组确实建起来了）")
        if not 进程终止.按组号探活(组号):
            return 自检项("5.1", "收口层真跑：起组→探活→终止→回收", 结论_不支持,
                        "按组号探活 对自己刚起的组返回 False → 探活原语在本机不可用",
                        为什么, "探活错 → 回收后无法判断是否真的死透。", {"步骤": 步骤})
        步骤.append("3) 按组号探活 → True")
        终止 = 进程终止.按组号终止(组号, 信号="强杀")
        结论值 = ((终止.值 or {}).get("结论") if 终止.成功 else 终止.错误码)
        if 结论值 not in (进程终止.结论_已终止, 进程终止.结论_进程不存在):
            return 自检项("5.1", "收口层真跑：起组→探活→终止→回收", 结论_不支持,
                        f"按组号终止未成功：{终止.错误码} {终止.错误说明}",
                        为什么, "整组终止不可用 → 子孙进程会逃逸（最常见的是转码/OCR 的子进程残留）。",
                        {"步骤": 步骤})
        步骤.append(f"4) 按组号终止(强杀) → {结论值}：{(终止.值 or {}).get('说明', '')}")
        try:
            退出码 = 子.wait(timeout=5)
        except subprocess.TimeoutExpired:
            return 自检项("5.1", "收口层真跑：起组→探活→终止→回收", 结论_不支持,
                        "强杀后 5 秒内子进程仍未退出（回收不成立）",
                        为什么, "回收不成立就是进程泄漏。", {"步骤": 步骤})
        步骤.append(f"5) 子进程已回收：退出码={退出码}（POSIX 被 SIGKILL 杀为 -9）")
        if 进程终止.进程存活(子.pid):
            return 自检项("5.1", "收口层真跑：起组→探活→终止→回收", 结论_不支持,
                        f"回收后 进程存活({子.pid}) 仍为 True（僵尸或漏杀）",
                        为什么, "『死透』判定不成立 → 上层会反复重试回收。", {"步骤": 步骤})
        步骤.append(f"6) 回收后 进程存活({子.pid}) → False（死透）")
        子 = None
        if not 进程终止.按组号探活(组号):
            步骤.append("7) 整组已消失：按组号探活 → False")
        else:
            步骤.append("7) 注意：整组仍被判存活（按组号探活 True）——组长已回收但组内可能仍有成员")
        return 自检项("5.1", "收口层真跑：起组→探活→终止→回收", 结论_通过,
                    "全链真执行并成立：起独立进程组 → 按组号探活 True → 按组号终止 → 已回收 → 死透",
                    为什么, "", {"步骤": 步骤})
    finally:
        if 子 is not None and 子.poll() is None:
            进程终止.强制结束子进程(子, 宽限秒=0.2, 等待秒=3.0)
