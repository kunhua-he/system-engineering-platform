"""收口层能力探测：虚拟环境解释器布局、句柄枚举目录、目录可列性。

判据是「本机真实布局与平台判定是否一致」，不是「函数存在」——布局判错会让隔离环境
恒判『环境缺失』、句柄数无法采样（详见各项 docstring）。"""

from __future__ import annotations

import os
from pathlib import Path

from 公共契约.基础类型.逻辑类型 import 真, 假
from 开发工具.环境自检.基础 import 结论_不支持, 结论_通过, 自检项


def _探_虚拟环境解释器路径() -> 自检项:
    from 公共契约.运行时 import 平台适配

    相对 = 平台适配.虚拟环境解释器相对路径()
    路径 = 平台适配.虚拟环境解释器路径("/示例环境根")
    期望 = "Scripts/python.exe" if os.name == "nt" else "bin/python3"
    拼接对 = 路径 == Path("/示例环境根") / 相对
    一致 = 相对 == 期望
    详情 = {"相对路径": 相对, "拼接结果": str(路径), "os.name": os.name,
            "本机解释器布局期望值": 期望, "拼接一致": 拼接对, "平台判定一致": 一致}
    为什么 = ("强制校验 规则 6 用 平台适配.虚拟环境解释器路径(环境目录) 判『独立受管环境是否就绪』，"
              "硬编码 POSIX 布局会让非 POSIX 平台恒判『环境缺失』，每个 pip 提供者都在装配期报不可用。")
    if not (拼接对 and 一致):
        return 自检项("4.2", "平台适配.虚拟环境解释器路径()", 结论_不支持,
                    f"平台判定给 {相对!r}，但本机解释器布局是 {期望!r}（os.name={os.name}）；"
                    f"拼接结果 {路径}",
                    为什么, "隔离环境恒判『环境缺失』→ 所有 pip 提供者在装配期不可用（fail-closed）。",
                    详情)
    return 自检项("4.2", "平台适配.虚拟环境解释器路径()", 结论_通过,
                f"{相对}（与本机 os.name={os.name} 的布局一致），拼接：{路径}", 为什么, "", 详情)


def _探_句柄枚举目录表() -> 自检项:
    from 公共契约.运行时 import 平台适配

    目录表 = 平台适配.句柄枚举目录表()
    可枚举 = [目录 for 目录 in 目录表
             if os.path.isdir(目录) and _可列目录(目录)]
    详情 = {"候选": list(目录表), "可枚举": 可枚举, "是Windows": 平台适配.是Windows()}
    为什么 = ("句柄数采样（资源占用诊断）只能靠 POSIX 的 /proc/self/fd 或 /dev/fd。"
              "空元组是平台模块给出的『本平台无此能力』显式信号——调用方必须据此报不支持，"
              "不得报 0 冒充真实值。")
    if not 目录表:
        return 自检项("4.3", "平台适配.句柄枚举目录表()", 结论_不支持,
                    "本平台无 /proc 与 /dev 等价目录（返回空元组）→ 句柄数无法采样",
                    为什么, "资源诊断在这一项如实报『不支持』而不是报 0；相关巡检项会缺一列。",
                    详情)
    if not 可枚举:
        return 自检项("4.3", "平台适配.句柄枚举目录表()", 结论_不支持,
                    f"候选 {list(目录表)} 一个都列不出来 → 句柄数采样不可用",
                    为什么, "同上：资源诊断会缺一列（但不能靠 0 冒充）。", 详情)
    return 自检项("4.3", "平台适配.句柄枚举目录表()", 结论_通过,
                f"可枚举：{可枚举}", 为什么, "", 详情)


def _可列目录(目录: str) -> bool:
    try:
        os.listdir(目录)
        return 真
    except OSError:
        return 假
