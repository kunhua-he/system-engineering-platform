"""第 4 项：收口层能力探测的编排（十个探针逐个真试）。

每个探针单独隔离（`_安全执行`）：一个探针抛异常只让它自己报【不支持】，
不许把其余九项一起吞掉（否则一台机器上只看得见一条报错，看不见全貌）。"""

from __future__ import annotations

from collections.abc import Callable

from 开发工具.环境自检.基础 import 自检项, _安全执行
from 开发工具.环境自检.探测_内存与POSIX能力 import _探_内存峰值原始单位, _探_要求POSIX能力
from 开发工具.环境自检.探测_环境能力 import (
    _探_句柄枚举目录表, _探_虚拟环境解释器路径)
from 开发工具.环境自检.探测_进程终止 import (
    _探_按组号终止_参数与幂等, _探_强制结束子进程_参数与幂等)
from 开发工具.环境自检.探测_进程组 import (
    _探_子进程组启动标志, _探_按组号探活, _探_进程存活, _探_进程组号)


_收口层为什么 = ("收口层（平台适配 + 进程终止）是全部调用点唯一的平台分支来源；"
              "它一旦在本机不可用或语义不对，受影响的是装载/调度/隔离环境/回收整条链，"
              "而且多为静默错（不报错、结果偏）。所以这里逐个函数真试，不接受「函数存在」当结论。")


def 自检_收口层能力() -> list[自检项]:
    """逐个真试收口层关键函数；POSIX 专有的在非 POSIX 上应得明确的平台不支持，而不是崩。

    每个探针单独隔离（`_安全执行`）：一个探针抛异常只让它自己报【不支持】，
    不许把其余 9 项一起吞掉（否则一台机器上只看得见一条报错，看不见全貌）。
    """
    探针表: tuple[tuple[str, str, Callable[[], 自检项]], ...] = (
        ("4.1", "平台适配.子进程组启动标志()", _探_子进程组启动标志),
        ("4.2", "平台适配.虚拟环境解释器路径()", _探_虚拟环境解释器路径),
        ("4.3", "平台适配.句柄枚举目录表()", _探_句柄枚举目录表),
        ("4.4", "平台适配.内存峰值原始单位()", _探_内存峰值原始单位),
        ("4.5", "平台适配.要求POSIX能力()", _探_要求POSIX能力),
        ("4.6", "进程终止.进程存活()", _探_进程存活),
        ("4.7", "进程终止.进程组号()", _探_进程组号),
        ("4.8", "进程终止.按组号探活()", _探_按组号探活),
        ("4.9", "进程终止.按组号终止()", _探_按组号终止_参数与幂等),
        ("4.10", "进程终止.强制结束子进程()", _探_强制结束子进程_参数与幂等),
    )
    项表: list[自检项] = []
    for 序号, 名称, 函数 in 探针表:
        项表.extend(_安全执行(序号, 名称, 函数))
    return 项表
