    项表.extend(_安全执行("2", "平台与架构", 自检_平台与架构))
    项表.extend(_安全执行("3", "依赖锁一致性（干跑）", 自检_依赖锁一致性))
    项表.extend(_安全执行("4", "收口层能力探测", 自检_收口层能力))
    项表.extend(_安全执行("5.1", "收口层真跑：起组→探活→终止→回收", 自检_进程组真跑))
    项表.extend(_安全执行("5.2", "收口层真跑：优雅→宽限→强杀升级", 自检_强制结束真跑))
    项表.extend(_安全执行("6.1", "POSIX 专有参数 dir_fd=", 自检_dirfd))
    项表.extend(_安全执行("6.2", "POSIX 专有参数 preexec_fn=", 自检_preexec_fn))
