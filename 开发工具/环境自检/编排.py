def _行宽(文本: str, 宽度: int) -> str:
    """按显示宽度补齐（中文算 2 列），让逐项输出对得齐。"""
    显示宽 = sum(2 if ord(字符) > 0x2E7F else 1 for 字符 in 文本)
    填充 = max(0, 宽度 - 显示宽)
    return 文本 + " " * 填充
