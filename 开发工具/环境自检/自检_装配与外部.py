"""第 8／9 项：装配冒烟（README 三条断言）与外部命令可用性。

第 8 项带**安全闸**：平台判定与实际解释器布局矛盾时拒绝执行真实装配（按错误判定跑装配
会把本机有效的受管环境删掉）。第 9 项的结论上限就是【警告】，不阻断、不影响退出码。"""

from __future__ import annotations

import os
import shutil
import sys
import time
from pathlib import Path

from 公共契约.基础类型.逻辑类型 import 假
from 开发工具.环境自检.基础 import (
    结论_不支持, 结论_通过, 结论_警告, 外部命令表, 系统根, 自检项, _截断)


def 自检_装配冒烟() -> 自检项:
    为什么 = ("README『部署』第 3 步的冒烟三条断言（装配成功、能力数 > 0、无跳过包）是"
              "『这台机器到底能不能跑起来』的唯一判据。这里直接复刻它，避免使用者抄错命令，"
              "也避免用『打印出 0 个能力也算过』的假绿写法。")
    根 = 系统根()
    切换说明 = ""
    if Path.cwd() != 根:
        os.chdir(根)  # 对齐 README 口径：命令都在仓库根执行，后端核心(Path("."))
        切换说明 = f"（原工作目录不是仓库根，已切到 {根} 以对齐 README 口径）"
    # 安全闸（必须放在真跑装配之前）：平台判定与实际解释器布局矛盾时，绝不能让真实装配去跑。
    # 装配会按（错误的）平台判定去校验/重建 工程缓存/提供者运行环境 下的受管环境，
    # 实测后果是**把本机有效的受管环境删掉**（模拟平台跑一次即复现，需联网重新安装依赖才能恢复）。
    # 自检的职责是"报告本机能不能跑"，不是"把机器跑坏"，所以这里拒绝执行并说明原因。
    from 公共契约.运行时 import 平台适配

    期望布局 = "Scripts/python.exe" if os.name == "nt" else "bin/python3"
    实际判定 = 平台适配.虚拟环境解释器相对路径()
    if 实际判定 != 期望布局:
        return 自检项(
            "8", "装配冒烟（后端核心.启动()）", 结论_不支持,
            f"平台判定与实际布局矛盾（平台判定 {实际判定!r}，本机 os.name={os.name} 的布局是 "
            f"{期望布局!r}）：拒绝执行真实装配，本项未验证",
            为什么,
            "按错误的平台判定去跑装配，会把它当作『受管环境缺失/损坏』并重建："
            "重建过程会先删掉 工程缓存/提供者运行环境/<提供者>/<摘要> 下已有的有效环境，"
            "本仓实测会因此把本机环境删掉（要联网重新安装第三方依赖才能恢复）。"
            "先把平台判定改回本机真实平台（sys.platform / 平台适配）再重跑本入口。",
            {"平台判定": 实际判定, "本机期望布局": 期望布局, "os.name": os.name,
             "sys.platform": sys.platform},
        )
    from 后端核心.后端核心 import 后端核心

    开始 = time.monotonic()
    后端 = 后端核心(Path("."))
    装配 = 后端.启动()
    快照 = 后端.状态快照()
    耗时 = round(time.monotonic() - 开始, 2)
    状态 = 快照["状态"]
    能力数 = 快照["能力数"]
    跳过 = list(快照["装配跳过包"])
    问题表: list[str] = []
    if not 装配.成功:
        问题表.append(f"装配失败（{装配.错误码}）：{_截断(装配.错误说明, 600)}")
    if 能力数 <= 0:
        问题表.append(f"能力数为 {能力数}：一个能力都没装配出来，不能算能跑")
    if 跳过:
        问题表.append(f"有 {len(跳过)} 个包被跳过：" + "；".join(跳过[:5]))
    if 状态 != "运行中":
        问题表.append(f"状态是 {状态!r}（期望 运行中）")
    详情 = {"状态": 状态, "能力数": 能力数, "跳过包数": len(跳过), "跳过包": 跳过[:20],
            "耗时秒": 耗时, "工作目录": str(Path.cwd()), "切换说明": 切换说明,
            "启动结果": {"成功": 装配.成功, "错误码": 装配.错误码, "错误说明": 装配.错误说明}}
    try:
        关闭 = 后端.优雅关闭()
        详情["优雅关闭"] = {"成功": 关闭.成功, "错误码": 关闭.错误码}
    except Exception as 错误:  # noqa: BLE001
        详情["优雅关闭"] = {"成功": 假, "异常": f"{type(错误).__name__}: {错误}"}
    if 问题表:
        return 自检项("8", "装配冒烟（后端核心.启动()）", 结论_不支持,
                    _截断(f"{耗时}s 内装配未过：{'；'.join(问题表)}{切换说明}", 1200), 为什么,
                    "装配不过就是这台机器还跑不起来（README 第 4 步的常驻网关也一样起不来）；"
                    "先看上面『跳过包』点名了哪个包，再按 开发文档/新建支持库与模块指南 第 8 节排查。",
                    详情)
    return 自检项("8", "装配冒烟（后端核心.启动()）", 结论_通过,
                f"{耗时}s 装配成功：状态={状态}、能力数={能力数}、跳过包 0 个{切换说明}",
                为什么, "", 详情)


def 自检_外部命令() -> 自检项:
    为什么 = ("这些命令不是 Python 包，pip 装不出来：缺了只影响对应提供者的能力（转码/OCR/"
              "文档转换/版本控制），不影响底座装配。所以本项**只提示不阻断**——"
              "但必须让使用者一眼看到『这台机器哪些能力不可用』，而不是等调用时报错。")
    命中表: dict[str, str | None] = {}
    缺失: list[str] = []
    for 候选, 用途 in 外部命令表:
        找到 = None
        for 名 in 候选:
            try:
                找到 = shutil.which(名)
            except Exception:  # noqa: BLE001 — 本项不阻断，探测异常一律当「没找到」
                找到 = None
            if 找到:
                break
        命中表[" 或 ".join(候选)] = 找到
        if 找到 is None:
            缺失.append(f"{' 或 '.join(候选)}（{用途}）")
    详情 = {"命令": 命中表, "缺失": 缺失}
    # 结论上限就是【警告】：外部命令缺失不是缺陷，绝不能把整轮自检拖成非零退出
    if 缺失:
        return 自检项("9", "外部命令可用性", 结论_警告,
                    f"{len(外部命令表) - len(缺失)}/{len(外部命令表)} 项可用；缺：" + "；".join(缺失),
                    为什么,
                    "对应能力在该机器上不可用（**非缺陷**）：装好对应命令即可恢复，"
                    "平台本体与装配不受影响（本项不影响退出码）。",
                    详情)
    return 自检项("9", "外部命令可用性", 结论_通过,
                f"{len(外部命令表)}/{len(外部命令表)} 项可用：" +
                "、".join(名 for 名, 路 in 命中表.items() if 路), 为什么, "", 详情)
