def _探_进程组号() -> 自检项:
    from 公共契约.运行时 import 平台适配, 进程终止

    组号 = 进程终止.进程组号(os.getpid())
    详情 = {"进程组号(本进程)": 组号, "平台": 平台适配.当前平台(), "是POSIX": 平台适配.是POSIX()}
    为什么 = ("`os.getpgid` 是 POSIX 专有；Windows 上 进程组号 如实返回 None。"
              "有组号才有『按组号探活/按组号终止』（组长被回收后仍能管住同组子孙）。")
    if not 平台适配.是POSIX():
        return 自检项("4.7", "进程终止.进程组号()", 结论_不支持,
                    f"平台 {平台适配.当前平台()} 无进程组号概念（返回 {组号!r}）："
                    f"按组号探活/终止整条链不可用",
                    为什么,
                    "Windows 上只能走 taskkill 整树终止（本仓诚实标注：该分支未真机验证）；"
                    "『组长退出但子孙仍在』的场景在本平台无法按组号收口。",
                    详情)
    if not (isinstance(组号, int) and not isinstance(组号, bool) and 组号 > 0):
        return 自检项("4.7", "进程终止.进程组号()", 结论_不支持,
                    f"POSIX 平台却拿不到正整数组号：{组号!r}",
                    为什么, "按组号的原语全部失效，回收到不了子孙进程。", 详情)
    return 自检项("4.7", "进程终止.进程组号()", 结论_通过,
                f"进程组号(本进程)={组号}（正整数）", 为什么, "", 详情)


def _探_按组号探活() -> 自检项:
    from 公共契约.运行时 import 进程终止

    组号 = 进程终止.进程组号(os.getpid())
    为什么 = ("`os.getpgid(pid)` 在组长被 wait() 回收后抛 ProcessLookupError，而"
              "`os.killpg(组号, 0)` 仍能探到组存在——『组长退出、同组子孙仍在』这类语义"
              "只有按组号的原语能表达。")
    详情 = {"本进程组号": 组号, "按组号探活(本进程组)": None if 组号 is None else 进程终止.按组号探活(组号),
            "按组号探活(不存在的组)": 进程终止.按组号探活(2 ** 31 - 1),
            "按组号探活(-1)": 进程终止.按组号探活(-1)}
    if 组号 is None:
        return 自检项("4.8", "进程终止.按组号探活()", 结论_不支持,
                    "本平台拿不到进程组号 → 按组号探活不可用（Windows 恒 False）",
                    为什么, "同 4.7：整组回收与『子孙仍在』判定不可用。", 详情)
    if 详情["按组号探活(本进程组)"] is not True or 详情["按组号探活(不存在的组)"] is not False:
        return 自检项("4.8", "进程终止.按组号探活()", 结论_不支持,
                    f"语义不对：自己所在的组={详情['按组号探活(本进程组)']!r}（期望 True）、"
                    f"不存在的组={详情['按组号探活(不存在的组)']!r}（期望 False）",
                    为什么, "组存活判据错 → 回收后会误报『仍有子孙活着』或漏报。", 详情)
    return 自检项("4.8", "进程终止.按组号探活()", 结论_通过,
                "自己所在的组→True、不存在的组→False、非法组号→False", 为什么, "", 详情)
