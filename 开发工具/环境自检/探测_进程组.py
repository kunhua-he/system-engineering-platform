"""收口层能力探测：独立进程组语义（启动标志、进程存活、组号、按组号探活）。

这四项是「按组号终止／连孙进程一起回收」的地基：判据错会静默杀错范围或谎报死透，
所以每项都验真实语义（自己→真、不存在的进程/组→假、非法入参不抛异常）。"""

from __future__ import annotations

import os

from 开发工具.环境自检.基础 import 结论_不支持, 结论_通过, 自检项, _喂非法入参


def _探_子进程组启动标志() -> 自检项:
    from 公共契约.运行时 import 平台适配

    标志 = 平台适配.子进程组启动标志()
    是Windows = 平台适配.是Windows()
    详情 = {"返回": {键: 值 for 键, 值 in 标志.items()}, "是Windows": 是Windows}
    if 是Windows:
        值 = 标志.get("creationflags")
        好 = isinstance(值, int) and not isinstance(值, bool) and 值 > 0
        return 自检项(
            "4.1", "平台适配.子进程组启动标志()", 结论_通过 if 好 else 结论_不支持,
            f"Windows 形态：creationflags={值!r}" + ("" if 好 else "（不是正整数 → 子进程会留在父进程组里）"),
            "独立进程组是一切『按组号终止/连孙进程一起回收』的前提。",
            "取值不对 → 终止范围错（杀不干净或误伤父进程组），且不会报错。", 详情)
    好 = 标志.get("start_new_session") is True and "creationflags" not in 标志
    return 自检项(
        "4.1", "平台适配.子进程组启动标志()", 结论_通过 if 好 else 结论_不支持,
        f"POSIX 形态：{标志!r}" + ("" if 好 else "（期望 {'start_new_session': True}）"),
        "独立进程组是一切『按组号终止/连孙进程一起回收』的前提。",
        "取值不对 → 终止范围错（杀不干净或误伤父进程组），且不会报错。", 详情)


