"""收口层能力探测：两个终止原语的**参数收口与幂等**（永不抛异常）。

按组号终止与强制结束子进程被全仓几十处调用点共用，契约是「非法入参→参数错误失败结果、
不存在的目标→幂等成功」。这两项就是真喂坏入参、真拿已结束进程去验。"""

from __future__ import annotations

import subprocess
import sys

from 开发工具.环境自检.基础 import 结论_不支持, 结论_通过, 自检项, _喂非法入参, _进程组启动参数


def _探_按组号终止_参数与幂等() -> 自检项:
    from 公共契约.运行时 import 进程终止

    为什么 = ("按组号终止 是『组长已被回收、同组子孙仍在』时唯一能用的终止原语，"
              "契约是**永不抛异常**：非法入参→参数错误失败结果，不存在的组→进程不存在（幂等成功）。")
    坏参 = 进程终止.按组号终止(-1)
    不存在 = 进程终止.按组号终止(2 ** 31 - 1, 信号="强杀")
    详情 = {
        "按组号终止(-1)": {"成功": 坏参.成功, "错误码": 坏参.错误码, "错误说明": 坏参.错误说明},
        "按组号终止(不存在的组, 强杀)": {
            "成功": 不存在.成功, "错误码": 不存在.错误码,
            "结论": (不存在.值 or {}).get("结论") if 不存在.成功 else None},
    }
    问题: list[str] = []
    if 坏参.成功 or 坏参.错误码 != 进程终止.结论_参数错误:
        # 非法入参必须失败且是「参数错误」
        问题.append(f"非法入参没有收口成『参数错误』：成功={坏参.成功} 错误码={坏参.错误码!r}")
    成功类 = (进程终止.结论_已终止, 进程终止.结论_进程不存在)
    结论值 = (不存在.值 or {}).get("结论") if 不存在.成功 else 不存在.错误码
    if 结论值 not in 成功类:
        问题.append(f"对不存在的组没走幂等路径，而是 {结论值!r}：{不存在.错误说明}")
    if 问题:
        return 自检项("4.9", "进程终止.按组号终止()", 结论_不支持, "；".join(问题),
                    为什么, "约束错会让调用点拿到异常或假成功，回收链断在这里。", 详情)
    return 自检项("4.9", "进程终止.按组号终止()", 结论_通过,
                f"非法入参→参数错误（不抛异常）；不存在的组→{结论值}（幂等）",
                为什么, "", 详情)


def _探_强制结束子进程_参数与幂等() -> 自检项:
    from 公共契约.运行时 import 进程终止

    为什么 = ("41 处调用点都要接这个统一形状（优雅→宽限→强杀→复查）。它接受 Popen 句柄或裸"
              "进程号，对坏入参必须给失败结果、对已结束进程必须幂等成功，**不能抛异常**"
              "（一处抛错波及全部调用方）。")
    坏参 = [_喂非法入参(进程终止.强制结束子进程, 参) for 参 in ("不是进程", True, 0)]
    已退出 = subprocess.Popen(
        [sys.executable, "-c", "pass"],
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        **_进程组启动参数())
    已退出.wait(timeout=30)
    幂等 = 进程终止.强制结束子进程(已退出)
    详情 = {
        "坏入参": [{"入参": 参, "成功": 果.成功, "错误码": 果.错误码} for 参, 果 in
                 zip(("不是进程", True, 0), 坏参)],
        "已结束句柄": {"成功": 幂等.成功, "错误码": 幂等.错误码,
                     "结论": (幂等.值 or {}).get("结论") if 幂等.成功 else None},
    }
    问题: list[str] = []
    for 参, 果 in zip(("不是进程", True, 0), 坏参):
        if 果.成功 or 果.错误码 != 进程终止.结论_参数错误:
            问题.append(f"坏入参 {参!r} 没收口成『参数错误』（成功={果.成功} 错误码={果.错误码!r}）")
    结论值 = (幂等.值 or {}).get("结论") if 幂等.成功 else 幂等.错误码
    if 结论值 not in (进程终止.结论_进程不存在, 进程终止.结论_已终止):
        问题.append(f"对已结束的句柄不幂等：{结论值!r}：{幂等.错误说明}")
    if 问题:
        return 自检项("4.10", "进程终止.强制结束子进程()", 结论_不支持, "；".join(问题),
                    为什么, "参数/幂等收口不成立 → 调用方要么抛异常要么误判已清理。", 详情)
    return 自检项("4.10", "进程终止.强制结束子进程()", 结论_通过,
                f"3 种坏入参→参数错误；已结束的句柄→{结论值}（幂等）", 为什么, "", 详情)
