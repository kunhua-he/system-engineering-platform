"""第 3 项：依赖锁一致性（走 `开发工具.重建依赖锁` 的干跑口径，只报不写）。

本项不另立第二套环境采样：同一把尺子（重建依赖锁.评估单锁）算「有几份锁与当前环境
不一致」，让使用者换平台后先看见要重建几份。"""

from __future__ import annotations

import json
from collections import Counter
from typing import Any

from 开发工具.环境自检.基础 import 结论_不支持, 结论_通过, 自检项


def 自检_依赖锁一致性() -> 自检项:
    from 开发工具 import 重建依赖锁 as 锁工具

    全部锁 = 锁工具.枚举依赖锁()
    本机环境 = 锁工具.采样环境()
    探针 = 锁工具.采样外部工具版本()
    为什么 = ("README『换平台』一节的核心：仓库里 32 份 `依赖锁.json` 写死了生成机指纹，"
              "换平台不重建就会在装配期被 强制校验 规则 5 逐条拒绝。本项直接调用"
              "`开发工具/重建依赖锁.py` 的干跑能力（评估单锁，不写盘），把『需重建几份』"
              "算给使用者看。")

    if not 全部锁:
        return 自检项("3", "依赖锁一致性", 结论_不支持,
                    "支持库/模块库/技能库 下一份 依赖锁.json 都没发现，无法验证环境一致性",
                    为什么, "仓库不完整（少目录或少了锁文件），装配无从谈起。", {})

    需重建: list[dict[str, Any]] = []
    拒绝: list[str] = []
    锁内环境计数: Counter[str] = Counter()
    for 锁路径 in 全部锁:
        报告 = 锁工具.评估单锁(锁路径, 本机环境, None, 探针)
        锁内环境计数[json.dumps(报告["原环境"], ensure_ascii=False, sort_keys=True)] += 1
        if 报告["问题"]:
            拒绝.append(f"{报告['锁']}: {'；'.join(报告['问题'])}")
        elif 报告["需重建"]:
            需重建.append({"锁": 报告["锁"], "环境差异": 报告["环境差异"]})
    多数锁内环境 = json.loads(锁内环境计数.most_common(1)[0][0]) if 锁内环境计数 else {}
    详情 = {
        "锁总数": len(全部锁), "本机环境": 本机环境, "多数锁内环境": 多数锁内环境,
        "需重建数": len(需重建), "拒绝重建数": len(拒绝),
        "需重建清单": 需重建[:20], "拒绝清单": 拒绝[:20],
        "锁内环境分布": dict(锁内环境计数),
    }
    if 需重建 or 拒绝:
        头部 = (f"{len(需重建)}/{len(全部锁)} 份依赖锁与当前环境不一致"
                + (f"，另有 {len(拒绝)} 份拒绝重建" if 拒绝 else ""))
        样例 = "；".join(
            f"{项['锁']}（{'，'.join(项['环境差异'])}）" for 项 in 需重建[:3])
        return 自检项(
            "3", "依赖锁一致性", 结论_不支持,
            f"{头部}。" + (f"示例：{样例}" if 样例 else "") +
            (f" 拒绝明细：{'；'.join(拒绝[:3])}" if 拒绝 else ""),
            为什么,
            "换平台后不重建锁，装配会被 运行核心.运行环境管理器.强制校验 规则 5 按"
            "『环境指纹不符』逐条拒绝（fail-closed，不是降级）。先跑："
            "python3.14 -m 开发工具.重建依赖锁 --写入 --全部（本入口只报不写）。",
            详情,
        )
    return 自检项(
        "3", "依赖锁一致性", 结论_通过,
        f"{len(全部锁)}/{len(全部锁)} 份依赖锁与当前环境一致（干跑：需重建 0 份）；"
        f"锁内环境 {json.dumps(多数锁内环境, ensure_ascii=False)}",
        为什么, "", 详情,
    )
