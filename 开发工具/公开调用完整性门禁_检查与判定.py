#: 页面 JSON 的目录段（相对仓根取末两段：`.../前端/页面/<页面>.json`）。
页面目录段 = ("前端", "页面")
#: 页面目录里以这两个名字落盘的 JSON 是编译产物/编辑留痕，不是设计态页面。
页面生成物文件名 = frozenset({"编译制品.json", "编辑记录.json"})


def 收集内部层能力(根: Path) -> list[dict]:
    """全仓 `包声明.json` 里 `内部层=真` 的能力清单（含聚合视图父包：它同样可能声明能力）。

    「内部层」字段的口径唯一源是 `公共契约/包声明/声明.解析包声明`（`内部层=bool(数据.get(...))`），
    本处按同一口径只读字段，不 import 装配层（与 `运行核心/依赖防火墙._所在包是内部层` 同读法）。
    包发现走 `找全部包目录`（唯一入口，E-2 起含全部正式根）：聚合视图父包也参与 ——
    它声明了能力就是真实 owner，不能靠「视图」身份把第二面整体移出扫描。
    """
    出: list[dict] = []
    for 包目录 in 找全部包目录(根):
        声明路径 = 包目录 / "包声明.json"
        声明值, 诊断 = 读取json带诊断(声明路径)
        if 诊断 is not None or not isinstance(声明值, dict):
            continue
        if not bool(声明值.get(内部层字段名, 假)):
            continue
        try:
            相对包 = 包目录.relative_to(根).as_posix()
        except ValueError:
            相对包 = 包目录.as_posix()
        for 能力 in 声明值.get("能力") or []:
            if not isinstance(能力, dict):
                continue
            能力id = str(能力.get("能力id") or "").strip()
            if not 能力id:
                continue
            出.append({"能力id": 能力id, "包": 相对包, "路径": 声明路径})
    return 出


def _页面扫描剪枝(根: Path) -> bool:
    """页面扫描是否**进目录即剪枝**生成式目录：真仓库必剪，夹具根不剪。

    为什么必须分档：`遍历源码` 的剪枝判据是**绝对路径**逐段比对 `生成式目录表`，
    而测试夹具的受管临时根就在 `<仓库>/工程缓存/测试临时/` 下 ⇒ 夹具根会被整棵剪掉，
    新判据在夹具上永远测不出来（平台纪律：新判据必须能在夹具上测出来）。变的只是
    代价开关（真仓库不剪 = 白走 `工程缓存` 30 万条），**什么算页面两档逐字一致**。
    """
    return 根.resolve() == 仓库根.resolve()


def 页面引用能力id集(根: Path) -> dict[str, list[str]]:
    """页面 JSON 里被引用的能力 id → 引用它的页面文件（仓根相对路径，升序去重）。

    扫描面 = 仓内 `<任意层>/前端/页面/*.json`；遍历走唯一入口
    `公共契约.正式根.遍历源码`（**进目录即剪枝**生成式目录：`工程缓存`/`.git`/`归档`/
    `参考资料`…）—— 生成物与归档不是设计态页面，扫它们只会把编译输出当契约。
    跳过 `编译制品.json`/`编辑记录.json`（编译产物与编辑留痕，不是页面定义）。
    """
    from 公共契约.正式根 import 源码层名表, 遍历源码

    出: dict[str, list[str]] = {}
    for 文件 in 遍历源码(根, 后缀=(".json",), 层名表=源码层名表, 剪枝=_页面扫描剪枝(根)):
        if 文件.name in 页面生成物文件名:
            continue
        try:
            相对 = 文件.relative_to(根)
        except ValueError:
            continue
        if tuple(相对.parts[-3:-1]) != 页面目录段:
            continue
        页面值, 诊断 = 读取json带诊断(文件)
        if 诊断 is not None or not isinstance(页面值, dict):
            continue
        页面路径 = 相对.as_posix()
        for 组件 in 页面值.get("组件列表") or []:
            if not isinstance(组件, dict):
                continue
            属性 = 组件.get("属性")
            引用: list[str] = []
            if isinstance(属性, dict):
                引用.append(str(属性.get("能力id") or "").strip())
            for 事件项 in 组件.get("事件") or []:
                if isinstance(事件项, dict):
                    引用.append(str(事件项.get("能力id") or "").strip())
            for 能力id in 引用:
                if not 能力id:
                    continue
                位置表 = 出.setdefault(能力id, [])
                if 页面路径 not in 位置表:
                    位置表.append(页面路径)
    return {能力id: sorted(位置) for 能力id, 位置 in 出.items()}


def 页面可绑定能力集(根: Path) -> tuple[set[str], str | None]:
    """「页面可绑定集」= `正式包索引.构建索引(根)["能力所有者"]` 的键集，返回 ``(集合, 诊断)``。

    **不自持第二份集合**：这一份就是 `轻代码前端编辑器/页面模型._读取能力目录()` 读的
    那一个（页面绑定只允许引用它），判据与消费方同源。索引构建失败（坏包声明等）⇒
    诊断非空、集合为空 —— 调用方**只在真有内部层能力要判时**据此判红（fail-closed，
    不静默当「可绑定集为空」放过）；一个内部层包都没有时本闸无对象，如实不报。
    """
    try:
        from 开发工具.项目编译.正式包索引 import 构建索引

        索引 = 构建索引(根)
    except Exception as 异常:
        return set(), f"{type(异常).__name__}:{异常}"
    所有者 = 索引.get("能力所有者")
    if not isinstance(所有者, dict):
        return set(), "能力所有者不是字典型"
    return set(所有者), None


def 检查内部层可绑定(根: Path) -> list[dict]:
    """第二面闸：`内部层=真` 的能力 id 不得仍出现在「页面/可绑定集」上。

    载体①「页面仍引用」⇒ 判红（页面真绑了内部层能力，正是收口半途而废的现场）；
    载体②「可绑定集仍含」⇒ 现状存量（页面**可以**绑，只差人不去绑），按本门禁既有
    体例走存量基线（只报不拦、只减不增）。
    """
    根 = Path(根)
    内部层能力 = 收集内部层能力(根)
    页面引用 = 页面引用能力id集(根)
    违规: list[dict] = []
    for 条 in 内部层能力:
        位置表 = 页面引用.get(条["能力id"])
        if not 位置表:
            continue
        违规.append({
            "能力id": 条["能力id"], "包": 条["包"], "缺口类型": 内部层页面缺口类型,
            "路径": str(条["路径"]),
            "详情": f"页面仍引用内部层能力（撤掉页面绑定后本项消失）：{'、'.join(位置表)}",
        })
    if not 内部层能力:
        # 一个 `内部层=真` 的包都没有 ⇒ 本闸无对象（空夹具根、未启用内部层的仓库都走这条），
        # 如实不报：空集不是通过也不是缺陷，是「这份切片里没有要被判的东西」。
        return 违规
    可绑定集, 诊断 = 页面可绑定能力集(根)
    if 诊断 is None and not 可绑定集:
        诊断 = "能力所有者为空"      # 有内部层能力却读不出任何 owner ⇒ 索引面为空 ⇒ 判红
    if 诊断 is not None:
        违规.append({
            "能力id": "*", "包": "全仓", "缺口类型": f"内部层-可绑定集判据不可用:{诊断}",
            "路径": str(根 / "开发工具" / "项目编译" / "正式包索引.py"),
            "详情": "页面可绑定集（构建索引.能力所有者）读不成 ⇒ 第二面无从判定，fail-closed 判红",
        })
        return 违规
    for 条 in 内部层能力:
        if 条["能力id"] not in 可绑定集:
            continue
        违规.append({
            "能力id": 条["能力id"], "包": 条["包"], "缺口类型": 内部层可绑定集缺口类型,
            "路径": str(条["路径"]),
            "详情": "页面可绑定集（正式包索引.构建索引.能力所有者）仍含该内部层能力："
                    "页面模型._读取能力目录 会把它发给页面，收口第二面未完成（生成侧过滤后本桶收敛）",
        })
    return 违规
