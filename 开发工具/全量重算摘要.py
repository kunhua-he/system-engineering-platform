"""全量重算完整性摘要（改过包内文件后跑一次，避免漏掉聚合父包）。

为什么需要：某个包的 `完整性摘要.json` 登记了它目录下**每一个文件**，而
**聚合父包**又登记了子包里的文件 —— 所以「只重算自己改过的那几个包」必然漏父包
（本仓已因此漂移过多次）。本入口一次扫遍全部正式根，凡「磁盘 ≠ 重算」一律重算。

用法：
    python3.14 -m 开发工具.全量重算摘要          # 重算
    python3.14 -m 开发工具.全量重算摘要 --只报    # 只列不写
    python3.14 开发工具/全量重算摘要.py --只报    # 直接跑也支持（入口自备工程根导入路径）

未知参数一律拒绝（退出码 2）：本入口的默认动作是**写盘**，把拼错的开关当成
「确认写入」会静默重算上百个包的摘要，属不可接受的风险（2026-09-17 实测：
`--干跑` 这类自造词此前会被当成「写」，而本入口此前直接跑还会先撞导入错误）。

**退出码口径（2026-09-19 修：原为「假门禁」）**：修前 `入口()` 的两个分支**都 return 0**
（「全部闭合」与「共 N 项」同码），于是编译口把它当**阻断项**接的线永远不红 ——
生成物漂移（哲学 7.9 的唯一机器判据）被静默掩盖。现按门禁口径分开：
- 0 = 全部闭合（无可重算项）；
- 1 = 存在待重算项（**只报**模式下即判红；默认写盘模式下写入成功后应为 0）。

反向验证（2026-09-19 实测）：故意改坏一个摘要哈希 → 输出「共 3 项」且退出码由 0 变 1。
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

# 唯一事实源 `公共契约/正式根.py::正式根名表`。本入口支持「直接跑」
# （`python3.14 开发工具/全量重算摘要.py`），那时 sys.path[0] 是本文件所在目录、
# 不是工程根，故先把工程根补进导入路径再导入（与 `把工程根放进导入路径` 同一口径）。
_工程根 = Path(__file__).resolve().parents[1]
if str(_工程根) not in sys.path:
    sys.path.insert(0, str(_工程根))
from 公共契约.正式根 import 正式根名表 as 正式根表  # noqa: E402


def 把工程根放进导入路径(仓库根: Path) -> None:
    """把工程根放进 sys.path：`python3.14 开发工具/全量重算摘要.py` 从别处跑也要能导入仓库包。

    与同目录 `环境自检.py`／`验证场景体检.py`／`重建依赖锁.py` 同一范式 —— 这三个入口
    早已自备导入路径，本入口此前漏了，直接跑必报 `ModuleNotFoundError: 支持库`。
    """
    根 = str(仓库根)
    if 根 not in sys.path:
        sys.path.insert(0, 根)


def 完整性摘要文本(目录: Path, *, 包id: str, 版本: str) -> str:
    """`完整性摘要.json` 的**唯一序列化口径**（内容形状归 `支持库.后端.组件规范支持库`，
    序列化归本函数）。

    ★ 为什么必须收成一处（2026-09-22 实测的真缺陷）：`开发工具.契约编译.能力定义编译器`
    也在写同一个文件，但它用 `indent=1` 且不加尾换行，而本入口用 `indent=2` + 尾换行
    ⇒ **同一产物两条腿、两种字节**。危害不是「难看」，而是：
      ① 跑一次 `能力定义编译` 就把该包的 `完整性摘要.json` 刷成 indent=1 的字节，
         与已提交内容不符 ⇒ 产生**与本次改动无关的 diff**（真跑一次会脏一片）；
      ② 摘要门禁（`校验完整性摘要`）只**解析后逐键比**，字节差异对它完全不可见
         ⇒ 「判据在」但「判据不覆盖」，漂移静默（哲学 7.9 的机器判据漏了这一维）。
    故序列化只留这一处：谁要写这个文件，就调本函数拿文本，不自己 `json.dumps`。
    """
    from 支持库.后端.组件规范支持库 import 生成完整性摘要

    return json.dumps(生成完整性摘要(目录, 包id=包id, 版本=版本),
                      ensure_ascii=False, indent=2) + "\n"


def 全量重算(仓库根: Path, *, 只报: bool = False) -> list[str]:
    from 支持库.后端.组件规范支持库 import 校验完整性摘要

    结果: list[str] = []
    for 名 in 正式根表:
        基 = 仓库根 / 名
        if not 基.is_dir():
            continue
        for 摘要文件 in sorted(基.rglob("完整性摘要.json")):
            if "__pycache__" in 摘要文件.parts:
                continue
            目录 = 摘要文件.parent
            好, 问题 = 校验完整性摘要(目录)
            if 好:
                continue
            if 只报:
                结果.append(f"[待重算] {目录.relative_to(仓库根)}: {问题[:1]}")
                continue
            声明路径 = 目录 / "包声明.json"
            声明 = json.loads(声明路径.read_text(encoding="utf-8")) if 声明路径.is_file() else {}
            包id = 声明.get("包id") or 声明.get("提供者id") or 目录.name
            版本 = 声明.get("版本", "1.0.0")
            # 落盘走**唯一写腿**（`文件系统支持库.文件操作.写入文件`），不裸 `write_text`：
            # 该腿自带「内核只读锁的解锁窗口」（`仓库只读锁.临时解锁`），而裸写会在整仓
            # 上锁后被内核以 `Operation not permitted` 拒（2026-09-23 实测：本函数正是
            # 编译口「摘要闭合」那条红的来源）。同时写腿还会按内容指纹登记写入凭据 —— 裸写没有。
            from 支持库.后端.文件系统支持库.文件操作 import 写入文件
            写入文件(str(摘要文件),
                 完整性摘要文本(目录, 包id=包id, 版本=版本)).确保成功()
            后, 问题2 = 校验完整性摘要(目录)
            结果.append(f"[已重算] {目录.relative_to(仓库根)}: 闭合={后} {问题2[:1]}")
    return 结果


def 入口() -> int:
    仓库根 = Path(__file__).resolve().parents[1]
    把工程根放进导入路径(仓库根)
    开关 = [项 for 项 in sys.argv[1:] if 项.startswith("-")]
    未知 = [项 for 项 in 开关 if 项 != "--只报"]
    if 未知:
        print(f"未知参数：{' '.join(未知)}；本入口只支持 --只报（只列不写），其余一律拒绝，不做任何写入。")
        return 2
    只报 = "--只报" in 开关
    结果 = 全量重算(仓库根, 只报=只报)
    if not 结果:
        print("全部闭合：无可重算项")
        return 0
    for 行 in 结果:
        print(" ", 行)
    if 只报:
        # 门禁用法（编译口按「阻断项」接线）：有未闭合项即判红。
        print(f"共 {len(结果)} 项待重算：摘要不闭合，判红"
              f"（去掉 --只报 重跑即可写入修复）")
        return 1
    # 写盘模式：已就地重算，再核一遍确认真的闭合（不许「写过了」就当闭合）
    残留 = 全量重算(仓库根, 只报=True)
    if 残留:
        print(f"共 {len(结果)} 项已重算，但仍有 {len(残留)} 项不闭合：判红")
        return 1
    print(f"共 {len(结果)} 项已重算，全部闭合")
    return 0


if __name__ == "__main__":
    raise SystemExit(入口())
