"""环境自检：拿到仓库后一跑就知道本机能不能跑、缺什么。

为什么需要（华哥 2026-09-16 的关注点：别人能不能在自己机器上跑起来）
    本仓已做完整跨平台收口（`公共契约/运行时/平台适配.py` + `公共契约/运行时/进程终止.py`），
    但**开发机是 macOS：Windows 分支全部只经过 monkeypatch 模拟，从未真机验证**。换一台机器
    的人缺的不是文档，而是「跑一次就知道差在哪」的入口：

    - 解释器是不是 3.14（不是 → 依赖锁 fail-closed，装配直接被拒）；
    - 平台/架构与 `依赖锁.json` 的 `环境` 字段对不对得上（换平台必须先重建锁）；
    - 收口层的跨平台能力在本机**真的能跑吗**（不是「函数存在」就算数）；
    - `dir_fd=` / `preexec_fn` / `os.fork` 这类 POSIX 专有参数在本平台能不能用；
    - 中文环境变量名（全仓 42 处 `os.environ` 中文键）在本平台真的传得进子进程吗；
    - 装配冒烟（README 的三条断言）；
    - 外部命令（ffmpeg / tesseract / soffice …）在不在。

结论口径（三级；逐项给结论，每项都带「为什么需要它」和「缺了会怎样」）
    通过    本项在本机**真做过一次验证**且成立（真起子进程、真探活、真回收、真回读）；
    警告    本项不成立但**不阻断**底座运行，不影响退出码（当前只有「外部命令缺失」一类）；
    不支持  本项在本机**确实缺失**，底座或工具链会因此跑不起来／跑不全 → **退出码非零**。

用法
    cd 仓库根
    python3.14 -m 开发工具.环境自检              # 人读：逐项一行 + 汇总
    python3.14 -m 开发工具.环境自检 --详细        # 人读：连「通过」项也打印为什么需要它
    python3.14 -m 开发工具.环境自检 --json        # 机器读：完整 JSON（含每项详情与为什么）

退出码
    0  没有任何【不支持】项（可以有【警告】项）
    1  存在【不支持】项（逐条列在汇总里，带影响范围）
    2  自检自身无法开始（定不到仓库根）

边界（诚实标注）
    本入口**只读**：不写依赖锁、不改仓库文件、不 commit。唯一副作用是运行时会话里
    `工程缓存/` 下的运行库（已被 .gitignore 排除，README 已说明），以及自检期间起过的
    子进程——全部在 `finally` 里回收。
"""

