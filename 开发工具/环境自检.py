    序号: str
    名称: str
    结论: str
    说明: str
    为什么: str = ""
    影响: str = ""
    详情: dict[str, Any] = field(default_factory=dict)

    def 是失败(self) -> bool:
        return self.结论 == 结论_不支持

    def 转字典(self) -> dict[str, Any]:
        return {
            "序号": self.序号, "名称": self.名称, "结论": self.结论,
            "说明": self.说明, "为什么": self.为什么, "影响": self.影响,
            "详情": self.详情,
        }


