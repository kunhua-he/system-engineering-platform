"""说明书生成器：从包声明+唯一聚合契约生成机器可读说明书（Markdown）。

说明书与声明/契约同源：帮助、搜索、参数提示、验证使用同一份定义与
同一聚合契约解析函数（开发工具/契约编译/聚合契约解析.py），不靠导入
源码猜测，不出现 任意/无调用示例 等占位。生成结果可重复执行且可被
文档审计器校验。

**同名不同物（D-13 消歧）**：平台里另有一份同名文件
`支持库/后端/组件规范支持库/实现/说明书生成器.py`，与本文件**不是重复实现**：
- 本文件（本入口）：输入 `包声明.json` + 唯一聚合契约，产出
  `# 名称（包id）` 形态的目录说明书（`能力目录说明书.md` + 每包一份）到**输出目录**，
  现存 116 份A支 `说明/使用说明.md` 与本文件格式同源；调用方为
  `开发工具/说明书生成/运行生成.py`（一键脚本）与测试中心断言。
- 另一份（组件规范支持库）：输入 `能力定义.json`+`能力契约/参数契约.json`+
  `能力数据/能力搜索数据.json`+`验证场景引用.json`，产出 `# XX 使用说明` 形态的
  单包说明书并**拒绝覆盖已有文件**；经 `组件规范支持库.生成说明书` 能力对外注册。
两侧输入、输出形态、调用方与能力面全不同，**不得互相转调、也不得互相删除**
（引用面均不为 0）；后续若裁决「唯一说明书形态」，须先合并两侧的输入源与产出格式，
属单独立项（见 `开发文档/临时文档/结构债处置方案_20260916.md` D-13）。
"""

from __future__ import annotations

from pathlib import Path

from 公共契约.包声明 import 包声明
from 开发工具.契约编译.聚合契约解析 import 解析聚合契约, 提取能力表


def _包契约表(声明: 包声明) -> dict[str, dict]:
    """读取包目录聚合契约（唯一聚合契约解析），返回 {能力id: 契约条目}。"""
    来源 = Path(声明.来源路径).parent if 声明.来源路径 else None
    契约文件 = 来源 / "能力契约" / "参数契约.json" if 来源 else None
    if 契约文件 is None or not 契约文件.is_file():
        return {}
    数据, _问题 = 解析聚合契约(契约文件)
    return {条目["能力id"]: 条目 for 条目 in 提取能力表(数据)}


def _参数列表(能力声明: Any, 契约条目: dict) -> list[dict]:
    """参数表：契约优先（含类型/必填/默认值/说明），包声明兜底，任意归一为未约束。"""
    参数列表 = 契约条目.get("参数")
    if not isinstance(参数列表, list):
        参数列表 = 能力声明.参数
    if not isinstance(参数列表, list):
        return []
    return [
        {
            "名称": 参数.get("名称", ""),
            "类型": "未约束" if 参数.get("类型") == "任意" else 参数.get("类型", ""),
            "必填": 参数.get("必填", True),
            "默认值": 参数.get("默认值"),
            "说明": 参数.get("说明", ""),
        }
        for 参数 in 参数列表
    ]


def _调用示例文本(示例: Any, 能力id: str) -> str:
    """调用示例对象 → 文本；缺示例时由契约解析器生成的可执行示例兜底。"""
    if isinstance(示例, dict):
        参数行 = ", ".join(f"{名称}={值}" for 名称, 值 in 示例.get("参数", {}).items())
        目标id = 示例.get("能力id", 能力id)
        return f"{目标id}({参数行})" if 参数行 else f"{目标id}()"
    return str(示例) if 示例 else f"{能力id}()"


def 生成单包说明书(声明: 包声明) -> str:
    """生成一份支持库/模块的说明书文本（每能力含完整信息）。"""
    契约表 = _包契约表(声明)
    行列表 = [
        f"# {声明.名称}（{声明.包id}）",
        "",
        f"- 类型：{声明.类型}",
        f"- 版本：{声明.版本}",
        f"- 说明：{声明.说明 or '（无）'}",
        f"- 入口：{声明.入口 or '（无）'}",
        "- 权威分工：**调用口径以本文为准**（能力/参数/返回/错误码/调用示例，由能力契约生成）；",
        "  该库的设计哲学与边界见同目录 `设计说明.md`（设计权威）。",
    ]
    if 声明.依赖:
        行列表.extend(["", "## 依赖能力"])
        for 依赖 in 声明.依赖:
            行列表.append(f"- 能力 `{依赖.get('能力', '')}` 版本约束 `{依赖.get('版本', '')}`")
    if 声明.能力:
        行列表.extend(["", "## 能力"])
        for 能力 in 声明.能力:
            契约 = 契约表.get(能力.能力id, {})
            参数列表 = _参数列表(能力, 契约)
            必填参数 = [参数 for 参数 in 参数列表 if 参数.get("必填", True)]
            可选参数 = [参数 for 参数 in 参数列表 if not 参数.get("必填", True)]
            参数描述 = ", ".join(
                f"{参数.get('名称', '?')}:{参数.get('类型', '')}" for 参数 in 参数列表
            ) or "无"
            必填描述 = ", ".join(参数.get("名称", "?") for 参数 in 必填参数) or "无"
            可选描述 = ", ".join(参数.get("名称", "?") for 参数 in 可选参数) or "无"
            版本 = 契约.get("版本") or 声明.版本
            错误码表 = 契约.get("错误码")
            if not isinstance(错误码表, list):
                错误码表 = []
            调用示例 = _调用示例文本(契约.get("调用示例"), 能力.能力id)
            行列表.extend(
                [
                    f"### {能力.名称 or 能力.能力id}（`{能力.能力id}`）",
                    f"- 版本：{版本}",
                    f"- 一句话说明：{能力.说明 or '（无）'}",
                    f"- 所属支持库或模块：{声明.包id}",
                    f"- 参数列表：{参数描述}",
                    f"- 必填参数：{必填描述}",
                    f"- 可选参数：{可选描述}",
                    f"- 返回结构：{能力.返回 or '无'}（统一结果：成功/值/错误码/错误说明）",
                    f"- 错误码：{', '.join(错误码表) or '无'}",
                    f"- 调用示例：{调用示例}",
                    f"- 依赖能力：{', '.join(依赖.get('能力', '') for 依赖 in 声明.依赖) or '无'}",
                ]
            )
    if 声明.配置项:
        行列表.extend(["", "## 可配置项"])
        for 条目 in 声明.配置项:
            敏感 = bool(条目.get("敏感", False))
            默认显示 = "敏感配置（不显示实际值）" if 敏感 else str(条目.get("默认值", ""))
            行列表.extend(
                [
                    f"### {条目.get('配置名称', '')}（类型: {条目.get('类型', '文本')}）",
                    f"- 必填：{条目.get('必填', False)}",
                    f"- 允许项目覆盖：{条目.get('允许项目覆盖', True)}",
                    f"- 允许运行时覆盖：{条目.get('允许运行时覆盖', False)}",
                    f"- 敏感：{敏感}",
                    f"- 默认值：{默认显示}",
                    f"- 说明：{条目.get('说明', '（无）')}",
                    f"- 不合法时错误码：{条目.get('错误码', '参数不合法')}",
                ]
            )
    行列表.append("")
    return "\n".join(行列表)


def 生成目录说明书(声明列表: list[包声明]) -> str:
    """生成全部支持库/模块的目录索引说明书。"""
    行列表 = [
        "# 系统能力目录",
        "",
        f"共 {len(声明列表)} 份包声明。",
        "",
        "| 包id | 名称 | 类型 | 版本 | 能力数 |",
        "|------|------|------|------|--------|",
    ]
    for 声明 in sorted(声明列表, key=lambda 条目: 条目.包id):
        行列表.append(
            f"| {声明.包id} | {声明.名称} | {声明.类型} | {声明.版本} | {len(声明.能力)} |"
        )
    行列表.append("")
    return "\n".join(行列表)


def 写出说明书(声明列表: list[包声明], 输出目录: Path) -> list[Path]:
    """把目录说明书与每包说明书写入输出目录，返回写入文件路径列表。"""
    输出目录.mkdir(parents=True, exist_ok=True)
    写入列表: list[Path] = []
    目录文件 = 输出目录 / "能力目录说明书.md"
    目录文件.write_text(生成目录说明书(声明列表), encoding="utf-8")
    写入列表.append(目录文件)
    for 声明 in 声明列表:
        文件 = 输出目录 / f"{声明.包id}.md"
        文件.write_text(生成单包说明书(声明), encoding="utf-8")
        写入列表.append(文件)
    return 写入列表
