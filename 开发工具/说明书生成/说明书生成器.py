"""说明书生成器：从包声明生成机器可读说明书（Markdown）。

说明书与声明同源：帮助、搜索、参数提示、验证使用同一份定义，
不靠导入源码猜测。生成结果可重复执行且可被文档审计器校验。
"""

from __future__ import annotations

from pathlib import Path

from 公共契约.包声明 import 包声明


def 生成单包说明书(声明: 包声明) -> str:
    """生成一份支持库/模块的说明书文本（每能力含完整信息）。"""
    行列表 = [
        f"# {声明.名称}（{声明.包id}）",
        "",
        f"- 类型：{声明.类型}",
        f"- 版本：{声明.版本}",
        f"- 说明：{声明.说明 or '（无）'}",
        f"- 入口：{声明.入口 or '（无）'}",
    ]
    if 声明.依赖:
        行列表.extend(["", "## 依赖能力"])
        for 依赖 in 声明.依赖:
            行列表.append(f"- 能力 `{依赖.get('能力', '')}` 版本约束 `{依赖.get('版本', '')}`")
    if 声明.能力:
        行列表.extend(["", "## 能力"])
        for 能力 in 声明.能力:
            参数列表 = 能力.参数
            必填参数 = [参数 for 参数 in 参数列表 if 参数.get("必填", True)]
            可选参数 = [参数 for 参数 in 参数列表 if not 参数.get("必填", True)]
            参数描述 = ", ".join(
                f"{参数.get('名称', '?')}:{参数.get('类型', '任意')}" for 参数 in 参数列表
            ) or "无"
            必填描述 = ", ".join(参数.get("名称", "?") for 参数 in 必填参数) or "无"
            可选描述 = ", ".join(参数.get("名称", "?") for 参数 in 可选参数) or "无"
            参数示例 = ", ".join(f"{参数.get('名称', '参数')}=值" for 参数 in 参数列表[:3])
            调用示例 = f"{声明.包id} 提供能力 {能力.能力id}"
            if 参数示例:
                调用示例 += f"（{参数示例}…）"
            行列表.extend(
                [
                    f"### {能力.名称 or 能力.能力id}（`{能力.能力id}`）",
                    f"- 一句话说明：{能力.说明 or '（无）'}",
                    f"- 所属支持库或模块：{声明.包id}",
                    f"- 参数列表：{参数描述}",
                    f"- 必填参数：{必填描述}",
                    f"- 可选参数：{可选描述}",
                    f"- 返回结构：{能力.返回 or '无'}（统一结果：成功/值/错误）",
                    f"- 错误码：参数不合法、外部不可访问、内部错误",
                    f"- 调用示例：{调用示例}",
                    f"- 依赖能力：{', '.join(依赖.get('能力', '') for 依赖 in 声明.依赖) or '无'}",
                ]
            )
    if 声明.配置项:
        行列表.extend(["", "## 可配置项"])
        for 条目 in 声明.配置项:
            敏感 = bool(条目.get("敏感", False))
            默认显示 = "敏感配置（不显示实际值）" if 敏感 else str(条目.get("默认值", ""))
            行列表.extend(
                [
                    f"### {条目.get('配置名称', '')}（类型: {条目.get('类型', '文本')}）",
                    f"- 必填：{条目.get('必填', False)}",
                    f"- 允许项目覆盖：{条目.get('允许项目覆盖', True)}",
                    f"- 允许运行时覆盖：{条目.get('允许运行时覆盖', False)}",
                    f"- 敏感：{敏感}",
                    f"- 默认值：{默认显示}",
                    f"- 说明：{条目.get('说明', '（无）')}",
                    f"- 不合法时错误码：{条目.get('错误码', '参数不合法')}",
                ]
            )
    行列表.append("")
    return "\n".join(行列表)


def 生成目录说明书(声明列表: list[包声明]) -> str:
    """生成全部支持库/模块的目录索引说明书。"""
    行列表 = [
        "# 系统能力目录",
        "",
        f"共 {len(声明列表)} 份包声明。",
        "",
        "| 包id | 名称 | 类型 | 版本 | 能力数 |",
        "|------|------|------|------|--------|",
    ]
    for 声明 in sorted(声明列表, key=lambda 条目: 条目.包id):
        行列表.append(
            f"| {声明.包id} | {声明.名称} | {声明.类型} | {声明.版本} | {len(声明.能力)} |"
        )
    行列表.append("")
    return "\n".join(行列表)


def 写出说明书(声明列表: list[包声明], 输出目录: Path) -> list[Path]:
    """把目录说明书与每包说明书写入输出目录，返回写入文件路径列表。"""
    输出目录.mkdir(parents=True, exist_ok=True)
    写入列表: list[Path] = []
    目录文件 = 输出目录 / "能力目录说明书.md"
    目录文件.write_text(生成目录说明书(声明列表), encoding="utf-8")
    写入列表.append(目录文件)
    for 声明 in 声明列表:
        文件 = 输出目录 / f"{声明.包id}.md"
        文件.write_text(生成单包说明书(声明), encoding="utf-8")
        写入列表.append(文件)
    return 写入列表
