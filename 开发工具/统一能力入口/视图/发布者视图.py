"""发布者视图：审核、签名、安装、灰度、激活、撤销、回滚（全部真实能力）。

发布者（角色等级 5）工作流：审核候选 → 签名 → 签名与发布（安装/健康/
灰度/激活）→ 撤销/回滚。所有写操作一律经 统一能力服务.执行操作 或
服务.仓库/服务.发布 的真实实现，禁止桩。本视图不提供需求确认、组件创建、
查看诊断等非发布操作（视图边界：只暴露发布操作面）。

签名失效检查真实重算制品仓库与安装目录中实际文件的 sha256，与签名
冻结的文件清单逐项对比：源码/安装文件被篡改后旧签名必然失效。

错误码口径（决策 0003「对外错误只走中文」，与包级说明
`视图/错误码与建议口径说明.md` 同批收口）：本视图**本地拒绝分支**的错误码
一律取**产出者真实返回的中文码**，逐条落点为
  制品不存在 ← `平台控制面/统一入口.py` `_签名发布`（消费者契约「签名与发布」错误码）
  未导入签名密钥 ← 同上（密钥环无该身份私钥）
  签名失败 ← 同上（包仓库.签名制品 失败）
  发布不存在 ← `平台控制面/统一入口.py` `_回滚` 消息 + `运行核心/统一网关` 稳定码表
               （与 维护者视图.py 同一条件的码、
                 `测试中心/平台控制面/测试_工作包04_维护者视图.py` 已断言 同码）
  未签名 ← `平台控制面/策略中心.py` `_签名判定`（公开能力
           `平台控制面.策略闸门.判定签名策略` 实测 错误码='未签名'）
产出者已全部中文化，故视图侧**不得再自造英文码**（历史英文码
`ARTIFACT_NOT_FOUND`/`NO_SIGNING_KEY`/`SIGN_FAILED`/`RELEASE_NOT_FOUND`/`UNSIGNED`
已于本批清除，仅存于 `开发文档/归档/2026-08_第十四阶段/公开操作契约.json`）。
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

发布授权操作 = "签名与发布"   # 发布链路统一鉴权参考操作（最小角色等级 5）
回滚授权操作 = "回滚"         # 撤销/回滚鉴权参考操作（最小角色等级 5）


class 发布者视图:
    """发布者视图：发布者专属操作面（构造接收 统一能力服务 实例）。"""

    def __init__(self, 服务) -> None:
        """构造：接收 统一能力服务 实例（平台控制面/统一入口.py）。"""
        self.服务 = 服务

    # ---- 统一授权与错误结构 ----
    def _校验发布者(self, 令牌: str, 操作: str = "") -> tuple[bool, dict[str, Any], str]:
        """校验发布者权限：返回（允许, 会话, 拒绝码）。

        拒绝码由授权实现（平台控制面/授权.py 校验操作）产出，按决策 0003
        「对外错误只走中文」恒为中文短词（会话不存在/会话过期/未知角色/
        角色未授予/越权操作）。本视图**如实透传**该中文码，禁止再用硬编码
        英文码 PERMISSION_DENIED 覆盖（那会把上游中文码降级为英文对外）。
        兜底值同为中文：越权操作（与授权实现越权拒绝分支同码）。
        """
        允许, 错误码, 会话 = self.服务.授权.校验操作(令牌=令牌, 操作=操作 or 发布授权操作)
        return 允许, 会话, 错误码

    @staticmethod
    def _拒绝(错误码: str, 消息: str = "权限不足") -> dict[str, Any]:
        """统一拒绝结构。

        拒绝码恒为中文：授权类（越权操作/会话不存在/会话过期/未知角色/角色未授予）
        由授权实现产出、本视图透传；业务类（制品不存在/未导入签名密钥/签名失败/
        发布不存在/未签名）逐条取自产出实现真实返回的中文码，见本模块文件头
        「错误码口径」。禁止在此自造英文码。
        """
        return {"成功": False, "错误码": 错误码, "消息": 消息}

    # ---- 审核候选（只读制品记录） ----
    def 审核候选(self, *, 令牌: str, 制品摘要: str) -> dict[str, Any]:
        """读取制品记录供审核：包id/版本/构建输入/来源证据/签名状态。"""
        允许, _会话, 拒绝码 = self._校验发布者(令牌)
        if not 允许:
            return self._拒绝(拒绝码 or "越权操作")
        制品 = self.服务.状态.读取记录("制品", "制品摘要", 制品摘要)
        if 制品 is None:
            return self._拒绝("制品不存在", "制品不存在")
        return {"成功": True, "消息": "审核信息已获取",
                "包id": 制品["包id"], "版本": 制品["版本"],
                "构建输入": json.loads(制品["构建输入"]),
                "来源证据": json.loads(制品["来源证据"]),
                "签名状态": 制品["状态"], "签名者": 制品["签名者"]}

    # ---- 签名（密钥环私钥 + 信任目录，真实 Ed25519） ----
    def 签名(self, *, 令牌: str, 制品摘要: str) -> dict[str, Any]:
        """签名候选：私钥取自服务密钥环，经 服务.仓库.签名制品 真实签名。"""
        允许, 会话, 拒绝码 = self._校验发布者(令牌)
        if not 允许:
            return self._拒绝(拒绝码 or "越权操作")
        身份id = 会话["身份id"]
        私钥 = self.服务._签名密钥环.get(身份id)
        if 私钥 is None:
            return self._拒绝("未导入签名密钥", "发布者未导入签名密钥")
        成功, 消息 = self.服务.仓库.签名制品(制品摘要=制品摘要, 私钥PEM=私钥, 发布者=身份id)
        if not 成功:
            return self._拒绝("签名失败", 消息)
        return {"成功": True, "消息": 消息, "制品摘要": 制品摘要, "发布者": 身份id}

    # ---- 签名与发布（签名→安装→健康→灰度→激活→证据） ----
    def 签名与发布(self, *, 令牌: str, 制品摘要: str, 需求id: str = "",
                  灰度比例: float = 0.1) -> dict[str, Any]:
        """完整发布链路：执行操作(签名与发布)，返回激活指针与证据id。"""
        结果 = self.服务.执行操作(
            令牌=令牌, 操作=发布授权操作,
            参数={"制品摘要": 制品摘要, "需求id": 需求id, "灰度比例": 灰度比例})
        结果["操作"] = 发布授权操作
        return 结果

    # ---- 撤销（先读发布状态，再执行回滚） ----
    def 撤销(self, *, 令牌: str, 发布id: str, 回滚目标: str = "") -> dict[str, Any]:
        """撤销发布：先读取发布状态，再经执行操作(回滚) 切回目标指针。"""
        允许, _会话, 拒绝码 = self._校验发布者(令牌, 回滚授权操作)
        if not 允许:
            return self._拒绝(拒绝码 or "越权操作")
        发布记录 = self.服务.状态.读取记录("发布", "发布id", 发布id)
        if 发布记录 is None:
            return self._拒绝("发布不存在", "发布不存在")
        目标 = 回滚目标 or 发布记录.get("期望版本", "")
        结果 = self.服务.执行操作(令牌=令牌, 操作=回滚授权操作,
                                 参数={"发布id": 发布id, "回滚目标": 目标})
        结果["撤销前状态"] = 发布记录["状态"]
        结果["操作"] = 回滚授权操作
        return 结果

    # ---- 回滚 ----
    def 回滚(self, *, 令牌: str, 发布id: str, 回滚目标: str) -> dict[str, Any]:
        """回滚：执行操作(回滚) 切换激活指针到回滚目标（保留历史证据）。"""
        结果 = self.服务.执行操作(令牌=令牌, 操作=回滚授权操作,
                                 参数={"发布id": 发布id, "回滚目标": 回滚目标})
        结果["操作"] = 回滚授权操作
        return 结果

    # ---- 签名失效检查（真实磁盘重算，非桩） ----
    def 签名失效检查(self, *, 令牌: str, 制品摘要: str) -> dict[str, Any]:
        """真实校验：重算制品仓库与安装目录实际文件摘要，对比签名覆盖清单。

        仓库 Ed25519 验证 + 磁盘逐一重算 sha256；任一正式文件被篡改
        （源码/安装内容变化）即返回失败，证明旧签名失效。
        """
        允许, _会话, 拒绝码 = self._校验发布者(令牌)
        if not 允许:
            return self._拒绝(拒绝码 or "越权操作")
        制品 = self.服务.状态.读取记录("制品", "制品摘要", 制品摘要)
        if 制品 is None:
            return self._拒绝("制品不存在", "制品不存在")
        if not 制品["签名"]:
            return self._拒绝("未签名", "制品未签名")
        冻结清单 = json.loads(制品["文件清单"])
        仓库目录 = self.服务.仓库.制品根目录 / 制品摘要
        安装目录 = self.服务.状态.存储目录 / "已激活" / 制品["包id"]
        仓库一致, 仓库差异 = self._重算对比(仓库目录, 冻结清单)
        安装存在 = 安装目录.is_dir()
        安装一致, 安装差异 = self._重算对比(安装目录, 冻结清单) if 安装存在 else (True, [])
        有效签名, 签名消息 = self.服务.仓库.校验签名(制品摘要=制品摘要)
        有效 = 仓库一致 and 有效签名 and (not 安装存在 or 安装一致)
        检查表 = {
            "制品仓库": {"一致": 仓库一致, "差异表": 仓库差异},
            "签名校验": {"有效": 有效签名, "消息": 签名消息},
            "安装目录": {"存在": 安装存在, "一致": 安装一致, "差异表": 安装差异},
        }
        return {"成功": 有效, "有效": 有效,
                "消息": "磁盘内容与签名一致" if 有效 else "磁盘文件被篡改，旧签名失效",
                "签名者": 制品["签名者"], "检查表": 检查表,
                "制品摘要": 制品摘要}

    # ---- 内部：逐一重算目录中正式文件摘要 ----
    @staticmethod
    def _重算对比(目录: Path, 冻结清单: dict[str, dict]) -> tuple[bool, list[str]]:
        """读取目录实际文件重算 sha256，与签名冻结清单逐项对比。"""
        if not 目录.is_dir():
            return False, ["目录缺失"]
        差异表 = []
        for 路径, 摘要信息 in 冻结清单.items():
            文件 = 目录 / 路径
            if not 文件.is_file():
                差异表.append(f"文件缺失:{路径}")
                continue
            实际 = hashlib.sha256(文件.read_bytes()).hexdigest()
            if 实际 != 摘要信息["sha256"]:
                差异表.append(f"被篡改:{路径}")
        return not 差异表, 差异表
