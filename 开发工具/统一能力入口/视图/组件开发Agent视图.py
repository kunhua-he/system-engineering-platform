"""组件开发Agent视图：需求确认、复用分析、占用租约、模板创建、候选提交。

视图只做中文业务组装与透传，全部业务判定由 统一能力服务.执行操作 真实完成：
未确认需求 → REQUIREMENT_UNCONFIRMED；缺复用证据 → 未做复用决策（B-8：英文码
NO_REUSE_DECISION 已随 契约编译/消费者契约.py 同批汉化）；
视图如实返回服务拒绝结果（统一结果结构 成功/错误码/消息），禁止伪造成功。
"""
from __future__ import annotations

from typing import Any


class 组件开发Agent视图:
    """组件开发Agent 视图：对 统一能力服务 的中文业务封装（无独立判定）。"""

    def __init__(self, 服务) -> None:
        self.服务 = 服务

    # ---- 会话辅助（登记需求直接写需求登记，证据账本需要调用者）----
    def _会话信息(self, 令牌: str) -> dict[str, str]:
        try:
            会话 = self.服务.授权.会话信息(令牌)
        except Exception:
            会话 = {}
        return {"身份id": 会话.get("身份id", ""), "角色": 会话.get("角色", "")}

    # ---- 需求阶段 ----
    def 登记需求(self, 令牌: str, 目标: str) -> dict[str, Any]:
        """登记需求：调用 服务.需求.登记需求（需求快照不可变），返回需求id。"""
        会话 = self._会话信息(令牌)
        快照 = self.服务.需求.登记需求(目标=目标, 调用者=会话["身份id"], 角色=会话["角色"])
        return {"成功": True, "错误码": "", "消息": "需求已登记",
                "需求id": 快照["需求id"], "目标": 目标}

    def 确认需求(self, 令牌: str, 需求id: str) -> dict[str, Any]:
        return self.服务.执行操作(令牌=令牌, 操作="确认需求", 参数={"需求id": 需求id})

    def 生成装配计划(self, 令牌: str, 需求id: str) -> dict[str, Any]:
        return self.服务.执行操作(令牌=令牌, 操作="生成装配计划", 参数={"需求id": 需求id})

    # ---- 复用分析（服务搜索 + 服务查看能力 真实数据组装）----
    def 复用分析(self, 令牌: str, 需求id: str, 关键词: str) -> dict[str, Any]:
        搜索结果 = self.服务.执行操作(令牌=令牌, 操作="搜索能力",
                                    参数={"关键词": 关键词, "限制": 50})
        if not 搜索结果.get("成功"):
            return 搜索结果
        候选能力表: list[dict[str, Any]] = []
        for 候选 in 搜索结果.get("结果表", []):
            能力id = 候选["能力id"]
            详情 = self.服务.执行操作(令牌=令牌, 操作="查看能力", 参数={"能力id": 能力id})
            记录 = 详情.get("能力") or {}
            候选能力表.append({
                "能力id": 能力id,
                "中文名称": 记录.get("组件") or 候选.get("组件") or 能力id,
                "契约指纹": 记录.get("契约指纹", ""),
                "提供者": 记录.get("提供者", ""),
                "候选原因": self._候选原因(候选, 记录, 关键词),
            })
        return {"成功": True, "错误码": "", "消息": "复用分析完成", "需求id": 需求id,
                "关键词": 关键词, "候选能力表": 候选能力表,
                "复用建议": self._复用建议(候选能力表, 关键词)}

    @staticmethod
    def _候选原因(候选: dict[str, Any], 记录: dict[str, Any], 关键词: str) -> str:
        原因表 = []
        if 关键词 and 关键词 in 候选.get("能力id", ""):
            原因表.append("关键词命中能力id")
        if 关键词 and 关键词 in 候选.get("组件", ""):
            原因表.append("关键词命中组件")
        if 记录 and 记录.get("契约指纹"):
            原因表.append(f"契约指纹 {记录['契约指纹'][:8]}…")
        if 候选.get("成熟度"):
            原因表.append(f"成熟度 {候选['成熟度']}")
        if 候选.get("裁决状态"):
            原因表.append(f"裁决 {候选['裁决状态']}")
        return "；".join(原因表) or f"关键词「{关键词}」相关候选"

    @staticmethod
    def _复用建议(候选能力表: list[dict[str, Any]], 关键词: str) -> dict[str, str]:
        if not 候选能力表:
            return {"类型": "新增能力",
                    "说明": f"关键词「{关键词}」未命中候选能力，建议新增能力", "首选能力id": ""}
        首选 = 候选能力表[0]
        能力id = 首选["能力id"]
        if 首选["契约指纹"] and 首选["提供者"]:
            return {"类型": "直接复用",
                    "说明": f"能力 {能力id} 契约指纹与提供者齐备，建议直接复用",
                    "首选能力id": 能力id}
        if 首选["契约指纹"]:
            return {"类型": "新提供者",
                    "说明": f"能力 {能力id} 契约指纹已存在但无提供者，建议声明新提供者",
                    "首选能力id": 能力id}
        return {"类型": "扩展契约",
                "说明": f"能力 {能力id} 与目标契约不匹配，建议扩展契约", "首选能力id": 能力id}

    # ---- 占用与模板创建 ----
    def 申请能力占用(self, 令牌: str, 能力id: str, 领域: str, 契约指纹: str,
                    任务: str) -> dict[str, Any]:
        return self.服务.执行操作(令牌=令牌, 操作="申请能力占用",
           参数={"能力id": 能力id, "领域": 领域, "契约指纹": 契约指纹, "任务": 任务})

    def 创建组件(self, 令牌: str, 需求id: str, 复用决策: dict, 资源预算: dict,
                 允许修改路径: list, 组件声明: dict, 能力id: str) -> dict[str, Any]:
        return self.服务.执行操作(令牌=令牌, 操作="创建组件",
           参数={"需求id": 需求id, "复用决策": 复用决策, "资源预算": 资源预算,
                 "允许修改路径": 允许修改路径, "组件声明": 组件声明, "能力id": 能力id})

    # ---- 候选提交 ----
    def 提交候选包(self, 令牌: str, 需求id: str, 复用决策: dict, 文件表: dict,
                  资源预算: dict, 构建输入: dict, 包id: str, 版本: str,
                  依赖: list) -> dict[str, Any]:
        return self.服务.执行操作(令牌=令牌, 操作="提交候选包",
           参数={"需求id": 需求id, "复用决策": 复用决策, "文件表": 文件表,
                 "资源预算": 资源预算, "构建输入": 构建输入, "包id": 包id,
                 "版本": 版本, "依赖": 依赖})
