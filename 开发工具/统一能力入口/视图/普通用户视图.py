"""普通用户视图：只面向普通用户的统一能力服务可读中文视图。

普通用户（角色等级 1）只能看到自己可执行的操作（搜索能力、查看能力）；
能力详情只含中文说明与公开契约信息；调用一律经 统一能力服务.执行操作
真实执行。视图不泄漏实现细节、签名密钥与内部日志。
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

系统根 = Path(__file__).resolve().parents[3]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 平台控制面.授权 import 操作最小角色, 角色等级, 普通用户
from 平台控制面.统一入口 import 稳定操作表, 统一能力服务

普通用户等级 = 角色等级[普通用户]

# 普通用户可见操作的中文说明（静态文案，不涉及实现逻辑）
操作说明表: dict[str, dict[str, Any]] = {
    "搜索能力": {
        "说明": "按关键词搜索平台已登记的功能，快速了解平台能做什么",
        "必填参数": [],
        "可选参数": [{"名称": "关键词", "说明": "要搜索的功能关键词，可留空"},
                    {"名称": "限制", "说明": "最多返回的结果数量，默认 20"}],
        "所需权限": "普通用户",
        "成功结果": "返回匹配的功能列表及数量",
        "失败处理建议": "搜索失败时请稍后再试；仍失败请联系平台管理员",
    },
    "查看能力": {
        "说明": "查看某个功能的中文名称、作用、输入参数、权限要求与可用状态",
        "必填参数": [{"名称": "能力id", "说明": "功能的唯一中文标识，来自搜索能力结果"}],
        "可选参数": [],
        "所需权限": "普通用户",
        "成功结果": "返回该功能的中文详情说明",
        "失败处理建议": "如提示功能不可用请稍后再试；如提示权限不足请升级账号权限",
    },
}

# 错误码 → 普通用户可执行的中文建议
错误码建议表 = {
    "CAPABILITY_NOT_FOUND": "该功能暂不可用，请稍后再试",
    "CAPABILITY_REQUIRED": "请先选择要查看的功能",
    "PERMISSION_DENIED": "当前账号没有该操作权限",
    "PROVIDER_UNAVAILABLE": "该功能正在维护，请稍后再试",
    "SESSION_EXPIRED": "登录已过期，请重新登录",
    "CALL_TIMEOUT": "处理超时，请稍后重试",
    "CALL_FAILED": "执行失败，请重试或联系管理员",
    "INTERNAL_ERROR": "系统繁忙，请稍后再试",
    "UNKNOWN_OPERATION": "该操作不存在，请刷新后重试",
    "会话不存在": "登录状态无效，请重新登录",
}


class 普通用户视图:
    """普通用户视图：构造时接收 统一能力服务 实例，全部真实转发。"""

    def __init__(self, 服务: 统一能力服务) -> None:
        self.服务 = 服务

    def 可见操作表(self) -> list[str]:
        """普通用户可见操作：授权表最小角色等级 ≤ 普通用户等级（真实判定）。"""
        return [操作 for 操作 in 稳定操作表
                if 操作最小角色.get(操作, 99) <= 普通用户等级]

    def 平台可用状态(self) -> str:
        """平台可用状态：真实读取服务持有的权威状态快照。"""
        try:
            return "可用" if self.服务.状态.状态快照() else "不可用"
        except Exception:
            return "不可用"

    def 展示能力摘要(self) -> list[dict[str, Any]]:
        """返回每个可见操作的中文说明列表（含真实可用状态）。"""
        状态 = self.平台可用状态()
        摘要表 = []
        for 操作 in self.可见操作表():
            说明 = 操作说明表[操作]
            摘要表.append({
                "操作名": 操作, "说明": 说明["说明"],
                "必填参数": 说明["必填参数"], "所需权限": 说明["所需权限"],
                "可用状态": 状态, "成功结果": 说明["成功结果"],
                "失败处理建议": 说明["失败处理建议"]})
        return 摘要表

    def 查看能力详情(self, 能力id: str) -> dict[str, Any]:
        """只返回中文名称/作用/输入参数说明/权限要求/可用状态/结果/处理建议。"""
        if not 能力id:
            return {"成功": False, "错误码": "CAPABILITY_REQUIRED",
                    "消息": "请先选择要查看的功能", "处理建议": "请先选择要查看的功能"}
        记录 = self.服务.状态.读取记录("能力条目", "能力id", 能力id)
        if 记录 is None:
            建议 = 错误码建议表["CAPABILITY_NOT_FOUND"]
            return {"成功": False, "错误码": "CAPABILITY_NOT_FOUND",
                    "消息": 建议, "处理建议": 建议}
        资源 = json.loads(记录.get("资源") or "{}") if isinstance(记录.get("资源"), str) else {}
        参数说明 = 资源.get("参数说明", []) if isinstance(资源, dict) else []
        可用 = (self.服务.提供者注册表.已注册(能力id)
                and self.平台可用状态() == "可用")
        return {
            "成功": True, "中文名称": 记录["能力id"],
            "作用": (f"由组件「{记录.get('组件', '')}」提供，"
                     f"领域「{记录.get('领域', '')}」，成熟度「{记录.get('成熟度', '')}」"),
            "输入参数说明": 参数说明 or "请按该功能提供方的约定传入调用参数",
            "权限要求": (f"普通用户可查看本详情；调用该功能需要授权等级不低于 "
                         f"{操作最小角色['调用能力']}（调用Agent）"),
            "可用状态": "可用" if 可用 else "暂不可用",
            "成功结果": "返回该功能的中文详情说明",
            "处理建议": "可立即查看" if 可用 else "请稍后再试",
        }

    def 调用能力(self, 令牌: str, 能力id: str, 参数: Any = None) -> dict[str, Any]:
        """经服务真实调用；返回统一结果结构（失败消息用中文建议，不泄内部）。"""
        结果 = self.服务.执行操作(
            令牌=令牌, 操作="调用能力",
            参数={"能力id": 能力id, "参数": 参数})
        建议 = self.失败处理建议(结果)
        return {"成功": bool(结果.get("成功")),
                "错误码": 结果.get("错误码", ""),
                "消息": 结果.get("消息", "") if 结果.get("成功") else 建议,
                "结果": 结果.get("结果"),
                "可重试": bool(结果.get("可重试", False)),
                "处理建议": 建议}

    def 失败处理建议(self, 结果: dict[str, Any]) -> str:
        """按错误码映射为普通用户可执行的中文建议。"""
        if 结果.get("成功"):
            return "操作成功，无需处理"
        return 错误码建议表.get(str(结果.get("错误码", "")),
                                "操作未成功，请稍后再试或联系管理员")
