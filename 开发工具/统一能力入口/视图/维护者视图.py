"""维护者视图：诊断、依赖、提供者、资源、证据、复用裁决、回滚建议。

维护者（角色等级 4）无签名、安装、发布执行权限；本视图不提供任何
签名/发布/回滚执行方法，执行类操作一律由统一能力服务授权真实拦截
（如实透传授权实现的中文拒绝码：越权操作/会话过期/角色未授予 等；
 历史英文名 PERMISSION_DENIED / RELEASE_DENIED 已停用，见 发布者视图._拒绝）。
视图数据全部来自统一能力
服务的公开能力与权威状态（只读）；冲突裁决经能力目录既有裁决方法
登记（能力目录.py 已提供 裁决 方法，直接复用，不修改能力目录本身）。
"""
from __future__ import annotations

import json
import threading
from typing import Any

只读授权操作 = "查看诊断"      # 只读视图统一鉴权参考操作（最小角色等级 4）
资源授权操作 = "监督资源"      # 资源视图鉴权参考操作（最小角色等级 4）
裁决授权操作 = "复用裁决"      # 冲突裁决鉴权参考操作（最小角色等级 4）


class 维护者视图:
    """维护者视图：只读诊断 + 复用裁决登记 + 回滚建议（禁止执行类操作）。"""

    def __init__(self, 服务) -> None:
        """构造：接收 统一能力服务 实例（平台控制面/统一入口.py）。"""
        self.服务 = 服务

    # ---- 统一授权与错误结构 ----
    def _校验(self, 令牌: str, 操作: str) -> tuple[bool, str, dict[str, Any]]:
        允许, 错误码, 会话 = self.服务.授权.校验操作(令牌=令牌, 操作=操作)
        return 允许, 错误码, 会话

    @staticmethod
    def _拒绝(错误码: str) -> dict[str, Any]:
        return {"成功": False, "错误码": 错误码, "消息": "权限不足"}

    # ---- 诊断视图（经统一入口真实执行） ----
    def 查看诊断(self, 令牌: str) -> dict[str, Any]:
        结果 = self.服务.执行操作(令牌=令牌, 操作="查看诊断", 参数={})
        if not 结果["成功"]:
            # `执行操作` 的失败返回点（未知操作/授权拒绝/内部错误）均带非空中文错误码，
            # 兜底值同样取中文，不回落英文码（决策 0003「对外错误只走中文」）。
            return {"成功": False, "错误码": 结果.get("错误码") or "内部错误",
                    "消息": 结果.get("消息", "")}
        return {"成功": True, "消息": "诊断查看完成",
                "监督报告": 结果["监督报告"], "证据数": 结果["证据数"],
                "状态快照": 结果["状态快照"]}

    # ---- 依赖视图（从权威状态读取能力记录，只读） ----
    def 查看依赖(self, 令牌: str, 能力id: str) -> dict[str, Any]:
        允许, 错误码, _ = self._校验(令牌, 只读授权操作)
        if not 允许:
            return self._拒绝(错误码)
        记录 = self.服务.状态.读取记录("能力条目", "能力id", 能力id)
        if 记录 is None:
            return {"成功": False, "错误码": "能力不存在",
                    "消息": f"能力未登记: {能力id}"}
        依赖表 = json.loads(记录.get("依赖", "[]") or "[]")
        被依赖表 = [条目["能力id"] for 条目 in self.服务.状态.查询记录("能力条目")
                   if 能力id in json.loads(条目.get("依赖", "[]") or "[]")]
        return {"成功": True, "消息": "依赖查看完成", "能力id": 能力id,
                "依赖表": 依赖表, "被依赖表": 被依赖表,
                "方向": {"依赖": "本能力 → 依赖表", "反向": "被依赖表 → 本能力"}}

    # ---- 提供者视图（注册表 + 预算 + 运行报告，只读） ----
    def 查看提供者(self, 令牌: str, 能力id: str) -> dict[str, Any]:
        允许, 错误码, _ = self._校验(令牌, 只读授权操作)
        if not 允许:
            return self._拒绝(错误码)
        记录 = self.服务.状态.读取记录("能力条目", "能力id", 能力id)
        if 记录 is None:
            return {"成功": False, "错误码": "能力不存在",
                    "消息": f"能力未登记: {能力id}"}
        已注册 = self.服务.提供者注册表.已注册(能力id)
        提供者表 = getattr(self.服务.提供者注册表, "_提供者表", {})
        预算 = dict(提供者表[能力id][1]) if 已注册 and 能力id in 提供者表 else {}
        运行报告 = self.服务.监督.状态报告().get(f"单元_{能力id}", {})
        return {"成功": True, "消息": "提供者查看完成", "能力id": 能力id,
                "已注册": 已注册, "预算": 预算, "运行报告": 运行报告}

    # ---- 资源视图（监督器真实报告：内存/线程/句柄/队列） ----
    def 查看资源(self, 令牌: str) -> dict[str, Any]:
        允许, 错误码, _ = self._校验(令牌, 资源授权操作)
        if not 允许:
            return self._拒绝(错误码)
        return {"成功": True, "消息": "资源查看完成",
                "资源报告": {"监督单元": self.服务.监督.状态报告(),
                              "活跃句柄数": self.服务.状态.活跃句柄数(),
                              "活跃线程数": threading.active_count()}}

    # ---- 证据视图（账本只读：时间/类型/结果） ----
    def 查看证据(self, 令牌: str, 主题: str, 限制: int = 20) -> dict[str, Any]:
        允许, 错误码, _ = self._校验(令牌, 只读授权操作)
        if not 允许:
            return self._拒绝(错误码)
        证据表 = self.服务.状态.查询证据(主题=主题, 限制=限制)
        证据链 = [{"时间": 条["时间"], "类型": 条["类型"], "结果": 条["结果"]}
                for 条 in 证据表]
        return {"成功": True, "消息": "证据查看完成", "主题": 主题,
                "数量": len(证据表), "证据链": 证据链, "证据表": 证据表}

    # ---- 冲突裁决（经能力目录既有裁决方法登记，可读回） ----
    def 冲突裁决(self, 令牌: str, 能力id: str, 裁决结果: str) -> dict[str, Any]:
        允许, 错误码, 会话 = self._校验(令牌, 裁决授权操作)
        if not 允许:
            return self._拒绝(错误码)
        记录 = self.服务.状态.读取记录("能力条目", "能力id", 能力id)
        if 记录 is None:
            return {"成功": False, "错误码": "能力不存在",
                    "消息": f"能力未登记: {能力id}"}
        成功, 消息 = self.服务.目录.裁决(能力id=能力id, 决定=裁决结果,
                                       维护者=会话.get("身份id", ""))
        if not 成功:
            return {"成功": False, "错误码": "裁决被拒", "消息": 消息}
        return {"成功": True, "消息": 消息, "能力id": 能力id, "裁决": 裁决结果}

    # ---- 回滚建议（只读建议，不执行回滚） ----
    def 回滚建议(self, 令牌: str, 发布id: str) -> dict[str, Any]:
        允许, 错误码, _ = self._校验(令牌, 只读授权操作)
        if not 允许:
            return self._拒绝(错误码)
        记录 = self.服务.状态.读取记录("发布", "发布id", 发布id)
        if 记录 is None:
            return {"成功": False, "错误码": "发布不存在",
                    "消息": f"发布不存在: {发布id}"}
        当前激活 = self.服务.发布.当前激活(记录["包id"])
        历史表 = self.服务.状态.查询记录(
            "发布", "包id=? AND 状态 IN ('完成','已回滚')", (记录["包id"],))
        可回滚表 = [{"发布id": 项["发布id"], "状态": 项["状态"],
                     "期望版本": 项["期望版本"], "候选版本": 项["候选版本"]}
                    for 项 in 历史表]
        目标 = (当前激活 or {}).get("目标", "") or "无"
        建议 = f"当前激活目标: {目标}；可回滚目标 {len(可回滚表)} 个（维护者仅建议，不执行回滚）"
        return {"成功": True, "消息": "回滚建议生成（只读，未执行回滚）",
                "发布id": 发布id, "包id": 记录["包id"],
                "当前激活": 当前激活, "可回滚目标表": 可回滚表, "建议": 建议}
