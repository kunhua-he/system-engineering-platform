"""调用Agent视图：稳定四操作（搜索能力/查看能力/验证可用/调用能力）。

搜索/查看/调用全部经 统一能力服务.执行操作 真实执行；验证可用组合
查看能力 + 监督报告/状态快照 + 授权校验 真实判定；错误全部映射为
错误码 + 中文错误说明 + 建议操作，异常文本绝不直接泄漏。Agent 不读取
实现源码、不解析物理目录、不接触第三方对象。

本视图不直连 `平台控制面`：授权口径一律经**唯一能力调用入口**按能力 id 取得
（`平台控制面.授权.查询角色模型`）。
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

系统根 = Path(__file__).resolve().parents[3]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

# ---- 唯一能力调用入口 ----
# `开发工具` 是进程外调用方：惰性装配钩子只装 支持库/模块库，取不到 `平台控制面`
# 的能力，故这里自建完整装配并按**惰性单例**复用（约 2 秒，不塞进 import 期）。
# 装配或调用失败一律抛出：不做 try/except 兜底、不静默降级。
_后端: Any = None


def _调用能力(能力id: str, 参数: dict[str, Any]) -> dict[str, Any]:
    """经唯一能力调用入口调用 `平台控制面` 公开能力，返回能力的值（字典）。"""
    global _后端
    if _后端 is None:
        from 后端核心.后端核心 import 后端核心

        实例 = 后端核心(系统根)
        启动结果 = 实例.启动()
        if not 启动结果.成功:
            raise RuntimeError(f"平台控制面 能力装配失败: {启动结果.错误说明}")
        _后端 = 实例
    调用结果 = _后端.调用(能力id, 参数)
    if not 调用结果.成功:
        raise RuntimeError(f"能力调用失败（{能力id}）: {调用结果.错误说明}")
    return dict(调用结果.值)


def 角色模型() -> dict[str, Any]:
    """授权口径只读模型（角色等级/操作最小角色）：经能力取得，不复制授权语义。"""
    return _调用能力("平台控制面.授权.查询角色模型", {})


