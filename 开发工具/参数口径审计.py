"""参数口径审计（只读）：量化「同一概念多种定义」的规模，并做基线比对。

## 为什么有这件工具（2026-09-22 华哥问「是不是应该统一一下定义」）

现象：Agent 每踩一个「形状坑」就往通用纪律里加一条，纪律从 1.5.0 涨到 1.7.0
加了 8 条，而每一条的根因都是**同一件事**：同一个概念在全仓有多个定义
（`超时秒` 一处整数型一处双精度数型；`返回` 一处 dict 一处 str）。

**纪律越写越长，是定义没收口的症状，不是解决办法。** 本工具把「不统一」量化出来，
好让修法收口到定义层：真分歧（一个概念应该只有一个定义）统一；
同名不同义（不同概念恰好同名）进登记表并改名；两者的边界由人裁决、机器只报事实。

## 判据分三类

1. **契约字段形状分歧**（`返回` 写成 dict 还是 str）：真分歧，判红。
2. **同名参数类型分歧**：区分两种情况 ——
   - 数值族内（整数型 vs 双精度数型）：真分歧，应统一（整数是双精度的子集）。
   - 跨类型族（文本型 vs 字典型、文本型 vs 列表型）：多为**同名不同义**，
     不应硬统一，而应改名或登记，故只报不判红。
3. **同名参数必填口径分歧**：纯事实，只报（同一参数在不同能力里必填性本就可能不同）。

## 唯一腿：契约来源必须转调 `模块库/能力目录`

本工具**不自己 glob 声明文件、不自己读 json** —— 「读能力契约」这个动作，
平台已有唯一腿（`能力目录.搜索能力` / `能力目录.读取能力`）。
自建第二套读取会被验证门禁的「同动作双路径检测」判为「自建契约读取腿未收口唯一腿」
（2026-09-22 实测命中，这是判据正确工作，不是假红）。

故 `扫全仓` 转调 搜索能力（细节级别=完整契约）逐页取全量契约，
并留一个 `契约源` 注入口给变异样本用（注入的是「读取器」而非「路径」，
所以函数体内永远不需要出现声明面扫描）。

## 假绿防线（本工具第一版就踩过两次）

1. 第一版按 `数据.get('参数')` 读契约顶层 → 全仓 142 份契约读出空列表，
   却报「0 分歧」——**扫了 N 份不等于扫对了 N 份**。真形状是
   `{"契约版本":…, "能力契约":[{能力id, 参数:[…]}]}`：一份文件装多个能力。
2. 第二版又崩在 `返回.get('值结构')`：`返回` 自己有 dict / str 两种形状。

故本工具强制：取到的能力数为 0 时直接报「无鉴别力」并非零退出码，不做静默通过。

## 已知口径差异（如实报，不掩盖）

唯一腿（`能力目录.搜索能力`）的索引面与「全仓契约文件扫描」面**可能不同**
（实测：搜索能力总数 675，而契约文件扫描得 749）。本工具按唯一腿口径计数，
并在报告首行写明；两个数字的差属「索引覆盖缺口」，不是本工具的判据对象。

用法：
    python3.14 -m 开发工具.参数口径审计            # 只报告
    python3.14 -m 开发工具.参数口径审计 --写基线    # 落基线（只增不改，新增即红）
"""
