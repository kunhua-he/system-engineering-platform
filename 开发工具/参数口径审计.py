def 唯一腿读契约(限制: int = 100) -> Iterable[dict]:
    """转调唯一腿逐页取全量能力契约记录（生成器）。

    **不自己扫声明文件、不自己读 json** —— 那是第二条读取腿（哲学 1.2/1.3）。
    失败一律抛异常，由调用方 fail-closed 处理，不返回空列表冒充「平台没有能力」。
    """
    from 模块库.能力目录 import 搜索能力

    游标 = ""
    while True:
        出 = 搜索能力(关键词="", 限制=限制, 游标=游标, 细节级别="完整契约")
        if not 出.成功:
            raise RuntimeError(f"{唯一腿入口} 读取失败：{出.错误码} {出.错误说明}")
        值 = 出.值 or {}
        yield from (值.get("能力列表") or [])
        游标 = 值.get("下一条游标") or ""
        if not 游标:
            break


def _形状名(值) -> str:
    if isinstance(值, dict):
        return "字典型"
    if isinstance(值, list):
        return "列表型"
    if isinstance(值, str):
        return "文本型"
    if isinstance(值, bool):
        return "逻辑型"
    if 值 is None:
        return "空值"
    return type(值).__name__


def 扫全仓(契约源: Iterable[dict] | None = None) -> dict:
    """汇总全量能力契约的事实（只读）。

    `契约源` 是可注入的**读取器产出**（默认转调唯一腿 模块库/能力目录）——
    留这个口子是为了让变异样本能在临时夹具上跑，而不必真去查平台能力目录。
    注意：注进来的是已解析的契约记录，不是路径 —— 本函数不承担任何文件扫描。
    """
    记录迭代 = 唯一腿读契约() if 契约源 is None else 契约源
    型表: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    填表: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    返回形状: dict[str, list[str]] = defaultdict(list)
    能力数 = 0

    for 记录 in 记录迭代:
        if not isinstance(记录, dict):
            continue
        能力id = 记录.get("能力id") or "?"
        能力数 += 1
        返回形状[_形状名(记录.get("返回"))].append(能力id)
        for 参数 in 记录.get("参数") or []:
            if not isinstance(参数, dict):
                continue
            名称 = 参数.get("名称")
            if not 名称:
                continue
            型表[名称][str(参数.get("类型"))].append(能力id)
            填表[名称]["必填" if 参数.get("必填") else "可选"].append(能力id)

    return {"能力数": 能力数, "型表": 型表, "填表": 填表, "返回形状": 返回形状}


def 判分歧(事实: dict) -> dict:
    """把事实拆成「真分歧（判红）」与「同名不同义（只报）」两组。"""
    真分歧: list[dict] = []
    同名不同义: list[dict] = []

    形状表 = {str(k): v for k, v in 事实["返回形状"].items() if v}
    if len(形状表) > 1:
        真分歧.append({
            "类别": "契约字段形状分歧",
            "字段": "返回",
            "明细": {k: len(v) for k, v in 形状表.items()},
            "样本": {k: v[:5] for k, v in 形状表.items()},
        })

    for 名称, 类型表 in 事实["型表"].items():
        真类型 = {t for t in 类型表 if t not in ("None", "null", "空值")}
        if len(真类型) <= 1:
            continue
        合计 = sum(len(v) for v in 类型表.values())
        if 真类型 <= 数值族:
            真分歧.append({
                "类别": "同名参数类型分歧（数值族内）",
                "字段": 名称,
                "明细": {t: len(v) for t, v in 类型表.items()},
                "样本": {t: v[:5] for t, v in 类型表.items()},
            })
        else:
            同名不同义.append({
                "类别": "同名不同义",
                "字段": 名称,
                "说明": 同名不同义登记.get(名称, "（未登记：待裁决是改名还是统一）"),
                "明细": {t: len(v) for t, v in 类型表.items()},
                "合计": 合计,
            })

    return {"真分歧": 真分歧, "同名不同义": 同名不同义}


def 主函数(argv: list[str] | None = None) -> int:
    参数表 = list(sys.argv[1:] if argv is None else argv)
    写基线 = "--写基线" in 参数表
    系统根 = Path(__file__).resolve().parents[1]

    try:
        事实 = 扫全仓()
    except Exception as 错误:  # noqa: BLE001 —— 唯一腿读不动时 fail-closed，不当通过
        print(f"★ 唯一腿读契约失败，本报告无鉴别力（fail-closed）：{错误}")
        return 2
    if 事实["能力数"] == 0:
        print("★ 唯一腿返回 0 个能力 —— 本报告无鉴别力（不得当通过，fail-closed）")
        return 2

    分歧 = 判分歧(事实)
    真分歧 = 分歧["真分歧"]
    同名不同义 = 分歧["同名不同义"]

    print(f"参数口径审计（契约来源＝唯一腿 {唯一腿入口}，细节级别=完整契约）")
    print(f"能力 {事实['能力数']} 个")
    print()
    print(f"── 一、真分歧（应统一）{len(真分歧)} 项 ──")
    for 项 in 真分歧:
        print(f"  [{项['类别']}] {项['字段']}：{项['明细']}")
        for 形状名, 样本 in 项["样本"].items():
            print(f"      {形状名}：{'、'.join(样本)}")
    if not 真分歧:
        print("  无")
    print()
    print(f"── 二、同名不同义（已在登记表说明；未登记的待裁决）{len(同名不同义)} 项 ──")
    for 项 in sorted(同名不同义, key=lambda x: -x["合计"]):
        标记 = "已登记" if 项["字段"] in 同名不同义登记 else "★待裁决"
        print(f"  [{标记}] {项['字段']}：{项['明细']}｜{项['说明']}")
    待裁决 = [x for x in 同名不同义 if x["字段"] not in 同名不同义登记]
    print()
    填分歧 = [1 for _n, t in 事实["填表"].items() if len(t) > 1]
    print(f"── 三、必填口径分歧（纯事实，只报）{len(填分歧)} 项同名参数 ──")
    print()
    print(f"结论：真分歧 {len(真分歧)} 项｜同名不同义 {len(同名不同义)} 项（其中待裁决 {len(待裁决)}）")

    基线路径 = 系统根 / "开发工具/参数口径基线.json"
    if 写基线:
        # 落盘统一走**唯一写腿**（`文件系统支持库.文件操作.写入文件`），不裸 `write_text`：
        # 该腿自带「内核只读锁的解锁窗口 + 原子替换」，裸写会在整仓上锁后被内核以
        # `Operation not permitted` 拒（2026-09-23 实测）。
        from 支持库.后端.文件系统支持库.文件操作 import 写入文件
        写入文件(str(基线路径), json.dumps({
            "口径": "真分歧 = 应当统一的概念被写成多种定义（判红）；同名不同义 = 不同概念恰好同名（只报，待裁决改名）",
            "契约来源": 唯一腿入口,
            "能力数": 事实["能力数"],
            "真分歧": [{"类别": x["类别"], "字段": x["字段"], "明细": x["明细"]} for x in 真分歧],
            "同名不同义": [{"字段": x["字段"], "明细": x["明细"], "合计": x["合计"]} for x in 同名不同义],
            "取证": "python3.14 -m 开发工具.参数口径审计 --写基线",
        }, ensure_ascii=False, indent=2, sort_keys=True) + "\n").确保成功()
        print(f"基线已写入：{基线路径.relative_to(系统根)}")
        return 0

    if not 基线路径.is_file():
        return 1 if 真分歧 else 0
    try:
        基线 = json.loads(基线路径.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        print("★ 基线读不动 —— 按未核验处理（fail-closed）")
        return 2
    旧真 = {f"{x['类别']}::{x['字段']}" for x in 基线.get("真分歧", [])}
    新真 = {f"{x['类别']}::{x['字段']}" for x in 真分歧}
    新增 = sorted(新真 - 旧真)
    已减 = sorted(旧真 - 新真)
    print(f"基线比对：真分歧 {len(旧真)} → {len(新真)}")
    if 新增:
        print(f"  ✗ 新增真分歧 {len(新增)} 项（应统一却新增，阻断）：")
        for 键 in 新增:
            print(f"      {键}")
        return 1
    if 已减:
        print(f"  ✓ 真分歧减少 {len(已减)} 项（好事，请重跑 --写基线 收拢）：")
        for 键 in 已减:
            print(f"      {键}")
    print("  ✓ 无新增真分歧")
    return 0


if __name__ == "__main__":
    raise SystemExit(主函数())
