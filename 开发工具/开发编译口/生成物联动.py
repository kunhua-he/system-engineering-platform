"""生成物联动：按登记表把「平台固定需求的派生凭据」一次全自动生成（编译口步骤2/4 的实现）。

为什么要有这个落点（华哥 2026-09-22 裁决，原文）：

> 「如果是平台底层固定需求的，能不能编译的同时，全部自动生成凭据，而不是反复的去修。」
> 「例如说 json，契约什么的，能不能全自动生成……编译的同时，后台自动生成凭据和底座需求的，
>   而不是每次都需要手动去运行一条命令，等于说把多个命令，组装成一个统一的命令，
>   把平台需求的东西，全自动解决。那后续的维护，只需要代码修复就行。」

现场症状（2026-09-22 实测）：改一个契约版本要**手改 3 处**（`能力定义.json` 顶层版本 /
`包声明.json` 版本 / `说明/使用说明.md` 的 `- 版本：` 行），再手跑 2 条派生命令
（`依赖分两段 --生成`、`全量重算摘要`），漏一条就红一轮 —— 而这些都是「源一变就必然
跟着变」的派生件，本该机器做。审计件 §8.3/§8.4 早已把这一步写进设计（步骤2 生成物自动联动、
步骤4 自动修复 + 复跑确认），`编译口.py` 也留了「步骤4 生成物自动修复（本版未实现）」的位置，
本模块就是那一步的实现。

设计（对齐哲学 1.2「一类事情只有一条腿」）：

  · **判据不在这里**：每条凭据的生成命令与核验命令登记在**数据侧**
    `开发文档/规范/生成物登记表.json`（与 `文档类型判据.json` 同形制：新增一类凭据 = 改数据
    一处，不加代码文件）。本模块只读表、按序跑、归并结论，**不新建第二套判据**。
  · **只跑「派生」类**：`类别=登记`（基线冻结 —— 自动执行等于门禁自废：会把本次新增一起写进
    基线，把「只增不改」的方向抹平）与 `类别=人工`（正文是人的判断，硬刷会丢事实）
    **一律不跑**，只如实报「未生成 + 为什么」。
  · **修完必须复跑确认**：生成绿 ≠ 修好。本模块只负责生成并**如实回带真实退出码**；
    「复跑确认」由编译口步骤4 拿**步骤3 各门禁的真实退出码**做（同一批命令不重复跑第二遍）。
  · **fail-closed**：登记表缺失/不可读/形状非法、派生条目为 0、命令超时或起不来
    ⇒ 一律记「未核验」，不许静默跳过（AGENTS.md：解析不出来一律按未核验处理，防假绿）。

用法（一般不必手敲 —— 编译口 `--联动` 会调它）：

    python3.14 -m 开发工具.开发编译口.生成物联动 --只报    # 只跑核验命令，不写盘
    python3.14 -m 开发工具.开发编译口.生成物联动 --联动    # 按登记表跑全部派生生成命令
"""
from __future__ import annotations

import json
import subprocess
import sys
import time
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 公共契约.基础类型.逻辑类型 import 真, 假

登记表相对路径 = "开发文档/规范/生成物登记表.json"

#: 生成命令单项超时秒（写盘类；300 秒是给包数膨胀留的余量，实测各项秒级到十余秒）。
默认生成超时秒 = 300
#: 核验命令单项超时秒（只读口径，比生成快）。
默认核验超时秒 = 180

#: 只跑这两类之外的：执行器一律不碰（见模块 docstring 的「只跑派生类」）。
派生类别 = "派生"


class 登记表不可用(RuntimeError):
    """登记表缺失/不可读/形状非法 —— fail-closed：判不出派生凭据 ≠ 没有派生凭据。"""


def 跑命令(命令列表: list[str], 超时秒: int = 120,
          工作目录: Path | None = None) -> tuple[int, str, float]:
    """跑一条命令，返回（退出码，输出，耗时秒）。超时/崩溃/解码失败一律记 -1（未核验）。

    **唯一实现**：开发编译口的 `_跑` 直接引用本函数，不另写第二份 subprocess 包装。
    """
    开始 = time.monotonic()
    try:
        完成 = subprocess.run(
            命令列表, capture_output=True, text=True, timeout=超时秒,
            cwd=str(工作目录 or 系统根),
        )
        输出 = (完成.stdout or "") + (完成.stderr or "")
        # ★ 不能用 .strip()：git status --porcelain 首行形如 " M 路径"，那个前导空格
        #   **就是状态字段本身**。整段 strip 会把它抹掉 → 行[:2] 从 2 字符塌成 1 字符
        #   → 行[3:] 吃掉路径首字（实测 `开发工具/开发编译口/编译口.py` →
        #   `发工具/开发编译口/编译口.py`），随后 py_compile 报 No such file，
        #   编译口把正常的已跟踪改动误判为「失败」（假红）。只去尾部换行（rstrip）。
        return 完成.returncode, 输出.rstrip(), time.monotonic() - 开始
    except subprocess.TimeoutExpired:
        return -1, f"超时（>{超时秒}秒，按未核验处理，绝不按通过处理）", time.monotonic() - 开始
    except (OSError, UnicodeDecodeError) as 异常:
        # UnicodeDecodeError 也要接：子进程输出非 UTF-8 时 text=True 的解码发生在
        # subprocess 内部，不接就裸冒泡、把「未核验」变成崩溃。
        return -1, f"无法执行：{异常}", time.monotonic() - 开始


def _首行(文本: str, 上限: int = 160) -> str:
    """输出的首条非空行（给结论行做摘要；不截断成空串）。"""
    for 行 in 文本.splitlines():
        if 行.strip():
            return 行.strip()[:上限]
    return "（无输出）"


def 读登记表(根: Path) -> list[dict]:
    """读数据侧登记表。

    四种形态一律 fail-closed 抛 `登记表不可用`（空表不是通过、判不出不等于没有）：
    文件缺失 / 不可读（坏 JSON、编码、权限）/ 顶层不是对象 / `凭据` 不是非空列表 /
    `类别=派生` 条目为 0（扫描面为 0 不得记作通过，与防回潮各项同口径）。
    """
    路径 = 根 / 登记表相对路径
    if not 路径.is_file():
        raise 登记表不可用(
            f"登记表缺失：{登记表相对路径}（fail-closed：判不出派生凭据 ≠ 没有派生凭据）")
    try:
        数据 = json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as 错误:
        raise 登记表不可用(
            f"登记表不可读：{登记表相对路径}（{type(错误).__name__}: {错误}）") from 错误
    if not isinstance(数据, dict):
        raise 登记表不可用(f"登记表形状非法：{登记表相对路径} 顶层必须是对象")
    凭据 = 数据.get("凭据")
    if not isinstance(凭据, list) or not 凭据:
        raise 登记表不可用(
            f"登记表形状非法：{登记表相对路径} 的 `凭据` 必须是非空列表（空表不是通过）")
    if not [项 for 项 in 凭据 if isinstance(项, dict) and 项.get("类别") == 派生类别]:
        raise 登记表不可用(
            f"登记表里没有任何 `类别={派生类别}` 的凭据（扫描面为 0 不是通过）")
    return 凭据


def _命令(项: dict, 键: str) -> list[str] | None:
    """取一条 argv 命令；形状非法返回 None（调用方按未核验处理，不当「没这条」）。"""
    值 = 项.get(键)
    if not isinstance(值, list) or not 值:
        return None
    if not all(isinstance(x, str) and x.strip() for x in 值):
        return None
    return [str(x) for x in 值]


def 执行(根: Path, *, 写盘: bool,
        生成超时秒: int = 默认生成超时秒,
        核验超时秒: int = 默认核验超时秒,
        打印=print) -> dict:
    """按登记表跑派生凭据。`写盘=真` 跑生成命令；`写盘=假` 只跑核验命令（不写任何文件）。

    返回结构化结论（`退出码`：0 全绿 / 1 有红 / 2 有未核验 —— **未核验不占通过位**）：

    - `生成表`：逐条 `名字 / 类别 / 对应门禁 / 生成退出码 / 生成耗时秒 / 生成摘要 /
      核验退出码 / 核验耗时秒 / 核验摘要 / 结论`；`结论` 取值域见 `结论取值域`；
    - 计数：`派生数 / 生成成功数 / 生成失败数 / 复跑仍红数 / 未核验数 / 不自动数`；
    - `失败说明` / `未核验说明`：逐条点名（不静默）。

    调用方（编译口）拿它的 `生成表` 与步骤3 的门禁真实退出码做**复跑确认**，
    故本函数不重复跑门禁（同一批命令不跑第二遍）。
    """
    凭据 = 读登记表(根)
    派生 = [项 for 项 in 凭据 if isinstance(项, dict) and 项.get("类别") == 派生类别]
    不自动 = [项 for 项 in 凭据 if isinstance(项, dict) and 项.get("类别") != 派生类别]
    生成表: list[dict] = []
    失败说明: list[str] = []
    未核验说明: list[str] = []

    for 项 in 派生:
        名字 = str(项.get("名字") or "（未命名）")
        行: dict = {
            "名字": 名字,
            "类别": 项.get("类别"),
            "对应门禁": 项.get("对应门禁"),
            "生成退出码": None,
            "生成耗时秒": 0.0,
            "生成摘要": "",
            "核验退出码": None,
            "核验耗时秒": 0.0,
            "核验摘要": "",
            "结论": "",
        }
        # ① 生成（仅写盘口径）。生成判红/未核验**仍继续跑核验**：核验能给出「现场到底是什么
        #    状态」，比只看生成退出码有用（只报生成码会把「生成器坏了但现场其实一致」误读成红）。
        if 写盘:
            生成命令 = _命令(项, "生成命令")
            if 生成命令 is None:
                # 声明为派生却给不出可执行命令 = 登记表与实现不符（空头承诺），按未核验
                未核验说明.append(f"{名字}：登记表里 `生成命令` 缺失或形状非法（声明派生却给不出命令）")
                行["结论"] = "未核验"
                打印(f"  [生成] {名字} —— 登记表里没有可执行的生成命令（未核验）")
                生成表.append(行)
                continue
            码, 输出, 耗时 = 跑命令(生成命令, 生成超时秒, 根)
            行["生成退出码"], 行["生成耗时秒"], 行["生成摘要"] = 码, 耗时, _首行(输出)
            打印(f"  [生成] {名字} 退出码={码} 耗时={耗时:.2f}s：{行['生成摘要']}")
            if 码 == -1:
                未核验说明.append(f"{名字}：生成命令未核验（{行['生成摘要']}）")
                行["结论"] = "未核验"
                生成表.append(行)
                continue
            if 码 != 0:
                失败说明.append(f"{名字}：生成命令判红（退出码 {码}）")

        # ② 核验（两种口径都跑：写盘口径 = 复跑确认，只读口径 = 现场一致性核对）
        核验命令 = _命令(项, "核验命令")
        if 核验命令 is None:
            未核验说明.append(f"{名字}：登记表里 `核验命令` 缺失或形状非法（判不出 ≠ 通过）")
            行["结论"] = 行["结论"] or "未核验"
            打印(f"  [核验] {名字} —— 登记表里没有可执行的核验命令（未核验）")
            生成表.append(行)
            continue
        码2, 输出2, 耗时2 = 跑命令(核验命令, 核验超时秒, 根)
        行["核验退出码"], 行["核验耗时秒"], 行["核验摘要"] = 码2, 耗时2, _首行(输出2)
        打印(f"  [核验] {名字} 退出码={码2} 耗时={耗时2:.2f}s：{行['核验摘要']}")

        # ③ 结论（写盘口径报「已生成·复跑…」；只读口径报「现场…」）
        if 码2 == -1:
            行["结论"] = "未核验"
            未核验说明.append(f"{名字}：核验命令未核验（{行['核验摘要']}）")
        elif 写盘 and 行["生成退出码"] != 0:
            行["结论"] = "生成失败·现场一致" if 码2 == 0 else "生成失败·现场不一致"
        elif 码2 == 0:
            行["结论"] = "已生成·复跑绿" if 写盘 else "现场一致"
        else:
            行["结论"] = "已生成·复跑仍红" if 写盘 else "现场不一致"
            if 写盘:
                失败说明.append(f"{名字}：已生成但复跑仍红（核验退出码 {码2}）")
            else:
                失败说明.append(f"{名字}：现场与源不一致（核验退出码 {码2}）")
        生成表.append(行)

    生成成功数 = len([x for x in 生成表 if x["生成退出码"] == 0])
    生成失败数 = len([x for x in 生成表
                    if isinstance(x["生成退出码"], int) and x["生成退出码"] not in (0, -1)])
    复跑仍红数 = len([x for x in 生成表 if x["结论"] in ("已生成·复跑仍红", "现场不一致")])
    未核验数 = len([x for x in 生成表 if x["结论"] == "未核验"])
    退出码 = 2 if 未核验数 else (1 if 失败说明 else 0)
    return {
        "写盘": 写盘,
        "生成表": 生成表,
        "派生数": len(派生),
        "不自动数": len(不自动),
        "不自动清单": [str(x.get("名字")) for x in 不自动],
        "生成成功数": 生成成功数,
        "生成失败数": 生成失败数,
        "复跑仍红数": 复跑仍红数,
        "未核验数": 未核验数,
        "失败说明": 失败说明,
        "未核验说明": 未核验说明,
        "退出码": 退出码,
    }


def 主函数(argv: list[str] | None = None) -> int:
    """命令行入口：`--只报`（只核验不写盘）/ `--联动`（按登记表生成全部派生凭据）。"""
    参 = list(sys.argv[1:] if argv is None else argv)
    未知 = [项 for 项 in 参 if 项 not in ("--只报", "--联动")]
    if 未知 or len(参) != 1:
        print(f"未知或缺失参数：{' '.join(未知) or '（未给口径）'}；"
              f"本入口只支持 `--只报`（只核验不写盘）或 `--联动`（生成全部派生凭据）。")
        return 2
    写盘 = "--联动" in 参
    print(f"═══ 生成物联动（{'写盘' if 写盘 else '只报'}口径；登记表 {登记表相对路径}）═══")
    try:
        结论 = 执行(系统根, 写盘=写盘)
    except 登记表不可用 as 异常:
        print(f"登记表不可用（fail-closed，按未核验处理）：{异常}")
        return 2
    for 行 in 结论["生成表"]:
        if 行["结论"] in ("已生成·复跑仍红", "现场不一致", "生成失败·现场不一致", "未核验"):
            print(f"  ! {行['名字']}：{行['结论']}")
    print(f"派生 {结论['派生数']} 条：生成绿 {结论['生成成功数']}、生成红 {结论['生成失败数']}、"
          f"复跑仍红 {结论['复跑仍红数']}、未核验 {结论['未核验数']}；"
          f"另有不自动生成 {结论['不自动数']} 条（{ '、'.join(结论['不自动清单']) }）")
    return int(结论["退出码"])


if __name__ == "__main__":
    sys.exit(主函数())
