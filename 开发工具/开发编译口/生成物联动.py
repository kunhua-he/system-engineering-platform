class 登记表不可用(RuntimeError):
    """登记表缺失/不可读/形状非法 —— fail-closed：判不出派生凭据 ≠ 没有派生凭据。"""


def _跑一次(命令列表: list[str], 超时秒: int,
          工作目录: Path | None) -> tuple[int, str]:
    """真正跑那条命令，返回（退出码，输出）。超时/崩溃/解码失败一律记 -1（未核验）。

    拆出来只为让 `跑命令` 有**唯一出口**，好把执行耗时账本记在一处（见 `跑命令`）。
    """
    try:
        完成 = subprocess.run(
            命令列表, capture_output=True, text=True, timeout=超时秒,
            cwd=str(工作目录 or 系统根),
        )
        输出 = (完成.stdout or "") + (完成.stderr or "")
        # ★ 不能用 .strip()：git status --porcelain 首行形如 " M 路径"，那个前导空格
        #   **就是状态字段本身**。整段 strip 会把它抹掉 → 行[:2] 从 2 字符塌成 1 字符
        #   → 行[3:] 吃掉路径首字（实测 `开发工具/开发编译口/编译口.py` →
        #   `发工具/开发编译口/编译口.py`），随后 py_compile 报 No such file，
        #   编译口把正常的已跟踪改动误判为「失败」（假红）。只去尾部换行（rstrip）。
        return 完成.returncode, 输出.rstrip()
    except subprocess.TimeoutExpired:
        return -1, f"超时（>{超时秒}秒，按未核验处理，绝不按通过处理）"
    except (OSError, UnicodeDecodeError) as 异常:
        # UnicodeDecodeError 也要接：子进程输出非 UTF-8 时 text=True 的解码发生在
        # subprocess 内部，不接就裸冒泡、把「未核验」变成崩溃。
        return -1, f"无法执行：{异常}"


def 跑命令(命令列表: list[str], 超时秒: int = 120,
          工作目录: Path | None = None) -> tuple[int, str, float]:
    """跑一条命令，返回（退出码，输出，耗时秒）。超时/崩溃/解码失败一律记 -1（未核验）。

    **唯一实现**：开发编译口的 `_跑` 直接引用本函数，不另写第二份 subprocess 包装。

    **执行耗时账本**（华哥 2026-09-23）：本函数是开发工具侧**所有**子进程的唯一出口
    （编译口的定向测试、派生凭据生成、语法编译都经它），故耗时记在这一处即可全覆盖。
    开关关着时 `记一笔` 第一行就返回、不碰盘（见 公共契约/运行时/执行耗时账本.py）。
    """
    开始 = time.monotonic()
    退出码, 输出 = _跑一次(命令列表, 超时秒, 工作目录)
    耗时 = time.monotonic() - 开始
    执行耗时账本.记一笔(
        来源="开发工具.开发编译口.生成物联动.跑命令", 命令=" ".join(命令列表),
        耗时秒=耗时, 退出码=退出码, 工作目录=str(工作目录 or 系统根),
        输出字节=len(输出))
    return 退出码, 输出, 耗时


def _首行(文本: str, 上限: int = 160) -> str:
    """输出的首条非空行（给结论行做摘要；不截断成空串）。"""
    for 行 in 文本.splitlines():
        if 行.strip():
            return 行.strip()[:上限]
    return "（无输出）"


def 读登记表(根: Path) -> list[dict]:
    """读数据侧登记表。

    四种形态一律 fail-closed 抛 `登记表不可用`（空表不是通过、判不出不等于没有）：
    文件缺失 / 不可读（坏 JSON、编码、权限）/ 顶层不是对象 / `凭据` 不是非空列表 /
    `类别=派生` 条目为 0（扫描面为 0 不得记作通过，与防回潮各项同口径）。
    """
    路径 = 根 / 登记表相对路径
    if not 路径.is_file():
        raise 登记表不可用(
            f"登记表缺失：{登记表相对路径}（fail-closed：判不出派生凭据 ≠ 没有派生凭据）")
    try:
        数据 = json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as 错误:
        raise 登记表不可用(
            f"登记表不可读：{登记表相对路径}（{type(错误).__name__}: {错误}）") from 错误
    if not isinstance(数据, dict):
        raise 登记表不可用(f"登记表形状非法：{登记表相对路径} 顶层必须是对象")
    凭据 = 数据.get("凭据")
    if not isinstance(凭据, list) or not 凭据:
        raise 登记表不可用(
            f"登记表形状非法：{登记表相对路径} 的 `凭据` 必须是非空列表（空表不是通过）")
    if not [项 for 项 in 凭据 if isinstance(项, dict) and 项.get("类别") == 派生类别]:
        raise 登记表不可用(
            f"登记表里没有任何 `类别={派生类别}` 的凭据（扫描面为 0 不是通过）")
    return 凭据


def _命令(项: dict, 键: str) -> list[str] | None:
    """取一条 argv 命令；形状非法返回 None（调用方按未核验处理，不当「没这条」）。"""
    值 = 项.get(键)
    if not isinstance(值, list) or not 值:
        return None
    if not all(isinstance(x, str) and x.strip() for x in 值):
        return None
    return [str(x) for x in 值]


#: 「按影响面包」凭据的节点并发口径。**不自己起第二套线程池** —— 复用平台
#: `系统核心支持库.进程管理.执行命令集`（并行 8 路、单批 ≤64 条），它的逐条实现又复用
#: `执行命令`（危险命令拦截 / argv 拆分 / 输出有界 / 进程组整组回收同一实现）。
#: 华哥 2026-09-22：「拆成 N 多个节点，然后复用我们的多线程库。快速的去解决掉。」
节点并发上限 = 8


def 跑分片(命令前缀: list[str], 分片表: list[str], 超时秒: int,
           根: Path) -> tuple[int, str, list[dict]]:
    """把一个「按影响面包」的凭据拆成 **N 个节点并行**跑（一个分片一个节点）。

    返回（总退出码, 聚合摘要, 逐节点结果）。总退出码：全 0 → 0；有红 → 1；
    有节点压根没跑起来（超时/拦截/执行失败）→ -1（未核验，不占通过位）。

    为什么并行：同一凭据对不同包**互相独立**（各写各包的文件），串行跑 N 个包是纯排队。
    为什么用 `执行命令集` 而不是 `concurrent.futures`：那是**第二条腿** —— 本仓已有
    有界的并行命令能力，自己再起一个池，进程组回收/输出上限/危险命令拦截就得各写一份。
    """
    from 支持库.后端.系统核心支持库.进程管理 import 执行命令集

    节点表: list[dict] = []
    批大小 = 64          # 与 `执行命令集上限条数` 同口径（超出请分批）
    墙钟开始 = time.monotonic()
    for 起 in range(0, len(分片表), 批大小):
        批 = 分片表[起:起 + 批大小]
        命令表 = [" ".join([*命令前缀, 分片]) for 分片 in 批]
        批结果 = 执行命令集(命令表=命令表, 模式="并行", 超时秒=float(超时秒),
                          工作目录=str(根))
        if not 批结果.成功 or not isinstance(批结果.值, dict):
            原因 = f"{批结果.错误码}：{批结果.错误说明}"
            节点表.extend({"分片": 分片, "退出码": -1, "耗时秒": 0.0,
                         "摘要": f"执行命令集未跑成（{原因}）"} for 分片 in 批)
            continue
        for 项 in 批结果.值.get("结果表") or []:
            if not isinstance(项, dict):
                continue
            序号 = 项.get("序号")
            下标 = (序号 - 1) if isinstance(序号, int) and 1 <= 序号 <= len(批) else None
            分片 = 批[下标] if 下标 is not None else f"（序号越界：{序号!r}）"
            退出码 = 项.get("退出码")
            节点表.append({
                "分片": 分片,
                "退出码": int(退出码) if isinstance(退出码, int) else -1,
                "耗时秒": round(float(项.get("耗时毫秒") or 0) / 1000, 2),
                "摘要": _首行(str(项.get("标准输出") or "") + str(项.get("错误输出") or "")),
            })
    墙钟秒 = round(time.monotonic() - 墙钟开始, 2)
    未跑 = [项["分片"] for 项 in 节点表 if 项["退出码"] == -1]
    红 = [项["分片"] for 项 in 节点表 if 项["退出码"] > 0]
    总退出码 = -1 if 未跑 else (1 if 红 else 0)
    摘要 = (f"{len(节点表)} 个节点并行（{节点并发上限} 路；墙钟 {墙钟秒}s）；"
           f"红 {len(红)}、未跑 {len(未跑)}")
    if 红:
        摘要 += f"；红项：{'、'.join(红[:5])}{' …' if len(红) > 5 else ''}"
    if 未跑:
        摘要 += f"；未跑：{'、'.join(未跑[:5])}{' …' if len(未跑) > 5 else ''}"
    return 总退出码, 摘要, 节点表


def _跑一条(命令前缀: list[str], 分片表: list[str], 超时秒: int,
           根: Path) -> tuple[int, str, float, list[dict]]:
    """跑一条凭据命令。无分片 = 单进程；有分片 = 拆 N 节点并行（见 `跑分片`）。

    返回（退出码, 输出摘要, 耗时秒, 逐节点结果）。
    """
    if not 分片表:
        码, 输出, 耗时 = 跑命令(命令前缀, 超时秒, 根)
        return 码, 输出, 耗时, []
    码, 摘要, 节点表 = 跑分片(命令前缀, 分片表, 超时秒, 根)
    耗时 = round(sum(项["耗时秒"] for 项 in 节点表), 2)
    return 码, 摘要, 耗时, 节点表


def 执行(根: Path, *, 写盘: bool,
        受影响包目录: list[str] | None = None,
        生成超时秒: int = 默认生成超时秒,
        核验超时秒: int = 默认核验超时秒,
        打印=print) -> dict:
    """按登记表跑派生凭据。`写盘=真` 跑生成命令；`写盘=假` 只跑核验命令（不写任何文件）。

    `受影响包目录`：给声明了 `按影响面包` 的条目用的扫描面（见模块 docstring）。
    **`None` 与 `[]` 语义不同**：`None` = 范围未知 ⇒ 记未核验；`[]` = 范围已知且为空 ⇒ 跳过。
    非空时该凭据**拆成 N 个节点并行跑**（一个包一个节点，8 路，见 `跑分片`）。

    返回结构化结论（`退出码`：0 全绿 / 1 有红 / 2 有未核验 —— **未核验不占通过位**）：

    - `生成表`：逐条 `名字 / 类别 / 对应门禁 / 生成退出码 / 生成耗时秒 / 生成摘要 / 生成节点 /
      核验退出码 / 核验耗时秒 / 核验摘要 / 核验节点 / 结论`；`生成节点` 与 `核验节点` 只在
      `按影响面包` 的条目上非空，逐节点带 `分片 / 退出码 / 耗时秒 / 摘要`（判红时**能点出是哪个包**）；
    - 计数：`派生数 / 生成成功数 / 生成失败数 / 复跑仍红数 / 未核验数 / 跳过数 / 不自动数`；
    - `失败说明` / `未核验说明`：逐条点名（不静默）。

    调用方（编译口）拿它的 `生成表` 与步骤3 的门禁真实退出码做**复跑确认**，
    故本函数不重复跑门禁（同一批命令不跑第二遍）。
    """
    凭据 = 读登记表(根)
    派生 = [项 for 项 in 凭据 if isinstance(项, dict) and 项.get("类别") == 派生类别]
    不自动 = [项 for 项 in 凭据 if isinstance(项, dict) and 项.get("类别") != 派生类别]
    生成表: list[dict] = []
    失败说明: list[str] = []
    未核验说明: list[str] = []

    for 项 in 派生:
        名字 = str(项.get("名字") or "（未命名）")
        行: dict = {
            "名字": 名字,
            "类别": 项.get("类别"),
            "对应门禁": 项.get("对应门禁"),
            "生成退出码": None,
            "生成耗时秒": 0.0,
            "生成摘要": "",
            "生成节点": [],
            "核验退出码": None,
            "核验耗时秒": 0.0,
            "核验摘要": "",
            "核验节点": [],
            "结论": "",
        }
        # ⓪ 扫描面（仅 `按影响面包` 条目）：范围未知记未核验，范围为空记跳过。
        分片表: list[str] = []
        if 项.get("按影响面包"):
            if 受影响包目录 is None:
                行["结论"] = "未核验"
                未核验说明.append(f"{名字}：调用方未提供受影响包目录（扫描面未知，不猜）")
                打印(f"  [跳过] {名字} —— 未提供受影响包目录（未核验）")
                生成表.append(行)
                continue
            if not 受影响包目录:
                行["结论"] = "无受影响包·跳过"
                打印(f"  [跳过] {名字} —— 本轮无受影响包（范围为空，不跑）")
                生成表.append(行)
                continue
            分片表 = [str(路径) for 路径 in 受影响包目录]
        # ① 生成（仅写盘口径）。生成判红/未核验**仍继续跑核验**：核验能给出「现场到底是什么
        #    状态」，比只看生成退出码有用（只报生成码会把「生成器坏了但现场其实一致」误读成红）。
        if 写盘:
            生成命令 = _命令(项, "生成命令")
            if 生成命令 is None:
                # 声明为派生却给不出可执行命令 = 登记表与实现不符（空头承诺），按未核验
                未核验说明.append(f"{名字}：登记表里 `生成命令` 缺失或形状非法（声明派生却给不出命令）")
                行["结论"] = "未核验"
                打印(f"  [生成] {名字} —— 登记表里没有可执行的生成命令（未核验）")
                生成表.append(行)
                continue
            码, 输出, 耗时, 节点 = _跑一条(生成命令, 分片表, 生成超时秒, 根)
            行["生成退出码"], 行["生成耗时秒"] = 码, 耗时
            行["生成摘要"], 行["生成节点"] = _首行(输出), 节点
            打印(f"  [生成] {名字} 退出码={码} 耗时={耗时:.2f}s：{行['生成摘要']}")
            if 码 == -1:
                未核验说明.append(f"{名字}：生成命令未核验（{行['生成摘要']}）")
                行["结论"] = "未核验"
                生成表.append(行)
                continue
            if 码 != 0:
                失败说明.append(f"{名字}：生成命令判红（退出码 {码}；{行['生成摘要']}）")

        # ② 核验（两种口径都跑：写盘口径 = 复跑确认，只读口径 = 现场一致性核对）
        核验命令 = _命令(项, "核验命令")
        if 核验命令 is None:
            未核验说明.append(f"{名字}：登记表里 `核验命令` 缺失或形状非法（判不出 ≠ 通过）")
            行["结论"] = 行["结论"] or "未核验"
            打印(f"  [核验] {名字} —— 登记表里没有可执行的核验命令（未核验）")
            生成表.append(行)
            continue
        码2, 输出2, 耗时2, 节点2 = _跑一条(核验命令, 分片表, 核验超时秒, 根)
        行["核验退出码"], 行["核验耗时秒"] = 码2, 耗时2
        行["核验摘要"], 行["核验节点"] = _首行(输出2), 节点2
        打印(f"  [核验] {名字} 退出码={码2} 耗时={耗时2:.2f}s：{行['核验摘要']}")

        # ③ 结论（写盘口径报「已生成·复跑…」；只读口径报「现场…」）
        if 码2 == -1:
            行["结论"] = "未核验"
            未核验说明.append(f"{名字}：核验命令未核验（{行['核验摘要']}）")
        elif 写盘 and 行["生成退出码"] != 0:
            行["结论"] = "生成失败·现场一致" if 码2 == 0 else "生成失败·现场不一致"
        elif 码2 == 0:
            行["结论"] = "已生成·复跑绿" if 写盘 else "现场一致"
        else:
            行["结论"] = "已生成·复跑仍红" if 写盘 else "现场不一致"
            if 写盘:
                失败说明.append(f"{名字}：已生成但复跑仍红（核验退出码 {码2}）")
            else:
                失败说明.append(f"{名字}：现场与源不一致（核验退出码 {码2}）")
        生成表.append(行)

    生成成功数 = len([x for x in 生成表 if x["生成退出码"] == 0])
    生成失败数 = len([x for x in 生成表
                    if isinstance(x["生成退出码"], int) and x["生成退出码"] not in (0, -1)])
    复跑仍红数 = len([x for x in 生成表 if x["结论"] in ("已生成·复跑仍红", "现场不一致")])
    未核验数 = len([x for x in 生成表 if x["结论"] == "未核验"])
    跳过数 = len([x for x in 生成表 if x["结论"] == "无受影响包·跳过"])
    # 逐节点红数（只有 `按影响面包` 的条目有节点）：用来回答「N 个节点里红了几片」，
    # 与「整条凭据红了几条」是两个粒度 —— 前者定位到包，后者定位到凭据。
    节点红数 = sum(len([n for n in (x.get("生成节点") or []) + (x.get("核验节点") or [])
                      if n.get("退出码", 0) > 0]) for x in 生成表)
    退出码 = 2 if 未核验数 else (1 if 失败说明 else 0)
    return {
        "写盘": 写盘,
        "生成表": 生成表,
        "派生数": len(派生),
        "不自动数": len(不自动),
        "不自动清单": [str(x.get("名字")) for x in 不自动],
        "生成成功数": 生成成功数,
        "生成失败数": 生成失败数,
        "复跑仍红数": 复跑仍红数,
        "未核验数": 未核验数,
        "跳过数": 跳过数,
        "节点红数": 节点红数,
        "失败说明": 失败说明,
        "未核验说明": 未核验说明,
        "退出码": 退出码,
    }


def 主函数(argv: list[str] | None = None) -> int:
    """命令行入口：默认写盘（全自动）；`--只读` 只核验不写盘；`--包 <目录>…` 指定扫描面。"""
    参 = list(sys.argv[1:] if argv is None else argv)
    未知 = [项 for 项 in 参 if 项.startswith("--") and 项 != "--只读"]
    if 未知:
        print(f"未知参数：{' '.join(未知)}；本入口支持 `--只读`（只核验）与 `--包 <目录>…`。")
        return 2
    写盘 = "--只读" not in 参
    # 没给 `--包` ⇒ 扫描面未知（按未核验处理，不猜）；给了但后面空 ⇒ 空扫描面（判错）。
    包目录表: list[str] | None = None
    if "--包" in 参:
        包目录表 = [项 for 项 in 参[参.index("--包") + 1:] if not 项.startswith("--")]
        if not 包目录表:
            print("`--包` 后面没跟任何目录（空扫描面）")
            return 2
    print(f"═══ 生成物联动（{'写盘' if 写盘 else '只读'}口径；登记表 {登记表相对路径}）═══")
    try:
        结论 = 执行(系统根, 写盘=写盘, 受影响包目录=包目录表)
    except 登记表不可用 as 异常:
        print(f"登记表不可用（fail-closed，按未核验处理）：{异常}")
        return 2
    for 行 in 结论["生成表"]:
        if 行["结论"] in ("已生成·复跑仍红", "现场不一致", "生成失败·现场不一致", "未核验"):
            print(f"  ! {行['名字']}：{行['结论']}")
    print(f"派生 {结论['派生数']} 条：生成绿 {结论['生成成功数']}、生成红 {结论['生成失败数']}、"
          f"复跑仍红 {结论['复跑仍红数']}、未核验 {结论['未核验数']}、"
          f"无受影响包跳过 {结论['跳过数']}；"
          f"另有不自动生成 {结论['不自动数']} 条（{ '、'.join(结论['不自动清单']) }）")
    return int(结论["退出码"])


if __name__ == "__main__":
    sys.exit(主函数())
