            # 反向破坏**不能**走「python3.14 -m 发布门禁」那条子进程命令行：那是跑整轮
            # 发布门禁（132 秒级），不是这一项，而发布门禁没有「只跑某项」的开关。
            # 它的入口是 in-process 可调用的（发布门禁 29 行接线消费的正是它），
