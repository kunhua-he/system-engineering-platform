    print("五态结论：干净通过（只报告类信息见上方各门禁输出；存量冻结债以登记基线为准）。")
    print(f"  按检查项如实声明：语法编译 已核验；测试伪装门禁 只报告（阻断口径在「硬限制不得增加」，"
          f"唯一接线腿见 门禁清单 注释）；防回潮六项判据本轮未纳入（原因与落点见"
          f"`_防回潮独立入口勘定`），反向破坏已核验{覆盖声明后缀}。")
