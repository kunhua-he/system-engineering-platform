def _跑反向破坏() -> tuple[int, str, float]:
    """跑「反向破坏」这一项：**消费发布门禁 29/30 行接线用的同一函数**，不另写判据。

    为什么不能写成子进程命令行：发布门禁**没有「只跑某项」的开关**，
    `python3.14 -m 开发工具.发布门禁.运行发布门禁` 是整轮门禁（实测 132 秒级），
    写成本清单里的一行等于把整轮发布门禁塞进开发循环，红线超时。
    为什么 in-process：它的入口本就是按 in-process 消费设计的（发布门禁自己在
    `__main__` 里直调 `校验反向破坏()`），本口不新增第二套调用腿。

    口径逐字对齐发布门禁：`校验反向破坏()` → `_防回潮检查("反向破坏", …)`
    —— **是否阻断由 `防回潮阻断配置` 显式配置**（13.2 要求），本口不另写一份降级逻辑。

    返回 `-1` = 未核验（取不到入口 / 抛异常 / 判据返回 None），**绝不按通过处理**。
    """
    开始 = time.monotonic()
    try:
        from 开发工具.发布门禁.运行发布门禁 import 校验反向破坏
        from 开发工具.发布门禁.运行发布门禁_防回潮公共 import _防回潮检查
        原判通过, 原判详情 = 校验反向破坏()
        通过, 详情 = _防回潮检查("反向破坏", 原判通过, 原判详情)
    except Exception as 错误:  # noqa: BLE001 —— fail-closed：取不到/跑不起来即未核验
        return -1, (f"反向破坏无法执行（{type(错误).__name__}: {错误}），按未核验处理，"
                    f"绝不当通过"), time.monotonic() - 开始
    耗时 = time.monotonic() - 开始
    if 通过 is None:
        return -1, f"{详情}（判据返回「未核验」，不占通过位）", 耗时
    return (0 if 通过 else 1), str(详情), 耗时




def _三拍自证() -> int:
    """编译口自身三拍：绿拍（真门禁必绿）→ 红拍（坏样本必红）→ 恢复拍（清理后归绿）。

    坏样本目录按 **PID 隔离**（`开发编译口自证_<pid>`）：固定同名目录在 40 路并行下会
    互删同一份坏样本 —— 红拍看到「文件不存在」也算非 0，于是并行时红拍会假绿通过。
    """
    坏样本目录 = Path(tempfile.gettempdir()) / f"开发编译口自证_{os.getpid()}"
    坏样本 = 坏样本目录 / "坏样本.py"
    try:
        print("── 三拍自证：绿拍 ──")
        退出码, 输出, _ = _跑(["python3.14", "-m", "开发工具.能力id冻结基线门禁"], 超时秒=120)
        print(f"  能力id冻结基线门禁 退出码={退出码}（期望 0）：{_尾部(输出, 1)}")
        绿拍成立 = 退出码 == 0

        print("── 三拍自证：红拍（故意弄坏，必须红）──")
        坏样本目录.mkdir(parents=True, exist_ok=True)
        坏样本.write_text("def 残缺(:\n", encoding="utf-8")
        退出码, 输出, _ = _跑(["python3.14", "-m", "py_compile", str(坏样本)], 超时秒=60)
        print(f"  坏样本 py_compile 退出码={退出码}（期望非 0）：{_尾部(输出, 1)}")
        红拍成立 = 退出码 != 0

        print("── 三拍自证：恢复拍（清理后必须归绿）──")
        坏样本.unlink(missing_ok=True)
        退出码, 输出, _ = _跑(["python3.14", "-m", "py_compile", str(系统根 / "开发工具/开发编译口/编译口.py")], 超时秒=60)
        print(f"  编译口本体 py_compile 退出码={退出码}（期望 0）")
        恢复拍成立 = 退出码 == 0 and not 坏样本.exists()

        if 绿拍成立 and 红拍成立 and 恢复拍成立:
            print("三拍自证通过：绿必绿 / 坏必红 / 恢复归绿。")
            return 0
        print(f"三拍自证失败：绿拍={绿拍成立} 红拍={红拍成立} 恢复拍={恢复拍成立}")
        return 1
    finally:
        # 无论中途怎样都清干净：并行期残留会污染下一轮的绿拍判定。
        坏样本.unlink(missing_ok=True)
        try:
            坏样本目录.rmdir()
        except OSError:
            pass


