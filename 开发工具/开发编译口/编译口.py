def _跑(命令列表: list[str], 超时秒: int = 120) -> tuple[int, str, float]:
    """跑一条命令，返回（退出码，尾部输出，耗时秒）。超时/崩溃/解码失败一律记 -1（未核验）。"""
    开始 = time.monotonic()
    try:
        完成 = subprocess.run(
            命令列表, capture_output=True, text=True, timeout=超时秒, cwd=str(系统根),
        )
        输出 = (完成.stdout or "") + (完成.stderr or "")
        # ★ 不能用 .strip()：git status --porcelain 首行形如 " M 路径"，那个前导空格**就是状态字段本身**。
        #   整段 strip 会把它抹掉 → 行[:2] 从 2 字符塌成 1 字符 → 行[3:] 吃掉路径首字
        #   （实测：`开发工具/开发编译口/编译口.py` → `发工具/开发编译口/编译口.py`，
        #    随后 py_compile 报 No such file，编译口把正常的已跟踪改动误判为「失败」假红）。
        #   只去尾部换行（rstrip），保留左侧空白。
        return 完成.returncode, 输出.rstrip(), time.monotonic() - 开始
    except subprocess.TimeoutExpired:
        return -1, f"超时（>{超时秒}秒，按未核验处理，绝不按通过处理）", time.monotonic() - 开始
    except (OSError, UnicodeDecodeError) as 异常:
        # UnicodeDecodeError 也要接：子进程输出非 UTF-8（如告警写 GBK 字节）时 text=True
        # 的解码发生在 subprocess 内部，不接就裸冒泡、把「未核验」变成崩溃退出 1。
        return -1, f"无法执行：{异常}", time.monotonic() - 开始


