#: `_跑` 已上移到 `开发工具/开发编译口/生成物联动.py`（本口顶部 import 引入）：
#: 它是本口与生成物联动**共用的唯一 subprocess 包装**，两处各写一份就是第二条腿。
#: 其中「不能用 .strip()」那条加固（git porcelain 首行前导空格 = 状态字段本身）
