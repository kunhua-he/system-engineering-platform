#: 「写者是不是平台自己的编译机」；两处各写一份，一改一不改就会让那道判据静默失效。
锁相对路径 = 编译机锁相对路径

#: 陈旧锁阈值（秒）。单轮实测 2~4 分钟、最长单项超时 300 秒 ⇒ 1 小时远大于任何一轮，
#: 超过它的锁必然是残留（进程崩了没来得及释放）可夺；活锁不会被误夺。
锁陈旧秒 = 3600

#: 有界排队等待上限（秒）与环境变量名：锁被**活写者**持有时排队等，不再当场拒启
#: （2026-09-24 批R R-25）。
#:
#: 为什么改（R-19 实测，本条的现场）：单写者锁本身是对的（防两个写者同改派生件），
#: 错的是「被占就拒启」—— 活被弹回调用方只会让它重试或放弃，而等待成本远低于重试。
#: 当日代价：**4 次拒启 ＋ 1 次 120 秒超时，两个读数根本没取到**。
#: 取值依据：单轮编译实测 2~4 分钟（见上 `锁陈旧秒` 注释）、`R-22` 实测
#: `自修复工具.静态编译` max 90.2 秒 ⇒ 900 秒覆盖「前面排 2~3 轮」；
#: 且**仍有界**（不删超时：无限等就是资源泄漏的温床），到上限才拒启。
#: 外层的调用方超时（如 `自修复工具.静态编译` 缺省 600 秒）是比它更紧的边界，
#: 两者取小即本次真实等待上限 —— 排队腿不持有任何句柄，被外层掐断也不留残留。
排队上限环境变量 = "编译口排队上限秒"
排队上限秒 = 900.0

#: 排队轮询间隔（秒）。编译一轮以分钟计，2 秒粒度足够，且不会把等待变成忙等。
排队轮询秒 = 2.0

#: 锁文件「刚建、内容还没落」的容忍窗（秒）。
#: 为什么需要：`占单写者锁` 是 `O_CREAT|O_EXCL` **先建空文件、再写内容**；并发的
#: 第二个进程在这个微窗口里读到的是空文件 —— `_读锁` 会判 `锁不可判定`（fail-closed）
#: ⇒ 本该「等它写完」的事被报成「判不出持有者」。该窗内一律按「对方正在写」重试；
#: 超过它仍不可判定才拒启（fail-closed 不变）。
不可判定容忍环境变量 = "编译口不可判定容忍秒"
不可判定容忍秒 = 6.0


class 锁被占(RuntimeError):
    """同树已有编译口在跑（锁被活进程持有）—— 拒启，不并发写。"""


class 锁不可判定(RuntimeError):
    """锁判不出持有者（形状非法 / 字段缺失 / 时刻解析不出）—— fail-closed 拒启。"""


def _进程存在(pid: int) -> bool:
    """PID 是否还在（`kill(pid, 0)`）。**判不出来按「存在」处理**（fail-closed：宁可不夺锁）。

    权限不足（EPERM）也算存在：那说明该 PID 属于别的用户或受保护进程，不是「已死」。
    """
    if pid <= 0:
        return 假
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return 假
    except OSError:
        return 真
    return 真


def _取pid(锁: dict) -> int:
    """锁里的 pid → int；不是整数 ⇒ 抛 `锁不可判定`（fail-closed，不猜成 0）。"""
    try:
        return int(锁.get("pid"))
    except (TypeError, ValueError) as 错误:
        raise 锁不可判定(f"锁里的 pid 不是整数（{锁.get('pid')!r}）") from 错误


def _读锁(路径: Path) -> dict | None:
    """读锁文件：不存在 → None；存在但读不出/形状非法 ⇒ 抛 `锁不可判定`（fail-closed）。"""
    if not 路径.is_file():
        return None
    try:
        数据 = json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as 错误:
        raise 锁不可判定(
            f"锁文件读不出（{type(错误).__name__}: {错误}）：{路径}") from 错误
    if not isinstance(数据, dict):
        raise 锁不可判定(f"锁文件形状非法（顶层不是对象）：{路径}")
    缺 = [键 for 键 in ("pid", "启动时刻", "仓库根") if not 数据.get(键)]
    if 缺:
        raise 锁不可判定(f"锁文件缺字段 {'、'.join(缺)}：{路径}")
    return 数据


def _启动时间戳(锁: dict) -> float:
    """锁里的启动时刻 → epoch 秒。两种表示都认；都解析不出 ⇒ 抛 `锁不可判定`。"""
    戳 = 锁.get("启动时间戳")
    if isinstance(戳, (int, float)) and not isinstance(戳, bool):
        return float(戳)
    文本 = str(锁.get("启动时刻") or "").strip()
    for 格式 in ("%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M:%S"):
        try:
            return time.mktime(time.strptime(文本, 格式))
        except ValueError:
            continue
    raise 锁不可判定(f"锁里的启动时刻解析不出（{文本!r}）—— 判不出它是不是陈旧锁")


def _占用裁定(锁: dict, 根: Path) -> str:
    """对**已存在**的锁做裁定：返回「可夺」的理由（非空）；不可夺则抛 `锁被占`。

    落点：
      · PID 不存在 ⇒ 可夺（理由「原 PID … 已不存在」）；
      · PID 还在但启动已超 `锁陈旧秒` ⇒ 可夺（理由如实带出存活时长）；
      · PID 还在且未超阈值 ⇒ **拒启**（同树真有写者在跑）；
      · 锁记录的仓库根不是本树：原 PID 已死 ⇒ 可夺；原 PID 还在 ⇒ **拒启**
        （这把锁不归本树，但「它到底是不是本树的写者」判不出来 —— fail-closed 不猜、不静默夺）。
    """
    持有根 = str(锁.get("仓库根") or "")
    pid = _取pid(锁)
    if Path(持有根) != Path(根):
        if not _进程存在(pid):
            return f"记录的仓库根是 {持有根}（不是本树 {根}），且原 PID {pid} 已不存在"
        raise 锁被占(
            f"锁记录的仓库根是 {持有根}，不是本树 {根}（原 PID {pid} 仍在跑）——"
            "判不出它是不是本树的写者，按拒启处理（fail-closed）")
    if not _进程存在(pid):
        return f"原 PID {pid} 已不存在"
    存活秒 = time.time() - _启动时间戳(锁)
    if 存活秒 > 锁陈旧秒:
        return (f"原 PID {pid} 仍在，但启动已 {存活秒 / 60:.1f} 分钟"
                f"（>阈值 {锁陈旧秒 / 60:.0f} 分钟）")
    raise 锁被占(f"同树已有编译口在跑（PID {pid}，启动于 {锁.get('启动时刻')}）")


def 占单写者锁(根: Path) -> dict:
    """占单写者锁。成功返回句柄（`夺锁说明` 非空 = 本次**夺了陈旧锁**，原样回带给人看）。

    占不到一律抛异常（`锁被占` / `锁不可判定`），由调用方拒启 —— 本函数**不静默放行**。

    原子性：建锁走 `O_CREAT|O_EXCL`（同一路径上只有一个进程能建成），**不是**
    「先判 is_file 再写」—— 那中间有窗口，两个进程会同时通过检查（正是本条要防的事）。
    夺陈旧锁 = 先删、再按同一原子建法重建；删完被别的进程抢先建成，下一轮按「被占」处理。
    """
    路径 = 根 / 锁相对路径
    路径.parent.mkdir(parents=True, exist_ok=True)
    夺锁说明 = ""
    for _ in range(3):
        try:
            句柄 = os.open(路径, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
        except FileExistsError:
            现有 = _读锁(路径)
            if 现有 is None:
                continue        # 对方刚释放（判存在与读之间没了）—— 立刻重试抢建
            夺锁说明 = _占用裁定(现有, 根)      # 不可夺时在这里抛 `锁被占`
            try:
                路径.unlink()
            except FileNotFoundError:
                pass
            continue            # 删完重试原子建；被抢先则由下一轮的裁定挡下
        except OSError as 错误:
            raise 锁不可判定(
                f"锁文件建不出来（{type(错误).__name__}: {错误}）：{路径}") from 错误
        现在 = time.time()
        内容 = {
            "pid": os.getpid(),
            "启动时刻": time.strftime("%Y-%m-%dT%H:%M:%S", time.localtime(现在)),
            "启动时间戳": round(现在, 3),
            "仓库根": str(根),
            "命令行": " ".join(sys.argv),
        }
        with os.fdopen(句柄, "w", encoding="utf-8") as 文件:
            文件.write(json.dumps(内容, ensure_ascii=False, indent=2))
        return {**内容, "路径": 路径, "夺锁说明": 夺锁说明}
    raise 锁不可判定(
        f"连续 3 次都建不出锁（每次都被抢先，或锁文件刚被释放）：{路径} —— fail-closed 拒启")


def 释放单写者锁(句柄: dict) -> None:
    """释放锁：**只删自己那把**（锁里的 pid 与本进程一致才删）。

    为什么按 pid 核对：万一自己这把已被判陈旧夺走、新写者已重建，直接 unlink 会把
    **别人的锁**删掉 —— 那等于亲手打开并发窗口。
    读不出/形状不对就**什么都不做**（留着它，下一轮按「原 PID 已不存在」夺陈旧锁并如实报）。
    """
    路径 = Path(句柄["路径"])
    try:
        现有 = json.loads(路径.read_text(encoding="utf-8"))
        持有 = int(现有.get("pid"))
    except Exception:  # noqa: BLE001 —— 清理路径：读不出就不删（留给下一轮按陈旧锁处理）
        return
    if 持有 != os.getpid():
        return
    try:
        路径.unlink()
    except OSError:
        pass


def _排队上限() -> float:
    """本次排队上限（秒）：环境变量 `编译口排队上限秒` 优先，非法值一律退回缺省。

    为什么要有环境变量：验收「等到上限才拒启」这条路径必须能把上限调到极小 ——
    否则验一条超时路径要真等 900 秒。传 `0` = **不排队**（被占即拒启，旧行为）——
    既有「活锁必须拒启」用例与门禁靠它钉住旧行为。**只影响等待，不影响锁语义**。
    """
    原值 = os.environ.get(排队上限环境变量, "").strip()
    if not 原值:
        return 排队上限秒
    try:
        值 = float(原值)
    except ValueError:
        return 排队上限秒
    return 值 if 值 >= 0 else 排队上限秒


def _不可判定容忍() -> float:
    """本次「锁文件正在写」的容忍窗（秒）：环境变量优先，非法值退回缺省。

    与 `_排队上限` 同形：验收「判不出持有者 ⇒ 拒启」这条 fail-closed 路径时把它钉成 0，
    免得每条坏锁用例都白等满缺省窗（缺省 6 秒）。
    """
    原值 = os.environ.get(不可判定容忍环境变量, "").strip()
    if not 原值:
        return 不可判定容忍秒
    try:
        值 = float(原值)
    except ValueError:
        return 不可判定容忍秒
    return 值 if 值 >= 0 else 不可判定容忍秒


def _排队占锁(根: Path, 上限秒: float, 打印=print) -> tuple[dict | None, str]:
    """有界排队占锁（R-25）：返回（句柄, ""）或（None, 拒启说明）。

    三种状态各有处置，**不混为一谈**：
      · 占到了 ⇒ 立刻返回句柄（`夺锁说明` 非空 = 夺了陈旧锁，原样回带，不静默夺）；
      · `锁被占`（同树有活写者）⇒ 等到 `上限秒` 才拒启，说明里带持锁者身份与已等多久；
      · `锁不可判定` ⇒ 先按「对方刚建锁、内容还没落」在 `不可判定容忍秒` 内重试，
        超过容忍窗才当场拒启（fail-closed 不变：判不出持有者时再等也没意义，
        但**不能**把「正在写」误报成「判不出」）。
    """
    起始 = time.monotonic()
    容忍秒 = _不可判定容忍()
    首次不可判定 = 0.0
    while True:
        try:
            return 占单写者锁(根), ""
        except 锁被占 as 异常:
            说明 = str(异常)
            首次不可判定 = 0.0      # 读到的是**形状完好**的锁 ⇒ 对方已写完，容忍窗重算
        except 锁不可判定 as 异常:
            现在 = time.monotonic()
            if 首次不可判定 <= 0.0:
                首次不可判定 = 现在
            已判不出 = 现在 - 首次不可判定
            if 已判不出 >= 容忍秒:
                return None, (f"{异常}（连续 {已判不出:.1f} 秒都判不出持有者 —— 不是"
                              f"「对方刚建锁、内容还没落」那类瞬时态，按 fail-closed 拒启）")
            说明 = f"{异常}（判不出持有者，按「对方刚建锁、内容还没落」重试中）"
        已等 = time.monotonic() - 起始
        if 已等 >= 上限秒:
            return None, (f"{说明}；已排队等待 {已等:.0f} 秒（上限 {上限秒:.0f} 秒）仍未拿到锁。"
                          f"建议：① 等它跑完再重跑；② 确认它已死则重跑即自动夺陈旧锁；"
                          f"③ 要等更久就把环境变量 {排队上限环境变量} 调大"
                          f"（当前上限 {上限秒:.0f} 秒）")
        打印(f"── 单写者守卫：锁被占，排队等待中（已等 {已等:.0f} 秒 / 上限 {上限秒:.0f} 秒）"
             f" —— {说明} ──")
        time.sleep(min(排队轮询秒, max(0.05, 上限秒 - 已等)))


def 起单写者守卫(写盘: bool, 根: Path, 打印=print) -> tuple[dict | None, bool]:
    """守卫入口：返回（锁句柄 | None, 是否拒启）。打印的行就是给人看的原话。

    · 不占锁的两种情形（`--只读` / 嵌套调用）**如实说明**为什么，不静默跳过；
    · 锁被**活写者**持有时**排队等**（`_排队占锁`，上限见 `排队上限秒`，可被环境变量
      `编译口排队上限秒` 覆盖），等到上限才拒启 —— 「被占就拒启」是 R-25 收掉的缺陷；
    · 拒启时打印「拒启」段 + `═══ 结论 ═══` 五态行，调用方据此退 2（退出码非 0）。
    """
    if not 写盘:
        打印("── 单写者守卫：`--只读` 不占锁（只跑核验命令、不写派生件；多读者无害）──")
        return None, 假
    if os.environ.get(编译口嵌套标记):
        # 嵌套调用 = 同一次运行的子调用（步骤5 的定向测试里又跑编译口）：父进程已持锁，
        # 它不是第二个写者。如实报，不静默跳过 —— 与步骤5 的嵌套说明同一口径。
        打印(f"── 单写者守卫：嵌套调用（环境里已有 {编译口嵌套标记}）不占锁"
             f"（同一次运行的子调用，父进程已持锁）──")
        return None, 假
    等待上限 = _排队上限()
    句柄, 拒启说明 = _排队占锁(根, 等待上限, 打印)
    if 句柄 is None:
        打印("── 单写者守卫：拒启 ──")
        打印(f"  {拒启说明}")
        打印("═══ 结论 ═══")
        打印("五态结论：未核验 —— 拒启（fail-closed）：同树已有编译口在跑，或判不出有没有"
             f"（不许两个写者同改派生件）。本次已排队等到上限（{等待上限:.0f} 秒）："
             "等它跑完再重跑，确认它已死则重跑即自动夺陈旧锁。")
        return None, 真
    if 句柄["夺锁说明"]:
        # 陈旧锁可夺，但**不许静默夺**：如实报原 PID 与判定理由。
        打印(f"── 单写者守卫：夺了陈旧锁（{句柄['夺锁说明']}）──")
    else:
        打印(f"── 单写者守卫：已占锁（PID {os.getpid()}，{锁相对路径}）──")
    # ★ 写者身份标记（2026-09-24）：占锁成功后把自己的 pid 写进环境，**子进程继承**。
    #   `写入授权` 靠它 + 进程祖先链判「这是平台自己的编译机在写派生件」⇒ 派生件
    #   （`完整性摘要.json` / `依赖登记.json` / `开发文档/规范/*.md` 元信息头）
    #   不再被自己的授权门拦死。判据本体只在 `公共契约/运行时/写入授权.写者是平台编译机`。
    os.environ[编译机PID环境变量名] = str(os.getpid())
    return 句柄, 假


def 主函数() -> int:
    解析 = argparse.ArgumentParser(description="开发编译口：改完文件后的一键静态全查")
    # ★ 范围组**不再必填**（华哥 2026-09-22「使用命令，传参是越少越好……地址就可以省下了」）：
    #   什么范围参数都不给 = 读 git 变更集（最常用的一档，不该要人记得加开关）。
    #   `--变更` 保留为显式同义（老文档/老脚本照抄仍然跑得通），它现在与「不给」完全等价。
    范围 = 解析.add_mutually_exclusive_group(required=False)
    范围.add_argument("--变更", action="store_true",
                     help="读 git 变更集（含未跟踪文件）。**这是默认档**：不给任何范围参数就是它")
    范围.add_argument("--文件", nargs="+", metavar="路径",
                     help="显式点名文件（路径相对仓库根写即可，工作目录固定 = 仓库根）")
    范围.add_argument("--库", nargs="+", metavar="包id",
                     help="显式点名包（库）的 id：按该包及其反向依赖闭包自动补全"
                          "（华哥 2026-09-22「改完代码，直接把库的 ID 传过去，然后就编译就行了」）")
    范围.add_argument("--全仓", action="store_true", help="全仓口径（影响面按全量叙述 + 全仓 .py 语法编译）")
    范围.add_argument("--自证", action="store_true", help="编译口自身三拍自证")
    解析.add_argument("--不跑点名", action="store_true",
                     help="步骤5 不执行定向测试，只点名（默认**执行**：点名集本就是定向的，"
                          "只点名不跑会让人再手动跑一轮 —— 华哥 2026-09-22「先把浪费时间的"
                          "找出原理，然后修好浪费速度的问题」；本轮外已单独跑过时才用它降级）")
    解析.add_argument("--只读", action="store_true",
                     help="只核验不生成（默认**按登记表自动生成全部派生凭据** —— 华哥 2026-09-22"
                          "「平台底层固定需求的东西，编译的同时全部自动生成，不要反复手修」"
                          "「尽量不需要人工维护……就用全自动」；并行多写者同改一个仓库时才用它降级）")
    参数 = 解析.parse_args()
    写盘 = not 参数.只读      # 默认写盘（全自动）；`--只读` 显式降级

    if 参数.自证:
        # 三拍自证**不占单写者锁**：它只跑 py_compile 与一个只读门禁，不写派生件、
        # 不参与「同改派生件」这件事；占锁只会让「写者正跑着时想自证一下」变成拒启。
        return _三拍自证()

    # ── 单写者守卫（口径与落点见上方 `锁相对路径` 注释块）──
    锁句柄, 拒启 = 起单写者守卫(写盘, 系统根)
    if 拒启:
        # fail-closed：同树已有写者在跑（或判不出有没有）⇒ 拒启，退出码非 0。
        return 2
    try:
        return _编译主流程(参数, 写盘)
    finally:
        # 正常结束与异常退出都要释放：异常退出留下的锁会挡住下一轮（属残留）。
        if 锁句柄 is not None:
            释放单写者锁(锁句柄)


def _编译主流程(参数: argparse.Namespace, 写盘: bool) -> int:
    """编译口主流程（步骤1~5 与五态结论）。由 `主函数` 在**守卫裁定之后**调用。

    拆出来是为了让单写者守卫的 `try/finally` 罩住整段主流程：
    任何 return（含 未核验/失败 早退）与任何异常，锁都在 `主函数` 的 finally 里释放。
    """
    print("═══ 开发编译口（易语言模式：一次编译，规则全查）═══")
    # ★ 默认口径 = 读 git 变更集（华哥 2026-09-22「使用命令，传参是越少越好……路径类的，
    #   本质上内部开发的时候，默认地址就是根目录，地址就可以省下了」）：
    #   什么范围参数都不给，就是「改了什么就查什么」——最常用的一档不该要人记得加开关。
    #   `--库 <库 id>` 是收窄档（直接点名包，不依赖 git 变更集）；`--文件`/`--全仓` 同理。
    #   工作目录固定 = 仓库根（`系统根`），故路径参数一律**相对根目录**写，不必写绝对路径。
    try:
        if 参数.文件:
            变更文件 = list(参数.文件)
        elif 参数.库 or 参数.全仓:
            变更文件 = []
        else:
            # 含 `--变更` 显式给（与不给等价）—— 默认档就是它
            变更文件 = _git变更文件()
    except Git不可用 as 异常:
        # fail-closed：git 不可用时连「改了什么」都不知道，任何绿都是假的。
        print("── 步骤1 影响面：无法取得变更集 ──")
        print(f"  {异常}")
        print("═══ 结论 ═══")
        print("五态结论：未核验 —— 无法取得变更集（fail-closed）。修好 git 或用 --文件/--库 显式点名后重跑。")
        return 2

    if 参数.全仓:
        影响面 = {"受影响包": ["（全仓口径）"], "反向依赖闭包": [], "非包文件": [],
                "摘要联动提示": [], "包目录表": {}, "未知包": []}
    else:
        影响面 = _影响面(变更文件, list(参数.库 or []))
    if 影响面.get("形态错误"):
        # 形态错误 = 传了路径而不是库 id —— 与「包不存在」是两回事，分开报（2026-09-22 实测）。
        print("── 步骤1 影响面：`--库` 收到路径形态 ──")
        for 项 in 影响面["形态错误"]:
            print(f"  {_库id形态提示(项)}")
        print("═══ 结论 ═══")
        print("五态结论：未核验 —— `--库` 只收库 id（点形态），不收路径（fail-closed）。")
        return 2
    if 影响面.get("未知包"):
        # 点名的库 id 现场不存在 —— fail-closed：连「改的是哪个包」都不知道，任何绿都是假的。
        print("── 步骤1 影响面：点名的库 id 现场找不到 ──")
        print(f"  未知包：{'、'.join(影响面['未知包'])}")
        print("═══ 结论 ═══")
        print("五态结论：未核验 —— 点名的库 id 不存在（fail-closed）。"
              "核对 `包声明.json` 的 包id 字段后重跑。")
        return 2
    print(f"── 步骤1 影响面：变更文件 {len(变更文件)} 个，受影响包 {len(影响面['受影响包'])}，"
          f"反向依赖闭包 {len(影响面['反向依赖闭包'])}，非包文件 {len(影响面['非包文件'])}")
    for 标签, 键 in (("受影响包", "受影响包"), ("反向依赖闭包", "反向依赖闭包")):
        if 影响面[键]:
            # ★ 全量列出（原先 `[:12]` 截样 + ` …`）：给「N 个」就必须把 N 个名字都给出，
            #   只给样例会让人反复重跑才看全（本口 2026-09-21 已有同款裁决，见 `_尾部`）。
            print(f"  {标签}（{len(影响面[键])} 个，全量列出）：{', '.join(影响面[键])}")

    未核验 = False
    未核验项: list[str] = []
    失败门禁: list[str] = []
    只报红项: list[str] = []

    print("── 步骤2 生成物自动联动（**默认全自动**：按登记表生成全部派生凭据；--只读 才降级）──")
    # 华哥 2026-09-22 裁决：「平台底层固定需求的东西，编译的同时全部自动生成凭据，而不是反复
    # 去修」「把多个命令，组装成一个统一的命令，把平台需求的东西全自动解决」
    # 「尽量不需要人工维护吧，毕竟人工维护最容易出现的问题就是会漂移。
    #   你确定哪一些变成机器维护的，代码维护的。就用全自动。」
    # ⇒ **默认写盘**：改完代码跑一次编译，派生凭据（摘要/依赖派生/说明书载位/文档账目/元信息头）
    #   全部自动跟上，不需要人记得加开关（「要人记得」的开关本身就是漂移源）。
    #   `--只读` 是并行多写者同改一个仓库时的降级口。
    # 派生凭据的清单与命令是**数据**（`开发文档/规范/生成物登记表.json`）——
    # 本口只按表跑、不另立判据、不复制命令（哲学 1.2「一类事情只有一条腿」）。
    摘要已核对 = False
    生成物结论: dict | None = None
    # 受影响包目录：给登记表里声明了 `按影响面包` 的凭据（契约版本自增 / 能力定义编译）当扫描面。
    # **只收「受影响包」，不收「反向依赖闭包」** —— 闭包里的包是「依赖了改动方」，它们自己的
    # 对外契约面没变，逐包跑一遍是纯浪费（判据会一致回「无需递增」），且与「开发期禁全量」同向。
    # `--全仓` 口径下 `受影响包` 是哨兵「（全仓口径）」，不在 `包目录表` 里 ⇒ 自然滤掉。
    目录表 = 影响面.get("包目录表") or {}
    受影响包目录: list[str] = []
    for 包id in 影响面.get("受影响包") or []:
        目录 = 目录表.get(包id)
        if 目录 is None:
            continue
        try:
            受影响包目录.append(目录.relative_to(系统根).as_posix())
        except ValueError:
            # 目录不在系统根下（理论上不该出现）：不静默丢，交给下游按「未核验」报
            受影响包目录.append(目录.as_posix())
    if 写盘:
        try:
            生成物结论 = 生成物执行(系统根, 写盘=真, 受影响包目录=受影响包目录)
        except 生成物登记表不可用 as 异常:
            # fail-closed：判不出派生凭据 ≠ 没有派生凭据（与门禁崩溃同口径，按未核验处理）
            未核验 = True
            未核验项.append(f"生成物联动（{异常}）")
            print(f"  生成物联动不可用（fail-closed，按未核验处理）：{异常}")
        if 生成物结论 is not None:
            print(f"  派生 {生成物结论['派生数']} 条（扫描面：受影响包 {len(受影响包目录)} 个；"
                  f"按包的凭据拆 N 节点并行）："
                  f"生成绿 {生成物结论['生成成功数']}、"
                  f"生成红 {生成物结论['生成失败数']}、复跑仍红 {生成物结论['复跑仍红数']}、"
                  f"未核验 {生成物结论['未核验数']}、无受影响包跳过 {生成物结论['跳过数']}、"
                  f"节点红 {生成物结论.get('节点红数', 0)}；"
                  f"不自动生成 {生成物结论['不自动数']} 条"
                  f"（{'、'.join(生成物结论['不自动清单'])} —— 登记/人工类，只报不跑）")
            # 摘要闭合的结论取自本次生成（它就是「摘要」这条凭据的生成器），不重复跑第二遍
            摘要退出码 = _生成码(生成物结论, "摘要闭合")
            if 摘要退出码 is None:
                pass            # 登记表里没这条：留给门禁清单按只读口径核（不当通过）
            elif 摘要退出码 == -1:
                未核验 = True
                未核验项.append("摘要闭合")
            elif 摘要退出码 != 0:
                失败门禁.append(f"摘要闭合（生成退出码 {摘要退出码}）")
            else:
                摘要已核对 = True
    else:
        # `--只读` 口径也走登记表 —— 但只跑**核验命令**（全部只读，不写任何文件）。
        # 为什么不让它退回「只跑摘要一条」：那是**降级口静默漏检** —— 并行写者拿到「绿」，
        # 而依赖派生/说明书载位/文档账目这些凭据在现场其实已经漂了，谁也看不见。
        # 只读口径只报「现场一致 / 现场不一致」，不当成写盘成功，也不改任何文件。
        try:
            生成物结论 = 生成物执行(系统根, 写盘=假, 受影响包目录=受影响包目录)
        except 生成物登记表不可用 as 异常:
            未核验 = True
            未核验项.append(f"生成物联动（{异常}）")
            print(f"  生成物联动不可用（fail-closed，按未核验处理）：{异常}")
        if 生成物结论 is not None:
            print(f"  派生 {生成物结论['派生数']} 条现场核对（只读口径，不写盘）："
                  f"现场一致 {len(生成物结论['生成表']) - 生成物结论['复跑仍红数'] - 生成物结论['未核验数'] - 生成物结论['跳过数']}、"
                  f"现场不一致 {生成物结论['复跑仍红数']}、未核验 {生成物结论['未核验数']}、"
                  f"无受影响包跳过 {生成物结论['跳过数']}")
            摘要退出码 = _核验码(生成物结论, "摘要闭合")
            if 摘要退出码 is None:
                pass
            elif 摘要退出码 == -1:
                未核验 = True
                未核验项.append("摘要闭合")
            elif 摘要退出码 != 0:
                失败门禁.append(f"摘要闭合（现场退出码 {摘要退出码}）")
            else:
                摘要已核对 = True
        else:
            退出码, 输出, 耗时 = _跑([解释器, "-m", "开发工具.全量重算摘要", "--只报"], 超时秒=120)
            print(f"  摘要闭合核对（只报）退出码={退出码} 耗时={耗时:.2f}s：{_尾部(输出, 2)}")
            if 退出码 == -1:
                未核验 = True
                未核验项.append("摘要闭合")
            elif 退出码 != 0:
                失败门禁.append(f"摘要闭合（退出码 {退出码}）")
            else:
                摘要已核对 = True

    print("── 步骤3 静态规则全查 ──")
    # 语法编译：**「没跑」不许算「跑过了」**（#68）。变更集无 .py 这类「无编译对象」
    # 与新出现的「全仓找不到 .py」，都由 `_变更py编译/_全仓py编译` 返回 -1 → 未核验。
    if 参数.全仓:
        退出码, 输出 = _全仓py编译()
        print(f"  全仓 .py 语法编译 退出码={退出码}：{_尾部(输出, 2)}")
    elif 参数.库:
        # `--库` 口径：编译对象 = 点名包（含反向依赖闭包）目录下的 .py，不由 git 变更集决定
        # （调用方传的是库 id 这个**变量**，不该被「工作区有没有未提交改动」影响）。
        点名文件 = _包内py相对路径(影响面["受影响包"], 影响面.get("包目录表") or {})
        退出码, 输出 = _变更py编译(点名文件)
        print(f"  点名包内 .py 语法编译（{len(点名文件)} 个文件）退出码={退出码}：{_尾部(输出, 2)}")
    elif 变更文件:
        退出码, 输出 = _变更py编译(变更文件)
        print(f"  变更 .py 语法编译 退出码={退出码}：{_尾部(输出, 2)}")
    else:
        # `--文件` 传了空列表这类入口（argparse 的 nargs='+' 挡不住程序内调用）：
        # 同口径走 `_变更py编译`，不再自己写 `= 0, ""`（那正是 #68 的原始写法）。
        退出码, 输出 = _变更py编译([])
        print(f"  变更 .py 语法编译 退出码={退出码}：{_尾部(输出, 2)}")
    if 退出码 == -1:
        未核验 = True
        未核验项.append(f"语法编译（{_尾部(输出, 1)}）")
    elif 退出码 != 0:
        失败门禁.append("语法编译")

    # 防回潮只读勘定（#62）：**只登记结论，不改被勘定对象**。
    # 放在门禁循环之前跑（它只做 import + callable 取到性检查，不跑判据本体，秒级）。
    _防回潮独立入口勘定()

    # ★ 并行起跑（2026-09-21；口径同华哥「单步超 2 分钟就是 bug」）：
    #   本轮 14 项此前是**串行**，单轮耗时＝各项**相加**（实测 29.5 秒）；
    #   先并发提交，再按 门禁清单 原序打印与判定 —— 顺序、判据、超时秒全不变，
    #   只有「等」的方式变了（相加 → 取最大）。
    待跑序号 = [
        序号 for 序号, 项 in enumerate(门禁清单)
        if not (项["模块"] == "开发工具.全量重算摘要" and 摘要已核对)
        and 项["名字"] != 反向破坏入口[0]
    ]
    print(f"── 步骤3b 静态门禁并发起跑（{len(待跑序号)} 项，并发 {门禁并行路数}）──")
    并发结果: dict[int, tuple[int, str, float]] = {}
    with ThreadPoolExecutor(max_workers=门禁并行路数) as 池:
        期约表 = {
            序号: 池.submit(
                _跑,
                [解释器, "-m", 门禁清单[序号]["模块"], *门禁清单[序号]["参数"]],
                超时秒=门禁清单[序号]["超时秒"],
            )
            for 序号 in 待跑序号
        }
        for 序号, 期约 in 期约表.items():
            并发结果[序号] = 期约.result()

    #: 门禁名字 → 真实退出码。**步骤4 的复跑确认只认这张表**（不另跑一遍命令）：
    #: 「修完自动复跑确认转绿」的判据必须是真实门禁退出码，不能是生成器自述。
    门禁退出码表: dict[str, int] = {}
    for 序号, 门禁 in enumerate(门禁清单):
        角色标注 = "阻断" if 门禁["角色"] == "阻断" else "只报告"
        if 门禁["模块"] == "开发工具.全量重算摘要" and 摘要已核对:
            # 步骤2 已同一口径跑过（写盘口径跑的是生成器本体，只读口径是 `--只报`）：
            # 结论已按乙的退出码归并，此处不再跑第二遍（修前版本同轮重复跑两遍）。
            门禁退出码表[门禁["名字"]] = 0
            print(f"  [{角色标注}] {门禁['名字']} 已在步骤2 核对，跳过（避免同轮重复执行）")
            continue
        if 门禁["名字"] == 反向破坏入口[0]:
            # 反向破坏**不能**走「python3.14 -m 发布门禁」那条子进程命令行：那是跑整轮
            # 发布门禁（132 秒级），不是这一项，而发布门禁没有「只跑某项」的开关。
            # 它的入口是 in-process 可调用的（发布门禁 29 行接线消费的正是它），
            # 故在本口 `__main__` 里直调——**消费同一函数，不另写第二份判据**（哲学 13.1）。
            退出码, 输出, 耗时 = _跑反向破坏()
            print(f"  [{角色标注}] {门禁['名字']} 退出码={退出码} 耗时={耗时:.2f}s：{_尾部单行(输出, 2)}")
        else:
            # 结果取自上面的并发批（同一 `_跑`、同一命令行、同一超时秒，只换了等待方式）。
            退出码, 输出, 耗时 = 并发结果[序号]
            # 判红时违规条目全量透出（见 `_尾部`）；显式行数只作判绿时的尾部保留量。
            # ★ 这里用 `_尾部单行`（不是 `_尾部`）：多行块会被 MCP 侧的逐行解析只认走第一行，
            #   第 2 行起的违规条目就丢了（实测：`公开调用完整性` 报 4 个包只抬出 1 行）。
            #   单行化后 `失败原因` 即含全量违规条目 —— 见 `_尾部单行` 的说明。
            print(f"  [{角色标注}] {门禁['名字']} 退出码={退出码} 耗时={耗时:.2f}s：{_尾部单行(输出, 判红尾巴行数)}")
        门禁退出码表[门禁["名字"]] = 退出码
        if 退出码 == -1:
            # ★ 假绿通道（P1）：未核验与角色无关 —— 只报告类门禁超时/无法执行同样不许放行。
            未核验 = True
            未核验项.append(f"{门禁['名字']}（{_尾部(输出, 1)}）")
            continue
        if 退出码 == 0:
            continue
        if 门禁["角色"] == "阻断":
            失败门禁.append(f"{门禁['名字']}（退出码 {退出码}）")
        else:
            # ★ 只报告类判红非 0：不判定红绿，但结论必须列出来（静默丢弃等于假绿）。
            只报红项.append(f"{门禁['名字']}（退出码 {退出码}）")

    # 步骤4 生成物复跑确认（审计件 §8.4 原设计「修完自动复跑确认转绿」）。
    # ★ 判据取自步骤3 各门禁的**真实退出码**（门禁退出码表）：不重复跑同一批命令，
    #   也不采信生成器的自述 —— 「生成绿」与「现场真的绿了」是两件事（防假绿）。
    #   逐条分类抽到 `_复跑确认`（可单测钉住「本轮没跑 ≠ 生成器坏了」）。
    print("── 步骤4 生成物复跑确认（判据 = 步骤3 各门禁的真实退出码，不重复跑命令）──")
    _转绿, _仍红, 步骤4未核验, 步骤4失败 = _复跑确认(
        生成物结论, 门禁退出码表, 写盘=写盘, 全仓口径=bool(参数.全仓))
    if 步骤4未核验:
        未核验 = True
        未核验项.extend(步骤4未核验)
    失败门禁.extend(步骤4失败)

    # ★ ③ 2026-09-23 覆盖声明：`--全仓` 口径下「按影响面包」的派生凭据（契约版本自增 /
    #   能力定义编译）**没有扫描面** ⇒ 覆盖为零 —— 那不是「本轮没变化」，是这两条本轮
    #   **没核验**。**保持现状**（不硬改去跑全量）：让 `--全仓` 真覆盖 = 全仓下逐包跑
    #   这两条（142 包），直接撞「开发期禁全量」既有裁决
    #   （`开发文档/规范/项目细则.md:124`「一律不跑全量……全量编译口 `--全仓`」；
    #   `生成物登记表.json` 的「按影响面包字段」也明写「不跑全仓」）。
    #   两案代价：
    #     方案A（真覆盖）= 逐包跑 142 个包 —— 代价：违反既有裁决；能力定义编译全量实测
    #       约 18 秒并改写全仓派生件（登记表自己写明「与开发期禁全量冲突」）。
    #     方案B（保持现状 + 如实声明）= 本段 —— 代价：`--全仓` 对这两条凭据的结论面是
    #       「覆盖为零」，要覆盖它们必须改用 `--库 <包id>` / `--文件 <路径>`。
    #   取 B：与「禁全量」同向，且「覆盖为零」按「未核验不占通过位」**不得读成通过**。
    全仓零覆盖: list[str] = []
    if 参数.全仓 and isinstance(生成物结论, dict):
        全仓零覆盖 = [str(行.get("名字")) for 行 in (生成物结论.get("生成表") or [])
                   if isinstance(行, dict) and 行.get("结论") == "无受影响包·跳过"]
    if 全仓零覆盖:
        print(f"  ★ 覆盖声明（--全仓）：{'、'.join(全仓零覆盖)} —— 按影响面包凭据在全仓口径下"
              f"无扫描面，本轮**覆盖为零（未核验）**；要覆盖它们请用 `--库 <包id>` 或 "
              f"`--文件 <路径>`。此声明不改五态：`--全仓` 的承诺面是全仓 .py 语法编译 + "
              f"影响面叙述，不含逐包派生凭据（登记表明写这两条「不跑全仓」，与「开发期禁全量」一致）。")
    覆盖声明后缀 = ("；**`--全仓` 口径下 按影响面包 派生凭据（契约版本自增／能力定义编译）"
                "覆盖为零（未核验）**（见步骤4 覆盖声明）" if 全仓零覆盖 else "")

    点名 = 点名模块(影响面)
    未接线 = 未接线非包py(影响面)
    # ★ 传递覆盖判据**自身的可用性**：判不准时如实报未核验，不许把「判不准」混成「无覆盖」
    #   （扫描面为 0 会让闭包恒空 ⇒ 全部非包源被报成「无覆盖」；解析失败会让闭包**假空**）。
    覆盖判据不可用 = 传递覆盖判据不可用()
    if 覆盖判据不可用:
        未核验 = True
        未核验项.append(f"传递覆盖判据（{覆盖判据不可用}）")
    # ★ 2026-09-22（华哥「先把浪费时间的找出原理，然后修好浪费速度的问题」）：
    #   原先这里**只点名不执行**，人要照着名单再手动跑一轮（实测每批白 1~2 轮，
    #   而且手动跑时又得重新拼 `python3.14 -m unittest …` 命令行，容易再错）。
    #   点名集本就是**定向**的（按受影响包短名匹配测试模块，不是全量）⇒ 直接跑掉，
    #   一次拿到逐模块真实退出码；并行复用 生成物联动.跑分片（同一个 `执行命令集`
    #   口径与 8 路上限，不自己起第二套线程池）。
    #   判红算**阻断**：只打印不判定的测试项是装饰（本仓口径：未被入口调用的检查器
    #   等同不存在）。`--不跑点名` 是唯一降级口（本轮外已单独跑过时用）。
    print(f"── 步骤5 定向测试（{len(点名)} 个模块，{8} 路并行）──")
    # 覆盖判据的**扫描面与结论**必须落在输出里：不然「一个模块都没点名」和「点了名但
    # 都是无关模块」从输出上分不出来（本仓口径：扫描面为 0 不得记作通过）。
    非包py = [路径 for 路径 in (影响面.get("非包文件") or []) if 路径.endswith(".py")]
    if 非包py:
        有覆盖 = [路径 for 路径 in 非包py if 传递覆盖测试模块(路径)]
        二阶 = [路径 for 路径 in 有覆盖 if not 直接覆盖测试模块(路径)]
        print(f"  传递覆盖判据（反向 import 图闭包 ∩ 测试模块）：本轮 {len(非包py)} 个非包 .py，"
              f"{len(有覆盖)} 个有测试覆盖，其中 **{len(二阶)} 个只有二阶覆盖**"
              f"（没有任何测试直接 import 它 —— 单层 import 口径必漏）"
              f"{'：' + '、'.join(二阶) if 二阶 else ''}")
    if 覆盖判据不可用:
        print(f"  ★ 传递覆盖判据不可用（{覆盖判据不可用}）—— 非包 .py 的覆盖结论本轮**未核验**："
              f"既不许读成「无覆盖」也不许读成「有覆盖」（fail-closed）。")
    if 未接线:
        print(f"  未接线（如实报，不当通过）：{len(未接线)} 个非包 .py **据现有判据**没有任何"
              f"测试覆盖到它（import 链闭包不可达且无显式接线）—— "
              f"{'、'.join(未接线)}")
    if os.environ.get(编译口嵌套标记):
        print(f"  嵌套调用（环境里已有 {编译口嵌套标记}）：跳过定向测试，防「编译口→测试→编译口」自递归。")
    elif not 点名:
        print("  受影响包未匹配到任何测试模块 —— 这是「没有点名对象」，不是「测试通过」。")
    elif 参数.不跑点名:
        for 模块名 in 点名:
            print(f"  python3.14 -m unittest {模块名}   # 本轮未执行（--不跑点名）")
    else:
        # 子进程继承本标记：测试里若再跑编译口，那一层据此跳过步骤5（防无限套娃，见上方注释）。
        os.environ[编译口嵌套标记] = "1"
        测试码, 测试摘要, 测试节点 = 生成物跑分片(
            [解释器, "-m", "unittest"], 点名, 定向测试超时秒, 系统根)
        for 节点 in 测试节点:
            print(f"  {节点['分片']} 退出码={节点['退出码']} 耗时={节点['耗时秒']}s：{节点['摘要']}")
        print(f"  {测试摘要}")
        if 测试码 == -1:
            未核验 = True
            未核验项.append("定向测试（有模块没跑起来）")
        elif 测试码 != 0:
            红模块 = [节点["分片"] for 节点 in 测试节点 if 节点["退出码"] > 0]
            # ★ 报红必须给全量（2026-09-25）：原 `红模块[:3]` 只列前 3 个名字，实测前一路拿到
            #   「9 个模块判红」却只看到 3 个名字，被迫做 3 组二分才凑齐真实数目（实际 11 个）。
            #   同形态本仓历史已有一次（判红消息报 66 只列 5）；处置口径同 `_尾部`：
            #   判红时**一条不砍**，`失败门禁` 里的这条必须列出全部判红模块名。
            失败门禁.append(f"定向测试（{len(红模块)} 个模块判红，全量列出：{'、'.join(红模块)}）")

    print("═══ 结论 ═══")
    if 未核验:
        print(f"五态结论：未核验 —— 有检查项**没跑成或本轮无核验对象**，不许当通过处理（fail-closed）：{'、'.join(未核验项)}。")
        if "语法编译" in "".join(未核验项):
            print("  语法编译：本轮**没有可编译的 .py**（变更集里无 .py 或全仓扫描面为 0）"
                  "—— 这一项**一次都没跑**，不得读成「语法编译通过」。要语法编译结论："
                  "`--全仓` 或 `--文件 <路径.py>`。")
        if 失败门禁:
            print(f"  本轮同时已记红项（一并修）：{'、'.join(失败门禁)}")
        if 只报红项:
            print(f"  本轮只报告类判红项（一并核）：{'、'.join(只报红项)}")
        return 2
