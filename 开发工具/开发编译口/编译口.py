def _尾部(文本: str, 行数: int = 每门禁输出行数) -> str:
    """门禁输出的显示行：**判红时违规条目全量透出，不截断**。

    2026-09-21 华哥裁决「不能一次性把不够规范的一次查出来吗？怎么访问那么多次才行」
    —— 根因就是这里：原实现一律取尾部 N 行（N=6），而门禁一次可报十几条违规
    （实测 `公开调用完整性门禁` 一次报 **13 条**、输出 20 行，这里只显示最后 6 行 ⇒
    前 7 条被静默砍掉，被迫反复单跑各门禁才看全）。这与「一次编译、规则全查」
    （易语言模式）的口径直接冲突，也与「解析不出来不许静默跳过（防假绿）」同源：
    **砍掉的红项 = 看不见的红项**。

    新口径（两条并存，不冲突）：
    ① `[判据名]` 开头的**违规条目行全部保留**（判红时它们才是要修的东西）；
    ② 其余行仍按 `判红尾巴行数` / `行数` 取尾部（结论、汇总、耗时在尾部）。

    判绿（无违规条目）时行为与原先**逐字一致**：仍只取尾部 `行数` 行。
    """
    行列表 = [行 for 行 in 文本.splitlines() if 行.strip()]
    if not 行列表:
        return "（无输出）"
    # ① 全量透出违规条目（判红时一条不砍）
    违规行 = [行 for 行 in 行列表 if 行.lstrip().startswith(违规条目前缀)]
    if 违规行:
        尾部 = 行列表[-判红尾巴行数:]
        # 违规条目按原顺序在前，尾部结论在后；重复的尾部行不重复打
        合并 = 违规行 + [行 for 行 in 尾部 if 行 not in 违规行]
        return "\n".join(合并)
    # ② 判绿：与原行为逐字一致
    return "\n".join(行列表[-行数:])


def _生成码(结论: dict | None, 名字: str) -> int | None:
    """从生成物联动结论里取某条凭据的生成退出码；**没有该条返回 None**（不是 0）。

    返回 None 与返回 0 是两件事：前者是「登记表里没有这条，本轮没生成过」，
    后者是「生成器真跑了且退出码 0」。混作一谈就会把「没跑」读成「跑过了」——
    正是本口 #68 与「未核验不占通过位」要防的那一类假绿。
    """
    if not isinstance(结论, dict):
        return None
    for 行 in 结论.get("生成表") or []:
        if isinstance(行, dict) and 行.get("名字") == 名字:
            码 = 行.get("生成退出码")
            return 码 if isinstance(码, int) else None
    return None


def _核验码(结论: dict | None, 名字: str) -> int | None:
    """从生成物联动结论里取某条凭据的**核验**退出码（只读口径用）；没有该条返回 None。

    与 `_生成码` 同一口径：None 是「登记表里没有这条」，不是 0（不把「没跑」读成「跑过了」）。
    """
    if not isinstance(结论, dict):
        return None
    for 行 in 结论.get("生成表") or []:
        if isinstance(行, dict) and 行.get("名字") == 名字:
            码 = 行.get("核验退出码")
            return 码 if isinstance(码, int) else None
    return None


def _git变更文件() -> list[str]:
    """git 变更集（含未跟踪，-uall 让新目录里的文件逐个列出），返回相对路径列表；删除条目自然排除。

    git 不可用时抛 `Git不可用`（由主函数捕获后按「未核验」退 2），
    不许裸冒泡成 Python 回溯退出 1 —— 那会被读成「编译口失败」而不是「没核验成」。
    """
    退出码, 输出, _ = _跑(
        # -c core.quotePath=false 必须显式带：本机 .gitconfig 设了 false，但**别人 clone 后默认 true**，
        # git 会把中文路径输出成 "\345\274\200..." 转义形式 → 路径不存在 → 编译口拿非 UTF-8 转义串
        # 去 py_compile，报 No such file 的假红。本仓路径全中文，这条不加固就只在别人机器上炸。
        ["git", "-c", "core.quotePath=false", "status", "--porcelain", "-uall"], 超时秒=30,
    )
    if 退出码 != 0:
        raise Git不可用(f"git status 不可用（退出码 {退出码}）：{输出[:200]}")
    文件列表 = []
    for 行 in 输出.splitlines():
        if len(行) < 4:
            continue
        状态, 路径 = 行[:2], 行[3:].strip().strip('"')
        # R 状态还要看**状态位里的布尔**，不能只比字符串：porcelain 里「重命名且内容改了」是
        # ``RM``（R=索引重命名 + M=工作区修改），``状态.strip() in {"D","R"}`` 漏掉它 →
        # ``旧 -> 新`` 整串被当成一个文件名 → py_compile 报 No such file 的假红（本仓实测）。
        if "R" in 状态 or "D" in 状态:
            # 重命名取新名（porcelain 的 R 行是 "旧 -> 新"）。
            if "->" in 路径:
                路径 = 路径.split("->")[-1].strip()
            else:
                continue
        if not 路径:
            continue
        if any(段 in 路径 for 段 in ("__pycache__",)) or 路径.startswith(("工程缓存/", ".git/")):
            continue
        文件列表.append(路径)
    return 文件列表


def _包id(路径文本: str) -> str | None:
    """文件 → 所属包：向上找最近的 包声明.json。"""
    当前 = (系统根 / 路径文本).resolve()
    if not 当前.exists():
        当前 = 当前.parent
    for 候选 in (当前, *当前.parents):
        if (候选 / "包声明.json").is_file():
            try:
                import json
                return str(json.loads((候选 / "包声明.json").read_text(encoding="utf-8")).get("包id") or "")
            except Exception:
                return 候选.name
        if 候选 == 系统根:
            break
    return None


def _影响面(变更文件列表: list[str], 显式包: list[str] | tuple[str, ...] = ()) -> dict:
    """受影响包 + 反向依赖闭包（按包声明.json 的 依赖 字段逐层扩散）。

    `显式包`（华哥 2026-09-22「改完代码，直接把库的 ID 传过去，然后就编译就行了」）：
    直接点名包 id，与「从变更文件推包」等价，但**不依赖 git 变更集** ——
    调用方传的是**变量（库 id）**，不是路径、更不是命令（通用纪律「传变量不写命令」）。
    点名的包 id 现场找不到时收进 `未知包`，由调用方 fail-closed 处理（不猜、不静默忽略）。
    """
    import json
    受影响: set[str] = set(str(x) for x in 显式包 if str(x).strip())
    非包文件: list[str] = []
    for 路径文本 in 变更文件列表:
        包id = _包id(路径文本)
        if 包id:
            受影响.add(包id)
        else:
            非包文件.append(路径文本)

    依赖表: dict[str, list[str]] = {}
    包目录表: dict[str, Path] = {}
    # 进目录即剪枝（`正式根.遍历源码`）：此前 `系统根.rglob("包声明.json")` 会把 9.3G
    # `工程缓存`（制品副本里的 `包声明.json` 成千上万）一并枚举再逐条过滤。
    for 声明路径 in 遍历源码(系统根, 后缀=("包声明.json",), 剪枝=真):
        try:
            数据 = json.loads(声明路径.read_text(encoding="utf-8"))
        except Exception:
            continue
        包id = str(数据.get("包id") or "")
        依赖表[包id] = [str(项) for 项 in (数据.get("依赖") or [])]
        包目录表[包id] = 声明路径.parent
    反向: dict[str, set[str]] = {}
    for 包id, 依赖列表 in 依赖表.items():
        for 被依赖 in 依赖列表:
            反向.setdefault(被依赖, set()).add(包id)

    已扩散: set[str] = set()
    队列 = list(受影响)
    while 队列:
        当前 = 队列.pop()
        if 当前 in 已扩散:
            continue
        已扩散.add(当前)
        队列.extend(反向.get(当前, ()))
    摘要联动提示 = sorted(
        {包id.rsplit(".", 1)[0] for 包id in 已扩散 if 包id.count(".") >= 3},
    )
    return {
        "受影响包": sorted(受影响),
        "反向依赖闭包": sorted(已扩散 - 受影响),
        "非包文件": sorted(非包文件),
        "摘要联动提示": 摘要联动提示,
        "包目录表": 包目录表,
        "未知包": sorted(受影响 - set(依赖表)),
    }


def _包内py相对路径(受影响包: list[str], 包目录表: dict[str, Path]) -> list[str]:
    """点名包（库）内的全部 .py 相对路径（`--库` 口径的语法编译对象）。

    只收**该包目录下**的 .py，不进子包 —— 子包有自己的 `包声明.json`，会被反向依赖闭包
    单独带进来，重复枚举等于同一份文件编译两遍。目录不存在（点名了未知包）时跳过，
    由调用方按 `未知包` 提前 fail-closed，不在这里静默吞。
    """
    命中: list[str] = []
    for 包id in 受影响包:
        目录 = 包目录表.get(包id)
        if 目录 is None or not 目录.is_dir():
            continue
        for 路径 in sorted(目录.rglob("*.py")):
            if "__pycache__" in 路径.parts:
                continue
            命中.append(str(路径.relative_to(系统根)))
    return 命中


def _定向测试点名(受影响包: list[str]) -> list[str]:
    """受影响包短名 → 测试中心里文件名含该短名的模块（只点名，不执行）。"""
    短名列表 = [包id.rsplit(".", 1)[-1] for 包id in 受影响包 if 包id]
    命中: set[str] = set()
    测试根 = 系统根 / "测试中心"
    for 测试文件 in 测试根.rglob("测试_*.py"):
        文件名 = 测试文件.stem
        if any(短名 and 短名 in 文件名 for 短名 in 短名列表):
            相对 = 测试文件.relative_to(系统根)
            命中.add(".".join(相对.with_suffix("").parts))
    return sorted(命中)


