def 接线表路径错(测试根: Path | None = None) -> list[str]:
    """逐条把接线表里的测试模块解析回文件路径，返回**对不上**的那些（空表＝全对）。

    `测试根` 只为**反向验证**留的口子（指到一个空目录，每一条都必须报错）；
    正常调用不传，解析基准是仓库根（键是仓库相对路径，值是仓库根下的模块路径）。
    """
    根 = Path(测试根) if 测试根 is not None else 系统根
    错: list[str] = []
    for 前缀, 模块表 in 非包文件测试点名.items():
        if not (系统根 / 前缀).exists():
            错.append(f"{前缀}：键指向的文件/目录不存在（改了名或写错了？）")
        for 模块 in 模块表:
            相对 = Path(*模块.split(".")).with_suffix(".py")
            if not (根 / 相对).is_file():
                错.append(f"{前缀} → {模块}：测试模块不存在（应为 {相对}）")
    return 错


