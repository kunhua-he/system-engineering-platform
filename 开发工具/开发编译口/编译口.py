        print(f"五态结论：失败 —— 阻断类红项：{'、'.join(失败门禁)}。按红项修完再跑一遍。")
        if 只报红项:
            print(f"  另有只报告类判红项（见上，未计入红绿）：{'、'.join(只报红项)}")
