"""门禁报告：文本与 JSON 两种呈现；判定与呈现分离。

`生成摘要行` 供发布门禁等调用方把结果压成一行（A4 落点期望
`检查("测试体系完整", not 违规, f"违规={…}")`）。
"""
from __future__ import annotations

import json

类型顺序 = ("导入失败", "零测试", "零测试文件", "未解释跳过", "跳过资产未守护")


def 分组计数(违规: list[dict]) -> dict[str, int]:
    计数: dict[str, int] = {}
    for 条 in 违规:
        名称 = 条.get("类型", "未分类")
        计数[名称] = 计数.get(名称, 0) + 1
    return 计数


def _摘要(违规: list[dict]) -> str:
    计数 = 分组计数(违规)
    return "、".join(f"{名称} {计数[名称]}" for 名称 in 类型顺序 if 名称 in 计数)


def 生成文本报告(结果: dict) -> str:
    行 = [
        f"测试体系门禁：{结果['相对根']} → 发现测试文件 {结果['测试文件数']} 个，"
        f"纳入可导入性 {结果['参与数']} 个，导入成功 {结果['导入成功数']} 个，"
        f"实际收集用例 {结果['用例总数']} 个，跳过 {结果['跳过数']} 个，"
        f"耗时 {结果['耗时秒']:.1f} 秒"
    ]
    if 结果["跳过"]:
        行.append(f"跳过（不纳入可导入性，共 {len(结果['跳过'])} 项）：")
        行.extend(f"  [跳过] {条['文件']} — {条['细节']}" for 条 in 结果["跳过"])
    if not 结果["违规"]:
        行.append("测试体系门禁通过：全部测试文件可导入、无零测试、无未解释跳过")
        return "\n".join(行)
    行.append(f"测试体系门禁失败：共 {len(结果['违规'])} 项违规（{_摘要(结果['违规'])}）")
    for 条 in 结果["违规"]:
        位置 = f"{条['文件']}:{条['行号']}" if 条.get("行号") else 条["文件"]
        行.append(f"  [{条['类型']}] {位置} — {条['细节']}")
    return "\n".join(行)


def 生成json报告(结果: dict) -> str:
    return json.dumps(结果, ensure_ascii=False, indent=2)


def 生成摘要行(结果: dict) -> str:
    """一行摘要：无换行，供门禁清单直接打印。"""
    if not 结果["违规"]:
        return (f"测试体系 0 违规（测试文件 {结果['测试文件数']}，"
                f"用例 {结果['用例总数']}，跳过 {结果['跳过数']}）")
    首条 = 结果["违规"][0]
    return (f"测试体系违规 {len(结果['违规'])} 项（{_摘要(结果['违规'])}）；"
            f"首项 {首条['文件']} — {首条['细节']}")
