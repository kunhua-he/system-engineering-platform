"""零测试检查：零用例、以及「扫描面塌成 0」都不得成功。

`AGENTS.md:135` 要求「门禁：实际加载全部测试；零测试、导入失败、未解释跳过
全部必须失败」。本门禁不执行用例，所以零测试落在两个可静态证真的口径上：

1. 某个 `测试_*.py` 被官方 `TestLoader` 收集到 **0 个用例** → 违规；
2. `测试中心` 下**一个测试文件都没有**，或发现的文件**全部被跳过**（连字符等）
   → 违规。否则「范围塌成 0」会让门禁在空目录上假绿。

导入失败的文件不在本模块重复计数（已由「可导入性检查」报出）。

本模块不打印、不退出。
"""
from __future__ import annotations

from . import 发现


def 零测试违规(探测结果: list[dict], 资产列表: list[发现.测试资产]) -> list[dict]:
    """返回零测试/零测试文件违规清单。"""
    违规: list[dict] = []
    if not 资产列表:
        违规.append({
            "类型": "零测试文件", "文件": 发现.测试中心目录名, "行号": None,
            "细节": f"{发现.测试中心目录名} 下未发现任何 {发现.测试文件名模式}（零测试不得成功）",
        })
        return 违规
    参与 = [资产 for 资产 in 资产列表 if not 资产.跳过原因]
    if not 参与:
        违规.append({
            "类型": "零测试文件", "文件": 发现.测试中心目录名, "行号": None,
            "细节": (f"发现 {len(资产列表)} 个测试文件，但全部被跳过"
                     f"（连字符等不可点号导入），无文件进入可导入性检查"),
        })
        return 违规
    for 项 in 探测结果:
        if not 项["导入成功"]:
            continue
        if int(项["用例数"] or 0) <= 0:
            违规.append({
                "类型": "零测试", "文件": 项["相对路径"], "行号": None,
                "细节": f"TestLoader 实际收集到 0 个用例（模块 {项['模块名']}）",
            })
    return 违规
