"""包级说明-使用说明 → 统一入口的分派适配层。

**为什么需要这一层**：统一入口 `开发工具.MD文档生成 --类型 <名>` 对「有可刷新生成区」
的类型统一按 `主流程(项目根, 写盘=?, 今天=?, 单文件=?)` 调用（见 `__main__.py` 的分派表），
而说明书合并重生成的原生入口是 `合并重生成.主函数(--包/--全部/--写盘/--详单)`。
两者签名不同 —— 由本层翻译，**不让调用方感知内部差异**（哲学 2.4 翻译器原则：差异在边界吃干净）。

**本层是纯翻译，不含任何生成逻辑**：逻辑唯一真源仍是 `合并重生成`，
本层只做「统一入口的入参形态 → 原生入口的入参形态」的映射，因此不构成第二套实现。
"""

from __future__ import annotations

from pathlib import Path

from 公共契约.运行时.平台适配 import 解析路径
from 开发工具.MD文档生成.说明书 import 合并重生成


def 主流程(项目根: Path, 写盘: bool, 今天: str | None = None,
          单文件: str | None = None) -> tuple[int, list[str]]:
    """统一入口形态 → 原生入口形态。

    - `项目根`：本层与原生入口都按「向上找含 开发文档/ 的根」自解析，故不传（原生入口内置）。
    - `写盘`：直通。
    - `今天`：说明书重生成不按「生成当天」打日期（日期从 git 派生，见 0057），故忽略。
    - `单文件`：说明书按**包**跑（一份文件对应它所在包），故把该文件所在包目录转成 `--包` 参数；
      传不进包时如实报错，不静默退化成「扫全仓」（那会让「定向核一份」变成全量，属假绿）。
    """
    原生参数: list[str] = []
    if 写盘:
        原生参数.append("--写盘")
    if 单文件:
        路径 = 解析路径(单文件, 项目根)
        # 说明书相对名固定为 说明/使用说明.md；从该文件上溯到所属包目录
        包目录 = 路径.parent.parent if 路径.parent.name == "说明" else 路径.parent
        if not (包目录 / "包声明.json").is_file():
            # 报错信息按「问题 + 当前值 + 期望形态」给全（调用方不必再猜）
            return 2, [f"单文件模式需要该文件属于某个含 包声明.json 的包："
                       f"当前 {单文件} → 推出包目录 {包目录}（无 包声明.json）。"
                       f"请用 `--类型 包级说明-使用说明`（全仓）或指向 说明/使用说明.md"]
        原生参数.extend(["--包", str(包目录.relative_to(项目根))])
    码 = 合并重生成.主函数(原生参数)
    return 码, []
