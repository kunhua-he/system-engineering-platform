    # **改判必须真的合得上才算数**（2026-09-22 补）：改判只是「换一支账再试」，
    # 试出来的提案仍要过同一道「人工行零丢失」自检。未过时**不产提案、退回问题态** ——
    # 否则本包的坏提案会触发 `主函数` 的全局拒写（任一包零丢失未过即整体 return 2、
