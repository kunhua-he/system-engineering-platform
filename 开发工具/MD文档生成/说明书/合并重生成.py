def 主函数(argv: list[str] | None = None) -> int:
    解析器 = argparse.ArgumentParser(
        description="说明书合并式重生成：刷生成行、保人工行；写盘前自检人工行零丢失")
    解析器.add_argument("--包", action="append", default=[],
                     help="只处理该包目录（可多次）；缺省 = 全仓扫描")
    解析器.add_argument("--全部", action="store_true", help="全仓扫描（默认即为全仓）")
    解析器.add_argument("--写盘", action="store_true",
                     help="落盘（人工行零丢失校验全绿才写；缺省干跑）")
    解析器.add_argument("--详单", action="store_true", help="打印逐行 diff")
    参数 = 解析器.parse_args(argv)

    白名单 = 读白名单()
    if 参数.包:
        目标表 = []
        for 原文 in 参数.包:
            包目录 = (系统根 / 原文) if not Path(原文).is_absolute() else Path(原文)
            if not 包目录.is_dir():
                print(f"✗ 不是目录: {原文}")
                return 2
            目标表.append(包目录)
    else:
        目标表 = 包目录表(系统根)
    if not 目标表:
        print("✗ 未扫描到任何含 说明/使用说明.md 的包")
        return 2

    提案表: dict[str, dict] = {}
    未核验表: dict[str, dict] = {}
    白名单跳过表: dict[str, dict] = {}
    for 包目录 in 目标表:
        单 = 合并单包(包目录, 系统根, 白名单)
        if 单.get("可合并"):
            提案表[单["路径"]] = 单
            continue
        print(f"  － {单['包']}: {单['问题']}")
        # #121（2026-09-23）：零提案必须**分成两类**计数，不能一律当「零漂移」。
        # 「判不出」（哨兵命中／改判自检未过／账读不出）= 未核验，退出码非 0；
        # 「白名单跳过」（人工类，生成器按规矩不碰）= 合法跳过，允许退出码 0。
        if 单.get("处置") == "白名单跳过":
            白名单跳过表[单["路径"]] = 单
        else:
            未核验表[单["路径"]] = 单

    有改动 = {路径: 单 for 路径, 单 in 提案表.items() if 单["统计"]["有改动"]}
    零丢失坏 = {路径: 单 for 路径, 单 in 提案表.items() if not 单["统计"]["人工行零丢失"]}

    # **血统改判如实报**（2026-09-22 补）：改判是「原判据选错、按另一支的账才合得上」的
    # 显式声明，不静默 —— 否则「为什么这份文件的账从 252 行变成 720 行」事后无从查证。
    for 路径, 单 in sorted(提案表.items()):
        if 单.get("血统改判"):
            print(f"  ↺ {单['包']}: 血统改判 {单['血统改判']}")

    for 路径, 单 in sorted(有改动.items()):
        统计 = 单["统计"]
        类别 = 单["白名单类别"] or "（不在白名单）"
        print(f"\n═══ {单['包']} ═══  血统={单['血统']} 白名单类别={类别}")
        print(f"  现行 {统计['现总行']} 行 / 账 {统计['账总行']} 行 / 合并 {统计['合并总行']} 行；"
              f"人工 {统计['人工行数']} 保、{统计['刷行数']} 刷、"
              f"丢账 {统计['丢弃账行数']}、补账 {统计['补入账行数']}；"
              f"人工行零丢失={统计['人工行零丢失']}")
        for 行 in 统计["刷行"]:
            print(f"    [刷] {行}")
        for 行 in 统计["补行"]:
            print(f"    [补账] {行}")
        if 参数.详单:
            for 行 in 单["差异"]:
                print(f"      {行}")

    print(f"\n扫描 {len(提案表)} 份说明书；有漂移 {len(有改动)} 份；"
          f"人工行零丢失未过 {len(零丢失坏)} 份；"
          f"未核验（判不出）{len(未核验表)} 份；"
          f"白名单合法跳过 {len(白名单跳过表)} 份")

    # #121：未核验必须**判红并退非 0**（与「有漂移」「零丢失未过」同级）——
    # 否则「生成器根本没刷这份说明书」会被上层读成 `退出码=0`（实测掩盖链的中间环）。
    # 放在 --写盘 之前：判不出的包在两种口径下都不该被当成「零漂移」。
    if 未核验表:
        print("⇒ 未核验（判不出，非零退出）：下列说明书的生成基准不成立，"
              "本轮**没有取得任何「已刷新」证据**：")
        for 路径 in sorted(未核验表):
            print(f"    ? {路径}: {未核验表[路径]['问题'][:160]}")
        print(f"  白名单合法跳过 {len(白名单跳过表)} 份（不判红：生成器按规矩不碰人工类件）")
        return 2

    if 零丢失坏:
        print("⇒ 拒绝写盘：下列说明书的人工行零丢失校验未过（合并算法有缺陷，先修算法）")
        for 路径 in sorted(零丢失坏):
            print(f"    ✗ {路径}: {零丢失坏[路径]['统计']['结构异常'] or '有人工行被丢'}")
        return 2

    if not 参数.写盘:
        if 有改动:
            print("⇒ 干跑（未写盘）。确认无误后加 --写盘 落盘")
            return 1
        print("⇒ 全部已是固定点（零漂移）")
        return 0

    for 路径, 单 in sorted(有改动.items()):
        (系统根 / 路径).write_text(单["提案"], encoding="utf-8")
        # **写盘必带机器印记**（2026-09-20 补，华哥口径「全部 md 都要经生成器写」）：
        # `开发工具.MD文档生成 --拒绝手写校验` 的判据就是「本轮改动的 md 有没有机器印记」，
        # 本工具原先只写正文、不加印记 ⇒ **经生成器写的 md 反被判成「手写」**
        # （实测：修 #63 时经本工具写的 `平台控制面/备份恢复/说明/使用说明.md` 被编译口
        # 判红「发现手写 md 1 份」，而它恰恰是生成器的产出）。印记是「这份在被生成器管」
        # 的声明，写盘与声明必须同一处发生，不能让调用方再手工补一步。
        机器印记.加印记(系统根, 路径, "包级说明-使用说明")
        print(f"    ✓ 已写盘 {路径}（人工行 {单['统计']['人工行数']} 行原样保留；机器印记已加）")
    print(f"⇒ 已写盘 {len(有改动)} 份；{len(提案表) - len(有改动)} 份零漂移未动")
    return 0


