def 读契约(包目录: Path) -> tuple[dict[str, dict], str, str]:
    """读包契约：返回（能力表 `能力id→定义项`, 包版本, 问题）。

    包版本取 `包声明.json` 的 `版本`（门禁对账用的正是这一侧，见
    `公开调用完整性门禁_说明书解析.检查说明书字段`）；能力级版本取 `能力定义.json`
    `能力列表[].版本`。

    **`能力定义.json` 不存在 ≠ 问题**：6 个聚合支持库（系统核心 / 大语言模型 / 数据操作 /
    文件系统 / 网络通信 / 办公文档）按 `AGENTS.md` 的聚合父包豁免**不持** `能力定义.json`
    （能力在子域包里），它们该被**跳过**而不是拒写。存在但读不出来才是问题。
    """
    定义路径 = 包目录 / "能力定义.json"
    if not 定义路径.is_file():
        return {}, "", ""
    try:
        定义 = json.loads(定义路径.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as 错误:
        return {}, "", f"能力定义.json 不可读（{type(错误).__name__}: {错误}）"
    if not isinstance(定义, dict):
        return {}, "", "能力定义.json 顶层不是对象"
    能力表: dict[str, dict] = {}
    for 项 in 定义.get("能力列表") or []:
        if isinstance(项, dict) and 项.get("能力id"):
            能力表[str(项["能力id"])] = 项
    if not 能力表:
        # ★ 2026-09-24（批R·R-31 收尾）：区分「读不出／坏了」与「显式零能力面」——
        #   后者是 R-28 后适配层 5 个提供者包「有实现、无能力面」的**合法形态**。
        #   为什么必须放行：判据侧 `公开调用完整性门禁_说明书解析.期望能力字段` 对这种包
        #   返回空表 ⇒ 对账射程为空；本模块是「修」腿，射程须与之同为空（哲学 1.2：
        #   不许两条腿各判一套）。口径**转调唯一节点**，单侧清空照旧 fail-closed 判红。
        if 包声明显式零能力(包目录):
            return {}, "", ""
        return {}, "", "能力定义.json 里没有能力（扫描面为 0 不是通过）"
    包版本 = ""
    try:
        声明 = json.loads((包目录 / "包声明.json").read_text(encoding="utf-8"))
        if isinstance(声明, dict):
            包版本 = str(声明.get("版本") or "")
    except (OSError, json.JSONDecodeError):
        包版本 = ""
    return 能力表, 包版本, ""


def _标题里的能力id(行: str, 能力表: dict[str, dict]) -> str:
    """标题行 → 能力 id：先认反引号写法，再退化为「标题里直接出现能力表里的 id」。

    退化那支取**最长命中**：`平台控制面.包仓库` 是 `平台控制面.包仓库.校验签名` 的前缀，
    取短的那个会把两个能力的段并成一段（实测体例里两种写法都存在）。
    """
    反引 = 反引号.search(行)
    if 反引 and 反引.group(1).strip() in 能力表:
        return 反引.group(1).strip()
    候选 = [能力id for 能力id in 能力表 if 能力id in 行]
    return max(候选, key=len) if 候选 else ""


def _参数项(定义项: dict) -> list[dict]:
    return [项 for 项 in (定义项.get("参数") or [])
            if isinstance(项, dict) and 项.get("名称")]


def _参数列表文本(定义项: dict) -> str:
    项表 = _参数项(定义项)
    if not 项表:
        return "无"
    return ", ".join(f"{项['名称']}:{项.get('类型') or ''}" for 项 in 项表)


def _必填名表(定义项: dict) -> str:
    """必填参数行的文本：`必填` 为真的参数名，逗号分隔；一个都没有写「无」。

    `必填` 键**缺省按假**（不是按真）：门禁只在「说明书列了该参数为必填」时才比对，
    所以这里保守地不替缺省的参数声明必填 —— 宁可少写（门禁不判），不可多写（会判红）。
    """
    名 = [str(项["名称"]) for 项 in _参数项(定义项) if bool(项.get("必填"))]
    return ", ".join(名) if 名 else "无"


def 同步文本(现行文本: str, 包版本: str, 能力表: dict[str, dict]) -> dict:
    """算出一份说明书的载位同步提案。

    返回 `{新行表, 变更, 跳过, 体例}`：

    - `变更`：逐条「改了什么」；
    - `跳过`：认不出的项（无散文段的能力、无包级版本载位）—— **不是问题，是边界**，
      判据归门禁；
    - `体例`：`散文式`（至少认出一个能力段）/ `非散文式`（一个都没认出，如表格体例）。

    只有 `体例=非散文式` 时整份不改：那种说明书把载位放在能力清单表里，
    本模块不猜表结构。
    """
    行表 = 现行文本.splitlines()
    新行表 = list(行表)
    # 标题识别转调唯一腿（见 门禁 `标题行表`）：行号自 1 起，与本处 `序号+1` 对齐。
    标题行们 = 标题行表(现行文本)
    变更: list[str] = []
    跳过: list[str] = []
    当前能力 = ""
    已见能力: set[str] = set()
    已出头部 = False
    有包级版本载位 = False
    for 序号, 行 in enumerate(行表):
        if (序号 + 1) in 标题行们:
            当前能力 = _标题里的能力id(行, 能力表)
            if 当前能力:
                已见能力.add(当前能力)
            已出头部 = True
            continue
        匹配 = 版本行.match(行)
        if 匹配:
            原文 = 匹配.group(1)
            if not 当前能力:
                if not 已出头部:
                    有包级版本载位 = True
                    if 包版本 and 原文 != 包版本:
                        新行表[序号] = f"- 版本：{包版本}"
                        变更.append(f"包级版本 {原文} → {包版本}")
            else:
                期望版本 = str(能力表[当前能力].get("版本") or "")
                if 期望版本 and 原文 != 期望版本:
                    新行表[序号] = f"- 版本：{期望版本}"
                    变更.append(f"{当前能力} 能力级版本 {原文} → {期望版本}")
            continue
        if not 当前能力:
            continue
        # 只同步门禁真正对账的两类载位（版本已在上面处理）：参数列表 / 必填参数。
        # `可选参数` / `错误码` / `返回结构` / `调用示例` **只校验不改写**（理由见模块 docstring）。
        for 正则, 生成, 标签 in (
            (参数列表行, _参数列表文本, "参数列表"),
            (必填参数行, _必填名表, "必填参数"),
        ):
            匹配 = 正则.match(行)
            if 匹配:
                期望文本 = 生成(能力表[当前能力])
                if 匹配.group(1).strip() != 期望文本:
                    新行表[序号] = f"- {标签}：{期望文本}"
                    变更.append(f"{当前能力} {标签} → {期望文本}")
                break
    体例 = "散文式" if 已见能力 else "非散文式"
    无段 = [能力id for 能力id in 能力表 if 能力id not in 已见能力]
    if 无段 and 体例 == "散文式":
        跳过.append(f"这些能力在本份说明书里没有散文式段落（载位可能在能力清单表里，"
                  f"本模块不猜表结构）：{'、'.join(无段)}")
    if 包版本 and not 有包级版本载位:
        跳过.append("本份说明书没有包级版本载位（`- 版本：X` 且位于首个二级标题之前）")
    return {"新行表": 新行表, "变更": 变更, "跳过": 跳过, "体例": 体例}


def 同步一份(说明相对: str, 项目根: Path, *, 写盘: bool) -> dict:
    """同步一份说明书的载位；返回 `{路径, 变更, 跳过, 体例, 问题, 已写盘, 已刷摘要}`。

    `已刷摘要` = 本次同轮重算的完整性摘要路径表（写盘口径下写实体后必刷）；
    只读口径恒为空表（不写盘就不改摘要）。

    入参是**白名单里的相对路径原文**（不自己拼 `说明/使用说明.md`）：白名单条目形态不一
    （实测有 `开发工具/直播逐字稿工具/使用说明.md` 这种不在 `说明/` 目录下的），照拼会把
    它误报成「说明书不存在」。非标准形态直接跳过，不猜。
    """
    出: dict = {"路径": 说明相对, "变更": [], "跳过": [], "体例": "",
               "问题": "", "已写盘": False, "已刷摘要": [], "摘要问题": ""}
    说明路径 = 项目根 / 说明相对
    if 说明路径.parent.name != 标准说明书相对[0] or 说明路径.name != 标准说明书相对[1]:
        出["跳过"].append(f"非标准说明书形态（{说明相对}）：本模块只处理 `**/说明/使用说明.md`")
        return 出
    if not 说明路径.is_file():
        出["问题"] = "说明书不存在"
        return 出
    能力表, 包版本, 问题 = 读契约(说明路径.parent.parent)
    if 问题:
        出["问题"] = 问题
        return 出
    if not 能力表:
        # 两支都**不是拒写**，各自如实报（跳过 ≠ 通过，扫描面口径见 `主流程`）：
        #   · 聚合父包（按 AGENTS.md 豁免，不持 能力定义.json，能力在子域包里）；
        #   · 显式零能力面（两侧同时空，如 R-28 后「有实现、无能力面」的适配层提供者包）
        #     ——无能力级载位可同步（判据侧射程同为空，见 `公开调用完整性门禁_说明书解析`）。
        if 包声明显式零能力(说明路径.parent.parent):
            出["跳过"].append("本包显式零能力面（能力定义.json 与 包声明.json 两侧同时为空）"
                          "——无能力级载位可同步，跳过")
        else:
            出["跳过"].append("本包不持 能力定义.json（聚合父包豁免，能力在子域包里）")
        return 出
    try:
        现行 = 说明路径.read_text(encoding="utf-8")
    except (OSError, ValueError) as 错误:
        出["问题"] = f"说明书不可读（{type(错误).__name__}: {错误}）"
        return 出
    提案 = 同步文本(现行, 包版本, 能力表)
    出["变更"], 出["跳过"], 出["体例"] = 提案["变更"], 提案["跳过"], 提案["体例"]
    if 出["体例"] != "散文式":
        出["跳过"].append("整份认不出散文式能力段（如能力清单表体例），本模块不改它")
        return 出
    if 出["变更"] and 写盘:
        写入文件(str(说明路径), "\n".join(提案["新行表"]) + "\n").确保成功()
        出["已写盘"] = True
        # ★ 写实体后**同轮刷摘要**（2026-09-24 批O O-6）：上面改的 `说明/使用说明.md` 被同包
        # `完整性摘要.json` 登记哈希（实测 139/140 份人工类说明书的同包摘要都登记了它，
        # 另有 42 份还被**祖先聚合包**登记） ⇒ 不刷就把「摘要≠实体」留到下一轮。
        # **为什么不靠别的腿兜**（登记表顺序，实测）：本凭据是登记表第 10 条 —— **最后一条**，
        # 它之后没有任何派生凭据；全仓那条 `摘要闭合` 是第 3 条，排在它之前。
        # 重算面定点（目标所在包 + 登记了它的祖先），不扫全仓。
        from 开发工具.MD文档生成.说明书.完整性摘要生成器 import 刷新登记该文件的摘要
        try:
            出["已刷摘要"] = 刷新登记该文件的摘要(说明路径)
        except (OSError, ValueError) as 错误:
            # 载位已写入、但摘要没跟上 ⇒ 「摘要≠实体」。不静默：如实升为真问题（主流程码 2）
            出["摘要问题"] = f"同轮摘要重算失败（{type(错误).__name__}: {错误}）"
    return 出


def 主流程(项目根: Path, *, 写盘: bool,
          单文件: str | None = None) -> tuple[int, list[str]]:
    """对全部**人工类**说明书做载位同步（范围读既有白名单，不另立判据）。

    退出码（**「修」的语义：修完就不再是红**）：

    - **写盘口径**（`--写盘`）：0 = 变更已全部写入 / 本来就没有变更（都已修好）；
      2 = 有真问题（说明书或能力定义不可读）或扫描面为 0。
      写盘后**不再按「有过变更」判非零** —— 那是把「修好了」报成「没修好」
      （实测踩到：编译口步骤4 复跑确认据此误报「生成未成功（退出码 1）」）。
    - **只读口径**（`--校验`）：0 = 全部一致；1 = 有变更**待同步**；2 同上。

    扫描面为 0 **不得记作通过**（与防回潮各项同口径）。
    """
    from 开发工具.MD文档生成.说明书.合并重生成 import 读白名单

    白名单 = 读白名单()
    人工类 = {路径: 条 for 路径, 条 in 白名单.items()
            if str(条.get("类别", "")).startswith("人工类")
            or "不得覆盖" in str(条.get("处置", ""))}
    if 单文件:
        人工类 = {单文件: 人工类.get(单文件, {})}
    if not 人工类:
        return 2, ["白名单里没有任何「人工类」说明书（扫描面为 0 不是通过）——"
                   "范围判据见 开发文档/项目证据/说明书白名单.json"]
    行表: list[str] = []
    码 = 0
    跳过数 = 0
    变更数 = 0
    for 相对 in sorted(人工类):
        结果 = 同步一份(相对, 项目根, 写盘=写盘)
        if 结果["问题"]:
            码 = max(码, 2)
            行表.append(f"  [拒写] {相对}：{结果['问题']}")
            continue
        if 结果["变更"]:
            变更数 += 1
            if not 写盘:
                # 只读口径：有变更 = 待同步（对「核验」而言就是红）
                码 = max(码, 1)
            行表.append(f"  [{'已同步' if 结果['已写盘'] else '待同步'}] {相对}："
                      + "；".join(结果["变更"]))
            for 摘要路径 in 结果.get("已刷摘要") or []:
                行表.append(f"      [刷摘要] {摘要路径}")
        else:
            行表.append(f"  [一致] {相对}")
        if 结果.get("摘要问题"):
            # 载位已写、摘要未跟上：真问题（不当「已同步」了事，判码 2）
            码 = max(码, 2)
            行表.append(f"      [摘要未刷] {结果['摘要问题']}")
        for 说明 in 结果["跳过"]:
            跳过数 += 1
            行表.append(f"      [跳过] {说明}")
    行表.append(f"共 {len(人工类)} 份人工类说明书；"
              f"{'已同步' if 写盘 else '待同步'} {变更数} 份；跳过说明 {跳过数} 条"
              f"（判据归 公开调用完整性门禁，本模块不重复判）")
    return 码, 行表
