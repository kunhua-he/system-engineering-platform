                    认到.add(当前能力)
                    块末 = _表块末尾(行表, 序)
                    已有 = {g[0] for g in (表行格(行表[位]) for 位 in range(序 + 2, 块末 + 1))
                          if g and g[0]}
                    补 = _参数补缺(能力表[当前能力], 已有)
                    契约项 = {str(项["名称"]): 项 for 项 in _参数项(能力表[当前能力])}
                    块 = list(行表[序:块末 + 1])
