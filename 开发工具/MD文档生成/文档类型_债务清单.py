def _分段名(标题文本: str) -> str:
    """从标题文本取分段键：首个空白或 `、` 之前的一段（`一、待修…`→`一`，`7.8 2026…`→`7.8`）。"""
    for i, 字 in enumerate(标题文本):
        if 字.isspace() or 字 == "、":
            return 标题文本[:i].rstrip("、,")
    return 标题文本


def 扫描正文(文本: str) -> tuple[dict[str, list[str]], dict[str, int]]:
    """返回 (分段→编号条目 id 列表, 分段→表格数据行数)。

    **标题与表格切分一律转调原子能力** `办公文档支持库.轻量文本解析.解析Markdown块`
    （哲学 1.2「一类事情只有一条腿」）：markdown 的表格边界规则只该有一处实现。
    本文件原来自写了一套 `表格行/表格分隔` 正则 + 「每段表第一行是表头」的启发式，
    结果三处同时错 —— 无编号表被按编号计、`| 6b |` 被正则漏、空行把表切成几段后
    每段首行都被当表头（§四 8 行数成 7、§7.7 12 行数成 11，2026-09-22 实测）。
    根因就是那套手写规则与真 markdown 规则各说各话。

    数据行判据（**不另写分隔行正则**）：能力给的表格块带 `行起/行止`，`区间` 是**原始行
    切片**（**含**分隔行），`块内` 是能力留下的（表头 + 数据）⇒ **两者之差 = 被能力
    丢掉的分隔行数**：差 > 0 即有表头，去掉「表头 + 差 行分隔」；差 = 0（空行切开的
    后半段，本就无表头）则整段都是数据行。
    """
    from 支持库.后端.办公文档支持库.轻量文本解析 import 解析Markdown块

    行表 = 文本.splitlines()
    编号: dict[str, list[str]] = {}
    行数: dict[str, int] = {}
    结果 = 解析Markdown块(文本, "完整")
    if not 结果.成功:
        raise RuntimeError(
            f"轻量文本解析.解析Markdown块 调用失败：{结果.错误码}：{结果.错误说明}")
    块列表 = (结果.值 or {}).get("块列表") or []
    当前 = ""
    for 块 in 块列表:
        属性 = 块.get("属性") or {}
        if 属性.get("章节") == "heading":
            # 与旧口径一致：只认 2~4 级标题当分段（能力把 >2 级的类型归为 paragraph，
            # 但属性里仍标 heading + level）。
            if 属性.get("level") in (2, 3, 4):
                当前 = _分段名(str(块.get("文本") or ""))
            continue
        if 块.get("类型") != "表格" or not 当前:
            continue
        起, 止 = 块.get("行起"), 块.get("行止")
        if not isinstance(起, int) or not isinstance(止, int):
            continue
        区间 = 行表[起 - 1:止]
        块内 = str(块.get("文本") or "").splitlines()
        # 区间是**原始行切片**（含分隔行），块内是能力留下的（表头 + 数据）：
        # 差 = 被丢掉的分隔行数 ⇒ 差 > 0 即有表头，去掉「表头 + 差 行分隔」。
        被丢 = len(区间) - len(块内)
        数据行 = 区间[被丢 + 1:] if 被丢 > 0 else 区间
        for 行 in 数据行:
            m2 = 编号行.match(行)
            if m2:
                编号.setdefault(当前, []).append(m2.group(1))
            行数[当前] = 行数.get(当前, 0) + 1
    return 编号, 行数


def 生成元信息行(项目根: Path) -> str:
    """日期从 git 派生（见 `元信息头.py` 的口径：内容没变日期不动，避免每天假红）。"""
    return (f"{元信息头.应然最后更新行(项目根, 账目文件相对)}"
            f"（**机器生成**；刷新区跑 `{出文档命令}`，核验跑 `{核验命令}`）")


def 生成账目块(编号: dict[str, list[str]], 行数: dict[str, int]) -> list[str]:
    行表 = [生成区.账目起 + "**（**机器生成，禁止手改**；核验 `" + 核验命令 + "`）：",
            ">", "> | 分区 | 条数 | 条目 |", "> |---|---|---|"]
    带编号和 = 0
    以项和 = 0
    行表.append(">")
    for 显示名, 键表, 以项计 in 计入待办:
        id表 = [i for 键 in 键表 for i in 编号.get(键, [])]
        if 以项计:
            数 = sum(行数.get(键, 0) for 键 in 键表)
            以项和 += 数
            条目 = "表内无编号，**以「项」计，不进编号合计**"
        else:
            数 = len(id表)
            带编号和 += 数
            条目 = " / ".join(f"#{i}" for i in id表) if id表 else "—（空）"
        行表.append(f"> | {显示名} | **{数}** | {条目} |")
    行表.append(f"> | **合计（计入待办）** | **{带编号和}** | 带编号分区之和；"
                f"另「以项计」分区共 **{以项和} 项**（无编号，不进编号合计） |")
    # 「一、待修 0」被读成「没有待办」是实测过的误读（§四 自有条目记过这条）：
    # §四/§7.8 走「以项计」、不进上一行的合计，于是机器读数说「0 条」而实际有 100+ 项。
    # 补一行把两档加起来摆在最显眼处，并在同一格里写明「0」的准确含义。
    行表.append(f"> | **可派活合计（含以项计）** | **{带编号和 + 以项和}** | "
                f"{带编号和}（带编号）+ {以项和}（以项计，§四与 §7.8 全在此）；"
                f"「一、待修 0」只说明「修法已明确到可逐条派活」那一档为空，"
                f"**不代表没有待办** |")
    五总数 = len(编号.get("五", []))
    行表.append(f"> | **全文件编号条目** | **{带编号和 + 五总数}** | {带编号和}（计入待办）+ "
                f"{五总数}（五段「已知覆盖缺口」，占编号但不计入待办） |")
    行表.append(">")
    return 行表


def 生成不计入块(编号: dict[str, list[str]], 行数: dict[str, int]) -> list[str]:
    行表 = [生成区.账目尾 + "："]
    for 显示名, 键表 in 不计入待办:
        id表 = [i for 键 in 键表 for i in 编号.get(键, [])]
        行表.append(f"> - {显示名} **{len(id表)}**"
                    f"（{' / '.join('#' + i for i in id表) or '—'}）：**不是缺陷**，"
                    "是「还没验到」或口径提示；")
    行表.append(f"> - 七之 7.7 + 7.9.5「不是缺陷（设计取舍）」**"
                f"{行数.get('7.7', 0) + 行数.get('7.9.5', 0)} 条**：**防误修清单**；")
    行表.append(f"> - 七之 7.9.4 与既有审计重复 **{行数.get('7.9.4', 0)} 条**：不重复登记，"
                "统一在跨平台那轮处置。")
    return 行表


def 出文档(项目根: Path, 文本: str) -> str:
    """产出整份文档文本：只换两个生成区，人工区逐行保留（零丢失自检）。"""
    中间 = 生成区.换元信息头(文本, 生成元信息行(项目根))
    编号, 行数 = 扫描正文(中间)
    return 生成区.换账目块(中间, 生成账目块(编号, 行数) + 生成不计入块(编号, 行数))


def 应然生成区(项目根: Path, 文本: str) -> list[str]:
    新 = 出文档(项目根, 文本)
    行表 = 新.splitlines()
    更新 = 生成区.找最后更新(行表)
    起, 末 = 生成区.找账目块(行表)
    return [行表[更新]] + 行表[起:末 + 1]


def 现行生成区(文本: str) -> list[str]:
    return [生成区.取元信息头(文本, 6)[0]] + 生成区.取账目块(文本)


def 主流程(项目根: Path, 写盘: bool, 今天: str | None = None,
           开工ID: str = "") -> tuple[int, list[str]]:
    路径 = 项目根 / 账目文件相对
    文本 = 路径.read_text(encoding="utf-8")
    应然 = 应然生成区(项目根, 文本)
    现行 = 现行生成区(文本)
    if 写盘:
        写入文件(str(路径), 出文档(项目根, 文本), 开工ID=开工ID).确保成功()
        机器印记.加印记(项目根, 账目文件相对, "债务清单", 开工ID=开工ID)
        return 0, ["生成区已按正文实数重写（人工区零丢失自检通过）；机器印记已加"] + \
                  [(行[2:] if 行.startswith("> ") else 行)
                   for 行 in 应然 if 行.startswith("> |") or 行.startswith("> 最后更新")]
    if 现行 == 应然:
        return 0, ["生成区与正文实数一致（机器生成，未漂移）"]
    差 = []
    for i in range(max(len(现行), len(应然))):
        左 = 现行[i] if i < len(现行) else "（缺行）"
        右 = 应然[i] if i < len(应然) else "（缺行）"
        if 左 != 右:
            差.append(f"  现行: {左}")
            差.append(f"  应然: {右}")
    return 1, ["**生成区与正文实数不一致** —— 跑 `--写盘` 重新生成"] + 差
