"""文档生成 · 类型动作：权威文档 / 规范 / 决策记录 / 方案 / 分析 / 交付记录。

各类型的生成区与处置按 `开发文档/规范/文档类型判据.json`；这里只放**动作实现**。

| 类型 | 生成区（只有生成器写） | 动作 |
|---|---|---|
| 权威文档 | 「最后更新」行 | 日期从 git 派生；缺元信息头则补（`口径`/`维护者` 留待填占位） |
| 规范 | 「最后更新」行 | 同上 |
| 决策记录 | 编号与骨架 | `--新建` 出骨架（编号按现存最大号 +1，不复用） |
| 方案 / 分析 / 交付记录 | 无（正文全属人工区） | 不刷、不猜，如实回报该类型的唯一生成器与核验命令 |

## 为什么权威文档不按「今天」打日期

见 `元信息头.py` 的口径：日期 = 该文件最后一次提交日；有未提交改动才取当天。
否则「内容没变日期天天变 ⇒ 每天假红」。本模块的输出可复算、可机判。
"""

