def 核验元信息头(项目根: Path, 相对: str) -> tuple[int, list[str]]:
    """核验「最后更新」行是否等于 git 派生的应然值；无元信息头按自身体例放过。"""
    路径 = 项目根 / 相对
    文本 = 路径.read_text(encoding="utf-8")
    行表 = 文本.splitlines()
    块 = 元信息头.找元信息头块(行表)
    应然 = 元信息头.应然最后更新行(项目根, 相对)
    if 块 is None:
        return 0, ["  无元信息头，按自身体例（不强加、不判红）"]
    现行 = 行表[块[0]]
    if 现行 == 应然:
        return 0, [f"  元信息头符合（{应然[2:]}）"]
    return 1, [f"  现行: {现行}", f"  应然: {应然}"]


def 写元信息头(项目根: Path, 相对: str, 允许补头: bool = False) -> tuple[int, list[str]]:
    """把「最后更新」改成 git 派生的应然值。

    **只刷已有的，不强加**（`允许补头=False`）：现场 16 份规范里只有 4 份有元信息头，
    其余 12 份按自身体例写（体例规范 §3.0 第 4 条：不要求，但也不得发明第二种）。
    生成器擅自补头 = 替人发明格式，会被当噪声；要补头须显式 `--补头`。
    """
    路径 = 项目根 / 相对
    文本 = 路径.read_text(encoding="utf-8")
    行表 = 文本.splitlines()
    应然 = 元信息头.应然最后更新行(项目根, 相对)
    块 = 元信息头.找元信息头块(行表)
    if 块 is None:
        if not 允许补头:
            return 0, [f"  无元信息头，按自身体例（不强加）"]
        位 = 元信息头.插入位置(行表)
        新表 = 行表[:位] + [应然, 元信息头.待填口径, 元信息头.待填维护者, ""] + 行表[位:]
        写入文件(str(路径),
               "\n".join(新表) + ("\n" if 文本.endswith("\n") else "")).确保成功()
        return 0, [f"  已补元信息头：{应然[2:]}", "  `口径`/`维护者` 两行留待填（属人工区）"]
    if 行表[块[0]] == 应然:
        return 0, [f"  元信息头无需改动（{应然[2:]}）"]
    行表[块[0]] = 应然
    写入文件(str(路径),
           "\n".join(行表) + ("\n" if 文本.endswith("\n") else "")).确保成功()
    return 0, [f"  已改：{应然[2:]}"]


# ── 决策记录：出骨架 ─────────────────────────────────────────────────────────

def 系统日期() -> str:
    import datetime
    return datetime.date.today().isoformat()


def 下一个决策编号(项目根: Path) -> str:
    """按现存最大号 +1；跳号合法但**不复用**（缺号即从未存在过）。"""
    最大 = 0
    for 路径 in (项目根 / 决策记录目录).glob("*.md"):
        m = 决策编号.match(路径.name)
        if m:
            最大 = max(最大, int(m.group(1)))
    return f"{最大 + 1:04d}"


决策记录模板相对 = "开发文档/决策记录/模板.md"


def 读决策模板(项目根: Path) -> list[str]:
    """读权威模板行；模板不存在即 fail-closed（不许代码里再抄一份格式）。"""
    路径 = 项目根 / 决策记录模板相对
    if not 路径.is_file():
        raise 生成区.边界缺失(f"决策记录模板不存在：{决策记录模板相对}（格式唯一源）")
    return 路径.read_text(encoding="utf-8").splitlines()


def 由模板出骨架(项目根: Path, 编号: str, 标题: str, 日期: str) -> list[str]:
    """把模板变成新骨架：只换标题行、去掉「复制说明」块、变更记录首行换成新日期。

    这样 **格式只有模板一份**：模板改了骨架自动跟着改，不会出现代码里另一套章节
    （哲学 1.2：不留第二套；「两边都归一」）。
    """
    行表 = 读决策模板(项目根)
    行表[0] = f"# {编号} {标题.strip()}"
    # 去掉模板首部「> 复制本文件为…」的说明块（那是给复制者的指引，不是文档内容）
    去: list[int] = []
    for i, 行 in enumerate(行表):
        if i and 行.startswith(">"):
            去.append(i)
        elif i and 行.strip() and not 行.startswith(">"):
            break
    行表 = [行 for i, 行 in enumerate(行表) if i not in 去]
    # 去掉说明块后会留下连续空行，归一为单空行（否则 H1 后出现双空行）
    归: list[str] = []
    for 行 in 行表:
        if 行 == "" and 归 and 归[-1] == "":
            continue
        归.append(行)
    行表 = 归
    # 变更记录首行改成「今天 / 草稿 / 建立」
    for i, 行 in enumerate(行表):
        if 行.startswith("|") and "| 现行 |" in 行:
            行表[i] = f"| {日期} | 草稿 | 建立 |"
            break
    return 行表


def 出决策骨架(项目根: Path, 标题: str, 日期: str) -> tuple[int, list[str]]:
    """出骨架：章节**从既有权威模板派生**（模板是格式唯一源，代码不抄第二份）。

    现场（2026-09-20 实测 57 份）：决策记录存在**两派并存** ——
    模板派 `## 背景 / ## 决策 / ## 考虑过的其他做法 / ## 后果 / ## 验证方式 / ## 变更记录`
    （各 16–19 份），与序号派 `## 一、背景 / ## 一、决策 / …`（各 3–5 份）。
    一个目录两套骨架正是「两边没归一」的例子 ⇒ 此后一律以模板派为准，序号派不再新增。
    """
    if not 标题 or not 标题.strip():
        return 2, ["  出骨架需要 `--标题`（例：--标题 统一生成器收口）"]
    编号 = 下一个决策编号(项目根)
    文件名 = f"{编号}_{标题.strip()}.md"
    路径 = 项目根 / 决策记录目录 / 文件名
    if 路径.exists():
        return 2, [f"  目标已存在，不覆盖：{文件名}"]
    骨架 = 由模板出骨架(项目根, 编号, 标题, 日期)
    写入文件(str(路径), "\n".join(骨架) + "\n").确保成功()
    return 0, [f"  已出骨架：{决策记录目录}/{文件名}"
              f"（编号按最大号 +1；章节从 `{决策记录模板相对}` 派生，格式只有一份）"]
