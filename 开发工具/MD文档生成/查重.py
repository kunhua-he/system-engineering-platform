"""文档生成 · 查重：落盘前判断「这内容是不是已经在别处写过了」。

华哥 2026-09-20 口径（原文）：

> 「有没有办法这个生成器，可以排查相似性？就是尽量写的时候，可以判断一下，
>   有没有重复的落盘了。**不然就变成了这里写一下，那里写一下，变成了文案都几条腿来。**」

## 为什么必须是「生成器自带」而不是另做一个工具

华哥要的是**写的时候就判**（落盘前拦一下），不是事后审计。所以它长在生成器里：
`--查重`（核验形态）与 `--新建 --查重`（出骨架前先查）。

## 判据怎么算（两级，先粗筛再精算）

1. **粗筛（便宜）**：把每份 md 归一化（去围栏、去空白、取字符 3-gram 集合），
   按 **Jaccard 相似度** 算粗略重合度，取前 N 名 —— 这一步避免 500×500 全量精算。
2. **精算（准）**：对短名单用 `difflib.SequenceMatcher` 算**文本相似比**（std 库，
   与本仓 `开发工具/MD文档生成/说明书/合并重生成.py` 同一实现血统，不引第三方）。

**阈值是判据不是结论**：默认报 `≥0.40` 的（够像了才提醒），`≥0.70` 标为「高度疑似重复」。
阈值可由 `--阈值` 覆盖 —— 因为「该不该合并」最终是人的判断，机器只负责**把候选摆到面前**。

## 射程（哪些件**退出比对**）

**「空骨架」件退出比对** —— 空骨架 = **机器管理**（有机器印记）且**人工区尚未填写**
（除 H1 标题行、引用块、印记行、空行外没有任何其它行）的件。它**没有任何人工内容**，
拿它去比只能量出**模板**：构造性的、零信息量。

为什么（2026-09-24 实测定性）：`支持库/后端/办公文档支持库/文字文档/说明/设计说明.md`
一文件曾命中 **68 对**（多数 ★0.99），对手**全部**是别的 `设计说明.md`，逐字比对两份
⇒ **7 行里只差机器印记那一行**。真根因：149 份 `设计说明.md` 里 **63 份正文行数为 0**
（#187 清掉「使用说明骨架」误装内容后的残留空壳，正文缺失属 #187 同族）。

**为什么是「退出」而不是「只堵骨架×骨架」**（2026-09-24 实测后收窄，原文口径在此修正）：
只堵「骨架 × 骨架」后复跑，该件仍余 **7 对**（0.50–0.78），对手是**只写了两三行的短人工件**
（如 `支持库/前端/桌面宿主/说明/设计说明.md` 11 行、正文 2 行）。那 7 对的相似**分子全部是模板头**
（H1 + 引用块 + 印记），人工内容一个字都没重合 ⇒ 同属假红。即：
**「人工区件 vs 空骨架」这一对在任何阈值下都只能量出模板**（空骨架没有内容可重合，
一方零信息时 `2M/(len1+len2)` 剩下的就是模板占比），保留它必然留下这批假红。
⇒ 射程定为：**空骨架件既不作为待查件、也不作为候选**（两处调用点都堵）。

**射程边界（不许放过真重复）**：

- **人工区件之间照旧比** —— 实测保留 `并发控制支持库` × `数据结构支持库` 的 `设计说明.md`
  （相似 0.95，56 行里 52 行逐字相同），那正是「这里写一下、那里写一下」，必须继续报；
- **人工区件 vs「整份生成物」照旧比**（`使用说明.md` / `目录树与命令.md` 等**有正文**的机器件仍在参与集合里）；
- 空骨架件**照实列出**（报「空骨架退出 N 份」），不静默丢弃。

**本条不覆盖的**（如实声明，不假装覆盖）：只填了章节标题、正文仍空的件（它有人工行 ⇒ 按非骨架参与）；
以及 `使用说明.md` / `目录树与命令.md` 这类**整份生成物**彼此之间的相似（另有存量，未收口）。

## 边界（如实声明，不包装成绝对保证）

- 它比的是**字面相似**，不做语义理解：换了说法讲同一件事（同义改写）**查不出来**；
- 反之，结构相同但内容不同的件（如同一模板出的两份**已填写**说明书）**会报高相似**——
  这类要人看一眼再决定，机器不代替裁决。

⇒ 定位：**降噪器**，不是「重复检测的绝对边界」（哲学 9.5②：不许包装成绝对边界）。
"""

from __future__ import annotations

import difflib
import re
from pathlib import Path

#: 豁免目录**不再在此另抄一份**：一律经 `机器印记.是豁免()` 读判据文件的 `豁免` 字段
#: （唯一真源）。此处保留的名字只作「名字来源」说明，实际判断走函数。
_豁免口径来源 = "开发文档/规范/文档类型判据.json 的 豁免 字段（经 机器印记.是豁免）"


def _豁免(项目根: Path, 相对: str) -> bool:
    from 开发工具.MD文档生成 import 机器印记
    return 机器印记.是豁免(项目根, 相对)


def 是空骨架(文本: str) -> bool:
    """该件是否「机器管理 + 人工区尚未填写」的空骨架。

    判据两半**都读既有唯一节点**，本文件不另立一份「哪些文件是骨架」的路径名单（哲学 1.2）：
    - 「机器管理」= `机器印记.取印记()` 有值（印记本身即登记表，写在文件里、跟着文件走）；
    - 「人工区尚未填写」= 除 H1 标题行、引用块（`>`）、印记行、空行外**没有任何其它行**。
    """
    from 开发工具.MD文档生成 import 机器印记
    行表 = 文本.splitlines()
    if 机器印记.取印记(行表) is None:
        return False
    return all(not 行.strip() or 行.startswith("# ") or 行.startswith(">")
               or 机器印记.印记正则.match(行) for 行 in 行表)


#: 默认阈值：报告这些以上的候选
默认报告阈值 = 0.40
#: 高度疑似重复
默认高度阈值 = 0.70

围栏 = re.compile(r"^\s*(```|~~~)")
非内容 = re.compile(r"[\s，。、；：！？（）「」『』【】《》…—·\-—_*|>#`\[\]()\"'=+:,.!?;/\\]+")


def 归一文本(文本: str) -> str:
    """去掉代码围栏内的内容与全部标点空白，只留「说了什么」的字符骨架。"""
    行表: list[str] = []
    在内 = False
    for 行 in 文本.splitlines():
        if 围栏.match(行):
            在内 = not 在内
            continue
        if 在内:
            continue
        行表.append(行)
    return 非内容.sub("", "\n".join(行表))


def 切片集合(归一: str, 宽: int = 3) -> set[str]:
    return {归一[i:i + 宽] for i in range(0, max(0, len(归一) - 宽 + 1))}


def 粗相似(集合一: set[str], 集合二: set[str]) -> float:
    if not 集合一 or not 集合二:
        return 0.0
    交 = len(集合一 & 集合二)
    return 交 / (len(集合一) + len(集合二) - 交)


def 精相似(文本一: str, 文本二: str) -> float:
    return difflib.SequenceMatcher(None, 文本一, 文本二).ratio()


class 库:
    """全仓 md 的查重索引（构造时读一遍，之后反复查）。"""

    def __init__(self, 项目根: Path, 排除: str | None = None):
        self.项目根 = 项目根
        self.条目: list[tuple[str, str, set[str]]] = []      # (相对路径, 归一文本, 3-gram 集合)
        #: 退出比对的空骨架件（相对路径，见模块 docstring「射程」）。
        #: 留着是为了**照实报出**「空骨架退出 N 份」（不静默丢弃），不是为了参与比对。
        self.空骨架: list[str] = []
        本轮根 = 项目根
        # 扫描面**与 `类型登记.枚举文件` 同一条腿**（本文件 2026-09-21 才补上）：同一根因
        # 2026-09-20 已在 `类型登记` 修过（那边留了实测记录），**那次漏了这里**。
        # 原实现 `项目根.rglob("*.md")` 在**过滤之前**走完整仓，而本仓 md 约 1.8 万份在
        # `工程缓存/`（生成物，判据文件里本就 `豁免`）⇒ 每次都白走一遍再丢掉。
        # 剪掉的正是 `豁免` 那三项 ⇒ **参与者集合不变**，只是不再白走
        # （哲学 1.2：同一件事不留第二套做法）。
        from 开发工具.MD文档生成 import 类型登记
        for 路径 in 类型登记.带剪枝遍历md(项目根):
            相对 = 路径.relative_to(项目根).as_posix()
            if _豁免(本轮根, 相对):
                continue
            if 排除 and 相对 == 排除:
                continue
            try:
                文本 = 路径.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            归一 = 归一文本(文本)
            if len(归一) < 50:                              # 太短的（占位/索引）不参与
                continue
            if 是空骨架(文本):                                # 射程：零人工内容 ⇒ 退出比对
                self.空骨架.append(相对)
                continue
            self.条目.append((相对, 归一, 切片集合(归一)))

    def 查(self, 待查文本: str, 取前: int = 5) -> list[tuple[str, float]]:
        """返回 [(相对路径, 相似度)] 降序；两级算法（先 Jaccard 粗筛，再 difflib 精算）。

        待查件自己是**空骨架**时直接回空表（射程：零人工内容 ⇒ 退出比对，见模块 docstring）。
        """
        if 是空骨架(待查文本):
            return []
        待归一 = 归一文本(待查文本)
        if len(待归一) < 50:
            return []
        待集 = 切片集合(待归一)
        # ① 粗筛：按 Jaccard 取前 待前 名（至少 12 个，避免精算漏掉）
        粗 = sorted(((粗相似(待集, 集), 相对) for 相对, _, 集 in self.条目),
                   reverse=True)[:max(12, 取前)]
        # ② 精算：对粗筛出的做 SequenceMatcher
        精 = [(相对, 精相似(待归一, self._归一(相对))) for _, 相对 in 粗]
        return sorted(精, key=lambda x: -x[1])[:取前]

    def _归一(self, 相对: str) -> str:
        for 路径, 归一, _ in self.条目:
            if 路径 == 相对:
                return 归一
        return ""


def 查文件(项目根: Path, 相对: str, 取前: int = 5) -> list[tuple[str, float]]:
    """查一份**已存在**的文件与其他文件的相似度（自身排除；射程同 `库.查`）。"""
    路径 = 项目根 / 相对
    文本 = 路径.read_text(encoding="utf-8")
    return 库(项目根, 排除=相对).查(文本, 取前=取前)
