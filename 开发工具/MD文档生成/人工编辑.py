def 查生成区(项目根: Path, 相对: str, 类型名: str, 草稿: str) -> tuple[bool, list[str]]:
    """该类型的生成区是否仍是「生成器算出来的那份」。返回 `(是否通过, 说明行)`。

    **逐类型接各自既有的判据，不另造一套**：各类型的生成区形态本来就不同 ——
    债务清单是「从头算出一份应然值」（`应然生成区` / `现行生成区`），
    目录树与命令是「只删不补不排」（`漂移条目` 报出与同包摘要对不上的树条目）。
    在没登记判据的类型上如实回报「无可算生成区」，不假装校验过（那是假绿）。
    """
    from 开发工具.MD文档生成 import 文档类型_债务清单, 文档类型_目录树与命令

    if 类型名 == "债务清单":
        try:
            应然 = 文档类型_债务清单.应然生成区(项目根, 草稿)
        except (OSError, ValueError) as 错误:
            return 假, [f"生成区实算失败（{类型名}）：{错误}"]
        实得 = 文档类型_债务清单.现行生成区(草稿)
        if 实得 != 应然:
            差 = [f"  草稿 - 应然: {x}" for x in 实得 if x not in 应然][:5]
            差 += [f"  应然 - 草稿: {x}" for x in 应然 if x not in 实得][:5]
            return 假, [f"**生成区被人工改动，拒绝落盘**（{类型名}：{相对}）",
                           f"  {类型名} 的生成区由生成器专管，人工只改人工区。差异：", *差,
                           "  处置：把草稿里的生成区恢复为生成器算出的值"
                           "（`--类型 债务清单 --写盘` 可重算），只保留人工区的改动"]
        return 真, [f"  生成区校验通过（{类型名}，{len(应然)} 行由生成器专管）"]

    if 类型名 == "包级说明-目录树与命令":
        # 该类型的生成区 = 「树块里对不上同包 完整性摘要.json 的条目」；有漂移即说明
        # 草稿里的树块混进了不属于摘要清单的条目（那是生成器该删的，不是人该留的）。
        漂移 = 文档类型_目录树与命令.漂移条目(项目根, 相对)
        if 漂移:
            return 假, [f"**生成区（目录树块）含生成器将删除的条目，拒绝落盘**：{相对}",
                           *[f"  {x}" for x in 漂移[:8]],
                           "  处置：删掉这些条目（它们不在同包 `完整性摘要.json` 里），"
                           "或先改摘要；树块的「选择」属人工区，但「树有摘要无」必须由生成器删"]
        return 真, ["  生成区校验通过（包级说明-目录树与命令：树块与同包摘要一致）"]

    return 真, [f"  该类型无可算生成区（{类型名}），只做类型判据与印记校验："
                  f"{'（整份人工区）'}"]


def 归一相对路径(项目根: Path, 目标: str) -> str:
    """把 `--文件` 归一成**项目根相对路径**；算不出来返回空串（调用方 fail-closed 拒绝）。

    为什么非归一不可（2026-09-23 实测活体缺陷：本通道的**生成区保护被静默跳过**）：
    `类型登记.命中类型` 是 `fnmatch` 按**相对路径**匹配 `路径判据`，而 `项目文档.人工改文档`
    这条能力把 目标文件 传成**绝对路径**（其 `能力定义.json` 的返回契约也写「目标文档绝对路径」）
    ⇒ 绝对路径匹配不上任何 `路径判据`，只剩兜底 `**/*.md`（`仓库内其他文档`）⇒ `查生成区`
    落进「该类型无可算生成区（整份人工区）」那一支，**生成区一行都不校验**。
    实测现场：`开发文档/未完成事项.md` 走能力通道落盘后，22 行生成区（元信息头 + 顶部账目块）
    无人校验，机器印记还被改成 `仓库内其他文档`。

    这不是「通道不通」，是「通道把门悄悄打开了」—— 比不通更坏：不通会被看见，静默降级不会。
    归一放在生成器这一侧（而不是只改调用方）：生成器是**唯一腿**，CLI 调用方同样会传绝对路径；
    且本文件每次生成器运行都是**新进程**，改完当场生效，不依赖热接入/重启。
    """
    try:
        候选 = Path(目标)
        绝对 = (候选 if 候选.is_absolute() else 项目根 / 候选).resolve()
        根 = 项目根.resolve()
    except OSError:
        return ""
    try:
        return 绝对.relative_to(根).as_posix()
    except ValueError:
        return ""


def 落盘人工正文(项目根: Path, 目标: str, 新正文: str, *, 写盘: bool) -> tuple[int, list[str]]:
    """人工正文的唯一落盘通道。返回 `(退出码, 说明行)`；0=通过（或已写盘），2=拒绝。"""
    行表: list[str] = []

    # ⓪ 归一：判据按项目根相对路径匹配（绝对路径会落进兜底类名 ⇒ 生成区保护失效）
    相对 = 归一相对路径(项目根, 目标)
    if not 相对:
        return 2, [f"目标路径不在项目根内（或不可解析）：{目标}",
                   "  处置：`--文件` 传项目根内的相对路径（如 开发文档/未完成事项.md）"
                   "或本仓库内的绝对路径；仓库外路径本通道不受理"]

    # ① 类型判据：这份文件必须在生成器管下（不在管辖内 ⇒ 先登记类型，不允许经此通道偷偷写）
    类型 = 类型登记.命中类型(项目根, 相对)
    if 类型 is None:
        return 2, [f"该路径不在任何文档类型判据下：{相对}",
                   "  处置：先在 `开发文档/规范/文档类型判据.json` 登记该类型（一处数据），再经生成器写"]
    类型名 = str(类型.get("类型"))

    # ② 生成区保护
    过, 行 = 查生成区(项目根, 相对, 类型名, 新正文)
    if not 过:
        return 2, 行
    行表.extend(行)

    # ③ 印记：落盘必带（否则编译口「拒绝手写md」当场判红）
    带印记 = "机器管理" in 新正文[:600]
    if not 带印记:
        行表.append("  草稿无机器印记 ⇒ 落盘时自动补（印记是「归生成器管」的声明，不占人工正文）")

    if not 写盘:
        行表.append(f"  干跑通过：加 `--写盘` 即写入 {相对}（人工正文 {len(新正文.splitlines())} 行）")
        return 0, 行表

    # ④ 落盘：先写正文，再经既有印记原语补印记（单一事实源，不另造一套插入逻辑）
    写入文件(str(项目根 / 相对), 新正文).确保成功()
    码, 印记行 = 机器印记.加印记(项目根, 相对, 类型名)
    if 码 != 0:
        return 码, [*行表, *印记行]
    行表.extend(印记行)
    行表.append(f"  ✓ 已落盘 {相对}（人工正文经生成器写入）")
    return 0, 行表


def 入口(argv: list[str] | None = None) -> int:
    """CLI：`--人工改 --文件 <目标> --正文文件 <草稿> [--写盘]`（缺失参数一律拒绝，退 2）。"""
    参数 = list(sys.argv[1:] if argv is None else argv)
    项目根 = Path(__file__).resolve()
    while 项目根.name and not (项目根 / "开发文档").is_dir():
        项目根 = 项目根.parent
    if not (项目根 / "开发文档").is_dir():
        print("找不到项目根（向上找不到含 开发文档/ 的目录）")
        return 2
    目标 = _取值(参数, "--文件")
    草稿 = _取值(参数, "--正文文件")
    if not 目标 or not 草稿:
        print("用法：--人工改 --文件 <目标路径> --正文文件 <草稿路径> [--写盘]")
        return 2
    草稿路径 = Path(草稿) if Path(草稿).is_absolute() else 项目根 / 草稿
    if not 草稿路径.is_file():
        print(f"草稿文件不存在：{草稿路径}")
        return 2
    新正文 = 草稿路径.read_text(encoding="utf-8")
    码, 行 = 落盘人工正文(项目根, 目标, 新正文, 写盘="--写盘" in 参数)
    print(f"MD 文档生成 · 人工编辑（{目标}）")
    for x in 行:
        print(x)
    return 码


def _取值(参数: list[str], 开关: str) -> str:
    位 = 参数.index(开关) if 开关 in 参数 else -1
    return 参数[位 + 1] if 0 <= 位 < len(参数) - 1 else ""
