"""文档生成 · 人工改动的**唯一落盘通道**（人提供正文，生成器负责校验与写入）。

## 为什么必须有这一层

华哥 2026-09-20 口径（原文）：

> 「**全部 md 文件，都需要通过生成器去写。生成器本质上是规范写东西的方式。而不是 0 人工参与。**」
> 「**人工参与，只是禁止直接写，可以通过生成器写**」

⇒ 「禁手写」约束的是**写入通道**，不是「人不许参与」。缺了下面这件事，口径就是空的：
**人要改 md 的正文（人工区内容）时，手上没有任何合法通道** —— 要么违反口径直接 `write_text`，
要么放弃修改。本项目实测踩过：一次目录改名（`开发工具/说明书生成/` → `开发工具/MD文档生成/说明书/`）
需要同步改 9 份 md 里的路径引用，全部只能直接 `write_text`，**当场违反了同一天刚定的口径**。

本模块就是那条通道：人把新正文交给它，由它完成
「**类型判据校验 → 生成区保护 → 加机器印记 → 落盘**」四步，人不需要（也不允许）自己动文件。

## 生成区保护（本层唯一的技术价值，不是把 write_text 包一层）

「生成区只有生成器能写」（体例规范 §3.2）必须在**人工改正文**这条路径上同样成立，
否则人可以从这里顺手把生成器算出来的生成区改掉 —— 那就是绕过生成器。
故落盘前把「草稿里的生成区」与「生成器现在算出来的生成区」逐行比对，不一致即 **fail-closed 拒绝**，
并明确指出该类型的生成区归谁管。

**没有可算生成区的类型**（如 `包级说明-设计说明`：整份是人工区）只做类型判据 + 印记两步 ——
这是如实处置，不是放宽：那类文件本来就没有「生成器算出来的东西」可保护。

## 用法

```bash
# 人先在草稿文件里写好新正文，再交给生成器落盘（人从不直接写目标文件）
python3.14 -m 开发工具.MD文档生成 --人工改 --文件 <目标路径> --正文文件 <草稿路径> [--写盘]
```

缺 `--写盘` 时只做全部校验并报结论（干跑），确认无误再加 `--写盘` 落盘。
"""

