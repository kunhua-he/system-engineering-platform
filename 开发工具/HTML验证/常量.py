#: 场景腿的**合成写入凭证**（`开工ID` 参数名与取值，唯一一份定义）。
#:
#: ## 为什么场景腿必须自带凭证（2026-09-25 底座权限面收口）
#:
#: 写入腿的判据已从「路径级」升级成「调用方级」：`公共契约/运行时/写入授权.校验写入授权`
#: 要求受管路径的活跃写租约 `所有者 == 调用方传进来的 开工ID`，**空即拒**。各写腿
#: （`文件操作` / `文本补丁` / `项目文档` / `直播逐字稿` …）的能力契约里因此都有
#: `开工ID`，且标成 **`必填=true`**。
#:
#: 而 `必填` 校验发生在**写盘之前、也发生在豁免判定之前**
#: （`运行核心/统一网关/协议/类型规格.校验能力参数`，经 `唯一能力调用` 与
#: `网关参数校验面._能力参数错误` 在派发前转调）⇒ 缺键的请求当场回
#: `参数不合法：… 缺少必填参数 开工ID`，**连落点全在豁免前缀 `工程缓存/` 的步骤
#: 也过不去**（豁免只对 `校验写入授权` 有效，管不到必填校验）。
#:
#: ## 为什么合成凭证不削弱判据
#:
#: 本值**不是一个真实开工ID**，因此它**不可能拥有任何文件租约**
#: （租约所有者由 `开工编排.开工即占` 现场生成并登记）。于是：
#:
#:   · 目标落点**受管**（仓库内、非豁免）⇒ 所有者比对必然不等 ⇒ 照旧 `越界` 拒绝；
#:   · 目标落点**非受管**（豁免前缀 `工程缓存/`、仓库外、平台自管生成物/临时资源）
#:     ⇒ `校验写入授权` 本就没有话说 ⇒ 放行。
#:
#: 这正是验证腿**应有的权限水位**：只够碰自己的受管临时区，碰不到任何 agent 的事实源
#: 文件。判据本体（`写入授权.py`）一个字不改。
#:
#: ## 补位口径
#:
#: 只在场景 `参数` **没有** `开工ID` 键时补（`setdefault` 语义）：场景自己给了凭证
#: （如 `模块库/项目文档/验证场景/*.json` 的 `开工-验证场景-项目文档`）就原样送出，
#: 不覆盖。**唯一注入点**是 `开发工具/HTML验证/HTTP请求.py::_单次请求` —— 场景腿
#: 的每一条 HTTP 请求都经它构造请求体（多步走 `场景执行器._执行场景束`，单步走
#: `单实例验证` → `返回判定.验证单个`），故本常量在此定义、只在那处使用。
