#: 本守卫**拒绝**的判据码集合 —— 取自唯一判据节点 `校验相对路径文本` 的**结构化读数**
#: `判据`（哲学 14.4：文案给人看，错误码给机器判），与 决策记录 0016 写明的守卫判据集合
#: 逐条对应：**绝对写法（含盘符）+ `..` 段跳转**。
#: `家目录写法`/`当前目录`/`点段` **必须放行**（0016 既定口径：`~` 越界用例留给运行期硬失败取证）。
#:
#: ★ 2026-09-24（未完成事项 §四 · 批H-H5）：此前这里放的是三条**原因文案串**常量，判据靠
#: `拒绝原因 in (…)` 比对 —— 文案一改判据就静默失效（14.4 反面）；且 2026-09-24 批H 裁-A
#: 把判据转调唯一节点时，写成 `if not 文本判定.成功 or 拒绝原因 in (…)`，
#: 于是节点对**非路径文本**回的 `失败("参数不合法")`（空串/空白串）也被当成「越界写法」，
#: 全仓 **24 个包**的负向用例（「空参数被拒」这类）在验证场景体检里整包报红。
#: 故本批把判据收成两件互不重叠的东西，**两件都住唯一腿**：
#: · **射程**（要不要问节点）= `支持库.后端.系统核心支持库.路径安全.像路径写法文本`；
#: · **判据码**（节点答什么）= `校验相对路径文本` 的 `判据` 键。
#: 本文件不再出现任何原因文案串，也不再自写任何路径形态判定。
守卫拒绝判据码 = frozenset({判据码_绝对写法, 判据码_段跳转})


def _解码URL一次(文本: str) -> str:
    """URL 解码归一化（未完成事项 §四「路径边界有 5 份实现、口径互不一致」，2026-09-23）：**只解一次，绝不解两遍**。

    二次解码本身就是漏洞：`%252e%252e` 解一次得 `%2e%2e`、再解一次就是 `..`。故本函数
    只接受**原始入参**；任何调用点都不得把已解码结果再送进来。
    """
    return unquote(文本)


def _安全合并路径(根: Path, 相对: str, 名称: str) -> Path:
    if not isinstance(相对, str) or not 相对:
        raise ValueError(f"{名称}路径不合法: {相对!r}")
    # URL 解码归一化（未完成事项 §四「路径边界有 5 份实现、口径互不一致」）：所有判据之前先 unquote，且只解一次。
    # 此前 `..%2f逃逸` 不解码时只是一个普通目录名（`resolve()` 追不出越界）⇒ 编码穿越全放行。
    原文 = 相对
    相对 = _解码URL一次(相对)
    if not 相对:
        raise ValueError(f"{名称}路径不合法: {相对!r}")
    # ★ 2026-09-24（批H 裁-A 收口）：此处原有的自写判据（`Path` 自带的绝对判定 + 盘符正则）
    # **全删**，绝对写法（含盘符）一律由下方**唯一判据节点** `系统核心支持库.路径安全.
    # 校验相对路径文本` 一条判完。绝对写法输入改由 resolve 后的 `relative_to` 分支拦下
    # （消息「越出包目录或受管目录」，与 `..` 跳转走同一条硬失败分支；
    # `测试_HTML验证器` 钉的就是这条消息）。
    # 拼根走唯一节点 `平台适配.解析路径`（相对 → 按生效根拼绝对）。唯一节点对 `~`
    # 做家目录展开：`~未知用户` 展开失败时它抛 `RuntimeError`，本函数对外只吐
    # `ValueError`（边界翻译，不让新异常型漏到 HTTP 面）。
    try:
        路径 = 解析路径(相对, 根)
    except RuntimeError as 错误:
        raise ValueError(f"{名称}路径逃逸: {相对!r}") from 错误
    if not isinstance(路径, Path):
        raise ValueError(f"{名称}路径不合法: {相对!r}")
    路径 = 路径.resolve()
    try:
        路径.relative_to(根.resolve())
    except ValueError as 错误:
        raise ValueError(f"{名称}越出包目录或受管目录: {相对}") from 错误
    # 解码后的 `..` 段直接拒（#106）：本函数原有判据是「`resolve()` 后仍在根内即放行」，
    # 而 `a/..%2f/b` 解码后是 `a/../b` —— 它**恰好落在根内**，光靠 resolve 追不出来，
    # `..%2f` 就此整段绕过。编码穿越要真被拦住，必须在解码后的**字面段**上判
    # （段切分口径与 系统核心支持库.路径安全.校验路径 一致：只按 `/` 切）。
    # 放在 resolve 判据**之后**：越出根的那种仍走既有的「越出包目录或受管目录」分支，
    # 消息与旧行为逐字不变（`测试_HTML验证器` 的 `assertRaisesRegex(..., "越出包目录")` 钉着它）。
    # 收口（2026-09-23 S4·T3）：字面段判据不再自己写，一律转调唯一节点
    # `系统核心支持库.路径安全.校验相对路径文本`（`..` 段/段内 `.`/盘符/`~` 全由它判）。
    # 放在 resolve 判据**之后**：越出根的那种仍走上面的「越出包目录或受管目录」分支，
    # 消息与旧行为逐字不变（`测试_HTML验证器` 的 `assertRaisesRegex(..., "越出包目录")` 钉着它）。
    文本判定 = 校验相对路径文本(原文)
    判定值 = 文本判定.值 if isinstance(文本判定.值, dict) else {}
    if not 文本判定.成功 or not 判定值.get("通过"):
        raise ValueError(f"{名称}路径逃逸: {相对!r}")
    return 路径

def _校验动态声明(值: Any, 场景id: str, 已出现步骤: set[str]) -> None:
    if isinstance(值, list):
        for 项 in 值:
            _校验动态声明(项, 场景id, 已出现步骤)
        return
    if not isinstance(值, dict):
        # 有意设计，不放宽：场景不得依赖作者本机的真实路径，也不得真的越界写。
        # 越界用例的写法口径见 `开发文档/决策记录/0016_验证场景越界用例口径.md`：
        # 用「写法上越界但字面不含 `..`、也非绝对路径」的方式触发（如 `~` 家目录写法）；
        # `..` 跳转型越界由定向 unittest + 真实网关调用取证，不进 HTML 黑盒矩阵。
        射程 = 像路径写法文本(值) if isinstance(值, str) else None
        射程值 = 射程.值 if (射程 is not None and isinstance(射程.值, dict)) else {}
        if 射程值.get("是路径写法"):
            # 判据一律转调**唯一判据节点** `系统核心支持库.路径安全.校验相对路径文本`
            # （2026-09-24 批H 裁-A 收口：原自写的 `Path` 绝对判定 + 盘符正则 + `..` 段
            # 三条判据全删）。传**原始入参**：节点自己 URL 解码一次
            # （`..%2f逃逸` / `%2e%2e/x` 靠它挡，见 #106）。
            # **本守卫只认 0016 明文的两条**（绝对写法含盘符、`..` 段）：`~` 家目录写法与
            # `.` 段**必须放行** —— `平台控制面/能力目录/验证场景/文件租约.json` 的
            # 「越界路径必须硬失败」用例正是用 `~/平台控制面/能力目录/服务.py` 在**运行期**
            # 硬失败并断言「家目录写法」，静态守卫不得抢先拦下（决策记录 0016 既定口径）。
            # **射程**（要不要问节点）也收口到唯一腿：`像路径写法文本` 与写法判据同住
            # `支持库/后端/系统核心支持库/路径安全`（此前写成调用方的 `_像路径写法`，
            # 被 `开发工具/验证门禁/同动作双路径检测.py` 规则七**正确判红**：
            # 「名字含路径 + 段里含 `..`」= 同职责路径判定的第二份实现）。
            # **判据读结构化判据码**（`判据` 键），不比对 `原因` 文案（哲学 14.4）：
            # 节点回 `失败`（空串/空白串 = 不是路径文本）时**没有判据码** ⇒ 天然不拒。
            文本判定 = 校验相对路径文本(值)
            判定值 = 文本判定.值 if isinstance(文本判定.值, dict) else {}
            if 判定值.get("判据") in 守卫拒绝判据码:
                raise ValueError(f"场景 {场景id} 禁止静态绝对路径或路径逃逸")
        return
    if "$动态" not in 值:
        for 项 in 值.values():
            _校验动态声明(项, 场景id, 已出现步骤)
        return
    类型 = 值.get("$动态")
    允许字段 = {
        "制品根": {"$动态", "相对路径"},
        "受管临时目录": {"$动态", "相对路径"},
        "受管临时路径": {"$动态", "相对路径"},
        "夹具文件复制": {"$动态", "来源", "目标"},
        "步骤返回": {"$动态", "步骤id", "JSON路径"},
        "环境变量": {"$动态", "名称"},
    }
    if 类型 not in 允许字段 or set(值) != 允许字段[类型]:
        raise ValueError(f"场景 {场景id} 动态值声明不合法: {类型!r}")
    if 类型 == "步骤返回":
        if 值.get("步骤id") not in 已出现步骤 or not isinstance(值.get("JSON路径"), str):
            raise ValueError(f"场景 {场景id} 动态引用缺失或不是前序步骤: {值.get('步骤id')}")
    else:
        for 字段 in 允许字段[类型] - {"$动态"}:
            if not isinstance(值.get(字段), str) or not 值[字段]:
                raise ValueError(f"场景 {场景id} 动态路径字段不合法: {字段}")
