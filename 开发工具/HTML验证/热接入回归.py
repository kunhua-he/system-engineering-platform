"""热接入真实 HTTP 回归：新增 / 变更 / 包内删能力 / 整包删除 / 失败包 / 并发。

对真实 40007 网关发公开 HTTP 请求，全部通过 GET/POST 黑盒验收，不测内部函数。
演练包在测试期间存在于正式支持库目录下，测试结束（含异常路径）必须删除并热接入卸载，
保证正式能力目录零残留。

用法：
    unset PYTHONPATH && python3.14 开发工具/HTML验证/热接入回归.py
"""

from __future__ import annotations

import json
import shutil
import sys
import threading
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
网关地址 = "http://127.0.0.1:40007"
凭证头 = {"Authorization": "Bearer html-blackbox-verifier"}
演练包id = "支持库.后端.热接入演练支持库"
演练包目录 = 系统根 / "支持库" / "后端" / "热接入演练支持库"
能力id_加法 = "热接入演练支持库.演练加法"
能力id_心跳 = "热接入演练支持库.演练心跳"


def 请求(路径: str, 方法: str = "GET", 数据: dict | None = None, 超时: float = 20):
    正文 = None if 数据 is None else json.dumps(数据, ensure_ascii=False).encode("utf-8")
    地址 = 网关地址 + urllib.parse.quote(路径, safe="/")
    请求对象 = urllib.request.Request(
        地址, data=正文, headers=凭证头 | {"Content-Type": "application/json"},
        method=方法,
    )
    try:
        with urllib.request.urlopen(请求对象, timeout=超时) as 响应:
            return 响应.status, json.loads(响应.read().decode("utf-8"))
    except urllib.error.HTTPError as 错误:
        return 错误.code, json.loads(错误.read().decode("utf-8"))


def 健康():
    状态码, 数据 = 请求("/健康")
    assert 状态码 == 200, f"健康探针失败: {状态码}"
    assert 数据["成功"] is True, f"健康返回失败: {数据}"
    return 数据["值"]["能力数"]


def 调用能力(能力id: str, 参数: dict | None = None):
    状态码, 数据 = 请求("/网关/调用", "POST", {"能力id": 能力id, "参数": 参数 or {}})
    return 状态码, 数据


def 热接入():
    状态码, 数据 = 请求("/网关/热接入", "POST", {})
    return 状态码, 数据


def 写文件(相对: str, 内容: str):
    (演练包目录 / 相对).parent.mkdir(parents=True, exist_ok=True)
    (演练包目录 / 相对).write_text(内容, encoding="utf-8")


def 创建演练包(版本: str = "v1", 带心跳: bool = True):
    实现 = f'''
"""热接入演练支持库实现。"""
from __future__ import annotations

def 演练加法(*, 左数: int = 1, 右数: int = 2) -> 结果:
    """演练：返回加法结果与版本。"""
    from 公共契约.基础类型.结果类型 import 结果
    return 结果.成功结果({{"和": 左数 + 右数, "版本": "{版本}"}})

def 演练心跳(*, 名称: str = "默认") -> 结果:
    """演练：返回心跳计数。"""
    from 公共契约.基础类型.结果类型 import 结果
    return 结果.成功结果({{"名称": 名称, "版本": "{版本}"}})
'''
    写文件("实现/热接入演练.py", 实现)

    导入行 = "from 支持库.后端.热接入演练支持库.实现.热接入演练 import 演练加法"
    注册行 = '''
        ("热接入演练支持库.演练加法", 演练加法, [
            {"名称": "左数", "类型": "整数型", "必填": False, "默认值": 1, "说明": "左数"},
            {"名称": "右数", "类型": "整数型", "必填": False, "默认值": 2, "说明": "右数"},
        ]),
'''
    if 带心跳:
        导入行 += "\nfrom 支持库.后端.热接入演练支持库.实现.热接入演练 import 演练心跳"
        注册行 += '''
        ("热接入演练支持库.演练心跳", 演练心跳, [
            {"名称": "名称", "类型": "文本型", "必填": False, "默认值": None, "说明": "心跳名称"},
        ]),
'''
    __init__ = f'''"""热接入演练支持库 包级中文入口。"""
from __future__ import annotations
{导入行}

def 注册能力(注册表) -> None:
    """由支持库加载器调用。"""
    from 公共契约.能力契约.契约 import 能力实现
    for 能力id, 函数, 参数表 in [{注册行}
    ]:
        注册表.注册(能力实现(能力id=能力id, 包id="支持库.后端.热接入演练支持库",
                        实现函数=函数, 参数=参数表, 返回="结果",
                        说明="热接入演练能力"))
'''
    写文件("__init__.py", __init__)

    写文件("包声明.json", json.dumps({
        "包id": 演练包id, "名称": "热接入演练支持库", "类型": "支持库",
        "版本": "1.0.0", "说明": "热接入回归演练（测试后即删除）",
        "入口": "__init__.py", "依赖": [],
        "能力": 声明能力表(带心跳),
    }, ensure_ascii=False, indent=1))


def 声明能力表(带心跳: bool = True) -> list[dict]:
    """演练包的能力声明；必须与入口注册一致（热接入一致性门禁）。"""
    表 = [{
        "能力id": 能力id_加法, "名称": "演练加法",
        "参数": [{"名称": "左数", "类型": "整数型"}, {"名称": "右数", "类型": "整数型"}],
        "返回": {"类型": "结果型", "值结构": {}}, "说明": "演练：返回加法结果与版本",
    }]
    if 带心跳:
        表.append({
            "能力id": 能力id_心跳, "名称": "演练心跳",
            "参数": [{"名称": "名称", "类型": "文本型"}],
            "返回": {"类型": "结果型", "值结构": {}}, "说明": "演练：返回心跳",
        })
    return 表


def 删除演练包():
    if 演练包目录.is_dir():
        shutil.rmtree(演练包目录)
    for 缓存 in 演练包目录.parent.rglob("__pycache__"):
        if 演练包id.replace(".", "/") in str(缓存) or "热接入演练" in str(缓存):
            shutil.rmtree(缓存, ignore_errors=True)


def 主流程() -> int:
    失败清单: list[str] = []
    基线 = 健康()
    print(f"基线能力数: {基线}")

    def 检查(名称: str, 条件: bool, 细节: str = ""):
        if 条件:
            print(f"  ✓ {名称}")
        else:
            失败清单.append(名称)
            print(f"  ✗ {名称} {细节}")

    try:
        # ── 1. 新增包 ──
        print("\n[1] 新增包（整包热接入）")
        创建演练包("v1")
        状态码, 数据 = 热接入()
        检查("热接入返回成功", 状态码 == 200 and 数据["成功"] is True,
             f"实际 {状态码} {数据.get('错误码')} {数据.get('错误说明')}")
        状态码, 调用 = 调用能力(能力id_加法, {"左数": 3, "右数": 4})
        检查("新增能力立即可调用", 状态码 == 200 and 调用["成功"] and 调用["值"]["和"] == 7,
             f"实际 {状态码} {调用}")
        检查("能力数 +2（演练包注册 2 个能力）", 健康() == 基线 + 2, f"实际 {健康()}")

        # ── 2. 变更包 ──
        print("\n[2] 变更包（同进程不重启）")
        创建演练包("v2")
        状态码, 数据 = 热接入()
        检查("热接入返回成功", 状态码 == 200 and 数据["成功"] is True, f"实际 {数据}")
        状态码, 调用 = 调用能力(能力id_加法, {"左数": 3, "右数": 4})
        检查("变更立即生效", 状态码 == 200 and 调用["值"]["版本"] == "v2",
             f"实际 {调用}")
        检查("能力数不变", 健康() == 基线 + 2, f"实际 {健康()}")

        # ── 3. 包内删能力 ──
        print("\n[3] 包内删除能力（心跳下线）")
        创建演练包("v3", 带心跳=False)
        状态码, 数据 = 热接入()
        检查("热接入返回成功", 状态码 == 200 and 数据["成功"] is True, f"实际 {数据}")
        状态码, 调用 = 调用能力(能力id_心跳)
        检查("被删能力真实 404", 状态码 == 404 and 调用["成功"] is False
             and 调用["错误码"] == "能力不存在", f"实际 {状态码} {调用}")
        状态码, 调用 = 调用能力(能力id_加法)
        检查("剩余能力仍可用", 状态码 == 200 and 调用["成功"], f"实际 {调用}")
        检查("能力数 -1", 健康() == 基线 + 1, f"实际 {健康()}")

        # ── 4. 整包删除 ──
        print("\n[4] 整包删除（旧能力全部卸载）")
        删除演练包()
        状态码, 数据 = 热接入()
        检查("热接入返回成功", 状态码 == 200 and 数据["成功"] is True
             and data_check(数据, "卸载包", 1), f"实际 {状态码} {数据}")
        状态码, 调用 = 调用能力(能力id_加法)
        检查("旧能力真实 404", 状态码 == 404 and 调用["错误码"] == "能力不存在",
             f"实际 {状态码} {调用}")
        检查("能力数回到基线", 健康() == 基线, f"实际 {健康()}")

        # ── 5. 失败包（加载失败必须失败）──
        print("\n[5] 失败包（坏入口必须返回失败，且不破坏其他包）")
        创建演练包("v4")
        (演练包目录 / "实现").mkdir(parents=True, exist_ok=True)
        (演练包目录 / "实现" / "热接入演练.py").write_text(
            "def 演练加法(*, 左数):\n    return 1 + 破语法(\n", encoding="utf-8")
        状态码, 数据 = 热接入()
        检查("失败包返回 HTTP 400", 状态码 == 400, f"实际 {状态码}")
        检查("失败信封成功=false", 数据["成功"] is False, f"实际 {数据}")
        检查("失败错误码明确", 数据["错误码"] == "热接入失败", f"实际 {数据.get('错误码')}")
        检查("错误说明包含失败包", 演练包id in str(数据.get("错误说明", "")),
             f"实际 {数据.get('错误说明')}")
        状态码, 调用 = 调用能力("并发控制支持库.创建互斥锁")
        检查("其他包不受影响", 状态码 == 200 and 调用["成功"], f"实际 {状态码} {调用}")

        # ── 6. 失败包修复后可重试 ──
        print("\n[6] 失败包修复后热接入恢复")
        创建演练包("v5")
        状态码, 数据 = 热接入()
        检查("修复后热接入成功", 状态码 == 200 and 数据["成功"] is True, f"实际 {数据}")
        状态码, 调用 = 调用能力(能力id_加法, {"左数": 5, "右数": 6})
        检查("修复后能力可用", 状态码 == 200 and 调用["值"]["和"] == 11, f"实际 {调用}")

        # ── 7. 并发调用 ──
        print("\n[7] 并发调用（20 线程真实 HTTP）")
        错误列表: list[str] = []

        def 并发调用():
            try:
                状态码, 调用 = 调用能力(能力id_加法, {"左数": 1, "右数": 1})
                if not (状态码 == 200 and 调用["成功"] and 调用["值"]["和"] == 2):
                    错误列表.append(f"{状态码} {调用}")
            except Exception as 异常:
                错误列表.append(str(异常))

        线程表 = [threading.Thread(target=并发调用) for _ in range(20)]
        for 线程 in 线程表:
            线程.start()
        for 线程 in 线程表:
            线程.join()
        检查("并发调用全部成功", not 错误列表, f"错误: {错误列表[:3]}")

        # ── 9. 一致性门禁（注册了但包声明未登记 → 必须失败）──
        print("\n[9] 一致性门禁（注册了但包声明未登记）")
        写文件("包声明.json", json.dumps({
            "包id": 演练包id, "名称": "热接入演练支持库", "类型": "支持库",
            "版本": "1.0.0", "说明": "热接入回归演练（测试后即删除）",
            "入口": "__init__.py", "依赖": [],
            "能力": 声明能力表(带心跳=False),
        }, ensure_ascii=False, indent=1))
        状态码, 数据 = 热接入()
        检查("注册未声明被拦下 HTTP 400", 状态码 == 400, f"实际 {状态码} {数据.get('值')}")
        检查("失败说明含注册未声明", "注册未声明" in str(数据.get("错误说明", "")),
             f"实际 {数据.get('错误说明')}")
        状态码, 调用 = 调用能力(能力id_加法, {"左数": 1, "右数": 2})
        检查("线上旧能力仍可用", 状态码 == 200 and 调用["成功"], f"实际 {状态码} {调用}")
    finally:
        # ── 8. 清理 ──
        print("\n[8] 清理演练包")
        删除演练包()
        状态码, 数据 = 热接入()
        清理后 = 健康()
        print(f"  清理后能力数: {清理后}（基线 {基线}）")
        if 清理后 != 基线:
            失败清单.append("清理后能力数未回到基线")
            print("  ✗ 清理后能力数未回到基线")
        else:
            print("  ✓ 演练包已卸载，能力目录零残留")
        if (演练包目录).is_dir():
            失败清单.append("演练包目录残留")
            print("  ✗ 演练包目录残留")

    print(f"\n{'全部通过' if not 失败清单 else '失败: ' + '; '.join(失败清单)}")
    return 0 if not 失败清单 else 1


def data_check(数据: dict, 字段: str, 期望) -> bool:
    return isinstance(数据.get("值"), dict) and 数据["值"].get(字段) == 期望


if __name__ == "__main__":
    raise SystemExit(主流程())
