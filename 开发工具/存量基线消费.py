"""存量基线消费的唯一节点：按桶消费「条目表 + 上限表」→ ``(新增, 存量, 收敛)``。

为什么单独一件（而不是住进某个门禁的公共件）：本判据有**两个不同簇的消费方**——
`开发工具/公开调用完整性门禁`（发布门禁必经项）与 `开发工具/契约编译/漂移检测`
（契约编译期门禁）。此前两处各写一遍循环，分叉出**一对一错**：公开调用那份
**只遍历现场出现的桶**（``for 键, 条们 in 桶.items()``），基线里有、现场一条都没有的桶
循环根本不进 ⇒ 该桶永不进收敛 ⇒「该减没减」永久发现不了（实测：基线 7 桶 20 条、
现场 0 条 ⇒ 返回收敛 0 条，应为 7 桶）。

**为什么不落 `开发工具/验证门禁/门禁公共.py`**（本轮先试过、实测不行）：那是验证门禁
四件检查器的骨架，模块级自举要求「祖先目录里同时有 ``模块库`` 与 ``测试中心``」（它按此
定位系统根）。一旦被 `开发工具/公开调用完整性门禁` 引入，**制品内的该门禁就会脱离源码树
即崩** —— 实测：把制品拷到源码树外再 import，`门禁公共` 抛 ``StopIteration``（找不到含
``测试中心`` 的祖先），而制品里本来就没有 ``测试中心``；制品内的 `开发工具/公开调用完整性门禁`
此前是可导入的，引入这条边等于给它造一个「换目录即崩」。本件刻意**零自举、零仓内依赖**
（只用标准库），源码树与制品内行为一致。

口径（只减不增）：桶计数 ≤ 上限 ⇒ 存量（只报不拦）；> 上限 ⇒ 超出上限的那几条算新增
（判红）；< 上限 ⇒ 收敛提示（存量已好转，应下调基线）。**必须遍历 ``set(桶) | set(上限表)``**
—— 两类桶都要遍历，收敛才算得出。
"""

from __future__ import annotations


def 分桶与收敛(条目列表: list, 上限表: dict[str, int],
              分桶函数) -> tuple[list, list, list]:
    """按桶消费「条目表 + 上限表」，返回 ``(新增, 存量, 收敛)``。

    分桶键由 ``分桶函数`` 参数化：各判据的桶键构造不同（如「包相对路径|缺口类型」与
    「包|缺口类型」）—— **只参数化键，不参数化判定**，分治口径仍是同一份。
    """
    桶: dict[str, list] = {}
    for 条 in 条目列表:
        桶.setdefault(分桶函数(条), []).append(条)
    新增: list = []
    存量: list = []
    收敛: list[dict] = []
    for 键 in sorted(set(桶) | set(上限表)):
        条们 = 桶.get(键, [])
        上限 = int(上限表.get(键, 0) or 0)
        if len(条们) > 上限:
            新增.extend(条们[上限:])
        存量.extend(条们[:上限])
        if len(条们) < 上限:
            收敛.append({"桶": 键, "当前": len(条们), "基线": 上限})
    return 新增, 存量, 收敛
