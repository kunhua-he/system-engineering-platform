"""规则自检（哲学 13.1「规则三要素」的机器判据）：没有反向试验的规则不算规则。

## 为什么必须有它（#67 现场计数，2026-09-22 实测）

`开发文档/未完成事项.md#67`：哲学总账缺「反向试验」栏、`开发工具/` 无「规则自检」强制点。
栏已于 2026-09-21 补上（`哲学总账.md`「四之二、反向试验栏」），但强制点一直是空的 ——
现场 `rg -n '规则自检' 开发工具/` **零命中**。即 13.1 这条元规则**自己**只有
① 规范（`项目说明.md:425`）与 ② 判据（本文件），**没有 ③ 强制点**：
按它自己的话，「三者缺一即为『纸面规则』」—— 元规则自己就是纸面规则。

本文件补上第三环，并把它接进必经路径（编译口门禁清单 + 发布门禁），
使「缺反向试验的规则」在提交时就报红，而不是靠下一次人工审计再发现一次。

## 四类判据（全部只看「三要素在不在」，不评价规则内容好坏）

| 判据 | 查什么 | 判红条件 |
|---|---|---|
| ① 第三栏存在 | `开发文档/哲学总账.md` 有「反向试验栏」小节，且栏内**每一行都带第三要素字样** | 栏不存在 / 有行不带字样 |
| ② 栏行自洽 | 每行 `条款编号 + 反向试验样本 + 登记状态` 三段齐全；登记状态 ∈ 三档；`已实测` 行必须带可复现证据；编号必须在逐条总账里真实存在 | 缺段 / 状态非法 / 已实测无证据 / 编号悬空 |
| ③ 逐条三要素 | 「逐条总账」每个条款块必须含 `判据` / `强制点` / `反向试验` 三个标签 | 缺标签（存量按基线冻结，只减不增） |
| ④ 元接线 | 本判据件必须被**必经路径**真实引用：编译口门禁清单含本模块 + 发布门禁真实 import 链两跳齐 | 任一处未接 |

## 口径

**存量冻结（13.2 门禁五态＝债务冻结）**：判据 ③ 的存量基线 = **44 块**
（2026-09-22 实测：逐条总账 45 块 / 60 条目，44 块缺 `反向试验` 标签，唯一带标签的是 13.1）。
直接判红会把开发循环打死，且这些缺口是「还没验过」而不是「写错了」。
基线**只减不增**：补一块降一块，**新增条款缺第三要素即红**。

**为什么不一次性把 44 块补满**：第三要素的**逐条**登记只有真做过反向试验才写得出来
（13.1 禁止把「没做过」写成「有」），而**汇总**登记处就是总账「四之二、反向试验栏」——
一处声明、派生所有呈现（1.3 结果唯一即收口），不在这里复制第二份。
故本判据只保证「不新增缺口」，并把缺口清单每次列出来（跳过面必须可见，不得静默当通过）。

**第三要素「在但值为空」单独计数**：标签写着但值是 `无` / `未做` / `待建` 的块，
不算缺标签（那是**如实认账**），但计数上报 —— 它们就是已认账的纸面规则。

**不另立第二份实现**：本判据只读 `哲学总账.md` 与两个必经路径文件，
不重述条款原文、不解析 `项目说明.md`（条数口径的唯一真源仍在那里）。

用法：
    python3.14 -m 开发工具.规则自检

退出码：0 = 无违规（三要素缺项在存量基线内）；1 = 有违规（fail-closed：总账读不成也判红，
不静默放行 —— 判据无核验对象不等于通过）。
"""

