import ast
import re
import sys
from pathlib import Path

系统根 = Path(__file__).resolve()
for _祖先 in 系统根.parents:
    if (_祖先 / "支持库").is_dir() and (_祖先 / "模块库").is_dir():
        系统根 = _祖先
        break
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

#: 本判据件自身的模块路径 —— 元接线判据要拿它去必经路径里找**真实引用**。
本模块路径 = "开发工具.规则自检"

#: 哲学总账（逐条登记处 + 第三栏汇总处）。
总账相对 = "开发文档/哲学总账.md"
#: 逐条总账段的起止标题（第三节 / 第四节）。
逐条起标题 = "## 三、逐条总账"
逐条止标题 = "## 四、"
#: 三要素标签（13.1：有判据、有强制点、有反向试验，才叫规则）。
三要素 = ("判据", "强制点", "反向试验")
#: 第三栏登记值的合法三档（栏自己的口径行声明的那三档）。
登记三档 = ("已实测", "纸面", "未做")
#: 「如实声明第三要素为空」的写法：不算缺标签，但计数上报。
空值句式 = re.compile(r"无（|无\s*$|未做|待建|未建")
#: 条款编号（逐条总账的条目行 / 第三栏的表格行）。
条款编号句式 = re.compile(r"^\s*(\d+\.\d+)\s")
#: 字段标签行（逐条块里 `判据  …` / `强制点  …` 这类）。
字段句式 = re.compile(r"^\s*(判据|强制点|反向试验|状态)\s")
#: 「已实测」行必须带的**可复现证据**（命令 / 日期 / 测试入口任一）。
证据句式 = re.compile(r"python3\.14|rg\s|unittest|20\d\d-\d\d-\d\d")
#: 必经接线第 1 处：开发循环的一键口（清单里的项被 `python3.14 -m` 真跑）。
编译口路径 = ("开发工具", "开发编译口", "编译口.py")
#: 必经接线第 2 处：发布门禁主文件（13.1 点名「由发布门禁的『规则自检』项报红」）。
发布门禁路径 = ("开发工具", "发布门禁", "运行发布门禁.py")
#: 发布门禁侧的包装件（主文件 import 它、它 import 本模块 —— 两跳都要在，才叫真实引用）。
门禁包装件路径 = ("开发工具", "发布门禁", "运行发布门禁_规则自检.py")
门禁包装模块路径 = "开发工具.发布门禁.运行发布门禁_规则自检"

#: 存量基线（2026-09-22 实测）：逐条总账 45 块 / 60 条目，其中 **44 块缺 `反向试验` 标签**。
#: 只减不增。取值与理由见模块 docstring「口径」段。
存量基线 = 44


def _读(路径: Path) -> str | None:
    """读文本；读不成返回 None（调用方按 fail-closed 处置，不许当「没有违规」）。"""
    try:
        return 路径.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _导入模块集(文本: str) -> set[str]:
    """AST 层**真实 import** 的模块名集合（`from A.B import C` 取 `A.B`；`import A.B` 取 `A.B`）。

    只看 import，不看字面 —— 哲学总账 1.3／1.4 的实测教训：帮助文本里出现关键词
    不等于调用（发布门禁里「反向破坏」曾只以包名清单字符串出现过一次）。
    """
    名集: set[str] = set()
    try:
        树 = ast.parse(文本)
    except SyntaxError:
        return 名集
    for 节点 in ast.walk(树):
        if isinstance(节点, ast.ImportFrom) and 节点.module:
            名集.add(节点.module)
        elif isinstance(节点, ast.Import):
            for 别名 in 节点.names:
                名集.add(别名.name)
    return 名集


def _段范围(行表: list[str], 起标题: str, 止标题: str) -> tuple[int, int] | None:
    """取 `起标题` 那一行到 `止标题` 那一行（不含止行）的下标范围；找不到起标题返回 None。"""
    起 = next((i for i, 行 in enumerate(行表) if 行.startswith(起标题)), None)
    if 起 is None:
        return None
    止 = next((i for i, 行 in enumerate(行表[起 + 1:], start=起 + 1)
              if 行.startswith(止标题)), len(行表))
    return 起, 止


def 解析逐条块(行表: list[str]) -> tuple[list[dict], set[str]]:
    """把「逐条总账」段切成条款块，返回（块表, 条款编号集）。

    块 = 一条或多条**连续编号行** + 紧跟的非空行（字段行）。

    连续编号行算**一个块**：现场 `4.1~4.4` / `10.1~10.5` / `12.1~12.4` 是共享一组
    字段的合并写法，拆成多块会把「共享的判据」误报成「缺判据」——
    判据太宽会造出没有行动价值的假红，与 6.1「阈值不设硬门禁」同源。
    """
    范围 = _段范围(行表, 逐条起标题, 逐条止标题)
    if 范围 is None:
        return [], set()
    起, 止 = 范围
    块表: list[dict] = []
    当前: dict | None = None
    for i in range(起, 止):
        行 = 行表[i]
        匹配 = 条款编号句式.match(行)
        if 匹配:
            if 当前 is not None and i == 当前["末"] + 1:
                当前["号"].append(匹配.group(1))
                当前["行"].append(行)
                当前["末"] = i
            else:
                if 当前 is not None:
                    块表.append(当前)
                当前 = {"号": [匹配.group(1)], "起": i, "末": i, "行": [行]}
            continue
        if 当前 is None:
            continue
        if not 行.strip():
            块表.append(当前)
            当前 = None
            continue
        当前["行"].append(行)
        当前["末"] = i
    if 当前 is not None:
        块表.append(当前)
    编号集 = {号 for 块 in 块表 for 号 in 块["号"]}
    return 块表, 编号集


def _栏行表(行表: list[str]) -> tuple[int | None, list[str]]:
    """定位「反向试验栏」小节，返回（栏标题行下标, 栏内条款行列表）。"""
    栏标题 = next((i for i, 行 in enumerate(行表)
                 if 行.startswith("##") and "反向试验" in 行), None)
    if 栏标题 is None:
        return None, []
    止 = next((i for i, 行 in enumerate(行表[栏标题 + 1:], start=栏标题 + 1)
              if 行.startswith("## ")), len(行表))
    return 栏标题, [行 for 行 in 行表[栏标题:止] if 条款编号句式.match(行)]


def 查第三栏(行表: list[str]) -> tuple[list[str], int, int]:
    """判据①：第三栏存在，且栏内**每一行都带第三要素字样**。

    返回（问题表, 栏行数, 带第三要素字样的行数）。

    「栏内每一行都带」就是栏自己声明的判据（`命中数 ≥ 本栏行数`）的机器形态：
    栏行不写「反向试验」四个字，读者无法判断这一行登记的到底是哪一要素
    （现场实测：补栏后 `反向试验` 在总账里命中 8 行，而栏有 14 行 —— 栏自己的判据不成立）。
    """
    栏标题, 栏行 = _栏行表(行表)
    if 栏标题 is None:
        return ["第三栏（反向试验栏）不存在：总账里找不到含「反向试验」的二级标题"], 0, 0
    问题: list[str] = []
    if not 栏行:
        问题.append("第三栏存在但没有条款行（栏内无「编号 … 样本 … 状态」行）")
    for 行 in 栏行:
        if "反向试验" not in 行:
            问题.append(f"栏行未带第三要素字样（无法判断登记的是哪一要素）：{行.strip()[:60]}")
    return 问题, len(栏行), sum(1 for 行 in 栏行 if "反向试验" in 行)


def 查栏行自洽(行表: list[str], 编号集: set[str]) -> list[str]:
    """判据②：栏内每行 `条款编号 + 反向试验样本 + 登记状态` 三段齐全且自洽。

    四类判红：
      · 登记状态缺失或不在三档（`已实测` / `纸面` / `未做`）内；
      · `已实测` 行没带**可复现证据**（命令 / 日期 / 测试入口任一）——
        「已实测」是断言，没有复现方式就只是形容词；
      · 条款编号在逐条总账里**悬空**（栏里登记了一条不存在的条款）；
      · 样本段为空（只剩编号与状态）。
    """
    _, 栏行 = _栏行表(行表)
    问题: list[str] = []
    for 行 in 栏行:
        匹配 = 条款编号句式.match(行)
        if 匹配 is None:
            continue
        号 = 匹配.group(1)
        余下 = 行[匹配.end():].strip()
        状态 = next((档 for 档 in 登记三档 if 档 in 余下), "")
        if not 状态:
            问题.append(f"栏行 {号} 的登记状态非法或缺失（只认 {'/'.join(登记三档)}）："
                       f"{行.strip()[:60]}")
        if 状态 == "已实测" and not 证据句式.search(余下):
            问题.append(f"栏行 {号} 标「已实测」但没有可复现证据"
                       f"（需给出命令 / 日期 / 测试入口）：{行.strip()[:60]}")
        样本 = 余下.replace(状态, "").strip()
        if not 样本:
            问题.append(f"栏行 {号} 缺「反向试验样本」段（只剩编号与状态）")
        if 编号集 and 号 not in 编号集:
            问题.append(f"栏行 {号} 悬空：逐条总账里没有这条条款（编号不复用、不跳号）")
    return 问题


def 查逐条三要素(块表: list[dict]) -> tuple[list[str], int, int]:
    """判据③：每个条款块必须含 `判据` / `强制点` / `反向试验` 三个标签。

    返回（缺项明细, 缺项块数, 第三要素「在但值为空」的块数）。

    第三要素「在但值为空」（`无（…）` / `未做` / `待建`）**不算缺标签** ——
    那是如实认账（13.1 禁止把「没做过」写成「有」），单独计数上报即可。
    """
    缺项: list[str] = []
    空值块 = 0
    for 块 in 块表:
        标签: dict[str, str] = {}
        for 行 in 块["行"]:
            匹配 = 字段句式.match(行)
            if 匹配:
                标签[匹配.group(1)] = 行.strip()
        缺 = [名 for 名 in 三要素 if 名 not in 标签]
        if 缺:
            缺项.append(f"块 {','.join(块['号'])}（第 {块['起'] + 1} 行）缺 {'/'.join(缺)}")
            continue
        if 空值句式.search(标签["反向试验"]):
            空值块 += 1
    return 缺项, len(缺项), 空值块


def 查元接线(项目根: Path) -> list[str]:
    """判据④（元检查）：本判据件必须被**必经路径**真实引用 —— 否则它自己就是纸面规则。

    两处都要，且各按它**真正的接线形态**判：

      · **编译口门禁清单**：清单项是 `python3.14 -m <模块>` 的**被执行**项，
        故认「AST 常量里出现本模块路径」；
      · **发布门禁**：认**真实 import 链**（主文件 import 包装件、包装件 import 本模块），
        **不认字符串常量** —— 门禁里字符串可能是帮助文本（1.4 实测教训：字面 ≠ 调用）。

    任一处未接即报红：这正是 13.1「判据未被门禁引用 → 报红」那条要求自己的落地。
    """
    问题: list[str] = []
    编译口 = 项目根.joinpath(*编译口路径)
    文本 = _读(编译口)
    if 文本 is None:
        问题.append(f"编译口门禁清单未核验：{编译口.relative_to(项目根).as_posix()} 读不成")
    else:
        try:
            常量 = {节点.value for 节点 in ast.walk(ast.parse(文本))
                  if isinstance(节点, ast.Constant) and isinstance(节点.value, str)}
        except SyntaxError:
            常量 = set()
        if 本模块路径 not in 常量:
            问题.append(f"编译口门禁清单未接线：`{编译口路径[-1]}` 的门禁清单里"
                       f"没有 `{本模块路径}`（开发循环看不见本判据）")
    主文件 = 项目根.joinpath(*发布门禁路径)
    主文本 = _读(主文件)
    if 主文本 is None:
        问题.append(f"发布门禁未核验：{主文件.relative_to(项目根).as_posix()} 读不成")
    elif 门禁包装模块路径 not in _导入模块集(主文本):
        问题.append(f"发布门禁未接线：`{发布门禁路径[-1]}` 里没有真实 import "
                   f"`{门禁包装模块路径}`（13.1 点名由发布门禁的「规则自检」项报红）")
    包装件 = 项目根.joinpath(*门禁包装件路径)
    包装文本 = _读(包装件)
    if 包装文本 is None:
        问题.append(f"发布门禁包装件缺失或不可读：{门禁包装件路径[-1]}")
    elif 本模块路径 not in _导入模块集(包装文本):
        问题.append(f"发布门禁包装件未 import 本模块：`{门禁包装件路径[-1]}` 里"
                   f"没有 `{本模块路径}`")
    return 问题


def 体检(项目根: Path | None = None) -> tuple[list[str], list[str], dict[str, int]]:
    """跑四类判据，返回（违规表, 存量缺口明细, 统计）。

    违规表 = 判红项（判据①②④ 的全部 + 判据③ 超出存量基线的部分）；
    存量缺口明细 = 判据③ 基线内的缺口（**显式上报，不当通过**，见模块 docstring）。
    """
    根 = 系统根 if 项目根 is None else Path(项目根)
    统计 = {"栏行数": 0, "带字样行数": 0, "块数": 0, "条目数": 0, "缺项块数": 0, "空值块数": 0}
    文本 = _读(根 / 总账相对)
    if 文本 is None:
        return ([f"哲学总账读不成：{总账相对}（fail-closed：判据无核验对象不等于通过）"],
                [], 统计)
    行表 = 文本.splitlines()
    块表, 编号集 = 解析逐条块(行表)
    统计["块数"] = len(块表)
    统计["条目数"] = len(编号集)

    问题1, 栏行数, 带字样行数 = 查第三栏(行表)
    统计["栏行数"], 统计["带字样行数"] = 栏行数, 带字样行数
    违规 = [*问题1, *查栏行自洽(行表, 编号集)]

    缺项, 缺项块数, 空值块数 = 查逐条三要素(块表)
    统计["缺项块数"], 统计["空值块数"] = 缺项块数, 空值块数
    if 缺项块数 > 存量基线:
        违规.extend(缺项)
    违规.extend(查元接线(根))
    return 违规, 缺项, 统计


