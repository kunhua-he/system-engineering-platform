"""门禁报告：文本与 JSON 两种呈现；判定与呈现分离。

`生成摘要行` 供发布门禁等调用方把结果压成一行（形制对齐
`开发工具/公开调用完整性门禁.py` 的 `检查("…", not 违规, f"违规={…}")`）。

文本报告固定顺序：基线 → 三条规则统计 → 豁免清单状态 → TOP 违规文件 →
违规明细（按文件分组）。首发「只报不拦」，所以报告必须把**存量基线**与
**新增违规**放在同一屏里可对照：存量由豁免清单命中数体现，未命中即新增。
"""
from __future__ import annotations

import json

规则顺序 = ("规则1", "规则2", "规则3")


def 按规则计数(违规: list[dict]) -> dict[str, int]:
    计数: dict[str, int] = {规则: 0 for 规则 in 规则顺序}
    for 条 in 违规:
        规则 = 条.get("规则") or _规则名(条.get("类型", ""))
        if 规则:
            计数[规则] = 计数.get(规则, 0) + 1
    return 计数


def _规则名(类型: str) -> str:
    for 规则 in 规则顺序:
        if str(类型).startswith(规则):
            return 规则
    return ""


def 文件计数(违规: list[dict]) -> list[tuple[str, int]]:
    计数: dict[str, int] = {}
    for 条 in 违规:
        文件 = 条.get("文件", "?")
        计数[文件] = 计数.get(文件, 0) + 1
    return sorted(计数.items(), key=lambda 项: (-项[1], 项[0]))


def _明细行(条: dict) -> str:
    位置 = f"{条.get('文件', '?')}:{条.get('行号')}" if 条.get("行号") else 条.get("文件", "?")
    子类型 = f"[{条['子类型']}] " if 条.get("子类型") else ""
    return f"  [{条.get('类型', '?')}] {位置} — {子类型}{条.get('细节', '')}"


def 生成文本报告(结果: dict, *, TOP: int = 10, 明细上限: int = 300) -> str:
    行: list[str] = []
    行.append(f"测试伪装门禁（mock 三条硬规则·首发只报不拦）：{结果['相对根']}")
    行.append(
        f"基线：测试文件 {结果['测试文件数']} 个（解析失败 {len(结果['解析失败'])}）｜"
        f"patch 调用点 {结果['桩调用点总数']} 个"
        f"（{_形式摘要(结果['桩形式分布'])}）"
    )
    统计1 = 结果["规则1统计"]
    行.append(
        f"规则1 禁 patch 被测对象/生产路径：违规 {统计1['违规']}"
        f"（P1 被测模块本体 {统计1['P1']}／P2 生产路径 {统计1['P2']}；"
        f"本体成员 {统计1['本体成员']}／依赖边界 {统计1['依赖边界']}／未知 {统计1['未知成员']}）"
        f"｜wraps 豁免 {统计1['wraps豁免']}｜清单豁免 {统计1['清单豁免']}"
        f"｜观察 {统计1['观察']}"
    )
    统计2 = 结果["规则2统计"]
    行.append(
        f"规则2 一律 autospec=True：违规 {统计2['违规']}（存量基线）"
        f"｜合规 {统计2['合规']}｜wraps 豁免 {统计2['wraps豁免']}"
        f"｜清单豁免 {统计2['清单豁免']}｜patch.dict 不适用 {统计2['不适用']}"
        f"｜create_autospec {统计2['自动规格调用']} 处"
    )
    统计3 = 结果["规则3统计"]
    行.append(
        f"规则3 负面断言强度下限：恒真违规 {统计3['恒真违规']}"
        f"｜强度不足违规 {统计3['强度不足违规']}｜用例总数 {统计3['用例总数']}"
        f"｜观察（无直接断言 {统计3['观察无直接断言']}／弱断言 {统计3['观察弱断言']}）"
    )
    清单 = 结果["豁免清单"]
    行.append(
        f"豁免清单：{清单['路径']}"
        f"（条目 {清单['条目数']}，命中 {清单['命中数']}，失效 {len(清单['失效'])}）"
    )
    if 清单["失效"]:
        for 条目 in 清单["失效"][:10]:
            行.append(f"  [清单失效] {条目['规则']} {条目['文件']}:{条目['行号']} — {条目['理由']}")
    if 结果["解析失败"]:
        行.append(f"解析失败（{len(结果['解析失败'])}，fail-closed 计入违规）：")
        行.extend(f"  [解析失败] {项['相对路径']} — {项['细节']}" for 项 in 结果["解析失败"])
    TOP项 = 文件计数(结果["违规"])[:TOP]
    if TOP项:
        行.append(f"TOP 违规文件（按条数，前 {len(TOP项)} 个）：")
        行.extend(f"  {条数:4d}  {文件}" for 文件, 条数 in TOP项)
    if not 结果["违规"]:
        行.append("测试伪装门禁通过：三条硬规则均无违规")
    else:
        计数 = 按规则计数(结果["违规"])
        # ★ 这里**不写「失败」**：本报告在判定**之前**生成，手里只有违规清单，没有
        #   `计数` 与 `存量违约上限` 的比较结果 —— 而本门禁的判定是
        #   `计数 = 违规数 + 清单豁免数 <= 存量违约上限`（见 测试伪装门禁.py 的 判定）。
        #   实测 2026-09-23：存量 213 项全在基线内、门禁判**绿**（退出码 0），报告却打
        #   「测试伪装门禁失败：共 213 项违规」—— 判据替判定下了结论，读者会以为门禁红了。
        #   结论由 `主程序` 单独打到 stderr（通过／判红各一行），本表只如实列明细。
        行.append(
            f"违规明细：共 {len(结果['违规'])} 项"
            f"（规则1 {计数.get('规则1', 0)}、规则2 {计数.get('规则2', 0)}、规则3 {计数.get('规则3', 0)}）"
            f"｜存量是否放行由「计数 ≤ 存量违约上限」另判"
        )
        当前文件 = ""
        for 条 in 结果["违规"][:明细上限]:
            if 条.get("文件") != 当前文件:
                当前文件 = 条.get("文件", "?")
                行.append(f"文件 {当前文件}")
            行.append(_明细行(条))
        if len(结果["违规"]) > 明细上限:
            行.append(f"…（明细已截断，共 {len(结果['违规'])} 项，用 --json 取全量）")
    if 结果["观察"]:
        行.append(f"观察项（不判违规，共 {len(结果['观察'])}）：")
        行.extend(
            f"  [观察] {条.get('相对路径', 条.get('文件', '?'))}:{条.get('行号')} — {条.get('细节', '')}"
            for 条 in 结果["观察"][:20]
        )
    行.append(f"耗时 {结果['耗时秒']:.1f} 秒（只读 AST 扫描，未导入被测模块、未执行用例）")
    return "\n".join(行)


def _形式摘要(分布: dict[str, int]) -> str:
    if not 分布:
        return "无"
    return "、".join(f"{名称} {数量}" for 名称, 数量 in sorted(分布.items(), key=lambda 项: -项[1]))


def 生成json报告(结果: dict) -> str:
    return json.dumps(结果, ensure_ascii=False, indent=2)


def 生成摘要行(结果: dict) -> str:
    """一行摘要：无换行，供门禁清单直接打印。"""
    if not 结果["违规"]:
        return (f"测试伪装 0 违规（patch 调用点 {结果['桩调用点总数']}，"
                f"测试文件 {结果['测试文件数']}）")
    计数 = 按规则计数(结果["违规"])
    首条 = 结果["违规"][0]
    return (f"测试伪装违规 {len(结果['违规'])} 项"
            f"（规则1 {计数.get('规则1', 0)}、规则2 {计数.get('规则2', 0)}、规则3 {计数.get('规则3', 0)}）；"
            f"首项 {首条.get('文件')}:{首条.get('行号')} — {首条.get('类型')}")
