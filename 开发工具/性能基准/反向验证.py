# 反向验证1：坏参数必须明确失败（退出码 2），不静默出 0
# ═══════════════════════════════════════════════════════════════
def 反向验证_坏参数(输出目录: Path) -> None:
    用例表 = [
        (["--轮数", "0"], "轮数下限"),
        (["--轮数", "abc"], "非数字轮数"),
        (["--轮数", "-5"], "负数轮数"),
        (["--轮数", "99999999"], "轮数超上限"),
        (["--预热轮数", "999999"], "预热超上限"),
        (["--重复", "0"], "重复下限"),
        (["--并发", "1"], "并发下限（并发采样要求 ≥2）"),
        (["--抖动上限", "abc"], "抖动上限非数字"),
        (["--超时秒", "0"], "超时秒下限"),
        (["--场景", "不存在的场景"], "未知场景"),
        (["--场景", ""], "空场景名"),
        (["--网关地址", "ftp://x"], "网关地址非 http"),
        (["--网关请求id", "也许"], "网关请求id 非 开/关"),
        (["--名称", "a/b"], "名称含路径分隔符"),
        (["--没有这个选项"], "未知选项"),
    ]
    for 参数, 说明 in 用例表:
        补充 = [] if "--场景" in 参数 else ["--场景", "原子能力直调"]
        码, 输出 = 跑命令行(参数 + 补充 + ["--输出目录", str(输出目录)])
        记(f"坏参数必须失败：{说明}",
           码 == 退出码_参数错误,
           f"参数 {参数} → 退出码 {码}（期望 {退出码_参数错误}）")


def 反向验证_输出目录不可写(临时根: Path) -> None:
    障碍 = 临时根 / "这是个普通文件"
    障碍.write_text("不是目录\n", encoding="utf-8")
    码, 输出 = 跑命令行(["--输出目录", str(障碍 / "子目录"), "--场景", "原子能力直调"])
    记("坏参数必须失败：输出目录不可写（落盘失败）",
       码 == 退出码_落盘失败,
       f"退出码 {码}（期望 {退出码_落盘失败}）；输出含「输出目录不可用」："
       f"{'是' if '输出目录不可用' in 输出 or '输出目录不可写' in 输出 else '否'}")


