"""性能基准的反向验证：故意弄坏 → 必须明确变红。

铁律：**没有反向验证的修复不算修好**；对基准工具而言，最危险的失效形态是
「悄悄出 0 或者出漂亮数字」。所以本脚本逐个把坏输入喂进去，要求它**明确失败**
（非零退出码 / 明确异常），并同时验证正向断言（抖动自检通过、正式运行库未被写入）。

跑法（工程根下，一律 python3.14；跑前 unset PYTHONPATH）：

    unset PYTHONPATH && python3.14 开发工具/性能基准/反向验证.py

退出码：0 全部反向验证通过；1 有任一项未通过（逐项打印中文结论）。
"""

