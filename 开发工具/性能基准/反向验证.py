def 主流程() -> int:
    print(f"性能基准反向验证：工程根 {工程根}")
    print(f"解释器 {sys.executable}（PYTHONPATH 已从子进程环境剔除）")
    print("-" * 78)
    临时根 = Path(tempfile.mkdtemp(prefix="性能基准反向验证-"))
    输出目录 = 临时根 / "结果"
    try:
        反向验证_坏参数(输出目录)
        反向验证_输出目录不可写(临时根)
        反向验证_统计与采样(临时根)
        反向验证_抖动自检()
        正向验证_真实跑一遍(输出目录)
        with 轻量运行态() as 环境:
            反向验证_要求成功(环境)
            反向验证_场景喂坏参数(环境)
            正向验证_线程包装断言(环境, {"轮数": 300, "预热轮数": 20,
                                     "并发": 2, "超时秒": 5.0})
    finally:
        import shutil

        shutil.rmtree(临时根, ignore_errors=True)
    未通过 = [名称 for 名称, 通过, _说明 in 检查记录 if not 通过]
    print("-" * 78)
    print(f"反向验证结论：共 {len(检查记录)} 项，通过 {len(检查记录) - len(未通过)} 项，"
          f"未通过 {len(未通过)} 项")
    if 未通过:
        for 名称 in 未通过:
            print(f"  未通过：{名称}")
        return 1
    print("全部反向验证通过：坏参数/坏输入一律明确失败，正向断言成立。")
    return 0


if __name__ == "__main__":
    raise SystemExit(主流程())
