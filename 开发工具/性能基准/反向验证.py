def 记(名称: str, 通过: bool, 说明: str) -> None:
    检查记录.append((名称, 通过, 说明))
    状态 = "通过" if 通过 else "未通过"
    print(f"[{状态}] {名称} —— {说明}")


def 干净环境() -> dict[str, str]:
    环境表 = dict(os.environ)
    环境表.pop("PYTHONPATH", None)
    return 环境表


def 跑命令行(额外参数: list[str], 超时秒: float = 180.0) -> tuple[int, str]:
    完成 = subprocess.run(
        [sys.executable, str(运行基准路径)] + 额外参数,
        cwd=str(工程根), env=干净环境(), capture_output=True, text=True,
        timeout=超时秒,
    )
    return 完成.returncode, (完成.stdout or "") + (完成.stderr or "")


