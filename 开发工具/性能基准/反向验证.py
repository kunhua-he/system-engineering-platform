# 反向验证3：抖动自检必须真会红（用确定性不稳定的桩环境）
# ═══════════════════════════════════════════════════════════════
class _确定性不稳定服务:
    """第一轮快、第二轮慢：让两轮同输入的 p50 必然拉开。"""

    def __init__(self, 第一轮调用数: int) -> None:
        from 公共契约.基础类型.结果类型 import 结果

        self._结果类 = 结果
        self.第一轮调用数 = 第一轮调用数
        self.已调用 = 0

    def 调用能力(self, 能力id, 参数=None, **关键字):
        self.已调用 += 1
        if self.已调用 > self.第一轮调用数:
            time.sleep(0.0005)
        return self._结果类.成功结果(固定数据)


class _桩环境:
    def __init__(self, 服务) -> None:
        self.服务 = 服务


def 反向验证_抖动自检() -> None:
    参数 = {"轮数": 10, "预热轮数": 10, "抖动上限": 0.35}
    每轮调用数 = 参数["预热轮数"] + max(参数["轮数"], 1000)
    桩 = _桩环境(_确定性不稳定服务(第一轮调用数=每轮调用数))
    结论 = 跑抖动自检(桩, 参数)
    记("抖动自检对确定性不稳定的两轮必须判不通过",
       (结论["通过"] is False) and (结论["相对差异"] is not None
                                and 结论["相对差异"] > 参数["抖动上限"]),
       f"相对差异={结论['相对差异']} 上限={结论['上限']} 结论={结论['结论']}")

    记("抖动不通过 ⇒ 退出码为口径失败",
       判定退出码(结论) == 退出码_口径失败,
       f"判定退出码={判定退出码(结论)}（期望 {退出码_口径失败}）")
    记("抖动通过/未做 ⇒ 退出码为成功",
       判定退出码({"通过": True}) == 退出码_成功 and 判定退出码(None) == 退出码_成功,
       f"通过={判定退出码({'通过': True})} 未做={判定退出码(None)}")


# ═══════════════════════════════════════════════════════════════
# 正向断言：真实跑一遍，抖动自检通过 + 正式运行库未被写入
# ═══════════════════════════════════════════════════════════════
def 正向验证_真实跑一遍(输出目录: Path) -> None:
    import json

    码, 输出 = 跑命令行([
        "--场景", "原子能力直调,SQLite写,线程包装开销",
        "--轮数", "200", "--预热轮数", "20", "--重复", "2",
        "--输出目录", str(输出目录),
    ], 超时秒=300)
    记("真实跑一遍（含重复 2 轮）必须成功退出", 码 == 退出码_成功,
       f"退出码 {码}（期望 {退出码_成功}）")
    文件表 = sorted(输出目录.glob("基准结果-*.json"))
    if not 文件表:
        记("真实跑一遍必须落盘机器可读 JSON", False, f"目录里没有结果文件：{输出目录}")
        return
    结果 = json.loads(文件表[-1].read_text(encoding="utf-8"))
    抖动 = 结果.get("抖动自检") or {}
    记("抖动自检（两次相同输入 p50 差异）必须通过",
       抖动.get("通过") is True,
       f"相对差异={抖动.get('相对差异')} 上限={抖动.get('上限')} 结论={抖动.get('结论')}")
    记("重复稳定性必须产出（重复=2）",
        isinstance(结果.get("重复稳定性"), dict)
       and len(结果["重复稳定性"].get("明细", [])) > 0,
       f"明细条数={len((结果.get('重复稳定性') or {}).get('明细', []))}")

    sqlite场景 = [场景 for 场景 in 结果.get("场景结果", [])
                if 场景.get("场景") == "SQLite写" and 场景.get("轮次") == 1]
    记("SQLite 场景必须证明正式运行数据根未被写入",
       bool(sqlite场景) and sqlite场景[0].get("附加结论", {}).get(
           "正式运行数据根未被写入") is True,
       f"附加结论={sqlite场景[0].get('附加结论', {}).get('正式运行数据根未被写入') if sqlite场景 else '场景缺失'}")
    记("SQLite 场景行数读回校验必须一致",
       bool(sqlite场景) and (
           sqlite场景[0]["附加结论"]["实际新增行数"]
           == sqlite场景[0]["附加结论"]["期望新增行数"]),
       f"实际={sqlite场景[0]['附加结论']['实际新增行数']} "
       f"期望={sqlite场景[0]['附加结论']['期望新增行数']}" if sqlite场景 else "场景缺失")


def 正向验证_线程包装断言(环境, 参数) -> None:
    场景 = 场景_线程包装开销(环境, 参数, 1)
    快照 = 场景["附加结论"]["超时执行器快照"]
    记("线程包装场景结束时不得留下仍在运行的执行单元",
       快照.get("仍在运行残留数") == 0 and 快照.get("累计超时次数") == 0,
       f"残留={快照.get('仍在运行残留数')} 超时次数={快照.get('累计超时次数')}")
    差值 = 场景["测量项"][1]["附加结论"]["线程包装差值毫秒（p50）"]
    记("线程包装开销必须量出正值（否则度量手段等于没有）",
       isinstance(差值, (int, float)) and 差值 > 0,
       f"p50 差值={差值} 毫秒")


