def 入口() -> int:
    try:
        return 主流程(sys.argv[1:])
    except SystemExit as 退出:
        return int(退出.code or 0)
    except 基准错误 as 错误:
        print(f"基准失败[{错误.类别}]：{错误.说明}", file=sys.stderr)
        return 类别对应退出码.get(错误.类别, 3)
    except KeyboardInterrupt:
        print("基准被中断", file=sys.stderr)
        return 130


