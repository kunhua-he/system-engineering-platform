def 解析场景名(原文: str) -> list[str]:
    """解析 `--场景`：支持逗号分隔与「全部」。非法名明确失败，不静默忽略。"""
    from 开发工具.性能基准.基准口径 import 报参数错误

    文本 = (原文 or "").strip()
    if not 文本:
        报参数错误("--场景 不能为空（要全部场景请写 --场景 全部）")
    if 文本 == "全部":
        return list(全部场景名)
    名称表: list[str] = []
    for 段 in 文本.replace("，", ",").split(","):
        名 = 段.strip()
        if not 名:
            continue
        if 名 == "全部":
            for 场景名 in 全部场景名:
                if 场景名 not in 名称表:
                    名称表.append(场景名)
            continue
        if 名 not in 场景表:
            报参数错误(f"未知场景 {名!r}；可选：{'、'.join(全部场景名)}（或用 全部）")
        if 名 not in 名称表:
            名称表.append(名)
    if not 名称表:
        报参数错误(f"--场景 未解析出任何场景（原文 {原文!r}）")
    return 名称表
