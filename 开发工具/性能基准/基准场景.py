def 场景_原子能力直调(环境, 参数: dict[str, Any], 轮次: int) -> dict[str, Any]:
    """热路径原子能力直调：纯计算 JSON 能力，经唯一能力调用服务与后端核心两层。"""
    轮数 = 参数["轮数"]
    预热轮数 = 参数["预热轮数"]

    def 服务层反序列化():
        值 = 要求成功(环境.服务.调用能力(能力_反序列化JSON, {"文本": 固定JSON文本}),
                     "唯一能力调用服务.反序列化JSON")
        if 值 != 固定数据:
            报场景失败(f"反序列化JSON 结果与固定输入不一致：{值!r}")
        return 值

    def 服务层序列化():
        值 = 要求成功(环境.服务.调用能力(能力_序列化JSON, {"数据": 固定数据}),
                     "唯一能力调用服务.序列化JSON")
        if not isinstance(值, str) or json.loads(值) != 固定数据:
            报场景失败(f"序列化JSON 结果与固定输入不一致（返回结果被改动过）：{值!r}")
        return 值

    def 后端层反序列化():
        值 = 要求成功(环境.后端.调用(能力_反序列化JSON, {"文本": 固定JSON文本}),
                     "后端核心.调用.反序列化JSON")
        if 值 != 固定数据:
            报场景失败(f"经后端核心的 反序列化JSON 结果不一致：{值!r}")
        return 值

    测量项 = [
        _测量串行(f"唯一能力调用服务.调用能力（{能力_反序列化JSON}，无超时秒）",
                服务层反序列化, 轮数=轮数, 预热轮数=预热轮数),
        _测量串行(f"唯一能力调用服务.调用能力（{能力_序列化JSON}，无超时秒）",
                服务层序列化, 轮数=轮数, 预热轮数=预热轮数),
        _测量串行(f"后端核心.调用（{能力_反序列化JSON}，无超时秒）",
                后端层反序列化, 轮数=轮数, 预热轮数=预热轮数),
    ]
    return _场景外壳(
        场景名_原子能力直调, 轮次,
        "纯计算原子能力（数据操作支持库.数据交换）在真实调用链上的 p50/p99："
        "同一实现分别经「唯一能力调用服务」与「后端核心」两层调用，"
        "固定输入、固定轮数，结果逐次与固定输入比对（值不符即判场景失败）。",
        测量项,
        [
            "无超时秒 ⇒ 走同线程直调分支（不建执行线程），这是热路径的最低开销形态。",
            "「后端核心」层比「唯一能力调用服务」层多出：运行上下文进入/退出、"
            "活动请求计数、权限表查询 —— 差值即该层的真实成本。",
            f"固定输入大小：JSON 文本 {len(固定JSON文本.encode('utf-8'))} 字节，"
            f"键数 {len(固定数据)}（含 5 条明细）。",
            "本场景不加载任何模型、不访问网络、不写任何库。",
        ],
        {
            "装配耗时秒": 环境.装配耗时秒,
            "已装配包id": list(环境.已装配包id),
            "能力数": 环境.能力数,
        },
    )


