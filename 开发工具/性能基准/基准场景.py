def _读回行数(环境, 库路径: str) -> int:
    """经 `查询` 能力读回总行数；返回不是整数即明确失败。"""
    值 = 要求成功(环境.服务.调用能力(
        能力_SQLite查询,
        {"数据库路径": 库路径, "SQL": "SELECT COUNT(*) AS 行数 FROM 基准写入"},
    ), "SQLite 读回行数")
    if isinstance(值, dict):
        值 = 值.get("行列表", 值.get("值"))
    if not isinstance(值, list) or not 值:
        报场景失败(f"读回行数返回结构异常：{值!r}")
    行 = 值[0]
    if not isinstance(行, dict) or "行数" not in 行:
        报场景失败(f"读回行数缺少 行数 字段：{行!r}")
    行数 = 行["行数"]
    if isinstance(行数, bool) or not isinstance(行数, int):
        报场景失败(f"读回行数不是整数：{行数!r}")
    return 行数


