def 场景_网关空跑(环境, 参数: dict[str, Any], 轮次: int) -> dict[str, Any]:
    """网关空跑：对真实 HTTP 网关发最小请求，量 QPS 与 p50/p99。"""
    from urllib.parse import quote

    轮数 = 参数["轮数"]
    预热轮数 = 参数["预热轮数"]
    并发数 = 参数["并发"]
    地址 = 参数.get("网关地址") or 环境.网关地址
    if not 地址:
        报场景失败("网关空跑场景缺少网关地址（进程内网关未启动且未指定 --网关地址）")
    带请求id = bool(参数.get("网关请求id"))
    路径健康 = "/" + quote("健康")
    路径调用 = "/" + quote("网关/调用")
    显示健康 = "/健康"
    显示调用 = "/网关/调用"
    调用体 = {"操作": "调用能力", "能力id": 能力_反序列化JSON,
              "参数": {"文本": 固定JSON文本}}

    def 发请求(方法: str, 路径: str, 体: dict[str, Any] | None) -> dict[str, Any]:
        请求id = uuid.uuid4().hex[:16] if 带请求id else ""
        状态码, 响应 = 网关HTTP请求(地址, 方法, 路径, 体=体, 请求id=请求id,
                                 超时秒=参数["超时秒"] + 5.0)
        if 状态码 == 429:
            报场景失败(
                "网关按限流拒绝（429 限流）：本次数字会量到限流拒绝而不是网关处理能力。"
                "进程内网关会自动放宽限流器；对**外部已激活网关**跑基准时，"
                "必须先把该网关的 单能力频率/单维度并发 放宽到覆盖 --轮数，"
                "或改用进程内网关（不给 --网关地址）")
        if 状态码 != 200:
            报场景失败(f"网关返回非 200（{状态码}）：{响应.get('错误码', '')} "
                     f"{响应.get('错误说明', '')}")
        if 响应.get("成功") is not True:
            报场景失败(f"网关响应未成功：{响应.get('错误码', '')} "
                     f"{响应.get('错误说明', '')}")
        return 响应

    def 健康():
        响应 = 发请求("GET", 路径健康, None)
        if not isinstance(响应.get("值"), dict) or "状态" not in 响应["值"]:
            报场景失败(f"健康检查响应缺少状态字段：{响应!r}")
        return 响应

    def 最小调用():
        响应 = 发请求("POST", 路径调用, 调用体)
        if 响应.get("值") != 固定数据:
            报场景失败(f"网关调用返回值与固定输入不一致：{响应.get('值')!r}")
        return 响应

    开始请求数 = getattr(环境.网关核心, "请求数", 0) if 环境.网关核心 is not None else 0
    测量项 = [
        _测量串行(f"HTTP GET {显示健康}（网关空跑，不含业务能力）",
                健康, 轮数=轮数, 预热轮数=预热轮数,
                每秒口径="串行 QPS（单线程顺序请求，每次新建连接）"),
        _测量串行(f"HTTP POST {显示调用}（全链路：HTTP 边界→网关核心→后端核心→"
                f"{能力_反序列化JSON}）",
                最小调用, 轮数=轮数, 预热轮数=预热轮数,
                每秒口径="串行 QPS（单线程顺序请求，每次新建连接）"),
        _测量并发(f"HTTP POST {显示调用}（并发{并发数}）",
                最小调用, 轮数=轮数, 预热轮数=预热轮数, 并发数=并发数),
    ]
    结束请求数 = getattr(环境.网关核心, "请求数", 0) if 环境.网关核心 is not None else 0
    口径注释 = [
        f"被测网关：{地址}"
        + ("（进程内测试服务器：回环 + 端口自动分配 + 免凭证，不起制品、不占制品仓库）"
           if not 参数.get("网关地址") else "（外部已激活网关，只发最小请求、只读轻量）"),
        (环境.限流放宽说明 if not 参数.get("网关地址") and 环境.限流放宽说明 else
         "外部网关的限流配置由该网关进程决定，本基准无法读取；"
         "若该网关保持默认 单能力频率 200 次/10 秒，则 QPS 上限约 20 次/秒，"
         "测到的是限流上限而不是处理能力。"),
        "样本含客户端建连开销：网关响应带 `Connection: close`，每次请求都是一条新连接，"
        "这是平台现状而非基准额外开销。",
        ("请求带唯一 X-请求-id ⇒ 网关幂等表参与（命中即返回缓存副本，含 deepcopy 开销）。"
         if 带请求id else
         "请求不带 X-请求-id ⇒ 网关幂等表不参与，测的是每次真实处理链路。"),
        "网关 HTTP 调用路径未向 后端核心.调用 传 超时秒（`网关核心._执行` 的调用点），"
        "故本场景量到的是同线程直调分支；「经超时执行器线程包装」的开销由"
        "「线程包装开销」场景单独度量。",
        "不含 TLS、不含公网往返、不含前端渲染；数字用于同机前后对比，不用于跨机绝对值。",
        f"并发吞吐对样本量敏感（墙钟含 {并发数} 条线程的启动与起跑同步）："
        f"建议 --轮数 ≥ 500 再读并发 QPS；本项每线程 {轮数} 次。",
    ]
    return _场景外壳(
        场景名_网关空跑, 轮次,
        "对真实 HTTP 网关（进程内回环测试服务器）发最小请求，量 QPS 与 p50/p99："
        "一条是纯网关空跑（健康检查），一条是全链路最小业务调用（反序列化固定 JSON）。",
        测量项, 口径注释,
        {
            "网关核心请求数增量": 结束请求数 - 开始请求数,
            "网关核心失败数": getattr(环境.网关核心, "失败数", None),
            "限流累计拒绝数": getattr(环境.限流器, "累计拒绝数", None),
            "带请求id": 带请求id,
        },
    )


