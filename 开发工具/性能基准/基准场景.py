# 场景4：线程包装开销（直接回答「每调用一线程」之争）
# ═══════════════════════════════════════════════════════════════
def 场景_线程包装开销(环境, 参数: dict[str, Any], 轮次: int) -> dict[str, Any]:
    """同线程直调 vs 经超时执行器线程包装：给出每调用一线程的真实开销。"""
    轮数 = 参数["轮数"]
    预热轮数 = 参数["预热轮数"]
    时限 = 参数["超时秒"]

    from 运行核心.能力调用.超时执行 import 执行器

    执行器.重置账本()  # 干净窗口：只统计本场景的残留与准入（不影响已在跑的线程）

    def 直调():
        值 = 要求成功(环境.服务.调用能力(能力_反序列化JSON, {"文本": 固定JSON文本}),
                     "直调.反序列化JSON")
        if 值 != 固定数据:
            报场景失败("直调返回值与固定输入不一致")
        return 值

    def 包装():
        值 = 要求成功(环境.服务.调用能力(能力_反序列化JSON, {"文本": 固定JSON文本},
                                    超时秒=时限),
                     f"超时线程包装.反序列化JSON（超时秒={时限:g}）")
        if 值 != 固定数据:
            报场景失败("包装调用返回值与固定输入不一致")
        return 值

    def 裸线程():
        线程 = threading.Thread(target=lambda: None, daemon=True)
        线程.start()
        线程.join()

    线程基线 = threading.active_count()
    直调测量 = _测量串行("同线程直调（唯一能力调用服务，无超时秒）",
                      直调, 轮数=轮数, 预热轮数=预热轮数,
                      每秒口径="串行吞吐（不建执行线程）")
    包装测量 = _测量串行(f"经超时执行器线程包装（超时秒={时限:g}，每调用一条执行线程）",
                      包装, 轮数=轮数, 预热轮数=预热轮数,
                      每秒口径="串行吞吐（每调用新建一条执行线程）")
    裸线程测量 = _测量串行("裸线程基线（threading.Thread.start()+join()，空函数）",
                       裸线程, 轮数=轮数, 预热轮数=预热轮数,
                       每秒口径="串行吞吐（纯线程创建与回收的地板价）")
    直调复测 = _测量串行("同线程直调（复测，用于排除采样顺序带来的漂移）",
                      直调, 轮数=轮数, 预热轮数=预热轮数,
                      每秒口径="串行吞吐（不建执行线程）")

    快照 = 执行器.状态快照()
    仍在运行残留 = int(快照.get("仍在运行残留数") or 0)
    累计超时 = int(快照.get("累计超时次数") or 0)
    if 仍在运行残留 != 0:
        报场景失败(f"线程包装留下仍在运行的执行单元 {仍在运行残留} 个"
                 f"（线程包装泄漏，基准拒绝给出「无开销」结论）")
    if 累计超时 != 0:
        报场景失败(f"出现 {累计超时} 次超时（超时秒={时限:g} 对本次能力太紧，"
                 f"该数字不能用来比较线程开销）")

    差值 = round(包装测量["p50毫秒"] - 直调测量["p50毫秒"], 4)
    倍数 = (round(包装测量["p50毫秒"] / 直调测量["p50毫秒"], 2)
          if 直调测量["p50毫秒"] > 0 else None)
    复测偏差 = (round(abs(直调复测["p50毫秒"] - 直调测量["p50毫秒"])
                  / 直调测量["p50毫秒"], 4)
             if 直调测量["p50毫秒"] > 0 else None)
    包装测量["附加结论"] = {
        "线程包装差值毫秒（p50）": 差值,
        "线程包装每调用开销微秒（p50）": round(差值 * 1000.0, 2),
        "线程包装倍数（p50）": 倍数,
        "裸线程地板价毫秒（p50）": 裸线程测量["p50毫秒"],
        "差值中属于纯线程创建回收的比例": (
            round(裸线程测量["p50毫秒"] / 差值, 4) if 差值 > 0 else None),
        "直调复测相对偏差": 复测偏差,
        "线程包装后活动线程数": threading.active_count(),
        "采样前活动线程数": 线程基线,
    }
    口径注释 = [
        "两条路径调**同一个能力、同一份固定输入**，唯一差别是 超时秒 是否给出："
        "不给 ⇒ 同线程直调；给出 ⇒ 经 `超时执行器.执行` 新建一条执行线程并等待完成事件。",
        "「每调用一线程」的代价由差值给出；裸线程基线给出其中「纯线程创建+回收」的地板价，"
        "剩余部分属于准入闸门占用/归还、完成事件等待、上下文在子线程重新进入。",
        "直调复测用于排除采样顺序漂移：复测 p50 与首测 p50 的相对偏差应远小于差值，"
        "否则本场景的差值不可信。",
        f"超时执行器为进程级单例，其线程侧准入上限为 全局 {快照.get('全局执行线程上限')} / "
        f"每能力 {快照.get('每能力执行线程上限')}；本场景串行执行，占用恒为 1，不触发限流。",
        "断言：场景结束时「仍在运行残留数」与「累计超时次数」都必须为 0，"
        "否则判场景失败 —— 不允许用泄漏的线程换取好看的数字。",
    ]
    return _场景外壳(
        场景名_线程包装开销, 轮次,
        "对比「同线程直调」与「经超时执行器线程包装」两条路径的 p50/p99 差值，"
        "并给出裸线程创建基线，为「每调用一线程开销」提供实测数据。",
        [直调测量, 包装测量, 裸线程测量, 直调复测], 口径注释,
        {
            "超时秒": 时限,
            "超时执行器快照": {
                键: 快照.get(键) for 键 in (
                    "仍在运行残留数", "累计超时次数", "全局执行线程上限",
                    "每能力执行线程上限", "全局执行线程占用", "准入后端",
                    "累计准入拒绝数", "准入释放失败数")
            },
        },
    )


