def _测量串行(名称: str, 调用: Callable[[], Any], *,
              轮数: int, 预热轮数: int, 每秒口径: str = "串行吞吐（单线程顺序调用）",
              附加结论: dict[str, Any] | None = None) -> dict[str, Any]:
    样本, 墙钟秒 = 采样串行(调用, 轮数=轮数, 预热轮数=预热轮数)
    测量 = {
        "测量项": 名称,
        **统计样本(样本),
        "墙钟秒": round(墙钟秒, 4),
        "每秒次数": 算每秒次数(len(样本), 墙钟秒),
        "每秒口径": 每秒口径,
    }
    if 附加结论:
        测量["附加结论"] = 附加结论
    return 测量


def _测量并发(名称: str, 调用: Callable[[], Any], *,
              轮数: int, 预热轮数: int, 并发数: int,
              附加结论: dict[str, Any] | None = None) -> dict[str, Any]:
    样本, 墙钟秒 = 采样并发(调用, 轮数=轮数, 预热轮数=预热轮数, 并发数=并发数)
    测量 = {
        "测量项": 名称,
        **统计样本(样本),
        "墙钟秒": round(墙钟秒, 4),
        "每秒次数": 算每秒次数(len(样本), 墙钟秒),
        "每秒口径": f"并发{并发数}吞吐（{并发数} 条线程各 {轮数} 次，按整段墙钟算）",
        "并发数": 并发数,
        "每线程轮数": 轮数,
    }
    if 附加结论:
        测量["附加结论"] = 附加结论
    return 测量


def _场景外壳(名称: str, 轮次: int, 说明: str, 测量项: list[dict[str, Any]],
              口径注释: list[str], 附加结论: dict[str, Any] | None = None) -> dict[str, Any]:
    场景 = {
        "场景": 名称, "轮次": 轮次, "说明": 说明,
        "测量项": 测量项, "口径注释": 口径注释,
    }
    if 附加结论:
        场景["附加结论"] = 附加结论
    return 场景


