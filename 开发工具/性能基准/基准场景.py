"""性能基准的四个场景实现（只用标准库）。

每个场景函数签名统一：`场景_xxx(环境, 参数, 轮次) -> dict`，返回机器可读的场景结果：
`{"场景": 名称, "轮次": k, "说明": ..., "测量项": [...], "口径注释": [...], "附加结论": {...}}`。

场景实现的三条硬规矩：
1. **只走公开入口**：能力一律经 `唯一能力调用服务` / `后端核心` / HTTP 网关调用，
   不 import 任何支持库的 `实现/`，不自己实现被测对象。
2. **不做无证据的成功**：每处调用都经 `要求成功()` 收口，失败即明确报错；
   另配**独立校验**（值相等 / 读回行数 / 残留与线程计数），防止「样本为空 → 0 毫秒」的假绿。
3. **不碰正式运行库、不加载模型**：SQLite 写独立临时库；包集由 `基准环境` 限定为纯计算包。
"""

