"""把统一任务系统接入网关：为每个正式能力注册独立进程的后台执行器。

任务在独立进程里跑，父进程只按 `任务id` 轮询；客户端断线不改任务账本，
网关重启后非终态任务收敛为「崩溃」（续跑由能力自身的缓存承担）。
本模块不改跨进程协议：执行器是闭包，fork 出的子进程直接继承。
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

from 运行核心.能力调用.运行上下文.上下文 import 运行上下文
from 运行核心.任务调度.任务系统 import 任务系统

# 网关与执行器之间的内保留键：随任务参数一起过管道，执行器取出后立即弹出，
# 能力自身永远看不到它，因此不污染任何能力契约的参数表。
任务追踪键 = "任务追踪"


# 本模块路径恒为 `<系统根>/运行核心/任务调度/任务接入.py` → parents[2] 即系统根
_系统根 = Path(__file__).resolve().parents[2]


def 默认任务存储目录() -> Path:
    """任务账本落盘目录：`系统库任务目录` → `系统底座_工程缓存根` → 唯一解析器运行缓存根。

    「有 env 时优先」语义**一字不改**：两个环境变量的读取顺序与取值原样保留
    （含相对值原样返回，不新增任何报错）。

    只改**缺省回落**：旧写法裸拼相对 `工程缓存` —— 相对路径按**当前工作目录**解析，
    而制品进程的 cwd 就是制品内，缺 env 时账本会落进不可变制品（2026-09-17 伪制品
    布局实测：默认目录解析到 `<制品>/平台客户端/工程缓存/任务状态`）。现经
    `公共契约/运行时/运行缓存.解析运行缓存根` 取运行缓存根：
    - 源码态回落 `<系统根>/工程缓存`（与旧值**同义**；cwd = 系统根时实测逐字同一路径），
      且返回绝对路径，不再随调用方 cwd 漂移；
    - 制品态回落平台受管缓存（制品外），与同平台其它运行态同根。
    """
    环境目录 = os.environ.get("系统库任务目录", "").strip()
    if 环境目录:
        return Path(环境目录)
    环境缓存根 = os.environ.get("系统底座_工程缓存根", "").strip()
    if 环境缓存根:
        return Path(环境缓存根) / "任务状态"
    from 公共契约.运行时.运行缓存 import 解析运行缓存根

    return 解析运行缓存根(_系统根) / "任务状态"


def 构造任务系统(后端核心: Any, *, 存储目录: Path | None = None) -> 任务系统:
    """建立任务系统，并把后端已装配的全部正式能力注册为可提交的后台任务。"""
    实例 = 任务系统(存储目录=存储目录 or 默认任务存储目录())
    注册全部能力(实例, 后端核心)
    return 实例


def 注册全部能力(任务系统实例: 任务系统, 后端核心: Any) -> int:
    """每个正式能力一个执行器；返回注册条数（能力清单变更后需重新装配）。"""
    注册表 = getattr(后端核心, "注册表", None)
    能力id表 = list(getattr(注册表, "能力id列表", []) or [])
    for 能力id in 能力id表:
        任务系统实例.注册执行函数(能力id, _构造执行器(后端核心, 能力id))
    return len(能力id表)


def _构造执行器(后端核心: Any, 能力id: str):
    """闭包执行器：只依赖 fork 继承的后端核心，不持有任何跨请求可变状态。"""

    def 执行(参数: dict[str, Any]) -> Any:
        追踪 = {}
        if isinstance(参数, dict):
            取出 = 参数.pop(任务追踪键, None)
            if isinstance(取出, dict):
                追踪 = 取出
        上下文 = 运行上下文(
            请求id=str(追踪.get("请求id", "")),
            来源地址=str(追踪.get("来源地址", "")),
            能力id=能力id,
            权限范围=list(追踪.get("权限范围", []) or []),
        )
        结果对象 = 后端核心.调用(能力id, 参数, 上下文=上下文)
        if 结果对象.成功:
            return 结果对象.值
        # 二元组第二项为失败标记：任务系统据此把失败错误码/说明原样回带，
        # 而不是笼统的「内部错误」。
        return {
            "错误码": 结果对象.错误码 or "内部错误",
            "错误说明": 结果对象.错误说明 or "任务执行失败",
        }, False

    return 执行
