#: 五态结论里**站在通过位**的那三个（哲学 13.2 唯一判定：退出码 0 干净通过，**可含
#: 只报告/债务冻结 信息**；1 有红失败；2 未核验 —— 未核验不占通过位）。口径唯一来源：
#: `开发工具/开发编译口/编译口.py` 头部「退出码」段。
结论_通过位 = frozenset({"干净通过", "只报告", "债务冻结"})


def _取结论字段(结果: Any, 名: str) -> Any:
    """从 `结果` 里取一个表态字段；**取不到就回 ``None``**（不猜、不编造）。

    任务通道把能力的 `值` 原样放进 `结果`（`任务进程_监视轮询面.py`：`任务对象.结果 =
    响应.get("值")`）。实测 `自修复工具.静态编译` 的 `结果` 就是归并结论字典（`五态结论` /
    `退出码` 在顶层，2026-09-24 从运行库读回任务 `8c8fb87af1e94367` 核对）。兼容 `结果` 是
    「统一结果信封」（表态字段在 `结果["值"]` 里）与对象形态两种可能，三处位置都看一眼 ——
    少看一种就会把「有结论」误判成「没结论」，正是要堵的假绿通道。
    """
    候选 = 结果
    if isinstance(候选, dict):
        if 名 in 候选:
            return 候选[名]
        内层 = 候选.get("值")
        return 内层.get(名) if isinstance(内层, dict) else None
    直接值 = getattr(候选, 名, None)
    if 直接值 is not None:
        return 直接值
    内层 = getattr(候选, "值", None)
    if isinstance(内层, dict):
        return 内层.get(名)
    return getattr(内层, 名, None)


def _按结论判状态(进程状态: str, 五态结论: Any, 退出码: Any) -> str:
    """顶层 `状态` 的对外口径：**结论没站在通过位，就不许读成「成功」**。

    现场（2026-09-24，任务 `8c8fb87af1e94367`）：`自修复工具.静态编译` 被单写者守卫
    **拒启（fail-closed）**，工作进程其实正常跑完、如实交回结论 ⇒ 进程状态是「成功」、
    `进度=1.0`，可它的 `结果.五态结论=未核验`、`退出码=2`、结论原文写着「拒启」。只看顶层
    `状态` 的调用方（忙轮询的发布门禁、按 `状态 == "成功"` 分流的脚本）把「拒启」读成了
    「通过」—— 这正是哲学 3.1 说的假绿。

    判据**退出码优先**（哲学 13.2：退出码 0/1/2 唯一判定）：`退出码 == 0` ⇒ 成功；非 0
    （1 有红 / 2 未核验）⇒ 失败。没有退出码时按 `五态结论` 判；两者都读不出来 ⇒ **失败**
    （fail-closed：解析不出来不许静默放行）。

    **只降级、不升格**：非「成功」的进程状态（等待中/运行中/取消中/已取消/超时/崩溃/失败）
    一律原样保留 —— 派生不得把「还在跑」抬成终态，也不得改写取消/超时的语义。精确档位不丢：
    同回执顶层另带 `五态结论` 与 `退出码`，故「未核验」与「失败」**不混为一谈**
    （同 `平台控制面/备份恢复/恢复执行.py` 的三态口径）。
    """
    if 进程状态 != 状态_成功:
        return 进程状态
    if isinstance(退出码, int) and not isinstance(退出码, bool):
        return 状态_成功 if 退出码 == 0 else 状态_失败
    if isinstance(五态结论, str) and 五态结论 in 结论_通过位:
        return 状态_成功
    return 状态_失败


@dataclass
class 任务:
    任务id: str
    能力id: str
    状态: str = 状态_等待中
    进度: float = 0.0
    结果: Any = None
    错误码: str = ""
    错误说明: str = ""
    创建时间: str = ""
    完成时间: str = ""
    请求id: str = ""
    项目id: str = ""
    用户id: str = ""
    取消标记: bool = 假

    def 转字典(self) -> dict[str, Any]:
        """回执投影：`状态` 按 `结果` 里的五态表态校准，并把表态原样抬到顶层。

        顶层 `状态` 只回「进程跑没跑完」是不够的 —— 编译口一族「跑完了但结论没通过」
        （拒启/有红）在旧口径下顶层读成「成功」，调用方据此判通过就是假绿（现场见
        `_按结论判状态`）。故 `结果` 带五态表态时，把 `状态` 按结论校准，并让 `五态结论` /
        `退出码` 与 `结果` 同级可见（**精确档位不丢**，读得出「未核验」与「失败」的区别）。
        """
        记录 = {
            "任务id": self.任务id, "能力id": self.能力id, "状态": self.状态,
            "进度": self.进度, "结果": self.结果, "错误码": self.错误码,
            "错误说明": self.错误说明, "创建时间": self.创建时间,
            "完成时间": self.完成时间, "请求id": self.请求id,
            "项目id": self.项目id, "用户id": self.用户id, "取消标记": self.取消标记,
        }
        五态结论 = _取结论字段(self.结果, 结论键)
        if 五态结论:
            退出码 = _取结论字段(self.结果, 退出码键)
            记录["五态结论"] = 五态结论
            if 退出码 is not None:
                记录["退出码"] = 退出码
            记录["状态"] = _按结论判状态(记录["状态"], 五态结论, 退出码)
        return 记录


class 任务系统:
    """任务门面：独立进程执行、并发安全查询、原子快照持久化。"""

    def __init__(self, 存储目录: Path | None = None, *,
                 最大活动数: int = 4, 最大排队数: int = 16,
                 提交截止秒: float = 30.0, 运行库路径: str | None = None) -> None:
        self.存储目录 = 存储目录 or Path(self.默认存储目录())
        self.存储目录.mkdir(parents=True, exist_ok=True)
        # 运行态唯一落点（华哥 2026-09-15 定盘：运行态一律入库，不再写 JSONL）。
        self.运行库路径 = 运行库路径 or self.默认运行库路径()
        self.上次落盘指纹: dict[str, str] = {}
        self.任务表: dict[str, 任务] = {}
        self.执行函数表: dict[str, Callable] = {}
        self.锁 = threading.RLock()
        self.进程池 = 任务进程池(
            存储目录=self.存储目录 / "进程任务",
            最大活动数=最大活动数, 最大排队数=最大排队数, 提交截止秒=提交截止秒,
        )
        self.同步线程: threading.Thread | None = None
        self.同步唤醒事件 = threading.Event()
        self.同步停止事件 = threading.Event()
        self.上次同步状态表: dict[str, str] = {}
        self.同步错误: str = ""
        self.加载()

    @staticmethod
    def 默认存储目录() -> str:
        return os.environ.get("系统库任务目录", str(Path(tempfile.gettempdir()) / "系统级支持库_任务"))

    @staticmethod
    def 默认运行库路径() -> str:
        """底座运行库路径（运行态唯一落点；可用 `系统库运行库` 环境变量覆盖）。"""
        环境 = os.environ.get("系统库运行库")
        if 环境:
            return 环境
        from 公共契约.运行时.运行缓存 import 解析运行数据根

        return str(解析运行数据根(Path(__file__).resolve().parents[2]) / "底座运行.db")

    def _运行库调用(self, 能力id: str, 参数: dict[str, Any]) -> Any:
        """经唯一调用入口访问底座运行库；不可用时记入 `同步错误`（可见，不静默）。"""
        try:
            from 公共契约.能力契约.调用器 import 获取能力调用器

            return 获取能力调用器().调用能力(能力id, 参数)
        except Exception as 错误:  # noqa: BLE001 —— 运行库不可用必须可见，见 同步错误
            self.同步错误 = f"运行库不可用：{错误}"
            return None

    def _读运行库(self) -> list[dict[str, Any]] | None:
        """从运行库读回任务记录；库不可用或为空时返回 None（运行库是运行态唯一落点）。"""
        结果对象 = self._运行库调用(
            "数据库连接支持库.SQLite数据库.查询运行态",
            {"数据库路径": self.运行库路径, "域": "任务", "限制": 1000, "超时秒": 10.0},
        )
        if 结果对象 is None or not 结果对象.成功:
            return None
        值 = 结果对象.值 if isinstance(结果对象.值, dict) else {}
        行列表 = 值.get("行列表") or []
        if not 行列表:
            return None
        记录表 = []
        for 行 in 行列表:
            载荷 = 行.get("载荷") if isinstance(行, dict) else None
            try:
                记录 = json.loads(载荷) if isinstance(载荷, str) and 载荷 else {}
            except json.JSONDecodeError:
                continue
            if isinstance(记录, dict) and 记录:
                记录表.append(记录)
        return 记录表 or None

    def 加载(self) -> None:
        """从**运行库**读回任务记录（运行态唯一落点）；库不可用或为空即如实停手。

        **旧账本读取腿已删**（2026-09-25 收口）：`任务.jsonl` 自 2026-09-15 定盘起就不再
        写（`_保存已加锁` 只写运行库），这条读取腿是迁移期残留 —— 留着就是同一件事的
        第二条腿（哲学 1.2）。库不可用已由 `_运行库调用` 记入 `同步错误`（可见，不静默）。

        **收敛必须立即落盘（B-08）**：非终态任务收敛成「崩溃」如果只改内存，重启后
        `进程池.查询` 会从磁盘快照 `{任务id}.json`（状态仍是「运行中」）重建对象并覆盖
        回状态，0.5 秒内把收敛结果回滚，任务永无终态。所以收敛结果必须在本次加载内
        写回运行库，让「崩溃」成为跨会话可见的事实。
        """
        记录表 = self._读运行库()
        if not 记录表:
            return
        with self.锁:
            收敛数 = 0
            for 数据 in 记录表:
                try:
                    任务对象 = 任务(**{键: 值 for 键, 值 in 数据.items() if 键 in 任务.__dataclass_fields__})
                except TypeError:
                    continue
                if 任务对象.状态 in (状态_等待中, 状态_运行中, 状态_取消中):
                    任务对象.状态 = 状态_崩溃
                    任务对象.错误码 = "崩溃"
                    任务对象.错误说明 = "进程重启，任务未完成"
                    任务对象.完成时间 = time.strftime("%Y-%m-%d %H:%M:%S")
                    收敛数 += 1
                self.任务表[任务对象.任务id] = 任务对象
            if 收敛数:
                self._保存已加锁()
            self.上次同步状态表 = {任务id: 任务对象.状态
                                   for 任务id, 任务对象 in self.任务表.items()}

    def 保存(self) -> None:
        with self.锁:
            self._保存已加锁()

    def _保存已加锁(self) -> None:
        """落盘到运行库（运行态唯一落点）；不再写 `任务.jsonl`，避免两条腿。"""
        if not self.任务表:
            return
        需要写 = {}
        for 任务对象 in self.任务表.values():
            记录 = 任务对象.转字典()
            记录["id"] = 任务对象.任务id
            指纹 = hashlib.sha256(
                json.dumps(记录, ensure_ascii=False, sort_keys=True, default=str).encode()
            ).hexdigest()
            if self.上次落盘指纹.get(任务对象.任务id) != 指纹:
                需要写[任务对象.任务id] = (记录, 指纹)
        if not 需要写:
            return
        for 任务id, (记录, 指纹) in 需要写.items():
            结果对象 = self._运行库调用(
                "数据库连接支持库.SQLite数据库.写入运行态",
                {"数据库路径": self.运行库路径, "域": "任务", "记录": 记录, "超时秒": 10.0},
            )
            if 结果对象 is None or not 结果对象.成功:
                说明 = getattr(结果对象, "错误说明", "") or "运行库不可用"
                self.同步错误 = f"任务落库失败（任务 {任务id}）：{说明}"
                return
            self.上次落盘指纹[任务id] = 指纹

    def 注册执行函数(self, 能力id: str, 函数: Callable) -> None:
        with self.锁:
            self.执行函数表[能力id] = 函数
            self.进程池.注册执行函数(能力id, 函数)

    def 提交(self, *, 能力id: str, 参数: dict | None = None, 请求id: str = "",
             项目id: str = "", 用户id: str = "", 超时秒: float = 5.0) -> 任务:
        独立对象 = self.进程池.提交(
            能力id=能力id, 参数=参数, 请求id=请求id,
            项目id=项目id, 用户id=用户id, 超时秒=超时秒,
        )
        任务对象 = 任务(
            任务id=独立对象.任务id, 能力id=能力id, 状态=独立对象.状态,
            创建时间=独立对象.创建时间, 请求id=请求id, 项目id=项目id, 用户id=用户id,
        )
        with self.锁:
            self.任务表[任务对象.任务id] = 任务对象
            self._保存已加锁()
        self._确保同步线程()
        return 任务对象

    def _确保同步线程(self) -> None:
        """任务系统内部至多保留一个后台聚合同步线程；线程意外死亡自动重建。"""
        with self.锁:
            if self.同步线程 is not None and self.同步线程.is_alive():
                return
            self.同步停止事件 = threading.Event()
            self.同步唤醒事件 = threading.Event()
            self.同步线程 = threading.Thread(
                target=self._同步循环, name="任务系统-同步", daemon=True)
            self.同步线程.start()

    def _同步循环(self) -> None:
        """单后台聚合同步：轮询**本会话待落库**任务，仅状态变化时全量持久化（fsync 降频）。

        替代原"每任务一个同步线程 + 10ms 全量 fsync"：单个线程按 0.5s
        轮询，状态变化才写盘；五终态必然伴随状态变化而全量持久化，
        崩溃收敛（加载时非终态→崩溃）语义不变。

        本线程是**终态回写的唯一收敛点**（批O）：`查询` 一族已收成纯读（不再落库），
        射程随之补上「终态但 `上次同步状态表` 还是旧值」那一类，否则被调用方先查询到
        终态的任务会永久落不了库（详见下面射程注释③）。
        """
        停止事件 = self.同步停止事件
        while not 停止事件.is_set():
            try:
                with self.锁:
                    # 射程 = **本会话任务 ∩（门面未终态 ∪ 终态但未落库）**（批K + 批O）：
                    # ① 门面只对「本会话起过工作进程」的任务有状态话语权（判据见
                    #    `_应用独立状态已加锁`），遍历跨会话历史任务纯属空转，还会把
                    #    池的**只读查询放大成写风暴**（现场：249 条逐条查，21 分钟烧
                    #    1:46 用户态；一轮遍历远超 0.5 秒 ⇒ 刚收敛的任务 10.5 分钟轮不到）；
                    # ② 池的终态一经发布不再改变（`_判定轮询` 见终态即返回 `None`），
                    #    门面已是终态就无新可同步，不必再查（省掉重建的磁盘读）；
                    # ③ **终态但还没落库的必须收**（批O）：`查询` 已是纯读（不再落库），
                    #    调用方先查询到终态时，②那条会把「已终态」当成「无新可同步」直接
                    #    跳过 ⇒ 终态永远落不了库、跨会话读回的还是「运行中」。故补一条
                    #    「门面状态 ≠ 已同步状态」：本线程落库后 `上次同步状态表` 记成新
                    #    状态，下一轮自然退出射程（收敛，不会长期空转）。
                    本会话 = self.进程池.本会话任务id
                    任务id表 = [任务id for 任务id, 任务对象 in self.任务表.items()
                                if 任务id in 本会话 and (
                                    任务对象.状态 not in _终态
                                    or self.上次同步状态表.get(任务id) != 任务对象.状态)]
                for 任务id in 任务id表:
                    with self.锁:
                        独立对象 = self._查独立对象(任务id)
                        任务对象 = self.任务表.get(任务id)
                        if 任务对象 is None:
                            continue
                        self._应用独立状态已加锁(任务对象, 独立对象)
                        if self.上次同步状态表.get(任务id) != 任务对象.状态:
                            self.上次同步状态表[任务id] = 任务对象.状态
                            self._保存已加锁()
            except Exception as 错误:
                with self.锁:
                    self.同步错误 = f"{type(错误).__name__}: {错误}"
                self.同步停止事件.set()
                print(f"任务系统-同步异常（已停止同步）: {错误}", file=sys.stderr)
                break
            self.同步唤醒事件.wait(timeout=0.5)
            self.同步唤醒事件.clear()

    @staticmethod
    def _应用独立状态已加锁(任务对象: 任务, 独立对象: Any) -> None:
        """把**本会话真实活动**的独立进程权威状态应用到门面任务上。

        **跨会话重建的快照不回写状态（B-08）**：重启后 `进程池.查询` 会从磁盘
        `{任务id}.json` 重建任务对象，那份快照停留在停机那一刻的「运行中」；`加载()` 刚把
        非终态收敛成「崩溃」，若无条件覆盖回去，收敛会在 0.5 秒内被陈旧快照回滚，任务
        永无终态。只有本会话真起过工作进程的独立任务（`本会话活动`）才有状态话语权；
        没有独立对象（本会话进程池与磁盘快照都没有的历史任务）同样以内存账本为准。
        """
        if 独立对象 is None or not getattr(独立对象, "本会话活动", 假):
            return
        if 任务对象.状态 in _终态 and 独立对象.状态 not in _终态:
            # 陈旧快照回滚闸（2026-09-25）：池的终态**一经发布不再改变**（`_判定轮询`
            # 见终态即返回 `None`），所以「门面已终态 + 独立对象非终态」只可能来自
            # `进程池.查询` 的**陈旧磁盘快照重建**（快照落盘失败/任务被驱逐时，快照仍
            # 停在「运行中」）。门面已终态就绝不许被它盖回非终态 —— 这正是「能力任务
            # 终态看不到」的直接成因（现场：任务 20 秒跑完、运行库已是终态，门面查询
            # 跑满 100 秒仍读非终态）。
            return
        任务对象.状态 = 独立对象.状态
        任务对象.进度 = 独立对象.进度
        任务对象.结果 = 独立对象.结果
        任务对象.错误码 = 独立对象.错误码
        任务对象.错误说明 = 独立对象.错误说明
        任务对象.完成时间 = 独立对象.完成时间
        任务对象.取消标记 = 独立对象.状态 in (状态_取消中, 状态_已取消)

    def _查独立对象(self, 任务id: str) -> Any:
        """查独立进程对象；本会话没有（重启后从运行库加载的历史任务）时回 ``None``。

        返回 ``None`` 是**如实表达「本会话没有该任务的独立进程权威状态」**，而不是把
        「查不到」当成异常：重启后从运行库加载的历史任务天然没有内存对象，也没有必要
        为它保留磁盘快照。旧实现直接 `进程池.查询` 抛 ``KeyError``——查询路径会把
        「重启后查历史任务」变成异常，后台同步线程更会因此整条停摆（`同步错误` 可见）。
        """
        try:
            return self.进程池.查询(任务id)
        except KeyError:
            return None

    def 查询(self, 任务id: str, 项目id: str = "", 用户id: str = "") -> 任务:
        """按任务id取门面任务对象；**只读入口不带写副作用**（批O）：本方法一次落库都不做。

        旧实现读到终态就顺手 `self._保存已加锁()`，并把状态抄进 `上次同步状态表` —— 两笔
        都是写：① 发布门禁用 `while … 查询状态(...)` **忙轮询**
        （`开发工具/发布门禁/运行发布门禁_执行项分组_真跑.py:208` 一带），于是每次轮询都落
        一次库，形成写风暴；② 抄 `上次同步状态表` 更坏 —— 后台同步线程正是拿它当「已同步」
        判据（`_同步循环`：状态与它不同才落库），被查询提前抄成终态之后，**终态永久落不了
        库**，跨会话读回的还是「运行中」。

        故本方法只做读路径该做的事：把独立进程权威状态应用到门面对象（内存刷新）。终态回写
        **唯一归收敛点** —— 后台同步线程（`_同步循环`，射程已含「终态但未落库」的条目）。
        兄弟腿 `任务进程.查询` 已按同一口径收口（批K：「查询」不登记、不驱逐、不落盘），
        本处是漏改的兄弟；`查询状态` / `查询进度` / `查询诊断` 三者都委托本方法，故一处即全族。
        """
        # 查询直接取独立进程权威状态，不能依赖后台同步线程的调度时机。
        独立对象 = self._查独立对象(任务id)
        with self.锁:
            任务对象 = self.任务表.get(任务id)
            if 任务对象 is None:
                raise KeyError(f"未知任务id: {任务id}")
            # 归属校验：任务有归属时，调用方必须匹配
            if 任务对象.项目id and 项目id and 任务对象.项目id != 项目id:
                raise KeyError(f"未知任务id: {任务id}")
            if 任务对象.用户id and 用户id and 任务对象.用户id != 用户id:
                raise KeyError(f"未知任务id: {任务id}")
            self._应用独立状态已加锁(任务对象, 独立对象)
            return 任务对象

    def 查询状态(self, 任务id: str) -> str:
        return self.查询(任务id).状态

    def 查询进度(self, 任务id: str) -> float:
        return self.查询(任务id).进度

    def 取消(self, 任务id: str, 项目id: str = "", 用户id: str = "") -> tuple[bool, str]:
        with self.锁:
            任务对象 = self.任务表.get(任务id)
            if 任务对象 is None:
                return 假, f"未知任务id: {任务id}"
            # 归属校验：任务有归属时，调用方必须匹配
            if 任务对象.项目id and 项目id and 任务对象.项目id != 项目id:
                return 假, f"未知任务id: {任务id}"
            if 任务对象.用户id and 用户id and 任务对象.用户id != 用户id:
                return 假, f"未知任务id: {任务id}"
            if 任务对象.状态 in _终态:
                return 真, f"任务已处于终态 {任务对象.状态}（取消幂等）"
            任务对象.取消标记 = 真
            任务对象.状态 = 状态_取消中
            self._保存已加锁()
        成功, 消息 = self.进程池.取消(任务id)
        独立对象 = self._查独立对象(任务id)
        if 独立对象 is None:
            # 本会话进程池没有该任务（重启后加载的历史任务）：内存账本即权威，
            # 只记下取消请求结果，不用「查不到」当成新状态来源。
            with self.锁:
                任务对象 = self.任务表.get(任务id)
                if 任务对象 is not None:
                    任务对象.取消标记 = 真
                    self._保存已加锁()
                    self.上次同步状态表[任务id] = 任务对象.状态
            return 成功, 消息
        with self.锁:
            # 状态回写**只走唯一节点** `_应用独立状态已加锁`：旧实现在这里手抄了 5 个
            # 字段（状态/错误码/错误说明/完成时间/进度），**漏了 `结果`**，也绕过了
            # 「本会话话语权」闸门 —— 同一件事两套实现即缺陷（批K 现场：任务
            # `6e392e5e99fd485a` 的池快照已写「成功 + 结果齐全」，门面运行库行却是
            # 「状态=成功、结果=null、取消标记=true」；取消标记=真 正说明这段没走
            # 唯一节点 —— 唯一节点会按状态推导该标记）。
            self._应用独立状态已加锁(任务对象, 独立对象)
            self._保存已加锁()
            self.上次同步状态表[任务id] = 任务对象.状态
        return 成功, 消息

    def 查询诊断(self, 任务id: str) -> dict[str, Any]:
        任务对象 = self.查询(任务id)
        return {"任务id": 任务对象.任务id, "状态": 任务对象.状态,
                "错误码": 任务对象.错误码, "错误说明": 任务对象.错误说明,
                "能力id": 任务对象.能力id, "请求id": 任务对象.请求id,
                "同步错误": self.同步错误,
                # 池侧最近一次快照落盘失败（fail-closed 留痕）：与 `同步错误` 同口径
                # —— 失败必须可见、不许静默；成功不自动清空，恢复与否由读的人判。
                "落盘错误": self.进程池.落盘错误}

    def 更新进度(self, 任务id: str, 进度: float) -> None:
        with self.锁:
            任务对象 = self.任务表.get(任务id)
            if 任务对象 is not None:
                任务对象.进度 = min(1.0, max(0.0, float(进度)))
                self._保存已加锁()

    def 活动任务数(self) -> int:
        return self.进程池.活动进程数()

    def 关闭全部(self) -> None:
        self.同步停止事件.set()
        self.同步唤醒事件.set()
        同步线程 = self.同步线程
        if 同步线程 is not None and 同步线程.is_alive():
            同步线程.join(timeout=2.0)
        self.进程池.关闭全部()
