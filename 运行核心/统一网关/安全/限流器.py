"""进程内固定窗口限流与并发治理（项目/用户/能力/任务/提供者五维键）。

**名字必须与实现相符（边界，不许删）**：

- **进程内**：全部状态是 `限流器` 实例上的字典与整数——`状态表`、`请求并发`、
  `任务数`、`流式连接数`。不落盘、不进权威状态库、**不跨重启保留、不跨进程/不跨实例共享**。
  「重启」等于换一个 `限流器` 实例，计数从零开始。
- **固定窗口**：窗口到点整体清零（见 `_状态`），**不是滑动窗口**；
  窗口边界前后各一波流量可以合计打到上限的两倍，这是固定窗口的固有语义。
- **五维不是五套机制**：只是同一套「固定窗口计数 + 并发计数」换了五个维度键
  （`_维度表`），五维共用同一个 `限流状态` 结构体与同一把 `锁`。
  哪几维真正被比对，取决于调用入口——见 `进入请求` / `进入任务` / `进入流式` 的说明。
- **适用面**：单进程网关 + 本机私有部署。多进程 / 多实例 / 分布式部署必须外接
  **共享限流**（本平台当前不提供），否则每个进程各自发一份配额。
- **对外契约不变**：拒绝仍返回错误码 `限流`（网关映射 HTTP 429）与既有中文错误说明。

核对手册与可复跑命令：`运行核心/统一网关/说明/限流边界说明.md`。
"""

from __future__ import annotations

import threading
import time
from collections import deque
from dataclasses import dataclass
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假

错误码_限流 = "限流"

#: 429 拒绝时给客户端的 `Retry-After` 秒数（HTTP 标准头，RFC 9110 §10.2.3）。
#: **本常量是全仓唯一真源**：`传输/网关边界面._写JSON` 与 `安全/有界服务器._写限流响应`
#: 都取这个值（后者因分层约束「不导入同目录任何模块」而就地复制，值必须一致）。
#: 为什么必须是 1 而不是 0：0 等于让客户端立刻重试 ⇒ 限流形同虚设。
建议重试秒 = 1

# 有界治理：空闲状态清理的调用间隔（每 N 次状态访问清一次，避免热路径开销）
清理间隔 = 256


@dataclass
class 限流状态:
    """一个维度键的频率与并发状态（活在本进程内存里，随实例消亡）。"""

    维度: str
    键: str
    当前并发: int = 0
    窗口开始: float = 0.0
    窗口计数: int = 0
    拒绝数: int = 0
    上限: int = 0
    最后访问: float = 0.0

    def 转字典(self) -> dict[str, Any]:
        return {
            "维度": self.维度,
            "键": self.键,
            "当前并发": self.当前并发,
            "窗口计数": self.窗口计数,
            "拒绝数": self.拒绝数,
            "上限": self.上限,
        }


class 限流器:
    """所有检查在同一把锁内完成；任一维度失败时不占用其他维度。

    边界：**进程内固定窗口**。状态只在实例内（`状态表` 与三个并发计数器），
    不落盘、不进权威状态库，**不跨重启、不跨实例、不跨进程**。
    「项目/用户/能力/任务/提供者」是同一个固定窗口计数器的五个维度键，不是五套机制。
    只适用单进程网关 + 本机私有部署；多实例部署需外部共享限流（本平台当前不提供）。
    详见模块说明与 `运行核心/统一网关/说明/限流边界说明.md`。
    """

    def __init__(
        self,
        *,
        最大并发请求: int = 50,
        最大任务数: int = 20,
        最大流式连接: int = 10,
        单项目频率: int = 500,
        单用户频率: int = 100,
        单能力频率: int = 200,
        单任务频率: int = 100,
        单提供者频率: int = 300,
        # 2026-09-16 华哥裁决：本地私有部署下按「相对安全」放宽。
        # 原 20 会让两个批量转码任务（16+4）正好占满、互相饿死；
        # 实测此时 CPU 仅 36%、磁盘 195MB/s，本机资源远未饱和。
        单维度并发: int = 40,
        窗口秒: float = 10.0,
        拒绝记录上限: int = 10000,
        状态空闲秒: float = 600.0,
    ) -> None:
        if min(最大并发请求, 最大任务数, 最大流式连接, 单维度并发) < 1:
            raise ValueError("并发上限必须大于零")
        if min(单项目频率, 单用户频率, 单能力频率, 单任务频率, 单提供者频率) < 1:
            raise ValueError("频率上限必须大于零")
        if 窗口秒 <= 0:
            raise ValueError("限流窗口必须大于零")
        if 拒绝记录上限 < 1:
            raise ValueError("拒绝记录上限必须大于零")
        if 状态空闲秒 <= 0:
            raise ValueError("状态空闲秒必须大于零")
        self.最大并发请求 = 最大并发请求
        self.最大任务数 = 最大任务数
        self.最大流式连接 = 最大流式连接
        self.单维度并发 = 单维度并发
        self.窗口秒 = 窗口秒
        self.频率上限表 = {
            "项目": 单项目频率,
            "用户": 单用户频率,
            "能力": 单能力频率,
            "任务": 单任务频率,
            "提供者": 单提供者频率,
        }
        self.拒绝记录上限 = 拒绝记录上限
        self.状态空闲秒 = 状态空闲秒
        self.锁 = threading.RLock()
        self.请求并发 = 0
        self.任务数 = 0
        self.流式连接数 = 0
        # 进程内唯一状态源：随实例生灭，不落盘、不跨重启、不跨实例。见模块说明。
        self.状态表: dict[tuple[str, str], 限流状态] = {}
        # 有界：拒绝记录只保留最近 N 条（deque maxlen），累计值另计，语义不丢
        self.拒绝记录: deque[dict[str, Any]] = deque(maxlen=拒绝记录上限)
        self.累计拒绝数 = 0
        self._清理计数 = 0

    def _维度表(
        self,
        *,
        项目id: str = "",
        用户id: str = "",
        能力id: str = "",
        任务id: str = "",
        提供者: str = "",
    ) -> list[tuple[str, str]]:
        return [(维度, 键) for 维度, 键 in (
            ("项目", 项目id), ("用户", 用户id), ("能力", 能力id),
            ("任务", 任务id), ("提供者", 提供者),
        ) if 键]

    def _状态(self, 维度: str, 键: str, 现在: float) -> 限流状态:
        标识 = (维度, 键)
        状态 = self.状态表.get(标识)
        if 状态 is None:
            状态 = 限流状态(维度=维度, 键=键, 窗口开始=现在, 上限=self.频率上限表[维度])
            self.状态表[标识] = 状态
        elif 现在 - 状态.窗口开始 >= self.窗口秒:
            状态.窗口开始 = 现在
            状态.窗口计数 = 0
        状态.最后访问 = 现在
        self._清理计数 += 1
        if self._清理计数 >= 清理间隔:
            self._清理计数 = 0
            self._清理空闲状态(现在)
        return 状态

    def _清理空闲状态(self, 现在: float) -> int:
        """有界：删除空闲超过 状态空闲秒 且当前无并发的维度状态（调用方必须已持锁）。

        只删"空闲且并发为 0"的条目，窗口（窗口秒）远小于空闲秒，不会放过频率限制。
        """
        过期 = [标识 for 标识, 状态 in self.状态表.items()
                if 状态.当前并发 <= 0 and 现在 - 状态.最后访问 > self.状态空闲秒]
        for 标识 in 过期:
            del self.状态表[标识]
        return len(过期)

    def _记录拒绝(self, 原因: str, 维度: str = "全局", 键: str = "") -> None:
        self.累计拒绝数 += 1
        self.拒绝记录.append({
            "时间": time.strftime("%Y-%m-%d %H:%M:%S"),
            "维度": 维度,
            "键": 键,
            "原因": 原因,
        })

    def 进入请求(
        self,
        *,
        项目id: str = "",
        用户id: str = "",
        能力id: str = "",
        任务id: str = "",
        提供者: str = "",
    ) -> tuple[bool, str]:
        """请求闸门：本方法**才是**比对五维频率/并发与全局并发上限的唯一入口。

        维度键只在传了非空值时建键（`_维度表` 过滤空串），所以「五维」对未传的维度不成立。
        """
        维度表 = self._维度表(
            项目id=项目id, 用户id=用户id, 能力id=能力id,
            任务id=任务id, 提供者=提供者,
        )
        with self.锁:
            if self.请求并发 >= self.最大并发请求:
                原因 = f"并发请求数超过上限 {self.最大并发请求}"
                self._记录拒绝(原因)
                return 假, f"{错误码_限流}: {原因}"
            现在 = time.monotonic()
            状态列表 = [self._状态(维度, 键, 现在) for 维度, 键 in 维度表]
            for 状态 in 状态列表:
                if 状态.当前并发 >= self.单维度并发:
                    状态.拒绝数 += 1
                    原因 = f"{状态.维度}并发超过上限"
                    self._记录拒绝(原因, 状态.维度, 状态.键)
                    return 假, f"{错误码_限流}: {原因}"
                if 状态.窗口计数 >= 状态.上限:
                    状态.拒绝数 += 1
                    原因 = f"{状态.维度}调用频率超过上限"
                    self._记录拒绝(原因, 状态.维度, 状态.键)
                    return 假, f"{错误码_限流}: {原因}"
            self.请求并发 += 1
            for 状态 in 状态列表:
                状态.当前并发 += 1
                状态.窗口计数 += 1
            return 真, ""

    def 离开请求(
        self,
        *,
        项目id: str = "",
        用户id: str = "",
        能力id: str = "",
        任务id: str = "",
        提供者: str = "",
    ) -> None:
        with self.锁:
            self.请求并发 = max(0, self.请求并发 - 1)
            现在 = time.monotonic()
            for 维度, 键 in self._维度表(
                项目id=项目id, 用户id=用户id, 能力id=能力id,
                任务id=任务id, 提供者=提供者,
            ):
                状态 = self._状态(维度, 键, 现在)
                状态.当前并发 = max(0, 状态.当前并发 - 1)

    def 进入任务(self, *, 项目id: str = "", 用户id: str = "", 能力id: str = "",
                 任务id: str = "", 提供者: str = "") -> tuple[bool, str]:
        """任务并发闸门：**只比对全局 `任务数`，不比对五维频率/并发**。

        五个维度参数当前仅用于拒绝记录，不参与判定（真要比对五维得走 `进入请求`）。
        说明：全仓目前没有调用方（网关的任务入口由 `进入请求` 覆盖），
        保留它是为将来独立的任务闸门留口子；不要据此认为「任务维」已在生效。
        """
        with self.锁:
            if self.任务数 >= self.最大任务数:
                原因 = f"任务数超过上限 {self.最大任务数}"
                self._记录拒绝(原因, "任务", 任务id)
                return 假, f"{错误码_限流}: {原因}"
            self.任务数 += 1
            return 真, ""

    def 离开任务(self) -> None:
        with self.锁:
            self.任务数 = max(0, self.任务数 - 1)

    def 进入流式(self, *, 项目id: str = "", 用户id: str = "", 能力id: str = "",
                 提供者: str = "") -> tuple[bool, str]:
        """流式并发闸门：**只比对全局 `流式连接数`，不比对五维频率/并发**。

        维度参数只进拒绝记录、不参与判定；流式的实际并发上限另有
        `运行核心/统一网关/传输/流式HTTP.py` 的 `_并发信号量`（与本闸门相互独立）。
        说明：全仓目前没有调用方，保留为将来独立闸门口子。
        """
        with self.锁:
            if self.流式连接数 >= self.最大流式连接:
                原因 = f"流式连接数超过上限 {self.最大流式连接}"
                self._记录拒绝(原因, "能力", 能力id)
                return 假, f"{错误码_限流}: {原因}"
            self.流式连接数 += 1
            return 真, ""

    def 离开流式(self) -> None:
        with self.锁:
            self.流式连接数 = max(0, self.流式连接数 - 1)

    def 状态快照(self) -> dict[str, Any]:
        with self.锁:
            return {
                "请求并发": self.请求并发,
                "任务数": self.任务数,
                "流式连接数": self.流式连接数,
                "拒绝总数": self.累计拒绝数,
                "拒绝记录保留": len(self.拒绝记录),
                "窗口秒": self.窗口秒,
                "五维状态": [状态.转字典() for 状态 in self.状态表.values()],
                # 键名沿用既有契约（不要改）：它只是「当前活着的维度-键计数器」清单，
                # 不代表五个维度各自独立生效，也不代表任何持久化。见模块说明。
            }

    def 查询拒绝记录(self) -> list[dict[str, Any]]:
        with self.锁:
            return [dict(记录) for 记录 in self.拒绝记录]
