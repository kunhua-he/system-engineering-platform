"""参数别名表：能力参数的旧名 → 正式名 归一（对外兼容层）。

2026-09-19 从 `网关核心.py` 按职责拆出。原处再导出，调用方零改动。
"""

from __future__ import annotations
from typing import Any


能力参数别名表 = {
    # 当前为空（2026-09-17 撤除最后两条）：`数据操作支持库.数据集合.集合取并集/取交集`
    # 的旧参数名是序次类占位字，按命名铁律删除；撤除前已核实**全仓零依赖**
    # （`rg` 该二字只剩本文件这两行 + 历史交付记录），故连同条目一并删除。
    # 旧名现在既不在契约参数表内、也不在别名表内 → 网关按「未知字段忽略、缺键补默认」
    # 判「缺少必填参数 集合1」，是**明确失败**而非静默放行。
    # 表本身保留：第 5 条 2 项指定「协议只增不删不改名，改名须走别名表」，这里是唯一改名落位。
}



def _应用参数别名(能力id: str, 参数: dict[str, Any]) -> dict[str, Any]:
    """把旧参数名映射成新名；两边都传时以新名为准，旧名丢弃（不报错）。"""
    映射 = 能力参数别名表.get(能力id)
    if not 映射:
        return dict(参数)
    结果 = dict(参数)
    for 旧名, 新名 in 映射.items():
        if 旧名 in 结果 and 新名 not in 结果:
            结果[新名] = 结果.pop(旧名)
        else:
            结果.pop(旧名, None)
    return 结果

