# 「本网关这一层」的边界（P1-6 结构判据）：判「抛错帧归不归本网关」。
#
# 为什么是**目录**而不是某一份文件：拆出本模块之前，网关是整份 `网关核心.py`，
# 「本层」＝那一个文件；拆开之后网关是 `运行核心/统一网关/` 这一层（协议 / 核心处理 /
# 传输 / 安全 / 运行态…），发起 `后端核心.调用` 的 `_执行` 在 `核心处理/网关执行面.py`，
