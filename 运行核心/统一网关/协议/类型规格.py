def _类型表自检() -> list[str]:
    """B-1 返潮自检：`类型匹配表` 的键必须全部属于 16 项正式类型表。

    自检对象是**契约表本身**，不是任一次调用的入参——非正式名一旦被重新加进
    `类型匹配表`（例如有人为了「让某个包先跑起来」再补一个 `数值型` 分支），
    这里立刻报出问题，避免回归到「非正式名被默认支持」的旧状态。
    返回问题清单（空列表=通过）；供门禁与发布前检查读取，不在导入期抛异常。

    E-8（2026-09-19）补第二档：**缺宽也报**。原判据只管「多」（键越界），
    不管「少」——有人从表里删掉一个键，或新增正式类型却忘了在这里登记判定函数，
    原判据一律静默放行，该类型就落进「声明了类型却谁都不校验」的假绿。
    现在两档合判：`键集 ∪ 数值类型名` 必须**恒等于** 16 项正式表。
    """
    问题: list[str] = []
    越界 = sorted(键 for 键 in 类型匹配表 if 键 not in 正式类型表)
    if 越界:
        问题.append(f"类型匹配表含非正式类型名（不在 16 项正式表内）: {越界}")
    无判定 = sorted(正式类型表 - set(类型匹配表) - set(数值类型名))
    if 无判定:
        问题.append(
            f"正式类型缺可执行判定（既不在 类型匹配表，也不在 数值类型名）: {无判定}"
        )
    return 问题



def _参数清单(声明参数: Any) -> str:
    """把参数声明渲染成一行「名*=必填」，供报错**一次带全**（`*` 标记必填）。

    2026-09-22 新增（华哥「先把浪费时间的找出原理，然后修好浪费速度的问题」）：
    本仓开发实测一批白掉 4 轮全在「猜参数名」上 —— 调用方拿不准参数名时，原先的
    「缺少必填参数 X」只给一个名字，猜错一次只前进一格，得再走一轮 `操作=能力详情`
    才拿到正确名字（而那一轮本身就是被省 token 的直觉跳过的）。
    带上全名单后，**一次猜错即可照抄正确名字**，省掉整轮探测。
    纯信息补全：不改任何判据、不放宽任何校验。
    """
    if not isinstance(声明参数, list):
        return "（无）"
    项表: list[str] = []
    for 项 in 声明参数:
        if not isinstance(项, dict):
            continue
        名 = str(项.get("名称") or "")
        if not 名:
            continue
        项表.append(f"{名}{'*' if 项.get('必填') is 真 else ''}")
    return "、".join(项表) or "（无）"


def _项结构清单(声明参数: Any) -> str:
    """把**列表型参数**的项结构渲染成一行「项名[字段*(类型)、…]」（`*`=必填）。

    2026-09-24 批R R-32 新增（与 `_参数清单` 同一处唯一节点、同一口径：**只增信息、
    不放宽任何校验**）。为什么必须有它：现场实测凑齐一次批量调用的参数**花了 5 轮** ——
    `路径清单` → `补丁清单` → `编辑列表` → `文件路径` → `旧文本`。既有报错只给参数名
    清单，**列表项的键名一个都不给**，而列表项恰恰是最难猜的一段（前 3 轮在参数名、
    后 2 轮在列表项键名）。

    **事实源只有一个**：能力契约的 `参数[].项结构`（每项 `{名称, 类型, 必填}`）。
    契约没声明就**如实留空** —— 不按 `说明` 里的散文（如「每条 {文件路径, 旧文本}」）
    反推：那是第二套口径，正则猜错时给的是**假**结构，比不给更坏（哲学第 8 条）。
    """
    if not isinstance(声明参数, list):
        return ""
    项表: list[str] = []
    for 项 in 声明参数:
        if not isinstance(项, dict) or 项.get("类型") != "列表型":
            continue
        结构 = 项.get("项结构")
        if not isinstance(结构, list) or not 结构:
            continue
        字段表: list[str] = []
        for 字段 in 结构:
            if not isinstance(字段, dict):
                continue
            名 = str(字段.get("名称") or "")
            if not 名:
                continue
            类型名 = str(字段.get("类型") or "") or "未声明类型"
            字段表.append(f"{名}{'*' if 字段.get('必填') is 真 else ''}({类型名})")
        if 字段表:
            项表.append(f"{项.get('名称')}[{'、'.join(字段表)}]")
    return "、".join(项表)


def _加项结构尾注(说明: str, 声明参数: Any) -> str:
    """给参数报错**追加**列表型参数的项结构尾注；契约没声明时**逐字返回原说明**。

    只用于「调用方自己传错」的两类失败（必填缺失 / 类型不符）；契约自身缺陷那两类
    （非正式类型名 / 未知类型）**不加**尾注 —— 那是能力作者要修的，对调用方没有信息量。
    """
    尾注 = _项结构清单(声明参数)
    if not 尾注:
        return 说明
    return f"{说明}；列表型参数的项结构：{尾注}"


def 校验能力参数(能力id: str, 声明参数: Any, 参数: dict[str, Any]) -> str:
    """按能力参数声明校验必填与类型；返回错误说明，空串=通过。

    **唯一校验点**：网关参数校验层与契约编译产物都只能调这里，任何地方
    都不得再写第二套类型表——两套类型表就是两端不对称的裂缝来源。
    """
    if not isinstance(声明参数, list):
        return f"参数不合法：能力 {能力id} 的参数契约不是列表"
    # 参数名口径（2026-09-24 批R R-1 华哥裁决「参数名一定要对齐，如果未对齐，直接给
    # 删除掉」，全文见 `开发文档/规范/网关调用最小示例.md` 规则 1）：
    # **参数名必须对齐；未对齐即剔除（回带 `被忽略参数`）**，不判红、不失败。
    # 只有「必填缺失」与「类型不符」才失败。旧行为是「未知参数即 400」——上游多传一个
    # 字段就整条调用失败，与「新增非必填字段不得影响旧调用」相冲，已废止；改成
    # fail-closed 同样不成立（同上裁决）。
    # **剔除与回带都在 `网关参数校验面` 做**（剔除＝`_过滤能力参数`，回带＝`_被忽略参数`，
    # 两条腿共调同一节点）；此前这里 `_ = sorted(set(参数) - 参数名)` 是算了又丢的
    # 第二套差集（哲学 1.2），已删。
    for 项 in 声明参数:
        if not isinstance(项, dict):
            continue
        名称 = 项.get("名称")
        if 项.get("必填") is 真 and 名称 not in 参数:
            return _加项结构尾注(
                f"参数不合法：能力 {能力id} 缺少必填参数 {名称}"
                f"（本能力参数（*=必填）：{_参数清单(声明参数)}）", 声明参数)
        if 名称 not in 参数:
            continue
        类型值 = 项.get("类型")
        类型 = 类型值 if isinstance(类型值, str) else ""
        if not 类型:
            # 没声明类型 = 没有可执行的类型承诺，不拦（声明了才校验）。
            continue
        # 旧包声明仍可能携带历史短名；先在边界归一化再严格校验，
        # 避免未知类型直接落入「未校验」分支形成假绿。
        类型 = 历史短名到正式名.get(类型, 类型)
        # B-1（2026-09-16，别名表撤除 2026-09-17）：非正式类型名 fail-closed——
        # 名字不在 16 项正式表内 → 明确拒绝（不猜语义、不静默放行）。
        if 类型 not in 正式类型表:
            return (f"参数不合法：能力 {能力id} 的参数 {名称} 声明了非正式类型名 {类型}"
                    f"（不在 16 项正式类型表内）")
        if 类型 in 数值类型名:
            try:
                合法 = 校验数值类型(参数[名称], 类型)
            except (TypeError, ValueError):
                合法 = False
            if not 合法:
                return _加项结构尾注(
                    f"参数不合法：能力 {能力id} 的参数 {名称} 必须是 {类型}", 声明参数)
            continue
        类型匹配 = 类型匹配表.get(类型)
        if 类型匹配 is None:
            # 声明了平台不认识的类型：宁可明确拒绝，也不能静默放行——
            # 放行等于这个参数永远不受任何校验，比报错危险得多。
            return f"参数不合法：能力 {能力id} 的参数 {名称} 声明了未知类型 {类型}"
        if not 类型匹配(参数[名称]):
            return _加项结构尾注(
                f"参数不合法：能力 {能力id} 的参数 {名称} 必须是 {类型}", 声明参数)
    return ""


