"""能力反馈路由面：`/平台/能力反馈*` 三条路由的 HTTP 侧实现（本地网关服务器的混入类）。

**为什么独立成文件**：这 5 个方法（+ 2 个私有辅助）原先住在 `本地网关.py`
（1222 行）的 HTTP 处理类内部，是**一条完整、自洽的路由簇**：只认 `/平台/能力反馈`
前缀，只经**唯一能力调用入口**（`公共契约.能力契约.调用器.获取能力调用器`）调用
`平台控制面.能力反馈` 的三条能力，不碰后端核心、不碰流式通道、不碰限流器。
改动频率 × 读取成本（哲学 6.1）都高，故按职责搬出。

**不是第二份实现**：`控制面.能力反馈` 的是**能力实现**（登记/查询/迁移的存储与
状态机），本文件是**HTTP 路由面**（路径解析 + 凭证门 + 响应信封 + 异常兜底），
两者职责不重叠；本文件只按能力 id 调用，不实现任何反馈存储逻辑。
``反馈处理凭证管理器``（平台处理凭证，与调用方访问凭证是两把不同的凭证）也只在
本簇使用，故一并搬来。

**对外零变化（2026-09-19 拆分）**：`本地网关.本地网关服务器` 的公开成员一个不改；
本类的成员名与签名逐字保留，宿主依赖写成**类注解**（契约）：宿主缺哪个属性当场
`AttributeError`，不会静默走各自拼路径。宿主属性口径的唯一事实源在 `本地网关.py`
`本地网关服务器.__init__`。

**导入方向**：本文件只被 `本地网关.py` 模块级导入，**不得反向导入** `本地网关.py`
（会成环）；也不导入 `统一网关` 同目录任何模块。
"""

from __future__ import annotations

import uuid
from typing import Any
from urllib.parse import parse_qs, unquote, urlsplit

from 公共契约.能力契约.调用器 import 获取能力调用器
from 公共契约.基础类型.逻辑类型 import 真, 假


class 反馈路由面:
    """`/平台/能力反馈` 路由簇：路径解析、平台处理凭证门、响应信封与异常兜底。

    宿主依赖（类注解即契约，真源＝`本地网关.本地网关服务器.__init__`）：
    ``_拒绝`` / ``_写JSON`` / ``_读请求体`` / ``_规范路径`` 由 `网关边界面` 提供；
    ``_反馈调用器`` 惰性缓存（装配完成前不触碰装配状态机）由宿主主类持有。
    """

    # ---- 宿主契约（由 本地网关.本地网关服务器 提供，只声明不赋值） ----
    headers: Any
    反馈处理凭证管理器: Any

    # 宿主服务器实例引用（由 `本地网关._构造处理类` 显式挂上：`处理类.网关服务器 = self`）
    网关服务器: Any
    反馈存储目录: str
    _反馈调用器: Any

    # ---- 宿主契约（由 网关边界面 提供） ----
    def _拒绝(self, 状态码: int, 错误码: str, 错误说明: str, 操作: str = "HTTP边界") -> None: ...
    def _写JSON(self, 状态码: int, 数据: dict[str, Any]) -> None: ...
    def _读请求体(self) -> tuple[bool, dict[str, Any], str]: ...
    def _规范路径(self) -> str: ...

    def _取反馈调用器(self):
        """唯一能力调用入口（惰性：首次反馈请求时解析，装配前不触碰状态机）。

        原为 `本地网关._构造处理类` 里的闭包 `取反馈调用器`，对宿主私有属性
        `本地网关服务器._反馈调用器` 读写；搬成宿主类方法后是**同一个存储位置、
        同一份惰性语义**（成员名 `_取反馈调用器` / `_调用反馈能力` 为新增，
        拆分前无同名成员，不构成对外面变化）。
        """
        if self.网关服务器._反馈调用器 is None:
            self.网关服务器._反馈调用器 = 获取能力调用器()
        return self.网关服务器._反馈调用器

    def _调用反馈能力(self, 能力id: str, 参数: dict[str, Any]):
        """按能力 id 调用反馈治理面能力，返回统一结果（失败带稳定错误码）。

        原为闭包 `self._调用反馈能力(能力id, 参数, 调用方="本地网关")`，调用方口径一字未改。
        """
        return self._取反馈调用器().调用能力(能力id, 参数, 调用方="本地网关")

    def _反馈响应(self, 状态码: int, 成功: bool, 值: Any = None,
                 错误码: str = "", 错误说明: str = "", 操作: str = "能力反馈") -> None:
        self._写JSON(状态码, {
            "请求id": str(self.headers.get("X-请求-id", ""))[:64] or uuid.uuid4().hex[:16],
            "操作": 操作, "成功": 成功, "值": 值 if 成功 else None,
            "错误码": 错误码 if not 成功 else "",
            "错误说明": 错误说明 if not 成功 else "",
            "句柄": None, "耗时毫秒": 0.0,
        })

    def _反馈路径段(self) -> list[str]:
        return [段 for 段 in self._规范路径().split("/") if 段]

    def _反馈处理认证(self) -> bool:
        凭证 = self.headers.get("X-Platform-Feedback-Credential", "")
        通过, _ = self.网关服务器.反馈处理凭证管理器.校验(凭证)
        if not 通过:
            self._拒绝(403, "权限不足", "反馈状态迁移需要平台处理凭证", "能力反馈状态")
            return 假
        return 真

    def _处理反馈登记(self) -> None:
        读取成功, 请求数据, 错误说明 = self._读请求体()
        if not 读取成功:
            self._反馈响应(400, 假, 错误码="参数不合法", 错误说明=错误说明,
                         操作="能力反馈登记")
            return
        结果对象 = self._调用反馈能力("平台控制面.能力反馈.登记能力反馈",
                            {"请求": 请求数据, "存储目录": self.网关服务器.反馈存储目录})
        成功, 错误码, 值 = bool(结果对象.成功), str(结果对象.错误码), 结果对象.值
        状态码 = 200 if 成功 else {"能力不存在": 404, "幂等键冲突": 409}.get(错误码, 400)
        self._反馈响应(状态码, 成功, 值, 错误码, 错误码, "能力反馈登记")

    def _处理反馈查询(self) -> None:
        段 = self._反馈路径段()
        反馈id = unquote(段[2]) if len(段) == 3 else ""
        查询 = parse_qs(urlsplit(self.path).query, encoding="utf-8")
        状态 = (查询.get("状态") or [""])[0]
        能力id = (查询.get("能力id") or [""])[0]
        限制原值 = (查询.get("限制") or ["50"])[0]
        try:
            限制 = int(限制原值)
        except (TypeError, ValueError):
            self._反馈响应(400, 假, 错误码="参数不合法", 错误说明="限制必须是整数",
                         操作="能力反馈查询")
            return
        结果对象 = self._调用反馈能力("平台控制面.能力反馈.查询能力反馈",
                            {"反馈id": 反馈id, "状态": 状态, "能力id": 能力id,
                             "限制": 限制, "存储目录": self.网关服务器.反馈存储目录})
        if not 结果对象.成功:
            self._反馈响应(400, 假, 错误码="参数不合法", 错误说明=结果对象.错误说明,
                         操作="能力反馈查询")
            return
        列表 = (结果对象.值 or {}).get("记录表", [])
        if 反馈id and not 列表:
            self._反馈响应(404, 假, 错误码="反馈不存在", 错误说明="反馈记录不存在",
                         操作="能力反馈查询")
            return
        self._反馈响应(200, 真, {"记录表": 列表, "数量": len(列表)}, 操作="能力反馈查询")

    def _处理反馈状态(self) -> None:
        if not self._反馈处理认证():
            return
        段 = self._反馈路径段()
        反馈id = unquote(段[2])
        读取成功, 请求数据, 错误说明 = self._读请求体()
        if not 读取成功:
            self._反馈响应(400, 假, 错误码="参数不合法", 错误说明=错误说明,
                         操作="能力反馈状态")
            return
        结果对象 = self._调用反馈能力("平台控制面.能力反馈.迁移能力反馈状态",
                            {"反馈id": 反馈id, "请求": 请求数据,
                             "存储目录": self.网关服务器.反馈存储目录})
        成功, 错误码, 值 = bool(结果对象.成功), str(结果对象.错误码), 结果对象.值
        状态码 = 200 if 成功 else {"反馈不存在": 404, "状态版本冲突": 409,
                                     "状态迁移不允许": 409}.get(错误码, 400)
        self._反馈响应(状态码, 成功, 值, 错误码, 错误码, "能力反馈状态")

    def _是反馈路由(self) -> bool:
        return self._规范路径() == "/平台/能力反馈" or self._规范路径().startswith("/平台/能力反馈/")

    def _反馈路由安全执行(self, 处理函数, 操作: str) -> None:
        """反馈路由统一兜底：任何异常都转 JSON 信封，禁止静默断连。

        反馈路由已完全经**唯一能力调用入口**解析（不再经 后端核心）：调用器
        未装配/装配中/装配失败，或能力实现自身抛错时，异常此前直接逃出
        do_POST —— 服务端一个字节都不回，直连看到 RemoteDisconnected，
        过本机代理（http_proxy=127.0.0.1:4780）被伪装成 502 + 空体，真因被藏住。
        「网关任何异常路径都回统一信封」是对外不变量，与 /健康 同口径。
        """
        try:
            处理函数()
        except Exception as 错误:
            try:
                self._反馈响应(
                    500, 假, None, "内部错误",
                    f"{type(错误).__name__}: {错误}", 操作)
            except Exception:
                # 连接已断，信封写不出去：不吞掉原始异常场景，交 HTTP 层收尾。
                return
