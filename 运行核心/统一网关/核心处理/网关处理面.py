class 请求处理面:
    def 处理(self, 请求: 网关请求) -> 网关响应:
        开始 = time.monotonic()
        请求id = 请求.请求id or uuid.uuid4().hex[:16]
        响应 = 网关响应(请求id=请求id, 操作=请求.操作)
        # 版本三项信息（哲学第 5 条 2 项）：回报「请求版本 / 当前版本 / 差异原因」；
        # 版本号不一致本身不失败，只有强制参数不满足才失败。
        响应.请求版本 = 请求.请求版本
        响应.当前版本 = 契约版本
        if 请求.请求版本 and 请求.请求版本 != 契约版本:
            响应.版本差异 = (
                f"请求版本 {请求.请求版本} 与当前契约版本 {契约版本} 不一致；"
                "无强制约束，按兼容放行（只有强制参数不满足才失败）"
            )
        已进入限流 = 假
        审计失败原因 = ""
        被限流 = 假
        权限拒绝 = 假
        try:
            if 请求.操作 not in 允许操作表:
                raise 操作不存在错误("未知操作")
            if not self._权限通过(请求):
                权限拒绝 = 真
                raise PermissionError("权限范围不足")
            通过, 限流原因 = self.限流器.进入请求(
                项目id=请求.项目id, 用户id=请求.用户id, 能力id=请求.能力id,
                任务id=请求.任务id, 提供者=请求.提供者,
            )
            if not 通过:
                被限流 = 真
                self._设置失败(响应, "限流")
                # 限流器返回的原因形如「限流: 请求频率超过上限 100（项目:xxx）」——
                # 带上它调用方才知道**是哪个维度**被限（原先这里把第二个返回值丢掉了，
                # 响应里只剩「限流」二字，排查时只能靠猜；哲学第 3 条 2 项：失败必须明确）。
                if 限流原因:
                    响应.错误说明 = 限流原因
            else:
                已进入限流 = 真
                响应 = self._执行幂等请求(请求, 响应)
        except 操作不存在错误:
            self._设置失败(响应, "操作不存在")
        # 异常分支 → 公开码收口：这里出现的每个码都必须在 公开错误说明表 与
        # 本地网关.公开错误码状态映射 中同时登记（批次0-3 同步纪律）。
        # KeyError 兜底=能力 id 未注册（能力 id 不存在时才是真实语义，业务分支
        # 应各自先判空，见 F-04）；FileNotFoundError=文件不存在（原先落在两张表外，
        # 已随批次0-3 登记为公开码，不再回落「请求处理失败」+500）。
        except KeyError:
            self._设置失败(响应, "能力不存在")
        except PermissionError:
            self._设置失败(响应, "权限不足")
        except FileNotFoundError:
            self._设置失败(响应, "文件不存在")
        except ValueError:
            self._设置失败(响应, "参数不合法")
        except 未知参数错误:
            # 契约层收到未声明参数（`TypeError` 子类）。缺这一支会落到 `except Exception`
            # 错报「内部错误」——把可预期的入参错误报成服务端故障，且与
            # `唯一能力调用_调用错误码._异常错误码表` 的同码映射漂移（该表映射 参数不合法）。
            # 两支必须逐码对齐（批次0-3 同步纪律，见本方法上方注释）。
            self._设置失败(响应, "参数不合法")
        except (ConnectionError, TimeoutError):
            self._设置失败(响应, "提供者不可用")
        except Exception as 错误:
            self._设置失败(响应, "内部错误")
            审计失败原因 = f"未处理异常类型: {type(错误).__name__}"
        finally:
            if 已进入限流:
                self.限流器.离开请求(
                    项目id=请求.项目id, 用户id=请求.用户id, 能力id=请求.能力id,
                    任务id=请求.任务id, 提供者=请求.提供者,
                )
            响应.耗时毫秒 = (time.monotonic() - 开始) * 1000
            # 返回体量维（2026-09-24 批R·R-23）：**只算字符数、不落正文** ——
            # 序列化口径与薄壳 `返回上限字符` 同源（`ensure_ascii=False` 的 JSON 文本长度）。
            # 算不出来按 0（体量统计绝不反噬主调用）。
            返回字符数 = 0
            try:
                返回字符数 = len(json.dumps(响应.值, ensure_ascii=False, default=str))
            except (TypeError, ValueError):
                pass
            # 耗时**只在这里产生一次**，随下面的 `self.审计.记录(... 耗时毫秒=...)` 写进
            # 权威审计账本；「哪些能力慢」由 `安全审计.慢调用报告()` 从该账本派生
            # （2026-09-21：原先另开一份「调用耗时日志」，与账本落在不同根、属同一事实的
            # 第二套实现，已删——哲学 1.2 同一件事两套实现即缺陷）。
            self.请求数 += 1
            if not 响应.成功:
                self.失败数 += 1
            self.审计.记录(
                操作=请求.操作, 用户id=请求.用户id, 项目id=请求.项目id,
                能力id=请求.能力id or 请求.目标, 请求id=请求id, 任务id=请求.任务id,
                会话id=请求.会话id, 提供者=请求.提供者,
                权限范围=请求.权限范围, 来源地址=请求.来源地址,
                成功=响应.成功, 错误码=响应.错误码,
                失败原因=审计失败原因 or 响应.错误说明,
                被限流=被限流, 权限拒绝=权限拒绝,
                耗时毫秒=响应.耗时毫秒, 返回字符数=返回字符数,
            )
            # 入参按形状计数入账（华哥 2026-09-21：「参数组合是唯一值，每一次访问同一个参数
            # 自 +1，然后返回的时候直接排序返回」）。**不写进上面的审计记录**：审计是逐条证据，
            # 入参是聚合统计，两者用途不同、量级不同（入参可以是几十 KB 的补丁文本）；
            # 合成一条会让审计账本膨胀且把长文本写进只读证据。
            # 口径/表结构/落点见 `公共契约.诊断.调用账本`；这里 fail-soft，统计失败绝不反噬主调用。
            #
            # ★ 参数级脱敏（2026-09-23；原债务行已随 2026-09-23 收口销账删除）：本行是「请求入口 → 持久账本」
            # 的唯一落点，收口前它把**入参原文**（含 `凭证`/`api_key`/`password` 等真实值）
            # 直接写进 `调用参数账.sqlite3` 的 `样例` 列 —— 只读账本里躺明文凭证。
            # 现在入账的是 `脱敏参数(请求.参数)` 的**副本**：命中敏感键名的值替换为 `已脱敏`，
            # **派发给能力的 `请求.参数` 一字不改**（真实值照常可用）。
            # 形状键与类型不受影响：真实敏感字段（`凭证`/`api_key`/`密钥`…）本就是文本型，
            # 掩码后仍是文本型，`入参形状`（分组主键）逐字不变。
            self.参数账.记一次调用(请求.能力id or 请求.目标, 脱敏参数(请求.参数))
        return 响应

    def _权限通过(self, 请求: 网关请求) -> bool:
        """进程内兼容调用可不带范围；HTTP 安全层会注入可信范围。"""
        if not 请求.权限范围:
            return 真
        需要权限 = 操作权限表.get(请求.操作, "")
        if 请求.操作 == "调用能力":
            # 能力级下沉（阶段一）：`调用能力` 一个档位盖住全部能力，只读查询与「任意命令
            # 执行」同权。这里按**能力 id** 取更细的档位，取不到就回落操作级档位（只增不改）。
            需要权限 = 能力权限表.get(请求.能力id or 请求.目标, 需要权限)
        return not 需要权限 or 需要权限 in 请求.权限范围 or "全部" in 请求.权限范围

    def _设置失败(self, 响应: 网关响应, 错误码: str) -> None:
        响应.成功 = 假
        响应.值 = None
        响应.错误码 = 错误码
        响应.错误说明 = 公开错误说明表.get(错误码, "请求处理失败")

    def _设置后端字典结果(self, 响应: 网关响应, 值: Any) -> None:
        """后端字典的兼容口径（哲学第 5 条 2 项）：信封**只增不改不删，缺键补默认**。

        旧行为是「缺任一必填键即判 502 返回结果不符合契约」——实现少写一个键就整条链路失败，
        属兼容性硬点，已废止。现在的判定分三类：
        - **缺 `成功` 键且未声明 `错误码`/`错误说明`**：视为**业务值**，按成功返回该字典
          （实现返回裸业务字典是合法用法，不该被判违约）；
        - **声明了 `错误码`/`错误说明` 但没写 `成功`**：视为实现声明的失败，取其错误码（缺则 `内部错误`）；
        - **键存在但类型不符**（`成功` 不是真正逻辑型、`错误码`/`错误说明` 不是文本）：仍判契约违约——
          类型漂移必须拦（第 3 条 2 项：失败必须明确），这条不能放宽。
        """
        if not isinstance(值, dict):
            响应.值 = 值
            return
        if "成功" not in 值:
            if "错误码" in 值 or "错误说明" in 值:
                self._设置失败(响应, str(值.get("错误码") or "内部错误"))
                响应.错误说明 = 脱敏错误信息(str(值.get("错误说明", "")))
                return
            响应.值 = 值
            return
        成功 = 值.get("成功")
        if (not isinstance(成功, bool)
                or not isinstance(值.get("错误码", ""), str)
                or not isinstance(值.get("错误说明", ""), str)):
            self._设置失败(响应, "返回结果不符合契约")
            return
        if not 成功:
            self._设置失败(响应, 值.get("错误码") or "内部错误")
            响应.错误说明 = 脱敏错误信息(值.get("错误说明", ""))
            return
        响应.值 = 值.get("值")

