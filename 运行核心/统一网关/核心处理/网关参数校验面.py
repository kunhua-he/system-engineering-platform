# 「最接近的契约参数」建议的相似度下限（difflib 口径，0~1）：低于它就不猜。
# 取 0.34 —— 实测 `路径` → `修改路径` 相似度 0.67，能点出真名；而 `路径` → `项目根`
# 这类无关名不会瞎点。**瞎点的建议比不给建议更坏**，故宁可留空。
近似名阈值 = 0.34


def 最接近的契约参数(键: str, 参数名: list[str], 取数: int = 3) -> list[str]:
    """「最接近的契约参数」**唯一相似度节点**（2026-09-24 批R R-1 收口）。

    全仓只有这一处 `difflib` 相似度口径：`调用能力`（同步腿）与 `任务提交`（异步腿）
    都经 `_被忽略参数` 共调本函数，任何地方不得再写第二套相似度实现（哲学 1.2）。
    阈值与口径见上面的 `近似名阈值`。
    """
    return difflib.get_close_matches(键, 参数名, n=取数, cutoff=近似名阈值)


