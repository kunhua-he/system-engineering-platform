def _生效解析根(项目根值: Any) -> Path | None:
    """从顶层 `项目根` 取本次调用的**路径解析基准**；取不到或不是绝对路径时返回 ``None``。

    ``None`` 的含义是「本层没有可用的基准」，交由 `公共契约.运行时.平台适配.解析路径`
    按它自己的三级兜底（环境变量 `系统平台_项目根` → 进程 cwd）处置 ——
    本函数**不**在这里复制那份兜底逻辑（否则就是第二套口径）。
    """
    if isinstance(项目根值, str) and 项目根值.strip():
        候选 = Path(项目根值).expanduser()
        if 候选.is_absolute():
            return 候选
    return None


def _归一化路径族参数(参数: dict[str, Any]) -> dict[str, Any]:
    """派发前把**路径族**入参里的相对路径改写为绝对路径（**入参归一，不是新腿**）。

    ## 为什么必须在这一层做（本函数存在的唯一理由）

    网关是**唯一一次**「已经拿到顶层 `项目根`、且还没派发」的地方：`开发工具/薄壳/薄壳服务.py`
    对每一次「调用能力」都自动补位顶层 `项目根`（华哥 2026-09-21 裁决「不要在同一个坑摔倒 2 次」），
    故本层必然握着那个基准；再往后（实现内部）只剩调用方给的裸字符串，根就丢了。
    实现层若各自解析（样本：`平台控制面/提供者/实现/能力入口.py:46` 自己写
    ``路径 if 路径.is_absolute() else (系统根目录 / 路径)``），根由本地 `parents[N]` 推出，
    在**制品态**就是制品根 —— 这正是「传相对路径回文件不存在」的病根。

    ## 这条改写是「同一腿上的入参归一」，不是新腿

    参数名 / 类型 / 必填 / 返回键**一字不改**（哲学第 5 条 2 项 + 强规范：字段类型必须冻结）：
    这里只在**派发之前**把「路径族字段的相对路径文本」换成等价的绝对路径文本。
    绝对路径原样不动，非路径族参数原样不动，空值 / 非文本原样不动。
    解析**只做「拼根」**（见 `解析路径`）—— **不查存在性**：存在性仍由实现报错，
    错误文本（如「文件不存在」）的归属与文案**逐字不变**。

    ## 判据

    哪些名字算路径族由 `公共契约.基础类型.字段名册.是路径族字段` **唯一判定**
    （本层**不得另写一份名单** —— 本层里一个路径名字面量都不许出现）；生效根取顶层
    `项目根`，取不到时落到 `解析路径` 的三级兜底。

    名单本身在 2026-09-23 补全过一次（初版只有 8 个统计口径名，`目录` / `输出目录` /
    `目标路径` / `源码根` 这类同类名当时不在集合内 ⇒ 同一件「路径语义」两套行为）。
    判据与「哪些名字**故意不入**」（`修改路径` 列表型、`相对路径`/`文档相对路径` 的基准是
    同调用的另一个入参或登记档案、格式名/通配模式/纯名/标识 等）逐条写在
    `字段名册.路径族字段名` 的上方注释里 —— 本层不复制那份判据，只在名单变动时自动生效。
    """
    if not isinstance(参数, dict) or not 参数:
        return dict(参数) if isinstance(参数, dict) else {}
    根 = _生效解析根(参数.get("项目根"))
    归一 = dict(参数)
    for 键, 值 in 参数.items():
        if not 是路径族字段(键):
            continue
        if not isinstance(值, str) or not 值.strip():
            continue
        归一[键] = str(解析路径(值, 根))
    return 归一


class 参数校验面:
    @staticmethod
    def _操作参数错误(请求: 网关请求) -> str:
        """校验网关查询操作的数值/文本参数，禁止静默回退。"""
        允许字段表 = {
            "能力目录": {"关键词", "偏移", "限制"},
            "能力搜索": {"关键词", "限制"},
            "包详情": {"包id"},
            "能力详情": {"能力id"},
            "资源状态": {"句柄"},
            "资源续租": {"句柄", "租约秒"},
            "资源关闭": {"句柄"},
            # 任务提交不在此表内：它的「参数」就是能力自身的入参，按能力契约校验
            # （见 _能力参数错误），与「调用能力」同一套规则。
            "任务查询": {"任务id"},
            "任务取消": {"任务id"},
            "热接入": set(),
        }
        允许字段 = 允许字段表.get(请求.操作)
        if 允许字段 is None:
            return ""
        参数 = 请求.参数
        # 参数名口径（2026-09-24 批R R-1 华哥裁决）：**未对齐字段一律剔除**（不判红、
        # 不失败），只有「必填缺失」与「类型不符」才失败。
        # 旧行为是「未知字段即 400」，等于上游多传一个字段就整条调用失败，属兼容性硬点，已废止；
        # 以后协议只增不删不改名（改名须走别名表），保证旧调用方永不因新增字段而失败。
        值映射 = {
            "包详情": ("包id", 参数.get("包id")),
            "能力详情": ("能力id", 参数.get("能力id") or 请求.能力id or 请求.目标),
            "资源状态": ("句柄", 参数.get("句柄") or 请求.句柄),
            "资源续租": ("句柄", 参数.get("句柄") or 请求.句柄),
            "资源关闭": ("句柄", 参数.get("句柄") or 请求.句柄),
            "任务查询": ("任务id", 参数.get("任务id") or 请求.任务id),
            "任务取消": ("任务id", 参数.get("任务id") or 请求.任务id),
        }
        缺少字段 = [字段 for 操作, (字段, 值) in 值映射.items()
                  if 请求.操作 == 操作 and not 值]
        if 缺少字段:
            return f"参数不合法：操作 {请求.操作} 缺少必填字段 {', '.join(缺少字段)}"
        if "关键词" in 参数 and not isinstance(参数["关键词"], str):
            return "参数不合法：关键词必须是文本型"
        for 字段 in ("包id", "能力id", "句柄", "任务id"):
            if 字段 in 参数 and not isinstance(参数[字段], (str, int)):
                return f"参数不合法：{字段}必须是文本型或句柄型"
        if "句柄" in 参数 and (
                isinstance(参数["句柄"], bool)
                or not isinstance(参数["句柄"], (str, int))
                or (isinstance(参数["句柄"], int) and not 1 <= 参数["句柄"] <= 999999)):
            return "参数不合法：句柄必须是有效句柄"
        if "限制" in 参数 and (
            isinstance(参数["限制"], bool) or not isinstance(参数["限制"], int)
            or 参数["限制"] < 1
        ):
            return "参数不合法：限制必须是大于等于 1 的整数型"
        if 请求.操作 == "能力目录" and "偏移" in 参数 and (
            isinstance(参数["偏移"], bool) or not isinstance(参数["偏移"], int)
            or 参数["偏移"] < 0
        ):
            return "参数不合法：偏移必须是大于等于 0 的整数型"
        return ""

    def _能力参数错误(self, 能力id: str, 参数: dict[str, Any]) -> str:
        """查注册表拿参数声明，委托唯一校验点 校验能力参数。"""
        注册表 = getattr(self.后端核心, "注册表", None)
        获取 = getattr(注册表, "获取", None)
        实现 = 获取(能力id) if callable(获取) else None
        if 实现 is None:
            return ""
        return 校验能力参数(能力id, getattr(实现, "参数", []), 参数)

    def _同步腿拒绝说明(self, 能力id: str, 参数: dict[str, Any]) -> str:
        """同步腿守卫（2026-09-23 华哥裁决）：返回**非空**=本次同步调用应拒并以此作
        错误说明；返回**空**=放行。

        规则：能力调用时，若该能力契约里 `名称 == "超时秒"` 那一项在本次调用中的
        **生效值** ≥ `同步腿超时上限秒`，则同步腿（`调用能力`）一律拒绝，只允许走
        异步腿（`任务提交`）。`< 10` 放行。

        生效值口径（唯一，三条）：
          ① 调用方显式传了 `超时秒` → 用传的值；
          ② 没传、但契约声明了 `默认值` → 用默认值；
          ③ 没传、且契约 `默认值` 为空（契约**没声明超时语义**，实测 4 个能力如此：
             `并发控制支持库.获取信号量/获取锁`、`系统核心支持库.进程管理.启动进程/
             等待进程结束`）→ **放行**。理由：生效值未知时拦它，等于凭空发明一个
             契约从未声明的默认阈值（发明数据），比漏拦更坏。
        契约里根本没有 `超时秒` 参数的能力 → 同样放行（无超时语义，规则不适用）。

        读取腿与 `_能力参数错误` 同源（同一处 `注册表.获取(能力id).参数`），不另写一份；
        类型判据放在这里只做「是不是数值」这一层 —— 参数**类型**是否合法由
        `_能力参数错误`（`校验能力参数`）先判，走到本方法时类型已过。
        """
        注册表 = getattr(self.后端核心, "注册表", None)
        获取 = getattr(注册表, "获取", None)
        实现 = 获取(能力id) if callable(获取) else None
        声明参数 = getattr(实现, "参数", None)
        if not isinstance(声明参数, list):
            return ""
        声明项 = next(
            (项 for 项 in 声明参数
             if isinstance(项, dict) and 项.get("名称") == "超时秒"),
            None,
        )
        if 声明项 is None:
            return ""
        生效值 = 参数.get("超时秒") if isinstance(参数, dict) else None
        if 生效值 is None:
            生效值 = 声明项.get("默认值")
        if 生效值 is None:
            return ""
        if isinstance(生效值, bool) or not isinstance(生效值, (int, float)):
            return ""
        生效秒 = float(生效值)
        if 生效秒 < 同步腿超时上限秒:
            return ""
        return (
            f"超时秒={生效秒:g} ≥ {同步腿超时上限秒:g}：该能力只允许走异步腿，"
            f"同步腿（调用能力）已拒绝。请改走异步腿 —— "
            f'capability_call(操作="任务提交", 能力id="{能力id}", 参数={{...}}) '
            f"拿 任务id，再 capability_call(操作=\"任务查询\", "
            f'参数={{"任务id": "<任务id>"}}) 取结果。'
        )

    def _过滤能力参数(self, 能力id: str, 参数: dict[str, Any]) -> dict[str, Any]:
        """按能力契约剔除未对齐参数名（口径：参数名必须与契约逐字对齐，未对齐即剔除、不转给实现；回带 被忽略参数 ＋ 最接近的契约参数）。

        边界归一化放在网关做，实现永远看不到未对齐参数名——否则上游多传一个字段
        会让实现收到 `TypeError`，等于把兼容性问题推给每个能力作者。

        **路径族入参的绝对化改写也在这里做**（2026-09-23）：本方法是「派发前」
        唯一必经的边界归一化点（`网关执行面` 在 `后端核心.调用` 前调用它），
        故 `_归一化路径族参数` 挂在这里 —— 见该函数的说明（为什么必须在这一层、
        以及为什么它只是同一腿上的入参归一而不是新腿）。
        """
        参数 = _归一化路径族参数(参数)
        注册表 = getattr(self.后端核心, "注册表", None)
        获取 = getattr(注册表, "获取", None)
        实现 = 获取(能力id) if callable(获取) else None
        声明参数 = getattr(实现, "参数", None)
        if not isinstance(声明参数, list):
            return dict(参数)
        参数名 = {项.get("名称") if isinstance(项, dict) else 项 for 项 in 声明参数}
        已归一 = _应用参数别名(能力id, 参数)
        return {键: 值 for 键, 值 in 已归一.items() if 键 in 参数名}

    def _被忽略参数(self, 能力id: str, 参数: dict[str, Any]) -> list[dict[str, Any]]:
        """列出会被契约剔除的入参（只增回带，不改剔除行为，2026-09-21）。

        为什么要有它：未对齐参数一律剔除是刻意口径（2026-09-24 批R R-1 华哥裁决），
        但「静默」让调用方分不清两种完全不同的情况 —— 「这个能力没这功能」与
        「我把参数名写错了」。实测踩过：给 `查询文件租约` 传 `路径`（真名 `修改路径`），
        条件被剔除后过滤器变成「取全部」⇒ 一次拿回 470KB 全表，还据此差点把平台
        判成缺陷。⇒ 剔除照旧，但**把「丢了哪些键、最接近的契约参数叫什么」说出来**。

        返回每条 `{参数名, 原因, 最接近的契约参数}`；没有被剔除项时返回空列表。
        近似名一律经**唯一相似度节点** `最接近的契约参数` 取（标准库 difflib 字符相似度，
        中文参数名按字符比：`路径` 对 `修改路径` 相似度 0.67 ⇒ 能被点出来），
        低于阈值不猜、返回空列表；两条腿（`调用能力` / `任务提交`）共调该节点。
        """
        注册表 = getattr(self.后端核心, "注册表", None)
        获取 = getattr(注册表, "获取", None)
        实现 = 获取(能力id) if callable(获取) else None
        声明参数 = getattr(实现, "参数", None)
        if not isinstance(声明参数, list):
            return []
        参数名 = [项.get("名称") if isinstance(项, dict) else 项 for 项 in 声明参数]
        参数名 = [名 for 名 in 参数名 if isinstance(名, str) and 名]
        if not 参数名:
            return []
        允许 = set(参数名)
        被忽略 = [键 for 键 in _应用参数别名(能力id, 参数)
                if 键 not in 允许 and 键 not in 横切参数名]
        if not 被忽略:
            return []
        return [
            {
                "参数名": 键,
                "原因": "该能力契约里没有这个参数，已被网关剔除",
                "最接近的契约参数": 最接近的契约参数(键, 参数名),
            }
            for 键 in 被忽略
        ]

    @staticmethod
    def _能力结果类型合法(结果对象: Any) -> bool:
        """能力返回必须是统一结果且关键字段类型固定，禁止真假值漂移。"""
        if not hasattr(结果对象, "成功") or not isinstance(结果对象.成功, bool):
            return 假
        for 字段 in ("错误码", "错误说明"):
            if not isinstance(getattr(结果对象, 字段, None), str):
                return 假
        return 真
