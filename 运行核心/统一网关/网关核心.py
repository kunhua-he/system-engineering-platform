def _应用参数别名(能力id: str, 参数: dict[str, Any]) -> dict[str, Any]:
    """把旧参数名映射成新名；两边都传时以新名为准，旧名丢弃（不报错）。"""
    映射 = 能力参数别名表.get(能力id)
    if not 映射:
        return dict(参数)
    结果 = dict(参数)
    for 旧名, 新名 in 映射.items():
        if 旧名 in 结果 and 新名 not in 结果:
            结果[新名] = 结果.pop(旧名)
        else:
            结果.pop(旧名, None)
    return 结果


