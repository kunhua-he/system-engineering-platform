    @staticmethod
    def _操作参数错误(请求: 网关请求) -> str:
        """校验网关查询操作的数值/文本参数，禁止静默回退。"""
        允许字段表 = {
            "能力目录": {"关键词", "偏移", "限制"},
            "能力搜索": {"关键词", "限制"},
            "包详情": {"包id"},
            "能力详情": {"能力id"},
            "资源状态": {"句柄"},
            "资源续租": {"句柄", "租约秒"},
            "资源关闭": {"句柄"},
            # 任务提交不在此表内：它的「参数」就是能力自身的入参，按能力契约校验
            # （见 _能力参数错误），与「调用能力」同一套规则。
            "任务查询": {"任务id"},
            "任务取消": {"任务id"},
            "热接入": set(),
        }
        允许字段 = 允许字段表.get(请求.操作)
        if 允许字段 is None:
            return ""
        参数 = 请求.参数
        # 协议兼容口径（哲学第 5 条 2 项）：**未知字段一律忽略**，只有「必填缺失」与「类型不符」才失败。
        # 旧行为是「未知字段即 400」，等于上游多传一个字段就整条调用失败，属兼容性硬点，已废止；
        # 以后协议只增不删不改名（改名须走别名表），保证旧调用方永不因新增字段而失败。
        值映射 = {
            "包详情": ("包id", 参数.get("包id")),
            "能力详情": ("能力id", 参数.get("能力id") or 请求.能力id or 请求.目标),
            "资源状态": ("句柄", 参数.get("句柄") or 请求.句柄),
            "资源续租": ("句柄", 参数.get("句柄") or 请求.句柄),
            "资源关闭": ("句柄", 参数.get("句柄") or 请求.句柄),
            "任务查询": ("任务id", 参数.get("任务id") or 请求.任务id),
            "任务取消": ("任务id", 参数.get("任务id") or 请求.任务id),
        }
        缺少字段 = [字段 for 操作, (字段, 值) in 值映射.items()
                  if 请求.操作 == 操作 and not 值]
        if 缺少字段:
            return f"参数不合法：操作 {请求.操作} 缺少必填字段 {', '.join(缺少字段)}"
        if "关键词" in 参数 and not isinstance(参数["关键词"], str):
            return "参数不合法：关键词必须是文本型"
        for 字段 in ("包id", "能力id", "句柄", "任务id"):
            if 字段 in 参数 and not isinstance(参数[字段], (str, int)):
                return f"参数不合法：{字段}必须是文本型或句柄型"
        if "句柄" in 参数 and (
                isinstance(参数["句柄"], bool)
                or not isinstance(参数["句柄"], (str, int))
                or (isinstance(参数["句柄"], int) and not 1 <= 参数["句柄"] <= 999999)):
            return "参数不合法：句柄必须是有效句柄"
        if "限制" in 参数 and (
            isinstance(参数["限制"], bool) or not isinstance(参数["限制"], int)
            or 参数["限制"] < 1
        ):
            return "参数不合法：限制必须是大于等于 1 的整数型"
        if 请求.操作 == "能力目录" and "偏移" in 参数 and (
            isinstance(参数["偏移"], bool) or not isinstance(参数["偏移"], int)
            or 参数["偏移"] < 0
        ):
            return "参数不合法：偏移必须是大于等于 0 的整数型"
        return ""

    @staticmethod
    def _请求摘要(请求: 网关请求) -> str:
        """对请求语义做稳定摘要；请求id本身不参与摘要。"""
        内容 = {
            "操作": 请求.操作, "能力id": 请求.能力id, "目标": 请求.目标,
            "参数": 请求.参数, "句柄": 请求.句柄, "获取句柄": 请求.获取句柄,
            "项目id": 请求.项目id, "用户id": 请求.用户id,
            "会话id": 请求.会话id, "任务id": 请求.任务id,
            "提供者": 请求.提供者, "超时秒": 请求.超时秒,
        }
        def _JSON默认值(值: Any):
            if isinstance(值, (bytes, bytearray, memoryview)):
                return {
                    "类型": "字节集型",
                    "base64": base64.b64encode(bytes(值)).decode("ascii"),
                }
            raise TypeError(f"请求参数包含不可摘要类型: {type(值).__name__}")
        return json.dumps(
            内容, ensure_ascii=False, sort_keys=True, separators=(",", ":"),
            allow_nan=False, default=_JSON默认值,
        )

    def _读取持久幂等(self, 请求: 网关请求) -> tuple[str, str | None] | None:
        """副作用类操作才查持久库；纯查询与未启用持久化一律 None。"""
        if 请求.操作 in 纯查询操作:
            return None
        库 = self._幂等库()
        if 库 is None:
            return None
        return 库.读取(请求.请求id)

    def _写入持久幂等(self, 请求: 网关请求, 摘要: str, 响应: 网关响应) -> None:
        """执行成功后落库；响应不可重放时记「操作已执行」标记（响应JSON 为 NULL）。"""
        if 请求.操作 in 纯查询操作:
            return
        库 = self._幂等库()
        if 库 is None:
            return
        库.写入(请求.请求id, 请求.操作, 摘要, self._响应转JSON(响应))

    def _响应转JSON(self, 响应: 网关响应) -> str | None:
        """响应可重放 → 公开信封的 JSON 文本；不可承载（字节集等）→ None。"""
        try:
            return json.dumps(响应.转字典(), ensure_ascii=False, sort_keys=True,
                              allow_nan=False)
        except (TypeError, ValueError):
            return None

    def _持久幂等结果(self, 请求: 网关请求, 响应: 网关响应, 摘要: str,
                      记录: tuple[str, str | None]) -> 网关响应:
        """持久记录命中 → 一律**不执行**，只回报结论（响应去重 / 操作去重）。"""
        记录摘要, 响应JSON = 记录
        if 记录摘要 != 摘要:
            self._设置失败(响应, "幂等键冲突")
            return 响应
        if 响应JSON is None:
            # 操作去重：副作用已执行过，但那次响应不可重放 → 绝不重复执行。
            self._设置失败(响应, "幂等键冲突")
            响应.错误说明 = (
                f"请求id {请求.请求id} 的操作已执行完成，其响应不可重放，"
                "拒绝重复执行；如需重做请换请求id")
            return 响应
        重放 = self._从JSON还原响应(响应JSON)
        if 重放 is None:
            self._设置失败(响应, "内部错误")
            return 响应
        return 重放

    def _从JSON还原响应(self, 响应JSON: str) -> 网关响应 | None:
        try:
            数据 = json.loads(响应JSON)
        except (TypeError, ValueError):
            return None
        if not isinstance(数据, dict):
            return None
        return 网关响应(**{键: 数据[键] for 键 in 幂等响应字段 if 键 in 数据})

    def _执行幂等请求(self, 请求: 网关请求, 响应: 网关响应) -> 网关响应:
        """同请求id串行执行一次并缓存结果；不同请求id不得被全局锁串行化。

        判据两层（B5）：本进程内存表优先（含「进行中」事件，同键并发只放行一次）；
        内存未命中且操作属**副作用类**时查持久库 —— 命中即**不执行**：可重放就返回
        缓存响应（响应去重），不可重放就明确回报冲突（操作去重）。
        """
        if not 请求.请求id:
            self._执行(请求, 响应)
            return 响应
        摘要 = self._请求摘要(请求)
        # 持久库预读放在锁外：库慢或不可用都不拖住其它请求；同键并发由内存表的
        # 「进行中」事件兜住（跨进程并发不在本层承诺内，见文件顶部 B5 说明）。
        持久记录 = self._读取持久幂等(请求)
        if 持久记录 is not None:
            return self._持久幂等结果(请求, 响应, 摘要, 持久记录)
        while True:
            with self._幂等锁:
                已有 = self._幂等表.get(请求.请求id)
                if 已有 is not None:
                    if 已有[0] != 摘要:
                        self._设置失败(响应, "幂等键冲突")
                        return 响应
                    return copy.deepcopy(已有[1])
                进行中 = self._幂等进行中.get(请求.请求id)
                if 进行中 is None:
                    完成事件 = threading.Event()
                    self._幂等进行中[请求.请求id] = (摘要, 完成事件)
                    break
                if 进行中[0] != 摘要:
                    self._设置失败(响应, "幂等键冲突")
                    return 响应
                完成事件 = 进行中[1]
            # 只有同一幂等键等待；其它请求已经在锁外并行执行。
            if not 完成事件.wait(timeout=max(0.1, 请求.超时秒)):
                self._设置失败(响应, "超时")
                return 响应
        try:
            self._执行(请求, 响应)
        except BaseException:
            # 异常场景不缓存部分响应；错误码映射由外层 处理 统一完成。
            with self._幂等锁:
                self._幂等进行中.pop(请求.请求id, None)
                while len(self._幂等表) > 500:
                    self._幂等表.pop(next(iter(self._幂等表)))
                完成事件.set()
            raise
        else:
            with self._幂等锁:
                self._幂等表[请求.请求id] = (摘要, copy.deepcopy(响应))
                self._幂等进行中.pop(请求.请求id, None)
                while len(self._幂等表) > 500:
                    self._幂等表.pop(next(iter(self._幂等表)))
                完成事件.set()
            # 落库在锁外：SQLite 写不进只留忽略痕迹，不影响本次响应。
            self._写入持久幂等(请求, 摘要, 响应)
        return 响应

    def _执行(self, 请求: 网关请求, 响应: 网关响应) -> None:
        if self.后端核心 is None:
            raise ConnectionError("后端核心未接入")
        操作参数错误 = self._操作参数错误(请求)
        if 操作参数错误:
            self._设置失败(响应, "参数不合法")
            响应.错误说明 = 操作参数错误
            return
        if 请求.操作 == "健康检查":
            结果对象 = self.后端核心.健康检查()
            if not 结果对象.成功:
                self._设置失败(响应, 结果对象.错误码 or "外部不可访问")
            else:
                响应.值 = 结果对象.值
        elif 请求.操作 == "能力目录":
            响应.值 = self.后端核心.能力目录(
                关键词=请求.参数.get("关键词", ""),
                偏移=请求.参数.get("偏移", 0),
                限制=请求.参数.get("限制", 20),
            )
        elif 请求.操作 == "能力搜索":
            响应.值 = self.后端核心.能力搜索(
                关键词=请求.参数.get("关键词", ""),
                限制=请求.参数.get("限制", 20),
            )
        elif 请求.操作 == "包详情":
            包id = 请求.参数.get("包id", "")
            if not 包id:
                raise ValueError("缺少包id")
            详情 = self.后端核心.包详情(包id)
            if 详情 is None:
                raise KeyError(包id)
            响应.值 = 详情
        elif 请求.操作 == "能力详情":
            能力id = 请求.参数.get("能力id", 请求.能力id)
            if not 能力id:
                raise ValueError("缺少能力id")
            详情 = self.后端核心.能力详情(能力id)
            if 详情 is None:
                raise KeyError(能力id)
            响应.值 = 详情
        elif 请求.操作 == "资源状态":
            句柄 = 请求.句柄 or str(请求.参数.get("句柄", ""))
            if not 句柄:
                raise ValueError("缺少句柄")
            状态 = self.后端核心.资源状态(句柄, 项目id=请求.项目id, 所有者=请求.用户id)
            if 状态 is None:
                # 句柄缺失属句柄域，不是能力域；与「调用能力」同报「句柄无效」。
                self._设置失败(响应, "句柄无效")
                return
            响应.值 = 状态
        elif 请求.操作 == "资源续租":
            句柄 = 请求.句柄 or str(请求.参数.get("句柄", ""))
            if not 句柄:
                raise ValueError("缺少句柄")
            状态 = self.后端核心.资源状态(句柄, 项目id=请求.项目id, 所有者=请求.用户id)
            if 状态 is None:
                self._设置失败(响应, "句柄无效")
                return
            if 状态.get("状态") != "有效":
                self._设置失败(响应, "句柄已过期")
                return
            响应.值 = self.后端核心.资源续租(
                句柄, 租约秒=请求.参数.get("租约秒", 300),
                项目id=请求.项目id, 所有者=请求.用户id,
            )
        elif 请求.操作 == "资源关闭":
            句柄 = 请求.句柄 or str(请求.参数.get("句柄", ""))
            if not 句柄:
                raise ValueError("缺少句柄")
            # 仅拦截「句柄不存在」；已失效句柄的重复关闭在句柄服务里是幂等的，不提前失败。
            状态 = self.后端核心.资源状态(句柄, 项目id=请求.项目id, 所有者=请求.用户id)
            if 状态 is None:
                self._设置失败(响应, "句柄无效")
                return
            响应.值 = self.后端核心.资源关闭(
                句柄, 项目id=请求.项目id, 所有者=请求.用户id,
            )
        elif 请求.操作 == "热接入":
            # 热接入：新增/变更包增量装配，免重启直接投产（调用需凭证）
            结果对象 = self.后端核心.热接入()
            if not 结果对象.成功:
                self._设置失败(响应, 结果对象.错误码 or "热接入失败")
                响应.错误说明 = 结果对象.错误说明 or "; ".join(结果对象.问题列表) if hasattr(结果对象, "问题列表") else 结果对象.错误说明
            else:
                响应.值 = 结果对象.值
        elif 请求.操作 == "调用能力":
            能力id = 请求.能力id or 请求.目标
            if not 能力id:
                raise ValueError("缺少能力id")
            已归一参数 = _应用参数别名(能力id, 请求.参数)
            参数错误 = self._能力参数错误(能力id, 已归一参数)
            if 参数错误:
                self._设置失败(响应, "参数不合法")
                响应.错误说明 = 参数错误
                return
            if 请求.句柄 is not None:
                状态 = self.后端核心.资源状态(
                    请求.句柄, 项目id=请求.项目id, 所有者=请求.用户id,
                )
                if 状态 is None:
                    self._设置失败(响应, "句柄无效")
                    return
                if 状态.get("状态") != "有效":
                    self._设置失败(响应, "句柄已过期")
                    return
                if 状态.get("元数据", {}).get("能力id") not in ("", 能力id):
                    self._设置失败(响应, "句柄无效")
                    return
            try:
                结果对象 = self.后端核心.调用(
                    能力id, self._过滤能力参数(能力id, 已归一参数),
                    上下文=运行上下文(
                        请求id=响应.请求id, 项目id=请求.项目id, 用户id=请求.用户id,
                        会话id=请求.会话id, 任务id=请求.任务id, 能力id=能力id,
                        提供者=请求.提供者, 权限范围=list(请求.权限范围),
                        来源地址=请求.来源地址,
                        句柄=请求.句柄,
                    ),
                    超时秒=请求.超时秒,
                )
            except TypeError as 错误:
                # 注册元数据漏标「必填」时，实现会抛缺少位置参数——这属参数问题，
                # 不是服务故障，必须明确回报（哲学第 3 条 2 项），不许变成 500 内部错误。
                # 判据＝异常类型 + 抛错帧归属（见 _是调用点缺参错误），**不按消息文案**：
                # 异常文案改字（含中文化）不影响本结论。
                if not _是调用点缺参错误(错误):
                    raise
                self._设置失败(响应, "参数不合法")
                响应.错误说明 = f"能力 {能力id} 调用参数缺少必填项：{错误}"
                return
            if not self._能力结果类型合法(结果对象):
                self._设置失败(响应, "返回结果不符合契约")
                响应.错误说明 = "能力返回结构不符合契约（成功、错误码、错误说明类型错误）"
            elif 结果对象.成功:
                响应.值 = 结果对象.值
                if 请求.句柄 is not None:
                    响应.句柄 = 请求.句柄
                elif 请求.获取句柄:
                    新句柄 = self.后端核心.资源句柄服务.创建(
                        资源id=能力id, 项目id=请求.项目id, 所有者=请求.用户id,
                        元数据={"能力id": 能力id},
                    )
                    响应.句柄 = 新句柄["句柄"]
            else:
                self._设置失败(响应, 结果对象.错误码 or "内部错误")
                if 结果对象.错误说明:
                    响应.错误说明 = 脱敏错误信息(结果对象.错误说明)
        elif 请求.操作 == "任务提交":
            if self.任务系统 is None:
                raise ConnectionError("任务系统未接入")
            能力id = 请求.能力id or 请求.目标
            if not 能力id:
                raise ValueError("缺少能力id")
            注册表 = getattr(self.后端核心, "注册表", None)
            获取 = getattr(注册表, "获取", None)
            if not callable(获取) or 获取(能力id) is None:
                self._设置失败(响应, "能力不存在")
                return
            已归一参数 = _应用参数别名(能力id, 请求.参数)
            参数错误 = self._能力参数错误(能力id, 已归一参数)
            if 参数错误:
                self._设置失败(响应, "参数不合法")
                响应.错误说明 = 参数错误
                return
            # 追踪上下文随任务参数过管道，执行器取出后立即弹出，能力看不到该键。
            from 运行核心.任务调度.任务接入 import 任务追踪键

            提交参数 = self._过滤能力参数(能力id, 已归一参数)
            提交参数[任务追踪键] = {
                "请求id": 响应.请求id, "来源地址": 请求.来源地址,
                "权限范围": list(请求.权限范围),
            }
            任务对象 = self.任务系统.提交(
                能力id=能力id, 参数=提交参数,
                请求id=响应.请求id, 项目id=请求.项目id, 用户id=请求.用户id,
                超时秒=请求.超时秒,
            )
            响应.值 = {"任务id": 任务对象.任务id, "状态": 任务对象.状态}
        elif 请求.操作 == "任务查询":
            if self.任务系统 is None:
                raise ConnectionError("任务系统未接入")
            任务id = 请求.参数.get("任务id", 请求.任务id)
            if not 任务id:
                raise ValueError("缺少任务id")
            # 「任务不存在」是**业务语义**（公开码 任务不存在 / 404），不是「能力不存在」。
            # 任务系统按约定用 KeyError 表达「查不到或不属于调用方」；让它冒到 处理() 的
            # except KeyError 兜底（那是「能力 id 未注册」的口径）就会把任务问题谎报成能力
            # 问题，调用方按「能力不存在」排查必然走错方向（哲学第 3 条 2 项：失败必须明确）。
            try:
                任务对象 = self.任务系统.查询(任务id, 项目id=请求.项目id, 用户id=请求.用户id)
            except KeyError:
                任务对象 = None
            if 任务对象 is None:
                self._设置失败(响应, "任务不存在")
                return
            响应.值 = 任务对象.转字典()
        elif 请求.操作 == "任务取消":
            if self.任务系统 is None:
                raise ConnectionError("任务系统未接入")
            任务id = 请求.参数.get("任务id", 请求.任务id)
            if not 任务id:
                raise ValueError("缺少任务id")
            # 先判定任务是否存在（含归属匹配），再谈取消动作本身是否成功：
            # 取消一个不存在的任务报「调用已取消」/409 是错误语义（调用方会以为
            # 「取消动作被取消」，实际是目标对象不存在），必须是「任务不存在」/404。
            # 只有任务真实存在、取消动作本身没跑完（进程组未确认退出）才回落
            # 「调用已取消」——那条语义对得上（与 任务系统.取消 的两类返回值一一对应）。
            try:
                self.任务系统.查询(任务id, 项目id=请求.项目id, 用户id=请求.用户id)
            except KeyError:
                self._设置失败(响应, "任务不存在")
                return
            成功, 消息 = self.任务系统.取消(任务id, 项目id=请求.项目id, 用户id=请求.用户id)
            self._设置后端字典结果(
                响应, {
                    "成功": 成功, "值": str(消息) if 成功 else None,
                    "错误码": "" if 成功 else "调用已取消",
                    "错误说明": "" if 成功 else 脱敏错误信息(str(消息)),
                },
            )
    def 处理(self, 请求: 网关请求) -> 网关响应:
        开始 = time.monotonic()
        请求id = 请求.请求id or uuid.uuid4().hex[:16]
        响应 = 网关响应(请求id=请求id, 操作=请求.操作)
        # 版本三项信息（哲学第 5 条 2 项）：回报「请求版本 / 当前版本 / 差异原因」；
        # 版本号不一致本身不失败，只有强制参数不满足才失败。
        响应.请求版本 = 请求.请求版本
        响应.当前版本 = 契约版本
        if 请求.请求版本 and 请求.请求版本 != 契约版本:
            响应.版本差异 = (
                f"请求版本 {请求.请求版本} 与当前契约版本 {契约版本} 不一致；"
                "无强制约束，按兼容放行（只有强制参数不满足才失败）"
            )
        已进入限流 = 假
        审计失败原因 = ""
        被限流 = 假
        权限拒绝 = 假
        try:
            if 请求.操作 not in 允许操作表:
                raise 操作不存在错误("未知操作")
            if not self._权限通过(请求):
                权限拒绝 = 真
                raise PermissionError("权限范围不足")
            通过, _ = self.限流器.进入请求(
                项目id=请求.项目id, 用户id=请求.用户id, 能力id=请求.能力id,
                任务id=请求.任务id, 提供者=请求.提供者,
            )
            if not 通过:
                被限流 = 真
                self._设置失败(响应, "限流")
            else:
                已进入限流 = 真
                响应 = self._执行幂等请求(请求, 响应)
        except 操作不存在错误:
            self._设置失败(响应, "操作不存在")
        # 异常分支 → 公开码收口：这里出现的每个码都必须在 公开错误说明表 与
        # 本地网关.公开错误码状态映射 中同时登记（批次0-3 同步纪律）。
        # KeyError 兜底=能力 id 未注册（能力 id 不存在时才是真实语义，业务分支
        # 应各自先判空，见 F-04）；FileNotFoundError=文件不存在（原先落在两张表外，
        # 已随批次0-3 登记为公开码，不再回落「请求处理失败」+500）。
        except KeyError:
            self._设置失败(响应, "能力不存在")
        except PermissionError:
            self._设置失败(响应, "权限不足")
        except FileNotFoundError:
            self._设置失败(响应, "文件不存在")
        except ValueError:
            self._设置失败(响应, "参数不合法")
        except (ConnectionError, TimeoutError):
            self._设置失败(响应, "提供者不可用")
        except Exception as 错误:
            self._设置失败(响应, "内部错误")
            审计失败原因 = f"未处理异常类型: {type(错误).__name__}"
        finally:
            if 已进入限流:
                self.限流器.离开请求(
                    项目id=请求.项目id, 用户id=请求.用户id, 能力id=请求.能力id,
                    任务id=请求.任务id, 提供者=请求.提供者,
                )
            响应.耗时毫秒 = (time.monotonic() - 开始) * 1000
            self.请求数 += 1
            if not 响应.成功:
                self.失败数 += 1
            self.审计.记录(
                操作=请求.操作, 用户id=请求.用户id, 项目id=请求.项目id,
                能力id=请求.能力id or 请求.目标, 请求id=请求id, 任务id=请求.任务id,
                会话id=请求.会话id, 提供者=请求.提供者,
                权限范围=请求.权限范围, 来源地址=请求.来源地址,
                成功=响应.成功, 错误码=响应.错误码,
                失败原因=审计失败原因 or 响应.错误说明,
                被限流=被限流, 权限拒绝=权限拒绝,
                耗时毫秒=响应.耗时毫秒,
            )
        return 响应
