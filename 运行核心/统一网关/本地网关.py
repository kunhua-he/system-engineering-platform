class 普通路由面(网关边界面):
    """普通调用路由簇：`POST /网关/调用` 与 `POST /网关/热接入`。

    **为什么留在本文件（而不是搬到 `网关边界面.py`）**：本簇用模块级
    `公开错误码状态映射` 把业务错误码映射成 HTTP 状态码，而该表**必须留在本文件**
    —— `开发工具/公开调用完整性门禁.py`、`开发工具/发布门禁/运行发布门禁.py`、
    `开发工具/错误码文案派生.py`、`开发工具/验证场景体检.py` 都按 AST 路径与名字
    `运行核心/统一网关/本地网关.py::公开错误码状态映射` 读取它。搬走该表或让
    `网关边界面.py` 反向导入本模块都会破坏契约或成环，故本簇与它所依赖的表同处一地。

    宿主依赖（类注解即契约）见 `网关边界面`；成员名与拆分前逐字相同。
    """

    def _处理网关请求(self) -> None:
        读取成功, 请求数据, 错误说明 = self._读请求体()
        if not 读取成功:
            状态码 = 413 if "大小上限" in 错误说明 else 400
            self._拒绝(状态码, "参数不合法", 错误说明)
            return
        # 顶层请求字段是冻结契约的一部分。**协议只增不删不改名**（哲学第 5 条 2 项）：
        # 新增字段一律先登记在这里；上游多传未登记字段不再拒绝（见下），
        # 旧名保留为别名永久可解析（如 `契约版本` 是 `请求版本` 的旧名）。
        允许顶层字段 = {
            "操作", "能力id", "目标", "参数", "句柄", "获取句柄",
            "契约版本", "请求版本", "请求id", "项目id", "用户id", "会话id",
            "任务id", "提供者", "超时秒",
        }
        未知顶层字段 = sorted(set(请求数据) - 允许顶层字段)
        if 未知顶层字段:
            # 兼容口径：未知字段**忽略**，不再 400——上游先升级、底座后升级时
            # 不该整条调用失败（旧行为是「未知即拒」，属兼容性硬点，已废止）。
            请求数据 = {键: 值 for 键, 值 in 请求数据.items()
                    if 键 in 允许顶层字段}
        文本字段 = (
            "能力id", "目标", "契约版本", "请求版本", "请求id", "项目id", "用户id",
            "会话id", "任务id", "提供者",
        )
        for 字段 in 文本字段:
            if 字段 in 请求数据 and not isinstance(请求数据[字段], str):
                self._拒绝(400, "参数不合法", f"{字段}必须是文本型")
                return
        if "请求id" in 请求数据 and len(请求数据["请求id"]) > 64:
            self._拒绝(400, "参数不合法", "请求id长度不能超过64个字符")
            return
        if self.网关服务器.禁止客户端身份 and any(
            str(请求数据.get(字段, ""))
            for 字段 in ("项目id", "用户id", "会话id", "任务id")
        ):
            self._拒绝(403, "权限不足", "项目/用户/会话/任务身份必须由网关凭证注入")
            return
        操作 = 请求数据.get("操作") or (
            "调用能力" if 请求数据.get("能力id") or 请求数据.get("目标") else ""
        )
        if not isinstance(操作, str) or not 操作:
            self._拒绝(400, "参数不合法", "缺少操作；调用能力请求必须提供能力id")
            return
        参数 = 请求数据.get("参数") if "参数" in 请求数据 else {}
        if not isinstance(参数, dict):
            self._拒绝(400, "参数不合法", "参数必须是对象", 操作)
            return
        SSL通过, SSL说明 = self.网关服务器.请求限制器.校验SSL策略(参数)
        if not SSL通过:
            self._拒绝(403, "权限不足", SSL说明, 操作)
            return
        try:
            超时原值 = 请求数据.get("超时秒", self.网关服务器.请求超时秒)
            if isinstance(超时原值, bool) or not isinstance(超时原值, (int, float)):
                # B-4（2026-09-16）：错误说明不得使用非正式类型名 `数值型`
                # （不在 16 项正式类型表内），按正式类型点名。
                raise TypeError("超时时间必须是数值（正式类型：整数型 或 双精度数型；布尔不算）")
            if not math.isfinite(float(超时原值)):
                raise ValueError("超时时间必须是有限数值")
            超时秒 = float(超时原值)
        except (TypeError, ValueError) as 错误:
            self._拒绝(400, "参数不合法", str(错误), 操作)
            return
        if 超时秒 <= 0 or 超时秒 > self.网关服务器.请求超时秒:
            self._拒绝(400, "参数不合法", "超时时间超出允许范围", 操作)
            return
        句柄原值 = 请求数据.get("句柄")
        if 句柄原值 is not None and (
            isinstance(句柄原值, bool) or not isinstance(句柄原值, int)
            or not 1 <= 句柄原值 <= 999999
        ):
            self._拒绝(400, "参数不合法", "句柄必须是 1 到 999999 的整数，只能使用网关返回值", 操作)
            return
        获取句柄 = 请求数据.get("获取句柄", 假)
        if not isinstance(获取句柄, bool):
            self._拒绝(400, "参数不合法", "获取句柄必须是逻辑型", 操作)
            return
        请求对象 = 网关请求(
            操作=操作, 能力id=请求数据.get("能力id", ""),
            目标=请求数据.get("目标", ""), 参数=参数,
            句柄=句柄原值,
            获取句柄=获取句柄,
            项目id=请求数据.get("项目id", ""),
            用户id=请求数据.get("用户id", ""),
            会话id=请求数据.get("会话id", ""),
            任务id=请求数据.get("任务id", ""),
            提供者=请求数据.get("提供者", ""),
            权限范围=sorted(self.网关服务器.安全配置.默认权限范围),
            来源地址=self.client_address[0],
            请求id=请求数据.get("请求id", self.headers.get("X-请求-id", "")),
            超时秒=超时秒,
            请求版本=str(请求数据.get("请求版本") or 请求数据.get("契约版本") or ""),
        )
        try:
            响应 = self.网关服务器.网关核心实例.处理(请求对象)
        except Exception as 错误:  # noqa: BLE001 - 网关主入口必须兜底，但细节不得丢（#157）
            # 缺陷 #157：原先固定文案「网关处理失败」且不落异常类型/消息，事后无法定位。
            # 现在把 异常类型 + 脱敏后的消息 拼进失败说明（脱敏走既有 `脱敏错误信息`，
            # 避免把请求体里的凭证泄进错误说明）。
            self._拒绝(500, "内部错误", 异常说明(错误, "网关处理失败"), 操作)
            return
        状态码 = 200
        if not 响应.成功:
            # 逐码映射见模块级 公开错误码状态映射（与 网关核心.公开错误说明表 一一对应）；
            # 缺键回落 500，因此任何新错误码都必须先登记再抛。
            状态码 = 公开错误码状态映射.get(响应.错误码, 500)
        self._写JSON(状态码, 响应.转字典())

    def _处理热接入请求(self) -> None:
        """热接入：扫描新增/变更支持库与模块，增量装配免重启投产。

        仅接受可选空请求体（未来可带 仅新增/仅变更 过滤），凭证由
        _校验边界 层强制；操作固定为 热接入，不可伪造其他操作。
        """
        读取成功, 请求数据, 错误说明 = self._读请求体()
        if not 读取成功:
            self._拒绝(400, "参数不合法", 错误说明, "热接入")
            return
        if self.网关服务器.禁止客户端身份 and any(
            str(请求数据.get(字段, ""))
            for 字段 in ("项目id", "用户id", "会话id", "任务id")
        ):
            self._拒绝(403, "权限不足", "项目/用户/会话/任务身份必须由网关凭证注入", "热接入")
            return
        请求对象 = 网关请求(
            操作="热接入", 参数={},
            权限范围=sorted(self.网关服务器.安全配置.默认权限范围),
            来源地址=self.client_address[0],
            请求id=str(self.headers.get("X-请求-id", ""))[:64],
            超时秒=self.网关服务器.请求超时秒,
        )
        try:
            响应 = self.网关服务器.网关核心实例.处理(请求对象)
        except Exception as 错误:  # noqa: BLE001 - 同上，细节不得丢（#157）
            self._拒绝(500, "内部错误", 异常说明(错误, "网关处理失败"), "热接入")
            return
        self._写JSON(200 if 响应.成功 else 400, 响应.转字典())

class 本地网关服务器(普通路由面, 反馈路由面, 流式路由面):
    """配置驱动的本机网关；默认不允许绑定非回环地址。"""

    def __init__(self, *, 网关核心实例: 网关核心, 地址: str = "127.0.0.1",
                 端口: int = 0, 配置: dict[str, Any] | None = None) -> None:
        self.网关核心实例 = 网关核心实例
        self.配置 = dict(配置 or {})
        # 幂等持久化默认开（见 网关核心 顶部 B5 说明：进程重启不丢幂等判据）。
        # 测试/演示实例经 创建测试服务器 显式关掉：那些用例用固定请求id，
        # 一旦共享持久库，上一次运行的记录会把本次真实执行「重放」掉。
        if not bool(self.配置.get("幂等持久化", 真)):
            self.网关核心实例.停用幂等持久化()
        self.地址 = str(self.配置.get("网关地址", 地址))
        self.端口 = int(self.配置.get("网关端口", 端口))
        # 2026-09-17 修复：默认值原为 10 秒，而转码/转写/精校这类能力本就需数分钟，
        # 10 秒会把它们全部判「超时」；更糟的是超时**不取消执行线程**（Python 无法强杀），
        # 于是每次超时都留下一个仍在跑的 ffmpeg → 媒体引擎被占满 → 后续请求真 -22 失败。
        # 实测：8 路配置下 2 分钟累积 30 个残留 ffmpeg，成功数 0。
        # 默认值统一取与 启动运行核心网关.py 一致的 1800 秒（30 分钟）。
        self.请求超时秒 = float(self.配置.get("请求超时秒", 1800))
        self.请求体读取超时秒 = min(10.0, max(1.0, float(self.配置.get("请求体读取超时秒", 10))))
        self.并发上限 = int(self.配置.get("并发上限", 64))
        if not 1 <= self.并发上限 <= 512:
            raise ValueError("并发上限必须在 1 到 512 之间")
        # 客户端提交的项目/用户/会话/任务字段不能作为身份来源；只有
        # 经过受信服务端上下文注入的身份才可进入核心。兼容旧测试或
        # 专用内部夹具时，必须显式传入 False，不能依赖默认放行。
        self.禁止客户端身份 = bool(self.配置.get("禁止客户端身份", 真))
        要求凭证 = bool(self.配置.get("要求凭证", 真))
        self.安全配置 = 安全配置(
            凭证环境变量=str(self.配置.get("凭证环境变量", "系统库网关凭证")),
            请求大小上限=int(self.配置.get("请求大小上限", 1024 * 1024)),
            监听地址="127.0.0.1",
            允许路径表=set(self.配置.get("允许路径表", {"/健康", "/存活", "/就绪", "/网关/调用", "/网关/流式", "/网关/流式/取消", "/网关/热接入", "/平台/能力反馈", "/能力/搜索", "/能力/目录"})),
            要求凭证=要求凭证,
            默认权限范围=set(self.配置.get("默认权限范围", {"查询", "调用", "任务"})),
            允许来源表=set(self.配置.get("允许来源表", set())),
            允许本地不验证SSL=bool(self.配置.get("允许本地不验证SSL", 假)),
        )
        self.请求限制器 = 请求限制器(self.安全配置)
        self.凭证管理器 = 凭证管理器(self.安全配置.凭证环境变量)
        # 运行态根统一走唯一解析器（2026-09-17，与已落地的 11 处同一口径）：
        # 环境变量 系统底座_工程缓存根 显式覆盖**优先**；未覆盖时源码态回落
        # <系统根>/工程缓存（与旧值解析结果逐字相同）、制品态回落平台级稳定受管缓存根。
        # 原写法 os.environ.get(…, "工程缓存") 在「缺环境变量 + 制品运行时」会回落
        # **裸相对 cwd**，把运行态写进不可变制品内部（实测制品内两种污染形态物证）。
        # 本模块只解析路径，不创建目录；源码态前缀不变由 解析运行缓存根 自身保证。
        默认缓存根 = 解析运行缓存根(Path(__file__).resolve().parents[2])
        反馈状态目录 = Path(self.配置.get(
            "反馈状态目录", str(Path(默认缓存根) / "平台控制面")))
        self.反馈处理凭证管理器 = 凭证管理器(
            str(self.配置.get("反馈处理凭证环境变量", "系统平台反馈处理凭证")))
        self.反馈处理凭证管理器.加载()
        # 反馈事实的读写动作由 平台控制面.能力反馈 的三条能力承担，网关只保留
        # 部署配置（存储目录）与唯一能力调用入口：不 import 实现、不自查注册表
        # （能力存在判定由能力侧经唯一调用入口的注册表判定，fail-closed）。
        # 调用器惰性获取：装配完成前不触碰装配状态机。
        self.反馈存储目录 = str(反馈状态目录)
        self._反馈调用器: Any = None
        # 流式通道与普通调用共用同一 HTTP 服务、线程预算和安全边界。
        # 延迟导入避免 流式HTTP.py 的类型引用与本模块形成导入环。
        from 运行核心.统一网关.传输.流式HTTP import HTTP流式管理器
        self.流式管理器 = HTTP流式管理器(最大并发通道数=self.并发上限)
        self.服务器: 有界线程HTTP服务器 | None = None
        self.线程: threading.Thread | None = None

    @classmethod
    def 创建测试服务器(cls, *, 网关核心实例: 网关核心,
                 地址: str = "127.0.0.1", 端口: int = 0,
                 配置: dict[str, Any] | None = None) -> "本地网关服务器":
        """测试/演示专用显式构造器；生产构造器不得隐式免凭证。"""
        测试配置 = dict(配置 or {})
        测试配置["要求凭证"] = 假
        # 测试/演示实例不落幂等库：用例里的固定请求id 不得被上一次运行的记录重放。
        测试配置["幂等持久化"] = 假
        return cls(网关核心实例=网关核心实例, 地址=地址, 端口=端口, 配置=测试配置)

    def 启动(self) -> tuple[bool, str]:
        地址通过, 地址消息 = self.请求限制器.校验监听地址(self.地址)
        if not 地址通过:
            return 假, 地址消息
        try:
            校验应用监听端口(self.端口)
        except (TypeError, ValueError) as 错误:
            return 假, str(错误)
        if self.安全配置.要求凭证:
            凭证通过, 凭证消息 = self.凭证管理器.加载()
            if not 凭证通过:
                return 假, 凭证消息
        try:
            self.服务器 = 有界线程HTTP服务器(
                (self.地址, self.端口), self._构造处理类(),
                最大工作线程=self.并发上限,
            )
        except (OSError, ValueError):
            return 假, "端口占用或监听地址不可用"
        self.端口 = int(self.服务器.server_address[1])
        self.线程 = threading.Thread(target=self.服务器.serve_forever, daemon=True)
        self.线程.start()
        return 真, f"网关已启动 http://{self.地址}:{self.端口}"

    def 优雅停止(self) -> tuple[bool, str]:
        服务器 = self.服务器
        线程 = self.线程
        self.服务器 = None
        self.线程 = None
        if 服务器 is not None:
            服务器.shutdown()
            服务器.server_close()
        if 线程 is not None and 线程.is_alive():
            线程.join(timeout=max(1.0, self.请求超时秒))
        self.凭证管理器.清除()
        return 真, "网关已优雅停止"

    def _构造处理类(self):
        """组装 HTTP 处理类（保持唯一事实源在本方法）。

        原实现把宿主属性拷进闭包变量再被嵌套 `处理类` 直接捕获。2026-09-19 拆分后
        实现分居 `网关边界面` / `反馈路由面` / `流式路由面` 三个混入类，它们只经
        **`self.` 同名属性**读取宿主状态（成员名一个不改）。故这里不再需要任何
        属性副本，`处理类` 只负责：HTTP 继承、套接字超时、公开名转发。
        """
        请求超时秒 = self.请求超时秒

        # 混入顺序＝依赖顺序：处理路由的用 `_拒绝`/`_写JSON`（网关边界面），
        # 反之不成立；路由簇之间互不调用。HTTP 层仍由 BaseHTTPRequestHandler 收口。
        class 处理类(普通路由面, 反馈路由面, 流式路由面, BaseHTTPRequestHandler):
            def setup(self) -> None:
                super().setup()
                self.connection.settimeout(请求超时秒)

            def log_message(self, 格式: str, *参数: Any) -> None:
                return

        # 混入类（网关边界面/反馈路由面/流式路由面/普通路由面）的宿主属性
        # （请求限制器/凭证管理器/安全配置/流式管理器/请求超时秒/…）住在**服务器实例**上，
        # 而混入类混入的是**处理器类**（处理器持有 headers/wfile/client_address）。
        # 故显式挂一个服务器引用：成员名 `网关服务器` 为新增（拆分前无同名成员），
        # 混入类一律经 `self.网关服务器.X` 读取宿主属性，唯一存储位置不变。
        处理类.网关服务器 = self

        return 处理类

    def 连接诊断快照(self) -> list[dict[str, Any]]:
        服务器 = self.服务器
        return 服务器.连接诊断快照() if 服务器 is not None else []


def 检查端口可用(端口: int) -> bool:
    """只探测本机回环地址，并确保套接字总能关闭。"""
    套接字 = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        套接字.bind(("127.0.0.1", 端口))
        return 真
    except OSError:
        return 假
    finally:
        套接字.close()
