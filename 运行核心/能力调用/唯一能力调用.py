"""唯一能力调用服务：所有入口（HTTP/Agent/MCP/项目代码）经同一调用服务。

收敛能力注册、提供者选择、能力调用和证据采集：
- 能力注册表是唯一权威（重复注册失败，只允许参数形状一致的幂等重放）。
- 调用者只持能力 id 与契约版本；提供者选择、参数校验、证据采集由本服务完成。
- 调用者不得持有第三方对象、连接、线程、进程或原生句柄。
- 正式代码、项目适配层与项目测试不得导入支持库/提供者/实现源码；
  唯一能力调用服务是模块按能力 id 调用支持库的唯一通道。
"""

from __future__ import annotations

import threading
from dataclasses import dataclass, field
from typing import Any, Callable

from 公共契约.能力契约.契约 import 能力注册表, 能力实现
from 公共契约.基础类型.结果类型 import 结果 as 统一结果类型
from 运行核心.能力调用.控制调用.证据链 import 调用证据, 证据链, 版本锁定
from 运行核心.能力调用.运行上下文.上下文 import 运行上下文, 全局上下文管理器
from 公共契约.基础类型.逻辑类型 import 真, 假


@dataclass
class 调用记录:
    """一次唯一能力调用的完整记录。"""

    能力id: str
    请求id: str
    调用方: str = ""
    项目id: str = ""
    成功: bool = 真
    错误码: str = ""
    错误说明: str = ""
    耗时秒: float = 0.0
    模块版本: str = ""
    支持库包id: str = ""
    提供者版本: str = ""
    制品摘要: str = ""
    资源释放结论: str = ""
    证据: 调用证据 | None = None

    def 转字典(self) -> dict[str, Any]:
        return {
            "能力id": self.能力id, "请求id": self.请求id, "调用方": self.调用方,
            "项目id": self.项目id, "成功": self.成功, "错误码": self.错误码,
            "错误说明": self.错误说明, "耗时秒": self.耗时秒,
            "模块版本": self.模块版本, "支持库包id": self.支持库包id,
            "提供者版本": self.提供者版本, "制品摘要": self.制品摘要,
            "资源释放结论": self.资源释放结论,
            "证据": self.证据.转字典() if self.证据 is not None else None,
        }


class 唯一能力调用服务:
    """唯一能力调用服务：注册、选择、调用、证据。

    用法（加载器装配后注入模块）：
        服务 = 唯一能力调用服务(注册表)
        模块入口.绑定唯一调用服务(服务)
    模块实现内：
        from 模块库.X import 获取唯一调用服务
        服务 = 获取唯一调用服务()
        return 服务.调用能力("办公文档支持库.表格文档.生成表格文档", {"内容参数": ...})
    """

    def __init__(self, 注册表: 能力注册表, *, 启用证据链: bool = 真) -> None:
        if not isinstance(注册表, 能力注册表):
            raise TypeError("唯一能力调用服务必须绑定权威能力注册表")
        self.注册表 = 注册表
        self.证据链 = 证据链() if 启用证据链 else None
        self.版本锁定 = 版本锁定()
        self.锁 = threading.RLock()
        self._模块调用服务表: dict[str, "唯一能力调用服务"] = {}
        self._调用历史: list[调用记录] = []
        self._历史上限 = 500
        # 包指纹校验（正式环境防静默漂移）：由核心注入校验回调，调用前校验
        # 该能力所属包的制品/源码指纹是否与注册时一致；不一致即报错，不静默
        # 沿用旧实现。测试/开发环境不注入时不产生任何额外开销。
        self._包指纹校验器 = None
        self._包指纹缓存: dict[str, tuple[float, bool, str]] = {}
        self._包指纹缓存秒 = 1.0

    def 设置包指纹校验器(self, 校验函数) -> None:
        """注入包指纹校验回调：接收包id，返回 (是否一致, 说明)。"""
        with self.锁:
            self._包指纹校验器 = 校验函数
            self._包指纹缓存.clear()

    def 清空包指纹缓存(self) -> None:
        """热接入重新注册指纹后清缓存，避免沿用旧的漂移判定。"""
        with self.锁:
            self._包指纹缓存.clear()

    def _校验包指纹(self, 包id: str) -> tuple[str, str] | None:
        """校验包指纹；一致返回 None，漂移返回 (错误码, 错误说明)。

        带 1 秒缓存：同一包在缓存窗口内不重复扫描，漂移检测延迟不超过 1 秒。
        """
        校验器 = self._包指纹校验器
        if 校验器 is None or not 包id:
            return None
        import time as _时间模块
        现在 = _时间模块.monotonic()
        with self.锁:
            缓存 = self._包指纹缓存.get(包id)
            if 缓存 is not None and 现在 - 缓存[0] < self._包指纹缓存秒:
                一致, 说明 = 缓存[1], 缓存[2]
            else:
                try:
                    一致, 说明 = 校验器(包id)
                except Exception as 异常:
                    一致, 说明 = 假, f"包指纹校验异常: {异常}"
                self._包指纹缓存[包id] = (现在, 一致, 说明)
        if 一致:
            return None
        错误码 = "制品缺失" if "缺失" in 说明 else "制品已变更"
        return 错误码, 说明 or f"包 {包id} 指纹与注册时不一致，请重新热接入"

    # ── 模块绑定 ──────────────────────────────────────────────

    def 绑定模块(self, 模块id: str) -> "唯一能力调用服务":
        """把本服务注入指定模块（模块只持能力 id，不直接导入支持库）。"""
        with self.锁:
            self._模块调用服务表[模块id] = self
            return self

    def 已绑定模块(self, 模块id: str) -> bool:
        with self.锁:
            return 模块id in self._模块调用服务表

    # ── 调用 ──────────────────────────────────────────────────

    @staticmethod
    def _规范化结果(值: Any) -> 统一结果类型:
        """跨包字典必须完整满足统一结果契约；原子值仍由适配边界包装。"""
        if isinstance(值, 统一结果类型):
            return 值
        if isinstance(值, dict):
            必填字段 = {"成功", "值", "错误码", "错误说明"}
            if not 必填字段.issubset(值):
                return 统一结果类型.失败(
                    "返回结果不符合契约", "字典返回缺少统一结果字段",
                )
            if (not isinstance(值.get("成功"), bool)
                    or not isinstance(值.get("错误码"), str)
                    or not isinstance(值.get("错误说明"), str)):
                return 统一结果类型.失败(
                    "返回结果不符合契约", "字典返回的统一结果字段类型不正确",
                )
            if 值["成功"]:
                return 统一结果类型.成功结果(值["值"])
            return 统一结果类型.失败(值["错误码"] or "调用失败", 值["错误说明"])
        return 统一结果类型.成功结果(值)

    def 请求(self, 目标: str, 参数: dict[str, Any] | None = None,
             句柄: str | None = None) -> Any:
        """历史适配入口：文本句柄只在此转换，统一调用入口只接收整数。

        不携带句柄表示一次性调用；当前无状态能力执行完即由其实现释放。
        有状态 Provider 接入后，句柄只作为不透明值向下传递，调用方不接触
        执行单元、租约或第三方对象。
        """
        if not isinstance(目标, str) or not 目标.strip():
            return self._失败("参数不合法", "目标不能为空")
        if 参数 is not None and not isinstance(参数, dict):
            return self._失败("参数不合法", "参数必须是字典")
        if 句柄 is None:
            统一句柄 = None
        elif isinstance(句柄, str) and 句柄.isdecimal() and 1 <= int(句柄) <= 999999:
            统一句柄 = int(句柄)
        else:
            return self._失败("参数不合法", "历史文本句柄必须表示 1 到 999999 的整数")
        return self.调用能力(目标, 参数 or {}, 句柄=统一句柄)

    def 调用能力(self, 能力id: str, 参数: dict[str, Any] | None = None, *,
                 调用方: str = "", 项目id: str = "", 超时秒: float | None = None,
                 句柄: int | None = None) -> Any:
        """按能力 id 调用唯一注册实现，返回统一 结果。

        参数校验、证据采集在此统一完成；调用方不接触提供者。
        证据字段（S0生产事实冻结第五节）：请求id/模块版本/能力id/支持库包id/
        提供者版本/制品摘要/成功失败/资源释放结论；调用前后版本锁定并释放，
        失败路径同样记录完整证据与释放结论。
        """
        import time as _时间模块
        开始 = _时间模块.monotonic()
        # 统一公开句柄冻结为整数；历史字符串只允许进程内连接器这个显式
        # 适配层进入，并在跨越唯一调用边界前立即归一。
        if isinstance(句柄, str) and 调用方 == "进程内连接器" and 句柄.isdecimal():
            句柄 = int(句柄)
        if 句柄 is not None and (
            isinstance(句柄, bool) or not isinstance(句柄, int)
            or not 1 <= 句柄 <= 999999
        ):
            return self._失败("参数不合法", "句柄必须是 1 到 999999 的整数")
        上下文 = 全局上下文管理器.当前()
        请求id = 上下文.请求id or ""
        实现 = self.注册表.获取(能力id)
        证据 = None
        if self.证据链 is not None:
            支持库id = _包归属(实现)
            证据 = self.证据链.开始调用(
                项目=项目id or 上下文.项目id,
                功能模块=上下文.模块id,
                支持库=支持库id,
                支持库包id=实现.包id if 实现 is not None else "",
                提供者=实现.提供者id if 实现 is not None else "",
                提供者版本=实现.提供者版本 if 实现 is not None else "",
                能力id=能力id,
                版本=实现.版本 if 实现 is not None else "",
                模块版本=上下文.包版本,
                制品摘要=实现.制品摘要 if 实现 is not None else "",
                任务id=上下文.任务id,
            )
        锁定请求id = 证据.请求id if 证据 is not None else 请求id
        版本锁定 = self.版本锁定
        已锁定 = 假
        if 实现 is not None and 版本锁定 is not None:
            if 版本锁定.锁定(
                请求id=锁定请求id, 包id=实现.包id,
                版本=实现.版本 or "", 提供者版本=实现.提供者版本 or "",
            ):
                已锁定 = 真
        try:
            if 实现 is None:
                return self._失败并记录(证据, "能力不存在", f"能力未注册: {能力id}",
                                         版本锁定, 锁定请求id, 已锁定, 请求id, 调用方,
                                         项目id, 上下文, 开始, 模块版本=上下文.包版本,
                                         支持库id="", 提供者版本="", 制品摘要="")
            if 参数 is None:
                参数 = {}
            if not isinstance(参数, dict):
                return self._失败并记录(证据, "参数不合法", f"能力 {能力id} 参数必须是字典",
                                         版本锁定, 锁定请求id, 已锁定, 请求id, 调用方,
                                         项目id, 上下文, 开始, 模块版本=上下文.包版本,
                                         支持库id=实现.包id, 提供者版本=实现.提供者版本,
                                         制品摘要=实现.制品摘要)
            # 制品/源码指纹校验（正式环境开启）：被改动但未重新热接入即报错，
            # 不静默沿用旧实现；测试/开发环境未注入校验器时零开销。
            指纹结论 = self._校验包指纹(实现.包id)
            if 指纹结论 is not None:
                return self._失败并记录(证据, 指纹结论[0], 指纹结论[1],
                                         版本锁定, 锁定请求id, 已锁定, 请求id, 调用方,
                                         项目id, 上下文, 开始, 模块版本=上下文.包版本,
                                         支持库id=实现.包id, 提供者版本=实现.提供者版本,
                                         制品摘要=实现.制品摘要)
            调用参数 = _展开参数(实现, 参数)
            # 「超时秒」必须真用（P0 B-02）：给了有效时限就走真实超时执行 ——
            # 到点即返回，调用方线程（HTTP 工作线程）立刻归还；执行单元若杀不掉，
            # 如实登记进残留账本，绝不用「执行异常」冒充超时检出（见 超时执行 模块）。
            原始结果, 超时残留 = self._执行实现(实现, 调用参数, 超时秒, 能力id, 请求id)
            if 超时残留 is not None:
                return self._超时并记录(
                    证据, 超时残留, 版本锁定, 锁定请求id, 已锁定, 请求id, 调用方,
                    项目id, 上下文, 开始)
            结果 = self._规范化结果(原始结果)
            耗时 = _时间模块.monotonic() - 开始
            资源释放结论 = _释放版本锁(版本锁定, 锁定请求id, 已锁定)
            if 证据 is not None:
                self.证据链.记录结果(
                    证据, 成功=结果.成功,
                    错误码=结果.错误码 if not 结果.成功 else "",
                )
                self.证据链.记录资源释放结论(证据, 资源释放结论)
            self._记录历史(调用记录(能力id=能力id, 请求id=请求id, 调用方=调用方,
                                     项目id=项目id or 上下文.项目id, 成功=结果.成功,
                                     错误码=结果.错误码 if not 结果.成功 else "",
                                     错误说明=结果.错误说明 if not 结果.成功 else "",
                                     耗时秒=耗时,
                                     模块版本=上下文.包版本,
                                     支持库包id=实现.包id if 实现 is not None else "",
                                     提供者版本=实现.提供者版本 if 实现 is not None else "",
                                     制品摘要=实现.制品摘要 if 实现 is not None else "",
                                     资源释放结论=资源释放结论, 证据=证据))
            return 结果
        except Exception as 错误:
            耗时 = _时间模块.monotonic() - 开始
            # 统一信封收口：调用服务对**任何**调用方（HTTP 经网关、进程内直调、
            # 模块经调用器）都只返回统一结果，异常不得逸出到调用方 —— 否则进程内
            # 直调方必须自己 try/except，违反「只处理统一结果」的调用铁律，也与
            # _失败并记录 的收口设计相矛盾。错误码按异常类型映射公开码（表见
            # 模块底部 _公开错误码），保证对外逐码不变。
            错误码 = _公开错误码(错误)
            错误说明 = f"{type(错误).__name__}: {错误}"
            资源释放结论 = _释放版本锁(版本锁定, 锁定请求id, 已锁定)
            if 证据 is not None:
                self.证据链.记录结果(证据, 成功=假, 错误码=错误码)
                self.证据链.记录资源释放结论(证据, 资源释放结论)
            self._记录历史(调用记录(能力id=能力id, 请求id=请求id, 调用方=调用方,
                                     项目id=项目id or 上下文.项目id, 成功=假,
                                     错误码=错误码, 错误说明=错误说明, 耗时秒=耗时,
                                     模块版本=上下文.包版本,
                                     支持库包id=实现.包id if 实现 is not None else "",
                                     提供者版本=实现.提供者版本 if 实现 is not None else "",
                                     制品摘要=实现.制品摘要 if 实现 is not None else "",
                                     资源释放结论=资源释放结论, 证据=证据))
            return self._失败(错误码, 错误说明)

    @staticmethod
    def _执行实现(实现: 能力实现, 调用参数: dict[str, Any],
                 超时秒: Any, 能力id: str, 请求id: str) -> tuple[Any, Any]:
        """执行实现函数；给了有效时限就走真实超时执行器。

        返回 `(原始结果, None)` 或 `(None, 残留执行)`。未给有效时限（None/布尔/
        非数值/<=0）保持既有直调语义 —— 此时「不限时」是**调用方明确的选择**，
        不是把参数收下不用：HTTP 边界始终显式传入（默认 请求超时秒）。
        """
        if not _有时限(超时秒):
            return 实现.调用(**调用参数), None
        from 运行核心.能力调用.超时执行 import 执行器
        from 运行核心.能力调用.运行上下文.上下文 import 全局上下文管理器
        return 执行器.执行(lambda: 实现.调用(**调用参数), 能力id=能力id,
                            包id=实现.包id, 请求id=请求id, 超时秒=float(超时秒),
                            上下文=全局上下文管理器.当前())

    def _超时并记录(
        self, 证据: 调用证据 | None, 残留: Any,
        版本锁定, 锁定请求id: str, 已锁定: bool, 请求id: str, 调用方: str,
        项目id: str, 上下文, 开始: float,
    ) -> Any:
        """超时返回路径：统一失败信封（公开码「超时」）+ 如实回报执行单元现状。

        超时结论与实现结果**解耦**：本次调用判超时，不用实现后来返回的值；
        执行单元杀不掉时如实写进错误说明与资源释放结论，并进证据链/调用历史，
        不假装已回收（哲学第 3 条 2 项：失败必须明确；资源状态必须如实）。
        """
        import time as _时间模块
        耗时 = _时间模块.monotonic() - 开始
        版本结论 = _释放版本锁(版本锁定, 锁定请求id, 已锁定)
        if 残留.仍在运行():
            残留结论 = (f"执行线程 {残留.线程名} 仍在运行（Python 无法强杀线程，"
                       f"该执行单元不可取消；已运行 {残留.已运行秒():.2f} 秒，"
                       f"残留序号 {残留.序号}）")
        else:
            残留结论 = (f"执行线程 {残留.线程名} 在超时回报前已结束"
                       f"（残留序号 {残留.序号}，无遗留）")
        资源释放结论 = f"{版本结论}；{残留结论}"
        说明 = (f"能力 {残留.能力id} 超过时限 {残留.超时秒:g} 秒未返回，"
                f"已按超时回报；{残留结论}")
        详情 = {
            "能力id": 残留.能力id, "请求id": 请求id,
            "超时秒": 残留.超时秒, "耗时秒": round(耗时, 3),
            "残留执行": 残留.转字典(),
        }
        if 证据 is not None and self.证据链 is not None:
            self.证据链.记录结果(证据, 成功=假, 错误码="超时")
            self.证据链.记录资源释放结论(证据, 资源释放结论)
        self._记录历史(调用记录(
            能力id=残留.能力id, 请求id=请求id, 调用方=调用方,
            项目id=项目id or 上下文.项目id, 成功=假,
            错误码="超时", 错误说明=说明, 耗时秒=耗时,
            模块版本=上下文.包版本, 支持库包id=残留.包id,
            资源释放结论=资源释放结论, 证据=证据))
        from 公共契约.基础类型.结果类型 import 结果 as _结果
        return _结果.失败("超时", 说明, 来源="唯一能力调用服务",
                        可重试=真, 详情=详情)

    def _失败并记录(
        self, 证据: 调用证据 | None, 错误码: str, 错误说明: str,
        版本锁定, 锁定请求id: str, 已锁定: bool, 请求id: str, 调用方: str,
        项目id: str, 上下文, 开始: float, *, 模块版本: str, 支持库id: str,
        提供者版本: str, 制品摘要: str,
    ) -> Any:
        """失败返回路径：记录完整证据（含资源释放结论）后返回统一失败结果。"""
        import time as _时间模块
        耗时 = _时间模块.monotonic() - 开始
        资源释放结论 = _释放版本锁(版本锁定, 锁定请求id, 已锁定)
        if 证据 is not None:
            self.证据链.记录结果(证据, 成功=假, 错误码=错误码)
            self.证据链.记录资源释放结论(证据, 资源释放结论)
        self._记录历史(调用记录(能力id=证据.能力id if 证据 is not None else "",
                                 请求id=请求id, 调用方=调用方,
                                 项目id=项目id or 上下文.项目id, 成功=假,
                                 错误码=错误码, 错误说明=错误说明, 耗时秒=耗时,
                                 模块版本=模块版本, 支持库包id=支持库id,
                                 提供者版本=提供者版本, 制品摘要=制品摘要,
                                 资源释放结论=资源释放结论, 证据=证据))
        return self._失败(错误码, 错误说明)

    @staticmethod
    def _失败(错误码: str, 错误说明: str) -> Any:
        from 公共契约.基础类型.结果类型 import 结果
        return 结果.失败(错误码, 错误说明, 来源="唯一能力调用服务")

    # ── 证据与诊断 ────────────────────────────────────────────

    def _记录历史(self, 记录: 调用记录) -> None:
        with self.锁:
            self._调用历史.append(记录)
            if len(self._调用历史) > self._历史上限:
                self._调用历史 = self._调用历史[-self._历史上限:]

    def 查询调用历史(self, 上限: int = 50) -> list[dict[str, Any]]:
        with self.锁:
            return [记录.转字典() for 记录 in self._调用历史[-上限:]]

    def 最近失败(self, 上限: int = 10) -> list[dict[str, Any]]:
        with self.锁:
            失败表 = [记录 for 记录 in self._调用历史 if not 记录.成功]
            return [记录.转字典() for 记录 in 失败表[-上限:]]

    def 回答九问(self, 能力id: str, 错误码: str) -> dict[str, str]:
        """失败诊断：哪一层/哪个能力/哪个版本/哪个提供者。"""
        if self.证据链 is None:
            return {"能力id": 能力id, "错误码": 错误码}
        证据 = 调用证据(能力id=能力id, 错误码=错误码)
        return self.证据链.回答九问(证据)

    # ── 幂等重放 ──────────────────────────────────────────────

    def 幂等重放(self, 能力id: str, 参数: dict[str, Any]) -> bool:
        """重复注册请求能否幂等复用：按**参数形状**（声明参数名集合）判定。

        语义：请求参数名集合与既有实现的参数声明一致才可复用（返回 True）；
        形状变化（多参/少参/换名）视为新能力行为，必须失败（返回 False）。
        判的是**形状**不是**值**——值级摘要见本文件 `_参数摘要`（尚未接线）。
        单参数聚合契约（如 内容参数/文件路径）：按键名传值与直接传聚合 dict
        是同一形状，故一律复用；该判定与 `_展开参数` 同源（共用 `_声明参数名`）。
        """
        实现 = self.注册表.获取(能力id)
        if 实现 is None:
            return 假
        try:
            声明参数名 = _声明参数名(实现)
            if len(声明参数名) == 1:
                return 真  # 单参数聚合契约：两种传法是同一形状
            return set(参数) == 声明参数名
        except Exception:
            return 假


def _声明参数名(实现: 能力实现) -> set[str]:
    """能力注册声明的参数名集合（兼容 dict 列表与字符串列表两种注册形态）。"""
    return {
        (参数项.get("名称") if isinstance(参数项, dict) else 参数项)
        for 参数项 in 实现.参数
    }


def _包归属(实现: 能力实现 | None) -> str:
    """取能力所属支持库包 id —— **只认显式来源字段**，不从能力 id 反推。

    唯一事实源是能力注册表里登记该实现时的 `能力实现.包id`（包声明.包id，
    由 运行核心/加载器/包安装/支持库安装 从 `包声明.json` 读入，是权威包身份）。

    为什么不能用 `能力id.split(".")[0]` 反推（历史缺陷，哲学 14.1 ② 架构错位）：

    - 该写法把「能力 id 的字符串形状」当成「包归属的事实源」。而 id 形态
      本身**两套口径并存**（未完成事项 §8.2 第 20 项实测：499 个裸族名
      如 `文件操作.删除文件` vs 5 个带包 id 前缀如 `文档生成.生成文档`），
      且 `热切换._取包id` 已实测「能力 id 首段恒不是包 id」
      （`系统核心支持库.环境变量.列出环境变量` 首段是 `系统核心支持库`，
      真实包 id 是 `支持库.后端.系统核心支持库.环境变量`）。
    - 后果是静默错：带前缀形态能撞对，裸族名形态会把族名当包名写进证据
      （`支持库`/`支持库包id` 同时被污染），而证据链是失败九问与包指纹
      校验的输入 —— 归属错则追责错、指纹校验打错包。

    未注册能力（注册表查不到实现）**没有**显式来源事实，返回空串：
    「未知即空」是仓库既有口径（契约.能力实现 docstring「不得伪造，未知即空」），
    继续从 id 猜只会造出假包 id。空串在 `证据链.开始调用` 里会落成空
    `支持库`/`支持库包id`，调用方据「能力不存在」错误码即可定位，不装成有归属。
    """
    if 实现 is None:
        return ""
    return 实现.包id or ""


def _有时限(超时秒: Any) -> bool:
    """`超时秒` 是否为有效时限。

    None / 布尔 / 非数值 / <=0 一律视为「不限时」：None 是调用方没给时限的
    既有语义（保持向后兼容，不把某个默认秒数强加给长耗时能力）；其余非法值
    在三层边界的参数校验处就被拒（HTTP 边界：1 ≤ 超时秒 ≤ 请求超时秒），
    这里再兜一层，绝不让「非法值」静默变成一个时限。
    """
    if 超时秒 is None or isinstance(超时秒, bool):
        return 假
    if not isinstance(超时秒, (int, float)):
        return 假
    return float(超时秒) > 0


def _展开参数(实现: 能力实现, 参数: dict[str, Any]) -> dict[str, Any]:
    """把调用方 dict 按能力注册参数名展开为关键字参数。

    兼容两种注册参数形态：dict 列表（{名称,类型}）与字符串参数名列表。
    规则：
    - dict 键名直接命中声明参数名 → 按名传值。
    - 声明只有 1 个参数（如 内容参数/文件路径 聚合契约）且 dict 键不在
      声明中 → 整个 dict 作为该唯一参数的值（内容参数 聚合语义）。
    - 其余未声明键保持原样（契约层 调用() 会拒绝未知参数）。
    """
    声明参数名 = _声明参数名(实现)
    if len(声明参数名) == 1 and not set(参数).issubset(声明参数名):
        唯一参数名 = next(iter(声明参数名))
        return {唯一参数名: dict(参数)}
    关键字表: dict[str, Any] = {}
    for 键, 值 in (参数 or {}).items():
        关键字表[键] = 值
    return 关键字表


def _参数摘要(参数: dict[str, Any]) -> str:
    """参数值级摘要（规范化 JSON + 排序键）——**当前未接线**。

    来源是一次「把幂等重放升级为值级摘要」的工作包（MCP反馈开工id
    17b41a8e9b0b43f4，2026-08-01），该工作包被停止、未落任何改动。
    在接线前 `幂等重放` 只比参数形状，不比值；保留本函数仅为承接该意图，
    是否真正实现值级比较待华哥定夺（见 开发文档/临时文档/47）。
    """
    import hashlib
    import json
    try:
        文本 = json.dumps(参数, ensure_ascii=False, sort_keys=True)
    except (TypeError, ValueError):
        文本 = str(参数)
    return hashlib.sha256(文本.encode("utf-8")).hexdigest()[:16]


# 提供者实现抛出的异常 → 统一信封的公开错误码。
# 逐码与 运行核心/统一网关/网关核心.py `处理()` 的异常分支对齐：调用服务收口后，
# 网关不再依赖异常类型兜底（HTTP 路径不会看到这些异常），因此这里是同一条链路对外
# 错误码的**唯一来源**——两边任一改动必须同步改另一边（见交付说明的剩余风险）。
_异常错误码表: tuple[tuple[type[BaseException], str], ...] = (
    (KeyError, "能力不存在"),
    (PermissionError, "权限不足"),
    (FileNotFoundError, "文件不存在"),
    (ValueError, "参数不合法"),
    (ConnectionError, "提供者不可用"),
    (TimeoutError, "提供者不可用"),
)


def _公开错误码(错误: BaseException) -> str:
    """把提供者异常映射为公开错误码；未登记类型回落「内部错误」（服务端问题）。"""
    for 异常类型, 错误码 in _异常错误码表:
        if isinstance(错误, 异常类型):
            return 错误码
    return "内部错误"


def _释放版本锁(锁定: 版本锁定 | None, 请求id: str, 已锁定: bool = 假) -> str:
    """调用结束后释放版本锁，返回资源释放结论（失败必须如实记录）。

    未锁定/无锁 → 无版本锁定需求；已锁定 → 释放成功/失败如实记录。
    """
    if 锁定 is None or not 请求id or not 已锁定:
        return "无版本锁定需求"
    已释放 = 锁定.释放(请求id=请求id)
    return "版本锁已释放" if 已释放 else "版本锁释放失败（引用残留）"


