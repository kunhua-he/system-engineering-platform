def 创建并绑定(注册表: 能力注册表 | None = None, *,
               任务系统实例: Any = None) -> "唯一能力调用服务":
    """**唯一装配入口**：创建唯一能力调用服务并设置为全局注入目标。

    装配状态机（唯一注册表调用器注入点，S0生产事实冻结第二节）：
    - 未装配/装配失败 → 装配中 → 创建并绑定成功 → 已装配；
    - 已装配 → 重复装配幂等（同摘要可重放，装配次数递增）；
    - 装配中 → 拒绝并发重复装配（抛 能力调用器状态异常 E装配中）；
    - 任一异常 → 回滚为 装配失败 并记录错误码/错误说明，不留半状态。

    **两条装配腿已收敛成这一条**（P2-12）：`注册表` 省略时本入口自己**发现 → 安装
    支持库 → 建注册表**（惰性首次获取时的原路径），传了就用调用方的注册表
    （生产 `装配系统` 与各测试的用法）。旧实现是两条并行装配腿
    （`创建并绑定` 有 CAS，`_惰性装配` 无 CAS、且在建表/发现/安装之后才进锁外**没有
    任何**装配中保护）—— 两个线程同时首次获取调用器时可能各跑一遍全库扫描 + 安装
    （秒级 I/O 双执行），第二次重复注册还会报错。现在惰性钩子直接转调本入口，
    发现的临界区由「装配中 CAS + 重查」保护，**同一时刻只有一条腿在装配**。

    `任务系统实例`：主进程的任务系统（执行形态 `常驻有状态` 能力的执行通道）。
    由启动脚本以关键字传入，**不为此另开装配入口、不猜全局变量名**。
    """
    from 公共契约.能力契约.调用器 import (
        查询装配状态, 标记装配中, 标记装配失败, 能力调用器状态异常,
    )
    当前状态 = 查询装配状态()["状态"]
    if 当前状态 == "装配中":
        raise 能力调用器状态异常(
            状态="装配中", 错误码="E装配中",
            错误说明="已有装配正在进行中，禁止并发重复装配",
        )
    if not 标记装配中():
        # CAS 未抢到：另一线程在「查询装配状态」与本行之间的 TOCTOU 窗口内已抢到
        # 「装配中」。旧实现丢弃返回值 ⇒ 两线程各跑一遍全库发现+安装（秒级 I/O
        # 双执行）。此处必须在 try 之外抛异常退出：
        #   - 不进 except 分支 ⇒ 不会把抢到方持有的「装配中」改写成 装配失败；
        #   - 不执行装配 ⇒ 禁止并发重复装配在 TOCTOU 窗口内同样成立。
        raise 能力调用器状态异常(
            状态="装配中", 错误码="E装配中",
            错误说明="已有装配正在进行中，禁止并发重复装配",
        )
    try:
        return _装配主体(注册表, 任务系统实例)
    except Exception as 错误:
        失败说明 = f"{type(错误).__name__}: {错误}"
        标记装配失败("E装配失败", 失败说明)
        raise


def _装配主体(注册表: 能力注册表 | None = None, 任务系统实例: Any = None,
              *, 系统根: Any = None) -> "唯一能力调用服务":
    """**装配主体**（唯一一份）：发现 → 安装 → 建服务 → 接任务通道 → 注入。

    调用前提：`装配中` 状态**已由调用方持有**（`创建并绑定` 自己抢的 CAS，或
    惰性钩子路径上 `公共契约.能力契约.调用器.获取能力调用器` 抢的 CAS）。
    因此本函数**不再抢 CAS、也不回滚状态**——状态收口留给持锁者：抢 CAS 的人负责
    装配失败时把状态写回 `装配失败`，装配成功由 `设置全局唯一服务` 写成 `已装配`。

    这正是 P2-12 要的形态：**一份装配实现 + 同一时刻一个装配所有者**。旧实现是两份
    装配实现（`创建并绑定` 与 `_惰性装配`），后者连「装配中」保护都没有，两个线程
    同时首次获取就会各跑一遍全库扫描 + 安装（秒级 I/O 双执行）。
    """
    注册表 = 注册表 if 注册表 is not None else _发现并安装(系统根)
    服务 = 唯一能力调用服务(注册表)
    # 顺序：先把执行通道接上，再对外可见（设置全局唯一服务会把状态标成已装配）；
    # 反过来会出现「已装配但任务通道还没接」的窗口，常驻有状态能力在这个窗口里
    # 会被判「任务不可提交」（装配缺陷口径）—— 那是我们自己制造的假缺陷。
    接入任务系统(任务系统实例)
    设置全局唯一服务(服务)
    return 服务


def _发现并安装(系统根: Any = None) -> 能力注册表:
    """惰性首装配的发现 + 安装（**只在装配中状态的临界区内被调用**）。

    为什么可以放在 CAS 之后放心做秒级 I/O：抢不到 CAS 的线程会立刻抛 `E装配中`
    退出，不会并发跑第二遍；装配成功后全局调用器已就绪，后续获取在读锁里直接拿
    就绪对象（`获取能力调用器` 的「就绪优先」），不会再进这里。

    `系统根` 不传时按本文件位置上溯定位（`<根>/运行核心/能力调用/…`）。
    发现不出任何支持库时抛 `RuntimeError`（由持锁者回滚为 `装配失败`）——
    旧实现是同一句口径，语义一字不变。
    """
    from pathlib import Path
    from 公共契约.能力契约.契约 import 能力注册表
    from 运行核心.加载器.包发现.发现器 import 发现全部
    from 运行核心.加载器.包安装.支持库安装 import 安装全部支持库

    系统根 = Path(系统根) if 系统根 is not None else Path(__file__).resolve()
    if 系统根.is_file():
        系统根 = 系统根.parent
    for _祖先 in 系统根.parents:
        if (_祖先 / "支持库").is_dir() and (_祖先 / "模块库").is_dir():
            系统根 = _祖先
            break
    注册表 = 能力注册表()
    发现 = 发现全部(系统根 / "支持库", 系统根 / "模块库")
    支持库声明 = [声明 for 声明 in 发现.声明列表
                 if 声明.类型 == "支持库" and not getattr(声明, "已废弃", 假)]
    if not 支持库声明:
        raise RuntimeError("首次装配失败：未发现任何支持库")
    安装全部支持库(系统根 / "支持库", 注册表)
    return 注册表


