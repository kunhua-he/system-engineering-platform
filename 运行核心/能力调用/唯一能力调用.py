"""唯一能力调用服务：所有入口（HTTP/Agent/MCP/项目代码）经同一调用服务。

收敛能力注册、提供者选择、能力调用和证据采集：
- 能力注册表是唯一权威（重复注册失败，只允许参数形状一致的幂等重放）。
- 调用者只持能力 id 与契约版本；提供者选择、参数校验、证据采集由本服务完成。
- 调用者不得持有第三方对象、连接、线程、进程或原生句柄。
- 正式代码、项目适配层与项目测试不得导入支持库/提供者/实现源码；
  唯一能力调用服务是模块按能力 id 调用支持库的唯一通道。
"""

from __future__ import annotations

import threading
from dataclasses import dataclass, field
from typing import Any, Callable

from 公共契约.能力契约.契约 import 能力注册表, 能力实现
from 公共契约.基础类型.结果类型 import 结果 as 统一结果类型
from 运行核心.能力调用.控制调用.证据链 import 调用证据, 证据链, 版本锁定
from 运行核心.能力调用.运行上下文.上下文 import 运行上下文, 全局上下文管理器
from 公共契约.基础类型.逻辑类型 import 真, 假


@dataclass
class 调用记录:
    """一次唯一能力调用的完整记录。"""

    能力id: str
    请求id: str
    调用方: str = ""
    项目id: str = ""
    成功: bool = 真
    错误码: str = ""
    错误说明: str = ""
    耗时秒: float = 0.0
    模块版本: str = ""
    支持库包id: str = ""
    提供者版本: str = ""
    制品摘要: str = ""
    资源释放结论: str = ""
    证据: 调用证据 | None = None

    def 转字典(self) -> dict[str, Any]:
        return {
            "能力id": self.能力id, "请求id": self.请求id, "调用方": self.调用方,
            "项目id": self.项目id, "成功": self.成功, "错误码": self.错误码,
            "错误说明": self.错误说明, "耗时秒": self.耗时秒,
            "模块版本": self.模块版本, "支持库包id": self.支持库包id,
            "提供者版本": self.提供者版本, "制品摘要": self.制品摘要,
            "资源释放结论": self.资源释放结论,
            "证据": self.证据.转字典() if self.证据 is not None else None,
        }


class 唯一能力调用服务:
    """唯一能力调用服务：注册、选择、调用、证据。

    用法（加载器装配后注入模块）：
        服务 = 唯一能力调用服务(注册表)
        模块入口.绑定唯一调用服务(服务)
    模块实现内：
        from 模块库.X import 获取唯一调用服务
        服务 = 获取唯一调用服务()
        return 服务.调用能力("办公文档支持库.表格文档.生成表格文档", {"内容参数": ...})
    """

    def __init__(self, 注册表: 能力注册表, *, 启用证据链: bool = 真) -> None:
        if not isinstance(注册表, 能力注册表):
            raise TypeError("唯一能力调用服务必须绑定权威能力注册表")
        self.注册表 = 注册表
        self.证据链 = 证据链() if 启用证据链 else None
        self.版本锁定 = 版本锁定()
        self.锁 = threading.RLock()
        self._模块调用服务表: dict[str, "唯一能力调用服务"] = {}
        self._调用历史: list[调用记录] = []
        self._历史上限 = 500
        # 包指纹校验（正式环境防静默漂移）：由核心注入校验回调，调用前校验
        # 该能力所属包的制品/源码指纹是否与注册时一致；不一致即报错，不静默
        # 沿用旧实现。测试/开发环境不注入时不产生任何额外开销。
        self._包指纹校验器 = None
        self._包指纹缓存: dict[str, tuple[float, bool, str]] = {}
        self._包指纹缓存秒 = 1.0

    def 设置包指纹校验器(self, 校验函数) -> None:
        """注入包指纹校验回调：接收包id，返回 (是否一致, 说明)。"""
        with self.锁:
            self._包指纹校验器 = 校验函数
            self._包指纹缓存.clear()

    def 清空包指纹缓存(self) -> None:
        """热接入重新注册指纹后清缓存，避免沿用旧的漂移判定。"""
        with self.锁:
            self._包指纹缓存.clear()

    def _校验包指纹(self, 包id: str) -> tuple[str, str] | None:
        """校验包指纹；一致返回 None，漂移返回 (错误码, 错误说明)。

        带 1 秒缓存：同一包在缓存窗口内不重复扫描，漂移检测延迟不超过 1 秒。
        """
        校验器 = self._包指纹校验器
        if 校验器 is None or not 包id:
            return None
        import time as _时间模块
        现在 = _时间模块.monotonic()
        with self.锁:
            缓存 = self._包指纹缓存.get(包id)
            if 缓存 is not None and 现在 - 缓存[0] < self._包指纹缓存秒:
                一致, 说明 = 缓存[1], 缓存[2]
            else:
                try:
                    一致, 说明 = 校验器(包id)
                except Exception as 异常:
                    一致, 说明 = 假, f"包指纹校验异常: {异常}"
                self._包指纹缓存[包id] = (现在, 一致, 说明)
        if 一致:
            return None
        错误码 = "制品缺失" if "缺失" in 说明 else "制品已变更"
        return 错误码, 说明 or f"包 {包id} 指纹与注册时不一致，请重新热接入"

    # ── 模块绑定 ──────────────────────────────────────────────

    def 绑定模块(self, 模块id: str) -> "唯一能力调用服务":
        """把本服务注入指定模块（模块只持能力 id，不直接导入支持库）。"""
        with self.锁:
            self._模块调用服务表[模块id] = self
            return self

    def 已绑定模块(self, 模块id: str) -> bool:
        with self.锁:
            return 模块id in self._模块调用服务表

    # ── 调用 ──────────────────────────────────────────────────

    @staticmethod
    def _规范化结果(值: Any) -> 统一结果类型:
        """跨包字典必须完整满足统一结果契约；原子值仍由适配边界包装。"""
        if isinstance(值, 统一结果类型):
            return 值
        if isinstance(值, dict):
            必填字段 = {"成功", "值", "错误码", "错误说明"}
            if not 必填字段.issubset(值):
                return 统一结果类型.失败(
                    "返回结果不符合契约", "字典返回缺少统一结果字段",
                )
            if (not isinstance(值.get("成功"), bool)
                    or not isinstance(值.get("错误码"), str)
                    or not isinstance(值.get("错误说明"), str)):
                return 统一结果类型.失败(
                    "返回结果不符合契约", "字典返回的统一结果字段类型不正确",
                )
            if 值["成功"]:
                return 统一结果类型.成功结果(值["值"])
            return 统一结果类型.失败(值["错误码"] or "调用失败", 值["错误说明"])
        return 统一结果类型.成功结果(值)

    def 请求(self, 目标: str, 参数: dict[str, Any] | None = None,
             句柄: str | None = None) -> Any:
        """历史适配入口：文本句柄只在此转换，统一调用入口只接收整数。

        不携带句柄表示一次性调用；当前无状态能力执行完即由其实现释放。
        有状态 Provider 接入后，句柄只作为不透明值向下传递，调用方不接触
        执行单元、租约或第三方对象。
        """
        if not isinstance(目标, str) or not 目标.strip():
            return self._失败("参数不合法", "目标不能为空")
        if 参数 is not None and not isinstance(参数, dict):
            return self._失败("参数不合法", "参数必须是字典")
        if 句柄 is None:
            统一句柄 = None
        elif isinstance(句柄, str) and 句柄.isdecimal() and 1 <= int(句柄) <= 999999:
            统一句柄 = int(句柄)
        else:
            return self._失败("参数不合法", "历史文本句柄必须表示 1 到 999999 的整数")
        return self.调用能力(目标, 参数 or {}, 句柄=统一句柄)

    def 调用能力(self, 能力id: str, 参数: dict[str, Any] | None = None, *,
                 调用方: str = "", 项目id: str = "", 超时秒: float | None = None,
                 句柄: int | None = None) -> Any:
        """按能力 id 调用唯一注册实现，返回统一 结果。

        参数校验、证据采集在此统一完成；调用方不接触提供者。
        证据字段（S0生产事实冻结第五节）：请求id/模块版本/能力id/支持库包id/
        提供者版本/制品摘要/成功失败/资源释放结论；调用前后版本锁定并释放，
        失败路径同样记录完整证据与释放结论。
        """
        import time as _时间模块
        开始 = _时间模块.monotonic()
        # 统一公开句柄冻结为整数；历史字符串只允许进程内连接器这个显式
        # 适配层进入，并在跨越唯一调用边界前立即归一。
        if isinstance(句柄, str) and 调用方 == "进程内连接器" and 句柄.isdecimal():
            句柄 = int(句柄)
        if 句柄 is not None and (
            isinstance(句柄, bool) or not isinstance(句柄, int)
            or not 1 <= 句柄 <= 999999
        ):
            return self._失败("参数不合法", "句柄必须是 1 到 999999 的整数")
        上下文 = 全局上下文管理器.当前()
        请求id = 上下文.请求id or ""
        实现 = self.注册表.获取(能力id)
        证据 = None
        if self.证据链 is not None:
            支持库id = _包归属(实现)
            证据 = self.证据链.开始调用(
                项目=项目id or 上下文.项目id,
                功能模块=上下文.模块id,
                支持库=支持库id,
                支持库包id=实现.包id if 实现 is not None else "",
                提供者=实现.提供者id if 实现 is not None else "",
                提供者版本=实现.提供者版本 if 实现 is not None else "",
                能力id=能力id,
                版本=实现.版本 if 实现 is not None else "",
                模块版本=上下文.包版本,
                制品摘要=实现.制品摘要 if 实现 is not None else "",
                任务id=上下文.任务id,
            )
        锁定请求id = 证据.请求id if 证据 is not None else 请求id
        # 形态判定（执行形态分流）在 try 之外先初始化：异常路径也要能带上它，
        # 否则「同一个能力有时带判定、有时不带」——诊断字段缺失本身就是失真。
        形态判定: dict[str, Any] | None = None
        if 实现 is not None:
            # 判定是**纯只读**（读形态声明与包名，不执行实现），所以可以先行求值：
            # 实现自身抛异常时（参数不合法等）判定也已就位，诊断面不会缺失。
            形态判定 = _判定字典(实现)
        版本锁定 = self.版本锁定
        已锁定 = 假
        if 实现 is not None and 版本锁定 is not None:
            if 版本锁定.锁定(
                请求id=锁定请求id, 包id=实现.包id,
                版本=实现.版本 or "", 提供者版本=实现.提供者版本 or "",
            ):
                已锁定 = 真
        try:
            if 实现 is None:
                return self._失败并记录(证据, "能力不存在", f"能力未注册: {能力id}",
                                         版本锁定, 锁定请求id, 已锁定, 请求id, 调用方,
                                         项目id, 上下文, 开始, 模块版本=上下文.包版本,
                                         支持库id="", 提供者版本="", 制品摘要="")
            if 参数 is None:
                参数 = {}
            if not isinstance(参数, dict):
                return self._失败并记录(证据, "参数不合法", f"能力 {能力id} 参数必须是字典",
                                         版本锁定, 锁定请求id, 已锁定, 请求id, 调用方,
                                         项目id, 上下文, 开始, 模块版本=上下文.包版本,
                                         支持库id=实现.包id, 提供者版本=实现.提供者版本,
                                         制品摘要=实现.制品摘要)
            # 制品/源码指纹校验（正式环境开启）：被改动但未重新热接入即报错，
            # 不静默沿用旧实现；测试/开发环境未注入校验器时零开销。
            指纹结论 = self._校验包指纹(实现.包id)
            if 指纹结论 is not None:
                return self._失败并记录(证据, 指纹结论[0], 指纹结论[1],
                                         版本锁定, 锁定请求id, 已锁定, 请求id, 调用方,
                                         项目id, 上下文, 开始, 模块版本=上下文.包版本,
                                         支持库id=实现.包id, 提供者版本=实现.提供者版本,
                                         制品摘要=实现.制品摘要)
            调用参数 = _展开参数(实现, 参数)
            # 「超时秒」必须真用（P0 B-02）：给了有效时限就走真实超时执行 ——
            # 到点即返回，调用方线程（HTTP 工作线程）立刻归还；执行单元若杀不掉，
            # 如实登记进残留账本，绝不用「执行异常」冒充超时检出（见 超时执行 模块）。
            # **执行形态分流在此收口（唯一一处）**：形态判据与判定入口都在
            # `运行核心.能力调用.超时执行`（单一来源），本服务只做两件事：
            #  ① 即时纯计算 → 同线程直调（零线程，P1-4）；
            #  ② 常驻有状态 → 走已成熟的异步任务通道（任务系统；未接入时走受管的
            #     进程内兜底通道，如实记录丢时限）；其余形态（阻塞IO/长耗时）→ 线程兜底。
            原始结果, 超时残留, 形态判定 = self._执行实现(
                实现, 调用参数, 超时秒, 能力id, 请求id)
            if 超时残留 is not None:
                return self._超时并记录(
                    证据, 超时残留, 版本锁定, 锁定请求id, 已锁定, 请求id, 调用方,
                    项目id, 上下文, 开始)
            结果 = self._规范化结果(原始结果)
            # 形态判定是**诊断面**信息：成功结果没有 详细信息 载体（统一结果的
            # 详细信息只挂在失败错误上），故只对失败结果附加；兜底路径的代价
            # （丢时限/丢取消）另经 `资源释放补充` 落进**资源释放结论**——
            # 那正是平台既有的「资源状态如实」字段，成功/失败两条路径都进得去。
            if 形态判定 and not 结果.成功:
                结果.详细信息.setdefault("执行形态判定", 形态判定)
            耗时 = _时间模块.monotonic() - 开始
            资源释放结论 = _释放版本锁(版本锁定, 锁定请求id, 已锁定)
            补充 = (形态判定 or {}).get("资源释放补充") or ""
            if 补充:
                资源释放结论 = f"{资源释放结论}；{补充}"
            if 证据 is not None:
                self.证据链.记录结果(
                    证据, 成功=结果.成功,
                    错误码=结果.错误码 if not 结果.成功 else "",
                )
                self.证据链.记录资源释放结论(证据, 资源释放结论)
            self._记录历史(调用记录(能力id=能力id, 请求id=请求id, 调用方=调用方,
                                     项目id=项目id or 上下文.项目id, 成功=结果.成功,
                                     错误码=结果.错误码 if not 结果.成功 else "",
                                     错误说明=结果.错误说明 if not 结果.成功 else "",
                                     耗时秒=耗时,
                                     模块版本=上下文.包版本,
                                     支持库包id=实现.包id if 实现 is not None else "",
                                     提供者版本=实现.提供者版本 if 实现 is not None else "",
                                     制品摘要=实现.制品摘要 if 实现 is not None else "",
                                     资源释放结论=资源释放结论, 证据=证据))
            return 结果
        except Exception as 错误:
            耗时 = _时间模块.monotonic() - 开始
            # 统一信封收口：调用服务对**任何**调用方（HTTP 经网关、进程内直调、
            # 模块经调用器）都只返回统一结果，异常不得逸出到调用方 —— 否则进程内
            # 直调方必须自己 try/except，违反「只处理统一结果」的调用铁律，也与
            # _失败并记录 的收口设计相矛盾。错误码按异常类型映射公开码（表见
            # 模块底部 _公开错误码），保证对外逐码不变。
            错误码 = _公开错误码(错误)
            错误说明 = f"{type(错误).__name__}: {错误}"
            资源释放结论 = _释放版本锁(版本锁定, 锁定请求id, 已锁定)
            补充 = (形态判定 or {}).get("资源释放补充") or ""
            if 补充:
                资源释放结论 = f"{资源释放结论}；{补充}"
            if 证据 is not None:
                self.证据链.记录结果(证据, 成功=假, 错误码=错误码)
                self.证据链.记录资源释放结论(证据, 资源释放结论)
            self._记录历史(调用记录(能力id=能力id, 请求id=请求id, 调用方=调用方,
                                     项目id=项目id or 上下文.项目id, 成功=假,
                                     错误码=错误码, 错误说明=错误说明, 耗时秒=耗时,
                                     模块版本=上下文.包版本,
                                     支持库包id=实现.包id if 实现 is not None else "",
                                     提供者版本=实现.提供者版本 if 实现 is not None else "",
                                     制品摘要=实现.制品摘要 if 实现 is not None else "",
                                     资源释放结论=资源释放结论, 证据=证据))
            # 异常路径的失败结果同样带上形态判定（诊断面字段，不进证据契约）。
            失败结果 = self._失败(错误码, 错误说明)
            if 形态判定:
                失败结果.详细信息.setdefault("执行形态判定", dict(形态判定))
            return 失败结果

    @staticmethod
    def _执行实现(实现: 能力实现, 调用参数: dict[str, Any],
                 超时秒: Any, 能力id: str, 请求id: str) -> tuple[Any, Any, dict[str, Any]]:
        """执行实现函数：按**执行形态**分流（本服务是唯一分流点）。

        返回 `(原始结果, 超时残留, 形态判定)`：
        - `(值, None, 判定)`：在时限内完成（实现异常在调用方线程原样抛出）；
        - `(None, 残留执行, 判定)`：已到时限、实现仍在运行（走 `_超时并记录`）；
        - `(失败结果, None, 判定)`：入口级失败（`限流` / `形态不匹配` / `任务不可提交`
          / `参数不合法`）—— **原样返回统一失败信封**，由 `调用能力` 收口。

        形态三路（判据与判定入口都在 `运行核心.能力调用.超时执行`，**不在此处复写**）：

        1. `即时纯计算` ⇒ **同线程直调，零线程**（P1-4：纯计算不再付建线程 + Event
           等待 + 跨线程上下文重入的固定成本）。同线程意味着运行上下文无需重入
           （本来就在当前线程栈上），直调语义与原实现逐字一致。
        2. `常驻有状态` ⇒ **走已成熟的异步任务通道**（任务系统：提交/轮询/取消/超时/
           整组回收都有），把同步调用回报成任务信封 `{任务id, 状态, 提交说明}`。
           没接入任务系统时**不静默退化**：起一个受管的 daemon 线程在**进程内**执行，
           并把「本次丢掉了时限与取消」在信封里如实写出来（进程会随主进程退出）。
           为什么这条兜底不是「第二条腿」：它就是 Python 线程唯一能提供的东西，条目
           上的 `限额缺失` 字段和说明文字都如实标注，调用方不会把它当成任务通道。
           主进程若**装了任务系统但没把本服务接上它**（装配缺陷），则**明确失败**
           `任务不可提交`：这类能力在同步通道上占用工作线程远超时限，静默兜底等于
           把缺陷藏起来。
        3. `阻塞IO` / `长耗时` ⇒ 执行器线程兜时限（`执行器.执行`），到点即返回。

        形态**只决定执行单位**，不改任何错误码、证据字段或返回结构；形态判定结果
        （形态/来源/依据）随返回值交给 `调用能力` 附进 `详细信息.执行形态判定`，
        **不进证据契约的冻结字段表**（那是对外契约面，不是诊断面）。
        """
        from 运行核心.能力调用.超时执行 import (
            执行器, 通道_任务, 通道_直调, 执行通道, 判定执行形态,
        )
        形态, 判定来源, 判定依据 = 判定执行形态(实现)
        判定 = {"执行形态": 形态, "形态判定来源": 判定来源, "形态判定依据": 判定依据}
        # **分流依据问执行器要**（`执行通道`），本服务不复写「哪些形态起线程」——
        # 两份清单必然漂移（调用方以为在直调、执行器却起线程，或反过来）。
        通道 = 执行通道(形态)
        判定["执行通道"] = 通道
        if 通道 == 通道_直调:
            # 同线程直调：不给实现任何「有独立执行单元」的错觉，也不起线程。
            return 实现.调用(**调用参数), None, 判定
        if 通道 == 通道_任务:
            return (唯一能力调用服务._常驻有状态调用(
                实现, 调用参数, 能力id, 请求id, 判定), None, 判定)
        # 其余形态（阻塞IO / 长耗时，含任何未登记形态的保守回落）⇒ 执行器线程兜时限。
        # 「不限时」是调用方明确的选择（保持既有语义）：线程照起，时限取足够宽的兜底
        # —— 绝不给长耗时能力强加小超时，也不借机把线程也省掉（那会失去时限手段）。
        时限 = float(超时秒) if _有时限(超时秒) else 不限期线程时限秒
        值, 残留 = 执行器.执行(lambda: 实现.调用(**调用参数), 能力id=能力id,
                              包id=实现.包id, 请求id=请求id, 超时秒=时限,
                              实现=实现)
        return 值, 残留, 判定

    @staticmethod
    def _常驻有状态调用(实现: 能力实现, 调用参数: dict[str, Any],
                        能力id: str, 请求id: str, 判定: dict[str, Any]) -> Any:
        """`常驻有状态` 形态的执行走向：任务通道优先，无通道才走受管兜底。

        返回三种形态之一（都不是异常，由 `调用能力` 的既有分支统一收口）：
        - 任务信封 `{任务id, 状态, 提交说明, 执行形态判定}`：已提交到任务通道，
          取消/查询走 `任务取消` / `任务查询`（这两个能力本来就存在，不是新机制）；
        - `统一结果.失败("任务不可提交")`：主进程装了任务系统但本服务没接上它
          （装配缺陷）—— 如实失败，不静默换通道；
        - 统一结果成功/失败（兜底路径的实际执行结果）：完全没有任务系统时，同步
          通道就是本平台唯一的执行面，起受管守护线程在进程内执行，并把「丢了时限
          与取消」写进 `详细信息`（**不隐藏代价**）。
        """
        from 运行核心.能力调用.运行上下文.上下文 import 全局上下文管理器
        任务系统实例 = 取任务系统()
        if 任务系统实例 is not None:
            已注册 = getattr(任务系统实例, "执行函数表", None)
            if not isinstance(已注册, dict) or 能力id not in 已注册:
                return 统一结果类型.失败(
                    "任务不可提交",
                    f"能力 {能力id} 未在任务系统注册执行函数，无法走任务通道"
                    f"（常驻有状态能力的唯一执行面）",
                    来源="唯一能力调用服务", 详情=dict(判定),
                )
            try:
                上下文 = 全局上下文管理器.当前()
                任务对象 = 任务系统实例.提交(
                    能力id=能力id, 参数=dict(调用参数), 请求id=请求id,
                    项目id=上下文.项目id, 用户id=上下文.用户id,
                    超时秒=不限期线程时限秒,
                )
            except Exception as 错误:  # noqa: BLE001 - 提交面失败必须明确回报，不静默换通道
                return 统一结果类型.失败(
                    "任务不可提交",
                    f"能力 {能力id} 提交任务通道失败: {type(错误).__name__}: {错误}",
                    来源="唯一能力调用服务", 详情=dict(判定),
                )
            return 统一结果类型.成功结果({
                "任务id": 任务对象.任务id, "状态": 任务对象.状态,
                "提交说明": ("已提交任务通道执行：取消走 任务取消，查询走 任务查询；"
                           "本响应不是执行结果"),
                "执行形态判定": dict(判定),
            })
        if _任务系统曾装配():
            # 装了却没接上：装配缺陷，明确失败（静默兜底会把缺陷藏起来）。
            return 统一结果类型.失败(
                "任务不可提交",
                f"能力 {能力id} 属常驻有状态形态，但任务系统未接入唯一能力调用服务"
                f"（装配缺陷：主进程已建任务系统却没有调用 接入任务系统）；"
                f"该形态在同步通道上无法提供时限与取消",
                来源="唯一能力调用服务", 详情=dict(判定),
            )
        状态: dict[str, Any] = {"完成": 假, "值": None, "异常": None}
        状态锁 = threading.Lock()

        def 兜底执行体() -> None:
            try:
                try:
                    状态["值"] = 实现.调用(**调用参数)
                except BaseException as 异常:  # noqa: BLE001 - 原样带回调用方线程
                    状态["异常"] = 异常
            finally:
                with 状态锁:
                    状态["完成"] = 真

        线程 = threading.Thread(target=兜底执行体, name=f"常驻有状态兜底-{能力id}",
                                daemon=True)
        线程.start()
        # 到点即返回（时限到此为止的最末端 —— 其后的实现仍在跑，如实标注）。
        线程.join(timeout=不限期线程时限秒)
        with 状态锁:
            已完成 = bool(状态["完成"])
        异常 = 状态.get("异常")
        if 异常 is not None:
            raise 异常
        if not 已完成:
            return 统一结果类型.失败(
                "超时",
                f"能力 {能力id} 的受管兜底执行未在时限内返回（该形态无任务通道，"
                f"不能取消；执行单元随主进程退出）",
                来源="唯一能力调用服务", 可重试=真, 详情=dict(判定),
            )
        结果 = 唯一能力调用服务._规范化结果(状态.get("值"))
        # 代价如实写进判定字典：`调用能力` 会把它落到**资源释放结论**（成功/失败都进
        # 得去），不假装「有任务通道」、也不假装「有时限与取消」。
        判定["资源释放补充"] = (
            "无任务通道：本次调用在进程内受管守护线程执行，丢掉了时限与取消"
            "（执行单元随主进程退出，不可单独回收）；代价在此如实标注，未被隐藏"
        )
        判定["限额缺失"] = 真
        return 结果

    def 常驻有状态分流快照() -> dict[str, Any]:
        """常驻有状态能力的「通道 — 后果」对照事实（诊断只读，无副作用）。"""
