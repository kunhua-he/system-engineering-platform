"""能力调用的真实时限执行（P0 B-02：`超时秒` 参数收了就得真用）。

背景：HTTP 边界严格校验 `1 ≤ 超时秒 ≤ 请求超时秒`，参数一路传到
`后端核心.调用 → 唯一能力调用服务.调用能力 → 实现.调用(**参数)`，但三层函数体
都只声明不使用（引用次数 0）→ 一个挂死的实现会永久占用一个 HTTP 工作线程，
并发上限耗尽后网关对所有新连接回 429，只能重启进程。

本模块给出的真实时限执行语义：

1. **时限是调用方的**：`执行()` 在独立执行线程里跑实现函数，调用方在事件上带
   时限等待；到点即返回，调用方线程（HTTP 工作线程）立刻归还。
2. **超时与实现结果解耦**：超时返回「超时」结论，绝不把「实现稍后返回的结果」
   冒充成本次调用结果；实现自身的异常仍在**调用方线程**里抛出，由调用方的
   公开错误码表统一映射（逐码不变）。
3. **超时后不假装回收**：Python 无法强杀线程（本仓标准库约束下没有安全等价物），
   执行单元是单次函数调用、没有取消点 → **一律不可取消**。因此超时后：
   - 把该执行单元如实登记进「残留执行账本」（能力id/请求id/线程名/已运行秒/
     是否仍在运行），并在返回说明与证据链的「资源释放结论」里写明「仍在运行」；
   - 残留账本由 `状态快照()` 可读，**不隐藏、不冲销**：仍在运行的条目一律不
     因为超限而被悄悄冲掉；
   - 若接入了自动排空管理器（`接排空管理器`），执行线程自己持计数
     （开始任务/结束任务）：挂死时计数不减 → 排空时如实报「活动任务 N」、
     不会谎报归零。**不注册强制终止器**——注册一个杀不掉线程的终止器才是撒谎。
3.1 **账本上限是「硬上限」，不是「软上限」**（2026-09-17 修正）：`残留账本硬上限`
   收的是**在册明细条目数**。旧实现的 `残留账本上限` 只回收「已结束」条目、
   对未结束的一律保留 → 名称为「上限」而实际无界（实测：上限 8、40 个真挂死
   调用 → 账本 40 条、无任何计数暴露被丢弃）。现在的语义：
   - 登记前先 `_清理已结束()` 回收已结束条目（尽量腾出在册位）；
   - 在册位用尽且全部仍在运行时，**不再入册**，只累加 `因上限丢弃残留数`
     （读取侧 `状态快照()["因上限丢弃残留数"]` 可见，并配 `账本已达硬上限` 布尔）；
   - 因此 `账本条目数 ≤ 残留账本硬上限` **恒成立**，账本内存有硬界；
   - 「真实还有多少执行单元在跑」**不由账本口径回答**：账本只是有界的诊断索引，
     全体规模要按 `在册残留数 + 因上限丢弃残留数`（下界）或排空管理器的
     「活动任务数」读取。逐次调用的证据链用的是 `执行()` 返回的记录本身，
     不受账本是否入册影响 —— 丢弃明细绝不等于丢弃证据。

4. **每次调用一条线程，不用共享线程池**：共享池的槽位会被挂死任务永久吃掉，
   池满后会把无关能力也一起判超时，等于把一个挂死放大成全平台挂死。
   线程创建开销（微秒级）换取「一个挂死只泄漏它自己那一份」。
"""

from __future__ import annotations

import threading
import time
from dataclasses import dataclass, field
from typing import Any, Callable

线程名前缀 = "能力执行"


@dataclass
class 残留执行:
    """一次超时后仍在运行（或刚结束）的执行单元。"""

    序号: int
    能力id: str
    包id: str
    请求id: str
    线程名: str
    超时秒: float
    开始时刻: float
    完成事件: threading.Event = field(default_factory=threading.Event)

    def 仍在运行(self) -> bool:
        return not self.完成事件.is_set()

    def 已运行秒(self) -> float:
        return max(0.0, time.monotonic() - self.开始时刻)

    def 转字典(self) -> dict[str, Any]:
        return {
            "序号": self.序号,
            "能力id": self.能力id,
            "包id": self.包id,
            "请求id": self.请求id,
            "线程名": self.线程名,
            "超时秒": self.超时秒,
            "已运行秒": round(self.已运行秒(), 3),
            "仍在运行": self.仍在运行(),
        }


class 超时执行器:
    """独立线程执行 + 事件带时限等待；超时如实记账，绝不假装回收。"""

    def __init__(self, 残留账本上限: int = 256) -> None:
        """`残留账本上限` 是**硬上限**（在册明细条目数的硬界），不是软上限。

        参数名保留 `残留账本上限`（对外契约不变）；规范字段名是
        `残留账本硬上限`，旧名以只读属性形式继续可读（同一取值，不会漂移）。
        """
        self._锁 = threading.RLock()
        self._残留: dict[int, 残留执行] = {}
        self._序号 = 0
        self._已归档残留数 = 0
        self._累计超时数 = 0
        #: 因账本已满（且全部仍在运行）而**没能入册**的残留条数；只累计计数，
        #: 绝不为它保留明细 —— 否则「有上限」就是自欺（旧实现的真缺陷）。
        self._丢弃残留数 = 0
        self._排空管理器 = None
        self.残留账本硬上限 = max(1, int(残留账本上限))

    @property
    def 残留账本上限(self) -> int:
        """兼容别名（只读）：等价于 `残留账本硬上限`，**本质是硬上限**。"""
        return self.残留账本硬上限

    # ── 装配 ──────────────────────────────────────────────────

    def 接排空管理器(self, 排空管理器: Any) -> None:
        """接入自动排空管理器：执行线程自己持「活动任务」计数。

        挂死的执行线程永远走不到 `结束任务()`，所以排空时
        `活动任务数` 不为 0 —— 这就是「超时后仍有执行单元在跑」的如实暴露。
        没有可用的线程终止手段，故不注册强制终止器（注册了也杀不掉，等于撒谎）。
        """
        with self._锁:
            self._排空管理器 = 排空管理器

    # ── 执行 ──────────────────────────────────────────────────

    def 执行(self, 调用: Callable[[], Any], *, 能力id: str, 包id: str = "",
             请求id: str = "", 超时秒: float,
             上下文: Any = None) -> tuple[Any, 残留执行 | None]:
        """在独立线程里执行 `调用`。

        返回 `(结果, None)`：在时限内完成（实现异常在调用方线程原样抛出）；
        返回 `(None, 残留记录)`：已到时限，实现仍在运行 —— 调用方必须按超时回报，
        并把残留记录如实带进错误说明与资源释放结论。

        `上下文` 会在执行线程里重新进入（运行上下文是**线程局部栈**）：否则实现
        在别的线程里读 `全局上下文管理器.当前()` 会拿到空上下文，属「换线程就跑偏」
        的隐性失真。传的是同一个上下文对象，语义与原来的同线程直调保持一致。
        """
        时限 = max(0.001, float(超时秒))
        with self._锁:
            self._序号 += 1
            序号 = self._序号
        记录 = 残留执行(序号=序号, 能力id=能力id, 包id=包id, 请求id=请求id,
                        线程名=f"{线程名前缀}-{序号}", 超时秒=时限,
                        开始时刻=time.monotonic())
        完成事件 = 记录.完成事件
        状态: dict[str, Any] = {"完成": False, "值": None, "异常": None}
        状态锁 = threading.Lock()

        def 执行体() -> None:
            排空 = self._排空管理器
            已计数 = bool(排空 is not None and 排空.开始任务())
            上下文管理器 = None
            if 上下文 is not None:
                from 运行核心.能力调用.运行上下文.上下文 import 全局上下文管理器
                上下文管理器 = 全局上下文管理器
                上下文管理器.进入(上下文)
            try:
                try:
                    状态["值"] = 调用()
                except BaseException as 异常:  # noqa: BLE001 - 原样带回调用方线程
                    状态["异常"] = 异常
            finally:
                with 状态锁:
                    状态["完成"] = True
                if 上下文管理器 is not None:
                    上下文管理器.退出()
                if 排空 is not None and 已计数:
                    排空.结束任务()
                完成事件.set()

        线程 = threading.Thread(target=执行体, name=记录.线程名, daemon=True)
        线程.start()
        if 完成事件.wait(timeout=时限):
            return self._取出已完成(状态), None
        # 到点后再确认一次：刚好在时限边界完成的，不能误记成残留。
        with 状态锁:
            已完成 = bool(状态["完成"])
        if 已完成:
            return self._取出已完成(状态), None
        self._登记残留(记录)
        return None, 记录

    @staticmethod
    def _取出已完成(状态: dict[str, Any]) -> Any:
        异常 = 状态.get("异常")
        if 异常 is not None:
            raise 异常
        return 状态.get("值")

    def _登记残留(self, 记录: 残留执行) -> None:
        """登记一条超时残留；在册明细条目数**硬性**不超过 `残留账本硬上限`。

        超限时只累加 `_丢弃残留数`（读取侧可见），绝不为了「如实登记」而让账本
        无界增长 —— 明细有界、计数如实，是这里唯一自洽的口径。
        """
        with self._锁:
            self._累计超时数 += 1
            self._清理已结束()
            if len(self._残留) < self.残留账本硬上限:
                self._残留[记录.序号] = 记录
                return
            self._丢弃残留数 += 1

    def _清理已结束(self) -> None:
        """在册位不够时优先回收「已经结束」的条目；仍在运行的一律保留（如实）。

        这是**腾位**而不是截断：已结束条目转成 `已归档残留数` 计数后出册，
        在册位因此不会被「跑完的残留」占死；真正仍在运行的条目一条都不动，
        所以超限时唯一诚实的做法是「不入册 + 计数」（见 `_登记残留`）。
        """
        if len(self._残留) < self.残留账本硬上限:
            return
        for 序号 in sorted(self._残留):
            if len(self._残留) < self.残留账本硬上限:
                break
            if not self._残留[序号].仍在运行():
                self._残留.pop(序号, None)
                self._已归档残留数 += 1

    # ── 观测 ──────────────────────────────────────────────────

    def 状态快照(self) -> dict[str, Any]:
        with self._锁:
            记录列表 = list(self._残留.values())
            仍在运行 = [r for r in 记录列表 if r.仍在运行()]
            return {
                "仍在运行残留数": len(仍在运行),
                "账本条目数": len(记录列表),
                "已归档残留数": self._已归档残留数,
                "累计超时次数": self._累计超时数,
                "排空已接入": self._排空管理器 is not None,
                "仍在运行明细": [r.转字典() for r in 仍在运行],
                # ── 有界性自证（新增，不改变既有键的语义）──────────────
                #: 在册明细条目的硬界；`账本条目数 ≤ 账本硬上限` 恒成立
                "账本硬上限": self.残留账本硬上限,
                "账本已达硬上限": len(记录列表) >= self.残留账本硬上限,
                #: 因账本已满而**未能入册**的残留条数：丢弃的是明细，不是事实；
                #: 「真实残留规模（下界）」= 账本条目数 + 因上限丢弃残留数
                "因上限丢弃残留数": self._丢弃残留数,
                "真实残留规模下界": len(记录列表) + self._丢弃残留数,
            }

    def 重置账本(self) -> None:
        """仅供测试隔离：清空账本计数（不影响已在运行的线程）。"""
        with self._锁:
            self._残留.clear()
            self._已归档残留数 = 0
            self._累计超时数 = 0
            self._丢弃残留数 = 0


# 执行器是进程级单例：不绑定某一个调用方，所有经唯一能力调用服务的调用共用一份
# 残留账本（账本口径唯一，才不会出现「有的超时看得见、有的看不见」）。
执行器 = 超时执行器()


def 残留账本快照() -> dict[str, Any]:
    """进程级残留执行账本快照（诊断用：超时后到底还有多少东西在跑）。"""
    return 执行器.状态快照()
