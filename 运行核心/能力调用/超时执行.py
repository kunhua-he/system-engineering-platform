def 执行通道(形态: str) -> str:
    """形态 → 执行通道（`直调` / `线程` / `任务通道`）；未登记形态按默认形态取通道。

    这是**调用方与执行器共用的唯一分流依据**（见 `执行通道表` 的说明）。
    """
    return 执行通道表.get(执行形态取值(形态), 执行通道表[默认执行形态])


def 执行形态取值(声明: Any) -> str:
    """把关声明归一成四种形态之一；未知/空/非法一律回落 `默认执行形态`。

    归一语义与 `_归一上限` 同一条：**非法不静默变成某个危险值**，而是回到保守默认。
    """
    if 声明 is None:
        return 默认执行形态
    文本 = str(声明).strip()
    return 文本 if 文本 in 执行形态表 else 默认执行形态


def 声明执行形态(实现: Any, 形态: str = 默认执行形态) -> Any:
    """给能力实现句柄**显式声明**执行形态，返回带该声明的新句柄（原始句柄不动）。

    为什么用「登记期包一层」而不是改能力契约的注册字段：注册入口有 141 个包、
    686 条能力，且**调用前置检查会逐字校验注册参数表与包声明**（改注册面就会
    波及其它并发维修路的文件）。`能力实现` 是 frozen dataclass，用
    `dataclasses.replace` 复制一份只改「执行形态」这一个可选字段，其余字段逐字不变
    —— 旧数据、旧调用方、旧门禁零影响。

    非法形态**明确拒绝**（抛 ValueError），不静默改成默认：形态是资源护栏的输入，
    写错了要当场知道。
    """
    文本 = str(形态).strip()
    if 文本 not in 执行形态表:
        raise ValueError(f"未知执行形态 {形态!r}；合法取值: {list(执行形态表)}")
    return replace(实现, 执行形态=文本)


def _本平台包id(包id: str) -> bool:
    """`包id` 是否属于**本平台自身**（源码树里能按顶层目录名定位到）。

    这是保守推断唯一敢当硬事实用的判据：包前缀（`支持库` / `模块库` / `平台控制面`
    / `运行核心` / `技能库` / `启动监督器`）就是源码树的顶层目录名 → `包id` 是点分路径
    ⇒ 路径存在即本平台包。第三方/虚拟包（`外部提供者.*` / 测试夹具包）在源码树里
    没有对应目录 → 判**非本平台** → 走保守默认。
    """
    if not 包id:
        return 假
    系统根 = _系统根目录()
    if 系统根 is None:
        return 假
    try:
        return (系统根.joinpath(*str(包id).split("."))).is_dir()
    except (OSError, ValueError):
        return 假


_系统根缓存: tuple[str, Path | None] | None = None
_系统根锁 = threading.Lock()


def _系统根目录() -> Path | None:
    """本模块所在源码树的系统根（`<根>/运行核心/能力调用/超时执行.py` → 上溯三级）。

    缓存一次（每进程常量），失败缓存为空值 —— 只影响保守推断的精度，不影响正确性。
    """
    global _系统根缓存
    with _系统根锁:
        if _系统根缓存 is None:
            系统根 = Path(__file__).resolve()
            for _祖先 in 系统根.parents:
                if (_祖先 / "支持库").is_dir() and (_祖先 / "模块库").is_dir():
                    系统根 = _祖先
                    break
            else:
                系统根 = None
            _系统根缓存 = (str(Path(__file__).resolve()), 系统根)
        return _系统根缓存[1]


def _推断执行形态(实现: Any) -> tuple[str, str]:
    """保守推断执行形态：返回 `(形态, 推断依据)`。

    轮次（每轮都只认可静态复算的事实，不猜、不嗅探运行期行为）：

    1. **端点形状**（提供者声明的 `端点`，只在 `提供者配置/*.json` 里）：命中模型/
       推理端点 → `阻塞IO`（**不直接判 `长耗时`**：端点形状像模型但能力可以是
       完全本地的外部适配能力，误标长耗时的代价更大；模型与语音转写的长耗时由
       提供者级显式声明开出）；命中常驻/会话端点 → `常驻有状态`；命中外部转换/
       压缩/转写关键词 → `长耗时`。
    2. **本平台包**：平台自身的适配层提供者是外部边界（`支持库.适配层.*`，会调
       外部命令/网络/数据库/子进程）→ `阻塞IO`；其余平台内包（后端支持库、模块库、
       平台控制面、运行核心）→ `即时纯计算`。
    3. **非本平台包**（第三方/虚拟/测试包）：本模块对它的执行单元一无所知 →
       `默认执行形态`（保守取阻塞IO）。
    """
    端点 = str(getattr(实现, "端点", "") or "")
    if 端点:
        小写端点 = 端点.lower()
        if any(关键词 in 端点 or 关键词 in 小写端点 for 关键词 in _常驻端点关键词):
            return 形态_常驻有状态, f"提供者端点形状为常驻/会话类（端点 {端点!r}）"
        if any(关键词 in 端点 or 关键词 in 小写端点 for 关键词 in _模型端点关键词):
            return 形态_阻塞IO, f"提供者端点形状为模型/推理类（端点 {端点!r}）"
        if any(关键词 in 端点 or 关键词 in 小写端点 for 关键词 in _长耗时端点关键词):
            return 形态_长耗时, f"提供者端点形状为外部转换/压缩/转写类（端点 {端点!r}）"
    包id = str(getattr(实现, "包id", "") or "")
    if _本平台包id(包id):
        if 包id.startswith("支持库.适配层."):
            return 形态_阻塞IO, f"平台适配层提供者（{包id}）会调外部命令/网络/数据库/子进程"
        return 形态_即时纯计算, f"平台内包（{包id}）无外部执行单元"
    return 默认执行形态, f"包 {包id or '未知'} 非本平台包，执行单元未知，保守取默认形态"


def 判定执行形态(实现: Any) -> tuple[str, str, str]:
    """判定一次能力调用的执行形态：返回 `(形态, 判定来源, 判定依据)`。

    这是**调用方唯一的形态判定入口**（公开名）：`唯一能力调用服务` 只 import 它，
    绝不复写判据 —— 判定两套就会出现「调用方按一种形态分流、执行器按另一种执行」。

    优先级（**声明优先，推断兜底**）：
    1. `能力实现.执行形态`（能力级显式声明，`声明执行形态()` 写入）；
    2. `能力实现.提供者执行形态`（提供者级声明，注册方按提供者给出）；
    3. 保守推断（见 `_推断执行形态`）。
    """
    显式 = getattr(实现, "执行形态", "")
    if 显式:
        return 执行形态取值(显式), "能力级声明", f"能力 {getattr(实现, '能力id', '')} 显式声明"
    提供者级 = getattr(实现, "提供者执行形态", "")
    if 提供者级:
        return 执行形态取值(提供者级), "提供者级声明", "注册方按提供者声明"
    形态, 依据 = _推断执行形态(实现)
    return 形态, "保守推断", 依据


