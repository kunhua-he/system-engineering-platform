_实例序号 = 0


class 超时执行器:
    """独立线程执行 + 事件带时限等待；超时如实记账，绝不假装回收。

    线程侧有界准入见模块说明第 5 条：执行前占「全局 + 每能力」槽位，满载即
    返回 `限流` 失败结果，不排队、不起线程。
    """

    def __init__(self, 残留账本上限: int = 256, *,
                 全局执行线程上限: int | None = None,
                 每能力执行线程上限: int | None = None) -> None:
        """`残留账本上限` 是**硬上限**（在册明细条目数的硬界），不是软上限。

        参数名保留 `残留账本上限`（对外契约不变）；规范字段名是
        `残留账本硬上限`，旧名以只读属性形式继续可读（同一取值，不会漂移）。

        `全局执行线程上限` / `每能力执行线程上限`：线程侧准入上限，None ⇒ 取
        模块常量（单一来源）。闸门名带执行器实例号，故同一进程里并存多个实例
        （生产只有一个 `执行器` 单例；测试各自造实例）时上限与占用互不串台。
        """
        global _实例序号
        with _实例计数锁:
            _实例序号 += 1
            实例号 = _实例序号
        基名 = f"{闸门名前缀}-{实例号}"
        self._锁 = threading.RLock()
        self._残留: dict[int, 残留执行] = {}
        self._序号 = 0
        self._已归档残留数 = 0
        self._累计超时数 = 0
        #: 因账本已满（且全部仍在运行）而**没能入册**的残留条数；只累计计数，
        #: 绝不为它保留明细 —— 否则「有上限」就是自欺（旧实现的真缺陷）。
        self._丢弃残留数 = 0
        self._排空管理器 = None
        self.残留账本硬上限 = max(1, int(残留账本上限))
        # ── 线程侧准入（见模块说明第 5 条）──────────────────────────
        self._闸门基名 = 基名
        self.全局执行线程上限 = _归一上限(全局执行线程上限, 默认全局执行线程上限)
        self.每能力执行线程上限 = _归一上限(每能力执行线程上限, 默认每能力执行线程上限)
        self._准入拒绝数 = 0
        self._准入释放失败数 = 0
        self._准入拒绝明细: deque[dict[str, Any]] = deque(maxlen=准入拒绝明细上限)
        #: 已为哪些 能力id 建过独立闸门（有界：超 `每能力闸门数上限` 走共享兜底闸门）
        self._已登记能力id: set[str] = set()
        self._兜底次数 = 0

    @property
    def 残留账本上限(self) -> int:
        """兼容别名（只读）：等价于 `残留账本硬上限`，**本质是硬上限**。"""
        return self.残留账本硬上限

    @property
    def 全局闸门名(self) -> str:
        return f"{self._闸门基名}.全局"

    @property
    def 兜底闸门名(self) -> str:
        return f"{self._闸门基名}.能力{兜底闸门后缀}"

    def 能力闸门名(self, 能力id: str) -> str | None:
        """每能力闸门名（未过登记上限时的规范名）；能力id 为空则不做每能力准入。"""
        return f"{self._闸门基名}.能力.{能力id}" if 能力id else None

    def _路由能力闸门(self, 能力id: str) -> str | None:
        """把 能力id 路由到闸门名：独立闸门（≤ 登记上限）或共享兜底闸门。

        闸门名按 能力id 生成 ⇒ 调用方传任意字符串都会新增一个闸门；若不设登记
        上限，闸门表会被无界撑大（等于把无界从线程搬到闸门表）。超限后统一走
        兜底闸门并计数，有界性与可观测性都在。
        """
        if not 能力id:
            return None
        with self._锁:
            if 能力id in self._已登记能力id:
                return f"{self._闸门基名}.能力.{能力id}"
            if len(self._已登记能力id) >= 每能力闸门数上限:
                self._兜底次数 += 1
                return self.兜底闸门名
            self._已登记能力id.add(能力id)
        return f"{self._闸门基名}.能力.{能力id}"

    # ── 装配 ──────────────────────────────────────────────────

    def 接排空管理器(self, 排空管理器: Any) -> None:
        """接入自动排空管理器：执行线程自己持「活动任务」计数。

        挂死的执行线程永远走不到 `结束任务()`，所以排空时
        `活动任务数` 不为 0 —— 这就是「超时后仍有执行单元在跑」的如实暴露。
        没有可用的线程终止手段，故不注册强制终止器（注册了也杀不掉，等于撒谎）。
        """
        with self._锁:
            self._排空管理器 = 排空管理器

    # ── 线程侧准入（后端：平台容量闸门优先，探测不到则降级）────────────

    @staticmethod
    def _确保并占用(闸门名: str, 上限: int) -> dict[str, Any]:
        """新建/复用闸门并尝试占用 1 槽位；满载 ⇒ `{"占用": False, ...}`。"""
        后端, _说明 = _解析准入后端()
        后端.确保(闸门名, 上限)
        return dict(后端.尝试占用(闸门名, 上限) or {})

    def _归还槽位(self, 闸门名: str) -> None:
        """归还 1 槽位。归还失败不吞、也不改调用结论：计数 + 明细如实留痕。"""
        try:
            后端, _说明 = _解析准入后端()
            成功, 说明 = 后端.归还(闸门名)
        except Exception as 异常:  # noqa: BLE001 - 归还异常必须留痕，不许静默吞掉
            成功, 说明 = 假, f"{type(异常).__name__}: {异常}"
        if 成功:
            return
        with self._锁:
            self._准入释放失败数 += 1
            self._准入拒绝明细.append({
                "阶段": "槽位归还失败", "闸门名": 闸门名, "说明": 说明,
                "时间": time.strftime("%Y-%m-%d %H:%M:%S"),
            })

    def _记准入拒绝(self, 维度: str, 闸门名: str, 上限: int,
                    占用: dict[str, Any], 能力id: str) -> dict[str, Any]:
        """满载拒绝的有界留痕（明细最多 `准入拒绝明细上限` 条，累计值另计）。"""
        详情 = {
            "维度": 维度, "闸门名": 闸门名, "上限": 上限,
            "当前占用": 占用.get("当前占用"), "能力id": 能力id,
            "时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        }
        with self._锁:
            self._准入拒绝数 += 1
            self._准入拒绝明细.append(dict(详情))
        return 详情

    def _准入(self, 能力id: str) -> tuple[list[str], dict[str, Any] | None, str]:
        """线程侧有界准入：全局槽位 → 每能力槽位。

        返回 `(已占闸门名列表, None, "")`：**通过**；占用方是调用方，但槽位
        由执行单元（执行体）在退出时归还，线程没起来时由调用方立即归还。
        返回 `([], 拒绝详情, 错误说明)`：**满载**，已占槽位一律即刻归还，
        调用方不得起线程、不得排队等待。

        **异常路径同样不留占死槽**（2026-09-18 补）：每能力那一步是「先抛后占」
        或「判定失败」都有分支，`确保/尝试占用` 自身可能抛（后端不可用、闸门表
        异常）—— 已占的**全局**槽位若不在这里兜底归还，就会永久占死一格全局
        预算（有效上限被静默削减，属「资源护栏 fail-open」）。故每能力那一步
        整段包在 `try` 里：任何异常都先归还全局槽位再原样抛出，绝不吞掉异常、
        也不把「没占上」写成「占上了」。
        """
        全局占用 = self._确保并占用(self.全局闸门名, self.全局执行线程上限)
        if not 全局占用.get("占用"):
            拒绝 = self._记准入拒绝("全局", self.全局闸门名,
                                    self.全局执行线程上限, 全局占用, 能力id)
            说明 = (f"能力执行线程已达全局上限 {self.全局执行线程上限}"
                    f"（当前占用 {全局占用.get('当前占用')}）：拒绝新建执行线程，不排队")
            return [], 拒绝, 说明
        try:
            能力闸门 = self._路由能力闸门(能力id)
            if 能力闸门 is None:
                return [self.全局闸门名], None, ""
            能力占用 = self._确保并占用(能力闸门, self.每能力执行线程上限)
        except BaseException:
            # 抛出点上「每能力」槽位尚未占到（占用失败就是异常），已占的全局槽位
            # 必须立刻归还；`_归还槽位` 自吞异常，故它绝不会掩盖本异常。
            self._归还槽位(self.全局闸门名)
            raise
        if not 能力占用.get("占用"):
            拒绝 = self._记准入拒绝("每能力", 能力闸门,
                                    self.每能力执行线程上限, 能力占用, 能力id)
            说明 = (f"能力 {能力id} 的执行线程已达每能力上限 {self.每能力执行线程上限}"
                    f"（当前占用 {能力占用.get('当前占用')}）：拒绝新建执行线程，不排队")
            # 每能力被拒 → 已占的全局槽位必须立刻归还，否则全局预算被拒掉的调用占死
            self._归还槽位(self.全局闸门名)
            return [], 拒绝, 说明
        return [self.全局闸门名, 能力闸门], None, ""

    def _准入失败结果(self, 拒绝: dict[str, Any], 说明: str, *,
                      能力id: str, 包id: str, 请求id: str) -> Any:
        """满载的**明确失败**：统一结果 + 公开码「限流」+ 同一口径的详情。

        为什么用公开码「限流」而不是「内部错误/超时」：网关的工作线程饱和就是
        回这个码（`统一网关.本地网关.公开错误码状态映射` → HTTP 429），执行线程
        饱和是同一类资源问题，沿用同码才能让调用方按同一策略（退避重试）处理。
        用统一结果而不是抛异常，是本平台的既成铁律：`唯一能力调用服务.调用能力`
        对任何调用方都只返回统一结果，异常不得逸出到调用方。
        """
        return 统一结果.失败(
            "限流", 说明, 来源="超时执行器.线程准入", 可重试=真,
            详情={
                "准入门": 拒绝,
                "能力id": 能力id, "包id": 包id, "请求id": 请求id,
                "全局执行线程上限": self.全局执行线程上限,
                "每能力执行线程上限": self.每能力执行线程上限,
            },
        )

    @staticmethod
    def _形态不匹配结果(说明: str, *, 能力id: str, 包id: str, 请求id: str,
                        判定: dict[str, Any]) -> Any:
        """形态不匹配的**明确失败**：统一结果 + 公开码「形态不匹配」（→ HTTP 503）。

        同 `_准入失败结果`：用统一结果收口而不是抛异常（调用服务对任何调用方只
        返回统一结果）。「形态不匹配」是**能力与执行通道的匹配问题**，不是调用方
        参数错、不是资源饱和、更不是超时 —— 单列公开码、单给 503，调用方据此才能
        改走任务通道（而不是按 429 退避重试，那会永远重试到同一个错）。
        """
        return 统一结果.失败(
            "形态不匹配", 说明, 来源=执行形态来源, 可重试=假,
            详情={
                "能力id": 能力id, "包id": 包id, "请求id": 请求id,
                **判定,
                "建议通道": "任务系统.提交",
            },
        )

    # ── 执行 ──────────────────────────────────────────────────

    def 执行(self, 调用: Callable[[], Any], *, 能力id: str, 包id: str = "",
             请求id: str = "", 超时秒: float, 实现: Any = None,
             上下文: Any = None) -> tuple[Any, 残留执行 | None]:
        """按**执行形态**决定执行单位：默认形态直调，有阻塞风险的形态才起线程。

        返回：
        - `(结果, None)`：在时限内完成（实现异常在调用方线程原样抛出）；
        - `(None, 残留记录)`：已到时限，实现仍在运行 —— 调用方必须按超时回报，
          并把残留记录如实带进错误说明与资源释放结论；
        - `(统一结果.失败(错误码="限流"), None)`：**线程侧准入满载**（模块说明
          第 5 条），本次调用没有起线程、没有排队；
        - `(统一结果.失败(错误码="形态不匹配"), None)`：形态为 `常驻有状态`
          （模块说明第 6 条），本模块不执行 —— 调用方原样收口即可。

        两形态两路径（**每路径只有一套机制**，不设形态开关散落各处）：

        - `即时纯计算`：**调用方线程直调**，零线程；不占执行线程槽位（不制造也不
          消耗），残留记录如实标注「本轮调用单元即调用方线程、遵守自身预算、无独立
          执行线程可挂起」—— 不假装起了线程、也不谎报可取消。
        - `阻塞IO` / `长耗时`：独立执行线程 + 事件带时限等待（有界准入在**建线程
          之前**），到点即返回，调用方线程立刻归还。

        `实现` 是能力实现句柄（形态判定与 `残留执行.包id` 的唯一来源；不传则按
        `包id` 参数做保守推断）。`上下文` 会在执行线程里重新进入（运行上下文是
        **线程局部栈**）：否则实现在别的线程里读 `全局上下文管理器.当前()` 会拿到
        空上下文，属「换线程就跑偏」的隐性失真。传的是同一个上下文对象，语义与
        同线程直调保持一致；直调路径本就在同一线程，进入/退出由调用方负责，不重复进。
        """
        时限 = max(0.001, float(超时秒))
        if 实现 is None:
            实现 = _形态替身(能力id=能力id, 包id=包id)
        形态, 判定来源, 判定依据 = 判定执行形态(实现)
        判定 = {"执行形态": 形态, "形态判定来源": 判定来源, "形态判定依据": 判定依据}
        通道 = 执行通道(形态)
        if 通道 != 通道_线程:
            if 通道 == 通道_任务:
                return self._形态不匹配结果(
                    f"能力 {能力id}（包 {包id or (getattr(实现, '包id', '') or '未知')}）"
                    f"判定为 {形态_常驻有状态}（判定依据：{判定依据}）；"
                    + 常驻有状态走任务通道说明,
                    能力id=能力id, 包id=包id, 请求id=请求id, 判定=判定), None
            return self._直调(调用), None
        闸门名表, 拒绝详情, 拒绝说明 = self._准入(能力id)
        if 拒绝详情 is not None:
            return self._准入失败结果(拒绝详情, 拒绝说明, 能力id=能力id,
                                     包id=包id, 请求id=请求id), None
        with self._锁:
            self._序号 += 1
            序号 = self._序号
        记录 = 残留执行(序号=序号, 能力id=能力id, 包id=包id, 请求id=请求id,
                        线程名=f"{线程名前缀}-{序号}", 超时秒=时限,
                        开始时刻=time.monotonic(), 执行形态=形态)
        完成事件 = 记录.完成事件
        状态: dict[str, Any] = {"完成": 假, "值": None, "异常": None}
        状态锁 = threading.Lock()

        def 归还准入() -> None:
            for 闸门名 in 闸门名表:
                self._归还槽位(闸门名)

        def 执行体() -> None:
            # 外层 finally 保住「槽位归执行单元自己持有」这条不变式：无论实现
            # 正常返回、抛异常、还是上下文进出失败，槽位都在本条路径上归还。
            try:
                排空 = self._排空管理器
                已计数 = bool(排空 is not None and 排空.开始任务())
                上下文管理器 = None
                if 上下文 is not None:
                    from 运行核心.能力调用.运行上下文.上下文 import 全局上下文管理器
                    上下文管理器 = 全局上下文管理器
                    上下文管理器.进入(上下文)
                try:
                    try:
                        状态["值"] = 调用()
                    except BaseException as 异常:  # noqa: BLE001 - 原样带回调用方线程
                        状态["异常"] = 异常
                finally:
                    with 状态锁:
                        状态["完成"] = 真
                    if 上下文管理器 is not None:
                        上下文管理器.退出()
                    if 排空 is not None and 已计数:
                        排空.结束任务()
            finally:
                归还准入()
                # **先归还槽位、后置完成事件**（顺序不能反）：调用方是
                # `完成事件.wait` 的等待者，若先置事件再归还，调用方在
                # 「槽位已释放」之前就被唤醒 —— 紧接着发起的同类调用会读到
                # 上一个单元还挂着的占用，被误判 `限流`（假限流，且随调度抖动
                # 时有时无）。置事件放在最后，使
                # 「调用方看见完成 ⇒ 本次槽位已归还」成为真不变式。
                # `_归还槽位` 内部自吞异常、绝不抛出，故置事件不会因此被跳过。
                完成事件.set()

        try:
            线程 = threading.Thread(target=执行体, name=记录.线程名, daemon=True)
            线程.start()
        except BaseException:
            # 线程没起来 ⇒ 执行体 永不运行 ⇒ 槽位必须由调用方立刻归还，
            # 否则被拒掉的调用把全局/每能力预算占死（有界准入必须先保证这条）。
            归还准入()
            raise
        if 完成事件.wait(timeout=时限):
            return self._取出已完成(状态), None
        # 到点后再确认一次：刚好在时限边界完成的，不能误记成残留。
        with 状态锁:
            已完成 = bool(状态["完成"])
        if 已完成:
            return self._取出已完成(状态), None
        self._登记残留(记录)
        return None, 记录

    def _直调(self, 调用: Callable[[], Any]) -> Any:
        """默认形态的**同线程直调**：零线程、零槽位、零事件。

        为什么不在这里也套一层「时限」：直调路径没有独立执行单元，任何时限都
        只能靠调用方自身预算遵守（Python 无法中断正在跑的调用）。诚实的做法就是
        **不建线程、不假装有超时手段**：挂死风险由调用方按形态判定承担
        （`超时执行器.执行()` 只把有阻塞风险的形态放进线程）。

        实现自身抛的异常（含它自己抛的 `TimeoutError`）一律原样向上，由调用方按
        公开错误码表映射 —— 与「实现异常在调用方线程原样抛出」的既有语义逐字一致。
        """
        return 调用()

    @staticmethod
    def _取出已完成(状态: dict[str, Any]) -> Any:
        异常 = 状态.get("异常")
        if 异常 is not None:
            raise 异常
        return 状态.get("值")

    def _登记残留(self, 记录: 残留执行) -> None:
        """登记一条超时残留；在册明细条目数**硬性**不超过 `残留账本硬上限`。

        超限时只累加 `_丢弃残留数`（读取侧可见），绝不为了「如实登记」而让账本
        无界增长 —— 明细有界、计数如实，是这里唯一自洽的口径。
        """
        with self._锁:
            self._累计超时数 += 1
            self._清理已结束()
            if len(self._残留) < self.残留账本硬上限:
                self._残留[记录.序号] = 记录
                return
            self._丢弃残留数 += 1

    def _清理已结束(self) -> None:
        """在册位不够时优先回收「已经结束」的条目；仍在运行的一律保留（如实）。

        这是**腾位**而不是截断：已结束条目转成 `已归档残留数` 计数后出册，
        在册位因此不会被「跑完的残留」占死；真正仍在运行的条目一条都不动，
        所以超限时唯一诚实的做法是「不入册 + 计数」（见 `_登记残留`）。
        """
        if len(self._残留) < self.残留账本硬上限:
            return
        for 序号 in sorted(self._残留):
            if len(self._残留) < self.残留账本硬上限:
                break
            if not self._残留[序号].仍在运行():
                self._残留.pop(序号, None)
                self._已归档残留数 += 1

    # ── 观测 ──────────────────────────────────────────────────

    @staticmethod
    def _查占用(闸门名: str) -> tuple[int | None, str]:
        """读闸门当前占用（只读诊断）：读不到如实说明，不打断调用链。"""
        try:
            后端, _说明 = _解析准入后端()
            return 后端.查占用(闸门名)
        except Exception as 异常:  # noqa: BLE001 - 只读诊断不得打断调用链
            return None, f"{type(异常).__name__}: {异常}"

    def _每能力占用明细(self) -> list[dict[str, Any]]:
        """本实例的每能力闸门占用（按占用降序、条数有界）。"""
        try:
            后端, _说明 = _解析准入后端()
            return 后端.列表(f"{self._闸门基名}.能力", 每能力占用明细上限)
        except Exception:  # noqa: BLE001 - 只读诊断不得打断调用链
            return []

    def 状态快照(self) -> dict[str, Any]:
        with self._锁:
            记录列表 = list(self._残留.values())
            仍在运行 = [r for r in 记录列表 if r.仍在运行()]
            准入拒绝数 = self._准入拒绝数
            准入释放失败数 = self._准入释放失败数
            准入拒绝明细 = list(self._准入拒绝明细)
            全局上限 = self.全局执行线程上限
            每能力上限 = self.每能力执行线程上限
            兜底次数 = self._兜底次数
            已登记闸门数 = len(self._已登记能力id)
        后端, 降级说明 = _解析准入后端()
        全局占用, 查询说明 = self._查占用(self.全局闸门名)
        return {
            "仍在运行残留数": len(仍在运行),
            "账本条目数": len(记录列表),
            "已归档残留数": self._已归档残留数,
            "累计超时次数": self._累计超时数,
            "排空已接入": self._排空管理器 is not None,
            "仍在运行明细": [r.转字典() for r in 仍在运行],
            # ── 有界性自证（新增，不改变既有键的语义）──────────────
            #: 在册明细条目的硬界；`账本条目数 ≤ 账本硬上限` 恒成立
            "账本硬上限": self.残留账本硬上限,
            "账本已达硬上限": len(记录列表) >= self.残留账本硬上限,
            #: 因账本已满而**未能入册**的残留条数：丢弃的是明细，不是事实；
            #: 「真实残留规模（下界）」= 账本条目数 + 因上限丢弃残留数
            "因上限丢弃残留数": self._丢弃残留数,
            "真实残留规模下界": len(记录列表) + self._丢弃残留数,
            # ── 线程侧有界准入（新增，不改变既有键的语义）──────────
            #: 执行线程数的**全局硬界**：`全局执行线程占用 ≤ 全局执行线程上限` 恒成立
            "全局执行线程上限": 全局上限,
            "每能力执行线程上限": 每能力上限,
            "全局执行线程占用": 全局占用,
            "准入后端": 后端.名称,
            "准入降级说明": 降级说明,
            "累计准入拒绝数": 准入拒绝数,
            "准入释放失败数": 准入释放失败数,
            "准入拒绝明细": 准入拒绝明细,
            "每能力占用明细": self._每能力占用明细(),
            "每能力闸门数上限": 每能力闸门数上限,
            "已登记能力闸门数": 已登记闸门数,
            "走兜底闸门次数": 兜底次数,
            "准入查询说明": 查询说明,
            # ── 执行形态（P1-4 新增，不改变既有键的语义）──────────────
            #: 形态表/默认形态/建线程形态表；判定入口是模块级 `_执行形态`
            "执行形态参考": 形态快照(),
        }

    def 重置账本(self) -> None:
        """仅供测试隔离：清空账本与准入计数（不影响已在运行的线程与闸门占用）。"""
        with self._锁:
            self._残留.clear()
            self._已归档残留数 = 0
            self._累计超时数 = 0
            self._丢弃残留数 = 0
            self._准入拒绝数 = 0
            self._准入释放失败数 = 0
            self._准入拒绝明细.clear()
            self._已登记能力id.clear()
            self._兜底次数 = 0


