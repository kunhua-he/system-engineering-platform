"""指纹与绑定面：包指纹校验（防静默漂移）与模块绑定（混入类）。

**为什么独立成文件**（拆分 2026-09-19，开工ID 开工-20260919-162046-1f9d）：本簇原是
`运行核心/能力调用/唯一能力调用.py` 里 `唯一能力调用服务` 类中的一整块职责，拆出只为让
文件回到可维护尺寸，**对外零变化**：成员名、签名、默认值、正文一个字符未改
（搬动方式＝原样片段去 4 空格缩进），主类只改基类列表
（`class 唯一能力调用服务(指纹与绑定面, 诊断面)`）。

**宿主属性契约**（类注解，真源＝主文件 `唯一能力调用服务.__init__`）：
`锁` / `包指纹校验器` / `包指纹缓存` / `包指纹缓存秒`。

**导入方向**：本文件只被 `运行核心/能力调用/唯一能力调用.py` 模块级导入，**不得反向导入**
主文件（会成环）；本文件不引用主文件的任何模块级件，也不引用宿主类名。

**判据唯一事实源**：包指纹「一致/漂移」的判定由注入的校验回调给出（`设置包指纹校验器`
的调用方），本文件只做 1 秒缓存的窗口判定与错误码映射，不自己扫描制品。
"""


from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 假



class 指纹与绑定面:
    """包指纹校验簇 + 模块绑定簇。

    宿主契约（类注解，真源＝主文件 `唯一能力调用服务.__init__`）：
    `锁` / `包指纹校验器` / `包指纹缓存` / `包指纹缓存秒`。
    """


    def 设置包指纹校验器(self, 校验函数) -> None:
        """注入包指纹校验回调：接收包id，返回 (是否一致, 说明)。"""
        with self.锁:
            self._包指纹校验器 = 校验函数
            self._包指纹缓存.clear()

    def 清空包指纹缓存(self) -> None:
        """热接入重新注册指纹后清缓存，避免沿用旧的漂移判定。"""
        with self.锁:
            self._包指纹缓存.clear()

    def _校验包指纹(self, 包id: str) -> tuple[str, str] | None:
        """校验包指纹；一致返回 None，漂移返回 (错误码, 错误说明)。

        带 1 秒缓存：同一包在缓存窗口内不重复扫描，漂移检测延迟不超过 1 秒。
        """
        校验器 = self._包指纹校验器
        if 校验器 is None or not 包id:
            return None
        import time as _时间模块
        现在 = _时间模块.monotonic()
        with self.锁:
            缓存 = self._包指纹缓存.get(包id)
            if 缓存 is not None and 现在 - 缓存[0] < self._包指纹缓存秒:
                一致, 说明 = 缓存[1], 缓存[2]
            else:
                try:
                    一致, 说明 = 校验器(包id)
                except Exception as 异常:
                    一致, 说明 = 假, f"包指纹校验异常: {异常}"
                self._包指纹缓存[包id] = (现在, 一致, 说明)
        if 一致:
            return None
        错误码 = "制品缺失" if "缺失" in 说明 else "制品已变更"
        return 错误码, 说明 or f"包 {包id} 指纹与注册时不一致，请重新热接入"

    # ── 模块绑定 ──────────────────────────────────────────────

    def 绑定模块(self, 模块id: str) -> "唯一能力调用服务":
        """把本服务注入指定模块（模块只持能力 id，不直接导入支持库）。"""
        with self.锁:
            self._模块调用服务表[模块id] = self
            return self

    def 已绑定模块(self, 模块id: str) -> bool:
        with self.锁:
            return 模块id in self._模块调用服务表
