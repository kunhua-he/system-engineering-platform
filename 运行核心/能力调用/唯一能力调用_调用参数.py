def _声明参数名(实现: 能力实现) -> set[str]:
    """能力注册声明的参数名集合（兼容 dict 列表与字符串列表两种注册形态）。"""
    return {
        (参数项.get("名称") if isinstance(参数项, dict) else 参数项)
        for 参数项 in 实现.参数
    }


#: 「不限时」调用在线程路径上的兜底时限：调用方没给时限时线程仍要有一个上限
#: （否则线程准入槽位会被无上限的长跑单元占死），取一天 —— 足够宽，不构成对长耗时
#: 能力的实际约束，又保证「执行线程数有界」这条不变式不被绕过。
不限期线程时限秒 = 86400.0


def _有时限(超时秒: Any) -> bool:
    """`超时秒` 是否为有效时限。

    None / 布尔 / 非数值 / <=0 一律视为「不限时」：None 是调用方没给时限的
    既有语义（保持向后兼容，不把某个默认秒数强加给长耗时能力）；其余非法值
    在三层边界的参数校验处就被拒（HTTP 边界：1 ≤ 超时秒 ≤ 请求超时秒），
    这里再兜一层，绝不让「非法值」静默变成一个时限。
    """
    if 超时秒 is None or isinstance(超时秒, bool):
        return 假
    if not isinstance(超时秒, (int, float)):
        return 假
    return float(超时秒) > 0


def _展开参数(实现: 能力实现, 参数: dict[str, Any]) -> dict[str, Any]:
    """把调用方 dict 按能力注册参数名展开为关键字参数。

    兼容两种注册参数形态：dict 列表（{名称,类型}）与字符串参数名列表。
    规则：
    - dict 键名直接命中声明参数名 → 按名传值。
    - 声明只有 1 个参数（如 内容参数/文件路径 聚合契约）且 dict 键不在
      声明中 → 整个 dict 作为该唯一参数的值（内容参数 聚合语义）。
    - 其余未声明键保持原样（契约层 调用() 会拒绝未知参数）。
    """
    声明参数名 = _声明参数名(实现)
    if len(声明参数名) == 1 and not set(参数).issubset(声明参数名):
        唯一参数名 = next(iter(声明参数名))
        return {唯一参数名: dict(参数)}
    关键字表: dict[str, Any] = {}
    for 键, 值 in (参数 or {}).items():
        关键字表[键] = 值
    return 关键字表
