"""执行器_结果面：`超时执行器` 的**结果面职责**混入类（无状态方法）。

方法名与实现逐字沿用原件：拆混入类不改签名、不改默认值、不改行为，只改「归属」，
故对外面（`超时执行器` 的成员名与签名）零变化。
源：`运行核心/能力调用/超时执行.py`（20260919 拆分，开工-20260919-225500-e4a1）。
"""

from __future__ import annotations

from 运行核心.能力调用.超时执行.形态判定 import 执行形态来源

from typing import Any
from 公共契约.基础类型.结果类型 import 结果 as 统一结果
from 公共契约.基础类型.逻辑类型 import 真, 假

class 执行器结果面:

    def _准入失败结果(self, 拒绝: dict[str, Any], 说明: str, *,
                      能力id: str, 包id: str, 请求id: str) -> Any:
        """满载的**明确失败**：统一结果 + 公开码「限流」+ 同一口径的详情。

        为什么用公开码「限流」而不是「内部错误/超时」：网关的工作线程饱和就是
        回这个码（`统一网关.本地网关.公开错误码状态映射` → HTTP 429），执行线程
        饱和是同一类资源问题，沿用同码才能让调用方按同一策略（退避重试）处理。
        用统一结果而不是抛异常，是本平台的既成铁律：`唯一能力调用服务.调用能力`
        对任何调用方都只返回统一结果，异常不得逸出到调用方。
        """
        return 统一结果.失败(
            "限流", 说明, 来源="超时执行器.线程准入", 可重试=真,
            详情={
                "准入门": 拒绝,
                "能力id": 能力id, "包id": 包id, "请求id": 请求id,
                "全局执行线程上限": self.全局执行线程上限,
                "每能力执行线程上限": self.每能力执行线程上限,
            },
        )

    @staticmethod
    def _形态不匹配结果(说明: str, *, 能力id: str, 包id: str, 请求id: str,
                        判定: dict[str, Any]) -> Any:
        """形态不匹配的**明确失败**：统一结果 + 公开码「形态不匹配」（→ HTTP 503）。

        同 `_准入失败结果`：用统一结果收口而不是抛异常（调用服务对任何调用方只
        返回统一结果）。「形态不匹配」是**能力与执行通道的匹配问题**，不是调用方
        参数错、不是资源饱和、更不是超时 —— 单列公开码、单给 503，调用方据此才能
        改走任务通道（而不是按 429 退避重试，那会永远重试到同一个错）。
        """
        return 统一结果.失败(
            "形态不匹配", 说明, 来源=执行形态来源, 可重试=假,
            详情={
                "能力id": 能力id, "包id": 包id, "请求id": 请求id,
                **判定,
                "建议通道": "任务系统.提交",
            },
        )
