# 线程侧准入上限（**单一来源**：本模块常量；构造参数是测试/装配的覆盖点）
#
# 依据都取平台既有公开上界，不是拍脑袋的数字：
#   全局上限 = 256：执行线程只可能由网关工作线程创建（调用链
#     `HTTP 工作线程 → 唯一能力调用服务.调用能力 → 执行器.执行`），而网关入口层
#     并发上限的**可配置区间**是 1..256（`统一网关.安全.有界服务器.最大工作线程`，
#     校验 `1<=x<=256`）。因此正常并发（执行线程数 ≤ 工作线程数）**永不触发**本上限，
#     只有「实现挂死 → 线程只增不减」的病态泄漏才会被熔断。
#   ⚠ **口径未收口（2026-09-22 现场核）**：入口层还有第二处并发上限
#     `统一网关.本地网关.并发上限`，默认同为 64，但校验区间是 **1..512** ——
#     两处区间不一致，本模块按更保守的 256 取值。收口方向：把 `本地网关.并发上限`
#     的区间收回 1..256，或加一条机器校验「入口上限 ≥ 执行线程上限」
#     （见 `开发文档/未完成事项.md` §7.8 批C 的 C1）。
#   每能力上限 = 64：同上两处网关工作线程数的**默认值**（默认 64）。单个能力把全部
#     默认工作线程占满即熔断，避免一个失控能力吃光全局预算、连带把无关能力一起
#     判失败 —— 与本模块第 4 条拒绝共享线程池是同一条理由（不许「一个挂死放大成
#     全平台挂死」），只是这里把边界显式写出来并做成可观测的拒绝。
默认全局执行线程上限 = 256
默认每能力执行线程上限 = 64
