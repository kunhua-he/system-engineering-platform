"""执行器_核心：`超时执行器` 的**有状态宿主**——装配（多继承混入类）+ 调度。

只留「占用/归还/准入/执行/账本登记」这些**有状态方法**（方法名与实现逐字沿用
原件）：槽位由执行单元自己持有、超时后仍在跑的单元继续占位、账本登记是硬上限
——这些不变式都要求与实例状态同处一处，散到混入类里会让「谁在改状态」变模糊。
源：`运行核心/能力调用/超时执行.py`（20260919 拆分，开工-20260919-225500-e4a1）。
"""

