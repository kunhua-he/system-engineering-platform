"""执行器_观测面：`超时执行器` 的**观测面职责**混入类（无状态方法）。

方法名与实现逐字沿用原件：拆混入类不改签名、不改默认值、不改行为，只改「归属」，
故对外面（`超时执行器` 的成员名与签名）零变化。
源：`运行核心/能力调用/超时执行.py`（20260919 拆分，开工-20260919-225500-e4a1）。
"""

from __future__ import annotations

import 运行核心.能力调用.超时执行.基础 as 基础常量

from 运行核心.能力调用.超时执行.准入闸门 import _解析准入后端
from 运行核心.能力调用.超时执行.形态判定 import 形态快照

from typing import Any

class 执行器观测面:

    # ── 观测 ──────────────────────────────────────────────────

    @staticmethod
    def _查占用(闸门名: str) -> tuple[int | None, str]:
        """读闸门当前占用（只读诊断）：读不到如实说明，不打断调用链。"""
        try:
            后端, _说明 = _解析准入后端()
            return 后端.查占用(闸门名)
        except Exception as 异常:  # noqa: BLE001 - 只读诊断不得打断调用链
            return None, f"{type(异常).__name__}: {异常}"

    def _每能力占用明细(self) -> list[dict[str, Any]]:
        """本实例的每能力闸门占用（按占用降序、条数有界）。"""
        try:
            后端, _说明 = _解析准入后端()
            return 后端.列表(f"{self._闸门基名}.能力", 基础常量.每能力占用明细上限)
        except Exception:  # noqa: BLE001 - 只读诊断不得打断调用链
            return []

    def 状态快照(self) -> dict[str, Any]:
        with self._锁:
            记录列表 = list(self._残留.values())
            仍在运行 = [r for r in 记录列表 if r.仍在运行()]
            准入拒绝数 = self._准入拒绝数
            准入释放失败数 = self._准入释放失败数
            准入拒绝明细 = list(self._准入拒绝明细)
            全局上限 = self.全局执行线程上限
            每能力上限 = self.每能力执行线程上限
            兜底次数 = self._兜底次数
            已登记闸门数 = len(self._已登记能力id)
        后端, 降级说明 = _解析准入后端()
        全局占用, 查询说明 = self._查占用(self.全局闸门名)
        return {
            "仍在运行残留数": len(仍在运行),
            "账本条目数": len(记录列表),
            "已归档残留数": self._已归档残留数,
            "累计超时次数": self._累计超时数,
            "排空已接入": self._排空管理器 is not None,
            "仍在运行明细": [r.转字典() for r in 仍在运行],
            # ── 有界性自证（新增，不改变既有键的语义）──────────────
            #: 在册明细条目的硬界；`账本条目数 ≤ 账本硬上限` 恒成立
            "账本硬上限": self.残留账本硬上限,
            "账本已达硬上限": len(记录列表) >= self.残留账本硬上限,
            #: 因账本已满而**未能入册**的残留条数：丢弃的是明细，不是事实；
            #: 「真实残留规模（下界）」= 账本条目数 + 因上限丢弃残留数
            "因上限丢弃残留数": self._丢弃残留数,
            "真实残留规模下界": len(记录列表) + self._丢弃残留数,
            # ── 线程侧有界准入（新增，不改变既有键的语义）──────────
            #: 执行线程数的**全局硬界**：`全局执行线程占用 ≤ 全局执行线程上限` 恒成立
            "全局执行线程上限": 全局上限,
            "每能力执行线程上限": 每能力上限,
            "全局执行线程占用": 全局占用,
            "准入后端": 后端.名称,
            "准入降级说明": 降级说明,
            "累计准入拒绝数": 准入拒绝数,
            "准入释放失败数": 准入释放失败数,
            "准入拒绝明细": 准入拒绝明细,
            "每能力占用明细": self._每能力占用明细(),
            "每能力闸门数上限": 基础常量.每能力闸门数上限,
            "已登记能力闸门数": 已登记闸门数,
            "走兜底闸门次数": 兜底次数,
            "准入查询说明": 查询说明,
            # ── 执行形态（P1-4 新增，不改变既有键的语义）──────────────
            #: 形态表/默认形态/建线程形态表；判定入口是模块级 `_执行形态`
            "执行形态参考": 形态快照(),
        }
