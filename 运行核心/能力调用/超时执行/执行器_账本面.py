"""执行器_账本面：`超时执行器` 的**账本面职责**混入类（无状态方法）。

方法名与实现逐字沿用原件：拆混入类不改签名、不改默认值、不改行为，只改「归属」，
故对外面（`超时执行器` 的成员名与签名）零变化。
源：`运行核心/能力调用/超时执行.py`（20260919 拆分，开工-20260919-225500-e4a1）。
"""

from __future__ import annotations


class 执行器账本面:

    @property
    def 残留账本上限(self) -> int:
        """兼容别名（只读）：等价于 `残留账本硬上限`，**本质是硬上限**。"""
        return self.残留账本硬上限

    def _清理已结束(self) -> None:
        """在册位不够时优先回收「已经结束」的条目；仍在运行的一律保留（如实）。

        这是**腾位**而不是截断：已结束条目转成 `已归档残留数` 计数后出册，
        在册位因此不会被「跑完的残留」占死；真正仍在运行的条目一条都不动，
        所以超限时唯一诚实的做法是「不入册 + 计数」（见 `_登记残留`）。
        """
        if len(self._残留) < self.残留账本硬上限:
            return
        for 序号 in sorted(self._残留):
            if len(self._残留) < self.残留账本硬上限:
                break
            if not self._残留[序号].仍在运行():
                self._残留.pop(序号, None)
                self._已归档残留数 += 1

    def 重置账本(self) -> None:
        """仅供测试隔离：清空账本与准入计数（不影响已在运行的线程与闸门占用）。"""
        with self._锁:
            self._残留.clear()
            self._已归档残留数 = 0
            self._累计超时数 = 0
            self._丢弃残留数 = 0
            self._准入拒绝数 = 0
            self._准入释放失败数 = 0
            self._准入拒绝明细.clear()
            self._已登记能力id.clear()
            self._兜底次数 = 0
