"""能力调用的真实时限执行（P0 B-02：`超时秒` 参数收了就得真用）。

背景：HTTP 边界严格校验 `1 ≤ 超时秒 ≤ 请求超时秒`，参数一路传到
`后端核心.调用 → 唯一能力调用服务.调用能力 → 实现.调用(**参数)`，但三层函数体
都只声明不使用（引用次数 0）→ 一个挂死的实现会永久占用一个 HTTP 工作线程，
并发上限耗尽后网关对所有新连接回 429，只能重启进程。

本模块给出的真实时限执行语义：

1. **时限是调用方的**：`执行()` 在独立执行线程里跑实现函数，调用方在事件上带
   时限等待；到点即返回，调用方线程（HTTP 工作线程）立刻归还。
2. **超时与实现结果解耦**：超时返回「超时」结论，绝不把「实现稍后返回的结果」
   冒充成本次调用结果；实现自身的异常仍在**调用方线程**里抛出，由调用方的
   公开错误码表统一映射（逐码不变）。
3. **超时后不假装回收**：Python 无法强杀线程（本仓标准库约束下没有安全等价物），
   执行单元是单次函数调用、没有取消点 → **一律不可取消**。因此超时后：
   - 把该执行单元如实登记进「残留执行账本」（能力id/请求id/线程名/已运行秒/
     是否仍在运行），并在返回说明与证据链的「资源释放结论」里写明「仍在运行」；
   - 残留账本由 `状态快照()` 可读，**不隐藏、不冲销**：仍在运行的条目一律不
     因为超限而被悄悄冲掉；
   - 若接入了自动排空管理器（`接排空管理器`），执行线程自己持计数
     （开始任务/结束任务）：挂死时计数不减 → 排空时如实报「活动任务 N」、
     不会谎报归零。**不注册强制终止器**——注册一个杀不掉线程的终止器才是撒谎。
3.1 **账本上限是「硬上限」，不是「软上限」**（2026-09-17 修正）：`残留账本硬上限`
   收的是**在册明细条目数**。旧实现的 `残留账本上限` 只回收「已结束」条目、
   对未结束的一律保留 → 名称为「上限」而实际无界（实测：上限 8、40 个真挂死
   调用 → 账本 40 条、无任何计数暴露被丢弃）。现在的语义：
   - 登记前先 `_清理已结束()` 回收已结束条目（尽量腾出在册位）；
   - 在册位用尽且全部仍在运行时，**不再入册**，只累加 `因上限丢弃残留数`
     （读取侧 `状态快照()["因上限丢弃残留数"]` 可见，并配 `账本已达硬上限` 布尔）；
   - 因此 `账本条目数 ≤ 残留账本硬上限` **恒成立**，账本内存有硬界；
   - 「真实还有多少执行单元在跑」**不由账本口径回答**：账本只是有界的诊断索引，
     全体规模要按 `在册残留数 + 因上限丢弃残留数`（下界）或排空管理器的
     「活动任务数」读取。逐次调用的证据链用的是 `执行()` 返回的记录本身，
     不受账本是否入册影响 —— 丢弃明细绝不等于丢弃证据。

4. **只有确有阻塞风险的形态才配线程**（2026-09-18 修正，审计报告 P1-4）：本模块
   曾经的语义是「给了有效时限就一律起线程」，而 HTTP 边界**始终**显式传时限
   （默认 请求超时秒=1800）⇒ **每一次 HTTP 能力调用都付**「建线程 + Event 等待 +
   跨线程上下文重入」的固定成本，连纯计算能力也不例外（性能基准场景
   `线程包装开销` 量的就是这个差值）。
   现在的语义：**默认形态不建线程**（调用方线程直调，语义与「调用方没传时限」一致）；
   线程只留给**有阻塞风险的形态**（`阻塞IO` / `长耗时`）。选它不是为了省那点微秒，
   而是因为线程是本模块唯一真正有效的**时限手段**：
   - 线程内实现挂死时，调用方线程仍能在时限到点后归还（网关工作线程不被永久占用）；
   - 「每次调用一条线程，不用共享线程池」——共享池的槽位会被挂死任务永久吃掉，
     池满后会把无关能力也一起判超时，等于把一个挂死放大成全平台挂死；线程创建
     开销（微秒级）换取「一个挂死只泄漏它自己那一份」。
   即：**慢的、会卡住调用方的东西用线程兜底，快的、纯计算的东西直调**（判定规则
   见 `_执行形态`，声明入口见下方「执行形态」一节）。

5. **线程侧有界准入**（2026-09-18 修正，未完成事项 §8.3 第 17 项）：上面第 3.1 条
   只给**账本**加了硬上限，**线程数本身仍无界** —— 实测：并发若干次带时限的调用，
   每次调用都会真起一条线程，挂死的实现只增不减，进程线程数无任何全局/每能力
   上限或熔断（外部审计报告①-4 的核部分成立：要补的是线程侧资源准入，不是账本）。
   现在的语义：
   - `执行()` 在**创建线程之前**做准入：先占**全局**槽位，再占**每能力**槽位；
     两个上限都来自本模块常量（见 `默认全局执行线程上限` / `默认每能力执行线程上限`，
     单一来源、可经构造参数覆盖），不散落魔法数字；
   - 准入**优先复用平台现成并发原语**：`支持库.后端.并发控制支持库` 的
     创建容量闸门/占用容量/释放容量（只用包级公开入口，不 import 其 `实现/`）；
     占用一律 `等待秒=0` ⇒ **满载直接拒绝、不排队**（不静默排队无限等）；
   - 该支持库是独立包，冷启动/制品裁剪场景可能**不在随附制品内**（实测：
     `测试中心/运行核心/测试_冷启动反向门禁.py` 的暂存制品只复制
     文件系统/系统核心 支持库 + 文件管理 模块）。硬依赖它会让「线程有界」这条
     核心不变式反向依赖一个可选包，比无界更糟；因此探测不到时降级为
     **语义逐条对齐**的内置标准库有界闸门（同名复用/同锁占用/满载直接拒绝/
     释放幂等），并把降级原因如实写进快照 `准入后端` + `准入降级说明`。
     生产保持全量制品（探测得到 → 恒走平台原语路径）；
   - 满载时**明确失败**：`执行()` 返回统一结果 `结果.失败("限流", …)`（「限流」是
     网关 `公开错误说明表`/`公开错误码状态映射` 里已登记的公开码 → HTTP 429，
     与网关工作线程饱和同一口径），说明里写明是「全局」还是「每能力」饱和、
     上限与当前占用；`详情["准入门"]` 带同一份明细，决不用「超时/内部错误」冒充；
   - **槽位归执行单元自己持有**：执行线程在哪条路径退出（正常返回 / 实现抛异常 /
     超时后继续跑完）就在哪条路径归还槽位；因此超时后仍在跑的挂死单元**继续占着
     它的槽位**，饱和时后续调用被如实判 `限流` —— 这就是「线程数有界」的可观测形态；
   - 线程**没起来**（`Thread.start()` 抛错）时由调用方立刻归还已占槽位，不留占死槽；
   - **准入自身抛异常的路径也不留占死槽**（2026-09-18 补）：每能力那一步
     （`_路由能力闸门` / `_确保并占用`）抛错时，已占的**全局**槽位由 `_准入`
     当场兜底归还后再原样抛出 —— 否则一次后端异常就永久占死一格全局预算
     （有效上限被静默削减、且无任何留痕），资源护栏变成 fail-open；
   - **槽位归还先于完成事件**：执行体在 `finally` 里先 `归还准入()` 再 `完成事件.set()`
     （2026-09-18 修正）。次序反了就会产生**假限流**——调用方被事件唤醒时槽位还没
     释放，它紧接着发起的同类调用会读到上一个单元仍挂着的占用而被误判 `限流`
     （随调度抖动时有时无，属最难复现的一类失真）。现在的次序使
     「调用方看见调用完成 ⇒ 本次槽位已归还」成为真不变式；
   - 满载拒绝**留痕**：`状态快照()["累计准入拒绝数"] / ["准入拒绝明细"]`（明细有界）
     如实可读，不隐藏、不冲销；
   - 每能力闸门名按 `能力id` 生成，故**登记数量也有上限**（`每能力闸门数上限`）：
     超过后新能力id 统一走一条共享兜底闸门并计数，绝不因为「调用方传了 10 万个
     不同能力id」而让闸门表无界增长（有界性是本模块的口径，闸门表也算）。

6. **执行形态：声明优先、保守推断兜底、默认不建线程**（P1-4 的判定规则）
   形态枚举与判定入口都在本模块（单一来源），调用方按 `能力id` 问一次即可：

   - `即时纯计算`：没有自己的执行单元（内联计算、平台内纯函数）。**不建线程**，
     调用方线程直调；超时无法中断它（没有取消点），因此 `执行()` 返回的残留记录
     标 `形态="即时纯计算"`、`可取消=假`，由调用方写明「本轮调用单元即调用方线程，
     遵守自身预算，无独立执行线程可挂起」—— 如实陈述，不假装起了线程。
   - `阻塞IO`：会调用外部命令/网络/数据库/子进程。**建线程**兜时限。
   - `长耗时`：模型推理/语音转写/批处理，单次可远超常规时限。**建线程**兜时限
     （调用方要给足时限，纯计算类不能只靠预算）。
   - `常驻有状态`：提供者常驻、调用会阻塞在同一提供者上（模型服务、浏览器会话）。
     **不在本模块执行**：`执行()` 返回统一失败 `形态不匹配`，说明里点名要走
     **已成熟的异步任务通道**（任务系统/任务进程池：已有提交/轮询/取消/超时/
     整组回收），绝不静默起线程、也绝不静默直调。
     为什么必须由本模块**拒绝**而不是放行：直调会把提供者上的调用占在网关工作线程上
     （工作线程被模型推理分分钟占满 → 网关对所有新连接回 429）；起线程则让**取消**
     形同虚设（Python 无法强杀线程，这类能力恰恰要求可取消、可整组回收）。
     主进程**无任务系统**时调用方（`唯一能力调用服务`）会启用受管的进程内兜底通道，
     本模块不掺和那条链路。

   判定顺序（`_执行形态`）：**能力级显式声明** → **提供者级声明** → **保守推断**。
   保守推断只认「本平台自身执行单元」这一条硬事实（`包id` 是不是本平台包），
   加上「端点形状」这一条可静态复算的判据；两者都不命中时**一律保守取 `阻塞IO`**，
   即**反方向错误才是安全的**：把纯计算误判成阻塞IO只多付一次线程开销（微秒级），
   把阻塞IO误判成纯计算则会让挂死能力永久占住网关工作线程（并发耗尽 → 429）。
   形态**只决定是否建线程**，不改任何错误码、不改证据字段、不改返回结构。
"""

