# ═══════════════════════════════════════════════════════════════════
# 异步任务通道接入点（执行形态 `常驻有状态` 的走向）
#
# 主进程的任务系统实例由唯一装配入口 `创建并绑定` 写入（启动脚本本来就把同一个实例
# 交给网关核心用于 `任务提交/查询/取消`，这里是**同一实例**的第二处引用，不新建实例）。
# 为什么需要它：常驻有状态能力的调用必须能取消、能整组回收、能超出单次请求时限，
# 这三件事只有任务通道做得到；把「任务通道在哪」收敛成一个函数，调用方不必知道
# 主进程的装配细节（也就不会各自去猜一个全局变量名 → 第二事实源）。
# ═══════════════════════════════════════════════════════════════════
_任务系统: Any = None
#: 本进程**是否曾装配过**任务系统（接入过又卸载即为真）。
#: 用途：把「装了却没接上本服务」的装配缺陷与「本进程本来就没有任务系统」
#: （测试/嵌入场景）区分开 —— 前者必须明确失败，后者才允许走受管兜底。
_任务系统曾装配标记 = 假


def 接入任务系统(任务系统实例: Any) -> None:
    """登记主进程的任务系统实例（唯一装配入口调用；None 表示卸载）。

    只由唯一装配入口 `创建并绑定` 调用，或由调用方在装配期显式调用 —— 目的是
    让「任务通道在哪」只有一个答案，而不是调用方各自去猜一个全局变量名。
    """
    global _任务系统, _任务系统曾装配标记
    with _全局服务锁:
        _任务系统 = 任务系统实例
        if 任务系统实例 is not None:
            _任务系统曾装配标记 = 真


def _任务系统曾装配() -> bool:
    """本进程是否曾装配过任务系统（接入过即真；与「当前是否接入」分开）。"""
    with _全局服务锁:
        return _任务系统曾装配标记


def 取任务系统() -> Any:
    """取主进程的任务系统实例；未接入返回 None（调用方据此自有判断，不猜）。"""
    with _全局服务锁:
        return _任务系统


_全局服务: "唯一能力调用服务 | None" = None
_全局服务锁 = threading.Lock()


def 设置全局唯一服务(服务: "唯一能力调用服务 | None") -> None:
    """加载器装配完成后设置全局唯一服务（供模块获取注入的调用器）。

    None 表示销毁：调用器卸载（状态回到 未装配），测试间不得残留能力。
    """
    global _全局服务
    from 公共契约.能力契约.调用器 import 注册能力调用器
    with _全局服务锁:
        _全局服务 = 服务
        注册能力调用器(服务)


def 销毁全局唯一服务() -> None:
    """销毁对称：卸载全局唯一服务并回到 未装配（进程重启/测试隔离）。"""
    设置全局唯一服务(None)


def 获取唯一调用服务() -> "唯一能力调用服务":
    """模块实现内获取运行核心注入的唯一能力调用服务。

    经公共契约调用器层获取；未装配/装配中/装配失败时抛
    能力调用器状态异常（携带 状态/错误码/错误说明），禁止绕过。
    """
    # 宿主类唯一实现在主文件；本文件禁止反向模块级导入（会成环）⇒ 函数内延迟导入
    from 运行核心.能力调用.唯一能力调用 import 唯一能力调用服务
    from 公共契约.能力契约.调用器 import 获取能力调用器
    调用器 = 获取能力调用器()
    if not isinstance(调用器, 唯一能力调用服务):
        raise RuntimeError(f"已注册调用器类型异常: {type(调用器).__name__}")
    return 调用器


def 创建并绑定(注册表: 能力注册表 | None = None, *,
               任务系统实例: Any = None) -> "唯一能力调用服务":
    """**唯一装配入口**：创建唯一能力调用服务并设置为全局注入目标。

    装配状态机（唯一注册表调用器注入点，S0生产事实冻结第二节）：
    - 未装配/装配失败 → 装配中 → 创建并绑定成功 → 已装配；
    - 已装配 → 重复装配幂等（同摘要可重放，装配次数递增）；
    - 装配中 → 拒绝并发重复装配（抛 能力调用器状态异常 E装配中）；
    - 任一异常 → 回滚为 装配失败 并记录错误码/错误说明，不留半状态。

    **两条装配腿已收敛成这一条**（P2-12）：`注册表` 省略时本入口自己**发现 → 安装
    支持库 → 建注册表**（惰性首次获取时的原路径），传了就用调用方的注册表
    （生产 `装配系统` 与各测试的用法）。旧实现是两条并行装配腿
    （`创建并绑定` 有 CAS，`_惰性装配` 无 CAS、且在建表/发现/安装之后才进锁外**没有
    任何**装配中保护）—— 两个线程同时首次获取调用器时可能各跑一遍全库扫描 + 安装
    （秒级 I/O 双执行），第二次重复注册还会报错。现在惰性钩子直接转调本入口，
    发现的临界区由「装配中 CAS + 重查」保护，**同一时刻只有一条腿在装配**。

    `任务系统实例`：主进程的任务系统（执行形态 `常驻有状态` 能力的执行通道）。
    由启动脚本以关键字传入，**不为此另开装配入口、不猜全局变量名**。
    """
    from 公共契约.能力契约.调用器 import (
        查询装配状态, 标记装配中, 标记装配失败, 能力调用器状态异常,
    )
    当前状态 = 查询装配状态()["状态"]
    if 当前状态 == "装配中":
        raise 能力调用器状态异常(
            状态="装配中", 错误码="E装配中",
            错误说明="已有装配正在进行中，禁止并发重复装配",
        )
    if not 标记装配中():
        # CAS 未抢到：另一线程在「查询装配状态」与本行之间的 TOCTOU 窗口内已抢到
        # 「装配中」。旧实现丢弃返回值 ⇒ 两线程各跑一遍全库发现+安装（秒级 I/O
        # 双执行）。此处必须在 try 之外抛异常退出：
        #   - 不进 except 分支 ⇒ 不会把抢到方持有的「装配中」改写成 装配失败；
        #   - 不执行装配 ⇒ 禁止并发重复装配在 TOCTOU 窗口内同样成立。
        raise 能力调用器状态异常(
            状态="装配中", 错误码="E装配中",
            错误说明="已有装配正在进行中，禁止并发重复装配",
        )
    try:
        return _装配主体(注册表, 任务系统实例)
    except Exception as 错误:
        失败说明 = f"{type(错误).__name__}: {错误}"
        标记装配失败("E装配失败", 失败说明)
        raise


def _装配主体(注册表: 能力注册表 | None = None, 任务系统实例: Any = None,
              *, 系统根: Any = None) -> "唯一能力调用服务":
    """**装配主体**（唯一一份）：发现 → 安装 → 建服务 → 接任务通道 → 注入。

    调用前提：`装配中` 状态**已由调用方持有**（`创建并绑定` 自己抢的 CAS，或
    惰性钩子路径上 `公共契约.能力契约.调用器.获取能力调用器` 抢的 CAS）。
    因此本函数**不再抢 CAS、也不回滚状态**——状态收口留给持锁者：抢 CAS 的人负责
    装配失败时把状态写回 `装配失败`，装配成功由 `设置全局唯一服务` 写成 `已装配`。

    这正是 P2-12 要的形态：**一份装配实现 + 同一时刻一个装配所有者**。旧实现是两份
    装配实现（`创建并绑定` 与 `_惰性装配`），后者连「装配中」保护都没有，两个线程
    同时首次获取就会各跑一遍全库扫描 + 安装（秒级 I/O 双执行）。
    """
    注册表 = 注册表 if 注册表 is not None else _发现并安装(系统根)
    # 宿主类唯一实现在主文件；本文件禁止反向模块级导入（会成环）⇒ 函数内延迟导入
    from 运行核心.能力调用.唯一能力调用 import 唯一能力调用服务
    服务 = 唯一能力调用服务(注册表)
    # 顺序：先把执行通道接上，再对外可见（设置全局唯一服务会把状态标成已装配）；
    # 反过来会出现「已装配但任务通道还没接」的窗口，常驻有状态能力在这个窗口里
    # 会被判「任务不可提交」（装配缺陷口径）—— 那是我们自己制造的假缺陷。
    接入任务系统(任务系统实例)
    设置全局唯一服务(服务)
    return 服务


def _发现并安装(系统根: Any = None) -> 能力注册表:
    """惰性首装配的发现 + 安装（**只在装配中状态的临界区内被调用**）。

    为什么可以放在 CAS 之后放心做秒级 I/O：抢不到 CAS 的线程会立刻抛 `E装配中`
    退出，不会并发跑第二遍；装配成功后全局调用器已就绪，后续获取在读锁里直接拿
    就绪对象（`获取能力调用器` 的「就绪优先」），不会再进这里。

    `系统根` 不传时按本文件位置上溯定位（`<根>/运行核心/能力调用/…`）。
    发现不出任何支持库时抛 `RuntimeError`（由持锁者回滚为 `装配失败`）——
    旧实现是同一句口径，语义一字不变。
    """
    from pathlib import Path
    from 公共契约.能力契约.契约 import 能力注册表
    from 运行核心.加载器.包发现.发现器 import 发现全部
    from 运行核心.加载器.包安装.支持库安装 import 安装全部支持库

    系统根 = Path(系统根) if 系统根 is not None else Path(__file__).resolve()
    if 系统根.is_file():
        系统根 = 系统根.parent
    for _祖先 in 系统根.parents:
        if (_祖先 / "支持库").is_dir() and (_祖先 / "模块库").is_dir():
            系统根 = _祖先
            break
    注册表 = 能力注册表()
    发现 = 发现全部(系统根 / "支持库", 系统根 / "模块库")
    支持库声明 = [声明 for 声明 in 发现.声明列表
                 if 声明.类型 == "支持库" and not getattr(声明, "已废弃", 假)]
    if not 支持库声明:
        raise RuntimeError("首次装配失败：未发现任何支持库")
    安装全部支持库(系统根 / "支持库", 注册表)
    return 注册表


def _惰性装配() -> None:
    """惰性装配钩子（首次获取调用器时由 `公共契约.能力契约.调用器` 触发）。

    **进入本函数时「装配中」状态已由 `获取能力调用器` 的 CAS 持有** —— 所以这里
    只调唯一装配主体，**不再自己抢 CAS**（再抢必然失败，还会把正在进行的装配误判成
    并发冲突、进而把状态改写成「装配失败」）。旧实现在这里又走一遍「查状态 → 自己
    发现/安装 → 锁内绑定」，与 `创建并绑定` 构成**两条装配腿**（P2-12）；现在两条腿
    已合并成一份装配主体（`_装配主体`），装配失败的回滚统一由持 CAS 的调用方负责。
    """
    _装配主体(None, None)


# 注册惰性装配钩子（模块经 公共契约.能力契约.调用器 首次获取时触发）
def _注册惰性钩子() -> None:
    from 公共契约.能力契约.调用器 import 设置惰性装配函数
    设置惰性装配函数(_惰性装配)




_注册惰性钩子()
