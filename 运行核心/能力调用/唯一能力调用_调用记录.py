from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from 公共契约.基础类型.逻辑类型 import 真
from 运行核心.能力调用.控制调用.证据链 import 调用证据


@dataclass
class 调用记录:
    """一次唯一能力调用的完整记录。"""

    能力id: str
    请求id: str
    调用方: str = ""
    项目id: str = ""
    成功: bool = 真
    错误码: str = ""
    错误说明: str = ""
    耗时秒: float = 0.0
    模块版本: str = ""
    支持库包id: str = ""
    提供者版本: str = ""
    制品摘要: str = ""
    资源释放结论: str = ""
    证据: 调用证据 | None = None

    def 转字典(self) -> dict[str, Any]:
        return {
            "能力id": self.能力id, "请求id": self.请求id, "调用方": self.调用方,
            "项目id": self.项目id, "成功": self.成功, "错误码": self.错误码,
            "错误说明": self.错误说明, "耗时秒": self.耗时秒,
            "模块版本": self.模块版本, "支持库包id": self.支持库包id,
            "提供者版本": self.提供者版本, "制品摘要": self.制品摘要,
            "资源释放结论": self.资源释放结论,
            "证据": self.证据.转字典() if self.证据 is not None else None,
        }
