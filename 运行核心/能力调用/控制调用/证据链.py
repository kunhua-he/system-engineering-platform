"""调用证据链：每次调用记录全链路证据，失败时回答九问。

证据字段：项目/功能模块/基础模块/支持库/提供者/能力id/版本/错误码/
请求id/任务id。
失败时必须回答：哪一层失败/哪个能力失败/使用哪个版本/使用哪个提供者/
上层来自哪个模块/是否可以重试/推荐哪个验证场景/是否可以回滚。
"""

from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假

验证场景推荐表 = {
    "参数不合法": "契约测试",
    "能力不存在": "组件合规-契约",
    "权限不足": "组件合规-权限",
    "外部未安装": "反向破坏-提供者崩溃",
    "外部不可访问": "反向破坏-提供者崩溃",
    "超时": "反向破坏-任务超时",
    "内部错误": "反向破坏-错误码删除",
    "契约不兼容": "漂移检测-契约升级",
    "资源泄漏": "反向破坏-资源泄漏",
    "崩溃": "反向破坏-提供者崩溃",
}


@dataclass
class 调用证据:
    """一条调用证据链。

    完整字段（唯一权威事实 第五节）：
    请求id/任务id/项目/功能模块/基础模块/支持库/支持库包id/提供者/
    提供者版本/能力id/版本(支持库版本)/模块版本/制品摘要/错误码/时间/
    成功/资源释放结论。
    """

    请求id: str = ""
    任务id: str = ""
    项目: str = ""
    功能模块: str = ""
    基础模块: str = ""
    支持库: str = ""
    支持库包id: str = ""
    提供者: str = ""
    提供者版本: str = ""
    能力id: str = ""
    版本: str = ""
    模块版本: str = ""
    制品摘要: str = ""
    错误码: str = ""
    时间: str = ""
    成功: bool = 真
    资源释放结论: str = ""

    def 转字典(self) -> dict[str, Any]:
        return {
            "请求id": self.请求id, "任务id": self.任务id, "项目": self.项目,
            "功能模块": self.功能模块, "基础模块": self.基础模块, "支持库": self.支持库,
            "支持库包id": self.支持库包id, "提供者": self.提供者,
            "提供者版本": self.提供者版本, "能力id": self.能力id,
            "版本": self.版本, "模块版本": self.模块版本, "制品摘要": self.制品摘要,
            "错误码": self.错误码, "时间": self.时间, "成功": self.成功,
            "资源释放结论": self.资源释放结论,
        }


class 证据链:
    """调用证据链：记录 + 九问回答。

    记录表有界保留**最近 `记录上限` 条**证据，口径与 唯一能力调用服务.
    `_调用历史`（`_历史上限 = 500`）同源：两套记录的回溯深度语义一致，
    只保证最近窗口，窗口外证据自然淘汰，内存不随请求数单调增长。
    """

    #: 证据回溯深度，与 `唯一能力调用服务._历史上限`（500）同口径。
    默认记录上限 = 500

    def __init__(self, *, 记录上限: int | None = None) -> None:
        self.记录上限 = self.默认记录上限 if 记录上限 is None else int(记录上限)
        if self.记录上限 < 1:
            raise ValueError("证据链记录上限必须为正整数")
        self.记录表: dict[str, 调用证据] = {}
        self.淘汰条数 = 0  # 累计淘汰计数（诊断用，不参与回溯）

    def 开始调用(self, *, 项目: str = "", 功能模块: str = "", 基础模块: str = "",
                 支持库: str = "", 支持库包id: str = "", 提供者: str = "",
                 提供者版本: str = "", 能力id: str = "", 版本: str = "",
                 模块版本: str = "", 制品摘要: str = "", 任务id: str = "") -> 调用证据:
        证据 = 调用证据(
            请求id=uuid.uuid4().hex[:16], 任务id=任务id, 项目=项目,
            功能模块=功能模块, 基础模块=基础模块, 支持库=支持库,
            支持库包id=支持库包id or 支持库, 提供者=提供者,
            提供者版本=提供者版本, 能力id=能力id, 版本=版本,
            模块版本=模块版本, 制品摘要=制品摘要,
            时间=time.strftime("%Y-%m-%d %H:%M:%S"),
        )
        self.记录表[证据.请求id] = 证据
        self._淘汰超限证据()
        return 证据

    def _淘汰超限证据(self) -> None:
        """超出上限即淘汰最旧证据（dict 保持插入序，先进先出）。

        只影响历史回溯深度，不影响本次调用：调用方始终持有 `证据` 对象引用，
        `记录结果`/`记录资源释放结论` 照常写在同一对象上；`查询(请求id)` 与
        `唯一能力调用服务.查询调用历史` 一样只保证最近 `记录上限` 次调用。
        """
        超限 = len(self.记录表) - self.记录上限
        if 超限 <= 0:
            return
        for 旧请求id in list(self.记录表)[:超限]:
            del self.记录表[旧请求id]
        self.淘汰条数 += 超限

    def 记录结果(self, 证据: 调用证据, *, 成功: bool, 错误码: str = "") -> None:
        证据.成功 = 成功
        证据.错误码 = 错误码

    def 记录资源释放结论(self, 证据: 调用证据, 结论: str) -> None:
        """记录本次调用的资源释放结论（版本锁/提供者资源回收）。"""
        证据.资源释放结论 = 结论

    def 查询(self, 请求id: str) -> 调用证据 | None:
        """按请求id查证据；只保证最近 `记录上限` 条（窗口外已淘汰）。"""
        return 记录表.get(请求id) if (记录表 := self.记录表) else None

    def 回答九问(self, 证据: 调用证据) -> dict[str, str]:
        """失败时回答九问。"""
        提供者 = 证据.提供者 or "内置实现"
        if 证据.提供者版本:
            提供者 = f"{提供者}@{证据.提供者版本}"
        return {
            "哪一层失败": self._哪一层失败(证据),
            "哪个能力失败": 证据.能力id,
            "使用哪个版本": 证据.版本 or "未锁定",
            "使用哪个提供者": 提供者,
            "上层来自哪个模块": 证据.功能模块 or 证据.基础模块 or "直接调用",
            "是否可以重试": "是" if 证据.错误码 in ("超时", "外部不可访问", "崩溃") else "否",
            "推荐哪个验证场景": 验证场景推荐表.get(证据.错误码, "组件合规-失败语义"),
            "是否可以回滚": "是" if 证据.版本 and 证据.错误码 not in ("参数不合法", "权限不足") else "否",
        }

    def _哪一层失败(self, 证据: 调用证据) -> str:
        """按错误码推断失败层。"""
        if 证据.错误码 in ("参数不合法", "能力不存在", "契约不兼容"):
            return "契约/参数层"
        if 证据.错误码 in ("权限不足",):
            return "权限层"
        if 证据.错误码 in ("超时", "外部不可访问", "崩溃"):
            return "提供者层"
        if 证据.错误码 in ("资源泄漏",):
            return "资源层"
        return "调用层"


class 版本锁定:
    """请求/长任务版本锁定：结束后才减少旧版本引用。"""

    def __init__(self) -> None:
        self.锁定表: dict[str, dict[str, str]] = {}  # 请求id → 版本锁定
        self.引用计数: dict[str, int] = {}  # "包id@版本" → 引用数

    def 锁定(self, *, 请求id: str, 包id: str, 版本: str,
             契约版本: str = "", 提供者版本: str = "") -> bool:
        """请求开始时锁定版本；返回是否成功。"""
        引用键 = f"{包id}@{版本}"
        self.锁定表[请求id] = {
            "包id": 包id, "版本": 版本, "契约版本": 契约版本, "提供者版本": 提供者版本,
        }
        self.引用计数[引用键] = self.引用计数.get(引用键, 0) + 1
        return 真

    def 释放(self, *, 请求id: str) -> bool:
        """请求/任务完成或资源释放后减少引用。"""
        锁定 = self.锁定表.pop(请求id, None)
        if 锁定 is None:
            return 假  # 重复释放幂等
        引用键 = f"{锁定['包id']}@{锁定['版本']}"
        self.引用计数[引用键] = max(0, self.引用计数.get(引用键, 0) - 1)
        return 真

    def 引用数(self, *, 包id: str, 版本: str) -> int:
        return self.引用计数.get(f"{包id}@{版本}", 0)

    def 可删除(self, *, 包id: str, 版本: str) -> bool:
        """引用数为零才允许删除。"""
        return self.引用数(包id=包id, 版本=版本) == 0
