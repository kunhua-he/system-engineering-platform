"""时钟校准：合盖睡眠 / 墙钟跳变 的唤醒检测（唯一实现，§9-B6）。

**为什么必须有这个文件**

两类时钟在笔记本合盖上表现相反（审计 §9-B6 实测，L3，个人 Mac 高频场景）：

- **墙钟**（``time.time()``）跟随真实时间：合盖 5 小时后唤醒，墙钟直接跳 5 小时。
  一切用墙钟做「经过时间/超时」判据的地方在唤醒瞬间**集体过期**——租约被判死、
  句柄被判超时、限流窗口被清空，而持有者自己一秒都没跑过。
- **单调时钟**（``time.monotonic()``）在 macOS 睡眠期间**不走**：`time.get_clock_info`
  实测本机实现为 ``mach_absolute_time()``（``adjustable=False``，睡眠期间停机），
  于是「3 秒超时」在睡眠中不触发、唤醒后**误判为未超时**。

两者**单独看都不可信**，但差值可判：`(墙钟增量 − 单调增量)` 在正常运行下恒为 0
（两者同速率），一旦发生睡眠/时钟跳变就突变出「睡眠秒数」。这就是唤醒检测的判据。

**本模块提供什么（三层，逐层可测）**

1. `时钟读数` / `时钟偏差`：一次采样两个时钟，偏差 = 墙钟 − 单调。
2. `判刚唤醒()` —— **纯函数**，无状态无副作用：喂入「上次读数 + 当前读数」，
   返回 `唤醒判定`（是否刚唤醒、睡眠秒数、睡眠窗口的墙钟起止）。
   纯函数才有可测性：喂入差值为 5 小时的两个时间即可伪造「刚唤醒」，不需要真合盖。
3. `采样并检测()` / `唤醒联动器` —— **挂在已有请求/巡检路径上的检测入口**。

**为什么不引入后台轮询线程**：华哥明确反感冗余等待/轮询。唤醒检测本身是纯计算，
只需在调用方**本来就有的**请求路径（句柄创建、提供者调用、账本巡检）上顺带问一句；
没有事件时开销恒定为「两次取时钟 + 一次比较」，不新建线程、不新建定时器。

**为什么每个组件各持一个 `唤醒联动器` 而不是共享一个「已消费」事件**：
一次唤醒需要多个组件各自动作（资源协调做租约重判、提供者生命周期做 reaper 与
健康复查）。若判定结果被「消费掉」，先问的那个组件会把事件吃掉，后面的组件永远
看不到。故检测结果按**序号**发布，各组件各自记住「处理到第几号」，
同一事件每个组件恰好处理一次（幂等，重复问不会重复动作）。

**平台事实（诚实标注）**：睡眠期间单调时钟停不停是**平台行为**，本模块只在 macOS
（Darwin）上实测过 `time.get_clock_info("monotonic")` 的实现为 `mach_absolute_time()`
（文档语义：睡眠期间递增值不变）。判据本身不依赖平台：差值突变就是突变，
Windows/Linux 上同样成立（Linux `CLOCK_MONOTONIC` 亦不含 ``CLOCK_BOOTTIME`` 的睡眠时间）。
"""

from __future__ import annotations

import threading
import time
from dataclasses import dataclass
from typing import Any

# 唤醒判定阈值：差值突变超过这个秒数才算「刚唤醒」。
# 为什么是 30 秒：正常运行下墙钟与单调时钟的差值漂移量级是**毫秒**（NTP 微调、
# 两次取时钟之间的调度延迟），30 秒留了 4 个数量级余量，不会把正常抖动误判成唤醒；
# 而个人 Mac 合盖一次最短也是分钟级，30 秒阈值不会漏判。
默认唤醒阈值秒 = 30.0


@dataclass(frozen=True)
class 时钟读数:
    """一次双时钟采样（墙钟秒 + 单调秒）。"""

    墙钟: float
    单调: float

    @property
    def 偏差(self) -> float:
        """本进程视角的「墙钟 − 单调」偏差；睡眠会让它整体增大。"""
        return self.墙钟 - self.单调


@dataclass(frozen=True)
class 唤醒判定:
    """一次唤醒判定的全部事实（纯函数输出，无状态）。"""

    刚唤醒: bool
    睡眠秒: float = 0.0
    墙钟增量: float = 0.0
    单调增量: float = 0.0
    窗口起点墙钟: float = 0.0
    窗口终点墙钟: float = 0.0
    序号: int = 0

    def 转字典(self) -> dict[str, Any]:
        return {
            "刚唤醒": self.刚唤醒, "睡眠秒": round(self.睡眠秒, 3),
            "墙钟增量": round(self.墙钟增量, 3), "单调增量": round(self.单调增量, 3),
            "窗口起点墙钟": self.窗口起点墙钟, "窗口终点墙钟": self.窗口终点墙钟,
            "序号": self.序号,
        }


def 当前读数() -> 时钟读数:
    """采样当前双时钟（唯一采样点，禁止各处各写一对 ``time`` 调用）。"""
    return 时钟读数(墙钟=time.time(), 单调=time.monotonic())


def 时钟偏差(读数: 时钟读数 | None = None) -> float:
    """当前「墙钟 − 单调」偏差（睡眠累计量就藏在它的增量里）。"""
    return (读数 or 当前读数()).偏差


def 墙钟到单调(墙钟秒: float, *, 偏差: float | None = None) -> float:
    """把落盘的墙钟秒换算成本进程单调时基（读写持久化字段的唯一换算入口）。

    为什么需要换算：墙钟是**落盘口径**（人能读、跨重启可比），单调时钟是
    **经过时间口径**（不受睡眠与改钟影响）。两者相差的那个常量就是偏差，
    换算一次即可让「内存里的剩余时间」按单调走。
    """
    return float(墙钟秒) - (时钟偏差() if 偏差 is None else float(偏差))


def 单调到墙钟(单调秒: float, *, 偏差: float | None = None) -> float:
    """把单调时基的秒换算回落盘墙钟秒（与 `墙钟到单调` 互逆）。"""
    return float(单调秒) + (时钟偏差() if 偏差 is None else float(偏差))


def 判刚唤醒(
    上次: 时钟读数,
    当前: 时钟读数,
    *,
    阈值秒: float = 默认唤醒阈值秒,
    序号: int = 0,
) -> 唤醒判定:
    """**纯函数**：由两次双时钟采样判定是否刚发生睡眠/墙钟跳变。

    判据：`偏差增量 = (墙钟增量 − 单调增量)`。正常运行恒为 0（两钟同速率），
    睡眠期间墙钟走、单调停，于是偏差增量 ≈ 睡眠秒数。超过 `阈值秒` 即判刚唤醒。

    `阈值秒 <= 0` 时**判据被破坏**（任何采样都算唤醒）—— 反向验证用的就是这一档：
    故意传 0 会让正常路径也报唤醒，测试必须因此变红（这是「弄坏检测」的合法手段，
    不是配置项）。

    返回 `唤醒判定`：`睡眠秒` = 偏差增量（负值不采用，墙钟被回拨时按 0 处理，
    回拨只影响墙钟绝对量、不构成「睡眠」），`窗口起点/终点墙钟` = 睡眠窗口的
    墙钟区间 `(当前墙钟 − 睡眠秒, 当前墙钟]`——「落在这个窗口内的截止时间」
    就是「睡眠期间才越过的」，唤醒重判一律以它为准。
    """
    墙钟增量 = 当前.墙钟 - 上次.墙钟
    单调增量 = 当前.单调 - 上次.单调
    偏差增量 = 墙钟增量 - 单调增量
    刚唤醒 = 偏差增量 > float(阈值秒)
    睡眠秒 = 偏差增量 if 刚唤醒 else 0.0
    return 唤醒判定(
        刚唤醒=刚唤醒,
        睡眠秒=睡眠秒,
        墙钟增量=墙钟增量,
        单调增量=单调增量,
        窗口起点墙钟=(当前.墙钟 - 睡眠秒) if 刚唤醒 else 0.0,
        窗口终点墙钟=当前.墙钟 if 刚唤醒 else 0.0,
        序号=int(序号),
    )


def 落在睡眠窗口(墙钟秒: float, 判定: 唤醒判定) -> bool:
    """该墙钟时刻是否落在「睡眠窗口内」（含终点、不含起点）。

    语义：`睡眠窗口 = (墙钟现在 − 睡眠秒, 墙钟现在]`。落在其中的截止时间意味着
    **睡下那一刻它还是未来**——持有者是被冻住而没能续租，不是真的闲置超时。
    """
    if not 判定.刚唤醒:
        return False
    try:
        值 = float(墙钟秒)
    except (TypeError, ValueError):
        return False
    return 判定.窗口起点墙钟 < 值 <= 判定.窗口终点墙钟


# ---------------- 进程内唯一检测入口（检测结果按序号发布，各组件各取一次） ----------------

_锁 = threading.Lock()
_上次读数: 时钟读数 | None = None
_最新判定: 唤醒判定 | None = None
_序号 = 0


def 采样并检测(*, 阈值秒: float = 默认唤醒阈值秒) -> 唤醒判定 | None:
    """采样一次并检测唤醒；**检出即发布**（返回该判定），未检出返回 None。

    每次调用都推进基线（基线只在前一次采样之后前移），故正常路径下一次「未检出」
    的开销 = 两次取时钟 + 一次比较；检出后再次调用立即回到「未检出」，
    不会因为「一直是刚唤醒」而反复触发重校准。
    """
    global _上次读数, _最新判定, _序号
    当前 = 当前读数()
    with _锁:
        上次 = _上次读数
        _上次读数 = 当前
        if 上次 is None:
            return None
        序号 = _序号 + 1
        判定 = 判刚唤醒(上次, 当前, 阈值秒=阈值秒, 序号=序号)
        if not 判定.刚唤醒:
            return None
        _序号 = 序号
        _最新判定 = 判定
        return 判定


def 最新唤醒() -> 唤醒判定 | None:
    """最近一次检出的唤醒判定（供诊断/巡检读取，不消费）。"""
    return _最新判定


def 取未处理唤醒(已处理序号: int, *, 阈值秒: float = 默认唤醒阈值秒) -> 唤醒判定 | None:
    """采样一次；返回**调用方尚未处理过的**最新唤醒判定，否则 None（零动作入口）。

    为什么不能只用 `采样并检测` 的返回值：唤醒是**进程级事件**，一次唤醒要多个组件
    各自动作（资源协调做租约重判、提供者生命周期做 reaper 与健康复查）。如果组件
    只看「本次调用是否新检出」，那先被调用的那个组件会把事件吃掉 —— 它推进了基线，
    后调用的组件采到的是「没有新跳变」，于是**永远看不到这次唤醒**，
    重校准就漏了半截。故这里做两步：
    1. 先采样（同时推进基线，正常路径的代价就在这里）；
    2. 若本次没检出，取**已发布的最新判定**兜底，与调用方自己的序号比一次。
    这样每个组件对同一次唤醒恰好处理一次，且谁先谁后都不影响。
    """
    判定 = 采样并检测(阈值秒=阈值秒)
    if 判定 is None:
        判定 = _最新判定
    if 判定 is None or 判定.序号 == int(已处理序号 or 0):
        return None
    return 判定


def 重置检测基线(读数: 时钟读数 | None = None) -> None:
    """重置基线（仅供测试与进程初始化使用）；不改已发布的序号与最新判定。"""
    global _上次读数
    with _锁:
        _上次读数 = 读数


class 唤醒联动器:
    """把「检出唤醒」翻译成「每个组件恰好处理一次」的联动器（挂已有路径用）。

    用法：在调用方**本来就有的**请求/巡检路径上顺带调 `检查()`；
    未检出唤醒时零动作（返回 None、不回调），检出时调一次注入的处理函数。

    为什么按序号去重而不是「取走即清空」：一次唤醒要资源协调做租约重判、
    提供者生命周期做 reaper 与健康复查，两个组件都要看到**同一次**唤醒；
    「取走即清空」会按提问顺序把事件吃掉。按序号去重后各组件互不干扰，
    且同一组件重复问也只会处理一次。
    """

    def __init__(self, 处理, *, 阈值秒: float = 默认唤醒阈值秒) -> None:
        self._处理 = 处理
        self._阈值秒 = float(阈值秒)
        self._已处理序号 = 0
        self.处理次数 = 0
        self.最近处理: dict[str, Any] | None = None

    def 检查(self, *额外参数) -> Any | None:
        """采样并检测；若是本联动器还没处理过的唤醒则处理一次，否则返回 None。"""
        判定 = 采样并检测(阈值秒=self._阈值秒)
        if 判定 is None or 判定.序号 == self._已处理序号:
            return None
        self._已处理序号 = 判定.序号
        self.处理次数 += 1
        结果 = self._处理(判定, *额外参数)
        self.最近处理 = {"判定": 判定.转字典(), "结果": 结果}
        return 结果


