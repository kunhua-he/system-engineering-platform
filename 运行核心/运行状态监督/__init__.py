"""运行核心.运行状态监督 包级中文入口（正式包包级中文入口）。

运行核心的只读/判定能力面：把 `运行核心/权威状态.py` 的结构版本/结构完整性判据与
`运行核心/依赖防火墙.py` 的依赖方向判据，切成可经网关调用的原子能力——
查询状态结构版本 / 校验状态完整性 / 审计依赖。三条能力**都不写盘**：
只开 sqlite 只读连接（不建库、不迁移结构、不注册进程身份），依赖审计只解析源码、
不改被审计文件。判定逻辑唯一实现在上述两个模块，本包只做边界校验与结果归一。

本入口只做两件事：把同包实现里的公开函数重新导出，以及向加载器暴露
`注册能力(注册表)`。能力注册的参数名与顺序**逐条对应** `能力定义.json`
（`公共契约.能力契约.契约.能力实现.声明一致` 会逐项比对，写错即报不一致）；
`包声明.json` 的能力清单与 `能力契约/参数契约.json` 由 `能力定义.json` 派生，
禁止手改（生成物由 `开发工具.契约编译.能力定义编译器.编译能力定义` 产出）。

正式包边界：调用方只经唯一能力调用入口按能力 id 调用，不得 import 实现，
也不得深入 `实现/` 目录。
"""

from __future__ import annotations

from 运行核心.运行状态监督.实现.提供者 import 查询状态结构版本
from 运行核心.运行状态监督.实现.提供者 import 校验状态完整性
from 运行核心.运行状态监督.实现.提供者 import 审计依赖

__all__ = [
    "查询状态结构版本",
    "校验状态完整性",
    "审计依赖",
    "注册能力",
]

包id = "运行核心.运行状态监督"


def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本包三条只读/判定能力。"""
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="运行核心.运行状态监督.查询状态结构版本",
        包id=包id,
        实现函数=查询状态结构版本,
        参数=[
            {"名称": "存储目录", "类型": "文本型"},
        ],
        返回="结果",
        说明="查询权威状态库的结构版本与目标版本（只读，不迁移结构）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="运行核心.运行状态监督.校验状态完整性",
        包id=包id,
        实现函数=校验状态完整性,
        参数=[
            {"名称": "存储目录", "类型": "文本型"},
        ],
        返回="结果",
        说明="校验权威状态库的表/列结构完整性与磁盘完整性（只读，不迁移结构）。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
    注册表.注册(能力实现(
        能力id="运行核心.运行状态监督.审计依赖",
        包id=包id,
        实现函数=审计依赖,
        参数=[
            {"名称": "目标目录", "类型": "文本型"},
        ],
        返回="结果",
        说明="AST 依赖方向审计（只读）：返回违规清单与审计文件数，不改被审计文件。",
        版本="1.0.0",
        提供者id=包id,
        提供者版本="1.0.0",
    ))
