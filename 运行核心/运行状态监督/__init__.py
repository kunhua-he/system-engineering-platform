包id = "运行核心.运行状态监督"



def _校验参数名序(参数契约表: dict[str, list[dict]],
                  注册参数名序: dict[str, list[str]]) -> None:
    """装配期闸门：注册参数名序必须逐字等于契约名序，否则本包装配失败。

    为什么要有它：注册处一旦漏一个参数（或顺序写反），网关的必填校验就与契约分叉
    ——那正是本包 2026-09-18 被修掉的缺陷形态。宁可装配期就 raise，也不静默漏参。
    """
    for 能力id, 契约参数 in 参数契约表.items():
        注册名序 = 注册参数名序.get(能力id)
        if 注册名序 is None:
            raise ValueError(f"能力 {能力id} 有契约但注册处未声明参数名序")
        契约名序 = [参数.get("名称") for 参数 in 契约参数]
        if 契约名序 != list(注册名序):
            raise ValueError(
                f"能力 {能力id} 注册参数名序 {list(注册名序)} 与契约参数名序 {契约名序} "
                "不一致：参数事实源只有 能力契约/参数契约.json 一处（哲学 12.1），"
                "入口不得另立一份")

def 注册能力(注册表) -> None:
    """由加载器调用，向能力注册表注册本包三条只读/判定能力。"""
# ===== 参数声明透传（契约整条镜像；本块由「丢参」缺陷修复注入，勿删）=====
    # 参数契约镜像（**函数内字面量**；本块由「丢参」缺陷修复注入，勿删）
    #
    # 缺陷溯源（2026-09-18）：本入口原先手工重建注册参数声明（只写 名称/类型），把
    # `必填` 丢掉；而网关唯一校验点 `运行核心/统一网关/类型规格.py` 的判据是
    # `项.get("必填") is 真` → `None is 真` = 假 → 必填校验静默失效：少传参数不再被
    # 网关拦下，直接落进实现体抛 TypeError，用户拿到 HTTP 500 而不是干净的 400
    # 「缺少必填参数 X」。修法：参数声明从 `能力契约/参数契约.json` **整条透传**
    # （`参数=_参数契约表[能力id]`），入口不再另立第二套事实源（哲学 12.1）。
    #
    # 为什么是**函数内字面量**而不是「运行时读 JSON」：
    #  ① `_参数契约表` 是字面量、键是常量，`开发工具/契约编译/漂移检测` 的 AST 读取器
    #     （`_静态字面量` 的 `ast.Subscript` 分支）能解析出**整条参数含 `必填`** ——
    #     改前那处「参数口径未解析」不因本次修复恶化，反而把读不到的 `必填` 读到了。
    #     放在函数内是因为该读取器只收 `注册能力` 函数体内的赋值（`_扫描注册语句`）。
    #  ② 「裸布尔」防回潮门禁是**全文件 AST 扫描**，字面量里的 `必填` 同样看得见。
    # 表内 True/False 是**契约 JSON 的原值镜像**（JSON 无 真/假 字面量；`公共契约/基础类型/
