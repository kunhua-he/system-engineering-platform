"""运行状态监督能力实现（只读/判定）：三条能力都不写盘。

分工（第 2 条 1 项 分层与归属固定，判据不复制）：
- 结构版本与结构完整性判据唯一实现在 `运行核心/权威状态.py`
  （`状态结构版本` / `校验规则表` / 逐项判定实现）；
- 依赖方向判据唯一实现在 `运行核心/依赖防火墙.py`（`审计依赖` / `系统根`）；
- 本模块：能力边界参数校验、相对路径按系统根解析、异常→稳定错误码归一，不重写判定分支。

三条能力的边界口径（调用权威见同包 `说明/使用说明.md`）：
- 库文件缺失不是「失败」而是「判定结论」：`查询状态结构版本` 报 `是否需要迁移=true`，
  `校验状态完整性` 报 `完整=false + 问题列表`，与「读取失败」（打不开/sqlite 报错）严格分开；
- `审计依赖` 的目标目录必须在 依赖防火墙.系统根 之内（层判定以该根为基准）；
  域外目录一律 `参数不合法` 明确拒绝，不交给被审计实现抛 ValueError。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

from 公共契约.基础类型.结果类型 import 结果
from 公共契约.运行时.运行缓存 import 解析运行缓存根
from 运行核心.权威状态 import 状态结构版本
from 运行核心.依赖防火墙 import 审计依赖 as 依赖防火墙审计依赖
from 运行核心.依赖防火墙 import 系统根 as 平台系统根
from 运行核心.运行状态监督.实现.只读状态库 import (
    库文件路径,
    安全版本元组,
    探查,
)

# 存储目录缺省值：经唯一解析器取运行态存储根（源码态 = `<系统根>/工程缓存/平台控制面`，
# 与旧的相对缺省值**同义**——旧写法经 `_解析目录` 拼 `依赖防火墙.系统根`，制品态会把
# 只读探查指向制品内的库，与真正写入方（统一能力服务 / 提供者注册表）**不是同一个库**，
# 表现为「写进去的登记，后续查不到」。解析器在源码态行为不变，只在制品态改道平台受管缓存。
默认存储目录 = str(解析运行缓存根(Path(__file__).resolve().parents[3]) / "平台控制面")
来源名称 = "运行状态监督"


def _解析目录(文本: str, 缺省: str) -> Path:
    """目录参数归一：留空取缺省；相对路径按 依赖防火墙.系统根 解析，并**规范化**。

    必须规范化（`resolve`）：`依赖防火墙.审计依赖` 按「文件相对 系统根 的路径段」定层名，
    传入未规范化的等价路径（如 `<根>/../系统工程平台`）会让相对路径以 `..` 开头 →
    全部文件被定成「其他」层，产出成百上千条**假违规**（实测 668 文件里 713 条误报）。
    规范化后路径与 `系统根` 同形，层判定才与直接审计系统根逐条一致。
    """
    取值 = str(文本 or "").strip() or 缺省
    路径 = Path(取值)
    return (路径 if 路径.is_absolute() else Path(平台系统根) / 路径).resolve()


def _需要迁移(库中结构版本: str, 目标版本: str) -> bool:
    """是否需要迁移：库缺失或版本不一致为真；非法版本同样按不一致处理（fail-closed）。"""
    if not 库中结构版本:
        return True
    库中元组, 目标元组 = 安全版本元组(库中结构版本), 安全版本元组(目标版本)
    if 库中元组 is None or 目标元组 is None:
        return 库中结构版本 != str(目标版本)
    return 库中元组 != 目标元组


def 查询状态结构版本(存储目录: str = ""):
    """查询权威状态库的结构版本与目标版本（只读，不迁移结构）。"""
    if not isinstance(存储目录, str):
        return 结果.失败("参数不合法", "存储目录必须是文本型", 来源=来源名称)
    目录 = _解析目录(存储目录, 默认存储目录)
    库文件 = 库文件路径(目录)
    目标版本 = 状态结构版本
    存在 = 库文件.is_file()
    库中结构版本 = ""
    if 存在:
        try:
            库中结构版本, _问题列表 = 探查(库文件, 目标版本)
        except (sqlite3.Error, OSError) as 错误:
            return 结果.失败("读取失败", f"只读探查状态库失败：{错误}", 来源=来源名称, 可重试=True)
    return 结果.成功结果({
        "目标结构版本": 目标版本,
        "库中结构版本": 库中结构版本,
        "是否需要迁移": _需要迁移(库中结构版本, 目标版本),
        "库文件存在": 存在,
        "库文件路径": str(库文件),
    })


def 校验状态完整性(存储目录: str = ""):
    """校验权威状态库的表/列结构完整性与磁盘完整性（只读，不迁移结构、不写库）。"""
    if not isinstance(存储目录, str):
        return 结果.失败("参数不合法", "存储目录必须是文本型", 来源=来源名称)
    if not 存储目录.strip():
        return 结果.失败("参数不合法", "存储目录不能为空", 来源=来源名称)
    目录 = _解析目录(存储目录, 存储目录)
    库文件 = 库文件路径(目录)
    目标版本 = 状态结构版本
    if not 库文件.is_file():
        缺失说明 = f"状态库不存在: {库文件}"
        return 结果.成功结果({
            "完整": False, "说明": 缺失说明, "问题列表": [缺失说明],
            "库中结构版本": "", "目标结构版本": 目标版本,
        })
    try:
        库中结构版本, 问题列表 = 探查(库文件, 目标版本)
    except (sqlite3.Error, OSError) as 错误:
        return 结果.失败("读取失败", f"只读校验状态库失败：{错误}", 来源=来源名称, 可重试=True)
    return 结果.成功结果({
        "完整": not 问题列表,
        "说明": 问题列表[0] if 问题列表 else "结构完整",
        "问题列表": 问题列表,
        "库中结构版本": 库中结构版本,
        "目标结构版本": 目标版本,
    })


def 审计依赖(目标目录: str = ""):
    """AST 依赖方向审计（只读）：返回违规清单与审计文件数；目标目录须在系统根内。"""
    if not isinstance(目标目录, str):
        return 结果.失败("参数不合法", "目标目录必须是文本型", 来源=来源名称)
    根 = Path(平台系统根)
    if not 根.is_dir():
        return 结果.失败("参数不合法", f"系统根不是目录，无法层判定：{根}", 来源=来源名称)
    目录 = _解析目录(目标目录, ".")
    if not 目录.is_dir():
        return 结果.失败("参数不合法", f"目标目录不存在或不是目录：{目录}", 来源=来源名称)
    if not 目录.is_relative_to(根):
        return 结果.失败(
            "参数不合法", f"目标目录必须在系统根内（层判定以 {根} 为基准）：{目录}", 来源=来源名称)
    try:
        审计结果 = 依赖防火墙审计依赖(目录)
    except ValueError as 错误:
        return 结果.失败("参数不合法", f"目标目录无法参与层判定：{错误}", 来源=来源名称)
    except OSError as 错误:
        return 结果.失败("读取失败", f"读取待审计源码失败：{错误}", 来源=来源名称, 可重试=True)
    违规表 = [违规.转字典() for 违规 in 审计结果.违规列表]
    return 结果.成功结果({
        "成功": bool(审计结果.成功),
        "违规表": 违规表,
        "违规数": len(违规表),
        "审计文件数": int(审计结果.审计文件数),
        "审计目录": str(目录),
    })
