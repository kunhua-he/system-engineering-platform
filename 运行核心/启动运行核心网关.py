def _环境数值(名称: str, 缺省值: float) -> float:
    """读取数值环境配置；非法值退回缺省并显式打印（启动脚本不因配置写错而崩溃）。"""
    文本 = str(os.environ.get(名称, "") or "").strip()
    if not 文本:
        return 缺省值
    try:
        return float(文本)
    except ValueError:
        print(f"配置无效，退回缺省: {名称}={文本!r} → {缺省值}")
        return 缺省值


