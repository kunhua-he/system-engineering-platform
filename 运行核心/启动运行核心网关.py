"""启动运行核心网关（含后端核心装配、能力执行）。端口 40007，统一执行入口为 /网关/调用。

**环境准入（fail-closed）**：本平台当前**只支持 macOS / arm64（Apple Silicon）**。
非该环境一律在此明确拒绝启动（中文错误 + 退出码 1），不做静默降级 ——
判定口径与错误文案的唯一来源是 `公共契约/运行时/平台适配.校验支持范围()`。
准入放在**任何装配之前**（先于后端核心/网关导入），确保换平台拿到的是本平台
的明确报错，而不是某个底层 ImportError。
"""
import atexit
import os
import sys
sys.path.insert(0, ".")

from 公共契约.运行时.平台适配 import 平台不支持错误, 校验支持范围

try:
    校验支持范围(用途="启动运行核心网关")
except 平台不支持错误 as 错误:
    print(f"启动被拒绝（环境准入不通过）：{错误}")
    sys.exit(1)

from 后端核心.后端核心 import 后端核心
from 运行核心.资源协调 import 资源账本维护循环
from 运行核心.权威状态 import 账本保留窗口秒
from 运行核心.任务调度.任务接入 import 构造任务系统
from 运行核心.统一网关.网关核心 import 网关核心
from 运行核心.统一网关.本地网关 import 本地网关服务器
from 公共契约.基础类型.逻辑类型 import 真, 假


def _环境数值(名称: str, 缺省值: float) -> float:
    """读取数值环境配置；非法值退回缺省并显式打印（启动脚本不因配置写错而崩溃）。"""
    文本 = str(os.environ.get(名称, "") or "").strip()
    if not 文本:
        return 缺省值
    try:
        return float(文本)
    except ValueError:
        print(f"配置无效，退回缺省: {名称}={文本!r} → {缺省值}")
        return 缺省值


后端 = 后端核心()
启动 = 后端.启动()
if not 启动.成功:
    print(f"后端核心装配失败: {启动.错误说明}")
    sys.exit(1)
print(f"后端核心装配成功: {启动.值}")

# 任务系统接入：每个正式能力都可作为后台任务提交（提交/查询/取消）。
# 长任务不再依赖单次同步请求；客户端断线与网关重启都不改任务账本
# （非终态任务重启后收敛为「崩溃」，续跑由能力自身缓存承担）。
任务系统实例 = 构造任务系统(后端)
atexit.register(任务系统实例.关闭全部)
print(f"任务系统接入成功: {len(任务系统实例.执行函数表)} 个能力可提交为任务")

网关 = 本地网关服务器(
    网关核心实例=网关核心(后端, 任务系统=任务系统实例), 端口=40007, 地址="127.0.0.1",
    # 正式固定端口不得以匿名模式启动；凭证只从受控环境变量加载。
    配置={
        "请求超时秒": 1800,
        "要求凭证": 真,
        "凭证环境变量": "系统库网关凭证",
        "禁止客户端身份": 真,
        # OCR/图像字节经 base64 后会膨胀；保持有界，避免默认 1MiB 拦截合法图片。
        "请求大小上限": 64 * 1024 * 1024,
        # 工作线程上限（默认 64，允许上限 256）：调用方（如 V3 限流中间件）对每个请求
        # 都要回调底座，并发批量验收会把 64 线程占满 → 网关回「限流/网关工作线程已达上限」
        # → 调用方 fail-closed 拒绝全部请求。2026-09-15 按机器承载能力调高。
        "并发上限": 256,
    },
)
成功, 说明 = 网关.启动()
if not 成功:
    print(f"运行核心网关启动失败: {说明}")
    sys.exit(1)

# 权威状态账本周期维护（落点清单_05 R2 接线）：句柄/租约/进程三表此前只增不删
# （现场 18 天 9130/9166/3633 行），而已有的 清理死亡进程资源/扫描过期租约
# 生产调用方为 0（只在发布门禁里被调用过）。首轮清扫由后台线程立即执行，
# 不阻塞已就绪的端口；此后按 间隔秒 周期推进「判死 → 终态 → 按保留窗口真删」。
# 心跳宽限默认 900s（库默认 15s 留给门禁/单进程场景）：真崩溃由判据A（pid 已消失）
# 立即回收，判据B 只兜「pid 还在但失联」，宽限 < 默认租约 1800s，避免把未刷心跳的
# 其它活宿主进程（现场实测 43 行 pid 仍存活 / 126 个有效句柄）误判为死亡。
# 退出顺序：本处 atexit 后注册者先执行 ⇒ 先停维护线程，再关权威状态连接。
账本维护 = 资源账本维护循环(
    后端.资源句柄服务.权威状态,
    间隔秒=_环境数值("系统底座_权威状态维护间隔秒", 300.0),
    心跳超时秒=_环境数值("系统底座_权威状态心跳超时秒", 900.0),
    保留窗口秒=_环境数值("系统底座_权威状态保留窗口秒", 账本保留窗口秒),
)
atexit.register(账本维护.停止)
账本维护.启动()

print(f"运行核心网关已启动: http://127.0.0.1:40007")
print(f"接口: POST /网关/调用  POST /网关/流式  GET /健康（调用需凭证）")
print(f"权威状态账本维护已接线: 每 {账本维护.间隔秒:.0f} 秒清扫一次，"
      f"判死心跳宽限 {账本维护.心跳超时秒:.0f} 秒，"
      f"终态行保留窗口 {账本维护.保留窗口秒:.0f} 秒")
import time
while True:
    time.sleep(3600)
