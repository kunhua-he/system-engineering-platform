def _停收新请求() -> tuple[bool, str]:
    """段 1：关 listen socket（内核直接拒绝新连接，不再产生新工作线程）。

    **不复用 `网关.优雅停止()`**：它的 `线程.join(timeout=max(1.0, 请求超时秒))`
    用的是 1800 秒（启动配置）那个量纲，而 launchd 默认 `ExitTimeOut` 只有 20 秒 ——
    直接调用等于把「停机」交给 30 分钟的无界等待，第 20 秒必被 SIGKILL 腰斩。
    本段只做「关监听 + 停 serve_forever」，排空交给**有界**的排空段；
    `网关.优雅停止()`（含凭证清除）留在收尾链里，那时监听已关、join 立即返回。
    """
    服务器 = 网关.服务器
    if 服务器 is None:
        return 真, "网关未在运行（无监听 socket 可关）"
    _停机起点["值"] = time.monotonic()
    try:
        服务器.shutdown()
    except Exception as 错误:  # noqa: BLE001 —— 停收失败必须如实上报，不得静默
        return 假, f"停止 serve_forever 失败 {type(错误).__name__}: {错误}"
    try:
        服务器.socket.close()
    except Exception as 错误:  # noqa: BLE001 —— 关不了监听 socket = 还在收新请求
        return 假, f"关闭监听 socket 失败 {type(错误).__name__}: {错误}"
    在途 = int(getattr(服务器, "活动工作线程数", 0) or 0)
    return 真, f"监听 socket 已关闭（新连接由内核拒绝），在途工作线程 {在途} 条"


def _有界排空(上限秒: float) -> tuple[bool, str]:
    """段 2：等在途工作线程自然归零，**有界**；到上限即如实返回未收敛。

    为什么必须有界：Python 无法强杀线程，无界等 = 停机卡死；上限从
    `停机编排.排空上限秒`（默认 20 秒）注入，与 launchd ExitTimeOut 同量纲。
    """
    服务器 = 网关.服务器
    if 服务器 is None:
        return 真, "网关未在运行（无可排空）"
    上限 = max(0.0, float(上限秒))
    起点 = time.monotonic()
    截止 = 起点 + 上限
    while int(getattr(服务器, "活动工作线程数", 0) or 0) > 0 and time.monotonic() < 截止:
        time.sleep(0.05)
    剩 = int(getattr(服务器, "活动工作线程数", 0) or 0)
    耗时 = time.monotonic() - 起点
    if 剩:
        return 假, f"排空 {耗时:.2f} 秒到上限 {上限:.1f} 秒，仍有在途 {剩} 条"
    return 真, f"在途已自然收尾（用时 {耗时:.2f} 秒，上限 {上限:.1f} 秒）"


def _在途快照() -> list[dict[str, Any]]:
    """在途未收尾**逐条**快照（网关只有工作线程计数粒度，此处如实标注该口径）。

    为什么只有计数粒度：`有界线程HTTP服务器` 不登记「哪个请求在飞」，
    只维护 `活动工作线程数`。本函数**不编造**请求路径/请求id，按真实粒度
    逐条展开并在说明里写明来源 —— 如实上报优先于好看。
    """
    服务器 = 网关.服务器
    剩 = int(getattr(服务器, "活动工作线程数", 0) or 0) if 服务器 is not None else 0
    if 剩 <= 0:
        return []
    已运行 = round(time.monotonic() - (_停机起点["值"] or time.monotonic()), 2)
    return [{
        "路径": "（网关工作线程：在途请求，服务器未登记路径/请求id）",
        "请求id": "",
        "已运行秒": 已运行,
        "拒绝请求数": int(getattr(服务器, "拒绝请求数", 0) or 0),
    } for _ in range(剩)]


def _取消在途流() -> str:
    """取消全部在途流式通道：SSE 是长连接，只靠等永远等不到排空。"""
    流式管理器 = getattr(网关, "流式管理器", None)
    if 流式管理器 is None:
        return "本网关无流式通道管理器"
    通道表 = list((getattr(流式管理器, "通道表", {}) or {}).items())
    已取消 = 0
    for 请求id, _通道 in 通道表:
        try:
            if 流式管理器.取消(请求id):
                已取消 += 1
        except Exception:  # noqa: BLE001 —— 单个通道取消失败不阻断其余通道
            continue
    return f"{已取消}/{len(通道表)} 个在途流式通道已取消"


def _任务账本落库() -> tuple[bool, str]:
    """段 4 的持久化项：任务账本落库（运行态唯一落点）。"""
