"""生命周期管理：加载器的装配编排。

流程：发现 → 校验（依赖/循环/版本/提供者）→ 锁定 → 装配（按拓扑
顺序）→ 可运行。校验不通过不装配；生命周期状态机记录每个包并支持
回滚；装配失败不得留下半成品状态。
"""

