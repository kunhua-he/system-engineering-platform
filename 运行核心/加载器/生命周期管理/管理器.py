from 公共契约.生命周期.生命周期 import 生命周期管理器
from 运行核心.加载器.包发现.发现器 import 发现全部
from 运行核心.加载器.包安装.模块安装 import 安装模块
from 运行核心.加载器.包安装.支持库安装 import 安装支持库
from 运行核心.加载器.依赖解析.解析器 import 解析依赖
from 运行核心.加载器.依赖解析.装配锁 import (
    构建装配锁,
    清除装配状态,
    记录装配状态,
    读取装配状态,
)
from 运行核心.加载器.提供者选择.选择器 import 选择全部提供者


def 恢复注册表(注册表: 能力注册表, 快照: dict[str, 能力实现]) -> None:
    """装配失败恢复注册表到装配前状态，不留半装配能力。

    只经公共契约公开接口操作：清空后按快照逐条重新注册。
    快照与当前一致时不动作（未发生任何注册）。
    """
    if set(注册表.能力id列表) == set(快照):
        return
    注册表.清空()
    for 能力id in sorted(快照):
        注册表.注册(快照[能力id])


@dataclass
class 装配结果:
    """一次完整装配的结果。"""

    成功: bool = False
    顺序列表: list[str] = field(default_factory=list)
    问题列表: list[str] = field(default_factory=list)
    已注册能力数: int = 0
    声明能力数: int = 0
    生命周期记录: list = field(default_factory=list)

    def 打印(self) -> str:
        行列表 = ["=" * 40, "加载器装配结果", "=" * 40]
        行列表.append(f"装配成功: {self.成功}")
        行列表.append(f"装配顺序: {' → '.join(self.顺序列表) if self.顺序列表 else '（无）'}")
        行列表.append(f"已注册能力: {self.已注册能力数} / 声明能力: {self.声明能力数}")
        if self.问题列表:
            行列表.append("问题清单:")
            for 问题 in self.问题列表:
                行列表.append(f"  ✗ {问题}")
        行列表.append(f"可复现: python3.14 -m 加载器.生命周期管理.管理器")
        return "\n".join(行列表)


def 装配系统(支持库根目录, 模块根目录, 注册表: 能力注册表 | None = None) -> 装配结果:
    """发现 → 校验 → 锁定 → 装配 → 可运行 的完整装配。

    任一校验失败即整体失败，不装配任何未通过校验的包；
    装配失败回滚，不留半成品状态。
    """
    注册表 = 注册表 or 能力注册表()
    结果 = 装配结果()

    # 1. 发现 + 唯一性检查（重复包id/重复能力id 必须失败）
    发现 = 发现全部(支持库根目录, 模块根目录)
    if not 发现.成功:
        结果.问题列表.extend(发现.问题列表)
        return 结果
    声明列表 = 发现.声明列表
    if not 声明列表:
        结果.问题列表.append("未发现任何支持库或模块")
        return 结果

    # 2. 提供者选择（多提供者冲突必须失败）+ 类型检查
    # 已废弃包（旧混装回滚版本）不参与提供者选择：文件保留，能力由新提供者唯一提供
    活跃声明列表 = [声明 for 声明 in 声明列表 if not getattr(声明, "已废弃", False)]
    提供者表 = 选择全部提供者(活跃声明列表)
    for 能力id, 选择 in 提供者表.items():
        if 选择.冲突列表:
            结果.问题列表.append(f"能力 {能力id} 多提供者冲突: {' / '.join(选择.冲突列表)}")
        elif 选择.缺失 and any(依赖.get("能力") == 能力id for 声明 in 活跃声明列表 for 依赖 in 声明.依赖):
            结果.问题列表.append(f"能力 {能力id} 被依赖但无提供者")
    for 声明 in 活跃声明列表:
        if 声明.类型 not in ("支持库", "基础模块", "功能模块"):
            结果.问题列表.append(f"类型错误: {声明.包id} 类型 {声明.类型} 不在（支持库/基础模块/功能模块）")
    if 结果.问题列表:
        return 结果

    # 3. 依赖解析（缺失/版本/循环）
    能力提供者 = {能力id: (选择.提供包id, 选择.提供版本) for 能力id, 选择 in 提供者表.items() if 选择.成功}
    解析 = 解析依赖(活跃声明列表, 能力提供者)
    结果.问题列表.extend(解析.缺失能力)
    结果.问题列表.extend(解析.版本冲突)
    if 解析.循环:
        结果.问题列表.append(f"依赖循环: {', '.join(解析.循环)}")
    if not 解析.成功:
        return 结果
    结果.顺序列表 = 解析.顺序列表

    # 3.4.1 聚合契约漂移校验（fail-closed 于契约已声明的包）：
    # 包已提供 能力契约/参数契约.json 时，声明能力必须全部出现在聚合契约中
    # （删契约/契约缺能力 → 装配失败）；尚未建聚合契约的支持库包由第二波
    # 13/13 收口补齐，本波不阻断（契约存在性由 组件合规 逐包权威门禁 强制执行）。
    from pathlib import Path as _契约路径
    for 声明 in 活跃声明列表:
        来源 = getattr(声明, "来源路径", "") or ""
        if not 来源:
            continue
        包目录 = _契约路径(来源)
        if not 包目录.is_dir():
            包目录 = 包目录.parent
        契约路径 = 包目录 / "能力契约" / "参数契约.json"
        if not 契约路径.is_file():
            # 模块契约已在第二十九阶段建成，缺失即阻断（删契约 fail-closed）；
            # 支持库聚合契约由第二波 13/13 收口补齐，本波不阻断。
            if 声明.类型 in ("基础模块", "功能模块"):
                结果.问题列表.append(
                    f"聚合契约缺失（装配阻断）: {声明.包id} 缺少 能力契约/参数契约.json"
                )
            continue
        try:
            import json as _json
            契约数据 = _json.loads(契约路径.read_text(encoding="utf-8"))
            契约能力id集合 = {项.get("能力id") for 项 in 契约数据.get("能力契约", [])}
        except (OSError, ValueError) as 契约错误:
            结果.问题列表.append(f"聚合契约不可读（装配阻断）: {声明.包id} {契约错误}")
            continue
        声明能力id集合 = {能力.能力id for 能力 in 声明.能力}
        缺失契约能力 = sorted(声明能力id集合 - 契约能力id集合)
        if 缺失契约能力:
            结果.问题列表.append(
                f"聚合契约缺声明能力（装配阻断）: {声明.包id} {缺失契约能力}"
            )
    if 结果.问题列表:
        return 结果

    # 3.5 装配前完成装配锁（依赖拓扑/版本锁/能力锁/提供者锁），并校验：
    # - 能力锁 vs 注册表现状：已注册提供方与本次声明不一致必须失败；
    # - 同一注册表重复装配：装配锁完全一致才可重放（幂等），
    #   任一不同（版本/提供者/顺序漂移）必须冲突失败，禁止覆盖。
    # 全部锁校验通过后才允许进入装配，保证失败零半装配。
    装配锁 = 构建装配锁(活跃声明列表, 提供者表, 解析.顺序列表)
    for 能力id in sorted(装配锁.能力锁):
        已有实现 = 注册表.获取(能力id)
        if 已有实现 is not None and 已有实现.包id != 装配锁.能力锁[能力id]:
            结果.问题列表.append(
                f"能力锁冲突: 能力 {能力id} 已被 {已有实现.包id} 注册，"
                f"本次声明提供方 {装配锁.能力锁[能力id]} 不一致"
            )
    上次装配锁 = 读取装配状态(注册表)
    if 上次装配锁 is not None:
        漂移表 = 上次装配锁.差异说明(装配锁)
        if 漂移表:
            结果.问题列表.append(f"装配锁漂移（重复装配冲突，禁止覆盖）: {'；'.join(漂移表)}")
    if 结果.问题列表:
        return 结果

    # 3.6 装配前快照注册表：装配失败时恢复，不留半装配状态
    注册表快照 = {能力id: 注册表.获取(能力id) for 能力id in 注册表.能力id列表}

    # 4. 生命周期流转 + 装配（严格按装配锁拓扑顺序，提供者在先）
    生命周期表 = {声明.包id: 生命周期管理器(声明.包id, 版本=声明.版本) for 声明 in 活跃声明列表}
    顺序索引 = {包id: 序号 for 序号, 包id in enumerate(解析.顺序列表)}
    支持库声明 = [声明 for 声明 in 活跃声明列表 if 声明.类型 == "支持库"]
    模块声明 = [声明 for 声明 in 活跃声明列表 if 声明.类型 in ("模块", "基础模块", "功能模块")]
    支持库声明.sort(key=lambda 声明: 顺序索引[声明.包id])
    模块声明.sort(key=lambda 声明: 顺序索引[声明.包id])

    # 4.0 创建并注入唯一能力调用服务（模块只持能力 id，经注入调用器按 id 调支持库）
    from 运行核心.能力调用.唯一能力调用 import 创建并绑定, 设置全局唯一服务
    唯一服务 = 创建并绑定(注册表)
    设置全局唯一服务(唯一服务)

    # 4.0.1 提供者环境批量确保 + 强制校验（fail-closed 硬门禁）
    # 支持库批次装配前，先收集含 依赖锁.json 的第三方提供者目录，经
    # 批量确保环境（内部 ≤8 并行，同提供者/同环境目录/同制品仓库串行锁）
    # 确保环境真实就绪：缓存命中复用、输入变化按新摘要重建、失败清理，
    # 全部经 缓存证据.jsonl 三态审计；随后保留 校验提供者环境 终检：
    # 缺锁、空锁、非精确版本、闭包未覆盖、环境指纹漂移、隔离环境缺失
    # 任一不满足仍拒绝装配。装配失败语义不变：任一失败整体阻断。
    from pathlib import Path as _路径
    from 运行核心.运行环境管理器 import 校验提供者环境, 批量确保环境

    待确保目录表: list[_路径] = []
    锁定提供者表: list = []
    for 声明 in 支持库声明:
        if getattr(声明, "已废弃", False):
            continue
        来源 = getattr(声明, "来源路径", "") or ""
        if not 来源:
            continue
        提供者目录 = _路径(来源)
        if not 提供者目录.is_dir():
            提供者目录 = 提供者目录.parent
        锁路径 = 提供者目录 / "依赖锁.json"
        # 适配层第三方提供者必须有依赖锁（删锁必须装配失败，fail-closed）；
        # 后端/前端纯标准库支持库无锁合法（不强制环境校验）。
        if not 锁路径.is_file():
            if 声明.包id.startswith("支持库.适配层.") or "适配层" in str(提供者目录):
                结果.问题列表.append(
                    f"提供者依赖锁缺失（装配阻断）: {声明.包id} 缺少 依赖锁.json"
                )
            continue
        待确保目录表.append(提供者目录)
        锁定提供者表.append((声明, 提供者目录))

    # 批量确保：真实构建/命中（结果与输入顺序一致），任一失败整体阻断
    环境结果表 = 批量确保环境(待确保目录表)
    if len(环境结果表) != len(锁定提供者表):
        结果.问题列表.append("提供者环境确保结果与提供者数量不一致（装配阻断）")
    for (声明, _提供者目录), 环境结果 in zip(锁定提供者表, 环境结果表):
        if not 环境结果.成功:
            结果.问题列表.append(
                f"提供者环境确保失败（装配阻断）: {声明.包id} "
                f"{环境结果.错误码}: {环境结果.错误说明}"
            )
    # fail-closed 终检：锁规则 + 隔离环境就绪（环境就绪校验不可跳过）
    for 声明, 提供者目录 in 锁定提供者表:
        校验 = 校验提供者环境(提供者目录, 提供者id=提供者目录.name)
        if not 校验.成功:
            问题文本 = [
                f"{问题.原因}@{问题.路径 or 声明.包id}"
                for 问题 in 校验.问题列表[:5]
            ]
            结果.问题列表.append(
                f"提供者环境校验失败（装配阻断）: {声明.包id} "
                f"{'；'.join(问题文本)}"
            )
    if 结果.问题列表:
        return 结果

    def 装配批次(声明批次: list) -> bool:
        """流转 已发现→已校验→已锁定，再按拓扑顺序逐包装配入口；失败返回 False。"""
        for 声明 in 声明批次:
            生命周期表[声明.包id].流转("已发现", 操作名称="扫描发现")
            生命周期表[声明.包id].流转("已校验", 操作名称="依赖校验通过")
            生命周期表[声明.包id].流转("已锁定", 操作名称="依赖锁定")
        try:
            for 声明 in 声明批次:
                if 声明.类型 == "支持库":
                    安装支持库(声明, 注册表)
                else:
                    安装模块(声明, 注册表)
        except Exception as 错误:
            raise RuntimeError(f"{声明.包id} 装配失败: {错误}") from 错误
        for 声明 in 声明批次:
            生命周期表[声明.包id].流转("已装配", 操作名称="入口加载并注册能力")
        return True

    try:
        装配批次(支持库声明)
        装配批次(模块声明)
    except Exception as 错误:
        结果.问题列表.append(f"装配失败: {错误}")
        for 管理器 in 生命周期表.values():
            管理器.回滚(错误码="装配失败", 错误说明=str(错误))
        结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
        恢复注册表(注册表, 注册表快照)
        return 结果

    # 5. 装配后检查：活跃正式 owner 声明能力都能从注册表获得。
    # Provider 是内部实现宿主，不是公开能力 owner；其能力仍可参与
    # 依赖解析和实际装配，但不能进入公开能力计数。
    声明能力id集合: set[str] = set()
    正式公开包id集合 = {
        声明.包id for 声明 in 活跃声明列表
        if not 声明.包id.startswith("支持库.适配层.")
    }
    for 声明 in 活跃声明列表:
        if 声明.包id not in 正式公开包id集合:
            continue
        for 能力 in 声明.能力:
            声明能力id集合.add(能力.能力id)
    结果.声明能力数 = len(声明能力id集合)
    缺失能力 = [能力id for 能力id in 声明能力id集合 if 注册表.获取(能力id) is None]
    if 缺失能力:
        结果.问题列表.append(f"装配后检查: {len(缺失能力)} 个声明能力未注册: {缺失能力[:5]}")
        for 管理器 in 生命周期表.values():
            管理器.回滚(错误码="装配后检查失败", 错误说明="声明能力未全部注册")
        结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
        恢复注册表(注册表, 注册表快照)
        return 结果

    # 6. 全部流转到 可运行
    for 声明 in 活跃声明列表:
        生命周期表[声明.包id].流转("可运行", 操作名称="装配完成可运行")

    记录装配状态(注册表, 装配锁)
    # 已注册能力数必须反映注册表真实数量，与声明能力数形成可核对闭环。
    # 内部 Provider 是否公开由搜索/契约层控制，不在这里篡改注册统计。
    公开注册能力数 = sum(
        1 for 能力id in 注册表.能力id列表
        if (实现 := 注册表.获取(能力id)) is not None
        and not (实现.包id or "").startswith("支持库.适配层.")
    )
    结果.已注册能力数 = 公开注册能力数
    结果.成功 = True
    结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
    return 结果


def 停止系统(支持库根目录, 模块根目录, 注册表: 能力注册表) -> 装配结果:
    """停止系统：全部包 可运行 → 已停止（重复停止幂等）。

    停止不卸载：能力仍在注册表，可再次启动。
    """
    结果 = 装配结果()
    发现 = 发现全部(支持库根目录, 模块根目录)
    声明列表 = 发现.声明列表
    if not 声明列表:
        结果.问题列表.append("未发现任何支持库或模块")
        return 结果
    生命周期表 = {声明.包id: 生命周期管理器(声明.包id, 版本=声明.版本, 初始状态="可运行") for 声明 in 声明列表}
    for 声明 in 声明列表:
        记录 = 生命周期表[声明.包id].流转("已停止", 操作名称="停止系统")
        if not 记录.成功 and 生命周期表[声明.包id].状态 != "已停止":
            结果.问题列表.append(f"停止失败: {声明.包id} {记录.错误说明}")
    if 结果.问题列表:
        return 结果
    结果.成功 = True
    结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
    return 结果


def 卸载系统(支持库根目录, 模块根目录, 注册表: 能力注册表) -> 装配结果:
    """卸载系统：全部包 已停止 → 已卸载，并清空能力注册表。

    规则：可运行资源必须先停止才能卸载；未装配对象不能直接卸载；
    重复卸载幂等；卸载后注册表不得残留任何能力。
    """
    结果 = 装配结果()
    发现 = 发现全部(支持库根目录, 模块根目录)
    声明列表 = 发现.声明列表
    if not 声明列表:
        结果.问题列表.append("未发现任何支持库或模块")
        return 结果
    生命周期表 = {声明.包id: 生命周期管理器(声明.包id, 版本=声明.版本, 初始状态="可运行") for 声明 in 声明列表}
    for 声明 in 声明列表:
        记录 = 生命周期表[声明.包id].流转("已停止", 操作名称="卸载前停止")
        if 记录.成功:
            生命周期表[声明.包id].流转("已卸载", 操作名称="停止后卸载")
    for 声明 in 声明列表:
        if 生命周期表[声明.包id].状态 != "已卸载":
            结果.问题列表.append(f"卸载失败: {声明.包id} 当前状态 {生命周期表[声明.包id].状态}")
    if 结果.问题列表:
        结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
        return 结果
    注册表.清空()
    清除装配状态(注册表)
    结果.成功 = True
    结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
    return 结果


