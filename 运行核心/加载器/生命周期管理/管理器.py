"""生命周期管理：加载器的装配编排。

流程：发现 → 校验（依赖/循环/版本/提供者）→ 锁定 → 装配（按拓扑
顺序）→ 可运行。校验不通过不装配；生命周期状态机记录每个包并支持
回滚；装配失败不得留下半成品状态。

单包级隔离（架构项A，2026-09-15）：单个包自己的半成品问题——实现缺失
（入口缺失/入口导入失败）、参数契约不可读、依赖锁内容为空或非法——
只跳过该包并写入 装配结果.跳过包列表 告警，其余包照常装配；跨包真冲突
（依赖缺失/版本冲突/多提供者冲突/能力重复注册/装配锁漂移/提供者环境
未就绪/适配层缺依赖锁）仍整体阻断，fail-closed 不变。边界见
`开发文档/新建支持库与模块指南.md` 第八节。
"""

