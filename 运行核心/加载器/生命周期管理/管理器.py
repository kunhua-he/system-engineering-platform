def 恢复注册表(注册表: 能力注册表, 快照: dict[str, 能力实现]) -> None:
    """装配失败恢复注册表到装配前状态，不留半装配能力。

    只经公共契约公开接口操作：清空后按快照逐条重新注册。
    快照与当前一致时不动作（未发生任何注册）。
    """
    if set(注册表.能力id列表) == set(快照):
        return
    注册表.清空()
    for 能力id in sorted(快照):
        注册表.注册(快照[能力id])


@dataclass
class 装配结果:
    """一次完整装配的结果。"""

    成功: bool = 假
    顺序列表: list[str] = field(default_factory=list)
    问题列表: list[str] = field(default_factory=list)
    已注册能力数: int = 0
    声明能力数: int = 0
    生命周期记录: list = field(default_factory=list)
    # 单包级跳过告警（只增字段）：每项写明「哪个包 / 在哪个阶段 / 什么原因」。
    # 有告警不等于装配失败——其余包照常装配；零包装配成功才算失败。
    跳过包列表: list[str] = field(default_factory=list)

    def 打印(self) -> str:
        行列表 = ["=" * 40, "加载器装配结果", "=" * 40]
        行列表.append(f"装配成功: {self.成功}")
        行列表.append(f"装配顺序: {' → '.join(self.顺序列表) if self.顺序列表 else '（无）'}")
        行列表.append(f"已注册能力: {self.已注册能力数} / 声明能力: {self.声明能力数}")
        if self.跳过包列表:
            行列表.append(f"单包级跳过告警（{len(self.跳过包列表)} 个，其余包照常装配）:")
            for 告警 in self.跳过包列表:
                行列表.append(f"  ⚠ {告警}")
        if self.问题列表:
            行列表.append("问题清单:")
            for 问题 in self.问题列表:
                行列表.append(f"  ✗ {问题}")
        行列表.append(f"可复现: python3.14 -m 加载器.生命周期管理.管理器")
        return "\n".join(行列表)


@dataclass
class 单包预检结果:
    """单个包的包级预检结果（只判「这个包自己是不是半成品」）。"""

    跳过原因: str = ""
    契约能力集合: set | None = None
    环境错误码: str = ""
    环境错误说明: str = ""

    def 需跳过(self) -> bool:
        return bool(self.跳过原因)


def _包根目录(声明) -> Path:
    """包根目录：声明文件所在目录（来源路径异常时退回空路径）。"""
    try:
        return Path(声明.来源路径).parent
    except Exception:
        return Path(getattr(声明, "来源路径", "") or "").parent


def _跳过告警(包id: str, 阶段: str, 原因: str) -> str:
    """单包级跳过告警文案：包 id / 阶段 / 原因 三件套一眼能定位。"""
    return f"已跳过 {包id}｜{阶段}｜{原因}"


#: 「唯一注册表拒绝重复注册」的权威实现代码对象（P1-6）：`能力注册表.注册` 本体。
#: 判跨包真冲突时按**代码对象同一性**比对调用栈，不比对函数名/异常文案。
_注册实现代码 = 能力注册表.注册.__code__


def _是跨包能力冲突(错误: Exception) -> bool:
    """是否跨包真冲突（唯一注册表拒绝重复注册）。

    这类冲突不是「单个包自己的半成品问题」：两个包抢同一个能力 id 属
    能力多提供者冲突，必须继续整体阻断（fail-closed），不得降级成跳过。

    **判据口径（P1-6 收口）**：修前判 ``isinstance(错误, ValueError) and "重复注册" in str(错误)``
    —— 改一句中文报错文案，跨包真冲突就会被降级成「跳过该包」，fail-closed 静默失效
    （实证见本条反向验证：文案改成「重复登记」后旧判据返回假）。

    现在按**异常类型 + 权威抛出点代码对象**判：异常必须是 ``ValueError``，且调用栈里
    必须出现 ``公共契约.能力契约.契约.能力注册表.注册`` 的**实现代码对象**（``f_code`` 同一性
    比对，不是函数名/文案字符串比对，故改文案、改函数名都不影响结论）。
    注册表是唯一权威：本函数只认「注册表自己拒绝」这一事实，不复制「谁和谁抢同一个
    能力 id」的判定规则（第二套判据）。
    """
    if not isinstance(错误, ValueError):
        return 假
    for 栈帧, _行号 in traceback.walk_tb(错误.__traceback__):
        if 栈帧.f_code is _注册实现代码:
            return 真
    return 假


def _单包级预检(声明) -> 单包预检结果:
    """单包级问题预检（不加载入口、不执行实现）。

    只判三类半成品问题：实现缺失（入口缺失/越界）、依赖锁内容为空或非法、
    参数契约不可读。适配层第三方提供者「完全缺少 依赖锁.json」不在这里
    处理——那是 fail-closed 硬门禁，仍由装配的提供者环境段整体阻断。
    顺序：入口 → 依赖锁 → 参数契约（读取结果顺带回带给装配后段，避免二次读盘）。
    """
    from 运行核心.运行环境管理器.环境管理器 import 检查依赖锁内容

    结果 = 单包预检结果()
    包根 = _包根目录(声明)
    if not 包根.is_dir():
        结果.跳过原因 = "包目录不存在（声明文件所在的包目录已不可读）"
        return 结果
    入口 = str(getattr(声明, "入口", "") or "")
    if not 入口:
        结果.跳过原因 = "实现缺失（包声明未声明 入口 字段）"
        return 结果
    try:
        解析入口路径(声明, "支持库" if 声明.类型 == "支持库" else "模块")
    # ★ 2026-09-24（批H-H4）：补捕 `ImportError`。`解析入口路径` 的「系统根」已收口到
    #   唯一节点 `公共契约/运行时/导入前缀.py::取系统根`（fail-closed：找不到同时含
    #   `支持库`/`模块库` 的祖先就抛 `ImportError`）。漏捕它 ⇒ 缺锚时这里**裸抛**，
    #   而不是像其它形状一样记成 `实现缺失（…）` —— 那会把「这棵树认不出来」报成
    #   「装配崩了」，与本批刚修掉的「退 起点 误报入口文件缺失」是同一类假读数。
    except (OSError, ValueError, ImportError) as 错误:
        结果.跳过原因 = f"实现缺失（{错误}）"
        return 结果
    错误码, 错误说明 = 检查依赖锁内容(包根)
    if 错误码:
        结果.跳过原因 = f"{错误码}（{错误说明}）"
        结果.环境错误码 = 错误码
        结果.环境错误说明 = 错误说明
        return 结果
    契约路径 = 包根 / "能力契约" / "参数契约.json"
    if 契约路径.is_file():
        import json as _json
        try:
            契约数据 = _json.loads(契约路径.read_text(encoding="utf-8"))
        except (OSError, ValueError) as 错误:
            结果.跳过原因 = f"参数契约不可读（{错误}）"
            return 结果
        if not isinstance(契约数据, dict):
            结果.跳过原因 = "参数契约不可读（顶层必须是 JSON 对象）"
            return 结果
        契约能力 = 契约数据.get("能力契约", [])
        if not isinstance(契约能力, list):
            结果.跳过原因 = "参数契约不可读（能力契约 必须是列表）"
            return 结果
        结果.契约能力集合 = {
            项.get("能力id") for 项 in 契约能力 if isinstance(项, dict)
        }
    return 结果


def 装配系统(支持库根目录, 模块根目录, 注册表: 能力注册表 | None = None,
            技能库根目录=None) -> 装配结果:
    """发现 → 校验 → 锁定 → 装配 → 可运行 的完整装配。

    任一校验失败即整体失败，不装配任何未通过校验的包；
    装配失败回滚，不留半成品状态。

    技能库根目录 为可选第三根（顶层 `技能库/`）；不传时行为与原来一致。
    """
    注册表 = 注册表 or 能力注册表()
    结果 = 装配结果()

    # 1. 发现 + 唯一性检查（重复包id/重复能力id 必须失败）
    发现 = 发现全部(支持库根目录, 模块根目录, 技能库根目录)
    if not 发现.成功:
        结果.问题列表.extend(发现.问题列表)
        return 结果
    声明列表 = 发现.声明列表
    if not 声明列表:
        结果.问题列表.append("未发现任何支持库或模块")
        return 结果

    # 2. 提供者选择（多提供者冲突必须失败）+ 类型检查
    # 已废弃包（旧混装回滚版本）不参与提供者选择：文件保留，能力由新提供者唯一提供
    活跃声明列表 = [声明 for 声明 in 声明列表 if not getattr(声明, "已废弃", 假)]
    提供者表 = 选择全部提供者(活跃声明列表)
    for 能力id, 选择 in 提供者表.items():
        if 选择.冲突列表:
            结果.问题列表.append(f"能力 {能力id} 多提供者冲突: {' / '.join(选择.冲突列表)}")
        elif 选择.缺失 and any(依赖.get("能力") == 能力id for 声明 in 活跃声明列表 for 依赖 in 声明.依赖):
            结果.问题列表.append(f"能力 {能力id} 被依赖但无提供者")
    for 声明 in 活跃声明列表:
        if 声明.类型 not in ("支持库", "基础模块", "功能模块"):
            结果.问题列表.append(f"类型错误: {声明.包id} 类型 {声明.类型} 不在（支持库/基础模块/功能模块）")
    if 结果.问题列表:
        return 结果

    # 3. 依赖解析（缺失/版本/循环）
    能力提供者 = {能力id: (选择.提供包id, 选择.提供版本) for 能力id, 选择 in 提供者表.items() if 选择.成功}
    解析 = 解析依赖(活跃声明列表, 能力提供者)
    结果.问题列表.extend(解析.缺失能力)
    结果.问题列表.extend(解析.版本冲突)
    if 解析.循环:
        结果.问题列表.append(f"依赖循环: {', '.join(解析.循环)}")
    if not 解析.成功:
        return 结果
    结果.顺序列表 = 解析.顺序列表

    # 3.4 单包级问题预检（架构项A，2026-09-15）：入口缺失/入口导入不了、
    # 依赖锁内容为空或非法、参数契约不可读，都是「这一个包自己的半成品
    # 问题」——只跳过该包并告警，其余包照常装配，不再全平台阻断（实测
    # 一条并行开发线的半成品包会让全平台装配失败约 10 分钟）。跨包真冲突
    # （依赖缺失/版本冲突/多提供者冲突/能力重复注册/装配锁漂移/提供者
    # 环境未就绪/适配层缺依赖锁）仍按后续各步整体阻断，fail-closed 不变。
    from 运行核心.运行环境管理器.环境管理器 import 记录跳过证据

    独立包id集合 = {声明.包id for 声明 in 活跃声明列表}
    生命周期表 = {声明.包id: 生命周期管理器(声明.包id, 版本=声明.版本)
                 for 声明 in 活跃声明列表}
    跳过包表: dict[str, str] = {}
    契约能力表: dict[str, set | None] = {}

    def 记录跳过(声明, 阶段: str, 原因: str) -> None:
        """登记单包级跳过：告警可见 + 生命周期留痕（证据不丢，也不是静默通过）。"""
        跳过包表[声明.包id] = 原因
        结果.跳过包列表.append(_跳过告警(声明.包id, 阶段, 原因))
        生命周期表[声明.包id].回滚(错误码="单包级跳过", 错误说明=f"{阶段}：{原因}")

    可装配声明列表: list = []
    for 声明 in 活跃声明列表:
        预检 = _单包级预检(声明)
        契约能力表[声明.包id] = 预检.契约能力集合
        if not 预检.需跳过():
            可装配声明列表.append(声明)
            continue
        if 预检.环境错误码:
            # 坏锁的缓存证据链不因「跳过而非阻断」而丢：仍按失败落一条可审计证据。
            记录跳过证据(_包根目录(声明), 预检.环境错误码, 预检.环境错误说明)
        记录跳过(声明, "装配前预检", 预检.跳过原因)
    if not 可装配声明列表:
        结果.问题列表.append(
            f"未发现可装配的包：{len(活跃声明列表)} 个包全部因单包级问题被跳过"
            f"（{'；'.join(结果.跳过包列表[:5])}）"
        )
        return 结果

    # 3.4.1 聚合契约漂移校验（fail-closed 于契约已声明的包）：
    # 包已提供 能力契约/参数契约.json 时，声明能力必须全部出现在聚合契约中
    # （删契约/契约缺能力 → 装配失败）；尚未建聚合契约的支持库包由第二波
    # 13/13 收口补齐，本波不阻断（契约存在性由 组件合规 逐包权威门禁 强制执行）。
    # 契约读取在 3.4 预检里已完成（不可读的包已按单包级跳过），此处复用
    # 同一份读取结果，避免二次读盘与并发写入窗口。
    for 声明 in 可装配声明列表:
        契约能力id集合 = 契约能力表.get(声明.包id)
        if 契约能力id集合 is None:
            # 模块契约已在第二十九阶段建成，缺失即阻断（删契约 fail-closed）；
            # 支持库聚合契约由第二波 13/13 收口补齐，本波不阻断。
            if 声明.类型 in ("基础模块", "功能模块"):
                结果.问题列表.append(
                    f"聚合契约缺失（装配阻断）: {声明.包id} 缺少 能力契约/参数契约.json"
                )
            continue
        声明能力id集合 = {能力.能力id for 能力 in 声明.能力}
        缺失契约能力 = sorted(声明能力id集合 - 契约能力id集合)
        if 缺失契约能力:
            结果.问题列表.append(
                f"聚合契约缺声明能力（装配阻断）: {声明.包id} {缺失契约能力}"
            )
    if 结果.问题列表:
        return 结果

    # 3.5 装配前完成装配锁（依赖拓扑/版本锁/能力锁/提供者锁），并校验：
    # - 能力锁 vs 注册表现状：已注册提供方与本次声明不一致必须失败；
    # - 同一注册表重复装配：装配锁完全一致才可重放（幂等），
    #   任一不同（版本/提供者/顺序漂移）必须冲突失败，禁止覆盖。
    # 全部锁校验通过后才允许进入装配，保证失败零半装配。
    装配锁 = 构建装配锁(活跃声明列表, 提供者表, 解析.顺序列表)
    for 能力id in sorted(装配锁.能力锁):
        已有实现 = 注册表.获取(能力id)
        if 已有实现 is not None and 已有实现.包id != 装配锁.能力锁[能力id]:
            结果.问题列表.append(
                f"能力锁冲突: 能力 {能力id} 已被 {已有实现.包id} 注册，"
                f"本次声明提供方 {装配锁.能力锁[能力id]} 不一致"
            )
    上次装配锁 = 读取装配状态(注册表)
    if 上次装配锁 is not None:
        漂移表 = 上次装配锁.差异说明(装配锁)
        if 漂移表:
            结果.问题列表.append(f"装配锁漂移（重复装配冲突，禁止覆盖）: {'；'.join(漂移表)}")
    if 结果.问题列表:
        return 结果

    # 3.6 装配前快照注册表：装配失败时恢复，不留半装配状态
    注册表快照 = {能力id: 注册表.获取(能力id) for 能力id in 注册表.能力id列表}

    # 4. 生命周期流转 + 装配（严格按装配锁拓扑顺序，提供者在先）
    # 生命周期表 已在 3.4 预检时建立（跳过包的回滚留痕也在其中），此处不重建。
    顺序索引 = {包id: 序号 for 序号, 包id in enumerate(解析.顺序列表)}
    支持库声明 = [声明 for 声明 in 可装配声明列表 if 声明.类型 == "支持库"]
    模块声明 = [声明 for 声明 in 可装配声明列表 if 声明.类型 in ("模块", "基础模块", "功能模块")]
    支持库声明.sort(key=lambda 声明: 顺序索引[声明.包id])
    模块声明.sort(key=lambda 声明: 顺序索引[声明.包id])

    # 4.0 创建并注入唯一能力调用服务（模块只持能力 id，经注入调用器按 id 调支持库）
    from 运行核心.能力调用.唯一能力调用 import 创建并绑定, 设置全局唯一服务
    唯一服务 = 创建并绑定(注册表)
    设置全局唯一服务(唯一服务)

    # 4.0.1 提供者环境批量确保 + 强制校验（fail-closed 硬门禁）
    # 支持库批次装配前，先收集含 依赖锁.json 的第三方提供者目录，经
    # 批量确保环境（内部 ≤8 并行，同提供者/同环境目录/同制品仓库串行锁）
    # 确保环境真实就绪：缓存命中复用、输入变化按新摘要重建、失败清理，
    # 全部经 缓存证据.jsonl 三态审计；随后保留 校验提供者环境 终检：
    # 缺锁、空锁、非精确版本、闭包未覆盖、环境指纹漂移、隔离环境缺失
    # 任一不满足仍拒绝装配。装配失败语义不变：任一失败整体阻断。
    from pathlib import Path as _路径
    from 运行核心.运行环境管理器 import 校验提供者环境, 批量确保环境

    待确保目录表: list[_路径] = []
    锁定提供者表: list = []
    for 声明 in 支持库声明:
        if getattr(声明, "已废弃", 假):
            continue
        来源 = getattr(声明, "来源路径", "") or ""
        if not 来源:
            continue
        提供者目录 = _路径(来源)
        if not 提供者目录.is_dir():
            提供者目录 = 提供者目录.parent
        锁路径 = 提供者目录 / "依赖锁.json"
        # 适配层第三方提供者必须有依赖锁（删锁必须装配失败，fail-closed）；
        # 后端/前端纯标准库支持库无锁合法（不强制环境校验）。
        if not 锁路径.is_file():
            if 声明.包id.startswith("支持库.适配层.") or "适配层" in str(提供者目录):
                结果.问题列表.append(
                    f"提供者依赖锁缺失（装配阻断）: {声明.包id} 缺少 依赖锁.json"
                )
            continue
        待确保目录表.append(提供者目录)
        锁定提供者表.append((声明, 提供者目录))

    # 批量确保：真实构建/命中（结果与输入顺序一致），任一失败整体阻断
    环境结果表 = 批量确保环境(待确保目录表)
    if len(环境结果表) != len(锁定提供者表):
        结果.问题列表.append("提供者环境确保结果与提供者数量不一致（装配阻断）")
    for (声明, _提供者目录), 环境结果 in zip(锁定提供者表, 环境结果表):
        if not 环境结果.成功:
            结果.问题列表.append(
                f"提供者环境确保失败（装配阻断）: {声明.包id} "
                f"{环境结果.错误码}: {环境结果.错误说明}"
            )
    # fail-closed 终检：锁规则 + 隔离环境就绪（环境就绪校验不可跳过）
    for 声明, 提供者目录 in 锁定提供者表:
        校验 = 校验提供者环境(提供者目录, 提供者id=提供者目录.name)
        if not 校验.成功:
            问题文本 = [
                f"{问题.原因}@{问题.路径 or 声明.包id}"
                for 问题 in 校验.问题列表[:5]
            ]
            结果.问题列表.append(
                f"提供者环境校验失败（装配阻断）: {声明.包id} "
                f"{'；'.join(问题文本)}"
            )
    if 结果.问题列表:
        return 结果

    def 卸载包能力(包id: str) -> None:
        """只移除该包自己注册的能力（含未独立成包的聚合子域前缀）。

        单包装配中途失败必须把自己已注册的能力撤干净：否则失败包会以
        「半装配」形态留在注册表里，对调用方表现为「能力在但结果是半成品」，
        比整体失败更危险。
        """
        for 能力id in list(注册表.能力id列表):
            实现 = 注册表.获取(能力id)
            if 实现 is None:
                continue
            if 实现.包id == 包id or (
                实现.包id.startswith(包id + ".") and 实现.包id not in 独立包id集合
            ):
                注册表.移除(能力id, 包id=实现.包id)

    def 被跳过依赖(声明) -> str:
        """该包依赖的能力由「已被跳过的包」提供时返回原因（级联跳过）。"""
        for 依赖 in 声明.依赖:
            依赖能力id = str(依赖.get("能力", ""))
            if not 依赖能力id:
                continue
            提供者 = 能力提供者.get(依赖能力id)
            if 提供者 and 提供者[0] in 跳过包表:
                return f"依赖能力 {依赖能力id} 的提供包 {提供者[0]} 已被跳过"
        return ""

    def 装配批次(声明批次: list) -> list:
        """流转 已发现→已校验→已锁定，再按拓扑顺序逐包装配入口。

        返回本次真正装配成功的声明列表。单包问题（入口导入失败/半路报错、
        依赖落在被跳过的包上）只跳过该包并告警，其余包继续装配；跨包真冲突
        （能力重复注册）抛异常，由调用方整体阻断（fail-closed 不降级）。
        """
        for 声明 in 声明批次:
            生命周期表[声明.包id].流转("已发现", 操作名称="扫描发现")
            生命周期表[声明.包id].流转("已校验", 操作名称="依赖校验通过")
            生命周期表[声明.包id].流转("已锁定", 操作名称="依赖锁定")
        本次成功: list = []
        for 声明 in 声明批次:
            原因 = 被跳过依赖(声明)
            if 原因:
                记录跳过(声明, "依赖级联", 原因)
                continue
            try:
                if 声明.类型 == "支持库":
                    安装支持库(声明, 注册表)
                else:
                    安装模块(声明, 注册表)
            except Exception as 错误:
                if _是跨包能力冲突(错误):
                    raise RuntimeError(f"{声明.包id} 装配失败: {错误}") from 错误
                卸载包能力(声明.包id)
                记录跳过(声明, "入口装配", f"装配失败（{错误}）")
                continue
            生命周期表[声明.包id].流转("已装配", 操作名称="入口加载并注册能力")
            本次成功.append(声明)
        return 本次成功

    try:
        # 支持库先、模块后（与装配锁拓扑序一致）；两个批次各自按包隔离。
        已装配声明列表 = 装配批次(支持库声明) + 装配批次(模块声明)
    except Exception as 错误:
        # 跨包真冲突：整体失败并回滚，不留半装配状态。
        结果.问题列表.append(f"装配失败: {错误}")
        for 管理器 in 生命周期表.values():
            管理器.回滚(错误码="装配失败", 错误说明=str(错误))
        结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
        恢复注册表(注册表, 注册表快照)
        return 结果

    # 5. 装配后检查（按包隔离）：成功装配的包，其**注册实现**必须与**声明**一致
    # （缺注册、参数名序/返回口径不一致、注册了声明外能力，都是该包自己的半成品
    # 问题），只跳过该包并告警，不升级成全平台阻断。
    #
    # ★ 2026-09-23 判据唯一化：判据改用 `公共契约/能力契约/契约.py` 的
    # `能力注册表.校验声明一致`（其内核即 `能力实现.声明一致`，契约.py:125）——
    # 这本就是「**注册实现 vs 真契约声明**」的真判据，但此前唯一生产调用点在发布
    # 门禁里「只报」，**装配期从不调它**，漂移因此能静默。同一件事此前散在 50 份各包
    # `__init__.py` 的 `_校验参数名序` 里做「镜像 vs 名序」的**同文件自比**（两份同源、
    # 一起写错即互证一致），从不与真契约比；现由本处**唯一一条**装配期闸门承担
    # （哲学 12.1：同一事实源；1.2：不保留旧腿）。
    # 包声明（包声明.json）与聚合契约（能力契约/参数契约.json）同出 `能力定义.json`，
    # 参数名序逐字一致（全仓实测 993/993），故此处即以真契约核注册实现。
    # Provider 是内部实现宿主，不是公开能力 owner；其能力仍可参与
    # 依赖解析和实际装配，但不能进入公开能力计数。
    正式公开包id集合 = {
        声明.包id for 声明 in 活跃声明列表
        if not 声明.包id.startswith("支持库.适配层.")
    }
    for 声明 in list(已装配声明列表):
        声明不一致 = 注册表.校验声明一致(声明.包id, 声明.能力)
        if not 声明不一致:
            continue
        卸载包能力(声明.包id)
        记录跳过(声明, "装配后检查", "；".join(声明不一致[:3]))
        已装配声明列表.remove(声明)

    if not 已装配声明列表:
        # 零包装配成功 = 平台一个能力都不可用：这才是真失败（fail-closed 底线）。
        结果.问题列表.append(
            f"装配失败: {len(活跃声明列表)} 个包全部未装配成功（零可用能力）"
            f"（{'；'.join(结果.跳过包列表[:5])}）"
        )
        for 管理器 in 生命周期表.values():
            管理器.回滚(错误码="装配失败", 错误说明="零包装配成功")
        结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
        恢复注册表(注册表, 注册表快照)
        return 结果

    声明能力id集合: set[str] = set()
    for 声明 in 已装配声明列表:
        if 声明.包id not in 正式公开包id集合:
            continue
        for 能力 in 声明.能力:
            声明能力id集合.add(能力.能力id)
    结果.声明能力数 = len(声明能力id集合)

    # 6. 全部流转到 可运行（只对成功装配的包；被跳过的包已在上面留回滚记录）
    for 声明 in 已装配声明列表:
        生命周期表[声明.包id].流转("可运行", 操作名称="装配完成可运行")

    记录装配状态(注册表, 装配锁)
    # 已注册能力数必须反映注册表真实数量，与声明能力数形成可核对闭环。
    # 内部 Provider 是否公开由搜索/契约层控制，不在这里篡改注册统计。
    公开注册能力数 = sum(
        1 for 能力id in 注册表.能力id列表
        if (实现 := 注册表.获取(能力id)) is not None
        and not (实现.包id or "").startswith("支持库.适配层.")
    )
    结果.已注册能力数 = 公开注册能力数
    结果.成功 = 真
    结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
    return 结果


def 停止系统(支持库根目录, 模块根目录, 注册表: 能力注册表) -> 装配结果:
    """停止系统：全部包 可运行 → 已停止（重复停止幂等）。

    停止不卸载：能力仍在注册表，可再次启动。
    """
    结果 = 装配结果()
    发现 = 发现全部(支持库根目录, 模块根目录)
    声明列表 = 发现.声明列表
    if not 声明列表:
        结果.问题列表.append("未发现任何支持库或模块")
        return 结果
    生命周期表 = {声明.包id: 生命周期管理器(声明.包id, 版本=声明.版本, 初始状态="可运行") for 声明 in 声明列表}
    for 声明 in 声明列表:
        记录 = 生命周期表[声明.包id].流转("已停止", 操作名称="停止系统")
        if not 记录.成功 and 生命周期表[声明.包id].状态 != "已停止":
            结果.问题列表.append(f"停止失败: {声明.包id} {记录.错误说明}")
    if 结果.问题列表:
        return 结果
    结果.成功 = 真
    结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
    return 结果


def 卸载系统(支持库根目录, 模块根目录, 注册表: 能力注册表) -> 装配结果:
    """卸载系统：全部包 已停止 → 已卸载，并清空能力注册表。

    规则：可运行资源必须先停止才能卸载；未装配对象不能直接卸载；
    重复卸载幂等；卸载后注册表不得残留任何能力。
    """
    结果 = 装配结果()
    发现 = 发现全部(支持库根目录, 模块根目录)
    声明列表 = 发现.声明列表
    if not 声明列表:
        结果.问题列表.append("未发现任何支持库或模块")
        return 结果
    生命周期表 = {声明.包id: 生命周期管理器(声明.包id, 版本=声明.版本, 初始状态="可运行") for 声明 in 声明列表}
    for 声明 in 声明列表:
        记录 = 生命周期表[声明.包id].流转("已停止", 操作名称="卸载前停止")
        if 记录.成功:
            生命周期表[声明.包id].流转("已卸载", 操作名称="停止后卸载")
    for 声明 in 声明列表:
        if 生命周期表[声明.包id].状态 != "已卸载":
            结果.问题列表.append(f"卸载失败: {声明.包id} 当前状态 {生命周期表[声明.包id].状态}")
    if 结果.问题列表:
        结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
        return 结果
    注册表.清空()
    清除装配状态(注册表)
    结果.成功 = 真
    结果.生命周期记录 = [记录 for 管理器 in 生命周期表.values() for 记录 in 管理器.记录列表]
    return 结果


