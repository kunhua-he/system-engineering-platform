"""进程工作器：独立进程子进程端。

从 stdin 读 JSON 请求行，调用能力，写 JSON 响应行到 stdout（flush）。
协议（与 进程协议.py 对应）：
请求: {"请求id", "类型": "调用|停止|健康", "能力id", "契约版本", "参数", "超时秒", "取消"}
响应: {"请求id", "成功", "值", "错误码", "错误说明", "来源", "可重试", "详细信息"}

启动后先打印 READY 行（父进程据此判断启动完成）。
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

# 父进程通过命令行参数传入系统根（-S 模式下无 site，需显式注入）
if len(sys.argv) > 1:
    系统根 = Path(sys.argv[1])
else:
    系统根 = Path(__file__).resolve().parents[1]
    for _祖先 in 系统根.parents:
        if (_祖先 / "支持库").is_dir() and (_祖先 / "模块库").is_dir():
            系统根 = _祖先
            break
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))
from 公共契约.基础类型.逻辑类型 import 真, 假

能力实现表 = {}


def 注册能力(能力id: str, 函数) -> None:
    能力实现表[能力id] = 函数


def 注册标准能力() -> None:
    """注册模拟能力：供独立进程调用（不依赖业务项目）。"""
    from 公共契约.基础类型.结果类型 import 结果
    from 公共契约.错误结构 import 错误码_参数不合法

    def 最小操作(参数: dict) -> 结果:
        名称 = (参数 or {}).get("名称", "")
        if not 名称:
            return 结果.失败(错误码_参数不合法, "缺少参数: 名称", 来源="进程工作器")
        if 名称 == "慢操作":
            time.sleep(0.3)  # 供超时/取消测试使用（调用超时须小于此值）
        if 名称 == "崩溃操作":
            raise RuntimeError("模拟崩溃")
        return 结果.成功结果({"名称": 名称, "工作器": "真实子进程"})

    注册能力("进程.最小操作", 最小操作)


def 处理请求(请求: dict) -> dict:
    """处理一条请求，返回响应字典。"""
    类型 = 请求.get("类型", "调用")
    if 类型 == "健康":
        return {"请求id": 请求.get("请求id"), "成功": 真, "值": "健康", "错误码": ""}
    if 类型 == "停止":
        return {"请求id": 请求.get("请求id"), "成功": 真, "值": "停止确认", "错误码": ""}
    能力id = 请求.get("能力id", "")
    函数 = 能力实现表.get(能力id)
    if 函数 is None:
        return {
            "请求id": 请求.get("请求id"), "成功": 假,
            "错误码": "能力不存在", "错误说明": f"能力未注册: {能力id}",
            "来源": "进程工作器", "可重试": 假, "详细信息": {},
        }
    try:
        结果 = 函数(请求.get("参数") or {})
        if hasattr(结果, "转字典"):
            return {
                "请求id": 请求.get("请求id"), "成功": 结果.成功,
                "值": 结果.值 if 结果.成功 else None,
                "错误码": 结果.错误码, "错误说明": 结果.错误说明,
                "来源": 结果.来源, "可重试": 结果.可重试,
                "详细信息": 结果.详细信息,
            }
        return {"请求id": 请求.get("请求id"), "成功": 真, "值": 结果, "错误码": ""}
    except Exception as 错误:
        return {
            "请求id": 请求.get("请求id"), "成功": 假,
            "错误码": "内部错误", "错误说明": str(错误),
            "来源": "进程工作器", "可重试": 假, "详细信息": {},
        }


def 主循环() -> int:
    """工作器主循环：READY → 逐行处理请求。

    协议唯一实现在 公共契约/运行时/子进程协议（空行/非法 JSON 跳过、停止类型也写响应）。
    """
    from 公共契约.运行时 import 子进程协议

    注册标准能力()
    return 子进程协议.多请求主循环(处理请求)


if __name__ == "__main__":
    主循环()
