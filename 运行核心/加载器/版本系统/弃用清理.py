"""版本弃用与清理：版本状态机与卸载条件检查。

版本状态：已发布 → 灰度中 → 已激活 → 已弃用 → 停止新装配 → 停止新调用
→ 等待清理 → 已卸载。
旧版本只有满足全部条件才允许卸载：无项目依赖/无运行中任务/无连接和句柄/
无待迁移状态/无待处理失败记录/无回滚窗口/已超过弃用期限。
卸载必须撤销：激活映射/路由/任务/事件监听/权限/注册表项/临时文件/外部资源。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from 公共契约.基础类型.逻辑类型 import 真, 假


@dataclass
class 卸载条件:
    """版本卸载的全部前置条件。"""

    无项目依赖: bool = 真
    无运行中任务: bool = 真
    无连接和句柄: bool = 真
    无待迁移状态: bool = 真
    无待处理失败记录: bool = 真
    无回滚窗口: bool = 真
    已超过弃用期限: bool = 真

    def 全部满足(self) -> bool:
        return all([
            self.无项目依赖, self.无运行中任务, self.无连接和句柄,
            self.无待迁移状态, self.无待处理失败记录,
            self.无回滚窗口, self.已超过弃用期限,
        ])

    def 未满足列表(self) -> list[str]:
        检查表 = [
            ("无项目依赖", self.无项目依赖, "仍有项目依赖"),
            ("无运行中任务", self.无运行中任务, "仍有运行中任务"),
            ("无连接和句柄", self.无连接和句柄, "仍有连接和句柄"),
            ("无待迁移状态", self.无待迁移状态, "仍有待迁移状态"),
            ("无待处理失败记录", self.无待处理失败记录, "仍有待处理失败记录"),
            ("无回滚窗口", self.无回滚窗口, "仍在回滚窗口内"),
            ("已超过弃用期限", self.已超过弃用期限, "未超过弃用期限"),
        ]
        return [说明 for _, 满足, 说明 in 检查表 if not 满足]


@dataclass
class 卸载结果:
    """一次版本卸载的结果。"""

    成功: bool = 假
    撤销清单: list[str] = field(default_factory=list)
    未满足条件: list[str] = field(default_factory=list)


标准撤销清单 = [
    "激活映射", "路由", "任务", "事件监听", "权限", "注册表项", "临时文件", "外部资源",
]


def 检查卸载条件(条件: 卸载条件) -> list[str]:
    """返回未满足条件列表（空=可卸载）。"""
    return 条件.未满足列表()


def 执行卸载(条件: 卸载条件, *, 撤销清单: list[str] | None = None) -> 卸载结果:
    """执行版本卸载；条件不满足则拒绝并保留明确状态。"""
    结果 = 卸载结果()
    未满足 = 检查卸载条件(条件)
    if 未满足:
        结果.未满足条件 = 未满足
        结果.成功 = 假
        return 结果
    结果.撤销清单 = 撤销清单 or list(标准撤销清单)
    结果.成功 = 真
    return 结果
