"""状态切换：无状态与有状态能力的切换流程。

无状态能力允许按请求切换：文本处理/数据转换/文件解析/只读查询/独立协议调用。
有状态能力必须先排空或迁移：数据库连接/任务队列/长连接/窗口/本地进程/
事务/会话/缓存/资源句柄。
不能证明状态可迁移时，禁止进程内热替换，改用新旧提供者并行运行和路由切换。
"""

from __future__ import annotations

from dataclasses import dataclass, field

无状态能力表 = ("文本处理.", "数据交换.", "文件系统.读取", "文件系统.列举",
                "数据集合.", "时间日期.", "只读查询", "独立协议调用")


def 判断有无状态(能力id: str) -> bool:
    """True=有状态；False=无状态。"""
    return not any(能力id.startswith(前缀) for 前缀 in 无状态能力表)


@dataclass
class 状态切换结果:
    """一次状态切换的结果。"""

    成功: bool = False
    步骤列表: list[str] = field(default_factory=list)
    问题列表: list[str] = field(default_factory=list)
    状态可迁移: bool = True


def 无状态切换(能力id: str) -> 状态切换结果:
    """无状态能力按请求切换（无需排空）。"""
    结果 = 状态切换结果()
    结果.步骤列表.append(f"无状态能力 {能力id} 按请求切换（无需排空）")
    结果.成功 = True
    return 结果


def 有状态切换(能力id: str, *, 状态可迁移: bool = True) -> 状态切换结果:
    """有状态能力切换：停止接收新请求→等待旧任务完成→关闭旧资源→
    导出或迁移状态→启动新版本→恢复状态→健康检查→开放新请求。"""
    结果 = 状态切换结果()
    结果.状态可迁移 = 状态可迁移
    if not 状态可迁移:
        结果.问题列表.append(
            f"有状态能力 {能力id} 无法证明状态可迁移，禁止进程内热替换；"
            "改用新旧提供者并行运行和路由切换"
        )
        结果.步骤列表.append("新旧提供者并行运行 + 路由切换")
        return 结果
    结果.步骤列表.extend([
        "停止接收新请求",
        "等待旧任务完成",
        "关闭旧资源",
        "导出或迁移状态",
        "启动新版本",
        "恢复状态",
        "健康检查",
        "开放新请求",
    ])
    结果.成功 = True
    return 结果


def 执行切换(能力id: str, *, 状态可迁移: bool = True) -> 状态切换结果:
    """按能力类型自动选择无状态/有状态切换。"""
    if 判断有无状态(能力id):
        return 有状态切换(能力id, 状态可迁移=状态可迁移)
    return 无状态切换(能力id)
