"""契约兼容性判断：新旧版本契约的兼容性检查。

兼容：内部实现修复/性能提升/增加可选参数/增加返回字段/非破坏性错误说明。
不兼容：修改必填参数/删除参数/修改返回结构/删除能力/删除错误码/
改变错误码语义/改变资源所有权/改变同步异步或流式语义。
不兼容升级必须提升契约主版本。结果：兼容/不兼容/需要适配器/无法升级。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假

结论_兼容 = "兼容"
结论_不兼容 = "不兼容"
结论_需要适配器 = "需要适配器"
结论_无法升级 = "无法升级"


@dataclass
class 兼容检查结果:
    """一次契约兼容性检查的结果。"""

    结论: str = 结论_兼容
    原因列表: list[str] = field(default_factory=list)
    是否需要适配器: bool = 假
    是否必须升主版本: bool = 假

    def 转字典(self) -> dict[str, Any]:
        return {"结论": self.结论, "原因": self.原因列表,
                "需要适配器": self.是否需要适配器, "必须升主版本": self.是否必须升主版本}


def 检查契约兼容(旧契约: dict[str, Any], 新契约: dict[str, Any]) -> 兼容检查结果:
    """检查新旧契约兼容性。

    契约结构：{"能力": [{"能力id", "参数": [{"名称","必填"}], "返回"}], "错误码": [str]}
    """
    结果 = 兼容检查结果()
    旧能力表 = {能力.get("能力id"): 能力 for 能力 in 旧契约.get("能力", [])}
    新能力表 = {能力.get("能力id"): 能力 for 能力 in 新契约.get("能力", [])}
    新能力id集合 = set(新能力表)

    # 1. 删除能力 → 不兼容
    for 能力id in 旧能力表:
        if 能力id not in 新能力表:
            结果.原因列表.append(f"删除能力: {能力id}")
            结果.结论 = 结论_不兼容
            结果.是否必须升主版本 = 真

    for 能力id, 新能力 in 新能力表.items():
        旧能力 = 旧能力表.get(能力id)
        if 旧能力 is None:
            结果.原因列表.append(f"新增能力（向后兼容）: {能力id}")
            continue
        旧参数表 = {参数.get("名称"): 参数 for 参数 in 旧能力.get("参数", [])}
        新参数表 = {参数.get("名称"): 参数 for 参数 in 新能力.get("参数", [])}

        # 2. 删除参数 → 不兼容
        for 参数名 in 旧参数表:
            if 参数名 not in 新参数表:
                结果.原因列表.append(f"删除参数 {参数名}（能力 {能力id}）")
                结果.结论 = 结论_不兼容
                结果.是否必须升主版本 = 真

        # 3. 修改必填参数（新增必填 或 可选变必填）→ 不兼容
        for 参数名, 新参数 in 新参数表.items():
            旧参数 = 旧参数表.get(参数名)
            if 旧参数 is None:
                if 新参数.get("必填", 真):
                    结果.原因列表.append(f"新增必填参数 {参数名}（能力 {能力id}）")
                    结果.结论 = 结论_不兼容
                    结果.是否必须升主版本 = 真
                else:
                    结果.原因列表.append(f"新增可选参数（兼容）: {参数名}")
            elif 旧参数.get("必填", 真) and not 新参数.get("必填", 真):
                结果.原因列表.append(f"必填改可选（兼容）: {参数名}")
            elif not 旧参数.get("必填", 真) and 新参数.get("必填", 真):
                结果.原因列表.append(f"可选改必填（不兼容）: {参数名}")
                结果.结论 = 结论_不兼容
                结果.是否必须升主版本 = 真

        # 4. 修改返回结构 → 不兼容
        if 旧能力.get("返回") != 新能力.get("返回"):
            结果.原因列表.append(f"返回结构变化（能力 {能力id}）: {旧能力.get('返回')} → {新能力.get('返回')}")
            结果.结论 = 结论_不兼容
            结果.是否必须升主版本 = 真

    # 5. 删除错误码 → 不兼容
    旧错误码集合 = set(旧契约.get("错误码", []))
    新错误码集合 = set(新契约.get("错误码", []))
    for 错误码 in 旧错误码集合:
        if 错误码 not in 新错误码集合:
            结果.原因列表.append(f"删除错误码: {错误码}")
            结果.结论 = 结论_不兼容
            结果.是否必须升主版本 = 真

    # 6. 内部实现修复/性能提升（无契约变化）→ 兼容
    if 结果.结论 == 结论_兼容 and 旧契约.get("说明") != 新契约.get("说明"):
        结果.原因列表.append("实现修复/说明变化（兼容）")

    if 结果.结论 == 结论_不兼容:
        结果.结论 = 结论_需要适配器  # 提供适配器可缓解；无适配器时无法升级
        结果.是否需要适配器 = 真
    return 结果
