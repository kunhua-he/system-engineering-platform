from 公共契约.基础类型.逻辑类型 import 真, 假

灰度指标阈值 = {"失败率上限": 0.05, "超时率上限": 0.10, "成功率下限": 0.95}

# 判定门槛：样本量不足只能报「未做结论」，不得读作「指标正常」。
# 口径与 `运行核心/加载器/版本系统/灰度指标.py` 的 `灰度指标库.超阈值问题` 一致
# （那边是 `请求总数 >= 5` 才下结论），避免同一平台两套阈值口径。
最小判定样本量 = 5

@dataclass
class 灰度指标:
    """灰度观察指标（进程内视图；落运行库的持久化口径见 灰度指标.py 的 `灰度指标库`）。"""

    成功数: int = 0
    失败数: int = 0
    超时数: int = 0
    平均耗时毫秒: float = 0.0

    def 样本量(self) -> int:
        """已记录的观测样本数（成功 + 失败）。"""
        return self.成功数 + self.失败数

    def 样本充足(self) -> bool:
        """样本量是否达到判定门槛（不足则既不能说正常，也不能下超阈值结论）。"""
        return self.样本量() >= 最小判定样本量

    def 失败率(self) -> float:
        总数 = self.成功数 + self.失败数
        return self.失败数 / 总数 if 总数 else 0.0

    def 超时率(self) -> float:
        总数 = self.成功数 + self.失败数
        return self.超时数 / 总数 if 总数 else 0.0

    def 记录(self, *, 成功: bool, 耗时毫秒: float = 0.0, 超时: bool = 假) -> None:
        if 成功:
            self.成功数 += 1
        else:
            self.失败数 += 1
        if 超时:
            self.超时数 += 1
        if 成功:
            总数 = self.成功数
            self.平均耗时毫秒 = (self.平均耗时毫秒 * (总数 - 1) + 耗时毫秒) / 总数

    def 超过阈值(self) -> list[str]:
        """带样本量门槛的超阈值判定；返回空列表 = 未做结论（**不等于**指标正常）。

        历史缺陷（父会话已复核）：本判定对零样本恒返回空列表，而调用点直接把它读成
        「指标正常」；`记录灰度观测` 全仓 0 调用方 → 指标表恒空 → 热切换永远输出
        「观察错误和耗时（指标正常）」这一恒真结论（零样本恒过）。
        修：样本不足一律不做结论；要判「正常」必须显式问 `样本充足()`。
        """
        if not self.样本充足():
            return []
        问题列表 = []
        if self.失败率() > 灰度指标阈值["失败率上限"]:
            问题列表.append(f"失败率 {self.失败率():.2%} 超过上限 {灰度指标阈值['失败率上限']:.0%}")
        if self.超时率() > 灰度指标阈值["超时率上限"]:
            问题列表.append(f"超时率 {self.超时率():.2%} 超过上限 {灰度指标阈值['超时率上限']:.0%}")
        return 问题列表


@dataclass
class 热切换结果:
    """一次热切换的结果。"""

    成功: bool = 假
    步骤列表: list[str] = field(default_factory=list)
    问题列表: list[str] = field(default_factory=list)
    自动回滚: bool = 假
    回滚记录: str = ""

    def 打印(self) -> str:
        行列表 = ["热切换结果", f"成功: {self.成功}" + ("（已自动回滚）" if self.自动回滚 else "")]
        for 步骤 in self.步骤列表:
            行列表.append(f"  ✓ {步骤}")
        for 问题 in self.问题列表:
            行列表.append(f"  ✗ {问题}")
        if self.回滚记录:
            行列表.append(f"  回滚记录: {self.回滚记录}")
        return "\n".join(行列表)


class 热切换管理器:
    """能力激活版本映射与热切换执行。"""

    def __init__(self, 版本注册表: 版本注册表) -> None:
        self.版本注册表 = 版本注册表
        self.激活映射: dict[str, str] = {}  # 能力id → 版本
        self.回退映射: dict[str, str] = {}  # 能力id → 回退版本
        self.灰度指标表: dict[str, 灰度指标] = {}  # 版本键 → 指标
        self.回滚记录表: list[dict[str, Any]] = []
        self.路由表: dict[str, Any] = {}  # 能力id → 当前活跃进程（第六阶段）
        self.提供者进程表: dict[str, dict[str, Any]] = {}  # 能力id → {版本: 进程}
        # 能力id → 灰度比例。**只是记录调用方意图**：全仓无任何读取者，
        # `调用路由` 也不看它（只按进程状态路由）→ 不产生按比例分流效果。
        # 口径权威：运行核心/加载器/版本系统/说明/灰度口径.md（决策记录 0018）。
        self.灰度比例表: dict[str, float] = {}

    def 设置激活(self, 能力id: str, 版本: str, 回退版本: str = "") -> None:
        """设置能力激活版本（含回退版本）。"""
        self.激活映射[能力id] = 版本
        if 回退版本:
            self.回退映射[能力id] = 回退版本

    def 当前激活版本(self, 能力id: str) -> str:
        return self.激活映射.get(能力id, "")

    def 可回滚版本(self, 能力id: str) -> list[str]:
        """当前激活版本的可回滚版本列表。"""
        版本 = self.激活映射.get(能力id, "")
        包 = self.版本注册表.获取版本(self._取包id(能力id), 版本)
        回退 = [版本]
        if 包 and 包.可回滚版本:
            回退 = list(包.可回滚版本) + [版本]
        elif 能力id in self.回退映射:
            回退 = [self.回退映射[能力id], 版本]
        return 回退

    def _取包id(self, 能力id: str) -> str:
        """按注册表已知包id反查能力id 所属包（最长前缀匹配，不再按 `split(".")[0]` 猜）。

        历史缺陷：此处返回能力id 首段，而注册表键是 `包id@版本`，首段恒不是包id
        （如 `支持库.后端.文字处理支持库.文档生成.生成文档` 首段是 `支持库`），
        于是 `可回滚版本` 与热切换第 10 步「旧版本进入弃用期」双双静默空转。

        命中顺序：① 版本包 `能力清单` 精确登记该能力id（真实口径下能力id 不是包id 前缀，
        如 `系统核心支持库.环境变量.列出环境变量` 属包 `支持库.后端.系统核心支持库.环境变量`，
        只能靠能力清单定位，与发布事务「激活映射无法唯一定位包」同一口径）；
        ② 能力id 以已知包id 打头时取最长者。都查不到返回空串——继续猜只会造出假包id。
        """
        候选 = ""
        for 包 in self.版本注册表.查询版本():
            if 能力id in 包.能力清单:
                return 包.包id
            if 包.包id and (能力id == 包.包id or 能力id.startswith(包.包id + ".")):
                if len(包.包id) > len(候选):
                    候选 = 包.包id
        return 候选

    def 热切换(self, *, 能力id: str, 新版本: str, 回退版本: str,
               影子启动结果: bool = 真, 健康检查结果: bool = 真,
               中立宿主验证: bool = 真, 项目装配验证: bool = 真,
               完整性校验: bool = 真, 依赖契约校验: bool = 真,
               灰度比例: float = 1.0) -> 热切换结果:
        """执行热切换；任一关键校验失败即自动回滚。"""
        结果 = 热切换结果()
        步骤 = 结果.步骤列表
        步骤.append(f"安装新版本 {能力id}@{新版本}")

        # 1-4. 安装后校验链
        if not 完整性校验:
            结果.问题列表.append("完整性校验失败")
        if not 依赖契约校验:
            结果.问题列表.append("依赖和契约校验失败")
        if not 中立宿主验证:
            结果.问题列表.append("中立宿主验证失败")
        if not 项目装配验证:
            结果.问题列表.append("项目装配验证失败")
        if 结果.问题列表:
            return self._回滚(结果, 能力id, 回退版本, "安装后校验未通过")

        步骤.append("完整性校验通过")
        步骤.append("依赖和契约校验通过")
        步骤.append("中立宿主验证通过")
        步骤.append("项目装配验证通过")

        # 5. 影子启动
        if not 影子启动结果:
            return self._回滚(结果, 能力id, 回退版本, "影子启动失败")
        步骤.append("影子启动成功")

        # 6. 健康检查
        if not 健康检查结果:
            return self._回滚(结果, 能力id, 回退版本, "健康检查失败")
        步骤.append("健康检查通过")

        # 7. 灰度运行（只记录比例，不按比例分流）
        # 历史缺陷一（父会话已复核）：本路径只把 灰度比例 写进步骤文案，从不写 self.灰度比例表，
        # 于是调用方读到「灰度运行（比例 10%）」的文案，路由侧却没有任何比例记录 → 实际全量切换
        # （调用方以为在灰度，最危险的一类静默偏差）。
        # 修一：与 `真实热切换` 第 6 步**同一写入口径**——键=能力id、值=比例，共用 self.灰度比例表，
        # 不另建一套表（两条路径的比例语义同为「该能力当前灰度比例」）。
        # 历史缺陷二（本轮取证）：`灰度比例表` **全仓 0 个读取者**，`调用路由` 只按
        # 「进程存在且状态为运行中」路由（见本类 `调用路由`）——比例被记录，但**没有任何执行者**，
        # 传 0.1 实际仍是 100% 全量切换。所以文案必须如实说明，不许让调用方以为已在按比例分流。
        # 本轮不新增任何路由口子（哲学：「都保留唯一一个口子」），只把话说明白。
        # 口径权威：运行核心/加载器/版本系统/说明/灰度口径.md（决策记录 0018）。
        self.灰度比例表[能力id] = 灰度比例
        if 灰度比例 < 1.0:
            步骤.append(
                f"灰度运行（已记录灰度比例 {灰度比例:.0%}；本平台当前由调用路由按进程状态路由，"
                "未实现按比例分流，本次实际为全量切换）"
            )
        else:
            步骤.append("灰度运行（全量 100%：比例已记录，无分流差异）")

        # 8. 切换激活映射
        原激活 = self.激活映射.get(能力id, "")
        self.激活映射[能力id] = 新版本
        self.回退映射[能力id] = 回退版本
        步骤.append(f"切换激活映射: {能力id} → {新版本}（全量生效，非按比例分流）")

        # 9. 观察期（灰度指标）——零样本不得被当成「指标正常」
        # 历史缺陷（父会话已复核）：判定对零样本恒为假，此处无条件输出「指标正常」；
        # 而喂数据的 记录灰度观测 全仓 0 调用方 → 这是恒真结论（未接线却报正常）。
        指标 = self.灰度指标表.setdefault(f"{能力id}@{新版本}", 灰度指标())
        if 指标.超过阈值():
            return self._回滚(结果, 能力id, 回退版本, "灰度指标超阈值", 原激活=原激活)
        if 指标.样本充足():
            步骤.append("观察错误和耗时（指标正常）")
        else:
            步骤.append(
                f"观察错误和耗时（样本 {指标.样本量()} 条 < 判定门槛 {最小判定样本量} 条，未做结论）"
            )

        # 10. 确认成功，旧版本弃用（按注册表已知包id 定位旧版本包；定位不到就不假装弃用）
        旧包id = self._取包id(能力id)
        if 旧包id:
            self.版本注册表.标记弃用(旧包id, 回退版本, "已弃用（进入弃用期）")
        结果.成功 = 真
        return 结果

    def _回滚(self, 结果: 热切换结果, 能力id: str, 回退版本: str, 原因: str,
              原激活: str = "") -> 热切换结果:
        """自动回滚：恢复激活映射、保留证据、不删除版本。"""
        结果.自动回滚 = 真
        self.激活映射[能力id] = 原激活 or 回退版本
        回滚记录 = {
            "回滚id": uuid.uuid4().hex[:16],
            "时间": time.strftime("%Y-%m-%d %H:%M:%S"),
            "能力id": 能力id, "恢复版本": 原激活 or 回退版本, "原因": 原因,
        }
        self.回滚记录表.append(回滚记录)
        if len(self.回滚记录表) > 1000:
            del self.回滚记录表[:-1000]
        结果.回滚记录 = f"{回滚记录['回滚id']} 恢复版本 {回滚记录['恢复版本']}（原因: {原因}）"
        return 结果

    def 记录灰度观测(self, 能力id: str, *, 成功: bool, 耗时毫秒: float = 0.0, 超时: bool = 假) -> list[str]:
        """记录一次灰度观测；返回超阈值问题列表（自动回滚由调用方执行）。

        返回空列表有两种含义，调用方必须自己区分（问 `灰度指标.样本充足()`）：
        「样本量不足 → 未做结论」或「样本达标且无超限 → 正常」。
        接线状态：本方法**全仓 0 调用方**（功能未接线），持久化观测走
        `灰度指标.py` 的 `灰度指标库.观测`（真实热切换第 7 步用的就是它）；
        所以进程内 灰度指标表 默认恒空，任何「指标正常」的结论都必须先过 `样本充足()`。
        """
        版本 = self.激活映射.get(能力id, "")
        指标 = self.灰度指标表.setdefault(f"{能力id}@{版本}", 灰度指标())
        指标.记录(成功=成功, 耗时毫秒=耗时毫秒, 超时=超时)
        return 指标.超过阈值()

    # ============ 第六阶段：真实提供者进程热切换 ============

    def 真实热切换(self, *, 能力id: str, 新版本: str, 回退版本: str,
                   灰度比例: float = 1.0, 状态可迁移: bool = 真,
                   指标库: Any = None, 工作器路径=None,
                   新进程启动失败: bool = 假, 新进程健康失败: bool = 假,
                   新进程最小调用失败: bool = 假) -> 热切换结果:
        """真实热切换：启动旧→启动新→健康检查→最小调用→影子→灰度→切换→排空→停止。

        新提供者失败不得影响旧提供者；切换失败自动恢复旧路由并保留证据。
        """
        结果 = 热切换结果()
        步骤 = 结果.步骤列表
        from 运行核心.加载器.提供者隔离.独立进程 import 独立进程

        # 1. 启动旧提供者（若未启动）
        旧版本 = self.激活映射.get(能力id, 回退版本)
        旧进程 = self.提供者进程表.get(能力id, {}).get(旧版本)
        if 旧进程 is None:
            旧进程 = 独立进程(f"{能力id}-{旧版本}", 工作器路径=工作器路径)
            self.提供者进程表.setdefault(能力id, {})[旧版本] = 旧进程
            成功, 消息 = 旧进程.启动()
            if not 成功:
                结果.问题列表.append(f"旧提供者启动失败: {消息}")
                return 结果
        步骤.append(f"旧提供者 {旧版本} 启动并健康检查通过")

        # 2. 启动新提供者
        新进程 = 独立进程(f"{能力id}-{新版本}", 工作器路径=工作器路径)
        self.提供者进程表.setdefault(能力id, {})[新版本] = 新进程
        if 新进程启动失败:
            return self._真实回滚(结果, 能力id, 旧进程, 新进程, "新提供者启动失败")
        成功, 消息 = 新进程.启动()
        if not 成功:
            return self._真实回滚(结果, 能力id, 旧进程, 新进程, f"新提供者启动失败: {消息}")
        步骤.append(f"新提供者 {新版本} 启动")

        # 3. 新提供者健康检查
        if 新进程健康失败 or not 新进程.健康检查():
            return self._真实回滚(结果, 能力id, 旧进程, 新进程, "新提供者健康检查失败")
        步骤.append("新提供者健康检查通过")

        # 4. 新提供者最小调用
        最小结果 = 新进程.调用(能力id="进程.最小操作", 参数={"名称": "最小调用"})
        if 新进程最小调用失败 or not 最小结果.成功:
            return self._真实回滚(结果, 能力id, 旧进程, 新进程, f"新提供者最小调用失败: {最小结果.错误说明}")
        步骤.append("新提供者最小调用成功")

        # 5. 影子调用（成功 + 失败样例）
        影子成功 = 新进程.调用(能力id="进程.最小操作", 参数={"名称": "影子调用"})
        影子失败 = 新进程.调用(能力id="进程.最小操作", 参数={"名称": "影子失败"})
        步骤.append(f"影子调用完成（成功 {影子成功.成功} / 失败样例 {影子失败.成功}）")

        # 6. 灰度路由（只记录比例，不按比例分流）
        # 同 `热切换` 第 7 步：`灰度比例表` **全仓 0 个读取者**，`调用路由` 只按进程状态路由 →
        # 这里的 灰度比例 也只是「记录调用方意图」，不产生任何分流效果；本次切换是全量的。
        # 不新增路由口子，只把话说准（口径权威：说明/灰度口径.md，决策记录 0018）。
        self.灰度比例表[能力id] = 灰度比例
        if 灰度比例 < 1.0:
            步骤.append(
                f"灰度路由（已记录灰度比例 {灰度比例:.0%}；本平台当前由调用路由按进程状态路由，"
                "未实现按比例分流，本次实际为全量切换）"
            )
        else:
            步骤.append("灰度路由（全量 100%：比例已记录，无分流差异）")

        # 7. 观察指标（持久化）——没接到指标库时不得声称「正常 / 已持久化」
        if 指标库 is not None:
            for _ in range(3):
                问题 = 指标库.观测(能力id=能力id, 版本=新版本, 成功=真, 耗时毫秒=10)
            if 问题:
                return self._真实回滚(结果, 能力id, 旧进程, 新进程, f"灰度指标超阈值: {问题[0]}")
            步骤.append("灰度观察指标正常（已持久化）")
        else:
            步骤.append("灰度观察未接线（未传指标库：无观测、未持久化，未做结论）")

        # 8. 正式切换：路由指向新进程
        self.路由表[能力id] = 新进程
        self.激活映射[能力id] = 新版本
        self.回退映射[能力id] = 回退版本
        步骤.append(f"正式切换: {能力id} 路由 → {新版本}（全量生效，非按比例分流）")

        # 9. 旧提供者排空（有状态检查）
        if not 状态可迁移:
            步骤.append("旧提供者状态不可迁移：并行运行 + 路由切换（不停止旧进程）")
        else:
            步骤.append("旧提供者排空完成（无活动请求）")

        # 10. 旧提供者停止（状态可迁移时）
        if 状态可迁移:
            停止结果, 停止消息 = 旧进程.优雅停止()
            if not 停止结果:
                return self._真实回滚(结果, 能力id, 新进程, 旧进程, f"旧提供者停止失败: {停止消息}", 已切换=真)
            步骤.append(f"旧提供者 {旧版本} 优雅停止")

        结果.成功 = 真
        return 结果

    def _真实回滚(self, 结果: 热切换结果, 能力id: str, 恢复进程: Any, 停止进程: Any,
                  原因: str, 已切换: bool = 假) -> 热切换结果:
        """真实切换失败回滚：恢复旧路由、停止新进程、保留证据、不删旧版本。"""
        结果.自动回滚 = 真
        import time as _时间, uuid as _uuid
        if 已切换:
            self.路由表[能力id] = 恢复进程
        else:
            self.路由表[能力id] = self.路由表.get(能力id) or 恢复进程
        if 停止进程 is not None and 停止进程 is not 恢复进程:
            try:
                停止进程.优雅停止()
            except Exception as 错误:  # 允许忽略，但留痕（哲学第 3 条）
                记录忽略('热切换._真实回滚', 错误)
        回滚记录 = {
            "回滚id": _uuid.uuid4().hex[:16],
            "时间": _时间.strftime("%Y-%m-%d %H:%M:%S"),
            "能力id": 能力id, "原因": 原因,
        }
        self.回滚记录表.append(回滚记录)
        if len(self.回滚记录表) > 1000:
            del self.回滚记录表[:-1000]
        结果.回滚记录 = f"{回滚记录['回滚id']}（原因: {原因}）"
        return 结果

    def 调用路由(self, 能力id: str, 参数: dict | None = None) -> Any:
        """经当前路由调用能力（新进程优先；无进程回退旧逻辑）。"""
        进程 = self.路由表.get(能力id)
        if 进程 is not None and 进程.状态 == "运行中":
            return 进程.调用(能力id="进程.最小操作", 参数=参数 or {})
        return None
