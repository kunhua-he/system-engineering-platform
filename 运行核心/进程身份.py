"""进程身份：进程id/启动指纹/项目id/所有者/实例id/最后心跳。

进程 id 被系统复用时不能误认成原进程：以 启动指纹（进程创建时间戳 +
实例随机数）区分，pid 相同但指纹不同即视为不同进程。

**时间源口径（审计 §9-B6）**：`最后心跳` 是内存内比较的**经过时间**量，
一律用单调时钟（`time.monotonic`）。改前用墙钟的两处后果：合盖 5 小时唤醒后，
`进程存活()` 算出的「距上次心跳」直接多出 5 小时 → 本进程被判失联。
落盘用的是 `启动指纹`（`time.time_ns()` = 墙钟纳秒，人能读、跨重启可比），
两条口径各司其职：**经过时间单调、落盘时间戳墙钟**。
"""

from __future__ import annotations

import os
import time
import uuid
from dataclasses import dataclass, field
from typing import Any

# 进程存活探测的跨平台实现只在 公共契约/运行时/ 收口层；本文件不裸调 os.kill。
from 公共契约.运行时 import 进程终止
from 公共契约.基础类型.逻辑类型 import 真, 假


@dataclass
class 进程身份:
    """一个进程的唯一身份。"""

    进程id: int = 0
    启动指纹: str = ""
    项目id: str = ""
    所有者: str = ""
    实例id: str = ""
    #: 最后一次心跳时刻，**单调时钟秒**（本进程时基，只用于内存内比较 =
    #: 经过时间口径，睡眠期间不走，故合盖唤醒不会被判失联）。
    #:
    #: 为什么必须钉住是 `monotonic`（审计 §9-B6 实测）：
    #: 1. 同一个 `进程身份` 对象可能被塞进多个进程（fork 后子进程继承父的
    #:    内存副本），若存墙钟，子进程会用**父进程那一刻**的墙钟与自己的墙钟
    #:    相减，算出的「距上次心跳」凭空多出两个进程的存续间隔 —— 那是活性判定的
    #:    假阴性，不是调度延迟；`monotonic` 是本机开机时基，两个进程同源同值，
    #:    相减恒为真实间隔（本仓实测：`mach_absolute_time()`，`adjustable=False`）。
    #: 2. 墙钟会被 NTP/改钟/合盖睡眠推进，任何一次推进都会把这颗心跳算成「很旧」。
    最后心跳: float = 0.0

    def 身份键(self) -> str:
        """跨进程唯一身份键（pid + 启动指纹）。"""
        return f"{self.进程id}:{self.启动指纹}"

    def 转字典(self) -> dict[str, Any]:
        """展示口径：心跳按**相对剩余秒**出，不出绝对值。

        为什么不出绝对值：`最后心跳` 是单调时钟量，跨进程/跨重启没有可比意义
        （另一个进程的 monotonic 时基与本进程只在本机同源；重启后归零），
        直接把原始数字抛给调用方就制造了一个「看着像 epoch 秒」的假事实。
        这里给出 `距上次心跳秒`（本进程视角的经过时间，单调口径），
        任何消费方拿到的都是可直接判断的量。
        """
        距上次心跳秒 = time.monotonic() - self.最后心跳 if self.最后心跳 else 0.0
        return {
            "进程id": self.进程id, "启动指纹": self.启动指纹, "项目id": self.项目id,
            "所有者": self.所有者, "实例id": self.实例id,
            "距上次心跳秒": round(max(0.0, 距上次心跳秒), 3),
            "身份键": self.身份键(),
        }


def 创建进程身份(*, 项目id: str = "", 所有者: str = "") -> 进程身份:
    """创建当前进程身份：pid + 启动指纹（进程创建时间 + 实例随机数）。"""
    启动指纹 = f"{time.time_ns():x}-{uuid.uuid4().hex[:8]}"
    return 进程身份(
        进程id=os.getpid(),
        启动指纹=启动指纹,
        项目id=项目id,
        所有者=所有者,
        实例id=uuid.uuid4().hex[:12],
        最后心跳=time.monotonic(),
    )


def 心跳(身份: 进程身份) -> None:
    """更新最后心跳（单调时钟口径）。"""
    身份.最后心跳 = time.monotonic()


def 心跳新鲜(身份: 进程身份, 心跳超时秒: float = 15.0) -> bool:
    """该身份的心跳是否新鲜（同一进程时基下比较；跨进程比较见下）。

    **跨进程语义说明**：单调时钟是**本机开机时基**，同一台机器上所有进程同源，
    故「A 进程写库的近心跳 vs B 进程的 monotonic」相减是有意义的；但**重启后**
    单调时钟归零，历史行的 `最后心跳` 会显得比当前 monotonic 大（差值为负），
    此时按「不新鲜」处理（判死回收会走 PID 探活兜底，不会误放行）。
    """
    距上次心跳 = time.monotonic() - float(身份.最后心跳 or 0.0)
    if 距上次心跳 < -心跳超时秒:
        return 假  # 负数跳变 = 跨重启/异常时基，宁可判不新鲜
    return 距上次心跳 <= 心跳超时秒


def 进程存活(身份: 进程身份, 心跳超时秒: float = 15.0) -> bool:
    """按心跳判断进程是否存活（pid 复用不误认：指纹一致才视为同进程）。"""
    return 心跳新鲜(身份, 心跳超时秒)


def 系统进程存在(进程id: int) -> bool:
    """查询操作系统中的进程是否仍存在，不发送终止信号。

    探测一律经跨平台收口层：原先按 0 号信号裸探活在 Windows 上不是探活，
    而是 ``TerminateProcess``——会把被查的进程真杀掉（且其它 OSError 还会逸出）。
    ``进程终止.进程存活`` 按平台选 WinAPI 或 POSIX 探活，非法入参返回 False 不抛。
    """
    if 进程id <= 0:
        return 假
    return 进程终止.进程存活(进程id)
