"""容量基线消费方：把「画像推导出的容量阈值」喂给 `启动监督器/容量基线.py`。

**为什么要这个文件**：`启动监督器/容量基线.py` 的 `声明基线(dict)` 早就有了，
但**没人给它一份按机器推出来的阈值** —— 阈值此前靠外部传写死值，等于「熔断器装了但没接线」。
本文件就是那条接线：档位层按可用内存推出的八阈值 → 直接喂给 `声明基线`。

**★纪律：本文件只做「消费」，一个字都不改 `容量基线.py`**（本批明确要求
「不要改 启动监督器/容量基线.py 的现有签名，只可新增消费方」）。
它用的都是既有公开入口：`容量基线(临时目录=…)`、`声明基线(dict)`、`实测采样()`、
`对比基线()` —— 不碰 `超限处理`（那是写类动作：停止接收/排空/写证据/熔断），
本文件**不触发**它。

**为什么放在 `运行核心/自适应选型/` 而不是 `启动监督器/`**：本层是「选型策略」，
它**读**档位、**喂**基线；`启动监督器` 是「执行保护」层。放在选型层，
依赖方向是「选型 → 启动监督器」，不反向，且不必往 `启动监督器` 里塞选型逻辑。

**只读边界**：`构造已声明基线()` 只构造对象并声明阈值（纯内存动作）；
`只读对账()` 额外真跑一次采样与比对，但**不写证据、不触发超限处理链** ——
与 `启动监督器/健康监督/实现/提供者.执行健康监督` 同一口径（那里也只跑
「声明基线 + 实测采样 + 对比基线」）。要触发熔断请由执行侧显式调 `超限处理`。
"""

from __future__ import annotations

from typing import Any, Mapping

from 公共契约.基础类型.逻辑类型 import 真, 假
from 运行核心.自适应选型.档位表 import 按画像定档位, 容量基线字段表


def 容量阈值(画像: Any, 部署形态: str = "") -> dict[str, float | int]:
    """按画像推导容量基线八阈值（**转调档位纯函数**，不在此重算第二套）。

    返回的字典键集与 `容量基线.必需基线字段` 逐字对应、值全为正数 ——
    因此可以直接交给 `声明基线`，不会因字段缺失/非正数被拒。
    """
    参数集 = 按画像定档位(画像, 部署形态 or "个人机")
    return dict(参数集.容量基线)


def 构造已声明基线(画像: Any, 部署形态: str = "", *,
                  临时目录: str = "") -> tuple[Any, bool, str, dict[str, float | int]]:
    """构造一个**已声明阈值**的 `容量基线` 实例（纯内存，不采样、不写盘、不起线程）。

    返回 `(实例, 声明是否通过, 声明说明, 阈值字典)`。
    声明不通过时不抛异常 —— 把 `说明` 原样带回，由调用方决定是拒绝启动还是降级，
    本文件不替调用方做决定。
    """
    from 启动监督器.容量基线 import 容量基线

    阈值 = 容量阈值(画像, 部署形态)
    实例 = 容量基线(临时目录=str(临时目录 or "").strip() or None)
    通过, 说明 = 实例.声明基线(阈值)
    return 实例, bool(通过), str(说明), 阈值


def 只读对账(画像: Any, 部署形态: str = "", *, 临时目录: str = "") -> dict[str, Any]:
    """只读对账：真跑一次采样并按推导出的阈值比对，返回结论与超限项。

    **不写证据、不改实例状态、不触发超限处理链**（与健康监督只读面同口径）。
    返回 `{成功, 阈值, 声明说明, 健康, 超限项, 采样}`；声明失败时 `成功=假` 并带说明。
    """
    实例, 通过, 说明, 阈值 = 构造已声明基线(画像, 部署形态, 临时目录=临时目录)
    if not 通过:
        return {"成功": 假, "阈值": 阈值, "声明说明": 说明, "健康": 假,
                "超限项": [], "采样": {}}
    采样 = 实例.实测采样()
    超限项 = 实例.对比基线()
    return {"成功": 真, "阈值": 阈值, "声明说明": 说明,
            "健康": not 超限项, "超限项": 超限项, "采样": 采样}


def 阈值与必需字段对账(阈值: Mapping[str, Any]) -> tuple[bool, str]:
    """判据：阈值字典的键集**是否**与容量基线必需字段逐字对应（供测试与接线自证）。

    这是「档位层与熔断层没接错」的**代码判据**：键集不一致会在 `声明基线` 处
    变成一句「基线缺少必需字段」，那种失败很难看出是接线问题；本函数把它提前、
    并点名缺哪个/多哪个。
    """
    键集 = set(str(键) for 键 in 阈值)
    必需 = set(容量基线字段表)
    缺 = sorted(必需 - 键集)
    多 = sorted(键集 - 必需)
    if 缺 or 多:
        return 假, f"阈值字段与容量基线必需字段不一致：缺 {缺}、多 {多}"
    return 真, f"阈值 {len(必需)} 项与容量基线必需字段逐字对应"


