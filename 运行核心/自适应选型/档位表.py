@dataclass(frozen=True)
class 档位参数集:
    """一组「写死并测过」的档位参数（内存/核数/图形三维坐标 → 参数）。

    `性能参数` 是标定/分化后的性能旋钮（首版全部等于现值）；
    `容量基线` 是按画像推导的八个阈值；
    `模型` 是模型实例数与内存预算推导结果。
    `选自档位` 与 `推导说明` 让「这个值是怎么来的」不必靠猜。
    """

    性能参数: dict[str, Any]
    容量基线: dict[str, float | int]
    模型: dict[str, Any]
    选自档位: 档位键
    推导说明: tuple[str, ...] = ()

    def 全部最终值(self) -> dict[str, Any]:
        """拍平后的「每个最终值」（供合并层记账与展示；键名全仓唯一）。"""
        拍平: dict[str, Any] = dict(self.性能参数)
        for 键, 值 in self.容量基线.items():
            拍平[键] = 值
        for 键, 值 in self.模型.items():
            拍平[f"模型{键}"] = 值
        return 拍平

    def 转字典(self) -> dict[str, Any]:
        """JSON 友好表示（诊断端点/启动日志的展示口径唯一在此）。"""
        return {
            "选自档位": self.选自档位.转字典(),
            "档位文本": self.选自档位.文本(),
            "性能参数": dict(self.性能参数),
            "容量基线": dict(self.容量基线),
            "模型": dict(self.模型),
            "推导说明": list(self.推导说明),
        }


def 内存档(画像: 硬件画像契约) -> tuple[int, str]:
    """物理内存 → 内存档（GB）与降级说明。

    规则：取 `内存档位表` 中**不大于**物理内存的最大档（低配与超高配都夹到端点档）。
    物理内存为 0（未知）→ 最小档 + 标记（fail-closed：不因未知而放开参数）。
    """
    GB数 = int(getattr(画像, "物理内存字节", 0) or 0) // (1024 ** 3)
    if GB数 <= 0:
        return 内存档位表[0], "物理内存未知，按最小内存档降级"
    档 = 内存档位表[0]
    for 候选 in 内存档位表:
        if GB数 >= 候选:
            档 = 候选
    return 档, ""


def 核数档(画像: 硬件画像契约) -> tuple[str, str]:
    """物理核数 → 核数档。

    优先用物理核数；取不到（0）时回落到逻辑核数并标记 —— **不冒充**：
    核数是档位坐标，用逻辑核数会高估（超线程），故回落时如实记名。
    两者都取不到 → 小核档 + 标记。
    """
    物理 = int(getattr(画像, "物理核数", 0) or 0)
    逻辑 = int(getattr(画像, "逻辑核数", 0) or 0)
    说明 = ""
    核数 = 物理
    if 核数 <= 0:
        核数 = 逻辑
        说明 = "物理核数未知，按逻辑核数进档（可能高估）"
    if 核数 <= 0:
        return 核数档_小核, "物理核数与逻辑核数均未知，按小核档降级"
    if 核数 <= 核数档位小核上限:
        return 核数档_小核, 说明
    if 核数 <= 核数档位中核上限:
        return 核数档_中核, 说明
    return 核数档_大核, 说明


def 图形档(画像: 硬件画像契约) -> str:
    """有无 Metal → 图形档。

    fail-closed：只有画像**明确为真**才算「有Metal」；未知/取不到一律「无Metal」
    （探不到被当成「有」会让档位向上冒进，与 `0045` 第 3 条相反）。
    """
    return 图形档_有Metal if bool(getattr(画像, "有Metal", 假)) else 图形档_无Metal


def 归一部署形态(部署形态: str) -> tuple[str, str]:
    """部署形态归一：不在 `部署形态域` 内的取值 → `部署形态缺省` + 说明（fail-closed）。"""
    文本 = str(部署形态 or "").strip()
