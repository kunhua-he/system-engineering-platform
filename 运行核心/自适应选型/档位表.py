"""硬件画像 → 离散档位 → 默认参数（决策记录 `0045` §11 零配置自适应 D2）。

**本模块是无副作用纯函数**：吃「不可变画像 + 部署形态」，吐「参数集」。
不读环境变量、不写盘、不起线程、不 import 适配层（画像由调用方按契约传入）。
这样测试可以直接**构造假画像**断言输出 —— 模拟的是**输入数据**，绝不触达
真实装配/写删路径（`0045` 第 2 条、本批红线）。

**★红线（本模块的第一约束）**：自适应**只决定性能档位**，**永远不决定安全边界**。
监听地址、鉴权开关/凭证/TLS、租户隔离与权限范围、允许路径表/沙箱边界、
数据目录/激活指针、部署形态 Profile、是否启用对外服务 —— 这些**一律不在**
本模块的参数集里，也**不许**经覆盖层（`三层合并`）注入（见 `安全边界字段名`
与 `校验不含安全边界`，反向测试见 `测试中心/运行核心/测试_硬件画像与档位.py`）。

**★首版标定口径（零行为变化）**：`档位表` 的**每一档**都刻意标定成与现值
**逐字段相同**（`标定参数集`）—— 即无论探测到什么画像、无论什么部署形态，
首版吐出的性能参数都与当前写死常量一模一样，接线不会改变任何行为。
差异化（按内存/核数/Metal 分档给出不同参数）留到后续批次**按实测数据**做，
且必须先把首版这套标定反向测试跑绿（`0045` 第 3 条「保守默认 + 预留余量」）。

**一个参数集里的两类内容**（别混）：

| 类 | 内容 | 首版口径 |
|---|---|---|
| 性能参数 | 网关工作线程/并发通道、超时执行器线程、任务池活动数与排队深度、非模型提供者池、有界队列/缓存/资源键表容量、调用超时、模型上下文长度与单实例占用 | **标定 = 现值**（每档相同） |
| 容量阈值与模型预算 | 容量基线八个阈值（内存高水位按**可用内存保守比例 + 固定 headroom**）、可开模型实例数/内存预算 | **按画像推导**（本批新增能力，无现值可比；判据=不损害整机稳定前提下的合理高水位） |

**两类的差别要在验收入口里看明白**：性能参数的「零行为变化」由
`测试_硬件画像与档位` 逐字段对账现值守住；容量阈值没有现值，改由
「保守不变量」守住（水位恒小于可用内存、各项恒为正、同一画像输出恒定）。

**为什么容量阈值按「可用内存」而不是「物理内存」**：容量基线的内存高水位是给
**本进程**（RSS 采样）用的上限，而个人 Mac 非独占 —— 别的进程随时会用掉大部分内存。
按物理内存推会把基线放到机器已经吃满时的实际水位之上，等于没护栏；按可用内存
配合固定预留，才是「不损害整机稳定前提下的合理高水位」（`0045` 第 3 条）。

**为什么水位还要有下限比例**：可用内存极小时（机器正在吃紧），
`× 保守比例 − 固定预留` 会算出负数或接近零，把正常进程误判成「超限」，
超限处理链一路熔断到拒绝服务 —— 那是把内存压力放大成停机。
故水位夹在 `可用内存 × 下限比例` 与 `可用内存 × 硬上限比例` 之间：
既保底、又任何情况下不超过可用内存的一半多一点。
"""

