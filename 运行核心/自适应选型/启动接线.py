"""自适应选型的启动接线与可见性（决策记录 `0045` §11 D3：三层覆盖、来源可见）。

**本文件只做「接线」三件事，不重写任何判定**：

1. `探测并定档(用户配置=None)`：真跑一次硬件画像探针 → 走 `三层合并`
   → 返回「探测到的画像 / 选中档位 / 每个最终值 / 由哪层决定」的人读清单与结构化结果。
2. `启动自适应摘要()`：把上面那份清单拍成启动日志用的**多行文本**。
3. `诊断自适应载荷()`：把同一份结果拍成诊断端点用的 **JSON 友好字典**
   （键名与清单同源，不另起一套）。

**为什么单独一个文件而不是改 `启动运行核心网关.py`**：网关启动脚本是**装配编排**，
它的职责是「把东西拉起来」；「画像怎么读、档位怎么定、值由哪层决定」属**选型策略**。
两者分开后，选型策略可以被诊断端点、被测试、被别的入口复用，
而启动脚本只调一行 —— 主入口只调度、不堆业务逻辑（`AGENTS.md` 开发偏好）。

**展示口径的唯一性**：清单与载荷都来自 `三层合并.展示三层结果()` 与
`三层结果.转字典()`，本文件**不自己拼字符串**。新增一项参数时，展示自动跟着变，
不存在「改了参数忘了改日志」这种漂移。

**只读性**：本文件不写盘、不起线程、不读环境变量（用户覆盖由调用方显式传入），
因此可以安全地在诊断端点里按需调用（画像与档位表各自有缓存，重复调用不重复采样）。
"""

from __future__ import annotations

from typing import Any, Mapping

from 公共契约.基础类型.逻辑类型 import 真
from 运行核心.自适应选型.三层合并 import 三层合并, 三层结果, 展示三层结果

#: 启动摘要的固定首行（启动脚本与诊断端点共用，便于日志检索与逐行 diff）
启动摘要标题 = "零配置自适应：硬件画像 → 离散档位 → 默认参数"


def 探测并定档(用户配置: Mapping[str, Any] | None = None,
              部署形态: str = "") -> tuple[三层结果, list[str]]:
    """真跑一次「探测画像 → 三层合并」；返回 `(三层结果, 人读清单)`。

    **画像来自真探针**（`支持库/适配层/硬件画像探针.读取硬件画像`），
    含图形加速（Metal）—— 该步有进程内缓存，重复调用不重复跑 `system_profiler`。

    `部署形态` 空串 ⇒ 由档位层按缺省归一（并记名）；
    `用户配置` 是最高优先级覆盖，命中安全边界会被**整键拒收并点名**
    （拒收明细在 `三层结果.拒收表`，也出现在清单里 —— 绝不悄悄没生效）。
    """
    from 支持库.适配层.硬件画像探针 import 读取硬件画像

    画像 = 读取硬件画像(含图形加速=真)
    结果 = 三层合并(画像, 部署形态, 用户配置=用户配置)
    return 结果, 展示三层结果(结果)


def 启动自适应摘要(用户配置: Mapping[str, Any] | None = None,
                  部署形态: str = "") -> str:
    """启动日志用的多行摘要（标题 + 画像 + 档位 + 逐键最终值与决定层 + 推导说明）。"""
    结果, 清单 = 探测并定档(用户配置, 部署形态)
    return "\n".join([启动摘要标题, *清单])


def 诊断自适应载荷(用户配置: Mapping[str, Any] | None = None,
                  部署形态: str = "") -> dict[str, Any]:
    """诊断端点用的 JSON 友好载荷：画像 / 选中档位 / 每个最终值的决定层 / 拒收明细。

    结构与 `三层结果.转字典()` **同源**（同一个键集），额外带上标题与档位文本，
    便于端点直接序列化返回；不在这里重算任何值。
    """
    结果, _清单 = 探测并定档(用户配置, 部署形态)
    载荷 = 结果.转字典()
    载荷["标题"] = 启动摘要标题
    return 载荷


__all__ = [
    "启动摘要标题",
    "探测并定档",
    "启动自适应摘要",
    "诊断自适应载荷",
]
