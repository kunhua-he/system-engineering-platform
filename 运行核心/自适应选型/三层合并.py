"""三层合并与来源可见（决策记录 `0045` §11 D3；第 5 条「三层覆盖、来源可见」）。

**三层与优先级（唯一口径）**：

| 层 | 来源 | 本模块的角色 |
|---|---|---|
| ① 内置档位 | `按画像定档位(画像, 部署形态)` | 基线，**总是**参与 |
| ② 部署 Profile | `部署形态覆盖表[部署形态]` | 只覆盖它显式声明的键 |
| ③ 用户显式配置 | 调用方传入的 `用户配置` 字典 | 最高优先级，只覆盖它显式声明的键 |

合并结果里**每个最终值都带「由哪层决定」**（`决定层`），
`展示三层结果()` 把「探测到的画像 / 选中档位 / 每个最终值 / 由哪层决定」拍成
一张人读清单 —— 启动日志与诊断端点**共用这一份**展示口径，不各写一套。

**★红线（本模块的第二约束，第一约束在 `档位表.py`）**：
`校验覆盖键安全(层名, 覆盖)` 是**唯一的覆盖准入判据** —— 第②③层的键命中
`档位表.安全边界字段名` 一律**拒收并点名**，绝不静默忽略。
理由（`0045` 表 C）：监听地址、鉴权、TLS、权限范围、允许路径表、数据目录、
部署形态 Profile、是否启用对外服务这些**永远不能**被「配置覆盖」这条通路放开 ——
一旦覆盖层能写它们，「零配置自适应」就变成了「零配置改安全边界」的后门。
拒收而不是忽略，是为了让**尝试放开安全边界的人拿到明确报错**，而不是以为改生效了。

**为什么不做「层内白名单」而只做黑名单**：白名单会随性能旋钮增加而长期失修
（新增一个旋钮就覆盖不了，且没人知道为什么）。黑名单只有一份、只随安全边界变化，
且它的**失效模式是显式报错**（fail-closed），符合本项目「参数可自动、边界绝不自动」的口径。

**层名是机器判据**：`层名_内置` / `层名_部署Profile` / `层名_用户配置` 三个常量
同时用于记账与拒收报文；判据只比对这三个常量，**不比对文案**（见任务记忆包
「文案当判据铁律」）。
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping

from 公共契约.基础类型.逻辑类型 import 真, 假
from 运行核心.自适应选型.档位表 import (
    部署形态覆盖表,
    安全边界字段名,
    按画像定档位,
    档位参数集,
    校验不含安全边界,
)

#: 三层名（**机器判据**：记账、拒收报文、展示都只认这三个常量）
层名_内置 = "内置档位"
层名_部署Profile = "部署Profile"
层名_用户配置 = "用户显式配置"
层名表 = (层名_内置, 层名_部署Profile, 层名_用户配置)


@dataclass(frozen=True)
class 来源记录:
    """一个最终值的「由哪层决定」记账。"""

    最终值: Any
    决定层: str
    被覆盖的层: tuple[str, ...] = ()

    def 转字典(self) -> dict[str, Any]:
        return {"最终值": self.最终值, "决定层": self.决定层,
                "被覆盖的层": list(self.被覆盖的层)}


@dataclass(frozen=True)
class 三层结果:
    """三层合并的完整结果：画像 / 档位 / 每个最终值的来源记账 / 拒收明细。"""

    档位: 档位参数集
    来源表: dict[str, 来源记录]
    拒收表: dict[str, tuple[str, ...]]
    画像展示: dict[str, Any]

    def 最终值表(self) -> dict[str, Any]:
        """`{键: 最终值}`（不含来源信息，供只需要值的调用方）。"""
        return {键: 记录.最终值 for 键, 记录 in self.来源表.items()}

    def 转字典(self) -> dict[str, Any]:
        return {
            "画像": dict(self.画像展示),
            "选中档位": self.档位.选自档位.转字典(),
            "档位文本": self.档位.选自档位.文本(),
            "最终值": {键: 记录.转字典() for 键, 记录 in sorted(self.来源表.items())},
            "拒收表": {层: list(键表) for 层, 键表 in self.拒收表.items()},
            "推导说明": list(self.档位.推导说明),
        }


def 校验覆盖键安全(层名: str, 覆盖: Mapping[str, Any] | None) -> tuple[bool, str, tuple[str, ...]]:
    """覆盖准入判据：该层的键**是否**越过了安全边界（`0045` 表 C）。

    返回 `(通过, 说明, 越权键表)`。命中 `安全边界字段名` 即不通过，
    说明里**点名具体键**（报「哪个字段被拒」，不是笼统失败）。
    `覆盖` 为空/None 视为通过（空覆盖不构成风险）。
    """
    越权 = tuple(sorted(str(键) for 键 in (覆盖 or {}) if str(键) in 安全边界字段名))
    if 越权:
        return 假, (f"「{层名}」覆盖含安全边界字段，已整键拒收"
                    f"（自适应只决定性能档位，安全边界绝不自动/绝不覆盖）: {list(越权)}"), 越权
    return 真, f"「{层名}」覆盖不含安全边界字段", ()


def _画像展示(画像: Any) -> dict[str, Any]:
    """画像的展示口径：优先用画像自带的 `转字典()`（探针是唯一事实源），
    没有该方法的（测试用的极简假画像）退化为「按属性名取」，**不伪造**缺失字段。"""
    转字典 = getattr(画像, "转字典", None)
    if callable(转字典):
        try:
            结果 = 转字典()
            if isinstance(结果, dict):
                return dict(结果)
        except Exception:  # 画像自述展示失败不影响合并：退化为属性读取
            pass
    展示: dict[str, Any] = {}
    for 名 in ("芯片", "逻辑核数", "物理核数", "物理内存字节", "可用内存字节",
               "有Metal", "金属版本", "磁盘可用字节"):
        if hasattr(画像, 名):
            展示[名] = getattr(画像, 名)
    return 展示


def 三层合并(画像: Any, 部署形态: str = "", *,
            用户配置: Mapping[str, Any] | None = None) -> 三层结果:
    """三层合并：内置档位 ← 部署 Profile ← 用户显式配置。

    参数：
        `画像`：不可变画像（真实画像来自 `支持库/适配层/硬件画像探针`；
            测试直接传假画像 —— 模拟的是**输入数据**，不触达真实装配/写删路径）。
        `部署形态`：空串表示「按缺省处理」（档位层会归一并记名）。
        `用户配置`：最高优先级的显式覆盖；键命中安全边界一律**整键拒收**。

    返回 `三层结果`（每个最终值都带决定层）。

    **拒收表是显式结果的一部分**：越权的覆盖不会「悄悄没生效」，
    调用方（启动脚本/诊断端点）必须能看到自己被拒了哪几个键。
    """
    档位 = 按画像定档位(画像, 部署形态 or 部署形态缺省形态())
    拒收表: dict[str, tuple[str, ...]] = {}

    档位通过, 档位说明 = 校验不含安全边界(档位.全部最终值())
    if not 档位通过:
        # 内置档位自己越权 ⇒ 是代码缺陷（档位表写进了安全字段），显名上报而不是继续合并。
        拒收表[层名_内置] = tuple(档位说明.split(":")[-1].strip().strip("[]").split(", "))

    来源表: dict[str, 来源记录] = {
        键: 来源记录(最终值=值, 决定层=层名_内置)
        for 键, 值 in 档位.全部最终值().items()
    }

    # ② 部署 Profile
    Profile = dict(部署形态覆盖表.get(档位.选自档位.部署形态, {}) or {})
    通过, _说明, 越权 = 校验覆盖键安全(层名_部署Profile, Profile)
    if not 通过:
        拒收表[层名_部署Profile] = 越权
        Profile = {键: 值 for 键, 值 in Profile.items() if 键 not in 安全边界字段名}
    来源表 = _套用覆盖(来源表, Profile, 层名_部署Profile)

    # ③ 用户显式配置（最高优先级）
    用户 = dict(用户配置 or {})
    通过, _说明, 越权 = 校验覆盖键安全(层名_用户配置, 用户)
    if not 通过:
        拒收表[层名_用户配置] = 越权
        用户 = {键: 值 for 键, 值 in 用户.items() if 键 not in 安全边界字段名}
    来源表 = _套用覆盖(来源表, 用户, 层名_用户配置)

    return 三层结果(档位=档位, 来源表=来源表, 拒收表=拒收表,
                    画像展示=_画像展示(画像))


def _套用覆盖(来源表: dict[str, 来源记录], 覆盖: Mapping[str, Any],
            层名: str) -> dict[str, 来源记录]:
    """把一层的覆盖套到记账表上：命中已有键 → 更新值并追加「被覆盖的层」。

    覆盖里**新出现**的键（内置档位没有的旋钮）也照收并记账为「由该层决定」——
    这样用户能加新旋钮而不必先改档位表；安全边界已在 `校验覆盖键安全` 处拦掉。
    """
    新表 = dict(来源表)
    for 键, 值 in 覆盖.items():
        已有 = 新表.get(键)
        if 已有 is None:
            新表[键] = 来源记录(最终值=值, 决定层=层名)
        else:
            新表[键] = 来源记录(最终值=值, 决定层=层名,
                                被覆盖的层=已有.被覆盖的层 + (已有.决定层,))
    return 新表


def 部署形态缺省形态() -> str:
    """缺省部署形态（转调 `档位表.部署形态缺省`，不在此重写第二份默认值）。"""
    from 运行核心.自适应选型.档位表 import 部署形态缺省

    return 部署形态缺省


def 展示三层结果(结果: 三层结果) -> list[str]:
    """把三层结果拍成**人读清单**（启动日志与诊断端点共用的唯一展示口径）。

    行序固定：画像 → 选中档位 → 逐键最终值（按键名排序）→ 拒收明细 → 推导说明。
    排序是为了两次启动的日志可以逐行 diff（可复现性，`0045` 第 1 条）。
    """
    行: list[str] = ["探测到的硬件画像:"]
    for 键 in sorted(结果.画像展示):
        行.append(f"  画像.{键} = {结果.画像展示[键]}")
    行.append(f"选中档位: {结果.档位.选自档位.文本()}")
    行.append("最终参数与决定层:")
    for 键 in sorted(结果.来源表):
        记录 = 结果.来源表[键]
        覆盖 = f"（覆盖了 {'/'.join(记录.被覆盖的层)}）" if 记录.被覆盖的层 else ""
        行.append(f"  {键} = {记录.最终值}　← {记录.决定层}{覆盖}")
    if 结果.拒收表:
        行.append("被拒收的覆盖（安全边界，绝不生效）:")
        for 层, 键表 in sorted(结果.拒收表.items()):
            行.append(f"  {层}: {list(键表)}")
    if 结果.档位.推导说明:
        行.append("推导说明:")
        for 说明 in 结果.档位.推导说明:
            行.append(f"  {说明}")
    return 行


