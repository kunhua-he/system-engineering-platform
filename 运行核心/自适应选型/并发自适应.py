"""并发自适应：**看真实系统性能 → 记录 → 动态调整**（2026-09-21 华哥裁决）。

## 为什么有本模块

华哥原话：

> 「你要不在档位这里，加上日志？直接看我系统性能啊，记录一下，然后动态调整啊，
>   写死的基本上电脑性能一点都拉不满。」

上下文（现场实测）：平台早有硬件档位系统（`档位表.按画像定档位`），但网关侧从没接过它 ——
`网关核心` 一直 `限流器()` 无参构造，吃默认 `单维度并发=40`。本机 M3 Ultra／32 核／96GB，
60 路并发实测「200×40 + 429×20」⇒ **通过数正好卡在 40**，机器性能远未用上。

本模块把「**实测 → 记录 → 调整**」做成闭环的**取值部分**：

1. **实测**：读硬件画像（核数/内存）+ 读真实系统负载（`os.getloadavg()`，标准库零依赖）；
2. **记录**：每次给出并发结论时产出一条**结构化记录**（含全部输入与理由），落盘成 JSONL 供事后核对；
3. **调整**：按「核数档给出基线，再按当前负载率收缩」算出本次并发值。

## 三条口径（与平台既有裁决一致）

- **离散、可复现**（`0045` 第 1 条：不做 PID / 机器学习式实时调参）：基线取**核数档**离散值，
  负载只做**比例收缩**（负载高就少给、负载低就给满），不做连续黑盒调参。
  同一 (画像, 负载率) 输入恒得同一输出 —— 可单测、可复现。
- **宁欠勿过**（`0045` 第 3 条「保守默认 + 预留余量」）：负载偏高时**收缩但不低于下限**，
  下限保证「机器再忙也不至于一个都跑不了」。
- **并发旋钮不是安全边界**：本模块**只**产出并发类数值，绝不产出也不允许注入
  监听地址/凭证/路径表等任何安全字段（`档位表.安全边界字段名` 是唯一名单）。

## 负载率为什么用「1 分钟负载 / 逻辑核数」

`os.getloadavg()` 是 POSIX 标准接口，返回过去 1/5/15 分钟的可运行进程平均数。
除以逻辑核数得到 `0..1` 的「相对饱和度」：`<0.5` 算空闲、`>=0.9` 算吃紧。
用它而不是 CPU 瞬时占用率：负载是**内核维护的均值**，不会因一次采样抖动给出忽高忽低的结论。

## 落盘位置与失败口径

记录落 `<受管缓存根>/并发自适应记录.jsonl`（经 `运行缓存.解析运行缓存根`，**不裸拼路径**）。
落盘失败**不影响并发取值**（记录是观测面，不是判据面）—— 但会返回失败原因，
由调用方决定是否打印，绝不静默吞掉。
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from 公共契约.基础类型.逻辑类型 import 假, 真

# ── 基线：按核数档给出「这台机器最多能给多少并发」─────────────────────────
# 与 `档位表.并发旋钮按核数档` **同源同值**（那里是档位表的槽位，这里是动态度量），
# 两处必须一致：档位表给的是「静态期望」，本模块给的是「当前该给多少」。
基线并发按核数: tuple[tuple[int, int], ...] = (
    # (物理核数上限, 基线并发)
    (8, 64),      # 小核档：保持平台现值，低端机行为不变
    (16, 128),    # 中核档
    (1 << 30, 256),  # 大核档（含本机 32 核）
)

# ── 负载率阈值与收缩比 ────────────────────────────────────────────────────
空闲负载率 = 0.50      # 低于此视为机器空闲：给满基线
吃紧负载率 = 0.90      # 高于此视为机器吃紧：给到下限
轻度收缩比 = 0.75      # 空闲..吃紧之间：线性插值到基线的这个比例
下限比 = 0.25          # 任何情况下不低于 基线 × 此比例（保底，别一个都跑不了）
硬下限 = 8             # 绝对下限（再少就连基本并发都没有了）

默认记录名 = "并发自适应记录.jsonl"
记录保留条数 = 200     # 有界：只保留最近 N 条（文件超限即裁剪，见 `_裁剪记录`）


@dataclass
class 并发结论:
    """一次并发取值的完整结论（**含全部输入与理由**，供记录与核对）。"""

    并发值: int
    物理核数: int = 0
    逻辑核数: int = 0
    负载1分钟: float = 0.0
    负载5分钟: float = 0.0
    负载率: float = 0.0
    基线: int = 0
    是否收缩: bool = False
    画像可用: bool = True
    理由: str = ""
    取数时间: float = field(default_factory=time.time)

    def 转字典(self) -> dict[str, Any]:
        return {
            "并发值": self.并发值,
            "物理核数": self.物理核数,
            "逻辑核数": self.逻辑核数,
            "负载1分钟": round(self.负载1分钟, 3),
            "负载5分钟": round(self.负载5分钟, 3),
            "负载率": round(self.负载率, 3),
            "基线": self.基线,
            "是否收缩": self.是否收缩,
            "画像可用": self.画像可用,
            "理由": self.理由,
            "取数时间": time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(self.取数时间)),
        }


def 基线并发(物理核数: int) -> int:
    """按物理核数取基线并发（**纯函数**，可单测）。"""
    for 上限, 基线 in 基线并发按核数:
        if 物理核数 <= 上限:
            return 基线
    return 基线并发按核数[-1][1]


def 按负载收缩(基线: int, 负载率: float) -> tuple[int, bool, str]:
    """按负载率收缩基线，返回 `(并发值, 是否收缩, 理由)`（**纯函数**，可单测）。

    分段（离散，不做 PID）：
    - `负载率 <= 空闲负载率`：给满基线；
    - `空闲..吃紧`：线性收缩到 `基线 × 轻度收缩比`；
    - `>= 吃紧负载率`：给到 `max(基线 × 下限比, 硬下限)`。
    """
    下限 = max(int(基线 * 下限比), 硬下限)
    if 负载率 <= 空闲负载率:
        return 基线, 假, f"机器空闲（负载率 {负载率:.2f} ≤ {空闲负载率}）⇒ 给满基线 {基线}"
    if 负载率 >= 吃紧负载率:
        return 下限, 真, f"机器吃紧（负载率 {负载率:.2f} ≥ {吃紧负载率}）⇒ 收缩到下限 {下限}"
    # 线性插值：空闲端 = 基线，吃紧端 = 基线 × 轻度收缩比
    比例 = (负载率 - 空闲负载率) / (吃紧负载率 - 空闲负载率)
    目标 = 基线 - (基线 - int(基线 * 轻度收缩比)) * 比例
    值 = max(int(目标), 下限)
    return 值, 真, (f"机器有负载（负载率 {负载率:.2f}，介于 {空闲负载率}..{吃紧负载率}）"
                     f"⇒ 按比例收缩到 {值}（下限 {下限}）")


def 读负载率(逻辑核数: int) -> tuple[float, float, float]:
    """读真实系统负载，返回 `(1分钟, 5分钟, 负载率)`；平台不支持时回全 0。

    `os.getloadavg()` 在无此接口的平台（Windows 类）抛 `OSError` ——
    按「读不到就当空闲」处理是**错的**（那会盲目放大），故回 0 由调用方走
    「画像不可用即回落默认」的分支（见 `并发取值`）。
    """
    try:
        一, 五, _十五 = os.getloadavg()
    except (OSError, AttributeError):
        return 0.0, 0.0, 0.0
    核 = max(int(逻辑核数), 1)
    return 一, 五, max(一 / 核, 0.0)


def 并发取值(*, 读画像: Any = None, 读负载: Any = None) -> 并发结论:
    """**唯一取值入口**：实测画像与负载 → 并发结论（不落盘；落盘见 `记录`）。

    `读画像` / `读负载` 可注入（测试用假数据，不碰真实系统）；缺省用真实探针。
    画像不可用时**回落平台现值 64**（首版标定值），并如实标注「画像不可用」。
    """
    if 读画像 is None:
        from 支持库.适配层.硬件画像探针 import 读取硬件画像
        读画像 = 读取硬件画像
    if 读负载 is None:
        读负载 = 读负载率

    物理核数 = 逻辑核数 = 0
    画像可用 = True
    try:
        画像 = 读画像(含图形加速=假)
        物理核数 = int(getattr(画像, "物理核数", 0) or 0)
        逻辑核数 = int(getattr(画像, "逻辑核数", 0) or 0)
        画像可用 = bool(getattr(画像, "全部取到", True))
    except Exception:
        画像可用 = False

    if not 画像可用 or 物理核数 <= 0:
        return 并发结论(
            并发值=64, 画像可用=False,
            理由="硬件画像不可用 ⇒ 回落平台现值 64（fail-closed，探测不到绝不放大）")

    一, 五, 率 = 读负载(逻辑核数 or 物理核数)
    基线 = 基线并发(物理核数)
    值, 收缩, 理由 = 按负载收缩(基线, 率)
    return 并发结论(
        并发值=值, 物理核数=物理核数, 逻辑核数=逻辑核数,
        负载1分钟=一, 负载5分钟=五, 负载率=率, 基线=基线,
        是否收缩=收缩, 画像可用=True, 理由=理由)


def 记录目录() -> Path:
    """记录落点目录（经唯一解析器取受管缓存根，**不裸拼** `工程缓存`）。"""
    from 公共契约.运行时.运行缓存 import 解析运行缓存根

    系统根 = Path(__file__).resolve().parents[2]
    return 解析运行缓存根(系统根)


def 记录(结论: 并发结论, *, 目录: Path | None = None) -> tuple[bool, str]:
    """把一次并发结论**追加**到 JSONL 记录；返回 `(是否成功, 说明)`。

    有界：写入后若条数超 `记录保留条数`，裁掉最旧的（**只保留最近 N 条**）。
    任何失败都**返回原因而不抛出** —— 记录是观测面，不能因为它坏掉就阻断启动。
    """
    try:
        基 = Path(目录) if 目录 is not None else 记录目录()
        基.mkdir(parents=True, exist_ok=True)
        路径 = 基 / 默认记录名
        with 路径.open("a", encoding="utf-8") as 文件:
            文件.write(json.dumps(结论.转字典(), ensure_ascii=False) + "\n")
        _裁剪记录(路径)
        return 真, str(路径)
    except OSError as 错误:
        return 假, f"并发自适应记录写入失败：{错误}"


def _裁剪记录(路径: Path) -> None:
    """只保留最近 `记录保留条数` 条（有界；平台纪律「所有日志必须有界」）。"""
    try:
        行表 = [行 for 行 in 路径.read_text(encoding="utf-8").splitlines() if 行.strip()]
    except OSError:
        return
    if len(行表) <= 记录保留条数:
        return
    路径.write_text("\n".join(行表[-记录保留条数:]) + "\n", encoding="utf-8")


def 并发参数组(结论: 并发结论) -> dict[str, dict[str, int]]:
    """按各组件**真实参数名**分组返回（**名字不一样，不可混传**）。

    - `限流器`：`最大并发请求` / `单维度并发`（`限流器.__init__` 的关键字）；
    - `网关`：`并发上限`（`本地网关服务器` 配置项名）。

    实测踩过：把 `并发上限` 传给 `限流器` 会 `TypeError: unexpected keyword argument`，
    网关直接起不来 —— 故本函数是「谁用哪个名字」的唯一落点。
    """
    值 = int(结论.并发值)
    return {
        "限流器": {"最大并发请求": 值, "单维度并发": 值},
        "网关": {"并发上限": 值},
    }
