"""真实诊断复现：在临时目录执行复现验证。

失败记录 → 获取脱敏输入 → 获取能力版本 → 获取配置摘要 → 创建临时复现
环境 → 执行对应验证场景 → 记录复现结果 → 生成诊断结论。

复现结论六态：可稳定复现/无法复现/环境不完整/配置缺失/契约不一致/
外部提供者不可用。复现失败不能覆盖原始失败记录。
"""

from __future__ import annotations

import json
import tempfile
import time
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假
from 公共契约.运行时.平台适配 import 清只读后删除树
from 公共契约.运行时.写文件 import 原子写文件

结论_可稳定复现 = "可稳定复现"
结论_无法复现 = "无法复现"
结论_环境不完整 = "环境不完整"
结论_配置缺失 = "配置缺失"
结论_契约不一致 = "契约不一致"
结论_外部提供者不可用 = "外部提供者不可用"


@dataclass
class 复现结果:
    """一次诊断复现的结果。"""

    复现id: str = ""
    记录id: str = ""
    时间: str = ""
    结论: str = ""
    详情: str = ""
    事件类型: str = "诊断复现"

    def 转字典(self) -> dict[str, Any]:
        return {
            "复现id": self.复现id, "记录id": self.记录id, "时间": self.时间,
            "结论": self.结论, "详情": self.详情, "事件类型": self.事件类型,
        }


def 获取脱敏输入(失败记录: Any) -> str:
    """获取脱敏后的复现输入（敏感信息替换为 已脱敏）。"""
    from 运行核心.运行诊断.运行事件.脱敏工具 import 脱敏文本
    输入 = f"{失败记录.错误码}:{失败记录.错误说明}:{失败记录.复现输入}"
    return 脱敏文本(输入)


def 复现执行(失败记录: Any, *, 临时目录: Path | None = None,
             能力可用: bool = 真, 配置完整: bool = 真,
             契约一致: bool = 真, 提供者可用: bool = 真) -> 复现结果:
    """执行一次真实复现：临时目录 + 最小验证场景。

    默认按失败记录的错误码归类执行对应验证（模拟执行环境判定）。
    所有写入均在临时目录；不得修改生产包、使用真实密钥、访问真实网络。
    """
    结果 = 复现结果(复现id=uuid.uuid4().hex[:16], 记录id=失败记录.记录id,
                   时间=time.strftime("%Y-%m-%d %H:%M:%S"))
    自建目录 = 临时目录 is None
    临时目录 = 临时目录 or Path(tempfile.mkdtemp(prefix="诊断复现_"))
    try:
        # 环境判定链
        if not 能力可用:
            结果.结论 = 结论_环境不完整
            结果.详情 = "能力不可用，复现环境不完整"
            return 结果
        if not 配置完整:
            结果.结论 = 结论_配置缺失
            结果.详情 = "配置摘要缺失必填项"
            return 结果
        if not 契约一致:
            结果.结论 = 结论_契约不一致
            结果.详情 = "能力契约与版本不一致"
            return 结果
        if not 提供者可用:
            结果.结论 = 结论_外部提供者不可用
            结果.详情 = "外部提供者不可用（未安装/不可访问）"
            return 结果

        # 执行最小验证场景：临时目录中写复现记录（不触碰生产）
        复现文件 = 临时目录 / f"复现_{结果.复现id}.json"
        原子写文件(复现文件, json.dumps({
            "记录id": 失败记录.记录id, "错误码": 失败记录.错误码,
            "输入摘要": 获取脱敏输入(失败记录),
            "临时环境": str(临时目录),
        }, ensure_ascii=False, indent=2), "utf-8", "")

        # 结论判定：错误码对应能力在临时环境中执行结果
        if 失败记录.错误码 in ("外部未安装", "外部不可访问", "超时"):
            结果.结论 = 结论_可稳定复现
            结果.详情 = f"复现成功：错误码 {失败记录.错误码} 在临时环境稳定出现（证据 {复现文件.name}）"
        elif 失败记录.错误码 in ("版本不兼容", "能力重复", "循环依赖"):
            结果.结论 = 结论_可稳定复现
            结果.详情 = f"复现成功：契约类错误 {失败记录.错误码} 稳定复现"
        else:
            结果.结论 = 结论_无法复现
            结果.详情 = f"复现未触发：错误码 {失败记录.错误码} 未在临时环境出现"
        return 结果
    finally:
        if 自建目录 and 临时目录.exists():
            清只读后删除树(临时目录, 忽略失败=真)
