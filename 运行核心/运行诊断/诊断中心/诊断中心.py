@dataclass
class 诊断结果:
    """一份失败诊断结果。"""

    记录id: str = ""
    归类: str = 归类_未知
    哪里失败: str = ""
    哪个版本: str = ""
    调用能力: str = ""
    依赖提供者: str = ""
    失败阶段: str = ""
    是否可以重试: bool = 假
    推荐验证场景: str = ""
    是否可以回滚: bool = 假
    结论: str = ""


def 归类失败(错误码: str) -> str:
    """按错误码归类失败类型。"""
    return 错误码归类表.get(错误码, 归类_未知)


def 关联验证场景(错误码: str) -> str:
    """按错误码关联推荐验证场景。"""
    return 错误码验证场景表.get(错误码, "")


def 诊断失败(记录: Any) -> 诊断结果:
    """生成一份完整诊断结果（回答 8 个问题）。"""
    结果 = 诊断结果()
    结果.记录id = 记录.记录id
    结果.归类 = 记录.归类 or 归类失败(记录.错误码)
    结果.哪里失败 = f"{记录.包id}" + (f"/{记录.模块id}" if 记录.模块id else "") + f"（错误码 {记录.错误码}）"
    结果.哪个版本 = 记录.版本 or "未知"
    结果.调用能力 = 记录.能力id or "（无能力上下文）"
    结果.依赖提供者 = 记录.提供者 or "（无提供者依赖）"
    结果.失败阶段 = 记录.阶段 or "未知阶段"
    结果.是否可以重试 = 记录.是否可重试
    结果.推荐验证场景 = 记录.关联验证场景 or 关联验证场景(记录.错误码)
    结果.是否可以回滚 = 记录.归类 in (归类_提供者问题, 归类_资源释放问题)
    结果.结论 = (
        f"失败位于 {结果.哪里失败}，版本 {结果.哪个版本}，阶段 {结果.失败阶段}；"
        f"归类为{结果.归类}；"
        f"推荐执行验证场景：{结果.推荐验证场景 or '（无）'}；"
        f"可重试：{结果.是否可以重试}；可回滚：{结果.是否可以回滚}"
    )
    return 结果


def 生成失败摘要(记录列表: list[Any]) -> str:
    """生成失败摘要（同类合并）。"""
    if not 记录列表:
        return "无失败记录"
    汇总表: dict[str, int] = {}
    for 记录 in 记录列表:
        键 = f"{记录.包id}@{记录.错误码}（{记录.归类 or 归类失败(记录.错误码)}）"
        汇总表[键] = 汇总表.get(键, 0) + 1
    行列表 = [f"共 {len(记录列表)} 条失败记录："]
    for 键, 数量 in sorted(汇总表.items(), key=lambda 项: -项[1]):
        行列表.append(f"  {数量} 条 {键}")
    return "\n".join(行列表)
