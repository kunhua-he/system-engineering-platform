"""运行事件模型：统一结构化事件（跨包唯一事件模型，禁止第二套）。

事件类型：调用开始/成功/失败、参数校验失败、配置错误、依赖解析失败、
提供者不可用/启动失败、生命周期变化、版本切换、升级成功/失败、
回滚开始/成功/失败、资源释放、模块卸载。

每条事件：事件id/时间/追踪id/项目id/包id/能力id/模块id/版本/契约版本/
提供者/生命周期状态/操作名称/成功状态/错误码/错误说明/是否可重试/耗时/
配置来源/依赖摘要。失败信息不可丢失；异常不得只输出字符串。
"""

from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field
from typing import Any
from 公共契约.基础类型.逻辑类型 import 真, 假

事件类型_调用开始 = "调用开始"
事件类型_调用成功 = "调用成功"
事件类型_调用失败 = "调用失败"
事件类型_参数校验失败 = "参数校验失败"
事件类型_配置错误 = "配置错误"
事件类型_依赖解析失败 = "依赖解析失败"
事件类型_提供者不可用 = "提供者不可用"
事件类型_提供者启动失败 = "提供者启动失败"
事件类型_生命周期变化 = "生命周期变化"
事件类型_版本切换 = "版本切换"
事件类型_升级成功 = "升级成功"
事件类型_升级失败 = "升级失败"
事件类型_回滚开始 = "回滚开始"
事件类型_回滚成功 = "回滚成功"
事件类型_回滚失败 = "回滚失败"
事件类型_资源释放 = "资源释放"
事件类型_模块卸载 = "模块卸载"


@dataclass
class 运行事件:
    """一条统一运行事件（JSONL 可序列化）。"""

    事件类型: str
    操作名称: str = ""
    成功: bool = 真
    错误码: str = ""
    错误说明: str = ""
    追踪id: str = ""
    项目id: str = ""
    包id: str = ""
    能力id: str = ""
    模块id: str = ""
    版本: str = ""
    契约版本: str = ""
    提供者: str = ""
    生命周期状态: str = ""
    是否可重试: bool = 假
    耗时毫秒: float = 0.0
    配置来源: str = ""
    依赖摘要: str = ""
    事件id: str = ""
    时间: str = ""

    def __post_init__(self) -> None:
        if not self.事件id:
            self.事件id = uuid.uuid4().hex[:16]
        if not self.时间:
            self.时间 = time.strftime("%Y-%m-%d %H:%M:%S")

    def 转字典(self) -> dict[str, Any]:
        return {
            "事件id": self.事件id,
            "时间": self.时间,
            "追踪id": self.追踪id,
            "事件类型": self.事件类型,
            "项目id": self.项目id,
            "包id": self.包id,
            "能力id": self.能力id,
            "模块id": self.模块id,
            "版本": self.版本,
            "契约版本": self.契约版本,
            "提供者": self.提供者,
            "生命周期状态": self.生命周期状态,
            "操作名称": self.操作名称,
            "成功": self.成功,
            "错误码": self.错误码,
            "错误说明": self.错误说明,
            "是否可重试": self.是否可重试,
            "耗时毫秒": self.耗时毫秒,
            "配置来源": self.配置来源,
            "依赖摘要": self.依赖摘要,
        }


def 生成事件(
    事件类型: str,
    *,
    成功: bool = 真,
    错误码: str = "",
    错误说明: str = "",
    追踪id: str = "",
    **补充字段: Any,
) -> 运行事件:
    """便捷生成事件；追踪id 为空时自动生成。"""
    return 运行事件(
        事件类型=事件类型,
        成功=成功,
        错误码=错误码,
        错误说明=错误说明,
        追踪id=追踪id or uuid.uuid4().hex[:16],
        **补充字段,
    )
