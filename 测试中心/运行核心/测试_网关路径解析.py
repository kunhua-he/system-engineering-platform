class 网关派发前改写(unittest.TestCase):
    def setUp(self):
        self.后端 = 假后端()
        self.网关 = 网关核心(self.后端)

    def _调用(self, 参数: dict):
        return self.网关.处理(网关请求(
            操作="调用能力", 能力id="示例.包.读文件", 参数=参数, 权限范围=["全部"],
        ))

    def test_路径族相对值被改写为绝对路径(self):
        响应 = self._调用({"文件路径": 相对锚, "项目根": str(根)})
        self.assertTrue(响应.成功, 响应.错误说明)
        收到 = self.后端.收到参数["文件路径"]
        self.assertTrue(Path(收到).is_absolute(), f"派发前必须已改写为绝对路径：{收到!r}")
        self.assertEqual(收到, str(根 / 相对锚))
        self.assertTrue(Path(收到).is_file(), "改写后必须指向真实存在的文件")

    def test_非路径族参数一字不改(self):
        响应 = self._调用({"文件路径": 相对锚, "项目根": str(根),
                          "起始行": 1, "模式": "r"})
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(self.后端.收到参数["起始行"], 1, "整数参数不许被碰")
        self.assertEqual(self.后端.收到参数["模式"], "r", "非路径族文本参数不许被碰")

    def test_绝对路径原样透传(self):
        绝对 = str(根 / 相对锚)
        响应 = self._调用({"文件路径": 绝对, "项目根": str(根)})
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(self.后端.收到参数["文件路径"], 绝对, "绝对路径必须原样，不重写")

    def test_不改写非路径族也不注入项目根(self):
        响应 = self._调用({"文件路径": 相对锚, "项目根": str(根), "起始行": 1})
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(set(self.后端.收到参数), {"文件路径", "起始行"},
                         "`项目根` 不得被塞进参数（那会改契约）；也不得凭空新增键")

    def test_无顶层项目根时按环境变量兜底(self):
        原 = os.environ.get(项目根环境变量名)
        os.environ[项目根环境变量名] = str(根)
        try:
            响应 = self._调用({"文件路径": 相对锚})  # 故意不传 项目根
        finally:
            if 原 is None:
                os.environ.pop(项目根环境变量名, None)
            else:
                os.environ[项目根环境变量名] = 原
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(self.后端.收到参数["文件路径"], str(根 / 相对锚),
                         "无顶层 项目根 时必须落到 解析路径 的环境变量兜底")

    def test_补全的路径族名相对值同样被改写(self):
        """2026-09-23 补全的名字：相对值必须与既有 8 名同等待遇（改前它们原样透传）。"""
        for 名 in 补全路径族名:
            with self.subTest(名=名):
                响应 = self._调用({"文件路径": 相对锚, 名: 相对锚, "项目根": str(根)})
                self.assertTrue(响应.成功, 响应.错误说明)
                收到 = self.后端.收到参数[名]
                self.assertTrue(Path(收到).is_absolute(), f"{名} 必须被改写为绝对路径：{收到!r}")
                self.assertEqual(收到, str(根 / 相对锚), f"{名} 必须按顶层 项目根 解析")
                self.assertTrue(Path(收到).is_file(), f"{名} 改写后必须指向真实存在的文件")

    def test_故意不入册的名字一字不改(self):
        """`修改路径`（列表型）/ `文档相对路径`（基准是文档根）/ `相对路径`（基准是受控根目录入参）。

        入册会把它们改坏 —— 故这三个名字的**相对值必须原样透给实现**：
        `修改路径` 是列表，连元素都不许动（开工即占/申请文件租约显式拒绝绝对路径）。
        """
        响应 = self._调用({"文件路径": 相对锚, "修改路径": [相对锚], "文档相对路径": 相对锚,
                          "相对路径": 相对锚, "项目根": str(根)})
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(self.后端.收到参数["修改路径"], [相对锚], "列表型 `修改路径` 连元素都不许动")
        self.assertEqual(self.后端.收到参数["文档相对路径"], 相对锚,
                         "`文档相对路径` 基准是登记档案的文档根，不是项目根")
        self.assertEqual(self.后端.收到参数["相对路径"], 相对锚,
                         "`相对路径` 基准是同调用的 受控根目录/根目录 入参")

    def test_新入册名的绝对_空值_非文本三种边界与既有名逐字一致(self):
        """边界行为不许因补全而分叉：绝对原样、空值原样、非文本原样（与 `文件路径` 逐字一致）。

        直接在归一化函数上判 —— 非文本值过不了 `文本型` 的参数校验，走不到网关派发，
        而边界逻辑本身就在这个函数里。
        """
        绝对 = str(根 / 相对锚)
        空值样本 = ("", "   ", None, 7, 3.5, ["a", "b"], {"a": 1}, 假)
        for 名 in ("文件路径",) + 补全路径族名:
            with self.subTest(名=名, 边界="绝对"):
                参数 = {名: 绝对, "项目根": str(根)}
                self.assertEqual(校验面模块._归一化路径族参数(参数)[名], 绝对,
                                 f"{名} 的绝对路径必须原样（不重写）")
            for 空 in 空值样本:
                with self.subTest(名=名, 边界=repr(空)):
                    参数 = {名: 空, "项目根": str(根)}
                    self.assertEqual(校验面模块._归一化路径族参数(参数)[名], 空,
                                     f"{名} 的 {空!r} 必须原样返回、不许抛")


def _缺陷态校验面(旧: str, 新: str):
    """把校验面源码故意改坏一次，返回缺陷态的 `参数校验面` 类（不落盘）。"""
    源 = _校验面源.read_text(encoding="utf-8")
    if 旧 not in 源:
        raise AssertionError(f"反向样本片段未命中：{旧!r}（判据需更新）")
    命名空间: dict = {"__name__": "反向样本_参数校验面", "__file__": str(_校验面源)}
    exec(compile(源.replace(旧, 新, 1), str(_校验面源), "exec"), 命名空间)  # noqa: S102
    return 命名空间["参数校验面"]


def _缺陷态字段名册(旧: str, 新: str) -> dict:
    """把字段名册源码退回**初版 8 名名单态**一次，返回缺陷态的模块命名空间（不落盘）。"""
    源 = _字段名册源.read_text(encoding="utf-8")
    if 旧 not in 源:
        raise AssertionError(f"反向样本片段未命中：{旧!r}（判据需更新）")
    命名空间: dict = {"__name__": "反向样本_字段名册", "__file__": str(_字段名册源)}
    exec(compile(源.replace(旧, 新, 1), str(_字段名册源), "exec"), 命名空间)  # noqa: S102
    return 命名空间


class 反向验证_掐掉改写(unittest.TestCase):
    """反向验证：把派发前的改写掐掉，相对路径必须原样透给实现（判据变红）。

    没有这层，「改写」可能只是恰好被别处做了，而不是这道判据在起作用 ——
    与 `测试_网关兼容性.py` 的 `被忽略参数反向验证` 同一用意。
    """

    def test_掐掉改写后过滤面原样透传相对路径(self):
        现行面 = 参数校验面()
        现行面.后端核心 = 假后端()
        现行 = 现行面._过滤能力参数("示例.包.读文件",
                                  {"文件路径": 相对锚, "项目根": str(根)})
        self.assertEqual(现行["文件路径"], str(根 / 相对锚), "现行实现必须改写")

        缺陷面 = _缺陷态校验面(_改写调用片段, "")
        缺陷实例 = 缺陷面()
        缺陷实例.后端核心 = 假后端()
        缺陷 = 缺陷实例._过滤能力参数("示例.包.读文件",
                                    {"文件路径": 相对锚, "项目根": str(根)})
        self.assertEqual(缺陷["文件路径"], 相对锚,
                         "掐掉改写后必须原样透传相对路径（这正是坏行为）")
        self.assertNotEqual(现行["文件路径"], 缺陷["文件路径"],
                            "反向样本与现行实现的结论必须不同，否则样本失效")

    def test_掐掉改写后网关真的把相对值透给实现(self):
        """证明「改写」真的读自那个计算，不是另有一份硬编码。"""
        网关 = 网关核心(假后端())
        原 = 校验面模块._归一化路径族参数
        校验面模块._归一化路径族参数 = lambda 参数: dict(参数)
        try:
            响应 = 网关.处理(网关请求(
                操作="调用能力", 能力id="示例.包.读文件",
                参数={"文件路径": 相对锚, "项目根": str(根)}, 权限范围=["全部"],
            ))
        finally:
            校验面模块._归一化路径族参数 = 原
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(网关.后端核心.收到参数["文件路径"], 相对锚,
                         "计算被掐掉后实现必须收到裸相对路径 —— 否则改写另有来源")
        self.assertFalse(Path(网关.后端核心.收到参数["文件路径"]).is_absolute())

    def test_补全名在初版名单态下不被改写_补全后才被改写(self):
        """反向验证「改前不生效」：把字段名册退回初版 8 名，`目录` 必须原样透传。

        这是 2026-09-23 补全的**唯一判据**：这些名字此前的坏行为不是「改写没跑」，
        而是「它们压根不在名单里」。故反向样本动的是**名单**，不是改写那一行。
        """
        现行面 = 参数校验面()
        现行面.后端核心 = 假后端()
        现行 = 现行面._过滤能力参数("示例.包.读文件",
                                  {"目录": 相对锚, "项目根": str(根)})
        self.assertEqual(现行["目录"], str(根 / 相对锚), "现行名单必须改写 `目录`")

        缺陷册 = _缺陷态字段名册(_补全名单行, "")
        self.assertFalse(缺陷册["是路径族字段"]("目录"),
                         "初版名单态里 `目录` 必须不在路径族（否则反向样本失效）")
        self.assertTrue(缺陷册["是路径族字段"]("文件路径"),
                        "初版 8 名必须仍在（反向样本只摘补全名）")
        原 = 校验面模块.是路径族字段
        校验面模块.是路径族字段 = 缺陷册["是路径族字段"]
        try:
            缺陷面 = 参数校验面()
            缺陷面.后端核心 = 假后端()
            缺陷 = 缺陷面._过滤能力参数("示例.包.读文件",
                                      {"目录": 相对锚, "项目根": str(根)})
        finally:
            校验面模块.是路径族字段 = 原
        self.assertEqual(缺陷["目录"], 相对锚,
                         "初版名单态下 `目录` 必须原样透传（这正是改前的坏行为）")
        self.assertNotEqual(现行["目录"], 缺陷["目录"],
                            "反向样本与现行实现的结论必须不同，否则样本失效")


