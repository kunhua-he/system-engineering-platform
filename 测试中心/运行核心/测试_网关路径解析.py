"""网关派发前的路径族入参归一：相对路径按顶层 `项目根` 改写为绝对路径。

## 为什么单独写

这是「传相对路径就能用」这条兼容性的**唯一改点**：网关是**唯一一次**「已经拿到顶层
`项目根`、且还没派发」的地方（薄壳对每一次「调用能力」都自动补位顶层 `项目根`）。
本件锁两件事：

- 正：路径族相对值在派发前被改写为**绝对路径**；非路径族参数**一字不改**；
  绝对路径原样；无顶层 `项目根` 时按环境变量 `系统平台_项目根` 兜底；
- 反：把改写掐掉 ⇒ 判据必须变红（实现收到的仍是相对路径）。
  手法照 `测试中心/开发工具/测试_薄壳返回可控.py` 的反向样本与
  `测试中心/运行核心/测试_网关兼容性.py` 的 `_缺陷态校验面`（源码副本 + exec，不落盘）。

**2026-09-23 补全**（华哥裁决「根目录是锁定解析基准，相对/绝对都要能用」）：路径族名单
从初版 8 个统计口径名补到 75 个（判据见 `公共契约/基础类型/字段名册.路径族字段名`）。
本件补三组判据：① 新入册名（`目录`/`输出目录`/`目标路径`/`源码根`/`证据目录`/`制品根目录`）
的相对值同样被改写；② **故意不入册**的名字（`修改路径` 列表型 / `文档相对路径` 基准是
文档根 / `相对路径` 基准是受控根目录入参）一字不改；③ 新入册名的绝对 / 空值 / 非文本
三种边界行为与既有 8 名**逐字一致**。反向样本改为「初版名单态」：证明这些名字**改前
确实不生效**、改后才生效（不是本来就生效）。

判据要点（强规范：参数/返回只增不改不删、字段类型冻结）：改写只发生在**派发之前**，
**不新增/不改名/不改类型**任何入参键 —— 非路径族键必须逐字不变。
"""

