"""进程内腿必填/类型校验收口测试（开工ID 开工-20260923-031428-1d4a）。

## 缺陷（改前实测，本文件是它的回归锁）

`运行核心/能力调用/唯一能力调用.py::唯一能力调用服务.调用能力` 是**所有进程内直调**
（`后端核心.调用` / `公共契约.能力契约.调用器` 的 `获取能力调用器().调用能力` /
`进程内连接器` / 任务通道执行器）唯一的收口点，改前**整段没有参数校验**：

- 缺必填参数 → 落成实现体 `TypeError: 探测媒体() missing 1 required positional argument`
  → 该 `TypeError` 不在 `唯一能力调用_调用错误码._异常错误码表` 里 → 回 **`内部错误`**；
- 显式传 `None` / 类型不符 → 实现照收，**静默成功**（比报错更坏）。

而 HTTP 腿（经网关）在派发前由 `网关参数校验面._能力参数错误` →
`运行核心/统一网关/协议/类型规格.py::校验能力参数` 拦下，同一入参回 **`参数不合法`**。
⇒ **同一条非法入参，两条腿口径不一致**；且把「可预期的入参错误」当成「未预期异常」
上报（哲学第 3 条 2 项：失败必须明确）。

## 本文件锁什么

1. 进程内腿缺必填 / 类型不符 / 显式 `None` 一律回 `参数不合法`，**不是** `内部错误`；
2. 错误说明与唯一校验点 `校验能力参数` **逐字一致**（证明是转调同一把尺子，
   不是在本文件另养的第二套类型表/必填判据）；
3. 合法入参（含缺可选参数）不误伤；
4. **兄弟入口扫全**：`请求` / 模块调用器（`获取能力调用器().调用能力`）/
   `进程内连接器` 四条进程内入口全部过同一校验点；
5. 失败路径的证据链与调用历史同样记为 `参数不合法`（不只是返回值对）。

## 未知参数（**错误码已收口，口径未动**）

网关对未知参数是「一律忽略 + 经 `被忽略参数` 回带」，进程内腿对未声明键是**拒绝**
（两层口径**刻意不同**，出处：`开发文档/当前流程图.md` 传参铁律 +
`开发文档/规范/网关调用最小示例.md` 规则 1）。**该「拒绝 vs 忽略」口径本轮不动**。

改前进程内腿把这条**可预期的入参错误**当成**未预期异常**上报：契约层抛裸 `TypeError`
→ `_异常错误码表` 里没有 → 回 **`内部错误`**。现已收口为 **`参数不合法`**：
契约层改抛 `公共契约/能力契约/契约.py::未知参数错误`（**TypeError 子类**，保持
Python 语义与既有 `except TypeError` 行为），`唯一能力调用_调用错误码._异常错误码表`
按该**子类**精确映射 `参数不合法` —— 实现体内其它 `TypeError`（真故障）照旧落
`内部错误`，不受影响。见 `Test未知参数错误码`。
"""

