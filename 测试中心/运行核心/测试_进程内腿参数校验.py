能力id = "媒体处理支持库.FFmpeg媒体.探测媒体"
#: 与真实包 `支持库/后端/媒体处理支持库/FFmpeg媒体/__init__.py` 的声明同形
#: （必填 文件路径 文本型 + 非必填 超时秒 双精度数型）。
声明参数 = [
    {"名称": "文件路径", "类型": "文本型", "必填": 真, "默认值": None},
    {"名称": "超时秒", "类型": "双精度数型", "必填": 假, "默认值": 60},
]


def 探测媒体(文件路径: str, 超时秒: float = 60) -> 结果:
    """同形实现：`文件路径` 是**必填位置参数**（缺则解释器在调用点抛 TypeError）。"""
    return 结果.成功结果({"文件路径": 文件路径, "超时秒": 超时秒})


def 构造服务() -> 唯一能力调用服务:
    注册表 = 能力注册表()
    注册表.注册(能力实现(
        能力id=能力id, 包id="支持库.后端.媒体处理支持库.FFmpeg媒体",
        实现函数=探测媒体, 参数=声明参数, 返回="结果型", 说明="进程内腿校验回归用",
        版本="1.0.0", 提供者id="FFmpeg提供者", 提供者版本="1.0.0",
        制品摘要="摘要进程内腿校验",
    ))
    return 唯一能力调用服务(注册表)


class 进程内腿校验测试基类(unittest.TestCase):
    def setUp(self) -> None:
        self.服务 = 构造服务()
        设置全局唯一服务(self.服务)

    def tearDown(self) -> None:
        注册能力调用器(None)
        销毁全局唯一服务()

    def 断言参数不合法(self, 结果对象, 片段: str) -> None:
        self.assertFalse(结果对象.成功)
        # 反向验证：改前这里恒为「内部错误」+ `TypeError: ...`，改后必须是参数口径。
        self.assertNotEqual(结果对象.错误码, "内部错误",
                            f"仍是「内部错误」（可预期的入参错误被当成未预期异常）: {结果对象.错误说明}")
        self.assertEqual(结果对象.错误码, "参数不合法")
        self.assertIn(片段, 结果对象.错误说明)


class Test唯一能力调用服务腿(进程内腿校验测试基类):
    """直调腿（`唯一能力调用服务.调用能力`，后端核心/任务通道同一条路）。"""

    def test_缺必填参数回参数不合法_不再是内部错误(self):
        结果对象 = self.服务.调用能力(能力id, {})
        self.断言参数不合法(结果对象, "缺少必填参数 文件路径")
        # 改前的错误说明是异常原文，改后不得再泄漏异常类型名。
        self.assertNotIn("TypeError", 结果对象.错误说明)

    def test_显式None回参数不合法_必须是文本型(self):
        结果对象 = self.服务.调用能力(能力id, {"文件路径": None})
        self.断言参数不合法(结果对象, "参数 文件路径 必须是 文本型")

    def test_类型不符回参数不合法(self):
        for 非法值 in (123, ["a"], {"a": 1}, 真):
            结果对象 = self.服务.调用能力(能力id, {"文件路径": 非法值})
            self.断言参数不合法(结果对象, "参数 文件路径 必须是 文本型")

    def test_合法入参不误伤_缺可选参数也成功(self):
        结果对象 = self.服务.调用能力(能力id, {"文件路径": "/tmp/不存在.mp4"})
        self.assertTrue(结果对象.成功, 结果对象.错误说明)
        self.assertEqual(结果对象.值["文件路径"], "/tmp/不存在.mp4")
        self.assertEqual(结果对象.值["超时秒"], 60)

    def test_合法入参不误伤_可选参数也给(self):
        结果对象 = self.服务.调用能力(能力id, {"文件路径": "/tmp/x.mp4", "超时秒": 5.0})
        self.assertTrue(结果对象.成功, 结果对象.错误说明)
        self.assertEqual(结果对象.值["超时秒"], 5.0)

    def test_错误说明与唯一校验点逐字一致(self):
        """进程内腿是**转调**唯一校验点，不是第二套判据：说明必须逐字相同。"""
        for 非法参数 in ({}, {"文件路径": None}, {"文件路径": 1}):
            唯一校验点说明 = 校验能力参数(能力id, 声明参数, dict(非法参数))
            self.assertTrue(唯一校验点说明.startswith("参数不合法："))
            结果对象 = self.服务.调用能力(能力id, 非法参数)
            self.assertEqual(结果对象.错误说明, 唯一校验点说明)

    def test_失败路径证据链与调用历史同记参数不合法(self):
        结果对象 = self.服务.调用能力(能力id, {}, 调用方="回归测试")
        self.assertFalse(结果对象.成功)
        最近 = self.服务.查询调用历史(1)[0]
        self.assertEqual(最近["错误码"], "参数不合法")
        self.assertEqual(最近["成功"], 假)
        self.assertEqual(最近["调用方"], "回归测试")
        self.assertIn("缺少必填参数 文件路径", 最近["错误说明"])
        # 证据链同样收口（失败也必须留痕，不是只改返回值）
        证据 = 最近["证据"]
        self.assertFalse(证据["成功"])
        self.assertEqual(证据["错误码"], "参数不合法")
        self.assertEqual(证据["能力id"], 能力id)

    def test_能力不存在仍回能力不存在_不被参数校验抢答(self):
        """校验只在能力已注册时进行：未注册能力照旧回「能力不存在」。"""
        结果对象 = self.服务.调用能力("不存在的.能力", {})
        self.assertEqual(结果对象.错误码, "能力不存在")


