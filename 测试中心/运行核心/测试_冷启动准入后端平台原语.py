def 平台原语判据问题(输出: dict) -> list[str]:
    """**正反共用**的判据：返回「准入后端＝平台原语」这条不变式的全部违约项。

    正向用例要求返回空表；反向用例要求返回非空表 —— 红与绿出自同一段逻辑，
    不存在「反向用的是另一套说法」。判据分两层：
    ① 认定层：快照 `准入后端` 是平台原语，且未降级（降级说明为空）；
    ② 行为层：准入真的落在平台治理面 —— 平台闸门表里能查出这次准入的上限与占用，
       且与执行器快照的上限/占用逐一对得上（自报字符串冒充不过这一层）。
    """
    问题: list[str] = []
    if 输出["准入后端"] != 平台原语后端名:
        问题.append(f"①准入后端不是平台原语：实测 {输出['准入后端']!r}")
    if 输出["准入降级说明"] != "":
        问题.append(f"①准入降级说明非空（应保持平台原语路径）：{输出['准入降级说明']!r}")
    if not 输出.get("平台闸门可查"):
        问题.append("②平台闸门查不到：准入没有落在平台容量闸门表上"
                    f"（{输出.get('平台闸门错误', '闸门不存在')}）")
    else:
        if 输出["平台闸门上限"] != 输出["全局执行线程上限"]:
            问题.append(f"②平台闸门上限 {输出['平台闸门上限']!r} 与执行器上限 "
                        f"{输出['全局执行线程上限']!r} 不一致")
        if 输出["运行中占用"] != 输出["平台闸门占用"] or not 输出["运行中占用"]:
            问题.append(f"②运行中占用 {输出['运行中占用']!r} 与平台闸门占用 "
                        f"{输出['平台闸门占用']!r} 不一致（或为 0，没测到真占用）")
    return 问题


