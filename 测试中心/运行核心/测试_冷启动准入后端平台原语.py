    def test_反向验证_临时换成假准入后端判据报红_还原后转绿(self) -> None:
        """反向①：临时把准入后端换成假的（非平台原语）⇒ 同一判据必须报红；还原 ⇒ 转绿。

        关键点：假后端跑的那次**平台支持库仍在制品里且可导入**（`闸门库文件` 非空），
        所以报红的原因只能是「选中的后端不是平台原语」，不是「支持库缺失」。
        """
        影子根 = self._建假准入后端影子()
        报红输出 = self.观测冷启动(影子根)
        # 证明确实加载的是影子副本（否则这次反向验证什么都没验证）
        self.assertIn(str(影子根), 报红输出["超时执行文件"],
                      f"影子副本未被导入：{报红输出['超时执行文件']}")
        self._断言基础链路成立(报红输出)
        self.assertIn(str(self.暂存根), 报红输出["闸门库文件"],
                      "平台支持库本应可用；否则这条反向验证测的是「缺失」而不是「换后端」")
        self.assertNotEqual(报红输出["准入后端"], 平台原语后端名)

        # 核心反向证据：**正向那条断言体**拿假后端跑必须抛 AssertionError（报红）
        with self.assertRaises(AssertionError) as 捕获:
            self._断言准入后端是平台原语(报红输出)
        报红文本 = str(捕获.exception)
        self.assertIn("准入后端不是平台原语", 报红文本)
        self.assertIn("平台闸门查不到", 报红文本)
        self.assertIn("反向验证假准入后端（非平台原语）", 报红文本,
                      "报红文本必须点名假后端，证明确实是被换掉的那个后端触发")

        报红 = 平台原语判据问题(报红输出)
        self.assertGreaterEqual(len(报红), 2,
                                f"认定层与行为层都应报红，实测 {报红}")
        # 降级说明为空 ⇒ 证明报红不是靠「降级说明」这一条侥幸触发的
        self.assertEqual(报红输出["准入降级说明"], "")

        # 还原（撤掉影子、不改仓库任何文件）⇒ 同一断言体在同一测试里转绿
        还原输出 = self.观测冷启动()
        self.assertIn(str(系统根), 还原输出["超时执行文件"],
                      f"还原后应回到仓库实现：{还原输出['超时执行文件']}")
        self._断言基础链路成立(还原输出)
        self._断言准入后端是平台原语(还原输出)  # 不抛 ⇒ 转绿

    def test_反向验证_裁掉平台并发原语则降级不隐瞒(self) -> None:
        """反向②：平台原语不在制品里 ⇒ 降级必须如实暴露，且判据同样报红。"""
        shutil.rmtree(self.暂存根 / "支持库" / "后端" / "并发控制支持库")
        输出 = self.观测冷启动()
        self._断言基础链路成立(输出)
        self.assertEqual(输出["闸门库文件"], "", "支持库已裁掉，不该还能导入")
        self.assertIn("并发控制支持库", 输出["闸门库错误"])
        self.assertNotEqual(输出["准入后端"], 平台原语后端名)
        self.assertIn("降级", 输出["准入后端"])
        self.assertIn("并发控制支持库", 输出["准入降级说明"],
                      "降级原因必须写进快照 `准入降级说明`，不许隐瞒")
        self.assertTrue(平台原语判据问题(输出), "降级路径必须被同一判据打红")
        # 降级后「有界 + 明确拒绝」逐条仍在：可选包缺失不得反向打掉线程有界这条不变式
        self.assertEqual(输出["运行中占用"], 1)


