class 被忽略参数回带(unittest.TestCase):
    """只增回带：未知字段照旧被剔除，但调用方能看见「丢了哪个键、真名最可能是什么」。

    为什么要有这组：`路径` 传给 `查询文件租约`（真名 `修改路径`）时条件被静默剔除，
    过滤器变成「取全部」⇒ 一次拿回 470KB 全表，还据此差点把平台判成缺陷。
    静默是刻意的协议兼容口径（哲学第 5 条 2 项），但它让「这能力没这功能」与
    「我参数名写错了」两件完全不同的事长得一模一样 —— 这组用例锁的就是这个区分。
    """

    def setUp(self):
        self.后端 = 假后端()
        self.网关 = 网关核心(self.后端)

    def _调用(self, 参数: dict):
        return self.网关.处理(网关请求(
            操作="调用能力", 能力id="示例.包.示例能力", 参数=参数,
            权限范围=["全部"],
        ))

    def test_参数名写错时点出最接近的真名(self):
        响应 = self._调用({"输入文本": "真实值", "路径": "开发文档/方案"})
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(self.后端.收到参数, {"输入文本": "真实值"}, "剔除行为本身不变")
        忽略 = {项["参数名"]: 项 for 项 in 响应.被忽略参数}
        self.assertEqual(set(忽略), {"路径"}, "只该报真正被剔除的那个键")
        self.assertEqual(忽略["路径"]["最接近的契约参数"], ["修改路径"],
                         "`路径` 必须被点向真名 `修改路径`（实测踩过的那一次）")

    def test_无关名不瞎点(self):
        响应 = self._调用({"输入文本": "真实值", "未来字段": "x"})
        忽略 = {项["参数名"]: 项 for 项 in 响应.被忽略参数}
        self.assertEqual(忽略["未来字段"]["最接近的契约参数"], [],
                         "没有相近的真名时必须留空 —— 瞎点的建议比不给建议更坏")

    def test_没有未知参数时清单为空(self):
        响应 = self._调用({"输入文本": "真实值", "修改路径": ["a"]})
        self.assertEqual(响应.被忽略参数, [], "参数全对时不许回带噪声")

    def test_横切参数项目根不回带(self):
        """`项目根` 是平台级横切参数（薄壳每次调用都自动补位）→ 不许当成调用方笔误报出来。

        实测（2026-09-21 验收薄壳时）：不排除的话每次调用都回带一条
        「`项目根` 已被网关剔除」，而那是**平台自己注入的**，属 100% 可预测的纯噪声 ——
        会把这个字段训成「人人无视」，反而毁掉它点出真笔误的用处。
        """
        响应 = self._调用({"输入文本": "真实值", "项目根": "/x"})
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(响应.被忽略参数, [], "平台自己注入的横切参数不算调用方写错")
        self.assertEqual(self.后端.收到参数, {"输入文本": "真实值"}, "剔除行为本身不变")

    def test_横切参数排除不影响真笔误(self):
        """同一调用里既有横切参数又有真笔误 → 只报真笔误（排除表不得放宽真信号）。"""
        响应 = self._调用({"输入文本": "真实值", "项目根": "/x", "路径": "开发文档/方案"})
        忽略 = {项["参数名"]: 项 for 项 in 响应.被忽略参数}
        self.assertEqual(set(忽略), {"路径"}, "横切参数被排除，真笔误照旧报出来")
        self.assertEqual(忽略["路径"]["最接近的契约参数"], ["修改路径"],
                         "真笔误的点名能力不因横切排除而退化")

    def test_信封字典带出被忽略参数(self):
        响应 = self._调用({"输入文本": "真实值", "未来字段": "x"})
        信封 = 响应.转字典()
        self.assertIn("被忽略参数", 信封, "信封必须带该键，否则薄壳无从透传")
        self.assertEqual(信封["被忽略参数"][0]["参数名"], "未来字段")


def _缺陷态校验面(旧: str, 新: str):
    """把校验面源码故意改坏一次，返回缺陷态的 `参数校验面` 类（不落盘）。"""
    源 = _校验面源.read_text(encoding="utf-8")
    if 旧 not in 源:
        raise AssertionError(f"反向样本片段未命中：{旧!r}（判据需更新）")
    命名空间: dict = {"__name__": "反向样本_参数校验面", "__file__": str(_校验面源)}
    exec(compile(源.replace(旧, 新, 1), str(_校验面源), "exec"), 命名空间)  # noqa: S102
    return 命名空间["参数校验面"]


def _取忽略(类, 参数: dict):
    面 = 类()
    面.后端核心 = 假后端()
    return 面._被忽略参数("示例.包.示例能力", 参数)


class 被忽略参数反向验证(unittest.TestCase):
    """反向验证：把两处判据各自弄坏一次，确认对应用例真的会红。

    没有这层，「回带」可能只是恰好空列表 / 恰好有值，而不是判据在起作用 ——
    与 `测试_目录树` 的反向样本同一用意。
    """

    def test_阈值提到不可达后建议必空(self):
        现行 = _取忽略(参数校验面, {"输入文本": "x", "路径": "y"})
        self.assertEqual(现行[0]["最接近的契约参数"], ["修改路径"], "现行必须点得出真名")
        缺陷 = _取忽略(_缺陷态校验面("近似名阈值 = 0.34", "近似名阈值 = 1.0"),
                       {"输入文本": "x", "路径": "y"})
        self.assertEqual(缺陷[0]["最接近的契约参数"], [], "阈值不可达时必须真的空")
        self.assertNotEqual(现行[0]["最接近的契约参数"], 缺陷[0]["最接近的契约参数"],
                            "反向样本与现行实现的结论必须不同，否则样本失效")

    def test_掐掉计算后清单必空(self):
        缺陷 = _取忽略(_缺陷态校验面(
            "被忽略 = [键 for 键 in _应用参数别名(能力id, 参数)\n"
            "                if 键 not in 允许 and 键 not in 横切参数名]",
            "被忽略 = []"), {"输入文本": "x", "未来字段": "y"})
        self.assertEqual(缺陷, [], "掐掉计算后必须真的没有清单（这正是坏行为）")

    def test_掐掉横切排除后项目根必被报出(self):
        """反向样本（故意弄坏）：去掉横切排除 → `项目根` 必须重新出现在清单里。

        证明 `test_横切参数项目根不回带` 的「不报」确实是横切参数表在起作用，
        而不是清单恒空 —— 与上面两条反向样本同一用意。
        """
        现行 = _取忽略(参数校验面, {"输入文本": "x", "项目根": "/x"})
        self.assertEqual(现行, [], "现行实现必须把横切参数排除掉")
        缺陷 = _取忽略(_缺陷态校验面(" and 键 not in 横切参数名", ""),
                       {"输入文本": "x", "项目根": "/x"})
        self.assertEqual([项["参数名"] for 项 in 缺陷], ["项目根"],
                         "掐掉排除后必须复现噪声，否则说明排除表是死代码")
        self.assertNotEqual(现行, 缺陷, "反向样本与现行实现的结论必须不同，否则样本失效")

    def test_掐掉计算后信封也确实不带(self):
        """证明「回带」真的读自那个计算，不是另有一份硬编码。"""
        网关 = 网关核心(假后端())
        原 = 参数校验面._被忽略参数
        参数校验面._被忽略参数 = lambda self, 能力id, 参数: []
        try:
            响应 = 网关.处理(网关请求(
                操作="调用能力", 能力id="示例.包.示例能力",
                参数={"输入文本": "x", "未来字段": "y"}, 权限范围=["全部"],
            ))
        finally:
            参数校验面._被忽略参数 = 原
        self.assertEqual(响应.被忽略参数, [],
                         "计算被掐掉后信封必须跟着空 —— 否则回带另有来源")


class 网关版本回报(unittest.TestCase):
    """哲学第 21 条：带旧版本号请求照常放行，并回报请求版本/当前版本/差异原因。"""

    def setUp(self):
        self.后端 = 假后端()
        self.网关 = 网关核心(self.后端)

    def _请求(self, 版本: str = ""):
        return self.网关.处理(网关请求(
            操作="调用能力", 能力id="示例.包.示例能力",
            参数={"输入文本": "值"}, 权限范围=["全部"], 请求版本=版本,
        ))

    def test_旧版本号不失败且回报三项信息(self):
        响应 = self._请求("1.0.0")
        self.assertTrue(响应.成功, 响应.错误说明)
        self.assertEqual(响应.请求版本, "1.0.0")
        self.assertTrue(响应.当前版本)
        self.assertIn("不一致", 响应.版本差异)

    def test_版本一致时差异为空(self):
        from 公共契约.版本规则.契约版本 import 契约版本

        响应 = self._请求(契约版本)
        self.assertTrue(响应.成功)
        self.assertEqual(响应.当前版本, 契约版本)
        self.assertEqual(响应.版本差异, "")

    def test_响应信封带版本三键(self):
        信封 = self._请求().转字典()
        for 键 in ("请求版本", "当前版本", "版本差异"):
            self.assertIn(键, 信封, f"信封必须包含 {键}（只增不改不删）")


