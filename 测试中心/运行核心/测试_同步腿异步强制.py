class 假实现:
    def __init__(self, 参数声明: list) -> None:
        self.参数 = 参数声明
        self.返回 = "结果"


class 假注册表:
    def __init__(self, 能力表: dict) -> None:
        self.能力表 = dict(能力表)

    @property
    def 能力id列表(self) -> list:
        return list(self.能力表)

    def 获取(self, 能力id: str):
        return self.能力表.get(能力id)


class 假结果:
    def __init__(self) -> None:
        self.成功 = 真
        self.值 = {"跑过": 真}
        self.错误码 = ""
        self.错误说明 = ""


class 假后端:
    """只实现网关在「调用能力」这条路上真正用到的面：注册表 + 调用。

    `调用` 里记一笔调用次数：用来断言「拒的时候**真的没派发**」——只看错误码
    无法区分「派发前拒」与「派发后回了个拒」（后者意味着副作用已经发生）。
    """

    def __init__(self) -> None:
        self.调用次数 = 0
        self.注册表 = 假注册表({
            能力_默认60: 假实现(声明_默认60),
            能力_默认5: 假实现(声明_默认5),
            能力_无默认: 假实现(声明_无默认),
            能力_无该参数: 假实现(声明_无该参数),
        })

    def 调用(self, 能力id: str, 参数: dict, *, 上下文=None, 超时秒=None) -> 假结果:
        self.调用次数 += 1
        return 假结果()


def 建网关() -> tuple[网关核心, 假后端]:
    后端 = 假后端()
    return 网关核心(后端, 幂等持久化=假), 后端


def 调(网关: 网关核心, 能力id: str, 参数: dict | None = None,
      信封超时秒: float = 1800.0):
    return 网关.处理(网关请求(操作="调用能力", 能力id=能力id, 参数=dict(参数 or {}),
                              权限范围=["查询", "调用", "任务", "管理员"],
                              超时秒=信封超时秒))


class 同步腿异步强制(unittest.TestCase):
    def test_1_显式大超时被拒(self) -> None:
        """① 调用方显式传 ≥10 ⇒ 拒（这是裁决的正例）。"""
        网关, 后端 = 建网关()
        响应 = 调(网关, 能力_默认60, {"超时秒": 600})
        self.assertFalse(响应.成功, f"显式 超时秒=600 仍被放行：{响应.转字典()}")
        self.assertEqual(响应.错误码, "须走异步腿", 响应.转字典())
        self.assertEqual(后端.调用次数, 0,
                         "在派发前就该拒 —— 调用次数不为 0 说明副作用已经发生了")

    def test_1b_边界含十(self) -> None:
        """「10 以上包含 10」⇒ 恰好 10 必须拒（边界值，最容易写错的一侧）。"""
        网关, _ = 建网关()
        响应 = 调(网关, 能力_默认60, {"超时秒": 同步腿超时上限秒})
        self.assertFalse(响应.成功, f"恰好 {同步腿超时上限秒} 应拒（裁决原文「包含 10」）")
        self.assertEqual(响应.错误码, "须走异步腿", 响应.转字典())

    def test_1c_错误说明给出可照抄的异步腿命令(self) -> None:
        """拒绝不够 —— 必须告诉调用方**下一步怎么走**（否则每个被拒者都要人再教一遍）。"""
        网关, _ = 建网关()
        响应 = 调(网关, 能力_默认60, {"超时秒": 600})
        self.assertIn("任务提交", 响应.错误说明,
                      "错误说明必须给出异步腿命令（照抄即可改走异步）")
        self.assertIn("任务查询", 响应.错误说明,
                      "还要给出取结果的第二段（只给第一段等于把调用方扔在半路）")
        self.assertIn(能力_默认60, 响应.错误说明, "命令里必须带上本次的能力 id")

    def test_2_信封1800不得成为判据(self) -> None:
        """★ 判据是「契约自声明参数的生效值」，不是信封 `请求.超时秒`。

        HTTP 边界**总是**把信封填成 1800；若误用信封值，本次调用会被拒 ——
        而本能力的契约声明 5（<10）本应放行。这条锁住「不许把整个同步面打死」。
        """
        网关, 后端 = 建网关()
        响应 = 调(网关, 能力_默认5, {}, 信封超时秒=1800.0)
        self.assertTrue(响应.成功,
                        f"契约默认 5（<10）却被信封的 1800 误判拒了：{响应.转字典()}")
        self.assertEqual(后端.调用次数, 1, "放行却没真的派发（空转）")

    def test_2b_无默认值放行(self) -> None:
        """③ 契约 `默认值` 为空 ⇒ 生效值未知 ⇒ 放行（不许发明阈值）。"""
        网关, 后端 = 建网关()
        响应 = 调(网关, 能力_无默认, {})
        self.assertTrue(响应.成功,
                        f"契约没声明默认值却按 ≥10 拦了（发明数据）：{响应.转字典()}")
        self.assertEqual(后端.调用次数, 1)

    def test_2c_契约无该参数放行(self) -> None:
        """契约里根本没有 `超时秒` ⇒ 无超时语义，规则不适用。"""
        网关, 后端 = 建网关()
        响应 = 调(网关, 能力_无该参数, {})
        self.assertTrue(响应.成功, f"无超时语义的能力被误伤：{响应.转字典()}")
        self.assertEqual(后端.调用次数, 1)

    def test_3_没传时吃契约默认值(self) -> None:
        """② 没传 + 契约默认 60 ⇒ 拒。**这是 173/179 能力默认被拒的来源**，
        少了它「默认档长任务必须走异步」这条裁决等于没落地。"""
        网关, 后端 = 建网关()
        响应 = 调(网关, 能力_默认60, {})
        self.assertFalse(响应.成功, f"没传但契约默认 60 应拒：{响应.转字典()}")
        self.assertEqual(响应.错误码, "须走异步腿", 响应.转字典())
        self.assertIn("60", 响应.错误说明, "说明里应回带生效值（默认值），便于调用方对账")
        self.assertEqual(后端.调用次数, 0, "拒必须在派发前")

    def test_4_小于十放行(self) -> None:
        """显式传 <10 ⇒ 放（与 test_1 成对；只测一侧会漏掉「恒拒」的假绿）。"""
        网关, 后端 = 建网关()
        响应 = 调(网关, 能力_默认60, {"超时秒": 5})
        self.assertTrue(响应.成功, f"超时秒=5（<10）被拒了：{响应.转字典()}")
        self.assertEqual(后端.调用次数, 1, "放行却没真的派发（空转）")

    def test_4b_默认小于十不传也放行(self) -> None:
        网关, 后端 = 建网关()
        响应 = 调(网关, 能力_默认5, {})
        self.assertTrue(响应.成功, f"契约默认 5 应放行：{响应.转字典()}")
        self.assertEqual(后端.调用次数, 1)

    def test_5_异步腿不得被自己拦(self) -> None:
        """`任务提交` 是**承接** ≥10 能力的腿，它自己绝不能过同一把尺子。

        若守卫挂到了 `任务提交` 分支上，本裁决就从「强制异步」变成「禁止执行」——
        死胡同。这条锁住「守卫只在 调用能力 分支」。
        """
        源码 = (系统根 / "运行核心" / "统一网关" / "核心处理"
              / "网关执行面.py").read_text(encoding="utf-8")
        调用能力位 = 源码.index('请求.操作 == "调用能力"')
        任务提交位 = 源码.index('请求.操作 == "任务提交"')
        self.assertLess(调用能力位, 任务提交位, "两个分支的先后假设变了，请复核本用例")
        守位 = 源码.index("_同步腿拒绝说明")
        self.assertGreater(守位, 调用能力位, "守卫必须在 调用能力 分支内")
        self.assertLess(守位, 任务提交位,
                        "守卫越过了 任务提交 分支 —— 异步腿会被自己拦死（死胡同）")

    def test_6_阈值只有一处定义(self) -> None:
        """哲学 1.2：阈值不许多处各写一份（各写一份必然漂移）。"""
        命中 = []
        for 源 in (系统根 / "运行核心").rglob("*.py"):
            if any(段 in 源.parts for 段 in 排除目录段):
                continue
            try:
                文本 = 源.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            for 行号, 行 in enumerate(文本.splitlines(), 1):
                if "同步腿超时上限秒" in 行 and "=" in 行 and "import" not in 行:
                    命中.append((源.relative_to(系统根).as_posix(), 行号, 行.strip()))
        定义处 = [x for x in 命中 if x[2].startswith("同步腿超时上限秒")]
        self.assertEqual(len(定义处), 1,
                         f"`同步腿超时上限秒` 必须只有一处定义，实测 {定义处}")

    def test_7_真实能力面读数(self) -> None:
        """对**真实** `能力定义.json` 核一遍分布 —— 防「规则只对测试夹具生效」。

        不硬编码具体条数（能力集会变），只锁两条不变量：
        ① 存在 ≥10 的真实能力（否则本裁决空转，等于没落地）；
        ② 写入/读取腿（`.md` 落盘与读回）**不在** ≥10 集合里 ——
           否则「拒绝手写md」判据与所有文本类工具链会被自己的守卫拦死。
        """
        大超时集: set[str] = set()
        声明过: set[str] = set()
        for 定义 in 系统根.rglob("能力定义.json"):
            if any(段 in 定义.parts for 段 in 排除目录段):
                continue
            try:
                数据 = json.loads(定义.read_text(encoding="utf-8"))
            except (OSError, ValueError, UnicodeDecodeError):
                continue
            for 项 in (数据.get("能力列表") or []):
                if not isinstance(项, dict):
                    continue
                for 参 in (项.get("参数") or []):
                    if isinstance(参, dict) and 参.get("名称") == "超时秒":
                        声明过.add(str(项.get("能力id")))
                        值 = 参.get("默认值")
                        if isinstance(值, (int, float)) and not isinstance(值, bool) \
                                and float(值) >= 同步腿超时上限秒:
                            大超时集.add(str(项.get("能力id")))
                        break
        self.assertTrue(声明过, "构造前提失效：一条声明了 超时秒 的真实能力都没扫到")
        self.assertTrue(大超时集,
                        "没有任何真实能力默认 ≥10 ⇒ 本裁决对真实能力面空转（等于没落地）")
        写读腿 = {"文件系统支持库.文件操作.写入文件", "文件系统支持库.文件操作.读取文件",
                "文件系统支持库.文本补丁.应用精确替换",
                "文件系统支持库.文本补丁.批量应用精确替换"}
        误伤 = sorted(写读腿 & 大超时集)
        self.assertEqual(误伤, [],
                         f"这些写/读腿落进了 ≥10 集合，会让判据与工具链被自己拦死：{误伤}")


