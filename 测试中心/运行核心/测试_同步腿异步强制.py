"""同步腿异步强制（2026-09-23 华哥裁决）回归锁：`超时秒` 生效值 ≥ 10 ⇒ 只许走异步腿。

## 华哥裁决原文

> 「`超时秒`: 600 超过 10 的，都只能用 `异步` 的方式。如果是 10 以下的可以直接执行。
>   如果是 10 以上包含 10 的，都只允许使用异步，使用直接的方式，直接提示报错」

## 判据落点（唯一腿）

- **判据本体**：`运行核心/统一网关/核心处理/网关参数校验面.py::参数校验面._同步腿拒绝说明`
  （读 `注册表.获取(能力id).参数` 里 `名称 == "超时秒"` 那一项，算**本次生效值**）；
- **强制点**：`运行核心/统一网关/核心处理/网关执行面.py` 的「调用能力」分支内、
  `后端核心.调用(...)` **之前** —— 判不过当场拒，一个字节都不派发；
- 阈值常量 `同步腿超时上限秒 = 10.0` 与判据同文件（不另立第二处数字）。

## 生效值口径（三条，本文件逐条锁）

1. **调用方显式传了** `超时秒` ⇒ 用传的值（传 600 ⇒ 拒；传 5 ⇒ 放）；
2. **没传、契约声明了默认值** ⇒ 用默认值（这是 173/179 能力默认被拒的来源）；
3. **没传、契约 `默认值` 为空** ⇒ **放行**（不视为 ≥10）。理由：这 4 个能力
   （`并发控制支持库.获取信号量`/`获取锁`、`系统核心支持库.进程管理.启动进程`/
   `等待进程结束`）的说明文字明确写「不传则阻塞等待」—— 契约自己声明「不设超时」，
   生效值未知时拦它等于**凭空发明一个契约从未声明的默认阈值**（发明数据），比漏拦更坏。
   契约里**根本没有** `超时秒` 参数的能力同样放行（无超时语义，规则不适用）。

## 为什么判据必须读「契约自声明参数的生效值」而不是信封上的 `请求.超时秒`

`传输/网关边界面.py` 的 HTTP 边界**总是**用网关配置的 `请求超时秒`（1800）填充信封字段。
若拿信封值当判据，**每一次普通调用都会命中 ≥10 被拒**，等于把整个同步调用面打死。
⇒ 本文件的 `test_2_信封1800不得成为判据` 就是这条的反向锁。

## 反向验证（不在本文件里，报告里给原文）

把 `网关执行面` 里那三行守卫拆掉 ⇒ `test_1_显式大超时被拒` 必须**变红**；
把 `_同步腿拒绝说明` 里 `if 生效值 is None: return ""` 改成 `return "拒绝"` ⇒
`test_2_无默认值放行` 必须**变红**（防后人把「未知」当「≥10」）。
"""

