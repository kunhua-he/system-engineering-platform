#: 三个功能等价的假能力，唯一差别是契约里 `超时秒` 的**声明形状** ——
#: 本文件的判据全在这三者的对比上（同一入参、不同声明 ⇒ 不同结论）。
能力_默认60 = "测试支持库.同步腿.默认六十"
