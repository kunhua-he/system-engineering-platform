"""冷启动独立子进程脚本（C4 工作包专用，非测试文件，不会被测试收集器加载）。

每次运行都是一个全新 python3.14 解释器：由调用方清空工作区 PYTHONPATH，
本脚本自行把 系统根 与 暂存根 按顺序加入 sys.path（与生产 管理器.py
__main__ 自举方式一致），全程不 import 测试中心、不预注册、无历史单例。
只经生产装配入口执行：装配系统 / 创建并绑定 / 获取能力调用器。

用法：python3.14 测试中心/运行核心/冷启动脚本.py <模式> [参数...]
模式：
  未装配                          —— 只导入 调用器.py，获取能力调用器 必须失败
  构建提供者 <根目录> <提供者名>   —— 生成带合法 依赖锁.json 的合成第三方提供者
  装配 <根目录> <请求JSON>        —— 装配→注册→调用 全链路（请求含 能力表）
  重复装配 <根目录>               —— 同注册表连续装配两次（幂等）
  校验提供者环境 <根目录> <相对路径> —— 提供者依赖锁强制校验（fail-closed 门禁）
  组件合规 <根目录> <相对路径>     —— 组件合规 13/13 权威门禁（S0.4）
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]


def _输出(数据: dict) -> None:
    print(json.dumps(数据, ensure_ascii=False))


def 未装配模式() -> None:
    """未装配时获取能力调用器必须失败（只导入契约层，不触发惰性钩子）。"""
    sys.path.insert(0, str(系统根))
    from 公共契约.能力契约.调用器 import 获取能力调用器
    try:
        获取能力调用器()
        _输出({"失败": False, "错误": ""})
    except RuntimeError as 错误:
        _输出({"失败": True, "错误": str(错误)})


def 构建提供者模式(根目录: str, 提供者名: str) -> None:
    """构造带合法 依赖锁.json 的合成第三方提供者（外部应用，不触发 venv 构建）。"""
    根 = Path(根目录)
    _装配路径(根)
    from 运行核心.环境指纹 import 计算环境指纹

    指纹 = 计算环境指纹(含外部应用=False).详细信息
    系统名 = "macOS" if 指纹["os"] == "Darwin" else 指纹["os"]
    目录 = 根 / "支持库" / "适配层" / 提供者名
    目录.mkdir(parents=True, exist_ok=True)
    (目录 / "包声明.json").write_text(json.dumps({
        "包id": f"支持库.适配层.{提供者名}", "名称": 提供者名, "类型": "支持库",
        "版本": "1.0.0", "入口": "入口.py", "依赖": [],
        "能力": [{"能力id": f"{提供者名}.最小能力", "名称": "最小能力"}],
    }, ensure_ascii=False), encoding="utf-8")
    (目录 / "入口.py").write_text(
        "from 公共契约.能力契约.契约 import 能力实现\n\n"
        "def 注册能力(注册表):\n"
        f"    注册表.注册(能力实现(\n"
        f"        能力id={提供者名 + '.最小能力'!r}, 包id='支持库.适配层.{提供者名}',\n"
        f"        实现函数=lambda: {{'成功': True, '值': {提供者名!r}, '错误码': '', '错误说明': ''}}))\n",
        encoding="utf-8")
    契约数据 = {
        "契约版本": "1.0.0",
        "能力契约": [{
            "能力id": 提供者名 + ".最小能力", "版本": "1.0.0",
            "说明": "冷启动测试合成能力", "参数": [],
            "返回": {"类型": "dict", "说明": "统一结果"}, "错误码": [],
            "调用示例": "{}",
        }],
    }
    (目录 / "能力契约").mkdir(parents=True, exist_ok=True)
    (目录 / "能力契约" / "参数契约.json").write_text(
        json.dumps(契约数据, ensure_ascii=False), encoding="utf-8")
    (目录 / "依赖锁.json").write_text(json.dumps({
        "包": [{"名称": "冷启动测试工具", "版本": "1.0.0",
                "模块名": "冷启动测试工具", "来源": "外部应用"}],
        "提供者id": 提供者名, "直接依赖": [], "依赖闭包": [],
        "环境": {"Python": 指纹["python"], "操作系统": 系统名, "CPU": 指纹["架构"]},
        "生成时间": "", "说明": "C4 冷启动测试提供者依赖锁",
    }, ensure_ascii=False), encoding="utf-8")
    _输出({"成功": True, "提供者目录": str(目录)})


def _装配路径(根: Path) -> None:
    """暂存根必须在 sys.path 最前：暂存包（支持库/模块库）优先于仓库同名包。"""
    sys.path.insert(0, str(系统根))
    sys.path.insert(0, str(根))


def _调用转记录(调用结果) -> dict:
    """统一 结果 对象/普通字典/裸值 三种返回形态的调用记录。"""
    if isinstance(调用结果, dict):
        return {
            "成功": bool(调用结果.get("成功", True)),
            "值": 调用结果.get("值"),
            "错误码": str(调用结果.get("错误码", "")),
            "错误说明": str(调用结果.get("错误说明") or 调用结果.get("消息") or ""),
        }
    if hasattr(调用结果, "成功"):
        return {
            "成功": bool(调用结果.成功),
            "值": getattr(调用结果, "值", None),
            "错误码": getattr(调用结果, "错误码", ""),
            "错误说明": getattr(调用结果, "错误说明", ""),
        }
    return {"成功": True, "值": 调用结果, "错误码": "", "错误说明": ""}


def 装配模式(根目录: str, 请求文本: str) -> None:
    """装配→注册→调用 全链路：装配系统 → 创建并绑定 → 获取能力调用器 → 调用能力。"""
    根 = Path(根目录)
    _装配路径(根)
    from 公共契约.能力契约.契约 import 能力注册表
    from 运行核心.加载器.生命周期管理.管理器 import 装配系统
    from 运行核心.能力调用.唯一能力调用 import 创建并绑定
    from 公共契约.能力契约.调用器 import 获取能力调用器
    from 运行核心.统一网关.网关核心 import 网关核心
    from 运行核心.统一网关.本地网关 import 本地网关服务器
    from 运行核心.能力调用.HTTP连接器 import HTTP连接器

    请求 = json.loads(请求文本)
    # 门禁的空请求可以用 [] 表示；统一规范为对象，避免把合法的“无调用
    # 仅装配”请求当成异常并触发 list.get 假失败。
    if isinstance(请求, list):
        请求 = {"能力表": 请求}
    if not isinstance(请求, dict):
        raise ValueError("装配请求必须是对象或能力列表")
    注册表 = 能力注册表()
    结果 = 装配系统(根 / "支持库", 根 / "模块库", 注册表=注册表)
    输出 = {
        "装配成功": 结果.成功,
        "问题列表": 结果.问题列表,
        "跳过包列表": 结果.跳过包列表,
        "已注册能力数": 结果.已注册能力数,
        "声明能力数": 结果.声明能力数,
        "生命周期记录": [记录.转字典() for 记录 in 结果.生命周期记录],
    }
    服务 = 创建并绑定(注册表)
    # 文件管理模块已迁移到 HTTP：冷启动也必须启动真实回环网关并注入
    # 连接器，不能用进程内调用器伪造模块成功。
    class 冷启动后端代理:
        def __init__(self) -> None:
            self.注册表 = 注册表
            # HTTP 网关默认按统一契约为成功调用签发资源句柄；冷启动
            # 代理也必须提供同一句柄服务，不能因测试代理缺属性而把
            # 已完成的业务调用转换成“内部错误”。状态目录位于本次
            # 暂存根内，随冷启动进程结束由调用方统一清理。
            from 运行核心.资源协调 import 资源句柄服务
            self.资源句柄服务 = 资源句柄服务(根 / "工程缓存" / "权威状态")

        def 调用(self, 能力id, 参数=None, *, 上下文=None, 超时秒=10.0):
            return 服务.调用能力(能力id, 参数 or {}, 超时秒=超时秒)

    网关 = 本地网关服务器(
        网关核心实例=网关核心(冷启动后端代理()), 地址="127.0.0.1", 端口=0,
        配置={"禁止客户端身份": False, "要求凭证": False},
    )
    网关启动, 网关说明 = 网关.启动()
    if not 网关启动:
        raise RuntimeError(f"冷启动 HTTP 网关启动失败: {网关说明}")
    try:
        from 模块库.文件管理 import 设置HTTP连接器
        HTTP调用器 = HTTP连接器(网关地址="127.0.0.1", 网关端口=网关.端口)
        设置HTTP连接器(HTTP调用器)
        # 模块入口由装配器以独立模块对象加载，可能与此处 import 的包入口
        # 不是同一个 Python 模块；同步把连接器注入已注册函数的全局变量，
        # 确保冷启动实际调用的模块实现也经过 HTTP。
        for 已注册能力id in getattr(注册表, "能力id列表", []):
            if not 已注册能力id.startswith("文件管理."):
                continue
            实现对象 = 注册表.获取(已注册能力id)
            函数 = getattr(实现对象, "实现函数", None)
            if callable(函数) and isinstance(getattr(函数, "__globals__", None), dict):
                函数.__globals__["_连接器"] = HTTP调用器
    except ModuleNotFoundError:
        设置HTTP连接器 = lambda *_参数, **_关键字: None
    try:
        调用器 = 获取能力调用器()
        输出["调用器可用"] = True
        输出["调用结果表"] = []
        for 项 in 请求.get("能力表", []):
            调用结果 = 调用器.调用能力(项["能力id"], 项.get("参数") or {})
            记录 = {"能力id": 项["能力id"]}
            记录.update(_调用转记录(调用结果))
            历史 = 调用器.查询调用历史(1)
            证据: dict = {}
            if 调用器.证据链 is not None and 历史:
                for _证据 in 调用器.证据链.记录表.values():
                    if _证据.能力id == 项["能力id"]:
                        证据 = _证据.转字典()
                        break
            记录["证据"] = 证据
            记录["历史"] = 历史
            输出["调用结果表"].append(记录)
    except Exception as 错误:
        输出["调用器可用"] = False
        输出["调用器错误"] = str(错误)
    finally:
        设置HTTP连接器(None)
        网关.优雅停止()
    _输出(输出)


def 重复装配模式(根目录: str) -> None:
    """同一注册表连续装配两次：重复装配必须幂等（结果一致、不冲突）。"""
    根 = Path(根目录)
    _装配路径(根)
    from 公共契约.能力契约.契约 import 能力注册表
    from 运行核心.加载器.生命周期管理.管理器 import 装配系统
    from 运行核心.能力调用.唯一能力调用 import 创建并绑定
    from 公共契约.能力契约.调用器 import 获取能力调用器

    注册表 = 能力注册表()
    第一 = 装配系统(根 / "支持库", 根 / "模块库", 注册表=注册表)
    第二 = 装配系统(根 / "支持库", 根 / "模块库", 注册表=注册表)
    创建并绑定(注册表)
    调用结果 = 获取能力调用器().调用能力(
        "文件系统支持库.文件操作.写入文件",
        {"文件路径": str(根 / "幂等.txt"), "内容": "幂等重放", "编码": "utf-8"},
    )
    _输出({
        "第一次": {"成功": 第一.成功, "问题列表": 第一.问题列表,
                   "已注册能力数": 第一.已注册能力数},
        "第二次": {"成功": 第二.成功, "问题列表": 第二.问题列表,
                   "已注册能力数": 第二.已注册能力数},
        "重复装配后调用": {
            "成功": bool(getattr(调用结果, "成功", True)),
            "值": getattr(调用结果, "值", None),
            "错误码": getattr(调用结果, "错误码", ""),
        },
    })


def 校验提供者环境模式(根目录: str, 相对路径: str) -> None:
    """提供者依赖锁强制校验门禁（fail-closed：缺锁/漂移/环境不符一律拒绝）。"""
    根 = Path(根目录)
    _装配路径(根)
    from 运行核心.运行环境管理器.强制校验 import 校验提供者环境

    结果 = 校验提供者环境(根 / 相对路径)
    _输出(结果.转字典())


def 组件合规模式(根目录: str, 相对路径: str) -> None:
    """组件合规 13/13 权威门禁（S0.4）：契约/权限/摘要等任一缺项必须失败。

    合规门禁是仓库工具链（经 平台控制面/开发工具 解析 支持库.适配层 等），
    按生产语义只走仓库 sys.path；暂存组件目录按路径传入，不覆盖导入。
    """
    sys.path.insert(0, str(系统根))
    from 开发工具.组件合规.合规测试包 import 组件合规

    报告 = 组件合规(Path(根目录) / 相对路径).执行()
    _输出({
        "通过数": 报告.通过数,
        "总场景数": 报告.总场景数,
        "失败场景": [名 for 名, 通过, _ in 报告.场景结果表 if not 通过],
    })


模式表 = {
    "未装配": 未装配模式,
    "构建提供者": 构建提供者模式,
    "装配": 装配模式,
    "重复装配": 重复装配模式,
    "校验提供者环境": 校验提供者环境模式,
    "组件合规": 组件合规模式,
}


def 主入口() -> int:
    模式 = sys.argv[1]
    参数表 = sys.argv[2:]
    执行 = 模式表.get(模式)
    if 执行 is None:
        _输出({"错误": f"未知模式: {模式}"})
        return 1
    执行(*参数表)
    return 0


if __name__ == "__main__":
    raise SystemExit(主入口())
