class Test超时后排空计数不泄漏(超时资源夹具):
    """排空计数是「还有多少执行单元在跑」的权威口径（生产接线在后端核心）。"""

    def test_超时单元真结束后排空计数必须归还为零(self) -> None:
        排空 = 排空管理器(排空超时秒=0.2, 允许强制终止=False)
        执行器 = 超时执行器(全局执行线程上限=4, 每能力执行线程上限=2)
        执行器.接排空管理器(排空)
        self.assertEqual(排空.活动任务数, 0, "接线前后排空计数应为零")
        self.assertTrue(执行器.状态快照()["排空已接入"], "排空管理器必须已接入")

        结果, 残留 = 执行器.执行(lambda: time.sleep(1.5), 能力id="测试.排空挂死", 超时秒=0.15)

        # 超时瞬间：计数如实为 1（不谎报归零）—— 这就是「超时后仍有资源占用」的真相
        self.assertIsNone(结果, "到点未完成 ⇒ 按超时回报，不冒充结果")
        self.assertIsNotNone(残留)
        self.assertEqual(排空.活动任务数, 1, "超时瞬间执行单元仍在跑 ⇒ 排空计数必须如实为 1")
        self.assertEqual(执行器.状态快照()["全局执行线程占用"], 1)

        # 执行单元真结束后：计数与线程、槽位三者必须全部归零（不得泄漏）
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0),
                        "挂死实现跑完后执行线程必须归零")
        self.assertTrue(等待条件(lambda: 排空.活动任务数 == 0, 5.0),
                        f"执行单元结束后排空计数必须归还，实测 {排空.活动任务数}")
        self.assertEqual(执行器.状态快照()["全局执行线程占用"], 0, "准入槽位必须归还")

    def test_永远不结束的单元必须一直占着计数_不得谎报归零(self) -> None:
        """反向边界：计数若被伪造（提前归还），这条立刻变红。"""
        排空 = 排空管理器(排空超时秒=0.15, 允许强制终止=False)
        执行器 = 超时执行器(全局执行线程上限=4, 每能力执行线程上限=2)
        执行器.接排空管理器(排空)
        释放闸 = threading.Event()

        执行器.执行(lambda: 释放闸.wait(8.0), 能力id="测试.永不结束", 超时秒=0.1)
        time.sleep(0.3)

        self.assertEqual(排空.活动任务数, 1, "单元还卡着 ⇒ 计数必须仍为 1")
        排空结果 = 排空.排空()
        self.assertFalse(排空结果.成功, "有单元卡着时排空不得报成功")
        self.assertIn("活动任务 1", 排空结果.诊断记录,
                      f"排空诊断必须点名未完成的任务计数: {排空结果.诊断记录}")
        self.assertIn("排空超时", 排空结果.诊断记录)

        释放闸.set()
        self.assertTrue(等待条件(lambda: 排空.活动任务数 == 0, 10.0),
                        "释放后计数必须归还")


class Test超时路径版本锁与资源释放结论(超时资源夹具):
    """超时回报必须同时做到「版本锁已释放」与「仍占用的事实如实写出来」。"""

    def test_超时回报时版本锁已释放且结论如实(self) -> None:
        服务, 实现 = self.造服务()
        引用数调用前 = 服务.版本锁定.引用数(包id=包id, 版本=版本号)

        结果 = 服务.调用能力("测试.超时挂死", {}, 超时秒=0.15)

        self.assertFalse(结果.成功, "超时必须回报失败，不得拿实现后来返回的值冒充")
        self.assertEqual(结果.错误码, "超时")
        self.assertTrue(结果.可重试, "超时必须标可重试")
        # 版本锁：调用前无残留、超时回报时也无残留（不泄漏）
        self.assertEqual(引用数调用前, 0)
        self.assertEqual(服务.版本锁定.引用数(包id=包id, 版本=版本号), 0,
                         "超时回报时版本锁必须已释放")
        # 详情里必须点名残留执行单元（可区分结构），不假装已回收
        详情 = 结果.详细信息
        self.assertEqual(详情["能力id"], "测试.超时挂死")
        self.assertEqual(详情["超时秒"], 0.15)
        self.assertTrue(详情["残留执行"]["仍在运行"], "挂死单元此刻应仍在运行，必须如实标注")
        self.assertTrue(str(详情["残留执行"]["线程名"]).startswith(线程名前缀))
        # 证据链/调用历史里的资源释放结论必须两手都写：锁已释放 + 线程仍在跑
        记录 = 服务.查询调用历史(1)[0]
        self.assertEqual(记录["错误码"], "超时")
        结论 = 记录["资源释放结论"]
        self.assertIn("版本锁已释放", 结论, f"资源释放结论: {结论}")
        self.assertIn("仍在运行", 结论, "尚有执行单元在跑 ⇒ 必须如实写明，不得谎报已回收")
        self.assertIn("版本锁已释放", 记录["证据"]["资源释放结论"])

        # 执行单元真结束后：线程归零（真正的「资源已回收」）
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0),
                        "挂死实现跑完后执行线程必须归零")
        self.assertEqual(服务.版本锁定.引用数(包id=包id, 版本=版本号), 0)

    def test_超时后服务仍可继续正常调用_未被打挂(self) -> None:
        """反向边界：超时不得把服务自身搞坏（否则「回收」只是把整条链路弄死）。"""
        服务, _实现 = self.造服务()

        def 快(**参数):
            return "正常返回"

        服务.注册表.注册(能力实现(能力id="测试.正常", 包id=包id, 实现函数=快,
                                  参数=[], 返回="结果", 版本=版本号, 提供者版本=版本号,
                                  制品摘要="摘要正常"))
        超时结果 = 服务.调用能力("测试.超时挂死", {}, 超时秒=0.15)
        self.assertEqual(超时结果.错误码, "超时")

        正常结果 = 服务.调用能力("测试.正常", {}, 超时秒=5.0)
        self.assertTrue(正常结果.成功, f"超时之后服务必须仍可调用: {正常结果.错误说明}")
        self.assertEqual(正常结果.值, "正常返回")
        self.assertEqual(服务.版本锁定.引用数(包id=包id, 版本=版本号), 0,
                         "正常调用结束后版本锁同样不得残留")
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0))


class Test超时达上限后拒新调用(超时资源夹具):
    """⑤ 超时达上限 ⇒ 拒新调用：不许静默排队、不许拿「超时」冒充、不许真起执行单元。

    落点说明（为什么断言打在**调用面**而不是执行器上）：执行器侧的「满载判限流」
    已有 `测试中心/运行核心/测试_超时执行线程准入.py` 守护；本类补的是**调用方
    看到的形状** —— `唯一能力调用服务.调用能力` 走的是**进程级生产单例**
    `超时执行.执行器`，被拒时它必须原样把这一个「限流」失败信封交出去
    （而不是映射成「超时」或「内部错误」），并且**不得真去跑实现**。
    这条是「超时把资源吃满 → 后续调用被拒而非陪着一起挂」的最后一段可观测链。
    """

    版本号 = "1.0.0"

    def setUp(self) -> None:
        super().setUp()
        # 生产单例：调用面（调用能力）经 `_执行实现` 用的就是它，不是自造实例
        self.执行器 = 超时模块.执行器
        self.原全局上限 = self.执行器.全局执行线程上限
        self.原每能力上限 = self.执行器.每能力执行线程上限
        self.调用次数 = {"次": 0}
        self.释放闸 = threading.Event()

    def tearDown(self) -> None:
        self.释放闸.set()
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0),
                        f"挂死单元退出后执行线程必须归零（存活 {本前缀活线程数()} 条），"
                        f"否则单例的槽位与上限会漂进别的用例")
        self.执行器.全局执行线程上限 = self.原全局上限
        self.执行器.每能力执行线程上限 = self.原每能力上限

    def 造双能力服务(self):
        """同一服务里既有「挂死能力」也有「快能力」，用于验证隔离与恢复。"""
        注册表 = 能力注册表()

        def 挂死(**参数):
            self.调用次数["次"] += 1
            self.释放闸.wait(6.0)
            return "挂死实现迟到返回"

        def 快(**参数):
            self.调用次数["次"] += 1
            return "正常返回"

        注册表.注册(能力实现(能力id="测试.超时上限挂死", 包id="测试.超时上限包",
                            实现函数=挂死, 参数=[], 返回="结果", 版本=self.版本号,
                            提供者版本=self.版本号, 制品摘要="摘要超时上限挂死"))
        注册表.注册(能力实现(能力id="测试.超时上限快", 包id="测试.超时上限包",
                            实现函数=快, 参数=[], 返回="结果", 版本=self.版本号,
                            提供者版本=self.版本号, 制品摘要="摘要超时上限快"))
        return 唯一能力调用服务(注册表)

    def test_超时占满每能力上限后_新调用判限流且不冒充实超时(self) -> None:
        self.执行器.全局执行线程上限 = 4
        self.执行器.每能力执行线程上限 = 1   # 被守护的「上限」：额度就是这一格
        服务 = self.造双能力服务()
        拒绝数前 = self.执行器.状态快照()["累计准入拒绝数"]

        第一次 = 服务.调用能力("测试.超时上限挂死", {}, 超时秒=0.15)
        self.assertFalse(第一次.成功)
        self.assertEqual(第一次.错误码, "超时", f"错误说明: {第一次.错误说明}")
        self.assertEqual(self.调用次数["次"], 1, "第一次应真起了 1 个执行单元")

        开始 = time.monotonic()
        第二次 = 服务.调用能力("测试.超时上限挂死", {}, 超时秒=0.15)
        拒绝耗时 = time.monotonic() - 开始

        # ① 不许拿「超时」冒充：超时是上一次调用的结论，这一次的原因是资源满
        self.assertFalse(第二次.成功)
        self.assertEqual(第二次.错误码, "限流",
                         f"超时单元仍占着上限 ⇒ 新调用必须判限流，实测 "
                         f"{第二次.错误码!r}（说明 {第二次.错误说明}）")
        self.assertTrue(第二次.可重试, "限流必须标可重试（调用方按退避重试处理）")
        # ② 拒绝原因必须可区分：点名维度、闸门、上限值
        self.assertEqual(第二次.来源, "超时执行器.线程准入")
        准入门 = 第二次.详细信息["准入门"]
        self.assertEqual(准入门["维度"], "每能力")
        self.assertEqual(准入门["上限"], 1)
        self.assertEqual(准入门["能力id"], "测试.超时上限挂死")
        self.assertIn("不排队", str(第二次.错误说明))
        self.assertEqual(第二次.详细信息["每能力执行线程上限"], 1)
        # ③ 不许静默排队等待、不许真起新执行单元
        self.assertEqual(self.调用次数["次"], 1,
                         "被拒的调用不得真去执行实现（次数涨了＝拒了个假的）")
        self.assertLess(拒绝耗时, 1.0,
                        f"满载拒绝必须立刻返回（实测 {拒绝耗时:.3f}s，挂死实现需 6s）")
        # ④ 留痕如实：拒绝计入累计、占用按真实在跑读
        快照 = self.执行器.状态快照()
        self.assertEqual(快照["累计准入拒绝数"] - 拒绝数前, 1)
        self.assertEqual(快照["全局执行线程占用"], 1,
                         "被准入的挂死单元仍在跑 ⇒ 占用必须如实为 1")
        # ⑤ 调用历史逐条如实（限流不是内部错误，资源释放结论不得漏）
        记录 = 服务.查询调用历史(1)[0]
        self.assertEqual(记录["错误码"], "限流")
        self.assertIn("版本锁已释放", 记录["资源释放结论"])
        # ⑥ 不牵连：每能力闸门按能力隔离，别的能力不受这一格耗尽影响
        快结果 = 服务.调用能力("测试.超时上限快", {}, 超时秒=2.0)
        self.assertTrue(快结果.成功,
                        f"每能力饱和不得牵连本能力之外的调用: {快结果.错误说明}")
        self.assertEqual(快结果.值, "正常返回")

    def test_挂死单元退出后上限归还_同一能力立刻恢复可调用(self) -> None:
        """反向边界：拒绝必须是「达上限」，不是「把服务打挂」——槽位归还后即恢复。"""
        self.执行器.全局执行线程上限 = 4
        self.执行器.每能力执行线程上限 = 1
        服务 = self.造双能力服务()

        self.assertEqual(服务.调用能力("测试.超时上限挂死", {}, 超时秒=0.15).错误码, "超时")
        self.assertEqual(服务.调用能力("测试.超时上限挂死", {}, 超时秒=0.15).错误码, "限流")

        self.释放闸.set()
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0),
                        "挂死单元退出后执行线程必须归零")
        self.assertTrue(等待条件(lambda: self.执行器.状态快照()["全局执行线程占用"] == 0, 5.0),
                        "挂死单元退出后准入槽位必须归还")

        恢复结果 = 服务.调用能力("测试.超时上限挂死", {}, 超时秒=2.0)
        self.assertTrue(恢复结果.成功,
                        f"上限归还后同一能力必须立刻恢复可调用: {恢复结果.错误说明}")
        self.assertEqual(恢复结果.值, "挂死实现迟到返回")


class Test反向_准入旁路必红(超时资源夹具):
    """反向控制：把生产单例的准入旁路成「恒放行」⇒ 上一类必须变红。

    手法与 `测试中心/运行核心/测试_超时执行线程准入.py` 改写后端 `尝试占用`
    同一手法：在**真实生产对象**上做故障注入，`finally` 还原；不用
    `unittest.mock`、不伪造副作用。这里断言的是**退化形态本身**（第二次调用
    不再是限流而是超时、实现被真跑了第二次）—— 也就是
    `Test超时达上限后拒新调用` 判据的必要条件。若本条哪天变绿，说明那条断言
    不再钉得住「超时达上限拒新调用」这条不变式，需重新对口径。
    """

    版本号 = "1.0.0"

    def setUp(self) -> None:
        super().setUp()
        self.执行器 = 超时模块.执行器
        self.原全局上限 = self.执行器.全局执行线程上限
        self.原每能力上限 = self.执行器.每能力执行线程上限
        self.原准入 = self.执行器._准入
        self.调用次数 = {"次": 0}
        self.释放闸 = threading.Event()

    def tearDown(self) -> None:
        self.释放闸.set()
        self.执行器._准入 = self.原准入
        self.执行器.全局执行线程上限 = self.原全局上限
        self.执行器.每能力执行线程上限 = self.原每能力上限
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0),
                        f"旁路下多起的执行线程必须全部退出（存活 {本前缀活线程数()} 条）")

    def test_旁路准入后_第二次不再是限流而是一直起线程(self) -> None:
        self.执行器.全局执行线程上限 = 4
        self.执行器.每能力执行线程上限 = 1
        注册表 = 能力注册表()

        def 挂死(**参数):
            self.调用次数["次"] += 1
            self.释放闸.wait(6.0)
            return "挂死实现迟到返回"

        注册表.注册(能力实现(能力id="测试.旁路挂死", 包id="测试.旁路包",
                            实现函数=挂死, 参数=[], 返回="结果", 版本=self.版本号,
                            提供者版本=self.版本号, 制品摘要="摘要旁路挂死"))
        服务 = 唯一能力调用服务(注册表)

        # 注入点：准入恒放行（＝上游修复前的无界形态）
        self.执行器._准入 = lambda 能力id: ([], None, "")

        self.assertEqual(服务.调用能力("测试.旁路挂死", {}, 超时秒=0.15).错误码, "超时")
        第二次 = 服务.调用能力("测试.旁路挂死", {}, 超时秒=0.15)

        self.assertEqual(第二次.错误码, "超时",
                         "准入被旁路 ⇒ 第二次照旧起线程跑实现，必然还是超时；"
                         "若这里是「限流」，说明故障注入没生效（反向控制失效）")
        self.assertEqual(self.调用次数["次"], 2,
                         "准入被旁路 ⇒ 上限形同不存在，实现必须被真跑第二次")


