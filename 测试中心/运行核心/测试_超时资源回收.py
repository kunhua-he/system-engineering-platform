def 本前缀活线程数() -> int:
    """本模块执行线程的真实存活数（按线程名计数，不读内部计数）。"""
    return sum(1 for 线程 in threading.enumerate()
               if 线程.is_alive() and 线程.name.startswith(线程名前缀))


def 等待条件(条件, 超时秒: float = 10.0) -> bool:
    截止 = time.monotonic() + 超时秒
    while time.monotonic() < 截止:
        if 条件():
            return True
        time.sleep(0.01)
    return bool(条件())


class 超时资源夹具(unittest.TestCase):
    def setUp(self) -> None:
        # 前置隔离：上一条用例的挂死单元必须已退出，否则线程/闸门占用跨用例漂移
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0),
                        f"上一条用例的执行线程未退出（存活 {本前缀活线程数()} 条）")

    def 造服务(self) -> tuple[唯一能力调用服务, object]:
        """一个只注册「挂死实现」的最小调用服务（真实注册表，不打桩）。"""
        注册表 = 能力注册表()

        def 挂死(**参数):
            time.sleep(2.0)
            return "挂死实现迟到返回"

        实现 = 能力实现(能力id="测试.超时挂死", 包id=包id, 实现函数=挂死,
                        参数=[], 返回="结果", 版本=版本号, 提供者版本=版本号,
                        制品摘要="摘要超时资源")
        注册表.注册(实现)
        return 唯一能力调用服务(注册表), 实现


class Test超时后排空计数不泄漏(超时资源夹具):
    """排空计数是「还有多少执行单元在跑」的权威口径（生产接线在后端核心）。"""

    def test_超时单元真结束后排空计数必须归还为零(self) -> None:
        排空 = 排空管理器(排空超时秒=0.2, 允许强制终止=False)
        执行器 = 超时执行器(全局执行线程上限=4, 每能力执行线程上限=2)
        执行器.接排空管理器(排空)
        self.assertEqual(排空.活动任务数, 0, "接线前后排空计数应为零")
        self.assertTrue(执行器.状态快照()["排空已接入"], "排空管理器必须已接入")

        结果, 残留 = 执行器.执行(lambda: time.sleep(1.5), 能力id="测试.排空挂死", 超时秒=0.15)

        # 超时瞬间：计数如实为 1（不谎报归零）—— 这就是「超时后仍有资源占用」的真相
        self.assertIsNone(结果, "到点未完成 ⇒ 按超时回报，不冒充结果")
        self.assertIsNotNone(残留)
        self.assertEqual(排空.活动任务数, 1, "超时瞬间执行单元仍在跑 ⇒ 排空计数必须如实为 1")
        self.assertEqual(执行器.状态快照()["全局执行线程占用"], 1)

        # 执行单元真结束后：计数与线程、槽位三者必须全部归零（不得泄漏）
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0),
                        "挂死实现跑完后执行线程必须归零")
        self.assertTrue(等待条件(lambda: 排空.活动任务数 == 0, 5.0),
                        f"执行单元结束后排空计数必须归还，实测 {排空.活动任务数}")
        self.assertEqual(执行器.状态快照()["全局执行线程占用"], 0, "准入槽位必须归还")

    def test_永远不结束的单元必须一直占着计数_不得谎报归零(self) -> None:
        """反向边界：计数若被伪造（提前归还），这条立刻变红。"""
        排空 = 排空管理器(排空超时秒=0.15, 允许强制终止=False)
        执行器 = 超时执行器(全局执行线程上限=4, 每能力执行线程上限=2)
        执行器.接排空管理器(排空)
        释放闸 = threading.Event()

        执行器.执行(lambda: 释放闸.wait(8.0), 能力id="测试.永不结束", 超时秒=0.1)
        time.sleep(0.3)

        self.assertEqual(排空.活动任务数, 1, "单元还卡着 ⇒ 计数必须仍为 1")
        排空结果 = 排空.排空()
        self.assertFalse(排空结果.成功, "有单元卡着时排空不得报成功")
        self.assertIn("活动任务 1", 排空结果.诊断记录,
                      f"排空诊断必须点名未完成的任务计数: {排空结果.诊断记录}")
        self.assertIn("排空超时", 排空结果.诊断记录)

        释放闸.set()
        self.assertTrue(等待条件(lambda: 排空.活动任务数 == 0, 10.0),
                        "释放后计数必须归还")


class Test超时路径版本锁与资源释放结论(超时资源夹具):
    """超时回报必须同时做到「版本锁已释放」与「仍占用的事实如实写出来」。"""

    def test_超时回报时版本锁已释放且结论如实(self) -> None:
        服务, 实现 = self.造服务()
        引用数调用前 = 服务.版本锁定.引用数(包id=包id, 版本=版本号)

        结果 = 服务.调用能力("测试.超时挂死", {}, 超时秒=0.15)

        self.assertFalse(结果.成功, "超时必须回报失败，不得拿实现后来返回的值冒充")
        self.assertEqual(结果.错误码, "超时")
        self.assertTrue(结果.可重试, "超时必须标可重试")
        # 版本锁：调用前无残留、超时回报时也无残留（不泄漏）
        self.assertEqual(引用数调用前, 0)
        self.assertEqual(服务.版本锁定.引用数(包id=包id, 版本=版本号), 0,
                         "超时回报时版本锁必须已释放")
        # 详情里必须点名残留执行单元（可区分结构），不假装已回收
        详情 = 结果.详细信息
        self.assertEqual(详情["能力id"], "测试.超时挂死")
        self.assertEqual(详情["超时秒"], 0.15)
        self.assertTrue(详情["残留执行"]["仍在运行"], "挂死单元此刻应仍在运行，必须如实标注")
        self.assertTrue(str(详情["残留执行"]["线程名"]).startswith(线程名前缀))
        # 证据链/调用历史里的资源释放结论必须两手都写：锁已释放 + 线程仍在跑
        记录 = 服务.查询调用历史(1)[0]
        self.assertEqual(记录["错误码"], "超时")
        结论 = 记录["资源释放结论"]
        self.assertIn("版本锁已释放", 结论, f"资源释放结论: {结论}")
        self.assertIn("仍在运行", 结论, "尚有执行单元在跑 ⇒ 必须如实写明，不得谎报已回收")
        self.assertIn("版本锁已释放", 记录["证据"]["资源释放结论"])

        # 执行单元真结束后：线程归零（真正的「资源已回收」）
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0),
                        "挂死实现跑完后执行线程必须归零")
        self.assertEqual(服务.版本锁定.引用数(包id=包id, 版本=版本号), 0)

    def test_超时后服务仍可继续正常调用_未被打挂(self) -> None:
        """反向边界：超时不得把服务自身搞坏（否则「回收」只是把整条链路弄死）。"""
        服务, _实现 = self.造服务()

        def 快(**参数):
            return "正常返回"

        服务.注册表.注册(能力实现(能力id="测试.正常", 包id=包id, 实现函数=快,
                                  参数=[], 返回="结果", 版本=版本号, 提供者版本=版本号,
                                  制品摘要="摘要正常"))
        超时结果 = 服务.调用能力("测试.超时挂死", {}, 超时秒=0.15)
        self.assertEqual(超时结果.错误码, "超时")

        正常结果 = 服务.调用能力("测试.正常", {}, 超时秒=5.0)
        self.assertTrue(正常结果.成功, f"超时之后服务必须仍可调用: {正常结果.错误说明}")
        self.assertEqual(正常结果.值, "正常返回")
        self.assertEqual(服务.版本锁定.引用数(包id=包id, 版本=版本号), 0,
                         "正常调用结束后版本锁同样不得残留")
        self.assertTrue(等待条件(lambda: 本前缀活线程数() == 0, 10.0))


