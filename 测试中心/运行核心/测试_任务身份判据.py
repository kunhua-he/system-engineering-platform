"""独立任务身份判据回归测试：身份语义必须是**显式约束**，不是隐式默认。

审计 P2-13⑤ 现场：`运行核心/任务调度/任务进程.py` 的 `独立任务` 是手写类，
`self.等待队列` 用 `in` / `remove` 判身份（`提交` 与 `_退出排队`），但类上当时
**没有**任何 `__eq__` / `__hash__` / `@dataclass` —— 身份判定纯靠「手写类恰好没定义
`__eq__`」这个**隐式默认**。当时不会误判，但今后谁给它叠一个 `@数据类(相等=真)`，
队列身份判定会**静默失效**（不抛异常、不打日志，只是账本悄悄错）。

本文件是那件事的**机器判据**：把「必须按身份比较」钉死在断言里。今后谁把比较语义改成
按值，这里立刻变红。反向验证已实测：给类加 `@数据类(相等=真)`（或换成按字段比较的
`__eq__`）→ 本文件报红 → 还原 → 恢复绿。

**为什么这里必须身份比较（不是洁癖）**：同一条逻辑任务会同时存在多个对象 ——
池内存里的那个，和 `查询` 从磁盘快照重建的那个（`查询` 读 json 后新建 `独立任务`
再逐键 `setattr`），后者字段**逐字相同**。而 `提交` / `_退出排队` 问的是「**是不是我**」：
一旦变成按值比较，`in` / `remove` 会命中孪生对象，`_退出排队` 把别人的排队槽移除，
死条目永久占槽 → 后续正常提交被误判成「资源繁忙」，且没有任何调用方能再清理它。
"""

from __future__ import annotations

import json
import sys
import tempfile
import unittest
from pathlib import Path

if str(Path(__file__).resolve().parents[2]) not in sys.path:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from 运行核心.任务调度.任务进程 import 独立任务, 任务进程池  # noqa: E402
from 公共契约.基础类型.逻辑类型 import 真, 假  # noqa: E402


def 造配对任务() -> tuple[独立任务, 独立任务]:
    """造两个**字段逐字相同**但身份不同的任务对象（孪生对象的构造方式）。"""
    甲 = 独立任务(任务id="身份判据同id", 能力id="示例.快", 项目id="p", 用户id="u", 请求id="r")
    乙 = 独立任务(任务id="身份判据同id", 能力id="示例.快", 项目id="p", 用户id="u", 请求id="r")
    return 甲, 乙


class Test任务身份判据(unittest.TestCase):
    """身份语义的机器判据（比较语义一旦变成按值，本类断言立刻变红）。"""

    def setUp(self):
        self.临时对象 = tempfile.TemporaryDirectory(prefix="任务身份判据_")
        self.存储目录 = Path(self.临时对象.name) / "状态"
        self.池列表: list[任务进程池] = []

    def tearDown(self):
        for 池 in self.池列表:
            池.停止()
        self.临时对象.cleanup()

    def _新池(self, **参数) -> 任务进程池:
        池 = 任务进程池(存储目录=self.存储目录, **参数)
        self.池列表.append(池)
        return 池

    # ---- 第一层：身份语义在类上**显式声明**（不许只靠默认行为）----

    def test_比较语义显式绑定到解释器自带的对象身份比较(self):
        """`__eq__` / `__hash__` 必须在**类体**里，且就是 `object` 的身份实现。

        为什么必须是 `object.__eq__` 而不是「自己写一个 return self is 其他」：
        身份比较**只有解释器那一份实现**（哲学 1.2 同一件事不留两套），自己再写一遍
        就是第二套实现，两者必然漂移。为什么必须写在类体而不是 `__init__` 里：
        `dataclasses` 只认**类体里已定义**的 `__eq__` 为「已有定义」而拒绝覆盖；
        写在类体才能同时起到「显式声明」和「挡住后来者叠 `@数据类(相等=真)`」两个作用。
        """
        self.assertIn("__eq__", 独立任务.__dict__,
                      "身份比较必须是显式声明（写在类体），不能只靠『手写类恰好没定义 __eq__』的隐式默认")
        self.assertIn("__hash__", 独立任务.__dict__,
                      "身份比较必须成对显式声明 __hash__（可变对象按身份可哈希，与值比较不共存）")
        self.assertIs(独立任务.__eq__, object.__eq__,
                      "比较语义必须绑定到解释器自带的对象身份比较，不得自写第二套身份比较实现")
        self.assertIs(独立任务.__hash__, object.__hash__,
                      "哈希语义必须绑定到解释器自带的对象身份哈希")

    def test_类上没有生成按字段比较的数据类语义(self):
        """本类**不是**数据类：一旦谁叠上 `@数据类`，这里与上一条一起报红。

        `独立任务` **没有类级字段注解**，`@dataclass(eq=True)` 生成的 `__eq__` 比较的
        是空元组 → **任意两个实例都判为相等**（已实测），失效范围会拉满。所以「不是
        数据类」在本类不是风格问题，而是身份语义成立的前提。
        """
        self.assertFalse(hasattr(独立任务, "__dataclass_fields__"),
                         "独立任务不得被叠成数据类：它无类级字段注解，按字段比较会让任意两个实例判等")
        self.assertFalse(hasattr(独立任务, "__dataclass_params__"),
                         "独立任务不得被叠成数据类")

    # ---- 第二层：身份语义的**行为**判据 ----

    def test_字段逐字相同的两个对象互不相等且可独立哈希(self):
        甲, 乙 = 造配对任务()
        self.assertFalse(甲 == 乙, "字段逐字相同的两个独立任务必须互不相等（按身份比较）")
        self.assertTrue(甲 == 甲, "对象必须等于它自己（身份比较的自反性，队列 remove 靠它）")
        self.assertIsNot(甲, 乙)
        # 可哈希：身份语义下对象能进 set/dict（按值比较会 `__hash__ = None` 而抛 TypeError）
        self.assertEqual(len({甲, 乙}), 2, "两个身份不同的任务必须能同时进集合（身份可哈希）")
        self.assertEqual(hash(甲), hash(甲))

    def test_列表判身份按对象而非按字段(self):
        """`in` / `remove` 是队列的两条身份判定原语；按字段比较时它们会命中孪生对象。"""
        甲, 乙 = 造配对任务()
        队列 = [甲]
        self.assertIn(甲, 队列, "自己必须在自己的队列里")
        self.assertNotIn(乙, 队列, "孪生对象不得被当成『我在队列里』（否则提交会跳过入队）")
        self.assertEqual(len({*队列} & {乙}), 0, "集合判定同样必须只认身份")

    # ---- 第三层：`_退出排队` 会计不变式（死条目永久占槽的现场）----

    def test_退出排队只归还自己的槽孪生对象归还不掉(self):
        """`_退出排队(孪生)` 必须返回 `假` 且**不动**队列 —— 别人的槽不许被移除。

        现场危害：旧语义下若变成按值比较，`remove` 会把**别人的**排队槽移除（或该
        归还的槽归还不掉），死条目永久占槽，后续正常提交被误判成「资源繁忙」，
        且没有任何调用方能再清理它（只有 停止/排空 才整队清空）。

        `_退出排队` 内含 `提交条件.notify_all()`，生产路径一律在池锁内调用
        （`提交条件` 就是建在池锁上的），故本用例同样持锁调用。
        """
        池 = self._新池()
        甲, 乙 = 造配对任务()
        池.等待队列.append(甲)
        with 池.锁:
            self.assertFalse(池._退出排队(乙),
                             "孪生对象不得被认为占用过排队槽（按值比较会让它误命中并移除别人的槽）")
            self.assertEqual(池.等待队列, [甲], "孪生对象归还失败后，真正的排队槽必须原样保留")
            self.assertTrue(池._退出排队(甲), "本体必须能归还自己的排队槽")
            self.assertEqual(池.等待队列, [], "本体归还后排队槽必须真正释放")
            self.assertFalse(池._退出排队(甲), "重复归还是幂等的（返回 假，不再报占槽）")

    def test_排队槽记账与队列长度一致(self):
        """「入队即占槽、归还即释放」在身份语义下逐次对齐 —— 队列长度就是容量判据。"""
        池 = self._新池()
        甲, 乙 = 造配对任务()
        with 池.锁:
            池.等待队列.append(甲)
            池.等待队列.append(乙)
            self.assertEqual(len(池.等待队列), 2, "两个身份不同的任务必须各占一个槽")
            self.assertTrue(池._退出排队(甲))
            self.assertEqual(len(池.等待队列), 1, "归还一个槽后长度必须减一（不是一还全清）")
            self.assertEqual(池.等待队列, [乙], "剩下的必须是没归还的那个对象本体")

    # ---- 第四层：磁盘快照重建路径（孪生对象真实来源）----

    def test_查询重建的孪生对象不顶替池内对象的排队槽(self):
        """真实孪生来源：`查询` 读磁盘快照后**新建**对象再逐键 setattr。

        跳过 任务表 直查分支的办法：池内不登记该 id，只放快照文件，走 JSON 重建路径。
        重建对象字段与本体逐字相同 —— 这正是「按值比较会静默顶替」的现场。
        """
        池 = self._新池()
        甲 = 独立任务(任务id="快照孪生id", 能力id="示例.快", 项目id="p", 用户id="u", 请求id="r")
        甲.状态 = "运行中"
        快照文件 = self.存储目录 / f"{甲.任务id}.json"
        快照文件.write_text(json.dumps(甲.转字典(), ensure_ascii=False), encoding="utf-8")

        重建 = 池.查询("快照孪生id")

        self.assertIsNot(重建, 甲, "查询必须新建对象（同一逻辑任务的两个对象）")
        self.assertEqual(重建.任务id, 甲.任务id)
        self.assertEqual(重建.状态, 甲.状态, "重建对象字段与本体逐字相同 —— 按值比较必误判")
        self.assertFalse(重建 == 甲, "重建的孪生对象与本体必须互不相等（身份比较）")

        # 把本体放进等待队列，再用重建对象去做归还动作：绝不许动本体的槽
        池.等待队列.append(甲)
        self.assertNotIn(重建, 池.等待队列, "孪生对象不得被当成『本体已在队列里』")
        with 池.锁:
            self.assertFalse(池._退出排队(重建), "孪生对象不得归还本体的排队槽")
        self.assertIn(甲, 池.等待队列, "本体的排队槽必须完好保留")

    def test_快照往返不改变身份判定结论(self):
        """序列化 → 反序列化往返后，队列判定仍只认身份（防「往返后变按值比较」）。"""
        甲, 乙 = 造配对任务()
        往返 = json.loads(json.dumps(甲.转字典(), ensure_ascii=False))
        重建 = 独立任务(任务id=往返["任务id"], 能力id=往返["能力id"])
        for 键, 值 in 往返.items():
            if hasattr(重建, 键):
                setattr(重建, 键, 值)
        self.assertEqual(重建.任务id, 乙.任务id)
        self.assertFalse(重建 == 乙, "往返重建的对象与字段相同的既有对象必须互不相等")
        队列 = [乙]
        self.assertNotIn(重建, 队列, "往返后 `in` 判定必须仍是身份判定")
        self.assertIn(乙, 队列)


if __name__ == "__main__":
    unittest.main()
