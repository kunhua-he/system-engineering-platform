睡眠秒_五小时 = 5 * 3600.0


def 构造睡眠前后(睡眠秒: float = 睡眠秒_五小时):
    """构造「睡下」与「现在（刚醒）」两个时钟读数。

    真实语义：睡下时刻记 (墙钟 W0, 单调 M0)；睡眠期间墙钟走 `睡眠秒`、单调不走，
    故醒来记 (W0 + 睡眠秒, M0)。

    **基准必须锚在真实当前时刻**（`time.time()` / `time.monotonic()`），不能用固定
    epoch 常量：被测代码里 `句柄服务.状态()`、`权威状态.唤醒重判租约` 的判据都直接与
    `time.time()` 比，用一个与真实时钟无关的假 epoch 会让「是否过期」的结论由构造值
    决定而不是由被测逻辑决定 —— 那是自欺（本轮实测：固定 1.8e9 造出的「过期」租约
    在真实墙钟下其实还在未来，测试假绿）。
    """
    import time

    现在 = 时钟读数(墙钟=time.time(), 单调=time.monotonic())
    睡下 = 时钟读数(墙钟=现在.墙钟 - 睡眠秒, 单调=现在.单调)
    return 睡下, 现在


