class 假时钟:
    """把检测入口的两次采样替换成**构造好的读数**（模拟合盖睡眠）。

    为什么替换 `当前读数` 而不是只调纯函数：整条链路的输入就是「上一读数 + 本次读数」，
    只要该函数返回构造值，`采样并检测` / `取未处理唤醒` / 各组件入口走的都是**真实的
    检测与联动逻辑**（含发布、序号去重、唤醒重判），被测面不缩水。
    进去时基线先置为「睡下」读数，所以第一次采样就会算出完整跳变。
    """

    def __init__(self, 读数表: list) -> None:
        if len(读数表) < 2:
            raise ValueError("假时钟至少需要「睡下基线 + 醒来读数」两个值")
        self._读数表 = list(读数表)

    def __enter__(self):
        import 运行核心.时钟校准 as 校准
        self._校准 = 校准
        self._原函数 = 校准.当前读数
        # 第 0 个是「睡下」基线（不代表任何一次采样），采样从第 1 个（醒来）开始 ——
        # 于是**第一次采样就带着完整跳变**，不会白耗一次采样去建立基线。
        校准.重置检测基线(self._读数表[0])
        self._索引 = 1
        校准.当前读数 = self._下一个
        return self

    def _下一个(self):
        索引 = min(len(self._读数表) - 1, self._索引)
        self._索引 = 索引 + 1
        return self._读数表[索引]

    def 发布(self):
        """把「睡下 → 醒来」采样一次，由真实检测逻辑发布唤醒（返回判定）。"""
        return self._校准.采样并检测()

    def __exit__(self, *异常):
        self._校准.当前读数 = self._原函数
        self._校准.重置检测基线()
        return False


class 唤醒检测纯函数测试(unittest.TestCase):
    """第 1 关：判据本身。"""

    def test_五小时跳变判刚唤醒(self):
        睡下, 醒来 = 构造睡眠前后(睡眠秒_五小时)
        判定 = 判刚唤醒(睡下, 醒来)
        self.assertTrue(判定.刚唤醒, "5 小时墙钟跳变必须判刚唤醒")
        self.assertAlmostEqual(判定.睡眠秒, 睡眠秒_五小时, places=3)
        self.assertAlmostEqual(判定.单调增量, 0.0, places=6)
        self.assertAlmostEqual(判定.墙钟增量, 睡眠秒_五小时, places=3)
        # 睡眠窗口 = (醒来墙钟 − 睡眠秒, 醒来墙钟]
        self.assertAlmostEqual(判定.窗口起点墙钟, 睡下.墙钟, places=3)
        self.assertAlmostEqual(判定.窗口终点墙钟, 醒来.墙钟, places=3)

    def test_正常差值判未唤醒(self):
        """正常路径：两钟同速率，偏差增量是毫秒级噪声 → 必须不判唤醒。"""
        for 噪声 in (0.0, 0.001, 0.05, 1.0, 29.9):
            睡下 = 时钟读数(墙钟=1_800_000_000.0, 单调=100.0)
            醒来 = 时钟读数(墙钟=睡下.墙钟 + 噪声, 单调=睡下.单调 + 噪声)
            判定 = 判刚唤醒(睡下, 醒来)
            self.assertFalse(判定.刚唤醒, f"差值 {噪声} 秒不该判唤醒")
            self.assertEqual(判定.睡眠秒, 0.0)
            self.assertEqual(判定.窗口起点墙钟, 0.0)

    def test_阈值边界(self):
        """阈值 30 秒：29.9 不判、30.1 判（判据是严格大于）。"""
        睡下 = 时钟读数(墙钟=1_800_000_000.0, 单调=100.0)
        睡下秒 = 时钟读数(墙钟=睡下.墙钟 + 29.9, 单调=睡下.单调)
        self.assertFalse(判刚唤醒(睡下, 睡下秒).刚唤醒)
        超阈 = 时钟读数(墙钟=睡下.墙钟 + 30.1, 单调=睡下.单调)
        self.assertTrue(判刚唤醒(睡下, 超阈).刚唤醒)
        self.assertEqual(默认唤醒阈值秒, 30.0)

    def test_墙钟回拨不判睡眠(self):
        """墙钟被改回（NTP 反向校正）→ 偏差增量为负，不该判成睡眠。"""
        睡下 = 时钟读数(墙钟=1_800_000_000.0, 单调=100.0)
        回拨 = 时钟读数(墙钟=睡下.墙钟 - 600.0, 单调=睡下.单调 + 1.0)
        判定 = 判刚唤醒(睡下, 回拨)
        self.assertFalse(判定.刚唤醒)
        self.assertEqual(判定.睡眠秒, 0.0)

    def test_睡眠窗口归属(self):
        """窗口归属：睡下前就越过的截止 → 不在窗口内；睡眠期间越过的 → 在窗口内。"""
        睡下, 醒来 = 构造睡眠前后(睡眠秒_五小时)
        判定 = 判刚唤醒(睡下, 醒来)
        睡下前越过 = 睡下.墙钟 - 120.0        # 睡下前 2 分钟就到期
        sleep期间越过 = 睡下.墙钟 + 60.0      # 睡下后才到期
        self.assertFalse(落在睡眠窗口(睡下前越过, 判定))
        self.assertTrue(落在睡眠窗口(sleep期间越过, 判定))
        self.assertTrue(落在睡眠窗口(醒来.墙钟, 判定), "终点算在窗口内")
        self.assertFalse(落在睡眠窗口(睡下.墙钟, 判定), "起点不算在窗口内")

    def test_墙钟与单调互逆(self):
        """换算互逆 + 真实时钟的平台事实（单调时钟不可调 = 睡眠不推进它）。"""
        偏差 = 当前读数().偏差
        原值 = 1_799_000_000.0
        单调值 = 墙钟到单调(原值, 偏差=偏差)
        self.assertAlmostEqual(原值, 单调到墙钟(单调值, 偏差=偏差), places=6)
        self.assertAlmostEqual(单调值, 墙钟到单调(单调到墙钟(单调值, 偏差=偏差), 偏差=偏差),
                               places=6)
        信息 = __import__("time").get_clock_info("monotonic")
        self.assertFalse(信息.adjustable, "单调时钟不得可调（睡眠/改钟不推进它）")


class 唤醒重校准账本测试(unittest.TestCase):
    """第 2 关：唤醒即租约重判 + 启动路径。"""

    def setUp(self) -> None:
        self.临时目录 = tempfile.TemporaryDirectory(prefix="唤醒重校准_")
        self.目录 = Path(self.临时目录.name)

    def tearDown(self) -> None:
        self.临时目录.cleanup()

    def _建租约(self, 状态: 权威状态, *, 租约id: str, 截止: float, 心跳: float):
        """直接写一条活跃租约（绕过句柄，聚焦租约判据本身）。"""
        状态.保存租约(
            租约id=租约id, 资源id=f"资源-{租约id}", 项目id="测试", 所有者="测试",
            句柄id=0, 空闲超时秒=1800.0, 硬截止时间=截止, 最后心跳=心跳)

    @staticmethod
    def _读租约(状态: 权威状态, 租约id: str) -> dict:
        """直查账本真值（不经被测方法的返回值自述）。"""
        行 = 状态._连接().execute(
            "SELECT 租约id, 硬截止时间, 最后心跳, 已回收 FROM 租约 WHERE 租约id=?",
            (租约id,)).fetchone()
        assert 行 is not None, f"账本里找不到租约 {租约id}"
        return {"租约id": 行[0], "硬截止时间": 行[1], "最后心跳": 行[2], "已回收": 行[3]}

    def test_唤醒重判_睡眠期间越过的顺延_睡下前已过的维持原判(self):
        """核心判据：只有「睡眠期间才越过」的顺延，睡下前就越过的保持过期。"""
        状态 = 权威状态(self.目录 / "权威状态")
        睡下, 醒来 = 构造睡眠前后(睡眠秒_五小时)
        判定 = 判刚唤醒(睡下, 醒来)

        # 睡下那一刻仍在有效期内的三条（不同剩余量）
        self._建租约(状态, 租约id="睡中_A", 截止=睡下.墙钟 + 300.0, 心跳=睡下.墙钟)
        self._建租约(状态, 租约id="睡中_B", 截止=睡下.墙钟 + 3600.0, 心跳=睡下.墙钟)
        # 睡下前就已经越过截止的两条 → 真闲置/真超时
        self._建租约(状态, 租约id="真过期_A", 截止=睡下.墙钟 - 1.0, 心跳=睡下.墙钟 - 1.0)
        self._建租约(状态, 租约id="真过期_B", 截止=睡下.墙钟 - 7200.0, 心跳=睡下.墙钟 - 7200.0)
        # 边界：截止**恰好等于**睡下时刻（睡下那一刻就已经没有剩余）→ 属真过期。
        # 窗口是左开右闭 `(睡下, 现在]`，睡下时刻本身不在窗口内。这条专门钉住
        # 「窗口归属用 >= 还是 >」——本轮反向验证实测：不加这条，把判据改成 `>=`
        # 全套测试仍然全绿（边界未被覆盖 = 判据可被悄悄改坏）。
        self._建租约(状态, 租约id="边界_睡下时刻", 截止=睡下.墙钟, 心跳=睡下.墙钟)

        结果 = 状态.唤醒重判租约(判定)
        self.assertTrue(结果["刚唤醒"])
        self.assertAlmostEqual(结果["睡眠秒"], 睡眠秒_五小时, places=3)
        self.assertEqual(结果["顺延租约数"], 2, f"睡眠期间越过的应全部顺延: {结果}")
        self.assertEqual(结果["真过期租约数"], 3, f"睡下前已过（含边界）应维持原判: {结果}")

        # 逐条核对账本真值（不看返回值自述）
        顺延A = self._读租约(状态, "睡中_A")
        顺延B = self._读租约(状态, "睡中_B")
        self.assertAlmostEqual(顺延A["硬截止时间"], 睡下.墙钟 + 300.0 + 睡眠秒_五小时, places=3)
        self.assertAlmostEqual(顺延B["硬截止时间"], 睡下.墙钟 + 3600.0 + 睡眠秒_五小时, places=3)
        # 顺延后一律晚于「现在」，即不再过期
        self.assertGreater(顺延A["硬截止时间"], 睡下.墙钟 + 睡眠秒_五小时)
        self.assertGreater(顺延B["硬截止时间"], 睡下.墙钟 + 睡眠秒_五小时)
        self.assertEqual(顺延A["已回收"], 0, "顺延的租约不得被回收")
        self.assertEqual(顺延B["已回收"], 0)

        不重判A = self._读租约(状态, "真过期_A")
        不重判B = self._读租约(状态, "真过期_B")
        self.assertAlmostEqual(不重判A["硬截止时间"], 睡下.墙钟 - 1.0, places=3,
                               msg="睡下前就越过的截止不得被顺延（那是真超时）")
        self.assertAlmostEqual(不重判B["硬截止时间"], 睡下.墙钟 - 7200.0, places=3)
        边界 = self._读租约(状态, "边界_睡下时刻")
        self.assertAlmostEqual(边界["硬截止时间"], 睡下.墙钟, places=3,
                               msg="截止恰好等于睡下时刻不得被顺延（窗口左开右闭）")

    def test_唤醒重判_未唤醒零动作(self):
        """正常路径：不构成唤醒时账本一个字都不改。"""
        状态 = 权威状态(self.目录 / "权威状态")
        睡下 = 时钟读数(墙钟=1_800_000_000.0, 单调=100.0)
        正常 = 时钟读数(墙钟=睡下.墙钟 + 0.02, 单调=睡下.单调 + 0.02)
        判定 = 判刚唤醒(睡下, 正常)
        self.assertFalse(判定.刚唤醒)
        截止 = 睡下.墙钟 - 10.0
        self._建租约(状态, 租约id="甲", 截止=截止, 心跳=截止)
        结果 = 状态.唤醒重判租约(判定)
        self.assertFalse(结果["刚唤醒"])
        self.assertEqual(结果["顺延租约数"], 0)
        self.assertEqual(结果["真过期租约数"], 0)
        未动 = self._读租约(状态, "甲")
        self.assertAlmostEqual(未动["硬截止时间"], 截止, places=3)

    def test_唤醒重判_幂等(self):
        """同一次唤醒重复调用（多组件各问一次）：不得重复顺延（时间会越滚越长）。"""
        状态 = 权威状态(self.目录 / "权威状态")
        睡下, 现在 = 构造睡眠前后()
        判定 = 判刚唤醒(睡下, 现在)
        截止 = 睡下.墙钟 + 300.0
        self._建租约(状态, 租约id="甲", 截止=截止, 心跳=睡下.墙钟)
        第一 = 状态.唤醒重判租约(判定)
        第二次 = 状态.唤醒重判租约(判定)
        self.assertEqual(第一["顺延租约数"], 1)
        # 第二次：截止已被推到现在之后 → 不在过期候选里，零动作（不是再顺延一次）
        self.assertEqual(第二次["顺延租约数"], 0, "重复调用不得二次顺延")
        self.assertEqual(第二次["真过期租约数"], 0)
        记录 = self._读租约(状态, "甲")
        self.assertAlmostEqual(记录["硬截止时间"], 截止 + 睡眠秒_五小时, places=3,
                               msg="顺延必须只发生一次（重复调用会越滚越长）")

    def test_跨重启唤醒_启动路径判租约(self):
        """启动路径：睡下后进程被重启 → 靠落盘读数判唤醒，启动恢复不误判超时。"""
        目录 = self.目录 / "权威状态"
        状态 = 权威状态(目录)
        睡下, 醒来 = 构造睡眠前后()
        # 模拟「睡下那一刻」先落一次基线（用真实时钟写，再手工改写为睡眠前的读数）
        状态.记录时钟观测()
        连接 = 状态._连接()
        with 连接:
            连接.execute("UPDATE 元信息 SET 值=? WHERE 键=?",
                        (f"{睡下.墙钟!r}|{睡下.单调!r}", 状态.时钟观测键))
        # 醒来后重新打开（模拟重启）：落盘基线还在，但本次单调时钟已远大于睡下值
        # 这里直接注入判定而不是伪造真时钟：判据函数与运行期完全同一个
        判定 = 状态.检测跨重启唤醒(阈值秒=1.0)
        # 真实单调时钟已走过「睡下」的假值 100.0 秒 → 单调未回退，且墙钟增量巨大
        self.assertIsNotNone(判定, "落盘基线 + 大墙钟跳变 必须判跨重启唤醒")
        self.assertTrue(判定.刚唤醒)
        self.assertGreater(判定.睡眠秒, 默认唤醒阈值秒)

    def test_跨重启唤醒_单调回退判为重启非睡眠(self):
        """本机重启过（单调时钟归零回退）→ 不是睡眠，不得判唤醒。"""
        目录 = self.目录 / "权威状态"
        状态 = 权威状态(目录)
        连接 = 状态._连接()
        with 连接:
            连接.execute("INSERT INTO 元信息(键, 值) VALUES(?, ?) "
                        "ON CONFLICT(键) DO UPDATE SET 值=excluded.值",
                        (状态.时钟观测键, "1800000000.0|999999.0"))
        self.assertIsNone(状态.检测跨重启唤醒(阈值秒=1.0),
                          "单调时钟回退（重启）不得判成睡眠唤醒")


class 进程心跳时基测试(unittest.TestCase):
    """第 3 关：`进程.最后心跳` 改单调口径后，账本真删判据必须跟着收敛时基。

    背景（本轮验收实测出的真缺陷）：`最后心跳` 自 §9-B6 起由 `进程身份.心跳`
    写 `time.monotonic()`（≈6e5），而 `回收过期资源行` 的进程分支仍拿墙钟
    epoch 截止（≈1.79e9）比 —— 对任何单调值恒真 ⇒ 每轮清扫把**全部活进程行真删**。
    生产可达：`启动运行核心网关.py` 起 `资源账本维护循环`，每 300 秒一轮。
    """

    def setUp(self) -> None:
        self.临时目录 = tempfile.TemporaryDirectory(prefix="心跳时基_")
        self.状态 = 权威状态(Path(self.临时目录.name) / "权威状态")
        self.连接 = self.状态._连接()

    def tearDown(self) -> None:
        try:
            self.状态.关闭()
        except Exception:
            pass
        self.临时目录.cleanup()

    def _写进程行(self, 身份键: str, 心跳: float) -> None:
        with self.连接:
            self.连接.execute(
                "INSERT OR REPLACE INTO 进程 VALUES(?,?,?,?,?,?,?)",
                (身份键, 900001, "指纹", "测试", "测试", "实例", 心跳))

    def _剩余身份键(self) -> list[str]:
        return sorted(r[0] for r in self.连接.execute(
            "SELECT 身份键 FROM 进程").fetchall())

    def test_回收过期资源行_不得误删活进程行(self):
        """核心回归：心跳为单调值的活进程行，一轮清扫后必须还在。"""
        import time as _time
        现在墙钟 = _time.time()
        self._写进程行("活_单调", _time.monotonic())          # 本次改动后的正常口径
        self._写进程行("活_墙钟_刚写", 现在墙钟)               # 迁移期历史行（墙钟）
        self._写进程行("死_墙钟_30天前", 现在墙钟 - 30 * 86400.0)  # 真该删的远古行
        删除 = self.状态.回收过期资源行(保留窗口秒=7 * 24 * 3600.0)
        剩 = self._剩余身份键()
        self.assertIn("活_单调", 剩, f"活进程行（单调心跳）被误删: {删除}")
        self.assertIn("活_墙钟_刚写", 剩, f"迁移期活进程行（墙钟心跳）被误删: {删除}")
        self.assertNotIn("死_墙钟_30天前", 剩, "30 天前的远古行必须被真删（回收本意）")

    def test_存活进程身份表_认得单调心跳(self):
        """同一口径：活进程行在 `存活的进程身份表` 里必须可见。"""
        import time as _time
        self._写进程行("活_单调", _time.monotonic())
        存活 = [行["身份键"] for 行 in self.状态.存活的进程身份表()]
        self.assertIn("活_单调", 存活, f"活进程行不在存活表里: {存活}")


class 提供者唤醒重校准测试(unittest.TestCase):
    """第 2 关另一半：唤醒触发 reaper + 健康复查。"""

    def setUp(self) -> None:
        self.临时根 = Path(tempfile.mkdtemp(prefix="唤醒提供者_"))
        self.适配层根 = self.临时根 / "适配层"
        self.适配层根.mkdir()
        self.管理器 = 提供者生命周期管理器(self.适配层根)

    def tearDown(self) -> None:
        # 唤醒测试用的是**替身**进程（未真起子进程）：清表后再走生产清理路径，
        # 避免替身缺 优雅停止/强制终止 协议而把 tearDown 打挂（测不到被测逻辑）。
        self.管理器._进程表.clear()
        self.管理器._状态表.clear()
        self.管理器.清理全部()
        shutil.rmtree(self.临时根, ignore_errors=True)

    def test_未唤醒零动作(self):
        """正常路径：不构成唤醒时零额外动作（不回调 reaper/健康复查）。"""
        睡下 = 时钟读数(墙钟=1_800_000_000.0, 单调=100.0)
        正常 = 时钟读数(墙钟=睡下.墙钟 + 0.01, 单调=睡下.单调 + 0.01)
        结果 = self.管理器.唤醒重校准(判刚唤醒(睡下, 正常))
        self.assertFalse(结果["刚唤醒"])
        self.assertEqual(结果["复查进程数"], 0)
        self.assertEqual(结果["明细"], [])
        self.assertEqual(self.管理器._日志表, {}, "零动作时不得写任何日志")

    def test_唤醒触发reaper与健康复查(self):
        """伪造刚唤醒 → 必须走到 reaper（崩溃检测）与健康复查，并留下可核对的明细。"""
        调用痕迹: list[str] = []
        原崩溃检测 = self.管理器.崩溃检测
        原健康检查 = self.管理器.健康检查

        def 假崩溃检测(提供者id):
            调用痕迹.append(f"崩溃检测:{提供者id}")
            return 假  # 假设已恢复

        def 假健康检查(提供者id):
            调用痕迹.append(f"健康检查:{提供者id}")
            return 真

        self.管理器.崩溃检测 = 假崩溃检测
        self.管理器.健康检查 = 假健康检查
        try:
            # 进程表里塞两个「常驻提供者」（不真起进程：本测只验唤醒联动与调用顺序）
            self.管理器._进程表["提供者甲"] = 假常驻进程()
            self.管理器._进程表["提供者乙"] = 假常驻进程()
            睡下, 现在 = 构造睡眠前后()
            结果 = self.管理器.唤醒重校准(判刚唤醒(睡下, 现在))
        finally:
            self.管理器.崩溃检测 = 原崩溃检测
            self.管理器.健康检查 = 原健康检查

        self.assertTrue(结果["刚唤醒"])
        self.assertEqual(结果["复查进程数"], 2)
        self.assertEqual(结果["未恢复数"], 0)
        self.assertEqual(结果["健康数"], 2)
        # 顺序：每个提供者先 reaper 后健康复查（依赖顺序）
        self.assertEqual(调用痕迹, [
            "崩溃检测:提供者甲", "健康检查:提供者甲",
            "崩溃检测:提供者乙", "健康检查:提供者乙"], f"动作顺序错: {调用痕迹}")
        self.assertIn("唤醒重校准", self.管理器._日志表, "唤醒重校准必须留日志")

    def test_唤醒重校准_单个提供者失败不拖垮其余(self):
        """一个提供者复查抛错 → 余下照走，且必须留痕（不静默）。"""
        def 会炸的崩溃检测(提供者id):
            if 提供者id == "坏的":
                raise RuntimeError("模拟复查失败")
            return 假

        self.管理器.崩溃检测 = 会炸的崩溃检测
        self.管理器.健康检查 = lambda 提供者id: 真
        self.管理器._进程表["坏的"] = 假常驻进程()
        self.管理器._进程表["好的"] = 假常驻进程()
        睡下, 现在 = 构造睡眠前后()
        结果 = self.管理器.唤醒重校准(判刚唤醒(睡下, 现在))
        self.assertEqual(结果["复查进程数"], 2)
        self.assertEqual(结果["健康数"], 1, "好的那个必须照常复查")
        坏项 = [项 for 项 in 结果["明细"] if 项["提供者id"] == "坏的"]
        self.assertTrue(坏项 and "异常" in 坏项[0]["崩溃检测"])


class 句柄服务唤醒重判测试(unittest.TestCase):
    """第 2 关另一半：句柄内存快照不被睡前的旧判定抹掉。"""

    def setUp(self) -> None:
        self.临时目录 = tempfile.TemporaryDirectory(prefix="唤醒句柄_")
        self.服务 = 资源句柄服务(Path(self.临时目录.name), 默认超时秒=1800)

    def tearDown(self) -> None:
        self.服务.关闭服务()
        self.临时目录.cleanup()

    def test_睡眠窗口内到期的句柄唤醒后仍有效(self):
        """核心回归：睡下后到期的句柄，唤醒后 `状态()` 不得立刻判超时失效。

        走**完整真实链路**（不手改内部状态）：喂入「睡下 → 醒来」两个假读数，
        由 `采样并检测` 发布唤醒 → `句柄服务.唤醒重判` 取到未处理唤醒 →
        账本顺延 + 内存快照懒刷新 → `状态()` 给出结论。
        """
        句柄 = self.服务.创建(资源id="资源-唤醒", 项目id="测试", 所有者="测试")
        句柄id = 句柄["句柄"]
        睡下, 现在 = 构造睡眠前后()
        状态 = self.服务.权威状态
        租约 = 状态.读取租约(int(句柄id))
        # 把账本与内存快照都改写成「睡下那一刻、仅剩 300 秒」的真实姿态
        连接 = 状态._连接()
        with 连接:
            连接.execute("UPDATE 租约 SET 硬截止时间=?, 最后心跳=? WHERE 租约id=?",
                        (睡下.墙钟 + 300.0, 睡下.墙钟, 租约["租约id"]))
        对象 = self.服务.句柄体系.查询句柄(句柄id)
        对象.元数据["租约截止"] = 睡下.墙钟 + 300.0
        对象.元数据["最后心跳"] = 睡下.墙钟

        with 假时钟([睡下, 现在]):
            公开 = self.服务.状态(句柄id, 项目id="测试", 所有者="测试")
        self.assertEqual(公开["状态"], "有效",
                         f"睡眠窗口内到期的句柄不得被判超时失效: {公开}")
        刷新后 = float(公开["元数据"]["租约截止"])
        self.assertGreater(刷新后, 睡下.墙钟 + 300.0, "内存快照必须跟上账本顺延值")
        # 账本侧也必须真被顺延（不看内存快照自述）
        账本 = 状态.读取租约(int(句柄id))
        self.assertGreater(float(账本["硬截止时间"]), 睡下.墙钟 + 300.0)

    def test_睡下前就已过期的句柄维持失效(self):
        """睡下前就越过截止的句柄：唤醒重判**不**该把它救活（那是真超时）。"""
        句柄 = self.服务.创建(资源id="资源-真过期", 项目id="测试", 所有者="测试")
        句柄id = 句柄["句柄"]
        睡下, 现在 = 构造睡眠前后()
        状态 = self.服务.权威状态
        租约 = 状态.读取租约(int(句柄id))
        连接 = 状态._连接()
        with 连接:
            连接.execute("UPDATE 租约 SET 硬截止时间=?, 最后心跳=? WHERE 租约id=?",
                        (睡下.墙钟 - 60.0, 睡下.墙钟 - 60.0, 租约["租约id"]))
        对象 = self.服务.句柄体系.查询句柄(句柄id)
        对象.元数据["租约截止"] = 睡下.墙钟 - 60.0
        with 假时钟([睡下, 现在]):
            公开 = self.服务.状态(句柄id, 项目id="测试", 所有者="测试")
        self.assertEqual(公开["状态"], "已失效", f"真过期的句柄必须仍判失效: {公开}")
        账本 = 状态.读取租约(int(句柄id))
        self.assertLess(float(账本["硬截止时间"]), 睡下.墙钟,
                        "睡下前就已越过的截止不得被顺延")

    def test_正常路径零影响(self):
        """未检测到唤醒时：`唤醒重判()` 返回 None，账本与句柄行为一个字不变。"""
        句柄 = self.服务.创建(资源id="资源-正常", 项目id="测试", 所有者="测试")
        句柄id = 句柄["句柄"]
        快照 = self.服务.状态(句柄id, 项目id="测试", 所有者="测试")
        # 连续多次热路径调用（模拟正常请求流）：每次都必须零动作
        for _ in range(5):
            self.assertIsNone(self.服务.唤醒重判(),
                              "未发生睡眠时唤醒重判不得返回判定（即零动作）")
        再次 = self.服务.状态(句柄id, 项目id="测试", 所有者="测试")
        self.assertEqual(再次["状态"], "有效")
        self.assertAlmostEqual(float(再次["元数据"]["租约截止"]),
                               float(快照["元数据"]["租约截止"]), places=6,
                               msg="正常路径不得改动租约截止时间")


