"""危险能力授权门（阶段一）回归锁：能力级档位下沉 + 默认范围含「管理员」⇒ 零行为变化。

## 缺的是什么

`操作权限表` 只细到「**操作**」—— `调用能力` 一个档位盖住全部能力，只读查询
（`平台控制面.能力目录.查询文件租约`）与「任意命令执行」（`系统核心支持库.进程管理.执行命令`）
**同权**。⇒ 危险能力事实上**没有按能力的授权门**。

## 阶段一做了什么（本轮）

1. `操作协议表.能力权限表`（能力id → 档位）就位，只给「能执行任意代码/命令」与
   「能提权」两类挂新档「管理员」；
2. `网关处理面._权限通过` 在 `调用能力` 上**下沉**读这张表（取不到回落操作级档位）；
3. 默认权限范围（`安全/安全边界.py` 与 `本地网关.py` 两处）**加入「管理员」**
   ⇒ 危险能力照旧放行，**现有调用方一个都不受影响** —— 这是阶段一敢上的唯一依据。

阶段二（**不在本轮**）＝ 从上述两处删掉「管理员」＋给调用方按能力授权声明通道，
一行之差、可随时回滚。

## 判据（任一条红即门失效）

1. **表就位且不空转**：`能力权限表` 非空，且每个键都是**真实存在**的能力 id
   （对着 能力定义.json 核，防拍脑袋填一个不存在的 id —— 那种键永远命中不了，门是死的）；
2. **档位真在操作级档位之外**：「管理员」不能同时是 `操作权限表` 的取值，否则下沉没意义；
3. **默认范围含「管理员」**：阶段一零行为变化的唯一依据，缺了它现有调用方当场被拒；
4. **真下沉**：同一危险能力，权限范围**缺**「管理员」→ 拒（`权限不足`）；
   范围**含**「管理员」→ 放 —— 两条必须成对，只测一条会漏掉「恒拒」或「恒放」的假绿；
5. **不误伤**：不在 `能力权限表` 里的只读能力，范围 `{查询,调用,任务}` → 照旧放行
   （证明下沉是**按能力**的，不是一刀切）。

## 反向验证（不在本文件里，报告里给原文）

把 `_权限通过` 的能力级下沉那几行拆掉（回退成只看操作级档位）⇒ 第 4 条的「缺管理员必须拒」
必须**变红**；把「管理员」从默认权限范围两处删掉 ⇒ 第 3 条必须**变红**。
"""

from __future__ import annotations

import json
import sys
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 运行核心.统一网关.网关核心 import 网关核心
from 运行核心.统一网关.协议.网关信封 import 网关请求
from 运行核心.统一网关.协议.操作协议表 import 操作权限表, 能力权限表
from 运行核心.统一网关.安全.安全边界 import 安全配置
from 公共契约.基础类型.逻辑类型 import 真, 假

#: 代表性危险能力（能执行任意命令）与代表性只读能力（不在 能力权限表 内）。
危险能力 = "系统核心支持库.进程管理.执行命令"
只读能力 = "系统核心支持库.进程管理.查询进程状态"

#: 阶段一默认权限范围（两处默认值同源）与阶段二范围（只差「管理员」一项）。
阶段一范围 = set(安全配置().默认权限范围)
阶段二范围 = 阶段一范围 - {"管理员"}

排除目录段 = frozenset({
    "工程缓存", "开发文档", "__pycache__", ".git", ".venv",
    "node_modules", "参考资料", "dist", "build", ".egg-info",
})


def 全仓能力id() -> set[str]:
    """扫 能力定义.json 收全部真实能力 id（只 glob，不装配；避开制品环境）。"""
    结果: set[str] = set()
    for 定义 in 系统根.rglob("能力定义.json"):
        if any(段 in 定义.parts for 段 in 排除目录段):
            continue
        try:
            数据 = json.loads(定义.read_text(encoding="utf-8"))
        except (OSError, ValueError, UnicodeDecodeError):
            continue
        for 项 in (数据.get("能力列表") or []):
            能力id = 项.get("能力id") if isinstance(项, dict) else 项
            if isinstance(能力id, str) and 能力id:
                结果.add(能力id)
    return 结果


class 假实现:
    def __init__(self) -> None:
        self.参数: list = []
        self.返回 = "结果"


class 假注册表:
    def __init__(self, 能力表: dict) -> None:
        self.能力表 = dict(能力表)

    @property
    def 能力id列表(self) -> list:
        return list(self.能力表)

    def 获取(self, 能力id: str):
        return self.能力表.get(能力id)


class 假结果:
    def __init__(self) -> None:
        self.成功 = 真
        self.值 = {"跑过": 真}
        self.错误码 = ""
        self.错误说明 = ""


class 假后端:
    """只实现网关在 调用能力 这条路上真正用到的面：注册表 + 调用。"""

    def __init__(self) -> None:
        self.注册表 = 假注册表({危险能力: 假实现(), 只读能力: 假实现()})

    def 调用(self, 能力id: str, 参数: dict, *, 上下文=None, 超时秒=None) -> 假结果:
        return 假结果()


def 建网关() -> 网关核心:
    return 网关核心(假后端(), 幂等持久化=假)


def 调(网关: 网关核心, 能力id: str, 权限范围):
    return 网关.处理(网关请求(操作="调用能力", 能力id=能力id, 参数={},
                              权限范围=sorted(权限范围)))


class 危险能力授权门(unittest.TestCase):
    def test_1_能力权限表就位且键都是真实能力id(self) -> None:
        self.assertTrue(能力权限表, "能力权限表 为空 —— 能力级下沉腿是死的")
        真实 = 全仓能力id()
        self.assertTrue(真实, "构造前提失效：一条能力 id 都没扫到")
        不存在 = sorted(k for k in 能力权限表 if k not in 真实)
        self.assertEqual(
            不存在, [],
            f"能力权限表 里这些键不是真实能力 id：{不存在}。"
            "填不存在的 id 等于永远命中不了，门是死的（不许拍脑袋填）。")

    def test_2_档位在操作级档位之外(self) -> None:
        self.assertNotIn(
            "管理员", set(操作权限表.values()),
            "「管理员」不能同时是操作级档位 —— 那样下沉到能力级就没有新档可挂")
        self.assertEqual(set(能力权限表.values()), {"管理员"},
                         f"能力权限表 档位应为「管理员」，实测 {set(能力权限表.values())}")

    def test_3_阶段一默认范围含管理员(self) -> None:
        """阶段一零行为变化的唯一依据。★ 阶段二（不在本轮）删掉「管理员」后本断言必须同改。"""
        self.assertIn(
            "管理员", 阶段一范围,
            "默认权限范围不含「管理员」⇒ 危险能力当场被拒，阶段一不许这样上")
        self.assertEqual(阶段一范围, {"查询", "调用", "任务", "管理员"},
                         f"阶段一默认范围应为 查询/调用/任务/管理员，实测 {阶段一范围}")

    def test_3b_两处默认范围同源(self) -> None:
        """两处默认值必须都含「管理员」——只改一处会让两条入口行为分叉。"""
        源 = (系统根 / "运行核心" / "统一网关" / "本地网关.py").read_text(encoding="utf-8")
        self.assertIn('{"查询", "调用", "任务", "管理员"}', 源,
                      "本地网关.py 的默认权限范围缺「管理员」（两处默认值已分叉）")

    def test_4_真下沉_缺管理员必须拒(self) -> None:
        响应 = 调(建网关(), 危险能力, 阶段二范围)
        self.assertFalse(响应.成功, f"危险能力在缺「管理员」时仍被放行：{响应.转字典()}")
        self.assertEqual(响应.错误码, "权限不足", 响应.转字典())

    def test_4b_真下沉_含管理员必须放(self) -> None:
        """与 test_4 成对：只测「拒」会漏掉「恒拒」这种假绿。"""
        响应 = 调(建网关(), 危险能力, 阶段一范围)
        self.assertTrue(响应.成功, f"危险能力在含「管理员」时被拒了：{响应.转字典()}")
        self.assertEqual(响应.值, {"跑过": 真}, "放行了但没真的走到能力实现（空转）")

    def test_5_不误伤_只读能力照旧放行(self) -> None:
        响应 = 调(建网关(), 只读能力, 阶段二范围)
        self.assertTrue(响应.成功, f"只读能力被下沉误伤了：{响应.转字典()}")
        self.assertEqual(响应.值, {"跑过": 真}, "放行了但没真的走到能力实现（空转）")


if __name__ == "__main__":
    unittest.main()
