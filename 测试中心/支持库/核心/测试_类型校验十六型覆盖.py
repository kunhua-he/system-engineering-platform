"""`类型转换.校验类型` 的 16 型全覆盖验收（E-8 收口，2026-09-19）。

**为什么要有这个测试**：收口前 `校验类型` 的 `委托校验表` 只有 2 项 ＋ 数值 4 型
= **6/16**，其余 10 个正式类型一律回「缺公共契约校验层」（实测形态见本包交付记录）。
收口后 16 型全绿。本测试逐型真调，**每个类型都给正例与反例**，防止「补了个函数但
判据是恒真」的假绿——只测正例的测试挡不住恒真实现。

**读值口径**（易错点，实测踩过）：`校验类型` 返回的是 `结果型<逻辑型>` 信封——
外层 `成功` 表示「这次校验跑通了」，**判定结论在信封内的 `值`**。只读外层 `成功`
会把「拒绝」误读成「放行」（本测试首版就这么错过，已改）。
"""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[3]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 公共契约.基础类型.类型表 import 正式类型表
from 公共契约.基础类型.逻辑类型 import 真, 假
from 支持库.后端.数据操作支持库.类型转换.实现.类型转换 import 校验类型


def _判(值, 目标类型) -> tuple[bool, bool, str]:
    """真调一次，返回 (信封是否成功, 判定结论, 错误说明)。

    判定结论取自信封内的 `值`（唯一正确读法）。
    """
    结果对象 = 校验类型(值, 目标类型)
    return bool(结果对象.成功), bool(结果对象.值), str(结果对象.错误说明)


# 逐型 (正例, 反例)：反例必须是「容易误判为真」的那种，不能拿明显不相干的值糊弄。
案例表: dict[str, tuple[object, object]] = {
    "逻辑型": (真, 1),
    "文本型": ("abc", 123),
    "整数型": (7, 真),
    "长整数型": (2**100, "1"),
    "单精度数型": (1.5, 10**60),
    "双精度数型": (1.5, 1),
    "字节型": (200, 256),
    "字节集型": (b"\x01", 3),
    "列表型": ([1, 2], (1, 2)),
    "字典型": ({"a": 1}, {1: "a"}),
    "日期时间型": ("2026-09-19T13:05:00+08:00", "下周三"),
    "资源引用型": (object(), "不是资源"),
    "句柄型": ("123456", "abc"),
    "结果型": ({"成功": 真}, {"成功": 1}),
    "空值型": (None, ""),
    "JSON值型": ({"a": [1, 2]}, float("nan")),
}


class 测试校验类型十六型覆盖(unittest.TestCase):
    def test_案例表与正式类型表等宽(self) -> None:
        """本测试必须覆盖全部 16 个正式类型名，且不多不少（防止新增类型漏测）。"""
        self.assertEqual(set(案例表), set(正式类型表),
                         f"案例表与正式类型表不等宽：缺 {正式类型表 - set(案例表)}，"
                         f"多 {set(案例表) - 正式类型表}")

    def test_逐型正例放行反例拒绝(self) -> None:
        for 类型名, (正例, 反例) in 案例表.items():
            with self.subTest(类型=类型名, 方向="正例"):
                信封成功, 结论, 说明 = _判(正例, 类型名)
                self.assertTrue(信封成功, f"{类型名} 正例：信封应成功，说明={说明}")
                self.assertTrue(结论, f"{类型名} 的正例 {正例!r} 必须判合格")
            with self.subTest(类型=类型名, 方向="反例"):
                信封成功, 结论, 说明 = _判(反例, 类型名)
                self.assertTrue(信封成功, f"{类型名} 反例：信封应成功（判定跑通），说明={说明}")
                self.assertFalse(结论, f"{类型名} 的反例 {反例!r} 必须判不合格")

    def test_再无缺公共校验层的正式类型(self) -> None:
        """16 型逐一真调，任何一型回「缺公共契约校验层」即为收口未完成（判红）。"""
        缺口 = []
        for 类型名 in sorted(正式类型表):
            信封成功, 结论, 说明 = _判(案例表[类型名][0], 类型名)
            if not 信封成功 or "缺公共契约校验层" in 说明:
                缺口.append((类型名, 说明))
        self.assertEqual(缺口, [], f"仍有正式类型无公共校验层：{缺口}")

    def test_非正式类型名仍明确拒绝(self) -> None:
        """历史短名／自造名 → 失败「未知目标类型」；空文本 → 失败「必须是非空文本」。

        两者都是**信封失败**（不是「判定为不合格」）：名字不合法时没有可判定的类型，
        必须明确报错而不是静默回一个「不合格」。
        """
        for 坏名 in ("文本", "数值型", "字符串型", "对象型", "浮点数"):
            信封成功, _, 说明 = _判("x", 坏名)
            self.assertFalse(信封成功, f"非正式类型名 {坏名!r} 必须回信封失败")
            self.assertIn("未知目标类型", 说明, f"{坏名!r} 的说明：{说明}")
        for 空名 in ("", None):
            信封成功, _, 说明 = _判("x", 空名)
            self.assertFalse(信封成功, f"空类型名 {空名!r} 必须回信封失败")
            self.assertIn("非空文本", 说明, f"{空名!r} 的说明：{说明}")

    def test_数值型反例走边界而非抛异常(self) -> None:
        """数值型的非法值必须判「不合格」，不得把 `校验数值类型` 的异常漏出去。"""
        信封成功, 结论, 说明 = _判(真, "整数型")
        self.assertTrue(信封成功, f"布尔校验整数型：信封应成功，说明={说明}")
        self.assertFalse(结论, "布尔不得混入整数型")
        信封成功, 结论, _ = _判(10**60, "单精度数型")
        self.assertTrue(信封成功)
        self.assertFalse(结论, "10**60 超出单精度范围，必须判不合格")


if __name__ == "__main__":
    unittest.main()
