"""模块库.直播逐字稿 实现.有效底稿 单元测试：死循环剔除与有效文本。

覆盖：区间内/外判定、边界（起点 0.0 的段必须保留）、空区间原样返回、
多区间合并剔除、有效文本拼接、剔除摘要数字、坏数据不抛异常。
"""

from __future__ import annotations

import re
import sys
import unittest
from pathlib import Path

项目根 = Path(__file__).resolve().parents[2]
if str(项目根) not in sys.path:
    sys.path.insert(0, str(项目根))

from 模块库.直播逐字稿.实现.有效底稿 import (在死循环区间, 压缩段内重复, 剔除摘要, 剔除死循环,
                                          折叠循环话术, 清洗分段, 是幻觉段, 有效文本)


def 造段(开始: float, 结束: float, 文本: str) -> dict:
    return {"分片序号": 1, "序号": 1, "开始秒": 开始, "结束秒": 结束, "文本": 文本}


class Test死循环剔除(unittest.TestCase):
    def test_区间外分段保留(self):
        段 = 造段(0.0, 5.0, "正常发言")
        self.assertFalse(在死循环区间(段, [{"开始秒": 600.0, "结束秒": 900.0}]))

    def test_区间内分段命中(self):
        段 = 造段(700.0, 705.0, "幻觉重复")
        self.assertTrue(在死循环区间(段, [{"开始秒": 600.0, "结束秒": 900.0}]))

    def test_起点为零的段必须保留(self):
        """反向用例：开始秒 0.0 是合法值，不能被 falsy 判定误伤。"""
        段 = 造段(0.0, 3.0, "开场白")
        self.assertFalse(在死循环区间(段, [{"开始秒": 600.0, "结束秒": 900.0}]))

    def test_边界包含端点(self):
        self.assertTrue(在死循环区间(造段(600.0, 601.0, "x"), [{"开始秒": 600.0, "结束秒": 900.0}]))
        self.assertTrue(在死循环区间(造段(900.0, 901.0, "x"), [{"开始秒": 600.0, "结束秒": 900.0}]))

    def test_空死循环区间原样返回(self):
        分段 = [造段(0.0, 1.0, "文本1"), 造段(700.0, 701.0, "文本2")]
        self.assertEqual(剔除死循环(分段, []), 分段)
        self.assertEqual(剔除死循环(分段, None), 分段)

    def test_剔除多区间内分段(self):
        分段 = [造段(0.0, 1.0, "文本1"), 造段(700.0, 701.0, "幻觉"),
               造段(1000.0, 1001.0, "文本3"), 造段(2000.0, 2001.0, "幻觉2")]
        区间 = [{"开始秒": 600.0, "结束秒": 900.0}, {"开始秒": 1900.0, "结束秒": 2100.0}]
        剩下 = 剔除死循环(分段, 区间)
        self.assertEqual([段["文本"] for 段 in 剩下], ["文本1", "文本3"])

    def test_有效文本只拼剩余分段(self):
        分段 = [造段(0.0, 1.0, "文本1"), 造段(700.0, 701.0, "幻觉")]
        剩下 = 剔除死循环(分段, [{"开始秒": 600.0, "结束秒": 900.0}])
        self.assertEqual(有效文本(剩下), "文本1")

    def test_剔除摘要数字正确(self):
        分段 = [造段(0.0, 1.0, "文本1"), 造段(700.0, 701.0, "幻觉"), 造段(800.0, 801.0, "幻觉2")]
        区间 = [{"开始秒": 600.0, "结束秒": 900.0}]
        剩下 = 剔除死循环(分段, 区间)
        摘要 = 剔除摘要(分段, 区间, 剩下)
        self.assertEqual((摘要["分段总数"], 摘要["剔除分段数"], 摘要["死循环区间数"]), (3, 2, 1))
        self.assertEqual(摘要["有效字符数"], 1)

    def test_短片段重复被压缩(self):
        self.assertLessEqual(len(压缩段内重复("嗯" * 32)), 3, "长噪声必须被压到门禁阈值以下")
        self.assertLessEqual(len(压缩段内重复("你好" + "嗯" * 8 + "你好")), 6)
        self.assertEqual(压缩段内重复("谢谢谢谢谢谢谢谢谢谢"), "谢谢")

    def test_正常重复不被误伤(self):
        self.assertEqual(压缩段内重复("对对对，可以可以"), "对对对，可以可以")
        self.assertEqual(压缩段内重复("好的好的"), "好的好的")

    def test_清洗分段同时剔区间并压重复(self):
        分段 = [造段(0.0, 1.0, "嗯" * 20 + "大家好"), 造段(700.0, 701.0, "幻觉")]
        剩下 = 清洗分段(分段, [{"开始秒": 600.0, "结束秒": 900.0}])
        self.assertEqual(len(剩下), 1)
        self.assertEqual(剩下[0]["文本"], "嗯大家好")

    def test_幻觉段被剔除(self):
        self.assertTrue(是幻觉段("明镜与点点栏目明镜与点点栏目"))
        self.assertTrue(是幻觉段("请不吝点赞 订阅 转发 打赏支持"))
        self.assertFalse(是幻觉段("欢迎走进直播间的家人们"))
        分段 = [造段(0.0, 1.0, "正常发言"), 造段(2.0, 3.0, "明镜与点点栏目明镜与点点栏目")]
        剩下 = 清洗分段(分段, [])
        self.assertEqual([段["文本"] for 段 in 剩下], ["正常发言"])

    def test_循环话术折叠只留首次(self):
        话术 = "欢迎走进直播间的家人们"
        分段 = [造段(0.0, 1.0, 话术), 造段(10.0, 11.0, "正常一句"),
               造段(20.0, 21.0, 话术), 造段(30.0, 31.0, 话术)]
        折叠后, 折叠数 = 折叠循环话术(分段, 最少次数=3)
        self.assertEqual(折叠数, 2, "重复出现的两次必须被折叠掉")
        self.assertEqual(len(折叠后), 2)
        self.assertIn("整场重复多次", 折叠后[0]["文本"])
        # 标注里不能出现数字：质检按阿拉伯数字算保留率，标注数字会污染基线
        self.assertNotIn("3", 折叠后[0]["文本"].replace(话术, ""))
        self.assertEqual(re.findall(r"\d+", 折叠后[0]["文本"]), [])

    def test_重复不足阈值不折叠(self):
        分段 = [造段(0.0, 1.0, "这句话只出现两次"), 造段(10.0, 11.0, "这句话只出现两次")]
        _, 折叠数 = 折叠循环话术(分段, 最少次数=3)
        self.assertEqual(折叠数, 0)

    def test_坏数据不抛异常(self):
        分段 = [{"开始秒": "坏值", "文本": "x"}, {"没有开始秒": True}, 造段(700.0, 701.0, "幻觉")]
        剩下 = 剔除死循环(分段, [{"开始秒": 600.0, "结束秒": 900.0}])
        self.assertEqual(len(剩下), 2)
        self.assertEqual(len(剔除死循环(分段, [{"开始秒": None, "结束秒": None}])), 3)


if __name__ == "__main__":
    unittest.main()
