class 记录型能力调用器:
    """只换**能力边界**：记录每次 `(能力id, 入参)`，并按能力 id 回预设结果。

    ★ 为什么是它、不是 `mock.patch.object(开工实现, '_调用')`（2026-09-23 修）：
    后者属「patch 被测对象本体·本体成员」（测试伪装门禁规则1 P1）且缺 `autospec`（规则2）。
    更关键的是**它把被测代码自己那段转发逻辑整段换掉** —— `开工即占` 里
    「把 `项目根` 塞进 `申请参数`」那一行是不是真的跑了，夹具版判据根本看不见，
    断言的对象变成夹具（假绿）。本类实现 `公共契约.能力契约.调用器.能力调用器` 协议，
    经**生产自带注入口** `注册能力调用器` 注入：`开工即占`/`开工准备`/`收工释放`
    的**真实实现照跑**，只有「调支持库」这一层边界被替换 —— 这属规则1 明确列出的
    「依赖注入式替换」例外，且不再有任何 `patch` 调用点。
    """

    def __init__(self, 应答表: dict | None = None):
        self.记录: dict[str, list] = {}
        self.应答表 = dict(应答表 or {})

    def 调用能力(self, 能力id, 参数=None, *, 调用方="", 项目id="", 超时秒=None):
        self.记录.setdefault(能力id, []).append(参数)
        应答 = self.应答表.get(能力id)
        if 应答 is None:
            return 结果.成功结果({})
        return 结果.成功结果(应答(参数) if callable(应答) else 应答)

    def 入参(self, 能力id) -> dict:
        """取**唯一一次**调用的入参；次数不为 1 即判红（「根本没调到」不许混过去）。"""
        表 = self.记录.get(能力id) or []
        if len(表) != 1:
            raise AssertionError(f"{能力id} 必须恰好调用一次，实为 {len(表)} 次")
        return 表[0]

    # ── 协议其余方法：本模块不调用，为「整体替换边界」给全实现 ──
    def 请求(self, 目标, 参数=None, 句柄=None):
        return None

    def 幂等重放(self, 能力id, 参数):
        return False

    def 查询调用历史(self, 上限=50):
        return []

    def 最近失败(self, 上限=10):
        return []

    def 回答九问(self, 能力id, 错误码):
        return {}


class 真转发能力调用器(记录型能力调用器):
    """指定能力**真转发**到真实实现，其余能力**一律报错**（防止用例顺手多打别的腿）。

    用在「入参里那一项真的起了作用」这类端到端判据上：边界照换（不 patch 被测模块），
    但被换上去的是**真实实现**（如 `释放文件租约`），于是转发下去的根真的去读了那棵树。
    """

    def __init__(self, 转发表: dict):
        super().__init__({})
        self.转发表 = dict(转发表)

    def 调用能力(self, 能力id, 参数=None, *, 调用方="", 项目id="", 超时秒=None):
        self.记录.setdefault(能力id, []).append(参数)
        if 能力id not in self.转发表:
            raise AssertionError(f"本用例只该调 {sorted(self.转发表)}，实际调了 {能力id}")
        return self.转发表[能力id](**(参数 or {}))


