    # ── 下面两个小工具把「上锁 → 收工释放 → 读解锁现场指纹」这条链收在一处 ──

    @staticmethod
    def _上锁(申请文件租约, 目标: str, 存储目录: str) -> str:
        认领 = 申请文件租约(修改路径=[目标], 所有者="会话1", 任务="对根上锁",
                        存储目录=存储目录, 项目根=str(系统根))
        if not 认领.成功:
            raise AssertionError(f"上锁失败: {认领.错误码} {认领.错误说明}")
        return 认领.值["租约id清单"][0]

    def _解锁现场指纹(self, 释放文件租约, 查询改动历史,
                 目标: str, 租约id: str, 存储目录: str, 收工项目根, 现场: str) -> str:
        """经 `开工编排.收工释放` 释放（边界换成**真转发**到解锁腿），回带解锁事件的现场指纹。

        ★ 不 patch 被测模块的 `_调用`：把能力边界整体换成 `真转发能力调用器`
        （生产自带注入口），被换上去的是**真实实现** `释放文件租约` —— 于是
        「转发下去的根」真的去读了那棵树，而不是只被夹具抄下来。
        """
        self._装边界(真转发能力调用器({能力_释放文件租约: 释放文件租约}))
        出 = 开工实现.收工释放(租约id清单=[租约id], 存储目录=存储目录,
                         项目根=收工项目根)
        self.assertTrue(出.成功, 出.错误说明)
        查询 = 查询改动历史(修改路径=[目标], 声明指纹=现场, 存储目录=存储目录,
                      项目根=self.仓库根)
        self.assertTrue(查询.成功, 查询.错误说明)
        解锁 = [e for e in 查询.值["结果表"][0]["区间事件"] if e.get("类型") == "解锁"]
        self.assertEqual(len(解锁), 1, "流水里必须有一条解锁事件")
        return str(解锁[0].get("内容指纹") or "")


