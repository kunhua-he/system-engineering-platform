class 撞车清单走占用判定测试(注入能力边界):
    """★ 2026-09-23 分名收口：撞车清单 = **占用判定**（这条租约现在**还挡不挡路**），
    判据**不在本模块**，由被调能力按全仓唯一那条 `是活跃`（状态活跃 **且** 未过期）出。

    缺陷态：本模块按 `str(记.get("状态")) == "活跃"` 字面量判 —— 它与 `是活跃` 只在
    「被调能力已在**读侧**把过期记录改判成 `已过期`」时才等价（`查询文件租约` 的
    `_改判过期`）。判据依赖调用顺序/对方实现，而不是同一判据：返回体一旦是未改判的
    原样记录，已过期的僵尸租约立刻被报成撞车（下面这条用例锚的就是这个）。
    修复态：把判据交给能力（`只要活跃=真`）—— 本模块不再持有第二套判据。

    夹具是「**盘上仍写着活跃 且 已过期**」这个组合（既有用例只覆盖心跳停摆，该组合曾全绿）。
    """

    仓库根 = str(系统根)

    def 僵尸记录(self) -> dict:
        """一条「盘上状态写着活跃、但已过点」的租约（读侧未改判的原样形态）。"""
        return {"路径": 目标路径, "键": f"文件::{目标路径}", "状态": 活跃状态,
                "所有者": "僵尸会话", "任务": "僵尸任务",
                "心跳": time.time() - 1000, "过期时间": time.time() - 100,
                "申请时间": "2026-09-23 00:00:00", "留言数": 0}

    def 应答表(self) -> dict:
        应答 = _默认应答表()

        def 查询文件租约(参数):
            # 被调能力的契约（与真实现同一判据）：`只要活跃=真` 只回 `是活跃` 的记录。
            记录 = [self.僵尸记录()]
            if (参数 or {}).get("只要活跃") is 真:
                记录 = [记 for 记 in 记录 if 是活跃(记)]
            return {"记录表": 记录, "活跃数": len(记录)}

        应答["平台控制面.能力目录.查询文件租约"] = 查询文件租约
        return 应答

    def _开工(self):
        出 = 开工实现.开工准备(任务="撞车清单占用判定", 项目根=self.仓库根,
                         修改路径=[目标路径])
        self.assertTrue(出.成功, 出.错误说明)
        return 出

    def test_已过期的僵尸租约不算撞车(self) -> None:
        出 = self._开工()
        文件租约 = 出.值["文件租约"]
        self.assertEqual(文件租约["撞车清单"], [],
                         "已过期（僵尸）的租约不许被报成撞车：判据必须是 是活跃，不是状态字面量")
        self.assertEqual(文件租约["数量"], 0, "活跃租约数量也不许把僵尸算进去")
        self.assertEqual(文件租约["占用者清单"], [])
        self.assertIn("撞车清单为空", " ".join(出.值["下一步"]),
                      "撞车清单为空时下一步必须说「没有别的会话在改」，不许把僵尸当撞车")

    def test_撞车查询必须传只要活跃(self) -> None:
        """判据**转调**：撞车清单的判据由能力侧按 `是活跃` 筛，本模块不再自己判状态字面量。"""
        出 = self._开工()
        self.assertTrue(出.成功)
        查询参数 = self.调用器.入参("平台控制面.能力目录.查询文件租约")
        self.assertIs(查询参数.get("只要活跃"), 真,
                      "撞车清单必须经 只要活跃=真 转调唯一判据 是活跃（不许在本模块重立一套）")

    def test_活着的租约仍要报成撞车(self) -> None:
        """反向：收口不许把真撞车也过滤掉（把判据交给能力 ≠ 放宽判据）。"""
        活着 = dict(self.僵尸记录(), 所有者="活着的会话", 心跳=time.time(),
                  过期时间=time.time() + 900)
        self.调用器.应答表["平台控制面.能力目录.查询文件租约"] = lambda 参数: {
            "记录表": ([活着] if (参数 or {}).get("只要活跃") is 真 else [活着, self.僵尸记录()])}
        出 = self._开工()
        self.assertEqual(出.值["文件租约"]["撞车清单"], [目标路径], "活着的租约必须被报成撞车")
        self.assertEqual(出.值["文件租约"]["占用者清单"][0]["占用者"], "活着的会话")


