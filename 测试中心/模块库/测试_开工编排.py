class 注入能力边界(unittest.TestCase):
    """把能力边界换成记录型调用器（**生产自带注入口**，不 patch 被测模块自身）。

    装载/卸载成对：`注册能力调用器` 注入、`设置惰性装配函数(None)` 停用惰性装配
    （否则卸载后首个调用会触发一次全树真装配，把别的用例拖进真装配）。两处都只动
    `公共契约.能力契约.调用器` 的全局注入点，不碰被测模块的任何成员。
    """

    def setUp(self):
        self._装边界(记录型能力调用器(self.应答表()))

    def tearDown(self):
        self._卸边界()

    def 应答表(self) -> dict:
        return _默认应答表()

    def _装边界(self, 调用器) -> None:
        from 公共契约.能力契约.调用器 import 注册能力调用器, 设置惰性装配函数
        if not hasattr(self, "原惰性装配"):
            self.原惰性装配 = 设置惰性装配函数.__globals__.get("_惰性装配函数")
            设置惰性装配函数(None)
        self.调用器 = 调用器
        注册能力调用器(调用器)

    def _卸边界(self) -> None:
        from 公共契约.能力契约.调用器 import 注册能力调用器, 设置惰性装配函数
        注册能力调用器(None)
        设置惰性装配函数(self.原惰性装配)


