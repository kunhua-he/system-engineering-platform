from 模块库.直播逐字稿.实现.疑难标记 import 默认阈值, 标记疑难

正常文本 = "大家好欢迎来到直播间今天讲三个动作"
循环文本 = "免费敷面膜"


def 造分段(序号: int, 文本: str = 正常文本, 开始秒: float = 0.0, 结束秒: float = 3.0,
           平均对数概率: float = -0.3, 压缩比: float = 0.7, 无语音概率: float = 0.05) -> dict:
    """造一个符合 03_分片转写 结构的分段。"""
    return {
        "序号": 序号,
        "开始秒": 开始秒,
        "结束秒": 结束秒,
        "文本": 文本,
        "平均对数概率": 平均对数概率,
        "压缩比": 压缩比,
        "无语音概率": 无语音概率,
    }


def 造分片(分片序号: int, 分段列表: list[dict], 开始秒: float = 0.0, 结束秒: float = 300.0) -> dict:
    """造一片分片转写结果。"""
    文本 = "".join(段.get("文本", "") for 段 in 分段列表)
    return {"分片序号": 分片序号, "开始秒": 开始秒, "结束秒": 结束秒, "文本": 文本, "分段": 分段列表}


class Test默认阈值(unittest.TestCase):
    def test_默认阈值包含全部可覆盖键(self):
        阈值 = 默认阈值()
        self.assertEqual(阈值["最小平均对数概率"], -1.0)
        self.assertEqual(阈值["最大压缩比"], 2.4)
        self.assertEqual(阈值["最大无语音概率"], 0.6)
        self.assertEqual(阈值["死循环连续次数"], 15)
        self.assertEqual(阈值["短语重复次数"], 10)
        阈值["最小平均对数概率"] = 0.0
        self.assertEqual(默认阈值()["最小平均对数概率"], -1.0, "默认阈值必须返回副本，不能被外部改坏")


class Test单段指标(unittest.TestCase):
    def test_正常文本不误报(self):
        结果 = 标记疑难([造分片(1, [造分段(1), 造分段(2, 开始秒=3.0, 结束秒=6.0)])])
        self.assertEqual(结果["疑难段"], [])
        self.assertEqual(结果["死循环区间"], [])

    def test_低置信度触发(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 平均对数概率=-1.8)])])
        self.assertEqual(len(结果["疑难段"]), 1)
        self.assertEqual(结果["疑难段"][0]["原因"], ["低置信度"])

    def test_高压缩比触发(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 压缩比=3.1)])])
        self.assertEqual(结果["疑难段"][0]["原因"], ["高压缩比"])

    def test_无语音概率高触发(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 无语音概率=0.83)])])
        self.assertEqual(结果["疑难段"][0]["原因"], ["无语音概率高"])

    def test_空文本触发(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 文本=""), 造分段(2, 文本="   ")])])
        self.assertEqual([段["原因"] for 段 in 结果["疑难段"]], [["空文本"], ["空文本"]])

    def test_同段多个指标同时命中(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 文本="2", 平均对数概率=-2.0, 压缩比=9.0, 无语音概率=0.9)])])
        self.assertEqual(结果["疑难段"][0]["原因"],
                         ["低置信度", "高压缩比", "无语音概率高", "空文本", "数字可疑"])

    def test_数字可疑触发(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 文本="3号链接")])])
        self.assertEqual(结果["疑难段"][0]["原因"], ["数字可疑"])

    def test_够长的数字文本不算数字可疑(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 文本="3号链接今天上架")])])
        self.assertEqual(结果["疑难段"], [])

    def test_疑难段带指标快照与时间戳(self):
        结果 = 标记疑难([造分片(1, [造分段(5, 开始秒=10.2, 结束秒=14.8, 平均对数概率=-1.5)])])
        疑难 = 结果["疑难段"][0]
        self.assertEqual((疑难["分片序号"], 疑难["序号"], 疑难["开始秒"], 疑难["结束秒"]),
                         (1, 5, 10.2, 14.8))
        self.assertEqual(疑难["指标"]["平均对数概率"], -1.5)
        self.assertEqual(疑难["指标"]["去空白长度"], len(正常文本))


class Test死循环(unittest.TestCase):
    def test_连续同文重复识别并排除出疑难段(self):
        分段列表 = [造分段(序号, 文本=循环文本, 开始秒=(序号 - 1) * 3.0, 结束秒=序号 * 3.0,
                            平均对数概率=-1.6) for 序号 in range(1, 17)]
        分段列表.append(造分段(17, 文本="这条我们讲完了", 开始秒=48.0, 结束秒=51.0, 平均对数概率=-1.6))
        结果 = 标记疑难([造分片(1, 分段列表)])
        区间 = 结果["死循环区间"]
        self.assertEqual(len(区间), 1)
        self.assertEqual(区间[0]["重复次数"], 16)
        self.assertEqual(区间[0]["开始秒"], 0.0)
        self.assertEqual(区间[0]["结束秒"], 48.0)
        self.assertEqual(区间[0]["样例文本"], 循环文本)
        self.assertEqual(len(结果["疑难段"]), 1, "死循环区间内 16 段不得进疑难段，只留区间外那一段")
        self.assertEqual(结果["疑难段"][0]["序号"], 17)
        self.assertEqual(结果["疑难段"][0]["原因"], ["低置信度"])

    def test_未达连续阈值不算死循环(self):
        分段列表 = [造分段(序号, 文本=循环文本, 开始秒=序号 * 3.0, 结束秒=序号 * 3.0 + 3.0)
                    for 序号 in range(1, 15)]
        结果 = 标记疑难([造分片(1, 分段列表)])
        self.assertEqual(结果["死循环区间"], [])
        self.assertEqual(结果["疑难段"], [])

    def test_段内短语重复识别为死循环(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 文本=循环文本 * 20, 开始秒=600.0, 结束秒=900.0)])])
        区间 = 结果["死循环区间"]
        self.assertEqual(len(区间), 1)
        self.assertGreaterEqual(区间[0]["重复次数"], 10)
        self.assertGreaterEqual(len(区间[0]["样例文本"]), 12)
        self.assertEqual((区间[0]["开始秒"], 区间[0]["结束秒"]), (600.0, 900.0))
        self.assertEqual(结果["疑难段"], [], "段内死循环命中的分段不再进疑难段")

    def test_普通复读三遍不算段内死循环(self):
        结果 = 标记疑难([造分片(1, [造分段(1, 文本=循环文本 * 3)])])
        self.assertEqual(结果["死循环区间"], [])


class Test阈值覆盖(unittest.TestCase):
    def test_覆盖低置信度阈值(self):
        分片列表 = [造分片(1, [造分段(1, 平均对数概率=-0.31)])]
        self.assertEqual(标记疑难(分片列表)["疑难段"], [])
        self.assertEqual(标记疑难(分片列表, {"最小平均对数概率": -0.05})["疑难段"][0]["原因"], ["低置信度"])

    def test_覆盖压缩比与无语音阈值(self):
        分片列表 = [造分片(1, [造分段(1, 压缩比=3.0, 无语音概率=0.7)])]
        结果 = 标记疑难(分片列表, {"最大压缩比": 5.0, "最大无语音概率": 0.9})
        self.assertEqual(结果["疑难段"], [])

    def test_覆盖死循环连续次数与短语重复次数(self):
        连续三段 = [造分段(序号, 文本=循环文本, 开始秒=序号 * 3.0, 结束秒=序号 * 3.0 + 3.0)
                    for 序号 in range(1, 4)]
        结果 = 标记疑难([造分片(1, 连续三段)], {"死循环连续次数": 3, "短语重复次数": 50})
        self.assertEqual(len(结果["死循环区间"]), 1)
        self.assertEqual(结果["死循环区间"][0]["重复次数"], 3)
        短语结果 = 标记疑难([造分片(1, [造分段(1, 文本=循环文本 * 20)])], {"短语重复次数": 50})
        self.assertEqual(短语结果["死循环区间"], [])
        self.assertEqual(len(短语结果["疑难段"]), 0)


class Test边界与合并(unittest.TestCase):
    def test_空输入返回空结果(self):
        结果 = 标记疑难([])
        self.assertEqual(结果, {"疑难段": [], "死循环区间": []})
        self.assertEqual(标记疑难(None), {"疑难段": [], "死循环区间": []})  # type: ignore[arg-type]

    def test_非列表输入返回错误码(self):
        结果 = 标记疑难("不是列表")  # type: ignore[arg-type]
        self.assertEqual(结果["疑难段"], [])
        self.assertEqual(结果["错误码"], "参数不合法")

    def test_分段缺字段不抛异常(self):
        分片列表 = [
            {"分片序号": 1, "分段": [{"文本": "今天讲三件事"}, {"文本": ""}, {}]},
            {"分片序号": 2, "分段": "不是列表"},
            "整片不是字典",
        ]
        结果 = 标记疑难(分片列表)
        self.assertEqual(len(结果["疑难段"]), 2, "缺指标字段的 6 字文本不误报，只有两个空文本入列")
        self.assertEqual([段["原因"] for 段 in 结果["疑难段"]], [["空文本"], ["空文本"]])
        self.assertEqual(结果["疑难段"][0]["指标"],
                         {"平均对数概率": 0.0, "压缩比": 0.0, "无语音概率": 0.0, "去空白长度": 0})

    def test_多分片合并序号正确(self):
        分片列表 = [
            造分片(1, [造分段(1, 文本="第一片第一段"), 造分段(2, 文本="第一片第二段", 平均对数概率=-2.0),
                       造分段(3, 文本="第一片第三段")]),
            造分片(2, [造分段(1, 文本="第二片第一段"), 造分段(2, 文本="第二片第二段", 压缩比=4.0)]),
        ]
        结果 = 标记疑难(分片列表)
        归属 = [(段["分片序号"], 段["序号"], 段["原因"]) for 段 in 结果["疑难段"]]
        self.assertEqual(归属, [(1, 2, ["低置信度"]), (2, 2, ["高压缩比"])])

    def test_分片缺分片序号按位置补序号(self):
        分片列表 = [{"分段": [造分段(1, 文本="缺分片序号的片", 平均对数概率=-3.0)]}]
        结果 = 标记疑难(分片列表)
        self.assertEqual(结果["疑难段"][0]["分片序号"], 1)


