"""模块库.直播逐字稿 内部工具「疑难标记」真实测试（纯计算，不依赖模型/网络）。

覆盖：默认阈值键齐全、正常文本不误报、四种指标各自触发、空文本、
数字可疑正反例、指标快照、连续同文重复识别为死循环并排除出疑难段、
死循环区间外分段照常判定、段内短语重复识别为死循环、
两类阈值可覆盖、空输入返回空结果、分段缺字段不抛异常、
多分片合并序号正确、非列表输入返回错误码。

数据全部为自造小样本，直接调用实现文件的纯函数，不装配任何能力/提供者。
"""

from __future__ import annotations

import sys
