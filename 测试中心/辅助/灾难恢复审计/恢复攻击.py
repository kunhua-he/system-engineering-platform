"""工作包19 恢复攻击审计：空目录恢复/备份损坏/旧快照重放 三类真实注入。"""
from __future__ import annotations

import json
import time
from pathlib import Path

from 平台控制面.包仓库.可信仓库元数据 import 可信仓库元数据
from 平台控制面.备份恢复.备份契约 import 权威数据备份契约
from 平台控制面.备份恢复.恢复编排器 import 新机器恢复编排器
from 支持库.适配层 import 内容摘要 as 仓库摘要

from 审计环境 import (构造存储根, 构造权威状态库, 构造制品目录, 构造源码快照,
                       构造依赖锁, 构造编排器备份, 读取版本标记, 最小能力输出)


def _最新快照(备份目录: Path) -> Path:
    return sorted(备份目录.glob("快照_*"))[-1]


class 恢复攻击审计:
    """对 备份契约/恢复编排器 真实注入四类恢复攻击。"""

    def __init__(self, 临时根: Path) -> None:
        self.临时根 = Path(临时根)

    def 审计空目录恢复(self) -> dict:
        """场景1：全新空目录 + 真实备份 → 恢复成功且最小能力真实调用。"""
        缺陷表: list[str] = []
        存储根 = 构造存储根(self.临时根 / "存储根1", 版本标记="v1")
        契约 = 权威数据备份契约(存储根)
        备份目录 = self.临时根 / "备份1"
        契约.执行备份(备份目录)
        校验成功, 校验原因 = 契约.校验备份(备份目录)
        if not 校验成功:
            缺陷表.append(f"空目录恢复前置校验失败: {校验原因}")
        恢复目录 = self.临时根 / "空目录1"
        恢复目录.mkdir(parents=True, exist_ok=True)
        编排备份 = 构造编排器备份(self.临时根 / "编排备份1",
                                    {"权威数据/恢复标记.txt": "权威数据已入编排备份"})
        源码快照 = 构造源码快照(self.临时根 / "源码快照1")
        制品源 = self.临时根 / "制品源1"
        构造制品目录(制品源, {"制品A.bin": "制品内容A"})
        依赖锁 = 构造依赖锁(self.临时根 / "依赖锁定1.json")
        编排器 = 新机器恢复编排器()
        编排结果 = 编排器.编排恢复({"空目录路径": str(恢复目录),
                                   "源码快照目录": str(源码快照),
                                   "制品目录": str(制品源),
                                   "依赖锁定文件路径": str(依赖锁),
                                   "备份目录": str(编排备份)})
        if 编排结果["状态"] != "已恢复":
            缺陷表.append(f"编排恢复未达已恢复: {编排结果['失败原因']}")
        契约恢复 = 契约.恢复(备份目录, 恢复目录)
        if not 契约恢复["成功"]:
            缺陷表.append(f"契约恢复失败: {[(x['类'], x['原因']) for x in 契约恢复['结果']]}")
        try:
            最小输出 = 编排器.恢复后最小调用(恢复目录)
        except Exception as 错误:
            缺陷表.append(f"最小能力真实调用失败: {错误}")
            最小输出 = ""
        if 最小输出 != 最小能力输出:
            缺陷表.append(f"最小能力输出不符: {最小输出!r}")
        期望状态 = 编排器.期望状态校验(恢复目录)
        if 期望状态["缺失"] or 期望状态["摘要不一致"]:
            缺陷表.append(f"期望状态差异: 缺失={期望状态['缺失']} "
                           f"摘要不一致={期望状态['摘要不一致']}")
        return {"场景": "空目录恢复", "防御有效": not 缺陷表, "缺陷": "；".join(缺陷表),
                "详情": {"校验备份": 校验成功, "编排状态": 编排结果["状态"],
                         "契约恢复": 契约恢复["成功"], "最小调用输出": 最小输出,
                         "期望差异数": len(期望状态["缺失"]) + len(期望状态["摘要不一致"])}}

    def 审计备份损坏(self) -> dict:
        """场景2：篡改权威状态 db / 制品文件 → 校验与恢复必须失败。"""
        缺陷表: list[str] = []
        存储根 = 构造存储根(self.临时根 / "存储根2a", 版本标记="v1")
        契约 = 权威数据备份契约(存储根)
        备份目录 = self.临时根 / "备份2a"
        契约.执行备份(备份目录)
        (_最新快照(备份目录) / "权威状态.db").write_bytes(
            "损坏的权威状态库字节".encode("utf-8") * 64)
        校验成功, 校验原因 = 契约.校验备份(备份目录)
        恢复结果 = 契约.恢复(备份目录, self.临时根 / "目标2a")
        if 校验成功:
            缺陷表.append("篡改权威状态.db 后校验备份仍成功")
        if 恢复结果["成功"]:
            缺陷表.append("篡改权威状态.db 后恢复仍成功")
        if "权威状态" not in 校验原因:
            缺陷表.append(f"校验失败原因未指明权威状态: {校验原因}")
        存储根b = 构造存储根(self.临时根 / "存储根2b", 版本标记="v2")
        契约b = 权威数据备份契约(存储根b)
        备份b = self.临时根 / "备份2b"
        契约b.执行备份(备份b)
        (_最新快照(备份b) / "制品" / "制品A.bin").write_bytes("被篡改的制品".encode("utf-8"))
        校验b, 原因b = 契约b.校验备份(备份b)
        if 校验b:
            缺陷表.append("篡改制成品文件后校验备份仍成功")
        if "制品" not in 原因b:
            缺陷表.append(f"校验失败原因未指明制品: {原因b}")
        return {"场景": "备份损坏", "防御有效": not 缺陷表, "缺陷": "；".join(缺陷表),
                "详情": {"db篡改校验": (校验成功, 校验原因), "db篡改恢复成功": 恢复结果["成功"],
                         "制品篡改校验": (校验b, 原因b)}}

    def 审计旧快照重放(self) -> dict:
        """场景3：旧备份（时间戳早）覆盖新状态 → 必须检测版本回退。"""
        缺陷表: list[str] = []
        存储根 = 构造存储根(self.临时根 / "存储根3", 版本标记="旧版v1")
        契约 = 权威数据备份契约(存储根)
        旧备份 = self.临时根 / "备份3_旧"
        契约.执行备份(旧备份)
        time.sleep(1.1)  # 保证新快照目录名时间戳严格晚于旧快照
        构造权威状态库(存储根, "新版v2")
        新备份 = self.临时根 / "备份3_新"
        契约.执行备份(新备份)
        目标 = self.临时根 / "重放目标3"
        新恢复 = 契约.恢复(新备份, 目标)
        旧恢复 = 契约.恢复(旧备份, 目标)
        版本 = 读取版本标记(目标 / "权威状态.db")
        旧快照目录, 新快照目录 = _最新快照(旧备份), _最新快照(新备份)
        旧恢复文本 = json.dumps(旧恢复, ensure_ascii=False)
        回退被检测 = ("回退" in 旧恢复文本 or "警告" in 旧恢复文本 or not 旧恢复["成功"])
        if not 回退被检测:
            缺陷表.append(f"旧快照重放未被检测：{旧快照目录.name} 无警告覆盖 "
                           f"{新快照目录.name} 恢复的新状态，恢复结果无任何回退标记，"
                           f"磁盘版本={版本}")
        if 版本 != "旧版v1":
            缺陷表.append(f"重放后版本异常: {版本}")
        仓库 = 可信仓库元数据(self.临时根 / "元数据3")
        仓库.初始化()
        仓库.发布目标("示例包", "1.0.0", 仓库摘要("制品1".encode("utf-8")),
                      制品内容="制品1".encode("utf-8"))
        旧快照元 = 仓库.生成快照()
        time.sleep(0.05)
        仓库.生成快照()
        校验旧, 原因旧 = 仓库.校验元数据("快照", 旧快照元)
        对照拒绝 = not 校验旧 and "版本回退" in 原因旧
        return {"场景": "旧快照重放", "防御有效": not 缺陷表, "缺陷": "；".join(缺陷表),
                "详情": {"回退被检测": 回退被检测, "重放后版本": 版本,
                         "旧快照": 旧快照目录.name, "新快照": 新快照目录.name,
                         "元数据层对照拒绝": 对照拒绝}}
