"""工作包19 仓库攻击审计：过期元数据/签名替换 两类真实注入。"""
from __future__ import annotations

import json
import time
from pathlib import Path

from 平台控制面.包仓库.可信仓库元数据 import 可信仓库元数据
from 支持库.适配层.密码适配 import 生成密钥对, 签名, 内容摘要


def 规范化正文(元数据: dict) -> bytes:
    """攻击者重推导的签名正文（去全部签名字段后的规范化 JSON）。"""
    干净 = {键: 值 for 键, 值 in 元数据.items() if not 键.endswith("签名")}
    return json.dumps(干净, ensure_ascii=False, sort_keys=True).encode("utf-8")


class 仓库攻击审计:
    """对 可信仓库元数据 真实注入过期与签名替换攻击。"""

    def __init__(self, 临时根: Path) -> None:
        self.临时根 = Path(临时根)

    def 审计过期元数据(self) -> dict:
        """场景4：元数据过期时间在过去 → 校验必须拒绝。"""
        缺陷表: list[str] = []
        仓库 = 可信仓库元数据(self.临时根 / "元数据4", 有效期秒=0.05)
        根元数据 = 仓库.初始化()
        目标元数据 = 仓库.发布目标("示例包", "1.0.0", 内容摘要("制品1".encode("utf-8")),
                                    制品内容="制品1".encode("utf-8"))
        快照元数据 = 仓库.生成快照()
        time.sleep(0.12)  # 真实等待全部元数据过期
        校验表 = {"根信任": 仓库.校验元数据("根信任", 根元数据),
                  "目标": 仓库.校验元数据("目标", 目标元数据),
                  "快照": 仓库.校验元数据("快照", 快照元数据)}
        for 名称, (成功, 原因) in 校验表.items():
            if 成功 or "过期" not in 原因:
                缺陷表.append(f"过期{名称}未被拒绝: {(成功, 原因)}")
        仓库b = 可信仓库元数据(self.临时根 / "元数据4b")
        仓库b.初始化()
        攻击私钥, _ = 生成密钥对()
        伪造正文 = {"类型": "目标", "包id": "伪造包", "版本": "9.9.9",
                    "制品摘要": "00" * 32, "签名者": "根信任",
                    "签名时间": time.time() - 3600, "过期时间": time.time() - 10}
        伪造目标 = {**伪造正文, "签名": 签名(攻击私钥, 规范化正文(伪造正文))}
        校验伪造 = 仓库b.校验元数据("目标", 伪造目标)
        if 校验伪造[0] or "过期" not in 校验伪造[1]:
            缺陷表.append(f"伪造过期目标未被拒绝: {校验伪造}")
        return {"场景": "过期元数据", "防御有效": not 缺陷表, "缺陷": "；".join(缺陷表),
                "详情": {**校验表, "伪造过期目标": 校验伪造}}

    def 审计签名替换(self) -> dict:
        """场景5：换公钥重签/替换制品/篡改快照/伪造根信任 → 校验必须失败。"""
        缺陷表: list[str] = []
        目录 = self.临时根 / "元数据5"
        仓库 = 可信仓库元数据(目录)
        仓库.初始化()
        制品内容 = "签名制品内容".encode("utf-8")
        目标元数据 = 仓库.发布目标("示例包", "1.0.0", 内容摘要(制品内容), 制品内容=制品内容)
        攻击私钥, 攻击公钥 = 生成密钥对()
        重签目标 = {**目标元数据, "签名": 签名(攻击私钥, 规范化正文(目标元数据))}
        校验a = 仓库.校验元数据("目标", 重签目标)
        if 校验a[0] or "签名" not in 校验a[1]:
            缺陷表.append(f"换公钥重签未被拒绝: {校验a}")
        (目录 / "制品" / "示例包_1.0.0.bin").write_bytes("被替换的制品内容".encode("utf-8"))
        校验b = 仓库.校验元数据("目标", 目标元数据)
        if 校验b[0] or "替换" not in 校验b[1]:
            缺陷表.append(f"制品替换未被拒绝: {校验b}")
        快照元数据 = 仓库.生成快照()
        篡改快照 = {**快照元数据, "目标表": {**快照元数据["目标表"], "示例包@1.0.0": "00" * 32}}
        校验c = 仓库.校验元数据("快照", 篡改快照)
        if 校验c[0]:
            缺陷表.append(f"篡改快照未被拒绝: {校验c}")
        伪造正文 = {"类型": "根信任", "元数据版本": 1, "公钥": 攻击公钥,
                    "恢复公钥": 攻击公钥, "签名时间": time.time(),
                    "过期时间": time.time() + 1000}
        伪造根 = {**伪造正文, "签名": 签名(攻击私钥, 规范化正文(伪造正文))}
        校验d = 仓库.校验元数据("根信任", 伪造根)
        if 校验d[0] or "签名" not in 校验d[1]:
            缺陷表.append(f"伪造根信任未被拒绝: {校验d}")
        return {"场景": "签名替换", "防御有效": not 缺陷表, "缺陷": "；".join(缺陷表),
                "详情": {"换公钥重签": 校验a, "制品替换": 校验b, "快照篡改": 校验c,
                         "伪造根信任": 校验d}}
