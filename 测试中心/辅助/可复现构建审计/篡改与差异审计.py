"""工作包17 反向审计·篡改与差异：输入篡改、时间、主机差异、构建历史污染。

篡改面判定：任一输入改变摘要必须改变；时间/主机按冻结输入语义核对；
构建历史污染为阻断项探测（同一冻结输入摘要不得依赖实例历史状态）。
"""
from __future__ import annotations

import time

from .基础 import (构建摘要表, 清理, 临时工作区, 新实例, 冻结时刻甲,
                  冻结时刻乙, 基本文件表, 主机甲, 主机乙)


def 审计_输入篡改() -> tuple[bool, str]:
    """篡改任一输入（内容/删除/新增/时刻/主机）摘要必须改变。"""
    基线 = {"文件表": {"a.txt": "版本={时间戳} 主机={主机名}\n原始内容\n", "b.txt": "另一份\n"},
           "构建时刻": 冻结时刻甲, "主机名": 主机甲}
    篡改案例 = [
        ("文件内容", {"文件表": {"a.txt": "版本={时间戳} 主机={主机名}\n被篡改内容\n", "b.txt": "另一份\n"}, "构建时刻": 冻结时刻甲, "主机名": 主机甲}),
        ("删除文件", {"文件表": {"a.txt": "版本={时间戳} 主机={主机名}\n原始内容\n"}, "构建时刻": 冻结时刻甲, "主机名": 主机甲}),
        ("新增文件", {"文件表": {"a.txt": "版本={时间戳} 主机={主机名}\n原始内容\n", "b.txt": "另一份\n", "c.txt": "多出\n"}, "构建时刻": 冻结时刻甲, "主机名": 主机甲}),
        ("构建时刻", {"文件表": {"a.txt": "版本={时间戳} 主机={主机名}\n原始内容\n", "b.txt": "另一份\n"}, "构建时刻": 冻结时刻乙, "主机名": 主机甲}),
        ("主机名", {"文件表": {"a.txt": "版本={时间戳} 主机={主机名}\n原始内容\n", "b.txt": "另一份\n"}, "构建时刻": 冻结时刻甲, "主机名": 主机乙}),
    ]
    工作区表 = [临时工作区(f"篡改{i}_") for i in range(len(篡改案例) + 1)]
    try:
        摘要基线 = 构建摘要表(基线, 工作区表[0])
        变化表 = [构建摘要表(输入, 工作区) != 摘要基线
                  for (名称, 输入), 工作区 in zip(篡改案例, 工作区表[1:])]
        证据 = "; ".join(f"{名称}摘要变化={变了}" for (名称, _), 变了 in zip(篡改案例, 变化表))
        return all(变化表), 证据
    finally:
        清理(*工作区表)


def 审计_时间污染() -> tuple[bool, str]:
    """同一冻结时刻+不同真实时钟摘要一致；不同冻结时刻摘要不同。"""
    输入 = {"文件表": 基本文件表, "构建时刻": 冻结时刻甲, "主机名": 主机甲}
    输入乙 = {"文件表": 基本文件表, "构建时刻": 冻结时刻乙, "主机名": 主机甲}
    工作区表 = [临时工作区(f"时间{i}_") for i in range(4)]
    try:
        时钟一 = time.time()
        摘要一 = 构建摘要表(输入, 工作区表[0])
        time.sleep(0.02)
        时钟二 = time.time()
        摘要二 = 构建摘要表(输入, 工作区表[1])
        同刻一致 = 时钟二 > 时钟一 and 摘要一 == 摘要二
        摘要三 = 构建摘要表(输入, 工作区表[2])
        摘要四 = 构建摘要表(输入乙, 工作区表[3])
        异刻有别 = 摘要三 != 摘要四
        return (同刻一致 and 异刻有别), (
            f"真实时钟一={时钟一:.6f} 时钟二={时钟二:.6f} 同一冻结时刻摘要一致={同刻一致}; "
            f"不同冻结时刻摘要有别={异刻有别}")
    finally:
        清理(*工作区表)


def 审计_主机差异() -> tuple[bool, str]:
    """同一主机名两次摘要一致；不同主机名输入摘要不同。"""
    输入 = {"文件表": 基本文件表, "构建时刻": 冻结时刻甲, "主机名": 主机甲}
    输入乙 = {"文件表": 基本文件表, "构建时刻": 冻结时刻甲, "主机名": 主机乙}
    工作区表 = [临时工作区(f"主机{i}_") for i in range(4)]
    try:
        摘要一 = 构建摘要表(输入, 工作区表[0])
        摘要二 = 构建摘要表(输入, 工作区表[1])
        同机一致 = 摘要一 == 摘要二
        摘要三 = 构建摘要表(输入, 工作区表[2])
        摘要四 = 构建摘要表(输入乙, 工作区表[3])
        异机有别 = 摘要三 != 摘要四
        return (同机一致 and 异机有别), (
            f"同一主机名两次摘要一致={同机一致}; 不同主机名摘要有别={异机有别}")
    finally:
        清理(*工作区表)


def 审计_构建历史污染() -> tuple[bool, str]:
    """探测阻断项：同一实例的构建历史不得残留进后续摘要。"""
    含时刻 = {"文件表": {"a.txt": "{时间戳}"}, "构建时刻": 冻结时刻甲}
    不含时刻 = {"文件表": {"a.txt": "{时间戳}"}}
    含主机 = {"文件表": {"b.txt": "{主机名}"}, "主机名": 主机甲}
    不含主机 = {"文件表": {"b.txt": "{主机名}"}}
    历史实例 = 新实例()
    全新实例 = 新实例()
    历史主机实例 = 新实例()
    全新主机实例 = 新实例()
    工作区表 = [临时工作区(f"历史{i}_") for i in range(6)]
    try:
        历史实例.构建(含时刻, 工作区表[0])
        _, 摘要历史 = 历史实例.构建(不含时刻, 工作区表[1])
        _, 摘要全新 = 全新实例.构建(不含时刻, 工作区表[2])
        时刻污染 = 摘要历史 != 摘要全新
        历史主机实例.构建(含主机, 工作区表[3])
        _, 摘要主机历史 = 历史主机实例.构建(不含主机, 工作区表[4])
        _, 摘要主机全新 = 全新主机实例.构建(不含主机, 工作区表[5])
        主机污染 = 摘要主机历史 != 摘要主机全新
        return (not (时刻污染 or 主机污染)), (
            f"构建时刻历史残留={时刻污染}(历史摘要={摘要历史} 全新摘要={摘要全新}); "
            f"主机名历史残留={主机污染}(历史摘要={摘要主机历史} 全新摘要={摘要主机全新})")
    finally:
        清理(*工作区表)
