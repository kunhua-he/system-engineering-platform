"""工作包17 反向审计·污染面：路径、环境顺序、文件遍历顺序、缓存。

污染面判定：摘要必须确定，与工作区路径、写入顺序、加入顺序、缓存残留无关。
"""
from __future__ import annotations

from .基础 import (构建摘要表, 清理, 临时工作区, 新实例, 基本文件表,
                  冻结时刻甲, 主机甲)


def 审计_路径污染() -> tuple[bool, str]:
    """两个完全不同工作区路径（短路径 vs 深长特殊字符路径）摘要一致。"""
    输入 = {"文件表": 基本文件表, "构建时刻": 冻结时刻甲, "主机名": 主机甲}
    工作区甲 = 临时工作区("短_")
    工作区乙 = 临时工作区("路径污染_")
    深路径 = 工作区乙 / "很深" / "的目录·链-带 空格!特殊#字符€€" / ("长" * 20)
    深路径.mkdir(parents=True)
    try:
        摘要甲 = 构建摘要表(输入, 工作区甲)
        摘要乙 = 构建摘要表(输入, 深路径)
        一致 = 摘要甲 == 摘要乙
        return 一致, f"短路径={工作区甲} vs 深长特殊路径={深路径}\n摘要一致={一致} 摘要={摘要甲}"
    finally:
        清理(工作区甲, 工作区乙)


def 审计_环境顺序污染() -> tuple[bool, str]:
    """文件表写入顺序不同（同内容反向排序）摘要一致。"""
    表甲 = {"a.txt": "内容A\n{时间戳}\n", "b/文件B.md": "内容B\n",
           "c/深/文件C.txt": "内容C\n"}
    表乙 = {路径: 内容 for 路径, 内容 in reversed(tuple(表甲.items()))}
    输入甲 = {"文件表": 表甲, "构建时刻": 冻结时刻甲, "主机名": 主机甲}
    输入乙 = {"文件表": 表乙, "构建时刻": 冻结时刻甲, "主机名": 主机甲}
    工作区甲 = 临时工作区("顺序甲_")
    工作区乙 = 临时工作区("顺序乙_")
    try:
        摘要甲 = 构建摘要表(输入甲, 工作区甲)
        摘要乙 = 构建摘要表(输入乙, 工作区乙)
        一致 = 摘要甲 == 摘要乙
        return 一致, f"文件表写入顺序 正向 vs 反向\n摘要一致={一致} 摘要={摘要甲}"
    finally:
        清理(工作区甲, 工作区乙)


def 审计_文件遍历顺序污染() -> tuple[bool, str]:
    """构建目录文件加入顺序不同（同一批文件不同写入次序）摘要一致。"""
    文件表 = {"z尾.txt": "内容Z\n", "a头.txt": "内容A\n", "m中/子.txt": "内容M\n"}
    目录甲 = 临时工作区("遍历甲_")
    目录乙 = 临时工作区("遍历乙_")
    try:
        for 路径 in ("a头.txt", "m中/子.txt", "z尾.txt"):
            目标 = 目录甲 / 路径
            目标.parent.mkdir(parents=True, exist_ok=True)
            目标.write_text(文件表[路径], encoding="utf-8")
        for 路径 in ("z尾.txt", "m中/子.txt", "a头.txt"):
            目标 = 目录乙 / 路径
            目标.parent.mkdir(parents=True, exist_ok=True)
            目标.write_text(文件表[路径], encoding="utf-8")
        摘要甲 = 新实例().构建摘要(目录甲)
        摘要乙 = 新实例().构建摘要(目录乙)
        一致 = 摘要甲 == 摘要乙
        return 一致, f"加入顺序 a→m→z vs z→m→a\n摘要一致={一致} 摘要={摘要甲}"
    finally:
        清理(目录甲, 目录乙)


def 审计_缓存污染() -> tuple[bool, str]:
    """先构建产生缓存（构建产物残留），篡改/删除缓存后重建摘要与首次一致。"""
    输入 = {"文件表": 基本文件表, "构建时刻": 冻结时刻甲, "主机名": 主机甲}
    工作区 = 临时工作区("缓存_")
    try:
        实例 = 新实例()
        构建目录, 摘要一 = 实例.构建(输入, 工作区)
        (构建目录 / "说明.md").write_text("被篡改的缓存内容", encoding="utf-8")
        (构建目录 / "垃圾.txt").write_text("垃圾", encoding="utf-8")
        垃圾目录 = 构建目录 / "垃圾目录"
        垃圾目录.mkdir()
        (垃圾目录 / "残留.txt").write_text("残留", encoding="utf-8")
        _, 摘要二 = 实例.构建(输入, 工作区)
        清理(构建目录)
        _, 摘要三 = 实例.构建(输入, 工作区)
        一致 = 摘要一 == 摘要二 == 摘要三
        return 一致, f"首建 vs 缓存篡改后重建 vs 删除缓存重建\n摘要一致={一致} 摘要={摘要一}"
    finally:
        清理(工作区)
