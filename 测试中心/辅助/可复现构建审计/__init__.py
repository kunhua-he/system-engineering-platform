"""可复现构建反向审计辅助包（P2-17）：污染面与篡改差异审计的真实执行入口。

导出全部八类审计函数与汇总入口 执行全部审计()；所有审计均基于
平台控制面.包仓库.可复现构建器 的真实构建（真实临时工作区、真实写盘、
真实 sha256），发现生产缺陷只返回阻断清单，不修改被测实现。
"""
from __future__ import annotations

from 测试中心.辅助.可复现构建审计.污染面审计 import (
    审计_路径污染, 审计_环境顺序污染, 审计_文件遍历顺序污染, 审计_缓存污染)
from 测试中心.辅助.可复现构建审计.篡改与差异审计 import (
    审计_输入篡改, 审计_时间污染, 审计_主机差异, 审计_构建历史污染)

全部审计函数表 = {
    "路径污染": 审计_路径污染, "环境顺序污染": 审计_环境顺序污染,
    "文件遍历顺序污染": 审计_文件遍历顺序污染, "缓存污染": 审计_缓存污染,
    "输入篡改": 审计_输入篡改, "时间污染": 审计_时间污染,
    "主机差异": 审计_主机差异, "构建历史污染": 审计_构建历史污染,
}


def 执行全部审计() -> tuple[bool, list[str], str]:
    """执行全部八类审计；返回 (全部通过, 阻断清单, 汇总证据)。"""
    阻断清单: list[str] = []
    证据行表: list[str] = []
    for 名称, 审计函数 in 全部审计函数表.items():
        通过, 证据 = 审计函数()
        证据行表.append(f"[{名称}] {'通过' if 通过 else '阻断'}：{证据}")
        if not 通过:
            阻断清单.append(f"{名称}: {证据}")
    return (not 阻断清单, 阻断清单, "\n".join(证据行表))


__all__ = ["执行全部审计", *全部审计函数表.keys()]
