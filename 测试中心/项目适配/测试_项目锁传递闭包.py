class Test传递闭包版本漂移(unittest.TestCase):
    def test_声明约束与锁定版本不符失败(self):
        临时根 = Path(tempfile.mkdtemp(prefix="闭包漂移_"))
        项目根 = 临时根 / "项目"
        _写项目声明(项目根, [{"包id": "支持库.后端.文件系统支持库.文件操作", "版本约束": ">=2.0.0"}], [])
        _写锁(项目根, [_锁条目("支持库.后端.文件系统支持库.文件操作", 版本="1.0.0")])
        结果 = 校验传递闭包(项目根, 系统根)
        self.assertFalse(结果.成功, "版本漂移应真实失败")
        self.assertTrue(
            any("版本漂移" in 问题 and "声明约束 >=2.0.0 与锁定版本 1.0.0 不符" in 问题
                for 问题 in 结果.问题列表),
            str(结果.问题列表),
        )

    def test_锁内版本与能力定义版本不符失败(self):
        临时根 = Path(tempfile.mkdtemp(prefix="闭包漂移_"))
        项目根 = 临时根 / "项目"
        _写项目声明(项目根, [{"包id": "支持库.后端.数据库连接支持库.SQLite数据库", "版本约束": ">=1.0.0"}], [])
        _写锁(项目根, [_锁条目(
            "支持库.后端.数据库连接支持库.SQLite数据库", 版本="9.9.9",
            提供者id="支持库.后端.数据库连接支持库.SQLite数据库", 提供者版本=">=1.0.0",
        )])
        结果 = 校验传递闭包(项目根, 系统根)
        self.assertFalse(结果.成功, "锁内版本漂移应真实失败")
        self.assertTrue(
            any("锁定版本 9.9.9 与能力定义版本 1.0.0 不符" in 问题
                for 问题 in 结果.问题列表),
            str(结果.问题列表),
        )
        # 反向证明：锁版本与能力定义一致即通过
        _写锁(项目根, [_锁条目(
            "支持库.后端.数据库连接支持库.SQLite数据库", 版本="1.0.0",
            提供者id="支持库.后端.数据库连接支持库.SQLite数据库", 提供者版本=">=1.0.0",
        )])
        恢复结果 = 校验传递闭包(项目根, 系统根)
        self.assertTrue(恢复结果.成功, f"锁版本对齐后应通过: {恢复结果.问题列表}")


