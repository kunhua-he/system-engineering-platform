class Test传递闭包提供者锁(unittest.TestCase):
    def test_提供者锁缺失失败(self):
        临时根 = Path(tempfile.mkdtemp(prefix="闭包锁缺失_"))
        _写迷你系统根(临时根)
        项目根 = 临时根 / "项目"
        _写项目声明(
            项目根,
            [{"包id": "支持库.后端.示例提供者", "版本约束": ">=1.0.0"}],
            [{"包id": "模块库.示例模块", "版本约束": ">=1.0.0"}],
        )
        生成结果 = 生成依赖锁定(项目根, 临时根)
        self.assertTrue(生成结果.成功, str(生成结果.问题列表))
        结果 = 校验传递闭包(项目根, 临时根)
        self.assertFalse(结果.成功, "提供者锁缺失应真实失败")
        self.assertTrue(
            any("提供者锁缺失" in 问题 and "依赖锁.json 不存在" in 问题
                and "支持库.后端.示例提供者" in 问题 for 问题 in 结果.问题列表),
            str(结果.问题列表),
        )

    def test_提供者锁为空失败(self):
        临时根 = Path(tempfile.mkdtemp(prefix="闭包锁空_"))
        _写迷你系统根(临时根, 空提供者锁=True)
        项目根 = 临时根 / "项目"
        _写项目声明(
            项目根,
            [{"包id": "支持库.后端.示例提供者", "版本约束": ">=1.0.0"}],
            [{"包id": "模块库.示例模块", "版本约束": ">=1.0.0"}],
        )
        _写锁(项目根, [
            _锁条目("模块库.示例模块"),
            _锁条目("支持库.后端.示例提供者",
                     提供者id="支持库.后端.示例提供者", 提供者版本=">=1.0.0"),
        ])
        结果 = 校验传递闭包(项目根, 临时根)
        self.assertFalse(结果.成功, "空提供者锁应真实失败")
        self.assertTrue(
            any("提供者锁缺失" in 问题 and "依赖锁.json 为空" in 问题 for 问题 in 结果.问题列表),
            str(结果.问题列表),
        )

    def test_问题清单稳定排序(self):
        临时根 = Path(tempfile.mkdtemp(prefix="闭包排序_"))
        项目根 = 临时根 / "项目"
        _写项目声明(项目根, [], [{"包id": "模块库.文件管理", "版本约束": ">=1.0.0"}])
        _写锁(项目根, [_锁条目("模块库.文件管理")])
        结果1 = 校验传递闭包(项目根, 系统根)
        结果2 = 校验传递闭包(项目根, 系统根)
        self.assertFalse(结果1.成功)
        self.assertEqual(结果1.问题列表, 结果2.问题列表, "问题清单必须稳定排序")
        包能力序列 = [(问题.split(": ")[0], 问题.split(": ")[1].split("→")[0])
                      for 问题 in 结果1.问题列表 if "→" in 问题]
        self.assertEqual(包能力序列, sorted(包能力序列), "问题清单应按 包id/能力id 排序")


