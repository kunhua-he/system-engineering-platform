def _写项目声明(项目根: Path, 支持库绑定: list, 模块绑定: list) -> None:
    """写最小项目声明（生成依赖锁定 与 校验传递闭包 共用格式）。"""
    项目根.mkdir(parents=True, exist_ok=True)
    数据 = {
        "项目id": "测试.闭包",
        "项目名称": "闭包测试",
        "系统版本": ">=1.0.0",
        "支持库绑定": 支持库绑定,
        "模块绑定": 模块绑定,
        "验证范围": ["结构", "契约", "资产", "装配", "加载器", "项目适配"],
    }
    (项目根 / "项目声明.json").write_text(
        json.dumps(数据, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def _写锁(项目根: Path, 包条目列表: list[dict]) -> None:
    """手工写 依赖锁定.json（最小字段，供闭包校验读取）。"""
    数据 = {"锁定版本": "1.0.0", "项目id": "测试.闭包", "生成时间": "", "包列表": 包条目列表}
    (项目根 / "依赖锁定.json").write_text(
        json.dumps(数据, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def _锁条目(包id: str, 版本: str = "1.0.0", 提供者id: str = "",
            提供者版本: str = "") -> dict:
    return {"包id": 包id, "版本": 版本, "类型": "支持库", "契约版本": "1.0.0",
            "能力版本": "1.0.0", "提供者": 包id, "完整性摘要": "测试摘要",
            "依赖顺序": 0, "提供者id": 提供者id, "提供者版本": 提供者版本,
            "环境摘要": "", "选择证据": "测试"}


def _写迷你系统根(临时根: Path, *, 空提供者锁: bool = False) -> None:
    """构造迷你系统根：示例提供者（第三方能力）+ 示例模块（依赖 能力.示例提供）。"""
    支持库 = 临时根 / "支持库" / "后端" / "示例提供者"
    支持库.mkdir(parents=True, exist_ok=True)
    (支持库 / "包声明.json").write_text(json.dumps({
        "包id": "支持库.后端.示例提供者", "名称": "示例提供者", "类型": "支持库",
        "版本": "1.0.0", "入口": "__init__.py", "依赖": [],
        "能力": [{"能力id": "能力.示例提供", "名称": "示例提供能力", "参数": [], "返回": "结果"}],
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    (支持库 / "能力定义.json").write_text(json.dumps({
        "包id": "支持库.后端.示例提供者", "版本": "1.0.0",
        "提供者": {"默认": "支持库.后端.示例提供者", "版本": ">=1.0.0"},
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    if 空提供者锁:
        (支持库 / "依赖锁.json").write_text(json.dumps({
            "包": [], "提供者id": "支持库.后端.示例提供者",
        }, ensure_ascii=False, indent=2), encoding="utf-8")
    (临时根 / "模块库" / "示例模块").mkdir(parents=True, exist_ok=True)
    (临时根 / "模块库" / "示例模块" / "包声明.json").write_text(json.dumps({
        "包id": "模块库.示例模块", "名称": "示例模块", "类型": "模块",
        "版本": "1.0.0", "入口": "__init__.py",
        "依赖": [{"能力": "能力.示例提供", "版本": ">=1.0.0"}],
        "能力": [{"能力id": "能力.示例使用", "名称": "示例使用能力", "参数": [], "返回": "结果"}],
    }, ensure_ascii=False, indent=2), encoding="utf-8")


def _写迷你循环根(临时根: Path) -> None:
    """构造循环系统根：循环模块1 依赖 循环模块2 提供的能力，反之亦然。"""
    for 模块名, 依赖能力, 自身能力 in (
        ("循环模块1", "能力.循环2", "能力.循环1"),
        ("循环模块2", "能力.循环1", "能力.循环2"),
    ):
        (临时根 / "模块库" / 模块名).mkdir(parents=True, exist_ok=True)
        (临时根 / "模块库" / 模块名 / "包声明.json").write_text(json.dumps({
            "包id": f"模块库.{模块名}", "名称": 模块名, "类型": "模块",
            "版本": "1.0.0", "入口": "__init__.py",
            "依赖": [{"能力": 依赖能力, "版本": ">=1.0.0"}],
            "能力": [{"能力id": 自身能力, "名称": 自身能力, "参数": [], "返回": "结果"}],
        }, ensure_ascii=False, indent=2), encoding="utf-8")
    (临时根 / "支持库").mkdir(parents=True, exist_ok=True)


