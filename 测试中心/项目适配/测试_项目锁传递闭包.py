class Test传递闭包缺项(unittest.TestCase):
    def test_锁内无能力提供者失败(self):
        临时根 = Path(tempfile.mkdtemp(prefix="闭包缺项_"))
        项目根 = 临时根 / "项目"
        _写项目声明(项目根, [], [{"包id": "模块库.文件管理", "版本约束": ">=1.0.0"}])
        _写锁(项目根, [_锁条目("模块库.文件管理")])
        结果 = 校验传递闭包(项目根, 系统根)
        self.assertFalse(结果.成功, "缺项应真实失败")
        self.assertTrue(any("缺项" in 问题 for 问题 in 结果.问题列表), str(结果.问题列表))
        self.assertTrue(
            any("模块库.文件管理→文件系统支持库.文件操作.读取文件→无提供者" in 问题 for 问题 in 结果.问题列表),
            f"应有 包→能力→无提供者 可诊断路径: {结果.问题列表}",
        )
        # 反向证明：把提供者补回锁内即通过（校验真实生效，非恒真断言）
        _写锁(项目根, [
            _锁条目("模块库.文件管理"),
            _锁条目("支持库.后端.文件系统支持库.文件操作"),
            _锁条目("支持库.后端.系统核心支持库.资源管理"),
        ])
        恢复结果 = 校验传递闭包(项目根, 系统根)
        self.assertTrue(恢复结果.成功, f"补回提供者后应通过: {恢复结果.问题列表}")


