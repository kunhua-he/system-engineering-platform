"""第十四阶段 P2-18 统一体验面对称审计测试：五类视图与统一能力服务的对称性。

审计目标：五类调用者（UI/Agent/命令行/Python/MCP 对应的五个视图）必须走
同一统一能力服务（平台控制面/统一入口.py 的统一能力服务.执行操作），不得
复制搜索、权限、调用、发布规则。测试分为：
- 测试1/2：静态审计（ast 解析五个视图源码：无自实现判定 + 服务调用必达）；
- 测试3：调用对称（普通用户视图 vs 服务直接调用，同一能力结果一致）；
- 测试4：权限对称（越权操作在两个路径都被同样拒绝，错误码一致）；
- 测试5：搜索对称（同一关键词，五视图搜索结果与直接搜索一致）；
- 测试6：错误对称（未登记能力两路径均 CAPABILITY_NOT_FOUND）；
- 测试7：阻断清单（发现不对称/违规即失败并列出阻断项）。
"""
