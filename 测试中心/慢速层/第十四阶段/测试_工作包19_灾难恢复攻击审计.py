"""第十四阶段工作包19：灾难恢复与可信仓库攻击审计测试（慢速层）。

七个注入场景全部真实执行：空目录恢复/备份损坏/旧快照重放/过期元数据/
签名替换/恢复中强杀（真实子进程 kill -9）/备份缺失；测试8 汇总阻断清单。
发现生产缺陷的测试断言如实失败并在输出列出（阻断项由主 Agent 在 S2 修复）。
"""
from __future__ import annotations

import json
import sys
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[3]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 测试中心.辅助.灾难恢复审计.阻断清单 import 审计全部场景, 阻断清单
from 测试中心.辅助.灾难恢复审计.审计环境 import 最小能力输出
from 测试中心.辅助.灾难恢复审计.强杀审计 import 旧版摘要

全部结果 = 审计全部场景()
场景索引 = {结果["场景"]: 结果 for 结果 in 全部结果}
阻断项 = 阻断清单(全部结果)


class 测试工作包19灾难恢复攻击审计(unittest.TestCase):
    """对灾难恢复与可信仓库的真实攻击注入；有缺陷的断言如实失败。"""

    def test_1_空目录恢复成功且最小能力真实调用(self):
        """场景1：全新空目录 + 真实备份 → 恢复成功、最小调用真实可用。"""
        结果 = 场景索引["空目录恢复"]
        self.assertTrue(结果["防御有效"], f"阻断缺陷: {结果['缺陷']}")
        self.assertEqual(结果["详情"]["校验备份"], True)
        self.assertEqual(结果["详情"]["编排状态"], "已恢复")
        self.assertTrue(结果["详情"]["契约恢复"])
        self.assertEqual(结果["详情"]["最小调用输出"], 最小能力输出)
        self.assertEqual(结果["详情"]["期望差异数"], 0)

    def test_2_备份损坏校验与恢复必须失败(self):
        """场景2：篡改权威状态 db / 制品文件 → 校验与恢复必须失败。"""
        结果 = 场景索引["备份损坏"]
        self.assertTrue(结果["防御有效"], f"阻断缺陷: {结果['缺陷']}")
        self.assertFalse(结果["详情"]["db篡改校验"][0], "篡改 db 后校验不得成功")
        self.assertFalse(结果["详情"]["db篡改恢复成功"], "篡改 db 后恢复不得假装成功")
        self.assertFalse(结果["详情"]["制品篡改校验"][0], "篡改制品后校验不得成功")

    def test_3_旧快照重放必须检测版本回退(self):
        """场景3：旧备份覆盖新状态 → 必须识别版本回退（若无此能力则如实失败列入阻断）。"""
        结果 = 场景索引["旧快照重放"]
        self.assertTrue(结果["详情"]["元数据层对照拒绝"], "可信仓库元数据层应已有快照回放检测")
        self.assertTrue(结果["详情"]["回退被检测"],
                        f"阻断缺陷: {结果['缺陷']}")
        self.assertEqual(结果["详情"]["重放后版本"], "旧版v1")

    def test_4_过期元数据校验必须拒绝(self):
        """场景4：元数据过期时间在过去 → 校验必须拒绝。"""
        结果 = 场景索引["过期元数据"]
        self.assertTrue(结果["防御有效"], f"阻断缺陷: {结果['缺陷']}")
        for 名称 in ("根信任", "目标", "快照"):
            成功, 原因 = 结果["详情"][名称]
            self.assertFalse(成功, f"过期{名称}未被拒绝: {原因}")
            self.assertIn("过期", 原因, f"过期{名称}拒绝原因不明: {原因}")
        self.assertIn("过期", 结果["详情"]["伪造过期目标"][1], "伪造过期目标必须拒绝")

    def test_5_签名替换校验必须失败(self):
        """场景5：换公钥重签/替换制品/篡改快照/伪造根信任 → 校验必须失败。"""
        结果 = 场景索引["签名替换"]
        self.assertTrue(结果["防御有效"], f"阻断缺陷: {结果['缺陷']}")
        self.assertFalse(结果["详情"]["换公钥重签"][0], "换公钥重签不得通过")
        self.assertFalse(结果["详情"]["制品替换"][0], "制品替换不得通过")
        self.assertFalse(结果["详情"]["快照篡改"][0], "快照目标表篡改不得通过")
        self.assertFalse(结果["详情"]["伪造根信任"][0], "伪造根信任不得通过")

    def test_6_恢复中强杀后再次恢复幂等无半状态(self):
        """场景6：真实子进程在恢复提交后被 kill -9 → 再次恢复必须幂等。"""
        结果 = 场景索引["恢复中强杀"]
        self.assertTrue(结果["防御有效"], f"阻断缺陷: {结果['缺陷']}")
        详情 = 结果["详情"]
        self.assertEqual(详情["恢复表"], [], "恢复动作已提交，再次恢复必须幂等为空")
        self.assertTrue(详情["幂等"])
        self.assertEqual(详情["指针目标"], 旧版摘要, "回滚场景指针必须明确旧版")

    def test_7_备份缺失必须明确失败(self):
        """场景7：备份缺关键文件 → 校验/恢复必须明确失败。"""
        结果 = 场景索引["备份缺失"]
        self.assertTrue(结果["防御有效"], f"阻断缺陷: {结果['缺陷']}")
        self.assertFalse(结果["详情"]["源缺失校验"][0], "源缺失备份校验不得成功")
        self.assertIn("缺失", 结果["详情"]["源缺失校验"][1], "源缺失失败原因不明确")
        self.assertFalse(结果["详情"]["源缺失恢复成功"], "源缺失备份恢复不得成功")
        self.assertFalse(结果["详情"]["删db校验"][0], "删除 db 后校验不得成功")
        self.assertTrue(结果["详情"]["删db恢复失败"], "删除 db 后恢复必须失败")
        self.assertTrue(结果["详情"]["删清单拒绝"], "删除备份清单后必须明确拒绝")

    def test_8_阻断清单汇总(self):
        """场景8：全部注入结果汇总；有缺陷的列为阻断项并如实输出。"""
        self.assertEqual(len(全部结果), 7,
                         f"必须恰好七个注入场景: {[结果['场景'] for 结果 in 全部结果]}")
        self.assertEqual({结果["场景"] for 结果 in 全部结果},
                         {"空目录恢复", "备份损坏", "旧快照重放", "过期元数据",
                          "签名替换", "恢复中强杀", "备份缺失"})
        print("\n===== 工作包19 攻击审计汇总 =====")
        for 结果 in 全部结果:
            状态 = "防御有效" if 结果["防御有效"] else "存在缺陷(阻断)"
            print(f"场景[{结果['场景']}]: {状态}")
            if not 结果["防御有效"]:
                print(f"  缺陷: {结果['缺陷']}")
                print(f"  详情: {json.dumps(结果['详情'], ensure_ascii=False)}")
        print(f"阻断项数: {len(阻断项)}")
        for 项 in 阻断项:
            print(f"阻断[{项['场景']}]: {项['缺陷']}")
        self.assertEqual([项["场景"] for 项 in 阻断项],
                         [结果["场景"] for 结果 in 全部结果 if not 结果["防御有效"]],
                         "阻断清单必须与缺陷场景一一对应")


if __name__ == "__main__":
    unittest.main(verbosity=2)
