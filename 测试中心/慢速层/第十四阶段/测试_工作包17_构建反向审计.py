"""第十四阶段 P2-17 构建反向审计真实测试（慢速层）。

反向审计工作包06 可复现构建器：路径、环境顺序、文件遍历顺序、缓存污染下
摘要必须确定；篡改任一输入摘要必须改变；时间/主机污染按输入冻结语义核对。
测试8 汇总全部审计并断言阻断清单为空——如发现生产缺陷，测试失败即阻断，
并在测试输出中明确列出阻断清单。
"""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[3]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))
from 测试中心.辅助.可复现构建审计 import (
    执行全部审计, 审计_路径污染, 审计_环境顺序污染, 审计_文件遍历顺序污染,
    审计_缓存污染, 审计_输入篡改, 审计_时间污染, 审计_主机差异,
)


class 测试构建反向审计(unittest.TestCase):
    """对工作包06 可复现构建器的污染/篡改反向审计，全部真实执行。"""

    def _执行并断言(self, 审计函数, 名称: str) -> None:
        通过, 证据 = 审计函数()
        print(f"[审计] {名称}:\n{证据}")
        self.assertTrue(通过, f"{名称}未通过（生产缺陷）：\n{证据}")

    def test_路径污染审计(self):
        """两个不同工作区路径构建摘要一致（路径不得进摘要）。"""
        self._执行并断言(审计_路径污染, "路径污染")

    def test_环境顺序污染审计(self):
        """文件表写入顺序不同摘要一致（排序稳定性）。"""
        self._执行并断言(审计_环境顺序污染, "环境顺序污染")

    def test_文件遍历顺序污染审计(self):
        """构建目录文件加入顺序不同摘要一致（遍历按路径排序）。"""
        self._执行并断言(审计_文件遍历顺序污染, "文件遍历顺序污染")

    def test_缓存污染审计(self):
        """修改/删除构建缓存后重建摘要与首次一致（不得依赖缓存残留）。"""
        self._执行并断言(审计_缓存污染, "缓存污染")

    def test_输入篡改审计(self):
        """篡改任一输入文件内容/删除/新增/时刻/主机，摘要必须改变。"""
        self._执行并断言(审计_输入篡改, "输入篡改")

    def test_时间污染审计(self):
        """同一冻结时刻两次构建一致；不同冻结时刻输入摘要不同。"""
        self._执行并断言(审计_时间污染, "时间污染")

    def test_主机差异审计(self):
        """同一主机名两次一致；不同主机名输入摘要不同。"""
        self._执行并断言(审计_主机差异, "主机差异")

    def test_阻断清单审计(self):
        """汇总全部审计：发现生产缺陷则测试失败，输出阻断清单。"""
        通过, 阻断清单, 证据 = 执行全部审计()
        print(f"[审计] 全部审计证据：\n{证据}")
        if 阻断清单:
            print(f"阻断清单（测试断言失败即阻断，共{len(阻断清单)}项）：")
            for 项 in 阻断清单:
                print(f"  [阻断] {项}")
        self.assertTrue(通过, "存在生产缺陷，阻断清单见上方输出")


if __name__ == "__main__":
    unittest.main(verbosity=2)
