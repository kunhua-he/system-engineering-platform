def 加载会话恢复模块():
    """按文件路径加载 会话恢复.py（与测试中心 load_tests 同机制）。

    不依赖 平台控制面/提供者/__init__.py 的当前导入链——第十三阶段
    并行收口期该入口可能被协调者改写，按文件加载免疫瞬时断链。
    """
    模块名 = "会话恢复_测试加载"
    sys.modules.pop(模块名, None)
    路径 = 系统根 / "平台控制面" / "提供者" / "会话恢复.py"
    规格 = importlib.util.spec_from_file_location(模块名, 路径)
    if 规格 is None or 规格.loader is None:
        raise ImportError(f"无法加载会话恢复模块: {路径}")
    模块 = importlib.util.module_from_spec(规格)
    sys.modules[模块名] = 模块
    规格.loader.exec_module(模块)
    return 模块


会话恢复模块 = 加载会话恢复模块()
恢复会话 = 会话恢复模块.恢复会话


class Test会话重启后旧令牌失效(unittest.TestCase):
    """场景一：模拟重启（同一存储目录新建统一能力服务）后旧令牌全部失效。"""

    def test_重启后旧会话令牌调用操作被拒(self):
        目录 = Path(tempfile.mkdtemp(prefix="会话恢复_重启_"))
        # 实例A：注册 + 引导授予 + 真实操作成功
        服务A = 统一能力服务(存储目录=目录)
        令牌A = 服务A.授权.注册身份(身份id="身份甲")
        成功, 消息 = 服务A.授权.引导授予(身份id="身份甲", 角色=组件开发Agent, 授予者="系统引导")
        self.assertTrue(成功, 消息)
        成功, 消息 = 服务A.授权.切换角色(令牌A, 组件开发Agent)
        self.assertTrue(成功, 消息)
        结果 = 服务A.执行操作(令牌=令牌A, 操作="搜索能力", 参数={"关键词": "文本"})
        self.assertTrue(结果["成功"], "重启前旧令牌可正常调用操作")
        # 对称场景：会话过期同样视为失效
        服务A.授权._会话表[令牌A]["过期时间"] = time.time() - 1
        允许, 错误码, _ = 服务A.授权.校验操作(令牌=令牌A, 操作="搜索能力")
        self.assertFalse(允许)
        self.assertEqual(错误码, 稳定错误码["会话过期"])
        服务A.状态.关闭()  # 模拟进程退出

        # 实例B：同一存储目录新建（模拟重启），旧令牌必须全部被拒
        服务B = 统一能力服务(存储目录=目录)
        结果 = 服务B.执行操作(令牌=令牌A, 操作="搜索能力", 参数={})
        self.assertFalse(结果["成功"], "重启后旧会话令牌调用操作必须失败")
        self.assertEqual(结果["错误码"], "会话不存在")
        结果 = 服务B.执行操作(令牌=令牌A, 操作="创建组件", 参数={})
        self.assertFalse(结果["成功"])
        self.assertEqual(结果["错误码"], "会话不存在")
        成功, 消息 = 服务B.授权.切换角色(令牌A, 组件开发Agent)
        self.assertFalse(成功)
        self.assertEqual(消息, "会话不存在")
        成功, 消息 = 服务B.授权.授予角色(授予者令牌=令牌A, 身份id="身份乙", 角色=调用Agent)
        self.assertFalse(成功)
        self.assertEqual(消息, "授予者会话不存在")
        服务B.状态.关闭()


class Test授予持久化按策略恢复(unittest.TestCase):
    """场景二：重启后持久化角色授予按策略恢复。"""

    def test_引导授予身份重新注册可切换回已授予角色(self):
        目录 = Path(tempfile.mkdtemp(prefix="会话恢复_授予_"))
        # 实例A：引导授予 平台维护者（唯一受信提权路径），重启前可执行高权限操作
        服务A = 统一能力服务(存储目录=目录)
        令牌A = 服务A.授权.注册身份(身份id="身份甲")
        成功, 消息 = 服务A.授权.引导授予(身份id="身份甲", 角色=平台维护者, 授予者="系统引导")
        self.assertTrue(成功, 消息)
        成功, 消息 = 服务A.授权.切换角色(令牌A, 平台维护者)
        self.assertTrue(成功, 消息)
        结果 = 服务A.执行操作(令牌=令牌A, 操作="查看诊断", 参数={})
        self.assertTrue(结果["成功"], f"重启前高权限操作放行: {结果}")
        服务A.状态.关闭()

        # 实例B：同一存储目录（模拟重启）——角色授予从持久化表恢复
        服务B = 统一能力服务(存储目录=目录)
        # 按策略恢复会话：重新注册 + 切回最高已授予角色
        成功, 消息, 令牌B, 角色B = 恢复会话(服务B.授权, "身份甲")
        self.assertTrue(成功, 消息)
        self.assertEqual(角色B, 平台维护者, "持久化授予按策略恢复")
        # 恢复出的会话可直接执行需该角色的操作
        结果 = 服务B.执行操作(令牌=令牌B, 操作="查看诊断", 参数={})
        self.assertTrue(结果["成功"], f"恢复会话后按已授予角色执行操作: {结果}")
        # 未授予的高权限仍然不可切（授权不可自举在重启后依旧成立）
        成功, 消息 = 服务B.授权.切换角色(令牌B, 发布者)
        self.assertFalse(成功)
        self.assertTrue(消息.startswith("角色未授予"), 消息)
        # 直接重新注册（不走恢复辅助）同样能切回已授予角色
        令牌B2 = 服务B.授权.注册身份(身份id="身份甲")
        成功, 消息 = 服务B.授权.切换角色(令牌B2, 平台维护者)
        self.assertTrue(成功, 消息)
        允许, 错误码, 会话 = 服务B.授权.校验操作(令牌=令牌B2, 操作="查看诊断")
        self.assertTrue(允许, 错误码)
        self.assertEqual(会话["角色"], 平台维护者)
        服务B.状态.关闭()


class Test跨项目范围拒绝(unittest.TestCase):
    """场景三：跨项目范围操作被拒。"""

    def test_授予项目范围不匹配的操作被拒(self):
        目录 = Path(tempfile.mkdtemp(prefix="会话恢复_跨项目_"))
        状态 = 平台状态(目录, 项目id="会话恢复测试")
        授权 = 授权服务(状态)
        # 管理员：引导授予 平台维护者（空范围=全局），给 身份乙 授予
        # 组件开发Agent 且限定 项目范围=项目A
        令牌管理 = 授权.注册身份(身份id="管理员")
        成功, 消息 = 授权.引导授予(身份id="管理员", 角色=平台维护者, 授予者="系统引导")
        self.assertTrue(成功, 消息)
        成功, 消息 = 授权.切换角色(令牌管理, 平台维护者)
        self.assertTrue(成功, 消息)
        成功, 消息 = 授权.授予角色(授予者令牌=令牌管理, 身份id="身份乙",
                                角色=组件开发Agent, 项目范围="项目A")
        self.assertTrue(成功, 消息)
        令牌乙 = 授权.注册身份(身份id="身份乙")
        # 项目A 范围内：切换 + 操作放行
        成功, 消息 = 授权.切换角色(令牌乙, 组件开发Agent, 项目范围="项目A")
        self.assertTrue(成功, 消息)
        允许, 错误码, _ = 授权.校验操作(令牌=令牌乙, 操作="创建组件", 项目范围="项目A")
        self.assertTrue(允许, 错误码)
        # 跨项目（项目B）：已授予集合不含该角色 → 操作被拒
        允许, 错误码, _ = 授权.校验操作(令牌=令牌乙, 操作="创建组件", 项目范围="项目B")
        self.assertFalse(允许, "跨项目范围操作必须被拒")
        self.assertEqual(错误码, 稳定错误码["角色未授予"])
        # 跨项目切换同样被拒
        成功, 消息 = 授权.切换角色(令牌乙, 组件开发Agent, 项目范围="项目B")
        self.assertFalse(成功)
        self.assertTrue(消息.startswith("角色未授予"), 消息)
        # 已授予角色() 按项目范围过滤
        self.assertNotIn(组件开发Agent, 授权.已授予角色("身份乙", "项目B"))
        self.assertIn(组件开发Agent, 授权.已授予角色("身份乙", "项目A"))
        # 跨项目恢复会话只恢复普通用户（最高匹配授予），不越权
        成功, 消息, 令牌恢复, 角色恢复 = 恢复会话(授权, "身份乙", "项目B")
        self.assertTrue(成功, 消息)
        self.assertEqual(角色恢复, 普通用户, "跨项目恢复不得恢复项目外角色")
        状态.关闭()


