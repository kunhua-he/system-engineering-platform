"""第十三阶段：授权会话重启恢复测试（模拟重启 = 同一存储目录新建实例）。

三个真实场景：
1. 重启后旧会话令牌调用操作必须失败——会话表是内存态，实例重建即清空，
   旧令牌在 校验操作/切换角色/授予角色 全部报\"会话不存在\"（对称：会话
   过期同样视为失效）；
2. 持久化角色授予按策略恢复——角色授予表是持久化权威事实，重启后引导
   授予过的身份重新注册，经 恢复会话() 辅助按策略切回已授予角色，恢复
   出的会话可执行需该角色的操作；未授予的高权限依旧不可切（授权不可
   自举在重启后仍成立）；
3. 跨项目范围操作被拒——授予带项目范围，越范围的操作/切换全部被拒，
   已授予角色() 按项目范围过滤。
"""
