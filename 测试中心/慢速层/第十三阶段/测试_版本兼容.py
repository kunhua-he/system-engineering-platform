"""第十三阶段：核心双版本状态兼容测试（真实执行链）。

4 个真实场景：
1. 迁移四步状态机真实推进：开始→扩展→双读→切换→清理，旧/新快照磁盘并存且
   文件表内容不同，激活指针 CAS 切换，四步状态证据齐全，旧快照真实删除。
2. 旧核心兼容窗口内双实例读同一状态存储：旧/新核心两个独立实例读同一权威
   状态库，读到同一份新快照记录；窗口外（新状态版本超出旧快照兼容范围）拒绝。
3. 状态兼容范围不匹配阻止切换：新快照兼容范围不含当前状态版本 → 切换被拒、
   激活指针保持旧快照；范围匹配 → 切换成功。
4. 新核心失败回退旧指针：健康检查真实失败 → 切换中止、指针保持/回退旧快照、
   显式回退 CAS 切回；引用未归零禁止删除旧快照，归零后真实删除。

调用生产实现（版本兼容编排器 + 核心快照 + 平台状态 + 发布管理），禁止模拟绿灯。
"""
import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[3]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 平台控制面.平台状态 import 平台状态
from 平台控制面.核心快照 import 核心快照管理
from 平台控制面.发布管理 import 发布管理
from 平台控制面.提供者.版本兼容 import 版本兼容
from 支持库.适配层.密码适配 import 生成密钥对


class Test核心双版本状态兼容(unittest.TestCase):
    """核心双版本状态兼容：4 个真实场景。"""

    def setUp(self):
        self.目录 = Path(tempfile.mkdtemp(prefix="版本兼容测试_"))
        self.状态 = 平台状态(self.目录, 项目id="版本兼容测试")
        self.快照 = 核心快照管理(self.状态, 快照根目录=self.目录 / "核心快照")
        self.发布 = 发布管理(self.状态)
        self.兼容 = 版本兼容(self.状态, self.快照, self.发布)
        self.私钥, self.公钥 = 生成密钥对()
        self.状态.写入记录("信任", {"发布者": "发布者甲", "公钥": self.公钥,
                                 "状态": "有效", "轮换时间": "", "过期时间": ""})
        # 旧核心快照：真实创建 + Ed25519 真实签名
        self.旧快照id = self.快照.创建快照(
            运行核心版本="1.2.0", 前端核心版本="1.2.0", 后端核心版本="1.2.0",
            状态兼容范围="1.0.0-1.4.0", 回滚许可=True, 迁移方式="扩展",
            文件表={"核心.manifest": "旧核心 1.2.0", "状态.json": '{"结构版本": "1.2.0"}'})
        成功, 消息 = self.快照.签名快照(快照id=self.旧快照id,
                                     私钥PEM=self.私钥, 发布者="发布者甲")
        self.assertTrue(成功, 消息)
        self.状态.写入记录("激活指针", {"指针id": "核心", "目标": self.旧快照id,
                                    "版本": 1, "栅栏令牌": 1, "状态": "激活"})

    def tearDown(self):
        self.状态.关闭()
        shutil.rmtree(self.目录, ignore_errors=True)

    def _新快照文件表(self) -> dict:
        return {"核心.manifest": "新核心 1.3.0", "状态.json": '{"结构版本": "1.3.0"}',
                "能力清单.json": "扩展的新状态结构"}

    def _走完双读(self, 迁移id: str) -> str:
        """扩展 + 双读 推进，返回新快照id（四步状态机前两步真实执行）。"""
        self.兼容.扩展(迁移id=迁移id, 运行核心版本="1.3.0", 前端核心版本="1.3.0",
                      后端核心版本="1.3.0", 状态兼容范围="1.0.0-1.4.0",
                      文件表=self._新快照文件表(),
                      私钥PEM=self.私钥, 发布者="发布者甲")
        结果 = self.兼容.双读(迁移id=迁移id, 新状态版本="1.4.0")
        self.assertTrue(结果["成功"], 结果.get("错误"))
        return self.兼容.查询迁移(迁移id)["新快照id"]

    def test_迁移四步状态机真实推进(self):
        """场景1：开始→扩展→双读→切换→清理全流程，每步状态证据真实。"""
        结果 = self.兼容.开始迁移(旧快照id=self.旧快照id, 目标版本="1.3.0",
                               状态兼容范围="1.0.0-1.4.0")
        self.assertTrue(结果["成功"], 结果.get("错误"))
        迁移id = 结果["迁移id"]
        self.assertEqual(结果["阶段"], "开始")
        self.assertEqual(结果["指针"]["目标"], self.旧快照id, "开始迁移时指针保持旧快照")
        # 扩展：真实创建新快照（文件表内容不同）+ 签名；双快照磁盘并存
        结果 = self.兼容.扩展(迁移id=迁移id, 运行核心版本="1.3.0",
                            前端核心版本="1.3.0", 后端核心版本="1.3.0",
                            状态兼容范围="1.0.0-1.4.0", 文件表=self._新快照文件表(),
                            私钥PEM=self.私钥, 发布者="发布者甲")
        self.assertTrue(结果["成功"], 结果.get("错误"))
        新快照id = 结果["新快照id"]
        self.assertNotEqual(新快照id, self.旧快照id)
        self.assertTrue(结果["双快照并存"], "扩展后旧/新快照必须磁盘并存")
        旧目录 = self.快照.快照根目录 / self.旧快照id
        新目录 = self.快照.快照根目录 / 新快照id
        self.assertTrue(旧目录.is_dir() and 新目录.is_dir())
        self.assertNotEqual((旧目录 / "核心.manifest").read_text(encoding="utf-8"),
                            (新目录 / "核心.manifest").read_text(encoding="utf-8"),
                            "旧/新快照文件表内容必须不同")
        # 双读：双实例读同一存储，旧核心兼容窗口内读到同一份新快照记录
        结果 = self.兼容.双读(迁移id=迁移id, 新状态版本="1.4.0")
        self.assertTrue(结果["成功"], 结果.get("错误"))
        self.assertTrue(结果["同一存储"], "双实例必须读同一存储")
        self.assertTrue(结果["兼容窗口"], "旧核心兼容窗口必须成立")
        self.assertEqual(结果["旧核心读取"]["快照id"], 新快照id)
        self.assertEqual(结果["新核心读取"]["快照id"], 新快照id)
        # 切换：健康检查真实通过 → CAS 指针切到新快照（版本/栅栏令牌递增）
        结果 = self.兼容.切换(迁移id=迁移id, 健康检查=lambda: True)
        self.assertTrue(结果["成功"], 结果.get("错误"))
        指针 = self.发布.当前激活("核心")
        self.assertEqual(指针["目标"], 新快照id, "切换后激活指针必须指向新快照")
        self.assertGreater(int(指针["版本"]), 1, "指针版本必须单调递增")
        self.assertGreater(int(指针["栅栏令牌"]), 1, "栅栏令牌必须单调递增")
        # 清理：引用归零 → 真实删除旧快照目录，新快照保留
        结果 = self.兼容.清理(迁移id=迁移id)
        self.assertTrue(结果["成功"], 结果.get("错误"))
        self.assertTrue(结果["已删除旧快照"])
        self.assertFalse(旧目录.exists(), "旧快照目录必须真实删除")
        self.assertTrue(新目录.is_dir(), "新快照目录必须保留")
        self.assertEqual(self.兼容.查询迁移(迁移id)["阶段"], "清理")
        # 四步状态证据齐全（开始/扩展/双读/切换/清理）
        证据表 = self.兼容.迁移证据(迁移id)
        阶段表 = [证据["内容"]["阶段"] for 证据 in 证据表]
        for 阶段 in ("开始", "扩展", "双读", "切换", "清理"):
            self.assertIn(阶段, 阶段表, f"证据账本必须包含 {阶段} 阶段证据")
        # 阶段顺序校验：状态机不得乱序推进
        顺序 = [证据["内容"]["阶段"] for 证据 in sorted(证据表,
                                                     key=lambda 证据: 证据["时间"])]
        self.assertEqual(顺序, ["开始", "扩展", "双读", "切换", "清理"], "四步必须按契约顺序推进")

    def test_旧核心兼容窗口内双实例读同一状态存储(self):
        """场景2：旧/新核心两个独立实例读同一权威状态库，读到同一份快照记录。"""
        迁移id = self.兼容.开始迁移(旧快照id=self.旧快照id, 目标版本="1.3.0",
                                 状态兼容范围="1.0.0-1.4.0")["迁移id"]
        新快照id = self._走完双读(迁移id)
        # 独立双实例：两个全新 平台状态/核心快照管理 实例指向同一 db 文件
        旧实例 = 核心快照管理(平台状态(self.目录, 项目id="旧核心进程"),
                           快照根目录=self.快照.快照根目录)
        新实例 = 核心快照管理(平台状态(self.目录, 项目id="新核心进程"),
                           快照根目录=self.快照.快照根目录)
        try:
            self.assertEqual(旧实例.状态.数据库路径, 新实例.状态.数据库路径,
                             "双实例必须指向同一权威状态库文件")
            self.assertEqual(旧实例.状态.数据库路径, self.状态.数据库路径)
            # 旧核心兼容窗口内：旧实例能看到新快照记录（读取新状态）
            旧记录 = 旧实例.状态.读取记录("核心快照", "快照id", 新快照id)
            新记录 = 新实例.状态.读取记录("核心快照", "快照id", 新快照id)
            self.assertIsNotNone(旧记录, "旧核心实例必须能读取新快照记录（兼容窗口内）")
            self.assertEqual(旧记录["摘要"], 新记录["摘要"], "双实例读到同一份记录")
            self.assertEqual(旧记录["状态兼容"], 新记录["状态兼容"])
            # 旧核心快照自身仍可读（服务不中断）
            旧快照 = 旧实例.状态.读取记录("核心快照", "快照id", self.旧快照id)
            self.assertIsNotNone(旧快照, "旧核心自身记录仍可读")
        finally:
            旧实例.状态.关闭()
            新实例.状态.关闭()
        # 窗口外：新状态版本 1.5.0 超出旧快照兼容范围 1.0.0-1.4.0 → 双读拒绝且不推进
        迁移id2 = self.兼容.开始迁移(旧快照id=self.旧快照id, 目标版本="1.5.0",
                                  状态兼容范围="1.5.0-1.6.0")["迁移id"]
        结果 = self.兼容.扩展(迁移id=迁移id2, 运行核心版本="1.5.0",
                            前端核心版本="1.5.0", 后端核心版本="1.5.0",
                            状态兼容范围="1.5.0-1.6.0", 文件表=self._新快照文件表(),
                            私钥PEM=self.私钥, 发布者="发布者甲")
        self.assertTrue(结果["成功"], 结果.get("错误"))
        结果 = self.兼容.双读(迁移id=迁移id2, 新状态版本="1.5.0")
        self.assertFalse(结果["成功"], "旧核心不在兼容窗口必须拒绝双读")
        self.assertIn("兼容窗口", 结果.get("错误", ""))
        self.assertFalse(结果["兼容窗口"])
        self.assertEqual(self.兼容.查询迁移(迁移id2)["阶段"], "扩展",
                         "双读失败不得推进状态机")

    def test_状态兼容范围不匹配阻止切换(self):
        """场景3：新快照兼容范围不含当前状态版本 → 切换被阻止，指针保持旧快照。"""
        迁移id = self.兼容.开始迁移(旧快照id=self.旧快照id, 目标版本="1.3.0",
                                 状态兼容范围="1.5.0-1.6.0")["迁移id"]
        # 新快照声明状态兼容 1.5.0-1.6.0（不含当前平台状态 1.3.0）
        结果 = self.兼容.扩展(迁移id=迁移id, 运行核心版本="1.3.0",
                            前端核心版本="1.3.0", 后端核心版本="1.3.0",
                            状态兼容范围="1.5.0-1.6.0", 文件表=self._新快照文件表(),
                            私钥PEM=self.私钥, 发布者="发布者甲")
        self.assertTrue(结果["成功"], 结果.get("错误"))
        # 双读仍成功（旧窗口覆盖新状态版本 1.4.0）
        结果 = self.兼容.双读(迁移id=迁移id, 新状态版本="1.4.0")
        self.assertTrue(结果["成功"], 结果.get("错误"))
        # 切换被阻止：新快照状态兼容范围不匹配
        结果 = self.兼容.切换(迁移id=迁移id, 健康检查=lambda: True)
        self.assertFalse(结果["成功"], "状态兼容范围不匹配必须阻止切换")
        self.assertTrue(结果.get("阻止切换"), 结果.get("错误"))
        self.assertIn("状态兼容范围不匹配", 结果.get("错误", ""))
        指针 = self.发布.当前激活("核心")
        self.assertEqual(指针["目标"], self.旧快照id, "阻止切换后指针必须保持旧快照")
        self.assertEqual(self.兼容.查询迁移(迁移id)["阶段"], "双读", "切换失败不得推进状态机")
        # 范围匹配的新快照（1.0.0-1.4.0 覆盖当前状态 1.3.0）→ 切换成功
        迁移id2 = self.兼容.开始迁移(旧快照id=self.旧快照id, 目标版本="1.3.0",
                                  状态兼容范围="1.0.0-1.4.0")["迁移id"]
        新快照id = self._走完双读(迁移id2)
        结果 = self.兼容.切换(迁移id=迁移id2, 健康检查=lambda: True)
        self.assertTrue(结果["成功"], 结果.get("错误"))
        指针 = self.发布.当前激活("核心")
        self.assertEqual(指针["目标"], 新快照id, "范围匹配后切换必须成功")

    def test_新核心失败回退旧指针且引用未归零禁止删除快照(self):
        """场景4：健康检查失败回退旧指针；引用未归零禁止删除，归零后真实删除。"""
        迁移id = self.兼容.开始迁移(旧快照id=self.旧快照id, 目标版本="1.3.0",
                                 状态兼容范围="1.0.0-1.4.0")["迁移id"]
        新快照id = self._走完双读(迁移id)
        # 健康检查真实失败（返回 False）→ 切换中止，指针保持旧快照（新核心失败回退旧指针）
        结果 = self.兼容.切换(迁移id=迁移id, 健康检查=lambda: False)
        self.assertFalse(结果["成功"])
        self.assertTrue(结果.get("回退"), 结果.get("错误"))
        指针 = self.发布.当前激活("核心")
        self.assertEqual(指针["目标"], self.旧快照id, "健康检查失败必须回退旧指针")
        # 已切到新快照后显式回退：CAS 切回旧指针（兜底路径）
        self.发布.切换激活指针(指针id="核心", 目标=新快照id, 期望版本=1, 期望令牌=1)
        指针 = self.发布.当前激活("核心")
        self.assertEqual(指针["目标"], 新快照id, "前置：指针已切到新快照")
        结果 = self.兼容.回退(迁移id=迁移id, 原因="新核心运行异常")
        self.assertTrue(结果["成功"], 结果.get("错误"))
        self.assertTrue(结果["回退"])
        self.assertFalse(结果["指针保持旧快照"], "指针已切走，本次回退是真实切换动作")
        指针 = self.发布.当前激活("核心")
        self.assertEqual(指针["目标"], self.旧快照id, "显式回退后指针必须指向旧快照")
        self.assertGreater(int(指针["版本"]), 2, "回退同样走 CAS，版本继续递增")
        # 第二段：切换成功后，引用未归零 → 禁止删除旧快照
        迁移id2 = self.兼容.开始迁移(旧快照id=self.旧快照id, 目标版本="1.3.0",
                                  状态兼容范围="1.0.0-1.4.0")["迁移id"]
        新快照id2 = self._走完双读(迁移id2)
        结果 = self.兼容.切换(迁移id=迁移id2, 健康检查=lambda: True)
        self.assertTrue(结果["成功"], 结果.get("错误"))
        self.状态.写入记录("引用计数", {"引用键": f"快照引用:{self.旧快照id}",
                                    "包id": self.旧快照id, "版本": "1.2.0", "计数": 2})
        旧目录 = self.快照.快照根目录 / self.旧快照id
        结果 = self.兼容.清理(迁移id=迁移id2)
        self.assertFalse(结果["成功"], "引用未归零必须禁止删除快照")
        self.assertTrue(结果.get("禁止删除"), 结果.get("错误"))
        self.assertIn("引用未归零", 结果.get("错误", ""))
        self.assertTrue(旧目录.is_dir(), "引用未归零时旧快照目录必须保留")
        self.assertEqual(self.兼容.查询迁移(迁移id2)["阶段"], "切换", "清理被拒不得推进状态机")
        # 引用归零 → 允许真实删除旧快照目录
        self.状态.条件更新("引用计数", {"计数": 0},
                          "引用键=?", (f"快照引用:{self.旧快照id}",))
