class Test占位符不污染制品(unittest.TestCase):
    """测试3：占位符 {时间戳}/{工作区路径}/{主机名} 不污染制品。"""

    def test_占位符内容双工作区摘要仍一致(self):
        冻结 = 冻结样例()
        冻结["文件表"] = {
            "元信息.json": (
                '{"构建时间": "{时间戳}", "工作区": "{工作区路径}", "主机": "{主机名}"}'),
            "运行.py": "print('{时间戳}')\nprint('{工作区路径}')\nprint('{主机名}')",
        }
        构建器 = 可复现构建器()
        一致, 摘要1, 摘要2, 消息 = 构建器.双工作区验证(冻结)
        self.assertTrue(一致, f"占位符污染制品: {消息}")
        self.assertEqual(摘要1, 摘要2, "占位符替换后两个工作区摘要必须一致")
        # 展开结果必须落在确定性值上：构建时刻来自冻结输入，工作区/主机为固定值
        # （显式传入冻结值——构建不再改写实例状态，杜绝历史残留污染）
        展开 = 构建器.确定性展开(冻结["文件表"]["元信息.json"], "/任意/真实/路径",
                               构建时刻=冻结["构建时刻"], 主机名=冻结["主机名"])
        self.assertIn("2026-08-01 10:00:00", 展开, "时间戳必须是输入提供的冻结时刻")
        self.assertNotIn("/任意/真实/路径", 展开, "真实工作区绝对路径不得进入制品")
        self.assertIn("构建机1", 展开, "主机名必须替换为确定性值")


class Test输入变化摘要变化(unittest.TestCase):
    """测试4：改变任一输入文件内容后，摘要必须变化（确定性）。"""

    def test_改内容摘要变化(self):
        构建器 = 可复现构建器()
        工作区 = 新建工作区()
        冻结1 = 冻结样例()
        冻结2 = 冻结样例()
        冻结2["文件表"] = dict(冻结2["文件表"])
        冻结2["文件表"]["主.py"] = "版本 = '2.0.0'"
        _, 摘要1 = 构建器.构建(冻结1, 工作区)
        _, 摘要2 = 构建器.构建(冻结2, 工作区)
        self.assertNotEqual(摘要1, 摘要2, "输入内容变化后摘要必须变化")
        self.assertNotEqual(摘要1["主.py"], 摘要2["主.py"], "变化文件自身摘要必须变化")


class Test构建目录只含正式文件(unittest.TestCase):
    """测试5：构建目录只含正式文件（无临时文件、无缓存）。"""

    def test_构建目录无临时文件无缓存(self):
        构建器 = 可复现构建器()
        工作区 = 新建工作区()
        构建目录, 摘要 = 构建器.构建(冻结样例(), 工作区)
        预期文件 = {"主.py", "配置/配置.json"}
        实际文件 = {路径 for 路径 in 摘要}
        self.assertEqual(实际文件, 预期文件, "构建目录必须只含正式文件")
        磁盘文件 = {文件.relative_to(构建目录).as_posix()
                    for 文件 in 构建目录.rglob("*") if 文件.is_file()}
        self.assertEqual(磁盘文件, 预期文件, "磁盘文件集合必须与文件表一致")
        for 文件 in 构建目录.rglob("*"):
            self.assertNotIn("pycache", str(文件), "不得产生缓存目录")
            self.assertNotIn(".临时", 文件.name, "不得残留临时文件")


