def 值(结果) -> dict:
    """取统一结果的值（成功结果才有值）；失败即抛出断言信息。"""
    if not 结果.成功:
        raise AssertionError(f"预期成功，实为失败: {结果.错误码} {结果.错误说明}")
    return 结果.值


class 文件租约测试基类(unittest.TestCase):
    """每个用例一个独立存储目录（临时目录），用例之间零共享。"""

    def setUp(self) -> None:
        self._临时 = tempfile.TemporaryDirectory(prefix="文件租约测试")
        self.存储目录 = self._临时.name
        # ★ 2026-09-25（本批实测，`开工-20260925-161955-849f`）：把生效根**钉死**到仓库根。
        #   为什么：租约腿生效根走唯一那条解析腿（显式 `项目根` → 环境变量
        #   `系统平台_项目根` → 进程 cwd）。本文件有一批调用**只给 `存储目录`、不给
        #   `项目根`**（`释放文件租约` / `回收过期文件租约` / `续租文件租约` / `文件租约留言`），
        #   它们落第三级 ⇒ **读数随「谁起这个测试进程」而漂移**：
        #     · 带网关同款环境变量手动跑 ⇒ 走环境变量 ⇒ 53/53 全绿；
        #     · 经编译口子进程跑（子进程全量继承编译进程环境，那里没有该变量）⇒ 落进程 cwd
        #       ⇒ 十几条判红，摘要一律「项目根 不能为空」（该 fail-closed 门本身是对的）。
        #   这正是本文件 `申请` 那条注释早就写下的纪律：「不传就落到进程 cwd，用例会随
        #   『从哪个目录跑测试』而假绿/假红」—— 当时只修了 `申请` 一处，**兄弟漏改**。
        #   修法 = **夹具把环境钉住**（不逐个调用点补参数）：一处生效、覆盖全文件，
        #   且**不动生产判据一个字**（fail-closed 门照旧）。`mock.patch.dict` 由
        #   `addCleanup` 自动还原，不污染同进程其它用例。
        self._环境 = mock.patch.dict(os.environ, {"系统平台_项目根": str(仓库根)})
        self._环境.start()
        self.addCleanup(self._环境.stop)

    def tearDown(self) -> None:
        # ★ 2026-09-25（实测抓出的真缺陷，`开工-20260925-161955-849f`）：
        #   本文件多处直接用**真仓库路径**当测试目标（`文件1` / `文件2` / 以及
        #   `test_冲突策略跳过占用只锁能拿的` 里的 `公共契约/正式根.py`），而
        #   **认领即 `解锁供写入(目标 ＋ 父链)`** —— 本基座此前没有兜底回锁，于是这些
        #   真仓源文件在用例跑完后**永久留在未锁**（实测 `仓库锁 --查看` 报真缺口 2 条：
        #   `公共契约/正式根.py`、`平台控制面/能力目录/服务.py`，与这几条用例的认领清单
        #   逐条重合）。危害：内核锁是这些路径**唯一还起作用的防线**（Python 判据挡不住
        #   终端裸写），洞一开 `echo >` 就能直接改真仓源码。
        #   为什么修在**夹具**而不是回锁腿：回锁腿没错（`释放 ⇒ 回锁` 是它的既定契约），
        #   错的是这些用例**认领了却从不释放**；且「测试不许有副作用」本就是本仓纪律
        #   （同文件 `test_两个指纹拉出中途全部流水` 的注释已为「改真仓库文件」反省过）。
        #   兜底口径 = 把本用例账本里**仍活跃的租约**逐个交给唯一那条释放腿 ⇒ 它内部
        #   逐条 `回锁`（含父链判定），真仓库锁位由此复原；幂等，重复跑无副作用。
        try:
            self._兜底回锁()
        finally:
            self._临时.cleanup()

    def _兜底回锁(self) -> None:
        """把本用例账本里仍活跃的租约逐条**释放**（释放腿自带 `回锁`）。

        **不自己写解锁/上锁骨架**（哲学 1.2）：一律转调唯一那条 `释放文件租约`，
        由它按租约账判定 `连父链`；本函数只负责「把还留着的都交给它」。
        异常一律如实打进标准错误、**不静默吞** —— 否则真仓库的锁洞又成了没人知道的那种。
        """
        try:
            快照 = 值(查询文件租约(存储目录=self.存储目录, 带明细=真))["记录表"]
        except Exception as 错误:  # noqa: BLE001 —— 兜底腿不许成新的假绿来源
            print(f"★ 租约夹具兜底回锁：读账本失败，真仓锁位可能未复原（{错误}）",
                  file=sys.stderr)
            return
        仍活跃 = [str(条.get("租约id") or "") for 条 in 快照
                 if 条.get("状态") == "活跃" and str(条.get("租约id") or "")]
        if not 仍活跃:
            return
        try:
            释放 = 释放文件租约(租约id清单=仍活跃,
                             原因="夹具兜底：用例收尾回锁真仓路径",
                             存储目录=self.存储目录, 项目根=str(仓库根))
        except Exception as 错误:  # noqa: BLE001
            print(f"★ 租约夹具兜底回锁：释放腿抛错，真仓锁位可能未复原（{错误}）",
                  file=sys.stderr)
            return
        if not 释放.成功:
            print(f"★ 租约夹具兜底回锁：释放失败（{释放.错误码} {释放.错误说明}），"
                  "真仓锁位可能未复原", file=sys.stderr)

    def 申请(self, 路径, 所有者="会话1", 任务="测试任务", 持有秒=300.0, 存储目录=None):
        # ★ 2026-09-23：**显式**给 `项目根` —— 现场指纹读的是仓库内真实文件，不传就落到
        # 进程 cwd（网关跑制品时是制品根），用例会随「从哪个目录跑测试」而假绿/假红。
        return 申请文件租约(修改路径=路径, 所有者=所有者, 任务=任务,
                          持有秒=持有秒, 存储目录=存储目录 or self.存储目录,
                          项目根=str(仓库根))


