class 过期租约清理反向验证测试(文件租约测试基类):
    """★ 反向验证（本仓铁律：判据在 ≠ 判据覆盖）：「过期租约回收空转」这条缺陷。

    缺陷现场（2026-09-23 实测）：存储 714 条里 397 条「盘上状态=活跃 且 已过期」，
    `回收过期文件租约(心跳超时秒=300)` 默认/显式存储目录两次都回 `回收数 0` —— 一条也收不走；
    `释放文件租约` 对这 54 条自持租约回 `释放数 0、过期未清数 54`，盘上状态仍是「活跃」。

    病根：`回收过期文件租约` 的入口门写成 `是活跃(记录)`，而 `是活跃` 的口径是
    「状态活跃 **且** 未过期」—— 本函数要收的正是「状态活跃但已过期」那批，
    目标集合被自己的入口门整批滤空（`到点` 那一支永远走不到）。

    为什么既有用例拦不住（这就是「判据在 ≠ 判据覆盖」）：
    `test_回收过期幂等且过期后可被他人认领` 用 `心跳超时秒=0.0` 造的是**心跳停摆**
    那一支（记录当时**未过期**，能过入口门），于是缺陷态下依然全绿。
    本组用例专门打「到点」这一支，并注入缺陷证明判据真的会红。
    """

    def 造已过期但盘上标活跃的租约(self, 路径=文件1, 所有者="会话1") -> tuple[str, dict]:
        """造一条「盘上状态=活跃、但 `过期时间` 已到」的记录（持有秒=0 ⇒ 过期时间=认领时刻）。"""
        值表 = 值(self.申请([路径], 所有者=所有者, 持有秒=0.0))
        租约id = 值表["租约id清单"][0]
        盘上 = self.盘上记录(路径)
        self.assertEqual(盘上["状态"], "活跃", "前提：盘上状态必须写着「活跃」")
        self.assertLessEqual(盘上["过期时间"], __import__("time").time(),
                          "前提：该记录必须已过期（持有秒=0）")
        return 租约id, 盘上

    def 盘上记录(self, 路径: str) -> dict:
        """直读存储 JSON（**不经**任何读侧改判）——判「盘上到底写着什么」。"""
        原始 = json.loads((Path(self.存储目录) / "文件租约.json").read_text(encoding="utf-8"))
        return 原始[文件键(路径)]

    def test_回收必须收走状态活跃但已过期的记录(self) -> None:
        """核心判据：`到点` 分支必须可达 —— 改前 回收数 恒 0（结构性空转）。"""
        self.造已过期但盘上标活跃的租约()
        回收 = 值(回收过期文件租约(心跳超时秒=300.0, 存储目录=self.存储目录))
        self.assertEqual(回收["回收数"], 1,
                      "「状态活跃且已过期」的记录必须被回收（改前这里恒为 0：入口门用了 是活跃）")
        self.assertEqual(回收["回收清单"][0]["状态"], "已过期")
        self.assertIn("过期时间", 回收["回收清单"][0]["释放原因"], "必须如实说明是「到点」触发的")
        self.assertEqual(self.盘上记录(文件1)["状态"], "已过期",
                      "回收必须**落盘**改判，不能只改读数（否则僵尸仍冒充活跃）")
        查询 = 值(查询文件租约(修改路径=[文件1], 存储目录=self.存储目录, 只要活跃=真))
        self.assertEqual(查询["数量"], 0, "回收后不得再出现在「只要活跃」结果里")
        重新 = self.申请([文件1], 所有者="会话2")
        self.assertTrue(重新.成功, f"回收后必须可被其他会话认领: {重新.错误说明}")
        第二次 = 值(回收过期文件租约(心跳超时秒=300.0, 存储目录=self.存储目录))
        self.assertEqual(第二次["回收数"], 0, "回收必须幂等：第二次回带空清单")

    def test_过期租约不再挡同路径新认领(self) -> None:
        """口径复核：**已过期 ⇒ 不再挡路径**（改前那批 397 条僵尸的真实影响面）。

        实测：一条「状态活跃但已过期」的租约**不会**挡住同路径的新认领 —— 占用判定走
        `是活跃`（状态活跃 **且** 未过期），过期即放行。故「僵尸租约挡死路径」在**当前**
        口径下不成立；真正的危害是它们在盘上永久冒充活跃、被按 `状态` 字面量读的消费方
        当成占用者（故 `回收`/`释放` 必须落盘终结，见另两条用例）。
        本用例把这条口径钉住：过期即放行，且新认领是**换了一条新租约**而不是复活旧的。
        """
        旧租约id, _ = self.造已过期但盘上标活跃的租约(所有者="会话1")
        新认领 = self.申请([文件1], 所有者="会话2")
        self.assertTrue(新认领.成功,
                     f"过期租约不得挡住同路径新认领（占用判定走 是活跃）: {新认领.错误说明}")
        新租约id = 值(新认领)["租约id清单"][0]
        self.assertNotEqual(新租约id, 旧租约id, "必须是一条新租约，不得复活旧的")
        盘上 = self.盘上记录(文件1)
        self.assertEqual(盘上["状态"], "活跃", "认领不回收：盘上仍写着「活跃」（清理是 回收/释放 的职责）")
        self.assertGreater(盘上["过期时间"], __import__("time").time(), "新租约必须是活的")

    def test_缺陷注入时核心判据必须变红(self) -> None:
        """★ 反向验证（**真实状态注入**，不 patch 被测模块成员）：造一条真实的
        「盘上状态=活跃、`过期时间`已到」记录，两拍同时断言。

        2026-09-23 改写（原写法 `mock.patch("…文件租约维护.盘上活跃", side_effect=…)`
        把**被测模块自己的入口门成员**换掉了，属「patch 被测对象自身」的替身形态；
        且断言对象是注入的夹具）。现在改法：**同一份真实盘上记录**，断言分两拍 ——

        ① **事实拍**：`是活跃(盘上记录)` 必须为 **假**（状态活跃但已过期）——
           这正是旧入口门（`是活跃` = 状态活跃 **且** 未过期）会把它整批滤掉的原因；
        ② **判据拍**：`回收数` 必须为 1 —— 只有入口门是 `盘上活跃`（只看盘上 `状态`）
           才可能成立；若入口门退回 `是活跃`，这条记录会被 ① 那一拍滤掉、回收数恒 0。

        两拍合起来与「注入缺陷 ⇒ 回收数 0」**等价**（① 证事实、② 证判据），
        但断言对象是真实记录而不是夹具，且生产实现**原样真跑**。
        """
        self.造已过期但盘上标活跃的租约()
        盘上 = self.盘上记录(文件1)
        self.assertFalse(是活跃(盘上),
                      "前提拍：该记录在旧入口门 `是活跃`（状态活跃且未过期）下必须判「非活跃」"
                      "——旧入口门正是靠这一点把它整批滤掉（缺陷形态）")
        self.assertTrue(盘上活跃(盘上), "前提拍：盘上 `状态` 仍写着「活跃」（未过期）")
        回收 = 值(回收过期文件租约(心跳超时秒=300.0, 存储目录=self.存储目录))
        self.assertEqual(回收["回收数"], 1,
                      "判据拍：入口门必须是 `盘上活跃`（只看盘上状态）——若是 `是活跃`，"
                      "这条「状态活跃但已过期」的记录会被滤掉、回收数恒 0（缺陷形态）")
        self.assertEqual(回收["回收清单"][0]["状态"], "已过期")
        self.assertEqual(self.盘上记录(文件1)["状态"], "已过期")

    def test_释放过期租约必须落盘终结(self) -> None:
        """「释放不了」判据：改前 释放 只改读数不落盘 ⇒ 盘上永久冒充活跃。"""
        租约id, _ = self.造已过期但盘上标活跃的租约()
        释放 = 值(释放文件租约(租约id清单=[租约id], 原因="收工", 存储目录=self.存储目录))
        self.assertEqual(释放["释放数"], 1,
                      "盘上状态是「活跃」就必须能终结（改前恒 0：入口门用了 是活跃）")
        self.assertEqual(释放["过期未清数"], 1, "必须如实告警：该租约在释放时已过期")
        self.assertEqual(释放["幂等清单"], [], "能终结的不该落进幂等清单")
        盘上 = self.盘上记录(文件1)
        self.assertEqual(盘上["状态"], "已释放",
                      "改前这里仍是「活跃」（僵尸固化）；显式释放必须落盘终结")
        self.assertTrue(盘上["释放时间"])
        self.assertTrue(盘上["释放原因"].startswith("收工"),
                      "释放原因必须以调用方给的原因开头（消费方按前缀读，如「收口：…」）")
        self.assertIn("已过期", 盘上["释放原因"], "过期事实必须如实记载，不许静默抹掉")
        # 终结后重复释放仍幂等，且不得复活
        重复 = 值(释放文件租约(租约id清单=[租约id], 存储目录=self.存储目录))
        self.assertEqual(重复["释放数"], 0)
        self.assertEqual(重复["过期未清数"], 0, "已落盘终结的记录不再计入 过期未清数")
        self.assertEqual(重复["幂等清单"][0]["结果"], "已结束且已释放")
        self.assertEqual(self.盘上记录(文件1)["状态"], "已释放")
        续租 = 续租文件租约(租约id清单=[租约id], 存储目录=self.存储目录)
        self.assertFalse(续租.成功, "已释放的租约不得复活")
        self.assertEqual(续租.错误码, "租约不存在")

    def test_释放只碰自己的租约不碰别人的活跃租约(self) -> None:
        """负向断言（交付收尾技能腿同口径）：释放本会话租约不得动别人的活跃租约。"""
