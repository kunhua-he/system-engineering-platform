        返回 = json.loads(进程.stdout.strip().splitlines()[-1])
        self.assertFalse(返回["成功"], "跨进程第二次认领必须失败")
        self.assertEqual(返回["错误码"], "文件已被占用")
        self.assertIn("会话1", 返回["错误说明"])


