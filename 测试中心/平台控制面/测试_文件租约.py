        self.assertEqual(str(基准), str(仓库根))
        错, 问题2, 基准2 = 现场指纹与基准(文件1, self.错根)
        self.assertEqual(问题2, "")
        self.assertEqual(错, "不存在", "换一棵树必须读到「不存在」")
        self.assertNotEqual(错, 对, "项目根 必须真的决定读哪棵树（否则这个参数是摆设）")
        self.assertEqual(str(基准2), self.错根)
