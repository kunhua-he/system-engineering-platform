def 值(结果) -> dict:
    """取统一结果的值（成功结果才有值）；失败即抛出断言信息。"""
    if not 结果.成功:
        raise AssertionError(f"预期成功，实为失败: {结果.错误码} {结果.错误说明}")
    return 结果.值


