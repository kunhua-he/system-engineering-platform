        self.assertEqual(错["未核验数"], 1)
        self.assertEqual(错["记录表"][0]["指纹核验"], "未核验")
        self.assertEqual(错["记录表"][0]["现场指纹"], "不存在")
        self.assertEqual(错["记录表"][0]["内容是否变更"], 假, "未核验一律不得冒充「已变更」")


