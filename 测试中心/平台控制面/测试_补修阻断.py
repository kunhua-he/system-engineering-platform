class Test授权自举阻断(unittest.TestCase):
    """任意身份升权失败 / 撤销角色后旧令牌失败 / 伪造所有者。"""

    def setUp(self):
        self.服务, self.目录 = 建服务()

    def test_任意身份自行升权失败(self):
        令牌 = self.服务.授权.注册身份(身份id="访客")
        for 角色 in ("发布者", "平台维护者", "组件开发Agent", "调用Agent"):
            成功, 消息 = self.服务.授权.切换角色(令牌, 角色)
            self.assertFalse(成功, f"访客不得自选 {角色}")
            self.assertIn("角色未授予", 消息)
        # 操作级也拒绝
        结果 = self.服务.执行操作(令牌=令牌, 操作="签名与发布", 参数={})
        self.assertEqual(结果["错误码"], "PERMISSION_DENIED")

    def test_注册身份默认最低角色(self):
        令牌 = self.服务.授权.注册身份(身份id="新用户")
        会话 = self.服务.授权._会话表[令牌]
        self.assertEqual(会话["角色"], "普通用户")

    def test_撤销角色后旧令牌失败(self):
        令牌 = 提权(self.服务, "被撤者", "发布者")
        结果 = self.服务.执行操作(令牌=令牌, 操作="签名与发布", 参数={})
        self.assertNotEqual(结果["错误码"], "PERMISSION_DENIED", "授予后权限已生效")
        # 维护者撤销
        维护令牌 = 提权(self.服务, "维护者", "平台维护者")
        成功, _ = self.服务.授权.撤销角色(授予者令牌=维护令牌, 身份id="被撤者", 角色="发布者")
        self.assertTrue(成功)
        # 旧令牌立即失效（角色被降为普通用户）
        结果 = self.服务.执行操作(令牌=令牌, 操作="签名与发布", 参数={})
        self.assertEqual(结果["错误码"], "PERMISSION_DENIED")

    def test_伪造所有者被拒(self):
        令牌 = self.服务.授权.注册身份(身份id="真身")
        # 用他人身份伪造注册记录的所有者 → 切换/操作被拒（角色未授予）
        成功, _ = self.服务.授权.切换角色(令牌, "发布者")
        self.assertFalse(成功)


