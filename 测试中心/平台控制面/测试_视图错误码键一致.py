class 基类(unittest.TestCase):
    """共用断言：三张表的键集判据。"""

    def 断言无未登记缺键(self, 视图名: str, 表名: str, 表: dict) -> None:
        缺 = (视图声明码集(视图名) - set(不可达登记)) - set(表)
        登记 = set(已登记缺口.get((视图名, 表名), {}))
        self.assertEqual(
            缺, 登记,
            f"{视图名}.{表名} 的可达对外码覆盖与登记不符：\n"
            f"  未登记缺键（须补键或登记理由）= {sorted(缺 - 登记)}\n"
            f"  已登记但已修好的项（须删除登记项）= {sorted(登记 - 缺)}")


class Test视图错误码键一致(基类):
    """三张「错误码 → 建议」表与生产对外错误码的口径一致性。"""

    def test_中文码键集必须是生产对外错误码子集(self):
        for (视图名, 表名), 表 in 表清单.items():
            声明 = 视图声明码集(视图名)
            中文键 = {码 for 码 in 表 if 是中文码(码)}
            多余 = 中文键 - 声明
            self.assertEqual(
                多余, set(),
                f"{视图名}.{表名} 出现生产不会返回的中文码键：{sorted(多余)}；"
                f"该视图声明码集 = {sorted(声明)}")

    def test_视图可达对外码必须在表中有键(self):
        for (视图名, 表名), 表 in 表清单.items():
            self.断言无未登记缺键(视图名, 表名, 表)

    def test_不可达登记项本身必须仍在声明集内(self):
        全部声明 = set()
        for 视图名 in 视图操作:
            全部声明 |= 视图声明码集(视图名)
        腐烂 = set(不可达登记) - 全部声明
        self.assertEqual(
            腐烂, set(),
            f"不可达登记里的码已不在对外错误码声明集中（登记项腐烂，须清理）："
            f"{sorted(腐烂)}")

    def test_每个中文码必须命中专属文案且不落兜底(self):
        # ① 普通用户视图：真实建议入口 + 不得等于兜底句
        普通表 = 表清单[("普通用户视图", "错误码建议表")]
        for 码 in sorted(k for k in 普通表 if 是中文码(k)):
            文 = _普通用户文案(码)
            self.assertEqual(文, 普通表[码], f"普通用户视图.{码} 建议与表不一致")
            self.assertNotEqual(
                文, 兜底文案["普通用户视图"],
                f"普通用户视图 中文码「{码}」落到兜底句，等于文案降级")
        # ② 调用Agent视图：真实调用点都不得落兜底
        for 码 in sorted(中文码集(错误说明表) | 中文码集(建议操作表)):
            文案 = _调用点文案(码)
            for 点, 文 in 文案.items():
                该点表 = 点对应表[点]
                if 码 not in 该点表:
                    continue
                self.assertEqual(
                    文, 该点表[码],
                    f"调用Agent视图{点} 对码「{码}」未取到本表文案")
                self.assertNotEqual(
                    文, 兜底文案[f"调用Agent视图.{点}"],
                    f"调用Agent视图{点} 对中文码「{码}」落到兜底句")

    def test_已登记缺口必须仍是真缺口且真落兜底(self):
        for (视图名, 表名), 缺口 in 已登记缺口.items():
            表 = 表清单[(视图名, 表名)]
            for 码 in 缺口:
                self.assertNotIn(
                    码, 表,
                    f"{视图名}.{表名} 已补上「{码}」键 → 请删除 已登记缺口 里的对应登记项")
                文案 = _调用点文案(码) if 视图名 == "调用Agent视图" else {}
                for 点, 文 in 文案.items():
                    self.assertEqual(
                        文, 兜底文案[f"调用Agent视图.{点}"],
                        f"调用Agent视图{点} 对「{码}」已不再落兜底，登记项须清理")

    def test_英文历史键仍在且与中文键同义(self):
        """向后兼容层（历史英文键）不得被误删，且不得与中文键语义分裂。"""
        for (视图名, 表名), 表 in 表清单.items():
            实际英文 = {码 for 码 in 表 if not 是中文码(码)}
            期望 = 期望英文键[(视图名, 表名)]
            丢的 = sorted(期望 - 实际英文)
            self.assertEqual(
                丢的, [],
                f"{视图名}.{表名} 丢了历史英文键：{丢的}"
                f"（历史夹具/外部调用方传英文码会落兜底句）")
            多的 = sorted(实际英文 - 期望)
            self.assertEqual(
                多的, [],
                f"{视图名}.{表名} 出现未登记的英文键：{多的}；"
                f"对外错误码只走中文，新增英文键必须同时登记中文对应键并更新 期望英文键")
            for 英, 中 in 英文中文对应.items():
                if 英 not in 实际英文:
                    continue
                self.assertIn(
                    中, 表,
                    f"{视图名}.{表名} 保留了英文键 {英} 但缺中文键「{中}」，向后兼容层与中文口径分裂")
                self.assertEqual(
                    表[英], 表[中],
                    f"{视图名}.{表名} 的 {英} 与「{中}」映射文案不同，语义分裂")
        for 表名, 表 in (("错误说明表", 错误说明表), ("建议操作表", 建议操作表)):
            for 英 in 无中文对应的英文键:
                self.assertIn(
                    英, 表,
                    f"调用Agent视图.{表名} 丢了历史英文键 {英}，向后兼容层被削")

    def test_调用Agent视图两表键集一致(self):
        self.assertEqual(
            set(错误说明表), set(建议操作表),
            f"两表键集不一致 → 会出现「有说明无建议」："
            f"仅说明表有={sorted(set(错误说明表) - set(建议操作表))}，"
            f"仅建议表有={sorted(set(建议操作表) - set(错误说明表))}")

    def test_视图源码直接索引的键必须存在(self):
        """视图里 `表名["键"]` 是硬索引（缺键即 KeyError），逐处核对。"""
        视图目录 = 系统根 / "开发工具" / "统一能力入口" / "视图"
        命名表 = {"错误码建议表": 错误码建议表, "错误说明表": 错误说明表,
                  "建议操作表": 建议操作表}
        缺 = []
        for 文件名 in ("普通用户视图.py", "调用Agent视图.py"):
            源码 = (视图目录 / 文件名).read_text(encoding="utf-8")
            for 表名, 键 in re.findall(
                    r"(错误码建议表|错误说明表|建议操作表)\[\"([^\"]+)\"\]", 源码):
                if 键 not in 命名表[表名]:
                    缺.append(f"{文件名}: {表名}[\"{键}\"]")
                if 是中文码(键) and 键 not in 视图声明码集(
                        "普通用户视图" if 文件名.startswith("普通") else "调用Agent视图"):
                    缺.append(f"{文件名}: {表名}[\"{键}\"] 不在对外错误码声明集内")
        self.assertEqual(缺, [], "视图源码直接索引的键缺失/口径不符：" + str(缺))


class Test真实调用码命中专属建议(基类):
    """以生产侧真实返回为准：真跑 统一能力服务 + 视图失败路径，收集真实码再核表。"""

    @classmethod
    def setUpClass(cls):
        cls.目录 = Path(tempfile.mkdtemp(prefix="视图错误码键一致_"))
        cls.服务 = 统一能力服务(cls.目录)
        cls.预算 = 完整预算()
        for 能力id in ("计算.求值", "无提供者.能力", "炸.能力", "超时.能力"):
            cls.服务.目录.登记能力(
                能力id=能力id, 组件="示例组件", 领域="计算", 成熟度="实验",
                契约={"能力id": 能力id, "名称": "x", "参数": [], "返回": {},
                      "错误码": [], "副作用": "无", "宿主": "后端", "权限": ""},
                资源={"参数说明": []})
        cls.服务.注册提供者(能力id="计算.求值", 函数=lambda **_: 42, 预算=cls.预算)
        cls.服务.注册提供者(
            能力id="炸.能力",
            函数=lambda **_: (_ for _ in ()).throw(RuntimeError("提供者内部错误")),
            预算=cls.预算)
        cls.服务.注册提供者(
            能力id="超时.能力",
            函数=lambda **_: (_ for _ in ()).throw(RuntimeError("执行超时")),
            预算=cls.预算)
        cls.普通用户视图 = 普通用户视图(cls.服务)
        cls.Agent视图 = 调用Agent视图(cls.服务)
        cls.普通令牌 = cls.服务.授权.注册身份(身份id="真实普通用户")
        cls.agent令牌 = cls.提权(cls, "真实调用Agent", "调用Agent")

    @staticmethod
    def 提权(实例, 身份id, 角色):
        令牌 = 实例.服务.授权.注册身份(身份id=身份id)
        成功, 消息 = 实例.服务.授权.引导授予(
            身份id=身份id, 角色=角色, 授予者="系统引导")
        assert 成功, 消息
        成功, 消息 = 实例.服务.授权.切换角色(令牌, 角色)
        assert 成功, 消息
        return 令牌

    def 收集真实错误码(self) -> dict[str, str]:
        """真跑失败路径 → 真实错误码（生产侧真实返回为准，不写死）。"""
