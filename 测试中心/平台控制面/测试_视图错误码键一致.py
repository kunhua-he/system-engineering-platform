    def test_真实调用返回的错误码都能命中专属建议(self):
        真实码 = set(self.收集真实错误码().values())
        self.assertTrue(真实码, "真实失败路径一个错误码都没收到，夹具失效")
        for 码 in sorted(真实码):
            self.assertIn(
                码, 错误码建议表,
                f"生产真实返回「{码}」，普通用户视图.错误码建议表 无该键 → 建议降级为兜底")
            文 = _普通用户文案(码)
            self.assertNotEqual(
                文, 兜底文案["普通用户视图"],
                f"生产真实返回「{码}」，普通用户视图 仍落兜底句")
            缺口 = set(已登记缺口.get(("调用Agent视图", "错误说明表"), {}))
            if 码 in 缺口:
                continue
            for 表名, 表 in (("错误说明表", 错误说明表), ("建议操作表", 建议操作表)):
                self.assertIn(
                    码, 表, f"生产真实返回「{码}」，调用Agent视图.{表名} 无该键 → 落兜底")
                文案 = _调用点文案(码)
                for 点, 文 in 文案.items():
                    该点表 = 错误说明表 if 点.endswith("错误说明") else 建议操作表
                    self.assertEqual(文, 该点表[码],
                                     f"调用Agent视图{点} 对真实码「{码}」未取到本表文案")

