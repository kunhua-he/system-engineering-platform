#: 模块级临时夹具登记：本模块的夹具**在模块级 helper 里**造（helper 拿不到 TestCase 实例，
#: 用不了 `self.addCleanup`）⇒ 走 unittest 的**模块级收尾钩子** `tearDownModule` 登记清理
#: （同样「用例失败也跑」）。拿得到用例实例的站点一律用 `self.addCleanup`。
_临时夹具登记: list[Path] = []


def tearDownModule() -> None:
    """模块收尾：清理本模块造在 `受管临时根` 下的全部夹具（**用例失败也跑**）。"""
    for 夹具 in _临时夹具登记:
        清只读后删除树(夹具, 忽略失败=真)
    _临时夹具登记.clear()



def 建服务() -> tuple[统一能力服务, Path]:
    目录 = Path(tempfile.mkdtemp(prefix="制品测试_", dir=受管临时根))
    _临时夹具登记.append(目录)
    return 统一能力服务(目录), 目录


class Test内容寻址制品(unittest.TestCase):
    """同摘要不可覆盖 / 同输入摘要一致 / 输入变化摘要变化。"""

    def setUp(self):
        self.服务, self.目录 = 建服务()

    def test_包仓库拒绝覆盖不可变版本(self):
        成功, _, 摘要 = self.服务.仓库.构建制品(
            包id="测试包", 版本="1", 文件表={"主.py": "print(1)"}, 构建输入={"源": "s1"})
        self.assertTrue(成功)
        # 同包同版本同内容 → 幂等复用（同摘要，不产生新制品）
        成功2, 消息2, 摘要2 = self.服务.仓库.构建制品(
            包id="测试包", 版本="1", 文件表={"主.py": "print(1)"}, 构建输入={"源": "s1"})
        self.assertTrue(成功2, "同版同摘要幂等复用")
        self.assertEqual(摘要, 摘要2, "同内容必须同摘要")
        # 同包同版本不同内容 → 明确拒绝（同版双摘要）
        成功3, 消息3, _ = self.服务.仓库.构建制品(
            包id="测试包", 版本="1", 文件表={"主.py": "print(2)"}, 构建输入={"源": "s1"})
        self.assertFalse(成功3, "同一包同一版本禁止双摘要")
        self.assertIn("双摘要", 消息3)

    def test_可复现构建摘要一致且输入变化摘要变化(self):
        成功, 消息 = self.服务.仓库.可复现校验(
            包id="测试包", 版本="1", 文件表={"主.py": "print(1)"}, 构建输入={"源": "s1"})
        self.assertTrue(成功, 消息)

    def test_摘要篡改后签名校验失败且安装被拒(self):
        私钥, 公钥 = 生成密钥对()
        成功, _, 摘要 = self.服务.仓库.构建制品(
            包id="篡改包", 版本="1", 文件表={"主.py": "print(1)"}, 构建输入={"源": "s1"})
        self.assertTrue(成功)
        self.服务.仓库.登记发布者(发布者="发布者1", 公钥PEM=公钥)
        成功签名, _ = self.服务.仓库.签名制品(制品摘要=摘要, 私钥PEM=私钥, 发布者="发布者1")
        self.assertTrue(成功签名)
        # 篡改前签名有效
        有效, _ = self.服务.仓库.校验签名(制品摘要=摘要)
        self.assertTrue(有效)
        # 摘要篡改：修改制品记录的文件清单（内容变化使签名失效）
        self.服务.状态.条件更新(
            "制品", {"文件清单": '{"主.py": {"sha256": "deadbeef", "大小": 1}}'},
            "制品摘要=?", (摘要,))
        有效2, 消息2 = self.服务.仓库.校验签名(制品摘要=摘要)
        self.assertFalse(有效2, f"篡改后签名校验必须失败: {消息2}")
        # 策略层：签名失效 → 发布/安装被拒
        决定 = self.服务.策略.判定(类型="签名", 主题="篡改包",
                                请求={"已签名": 真, "签名失效": not 有效2,
                                       "签名者": "发布者1"})
        self.assertFalse(决定["允许"], "签名失效后安装/发布必须被拒")
        # 安装被拒
        安装成功, 安装消息 = self.服务.仓库.安装制品(制品摘要=摘要, 目标目录=self.目录 / "安装")
        self.assertFalse(安装成功)
        self.assertTrue(("签名" in 安装消息) or ("篡改" in 安装消息) or ("不符" in 安装消息),
                        f"安装拒绝原因必须指向签名/篡改: {安装消息}")


class Test签名与信任(unittest.TestCase):
    """未签名/撤销发布者拒绝安装；签名后发布者撤销失效。"""

    def setUp(self):
        self.服务, self.目录 = 建服务()

    def test_未签名包拒绝安装(self):
        成功, _, 摘要 = self.服务.仓库.构建制品(
            包id="未签名包", 版本="1", 文件表={"主.py": "x"}, 构建输入={"源": "s"})
        self.assertTrue(成功)
        安装成功, 消息 = self.服务.仓库.安装制品(制品摘要=摘要, 目标目录=self.目录 / "安装")
        self.assertFalse(安装成功)
        self.assertIn("未签名", 消息)

    def test_撤销发布者后新签名失效(self):
        私钥, 公钥 = 生成密钥对()
        self.服务.仓库.登记发布者(发布者="发布者2", 公钥PEM=公钥)
        成功, _, 摘要 = self.服务.仓库.构建制品(
            包id="撤销包", 版本="1", 文件表={"主.py": "x"}, 构建输入={"源": "s"})
        self.服务.仓库.签名制品(制品摘要=摘要, 私钥PEM=私钥, 发布者="发布者2")
        有效, _ = self.服务.仓库.校验签名(制品摘要=摘要)
        self.assertTrue(有效)
        # 撤销发布者 → 校验签名必须失败
        self.服务.仓库.撤销发布者(发布者="发布者2")
        有效2, 消息2 = self.服务.仓库.校验签名(制品摘要=摘要)
        self.assertFalse(有效2)
        self.assertIn("撤销", 消息2)


class Test资源监督(unittest.TestCase):
    """预算声明 / 超限明确失败且资源释放 / 提供者崩溃不影响其他能力。"""

    def setUp(self):
        self.服务, self.目录 = 建服务()
        self.监督 = 资源监督器(self.服务.状态)

    def test_缺少必需预算项被拒绝(self):
        有效, 消息 = self.监督.校验预算声明({"内存上限": 1})
        self.assertFalse(有效)
        self.assertIn("缺少必需项", 消息)

    def test_队列超限明确失败(self):
        预算 = {"内存上限": 100, "线程上限": 1, "子进程上限": 1, "并发调用上限": 1,
                "队列长度": 1, "文件句柄上限": 50, "临时空间上限": 100,
                "单次调用超时": 5, "每分钟重启次数": 2, "空闲回收时间": 60}
        成功, _ = self.监督.注册执行单元(单元id="受限单元", 预算=预算)
        self.assertTrue(成功)
        import threading as _线程
        阻塞 = _线程.Event()
        任务 = lambda: 阻塞.wait(2)
        # 提交第一个任务占住并发位
        self.assertTrue(self.监督.提交任务("受限单元", 任务)[0])
        结果 = self.监督.提交任务("受限单元", 任务)
        self.assertFalse(结果[0], "并发超限必须明确失败")
        self.监督.优雅停止("受限单元")
        报告 = self.监督.状态报告()
        self.assertGreaterEqual(报告["受限单元"]["超限次数"], 1, "超限必须记录")
        self.assertNotIn("受限单元", self.监督._池表, "停止后资源释放")

    def test_单元崩溃不影响其他能力(self):
        预算 = {"内存上限": 100, "线程上限": 2, "子进程上限": 1, "并发调用上限": 2,
                "队列长度": 10, "文件句柄上限": 50, "临时空间上限": 100,
                "单次调用超时": 5, "每分钟重启次数": 2, "空闲回收时间": 60}
        # 单元1超限：注册并发=2 线程=2，闸门阻塞保持 2 个活跃，第 3 个被拒
        预算1 = {**预算, "并发调用上限": 2, "线程上限": 2}
        self.监督.注册执行单元(单元id="单元1", 预算=预算1)
        self.监督.注册执行单元(单元id="单元2", 预算=预算)
        import threading as _线程
        闸门 = _线程.Event()
        阻塞任务 = lambda: 闸门.wait(2)
        for _ in range(3):
            self.监督.提交任务("单元1", 阻塞任务)
        超限, 消息 = self.监督.检查超限("单元1", {**预算1, "并发调用上限": 1})
        self.assertFalse(超限, "单元1并发超限（峰值2>预算1）")
        闸门.set()  # 放行阻塞任务
        # 单元2仍可用
        正常, _ = self.监督.检查超限("单元2", 预算)
        self.assertTrue(正常, "一个提供者超限不能拖垮其他提供者")
        self.监督.优雅停止("单元1")
        self.监督.优雅停止("单元2")
        self.assertEqual(self.监督.状态报告(), {"单元1": self.监督.状态报告().get("单元1"),
                                                "单元2": self.监督.状态报告().get("单元2")},
                         "停止后池释放")


class Test核心快照与发布(unittest.TestCase):
    """激活指针 CAS / 陈旧监督器被拒 / 健康失败保留旧核心 / 回滚。"""

    def setUp(self):
        self.服务, self.目录 = 建服务()

    def test_陈旧监督器旧令牌切换被拒(self):
        发布 = 发布管理(self.服务.状态)
        # 第一次激活：指针 版本1 令牌1
        成功, _ = 发布.激活(发布id=发布.登记期望版本(包id="核心包1", 期望版本="1"), 目标="v1")
        self.assertTrue(成功)
        指针 = 发布.当前激活("核心包1")
        self.assertEqual(指针["版本"], 1)
        # 新监督器正常切换：期望 版本1令牌1 → 版本2令牌2
        成功新, _ = 发布.切换激活指针(指针id="核心包1", 目标="v2", 期望版本=1, 期望令牌=1)
        self.assertTrue(成功新)
        # 陈旧监督器仍带 版本1令牌1（旧值）切换 → CAS 拒绝
        成功2, 消息2 = 发布.切换激活指针(指针id="核心包1", 目标="v3", 期望版本=1, 期望令牌=1)
        self.assertFalse(成功2, "陈旧监督器旧令牌切换必须被拒")
        self.assertIn("陈旧", 消息2)
        # 当前指针仍是 v2（未被陈旧监督器覆盖）
        指针 = 发布.当前激活("核心包1")
        self.assertEqual(指针["目标"], "v2")

    def test_健康失败时旧核心继续服务(self):
        快照 = 核心快照管理(self.服务.状态)
        # 两个快照：候选健康失败 → 激活指针保持旧快照
        发布 = 发布管理(self.服务.状态)
        成功, _ = 发布.激活(发布id=发布.登记期望版本(包id="服务", 期望版本="1"), 目标="旧快照")
        self.assertTrue(成功)
        健康 = 快照.健康检查(快照id="不存在", 调用=lambda: 真)
        self.assertFalse(健康[0], "候选快照不存在/未签名 → 健康失败")
        指针 = 发布.当前激活("服务")
        self.assertEqual(指针["目标"], "旧快照", "健康失败后旧核心继续服务")

    def test_回滚保留历史证据(self):
        发布 = 发布管理(self.服务.状态)
        发布id = 发布.登记期望版本(包id="组件2", 期望版本="2")
        发布.激活(发布id=发布id, 目标="v2")
        成功, 消息 = 发布.回滚(发布id=发布id, 回滚目标="v1")
        self.assertTrue(成功, 消息)
        指针 = 发布.当前激活("组件2")
        self.assertEqual(指针["目标"], "v1", "回滚后指针指向旧版")
        记录 = self.服务.状态.读取记录("发布", "发布id", 发布id)
        self.assertEqual(记录["状态"], "已回滚", "发布历史保留")


