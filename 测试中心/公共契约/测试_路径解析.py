"""路径解析唯一口径：相对路径按生效根解析成绝对路径（正反双向判据）。

## 为什么单独写

华哥 2026-09-22 原话实测缺陷：「mcp 应该有一个默认配置项，是锁定根目录的，然后用户
无论输入绝对路径，还是相对路径（复用根目录配置），只要文件存在，就可以使用的兼容性
才对，这纯粹是 bug 了」。现场代价：给 MCP 传相对路径时，网关跑的是**制品**（不是源码树），
相对路径落到制品根，回「文件不存在」；调用方只能靠猜该给绝对路径。
根因是「相对路径按根解析」被多处各自实现、根由本地 ``parents[N]`` 推出
（样本：`平台控制面/提供者/实现/能力入口.py` 自己写 ``路径 if 路径.is_absolute()
else (系统根目录 / 路径)``，根在制品态就是制品根）。

本件锁 `公共契约.运行时.平台适配.解析路径` 这**一份唯一实现**：

- 正：绝对原样 / 相对按根拼成**存在**的绝对路径 / 空值非文本不炸 / 环境变量兜底 / 显式根优先；
- 正：`公共契约.基础类型.字段名册.是路径族字段` 认全路径族名单（初版 8 名 + 2026-09-23
  补全的 67 名 = 75 名），且**不认**列表型与「基准是同调用另一个入参 / 登记档案」的名字；
- 反：把「相对路径按根拼接」这一段去掉 ⇒ 相对路径退化成裸相对名，喂给真实的
  `文件系统支持库.文件操作.读取文件` 必须回**真实错误文本「文件不存在」**。
  手法照 `测试中心/开发工具/测试_薄壳返回可控.py` 的 `换壳后不握手反向验证`
  （缺陷态源码副本 + 反向样本 + 断言真实错误文本）。
"""

