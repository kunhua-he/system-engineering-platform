def _缺陷态解析路径(旧: str, 新: str):
    """把平台适配源码故意改坏一次，返回缺陷态的 `解析路径`（**不落盘**，工作区不受污染）。"""
    源 = 平台适配源.read_text(encoding="utf-8")
    if 旧 not in 源:
        raise AssertionError(f"反向样本片段未命中：{旧!r}（判据需更新）")
    命名空间: dict = {"__name__": "反向样本_平台适配", "__file__": str(平台适配源)}
    exec(compile(源.replace(旧, 新, 1), str(平台适配源), "exec"), 命名空间)  # noqa: S102
    return 命名空间["解析路径"]


class 绝对与相对解析(unittest.TestCase):
    """解析路径 的正向语义：绝对原样、相对按根、空值非文本不炸。"""

    def test_绝对路径原样返回且不查存在性(self):
        不存在 = "/tmp/这个路径故意不存在_路径解析判据"
        self.assertEqual(解析路径(不存在), Path(不存在),
                         "绝对路径必须原样返回 —— 存在性是调用方的判据，不是解析函数的")
        self.assertFalse(Path(不存在).exists(), "样本本身不该真的存在（否则证明不了「不查存在性」）")

    def test_相对路径按本仓根解析为存在的绝对路径(self):
        解析后 = 解析路径(相对锚, 根=系统根)
        self.assertTrue(解析后.is_absolute(), f"必须解析成绝对路径：{解析后}")
        self.assertEqual(解析后, 系统根 / 相对锚)
        self.assertTrue(解析后.is_file(), f"按本仓根解析后必须真实存在：{解析后}")

    def test_空值与非文本原样返回不抛(self):
        for 值 in (None, "", "   ", 7, 3.5, ["a", "b"], {"a": 1}, b"x"):
            with self.subTest(值=值):
                self.assertEqual(解析路径(值), 值,
                                 f"非文本/空值必须原样返回、不许抛：{值!r}")

    def test_环境变量作为默认根(self):
        原 = os.environ.get(项目根环境变量名)
        os.environ[项目根环境变量名] = str(系统根)
        try:
            解析后 = 解析路径(相对锚)  # 不给显式根 → 走环境变量
        finally:
            if 原 is None:
                os.environ.pop(项目根环境变量名, None)
            else:
                os.environ[项目根环境变量名] = 原
        self.assertEqual(解析后, 系统根 / 相对锚, "无显式根时必须按 系统平台_项目根 解析")
        self.assertTrue(解析后.is_file())

    def test_显式根优先于环境变量(self):
        with tempfile.TemporaryDirectory() as 临时:
            原 = os.environ.get(项目根环境变量名)
            os.environ[项目根环境变量名] = 临时
            try:
                解析后 = 解析路径(相对锚, 根=系统根)
            finally:
                if 原 is None:
                    os.environ.pop(项目根环境变量名, None)
                else:
                    os.environ[项目根环境变量名] = 原
        self.assertEqual(解析后, 系统根 / 相对锚,
                         "显式根必须压过环境变量（否则「调用方现场已知的基准」被默认项覆盖）")


class 路径族字段判定(unittest.TestCase):
    """`是路径族字段` 是「哪些入参要做绝对化改写」的唯一名单。"""

    def test_认全F3的八个名字(self):
        for 名 in F3路径族名:
            with self.subTest(名=名):
                self.assertIn(名, 路径族字段名)
                self.assertTrue(是路径族字段(名), f"{名} 必须被认成路径族字段")

    def test_补全后共七十五名且补全名单逐条在册(self):
        """2026-09-23 补全：初版 8 名 + 补全 67 名 = 75 名（冻结集合，多一个少一个都是口径漂移）。"""
        self.assertEqual(len(F3路径族名) + len(补全路径族名), len(路径族字段名),
                         f"补全后应共 {len(F3路径族名) + len(补全路径族名)} 名，"
                         f"实际 {len(路径族字段名)} 名")
        for 名 in 补全路径族名:
            with self.subTest(名=名):
                self.assertIn(名, 路径族字段名, f"{名} 必须入册（否则不参与归一化）")
                self.assertTrue(是路径族字段(名), f"{名} 必须被认成路径族字段")

    def test_任务点名的四个缺口逐个有定性(self):
        """任务点名的 4 个「疑似缺口」：`目录`/`输出目录` 入册，`修改路径`/`文档相对路径` 不入册。

        这是本件最容易「凭名字像就加」的地方 —— 故把结论钉死在判据上：
        `修改路径` 是列表型且其契约显式拒绝绝对路径；`文档相对路径` 的解析基准是
        登记档案的 文档根（说明原文「不是项目根」）。
        """
        self.assertTrue(是路径族字段("目录"), "`目录` 是单个目录路径 → 必须入册")
        self.assertTrue(是路径族字段("输出目录"), "`输出目录` 是单个目录路径 → 必须入册")
        self.assertFalse(是路径族字段("修改路径"), "`修改路径` 是列表型 → 不许入册")
        self.assertFalse(是路径族字段("文档相对路径"),
                         "`文档相对路径` 基准是文档根而非项目根 → 不许入册")

    def test_不认故意不入册的名字(self):
        for 名 in 故意不入册名:
            with self.subTest(名=名):
                self.assertFalse(是路径族字段(名),
                                 f"{名!r} 故意不入册（依据见 字段名册.路径族字段名 注释），判定不许放宽")

    def test_不认非路径族名(self):
        for 名 in ("模式", "关键词", "输入文本", "成功", "超时秒",
                   "", "   ", None, 7):
            with self.subTest(名=名):
                self.assertFalse(是路径族字段(名),
                                 f"{名!r} 不是路径族字段，判定不许放宽")


class 反向验证_去掉按根拼接(unittest.TestCase):
    """反向验证：去掉「相对路径按根拼接」那一段，判据必须变红。

    判据不靠「解析后字符串长得对不对」自证 —— 而是把缺陷态的产物真的喂给
    `文件系统支持库.文件操作.读取文件`，断言它回**真实错误文本「文件不存在」**：
    与 `测试_薄壳返回可控.py` 的 `换壳后不握手反向验证` 同一手法（真反向样本 +
    断言真实错误文本）。为让相对路径确实落空，本用例把进程 cwd 切到临时目录 ——
    这正是**制品态**的情形（cwd 是制品根、调用方想的是源码树）。
    """

    _现行片段 = "    return Path(生效根).expanduser() / 目标"
    _缺陷片段 = "    return 目标"

    def test_现行态读得到_缺陷态回文件不存在(self):
        from 支持库.后端.文件系统支持库.文件操作.实现.文件系统 import 读取文件

        现行 = 解析路径(相对锚, 根=系统根)
        缺陷解析 = _缺陷态解析路径(self._现行片段, self._缺陷片段)
        缺陷 = 缺陷解析(相对锚, 根=系统根)

        self.assertTrue(现行.is_file(), "现行态必须解析到真实存在的绝对路径")
        self.assertEqual(缺陷, Path(相对锚),
                         "缺陷态必须真的退化成裸相对路径（样本失效则判据无意义）")
        self.assertNotEqual(现行, 缺陷, "两态结论必须不同，否则反向样本无效")

        原cwd = os.getcwd()
        with tempfile.TemporaryDirectory() as 临时:
            os.chdir(临时)
            try:
                现行读 = 读取文件(str(现行), 起始行=1, 结束行=1)
                缺陷读 = 读取文件(str(缺陷), 起始行=1, 结束行=1)
            finally:
                os.chdir(原cwd)

        self.assertTrue(现行读.成功, f"现行态必须读得到：{现行读.错误说明}")
        self.assertFalse(缺陷读.成功,
                         "缺陷态必须失败（否则这道闸门等于没接线，任何实现下都绿）")
        self.assertEqual(缺陷读.错误码, "文件不存在")
        self.assertIn("文件不存在", 缺陷读.错误说明,
                      f"必须复现那条真实错误文本：{缺陷读.错误说明}")

    def test_生效根指向不存在的目录时相对路径同样落空(self):
        """第二种反向口径（判据允许的「或」分支）：生效根指到不存在的目录 ⇒ 同样红。

        证明「解析成功」确实取决于**根是否有效**，而不是恒真。
        """
        from 支持库.后端.文件系统支持库.文件操作.实现.文件系统 import 读取文件

        假根 = 系统根 / "这个根故意不存在_路径解析判据"
        self.assertFalse(假根.exists())
        解析后 = 解析路径(相对锚, 根=假根)
        self.assertTrue(解析后.is_absolute(), "仍必须是绝对路径（只拼根，不查存在性）")
        读取 = 读取文件(str(解析后), 起始行=1, 结束行=1)
        self.assertFalse(读取.成功)
        self.assertEqual(读取.错误码, "文件不存在")
        self.assertIn("文件不存在", 读取.错误说明)


