"""编译口「防回潮六项未纳入」的登记复核（④，2026-09-23）。

## 为什么要这个测试

编译口结论里有一句对外**覆盖声明**：「防回潮六项判据本轮未纳入（原因与落点见
`_防回潮独立入口勘定`）」。修前它的登记理由有两条**与现场不符**：

1. 「其判据在发布门禁内是**就地定义**（非独立入口）」—— **不成立**：`_防回潮独立入口勘定`
   自己就证明了八项都能独立 `import` + 直调（六项判据定义在
   `开发工具/发布门禁/运行发布门禁_防回潮判据.py`，主文件只 re-export）。
2. 「三项在本轮现场是红的（文档生命周期／说明书白名单联动／裸布尔）」—— **已过期**：
   2026-09-23 复跑六项 + 能力调用图，前两项已转绿，当前红的是 裸布尔 / 占位代称。

两条理由此前**没有任何机器判据**，故一直以错的方式被引用。本测试把复核结论
（`编译口.防回潮未纳入登记`）与三条可验证事实钉住：

- 六项判据**确实可独立跑**（可调用对象取得到）⇒ 原「非独立入口」理由不成立；
- 它们**不在**编译口 `门禁清单` 里 ⇒ 「不纳入」是**有意的边界**（非漏接线）：
  若将来有人接线，本测试当场报错，逼一个显式决定（同时更新登记与本测试）；
- 接线的那一项（`防回潮·反向破坏`）**确实在**清单里 ⇒ 边界不得宽到把已接线项一起排除。

跑法：python3.14 -m unittest 测试中心.开发工具.测试_编译口防回潮未纳入登记
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

仓库根 = Path(__file__).resolve().parents[2]
if str(仓库根) not in sys.path:
    sys.path.insert(0, str(仓库根))

from 开发工具.开发编译口 import 编译口


class 登记存在且理由可验证(unittest.TestCase):
    """`防回潮未纳入登记` 是对外覆盖声明的**唯一事实源**，字段必须齐、理由必须落点明确。"""

    def test_登记字段齐全(self) -> None:
        登记 = 编译口.防回潮未纳入登记
        for 键 in ("名字", "结论", "未纳入理由", "复核日期", "复核命令", "可选替代"):
            self.assertTrue(登记.get(键), f"登记缺字段 {键}：{登记}")
        self.assertIn("合理边界", 登记["结论"])
        self.assertIn("必经路径", 登记["未纳入理由"])

    def test_复核日期是当日(self) -> None:
        self.assertEqual(编译口.防回潮未纳入登记["复核日期"], "2026-09-23")


class 六项可独立跑(unittest.TestCase):
    """原登记说「非独立入口」—— 事实相反：八项都能 import + 直调（勘定的原始结论）。"""

    def test_入口表里每个符号都可调用(self) -> None:
        from 开发工具.发布门禁 import 运行发布门禁, 运行发布门禁_防回潮判据
        模块表 = {
            "开发工具.发布门禁.运行发布门禁_防回潮判据": 运行发布门禁_防回潮判据,
            "开发工具.发布门禁.运行发布门禁": 运行发布门禁,
        }
        for 名字, 模块名, 符号名 in (*编译口.防回潮判据入口表, 编译口.反向破坏入口):
            with self.subTest(名字=名字):
                self.assertTrue(callable(getattr(模块表[模块名], 符号名, None)),
                                f"{名字} 取不到可调用对象 —— 与「可独立跑」结论不符")

    def test_勘定现场一致(self) -> None:
        self.assertTrue(编译口._防回潮独立入口勘定(),
                        "勘定结论与现场不符 —— 须更新 `_防回潮独立入口勘定` docstring")


class 不纳入是有意边界(unittest.TestCase):
    """边界判据：六项**不在** `门禁清单`（有意不接线），反向破坏**在**（已接线）。"""

    def test_六项不在门禁清单里(self) -> None:
        清单名字 = {项["名字"] for 项 in 编译口.门禁清单}
        六项 = {名字 for 名字, _模块, _符号 in 编译口.防回潮判据入口表}
        命中 = sorted(清单名字 & 六项)
        self.assertEqual(命中, [],
                         f"防回潮六项被判据清单纳入：{命中} —— 若是有意接线，"
                         f"请同时更新 `防回潮未纳入登记` 与本测试（那是显式决定，不是静默改）")

    def test_已接线项反向破坏仍在清单里(self) -> None:
        """★ 反向保护：边界不得宽到把**已接线**的 `防回潮·反向破坏` 一起排除。"""
        清单名字 = {项["名字"] for 项 in 编译口.门禁清单}
        self.assertIn(编译口.反向破坏入口[0], 清单名字,
                      "反向破坏是已接线项（阻断），必须仍在 门禁清单 里")

    def test_反向破坏是阻断角色(self) -> None:
        角色表 = {项["名字"]: 项["角色"] for 项 in 编译口.门禁清单}
        self.assertEqual(角色表.get(编译口.反向破坏入口[0]), "阻断")


if __name__ == "__main__":
    unittest.main()
