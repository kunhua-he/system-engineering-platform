"""同名参数 `类型` 口径收口测试（2026-09-24 裁决：**改名**，不硬统一）。

依据：`开发文档/项目说明.md` 哲学第 1 条「同一件事两套实现即缺陷」＋第 8 条③
「同名不同义应**改名**（让每个参数名自描述），不硬把类型统一」；裁决与理由的
**唯一来源**是 `开发工具/参数口径审计.py::同名不同义登记` 里 `类型` 那一条。

收口前的三个概念（审计面实测 `{'文本型': 4, '整数型': 2}`）：

    · ① 编译范围口径号（整数型：`0`=全仓 / `1`=指定库或模块）—— `自修复工具.静态编译`/`动态编译`
    · ② 模块类型（文本型）—— `组件生成.生成模块脚手架` / `组件规范支持库.生成模块模板`
    · ③ 证据类型（文本型）—— `平台控制面.平台状态.追加证据` / `查询证据`

②③ 改名收口为 `模块类型` / `证据类型`；① 保留 `类型`（编译是平台仅有的两条公开
能力，`类型=0/1` 已被 AGENTS.md 项目硬规则冻结，改名等于改对外契约面）。

覆盖四件事（全部真读仓内契约文件，禁止 mock）：
1. 正向：6 处真实契约事实喂进 `判分歧` 后，`类型` **不出现**在「未登记（待裁决）」清单；
2. 承重：登记表里 `类型` 那一条必须写明三个概念与两个新名（唯一来源，不许在别处另写）；
3. 反向：把任一处的 `模块类型`/`证据类型` **改回旧名 `类型`**，同一判据必须重新报它
   （判红确由本判据承担，不是靠删断言变绿）；
4. 面齐：4 处文本型新名与 2 处整数型口径号在真实 `能力定义.json` 与包内
   `说明/*.md` 里逐处可查，旧参数行一处不留。
"""
from __future__ import annotations

import json
import sys
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 开发工具.参数口径审计 import 判分歧, 同名不同义登记, 扫全仓

#: 6 处同名参数 `类型` 的**能力定义文件**（能力id → 文件；一处文件可装多个能力）。
定义文件 = {
    "自修复工具.静态编译": "模块库/自修复工具/能力定义.json",
    "自修复工具.动态编译": "模块库/自修复工具/能力定义.json",
    "组件生成.生成模块脚手架": "模块库/组件生成/能力定义.json",
    "组件规范支持库.生成模块模板": "支持库/后端/组件规范支持库/能力定义.json",
    "平台控制面.平台状态.追加证据": "平台控制面/平台状态/能力定义.json",
    "平台控制面.平台状态.查询证据": "平台控制面/平台状态/能力定义.json",
}

#: 4 处文本型改名后的目标名（概念 → 新参数名）。
改名后 = {
    "组件生成.生成模块脚手架": "模块类型",
    "组件规范支持库.生成模块模板": "模块类型",
    "平台控制面.平台状态.追加证据": "证据类型",
    "平台控制面.平台状态.查询证据": "证据类型",
}

#: 4 处改名所在的包目录（说明书面逐份核旧参数行是否清干净）。
包目录 = [
    "模块库/组件生成",
    "支持库/后端/组件规范支持库",
    "平台控制面/平台状态",
]


def _读真实契约(能力id: str) -> dict:
    """按能力id 从真实 `能力定义.json` 里取该能力条目（读不到即失败，不静默跳过）。"""
    路径 = 系统根 / 定义文件[能力id]
    if not 路径.is_file():
        raise AssertionError(f"能力定义文件不存在: {定义文件[能力id]}")
    数据 = json.loads(路径.read_text(encoding="utf-8"))
    for 条目 in 数据.get("能力列表") or []:
        if 条目.get("能力id") == 能力id:
            return 条目
    raise AssertionError(f"{定义文件[能力id]} 里没有能力 {能力id}")


def _真实契约源() -> list[dict]:
    """把 6 处真实契约事实组装成 `扫全仓` 的契约源（形状同 `能力目录.搜索能力` 记录）。"""
    记录表 = []
    for 能力id in 定义文件:
        条目 = _读真实契约(能力id)
        记录表.append({"能力id": 能力id, "参数": 条目.get("参数") or [], "返回": 条目.get("返回")})
    return 记录表


def _参数名表(契约源: list[dict], 能力id: str) -> list[str]:
    记录 = next(记 for 记 in 契约源 if 记["能力id"] == 能力id)
    return [p.get("名称") for p in 记录["参数"]]


class Test参数口径同名收口(unittest.TestCase):
    """`类型` 三个概念 → 改名收口的判据测试。"""

    def test_正向_类型不再出现在待裁决清单(self):
        事实 = 扫全仓(契约源=_真实契约源())
        分歧 = 判分歧(事实)
        待裁决 = [x["字段"] for x in 分歧["同名不同义"] if x["字段"] not in 同名不同义登记]
        self.assertNotIn("类型", 待裁决, f"类型 仍在待裁决清单: {待裁决}")
        已登记 = [x["字段"] for x in 分歧["同名不同义"] if x["字段"] in 同名不同义登记]
        self.assertNotIn("类型", 已登记,
                         "6 处收口后 `类型` 只剩整数型一种含义，不应再进同名不同义清单")

    def test_承重_登记表写明三个概念与两个新名(self):
        说明 = 同名不同义登记.get("类型")
        self.assertIsNotNone(说明, "同名不同义登记 缺 `类型` 条目（裁决的唯一来源）")
        for 必需 in ("整数型", "模块类型", "证据类型", "改名"):
            self.assertIn(必需, 说明, f"登记表 `类型` 条目缺要素: {必需}")

    def test_反向_改回旧名即重新被报(self):
        契约源 = _真实契约源()
        目标 = "组件生成.生成模块脚手架"
        记录 = next(记 for 记 in 契约源 if 记["能力id"] == 目标)
        # 故意改回旧名（反向样本：判据必须重新报它，否则判红不是本判据承担的）。
        for 参数 in 记录["参数"]:
            if 参数.get("名称") == 改名后[目标]:
                参数["名称"] = "类型"
        self.assertIn("类型", _参数名表(契约源, 目标), "反向样本没改成功")
        分歧 = 判分歧(扫全仓(契约源=契约源))
        报出 = {x["字段"] for x in 分歧["同名不同义"]}
        self.assertIn("类型", 报出, f"改回旧名后审计没重新报 `类型`: {报出}")
        self.assertNotIn("类型", {x["字段"] for x in 分歧["真分歧"]},
                         "同名不同义不该被判成真分歧（不硬统一）")

    def test_面齐_四处新名与两处整数型口径号逐处可查(self):
        契约源 = _真实契约源()
        for 能力id, 新名 in 改名后.items():
            名称表 = _参数名表(契约源, 能力id)
            self.assertIn(新名, 名称表, f"{能力id} 缺新参数名 {新名}: {名称表}")
            self.assertNotIn("类型", 名称表, f"{能力id} 仍留旧参数名 `类型`: {名称表}")
            类型表 = {p["名称"]: p.get("类型") for p in
                      next(记 for 记 in 契约源 if 记["能力id"] == 能力id)["参数"]}
            self.assertEqual(类型表[新名], "文本型", f"{能力id} 的 {新名} 应为文本型")
        for 能力id in ("自修复工具.静态编译", "自修复工具.动态编译"):
            参数表 = next(记 for 记 in 契约源 if 记["能力id"] == 能力id)["参数"]
            命中 = [p for p in 参数表 if p.get("名称") == "类型"]
            self.assertEqual(len(命中), 1, f"{能力id} 的整数型 `类型` 口径号被误改: {参数表}")
            self.assertEqual(命中[0].get("类型"), "整数型", f"{能力id} 的 `类型` 应为整数型")

    def test_面齐_包内说明书不留旧参数行(self):
        for 包 in 包目录:
            说明目录 = 系统根 / 包 / "说明"
            for 路径 in sorted(说明目录.glob("*.md")):
                文本 = 路径.read_text(encoding="utf-8")
                相对 = 路径.relative_to(系统根)
                self.assertNotIn("| 类型 | 文本型", 文本, f"{相对} 仍留旧参数行 `| 类型 | 文本型`")
                self.assertNotIn("(类型=", 文本, f"{相对} 仍留旧调用示例 `(类型=`")
                self.assertNotIn("/类型 ", 文本, f"{相对} 仍留旧散文写法 `/类型 `")


if __name__ == "__main__":
    unittest.main()
