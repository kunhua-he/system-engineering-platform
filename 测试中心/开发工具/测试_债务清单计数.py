"""债务清单计数：账目块数字必须等于正文实数（防「机器生成却算错」）。

为什么单独有这一份（2026-09-22）：`开发文档/未完成事项.md` 的账目块号称「按正文实数
算出」，但计数器只统计带编号的行 ⇒ §四「新增债务」8 条实物被报成 0 条 / 「—（空）」。
而门禁「债务清单」只比对「文件里的账目 vs 重算的账目」——两边同一份代码算，
**它抓不住计数器本身算错**，所以那个缺陷能长期存活。本模块把计数器的判据面钉住。

判据面四处（逐条对应当时的缺陷）：
① 无编号表（行首列 `—`）按**数据行**计，不是按编号计；
② `| 6b |` 这类带后缀编号也算编号；
③ 空行把一张表切成几段后，**每段的数据行都要算**（旧口径把每段首行当表头）；
④ 真件账目块报的数字 == 按正文重算的实数（承重断言）。
"""

from __future__ import annotations

import re
import unittest
from pathlib import Path

from 开发工具.MD文档生成.文档类型_债务清单 import 扫描正文

项目根 = Path(__file__).resolve().parents[2]
账目文件 = 项目根 / "开发文档" / "未完成事项.md"

表头 = "| # | 项 | 说明 |\n|---|---|---|\n"


def _文档(标题: str, 表体: str) -> str:
    return f"## {标题}\n\n{表头}{表体}\n"


def _账目块数字(文本: str) -> dict[str, int]:
    """从账目块取每分区条数：主表 `> | 分区 | **N** |`，不计入块 `> - 分区 **N**（…）`。"""
    表: dict[str, int] = {}
    for 行 in 文本.splitlines():
        m = re.match(r"^>\s*\|\s*(.+?)\s*\|\s*\*\*(\d+)\*\*", 行)
        if not m:
            m = re.match(r"^>\s*-\s*(.+?)\s*\*\*(\d+)\*\*", 行)
        if m:
            表[m.group(1).strip("* ")] = int(m.group(2))
    return 表


class Test扫描正文(unittest.TestCase):
    def test_无编号表按数据行计(self):
        """① 行首列是 `—`（无编号）的表：必须按数据行算，不能恒为 0。"""
        编号, 行数 = 扫描正文(_文档("四、新增债务",
                                 "| — | 甲 | 一 |\n| — | 乙 | 二 |\n| — | 丙 | 三 |"))
        self.assertIsNone(编号.get("四"))
        self.assertEqual(行数.get("四"), 3)

    def test_带后缀编号也算编号(self):
        """② `| 6b |` 是编号 —— 只认纯数字会漏（旧正则漏了 §五 的 6b）。"""
        编号, 行数 = 扫描正文(_文档(
            "五、已知覆盖缺口",
            "| 4 | 甲 | 一 |\n| 6 | 乙 | 二 |\n| 6b | 丙 | 三 |\n| 7 | 丁 | 四 |"))
        self.assertEqual(编号.get("五"), ["4", "6", "6b", "7"])
        self.assertEqual(行数.get("五"), 4)

    def test_空行切段每段都算(self):
        """③ 同一分段被空行切成两段表：两段数据行都要算（后半段无表头，整段是数据）。"""
        文本 = ("## 四、新增债务\n\n" + 表头
                + "| — | 甲 | 一 |\n| — | 乙 | 二 |\n\n"
                + "| — | 丙 | 三 |\n| — | 丁 | 四 |\n")
        _编号, 行数 = 扫描正文(文本)
        self.assertEqual(行数.get("四"), 4)

    def test_表头与分隔行不算数据行(self):
        """表头行与 `|---|` 都不是数据行。"""
        _编号, 行数 = 扫描正文(_文档("四、新增债务", "| — | 甲 | 一 |"))
        self.assertEqual(行数.get("四"), 1)

    def test_账目块数字等于正文实数(self):
        """④ **承重断言**：真件账目块报的数字必须等于按正文重算的实数。

        2026-09-22 那个缺陷就是在这里破的：§四 报 0 而实物 8 条。
        """
        文本 = 账目文件.read_text(encoding="utf-8")
        编号, 行数 = 扫描正文(文本)
        账目 = _账目块数字(文本)
        期望 = {
            "四、新增债务": 行数.get("四", 0),
            "七之 7.8 20260918 批审计待证真": 行数.get("7.8", 0),
            "五、已知覆盖缺口": len(编号.get("五", [])),
        }
        for 分区, 应 in 期望.items():
            with self.subTest(分区=分区):
                self.assertIn(分区, 账目, f"账目块里没有 {分区} 这一行")
                self.assertEqual(账目[分区], 应)
        self.assertGreater(账目["四、新增债务"], 0, "§四 不该被报成空表")


if __name__ == "__main__":
    unittest.main()
