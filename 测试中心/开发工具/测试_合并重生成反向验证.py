class 反向验证_退出码三类分开计数(unittest.TestCase):
    """2026-09-23（开工-20260923-092611-b43c，债务行 121 销账）：**零提案 ≠ 零漂移**。

    现场掩盖链（2026-09-22 实测）：`55191d54` 改能力 → 生成器对「哨兵命中／白名单拦下」的包
    **零提案却返回 0**（输出 `⇒ 全部已是固定点（零漂移）`）→ 编译口读 `生成物登记表.json` 的
    `[生成] 包级说明-使用说明 退出码=0` 判绿 → 门禁红 4 项，**怎么跑生成器都修不掉**。

    判据（本题的生效点）：三类分开计数 ——
      · **判不出**（哨兵命中／改判自检未过／账读不出）= **未核验** ⇒ 退 2；
      · **白名单跳过**（人工类，生成器按规矩不碰）= **合法跳过** ⇒ 允许 0；
      · 有漂移（干跑）= 1；零漂移 = 0。

    本类用**打桩**造三种包（不读真文件、不写盘），逐条钉住计数与退出码，并保留反向样本。
    """

    @staticmethod
    def _假单(名: str) -> dict:
        if 名 == "白名单跳过":
            return {"包": "假/白名单跳过", "路径": "假/白名单跳过/说明/使用说明.md",
                    "可合并": False, "处置": "白名单跳过",
                    "问题": "白名单登记为「人工类」（处置：生成器不得覆盖）"}
        if 名 == "判不出":
            return {"包": "假/判不出", "路径": "假/判不出/说明/使用说明.md",
                    "可合并": False, "处置": "判不出",
                    "问题": "账行数 2 远小于现行 97 行：疑似血统判错"}
        return {"包": "假/零漂移", "路径": "假/零漂移/说明/使用说明.md", "可合并": True,
                "血统": "G1", "白名单类别": "", "差异": [], "血统改判": "",
                "统计": {"有改动": False, "人工行零丢失": True}}

    def _跑主函数(self, 包名表: list[str], 源: str | None = None):
        """打桩 `包目录表`／`合并单包` 跑 `主函数`，返回（退出码, 输出文本）。

        `源` 非空时用**该源码**（反向样本）加载模块，否则用真源码。

        **打桩必须改 `命名空间` 本身**（2026-09-23 实测踩坑）：`exec` 出来的 `主函数`
        其 `__globals__` 就是那个 dict，往 `ModuleType` 的副本里改是改不到的——
        副本方案下 `主函数` 仍去扫全仓真文件（实测：断言里出现真实包名）。
        """
        import contextlib
        import io
        from types import SimpleNamespace

        命名空间: dict = {"__name__": "打桩样本", "__file__": str(_源路径)}
        文本源 = _源路径.read_text(encoding="utf-8") if 源 is None else 源
        exec(compile(文本源, str(_源路径), "exec"), 命名空间)  # noqa: S102
        命名空间["包目录表"] = lambda 项目根: [SimpleNamespace(name=名) for 名 in 包名表]
        命名空间["合并单包"] = lambda 包目录, 项目根, 白名单: self._假单(包目录.name)
        缓冲 = io.StringIO()
        with contextlib.redirect_stdout(缓冲):
            码 = 命名空间["主函数"]([])
        return 码, 缓冲.getvalue()

    def test_判不出必须退非零(self):
        """哨兵命中／改判未过 = 未核验 ⇒ 必须退 2（否则「没刷新」被读成退出码 0）。"""
        码, 出 = self._跑主函数(["判不出", "零漂移"])
        self.assertEqual(码, 2, f"未核验竟退了 {码} ⇒ 掩盖链的中间环还在：\n{出}")
        self.assertIn("未核验", 出, f"输出没如实报未核验：\n{出}")
        self.assertNotIn("全部已是固定点", 出,
                     f"判不出被报成零漂移（正是掩盖链的中间环）：\n{出}")

    def test_白名单跳过允许退零(self):
        """白名单「人工类」是**合法跳过**（生成器按规矩不碰）⇒ 不得判红。"""
        码, 出 = self._跑主函数(["白名单跳过", "零漂移"])
        self.assertEqual(码, 0, f"合法跳过被判红（假红）：\n{出}")
        self.assertIn("白名单合法跳过 1 份", 出, f"未分开计数：\n{出}")

    def test_两类分开计数_互不吞噬(self):
        """同一次运行里两类同时出现：跳过仍计跳过、未核验仍计未核验（不许合成一类）。"""
        码, 出 = self._跑主函数(["白名单跳过", "判不出"])
        self.assertEqual(码, 2, f"含未核验时必须退 2：\n{出}")
        self.assertIn("未核验（判不出）1 份", 出, f"未核验计数丢了：\n{出}")
        self.assertIn("白名单合法跳过 1 份", 出, f"跳过计数丢了：\n{出}")

    def test_反向_撤掉未核验闸必退回假绿(self):
        """反向样本：撤掉「未核验 ⇒ 退 2」那道闸 ⇒ 同一夹具必须退回退出码 0（假绿重现）。"""
        源 = _源路径.read_text(encoding="utf-8")
        闸行 = "    if 未核验表:\n"
        假行 = "    if False:  # 反向样本：撤掉未核验闸\n"
        self.assertIn(闸行, 源, "未核验闸行未命中，反向样本失效（判据需更新）")
        码, 出 = self._跑主函数(["判不出"], 源.replace(闸行, 假行))
        self.assertEqual(
            码, 0,
            f"撤闸后竟仍退非零 ⇒ 判红来自别处，样本没测到这道闸：{码}\n{出}")
        self.assertIn(
            "全部已是固定点", 出,
            f"撤闸后应重现「判不出被报成零漂移」的假绿形态：\n{出}")

    def test_退出码口径写进文档串(self):
        """口径必须写在 `主函数` 所在模块的文档串里（改判据的人先读到它，不靠口口相传）。"""
        文本 = _源路径.read_text(encoding="utf-8")
        for 片段 in ("未核验", "白名单", "非 0"):
            self.assertIn(片段, 文本[:3000],
                       f"模块文档串没写清退出码口径（缺「{片段}」）")


