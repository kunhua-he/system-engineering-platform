class 反向验证_补账不得插重复条目(unittest.TestCase):
    """★判据升级（2026-09-20，华哥口径「全部 md 都要经生成器写」）。

    本类原先是「**检出**重复条目」——那是**兜底判据**，治的是症状：账侧同键变体行
    仍被补进来，只是靠自检判红拦住写盘。华哥口径落地后，表条目改为**按键配对、值恒刷**
    （见 `字段键` 的 `表条目` 分支与 `合并说明书` 的对应分支），重复**根本不再产生**。

    所以断言同步升级为「不产生重复」，并按项目铁律保留**反向样本**：把配对退回缺陷态
    （表条目落回 `("独有", 整行)`）必须重现重复，以此证明新判据真的在起作用、不是恒真。
    """

    def test_同键变体不再被补成两行(self):
        输出, 统计 = 合并说明书(表现行, 表账)
        命中 = 重复条目行(表现行.strip().splitlines(), 输出)
        self.assertEqual(
            命中, [],
            f"账侧同键变体行仍被补成第二条 ⇒ 表条目按键配对没生效：{命中}")
        self.assertTrue(
            统计["人工行零丢失"],
            f"零重复的合并不该判红：{统计['结构异常']}")

    def test_值以账为准(self):
        """同一条目的值差异按「生成器自有内容」刷成账 —— 不是两边各留一行。"""
        输出, _ = 合并说明书(表现行, 表账)
        文本 = "\n".join(输出)
        self.assertIn("'值结构': {}", 文本, "账侧的新值应被写进输出")
        self.assertEqual(
            sum(1 for 行 in 输出 if 行.startswith("| 示例库.做甲事")), 1,
            "同一条目在输出里必须只出现一次")

    def test_退回缺陷态必重现重复(self):
        """反向样本：表条目退回 `("独有", 整行)` ⇒ 重复必须重现（判据存在性证明）。"""
        源 = _源路径.read_text(encoding="utf-8")
        # 只退一行：把「表条目」按键返回改回缺陷态的 `("独有", 净)`。
        # 用单行替换而非整块，避免因注释里的反引号/空白差异导致片段匹配不上
        # （实测踩过：整块片段含 `# 分隔行 \`|---|---|\`` 时匹配失败，反向样本直接失效）。
        缺陷行 = '        return ("表条目", 首)'
        恢复行 = '        return ("独有", 净)'
        self.assertIn(缺陷行, 源, "表条目配对行未命中，反向样本失效（判据需更新）")
        坏 = 源.replace(缺陷行, 恢复行)
        命名空间: dict = {"__name__": "反向样本", "__file__": str(_源路径)}
        exec(compile(坏, str(_源路径), "exec"), 命名空间)  # noqa: S102
        输出_坏, _ = 命名空间["合并说明书"](表现行, 表账)
        命中 = 命名空间["重复条目行"](表现行.strip().splitlines(), 输出_坏)
        self.assertTrue(
            命中,
            "退回缺陷态后重复竟未重现 ⇒ 新判据测的不是真实的生效点")

    def test_无重复时不得误报(self):
        # 同一份文本自己与自己比：零新增重复 ⇒ 不得误判
        输出, 统计 = 合并说明书(表现行, 表现行.strip().splitlines())
        self.assertEqual(
            重复条目行(表现行.strip().splitlines(), 输出), [],
            "无重复的输入被误报成重复条目（判据过宽）")
        self.assertTrue(统计["人工行零丢失"], f"零漂移输入应判绿：{统计['结构异常']}")

    #: 白名单「人工类」的真实现场（`支持库/后端/组件规范支持库/说明/使用说明.md`）。
    #: 用它而不是临时夹具：账由 `判定血统` + 生成器现场重算，夹具包里没有真契约/真声明，
    #: 账必然算不出来 ⇒ 提案本就不可合，测到的是「账算不出来」而不是「闸拦下了」
    #: （实测踩过：临时夹具版反向样本假过，测不到闸）。
    _人工类包 = "支持库/后端/组件规范支持库"
    _人工类相对 = "支持库/后端/组件规范支持库/说明/使用说明.md"

    def _真实白名单(self) -> dict:
        import json
        from pathlib import Path as _Path

        路径 = _Path(__file__).resolve().parents[2] / "开发文档/项目证据/说明书白名单.json"
        数据 = json.loads(路径.read_text(encoding="utf-8"))
        return {条["路径"]: 条 for 条 in 数据["白名单"]}

    def test_白名单人工类必须拒写(self):
        """正样本：白名单登记「人工类／生成器不得覆盖」的说明 ⇒ 一律不产提案。"""
        from pathlib import Path as _Path

        from 开发工具.MD文档生成.说明书.合并重生成 import 合并单包

        根 = _Path(__file__).resolve().parents[2]
        单 = 合并单包(根 / self._人工类包, 根, self._真实白名单())
        self.assertFalse(单.get("可合并"), "白名单人工类竟产出了合并提案（闸没生效）")
        self.assertIn("不得覆盖", str(单.get("问题", "")), f"拒绝理由不明确：{单.get('问题')}")

    def test_撤闸后人工类必产提案(self):
        """反向样本：撤掉人工类闸 ⇒ 同一份必须产出提案（证明闸在真实生效点上）。"""
        from pathlib import Path as _Path

        源 = _源路径.read_text(encoding="utf-8")
        # 必须整行替换：该闸是 `if A or B:` 两条件（类别=人工类 / 处置含「不得覆盖」），
        # 只替换 A 会变成 `(False and A) or B` —— B 仍成立 ⇒ 闸照样拦，样本假绿
        # （实测踩过：样本报「闸不在生效点」，其实是样本自己没撤干净）。
        闸行 = ("    if str(白名单条.get(\"类别\", \"\")).startswith(\"人工类\")"
              " or \"不得覆盖\" in str(白名单条.get(\"处置\", \"\")):")
        假行 = "    if False:"
        self.assertIn(闸行, 源, "人工类闸行未命中，反向样本失效（判据需更新）")
        坏 = 源.replace(闸行, 假行)
        命名空间: dict = {"__name__": "反向样本", "__file__": str(_源路径)}
        exec(compile(坏, str(_源路径), "exec"), 命名空间)  # noqa: S102
        根 = _Path(__file__).resolve().parents[2]
        单 = 命名空间["合并单包"](根 / self._人工类包, 根, self._真实白名单())
        self.assertTrue(
            单.get("可合并"),
            f"撤掉人工类闸后竟仍不产提案 ⇒ 闸不在真实生效点上：{单.get('问题')}")


