class 反向验证_围栏内注释不得被删(unittest.TestCase):
    def test_围栏内注释在合并后仍在(self):
        输出, 统计 = 合并说明书(现行, 账)
        合并文本 = "\n".join(输出)
        self.assertIn(
            "【人工注释】", 合并文本,
            "围栏内的人工注释被合并算法删掉了 —— 这正是 #188 的现场症状")

    def test_围栏内代码行在合并后仍在(self):
        输出, _ = 合并说明书(现行, 账)
        合并文本 = "\n".join(输出)
        self.assertIn('调用能力("示例库.做甲事", {"参数": 1})', 合并文本)

    def test_围栏行下标判定含围栏自身与内容(self):
        # 围栏行 + 围栏内内容都在「围栏序集」里；围栏外的不在
        现 = 现行.strip().splitlines()
        集 = 围栏序集(现)
        围栏起 = next(序 for 序, 行 in enumerate(现) if 行.strip() == "```python")
        self.assertIn(围栏起, 集, "围栏起始行应计入")
        注释序 = next(序 for 序, 行 in enumerate(现) if "【人工注释】" in 行)
        self.assertIn(注释序, 集, "围栏内注释行应计入")
        表头序 = next(序 for 序, 行 in enumerate(现) if 行.startswith("| 能力id"))
        self.assertNotIn(表头序, 集, "围栏外的表格行不该计入")

    def test_该夹具合并后自检判绿(self):
        _, 统计 = 合并说明书(现行, 账)
        self.assertTrue(
            统计["人工行零丢失"],
            f"夹具本身应是干净的合并，却报了结构异常：{统计['结构异常']}")

    def test_围栏不得被账侧再吐一遍(self):
        """账里也有同结构围栏时，落盘只应有**一份**示例。

        实测踩坑：给账侧围栏只做「现行没有的才丢」时，现行已有的围栏行会被收尾 `冲()`
        从账里再补一遍 ⇒ 同一段示例在文件里出现两次。
        """
        输出, _ = 合并说明书(现行, 账)
        围栏数 = sum(1 for 行 in 输出 if 行.strip() == "```python")
        self.assertEqual(
            围栏数, 1, f"围栏被重复吐了一份（实测 {围栏数} 份，应为 1 份）")
        收尾数 = sum(1 for 行 in 输出 if 行.strip() == "```")
        self.assertEqual(收尾数, 1, f"围栏收尾被重复（实测 {收尾数} 个）")

    def test_示例行不得被丢(self):
        """★回归样本（实测踩过）：修围栏时把「账侧围栏整块丢弃 + 输出期保护」一起上，
        会让现行示例行走「行在账里」分支、但账那份已被丢弃 ⇒ **两边都落不下去**，
        示例行消失、输出反而膨胀（实测 `模块库/测试资源`：111 行 → 174 行、示例行没了）。

        判据：围栏内的示例代码行必须原样出现在输出里。
        """
        输出, 统计 = 合并说明书(现行, 账)
        文本 = "\n".join(输出)
        self.assertIn(
            '结果 = 调用能力("示例库.做甲事", {"参数": 1})', 文本,
            "围栏内示例行被丢了 —— 这正是「账侧丢弃 + 输出期保护」并用时的回归")
        # 输出行数不得比现行膨胀（膨胀是同一根因的另一个症状）
        现行数 = len(现行.strip().splitlines())
        self.assertLessEqual(
            len(输出), 现行数 + 2,
            f"输出行数异常膨胀：现行 {现行数} → 合并 {len(输出)}")
        self.assertEqual(
            统计["意外丢"], [], f"示例行被判意外丢：{统计['意外丢']}")

    def test_删掉围栏保护必须变红(self):
        """反向样本：原始判定期（`字段键` 把围栏内 `#` 判成标题 ⇒ 恒取账）必须变红。

        这条是上面正向断言的**判据存在性证明**：实测第一版反向样本删错了分支
        （删的是输出期那段，7 例仍全绿），故这里直接钉住**缺陷态的判定期**：
        围栏内注释行判为「刷」，于是被账的标题行顶掉。
        """
        命名空间 = _载入缺陷态()
        输出_坏, 统计_坏 = 命名空间["合并说明书"](现行, 账)
        self.assertNotIn(
            "【人工注释】", "\n".join(输出_坏),
            "去掉判定期围栏保护后注释竟还在 ⇒ 该反向样本没测到真实生效点（实测 HEAD 原版此处注释确被删）")
        # ★缺陷态的特征**不是**自检变红，而是**内容被删了、自检却仍判绿** —— 这正是 #188
        # 的假绿现场（注释行被判「刷」⇒ 不在「必保」集合里 ⇒ 「丢人工/意外丢」两道都抓不到）。
        # 若这里断言成「自检变红」，测的就不是原缺陷，而是另一个（不存在的）行为。
        self.assertTrue(
            统计_坏["人工行零丢失"],
            "缺陷态自检竟变红了 ⇒ 与 HEAD 原版现场不符（原版是注释被删但自检判绿）")

    def test_缺陷态与修版对同夹具结论相反(self):
        """同一夹具：缺陷态删注释、修版留注释 —— 两版结论必须相反，否则测得的是恒真判据。"""
        好集 = 合并说明书(现行, 账)[0]
        命名空间 = _载入缺陷态()
        坏集 = 命名空间["合并说明书"](现行, 账)[0]

        留好 = any("【人工注释】" in x for x in 好集)
        留坏 = any("【人工注释】" in x for x in 坏集)
        self.assertTrue(留好 and not 留坏,
                        f"判据恒真：缺陷态留注释={留坏}、修版留注释={留好}（应分别为 假/真）")


