        self.assertIn(好, 源, "形态优先分支未命中，反向样本失效（判据需更新）")
        源 = 源.replace(好, 坏)
        命名空间: dict = {"__name__": "反向样本", "__file__": str(_源路径)}
        exec(compile(源, str(_源路径), "exec"), 命名空间)  # noqa: S102
        return 命名空间

