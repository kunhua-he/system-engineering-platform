# 账侧把「返回」列渲染成 dict 字面量 ⇒ 整行与现行不同名 ⇒ 被当成新行补进来
表账 = """# 示例库 使用说明

## 能力清单

| 能力id | 名称 | 版本 | 返回 | 说明 |
|---|---|---|---|---|
| 示例库.做甲事 | 做甲事 | 1.0.0 | {'类型': '结果型', '值结构': {}} | 做甲事 |
""".splitlines()


class 反向验证_补账不得插重复条目(unittest.TestCase):
    def test_检测出重复条目(self):
        输出, 统计 = 合并说明书(表现行, 表账)
        命中 = 重复条目行(表现行.strip().splitlines(), 输出)
        self.assertTrue(
            命中, "账侧同键变体行被补进来，应检出重复条目，实际一条都没报")
        self.assertTrue(
            any("示例库.做甲事" in x for x in 命中),
            f"应指名重复的条目键，实际：{命中}")

    def test_重复条目纳入fail_closed自检(self):
        _, 统计 = 合并说明书(表现行, 表账)
        self.assertFalse(
            统计["人工行零丢失"],
            "检出重复条目后自检仍判绿 ⇒ 写盘会把这行重复写进人的文件（#188 假绿）")
        self.assertTrue(
            any("重复条目" in x for x in 统计["结构异常"]),
            f"结构异常里应写明重复条目，实际：{统计['结构异常']}")

    def test_无重复时不得误报(self):
        # 同一份文本自己与自己比：零新增重复 ⇒ 不得误判
        输出, 统计 = 合并说明书(表现行, 表现行.strip().splitlines())
        self.assertEqual(
            重复条目行(表现行.strip().splitlines(), 输出), [],
            "无重复的输入被误报成重复条目（判据过宽）")
        self.assertTrue(统计["人工行零丢失"], f"零漂移输入应判绿：{统计['结构异常']}")


if __name__ == "__main__":
    unittest.main()
