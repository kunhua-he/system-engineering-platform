"""合并重生成 反向验证：#188 两处有损（围栏内注释被删 / 补账插入重复条目）。

缺陷现场（2026-09-20 开工-20260920-214719-4a04）：`支持库/后端/项目文档支持库/说明/使用说明.md`
的人工代码示例里写着注释 `# 四档粒度（默认「简介」档与改前逐字段兼容）`，跑
`合并重生成 --写盘` 后该注释消失（`rg -c '四档粒度'` 由 1 → 0），只能 `git checkout` 恢复。

根因：`字段键()` 把围栏内以 `#` 开头的行判成「标题行」，而标题行的处置是**恒取账**
⇒ 被账的标题行顶掉。

同一份文件还出现第二处损伤：能力清单表被**补账插入重复行**（账侧把返回列渲染成
`{'类型': …}`，与现行的 `结果型` 不同名，于是被当成新行），参数表同样重复。两处都发生在
「人工行零丢失 = True」的情况下 ⇒ 原自检判不出「多出来的行」，属**假绿**。

本测试用**最小夹具**复现这两类结构（不读生产说明书，避免测试与人工内容耦合）。
"""
import unittest

from 开发工具.说明书生成.合并重生成 import 合并说明书, 围栏序集, 重复条目行


from pathlib import Path

_源路径 = Path(__file__).resolve().parents[2] / "开发工具" / "说明书生成" / "合并重生成.py"

_判定期保护 = (
    '        if 序 in 现围栏:\n'
    '            判定[序] = "保"          # 围栏内整块取现行（含人工注释与空行）\n'
    '            continue\n'
)

_输出期保护 = (
    '        if 序 in 现围栏:\n'
    '            # 围栏内整块取现行：**先于**「行 in 账集」判断，否则示例里的注释/命令行\n'
    '            # 只要与账里某行同字，就会被账行顶掉（注释被删正是这么发生的）。\n'
    '            超配对.append(行) if 行 in 账集 else None\n'
    '            输出.append(行)\n'
    '            continue\n'
)


def _缺陷态源码() -> str:
    """把算法退回 #188 缺陷态：**两处**围栏保护都去掉。

    实测踩坑：只去掉其中一处时另一处仍会兜住注释 ⇒ 反向样本恒绿（第一版就这么错）。
    `字段键` 把围栏内 `#` 判成标题、标题恒取账 —— 这才是原始删除路径。
    """
    源 = _源路径.read_text(encoding="utf-8")
    坏 = 源.replace(_判定期保护, "").replace(_输出期保护, "")
    if 坏 == 源:
        raise AssertionError("两处围栏保护片段一处都没命中，反向样本失效（判据需更新）")
    if _判定期保护 in 坏 or _输出期保护 in 坏:
        raise AssertionError("只去掉了部分围栏保护，反向样本仍会被兜住（恒绿）")
    return 坏


def _载入缺陷态():
    # 被执行的源码模块级用 `Path(__file__)` 定位系统根，注入 __file__ 才能加载。
    命名空间: dict = {"__name__": "反向样本", "__file__": str(_源路径)}
    exec(compile(_缺陷态源码(), str(_源路径), "exec"), 命名空间)  # noqa: S102
    return 命名空间

现行 = """# 示例库 使用说明

## 能力清单

| 能力id | 名称 |
|---|---|
| 示例库.做甲事 | 做甲事 |

## 调用示例

```python
# 【人工注释】这是人工写在围栏里的说明，生成器账里没有
结果 = 调用能力("示例库.做甲事", {"参数": 1})
```
"""

# 账：与现行同结构，但**没有**那条人工注释（生成器不会产它）
账 = """# 示例库 使用说明

## 能力清单

| 能力id | 名称 |
|---|---|
| 示例库.做甲事 | 做甲事 |

## 调用示例

```python
结果 = 调用能力("示例库.做甲事", {"参数": 1})
```
""".splitlines()


class 反向验证_围栏内注释不得被删(unittest.TestCase):
    def test_围栏内注释在合并后仍在(self):
        输出, 统计 = 合并说明书(现行, 账)
        合并文本 = "\n".join(输出)
        self.assertIn(
            "【人工注释】", 合并文本,
            "围栏内的人工注释被合并算法删掉了 —— 这正是 #188 的现场症状")

    def test_围栏内代码行在合并后仍在(self):
        输出, _ = 合并说明书(现行, 账)
        合并文本 = "\n".join(输出)
        self.assertIn('调用能力("示例库.做甲事", {"参数": 1})', 合并文本)

    def test_围栏行下标判定含围栏自身与内容(self):
        # 围栏行 + 围栏内内容都在「围栏序集」里；围栏外的不在
        现 = 现行.strip().splitlines()
        集 = 围栏序集(现)
        围栏起 = next(序 for 序, 行 in enumerate(现) if 行.strip() == "```python")
        self.assertIn(围栏起, 集, "围栏起始行应计入")
        注释序 = next(序 for 序, 行 in enumerate(现) if "【人工注释】" in 行)
        self.assertIn(注释序, 集, "围栏内注释行应计入")
        表头序 = next(序 for 序, 行 in enumerate(现) if 行.startswith("| 能力id"))
        self.assertNotIn(表头序, 集, "围栏外的表格行不该计入")

    def test_该夹具合并后自检判绿(self):
        _, 统计 = 合并说明书(现行, 账)
        self.assertTrue(
            统计["人工行零丢失"],
            f"夹具本身应是干净的合并，却报了结构异常：{统计['结构异常']}")

    def test_围栏不得被账侧再吐一遍(self):
        """账里也有同结构围栏时，落盘只应有**一份**示例。

        实测踩坑：给账侧围栏只做「现行没有的才丢」时，现行已有的围栏行会被收尾 `冲()`
        从账里再补一遍 ⇒ 同一段示例在文件里出现两次。
        """
        输出, _ = 合并说明书(现行, 账)
        围栏数 = sum(1 for 行 in 输出 if 行.strip() == "```python")
        self.assertEqual(
            围栏数, 1, f"围栏被重复吐了一份（实测 {围栏数} 份，应为 1 份）")
        收尾数 = sum(1 for 行 in 输出 if 行.strip() == "```")
        self.assertEqual(收尾数, 1, f"围栏收尾被重复（实测 {收尾数} 个）")

    def test_删掉围栏保护必须变红(self):
        """反向样本：原始判定期（`字段键` 把围栏内 `#` 判成标题 ⇒ 恒取账）必须变红。

        这条是上面正向断言的**判据存在性证明**：实测第一版反向样本删错了分支
        （删的是输出期那段，7 例仍全绿），故这里直接钉住**缺陷态的判定期**：
        围栏内注释行判为「刷」，于是被账的标题行顶掉。
        """
        命名空间 = _载入缺陷态()
        输出_坏, 统计_坏 = 命名空间["合并说明书"](现行, 账)
        self.assertNotIn(
            "【人工注释】", "\n".join(输出_坏),
            "去掉判定期围栏保护后注释竟还在 ⇒ 该反向样本没测到真实生效点（实测 HEAD 原版此处注释确被删）")
        self.assertFalse(
            统计_坏["人工行零丢失"],
            "去掉判定期围栏保护后自检仍判绿 ⇒ 这正是 #188 的假绿（实测 HEAD 原版即此症状）")

    def test_缺陷态与修版对同夹具结论相反(self):
        """同一夹具：缺陷态删注释、修版留注释 —— 两版结论必须相反，否则测得的是恒真判据。"""
        好集 = 合并说明书(现行, 账)[0]
        命名空间 = _载入缺陷态()
        坏集 = 命名空间["合并说明书"](现行, 账)[0]

        留好 = any("【人工注释】" in x for x in 好集)
        留坏 = any("【人工注释】" in x for x in 坏集)
        self.assertTrue(留好 and not 留坏,
                        f"判据恒真：缺陷态留注释={留坏}、修版留注释={留好}（应分别为 假/真）")


