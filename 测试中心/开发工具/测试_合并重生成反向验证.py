        输出, 统计 = 合并说明书(现行, 账)
        文本 = "\n".join(输出)
        self.assertIn(
            '结果 = 调用能力("示例库.做包1事", {"参数": 1})', 文本,
            "围栏内示例行被丢了 —— 这正是「账侧丢弃 + 输出期保护」并用时的回归")
        # 输出行数不得比现行膨胀（膨胀是同一根因的另一个症状）
        现行数 = len(现行.strip().splitlines())
        self.assertLessEqual(
            len(输出), 现行数 + 2,
            f"输出行数异常膨胀：现行 {现行数} → 合并 {len(输出)}")
        self.assertEqual(
            统计["意外丢"], [], f"示例行被判意外丢：{统计['意外丢']}")

