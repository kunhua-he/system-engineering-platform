"""合并重生成 反向验证：#188 两处有损（围栏内注释被删 / 补账插入重复条目）。

缺陷现场（2026-09-20 开工-20260920-214719-4a04）：`支持库/后端/项目文档支持库/说明/使用说明.md`
的人工代码示例里写着注释 `# 四档粒度（默认「简介」档与改前逐字段兼容）`，跑
`合并重生成 --写盘` 后该注释消失（`rg -c '四档粒度'` 由 1 → 0），只能 `git checkout` 恢复。

根因：`字段键()` 把围栏内以 `#` 开头的行判成「标题行」，而标题行的处置是**恒取账**
⇒ 被账的标题行顶掉。

同一份文件还出现第二处损伤：能力清单表被**补账插入重复行**（账侧把返回列渲染成
`{'类型': …}`，与现行的 `结果型` 不同名，于是被当成新行），参数表同样重复。两处都发生在
「人工行零丢失 = True」的情况下 ⇒ 原自检判不出「多出来的行」，属**假绿**。

本测试用**最小夹具**复现这两类结构（不读生产说明书，避免测试与人工内容耦合）。
"""
import unittest

from 开发工具.MD文档生成.说明书.合并重生成 import 合并说明书, 围栏序集, 重复条目行


from pathlib import Path

_源路径 = Path(__file__).resolve().parents[2] / "开发工具" / "MD文档生成" / "说明书" / "合并重生成.py"

_判定期保护 = (
    '        if 序 in 现围栏:\n'
    '            判定[序] = "保"          # 围栏内整块取现行（含人工注释与空行）\n'
    '            continue\n'
)

def _缺陷态源码() -> str:
    """把算法退回 #188 缺陷态：去掉判定期围栏保护。

    **踩坑记录（两轮）**：第一版反向样本删的是**输出期**那段（当时有两处保护），
    删完 7 例仍全绿 —— 因为判定期那处还在兜。后改为两处同退才变红。
    最终修法只保留**判定期一处**（输出期那处已随账侧围栏整块丢弃一并移除，
    原因是它会让「行在账里」的现行围栏行两边都落不下去 ⇒ 示例行被丢，
    实测 `模块库/测试资源` 输出膨胀到 174 行、示例行消失）。故反向样本同步收成一处。
    """
    源 = _源路径.read_text(encoding="utf-8")
    坏 = 源.replace(_判定期保护, "")
    if 坏 == 源:
        raise AssertionError("判定期围栏保护片段未命中，反向样本失效（判据需更新）")
    return 坏


def _载入缺陷态():
    # 被执行的源码模块级用 `Path(__file__)` 定位系统根，注入 __file__ 才能加载。
    命名空间: dict = {"__name__": "反向样本", "__file__": str(_源路径)}
    exec(compile(_缺陷态源码(), str(_源路径), "exec"), 命名空间)  # noqa: S102
    return 命名空间

