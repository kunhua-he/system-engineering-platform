#: `字段键` 判成标题行而恒取账 ⇒ #188 的「注释被删且自检仍绿」原样重现（见下方两条断言）。
_判定期保护 = (
    '        if 序 in 现围栏:\n'
    '            候 = 自有围栏配对.get(序)\n'
    '            if 候 is None:\n'
    '                判定[序] = "保"      # 人工围栏块 / 无账对应位：整块取现行（含人工注释与空行）\n'
    '                continue\n'
    '            判定[序], 配对[序] = "刷", 候\n'
    '            continue\n'
)

def _缺陷态源码() -> str:
    """把算法退回 #188 缺陷态：去掉判定期围栏保护。

    **踩坑记录（两轮）**：第一版反向样本删的是**输出期**那段（当时有两处保护），
    删完 7 例仍全绿 —— 因为判定期那处还在兜。后改为两处同退才变红。
    最终修法只保留**判定期一处**（输出期那处已随账侧围栏整块丢弃一并移除，
    原因是它会让「行在账里」的现行围栏行两边都落不下去 ⇒ 示例行被丢，
    实测 `模块库/测试资源` 输出膨胀到 174 行、示例行消失）。故反向样本同步收成一处。
    """
    源 = _源路径.read_text(encoding="utf-8")
    坏 = 源.replace(_判定期保护, "")
    if 坏 == 源:
        raise AssertionError("判定期围栏保护片段未命中，反向样本失效（判据需更新）")
    return 坏


def _载入缺陷态():
    # 被执行的源码模块级用 `Path(__file__)` 定位系统根，注入 __file__ 才能加载。
    命名空间: dict = {"__name__": "反向样本", "__file__": str(_源路径)}
    exec(compile(_缺陷态源码(), str(_源路径), "exec"), 命名空间)  # noqa: S102
    return 命名空间


def _手写markdown语法正则(源: str) -> list[str]:
    """按 `同动作双路径检测` 规则六的**同一口径**扫出一份源码里的手写 markdown 语法正则。

    **不复制判据**：直接消费判据件的 `_正则字面量` / `_是通用markdown语法`（哲学 1.2
    「一类事情只有一条腿」），本函数只把那条判据的扫描面缩到一份源码文本上 ——
    故「改后为 0」与编译口跑出的判据同源，不是另写一套更松的断言。
    """
    import ast

    from 开发工具.验证门禁.同动作双路径检测 import _正则字面量, _是通用markdown语法

    命中: list[str] = []
    for 节点 in ast.walk(ast.parse(源)):
        形态 = _正则字面量(节点)
        if 形态 is not None and _是通用markdown语法(形态):
            命中.append(形态)
    return 命中

