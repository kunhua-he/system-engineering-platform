"""验证场景静态守卫的**射程**与**判据码**回归（批H-H5，2026-09-24）。

背景（现场实测）：`开发工具/HTML验证/路径安全.py::_校验动态声明` 是场景解析链上的静态守卫
—— 它按「场景入参不得出现静态绝对路径或 `..` 逃逸写法」（决策记录 0016）逐条判每个字符串。
2026-09-24 批H 裁-A 把自写判据转调唯一判据节点 `系统核心支持库.路径安全.校验相对路径文本`
时写成 `if not 文本判定.成功 or 拒绝原因 in (绝对写法原因, 盘符写法原因, 段跳转原因)`，
于是**非路径字面**也被当成越界写法：

- 节点对空串/空白串如实回 `失败("参数不合法")` ⇒ `not 成功` 命中 ⇒ **拒**；
  而「空参数被拒」正是全仓负向用例的常规写法 ⇒ 实测 **24 个包**在
  `开发工具/验证场景体检` 里整包报红（`python3.14 -m 开发工具.验证场景体检`：改前 24 不合格）。
- 节点判据前把反斜杠归一成 `/`（为的是挡住 `a\\..\\b` 这类写法）⇒ 正则字面 `\\d+` 被读成
  绝对路径 `/d+` 而**拒**，同一份场景里的 `(\\d+)` 却**放行** —— 同一件事两种读数。

本测试钉住修后的两条口径（判据仍只有唯一节点那五条，**不新增判据**）：
1. **射程**：只有「字面像路径」的字符串才送节点问写法 —— 与批H 之前的自写判据**等价**，
   空串/空白/正则/单前导反斜杠一律**放行**；含 `/`、含 `..`、盘符写法才进射程。
2. **判据码**：守卫只读节点回的结构化 `判据`（哲学 14.4），**不比对 `原因` 文案串**；
   拒的是 `绝对写法`（含盘符）与 `段跳转`，`家目录写法`/`当前目录`/`点段` 必须放行（0016）。

跑法：python3.14 -m unittest 测试中心.开发工具.测试_HTML验证场景路径守卫
"""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 开发工具.HTML验证.路径安全 import 守卫拒绝判据码
from 支持库.后端.系统核心支持库.路径安全 import 校验相对路径文本, 像路径写法文本


def 像路径(值: str) -> bool:
    """唯一腿的射程判定（`像路径写法文本`）。"""
    结果 = 像路径写法文本(值)
    值字典 = 结果.值 if isinstance(结果.值, dict) else {}
    return bool(值字典.get("是路径写法"))


def 守卫判(值: str) -> bool:
    """复现守卫的判定链（射程 → 送唯一判据节点 → 读判据码），返回「是否拦下」。"""
    if not 像路径(值):
        return False
    文本判定 = 校验相对路径文本(值)
    判定值 = 文本判定.值 if isinstance(文本判定.值, dict) else {}
    return 判定值.get("判据") in 守卫拒绝判据码


class 场景路径守卫回归(unittest.TestCase):
    def test_非路径字面必须放行(self) -> None:
        """批H-H5 的回归面：这些字面都不是路径写法，守卫不得拦（拦了就是 24 包整包报红）。"""
        for 用例 in ("", "   ", "\t", "\\d+", "^[A-Z]{2}\\d{2}$", "\\etc\\passwd", "1..10", "北京12上海34"):
            with self.subTest(用例=用例):
                self.assertFalse(守卫判(用例), f"{用例!r} 不是路径写法，守卫不得拦下")

    def test_越界写法必须拦下(self) -> None:
        """0016 明文的两条：绝对写法（含盘符）与 `..` 段跳转（含 URL 编码穿越）。"""
        for 用例 in ("/etc/passwd", "C:/Windows", "a\\..\\b", "..%2f逃逸", "%2e%2e/x", "a/..%2f/b", ".."):
            with self.subTest(用例=用例):
                self.assertTrue(守卫判(用例), f"{用例!r} 是越界写法，守卫必须拦下")

    def test_0016_要求放行的两类不得拦(self) -> None:
        """`~` 家目录写法与 `.` 段留给**运行期**硬失败取证（决策记录 0016 既定口径）。"""
        for 用例 in ("~/平台控制面/能力目录/服务.py", "./x"):
            with self.subTest(用例=用例):
                self.assertFalse(守卫判(用例), f"{用例!r} 按 0016 必须放行，交给运行期取证")

    def test_射程判据三条与原因文案无关(self) -> None:
        """射程只看字面形态（含 `/`、含 `..`、盘符），且**住唯一腿**（`像路径写法文本`）；
        守卫判据只读判据码，不读 `原因` 文案。

        为什么射程必须住唯一腿（本测试的前提）：写成调用方的私有函数会被
        `开发工具/验证门禁/同动作双路径检测.py` 规则七判红（名字含路径 + 段里含 `..`
        = 同职责路径判定的第二份实现）—— 实测本批初版就吃了这条红。
        """
        self.assertTrue(像路径("a/b"))
        self.assertTrue(像路径("a..b"))
        self.assertTrue(像路径("C:/x"))
        self.assertFalse(像路径("C:foo"))  # 盘符相对（无分隔符）：批H 前同样放行，口径不变
        self.assertFalse(像路径("\\d+"))
        判据码集 = {
            值.get("判据")
            for 值 in (
                校验相对路径文本("/x").值,
                校验相对路径文本("~/x").值,
                校验相对路径文本("a/../b").值,
                校验相对路径文本(".").值,
                校验相对路径文本("a/./b").值,
            )
            if isinstance(值, dict)
        }
        self.assertEqual(
            {"绝对写法", "家目录写法", "段跳转", "当前目录", "点段"}, 判据码集,
            "唯一判据节点的判据码集合变了 ⇒ 守卫的判据集合要同步复核（哲学 14.4）",
        )

    def test_反向_按成功标志与原因文案判会误拦非路径字面(self) -> None:
        """反向证据：把判据换回 `not 成功 or 原因 in (文案…)`，空串与 `\\d+` 立刻被误拦。"""
        绝对写法原因 = "相对路径不能是绝对路径"
        盘符写法原因 = "相对路径不能是 Windows 盘符路径"
        段跳转原因 = "相对路径不能包含 .. 目录跳转"

        def 坏判据(值: str) -> bool:
            文本判定 = 校验相对路径文本(值)
            判定值 = 文本判定.值 if isinstance(文本判定.值, dict) else {}
            拒绝原因 = "" if 判定值.get("通过") else str(判定值.get("原因") or "")
            return (not 文本判定.成功) or 拒绝原因 in (绝对写法原因, 盘符写法原因, 段跳转原因)

        for 用例 in ("", "   ", "\\d+"):
            with self.subTest(用例=用例):
                self.assertTrue(坏判据(用例), f"{用例!r} 在旧判据下会被误拦（本测试的前提）")
                self.assertFalse(守卫判(用例), f"{用例!r} 现判据下必须放行")


if __name__ == "__main__":
    unittest.main()
