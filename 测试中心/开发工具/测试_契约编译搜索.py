def _读契约调用示例(包相对路径: str, 能力id: str):
    """从包内 `能力契约/参数契约.json` 读该能力的契约调用示例（唯一事实源，测试侧不复算）。"""
    契约路径 = 项目根 / 包相对路径 / "能力契约" / "参数契约.json"
    数据 = json.loads(契约路径.read_text(encoding="utf-8"))
    for 条目 in 数据.get("能力契约", []):
        if isinstance(条目, dict) and 条目.get("能力id") == 能力id:
            return 条目.get("调用示例", "无")
    return "无"


