"""验证覆盖与判据 自检脚本的覆盖断言测试。

该自检脚本此前**零测试覆盖**（2026-09-23 实测：`测试中心/开发工具/测试_依赖生命周期审计.py`
只测审计核心，不跑这个自检脚本），这正是它红着没人发现的原因 —— 适配层腿原用裸计数
``适配层提供者数 = 17``，适配层长到 21 个之后恒报「既有覆盖被改动」，而审计结论一个没变。

本模块钉住两条腿各自的语义（它们**本来就不同**，见 覆盖失败项 的 docstring）：

- 后端腿是**下界**：指定必审的一批被审到即可，现场多出别的后端提供者不算缺口；
- 适配层腿是**等号**：适配层提供者的增删都必须落到名单上 —— 少了「增」这一半，
  删掉某家的 `生命周期契约.json` 就会让覆盖静默掉一块。

不构造真实提供者目录、不落任何临时文件：直接把 被测路径 集合喂给判据函数。
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 开发工具.依赖生命周期审计 import 验证覆盖与判据


def 全部名单() -> set[str]:
    return set(验证覆盖与判据.后端契约提供者) | set(验证覆盖与判据.适配层契约提供者)


def 现场被测路径() -> set[str]:
    """用真实仓库跑一遍审计，取它实际扫到的提供者目录（仓库相对路径）。"""
    结果列表, _跳过 = 验证覆盖与判据.审计全部(验证覆盖与判据.系统根)
    return {str(结果.目录.relative_to(验证覆盖与判据.系统根)) for 结果 in 结果列表}


class Test覆盖断言形状(unittest.TestCase):
    """后端腿下界、适配层腿等号；两个方向都要抓。"""

    def test_后端新增提供者不算缺口(self):
        """后端腿是下界：实测现场后端有 7 个被审但不在名单里，不得因此报红。"""
        被测路径 = 全部名单() | {"支持库/后端/将来新增的后端"}
        self.assertEqual(验证覆盖与判据.覆盖失败项(被测路径), [])

    def test_适配层新增提供者必须登记否则报红(self):
        """适配层腿是等号：新提供者不登记进名单，日后它消失就不会被发现。"""
        被测路径 = 全部名单() | {"支持库/适配层/将来新增的提供者"}
        失败项 = 验证覆盖与判据.覆盖失败项(被测路径)
        self.assertTrue(any("未登记进 适配层契约提供者" in 项 for 项 in 失败项), 失败项)

    def test_适配层提供者不再被审计必须报出(self):
        被测路径 = 全部名单() - {"支持库/适配层/Pillow提供者"}
        失败项 = 验证覆盖与判据.覆盖失败项(被测路径)
        self.assertTrue(any("适配层提供者未被审计" in 项 for 项 in 失败项), 失败项)

    def test_后端提供者不再被审计必须报出(self):
        被测路径 = 全部名单() - {验证覆盖与判据.后端契约提供者[0]}
        失败项 = 验证覆盖与判据.覆盖失败项(被测路径)
        self.assertTrue(any("后端提供者未被审计" in 项 for 项 in 失败项), 失败项)

    def test_真实仓库覆盖无缺口(self):
        """用现场真实审计结果喂判据：当前仓库必须零缺口（后端那 7 个未列名者不误报）。"""
        self.assertEqual(验证覆盖与判据.覆盖失败项(现场被测路径()), [])

    def test_真实仓库自检通过(self):
        self.assertEqual(验证覆盖与判据.主入口(), 0)


if __name__ == "__main__":
    unittest.main()
