"""合规调用器参数校验收口测试（开工ID 开工-20260923-043726-de76）。

## 缺陷（改前实测，本文件是它的回归锁）

`开发工具/组件合规/合规测试包.py` 的 `_合规调用器.调用能力` **直调
`能力实现.调用`**（原第 689 行 `返回值 = 实现.调用(**(参数 or {}))`），
**绕过唯一校验点** `运行核心/统一网关/协议/类型规格.py::校验能力参数`：

后果：合规测试脚手架在 `_场景真实返回值` 里装配并注册的进程内调用器
（`公共契约.能力契约.调用器.注册能力调用器(_合规调用器(注册表))`）
**没有任何参数校验** —— 缺必填参数时解释器在调用点抛 `TypeError`，
**异常直接逸出**（调用方连统一结果都拿不到）；而同一条入参在 HTTP 腿
（`网关参数校验面._能力参数错误` → `校验能力参数`）与进程内唯一能力调用腿
（`唯一能力调用.调用能力` → `校验能力参数`）都回 **`参数不合法`**。

## 修法（本仓铁律：同一件事两套实现即缺陷 / 新写的读取必须转调唯一腿）

让 `_合规调用器.调用能力` **转调唯一校验点** `校验能力参数`
（与 HTTP 腿、进程内唯一能力调用腿**同一个函数、同一份声明** `实现.参数`），
不在 `合规测试包.py` 另养第二套类型表/必填判据。

## 本文件锁什么

1. 合规调用器缺必填参数 → 回统一结果 `参数不合法`（**不是异常逸出、不是 内部错误**）；
2. 错误说明与唯一校验点 `校验能力参数` **逐字一致**（证明是转调同一把尺子，
   不是在本文件另养的第二套判据）；
3. 合法入参不误伤（成功路径照旧走 `实现.调用` → 结果包装）。

## 怎么拿到 `_合规调用器`（它是 `_场景真实返回值` 里的局部类）

局部类不可直接 import，故本文件**不改被测代码**，改为在 `组件合规(...).执行()`
期间劫持 `公共契约.能力契约.调用器.注册能力调用器`（`合规测试包.py` 在方法体内
`from ... import 注册能力调用器`，按模块属性解析），把注入的调用器实例截获下来，
再直接对它施加入参——这正是脚手架真实装配的那个对象。
"""

from __future__ import annotations

import json
import sys
import tempfile
import unittest
from pathlib import Path

系统根 = Path(__file__).resolve().parents[2]
if str(系统根) not in sys.path:
    sys.path.insert(0, str(系统根))

from 公共契约.基础类型.逻辑类型 import 真
from 公共契约.运行时.平台适配 import 清只读后删除树
from 开发工具.组件合规.合规测试包 import 组件合规
from 运行核心.统一网关.协议.类型规格 import 校验能力参数

能力id = "合规.校验.能力1"
包id = "合规.调用器校验组件"
#: 与真实包同形：必填 `文本` 是**必填位置参数**（缺则解释器在调用点抛 TypeError）。
声明参数 = [{"名称": "文本", "类型": "文本型", "必填": 真, "默认值": None}]

入口源码 = '''"""合规调用器校验组件包级中文入口。"""
from __future__ import annotations

from 公共契约.基础类型.逻辑类型 import 真
from 实现.实现 import 能力1

__all__ = ["能力1"]


def 注册能力(注册表) -> None:
    """由合规脚手架装配时调用。"""
    from 公共契约.能力契约.契约 import 能力实现

    注册表.注册(能力实现(
        能力id="合规.校验.能力1", 包id="合规.调用器校验组件", 实现函数=能力1,
        参数=[{"名称": "文本", "类型": "文本型", "必填": 真, "默认值": None}],
        返回="结果型", 说明="合规调用器校验用",
    ))
'''

实现源码 = '''"""合规调用器校验组件实现。"""
from __future__ import annotations


def 能力1(文本: str) -> dict:
    return {"成功": True, "值": {"长度": len(文本)}}
'''

契约条目 = {
    "能力id": 能力id, "版本": "1.0.0", "说明": "合规调用器校验用",
    "参数": [{"名称": "文本", "类型": "文本型", "必填": 真,
              "默认值": None, "说明": "待处理文本"}],
    "返回": {"类型": "结果型", "值结构": {"长度": "整数型"}},
    "错误码": ["参数不合法", "内部错误"],
    "调用示例": {"能力id": 能力id, "参数": {"文本": "示例"}},
}


def 截获合规调用器(组件目录: Path):
    """在 `组件合规(...).执行()` 期间截获注入的 `_合规调用器` 实例。"""
    import 公共契约.能力契约.调用器 as 调用器模块

    原注册 = 调用器模块.注册能力调用器
    捕获: list = []

    def 捕获注册(调用器):
        捕获.append(调用器)
        原注册(调用器)

    调用器模块.注册能力调用器 = 捕获注册
    try:
        组件合规(组件目录).执行()
    finally:
        调用器模块.注册能力调用器 = 原注册
    # 执行期间另有场景注册**真实** `唯一能力调用服务`（同名注册点），
    # 故按类名只取 `_合规调用器`——它就是本工作包要收口的那个对象。
    实例 = [项 for 项 in 捕获
            if 项 is not None and type(项).__name__ == "_合规调用器"]
    if not 实例:
        raise AssertionError("未截获到 _合规调用器（真实返回值场景未装配调用器）")
    return 实例[0]


class Test合规调用器参数校验(unittest.TestCase):
    """合规脚手架内的进程内调用器必须过唯一校验点（不再是第二套/无校验）。"""

    def setUp(self) -> None:
        # 夹具根**由 setUp 造**（`self.组件目录`），组件内容由 `建校验组件()` 往它里面写：
        # 夹具根若当形参传，静态判据（`测试写入边界门禁` 判据一）解析不出外部名字，
        # `目录 / "包声明.json"` 一类合法临时夹具写会被整片计入「未解析」违规。
        self.组件目录 = Path(tempfile.mkdtemp(prefix="合规调用器校验_"))
        self.建校验组件()
        self.调用器 = 截获合规调用器(self.组件目录)

    def 建校验组件(self) -> None:
        """构造可装配的最小正式包形态组件（只求走到 `_场景真实返回值`）。"""
        目录 = self.组件目录
        for 子目录 in ("能力契约", "依赖契约", "实现", "说明"):
            (目录 / 子目录).mkdir()
        (目录 / "能力契约" / "参数契约.json").write_text(
            json.dumps({"契约版本": "1.0.0", "能力契约": [契约条目]},
                       ensure_ascii=False, indent=2), encoding="utf-8")
        (目录 / "依赖契约" / "依赖契约.json").write_text(
            json.dumps({"依赖": []}, ensure_ascii=False), encoding="utf-8")
        (目录 / "包声明.json").write_text(json.dumps({
            "包id": 包id, "名称": "调用器校验组件", "类型": "基础模块",
            "版本": "1.0.0", "说明": "合规调用器参数校验测试组件",
            "入口": "__init__.py", "依赖": [],
        }, ensure_ascii=False), encoding="utf-8")
        (目录 / "__init__.py").write_text(入口源码, encoding="utf-8")
        (目录 / "实现" / "实现.py").write_text(实现源码, encoding="utf-8")
        (目录 / "说明" / "使用说明.md").write_text(
            "# 调用器校验组件说明书\n\n能力1，错误码：参数不合法/内部错误。\n",
            encoding="utf-8")

    def tearDown(self) -> None:
        清只读后删除树(self.组件目录, 忽略失败=真)

    def test_缺必填参数回参数不合法_不是异常逸出(self) -> None:
        # 改前：`实现.调用()` 直调 → TypeError 逸出（调用方拿不到统一结果）。
        # 改后：转调唯一校验点 → 统一结果 `参数不合法`。
        结果对象 = self.调用器.调用能力(能力id, {})
        self.assertFalse(结果对象.成功, 结果对象)
        self.assertEqual(结果对象.错误码, "参数不合法")
        self.assertIn("缺少必填参数 文本", 结果对象.错误说明)
        self.assertNotIn("TypeError", 结果对象.错误说明)

    def test_错误说明与唯一校验点逐字一致(self) -> None:
        """是**转调**唯一校验点，不是第二套判据：说明必须逐字相同。"""
        唯一校验点说明 = 校验能力参数(能力id, 声明参数, {})
        self.assertTrue(唯一校验点说明.startswith("参数不合法："))
        结果对象 = self.调用器.调用能力(能力id, {})
        self.assertEqual(结果对象.错误说明, 唯一校验点说明)

    def test_合法入参不误伤(self) -> None:
        结果对象 = self.调用器.调用能力(能力id, {"文本": "abc"})
        self.assertTrue(结果对象.成功, 结果对象.错误说明)
        self.assertEqual(结果对象.值, {"长度": 3})

    def test_未注册能力仍回提供者不可用(self) -> None:
        结果对象 = self.调用器.调用能力("不存在的.能力", {})
        self.assertFalse(结果对象.成功)
        self.assertEqual(结果对象.错误码, "提供者不可用")


if __name__ == "__main__":
    unittest.main()
