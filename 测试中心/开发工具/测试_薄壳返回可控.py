class 调用腿自动改腿测试(unittest.TestCase):
    """腿② 收到网关 `须走异步腿` 必须**自己改走异步腿**，不把换腿的事抛回调用方。

    为什么要这条（2026-09-25 实测）：`自修复工具.静态编译`／`动态编译` 的 `超时秒` 生效值
    600 ≥ 10，网关「同步腿守卫」一律拒同步调用 ⇒ 腿② 若原样抛回，平台「改完第一动作」
    当场不可执行（现场读数 `-1 错误码：须走异步腿`）。腿④ 早就接了这条改腿
    （`_终端运行`：同步腿收到该错误码即改走 `_走异步腿`），腿② 的 docstring 也早已声明
    「对 agent 只体现为『超时才回 任务id』（见 `_走异步腿`）」—— 属**已声明未实现**，不是新设计。

    判据走桩：`_转发能力` 回固定错文、`_走异步腿` 记账 —— 不起真子进程、不碰网关，
    故这两条只钉「有没有改腿」这一件事（真链路由 `自测_stdio客户端` 与 腿④ 的实测读数覆盖）。
    """

    def _调用(self, 转发回执: dict) -> tuple[dict, list]:
        调用过: list = []
        原转发, 原异步 = 壳._转发能力, 壳._走异步腿
        try:
            壳._转发能力 = lambda *a, **k: dict(转发回执)

            def 桩异步(能力id, 转发参数, 上限字符, 账键="", 顶层开工ID=""):
                调用过.append((能力id, dict(转发参数)))
                return {"成功": True, "值": "异步腿拿回来的答案"}

            壳._走异步腿 = 桩异步
            return 壳._调用能力({"能力id": "自修复工具.静态编译"}), 调用过
        finally:
            壳._转发能力, 壳._走异步腿 = 原转发, 原异步

    def test_收到须走异步腿时改走异步腿(self):
        回执, 调用过 = self._调用({"成功": False, "错误码": "须走异步腿",
                                   "错误说明": "超时秒=600 ≥ 10：该能力只允许走异步腿"})
        self.assertEqual(1, len(调用过),
                         "腿② 收到 `须走异步腿` 必须自己改走异步腿（否则编译口不可执行）")
        self.assertEqual("自修复工具.静态编译", 调用过[0][0], "改腿时必须把同一个 能力id 交过去")
        self.assertEqual({"成功": True, "值": "异步腿拿回来的答案"}, 回执,
                         "改腿后要把异步腿的答案原样回带（不解释、不改写）")

    def test_其它失败不改腿(self):
        """反向保护：只有 `须走异步腿` 才改腿 —— 别的失败原样回，不许被吞掉换成异步腿。"""
        回执, 调用过 = self._调用({"成功": False, "错误码": "能力未注册", "错误说明": "没这个能力"})
        self.assertEqual([], 调用过, "非 `须走异步腿` 的失败不许改腿")
        self.assertEqual("能力未注册", 回执.get("错误码"), "原失败必须原样回带")


