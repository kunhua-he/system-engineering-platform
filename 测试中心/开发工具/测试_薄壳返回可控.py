@contextlib.contextmanager
def _捕获子进程标准错误():
    """把 fd 2 临时接到一个临时文件上 —— 只为抓真壳 stderr 里那行「薄壳自换新壳」。

    为什么只能这样抓（2026-09-25 实测）：`构造标准输入输出参数` 不接 `errlog`
    （`支持库/适配层/MCP协议提供者/实现/协议.py:147`），SDK 于是按默认 `sys.stderr` 起子进程
    ⇒ 子进程**继承本进程的 fd 2**。故在 fd 层临时改向即可：`执行换壳` 在 `os.execve` 之前
    写的那行说明就落进文件。`tool_catalog` 随 4 腿面撤下之后，这是「换壳到底换没换、换了几次」
    **唯一还在产线上的观测口**（一次换壳恰好一行，且 `execve` 不可回退 ⇒ 行数＝换壳次数）。

    用法：`with _捕获子进程标准错误() as 流:` … 之后用 `_换壳行(流)` 取正文。
    """
    原 = os.dup(2)
    临时 = tempfile.TemporaryFile()
    try:
        sys.stderr.flush()
        os.dup2(临时.fileno(), 2)
        yield 临时
    finally:
        sys.stderr.flush()
        os.dup2(原, 2)
        os.close(原)


def _换壳行(流) -> list[str]:
    """从捕获到的 stderr 里取「薄壳自换新壳」行（**一行＝一次换壳**）。"""
    流.seek(0)
    return [行 for 行 in 流.read().decode("utf-8", "replace").splitlines()
            if 壳.自换新壳说明 in 行]


def _副本布局(根: Path) -> Path:
    """在 `根` 下摆一份**与生产同形**的薄壳副本，并让它的「项目根」指向真平台根。

    为什么必须同形（2026-09-25 实测，原文见 开发文档/未完成事项.md §三-3）：薄壳按 `__file__`
    推项目根 —— `薄壳服务.py` 取 `薄壳目录.parents[1]`、`工具清单.py` 取 `__file__.parents[2]`，
    两条**只有摆成 `<根>/开发工具/薄壳/` 时才指向同一个根**；平铺复制（`<根>/薄壳/`）会让两处
    各算一个根，且都缺平台锚文件 ⇒ 调用当场被 `_项目根检查` 拒成 `非本平台项目根`。
    锚文件用**符号链接**指向真仓库那两份：副本不是「另一个平台仓库」，它就是本仓库这一版薄壳的
    替身，根指回真根才是如实。
    """
    目录 = 根 / "开发工具" / "薄壳"
    shutil.copytree(薄壳目录, 目录, ignore=shutil.ignore_patterns("__pycache__"))
    对齐目标锁态(目录)   # ★ copytree 会把源的 uchg 带过来 ⇒ 副本不可写（见头部注）
    (根 / "AGENTS.md").symlink_to(系统根 / "AGENTS.md")
    (根 / "开发文档").mkdir()
    (根 / "开发文档" / "项目说明.md").symlink_to(系统根 / "开发文档" / "项目说明.md")
    return 目录


async def _跑多次探针(次数: int, 环境追加: dict) -> list[str]:
    """把薄壳当真 stdio 子进程拉起，连调 N 次 `capability_call{能力id=""}`（薄壳本地校验，不转发网关，故不需要 40007）。

    回的是**文本口径回包原文**（逐条）；判据由调用方经 `_判据` 读 ——
    `本进程已换壳`／`进程号` 那类结构化字段随文本口径已经读不到，「换壳换没换」改看子进程 stderr
    （见 `_捕获子进程标准错误`／`_换壳行`）。
    """
    from 支持库.适配层.MCP协议提供者 import (
        构造客户端会话, 构造标准输入输出参数, 标准输入输出客户端,
    )

    参数 = 构造标准输入输出参数(
        命令=sys.executable,
        参数表=[str(薄壳目录 / "薄壳服务.py")],
        环境={**os.environ, **环境追加},
        工作目录=str(系统根),
    )
    async with 标准输入输出客户端(参数) as (读取流, 写入流):
        async with 构造客户端会话(读取流, 写入流) as 会话:
            await 会话.initialize()
            出: list[dict] = []
            for _ in range(次数):
                结果 = await 会话.call_tool("capability_call", {"能力id": ""})
                正文 = 结果.content[0].text if 结果.content else ""
                出.append(正文)
                # 换壳自 2026-09-23 起是**异步**的（周期巡检，且要等「无在途请求」）⇒ 两次
                # 调用之间留一个空闲窗口，让巡检有机会在**没有在飞回包**时把壳换掉。
                # 不留窗口也不是缺陷（换壳只是被推迟到下一次真空闲），但这条判据要验「换过」。
                await asyncio.sleep(0.3)
    return 出


