def 跑编译口(*参数: str, 超时秒: int = 300, 环境: dict | None = None) -> tuple[int, str]:
    """以子进程真跑编译口入口，返回（退出码, stdout+stderr）。只读，不写仓库任何文件。

    ★ 默认带嵌套标记：**测试里跑的编译口就是嵌套调用**。不带的话，编译口在步骤5 点名本测试
    模块 ⇒ 本测试又跑编译口 ⇒ 无限套娃（实测 2026-09-22 撞过：5~9 个进程同时套娃、
    网关侧 120 秒超时）。只靠编译口自己给子进程设标记不够 —— **单独跑本测试模块**时
    环境里就没有标记，那条路径照样套娃。
    """
    进程环境 = {**os.environ, 编译口.编译口嵌套标记: "1", **(环境 or {})}
    完成 = subprocess.run(
        [sys.executable, "-m", "开发工具.开发编译口.编译口", *参数],
        cwd=str(仓库根), capture_output=True, text=True, timeout=超时秒, env=进程环境,
    )
    return 完成.returncode, (完成.stdout or "") + (完成.stderr or "")


class 变更集无py不得算通过(unittest.TestCase):
    """#68：没有编译对象 ⇒ 未核验（-1 / 退出码 2），不占通过位。"""

    def test_变更py编译_无py返回未核验(self) -> None:
        码, 说明 = 编译口._变更py编译(["README.md"])
        self.assertEqual(码, -1,
                         f"变更集无 .py 必须返回 -1（未核验），实得 {码}；说明={说明}")
        self.assertIn("未核验", 说明, f"说明必须写明未核验：{说明}")

    def test_变更py编译_空列表返回未核验(self) -> None:
        """`--文件` 传空列表这条入口同样不许自己写 `= 0`（#68 的原始写法）。"""
        self.assertEqual(编译口._变更py编译([])[0], -1)

    def test_有py变更不得矫枉过正报未核验(self) -> None:
        """★ 反向保护：有真实 .py 可编译时必须是 0，不许把「跑过了」也报成未核验。"""
        码, 说明 = 编译口._变更py编译(["开发工具/开发编译口/编译口.py"])
        self.assertEqual(码, 0, f"有 .py 可编译应退 0，实得 {码}；说明={说明}")

    def test_子进程_无py场景结论为未核验且不含干净通过(self) -> None:
        码, 出 = 跑编译口("--文件", "README.md")
        self.assertEqual(码, 2, f"未核验应退 2，实得 {码}；输出：\n{出}")
        self.assertIn("五态结论：未核验", 出, 出)
        self.assertNotIn("干净通过", 出, "未核验时不得出现「干净通过」（没跑 ≠ 通过）")
        self.assertIn("语法编译", 出, "未核验项必须点名「语法编译」，读者才知道哪一项没跑")
        self.assertIn("退出码=-1", 出, "打印行须保留 -1 未核验标记，不得被抹成 0")

    def test_子进程_有py场景照样退0且不报未核验(self) -> None:
        码, 出 = 跑编译口("--文件", "开发工具/开发编译口/编译口.py")
        self.assertIn("变更 .py 语法编译 退出码=0", 出, 出)
        self.assertNotIn("五态结论：未核验", 出, "有编译对象时不许报未核验")


class 非包文件必须接线到测试(unittest.TestCase):
    """薄壳不是注册包 ⇒ 按「包短名」点名**永远点不到**它的测试模块。

    实测代价（2026-09-22）：薄壳实现升级为 `起始行/结束行` 后，三条判据停在旧键上躺红，
    而编译口报「定向测试 红 0」—— 因为它一个模块都没点名。扫描面为 0 不得记作通过。
    """

    def test_改了薄壳必须点名薄壳测试(self) -> None:
        影响面 = {"受影响包": [], "反向依赖闭包": [],
                  "非包文件": ["开发工具/薄壳/薄壳服务.py"]}
        self.assertIn("测试中心.开发工具.测试_薄壳返回可控", 编译口.点名模块(影响面),
                      "改了薄壳必须点名它的测试，否则判据躺红无人知")

    def test_反向_不相关非包文件不得误点薄壳测试(self) -> None:
        """★ 反向保护：接线不得宽到「任何非包文件都把薄壳测试拉进来」——
        那样判据会被无关改动冲淡（每次都跑、每次都绿，等于没有判据）。"""
        影响面 = {"受影响包": [], "反向依赖闭包": [],
                  "非包文件": ["开发文档/项目说明.md"]}
        self.assertNotIn("测试中心.开发工具.测试_薄壳返回可控", 编译口.点名模块(影响面))

    def test_嵌套调用跳过定向测试防自递归(self) -> None:
        """实测事故（2026-09-22）：接线后 `跑编译口("--文件", "开发工具/开发编译口/编译口.py")`
        又把同一个测试点起来 —— **5~9 个编译口进程同时套娃**，网关侧 120 秒超时。
        判据：环境里已有嵌套标记时，编译口必须跳过步骤5 并**如实说明**（不是静默跳过）。
        """
        码, 出 = 跑编译口("--文件", "开发工具/开发编译口/编译口.py",
                         环境={编译口.编译口嵌套标记: "1"}, 超时秒=180)
        self.assertEqual(码, 0, f"嵌套调用应正常跑完并退 0，实得 {码}；输出：\n{出[-800:]}")
        self.assertIn("嵌套调用", 出, "嵌套时必须如实说明跳过原因，不得静默跳过")
        self.assertNotIn("1 个节点并行", 出, "嵌套层不得真的去跑定向测试（那正是套娃的入口）")

    def test_未接线非包py如实报出(self) -> None:
        """没接线的非包 .py 要**如实报**（不然又是一层「扫描面为 0 却看着像通过」）。

        三条边界：① 文档类非包文件不报（不需要测试，报了只是噪声）；② 已接线的前缀不报；
        ③ `测试中心/` 下的不报 —— 它们是判据本体，不给自己再配一层测试。
        """
        影响面 = {"受影响包": [], "反向依赖闭包": [],
                  "非包文件": ["开发工具/别的工具.py", "开发文档/项目说明.md",
                            "开发工具/薄壳/薄壳服务.py",
                            "测试中心/开发工具/测试_别的.py"]}
        self.assertEqual(["开发工具/别的工具.py"], 编译口.未接线非包py(影响面),
                         "只报未接线的非包 .py；文档类/已接线/测试本体三类都不得混进来")


