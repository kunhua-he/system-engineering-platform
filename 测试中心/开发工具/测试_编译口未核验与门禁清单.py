def 跑编译口(*参数: str, 超时秒: int = 300, 环境: dict | None = None) -> tuple[int, str]:
    """以子进程真跑编译口入口，返回（退出码, stdout+stderr）。只读，不写仓库任何文件。

    ★ 默认带嵌套标记：**测试里跑的编译口就是嵌套调用**。不带的话，编译口在步骤5 点名本测试
    模块 ⇒ 本测试又跑编译口 ⇒ 无限套娃（实测 2026-09-22 撞过：5~9 个进程同时套娃、
    网关侧 120 秒超时）。只靠编译口自己给子进程设标记不够 —— **单独跑本测试模块**时
    环境里就没有标记，那条路径照样套娃。
    """
    进程环境 = {**os.environ, 编译口.编译口嵌套标记: "1", **(环境 or {})}
    完成 = subprocess.run(
        [sys.executable, "-m", "开发工具.开发编译口.编译口", *参数],
        cwd=str(仓库根), capture_output=True, text=True, timeout=超时秒, env=进程环境,
    )
    return 完成.returncode, (完成.stdout or "") + (完成.stderr or "")


