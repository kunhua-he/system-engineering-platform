class 非包文件必须接线到测试(unittest.TestCase):
    """薄壳不是注册包 ⇒ 按「包短名」点名**永远点不到**它的测试模块。

    实测代价（2026-09-22）：薄壳实现升级为 `起始行/结束行` 后，三条判据停在旧键上躺红，
    而编译口报「定向测试 红 0」—— 因为它一个模块都没点名。扫描面为 0 不得记作通过。
    """

    def test_改了薄壳必须点名薄壳测试(self) -> None:
        影响面 = {"受影响包": [], "反向依赖闭包": [],
                  "非包文件": ["开发工具/薄壳/薄壳服务.py"]}
        self.assertIn("测试中心.开发工具.测试_薄壳返回可控", 编译口.点名模块(影响面),
                      "改了薄壳必须点名它的测试，否则判据躺红无人知")

    def test_反向_不相关非包文件不得误点薄壳测试(self) -> None:
        """★ 反向保护：接线不得宽到「任何非包文件都把薄壳测试拉进来」——
        那样判据会被无关改动冲淡（每次都跑、每次都绿，等于没有判据）。"""
        影响面 = {"受影响包": [], "反向依赖闭包": [],
                  "非包文件": ["开发文档/项目说明.md"]}
        self.assertNotIn("测试中心.开发工具.测试_薄壳返回可控", 编译口.点名模块(影响面))

    def test_嵌套调用跳过定向测试防自递归(self) -> None:
        """实测事故（2026-09-22）：接线后 `跑编译口("--文件", "开发工具/开发编译口/编译口.py")`
        又把同一个测试点起来 —— **5~9 个编译口进程同时套娃**，网关侧 120 秒超时。
        判据：环境里已有嵌套标记时，编译口必须跳过步骤5 并**如实说明**（不是静默跳过）。
        """
        码, 出 = 跑编译口("--文件", "开发工具/开发编译口/编译口.py",
                         环境={编译口.编译口嵌套标记: "1"}, 超时秒=180)
        # ★ 2026-09-24（批R R-31）**判据射程修正**：原断言是 `assertEqual(码, 0)`，
        #   而 `码` 是**整仓门禁**的汇总读数 —— 仓库里只要有**任何一条与本用例无关的**
        #   门禁红项，`码` 就恒为 1，于是「跳没跳过定向测试」这条判据被一票无关红项
        #   永久掩埋（红得没有信息量；实测 2026-09-24：4 条阻断类红项＝契约漂移／
        #   公开调用完整性／包级说明-使用说明／说明书载位同步，全部与本用例主语无关）。
        #   故把射程收到判据自己的主语上，四条都有牙：
        #   ① 必须跑完并给出五态结论（不是崩、不是未核验）；
        #   ② 必须如实说明跳过（不是静默跳过）；
        #   ③ 嵌套层不得真去跑定向测试（那正是套娃入口）；
        #   ④ 若退了 1，输出必须点名阻断类红项 —— 不许拿「反正有红项」当免检。
        self.assertIn(码, (0, 1),
                      f"嵌套调用应正常跑完（0=全绿／1=有红项），实得 {码}；输出：\n{出[-800:]}")
        self.assertIn("五态结论", 出, "嵌套调用必须给出五态结论，不许半途而废")
        self.assertNotIn("五态结论：未核验", 出,
                         "嵌套调用不得降级为未核验（那说明本腿压根没跑起来）")
        if 码 == 1:
            self.assertIn("阻断类红项", 出,
                          "退 1 必须点名阻断类红项（否则就是一条没有理由的红）")
        self.assertIn("嵌套调用", 出, "嵌套时必须如实说明跳过原因，不得静默跳过")
        self.assertNotIn("1 个节点并行", 出, "嵌套层不得真的去跑定向测试（那正是套娃的入口）")

    def test_未接线非包py如实报出(self) -> None:
        """没接线的非包 .py 要**如实报**（不然又是一层「扫描面为 0 却看着像通过」）。

        三条边界：① 文档类非包文件不报（不需要测试，报了只是噪声）；② 已接线的前缀不报；
        ③ `测试中心/` 下的不报 —— 它们是判据本体，不给自己再配一层测试。
        """
        影响面 = {"受影响包": [], "反向依赖闭包": [],
                  "非包文件": ["开发工具/别的工具.py", "开发文档/项目说明.md",
                            "开发工具/薄壳/薄壳服务.py",
                            "测试中心/开发工具/测试_别的.py"]}
        self.assertEqual(["开发工具/别的工具.py"], 编译口.未接线非包py(影响面),
                         "只报未接线的非包 .py；文档类/已接线/测试本体三类都不得混进来")

    def test_接线表每条路径都必须解析到真测试文件(self) -> None:
        """接线表写错一条，代价不是「少跑一个测试」而是**整轮降为未核验**。

        2026-09-23 复核四实测：清单把 `权威状态门禁.py` 的测试写成
        `测试中心.开发工具.测试_权威状态门禁`（实际在 `测试中心/发布门禁/`）⇒
        `-m unittest` 起不来 ⇒ 编译口判该节点「未跑起来」(-1) ⇒ 五态降**未核验**。
        故：接线表必须自带路径自校验，且**判据要机器逐条核**，不是人核 11 行。
        """
        self.assertEqual(编译口.接线表路径错(), [],
                         "接线表里有解析不到真文件的条目（键或模块路径写错）")

    def test_反向_接线表路径写错必须被抓(self) -> None:
        """★ 反向验证：把解析基准指到一个空目录，**每一条模块都必须报错** ——
        证明上面那条判据真的在看路径，而不是恒回空表（恒空表的判据等于没有）。"""
        条目数 = sum(len(v) for v in 编译口.非包文件测试点名.values())
        self.assertGreater(条目数, 0, "接线表不该是空的（空表下本条反向验证无意义）")
        with tempfile.TemporaryDirectory() as 空目录:
            错 = 编译口.接线表路径错(Path(空目录))
        self.assertEqual(len(错), 条目数,
                         f"空目录下 {条目数} 条模块应**全部**报错，实得 {len(错)} 条：{错}")


class 测试文件变更必须点名自身(unittest.TestCase):
    """结构性盲区（2026-09-23）：**测试文件不属任何包** ⇒ 「受影响包短名 ∈ 测试文件名」点不到它。

    实测代价：`测试中心/支持库/测试_原子写失败目标逐字不变.py` 当晚被改，编译口步骤5 打印
    「受影响包未匹配到任何测试模块」= **0 个模块**（看着像通过，实际没有任何测试跑它）。
    本腿只对「被改到的那个测试文件」点名（定向），`--全仓` 口径下 `非包文件` 恒为空表
    ⇒ 不触发 —— 默认档仍是定向档，没有被变成全量。
    """

    def test_只改一个测试文件必须点名它自己(self) -> None:
        影响面 = {"受影响包": [], "反向依赖闭包": [],
                  "非包文件": ["测试中心/支持库/测试_原子写失败目标逐字不变.py"]}
        self.assertEqual(编译口.点名模块(影响面),
                         ["测试中心.支持库.测试_原子写失败目标逐字不变"],
                         "改测试文件必须点名它自己，否则该文件的变更等于无人跑"
                         "（扫描面为 0 不得记作通过）")

    def test_测试文件模块名判据(self) -> None:
        self.assertEqual(编译口.测试文件模块名("测试中心/支持库/测试_原子写失败目标逐字不变.py"),
                         "测试中心.支持库.测试_原子写失败目标逐字不变")
        self.assertEqual(编译口.测试文件模块名("测试中心/开发工具/子目录/测试_x.py"),
                         "测试中心.开发工具.子目录.测试_x", "任意深度都要能推出模块路径")
        # 非测试模块：加载器/夹具拿去 `-m unittest` 只会 import 失败（步骤5 假红）。
        self.assertIsNone(编译口.测试文件模块名("测试中心/加载器/夹具.py"))
        self.assertIsNone(编译口.测试文件模块名("测试中心/加载器/__init__.py"))
        self.assertIsNone(编译口.测试文件模块名("开发工具/别的工具.py"))

    def test_反向_非测试模块不得被本腿拉进来(self) -> None:
        """★ 反向保护：本腿只认 `测试中心/**/测试_*.py`。"""
        影响面 = {"受影响包": [], "反向依赖闭包": [],
                  "非包文件": ["测试中心/加载器/夹具.py", "开发文档/项目说明.md"]}
        self.assertEqual(编译口.点名模块(影响面), [])

    def test_全仓口径不触发本腿(self) -> None:
        """★ `--全仓` 口径 `非包文件` 恒为空表 ⇒ 本腿不触发（默认档不得被变成全量）。"""
        影响面 = {"受影响包": ["（全仓口径）"], "反向依赖闭包": [], "非包文件": []}
        self.assertEqual(编译口.点名模块(影响面), [])


class 门禁清单已接线(unittest.TestCase):
    """#62：三项已建成门禁必须真在清单里，且旧六条一条不少。"""

    清单名字 = {项["名字"] for 项 in 编译口.门禁清单}

    def test_旧六条仍在(self) -> None:
        应有 = {"摘要闭合", "契约漂移", "公开调用完整性", "能力id冻结基线",
                "验证场景体检", "重复腿与旁路"}
        self.assertTrue(应有 <= self.清单名字, f"接线不得替换既有项，缺：{sorted(应有 - self.清单名字)}")

    def test_新增三条在册且角色与参数正确(self) -> None:
        新项 = {项["名字"]: 项 for 项 in 编译口.门禁清单
                if 项["名字"] in {"测试体系门禁", "测试伪装门禁", "防回潮·反向破坏"}}
        self.assertEqual(set(新项), {"测试体系门禁", "测试伪装门禁", "防回潮·反向破坏"},
                         f"三条新纳入项必须都在：实得 {sorted(新项)}")
        # 测试体系门禁只能在「快速级」：真跑级全量实测 527.6 秒，超时即假红。
        self.assertEqual(新项["测试体系门禁"]["参数"], ["--级别", "快速级"])
        self.assertEqual(新项["测试体系门禁"]["角色"], "阻断")
        # 测试伪装门禁只报告（其阻断口径在「计数 ≤ 存量违约上限」，不复制上限）。
        self.assertEqual(新项["测试伪装门禁"]["角色"], "只报告")
        # 反向破坏＝故意弄坏必须变红，属阻断（与发布门禁 29/30 行接线同形制）。
        self.assertEqual(新项["防回潮·反向破坏"]["角色"], "阻断")

    def test_清单参数名与真实入口对齐(self) -> None:
        """参数拼错＝门禁永远跑不起来（会退 2 而非 0），故按真实入口逐条核。"""
        备查 = {项["名字"]: (项["模块"], 项["参数"]) for 项 in 编译口.门禁清单}
        self.assertEqual(备查["测试体系门禁"], ("开发工具.测试体系门禁", ["--级别", "快速级"]))
        self.assertEqual(备查["测试伪装门禁"], ("开发工具.测试伪装门禁", []))
        self.assertEqual(备查["防回潮·反向破坏"], ("开发工具.发布门禁.运行发布门禁", []))

    def test_反向破坏独立调用现场为绿(self) -> None:
        码, 说明, 耗时 = 编译口._跑反向破坏()
        self.assertEqual(码, 0, f"反向破坏应现场为绿（13/13 被真实拒绝），实得 {码}；{说明}")
        self.assertIn("13", 说明)
        self.assertGreater(耗时, 0.0)

    def test_防回潮八项均可独立跑(self) -> None:
        """#62 只读勘定：八项入口都能 import 且可取到可调用对象。"""
        self.assertTrue(编译口._防回潮独立入口勘定(),
                        "防回潮八项入口取不到 —— 勘定结论与现场不符，须更新 docstring")
        self.assertEqual(len(编译口.防回潮判据入口表), 7)
        self.assertEqual(编译口.反向破坏入口[0], "防回潮·反向破坏")


