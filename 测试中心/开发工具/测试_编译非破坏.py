"""唯一编译器「非破坏性生成」回归测试。

背景（真实缺陷，2026-09-14 复核）：`生成能力契约` 原先既不接受既有契约、也不读取磁盘，
导致盲重编译会**降级版本、丢手写内容**。修复前实测影响：17 包契约版本被从
1.1.0/1.2.0/1.3.0 降回硬编码的 1.0.0、32 包丢 `中文名称`、53 包的手写 `调用示例` 被默认拼装覆盖。

本测试锁死四条不变量：
1) **契约版本恒等于契约事实源**（`公共契约/版本规则/契约版本.py`，哲学第 5 条 1 项）——契约只有一套，
   旧的「只升不降」口径已作废（那是把既有契约版本当真相，现在真相只有一处）；
2) 支持库/能力**各自的迭代版本原样保留**（不跟随契约版本被抹平）；
3) 既有条目的键不丢、`中文名称`/`名称` 等编译器不产出的键原样保留；
4) 手写 `调用示例` 不被默认拼装覆盖。

另对全仓真实包做一次逐包只读验算（不写盘），任何一包违约即失败。
"""

