class 生成真失败必须进失败门禁(unittest.TestCase):
    """② 2026-09-23 收紧：生成器真失败（退出码非 0 且非 -1）必须进 `失败说明`。

    修前只打印「按未修好处理」，结论里查无此项 ⇒ 生成失败**不会让编译口判红**，
    那句话是纸面的（假绿通道）。判据与 `生成物联动.执行` 的失败说明同源（单一处）。
    """

    def test_真失败进失败说明(self) -> None:
        (_, 仍红, 未核验说明, 失败说明), 出 = _跑([_行("摘要闭合", 1, "生成失败·现场一致")])
        self.assertEqual(仍红, 0, "「生成失败」不是「复跑仍红」，两者分列")
        self.assertEqual(未核验说明, [], "生成失败不是未核验（有真实退出码）")
        self.assertTrue(any("生成退出码 1" in 项 for 项 in 失败说明),
                        f"生成失败必须进失败说明（否则编译口不判红）：{失败说明}")
        self.assertIn("生成未成功（退出码 1）", "\n".join(出))

    def test_生成失败现场不一致也进失败说明(self) -> None:
        (_, _, _, 失败说明), _ = _跑([_行("摘要闭合", 2, "生成失败·现场不一致")])
        self.assertTrue(any("生成退出码 2" in 项 for 项 in 失败说明), f"{失败说明}")

    def test_反向_跳过与未核验不得被拉进失败门禁(self) -> None:
        """★ 反向保护：收紧不得做成「跳过 / 未核验一起判红」（那会造成假红）。"""
        (_, _, 未核验说明, 失败说明), _ = _跑([
            _行("契约版本自增", None, "无受影响包·跳过"),
            _行("某凭据", None, "未核验"),
        ])
        self.assertEqual(失败说明, [], "跳过/未核验不得进失败说明（否则假红）")
        self.assertEqual(len(未核验说明), 1, "未核验行仍要如实进未核验说明")


class 全仓覆盖为零如实声明(unittest.TestCase):
    """③ 2026-09-23：`--全仓` 下按影响面包凭据**覆盖为零**，必须如实声明。

    为什么**保持现状**（不改成红/未核验）：`--全仓` 是「开发期禁全量」名单里的档
    （`开发文档/规范/项目细则.md`「一律不跑全量……全量编译口 `--全仓`」），
    `生成物登记表.json` 也明写这两条「不跑全仓」；让它真覆盖 = 逐包跑 142 包，
    直接撞那条既有裁决。⇒ 取「保持现状 + 如实声明覆盖为零」。
    """

    def test_全仓下跳过行报覆盖为零(self) -> None:
        (_, _, 未核验说明, 失败说明), 出 = _跑(
            [_行("契约版本自增", None, "无受影响包·跳过"),
             _行("能力定义编译", None, "无受影响包·跳过")], 全仓口径=True)
        文本 = "\n".join(出)
        self.assertEqual(文本.count("覆盖为零（--全仓）"), 2, f"两条都要如实声明：\n{文本}")
        self.assertIn("未核验", 文本)
        # 保持现状：覆盖声明不改五态（不进失败门禁、也不把 `--全仓` 判成未核验）
        self.assertEqual((未核验说明, 失败说明), ([], []), "覆盖声明不改五态")

    def test_反向_非全仓仍报本轮无受影响包(self) -> None:
        """★ 反向保护：非 `--全仓` 口径下跳过仍报「本轮无受影响包」，不得改成覆盖为零。"""
        _, 出 = _跑([_行("契约版本自增", None, "无受影响包·跳过")])
        文本 = "\n".join(出)
        self.assertNotIn("覆盖为零", 文本)
        self.assertIn("本轮无受影响包", 文本)

    def test_只读口径全仓也如实声明(self) -> None:
        (_, _, _, 失败说明), 出 = _跑(
            [_行("契约版本自增", None, "无受影响包·跳过")], 写盘=False, 全仓口径=True)
        self.assertIn("覆盖为零（--全仓）", "\n".join(出))
        self.assertEqual(失败说明, [])


