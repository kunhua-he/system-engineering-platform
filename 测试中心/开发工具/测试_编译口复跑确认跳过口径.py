"""编译口步骤4 复跑确认：「生成退出码 is None（本轮没跑）」不得读成「生成未成功」。

## 修前缺陷（2026-09-23 现场，父会话 `--全仓` 实测）

编译口 `--全仓` 跑完，步骤4「生成物复跑确认」只对两条 `按影响面包` 派生凭据
（契约版本自增 / 能力定义编译）打印「生成未成功（退出码 None）—— 按未修好处理」，
而同批其余凭据（摘要闭合 / 依赖分两段 / 包级说明 / 债务清单 / 元信息头 …）都转绿。

根因**不是生成器坏了**（单独跑、给包目录，两条都是退出码 0），而是**取回口径**：

- `--全仓` 口径下 `受影响包` 是哨兵「（全仓口径）」，经 `包目录表` 过滤后
  `受影响包目录=[]`（`开发工具/开发编译口/编译口.py` 步骤2 的组装）；
- `开发工具/开发编译口/生成物联动.py` 的 ⓪ 扫描面分支据此把这两条记
  「无受影响包·跳过」、`生成退出码` 留在 `None`；
- 修前步骤4 写盘分支直接判 `生成退出码 != 0` —— `None != 0` 为真 ⇒ 误报。

## 钉住的判据（真实函数调用取证，不靠读源码字面）

1. **跳过行不得报失败**：`结论=无受影响包·跳过`、`生成退出码=None` ⇒ 不打印
   「生成未成功」、不计入仍红/失败；
2. **反向保护：真失败仍须照报**：`生成退出码=1` ⇒ 必须打印「生成未成功（退出码 1）」，
   修法不得做成「生成退出码非 0/为 None 一律放过」；
3. **未核验行如实报**：`生成退出码=None` 且 `结论≠跳过` ⇒ 进未核验说明、不占通过位；
4. **转绿行计入转绿**：`生成退出码=0` 且对应门禁退出码=0 ⇒ 转绿 +1；
5. **仍红行计入仍红**：`生成退出码=0` 但对应门禁退出码≠0 ⇒ 仍红 +1、进失败说明。

## 2026-09-23 追加的两条（②③）

6. **② 生成真失败必须进失败门禁**：`生成退出码` 非 0 且非 -1 ⇒ 进 `失败说明`
   （否则「按未修好处理」只是打印，生成失败不会让编译口判红 —— 纸面规则）；
   同时**反向保护**：跳过（`生成退出码=None`）与未核验行**不得**被一起拉进失败门禁。
7. **③ `--全仓` 覆盖为零如实声明**：`全仓口径=真` 且行被跳过 ⇒ 打印
   「覆盖为零（--全仓）」；**保持现状**（不改五态、不进失败门禁/未核验说明）；
   非 `--全仓` 口径下仍报「本轮无受影响包」（不得被改成覆盖为零）。

跑法：python3.14 -m unittest 测试中心.开发工具.测试_编译口复跑确认跳过口径
"""

from __future__ import annotations

import sys
import unittest
