"""派活前核验 `--多条` 的回归：**它曾经是个假绿**（2026-09-23 实测）。

## 修前缺陷（现场证据）

`python3.14 -m 开发工具.派活前核验 --多条 开发文档/未完成事项.md` 在修前打印：

    逐条核验 未完成事项.md：共 4 条带状态的条目
    ...
    可疑 0 条 / 共 4 条
    exit=0

而清单里 §四 有 **103 项**。根因是抽取判据写成了「表首列首字符是数字」，而 §四 的
103 项首列**全是 `—`**（该表没有编号列）⇒ 整表被 `continue` 跳过。于是
**「103 项一个字没读」被报成「检查过且没问题」并 exit 0** —— 正是 AGENTS.md 禁止的
假绿（哲学第 3 条 2 项：失败必须明确）。附带：旧 docstring 声称抽 ✅/⏳/🔧/📋 状态标注，
而这四个字符在整份清单里出现 **0 次**（该清单 §四 的列是「缺陷/现场证据/期望修法」，
**根本没有状态列**）。

## 本测试钉住的判据（真仓库 + 真 git，夹具清单写进临时目录，不碰仓库任何文件）

1. **`—` 首列的行必须被读到**（防那条假绿回潮）：夹具里 3 行 `—` + 1 行数字 + 1 行数字
   ⇒ 必须报「共 5 条」，而不是旧版的「共 1 条」；
2. **无状态列的表不得产判定**：这类行只能落「线索」档，输出里**不许出现 `与现场一致`**
   —— 没有状态可比，任何 ✓ 都是编的（旧版在这类条目上产的 ✓ 是假绿）；
3. **有状态列的表照旧判**：`⏳` + 文件有提交 ⇒ 计入「真可疑」且**退出码 1**
   （这条腿不能被重写弄丢）；
4. **扫描面为 0 不得记作通过**：表格形态变了（一条都抽不出）⇒ 返回 **2**，不是 0。

跑法：python3.14 -m unittest 测试中心.开发工具.测试_派活前核验
"""

from __future__ import annotations

import io
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

仓库根 = Path(__file__).resolve().parents[2]
if str(仓库根) not in sys.path:
    sys.path.insert(0, str(仓库根))

from 开发工具 import 派活前核验

#: 夹具清单。刻意混三类表：无状态列（§一/§四）、有状态列（§七）、以及 `—` 首列。
夹具清单 = """# 夹具 · 债务清单

## 一、待修（修法已明确）

| # | 事项 | 规模 | 落点 |
|---|---|---|---|
| 1 | 夹具条目 | 小 | `开发工具/派活前核验.py` |

## 四、新增债务

| # | 缺陷 | 现场证据 | 期望修法 |
|---|---|---|---|
| — | 无状态列的行 A | 见 `开发工具/派活前核验.py` | 修 |
| — | 无状态列的行 B | 见 `开发工具/派活前核验.py` | 修 |
| — | 无状态列的行 C | 正文里没有任何反引号路径 | 修 |

## 七、带状态列的表

| # | 事项 | 状态 | 现场证据 |
|---|---|---|---|
| 9 | 在办条目 | ⏳ 维修中 | `开发工具/派活前核验.py` |
"""


def 跑核验(文本: str) -> tuple[int, str]:
    """把夹具清单写进临时目录再跑真函数，返回（退出码, 输出）。"""
    with tempfile.TemporaryDirectory() as 目录:
        路径 = Path(目录) / "未完成事项.md"
        路径.write_text(文本, encoding="utf-8")
        缓冲 = io.StringIO()
        with redirect_stdout(缓冲):
            码 = 派活前核验.核验债务清单(路径)
    return 码, 缓冲.getvalue()


class 破折号首列的行不得被跳过(unittest.TestCase):
    """★ 这是本文件存在的理由：旧版把 `—` 首列整表跳过，103 项一个字没读还报绿。"""

    def test_破折号首列的行照样被读到(self) -> None:
        _, 出 = 跑核验(夹具清单)
        self.assertIn("共 5 条", 出,
                      "3 行 `—` + 2 行数字 = 5 条；旧版只认数字首列，会报「共 2 条」"
                      "（真清单上就退化成「103 项一个字没读」）")

    def test_无状态列的表不得产判定(self) -> None:
        _, 出 = 跑核验(夹具清单)
        self.assertNotIn("与现场一致", 出,
                         "§一/§四 两张表都没有状态列 ⇒ 只能报事实，"
                         "不许出现「✓ 与现场一致」（那是编出来的判定）")
        self.assertIn("线索 3", 出, "无状态列且有文件路径的行必须落在「线索」档")
        self.assertIn("抽不出 1", 出, "正文里没有可解析路径的行必须如实报「抽不出」")


class 有状态列的表照旧判(unittest.TestCase):
    """重写不得把原有的「真可疑 + 退出码 1」那条腿弄丢。"""

    def test_在办标且文件有提交必须判可疑并退1(self) -> None:
        码, 出 = 跑核验(夹具清单)
        self.assertIn("真可疑 1", 出, "§七 的 `⏳` 条目 + 真实有提交的文件 ⇒ 应计入真可疑")
        self.assertEqual(码, 1, "有真可疑时必须退 1（不能报绿）")


class 扫描面为0不得记作通过(unittest.TestCase):
    def test_表格形态变了必须退2(self) -> None:
        码, 出 = 跑核验("# 夹具\n\n没有表格的正文。\n")
        self.assertEqual(码, 2, "一条都抽不出 ⇒ 退 2（未核验），不得退 0 装作检查过")
        self.assertIn("未从", 出)


if __name__ == "__main__":
    unittest.main()
