#!/usr/bin/env python3.14
"""仓库锁：一条命令给整个项目上 / 下 / 查内核级只读封禁（macOS `chflags uchg`）。

用法：
    python3.14 运维脚本/仓库锁.py             # 上锁全仓（默认动作）
    python3.14 运维脚本/仓库锁.py --查看        # 只看状态，不改任何东西（未锁分「活跃租约开窗」与「真缺口」两档）
    python3.14 运维脚本/仓库锁.py --下锁        # 解开全仓（**只认网关凭证**：终端直跑一律被拒；改用 MCP 能力 自修复工具.仓库锁 动作=下锁）
    python3.14 运维脚本/仓库锁.py --补齐        # 只补**真缺口**（写腿中途被杀留下的）；**活跃租约开窗不锁** —— 那是别人正在用的写窗口

为什么要有这个脚本（而不是让人背一串 python -c）：
上锁/下锁是**开发循环里每天要做的动作**，而它的正确性靠的是三个一起记住的约束
（锁文件 + 锁目录 + 豁免 `工程缓存/` 等）。让人手敲就会漏，漏了不报错只是锁有洞
（`查询()` 早先还报全绿）。故收成**唯一入口**：动作在一处、判据在一处（哲学 1.2）。

判据本体在 `公共契约/运行时/仓库只读锁.py`，本脚本**只做命令行翻译**，
不在本文件另写一套扫描面或上锁逻辑（另写一套就是同一件事的第二条腿）。

★ 只作用于本仓库（`项目根` 由本文件位置推出，不接受命令行传别的根）：
  华哥 2026-09-23 裁决「**仅限这个项目**」。

★ 本脚本自己也会被锁上（它在扫描面里）—— 这**不影响**运行：
  内核锁挡的是「写」，读与执行照常。被锁状态下本脚本仍可正常跑 `--查看` / `--下锁`。

★ 四类动作的门槛不同（**有意为之**，判据只在 `公共契约/运行时/仓库只读锁.py` 一处）：
  · `--下锁` 是**放宽**动作 ⇒ **只认网关凭证**（终端直跑被拒；也**不认**
    `系统平台_修MCP自身=1` 白名单 —— 华哥 2026-09-23 裁决「只有 mcp 才能解锁，禁止用
    其他方式解锁」）；
  · `--查看` / `--补齐` / 默认上锁 是**只读或收紧**动作 ⇒ 终端腿照常可用（上锁是安全方向）。
"""
from __future__ import annotations

import sys
from pathlib import Path

# 环境准入（必须在任何装配与第三方导入之前）：平台判定的唯一来源是
# `公共契约/运行时/平台适配`，本文件不自己写 sys.platform 判断。
if str(Path(__file__).resolve().parents[1]) not in sys.path:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from 公共契约.运行时.平台适配 import 脚本入口准入

脚本入口准入("仓库锁（整仓内核级只读封禁）")

from 公共契约.运行时 import 仓库只读锁 as 锁

#: 本仓库根：由本文件位置推出（`运维脚本/仓库锁.py` ⇒ 上两级）。
项目根 = Path(__file__).resolve().parents[1]


def _打印支持边界() -> None:
    """把「本锁挡什么、不挡什么」印出来 —— 边界不说清，使用者会以为它是「绝对锁死」。"""
    print("  边界①：属主自己可以解开（`chflags nouchg` 无门槛）⇒ 挡的是「不经平台就落盘」")
    print("         这个**动作**，不是「有权限的人」。可达上限 = 想改必须显式先下锁。")
    print("  边界②：文件锁与目录锁各挡一半，必须都锁（本脚本走的 `上锁全仓()` 两者都锁）。")
    print("  边界③：`工程缓存/`、`.git/`、`.venv/`、`node_modules/` 明确豁免 —— 它们不是事实源，")
    print("         锁了会让网关与 git 双双失效。")
    print("  边界④：只作用于本仓库，不碰机器上别的项目。")


def _查看() -> int:
    结果 = 锁.查询(项目根)
    if not 结果["支持"]:
        print(f"本平台不支持内核级只读锁（仅 macOS）：{结果['说明']}")
        return 0
    print(f"支持内核锁：真｜受管条目 {结果['文件数']} 文件 + {结果['目录数']} 目录")
    print(f"已锁 {结果['已锁数']}｜**未锁 {结果['未锁数']}**"
          f"（其中 活跃租约开窗 {结果['开窗数']}｜**真缺口 {结果['缺口数']}**）")
    print(f"  {结果['说明']}")
    if not 结果["开窗清单可用"]:
        print(f"  ★ 开窗清单取不到（{结果['开窗清单问题']}）⇒ 未锁一律按真缺口计（fail-closed）。")
    if 结果["缺口样本"]:
        print("真缺口样本（跑 `--补齐` 可修）：")
        for 一项 in 结果["缺口样本"]:
            print(f"    {一项}")
    if 结果["开窗样本"]:
        print(f"活跃租约开窗 {结果['开窗数']} 条（**设计行为**：认领路径的写窗口，"
              "不判红、也不补齐）：")
        for 一项 in 结果["开窗样本"]:
            print(f"    {一项}")
    _打印支持边界()
    return 0 if 结果["缺口数"] == 0 else 1


def _上锁() -> int:
    结果 = 锁.上锁全仓(项目根)
    if not 结果["支持"]:
        print(f"本平台不支持内核级只读锁（仅 macOS）：{结果['失败表']}")
        return 1
    print(f"已上锁 {结果['已锁数']} 项（新锁 {结果['新锁数']}）"
          f"｜受管 {结果['文件数']} 文件 + {结果['目录数']} 目录")
    if 结果["锁掉开窗数"]:
        # 上锁是「显式把整仓锁死」，本行只把它从「无声」变成「有声」：那些条目可能是
        # **别的会话正在用的写窗口**，锁掉它对方下一次落盘会撞 PermissionError。
        print(f"★ 本次锁掉了 {结果['锁掉开窗数']} 条**活跃租约开窗**（另一会话正在用的写窗口）")
        print("  要只补真缺口、不动别人的窗口，请用 `--补齐`（它不锁开窗）；"
              "要按锁前状态回退，请让对应会话重跑认领或等它释放后回锁。")
    if 结果["失败表"]:
        print(f"★ 有 {len(结果['失败表'])} 项锁不上（前 5 条）：")
        for 相对, 原因 in 结果["失败表"][:5]:
            print(f"    {相对}：{原因}")
        print("  锁不上即锁有洞，必须查清后才算完成。")
    print("现在起：终端与编辑器对源码的写入一律被内核拒；")
    print("要改代码先 `python3.14 运维脚本/仓库锁.py --下锁`，改完再跑本脚本上锁。")
    _打印支持边界()
    return 1 if 结果["失败表"] else 0


def _下锁() -> int:
    # 解锁是**放宽**动作：先过 MCP 身份对账，不过就打印说明 + 退出码 1（不抛裸 traceback）。
    # ★ 必须用 `对账MCP身份()`（只看网关凭证），**不用** `脚本入口准入MCP()` —— 后者含
    # `系统平台_修MCP自身=1` 白名单，而华哥裁决是「只有 mcp 才能解锁」，白名单在这条腿上
    # 必须无效（这正是本脚本要守的反向样本）。
    from 公共契约.运行时.平台适配.身份对账 import 对账MCP身份

    通过, 说明 = 对账MCP身份()
    if not 通过:
        print(说明)
        print("★ 解锁是「放宽」动作，**只认网关凭证**："
              "`系统平台_修MCP自身=1` 白名单在这条腿上**无效**（有意为之）。")
        print("  要在 MCP 侧解锁，请调用能力：")
        print('  capability_call(能力id="自修复工具.仓库锁", 参数={"动作": "下锁"})')
        return 1
    结果 = 锁.解锁全仓(项目根)
    if not 结果["支持"]:
        print("本平台不支持内核级只读锁（仅 macOS），无需下锁。")
        return 0
    print(f"已解锁 {结果['解锁数']} 项（受管 {结果['文件数']} 文件）")
    if 结果["失败表"]:
        print(f"★ 有 {len(结果['失败表'])} 项解不开（前 5 条）：{结果['失败表'][:5]}")
        return 1
    print("★ 现在是**开窗期**：改完代码请立刻跑本脚本（不带参数）重新上锁，")
    print("  否则「终端也可以随意落盘」，封禁就等于没上。")
    return 0


def _补齐() -> int:
    结果 = 锁.重锁一遍(项目根)
    if 结果.get("拒绝"):
        # fail-closed：证不出哪些未锁是「活跃租约开窗」，就不许拿全仓上锁去赌 ——
        # 赌错的代价是吊销别人正在用的写窗口（M-1 现场实测过）。
        print(f"★ 未补齐：{结果['说明']}")
        print("  修法：确认本仓能 import `平台控制面/能力目录`（开窗清单由它载入时注册）后重跑。")
        return 1
    print(f"补齐完成：新锁 {结果['新锁数']} 项（已是锁态 {结果['已锁数']} 项）")
    if 结果["跳过开窗数"]:
        print(f"跳过活跃租约开窗 {结果['跳过开窗数']} 条（**设计行为，不锁** ——"
              "锁上等于吊销别人正在用的写窗口）")
    if 结果["失败表"]:
        print(f"★ 仍有 {len(结果['失败表'])} 项锁不上：{结果['失败表'][:5]}")
        return 1
    剩下 = 锁.查询(项目根)
    print(f"复核：未锁 {剩下['未锁数']}（开窗 {剩下['开窗数']}｜**真缺口 {剩下['缺口数']}**）"
          f"｜{剩下['说明']}")
    return 0 if 剩下["缺口数"] == 0 else 1


def main(argv: list[str]) -> int:
    参数 = [a for a in argv[1:]]
    if "--help" in 参数 or "-h" in 参数:
        print(__doc__)
        return 0
    命中的开关 = [a for a in 参数 if a in ("--查看", "--下锁", "--补齐")]
    if len(命中的开关) > 1:
        print(f"★ 开关互斥，只能给一个：{命中的开关}")
        return 2
    if 命中的开关 == ["--查看"]:
        return _查看()
    if 命中的开关 == ["--下锁"]:
        return _下锁()
    if 命中的开关 == ["--补齐"]:
        return _补齐()
    if 参数:
        print(f"★ 不认识的参数：{参数}\n跑 `--help` 看用法。")
        return 2
    return _上锁()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
