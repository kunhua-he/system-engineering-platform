"""支持库绑定：校验并绑定支持库到项目。

六项校验：包存在、版本满足、能力存在、多提供者、依赖循环、宿主冲突。
绑定只读包声明，不加载支持库实现。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from 公共契约.包声明 import 包声明
from 公共契约.版本规则.比较 import 满足约束
from 运行核心.加载器.包发现.发现器 import 发现全部
from 运行核心.加载器.依赖解析.解析器 import 解析依赖
from 运行核心.加载器.提供者选择.选择器 import 选择提供者, 选择全部提供者


@dataclass
class 绑定结果:
    """一次支持库绑定的结果。"""

    支持库id: str
    成功: bool = False
    绑定版本: str = ""
    问题列表: list[str] = field(default_factory=list)


def 校验绑定(支持库id: str, 版本约束: str, 支持库根目录: Path) -> 绑定结果:
    """校验支持库能否绑定到项目（不修改任何状态）。"""
    结果 = 绑定结果(支持库id=支持库id)
    # 三根同口径（与写入侧 依赖锁定 / 校验侧 锁定校验 一致）：技能库包的类型也是
    # 「支持库」，原实现拿 Path("不存在的模块目录") 占位只是靠发现器的声明式根兜底，
    # 一旦发现器改为显式根集合就会静默漏扫——这里如实传真实兄弟根。
    系统根目录 = Path(支持库根目录).resolve().parent
    发现 = 发现全部(系统根目录 / "支持库", 系统根目录 / "模块库",
                  系统根目录 / "技能库")
    声明列表 = [声明 for 声明 in 发现.声明列表 if 声明.类型 == "支持库"]

    # 1. 包是否存在
    匹配列表 = [声明 for 声明 in 声明列表 if 声明.包id == 支持库id]
    if not 匹配列表:
        结果.问题列表.append(f"支持库不存在: {支持库id}")
        return 结果
    声明 = 匹配列表[0]

    # 2. 版本是否满足
    if 版本约束 and not 满足约束(声明.版本, 版本约束):
        结果.问题列表.append(f"版本不满足: {支持库id}@{声明.版本} 不满足 {版本约束}")
        return 结果

    # 3. 能力是否存在（支持库必须至少提供一项能力）
    if not 声明.能力:
        结果.问题列表.append(f"支持库未声明任何能力: {支持库id}")
        return 结果

    # 4. 多提供者冲突（支持库id 唯一，能力不应被多个包重复提供）
    for 能力 in 声明.能力:
        选择 = 选择提供者(能力.能力id, 声明列表)
        if 选择.冲突列表:
            结果.问题列表.append(f"能力 {能力.能力id} 多提供者冲突: {' / '.join(选择.冲突列表)}")
            return 结果

    # 5. 依赖循环（支持库之间不得循环依赖）
    # 原实现把依赖边建成 能力id.split(".")[0]（顶层目录名，如 "支持库"），该值
    # 永不等于任何包id → 依赖图只有孤立节点 → 检测循环 永不返回真：真环也报「通过」，
    # 属恒空跑的假检查。现改为：边指向能力 owner 包（经 选择全部提供者 解析；
    # 依赖条目显式给了 包id 时以显式 owner 为准），判环复用本仓唯一依赖解析器
    # （与 依赖锁定/传递闭包.py、锁定校验.py 同源），不再另立一套图算法。
    声明表 = {条目.包id: 条目 for 条目 in 声明列表}
    能力提供者 = {
        能力id: (选择.提供包id, 选择.提供版本)
        for 能力id, 选择 in 选择全部提供者(声明列表).items() if 选择.成功
    }
    for 条目 in 声明列表:
        for 依赖 in 条目.依赖:
            显式包id = str(依赖.get("包id", "")).strip()
            能力id = str(依赖.get("能力", "")).strip()
            if 显式包id and 能力id and 显式包id in 声明表:
                能力提供者[能力id] = (显式包id, 声明表[显式包id].版本)
    解析 = 解析依赖(声明列表, 能力提供者)
    if 解析.循环:
        结果.问题列表.append(f"支持库存在依赖循环: {'、'.join(解析.循环)}")
        return 结果

    # 6. 宿主冲突（同名能力不得跨越正式支持库宿主重复声明；废弃包与
    # 适配层 Provider 不参与）。Provider 只是公开 owner 的内部实现，
    # 不能因实现声明同一能力而被算作第二个宿主。
    能力id出现: dict[str, int] = {}
    for 条目 in 声明列表:
        if (getattr(条目, "已废弃", False)
                or 条目.包id.startswith("支持库.适配层.")):
            continue
        for 能力 in 条目.能力:
            能力id出现[能力.能力id] = 能力id出现.get(能力.能力id, 0) + 1
    for 能力id, 次数 in 能力id出现.items():
        if 次数 > 1:
            结果.问题列表.append(f"能力 {能力id} 被 {次数} 个宿主声明（宿主冲突）")
            return 结果

    结果.成功 = True
    结果.绑定版本 = 声明.版本
    return 结果
