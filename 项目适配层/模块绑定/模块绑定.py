"""模块绑定：校验并绑定模块到项目。

模块只能经公开支持库能力运行；绑定校验：模块存在、版本满足、无模块间依赖
循环（先判，避免真环被误报成能力缺失）、模块依赖的支持库能力全部存在且版本满足。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from 公共契约.版本规则.比较 import 满足约束
from 运行核心.加载器.包发现.发现器 import 发现全部
from 运行核心.加载器.依赖解析.解析器 import 解析依赖
from 运行核心.加载器.提供者选择.选择器 import 选择全部提供者


@dataclass
class 绑定结果:
    """一次模块绑定的结果。"""

    模块id: str
    成功: bool = False
    绑定版本: str = ""
    问题列表: list[str] = field(default_factory=list)


def 校验绑定(模块id: str, 版本约束: str, 系统根目录: Path) -> 绑定结果:
    """校验模块能否绑定到项目（不修改任何状态）。"""
    结果 = 绑定结果(模块id=模块id)
    发现 = 发现全部(系统根目录 / "支持库", 系统根目录 / "模块库")
    支持库声明 = [声明 for 声明 in 发现.声明列表 if 声明.类型 == "支持库"]
    模块声明列表 = [声明 for 声明 in 发现.声明列表 if 声明.类型 in ("模块", "基础模块", "功能模块")]

    # 1. 模块是否存在
    匹配列表 = [声明 for 声明 in 模块声明列表 if 声明.包id == 模块id]
    if not 匹配列表:
        结果.问题列表.append(f"模块不存在: {模块id}")
        return 结果
    声明 = 匹配列表[0]

    # 2. 版本是否满足
    if 版本约束 and not 满足约束(声明.版本, 版本约束):
        结果.问题列表.append(f"版本不满足: {模块id}@{声明.版本} 不满足 {版本约束}")
        return 结果

    # 3. 模块间依赖循环
    # 原实现把依赖边建成 能力id.split(".")[0]（顶层目录名，如 "模块库"），该值永不
    # 等于任何包id → 依赖图只有孤立节点 → 检测循环 永不返回真，属恒空跑的假检查；
    # 真环反而会在「依赖的支持库能力不存在」那一步被误报成能力缺失（错误归因）。
    # 现改为边指向 owner 包（依赖条目显式 包id 优先，否则经 选择全部提供者 解析），
    # 判环复用本仓唯一依赖解析器（与 依赖锁定/传递闭包.py、锁定校验.py 同源），
    # 并提前到能力存在性之前判，保证真环报的是真原因。
    全部声明 = 支持库声明 + 模块声明列表
    全部声明表 = {条目.包id: 条目 for 条目 in 全部声明}
    能力提供者 = {
        能力id: (选择.提供包id, 选择.提供版本)
        for 能力id, 选择 in 选择全部提供者(全部声明).items() if 选择.成功
    }
    for 条目 in 全部声明:
        for 依赖 in 条目.依赖:
            显式包id = str(依赖.get("包id", "")).strip()
            能力id = str(依赖.get("能力", "")).strip()
            if 显式包id and 能力id and 显式包id in 全部声明表:
                能力提供者[能力id] = (显式包id, 全部声明表[显式包id].版本)
    解析 = 解析依赖(模块声明列表, 能力提供者)
    if 解析.循环:
        结果.问题列表.append(f"模块存在依赖循环: {'、'.join(解析.循环)}")
        return 结果

    # 4. 模块依赖的支持库能力必须存在且版本满足
    支持库能力表 = {
        能力.能力id: (条目.包id, 条目.版本)
        for 条目 in 支持库声明 for 能力 in 条目.能力
    }
    for 依赖 in 声明.依赖:
        能力id = 依赖.get("能力", "")
        版本约束值 = 依赖.get("版本", "")
        if 能力id not in 支持库能力表:
            结果.问题列表.append(f"模块依赖的支持库能力不存在: {模块id} 依赖 {能力id}")
            return 结果
        if 版本约束值:
            提供版本 = 支持库能力表[能力id][1]
            if not 满足约束(提供版本, 版本约束值):
                结果.问题列表.append(f"模块依赖版本不满足: {能力id}@{提供版本} 不满足 {版本约束值}")
                return 结果

    结果.成功 = True
    结果.绑定版本 = 声明.版本
    return 结果
